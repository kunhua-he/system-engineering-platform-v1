# -*- coding: utf-8 -*-
"""翻译器主流程 —— 把读源 · 译名 · 号段 · 生成 · 落盘串成一条命令，并出任务书形状的单件。"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from 翻译器常量 import 老项目默认根, 产出默认根, 号段分配表件, 命名修复映射件, 模块号段起, 模块号段止
from 翻译器实现 import (读件, 读模块, 找模块目录, 列模块名表, 取模块相对路径,
                     分配号段, 生成声明根, 落盘)


def 翻译模块(模块目录: Path, 老项目根: Path, 修复表: dict, 号段表: dict) -> dict:
    """单模块翻译：老项目模块目录 → V1 声明根（不落盘，便于测试与批量脚本复用）。"""
    模块数据 = 读模块(模块目录)
    老项目路径 = 取模块相对路径(模块目录, 老项目根)
    号段 = 分配号段(模块数据["模块名"], 号段表, 列模块名表(老项目根), 老项目路径)
    return 生成声明根(模块数据, 号段, 修复表)


def 读依赖表(依赖目录: Path) -> tuple:
    """读小队 2 / 小队 4 的产物 ⇒ `(号段表, 修复表)`；缺件一律给空表（走内置默认）。"""
    return 读件(依赖目录 / 号段分配表件), 读件(依赖目录 / 命名修复映射件)


def 契约单件(声明根: dict) -> dict:
    """任务书 01/05 的单件形状：{模块名, 号段, 能力列表[{能力编号,能力名,参数表,返回类型号}]}。"""
    包声明 = 声明根["包声明"]
    能力清单 = []
    for 能力声明 in 声明根["能力声明表"]:
        能力清单.append({
            "能力编号": 能力声明["编号"],
            "能力名": 能力声明["名称"],
            "参数表": [{"参数名": 参数行["名称"], "类型号": 参数行["类型标签"], "行序": 序号}
                     for 序号, 参数行 in enumerate(能力声明["参数表"])],
            "返回类型号": 能力声明["返回类型"],
        })
    号段项 = 包声明["能力号段"][0]
    return {"模块名": 包声明["名称"], "号段": "%d~%d" % (号段项["起"], 号段项["止"]),
            "能力列表": 能力清单}


def 解析命令行(命令行参数: list):
    """解析命令行参数（翻译一个模块 · 指定输出 · 可选另出单件）。"""
    解析器 = argparse.ArgumentParser(
        description="老项目模块翻译器 —— 老项目模块声明 → V1 扩展声明根")
    解析器.add_argument("--模块", help="老项目模块名（如：知识检索）")
    解析器.add_argument("--源目录", help="老项目模块目录（给了它就跳过按名查找）")
    解析器.add_argument("--老项目根", default=老项目默认根, help="老项目根目录")
    解析器.add_argument("--输出", help="输出目录（默认 构建装配/翻译器/产物/<模块名>）")
    解析器.add_argument("--依赖目录", help="号段分配表.json / 命名修复映射.json 所在目录")
    解析器.add_argument("--契约单件", action="store_true",
                      help="另出一份任务书形状的合并 JSON（外部_<模块名>.json）")
    return 解析器.parse_args(命令行参数)


def 跑翻译(命令行参数: list) -> int:
    """命令行主流程：解析 → 翻译 → 落盘 → 报读数。"""
    选项 = 解析命令行(命令行参数)
    仓根 = Path(__file__).resolve().parents[2]
    依赖目录 = Path(选项.依赖目录) if 选项.依赖目录 else 仓根 / "构建装配" / "翻译器"
    号段表, 修复表 = 读依赖表(依赖目录)
    if not 号段表:
        print("提示：未读到 号段分配表.json ⇒ 号段按模块段（%d–%d）按模块名序均分兜底"
              % (模块号段起, 模块号段止))
    if not 修复表:
        print("提示：未读到 命名修复映射.json ⇒ 命名修复按原样透传")

    老项目根 = Path(选项.老项目根)
    模块目录 = Path(选项.源目录) if 选项.源目录 else 找模块目录(选项.模块 or "", 老项目根)
    if not 模块目录.is_dir():
        print("拒：找不到模块目录 %s（用 --源目录 直接点名）" % 模块目录, file=sys.stderr)
        return 2

    声明根 = 翻译模块(模块目录, 老项目根, 修复表, 号段表)
    模块名 = 声明根["包声明"]["名称"]
    输出目录 = Path(选项.输出) if 选项.输出 else 仓根 / 产出默认根 / 模块名
    指纹表 = 落盘(声明根, 输出目录)

    号段项 = 声明根["包声明"]["能力号段"][0]
    print("✓ 翻译完成：%s" % 模块名)
    print("  能力 %d 个 · 号段 %d–%d · 落盘 %d 件"
          % (len(声明根["能力声明表"]), 号段项["起"], 号段项["止"], len(指纹表)))
    print("  输出：%s" % 输出目录)
    if 选项.契约单件:
        单件路径 = 输出目录 / ("外部_%s.json" % 模块名)
        单件路径.write_text(
            json.dumps(契约单件(声明根), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print("  单件：%s" % 单件路径)
    return 0
