# -*- coding: utf-8 -*-
"""翻译器实现 —— 读源 · 命名修复 · 号段分配 · V1 声明根生成 · 落盘。

一段一条：读老项目模块目录（包声明.json + 能力定义.json）→ 译名 → 分配号段 →
生成声明（包声明 / 能力声明 / 错误码表 / 类型声明）→ 落盘（含指纹与用法说明）。
一切按「同一份老项目树 ⇒ 同一套产物」的口径 ⇒ 重译不漂。
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from 翻译器常量 import (
    声明格式号, 目标字宽, 模块号段起, 模块号段止, 模块错误段位, 导出目标默认,
    号段类宽度, 基础类型表, 复合类型表, 兜底类型标签, 错误码序号表, 错误码兜底序号起,
)

模块库目录表 = ("模块库", "支持库", "平台控制面", "技能库", "启动监督器", "运行核心")


# ── 读源 ───────────────────────────────────────────────────────────────
def 读件(件路径: Path) -> dict:
    """读一个 JSON 件；读不动 / 顶层不是字典 ⇒ 空字典（缺字段由调用方走默认）。"""
    try:
        结构 = json.loads(件路径.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return 结构 if isinstance(结构, dict) else {}


def 找模块目录(模块名: str, 老项目根: Path) -> Path:
    """在老项目根下按模块名找模块目录；找不到就按「根 / 模块名」给一个（读源时自然报缺）。"""
    for 父目录名 in 模块库目录表:
        for 候选名 in sorted((老项目根 / 父目录名).glob("**/" + 模块名)):
            if 候选名.is_dir():
                return 候选名
    return 老项目根 / 模块名


def 列模块名表(老项目根: Path) -> list:
    """列老项目里的模块名（模块库目录表下扫两层），排序稳定 ⇒ 号段兜底分配可复现。"""
    名表 = set()
    for 父目录名 in 模块库目录表:
        父目录 = 老项目根 / 父目录名
        if not 父目录.is_dir():
            continue
        for 子目录 in sorted(父目录.iterdir()):
            if not 子目录.is_dir() or 子目录.name.startswith("__"):
                continue
            名表.add(子目录.name)
            for 孙目录 in sorted(子目录.iterdir()):
                if 孙目录.is_dir() and not 孙目录.name.startswith("__"):
                    名表.add(孙目录.name)
    return sorted(名表)


def 读模块(模块目录: Path) -> dict:
    """⇒ {模块名, 模块说明, 版本, 能力项表}。能力定义.json 更全，优先读它。"""
    能力定义 = 读件(模块目录 / "能力定义.json")
    包声明 = 读件(模块目录 / "包声明.json")
    来源 = 能力定义 or 包声明
    模块名 = str(来源.get("名称") or 包声明.get("名称") or 模块目录.name)
    能力项表 = 能力定义.get("能力列表") or 包声明.get("能力") or []
    return {
        "模块名": 模块名,
        "模块说明": 净化说明文本(str(来源.get("说明") or "")),
        "版本": str(来源.get("版本") or "1.0.0"),
        "能力项表": 能力项表 if isinstance(能力项表, list) else [],
    }


def 取能力名(能力项: dict) -> str:
    return str(能力项.get("中文名称") or 能力项.get("名称") or "未命名能力")


def 净化说明文本(文本: str) -> str:
    """老项目「说明」自由文本里常把逻辑类型写成外来译名（判据 ㊹ 的禁译名码位，
    见 开发工具/代码地图/查名.py::禁译名码位）；V1 已把该类型名裁为 `逻辑型`
    （口径同 `判据_禁译名.py`、`翻译规范.md` §「实测发现」一节）。

    只处理**这一个确定场景**——文本里出现该词就整词换成 `逻辑型`，不碰其余汉字
    （该词按码位拼，不写字面，否则本件自身也会撞上判据 ㊹）。翻译器只搬运说明散文、
    不改写老项目的自由表达，但这个词是外来译名本身（不是作者的措辞选择），全树已有
    唯一裁定的新名 ⇒ 按它在「类型提示」里的实际角色换字，不是机械改写别的内容。
    """
    禁译名词 = "".join(chr(码位) for 码位 in (0x5E03, 0x5C14))
    return 文本.replace(禁译名词, "逻辑型") if 禁译名词 in 文本 else 文本


def 取能力说明(能力项: dict) -> str:
    return 净化说明文本(str(能力项.get("说明") or ""))


def 取参数项表(能力项: dict) -> list:
    参数项表 = 能力项.get("参数")
    return 参数项表 if isinstance(参数项表, list) else []


def 取返回项(能力项: dict) -> dict:
    返回项 = 能力项.get("返回")
    return 返回项 if isinstance(返回项, dict) else {}


def 取错误码短语表(能力项: dict) -> list:
    短语表 = 能力项.get("错误码")
    return [str(短语项) for 短语项 in 短语表] if isinstance(短语表, list) else []


def 类型标签(类型名: str) -> int:
    """老项目类型名 → V1 类型标签。带「，」后缀说明的先取首段；认不出走兜底。"""
    名字 = str(类型名 or "").strip()
    for 候选名 in (名字, 名字.split("，")[0].strip()):
        if 候选名 in 基础类型表:
            return 基础类型表[候选名]
        if 候选名 in 复合类型表:
            return 复合类型表[候选名][0]
    return 兜底类型标签


# ── 命名修复 · 号段分配 ──────────────────────────────────────────────────
def 修复名字(名字: str, 修复表: dict) -> str:
    """命名修复：确定性映射 → 上下文映射（取首候选）→ 原样返回。"""
    原名 = str(名字 or "").strip()
    确定表 = 修复表.get("确定性映射") or {}
    上下文表 = 修复表.get("上下文映射") or {}
    if 原名 in 确定表:
        return str(确定表[原名])
    if 原名 in 上下文表:
        候选原始 = 上下文表[原名] or []
        候选名表 = 候选原始.get("候选") if isinstance(候选原始, dict) else 候选原始
        if 候选名表:
            return str(候选名表[0])
    return 原名


def 取模块相对路径(模块目录: Path, 老项目根: Path) -> str:
    """模块目录相对老项目根的路径（号段分配表按它定位）；算不出给空串。"""
    try:
        return str(模块目录.resolve().relative_to(老项目根.resolve())).replace("\\", "/")
    except ValueError:
        return ""


def 查分配行(号段表: dict, 老项目路径: str, 模块名: str):
    """在号段分配表里按「老项目路径优先、模块名次之」找一行 ⇒ `(段起, 段止)` 或 None。

    认两种形状：
      · 小队 2 的**真形状** `模块分配` —— 每行是数组 `[老项目路径, 模块名, 类别, 号段起, 号段止, 容量]`；
      · 任务书 02 的形状 `模块映射` —— 每行是字典 `{模块名, 号段起, 号段止}`。
    路径优先是必要的：不同层里模块名可能重名。
    """
    分配表 = [分配行 for 分配行 in (号段表.get("模块分配") or [])
            if isinstance(分配行, (list, tuple)) and len(分配行) >= 5]
    for 命中行 in 分配表:
        if 老项目路径 and str(命中行[0]) == 老项目路径:
            return int(命中行[3]), int(命中行[4])
    for 命中行 in 分配表:
        if str(命中行[1]) == 模块名:
            return int(命中行[3]), int(命中行[4])
    for 映射项 in (号段表.get("模块映射") or []):
        if isinstance(映射项, dict) and str(映射项.get("模块名")) == 模块名:
            return (int(映射项.get("号段起", 模块号段起)),
                    int(映射项.get("号段止", 模块号段止)))
    return None


def 兜底子段(模块名: str, 模块名表: list):
    """号段分配表缺该模块时的兜底：模块段 7000–7999 内按模块名序均分（可复现）。"""
    序表 = sorted(set(模块名表)) or [模块名]
    序号 = 序表.index(模块名) if 模块名 in 序表 else 0
    宽度 = max(1, (模块号段止 - 模块号段起 + 1) // len(序表))
    段起 = 模块号段起 + 序号 * 宽度
    return 段起, min(模块号段止, 段起 + 宽度 - 1)


def 分配号段(模块名: str, 号段表: dict, 模块名表: list, 老项目路径: str = "") -> dict:
    """⇒ `{号段起, 号段止, 段位}`。

    **段位 = 号段起 // 号段类宽度（1000）** —— 与 `契约声明/号段图.json` 同口径（段位 = 码的首位）。
    模块落 7xxx ⇒ 段位 7；核心支持库落 1xxx ⇒ 段位 1；三方封装落 2xxx ⇒ 段位 2。
    段位不是常量：包声明的 `错误段位表` 与错误码都要按它出。
    """
    命中 = 查分配行(号段表, 老项目路径, 模块名)
    段起, 段止 = 命中 if 命中 else 兜底子段(模块名, 模块名表)
    return {"号段起": 段起, "号段止": 段止, "段位": 段起 // 号段类宽度}


def 标识串(模块名: str) -> str:
    """扩展身份：由模块名派生的 32 位小写十六进制（稳定 ⇒ 重译不变）。"""
    return hashlib.md5(("老项目模块接入/" + 模块名).encode("utf-8")).hexdigest()


# ── 生成声明 ───────────────────────────────────────────────────────────
def 生成包声明(模块数据: dict, 号段: dict) -> dict:
    """V1 扩展包声明（形状照 扩展根目录/原子支持库/编译器支持库/包声明.json）。"""
    段位 = int(号段.get("段位", 号段["号段起"] // 号段类宽度))
    return {
        "声明格式号": 声明格式号,
        "标识串": 标识串(模块数据["模块名"]),
        "实现版本": {"主": 0, "次": 1, "构建": 0},
        "要求宿主版本": {"主": 1, "次": 0},
        "要求内核版本": {"主": 1, "次": 0},
        "名称": 模块数据["模块名"],
        "说明": 模块数据["模块说明"],
        "目标字宽": 目标字宽,
        "能力号段": [{"起": 号段["号段起"], "止": 号段["号段止"]}],
        "通知号段": [],
        "错误段位表": [段位],
        "导出目标": 导出目标默认,
    }


def 生成参数行(参数项: dict, 修复表: dict) -> dict:
    """V1 参数信息：名称 · 说明 · 类型标签 · 状态位 · 默认值（行序即契约，按老项目原序）。"""
    return {
        "名称": 修复名字(参数项.get("名称"), 修复表),
        "说明": 净化说明文本(str(参数项.get("说明") or "")),
        "类型标签": 类型标签(参数项.get("类型")),
        "状态位": 0,
        "默认值": {"类型标签": 0, "值": 0},
    }


def 收集错误码(能力项表: list, 段位: int) -> dict:
    """⇒ {码表, 短语转码}。**码 = 段位 × 1000 + 序号**；已知短语走序号固定表，
    未知短语按排序从兜底序号起取。段位来自模块所在的号段（见 `分配号段`）。"""
    短语表 = sorted({短语 for 能力项 in 能力项表 for 短语 in 取错误码短语表(能力项)})
    码表 = {}
    短语转码 = {}
    兜底序 = 错误码兜底序号起
    for 短语 in 短语表:
        if 短语 in 错误码序号表:
            序号 = 错误码序号表[短语]
        else:
            序号 = 兜底序
            兜底序 += 1
        码值 = 段位 * 号段类宽度 + 序号
        短语转码[短语] = 码值
        码表[码值] = {
            "码": 码值,
            "名称": 短语,
            "说明": "老项目错误码「%s」在 V1 的登记码（段位 %d）。" % (短语, 段位),
            "段位": 段位,
            "可重试": False,
            "可自愈": False,
            "需人工": False,
        }
    return {"码表": 码表, "短语转码": 短语转码}


def 取值结构(能力项: dict) -> list:
    """老项目 返回.值结构（字段名 → 「类型，说明」）⇒ V1 属性表。"""
    值结构 = 取返回项(能力项).get("值结构") or {}
    if not isinstance(值结构, dict):
        return []
    属性表 = []
    for 字段名, 描述 in 值结构.items():
        描述 = 净化说明文本(str(描述 or ""))
        属性表.append({"名称": str(字段名), "说明": 描述,
                       "类型标签": 类型标签(描述), "状态位": 0})
    return 属性表


def 收集类型声明(能力项表: list) -> dict:
    """⇒ {标签: 类型声明}。只收**复合类型**（基础 0–7 由底座提供，不重声明）。"""
    标签表 = {}
    for 能力项 in 能力项表:
        类型名表 = [取返回项(能力项).get("类型")]
        类型名表 += [参数项.get("类型") for 参数项 in 取参数项表(能力项)]
        for 类型名 in 类型名表:
            首段名 = str(类型名 or "").split("，")[0].strip()
            if 首段名 not in 复合类型表:
                continue
            标签, 名称, 说明 = 复合类型表[首段名]
            属性表 = (标签表.get(标签) or {}).get("属性表") or []
            if 首段名 == "结果型":
                属性表 = 属性表 + 取值结构(能力项)
            标签表[标签] = {
                "类型标签": 标签, "名称": 名称, "说明": 说明, "状态位": 0,
                "元素表": [], "属性表": 属性表, "事件表": [], "命令号表": [],
            }
    return 标签表


def 生成能力声明(模块数据: dict, 号段: dict, 修复表: dict, 短语转码: dict) -> list:
    """⇒ 能力声明表：编号自号段起连续递增（行序 = 老项目原序，不重排）。"""
    声明表 = []
    当前号 = 号段["号段起"]
    for 能力项 in 模块数据["能力项表"]:
        能力名 = 修复名字(取能力名(能力项), 修复表)
        参数表 = [生成参数行(参数项, 修复表) for 参数项 in 取参数项表(能力项)]
        可抛码表 = sorted({短语转码[短语] for 短语 in 取错误码短语表(能力项)
                         if 短语 in 短语转码})
        声明表.append({
            "编号": 当前号,
            "名称": "%s_%s" % (模块数据["模块名"], 能力名),
            "说明": 取能力说明(能力项),
            "类别": 0,
            "状态位": 0,
            "返回类型": 类型标签(取返回项(能力项).get("类型")),
            "用户级别": 0,
            "参数表": 参数表,
            "可抛错误码": 可抛码表,
        })
        当前号 += 1
    return 声明表


def 生成声明根(模块数据: dict, 号段: dict, 修复表: dict) -> dict:
    """⇒ {包声明, 能力声明表, 错误码表, 类型声明表}。"""
    段位 = int(号段.get("段位", 号段["号段起"] // 号段类宽度))
    错误码 = 收集错误码(模块数据["能力项表"], 段位)
    return {
        "包声明": 生成包声明(模块数据, 号段),
        "能力声明表": 生成能力声明(模块数据, 号段, 修复表, 错误码["短语转码"]),
        "错误码表": 错误码["码表"],
        "类型声明表": 收集类型声明(模块数据["能力项表"]),
    }


# ── 落盘 ───────────────────────────────────────────────────────────────
def 写件(件路径: Path, 结构) -> str:
    """写一个 JSON 件（缩进 2 · 不转义中文）⇒ 返回它的 sha256。"""
    件路径.parent.mkdir(parents=True, exist_ok=True)
    正文 = json.dumps(结构, ensure_ascii=False, indent=2) + "\n"
    件路径.write_text(正文, encoding="utf-8")
    return hashlib.sha256(正文.encode("utf-8")).hexdigest()


def 写说明书(输出目录: Path, 声明根: dict) -> str:
    """出扩展自带的用法说明（必备件之一）⇒ 返回它的 sha256。"""
    包声明 = 声明根["包声明"]
    号段项 = 包声明["能力号段"][0]
    行表 = ["# %s —— 用法说明" % 包声明["名称"], "", str(包声明["说明"]), "",
            "## 能力清单", "", "| 编号 | 名称 | 参数个数 |", "| --- | --- | --- |"]
    for 能力声明 in 声明根["能力声明表"]:
        行表.append("| %d | %s | %d |" % (能力声明["编号"], 能力声明["名称"],
                                          len(能力声明["参数表"])))
    行表 += ["", "## 号段", "",
             "能力号段 %d–%d（段位 %d 归模块扩展）。" % (号段项["起"], 号段项["止"],
                                                        包声明["错误段位表"][0]), ""]
    return 写件(输出目录 / "说明" / "使用说明.md", "\n".join(行表))


def 落盘(声明根: dict, 输出目录: Path) -> dict:
    """把声明根落成一棵 V1 扩展声明根 ⇒ 返回 {相对路径: sha256}。"""
    指纹表 = {}
    指纹表["包声明.json"] = 写件(输出目录 / "包声明.json", 声明根["包声明"])
    for 能力声明 in 声明根["能力声明表"]:
        相对名 = "能力声明/%d.json" % 能力声明["编号"]
        指纹表[相对名] = 写件(输出目录 / 相对名, 能力声明)
    for 码值, 错误码声明 in sorted(声明根["错误码表"].items()):
        相对名 = "错误码表/%d.json" % 码值
        指纹表[相对名] = 写件(输出目录 / 相对名, 错误码声明)
    for 标签, 类型声明 in sorted(声明根["类型声明表"].items()):
        相对名 = "类型声明/%d.json" % 标签
        指纹表[相对名] = 写件(输出目录 / 相对名, 类型声明)
    指纹表["说明/使用说明.md"] = 写说明书(输出目录, 声明根)
    写件(输出目录 / "指纹.json",
        {"说明": "本扩展各声明件的 sha256（重译即刷新）", "件": 指纹表})
    return 指纹表
