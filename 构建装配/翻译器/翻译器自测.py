# -*- coding: utf-8 -*-
"""翻译器自测 —— 正反向样本（夹具在临时目录现造，不碰仓里任何件）。

覆盖：类型映射 · 命名修复 · 号段分配 · 声明生成（编号/名称/参数表/可抛错误码/类型声明）·
落盘（目录形状 + 指纹）· 任务书形状单件。

本件**不是入口**（不写 `__main__`）：跑它走 `翻译器测试.py` —— 入口只做路由，实现住本件。
"""
from __future__ import annotations

import json
import tempfile
import unittest
from pathlib import Path

from 翻译器常量 import 模块号段起, 模块号段止, 兜底类型标签
from 翻译器实现 import 读模块, 类型标签, 修复名字, 分配号段, 生成声明根, 落盘
from 翻译器主流程 import 翻译模块, 契约单件

修复表样本 = {
    "确定性映射": {"记录": "编目记录"},
    "上下文映射": {"条目": {"候选": ["条目表", "条目清单"]}},
}


def 造样本(样本根: Path) -> Path:
    """在临时根里造一个最小老项目模块 ⇒ 返回它的目录。"""
    模块目录 = 样本根 / "模块库" / "样本模块"
    模块目录.mkdir(parents=True)
    能力定义 = {
        "包id": "模块库.样本模块",
        "名称": "样本模块",
        "版本": "1.0.0",
        "说明": "自测用样本模块",
        "能力列表": [
            {"能力id": "样本模块.编目", "中文名称": "编目", "说明": "给文件编目",
             "参数": [{"名称": "文件路径", "类型": "文本型", "说明": "目标文件"},
                     {"名称": "元数据", "类型": "字典型", "说明": "附加元数据"}],
             "返回": {"类型": "结果型", "值结构": {"总数": "整数型，条目数"}},
             "错误码": ["参数不合法", "读取失败"]},
            {"能力id": "样本模块.列举", "中文名称": "列举", "说明": "列举条目",
             "参数": [{"名称": "记录", "类型": "文本型", "说明": "目标记录"}],
             "返回": {"类型": "列表型"},
             "错误码": ["参数不合法"]},
        ],
    }
    (模块目录 / "能力定义.json").write_text(
        json.dumps(能力定义, ensure_ascii=False), encoding="utf-8")
    return 模块目录


class 翻译器测试(unittest.TestCase):
    """一个模块一条链：读源 → 译名 → 号段 → 生成 → 落盘。"""

    def setUp(self):
        self.临时根 = tempfile.TemporaryDirectory()
        self.样本根 = Path(self.临时根.name)
        self.模块目录 = 造样本(self.样本根)

    def tearDown(self):
        self.临时根.cleanup()

    def test_类型映射(self):
        self.assertEqual(类型标签("文本型"), 4)
        self.assertEqual(类型标签("整数型"), 1)
        self.assertEqual(类型标签("逻辑型"), 3)
        self.assertEqual(类型标签("字典型"), 101)
        self.assertEqual(类型标签("结果型"), 102)
        self.assertEqual(类型标签("文本型，固定 队列"), 4)
        self.assertEqual(类型标签("认不出的型"), 兜底类型标签)

    def test_命名修复(self):
        self.assertEqual(修复名字("记录", 修复表样本), "编目记录")
        self.assertEqual(修复名字("条目", 修复表样本), "条目表")
        self.assertEqual(修复名字("文件路径", 修复表样本), "文件路径")
        self.assertEqual(修复名字("记录", {}), "记录")

    def test_号段分配(self):
        号段表 = {"模块映射": [{"模块名": "样本模块", "号段起": 7200, "号段止": 7299}]}
        任务书形 = 分配号段("样本模块", 号段表, [])
        self.assertEqual((任务书形["号段起"], 任务书形["号段止"]), (7200, 7299))
        self.assertEqual(任务书形["段位"], 7)
        兜底 = 分配号段("样本模块", {}, ["样本模块", "另个模块"])
        self.assertGreaterEqual(兜底["号段起"], 模块号段起)
        self.assertLessEqual(兜底["号段止"], 模块号段止)
        # 兜底分配只看模块名集合（排序后定位）⇒ 入参顺序不改变结果
        self.assertEqual(兜底, 分配号段("样本模块", {}, ["另个模块", "样本模块"]))

    def test_认号段分配表真形状(self):
        """小队 2 的真形状：`模块分配` 是数组行 [路径, 模块名, 类别, 起, 止, 容量]；
        段位随号段起 —— 支持库落 1xxx ⇒ 段位 1（不是模块段位 7）。"""
        号段表 = {"模块分配": [
            ["模块库/知识检索", "知识检索", "模块（扩展）", 7550, 7599, 50],
            ["支持库/后端/数值计算支持库", "数值计算支持库", "核心支持库", 1270, 1299, 30],
        ]}
        模块级 = 分配号段("知识检索", 号段表, [], "模块库/知识检索")
        self.assertEqual((模块级["号段起"], 模块级["号段止"], 模块级["段位"]),
                         (7550, 7599, 7))
        支持库级 = 分配号段("数值计算支持库", 号段表, [], "支持库/后端/数值计算支持库")
        self.assertEqual((支持库级["号段起"], 支持库级["段位"]), (1270, 1))
        # 无路径时退回按模块名定位
        self.assertEqual(分配号段("知识检索", 号段表, [], "")["号段起"], 7550)

    def test_错误码随段位(self):
        """段位不是常量：支持库（段位 1）的错误码落 1xxx，不是 7xxx。"""
        模块数据 = 读模块(self.模块目录)
        声明根 = 生成声明根(模块数据, {"号段起": 1270, "号段止": 1299, "段位": 1}, {})
        self.assertEqual(声明根["包声明"]["错误段位表"], [1])
        self.assertIn(1001, 声明根["错误码表"])
        self.assertTrue(set(声明根["能力声明表"][0]["可抛错误码"]) <= set(声明根["错误码表"]))

    def test_生成声明根(self):
        模块数据 = 读模块(self.模块目录)
        声明根 = 生成声明根(模块数据, {"号段起": 7100, "号段止": 7199}, 修复表样本)
        self.assertEqual(len(声明根["能力声明表"]), 2)
        首项 = 声明根["能力声明表"][0]
        self.assertEqual(首项["编号"], 7100)
        self.assertEqual(声明根["能力声明表"][1]["编号"], 7101)
        self.assertEqual(首项["名称"], "样本模块_编目")
        self.assertEqual(首项["返回类型"], 102)
        self.assertEqual(len(首项["参数表"]), 2)
        self.assertEqual(首项["参数表"][0]["名称"], "文件路径")
        self.assertEqual(首项["参数表"][0]["类型标签"], 4)
        self.assertEqual(首项["参数表"][1]["类型标签"], 101)
        self.assertTrue(set(首项["可抛错误码"]) <= set(声明根["错误码表"]))
        self.assertIn(102, 声明根["类型声明表"])
        self.assertEqual(声明根["类型声明表"][102]["属性表"][0]["名称"], "总数")
        self.assertEqual(声明根["包声明"]["能力号段"], [{"起": 7100, "止": 7199}])
        self.assertEqual(声明根["包声明"]["错误段位表"], [7])
        self.assertEqual(声明根["包声明"]["声明格式号"], 1398362929)

    def test_落盘(self):
        声明根 = 生成声明根(读模块(self.模块目录),
                        {"号段起": 7100, "号段止": 7199}, 修复表样本)
        输出目录 = self.样本根 / "产物"
        指纹表 = 落盘(声明根, 输出目录)
        self.assertTrue((输出目录 / "包声明.json").is_file())
        self.assertTrue((输出目录 / "能力声明" / "7100.json").is_file())
        self.assertTrue((输出目录 / "错误码表" / "7001.json").is_file())
        self.assertTrue((输出目录 / "说明" / "使用说明.md").is_file())
        self.assertTrue((输出目录 / "指纹.json").is_file())
        self.assertEqual(len(指纹表["包声明.json"]), 64)

    def test_翻译模块与单件(self):
        声明根 = 翻译模块(self.模块目录, self.样本根, 修复表样本, {})
        单件 = 契约单件(声明根)
        self.assertEqual(单件["模块名"], "样本模块")
        self.assertIn("~", 单件["号段"])
        self.assertEqual(单件["能力列表"][0]["能力编号"], 单件["能力列表"][1]["能力编号"] - 1)
        self.assertEqual(单件["能力列表"][0]["参数表"][0]["行序"], 0)
        self.assertEqual(单件["能力列表"][0]["参数表"][0]["参数名"], "文件路径")
