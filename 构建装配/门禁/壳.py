# -*- coding: utf-8 -*-
"""命令壳 —— 每条命令的「壳自量自门禁」（`2026-09-27_所有运行五秒硬顶.md` §六.1 的落法）。

**为什么是「壳自量」而不是「一条中央判据读各命令的回执」**（§六.1 给了两条实测理由）：
  · 回执不在 ⇒ 中央判据只能报「未判」，而闸1 的退出码语义是「未判即 1」⇒ 门禁**永久变红**
    （新克隆、`git clean` 之后必然如此）；
  · 回执里记的常是**内部耗时**（例：案例回执的 `耗时微秒` 不含 `cargo` 启动那一段）
    ⇒ 拿它冒充墙钟就是**假读数**。
⇒ 一条命令的**完整墙钟只有它自己的壳能量**。所以每条命令的入口：① 在**导入业务包之前**起表
（`起 = time.monotonic()` 写在入口的**第一行可执行语句** —— 比 import 本模块还早，同
`开发工具/取证/声明记录区反解.py` 的先例）
② 跑完调 `自门禁` ③ 超阈值 ⇒ 打印红 + 非 0。

**量不到的边界（如实登记）**：壳在入口的第一行可执行语句起表，故量不到「解释器启动」与
「进程退出」那两段。阈值取「硬顶 − 该命令的尾巴余量」（裁决 §二 第四轮），
这样「完整命令 ≤ 硬顶」这句声明才**为真**。余量由**该命令自己**给（见 `常量.py` 的说明）。

**反向样本（证明门禁不空转）**：`人为慢环境变量` 给毫秒数 ⇒ 算完之后**真睡**那么久
⇒ 门禁必须报红。它是环境变量而不是命令行开关：它只服务于这条自证，不进公开用法面。
变量名**必须 ASCII**（`sh`/`zsh` 不认非 ASCII 变量名，实测过 —— 同 `进入.sh` 顶部那条理由）。
"""

from __future__ import annotations

import os
import sys
import time

from .常量 import 硬顶毫秒

人为慢环境变量 = "V1_CMD_SLOW_MS"


def 注入人为慢() -> int:
    """反向样本注入：环境变量给毫秒数，就在算完之后**真睡**那么久（默认 0 = 不注入）。"""
    值 = os.environ.get(人为慢环境变量)
    if not 值:
        return 0
    try:
        毫秒 = float(值)
    except ValueError:
        return 0
    if 毫秒 <= 0:
        return 0
    time.sleep(毫秒 / 1000.0)
    return int(毫秒)


def 自门禁(起: float, 码: int, 尾巴余量毫秒: int, 修法: str, 流=None) -> int:
    """自量墙钟 → 超阈值报红并非 0。**命令本体算出来的码优先保留**（在顶内时原样返回）。

    `尾巴余量毫秒` 由调用方给（每条命令的尾巴不同，见 `常量.py`）；`修法` 是超顶时指的路
    （按裁决 §三：分片 / 缓存 / 把重活移出命令路）。
    """
    流 = 流 or sys.stderr
    阈值毫秒 = 硬顶毫秒 - 尾巴余量毫秒
    注入 = 注入人为慢()
    墙钟毫秒 = int((time.monotonic() - 起) * 1000)
    print("─" * 78, file=流)
    print("命令墙钟（壳自量）%d ms · 阈值 %d ms（硬顶 %d − 尾巴余量 %d）· 人为慢注入 %d ms"
          % (墙钟毫秒, 阈值毫秒, 硬顶毫秒, 尾巴余量毫秒, 注入), file=流)
    if 墙钟毫秒 > 阈值毫秒:
        print("✗ 超顶：完整墙钟 %d ms > %d ms —— 五秒硬顶无例外（裁决 §一）"
              % (墙钟毫秒, 阈值毫秒), file=流)
        print("  修法（裁决 §三.2/§三.3）：%s" % 修法, file=流)
        return 1
    print("✓ 在硬顶内", file=流)
    return 码
