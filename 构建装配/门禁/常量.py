# 后面所有合并都会被堵住 ⇒ 90 秒护栏就是为这个兜底的。
# ★ 它**不是判决线**：不参与验收判定；判据逻辑一条都不许放松，只是「墙钟」这一维不判红。
# ★ 触发时**也记一条债务**，但**理由与「墙钟超 5 秒」区分开**
#   （`债务.原因_失控护栏` = 疑似挂死 vs `债务.原因_超效率目标` = 性能债务）—— 收口时分两类处理。
# ★ **各外层一律从本值派生**（闸 0 两条子闸 / ㊽ 自检 / 隔离重样本组 / 腿树门禁 / 提交钩子）：
#   本件仍是**唯一一处**，不许在别处再抄一个数（抄了就会内外不同步、内层先杀外层拿假读数）。
#   参考量级：闸0 单跑 6.23 s、4 条并发被打满 13.4 s、最长的串行段（源件重抽 10.6 s /
#   长样本 13.8 s）离 90 s 都差一个数量级 ⇒ 只在真挂死时触发，不因负载误伤。
#   普通 `v1_shell` 短命令 1..5 / 操作脚本超时 / 普通只读 git 短窗**不取**这里。
失控护栏毫秒 = 90000

