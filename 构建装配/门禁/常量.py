# ── 效率目标（**报告线，不是判决线**）────────────────────────────────────────
#
# ★★ **2026-10-09 用户当场下令（口径变更 · 覆盖此前所有「硬顶」口径）** ★★
#   原为「命令级硬顶」：一条命令完整跑完的墙钟 > `硬顶毫秒` ⇒ **判红、拒提交**。
#   用户原话：「把这个硬顶移除掉，然后加上一个汇报，超过5秒就汇报进债务就行……
#   接下来只有墙钟，没有硬顶，墙钟超过5秒就后台记一条债务。」
#   ⇒ 现在这条线**只做一件事**：超了就**后台记一条债务**（可查询 · 不需要 agent 介入）；
#   **不再判红、不再杀进程、不参与任何验收判决**。
#   ⇒ 判据 ⑱ 仍在（它报**读数**，是债务记录的读数来源），但它**不再判失败**。
#   ⇒ **判据面里凡「把 5000 当规则本身」的，必须从本值派生**（不许从护栏派生 —— 那会把
#     一条判据的上限从 5 秒悄悄放到 90 秒，等于放松验收强度）。实查两处：
#     · 判据 ㊲「超时设置上限五秒」的 `秒上限` / `毫秒上限`；
#     · 判据 ⑱ 那条报告线。
#   ⇒ 尾巴余量 200 **仍然要**：它不是「让 ⑱ 抢先自报」，而是「壳量不到解释器启动 / 退出
#     那一段」的补偿 —— **比的是报告线**（「完整命令 ≤ 效率目标」这句报告才为真），与判红无关。
