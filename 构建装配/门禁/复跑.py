"""复跑 —— 「瞬时超顶自动复跑一次」的**唯一口径**（钩子与开工释放共用这一份）。

并发腿抢 CPU 会把一条命令的墙钟顶过五秒硬顶（实测闸 0 见 5578 / 5793 / 6688 / 4816 ms），
那是**读数被污染**、不是代码坏了 ⇒ 复跑一次，仍超才红。

认的输出字样 = 「超顶」/「超时」/「已越过」：`自门禁` 超顶打「✗ 超顶」；`仓操作.跑命令` 自身超时打
「超时（N 秒）」；判据 ⑱（命令墙钟）红打「⇒ 完整命令墙钟已越过 N ms」（`--自测` 嵌套里 ⑱ 假红就是它）。
三处都算瞬时 —— 钩子的 ①闸0 与 ①b（`--自测`）用同一份口径，别让作者自行挤。
"""

import os
import time

# ── 负载感知（华哥 2026-10-13）────────────────────────────────────
# 负载是**瞬时**的：并发腿 / 系统索引 / 其它会话抢 CPU，会把一条命令的墙钟顶过五秒。
# 只「立即复跑一次」不够 —— 负载还高就再红一次（实测 load 12.22 / 968 进程）。
# 所以复跑前先**读每核负载**，高就等它落下来再复跑；**有界**：等满上限仍高照跑。
负载红线 = 0.9
等待上限秒 = 10.0
等待步长秒 = 2.0


def 取每核负载() -> float:
    """1 分钟平均负载 ÷ CPU 核数。取不到 ⇒ 0.0（当空闲，不误伤）。"""
    try:
        return os.getloadavg()[0] / (os.cpu_count() or 1)
    except Exception:
        return 0.0


def 等负载落(等待上限秒=等待上限秒, 负载红线=负载红线, 报进度=None) -> float:
    """阻塞等到每核负载 < 负载红线；返回实际等待秒数（到上限也返回，不无限等）。"""
    起 = time.monotonic()
    while time.monotonic() - 起 < 等待上限秒:
        当前 = 取每核负载()
        if 当前 < 负载红线:
            break
        if 报进度:
            报进度("每核负载 %.2f ≥ %.2f ⇒ 等 %.0f s 再复跑" % (当前, 负载红线, 等待步长秒))
        time.sleep(等待步长秒)
    return time.monotonic() - 起


def 是瞬时超顶(输出文本: str) -> bool:
    """输出里带「超顶」/「超时」/「已越过」字样 ⇒ 疑似瞬时（并发抢 CPU / 子进程超时 / ⑱ 越过硬顶）。"""
    return ("超顶" in (输出文本 or "")) or ("超时" in (输出文本 or "")) or ("已越过" in (输出文本 or ""))


def 跑并复跑超顶(执行一次, 等待器=None, 复跑次数: int = 3, 报进度=None):
    """跑 `执行一次()`（⇒ `(退出码, 输出)`）；失败且输出疑似瞬时超顶 ⇒ **等负载落 + 复跑**。

    返回 `(退出码, 输出, 复跑过)`。真红（判据失败，输出里没有超顶/超时字样）⇒ 不复跑。
    `等待器` 可注入（自检传空等器 ⇒ 不真睡）；默认用 `等负载落`。
    """
    等待器 = 等待器 or (lambda: 等负载落(报进度=报进度))
    退出码, 输出文本 = 执行一次()
    for _ in range(复跑次数):
        if 退出码 == 0 or not 是瞬时超顶(输出文本):
            return 退出码, 输出文本, False
        等待器()
        退出码, 输出文本 = 执行一次()
        if 退出码 == 0:
            return 退出码, 输出文本, True
    return 退出码, 输出文本, True


def 自检_复跑() -> list:
    """复跑口径的身份证（挂 `一键验证.py --自测` 的机制用例）：正 + 反三问。"""
    调用计数 = [0]

    def 慢一次():
        调用计数[0] += 1
        return (1, "✗ 超顶：完整墙钟 4816 ms > 4800 ms") if 调用计数[0] == 1 else (0, "通过 51 项")

    def 一直慢():
        return 1, "失败：⇒ 完整命令墙钟已越过 5000 ms"

    def 真红():
        return 1, "失败：单件超 400 行（判据红，非瞬时）"

    空等器 = lambda: 0.0
    瞬时绿 = 跑并复跑超顶(慢一次, 等待器=空等器)
    瞬时拒 = 跑并复跑超顶(一直慢, 等待器=空等器)
    真红果 = 跑并复跑超顶(真红, 等待器=空等器)
    return [
        ("复跑口径：瞬时超顶一次 ⇒ 自动复跑后判绿", 瞬时绿 == (0, "通过 51 项", True), "%r" % (瞬时绿,)),
        ("复跑口径：真超顶（含 ⑱「已越过」字样）仍拒", 瞬时拒[0] == 1 and 瞬时拒[2] is True, "%r" % (瞬时拒,)),
        ("复跑口径：真红（无超顶/超时/已越过字样）不复跑", 真红果[0] == 1 and 真红果[2] is False, "%r" % (真红果,)),
        ("复跑口径：负载感知可读且**有界**（上限 0 ⇒ 不睡即返）",
         0.0 <= 取每核负载() < 999 and 等负载落(等待上限秒=0) >= 0.0,
         "每核负载 %r" % (取每核负载(),)),
    ]
