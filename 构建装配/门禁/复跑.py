"""复跑 —— 「瞬时超顶自动复跑一次」的**唯一口径**（钩子与开工释放共用这一份）。

并发腿抢 CPU 会把一条命令的墙钟顶过五秒硬顶（实测闸 0 见 5578 / 5793 / 6688 / 4816 ms），
那是**读数被污染**、不是代码坏了 ⇒ 复跑一次，仍超才红。

认的输出字样 = 「超顶」/「超时」/「已越过」：`自门禁` 超顶打「✗ 超顶」；`仓操作.跑命令` 自身超时打
「超时（N 秒）」；判据 ⑱（命令墙钟）红打「⇒ 完整命令墙钟已越过 N ms」（`--自测` 嵌套里 ⑱ 假红就是它）。
三处都算瞬时 —— 钩子的 ①闸0 与 ①b（`--自测`）用同一份口径，别让作者自行挤。
"""

import os
import time

# ── 负载感知（华哥 2026-10-13）────────────────────────────────────
# 负载是**瞬时**的：并发腿 / 系统索引 / 其它会话抢 CPU，会把一条命令的墙钟顶过五秒。
# 只「立即复跑一次」不够 —— 负载还高就再红一次（实测 load 12.22 / 968 进程）。
# 所以复跑前先**读每核负载**，高就等它落下来再复跑；**有界**：等满上限仍高照跑。
负载红线 = 0.9
等待上限秒 = 10.0
等待步长秒 = 2.0


def 取每核负载() -> float:
    """1 分钟平均负载 ÷ CPU 核数。取不到 ⇒ 0.0（当空闲，不误伤）。"""
    try:
        return os.getloadavg()[0] / (os.cpu_count() or 1)
    except Exception:
        return 0.0


def 等负载落(等待上限秒=等待上限秒, 负载红线=负载红线, 报进度=None) -> float:
    """阻塞等到每核负载 < 负载红线；返回实际等待秒数（到上限也返回，不无限等）。"""
    起始 = time.monotonic()
    while time.monotonic() - 起始 < 等待上限秒:
        当前负载 = 取每核负载()
        if 当前负载 < 负载红线:
            break
        if 报进度:
            报进度("每核负载 %.2f ≥ %.2f ⇒ 等 %.0f s 再复跑" % (当前负载, 负载红线, 等待步长秒))
        time.sleep(等待步长秒)
    return time.monotonic() - 起始


def 是瞬时超顶(输出文本: str) -> bool:
    """输出里带「超顶」/「超时」/「已越过」字样 ⇒ 疑似瞬时（并发抢 CPU / 子进程超时 / ⑱ 越过硬顶）。"""
    return ("超顶" in (输出文本 or "")) or ("超时" in (输出文本 or "")) or ("已越过" in (输出文本 or ""))


def 跑并复跑超顶(执行一次, 等待器=None, 复跑次数: int = 3, 报进度=None, 读负载=None):
    """跑 `执行一次()`（⇒ `(退出码, 输出)`）；失败且输出疑似瞬时超顶 ⇒ **等负载落 + 复跑**。

    ★ 华哥 2026-10-13：**负载拉满也不许直接爆** —— 负载异常的登记「资源占用不足，但能跑」放行，
      负载正常的才照常判。据此，复跑到底仍红时看负载：
        · 每核负载 ≥ `负载红线` ⇒ **放行**（退出码 0）+ 回执里带「资源占用不足，但能跑」
        · 每核负载 < `负载红线` ⇒ **真红**（原样返回，不改判）
      **非瞬时真红**（判据自身失败）不走这条路 ⇒ 不受负载豁免。

    返回 `(退出码, 输出, 复跑过)`。`等待器` / `读负载` 可注入（自检用 ⇒ 不真睡、不真读机）。
    """
    读负载 = 读负载 or 取每核负载
    等待器 = 等待器 or (lambda: 等负载落(报进度=报进度))
    退出码, 输出文本 = 执行一次()
    for _ in range(复跑次数):
        if 退出码 == 0 or not 是瞬时超顶(输出文本):
            return 退出码, 输出文本, False
        等待器()
        退出码, 输出文本 = 执行一次()
        if 退出码 == 0:
            return 退出码, 输出文本, True
    当前负载 = 读负载()
    if 当前负载 >= 负载红线:
        return 0, (输出文本 + "\n★ 资源占用不足，但能跑：每核负载 %.2f ≥ %.2f ⇒ 本次超顶按**负载异常**放行"
                   "（登记，不判红；机器闲下来重跑即恢复真读数）" % (当前负载, 负载红线)), True
    return 退出码, 输出文本, True


def 自检_复跑() -> list:
    """复跑口径的身份证（挂 `一键验证.py --自测` 的机制用例）：正 + 反三问。"""
    调用计数 = [0]

    def 慢一次():
        调用计数[0] += 1
        return (1, "✗ 超顶：完整墙钟 4816 ms > 4800 ms") if 调用计数[0] == 1 else (0, "通过 51 项")

    def 一直慢():
        return 1, "失败：⇒ 完整命令墙钟已越过 5000 ms"

    def 真红():
        return 1, "失败：单件超 400 行（判据红，非瞬时）"

    空等器 = lambda: 0.0
    高负载 = lambda: 1.5
    低负载 = lambda: 0.1
    瞬时绿 = 跑并复跑超顶(慢一次, 等待器=空等器, 读负载=低负载)
    负载真拒 = 跑并复跑超顶(一直慢, 等待器=空等器, 读负载=低负载)
    负载放行 = 跑并复跑超顶(一直慢, 等待器=空等器, 读负载=高负载)
    真红果 = 跑并复跑超顶(真红, 等待器=空等器, 读负载=低负载)
    真红高载 = 跑并复跑超顶(真红, 等待器=空等器, 读负载=高负载)
    return [
        ("复跑口径：瞬时超顶一次 ⇒ 自动复跑后判绿", 瞬时绿 == (0, "通过 51 项", True), "%r" % (瞬时绿,)),
        ("复跑口径：真超顶 + **负载正常** ⇒ 仍拒", 负载真拒[0] == 1 and 负载真拒[2] is True, "%r" % (负载真拒,)),
        ("复跑口径：真超顶 + **负载异常** ⇒ 放行且登记「资源占用不足，但能跑」",
         负载放行[0] == 0 and "资源占用不足，但能跑" in 负载放行[1], "%r" % (负载放行[0],)),
        ("复跑口径：真红（无超顶字样）不复跑", 真红果[0] == 1 and 真红果[2] is False, "%r" % (真红果,)),
        ("复跑口径：真红**不受负载豁免**（负载异常也照拒）", 真红高载[0] == 1, "%r" % (真红高载[0],)),
        ("复跑口径：负载感知可读且**有界**（上限 0 ⇒ 不睡即返）",
         0.0 <= 取每核负载() < 999 and 等负载落(等待上限秒=0) >= 0.0,
         "每核负载 %r" % (取每核负载(),)),
    ]
