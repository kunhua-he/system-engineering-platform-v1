"""复跑 —— 「瞬时超顶自动复跑一次」的**唯一口径**（钩子与开工释放共用这一份）。

并发腿抢 CPU 会把一条命令的墙钟顶过五秒硬顶（实测闸 0 见 5578 / 5793 / 6688 / 4816 ms），
那是**读数被污染**、不是代码坏了 ⇒ 复跑一次，仍超才红。

认的输出字样 = 「超顶」/「超时」：`自门禁` 超顶打「✗ 超顶」；`仓操作.跑命令` 自身超时打
「超时（N 秒）」。两处都算瞬时。
"""


def 是瞬时超顶(输出文本: str) -> bool:
    """输出里带「超顶」或「超时」字样 ⇒ 疑似瞬时（并发抢 CPU / 子进程超时）。"""
    return "超顶" in (输出文本 or "") or "超时" in (输出文本 or "")


def 跑并复跑超顶(执行一次):
    """跑一次 `执行一次()`（⇒ `(退出码, 输出)`）；失败且输出疑似瞬时超顶 ⇒ **复跑一次**。

    返回 `(退出码, 输出, 复跑过)`。真红（判据失败）输出里没有超顶/超时字样 ⇒ 不复跑。
    """
    退出码, 输出文本 = 执行一次()
    if 退出码 != 0 and 是瞬时超顶(输出文本):
        退出码, 输出文本 = 执行一次()
        return 退出码, 输出文本, True
    return 退出码, 输出文本, False
