# -*- coding: utf-8 -*-
"""装载守卫 —— 把「装载期崩」变成**一条可诊断的红**（债务 526）。

**为什么要这一条**：两条闸的入口在**导入业务包那一刻**就硬读仓内主人件 ——
例：`构建装配/一键验证/一键验证/基础定义/判据取值硬顶硬顶常量.py` 顶层 `import 表定义`（层名 / 契约目录名 /
常量表路径 / 扩展三类 / 底座树 五处都引它当主人）。并行开发时那条链上的件**必然**
有中间态（改到一半 / 正在改名 / 临时语法错）⇒ 入口在**进入判据之前**就抛裸
`SyntaxError` / `ImportError`，调用方（人 / Agent）只拿到一段 Traceback：既不知道
是哪一件坏了，也拿不到修法，只能逆着栈人工读。

实测（2026-10-12）：腿树里把 `开发工具/信息核心/表定义.py` 改坏 ⇒
`一键验证.py` 与 `闸0.py` **双双裸崩**、退出码 1、0 处「修法」字样；
同刻干净主干跑绿 56 项 / 0 失败。把**链外件**改坏则出的是正常判据报告 ⇒
差别只在**坏件在不在装载链上**。

**本件只做一件事**：包住装载动作；异常时打印**一条**可诊断的红（坏件路径 · 异常类型 ·
一行原因 · 修法），再以非 0 退出 —— **不吞异常、不接着跑**（装载链断了，后面每一步
都不可信，fail-closed）。
"""

from __future__ import annotations

import traceback


def 取坏件(装载异常: BaseException) -> str:
    """从异常里取**坏件路径**：优先异常自带的文件名，取不到回空串（不猜）。"""
    文件名 = getattr(装载异常, "filename", None) or getattr(装载异常, "filename2", None)
    return str(文件名) if 文件名 else ""


def 报装载失败(装载异常: BaseException, 装载件名: str, 修法: str) -> str:
    """打印一条可诊断的红 ⇒ 回那段诊断文本（供样本逐字断言）。"""
    坏件路径 = 取坏件(装载异常)
    首行 = ("%s: %s" % (type(装载异常).__name__, 装载异常)).splitlines()[0]
    诊断文本 = "\n".join([
        "─" * 78,
        "✗ 装载失败（%s）：入口在**导入业务代码那一刻**就断了，判据一条都没跑。" % 装载件名,
        "  坏件：%s" % (坏件路径 or "（异常未带文件名，见下方栈）"),
        "  原因：%s" % 首行,
        "  修法：%s" % 修法,
        "  为什么这样报：装载链上的件处于中间态（改到一半 / 正改名 / 临时语法错）时，",
        "  入口连判据都进不去 ⇒ 调用方只看到 Traceback，读不出是哪一件、也不知道怎么修。",
        "─" * 78,
        traceback.format_exc(),
    ])
    print(诊断文本)
    return 诊断文本


def 守卫装载(装载动作, 装载件名: str, 修法: str):
    """跑 `装载动作()`；装载期异常 ⇒ 打印诊断 + 非 0 退出；成功 ⇒ 原样回它的返回值。"""
    try:
        return 装载动作()
    except Exception as 装载异常:
        报装载失败(装载异常, 装载件名, 修法)
        raise SystemExit(1)


def 自检_守卫装载() -> list:
    """本守卫的身份证（挂 `一键验证.py --自测` 的机制用例）：正一问 + 反两问。"""
    好果 = 守卫装载(lambda: 42, 装载件名="样本包", 修法="样本修法")

    def 坏动作():
        raise SyntaxError("'(' was never closed", ("坏件.py", 1, 1, "def 半成品("))

    坏果 = None
    try:
        守卫装载(坏动作, 装载件名="样本包", 修法="样本修法")
    except SystemExit as 退出:
        坏果 = 退出.code
    诊断文本 = ""
    try:
        坏动作()
    except Exception as 装载异常:
        诊断文本 = 报装载失败(装载异常, "样本包", "样本修法")
    return [
        ("装载守卫：装载成功 ⇒ 原样回返回值（不吞结果）", 好果 == 42, "%r" % (好果,)),
        ("装载守卫：装载失败 ⇒ 非 0 退出（不裸崩）", 坏果 == 1, "%r" % (坏果,)),
        ("装载守卫：诊断里带坏件路径与修法（调用方能直接照着修）",
         ("坏件.py" in 诊断文本) and ("样本修法" in 诊断文本) and ("✗ 装载失败" in 诊断文本),
         "坏件=%r 修法=%r" % ("坏件.py" in 诊断文本, "样本修法" in 诊断文本)),
    ]
