# -*- coding: utf-8 -*-
r"""墙钟债务 —— 命令墙钟超效率目标时**后台自动记一条**，可查询、不需要 agent 介入。

**为什么要有它**（2026-10-09 用户当场下令）：
「把这个硬顶移除掉，然后加上一个汇报，超过5秒就汇报进债务就行……接下来只有墙钟，没有硬顶，
墙钟超过5秒就后台记一条债务。」（原话里的自称词按仓内禁用字口径改写，事实不变）
⇒ 效率目标不再是**判决线**（不再判红、不再拒提交、不再杀进程），改为**报告线**：
超了就记一条可查询的债务，把「为什么慢」留在盘上。

**★ 落点硬约束（这一次最要紧的一条，别弄错）**：记录**绝不能写进仓内受版本控制的工作区**
（`未完成.json` / 信息核心库源表 / 任何跟踪件）—— 门禁在 `pre-commit` 里跑，一写就把工作区弄脏
⇒ 合并第 ④ 步「推进前同步保护」会拒，**全队列卡死**（2026-10-08 真实发作过：有腿在仓根跑 `建库`，
把主库改脏，678 连卡三次）。
⇒ 落到**运行数据根**的 `日志` 类子目录（非版本控制的派生面），一行一条 JSON（追加写，不重写整档）。
★ 收官时由主策划蒸馏进唯一台账 `未完成.json`（那是**人**的动作，不是本件）。

**三条性质**（缺一条就不成立）：
  · **后台**：只追加一行，不阻塞调用方、不抛异常出来（写不动就静默 —— 记录本身不许成为新故障点）。
  · **可查询**：`读债务` 给最近若干条（结构化），另有 `汇总债务` 按「原因 + 命令 + 阶段」聚合。
  · **能定位原因**：每条带 `线索块`（CPU 空闲率 / 负载 / 并发闸进程数）。

**为什么记机器线索而不是一句「慢」**：实测过 ⑱ 在负载高时被推过阈值（那是**读数被污染**），
而真慢出在**命令本身**（例：㊽ 里 12 组撞超订、sys 占 92%）。两者处置完全不同 ⇒ 记清楚。
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from pathlib import Path

# 记录件名（住运行数据根 `日志` 类）：**只追加**的 JSONL，一行一条。
记录件名 = "墙钟债务.jsonl"
# 记录格式的版本号：将来加字段时，读的人按它分流（不是「改了就覆盖」）。
记录格式版本 = 1
# 两个原因（**必须分得清** —— 见 `原因_失控护栏`）：
原因_超效率目标 = "墙钟超效率目标"
原因_失控护栏 = "失控护栏触发（疑似挂死）"
# 线索取不到时的占位（**照记，不编数**）。
线索取不到 = "取不到"


def 台账目录():
    """⇒ 运行数据根的 `日志` 类子目录路径（**不建目录**）；解析不出 ⇒ `None`。

    走**唯一解析口** `开发工具/运行数据根`（不许本件本件拼路径 —— 自身拼 = 第二个来源）。
    解析不出（家目录 / XDG / APPDATA 全缺）⇒ 回 `None`：**记不上就不记**，
    绝不把一条命令变成 traceback。
    """
    仓根 = Path(__file__).resolve().parents[2]
    加目录 = str(仓根 / "开发工具")
    if 加目录 not in sys.path:
        sys.path.insert(0, 加目录)
    try:
        from 运行数据根 import 解析当前环境, 子目录路径
        return 子目录路径(解析当前环境(), "日志")
    except Exception:
        return None


def 机器线索() -> dict:
    """⇒ 当时的机器线索块。取不到就如实写 `取不到`（**不编数**）。

    · 负载：`os.getloadavg()`（三个窗口都记，看的是趋势）；
    · CPU 空闲率：`ps -A -o %cpu` 求和 ÷ 核数（**与收口方手测同一口径** —— 那条实测里
      「4 条闸0 并发 ⇒ 空闲 74.9% → 8.9%」就是这么量的）；
    · 并发闸进程数：数命令行里含闸入口关键词的进程（同一口径）。
    """
    线索块 = {"负载": 线索取不到, "CPU空闲率": 线索取不到, "并发闸进程数": 线索取不到,
           "核数": os.cpu_count() or 0}
    try:
        if hasattr(os, "getloadavg"):
            线索块["负载"] = [round(值, 2) for 值 in os.getloadavg()]
    except Exception:
        pass
    try:
        读数 = subprocess.run(["ps", "-A", "-o", "%cpu="], capture_output=True, text=True, timeout=5)
        占用和 = sum(float(文本行) for 文本行 in (读数.stdout or "").split() if 文本行)
        核数 = max(1, os.cpu_count() or 1)
        线索块["CPU空闲率"] = "%.1f%%" % max(0.0, 100.0 - 占用和 / 核数)
    except Exception:
        pass
    try:
        读数 = subprocess.run(["ps", "-A", "-o", "command="], capture_output=True, text=True, timeout=5)
        入口词表 = ("闸0.py", "闸零.py", "一键验证.py", "扫实现.py")
        线索块["并发闸进程数"] = sum(
            1 for 文本行 in (读数.stdout or "").splitlines()
            if any(入口词 in 文本行 for 入口词 in 入口词表)
        )
    except Exception:
        pass
    return 线索块


def 记录墙钟债务(墙钟毫秒: int, 阈值毫秒: int, 阶段说明: str, 命令: str, 修法: str = "",
            债务原因: str = 原因_超效率目标) -> str:
    """记一条墙钟债务 ⇒ 落点路径（记不上回空串）。**不抛异常、不阻塞**。

    `债务原因` 区分「慢」（`原因_超效率目标`）与「护栏掐了」（`原因_失控护栏`）——
    那两件事的处置完全不同（前者查并发 / 分片 / 缓存，后者先查是不是真挂死）。
    """
    日志目录 = 台账目录()
    if 日志目录 is None:
        return ""
    债务记录 = {
        "格式版本": 记录格式版本,
        "时刻": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "命令": 命令 or "（未记名）",
        "阶段说明": 阶段说明 or "",
        "墙钟毫秒": int(墙钟毫秒),
        "阈值毫秒": int(阈值毫秒),
        "原因": 债务原因,
        "线索块": 机器线索(),
        "修法": 修法 or "",
    }
    try:
        日志目录.mkdir(parents=True, exist_ok=True)
        with (日志目录 / 记录件名).open("a", encoding="utf-8") as 记录件:
            记录件.write(json.dumps(债务记录, ensure_ascii=False) + "\n")
    except Exception:
        return ""
    return str(日志目录 / 记录件名)


def 读债务(读取条数: int = 20) -> list:
    """⇒ 最近 `读取条数` 条债务（**倒序** · 最新的在前）；记录件不在 ⇒ 空表。"""
    日志目录 = 台账目录()
    if 日志目录 is None:
        return []
    件路径 = 日志目录 / 记录件名
    if not 件路径.is_file():
        return []
    记录表 = []
    try:
        for 文本行 in 件路径.read_text(encoding="utf-8").splitlines():
            文本行 = 文本行.strip()
            if not 文本行:
                continue
            try:
                记录表.append(json.loads(文本行))
            except ValueError:
                continue
    except OSError:
        return []
    return list(reversed(记录表))[: 读取条数]


def 汇总债务() -> list:
    """按「原因 + 命令 + 阶段」聚合 ⇒ `[(键, 条数, 最大墙钟毫秒, 最近一次时刻)]`（条数多的在前）。"""
    聚合桶 = {}
    for 债务记录 in 读债务(读取条数=100000):
        聚合键 = (债务记录.get("原因", ""), 债务记录.get("命令", ""), 债务记录.get("阶段说明", ""))
        已有条数, 已有最大, 已有最近 = 聚合桶.get(聚合键, (0, 0, ""))
        聚合桶[聚合键] = (已有条数 + 1,
                  max(已有最大, int(债务记录.get("墙钟毫秒") or 0)),
                  max(已有最近, 债务记录.get("时刻", "")))
    return sorted(
        ((聚合键, 值[0], 值[1], 值[2]) for 聚合键, 值 in 聚合桶.items()),
        key=lambda 聚合条目: (-聚合条目[1], -聚合条目[2]),
    )


def 记录件路径() -> str:
    """⇒ 记录件的绝对路径（给查询口与报告打印用）；运行数据根解析不出 ⇒ 空串。"""
    日志目录 = 台账目录()
    return "" if 日志目录 is None else str(日志目录 / 记录件名)


def 打印债务(读取条数: int = 20) -> int:
    """只读查询口的**呈现**：打最近若干条 + 聚合 ⇒ 退出码（0 恒；读不到也 0，那不是失败）。

    形如收口方能查的那种记录：`时刻 · 命令/阶段 · 墙钟毫秒 · 原因 · 线索（CPU / 负载 / 并发闸数）`。
    """
    路径文本 = 记录件路径()
    print("墙钟债务记录件：%s" % (路径文本 or "（运行数据根解析不出 ⇒ 未记）"))
    记录表 = 读债务(读取条数)
    if not 记录表:
        print("（还没有记录 —— 没有任何命令越过效率目标）")
        return 0
    print("最近 %d 条（最新在前）：" % len(记录表))
    for 债务记录 in 记录表:
        线索块 = 债务记录.get("线索块") or {}
        print("  %s ｜ %s ｜ %s ｜ 墙钟 %s ms > 阈值 %s ms ｜ CPU空闲 %s · 负载 %s · 并发闸进程 %s"
              % (债务记录.get("时刻", "?"), 债务记录.get("命令", "?"),
                 债务记录.get("阶段说明", "") or "（无阶段）", 债务记录.get("墙钟毫秒"),
                 债务记录.get("阈值毫秒"), 线索块.get("CPU空闲率"), 线索块.get("负载"),
                 线索块.get("并发闸进程数")))
        if 债务记录.get("原因"):
            print("      原因：%s" % 债务记录["原因"])
        if 债务记录.get("修法"):
            print("      提速方向：%s" % 债务记录["修法"])
    print("")
    print("按「原因 · 命令 · 阶段」聚合（条数多的在前）：")
    for 聚合键, 聚合条数, 最大墙钟, 最近时刻 in 汇总债务():
        print("  %3d 条 ｜ 最慢 %6d ms ｜ 最近 %s ｜ %s ｜ %s ｜ %s"
              % (聚合条数, 最大墙钟, 最近时刻, 聚合键[0], 聚合键[1], 聚合键[2] or "（无阶段）"))
    return 0
