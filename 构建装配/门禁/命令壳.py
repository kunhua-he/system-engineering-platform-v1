# -*- coding: utf-8 -*-
"""命令壳 —— 每条命令的「壳自量自门禁」（`2026-09-27_所有运行五秒硬顶.md` §六.1 的落法）。

**为什么是「壳自量」而不是「一条中央判据读各命令的回执」**（§六.1 给了两条实测理由）：
  · 回执不在 ⇒ 中央判据只能报「未判」，而闸1 的退出码语义是「未判即 1」⇒ 门禁**永久变红**
    （新克隆、`git clean` 之后必然如此）；
  · 回执里记的常是**内部耗时**（例：案例回执的 `耗时微秒` 不含 `cargo` 启动那一段）
    ⇒ 拿它冒充墙钟就是**假读数**。
⇒ 一条命令的**完整墙钟只有它自身的壳能量**。所以每条命令的入口：① 在**导入业务包之前**起表
（`起 = time.monotonic()` 写在入口的**第一行可执行语句** —— 比 import 本模块还早，同
`开发工具/易语言取证/声明记录区反解.py` 的先例）
② 跑完调 `自门禁` ③ 超阈值 ⇒ 打印红 + 非 0。

**量不到的边界（如实登记）**：壳在入口的第一行可执行语句起表，故量不到「解释器启动」与
「进程退出」那两段。阈值取「硬顶 − 该命令的尾巴余量」（裁决 §二 第四轮），
这样「完整命令 ≤ 硬顶」这句声明才**为真**。余量由**该命令自身**给（见 `硬顶硬顶常量.py` 的说明）。

**反向样本（证明门禁不空转）**：`人为慢环境变量` 给毫秒数 ⇒ 算完之后**真睡**那么久
⇒ 门禁必须报红。它是环境变量而不是命令行开关：它只服务于这条自证，不进公开用法面。
变量名**必须 ASCII**（`sh`/`zsh` 不认非 ASCII 变量名，实测过 —— 同 `进入.sh` 顶部那条理由）。
"""

from __future__ import annotations

import os
import sys
import time

from .硬顶常量 import 效率目标毫秒

人为慢环境变量 = "V1_CMD_SLOW_MS"


def 注入人为慢() -> int:
    """反向样本注入：环境变量给毫秒数，就在算完之后**真睡**那么久（默认 0 = 不注入）。"""
    待处理值 = os.environ.get(人为慢环境变量)
    if not 待处理值:
        return 0
    try:
        毫秒数 = float(待处理值)
    except ValueError:
        return 0
    if 毫秒数 <= 0:
        return 0
    time.sleep(毫秒数 / 1000.0)
    return int(毫秒数)


def 自门禁(区间起点: float, 错误码: int, 尾巴余量毫秒: int, 修法: str, 输出流=None) -> int:
    """量墙钟 → **照实打出读数** → **原样返回**命令本体算出来的码。

    ★ **2026-10-13 用户当场裁定（口径再变，覆盖 2026-10-09 的「超 5 秒记债务」）**：原话
    「之前是改过了。超过就超过了，记录也不记录了」「就是没有强制 5 秒这个要求了，也不报错了」
    ⇒ **5 秒这一维整条撤掉**：不判红、**也不记债务**。本函数只剩一件事 —— 把读数打出来
    （读数照实，谁都能看）。判决一律由命令本体给：`错误码` 是什么就是什么。

    ★ 「原样返回」是硬要求（原实现超顶返回 1 判红；2026-10-09 去硬顶，2026-10-13 连记录也去掉）。
    形参 `尾巴余量毫秒` / `修法` **保留**（调用面不改，多处入口都在传）—— 它们现在只作说明位，
    不再参与任何判定或记录。
    """
    输出流 = 输出流 or sys.stderr
    注入 = 注入人为慢()
    墙钟毫秒 = int((time.monotonic() - 区间起点) * 1000)
    print("─" * 78, file=输出流)
    print("命令墙钟（壳自量）%d ms · 人为慢注入 %d ms（2026-10-13 口径：墙钟只报读数 —— 不判红、不记债务）"
          % (墙钟毫秒, 注入), file=输出流)
    return 错误码


def 报告环境步(区间起点: float, 错误码: int, 说明: str, 输出流=None) -> int:
    """**环境步**的墙钟：照实报，但**不判顶** —— §四 明写「唯一不算命令的只有工具链一次性冷构建」。

    **为什么要有这个函数，而不是让环境步偷偷不调门禁**：豁免必须是**具名的、写在一处的**。
    让某个入口自身写 `if "--预构建" in 参数: 不调门禁`，豁免就散进了各入口 ——
    下一个人读那条入口时会以为「这里漏了门禁」，而真相是「这里按 §四 豁免」。
    ⇒ 豁免的**口径与理由**留在本函数里，各入口只调它；墙钟照实打出来（读数不丢）。

    只给**显式指名的环境步**用（例：`构建制品.py --预构建` 编底座与扩展的 release 产物）。
    **命令本体（装配 / 检查 / 调用）一律仍走 `自门禁`** —— 别拿本函数给命令路开后门。
    """
    输出流 = 输出流 or sys.stderr
    注入 = 注入人为慢()
    墙钟毫秒 = int((time.monotonic() - 区间起点) * 1000)
    print("─" * 78, file=输出流)
    print("环境步墙钟（壳自量）%d ms · 效率目标 %d ms **不记**（§四：一次性冷构建）· 人为慢注入 %d ms"
          % (墙钟毫秒, 效率目标毫秒, 注入), file=输出流)
    print("  %s" % 说明, file=输出流)
    return 错误码
