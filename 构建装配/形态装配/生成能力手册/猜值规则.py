# -*- coding: utf-8 -*-
"""猜值规则 —— 参数名关键词 → 能通过校验的真值，以及按类型定形状的 `猜值`。

为什么先名字后类型：反了就会给出「形状不符」的值（类型说整数、名字说路径）。
"""

# 参数名关键词 → 能通过校验的真值。顺序有意义：先具体的，后笼统的。
猜值规则 = [
    (('路径', '文件', '目录'), '/tmp/提交50.log'),
    (('网址', '链接', '地址'), 'https://example.com/a?b=1'),
    (('日期',), '2026-11-05'),
    (('时间',), '2026-11-05T10:00:00+08:00'),
    (('编码',), 'utf-8'),
    (('正则', '模式'), r'\d+'),
    (('JSON',), '{"名称": "示例", "数值": 1}'),
    (('分隔',), ','),
    (('表头',), 'a,b,c'),
    (('前缀',), '货号-'),
    (('查找', '搜索', '查询', '关键词'), '示例'),
    (('端口',), 8080),
    (('毫秒',), 1000),
    (('秒',), 5),
    (('维度', '条数', '个数', '数量', '小数位', '页码', '页数', '次数', '上限'), 1),
    (('文本', '内容', '字符串', '源', '原', '串'), '示例内容'),
]


def 猜值(参数项):
    """猜一个能通过校验的值。先按类型定形状，再按名字挑内容 —— 顺序反了就会「输入形状不符」。"""
    参数名 = 参数项.get('名称') or ''
    类型 = 参数项.get('类型标签', 0)
    默认 = 参数项.get('默认值') or {}
    if 默认.get('类型标签'):
        return 默认.get('值', 默认.get('逻辑', ''))

    # 名字先决定「给什么内容」
    候选值 = None
    for 词们, 值 in 猜值规则:
        if any(关键词 in 参数名 for 关键词 in 词们):
            候选值 = 值
            break

    # 类型决定「什么形状」，名字给的内容形状不对就退回该类型的默认值
    if 类型 == 1:
        return 候选值 if isinstance(候选值, int) and not isinstance(候选值, bool) else 1
    if 类型 == 2:
        if isinstance(候选值, (int, float)) and not isinstance(候选值, bool):
            return float(候选值)
        return 1.2345
    if 类型 == 3:
        return bool(候选值) if isinstance(候选值, bool) else False
    if 类型 in (6, 7):
        return 1
    if 类型 == 100:
        return {'类型标签': 100, '值': []}
    if 类型 == 101:
        return {'类型标签': 101, '值': {}}
    # 文本型
    if isinstance(候选值, str):
        return 候选值
    return '示例'
