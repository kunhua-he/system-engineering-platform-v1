def 提返回字段(库目录):
    """从扩展源码提返回字段名与类型。

    只认 `X字段("名", …)` 这一种写法（数值计算库那样）。别的库返回形态本就不同
    —— 有结构体的、回纯文本的、回 JSON 文本的、回句柄的 —— 没有通用规律，
    提不到就返回空，交给真实样例或声明里的返回描述。
    """
    源目录 = 库目录 / 'src'
    if not 源目录.is_dir():
        return {}
    源码全文 = ''
    for 源件 in sorted(源目录.glob('*.rs')):
        源码全文 += 源件.read_text(encoding='utf-8')

    名到号 = {匹配项.group(1): int(匹配项.group(2))
              for 匹配项 in re.finditer(r'pub const (\w+): u32 = (\d+);', 源码全文)}
    映射 = {匹配项.group(1): 匹配项.group(2) for 匹配项 in
            re.finditer(r'本表\[命令表内位\(能力号::(\w+)\)\]\s*=\s*(\w+);', 源码全文)}

    字段表 = {}
    for 能力名, 函数名 in 映射.items():
        编号 = 名到号.get(能力名)
        if 编号 is None:
            continue
        函数体 = 取函数体(源码全文, 函数名)
        字段 = [(匹配项.group(2), 字段构造名[匹配项.group(1)])
                for 匹配项 in re.finditer(r'(%s)\("([^"]+)"' % '|'.join(字段构造名), 函数体)]
        if 字段:
            字段表[编号] = 字段
    return 字段表


def 取函数体(源码全文, 函数名):
    """按大括号配对取函数体。签名里有 extern "C-unwind"，只认 fn 名字。"""
    匹配项 = re.search(r'fn %s\s*\(' % re.escape(函数名), 源码全文)
    if not 匹配项:
        return ''
    体起点 = 源码全文.find('{', 匹配项.end())
    if 体起点 < 0:
        return ''
    配对深度 = 0
    for 扫描位 in range(体起点, len(源码全文)):
        if 源码全文[扫描位] == '{':
            配对深度 += 1
        elif 源码全文[扫描位] == '}':
            配对深度 -= 1
            if 配对深度 == 0:
                return 源码全文[体起点:扫描位 + 1]
    return ''
