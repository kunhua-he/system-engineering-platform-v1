def 采样(编号, 模板):
    """真发一次请求。失败就返回 None —— 文档里不放错误样例。"""
    体 = json.dumps({'编号': 编号, '命名值': 模板}, ensure_ascii=False).encode()
    try:
        请求 = urllib.request.Request(接口, 体, {'Content-Type': 'application/json'})
        with urllib.request.urlopen(请求, timeout=15) as 回:
            数据 = json.loads(回.read())
    except Exception as 错:
        采样失败.append('%d %s' % (编号, type(错).__name__))
        return None
    if not 数据.get('成功'):
        采样失败.append('%d %s' % (编号, (数据.get('错误') or {}).get('名称', '')))
        return None
    值 = 剥(数据.get('值'))
    if isinstance(值, list) and len(值) == 1:
        值 = 值[0]
    return 值


