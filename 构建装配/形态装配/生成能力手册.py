"""按易语言 F1 帮助的格式，从能力声明 json 生成扩展的用法说明。

为什么用生成而不是手写：参数名、类型、默认值都是声明里已有的东西，
抄一遍就是第二事实源，改一处忘一处。

每段五栏固定：
    调用格式：〈返回类型〉 编号 名称 （类型 参数名，…）
    说明：一句话讲清干什么、返回什么
    参数说明：逐条，带类型与默认值
    返回：…
    备注：只写真会踩的坑

用法：python3 构建装配/形态装配/生成能力手册.py
产出：扩展根目录/原子支持库/大语言模型支持库/用法说明/使用说明.md
"""

import json
import sys
from pathlib import Path

库根 = Path(__file__).resolve().parents[2]
声明目录 = 库根 / '扩展根目录/原子支持库/大语言模型支持库/能力声明'
产出 = 库根 / '扩展根目录/原子支持库/大语言模型支持库/用法说明/使用说明.md'

类型名 = {
    0: '空', 1: '整数', 2: '双精度', 3: '逻辑型', 4: '文本',
    5: '字节集', 6: '句柄', 7: '任务句柄', 100: '列表', 101: '对象', 103: '生成结构',
}

# 能力段装不下的硬约束
边界 = [
    '连接与流内停顿各五秒上限；模型整体生成时长不受这五秒限制，但上游若超过五秒不吐任何字节会明确失败',
    '句柄至 64 个、任务至 64 个，超出返回 2506 资源受限',
    '端点由调用方配置，属运维指定的服务地址，不套用面向任意网址的出站策略；不继承环境代理',
    '任务与句柄只在当前扩展实例内有效，不承诺跨重启；卸载先拒新任务并置取消，线程未退完报延迟释放',
    '参数必须全传：没有真默认值的一个都不能省。复合参数（列表/对象）要逐层带 {"类型标签": N, "值": …} 标签，标量给裸值',
]

# 每个能力真正会踩的坑。没踩过的不写 —— 凑数的备注比没有更糟。
备注表 = {
    2519: [
        '模型没起会自动拉起，起了直接复用，不重起进程',
        '模型在内存里约 1 秒返回，冷启动约 3 秒',
        '同样的前缀第二次快四成（实测 0.67 → 0.44 秒）：长期不变的内容放最前面，历史只追加不改写',
        '等不到就回任务句柄，用 2503 接着取（只有超长生成会遇到）',
        '没人用 15 分钟自动退出内存，下次要用自动回来',
    ],
    2512: [
        '拉起立刻返回句柄，不等载入。状态用 2514 查',
        '看图模型必须带 --mmproj 视觉投影层，少了上游只报「上游失败」，看不出缺什么。2519 已按模型名自动推',
        '闲置超时秒不建议传 0（永不退），要常驻给长值如 3600',
        '拉起前会算内存预算，不够报 2506 资源受限',
    ],
    2514: [
        '判「已载入」必须走真就绪探测，不能只看端口通 —— llama-server 载入期间就在监听，但接口回 503',
        '只有调 2516 申请许可才算真正使用，查本能力不刷新闲置计时',
        '闲置超时秒为 0 时，「距自动退出秒」这个字段不出现（不是 null）',
    ],
    2515: ['单次等待封顶 800 毫秒。要等更久就循环调，2519 内部就是这么循环的'],
    2513: [
        '幂等：句柄本来就不在也回真',
        '强制=真是不论退没退一律摘除条目，卡死时的逃生口，代价是可能留孤儿进程',
    ],
    2516: ['同模型内排队（共享显存与 KV 缓存），不同模型并行（各独立进程）'],
    2517: ['用完必须还，否则租约到期前这个模型对别人是锁住的'],
    2507: ['回的是连接句柄（字段只有 句柄/地址/模型），不是服务句柄'],
    2502: ['提交后立刻返回任务句柄，结果用 2503 取'],
    2503: ['资源在途为真时读到的内容不完整，要继续等'],
}


def 一段(声明):
    编号 = 声明['编号']
    短名 = (声明.get('名称') or '').split('_')[-1]
    返回 = 类型名.get(声明.get('返回类型', 0), '未知')
    参数们 = 声明.get('参数表') or []
    星标 = ' ★日常只用这个' if 编号 == 2519 else ''

    签名 = '，'.join(
        '%s %s' % (类型名.get(参.get('类型标签', 0), '未知'), 参['名称']) for 参 in 参数们
    )
    行 = ['## %d %s%s' % (编号, 短名, 星标), '']
    行.append('调用格式：〈%s〉 %d %s （%s）' % (返回, 编号, 短名, 签名 or '无参数'))
    行.append('')
    行.append('说明：%s' % (声明.get('说明') or '').rstrip('。'))
    行.append('')

    if 参数们:
        行.append('参数说明：')
        for 序, 参 in enumerate(参数们, 1):
            类型 = 类型名.get(参.get('类型标签', 0), '未知')
            说 = (参.get('说明') or '').rstrip('。')
            if 说 == 参['名称']:
                说 = ''
            默认 = 参.get('默认值') or {}
            if 默认.get('类型标签') and 默认['类型标签'] != 0 and '默认' not in 说:
                说 += '。默认 %s' % 默认.get('值', 默认.get('逻辑', ''))
            行.append('%d. %s - %s - %s' % (序, 参['名称'], 类型, 说) if 说
                     else '%d. %s - %s' % (序, 参['名称'], 类型))
        行.append('')

    行.append('返回：%s' % 返回)
    行.append('')

    备注 = [一条 for 一条 in (备注表.get(编号) or []) if 一条.strip()]
    if 备注:
        行.append('备注：')
        for 一条 in 备注:
            行.append('· %s' % 一条)
        行.append('')

    return 行


def 主():
    文件们 = sorted(声明目录.glob('*.json'), key=lambda 路径: int(路径.stem))
    if not 文件们:
        print('能力声明目录是空的：%s' % 声明目录)
        return 1

    按号 = {json.loads(f.read_text(encoding='utf-8'))['编号']: f for f in 文件们}

    行 = [
        '# 大语言模型支持库',
        '',
        '做 chat_completions / embeddings / rerank 的连接登记与生成任务，是拉起模型进程的唯一入口；'
        '不做协议翻译、不重试、不落盘。',
        '',
        '每个能力一段，五栏固定：调用格式 · 说明 · 参数说明 · 返回 · 备注。'
        '**日常只用 2519 一次对话**，其余是它内部拆开的零件。',
        '',
        '---',
        '',
    ]

    # 2519 是门面，排最前；其余按编号
    if 2519 in 按号:
        行 += 一段(json.loads(按号[2519].read_text(encoding='utf-8')))
        行.append('---')
        行.append('')

    for 编号 in sorted(按号):
        if 编号 == 2519:
            continue
        行 += 一段(json.loads(按号[编号].read_text(encoding='utf-8')))
        行.append('---')
        行.append('')

    行.append('## 边界')
    行.append('')
    for 一条 in 边界:
        行.append('- %s' % 一条)
    行.append('')

    产出.parent.mkdir(parents=True, exist_ok=True)
    产出.write_text('\n'.join(行).rstrip() + '\n', encoding='utf-8')
    print('已生成 %s（%d 个能力 / %d 行）' % (产出, len(文件们), len(行)))
    return 0


if __name__ == '__main__':
    sys.exit(主())
