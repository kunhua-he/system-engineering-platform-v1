def 提返回字段(库目录):
    """从扩展源码提返回字段名与类型。

    只认 `X字段("名", …)` 这一种写法（数值计算库那样）。别的库返回形态本就不同
    —— 有结构体的、回纯文本的、回 JSON 文本的、回句柄的 —— 没有通用规律，
    提不到就返回空，交给真实样例或声明里的返回描述。
    """
    源目录 = 库目录 / 'src'
    if not 源目录.is_dir():
        return {}
    源 = ''
    for f in sorted(源目录.glob('*.rs')):
        源 += f.read_text(encoding='utf-8')

    名到号 = {m.group(1): int(m.group(2))
              for m in re.finditer(r'pub const (\w+): u32 = (\d+);', 源)}
    映射 = {m.group(1): m.group(2) for m in
            re.finditer(r'本表\[命令表内位\(能力号::(\w+)\)\]\s*=\s*(\w+);', 源)}

    得 = {}
    for 能力名, 函数名 in 映射.items():
        编号 = 名到号.get(能力名)
        if 编号 is None:
            continue
        体 = 取函数体(源, 函数名)
        字段 = [(m.group(2), 字段构造名[m.group(1)])
                for m in re.finditer(r'(%s)\("([^"]+)"' % '|'.join(字段构造名), 体)]
        if 字段:
            得[编号] = 字段
    return 得


def 取函数体(源, 函数名):
    """按大括号配对取函数体。签名里有 extern "C-unwind"，只认 fn 名字。"""
    m = re.search(r'fn %s\s*\(' % re.escape(函数名), 源)
    if not m:
        return ''
    起 = 源.find('{', m.end())
    if 起 < 0:
        return ''
    深 = 0
    for i in range(起, len(源)):
        if 源[i] == '{':
            深 += 1
        elif 源[i] == '}':
            深 -= 1
            if 深 == 0:
                return 源[起:i + 1]
    return ''


def 提取返回描述(说明):
    """声明里常写「返回 字段/结构」，把这句挖出来单独放返回栏。"""
    位 = 说明.find('返回')
    if 位 < 0:
        return ''
    段 = 说明[位:]
    for 止 in ('；', '。'):
        切 = 段.find(止)
        if 切 > 0:
            段 = 段[:切]
            break
    return 段.strip()[:160]


