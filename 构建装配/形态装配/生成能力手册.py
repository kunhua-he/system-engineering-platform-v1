def 一段(声明):
    编号 = 声明['编号']
    短名 = (声明.get('名称') or '').split('_')[-1]
    返回 = 类型名.get(声明.get('返回类型', 0), '未知')
    参数们 = 声明.get('参数表') or []

    签名 = '，'.join(
        '%s %s' % (类型名.get(参.get('类型标签', 0), '未知'), 参['名称']) for 参 in 参数们
    )
    行 = ['## %d · %s' % (编号, 短名), '']
    行.append('调用格式：〈%s〉 %d %s （%s）' % (返回, 编号, 短名, 签名 or '无参数'))
    行.append('')
    行.append('说明：%s' % (声明.get('说明') or '').rstrip('。'))
    行.append('')

    if 参数们:
        行.append('参数说明：')
        for 序, 参 in enumerate(参数们, 1):
            类型 = 类型名.get(参.get('类型标签', 0), '未知')
            说 = (参.get('说明') or '').rstrip('。')
            # 声明里说明就写成参数名本身（同义反复）时不重复，只给类型
            if 说 == 参['名称'] or 说.startswith(参['名称'] + '\0'):
                说 = ''
            默认 = 参.get('默认值') or {}
            # 空槽（类型 0）就是没有真默认值，必传
            if 默认.get('类型标签') and 默认['类型标签'] != 0 and '默认' not in 说:
                说 += '。默认 %s' % 默认.get('值', 默认.get('逻辑', ''))
            行.append('%d. %s - %s - %s' % (序, 参['名称'], 类型, 说) if 说
                     else '%d. %s - %s' % (序, 参['名称'], 类型))
        行.append('')

    行.append('返回：%s' % 返回)
    行.append('')

    备注 = [一条 for 一条 in (备注表.get(编号) or []) if 一条.strip()]
    if 备注:
        行.append('备注：')
        for 一条 in 备注:
            行.append('· %s' % 一条)
        行.append('')

    return 行


def 抽保留章节():
    """从现有使用说明里抽出能力段覆盖不到的章节（边界 / 并发育 / 生命周期口径）。"""
    if not 产出.is_file():
        return []
    原文 = 产出.read_text(encoding='utf-8').split('\n')
    段们 = []
    在段 = False
    当前 = []
    for 行 in 原文:
        if 行.startswith('## '):
            在段 = 行.strip() in 保留章节
            if 在段:
                当前 = [行]
            elif 当前:
                段们.append(当前)
                当前 = []
        elif 在段:
            当前.append(行)
    if 当前:
        段们.append(当前)
    return 段们


