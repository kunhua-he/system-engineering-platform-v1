def 猜值(参):
    """猜一个能通过校验的值。先按类型定形状，再按名字挑内容 —— 顺序反了就会「输入形状不符」。"""
    名 = 参.get('名称') or ''
    类型 = 参.get('类型标签', 0)
    默认 = 参.get('默认值') or {}
    if 默认.get('类型标签'):
        return 默认.get('值', 默认.get('逻辑', ''))

    # 名字先决定「给什么内容」
    候选 = None
    for 词们, 值 in 猜值规则:
        if any(词 in 名 for 词 in 词们):
            候选 = 值
            break

    # 类型决定「什么形状」，名字给的内容形状不对就退回该类型的默认值
    if 类型 == 1:
        return 候选 if isinstance(候选, int) and not isinstance(候选, bool) else 1
    if 类型 == 2:
        if isinstance(候选, (int, float)) and not isinstance(候选, bool):
            return float(候选)
        return 1.2345
    if 类型 == 3:
        return bool(候选) if isinstance(候选, bool) else False
    if 类型 in (6, 7):
        return 1
    if 类型 == 100:
        return {'类型标签': 100, '值': []}
    if 类型 == 101:
        return {'类型标签': 101, '值': {}}
    # 文本型
    if isinstance(候选, str):
        return 候选
    return '示例'


