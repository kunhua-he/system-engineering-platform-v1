def 剥(x):
    """去掉类型标签外壳，把 JSON 文本解开。"""
    if isinstance(x, list):
        return [剥(每) for 每 in x]
    if isinstance(x, dict) and set(x) == {'类型标签', '值'}:
        内 = 剥(x['值'])
        if x['类型标签'] == 4 and isinstance(内, str) and 内.strip().startswith(('{', '[')):
            try:
                return json.loads(内)
            except Exception:
                return 内
        if x['类型标签'] == 3:
            return bool(内)
        return 内
    if isinstance(x, dict):
        return {k: 剥(v) for k, v in x.items()}
    return x


