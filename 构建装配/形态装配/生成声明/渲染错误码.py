# -*- coding: utf-8 -*-
"""渲染错误码 —— 产物「三 错误码」小节（错误码常量 · 错误码表 · 错误码信息表）。"""

from .小工具 import rust串


def 渲染错误码(加, 根, 错误码表, 平台):
    # ── 三 错误码 ──────────────────────────────────────────────────────
    加("// ════════════════════════════════════════════════════════════════════════════")
    加("// 三 错误码（源：%s/*.json，按 码 升序；常量名与值都取自「码」）" % 根.错误码表)
    加("// ════════════════════════════════════════════════════════════════════════════")
    加("")
    已登记段位 = 平台["错误段位表"]
    上段位 = None
    for 项 in 错误码表:
        if 项["段位"] != 上段位:
            if 上段位 is not None:
                加("")
            上段位 = 项["段位"]
            标记 = "（已登记段位）" if 上段位 in 已登记段位 else "（**未登记**：不在 平台声明.json 的错误段位表 里）"
            加("// ── 段位 %d：码 %d..%d%s ──" % (上段位, 上段位 * 1000, 上段位 * 1000 + 999, 标记))
        加("/// 码 %d · %s" % (项["码"], 项["名称"]))
        加("/// %s" % " ".join(项["说明"].split()))
        加(
            "/// 段位 %d · 可重试 %s · 可自愈 %s · 需人工 %s"
            % (
                项["段位"],
                "是" if 项["可重试"] else "否",
                "是" if 项["可自愈"] else "否",
                "是" if 项["需人工"] else "否",
            )
        )
        加("pub const 错误码_%d: u32 = %d;" % (项["码"], 项["码"]))
    加("")
    if 错误码表:
        加("/// 已登记的错误码（源：%s/*.json，按 码 升序）。" % 根.错误码表)
        加("pub const 错误码表: [u32; %d] = [" % len(错误码表))
        宽 = max(len("%d," % 项["码"]) for 项 in 错误码表)
        for 项 in 错误码表:
            加("    %-*s // 段位 %d · %s" % (宽, "%d," % 项["码"], 项["段位"], 项["名称"]))
        加("];")
    else:
        加("/// 已登记的错误码（源：%s/*.json）——当前为空。" % 根.错误码表)
        加("pub const 错误码表: [u32; 0] = [];")
    加("")

    # 错误码**内容**表（`错误码信息`）：宪法级判据「失败可编程处理」的落点。
    for 项 in 错误码表:
        加("/// %s · 码 %d · 名称「%s」" % (项["相对路径"], 项["码"], 项["名称"]))
        加("const 错误码名_%s: &[u8] = %s.as_bytes();" % (项["词干"], rust串(项["名称"] + "\0")))
        加("const 错误码说明_%s: &[u8] = %s.as_bytes();" % (项["词干"], rust串(项["说明"] + "\0")))
    加("")
    加("/// 错误码信息 表（源：%s/*.json，共 %d 项，按 码 升序）。" % (根.错误码表, len(错误码表)))
    加("/// **宪法级判据的落点**：调用方拿到 `码` 之后能查到 `可重试 · 可自愈 · 需人工`，")
    加("/// 否则那三项只是注释、到不了运行期。`段位` 是冗余登记项（可从 `码` 导出），")
    加("/// 故意写出来由验证面交叉比对抓错。三项业务判断用 0/1（跨边界宽度要显式）。")
    if 错误码表:
        加("pub const 错误码信息表: [v1_contract::错误码信息; %d] = [" % len(错误码表))
        for 项 in 错误码表:
            加("    // %s" % 项["相对路径"])
            加("    v1_contract::错误码信息 {")
            加("        码: %d," % 项["码"])
            加("        段位: %d," % 项["段位"])
            加("        名称: 串(错误码名_%s)," % 项["词干"])
            加("        说明: 串(错误码说明_%s)," % 项["词干"])
            加("        可重试: %d," % (1 if 项["可重试"] else 0))
            加("        可自愈: %d," % (1 if 项["可自愈"] else 0))
            加("        需人工: %d," % (1 if 项["需人工"] else 0))
            加("        保留: 0,")
            加("    },")
        加("];")
    else:
        加("pub const 错误码信息表: [v1_contract::错误码信息; 0] = [];")
    加("/// `平台信息.错误码表` 直接可用：项数 + 项表。")
    加("pub const fn 错误码信息表段() -> v1_contract::表段<v1_contract::错误码信息> {")
    加("    v1_contract::表段::新(错误码信息表.as_ptr(), %d)" % len(错误码表))
    加("}")
    加("")
