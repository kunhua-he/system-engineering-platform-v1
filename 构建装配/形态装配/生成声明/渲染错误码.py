# -*- coding: utf-8 -*-
"""渲染错误码 —— 产物「三 错误码」小节，**按表拆成三件**（`开发规范.md` §六 单源 ≤400 行）。

为什么拆成三件：本小节是最大的一节（38 条码 × 三条列表），单件远超 400 行。拆法按**结构**：
  · `错误码数据.rs`      —— 逐码常量 + `错误码表` + 名/说明常量（`错误码信息表` 的用料）
  · `错误码信息数据.rs`  —— `错误码信息表` 的**前半项** + 表 + 表段
  · `错误码信息续数据.rs` —— `错误码信息表` 的**后半项**（`错误码信息表` 仍是一张表，项经
                            `pub(super) const` 引用过来 —— 公开面 `错误码信息表` 逐字不变）
"""

from .小工具 import 转字符串字面量

# `错误码信息表` 的项拆两件的分界：前半 = ceil(N/2)。两件都远低于 400 行。
def _前半数(总数):
    return (总数 + 1) // 2


def _渲染逐码(渲染器, 根目录, 错误码表, 平台):
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 三 错误码（源：%s/*.json，按 码 升序；常量名与值都取自「码」）" % 根目录.错误码表)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    已登记段位 = 平台["错误段位表"]
    上段位 = None
    for 一项 in 错误码表:
        if 一项["段位"] != 上段位:
            if 上段位 is not None:
                渲染器("")
            上段位 = 一项["段位"]
            标记 = "（已登记段位）" if 上段位 in 已登记段位 else "（**未登记**：不在 平台声明.json 的错误段位表 里）"
            渲染器("// ── 段位 %d：码 %d..%d%s ──" % (上段位, 上段位 * 1000, 上段位 * 1000 + 999, 标记))
        渲染器("/// 码 %d · %s" % (一项["码"], 一项["名称"]))
        渲染器("/// %s" % " ".join(一项["说明"].split()))
        渲染器(
            "/// 段位 %d · 可重试 %s · 可自愈 %s · 需人工 %s"
            % (
                一项["段位"],
                "是" if 一项["可重试"] else "否",
                "是" if 一项["可自愈"] else "否",
                "是" if 一项["需人工"] else "否",
            )
        )
        渲染器(
            "pub const 错误码_%d: v1_contract::错误码 = v1_contract::错误码::新建(%d);"
            % (一项["码"], 一项["码"])
        )
    渲染器("")
    if 错误码表:
        渲染器("/// 已登记的错误码（源：%s/*.json，按 码 升序）。" % 根目录.错误码表)
        渲染器("pub const 错误码表: [u32; %d] = [" % len(错误码表))
        宽度 = max(len("%d," % 项["码"]) for 项 in 错误码表)
        for 一项 in 错误码表:
            渲染器("    %-*s // 段位 %d · %s" % (宽度, "%d," % 一项["码"], 一项["段位"], 一项["名称"]))
        渲染器("];")
    else:
        渲染器("/// 已登记的错误码（源：%s/*.json）——当前为空。" % 根目录.错误码表)
        渲染器("pub const 错误码表: [u32; 0] = [];")
    渲染器("")
    # 名/说明常量：`错误码信息表`（在 错误码信息数据/续数据 两件里）引用它们 ⇒ `pub(super)`。
    渲染器("// `错误码信息表` 的用料：名 / 说明（NUL 结尾）。子件 `use super::错误码数据::{…}` 取用。")
    for 一项 in 错误码表:
        渲染器("/// %s · 码 %d · 名称「%s」" % (一项["相对路径"], 一项["码"], 一项["名称"]))
        渲染器("pub(super) const 错误码名_%s: &[u8] = %s.as_bytes();" % (一项["词干"], 转字符串字面量(一项["名称"] + "\0")))
        渲染器("pub(super) const 错误码说明_%s: &[u8] = %s.as_bytes();" % (一项["词干"], 转字符串字面量(一项["说明"] + "\0")))
    渲染器("")


def _渲染信息项(渲染器, 项表):
    """一组 `错误码信息` 项 → `pub(super) const 错误码信息_<词干>`（供 `错误码信息表` 引用）。"""
    for 一项 in 项表:
        渲染器("/// %s · 码 %d · 名称「%s」" % (一项["相对路径"], 一项["码"], 一项["名称"]))
        渲染器("pub(super) const 错误码信息_%s: v1_contract::错误码信息 = v1_contract::错误码信息 {" % 一项["词干"])
        渲染器("    码: %d," % 一项["码"])
        渲染器("    段位: %d," % 一项["段位"])
        渲染器("    名称: 取字节串指针(错误码名_%s)," % 一项["词干"])
        渲染器("    说明: 取字节串指针(错误码说明_%s)," % 一项["词干"])
        渲染器("    可重试: %d," % (1 if 一项["可重试"] else 0))
        渲染器("    可自愈: %d," % (1 if 一项["可自愈"] else 0))
        渲染器("    需人工: %d," % (1 if 一项["需人工"] else 0))
        渲染器("    保留: 0,")
        渲染器("};")
        渲染器("")


def 渲染错误码(加常量, 加信息, 加信息续, 根目录, 错误码表, 平台):
    # ── 件一：错误码数据.rs ──
    _渲染逐码(加常量, 根目录, 错误码表, 平台)

    # ── 件二/三：错误码信息数据.rs（前半项 + 表）· 错误码信息续数据.rs（后半项）──
    前半数 = _前半数(len(错误码表))
    前半, 后半 = 错误码表[:前半数], 错误码表[前半数:]

    # 取用件一的名/说明常量（`pub(super)` ⇒ 本件与续件都能取）。**各取自身那半**，避免空转导入。
    用名 = [名 for 一项 in 前半 for 名 in ("错误码名_%s" % 一项["词干"], "错误码说明_%s" % 一项["词干"])]
    if 用名:
        加信息("use super::错误码数据::{%s};" % ", ".join(用名))
        加信息("")
    if 后半:
        加信息("use super::错误码信息续数据::{%s};" % ", ".join("错误码信息_%s" % 项["词干"] for 项 in 后半))
        加信息("")
    加信息("// ════════════════════════════════════════════════════════════════════════════")
    加信息("// 三 错误码信息表（源：%s/*.json，共 %d 项，按 码 升序）—— 前半 %d 项" % (根目录.错误码表, len(错误码表), len(前半)))
    加信息("// ════════════════════════════════════════════════════════════════════════════")
    加信息("")
    _渲染信息项(加信息, 前半)
    加信息("/// 错误码信息 表（源：%s/*.json，共 %d 项，按 码 升序）。" % (根目录.错误码表, len(错误码表)))
    加信息("/// **宪法级判据的落点**：调用方拿到 `码` 之后能查到 `可重试 · 可自愈 · 需人工`，")
    加信息("/// 否则那三项只是注释、到不了运行期。`段位` 是冗余登记项（可从 `码` 导出），")
    加信息("/// 故意写出来由验证面交叉比对抓错。三项业务判断用 0/1（跨边界宽度要显式）。")
    加信息("/// 本表项经 `pub(super) const 错误码信息_<词干>` 从本件与 `错误码信息续数据` 两件引用。")
    if 错误码表:
        加信息("pub const 错误码信息表: [v1_contract::错误码信息; %d] = [" % len(错误码表))
        for 一项 in 错误码表:
            加信息("    错误码信息_%s, // %s" % (一项["词干"], 一项["相对路径"]))
        加信息("];")
    else:
        加信息("pub const 错误码信息表: [v1_contract::错误码信息; 0] = [];")
    加信息("/// `平台信息.错误码表` 直接可用：项数 + 项表。")
    加信息("pub const fn 错误码信息表段() -> v1_contract::表段<v1_contract::错误码信息> {")
    加信息("    v1_contract::表段::新建(错误码信息表.as_ptr(), %d)" % len(错误码表))
    加信息("}")
    加信息("")

    加信息续("// ════════════════════════════════════════════════════════════════════════════")
    加信息续("// 三 错误码信息表（源：%s/*.json）—— 后半 %d 项" % (根目录.错误码表, len(后半)))
    加信息续("// ════════════════════════════════════════════════════════════════════════════")
    加信息续("")
    if 后半:
        加信息续("use super::错误码数据::{%s};" % ", ".join(名 for 一项 in 后半 for 名 in ("错误码名_%s" % 一项["词干"], "错误码说明_%s" % 一项["词干"])))
        加信息续("")
    _渲染信息项(加信息续, 后半)
