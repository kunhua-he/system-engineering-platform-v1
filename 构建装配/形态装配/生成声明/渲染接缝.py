# -*- coding: utf-8 -*-
"""渲染接缝 —— 由声明字段「导出目标」渲染唯一导出符号的接缝文件 `<根>/src/接缝.rs`。

**为什么要有这一件**：`导出目标` 原先不是声明字段，谁都能手写 `#[unsafe(export_name = …)]`。
实测（`项目文档/设计文档/导出目标.md` §五）：底座与扩展各手写一个同名 `GetPlatformInfo`
⇒ 同一二进制里只解析得到一个 ⇒ 底座身份自检恒假。正解是把符号名收进声明、由生成器出接缝 ——
手写导出属性消失，这类缺陷从根上没了。

**形状**（源：`契约声明/格式说明.md` §二·五）：
  · `导出目标 = null`  ⇒ 本声明**不导出**接缝（底座不是可装载件；裁决 6）⇒ 不出接缝文件；
  · `导出目标 = "<符号名>"` ⇒ 出接缝文件：`#[unsafe(export_name = "<符号名>")]` 的导出函数。

**接缝文件怎么被用**：实现侧把它声明成一个模块（`#[path]` 指向本件），只依赖一个固定钩子
`crate::取接缝地址()`（返回本声明的静态结构指针）—— 生成物不碰实现侧的私有数据名。实现侧不再
手写 `#[unsafe(export_name = …)]`。

**为什么接缝要能单独出**（`--接缝`）：可装载件（扩展）的声明根里**没有**号段图/常量表/作废号表
（`扩展装载/开发标准/必备件.json`），跑不了整份生成；接缝只需要声明文件一个源。
"""

from .路径形状 import 生成器相对路径, 生成失败
from .小工具 import 读json

# 接缝函数名 = 平台级约定（底座与扩展的接缝函数同名，crate 根的 `取平台信息` 都指它）。
接缝函数名 = "取平台信息"
# 接缝钩子名 = 生成物与实现侧之间的固定契约：**crate 根**提供 `取接缝地址()`，返回本声明的
# 静态结构指针。生成物只认这一个名字，不碰实现侧的模块布局或私有数据名。
接缝钩子名 = "取接缝地址"
# 接缝钩子的**调用路径**（crate 根；实现侧把它 re-export 到根，见 `渲染接缝` 的说明）。
接缝钩子路径 = "crate::" + 接缝钩子名


def 接缝路径(根):
    """接缝文件的仓内相对路径（= 根 + 固定名，与「落盘件」并列）。"""
    return 根.接缝件


def 是合法符号名(值):
    """导出的 ABI 符号一律 ASCII（外部协议边界，`跨语言适配/边界协议/边界协议.md` §二）。"""
    if not 值 or not (值[0].isascii() and (值[0].isalpha() or 值[0] == "_")):
        return False
    return all(字.isascii() and (字.isalnum() or 字 == "_") for 字 in 值)


def 校验导出目标(值, 源, 是底座):
    """**唯一的**导出目标校验处（整份生成与 `--接缝` 共用，一处口径）。返回 值 or None。

    底座（`平台声明.json`）：`null` / 缺 = 不导出；是字符串 ⇒ fail-closed（底座不是可装载件，裁决 6）。
    扩展（`包声明.json`）：必须是合法符号名串；`null` / 缺 ⇒ fail-closed（可装载件必须导出接缝）。
    """
    if 值 is None:
        if 是底座:
            return None
        raise 生成失败(
            "%s 缺 `导出目标`（或为 null）：扩展是可装载件，必须声明它导出的接缝符号名"
            "（每个扩展恰好 1 个，`跨语言适配/边界协议/边界协议.md` §二）；"
            "缺了就没有导出符号、底座载不进来 ⇒ fail-closed" % 源
        )
    if not isinstance(值, str) or not 是合法符号名(值):
        raise 生成失败(
            "%s 的 `导出目标` 不是合法符号名：%r（导出的 ABI 符号一律 ASCII）⇒ fail-closed"
            % (源, 值)
        )
    if 是底座:
        raise 生成失败(
            "%s 的 `导出目标` 是 %r，但**底座不是可装载件**（没人 dlopen 它；"
            "`项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 6）："
            "底座声明里 `导出目标` 只能是 null（不导出）⇒ fail-closed" % (源, 值)
        )
    return 值


def 读导出目标(根):
    """只读声明文件里的 `导出目标`；返回 (值 or None, 源相对路径)。**不读别的源**。"""
    源 = 根.声明文件
    文档 = 读json(源)
    if not isinstance(文档, dict):
        raise 生成失败("%s 顶层不是对象" % 源)
    return 校验导出目标(文档.get("导出目标"), 源, 根.声明文件 == 根.平台声明), 源


def 渲染接缝(根, 导出目标):
    """渲染接缝文件文本。`导出目标 = None` ⇒ 只有一段「不导出」的说明（不出函数）。"""
    头 = [
        "// 生成物，禁手改。要改请改源并重跑生成器。",
        "// 源：%s（导出目标 = %s）"
        % (根.声明文件, "null" if 导出目标 is None else '"%s"' % 导出目标),
        "// 生成器：%s" % 生成器相对路径,
    ]
    if 导出目标 is None:
        return "\n".join(
            头
            + [
                "//",
                "// 本声明**不导出接缝**：底座不是可装载件，没人 dlopen 它（裁决 6）。",
                "",
            ]
        )
    return "\n".join(
        头
        + [
            "//",
            "// 接缝：本声明唯一的导出符号名由声明字段「导出目标」给出 —— 手写",
            "// `#[unsafe(export_name = …)]` 会与别的声明撞名（底座与扩展各写一个同名 ⇒",
            "// 同二进制里只解析得到一个），故由生成器出。",
            "// 实现侧把它声明成一个模块（`#[path]` 指向本件）；它只依赖一个固定钩子",
            "// `%s`（返回本声明的静态结构指针），不碰任何私有数据名。" % 接缝钩子路径,
            '#[unsafe(export_name = "%s")]' % 导出目标,
            'pub extern "C" fn %s() -> *const v1_contract::平台信息 {' % 接缝函数名,
            "    %s()" % 接缝钩子路径,
            "}",
            "",
        ]
    )
