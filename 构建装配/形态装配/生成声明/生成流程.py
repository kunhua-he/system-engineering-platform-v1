def 收集指纹行(根):
    行 = [(根.声明文件, 源指纹(根.声明文件)), (根.号段图, 源指纹(根.号段图))]
    行.append((根.常量表, 源指纹(根.常量表)))
    for 目录 in (根.类型声明, 根.能力声明, 根.错误码表, 根.通知号段, 根.命令类别):
        if not os.path.isdir(os.path.join(仓根, 目录)):
            continue
        for _, 相对路径 in 列目录json(目录):
            行.append((相对路径, 源指纹(相对路径)))
    行.append((根.作废号表, 源指纹(根.作废号表)))
    return 行


def 建声明根(原始):
    """把命令行给的目录规范化成**仓内相对、POSIX 分隔**的声明根；仓外 / 非目录即 fail-closed。

    为什么只认仓内相对：产物头要写「源：<路径>」，绝对路径会带上机器相关前缀 ⇒ 产物不确定
    （同一份源在两台机器上生成出不同字节），指纹闸就废了。
    """
    if 原始 is None or 原始.strip() == "":
        raise 生成失败("声明根是空串")
    绝对 = os.path.abspath(原始 if os.path.isabs(原始) else os.path.join(仓根, 原始))
    相对 = os.path.relpath(绝对, 仓根).replace(os.sep, "/")
    if 相对 in (".", "..") or 相对.startswith("../"):
        raise 生成失败(
            "声明根 %r 解析成 %r：它不在仓库内（仓根 %s）⇒ 产物里会出现机器相关路径、"
            "破坏确定性 —— fail-closed" % (原始, 相对, 仓根)
        )
    if not os.path.isdir(绝对):
        raise 生成失败("声明根 %r 不是一个目录（解析成 %s）" % (原始, 相对))
    根 = 声明根(相对)
    根.声明文件 = 选声明文件(根)
    return 根


def 生成(根):
    平台 = 读平台声明(根)
    号段图 = 读号段图(根)
    判占用落在布局内(平台, 号段图, 根)
    常量表 = 读常量表(根)
    号段类 = 推导号段类(号段图)
    号段归属 = 号段归属表(号段图)
    交叉比对(常量表, 平台, 号段类, 根)
    类型表 = 读类型声明(根)
    命令表 = 读能力声明(根)
    命令类别表 = 读命令类别(根)
    错误码表 = 读错误码表(根)
    通知号表 = 读通知号段(根)
    提醒 = []
    if 平台["扩展侧含提供键"]:
        提醒 = list(提醒) + [
            "%s：扩展侧还带着 `提供宿主版本` / `提供内核版本` —— 扩展侧**没有消费者**"
            "（判定 ④ 只拿**底座**的「提供*」比扩展的「要求*」），按准入判据 ⑧ 是**死键**，应删"
            "（`扩展装载/开发标准/必备件.json`）。本生成器不要求它有，也不再为它出常量。" % 根.声明文件
        ]
    作废号表 = 读作废号表(根)
    # 命令类别：`能力声明` 里用到的每个 `类别` 值都该在 `命令类别/` 有登记（否则运行期查不到名字）。
    # **报成提醒、不 fail-closed** —— 类别号是**可选说明**（`取命令类别名` 查不到时返回空指针，
    # 那不是错误）：`能力声明.类别 = 0` = **未分类**，是合法状态，不该卡住生成。
    # 值域**已裁** `1..23`（格式说明 §三·五，照易语言内核库 `m_szzCategory`），
    # 所以这条提醒的含义只剩「你填了一个没有名字的号，要不要补登记」。
    已登记类别 = {项["类别号"] for 项 in 命令类别表}
    未登记类别 = sorted({项["类别"] for 项 in 命令表 if 项["类别"] not in 已登记类别})
    if 未登记类别:
        提醒 = list(提醒) + [
            "%s：命令用到的「类别」%s 没有在 %s 里登记 ⇒ 这些类别号在运行期查不到名字"
            "（类别号是可选说明，不是错误；值域已裁 `1..23`，`0` = 未分类）"
            % (根.能力声明, " · ".join("%d" % 值 for 值 in 未登记类别), 根.命令类别)
        ]
    文本 = 渲染(
        根,
        平台,
        号段图,
        常量表,
        号段类,
        号段归属,
        类型表,
        命令表,
        命令类别表,
        错误码表,
        通知号表,
        作废号表,
        收集指纹行(根),
    )
    未定 = [条["名"] for 条 in 常量表 if 条["值"] is None]
    if 未定:
        提醒 = list(提醒) + [
            "%s：「%s」的值是 null（未定数）⇒ 未生成常量，名字进生成物的 `未定数常量`"
            "（显式跳过，不是静默跳过）" % (根.常量表, " · ".join(未定))
        ]
    件 = {相对路径: 文.encode("utf-8") for 相对路径, 文 in 文本.items()}
    return 件, {
        "类型": len(类型表),
        "命令": len(命令表),
        "命令类别": len(命令类别表),
        "错误码": len(错误码表),
        "通知号": len(通知号表),
        "作废号": sum(len(号s) for 号s in 作废号表.values()),
        "能力号段": len(平台["能力号段"]),
        "通知号段": len(平台["通知号段"]),
        "错误段位": len(平台["错误段位表"]),
        "常量表": len(常量表),
        "常量本表出": len(
            [条 for 条 in 常量表 if 条["值"] is not None and 条["名"] not in 常量表落点]
        ),
        "常量交叉比对": len(
            [条 for 条 in 常量表 if 条["值"] is not None and 条["名"] in 常量表落点]
        ),
        "常量未定数": len(未定),
        "号段类宽度": 号段类[0],
        "号段类个数": 号段类[1],
    }, 提醒


def 落盘路径(根):
    return os.path.join(仓根, 根.落盘件)


def 落盘件表(根):
    """本份生成物的**全部落点**（仓内相对路径）：路由件 + 各子件。顺序固定。"""
    return [根.落盘件] + [根.子件[名] for 名 in 生成子件名]
