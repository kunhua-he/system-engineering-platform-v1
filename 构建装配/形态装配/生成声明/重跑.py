# -*- coding: utf-8 -*-
"""重跑 —— **可转调的重跑生成物入口**。

判据 ⑩（生成物与 JSON 一致）在写**任何**一份声明后都会红：`契约声明/src/声明数据.rs` 是生成物，
源改了它就不再新鲜（生成器 `--检查` 退出码 1）。面（`对外接口面/声明编写面/`）把 ⑩ 归成
「生成物待重跑」并原样报给调用方，但**面明确不重跑生成器**（`声明编写面/形状.md` §七.3：
「不重跑生成器、不碰 `契约声明/src/`」）。于是「重跑」这一步需要一个**可转调**的入口 —— 就是本件。

## 谁跑 · 怎么转调 · 退出码怎么传

- **谁跑**：**面外** —— 面的**调用方**（编排器 / CI / 人）。面只报「待重跑 + 修法」，
  不替调用方跑；本入口给调用方一个**进程内**的转调点（也保留 CLI 那条路）。
- **怎么转调**（两条，**同一条实现**，不是两套）：

  1. 进程内（与 `声明编写面/转调判据.py` 转调判据器**同一种姿势**：按文件路径 importlib 加载，
     取一个约定名字的函数）：

     ```python
     import importlib.util
     规 = importlib.util.spec_from_file_location("生成声明转调", "<仓根>/构建装配/形态装配/生成声明.py")
     模 = importlib.util.module_from_spec(规); 规.loader.exec_module(模)
     码 = 模.重跑("契约声明")             # 重跑并落盘 → 0（成）/ 2（fail-closed，产物未动）
     码 = 模.重跑("契约声明", 检查=True)   # 只比对 → 0（新鲜）/ 1（不新鲜）
     ```

     （`生成声明.py` 里有 `from 生成声明 import *`，故本函数会落到那个模块的公开面上。）
  2. CLI：`python3 构建装配/形态装配/生成声明.py --声明根 <目录>`（**不带 `--检查` 即重跑落盘**）。

- **退出码怎么传**：本函数**原样返回**生成器主函数的退出码（**0 一致 · 1 不新鲜 · 2 生成失败**），
  一个都不改写、不吞。调用方拿它当自身的退出码即可（`sys.exit(模.重跑(...))`）。
  注意 **1 只可能从 `检查=True` 那条路来** —— 重跑（落盘）成功就是 0，落盘失败是 2。

**为什么本件不另写一份「生成 + 落盘」**：那正是「同一件事两套实现」（老仓哲学第 8.2）。
本函数只把生成器主函数（`命令行.py::入口函数`）的参数拼出来再调它 —— 退出码契约只有**一处**定义
（`生成声明.py` 文件头那三档），本件不复制它。
"""

from .命令行 import 入口函数
from .路径形状 import 默认声明根


def 重跑(声明根=默认声明根, 检查=False):
    """重跑生成物。返回生成器主函数的退出码（0 / 1 / 2，**逐字传**）。

    `检查=False`（默认）：重新生成并**落盘** → 成功 `0`；源不合契约形状时 `2`（fail-closed，产物未动）。
    `检查=True`：只重新生成到内存、与落盘件逐字节比对 → `0` 新鲜 / `1` 不新鲜（**不落盘**）。

    `声明根` 只认**仓内相对路径**（同 CLI 口径）；`None` / 空 ⇒ 用默认声明根。
    """
    if 声明根 is None or str(声明根).strip() == "":
        声明根 = 默认声明根
    参数 = ["--声明根", str(声明根)]
    if 检查:
        参数.append("--检查")
    return 入口函数(参数)
