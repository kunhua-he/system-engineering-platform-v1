"""渲染 —— 渲染编排：按固定顺序把各小节拼成**多份**产物文本。零业务判定，只拼接。

按表拆（`开发规范.md` §六 单源 ≤400 行）：`声明数据.rs` 是**路由件**（`mod` + `pub use`），
各小节落进同目录的子件。本模块决定「哪一小节进哪一件」，以及路由件的 `#[path]` 挂载与再导出。
"""

from .渲染平台声明 import 渲染平台声明
from .渲染数据表 import 渲染类型表, 渲染能力编号, 渲染命令类别
from .渲染错误码 import 渲染错误码
from .渲染通知作废 import 渲染通知号, 渲染作废号
from .渲染常量推导 import 渲染常量表, 渲染号段推导
from .渲染说明 import 收口说明, 缺口说明
from .路径形状 import 生成器相对路径, 生成子件名, 再导出子件名

# 哪些子件用到路由件里的 `串()` 适配器（`const fn 串` 定义在路由件，子件 `use super::串;`）。
需串的子件 = {"平台与类型数据", "命令类别数据", "错误码信息数据", "错误码信息续数据"}


def 渲染头(加, 根, 指纹行):
    # ── 文件头（路由件）────────────────────────────────────────────────
    加("// 生成物，禁手改。要改请改源并重跑生成器。")
    加("// 源：" + 根.源清单())
    加("// 源指纹：")
    for 相对路径, 指纹 in 指纹行:
        加("//   %s = %s" % (相对路径, 指纹))
    加("// 生成器：" + 生成器相对路径)
    加("//")
    加("// 判据（`契约声明/格式说明.md` 第八节）：任何一处出现手写的 `static 平台信息` 即为违规。")
    加("//")
    加("// 闸 4「生成物指纹」怎么响：")
    加("//   python %s --检查" % 生成器相对路径)
    加("//   一致 ⇒ 退出 0 打印「生成物新鲜」；不一致 ⇒ 退出非 0 并报第一处不一致的字节偏移。")
    加("//")
    加("// 本份的声明根：%s（换根：python %s --声明根 <目录>）" % (根.根, 生成器相对路径))
    加("//")
    加(收口说明)
    加("")


def 渲染子件头(加, 根, 名):
    """子件头：标明「生成物 · 禁手改 · 路由件的子件」。**不写源指纹**（那在路由件里，只一处）。"""
    加("// 生成物，禁手改。要改请改源并重跑生成器。")
    加("// 本件是 `%s` 按表拆出的子件（路由件以 `#[path]` 挂它）—— 故本件不单独声明、"
        "不重复源指纹。" % 根.落盘件)
    加("// 生成器：" + 生成器相对路径)
    加("")
    if 名 in 需串的子件:
        加("use super::串;")
        加("")


def 渲染路由体(加, 根):
    """路由件的正文：`串()` 适配器 + `#[path]` 挂子件 + `pub use` 再导出公开面。

    **公开面逐字不变**：`v1_contract::声明数据::…` 的每一条路径都经 `pub use <子件>::*` 转出，
    调用方一处不用改（`lib.rs` 的 `pub use 声明数据::{取命令类别名, 命令类别表}` 也在其中）。
    """
    加("/// 静态 NUL 结尾串 → 契约要的 `*const u8`。生成物内部用；路由件不含 `unsafe`。")
    加("/// 定义在路由件（只一处），子件 `use super::串;` 取用。")
    加("const fn 串(字节: &'static [u8]) -> *const u8 {")
    加("    字节.as_ptr()")
    加("}")
    加("")
    加("// ── 按表拆出的子件（文件名非 ASCII ⇒ 逐条给 `#[path]`）──")
    for 名 in 生成子件名:
        加('#[path = "%s.rs"] mod %s;' % (名, 名))
    加("")
    加("// ── 再导出：公开面（符号名 · 路径）逐字不变 ──")
    for 名 in 再导出子件名:
        加("pub use %s::*;" % 名)
    加("")


def 渲染缺口(加):
    # ── 缺口 ───────────────────────────────────────────────────────────
    加(缺口说明)
    加("")


def 渲染(
    根,
    平台,
    号段图,
    常量表,
    号段类,
    号段归属,
    类型表,
    命令表,
    命令类别表,
    错误码表,
    通知号表,
    作废号表,
    指纹行,
):
    """返回 {仓内相对路径: 文本}：路由件 + 各子件。"""
    行 = {}
    已开子件 = set()

    def 器(名=None):
        行.setdefault(名, [])
        return 行[名].append

    def 子件(名):
        if 名 not in 已开子件:
            已开子件.add(名)
            渲染子件头(器(名), 根, 名)
        return 器(名)

    路由 = 器(None)
    渲染头(路由, 根, 指纹行)
    渲染路由体(路由, 根)
    渲染平台声明(子件("平台与类型数据"), 根, 平台, 号段图)
    渲染类型表(子件("平台与类型数据"), 根, 类型表)
    渲染能力编号(子件("平台与类型数据"), 根, 命令表)
    渲染命令类别(子件("命令类别数据"), 根, 命令类别表)
    渲染错误码(
        子件("错误码数据"),
        子件("错误码信息数据"),
        子件("错误码信息续数据"),
        根,
        错误码表,
        平台,
    )
    渲染通知号(子件("通知常量推导数据"), 根, 通知号表)
    渲染作废号(子件("通知常量推导数据"), 根, 作废号表)
    渲染常量表(子件("通知常量推导数据"), 根, 常量表)
    渲染号段推导(子件("通知常量推导数据"), 根, 号段图, 号段类, 号段归属)
    渲染缺口(路由)
    出 = {根.落盘件: "\n".join(行[None])}
    for 名 in 生成子件名:
        出[根.子件[名]] = "\n".join(行.get(名, []))
    return 出
