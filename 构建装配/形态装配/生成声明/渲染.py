# -*- coding: utf-8 -*-
"""渲染 —— 渲染编排：按固定顺序把各小节拼成产物文本。零业务判定，只拼接。"""

from .渲染平台声明 import 渲染平台声明
from .渲染数据表 import 渲染类型表, 渲染能力编号, 渲染命令类别
from .渲染错误码 import 渲染错误码
from .渲染通知作废 import 渲染通知号, 渲染作废号
from .渲染常量推导 import 渲染常量表, 渲染号段推导
from .渲染说明 import 收口说明, 缺口说明
from .路径形状 import 生成器相对路径


def 渲染头(加, 根, 指纹行):
    # ── 文件头 ──────────────────────────────────────────────────────────
    加("// 生成物，禁手改。要改请改源并重跑生成器。")
    加("// 源：" + 根.源清单())
    加("// 源指纹：")
    for 相对路径, 指纹 in 指纹行:
        加("//   %s = %s" % (相对路径, 指纹))
    加("// 生成器：" + 生成器相对路径)
    加("//")
    加("// 判据（`契约声明/格式说明.md` 第八节）：任何一处出现手写的 `static 平台信息` 即为违规。")
    加("//")
    加("// 闸 4「生成物指纹」怎么响：")
    加("//   python %s --检查" % 生成器相对路径)
    加("//   一致 ⇒ 退出 0 打印「生成物新鲜」；不一致 ⇒ 退出非 0 并报第一处不一致的字节偏移。")
    加("//")
    加("// 本份的声明根：%s（换根：python %s --声明根 <目录>）" % (根.根, 生成器相对路径))
    加("//")
    加(收口说明)
    加("")


def 渲染缺口(加):
    # ── 缺口 ───────────────────────────────────────────────────────────
    加(缺口说明)
    加("")


def 渲染(
    根,
    平台,
    号段图,
    常量表,
    号段类,
    号段归属,
    类型表,
    命令表,
    命令类别表,
    错误码表,
    通知号表,
    作废号表,
    指纹行,
):
    行 = []
    加 = 行.append
    渲染头(加, 根, 指纹行)
    渲染平台声明(加, 根, 平台, 号段图)
    渲染类型表(加, 根, 类型表)
    渲染能力编号(加, 根, 命令表)
    渲染命令类别(加, 根, 命令类别表)
    渲染错误码(加, 根, 错误码表, 平台)
    渲染通知号(加, 根, 通知号表)
    渲染作废号(加, 根, 作废号表)
    渲染常量表(加, 根, 常量表)
    渲染号段推导(加, 根, 号段图, 号段类, 号段归属)
    渲染缺口(加)
    return "\n".join(行)
