# 哪些子件用到路由件里的 `取字节串指针()` 适配器（`const fn 取字节串指针` 定义在路由件，子件 `use super::取字节串指针;`）。
需指针适配器的子件 = {"平台与类型数据", "命令类别数据", "错误码信息数据", "错误码信息续数据"}


def 渲染文件头(渲染器, 根目录, 指纹行):
    # ── 文件头（路由件）────────────────────────────────────────────────
    渲染器("// 生成物，禁手改。要改请改源并重跑生成器。")
    渲染器("// 源：" + 根目录.源清单())
    渲染器("// 源指纹：")
    for 相对路径, 指纹 in 指纹行:
        渲染器("//   %s = %s" % (相对路径, 指纹))
    渲染器("// 生成器：" + 生成器相对路径)
    渲染器("//")
    渲染器("// 判据（`契约声明/格式说明.md` 第八节）：任何一处出现手写的 `static 平台信息` 即为违规。")
    渲染器("//")
    渲染器("// 闸 4「生成物指纹」怎么响：")
    渲染器("//   python %s --检查" % 生成器相对路径)
    渲染器("//   一致 ⇒ 退出 0 打印「生成物新鲜」；不一致 ⇒ 退出非 0 并报第一处不一致的字节偏移。")
    渲染器("//")
    渲染器("// 本份的声明根：%s（换根：python %s --声明根 <目录>）" % (根目录.根, 生成器相对路径))
    渲染器("//")
    渲染器(收口说明)
    渲染器("")


def 渲染子件头(渲染器, 根目录, 名称):
    """子件头：标明「生成物 · 禁手改 · 路由件的子件」。**不写源指纹**（那在路由件里，只一处）。"""
    渲染器("// 生成物，禁手改。要改请改源并重跑生成器。")
    渲染器("// 本件是 `%s` 按表拆出的子件（路由件以 `#[path]` 挂它）—— 故本件不单独声明、"
        "不重复源指纹。" % 根目录.落盘件)
    渲染器("// 生成器：" + 生成器相对路径)
    渲染器("")
    if 名称 in 需指针适配器的子件:
        渲染器("use super::取字节串指针;")
        渲染器("")


def 渲染路由体(渲染器, 根目录):
    """路由件的正文：`取字节串指针()` 适配器 + `#[path]` 挂子件 + `pub use` 再导出公开面。

    **公开面逐字不变**：`v1_contract::声明数据::…` 的每一条路径都经 `pub use <子件>::*` 转出，
    调用方一处不用改（`lib.rs` 的 `pub use 声明数据::{取命令类别名, 命令类别表}` 也在其中）。
    """
    渲染器("/// 静态 NUL 结尾串 → 契约要的 `*const u8`。生成物内部用；路由件不含 `unsafe`。")
    渲染器("/// 定义在路由件（只一处），子件 `use super::取字节串指针;` 取用。")
    渲染器("const fn 取字节串指针(字节串: &'static [u8]) -> *const u8 {")
    渲染器("    字节串.as_ptr()")
    渲染器("}")
    渲染器("")
    渲染器("// ── 按表拆出的子件（文件名非 ASCII ⇒ 逐条给 `#[path]`）──")
    for 名称 in 生成子件名:
        渲染器('#[path = "%s.rs"] mod %s;' % (名称, 名称))
    渲染器("")
    渲染器("// ── 再导出：公开面（符号名 · 路径）逐字不变 ──")
    for 名称 in 再导出子件名:
        渲染器("pub use %s::*;" % 名称)
    渲染器("")


def 渲染缺口(渲染器):
    # ── 缺口 ───────────────────────────────────────────────────────────
    渲染器(缺口说明)
    渲染器("")


def 渲染(
    根目录,
    平台,
    号段图,
    常量表,
    号段类,
    号段归属,
    类型表,
    命令表,
    命令类别表,
    错误码表,
    通知号表,
    作废号表,
    指纹行,
):
    """返回 {仓内相对路径: 文本}：路由件 + 各子件。"""
    源码行 = {}
    已开子件 = set()

    def 取渲染器(名称=None):
        源码行.setdefault(名称, [])
        return 源码行[名称].append

    def 子件(名称):
        if 名称 not in 已开子件:
            已开子件.add(名称)
            渲染子件头(取渲染器(名称), 根目录, 名称)
        return 取渲染器(名称)

    路由 = 取渲染器(None)
    渲染文件头(路由, 根目录, 指纹行)
    渲染路由体(路由, 根目录)
    渲染平台声明(子件("平台与类型数据"), 根目录, 平台, 号段图)
    渲染类型表(子件("平台与类型数据"), 根目录, 类型表)
    渲染能力编号(子件("平台与类型数据"), 根目录, 命令表)
    渲染命令类别(子件("命令类别数据"), 根目录, 命令类别表)
    渲染错误码(
        子件("错误码数据"),
        子件("错误码信息数据"),
        子件("错误码信息续数据"),
        根目录,
        错误码表,
        平台,
    )
    渲染通知号(子件("通知常量推导数据"), 根目录, 通知号表)
    渲染作废号(子件("通知常量推导数据"), 根目录, 作废号表)
    渲染常量表(子件("通知常量推导数据"), 根目录, 常量表)
    渲染号段推导(子件("通知常量推导数据"), 根目录, 号段图, 号段类, 号段归属)
    渲染缺口(路由)
    输出缓冲 = {根目录.落盘件: "\n".join(源码行[None])}
    for 名称 in 生成子件名:
        输出缓冲[根目录.子件[名称]] = "\n".join(源码行.get(名称, []))
    return 输出缓冲
