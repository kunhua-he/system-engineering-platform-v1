"""读子表 —— 类型声明 / 能力声明 / 命令类别 / 错误码表 / 通知号段 / 作废号表。

文件名即编号（词干），逐条校验文件名与字段一致。形状依据 `契约声明/格式说明.md`。
"""

import os

from .路径形状 import 仓根, 生成失败
from .小工具 import 读json, 取整, 取串, 取表, 取逻辑, 列目录json

未定义的子表 = ("元素表", "属性表", "事件表", "命令号表")


def 读类型声明(根):
    """返回按 类型标签 升序的表。文件名 = 类型标签。"""
    出 = []
    for 文件名, 相对路径 in 列目录json(根.类型声明):
        词干 = 文件名[: -len(".json")]
        if not 词干.isdigit():
            raise 生成失败("%s 的文件名不是十进制编号：%s" % (根.类型声明, 文件名))
        文档 = 读json(相对路径)
        标签 = 取整(文档, "类型标签", 相对路径, 0, 0xFFFFFFFF)
        if 标签 != int(词干):
            raise 生成失败(
                "%s：文件名 %s 与「类型标签」%d 不一致（文件名即类型标签）"
                % (相对路径, 词干, 标签)
            )
        for 键 in 未定义的子表:
            子表 = 取表(文档, 键, 相对路径)
            if 子表:
                raise 生成失败(
                    "%s 的「%s」有 %d 项，但本格式未定义该项的形状"
                    "（`契约声明/格式说明.md` 第四节只给了空数组的例子）"
                    "——生成器不敢替它编一个形状，故 fail-closed"
                    % (相对路径, 键, len(子表))
                )
        出.append(
            {
                "词干": 词干,
                "相对路径": 相对路径,
                "类型标签": 标签,
                "名称": 取串(文档, "名称", 相对路径),
                "说明": 取串(文档, "说明", 相对路径),
                "状态位": 取整(文档, "状态位", 相对路径, 0, 0xFFFFFFFF),
            }
        )
    出.sort(key=lambda 项: (项["类型标签"], 项["词干"]))
    if not 出:
        raise 生成失败("%s 下没有任何类型声明" % 根.类型声明)
    return 出


def 读能力声明(根):
    """读 `<声明根>/能力声明/*.json`（**本声明自己的**命令声明），按 `编号` 升序。

    形状逐字按 `契约声明/格式说明.md` §三：
      {编号, 名称, 说明, 类别, 状态位, 返回类型, 用户级别,
       参数表[{名称,说明,类型标签,状态位,默认值{类型标签,值}}], 可抛错误码[码…]}

    **一份声明根装它自己的声明**（§一 ★）：底座 = `契约声明/`；扩展 = 它自己目录里的
    `能力声明/`（编译器扩展已是这么落的）。故本函数读的是「本声明自己的命令」，不读别处。

    为什么生成器要认它：`命令信息.编号`（显式）与 `命令信息.可抛错误码` 的唯一来源就是
    这份 JSON。**没有读方的声明等于零**，故本函数逐条消费它、出成命令表（见渲染 二·五）。

    **表按编号严格递增**是注册表「按编号二分查找」的前提：这里判重复（fail-closed）。
    """
    出 = []
    for 文件名, 相对路径 in 列目录json(根.能力声明):
        词干 = 文件名[: -len(".json")]
        if not 词干.isdigit():
            raise 生成失败("%s 的文件名不是十进制编号：%s" % (根.能力声明, 文件名))
        文档 = 读json(相对路径)
        编号 = 取整(文档, "编号", 相对路径, 0, 0xFFFFFFFF)
        if 编号 != int(词干):
            raise 生成失败(
                "%s：文件名 %s 与「编号」%d 不一致（文件名即编号）" % (相对路径, 词干, 编号)
            )
        参数表 = 取表(文档, "参数表", 相对路径)
        参数出 = []
        for 序, 行 in enumerate(参数表):
            处 = "%s.参数表[%d]" % (相对路径, 序)
            if not isinstance(行, dict):
                raise 生成失败("%s 不是对象" % 处)
            默认值 = 行.get("默认值")
            if not isinstance(默认值, dict):
                raise 生成失败(
                    "%s 的「默认值」不是对象（§三 形状 {类型标签, 值}）：%r" % (处, 默认值)
                )
            参数出.append(
                {
                    "名称": 取串(行, "名称", 处),
                    "说明": 取串(行, "说明", 处),
                    "类型标签": 取整(行, "类型标签", 处, 0, 0xFFFFFFFF),
                    "状态位": 取整(行, "状态位", 处, 0, 0xFFFF),
                    "默认值标签": 取整(默认值, "类型标签", 处 + ".默认值", 0, 0xFFFFFFFF),
                    "默认值值": 取整(默认值, "值", 处 + ".默认值", 0, 0xFFFFFFFFFFFFFFFF),
                }
            )
        可抛 = 取表(文档, "可抛错误码", 相对路径)
        可抛出 = []
        for 序, 码 in enumerate(可抛):
            if isinstance(码, bool) or not isinstance(码, int) or not (0 <= 码 <= 9999):
                raise 生成失败(
                    "%s.可抛错误码[%d] 不是 0–9999 的码（§五：码是完整 4 位号）：%r"
                    % (相对路径, 序, 码)
                )
            可抛出.append(码)
        出.append(
            {
                "编号": 编号,
                "词干": 词干,
                "相对路径": 相对路径,
                "名称": 取串(文档, "名称", 相对路径),
                "说明": 取串(文档, "说明", 相对路径),
                "类别": 取整(文档, "类别", 相对路径, 0, 0xFFFF),
                "状态位": 取整(文档, "状态位", 相对路径, 0, 0xFFFF),
                "返回类型": 取整(文档, "返回类型", 相对路径, 0, 0xFFFFFFFF),
                "用户级别": 取整(文档, "用户级别", 相对路径, 0, 0xFFFF),
                "参数表": 参数出,
                "可抛错误码": 可抛出,
            }
        )
    出.sort(key=lambda 项: (项["编号"], 项["词干"]))
    编号s = [项["编号"] for 项 in 出]
    if len(set(编号s)) != len(编号s):
        raise 生成失败(
            "%s 下有两份能力声明用了同一个编号 ⇒ 注册表按编号查找会撞号"
            "（号只增不复用、允许有洞，但同一声明里不许重号）—— fail-closed" % 根.能力声明
        )
    return 出


def 读命令类别(根):
    """读 `<声明根>/命令类别/*.json`（**本声明自己的**命令类别表），按 `类别号` 升序。

    形状（`契约声明/格式说明.md` §三·五）：`{类别号, 名称, 说明}`。文件名 = 类别号 ——
    它就是 `命令信息.类别: u16` 那个号。

    **为什么要有它**：`命令信息.类别` 若没有「类别号 → 类别名」表，这个号在运行期**永远解不出
    名字**（参照实现把它放在 `LIB_INFO +0x5C/+0x60` 那一对里 —— 字节级实测见
    `项目文档/设计文档/接缝实测.md` §二/§三）。故本函数逐条消费它、出成 `命令类别表`
    （见渲染 二·六），并出 `取命令类别名` 供运行期查。

    **目录不存在 / 表为空都不 fail-closed**：类别号的**值域与含义尚未裁**
    （`契约声明/格式说明.md` §三·五 与 §十 待裁），生成器**不替它编一个值域**。
    空表 = 「表在（机制已通），值域待裁」，不是漏写 —— 与「静默跳过」不是一回事
    （名字仍进生成物的注释与空表，谁要判「值域定了没」读那张表即可）。
    """
    if not os.path.isdir(os.path.join(仓根, 根.命令类别)):
        return []
    出 = []
    for 文件名, 相对路径 in 列目录json(根.命令类别):
        词干 = 文件名[: -len(".json")]
        if not 词干.isdigit():
            raise 生成失败("%s 的文件名不是十进制编号：%s" % (根.命令类别, 文件名))
        文档 = 读json(相对路径)
        类别号 = 取整(文档, "类别号", 相对路径, 0, 0xFFFF)
        if 类别号 != int(词干):
            raise 生成失败(
                "%s：文件名 %s 与「类别号」%d 不一致（文件名即类别号）" % (相对路径, 词干, 类别号)
            )
        出.append(
            {
                "类别号": 类别号,
                "词干": 词干,
                "相对路径": 相对路径,
                "名称": 取串(文档, "名称", 相对路径),
                "说明": 取串(文档, "说明", 相对路径),
            }
        )
    出.sort(key=lambda 项: (项["类别号"], 项["词干"]))
    号s = [项["类别号"] for 项 in 出]
    if len(set(号s)) != len(号s):
        raise 生成失败(
            "%s 下有两份命令类别用了同一个类别号 ⇒ 「按号查名」会撞号 —— fail-closed" % 根.命令类别
        )
    return 出


def 读错误码表(根):
    """返回按 码 升序的表。文件名 = 码；段位 = 码的首位十进制数字。"""
    出 = []
    for 文件名, 相对路径 in 列目录json(根.错误码表):
        词干 = 文件名[: -len(".json")]
        if not 词干.isdigit():
            raise 生成失败("%s 的文件名不是十进制编号：%s" % (根.错误码表, 文件名))
        文档 = 读json(相对路径)
        码 = 取整(文档, "码", 相对路径, 0, 9999)
        if 码 != int(词干):
            raise 生成失败("%s：文件名 %s 与「码」%d 不一致（文件名即码）" % (相对路径, 词干, 码))
        段位 = 取整(文档, "段位", 相对路径, 0, 9)
        if 段位 != int(词干.zfill(4)[0]):
            raise 生成失败(
                "%s：「段位」%d 与「码」%04d 的首位十进制数字 %s 不一致"
                % (相对路径, 段位, 码, 词干.zfill(4)[0])
            )
        出.append(
            {
                "码": 码,
                "词干": 词干,
                "相对路径": 相对路径,
                "名称": 取串(文档, "名称", 相对路径),
                "说明": 取串(文档, "说明", 相对路径),
                "段位": 段位,
                "可重试": 取逻辑(文档, "可重试", 相对路径),
                "可自愈": 取逻辑(文档, "可自愈", 相对路径),
                "需人工": 取逻辑(文档, "需人工", 相对路径),
            }
        )
    出.sort(key=lambda 项: (项["码"], 项["词干"]))
    return 出


def 读通知号段(根):
    """返回按 通知号 升序的表。文件名 = 通知号。

    **本件只读值，不判「方向与号段相符」** —— 那条口径的唯一实现是
    `构建装配/一键验证/一键验证/判据_通知与冻结.py::检查8_通知号落在对应方向的号段内`
    （`一键验证.py` 检查 8，带反向样本「通知号越方向」）。

    为什么本件不再自带一份（裁决 §六，`决策记录/2026-09-27_判据口径十一条.md`）：
    本件曾按 `格式说明.md` §六 的**旧**字面自判（下行 1–999 · 上行 1000–1999），
    而 `号段图.json` 的磁盘事实是 `2000–2999` 生命周期段**两个方向都有**（2000..2003 下行 ·
    2015 上行）⇒ 同一条判据两条腿两套读法，其中一套是错的。**口径只留一处**。
    本件对 `方向` 的要求只剩「读得出来是个字符串」（渲染要印它）；
    值域与落段由闸1 判 8 管，本件不重复判。
    """
    出 = []
    for 文件名, 相对路径 in 列目录json(根.通知号段):
        词干 = 文件名[: -len(".json")]
        if not 词干.isdigit():
            raise 生成失败("%s 的文件名不是十进制编号：%s" % (根.通知号段, 文件名))
        文档 = 读json(相对路径)
        通知号 = 取整(文档, "通知号", 相对路径, 0, 0xFFFFFFFF)
        if 通知号 != int(词干):
            raise 生成失败(
                "%s：文件名 %s 与「通知号」%d 不一致（文件名即通知号）"
                % (相对路径, 词干, 通知号)
            )
        方向 = 取串(文档, "方向", 相对路径)
        参数 = 取表(文档, "参数", 相对路径)
        if len(参数) != 2:
            raise 生成失败(
                "%s 的「参数」有 %d 项，但 `通知函数` 恰好两个 usize 入参 ⇒ 必须是 2 项"
                % (相对路径, len(参数))
            )
        for 序, 值 in enumerate(参数):
            if not isinstance(值, str):
                raise 生成失败("%s.参数[%d] 不是字符串：%r" % (相对路径, 序, 值))
        出.append(
            {
                "通知号": 通知号,
                "词干": 词干,
                "相对路径": 相对路径,
                "名称": 取串(文档, "名称", 相对路径),
                "说明": 取串(文档, "说明", 相对路径),
                "方向": 方向,
                "参数": 参数,
            }
        )
    出.sort(key=lambda 项: (项["通知号"], 项["词干"]))
    return 出


# 作废号表的「号空间」值域：**五个**号空间互不相通 —— 前四个是**号段空间**
# （`契约声明/号段图.json` 的「四个号空间互不相通」：能力号 · 通知号 · 错误码 · 资源号），
# 第五个 `类型` 是**类型标签空间**：它是独立空间（`项目文档/设计文档/字段名册与引用方式.md`
# §五「类型标签 … 与上面四个不通」），只是不属号段制（`u32` 全域，无号段可依），故
# `号段图.json` 里没有它，但值域不能漏它（漏了 ⇒ `类型声明/` 掉出判据面覆盖）。
# 一个号在哪个空间里作废，就只在**那个空间**里不可再用 —— 数字相同不算同号
# （能力号 16 与 错误码 16 是两回事；类型标签 0 与能力号 0 同理）。判定只比同空间的号。
作废号空间 = ("能力", "类型", "通知", "错误码", "资源")


def 读作废号表(根):
    """→ {号空间: [编号…]（升序）}，五个空间都在（没有行的给空表）。

    每一行**必须**带 `号空间`（值域 `作废号空间`）—— 它是「这个号在哪个空间里作废」的
    唯一依据。缺了 / 不在值域 ⇒ fail-closed：不带空间的作废行只能被**全局**排除，
    而那正是实测的假冲突（错误码 `16` 被当成能力号 `16`，底座 `能力号段 0–999` 自己撞自己）。
    去重按**空间**分别判：同一个数字可以在不同空间各作废一次（那是两个号）。
    """
    源 = 根.作废号表
    文档 = 读json(源)
    作废 = 取表(文档, "作废", 源)
    出 = {空间: [] for 空间 in 作废号空间}
    for 序, 行 in enumerate(作废):
        处 = "%s.作废[%d]" % (源, 序)
        if not isinstance(行, dict):
            raise 生成失败("%s 不是对象" % 处)
        空间 = 取串(行, "号空间", 处)
        if 空间 not in 作废号空间:
            raise 生成失败(
                "%s 的「号空间」是 %r；只认 %s 之一（五个号空间互不相通，见 %s 的"
                "「四个号空间互不相通」＋ %s §七 的「值域五个」）。没有它，这个号会被五个"
                "空间**一起**排除 —— 那正是「错误码 16 撞上底座 能力号段 0–999」的假冲突"
                "（实测 31 条红）"
                % (处, 空间, " · ".join(作废号空间), 根.号段图, "契约声明/格式说明.md")
            )
        出[空间].append(取整(行, "编号", 处, 0, 0xFFFFFFFF))
    for 空间 in 作废号空间:
        出[空间].sort()
        if len(set(出[空间])) != len(出[空间]):
            raise 生成失败("%s 里「号空间」= %s 的作废编号有重复" % (源, 空间))
    return 出
