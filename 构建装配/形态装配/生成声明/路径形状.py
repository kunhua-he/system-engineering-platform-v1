# -*- coding: utf-8 -*-
"""路径形状 —— 落点与源（一律仓库内相对路径；绝对路径不许进产物）。

只有「根」是可变的；根下面有什么、叫什么，是**声明的形状**，不随根变。
加一个根 = 加一份声明；加一个字段 = 改形状 —— 后者要按 `契约声明/冻结登记.json` 走。
"""

import os

# ════════════════════════════════════════════════════════════════════════════
# 落点与源（一律仓库内相对路径；绝对路径不许进产物）
# ════════════════════════════════════════════════════════════════════════════

生成器相对路径 = "构建装配/形态装配/生成声明.py"
默认声明根 = "契约声明"

# 本包比原入口深一层（`生成声明/路径形状.py`），故上溯四级取仓根。
仓根 = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
)


class 声明根:
    """一份声明的根目录（默认 `契约声明`）。路径 = 根 + 固定相对名，一律仓内相对、POSIX 分隔。

    只有「根」是可变的；根下面有什么、叫什么，是**声明的形状**，不随根变。
    加一个根 = 加一份声明；加一个字段 = 改形状 —— 后者要按 `契约声明/冻结登记.json` 走。
    """

    def __init__(self, 根):
        self.根 = 根
        self.平台声明 = 根 + "/平台声明.json"
        self.包声明 = 根 + "/包声明.json"
        self.号段图 = 根 + "/号段图.json"
        self.常量表 = 根 + "/常量表.json"
        self.类型声明 = 根 + "/类型声明"
        self.能力声明 = 根 + "/能力声明"
        self.错误码表 = 根 + "/错误码表"
        self.通知号段 = 根 + "/通知号段"
        # 命令类别（`命令信息.类别` 那个号 → 名字）。**值域与含义尚未裁**（格式说明 §三·五 / §十 待裁），
        # 故本目录**允许不存在 / 允许为空** —— 空 = 「表在（机制已通），值域待裁」，不是漏写。
        self.命令类别 = 根 + "/命令类别"
        self.作废号表 = 根 + "/作废号表.json"
        self.落盘件 = 根 + "/src/声明数据.rs"
        # 接缝文件：由声明字段「导出目标」渲染（`渲染接缝.py`），与「落盘件」并列。
        # 底座不导出 ⇒ 无此件；可装载件（扩展）的接缝落这里，由实现侧 `include!`。
        self.接缝件 = 根 + "/src/接缝.rs"
        # 声明文件本身：底座叫 `平台声明.json`，扩展叫 `包声明.json`（同形状，只是名字不同）。
        # 由 选声明文件() 定，定完不再变。
        self.声明文件 = None

    def 源清单(self):
        """产物头里「源：」那一行。逐字由**实际读的源**拼出，不另抄一份清单。"""
        return " · ".join(
            [
                self.声明文件,
                self.号段图,
                self.常量表,
                self.类型声明 + "/*.json",
                self.能力声明 + "/*.json",
                self.错误码表 + "/*.json",
                self.通知号段 + "/*.json",
                self.命令类别 + "/*.json",
                self.作废号表,
            ]
        )


class 生成失败(Exception):
    """源不合契约形状。fail-closed：宁可不出生成物，也不出错的生成物。"""
