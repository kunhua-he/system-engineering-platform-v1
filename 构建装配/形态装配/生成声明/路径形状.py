# -*- coding: utf-8 -*-
"""路径形状 —— 落点与源（一律仓库内相对路径；绝对路径不许进产物）。

只有「根」是可变的；根下面有什么、叫什么，是**声明的形状**，不随根变。
加一个根 = 加一份声明；加一个字段 = 改形状 —— 后者要按 `契约声明/冻结登记.json` 走。
"""

import os

# ════════════════════════════════════════════════════════════════════════════
# 落点与源（一律仓库内相对路径；绝对路径不许进产物）
# ════════════════════════════════════════════════════════════════════════════

生成器相对路径 = "构建装配/形态装配/生成声明.py"
默认声明根 = "契约声明"

# 生成物**按表拆**（`开发规范.md` 第六节：单源文件 ≤400 行；判据 ⑲ 的行数硬数）。
# `声明数据.rs` 只留 `mod` + `pub use`（路由），各小节落进同目录的子件。
# 子件名 = Rust 模块名；文件名 = 模块名 + ".rs"（非 ASCII ⇒ 路由件用 `#[path]` 挂）。
# 全部以「数据.rs」结尾 ⇒ 顶层 `src/*数据.rs` 就是「生成物全集」（陈旧件检测靠它）。
生成子件名 = (
    "平台与类型数据",      # 一 平台声明 · 二 数据类型表 · 二·五 能力编号
    "参数默认数据",
    "命令类别数据",        # 二·六 命令类别（#224 点名的拆出件）
    "错误码数据",          # 三 错误码（逐码常量 + 错误码表 + 名/说明常量）
    "错误码信息数据",      # 三 错误码信息表（前半项 + 表 + 表段）
    "错误码信息续数据",    # 三 错误码信息表（后半项）
    "通知常量推导数据",    # 四 通知号 · 五 作废号表 · 六 平台常量表 · 七 号段图推导
)

# 哪些子件**没有公开项**（只放 `pub(super)` 用料）⇒ 路由件不给它 `pub use`（给了是空转 + 告警）。
# `错误码信息续数据` 只有 `错误码信息表` 的后半用料，公开面是 `错误码信息表`（在 `错误码信息数据`）。
仅内部子件名 = ("错误码信息续数据",)
再导出子件名 = tuple(名称 for 名称 in 生成子件名 if 名称 not in 仅内部子件名)

# 本包比原入口深一层（`生成声明/路径形状.py`），故上溯四级取仓根。
仓根 = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
)


class 声明根:
    """一份声明的根目录（默认 `契约声明`）。路径 = 根 + 固定相对名，一律仓内相对、POSIX 分隔。

    只有「根」是可变的；根下面有什么、叫什么，是**声明的形状**，不随根变。
    加一个根 = 加一份声明；加一个字段 = 改形状 —— 后者要按 `契约声明/冻结登记.json` 走。
    """

    def __init__(self, 根目录):
        self.根目录 = 根目录
        self.平台声明 = 根目录 + "/平台声明.json"
        self.包声明 = 根目录 + "/包声明.json"
        self.号段图 = 根目录 + "/号段图.json"
        self.常量表 = 根目录 + "/常量表.json"
        self.类型声明 = 根目录 + "/类型声明"
        self.能力声明 = 根目录 + "/能力声明"
        self.错误码表 = 根目录 + "/错误码表"
        self.通知号段 = 根目录 + "/通知号段"
        # 命令类别（`命令信息.类别` 那个号 → 名字）。**值域已裁 = 1..23**（取自参照实现的类别表，
        # 不发明；格式说明 §三·五），故本目录**允许不存在 / 允许为空** —— 空 = 「表在（机制已通）」，不是漏写。
        self.命令类别 = 根目录 + "/命令类别"
        self.作废号表 = 根目录 + "/作废号表.json"
        self.落盘件 = 根目录 + "/src/声明数据.rs"
        # 生成物按表拆出的子件（路由件以 `#[path]` 挂它们）。**名字固定、随根变**。
        self.子件 = {名称: 根目录 + "/src/" + 名称 + ".rs" for 名称 in 生成子件名}
        # 接缝文件：由声明字段「导出目标」渲染（`渲染接缝.py`），与「落盘件」并列。
        # 底座不导出 ⇒ 无此件；可装载件（扩展）的接缝落这里，由实现侧 `include!`。
        self.接缝件 = 根目录 + "/src/接缝.rs"
        # 声明文件本身：底座叫 `平台声明.json`，扩展叫 `包声明.json`（同形状，只是名字不同）。
        # 由 选声明文件() 定，定完不再变。
        self.声明文件 = None

    def 源清单(self):
        """产物头里「源：」那一行。逐字由**实际读的源**拼出，不另抄一份清单。"""
        return " · ".join(
            [
                self.声明文件,
                self.号段图,
                self.常量表,
                self.类型声明 + "/*.json",
                self.能力声明 + "/*.json",
                self.错误码表 + "/*.json",
                self.通知号段 + "/*.json",
                self.命令类别 + "/*.json",
                self.作废号表,
            ]
        )


class 生成失败(Exception):
    """源不合契约形状。fail-closed：宁可不出生成物，也不出错的生成物。"""
