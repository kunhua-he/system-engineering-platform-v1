def 默认值表达式(参数项):
    """把一个参数行的默认值渲染成**编译期可求值**的 `数据槽` 表达式。

    与 `渲染参数表` 的 `取生成默认值` 同一套口径（三态 未提供/空值/显式默认 ＋ 文本承载），
    区别只是这里要的是**常量表达式**（生成物里直接进 `const` 数组），不是运行期分支。
    `数据槽::空槽` / `数据槽::内联槽` 都是 `const fn`（`契约声明/src/契约声明/基础形状.rs`）。
    """
    情形 = 参数项["默认值情形"]
    标签 = 参数项["默认值标签"]
    if 情形 != "显式默认" or 标签 == 0:
        return "v1_contract::数据槽::空槽()"
    if 标签 == 4:
        默认文本 = 参数项["默认值文本"]
        return (
            "v1_contract::数据槽 { 类型标签: v1_contract::类型标签::构造(4), "
            "槽标志位: v1_contract::槽标志::引用 | v1_contract::槽标志::只读, 保留: 0, "
            "槽字节长度: %d, 槽值: %s.as_bytes().as_ptr() as u64 }"
            % (len(默认文本.encode("utf-8")), 转字符串字面量(默认文本))
        )
    return "v1_contract::数据槽::内联槽(v1_contract::类型标签::构造(%d), %d, %d)" % (
        标签, 参数项["默认值值"], 1 if 标签 == 3 else 8
    )


