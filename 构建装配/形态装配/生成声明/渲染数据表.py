def 渲染参数表(渲染器, 根目录, 命令表):
    for 命令项 in 命令表:
        错误码表 = ", ".join("v1_contract::错误码::构造(%d)" % 错误码 for 错误码 in 命令项["可抛错误码"])
        渲染器("const 可抛错误码_%s: &[v1_contract::错误码] = &[%s];" % (命令项["词干"], 错误码表))
    渲染器("pub fn 取生成命令表(编号: u32) -> Option<v1_contract::命令信息> {")
    渲染器("    match 编号 {")
    for 命令项 in 命令表:
        错误码表 = ", ".join("v1_contract::错误码::构造(%d)" % 错误码 for 错误码 in 命令项["可抛错误码"])
        渲染器("        %d => Some(v1_contract::命令信息 { 名称: %s.as_bytes().as_ptr(), 说明: %s.as_bytes().as_ptr(), 类别号: %d, 状态位: %d, 返回类型: v1_contract::类型标签::构造(%d), 用户级别: %d, 参数个数: %d, 参数表: core::ptr::null(), 编号: v1_contract::能力号::构造(%d), 可抛错误码: v1_contract::表段::构造(可抛错误码_%s.as_ptr(), %d) })," % (命令项["编号"], 转字符串字面量(命令项["名称"] + "\0"), 转字符串字面量(命令项["说明"] + "\0"), 命令项["类别"], 命令项["状态位"], 命令项["返回类型"], 命令项["用户级别"], len(命令项["参数表"]), 命令项["编号"], 命令项["词干"], len(命令项["可抛错误码"])))
    渲染器("        _ => None,")
    渲染器("    }")
    渲染器("}")
    渲染器("pub fn 取生成默认值(编号: u32, 序号: usize) -> Option<v1_contract::数据槽> {")
    渲染器("    match (编号, 序号) {")
    for 命令项 in 命令表:
        for 序号, 参数项 in enumerate(命令项["参数表"]):
            情形 = 参数项["默认值情形"]
            if 情形 == "未提供":
                continue
            标签 = 参数项["默认值标签"]
            if 情形 == "空值":
                源文本 = "v1_contract::数据槽::空槽()"
            elif 标签 == 4:
                默认文本 = 参数项["默认值文本"]
                源文本 = "v1_contract::数据槽 { 类型标签: v1_contract::类型标签::构造(4), 槽标志位: v1_contract::槽标志::引用 | v1_contract::槽标志::只读, 保留: 0, 槽字节长度: %d, 槽值: %s.as_bytes().as_ptr() as u64 }" % (len(默认文本.encode("utf-8")), 转字符串字面量(默认文本))
            else:
                源文本 = "v1_contract::数据槽::内联槽(v1_contract::类型标签::构造(%d), %d, %d)" % (标签, 参数项["默认值值"], 1 if 标签 == 3 else 8)
            渲染器("        (%d, %d) => Some(%s)," % (命令项["编号"], 序号, 源文本))
    渲染器("        _ => None,")
    渲染器("    }")
    渲染器("}")
    渲染器("pub fn 取生成参数(编号: u32, 序号: usize) -> Option<v1_contract::参数信息> {")
    渲染器("    let (名称, 说明, 标签, 状态位): (&str, &str, u32, u16) = match (编号, 序号) {")
    for 命令项 in 命令表:
        for 序号, 参数项 in enumerate(命令项["参数表"]):
            渲染器("        (%d, %d) => (%s, %s, %d, %d)," % (命令项["编号"], 序号, 转字符串字面量(参数项["名称"] + "\0"), 转字符串字面量(参数项["说明"] + "\0"), 参数项["类型标签"], 参数项["状态位"]))
    渲染器("        _ => return None,")
    渲染器("    };")
    渲染器("    Some(v1_contract::参数信息 { 名称: 名称.as_bytes().as_ptr(), 说明: 说明.as_bytes().as_ptr(), 类型标签: v1_contract::类型标签::构造(标签), 状态位, 默认值: 取生成默认值(编号, 序号).unwrap_or(v1_contract::数据槽::空槽()) })")
    渲染器("}")
    渲染器("")


def 渲染命令类别(渲染器, 根目录, 命令类别表):
    # ── 二·六 命令类别 ────────────────────────────────────────────────
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 二·六 命令类别（源：%s/*.json，按 类别号 升序）" % 根目录.命令类别)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    渲染器("// `命令信息.类别: u16` 若没有这张表，这个号在运行期**永远解不出名字** ——")
    渲染器("// 参照实现把它放在 `LIB_INFO +0x5C/+0x60` 那一对（计数 + 串块）里，我方顶层原先没有这一对。")
    渲染器("// 本表就是补上的那一对：号 → 名（`取命令类别名`），表按 类别号 升序。")
    渲染器("//")
    渲染器("// **表可以为空**（源目录可缺 / 可空 ⇒ 空表 = 「本声明没有类别表」，不是漏写）。")
    渲染器("// 值域**已裁**：`1..23`，照易语言内核库 `krnln.fne` 的 `m_szzCategory` 那张 23 条类别表")
    渲染器("// （`契约声明/格式说明.md` §三·五）—— 生成器不替它编值域。`能力声明.类别` 用 `0` = **未分类**，")
    渲染器("// 合法：类别号是可选说明，查不到名不是错误（见下面 `取命令类别名`）。")
    渲染器("")
    for 命令类别项 in 命令类别表:
        渲染器("/// %s · 类别号 %d · 名称「%s」" % (命令类别项["相对路径"], 命令类别项["类别号"], 命令类别项["名称"]))
        渲染器("const 命令类别名_%s: &[u8] = %s.as_bytes();" % (命令类别项["词干"], 转字符串字面量(命令类别项["名称"] + "\0")))
        渲染器("const 命令类别说明_%s: &[u8] = %s.as_bytes();" % (命令类别项["词干"], 转字符串字面量(命令类别项["说明"] + "\0")))
    渲染器("")
    for 命令类别项 in 命令类别表:
        渲染器("/// 命令类别号 %d（源：%s 的「类别号」字段）。" % (命令类别项["类别号"], 命令类别项["相对路径"]))
        渲染器("pub const 命令类别_%s: u16 = %d;" % (命令类别项["词干"], 命令类别项["类别号"]))
        渲染器("")
    if 命令类别表:
        渲染器("/// 命令类别表（源：%s/*.json，共 %d 项，按 类别号 升序）。" % (根目录.命令类别, len(命令类别表)))
        渲染器("/// **`命令信息.类别` 的名字从这张表查**（见下面的 `取命令类别名`）。")
        渲染器("pub const 命令类别表: [v1_contract::命令类别信息; %d] = [" % len(命令类别表))
        for 命令类别项 in 命令类别表:
            渲染器("    // %s" % 命令类别项["相对路径"])
            渲染器("    v1_contract::命令类别信息 {")
            渲染器("        类别号: %d," % 命令类别项["类别号"])
            渲染器("        保留: 0,")
            渲染器("        名称: 取字节串指针(命令类别名_%s)," % 命令类别项["词干"])
            渲染器("        说明: 取字节串指针(命令类别说明_%s)," % 命令类别项["词干"])
            渲染器("    },")
        渲染器("];")
    else:
        渲染器("/// 命令类别表（源：%s/*.json）——**当前为空**。" % 根目录.命令类别)
        渲染器("/// 空 = 「本声明没有类别表」（源目录可缺 / 可空），不是漏写。值域**已裁** `1..23`")
        渲染器("/// （`契约声明/格式说明.md` §三·五）⇒ 生成器不替它编值域。")
        渲染器("pub const 命令类别表: [v1_contract::命令类别信息; 0] = [];")
    渲染器("")
    渲染器("/// `命令信息.类别` → 类别名（NUL 结尾）。**查不到返回空指针**（那是「本声明没有类别表」")
    渲染器("/// 或「这个号没登记」—— 如 `0` = 未分类，**不是错误**：类别号是可选说明，不是能力编号）。")
    渲染器("/// 表按 类别号 升序（生成期已判重号），线性查即可。")
    渲染器("pub const fn 取命令类别名(类别号: u16) -> *const u8 {")
    渲染器("    let mut 序号 = 0usize;")
