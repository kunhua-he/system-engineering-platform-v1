# -*- coding: utf-8 -*-
"""渲染数据表 —— 产物「二 数据类型表」·「二·五 能力编号」·「二·六 命令类别」三小节。"""

from .小工具 import 转字符串字面量


def 渲染类型表(渲染器, 根目录, 类型表):
    # ── 二 数据类型表 ──────────────────────────────────────────────────
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 二 数据类型表（源：%s/*.json，按 类型标签 升序）" % 根目录.类型声明)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    for 一项 in 类型表:
        渲染器("/// %s · 类型标签 %d · 名称「%s」" % (一项["相对路径"], 一项["类型标签"], 一项["名称"]))
        渲染器("const 类型名_%s: &[u8] = %s.as_bytes();" % (一项["词干"], 转字符串字面量(一项["名称"] + "\0")))
        渲染器("const 类型说明_%s: &[u8] = %s.as_bytes();" % (一项["词干"], 转字符串字面量(一项["说明"] + "\0")))
    渲染器("")
    渲染器("/// 各数据类型的**显式类型标签**常量（源：%s/*.json 的「类型标签」字段）。" % 根目录.类型声明)
    渲染器("/// 显式给标签，**不是**表内下标：下标会随合并顺序漂移，跨版本不稳定。")
    渲染器("/// 统一注册表 的 `类型标签_错误` 就引用这里的 `类型标签_4294967295`（不再硬写 u32::MAX）。")
    渲染器("/// 型是 `v1_contract::类型标签`（号空间 newtype）：用点直接拿到号空间型，不用再包一层。")
    for 一项 in 类型表:
        渲染器(
            "pub const 类型标签_%s: v1_contract::类型标签 = v1_contract::类型标签::新建(%d); // %s"
            % (一项["词干"], 一项["类型标签"], 一项["名称"])
        )
    渲染器("")
    渲染器("/// 数据类型信息 表（源：%s/*.json，共 %d 项，按 类型标签 升序）。" % (根目录.类型声明, len(类型表)))
    渲染器("/// 每一项的 `类型标签` 都来自 JSON，**不是**表内下标。")
    渲染器("pub const 底座类型表: [v1_contract::数据类型信息; %d] = [" % len(类型表))
    for 一项 in 类型表:
        渲染器("    // %s" % 一项["相对路径"])
        渲染器("    v1_contract::数据类型信息 {")
        渲染器("        名称: 取字节串指针(类型名_%s)," % 一项["词干"])
        渲染器("        说明: 取字节串指针(类型说明_%s)," % 一项["词干"])
        渲染器("        状态位: %d," % 一项["状态位"])
        渲染器("        命令个数: 0,")
        渲染器("        命令号表: core::ptr::null(),")
        渲染器("        事件个数: 0,")
        渲染器("        事件表: core::ptr::null(),")
        渲染器("        属性个数: 0,")
        渲染器("        属性表: core::ptr::null(),")
        渲染器("        元素个数: 0,")
        渲染器("        元素表: core::ptr::null(),")
        渲染器("        类型标签: v1_contract::类型标签::新建(%d)," % 一项["类型标签"])
        渲染器("    },")
    渲染器("];")
    渲染器("/// `平台信息.类型表` 直接可用：项数 + 项表。")
    渲染器("pub const fn 底座类型表段() -> v1_contract::表段<v1_contract::数据类型信息> {")
    渲染器("    v1_contract::表段::新建(底座类型表.as_ptr(), %d)" % len(类型表))
    渲染器("}")
    渲染器("")


def 渲染能力编号(渲染器, 根目录, 命令表):
    # ── 二·五 能力编号 ────────────────────────────────────────────────
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 二·五 能力编号（源：%s/*.json，按 编号 升序）" % 根目录.能力声明)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    渲染器("// `命令信息.编号` 是**显式字段**（不是表内下标）：注册表 `按号取命令` 按编号二分查找，")
    渲染器("// 建表要求命令表按 `编号` **严格递增**（生成器判重号 · 建表期再判一次，两边都 fail-closed）。")
    渲染器("// 号只增不复用、允许有洞（宪法第 7 条）。")
    渲染器("//")
    渲染器("// 这里逐条出**能力编号常量**：命令表（在实现侧，`装载入口` 手写）的 `编号` 字段引用它，")
    渲染器("// 于是「编号」的唯一来源是 `能力声明/<编号>.json`，不是实现侧的字面量。")
    渲染器("// 命令的名称 / 说明 / 参数表 / 可抛错误码 由**实现侧手写**（JSON 侧另有源），")
    渲染器("// 两者是否一致由「声明 ↔ 实现」那组判据（③a–③d）盯着 —— 不在本生成物的收口范围内。")
    渲染器("")
    for 一项 in 命令表:
        渲染器("/// 能力编号 %d · 名称「%s」· 参数 %d 个 · 返回类型 %d · 可抛错误码 %d 个"
            % (一项["编号"], 一项["名称"], len(一项["参数表"]), 一项["返回类型"], len(一项["可抛错误码"])))
        渲染器("/// 源：%s（文件名即编号）。" % 一项["相对路径"])
        渲染器("pub const 能力编号_%s: u32 = %d;" % (一项["词干"], 一项["编号"]))
        渲染器("")


def 渲染命令类别(渲染器, 根目录, 命令类别表):
    # ── 二·六 命令类别 ────────────────────────────────────────────────
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 二·六 命令类别（源：%s/*.json，按 类别号 升序）" % 根目录.命令类别)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    渲染器("// `命令信息.类别: u16` 若没有这张表，这个号在运行期**永远解不出名字** ——")
    渲染器("// 参照实现把它放在 `LIB_INFO +0x5C/+0x60` 那一对（计数 + 串块）里，我方顶层原先没有这一对。")
    渲染器("// 本表就是补上的那一对：号 → 名（`取命令类别名`），表按 类别号 升序。")
    渲染器("//")
    渲染器("// **表可以为空**（源目录可缺 / 可空 ⇒ 空表 = 「本声明没有类别表」，不是漏写）。")
    渲染器("// 值域**已裁**：`1..23`，照易语言内核库 `krnln.fne` 的 `m_szzCategory` 那张 23 条类别表")
    渲染器("// （`契约声明/格式说明.md` §三·五）—— 生成器不替它编值域。`能力声明.类别` 用 `0` = **未分类**，")
    渲染器("// 合法：类别号是可选说明，查不到名不是错误（见下面 `取命令类别名`）。")
    渲染器("")
    for 一项 in 命令类别表:
        渲染器("/// %s · 类别号 %d · 名称「%s」" % (一项["相对路径"], 一项["类别号"], 一项["名称"]))
        渲染器("const 命令类别名_%s: &[u8] = %s.as_bytes();" % (一项["词干"], 转字符串字面量(一项["名称"] + "\0")))
        渲染器("const 命令类别说明_%s: &[u8] = %s.as_bytes();" % (一项["词干"], 转字符串字面量(一项["说明"] + "\0")))
    渲染器("")
    for 一项 in 命令类别表:
        渲染器("/// 命令类别号 %d（源：%s 的「类别号」字段）。" % (一项["类别号"], 一项["相对路径"]))
        渲染器("pub const 命令类别_%s: u16 = %d;" % (一项["词干"], 一项["类别号"]))
        渲染器("")
    if 命令类别表:
        渲染器("/// 命令类别表（源：%s/*.json，共 %d 项，按 类别号 升序）。" % (根目录.命令类别, len(命令类别表)))
        渲染器("/// **`命令信息.类别` 的名字从这张表查**（见下面的 `取命令类别名`）。")
        渲染器("pub const 命令类别表: [v1_contract::命令类别信息; %d] = [" % len(命令类别表))
        for 一项 in 命令类别表:
            渲染器("    // %s" % 一项["相对路径"])
            渲染器("    v1_contract::命令类别信息 {")
            渲染器("        类别号: %d," % 一项["类别号"])
            渲染器("        保留: 0,")
            渲染器("        名称: 取字节串指针(命令类别名_%s)," % 一项["词干"])
            渲染器("        说明: 取字节串指针(命令类别说明_%s)," % 一项["词干"])
            渲染器("    },")
        渲染器("];")
    else:
        渲染器("/// 命令类别表（源：%s/*.json）——**当前为空**。" % 根目录.命令类别)
        渲染器("/// 空 = 「本声明没有类别表」（源目录可缺 / 可空），不是漏写。值域**已裁** `1..23`")
        渲染器("/// （`契约声明/格式说明.md` §三·五）⇒ 生成器不替它编值域。")
        渲染器("pub const 命令类别表: [v1_contract::命令类别信息; 0] = [];")
    渲染器("")
    渲染器("/// `命令信息.类别` → 类别名（NUL 结尾）。**查不到返回空指针**（那是「本声明没有类别表」")
    渲染器("/// 或「这个号没登记」—— 如 `0` = 未分类，**不是错误**：类别号是可选说明，不是能力编号）。")
    渲染器("/// 表按 类别号 升序（生成期已判重号），线性查即可。")
    渲染器("pub const fn 取命令类别名(类别号: u16) -> *const u8 {")
    渲染器("    let mut 序号 = 0usize;")
    渲染器("    while 序号 < 命令类别表.len() {")
    渲染器("        if 命令类别表[序号].类别号 == 类别号 {")
    渲染器("            return 命令类别表[序号].名称;")
    渲染器("        }")
    渲染器("        序号 += 1;")
    渲染器("    }")
    渲染器("    core::ptr::null()")
    渲染器("}")
    渲染器("")
