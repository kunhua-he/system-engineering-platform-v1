# -*- coding: utf-8 -*-
"""命令行 —— CLI 契约：用法行 · 帮助文本 · 主(参数)（三档退出码）。"""

import hashlib
import sys

from .路径形状 import 生成器相对路径, 生成失败, 默认声明根
from .检查 import 报提醒, 检查
from .生成流程 import 建声明根, 生成, 落盘路径


用法行 = "用法：python %s [--声明根 <目录>] [--检查]" % 生成器相对路径


def 帮助文本():
    return [
        用法行,
        "",
        "  --声明根 <目录>  一份声明自己的根目录。默认 %s。" % 默认声明根,
        "                  只认**仓内相对路径**：绝对路径会让产物带上机器相关前缀、破坏确定性，",
        "                  故解析到仓外即 fail-closed（不是警告，是拒绝生成）。",
        "                  根下面必须有（**形状固定，不随根变**）：",
        "                    平台声明.json —— 扩展那份叫 包声明.json，同形状，二者取其一",
        "                    号段图.json · 常量表.json · 作废号表.json",
        "                    类型声明/ · 能力声明/ · 错误码表/ · 通知号段/",
        "                  落盘到 <目录>/src/声明数据.rs（src/ 必须已存在）。",
        "                  底座用默认值 %s；扩展将来用同一生成器时传自己的声明根。" % 默认声明根,
        "  --检查          重新生成到内存，与落盘件逐字节比对（闸 4「生成物指纹」）。",
        "  -h / --帮助      本说明。",
        "",
        "不带参数 = 按声明根 %s 重新生成 %s/src/声明数据.rs。" % (默认声明根, 默认声明根),
    ]


def 主(参数):
    声明根参数 = 默认声明根
    检查模式 = False
    未知 = []
    序 = 0
    while 序 < len(参数):
        词 = 参数[序]
        if 词 == "--检查":
            检查模式 = True
        elif 词 in ("-h", "--帮助"):
            for 行 in 帮助文本():
                print(行)
            return 0
        elif 词 == "--声明根":
            if 序 + 1 >= len(参数):
                print("--声明根 后面要跟一个目录", file=sys.stderr)
                print(用法行, file=sys.stderr)
                return 2
            序 += 1
            声明根参数 = 参数[序]
        elif 词.startswith("--声明根="):
            声明根参数 = 词.split("=", 1)[1]
        else:
            未知.append(词)
        序 += 1
    if 未知:
        print("不认的参数：%s" % " ".join(sorted(未知)), file=sys.stderr)
        print(用法行, file=sys.stderr)
        return 2
    try:
        根 = 建声明根(声明根参数)
        if 检查模式:
            return 检查(根)
        新字节, 计数, 提醒 = 生成(根)
        with open(落盘路径(根), "wb") as 句柄:
            句柄.write(新字节)
        报提醒(提醒)
        print(
            "已生成 %s（%d 字节 · sha256 %s）"
            % (根.落盘件, len(新字节), hashlib.sha256(新字节).hexdigest())
        )
        print("  声明根：%s" % 根.根)
        print(
            "  覆盖：类型 %d · 命令 %d · 命令类别 %d · 错误码 %d · 通知号 %d · 作废号 %d · 能力号段 %d · 通知号段 %d · 错误段位 %d"
            % (
                计数["类型"],
                计数["命令"],
                计数["命令类别"],
                计数["错误码"],
                计数["通知号"],
                计数["作废号"],
                计数["能力号段"],
                计数["通知号段"],
                计数["错误段位"],
            )
        )
        print(
            "  常量表：共 %d 条 ⇒ 本表出常量 %d 条 · 交叉比对 %d 条 · 未定数显式跳过 %d 条"
            % (
                计数["常量表"],
                计数["常量本表出"],
                计数["常量交叉比对"],
                计数["常量未定数"],
            )
        )
        print(
            "  号段图推导：号段类宽度 %d · 号段类个数 %d"
            % (计数["号段类宽度"], 计数["号段类个数"])
        )
        return 0
    except 生成失败 as 错:
        print("生成失败（fail-closed，产物未动）：%s" % 错, file=sys.stderr)
        return 2
