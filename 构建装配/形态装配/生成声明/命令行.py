"""命令行 —— CLI 契约：用法行 · 帮助文本 · 入口函数(参数)（三档退出码）。"""

import hashlib
import os
import sys

from .路径形状 import 仓根, 生成器相对路径, 生成失败, 默认声明根
from .检查 import 报提醒, 检查
from .生成流程 import 建声明根, 生成声明, 落盘件表
from .渲染接缝 import 接缝路径, 渲染接缝, 读导出目标


用法文本 = "用法：python %s [--声明根 <目录>] [--检查] [--接缝]" % 生成器相对路径


def 帮助文本():
    return [
        用法文本,
        "",
        "  --声明根 <目录>  一份声明自身的根目录。默认 %s。" % 默认声明根,
        "                  只认**仓内相对路径**：绝对路径会让产物带上机器相关前缀、破坏确定性，",
        "                  故解析到仓外即 fail-closed（不是警告，是拒绝生成）。",
        "                  根下面必须有（**形状固定，不随根变**）：",
        "                    平台声明.json —— 扩展那份叫 包声明.json，同形状，二者取其一",
        "                    号段图.json · 常量表.json · 作废号表.json",
        "                    类型声明/ · 能力声明/ · 错误码表/ · 通知号段/",
        "                  落盘到 <目录>/src/声明数据.rs（src/ 必须已存在）。",
        "                  底座用默认值 %s；扩展将来用同一生成器时传自身的声明根。" % 默认声明根,
        "  --检查          重新生成到内存，与落盘件逐字节比对（闸 4「生成物指纹」）。",
        "  --接缝          只渲染接缝文件 <目录>/src/接缝.rs（由声明字段 `导出目标` 出",
        "                  `#[unsafe(export_name = …)]`）。可装载件（扩展）的声明根没有",
        "                  号段图/常量表/作废号表 ⇒ 跑不了整份生成，但接缝只需声明文件一个源。",
        "  -h / --帮助      本说明。",
        "",
        "不带参数 = 按声明根 %s 重新生成 %s/src/声明数据.rs。" % (默认声明根, 默认声明根),
    ]


def 出接缝(根目录, 检查模式):
    """`--接缝`：只渲染接缝文件 `<根>/src/接缝.rs`（不读号段图/常量表等平台级源）。"""
    导出目标, 来源 = 读导出目标(根目录)
    if 导出目标 is None:
        print("本声明不导出接缝（%s.导出目标 = null）⇒ 不出接缝文件" % 来源)
        return 0
    相对 = 接缝路径(根目录)
    落盘 = os.path.join(仓根, 相对)
    if not os.path.isdir(os.path.dirname(落盘)):
        raise 生成失败(
            "接缝落点目录不存在：%s —— 接缝要落进实现 crate 的 src/（%s 下没有 src/）。"
            "没有 src/ 的声明根（如技能：本体是 md，无实现）出不了接缝 ⇒ fail-closed"
            % (os.path.dirname(相对), 根目录.根)
        )
    新字节 = 渲染接缝(根目录, 导出目标).encode("utf-8")
    if 检查模式:
        if not os.path.isfile(落盘):
            print("接缝文件不存在：%s（跑一次 --接缝 生成）" % 相对)
            return 1
        with open(落盘, "rb") as 句柄:
            旧字节 = 句柄.read()
        if 旧字节 == 新字节:
            print("接缝新鲜：%s（%d 字节）" % (相对, len(新字节)))
            return 0
        print("接缝不新鲜：%s（落盘 %d 字节 · 重新生成 %d 字节）" % (相对, len(旧字节), len(新字节)))
        return 1
    with open(落盘, "wb") as 句柄:
        句柄.write(新字节)
    print("已生成 %s（%d 字节 · 接缝符号 %s）" % (相对, len(新字节), 导出目标))
    return 0


def 入口函数(参数):
    声明根参数 = 默认声明根
    检查模式 = False
    接缝模式 = False
    未知 = []
    序号 = 0
    while 序号 < len(参数):
        参数词 = 参数[序号]
        if 参数词 == "--检查":
            检查模式 = True
        elif 参数词 == "--接缝":
            接缝模式 = True
        elif 参数词 in ("-h", "--帮助"):
            for 源码行 in 帮助文本():
                print(源码行)
            return 0
        elif 参数词 == "--声明根":
            if 序号 + 1 >= len(参数):
                print("--声明根 后面要跟一个目录", file=sys.stderr)
                print(用法文本, file=sys.stderr)
                return 2
            序号 += 1
            声明根参数 = 参数[序号]
        elif 参数词.startswith("--声明根="):
            声明根参数 = 参数词.split("=", 1)[1]
        else:
            未知.append(参数词)
        序号 += 1
    if 未知:
        print("不认的参数：%s" % " ".join(sorted(未知)), file=sys.stderr)
        print(用法文本, file=sys.stderr)
        return 2
    try:
        根目录 = 建声明根(声明根参数)
        if 接缝模式:
            return 出接缝(根目录, 检查模式)
        if 检查模式:
            return 检查(根目录)
        新件, 计数, 提醒 = 生成声明(根目录)
        总字节 = 0
        for 相对 in 落盘件表(根目录):
            新字节 = 新件[相对]
            总字节 += len(新字节)
            with open(os.path.join(仓根, 相对), "wb") as 句柄:
                句柄.write(新字节)
            print(
                "已生成 %s（%d 字节 · sha256 %s）"
                % (相对, len(新字节), hashlib.sha256(新字节).hexdigest())
            )
        报提醒(提醒)
        print("共 %d 件（路由件 %s · 子件 %d 件 · 合计 %d 字节）"
              % (len(落盘件表(根目录)), 根目录.落盘件, len(落盘件表(根目录)) - 1, 总字节))
        print("  声明根：%s" % 根目录.根)
        print(
            "  覆盖：类型 %d · 命令 %d · 命令类别 %d · 错误码 %d · 通知号 %d · 作废号 %d · 能力号段 %d · 通知号段 %d · 错误段位 %d"
            % (
                计数["类型"],
                计数["命令"],
                计数["命令类别"],
                计数["错误码"],
                计数["通知号"],
                计数["作废号"],
                计数["能力号段"],
                计数["通知号段"],
                计数["错误段位"],
            )
        )
        print(
            "  常量表：共 %d 条 ⇒ 本表出常量 %d 条 · 交叉比对 %d 条 · 未定数显式跳过 %d 条"
            % (
                计数["常量表"],
                计数["常量本表出"],
                计数["常量交叉比对"],
                计数["常量未定数"],
            )
        )
        print(
            "  号段图推导：号段类宽度 %d · 号段类个数 %d"
            % (计数["号段类宽度"], 计数["号段类个数"])
        )
        return 0
    except 生成失败 as 错误:
        print("生成失败（fail-closed，产物未动）：%s" % 错误, file=sys.stderr)
        return 2
