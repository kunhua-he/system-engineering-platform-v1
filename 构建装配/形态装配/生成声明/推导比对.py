"""推导比对 —— 从 号段图.json 推导 号段类宽度 / 号段类个数，并与 常量表.json 交叉比对。

推导「稳不稳」：gcd 对**不等宽**的段不鲁棒 —— 只要冒出一段边界不是 号段类宽度 的整数倍
（例如某天加一段 1000–2500），gcd 就掉到 1，推出「宽度 1、个数 10000」。所以本生成器
**不单靠推导**：推出来的两个数必须与 `常量表.json` 的同名条目**交叉比对**，不一致即
fail-closed。有了这道闸，「不等宽的段」会当场报错，而不会静默换掉段位口径。
若哪天不等宽的段**确实合法**，那要裁的是模型本身（「一段 = 一个段位」不成立 ⇒ 段位改成
按段表二分定位，`常量表.json` 里的 号段类宽度/号段类个数 两条一并废弃），不是改推导。
"""

import math

from .号段归属 import 通知号段标签
from .常量表 import 常量表落点
from .路径形状 import 生成失败

推导规则 = """\
号段类宽度 = 全部段边界（每段的 `起` 与 `止 + 1`）的最大公约数（gcd）。
  依据：号段类宽度 = 「一个段位占多少个号」⇒ 每一段都由整数个段位拼成 ⇒ 每个段边界都是它的整数倍。
  满足这一条的数有无穷多个（gcd 的任一因子都行），取**最大**的那个（= gcd）：
  更细的因子会让「段位」比「0xxx 一段」更碎，与 `README.md` 第七节「号段即归属」的口径不符。
  本例的边界集与 gcd **不写死在这里** —— 见下一行「本例实测」，那一行由生成器按当前
  `号段图.json` 现算（写死一个例子，号段图一改这行注释就成了假的）。
号段类个数 = (最大 `止` + 1) ÷ 号段类宽度 = 段位上界 + 1。
推导源只取 `号段图.json.能力号段` —— **不许用 `通知号段`**：通知号的边界是
{1, 1000, 2000, 3000}，gcd = 1，推出来的宽度是 1（通知号与能力号是两个独立命名空间，
刻度本来就不是同一套）。"""

推导鲁棒性 = """\
**推导稳不稳（如实说）**：gcd 对**不等宽**的段不鲁棒 —— 只要冒出一段边界不是 `号段类宽度`
的整数倍（例如某天加一段 `1000–2500`），gcd 就掉到 1，会推出「宽度 1 · 个数 10000」。
所以本生成器**不单靠推导**：推出来的两个数必须与 `%s` 的同名条目**交叉比对**，
不一致即 fail-closed（见 `交叉比对`）。有了这道闸，不等宽的段会当场报错，
而不会静默换掉段位口径。
若哪天不等宽的段**确实合法**，要裁的是模型本身（「一段 = 一个段位」不成立 ⇒ 段位改成按段表
二分定位，`常量表.json` 的 `号段类宽度` / `号段类个数` 两条一并废弃），不是改推导。"""


def 推导号段类(号段图):
    """从 `号段图.json.能力号段` 推出 (号段类宽度, 号段类个数)。规则见 `推导规则`。

    **推不出来就 fail-closed**，不写一个「大概对」的推导：段边界 gcd = 1 意味着出现了
    不等宽 / 未对齐的段，那时「一段 = 一个段位」这个模型本身就塌了 —— 该由人裁
    （替代方案：按段表二分定位段位，或把号段图整成等宽），不该由生成器猜。
    """
    段表 = 号段图["能力号段"]
    边界 = []
    for 区间起点, 区间终点, _ in 段表:
        边界.append(区间起点)
        边界.append(区间终点 + 1)
    宽度 = 0
    for 待处理值 in 边界:
        宽度 = math.gcd(宽度, 待处理值)
    if 宽度 <= 1:
        raise 生成失败(
            "号段图.能力号段 的段边界 %s 的 gcd = %d ⇒ 推不出「号段类宽度」"
            "（段不等宽或未对齐，「一段 = 一个段位」的模型不成立）"
            " —— fail-closed，不猜。替代方案见生成器注释 `推导规则` 上方说明"
            % (" · ".join("%d" % 待处理值 for 待处理值 in sorted(set(边界))), 宽度)
        )
    最大止 = max(区间终点 for _, 区间终点, _ in 段表)
    if (最大止 + 1) % 宽度 != 0:
        raise 生成失败(
            "号段图.能力号段 的最大 止 = %d ⇒ 上界 %d 不是号段类宽度 %d 的整数倍"
            % (最大止, 最大止 + 1, 宽度)
        )
    个数 = (最大止 + 1) // 宽度
    return 宽度, 个数


def 推导过程(号段图):
    """推导过程的一行文字（进生成物注释，供追溯）。"""
    段表 = 号段图["能力号段"]
    边界 = sorted({待处理值 for 区间起点, 区间终点, _ in 段表 for 待处理值 in (区间起点, 区间终点 + 1)})
    宽度, 个数 = 推导号段类(号段图)
    最大止 = max(区间终点 for _, 区间终点, _ in 段表)
    return (
        "段边界集 {%s} ⇒ gcd = %d = 号段类宽度；最大 止 = %d ⇒ 段位上界 %d ⇒ 号段类个数 %d"
        % (" · ".join("%d" % 待处理值 for 待处理值 in 边界), 宽度, 最大止, 最大止 // 宽度, 个数)
    )


def 通知号段三段(号段归属, 根目录):
    """`通知号段` 模块的三段（下行 · 上行 · 生命周期），固定按此顺序出。缺一段即 fail-closed。

    顺序固定 = 产物确定；缺一段 = 契约层 `v1_contract::通知号段::..起/止` 没源，只能 fail-closed。
    """
    输出缓冲 = []
    for 标签 in 通知号段标签:
        if 标签 not in 号段归属:
            raise 生成失败(
                "%s.通知号段 里没有「%s」段（`归属` 前缀缺这个标签）⇒ 契约层的 "
                "`v1_contract::通知号段::%s起` / `%s止` 就没有源了 —— fail-closed"
                % (根目录.号段图, 标签, 标签, 标签)
            )
        起, 止, 归属 = 号段归属[标签]
        输出缓冲.append((标签, 起, 止, 归属))
    return 输出缓冲


def 常量表落点描述(一条, 根目录):
    """(生成物里的落点常量名, 值的源)。未定数 → 落点写「（未生成）」。"""
    if 一条["值"] is None:
        return "（未生成）", "未定数（值 = null）⇒ 显式跳过，名字进 `未定数常量`"
    落点 = 常量表落点.get(一条["名"])
    if 落点 is None:
        return 一条["名"], "本表即源（%s 的「%s」条目）" % (根目录.常量表, 一条["名"])
    if 一条["名"] in ("号段类宽度", "号段类个数"):
        return 落点[0], "%s.能力号段 推导（与 %s 交叉比对）" % (根目录.号段图, 根目录.常量表)
    return 落点[0], "%s.%s（与 %s 交叉比对）" % (根目录.声明文件, 一条["名"], 根目录.常量表)


def 交叉比对(常量表, 平台, 号段类, 根目录):
    """常量表里「值另有源」的 4 条：两源必须一致，不一致即 fail-closed。

    这 4 条在 常量表.json 与 平台声明.json / 号段图.json 各写了一份 —— 它们**必须**相等，
    否则就是「同一事实两个来源」已经漂移（段位口径半新半旧的后果是段归属判错）。
    """
    实际 = {
        "声明格式号": (平台["声明格式号"], 32),
        "目标字宽": (平台["目标字宽"], 16),
        "号段类宽度": (号段类[0], 32),
        "号段类个数": (号段类[1], 32),
    }
    for 一条 in 常量表:
        if 一条["值"] is None or 一条["名"] not in 常量表落点:
            continue
        名, _ = 常量表落点[一条["名"]]
        真值, 真宽 = 实际[一条["名"]]
        if 一条["值"] != 真值:
            raise 生成失败(
                "%s 的「%s」= %d，但生成物里 `%s` 的值是 %d ⇒ 同一事实两个来源已漂移"
                % (根目录.常量表, 一条["名"], 一条["值"], 名, 真值)
            )
        if 一条["位宽"] != 真宽:
            raise 生成失败(
                "%s 的「%s」位宽 = %s，但 `%s` 的位宽是 %d"
                % (根目录.常量表, 一条["名"], 一条["位宽"], 名, 真宽)
            )
