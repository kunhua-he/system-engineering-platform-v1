# -*- coding: utf-8 -*-
"""渲染调用任务 —— 图任务协议派生件（`调用任务数据.rs`）。

**唯一来源**：`契约声明/调用任务协议.json`。渲染三样：
① 阶段/操作/错误类别 —— 枚举 + 码常量（`码` 是线上值，改名不改码）
② 字段名 —— 文本常量（请求/回执两侧按它取键，不各写一份字面量）
③ 可转换表 —— `可转换(从, 到)` 一个**表驱动**判定，内核不再自带 `matches!`

**为什么是表驱动**：跃迁规则是协议的一部分。写在 Rust 里就成了「JSON 一份、Rust 一份」，
改一处不改另一处即静默分叉（本项目已因同类问题吃过亏：两处枚举各写一套，谁也不知道谁生效）。
"""


def _枚举名(名):
    """中文标识符直接用（本项目铁律：正式代码用中文名）。"""
    return 名


def 渲染调用任务(渲染器, 根目录, 协议):
    if 协议 is None:
        return
    源 = 协议["相对路径"]
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 八 调用任务协议（源：%s）" % 源)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 图任务的唯一声明源派生件：任务/节点阶段、任务操作、错误类别、字段名、可转换表。")
    渲染器("// 改协议只改那份 JSON 再重跑生成器；**不许在 Rust 里手抄第二份**。")
    渲染器("")

    # ── 枚举与码常量 ────────────────────────────────────────────────
    枚举说明 = (
        ("任务操作", "调用任务操作"),
        ("任务阶段", "调用任务阶段"),
        ("节点阶段", "调用节点阶段"),
        ("错误类别", "调用任务错误"),
    )
    for 小节, 类型名 in 枚举说明:
        项表 = 协议[小节]
        渲染器("/// %s（源：%s 的「%s」，共 %d 项）。" % (类型名, 源, 小节, len(项表)))
        渲染器("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
        渲染器("pub enum %s {" % 类型名)
        for 项 in 项表:
            渲染器("    /// 码 %d。%s" % (项["码"], " ".join(项["说明"].split()) or "（无说明）"))
            渲染器("    %s," % _枚举名(项["名"]))
        渲染器("}")
        渲染器("")
        渲染器("impl %s {" % 类型名)
        渲染器("    /// 线上码（协议里冻结的整数；改名不改码）。")
        渲染器("    pub const fn 码(self) -> u32 {")
        渲染器("        match self {")
        for 项 in 项表:
            渲染器("            Self::%s => %d," % (项["名"], 项["码"]))
        渲染器("        }")
        渲染器("    }")
        渲染器("")
        渲染器("    /// 全部取值（按协议顺序）。")
        渲染器("    pub const 全部: &'static [Self] = &[%s];"
              % ", ".join("Self::%s" % 项["名"] for 项 in 项表))
        渲染器("")
        渲染器("    /// 文本名（线上用中文名逐字比，不用码猜）。")
        渲染器("    pub const fn 名(self) -> &'static str {")
        渲染器("        match self {")
        for 项 in 项表:
            渲染器('            Self::%s => "%s",' % (项["名"], 项["名"]))
        渲染器("        }")
        渲染器("    }")
        渲染器("}")
        渲染器("")

    # ── 字段名常量 ─────────────────────────────────────────────────
    字段说明 = (
        ("提交字段", "提交字段"),
        ("节点字段", "节点字段"),
        ("输入引用字段", "输入引用字段"),
        ("控制字段", "控制字段"),
        ("回执字段", "回执字段"),
        ("回执节点字段", "回执节点字段"),
        ("错误字段", "错误字段"),
    )
    for 小节, 前缀 in 字段说明:
        项表 = 协议[小节]
        渲染器("/// %s的键名（源：%s 的「%s」）。必填以注释标出，判定在接口面。" % (前缀, 源, 小节))
        渲染器("pub mod %s名 {" % 前缀)
        for 项 in 项表:
            渲染器("    /// %s%s" % ("必填 · " if 项["必填"] else "可选 · ",
                                 " ".join(项["说明"].split()) or "（无说明）"))
            渲染器('    pub const %s: &str = "%s";' % (项["名"], 项["名"]))
        渲染器("}")
        渲染器("")

    # ── 可转换表 ───────────────────────────────────────────────────
    if 协议["可转换表"]:
        渲染器("/// 节点阶段的合法跃迁表（源：%s 的「可转换表」）。" % 源)
        渲染器("///")
        渲染器("/// 判定只有一个实现：查这张表。内核不许再写一份 `matches!` —— ")
        渲染器("/// 两份规则必然分叉，而分叉时没有任何闸能同时看见两边。")
        渲染器("pub const 可转换表: &[(调用节点阶段, &[调用节点阶段])] = &[")
        for 项 in 协议["可转换表"]:
            到 = ", ".join("调用节点阶段::%s" % 目标 for 目标 in 项["到"])
            渲染器("    (调用节点阶段::%s, &[%s])," % (项["从"], 到))
        渲染器("];")
        渲染器("")
        渲染器("/// 这一跃迁合不合法（表里查得到就是合法）。")
        渲染器("pub fn 可转换(从: 调用节点阶段, 到: 调用节点阶段) -> bool {")
        渲染器("    可转换表")
        渲染器("        .iter()")
        渲染器("        .any(|(起点, 目标表)| *起点 == 从 && 目标表.contains(&到))")
        渲染器("}")
        渲染器("")
