# -*- coding: utf-8 -*-
"""读调用任务 —— 图任务协议（`契约声明/调用任务协议.json`）。

**为什么单独一件**：本表与「文件名即编号」的那几张子表不同形 —— 它是一份**协议描述**
（任务操作 / 任务阶段 / 节点阶段 / 可转换表 / 字段 / 错误类别），不是每条一个文件的号表。
故不与 `读子表.py` 混住：读法、形状、校验口径都不一样。

**只校验形状，不判语义**：阶段码是否连续、跃迁是否覆盖每个阶段，都属语义，
放闸 1 的判据面判（本件不重复一份，同 `读子表.py::读通知号段` 的口径）。
"""

import os

from ..生成编排.路径形状 import 仓根, 生成失败
from ..生成编排.生成小工具 import 读JSON件, 取串, 取表, 取整

# 各小节的键名与形状（唯一落点：改协议描述只改本表 + 那份 JSON）。
枚举小节 = ("任务操作", "任务阶段", "节点阶段", "错误类别")
字段小节 = ("提交字段", "节点字段", "输入引用字段", "控制字段", "回执字段", "回执节点字段", "错误字段")


def _取枚举(文档, 小节, 相对路径):
    """`{名, 码, 说明}` 列表；名/码/说明三样都必须齐。"""
    项表 = 取表(文档, 小节, 相对路径)
    输出 = []
    已见码 = {}
    for 序号, 项 in enumerate(项表):
        名 = 取串(项, "名", "%s 第 %d 项" % (相对路径, 序号 + 1), 允许空=False)
        if not 名:
            raise 生成失败("%s：%s 第 %d 项的 名 是空串" % (相对路径, 小节, 序号 + 1))
        if 名 in [项已见["名"] for 项已见 in 输出]:
            raise 生成失败("%s：%s 里 名 重复：%s" % (相对路径, 小节, 名))
        码 = 取整(项, "码", "%s 第 %d 项" % (相对路径, 序号 + 1), 0, 255)
        if 码 in 已见码:
            raise 生成失败(
                "%s：%s 里 码 %d 被「%s」与「%s」共用（同号两义 = 第二套含义）"
                % (相对路径, 小节, 码, 已见码[码], 名)
            )
        已见码[码] = 名
        输出.append({
            "名": 名,
            "码": 码,
            "说明": 取串(项, "说明", "%s 第 %d 项" % (相对路径, 序号 + 1), 允许空=True),
        })
    return 输出


def _取字段(文档, 小节, 相对路径):
    """`{名, 类型, 必填, 说明}` 列表。"""
    项表 = 取表(文档, 小节, 相对路径)
    输出 = []
    for 序号, 项 in enumerate(项表):
        位置 = "%s 第 %d 项" % (相对路径, 序号 + 1)
        输出.append({
            "名": 取串(项, "名", 位置, 允许空=False),
            "类型": 取串(项, "类型", 位置, 允许空=False),
            "必填": 项.get("必填") is True,
            "说明": 取串(项, "说明", 位置, 允许空=True),
        })
    return 输出


def _取跃迁(文档, 相对路径):
    """`{从: str, 到: [str]}` 列表。"""
    表 = 文档.get("可转换表")
    if not isinstance(表, dict):
        raise 生成失败("%s：可转换表 必须是对象（{说明, 跃迁}）" % 相对路径)
    项表 = 取表(表, "跃迁", "%s 可转换表" % 相对路径)
    输出 = []
    for 序号, 项 in enumerate(项表):
        位置 = "%s 可转换表 第 %d 项" % (相对路径, 序号 + 1)
        到表 = 取表(项, "到", 位置)
        if not 到表:
            raise 生成失败("%s：到 是空表（一条跃迁没有任何目标）" % 位置)
        for 序号2, 目标 in enumerate(到表):
            if not isinstance(目标, str) or 目标 == "":
                raise 生成失败("%s：到 第 %d 项不是非空文本" % (位置, 序号2 + 1))
        输出.append({"从": 取串(项, "从", 位置, 允许空=False), "到": list(到表)})
    return 输出


def 读调用任务协议(根目录):
    """返回协议描述字典；文件不存在 ⇒ 空（底座以外的声明根可以不写这张表）。"""
    相对路径 = 根目录.调用任务协议
    if not os.path.isfile(os.path.join(仓根, 相对路径)):
        return None
    文档 = 读JSON件(相对路径)
    输出 = {"相对路径": 相对路径, "可转换表": _取跃迁(文档, 相对路径)}
    for 小节 in 枚举小节:
        输出[小节] = _取枚举(文档, 小节, 相对路径)
    for 小节 in 字段小节:
        输出[小节] = _取字段(文档, 小节, 相对路径)
    return 输出
