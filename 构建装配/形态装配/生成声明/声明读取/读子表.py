def 读子表项(源码行, 键名, 相对路径, 序号, 合法标签):
    """读一条子表项并校形 —— 四张子表同形 `{名称, 类型标签, 说明}`（§四）。"""
    出错位置 = "%s 的「%s」第 %d 项" % (相对路径, 键名, 序号)
    if not isinstance(源码行, dict):
        raise 生成失败("%s 不是对象（§四 形状 = %s）：%r" % (出错位置, " · ".join(子表项键), 源码行))
    缺字段 = [键名 for 键名 in 子表项键 if 键名 not in 源码行]
    if 缺字段:
        raise 生成失败("%s 缺字段 %s（§四 形状 = %s）" % (出错位置, " · ".join(缺字段), " · ".join(子表项键)))
    标签 = 取整(源码行, "类型标签", 出错位置, 0, 0xFFFFFFFF)
    if 标签 not in 合法标签:
        raise 生成失败("%s 的「类型标签」%d 在类型表里查不到（合法域 = 本声明类型表 ∪ 底座已登记标签 = %s）" % (出错位置, 标签, sorted(合法标签)))
    return {"名称": 取串(源码行, "名称", 出错位置), "类型标签": 标签, "说明": 取串(源码行, "说明", 出错位置, 允许空=True)}


def 读子表集(文档, 相对路径, 合法标签):
    """读四张子表，逐项校形（§四）。空表合法（原行为不变）。

    **名称不判唯一** —— 依据与实测代价见件头「为什么不判重名」。
    """
    输出缓冲 = {}
    for 键名 in 未定义的子表:
        子表 = 取表(文档, 键名, 相对路径)
        输出缓冲[键名] = [读子表项(源码行, 键名, 相对路径, 序号, 合法标签) for 序号, 源码行 in enumerate(子表, 1)]
    return 输出缓冲


def 读类型声明(根目录):
    """返回按 类型标签 升序的表。文件名 = 类型标签。

    四张子表**同形**（§四），逐项校形（名称非空 · 类型标签在类型表里查得到 · 说明可空）；合法域 =
    本声明类型表 ∪ 底座已登记标签（`标签登记.rs` 同口径）⇒ 两趟：先收齐本声明全部标签，再逐件校形（元素可引用后面才声明的标签）。"""
    声明条目表 = []
    for 文件名, 相对路径 in 列目录JSON件(根目录.类型声明):
        词干 = 文件名[: -len(".json")]
        if not 词干.isdigit():
            raise 生成失败("%s 的文件名不是十进制编号：%s" % (根目录.类型声明, 文件名))
        文档 = 读JSON件(相对路径)
        标签 = 取整(文档, "类型标签", 相对路径, 0, 0xFFFFFFFF)
        if 标签 != int(词干):
            raise 生成失败("%s：文件名 %s 与「类型标签」%d 不一致（文件名即类型标签）" % (相对路径, 词干, 标签))
        声明条目表.append((词干, 相对路径, 标签, 文档))
    if not 声明条目表:
        raise 生成失败("%s 下没有任何类型声明" % 根目录.类型声明)
    合法标签 = {标签 for _, _, 标签, _ in 声明条目表} | 读底座类型标签()
    输出缓冲 = [
        {"词干": 词干, "相对路径": 相对路径, "类型标签": 标签, "名称": 取串(文档, "名称", 相对路径),
         "说明": 取串(文档, "说明", 相对路径), "状态位": 取整(文档, "状态位", 相对路径, 0, 0xFFFFFFFF),
         **读子表集(文档, 相对路径, 合法标签)}
        for 词干, 相对路径, 标签, 文档 in 声明条目表
    ]
    输出缓冲.sort(key=lambda 类型项: (类型项["类型标签"], 类型项["词干"]))
    return 输出缓冲


def 读默认值槽(源码行, 出错位置):
    """读一个参数行的「默认值」槽 —— 三态（未提供 · 空值 · 显式默认）＋ 文本承载。

    形状 = `契约声明/格式说明.md` §三 的 `默认值{类型标签,值}` 的**兼容扩展**：
    **旧键 `值` 仍只装整数、含义一字未改**；文本默认值走**新增键** `文本`（文本串）。
    旧读者读 `值` 拿不到文本 —— 那是「承载得了」，不是「改写旧字段」。

    三态（W01 第三节裁：「区分 未提供 · 空值 · 显式默认」）：
      · 键 `默认值` 缺                ⇒ **未提供**（该参数没有默认值）
      · `类型标签` == 0               ⇒ **空值**（§四：`0` 是保留标签「空」，不是「没填」）
      · `类型标签` != 0 · 有 `值`（整数）⇒ **显式默认**（整数）
      · `类型标签` != 0 · 有 `文本`（串）⇒ **显式默认**（文本）
    「值」与「文本」**只居其一** —— 都给即 fail-closed（同一槽两种值形状 = 一份数据两套读法）。

    ★ **放宽的一处**：旧代码对「缺 `默认值` 键」fail-closed；此处放宽成三态之一
    （未提供）。这是把「没有默认值」从「报错」变成一个**可表达的状态**，
    不改任何旧字段的含义；仓内现有声明**全部给了 `默认值`**，故无存量受影响。
    """
    if "默认值" not in 源码行:
        return {"默认值标签": 0, "默认值值": 0, "默认值文本": "", "默认值情形": "未提供"}
    默认值 = 源码行["默认值"]
    if not isinstance(默认值, dict):
        raise 生成失败(
            "%s 的「默认值」不是对象（§三 形状 {类型标签, 值}；文本默认值加键「文本」）：%r"
            % (出错位置, 默认值)
        )
    标签 = 取整(默认值, "类型标签", 出错位置 + ".默认值", 0, 0xFFFFFFFF)
    if 标签 == 0:
        if "文本" in 默认值 or ("值" in 默认值 and 取整(默认值, "值", 出错位置) != 0):
            raise 生成失败("%s：空值不能携带文本或非零载荷" % 出错位置)
        return {"默认值标签": 0, "默认值值": 0, "默认值文本": "", "默认值情形": "空值"}
    if 标签 != 取整(源码行, "类型标签", 出错位置):
        raise 生成失败("%s：默认值类型与参数类型不一致" % 出错位置)
    if 标签 not in (1, 2, 3, 4, 6):
        raise 生成失败("%s：该类型的显式默认值载荷尚未定义" % 出错位置)
    if ("值" in 默认值) and ("文本" in 默认值):
        raise 生成失败(
            "%s 同时给了「值」与「文本」：两者只居其一"
            "（整数默认值走「值」· 文本默认值走「文本」）—— fail-closed"
            % (出错位置 + ".默认值")
        )
    if (标签 == 4) != ("文本" in 默认值):
        raise 生成失败("%s：文本标签只接受文本载荷，其他标签只接受整数位载荷" % 出错位置)
    if 标签 == 3 and 默认值.get("值") not in (0, 1):
        raise 生成失败("%s：逻辑默认值只接受0或1" % 出错位置)
    if "文本" in 默认值:
        默认文本 = 默认值.get("文本")
        if not isinstance(默认文本, str):
            raise 生成失败("%s 的「文本」不是字符串：%r" % (出错位置 + ".默认值", 默认文本))
        try:
            默认文本.encode("utf-8")
        except UnicodeEncodeError:
            raise 生成失败("%s：文本默认值不能编码为UTF-8" % 出错位置)
        return {
            "默认值标签": 标签,
            "默认值值": 0,
            "默认值文本": 默认文本,
            "默认值情形": "显式默认",
        }
    return {
        "默认值标签": 标签,
        "默认值值": 取整(默认值, "值", 出错位置 + ".默认值", 0, 0xFFFFFFFFFFFFFFFF),
        "默认值文本": "",
        "默认值情形": "显式默认",
    }


def 读能力声明(根目录):
    """读 `<声明根>/能力声明/*.json`（**本声明自身的**命令声明），按 `编号` 升序。

    形状按 `契约声明/格式说明.md` §三：
      {编号, 名称, 说明, 类别, 状态位, 返回类型, 用户级别,
       参数表[{名称,说明,类型标签,状态位,默认值{类型标签,值|文本}}], 可抛错误码[码…]}
    （`默认值` 的文本键是**兼容扩展**，见 `读默认值槽`。）

    **一份声明根装它自身的声明**（§一 ★）：底座 = `契约声明/`；扩展 = 它自身目录里的
    `能力声明/`（编译器扩展已是这么落的）。故本函数读的是「本声明自身的命令」，不读别处。

    为什么生成器要认它：`命令信息.编号`（显式）与 `命令信息.可抛错误码` 的唯一来源就是
    这份 JSON。**没有读方的声明等于零**，故本函数逐条消费它、出成命令表（见渲染 二·五）。

    **表按编号严格递增**是注册表「按编号二分查找」的前提：这里判重复（fail-closed）。
    """
    输出缓冲 = []
    for 文件名, 相对路径 in 列目录JSON件(根目录.能力声明):
        词干 = 文件名[: -len(".json")]
        if not 词干.isdigit():
            raise 生成失败("%s 的文件名不是十进制编号：%s" % (根目录.能力声明, 文件名))
        文档 = 读JSON件(相对路径)
        编号 = 取整(文档, "编号", 相对路径, 0, 0xFFFFFFFF)
        if 编号 != int(词干):
            raise 生成失败(
                "%s：文件名 %s 与「编号」%d 不一致（文件名即编号）" % (相对路径, 词干, 编号)
            )
        参数表 = 取表(文档, "参数表", 相对路径)
        参数出 = []
        for 序号, 源码行 in enumerate(参数表):
            出错位置 = "%s.参数表[%d]" % (相对路径, 序号)
            if not isinstance(源码行, dict):
                raise 生成失败("%s 不是对象" % 出错位置)
            参数出.append(
                {
                    "名称": 取串(源码行, "名称", 出错位置),
                    "说明": 取串(源码行, "说明", 出错位置),
                    "类型标签": 取整(源码行, "类型标签", 出错位置, 0, 0xFFFFFFFF),
                    "状态位": 取整(源码行, "状态位", 出错位置, 0, 0xFFFF),
                    **读默认值槽(源码行, 出错位置),
                }
            )
        可抛 = 取表(文档, "可抛错误码", 相对路径)
        可抛出 = []
        for 序号, 错误码 in enumerate(可抛):
            if isinstance(错误码, bool) or not isinstance(错误码, int) or not (0 <= 错误码 <= 9999):
                raise 生成失败(
                    "%s.可抛错误码[%d] 不是 0–9999 的码（§五：码是完整 4 位号）：%r"
                    % (相对路径, 序号, 错误码)
                )
            可抛出.append(错误码)
        输出缓冲.append(
            {
                "编号": 编号,
                "词干": 词干,
                "相对路径": 相对路径,
                "名称": 取串(文档, "名称", 相对路径),
                "说明": 取串(文档, "说明", 相对路径),
                "类别": 取整(文档, "类别", 相对路径, 0, 0xFFFF),
                "状态位": 取整(文档, "状态位", 相对路径, 0, 0xFFFF),
                "返回类型": 取整(文档, "返回类型", 相对路径, 0, 0xFFFFFFFF),
                "用户级别": 取整(文档, "用户级别", 相对路径, 0, 0xFFFF),
                "参数表": 参数出,
                "可抛错误码": 可抛出,
            }
        )
    输出缓冲.sort(key=lambda 命令项: (命令项["编号"], 命令项["词干"]))
    编号s = [命令项["编号"] for 命令项 in 输出缓冲]
    if len(set(编号s)) != len(编号s):
        raise 生成失败(
            "%s 下有两份能力声明用了同一个编号 ⇒ 注册表按编号查找会撞号"
            "（号只增不复用、允许有洞，但同一声明里不许重号）—— fail-closed" % 根目录.能力声明
        )
    return 输出缓冲


def 读命令类别(根目录):
    """读 `<声明根>/命令类别/*.json`（**本声明自身的**命令类别表），按 `类别号` 升序。

    形状（`契约声明/格式说明.md` §三·五）：`{类别号, 名称, 说明}`。文件名 = 类别号 ——
    它就是 `命令信息.类别: u16` 那个号。

    **为什么要有它**：`命令信息.类别` 若没有「类别号 → 类别名」表，这个号在运行期**永远解不出
    名字**（参照实现把它放在 `LIB_INFO +0x5C/+0x60` 那一对里 —— 字节级实测见
    `项目文档/设计文档/接缝实测.md` §二/§三）。故本函数逐条消费它、出成 `命令类别表`
    （见渲染 二·六），并出 `取命令类别名` 供运行期查。

    **目录不存在 / 表为空都不 fail-closed**：类别号的**值域已裁 = 1..23**
    （取自参照实现的类别表，不发明；`契约声明/格式说明.md` §三·五），生成器**不替它编值域**。
    空表 = 「表在（机制已通）」，不是漏写 —— 与「静默跳过」不是一回事
    （名字仍进生成物的注释与空表）。
    """
    if not os.path.isdir(os.path.join(仓根, 根目录.命令类别)):
        return []
    输出缓冲 = []
    for 文件名, 相对路径 in 列目录JSON件(根目录.命令类别):
        词干 = 文件名[: -len(".json")]
        if not 词干.isdigit():
            raise 生成失败("%s 的文件名不是十进制编号：%s" % (根目录.命令类别, 文件名))
        文档 = 读JSON件(相对路径)
        类别号 = 取整(文档, "类别号", 相对路径, 0, 0xFFFF)
        if 类别号 != int(词干):
            raise 生成失败(
                "%s：文件名 %s 与「类别号」%d 不一致（文件名即类别号）" % (相对路径, 词干, 类别号)
            )
        输出缓冲.append(
            {
                "类别号": 类别号,
                "词干": 词干,
                "相对路径": 相对路径,
                "名称": 取串(文档, "名称", 相对路径),
                "说明": 取串(文档, "说明", 相对路径),
            }
        )
    输出缓冲.sort(key=lambda 命令类别项: (命令类别项["类别号"], 命令类别项["词干"]))
    号s = [命令类别项["类别号"] for 命令类别项 in 输出缓冲]
    if len(set(号s)) != len(号s):
        raise 生成失败(
            "%s 下有两份命令类别用了同一个类别号 ⇒ 「按号查名」会撞号 —— fail-closed" % 根目录.命令类别
        )
    return 输出缓冲


