# 作废号表的「号空间」值域：`作废号空间` 引主人
# `构建装配/一键验证/一键验证/基础定义/判据取值常量.py::号空间值域`（值域为何是这五个、五个空间为何互不相通，
# 理由写在主人那处的注释里，本件不复述）。
# 一个号在哪个空间里作废，就只在**那个空间**里不可再用 —— 数字相同不算同号
# （能力号 16 与 错误码 16 是两回事；类型标签 0 与能力号 0 同理）。判定只比同空间的号。


def 读作废号表(根目录):
    """→ {号空间: [编号…]（升序）}，五个空间都在（没有行的给空表）。

    每一行**必须**带 `号空间`（值域 `作废号空间`）—— 它是「这个号在哪个空间里作废」的
    唯一依据。缺了 / 不在值域 ⇒ fail-closed：不带空间的作废行只能被**全局**排除，
    而那正是实测的假冲突（错误码 `16` 被当成能力号 `16`，底座 `能力号段 0–999` 自身撞自身）。
    去重按**空间**分别判：同一个数字可以在不同空间各作废一次（那是两个号）。
    """
    来源 = 根目录.作废号表
    文档 = 读JSON件(来源)
    作废 = 取表(文档, "作废", 来源)
    输出缓冲 = {号空间: [] for 号空间 in 作废号空间}
    for 序号, 源码行 in enumerate(作废):
        出错位置 = "%s.作废[%d]" % (来源, 序号)
        if not isinstance(源码行, dict):
            raise 生成失败("%s 不是对象" % 出错位置)
        号空间 = 取串(源码行, "号空间", 出错位置)
        if 号空间 not in 作废号空间:
            raise 生成失败(
                "%s 的「号空间」是 %r；只认 %s 之一（五个号空间互不相通，见 %s 的"
                "「四个号空间互不相通」＋ %s §七 的「值域五个」）。没有它，这个号会被五个"
                "空间**一起**排除 —— 那正是「错误码 16 撞上底座 能力号段 0–999」的假冲突"
                "（实测 31 条红）"
                % (出错位置, 号空间, " · ".join(作废号空间), 根目录.号段图, "契约声明/格式说明.md")
            )
        输出缓冲[号空间].append(取整(源码行, "编号", 出错位置, 0, 0xFFFFFFFF))
    for 号空间 in 作废号空间:
        输出缓冲[号空间].sort()
        if len(set(输出缓冲[号空间])) != len(输出缓冲[号空间]):
            raise 生成失败("%s 里「号空间」= %s 的作废编号有重复" % (来源, 号空间))
    return 输出缓冲
