"""渲染常量推导 —— 产物「六 平台常量表」与「七 号段图推导」两小节。"""

from .号段归属 import 资源号段两段
from .常量表 import 常量表落点
from .推导比对 import 推导规则, 推导鲁棒性, 推导过程, 通知号段三段, 常量表落点描述
from .小工具 import 注释行, 转字符串字面量


def 渲染常量表(渲染器, 根目录, 常量表):
    # ── 六 平台常量表 ──────────────────────────────────────────────────
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 六 平台常量表（源：%s，共 %d 条）" % (根目录.常量表, len(常量表)))
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    渲染器("// 判据（`%s` 的「判据」键，按**名**匹配，两条）：" % 根目录.常量表)
    渲染器("//   ① 同一个常量名不许在别处再定义 —— 实现侧必须引用本表生成的常量；")
    渲染器("//   ② 本表每条常量在生成物里**要么有对应常量、要么有显式的「未定数」标注**。")
    渲染器("// 故本节**逐条**给落点，一条不漏；值一律从落点那一处取，本表不另存一份值。")
    渲染器("//")
    渲染器("// 名 → 生成物里的落点 · 值的源：")
    for 条 in 常量表:
        落点, 来源 = 常量表落点描述(条, 根目录)
        渲染器("//   %-12s %-16s %s" % (条["名"], 落点, 来源))
    渲染器("")

    交叉条 = [条 for 条 in 常量表 if 条["值"] is not None and 条["名"] in 常量表落点]
    if 交叉条:
        渲染器("// ── 以下 %d 条的**值另有源**：常量出在对应小节，常量表这一份只做交叉比对 ──"
            % len(交叉条))
        for 条 in 交叉条:
            落点, 来源 = 常量表落点描述(条, 根目录)
            渲染器("//   %s → `%s`（%s）" % (条["名"], 落点, 来源))
        渲染器("")

    本表条 = [条 for 条 in 常量表 if 条["值"] is not None and 条["名"] not in 常量表落点]
    if 本表条:
        渲染器("// ── 以下 %d 条**本表即唯一的源**：逐条出常量，每条上方带它的「依据」 ──"
            % len(本表条))
        渲染器("")
    for 条 in 本表条:
        渲染器("/// %s = %d（u%d）。" % (条["名"], 条["值"], 条["位宽"]))
        渲染器("/// 源：%s 的「%s」条目（本表即唯一的源；别处再写一份同名的就是第二来源）。"
            % (根目录.常量表, 条["名"]))
        渲染器(注释行("依据：" + 条["依据"]))
        渲染器("pub const %s: u%d = %d;" % (条["名"], 条["位宽"], 条["值"]))
        渲染器("")

    未定条 = [条 for 条 in 常量表 if 条["值"] is None]
    if 未定条:
        渲染器("/// 常量表里**未定数**（`值` = null）的条目名。")
        渲染器("/// 生成器**显式跳过**它们，并把名字留在这里 —— **不是静默跳过**")
        渲染器("/// （静默跳过 = 一份没有任何效果的声明，最坏）。")
        渲染器("/// 谁要判「常量表是否已全部落地」，读这张表即可；定数后把值填进")
        渲染器("/// `%s` 重跑生成器，本表即空、对应常量即出。" % 根目录.常量表)
        for 条 in 未定条:
            渲染器("/// - %s：%s" % (条["名"], " ".join(条["依据"].split())))
        渲染器(
            "pub const 未定数常量: &[&str] = &[%s];"
            % ", ".join(转字符串字面量(条["名"]) for 条 in 未定条)
        )
    else:
        渲染器("/// 常量表里**未定数**（`值` = null）的条目名 —— 当前为空：全部条目都已落地。")
        渲染器("pub const 未定数常量: &[&str] = &[];")
    渲染器("")


def 渲染号段推导(渲染器, 根目录, 号段图, 号段类, 号段归属):
    # ── 七 号段图推导 ──────────────────────────────────────────────────
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 七 号段图推导（源：%s）" % 根目录.号段图)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    渲染器("// `号段类宽度` / `号段类个数` 从 `号段图.json.能力号段` 推出。**推导规则逐字**：")
    for 一行 in 推导规则.split("\n"):
        渲染器(注释行(一行))
    for 一行 in (推导鲁棒性 % 根目录.常量表).split("\n"):
        渲染器(注释行(一行))
    渲染器("//")
    渲染器("// 本例实测：%s" % 推导过程(号段图))
    渲染器("")
    渲染器("/// 号段类宽度：一个段位占多少个号（`0xxx` 一段）。")
    渲染器("/// 源：%s.能力号段 的段边界 gcd（与 %s 的「号段类宽度」条目交叉比对）。"
        % (根目录.号段图, 根目录.常量表))
    渲染器("pub const 号段类宽度: u32 = %d;" % 号段类[0])
    渲染器("")
    渲染器("/// 号段类个数：段位上界 + 1（`0xxx`–`9xxx` ⇒ 10）。")
    渲染器("/// 源：%s.能力号段（与 %s 的「号段类个数」条目交叉比对）。" % (根目录.号段图, 根目录.常量表))
    渲染器("pub const 号段类个数: u32 = %d;" % 号段类[1])
    渲染器("")
    渲染器("/// 通知号的三个号段（源：%s.通知号段，按 `归属` 前缀取标签）。" % 根目录.号段图)
    渲染器("/// 这是**全平台布局**（每个方向占哪一段），不是任何一份声明的占用。")
    渲染器("/// `契约声明/src/lib.rs` 的 `v1_contract::通知号段` 就是 `pub use` 本模块 ——")
    渲染器("/// **路径名不变，值只有一个来源**（手写的那 6 个区间常量已删，不留别名）。")
    渲染器("pub mod 通知号段 {")
    for 标签, 起, 止, 归属 in 通知号段三段(号段归属, 根目录):
        渲染器("    /// %s" % " ".join(归属.split()))
        渲染器("    pub const %s起: u32 = %d;" % (标签, 起))
        渲染器("    pub const %s止: u32 = %d;" % (标签, 止))
    渲染器("}")
    渲染器("")
    渲染器("/// 资源号的两个号段（源：%s.资源号段）。" % 根目录.号段图)
    渲染器("/// 这是**全平台布局**：资源号与能力号 / 通知号 / 错误码各占一套区间，**互不相通**。")
    渲染器("/// 资源网关口据此判「这个号该由扩展声明还是平台声明」——")
    渲染器("/// 没有它，关口只能自身手写一份区间（同一事实两个来源）。")
    渲染器("pub mod 资源号段 {")
    for 标签, 起, 止, 归属 in 资源号段两段(号段图, 根目录):
        渲染器("    /// %s" % " ".join(归属.split()))
        渲染器("    pub const %s起: u32 = %d;" % (标签, 起))
        渲染器("    pub const %s止: u32 = %d;" % (标签, 止))
    渲染器("}")
    渲染器("")
