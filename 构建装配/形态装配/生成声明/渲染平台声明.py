# -*- coding: utf-8 -*-
"""渲染平台声明 —— 产物「一 平台声明」小节（格式号 / 标识串 / 版本 / 名称说明 / 占用号段 / 错误段位）。"""

from .小工具 import 转字符串字面量
from .读平台声明 import 查归属


def 渲染平台声明(渲染器, 根目录, 平台, 号段图):
    # ── 一 平台声明 ────────────────────────────────────────────────────
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 一 平台声明（源：%s）" % 根目录.声明文件)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    渲染器("/// 声明格式号：**格式的身份证，不是版本号**。格式不变，它永远不变。")
    渲染器("/// 源：%s.声明格式号（与 %s 的「声明格式号」条目交叉比对，不一致即 fail-closed）。"
        % (根目录.声明文件, 根目录.常量表))
    渲染器("pub const 底座声明格式号: v1_contract::格式号 = v1_contract::格式号::新建(%d);" % 平台["声明格式号"])
    渲染器("")
    渲染器("/// 标识串内容（32 位十六进制，不含 NUL）——比对用。")
    渲染器('pub const 底座标识串内容: &[u8] = b"%s";' % 平台["标识串"])
    渲染器("/// 标识串（32 位十六进制 + NUL）——交给契约主结构用。")
    渲染器('pub const 底座标识串: &[u8] = b"%s\\0";' % 平台["标识串"])
    渲染器("")
    if 平台["提供宿主版本"] is None:
        渲染器("// 本份声明（扩展那份 `包声明.json`）**没有** `提供宿主版本` / `提供内核版本` —— 扩展侧这两个键")
        渲染器("// 没有消费者（判定 ④ 只拿**底座**的「提供*」去比扩展的「要求*」，而 `平台信息` 里没有「提供*」字段），")
        渲染器("// 按准入判据 ⑧ 是死键，形状里已删（`扩展装载/开发标准/必备件.json`）。")
        渲染器("// 故本份生成物**不出** `底座提供宿主版本` / `底座提供内核版本` 两个常量 —— 不是漏出，是扩展侧没有这一对。")
        渲染器("")
    for 名, 键, 型, 说明 in (
        ("实现版本", "实现版本", "版本三元组", "实现版本（本声明自身的版本）"),
        ("要求宿主版本", "要求宿主版本", "版本要求", "**要求**的宿主版本（本声明要什么；无修订段）"),
        ("要求内核版本", "要求内核版本", "版本要求", "**要求**的内核版本（本声明要什么；无修订段）"),
        ("提供宿主版本", "提供宿主版本", "版本三元组", "**提供**的宿主版本（判定 ④ 的据：本声明拿什么版本去比扩展的「要求宿主版本」）"),
        ("提供内核版本", "提供内核版本", "版本三元组", "**提供**的内核版本（判定 ④ 的据）"),
    ):
        号段 = 平台[键]
        if 号段 is None:
            continue  # 扩展侧的死键：不出常量（见上面的注释）
        渲染器("/// %s（源：%s.%s）。" % (说明, 根目录.声明文件, 键))
        实参 = ", ".join("%d" % 一 for 一 in 号段)
        渲染器(
            "pub const 底座%s: v1_contract::%s = v1_contract::%s::新建(%s);"
            % (名, 型, 型, 实参)
        )
        渲染器("")
    渲染器("/// 目标字宽（源：%s.目标字宽；与 %s 的「目标字宽」条目交叉比对）。"
        % (根目录.声明文件, 根目录.常量表))
    渲染器("pub const 底座目标字宽: u16 = %d;" % 平台["目标字宽"])
    渲染器("")
    渲染器("/// 名称（源：%s.名称）。" % 根目录.声明文件)
    渲染器("pub const 底座名称: &[u8] = %s.as_bytes();" % 转字符串字面量(平台["名称"] + "\0"))
    渲染器("/// 说明（源：%s.说明）。" % 根目录.声明文件)
    渲染器("pub const 底座说明: &[u8] = %s.as_bytes();" % 转字符串字面量(平台["说明"] + "\0"))
    渲染器("")
    # 注：声明字段 `导出目标` **不进本生成物**（`平台信息` 里没有这个字段）—— 它是编译期的
    # 选择，由生成器渲染成接缝文件 `根目录.接缝件` 的 `#[unsafe(export_name = …)]`（`--接缝`）。
    # 故这里不产出任何常量、也不加注释行（加行会让生成物行数涨过行数基线）。

    段表说明 = (
        ("能力号段", "底座能力号段", "底座**本声明占用**的能力号段（源：%s.能力号段，共 %d 段）。"),
        ("通知号段", "底座通知号段", "底座**本声明占用**的通知号段（源：%s.通知号段，共 %d 段）。"),
    )
    for 键, 常量名, 模板 in 段表说明:
        一项 = 平台[键]
        渲染器("/// " + 模板 % (根目录.声明文件, len(一项)))
        渲染器("/// 注意：这是「本声明占用」的段，不是全平台布局（全平台布局在 %s，不进 `平台信息`）。" % 根目录.号段图)
        渲染器("pub const %s: [v1_contract::号段; %d] = [" % (常量名, len(一项)))
        宽度 = max(len("v1_contract::号段::新建(%d, %d)," % (起, 止)) for 起, 止, _ in 一项)
        for 起, 止, _ in 一项:
            归属 = 查归属(起, 止, 号段图, 键)
            渲染器(
                "    %-*s%s"
                % (
                    宽度 + 1,
                    "v1_contract::号段::新建(%d, %d)," % (起, 止),
                    ("// 号段图归属：%s" % " ".join(归属.split())) if 归属 else "",
                )
            )
        渲染器("];")
        渲染器("/// `平台信息.%s` 直接可用：项数 + 项表。" % 键)
        渲染器(
            "pub const fn %s表段() -> v1_contract::表段<v1_contract::号段> {"
            % 常量名
        )
        渲染器("    v1_contract::表段::新建(%s.as_ptr(), %d)" % (常量名, len(一项)))
        渲染器("}")
        渲染器("")

    段位项 = 平台["错误段位表"]
    渲染器("/// 底座登记的错误段位（源：%s.错误段位表，共 %d 项）。" % (根目录.声明文件, len(段位项)))
    渲染器("/// 段位 = 码的首位十进制数字，也即能力号段的首位；段位 0 = 内核自有（码 1..999）。")
    渲染器("pub const 底座错误段位表: [u32; %d] = [" % len(段位项))
    宽度 = max(len("%d," % 值) for 值 in 段位项)
    for 待处理值 in 段位项:
        渲染器("    %-*s // 段位 %d：码 %d..%d" % (宽度, "%d," % 待处理值, 待处理值, 待处理值 * 1000, 待处理值 * 1000 + 999))
    渲染器("];")
    渲染器("/// `平台信息.错误段位表` 直接可用：项数 + 项表。")
    渲染器("pub const fn 底座错误段位表段() -> v1_contract::表段<u32> {")
    渲染器("    v1_contract::表段::新建(底座错误段位表.as_ptr(), %d)" % len(段位项))
    渲染器("}")
    渲染器("")
