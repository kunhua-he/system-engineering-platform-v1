# -*- coding: utf-8 -*-
"""资源声明 · 读声明 —— 读 `<根>/资源声明/*.json` 并做**形状校验**。

**只判「形状」，不判「语义」**（一处口径，不许两套）：本件 fail-closed 在 JSON 键齐不齐 /
类型对不对 / 枚举值认不认得 / `入口.路径` 有没有（§三 规则 3）/ `需要副作用` 有没有
（`操作声明.需要副作用` 是 `Option`：`None` = 漏写 ⇒ 关口拒）。**语义**（资源号在不在号段 ·
隔离自不自洽 · 副作用覆盖够不够）留给关口的 `资源声明::校验` —— 那是唯一实现，本件不复制。
"""

import os

from ..路径形状 import 仓根, 生成失败
from ..小工具 import 读JSON件, 源指纹
from .路径与枚举 import (
    顶层键,
    操作键,
    入口键,
    允许键,
    隔离键,
    载体表,
    崩溃影响面表,
    副作用表,
    源目录,
)


def _查未知键(文档, 允许键, 来源):
    多余 = sorted(键名 for 键名 in 文档 if 键名 not in 允许键)
    if 多余:
        raise 生成失败(
            "%s 有多余的键：%s（资源声明的键名逐字对应 `资源声明` 的字段名；"
            "多余的键没有读方 —— 要么是拼错，要么是发明了一个字段）⇒ fail-closed"
            % (来源, " · ".join(多余))
        )


def _取对象(容器, 键名, 来源):
    待处理值 = 容器.get(键名)
    if not isinstance(待处理值, dict):
        raise 生成失败("%s 的「%s」不是对象：%r" % (来源, 键名, 待处理值))
    return 待处理值


def _取数组(容器, 键名, 来源):
    待处理值 = 容器.get(键名)
    if not isinstance(待处理值, list):
        raise 生成失败("%s 的「%s」不是数组：%r" % (来源, 键名, 待处理值))
    return 待处理值


def _取整(容器, 键名, 来源, 下界=None):
    待处理值 = 容器.get(键名)
    if isinstance(待处理值, bool) or not isinstance(待处理值, int):
        raise 生成失败("%s 的「%s」不是整数：%r" % (来源, 键名, 待处理值))
    if 下界 is not None and 待处理值 < 下界:
        raise 生成失败("%s 的「%s」=%d 小于 %d" % (来源, 键名, 待处理值, 下界))
    return 待处理值


def _取串(容器, 键名, 来源):
    待处理值 = 容器.get(键名)
    if not isinstance(待处理值, str) or 待处理值 == "":
        raise 生成失败("%s 的「%s」必须是非空字符串：%r" % (来源, 键名, 待处理值))
    return 待处理值


def _取逻辑(容器, 键名, 来源):
    待处理值 = 容器.get(键名)
    if not isinstance(待处理值, bool):
        raise 生成失败("%s 的「%s」不是逻辑型：%r" % (来源, 键名, 待处理值))
    return 待处理值


def _取枚举(容器, 键名, 来源, 合法值):
    待处理值 = 容器.get(键名)
    if 待处理值 not in 合法值:
        raise 生成失败(
            "%s 的「%s」=%r 不在合法值里（%s）—— 这些名字逐字来自 跨语言适配/资源网关口/"
            "src/声明形状/，不许发明" % (来源, 键名, 待处理值, " / ".join(合法值))
        )
    return 待处理值


def 读一条(文档, 来源):
    """一条资源声明 JSON → 规范化 dict（键序固定）。**只判形状**。"""
    if not isinstance(文档, dict):
        raise 生成失败("%s 顶层不是对象" % 来源)
    _查未知键(文档, 顶层键, 来源)

    入口 = _取对象(文档, "入口", 来源)
    _查未知键(入口, 入口键, 来源)
    # §三 规则 3：入口不写进声明仓。写了即拒（不是警告）。
    if 入口.get("路径") is not None:
        raise 生成失败(
            "%s 的 入口.路径 = %r：§三 规则 3 明写「入口不写进声明仓」（声明说『怎么调』、"
            "部署说『调哪一份』）—— 填了即拒（关口也会判 `入口写进声明仓`）⇒ fail-closed"
            % (来源, 入口.get("路径"))
        )
    载体 = _取枚举(入口, "载体", 来源 + ".入口", 载体表)

    操作表 = _取数组(文档, "操作", 来源)
    if not 操作表:
        raise 生成失败("%s 的「操作」是空数组：§三 规则 1 的 `操作` 是白名单，空表 = 这个资源什么都做不了" % 来源)
    操作 = []
    for 序号, 操作声明项 in enumerate(操作表):
        源2 = "%s.操作[%d]" % (来源, 序号)
        if not isinstance(操作声明项, dict):
            raise 生成失败("%s 不是对象：%r" % (源2, 操作声明项))
        _查未知键(操作声明项, 操作键, 源2)
        副作用 = _取数组(操作声明项, "需要副作用", 源2)
        for 副作用名 in 副作用:
            if 副作用名 not in 副作用表:
                raise 生成失败("%s.需要副作用 里 %r 不在合法值里（%s）" % (源2, 副作用名, " / ".join(副作用表)))
        操作.append(
            {
                "操作号": _取整(操作声明项, "操作号", 源2),
                "名": _取串(操作声明项, "名", 源2),
                "输入类型": _取整(操作声明项, "输入类型", 源2),
                "输出类型": _取整(操作声明项, "输出类型", 源2),
                # 超时毫秒 `0` 即拒（`操作声明.超时毫秒`：没有预算就是「默认允许」）⇒ 下界 1。
                "超时毫秒": _取整(操作声明项, "超时毫秒", 源2, 下界=1),
                "需要副作用": 副作用,
            }
        )

    允许 = _取对象(文档, "允许", 来源)
    _查未知键(允许, 允许键, 来源)
    隔离 = _取对象(文档, "隔离", 来源)
    _查未知键(隔离, 隔离键, 来源)

    return {
        "资源号": _取整(文档, "资源号", 来源),
        "标识": _取串(文档, "标识", 来源),
        "种类": _取串(文档, "种类", 来源),
        "入口": {"载体": 载体},
        "操作": 操作,
        # `允许` 四个开关**都要显式给**（§三 规则 2：默认全 false；不许靠默认值 ——
        # 「默认能用」是最危险的默认值，靠默认值就没人写它了）。
        "允许": {键名: _取逻辑(允许, 键名, 来源 + ".允许") for 键名 in ("读文件", "写文件", "联网", "派生进程")},
        "隔离": {
            "载体": _取枚举(隔离, "载体", 来源 + ".隔离", 载体表),
            "可重建": _取逻辑(隔离, "可重建", 来源 + ".隔离"),
            "崩溃影响面": _取枚举(隔离, "崩溃影响面", 来源 + ".隔离", 崩溃影响面表),
        },
        "留痕": _取逻辑(文档, "留痕", 来源),
    }


def 读资源声明(根目录):
    """读 `<根>/资源声明/*.json`。→ (声明表, 指纹行)。**次序 = 文件名升序**（确定性）。"""
    目录 = 源目录(根目录)
    绝对 = os.path.join(仓根, 目录)
    if not os.path.isdir(绝对):
        raise 生成失败(
            "资源声明的源目录不存在：%s\n"
            "  本件只认这一条源（一文件一条资源声明）：%s/*.json ⇒ fail-closed（不猜别的落点）"
            % (目录, 目录)
        )
    名单 = sorted(名称 for 名称 in os.listdir(绝对) if 名称.endswith(".json"))
    声明表, 指纹行, 已见号 = [], [], {}
    for 名称 in 名单:
        相对 = 目录 + "/" + 名称
        文档 = 读JSON件(相对)
        资源声明项 = 读一条(文档, 相对)
        # 同一份声明根里资源号不许重复（关口的 `从声明根` 也会判 `资源号重复`）。
        # 本件先判一次：重号会让生成的清单在同一根里自相矛盾，那是源错，不是运行期的事。
        if 资源声明项["资源号"] in 已见号:
            raise 生成失败(
                "%s 的 资源号 %d 与 %s 重复（同一份声明根里资源号必须唯一）⇒ fail-closed"
                % (相对, 资源声明项["资源号"], 已见号[资源声明项["资源号"]])
            )
        已见号[资源声明项["资源号"]] = 相对
        声明表.append(资源声明项)
        指纹行.append((相对, 源指纹(相对)))
    return 声明表, 指纹行
