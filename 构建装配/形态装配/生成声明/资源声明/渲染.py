# -*- coding: utf-8 -*-
"""资源声明 · 渲染 —— 把规范化后的声明表渲染成 `<根>/src/资源声明.rs` 的文本。

只引用 `v1_resource_gateway` 的**公开面**（`跨语言适配/资源网关口/src/lib.rs` 的 `pub use`）：
`资源声明` · `操作声明` · `入口声明` · `允许表` · `隔离声明` · `载体` · `崩溃影响面` ·
`副作用` · `副作用集`。符号名逐字照抄，不发明。
"""

from ..小工具 import 转字符串字面量
from .路径与枚举 import 生成器相对路径, 源目录
from .读声明 import 读资源声明


def _渲染副作用(列表, 缩进):
    """`需要副作用: Option<副作用集>`。空表 ⇒ `Some(副作用集::空)`；非空 ⇒ 逐项 `并入`。"""
    if not 列表:
        return [缩进 + "需要副作用: Some(副作用集::空),"]
    输出缓冲 = [缩进 + "需要副作用: Some({", 缩进 + "    let mut 集 = 副作用集::空;"]
    for 一项 in 列表:
        输出缓冲.append("%s    集.并入(副作用::%s);" % (缩进, 一项))
    输出缓冲.extend([缩进 + "    集", 缩进 + "}),"])
    return 输出缓冲


def _渲染一条(一条):
    输出缓冲 = [
        "        资源声明 {",
        "            资源号: %d," % 一条["资源号"],
        "            标识: %s," % 转字符串字面量(一条["标识"]),
        "            种类: %s," % 转字符串字面量(一条["种类"]),
        "            入口: 入口声明::仅载体(载体::%s)," % 一条["入口"]["载体"],
        "            操作: vec![",
    ]
    for 操作 in 一条["操作"]:
        输出缓冲.append("                操作声明 {")
        输出缓冲.append("                    操作号: %d," % 操作["操作号"])
        输出缓冲.append("                    名: %s," % 转字符串字面量(操作["名"]))
        输出缓冲.append("                    输入类型: %d," % 操作["输入类型"])
        输出缓冲.append("                    输出类型: %d," % 操作["输出类型"])
        输出缓冲.append("                    超时毫秒: %d," % 操作["超时毫秒"])
        输出缓冲.extend(_渲染副作用(操作["需要副作用"], "                    "))
        输出缓冲.append("                },")
    输出缓冲.append("            ],")
    允许开关 = 一条["允许"]
    输出缓冲.append(
        "            允许: 允许表 { 读文件: %s, 写文件: %s, 联网: %s, 派生进程: %s },"
        % (str(允许开关["读文件"]).lower(), str(允许开关["写文件"]).lower(), str(允许开关["联网"]).lower(), str(允许开关["派生进程"]).lower())
    )
    隔离配置 = 一条["隔离"]
    输出缓冲.append(
        "            隔离: 隔离声明 { 载体: 载体::%s, 可重建: %s, 崩溃影响面: 崩溃影响面::%s },"
        % (隔离配置["载体"], str(隔离配置["可重建"]).lower(), 隔离配置["崩溃影响面"])
    )
    输出缓冲.append("            留痕: %s," % str(一条["留痕"]).lower())
    输出缓冲.append("        },")
    return 输出缓冲


def 渲染资源声明(根目录):
    """渲染 `<根>/src/资源声明.rs` 的文本（bytes 由调用方编）。"""
    声明表, 指纹行 = 读资源声明(根目录)
    源码行 = [
        "// 生成物，禁手改。要改请改源并重跑生成器。",
        "// 源：%s/*.json（%d 条）" % (源目录(根目录), len(声明表)),
        "// 生成器：%s" % 生成器相对路径,
        "//",
        "// 本件把「资源声明 JSON」渲染成进程内的 `资源声明`：关口**不解析 JSON**（零第三方依赖），",
        "// JSON → 声明这一步是**声明侧**的生成物动作（`跨语言适配/资源网关口/src/lib.rs` 缺口 1）。",
        "// 语义校验（资源号号段 · 隔离自洽 · 副作用覆盖）在关口 `资源声明::校验`，本件不复制。",
        "//",
        "// 源指纹：",
    ]
    for 相对, 待处理值 in 指纹行:
        源码行.append("//   %s = %s" % (相对, 待处理值))
    源码行.extend(
        [
            "use v1_resource_gateway::{",
            "    崩溃影响面, 副作用, 副作用集, 入口声明, 隔离声明, 允许表, 操作声明, 载体, 资源声明,",
            "};",
            "",
            "/// 本声明根里的全部资源声明（次序 = 文件名升序，确定性）。",
            "pub fn 声明根() -> Vec<资源声明> {",
        ]
    )
    if not 声明表:
        源码行.append("    Vec::new()")
    else:
        源码行.append("    vec![")
        for 一条 in 声明表:
            源码行.extend(_渲染一条(一条))
        源码行.append("    ]")
    源码行.extend(["}", ""])
    return "\n".join(源码行)
