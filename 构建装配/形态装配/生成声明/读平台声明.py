# -*- coding: utf-8 -*-
"""读平台声明 —— 读 `<声明根>/平台声明.json`（扩展叫 `包声明.json`）与 `<声明根>/号段图.json`。

「本声明占用」与「全平台布局」是两件事：前者在 平台声明/包声明，后者在 号段图。
号段图**不进 `平台信息`**，故本生成物不据它产出任何「全平台号段图」常量。
"""

import os

from .路径形状 import 仓根, 生成失败
from .小工具 import 读JSON件, 取整, 取串, 取表, 版本三元组, 版本要求
from .渲染接缝 import 校验导出目标


def 读号段表(一项, 来源, 键名):
    """一张「号段表」。每项必须有 起/止；`归属` 是**可选**的说明字段。

    2026-09-26 实测：`归属` 已从 平台声明.json 的号段表里挪走（落到 号段图.json），
    所以这里不许把 归属 当必填——否则源一动生成器就瞎。
    """
    输出缓冲 = []
    for 序号, 源码行 in enumerate(一项):
        if not isinstance(源码行, dict):
            raise 生成失败("%s.%s[%d] 不是对象" % (来源, 键名, 序号))
        出错位置 = "%s.%s[%d]" % (来源, 键名, 序号)
        区间起点 = 取整(源码行, "起", 出错位置, 0, 0xFFFFFFFF)
        区间终点 = 取整(源码行, "止", 出错位置, 0, 0xFFFFFFFF)
        if 区间起点 > 区间终点:
            raise 生成失败("%s 起 %d 大于 止 %d" % (出错位置, 区间起点, 区间终点))
        归属 = 源码行.get("归属")
        if 归属 is not None and not isinstance(归属, str):
            raise 生成失败("%s 的「归属」不是字符串：%r" % (出错位置, 归属))
        输出缓冲.append((区间起点, 区间终点, 归属))
    return 输出缓冲


def 选声明文件(根目录):
    """定下本声明根里的**声明文件**：`平台声明.json` 优先，其次 `包声明.json`。

    底座那份叫 `平台声明.json`，扩展那份叫 `包声明.json` —— **同形状，只是名字不同**
    （`契约声明/格式说明.md` 第二节 · 扩展装载/开发标准）。两个都没有即 fail-closed。
    """
    for 相对路径 in (根目录.平台声明, 根目录.包声明):
        if os.path.isfile(os.path.join(仓根, 相对路径)):
            return 相对路径
    raise 生成失败(
        "声明根 %s 里既没有 %s 也没有 %s ⇒ 没有声明可读（fail-closed）"
        % (根目录.根, 根目录.平台声明, 根目录.包声明)
    )


def 读平台声明(根目录):
    来源 = 根目录.声明文件
    文档 = 读JSON件(来源)
    if not isinstance(文档, dict):
        raise 生成失败("%s 顶层不是对象" % 来源)

    声明格式号 = 取整(文档, "声明格式号", 来源, 0, 0xFFFFFFFF)

    本扩展标识串 = 取串(文档, "标识串", 来源)
    if len(本扩展标识串) != 32 or any(字符 not in "0123456789abcdefABCDEF" for 字符 in 本扩展标识串):
        raise 生成失败("%s 的「标识串」必须是 32 位十六进制：%r" % (来源, 本扩展标识串))
    本扩展标识串 = 本扩展标识串.lower()

    目标字宽 = 取整(文档, "目标字宽", 来源, 0, 65535)
    if 目标字宽 not in (32, 64):
        raise 生成失败("%s 的「目标字宽」只能是 32 或 64：%d" % (来源, 目标字宽))

    段表 = {}
    for 键名 in ("能力号段", "通知号段"):
        一项 = 取表(文档, 键名, 来源)
        if not 一项:
            raise 生成失败("%s 的「%s」是空表" % (来源, 键名))
        段表[键名] = 读号段表(一项, 来源, 键名)

    错误段位 = 取表(文档, "错误段位表", 来源)
    if not 错误段位:
        raise 生成失败("%s 的「错误段位表」是空表" % 来源)
    段位表 = []
    for 序号, 待处理值 in enumerate(错误段位):
        if isinstance(待处理值, bool) or not isinstance(待处理值, int) or not (0 <= 待处理值 <= 9):
            raise 生成失败("%s.错误段位表[%d] 不是 0–9 的段位：%r" % (来源, 序号, 待处理值))
        段位表.append(待处理值)

    # 「提供宿主版本 / 提供内核版本」：**只有底座侧有消费者**（判定 ④ 拿**底座**的「提供*」去比
    # 扩展的「要求*」；`平台信息` 里根本没有「提供*」字段）。故按准入判据 ⑧，扩展侧（`包声明.json`）
    # 这两个键是**死键**，形状里不许有（`扩展装载/开发标准/必备件.json`）。
    # 落地口径：底座那份（`平台声明.json`）**必须**有（缺即 fail-closed，判定 ④ 的据不能没有源）；
    # 扩展那份**不许**有 —— 生成器**不要求**它有（否则扩展按 必备件.json 删了键就跑不了生成器，
    # 那条路是断的），也不为它出「提供*」常量（没有消费者）。扩展侧若仍带着这两个键 ⇒ 生成器
    # 报**提醒**（不是 fail-closed：删键是扩展作者的动作，不该卡住生成）。
    是底座声明 = 根目录.声明文件 == 根目录.平台声明
    if 是底座声明:
        提供宿主版本 = 版本三元组(文档.get("提供宿主版本"), 来源 + ".提供宿主版本")
        提供内核版本 = 版本三元组(文档.get("提供内核版本"), 来源 + ".提供内核版本")
    else:
        提供宿主版本 = None
        提供内核版本 = None

    # 导出目标：本声明导出哪个接缝符号（形状与语义见 `契约声明/格式说明.md` §二·五）。
    # 校验只有一处（`渲染接缝.py::校验导出目标`）—— 底座不导出（null），扩展必须给符号名；
    # 整份生成与 `--接缝` 读同一处口径，不许两套读法。
    导出目标 = 校验导出目标(文档.get("导出目标"), 来源, 是底座声明)

    return {
        "声明格式号": 声明格式号,
        "标识串": 本扩展标识串,
        "实现版本": 版本三元组(文档.get("实现版本"), 来源 + ".实现版本"),
        "要求宿主版本": 版本要求(文档.get("要求宿主版本"), 来源 + ".要求宿主版本"),
        "要求内核版本": 版本要求(文档.get("要求内核版本"), 来源 + ".要求内核版本"),
        # 判定 ④ 的据：本声明**提供**的宿主/内核版本。与「要求宿主/内核版本」（本声明**要什么**）
        # 是两个概念，2026-09-26 起 JSON 里两对都有源，不再手写。
        # **扩展侧是 None**（死键，见上）：渲染时跳过，不出常量。
        "提供宿主版本": 提供宿主版本,
        "提供内核版本": 提供内核版本,
        # 扩展侧还带着这两个死键吗（真则生成时报提醒，见 `生成`）。
        "扩展侧含提供键": (not 是底座声明)
        and (文档.get("提供宿主版本") is not None or 文档.get("提供内核版本") is not None),
        "名称": 取串(文档, "名称", 来源),
        "说明": 取串(文档, "说明", 来源),
        "目标字宽": 目标字宽,
        "能力号段": 段表["能力号段"],
        "通知号段": 段表["通知号段"],
        "错误段位表": 段位表,
        # 本声明导出的接缝符号名（`None` = 不导出）。见上「导出目标」。
        "导出目标": 导出目标,
    }


def 读号段图(根目录):
    """全平台的编号布局（`<声明根>/号段图.json`）。

    **它不进 `平台信息`** —— `平台信息` 里没有「全平台布局」这个字段。所以本生成物
    不据它产出任何「全平台号段图」常量（留一份就是第二个来源）；据它产出的是四样
    **从布局能唯一推出来**的数与区间（见 `推导号段类` 与 `渲染` 第七节）：
    `号段类宽度` · `号段类个数` · 通知号的三个方向号段 · 资源号的两个号段。此外它还给占用段配 `归属` 注释、
    并校验「占用 ⊆ 布局」。

    它是必需源：没有它，「声明只能占布局里已有的段」这条判据无从落点。
    """
    if not os.path.isfile(os.path.join(仓根, 根目录.号段图)):
        raise 生成失败(
            "%s 不在。它是「声明只能占布局里已有的段」这条判据的依据"
            "（占用 ⊆ 布局），也是 `号段类宽度`/`号段类个数` 与通知号三个方向号段的推导源，"
            "缺了就没法判 —— fail-closed" % 根目录.号段图
        )
    文档 = 读JSON件(根目录.号段图)
    if not isinstance(文档, dict):
        raise 生成失败("%s 顶层不是对象" % 根目录.号段图)
    输出缓冲 = {}
    for 键名 in ("能力号段", "通知号段", "资源号段"):
        一项 = 取表(文档, 键名, 根目录.号段图)
        if not 一项:
            raise 生成失败("%s 的「%s」是空表" % (根目录.号段图, 键名))
        输出缓冲[键名] = 读号段表(一项, 根目录.号段图, 键名)
    return 输出缓冲


def 判并集覆盖(布局段表, 区间起点, 区间终点):
    """`[起, 止]` 是否整个落在 布局段表 的并集里（先把相邻段归并，再判包含）。"""
    归并 = []
    for 段起, 段止, _ in sorted(布局段表):
        if 归并 and 段起 <= 归并[-1][1] + 1:
            归并[-1][1] = max(归并[-1][1], 段止)
        else:
            归并.append([段起, 段止])
    return any(区间低端 <= 区间起点 and 区间终点 <= 区间高端 for 区间低端, 区间高端 in 归并)


def 判占用落在布局内(平台, 号段图, 根目录):
    """fail-closed：声明的每个占用段都必须落在 `号段图.json` 对应命名空间的并集内。"""
    for 键名 in ("能力号段", "通知号段"):
        for 序号, (区间起点, 区间终点, _) in enumerate(平台[键名]):
            if not 判并集覆盖(号段图[键名], 区间起点, 区间终点):
                布局 = " · ".join("%d–%d" % (区间低端, 区间高端) for 区间低端, 区间高端, _ in 号段图[键名])
                raise 生成失败(
                    "%s.%s[%d] 声明占用 %d–%d，但 %s 的「%s」只布局了 %s"
                    " ⇒ 声明占了一段布局里没有的号（号段即归属，占了就是归属不明）"
                    % (根目录.声明文件, 键名, 序号, 区间起点, 区间终点, 根目录.号段图, 键名, 布局)
                )


def 查归属(区间起点, 区间终点, 号段图, 键名):
    """号段图里有没有一段与 (起, 止) 完全相同？有就取它的归属当注释。"""
    for 图起, 图止, 图归属 in 号段图.get(键名, ()):
        if 图起 == 区间起点 and 图止 == 区间终点:
            return 图归属
    return None
