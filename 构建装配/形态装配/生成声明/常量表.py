# -*- coding: utf-8 -*-
"""常量表 —— 读 `<声明根>/常量表.json`。

常量表自称「全平台常量的唯一定义处：凡被两处以上引用的数都必须在这里定义」。
一份**没有任何读方**的声明等于零 —— 故生成器逐条给它落点：出常量，或显式标注未定数。
"""

from .路径形状 import 生成失败
from .小工具 import 读JSON件, 取整, 取串, 取表, 是标识符

# 常量表条目名 → (生成物里的落点常量名, 该常量的位宽)。
#
# **只列「值另有源」的条目**：它们的值由 平台声明.json / 号段图.json 给出，
# 常量表这一份只做**交叉比对**（两源不一致即 fail-closed，正是「同一事实两个来源」的抓错口）。
# 不在这张表里的条目 = 常量表就是它唯一的源 ⇒ 生成器直接按名字出常量。
常量表落点 = {
    "声明格式号": ("底座声明格式号", 32),
    "目标字宽": ("底座目标字宽", 16),
    "号段类宽度": ("号段类宽度", 32),
    "号段类个数": ("号段类个数", 32),
}

# 生成物里**固定会出**的常量名（不含按数据展开的那些）。常量表若撞上它们，
# 生成物会出现重名 `const` ⇒ 生成期就 fail-closed，不留给编译器报一堆 E0428。
生成物固定名 = frozenset(
    [
        "底座声明格式号",
        "底座标识串内容",
        "底座标识串",
        "底座目标字宽",
        "底座名称",
        "底座说明",
        "底座实现版本",
        "底座要求宿主版本",
        "底座要求内核版本",
        "底座提供宿主版本",
        "底座提供内核版本",
        "底座能力号段",
        "底座通知号段",
        "底座错误段位表",
        "底座类型表",
        "错误码表",
        "错误码信息表",
        "通知号表",
        "命令类别表",
        "作废号表_能力",
        "作废号表_类型",
        "作废号表_通知",
        "作废号表_错误码",
        "作废号表_资源",
        "未定数常量",
        "号段类宽度",
        "号段类个数",
        "通知号段",
    ]
)


def 读常量表(根目录):
    """返回按表内顺序的条目表；每条 = {名, 值, 位宽, 依据, 序}。`值` 可为 None（未定数）。

    形状（`契约声明/格式说明.md` 第八节）：`{名, 值, 类型, 位宽, 依据}`。
    `类型` 只认 `整数`；`位宽` 只认 8/16/32/64（**未定数条目不必给位宽** —— 值都还没定，
    位宽更没定）。本格式目前只定义**非负**整数常量：要负数得先定「跨边界负数怎么表达」。
    """
    来源 = 根目录.常量表
    文档 = 读JSON件(来源)
    if not isinstance(文档, dict):
        raise 生成失败("%s 顶层不是对象" % 来源)
    项表 = 取表(文档, "常量", 来源)
    if not 项表:
        raise 生成失败("%s 的「常量」是空表" % 来源)
    输出缓冲 = []
    见名 = set()
    for 序, 行 in enumerate(项表):
        出错位置 = "%s.常量[%d]" % (来源, 序)
        if not isinstance(行, dict):
            raise 生成失败("%s 不是对象" % 出错位置)
        名称 = 取串(行, "名", 出错位置)
        if 名称 in 见名:
            raise 生成失败("%s 的「名」%s 与前面某条重复" % (出错位置, 名称))
        见名.add(名称)
        if not 是标识符(名称):
            raise 生成失败("%s 的「名」%r 不是合法标识符（要当 Rust 常量名）" % (出错位置, 名称))
        类型 = 取串(行, "类型", 出错位置)
        if 类型 != "整数":
            raise 生成失败(
                "%s 的「类型」是 %r；本格式只定义了「整数」常量"
                "（要别的类型得先在 格式说明.md 定形状，生成器不替它编）" % (出错位置, 类型)
            )
        依据 = 取串(行, "依据", 出错位置)
        待处理值 = 行.get("值")
        if 待处理值 is None:
            输出缓冲.append({"名": 名称, "值": None, "位宽": None, "依据": 依据, "序": 序, "处": 出错位置})
            continue
        if isinstance(待处理值, bool) or not isinstance(待处理值, int):
            raise 生成失败("%s 的「值」不是整数也不是 null：%r" % (出错位置, 待处理值))
        if 待处理值 < 0:
            raise 生成失败(
                "%s 的「值」%d 是负数；本格式目前只定义非负整数常量"
                "（负数要先定跨边界表达口径）" % (出错位置, 待处理值)
            )
        位宽 = 取整(行, "位宽", 出错位置)
        if 位宽 not in (8, 16, 32, 64):
            raise 生成失败("%s 的「位宽」只能是 8/16/32/64：%d" % (出错位置, 位宽))
        if 待处理值 > (1 << 位宽) - 1:
            raise 生成失败("%s 的「值」%d 超出 u%d 上界 %d" % (出错位置, 待处理值, 位宽, (1 << 位宽) - 1))
        if 名称 not in 常量表落点 and 名称 in 生成物固定名:
            raise 生成失败(
                "%s 的「名」%s 与生成物里固定会出的常量重名 ⇒ 会出两个同名 const" % (出错位置, 名称)
            )
        输出缓冲.append({"名": 名称, "值": 待处理值, "位宽": 位宽, "依据": 依据, "序": 序, "处": 出错位置})
    return 输出缓冲
