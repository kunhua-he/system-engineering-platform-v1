# -*- coding: utf-8 -*-
"""渲染通知作废 —— 产物「四 通知号」与「五 作废号表」两小节。"""

from .读子表 import 作废号空间
from .小工具 import 转字符串字面量


def 渲染通知号(渲染器, 根目录, 通知号表):
    # ── 四 通知号 ──────────────────────────────────────────────────────
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 四 通知号（源：%s/*.json，按 通知号 升序）" % 根目录.通知号段)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    for 一项 in 通知号表:
        渲染器("/// 通知号 %d · %s（方向 %s）" % (一项["通知号"], 一项["名称"], 一项["方向"]))
        渲染器("/// %s" % " ".join(一项["说明"].split()))
        渲染器("/// 参数：%s · %s" % (一项["参数"][0], 一项["参数"][1]))
        渲染器("pub const 通知号_%d: u32 = %d;" % (一项["通知号"], 一项["通知号"]))
        渲染器("")
    if 通知号表:
        渲染器("/// 已登记的通知号（源：%s/*.json，按 通知号 升序）。" % 根目录.通知号段)
        渲染器("pub const 通知号表: [u32; %d] = [" % len(通知号表))
        宽度 = max(len("%d," % 一项["通知号"]) for 一项 in 通知号表)
        for 一项 in 通知号表:
            渲染器("    %-*s // %s · %s" % (宽度, "%d," % 一项["通知号"], 一项["方向"], 一项["名称"]))
        渲染器("];")
    else:
        渲染器("/// 已登记的通知号（源：%s/*.json）——当前为空。" % 根目录.通知号段)
        渲染器("pub const 通知号表: [u32; 0] = [];")
    渲染器("")


def 渲染作废号(渲染器, 根目录, 作废号表):
    # ── 五 作废号表 ────────────────────────────────────────────────────
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("// 五 作废号表（源：%s）" % 根目录.作废号表)
    渲染器("// ════════════════════════════════════════════════════════════════════════════")
    渲染器("")
    渲染器("// 作废号表（宪法第 7 条：号只增不复用）——**按号空间分开出常量**。")  # 段落标题，不是条目的文档注释（否则 clippy 判 empty_line_after_doc_comments）
    渲染器("// **为什么按空间分**：五个号空间互不相通 —— 前四个是号段空间（源：%s 的" % 根目录.号段图)
    渲染器("// 「四个号空间互不相通」：能力号 · 通知号 · 错误码 · 资源号），第五个 `类型` 是")
    渲染器("// 类型标签空间（%s §五「类型标签 … 与上面四个不通」），不属号段制故不在号段图里。" % "项目文档/设计文档/字段名册与引用方式.md")
    渲染器("// 能力号 16 与 错误码 16 只是数字撞了，不是同一个号（类型标签 0 与能力号 0 同理）。")
    渲染器("// 一个号在哪个空间作废，就只在那个空间里不可再用；判定只比**同空间**的号，不做全局排除。")
    渲染器("// 旧的不带空间的 `作废号表` 已删（**不保留旧腿**：同一件事两套实现即缺陷）。")
    渲染器("")
    for 空间 in 作废号空间:
        号s = 作废号表[空间]
        渲染器("/// 作废号表_%s：**%s空间**里已作废的号（宪法第 7 条：号只增不复用）。当前 %d 项。"
            % (空间, 空间, len(号s)))
        渲染器("/// 源：%s（逐行的「号空间」= %s）。" % (根目录.作废号表, 空间))
        渲染器("pub const 作废号表_%s: &[u32] = &[%s];" % (空间, ", ".join("%d" % 号值 for 号值 in 号s)))
        渲染器("")
