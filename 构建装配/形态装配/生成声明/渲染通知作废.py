"""渲染通知作废 —— 产物「四 通知号」与「五 作废号表」两小节。"""

from .读子表 import 作废号空间
from .小工具 import rust串


def 渲染通知号(加, 根, 通知号表):
    # ── 四 通知号 ──────────────────────────────────────────────────────
    加("// ════════════════════════════════════════════════════════════════════════════")
    加("// 四 通知号（源：%s/*.json，按 通知号 升序）" % 根.通知号段)
    加("// ════════════════════════════════════════════════════════════════════════════")
    加("")
    for 项 in 通知号表:
        加("/// 通知号 %d · %s（方向 %s）" % (项["通知号"], 项["名称"], 项["方向"]))
        加("/// %s" % " ".join(项["说明"].split()))
        加("/// 参数：%s · %s" % (项["参数"][0], 项["参数"][1]))
        加("pub const 通知号_%d: u32 = %d;" % (项["通知号"], 项["通知号"]))
        加("")
    if 通知号表:
        加("/// 已登记的通知号（源：%s/*.json，按 通知号 升序）。" % 根.通知号段)
        加("pub const 通知号表: [u32; %d] = [" % len(通知号表))
        宽 = max(len("%d," % 项["通知号"]) for 项 in 通知号表)
        for 项 in 通知号表:
            加("    %-*s // %s · %s" % (宽, "%d," % 项["通知号"], 项["方向"], 项["名称"]))
        加("];")
    else:
        加("/// 已登记的通知号（源：%s/*.json）——当前为空。" % 根.通知号段)
        加("pub const 通知号表: [u32; 0] = [];")
    加("")


def 渲染作废号(加, 根, 作废号表):
    # ── 五 作废号表 ────────────────────────────────────────────────────
    加("// ════════════════════════════════════════════════════════════════════════════")
    加("// 五 作废号表（源：%s）" % 根.作废号表)
    加("// ════════════════════════════════════════════════════════════════════════════")
    加("")
    加("// 作废号表（宪法第 7 条：号只增不复用）——**按号空间分开出常量**。")  # 段落标题，不是条目的文档注释（否则 clippy 判 empty_line_after_doc_comments）
    加("// **为什么按空间分**：五个号空间互不相通 —— 前四个是号段空间（源：%s 的" % 根.号段图)
    加("// 「四个号空间互不相通」：能力号 · 通知号 · 错误码 · 资源号），第五个 `类型` 是")
    加("// 类型标签空间（%s §五「类型标签 … 与上面四个不通」），不属号段制故不在号段图里。" % "项目文档/设计文档/字段名册与引用方式.md")
    加("// 能力号 16 与 错误码 16 只是数字撞了，不是同一个号（类型标签 0 与能力号 0 同理）。")
    加("// 一个号在哪个空间作废，就只在那个空间里不可再用；判定只比**同空间**的号，不做全局排除。")
    加("// 旧的不带空间的 `作废号表` 已删（**不保留旧腿**：同一件事两套实现即缺陷）。")
    加("")
    for 空间 in 作废号空间:
        号s = 作废号表[空间]
        加("/// 作废号表_%s：**%s空间**里已作废的号（宪法第 7 条：号只增不复用）。当前 %d 项。"
            % (空间, 空间, len(号s)))
        加("/// 源：%s（逐行的「号空间」= %s）。" % (根.作废号表, 空间))
        加("pub const 作废号表_%s: &[u32] = &[%s];" % (空间, ", ".join("%d" % 号 for 号 in 号s)))
        加("")
