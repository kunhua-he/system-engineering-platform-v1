def 收集指纹行(根):
    行 = [(根.声明文件, 源指纹(根.声明文件)), (根.号段图, 源指纹(根.号段图))]
    行.append((根.常量表, 源指纹(根.常量表)))
    for 目录 in (根.类型声明, 根.错误码表, 根.通知号段):
        for _, 相对路径 in 列目录json(目录):
            行.append((相对路径, 源指纹(相对路径)))
    行.append((根.作废号表, 源指纹(根.作废号表)))
    return 行


# 号段归属标签：`归属` 文案里 "：" / ":" 前那一段。三个合法标签就是号段图.通知号段 的三段。
通知号段标签 = ("下行", "上行", "生命周期")


def 号段归属表(号段图):
    """归属标签 → (起, 止, 归属原文)，从 号段图.json.通知号段 的「归属」前缀推出来。

    不写死号段：规则（哪个方向占哪一段）本来就是源里的数据，再抄一份到生成器就是双源。
    2026-09-26 实测：归属 已从 平台声明.json 挪到 号段图.json，故这里读号段图。
    """
    出 = {}
    for 起, 止, 归属 in 号段图["通知号段"]:
        if not 归属:
            continue
        头 = 归属.split("：", 1)[0].split(":", 1)[0].strip()
        if 头 in 通知号段标签 and 头 not in 出:
            出[头] = (起, 止, 归属)
    return 出


# 资源号段的两个归属标签：`归属` 文案里 "（" 前那一段（资源号段的归属**不带** "："，
# 与通知号段的三段不同，故另取一条前缀规则）。
资源号段标签 = ("扩展自带资源", "平台级资源")


def 资源号段两段(号段图, 根):
    """`资源号段` 模块的两段（扩展自带资源 · 平台级资源），固定按此顺序出。缺一段即 fail-closed。

    为什么必须出：跨语言适配/资源网关口 要判「这个资源号该由扩展声明还是平台声明」，
    判据就是这两个区间的归属。不出成常量，关口就只能自己手写一份区间 —— **同一事实两个来源**，
    实测发生过（关口手写 `资源号段 = 1..=9999`）。顺序固定 = 产物确定。
    """
    出 = {}
    for 起, 止, 归属 in 号段图.get("资源号段", ()):
        if not 归属:
            continue
        头 = 归属.split("（", 1)[0].split("(", 1)[0].strip()
        if 头 in 资源号段标签 and 头 not in 出:
            出[头] = (起, 止, 归属)
    for 标签 in 资源号段标签:
        if 标签 not in 出:
            raise 生成失败(
                "%s.资源号段 里没有「%s」段（`归属` 缺这个标签）⇒ 资源网关口判不了"
                "「这个号该由扩展声明还是平台声明」，只能自己手写一份区间（同一事实两个来源）"
                " —— fail-closed" % (根.号段图, 标签)
            )
    # 与 `通知号段三段` **同形状**返回四元组：调用处解包方式一致，少一处能写错的地方。
    return [(标签,) + 出[标签] for 标签 in 资源号段标签]


def 建声明根(原始):
    """把命令行给的目录规范化成**仓内相对、POSIX 分隔**的声明根；仓外 / 非目录即 fail-closed。

    为什么只认仓内相对：产物头要写「源：<路径>」，绝对路径会带上机器相关前缀 ⇒ 产物不确定
    （同一份源在两台机器上生成出不同字节），指纹闸就废了。
    """
    if 原始 is None or 原始.strip() == "":
        raise 生成失败("声明根是空串")
    绝对 = os.path.abspath(原始 if os.path.isabs(原始) else os.path.join(仓根, 原始))
    相对 = os.path.relpath(绝对, 仓根).replace(os.sep, "/")
    if 相对 in (".", "..") or 相对.startswith("../"):
        raise 生成失败(
            "声明根 %r 解析成 %r：它不在仓库内（仓根 %s）⇒ 产物里会出现机器相关路径、"
            "破坏确定性 —— fail-closed" % (原始, 相对, 仓根)
        )
    if not os.path.isdir(绝对):
        raise 生成失败("声明根 %r 不是一个目录（解析成 %s）" % (原始, 相对))
    根 = 声明根(相对)
    根.声明文件 = 选声明文件(根)
    return 根


