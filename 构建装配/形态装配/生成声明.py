def 常量表落点描述(条, 根):
    """(生成物里的落点常量名, 值的源)。未定数 → 落点写「（未生成）」。"""
    if 条["值"] is None:
        return "（未生成）", "未定数（值 = null）⇒ 显式跳过，名字进 `未定数常量`"
    落点 = 常量表落点.get(条["名"])
    if 落点 is None:
        return 条["名"], "本表即源（%s 的「%s」条目）" % (根.常量表, 条["名"])
    if 条["名"] in ("号段类宽度", "号段类个数"):
        return 落点[0], "%s.能力号段 推导（与 %s 交叉比对）" % (根.号段图, 根.常量表)
    return 落点[0], "%s.%s（与 %s 交叉比对）" % (根.声明文件, 条["名"], 根.常量表)


def 交叉比对(常量表, 平台, 号段类, 根):
    """常量表里「值另有源」的 4 条：两源必须一致，不一致即 fail-closed。

    这 4 条在 常量表.json 与 平台声明.json / 号段图.json 各写了一份 —— 它们**必须**相等，
    否则就是「同一事实两个来源」已经漂移（段位口径半新半旧的后果是段归属判错）。
    """
    实际 = {
        "声明格式号": (平台["声明格式号"], 32),
        "目标字宽": (平台["目标字宽"], 16),
        "号段类宽度": (号段类[0], 32),
        "号段类个数": (号段类[1], 32),
    }
    for 条 in 常量表:
        if 条["值"] is None or 条["名"] not in 常量表落点:
            continue
