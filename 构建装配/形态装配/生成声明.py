class 声明根:
    """一份声明的根目录（默认 `契约声明`）。路径 = 根 + 固定相对名，一律仓内相对、POSIX 分隔。

    只有「根」是可变的；根下面有什么、叫什么，是**声明的形状**，不随根变。
    加一个根 = 加一份声明；加一个字段 = 改形状 —— 后者要按 `契约声明/冻结登记.json` 走。
    """

    def __init__(self, 根):
        self.根 = 根
        self.平台声明 = 根 + "/平台声明.json"
        self.包声明 = 根 + "/包声明.json"
        self.号段图 = 根 + "/号段图.json"
        self.常量表 = 根 + "/常量表.json"
        self.类型声明 = 根 + "/类型声明"
        self.错误码表 = 根 + "/错误码表"
        self.通知号段 = 根 + "/通知号段"
        self.作废号表 = 根 + "/作废号表.json"
        self.落盘件 = 根 + "/src/声明数据.rs"
        # 声明文件本身：底座叫 `平台声明.json`，扩展叫 `包声明.json`（同形状，只是名字不同）。
        # 由 选声明文件() 定，定完不再变。
        self.声明文件 = None

    def 源清单(self):
        """产物头里「源：」那一行。逐字由**实际读的源**拼出，不另抄一份清单。"""
        return " · ".join(
            [
                self.声明文件,
                self.号段图,
                self.常量表,
                self.类型声明 + "/*.json",
                self.错误码表 + "/*.json",
                self.通知号段 + "/*.json",
                self.作废号表,
            ]
        )

