"""生成声明 —— 读 契约声明/ 下的 JSON，生成 契约声明/src/声明数据.rs。

落点在**契约层**（`v1-contract`），不在 装载入口：`统一注册表` 要用生成物里的
错误码与类型标签，而 `统一注册表` 不能依赖 `装载入口`（反向即成环）。契约派生常量
与契约同住，两边才都能引用。

本文件是四道闸里**闸 4「生成物指纹」**的实现（`项目文档/设计文档/内核落点.md` 第三节）。
判据：任何一处出现手写的 `static 平台信息`，即为违规——声明只有 JSON 一个来源。

用法（在仓库根执行）：

    python 构建装配/形态装配/生成声明.py                       # 重新生成落盘件
    python 构建装配/形态装配/生成声明.py --检查                 # 重新生成到内存，与落盘件逐字节比对
    python 构建装配/形态装配/生成声明.py --声明根 <目录>        # 换一份声明的根（默认 契约声明）
    python 构建装配/形态装配/生成声明.py --帮助                 # 用法全文

**声明根**：一份声明自己的目录。所有源与落点都从它派生（`<根>/平台声明.json` ·
`<根>/号段图.json` · `<根>/常量表.json` · `<根>/类型声明/*.json` · `<根>/错误码表/*.json` ·
`<根>/通知号段/*.json` · `<根>/作废号表.json` → `<根>/src/声明数据.rs`）。
参数只认**仓内相对路径**（绝对路径会让产物带上机器相关前缀 ⇒ 破坏确定性，故 fail-closed）。
底座用默认值 `契约声明`；扩展将来用同一生成器出自己那份静态声明时传自己的声明根。

只用 Python 标准库（hashlib · json · math · os · sys）。不许 pip、不许联网。
确定性：所有遍历按编号/键名排序，缩进与换行固定，产物里不含时间戳、绝对路径、随机数。
"""

