def 读号段表(项, 源, 键):
    """一张「号段表」。每项必须有 起/止；`归属` 是**可选**的说明字段。

    2026-09-26 实测：`归属` 已从 平台声明.json 的号段表里挪走（落到 号段图.json），
    所以这里不许把 归属 当必填——否则源一动生成器就瞎。
    """
    出 = []
    for 序, 行 in enumerate(项):
        if not isinstance(行, dict):
            raise 生成失败("%s.%s[%d] 不是对象" % (源, 键, 序))
        处 = "%s.%s[%d]" % (源, 键, 序)
        起 = 取整(行, "起", 处, 0, 0xFFFFFFFF)
        止 = 取整(行, "止", 处, 0, 0xFFFFFFFF)
        if 起 > 止:
            raise 生成失败("%s 起 %d 大于 止 %d" % (处, 起, 止))
        归属 = 行.get("归属")
        if 归属 is not None and not isinstance(归属, str):
            raise 生成失败("%s 的「归属」不是字符串：%r" % (处, 归属))
        出.append((起, 止, 归属))
    return 出


def 选声明文件(根):
    """定下本声明根里的**声明文件**：`平台声明.json` 优先，其次 `包声明.json`。

    底座那份叫 `平台声明.json`，扩展那份叫 `包声明.json` —— **同形状，只是名字不同**
    （`契约声明/格式说明.md` 第二节 · 扩展装载/开发标准）。两个都没有即 fail-closed。
    """
    for 相对路径 in (根.平台声明, 根.包声明):
        if os.path.isfile(os.path.join(仓根, 相对路径)):
            return 相对路径
    raise 生成失败(
        "声明根 %s 里既没有 %s 也没有 %s ⇒ 没有声明可读（fail-closed）"
        % (根.根, 根.平台声明, 根.包声明)
    )


def 读平台声明(根):
    源 = 根.声明文件
    文档 = 读json(源)
    if not isinstance(文档, dict):
        raise 生成失败("%s 顶层不是对象" % 源)

    声明格式号 = 取整(文档, "声明格式号", 源, 0, 0xFFFFFFFF)

    标识串 = 取串(文档, "标识串", 源)
    if len(标识串) != 32 or any(字符 not in "0123456789abcdefABCDEF" for 字符 in 标识串):
        raise 生成失败("%s 的「标识串」必须是 32 位十六进制：%r" % (源, 标识串))
    标识串 = 标识串.lower()

    目标字宽 = 取整(文档, "目标字宽", 源, 0, 65535)
    if 目标字宽 not in (32, 64):
        raise 生成失败("%s 的「目标字宽」只能是 32 或 64：%d" % (源, 目标字宽))

    段表 = {}
    for 键 in ("能力号段", "通知号段"):
        项 = 取表(文档, 键, 源)
        if not 项:
            raise 生成失败("%s 的「%s」是空表" % (源, 键))
        段表[键] = 读号段表(项, 源, 键)

    错误段位 = 取表(文档, "错误段位表", 源)
    if not 错误段位:
        raise 生成失败("%s 的「错误段位表」是空表" % 源)
    段位表 = []
    for 序, 值 in enumerate(错误段位):
        if isinstance(值, bool) or not isinstance(值, int) or not (0 <= 值 <= 9):
            raise 生成失败("%s.错误段位表[%d] 不是 0–9 的段位：%r" % (源, 序, 值))
        段位表.append(值)

    return {
        "声明格式号": 声明格式号,
        "标识串": 标识串,
        "实现版本": 版本三元组(文档.get("实现版本"), 源 + ".实现版本"),
        "要求宿主版本": 版本三元组(文档.get("要求宿主版本"), 源 + ".要求宿主版本"),
        "要求内核版本": 版本三元组(文档.get("要求内核版本"), 源 + ".要求内核版本"),
        # 判定 ④ 的据：本声明**提供**的宿主/内核版本。与「要求宿主/内核版本」（本声明**要什么**）
        # 是两个概念，2026-09-26 起 JSON 里两对都有源，不再手写。
        "提供宿主版本": 版本三元组(文档.get("提供宿主版本"), 源 + ".提供宿主版本"),
        "提供内核版本": 版本三元组(文档.get("提供内核版本"), 源 + ".提供内核版本"),
        "名称": 取串(文档, "名称", 源),
        "说明": 取串(文档, "说明", 源),
        "目标字宽": 目标字宽,
        "能力号段": 段表["能力号段"],
        "通知号段": 段表["通知号段"],
        "错误段位表": 段位表,
    }


def 读号段图(根):
    """全平台的编号布局（`<声明根>/号段图.json`）。

    **它不进 `平台信息`** —— `平台信息` 里没有「全平台布局」这个字段。所以本生成物
    不据它产出任何「全平台号段图」常量（留一份就是第二个来源）；据它产出的是四样
    **从布局能唯一推出来**的数与区间（见 `推导号段类` 与 `渲染` 第七节）：
    `号段类宽度` · `号段类个数` · 通知号的三个方向号段 · 资源号的两个号段。此外它还给占用段配 `归属` 注释、
    并校验「占用 ⊆ 布局」。

    它是必需源：没有它，「声明只能占布局里已有的段」这条判据无从落点。
    """
    if not os.path.isfile(os.path.join(仓根, 根.号段图)):
        raise 生成失败(
            "%s 不在。它是「声明只能占布局里已有的段」这条判据的依据"
            "（占用 ⊆ 布局），也是 `号段类宽度`/`号段类个数` 与通知号三个方向号段的推导源，"
            "缺了就没法判 —— fail-closed" % 根.号段图
        )
    文档 = 读json(根.号段图)
    if not isinstance(文档, dict):
        raise 生成失败("%s 顶层不是对象" % 根.号段图)
    出 = {}
    for 键 in ("能力号段", "通知号段", "资源号段"):
        项 = 取表(文档, 键, 根.号段图)
        if not 项:
            raise 生成失败("%s 的「%s」是空表" % (根.号段图, 键))
        出[键] = 读号段表(项, 根.号段图, 键)
    return 出


def 并集覆盖(布局段表, 起, 止):
    """`[起, 止]` 是否整个落在 布局段表 的并集里（先把相邻段归并，再判包含）。"""
    归并 = []
    for 段起, 段止, _ in sorted(布局段表):
        if 归并 and 段起 <= 归并[-1][1] + 1:
            归并[-1][1] = max(归并[-1][1], 段止)
        else:
            归并.append([段起, 段止])
    return any(低 <= 起 and 止 <= 高 for 低, 高 in 归并)


def 判占用落在布局内(平台, 号段图, 根):
    """fail-closed：声明的每个占用段都必须落在 `号段图.json` 对应命名空间的并集内。"""
    for 键 in ("能力号段", "通知号段"):
        for 序, (起, 止, _) in enumerate(平台[键]):
            if not 并集覆盖(号段图[键], 起, 止):
                布局 = " · ".join("%d–%d" % (低, 高) for 低, 高, _ in 号段图[键])
                raise 生成失败(
                    "%s.%s[%d] 声明占用 %d–%d，但 %s 的「%s」只布局了 %s"
                    " ⇒ 声明占了一段布局里没有的号（号段即归属，占了就是归属不明）"
                    % (根.声明文件, 键, 序, 起, 止, 根.号段图, 键, 布局)
                )


def 查归属(起, 止, 号段图, 键):
    """号段图里有没有一段与 (起, 止) 完全相同？有就取它的归属当注释。"""
    for 图起, 图止, 图归属 in 号段图.get(键, ()):
        if 图起 == 起 and 图止 == 止:
            return 图归属
    return None


