def 读常量表(根):
    """返回按表内顺序的条目表；每条 = {名, 值, 位宽, 依据, 序}。`值` 可为 None（未定数）。

    形状（`契约声明/格式说明.md` 第八节）：`{名, 值, 类型, 位宽, 依据}`。
    `类型` 只认 `整数`；`位宽` 只认 8/16/32/64（**未定数条目不必给位宽** —— 值都还没定，
    位宽更没定）。本格式目前只定义**非负**整数常量：要负数得先定「跨边界负数怎么表达」。
    """
    源 = 根.常量表
    文档 = 读json(源)
    if not isinstance(文档, dict):
        raise 生成失败("%s 顶层不是对象" % 源)
    项表 = 取表(文档, "常量", 源)
    if not 项表:
        raise 生成失败("%s 的「常量」是空表" % 源)
    出 = []
    见名 = set()
    for 序, 行 in enumerate(项表):
        处 = "%s.常量[%d]" % (源, 序)
        if not isinstance(行, dict):
            raise 生成失败("%s 不是对象" % 处)
        名 = 取串(行, "名", 处)
        if 名 in 见名:
            raise 生成失败("%s 的「名」%s 与前面某条重复" % (处, 名))
        见名.add(名)
        if not 是标识符(名):
            raise 生成失败("%s 的「名」%r 不是合法标识符（要当 Rust 常量名）" % (处, 名))
        类型 = 取串(行, "类型", 处)
        if 类型 != "整数":
            raise 生成失败(
                "%s 的「类型」是 %r；本格式只定义了「整数」常量"
                "（要别的类型得先在 格式说明.md 定形状，生成器不替它编）" % (处, 类型)
            )
        依据 = 取串(行, "依据", 处)
        值 = 行.get("值")
        if 值 is None:
            出.append({"名": 名, "值": None, "位宽": None, "依据": 依据, "序": 序, "处": 处})
            continue
        if isinstance(值, bool) or not isinstance(值, int):
            raise 生成失败("%s 的「值」不是整数也不是 null：%r" % (处, 值))
        if 值 < 0:
            raise 生成失败(
                "%s 的「值」%d 是负数；本格式目前只定义非负整数常量"
                "（负数要先定跨边界表达口径）" % (处, 值)
            )
        位宽 = 取整(行, "位宽", 处)
        if 位宽 not in (8, 16, 32, 64):
            raise 生成失败("%s 的「位宽」只能是 8/16/32/64：%d" % (处, 位宽))
        if 值 > (1 << 位宽) - 1:
            raise 生成失败("%s 的「值」%d 超出 u%d 上界 %d" % (处, 值, 位宽, (1 << 位宽) - 1))
        if 名 not in 常量表落点 and 名 in 生成物固定名:
            raise 生成失败(
                "%s 的「名」%s 与生成物里固定会出的常量重名 ⇒ 会出两个同名 const" % (处, 名)
            )
        出.append({"名": 名, "值": 值, "位宽": 位宽, "依据": 依据, "序": 序, "处": 处})
    return 出


