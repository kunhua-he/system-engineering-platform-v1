# -*- coding: utf-8 -*-
"""命令行 —— 用法行 · 帮助文本 · 入口函数(参数)（退出码 0 全成 / 1 有模块没编成）。"""

from .路径形状 import 组合模块库根, 生成器相对路径, 程序文本后缀, 制品后缀, 出制品示例名
from .找模块 import 找模块, 模块名表
from .编译模块 import 跑模块, 回收退役模块


def 用法文本() -> str:
    return "用法：python %s [模块名 ...]（不带参数 = 全部模块）" % 生成器相对路径


def 帮助文本() -> list:
    return [
        用法文本(),
        "",
        "扫 %s 下每个子目录：凡有 `<目录名>%s` 的就是一个待编模块。" % (组合模块库根, 程序文本后缀),
        "每包可声明多能力；源码映射按编号定位各流程，同包合编一次。",
        "--仅回收：只回收缺声明、缺源码的退役制品，不编译在用模块。",
        "",
        "编译走真的 1106 链（`cargo run --example %s -- <模块目录绝对路径>`）；" % 出制品示例名,
        "产物落回模块目录：`<模块名>%s` —— 目录名与件名同名，生成器源里的" % 制品后缀,
        "`二进制输出模板` 说的就是这条规则（新增模块不必改声明）。",
        "",
        "不带参数 = 编全部模块（现量：%s）。" % ("、".join(模块名表(组合模块库根)) or "一个都没有"),
    ]


def 入口函数(命令行参数) -> int:
    if 命令行参数 == ["--仅回收"]:
        回收退役模块()
        return 0
    if any(参数词 in ("-h", "--帮助") for 参数词 in 命令行参数):
        for 源码行 in 帮助文本():
            print(源码行)
        return 0
    只要 = set(命令行参数)
    模块目录表 = [模块目录 for 模块目录 in 找模块(组合模块库根)
              if not 只要 or 模块目录.name in 只要]
    if not 模块目录表:
        print("没扫到任何模块（根 = %s；认的标记 = `<目录名>%s`）" % (组合模块库根, 程序文本后缀))
        return 1
    单模块结果 = [跑模块(模块目录) for 模块目录 in 模块目录表]
    if 单模块结果 and max(单模块结果) == 0:
        if not 只要: 回收退役模块()
        return 0
    return 1
