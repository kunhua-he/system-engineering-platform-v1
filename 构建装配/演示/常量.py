def 打点(阶段: dict, 打点起: list, 名称: str) -> None:
    """演示阶段打点：把「距上次打点」的秒数记进 `阶段[名称]`，并推进起表。

    `打点起` 是**单元素表**（闭包外的可变格子）—— `网关与调用.py` 与
    `热载入与调用.py` 共用这一份，不各写一遍。
    """
    阶段[名称] = round(time.time() - 打点起[0], 2)
    打点起[0] = time.time()


def 端口监听读数(监听端口: int) -> list:
    """`lsof` 读一个端口的 LISTEN 状态（只读取证：本演示的误杀证据链用）。

    ★ `errors="replace"` 不是可选项：`lsof` 会把**别人的进程名**打出来，而进程名不必是
    UTF-8（实测 2026-09-27 一次运行就撞上：`UnicodeDecodeError: invalid continuation byte`
    ⇒ **整条演示命令在清理步骤崩掉**，「一条可复跑的命令」当场不成立）。
    这里只取「有没有 LISTEN」这一件事，进程名解不干净不影响判读 ⇒ 用 `replace` 兜住。
    """
    运行结果 = subprocess.run(
        ["/usr/sbin/lsof", "-nP", "-iTCP:{}".format(监听端口), "-sTCP:LISTEN"],
        capture_output=True, text=True, errors="replace",
    )
    源码行 = [源码行 for 源码行 in 运行结果.stdout.splitlines() if "LISTEN" in 源码行]
    return 源码行


def 写回执(回执: dict, 落点: Path = 回执落点) -> None:
    """原子写回执（同 上线切换.py::写指针 的写法：临时件 + os.replace）。

    落点由参数定（默认 = 本模块的 `回执落点`）：`热载入与调用.py` 传它那份
    `最近一次热载入回执.json` —— 同一份实现，不另写第二套。
    """
    落点.parent.mkdir(parents=True, exist_ok=True)
    临时路径 = 落点.with_suffix(".json.临时")
    临时路径.write_text(json.dumps(回执, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    os.replace(临时路径, 落点)
