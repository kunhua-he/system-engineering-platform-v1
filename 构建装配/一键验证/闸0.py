#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""闸 0 —— 一条入口把**两条闸一起跑**，两个读数并排报出。

**为什么要这一条**（本条存在的全部理由）：
`构建装配/一键验证/一键验证.py`（闸 1 · 声明侧）与
`测试验证/契约一致性/扫实现.py`（闸 2 · 实现侧）此前**各跑各的** ——
而闸 1 **不调用**闸 2。实测撞到过：`扫实现.py` 的改名提交只搬了文件夹
（`扫实现模块/` → `扫实现/`），入口那行 `from 扫实现模块 import` 没跟着改
（留在腿的脏工作区里没提交）⇒ 入口一跑就 `ModuleNotFoundError`，
**在主干上坏了整段而没有任何门禁抓到**，直到收口方手跑才发现。
（事发经过与纪律落点：`项目文档/开发规范/开发规范.md` §六.6「拆完必须真跑一遍入口，
不是只 `py_compile`」。）

⇒ 补这一条：**两条闸一起跑**。任一失败即非零退出。

**约束（不许违反）**：**不许让闸 1 去 import 闸 2**（那是层序问题 ——
`测试验证/` 不在产品层序里，闸 1 反向依赖它会被判违规；见 `判据口径十一条.md` §十四）。
所以本件用**子进程**调两条闸的**入口**，各按各的退出码与读数报，互不 import。

**为什么是「串行」不是「并发」**（2026-09-27 实测裁的）：
试过并发跑两条闸（它们只读仓、互不写、互不 import，技术上可并发）：闸 0 自身降到 4.6 s，
但**闸 1 自身被判红了** —— 它的判据 ⑱ 量的是「本命令自身的完整墙钟」，与闸 2 抢 CPU 时
那段墙钟被推过 4800 ms 阈值。那是**读数被污染**，不是真超顶 ⇒ 不能这么提速。
（同理，闸 0 也不该把自身的开销算进任一条闸的账。）
真正的修法是**让闸 1 自身变快**：实测它的 4.6 s 里有 2.8 s 花在「对象数读数」那一段
（串行取 37 条，其中 ㉕ 与 ㊲ 各要把全仓 746 件过一遍生产区）—— 已改成并行取
（`一键验证/验证.py::验证`，理由与读数写在那里）。提速后闸 1 ≈ 2.6 s ⇒ 闸 0 串行 ≈ 3.3 s。

用法（在仓库根）：

    python3 构建装配/一键验证/闸0.py

退出码：两条闸都 0 ⇒ 0；任一非 0 ⇒ 1。两条闸的读数逐行并排打印；失败的那条把明细透传。

★ **全量 `闸0.py` ≠ 提交放行**（2026-10-05 补 · 审计 B-10）：pre-commit 钩子（`测试验证/案例/装门禁.sh`）
在闸 0 之外**另跑**判据自测（`一键验证.py --自测`，实测 6.4 s，装不进 5 秒硬顶）与全部案例（cargo），
任一红即拒提交 ⇒ 「闸 0 绿」是提交放行的**必要一环**，不是全部（全量 `v1_gate` 亦只跑闸 0）。
"""
import re
import subprocess
import sys
import time
from pathlib import Path

起始时刻 = time.monotonic()  # 壳起表点：必须在 import 业务包**之前**（见 构建装配/门禁/壳.py）

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # 仓根：取共享门禁
from 构建装配.门禁 import 自门禁  # noqa: E402

# 两条闸的**入口**（子进程调它们，不 import —— 层序问题，见文件头）。
闸表 = (
    ("闸 1 · 声明侧", "构建装配/一键验证/一键验证.py"),
    ("闸 2 · 实现侧", "测试验证/契约一致性/扫实现.py"),
)
读数行模式 = re.compile(r"^通过\s.*$", re.M)


def 入口函数(命令行参数: list) -> int:
    仓根 = Path(__file__).resolve().parents[2]
    全过 = True
    明细 = []
    print("闸 0：两条闸串起来跑（声明侧 + 实现侧；子进程调入口，互不 import）")
    print("")
    # **串行**（不并发）：并发会让闸 1 的 ⑱ 读到被抢 CPU 的墙钟 ⇒ 假红（见文件头）。
    for 名称, 相对 in 闸表:
        # ★ 子进程 5 秒 timeout（2026-10-05 修 · 审计 B-7）：原先只**事后量**、子进程无 timeout
        #   ⇒ CLI / pre-commit 路径一旦卡死就挂死（MCP 侧已有 `timeout=5`）。超时 = 判红并报「超时」。
        try:
            判定汇总 = subprocess.run(
                [sys.executable, str(仓根 / 相对)],
                cwd=str(仓根), capture_output=True, text=True, timeout=5,
            )
        except subprocess.TimeoutExpired:
            全过 = False
            print(f"  {名称} ｜ {相对}")
            print("    退出码 超时 ｜ （超时：本闸 > 5 s 未返回 —— 五秒硬顶无例外）")
            明细.append((名称, 相对, "超时：%s 未在 5 s 内返回" % 相对))
            continue
        命中 = 读数行模式.search(判定汇总.stdout or "")
        读数 = 命中.group(0).strip() if 命中 else "（没有读出「通过 …」那一行）"
        全过 = 全过 and (判定汇总.returncode == 0)
        print(f"  {名称} ｜ {相对}")
        print(f"    退出码 {判定汇总.returncode} ｜ {读数}")
        if 判定汇总.returncode != 0:
            明细.append((名称, 相对, (判定汇总.stdout or "") + (判定汇总.stderr or "")))
    print("")
    if 全过:
        print("闸 0：两条闸都过（退出码 0）")
        return 0
    for 名称, 相对, 原始 in 明细:
        print(f"── {名称}（{相对}）失败明细 ──")
        print(原始.rstrip())
        print("")
    print("闸 0：至少一条闸没过（退出码 1）")
    return 1


if __name__ == "__main__":
    sys.exit(
        自门禁(
            起始时刻, 入口函数(sys.argv[1:]), 尾巴余量毫秒=200,
            修法="两条闸各自提速（分片 / 缓存 / 把重活移出命令路，裁决 §三）；"
                 "本件只串行调用它们，不替它们干活，也不并发抢它们的 CPU（那会污染闸 1 的 ⑱ 读数）。",
        )
    )
