# -*- coding: utf-8 -*-
"""注入样本 · 判据 ㊴（引用可解析）。

反向样本注入到**干净合成仓**（不依赖仓库现状 ⇒ 可重复）。合成仓的
`构建装配/一键验证/引用基线.json` 是**空的**（合成仓里 0 处悬空引用），
所以任何一处注入都必然是「新增」⇒ 当场红。
"""
from __future__ import annotations

from pathlib import Path


def 注入_引用不存在节(临根: Path) -> str:
    """往合成仓的一个 `.md` 里写一句引用**不存在的节** ⇒ 判据 ㊴ 当场红。

    形状取现场实测那一类（引用方指向已不存在的节号）。目标件用合成仓自带的 `样例说明.md`
    （它有 §一）——引用它的 §九十九 ⇒ 目标件匹配得到、却无该节 ⇒ 当场红。

    **为什么字面拆开拼**：本件自身也在判据 ㊴ 的扫描面内（`.py`）。整字连写会被本件读到
    ⇒ 给判据面造一处假红（先例：`注入_行号引用` 把行号写成 `{12}`）。
    """
    路径 = 临根 / "项目文档" / "引用说明.md"
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "见 `" "样例说明" ".md` §" "九十九。\n",
        encoding="utf-8",
    )
    return "项目文档/引用说明.md"
