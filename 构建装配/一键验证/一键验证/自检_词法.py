"""解析器的身份证：剥字面量剥序 · 并行生产区上下文。"""

from __future__ import annotations

from .Rust文本 import 漏传上下文调用
from .剥字面量 import 去字面量
from .测试件 import 生产区文本


def 自检_剥字面量剥序() -> list:
    """`去字面量` / `去注释保串` 剥序缺陷的身份证（反向样本 + 正向样本）。

    为什么单列：这一条不是「判据」，是**判据的解析器**——`判据的可信性.md` §三.5
    「判据的解析器坏了」是假绿来源之一，所以解析器自己也要有反向样本。
    反向样本的形状**就是实测撞到的那一条**：断言消息里写 `码 // 号段类宽度`。
    """
    出 = []
    # 模板里刻意留两个特征：
    #   · `#[cfg(test)]` 块（必须整块剥掉）
    #   · 测试块**之后**还有一个字符串（`"尾部"`）——剥序错时，字符串里那个 `//` 会把
    #     收尾引号一起剥掉，留下一个孤立引号，与它配成一对 ⇒ 中间（含 `}`）整段被抹掉
    #     ⇒ cfg 块的大括号找不到闭合 ⇒ 测试代码漏进生产区。
    模板 = (
        "pub fn 生产() -> u32 { 1 }\n"
        "#[cfg(test)]\n"
        "mod 测试 {\n"
        "    pub fn 夹具() -> u32 { 2 }\n"
        "    pub const 目标字宽: u32 = 64;\n"
        '    pub const 说明: &str = "@串@";\n'
        "}\n"
        'pub const 后一个: &str = "尾部";\n'
        "pub fn 之后() -> u32 { 3 }\n"
    )
    坏 = 模板.replace("@串@", "段位 = 码 // 号段类宽度")
    好 = 模板.replace("@串@", "段位 = 码 除以 号段类宽度")
    净坏, 净好 = 生产区文本(坏), 生产区文本(好)
    出.append(
        (
            "反向样本：字符串里的 `//` 不改变 `#[cfg(test)]` 块的剥离结果",
            ("夹具" not in 净坏)
            and ("目标字宽" not in 净坏)
            and 净坏.count("{") == 净好.count("{")
            and 净坏.count("}") == 净好.count("}"),
            f"含 `//` 的净文里 `夹具` 还在={('夹具' in 净坏)} · `目标字宽` 还在="
            f"{('目标字宽' in 净坏)} · 大括号 {净坏.count('{')}/{净坏.count('}')}"
            f"（不含 `//` 的净文是 {净好.count('{')}/{净好.count('}')}）",
        )
    )
    # 正向样本：注释里含引号也必须整段剥掉，且不许把后面的代码当字符串吞掉
    注释样本 = '// 这是 "引号" 与 /* 这也不是注释 */ 的说明\npub fn 生产() { let _ = 1; }\n'
    净注释 = 去字面量(注释样本)
    出.append(
        (
            "正向样本：注释里的引号被正确剥掉，且不吞掉后面的代码",
            '"' not in 净注释 and "fn 生产" in 净注释,
            f"净文里剩引号 {净注释.count(chr(34))} 个 · 后面的 `fn 生产` 还在="
            f"{('fn 生产' in 净注释)}",
        )
    )
    # 正向样本：字符串里含 `/*` 也不许当块注释（同一个剥序缺陷的另一面）
    块样本 = 'pub const 常量项: &str = "a /* b";\npub fn 函数项() -> u32 { 1 }\n'
    净块 = 去字面量(块样本)
    出.append(
        (
            "正向样本：字符串里的 `/*` 不当块注释（不吞后面的代码）",
            '"' not in 净块 and "fn 函数项" in 净块,
            f"净文里剩引号 {净块.count(chr(34))} 个 · 后面的 `fn 函数项` 还在={('fn 函数项' in 净块)}",
        )
    )
    # ── #185 承重证明：块注释吃掉换行 ⇒ 其后行号整体前移 ──
    # 反向样本的形状就是实测撞到的那一条：一个 4 行的块注释（含 3 个换行）后面跟一个标记。
    带块注释 = (
        "pub fn 函数项() -> u32 { 1 }\n"
        "/*\n"
        " 块注释第一行\n"
        " 块注释第二行\n"
        "*/\n"
        "pub const 标记: u32 = 7;\n"
    )
    原文行 = 带块注释[: 带块注释.find("标记")].count("\n") + 1
    净文行 = 去字面量(带块注释)[: 去字面量(带块注释).find("标记")].count("\n") + 1
    出.append(
        (
            "反向样本：块注释剥掉后，其后 token 的行号必须不变（#185）",
            净文行 == 原文行,
            f"原文里 `标记` 在第 {原文行} 行 · 剥后第 {净文行} 行（要求相等）——"
            f"抹掉换行会让其后行号整体前移 N-1 行",
        )
    )
    # 承重证明（退回一步）：**旧抹法**（换行也换成空格）在同一份注入上必须偏 3 行。
    # 把旧行为在样本里复算一遍，证明这条断言真的在承重（不是恒真）。
    def 旧抹法(文: str) -> str:
        """旧 `抹` 的行为：命中区间内**每一个**字符（含换行）都写成空格。"""
        净 = list(去字面量(文))
        起 = 文.find("/*")
        止 = 文.find("*/") + 2
        for 位 in range(起, 止):
            净[位] = " "
        return "".join(净)

    旧净 = 旧抹法(带块注释)
    旧行 = 旧净[: 旧净.find("标记")].count("\n") + 1
    出.append(
        (
            "承重证明（退回一步）：旧抹法（换行也抹）在同一注入上必须偏移",
            旧行 != 原文行 and 原文行 - 旧行 == 3,
            f"旧抹法下 `标记` 落在第 {旧行} 行（原文 {原文行}）· 偏移 {原文行 - 旧行} 行（要求 3）——"
            f"证明上一条断言不是恒真",
        )
    )
    return 出

def 自检_并行生产区上下文() -> list:
    """元判据 ⑤「判据调 `并行生产区` 必须传全套上下文」的身份证。

    为什么单列：漏传 `测试文件集` 时 `并行生产区` 用默认空集 ⇒ 整份夹具被当生产代码
    （实测 检查13 曾漏传 ⇒ 常量重定义假红）。这条判据的扫描器自己也要有正/反样本，
    否则它可能恒真（例如配平括号写错 ⇒ 永远取不到实参 ⇒ 永远不报）。
    """
    出 = []
    # 样本里的调用形状**拆开拼**（`名 + "("`）：本判据扫的是本文件自己的源码，
    # 源码里直接写一整条调用会被它读成一处**真调用** ⇒ 给判据面造假红
    # （同 `自检_整份夹具跳过` 把 Rust 形状拆开拼的先例）。
    名 = "并行生产区"
    正 = f'代码件 = {名}(扫描件源, 上["测试文件集"])\n'
    反 = f"代码件 = {名}(扫描件源)\n"
    反保串 = f"导出表 = {名}(扫描件源, 保串=True)\n"
    定义 = f"def {名}(件表, 测试文件集=frozenset(), 保串=False):\n    pass\n"
    出.append(
        (
            "正向样本：传了 `测试文件集` 的调用 ⇒ 不报",
            len(漏传上下文调用(正)) == 0,
            f"报 {len(漏传上下文调用(正))} 处（要求 0）",
        )
    )
    出.append(
        (
            "反向样本：漏传 `测试文件集`（含只传 `保串`）⇒ 报，且报出行号",
            len(漏传上下文调用(反)) == 1 and len(漏传上下文调用(反保串)) == 1,
            f"反 {len(漏传上下文调用(反))} 处 · 反保串 {len(漏传上下文调用(反保串))} 处（都要求 1）",
        )
    )
    出.append(
        (
            "正向样本：定义形不算调用（不许把 `def` 那一行报成漏传）",
            len(漏传上下文调用(定义)) == 0,
            f"报 {len(漏传上下文调用(定义))} 处（要求 0）",
        )
    )
    return 出
