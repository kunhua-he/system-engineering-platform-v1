r"""判据 55：名册新鲜度 —— 库 `命名出现` 的名字集必须等于**写口会写进去的那个名集**。

依据：加固项 A3（「磁盘 ≠ 运行时」的 V1 版本）· `加固与升级总纲.md` 的加固项表 A3。

**为何要这一条**（实测）：库 `命名出现`（约 8 万行）的**唯一 insert 写口**（旧
`开发工具/信息核心/` 那件（已删）的 `落库()`）**零调用者** ⇒ 库说「债 0 · 全合格」，现场重扫却「新增 17 · 待改名 5」——
**两套读数谁也管不着**：改名改了、名册没跟着动，而没有任何东西会报。2026-10-07 把写口蒸馏进
`开发工具/信息核心/落库.py` 并接回流水线（`信息核心.py 落库`）；本条就是**逼它不被遗忘**的那道闸。

**判什么**：**写口会写进去的名集**（`落库.写库名集` —— 现场重扫 − 例外 − 外来）对库
`命名出现` 的名字集 —— 两向差都报：
  · **新增**（写口会写、库里没有）⇒ 名册没跟上，改名后忘了跑 `落库`；
  · **陈旧**（库里有、写口已经不会写了）⇒ 名已改净 / 已成例外，而名册里还挂着
    （旧 `落库` 只新增、不删的遗留面）。

★ **推导只此一份**：本判据调 `落库.写库名集`，**不另写一套** —— 两边各推一遍就等于判据量的
  不是本口写进去的东西（判据报绿而库里是旧的）。
★ **不要基线表**（有意）：本判据落地当刻跑一次 `落库`，两向差就归零 ⇒ 真仓从「零差」起步，
  此后**任何**改名不落库都当场红。立一张基线反而会让「存量 593 个新增名」长期挂着不修。

**三元读数**：通过 = 两向差为空；失败 = 逐条报出差名；
未判 = 规则库读不动 / 扫描面 0 件（fail-closed）。
"""
from __future__ import annotations

import sqlite3
import sys
from pathlib import Path

from .验证小工具 import 判不了, 违规
from .常量 import 仓根, 检查名


# 最多报几条（差名可能成百上千，全打出来会把读数淹没；另行列明总条数）。
上限条数 = 20


# 写口主人与扫描面都按仓根缓存（同 判据 ㊲/㊳ 的先例）—— 判定与对象数各取一次。
_写库名集缓存: dict = {}


def 取落库模块():
    """惰性取**写口主人**（`开发工具/信息核心/落库.py`）—— 推导只此一份。

    与 `判据_后缀唯一` 引剥器同形：工具从「判据自身所在的仓」取，不从被扫的仓取
    （夹具仓没有 `开发工具/`）。仓根 = `常量.仓根`（本验证器所在那个仓）。
    """
    子目录 = str(仓根 / "开发工具" / "信息核心")
    for 加目录 in (子目录, str(仓根 / "开发工具"), str(仓根 / "构建装配" / "一键验证")):
        if 加目录 not in sys.path:
            sys.path.insert(0, 加目录)
    import 落库 as 写口

    return 写口


def 库相对路径() -> str:
    """库相对路径的**主人**是 `开发工具/信息核心/表定义.py`（本件不另写一份字面量）。"""
    子目录 = str(仓根 / "开发工具" / "信息核心")
    if 子目录 not in sys.path:
        sys.path.insert(0, 子目录)
    import 表定义

    return 表定义.库相对路径


def 写库名集(树根) -> set:
    """⇒ **写口会写进 `命名出现` 的那个名字集**（调 `落库.写库名集`，不另推一套）。"""
    缓存键 = str(树根)
    if 缓存键 in _写库名集缓存:
        return _写库名集缓存[缓存键]
    写口 = 取落库模块()
    名集 = 写口.写库名集(树根, Path(树根) / 库相对路径())
    _写库名集缓存[缓存键] = 名集
    return 名集


def 样本_名册面(上层读数: dict) -> int:
    """对象数：写口会扫到的出现记录数（0 ⇒ 未判）。"""
    写口 = 取落库模块()
    return len(写口.扫出现(上层读数["仓根"]))


def 库侧名集(树根) -> tuple:
    """⇒ `(库 `命名出现` 的名字集, 错误或 None)` —— 库不在 / 读不动 ⇒ 交错误回去（fail-closed）。

    读 `命名出现`（**不是** `命名登记`）：本判据量的是「出现面跟不跟得上盘」。
    """
    库件 = Path(树根) / 库相对路径()
    if not 库件.is_file():
        return set(), f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            库中名集 = {文本行[0] for 文本行 in 连接.execute("select distinct 名字 from 命名出现")}
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return set(), f"`命名出现` 读不动：{错误}"
    return 库中名集, None


def 检查55_名册新鲜度(上层读数: dict) -> list:
    """库 `命名出现` 的名字集 == 写口会写进去的名集（三元：通过 / 失败 / 未判）。"""
    输出缓冲 = []
    树根 = 上层读数["仓根"]
    try:
        应写名集 = 写库名集(树根)
    except Exception as 错误:
        判不了(
            检查名[54],
            str(树根),
            f"判不了：名册写口跑不动：{错误}",
            "本判据要与库 `命名出现` 对比，而对比的基准就是**写口会写进去的名集**（只此一份推导）；"
            "推导跑不动就量不出「名册新不新鲜」⇒ 修法：先跑 "
            "`python3 开发工具/信息核心/信息核心.py 建库`，再重跑 ⇒ 只能由维护方修",
        )
        return 输出缓冲
    if not 应写名集:
        判不了(
            检查名[54],
            "命名出现",
            "写口在这棵仓里算出 0 个名字（一个代码件都没扫到）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一个名都没扫到的仓天然是绿的，"
            "那不是本条判据的功劳 ⇒ 只能由判据作者确认扫描面与后缀表",
        )
        return 输出缓冲
    库中名集, 错误 = 库侧名集(树根)
    if 错误:
        判不了(
            检查名[54],
            str(树根),
            f"判不了：{错误}",
            "本判据要与库 `命名出现` 对比，读不到库就量不出「名册新不新鲜」；"
            "且库旧时读数只能造假绿（改名看不见）或假红（改好的名还在）⇒ "
            "修法：先跑 `python3 开发工具/信息核心/信息核心.py 建库`，再重跑 ⇒ 只能由维护方修",
        )
        return 输出缓冲
    新增名, 陈旧名 = sorted(应写名集 - 库中名集), sorted(库中名集 - 应写名集)
    修法 = (
        "修法：跑 `python3 开发工具/信息核心/信息核心.py 落库` —— 它是 `命名出现` 的**唯一写口**"
        "（全量重写）⇒ 跑完两向差都归零。口径（加固项 A3「名册新鲜度」）：改名 / 新增标识符 / "
        "新登记例外 之后不跑它，名册就停在旧快照 ⇒ 「库说债 0」与现场重扫两套读数谁也管不着"
        "（这正是本判据要堵的）。改库要走 `v1_task` 功能=6 记账 ⇒ 只能由改名方跑"
    )
    for 差名 in 新增名[:上限条数]:        输出缓冲.append(违规(
            检查名[54], f"开发工具/信息核心/信息核心.db::命名出现::{差名}",
            f"名「{差名}」在盘上（写口会写它），而库 `命名出现` 里没有（名册没跟上）",
            修法,
        ))
    if len(新增名) > 上限条数:
        输出缓冲.append(违规(
            检查名[54], "命名出现",
            f"还有 {len(新增名) - 上限条数} 个新增名未逐条报出（共 {len(新增名)} 个）",
            "修法同上（跑 `落库`）。这条只是读数，不是额外一笔债",
        ))
    for 差名 in 陈旧名[:上限条数]:
        输出缓冲.append(违规(
            检查名[54], f"开发工具/信息核心/信息核心.db::命名出现::{差名}",
            f"名「{差名}」已不再是写口会写的（已改净 / 已成例外），而库里还挂着（陈旧）",
            "修法：跑 `python3 开发工具/信息核心/信息核心.py 落库`（**全量重写**，一并清陈旧行）。"
            "不要手动 delete `命名出现` 的行 —— 那正是本口要收口的「第二套写面」",
        ))
    if len(陈旧名) > 上限条数:
        输出缓冲.append(违规(
            检查名[54], "命名出现",
            f"还有 {len(陈旧名) - 上限条数} 个陈旧名未逐条报出（共 {len(陈旧名)} 个）",
            "修法同上（跑 `落库`）",
        ))
    return 输出缓冲
