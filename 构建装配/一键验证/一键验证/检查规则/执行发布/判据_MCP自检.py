"""判据 ㊽：MCP 工具面自检 —— 跑 `开发工具/MCP服务.py --自检`，退出码非 0 ⇒ 红。

依据：第九批 MCP 审计 `第九批_MCP审计_A.md` 缺陷 9 ≡ `_C.md` C-3 —— 工具面在闸 0
**零判据、零反向样本**：`v1_gate` 原有一档 `自测` 在 commit c1b2bde 被删，而
`MCP服务.py --自检` 又**没有任何判据 / pre-commit 调它** ⇒ 四道闸 · 拒绝码 · 参数名
一致性全在盲区。本条补上对等物（判据面有 `一键验证.py --自测`，工具面有它）：
把 `--自检`（协议三帧 + 工具表名单 + 工具名 ASCII + **拒绝样本**）挂进闸 0，
退出码非 0 即红。

**不犯错纪律**：工具面异常 / 失败时代理怎么不犯错（分清「工具坏」与「业务真失败」· 重试边界 ·
失败留痕与唯一凭据 · 断链恢复口 · 假绿假红）住库条款 `项目文档/MCP工具面不犯错纪律.md`；
本条只证明「自检起得来、拒绝样本真拒」，不代替那份纪律。

**对象**（`样本_MCP自检面`）：本仓 MCP 工具面的自检这**一件**事，恒 1 个（不是扫描集，
同判据 ⑱ 的 `_样本_本命令`）。**读数**：子进程跑 `--自检` 的退出码。

**测哪一份**：被扫仓里有 `开发工具/MCP服务.py` 就跑它（真仓 / 变体仓 / 合成夹具 ——
合成仓**自带一份可控等价入口**，见 `合成仓.py` 的 `开发工具/MCP服务.py`）；没有才退回
**本验证器所在仓**的那一份 —— 本条的对象是「本仓的 MCP 工具面」，与夹具无关。
子进程带 **5 秒硬顶**（决策记录 2026-09-27_所有运行五秒硬顶.md §一）；那一支的边界
（失败 / 超时传递）由 `自检_延迟与两遍.自检_MCP工具面边界` 用**夹具作用域**的可控入口证。

**三元读数**：通过 = 退出码 0；失败 = 退出码非 0 / 起不来 / 超 5 秒（逐条报出读数）；
未判 = 无（对象恒 1，不落空集）。
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from ...判据编排.验证小工具 import 违规
from ...基础定义.常量 import 仓根, 检查名, 硬顶毫秒


# 自检子进程的兜底上限（秒）：**从唯一主人** `构建装配/门禁/常量.py::硬顶毫秒` 派生。
# ★ 这里要的是**护栏**（90 秒，只防真挂死），不是效率目标（5 秒）—— 本处是「等子进程返回」
#   的外层兜底，不是一条判据规则；用它去判「自检是不是太慢」会在真仓上假红（自检本身
#   曾实测 2.6–4.3 s，且负载下更长）。它触发只记一条债务（见 `墙钟采样.报告墙钟` 的同类）。
# ★ 抽成模块级名是**行为逐字不变**的提取，只为给「起不来 / 超护栏」那一支一个**样本作用域**
#   的注入点（此前那一支零反向样本：真睡满会把 `--自测` 顶长）。
自检超时秒 = 硬顶毫秒 / 1000


def 取自检入口件(被扫仓根: Path) -> tuple:
    """㊽ 跑**哪一份**、在**哪个目录**跑 ⇒ `(入口件, 工作目录)`。

    被扫仓自带 `开发工具/MCP服务.py`（真仓 / 变体仓 / 合成夹具）就跑它；没有才**退回
    本验证器所在仓**那一份 —— 本条的对象是「本仓的 MCP 工具面」，与夹具无关。
    ★ 抽成模块级函数只为**可断言**（样本可证「自带就跑自带、没有才退回」，不必真跑一次
      3.1 s 的真命令）；判定与工作目录**逐字不变**。
    """
    候选路径 = 被扫仓根 / "开发工具" / "MCP服务.py"
    if 候选路径.is_file():
        return 候选路径, 被扫仓根
    return 仓根 / "开发工具" / "MCP服务.py", 仓根


def 检查48_MCP工具面自检(上层读数: dict) -> list:
    """跑 MCP 工具面自检（子进程）⇒ 退出码非 0 即红。"""
    被扫仓根 = Path(上层读数["仓根"])
    入口件, 工作目录 = 取自检入口件(被扫仓根)
    try:
        子进程 = subprocess.run(
            [sys.executable, str(入口件), "--自检"],
            cwd=str(工作目录), capture_output=True, text=True, timeout=自检超时秒,
        )
    except Exception as 错误:
        return [
            违规(
                检查名[47],
                "开发工具/MCP服务.py --自检",
                "自检起不来 / 超 %g 秒：%r" % (自检超时秒, 错误),
                "决策记录 2026-09-27_所有运行五秒硬顶.md §一：一条命令完整跑完的墙钟 ≤ 5000 ms，"
                "超过即 bug、无例外。自检是工具面的身份证，起不来等于工具面无人背书 ⇒ "
                "只能由 MCP 服务的作者修（`开发工具/MCP服务.py` 与 `MCP服务/`）。",
            )
        ]
    返回码 = 子进程.returncode
    if 返回码 != 0:
        return [
            违规(
                检查名[47],
                "开发工具/MCP服务.py --自检",
                "自检退出码 %d（非 0）⇒ 工具面拒绝样本没过。读数：\n%s"
                % (返回码, ((子进程.stdout or "") + (子进程.stderr or ""))[-1000:]),
                "第九批_MCP审计_A.md 缺陷 9 ≡ _C.md C-3：工具面在闸 0 零判据、零反向样本 ⇒ "
                "`--自检` 是工具面（协议三帧 + 工具表名单 + 工具名 ASCII + 拒绝样本）的唯一身份证。"
                "退出码非 0 即工具面有回潮（协议层崩 / 工具名非 ASCII / 某条拒绝样本没拒）⇒ "
                "只能由 MCP 服务的作者修。",
            )
        ]
    return []


def 样本_MCP自检面(上层读数: dict) -> int:
    """对象数：本仓 MCP 工具面的自检这件事，恒 1 个（不是扫描集，同判据 ⑱ 的 `_样本_本命令`）。"""
    return 1
