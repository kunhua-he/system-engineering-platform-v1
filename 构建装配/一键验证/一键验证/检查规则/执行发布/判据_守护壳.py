# -*- coding: utf-8 -*-
"""判据 71：网关守护壳必须**真跑**得起（`sh -n` 查不出运行期 `bad substitution`）。

依据：实测踩过 —— 壳里五个可覆盖变量写成中文名（`${V1_运行根:-…}`），`sh -n` 退出码 0、全绿，
真跑却逐行报 `bad substitution`、整壳起不来、网关无人保活。**语法检查不是反证**。

**测哪一份**：被扫仓里有 `构建装配/上线切换/网关守护.sh` 就测它（反向样本注在合成仓里）；
没有（干净合成夹具）就退回**本验证器所在仓** —— 本条的对象是「本仓这份壳真跑得起」，
与夹具无关（同判据 60 与 ㊽ 的口径）。真跑逻辑只有一份：那片可重跑的自检实现件。

三元读数：通过 = 五条断言全绿且条数与声明一致；失败 = 逐条报出（报告位置 = 壳的相对路径）；
未判 = 壳或自检件不在盘上。
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

from ...判据编排.验证小工具 import 判不了, 违规, 取相对路径
from ...基础定义.判据取值常量 import 仓根, 检查名

# 壳与自检件（相对仓根）—— 同时登记进元数据的「落点」，判据 ㉖ 盯它们不悬空
壳相对路径 = "构建装配/上线切换/网关守护.sh"
自检相对路径 = "构建装配/上线切换/网关守护自检实现.py"


def 装自检(扫根: Path):
    """按文件路径装载自检实现件（它不是包；入口与判据共用同一份实现 —— 两套实现必然漂）。"""
    件路径 = Path(扫根) / 自检相对路径
    if not 件路径.is_file():
        return None
    规格 = importlib.util.spec_from_file_location("网关守护自检实现件", 件路径)
    if 规格 is None or 规格.loader is None:
        return None
    自检模块 = importlib.util.module_from_spec(规格)
    规格.loader.exec_module(自检模块)
    return 自检模块


def 取壳根(上层读数: dict) -> Path:
    """被扫仓里有这份壳就测它；没有（干净合成夹具）就退回本验证器所在仓。"""
    被扫根 = Path(上层读数["仓根"])
    return 被扫根 if (被扫根 / 壳相对路径).is_file() else Path(仓根)


def 检查71_守护壳真跑(上层读数: dict) -> list:
    """守护壳真跑得起（自检分支 + 四个覆盖变量 + 5 MiB 轮转两支）；红的位置 = 壳的相对路径。"""
    输出缓冲 = []
    扫根 = 取壳根(上层读数)
    壳路径 = 扫根 / 壳相对路径
    if not 壳路径.is_file():
        判不了(检查名[64], 壳相对路径,
               "守护壳不在盘上（找的是 %s）⇒ 这条判据没有对象" % 壳路径,
               "判据的可信性.md 第二节：空集是「未判」不是「通过」—— 壳不在时这条判据什么都没验；"
               "壳的落地属上线切换面，验证面不造壳 ⇒ 只能由壳的归属节点补回")
        return 输出缓冲
    自检模块 = 装自检(扫根) or 装自检(Path(仓根))
    if 自检模块 is None:
        判不了(检查名[64], 自检相对路径,
               "真跑自检件不在盘上（找的是 %s）⇒ 判不了" % (扫根 / 自检相对路径),
               "判据不得另写一套真跑逻辑（两套实现必然漂：改了一处、另一处照旧假绿）"
               "⇒ 只能由该件作者补回自检件")
        return 输出缓冲
    结果表 = 自检模块.跑自检(壳路径)
    报告位置 = 取相对路径(扫根, 壳路径)
    修法 = ("修法：壳里**每个变量名**（含可覆盖环境变量 `V1_*` 那五个）都必须是 ASCII —— "
            "macOS 自带 bash 3.2 下 `${中文名:-默认}` 语法合法、`sh -n` 也绿，只有真跑才报 "
            "`bad substitution` 并让整壳起不来；改完必须真跑 "
            "`构建装配/上线切换/网关守护自检.py` 复核，别拿 `sh -n` 当反证")
    for 断言名, 通过, 读数 in 结果表:
        if not 通过:
            输出缓冲.append(违规(检查名[64], 报告位置, "%s —— 读数：%s" % (断言名, 读数), 修法))
    if len(结果表) != 自检模块.自检断言条数:
        输出缓冲.append(违规(检查名[64], 报告位置,
                          "自检只跑了 %d 条断言，声明是 %d 条 ⇒ 有一支没跑（判据与自检漂了）"
                          % (len(结果表), 自检模块.自检断言条数), 修法))
    return 输出缓冲


def 样本_守护壳(上层读数: dict) -> int:
    """对象数：壳与自检件都在 ⇒ 断言条数（5 支：自检 1 · 覆盖 1 · 轮转 3）；缺则 0（未判）。

    ★ 这里**不重跑一遍**去数实际断言：那是白造一次 6 MiB 件加五个子进程。条数由自检件自身声明
    （`自检断言条数`），真跑出来的条数对不上时 `检查71_守护壳真跑` 会当场报红 ⇒ 不会静默少判。
    """
    扫根 = 取壳根(上层读数)
    if not (扫根 / 壳相对路径).is_file():
        return 0
    自检模块 = 装自检(扫根) or 装自检(Path(仓根))
    return 0 if 自检模块 is None else 自检模块.自检断言条数
