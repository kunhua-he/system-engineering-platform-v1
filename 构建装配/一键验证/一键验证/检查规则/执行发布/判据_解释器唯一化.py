from __future__ import annotations

import re

from ...判据编排.验证小工具 import 判不了, 违规
from ...基础定义.判据取值常量 import 检查名, 代码后缀
from ...源码解析.测试件 import 并行取生产区文本

# 「命令位置」：`subprocess` 家族调用，或命令变量赋值。
_命令位形 = re.compile(
    r"subprocess\.(?:run|Popen|call|check_output|check_call)\s*\(|"
    r"(?<![\w.])(?:命令|cmd|生成命令|运行命令)\s*="
)
# 「裸解释器名」：串里恰好是 `python3` / `python`（前后不许是标识符字符 · 点 · 版本号 · `$`）。
_裸名形 = re.compile(r"""["'](?:[^"']*?(?<![\w.$-]))(python3|python)(?![\w.-])[^"']*?["']""")

行注释符 = {".py": "#"}


def _后缀(路径: str) -> str:
    尾部 = 路径.rsplit("/", 1)[-1]
    return "." + 尾部.rsplit(".", 1)[-1] if "." in 尾部 else ""


def 扫解释器面(件表: dict) -> list:
    """扫一遍（**保串**的生产区文本）⇒ 命中清单：`(路径, 行号, 说明)`。"""
    输出缓冲 = []
    for 键名 in sorted(件表):
        源文本 = 件表[键名]
        if not 源文本 or _后缀(键名) not in 行注释符:
            continue
        注释符 = 行注释符[_后缀(键名)]
        for 号值, 原行 in enumerate(源文本.split("\n"), 1):
            源码行 = 原行.split(注释符, 1)[0]
            if not _命令位形.search(源码行):
                continue
            for 裸名 in _裸名形.findall(源码行):
                输出缓冲.append(
                    (键名, 号值,
                     "执行面命令串里写裸 `%s`：它按 PATH 解析，在「git 给钩子的干净环境」里 PATH 可能"
                     "没有 `python3` ⇒ `command not found`、作业 64 ms 内假失败（比真跑一趟还快）；"
                     "唯一允许的是 `$V1_PY`（入口层注入）" % 裸名)
                )
    return 输出缓冲


# 生产区读数在一次运行里不变（对象数与判定各取一次）⇒ 按仓根缓存。
_解释器面缓存: dict = {}


def 解释器面(上层读数: dict) -> dict:
    """扫描面：全仓 `.py` 的**生产区文本**（**保串** —— 要抓的正是串里的名字）。"""
    键名 = str(上层读数["仓根"])
    if 键名 in _解释器面缓存:
        return _解释器面缓存[键名]
    件表 = [
        (键_件, 文件项["文本"])
        for 键_件, 文件项 in 上层读数["文件"].items()
        if 文件项.get("文本") is not None and 键_件.endswith(代码后缀)
    ]
    扫描面 = 并行取生产区文本(件表, 上层读数.get("测试文件集") or frozenset(), 保串=True)
    _解释器面缓存[键名] = 扫描面
    return 扫描面


def 样本_解释器面(上层读数: dict) -> int:
    """对象数：扫描面下的 `.py` 件数（0 ⇒ 未判）。"""
    return sum(1 for 键名 in 解释器面(上层读数) if _后缀(键名) in 行注释符)


def 检查61_解释器唯一化(上层读数: dict) -> list:
    """全仓 `.py` 执行面里 0 处裸 `python3` / `python`。"""
    if 样本_解释器面(上层读数) == 0:
        判不了(检查名[55], "（全仓）",
              "扫描面 0 件 `.py` ⇒ 空集不算通过（空集不是「没问题」，是「这条判据这次没量到东西」）",
              "确认传进来的仓根是不是真的仓根（`上层读数[\"仓根\"]` 指到空目录时就会这样）")
        return []
    return [
        违规(检查名[55], "%s:%d" % (路径, 号值), 说明,
             "改用 `$V1_PY`（入口层注入的唯一解释器绝对路径），不要写裸 `python3` —— "
             "裸名按 PATH 解析，干净环境里可能不存在，故障会藏成 64 ms 的假失败")
        for 路径, 号值, 说明 in 扫解释器面(解释器面(上层读数))
    ]
