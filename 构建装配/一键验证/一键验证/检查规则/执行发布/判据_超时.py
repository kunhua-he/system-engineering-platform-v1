# 数值类：允许 Rust 惯用的下划线分隔（`9_000` · `10_000`），命中后**去掉下划线再转数**。
# ★ 2026-09-30 收紧（判据假绿审计 ㊲）：原来 `[0-9]+(?:\.[0-9]+)?` ⇒ `9_000` 只匹配到 `9`、
#   `from_millis(10_000)` 干脆不匹配 ⇒ 9000 毫秒的超时设置判绿。范本：`构造点._抽整数常量`。
数值形 = r"[0-9](?:_?[0-9])*(?:\.[0-9](?:_?[0-9])*)?"
# 形①/②：`<名字以 毫秒|秒 结尾><可选类型标注> = <数字>`。
# `==` / `>=` / `<=` / `!=` 由正则自身挡掉：名字之后必须紧跟 `=`，`>` `!` `<` 都过不了。
# 类型标注（Rust `const X: u64 = 9` · Python `X: float = 9.0`）允许夹在中间。
_超时赋值式 = re.compile(r"([\w.\[\]]*(?:毫秒|秒))\s*(?::[^=\n]*)?=\s*(" + 数值形 + r")")
# 形③：`timeout=<数字>`（Python 关键字参数）与 `timeout: <数字>`（JS/TS 对象键）。
# 同样由 `[:=]` 单字符挡掉 `==` / `>=` / `<=`。
_超时参 = re.compile(r"\btimeout\s*[:=]\s*(" + 数值形 + r")")
# Rust：`Duration::from_secs(N)` / `Duration::from_millis(N)`。
_秒实参模式 = re.compile(r"from_secs\s*\(\s*(" + 数值形 + r")\s*\)")
_毫秒实参模式 = re.compile(r"from_millis\s*\(\s*(" + 数值形 + r")\s*\)")

# 行注释符：**本判据自身按后缀认**（见模块 docstring 的「行注释」段）。
# `.js`/`.ts`/`.go`/`.java`/`.c*` 都是 `//`，已由共享解析器覆盖；`.sh` 不在 `代码后缀` 内。
行注释符 = {".py": "#"}


def _后缀(路径: str) -> str:
    尾部 = 路径.rsplit("/", 1)[-1]
    return "." + 尾部.rsplit(".", 1)[-1] if "." in 尾部 else ""


def _去行注释(源码行: str, 注释符: str) -> str:
    """去串之后，Python 里 `#` 起就是注释（串已抹成空格 ⇒ 剩下的 `#` 必是注释）⇒ 截断。

    不做这一步的实测后果：`构建装配/上线切换/上线切换/常量.py` 的**注释**里写着
    「那时 停等秒 = 5.0 · 健康超时秒 = 15.0」（那是记录改之前的历史读数），
    被当成了真的超时设置 ⇒ ㊲ 假红。
    """
    落点 = 源码行.find(注释符)
    return 源码行 if 落点 < 0 else 源码行[:落点]


def 扫超时(件表: dict) -> list:
    """扫一遍（**去串的生产区文本**）⇒ 命中清单：`(路径, 行号, 说明, 是未判)`。

    `是未判=真` 的那一条走 `判不了` 通道（形③ 的 101–999：单位分不出）；
    其余是**违规**（读数明确超上限）。
    """
    输出缓冲 = []
    for 键名 in sorted(件表):
        源文本 = 件表[键名]
        if not 源文本:
            continue
        for (生命周期路径,生命周期名字),周期值 in 生命周期约束.items():
            if 生命周期路径!=键名:
                continue
            命令等待式=r"(?:recv_timeout|set_read_timeout|set_write_timeout|timeout)\s*\(\s*(?:Some\s*\(\s*)?"+re.escape(生命周期名字)+r"\b"
            if re.search(命令等待式,源文本):
                输出缓冲.append((键名,1,"生命周期时长不得直接作为命令或传输超时",False))
        注释符 = 行注释符.get(_后缀(键名))
        for 号值, 原行 in enumerate(源文本.split("\n"), 1):
            源码行 = _去行注释(原行, 注释符) if 注释符 else 原行
            生命周期匹配=生命周期声明式.fullmatch(源码行)
            if 生命周期匹配 and (键名,生命周期匹配[1]) in 生命周期约束 and not 是冻结生命周期(键名,源码行):
                输出缓冲.append((键名,号值,"生命周期周期与正式冻结值不符",False))
            for 名称, 待处理值 in _超时赋值式.findall(源码行):
                if (键名, 名称) in 不适用声明:  # 见上方「上限不适用」：换了一类对象，不是放宽上限
                    continue
                毫秒数 = float(待处理值.replace("_", ""))
                if "毫秒" in 名称:
                    if 毫秒数 > 毫秒上限:
                        输出缓冲.append((键名, 号值, "`%s = %s`（毫秒）> 上限 %d 毫秒" % (名称, 待处理值, 毫秒上限), False))
                elif 毫秒数 > 秒上限:
                    输出缓冲.append((键名, 号值, "`%s = %s`（秒）> 上限 %g 秒" % (名称, 待处理值, 秒上限), False))
            for 待处理值 in _超时参.findall(源码行):
                毫秒数 = float(待处理值.replace("_", ""))
                if 秒上限 < 毫秒数 <= 100:
                    输出缓冲.append((键名, 号值, "`timeout=%s`（按秒）> 上限 %g 秒" % (待处理值, 秒上限), False))
                elif 毫秒数 >= 1000 and 毫秒数 > 毫秒上限:
                    输出缓冲.append((键名, 号值, "`timeout=%s`（按毫秒）> 上限 %d 毫秒" % (待处理值, 毫秒上限), False))
                elif 100 < 毫秒数 < 1000:
                    输出缓冲.append((键名, 号值, "`timeout=%s`：**单位分不出**（101–999）" % 待处理值, True))
            for 待处理值 in _秒实参模式.findall(源码行):
                if 是冻结生命周期(键名,源码行):
                    continue
                if float(待处理值.replace("_", "")) > 秒上限:
                    输出缓冲.append((键名, 号值, "`Duration::from_secs(%s)` > 上限 %g 秒" % (待处理值, 秒上限), False))
            for 待处理值 in _毫秒实参模式.findall(源码行):
                if float(待处理值.replace("_", "")) > 毫秒上限:
                    输出缓冲.append((键名, 号值, "`Duration::from_millis(%s)` > 上限 %d 毫秒" % (待处理值, 毫秒上限), False))
    return 输出缓冲


# 生产区读数在一次运行里不变（对象数与判定各取一次）⇒ 按仓根缓存。
# 键是**绝对路径**：`--自测` 每个夹具一个独立临时目录 ⇒ 不会串。
_超时面缓存: dict = {}


def 超时面(上层读数: dict) -> dict:
    """扫描面：全仓代码件的**生产区文本**（跳过 `#[cfg(test)]` 区与整份夹具文件，**去串**）。"""
    键名 = str(上层读数["仓根"])
    if 键名 in _超时面缓存:
        return _超时面缓存[键名]
    件表 = [
        (键_件, 文件项["文本"])
        for 键_件, 文件项 in 上层读数["文件"].items()
        if 文件项.get("文本") is not None and 键_件.endswith(代码后缀)
    ]
    扫描面 = 并行取生产区文本(件表, 上层读数.get("测试文件集") or frozenset(), 保串=False)
    _超时面缓存[键名] = 扫描面
    return 扫描面


def 样本_超时面(上层读数: dict) -> int:
    """对象数：扫描面下的代码件数（0 ⇒ 未判）。"""
    return len(超时面(上层读数))


