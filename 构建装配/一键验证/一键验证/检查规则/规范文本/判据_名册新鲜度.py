from __future__ import annotations

import sqlite3
import sys
from pathlib import Path

from ...判据编排.验证小工具 import 判不了, 违规
from ...基础定义.判据取值常量 import 仓根, 检查名


# 最多报几条（差名可能成百上千，全打出来会把读数淹没；另行列明总条数）。
上限条数 = 20


# 写口主人与扫描面都按仓根缓存（同 判据 ㊲/㊳ 的先例）—— 判定与对象数各取一次。
_写库名集缓存: dict = {}


def 取落库模块():
    """惰性取**写口主人**（`开发工具/信息核心/落库.py`）—— 推导只此一份。

    与 `判据_后缀唯一` 引剥器同形：工具从「判据自身所在的仓」取，不从被扫的仓取
    （夹具仓没有 `开发工具/`）。仓根 = `常量.仓根`（本验证器所在那个仓）。
    """
    子目录 = str(仓根 / "开发工具" / "信息核心")
    for 加目录 in (子目录, str(仓根 / "开发工具"), str(仓根 / "构建装配" / "一键验证")):
        if 加目录 not in sys.path:
            sys.path.insert(0, 加目录)
    import 落库 as 写口

    return 写口


def 库相对路径() -> str:
    """库相对路径的**主人**是 `开发工具/信息核心/表定义.py`（本件不另写一份字面量）。"""
    子目录 = str(仓根 / "开发工具" / "信息核心")
    if 子目录 not in sys.path:
        sys.path.insert(0, 子目录)
    import 表定义

    return 表定义.库相对路径


def 写库名集(树根) -> set:
    """⇒ **写口会写进名册的那个名字集**（调 `落库.写库名集`，不另推一套）。"""
    缓存键 = str(树根)
    if 缓存键 in _写库名集缓存:
        return _写库名集缓存[缓存键]
    写口 = 取落库模块()
    名集 = 写口.写库名集(树根, Path(树根) / 库相对路径())
    _写库名集缓存[缓存键] = 名集
    return 名集


def 样本_名册面(上层读数: dict) -> int:
    """对象数：写口会扫到的出现记录数（0 ⇒ 未判）。"""
    写口 = 取落库模块()
    return len(写口.扫出现(上层读数["仓根"]))


def 库侧名集(树根) -> tuple:
    """⇒ `(库 `命名登记` 的名字集, 错误或 None)` —— 库不在 / 读不动 ⇒ 交错误回去（fail-closed）。

    读 `命名登记`（**不是** `命名出现`）：`命名出现` 是派生明细、住非版本派生库（新树没有），
    而**受版本的权威登记名集**是 `命名登记`（见件头 ★）。
    """
    库件 = Path(树根) / 库相对路径()
    if not 库件.is_file():
        return set(), f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            库中名集 = {文本行[0] for 文本行 in 连接.execute("select 名字 from 命名登记")}
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return set(), f"`命名登记` 读不动：{错误}"
    return 库中名集, None


def 检查55_名册新鲜度(上层读数: dict) -> list:
    """写口会写进名册的名集 ⊆ 库 `命名登记`（三元：通过 / 失败 / 未判）。"""
    输出缓冲 = []
    树根 = 上层读数["仓根"]
    try:
        应写名集 = 写库名集(树根)
    except Exception as 错误:
        判不了(
            检查名[54],
            str(树根),
            f"判不了：名册写口跑不动：{错误}",
            "本判据要与库 `命名登记` 对比，而对比的基准就是**写口会写进去的名集**（只此一份推导）；"
            "推导跑不动就量不出「名册新不新鲜」⇒ 修法：先跑 "
            "`python3 开发工具/信息核心/信息核心.py 建库`，再重跑 ⇒ 只能由维护方修",
        )
        return 输出缓冲
    if not 应写名集:
        判不了(
            检查名[54],
            "命名登记",
            "写口在这棵仓里算出 0 个名字（一个代码件都没扫到）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一个名都没扫到的仓天然是绿的，"
            "那不是本条判据的功劳 ⇒ 只能由判据作者确认扫描面与后缀表",
        )
        return 输出缓冲
    库中名集, 错误 = 库侧名集(树根)
    if 错误:
        判不了(
            检查名[54],
            str(树根),
            f"判不了：{错误}",
            "本判据要与库 `命名登记` 对比，读不到库就量不出「名册新不新鲜」；"
            "且库旧时读数只能造假绿（改名看不见）或假红（改好的名还在）⇒ "
            "修法：先跑 `python3 开发工具/信息核心/信息核心.py 建库`，再重跑 ⇒ 只能由维护方修",
        )
        return 输出缓冲
