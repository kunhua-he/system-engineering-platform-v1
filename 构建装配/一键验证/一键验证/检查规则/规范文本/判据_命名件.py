from __future__ import annotations

import os
from pathlib import Path

from ...判据编排.验证小工具 import 判不了, 违规, 取相对路径
from ...基础定义.常量 import 检查名, 跳过目录, 临时目录前缀
from ...判据编排.判据基线 import 读件名基线


# 构建结构的**通用名**（不是作者起的名字）—— 判它必假红。封闭白名单，加词须证明是通用结构名。
结构目录名 = frozenset({
    "src", "examples", "tests", "test", "benches", "bin", "lib",
    "docs", "assets", "public", "scripts", "include",
})


def 取查名():
    """惰性取**命名规范的口径**（`开发工具/代码地图/查名.py`）—— 规则只此一份。"""
    from ...源码解析.命名面 import 取查名 as _取查名

    return _取查名()


def 读泛名(仓根) -> set:
    """库 `命名泛名` 黑名单（**库是唯一存本**）⇒ 名字集；读不动 ⇒ 空集（由调用方报未判）。"""
    import sqlite3

    from ...判据编排.判据基线 import 库相对路径

    库件 = Path(仓根) / 库相对路径
    if not 库件.is_file():
        return set()
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            return {名字 for (名字,) in 连接.execute("select 名字 from 命名泛名")}
        finally:
            连接.close()
    except sqlite3.Error:
        return set()


def 走件名与目录名(仓根: Path) -> tuple:
    """走树 ⇒ `([(件路径, 基名)], [(目录路径, 基名)])`（跳过目录 · 临时件 · 隐藏目录）。"""
    件表 = []
    目录表 = []
    for 根目录, 子目录表, 文件表 in os.walk(仓根):
        子目录表[:] = [
            目录名 for 目录名 in 子目录表
            if 目录名 not in 跳过目录
            and not 目录名.startswith(临时目录前缀)
            and not 目录名.startswith(".")
        ]
        for 名称 in 文件表:
            件表.append((取相对路径(仓根, Path(根目录) / 名称), 名称))
        for 目录名 in 子目录表:
            目录表.append((取相对路径(仓根, Path(根目录) / 目录名), 目录名))
    return 件表, 目录表


def 判禁止形状(基名: str, 泛名表: set) -> str:
    """⇒ 命中的禁止形状名（空串＝没命中）。四条：泛名 · 单汉字名 · 序数代称 · 西文单字母。"""
    查名 = 取查名()
    if 基名 in 泛名表:
        return "泛名"
    if len(基名) == 1:
        if not 基名.isascii():
            return "单汉字名"
        return "西文单字母" if 基名.isalpha() else ""
    if 查名.含序数代称作标识符(基名):
        return "序数代称"
    if 查名.是单西文字母(基名):
        return "西文单字母"
    return ""


def 扫件名禁形(上层读数: dict) -> tuple:
    """实测 ⇒ `({路径: (基名, 形状)}, 面件数)`（只收命中禁止形状的；面件数 = 件名 + 目录名总数）。"""
    仓根 = Path(上层读数["仓根"])
    泛名表 = 读泛名(仓根)
    件表, 目录表 = 走件名与目录名(仓根)
    命中 = {}
    for 路径, 名称 in 件表:
        基名 = 名称.rsplit(".", 1)[0] if "." in 名称 else 名称
        形状 = 判禁止形状(基名, 泛名表)
        if 形状:
            命中[路径] = (基名, 形状)
    for 路径, 目录名 in 目录表:
        if 目录名 in 结构目录名:
            continue
        形状 = 判禁止形状(目录名, 泛名表)
        if 形状:
            命中[路径] = (目录名, 形状)
    return 命中, len(件表) + len(目录表)


def 样本_命名件面(上层读数: dict) -> int:
    """对象数：件名 + 目录名的总数（0 ⇒ 未判：走树没读到东西）。"""
    return 扫件名禁形(上层读数)[1]


def 检查59_件名与目录名禁形(上层读数: dict) -> list:
    """件名 / 目录名的基名不许是禁止形状（存量入基线、新增即红 · 基线只许减）。"""
    输出缓冲 = []
    命中, 面件数 = 扫件名禁形(上层读数)
    if not 面件数:
        判不了(
            检查名[51],
            "全仓",
            "走树读到 0 个件名 / 目录名（走树坏了，或仓是空的）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 ⇒ 只能由判据作者确认走树口径",
        )
        return 输出缓冲
    基线表, 错误 = 读件名基线(上层读数["仓根"])
    if 错误:
        return [违规(
            检查名[51], "开发工具/信息核心/信息核心.db",
            错误,
            "「存量入基线、新增即红」要求先有存量清单（形状照判据 ㊻）；没有它，"
            "实测的全部存量会被算成「新增」⇒ 判据当场红一片，等于没上闸 ⇒ "
            "只能由维护方登记（库 `件名基线` 表）",
        )]
    口径 = (
        "命名规范：件名 / 目录名的基名也要语义自明 —— 单汉字名 · 泛名 · 序数代称 · 西文单字母 "
        "四条禁止形状对**路径名**同样成立（`命名登记` 只管代码标识符，件名**不登记**）。"
        "修法：按 `审计_文件名命名.md` 的清单改名（D1 腿）⇒ 只能由该件作者改"
    )
    for 路径, (基名, 形状) in sorted(命中.items()):
        if 路径 not in 基线表:
            输出缓冲.append(违规(
                检查名[51], 路径,
                f"件名 / 目录名基名「{基名}」落禁止形状「{形状}」，基线里没有它 ⇒ **新增即红**",
                口径,
            ))
    for 路径 in sorted(基线表):
        if 路径 not in 命中:
            输出缓冲.append(违规(
                检查名[51], 路径,
                "基线登记着这个件名 / 目录名，而实测**已经不落禁止形状**（或已改名）⇒ **陈旧登记**",
                "「基线只许减」：改掉了就该把登记删掉 ⇒ 只能由维护方删"
                "（库 `件名基线` 表 · `python3 开发工具/信息核心/信息核心.py 冻结基线`）",
            ))
    return 输出缓冲
