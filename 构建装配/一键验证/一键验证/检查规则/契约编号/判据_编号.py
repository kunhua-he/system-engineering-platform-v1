def 检查1_编号与文件名一致(上层读数: dict) -> list:
    输出缓冲 = []
    for 目录名 in 编号目录:
        if not 上层读数["编号目录存在"].get(目录名, False):
            输出缓冲.append(
                违规(
                    检查名[0],
                    f"{契约目录名}/{目录名}/",
                    f"编号目录不存在（§一 的目录布局里它必须在）",
                    f"目录不在，第 1/2/3/4 项对它就变成空集（判据的可信性.md 第二节：空集是未判，"
                    f"不是通过）——「编号与文件名一致」这条不是查过之后通过，而是没东西可查。"
                    f"目录是被删了还是从没建过，"
                    f"只能由声明方说明（§一 的布局不许悄悄少一格）⇒ 只能人来裁",
                )
            )
    for 目录名, 记录表 in 上层读数["编号表"].items():
        for 编号条目 in 记录表:
            落点 = f"{契约目录名}/{目录名}/{编号条目['文件名']}:{编号条目['字段']}"
            if 编号条目["错误"]:
                输出缓冲.append(
                    违规(
                        检查名[0],
                        落点,
                        编号条目["错误"],
                        f"文件名是号、字段也是号，两个都是号；文件读不动/解析不了，"
                        f"就没法判「编号与文件名一致」。修法是声明编写面重写这份 JSON，"
                        f"验证面不能替它猜字段值 ⇒ 只能由声明方补",
                    )
                )
                continue
            配置表 = 编号条目["数据"]
            文件名主干 = 编号条目["文件名"][:-5]
            if not 文件名主干.isdigit():
                输出缓冲.append(
                    违规(
                        检查名[0],
                        落点,
                        f"文件名 {编号条目['文件名']} 不是编号（§一：文件名 = 编号，如 0001.json）",
                        f"文件名承担「号」这个语义，改成数字就等于改号；已按名索引的工具"
                        f"（生成器 · 装载入口 · 绑定）全都按文件名寻址 ⇒ 只能人来裁",
                    )
                )
                continue
            待处理值 = 配置表.get(编号条目["字段"])
            if 待处理值 is None:
                输出缓冲.append(
                    违规(
                        检查名[0],
                        落点,
                        f"JSON 里没有 {编号条目['字段']} 字段（文件名给的是 {文件名主干}）",
                        f"字段缺失有两种可能：漏写，或字段名又改过名（改名就是造第二个事实源）。"
                        f"两种都只能由声明方按 §一 的形状补，验证面补不出来 ⇒ 只能由声明方补",
                    )
                )
                continue
            if not 是整数(待处理值):
                输出缓冲.append(
                    违规(
                        检查名[0],
                        落点,
                        f"{编号条目['字段']} 是 {type(待处理值).__name__}（{待处理值!r}），不是整数",
                        f"号必须是整数：装载入口按 u32 读它、生成器按它算指纹，字符串或浮点"
                        f"会让两侧读法不一致；该填哪个数只有声明方知道 ⇒ 只能由声明方补",
                    )
                )
                continue
            if 待处理值 != int(文件名主干):
                输出缓冲.append(
                    违规(
                        检查名[0],
                        落点,
                        f"文件名是 {文件名主干}，字段 {编号条目['字段']} 是 {待处理值}，两者不一致",
                        f"两个值都已被外部引用（文件名是号、字段也是号）；改文件名会让"
                        f"已按名索引的工具失配，改字段会让已按字段读的读者失配，"
                        f"判据没定以谁为准 ⇒ 只能人来裁",
                    )
                )
    return 输出缓冲


def 检查2_编号不重复(上层读数: dict) -> list:
    输出缓冲 = []
    for 目录名, 记录表 in 上层读数["编号表"].items():
        # (a) 文件名映射成号之后撞车：0001.json 与 1.json 是同一个号
        按杆 = {}
        for 编号条目 in 记录表:
            文件名主干 = 编号条目["文件名"][:-5]
            if 文件名主干.isdigit():
                按杆.setdefault(int(文件名主干), []).append(编号条目)
        for 号值, 同号表 in sorted(按杆.items()):
            if len(同号表) > 1:
                名表 = " · ".join(f"{契约目录名}/{目录名}/{同号条['文件名']}" for 同号条 in 同号表)
                落点 = " ↔ ".join(
                    f"{契约目录名}/{目录名}/{同号条['文件名']}:文件名" for 同号条 in 同号表
                )
                输出缓冲.append(
                    违规(
                        检查名[1],
                        落点,
                        f"{名表} 的编号都是 {号值}（文件名拼写不同、号是同一个）",
                        f"两个文件都声明了号 {号值}，删哪个都会让「编号永不回收」与"
                        f"「已公布含义永不改写」二选一破；且两个文件都可能在别处已被引用 ⇒ 只能人来裁",
                    )
                )
        # (b) 字段值撞车（文件名不同、字段声明同一个号）
        按值 = {}
        for 编号条目 in 记录表:
            if 编号条目["数据"] is None:
                continue
            待处理值 = 编号条目["数据"].get(编号条目["字段"])
            if 是整数(待处理值):
                按值.setdefault(待处理值, []).append(编号条目)
        for 号值, 同值表 in sorted(按值.items()):
            if len(同值表) > 1:
                名表 = " · ".join(
                    f"{契约目录名}/{目录名}/{同值条['文件名']}:{同值条['字段']}" for 同值条 in 同值表
                )
                落点 = " ↔ ".join(
                    f"{契约目录名}/{目录名}/{同值条['文件名']}:{同值条['字段']}" for 同值条 in 同值表
                )
                输出缓冲.append(
                    违规(
                        检查名[1],
                        落点,
                        f"{名表} 都声明了同一个号 {号值}",
                        f"两个文件都声明了号 {号值}，删哪个都会让「编号永不回收」与"
                        f"「已公布含义永不改写」二选一破；且两个号都可能在别处已被引用 ⇒ 只能人来裁",
                    )
                )
    return 输出缓冲


def 检查3_编号不在作废号表里(上层读数: dict) -> list:
    输出缓冲 = []
    落点 = f"{契约目录名}/作废号表.json:作废"
    作废 = 上层读数["作废"]
    if 作废 is None:
        输出缓冲.append(
            违规(
                检查名[2],
                落点,
                "作废号表.json 不存在或解析不了",
                f"作废号表是宪法第 7 条（只增不复用）的唯一登记处；它缺了，"
                f"「编号是否被回收」这条就无处对照。重建表要区分「从没作废过」与"
                f"「作废记录被删了」，前者可空表、后者要靠历史 ⇒ 只能人来裁",
            )
        )
        return 输出缓冲
    条目表 = 作废.get("作废")
    if not isinstance(条目表, list):
        输出缓冲.append(
            违规(
                检查名[2],
                落点,
                f"作废 不是列表（是 {type(条目表).__name__}）",
                f"§七 定死了形状 作废: [{{编号,原名称,作废于,原因,号空间}}]；改成别的形状"
                f"会让所有读它的地方（声明编写面 · 装载入口 · 生成器）读法分叉 ⇒ 只能人来裁",
            )
        )
        return 输出缓冲

    # 按**号空间**分账：{号空间: {编号: 条}}。只比同空间的号 —— 全局封禁会把两个空间的
    # 同号混为一谈（实测：错误码 16 进作废表 ⇒ 底座 能力号段 0–999 被判冲突 ⇒ 底座自身
    # 载不进来 · 31 条红）。见 `契约声明/号段图.json`「四个号空间互不相通」。
    作废号 = {}
    for 序号, 条目项 in enumerate(条目表):
        if not isinstance(条目项, dict):
            输出缓冲.append(
                违规(
                    检查名[2],
                    f"{落点}[{序号}]",
                    f"不是对象（是 {type(条目项).__name__}）",
                    f"§七 的作废行是五键对象；这一条不是对象就没法读它的号与号空间，"
                    f"也就判不了「谁作废过」⇒ 只能由声明方补",
                )
            )
            continue
        缺失项 = [键名 for 键名 in ("编号", "原名称", "作废于", "原因", "号空间") if 键名 not in 条目项]
        if 缺失项:
            输出缓冲.append(
                违规(
                    检查名[2],
                    f"{落点}[{序号}]",
                    f"缺 {(' · '.join(缺失项))}（§七 的五键：编号 · 原名称 · 作废于 · 原因 · 号空间）",
                    f"作废行是历史档案：原名称 · 作废于 · 原因 只能来自当时的记录，"
                    f"事后补不出来；号空间 是「这个号在哪个空间里作废」的唯一依据（缺了它，"
                    f"这个号会被五个空间一起排除）⇒ 验证面替它编一条就是伪造历史 ⇒ 只能由声明方补",
                )
            )
            continue
        号空间 = 条目项.get("号空间")
        if 号空间 not in 号空间值域:
            输出缓冲.append(
                违规(
                    检查名[2],
                    f"{落点}[{序号}]:号空间",
                    f"号空间 是 {号空间!r}；只认 {(' · '.join(号空间值域))} 之一",
                    f"号空间 是「这个号在哪个空间里作废」的唯一依据（§七 · "
                    f"契约声明/号段图.json 的「四个号空间互不相通」＋ 字段名册与引用方式.md §五 的类型标签）："
                    f"认不出它就退化成"
                    f"全局排除 —— 那正是「错误码 16 撞上底座能力号段 0–999」的假冲突"
                    f"（实测 31 条红）⇒ 只能由声明方补",
                )
            )
            continue
        if 是整数(条目项.get("编号")):
            作废号.setdefault(号空间, {}).setdefault(条目项["编号"], 条目项)

    # 只对**同空间**的编号目录比（号空间 → 目录）。类型空间对到 `类型声明/`（类型标签虽不属号段制，
    # 但它是独立空间 —— `字段名册与引用方式.md` §五「与上面四个不通」；补成第五个空间之前，
    # 类型声明靠「标签撞作废号」被顺带覆盖，那本身就是跨空间比较）。资源空间在 `契约声明/` 下
    # 没有对应目录 ⇒ 不比（不是漏，是无处可比）。
    for 号空间, 目录名 in 号空间到目录.items():
        同空间 = 作废号.get(号空间, {})
        if not 同空间:
            continue
        for 编号条目 in 上层读数["编号表"].get(目录名, []):
            if 编号条目["数据"] is None:
                continue
            待处理值 = 编号条目["数据"].get(编号条目["字段"])
            if 是整数(待处理值) and 待处理值 in 同空间:
                条目项 = 同空间[待处理值]
                输出缓冲.append(
                    违规(
                        检查名[2],
                        f"{契约目录名}/{目录名}/{编号条目['文件名']}:{编号条目['字段']}",
                        f"号 {待处理值} 是活跃声明，同时又在 {契约目录名}/作废号表.json 里被登记作废"
                        f"（号空间 {号空间} · 原名称「{条目项.get('原名称')}」· 作废于 {条目项.get('作废于')} · "
                        f"原因「{条目项.get('原因')}」）",
                        f"作废号永不回收是宪法第 7 条，且只比同空间的号（号空间互不相通："
                        f"四个号段空间 ＋ 类型标签空间）；"
                        f"要么给这份活跃声明换号（改声明方的事），要么撤销作废（改历史）——"
                        f"验证面替谁选都是改契约 ⇒ 只能人来裁",
                    )
                )
    return 输出缓冲
