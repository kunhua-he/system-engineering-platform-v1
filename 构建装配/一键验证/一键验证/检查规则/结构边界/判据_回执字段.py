"""判据 63：回执裁字段只许裁壳 —— 承重字段一个都不许裁。

★ 2026-10-10（回执口径，见 `项目文档/决策记录/2026-10-09_回执与绑定裁决口径.md` §五「分层约束」）：
回执顶层字段里，`退出码` / `工具` / `操作` / `截断` 等是被**探针链与流水直接依赖的承重件**
（`反馈帧样本.py::取码` 靠顶层 `退出码` 读业务码，缺即退化成 -99；`工具` / `操作` 被诊断样本
与流水读；`截断` 被死腿检测读），而 `树` / `服务` 是**纯壳字段**（全仓实测 0 处引用，
却每次调用都原样重带）。

**为什么要这一条**：两者在契约上**没有任何标记区分** —— 想裁字段只能逐个 grep 引用去猜，
删错一次就让腿里 26 条探针齐红。本条把「哪些能裁」变成可跑的判据：

  · 只判「名落在回执字段全集里」的裁字段点（`.pop("名")`）—— 别的 `.pop()` 与本条无关。
  · 名在 `_承重字段` 里 ⇒ **红**（裁承重件）。
  · 名在 `_壳字段` 里 ⇒ 过。
  · 另外核一遍：承重字段必须仍能在信封构造里找到（防止「整段搬走」这种更隐蔽的裁法）。

**扫描面必须保串**：裁字段点与承重字段名都是**字符串字面量**（形如 `点.pop(引号包的名)`），
去串会把它们一起抹掉 ⇒ 判据什么都扫不到。实测：用去串面时反向样本根本抓不住
（闸 0 全绿、自测三红 —— 那就是假绿）。保串的代价是注释/散文里出现同样的形状也会命中，
按「宁可多报」取，不设豁免表。
"""
from __future__ import annotations

import re

from ...判据编排.验证小工具 import 判不了, 违规
from ...基础定义.判据取值常量 import 检查名, 代码后缀
from ...源码解析.测试件 import 并行取生产区文本

# 纯壳字段（**唯一主人**）：全仓实测 0 处引用、每次调用原样重带，可以裁。
_壳字段 = frozenset({"树", "服务"})

# 承重字段（**唯一主人**）：被探针链 / 流水 / 诊断样本直接读，裁一个就断一条链。
_承重字段 = frozenset({"成功", "退出码", "工具", "操作", "说明", "结果", "错误", "截断", "日志"})

# 裁字段点的形状：`.pop("名")` / `.pop('名')`（可带默认值）。
_裁字段形 = re.compile(r"\.pop\(\s*[\"']([^\"']+)[\"']")

# 信封构造件：承重字段必须仍能在它里找到。
_信封构造件 = "开发工具/MCP服务/服务协议/参数规范.py"

# 扫描面按仓根缓存（同一轮闸里多个调用点不重算）。
_回执字段面缓存: dict = {}


def 回执字段面(上层读数: dict) -> dict:
    """扫描面：全仓代码件的**生产区文本**（跳过夹具区，**保串**）。"""
    键名 = str(上层读数["仓根"])
    if 键名 in _回执字段面缓存:
        return _回执字段面缓存[键名]
    件表 = [
        (键_件, 文件项["文本"])
        for 键_件, 文件项 in 上层读数["文件"].items()
        if 文件项.get("文本") is not None and 键_件.endswith(代码后缀)
    ]
    扫描面 = 并行取生产区文本(件表, 上层读数.get("测试文件集") or frozenset(), 保串=True)
    _回执字段面缓存[键名] = 扫描面
    return 扫描面


def 扫回执裁字段(件表: dict) -> list:
    """扫一遍 ⇒ 命中清单：`(路径, 行号, 字段名, 是否承重)`（只收名落在回执字段全集里的）。"""
    输出缓冲 = []
    for 键名 in sorted(件表):
        源文本 = 件表[键名]
        if not 源文本:
            continue
        for 匹配项 in _裁字段形.finditer(源文本):
            字段名 = 匹配项.group(1)
            if 字段名 not in _壳字段 and 字段名 not in _承重字段:
                continue
            行号 = 源文本.count("\n", 0, 匹配项.start()) + 1
            输出缓冲.append((键名, 行号, 字段名, 字段名 in _承重字段))
    return 输出缓冲


def 样本_回执字段(上层读数: dict) -> int:
    """对象数：扫描面下的件数（0 ⇒ 未判）。"""
    return len(回执字段面(上层读数))


def 检查63_回执裁字段只许裁壳(上层读数: dict) -> list:
    """全仓 0 处裁承重字段；且承重字段仍能在信封构造里找到。"""
    if 样本_回执字段(上层读数) == 0:
        判不了(检查名[57], "（全仓）",
              "扫描面 0 件 ⇒ 空集不算通过（空集不是「没问题」，是「这条判据这次没量到东西」）",
              "确认传进来的仓根是不是真的仓根（`上层读数[\"仓根\"]` 指到空目录时就会这样）")
        return []
    件表 = 回执字段面(上层读数)
    违规表 = [
        违规(检查名[57], "%s:%d" % (路径, 行号),
             "裁了承重字段 `%s` —— 它被探针链 / 流水 / 诊断样本直接读，裁掉即断一条链"
             "（实测：裁顶层 `退出码` ⇒ 腿里 26 条探针齐报 -99）" % 字段名,
             "承重字段不可裁；确实要换形状就先迁探针链读点（如改读 `structuredContent`），"
             "探针全迁完再一起撤，不许一步砍到底")
        for 路径, 行号, 字段名, 是承重 in 扫回执裁字段(件表) if 是承重
    ]
    信封文本 = 件表.get(_信封构造件)
    if 信封文本:
        缺失 = [字段名 for 字段名 in sorted(_承重字段) if "\"%s\"" % 字段名 not in 信封文本]
        if 缺失:
            违规表.append(违规(
                检查名[57], _信封构造件,
                "承重字段 %s 在信封构造里找不到了 —— 整段搬走是比 `.pop` 更隐蔽的裁法"
                % "、".join("`%s`" % 字段名 for 字段名 in 缺失),
                "把承重字段放回信封构造（它们是被探针链依赖的承重件，不是可以顺手精简的壳）"))
    return 违规表
