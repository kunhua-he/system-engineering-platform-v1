from __future__ import annotations

from ...判据编排.验证小工具 import 判不了, 违规
from ...基础定义.常量 import Rust后缀, 检查名


# 内核一旦持一张任务注册表，至少命中其一（与 `测试验证/准入判据/准入判据/长活原语.py::任务表认定词`
# 同形 —— 那条 runner 判动态三条，本判据判静态这一条，两条各管一面）。
任务表认定词 = ("任务表", "任务注册表", "任务表项", "任务句柄表")

# 扫描面：长活状态该住扩展侧 ⇒ 内核树里一处都不许有。
内核目录 = "运行内核"


def 扫内核任务表(上层读数: dict) -> tuple:
    """⇒ `([(件, 行号, 词)], 扫描件数)` —— 走 `运行内核/` 下 `.rs` 的**生产区文本**。"""
    命中 = []
    件数 = 0
    for 键名, 文件项 in sorted(上层读数["文件"].items()):
        if not 键名.startswith(内核目录 + "/") or not 键名.endswith(Rust后缀):
            continue
        源文本 = 文件项.get("文本")
        if 源文本 is None:
            continue
        件数 += 1
        for 关键词 in 任务表认定词:
            起点 = 源文本.find(关键词)
            if 起点 >= 0:
                命中.append((键名, 源文本[:起点].count(chr(10)) + 1, 关键词))
    return 命中, 件数


def 样本_边界表达力面(上层读数: dict) -> int:
    """对象数：`运行内核/` 下可读的 `.rs` 件数（0 ⇒ 未判：内核树没读到）。"""
    return 扫内核任务表(上层读数)[1]


def 检查58_边界表达力(上层读数: dict) -> list:
    """长活状态住扩展侧 ⇒ `运行内核/` 下 0 处任务表（三元：通过 / 失败 / 未判）。"""
    输出缓冲 = []
    命中, 件数 = 扫内核任务表(上层读数)
    if not 件数:
        判不了(
            检查名[50],
            内核目录 + "/",
            f"`{内核目录}/` 下 0 个可读 `.rs` 件（扫描面坏了，或内核树真的空了）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 ⇒ 只能由判据作者确认扫描面",
        )
        return 输出缓冲
    口径 = (
        "库 `条款` `2026-09-27_边界表达力_长活原语.md` §三/§四：长活原语 = 任务句柄（不透明 8 字节）"
        "+ 立刻返回 + 取消；**任务状态住扩展自身** —— 内核不新增任务注册表（否则内核承载业务，"
        "破入核五问第 1 问）。修法：把任务表挪回扩展侧 ⇒ 只能由该件作者改"
    )
    for 键名, 行号, 关键词 in 命中:
        输出缓冲.append(违规(
            检查名[50], f"{键名}:{行号}",
            f"`{内核目录}/` 下出现「{关键词}」—— 内核持任务表（长活状态该住扩展侧）",
            口径,
        ))
    return 输出缓冲
