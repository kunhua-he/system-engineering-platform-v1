# 调用形与定义形的字面**只此一处**：判据本体、注入样本、元数据都从这里取口径。
调用符号 = "调用能力"
卸载符号 = "卸载扩展"


def _调用点条数(源文本: str, 符号: str) -> int:
    """剥过注释与串的生产区文本里，`符号(` 的**调用点**条数（`fn 符号(` 定义形不算）。"""
    条数 = 0
    for 匹配结果 in re.finditer(re.escape(符号) + r"\s*\(", 源文本):
        行起 = 源文本.rfind("\n", 0, 匹配结果.start()) + 1
        源码行 = 源文本[行起 : 源文本.find("\n", 匹配结果.start())]
        if re.search(r"\bfn\s+" + re.escape(符号) + r"\s*\(", 源码行):
            continue
        条数 += 1
    return 条数


def 唯一执行路径面(上层读数: dict) -> dict:
    """扫描面：全仓 `.rs` 的**生产区文本**（去串 —— 字符串里的调用形不算调用）。"""
    件表 = [
        (键_件, 文件项["文本"])
        for 键_件, 文件项 in 上层读数["文件"].items()
        if 文件项.get("文本") is not None and 键_件.endswith(Rust后缀)
    ]
    return 并行取生产区文本(件表, 上层读数.get("测试文件集") or frozenset(), 保串=False)


def 样本_唯一执行路径(上层读数: dict) -> int:
    """对象数：面里这两类调用点的总条数（0 ⇒ 未判）。"""
    return sum(
        _调用点条数(件文本, 调用符号) + _调用点条数(件文本, 卸载符号)
        for 件文本 in 唯一执行路径面(上层读数).values()
    )


def 扫描违规(扫描面: dict, 判陈旧: bool = True) -> list:
    """逐件扫 ⇒ `[(件路径, [缺什么…])]`（空 = 全合规）。

    `判陈旧=假` 用在**夹具仓**上：夹具会把同一个件路径写成另一份形状（例：`合成仓_准入` 的
    `边界接缝/边界面.rs` 只有声明、没有调用），拿真仓的权威件清单去判夹具「有没有调用点」
    是张冠李戴 —— 实测那会让正向样本假红。真仓（`判陈旧=真`）照旧「白名单只许减」。
    """
    违规表 = []
    for 件路径, 件文本 in sorted(扫描面.items()):
        缺失表 = []
        调用条数 = _调用点条数(件文本, 调用符号)
        卸载条数 = _调用点条数(件文本, 卸载符号)
        if 调用条数 and 件路径 not in 权威调用件:
            缺失表.append("%d 处 `%s(` 调用点不在权威调用件里（第二调用腿）" % (调用条数, 调用符号))
        if 卸载条数 and 件路径 not in 权威卸载件:
            缺失表.append("%d 处 `%s(` 调用点不在权威卸载件里（绕过生命周期保护的卸载口）"
                        % (卸载条数, 卸载符号))
        if 判陈旧 and 件路径 in 权威调用件 and not 调用条数:
            缺失表.append("登记成权威调用件，却一个 `%s(` 调用点都没有（陈旧登记；白名单只许减）" % 调用符号)
        if 判陈旧 and 件路径 in 权威卸载件 and not 卸载条数:
            缺失表.append("登记成权威卸载件，却一个 `%s(` 调用点都没有（陈旧登记；白名单只许减）" % 卸载符号)
        if 缺失表:
            违规表.append((件路径, 缺失表))
    return 违规表


def 检查70_唯一执行路径(上层读数: dict) -> list:
    """生产区 Rust 的能力调用 / 公开卸载都只在权威件里。"""
    if 样本_唯一执行路径(上层读数) == 0:
        判不了(检查名[63], "（全仓 .rs 生产区）",
              "扫描面 0 条调用点 ⇒ 空集不算通过（这条判据这次没量到东西）",
              "确认租进来的仓根是不是真仓根、以及 `.rs` 生产区是否被测试文件集整片吃掉")
        return []
    return [
        违规(检查名[63], 件路径, "；".join(缺失表),
             "修法：调用只许从权威件走（要在新层调 ⇒ 先把该层写进 `权威调用件`/`权威卸载件` 并说明"
             "为什么这一层必须有第二个调用方，否则就是第二执行腿）")
        for 件路径, 缺失表 in 扫描违规(唯一执行路径面(上层读数),
                                          判陈旧=not 仓登记.是夹具仓(上层读数["仓根"]))
    ]
