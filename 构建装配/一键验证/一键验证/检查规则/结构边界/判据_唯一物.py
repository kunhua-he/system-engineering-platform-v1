# -*- coding: utf-8 -*-
r"""判据 56：核心只放唯一物 —— 唯一物清单每行落点在盘上存在 · 条数只许减。

依据：库 `条款` `2026-09-27_核心只放唯一物.md` §四（12 项唯一物）+
`2026-09-27_补主人与核心预算.md`（第 13 个 = 运行数据根）·
`2026-10-07_六项设计与判据裁决.md` 序号6 的下位裁定（收口方 2026-10-07 改口径）。

**为什么改口径**（原裁「members 数 == 运行内核目录数 == 唯一物条数」是编一个不成立的等式）：
实测三数**不相等** —— `Cargo.toml` members **14** ≠ `运行内核/` 目录 **9** ≠ 唯一物清单 **13**。
三者是三样不同的东西（members 含非内核节点；运行内核只数内核 crate；唯一物是概念清单）。
⇒ 改立**两条可判的**：

  ① **清单每行落点存在** —— 唯一物清单每行的「落点」路径在盘上存在（删了落点即红）；
  ② **清单只许减** —— 条数不许增（增必须走「入核五问」+ 收口方登记，形状照 `硬写能力号基线`）。

**清单落点**：库 `规则` 表 `类` = `唯一物`（一行一个唯一物；`依据` 列 = 它的**落点路径**，
`内容` 列 = 它的唯一性由谁保证）。清单缺（0 行）⇒ **未判**（fail-closed：空集不是通过）。

三元读数：**通过** = 清单非空 · 每行落点都在盘上 · 条数 ≤ 上限；
**失败** = 逐条报出（落点不存在 / 条数超上限）；**未判** = 清单为空。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path

from ...判据编排.验证小工具 import 判不了, 违规
from ...判据编排.判据基线 import 库相对路径
from ...基础定义.判据取值常量 import 检查名


# 唯一物**条数上限**（「清单只许减」的那把尺）：加第 14 个必须走「入核五问」并单独裁决 ⇒
# 改这个数就是**登记动作**本身（只能由收口方改，与 `硬写能力号基线` 的「只许减」同一条纪律）。
唯一物上限 = 13

# 清单住的表与类（只此一份）。
唯一物表 = "规则"
唯一物类 = "唯一物"


def 读唯一物清单(仓根) -> tuple:
    """⇒ `([(编号, 名, 内容, 依据)], 错误或 None)` —— 库不在 / 读不动即交错误回去（fail-closed）。"""
    库件 = Path(仓根) / 库相对路径
    if not 库件.is_file():
        return [], f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute(
                "select 编号, 名, 内容, 依据 from %s where 类 = ?" % 唯一物表, (唯一物类,)))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return [], f"`{唯一物表}` 读不动：{错误}"
    return [(表行[0] or "", 表行[1] or "", 表行[2] or "", 表行[3] or "") for 表行 in 行表], None


def 样本_唯一物面(上层读数: dict) -> int:
    """对象数：唯一物清单的条数（0 ⇒ 未判：清单没落库，本条无对象）。"""
    行表, _错误 = 读唯一物清单(上层读数["仓根"])
    return len(行表)


def 检查56_核心只放唯一物(上层读数: dict) -> list:
    """唯一物清单每行落点在盘上存在 · 条数只许减（三元：通过 / 失败 / 未判）。"""
    输出缓冲 = []
    仓根 = Path(上层读数["仓根"])
    行表, 错误 = 读唯一物清单(仓根)
    if 错误:
        判不了(
            检查名[44],
            库相对路径,
            错误,
            "「唯一物清单」住库 `规则` 表 `类`=`唯一物`（13 行）—— 读不动就判不了"
            "「每行落点在盘上 · 条数只许减」。库是唯一存本，只能由维护方补"
            "（`python3 开发工具/信息核心/信息核心.py 记规则 --类 唯一物 …`）",
        )
        return 输出缓冲
    if not 行表:
        判不了(
            检查名[44],
            库相对路径,
            "唯一物清单为空（库 `规则` 表 `类`=`唯一物` 0 行）—— 空集上两条子判据恒真 ⇒ 假绿",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。清单必须先落库"
            "（12 项 + 运行数据根 = 13 行）⇒ 只能由维护方登记",
        )
        return 输出缓冲
    口径 = (
        "库 `条款` `2026-09-27_核心只放唯一物.md` §四 + `2026-09-27_补主人与核心预算.md`："
        "唯一物 = 全平台恰好一个、换掉它所有调用方都得改的东西；加第 14 个必须走「入核五问」"
        "并单独裁决。修法：把落点改回真实路径，或（真要加）由收口方登记"
    )
    for 表行 in 行表:
        落点 = (表行[3] or "").strip()
        if not 落点:
            输出缓冲.append(违规(
                检查名[44], f"{唯一物表}:{表行[0]}",
                f"唯一物「{表行[1]}」没有落点（`依据` 列空）—— 清单每行必须能指到一处落点",
                口径,
            ))
            continue
        if not (仓根 / 落点).exists():
            输出缓冲.append(违规(
                检查名[44], 落点,
                f"唯一物「{表行[1]}」的落点 `{落点}` 在盘上不存在（清单与盘面漂了）",
                口径,
            ))
    if len(行表) > 唯一物上限:
        输出缓冲.append(违规(
            检查名[44], f"{唯一物表}:{唯一物类}",
            f"唯一物清单 {len(行表)} 条 > 上限 {唯一物上限} 条 ⇒ **只许减不许增**被破",
            "「核心只许变小」：加第 14 个唯一物必须走「入核五问」并单独裁决 ⇒ "
            "改上限 `判据_唯一物.唯一物上限` 就是登记动作本身 ⇒ 只能由收口方改",
        ))
    return 输出缓冲
