# -*- coding: utf-8 -*-
"""判据 ㊾：网页端点与接口面一致 —— 网页硬编码的端点路径 / 类型标签必须与接口面权威清单逐项相同。

依据：第九批_MCP审计_第4轮B.md 真缺陷 1 —— `前端呈现/网页应用/接口请求/请求客户端.js`（10 条端点路径 +
`类型标签` 对象）与 `编译.js`（文本类型标签字面量 `4`）是**同一事实的第二份**；判据 ㊸ 只比
「命令行界面 ↔ 对外接口面」（㊸ 件头逐字自认「旁路是网页应用那一面」）⇒ 改后端
`常量.rs` 的某条路径、或改类型标签号，网页静默失能（编译链取空 / 请求打 404）而闸 0 全绿。

**取法与 ㊸ 同一套**：权威侧复用 `判据_接口面常量._取Rust串常量`（读 `常量.rs` 的
`pub const 路径_X: &str = "…";`）；网页侧是 `.js`（㊸ 只有 Rust / Python 两个取器）⇒ 本件
只补一个 JS 常量取器与一个 JS 对象取器，**判定框架与 ㊸ 同形**（可比项 + 逐项对读），不另写。

三元读数：通过 = 逐项一致；失败 = 逐项报出差在哪一项；未判 = 两侧件缺一侧或可比项 0 条。
"""
from __future__ import annotations

import re

from ...判据编排.验证小工具 import 判不了, 违规
from ...基础定义.常量 import 检查名, 接口面件
from .判据_接口面常量 import _取Rust串常量

网页面件 = "前端呈现/网页应用/接口请求/请求客户端.js"
网页编译件 = "前端呈现/网页应用/编译调试/编译.js"
# 网页里的 10 条端点路径常量名（与后端 `常量.rs` 同名 ⇒ 逐名对读；后端另有
# `路径_生命周期` / `路径_留痕` 两条，网页不实现 ⇒ 不在本表里）。
网页面路径名表 = (
    "路径_根", "路径_能力", "路径_调用", "路径_声明", "路径_扩展",
    "路径_案例", "路径_案例跑", "路径_导出", "路径_程序文本", "路径_菜单命令",
)
# 类型标签的「文本」项名（后端 `常量.rs` 的 `pub const 文本: u32 = 4;` · 网页 `类型标签.文本`）。
文本标签名 = "文本"


def _取JS串常量(源文本: str, 名称: str):
    """JS 件里 `const <名> = "<值>";` 的值（可带 `export`；取不到 ⇒ None）。"""
    匹配结果 = re.search(
        r'(?m)^[ \t]*(?:export[ \t]+)?const[ \t]+' + re.escape(名称) + r'[ \t]*=[ \t]*"([^"]*)"', 源文本)
    return 匹配结果.group(1) if 匹配结果 else None


def _取JS对象整数(源文本: str, 对象名: str, 键名: str):
    """JS 件里 `const <对象名> = { … <键名>: <整数> … };` 的整数（取不到 ⇒ None）。"""
    对象配 = re.search(r'const[ \t]+' + re.escape(对象名) + r'[ \t]*=[ \t]*\{([^}]*)\}', 源文本)
    if not 对象配:
        return None
    键配 = re.search(r'(?<![\w$])' + re.escape(键名) + r'[ \t]*:[ \t]*(\d+)', 对象配.group(1))
    return int(键配.group(1)) if 键配 else None


def _取Rust类型标签(源文本: str, 标签名: str):
    """`常量.rs` 的 `pub mod 类型标签 { … pub const <标签名>: u32 = <整数>; … }` 的值。"""
    模块配 = re.search(r'pub mod 类型标签\s*\{(.*?)\n\}', 源文本, re.S)
    if not 模块配:
        return None
    匹配结果 = re.search(r'pub const ' + re.escape(标签名) + r'\s*:\s*u32\s*=\s*(\d+)', 模块配.group(1))
    return int(匹配结果.group(1)) if 匹配结果 else None


def _取JS编译字面量(源文本: str):
    """`编译.js` 里文本类型标签的硬编码字面量：`…类型标签) !== <整数>`。"""
    匹配结果 = re.search(r'类型标签\s*\)\s*!==\s*(\d+)', 源文本)
    return int(匹配结果.group(1)) if 匹配结果 else None


def 可比项(上层读数: dict) -> tuple:
    """两侧摊成 `[(项名, 权威值, 网页值, 权威处, 网页处)]` 与「只一侧有」的缺项表。

    判定与对象数共用这一份。权威侧 = `接口面件`（`常量.rs`）—— 与 ㊸ 取后端同一处；
    网页侧 = `取接口.js`（10 条路径 + `类型标签` 对象）· `编译.js`（文本类型标签字面量）。
    """
    文件表 = 上层读数["文件"]
    网页文本 = (文件表.get(网页面件) or {}).get("文本") or ""
    编译文本 = (文件表.get(网页编译件) or {}).get("文本") or ""
    权威文本 = (文件表.get(接口面件) or {}).get("文本") or ""
    项表 = []
    缺项表 = []
    for 路径名 in 网页面路径名表:
        权威值 = _取Rust串常量(权威文本, 路径名)
        网页值 = _取JS串常量(网页文本, 路径名)
        if 权威值 is None and 网页值 is None:
            continue
        if 权威值 is None or 网页值 is None:
            缺项表.append((f"路径 {路径名}", 权威值, 网页值, 接口面件, 网页面件))
            continue
        项表.append((f"路径 {路径名}", 权威值, 网页值, 接口面件, 网页面件))
    权威标签 = _取Rust类型标签(权威文本, 文本标签名)
    网页标签 = _取JS对象整数(网页文本, "类型标签", 文本标签名)
    if 权威标签 is not None and 网页标签 is not None:
        项表.append((f"类型标签 {文本标签名}（取接口.js）", 权威标签, 网页标签, 接口面件, 网页面件))
    elif 权威标签 is not None or 网页标签 is not None:
        缺项表.append((f"类型标签 {文本标签名}（取接口.js）", 权威标签, 网页标签, 接口面件, 网页面件))
    编译标签 = _取JS编译字面量(编译文本)
    if 权威标签 is not None and 编译标签 is not None:
        项表.append((f"类型标签 {文本标签名}（编译.js）", 权威标签, 编译标签, 接口面件, 网页编译件))
    return 项表, 缺项表


def 样本_网页端点(上层读数: dict) -> int:
    """对象数：两侧可比的项数（0 ⇒ 未判，不报通过）。"""
    项表, _缺项表 = 可比项(上层读数)
    return len(项表)


def 检查49_网页端点与接口面一致(上层读数: dict) -> list:
    """网页硬编码的端点路径 / 类型标签与接口面权威清单逐项一致。"""
    输出缓冲 = []
    文件表 = 上层读数["文件"]
    缺件表 = [路径 for 路径 in (网页面件, 接口面件) if 路径 not in 文件表]
    if 缺件表:
        判不了(
            检查名[48],
            " · ".join(缺件表),
            f"两侧件缺 {len(缺件表)} 件：{缺件表} ⇒ 网页端点无从比对",
            "这条判据的对象就是网页件（`前端呈现/网页应用/接口请求/请求客户端.js`）与接口面权威件"
            "（`对外接口面/调用接口面/src/契约级常量.rs`）；缺一件，另一件的值没有对照物 ⇒ "
            "空集是未判不是通过。补件或改落点 ⇒ 只能由该件的作者处置",
        )
        return 输出缓冲
    项表, 缺项表 = 可比项(上层读数)
    if not 项表 and not 缺项表:
        判不了(
            检查名[48],
            f"{网页面件} · {接口面件}",
            "两侧件都在，但一条可比项都取不到（10 条路径常量 · 类型标签全没读到）"
            "—— 也可能是**解析器坏了**（正则认不出 JS `const 名 = \"…\"` / Rust `pub const …`）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。修法：查本件 `_取JS串常量` / "
            "`_取Rust串常量` / `_取Rust类型标签` 的正则，或确认那两件确实还写着这些常量 ⇒ "
            "只能由判据作者确认",
        )
        return 输出缓冲
    for 项名, 权威值, 网页值, 权威处, 网页处 in 缺项表:
        输出缓冲.append(
            违规(
                检查名[48],
                f"{权威处} ↔ {网页处}",
                f"{项名} 只有一侧有：权威 {权威值!r} · 网页 {网页值!r} ⇒ 另一侧的端点清单"
                "丢了这一项（改名 / 删除会让对读静默少一项）",
                "同一事实（HTTP 端点路径 · 类型标签）在两处各写一份 ⇒ 一侧改名/删项，"
                "另一侧还在用旧名，请求会打 404 而闸 0 全绿。以接口面（`常量.rs`）为准 ⇒ "
                "改哪边只能由两侧的作者定",
            )
        )
    for 项名, 权威值, 网页值, 权威处, 网页处 in 项表:
        if str(权威值) != str(网页值):
            输出缓冲.append(
                违规(
                    检查名[48],
                    f"{权威处} ↔ {网页处}",
                    f"{项名} 两侧不一致：权威 {权威值!r} · 网页 {网页值!r}",
                    "同一事实（HTTP 端点路径 · 类型标签）在**接口面与网页应用**两处各写一份："
                    "判据 ㊸ 只比「命令行界面 ↔ 接口面」，网页应用是**另一面**（㊸ 件头自认）⇒ "
                    "改一处不改另一处就漂，网页静默失能（编译链取空 / 请求打 404）而闸 0 全绿。"
                    "以哪一侧为准要按契约（接口面 `常量.rs`）⇒ 改哪边只能由两侧的作者定",
                )
            )
    return 输出缓冲
