def _读JSON(件路径: Path):
    """读一份 JSON ⇒ 字典；读不出或不是字典就给 None（调用方按缺件报）。"""
    try:
        件内容 = json.loads(件路径.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return 件内容 if isinstance(件内容, dict) else None


def _跑翻译(夹具模块目录: Path, 出根: Path, 来源目录: Path) -> tuple:
    """真跑翻译器 ⇒ `(退出码, 输出尾)`。翻译器从本验证器所在仓取（合成仓没有它）。"""
    命令 = [
        sys.executable, str(Path(仓根) / 翻译器相对路径),
        "--源目录", str(夹具模块目录),
        "--老项目根", str(夹具模块目录.parent),
        "--输出", str(出根),
        "--来源目录", str(来源目录),
        "--依赖目录", str(Path(仓根) / 依赖目录相对路径),
    ]
    翻译结果 = subprocess.run(命令, capture_output=True, text=True, timeout=翻译超时秒)
    return 翻译结果.returncode, ((翻译结果.stdout or "") + (翻译结果.stderr or "")).strip()


def _查三类类型(出根: Path) -> list:
    """三类类型逐项查 ⇒ 问题清单（空表 = 全对）。"""
    问题表 = []
    类型目录 = 出根 / "类型声明"
    能力目录 = 出根 / "能力声明"
    if not 类型目录.is_dir() or not 能力目录.is_dir():
        return ["翻译产物里没有 `类型声明/` 或 `能力声明/` 目录"]
    标签表 = {}
    for 声明件 in sorted(类型目录.glob("*.json")):
        件内容 = _读JSON(声明件)
        if 件内容 and isinstance(件内容.get("类型标签"), int):
            标签表[件内容["类型标签"]] = 件内容
    if 列表型标签 not in 标签表:
        问题表.append("`类型声明/` 里没有 100 号（列表型）—— 列表型参数无处落标签")
    结果件 = 标签表.get(结果型标签)
    if 结果件 is None:
        问题表.append("`类型声明/` 里没有 103 号（结果型结构）")
    else:
        元素标签 = [元素项.get("类型标签") for 元素项 in (结果件.get("元素表") or [])
                    if isinstance(元素项, dict)]
        if 列表型标签 not in 元素标签:
            问题表.append("103 的元素表里没有 100 号 —— 结果型结构里嵌的列表型字段丢了")
    能力表 = []
    for 声明件 in sorted(能力目录.glob("*.json")):
        件内容 = _读JSON(声明件)
        if 件内容:
            能力表.append(件内容)
    if not 能力表:
        问题表.append("`能力声明/` 目录里一件有效声明也没有")
        参数项表 = []
    else:
        参数项表 = [参数项 for 件内容 in 能力表 for 参数项 in (件内容.get("参数表") or [])
                  if isinstance(参数项, dict)]
        if 列表型标签 not in [参数项.get("类型标签") for 参数项 in 参数项表]:
            问题表.append("能力声明的参数表里没有 100 号 —— 列表型参数没落成标签")
        if 结果型标签 not in [件内容.get("返回类型") for 件内容 in 能力表]:
            问题表.append("没有一条能力的 `返回类型` 是 103 —— 结果型结构没落成返回类型")
    默认值表 = [参数项["默认值"] for 参数项 in 参数项表
              if isinstance(参数项.get("默认值"), dict)]
    if not [默认值 for 默认值 in 默认值表
            if 默认值.get("类型标签") == 文本型标签 and 默认值.get("文本") == ""]:
        问题表.append("没有参数带 `{类型标签: 4, 文本: 空串}` —— 文本型显式空默认值丢了")
    if not [默认值 for 默认值 in 默认值表
            if 默认值.get("类型标签") == 逻辑型标签 and 默认值.get("值") == 0]:
        问题表.append("没有参数带 `{类型标签: 3, 值: 0}` —— 逻辑型显式默认值丢了")
    return 问题表


def _查号段与命名修复(出根: Path) -> list:
    """号段派生 · 命名修复 · 落盘形状 —— 在同一份真产物上查（不另跑翻译器）。

    **为什么这三条进这里**：它们原先只活在 `开发工具/老项目接入/翻译器自测.py`（unittest 孤儿，
    全仓无人 import ⇒ 写了没人跑）。同一份真产物上就能判 ⇒ 零新增翻译成本（实测判据 64 全条 67 ms）。

    **映射表缺件不是「跳过」**：它不在 ⇒ 翻译器走内置默认、命名修复根本不会发生，
    而「映射生效」正是本条要守的东西 ⇒ 缺件必须报，不许静默放过（假绿原形）。
    """
    问题表 = []
    模块号段起, 模块号段止, 号段类宽度 = _取号段口径()
    if 模块号段起 is None or 模块号段止 is None or 号段类宽度 is None:
        return ["号段口径取不到（常量表.json 的「号段类宽度」或号段图.json 的模块段）⇒ 本条判不了"]
    包声明 = _读JSON(出根 / "包声明.json")
    段位表 = []
    if 包声明 is None:
        问题表.append("翻译产物里没有 `包声明.json` ⇒ 号段与段位无从核")
    else:
        号段表 = 包声明.get("能力号段") or []
        段位表 = 包声明.get("错误段位表") or []
        if not 号段表 or not isinstance(号段表[0], dict):
            问题表.append("`包声明` 的 `能力号段` 不是 `[{起, 止}]` 形状")
        else:
            段起 = 号段表[0].get("起")
            段止 = 号段表[0].get("止")
            if not isinstance(段起, int) or not isinstance(段止, int) or 段起 > 段止:
                问题表.append("`能力号段` 的起止不是合法整数区间：%r" % (号段表[0],))
            else:
                if not (模块号段起 <= 段起 and 段止 <= 模块号段止):
                    问题表.append("号段 %d–%d 不在模块段 %d–%d 内（号段分配表没被读、或读错位置）"
                                  % (段起, 段止, 模块号段起, 模块号段止))
                期望段位 = 段起 // 号段类宽度
                if 段位表 != [期望段位]:
                    问题表.append("`错误段位表` 是 %r，而号段起 %d ⇒ 段位应为 [%d]（段位 = 号段起 // %d，不是常量）"
                                  % (段位表, 段起, 期望段位, 号段类宽度))
    # 错误码表的每个 段位 都必须与包声明同值
    if isinstance(段位表, list) and 段位表 and isinstance(段位表[0], int):
        段位期望 = 段位表[0]
        for 错误码件 in sorted((出根 / "错误码表").glob("*.json")):
            件内容 = _读JSON(错误码件)
            if 件内容 is None:
                continue
            if 件内容.get("段位") != 段位期望:
                问题表.append("错误码 %s 的 `段位` 是 %r，与包声明 `错误段位表` 的 %d 不一致"
                              % (错误码件.name, 件内容.get("段位"), 段位期望))
    # 命名修复：夹具的「覆盖」经真映射表应落成「环境覆盖值」
    #    映射表真身在 `开发工具/老项目接入/`（翻译器 `--依赖目录` 指的就是它），不是夹具目录。
    修复映射件 = Path(仓根) / 依赖目录相对路径 / "命名修复映射.json"
    if not 修复映射件.is_file():
        问题表.append("命名修复映射表不在（%s）⇒ 翻译器走内置默认、命名修复不会发生"
                      % 修复映射件.relative_to(仓根))
    else:
        确定表 = (_读JSON(修复映射件) or {}).get("确定性映射") or {}
        期望名 = 确定表.get("覆盖")
        if not 期望名:
            问题表.append("命名修复映射表里没有「覆盖」的确定性映射 ⇒ 本条无从核（表被改小了）")
        else:
            参数名表 = []
            for 声明件 in sorted((出根 / "能力声明").glob("*.json")):
                件内容 = _读JSON(声明件)
                if 件内容 is None:
                    continue
                参数名表.extend(参数项.get("名称") for 参数项 in (件内容.get("参数表") or [])
                              if isinstance(参数项, dict))
            if 期望名 not in 参数名表:
                问题表.append("参数名里没有 %r（命名修复没生效：「覆盖」原样透传了）" % (期望名,))
    # 落盘形状：指纹 64 位小写十六进制 · 能力声明按编号逐件 · 说明在位
    指纹表 = _读JSON(出根 / "指纹.json")
    if 指纹表 is None:
        问题表.append("翻译产物里没有 `指纹.json` ⇒ 落盘只写了一半")
    else:
        件指纹表 = 指纹表.get("件") or {}
        if not 件指纹表:
            问题表.append("`指纹.json` 的 `件` 是空的（一件也没记）")
        for 件名, 指纹 in sorted(件指纹表.items()):
            if not isinstance(指纹, str) or len(指纹) != 64 or 指纹 != 指纹.lower():
                问题表.append("`指纹.json` 里 %s 的指纹不是 64 位小写十六进制：%r" % (件名, 指纹))
        if "包声明.json" not in 件指纹表:
            问题表.append("`指纹.json` 没记 `包声明.json` ⇒ 指纹面漏了主件")
    if not (出根 / "说明" / "使用说明.md").is_file():
        问题表.append("翻译产物里没有 `说明/使用说明.md`（落盘漏了说明）")
    return 问题表


def _查默认值三态与损失(出根: Path) -> list:
    """默认值三态可辨 + 承载不下的类型不得冒充显式默认值。

    三态（`读默认值槽` 的口径）：未提供（键不在）· 空值（类型标签 0）· 显式默认（标签非 0）。
    承载损失：老项目给了默认值、而该类型标签承载不下 ⇒ 必须落空值槽并记进 `保真损失`，
    不许静默丢掉（那是「一条数据两套读法」的源头）。
    """
    问题表 = []
    能力目录 = 出根 / "能力声明"
    if not 能力目录.is_dir():
        return ["翻译产物里没有 `能力声明/` 目录"]
    三态 = set()
    承载不下的显式默认 = []
    for 声明件 in sorted(能力目录.glob("*.json")):
        件内容 = _读JSON(声明件)
        if 件内容 is None:
            continue
        for 参数项 in (件内容.get("参数表") or []):
            if not isinstance(参数项, dict):
                continue
            默认值 = 参数项.get("默认值")
            if not isinstance(默认值, dict):
                问题表.append("能力声明 %s 的参数 %r 没有 `默认值` 槽（三态不可辨）"
                              % (声明件.name, 参数项.get("名称")))
                continue
            标签 = 默认值.get("类型标签")
            if 标签 == 0:
                三态.add("空值")
            elif isinstance(标签, int):
                三态.add("显式默认")
            else:
                问题表.append("能力声明 %s 的参数 %r 默认值标签不是整数：%r"
                              % (声明件.name, 参数项.get("名称"), 标签))
            if isinstance(标签, int) and 标签 not in (0, 1, 2, 3, 4, 6):
                承载不下的显式默认.append("%s:%s" % (声明件.name, 参数项.get("名称")))
    if "空值" not in 三态:
        问题表.append("参数表里没有一件是「空值」态（类型标签 0）⇒ 三态只剩两态")
    if "显式默认" not in 三态:
        问题表.append("参数表里没有一件是「显式默认」态 ⇒ 三态只剩两态")
    if 承载不下的显式默认:
        问题表.append("承载不下的类型却落了非空槽（应为空值槽并记保真损失）：" + " · ".join(承载不下的显式默认))
    return 问题表


def _取号段口径() -> tuple:
    """号段口径从**真源**读 ⇒ `(模块段起, 模块段止, 号段类宽度)`。

    不写死值：号段类宽度 的主人 = `契约声明/常量表.json`（按名取）；
    模块段的主人 = `契约声明/号段图.json` 的 `能力号段` 里「模块（扩展」那一段。
    两处任一取不到 ⇒ 给 `None`，调用方按「判不了」报（不许静默当通过）。
    """
    契约根 = Path(仓根) / "契约声明"
    常量表 = _读JSON(契约根 / "常量表.json") or {}
    类宽度 = None
    for 常量条目 in (常量表.get("常量") or []):
        if isinstance(常量条目, dict) and 常量条目.get("名") == "号段类宽度":
            类宽度 = 常量条目.get("值")
            break
    号段图 = _读JSON(契约根 / "号段图.json") or {}
    模块段起 = 模块段止 = None
    for 段项 in (号段图.get("能力号段") or []):
        if not isinstance(段项, dict):
            continue
        if "模块（扩展" in str(段项.get("归属") or ""):
            模块段起, 模块段止 = 段项.get("起"), 段项.get("止")
            break
    return 模块段起, 模块段止, 类宽度


def _查子表形状拒绝() -> list:
    """子表形状四类错 ⇒ 生成器拒（直接调校形纯函数，零子进程成本）。

    **为什么本判据能这么判**：四张子表同形 `{名称, 类型标签, 说明}`，校形在
    `构建装配/形态装配/生成声明/声明读取/读子表.py::读子表项` —— 纯函数、不起进程（import 实测 64 ms，
    且已在本判据的进程里）。原先这块断言只活在 `构建装配/形态装配/生成声明/参数生成测试.py`
    （unittest 孤儿，全仓无人 import ⇒ 写了没人跑），且走真跑 CLI（rustc 级成本）。

    成对样本：四类错各必须被拒（只报一类就是漏判）+ 合法项与空表必须过（不许误拒）。
    """
    问题表 = []
    # 子表校形的**唯一实现**在生成声明链（`读子表.py::读子表项`）—— 引它、不另写一套。
