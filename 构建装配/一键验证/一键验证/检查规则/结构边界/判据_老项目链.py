def _查落盘按编号(出根: Path) -> list:
    """落盘按编号逐件 —— 件名与件里的编号字段必须一致（件名即编号）。

    原先只活在 `翻译器自测.py::test_落盘`（unittest 孤儿）的「按编号逐件在位」那半；
    指纹那半已在 `_查号段与命名修复` 里。落盘写成汇总件、或件名与编号错位，
    形状判据看不出来，这一条会红。
    """
    问题表 = []
    for 目录名, 键名 in (("能力声明", "编号"), ("类型声明", "类型标签"), ("错误码表", "码")):
        目录路径 = 出根 / 目录名
        if not 目录路径.is_dir():
            问题表.append("翻译产物里没有 `%s/` 目录" % 目录名)
            continue
        件表 = sorted(目录路径.glob("*.json"))
        if not 件表:
            问题表.append("`%s/` 目录里一件也没有" % 目录名)
            continue
        for 声明件 in 件表:
            件内容 = _读JSON(声明件)
            if 件内容 is None:
                问题表.append("`%s/%s` 读不出（不是有效 JSON 对象）" % (目录名, 声明件.name))
                continue
            词干 = 声明件.stem
            if not 词干.isdigit():
                问题表.append("`%s/%s` 的件名不是十进制编号" % (目录名, 声明件.name))
                continue
            if 件内容.get(键名) != int(词干):
                问题表.append("`%s/%s` 的件名与件里的「%s」%r 不一致（件名即编号）"
                              % (目录名, 声明件.name, 键名, 件内容.get(键名)))
    return 问题表


