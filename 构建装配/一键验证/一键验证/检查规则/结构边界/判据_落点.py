def _展开花括号(扫描面项: str) -> list:
    """把 `a/{b,c}/d` 展开成 `[a/b/d, a/c/d]`（扫描面里就一层花括号）。"""
    扫描面项 = str(扫描面项)
    if "{" in 扫描面项 and "}" in 扫描面项:
        文本前缀, 剩余部分 = 扫描面项.split("{", 1)
        括号内容, 尾部 = 剩余部分.split("}", 1)
        return [文本前缀 + 号段.strip() + 尾部 for 号段 in 括号内容.split(",")]
    return [扫描面项]


# 落点存在性按 (仓根, 落点, 期望形状) 缓存：判据器的仓在一次运行里不变，而 `--自测` 会反复调本判据
# （每个夹具一次）—— 不缓存的话，同一批真实落点会被重复 glob 几十次（实测撞到过：
# `--自测` 因此被顶过 5 s 硬顶）。
_存在缓存: dict = {}


def 落点存在(仓根: Path, 落点项: str, 期望: str = "文件") -> bool:
    """一条落点（文件 / 目录 / 花括号或通配模式）在被扫仓里找得到**且形状对**吗。

    ★ 2026-09-30 收紧（判据假绿审计 ㉖）：原来只要 `exists()` ⇒ 落点写成同名**目录**也算过，
    而本条判据正是「防写死文件名」的守卫。现在按**形状**判（`期望` 三档）：
    `"文件"` ⇒ 必须 `is_file()`；`"目录"` ⇒ 必须 `is_dir()`；`"任意"` ⇒ 只看在不在
    （`扫描面` 那一栏混着件与目录，且带花括号/通配，故仍按「在不在」判）。
    """
    键名 = (str(仓根), str(落点项), 期望)
    if 键名 in _存在缓存:
        return _存在缓存[键名]
    判定汇总 = False
    for 单条落点 in _展开花括号(落点项):
        单条落点 = 单条落点.strip().rstrip("/")
        if not 单条落点:
            continue
        if any(通配符 in 单条落点 for 通配符 in "*?["):
            命中表 = glob.glob(str(仓根 / 单条落点), recursive=True)
            if 期望 == "文件":
                命中表 = [命中 for 命中 in 命中表 if Path(命中).is_file()]
            elif 期望 == "目录":
                命中表 = [命中 for 命中 in 命中表 if Path(命中).is_dir()]
            if 命中表:
                判定汇总 = True
                break
        else:
            实体 = 仓根 / 单条落点
            if (
                (期望 == "文件" and 实体.is_file())
                or (期望 == "目录" and 实体.is_dir())
                or (期望 == "任意" and 实体.exists())
            ):
                判定汇总 = True
                break
    _存在缓存[键名] = 判定汇总
    return 判定汇总


def 判据落点表(元数据: dict) -> list:
    """把判据元数据摊成 `[(判据名, 落点, 是什么, 期望形状)]`（一处定义）。

    `扫描面` 只判「在不在」（它混着件与目录，且可带花括号/通配）；`落点` 一律按**件**判；
    `目录落点` 一律按**目录**判 —— 见 `落点存在` 的 `期望`。分栏就是为了让「件 / 目录」
    的期望写在**声明**里，而不是在判据里用 `exists()` 一刀切（审计 ㉖）。
    """
    输出缓冲 = []
    for 名称, 元数据项 in 元数据.items():
        扫描面 = 元数据项.get("扫描面")
        for 扫描面项 in (扫描面 if isinstance(扫描面, (list, tuple)) else [扫描面]):
            if 扫描面项:
                输出缓冲.append((名称, str(扫描面项), "扫描面", "任意"))
        for 落点项 in 元数据项.get("落点") or ():
            输出缓冲.append((名称, str(落点项), "落点", "文件"))
        for 落点条目 in 元数据项.get("目录落点") or ():
            输出缓冲.append((名称, str(落点条目), "目录落点", "目录"))
    return 输出缓冲


def 检查26_判据落点不悬空(上层读数: dict) -> list:
    """每个判据器的落点都还能找到（落点悬空即红）。

    三元读数：**通过** = 判据面非空且无悬空；**失败** = 逐条报出悬空落点；
    **未判** = 判据面为空（元数据读不到）。
    """
    输出缓冲 = []
    元数据 = 上层读数.get("判据元数据覆盖") or 判据元数据
    if not 元数据:
        判不了(
            检查名[25],
            "判据元数据",
            "判据面下 0 条判据（读不到判据元数据）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 没有判据面，"
            "「落点不悬空」无从谈起 ⇒ 只能由判据作者确认元数据可读",
        )
        return 输出缓冲

    # 判据器的落点按**判据自身所在的仓**判（被扫的仓可以是合成夹具，夹具里没有这些落点）。
    for 名称, 落点项, 是什么, 期望 in 判据落点表(元数据):
        if not 落点存在(仓根, 落点项, 期望):
            输出缓冲.append(
                违规(
                    检查名[25],
                    落点项,
                    f"判据「{名称}」的{是什么} `{落点项}` 在 `{仓根.name}` 里**找不到**"
                    f"（期望形状：{期望}）⇒ 落点悬空",
                "判据器的落点写死成「文件路径」时，拆分/搬家会让它取空 ⇒ "
                "整条检查被**静默跳过**（闸还是绿的）。落点必须**按符号/目录在目录里找**"
                "（`契约声明/src` 而不是 `契约声明/src/lib.rs`），并且本判据盯着它 —— "
                "悬空即红。修法：把落点改成那个符号/目录所在的**目录**，或把落点登记改成"
                "新落点 ⇒ 只能由该判据的作者改（`构建装配/一键验证/一键验证/判据编排/判据元数据.py`）",
                )
            )
            continue
        # 具名符号落点（`路径::符号名`）必须**真取到那个符号的声明** —— 与判据 ⑨ 同一份判法
        # （`冻结形状.抽符号声明文本`）。落点在、符号不在 ⇒ 与「落点悬空」同罪（眼睛还在、
        # 瞳孔没了）：判据读它时取空，整条检查照样**静默跳过**。
        若路径, _, 符号名 = str(落点项).partition("::")
        if "::" not in str(落点项) or not 符号名.strip():
            continue
        源文本 = (上层读数.get("文件") or {}).get(若路径, {}).get("文本") or ""
        if 源文本 and 抽符号声明文本(源文本, 符号名.strip()) is None:
            输出缓冲.append(
                违规(
                    检查名[25],
                    f"{若路径}::{符号名.strip()}",
                    f"判据「{名称}」的{是什么} 里的符号「{符号名.strip()}」在 `{若路径}` 里找不到",
                    "落点写了 `路径::符号名` 就该能抽到那个声明（判据 ⑨ 的同一份判法）；"
                    "抽不到说明符号改名/搬走/换了声明种类 ⇒ 判据读它时取空、整条检查静默跳过。"
                    "修法：把落点改成新符号，或把它改成**目录**（按符号在目录里找）⇒ "
                    "只能由该判据的作者改（`构建装配/一键验证/一键验证/判据编排/判据元数据.py`）",
                )
            )
    return 输出缓冲
