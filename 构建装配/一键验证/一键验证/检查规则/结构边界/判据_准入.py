# 判法的唯一落点：独立 runner 的包根（**判据自身所在仓**，不是被扫的仓）。
_准入包根 = str(仓根 / "测试验证" / "准入判据")
_判据模块 = None


def _取判据模块():
    """惰性取独立 runner 的判据模块（`准入判据.判据`）。`sys.path` 只插一次。"""
    global _判据模块
    if _判据模块 is None:
        if _准入包根 not in sys.path:
            sys.path.insert(0, _准入包根)
        from 准入判据 import 判据 as 准入判据模块
        _判据模块 = 准入判据模块
    return _判据模块


_世界缓存: dict = {}      # {仓根: 世界}
_判结果缓存: dict = {}    # {(仓根, 判名): (状态, 说明, 对象数)}


def _取世界(上层读数):
    """按 `仓根` 记忆世界：一次验证里 10 条判据共用一个（`世界` 只建一次）。"""
    仓根键 = str(上层读数["仓根"])
    判读世界 = _世界缓存.get(仓根键)
    if 判读世界 is None:
        判读世界 = _取判据模块().判读世界(仓根键)
        _世界缓存[仓根键] = 判读世界
    return 判读世界


def _跑一条判据(上层读数, 判名):
    """转调独立 runner 的一条判据 ⇒ `(状态, 说明, 对象数)`（按 `(仓根, 判名)` 记忆）。"""
    缓存键 = (str(上层读数["仓根"]), 判名)
    记住 = _判结果缓存.get(缓存键)
    if 记住 is None:
        记住 = getattr(_取判据模块(), 判名)(_取世界(上层读数))
        _判结果缓存[缓存键] = 记住
    return 记住


def _转违规列表(名称, 落点, 不能自愈, 判定汇总):
    """runner 的三元结果 ⇒ 闸 1 的违规列表（`未判` 走未判通道，**不许当通过**）。"""
    状态, 说明, _对象数 = 判定汇总
    if 状态 == "通过":
        return []
    if 状态 == "失败":
        return [违规(名称, 落点, 说明, 不能自愈)]
    判不了(名称, 落点, 说明, 不能自愈)
    return []


