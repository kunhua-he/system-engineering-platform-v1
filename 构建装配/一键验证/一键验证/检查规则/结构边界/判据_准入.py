"""判据 ㉗–㊱：外部支持库准入判据（机器可判的 10 条）并入主门禁。

★ **判法以独立 runner 为准**（`测试验证/准入判据/准入判据/判据.py`），本模块**只转调**。
  为什么（#229 实测）：这两处曾各写一遍同样的 10 条 ⇒ 改一处漏另一处 —— `服务::跑`→`跑服务`
  改名只改了本模块，独立 runner 的 `判_16_适配器SendSync` 仍找旧串 ⇒ **闸 0 全绿而 `准入判据.py` 红**。
  一处实现才不会静默漂：判法只在 runner，本模块把它的 `(状态, 说明, 对象数)` 翻成闸 1 的
  `违规(...)` 列表（`通过` ⇒ 空表 · `失败` ⇒ 一条违规 · `未判` ⇒ 走未判通道，不许当通过）。

判据编号 ↔ 准入判据编号：
  ㉗=④ 广播段 · ㉘=⑤ 通知口 · ㉙=⑦ 接缝冻结 · ㉚=⑧ 无死键 · ㉛=⑨ crate-type ·
  ㉜=⑩ 命令类别 · ㉝=⑪ 显式顺序 · ㉞=⑬ 报因 · ㉟=⑭ 指纹可跑 · ㊱=⑯ 并发。

**未判的 5~6 条（①②③⑥⑫⑮）不进主门禁**：它们要么要一个允许跑 cargo 的窗口、要么要一个真外部库，
是「跑一次也没有读数」的裁决项 —— 留在 `准入判据.py` 照实报「未判」（不许当通过）。

**导入方向（闸 1 → `测试验证/准入判据`）**：惰性 import + `sys.path` 插**判据自身所在仓**的
`测试验证/准入判据`（照 `判据_命名.py::_查名` 的先例：工具从判据自身那棵树取，不从被扫的仓取）。
这不是「闸 1 调用闸 2」——闸 2 是 `测试验证/契约一致性/扫实现.py`（实现侧）；本件读的是
**判法的唯一落点**（准入判据的独立 runner），闸 1 只是它的一个消费者。

**世界与判结果按 `仓根` 记忆**（一次验证里只建/判一次）：10 条判据共用一个世界，而
`对象数_2X` 要的是**同一份**读数（搭判据批的车那条纪律，见 `验证.py::跑一项判据`）。
不跨「被扫仓不同」复用（夹具仓路径各不相同 ⇒ 不会串；同 `读文件._合成索引缓存` 的理由）。
"""

from __future__ import annotations

import sys

from ...判据编排.验证小工具 import 判不了, 违规
