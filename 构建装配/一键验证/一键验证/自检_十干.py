# -*- coding: utf-8 -*-
"""解析器的身份证 · 判据 ㊵（零字面十干）：正/反样本 + 承重证明 + 排除面。

为什么单列：`判据的可信性.md` §三.5「判据的解析器坏了」是假绿来源之一 —— 走树 / 逐字节
读原文是判据 ㊵ 的眼睛，它自身也要有反向样本（该抓的抓得住）与正向样本（干净件不许报红）。

★ 样本里的十干字**按码位取**（`chr(0x7532)` 一类）—— 本件自身也在判据 ㊵ 的扫描面内，
写整字会给**自身**造一处真违规（先例：`注入_行号引用` 把行号写成 `{12}`）。
"""
from __future__ import annotations

import sqlite3
import tempfile
from pathlib import Path

from .判据_十干 import 扫十干, 数命中, 十干字, 路径被排除, 十干面, 词内十干, 去词内十干
from .命名扫描 import 抽标识符, 剥后缀


def _只剥标识符命中(后缀: str, 文本: str, 字表: str) -> list:
    """**退回一步**的面：只剥注释与字符串后抽**标识符**（判据 ㉒ 的那条路）——
    用来证明「逐字节读原文」这一步真在承重（注释 / 字符串里的十干它必漏）。"""
    return [标识符名 for 标识符名 in 抽标识符(剥后缀(后缀, 文本)) if any(字符 in 字表 for 字符 in 标识符名)]


def 自检_十干扫描() -> list:
    """判据 ㊵ 的走树 / 读原文 / 排除面的正反样本与承重证明。

    五问：① 正向（注释 / 字符串 / 散文里的字面十干）抓得住；② 反向（干净件）不报红；
    ③ 承重证明：退回「只剥标识符」⇒ 注释 / 字符串样本必漏；④ 排除面：`构建环境/` 与
    `只读参考/` 里的巧合字节不算（否则是假红）；⑤ 白名单机制：词内十干（空表）不影响判定；
    ⑥ 库 `条款` 表（已删 md 的正文）在面里（`.db` 整份不是合法 UTF-8 ⇒ 走树会跳过它）。
    """
    字表 = 十干字()
    首字 = 字表[0]
    输出缓冲 = []

    # ── ① 正向样本（该抓的）：注释 · 字符串 · 散文里的字面十干 ──
    件表 = {
        "运行内核/样例.rs": "// 注释里的字面十干 " + 首字 + "\npub fn 样例() {}\n",
        "前端呈现/样例.js": "const 说明 = \"" + 首字 + "\";\n",
        "项目文档/样例.md": "散文里的字面十干 " + 首字 + "。\n",
    }
    命中 = 数命中(扫十干(件表))
    输出缓冲.append((
        "正向样本：注释 / 字符串 / 散文里的**字面十干** ⇒ 抓得住（这正是判据 ㉒ 拦不住的那一类）",
        all((路径, ord(首字)) in 命中 for 路径 in 件表),
        "命中键 = %s（三件都要有）" % sorted(命中),
    ))

    # ── ② 反向样本：干净件不许报红 ──
    干净面 = {
        "运行内核/样例.rs": "// 干净的注释：`序数代称字` 这几个字本身不是十干\npub fn 样例() {}\n",
        "项目文档/样例.md": "干净的散文，一个十干字都没有。\n",
    }
    干净命中 = 扫十干(干净面)
    输出缓冲.append((
        "反向样本：干净件 ⇒ 不报红",
        not 干净命中,
        "命中 = %s（要求空）" % 干净命中,
    ))

    # ── ③ 承重证明（退回一步）：只剥标识符 ⇒ 注释 / 字符串样本必漏 ──
    注释样本 = "// 注释里的字面十干 " + 首字 + "\npub fn 样例() {}\n"
    串样本 = "pub fn 样例() -> &'static str { \"" + 首字 + "\" }\n"
    原文命中 = 扫十干({"件.rs": 注释样本}) + 扫十干({"件.rs": 串样本})
    标识符命中 = _只剥标识符命中(".rs", 注释样本, 字表) + _只剥标识符命中(".rs", 串样本, 字表)
    输出缓冲.append((
        "承重证明（退回一步）：把「逐字节读原文」退回成「只剥标识符」⇒ 注释 / 字符串样本必漏",
        bool(原文命中) and not 标识符命中,
        "原文 %d 处 · 只剥标识符 %d 处（要求 原文 > 0 且 标识符 == 0）"
        % (len(原文命中), len(标识符命中)),
    ))

    # ── ④ 排除面：`构建环境/` 与 `只读参考/` 里的巧合字节不许被算进来（否则是假红）──
    # 真造一个仓外夹具：两个排除目录各放一个**含十干字**的件，另放一个真件 ⇒ 走树只收真件。
    with tempfile.TemporaryDirectory(prefix="十干排除面-") as 临时:
        临时根 = Path(临时)
        for 目录名 in ("构建环境", "只读参考", "运行内核"):
            (临时根 / 目录名).mkdir()
        (临时根 / "构建环境" / "缓存.bin").write_text("巧合字节 " + 首字 + "\n", encoding="utf-8")
        (临时根 / "只读参考" / "语料.md").write_text("只读语料 " + 首字 + "\n", encoding="utf-8")
        (临时根 / "运行内核" / "真件.rs").write_text("真件里的十干 " + 首字 + "\n", encoding="utf-8")
        键集 = set(十干面({"仓根": 临时根}))
        输出缓冲.append((
            "排除面：`构建环境/` 与 `只读参考/` 里的巧合字节不算（否则是假红）",
            键集 == {"运行内核/真件.rs"}
            and 路径被排除("构建环境/缓存.bin") and 路径被排除("只读参考/语料.md"),
            "面里的件 = %s（要求只有真件）" % sorted(键集),
        ))

    # ── ⑤ 白名单机制：词内十干（**空表**）⇒ 判定不受影响 ──
    输出缓冲.append((
        "白名单机制：词内十干表实测为空 ⇒ 去词内十干是恒等（表非空时才剥）",
        词内十干 == () and 去词内十干(首字) == 首字,
        "词内十干 = %r（要求空）· 去词内十干(十干首字) 仍等于它自身" % (词内十干,),
    ))

    # ── ⑥ 库 `条款` 表（已删 md 的正文）也在面里 ──
    # `.db` 整份不是合法 UTF-8（sqlite 头 + 页对齐零字节）⇒ 走树会**整份跳过它**，
    # 那批正文成盲区。真造一个临时库：`条款` 表里放一行**含十干字**的正文 ⇒
    # `十干面` 必须把它收进面、且报红。
    with tempfile.TemporaryDirectory(prefix="十干条款面-") as 临时:
        临时根 = Path(临时)
        库目录 = 临时根 / "开发工具" / "信息核心"
        库目录.mkdir(parents=True)
        连接 = sqlite3.connect(库目录 / "信息核心.db")
        连接.execute(
            "create table 条款(文档路径 text not null, 序号 integer not null, "
            "标题 text, 正文 text not null, 权威档 text, primary key(文档路径, 序号))"
        )
        连接.execute(
            "insert into 条款 values(?,?,?,?,?)",
            ("项目文档/样例.md", 1, "一节", "已删 md 的正文里的十干 " + 首字, None),
        )
        连接.commit()
        连接.close()
        条款面 = 十干面({"仓根": 临时根})
        条款键 = "库::条款::项目文档/样例.md::1"
        输出缓冲.append((
            "库 `条款` 表（已删 md 的正文）在面里：临时库里放一行含十干字的正文 ⇒ 必须收进面并报红",
            条款键 in 条款面 and bool(扫十干({条款键: 条款面.get(条款键, "")})),
            "面里的键 = %s（要求含 `%s`）" % (sorted(条款面), 条款键),
        ))
    return 输出缓冲
