# 外层壳把它的起表点（秒 · `time.monotonic()` 口径）经这个变量送给子进程。
# 名字必须 ASCII（`sh` / `zsh` 不认非 ASCII 变量名）。也够**唯一**：只有闸 0 的壳设它。
采样环境变量 = "V1_GATE_OUTER_START"

# 采样的三种来源（读数行里照实写出来，读的人不必猜这次判的是谁）。
来源_外层壳 = "外层壳送来的采样（本命令 = 外层那条命令）"
来源_进程内 = "进程内自量（本命令 = 本进程）"
来源_兜底 = "进程内自量兜底（⑱ 被单独调用，没走命令壳的收尾）"


def 读入采样():
    """⇒ 外层壳送进来的**起表秒**；没设 / 设了个读不出的值 ⇒ `None`。

    读不出（`float()` 抛 `ValueError`）时回 `None` **而不是抛异常**：环境变量是壳写进来的，
    壳写坏了不许把一条命令变成 traceback —— 退回进程内自量那条路，照样判、照样报。
    """
    文本值 = os.environ.get(采样环境变量)
    if not 文本值:
        return None
    try:
        return float(文本值)
    except ValueError:
        return None


def 外送模式() -> bool:
    """本次运行是不是「外层壳在判」⇒ 给读数行用（说清这次量的是谁）。"""
    return 读入采样() is not None


def 外送采样(起表秒: float) -> dict:
    """外层壳用：把它的起表点包成子进程环境（在起子进程之前合并进 `env`）。"""
    return {采样环境变量: repr(起表秒)}


def 定读数毫秒(上层读数: dict, 进程起始时刻: float) -> tuple:
    """⇒ `(读数毫秒, 读数来源)` —— 外层采样优先，其次 `上` 里那一份，最后进程内兜底。

    三档**从强到弱**：
      · 外层壳采样（覆盖外层命令的全部墙钟 · 含两条闸的采集与收集）；
      · 进程内自量（`跑一遍` / `跑全量判据` 在两遍都跑完之后写进 `上["本命令墙钟毫秒"]`）；
      · 进程内已耗时兜底（⑱ 被**单独**调用、没走命令壳的收尾 —— 这是个**偏小**的下界，
        只该出现在自测 / 调试路径，见 `判据_墙钟与行数.py` 的说明）。
    """
    外层起表秒 = 读入采样()
    if 外层起表秒 is not None:
        return int((time.monotonic() - 外层起表秒) * 1000), 来源_外层壳
    读数毫秒 = 上层读数.get("本命令墙钟毫秒")
    if 读数毫秒 is not None:
        return 读数毫秒, 来源_进程内
    return int((time.perf_counter() - 进程起始时刻) * 1000), 来源_兜底


def 报告墙钟(读数毫秒: int, 读数来源: str, 阶段说明: str) -> list:
    """量墙钟 ⇒ **照实打读数**；只有**超失控护栏**才判红（防真挂死）。

    **★ 2026-10-13 用户当场裁定（口径再变）**：原话「之前是改过了。超过就超过了，记录也不记录了」
    「就是没有强制 5 秒这个要求了，也不报错了」⇒ 5 秒这一维**整条撤掉**：
      · 超效率目标（5 秒）⇒ **什么也不做**（2026-10-09 是「记一条债务」，2026-10-13 连记录也去掉）；
      · 超失控护栏（90 秒）⇒ **判红**（一条违规）—— 它只防「真挂死把 `合主干.lock` 占死」，
        与「快不快」无关；
      · 读数照实打出来（人看效率的窗口）。
    ★ **进程内自量与闸 0 外层共用本函数** —— 两边各写一份报告就是「同一件事两套实现」
      （`判据的可信性.md` 第三节第三条的假绿来源）：一处改了，另一处看不出来。
    """
    护栏线毫秒 = 失控护栏毫秒 - 尾巴余量毫秒
    if 读数毫秒 > 护栏线毫秒:
        return [
            违规(
                检查名[17],
                "本命令墙钟",
                f"读数 {读数毫秒} ms > 失控护栏线 {护栏线毫秒} ms"
                f"（= 护栏 {失控护栏毫秒} − 尾巴余量 {尾巴余量毫秒}）⇒ 疑似真挂死（{读数来源}）",
                "2026-10-13 口径：墙钟**不判效率目标、也不记债务**，只有**失控护栏**（90 秒）"
                "仍是判决线 —— 没有它，一条真挂死的命令会把 `合主干.lock` 永久占住、"
                "后面所有合并都被堵死。修法是**查挂死**，不是放宽护栏。",
            )
        ]
    return []
