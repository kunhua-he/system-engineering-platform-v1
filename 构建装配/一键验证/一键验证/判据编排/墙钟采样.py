r"""墙钟采样 —— 判据 ⑱ 的读数**来源**：本进程自量，还是外层壳量好了送进来。

**为什么要这一件**（2026-10-08）：判据 ⑱ 原先**只在进程内自量**本命令墙钟
（`起始时刻` → 判据跑完那一刻）。而 ⑱ 的对象是「**本命令**这一次运行」：用户敲 `闸0.py` 时
本命令 = 闸0，那两条闸是它的**子步骤**。子步骤的墙钟里混着「另一条闸同时在抢 CPU」的那一段
（读数被污染，不是真超顶）⇒ 两条闸只能串行跑，提速无从谈起。

**这一件的落法**：把「本命令墙钟从哪来」与「怎么判它」拆开 ——
  · `定读数毫秒()`：有外层采样就用外层采样，没有就退回进程内自量；
  · `报告墙钟()`：唯一一处报告（`效率目标 − 尾巴余量` 超了就记债务），外层与自量**共用**它。

**外层怎么把采样送进来**：`闸0.py` 在**起子进程之前**把它的起表点写进环境变量
`采样环境变量`（秒 · `time.monotonic()` 口径）⇒ 子进程里的 ⑱ 用
`time.monotonic() − 起表秒` 直接得到**外层那条命令**此刻的完整已耗时。
`time.monotonic()` 是**系统级**时钟（不随进程走）⇒ 父进程的读数在子进程里直接可用，
不需要文件、不需要跨进程同步 —— 这也正是「命令级墙钟只能由它自身的壳量」那条裁决的落法。

**强度不降反而升**：外层读数覆盖**外层命令从启动到此刻**的**全部**墙钟（含两条闸的调度、
采集、收集那段），比进程内自量覆盖得更全；报告线仍按「效率目标 − 该命令的尾巴余量」取，未放宽。
"""

