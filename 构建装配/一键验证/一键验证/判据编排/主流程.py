def 解析只跑(词表: list) -> tuple:
    """`--只跑` 后面那串（逗号分隔）⇒ `(判据名集, 错误或 None)`。**口径与选择器同源**。

    合法面 = `判据表.检查表` 的**可运行判据**：词可给**编号**（`19` · `⑲`）或**判据名的一段**。
    本件原先按 `常量.检查名` 的**目录**（55 条：含两条空位占位与已删旧名）筛 —— 那与真跑的
    `检查表`**不同源** ⇒ 目录里有、可运行表里没有的名（如 `㉒ 命名防回潮`）会被放行到
    `跑全量判据`，那儿一条都不过 ⇒ 内部 `UnboundLocalError`（既不是清楚的「拒」，又掩盖了
    「选中 0 条 = 假绿」）。现整段交 `判据选择.解析选择`（一处定义 · 两处复用）。
    """
    return 解析选择(词表)


