# -*- coding: utf-8 -*-
"""解析器的身份证 · 引用扫描（判据 ㊴）：正/反/自引用样本 + 三处承重证明。

为什么单列：`判据的可信性.md` §三.5「判据的解析器坏了」是假绿来源之一 —— 引用扫描
是判据 ㊴ 的眼睛，它自身也要有反向样本（该抓的抓得住）与正向样本（**最容易假红的那一条**：
存在的节不许报红）。三处**承重证明**（退回一步）分别钉住三条放宽：紧邻门 · 任一候选 · 自引用。

★ 样本里的件名都是**仓里不存在的假名**（目标件/他件/…）⇒ 真仓扫描时「候选件为空」而跳过，
不会给判据面造假红（先例：`注入_行号引用` 把行号写成 `{12}`）。
"""
from __future__ import annotations

from .引用扫描 import 扫引用


def _悬空键(扫结果) -> set:
    悬空表, _判过 = 扫结果
    return {(本件, 件名, 节号) for 本件, _行号, 件名, 节号, _原文 in 悬空表}


def 自检_引用扫描() -> list:
    """引用扫描的正/反/自引用样本与三处承重证明。

    六问：① 正向（存在的节）不报红；② 反向（不存在的节）抓得住；③ 自引用（所在件自身有该节）
    不报红；④ 承重证明：关掉「所在件自身也算」⇒ 自引用样本必被误报；
    ⑤ 承重证明：关掉「任一候选」⇒ 同一行两个件名时必被误报；
    ⑥ 承重证明：关掉「紧邻门」⇒ 跨行上下文人名必被误报。
    """
    输出缓冲 = []

    # ── 主样本：正向 / 反向 / 自引用三类同在 ──
    件表 = {
        "项目文档/目标件.md": "## 一 目标节\n",
        "项目文档/他件.md": "## 三 他节\n",
        "项目文档/引用件.md": (
            "## 一 自节\n"
            "正向：见 `他件.md` §三。\n"
            "反向：见 `他件.md` §九。\n"
            "自引用：见 `他件.md` §一。\n"
        ),
    }
    扫结果 = 扫引用(件表)
    悬空 = _悬空键(扫结果)
    说明 = "悬空键=%s · 判过=%d" % (sorted(悬空), 扫结果[1])

    输出缓冲.append((
        "正向样本：引用一个**存在**的节（`他件.md` §三）⇒ 不报红",
        ("项目文档/引用件.md", "他件.md", 3) not in 悬空,
        说明,
    ))
    输出缓冲.append((
        "反向样本：引用一个**不存在**的节（`他件.md` §九）⇒ 抓得住",
        ("项目文档/引用件.md", "他件.md", 9) in 悬空,
        说明,
    ))
    输出缓冲.append((
        "自引用样本：所在件自身有该节（`引用件.md` 有 §一）⇒ 不报红",
        ("项目文档/引用件.md", "他件.md", 1) not in 悬空,
        说明 + "（三处实测假阳性全是自引用，这条必须钉住）",
    ))

    # ── 承重证明④：关掉「所在件自身也算」⇒ 自引用样本必被误报 ──
    扫关自身 = 扫引用(件表, 自身算=False)
    输出缓冲.append((
        "承重证明（退回一步）：关掉「所在件自身也算」⇒ 自引用样本必被误报",
        ("项目文档/引用件.md", "他件.md", 1) in _悬空键(扫关自身),
        "关掉后悬空键=%s（要求含自引用那处）—— 证明这一步真在承重" % sorted(_悬空键(扫关自身)),
    ))

    # ── 承重证明⑤：关掉「任一候选」⇒ 同一行两个件名时必被误报 ──
    # 一行里两个件名，§ 属**前一个**（目标件有 §一），最近的却是后一个（他件无 §一）。
    件表归属 = {
        "项目文档/目标件.md": "## 一 目标节\n",
        "项目文档/他件.md": "## 三 他节\n",
        "项目文档/归属件.md": "见 `目标件.md` 与 `他件.md` §一。\n",
    }
    扫任一 = 扫引用(件表归属)
    扫最近 = 扫引用(件表归属, 任一候选=False)
    输出缓冲.append((
        "正向样本：同一行两个件名，§ 属前一个（目标件有 §一）⇒ 不报红",
        not _悬空键(扫任一),
        "悬空键=%s" % sorted(_悬空键(扫任一)),
    ))
    输出缓冲.append((
        "承重证明（退回一步）：只按「最近前导件名」归属 ⇒ 上面那行必被误报",
        bool(_悬空键(扫最近)),
        "只看最近时悬空键=%s（要求非空）—— 证明「任一候选」这一步真在承重" % sorted(_悬空键(扫最近)),
    ))

    # ── 承重证明⑥：关掉「紧邻门」⇒ 跨行上下文人名必被误报 ──
    件表跨行 = {
        "项目文档/目标件.md": "## 一 目标节\n",
        "项目文档/跨行件.md": "见 `目标件.md` 的说明（§九 那条）。\n",
    }
    扫紧邻 = 扫引用(件表跨行)
    扫不紧邻 = 扫引用(件表跨行, 要求紧邻=False)
    输出缓冲.append((
        "正向样本：`<名>.md` 与 § 之间夹了散文（跨行上下文人名）⇒ 不当引用（不报红）",
        not _悬空键(扫紧邻),
        "悬空键=%s · 判过=%d" % (sorted(_悬空键(扫紧邻)), 扫紧邻[1]),
    ))
    输出缓冲.append((
        "承重证明（退回一步）：关掉紧邻门 ⇒ 跨行上下文人名必被误报",
        bool(_悬空键(扫不紧邻)),
        "关掉后悬空键=%s（要求非空）—— 证明「紧邻门」这一步真在承重" % sorted(_悬空键(扫不紧邻)),
    ))

    # ── 件名三级匹配：引用常省日期前缀（`说明件.md` 指 `2026-09-27_说明件.md`）──
    件表省前缀 = {
        "项目文档/决策记录/2026-09-27_说明件.md": "## 五 说明节\n",
        "项目文档/省前缀件.md": "见 `说明件.md` §五。\n",
    }
    扫省前缀 = 扫引用(件表省前缀)
    输出缓冲.append((
        "正向样本：引用省了日期前缀（`说明件.md` 指 `2026-09-27_说明件.md`）⇒ 仍可解析",
        not _悬空键(扫省前缀) and 扫省前缀[1] == 1,
        "悬空键=%s · 判过=%d（要求空 · 1）" % (sorted(_悬空键(扫省前缀)), 扫省前缀[1]),
    ))
    return 输出缓冲
