"""判据 68：条款写口占用保护 —— 往 `条款` 表 `insert or replace` 的件必须先过占用检查。

**为何要有这一条**（实测，不是推测）：`条款` 表是**已删 md 的唯一存本**（`表定义.分片源件表`：
`文档路径` 是源件路径，源件不在 ⇒ 保住库里的行）。写口 `开发工具/信息核心/记条款.py::记条款`
收尾是直写 `insert or replace`（表 `条款`），主键 `(文档路径, 序号)` —— 它只读 `权威档`，从不检查该序号
是否已被占用。实测后果：往 `测试验证/案例/形状.md` §10 写新节，把库里原有整节正文静默替换
（正文 1824 字 → 681 字）；库行数不变、闸 1 / 闸 2 / 案例全绿 —— 因为判据 ㊴ 只核「节号在不在」，
10 一直在，三处 §10.x 引用于是落到新节编号下。原正文已由一次恢复提交还原，但机制当时未修。

修法是两件套：① 写口默认拒覆盖（同键非空正文必须显式 `--覆盖`）；② 本条判据守**它不许回潮**。
数据面由写口 fail-closed 保证（覆盖只能由显式 `--覆盖` 发生）；本条只判**写口结构在位**。

**判什么**：生产区 `.py` 里凡往 `条款` 表**直写 `insert or replace`** 的件，必须同时满足三件（缺一即红）：
  · 调用占用检查节点（`= 检查占用(`），且调用出现在那句 `insert or replace` **之前**；
  · 读显式开关（`"覆盖" in 字段表` 这一形）；
  · 用法串里有 `--覆盖`（开关不可达 = 没人知道要加它）。

**不算写口的两类**：测试夹具（文件名以 `夹具` / `注入` / `自测` 开头）是造夹具数据，不是生产写口 ——
它们在 `条款` 里塞样本行，天然不持有占用保护；扫进来就是假红。

**诚实登记的假阴性面**：扫描面是**生产区文本且保串**（开关名住在字符串里，抹了串就抓不住）
⇒ 注释里把这三个字面量写出来也能看起来满足。它守的是结构，不证明运行期行为 ——
运行期由 `记条款` 的三条真跑读数（占用拒写 / 只增新序号 / 显式覆盖）交付。

三元读数：通过 = 面非空且 0 命中；失败 = 逐件报出缺哪一件；未判 = 面里 0 件 `.py`（空集不算通过）。
"""
from __future__ import annotations

from .验证小工具 import 判不了, 违规
from .常量 import 检查名, 代码后缀
from .测试件 import 并行取生产区文本


# 四个字面量一律**拆开拼**：本件自身也在扫描面内，整字连写会被自身当成写口命中。
写口语句 = "insert or replace into " + "条" + "款"
占用节点 = "检查" + "占用("
开关形 = "\"覆盖\"" + " in 字段表"
用法形 = "--" + "覆盖"
# 拒写形：开关必须真的控住拒写分支（光读开关、不靠它拦，等于开关没用）。
拒写形 = "and not " + "允许覆盖"
# 调用形：`= 检查占用(` —— 占用检查的返回值要被用上才叫真调，光写定义不算。
调用形 = "= " + 占用节点
# 测试夹具前缀：它们是造夹具数据的，不是生产写口（口径见件头）。
夹具前缀 = ("夹具", "注入", "自测")


def 扫写口(写口面: dict) -> list:
    """扫一遍 ⇒ `[(路径, 缺失表)]`；缺失表为空 = 该写口合规（不列入输出）。"""
    输出缓冲 = []
    for 路径 in sorted(写口面):
        源文本 = 写口面[路径] or ""
        if 写口语句 not in 源文本:
            continue
        if 路径.rsplit("/", 1)[-1].startswith(夹具前缀):
            continue
        缺失表 = []
        写口位 = 源文本.index(写口语句)
        调用位 = 源文本.find(调用形)
        if 调用位 < 0:
            缺失表.append("没有调用占用检查（`= 检查占用(` 一处都找不到）")
        elif 调用位 > 写口位:
            缺失表.append("占用检查排在 `insert or replace` 之后 ⇒ 拦不住覆盖")
        if 开关形 not in 源文本:
            缺失表.append("没有读显式开关（`\"覆盖\" in 字段表`）")
        elif 拒写形 not in 源文本:
            缺失表.append("读了开关却没拿它拦（`and not 允许覆盖` 这一形缺）⇒ 缺保护照样覆盖")
        if 用法形 not in 源文本:
            缺失表.append("用法串里没有 `--覆盖`（开关存在但没人知道要加）")
        if 缺失表:
            输出缓冲.append((路径, 缺失表))
    return 输出缓冲


# 面在一次运行里不变（判定与对象数各取一次）⇒ 按仓根缓存（同判据 61 / ㊳ 的先例）。
_写口面缓存: dict = {}


def 条款写口面(上层读数: dict) -> dict:
    """扫描面：全仓 `.py` 的**生产区文本**（**保串** —— 要抓的开关名与用法串都在串里）。"""
    键名 = str(上层读数["仓根"])
    if 键名 in _写口面缓存:
        return _写口面缓存[键名]
    件表 = [
        (键_件, 文件项["文本"])
        for 键_件, 文件项 in 上层读数["文件"].items()
        if 文件项.get("文本") is not None and 键_件.endswith(代码后缀)
    ]
    扫描面 = 并行取生产区文本(件表, 上层读数.get("测试文件集") or frozenset(), 保串=True)
    _写口面缓存[键名] = 扫描面
    return 扫描面


def 样本_条款写口(上层读数: dict) -> int:
    """对象数：面里的 `.py` 件数（0 ⇒ 未判）。"""
    return sum(1 for 键名 in 条款写口面(上层读数) if 键名.endswith(".py"))


def 检查68_条款写口占用(上层读数: dict) -> list:
    """全仓 `.py` 里每个条款写口都带占用保护。"""
    if 样本_条款写口(上层读数) == 0:
        判不了(检查名[61], "（全仓）",
              "扫描面 0 件 `.py` ⇒ 空集不算通过（空集不是「没问题」，是「这条判据这次没量到东西」）",
              "确认传进来的仓根是不是真的仓根（`上层读数[\"仓根\"]` 指到空目录时就会这样）")
        return []
    return [
        违规(检查名[61], 路径,
             "条款写口缺占用保护：" + "；".join(缺失表),
             "修法：写口照 `记条款.py::记条款` 的形状补三件 —— ① 调 `检查占用`（同键读标题与正文）"
             "且该序号已有非空正文时默认 `return 1` 拒写；② 读显式开关（`\"覆盖\" in 字段表`）；"
             "③ 用法串写 `--覆盖`。`条款` 是已删 md 的唯一存本，一次静默覆盖即不可逆，"
             "而库行数不变、其它判据全绿 ⇒ 只有本条能把它报出来")
        for 路径, 缺失表 in 扫写口(条款写口面(上层读数))
    ]
