# -*- coding: utf-8 -*-
"""自检_续缺口 —— 合主干 ① 门禁复跑 / 暂存非冲突件 / 恢复现场重跑的常驻身份证（挂 `--自测`）。

为什么单挂一件：`自检_现场清理.py` 的闭包已 3.5 秒（含真 `--恢复现场` 五步），再并这三条会把它拉长；
单开一件各守各的。

★ **闭包超时走正式口 `自测闭包.跑自测闭包`**（不设超时）—— 同 `自检_集成接管.py` / `自检_保全主目录.py`。
本件原先硬写 `timeout=5`，那是把**判据面的五秒硬顶误用到环境步**上：`--自测` 是环境步、不判顶，
而本闭包单独跑实测 **3.0–3.4 s**，离 5 s 只差 1.6 s 余量 ⇒ load 一高（实测 ≥8）就被判「起不来 / 超时」
——**负载假红**，调用方只能重跑整条 `--自测`（用户最想消灭的正是重跑）。
（同源实测：v1-100676 并发批里必红；v1-100678 独立复现 `TimeoutExpired(..., 5)`，单独跑 7/7 通过、3.0/3.4 s。）
★ 换成「不设超时」≠「永不红」：闭包**真挂住**时仍会红（真退出码非 0 即不过）—— 只是不再拿 5 秒去卡它。
"""

from pathlib import Path

from .自测闭包 import 跑自测闭包


def 自检_续缺口闭环() -> list:
    """⇒ `[(名称, 是否好, 说明)]`；起不来 / 非 0 退出即不过。"""
    仓根 = Path(__file__).resolve().parents[3]
    工具目录 = 仓根 / "开发工具"
    脚本 = ("import sys\n"
          "from MCP服务.合主干续缺口样本 import 续缺口样本\n"
          "样本表 = 续缺口样本()\n"
          "for 说明, 通过 in 样本表:\n"
          "    print(('OK ' if 通过 else 'XX '), 说明)\n"
          "sys.exit(0 if 样本表 and all(通过 for _, 通过 in 样本表) else 1)\n")
    退出码, 输出文本 = 跑自测闭包(脚本, 工具目录)
    通过 = 退出码 == 0
    说明 = "退出码 %d · 闭环样本：\n%s" % (退出码, 输出文本[-1600:])
    if not 通过:
        说明 += "\n标准错误：\n" + 输出文本[-800:]
    return [("合主干续缺口（① 门禁负载红复跑 · 真判据红仍拒 · 暂存非冲突件 · 恢复现场可重跑）",
             通过, 说明)]
