# -*- coding: utf-8 -*-
"""自检_条款占用 —— 判据 68 的机制身份证：五种假满足必须判红，真写口与夹具不许误伤。

**为什么单有它**：判据 68 旧版是「整文本四字面量」判法 ⇒ 把保护体删光、只在注释里凑齐字面量
即可绿（实测确证：内存夹具返回 0 条违规）。改成 AST 判「真正执行的 SQL 调用 + 占用检查结果被接住
+ 开关赋值形 + 写前拒写分支」之后，**判据自身也必须有一张身份证**证明这些反例真会红 ——
只立判据不证它，等于把假绿从写口搬到判据。

**八条断言**：五条假满足必红（注释伪满足 / 仅定义不调用 / 开关读而不拒 / 保护在写后 / 断言被删），
三条不误伤（记条款.py 真写口 / `夹具` 前缀测试夹具 / 只读 SELECT 的非写口）。

挂 `一键验证.py --自测` 的「判据器自身机制」一节（纯内存 + 只读一个真件，无外部钟）。
"""
from __future__ import annotations

from ..检查规则.规范文本.判据_条款占用 import 扫写口
from ..基础定义.常量 import 仓根

# 样例源一律**像素拼**出来：本件也在生产区扫描面内（`自检` 前缀已排除，这里再加一层不写整字连写）。
写口句子 = '    连接.execute("insert or replace into ' + '条' + '款 values(?,?,?,?,?)", (文档路径, 序号, 标题, 正文, ""))\n'
用法句子 = '    """用法：… [--' + '覆盖]"""\n'
# 真保护段：读开关 → 接住占用结果 → 写前「占用非空 ∧ 开关未给 ⇒ 非零 return」。
核心段 = (
    '    允许覆盖 = "覆盖" in 字段表\n'
    '    当前标题, 当前正文 = 检查占用(连接, 文档路径, 序号)\n'
    '    if (当前正文 or "").strip() and not 允许覆盖:\n'
    '        return 1\n'
)


def _造源(前段: str, 后段: str = "") -> str:
    """拼一份「真条款写口」样例源：`前段` 在写口之前，`后段` 在写口之后。"""
    return ('def 写(连接, 文档路径, 序号, 标题, 正文, 字段表):\n'
            + 用法句子 + 前段 + 写口句子 + 后段)


# 五条假满足：判据 68 每一条都必须判红（少了任一即假阴性面回潮）。
红样例表 = (
    ("注释伪满足（保护只写在注释里、代码零保护）",
     _造源('    # 检查占用(连接, …) / "覆盖" in 字段表 / and not 允许覆盖\n')),
    ("仅定义不调用（`def 检查占用` 在，但没人调它）",
     _造源('    def 检查占用(连接, 文档路径, 序号):\n        return ("", "")\n')),
    ("开关读而不拒（读了覆盖开关、写前没有拒写分支）",
     _造源('    允许覆盖 = "覆盖" in 字段表\n'
          '    当前标题, 当前正文 = 检查占用(连接, 文档路径, 序号)\n')),
    ("保护在写后（占用检查与拒写分支都排在 insert or replace 之后）",
     _造源("", 核心段)),
    ("断言被删（取反开关的分支里只剩 pass，没有非零 return）",
     _造源('    允许覆盖 = "覆盖" in 字段表\n'
          '    当前标题, 当前正文 = 检查占用(连接, 文档路径, 序号)\n'
          '    if 当前正文 and not 允许覆盖:\n'
          '        pass\n')),
)


def 自检_条款占用扫描() -> list:
    """判据 68 的机制身份证 ⇒ `[(名称, 是否好, 说明)]`。"""
    断言表 = []
    for 名称, 样例源 in 红样例表:
        命中 = 扫写口({"构建装配/样例/条款写口样本.py": 样例源})
        断言表.append((f"判据 68 假满足必红：{名称}", bool(命中),
                       "扫写口 返回 0 条 ⇒ 这种假满足会被放行（判据退化成记号）"))
    真件 = 仓根 / "开发工具/信息核心/记条款.py"
    try:
        真源 = 真件.read_text(encoding="utf-8")
    except OSError as 错误:
        断言表.append(("判据 68 真写口不误伤", False, f"读不到真写口 {真件} —— {错误}"))
    else:
        断言表.append(("判据 68 真写口不误伤（记条款.py 原文）",
                       not 扫写口({"开发工具/信息核心/记条款.py": 真源}),
                       "真写口被判红 ⇒ 判据误伤生产件（反向样本会失去可信度）"))
    断言表.append(("判据 68 测试夹具不误伤（`夹具` 前缀件塞样本行）",
                   not 扫写口({"构建装配/样例/夹具样本.py": _造源("")}),
                   "夹具件不是生产写口，被扫进来就是假红"))
    断言表.append(("判据 68 非写口不误伤（只读 SELECT 的件）",
                   not 扫写口({"构建装配/样例/只读样本.py":
                              'def 读(连接):\n    连接.execute("select 1 from ' + '条' + '款")\n'}),
                   "没有 insert or replace 的件不该被当成写口"))
    return 断言表
