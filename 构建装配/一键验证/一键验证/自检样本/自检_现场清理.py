from pathlib import Path

from ..共享夹具.自测闭包 import 跑自测闭包


def 自检_现场清理闭环() -> list:
    """⇒ `[(名称, 是否好, 说明)]`；起不来 / 非 0 退出即不过。"""
    仓根 = Path(__file__).resolve().parents[4]
    工具目录 = 仓根 / "开发工具"
    脚本 = ("import sys\n"
          "from MCP服务.验证样本.集成管理.现场清理样本 import 现场清理样本\n"
          "样本表 = 现场清理样本()\n"
          "for 说明, 通过 in 样本表:\n"
          "    print(('OK ' if 通过 else 'XX '), 说明)\n"
          "sys.exit(0 if 样本表 and all(通过 for _, 通过 in 样本表) else 1)\n")
    退出码, 输出文本 = 跑自测闭包(脚本, 工具目录)
    通过 = 退出码 == 0
    说明 = "退出码 %d · 闭环样本：\n%s" % (退出码, 输出文本[-1600:])
    if not 通过:
        说明 += "\n标准错误：\n" + 输出文本[-800:]
    return [("现场清理 正反样本（① DB-only UU 恢复收敛 · ② 旧主干基清理 · ③ 代码冲突仍拒 · ④ 无现场仍拒）",
             通过, 说明)]
