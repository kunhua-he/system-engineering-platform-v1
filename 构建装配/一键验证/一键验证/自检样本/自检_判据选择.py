# -*- coding: utf-8 -*-
"""判据选择器的身份证 —— 短 mock 面，证「拒得不静默 · 不自动选 · 局部 0 不放行」。

为何住本件：选择器（`判据选择.py`）本身也是假绿来源（选中 0 条被当成通过就是它要堵的病），
故它自身要有反向样本。面用**短 mock 可运行面**（两条判据）—— 与真目录的漂移解耦，
跑得也快（不起全闸、不 spawn）。
"""
from __future__ import annotations

from ..判据编排 import 判据选择
from ..判据编排.判据表 import 检查表


# 短 mock 可运行面：两条判据 ⇒ 只用来证选择器**本身**的行为。
_短样本面 = (("19", "⑲ 行数硬数：单源文件 ≤400"), ("37", "㊲ 超时设置上限五秒"))


def _在样本面上跑(词表) -> tuple:
    """把 `取可运行判据` 临时换成短样本面跑一次 ⇒ `(判据名集, 问题或 None)`。"""
    原取函数 = 判据选择.取可运行判据
    判据选择.取可运行判据 = lambda: _短样本面
    try:
        return 判据选择.解析选择(词表)
    finally:
        判据选择.取可运行判据 = 原取函数


def 自检_判据选择() -> list:
    """选择器七问：编号/圈号/子串命中 · 未知带候选 · 空/非法类型/重复/混给一律拒 · 局部 0 不放行。"""
    输出缓冲 = []
    行数判据名, 超时判据名 = _短样本面[0][1], _短样本面[1][1]

    # ① 编号命中（阿拉伯数字与圈号同解）。
    数字集, 数字错 = _在样本面上跑(["19"])
    圈号集, 圈号错 = _在样本面上跑(["⑲"])
    输出缓冲.append((
        "命中·编号：`19` 与 `⑲` 都选中「行数硬数」那一条",
        数字错 is None and 圈号错 is None and 数字集 == {行数判据名} and 圈号集 == {行数判据名},
        f"`19`→{len(数字集)} 条 · `⑲`→{len(圈号集)} 条（要求各 1 条）",
    ))
    # ② 子串命中（不猜别名，只认逐字子串）。
    子串集, 子串错 = _在样本面上跑(["超时设置"])
    输出缓冲.append((
        "命中·子串：`超时设置` 选中含该段的那一条",
        子串错 is None and 子串集 == {超时判据名},
        f"`超时设置`→{sorted(子串集)}（要求 {超时判据名[:8]}…）",
    ))
    # ③ 未知词：明确拒，且给 ≤上限条候选（候选不是自动选中）。
    未知集, 未知错 = _在样本面上跑(["文件行数"])
    输出缓冲.append((
        "未命中：明确拒 · 附近似候选（候选只供人挑，绝不自动选中）",
        未知错 is not None and 未知集 == set() and "近似候选" in 未知错,
        f"问题={('有' if 未知错 else '无')} · 选中={len(未知集)} 条（要求空集 + 有候选行）",
    ))
    # ④ 空表 · 空词 · 非法类型 · 重复：四种一律拒。
    空表集, 空表错 = _在样本面上跑([])
    空词集, 空词错 = _在样本面上跑(["  "])
    类型集, 类型错 = _在样本面上跑([5])
    重复集, 重复错 = _在样本面上跑(["19", "19"])
    输出缓冲.append((
        "拒·空表/空词/非法类型/重复：四种都明确拒（不静默跳过、不退回全量）",
        all(问题 is not None for 问题 in (空表错, 空词错, 类型错, 重复错))
        and 空表集 == set() and 空词集 == set() and 类型集 == set() and 重复集 == set(),
        "空表/空词/类型/重复 四种‘有问题’="
        f"{[bool(问题) for 问题 in (空表错, 空词错, 类型错, 重复错)]}",
    ))
    # ⑤ 混给已知 + 未知：整批拒，**不返回部分命中**（不许静默跳过未知）。
    混给集, 混给错 = _在样本面上跑(["19", "根本没这条"])
    输出缓冲.append((
        "混给已知+未知：整批拒、不返回部分命中（不许静默跳过未知）",
        混给错 is not None and 混给集 == set(),
        f"问题={('有' if 混给错 else '无')} · 选中={len(混给集)} 条（要求空集 —— 不许只返回 `19`）",
    ))
    # ⑥ 入参不是词表（整串当词表）：明确拒。
    串集, 串错 = _在样本面上跑("19")
    输出缓冲.append((
        "拒·入参不是词表：整串直接拒",
        串错 is not None and 串集 == set(),
        f"问题={('有' if 串错 else '无')}",
    ))
    # ⑦ 守可运行（读的是**真**可运行面 `判据表.检查表`，不是上面那个 mock 面）⇒
    #    面内真名无说明 · 未知名 / 空集 都有说明（局部 0 不算放行）。故这里拿真名，不拿 mock 名。
    输出缓冲.append((
        "守可运行：未知名与空集都要报问题（局部 0 不算放行）",
        not 判据选择.守可运行({检查表[0][0]})
        and bool(判据选择.守可运行({检查表[0][0], "㉒ 命名防回潮：已删的旧名"}))
        and bool(判据选择.守可运行(set())),
        "面内真名无说明 · 未知名/空集 都有说明",
    ))
    return 输出缓冲
