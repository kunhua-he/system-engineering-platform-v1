def 自检_整份夹具跳过() -> list:
    """整份夹具（由父文件 `#[cfg(test)] … mod …;` 挂进来的独立文件）必须整份跳过。

    反向样本：把一份**看起来是生产代码**的文件（重定义 常量表 里的常量 + 第二个导出符号）
    用 `#[cfg(test)] #[path = "子/夹具.rs"] mod 夹具;` 挂进来 ⇒ 必须整份跳过（不报红）。
    对照：**去掉**那条挂载声明 ⇒ 同一份文件必须被当成生产代码抓到（证明「跳过」不是空转）。
    形状取自真仓实测：`#[path]` 指向**子目录**、mod 名与文件名**不同**、挂载声明写在
    **兄弟文件**（不是 lib.rs/mod.rs/main.rs）里。
    """
    输出缓冲 = []
    # 样本里的 Rust 形状**拆开拼**：本文件虽在 `构建装配/`（⑪/⑫ 的扫描面把它排除了），
    # 但「排除工具目录」只是判据面的一条口径，随时可能变；在源码里写一整条
    # 「导出属性 + 引号里的符号名」等于给判据面埋一处假红（实测撞到过同类：
    # `测试验证/契约一致性/扫实现.py` 里的样本被读成一个真导出，连注释里的也算）。
    造属性 = lambda 内层: "#" + "[" + 内层 + "]"  # noqa: E731
    # ★ 2026-10-01 修：样本里的标识符必须**已在夹具名册里**（`目标字宽` 是；`第二道门` /
    #   `usize` / `夹具` 原先不是）—— 判据 ㊷ 的面**含整份夹具**（真仓的名册也由含测试件的
    #   全量代码派生，见 `夹具规则库.py::名册表`）⇒ 样本一引入没登记的名，挂了的那一轮就
    #   不再是 0 失败，本对照断言当场红。改用已登记的名（`取扩展声明` / `u32`）证同一件事。
    夹具文 = (
        "// 整份夹具：自身文件里没有 cfg 测试标记\n"
        "pub const 目标字宽: u32 = 64;\n"
        + 造属性('unsafe(export_name = "SecondDoor")') + "\n"
        + 'pub extern "C" fn 取扩展声明() -> u32 { 0 }\n'
    )
    键父 = "运行内核/实例状态/src/lib.rs"
    键夹具 = "运行内核/实例状态/src/子目录/夹具.rs"
    节点件 = {
        "运行内核/实例状态/Cargo.toml": '[package]\nname = "v1-state"\nversion = "0.1.0"\n',
        键父: 造属性("cfg(test)") + "\n" + 造属性('path = "子目录/夹具.rs"') + "\nmod 取扩展声明;\n",
        键夹具: 夹具文,
    }
    测试文件集 = 建测试文件集({键名: {"文本": 源文本} for 键名, 源文本 in 节点件.items()})
    输出缓冲.append(
        (
            "反向样本：被 `#[cfg(test)] #[path]` 挂进来的整份夹具 ⇒ 跳过",
            键夹具 in 测试文件集,
            f"整份夹具集={sorted(测试文件集)}",
        )
    )
    # 对照：挂 vs 不挂 —— 只差父文件里那一行挂载声明
    import tempfile

    def 跑自检(是否挂: bool) -> dict:
        with tempfile.TemporaryDirectory(prefix="一键验证夹具对照-") as 临时目录:
            临根 = Path(临时目录) / "仓"
            造干净仓(临根)
            for 相对, 件内容 in 节点件.items():
                if not 是否挂 and 相对 == 键父:
                    continue
                路径 = 临根 / 相对
                路径.parent.mkdir(parents=True, exist_ok=True)
                路径.write_text(件内容, encoding="utf-8")
            return 跑全量判据(临根)

    挂了, 没挂 = 跑自检(True), 跑自检(False)
    # ★ 计数**排除 ⑱ 命令墙钟**：它量的是**本命令（`--自测`）这个进程**的墙钟（模块导入 → 此刻），
    #   不是这一份夹具的判定 —— `--自测` 跑到这里已越 5 秒硬顶 ⇒ ⑱ 恒红，与「夹具跳没跳过」无关。
    #   本对照要证的是「**夹具被判据抓到**」，故只数**按夹具内容判定**的判据（⑱ 不是）。
    失败数 = lambda 判定汇总: len([  # noqa: E731
        明细条 for 明细条 in 判定汇总["失败"]
        if isinstance(明细条, str) and 明细条 != 检查名[17]])
    输出缓冲.append(
        (
            "对照：不挂载 ⇒ 同一份文件被抓到（证明「跳过」不是空转）",
            失败数(挂了) == 0 and 失败数(没挂) > 0,
            f"挂了：失败 {失败数(挂了)} 项 · 没挂：失败 {失败数(没挂)} 项 "
            f"{[明细条 for 明细条 in 没挂['失败'] if isinstance(明细条, str)]}",
        )
    )
    return 输出缓冲


def 自检_拓扑判据收窄() -> list:
    """⑪-3 / ⑪-4 两条判据**收窄后的形状**的身份证（2026-09-25 收窄）。

    为什么单列：这两条原先都靠「词」判（⑪-3 数 `载入(` 的任意出现 · ⑪-4 数 6 个中文词），
    词法判据必然把**枚举解构 / 文档串 / 调用点 / 同义词**算进去 ⇒ 假阳性
    （依据：决策记录/2026-09-26_验证面的边界.md §7.2）。
    收窄最怕**收过头**：把真调用点一起毙掉，读数从「2 处假红」变成「0 处假红」——同样错。
    故每条都成对钉：**不该命中的形状必须 0 处** + **该命中的形状必须 1 处**。
    （判据的可信性.md §三.5：判据的解析器也是假绿来源，所以它自身也要有身份证。）
    """
    输出缓冲 = []

    def 断言(名称, 合格样本, 说明):
        输出缓冲.append((名称, 合格样本, 说明))

    # ── ⑪-3：`载入` 的调用点 ──
    真调用 = "let 表 = v1_loader::载入声明(声明, &台账).map_err(装载失败::载入失败)?;\n"
    解构_臂 = "match 结果 {\n    装载失败::载入声明(内) => 报(内),\n    _ => 好,\n}\n"
    解构_iflet = "if let 装载失败::载入声明(内) = 结果 { 报(内); }\n"
    定义 = "pub fn 载入声明(声明: &'static 平台信息) -> Result<注册表, 载入错误> { 好 }\n"
    变体声明 = "    载入声明(载入错误),\n"
    断言(
        "正向样本：真调用点 `v1_loader::载入声明(声明, &台账)`（带路径前缀）必须被数到",
        len(载入调用点(真调用)) == 1,
        f"数到 {len(载入调用点(真调用))} 处（要求 1）——带 `::` 前缀的真调用点不许被收窄毙掉",
    )
    断言(
        "反向样本：枚举解构（match 臂模式位 `装载失败::载入声明(内) =>`）不该被数成调用点",
        len(载入调用点(解构_臂)) == 0,
        f"数到 {len(载入调用点(解构_臂))} 处（要求 0）——这就是两条腿各自绕开的那处假阳性",
    )
    断言(
        "反向样本：`if let` 解构（`装载失败::载入声明(内) = …`）不该被数成调用点",
        len(载入调用点(解构_iflet)) == 0,
        f"数到 {len(载入调用点(解构_iflet))} 处（要求 0）——模式位不止 match 臂一种",
    )
    断言(
        "反向样本：定义形 `fn 载入声明(` 与枚举变体声明 `载入声明(载入错误),` 都不算调用点",
        len(载入调用点(定义)) == 0 and len(载入调用点(变体声明)) == 0,
        f"定义 {len(载入调用点(定义))} 处 · 变体声明 {len(载入调用点(变体声明))} 处（都要求 0）",
    )
    混装文 = 真调用 + 解构_臂 + 解构_iflet
    断言(
        "对照：真调用 + 两处解构混在一起 ⇒ 仍恰好 1 处（解构不许把读数抬起来）",
        len(载入调用点(混装文)) == 1,
        f"混装文里数到 {len(载入调用点(混装文))} 处（要求 1）——收窄前这里会数成 3 处",
    )

    # ── ⑪-4：资源唯一出入口（冻结访问形状）──
    真定义 = "pub fn 资源调用(&self, 资源号: u32, 操作号: u32, 输入槽表: &[数据槽]) -> 关口结果 {\n"
    改名定义 = "pub fn 另一条腿(资源号: u32, 操作号: u32, 输入槽表: &[数据槽]) -> 关口结果 {\n"
    文档串 = "//! 调：(资源号, 操作号, 输入槽表) → 输出槽表 | 结构化错误（`资源调用`）\n"
    调用点 = "let 结果 = 关口.资源调用(资源号, 操作号, 输入槽表);\n"
    私有助手 = "fn 派发(&self, 声明: Option<&资源声明>, 资源号: u32, 操作号: u32, 输入槽表: &[数据槽]) -> 关口结果 {\n"
    校形状 = "pub(super) fn 校输入形状(资源号: u32, 操作号: u32, 输入类型: u32, 输入槽表: &[数据槽]) -> Result<数据槽, 资源错误> {\n"
    断言(
        "正向样本：真出入口定义（§四 冻结访问形状）必须被数到",
        len(资源出入口形.findall(真定义)) == 1,
        f"数到 {len(资源出入口形.findall(真定义))} 处（要求 1）",
    )
    断言(
        "反向样本：文档串里的同名词（`//! 调：(资源号, 操作号, 输入槽表)`）不该被数成出入口",
        len(资源出入口形.findall(文档串)) == 0,
        f"数到 {len(资源出入口形.findall(文档串))} 处（要求 0）——原来这袋同义词连文档串都算",
    )
    断言(
        "反向样本：调用点 `关口.资源调用(资源号, 操作号, 输入槽表)` 不该被数成出入口",
        len(资源出入口形.findall(调用点)) == 0,
        f"数到 {len(资源出入口形.findall(调用点))} 处（要求 0）——出入口数**定义**，不数调用",
    )
    断言(
        "反向样本：私有助手（参数多一个 / 中间插了别的参数）不算第二个出入口",
        len(资源出入口形.findall(私有助手)) == 0 and len(资源出入口形.findall(校形状)) == 0,
        f"派发 {len(资源出入口形.findall(私有助手))} 处 · 校输入形状 {len(资源出入口形.findall(校形状))} 处（都要求 0）",
    )
    断言(
        "正向样本：**改名**的同一形状仍被抓（判据不认函数名）",
        len(资源出入口形.findall(改名定义)) == 1,
        f"数到 {len(资源出入口形.findall(改名定义))} 处（要求 1）——#34 的抱怨「换个命名就红」的反面",
    )
    混合文本 = 真定义 + 文档串 + 调用点 + 私有助手 + 校形状
    断言(
        "对照：真定义 + 文档串 + 调用点 + 私有助手混在一起 ⇒ 仍恰好 1 处",
        len(资源出入口形.findall(混合文本)) == 1,
        f"混装文里数到 {len(资源出入口形.findall(混合文本))} 处（要求 1）——收窄前这里会数成 3 处",
    )

    # ── ⑪-1 / ⑫-3 / ⑫-4：三条 ①类判据的**收窄身份证**（#33）──
    # 这三条编译期断言不了（构造口在实现侧 / 是否定存在性），故按 #33 口径迁到
    # 「写清为什么 + 留一条能跑的读数」那一档。读数就是下面这几份：**类型提及 / 普通判断 /
    # 非模块级写法这些「收窄前会数错的形状」必须数不到；该数的那一处必须数得到**。
    # （反向样本仍归 `自测用例`：`注入_第二处对外监听` / `注入_边界里出现业务判断` / `注入_边界里出现状态`。）
    断言(
        "⑪-1 收窄：监听**调用点**数得到（`TcpListener::bind` / `.listen(` / `.serve(`）",
        len(监听模式.findall('let 监听 = TcpListener::bind("127.0.0.1:0");\n')) == 1
        and len(监听模式.findall("服务.listen(端口);\n")) == 1
        and len(监听模式.findall("服务.serve(处理);\n")) == 1,
        "三种真实开监听的调用形各数一处（要求都 1）",
    )
    断言(
        "⑪-1 收窄：**类型提及**不算监听点（导入 / 字段声明 / 结构体字段）",
        len(监听模式.findall("use std::net::{TcpListener, TcpStream};\n")) == 0
        and len(监听模式.findall("    监听: TcpListener,\n")) == 0
        and len(监听模式.findall("pub struct 网关 { 监听: TcpListener }\n")) == 0,
        "这三个形状原来会把读数从 1 抬到 6（实测）—— 收窄后必须都 0",
    )
    断言(
        "⑫-3 收窄：边界里的业务判断（`if 能力号 ==` / `match 编号 {`）数得到",
        len(边界业务判断模式.findall("if 能力号 == 1 { 1 } else { 0 }\n")) == 1
        and len(边界业务判断模式.findall("match 编号 { _ => 0 }\n")) == 1,
        "两种按号分派的形状各数一处（要求都 1）",
    )
    断言(
        "⑫-3 收窄：**不是按号特例**的判断不算业务判断（普通 if 与普通 match）",
        len(边界业务判断模式.findall("if 表.is_empty() { 返回() }\n")) == 0
        and len(边界业务判断模式.findall("if 结果状态 == 成功 { 好() }\n")) == 0
        and len(边界业务判断模式.findall("match 参数类型 { _ => 0 }\n")) == 0,
        "按「号」字族特判才是业务判断——别类判断在边界里合法（协议翻译必需）",
    )
    断言(
        "⑫-4 收窄：**模块级** `static`（行首，可带 pub / mut）数得到",
        len(边界状态模式.findall("static 缓存: u32 = 0;\n")) == 1
        and len(边界状态模式.findall("pub static 表: [u32; 2] = [0, 0];\n")) == 1
        and len(边界状态模式.findall("static mut 计: u32 = 0;\n")) == 1,
        "三种模块级 static 各数一处（要求都 1）",
    )
    断言(
        "⑫-4 收窄：**不是模块级 static** 的写法不算状态（局部 `let` / `const`）",
        len(边界状态模式.findall("    let 缓存 = 0;\n")) == 0
        and len(边界状态模式.findall("const 上限: u32 = 5;\n")) == 0,
        "`const` 是编译期常量不是状态；局部变量不在模块级（模式本来就要求行首）",
    )
    return 输出缓冲
