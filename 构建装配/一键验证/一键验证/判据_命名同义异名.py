# -*- coding: utf-8 -*-
"""判据 52：命名同义异名 —— 两名是同一件事的两种拼法（候选未裁即红）。

依据：库 `规则` 表 命名口径-20。判法只此一份（`命名判法.同义候选`）。
**★ 与 R3 的「只报告」不同**：①②③④ 机械判 ⇒ 候选；**⑤ 同所指是人判，结论住库 `命名同义已裁`**
⇒ 判据只核「这个候选有没有被裁过」：未裁候选 ⇒ **红**（与 `命名口径-1` 同形）。
**三元读数**：通过 = 无未裁候选；失败 = 逐条报；未判 = 名册 / 索引读不动或 0 行。
"""
from __future__ import annotations

from .小工具 import 判不了, 违规
from .常量 import 检查名
from . import 常量
from . import 命名判法
from .判据基线 import 库相对路径


def 读索引定义面(上层读数: dict) -> list:
    """C 的面：代码地图索引的定义面（夹具仓走合成索引 —— 与 ㉒/㊷ 同一份读法）。"""
    import sys

    from .读文件 import 索引路径
    from .判据_命名穷举 import 命名件表

    根目录 = str(常量.仓根 / "开发工具")
    if 根目录 not in sys.path:
        sys.path.insert(0, 根目录)
    import 代码地图.索引库 as 索引库

    件表 = 命名件表(上层读数)
    return 索引库.全部定义(索引路径(上层读数["仓根"], 件表, 检查名[51]))


def 对象数_命名同义异名面(上层读数: dict) -> int:
    """对象数：库 `命名定义` 的行数（0 ⇒ 未判）。"""
    定义行表, _错误 = 命名判法.读命名定义(上层读数["仓根"])
    return len(定义行表)


def 检查52_命名同义异名(上层读数: dict) -> list:
    """命名同义异名：机械候选不在已裁清单里 ⇒ 红（⑤ 人判结论住库 `命名同义已裁`）。"""
    输出缓冲 = []
    定义行表, 错误 = 命名判法.读命名定义(上层读数["仓根"])
    if 错误:
        return [违规(检查名[51], 库相对路径, f"判不了：{错误}",
                    "名册是本条的面之一（候选从它来）⇒ 读不出就判不了。修法：把规则库补上"
                    "（`python3 开发工具/信息核心/信息核心.py 建库`）⇒ 只能由维护方补")]
    if not 定义行表:
        判不了(检查名[51], 库相对路径, "`命名定义` 0 行 —— 空名册（或库不在）",
              "判据的可信性.md 第二节：空集是**未判**，不是通过 ⇒ 只能由维护方确认规则库")
        return 输出缓冲
    节点表 = 读索引定义面(上层读数)
    if not 节点表:
        判不了(检查名[51], "代码地图索引（.codegraph/codegraph.db）",
              "索引定义面 0 个节点 —— 索引不在或陈旧（夹具仓该由 读文件.索引路径 挂合成索引）",
              "判据的可信性.md 第二节：空集是**未判**，不是通过。修法：先跑 "
              "`python3 开发工具/代码地图.py 建` ⇒ 只能由维护方补")
        return 输出缓冲
    实测表 = 命名判法.同义候选(定义行表, 节点表)
    已裁表, 错误 = 命名判法.读同义已裁(上层读数["仓根"])
    if 错误:
        return [违规(检查名[51], 库相对路径, 错误,
                    "已裁清单是本条的**豁免依据**（被裁过的候选才放行）⇒ 读不出就判不了。"
                    "修法：把规则库补上（库 `命名同义已裁` 表）⇒ 只能由维护方补")]
    口径 = ("库 `规则` 表 命名口径-20：同义异名五条全真才判合并；⑤ 同所指是人判 ⇒ 结论住库 "
          "`命名同义已裁`。判据只核「这个候选有没有被裁过」：未裁 ⇒ 红。修法：逐组核代码，"
          "裁「合并」或「误报」，记入 `命名同义已裁`（`信息核心.py 记同义`）")
    for 前名, 后名 in 实测表:
        if (前名, 后名) in 已裁表:
            continue
        输出缓冲.append(违规(检查名[51], f"命名定义::{前名} ↔ {后名}",
            f"新增同义候选（未裁）：`{前名}` / `{后名}` 不在已裁清单里 ⇒ **新增候选即红**", 口径))
    return 输出缓冲
