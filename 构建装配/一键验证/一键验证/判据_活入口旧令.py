def 读活入口清单(仓根) -> tuple:
    """⇒ `([(编号, 名, 依据)], 错误或 None)` —— 库不在 / 读不动交错误回去（fail-closed）。"""
    库件 = Path(仓根) / 库相对路径
    if not 库件.is_file():
        return [], f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute(
                "select 编号, 名, 依据 from %s where 类 = ?" % 清单表, (清单类,)))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return [], f"`{清单表}` 读不动：{错误}"
    return [(表行[0] or "", 表行[1] or "", 表行[2] or "") for 表行 in 行表], None


def 解析落点(落点依据: str):
    """清单 `依据` 是绝对路径就用它，否则按「相对运行数据根」解析；解析不出 ⇒ None。"""
    路径文本 = (落点依据 or "").strip()
    if not 路径文本:
        return None
    if 路径文本.startswith("/"):
        return Path(路径文本)
    try:
        数据根 = 解析当前环境()
    except Exception:  # noqa: BLE001 —— 口径给不出根 ⇒ 落点解析不出（调用方判红）
        return None
    片段 = 路径文本.split("/")
    if len(片段) > 1:
        return 子目录路径(数据根, 片段[0]) / Path(*片段[1:])
    return 子目录路径(数据根, "临时件") / 路径文本


def 展开件(落点: Path) -> list:
    """落点是目录 ⇒ 取其中所有 `.md`；是件 ⇒ 就它本身；不存在 ⇒ 空表。"""
    if 落点.is_dir():
        return sorted(待扫件 for 待扫件 in 落点.rglob("*.md") if 待扫件.is_file())
    return [落点] if 落点.is_file() else []


def 扫失效指令(正文文本: str, 件名: str) -> list:
    """逐行扫：带历史标记的行放过，其余命中失效形 ⇒ 一条违规。"""
    命中表 = []
    for 行号, 当前行 in enumerate(正文文本.splitlines(), start=1):
        if any(标记 in 当前行 for 标记 in 历史标记表):
            continue
        for 名字, 模式, 口径 in 失效指令表:
            if re.search(模式, 当前行):
                命中表.append(违规(
                    检查名称, f"{件名}:{行号}",
                    f"活入口里把已撤的旧指令「{名字}」当现行指令：{当前行.strip()[:80]}",
                    口径,
                ))
                break
    return 命中表


def 自检正反样本() -> list:
    """⇒ `[(样本名, 是否如期, 读数)]`；正样本必须逐条报红、反样本必须 0 命中。"""
    正命中 = len(扫失效指令(正样本文本, "正样本.md"))
    反命中 = len(扫失效指令(反样本文本, "反样本.md"))
    return [
        ("正样本：五条旧指令当现行 ⇒ 必须逐条报红", 正命中 == len(失效指令表), f"命中 {正命中} 条"),
        ("反样本：带历史标记的旧指令引用 ⇒ 必须 0 命中", 反命中 == 0, f"命中 {反命中} 条"),
    ]


def 样本_活入口面(上层读数: dict) -> int:
    """对象数：声明清单的条数（0 ⇒ 未判：没有活入口就没有对象）。"""
    行表, _错误 = 读活入口清单(上层读数.get("仓根") or ".")
    return len(行表)


def 检查68_活入口无失效指令(上层读数: dict) -> list:
    """声明的活入口件里不许把已撤的旧指令当现行指令（三元：通过 / 失败 / 未判）。"""
    输出缓冲 = []
    for 样本名, 如期, 读数 in 自检正反样本():
        if not 如期:
            输出缓冲.append(违规(
                检查名称, "判据自检",
                f"本检查自身失效：{样本名}（{读数}）",
                "判据的可信性.md 第六节：正反样本缺一即「未验证」，它的通过不计入通过数",
            ))
    仓根 = Path(上层读数.get("仓根") or ".")
    行表, 错误 = 读活入口清单(仓根)
    if 错误:
        判不了(检查名称, 库相对路径, 错误,
               "「活入口清单」住库 `规则` 表 `类`=`活入口` —— 读不动就判不了「活入口里有没有旧指令」")
        return 输出缓冲
    if not 行表:
        判不了(检查名称, 库相对路径,
               "活入口清单为空（库 `规则` 表 `类`=`活入口` 0 行）—— 空集上子判据恒真 ⇒ 假绿",
               "清单必须先落库（`python3 开发工具/信息核心/信息核心.py 记规则 --类 活入口 …`）")
        return 输出缓冲
    口径 = ("活入口是「当前执行指令」的注入源（`AGENTS.md` 读取顺序直接指到它）；"
          "旧指令留在里面，新会话照它开工。修法：把那一行改成正式源指针，历史留存只许写在带历史标记的行里")
    for 表行 in 行表:
        落点 = 解析落点(表行[2])
        if 落点 is None:
            输出缓冲.append(违规(检查名称, f"{清单表}:{表行[0]}",
                                f"活入口「{表行[1]}」的落点解析不出（`依据` = {表行[2]!r}）", 口径))
            continue
        件表 = 展开件(落点)
        if not 件表:
            输出缓冲.append(违规(检查名称, str(落点),
                                f"活入口「{表行[1]}」的落点不存在：{落点}", 口径))
            continue
        for 待扫件 in 件表:
            try:
                正文文本 = 待扫件.read_text(encoding="utf-8")
            except OSError as 错误:
                判不了(检查名称, str(待扫件), f"读不动：{错误}", "读不动就判不了这一件，不许当通过")
                continue
            输出缓冲.extend(扫失效指令(正文文本, str(待扫件)))
    return 输出缓冲
