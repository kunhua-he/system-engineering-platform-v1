# -*- coding: utf-8 -*-
"""判据 ⑩：生成物与 JSON 一致（指纹比对）。"""

from __future__ import annotations

from concurrent.futures import ThreadPoolExecutor
import re

from .小工具 import 违规, 判不了
from .常量 import 声明数据字段, 契约目录名, 平台信息所在目录, 并发度, 检查名, 生成器相对路径, 生成物头标要求, 生成物路由件相对路径, 是生成物, 装载入口落点
from .构造点 import _抽平台信息字段, _解Rust转义, 找构造点, 跑生成器检查
from .测试件 import 并行生产区


def 检查10_生成物与JSON一致(上层读数: dict) -> list:
    输出缓冲 = []
    仓根 = 上层读数["仓根"]
    平台 = 上层读数["平台"] or {}
    文件 = 上层读数["文件"]

    # ── (a) 生成物存在 + 头标四件事 ──
    生成物文本 = 文件.get(生成物路由件相对路径, {}).get("文本")
    生成器 = 仓根 / 生成器相对路径
    if 生成物文本 is None:
        输出缓冲.append(
            违规(
                检查名[9],
                生成物路由件相对路径,
                f"生成物不存在（格式说明 §八 指定的落点）；生成器 "
                f"{生成器相对路径} {'在' if 生成器.is_file() else '也不在'} ⇒ 指纹比对无从谈起",
                f"第 10 项的自愈路径是「重跑生成器」（验证流程图 ④：指纹过期 → 重算），"
                f"而落盘件不在就没有可比的对照物。验证面若自身把 JSON 写成 Rust 常量，"
                f"就是在仓库里起第二套生成实现（开发规范 五-1：同一件事两套形态即缺陷）⇒ "
                f"只能由生成链的负责方（{生成器相对路径}）重跑落盘",
            )
        )
    else:
        头部 = "\n".join(生成物文本.splitlines()[:40])
        缺头标 = [名称 for 名称, 谓词函数 in 生成物头标要求 if not 谓词函数(头部)]
        if 缺头标:
            输出缓冲.append(
                违规(
                    检查名[9],
                    f"{生成物路由件相对路径}:头标",
                    f"产物头缺 {(' · '.join(缺头标))}"
                    f"（§八 要求四件事：生成物声明 · 源文件清单 · 源文件指纹 · 生成器路径）",
                    f"头标是「这是生成物、禁手改」的唯一标记（README 第九节：生成物被手改即为违规）；"
                    f"缺头标后人就无从判断该改源还是改产物 ⇒ 只能由生成器补",
                )
            )

    # ── (b) 指纹闸：交给生成器自身的 --检查（§八 原话：重新生成并与落盘件逐字节比对）──
    if not 生成器.is_file():
        输出缓冲.append(
            违规(
                检查名[9],
                f"{生成器相对路径}",
                f"生成器不存在（§八 指定的落点），产物头里写的 --检查 模式无从执行",
                f"指纹闸按 §八 由生成器实现（产物头必须能指到它）；生成器不在，"
                f"「生成物与 JSON 是否一致」就没有第三方可判——验证面另写一套哈希"
                f"就是第二个判据（同一件事两套实现即缺陷）⇒ 只能由生成链的负责方落地",
            )
        )
    elif 生成物文本 is not None:
        退出码, 输出 = 跑生成器检查(仓根, 生成器)
        if 退出码 != 0:
            输出缓冲.append(
                违规(
                    检查名[9],
                    f"{生成物路由件相对路径}:源文件指纹",
                    f"生成器 --检查 报不一致（退出码 {退出码}）：{输出}",
                    f"不一致有两种可能：声明改过而生成物没重跑，或产物被手改。"
                    f"按 README 第九节产物是生成物、不是源 ⇒ 修法是重跑生成器；"
                    f"但重跑会覆盖落盘件，是否有意的手改须由人定 ⇒ 只能人来裁",
                )
            )

    # ── (c) 手写 `平台信息` 判据（收窄范围 + 加约束；依据：§八 + 冻结登记 待办旁路）──
    #      A 非测试区不许出现手写的 平台信息   B 声明数据字段必须来自生成物   C 测试夹具两条更严条件
    #      范围：**底座**（§八 的理由写的是 `static 底座存储`——装载入口自身就是消费方；
    #      扩展的声明在扩展自身的目录里、不在 契约声明/，没有生成物可引用 ⇒ 不在此判据内，见 --缺口）
    扫描件 = [
        (键名, 一项["文本"])
        for 键名, 一项 in 文件.items()
        if 键名.endswith(".rs")
        and 一项["文本"] is not None
        and not 是生成物(键名)
        and not 键名.startswith("扩展根目录/")
    ]
    with ThreadPoolExecutor(max_workers=并发度) as 线程池:
        构造点表 = list(线程池.map(lambda 一项: (一项[0], 找构造点(一项[1])), 扫描件))
    # 生产区文本（去掉 #[cfg(test)] 区 + 整文件即测试的模块）——判据 C 的②要拿它查夹具名
    生产区文本 = 并行生产区(扫描件, 上层读数["测试文件集"])

    for 键名, 点表 in 构造点表:
        整文件测试 = 键名 in 上层读数["测试文件集"]
        for 构造点 in 点表:
            在测试区 = 构造点["测试区"] or 整文件测试
            位置 = f"{键名}:{构造点['行号']}:平台信息 构造点"
            # 「手写」= 声明数据字段的值不是 `声明数据::…`。
            # 为什么要这样读：生成物自身的收口说明要求**保留** `static 底座存储` 这个构造点、
            # 只把字段换成 `v1_contract::声明数据::..`（契约声明/src/声明数据.rs 引用方怎么接）。
            # 若把「手写」读成「构造点存在即违规」，收口做完这条也永远红 ⇒ 判据自身写错。
            手写字段 = [
                名称
                for 名称, 待处理值 in 构造点["字段"].items()
                if 名称 in 声明数据字段 and "声明数据::" not in 待处理值
            ]
            if not 在测试区:
                if 手写字段:
                    # 判据 A：非测试区出现了手写的 平台信息
                    输出缓冲.append(
                        违规(
                            检查名[9],
                            位置,
                            f"非 `#[cfg(test)]` 代码里出现了**手写**的平台信息构造点"
                            f"（`{构造点['头行']}`）——§八 判据：底座的声明只有一个来源",
                            f"底座声明的唯一来源是 契约声明/*.json（经生成物）。这个构造点没有任何"
                            f"一个声明数据字段引用生成物，等于声明在代码里另有一份 ⇒ "
                            f"两处改一处就漂移。修法是照生成物的收口说明把字段换成 "
                            f"`v1_contract::声明数据::..`（构造点本身要保留，它是引用生成物的壳）；"
                            f"哪些字段该换、手写的那份要不要删，按收口说明走 ⇒ 只能由收口方按步骤改",
                        )
                    )
                    # 判据 B：逐字段明细（同一点拆开报，谁违了哪一条一目了然）
                    明细 = " · ".join(f"{名称}={构造点['字段'][名称]}" for 名称 in 手写字段)
                    输出缓冲.append(
                        违规(
                            检查名[9],
                            位置,
                            f"这些声明数据字段没来自生成物：{明细}",
                            f"§八 判据：声明只有 JSON 一个来源。这些字段的值是字面量 · 本地常量 · "
                            f"契约常量（各与 平台声明.json 有一份），改一处不改另一处就漂移；"
                            f"换成 `声明数据::…` 是机械动作，但「手写的那份删不删 · 版本口径以谁为准」"
                            f"是契约侧裁决 ⇒ 只能由收口方按生成物的收口说明改",
                        )
                    )
            else:
                # 判据 C：测试夹具两条更严条件
                项名 = 构造点["具名项"]
                if not 项名:
                    输出缓冲.append(
                        违规(
                            检查名[9],
                            位置,
                            f"`#[cfg(test)]` 里有一处构造 平台信息，但它不属于任何具名项"
                            f"（`{构造点['头行']}`）——匿名夹具",
                            f"夹具的两条更严条件（冻结登记 待办旁路）里，②「不许被生产代码引用」"
                            f"靠夹具的名字来判；匿名夹具没有名字，②判不了 ⇒ 不许默默放过 ⇒ "
                            f"只能由声明方给它起个名字（或改成具名项）",
                        )
                    )
                    continue
                引用处 = []
                for 它键, 生产文本 in 生产区文本.items():
                    for 匹配结果 in re.finditer(r"(?<![\w])" + re.escape(项名) + r"(?![\w])", 生产文本):
                        行号 = 生产文本[: 匹配结果.start()].count("\n") + 1
                        引用处.append(f"{它键}:{行号}")
                if 引用处:
                    输出缓冲.append(
                        违规(
                            检查名[9],
                            位置,
                            f"测试夹具「{项名}」被生产代码引用：{' · '.join(引用处[:5])}",
                            f"夹具在 `#[cfg(test)]` 内是本分（条件①满足），但条件②要求它"
                            f"**不许被生产代码引用**——被引用就等于生产代码依赖了一份测试里合成的声明，"
                            f"而测试代码不进制且可随时改 ⇒ 生产行为会跟着测试漂移。"
                            f"把引用改成走真声明、还是把夹具搬进测试调用链，是结构裁决 ⇒ 只能人来裁",
                        )
                    )

    # ── (d) 底座身份 / 版本八项：源码侧的唯一源必须是生成物（手写则逐项比 JSON）──
    # 2026-10-01 修（判据假绿审计 N1）：落点原写死成一个**文件**（`运行内核/装载入口/src/lib.rs`），
    # 而八项常量已搬进同 crate 的子件（`底座静态声明.rs` · `判定.rs`）⇒ 抽取全 None、逐项
    # `continue`、**一条也不判**（闸还是绿的）。现按「落点是符号不是文件」（判据 ㉖）改成扫
    # **目录** `装载入口落点` 下全部 `.rs`，逐项按符号取：
    #   ① 接线形 —— 字段/常量的值是 `v1_contract::声明数据::<生成物常量>` ⇒ 唯一源就是生成物，
    #      值与 JSON 的一致性归 (b) 的生成器 `--检查`（**这里不再比一遍** —— 那是第二套生成物比对）。
    #   ② 手写形 —— 源码值本身是字面量 ⇒ 就地抽出来与 平台声明.json 逐项比。
    # 两形都取不到 ⇒ **判不了**（fail-closed）—— 绝不许静默通过。
    装载文本 = "\n".join(
        文件.get(件文本, {}).get("文本") or ""
        for 件文本 in sorted(文件)
        if 件文本.startswith(装载入口落点 + "/") and 件文本.endswith(".rs")
    )
    字段表 = {}
    for 件文本 in sorted(文件):
        if not (件文本.startswith(装载入口落点 + "/") and 件文本.endswith(".rs")):
            continue
        for 构造点 in 找构造点(文件[件文本]["文本"] or ""):
            字段表.update(构造点["字段"])

    for 名目, 声明键, 字段名, 常量名, 段名表 in (
        ("标识串", "标识串", "标识串", "底座标识串", None),
        ("名称", "名称", "名称", "底座名称", None),
        ("声明格式号", "声明格式号", "声明格式号", "底座声明格式号", None),
        ("实现版本", "实现版本", "实现版本", "底座实现版本", ("主", "次", "构建")),
        ("要求宿主版本", "要求宿主版本", "要求宿主版本", "底座要求宿主版本", ("主", "次")),
        ("要求内核版本", "要求内核版本", "要求内核版本", "底座要求内核版本", ("主", "次")),
        ("提供宿主版本", "提供宿主版本", "底座宿主版本", "底座提供宿主版本", ("主", "次", "构建")),
        ("提供内核版本", "提供内核版本", "底座内核版本", "底座提供内核版本", ("主", "次", "构建")),
    ):
        # 源码侧取值：`平台信息` 的字段优先（前六项）；`提供宿主版本` / `提供内核版本` 不在
        # `平台信息` 里，住在 `判定.rs` 的同名 `const`（值同样来自 `声明数据::`）。
        待处理值 = 字段表.get(字段名)
        if 待处理值 is None:
            命中 = re.search(r"const\s+" + re.escape(字段名) + r"\s*:[^=]+=\s*([^;]+);", 装载文本)
            待处理值 = 命中.group(1).strip() if 命中 else None
        if 待处理值 is None:
            判不了(
                检查名[9],
                f"{装载入口落点}:{字段名}",
                f"在 `{装载入口落点}` 下（含子目录）取不到 `{名目}` 的源码落点 —— 既没有 "
                f"`平台信息` 的 `{字段名}` 字段，也没有 `const {字段名}` ⇒ "
                f"「{名目} 与 {契约目录名}/平台声明.json 一致」这一条判不了",
                f"落点是**符号**不是文件：常量搬进同 crate 的子件（或改名）就取不到。"
                f"**判不了不许算通过**（早先写死一个文件、取空就静默跳过，那是假绿）⇒ "
                f"只能由契约设计方确认这八项的源码落点",
            )
            continue
        if ("声明数据::" + 常量名) in 待处理值:
            # 接线形：唯一源是生成物 `声明数据`（生成器 `--检查` 保证它与 JSON 逐字节一致）。
            continue
        # 手写形：源码值本身是字面量 ⇒ 就地抽出来与 平台声明.json 逐项比（原判据的活）。
        if 段名表 is None and 名目 != "声明格式号":
            命中 = re.search(r'b?"((?:[^"\\]|\\.)*)"', 待处理值)
            声明值 = _解Rust转义(命中.group(1)) if 命中 else None
            声明文 = str(平台.get(声明键)) if 平台.get(声明键) is not None else None
        elif 名目 == "声明格式号":
            命中 = re.search(r"[0-9_]+", 待处理值)
            声明值 = int(命中.group(0).replace("_", "")) if 命中 else None
            声明文 = str(平台.get(声明键)) if 平台.get(声明键) is not None else None
        else:
            命中 = re.search(r"新建\s*\(([^)]*)\)", 待处理值)
            声明值 = re.sub(r"\s+", "", 命中.group(1)).replace(",", ".") if 命中 else None
            声明文 = (
                ".".join(str(平台.get(声明键, {}).get(段名)) for 段名 in 段名表)
                if isinstance(平台.get(声明键), dict) else None
            )
        if 声明值 is None or 声明文 is None:
            判不了(
                检查名[9],
                f"{装载入口落点}:{字段名}",
                f"`{名目}` 的源码值 `{待处理值}` 既不是生成物接线（`声明数据::{常量名}`），"
                f"也不是本判据认得的字面量写法（字节串 · 整数 · `v1_contract::版本*::新建(…)`）"
                f"⇒ 判不了",
                f"手写字面量的写法只有这三种，换了写法就抽不出来。**判不了不许算通过** ⇒ "
                f"只能由契约设计方确认这八项的写法",
            )
            continue
        if str(声明值) != str(声明文):
            输出缓冲.append(
                违规(
                    检查名[9],
                    f"{装载入口落点}:{字段名} ↔ {契约目录名}/平台声明.json:{声明键}",
                    f"手写常量是 {声明值!r}，声明里是 {声明文!r}，两者不一致",
                    f"§八 判据：声明只有 JSON 一个来源；{名目} 在源码里另抄一份就与声明漂移。"
                    f"修法是照生成物的收口说明把字段换成 `v1_contract::声明数据::{常量名}` ⇒ "
                    f"只能由收口方按步骤改",
                )
            )

    # ── (d) 键名逐字对应：平台声明 的三个键名 == 平台信息 的旁路字段名 ──
    # 落点是**符号**不是文件：扫 `平台信息所在目录` 下全部 `.rs`（含子目录）。
    # 写死一个文件名，下次把 `平台信息` 挪进子件就**静默丢覆盖面**（闸还绿）——实测 2026-09-27，见 #230。
    字段集 = set()
    平台信息落点 = ""
    for 路径, 节点件 in sorted(文件.items()):
        if not 路径.startswith(平台信息所在目录 + "/") or not 路径.endswith(".rs"):
            continue
        本件字段 = _抽平台信息字段(节点件.get("文本") or "")
        if 本件字段:
            字段集 |= 本件字段
            平台信息落点 = 路径
    if not 字段集:
        判不了(
            检查名[9],
            f"{平台信息所在目录}/**/*.rs",
            f"在 {平台信息所在目录} 下（含子目录）找不到 `pub struct 平台信息 {{ … }}` ⇒ "
            f"「三个键名逐字对应」这一条判不了",
            f"这条检查的对象是 `平台信息` 的字段名；结构体被搬走或改名就取不到。"
            f"**判不了不许算通过**（早先写死一个文件、取空就静默跳过，那是假绿）⇒ "
            f"只能由契约设计方确认 `平台信息` 落在哪",
        )
    else:
        for 键名 in ("能力号段", "通知号段", "错误段位表"):
            if 键名 in 平台 and 键名 not in 字段集:
                输出缓冲.append(
                    违规(
                        检查名[9],
                        f"{契约目录名}/平台声明.json:{键名} ↔ {平台信息落点}:平台信息",
                        f"声明里有键 {键名}，而 {平台信息落点} 的 平台信息 里没有同名字段"
                        f"（现有：{sorted(字段集)}）",
                        f"§二：三个键名与 平台信息 的三个旁路字段逐字对应，"
                        f"生成器不做改名——改名就是又造一个「同一事实两个名字」的漂移点；"
                        f"以哪边为准只有契约设计方能定 ⇒ 只能人来裁",
                    )
                )
    return 输出缓冲
