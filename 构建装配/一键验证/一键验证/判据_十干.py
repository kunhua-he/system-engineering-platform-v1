# -*- coding: utf-8 -*-
"""判据 ㊵：零字面十干 —— 逐字节全树（含未跟踪件）里 0 处十干字。

依据：`项目文档/未完成事项.md` 的那条（散文面：注释 · 字符串 · 样本）·
`项目文档/决策记录/2026-09-27_命名规范.md` §二（序数代称一律停用 —— 本判据把「停用」从
**标识符面**扩到**全文本面**）。

**为什么要这一条**：判据 ㉒ 的四档全在**标识符**上 ⇒ 写在**注释 / 字符串 / 样本 / 数据**
里的十干一个都拦不住。实测：曾有 6 处字面十干是在一次「逐字节全树 = 0」的审计**之后**才
引入的，**无一处报红**；那一行「散文面」是**手工命令**，不是判据。把口径变成常驻判据 ⇒
一处字面十干出现就红，不必等下一次批次清存量。

**判什么**：文件按 UTF-8 解出的文本里，不许出现这 10 个码位。**检测表只此一份**：
`开发工具/代码地图/查名.py::序数代称码位`（按 Unicode 码位写、全仓零字面）—— 本件 import 它，
不抄第二份（判据 ㉒ 的 `判据_命名._查名` 就是现成例子）。

**扫描面**：逐字节**全树**（**含未跟踪件**），排除 `/只读参考/`（只读、且不许被任何一层读取）·
`/构建环境/`（编译缓存里有非 UTF-8 的巧合字节序列，不是内容）· `/.git/` · `/.codegraph/`。
★ **判据本体逐字节读树**（`git grep` 只作旁证 —— 它看不见未跟踪件）。

**白名单机制**（照 `查名.词内序数代称`）：**词内十干不算** —— 词的一部分（有词典义），
字在词内不表序。**空表 + 加词门槛**（机制留着，表实测为空）。见 `词内十干码位`。

**形状照抄判据 ㉒**（`判据_命名.检查22_命名防回潮`）：基线文件 + 三条 —— ① 新增（基线里没有）
⇒ 红 ② 超基线（实际 > 登记）⇒ 红 ③ **基线不许留陈旧登记**（登记着却已不出现，或实测低于
登记）⇒ 红。**基线只许减**。基线件 `十干基线.json`；读不到它就 fail-closed 报红。

三元读数：**通过** = 扫描面非空且无新增/超基线/陈旧；**失败** = 逐条报出；
**未判** = 扫描面 0 件（那说明走树坏了或仓是空的，不是「没问题」）。
"""
from __future__ import annotations

import json
import os
from pathlib import Path

from .小工具 import 判不了, 违规
from .常量 import 检查名
# 检测表**只此一份**（`查名.py::序数代称码位`）—— 取法照 判据_命名 引 `命名面.取查名`。
from .命名面 import 取查名 as _查名


# 基线文件：**存量清单**（谁欠的债谁登记）。判据读不到它就 fail-closed 报红 ——
# 「存量入基线」要求先有存量清单，没有它，实测的全部存量会被当成「新增」⇒ 当场红一片。
十干基线路径 = "构建装配/一键验证/十干基线.json"

# 排除的顶层目录名（口径书点名的四个）。按**路径段**判 —— 比按 `/片段/` 判更稳：
# 链接工作树里 `.git` 是个**文件**（不是目录），按 `/片段/` 判会漏掉它。
排除目录 = ("只读参考", "构建环境", ".git", ".codegraph")

# ── 白名单：词内十干（**空表 + 加词门槛**）────────────────────────────────────────────
# 口径照 `查名.词内序数代称`：判的是「拿十干字**当序数**」，不是「文本里出现过某个字」——
# 词的一部分（有词典义）不算。**加词门槛**（三条，缺一不可）：
#   ① 那个词必须有**词典义**；② 十干字在词内**不表序**；③ 给出**全仓实测读数**。
# ★ **表实测为空**（2026-09-28 全树清到 0）。加词**按码位写**（不许写字面）——
#   本件自身也在扫描面内，写字面会自红。
词内十干码位 = ()
词内十干 = tuple("".join(chr(码位) for 码位 in 码位串) for 码位串 in 词内十干码位)


def 十干字() -> str:
    """十干字的**检测表**（从 `查名.py::序数代称字` 取，不抄第二份）。"""
    return _查名().序数代称字


def 去词内十干(文本: str) -> str:
    """把白名单词换成**等长空格**（列位置不变）—— 词内的十干字不算。空表 ⇒ 原样返回。"""
    if not 词内十干:
        return 文本
    净文本 = 文本
    for 白名单词 in 词内十干:
        净文本 = 净文本.replace(白名单词, " " * len(白名单词))
    return 净文本


def 路径被排除(相对路径: str) -> bool:
    """路径里有**排除目录**的任一段 ⇒ 不进扫描面。"""
    return any(路径段 in 排除目录 for 路径段 in Path(相对路径).parts)


# 扫描面 / 扫一遍的结果都在一次运行里不变（判定与对象数各取一次）⇒ 按仓根缓存
# （同 判据 ㊴ 的先例）。不跨调用复用：`--自测` 的注入发生在两次 `验证` 之间。
十干面缓存: dict = {}
_扫缓存: dict = {}


def 十干面(上层读数: dict) -> dict:
    """扫描面：逐字节**全树**（含未跟踪件）⇒ `{相对路径: 文本}`。

    **判据本体走树读字节**（不借 `上["文件"]`：它只收 `扫描后缀`，看不见 `.md` 之外的
    样本 / 数据件；也不借 `git grep`：它看不见未跟踪件）。非 UTF-8 件不是「文本」⇒ 跳过。
    """
    仓根 = Path(上层读数["仓根"])
    键名 = str(仓根)
    if 键名 in 十干面缓存:
        return 十干面缓存[键名]
    件表 = {}
    for 根目录, 目录表, 文件表 in os.walk(仓根):
        目录表[:] = [
            目录名 for 目录名 in 目录表
            if not 路径被排除(str(Path(根目录, 目录名).relative_to(仓根)))
        ]
        for 文件名 in 文件表:
            件路径 = Path(根目录) / 文件名
            相对 = str(件路径.relative_to(仓根))
            if 路径被排除(相对):
                continue
            try:
                件表[相对] = 件路径.read_bytes().decode("utf-8")
            except (OSError, UnicodeDecodeError):
                continue  # 读不动 / 不是 UTF-8 ⇒ 不是「文本」（不是内容）
    十干面缓存[键名] = 件表
    return 件表


def 扫十干(件表: dict) -> list:
    """扫一遍件表 ⇒ `[(路径, 行号, 码位)]`（白名单词先去掉）。

    白名单先剥（词内的字不算）⇒ 逐字找（行号才准）。**10 个 `in` 先筛件**（C 级、快），
    只有真含字的那几件才逐行定位 —— 全树 0 命中时这一趟只花几毫秒。
    """
    字表 = 十干字()
    结果 = []
    for 路径 in sorted(件表):
        净文本 = 去词内十干(件表[路径] or "")
        if not 净文本:
            continue
        for 字符 in 字表:
            if 字符 in 净文本:
                for 行号, 行文本 in enumerate(净文本.split("\n"), 1):
                    if 字符 in 行文本:
                        结果.append((路径, 行号, ord(字符)))
    return 结果


def 扫十干面(上层读数: dict) -> list:
    """扫一遍扫描面（按仓根缓存）。"""
    键名 = str(上层读数["仓根"])
    if 键名 not in _扫缓存:
        _扫缓存[键名] = 扫十干(十干面(上层读数))
    return _扫缓存[键名]


def 数命中(扫结果: list) -> dict:
    """`[(路径, 行号, 码位)]` ⇒ `{(路径, 码位): 处数}`（基线读写与判定共用一份口径）。"""
    命中 = {}
    for 路径, _行号, 码位 in 扫结果:
        键名 = (路径, 码位)
        命中[键名] = 命中.get(键名, 0) + 1
    return 命中


def 样本_十干面(上层读数: dict) -> int:
    """对象数：扫描面下的件数（0 ⇒ 未判：走树坏了也是 0 件，两者必须分得开）。"""
    return len(十干面(上层读数))


def 码位文案(码位: int) -> str:
    """码位的**文案**（`U+7532` 形）—— 报违规时用，不写字面。"""
    return "U+%04X" % 码位


def _读基线(基线件) -> tuple:
    """读基线 ⇒ `({(路径, 码位): 处数}, 错误或 None)`。"""
    if not 基线件.is_file():
        return {}, f"基线文件不存在（{十干基线路径}）"
    try:
        数据 = json.loads(基线件.read_text(encoding="utf-8"))
    except Exception as 错误:
        return {}, f"基线文件解析不了（{type(错误).__name__}）"
    项表 = {}
    for 一条 in 数据.get("条目") or []:
        try:
            码位 = 一条["码位"]
            码位 = int(码位, 16) if isinstance(码位, str) else int(码位)
            项表[(str(一条["件"]), 码位)] = int(一条.get("处数", 0))
        except (KeyError, TypeError, ValueError):
            return {}, f"基线条目形状不对（{一条!r}）—— 要 件/码位/处数 三键"
    return 项表, None


def 检查40_零字面十干(上层读数: dict) -> list:
    """零字面十干：逐字节全树（含未跟踪件）里 0 处十干（存量入基线、新增即红 · 基线只许减）。

    三元读数：**通过** = 扫描面非空且无新增/超基线/陈旧；**失败** = 逐条报出；
    **未判** = 扫描面 0 件（走树坏了也是 0 件）。
    """
    输出缓冲 = []
    件表 = 十干面(上层读数)
    if not 件表:
        判不了(
            检查名[39],
            "全树（排除 只读参考/ · 构建环境/ · .git/ · .codegraph/）",
            "扫描面下 0 个件（判据没有可查的对象）—— 也可能是**走树坏了**：那样恒为 0 命中 ⇒ 假绿",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一个空仓天然是绿的，"
            "那不是本条判据的功劳 ⇒ 只能由判据作者确认走树与排除表",
        )
        return 输出缓冲

    基线表, 错误 = _读基线(上层读数["仓根"] / 十干基线路径)
    if 错误:
        return [
            违规(
                检查名[39],
                十干基线路径,
                错误,
                "「存量入基线、新增即红」要求先有存量清单（形状照判据 ㉒）；没有它，"
                "实测的全部存量会被算成「新增」⇒ 判据当场红一片，等于没上闸。"
                "基线只能由**声明方**登记（谁欠的债谁登记）⇒ 只能由维护方补",
            )
        ]

    实测 = 数命中(扫十干面(上层读数))
    口径 = (
        "`项目文档/决策记录/2026-09-27_命名规范.md` §二：十干字（序数代称）在本项目里没有"
        "语义 —— 判据 ㉒ 只判**标识符**，注释 / 字符串 / 样本 / 数据里的十干一个都拦不住"
        "（实测：6 处字面十干在「逐字节全树 = 0」的审计**之后**才引入，无一处报红）。"
        "修法：按它在这一处的**实际角色**命名，或**删掉那个字**（不许机械替换成「第一个」）"
        "⇒ 只能由该件的作者改"
    )
    for (路径, 码位), 实际 in sorted(实测.items()):
        登记 = 基线表.get((路径, 码位))
        if 登记 is None:
            输出缓冲.append(
                违规(
                    检查名[39],
                    f"{路径}::{码位文案(码位)}",
                    f"新增字面十干（{码位文案(码位)}，{实际} 处），基线里没有它 ⇒ **新增即红**",
                    口径,
                )
            )
        elif 实际 > 登记:
            输出缓冲.append(
                违规(
                    检查名[39],
                    f"{路径}::{码位文案(码位)}",
                    f"字面十干（{码位文案(码位)}）实测 {实际} 处 > 基线登记 {登记} 处 ⇒ **存量还在长**",
                    "基线是「存量不许再长」的闸，不是白名单（形状照判据 ㉒）。这一处已在基线里"
                    "登记过，却又多了 ⇒ 要么改回去，要么在提交信息里说明为什么必须涨并同步登记 ⇒ "
                    "只能由该件的作者处置",
                )
            )

    # ── 基线里不许留**陈旧登记**（与判据 ㉒/⑲/㊴ 同一条）──
    for (路径, 码位), 登记 in sorted(基线表.items()):
        实际 = 实测.get((路径, 码位), 0)
        if 实际 == 0:
            输出缓冲.append(
                违规(
                    检查名[39],
                    f"{路径}::{码位文案(码位)}",
                    f"基线登记着字面十干（{码位文案(码位)}，{登记} 处），而实测这一处"
                    f"**已经不出现** ⇒ **陈旧登记**",
                    "「基线只许减」：改掉了就该把登记删掉。留着它，基线读数就不再是现状"
                    f"（读的人会以为债还在）⇒ 只能由维护方删（{十干基线路径}）",
                )
            )
        elif 实际 < 登记:
            输出缓冲.append(
                违规(
                    检查名[39],
                    f"{路径}::{码位文案(码位)}",
                    f"基线登记字面十干（{码位文案(码位)}）{登记} 处，实测只有 {实际} 处 ⇒ "
                    f"**登记没跟着减**",
                    "「基线只许减」：实测比登记低就该同步减下来。不减的话，这一处可以一路长回"
                    f"登记值而不报红 —— 那是「只增不减」的一个洞 ⇒ 只能由维护方改（{十干基线路径}）",
                )
            )
    return 输出缓冲
