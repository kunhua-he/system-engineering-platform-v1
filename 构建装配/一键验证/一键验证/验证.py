def 用判据进程池(上: dict) -> bool:
    """这次判据分片用不用**进程池**（fork）。

    为什么按件数门槛分两种池：真仓 368 件 ⇒ 判据是 CPU 密集（正则/字符串），GIL 之下线程
    拿不到并行（实测线程池 2235 ms ≈ 串行 2260 ms）；fork 进程池 685 ms。但**合成小仓**只有
    ~15 件，判据本身几毫秒 ⇒ 付进程启动成本反而更慢，且自测要跑几十次 `验证` ⇒ 退回线程池。
    平台没有 `fork`（Windows）也退回线程池（不是假绿：判据照样全跑，只是不并行）。
    """
    if not 常量.提速开关:
        return False
    if len(上.get("文件") or {}) < 进程池最小件数:
        return False
    try:
        import multiprocessing

        return "fork" in multiprocessing.get_all_start_methods()
    except Exception:
        return False


# 本批的上下文：**由 `分片跑` 在起池前填**，`跑一项判据` 从这里取。
#
# ★ 为什么不把 `上` 放进任务里（2026-09-27 提速 · 实测）：`Pool.map` 会把**每个任务**
#   都 pickle 一遍送进管道 ⇒ `上`（本仓实测 **4.74 MB**）会被序列化 36 次。
#   实测：36 个任务各带 `上` 166 ms · 不带 57 ms（差 109 ms 纯是序列化）。
#   而 fork 出来的子进程**本来就继承**父进程的内存（COW）⇒ 父进程先填好这个全局，
#   子进程直接读，一个字节都不用传。线程池那条路也成立（同进程共享）。
_本批上: dict = {}


def 跑一项判据(任务: tuple) -> tuple:
    """跑一条判据 **并顺带取它的对象数**，返回 `(判据名, 违规表, 本分片未判表, 对象数)`。

    未判桶是 `threading.local`（见 `_本分片未判`）：进程池里每个子进程一份、线程池里每个
    线程一份 ⇒ 两条路都不丢「子判据空集」，也不再有共享列表的竞态。

    ★ **为什么对象数搭这条车**（2026-09-27 提速 · 实测裁的，别拆开）：
      几条判据的对象数就是「把全仓 746 件过一遍生产区」（㉕ 运行数据自拼 · ㊲ 超时设置），
      各 ~0.8 s。**判据本体用的正是同一份生产区读数** ⇒ 在同一个子进程里先跑判据、
      再取对象数，第二次是**纯缓存命中**（`_…面缓存` 按仓根缓存），几乎不要钱。
      早先把它单开一趟（无论串行、线程池、还是再起一个 fork 池）都等于**把同一份活重算一遍**：
        串行 2821 ms · 线程池 1→3140 / 2→2699 / 4→3082 / 8→7736 ms（抢 GIL）· 另起 fork 池 988 ms。
      搭车后这一趟**整个消失**，`验证` 从 2374 ms 降到 ~1400 ms。
    """
    上 = _本批上
    项, 对象数函数 = 任务
    名, 函数 = 项
    清未判()
    违规表 = 函数(上)
    未判 = 取未判()
    清未判()
    值 = 对象数函数(上) if callable(对象数函数) else None
    # 对象数**不该**产未判；真产了也不许静默丢 ⇒ 并进本分片的未判表。
    return 名, 违规表, 未判 + 取未判(), 值


def 分片跑(上: dict, 任务表: list, 工人) -> list:
    """**通用分片**：用 `工人` 把 `任务表` 跑完，返回结果表（顺序与 `任务表` 一致）。

    两条路：**fork 进程池**（CPU 密集时快 3.3×，见 `用判据进程池`）· 起不来就退回**线程池**。
    `工人` 必须是**模块级函数**（进程池按「模块名 + 函数名」反序列化它，闭包/lambda 不行）。

    起池前把 `上` 填进 `_本批上`：fork 的子进程继承（COW）⇒ **不必按任务 pickle 它**（见那里）。

    ★ 这里**试过**改用 `ProcessPoolExecutor`（它的工人**不是** daemon，于是判据能自己再 fork
      一批子进程把「全仓过一遍生产区」摊开）—— 单条重判据确实从 871 ms 降到 ~83 ms，
      但**整条命令的墙钟没有变**（实测 1.79/1.80/1.82 → 1.83/1.77/1.78 s）。
      为什么：判据批本来就已把 32 核跑满（37 条合计 ~9.6 s CPU），
      摊开只是把「一条 871 ms」换成「六条各 ~750 ms」——**墙钟由总 CPU 决定，不由并发度决定**。
      并发度不是这里的杠杆 ⇒ 退回 `multiprocessing.Pool`（更简单，且自测依赖的
      「子进程继承父进程模块全局」这条语义在 `Pool` 上更直白）。
      要真降墙钟得**减少总 CPU**（好几条判据各自把全仓过一遍 `剥字面量`，该共享一份）——
      那是扫描层的事，另案。**别再加并发度**：实测已证无效。
    """
    global _本批上
    if not 任务表:
        return []
    _本批上 = 上
    if 用判据进程池(上):
        import multiprocessing

        上下文 = multiprocessing.get_context("fork")
        进程数 = max(1, min(len(任务表), 判据进程池上限))
        try:
            with 上下文.Pool(processes=进程数) as 池:
                return list(池.map(工人, 任务表))
        except Exception:
            # 进程池起不来（例：本件不是以 `__main__` / 已注册模块名被装载 ⇒ 分片函数没法按名字
            # 反序列化；或 fork 被平台禁掉）⇒ 退回线程池：判据照样**全跑**、判定口径不变，
            # 只是不并行。这不是静默降级：真退回时命令会变慢，而**检查18 量的就是真墙钟**
            # ⇒ 慢过 5000 ms 会被 ⑱ 当场抓住（⑱ 自己就是这条退路的守卫）。
            pass
    with ThreadPoolExecutor(max_workers=并发度) as 池:
        return list(池.map(工人, 任务表))


def 跑判据集(上: dict, 项表: list) -> list:
    """把 `项表` 分片跑完，返回 [(判据名, 违规表, 未判表, 对象数)]。**没有任何一处串行 for 跑全量。**"""
    对象数表 = (上.get("判据元数据覆盖") or 判据元数据)
    return 分片跑(
        上,
        [(项, 对象数表.get(项[0], {}).get("对象数")) for 项 in 项表],
        跑一项判据,
    )


def 跑一遍(仓根: Path, 元数据覆盖=None, 只跑=None, 跑延迟=True, 上=None) -> dict:
    """跑一遍判据（默认全量；`只跑` 给一个判据名集合时只跑那个子集）。

    判据 ⑱（命令墙钟）**不进并行批**：它的读数要「整条命令跑到此刻」的墙钟，
    批内跑会读到「跑到一半」的已耗时（偏小）⇒ 它在批后单独判，读数才准。
    `跑延迟=False` 给 `验证` 用：`验证` 要等**两遍都跑完**才判 ⑱（读数才覆盖整条命令），
    所以第一遍先别判（否则 ⑱ 一次 `验证` 会跑两次、且第一次的读数是偏小的）。

    **对象数搭判据批的车回来**（见 `跑一项判据`）：不另开一趟。

    `上` 给一个已经建好的上下文（`验证` 用）：**一次 `验证` 只读一次仓**。
    为什么要它（2026-09-27 提速 · 实测）：`验证` 会跑两遍（第一遍全量 + 第二遍只复核报出东西的），
    而两遍读的是**同一个仓、同一刻的盘面** ⇒ 第二遍再 `建上下文` 纯属白读（实测 271 ms，
    且 `--自测` 每条样本都要付两次）。**只在这一个 `验证` 调用内复用**：跨调用不许复用 ——
    `--自测` 的反向样本会在两次调用之间往仓里注入违规，复用了就读到旧盘面（假绿）。
    """
    上 = 建上下文(仓根) if 上 is None else 上
    if 元数据覆盖 is not None:
        上["判据元数据覆盖"] = 元数据覆盖
    上["样本清单"] = 样本清单
    上["已执行判据"] = [名 for 名, _ in 判据表.检查表]
    延迟名 = 检查名[17]
    项表 = [
        (名, 函数)
        for 名, 函数 in 判据表.检查表
        if (只跑 is None or 名 in 只跑) and 名 != 延迟名
    ]
    分片 = 跑判据集(上, 项表)
    结果表 = {名: 违规 for 名, 违规, _未, _数 in 分片}
    子未判 = [条 for _名, _违规, 未, _数 in 分片 for 条 in 未]
    对象数表 = {名: 数 for 名, _违规, _未, 数 in 分片 if 数 is not None}

    # 延迟判据：在所有其它判据跑完之后，用「进程启动 → 此刻」的墙钟单独判一次。
    # 它**不在批里** ⇒ 对象数没搭上车，在这里单独取一次（`_样本_本命令` 恒为 1，不要钱）。
    if 跑延迟 and (只跑 is None or 延迟名 in 只跑):
        延迟函数 = dict(判据表.检查表).get(延迟名)
        if 延迟函数 is not None:
            上["本命令墙钟毫秒"] = int((time.perf_counter() - 进程起始时刻) * 1000)
            清未判()
            结果表[延迟名] = 延迟函数(上)
            子未判 += 取未判()
            取对象 = (上.get("判据元数据覆盖") or 判据元数据).get(延迟名, {}).get("对象数")
            if callable(取对象):
                对象数表[延迟名] = 取对象(上)
    return {
        "上": 上,
        "结果": 结果表,
        "子未判": 子未判,
        "对象数表": 对象数表,
    }


def 分类红(条: dict) -> str:
    """红的分类（判据的可信性.md 第四节来源 #1 + 半成品）：
    源码错 / 缺件或半成品。判法按「缺什么」里说的是不是「东西还没落地」。
    """
    文 = str(条.get("缺什么", "")) + str(条.get("不能自愈", ""))
    for 词 in ("不存在", "未落地", "还没接上", "一个都没", "一处都没有", "没有可判的样本",
               "找不到", "读不出来", "缺失", "还没出", "尚未落地", "0 个文件", "没有对应常量",
               "不新鲜", "过期", "滞后"):
        if 词 in 文:
            return "缺件或半成品"
    return "源码错"


def 验证(仓根: Path, 两遍=True, 元数据覆盖=None, 只跑=None) -> dict:
    """跑判据并出三元读数（通过 / 失败 / 未判）。

    `只跑`（一个判据名集合）给 `--自测` 的反向样本用：每条反向样本只需要证「**这一条**判据
    抓得住这次注入」，跑全量 36 条是浪费 —— 59 条样本 × 36 条判据会把 `--自测` 顶过它自己的
    五秒硬顶（实测 7.4 s）。只跑目标判据**不放松**任何断言：退出码仍由该判据的红算，
    「报出且指到路径」照样逐字判；跑全量的那一次（正向样本 + 承重证明）仍在，口径不变。
    `只跑=None` 时行为与旧版逐字相同（全量）。

    **第二遍只复核「第一遍报出东西的判据」**（2026-09-27 提速 · 决策记录 §三.2）：
    第二遍的**唯一**作用是给第一遍的红做「真红 vs 疑似瞬时」判别 —— 第一遍**空的**判据
    没有红要复核，跑它纯属浪费（旧行为每遍跑全部 ⇒ 成本翻倍，实测 4900 ≈ 2 × 2450）。
    本命令健康时第一遍全空 ⇒ 第二遍整条省掉。

    ★ 这个收窄**动了什么、没动什么**（不许静默降级，如实登记）：
      · **没动**：任何**被报出**的红的真红/瞬时判别 —— 第一遍报了的判据一定进 `需复核`、
        一定跑第二遍，判别口径与旧行为逐字相同；**判定结论（通过/失败/未判/退出码）不变**。
      · **动了**：旧行为还能发现「第一遍**没报**、第二遍**才报**」的瞬时（旧代码把它归
        `疑似瞬时`）。这种瞬时**本来就不阻断**（`算退出码` 只看失败与未判），收窄后不再被
        报出来 ⇒ 丢的是**一条不阻断的信息**，不是一条判定。要复核这一条，跑
        `--自测` 的 `自检_两遍复核收窄`（它证明「报了的照样两遍复核、没报的不跑第二遍」）。
      · 需要旧的全量两遍行为时：置 `提速开关 = False`（承重证明用）。

    ★ **延迟判据 ⑱ 不进「真红 vs 疑似瞬时」判别**（为什么）：它的 `缺什么` 带的是
      **当时那一刻的墙钟读数**（「读数 N ms > 硬顶 5000 ms」），两遍的读数天然不同
      ⇒ 指纹永远配不上 ⇒ 会被误判成「疑似瞬时」而**不阻断**（假绿）。而它的读数是从
      进程启动起算的**单调量**：第一遍超了，第二遍只多不少 ⇒ 第一遍红就是真红，
      不需要第二遍复核。故 ⑱ 直接按第一遍的读数判真红（见下面循环里的 `第二表`）。
    """
    起 = time.perf_counter()
    # 一次 `验证` **只读一次仓**：两遍读的是同一刻的同一份盘面 ⇒ 建好一次传下去。
    上 = 建上下文(仓根)
    第一 = 跑一遍(仓根, 元数据覆盖, 跑延迟=False, 只跑=只跑, 上=上)
    名集 = {名 for 名, _ in 判据表.检查表} if 只跑 is None else set(只跑)
    需复核 = {
        名
        for 名 in 名集
        if 名 != 检查名[17]  # 见下：延迟判据不进「真红 vs 疑似瞬时」判别
        and (第一["结果"].get(名) or 名 in {条["检查"] for 条 in 第一["子未判"]})
    }
    if 两遍 and not 常量.提速开关:
        需复核 = {名 for 名 in 名集 if 名 != 检查名[17]}  # 退回一步：两遍全量（承重证明用）
    第二 = 跑一遍(仓根, 元数据覆盖, 只跑=需复核, 上=上) if (两遍 and 需复核) else None
    # 延迟判据 ⑱ 在**这里**判（`跑一遍` 那次用 `跑延迟=False` 关掉了）：
    # 必须在「两遍都跑完」之后读钟。若在 跑一遍 的第一遍末尾读，只要第二遍要跑（有红要复核），
    # 读数就少读了整个第二遍 —— 实测 `提速开关=False` 时 验证 墙钟 5087 ms，而第一遍末尾
    # 只读到 2431 ms ⇒ 会把一条真超 5 s 的命令判绿（**假绿**）。读在这里，读数覆盖两遍，
    # 只剩「结果装配 + 打印失败明细 + 解释器退出」那条尾巴（实测 80 ms，登记在 `--缺口`）。
    上["本命令墙钟毫秒"] = int((time.perf_counter() - 进程起始时刻) * 1000)
    延迟函数 = dict(判据表.检查表).get(检查名[17])
    if 延迟函数 is not None:
        第一["结果"][检查名[17]] = 延迟函数(上)
    耗时毫秒 = int((time.perf_counter() - 起) * 1000)

    元数据 = 上.get("判据元数据覆盖") or 判据元数据

    # ── 对象数读数：**搭判据批的车**（2026-09-27 提速 · 实测撞到的真瓶颈）──
    # 几条判据的对象数是「把全仓 746 件过一遍生产区」（㉕ 运行数据自拼 · ㊲ 超时设置），
    # 各 ~0.8 s；判据本体用的正是同一份读数 ⇒ 在同一个子进程里取第二次是**纯缓存命中**。
    # 早先它单开一趟：串行 2821 ms · 线程池 1→3140/2→2699/4→3082/8→7736 ms（抢 GIL）·
    # 另起 fork 池 988 ms —— 三种都是把同一份活重算一遍。
    # 实测后果：闸 1 真墙钟 4.6 s，而它自报「耗时 1.4 s」；闸 0 串起来 **5102 ms ⇒ 超五秒硬顶**。
    # 搭车后那一趟整个消失（见 `跑一项判据`）。这里只补**不在批里**的（只跑子集 / 延迟判据 ⑱）。
    对象数表 = dict(第一.get("对象数表") or {})
    补未判 = []  # 取对象数时若真有判据报了未判（不该有），照收 —— 不许静默丢。
    for 名, 元 in 元数据.items():
        取对象 = 元.get("对象数")
        if 名 in 对象数表 or not callable(取对象):
            continue
        清未判()
        对象数表[名] = 取对象(上)
        补未判 += 取未判()

    通过表, 失败表, 未判表, 瞬时表 = [], [], [], []
    for 名, _ in 判据表.检查表:
        if 名 not in 名集:
            continue  # 只跑：没跑的判据不进三元读数（不许被当成「通过」）
        违规表 = 第一["结果"].get(名) or []
        # 不在 `需复核` 里的判据：第一遍是空的（无红、无子未判）⇒ 第二表就是空，取自身即可。
        第二表 = (第二["结果"].get(名) or []) if (第二 is not None and 名 in 需复核) else 违规表

        def 指纹(条):
            return (条["检查"], 条["位置"], 条["缺什么"])

        第二指纹 = {指纹(c) for c in 第二表}
        真红, 瞬时 = [], []
        for 条 in 违规表:
            if 指纹(条) in 第二指纹:
                真红.append(条)
            else:
                瞬时.append(条)
        瞬时.extend(c for c in 第二表 if 指纹(c) not in {指纹(x) for x in 违规表})

        对象数 = 对象数表.get(名)
        样本数 = 对象数 if 对象数 is not None else None
        样本齐 = (
            元数据.get(名, {}).get("反向样本") in 样本清单
            and 元数据.get(名, {}).get("正向样本") in 样本清单
        )

        if 真红:
            失败表.append(名)
            for 条 in 真红:
                条.setdefault("分类", 分类红(条))
                条["_判据"] = 名
            失败表.extend(真红)
        elif 样本数 == 0:
            未判表.append(名)
            未判表.append(
                {
                    "检查": 名,
                    "位置": f"扫描面：{元数据.get(名, {}).get('扫描面')}",
                    "缺什么": "扫描 0 项（该判据的对象当前不存在）",
                    "不能自愈": "判据的可信性.md 第二节：空集是「未判」，不是「通过」——"
                    "对象不存在时这条判据什么都没验，算成通过就是假绿。"
                    "对象的落地不属验证面（验证面不造声明、不造扩展）⇒ 只能由对应节点补",
                    "分类": "缺件或半成品",
                    "_判据": 名,
                }
            )
        elif not 样本齐:
            未判表.append(名)
            未判表.append(
                {
                    "检查": 名,
                    "位置": f"判据元数据:{名}",
                    "缺什么": f"未验证：缺反向样本或正向样本（元数据："
                    f"反向「{元数据.get(名, {}).get('反向样本')}」· "
                    f"正向「{元数据.get(名, {}).get('正向样本')}」）",
                    "不能自愈": "判据的可信性.md 第五节：缺任一方 ⇒ 该判据「未验证」，"
                    "它的「通过」不计入通过数（没有自证能力的判据，不计入通过）⇒ "
                    "只能由判据作者补齐样本",
                    "分类": "源码错",
                    "_判据": 名,
                }
            )
        else:
            通过表.append(名)
    瞬时表 = [{**条, "分类": "疑似瞬时"} for 条 in 瞬时]
    # 子判据空集（判据内部的「这条子判据的对象是空集」）：并进未判逐条。
    # 两遍都出现才算（与红的「真红 / 疑似瞬时」同一条纪律）。
    子未判表 = 第一.get("子未判") or []
    if 第二 is not None:
        子指纹 = {(条["检查"], 条["位置"]) for 条 in (第二.get("子未判") or [])}
        子未判表 = [条 for 条 in 子未判表 if (条["检查"], 条["位置"]) in 子指纹]
    # 取对象数时若真有判据报了未判（不该有），照收 —— 不许静默丢（也不进两遍过滤：
    # 它不是「判据报的红」，没有「真红 vs 疑似瞬时」要判别）。
    未判表 += 补未判
    未判表.extend(子未判表)
    return {
        "通过": 通过表,
        "失败": 失败表,
        "未判": 未判表,
        "疑似瞬时": 瞬时表,
        "耗时毫秒": 耗时毫秒,
        "上下文": 上,
    }
