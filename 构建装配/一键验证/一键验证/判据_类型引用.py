# -*- coding: utf-8 -*-
"""判据 ⑤⑥⑦：参数/返回类型在类型表里 · 可抛错误码都在错误码表登记。"""

from __future__ import annotations

from .小工具 import 是整数, 违规
from .常量 import 号段图路径, 契约目录名, 检查名


def 检查5_参数类型都在类型表里(上层读数: dict) -> list:
    输出缓冲 = []
    标签集 = {记录["数据"].get("类型标签") for 记录 in 上层读数["编号表"]["类型声明"] if 记录["数据"]}
    标签集 = {标签 for 标签 in 标签集 if 是整数(标签)}
    for 记录 in 上层读数["编号表"]["能力声明"]:
        if 记录["数据"] is None:
            continue
        参数表 = 记录["数据"].get("参数表")
        位置基 = f"{契约目录名}/能力声明/{记录['文件名']}:参数表"
        if 参数表 is None:
            输出缓冲.append(
                违规(
                    检查名[4],
                    位置基,
                    "没有 参数表 字段（§三：行序即契约，空表也要写 []）",
                    f"参数表缺字段与「参数表为空」是两回事：前者让读者无从判断"
                    f"「无参」还是「漏写」；§三 定死了形状 ⇒ 只能由声明方补",
                )
            )
            continue
        if not isinstance(参数表, list):
            输出缓冲.append(
                违规(
                    检查名[4],
                    位置基,
                    f"参数表 不是列表（是 {type(参数表).__name__}）",
                    f"行序即契约（§三 冻结项）：不是列表就没有行序可言，"
                    f"与实现侧逐位比对无从下手 ⇒ 只能由声明方补",
                )
            )
            continue
        for 序号, 源码行 in enumerate(参数表):
            行位置 = f"{位置基}[{序号}]"
            if not isinstance(源码行, dict):
                输出缓冲.append(
                    违规(
                        检查名[4],
                        行位置,
                        f"不是对象（是 {type(源码行).__name__}）",
                        f"§三 的参数行是 {{名称,说明,类型标签,状态位,默认值}}；"
                        f"不是对象就读不出类型标签，行序比对也随之失锚 ⇒ 只能由声明方补",
                    )
                )
                continue
            标签 = 源码行.get("类型标签")
            if not 是整数(标签):
                输出缓冲.append(
                    违规(
                        检查名[4],
                        f"{行位置}:类型标签",
                        f"类型标签 缺失或不是整数（{标签!r}）",
                        f"参数类型标签是跨边界放值的唯一锚点（§四）；它缺了，"
                        f"这一行的值就没法在槽里解释，实参类型只有声明方知道 ⇒ 只能由声明方补",
                    )
                )
            elif 标签 not in 标签集:
                输出缓冲.append(
                    违规(
                        检查名[4],
                        f"{行位置}:类型标签",
                        f"类型标签 {标签} 在 类型声明/ 里查不到"
                        f"（现有标签：{sorted(标签集)}）",
                        f"类型声明是唯一事实源（§四）；补一个标签要占一个永不改写的号，"
                        f"把参数改成已有标签会改已公布的参数行序语义（冻结项）⇒ 只能人来裁",
                    )
                )
            默认值 = 源码行.get("默认值")
            if isinstance(默认值, dict):
                默认标签 = 默认值.get("类型标签")
                if 是整数(默认标签) and 默认标签 not in 标签集:
                    输出缓冲.append(
                        违规(
                            检查名[4],
                            f"{行位置}:默认值.类型标签",
                            f"默认值的类型标签 {默认标签} 在 类型声明/ 里查不到",
                            f"默认值要按标签解释成槽里的值（§三 的 默认值{{类型标签,值}}）；"
                            f"标签没登记就没法解释，补标签要占新号 ⇒ 只能人来裁",
                        )
                    )
    return 输出缓冲


def 检查6_返回类型在类型表里(上层读数: dict) -> list:
    输出缓冲 = []
    标签集 = {记录["数据"].get("类型标签") for 记录 in 上层读数["编号表"]["类型声明"] if 记录["数据"]}
    标签集 = {标签 for 标签 in 标签集 if 是整数(标签)}
    for 记录 in 上层读数["编号表"]["能力声明"]:
        if 记录["数据"] is None:
            continue
        位置 = f"{契约目录名}/能力声明/{记录['文件名']}:返回类型"
        待处理值 = 记录["数据"].get("返回类型")
        if not 是整数(待处理值):
            输出缓冲.append(
                违规(
                    检查名[5],
                    位置,
                    f"返回类型 缺失或不是整数（{待处理值!r}）",
                    f"§三：返回类型 0 表示无返回值，非 0 必须在类型表里；字段缺了"
                    f"读者无从区分「无返回」与「漏写」，而这一项是使用角色最先看的东西 ⇒ 只能由声明方补",
                )
            )
            continue
        if 待处理值 != 0 and 待处理值 not in 标签集:
            输出缓冲.append(
                违规(
                    检查名[5],
                    位置,
                    f"返回类型 {待处理值} 在 类型声明/ 里查不到（0 才是无返回值；"
                    f"现有标签：{sorted(标签集)}）",
                    f"返回槽按类型标签解释（§三 · lib.rs 数据槽）；补标签要占一个永不改写的号，"
                    f"改成 0 会改已公布的返回语义 ⇒ 只能人来裁",
                )
            )
    return 输出缓冲


def 检查7_可抛错误码都在错误码表登记(上层读数: dict) -> list:
    输出缓冲 = []
    项表 = {}
    for 记录 in 上层读数["编号表"]["错误码表"]:
        位置 = f"{契约目录名}/错误码表/{记录['文件名']}"
        if 记录["数据"] is None:
            输出缓冲.append(
                违规(
                    检查名[6],
                    位置,
                    f"这份错误码声明读不出来（{记录['错误']}）",
                    f"错误码表是「未登记不许抛出」的唯一登记处（§五）；"
                    f"这一份读不出来，它登记的那个码就等于没登记，而码本身只有声明方知道 ⇒ 只能由声明方补",
                )
            )
            continue
        数据 = 记录["数据"]
        错误码 = 数据.get("码")
        if not 是整数(错误码):
            输出缓冲.append(
                违规(
                    检查名[6],
                    f"{位置}:码",
                    f"码 缺失或不是整数（{错误码!r}）",
                    f"§五：码 = 完整的 4 位号，就是文件名；字段缺了就只能靠文件名，"
                    f"而文件名与字段谁是源判据没定 ⇒ 只能由声明方补",
                )
            )
            continue
        if 错误码 not in 项表:
            项表[错误码] = 记录
        缺失项 = [键名 for 键名 in ("可重试", "可自愈", "需人工") if 键名 not in 数据]
        if 缺失项:
            输出缓冲.append(
                违规(
                    检查名[6],
                    f"{位置}:{(' · '.join(缺失项))}",
                    f"缺三项业务登记项里的 {(' · '.join(缺失项))}"
                    f"（§五：三项业务登记项 = 可重试 · 可自愈 · 需人工；"
                    f"段位 是**冗余登记项**，另判「段位 == 码//1000」）",
                    f"三项业务登记项是「失败可编程处理」的全部依据（README 第一节宪法级判据）："
                    f"调用方靠它判可重试/可自愈/需人工，三项都是业务判断，验证面猜不出来；"
                    f"段位可由码算出，但那三项算不出来 ⇒ 只能人来裁",
                )
            )
            continue
        段位 = 数据.get("段位")
        if 段位 is None:
            输出缓冲.append(
                违规(
                    检查名[6],
                    f"{位置}:段位",
                    f"缺**冗余登记项** 段位（§五：段位 可从 码 导出，故意写出来由验证面交叉比对抓错）",
                    f"段位 是故意冗余的那一项：它的用处就是「写错了能被判据抓住，而不是默默按错的用」；"
                    f"缺了它这条交叉比对就空转。它可由码算出，但「要不要保留这项冗余」是契约侧的决定 ⇒ "
                    f"只能由声明方补（照 §五 的形状）",
                )
            )
        elif not 是整数(段位):
            输出缓冲.append(
                违规(
                    检查名[6],
                    f"{位置}:段位",
                    f"段位 不是整数（{段位!r}）",
                    f"§五：段位 = 码的首位十进制数字（0–9）；不是整数就算不出归属，"
                    f"而它决定这个码落哪一层 ⇒ 只能由声明方补",
                )
            )
        else:
            应段位 = 错误码 // 1000
            if 段位 != 应段位:
                输出缓冲.append(
                    违规(
                        检查名[6],
                        f"{位置}:段位",
                        f"码 {错误码} 的首位十进制数字是 {应段位}，文件里 段位 写的是 {段位}",
                        f"§五：段位 = 码的首位数字，也是号段归属的唯一入口"
                        f"（段位 2 ⇒ 2xxx 文件与目录）；改码要动文件名与全局唯一号，"
                        f"改段位要改归属 ⇒ 两个方向都动契约 ⇒ 只能人来裁",
                    )
                )
        for 键名 in ("可重试", "可自愈", "需人工"):
            if 键名 in 数据 and not isinstance(数据[键名], bool):
                输出缓冲.append(
                    违规(
                        检查名[6],
                        f"{位置}:{键名}",
                        f"{键名} 不是逻辑型（{数据[键名]!r}）",
                        f"§五 的三项登记是逻辑型（lib.rs 与调用方按 true/false 判分支）；"
                        f"写成字符串会让判定悄悄走另一条路，该取哪个值只有声明方能定 ⇒ 只能由声明方补",
                    )
                )

    # 平台声明.错误段位表：里面是段位（不是码），每个段位都必须有登记
    平台 = 上层读数["平台"] or {}
    段位表 = 平台.get("错误段位表")
    位置 = f"{契约目录名}/平台声明.json:错误段位表"
    if not isinstance(段位表, list) or not 段位表:
        输出缓冲.append(
            违规(
                检查名[6],
                位置,
                f"错误段位表 不是非空列表（是 {type(段位表).__name__}）",
                f"§二：错误段位表 里是段位（不是码），是 平台信息 的旁路字段之一；"
                f"缺了它「未登记的错误码不许抛出」判不了（冻结登记 已收口旁路 原话）⇒ 只能由声明方补",
            )
        )
    else:
        for 序号, 段位 in enumerate(段位表):
            if not 是整数(段位):
                输出缓冲.append(
                    违规(
                        检查名[6],
                        f"{位置}[{序号}]",
                        f"不是整数（{段位!r}）",
                        f"§二：段位 = 码的首位十进制数字（0–9）；写成别的形状会让"
                        f"装载入口的段位比对失锚 ⇒ 只能由声明方补",
                    )
                )
                continue
            if not (0 <= 段位 <= 9):
                输出缓冲.append(
                    违规(
                        检查名[6],
                        f"{位置}[{序号}]",
                        f"段位 {段位} 不在 0–9（§五：段位 = 码的首位十进制数字）",
                        f"段位是一位十进制数字；超出去就取不出对应的码区间，"
                        f"这个段位下的码全判不了 ⇒ 只能人来裁",
                    )
                )
                continue
            段位图集 = {
                段位项.get("段位")
                for 段位项 in ((上层读数["号段图"] or {}).get("错误码段位图") or [])
                if isinstance(段位项, dict)
            }
            if 段位图集 and 段位 not in 段位图集:
                输出缓冲.append(
                    违规(
                        检查名[6],
                        f"{位置}[{序号}]",
                        f"占用的段位 {段位} 不在 {号段图路径}:错误码段位图 里"
                        f"（图里有 {sorted(段位图集)}）",
                        f"§二 ★：错误码段位图 是**全平台的段位布局**（每一位归谁），"
                        f"平台声明.错误段位表 只是**本声明占用**；占了平台没划的段位"
                        f"就等于声称占用不存在的层。缩占用会丢码，扩布局要动全平台表 ⇒ 只能人来裁",
                    )
                )
            if not any(是整数(错误码) and 错误码 // 1000 == 段位 for 错误码 in 项表):
                输出缓冲.append(
                    违规(
                        检查名[6],
                        位置,
                        f"段位 {段位} 在 错误码表/ 里一条登记都没有"
                        f"（该段位的码区间是 {段位}000–{段位}999）",
                        f"§五：未登记的错误码不许抛出；段位声明了却一个码都没登记，"
                        f"等于声称占了一段却交不出内容。补登记要定「可重试/可自愈/需人工」三项语义 ⇒ 只能人来裁",
                    )
                )
        # 反向交叉比对（lib.rs 平台信息.错误码表 注释原话：
        # 「验证面交叉比对『段位表 == 本表里各码的段位集合』，两边不一致即判红」）
        声明段位集 = {段位项 for 段位项 in 段位表 if 是整数(段位项)}
        实际段位集 = {错误码 // 1000 for 错误码 in 项表 if 是整数(错误码)}
        for 段位 in sorted(实际段位集 - 声明段位集):
            码表 = sorted(错误码 for 错误码 in 项表 if 是整数(错误码) and 错误码 // 1000 == 段位)
            输出缓冲.append(
                违规(
                    检查名[6],
                    位置,
                    f"错误码表/ 里有段位 {段位} 的码（{码表}），"
                    f"但 错误段位表 里没声明这个段位（声明的是 {sorted(声明段位集)}）",
                    f"lib.rs 平台信息.错误码表 注释定死了这条交叉比对：段位表是**占用声明**、"
                    f"错误码表是内容，两边必须一致。段位是「本声明占哪几个段位」的对外承诺，"
                    f"补进声明表等于扩大占用面，删掉那个码等于撤一个已公布错误码 ⇒ 只能人来裁",
                )
            )

    # 能力声明.可抛错误码：每一项都要能查到
    for 记录 in 上层读数["编号表"]["能力声明"]:
        if 记录["数据"] is None:
            continue
        位置 = f"{契约目录名}/能力声明/{记录['文件名']}:可抛错误码"
        值表 = 记录["数据"].get("可抛错误码")
        if 值表 is None:
            输出缓冲.append(
                违规(
                    检查名[6],
                    位置,
                    "没有 可抛错误码 字段（§三：空表也要写 []）",
                    f"字段缺了读者无从区分「不抛错」与「漏写」；§三 定死了这个字段名"
                    f"（旧名 错误段位 已废止），补哪个名字只有声明方能定 ⇒ 只能由声明方补",
                )
            )
            continue
        if not isinstance(值表, list):
            输出缓冲.append(
                违规(
                    检查名[6],
                    位置,
                    f"可抛错误码 不是列表（是 {type(值表).__name__}）",
                    f"§三 的形状是可抛错误码: [码, …]；不是列表就没法逐项比对 ⇒ 只能由声明方补",
                )
            )
            continue
        for 序号, 错误码 in enumerate(值表):
            if not 是整数(错误码):
                输出缓冲.append(
                    违规(
                        检查名[6],
                        f"{位置}[{序号}]",
                        f"不是整数（{错误码!r}）",
                        f"§三：可抛错误码 里是码（完整 4 位号）；写成别的形状"
                        f"会让装载入口与调用方读法分叉 ⇒ 只能由声明方补",
                    )
                )
            elif 错误码 not in 项表:
                输出缓冲.append(
                    违规(
                        检查名[6],
                        f"{位置}[{序号}]",
                        f"码 {错误码} 在 错误码表/ 里没有登记"
                        f"（已登记：{sorted(项表)}）",
                        f"§五：未登记的错误码不许抛出。补登记要定「可重试 · 可自愈 · 需人工」"
                        f"三项语义（调用方靠它编程处置），那是业务判断；"
                        f"改成别的已登记码会改这条能力已公布的失败语义 ⇒ 只能人来裁",
                    )
                )
    return 输出缓冲
