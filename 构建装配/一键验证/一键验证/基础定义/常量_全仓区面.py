from __future__ import annotations

# ── 判据「扫描面」的全仓顶层区基础集（2026-09-30 收口）───────────────────────
# 判据元数据里各判据声明的 `扫描面` 大多是一份**全仓顶层区清单** —— 同一事实原先在
# `判据元数据.py` 与 6 个拆件里抄了十几份。这里立**唯一主人**：一份基础集 + `取全仓区面` 加减。
# ★ **不许把合法的面差抹平** —— 各判据的面**可以合法不同**（有的含 `扩展装载/` · `构建环境/` ·
#   `AGENTS.md`，有的只 5 项、2 项）；加减的**最终集合必须与该判据原本声明逐项相等**
#   （2026-09-29 实测教训：把两份「目录 → 层」映射并成一份 ⇒ 判据 ⑪ 当场红）。
全仓区基础集 = (
    "契约声明", "运行内核", "跨语言适配", "对外接口面", "前端呈现",
    "扩展装载", "扩展根目录", "项目文档", "测试验证", "构建装配",
    "开发工具", "README.md",
)


def 取全仓区面(加项: tuple = (), 减项: tuple = (), 只项: tuple = ()) -> tuple:
    """`全仓区基础集` ± 增量 —— 判据 `扫描面` 的**唯一表达处**。

    `只项` 非空 ⇒ 定向面（只取基础集里这几项）；`减项` ⇒ 收窄面（去掉这几项）；
    `加项` ⇒ 追加在末（基础集之外的顶层区 / 路径）。顺序按基础集给 —— 判据面是集合语义
    （元判据 ⑭ 与判据 ㉖ 都只看集合，不看顺序）。
    """
    if 只项:
        return tuple(每项 for 每项 in 全仓区基础集
                     if 每项 in 只项 and 每项 not in 减项) + tuple(加项)
    return tuple(每项 for 每项 in 全仓区基础集 if 每项 not in 减项) + tuple(加项)
