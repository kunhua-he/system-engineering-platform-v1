def _行数工具(上层读数: dict):
    """惰性取「开发规范 第六节硬数」的机器判据（`开发工具/查文件行数/核心.py`）。

    **不在这里重写一遍扫描与判定**：那会是同一件事两套实现（判据的可信性.md §三.3 的
    假绿来源）。工具自身带 8 条自测断言（`--自测`），本判据只做它没做的那一件事：
    **对照基线判「新增」与「还在长」**。

    ★ **工具从「判据自身所在的仓」取，不从「被扫的仓」取**：被扫的仓可以是合成夹具
    （`--自测` 的干净合成仓里没有 `开发工具/查文件行数/`）—— 判据的**实现**跟着判据走，
    被扫的仓只提供**基线**（那是被扫仓自身的债务）。这两件事分开，判据才能在夹具上跑。
    """
    import importlib
    import sys as _sys

    根目录 = str(常量.仓根 / "开发工具")
    if 根目录 not in _sys.path:
        _sys.path.insert(0, 根目录)
    import 查文件行数.核心 as 核心

    return 核心


def 检查19_行数硬数(上层读数: dict) -> list:
    """`开发规范.md` 第六节三条硬数：**单源文件 ≤800 行 · 入口 ≤120 行 · 入口零实现**。

    依据：`项目文档/决策记录/2026-09-27_行数硬数与拆分面裁决.md`（裁决 + 存量基线口径）。
    **这条判据此前不存在** —— 规则在 `开发规范.md` §六 写了很久，全仓没有一条判据盯着它，
    于是实测违反 **59 处**（①12 · ②22 · ③25）而没有人被拦。这是「一劳永逸」条件 ④
    （**规则有判据**）的一个空洞：**规则没判据 = 最松的接缝**。

    **为什么是「存量入基线、新增即红」而不是「今天全清」**（裁决 §三）：拆
    `一键验证.py`（6192 行）与 `扫实现.py`（2662 行）是大重构，与本轮要动的契约面撞车；
    判据的当务之急是**不许再长**。照 `决策记录/2026-09-27_命名规范.md` 的先例办。

    **基线只能减**：任何往 `行数基线.json` 里加新登记的动作都会让「债务合计」读数上涨，
    涨了就要在提交信息里解释 —— 这是本条判据能立住的关键（否则基线就成了白名单）。

    **扫描与判定在 `开发工具/查文件行数/核心.py`**（一处实现，本判据不重写）；这里只做
    「对照基线」这一件工具没做的事。
    """
    输出缓冲 = []
    核心 = _行数工具(上层读数)
    仓根 = 上层读数["仓根"]
    基线表, 错误 = 读行数基线(仓根)
    if 错误:
        return [
            违规(
                检查名[18],
                行数基线路径,
                错误,
                "「存量入基线、新增即红」要求先有存量清单；没有它，实测 59 处违反会全部算成"
                "「新增」⇒ 判据当场红一片，等于没上闸。基线只能由**声明方**登记"
                "（谁欠的债谁登记）⇒ 只能由维护方补（库 `行数基线` 表）",
            )
        ]
    登记表 = {判据类别: {} for 判据类别 in 行数类别}
    for (判据类别, 路径), 处数 in 基线表.items():
        登记表.setdefault(判据类别, {})[路径] = 处数

    try:
        超行数, 入口超行数, 入口有实现 = 核心.扫一遍(仓根)
    except Exception as 错误:
        return [
            违规(
                检查名[18],
                行数基线路径,
                f"扫描面跑不起来（{type(错误).__name__}：{错误}）",
                "扫描面是判据的眼睛；它跑不起来就一条都判不出 ⇒ 只能由判据作者修"
                "（实现在 `开发工具/查文件行数/核心.py`）",
            )
        ]

    上限源, 上限口 = 核心.行数上限, 核心.入口行数上限

    def 判一批(判据类别: str, 实测: list, 上限: int, 怎么说: str) -> None:
        for 实测项 in 实测:
            路径, 实际 = 实测项[1], 实测项[0]
            登记 = 登记表[判据类别].get(路径)
            if 登记 is None:
                输出缓冲.append(
                    违规(
                        检查名[18],
                        f"{路径}",
                        f"{实际} 行 > 上限 {上限} 行（{怎么说}），而基线里没有它 ⇒ **新增**",
                        f"开发规范.md 第六节：{怎么说} 的硬数是「改一处时不需要把整个文件读进来」"
                        f"（800 行）。`项目文档/决策记录/2026-09-27_行数硬数与拆分面裁决.md`"
                        f" §三 定「存量入基线、**新增即红**」——新写出来的超限文件"
                        f"是**新债**，不是历史遗留。修法：拆件（一个关注点一个文件，放同名字文件夹）"
                        f"⇒ 只能由该文件的作者拆",
                    )
                )
            elif 实际 > 登记:
                输出缓冲.append(
                    违规(
                        检查名[18],
                        f"{路径}",
                        f"{实际} 行 > 基线登记 {登记} 行（{怎么说}）⇒ **存量还在长**",
                        f"基线是「存量不许再长」的闸，不是白名单（裁决 §三）。这一件已在基线里"
                        f"登记过，却又长了 {实际 - 登记} 行 ⇒ 要么拆回去，要么在提交信息里说明"
                        f"为什么必须涨并同步登记 ⇒ 只能由该文件的作者处置",
                    )
                )

    判一批("超行数", 超行数, 上限源, "单源文件")
    判一批("入口超行数", 入口超行数, 上限口, "入口文件")
    for 路径, 实现 in 入口有实现:
        登记 = 登记表["入口有实现"].get(路径)
        if 登记 is None:
            输出缓冲.append(
                违规(
                    检查名[18],
                    f"{路径}",
                    f"入口文件里有 {len(实现)} 处实现（基线里没有它 ⇒ **新增**）",
                    f"开发规范.md 第六节：入口（`lib.rs`/`main.rs`/`mod.rs`/`__init__.py`/脚本）"
                    f"只做三件事 —— 声明子模块 · 再导出公开面 · **零实现**。入口是路由不是实现；"
                    f"路由里有实现，每个读入口的人都被迫读一遍实现。第一条实现在"
                    f"「{实现[0][2][:60]}」⇒ 只能由该文件的作者搬进子模块",
                )
            )
        elif len(实现) > 登记:
            输出缓冲.append(
                违规(
                    检查名[18],
                    f"{路径}",
                    f"入口实现 {len(实现)} 处 > 基线登记 {登记} 处 ⇒ **存量还在长**",
                    f"基线只许减不许增（裁决 §三）；这一件已登记过，又多出 "
                    f"{len(实现) - 登记} 处 ⇒ 要么搬走，要么在提交信息里说明并同步登记 ⇒ "
                    f"只能由该文件的作者处置",
                )
            )

    # ── 基线里不许留**陈旧登记**（2026-09-27 加）──
    # 裁决说「基线只许减」。一条登记若不再超限、或实测已低于登记值，它自身就成了「只增不减」的
    # 反面：读「债务合计」的人看到的是历史而不是现状，且它把上限白抬一格（缩水的那个洞尤其隐蔽）。
    # 实测（2026-09-27）：`契约声明/src/lib.rs` 拆成路由入口（零实现）之后，
    # `入口有实现` 那条 60 处一直挂着 —— 没有任何一条判据会去问「你还欠着吗」。
    实测表 = {
        "超行数": {实测项[1]: 实测项[0] for 实测项 in 超行数},
        "入口超行数": {实测项[1]: 实测项[0] for 实测项 in 入口超行数},
        "入口有实现": {路径: len(实现) for 路径, 实现 in 入口有实现},
    }
    for 判据类别, 项表 in 登记表.items():
        for 路径, 登记 in sorted(项表.items()):
            实际 = 实测表[判据类别].get(路径)
            if 实际 is None:
                输出缓冲.append(
                    违规(
                        检查名[18],
                        f"{路径}",
                        f"基线登记着 {登记}（{判据类别}），而实测这一件**已经不超限**（不在扫描面里）"
                        f"⇒ **陈旧登记**",
                        f"裁决 §三「基线只许减」：不超限了就该把登记删掉。留着它，基线读数就不再是"
                        f"现状（读的人会以为债还在），而且它白占一格上限 ⇒ "
                        f"只能由维护方删（`{行数基线路径}`）",
                    )
                )
            elif 实际 < 登记:
                输出缓冲.append(
                    违规(
                        检查名[18],
                        f"{路径}",
                        f"基线登记 {登记}，实测只有 {实际}（{判据类别}）⇒ **登记没跟着减**",
                        f"裁决 §三「基线只许减」：实测比登记低就该同步减下来。不减的话，"
                        f"这一件可以一路长回 {登记} 而不报红 —— 那是「只增不减」的一个洞 ⇒ "
                        f"只能由维护方改（`{行数基线路径}`）",
                    )
                )
    return 输出缓冲
