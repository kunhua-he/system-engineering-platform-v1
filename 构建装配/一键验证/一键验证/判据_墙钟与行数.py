def 检查18_命令墙钟不超五秒(上层读数: dict) -> list:
    """命令级延迟判据：**本命令一次完整运行的墙钟 > 效率目标 ⇒ 后台记一条债务**（不判红），读数带实际毫秒。

    依据：`项目文档/决策记录/2026-09-27_所有运行五秒硬顶.md` §一/§三.4 ——
    一条命令完整跑完（进程启动到退出）的墙钟 ≤ 5000 ms，取 p100，超过即 bug、无例外；
    本件 §三.4 明确要求「加一条延迟判据：每个命令墙钟 > 5000 ms ⇒ 红，读数带实际毫秒；
    配承重证明」。本判据就是那一条。

    **对象**（`_样本_本命令`）：本命令的这一次运行，恒 1 个 —— 不是扫描集。
    **读数**：三档来源（从强到弱），全部在 `墙钟采样.定读数毫秒()` 一处定下：
      · **外层壳采样** —— 外层命令（例：`闸0.py`）在起子进程之前把它的起表点经
        `V1_GATE_OUTER_START` 送进来。⑱ 的对象是「**本命令**」：用户敲 `闸0.py` 时
        本命令就是闸0，两条闸是它的子步骤。进程内自量量到的只是「子步骤这一段」，且混着
        「另一条闸同时在抢 CPU」那一段 ⇒ 那既不是本命令的墙钟、又是**读数被污染**
        （2026-09-27 实测：并发跑两条闸，闸 1 的 ⑱ 当场假红）。外层读数才是**真读数**。
      · **进程内自量** —— 没有外层采样时（直接跑 `一键验证.py`）：读数由 `跑一遍` 在
        **所有其它判据跑完之后**写进 `上["本命令墙钟毫秒"]`，所以它看到的是整条命令的墙钟。
      · 进程内已耗时兜底（⑱ 被单独调用、没走命令壳收尾时 —— 偏小的下界，只用于调试路径）。

    **残余（**已裁，2026-09-27**）**：进程内自量的读数**不含**本判据之后的「结果装配 + 打印
    失败/未判明细」与解释器退出那段尾巴（实测 **80 ms**，上界由 `自检_延迟判据承重` 的尾巴
    自证钉在 **< 200 ms**）。判据跑在进程内 ⇒ 它**不可能**读到自身的退出，这是形状的硬限制。
    **裁法**：内部按「效率目标 − `尾巴余量毫秒`」取报告线 ⇒ 报告对**完整命令**（进程启动到退出）为真。
    ★ 有外层采样时这条残余**整段消失**（外层读数就是完整命令的墙钟）。

    修法是**提速**（并发 / 分片 / 缓存），不是改判据、不是放宽上限、不是「再等等」——
    决策记录 第一节 的禁止栏。所以本判据的「不能自愈」指到本验证器的作者。
    """
    读数毫秒, 读数来源 = 定读数毫秒(上层读数, 起始时刻)
    return 报告墙钟(读数毫秒, 读数来源, "本命令墙钟")


