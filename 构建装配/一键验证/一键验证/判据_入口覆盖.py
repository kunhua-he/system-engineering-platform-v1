入口白名单路径 = "构建装配/一键验证/入口白名单.json"

# 入口口径（**锚在第 0 列**：docstring / 字符串里的同名模式不算入口）。
# ★ 2026-09-30 收紧（审计 ㉔ 的连带）：原来是 `^\s*` ⇒ **缩进的 docstring 示例**也被当成入口
#   （实测 `构建装配/门禁/__init__.py` 的公开面说明里那行缩进示例 —— 旧口径靠「说明里含
#   `自门禁`」这个子串把它蒙过去，收紧带壳后它当场变成假红）。改成**第 0 列**（真入口的
#   `if __name__ == "__main__":` 恒在模块级）⇒ 全仓入口 42 → 41 件，少的正是那一件假入口。
主入口模式 = re.compile(r'^if\s+__name__\s*==\s*[\'"]__main__[\'"]\s*:', re.M)
# 带壳的**壳形**（2026-09-30 收紧 · 判据假绿审计 ㉔）：原来只判「文件里出现子串」⇒
# 在 docstring / 注释里提一句 `自门禁` 就算带壳（实测：只提不调的入口 ㉔ 报绿）。
# 现在只认**代码位置**的壳形（`.py` 先剥注释与串；`.sh` 先去掉整行注释）：
#   · 共享壳的调用：`自门禁(` / `报告环境步(`（壳的唯一下落在 `构建装配/门禁/`）；
#   · 任一「门禁」具名函数的调用：`带门禁跑(` 一类（`声明记录区反解/门禁.py`）；
#   · 共享壳的**起表点**：`time.monotonic(`（壳口径：起表点写在入口第一行可执行语句 ——
#     `构建装配/演示/` 那两条自量入口由它认出来）。
脚本带壳形 = re.compile(
    r"(?<![\w])(?:自门禁|报告环境步)\s*\(|(?<![\w])\w*门禁\w*\s*\(|(?<![\w])time\s*\.\s*monotonic\s*\("
)
# `.sh`：**命令位**上的壳形（2026-10-01 收紧 · 判据假绿审计 ㉔ 的残项）。原来 `自门禁` /
# `gate_report` 是**裸子串** ⇒ `echo "gate_report"` 与函数定义 `gate_report() {` 都算带壳
# （「子串存在」而非「真调了」）。现在只认**命令位**（行首 / `;` `&&` `||` `|` `(` 之后 /
# `then` `do` `else` 之后）上的：`trap …`（装 EXIT 钩子）· `自门禁 …`（调共享壳）·
# `gate_report`（自量报告命令）· `START_EPOCH=…`（自量起表点，赋值）。
外壳脚本带壳形 = re.compile(
    r"(?:^|[;&|()]|\bthen\b|\bdo\b|\belse\b)[ \t]*"
    r"(?:trap[ \t]|自门禁(?:[ \t;&|)]|$)|gate_report(?:[ \t;&|)]|$)|START_EPOCH=)",
    re.M,
)

# 走树时的排除：按**相对路径**排（不是按目录名 —— 免得误伤将来别处同名目录）；顶层目录的
# 相对路径**就是段名本身** ⇒ 基础集直接取**段形态主人**（`常量.排除目录` ← `开发工具/代码地图/落点.py`）。
# ★ 本判据**故意要含 `构建环境/`**（`构建环境/{进入,自检}.sh` 是 §六 点名的边界实例，必须进覆盖面）
#   ⇒ 从基础集**减去** `构建环境`，再按相对路径补回它下面真正要跳的缓存 / 工具链目录；
#   `只读参考` 走基础集；`.codegraph` 不在本面（无 `.py` / `.sh`）⇒ 也减掉（集合与改前逐项相等）。
走树排除路径 = (
    tuple(目录名 for 目录名 in 排除目录 if 目录名 not in ("构建环境", ".codegraph"))
    + ("__pycache__", "node_modules", "target",
       "构建环境/构建缓存", "构建环境/cargo", "构建环境/python")
)


def _该排除路径(相对根: str, 名称: str) -> bool:
    路径 = f"{相对根}/{名称}" if 相对根 not in ("", ".") else 名称
    return 路径 in 走树排除路径 or 名称 in (".git", "__pycache__", "node_modules", "target")


# 走树读数在一次运行里不变（同一条判据的对象数与判定各取一次）⇒ 按仓根缓存。
# 键是**绝对路径**：`--自测` 每个夹具一个独立临时目录 ⇒ 不会串。
_入口面缓存: dict = {}


def 扫入口(仓根: Path) -> dict:
    """走树取入口 ⇒ `{相对路径: 文本}`（`.py` 有行首 `__main__` 才算入口；`.sh` 一律算）。"""
    键名 = str(仓根)
    if 键名 in _入口面缓存:
        return _入口面缓存[键名]
    输出缓冲 = {}
    for 根目录, 目录表, 文件表 in os.walk(仓根):
        相对根 = os.path.relpath(根目录, 仓根).replace(os.sep, "/")
        目录表[:] = [目录名 for 目录名 in 目录表 if not _该排除路径(相对根, 目录名)]
        for 名称 in sorted(文件表):
            if not (名称.endswith(".py") or 名称.endswith(".sh")):
                continue
            路径 = Path(根目录) / 名称
            try:
                源文本 = 路径.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            if 名称.endswith(".py") and not 主入口模式.search(源文本):
                continue
            输出缓冲[取相对路径(仓根, 路径)] = 源文本
    _入口面缓存[键名] = 输出缓冲
    return 输出缓冲


def 入口带壳(路径: str, 源文本: str) -> bool:
    """这条入口带壳吗（口径见模块头「带壳」那一段）。

    ★ 2026-09-30 收紧（审计 ㉔）：只认**代码位置**的壳形 —— `.py` 先剥注释与串（复用
    `命名扫描.剥后缀` 这一份剥器，不另写一套）；`.sh` 先去掉整行注释。docstring /
    注释里只提一句不再算带壳。★ 2026-10-01 再收紧：`.sh` 还要落在**命令位**上
    （`echo "gate_report"` / 函数定义 / 赋值都不算），见 `外壳脚本带壳形`。
    """
    if 路径.endswith(".sh"):
        净文本 = "\n".join(源码行 for 源码行 in 源文本.split("\n")
                          if not 源码行.lstrip().startswith("#"))
        return bool(外壳脚本带壳形.search(净文本))
    净文本 = 剥后缀(".py", 源文本)
    return bool(脚本带壳形.search(净文本))


def 自检_入口覆盖() -> list:
    """壳形解析器的身份证（`判据的可信性.md` §三.5：判据的解析器自身也要有反向样本）。

    四问：① `.py` 只在 docstring 里提一句不算带壳（旧口径会假绿）；② `.py` 的代码位置
    真调 `自门禁(` 算带壳；③ `.sh` 的 `echo "gate_report"` 与函数定义 `gate_report() {`
    不算带壳（旧口径会假绿）；④ `.sh` 命令位上的 `trap …` / `START_EPOCH=` 算带壳。
    """
    样本表 = {
        "样例/只提不调.py": '"""样例入口（带壳）：起表点 + 调 自门禁 报墙钟。"""\nprint(1)\n',
        "样例/真调.py": '"""样例入口。"""\nif __name__ == "__main__":\n    自门禁(起始时刻, 入口函数())\n',
        "样例/串里提.sh": 'echo "gate_report"\n跑\n',
        "样例/只定义.sh": 'gate_report() {\n  :\n}\n',
        "样例/命令位.sh": 'START_EPOCH="$(date +%s)"\ntrap gate_report EXIT\n',
    }
    读数 = {路径: 入口带壳(路径, 源文本) for 路径, 源文本 in 样本表.items()}
    说明文字 = " | ".join("%s=%s" % (路径, 读数[路径]) for 路径 in sorted(样本表))
    return [
        ("反向样本：`.py` 只在 docstring 里提一句不算带壳（旧口径会假绿）",
         not 读数["样例/只提不调.py"], 说明文字),
        ("正向样本：`.py` 的代码位置真调 `自门禁(` 算带壳",
         读数["样例/真调.py"], 说明文字),
        ("反向样本：`.sh` 的 `echo \"gate_report\"` 与函数定义不算带壳（旧口径会假绿）",
         not 读数["样例/串里提.sh"] and not 读数["样例/只定义.sh"], 说明文字),
        ("正向样本：`.sh` 命令位上的 `trap …` / `START_EPOCH=` 算带壳",
         读数["样例/命令位.sh"], 说明文字),
    ]


def 读入口白名单(仓根: Path) -> tuple:
    """读被扫仓的入口白名单 ⇒ `({路径: (类, 理由)}, 错误或 None)`。"""
    节点件 = 仓根 / 入口白名单路径
    if not 节点件.is_file():
        return {}, f"白名单文件不存在（{入口白名单路径}）"
    try:
        配置表 = json.loads(节点件.read_text(encoding="utf-8"))
    except Exception as 错误:
        return {}, f"白名单解析不了（{type(错误).__name__}）"
    项表 = {}
    for 白名单项 in 配置表.get("白名单") or []:
        try:
            项表[str(白名单项["路径"])] = (str(白名单项["类"]), str(白名单项["理由"]))
        except (KeyError, TypeError):
            return {}, f"白名单条目形状不对（{白名单项!r}）—— 要 路径/类/理由 三键"
    return 项表, None


def 样本_入口面(上层读数: dict) -> int:
    """对象数：扫到的入口数（0 ⇒ 未判）。"""
    return len(扫入口(上层读数["仓根"]))


def 检查24_入口覆盖面(上层读数: dict) -> list:
    """每个能跑完的入口要么带壳、要么在边界白名单里（§四/§六）。

    三元读数：**通过** = 入口面非空且全部带壳/在白名单里；**失败** = 逐条报出漏网入口
    （含白名单里的陈旧登记）；**未判** = 白名单读不到、或入口面为空。
    """
    输出缓冲 = []
    仓根 = 上层读数["仓根"]
    白名单, 错误 = 读入口白名单(仓根)
    if 错误:
        return [
            违规(
                检查名[23],
                入口白名单路径,
                错误,
                "边界白名单是本条判据的唯一依据（「要么带壳、要么在边界白名单里」）——"
                "没有它，所有边界入口都会被算成「漏了壳」⇒ 当场红一片，等于没上闸。"
                "白名单随被扫仓走（同 行数基线/命名基线 的形状）⇒ 只能由维护方补",
            )
        ]
    入口 = 扫入口(仓根)
    if not 入口:
        判不了(
            检查名[23],
            "全仓 `.py`（行首 `if __name__ == \"__main__\"`）+ 全部 `.sh`",
            "扫到 0 个入口（扫描面或入口口径坏了）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一条入口都没有的仓，"
            "本条判据什么都没验 ⇒ 只能由判据作者确认走树排除与入口口径",
        )
        return 输出缓冲

    for 键名 in sorted(入口):
        if 入口带壳(键名, 入口[键名]) or 键名 in 白名单:
            continue
        输出缓冲.append(
            违规(
                检查名[23],
                键名,
                "这条入口能跑完，却既没带壳、也不在边界白名单里",
                "决策记录 2026-09-27_构建段归环境步.md §六：能跑完的入口要么带壳自门禁"
                "（`.py` 的**代码位置**调 `自门禁`/`报告环境步` 或起表 `time.monotonic(`；"
                "`.sh` 的**命令位**上有 `trap`/`自门禁`/`gate_report`/`START_EPOCH=`），"
                "要么落在三类结构边界（永不返回 · 环境步 · 工具链本体）或 §四/§六 另点名的"
                "薄壳/自量里并**登记进白名单（带理由）**。漏了壳 = 这条命令的墙钟没人量，"
                "慢成 bug 也没人拦 ⇒ 只能由该入口的作者加壳（阈值与理由只从 `构建装配/门禁/` 取）"
                "或在白名单里登记它为什么不必带壳",
            )
        )

    # ── 白名单里不许留**陈旧登记**（同判据 ⑲/㉒ 的口径）──
    # 一条登记若已不是入口（改名/删掉/已带壳），它自身就成了「只增不减」的反面：读白名单的人
    # 看到的是历史而不是现状，而且它白占一格（把一条本该带壳的入口提前豁免）。
    for 键名 in sorted(白名单):
        if 键名 not in 入口:
            判据类别, 理由 = 白名单[键名]
            输出缓冲.append(
                违规(
                    检查名[23],
                    键名,
                    f"白名单登记着「{判据类别}」，而实测这一件**已经不是入口**（不在扫描面里）"
                    f"⇒ **陈旧登记**",
                    "决策记录 2026-09-27_构建段归环境步.md §六：白名单是「按设计不必带壳」的"
                    "声明，不是永久豁免。改名/删除/已加壳之后就把它删掉 —— 留着它，白名单读数"
                    "就不再是现状（读的人会以为这个边界还在），而且它白占一格豁免 ⇒ "
                    f"只能由维护方改（{入口白名单路径}）",
                )
            )
    return 输出缓冲
