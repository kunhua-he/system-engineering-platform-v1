# -*- coding: utf-8 -*-
"""判据 ㉔：入口覆盖面 —— 每个能跑完的入口，要么带壳，要么在边界白名单里。

依据：`项目文档/决策记录/2026-09-27_构建段归环境步.md` §四（薄壳与有逻辑的 shell）·
§六（覆盖面与边界 —— 本条判据的唯一口径落点）。

**为什么要这一条**：全仓入口此前**逐条人量过**（§六 就是那次量的记录），但那是**人维持的**，
不是判据 —— 它会随仓长大而失效。本条把它变成常驻判据：新写一条能跑完的入口而忘了加壳/登记，
当场红。

**口径（逐条抄 §四/§六，不自行发明）**：

  · **入口** = 有 `if __name__ == "__main__"` 的 `.py`（锚在行首，避免把字符串/正则里的
    同名模式当入口），加**全部 `.sh`**（shell 没有 `__main__` 标记 ⇒ 它本身就是入口）。
  · **带壳** = `.py` 里有 `自门禁` 或 `报告环境步`；`.sh` 里有 `trap` 或 `自门禁` 或 `gate_report`。
    壳的**唯一落点**是 `构建装配/门禁/`（阈值与理由都写在那里，不许各入口自身写一份）。
  · **边界白名单**（`构建装配/一键验证/入口白名单.json`，随被扫仓走）：每条**具名 + 带理由**，
    三类结构边界 + §四/§六 另点名的两种：

      ① **永不返回**：没有「一条命令完整运行」这个可量的对象（GUI 壳 / source 脚本）；
      ② **环境步**：§四 豁免项（构建），走 `报告环境步` 照实报、不判顶；
      ③ **工具链本体**：`cargo …` 没有我们的壳，只能靠跑法保证；
      ④ **薄壳**（§四）：只 `exec` 已带壳的 Python 入口、零逻辑 ⇒ 不另加壳；
      ⑤ **自量**（§六）：闸 1 `一键验证.py` 的墙钟由**判据 ⑱** 自量（「壳的判据化」），不是漏了。

**扫描面**：全仓 `.py` / `.sh`。**自身走树**（不复用 `上["文件"]`）—— 因为 `上["文件"]` 按
`跳过目录` 排掉了 `构建环境/`，而 `构建环境/{进入,自检}.sh` 正是 §六 点名的边界实例，必须进覆盖面。
走树时排掉构建环境的缓存/工具链目录（`构建缓存`/`cargo`/`python`）与 `.git` 等。

三元读数：**通过** = 扫到入口且全部带壳/在白名单里；**失败** = 逐条报出漏网的入口；
**未判** = 一条入口都没有（扫描面或入口口径坏了，不是「没问题」）。
"""
from __future__ import annotations

import json
import os
import re
from pathlib import Path

from .小工具 import 判不了, 相对, 违规
from .常量 import 检查名


入口白名单路径 = "构建装配/一键验证/入口白名单.json"

# 入口口径（锚在行首：字符串/正则里的同名模式不算入口）。
主入口模式 = re.compile(r'^\s*if\s+__name__\s*==\s*[\'"]__main__[\'"]\s*:', re.M)
# 带壳标记（口径逐字抄 §四/§六）。
脚本带壳标记 = ("自门禁", "报告环境步")          # `.py` 入口脚本
外壳脚本带壳标记 = ("trap", "自门禁", "gate_report")  # `.sh` 入口脚本

# 走树时的排除：按**相对路径**排（不是按目录名 —— 免得误伤将来别处同名目录）。
走树排除路径 = (
    ".git", "__pycache__", "node_modules", "target",
    "只读参考", "构建环境/构建缓存", "构建环境/cargo", "构建环境/python",
)


def _排掉(相对根: str, 名称: str) -> bool:
    路径 = f"{相对根}/{名称}" if 相对根 not in ("", ".") else 名称
    return 路径 in 走树排除路径 or 名称 in (".git", "__pycache__", "node_modules", "target")


# 走树读数在一次运行里不变（同一条判据的对象数与判定各取一次）⇒ 按仓根缓存。
# 键是**绝对路径**：`--自测` 每个夹具一个独立临时目录 ⇒ 不会串。
_入口面缓存: dict = {}


def 扫入口(仓根: Path) -> dict:
    """走树取入口 ⇒ `{相对路径: 文本}`（`.py` 有行首 `__main__` 才算入口；`.sh` 一律算）。"""
    键名 = str(仓根)
    if 键名 in _入口面缓存:
        return _入口面缓存[键名]
    输出缓冲 = {}
    for 根目录, 目录表, 文件表 in os.walk(仓根):
        相对根 = os.path.relpath(根目录, 仓根).replace(os.sep, "/")
        目录表[:] = [目录名 for 目录名 in 目录表 if not _排掉(相对根, 目录名)]
        for 名称 in sorted(文件表):
            if not (名称.endswith(".py") or 名称.endswith(".sh")):
                continue
            路径 = Path(根目录) / 名称
            try:
                文本 = 路径.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            if 名称.endswith(".py") and not 主入口模式.search(文本):
                continue
            输出缓冲[相对(仓根, 路径)] = 文本
    _入口面缓存[键名] = 输出缓冲
    return 输出缓冲


def 带壳(路径: str, 文本: str) -> bool:
    """这条入口带壳吗（口径逐字抄 §四/§六）。"""
    标记 = 外壳脚本带壳标记 if 路径.endswith(".sh") else 脚本带壳标记
    return any(关键词 in 文本 for 关键词 in 标记)


def 读白名单(仓根: Path) -> tuple:
    """读被扫仓的入口白名单 ⇒ `({路径: (类, 理由)}, 错误或 None)`。"""
    节点件 = 仓根 / 入口白名单路径
    if not 节点件.is_file():
        return {}, f"白名单文件不存在（{入口白名单路径}）"
    try:
        数据 = json.loads(节点件.read_text(encoding="utf-8"))
    except Exception as 错误:
        return {}, f"白名单解析不了（{type(错误).__name__}）"
    项表 = {}
    for 一条 in 数据.get("白名单") or []:
        try:
            项表[str(一条["路径"])] = (str(一条["类"]), str(一条["理由"]))
        except (KeyError, TypeError):
            return {}, f"白名单条目形状不对（{一条!r}）—— 要 路径/类/理由 三键"
    return 项表, None


def 样本_入口面(上层读数: dict) -> int:
    """对象数：扫到的入口数（0 ⇒ 未判）。"""
    return len(扫入口(上层读数["仓根"]))


def 检查24_入口覆盖面(上层读数: dict) -> list:
    """每个能跑完的入口要么带壳、要么在边界白名单里（§四/§六）。

    三元读数：**通过** = 入口面非空且全部带壳/在白名单里；**失败** = 逐条报出漏网入口
    （含白名单里的陈旧登记）；**未判** = 白名单读不到、或入口面为空。
    """
    输出缓冲 = []
    仓根 = 上层读数["仓根"]
    白名单, 错 = 读白名单(仓根)
    if 错:
        return [
            违规(
                检查名[23],
                入口白名单路径,
                错,
                "边界白名单是本条判据的唯一依据（「要么带壳、要么在边界白名单里」）——"
                "没有它，所有边界入口都会被算成「漏了壳」⇒ 当场红一片，等于没上闸。"
                "白名单随被扫仓走（同 行数基线/命名基线 的形状）⇒ 只能由维护方补",
            )
        ]
    入口 = 扫入口(仓根)
    if not 入口:
        判不了(
            检查名[23],
            "全仓 `.py`（行首 `if __name__ == \"__main__\"`）+ 全部 `.sh`",
            "扫到 0 个入口（扫描面或入口口径坏了）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一条入口都没有的仓，"
            "本条判据什么都没验 ⇒ 只能由判据作者确认走树排除与入口口径",
        )
        return 输出缓冲

    for 键名 in sorted(入口):
        if 带壳(键名, 入口[键名]) or 键名 in 白名单:
            continue
        输出缓冲.append(
            违规(
                检查名[23],
                键名,
                "这条入口能跑完，却既没带壳、也不在边界白名单里",
                "决策记录 2026-09-27_构建段归环境步.md §六：能跑完的入口要么带壳自门禁"
                "（`.py` 含 `自门禁`/`报告环境步`；`.sh` 含 `trap`/`自门禁`/`gate_report`），"
                "要么落在三类结构边界（永不返回 · 环境步 · 工具链本体）或 §四/§六 另点名的"
                "薄壳/自量里并**登记进白名单（带理由）**。漏了壳 = 这条命令的墙钟没人量，"
                "慢成 bug 也没人拦 ⇒ 只能由该入口的作者加壳（阈值与理由只从 `构建装配/门禁/` 取）"
                "或在白名单里登记它为什么不必带壳",
            )
        )

    # ── 白名单里不许留**陈旧登记**（同判据 ⑲/㉒ 的口径）──
    # 一条登记若已不是入口（改名/删掉/已带壳），它自身就成了「只增不减」的反面：读白名单的人
    # 看到的是历史而不是现状，而且它白占一格（把一条本该带壳的入口提前豁免）。
    for 键名 in sorted(白名单):
        if 键名 not in 入口:
            类, 理由 = 白名单[键名]
            输出缓冲.append(
                违规(
                    检查名[23],
                    键名,
                    f"白名单登记着「{类}」，而实测这一件**已经不是入口**（不在扫描面里）"
                    f"⇒ **陈旧登记**",
                    "决策记录 2026-09-27_构建段归环境步.md §六：白名单是「按设计不必带壳」的"
                    "声明，不是永久豁免。改名/删除/已加壳之后就把它删掉 —— 留着它，白名单读数"
                    "就不再是现状（读的人会以为这个边界还在），而且它白占一格豁免 ⇒ "
                    f"只能由维护方改（{入口白名单路径}）",
                )
            )
    return 输出缓冲
