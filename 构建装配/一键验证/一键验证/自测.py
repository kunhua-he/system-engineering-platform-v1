def 跑自测(源仓根: Path) -> int:
    """逐条判据跑「反向样本 + 正向样本」，并给出每条的身份证。"""
    import tempfile

    print("自测：逐条判据的身份证（反向样本必须报红且报对位置；正向样本必须通过）")
    print("")
    全过 = True
    命中表 = {}

    # ── 反向样本：注入到干净合成仓 ──
    # 77 条**互相独立**（各自一个临时夹具）⇒ 走 fork 进程池；**收集后按原序打印**
    # （判定、断言条数、打印格式、退出码语义一条不改）。
    for 单元果 in 并行执行(_跑反向样本, list(range(len(自测用例))), 自测档位):
        for 文本行 in 单元果["行表"]:
            print(文本行)
        全过 = 全过 and 单元果["这轮过"]
        命中表[单元果["该报的检查"]] = 命中表.get(单元果["该报的检查"], 0) + (1 if 单元果["有命中位置"] else 0)

    # ── 正向样本：干净合成仓，不注入 ⇒ 所有判据必须通过 ──
    # ⑱（命令墙钟）读的是「验证.起始时刻 → 此刻」，而 起始时刻 是模块导入那一刻
    # ⇒ 不重置的话，这里量到的是**整条 `--自测` 进程的年龄**，而不是「一条新命令」的耗时
    # （本机负载一高就假红）。与 `自检_延迟与两遍._挪进程起点到此刻` 同口径：挪到此刻再跑。
    with tempfile.TemporaryDirectory(prefix="一键验证正向样本-") as 临时目录:
        临根 = Path(临时目录) / "仓"
        造干净仓(临根)
        验证模块, 原起 = _挪进程起点到此刻()
        try:
            判定汇总 = 跑全量判据(临根)
        finally:
            验证模块.起始时刻 = 原起
    正过 = not 判定汇总["失败"] and not 判定汇总["未判"]
    全过 = 全过 and 正过
    print(f"【正向样本·干净合成仓】不注入任何东西    结果：{'过' if 正过 else '不过'}")
    print(
        f"  通过 {len(判定汇总['通过'])} 项 · 失败 {len([明细条 for 明细条 in 判定汇总['失败'] if isinstance(明细条, str)])} 项 · "
        f"未判 {len([明细条 for 明细条 in 判定汇总['未判'] if isinstance(明细条, str)])} 项 · "
        f"疑似瞬时 {len(判定汇总['疑似瞬时'])} 项"
    )
    if not 正过:
        for 明细项 in [明细条 for 明细条 in 判定汇总["失败"] + 判定汇总["未判"] if isinstance(明细条, dict)][:6]:
            print(f"  ✗ 干净输入上仍报：{明细项['检查']} ｜ {明细项['位置']} ｜ 缺什么：{明细项['缺什么'][:160]}")
    print("")

    # ── 判据器自身机制的身份证：解析器也要有反向样本（判据的可信性.md §三.5）──
    # 29 条断言互相独立 ⇒ fork 进程池；**回显与异常都带回父进程**，故顺序与格式与旧版逐字一致，
    # 且**一条断言都不会因并行被吞掉**（异常照抛 ⇒ 退出码语义不变）。
    print("判据器自身机制（判据的解析器也是假绿来源，所以它自身也要有身份证）：")
    # 两类批**依次跑**（不叠在一起）：两类批各自还会起子进程，叠起来会把 32 核超订
    # ⇒ 门禁类那批里带 5 秒 `timeout` 的单元必假红（实测：两批同跑时 load 顶到 46，
    # red 四条；叠起来只快 4 s，却把「假红重跑」的代价又请回来了）。
    # 依次跑的代价就是把两段相加，但两段各自都是真并行 ⇒ 比原来单核串行 112.6 s 仍是一个数量级。
    机制果表 = [None] * len(机制单元表)
    门禁序号表 = [序号 for 序号, 单元函数 in enumerate(机制单元表) if 单元函数 in 门禁类单元]
    其余序号表 = [序号 for 序号, 单元函数 in enumerate(机制单元表) if 单元函数 not in 门禁类单元]
    for 单元果 in 并行执行(_跑机制单元, 门禁序号表, 门禁类档位):
        机制果表[单元果["序号"]] = 单元果
    for 单元果 in 并行执行(_跑机制单元, 其余序号表, 自测档位):
        机制果表[单元果["序号"]] = 单元果
    机制用例 = []
    for 单元果 in 机制果表:
        if 单元果["回显"]:
            print(单元果["回显"], end="")
        if 单元果["异常"] is not None:
            raise RuntimeError("判据器自身机制第 %d 条异常：%s" % (单元果["序号"] + 1, 单元果["异常"]))
        机制用例.extend(单元果["结果"])
    for 名称, 是否好, 说明 in 机制用例:
        全过 = 全过 and 是否好
        print(f"  {'✓' if 是否好 else '✗'} {名称}")
        print(f"      {说明}")
    print("")

    # ── 身份证总表：每条判据都必须有反向样本与正向样本 ──
    print("判据身份证（每条判据 反向样本 + 正向样本）：")
    缺证 = []
    for 名称, _函数 in 判据表.检查表:
        元数据 = 判据元数据.get(名称, {})
        反向样本 = 元数据.get("反向样本")
        正向样本 = 元数据.get("正向样本")
        有反 = bool(反向样本) and 反向样本 in {用例条[0] for 用例条 in 自测用例}
        有正 = bool(正向样本) and 正向样本 == "干净合成仓"
        if not (有反 and 有正):
            缺证.append(名称)
        print(f"  {'✓' if (有反 and 有正) else '✗'} {名称}")
        print(f"      反向样本：{反向样本 or '（无）'}    正向样本：{正向样本 or '（无）'}")
    if 缺证:
        全过 = False
        print(f"  缺身份证的判据：{缺证}")
    print("")
    print(
        f"自测{'全部通过' if 全过 else '有不过的用例'}："
        f"{len(自测用例)} 个反向样本 + 1 个正向样本 · "
        f"判据器自身机制 {len(机制用例)} 条断言"
    )
    return 0 if 全过 else 1


def _跑反向样本(序号: int) -> dict:
    """一个反向样本的完整判定（**整段跑在子进程里**：临时目录 · 注入 · 只跑目标判据）。

    返回全是朴素值（可 pickle）：`序号` / `该报的检查` / `行表`（要打印的逐行）/
    `这轮过` / `有命中位置`。**打印留在父进程** ⇒ 77 条的顺序与格式逐字不变。
    """
    名称, 该报的检查, 注入, 该出现的路径 = 自测用例[序号]
    with tempfile.TemporaryDirectory(prefix="一键验证反向样本-") as 临时目录:
        临根 = Path(临时目录) / "仓"
        造干净仓(临根)
        原硬顶 = 常量.硬顶毫秒  # 注入可能临时改坏它 ⇒ 本轮结束必须还原
        原护栏 = 墙钟采样.失控护栏毫秒  # ⑱ 的判决线：`注入_硬顶失效` 压的是它
        判定汇总 = 注入(临根)
        元数据覆盖 = 判定汇总 if isinstance(判定汇总, dict) else None
        try:
            # `只跑`：反向样本只需证「**这一条**判据抓得住」，跑全量 37 条是浪费
            # （60 条样本 × 37 条会把 `--自测` 顶过五秒硬顶，实测 7.4 s ⇒ ⑱ 假红）。
            判定汇总 = 跑全量判据(临根, 元数据覆盖=元数据覆盖, 只跑={该报的检查})
        finally:
            常量.硬顶毫秒 = 原硬顶
            墙钟采样.失控护栏毫秒 = 原护栏
    退出码 = 0 if not 判定汇总["失败"] else 1
    条表 = [明细项 for 明细项 in (判定汇总["失败"] + 判定汇总["未判"]) if isinstance(明细项, dict)]
    命中 = [明细项 for 明细项 in 条表 if 明细项["检查"] == 该报的检查]
    命中位置 = [明细项 for 明细项 in 命中 if 该出现的路径 in 明细项["位置"] or 该出现的路径 in 明细项["缺什么"]]
    理由合格 = [
        明细项
        for 明细项 in 命中位置
        if len(明细项["不能自愈"]) >= 30 and not any(空话 in 明细项["不能自愈"] for 空话 in 空话表)
    ]
    断言 = [
        ("① 退出码非 0", 退出码 != 0),
        (f"② 报出「{该报的检查}」且指到 {该出现的路径}", bool(命中位置)),
        ("③ 理由具体（≥30 字 · 不含空话）", bool(理由合格)),
    ]
    这轮过 = all(是否好 for _, 是否好 in 断言)
    行表 = [f"【反向样本·{名称}】→ {该出现的路径}    结果：{'过' if 这轮过 else '不过'}"]
    行表 += [f"  {'✓' if 是否好 else '✗'} {断言名}" for 断言名, 是否好 in 断言]
    行表 += [
        f"  - {明细项['检查']} ｜ {明细项['位置']} ｜ 缺什么：{明细项['缺什么'][:120]} ｜ "
        f"分类：{明细项.get('分类')}"
        for 明细项 in 命中位置[:2]
    ]
    if not 命中位置:
        行表.append("  实际：该判据没有报出这一条（断言②失败）")
    行表.append("")
    return {
        "序号": 序号,
        "该报的检查": 该报的检查,
        "行表": 行表,
        "这轮过": 这轮过,
        "有命中位置": bool(命中位置),
    }


def _跑机制单元(序号: int) -> dict:
    """一条「判据器自身机制」断言（整段跑在子进程里；**回显留父进程按原序打印**）。"""
    import contextlib
    import io

    回显 = io.StringIO()
    try:
        with contextlib.redirect_stdout(回显):
            机制果 = 机制单元表[序号]()
        return {"序号": 序号, "结果": 机制果, "回显": 回显.getvalue(), "异常": None}
    except BaseException as 错误:
        return {"序号": 序号, "结果": [], "回显": 回显.getvalue(), "异常": "%r" % (错误,)}
