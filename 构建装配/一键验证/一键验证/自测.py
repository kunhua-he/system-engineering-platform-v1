# ① `门禁类单元` —— **单元内部带 `subprocess.run(timeout=…)`**（据 5 秒）或再起一批子进程
#    （真 git 合并夹具 / 门禁），而且**各自内部就把核占满**（`长样本` 内部又起 6 套件，其中
#    `合主干回归` 再起 12 单元）。⇒ 并发一高，外层调度抖动就把那个 5 秒吃掉 ⇒ 报
