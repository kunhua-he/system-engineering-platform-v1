"""自测：逐条判据的身份证（反向样本 + 正向样本）。"""

from __future__ import annotations

import tempfile
from pathlib import Path

from . import 常量, 判据表

from .判据元数据 import 判据元数据
from .判据表 import 检查表
from .合成仓 import 造干净仓
from .常量 import 硬顶毫秒, 空话表
from .自检_临时件 import 自检_临时件排除承重
from .自检_前端 import 自检_前端内联脚本, 自检_前端语义判据
from .自检_夹具与拓扑 import 自检_拓扑判据收窄, 自检_整份夹具跳过
from .自检_延迟与两遍 import 自检_两遍复核收窄, 自检_延迟判据承重
from .自检_词法 import 自检_剥字面量剥序, 自检_并行生产区上下文
from .自检_命名 import 自检_命名扫描
from .自检_命名穷举 import 自检_命名穷举三面
from .自检_引用 import 自检_引用扫描
from .自检_十干 import 自检_十干扫描
from .判据_运行数据 import 自检_运行数据扫描
from .判据_超时 import 自检_超时扫描
from .判据_台账号 import 自检_台账号扫描
from .自测用例 import 自测用例
from .退出码 import 自检_退出码语义
from .验证 import 跑全量判据


def 自测(源仓根: Path) -> int:
    """逐条判据跑「反向样本 + 正向样本」，并给出每条的身份证。"""
    import tempfile

    print("自测：逐条判据的身份证（反向样本必须报红且报对位置；正向样本必须通过）")
    print("")
    全过 = True
    命中表 = {}

    # ── 反向样本：注入到干净合成仓 ──
    for 名称, 该报的检查, 注入, 该出现的路径 in 自测用例:
        with tempfile.TemporaryDirectory(prefix="一键验证反向样本-") as 临时:
            临根 = Path(临时) / "仓"
            造干净仓(临根)
            原硬顶 = 常量.硬顶毫秒  # 注入可能临时改坏它（注入_硬顶失效）⇒ 本轮结束必须还原
            结果 = 注入(临根)
            元数据覆盖 = 结果 if isinstance(结果, dict) else None
            try:
                # `只跑`：反向样本只需证「**这一条**判据抓得住」，跑全量 37 条是浪费
                # （60 条样本 × 37 条会把 `--自测` 顶过五秒硬顶，实测 7.4 s ⇒ ⑱ 假红）。
                结果 = 跑全量判据(临根, 元数据覆盖=元数据覆盖, 只跑={该报的检查})
            finally:
                常量.硬顶毫秒 = 原硬顶
            退出码 = 0 if not 结果["失败"] else 1
            条表 = [一条 for 一条 in (结果["失败"] + 结果["未判"]) if isinstance(一条, dict)]
            命中 = [一条 for 一条 in 条表 if 一条["检查"] == 该报的检查]
            命中位置 = [一条 for 一条 in 命中 if 该出现的路径 in 一条["位置"] or 该出现的路径 in 一条["缺什么"]]
            理由合格 = [
                一条
                for 一条 in 命中位置
                if len(一条["不能自愈"]) >= 30 and not any(空话 in 一条["不能自愈"] for 空话 in 空话表)
            ]
            断言 = [
                ("① 退出码非 0", 退出码 != 0),
                (f"② 报出「{该报的检查}」且指到 {该出现的路径}", bool(命中位置)),
                ("③ 理由具体（≥30 字 · 不含空话）", bool(理由合格)),
            ]
            这轮过 = all(是否好 for _, 是否好 in 断言)
            全过 = 全过 and 这轮过
            命中表[该报的检查] = 命中表.get(该报的检查, 0) + (1 if 命中位置 else 0)
            print(f"【反向样本·{名称}】→ {该出现的路径}    结果：{'过' if 这轮过 else '不过'}")
            for 名目, 是否好 in 断言:
                print(f"  {'✓' if 是否好 else '✗'} {名目}")
            for 一条 in 命中位置[:2]:
                print(
                    f"  - {一条['检查']} ｜ {一条['位置']} ｜ 缺什么：{一条['缺什么'][:120]} ｜ "
                    f"分类：{一条.get('分类')}"
                )
            if not 命中位置:
                print("  实际：该判据没有报出这一条（断言②失败）")
            print("")

    # ── 正向样本：干净合成仓，不注入 ⇒ 所有判据必须通过 ──
    with tempfile.TemporaryDirectory(prefix="一键验证正向样本-") as 临时:
        临根 = Path(临时) / "仓"
        造干净仓(临根)
        结果 = 跑全量判据(临根)
    正过 = not 结果["失败"] and not 结果["未判"]
    全过 = 全过 and 正过
    print(f"【正向样本·干净合成仓】不注入任何东西    结果：{'过' if 正过 else '不过'}")
    print(
        f"  通过 {len(结果['通过'])} 项 · 失败 {len([明细条 for 明细条 in 结果['失败'] if isinstance(明细条, str)])} 项 · "
        f"未判 {len([明细条 for 明细条 in 结果['未判'] if isinstance(明细条, str)])} 项 · "
        f"疑似瞬时 {len(结果['疑似瞬时'])} 项"
    )
    if not 正过:
        for 一条 in [明细条 for 明细条 in 结果["失败"] + 结果["未判"] if isinstance(明细条, dict)][:6]:
            print(f"  ✗ 干净输入上仍报：{一条['检查']} ｜ {一条['位置']} ｜ 缺什么：{一条['缺什么'][:160]}")
    print("")

    # ── 判据器自身机制的身份证：解析器也要有反向样本（判据的可信性.md §三.5）──
    print("判据器自身机制（判据的解析器也是假绿来源，所以它自身也要有身份证）：")
    机制用例 = (
        自检_剥字面量剥序()
        + 自检_命名扫描()
        + 自检_命名穷举三面()
        + 自检_运行数据扫描()
        + 自检_超时扫描()
        + 自检_台账号扫描()
        + 自检_引用扫描()
        + 自检_十干扫描()
        + 自检_整份夹具跳过()
        + 自检_拓扑判据收窄()
        + 自检_前端语义判据()
        + 自检_前端内联脚本()
        + 自检_临时件排除承重()
        + 自检_并行生产区上下文()
        + 自检_延迟判据承重()
        + 自检_两遍复核收窄()
        + 自检_退出码语义()
    )
    for 名称, 是否好, 说明 in 机制用例:
        全过 = 全过 and 是否好
        print(f"  {'✓' if 是否好 else '✗'} {名称}")
        print(f"      {说明}")
    print("")

    # ── 身份证总表：每条判据都必须有反向样本与正向样本 ──
    print("判据身份证（每条判据 反向样本 + 正向样本）：")
    缺证 = []
    for 名称, _函数 in 判据表.检查表:
        元数据 = 判据元数据.get(名称, {})
        反向样本 = 元数据.get("反向样本")
        正向样本 = 元数据.get("正向样本")
        有反 = bool(反向样本) and 反向样本 in {用例条[0] for 用例条 in 自测用例}
        有正 = bool(正向样本) and 正向样本 == "干净合成仓"
        if not (有反 and 有正):
            缺证.append(名称)
        print(f"  {'✓' if (有反 and 有正) else '✗'} {名称}")
        print(f"      反向样本：{反向样本 or '（无）'}    正向样本：{正向样本 or '（无）'}")
    if 缺证:
        全过 = False
        print(f"  缺身份证的判据：{缺证}")
    print("")
    print(
        f"自测{'全部通过' if 全过 else '有不过的用例'}："
        f"{len(自测用例)} 个反向样本 + 1 个正向样本 · "
        f"判据器自身机制 {len(机制用例)} 条断言"
    )
    return 0 if 全过 else 1
