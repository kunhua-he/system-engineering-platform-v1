# 档 E：`_` + 一个非下划线字符（模块私有单字）—— 旧的「单字」两档只卡 `len == 1`，
# 长 2 的 `_判` 静默绕过，故单开一档。`fullmatch` 而非 `search`：**整名**才是它。
单字私有式 = re.compile(r"_[^_]")
# 档 F：整名 = 数词 + 量词（说「几个」不说「是什么」）。`元` 不在量词里 ⇒ `一元`/`二元` 不误伤。
数量代称式 = re.compile(r"[一二三四五六七八九十两几多单双半](条|项|段|个|种类次处份件块张组对列步层遍批轮期边端方位)")


def 定义面两档(名称: str) -> str:
    """名的**形态** ⇒ 档 E / 档 F 的档名（都不匹配 ⇒ 空串）。

    两档都只吃**名本身**，不看上下文 —— 所以它们是**零歧义**的：要么整名就是个数量代称，
    要么不是。要判「泛不泛」（`解析` 那类）得读代码，形状判不出来（那是另一条路，不在本判据）。
    """
    if 单字私有式.fullmatch(名称):
        return 档_下划线单字
    if 数量代称式.fullmatch(名称):
        return 档_数量代称
    return ""
