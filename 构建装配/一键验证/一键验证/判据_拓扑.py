# -*- coding: utf-8 -*-
"""判据 ⑪：拓扑唯一性（每类出入口恰好一个）。"""

from __future__ import annotations

import re

from . import 常量

from .Rust文本 import 载入调用点
from .小工具 import 判不了, 相对, 违规
from .常量 import Rust后缀, 代码后缀, 公共底层, 前端逻辑模式, 对外边界符号, 层序, 层相邻下层, 接缝符号, 检查名, 监听模式, 资源出入口形
from .测试件 import 并行生产区, 收集导出
from .读文件 import 路径到层


def 检查11_拓扑唯一性(上: dict) -> list:
    """每类出入口恰好一个（项目文档/设计文档/全局连接器与网关.md 第四节）。

    六条子判据。判不了的**如实报「判不了 + 缺什么」**，不许写成判过了。
    """
    出 = []
    仓根 = 上["仓根"]
    文件 = 上["文件"]
    # 代码后缀 用模块级那一份（一个地方定义）——原来这里是第二份，实测差点漂移。

    # 生产区文本（去掉 #[cfg(test)] 区）——夹具不算平台代码。
    # 另排除 构建装配/ 与 开发工具/：README 第六节写明「构建装配 只读契约、只收扩展，
    # **不参与运行**」，验证器与生成器是开发期工具，不是平台运行时的一条腿。
    跳过工具目录 = ("构建装配/", "开发工具/")
    扫描件源 = [
        (键, 项["文本"])
        for 键, 项 in 文件.items()
        if 键.endswith(代码后缀)
        and 项["文本"] is not None
        and not 键.startswith(跳过工具目录)
    ]
    # Rust 类子判据（1/2/3/4/5）只收 `.rs`（未完成事项.md #37）；判据 6 是前端类，另起一份。
    扫描件源_rs = [项 for 项 in 扫描件源 if 项[0].endswith(Rust后缀)]
    代码件 = 并行生产区(扫描件源_rs, 上["测试文件集"])

    def 命中处(模式, 件表=None):
        处 = []
        for 键, 文本 in (代码件 if 件表 is None else 件表).items():
            for 命 in 模式.finditer(文本):
                处.append(f"{键}:{文本[: 命.start()].count(chr(10)) + 1}")
        return 处

    def 命中位置(标目: str, 处表: list) -> str:
        """位置字段：有命中就列出来（「哪个文件」要落在位置里），没有就给标目。"""
        if not 处表:
            return f"全仓代码:{标目}"
        return f"全仓代码:{标目}（命中 {len(处表)} 处：{' · '.join(处表)}）"

    # ── 1 对外监听恰好 1 处 ──
    监听 = 命中处(监听模式)
    if len(监听) != 1:
        情形 = (
            "一处都没有 ⇒ 不是「多了一条腿」，是「腿还没接上」（全局网关 尚未落地）"
            if not 监听
            else f"多出来的就是第二条腿：{监听[1:]}"
        )
        出.append(
            违规(
                检查名[10],
                命中位置("对外监听", 监听),
                f"对外监听 {len(监听)} 处（判据要求恰好 1 处）——{情形}",
                f"全局连接器与网关 第四节判据 1：对外监听是可数的出入口，必须恰好 1 个。"
                f"验证面不能替网关写一个监听点（那就是第二套实现）⇒ 只能由接口面节点落地；"
                f"若确实多了一处，摘掉哪一处是拓扑裁决 ⇒ 只能人来裁",
            )
        )

    # ── 2a 宿主侧「对外边界」恰好 1 组（三个符号；接缝 GetPlatformInfo 不算）──
    #     导出符号名写在字符串里 ⇒ 这一处必须用**保串**的生产区文本
    导出表 = 收集导出(并行生产区(扫描件源_rs, 上["测试文件集"], 保串=True))
    对外名 = sorted(名 for 名 in 导出表 if 名 != 接缝符号)
    缺名 = [名 for 名 in 对外边界符号 if 名 not in 对外名]
    多名 = [名 for 名 in 对外名 if 名 not in 对外边界符号]
    if 缺名 or 多名:
        情形 = (
            f"一个都没导出 ⇒ 不是「多了一条腿」，是「腿还没接上」"
            f"（跨语言适配/适配器实现/ 只给了 Rust 安全入口，还没出 C ABI 面）"
            if not 对外名
            else f"多出来的就是第二条对外面：{多名}"
        )
        命中处表 = [处 for 名 in 多名 for 处 in 导出表.get(名, [])]
        出.append(
            违规(
                检查名[10],
                "全仓代码:宿主侧对外边界"
                + (f"（现有导出 {对外名}：{' · '.join(命中处表) or '位置未取到'}）" if 对外名 else ""),
                f"宿主侧对外边界符号 {len(对外名)} 个（判据要求恰好 1 组 = 三个："
                f"{(' · '.join(对外边界符号))}）：缺 {缺名 or '无'} · 多 {多名 or '无'}——{情形}",
                f"边界协议 第四节判据 1：对外边界是**三个符号**（读接口 / 调用 / 释放值），"
                f"不是一组同义词，也不含接缝 `{接缝符号}`（那是扩展 → 宿主方向，每个扩展各一个）。"
                f"少一个 ⇒ 那条腿还没接上；多一个 ⇒ 第二个对外面，等于给某语言开了专用通道"
                f"（开发规范 B5）。补或撤哪一处是拓扑裁决 ⇒ 只能由跨语言适配节点落地 / 人来裁",
            )
        )

    # ── 3 内核入口恰好 1 处调用 载入 ──
    #     只认**调用形**（定义 / 枚举变体声明 / **模式位解构**都不算）——收窄口径见 `载入调用点`。
    载入处 = []
    for 键, 文本 in 代码件.items():
        载入处 += [f"{键}:{行}" for 行 in 载入调用点(文本)]
    if len(载入处) != 1:
        情形 = (
            "一处都没有 ⇒ 内核入口还没被接上（网关 / 连接器 尚未落地）"
            if not 载入处
            else f"多出来的就是第二条腿：{载入处[1:]}"
        )
        出.append(
            违规(
                检查名[10],
                命中位置("载入 调用点", 载入处),
                f"调用内核入口 `载入` 的处数 {len(载入处)}（判据要求恰好 1 处）——{情形}",
                f"判据 3：读契约 → 建注册表 → 交控制权 这条路只能有一条。"
                f"第二条调用点就是绕过网关的第二条腿。验证面不能替它补一条（第二套实现）⇒ "
                f"只能由 对外接口面 / 跨语言适配 落地；撤哪一处是拓扑裁决 ⇒ 只能人来裁",
            )
        )

    # ── 4 资源出入口恰好 1 处 ──
    #     数的是**冻结访问形状的定义形**（不是一袋同义词）——形状见模块级 `资源出入口形`。
    资源处 = 命中处(资源出入口形)
    if len(资源处) != 1:
        情形 = (
            "一处都没有 ⇒ 资源网关口 尚未落地（资源那一侧的腿还没接上）"
            if not 资源处
            else f"多出来的就是第二条腿：{资源处[1:]}"
        )
        出.append(
            违规(
                检查名[10],
                命中位置("资源出入口", 资源处),
                f"资源唯一出入口（冻结访问形状）的定义处数 {len(资源处)}（判据要求恰好 1 处）——{情形}",
                f"判据 4：资源访问也只有一个出入口（资源网关口.md：资源声明 + 唯一出入口 + 默认拒绝）。"
                f"验证面不能替它写一个（第二套实现）⇒ 只能由资源网关口节点落地 ⇒ 只能由该节点补",
            )
        )

    # ── 5 层间边：不许跳层 · 不许反向（判据 5 已改：原「同一对层之间不许有两条边」是空转的）──
    包到层 = 上["包到层"]
    边表 = {}
    for 键, 文本 in 代码件.items():
        源层 = 路径到层(键)
        if not 源层:
            continue
        for 命 in re.finditer(r"(?m)^[ \t]*(?:pub[ \t]+)?use[ \t]+([A-Za-z_][\w]*)", 文本):
            目标包 = 命.group(1)
            目标层 = 包到层.get(目标包)
            if not 目标层:
                continue
            行号 = 文本[: 命.start()].count(chr(10)) + 1
            边表.setdefault((源层, 目标层), []).append(f"{键}:{行号}")
    for (源层, 目标层), 处表 in sorted(边表.items()):
        if 源层 == 目标层:
            continue  # 同层互依（`运行内核/` 内部各 crate）——**已裁：不算违规**
            # 依据 `决策记录/2026-09-27_判据口径十一条.md` §一：README 第六节把 `运行内核/`
            # 当一个层（只禁「依赖任何扩展」），`开发规范.md` B3 的「同层」指 `能力实现/`
            # 内部各能力 —— 两处说的不是同一个「同层」，按各自适用范围读，不合并。
        源序, 目标序 = 层序.get(源层), 层序.get(目标层)
        if 源序 is not None and 目标序 is not None and 目标序 > 源序:
            出.append(
                违规(
                    检查名[10],
                    f"层间边 {源层} → {目标层}（{' · '.join(处表)}）",
                    f"**反向依赖**：{源层} 依赖了上层 {目标层}",
                    f"README 第六节：单向、自下而上；边界协议与拓扑都要求方向自上层向下层。"
                    f"反向 import 会让下层依赖上层，编译期就成环，且「下层 import 上层」"
                    f"正是第二条腿的形状（全局连接器与网关 第四节判据 5）⇒ 只能人来裁",
                )
            )
            continue
        if 目标层 != 层相邻下层.get(源层) and 目标层 != 公共底层:
            出.append(
                违规(
                    检查名[10],
                    f"层间边 {源层} → {目标层}（{' · '.join(处表)}）",
                    f"**跳层**：{源层} 的直接下层是 "
                    f"{层相邻下层.get(源层) or '（无，它是最底层）'}，却依赖了 {目标层}",
                    f"全局连接器与网关 第四节判据 5：第二条腿的真身就是「跳过中间层」——"
                    f"前端直连内核、网关直连扩展实现都是跳层。"
                    f"（直接依赖 `{公共底层}` 不算跳层：它是两条链的公共底、自己没有依赖，"
                    f"README 第六节也把它列进了每一层的可依赖层。）"
                    f"改依赖方向是架构级改动；若这一条依赖其实该走中间层，"
                    f"补哪一层是拓扑裁决 ⇒ 只能人来裁",
                )
            )

    # ── 6 前端呈现 恰好 0 处解析 / 生成 / 校验逻辑 ──
    # **扫描面只收前端自己的语言**（裁决 2026-09-26 §7.1「判据不许跨语言借词法」）。
    # 实测机理：本判据用的 `去字面量` / `去注释保串` 认的是 `//` 与 `/* */`（Rust/JS 词法），
    # 而 Python 的注释是 `#` ⇒ **`.py` 里的注释永远剥不掉** ⇒ 注释里每个关键词都算命中。
    # 实测：`前端呈现/命令行界面/命令行界面.py` 报 8 处，其中 **4 处来自一条注释**
    # （那条注释写的正是「这里不解析、不校验」）——**话说得越清楚，判据越判你违规**。
    # 故 `.py` 不进本判据的扫描面（`.py` 是「前端呈现」的节点，但它是 HTTP 客户端的壳，
    # 判它的形状要用 Python 的读法，那是另一条判据的事）。
    # **先剥注释再扫**：`前端件` 是 `生产区文本(保串=假)` 的产物 ⇒ `//` 与 `/* */` 与字面量
    # 都已换成等长空格（长度不变 ⇒ 行号仍对齐）。`.js` 的注释词法与它认的同一套，剥得掉；
    # 这正是 2026-09-27 收窄的前提（判「有没有自己解析」之前，得先保证读的是**代码**）。
    前端件 = 并行生产区(
        [
            (键, 文本)
            for 键, 文本 in 扫描件源
            if 键.startswith("前端呈现/")
            and 键.endswith((".js", ".jsx", ".ts", ".tsx", ".vue", ".svelte"))
        ],
        上["测试文件集"],
    )
    # 扫描面还要含 `.html` 的**内联 `<script>`**（未完成事项.md #38）：
    # 外链脚本（`<script src=…>`）已由它自己的 `.js` 件覆盖，这里只取**内联体**。
    # 实测：`前端呈现/网页应用/index.html` 现在只有一条外链（`src="应用.js"`）、无内联 ⇒ 0 命中。
    内联脚本件 = {}
    for 路径 in sorted((仓根 / "前端呈现").rglob("*.html")):
        try:
            文 = 路径.read_text(encoding="utf-8")
        except OSError:
            continue
        体 = "\n".join(
            配.group(2)
            for 配 in re.finditer(r"<script\b([^>]*)>(.*?)</script>", 文, re.S | re.I)
            if "src" not in 配.group(1).lower()
        )
        if 体.strip():
            # 键上标注「（内联脚本体）」：报出的行号是**脚本体里**的行号，不是 `.html` 文件的行号
            # （多个 `<script>` 体拼在一起 ⇒ 与 html 行号不同）——位置必须诚实（判据的可信性.md #185 同理）。
            内联脚本件[f"{相对(仓根, 路径)}（内联脚本体）"] = 体
    if 内联脚本件:
        前端件 = {**前端件, **并行生产区(list(内联脚本件.items()), 上["测试文件集"])}
    前端命中 = 命中处(常量.前端逻辑模式, 前端件)
    if not 前端件:
        判不了(
            检查名[10],
            "前端呈现/",
            "扫描 0 个源文件——「恰好 0 处解析 / 生成 / 校验」在空集上恒真，"
            "判不了前端到底有没有逻辑",
            "判据的可信性.md 第二节：空集是「未判」，不是「通过」。"
            "前端落地不属验证面（验证面不写前端）⇒ 只能由 前端呈现 节点补",
        )
    elif 前端命中:
        出.append(
            违规(
                检查名[10],
                f"前端呈现/:解析·生成·校验（命中 {len(前端命中)} 处："
                f"{' · '.join(前端命中[:5])}）",
                f"前端目录里有 {len(前端命中)} 处解析 / 生成 / 校验逻辑：{前端命中[:5]}",
                f"判据 6：前端是纯 UI，零逻辑（全局连接器与网关 第二节）。"
                f"前端一旦自己解析或校验，就等于绕过网关直连声明 ⇒ 前端与网关两套判定必然漂移。"
                f"（`JSON.stringify` 这类**纯编码**不算——它不看内容、不改内容，是传输必需；"
                f"本判据只判「有没有对内容作出判断」。）"
                f"搬去哪一层是结构裁决 ⇒ 只能人来裁",
            )
        )
    return 出
