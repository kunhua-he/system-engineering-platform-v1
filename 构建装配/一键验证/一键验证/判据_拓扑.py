def 前端命中(文本: str) -> list:
    """前端件里「真解析 / 动态求值 / 判断动词的调用形」的命中处（⑪-6 的**同一个**语义判）。

    输入是**已剥过字面量**的净文（`生产区文本(保串=假)`）—— 注释 / 字符串 / **正则字面量**
    都已在剥离层换成等长空格（`剥字面量._剥` 认 `／…／flags`）。所以正则字面量里的
    `JSON.parse(` 字样**不会**被当成真调用（实测旧行为：`const 形 = /JSON.parse(/;`
    报出 `JSON.parse`）。

    两支合成一处（按字符区间重叠去重，保持出现顺序）：
      · `常量.前端逻辑模式` —— 真解析 / 动态求值 / 判断动词调用形；
      · `命名扫描.扫正则字面量` —— 兜底（对**未剥**的文本也安全）：净文里正则字面量已剥空，
        故本支通常为空；留着它是为了「本函数拿到原始文本时不会把字面量里的字样当调用」。

    **诚实登记的残余**：紧跟 `)` 的裸 `/…/`（语句位，如 `if (条件) /JSON.parse(/;`）里那个**未转义**
    的 `JSON.parse(` 字样仍是假红 —— 该位置与 `(a) / b` 除法同形，剥它会错剥真除法（最坏的假阴性），
    宁可收窄（口径：`决策记录/2026-09-27_判据口径十一条.md` §三）。身份证见 `自检_前端.py`。
    """
    区段 = [(命.start(), 命.end(), 命.group(0)) for 命 in 常量.前端逻辑模式.finditer(文本)]
    区段 += [(位, 位 + len(文), 文) for 位, 文 in 扫正则字面量(文本)]
    输出缓冲 = []
    止于 = -1
    for 区间起点, 区间终点, 文本 in sorted(区段):
        if 区间起点 < 止于:
            continue  # 与上一处重叠 ⇒ 同一处被两支都认出来了，只报一次
        输出缓冲.append(文本)
        止于 = 区间终点
    return 输出缓冲


def 命中处前端(件表: dict) -> list:
    """前端件表 ⇒ `["路径:行号"]`（⑪-6 的命中位置；口径与 `前端命中` 同一处）。"""
    命中处表 = []
    for 键名, 文本 in 件表.items():
        for 命中文字 in 前端命中(文本):
            位置 = 文本.find(命中文字)
            行号 = (文本[:位置].count(chr(10)) + 1) if 位置 >= 0 else 0
            命中处表.append(f"{键名}:{行号}")
    return 命中处表


