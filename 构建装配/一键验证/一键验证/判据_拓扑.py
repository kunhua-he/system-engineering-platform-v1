    # 实测：`前端呈现/命令行界面/命令行界面.py` 报 8 处，其中 **4 处来自一条注释**
    # （那条注释写的正是「这里不解析、不校验」）——**话说得越清楚，判据越判你违规**。
    # 故 `.py` 不进本判据的扫描面（`.py` 是「前端呈现」的节点，但它是 HTTP 客户端的壳，
    # 判它的形状要用 Python 的读法，那是另一条判据的事）。
