def 建测试文件集(文件: dict) -> set:
    """整文件都是测试的 .rs —— 口径：**路径在测试面即算**。

    判法：某份 .rs 被一条 `#[cfg(test)]`（可含别的 cfg 条件）属性引出的 `mod` 项挂进来
    ⇒ 它整份是夹具。内联 `mod 名 { … }` 引出的**自挂**（目标 = 父文件自身）只有在**文件自身
    在测试面**（路径段含 `tests`，= cargo 集成测试目标）时才算 —— 实测
    `对外接口面/调用接口面/tests/整条HTTP.rs` 自带 `#[cfg(test)] mod 整条HTTP {`（模块名与
    文件同名 ⇒ 自挂），它在 `tests/` 下，必须收（此前本件跳内联 ⇒ 漏判）；而生产件里的内联
    同名 mod **不许**把该件整份算作夹具（否则真代码从实现面消失）。

    ★ 同一事实只有一份实现（本件）；闸 2 侧 `测试验证/契约一致性/扫实现/夹具判定.py::建夹具集`
      的「整份夹具」直接 import 本函数（闸2→闸1 是既有合法方向），那边不再另算一份。

    为什么要它：夹具常被拆成单独文件（`#[cfg(test)] #[path = "测试夹具.rs"] mod 测试夹具;`），
    文件**自身**没有 `#[cfg(test)]` 属性 ⇒ 只看文件内会把它当生产代码（实测撞到过）。

    口径细节（真仓实测）：
      · 父文件可以是**任意一个 .rs**——实测撞到过 `装载测试.rs` 由同目录兄弟 `装载.rs`
        挂进来，不是 lib.rs/mod.rs/main.rs 挂的；
      · `#[path = "…"]` 与 `mod 名;` 都**相对父文件所在目录**解析 ⇒ 目标可以在子目录里、
        名字也可以与 mod 名不同——实测撞到过 `容器.rs` 用 `#[path = "容器/测试.rs"] mod 测试;`
        把 `容器/测试.rs` 挂进来（只按「同目录 + 同名」找会把这一份当生产代码 ⇒ 假红）；
      · `#[path]` 写在 `#[cfg(test)]` 之前也合法；cfg 条件里可以嵌括号
        （`#[cfg(any(test, feature = "x"))]`）——两种形状都要认；
      · **父文件本身是夹具的，它的 mod 声明不算数**（两趟不动点）：夹具文件内部的
        `#[cfg(test)] mod …;` 是测试内部的事，不该把第三份文件也拖进集合；
      · `mod lib;` / `mod mod;` / `mod main;` 不是 Rust 能编的形状 ⇒ 包根不算夹具。
    """
    # 一遍预扫：把每份 .rs 的挂载声明解析成「(父角色, 父目录, 相对父文件目录的目标路径)」。
    # 注意 `#[path = "…"]` 的值写在字符串里 ⇒ 去字面量会把它抹成空白，必须回**原文**取引号内内容。
    挂载 = []
    for 父键, 文件项 in 文件.items():
        if not 父键.endswith(".rs") or 文件项["文本"] is None:
            continue
        净文本 = 去字面量(文件项["文本"])
        原文 = 文件项["文本"]
        父目录 = 父键.rsplit("/", 1)[0] if "/" in 父键 else ""
        for 命中 in _夹具挂载形.finditer(净文本):
            属性 = _条件编译属性(净文本, 命中.start())
            if 属性 is None:
                continue
            属性文本, 属止 = 属性
            if not re.search(r"\btest\b", 属性文本):
                continue
            # 项头：从 cfg 属性之后扫到第一个 `{` 或 `;`（`{` 是内联块，照样算一条挂载声明）
            区间终点 = 属止
            while 区间终点 < len(净文本) and 净文本[区间终点] not in "{;":
                区间终点 += 1
            if 区间终点 >= len(净文本):
                continue
            名配 = re.search(r"\bmod\s+([^\s;{]+)", 净文本[属止:区间终点])
            if not 名配:
                continue
            路径 = None
            # `#[path = "…"]` 可以写在 cfg 之前，也可以写在 cfg 之后（属性顺序不影响语义）
            窗起 = _属性窗口起(净文本, 命中.start())
            for 路命 in re.finditer(r"#\[\s*path\b", 净文本[窗起:区间终点]):
                引号符 = 原文.find('"', 窗起 + 路命.end(), 区间终点)
                if 引号符 >= 0:
                    终引 = 原文.find('"', 引号符 + 1)
                    if 终引 > 引号符:
                        路径 = 原文[引号符 + 1 : 终引]
                        break
            if 路径 is None:
                路径 = 名配.group(1) + ".rs"
            挂载.append((父键, 父目录, 路径))
    整份 = set()
    # 两趟不动点：先按「父文件不是夹具文件」收集；父文件本身是夹具的，它的 mod 声明不算数。
    for _ in range(2):
        新内容 = set()
        for 父角色, 父目录, 路径 in 挂载:
            if 父角色 in 整份:
                continue
            备选路径 = f"{父目录}/{路径}" if 父目录 else 路径
            备选路径 = os.path.normpath(备选路径).replace("\\", "/")
            待定 = [备选路径]
            if 备选路径 not in 文件 and 备选路径.endswith(".rs"):
                待定.append(备选路径[:-3] + "/mod.rs")
            for 候选件 in 待定:
                if 候选件 not in 文件 or not 候选件.endswith(".rs"):
                    continue
                if 候选件.rsplit("/", 1)[-1][:-3] in ("lib", "mod", "main"):
                    continue  # 包根不是夹具（`mod lib;` 不是 Rust 能编的形状）
                # 内联 `mod 名 { … }`（`备2 == 父角色` = 自挂）只有在**文件自身在测试面**
                # （路径段含 `tests`，= cargo 集成测试目标）时才算整份夹具 ——
                # 实测 `对外接口面/调用接口面/tests/整条HTTP.rs` 自挂，必须收；
                # 而生产件里的内联同名 mod **不许**把该件整份算作夹具（否则真代码从实现面消失）。
                # `;` 引出的外部夹具文件不受这条限制（那才是真的挂载）。
                if 候选件 == 父角色 and "tests" not in 候选件.split("/"):
                    continue
                新内容.add(候选件)
        if not 新内容 - 整份:
            break
        整份 |= 新内容
    return 整份


def 生产区文本(文本: str, 保串: bool = False) -> str:
    """去注释 + 抹掉 `#[cfg(test)]` 区 ⇒ 只剩生产代码。

    `保串=真` 时**保留字符串字面量**——数导出符号名必须保串（符号名就写在字符串里；
    实测撞到过：先去字面量会把 `export_name = "平台_调用"` 的名字抹成空白 ⇒ 数出 0 组）。

    ★ **按 `(保串, 文本)` 记忆化**（2026-09-27 · #224「共享一份扫描结果」）：本函数是**纯函数**
      —— 输出只由 `文本` 与 `保串` 决定（`去字面量` / `去注释保串` / `条件编译测试区` 全是纯的）。
      而底下的 `_剥注释与串` 是**纯 Python 字符循环**，好几条判据各自把同一份文本重算一遍
      （实测 `--自测` 里 `并行生产区` 共 380 次、累计 6346 件、4616 ms）。键里放**文本本身**
      （不是它的哈希）⇒ 没有碰撞风险，不会因为「哈希撞了」而假绿；同文本必然同输出。
      跨夹具：文本相同则结果本就该相同 ⇒ 复用是**逐字正确**的，不是近似。
    """
    键名 = (保串, 文本)
    记住 = _生产区缓存.get(键名)
    if 记住 is not None:
        return 记住
    净文本 = 去字面量(文本) if not 保串 else 去注释保串(文本)
    出区 = list(净文本)
    for 区间起点, 区间终点 in 条件编译测试区(文本):
        for 游标 in range(区间起点, min(区间终点 + 1, len(出区))):
            出区[游标] = " "
    结果 = "".join(出区)
    _生产区缓存[键名] = 结果
    return 结果


# 生产区文本的记忆化表（纯函数 ⇒ 可缓存；见 `生产区文本`）。
# 键含**文本本身**：上一轮自测夹具的文本留在表里只会占内存、不会串（同文本必然同输出）。
_生产区缓存: dict = {}


def 去注释保串(文本: str) -> str:
    """去注释（长度不变），**字符串字面量原样保留**。

    与 `去字面量` 共用同一个单次扫描器（`_剥注释与串`）——不许在这里另写一遍正则：
    早先这里也是「先 `/* */` 再 `//`」两遍，字符串里含 `//` 时会把收尾引号当注释剥掉
    （同 去字面量 的实测缺陷）⇒ 两条腿必须走同一个解析器。
    """
    return _剥注释与串(文本, 保串=True)


def 并行取生产区文本(件表: list, 测试文件集=frozenset(), 保串: bool = False) -> dict:
    件表 = [(键名, 文本) for 键名, 文本 in 件表 if 文本 is not None]
    with ThreadPoolExecutor(max_workers=并发度) as 线程池:
        return dict(
            线程池.map(
                lambda 文件项: (
                    文件项[0],
                    "" if 文件项[0] in 测试文件集 else 生产区文本(文件项[1], 保串),
                ),
                件表,
            )
        )


def 收集导出(代码件: dict) -> dict:
    """导出符号名 → 出现处。`export_name` 取属性里的名字；`no_mangle` 取紧跟的 fn 名。"""
    输出缓冲 = {}
    for 键名, 文本 in 代码件.items():
        for 命中 in 导出名模式.finditer(文本):
            行号 = 文本[: 命中.start()].count("\n") + 1
            输出缓冲.setdefault(命中.group(1), []).append(f"{键名}:{行号}")
        for 命中 in re.finditer(r"#\[no_mangle\]", 文本):
            尾部 = 文本[命中.end() : 命中.end() + 400]
            名配 = re.search(r"\bfn[ \t]+([A-Za-z_]\w*)", 尾部)
            名称 = 名配.group(1) if 名配 else "（未标名）"
            行号 = 文本[: 命中.start()].count("\n") + 1
            输出缓冲.setdefault(名称, []).append(f"{键名}:{行号}")
    return 输出缓冲
