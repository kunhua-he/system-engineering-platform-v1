# -*- coding: utf-8 -*-
"""注入样本 · 命名穷举（判据 ㊷）：往干净合成仓塞一个**没登记的名**。

反向样本全部注入到**干净合成仓**（不依赖仓库现状 ⇒ 可重复）。夹具的最小规则库里，名册是从
**夹具的干净代码**派生的（`夹具规则库.py`）⇒ 注入件的名不在名册里 ⇒ 必然「新增即红」。
"""
from __future__ import annotations

from pathlib import Path

_样本件 = "运行内核/实例状态/src/命名穷举样本.rs"


def 注入_未登记名(临根: Path) -> str:
    """往一个 `.rs` 里写**没登记的形参名与局部名** ⇒ 判据 ㊷ 当场红（「新增即红」）。

    为何塞两处（形参 + 局部）：本条判据的面比判据 ㉒ 宽（三面），而形参面 / 局部面正是索引
    看不见的那两层 —— 只塞定义面的话，证不出「那两面也在判」。
    """
    路径 = 临根 / _样本件
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "pub fn 命名穷举样例(未登记形参名: u32) -> u32 {\n"
        "    let 未登记局部名 = 未登记形参名;\n"
        "    未登记局部名\n"
        "}\n",
        encoding="utf-8",
    )
    return _样本件
