def 命名扫描件(上层读数: dict) -> dict:
    """判据 ㉒ 的**扫描面**：索引定义面里、且被扫仓真有这一件的那些命名件 ⇒ `{件: 条表}`。

    ★ **判定与对象数共用这一个函数**（一处定义）—— 手写第二份扫描面就是第二个事实源
    （`判据的可信性.md` §三.3 的假绿来源）。`.css`/`.html`/`.sh` 没有标识符这回事，
    由 `查名.分档` 按 `是命名件` 筛。
    「件在被扫仓里」这一条必须明写：真索引是**判据自身所在那棵树**的（`开发工具` 的索引），
    而 `--自测` 扫的是夹具仓 ⇒ 不按 `上["文件"]` 过滤就会把真仓的符号算进夹具（假绿）。
    """
    查名 = _查名()
    节点件 = set(查名.命名后缀)
    扫描面: dict = {}
    for 一条 in 读索引定义(上层读数):
        路径 = 一条.get("路径", "")
        if 路径 and 路径.endswith(tuple(节点件)) and 路径 in 上层读数["文件"]:
            扫描面.setdefault(路径, []).append(一条)
    return 扫描面


def 数命中(上层读数: dict) -> dict:
    """读索引定义面 ⇒ `{档: {(路径, 名字): 处数}}` —— **只数两档**（序数代称 · 单西文）。

    `处数` = 该名字在那一件里的**定义处数**（索引面按定义给节点）。规则走 `查名.分档`
    —— 与 `python3 开发工具/代码地图.py 检名` 逐条一致的那一份（同面 · 同规则）。
    """
    扫描面 = 命名扫描件(上层读数)
    允许 = {路径 for 路径 in 扫描面}
    查名 = _查名()
    档表 = 查名.分档([条 for 条表 in 扫描面.values() for 条 in 条表])
    命中 = {档_序数代称: {}, 档_单西文: {}}
    for 档名, 本档 in (("序数代称", 档_序数代称), ("西文单字母", 档_单西文)):
        for 一条 in 档表[档名]:
            if 一条["路径"] not in 允许:
                continue
            键名 = (一条["路径"], 一条["名字"])
            命中[本档][键名] = 命中[本档].get(键名, 0) + 1
    return 命中


def 数无义单字(上层读数: dict) -> dict:
    """**读数**（不判）：无义中文单字（`出` `加` `取` `查` `判`）作标识符的 {(路径, 名字): 处数}。

    它**不进基线、不报违规**（决策记录 §三 那一档的名单是开放的，判它必假红）——
    只把读数如实报出来，由裁决方裁。见 `--缺口`。
    """
    读数 = {}
    for 条表 in 命名扫描件(上层读数).values():
        for 一条 in 条表:
            名称 = 一条.get("名字", "")
            if len(名称) == 1 and 名称 in _查名().无义单字:
                键名 = (一条["路径"], 名称)
                读数[键名] = 读数.get(键名, 0) + 1
    return 读数


