def 读索引定义(上: dict) -> list:
    """本仓的**索引定义面** ⇒ 定义表（真仓读真索引，夹具仓读合成索引）。

    读法只有一处：`开发工具/代码地图/索引库.全部定义(库路径)` —— 本函数只负责把
    「该读哪个库」交给 `读文件.索引路径`（它管夹具 vs 真仓的分支）。
    """
    import sys as _sys

    根 = str(常量.仓根目录 / "开发工具")
    if 根 not in _sys.path:
        _sys.path.insert(0, 根)
    import 代码地图.索引库 as 索引库

    from .读文件 import 索引路径

    # 件表**取当场那一份**（`上["文件"]`）：夹具仓的索引由它现场造 ——
    # `--自测` 的注入发生在 `造干净仓` 之后，重取夹具会看不见注入件。
    return 索引库.全部定义(索引路径(上["仓根"], {键: 项["文本"] for 键, 项 in 上["文件"].items()}))


def 命名扫描件(上: dict) -> dict:
    """判据 ㉒ 的**扫描面**：索引定义面里、且被扫仓真有这一件的那些命名件 ⇒ `{件: 条表}`。

    ★ **判定与对象数共用这一个函数**（一处定义）—— 手写第二份扫描面就是第二个事实源
    （`判据的可信性.md` §三.3 的假绿来源）。`.css`/`.html`/`.sh` 没有标识符这回事，
    由 `查名.分档` 按 `是命名件` 筛。
    「件在被扫仓里」这一条必须明写：真索引是**判据自身所在那棵树**的（`开发工具` 的索引），
    而 `--自测` 扫的是夹具仓 ⇒ 不按 `上["文件"]` 过滤就会把真仓的符号算进夹具（假绿）。
    """
    查名 = _查名()
    件 = set(查名.命名后缀)
    面: dict = {}
    for 条 in 读索引定义(上):
        路径 = 条.get("路径", "")
        if 路径 and 路径.endswith(tuple(件)) and 路径 in 上["文件"]:
            面.setdefault(路径, []).append(条)
    return 面


def 数命中(上: dict) -> dict:
    """读索引定义面 ⇒ `{档: {(路径, 名字): 处数}}` —— **只数两档**（序数代称 · 单西文）。

    `处数` = 该名字在那一件里的**定义处数**（索引面按定义给节点）。规则走 `查名.分档`
    —— 与 `python3 开发工具/代码地图.py 检名` 逐条一致的那一份（同面 · 同规则）。
    """
    面 = 命名扫描件(上)
    允许 = {路径 for 路径 in 面}
    查名 = _查名()
    档表 = 查名.分档([条 for 条表 in 面.values() for 条 in 条表])
    命中 = {档_序数代称: {}, 档_单西文: {}}
    for 档名, 本档 in (("序数代称", 档_序数代称), ("西文单字母", 档_单西文)):
        for 条 in 档表[档名]:
            if 条["路径"] not in 允许:
                continue
            键 = (条["路径"], 条["名字"])
            命中[本档][键] = 命中[本档].get(键, 0) + 1
    return 命中


def 数无义单字(上: dict) -> dict:
    """**读数**（不判）：无义中文单字（`出` `加` `取` `查` `判`）作标识符的 {(路径, 名字): 处数}。

    它**不进基线、不报违规**（决策记录 §三 那一档的名单是开放的，判它必假红）——
    只把读数如实报出来，由裁决方裁。见 `--缺口`。
    """
    读数 = {}
    for 条表 in 命名扫描件(上).values():
        for 条 in 条表:
            名 = 条.get("名字", "")
            if len(名) == 1 and 名 in _查名().无义单字:
                键 = (条["路径"], 名)
                读数[键] = 读数.get(键, 0) + 1
    return 读数


def _读基线(基线件) -> tuple:
    """读基线 ⇒ `({(档, 路径, 名字): 处数}, 错误或 None)`。"""
    if not 基线件.is_file():
        return {}, f"基线文件不存在（{命名基线路径}）"
    try:
        数据 = json.loads(基线件.read_text(encoding="utf-8"))
    except Exception as 错:
        return {}, f"基线文件解析不了（{type(错).__name__}）"
    表 = {}
    for 档 in (档_序数代称, 档_单西文):
        for 条 in 数据.get("档", {}).get(档) or []:
            try:
                表[(档, str(条["路径"]), str(条["名字"]))] = int(条.get("处数", 0))
            except (KeyError, TypeError, ValueError):
                return {}, f"基线条目形状不对（{档}：{条!r}）—— 要 路径/名字/处数 三键"
    return 表, None


def 检查22_命名防回潮(上: dict) -> list:
    """命名防回潮：序数代称字与西文单字母**存量入基线、新增即红**（基线只许减）。

    三元读数：**通过** = 扫描面非空且无新增/超基线/陈旧；**失败** = 逐条报出；
    **未判** = 扫描面下 0 个件（那说明扫描面或后缀表坏了，不是「没问题」）。
    """
    出 = []
    件表 = 命名扫描件(上)
    if not 件表:
        判不了(
            检查名[21],
            " · ".join(_查名().命名后缀),
            f"扫描面下 0 个件（有标识符的语言：{' · '.join(_查名().命名后缀)}）"
            f"——也可能是**索引不在**（夹具仓该由 读文件.索引路径 挂一份合成索引）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。一条标识符都没有的仓"
            "天然是绿的，那不是这条判据的功劳；而索引缺失也会让面为空 ⇒ 两件事都要由"
            "判据作者确认（扫描面 · 后缀表 · 该读的那份索引在不在）",
        )
        return 出

    基线表, 错 = _读基线(上["仓根"] / 命名基线路径)
    if 错:
        return [
            违规(
                检查名[21],
                命名基线路径,
                错,
                "「存量入基线、新增即红」要求先有存量清单（决策记录 2026-09-27_命名规范.md §四.2）；"
                "没有它，实测的全部存量会被算成「新增」⇒ 判据当场红一片，等于没上闸。"
                "基线只能由**声明方**登记（谁欠的债谁登记）⇒ 只能由维护方补",
            )
        ]

    实测 = 数命中(上)
    for 档 in (档_序数代称, 档_单西文):
        口径 = (
            "决策记录 2026-09-27_命名规范.md §二：序数代称（序数代称字）一律停用（作标识符）——"
            "它在这里没有语义（只是序数代称），而本项目其它地方全是语义命名（`值` `码` `槽` `前止`）。"
            "（**词内**序数代称字不算：那个字是词的一部分 —— 口径见 判据口径十一条 §十三，"
            "白名单现在实测为空。）"
            "改法：按它在这一处的**实际角色**命名（`首数组/次数组/末数组` → `原数组/改后数组/期望数组`），"
            "不许机械替换成「第一个/第二个」了事 ⇒ 只能由该件的作者改名"
            if 档 == 档_序数代称
            else "决策记录 2026-09-27_命名规范.md §三：西文单字母（`f` `i` `n` `s` `d` `b` `t` `r` 这类）"
            "无义 —— 一个不懂上下文的人看不出它是什么。改法：按角色命名（循环计数 → `序号`/`下标`，"
            "缓冲 → `缓冲`）⇒ 只能由该件的作者改名"
        )
        for (路径, 名字), 实际 in sorted(实测[档].items()):
            登记 = 基线表.get((档, 路径, 名字))
            if 登记 is None:
                出.append(
                    违规(
                        检查名[21],
                        f"{路径}::{名字}",
                        f"新增「{档}」标识符 `{名字}`（{实际} 处），基线里没有它 ⇒ **新增即红**",
                        口径,
                    )
                )
            elif 实际 > 登记:
                出.append(
                    违规(
                        检查名[21],
                        f"{路径}::{名字}",
                        f"「{档}」标识符 `{名字}` 实测 {实际} 处 > 基线登记 {登记} 处 ⇒ **存量还在长**",
                        "基线是「存量不许再长」的闸，不是白名单（决策记录 §四.2）。这一处已在基线里"
                        "登记过，却又多了 ⇒ 要么改回去，要么在提交信息里说明为什么必须涨并同步登记 ⇒ "
                        "只能由该件的作者处置",
                    )
                )

    # ── 基线里不许留**陈旧登记**（与判据 ⑲ 同一条）──
    # 裁决说「基线只许减」。一条登记若已不再出现、或实测已低于登记值，它自身就成了
    # 「只增不减」的反面：读基线的人看到的是历史而不是现状，而且它把那一档的上限白抬一格。
    for (档, 路径, 名字), 登记 in sorted(基线表.items()):
        实际 = 实测[档].get((路径, 名字), 0)
        if 实际 == 0:
            出.append(
                违规(
                    检查名[21],
                    f"{路径}::{名字}",
                    f"基线登记着「{档}」`{名字}`（{登记} 处），而实测这一处**已经不出现**"
                    f"⇒ **陈旧登记**",
                    "决策记录 §四.2「基线只许减」：改掉了就该把登记删掉。留着它，基线读数就不再是"
                    f"现状（读的人会以为债还在），而且它白占一格上限 ⇒ 只能由维护方删（{命名基线路径}）",
                )
            )
        elif 实际 < 登记:
            出.append(
                违规(
                    检查名[21],
                    f"{路径}::{名字}",
                    f"基线登记「{档}」`{名字}` {登记} 处，实测只有 {实际} 处 ⇒ **登记没跟着减**",
                    "决策记录 §四.2「基线只许减」：实测比登记低就该同步减下来。不减的话，"
                    "这一处可以一路长回登记值而不报红 —— 那是「只增不减」的一个洞 ⇒ "
                    f"只能由维护方改（{命名基线路径}）",
                )
            )
    return 出
