def _读基线(基线件) -> tuple:
    """读基线 ⇒ `({(档, 路径, 名字): 处数}, 错误或 None)`。"""
    if not 基线件.is_file():
        return {}, f"基线文件不存在（{命名基线路径}）"
    try:
        数据 = json.loads(基线件.read_text(encoding="utf-8"))
    except Exception as 错:
        return {}, f"基线文件解析不了（{type(错).__name__}）"
    项表 = {}
    for 档位 in 全部档:
        for 一条 in 数据.get("档", {}).get(档位) or []:
            try:
                项表[(档位, str(一条["路径"]), str(一条["名字"]))] = int(一条.get("处数", 0))
            except (KeyError, TypeError, ValueError):
                return {}, f"基线条目形状不对（{档位}：{一条!r}）—— 要 路径/名字/处数 三键"
    return 项表, None


