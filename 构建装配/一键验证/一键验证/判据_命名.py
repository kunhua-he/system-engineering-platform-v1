"""判据 ㉒：命名防回潮（序数代称字作标识符 · 西文单字母作标识符）。

依据：`项目文档/决策记录/2026-09-27_命名规范.md` §二（序数代称一律停用）· §三（两档口径）·
§四.2（判据形状：**存量入基线、新增即红**）· §四.1（改名是独立批次，本判据是它的闸）。

本判据要防的那句话：「**存量入基线、新增即红。没有它，后人会写回来。**」

**形状照抄判据 ⑲**（`判据_墙钟与行数.检查19_行数硬数`）：基线文件 + 三条 ——
① 新增（基线里没有）⇒ 红 ② 超基线（实际 > 登记）⇒ 红 ③ **基线不许留陈旧登记**
（登记着却已不出现，或实测低于登记）⇒ 红。**基线只许减**（改名批次落地后删登记，不许留）。

**只判两档**（决策记录 §三）：
  · A 序数代称字作标识符：标识符里出现序数代称字中的字（**当序数代称**才算；
    词内的那个字不算 —— 白名单封闭在 `查名.py::词内序数代称`（**实测为空**），依据见 §十三）。
  · B 西文单字母作标识符：`f` `i` `n` `s` `d` `b` `t` `r` 这类**单个西文字母**。
  · 「无义中文单字」那一档（`出` `加` `取` `查` `判`）**不判** —— 白名单/黑名单是开放的，
    判它必假红；本模块只把它当**读数**算出来（`数无义单字`），由裁决方裁。
  · 实义单字名（`值` `码` `槽` `号` `根` `表` `键` `止` `起` `名` `项` `条` `位` `序`）**一律不判**。

**为什么必须剥注释与字符串**（决策记录 §一）：读数面是**标识符**，不是散文。
不剥的话，注释里写一句「序数代称字」、字符串里写一个 `"序数代称"` 就会假红 —— 那是本项目判据
最反对的「假红工厂」。剥法分语言，见 `命名扫描` 的模块注释。
"""
