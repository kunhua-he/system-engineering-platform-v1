def 是临时路径(相对键: str) -> bool:
    """路径的**任一段**以 `_临时_` 开头 ⇒ 是临时件（扫描面一律排除）。"""
    return any(段.startswith(常量.临时目录前缀) for 段 in str(相对键).split("/"))
