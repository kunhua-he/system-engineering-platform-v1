# -*- coding: utf-8 -*-
"""判据 ㊿：命名重复登记 —— 同一 `唯一名`（整串为键）挂 ≥2 行同义语义（真子串包含）。

依据：库 `规则` 表 命名口径-21。判法只此一份（`命名判法.重复登记`）—— 写侧登记口也调它。
**三元读数**：通过 = 无新增 / 无涨 / 无陈旧；失败 = 逐条报；未判 = 名册读不动或 0 行。
**存量入基线**（库 `命名重复基线`，只许减）· 新增即红 · 不许留陈旧 · 不许假绿（空集是未判）。
"""
from __future__ import annotations

from .小工具 import 判不了, 违规
from .常量 import 检查名
from . import 命名判法
from .判据基线 import 读命名重复基线, 库相对路径


def 对象数_命名重复面(上层读数: dict) -> int:
    """对象数：库 `命名定义` 的行数（0 ⇒ 未判：空名册与库读不动必须分得开）。"""
    定义行表, _错误 = 命名判法.读命名定义(上层读数["仓根"])
    return len(定义行表)


def 检查50_命名重复登记(上层读数: dict) -> list:
    """命名重复登记：同一唯一名挂 ≥2 行同义语义（存量入基线、新增即红 · 基线只许减）。"""
    输出缓冲 = []
    定义行表, 错误 = 命名判法.读命名定义(上层读数["仓根"])
    if 错误:
        return [违规(检查名[49], 库相对路径, f"判不了：{错误}",
                    "名册是本条的唯一对象（重复登记就从它来）⇒ 读不出就判不了。修法：把规则库补上"
                    "（`python3 开发工具/信息核心/信息核心.py 建库`）⇒ 只能由维护方补")]
    if not 定义行表:
        判不了(检查名[49], 库相对路径, "`命名定义` 0 行 —— 空名册（或库不在）",
              "判据的可信性.md 第二节：空集是**未判**，不是通过 ⇒ 只能由维护方确认规则库")
        return 输出缓冲
    实测表 = 命名判法.重复登记(定义行表)
    基线表, 错误 = 读命名重复基线(上层读数["仓根"])
    if 错误:
        return [违规(检查名[49], 库相对路径, 错误,
                    "「存量入基线、新增即红」要求先有存量清单；没有它，实测的全部存量会被算成"
                    "「新增」⇒ 判据当场红一片，等于没上闸 ⇒ 只能由维护方登记（库 `命名重复基线` 表）")]
    口径 = ("库 `规则` 表 命名口径-21：同一 `唯一名` 挂 ≥2 行同义语义 = 重复登记。修法：保留一条"
          "「名即语义」行，其余行删（`信息核心.py 登记 --删 --语义 <语义>`）⇒ 只能由维护方处置")
    for 唯一名, 包含对表 in sorted(实测表.items()):
        实际 = len(包含对表)
        登记 = 基线表.get(唯一名)
        if 登记 is None:
            输出缓冲.append(违规(检查名[49], f"命名定义::{唯一名}",
                f"新增重复登记：`{唯一名}` 挂 {实际} 对同义语义（真子串包含），"
                f"基线里没有它 ⇒ **新增即红**", 口径))
        elif 实际 > 登记:
            输出缓冲.append(违规(检查名[49], f"命名定义::{唯一名}",
                f"重复登记 `{唯一名}` 实测 {实际} 对 > 基线登记 {登记} 对 ⇒ **存量还在长**", 口径))
    for 唯一名, 登记 in sorted(基线表.items()):
        实际 = len(实测表.get(唯一名, []))
        if 实际 == 0:
            输出缓冲.append(违规(检查名[49], f"命名定义::{唯一名}",
                f"基线登记着重复登记 `{唯一名}`（{登记} 对），而实测已无 ⇒ **陈旧登记**",
                "「基线只许减」：修完就该删登记 ⇒ 只能由维护方删（库 `命名重复基线` 表）"))
        elif 实际 < 登记:
            输出缓冲.append(违规(检查名[49], f"命名定义::{唯一名}",
                f"基线登记 `{唯一名}` {登记} 对，实测只有 {实际} 对 ⇒ **登记没跟着减**",
                "「基线只许减」：实测比登记低就该同步减下来 ⇒ 只能由维护方改（库 `命名重复基线` 表）"))
    return 输出缓冲
