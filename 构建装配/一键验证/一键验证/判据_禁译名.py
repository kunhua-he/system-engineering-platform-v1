"""判据 ㊹：零字面禁译名 —— 逐字节全树（含未跟踪件）里 0 处 U+5E03 U+5C14 二字。

依据：库 `条款` 表（`项目文档/未完成事项.md` §五 第 247 条）—— 那两个字是外来译名，
本项目对应的类型名裁为 `逻辑型`。2026-09-28 做过一轮全仓清零（散文 · 注释 · 标识符里的两个
读值函数名 → `逻辑型值()` / `取逻辑型值()` · 生成物重跑），**但那一轮「已全仓清零」的断言
不成立** —— 深度审计复扫（逐字节全树，含未跟踪件）仍有 1 处残留
（`构建装配/上线切换/构建制品/扩展.py` 的一处注释）。⇒ 立本条常驻判据：一处字面出现就红，
不必等下一次批次清存量。

**扫描面含库 `条款` 表的行**（2026-10-01）：已删 md 的正文住在库 `条款` 表里，而 `.db`
整份不是合法 UTF-8 ⇒ 走树看不见它（同 ㊵/㊳）。读法只此一处 = `条款文本.读条款件`。

**判什么**：文件按 UTF-8 解出的文本里，不许出现这两个码位**连成的那个词**（判的是整个词，
不是单个汉字 —— `布` 是常用字（布局 · 发布 · 画布 · 分布），按单字判会当场假红一片）。
**检测表只此一份**：
`开发工具/代码地图/查名.py::禁译名码位`（按 Unicode 码位写、全仓零字面）—— 本件 import 它，
不抄第二份。

**扫描面**：逐字节**全树**（**含未跟踪件**），排除 `/只读参考/`（只读、且不许被任何一层读取）·
`/构建环境/`（编译缓存里有非 UTF-8 的巧合字节序列，不是内容）· `/.git/` · `/.codegraph/`。
★ **判据本体逐字节读树**（`git grep` 只作旁证 —— 它看不见未跟踪件）。

**排除 `/构建装配/制品产物/`**（复用 `判据_台账号.是制品产物`，与判据 ㊳ 同一条规则）：它是
**被 git 忽略的构建快照**（裁决 §二）—— 快照里那个字是**旧构建那一刻的源**的副本，源侧早已
改净（`构建装配/上线切换/构建制品/扩展.py` 已改 `逻辑型`）。改它没有意义（重出即复原），
也不许手改（手改会让制品清单的 sha256 当场变红）⇒ 要改就改源、再重出快照。
★ 「含未跟踪件」的意图是抓**手写的**未跟踪件（判据本体逐字节走树才看得见它们）——
快照是**机器生成**的、且被 `.gitignore` 明示排除 ⇒ 不在那条意图内，排除它不动摇本条。

**白名单机制**（照 `查名.词内序数代称`）：**词内不算** —— 词的一部分（有词典义）不算。
**空表 + 加词门槛**（机制留着，表实测为空）。见 `词内禁译名码位`。

**形状照抄判据 ㊵**（`判据_十干.检查40_零字面十干`）：基线文件 + 三条 —— ① 新增（基线里没有）
⇒ 红 ② 超基线（实际 > 登记）⇒ 红 ③ **基线不许留陈旧登记**（登记着却已不出现，或实测低于
登记）⇒ 红。**基线只许减**。基线**住规则库** `禁译名基线` 表（不落外部 json）；读不到它就
fail-closed 报红。

三元读数：**通过** = 扫描面非空且无新增/超基线/陈旧；**失败** = 逐条报出；
**未判** = 扫描面 0 件（那说明走树坏了或仓是空的，不是「没问题」）。
"""
from __future__ import annotations

import os
from pathlib import Path

from .小工具 import 判不了, 违规
from .常量 import 检查名, 排除目录
from .命名面 import 取查名 as _查名
from .判据基线 import 读禁译名基线, 库相对路径
# 制品产物段判定**只此一份**（`判据_台账号.是制品产物`，与判据 ㊳ 同一条规则）—— 不抄第二份。
from .判据_台账号 import 是制品产物
from .条款文本 import 读条款件


# 基线**住规则库**（`禁译名基线` 表）—— 不落外部 json。判据读不到它就 fail-closed 报红 ——
# 「存量入基线」要求先有存量清单，没有它，实测的全部存量会被当成「新增」⇒ 当场红一片。
# 库路径**只此一份**（`判据基线`）。
禁译名基线路径 = 库相对路径

# ── 白名单：词内禁译名（**空表 + 加词门槛**）────────────────────────────────
# 口径照 `查名.词内序数代称`：判的是「拿这两个字当外来译名」，不是「文本里出现过某个字」——
# 词的一部分（有词典义）不算。**加词门槛**（三条，缺一不可）：
#   ① 那个词必须有**词典义**；② 这两个字在词内**不表译名**；③ 给出**全仓实测读数**。
# ★ **表实测为空**（2026-10-01 全树清到 0）。加词**按码位写**（不许写字面）——
#   本件自身也在扫描面内，写字面会自红。
词内禁译名码位 = ()
词内禁译名 = tuple("".join(chr(码位) for 码位 in 码位串) for 码位串 in 词内禁译名码位)


def 禁译名字() -> str:
    """禁译名的**检测表**（从 `查名.py::禁译名字` 取，不抄第二份）。"""
    return _查名().禁译名字


def 去词内禁译名(文本: str) -> str:
    """把白名单词换成**等长空格**（列位置不变）—— 词内的字不算。空表 ⇒ 原样返回。"""
    if not 词内禁译名:
        return 文本
    净文本 = 文本
    for 白名单词 in 词内禁译名:
        净文本 = 净文本.replace(白名单词, " " * len(白名单词))
    return 净文本


def 路径被排除(相对路径: str) -> bool:
    """路径里有**排除目录**的任一段 ⇒ 不进扫描面。"""
    return any(路径段 in 排除目录 for 路径段 in Path(相对路径).parts)


# 扫描面 / 扫一遍的结果都在一次运行里不变（判定与对象数各取一次）⇒ 按仓根缓存。
# 不跨调用复用：`--自测` 的注入发生在两次 `验证` 之间。
禁译名面缓存: dict = {}
_扫缓存: dict = {}


def 禁译名面(上层读数: dict) -> dict:
    """扫描面：逐字节**全树**（含未跟踪件）⇒ `{相对路径: 文本}`。

    **判据本体走树读字节**（不借 `上["文件"]`：它只收 `扫描后缀`，看不见 `.md` 之外的
    样本 / 数据件；也不借 `git grep`：它看不见未跟踪件）。非 UTF-8 件不是「文本」⇒ 跳过。
    """
    仓根 = Path(上层读数["仓根"])
    键名 = str(仓根)
    if 键名 in 禁译名面缓存:
        return 禁译名面缓存[键名]
    件表 = {}
    for 根目录, 目录表, 文件表 in os.walk(仓根):
        目录表[:] = [
            目录名 for 目录名 in 目录表
            if not 路径被排除(str(Path(根目录, 目录名).relative_to(仓根)))
        ]
        for 文件名 in 文件表:
            件路径 = Path(根目录) / 文件名
            相对 = str(件路径.relative_to(仓根))
            if 路径被排除(相对) or 是制品产物(相对):
                continue  # 排除目录 · 或 制品产物 快照（裁决 §二：快照要改就改源）
            try:
                件表[相对] = 件路径.read_bytes().decode("utf-8")
            except (OSError, UnicodeDecodeError):
                continue  # 读不动 / 不是 UTF-8 ⇒ 不是「文本」（不是内容）
    # 库 `条款` 表的行（已删 md 的正文）—— `.db` 整份不是合法 UTF-8，走树看不见它
    # （读法只此一处 = `条款文本.读条款件`，与 ㊵/㊳ 同一份）。
    件表.update(读条款件(上层读数["仓根"]))
    禁译名面缓存[键名] = 件表
    return 件表


def 扫禁译名(件表: dict) -> list:
    """扫一遍件表 ⇒ `[(路径, 行号)]`（白名单词先去掉）。

    判的是**整个词**（两个码位连着的那个外来译名），不是单个汉字 —— `布` 是常用字
    （布局 · 发布 · 画布 · 分布），按单字判会当场假红一片（实测：84 件含 `布`）。
    白名单先剥 ⇒ 逐行找（行号才准）；件里没这个词的直接跳过（C 级、快）。
    """
    禁译名词 = 禁译名字()
    结果 = []
    for 路径 in sorted(件表):
        净文本 = 去词内禁译名(件表[路径] or "")
        if not 净文本 or 禁译名词 not in 净文本:
            continue
        for 行号, 行文本 in enumerate(净文本.split("\n"), 1):
            if 禁译名词 in 行文本:
                结果.append((路径, 行号))
    return 结果


def 扫禁译名面(上层读数: dict) -> list:
    """扫一遍扫描面（按仓根缓存）。"""
    键名 = str(上层读数["仓根"])
    if 键名 not in _扫缓存:
        _扫缓存[键名] = 扫禁译名(禁译名面(上层读数))
    return _扫缓存[键名]


def 数命中(扫结果: list) -> dict:
    """`[(路径, 行号)]` ⇒ `{路径: 处数}`（基线读写与判定共用一份口径）。"""
    命中 = {}
    for 路径, _行号 in 扫结果:
        命中[路径] = 命中.get(路径, 0) + 1
    return 命中


def 样本_禁译名面(上层读数: dict) -> int:
    """对象数：扫描面下的件数（0 ⇒ 未判：走树坏了也是 0 件，两者必须分得开）。"""
    return len(禁译名面(上层读数))


def 词文案() -> str:
    """禁译名的**文案**（按码位写，不写字面）—— 报违规时用（码位表从 `查名.py` 取）。"""
    return " ".join("U+%04X" % 码位 for 码位 in _查名().禁译名码位)


def 检查44_零字面禁译名(上层读数: dict) -> list:
    """零字面禁译名：逐字节全树（含未跟踪件）里 0 处该二字（存量入基线、新增即红 · 基线只许减）。

    三元读数：**通过** = 扫描面非空且无新增/超基线/陈旧；**失败** = 逐条报出；
    **未判** = 扫描面 0 件（走树坏了也是 0 件）。
    """
    输出缓冲 = []
    件表 = 禁译名面(上层读数)
    if not 件表:
        判不了(
            检查名[43],
            "全树（排除 只读参考/ · 构建环境/ · .git/ · .codegraph/）",
            "扫描面下 0 个件（判据没有可查的对象）—— 也可能是**走树坏了**：那样恒为 0 命中 ⇒ 假绿",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一个空仓天然是绿的，"
            "那不是本条判据的功劳 ⇒ 只能由判据作者确认走树与排除表",
        )
        return 输出缓冲

    基线表, 错误 = 读禁译名基线(上层读数["仓根"])
    if 错误:
        return [
            违规(
                检查名[43],
                禁译名基线路径,
                错误,
                "「存量入基线、新增即红」要求先有存量清单（形状照判据 ㊵）；没有它，"
                "实测的全部存量会被算成「新增」⇒ 判据当场红一片，等于没上闸。"
                "基线只能由**声明方**登记（谁欠的债谁登记）⇒ 只能由维护方补",
            )
        ]

    实测 = 数命中(扫禁译名面(上层读数))
    口径 = (
        "库 `条款` 表（`项目文档/未完成事项.md` §五 第 247 条）：那两个字是外来译名，"
        "本项目对应的类型名裁为 `逻辑型`。修法：按它在这一处的**实际角色**命名"
        "（类型名写 `逻辑型`），或**删掉那个词**（不许机械替换）⇒ 只能由该件的作者改"
    )
    for 路径, 实际 in sorted(实测.items()):
        登记 = 基线表.get(路径)
        if 登记 is None:
            输出缓冲.append(
                违规(
                    检查名[43],
                    f"{路径}::{词文案()}",
                    f"新增字面禁译名（{词文案()}，{实际} 处），基线里没有它 ⇒ **新增即红**",
                    口径,
                )
            )
        elif 实际 > 登记:
            输出缓冲.append(
                违规(
                    检查名[43],
                    f"{路径}::{词文案()}",
                    f"字面禁译名（{词文案()}）实测 {实际} 处 > 基线登记 {登记} 处 ⇒ **存量还在长**",
                    "基线是「存量不许再长」的闸，不是白名单（形状照判据 ㊵）。这一处已在基线里"
                    "登记过，却又多了 ⇒ 要么改回去，要么在提交信息里说明为什么必须涨并同步登记 ⇒ "
                    "只能由该件的作者处置",
                )
            )

    # ── 基线里不许留**陈旧登记**（与判据 ㊵/㉒/⑲ 同一条）──
    for 路径, 登记 in sorted(基线表.items()):
        实际 = 实测.get(路径, 0)
        if 实际 == 0:
            输出缓冲.append(
                违规(
                    检查名[43],
                    f"{路径}::{词文案()}",
                    f"基线登记着字面禁译名（{词文案()}，{登记} 处），而实测这一处"
                    f"**已经不出现** ⇒ **陈旧登记**",
                    "「基线只许减」：改掉了就该把登记删掉。留着它，基线读数就不再是现状"
                    f"（读的人会以为债还在）⇒ 只能由维护方删（{禁译名基线路径}）",
                )
            )
        elif 实际 < 登记:
            输出缓冲.append(
                违规(
                    检查名[43],
                    f"{路径}::{词文案()}",
                    f"基线登记字面禁译名（{词文案()}）{登记} 处，实测只有 {实际} 处 ⇒ "
                    f"**登记没跟着减**",
                    "「基线只许减」：实测比登记低就该同步减下来。不减的话，这一处可以一路长回"
                    f"登记值而不报红 —— 那是「只增不减」的一个洞 ⇒ 只能由维护方改（{禁译名基线路径}）",
                )
            )
    return 输出缓冲
