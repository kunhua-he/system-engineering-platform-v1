"""判据 65：台账四栏形状 —— `未完成` 每一行的 `验证命令` 必须**可机判**。

依据：债务 533（「验证命令」字段大量不可机判：散文 · 「仓根」占位词 · 引用已删件 ⇒ 验不动）。
台账是一行一债的**待办**，第四栏是**给机器跑的验证命令**，不是验收口径的描述 —— 本条把
「跑得动」这一半钉成常驻判据（原先只有人眼读得出来）。

四问（逐行）：
  ① `缺什么` 与 `验证命令` 都非空（说不出缺什么 / 验不动，都不是台账行）；
  ② `验证命令` 不含**占位词**（`仓根` —— 要人替换的词；实测回执 `cd: 仓根: No such file`）；
  ③ `验证命令` 不引用**已删件**（`未完成.json` —— 台账自 2026-10-13 起「库即存本」，那份 json 已删）；
  ④ `验证命令` 的**首字**是仓内可跑的入口（白名单）—— 散文一律红。

三元读数：**通过** = 0 命中（0 行也算通过：库**在**而 `未完成` 无行 = 清账，不是空集）；
**失败** = 命中逐条报出（`件::号` · 哪一问 · 原文）；**未判** = 库件缺失 / 读不动 / `未完成` 表不可读
—— 那才是判不了的对象（对象是「库」，不是「库里有几行」）。

**诚实登记（假阴性面）**：本条只判「跑得动、不是散文」，判不了「是不是**断言式**」——
取证式命令（`sed -n …` 列当前状态）照样过。断言式是作者的纪律，机器分不出（债务 533 的
「更深的问题」那一半登记在此，不假装已机判）。
"""
from __future__ import annotations

import shlex
import sqlite3
from pathlib import Path

from .验证小工具 import 判不了, 违规
from .常量 import 检查名
from .判据基线 import 库相对路径

# 首字白名单：仓内真能跑起来的入口。判据要的是**形状**（能不能当命令跑），不是语法校验。
可跑入口首字 = (
    "cd", "$V1_PY", "python3", "cargo", "git", "rg", "grep", "ls", "sed", "find", "wc", "echo",
    "test", "jq", "sqlite3", "cat", "head", "tail", "awk", "sort", "uniq", "diff", "file", "stat",
    "du", "which", "sh", "bash", "curl", "xargs", "构建环境/", "开发工具/", "构建装配/",
    "测试验证/", "运行内核/", "跨语言适配/", "对外接口面/", "扩展根目录/", "契约声明/",
)

# 占位词：要人替换才能跑的词（实测回执 `cd: 仓根: No such file or directory`）。
占位词表 = ("仓根",)

# 已删件：引它必然读不动（台账自 2026-10-13 起「库即存本」，那份 json 已删）。
已删件词表 = ("未完成.json",)


def 读台账行(树根) -> tuple:
    """本树规则库 `未完成` 表的四栏 ⇒ `(行表, 错误或 None)`；读不动交错误回去（不抛）。"""
    库件 = Path(树根) / 库相对路径
    if not 库件.is_file():
        return [], "规则库不在（%s）" % 库件
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute("select 号, 缺什么, 落点, 验证命令 from 未完成 order by 号"))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return [], "`未完成` 读不动：%s" % 错误
    return 行表, None


def 样本_台账面(上层读数: dict) -> int:
    """对象数：本判据的面是**台账库本身**而不是库里有几行 —— 库在 = 1（真判了）。

    2026-10-16 裁定（台账清零收口）：行数归 0 是「清账终态」，不是「对象不存在」。
    用行数当对象数 ⇒ 空台账恒报「扫描 0 项 = 未判」，把清账真态误报成未判。
    真正的空集是**库缺失 / 读不动**（那由 `检查65` 走错误分支报判不了）。
    """
    return 0 if 读台账行(上层读数.get("仓根") or ".")[1] else 1


def 取首字(命令文本: str) -> str:
    """安全解析首个 shell 词，去引号但不执行或展开；空串与未闭合引号拒收。"""
    命令词法 = shlex.shlex(str(命令文本 or ""), posix=True)
    命令词法.whitespace_split = True
    try:
        return 命令词法.get_token() or ""
    except ValueError:
        return ""


def 入口命中(文本值: str) -> bool:
    """命令是否以**仓内可跑入口**开头：白名单里带 `/` 的按**前缀**命中（如 `构建环境/`），
    其余按**首字**精确命中（如 `python3`）。

    ★ 2026-10-14（债务 603）：原先整表按 `取首字 not in 可跑入口首字`（精确成员）判 ⇒ 白名单里
    九条**目录前缀**（`构建环境/` 等）永远命中不上、等于没写（实测：以
    `构建环境/python/bin/python3` 开头的那几条验证命令曾被判「首字不是仓内可跑的入口（散文）」而红）。
    """
    文本值 = 取首字(文本值)
    return any(文本值.startswith(入口项) if 入口项.endswith("/") else 文本值 == 入口项
               for 入口项 in 可跑入口首字)


def 检查65_台账四栏形状(上层读数: dict) -> list:
    """台账每行的四栏形状 ⇒ 违规表（空 = 通过；台账为空 = 未判）。"""
    行表, 错误 = 读台账行(Path(上层读数["仓根"]))
    if 错误:
        return [违规(检查名[58], 库相对路径, 错误,
                   "台账是**库即存本**（2026-10-13 裁）⇒ 库读不动就判不了形状；"
                   "修法：把规则库放回本树（`信息核心.py 建库`）")]
    if not 行表:
        # 2026-10-16 裁定（台账清零收口）：库**在**而 `未完成` 表零行 ⇒ 无待办行 ⇒ 通过。
        # 本判据的对象是「库里的台账行」；零行 = 没有可判对象，不是「空集假绿」——
        # 真正的空集是**库件缺失 / 读不动 / 表建不了**（走上面 `错误` 分支，照旧未判）。
        # 正向样本「干净合成仓」本身就是台账留空 ⇒ 零行本就是干净仓的常态，恒未判会把它误报。
        return []
    输出缓冲 = []
    for 号值, 缺什么, _落点, 验证命令 in 行表:
        行位置 = "%s::%s" % (库相对路径, 号值)
        if not str(缺什么 or "").strip():
            输出缓冲.append(违规(检查名[58], 行位置, "`缺什么` 空 ⇒ 这一行说不出缺什么",
                            "台账一行必须说清缺什么 ⇒ 只能由作者补（`信息核心.py 记未完成`）"))
        文本值 = str(验证命令 or "").strip()
        if not 文本值:
            输出缓冲.append(违规(检查名[58], 行位置, "`验证命令` 空 ⇒ 这一行验不动",
                            "验不动 = 这条债没人能核 ⇒ 只能由作者补一条仓内可跑的命令"))
            continue
        for 占位词项 in 占位词表:
            if 占位词项 in 文本值:
                输出缓冲.append(违规(检查名[58], 行位置,
                                "`验证命令` 含占位词「%s」（要人替换才能跑）：%s" % (占位词项, 文本值[:80]),
                                "占位词照抄进回执就是 `No such file`（实测）⇒ 只能由作者改成真落点"))
                break
        for 已删件项 in 已删件词表:
            if 已删件项 in 文本值:
                输出缓冲.append(违规(检查名[58], 行位置,
                                "`验证命令` 引用**已删件**「%s」（台账已改「库即存本」）：%s" % (已删件项, 文本值[:80]),
                                "引已删件的命令必然读不动 ⇒ 只能由作者改读规则库 `未完成` 表"))
                break
        if not 入口命中(文本值):
            输出缓冲.append(违规(检查名[58], 行位置,
                            "`验证命令` 的首字「%s」不是仓内可跑的入口（散文）：%s" % (取首字(文本值), 文本值[:80]),
                            "散文不是命令 —— 机器跑不了、人也没法照抄 ⇒ 只能由作者改写成可跑的命令"))
    return 输出缓冲
