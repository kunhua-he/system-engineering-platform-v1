def 自检_超时扫描() -> list:
    """扫描器的身份证（`判据的可信性.md` §三.5：判据的解析器自身也要有反向样本）。

    十问：① 形①/形② 各抓得住（含 Rust 带类型标注的 `const`）；② 形① 的 Python 带标注赋值；
    ③ 形③ 的秒侧；④ 形③ 的毫秒侧；⑤ JS 对象键 `timeout: N`；⑥ 形③ 的 101–999 走**未判**
    （不是通过、也不是违规）；⑦ 合规值 0 命中；⑧ `==` / `>=` 比较不算「设置」；
    ⑨ 名字不以「秒/毫秒」结尾的不算、`.py` 的 `#` 注释也不算；
    ⑩ 下划线数字写法（`9_000` · `from_millis(10_000)` · `from_secs(9)`）三处都抓得住。
    """
