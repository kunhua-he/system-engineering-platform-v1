def _规范段表(段表, 位置: str, 必填键, 输出缓冲: list, 哪一份: str) -> list:
    """把一张段表规范化成 [(起,止,标签,段位置)]；形状问题当场报违规。"""
    规范 = []
    if not isinstance(段表, list) or not 段表:
        输出缓冲.append(
            违规(
                检查名[3],
                位置,
                f"不是非空列表（是 {type(段表).__name__}）",
                f"{哪一份} 缺了它，这一层的号就没有归属依据；验证面自带一张表就是第二个事实源 ⇒ 只能由声明方补",
            )
        )
        return 规范
    for 序号, 号段 in enumerate(段表):
        段位置 = f"{位置}[{序号}]"
        if not isinstance(号段, dict):
            输出缓冲.append(
                违规(
                    检查名[3],
                    段位置,
                    f"不是对象（是 {type(号段).__name__}）",
                    f"{哪一份} 的段形状是 {{{(' · '.join(必填键))}}}；不是对象就读不出区间，"
                    f"号归属判不了 ⇒ 只能由声明方补",
                )
            )
            continue
        缺失项 = [键名 for 键名 in 必填键 if 键名 not in 号段]
        if 缺失项:
            输出缓冲.append(
                违规(
                    检查名[3],
                    段位置,
                    f"缺 {(' · '.join(缺失项))}（{哪一份} 的段形状：{(' · '.join(必填键))}）",
                    f"归属 是「号段即层级」的落点（README 第七节）：缺归属，"
                    f"号落在段里也判不出属于哪一层 ⇒ 只能由声明方补",
                )
            )
            continue
        if not (是整数(号段["起"]) and 是整数(号段["止"])):
            输出缓冲.append(
                违规(
                    检查名[3],
                    f"{段位置}:起/止",
                    f"起/止 不是整数（起={号段['起']!r} · 止={号段['止']!r}）",
                    f"区间端点按 lib.rs 的 号段{{起:u32,止:u32}} 读；写成字符串"
                    f"会让 Rust 侧与 Python 侧读法分叉 ⇒ 只能由声明方补",
                )
            )
            continue
        if 号段["起"] > 号段["止"]:
            输出缓冲.append(
                违规(
                    检查名[3],
                    段位置,
                    f"空段：起 {号段['起']} > 止 {号段['止']}",
                    f"起>止 的段在 lib.rs 里被定义为「恒不相交的空段」⇒ 这一段实际没有号可用；"
                    f"是笔误还是有意留空，只有声明方能定 ⇒ 只能人来裁",
                )
            )
            continue
        规范.append((号段["起"], 号段["止"], 段归属标签(号段), 段位置))
    return 规范


def _读命名空间边界(号段图, 输出缓冲: list) -> dict:
    """`号段图.json:命名空间边界` → `{空间: (起, 止)}`；形状不对当场报违规。

    **为什么要有这一节**：判据要判「本空间的布局必须无缝铺满」，就必须知道本空间的全宽；
    而全宽是**声明侧的事实**（能力号 0–9999 · 通知号 1–2999 · 资源号 1–9999），
    判据自带一份就是第二个事实源（裁决 §八）。
    """
    元素 = 号段图.get("命名空间边界")
    出表 = {}
    if not isinstance(元素, dict):
        输出缓冲.append(
            违规(
                检查名[3],
                f"{号段图路径}:命名空间边界",
                f"不是对象（是 {type(元素).__name__}）",
                f"这一节给的是每个号空间的**全宽**，判据 4 判「布局必须无缝铺满」靠它；"
                f"缺了它就只能判「起≤止 + 两两不相交」，判不了无洞 ⇒ 只能由声明方补",
            )
        )
        return 出表
    for 空间, 取片段字节区间 in 元素.items():
        if 空间 == "说明":
            continue
        if (
            not isinstance(取片段字节区间, list)
            or len(取片段字节区间) != 2
            or not all(是整数(端点) for 端点 in 取片段字节区间)
            or 取片段字节区间[0] > 取片段字节区间[1]
        ):
            输出缓冲.append(
                违规(
                    检查名[3],
                    f"{号段图路径}:命名空间边界:{空间}",
                    f"不是 `[起, 止]` 两整数（起 ≤ 止）：{取片段字节区间!r}",
                    f"形状不对就取不出全宽，判不了无洞；判据不能替它猜一个 ⇒ 只能由声明方补",
                )
            )
            continue
        出表[空间] = (取片段字节区间[0], 取片段字节区间[1])
    return 出表


def _查段表重叠与洞(规范: list, 位置: str, 键名: str, 全区间: tuple, 输出缓冲: list) -> None:
    排好 = sorted(规范)
    for 游标 in range(len(排好)):
        for 内游标 in range(游标 + 1, len(排好)):
            左段, 右段 = 排好[游标], 排好[内游标]
            if 右段[0] <= 左段[1]:
                交低, 交高 = max(左段[0], 右段[0]), min(左段[1], 右段[1])
                输出缓冲.append(
                    违规(
                        检查名[3],
                        f"{左段[3]} ↔ {右段[3]}",
                        f"号段 [{左段[0]},{左段[1]}]（{左段[2]}）与 [{右段[0]},{右段[1]}]（{右段[2]}）"
                        f"相交，交集 [{交低},{交高}]",
                        f"两段归属不同（{左段[2]} / {右段[2]}），号落在交集 [{交低},{交高}] 里"
                        f"就有两个归属；缩哪一段都会把已归属该段的号挤出，"
                        f"判据本身定不了 ⇒ 只能人来裁",
                    )
                )
    覆盖 = 全区间[0]
    洞表 = []
    for 区间起点, 区间终点, _, _ in 排好:
        if 区间起点 > 覆盖:
            洞表.append((覆盖, 区间起点 - 1))
        覆盖 = max(覆盖, 区间终点 + 1)
    if 覆盖 <= 全区间[1]:
        洞表.append((覆盖, 全区间[1]))
    if 洞表:
        洞文 = " · ".join(f"[{洞起},{洞止}]" for 洞起, 洞止 in 洞表)
        输出缓冲.append(
            违规(
                检查名[3],
                位置,
                f"{键名} 的并集有洞：{洞文}（未覆盖 {全区间[0]}–{全区间[1]}）",
                f"§九 第 4 项要求「编号落在自身那一层号段内」——有洞就意味着洞里那些号"
                f"没有任何一层可归属，这一层的号一旦出现就判不了；补哪一段等于给新号"
                f"定归属，是号段级裁决 ⇒ 只能人来裁",
            )
        )


def 检查4_编号落在自身那一层号段内(上层读数: dict) -> list:
    输出缓冲 = []
    平台 = 上层读数["平台"]
    号段图 = 上层读数["号段图"]

    # ── (a) 布局（号段图.json）：全平台，每段必须带 归属 ──
    布局 = {}
    if 号段图 is None:
        输出缓冲.append(
            违规(
                检查名[3],
                号段图路径,
                "号段图.json 不存在或解析不了（第 4 项的唯一依据）",
                f"§二 ★：号段图 是**平台的布局**（每一段归谁），"
                f"平台声明.json 的 能力号段/通知号段 只是**本声明占用**；"
                f"布局读不到，就没有任何「哪层是哪段」的依据，"
                f"验证面不能自带一张图（那就是第二个事实源）⇒ 只能由声明方补",
            )
        )
    else:
        # 本空间的**全宽**从 `号段图.json` 的 `命名空间边界` 读（**不在本件里硬编码**）——
        # 判据自带一份边界就是第二个事实源：改了一处、另一处不跟，判据会照旧绿。
        边界表 = _读命名空间边界(号段图, 输出缓冲)
        for 键名 in ("能力号段", "通知号段", "资源号段"):
            位置 = f"{号段图路径}:{键名}"
            布局[键名] = _规范段表(
                号段图.get(键名), 位置, 布局段键, 输出缓冲, "§二 ★ 号段图（全平台布局）"
            )
            空间 = 键名[: -len("号段")] + "号"  # 键名「能力号段」→ 空间名「能力号」（同 `四个号空间互不相通` 的叫法）
            全区间 = 边界表.get(空间)
            if 全区间 is None:
                # 边界读不到 ⇒ **判不了无洞**（不是「通过」）：如实报，别静默降级成「只判相交」
                输出缓冲.append(
                    违规(
                        检查名[3],
                        位置,
                        f"判不了无洞：{号段图路径}:命名空间边界 里没有「{空间}」的全宽",
                        f"没有全宽就判不出「布局铺满没铺满」；判据不能自身带一份边界"
                        f"（那就是第二个事实源）⇒ 只能由声明方补",
                    )
                )
                continue
            _查段表重叠与洞(布局[键名], 位置, 键名, 全区间, 输出缓冲)

        # 错误码段位图：形状与其它三节不同（段位 + 归属，不是 起/止）
        位置 = f"{号段图路径}:错误码段位图"
        段位图 = 号段图.get("错误码段位图")
        if not isinstance(段位图, list) or not 段位图:
            输出缓冲.append(
                违规(
                    检查名[3],
                    位置,
                    f"不是非空列表（是 {type(段位图).__name__}）",
                    f"§二 ★ 号段图 的四节（能力号段 · 通知号段 · 资源号段 · 错误码段位图）"
                    f"缺一节，「段位落在哪个号空间」就没有依据 ⇒ 只能由声明方补",
                )
            )
        else:
            见过段位 = {}
            for 序号, 一条 in enumerate(段位图):
                条位置 = f"{位置}[{序号}]"
                if not isinstance(一条, dict):
                    输出缓冲.append(
                        违规(
                            检查名[3],
                            条位置,
                            f"不是对象（是 {type(一条).__name__}）",
                            f"错误码段位图的条目是 {{段位, 归属}}；不是对象就读不出段位 ⇒ 只能由声明方补",
                        )
                    )
                    continue
                缺失项 = [键名 for 键名 in ("段位", "归属") if 键名 not in 一条]
                if 缺失项:
                    输出缓冲.append(
                        违规(
                            检查名[3],
                            条位置,
                            f"缺 {(' · '.join(缺失项))}（错误码段位图的形状：段位 · 归属）",
                            f"段位是「号段即归属」的入口（§五）；缺归属就判不出这一位归谁 ⇒ 只能由声明方补",
                        )
                    )
                    continue
                if not 是整数(一条["段位"]) or not (0 <= 一条["段位"] <= 9):
                    输出缓冲.append(
                        违规(
                            检查名[3],
                            f"{条位置}:段位",
                            f"段位 不是 0–9 的整数（{一条['段位']!r}）",
                            f"§五：段位 = 码的首位十进制数字（0–9）；超出这个域就取不出码区间 ⇒ 只能由声明方补",
                        )
                    )
                    continue
                if 一条["段位"] in 见过段位:
                    输出缓冲.append(
                        违规(
                            检查名[3],
                            f"{条位置}:段位",
                            f"段位 {一条['段位']} 重复（已在 {见过段位[一条['段位']]} 出现）",
                            f"同一段位在段位图里出现两次 ⇒ 归属有两个答案；删哪一条都会让某个码的归属丢失 ⇒ 只能人来裁",
                        )
                    )
                    continue
                见过段位[一条["段位"]] = 条位置
                # 号段即归属：段位 N 的归属必须与 能力号段 里含 N×1000 的那一段同层
                命中 = [段项 for 段项 in 布局.get("能力号段", []) if 段项[0] <= 一条["段位"] * 1000 <= 段项[1]]
                if 命中 and 层级标签(一条["归属"]) != 层级标签(命中[0][2]):
                    输出缓冲.append(
                        违规(
                            检查名[3],
                            f"{条位置}:归属",
                            f"段位 {一条['段位']} 的归属是「{一条['归属']}」，"
                            f"而 能力号段 里含 {一条['段位'] * 1000} 的那一段归属是「{命中[0][2]}」",
                            f"§五：段位 = 码的首位十进制数字，**也即能力号段的首位**（号段即归属）——"
                            f"两个号空间的同一层必须同归属，否则「段位 2 的码」与「2xxx 能力」"
                            f"归到两个不同的层。改哪边都会让一层改名 ⇒ 只能人来裁",
                        )
                    )
            缺段位 = sorted(set(range(10)) - set(见过段位))
            if 缺段位:
                输出缓冲.append(
                    违规(
                        检查名[3],
                        位置,
                        f"错误码段位图 缺段位 {缺段位}（段位 0–9 应各有一条）",
                        f"§五：段位 0–9 是全部号段位；缺一条，那个段位的码就没有归属依据。"
                        f"补哪一条等于给该层定归属 ⇒ 只能人来裁",
                    )
                )

    # ── (b) 占用（平台声明.json）：形状只有 {起,止}，没有 归属 是对的 ──
    if 平台 is None:
        输出缓冲.append(
            违规(
                检查名[3],
                f"{契约目录名}/平台声明.json",
                "平台声明.json 不存在或解析不了（「占用 ⊆ 布局」无从判）",
                f"占用段是「本声明占哪几段」（§二 ★），也是 平台信息.能力号段/通知号段 的源；"
                f"它读不到，就判不了「本声明有没有占了平台没划给它的号」⇒ 只能由声明方补",
            )
        )
    else:
        for 键名 in ("能力号段", "通知号段"):
            位置 = f"{契约目录名}/平台声明.json:{键名}"
            占用 = _规范段表(
                平台.get(键名), 位置, 占用段键, 输出缓冲,
                "§二 ★ 平台声明（本声明占用；占用段只有 起/止，没有 归属）",
            )
            for 区间起点, 区间终点, _, 段位置 in 占用:
                命中 = [段项 for 段项 in 布局.get(键名, []) if 段项[0] <= 区间起点 and 区间终点 <= 段项[1]]
                if not 命中:
                    输出缓冲.append(
                        违规(
                            检查名[3],
                            段位置,
                            f"占用段 [{区间起点},{区间终点}] 不落在 {号段图路径}:{键名} 的任何一段内"
                            f"（占用 ⊆ 布局 不成立）",
                            f"号段图 是全平台布局（每一段归谁）；占了一段平台没划给任何人的号，"
                            f"等于声称占用了不存在的层。缩占用会丢掉已声明的号，"
                            f"扩布局要同时动 号段图 的 归属 文案（全平台表）⇒ 只能人来裁",
                        )
                    )

    # ── (c) 逐个编号查归属（依据 号段图，不是平台声明的占用）──
    能力段 = 布局.get("能力号段", [])
    通知段 = 布局.get("通知号段", [])
    for 记录 in 上层读数["编号表"]["能力声明"]:
        if 记录["数据"] is None:
            continue
        待处理值 = 记录["数据"].get("编号")
        if not 是整数(待处理值):
            continue
        if not [段项 for 段项 in 能力段 if 段项[0] <= 待处理值 <= 段项[1]]:
            输出缓冲.append(
                违规(
                    检查名[3],
                    f"{契约目录名}/能力声明/{记录['文件名']}:编号",
                    f"能力编号 {待处理值} 不落在 {号段图路径}:能力号段 的任何一段里",
                    f"号段即层级（README 第七节）：号越段就等于能力落错了仓；"
                    f"改号会让已公布编号的含义漂移，改号段会动 号段图 这张全平台表 ⇒ "
                    f"两个方向都动契约 ⇒ 只能人来裁",
                )
            )
    for 记录 in 上层读数["编号表"]["通知号段"]:
        if 记录["数据"] is None:
            continue
        待处理值 = 记录["数据"].get("通知号")
        if not 是整数(待处理值):
            continue
        if not [段项 for 段项 in 通知段 if 段项[0] <= 待处理值 <= 段项[1]]:
            输出缓冲.append(
                违规(
                    检查名[3],
                    f"{契约目录名}/通知号段/{记录['文件名']}:通知号",
                    f"通知号 {待处理值} 不落在 {号段图路径}:通知号段 的任何一段里",
                    f"通知号段是外部协议的两侧派发依据（lib.rs 通知函数 · 通知号段 模块）；"
                    f"改号会让已在跑的对端派发错方向，改号段会动全平台布局表 ⇒ 只能人来裁",
                )
            )

    # ── (d) 类型标签 / 码 的派生范围约束 ──
    # 类型标签不在号段制内（裁决 §七 · `格式说明.md` §十 待裁 3 已就地裁掉）：
    #   ① 是 u32；② **`0–99` 为内核自有**（`契约声明/类型声明/` 里的都在这个段；
    #      扩展从 `100` 起）；③ `4294967295` 是保留的**哨兵**（「错误」），**不参与区间判断**
    #      —— 拿区间判它必然越界，那是把哨兵当普通号。
    # ★ 「`0–99`」而不是待裁原文的「`1–99`」：实测 `契约声明/类型声明/0000.json` 的
    #   `类型标签` 是 **0**（名称「空」：无返回值/无值）—— 0 是内核定义的合法标签，
    #   不是「没填」（`格式说明.md` §四 明说「不许有『把 0 当没填』的判据」）。
    #   本件只扫 `契约声明/` 那一份声明根（`读文件.py::建编号表` 的前缀写死 `契约目录名`）
    #   ⇒ 这里判的正是「内核自有段」；扩展声明根的「≥100」眼下没有判据面（扩展侧 0 份类型声明）。
    哨兵 = 0xFFFFFFFF
    内核标签段 = (0, 99)
    for 记录 in 上层读数["编号表"]["类型声明"]:
        if 记录["数据"] is None:
            continue
        待处理值 = 记录["数据"].get("类型标签")
        if not 是整数(待处理值) or 待处理值 == 哨兵:
            continue
        if not (内核标签段[0] <= 待处理值 <= 内核标签段[1]):
            输出缓冲.append(
                违规(
                    检查名[3],
                    f"{契约目录名}/类型声明/{记录['文件名']}:类型标签",
                    f"类型标签 {待处理值} 越出内核自有段 {内核标签段[0]}–{内核标签段[1]}"
                    f"（哨兵 {哨兵} 除外）",
                    f"类型标签是槽内携带的那个数（§四），槽里只有 u32 给它；"
                    f"内核自有段 `0–99`、扩展从 `100` 起（裁决 §七）—— 越段的标签会与将来"
                    f"扩展标签撞号，而撞号之后同一个数有两种含义，运行期判不出"
                    f"⇒ 只能人来裁（缩号会改已公布标签的含义）",
                )
            )
    for 记录 in 上层读数["编号表"]["错误码表"]:
        if 记录["数据"] is None:
            continue
        待处理值 = 记录["数据"].get("码")
        if 是整数(待处理值) and not (0 <= 待处理值 <= 9999):
            输出缓冲.append(
                违规(
                    检查名[3],
                    f"{契约目录名}/错误码表/{记录['文件名']}:码",
                    f"码 {待处理值} 超出 0–9999（§五：码 = 完整的 4 位号）",
                    f"码的编法是 <段位 1 位><序 3 位>（§五），超 4 位就取不出段位，"
                    f"归属随之丢失；改码会动文件名与全局唯一号 ⇒ 只能人来裁",
                )
            )
    return 输出缓冲
