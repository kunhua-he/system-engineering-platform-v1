"""判据 ④：编号落在自己那一层号段内 + 占用 ⊆ 布局。"""

from __future__ import annotations

from .小工具 import 层级标签, 是整数, 段归属标签, 违规
from .常量 import 占用段键, 号段图路径, 契约目录名, 布局段键, 检查名


def _规范段表(段表, 位置: str, 必填键, 出: list, 谁: str) -> list:
    """把一张段表规范化成 [(起,止,标签,段位置)]；形状问题当场报违规。"""
    规范 = []
    if not isinstance(段表, list) or not 段表:
        出.append(
            违规(
                检查名[3],
                位置,
                f"不是非空列表（是 {type(段表).__name__}）",
                f"{谁} 缺了它，这一层的号就没有归属依据；验证面自带一张表就是第二个事实源 ⇒ 只能由声明方补",
            )
        )
        return 规范
    for 序, 段 in enumerate(段表):
        段位置 = f"{位置}[{序}]"
        if not isinstance(段, dict):
            出.append(
                违规(
                    检查名[3],
                    段位置,
                    f"不是对象（是 {type(段).__name__}）",
                    f"{谁} 的段形状是 {{{(' · '.join(必填键))}}}；不是对象就读不出区间，"
                    f"号归属判不了 ⇒ 只能由声明方补",
                )
            )
            continue
        缺 = [k for k in 必填键 if k not in 段]
        if 缺:
            出.append(
                违规(
                    检查名[3],
                    段位置,
                    f"缺 {(' · '.join(缺))}（{谁} 的段形状：{(' · '.join(必填键))}）",
                    f"归属 是「号段即层级」的落点（README 第七节）：缺归属，"
                    f"号落在段里也判不出属于哪一层 ⇒ 只能由声明方补",
                )
            )
            continue
        if not (是整数(段["起"]) and 是整数(段["止"])):
            出.append(
                违规(
                    检查名[3],
                    f"{段位置}:起/止",
                    f"起/止 不是整数（起={段['起']!r} · 止={段['止']!r}）",
                    f"区间端点按 lib.rs 的 号段{{起:u32,止:u32}} 读；写成字符串"
                    f"会让 Rust 侧与 Python 侧读法分叉 ⇒ 只能由声明方补",
                )
            )
            continue
        if 段["起"] > 段["止"]:
            出.append(
                违规(
                    检查名[3],
                    段位置,
                    f"空段：起 {段['起']} > 止 {段['止']}",
                    f"起>止 的段在 lib.rs 里被定义为「恒不相交的空段」⇒ 这一段实际没有号可用；"
                    f"是笔误还是有意留空，只有声明方能定 ⇒ 只能人来裁",
                )
            )
            continue
        规范.append((段["起"], 段["止"], 段归属标签(段), 段位置))
    return 规范


def _查段表重叠(规范: list, 出: list) -> None:
    """只判两两不相交（不判无洞）——用于命名空间边界未明文的号空间。"""
    排好 = sorted(规范)
    for i in range(len(排好)):
        for j in range(i + 1, len(排好)):
            a, b = 排好[i], 排好[j]
            if b[0] <= a[1]:
                交低, 交高 = max(a[0], b[0]), min(a[1], b[1])
                出.append(
                    违规(
                        检查名[3],
                        f"{a[3]} ↔ {b[3]}",
                        f"号段 [{a[0]},{a[1]}]（{a[2]}）与 [{b[0]},{b[1]}]（{b[2]}）"
                        f"相交，交集 [{交低},{交高}]",
                        f"两段归属不同（{a[2]} / {b[2]}），号落在交集 [{交低},{交高}] 里"
                        f"就有两个归属；缩哪一段都会把已归属该段的号挤出，"
                        f"判据本身定不了 ⇒ 只能人来裁",
                    )
                )


def _查段表重叠与洞(规范: list, 位置: str, 键名: str, 全区间: tuple, 出: list) -> None:
    排好 = sorted(规范)
    for i in range(len(排好)):
        for j in range(i + 1, len(排好)):
            a, b = 排好[i], 排好[j]
            if b[0] <= a[1]:
                交低, 交高 = max(a[0], b[0]), min(a[1], b[1])
                出.append(
                    违规(
                        检查名[3],
                        f"{a[3]} ↔ {b[3]}",
                        f"号段 [{a[0]},{a[1]}]（{a[2]}）与 [{b[0]},{b[1]}]（{b[2]}）"
                        f"相交，交集 [{交低},{交高}]",
                        f"两段归属不同（{a[2]} / {b[2]}），号落在交集 [{交低},{交高}] 里"
                        f"就有两个归属；缩哪一段都会把已归属该段的号挤出，"
                        f"判据本身定不了 ⇒ 只能人来裁",
                    )
                )
    覆盖 = 全区间[0]
    洞表 = []
    for 起, 止, _, _ in 排好:
        if 起 > 覆盖:
            洞表.append((覆盖, 起 - 1))
        覆盖 = max(覆盖, 止 + 1)
    if 覆盖 <= 全区间[1]:
        洞表.append((覆盖, 全区间[1]))
    if 洞表:
        洞文 = " · ".join(f"[{a},{b}]" for a, b in 洞表)
        出.append(
            违规(
                检查名[3],
                位置,
                f"{键名} 的并集有洞：{洞文}（未覆盖 {全区间[0]}–{全区间[1]}）",
                f"§九 第 4 项要求「编号落在自己那一层号段内」——有洞就意味着洞里那些号"
                f"没有任何一层可归属，这一层的号一旦出现就判不了；补哪一段等于给新号"
                f"定归属，是号段级裁决 ⇒ 只能人来裁",
            )
        )


def 检查4_编号落在自己那一层号段内(上: dict) -> list:
    出 = []
    平台 = 上["平台"]
    号段图 = 上["号段图"]

    # ── (a) 布局（号段图.json）：全平台，每段必须带 归属 ──
    布局 = {}
    if 号段图 is None:
        出.append(
            违规(
                检查名[3],
                号段图路径,
                "号段图.json 不存在或解析不了（第 4 项的唯一依据）",
                f"§二 ★：号段图 是**平台的布局**（每一段归谁），"
                f"平台声明.json 的 能力号段/通知号段 只是**本声明占用**；"
                f"布局读不到，就没有任何「哪层是哪段」的依据，"
                f"验证面不能自带一张图（那就是第二个事实源）⇒ 只能由声明方补",
            )
        )
    else:
        for 键名, 全区间 in (
            ("能力号段", (0, 9999)),
            ("通知号段", (1, 2999)),
            # 资源号段的命名空间边界**没有明文**（能力号 0–9999 · 通知号 1–2999 都有），
            # 所以只判「起≤止 + 两两不相交」，不判无洞 —— 见 --缺口
            ("资源号段", None),
        ):
            位置 = f"{号段图路径}:{键名}"
            布局[键名] = _规范段表(
                号段图.get(键名), 位置, 布局段键, 出, "§二 ★ 号段图（全平台布局）"
            )
            if 全区间:
                _查段表重叠与洞(布局[键名], 位置, 键名, 全区间, 出)
            else:
                _查段表重叠(布局[键名], 出)

        # 错误码段位图：形状与其它三节不同（段位 + 归属，不是 起/止）
        位置 = f"{号段图路径}:错误码段位图"
        段位图 = 号段图.get("错误码段位图")
        if not isinstance(段位图, list) or not 段位图:
            出.append(
                违规(
                    检查名[3],
                    位置,
                    f"不是非空列表（是 {type(段位图).__name__}）",
                    f"§二 ★ 号段图 的四节（能力号段 · 通知号段 · 资源号段 · 错误码段位图）"
                    f"缺一节，「段位落在哪个号空间」就没有依据 ⇒ 只能由声明方补",
                )
            )
        else:
            见过段位 = {}
            for 序, 条 in enumerate(段位图):
                条位置 = f"{位置}[{序}]"
                if not isinstance(条, dict):
                    出.append(
                        违规(
                            检查名[3],
                            条位置,
                            f"不是对象（是 {type(条).__name__}）",
                            f"错误码段位图的条目是 {{段位, 归属}}；不是对象就读不出段位 ⇒ 只能由声明方补",
                        )
                    )
                    continue
                缺 = [k for k in ("段位", "归属") if k not in 条]
                if 缺:
                    出.append(
                        违规(
                            检查名[3],
                            条位置,
                            f"缺 {(' · '.join(缺))}（错误码段位图的形状：段位 · 归属）",
                            f"段位是「号段即归属」的入口（§五）；缺归属就判不出这一位归谁 ⇒ 只能由声明方补",
                        )
                    )
                    continue
                if not 是整数(条["段位"]) or not (0 <= 条["段位"] <= 9):
                    出.append(
                        违规(
                            检查名[3],
                            f"{条位置}:段位",
                            f"段位 不是 0–9 的整数（{条['段位']!r}）",
                            f"§五：段位 = 码的首位十进制数字（0–9）；超出这个域就取不出码区间 ⇒ 只能由声明方补",
                        )
                    )
                    continue
                if 条["段位"] in 见过段位:
                    出.append(
                        违规(
                            检查名[3],
                            f"{条位置}:段位",
                            f"段位 {条['段位']} 重复（已在 {见过段位[条['段位']]} 出现）",
                            f"同一段位在段位图里出现两次 ⇒ 归属有两个答案；删哪一条都会让某个码的归属丢失 ⇒ 只能人来裁",
                        )
                    )
                    continue
                见过段位[条["段位"]] = 条位置
                # 号段即归属：段位 N 的归属必须与 能力号段 里含 N×1000 的那一段同层
                命中 = [s for s in 布局.get("能力号段", []) if s[0] <= 条["段位"] * 1000 <= s[1]]
                if 命中 and 层级标签(条["归属"]) != 层级标签(命中[0][2]):
                    出.append(
                        违规(
                            检查名[3],
                            f"{条位置}:归属",
                            f"段位 {条['段位']} 的归属是「{条['归属']}」，"
                            f"而 能力号段 里含 {条['段位'] * 1000} 的那一段归属是「{命中[0][2]}」",
                            f"§五：段位 = 码的首位十进制数字，**也即能力号段的首位**（号段即归属）——"
                            f"两个号空间的同一层必须同归属，否则「段位 2 的码」与「2xxx 能力」"
                            f"归到两个不同的层。改哪边都会让一层改名 ⇒ 只能人来裁",
                        )
                    )
            缺段位 = sorted(set(range(10)) - set(见过段位))
            if 缺段位:
                出.append(
                    违规(
                        检查名[3],
                        位置,
                        f"错误码段位图 缺段位 {缺段位}（段位 0–9 应各有一条）",
                        f"§五：段位 0–9 是全部号段位；缺一条，那个段位的码就没有归属依据。"
                        f"补哪一条等于给该层定归属 ⇒ 只能人来裁",
                    )
                )

    # ── (b) 占用（平台声明.json）：形状只有 {起,止}，没有 归属 是对的 ──
    if 平台 is None:
        出.append(
            违规(
                检查名[3],
                f"{契约目录名}/平台声明.json",
                "平台声明.json 不存在或解析不了（「占用 ⊆ 布局」无从判）",
                f"占用段是「本声明占哪几段」（§二 ★），也是 平台信息.能力号段/通知号段 的源；"
                f"它读不到，就判不了「本声明有没有占了平台没划给它的号」⇒ 只能由声明方补",
            )
        )
    else:
        for 键名 in ("能力号段", "通知号段"):
            位置 = f"{契约目录名}/平台声明.json:{键名}"
            占用 = _规范段表(
                平台.get(键名), 位置, 占用段键, 出,
                "§二 ★ 平台声明（本声明占用；占用段只有 起/止，没有 归属）",
            )
            for 起, 止, _, 段位置 in 占用:
                命中 = [s for s in 布局.get(键名, []) if s[0] <= 起 and 止 <= s[1]]
                if not 命中:
                    出.append(
                        违规(
                            检查名[3],
                            段位置,
                            f"占用段 [{起},{止}] 不落在 {号段图路径}:{键名} 的任何一段内"
                            f"（占用 ⊆ 布局 不成立）",
                            f"号段图 是全平台布局（每一段归谁）；占了一段平台没划给任何人的号，"
                            f"等于声称占用了不存在的层。缩占用会丢掉已声明的号，"
                            f"扩布局要同时动 号段图 的 归属 文案（全平台表）⇒ 只能人来裁",
                        )
                    )

    # ── (c) 逐个编号查归属（依据 号段图，不是平台声明的占用）──
    能力段 = 布局.get("能力号段", [])
    通知段 = 布局.get("通知号段", [])
    for 记录 in 上["编号表"]["能力声明"]:
        if 记录["数据"] is None:
            continue
        值 = 记录["数据"].get("编号")
        if not 是整数(值):
            continue
        if not [s for s in 能力段 if s[0] <= 值 <= s[1]]:
            出.append(
                违规(
                    检查名[3],
                    f"{契约目录名}/能力声明/{记录['文件名']}:编号",
                    f"能力编号 {值} 不落在 {号段图路径}:能力号段 的任何一段里",
                    f"号段即层级（README 第七节）：号越段就等于能力落错了仓；"
                    f"改号会让已公布编号的含义漂移，改号段会动 号段图 这张全平台表 ⇒ "
                    f"两个方向都动契约 ⇒ 只能人来裁",
                )
            )
    for 记录 in 上["编号表"]["通知号段"]:
        if 记录["数据"] is None:
            continue
        值 = 记录["数据"].get("通知号")
        if not 是整数(值):
            continue
        if not [s for s in 通知段 if s[0] <= 值 <= s[1]]:
            出.append(
                违规(
                    检查名[3],
                    f"{契约目录名}/通知号段/{记录['文件名']}:通知号",
                    f"通知号 {值} 不落在 {号段图路径}:通知号段 的任何一段里",
                    f"通知号段是外部协议的两侧派发依据（lib.rs 通知函数 · 通知号段 模块）；"
                    f"改号会让已在跑的对端派发错方向，改号段会动全平台布局表 ⇒ 只能人来裁",
                )
            )

    # ── (d) 类型标签 / 码 的派生范围约束（§十 待裁：它们不在号段制内）──
    for 记录 in 上["编号表"]["类型声明"]:
        if 记录["数据"] is None:
            continue
        值 = 记录["数据"].get("类型标签")
        if 是整数(值) and not (0 <= 值 <= 0xFFFFFFFF):
            出.append(
                违规(
                    检查名[3],
                    f"{契约目录名}/类型声明/{记录['文件名']}:类型标签",
                    f"类型标签 {值} 超出 u32（lib.rs 数据槽.类型标签 是 u32）",
                    f"类型标签是槽内携带的那个数（§四），槽里只有 u32 给它；"
                    f"缩号会改已公布标签的含义，放宽槽宽度是冻结形状改动 ⇒ 只能人来裁",
                )
            )
    for 记录 in 上["编号表"]["错误码表"]:
        if 记录["数据"] is None:
            continue
        值 = 记录["数据"].get("码")
        if 是整数(值) and not (0 <= 值 <= 9999):
            出.append(
                违规(
                    检查名[3],
                    f"{契约目录名}/错误码表/{记录['文件名']}:码",
                    f"码 {值} 超出 0–9999（§五：码 = 完整的 4 位号）",
                    f"码的编法是 <段位 1 位><序 3 位>（§五），超 4 位就取不出段位，"
                    f"归属随之丢失；改码会动文件名与全局唯一号 ⇒ 只能人来裁",
                )
            )
    return 出
