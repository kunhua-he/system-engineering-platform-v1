def _挪进程起点到此刻():
    """把 `验证` 模块里的「进程起始时刻」临时挪到**现在**，返回 `(模块, 原值)`。

    ★ 为什么需要它（实测撞到过，别删）：⑱ 量的是「**进程启动** → 此刻」的墙钟
      ⇒ 在 `--自测` 里它读到的自然包含「本次自测已经跑了多久」。而本文件的几条
      正向样本问的是「一条**新命令**在干净仓上跑 ⇒ ⑱ 不红」—— 与 `--自测` 自身的年龄无关。
      不挪的话，`--自测` 一旦整体变慢（实测：对象数读数那一段误改成建线程池，
      进程总墙钟被顶过 5000 ms）这几条正向样本就**假红**，而根因跟被验的事毫无关系。
      挪成「现在」= 模拟一条刚启动的命令 ⇒ 量的是它该量的东西。
      调用方负责在 `finally` 里还原（`验证模块.进程起始时刻 = 原值`）。
    """
    模块 = sys.modules[跑全量判据.__module__]
    原值 = 模块.进程起始时刻
    模块.进程起始时刻 = time.perf_counter()
    return 模块, 原值


def 自检_延迟判据承重() -> list:
    """判据 ⑱（命令墙钟 ≤ 硬顶）的身份证 + 承重证明。

    四层：
      · 反向样本（**真读数**）：硬顶临时压到 0 ms ⇒ ⑱ 报红，读数带**实际**毫秒（>0）。
      · 承重证明（退回一步·阈值恢复 5000）：同一仓 ⇒ 不红 ⇒ 证明那条红不是恒真，
        是由「读数 > 硬顶」共同承重。
      · 承重证明（退回一步·判据关掉）：硬顶仍是 0，但把 检查表 里 ⑱ 换成空转
        （模拟「修法退回一步 = 没有这条判据」）⇒ 不报 ⇒ 证明那条红确实由 ⑱ 承重，
        不是别的判据顺带报的。
      · 正向样本：硬顶 5000、干净仓 ⇒ 不红。

    真·>5 s 的一次性承重证明（不在本函数里跑 —— 它会睡满 5 s、把 `--自测` 顶过它自身的硬顶）：
    见 `--缺口` 与文件头「⑱ 承重证明」那段：给进程起始后注入 >5 s 真延时 ⇒ ⑱ 红、退出码 1。
    """
    import tempfile

    输出缓冲 = []
    名称 = 检查名[17]
    真硬顶 = 常量.硬顶毫秒

    def 跑自检(硬顶, 关判据=False):
        with tempfile.TemporaryDirectory(prefix="一键验证延迟承重-") as 临时:
            临根 = Path(临时) / "仓"
            造干净仓(临根)
            原硬顶 = 常量.硬顶毫秒
            原表 = 判据表.检查表
            验证模块, 原起 = _挪进程起点到此刻()
            try:
                常量.硬顶毫秒 = 硬顶
                if 关判据:
                    # 「判据关掉」= ⑱ 的判据函数换成空转（名字仍在 检查表 里 ⇒ 检查14 ④ 不受影响）
                    判据表.检查表 = tuple(
                        (判据名, (lambda 上层读数: []) if 判据名 == 名称 else 判据函数) for 判据名, 判据函数 in 原表
                    )
                return 跑全量判据(临根, 两遍=False)
            finally:
                常量.硬顶毫秒 = 原硬顶
                验证模块.进程起始时刻 = 原起
                判据表.检查表 = 原表

    def 筛明细(结果):
        return [
            明细条
            for 明细条 in (结果["失败"] + 结果["未判"])
            if isinstance(明细条, dict) and 明细条["检查"] == 名称
        ]

    失效 = 跑自检(0)
    失效条 = 筛明细(失效)
    恢复 = 跑自检(真硬顶)
    关掉 = 跑自检(0, 关判据=True)

    输出缓冲.append(
        (
            "反向样本（真读数）：硬顶压到 0 ms ⇒ ⑱ 报红，读数带实际毫秒",
            bool(失效条) and all("ms" in 明细条["缺什么"] for 明细条 in 失效条),
            f"⑱ 报 {len(失效条)} 条：{[明细条['缺什么'] for 明细条 in 失效条][:1]}",
        )
    )
    输出缓冲.append(
        (
            "承重证明（退回一步·阈值恢复 5000）：同一仓 ⇒ ⑱ 不红",
            not 筛明细(恢复),
            f"⑱ 报 {len(筛明细(恢复))} 条（要求 0）——证明上面那条红不是恒真",
        )
    )
    输出缓冲.append(
        (
            "承重证明（退回一步·判据关掉）：硬顶仍 0 但 ⑱ 换成空转 ⇒ 不报",
            not 筛明细(关掉),
            f"⑱ 报 {len(筛明细(关掉))} 条（要求 0）——证明那条红由 ⑱ 承重，不是别的判据顺带报的",
        )
    )
    输出缓冲.append(
        (
            "正向样本：硬顶 5000、干净合成仓 ⇒ ⑱ 不红",
            not 筛明细(恢复),
            f"⑱ 报 {len(筛明细(恢复))} 条（要求 0）",
        )
    )
    # 尾巴自证：⑱ 的读数（进程启动 → 两遍判据跑完）与**真墙钟**（再含结果装配 + 打印）
    # 之差必须小 —— `--缺口` 里登记的那条「读数不含 80 ms 尾巴」不靠估，这里直接量。
    import io

    with tempfile.TemporaryDirectory(prefix="一键验证延迟尾巴-") as 临时:
        临根 = Path(临时) / "仓"
        造干净仓(临根)
        注入_常量重定义(临根)  # 造一条失败明细，让「打印」那段尾巴真的发生
        尾巴果 = 跑全量判据(临根)
        读数 = 尾巴果["上下文"].get("本命令墙钟毫秒")
        打印验证结果(尾巴果, io.StringIO())
        真墙钟 = int((time.perf_counter() - 进程起始时刻) * 1000)
    尾巴 = 真墙钟 - (读数 or 0)
    输出缓冲.append(
        (
            "尾巴自证：⑱ 读数 与 真墙钟（含结果装配 + 打印）之差 < 200 ms",
            0 <= 尾巴 < 200,
            f"读数 {读数} ms · 真墙钟 {真墙钟} ms · 尾巴 {尾巴} ms（要求 0 ≤ 尾巴 < 200）",
        )
    )
    return 输出缓冲


def 自检_两遍复核收窄() -> list:
    """「第二遍只复核第一遍报出东西的判据」这条提速的身份证（**不许静默降级**）。

    判法：给 检查表 里每条判据套一个计数器，看每轮到底跑了几次。
      · 正向样本：干净合成仓 ⇒ 每条判据**恰好 1 次**（第一遍全空 ⇒ 第二遍整条不跑）。
      · 反向样本：注入一处真违规（常量重定义 ⇒ ⑬）⇒ **只有 ⑬ 跑 2 次**、其余仍 1 次
        （证明「报了的照样两遍复核」没被收窄掉）。
      · 对照（退回一步）：`提速开关 = False`（退回两遍全量）⇒ 同一干净仓上每条跑 **2 次**
        ⇒ 证明这条收窄真在省一半成本（不是空转），且旧行为确实是全量两遍。
      · 结论不变：干净仓上「收窄后」与「退回全量」都全过；注入仓上 ⑬ 都是**真红**。
    """
    import tempfile

    输出缓冲 = []
    计数: dict = {}

    def 带计数(原表):
        def 包计数(函数, 名称):
            def 计数包装(上层读数):
                计数[名称] = 计数.get(名称, 0) + 1
                return 函数(上层读数)

            return 计数包装

        return tuple((名称, 包计数(函数, 名称)) for 名称, 函数 in 原表)

    原表 = 判据表.检查表
    真提速 = 常量.提速开关

    def 跑一遍自检(注入=None, 提速=True):
        with tempfile.TemporaryDirectory(prefix="一键验证两遍收窄-") as 临时:
            临根 = Path(临时) / "仓"
            造干净仓(临根)
            if 注入 is not None:
                注入(临根)
            计数.clear()
            验证模块, 原起 = _挪进程起点到此刻()  # 同 `_挪进程起点到此刻` 的理由
            try:
                判据表.检查表 = 带计数(原表)
                常量.提速开关 = 提速
                return 跑全量判据(临根), dict(计数)
            finally:
                判据表.检查表 = 原表
                常量.提速开关 = 真提速
                验证模块.进程起始时刻 = 原起

    净果, 净计数 = 跑一遍自检()
    注果, 注计数 = 跑一遍自检(注入=注入_常量重定义)
    旧果, 旧计数 = 跑一遍自检(提速=False)

    常量名 = 检查名[12]
    全名 = {名称 for 名称, _ in 原表}
    输出缓冲.append(
        (
            "正向样本：干净仓 ⇒ 每条判据恰好跑 1 次（第二遍整条不跑）",
            set(净计数) == 全名 and max(净计数.values()) == 1,
            f"跑过的判据 {len(净计数)}/{len(全名)} 条 · 最多的跑 {max(净计数.values())} 次"
            f"（要求 1）",
        )
    )
    # 收窄的**真正不变量**是「**报出东西的判据**才跑第二遍」（`验证` 里 `需复核` 的定义），
    # 不是「只有 ⑬ 跑第二遍」—— 注入件同时踩中几条判据是正常的（例：⑲ 行数硬数会因为
    # 那个注入件往入口 `lib.rs` 里写了实现而报出东西）。断言写成「两边集合相等」，
    # 与注入踩中几条无关，故它不会因为判据条数增加而失效。
    注报 = {一条["检查"] for 一条 in (注果["失败"] + 注果["未判"]) if isinstance(一条, dict)}
    二遍 = {判据名 for 判据名, 次数 in 注计数.items() if 次数 == 2}
    输出缓冲.append(
        (
            "反向样本：注入真违规（常量重定义）⇒ **报出东西的判据**跑 2 次、其余仍 1 次",
            注计数.get(常量名) == 2 and 二遍 == 注报,
            f"⑬ 跑 {注计数.get(常量名)} 次 · 跑 2 次的判据 {len(二遍)} 条 · 报出东西的判据 "
            f"{len(注报)} 条 · 两者{'一致' if 二遍 == 注报 else '不一致：' + str(sorted(二遍 ^ 注报))}",
        )
    )
    输出缓冲.append(
        (
            "对照（退回一步·提速开关 False）：同一干净仓 ⇒ 每条跑 2 次（旧的全量两遍）",
            set(旧计数) == 全名 and max(旧计数.values()) == 2,
            f"跑过的判据 {len(旧计数)}/{len(全名)} 条 · 最多的跑 {max(旧计数.values())} 次"
            f"（要求 2）——证明收窄真在省一半成本",
        )
    )
    输出缓冲.append(
        (
            "结论不变：干净仓 收窄 / 全量 都全过 · 注入仓 ⑬ 在两种口径下都是真红",
            not 净果["失败"]
            and not 净果["未判"]
            and not 旧果["失败"]
            and not 旧果["未判"]
            and any(
                isinstance(明细条, dict) and 明细条["检查"] == 常量名 for 明细条 in 注果["失败"]
            ),
            f"净 失败 {len([明细条 for 明细条 in 净果['失败'] if isinstance(明细条, str)])} · "
            f"旧 失败 {len([明细条 for 明细条 in 旧果['失败'] if isinstance(明细条, str)])} · "
            f"注入仓 ⑬ 在 失败 里={any(isinstance(明细条, dict) and 明细条['检查'] == 常量名 for 明细条 in 注果['失败'])}",
        )
    )
    return 输出缓冲
