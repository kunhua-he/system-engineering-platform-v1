"""判据 ㊷ 的身份证（解析器那一层）：三面扫描器与名册判定的**承重证明**。

为何单列：`判据的可信性.md` §三.5「判据的解析器坏了」是假绿来源之一 —— 本条吃**三面**
（定义面 · 形参面 · 局部面），而旧口径只吃定义面 ⇒ 必须证「那两面真在判」（退回一步就必漏）。
"""
from __future__ import annotations

import sys

from . import 常量


def 取命名穷举():
    """惰性取**共享实现**（`开发工具/信息核心/命名穷举.py`）—— 口径只此一份。"""
    根目录 = str(常量.仓根 / "开发工具" / "信息核心")
    if 根目录 not in sys.path:
        sys.path.insert(0, 根目录)
    import 命名穷举

    return 命名穷举


# 一份最小样本：`.rs` 一个形参 + 一个局部；`.py` 一个形参 + 一个局部（两面各两种后缀）。
# ★ 名字**不取十干字**（判据 ㊵ 逐字节扫全树，字符串里的十干也算）—— 用实义词。
样例件 = {
    "样例.rs": "pub fn 样例(形参取值源: u32) -> u32 {\n    let 局部暂存值 = 形参取值源;\n    局部暂存值\n}\n",
    "样例.py": "def 样例(形参入参表):\n    局部累计值 = 形参入参表\n    return 局部累计值\n",
}


def 自检_命名穷举三面() -> list:
    """三面扫描器 + 名册判定的正 / 反样本 + **承重证明**（退回一步 ⇒ 必漏）。"""
    穷举 = 取命名穷举()
    输出缓冲 = []
    形参名集 = {出现名 for 出现名, _所在件, _行号 in 穷举.扫形参面(样例件)}
    局部名集 = {出现名 for 出现名, _所在件, _行号 in 穷举.扫局部面(样例件)}
    输出缓冲.append(("正向样本：形参面 ⇒ 抓得住", 形参名集 == {"形参取值源", "形参入参表"},
                    "命中 = %s" % sorted(形参名集)))
    输出缓冲.append(("正向样本：局部面 ⇒ 抓得住", 局部名集 == {"局部暂存值", "局部累计值"},
                    "命中 = %s" % sorted(局部名集)))
    出现表 = {"形参面": sorted(穷举.扫形参面(样例件))}
    未登记 = 穷举.判未登记(出现表, {"形参取值源"}, set())
    输出缓冲.append(("反向样本：名册只收一个 ⇒ 另一个必报未登记",
                     set(未登记["形参面"]) == {"形参入参表"},
                     "未登记 = %s" % sorted(未登记["形参面"])))
    只定义面 = 穷举.扫定义面(None)
    输出缓冲.append(("承重证明（退回一步）：只扫定义面 ⇒ 形参面整层漏",
                     bool(形参名集)
                     and not any(出现名 in {"形参取值源", "形参入参表"}
                                 for 出现名, _所在件, _行号 in 只定义面),
                     "定义面 %d 条 · 形参面 %d 条" % (len(只定义面), len(形参名集))))
    return 输出缓冲
