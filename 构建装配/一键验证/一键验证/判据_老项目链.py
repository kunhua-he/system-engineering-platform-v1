# -*- coding: utf-8 -*-
"""判据 64：老项目翻译链 —— 翻译 → 读回，三类类型逐项对得上。

**为什么立它**：这条链（老项目模块 `能力定义.json` → 翻译器 → 扩展声明根 → 消费侧读回）
一直只是**手工跑通** —— 读数是人手打命令打出来的，闸里没有一条判据守它。手工读数不防重犯：
改坏了没人知道。口径是「已修缺陷抽判据进闸 · 新判据必带反向样本」。

**面**：仓内夹具老项目模块（`测试验证/老项目样本/样本接入模块/能力定义.json`）。
**规则**：拿真翻译器跑它，逐项断言 ——
  · 列表型参数：能力声明的参数表里真出现 100 号标签（不是「类型名写对了但没落标签」）
  · 结果型结构：有能力的 `返回类型` 是 103，且 103 的元素表里真嵌着 100 号标签
  · 文本默认值：有参数的默认值形如 `{类型标签: 4, 文本: 空串}` —— 显式空文本，不是「没给」
  · 逻辑默认值：有参数的默认值形如 `{类型标签: 3, 值: 0}` —— 显式假，不是「没给」
  · 保真损失：翻译来源的 `保真损失` 必须是空表
**测哪一份**：夹具从**被扫仓**取（真仓 / 反向样本的注入仓）；翻译器从**本验证器所在仓**取
（夹具仓是合成仓，没有 `开发工具/`）—— 本条的对象是「本仓的翻译链」，与夹具无关
（同判据 60 的口径）。
**三元读数**：通过 = 夹具在、翻译跑得出、逐项全对；失败 = 逐项报出；未判 = 夹具不在
或翻译器不在。
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

from .验证小工具 import 判不了, 违规
from .常量 import 仓根, 检查名

夹具相对路径 = "测试验证/老项目样本/样本接入模块/能力定义.json"
翻译器相对路径 = "开发工具/老项目接入/老项目模块翻译.py"
依赖目录相对路径 = "开发工具/老项目接入"
翻译超时秒 = 5
列表型标签 = 100
结果型标签 = 103
文本型标签 = 4
逻辑型标签 = 3


def _读JSON(件路径: Path):
    """读一份 JSON ⇒ 字典；读不出或不是字典就给 None（调用方按缺件报）。"""
    try:
        件内容 = json.loads(件路径.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return 件内容 if isinstance(件内容, dict) else None


def _跑翻译(夹具模块目录: Path, 出根: Path, 来源目录: Path) -> tuple:
    """真跑翻译器 ⇒ `(退出码, 输出尾)`。翻译器从本验证器所在仓取（合成仓没有它）。"""
    命令 = [
        sys.executable, str(Path(仓根) / 翻译器相对路径),
        "--源目录", str(夹具模块目录),
        "--老项目根", str(夹具模块目录.parent),
        "--输出", str(出根),
        "--来源目录", str(来源目录),
        "--依赖目录", str(Path(仓根) / 依赖目录相对路径),
    ]
    翻译结果 = subprocess.run(命令, capture_output=True, text=True, timeout=翻译超时秒)
    return 翻译结果.returncode, ((翻译结果.stdout or "") + (翻译结果.stderr or "")).strip()


def _查三类类型(出根: Path) -> list:
    """三类类型逐项查 ⇒ 问题清单（空表 = 全对）。"""
    问题表 = []
    类型目录 = 出根 / "类型声明"
    能力目录 = 出根 / "能力声明"
    if not 类型目录.is_dir() or not 能力目录.is_dir():
        return ["翻译产物里没有 `类型声明/` 或 `能力声明/` 目录"]
    标签表 = {}
    for 声明件 in sorted(类型目录.glob("*.json")):
        件内容 = _读JSON(声明件)
        if 件内容 and isinstance(件内容.get("类型标签"), int):
            标签表[件内容["类型标签"]] = 件内容
    if 列表型标签 not in 标签表:
        问题表.append("`类型声明/` 里没有 100 号（列表型）—— 列表型参数无处落标签")
    结果件 = 标签表.get(结果型标签)
    if 结果件 is None:
        问题表.append("`类型声明/` 里没有 103 号（结果型结构）")
    else:
        元素标签 = [元素项.get("类型标签") for 元素项 in (结果件.get("元素表") or [])
                    if isinstance(元素项, dict)]
        if 列表型标签 not in 元素标签:
            问题表.append("103 的元素表里没有 100 号 —— 结果型结构里嵌的列表型字段丢了")
    能力表 = []
    for 声明件 in sorted(能力目录.glob("*.json")):
        件内容 = _读JSON(声明件)
        if 件内容:
            能力表.append(件内容)
    if not 能力表:
        问题表.append("`能力声明/` 目录里一件有效声明也没有")
        参数项表 = []
    else:
        参数项表 = [参数项 for 件内容 in 能力表 for 参数项 in (件内容.get("参数表") or [])
                  if isinstance(参数项, dict)]
        if 列表型标签 not in [参数项.get("类型标签") for 参数项 in 参数项表]:
            问题表.append("能力声明的参数表里没有 100 号 —— 列表型参数没落成标签")
        if 结果型标签 not in [件内容.get("返回类型") for 件内容 in 能力表]:
            问题表.append("没有一条能力的 `返回类型` 是 103 —— 结果型结构没落成返回类型")
    默认值表 = [参数项["默认值"] for 参数项 in 参数项表
              if isinstance(参数项.get("默认值"), dict)]
    if not [默认值 for 默认值 in 默认值表
            if 默认值.get("类型标签") == 文本型标签 and 默认值.get("文本") == ""]:
        问题表.append("没有参数带 `{类型标签: 4, 文本: 空串}` —— 文本型显式空默认值丢了")
    if not [默认值 for 默认值 in 默认值表
            if 默认值.get("类型标签") == 逻辑型标签 and 默认值.get("值") == 0]:
        问题表.append("没有参数带 `{类型标签: 3, 值: 0}` —— 逻辑型显式默认值丢了")
    return 问题表


def 扫老项目链(上层读数: dict) -> tuple:
    """⇒ `(问题清单, 对象数)`。对象数 = 夹具在不在（0 ⇒ 未判）。"""
    夹具件 = Path(上层读数["仓根"]) / 夹具相对路径
    if not 夹具件.is_file():
        return [], 0
    if not (Path(仓根) / 翻译器相对路径).is_file():
        return ["翻译器不在（%s）—— 链的入口无从真跑" % 翻译器相对路径], 1
    with tempfile.TemporaryDirectory(prefix="老项目链判据-") as 临时根:
        出根 = Path(临时根) / "样本接入模块"
        来源目录 = Path(临时根) / "来源"
        退出码, 输出尾 = _跑翻译(夹具件.parent, 出根, 来源目录)
        if 退出码 != 0:
            return ["翻译器没跑通（退出码 %d）：%s" % (退出码, 输出尾[-400:])], 1
        来源 = _读JSON(来源目录 / "样本接入模块.翻译来源.json")
        if 来源 is None:
            return ["翻译来源.json 读不出 ⇒ 保真损失无从核"], 1
        if "保真损失" not in 来源:
            return ["翻译来源里没有 `保真损失` 键 ⇒ 保真损失无从核"], 1
        if 来源["保真损失"]:
            return ["保真损失不是空表：%s"
                    % json.dumps(来源["保真损失"], ensure_ascii=False)[:300]], 1
        return _查三类类型(出根), 1


def 检查64_老项目翻译链(上层读数: dict) -> list:
    """老项目模块经翻译器出声明根、再被读回 —— 三类类型逐项对得上。"""
    输出缓冲 = []
    问题表, 对象数 = 扫老项目链(上层读数)
    if not 对象数:
        判不了(
            检查名[52],
            夹具相对路径,
            "夹具老项目模块不在 ⇒ 「翻译 → 读回 三类类型」这一条判不了",
            "本条的对象是仓内夹具；夹具被删或搬走就判不了。**判不了不许算通过**"
            "（空集是未判，不是通过）⇒ 只能由判据作者确认夹具落点",
        )
        return 输出缓冲
    for 问题 in 问题表:
        输出缓冲.append(
            违规(
                检查名[52],
                夹具相对路径,
                问题,
                "修法：这条链的对象是**三类类型的翻译与读回**（列表型参数 · 结果型结构 · "
                "文本默认值 · 逻辑默认值）。先看是哪一段丢的 —— 翻译器把类型名映射成标签、"
                "产物按标签落盘、读回按标签取。**不许把断言放宽成「件在位」**（那是自证）⇒ "
                "只能由翻译链的负责方按真产物改",
            )
        )
    return 输出缓冲


def 样本_老项目链面(上层读数: dict) -> int:
    """对象数：夹具在不在（0 ⇒ 未判）。"""
    return 扫老项目链(上层读数)[1]
