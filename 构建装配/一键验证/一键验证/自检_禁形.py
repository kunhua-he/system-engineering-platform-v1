"""解析器的身份证 · 判据 ㊺（命名定义现状禁形）：拆行口径的正反样本。

为什么单列：`判据的可信性.md` §三.5「判据的解析器坏了」是假绿来源之一 —— `现状` 列的
拆行（`（名即语义）` 跳过 · `→` 行取 `唯一名` 栏 · 其余取 `现状` 栏）是判据 ㊺ 的眼睛，
它自身也要有反向样本（该收的禁形收得到）与正向样本（干净行不许报出禁形）。
"""
from __future__ import annotations

from .判据_禁形 import 拆禁形


def 自检_禁形拆行() -> list:
    """判据 ㊺ 的拆行口径：五种形状的正反样本（纯函数，不依赖库/仓）。"""
    输出缓冲 = []
    断言 = (
        ("名即语义 ⇒ 无禁形", 拆禁形("（名即语义）", "`任意名`") == []),
        ("已合规，不动 ⇒ 无禁形", 拆禁形("已合规，不动", "`任意名`") == []),
        ("现状列出禁形（`旧一` · `旧二`）⇒ 两个都收",
          sorted(拆禁形("`旧一` · `旧二`", "`新名`")) == ["旧一", "旧二"]),
        ("箭头形（待改名 → 新名）⇒ 禁形取唯一名栏，去掉箭头右侧的新名",
         拆禁形("待改名 → 新名", "`旧名` · `新名`") == ["旧名"]),
        ("括号注解不算是名的一部分", 拆禁形("`旧`（某处）", "`新`") == ["旧"]),
    )
    for 名称, 是否好 in 断言:
        输出缓冲.append((名称, 是否好, "拆禁形 的实测见用例"))
    return 输出缓冲
