# -*- coding: utf-8 -*-
"""注入样本 · 判据 54（后缀表唯一）· 判据 55（名册新鲜度）。

两条合一件（拆法照 `注入_台账号.py` 的先例）：都是「本腿新立的判据」的身份证，关注点相邻。
"""
from __future__ import annotations

from pathlib import Path


# ── 判据 54：后缀表唯一 ───────────────────────────────────
# 第二处定义（反向样本的靶）：一个**不在权威白名单**里的件里又写一份 `代码后缀 = (...)`。
# 形状就是实测撞到的那一条：三处局部定义各自一份、内容各不相同。
第二处定义件 = "构建装配/样例/后缀表副本.py"


def 注入_第二处后缀定义(临根: Path) -> str:
    """在合成仓里放一份**又定义了一遍** `代码后缀` 的 `.py` ⇒ 判据 54 当场红。

    值刻意与权威不同（只五个后缀）—— 正是实测撞到的那个形状（缺 `.swift`）。
    """
    路径 = 临根 / 第二处定义件
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "# 反向样本：本件又定义了一遍后缀表（缺 .swift）。\n"
        '代码后缀 = (".rs", ".py", ".js", ".ts", ".vue")\n'
        '\n\ndef 取后缀() -> tuple:\n    return 代码后缀\n',
        encoding="utf-8",
    )
    return 第二处定义件


# ── 判据 55：名册新鲜度 ───────────────────────────────────
# 反向样本的形状就是实测撞到的那一条：盘上新增了标识符、名册（`命名登记`）没跟着动。
# 这里在夹具仓放一个含**全新标识符**的代码件 ⇒ 现场重扫会写它、而夹具库 `命名登记` 里没有
# （夹具名册按**建库时**的干净代码派生）⇒ 「盘上有、登记里没有」当场红。
# ★ 不能用「名册为空」造差（那是 0 对象 ⇒ 未判，不是失败）。
# ★ 改的是**现场**（新增件），不是库：判据 55 已改比**受版本的权威登记名集** `命名登记`
#   （`命名出现` 搬进了非版本派生库，见 `表定义.派生表`）—— 新名进写口名集、而不在登记里。

# 反向样本的靶件（含一个夹具干净代码里没有的标识符）。
名册没跟上件 = "构建装配/样例/名册没跟上样本.py"
# 该件里的新标识符（夹具库名册按夹具**干净代码**派生 ⇒ 它不在名册里）。
名册没跟上名 = "名册新鲜度样本名字"


def 注入_名册没跟上(临根: Path) -> str:
    """在夹具仓放一个含**全新标识符**的代码件 ⇒ 判据 55 当场红（盘上新名未登记）。

    返回**库件相对路径**（断言②要求报出的位置里含它；判据的报出位置是
    `开发工具/信息核心/信息核心.db::命名登记::<名>`）。
    """
    路径 = 临根 / 名册没跟上件
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "# 反向样本：本件引入一个夹具名册里没有的新标识符。\n"
        f"def {名册没跟上名}():\n"
        f"    return {名册没跟上名}\n",
        encoding="utf-8",
    )
    return "开发工具/信息核心/信息核心.db"
