# -*- coding: utf-8 -*-
"""注入样本 · 判据 54（后缀表唯一）· 判据 55（名册新鲜度）。

两条合一件（拆法照 `注入_台账号.py` 的先例）：都是「本腿新立的判据」的身份证，关注点相邻。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path


# ── 判据 54：后缀表唯一 ───────────────────────────────────
# 第二处定义（反向样本的靶）：一个**不在权威白名单**里的件里又写一份 `代码后缀 = (...)`。
# 形状就是实测撞到的那一条：三处局部定义各自一份、内容各不相同。
第二处定义件 = "构建装配/样例/后缀表副本.py"


def 注入_第二处后缀定义(临根: Path) -> str:
    """在合成仓里放一份**又定义了一遍** `代码后缀` 的 `.py` ⇒ 判据 54 当场红。

    值刻意与权威不同（只五个后缀）—— 正是实测撞到的那个形状（缺 `.swift`）。
    """
    路径 = 临根 / 第二处定义件
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "# 反向样本：本件又定义了一遍后缀表（缺 .swift）。\n"
        '代码后缀 = (".rs", ".py", ".js", ".ts", ".vue")\n'
        '\n\ndef 取后缀() -> tuple:\n    return 代码后缀\n',
        encoding="utf-8",
    )
    return 第二处定义件


# ── 判据 55：名册新鲜度 ───────────────────────────────────
# 反向样本的形状就是实测撞到的那一条：改名改了、名册（`命名出现`）没跟着动。
# 这里把夹具规则库 `命名出现` 里的一个名改成另一个拼法 ⇒
# 「写口会写的名」里有新拼法（库里无）且库里那名已不再被写（库里挂着） ⇒ 两向差都出。
# ★ 不能用「名册为空」造差（那是 0 对象 ⇒ 未判，不是失败）。

def 注入_名册没跟上(临根: Path) -> str:
    """把夹具规则库 `命名出现` 里的一个名改成另一个拼法 ⇒ 判据 55 当场红（两向差都出）。

    改 `命名出现`（不是 `命名登记`）：判据比的是**出现面**与现场重扫的差。
    返回**库件相对路径**（断言②要求报出的位置里含它；判据的报出位置是 `命名出现：<名>`）。
    """
    库相对路径 = "开发工具/信息核心/信息核心.db"
    库件 = 临根 / 库相对路径
    if not 库件.is_file():
        # 夹具仓没建库 ⇒ 造不出这条反向样本（判据会报「库不在」）——
        # 照实返回路径，断言①仍成立（退出码非 0）。
        return 库相对路径
    连接 = sqlite3.connect(库件)
    try:
        现有 = [文本行[0] for 文本行 in 连接.execute("select distinct 名字 from 命名出现 limit 1")]
        if 现有:
            旧名 = 现有[0]
            连接.execute("update 命名出现 set 名字 = ? where 名字 = ?", (旧名 + "_陈", 旧名))
            连接.commit()
    finally:
        连接.close()
    return 库相对路径
