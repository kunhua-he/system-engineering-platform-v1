# ── 判据 ㊴：引用可解析 ──────────────────────────────────────────────────────────────────

def 读引用基线(树根) -> tuple:
    """⇒ `({(件, 名, 节号)}, {已删件名}, 错误或 None)` —— 两面分开存（对应判据 ㊴ 的三元读数）：

      · 悬空面 —— 键 `(件, 名, 节号)`：目标件在、却没有那个节；
      · 未判面 —— **已删件名册**（目标件在盘上一件都匹配不到；粒度是件名，与「哪一处引的 · 引的
        第几节」无关，见判据 ㊴ 审计 N2 修）。
    两读其一坏即整体交错误回去（判据 fail-closed）。
    """
    键表, 错误 = _读键集(树根, 表_引用, lambda 一行: (一行[0], 一行[1], int(一行[2])))
    if 错误:
        return set(), set(), 错误
    名表, 错误 = _读键集(树根, 表_引用未判, lambda 一行: 一行[0])
    return 键表, 名表, 错误


def 写引用基线(树根, 键集, 名集) -> int:
    _写一张(树根, 表_引用, [tuple(键名) for 键名 in sorted(键集)])
    return _写一张(树根, 表_引用未判, [(件名,) for 件名 in sorted(名集)])


def 读条款标题(树根) -> tuple:
    """⇒ `([(文档路径, 标题)], 错误或 None)` —— 判据 ㊴ 拿它把引用**解到 `条款` 表**
    （md 已删、正文住库；解到就能与磁盘件同口径判「节在不在」，见 `引用扫描.条款节集`）。
    读不动 ⇒ 交错误回去（调用方据此退回磁盘面，不假装「无此件」）。
    """
    库件 = Path(树根) / 库相对路径
    if not 库件.is_file():
        return [], f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute("select 文档路径, 标题 from 条款"))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return [], f"`条款` 读不动：{错误}"
    return [(路径, 标题 or "") for 路径, 标题 in 行表], None


