# -*- coding: utf-8 -*-
"""判据基线 —— 判据 ⑲ / ㉕ / ㊴ / ㊵ 的**存量清单**读写（住规则库四张表，**不落外部 json**）。

四张表都是「存量入基线、新增即红 · 基线只许减」那一套（判据 ⑲ 先立的形状）：
  · `行数基线`     —— 判据 ⑲ 的三类：`(类别, 路径, 处数)`（类别 = 超行数 / 入口超行数 / 入口有实现）；
  · `运行数据基线` —— 判据 ㉕ 的四形：`(路径, 形, 处数)`；
  · `引用基线`     —— 判据 ㊴ 的悬空引用：`(件, 名, 节号)`（是集合，无处数）；
  · `引用未判基线` —— 判据 ㊴ 未判面的已删件名：`(件名)`（是集合，无处数）；
  · `台账号基线`   —— 判据 ㊳ 的台账引用：`(件, 形)`；
  · `底座扩展名基线` —— 判据 ⑯ 注释面的点名：`(件, 名)`；
  · `十干基线`     —— 判据 ㊵ 的字面十干：`(件, 码位, 处数)`；
  · `禁译名基线`   —— 判据 ㊹ 的字面禁译名：`(件, 处数)`；
  · `命名禁形基线` —— 判据 ㊺ 的命名定义现状禁形：`(禁形, 处数)`；
  · `硬写能力号基线` —— 判据 ㊻ 的硬写能力号：`(件, 号, 处数)`（号按十进制文本存）。

**为何住库**（华哥 2026-09-29「全规则都在 db 里面。外部不留」）：基线是判据的**对象**，与名册
同一类东西。住库 ⇒ 夹具仓只要有一张最小库就照跑，不再多一份 json 要跟着维护。重冻（只许减）
走 `信息核心.py 冻结基线`；判定侧**永远只读**。

**面各只一份**：四张表的读写只此一处 —— 判据、夹具、冻结都调它，不各写一套。
"""
from __future__ import annotations

import sqlite3
import sys
from pathlib import Path


def _取表定义():
    """惰性取**表结构主人**（`开发工具/信息核心/表定义.py`）—— 库路径只此一份。

    取法照 `夹具规则库.取表定义` 的先例：本包不另写一份库路径字面量（全仓曾有多份）。
    """
    工具根 = Path(__file__).resolve().parents[3]
    根目录 = str(工具根 / "开发工具" / "信息核心")
    if 根目录 not in sys.path:
        sys.path.insert(0, 根目录)
    import 表定义

    return 表定义


库相对路径 = _取表定义().库相对路径

表_行数 = "行数基线"
表_运行数据 = "运行数据基线"
表_台账号 = "台账号基线"
表_底座扩展名 = "底座扩展名基线"
表_引用 = "引用基线"
表_引用未判 = "引用未判基线"
表_十干 = "十干基线"
表_禁译名 = "禁译名基线"
表_命名禁形 = "命名禁形基线"
表_硬写能力号 = "硬写能力号基线"

# 判据 ⑲ 的三类（读写与判定循环共用一份 —— 加一类只改这里）。
行数类别 = ("超行数", "入口超行数", "入口有实现")


def _读一张(树根, 表名: str, 组键) -> tuple:
    """⇒ `(项表, 错误或 None)` —— 读不动就交错误回去（由判据报红 / 未判），不抛。"""
    库件 = Path(树根) / 库相对路径
    if not 库件.is_file():
        return {}, f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute(f"select * from {表名}"))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return {}, f"`{表名}` 读不动：{错误}"
    项表 = {}
    for 一行 in 行表:
        键名, 处数 = 组键(一行)
        项表[键名] = int(处数 or 0)
    return 项表, None


def _读键集(树根, 表名: str, 组键) -> tuple:
    """读一张**无处数**的表（判据 ㊴ 的悬空引用是集合）⇒ `(键集, 错误或 None)`。"""
    库件 = Path(树根) / 库相对路径
    if not 库件.is_file():
        return set(), f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute(f"select * from {表名}"))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return set(), f"`{表名}` 读不动：{错误}"
    return {组键(一行) for 一行 in 行表}, None


def _写一张(树根, 表名: str, 行表: list) -> int:
    """整表重写（先 delete 再 insert）—— **只有登记 / 冻结 / 夹具走它**，判据永远只读。"""
    连接 = sqlite3.connect(Path(树根) / 库相对路径)
    try:
        连接.execute(f"delete from {表名}")
        if 行表:
            连接.executemany(
                f"insert or replace into {表名} values({','.join('?' * len(行表[0]))})", 行表)
        连接.commit()
    finally:
        连接.close()
    return len(行表)


# ── 判据 ⑲：行数硬数 ────────────────────────────────────────────────────────────────────

def 读行数基线(树根) -> tuple:
    """⇒ `({(类别, 路径): 处数}, 错误或 None)`。"""
    return _读一张(树根, 表_行数, lambda 一行: ((一行[0], 一行[1]), 一行[2]))


def 写行数基线(树根, 项表: dict) -> int:
    return _写一张(树根, 表_行数, [(*键名, 处数) for 键名, 处数 in sorted(项表.items())])


