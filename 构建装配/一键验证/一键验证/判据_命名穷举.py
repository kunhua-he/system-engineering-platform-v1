"""判据 ㊷：命名穷举 —— 出现即须登记（三面：定义面 · 形参面 · 局部面）。

依据：华哥 2026-09-28「出现即须定义，未定义即红」· 2026-09-29「之前的老规则，全部移除掉」
（形状模式不再算定义）·「全规则都在 db 里面。外部不留」（名册与基线都住规则库）。

**判什么**：三面扫出来的**每一个名**拿去问名册（库 `命名定义` 表）与例外（库 `命名例外` 表）；
两档都不收 ⇒ **未登记**。存量入基线（库 `命名穷举基线` 表 = **债清单**）· 新增债即红 · 基线只许减。

**只判债，不判处数**：同一个未登记的名在别处再出现一次**不是新增债** —— 华哥 2026-09-29：
「命名一定是可以复用，而且定义清晰的」⇒ 名册里有定义的名一律放行，处数只作读数。
判据 ㉒ 那三档判的是**违规形状**（多一处就更糟，故比处数）；本条判的是**名有没有定义**
（债按名记，不按处数记）—— 两条不同形，别照抄。

**三元读数**：通过 = 三面非空且无新增债 / 无陈旧债；失败 = 逐条报出；
未判 = 三面下 0 个名，或名册 / 基线读不动（**空集是未判，不是通过**）。

**面各只一份**：本件**不写扫描器** —— 编排归 `开发工具/信息核心/命名穷举.py`（验证器与写盘闸
也调它）；剥器归 `代码地图/形参面.py` 与 `命名扫描.py`（与判据 ㉒ 同一份）。

**已知缺口（如实登记）**：索引**引用面少约 7%**，且定义面读数依赖代码地图索引（索引陈旧 ⇒
假读数，先跑 `python3 开发工具/代码地图.py 建`）；宏体 / 字符串字面量 / JS 模板串里的名看不见；
嵌套函数 `def` 名三不管。
"""
from __future__ import annotations

from .小工具 import 判不了, 违规
from . import 常量
from .常量 import 检查名


def _取信息核心件(件名: str):
    """惰性取 `开发工具/信息核心/` 下的共享件 —— 取法照判据 ⑲ 引工具的先例：
    **工具从「判据自身所在的仓」取**，不从被扫的仓取（夹具仓没有这些工具）。
    """
    import sys as _sys

    根目录 = str(常量.仓根目录 / "开发工具" / "信息核心")
    if 根目录 not in _sys.path:
        _sys.path.insert(0, 根目录)
    return __import__(件名)


def 命名件表(上层读数: dict) -> dict:
    """扫描面：`上层读数["文件"]` 里的**命名件** ⇒ `{路径: 文本}`（后缀表只此一份）。"""
    后缀表 = tuple(_取信息核心件("命名穷举").查名.命名后缀)
    return {路径: 一项["文本"] for 路径, 一项 in 上层读数["文件"].items()
            if 一项.get("文本") is not None and 路径.endswith(后缀表)}


def 扫三面(上层读数: dict) -> dict:
    """三面一起扫 ⇒ `{面: [(名, 件, 行)]}`（读哪个索引交给 `读文件.索引路径` 管夹具 vs 真仓）。"""
    from .读文件 import 索引路径

    件表 = 命名件表(上层读数)
    return _取信息核心件("命名穷举").扫三面(件表, 索引路径(上层读数["仓根"], 件表))


def 对象数_命名穷举面(上层读数: dict) -> int:
    """对象数：三面出现的**处数**（0 ⇒ 未判）。"""
    return sum(len(条表) for 条表 in 扫三面(上层读数).values())


def 检查42_命名穷举(上层读数: dict) -> list:
    """命名穷举：出现即须登记（三面 · 存量入基线、新增即红 · 基线只许减）。"""
    输出缓冲 = []
    穷举 = _取信息核心件("命名穷举")
    出现表 = 扫三面(上层读数)
    if not any(出现表.values()):
        判不了(
            检查名[41],
            "三面（定义面 · 形参面 · 局部面）",
            "三面下 0 个名 —— 也可能是**索引不在**（夹具仓该由 读文件.索引路径 挂一份合成索引）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。一条标识符都没有的仓天然是绿的，"
            "那不是这条判据的功劳 ⇒ 只能由判据作者确认扫描面与索引",
        )
        return 输出缓冲
    try:
        唯一名, 例外 = 穷举.读名册(上层读数["仓根"])
    except 穷举.名册读不动 as 错误:
        判不了(
            检查名[41],
            穷举.库相对路径,
            f"判不了：{错误}",
            "名册是本条的**唯一对象**（出现即须登记）⇒ 读不出就判不了。修法：把规则库补上"
            "（`python3 开发工具/信息核心/信息核心.py 建库`）⇒ 只能由维护方补",
        )
        return 输出缓冲
    基线表, 错误 = _取信息核心件("命名基线").读穷举基线(上层读数["仓根"])
    if 错误:
        return [
            违规(
                检查名[41],
                穷举.库相对路径,
                错误,
                "「存量入基线、新增即红」要求先有存量清单；没有它，实测的全部存量会被算成"
                "「新增」⇒ 判据当场红一片，等于没上闸 ⇒ 只能由维护方登记（库 `命名穷举基线` 表）",
            )
        ]
    未登记 = 穷举.判未登记(出现表, 唯一名, 例外)
    for 面名, 面表 in 未登记.items():
        for 出现名, 记录 in sorted(面表.items()):
            if (面名, 出现名) in 基线表:
                continue
            输出缓冲.append(
                违规(
                    检查名[41],
                    f"{记录['样例']}::{出现名}",
                    f"新增「{面名}」未登记的名 `{出现名}`（{记录['处数']} 处 / {记录['件数']} 件），"
                    f"基线里没有它 ⇒ **新增即红**",
                    "华哥 2026-09-28：「出现即须定义，未定义即红」—— 名要在库 `命名定义` 表里"
                    "（语义 → 唯一名），或属库 `命名例外`（语言强加）。改法：① 取名（按它承载什么）"
                    "并登记进库（`python3 开发工具/信息核心/信息核心.py 登记 <名>`），"
                    "或 ② 按实际角色改名 ⇒ 只能由该件的作者定",
                )
            )
    # 反向：基线里登记着、实测却一个都不剩 ⇒ 陈旧债（「基线只许减」）。
    for 面名, 出现名 in sorted(基线表):
        if 未登记.get(面名, {}).get(出现名) is not None:
            continue
        输出缓冲.append(
            违规(
                检查名[41],
                f"{面名}::{出现名}",
                f"基线登记着「{面名}」`{出现名}`，而实测这个名**已经不出现** ⇒ **陈旧登记**",
                "「基线只许减」：登记完了就该删掉 —— 留着它，基线读数就不再是现状（读的人会以为债还在）"
                "⇒ 只能由维护方删（库 `命名穷举基线` 表）",
            )
        )
    return 输出缓冲
