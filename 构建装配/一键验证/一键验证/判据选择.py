# -*- coding: utf-8 -*-
"""判据选择 —— `--只跑` 的统一选择器（合法选择面 = `判据表.检查表` 的可运行判据）。

**为什么单开一件**（判据 ⑲ 单源文件 ≤400 行）：选择口径在 `主流程` 的路由与
`MCP服务/门禁` 的转发两处都要用同一份 —— 各写一套必漂。实测原有缺陷：`--只跑` 按
`常量.检查名` 的**目录**（55 条：含两条占位与已删旧名）筛，而真跑的是 `判据表.检查表`
的**可运行判据**（51 条）—— 两者不同源 ⇒ 命中只在目录里、不在可运行表里的名（如
`㉒ 命名防回潮`）时，`验证.跑全量判据` 的循环一条都不过 ⇒ 局部变量 `瞬时` 未绑定 ⇒
`UnboundLocalError` 内部错（既不是清楚的「拒」，又掩盖了「选中 0 条 = 假绿」）。

**口径**（一处定义、两处复用）：
  · 合法选择面**只有** `判据表.检查表`（真能跑的判据）；目录里占位 / 已删的旧名不在面内；
  · 词可给**编号**（`19` · `⑲`）或**判据名的一段**（子串）；**不猜别名**、不模糊自动选；
  · 空表 · 非字符串项 · 重复词 · 未知词 · 已知未知混给 ⇒ **一律明确拒**（不静默跳过、
    不退回全量）；
  · 未知词给 ≤ `候选上限` 条**近似候选**（按共用字数排名，仅供人挑，**绝不自动选中**）。

**局部 0 条 ≠ 放行**：本件只回答「选中哪几条」；放行仍只认全量（`v1_gate` 的合同）。
"""
from __future__ import annotations

import time

from .判据表 import 检查表


# 未知词最多列几条候选（列多了淹读数；它不是自动选中，只是给人挑的提示）。
候选上限 = 5
# 圈号段：三段（① 起 · ㉑ 起 · ㊱ 起）⇒ 每段的（码位起点，码位终点，序数起点）。
# 段长各不同（①–⑳ 20 个 · ㉑–㉟ 15 个 · ㊱–㊿ 15 个）⇒ **不能按固定偏移**收，得按终点收
# （实测：按固定偏移 +13 会漏 ⑮–⑳ 与 ㉟ —— 那 7 条取不到编号）。
圈号起点表 = ((0x2460, 0x2473, 1), (0x3251, 0x325F, 21), (0x32B1, 0x32BF, 36))


def 提取编号(判据名: str) -> str:
    """判据名开头的编号 ⇒ 十进制字符串（`⑲ 行数硬数…` → `19` · `54 后缀表唯一…` → `54`）。"""
    圈号 = 判据名[:1]
    for 码位起点, 码位终点, 序数起点 in 圈号起点表:
        if 码位起点 <= ord(圈号) <= 码位终点:
            return str(序数起点 + ord(圈号) - 码位起点)
    数字段 = ""
    for 单字符 in 判据名:
        if 单字符.isascii() and 单字符.isdigit():
            数字段 += 单字符
        else:
            break
    return str(int(数字段)) if 数字段 else ""


def 取可运行判据() -> tuple:
    """⇒ 可运行面：`((编号, 判据名), …)` —— **唯一合法选择面** = `判据表.检查表`。"""
    return tuple((提取编号(判据名), 判据名) for 判据名, _ in 检查表)


def 规范编号(选择词: str) -> str:
    """把编号词规整成十进制字符串（`19` · `⑲` → `19`）；不是编号词 ⇒ 空串。"""
    if 选择词.isascii() and 选择词.isdigit():
        return str(int(选择词))
    return 提取编号(选择词) if len(选择词) == 1 else ""


def 近似候选(选择词: str, 可运行面: tuple) -> list:
    """未知词的**近似候选** ⇒ `[判据名…]`（按共用字数降序、编号升序，最多 `候选上限` 条）。

    只按**共用字数**排名（确定、不猜同义）——候选只供人挑，**绝不自动选中**。
    """
    计分表 = []
    for 编号, 判据名 in 可运行面:
        共用数 = len(set(选择词) & set(判据名))
        if 共用数:
            计分表.append((共用数, 编号, 判据名))
    计分表.sort(key=lambda 计分项: (-计分项[0], 计分项[1]))
    return [判据名 for 共用数, 编号, 判据名 in 计分表[:候选上限]]


def 解析选择(词表) -> tuple:
    """`--只跑` 的词表 ⇒ `(判据名集, 问题或 None)`。**不静默** · **不自动选** · **不退回全量**。"""
    if isinstance(词表, str) or not isinstance(词表, (list, tuple)):
        return set(), "选择词要是一张表（`--只跑` 后面逗号分隔的一段），收到：%r" % (词表,)
    净词表 = []
    for 选择词 in 词表:
        if not isinstance(选择词, str):
            return set(), "选择词里有一项不是字符串：%r" % (选择词,)
        选择词 = 选择词.strip()
        if not 选择词:
            return set(), "选择词里有一项是空的（`--只跑` 不许空词）"
        净词表.append(选择词)
    if not 净词表:
        return set(), ("`--只跑` 后面要给判据的编号或名子串（逗号分隔），如 `--只跑 19,超时设置`；"
                   "要跑全量就别给 `--只跑`")
    重复词 = sorted({选择词 for 选择词 in 净词表 if 净词表.count(选择词) > 1})
    if 重复词:
        return set(), "这些选择词重复了：%s" % " · ".join(重复词)
    可运行面 = 取可运行判据()
    编号到名 = {编号: 判据名 for 编号, 判据名 in 可运行面 if 编号}
    选中集, 未命中行表 = set(), []
    for 选择词 in 净词表:
        编号 = 规范编号(选择词)
        if 编号 and 编号 in 编号到名:
            命中表 = [编号到名[编号]]
        else:
            命中表 = [判据名 for _编号, 判据名 in 可运行面 if 选择词 in 判据名]
        if not 命中表:
            未命中行表.append((选择词, 近似候选(选择词, 可运行面)))
            continue
        选中集 |= set(命中表)
    if 未命中行表:
        行表 = []
        for 选择词, 候选名表 in 未命中行表:
            候选文本 = " · ".join(候选名表) if 候选名表 else "（没有相近的可运行判据）"
            行表.append("  「%s」一条可运行的判据也没命中 —— 近似候选（≤%d）：%s"
                    % (选择词, 候选上限, 候选文本))
        return set(), "这些选择词没命中可运行判据（已知未知混给也不放行）：\n%s" % "\n".join(行表)
    if not 选中集:
        return set(), "没有选中任何可运行的判据"
    return 选中集, None


def 守可运行(只跑) -> str:
    """`只跑` 给的判据名集是否都在可运行面里、且非空 ⇒ **问题说明**（空串 = 合法）。"""
    if 只跑 is None:
        return ""
    可运行名集 = {判据名 for 判据名, _ in 检查表}
    未知名 = sorted(set(只跑) - 可运行名集)
    if 未知名:
        return "这些名字没有可运行的判据（不在 检查表 里）：%s" % " · ".join(未知名)
    if not 只跑:
        return "选择集为空 —— 一条判据都没选中"
    return ""


def 拒果(问题: str, 上层读数: dict, 开跑时刻: float) -> dict:
    """不可运行的「只跑」⇒ 三元读数的**清楚非 0**（不是未绑定变量的内部错）。"""
    return {
        "通过": [],
        "失败": [{
            "检查": "只跑选择",
            "位置": "--只跑",
            "缺什么": 问题,
            "不能自愈": "「只跑」的合法面只有 `判据表.检查表` 注册的可运行判据（编号或名子串）；"
                    "空集与未知名都不许静默退回全量，更不许算成「通过」⇒ "
                    "改用 `一键验证.py --只跑 <编号或名子串>`（选择器 `判据选择.py` 会列出近似候选）",
            "分类": "源码错",
        }],
        "未判": [],
        "疑似瞬时": [],
        "耗时毫秒": int((time.perf_counter() - 开跑时刻) * 1000),
        "上下文": 上层读数,
    }
