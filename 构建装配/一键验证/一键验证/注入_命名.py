# -*- coding: utf-8 -*-
"""注入样本 · 命名防回潮一类（判据 ㉒）：序数代称作标识符 · 西文单字母 · 基线陈旧登记。

反向样本全部注入到**干净合成仓**（不依赖仓库现状 ⇒ 可重复）。合成仓的
`构建装配/一键验证/命名基线.json` 是**空的两档**（合成仓里没有这两档标识符），
所以任何一处注入都必然是「新增」⇒ 当场红。
"""
from __future__ import annotations

import json
from pathlib import Path

from .判据_命名 import _查名

# 代称首字：**不写死** —— 从判据的检测表取（全仓只有 `查名.py::序数代称字` 一处字面序数代称）。
代称首字 = _查名().序数代称字[0]


命名基线相对路径 = "构建装配/一键验证/命名基线.json"
_样本件 = "运行内核/实例状态/src/命名样本.rs"


def _写样本件(临根: Path, 源码: str) -> str:
    路径 = 临根 / _样本件
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(源码, encoding="utf-8")
    return _样本件


def 注入_序数代称作标识符(临根: Path) -> str:
    """往一个 `.rs` 里加一行 `let <代称首字> = 1;` ⇒ 判据 ㉒ 当场红（「新增即红」）。

    字从检测表取（见 `代称首字`），**不写死** —— 这样全仓只有检测表那一处字面序数代称。
    """
    return _写样本件(
        临根,
        "pub fn 样例() -> u32 {\n"
        "    let %s = 1;\n"
        "    %s\n"
        "}\n" % (代称首字, 代称首字),
    )


def 注入_单西文字母(临根: Path) -> str:
    """往一个 `.rs` 里加一行 `let i = 1;` ⇒ 判据 ㉒ 当场红（「新增即红」）。

    这就是决策记录 §三 点名的那一档（`f` / `i` / `n` 之类的循环计数）。
    """
    return _写样本件(
        临根,
        "pub fn 样例() -> u32 {\n"
        "    let i = 1;\n"
        "    i\n"
        "}\n",
    )


def 注入_形参单字(临根: Path) -> str:
    """往一个 `.rs` 里加一个**单字形参** ⇒ 判据 ㉒ 第三档当场红（「新增即红」）。

    专证**形参面**这一档不是空的：索引的**定义面不收形参** ⇒ 只判前两档的话，
    这个样本对它**视而不见** —— 这就是 2026-09-28 补第三档要堵的那个洞。
    """
    return _写样本件(
        临根,
        "pub fn 样例(名: u32) -> u32 {\n"
        "    名\n"
        "}\n",
    )


def 注入_局部单字(临根: Path) -> str:
    """往一个 `.rs` 里加一行 `let 名 = 1;` ⇒ 判据 ㉒ 第四档当场红（「新增即红」）。

    专证**局部面**这一档不是空的：索引的**定义面不收局部名**（#226）、形参面只扫签名
    ⇒ 只判前三档的话，这个样本对它**视而不见** —— 这就是 2026-09-28 补第四档要堵的那个洞。
    """
    return _写样本件(
        临根,
        "pub fn 样例() -> u32 {\n"
        "    let 名 = 1;\n"
        "    名\n"
        "}\n",
    )


def 注入_局部单字_其余形状(临根: Path) -> str:
    """往一个 `.rs` 里加一条 **`match` 臂模式绑定** `Ok(名) => …` ⇒ 判据 ㉒ 第四档当场红。

    专证第四档**补全形状**之后那几类真走到了判据（不只停在扫描器）：闭包参 / 模式绑定 /
    元组解包 / 推导式目标 —— 这些形状原先**收了就要猜**故不收 ⇒ 只测 `let 名 = 1;`
    一种的话，形状表里其余十几条全坏了也不报（自检的反向样本只证扫描器，不证判据这条路）。
    """
    return _写样本件(
        临根,
        "pub fn 样例(读数: Result<u32, u32>) -> u32 {\n"
        "    match 读数 {\n"
        "        Ok(名) => 名,\n"
        "        Err(_) => 0,\n"
        "    }\n"
        "}\n",
    )


def 注入_命名基线陈旧登记(临根: Path) -> str:
    """给基线**加一条已经不出现的登记** ⇒ 判据 ㉒ 当场红（「陈旧登记」）。

    专证「基线只许减」的反面不是空的（同判据 ⑲ 的 `注入_基线陈旧登记`）：
    改名批次落地后若留着旧登记，基线读数就不再是现状，而且它白占一格上限。
    """
    路径 = 临根 / 命名基线相对路径
    数据 = json.loads(路径.read_text(encoding="utf-8"))
    数据["档"]["西文单字母"].append(
        {"路径": "契约声明/src/lib.rs", "名字": "i", "处数": 1}
    )
    路径.write_text(json.dumps(数据, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return "契约声明/src/lib.rs"
