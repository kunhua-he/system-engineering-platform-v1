# -*- coding: utf-8 -*-
"""退出码语义（全过为零、未判不算过）。"""

from __future__ import annotations


def 算退出码(结果: dict) -> int:
    """全过（无失败、无未判）= 0；否则 = 1。空集是「未判」不是「通过」。"""
    return 0 if not 结果["失败"] and not 结果["未判"] else 1


def 自检_退出码语义() -> tuple:
    """退出码语义：全过为零、未判不算过。

    反向样本就是本函数自己的历史缺陷：曾写成 `结果["失败"] == 0`，
    而它是 list ⇒ `[] == 0` 恒假 ⇒ 退出码恒 1（门禁报假红，读数与退出码相抵）。
    """
    return [
        ("退出码_全过为零", 算退出码({"失败": [], "未判": []}) == 0, "无失败无未判 ⇒ 0"),
        ("退出码_未判不算过", 算退出码({"失败": [], "未判": ["x"]}) == 1, "未判不是通过 ⇒ 1"),
        ("退出码_有失败为一", 算退出码({"失败": ["x"], "未判": []}) == 1, "有失败 ⇒ 1"),
    ]
