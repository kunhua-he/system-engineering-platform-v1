# -*- coding: utf-8 -*-
"""解析器的身份证 · 判据 ㊹（零字面禁译名）：正/反样本 + 承重证明 + 排除面。

为什么单列：`判据的可信性.md` §三.5「判据的解析器坏了」是假绿来源之一 —— 走树 / 逐字节
读原文是判据 ㊹ 的眼睛，它自身也要有反向样本（该抓的抓得住）与正向样本（干净件不许报红）。

★ 样本里的禁译名**按码位取**（`chr(0x5E03)` 一类）—— 本件自身也在判据 ㊹ 的扫描面内，
写整字会给**自身**造一处真违规（先例：`注入_行号引用` 把行号写成 `{12}`）。
"""
from __future__ import annotations

import tempfile
from pathlib import Path

from .判据_禁译名 import (
    扫禁译名, 数命中, 禁译名字, 路径被排除, 禁译名面, 词内禁译名, 去词内禁译名,
)
from .自检_十干 import _只剥标识符命中


def 自检_禁译名扫描() -> list:
    """判据 ㊹ 的走树 / 读原文 / 排除面的正反样本与承重证明。

    五问：① 正向（注释 / 字符串 / 散文里的字面禁译名）抓得住；② 反向（干净件）不报红；
    ③ 承重证明：退回「只剥标识符」⇒ 注释 / 字符串样本必漏；④ 排除面：`构建环境/` 与
    `只读参考/` 里的巧合字节不算（否则是假红）；⑤ 白名单机制：词内禁译名（空表）不影响判定。
    """
    禁译名词 = 禁译名字()
    输出缓冲 = []

    # ── ① 正向样本（该抓的）：注释 · 字符串 · 散文里的字面禁译名 ──
    件表 = {
        "运行内核/样例.rs": "// 注释里的字面禁译名 " + 禁译名词 + "\npub fn 样例() {}\n",
        "前端呈现/样例.js": "const 说明 = \"" + 禁译名词 + "\";\n",
        "项目文档/样例.md": "散文里的字面禁译名 " + 禁译名词 + "。\n",
    }
    命中 = 数命中(扫禁译名(件表))
    输出缓冲.append((
        "正向样本：注释 / 字符串 / 散文里的**字面禁译名** ⇒ 抓得住（这正是只剥标识符拦不住的那一类）",
        all(路径 in 命中 for 路径 in 件表),
        "命中键 = %s（三件都要有）" % sorted(命中),
    ))

    # ── ② 反向样本：干净件不许报红 ──
    干净面 = {
        "运行内核/样例.rs": "// 干净的注释：`逻辑型` 与 `禁译名` 这几个字本身不是那个词\npub fn 样例() {}\n",
        "项目文档/样例.md": "干净的散文，一个禁译名字都没有。\n",
    }
    干净命中 = 扫禁译名(干净面)
    输出缓冲.append((
        "反向样本：干净件 ⇒ 不报红",
        not 干净命中,
        "命中 = %s（要求空）" % 干净命中,
    ))

    # ── ③ 承重证明（退回一步）：只剥标识符 ⇒ 注释 / 字符串样本必漏 ──
    注释样本 = "// 注释里的字面禁译名 " + 禁译名词 + "\npub fn 样例() {}\n"
    串样本 = "pub fn 样例() -> &'static str { \"" + 禁译名词 + "\" }\n"
    原文命中 = 扫禁译名({"件.rs": 注释样本}) + 扫禁译名({"件.rs": 串样本})
    标识符命中 = (_只剥标识符命中(".rs", 注释样本, 禁译名词)
              + _只剥标识符命中(".rs", 串样本, 禁译名词))
    输出缓冲.append((
        "承重证明（退回一步）：把「逐字节读原文」退回成「只剥标识符」⇒ 注释 / 字符串样本必漏",
        bool(原文命中) and not 标识符命中,
        "原文 %d 处 · 只剥标识符 %d 处（要求 原文 > 0 且 标识符 == 0）"
        % (len(原文命中), len(标识符命中)),
    ))

    # ── ④ 排除面：`构建环境/` 与 `只读参考/` 里的巧合字节不许被算进来（否则是假红）──
    with tempfile.TemporaryDirectory(prefix="禁译名排除面-") as 临时:
        临时根 = Path(临时)
        for 目录名 in ("构建环境", "只读参考", "运行内核"):
            (临时根 / 目录名).mkdir()
        (临时根 / "构建环境" / "缓存.bin").write_text("巧合字节 " + 禁译名词 + "\n", encoding="utf-8")
        (临时根 / "只读参考" / "语料.md").write_text("只读语料 " + 禁译名词 + "\n", encoding="utf-8")
        (临时根 / "运行内核" / "真件.rs").write_text("真件里的禁译名 " + 禁译名词 + "\n", encoding="utf-8")
        键集 = set(禁译名面({"仓根": 临时根}))
        输出缓冲.append((
            "排除面：`构建环境/` 与 `只读参考/` 里的巧合字节不算（否则是假红）",
            键集 == {"运行内核/真件.rs"}
            and 路径被排除("构建环境/缓存.bin") and 路径被排除("只读参考/语料.md"),
            "面里的件 = %s（要求只有真件）" % sorted(键集),
        ))

    # ── ⑤ 白名单机制：词内禁译名（**空表**）⇒ 判定不受影响 ──
    输出缓冲.append((
        "白名单机制：词内禁译名表实测为空 ⇒ 去词内禁译名是恒等（表非空时才剥）",
        词内禁译名 == () and 去词内禁译名(禁译名词) == 禁译名词,
        "词内禁译名 = %r（要求空）· 去词内禁译名(禁译名) 仍等于它自身" % (词内禁译名,),
    ))
    return 输出缓冲
