# -*- coding: utf-8 -*-
"""注入样本 · 判据 ㊳（台账号不悬空）。"""
from __future__ import annotations

from pathlib import Path


# 前缀**拆开拼**：本件自身也在扫描面内（形①②③ 扫全仓）—— 整字连写会被自身抓到。
_台账 = "台" "账"


def 注入_台账号引用(临根: Path) -> str:
    """往干净合成仓里写一处理台账引用 ⇒ 判据 ㊳ 当场红。

    形状取现场实测那一类（`构建装配/上线切换/形状.md` 曾写过「同一条扫描规则两处实现」并挂号）：
    这里一次给 **形①**（散文里的 `台账 #N`）与 **形④**（同一件里的裸 `#N`）两处 ——
    证明「有前缀」与「无前缀」两条路都拦得住。
    号取 **241**（不在台账里、也不与任何作废号重）⇒ 读数明确，不走「已删号 / 从未有过」那条歧义路。
    """
    路径 = 临根 / "项目文档" / "决策记录" / "台账号样例.md"
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        f"# 样例（反向样本）\n\n"
        f"同一条扫描规则两处实现（{_台账} " f"#" f"241）。\n\n"
        f"另：两侧分界见 #241 那张表。\n",
        encoding="utf-8",
    )
    return "项目文档/决策记录/台账号样例.md"
