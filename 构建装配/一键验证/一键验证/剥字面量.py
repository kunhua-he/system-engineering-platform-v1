# -*- coding: utf-8 -*-
"""词法层：剥字符串/注释/字面量（判据的解析器）。"""

from __future__ import annotations

import re


# 字面量 / 注释的**单次扫描**用到的形状（都在 `_剥` 里按位置逐个匹配，不预先全局替换）。
_原始串形 = re.compile(r'(?:b|c)?r(#*)"')
_普通串形 = re.compile(r'(?:b|c)?"')
_字符形 = re.compile(r"b?'(?:\\.|[^\\'\n])'")


def _剥(文本: str, 保串: bool) -> str:
    """**单次扫描**：注释与字符串 / 字符字面量**配对识别**，命中的内容换成等长空格（**换行原样保留**）。

    为什么换行必须保留（实测撞到过的真缺陷）：
    早先的 `抹` 把命中区间里**每一个**字符都写成空格——**含换行**。于是剥掉一个 N 行的块注释，
    其后的行号整体前移 N-1 行（实测：`前端呈现/网页应用/取接口.js` 的块注释吃掉 7 个换行，
    该文件里 `取能力` 这一处导出函数的行号整体前移 7 行）。**15 条判据共用这个解析器** ⇒ 凡是报位置的地方都偏。
    位置报错比不报更坏：照着去找找不到，然后不信判据（`判据的可信性.md` 第六节）。
    `//` 行注释本来就止于换行前，不受影响；受影响的正是**块注释**与**跨行字符串**。

    为什么必须单次配对（实测撞到过的真缺陷）：
    早先的实现是「先剥 `//` 注释、再剥字符串」**两遍各自扫**。于是**字符串里出现 `//`** 时
    （实测形状：某腿在断言消息里写 `"段位 = 码 // 号段类宽度"`），注释那一遍从那个 `//` 起
    把本行剩下部分（**含收尾引号**）一起剥掉 ⇒ 引号配对失衡 ⇒ 那个孤立引号与**下一个引号**
    配成一对，把中间整段（含大括号）抹成空白 ⇒ `#[cfg(test)]` 的大括号配对永远找不到闭合
    ⇒ 整块测试代码剥不掉、被当生产代码数进判据。
    实测读数：注入那一行后 ⑪ 判据 4（资源出入口）的读数从 1 处涨到 31 处，去掉后恢复 1 处。
    单次扫描里遇到 `"` 就按字符串走、遇到 `//` 或 `/*` 才按注释走，两个方向都不会咬到对方
    （正向样本：注释里含引号 `// 这是 "引号"` 也必须整段剥掉，且不许吞掉后面的代码）。

    `保串=真` 时字符串 / 字符字面量**原样保留**（只剥注释）——数导出符号名必须保串
    （符号名就写在字符串里；实测撞到过：抹掉字符串会把 `export_name = "平台_调用"` 的名字
    抹成空白 ⇒ 数出 0 组）。此时注释识别仍然要**认得出字符串**：字符串里的 `//` 不是注释。
    """
    出 = list(文本)
    n = len(文本)

    def 抹(起: int, 止: int) -> None:
        # 换行**不抹**：抹掉换行会让其后行号整体前移，
        # 位置判据报出的行号与真身对不上 ⇒ 位置报错比不报更坏。
        for p in range(起, min(止, n)):
            if 文本[p] != "\n":
                出[p] = " "

    i = 0
    while i < n:
        c = 文本[i]
        # ── 注释：`//` 到行尾；`/* */` 可嵌套（Rust 的块注释是嵌套的）──
        if c == "/" and i + 1 < n and 文本[i + 1] == "/":
            j = 文本.find("\n", i)
            止 = n if j < 0 else j
            抹(i, 止)
            i = 止
            continue
        if c == "/" and i + 1 < n and 文本[i + 1] == "*":
            深 = 1
            k = i + 2
            while k < n and 深:
                if 文本[k] == "/" and k + 1 < n and 文本[k + 1] == "*":
                    深 += 1
                    k += 2
                elif 文本[k] == "*" and k + 1 < n and 文本[k + 1] == "/":
                    深 -= 1
                    k += 2
                else:
                    k += 1
            抹(i, k)
            i = k
            continue
        # ── 原始字符串：`r"…"` · `r#"…"#` · `br#"…"#` · `cr#"…"#` ──
        配 = _原始串形.match(文本, i)
        if 配:
            井 = 配.group(1)
            起 = 配.end()
            终 = 文本.find('"' + 井, 起)
            终 = n if 终 < 0 else 终 + len(井) + 1
            if not 保串:
                抹(i, 终)
            i = 终
            continue
        # ── 普通字符串：`"…"` · `b"…"` · `c"…"`（转义按 `\` 跳过下一个字符）──
        配 = _普通串形.match(文本, i)
        if 配:
            k = 配.end()
            while k < n:
                if 文本[k] == "\\":
                    k += 2
                    continue
                if 文本[k] == '"':
                    k += 1
                    break
                k += 1
            if not 保串:
                抹(i, k)
            i = k
            continue
        # ── 字符字面量：`'x'` · `'\n'` · `b'x'`（`'a` 这种是生命周期，不配对 ⇒ 不命中）──
        配 = _字符形.match(文本, i)
        if 配:
            if not 保串:
                抹(i, 配.end())
            i = 配.end()
            continue
        i += 1
    return "".join(出)


def 去字面量(文本: str) -> str:
    """注释 · 字符串 · 字符字面量的内容换成等长空格（长度不变 ⇒ 行号与偏移仍对齐）。

    为什么要它：大括号配对与「这一段里有没有某名字」都要在**代码**上做，
    注释里写 `static 平台信息 {` 不算手写实现，字符串里的 `{` 不该参与配对。
    """
    return _剥(文本, 保串=False)


def cfg测试区(文本: str) -> list:
    """`#[cfg(test)]` 覆盖的字符区间表 [(起, 止)]（按大括号配对求边界）。"""
    净 = 去字面量(文本)
    区表 = []
    for 命 in re.finditer(r"#\[cfg\(test\)\]", 净):
        起 = 净.find("{", 命.end())
        if 起 < 0:
            continue
        深 = 0
        for i in range(起, len(净)):
            if 净[i] == "{":
                深 += 1
            elif 净[i] == "}":
                深 -= 1
                if 深 == 0:
                    区表.append((起, i))
                    break
    return 区表
