# -*- coding: utf-8 -*-
"""词法层：剥字符串/注释/字面量（判据的解析器）。"""

from __future__ import annotations

import re


# 字面量 / 注释的**单次扫描**用到的形状（都在 `_剥` 里按位置逐个匹配，不预先全局替换）。
_原始串形 = re.compile(r'(?:b|c)?r(#*)"')
_普通串形 = re.compile(r'(?:b|c)?"')
_字符形 = re.compile(r"b?'(?:\\.|[^\\'\n])'")

# ── `/` 是「正则起始」还是「除号」：只看**前一个有意义字符**（跳过空白与已抹掉的字面量）──
# 全项目**只此一份**（`命名扫描` 的 `剥JS` / `扫正则字面量` 与判据 ⑪-6 的剥器都引它 —— 不许写第二套）。
# 判法：前一个字符若是运算符 / 开括号 / 分隔符 ⇒ 它**不可能结束一个表达式** ⇒ 后面那个 `/` 是正则起始；
# 若是标识符 · 数字 · `)` · `]` · 引号收尾 ⇒ 是除号（真除法左边必有值 ⇒ 前一个字符落在这几种里）。
# `}` 收进正则起始档（块尾之后可能接正则）；`<` **刻意不收** —— JSX 的 `</div>` 会被错剥（保守优先）。
正则前缀 = set("=(,:[!&|?{};>+-*%^~")
# 关键词前缀：它们后面**必须**跟一个表达式，且除号不可能紧跟它们
# （`return a / b` 的前一个非空白是 `a`，不是 `return`）⇒ 收进来无假红风险。
正则前缀词 = (
    "return", "typeof", "throw", "void", "delete",
    "case", "in", "of", "do", "else", "yield", "await",
)


def _前是表达式头(文本, 指: int) -> bool:
    """`文本[指]` 是 `/`：往前看第一个有意义字符 —— 它不可能结束一个表达式 ⇒ 这里是正则起始。

    `文本` 收 `str` 或 `list`：`_剥` 传的是**已抹掉前面字面量的缓冲**（注释 / 字符串的内容
    已变成空格）⇒ 前一个有意义字符不会被注释或字符串里的字带偏；`命名扫描` 传净文（str）。
    """
    位 = 指 - 1
    while 位 >= 0 and 文本[位] in " \t":
        位 -= 1
    if 位 < 0:
        return True
    if 文本[位] in 正则前缀:
        return True
    if 文本[位].isalnum() or 文本[位] in "_$":
        词起 = 位
        while 词起 >= 0 and (文本[词起].isalnum() or 文本[词起] in "_$"):
            词起 -= 1
        return "".join(文本[词起 + 1 : 位 + 1]) in 正则前缀词
    return False


def _扫正则止(文本: str, 起: int) -> int:
    """从 `起`（`/` 的位置）找正则字面量的**收尾边界**（含 flags）；找不到同行闭合 ⇒ 返回 -1。

    必须跳掉转义（反斜杠转义的斜杠）与字符类（`[/]`）—— 否则提前收尾，把后面的代码当正则吞掉（最坏的假阴性）。
    JS 正则不许跨行 ⇒ 遇到换行即判「找不到闭合」⇒ 当除号（**判不准就不剥**）。
    """
    长 = len(文本)
    步 = 起 + 1
    类内 = False
    闭 = -1
    while 步 < 长:
        字 = 文本[步]
        if 字 == "\\":
            步 += 2
            continue
        if 字 == "\n":
            break
        if 字 == "[":
            类内 = True
        elif 字 == "]":
            类内 = False
        elif 字 == "/" and not 类内:
            闭 = 步
            break
        步 += 1
    if 闭 < 0:
        return -1
    止 = 闭 + 1
    while 止 < 长 and 文本[止] in "gimsuyvd":
        止 += 1
    return 止


def 扫正则区段(文本: str) -> list:
    """位置无关地找 `/…/flags` 正则字面量 ⇒ `[(起, 止)]`（含 flags；同行的才算）。

    **全项目唯一的一份** `/` 启发式就在这里（`_前是表达式头` + `_扫正则止`）——
    `_剥` 剥正则字面量时、`命名扫描.扫正则字面量`（前端判据 ⑪-6 引它）都走这一份。
    """
    出 = []
    指 = 0
    长 = len(文本)
    while 指 < 长:
        if 文本[指] == "/" and _前是表达式头(文本, 指):
            止 = _扫正则止(文本, 指)
            if 止 > 0:
                出.append((指, 止))
                指 = 止
                continue
        指 += 1
    return 出


def _剥(文本: str, 保串: bool) -> str:
    """**单次扫描**：注释与字符串 / 字符字面量**配对识别**，命中的内容换成等长空格（**换行原样保留**）。

    为什么换行必须保留（实测撞到过的真缺陷）：
    早先的 `抹区间` 把命中区间里**每一个**字符都写成空格——**含换行**。于是剥掉一个 N 行的块注释，
    其后的行号整体前移 N-1 行（实测：`前端呈现/网页应用/取接口.js` 的块注释吃掉 7 个换行，
    该文件里 `取能力` 这一处导出函数的行号整体前移 7 行）。**15 条判据共用这个解析器** ⇒ 凡是报位置的地方都偏。
    位置报错比不报更坏：照着去找找不到，然后不信判据（`判据的可信性.md` 第六节）。
    `//` 行注释本来就止于换行前，不受影响；受影响的正是**块注释**与**跨行字符串**。

    为什么必须单次配对（实测撞到过的真缺陷）：
    早先的实现是「先剥 `//` 注释、再剥字符串」**两遍各自扫**。于是**字符串里出现 `//`** 时
    （实测形状：某腿在断言消息里写 `"段位 = 码 // 号段类宽度"`），注释那一遍从那个 `//` 起
    把本行剩下部分（**含收尾引号**）一起剥掉 ⇒ 引号配对失衡 ⇒ 那个孤立引号与**下一个引号**
    配成一对，把中间整段（含大括号）抹成空白 ⇒ `#[cfg(test)]` 的大括号配对永远找不到闭合
    ⇒ 整块测试代码剥不掉、被当生产代码数进判据。
    实测读数：注入那一行后 ⑪ 判据 4（资源出入口）的读数从 1 处涨到 31 处，去掉后恢复 1 处。
    单次扫描里遇到 `"` 就按字符串走、遇到 `//` 或 `/*` 才按注释走，两个方向都不会咬到对方
    （正向样本：注释里含引号 `// 这是 "引号"` 也必须整段剥掉，且不许吞掉后面的代码）。

    `保串=真` 时字符串 / 字符字面量**原样保留**（只剥注释）——数导出符号名必须保串
    （符号名就写在字符串里；实测撞到过：抹掉字符串会把 `export_name = "平台_调用"` 的名字
    抹成空白 ⇒ 数出 0 组）。此时注释识别仍然要**认得出字符串**：字符串里的 `//` 不是注释。
    """
    出 = list(文本)
    长度 = len(文本)

    def 抹区间(起: int, 止: int) -> None:
        # 换行**不抹**：抹掉换行会让其后行号整体前移，
        # 位置判据报出的行号与真身对不上 ⇒ 位置报错比不报更坏。
        for 位 in range(起, min(止, 长度)):
            if 文本[位] != "\n":
                出[位] = " "

    游标 = 0
    while 游标 < 长度:
        字符 = 文本[游标]
        # ── 注释：`//` 到行尾；`/* */` 可嵌套（Rust 的块注释是嵌套的）──
        if 字符 == "/" and 游标 + 1 < 长度 and 文本[游标 + 1] == "/":
            行末 = 文本.find("\n", 游标)
            止 = 长度 if 行末 < 0 else 行末
            抹区间(游标, 止)
            游标 = 止
            continue
        if 字符 == "/" and 游标 + 1 < 长度 and 文本[游标 + 1] == "*":
            深 = 1
            探位 = 游标 + 2
            while 探位 < 长度 and 深:
                if 文本[探位] == "/" and 探位 + 1 < 长度 and 文本[探位 + 1] == "*":
                    深 += 1
                    探位 += 2
                elif 文本[探位] == "*" and 探位 + 1 < 长度 and 文本[探位 + 1] == "/":
                    深 -= 1
                    探位 += 2
                else:
                    探位 += 1
            抹区间(游标, 探位)
            游标 = 探位
            continue
        # ── 原始字符串：`r"…"` · `r#"…"#` · `br#"…"#` · `cr#"…"#` ──
        配 = _原始串形.match(文本, 游标)
        if 配:
            井 = 配.group(1)
            起 = 配.end()
            终 = 文本.find('"' + 井, 起)
            终 = 长度 if 终 < 0 else 终 + len(井) + 1
            if not 保串:
                抹区间(游标, 终)
            游标 = 终
            continue
        # ── 普通字符串：`"…"` · `b"…"` · `c"…"`（转义按 `\` 跳过下一个字符）──
        配 = _普通串形.match(文本, 游标)
        if 配:
            探位 = 配.end()
            while 探位 < 长度:
                if 文本[探位] == "\\":
                    探位 += 2
                    continue
                if 文本[探位] == '"':
                    探位 += 1
                    break
                探位 += 1
            if not 保串:
                抹区间(游标, 探位)
            游标 = 探位
            continue
        # ── 字符字面量：`'x'` · `'\n'` · `b'x'`（`'a` 这种是生命周期，不配对 ⇒ 不命中）──
        配 = _字符形.match(文本, 游标)
        if 配:
            if not 保串:
                抹区间(游标, 配.end())
            游标 = 配.end()
            continue
        # ── JS 正则字面量：`/…/flags`（词法层补上「正则字面量」这一种）──
        # 为什么必须剥：正则字面量里的文本是**数据**，不是代码。不剥的话 `/JSON\.parse\(/`
        # 这类字面量里的字样会被判据 ⑪-6 的语义判当成**真调用**（实测：`const 形 = /JSON.parse(/;`
        # 报出 `JSON.parse`）—— 与「字符串 / 注释里的同名字样不算命中」同一条道理。
        # 认法只看前一个有意义字符（`_前是表达式头`，全项目唯一那份）；`//` `/*` 已在上面按注释处理。
        # **保守**：找不到同行闭合的 `/` ⇒ 当除号，**不剥**（宁可漏剥 —— 错剥会把真的
        # `JSON.parse(` 调用一起吃掉，那是最坏的假阴性）。
        if 字符 == "/" and _前是表达式头(出, 游标):
            止 = _扫正则止(文本, 游标)
            if 止 < 0:
                游标 += 1
                continue
            抹区间(游标, 止)
            游标 = 止
            continue
        游标 += 1
    return "".join(出)


def 去字面量(文本: str) -> str:
    """注释 · 字符串 · 字符字面量的内容换成等长空格（长度不变 ⇒ 行号与偏移仍对齐）。

    为什么要它：大括号配对与「这一段里有没有某名字」都要在**代码**上做，
    注释里写 `static 平台信息 {` 不算手写实现，字符串里的 `{` 不该参与配对。
    """
    return _剥(文本, 保串=False)


def 条件编译测试区(文本: str) -> list:
    """`#[cfg(test)]` 覆盖的字符区间表 [(起, 止)]（按大括号配对求边界）。"""
    净 = 去字面量(文本)
    区表 = []
    for 命 in re.finditer(r"#\[cfg\(test\)\]", 净):
        起 = 净.find("{", 命.end())
        if 起 < 0:
            continue
        深 = 0
        for 游标 in range(起, len(净)):
            if 净[游标] == "{":
                深 += 1
            elif 净[游标] == "}":
                深 -= 1
                if 深 == 0:
                    区表.append((起, 游标))
                    break
    return 区表
