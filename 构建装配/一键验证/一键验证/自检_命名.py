# -*- coding: utf-8 -*-
"""解析器的身份证 · 命名扫描（判据 ㉒）：剥注释与字符串 · 抽标识符。

为什么单列：`判据的可信性.md` §三.5「判据的解析器坏了」是假绿来源之一 —— 命名扫描
是判据 ㉒ 的眼睛，它自身也要有反向样本（该抓的抓得住）与正向样本（**最容易假红的那一条**：
注释里的序数代称 · 字符串里的序数代称 · 实义单字名，都不许报红）。
"""
from __future__ import annotations

from .命名扫描 import _标识符, 抽标识符, 剥后缀
from .判据_命名 import _查名   # 规则只此一份（在 开发工具/代码地图/查名.py）
from .剥字面量 import 去字面量


def _计(后缀: str, 文本: str) -> tuple:
    """扫一段样本 ⇒ (序数代称处数, 单西文字母处数)。与判据 ㉒ 走**同一个** `剥后缀` / `抽标识符`
    与**同一份口径**（`_查名()`）。"""
    查名 = _查名()
    代称处数 = 0
    字母数 = 0
    for 名 in 抽标识符(剥后缀(后缀, 文本)):
        if any(字 in 查名.序数代称字 for 字 in 名):
            代称处数 += 1
        if 查名.是单西文字母(名):
            字母数 += 1
    return 代称处数, 字母数


def _条(名: str, 好: bool, 说明: str) -> tuple:
    return (名, 好, 说明)


def 自检_命名扫描() -> list:
    """命名扫描的正/反样本：注释 · 字符串 · 实义单字 · 生命周期 · 字形 · 成员访问 · 真违规。

    ★ **样本里的序数代称字不写死**：从判据的检测表取（`序数代称字`）—— 全仓只有 `查名.py::序数代称字`
    一处字面序数代称，样本跟着表走（表改了样本自动跟）。
    """
    序数代称字 = _查名().序数代称字
    出 = []

    # ── 检测表本身：序数代称字是**码位表**展开的（全仓零字面序数代称）⇒ 码位写错一位就废 ──
    出.append(
        _条(
            "检测表：序数代称码位表展开正好 10 个互不相同的字（码位错一位即红）",
            len(序数代称字) == 10 and len(set(序数代称字)) == 10,
            f"展开出 {len(序数代称字)} 个字 · 去重后 {len(set(序数代称字))} 个（都要求 10）"
            " —— 检测表按 Unicode 码位写（全仓不写字面序数代称，见 查名.py），写错一位这条当场红",
        )
    )

    # ── 正向样本（最容易假红的那一条）：注释与字符串里的序数代称不许报红 ──
    注释样本 = "// %s（这一行在注释里）\n/* %s · %s */\npub fn 生产() {}\n" % (序数代称字, 序数代称字[0], 序数代称字[1])
    注释处数, _ = _计(".rs", 注释样本)
    出.append(
        _条(
            "正向样本：Rust 注释里的序数代称不报红（行注释 + 块注释）",
            注释处数 == 0,
            f"报 {注释处数} 处序数代称（要求 0）—— 拿散文里的字充数就是假红",
        )
    )
    串样本 = 'pub fn 生产() -> &\'static str { "序数代称字" }\n'
    串处数, _ = _计(".rs", 串样本)
    出.append(
        _条(
            "正向样本：Rust 字符串里的序数代称不报红",
            串处数 == 0,
            f"报 {串处数} 处序数代称（要求 0）",
        )
    )
    实义样本 = "pub fn 生产() -> u32 { let 值 = 1; let 码 = 2; 值 + 码 }\n"
    实义处数, 实义字母 = _计(".rs", 实义样本)
    出.append(
        _条(
            "正向样本：实义单字名（`值` `码`）不报红（决策记录 §三 明写不判）",
            实义处数 == 0 and 实义字母 == 0,
            f"报序数代称 {实义处数} 处 · 单西文字母 {实义字母} 处（都要求 0）",
        )
    )

    # ── 正向样本：Rust 的两处专属排除（生命周期 · `\\u{…}` 字形）与成员访问 ──
    寿样本 = "pub fn 取样<'a>(参数: &'a str) -> &'a str { 参数 }\n"
    _, 寿字母 = _计(".rs", 寿样本)
    出.append(
        _条(
            "正向样本：生命周期 `'a` 不算标识符（`a` 不报红）",
            寿字母 == 0,
            f"报单西文字母 {寿字母} 处（要求 0）—— 生命周期名不是作者起的名字",
        )
    )
    字形样本 = "pub fn 样例() -> char { '\\u{0C}' }\n"
    _, 字形字母 = _计(".rs", 字形样本)
    出.append(
        _条(
            "正向样本：`'\\u{0C}'` 字形里的 `C` 不报红（去字面量认不出这种字形）",
            字形字母 == 0,
            f"报单西文字母 {字形字母} 处（要求 0）",
        )
    )
    成员样本 = "pub fn 样例() -> u32 { let 标志 = 模式.S; 0 }\n"
    _, 成员字母 = _计(".rs", 成员样本)
    出.append(
        _条(
            "正向样本：成员访问 `.S`（如 `re.S`）不报红（不是作者起的名字）",
            成员字母 == 0,
            f"报单西文字母 {成员字母} 处（要求 0）",
        )
    )

    # ── 正向样本：Python 的 `#` 注释与字符串（**必须自身处理**，别硬套 Rust 那套）──
    皮样本 = '# 序数代称字\n说明 = "序数代称"\n值 = 1\n'
    皮处数, 皮字母 = _计(".py", 皮样本)
    出.append(
        _条(
            "正向样本：Python `#` 注释与字符串里的序数代称不报红",
            皮处数 == 0 and 皮字母 == 0,
            f"报序数代称 {皮处数} 处 · 单西文字母 {皮字母} 处（都要求 0）—— 拿 Rust 的 `//` 去剥 `.py` 会剥不掉",
        )
    )
    皮三 = "'''序数代称字'''\n说明 = \"序数代称\"\n"
    皮三处数, _ = _计(".py", 皮三)
    出.append(
        _条(
            "正向样本：Python 三引号串里的序数代称不报红",
            皮三处数 == 0,
            f"报序数代称 {皮三处数} 处（要求 0）",
        )
    )

    # ── 正向样本：JS 的行注释 · 单/双引号串 · 模板串 · 正则字面量 ──
    脚样本 = "// 序数代称\nconst 说明 = '序数代称';\nconst 值 = 1;\n"
    脚处数, 脚字母 = _计(".js", 脚样本)
    出.append(
        _条(
            "正向样本：JS 行注释与**单引号**串里的序数代称不报红",
            脚处数 == 0 and 脚字母 == 0,
            f"报序数代称 {脚处数} 处 · 单西文字母 {脚字母} 处（都要求 0）—— 剥字面量只认双引号",
        )
    )
    脚模 = "const 说明 = `序数代称${值}`;\nconst 样 = /序数代称/;\n"
    脚模处数, 脚模字母 = _计(".js", 脚模)
    出.append(
        _条(
            "正向样本：JS 模板串与正则字面量里的序数代称不报红",
            脚模处数 == 0 and 脚模字母 == 0,
            f"报序数代称 {脚模处数} 处 · 单西文字母 {脚模字母} 处（都要求 0）",
        )
    )

    # ── 反向样本：两档真违规必须抓得住 ──
    反例处数 = "pub fn 样例() -> u32 { let %s = 1; %s }\n" % (序数代称字[0], 序数代称字[0])
    反例处数数, _ = _计(".rs", 反例处数)
    出.append(
        _条(
            "反向样本：序数代称名作局部名 ⇒ 抓到序数代称（且只算一处）",
            反例处数数 == 2,
            f"报序数代称 {反例处数数} 处（要求 2：声明一处 + 使用一处）—— 0 就是空转",
        )
    )
    反例单字母 = "pub fn 样例() -> u32 { let i = 1; i }\n"
    _, 反例单字母数 = _计(".rs", 反例单字母)
    出.append(
        _条(
            "反向样本：`let i = 1;` ⇒ 抓到单西文字母",
            反例单字母数 == 2,
            f"报单西文字母 {反例单字母数} 处（要求 2）",
        )
    )
    皮反例 = "i = 0\n%s = 1\n" % 序数代称字[0]
    皮反例处数, 皮反例字母 = _计(".py", 皮反例)
    出.append(
        _条(
            "反向样本：Python 里的 `i` 与序数代称名都抓得住",
            皮反例处数 == 1 and 皮反例字母 == 1,
            f"报序数代称 {皮反例处数} 处 · 单西文字母 {皮反例字母} 处（都要求 1）",
        )
    )
    脚反例 = "let i = 0;\n"
    _, 脚反例字母 = _计(".js", 脚反例)
    出.append(
        _条(
            "反向样本：JS 里的 `i` 抓得住",
            脚反例字母 == 1,
            f"报单西文字母 {脚反例字母} 处（要求 1）",
        )
    )

    # ── 反向样本：`self.名` 是**本类型的成员定义**，不是「别人家的成员」──
    # 实测漏过：`开发工具/取证/*/形状.py` 的 `self.d` / `self.e`（单字母成员名）。
    # 旧规则把紧跟 `.` 的一律排除 ⇒ 判据看不见它 ⇒ 假阴性。
    自身皮 = "class 盒子:\n    def __init__(self, 数据):\n        self.d = 数据\n        self.e = 1\n"
    _, 自身皮字母 = _计(".py", 自身皮)
    出.append(
        _条(
            "反向样本：Python 的 `self.d = 数据` ⇒ 抓到单西文字母（成员定义不是「别人家的成员」）",
            自身皮字母 == 2,
            f"报单西文字母 {自身皮字母} 处（要求 2：`self.d` 与 `self.e`）—— 0 就是假阴性",
        )
    )
    自身铁 = "impl 盒子 {\n    fn 造(&self) -> u32 { self.n }\n}\n"
    _, 自身铁字母 = _计(".rs", 自身铁)
    出.append(
        _条(
            "反向样本：Rust 的 `self.n`（含 `&self`）⇒ 抓到单西文字母",
            自身铁字母 == 1,
            f"报单西文字母 {自身铁字母} 处（要求 1）",
        )
    )
    # 承重证明（退回一步）：退回旧规则（`. 后一律排除）⇒ 上面那条**必抓不到**。
    自身不排除 = sum(
        1 for 命 in _标识符.finditer(自身皮)
        if 命.start() > 0 and 自身皮[命.start() - 1] == "."
        and _查名().是单西文字母(命.group(0))
    )
    出.append(
        _条(
            "承重证明（退回一步）：`. 后一律排除` 的旧规则 ⇒ `self.d` 必漏",
            自身不排除 == 2,
            f"旧规则下漏掉 {自身不排除} 处（要求 2）—— 证明「放行 self.」这一步真的在承重",
        )
    )

    # ── 承重证明（退回一步）：不剥注释 ⇒ 注释里的序数代称**必被数出来** ──
    # 把「剥」这一步退回一步（直接对原文抽标识符），证明上面那条正向样本不是恒真。
    不剥处数 = sum(1 for 名 in 抽标识符(注释样本)
                 if any(字 in _查名().序数代称字 for 字 in 名))
    出.append(
        _条(
            "承重证明（退回一步）：不剥注释 ⇒ 注释里的序数代称必被数出来",
            不剥处数 > 0,
            f"不剥时报 {不剥处数} 处序数代称（要求 > 0）—— 证明「剥注释」这一步真的在承重",
        )
    )

    # ── Rust 属性里的字母不算标识符（2026-09-27 实测假红）──
    # `#[repr(C)]` 的 `C` 是 ABI 记法，不是标识符 —— 实测 `契约声明/src/契约声明/`
    # 三件 7 处被当成「西文单字母」⇒ 假红，还白占三格基线登记。
    属性样本 = (
        "#[repr(C)]\n#[derive(Clone, Copy)]\npub struct 表段<T> {\n    pub 项表: *const T,\n}\n"
        "#![allow(dead_code)]\n"
    )
    _, 属性字母 = _计(".rs", 属性样本)
    出.append(
        _条(
            "正向样本：Rust 属性（`#[repr(C)]` / `#![…]`）里的字母不算标识符",
            属性字母 == 2,  # 只剩 `表段<T>` 的真泛型参数 `T`（声明处 + 字段类型处）
            f"报单西文字母 {属性字母} 处（要求 2 —— 只该报真泛型参数 `T` 的 2 处；`repr` 的 `C` 不算）",
        )
    )
    # 承重证明（退回一步）：不抹属性 ⇒ `#[repr(C)]` 的 `C` 必被数出来。
    不抹属性字母 = sum(1 for 名 in 抽标识符(去字面量(属性样本))
                  if _查名().是单西文字母(名))
    出.append(
        _条(
            "承重证明（退回一步）：不抹属性 ⇒ `repr(C)` 的 `C` 必被数出来",
            不抹属性字母 == 3,
            f"不抹时报 {不抹属性字母} 处（要求 3 = `repr` 的 `C` + 泛型 `T` 的 2 处）—— "
            f"证明「抹属性」这一步真的在承重",
        )
    )
    return 出
