# -*- coding: utf-8 -*-
"""注入样本 · 判据 ㊽（MCP 工具面自检）。"""
from __future__ import annotations

from pathlib import Path


def 可控自检入口文本(退出码: int = 0, 睡眠毫秒: int = 0, 计数文件: str | None = None) -> str:
    """**可控等价** MCP 自检入口的文本（夹具作用域 —— 真仓那份一个字不动）。

    判据 ㊽ 认「被扫仓里有 `开发工具/MCP服务.py` 就跑它」⇒ 合成仓自带这一份，就把
    **外部真长命令**（真仓 `MCP服务.py --自检`，实测 3157 ms、且随它自身的样本增多而变长）
    换成**可控等价完成状态**：退出码 · 睡眠毫秒 · 调用计数三样都由调用方给。

    **为什么必须有它**（实测首因）：合成仓**没有**这一份时，㊽ 会**退回本验证器所在仓**跑
    真命令 ⇒ 夹具跑一次全量判据被一条外部命令拖成 ~3.5 s；而 `自检_两遍复核收窄` 的
    「提速开关=False」对照要跑**两遍全量** ⇒ 6.3 s > 内阈值 4800 ms ⇒ ⑱ 当场红、
    「干净仓 收窄/全量 都全过」那条断言恒假红（根因与「两遍收窄」这件事毫无关系）。
    夹具自带可控入口后，夹具成本与外部真命令**解耦**（3.5 s → 0.17 s）。

    `计数文件` 给绝对路径时，入口每被跑一次就往它追加一行 —— 用来证「可控命令**真被调用**
    N 次」，不是把判据换成空转蒙过去的。
    """
    行表 = [
        "# 夹具：可控等价 MCP 自检入口（不是真服务；真仓那份不动）。",
        "import sys",
    ]
    if 睡眠毫秒:
        行表.insert(1, "import time")
    if 计数文件:
        # ★ 不给 `encoding=`：夹具规则库的名册是按**干净合成仓**建的，多一个裸名
        #   （`encoding`）就会让判据 55「名册新鲜度」在夹具上假红（实测撞到）。内容只写 `1`。
        行表.append('open(%r, "a").write("1\\n")' % (计数文件,))
    if 睡眠毫秒:
        行表.append("time.sleep(%d / 1000.0)" % (睡眠毫秒,))
    行表.append("sys.exit(%d)" % (退出码,))
    return "\n".join(行表) + "\n"


def 造可控自检入口(临根: Path, 退出码: int = 0, 睡眠毫秒: int = 0,
              计数文件: str | None = None) -> str:
    """把**可控等价**入口写进合成仓 ⇒ 返回相对路径（真仓那份一个字不动）。"""
    路径 = 临根 / "开发工具" / "MCP服务.py"
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        可控自检入口文本(退出码=退出码, 睡眠毫秒=睡眠毫秒, 计数文件=计数文件),
        encoding="utf-8",
    )
    return "开发工具/MCP服务.py"


def 注入_MCP自检(临根: Path) -> str:
    """在合成仓里放一个**自检退出非 0** 的 MCP 服务入口 ⇒ 判据 ㊽ 当场红。

    形状取「入口跑起来就非零退出」这一类（真缺陷长这样：协议层崩 / 工具名非 ASCII /
    拒绝样本没拒，都会让 `--自检` 退出非 0）。判据按被扫仓里的这一份跑 —— 合成夹具的
    自带入口是**可控等价**那一份（`可控自检入口文本`，exit 0），这里把它换成 exit 1
    ⇒ 证「退出码非 0 必被抓」（**失败传递不因夹具替身而丢**）。
    """
    路径 = 临根 / "开发工具" / "MCP服务.py"
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text("import sys\nsys.exit(1)\n", encoding="utf-8")
    return "开发工具/MCP服务.py"
