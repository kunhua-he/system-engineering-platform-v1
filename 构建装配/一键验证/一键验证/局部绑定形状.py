# -*- coding: utf-8 -*-
r"""局部绑定形状 —— 「什么形状算局部绑定」的那张表（判据 ㉒ 第四档 · 命名穷举的局部面）。

**为何单开一件**：`命名扫描.py` 是**剥注释与字符串**的剥器（词法）；这张表是**形状**（哪种写法
算一个绑定）—— 两件事关注点不同，混在一件里会把 `命名扫描.py` 顶过 400 行硬数
（`开发规范.md` §六）。故形状表搬到这里；**面函数（`扫局部绑定` / `有局部绑定`）与
`拆绑定名` · `_括号深度` 留在 `命名扫描.py`** —— 调用方一处不用改。

**两份**（表头有逐条口径）：
  · **单名形** `_单名形`：一个匹配 = 一个名字（`let 名` · `for 名 in` · `catch (名)`）；
  · **多名形** `_多名形`：一个匹配 = 一段**绑定列表**，要拆（元组 `let (a, b)` · 闭包参
    `|a, b|` · `Ok(名)` 模式 · Python 元组解包 · `with … as 名` · `lambda 名` · JS 解构）。

★ 口径仍是**宁漏不假红**：只收「长得像绑定」的形状，凡要先猜的一律不收。
★ `.py` 的两条「语句首」形还要过**括号深度 0**（`_要深度零`；深度表在 `命名扫描._括号深度`）。
"""
import re

# ── 局部绑定（判据 ㉒ 第四档的面）—— 分**单名形**与**多名形**两类：
#   单名形：一个匹配 = 一个名字（`let 名` · `for 名 in` · `catch (名)`）。
#   多名形：一个匹配 = 一段**绑定列表**，要拆（元组 `let (a, b)` · 闭包参 `|a, b|` ·
#           `Ok(名)` 模式 · Python 元组解包 · `with … as 名` · `lambda 名` · JS 解构）。
# ★ 口径仍是**宁漏不假红**：只收「长得像绑定」的形状，凡要先猜的一律不收（残余见 `扫局部绑定`）。
_名式 = r"[A-Za-z_\u4e00-\u9fff][\w\u4e00-\u9fff]*"

# `.py` 的两条「语句首」形 —— 它们必须额外过**括号深度 0**这一关（见 `命名扫描._括号深度`）：
# Python 的多行调用续行（`subprocess.run(cmd,\n    capture_output=True)`）行首与它们**同形**。
_纯赋值形 = re.compile(rf"^[ \t]*({_名式})\s*(?::[^=\n]+)?=(?!=)", re.M)
# ★ 2026-10-08 修**跳行假阳**（546/547 腿实测）：本形的名字列表里原先用 `\s*` 分隔，而 `\s`
#   吃换行 ⇒ 剥完串之后 `return "…", "…"` 的下一个语句首 `落点 = …` 会被并进同一段，抓出一个
#   名叫 `return` 的绑定（实测 `构建装配/形态装配/生成声明/推导比对.py::常量表落点描述`；`v1_edit` 命名闸
#   因此误拒写盘）。名字列表里的分隔只许是**同一行的横空白** ⇒ 一律收紧为 `[ \t]*`。
_元组解包形 = re.compile(
    rf"^[ \t]*\(?(?P<段>{_名式}(?:[ \t]*,[ \t]*\(?{_名式}\)?)+)\)?[ \t]*(?::[^=\n]+)?=(?!=)", re.M)
# 要过「括号深度 0」这一关的形状（**只有 `.py` 这两条**；Rust/JS 的块是 `{}`，不能用深度 0）。
_要深度零 = (_纯赋值形, _元组解包形)

_单名形 = {
    ".rs": (
        re.compile(rf"\blet\s+(?:mut\s+)?({_名式})\s*(?::|=)"),
        re.compile(rf"\bfor\s+({_名式})\s+in\b"),
    ),
    ".py": (
        # 语句首的**纯赋值**（`名 = …`）；`名 += …` / `名 <= …` 不算（`名, 别 = …` 归多名形）。
        _纯赋值形,
    ),
    ".js": (
        re.compile(rf"\b(?:let|const|var)\s+({_名式})\s*(?:=|;|,)"),
        re.compile(rf"\bcatch\s*\(\s*({_名式})\s*\)"),
    ),
}

_多名形 = {
    ".rs": (
        re.compile(rf"\blet\s+(?:mut\s+)?\((?P<段>[^()\n]*)\)\s*(?::[^=\n]+)?="),
        re.compile(rf"\bfor\s+\((?P<段>[^()\n]*)\)\s+in\b"),
        re.compile(rf"\b(?:let|if\s+let|while\s+let)\s+(?:Some|Ok|Err)\s*\(\s*(?:mut\s+)?(?P<段>{_名式})\s*\)"),
        re.compile(rf"(?:^|[{{,;])\s*(?:Some|Ok|Err)\s*\(\s*(?:mut\s+)?(?P<段>{_名式})\s*\)\s*(?:=>|\{{)"),
        re.compile(r"(?:^|[=(,{;:])\s*\|(?P<段>[^|\n]{0,80})\|"),
    ),
    ".py": (
        _元组解包形,
        re.compile(rf"\bfor\s+(?P<段>[^:\n]+?)\s+in\b"),
        re.compile(rf"^[ \t]*(?:async\s+)?(?:with|except)\b[^\n]*?\bas\s+(?P<段>{_名式})", re.M),
        re.compile(r"\blambda\s+(?P<段>[^:\n]*):"),
    ),
    ".js": (
        re.compile(r"\b(?:let|const|var)\s*[\{\[]\s*(?P<段>[^\}\]]*)[\}\]]"),
        re.compile(rf"\bfor\s*\(\s*(?:let|const|var)?\s*(?P<段>{_名式})\s+(?:of|in)\b"),
    ),
}
