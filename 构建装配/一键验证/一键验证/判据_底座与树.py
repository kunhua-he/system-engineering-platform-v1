def 检查16_底座不认识扩展(上层读数: dict) -> list:
    """底座不认识任何扩展（README §五「底座与扩展」硬边界 1 · 扩展根声明.json 文件头同口径）。

    底座里不许出现任何扩展的名字、路径或特例分支 —— 这条此前**一条判据都没有**，
    所以 `对外接口面/调用接口面/src/工具响应_未落.rs` 的回执文本里那句
    「编译链 1101→1102→1103→1106」、以及前端三处点名的扩展名，一路活到 2026-09-27 才被扫出来。

    扫描面与排除项见 底座代码树 / 底座代码面排除 的注释。违规形只有一种：**出现扩展的名字**
    —— `扩展根目录/<层>/<扩展名>` 这种具体路径必然含名字 ⇒ 一并被抓。
    """
    输出缓冲 = []
    文件 = 上层读数["文件"]
    扩展名 = sorted(
        {
            键名.split("/")[2]
            for 键名 in 文件
            if 键名.endswith("/Cargo.toml")
            and 键名.split("/")[0] == "扩展根目录"
            and len(键名.split("/")) >= 4
            and 键名.split("/")[1] in 扩展根三类
        }
    )
    if not 扩展名:
        判不了(
            检查名[15],
            "扩展根目录/{原子支持库 · 组合模块库 · 技能封装库}/<扩展名>/Cargo.toml",
            "扫描 0 个扩展（找不到带 Cargo.toml 的扩展目录）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。一条扩展名都没有的仓天然是绿的，"
            "那不是这条判据的功劳 ⇒ 只能由扩展作者落地（扩展是独立仓，验证面不替它建目录）",
        )
        return 输出缓冲

    扫描件源 = [
        (键名, 一项["文本"])
        for 键名, 一项 in 文件.items()
        if 一项["文本"] is not None
        and 键名.endswith(代码后缀)
        and 键名.split("/")[0] in 底座代码树
        and not 键名.startswith(底座代码面排除)
    ]
    if not 扫描件源:
        判不了(
            检查名[15],
            " · ".join(底座代码树),
            f"底座代码面下 0 个代码件（后缀 {代码后缀}）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。"
            "要么扫描面 / 后缀表坏了，要么底座代码面真的空了 ⇒ 只能由判据作者确认",
        )
        return 输出缓冲

    生产 = 并行生产区(扫描件源, 上层读数["测试文件集"], 保串=True)
    for 键名 in sorted(生产):
        文本 = 生产[键名]
        命中 = [名称 for 名称 in 扩展名 if 名称 in 文本]
        if not 命中:
            continue
        # 行号取第一处命中的行（生产区文本与原文等长 ⇒ 偏移与行号仍对齐）
        位置 = min(文本.find(名称) for 名称 in 命中)
        行号 = 文本.count("\n", 0, 位置) + 1
        输出缓冲.append(
            违规(
                检查名[15],
                f"{键名}:{行号}",
                f"底座里出现了扩展的名字：{命中}",
                f"README §五「底座与扩展」硬边界 1：底座不认识任何扩展 —— 底座里不许出现任何扩展的"
                f"名字、路径或特例分支。扩展名是**扩展自身的**（写在 "
                f"扩展根目录/<层>/<扩展名>/包声明.json 的 `名称` 里），底座要用只能经端点实时取"
                f"（`GET /接口` 回能力清单 · `GET /接口/扩展` 回扩展清单），**不许抄进代码**；"
                f"抄一份的代价是加一个扩展就要改底座（破硬边界 2）⇒ 只能由该面作者改",
            )
        )
    # ── 注释面（2026-10-01 · 判据机制盲区 ③）：`并行生产区` 剥掉注释 ⇒ 只在注释里点名扩展
    #    的看不见。注释命中按「原文数 − 去注释保串数」取（后者只剥注释、保串与测试块 ⇒ 差值
    #    就是注释里的）。存量入基线（形状照判据 ㊵）、新增即红 · 基线只许减。
    实测 = {}
    原文 = {键名: 文本 for 键名, 文本 in 扫描件源}
    for 键名 in sorted(生产):
        净文本 = 去注释保串(原文.get(键名) or "")
        for 名称 in 扩展名:
            处数 = (原文.get(键名) or "").count(名称) - 净文本.count(名称)
            if 处数 > 0:
                实测[(键名, 名称)] = 处数
    基线表 = {}
    解析错误 = None
    基线件 = 上层读数["仓根"] / "构建装配/一键验证/底座扩展名基线.json"
    if not 基线件.is_file():
        解析错误 = "基线文件不存在（构建装配/一键验证/底座扩展名基线.json）"
    else:
        try:
            for 记录 in json.loads(基线件.read_text(encoding="utf-8")).get("条目") or []:
                基线表[(str(记录["件"]), str(记录["名"]))] = int(记录.get("处数", 0))
        except Exception:
            解析错误 = "基线文件解析不了或条目形状不对（要 件/名/处数 三键）"
    if 解析错误:
        输出缓冲.append(
            违规(
                检查名[15],
                "构建装配/一键验证/底座扩展名基线.json",
                解析错误,
                "「存量入基线、新增即红」要求先有存量清单（形状照判据 ㊵）；没有它，"
                "实测的全部注释存量会被算成「新增」⇒ 判据当场红一片，等于没上闸。"
                "基线只能由**声明方**登记（谁欠的债谁登记）⇒ 只能由维护方补",
            )
        )
    else:
        for 键名, 名称 in sorted(实测):
            实际 = 实测[(键名, 名称)]
            登记 = 基线表.get((键名, 名称))
            if 登记 is None:
                输出缓冲.append(
                    违规(
                        检查名[15],
                        f"{键名}::{名称}",
                        f"底座**注释**里点名扩展 `{名称}`（{实际} 处），基线里没有它 ⇒ **新增即红**",
                        "README §五「底座与扩展」硬边界 1：底座不认识任何扩展 —— 名字、路径、"
                        "特例分支都不许出现在底座里（注释里点名也算，注释会被后人当依据抄）。"
                        "修法：把点名换成中性说法（「该扩展」「外部支持库」），或改指实时端点 ⇒ "
                        "只能由该面作者改",
                    )
                )
            elif 实际 > 登记:
                输出缓冲.append(
                    违规(
                        检查名[15],
                        f"{键名}::{名称}",
                        f"底座注释里点名扩展 `{名称}` 实测 {实际} 处 > 基线登记 {登记} 处 ⇒ **存量还在长**",
                        "基线是「存量不许再长」的闸，不是白名单（形状照判据 ㊵）⇒ "
                        "要么改回去，要么同步登记 ⇒ 只能由该面作者处置",
                    )
                )
        for 键名, 名称 in sorted(基线表):
            if 实测.get((键名, 名称), 0) == 0:
                输出缓冲.append(
                    违规(
                        检查名[15],
                        f"{键名}::{名称}",
                        f"基线登记着底座注释里点名扩展 `{名称}`，而实测**已经不出现** ⇒ **陈旧登记**",
                        "「基线只许减」：改掉了就该把登记删掉 ⇒ 只能由维护方删"
                        "（构建装配/一键验证/底座扩展名基线.json）",
                    )
                )
    return 输出缓冲


def 检查17_临时件不落源码树(上层读数: dict) -> list:
    """临时件一律落 `/tmp`（仓外）—— 源码树里不许出现 `_临时_` 前缀的目录或文件。

    为什么有这条：临时件落进源码树会让**别的**判据一起报假红
    （实测：临时声明根在树里时 ⑬ 报 9 条、⑮ 报 1 条，全是假红）。本验证器的扫描面已
    **防御性排除** `_临时_` 前缀（见 `临时目录前缀` / `是临时路径`），所以那些假红不会再出现；
    但「临时件在树里」这件事本身仍违 README §十.1（运行数据/临时件不在源码树内）
    ⇒ 由这一条单独、明确地报出来，指到具体路径并说明「挪到 /tmp 或删掉」。
    """
    输出缓冲 = []
    仓根 = 上层读数["仓根"]
    命中 = []
    for 根目录, 目录表, 文件表 in os.walk(仓根):
        目录表[:] = [目录名 for 目录名 in 目录表 if 目录名 != ".git"]
        临时目录 = [目录名 for 目录名 in 目录表 if 目录名.startswith(常量.临时目录前缀)]
        临时文件 = [文件名 for 文件名 in 文件表 if 文件名.startswith(常量.临时目录前缀)]
        命中 += [取相对路径(仓根, Path(根目录) / 目录名) for 目录名 in 临时目录]
        命中 += [取相对路径(仓根, Path(根目录) / 文件名) for 文件名 in 临时文件]
        # 不再往临时目录里钻（报最外层那一处就够，免得一个临时根报出几百条）
        目录表[:] = [目录名 for 目录名 in 目录表 if not 目录名.startswith(常量.临时目录前缀)]
    for 键名 in sorted(set(命中)):
        输出缓冲.append(
            违规(
                检查名[16],
                键名,
                f"源码树里出现了临时件 `{键名.rsplit('/', 1)[-1]}`",
                "README §十.1：运行数据（数据库 · 缓存 · 日志 · 临时件）不在源码树内。"
                "临时件落仓内会污染判据（实测 ⑬ 报 9 条 · ⑮ 报 1 条，全是假红）⇒ "
                "正解是**临时件一律落 `/tmp`（仓外）**；本验证器的扫描面已防御性排除 `_临时_` 前缀，"
                "但纪律仍由本判据钉住 ⇒ 由建临时件的那条腿清掉（挪走或删除）",
            )
        )
    return 输出缓冲

运行数据目录名 = ("数据库", "缓存", "日志", "临时件")


def 检查20_运行数据不落源码树(上层读数: dict) -> list:
    """**运行数据一律不在源码树内**（`README.md` §十 · 第 13 个唯一物「运行数据根」）。

    依据：`项目文档/决策记录/2026-09-27_运行数据根.md` —— 全平台运行数据（数据库 · 缓存 ·
    日志 · 临时件）的**唯一落点**是 `运行内核/运行数据根/` 给出的那个根（默认在**平台数据目录**，
    可用环境变量 `V1_RUN_DATA_ROOT` 覆盖），**不是源码树**。

    **为什么必须有它**：运行数据落进源码树会同时坏三件事 —— ① 提交里混进机器相关的状态；
    ② `git status` 永远不干净（「干净树重跑回执」这条纪律当场失效）；
    ③ 别的判据开始报假红（与 ⑰ 临时件同一条病，实测过）。

    **与 ⑰ 的分工**：⑰ 管 `_临时_` 前缀（工具造的中间件）；本项管**四个运行数据目录名**。
    两条都不许互相代替 —— 名字不同、来源不同、修法不同。

    **对象数不是 0**：扫的是整棵仓树（`_样本_仓树条目`），故「0 命中」是**真通过**，
    不是空集上的假绿。`运行内核/运行数据根/` 这个 **crate 目录**不算命中 ——
    命中的是**四个运行数据目录名**，crate 的名字是「运行数据根」，与那四个都不同。
    """
    输出缓冲 = []
    仓根 = 上层读数["仓根"]
    命中 = []
    for 根目录, 目录表, 文件表 in os.walk(仓根):
        目录表[:] = [目录名 for 目录名 in 目录表 if 目录名 != ".git"]
        命中 += [取相对路径(仓根, Path(根目录) / 目录名) for 目录名 in 目录表 if 目录名 in 运行数据目录名]
        命中 += [取相对路径(仓根, Path(根目录) / 文件名) for 文件名 in 文件表 if 文件名 in 运行数据目录名]
        # 命中的目录不再下钻（报最外层那一处就够）
        目录表[:] = [目录名 for 目录名 in 目录表 if 目录名 not in 运行数据目录名]
    for 键名 in sorted(set(命中)):
        输出缓冲.append(
            违规(
                检查名[19],
                键名,
                f"源码树里出现了运行数据目录/文件 `{键名.rsplit('/', 1)[-1]}`",
                "README §十：运行数据（数据库 · 缓存 · 日志 · 临时件）**不在源码树内**。"
                "全平台唯一的落点是 `运行内核/运行数据根/` 给出的那个根（默认在**平台数据目录**，"
                "可用 `V1_RUN_DATA_ROOT` 覆盖）。落进源码树的代价：提交里混进机器相关状态 · "
                "`git status` 永远不干净（「干净树重跑回执」当场失效）· 别的判据报假红。"
                "修法：改调 `v1_dataroot`（`确保子目录` / `子目录路径`）拿到仓外那个路径 ⇒ "
                "由落这份数据的节点自身改",
            )
        )
    return 输出缓冲
