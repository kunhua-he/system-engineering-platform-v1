# -*- coding: utf-8 -*-
"""判据 ㊳：台账号不悬空 —— 源码树里 0 处台账引用。

依据：`项目文档/决策记录/2026-09-27_台账号与腿轮引用口径.md` §一（四形态口径）· §二（被忽略的
生成物快照不清）· `项目文档/开发规范/开发规范.md` §八.4（源码注释里不出现台账号，也不出现
「哪条腿 / 哪一轮」）· `项目文档/未完成事项.md` 的「做完即删」纪律。

**为什么要这一条**：台账的纪律是**做完即删** —— 条目一删，指向它的引用就**当场悬空**，
而读者无从查起（`开发规范.md` §八.4 的理由原话：「注释的读者不该被要求去 git 历史里翻一条已销
的台账」）。实测已发生：台账一次删掉五条 ⇒ 一批引用当场悬空。把口径变成常驻判据 ⇒ 引用一出现
就红，不必等下一次批次清存量。

**四形态（口径已裁，不自行发明）** —— 前三形扫**全仓**，第四形**只在散文 `.md` 里认**：

  · **形①②③ 同一个正则**：「台账」或「未完成事项」之后 24 字符内出现 `#` 加数字。
    形③（路径夹在中间）不过是 24 字内的一种，不必单列。
  · **形④ 散文里的裸号**：正则 `(?<!\\w)#[1-9][0-9]{0,3}(?![0-9A-Za-z（])`。
    `\\w` **Unicode 感知** ⇒ 程序文本里的 `预定义#<类原子>` 天然不匹配；十六进制颜色码由
    「不许前导 0」（`[1-9]`）与「右邻不许是字母数字」排掉；`（资源序数）` 由 `(?![（])` 排掉。

**三条排除（都是「程序文本 / 生成物，不是引用」）**：

  · **程序文本**（围栏代码块与**行内代码**）：块 / span 内是**样本 / 程序原文**。实测形状：语料件
    `扩展根目录/…/说明/真文本覆盖.md` 里 DLL 序号写作行内代码里的纯数字名（`#` 加数字），
    与台账引用**同形**——只有「它在程序文本标记里」这条能把两者分开（这正是裁决 §一 排除行
    ②「程序文本里的类原子 / 资源序数」的具体落法，裁决那两个例子用 `<编号>` 占位符、纯数字形
    它没遇到）。★ **本条的假阴性面**：藏在行内代码里的**真**台账引用也不判（同形不可分）——
    如实登记，由作者自行坚守（形式①②③ 那条全仓扫，不受此限）。
    （另：裸号紧跟引号 `"#60"` 那种半角字面量也不判，见下。）
  · **被 git 忽略的生成物**（路径含 `制品产物` 段）：口径见裁决 §二 —— 它是**快照**，要改就改源
    再重出；本判据不清它，也不许手改（手改会让制品清单的 sha256 当场变红）。

**诚实登记（本条的假阴性面）**：形④ 只在 `.md` 里认 ⇒ **代码注释里的裸号不判**（口径的选择，
不是遗漏：代码里 `#` 与属性 / 颜色码 / 注释符同形，全判必假红工厂）。形①②③ 在全仓判 ⇒ 注释里
的「台账」式引用照旧抓得住。另：形①②③ 在 `.md` 里**不排围栏块**（宁可多抓）—— 实测本仓 0 处，
若将来围栏块里真出现台账式引用，本条会红，那正是想要的行为。

三元读数：**通过** = 扫描面非空且 0 命中；**失败** = 命中逐条报出（件 · 行 · 原文）；
**未判** = 扫描面 0 件（空集不算通过）。
"""
from __future__ import annotations

import re

from .小工具 import 判不了, 违规
from .常量 import 检查名


# 台账的两种写法**拆开拼**：本件自身也在扫描面内（形①②③ 扫全仓）—— 整字连写会被自己抓到
# （先例：`注入_行号引用` 把行号写成 `{12}` 正是为躲这个）。
_引用前缀 = ("台" "账", "未完成事项")

# 形①②③：前缀之后 **24 字符内**出现 `#` 加数字（中间允许空白）。
_台账引用 = re.compile("(?:" + "|".join(_引用前缀) + r")[^\n]{0,24}#\s?[0-9]+")

# 形④：裸的号（口径原文，见文件头）。只在 `.md` 的**非围栏**文本上跑。
_裸号引用 = re.compile(r"(?<!\w)#[1-9][0-9]{0,3}(?![0-9A-Za-z（])")

# 围栏块起止行（``` 或 ~~~，允许前导空白与语言标注）。
_围栏行 = re.compile(r"^[ \t]*(?:`{3,}|~{3,})")

# 行内代码 span（markdown 的反引号标记）—— 同围栏块：它是程序文本，不是散文。
_行内代码 = re.compile(r"`[^`\n]*`")

# 被 git 忽略的生成物目录名（裁决 §二：快照不清、也不许手改）。
制品产物段 = "制品产物"

# 紧邻号左侧的引号（半角字面量 ⇒ 不是引用）。
_引号 = ('"', "'")


def 去围栏块(文本: str) -> str:
    """把围栏代码块**整块换成空行**（行数不变 ⇒ 行号仍对得上原文）。"""
    出 = []
    在内 = False
    for 行 in 文本.splitlines(True):
        if _围栏行.match(行):
            在内 = not 在内
            出.append("\n")
            continue
        出.append("\n" if 在内 else 行)
    return "".join(出)


def 去行内代码(文本: str) -> str:
    """把行内代码 span 换成等长空格（列位置不变）。"""
    return _行内代码.sub(lambda 命: " " * len(命.group(0)), 文本)


def 是制品产物(键名: str) -> bool:
    """路径里有 `制品产物` 这一段 ⇒ 被 git 忽略的生成物（裁决 §二：面里排除）。"""
    return 制品产物段 in str(键名).split("/")


# 扫描面在一次运行里不变（判定与对象数各取一次）⇒ 按仓根缓存（同 判据 ㊲ 的先例）。
_面缓存: dict = {}


def 台账号面(上层读数: dict) -> dict:
    """扫描面：全仓**非生成物**件 ⇒ `{键: 文本}`。"""
    键 = str(上层读数["仓根"])
    if 键 in _面缓存:
        return _面缓存[键]
    面 = {
        路: 项["文本"]
        for 路, 项 in 上层读数["文件"].items()
        if 项.get("文本") is not None and not 是制品产物(路)
    }
    _面缓存[键] = 面
    return 面


def 样本_台账号面(上层读数: dict) -> int:
    """对象数：扫描面下的件数（0 ⇒ 未判）。"""
    return len(台账号面(上层读数))


def 扫台账号(扫描面: dict) -> list:
    """扫一遍 ⇒ `[(路径, 行号, 形式, 原文)]`。

    形①②③ 在**原文**上跑（含围栏块，宁可多抓）；形④ 只在 `.md` 的**散文**上跑
    （去围栏块 + 去行内代码），并排掉紧跟引号的半角字面量。
    """
    出 = []
    for 路 in sorted(扫描面):
        if 是制品产物(路):
            continue  # 被忽略的生成物（裁决 §二）；与 台账号面 同一条规则（都调 是制品产物）
        文本 = 扫描面[路] or ""
        if not 文本:
            continue
        for 号, 行 in enumerate(文本.split("\n"), 1):
            if _台账引用.search(行):
                出.append((路, 号, "形①②③（前缀后 24 字符内出现号）", 行.strip()[:120]))
        if not 路.endswith(".md"):
            continue
        散文 = 去行内代码(去围栏块(文本))
        for 号, 行 in enumerate(散文.split("\n"), 1):
            for 命 in _裸号引用.finditer(行):
                if 命.start() > 0 and 行[命.start() - 1] in _引号:
                    continue  # 半角字面量里的号 —— 程序内容，不是引用
                出.append((路, 号, "形④（散文里的裸号）", 行.strip()[:120]))
    return 出


def 检查38_台账号不悬空(上层读数: dict) -> list:
    """源码树里 0 处台账引用（三元：通过 / 失败 / 未判）。

    **失败** = 逐条报出命中（件 · 行 · 形式 · 原文）；**未判** = 扫描面 0 件（空集不算通过）。
    """
    出 = []
    面 = 台账号面(上层读数)
    if not 面:
        判不了(
            检查名[37],
            f"全仓（排除 {制品产物段}）",
            "扫描面下 0 个件（判据没有可查的对象）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一件都没有的仓天然是绿的，"
            "那不是本条判据的功劳 ⇒ 只能由判据作者确认扫描面",
        )
        return 出

    口径 = (
        "`项目文档/决策记录/2026-09-27_台账号与腿轮引用口径.md` §一：台账是**做完即删**的，"
        "指向它的引用会当场悬空，而读者无从查起（`开发规范.md` §八.4）。修法：**清出处、留事实** ——"
        "说「我们试过 X、实测不成立」的句子逐字留着，只去掉号；要指落点就改指**durable** 的"
        "`决策记录/… §节名`（**不许把一个号换成另一个号**，那只是把悬空换个地方）。"
        "⇒ 改指哪一处只有该件的作者能定"
    )
    for 路, 号, 形式, 原文 in 扫台账号(面):
        出.append(违规(检查名[37], f"{路}:{号}", f"{形式}（原文：{原文}）", 口径))
    return 出


def 自检_台账号扫描() -> list:
    """扫描器的身份证（`判据的可信性.md` §三.5：判据的解析器自身也要有反向样本）。

    五问：① 形①②③ 带前缀的两种写法各抓得住；② 形④ 散文里的裸号抓得住；
    ③ 形①②③ 在全仓判 ⇒ 代码件里的也抓得住；④ 围栏块 / 引号字面量 / 行内代码里的一律不算；
    ⑤ 制品产物 的生成物不算。
    """
    样本 = {
        "项目文档/样例.md": (
            "见 台" "账" " #12 那条。\n"
            "另见 未完成事项" ".md " "#" "7。\n"
            "还有裸的 #9 一处。\n"
        ),
        "前端呈现/样例.md": (
            "```text\n"
            "样例原文里的 #1 与 #2 都不算。\n"
            "```\n"
            "半角字面量 \"#60\" 也不算。\n"
            "行内代码 `#59` `#60` 也不算（程序文本）。\n"
        ),
        "构建装配/制品产物/扩展根声明.json": "\"落点\": \"台" "账" " #3\"\n",
        "运行内核/样例.rs": "// 这里写 台" "账" " #4 会被抓到\n",
    }
    命 = 扫台账号(样本)
    说 = " | ".join("%s:%d %s" % (条[0], 条[1], 条[2]) for 条 in 命)

    def 那件(路径: str, 形式前缀: str = "") -> list:
        return [条 for 条 in 命 if 条[0] == 路径 and 条[2].startswith(形式前缀)]

    return [
        ("反向样本：形①②③ 带前缀的两种写法各抓得住（同一散文里两处）",
         len(那件("项目文档/样例.md", "形①②③")) == 2, 说),
        ("反向样本：形④ 散文里的裸号抓得住（三处）",
         len(那件("项目文档/样例.md", "形④")) == 3, 说),
        ("反向样本：形①②③ 在全仓判 ⇒ 代码件里的也抓得住",
         len(那件("运行内核/样例.rs", "形①②③")) == 1, 说),
        ("正向样本：围栏块内的裸号不算 · 半角字面量不算 · 行内代码里的不算",
         not 那件("前端呈现/样例.md"), 说),
        (f"排除：{制品产物段} 的生成物不算", not 那件("构建装配/制品产物/扩展根声明.json"), 说),
    ]
