"""判据 ㊳：台账号不悬空 —— 源码树里 0 处台账引用。

依据：`项目文档/决策记录/2026-09-27_台账号与腿轮引用口径.md` §一（四形态口径）· §二（被忽略的
生成物快照不清）· `项目文档/开发规范/开发规范.md` §八.4（源码注释里不出现台账号，也不出现
「哪条腿 / 哪一轮」）· `项目文档/未完成事项.md` 的「做完即删」纪律。

**为什么要这一条**：台账的纪律是**做完即删** —— 条目一删，指向它的引用就**当场悬空**，
而读者无从查起（`开发规范.md` §八.4 的理由原话：「注释的读者不该被要求去 git 历史里翻一条已销
的台账」）。实测已发生：台账一次删掉五条 ⇒ 一批引用当场悬空。把口径变成常驻判据 ⇒ 引用一出现
就红，不必等下一次批次清存量。

**四形态（口径已裁，不自行发明）** —— 前三形扫**全仓**，第四形**只在散文 `.md` 里认**：

  · **形①②③ 同一个正则**：「台账」或「未完成事项」之后 24 字符内出现 `#` 加数字。
    形③（路径夹在中间）不过是 24 字内的一种，不必单列。
  · **形④ 散文里的裸号**：正则 `(?<!\\w)#[1-9][0-9]{0,3}(?![0-9A-Za-z（])`。
    `\\w` **Unicode 感知** ⇒ 程序文本里的 `预定义#<类原子>` 天然不匹配；十六进制颜色码由
    「不许前导 0」（`[1-9]`）与「右邻不许是字母数字」排掉；`（资源序数）` 由 `(?![（])` 排掉。

**三条排除（都是「程序文本 / 生成物，不是引用」）**：

  · **程序文本**（围栏代码块与**行内代码**）：块 / span 内是**样本 / 程序原文**。实测形状：语料件
    `扩展根目录/…/说明/真文本覆盖.md` 里 DLL 序号写作行内代码里的纯数字名（`#` 加数字），
    与台账引用**同形**——只有「它在程序文本标记里」这条能把两者分开（这正是裁决 §一 排除行
    ②「程序文本里的类原子 / 资源序数」的具体落法，裁决那两个例子用 `<编号>` 占位符、纯数字形
    它没遇到）。★ **本条的假阴性面**：藏在行内代码里的**真**台账引用也不判（同形不可分）——
    如实登记，由作者自行坚守（形式①②③ 那条全仓扫，不受此限）。
    （另：裸号紧跟引号 `"#60"` 那种半角字面量也不判，见下。）
  · **被 git 忽略的生成物**（路径含 `制品产物` 段）：口径见裁决 §二 —— 它是**快照**，要改就改源
    再重出；本判据不清它，也不许手改（手改会让制品清单的 sha256 当场变红）。

**诚实登记（本条的假阴性面）**：形④ 只在 `.md` 里认 ⇒ **代码注释里的裸号不判**（口径的选择，
不是遗漏：代码里 `#` 与属性 / 颜色码 / 注释符同形，全判必假红工厂）。形①②③ 在全仓判 ⇒ 注释里
的「台账」式引用照旧抓得住。另：形①②③ 在 `.md` 里**不排围栏块**（宁可多抓）—— 实测本仓 0 处，
若将来围栏块里真出现台账式引用，本条会红，那正是想要的行为。

三元读数：**通过** = 扫描面非空且 0 命中；**失败** = 命中逐条报出（件 · 行 · 原文）；
**未判** = 扫描面 0 件（空集不算通过）。
"""
from __future__ import annotations

import re

from .小工具 import 判不了, 违规
from .常量 import 检查名
from .判据基线 import 读台账号基线, 库相对路径
