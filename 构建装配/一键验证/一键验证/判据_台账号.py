# 基线**住规则库**（`台账号基线` 表）—— 不再落外部 json（华哥 2026-09-29）。库路径**只此一份**。
台账号基线路径 = 库相对路径


# 台账的两种写法**拆开拼**：本件自身也在扫描面内（形①②③ 扫全仓）—— 整字连写会被自身抓到
# （先例：`注入_行号引用` 把行号写成 `{12}` 正是为躲这个）。
_台账引用前缀 = ("台" "账", "未完成事项")

# 形①②③：前缀之后 **24 字符内**出现 `#` 加数字（中间允许空白）。
# ★ 2026-10-01（判据机制盲区 ②）：并入**无 `#` 的两形** —— ⑤ 前缀 + 空白 + 号（前缀后紧跟
#   空白才算，免得把 `台账号.已载入数()` / `台账号预置了…` 这类标识符 / 句子误判成引用）；
#   ⑥ `未完成事项…第 N 条`。两形都是现场实测的存量写法，旧正则只认 `#` 形 ⇒ 看不见。
_台账引用 = re.compile(
    "(?:" + "|".join(_台账引用前缀) + r")[^\n]{0,24}#\s?[0-9]+"
    r"|台" r"账[ \t]+[0-9]{1,4}(?![0-9A-Za-z])"
    r"|未完成事项[^\n]{0,8}第\s*[0-9]+\s*条"
)

# 形④：裸的号（口径原文，见文件头）。只在 `.md` 的**非围栏**文本上跑。
_裸号引用 = re.compile(r"(?<!\w)#[1-9][0-9]{0,3}(?![0-9A-Za-z（])")

# 围栏块起止行（``` 或 ~~~，允许前导空白与语言标注）。
_围栏行 = re.compile(r"^[ \t]*(?:`{3,}|~{3,})")

# 行内代码 span（markdown 的反引号标记）—— 同围栏块：它是程序文本，不是散文。
_行内代码 = re.compile(r"`[^`\n]*`")

# 被 git 忽略的生成物目录名（裁决 §二：快照不清、也不许手改）。
制品产物段 = "制品产物"

# 紧邻号左侧的引号（半角字面量 ⇒ 不是引用）。
_引号 = ('"', "'")


def 去围栏块(文本: str) -> str:
    """把围栏代码块**整块换成空行**（行数不变 ⇒ 行号仍对得上原文）。"""
    输出缓冲 = []
    在内 = False
    for 源码行 in 文本.splitlines(True):
        if _围栏行.match(源码行):
            在内 = not 在内
            输出缓冲.append("\n")
            continue
        输出缓冲.append("\n" if 在内 else 源码行)
    return "".join(输出缓冲)


def 去行内代码(文本: str) -> str:
    """把行内代码 span 换成等长空格（列位置不变）。"""
    return _行内代码.sub(lambda 命中: " " * len(命中.group(0)), 文本)


def 是制品产物(键名: str) -> bool:
    """路径里有 `制品产物` 这一段 ⇒ 被 git 忽略的生成物（裁决 §二：面里排除）。"""
    return 制品产物段 in str(键名).split("/")


# 扫描面在一次运行里不变（判定与对象数各取一次）⇒ 按仓根缓存（同 判据 ㊲ 的先例）。
台账号面缓存: dict = {}


def 台账号面(上层读数: dict) -> dict:
    """扫描面：全仓**非生成物**件 **∪ 库 `条款` 表的行** ⇒ `{键: 文本}`。

    ★ 2026-10-01（md 收尾）：已删 md 的正文住在库 `条款` 表里，而 `.db` 整份**不是合法
    UTF-8** ⇒ 走树看不见它，那批正文成了盲区（md 在的时候它在面里，删了之后就没人再看）。
    补回：把 `条款` 表的行按「件」拼进面（读法只此一处 = `条款文本.读条款件`，与 ㊵/㊹ 同一份）。
    """
    键名 = str(上层读数["仓根"])
    if 键名 in 台账号面缓存:
        return 台账号面缓存[键名]
    扫描面 = {
        路径: 一项["文本"]
        for 路径, 一项 in 上层读数["文件"].items()
        if 一项.get("文本") is not None and not 是制品产物(路径)
    }
    扫描面.update(读条款件(上层读数["仓根"]))
    台账号面缓存[键名] = 扫描面
    return 扫描面


def 样本_台账号面(上层读数: dict) -> int:
    """对象数：扫描面下的件数（0 ⇒ 未判）。"""
    return len(台账号面(上层读数))


def 扫台账号(扫描面: dict) -> list:
    """扫一遍 ⇒ `[(路径, 行号, 形式, 原文)]`。

    形①②③ 在**原文**上跑（含围栏块，宁可多抓）；形④ 只在 `.md` 的**散文**上跑
    （去围栏块 + 去行内代码），并排掉紧跟引号的半角字面量。
    """
    输出缓冲 = []
    for 路径 in sorted(扫描面):
        if 是制品产物(路径):
            continue  # 被忽略的生成物（裁决 §二）；与 台账号面 同一条规则（都调 是制品产物）
        文本 = 扫描面[路径] or ""
        if not 文本:
            continue
        for 号值, 源码行 in enumerate(文本.split("\n"), 1):
            # 三种带前缀的写法共用一个正则（同一份扫描面）：按命中文本回判是哪一形。
            for 匹配结果 in _台账引用.finditer(源码行):
                输出缓冲.append(
                    (
                        路径,
                        号值,
                        "形①②③（前缀后 24 字符内出现号）"
                        if "#" in 匹配结果.group(0)
                        else (
                            "形⑥（未完成事项 … 第 N 条）"
                            if "第" in 匹配结果.group(0)
                            else "形⑤（前缀 + 空白 + 号）"
                        ),
                        源码行.strip()[:120],
                    )
                )
        if not 路径.endswith(".md"):
            continue
        散文 = 去行内代码(去围栏块(文本))
        for 号值, 源码行 in enumerate(散文.split("\n"), 1):
            for 匹配结果 in _裸号引用.finditer(源码行):
                if 匹配结果.start() > 0 and 源码行[匹配结果.start() - 1] in _引号:
                    continue  # 半角字面量里的号 —— 程序内容，不是引用
                输出缓冲.append((路径, 号值, "形④（散文里的裸号）", 源码行.strip()[:120]))
    return 输出缓冲


def 检查38_台账号不悬空(上层读数: dict) -> list:
    """源码树里 0 处台账引用（三元：通过 / 失败 / 未判）。

    **失败** = 逐条报出命中（件 · 行 · 形式 · 原文）；**未判** = 扫描面 0 件（空集不算通过）。
    """
    输出缓冲 = []
    扫描面 = 台账号面(上层读数)
    if not 扫描面:
        判不了(
            检查名[37],
            f"全仓（排除 {制品产物段}）",
            "扫描面下 0 个件（判据没有可查的对象）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一件都没有的仓天然是绿的，"
            "那不是本条判据的功劳 ⇒ 只能由判据作者确认扫描面",
        )
        return 输出缓冲

    口径 = (
        "`项目文档/决策记录/2026-09-27_台账号与腿轮引用口径.md` §一：台账是**做完即删**的，"
        "指向它的引用会当场悬空，而读者无从查起（`开发规范.md` §八.4）。修法：**清出处、留事实** ——"
        "说「我们试过 X、实测不成立」的句子逐字留着，只去掉号；要指落点就改指**durable** 的"
        "`决策记录/… §节名`（**不许把一个号换成另一个号**，那只是把悬空换个地方）。"
        "⇒ 改指哪一处只有该件的作者能定"
    )
    命中 = 扫台账号(扫描面)
    # ── 存量入基线（形状照判据 ㊵）────────────────────────────────────────────
    # ★ 2026-10-01（判据机制盲区 ②）：旧正则只认 `#` 形 ⇒ 两形存量（前缀 + 空白 + 号 · `未完成
    #   事项…第 N 条`）从不被看见；纳入后存量当场红 ⇒ 按「存量入基线、新增即红 · 基线只许减」
    #   收口。基线读不到即 fail-closed（同 ㊵）。
    基线表, 解析错误 = 读台账号基线(上层读数["仓根"])
    if 解析错误:
        return [
            违规(
                检查名[37],
                台账号基线路径,
                解析错误,
                "「存量入基线、新增即红」要求先有存量清单（形状照判据 ㊵）；没有它，"
                "实测的全部存量会被算成「新增」⇒ 判据当场红一片，等于没上闸。"
                "基线只能由**声明方**登记（谁欠的债谁登记）⇒ 只能由维护方补（库 `台账号基线` 表）",
            )
        ]
    实测 = {}
    for 路径, 号值, 形式, 原文 in 命中:
        键名 = (路径, 形式.split("（", 1)[0])
        实测[键名] = 实测.get(键名, 0) + 1
    for 路径, 号值, 形式, 原文 in 命中:
        if 基线表.get((路径, 形式.split("（", 1)[0])) is None:
            输出缓冲.append(违规(检查名[37], f"{路径}:{号值}", f"{形式}（原文：{原文}）", 口径))
    for 键名, 实际 in sorted(实测.items()):
        登记 = 基线表.get(键名)
        if 登记 is not None and 实际 > 登记:
            输出缓冲.append(
                违规(
                    检查名[37],
                    f"{键名[0]}::{键名[1]}",
                    f"「{键名[1]}」实测 {实际} 处 > 基线登记 {登记} 处 ⇒ **存量还在长**",
                    "基线是「存量不许再长」的闸，不是白名单（形状照判据 ㊵）。这一处已在基线里"
                    "登记过，却又多了 ⇒ 要么改回去，要么在提交信息里说明为什么必须涨并同步登记 ⇒ "
                    "只能由该件的作者处置",
                )
            )
    # ── 基线里不许留**陈旧登记**（与判据 ㊵ 同一条）──
    for 键名, 登记 in sorted(基线表.items()):
        if 实测.get(键名, 0) == 0:
            输出缓冲.append(
                违规(
                    检查名[37],
                    f"{键名[0]}::{键名[1]}",
                    f"基线登记着「{键名[1]}」{登记} 处，而实测这一处**已经不出现** ⇒ **陈旧登记**",
                    "「基线只许减」：改掉了就该把登记删掉。留着它，基线读数就不再是现状"
                    f"（读的人会以为债还在）⇒ 只能由维护方删（{台账号基线路径}）",
                )
            )
    return 输出缓冲


def 自检_台账号扫描() -> list:
    """扫描器的身份证（`判据的可信性.md` §三.5：判据的解析器自身也要有反向样本）。

    五问：① 形①②③ 带前缀的两种写法各抓得住；② 形④ 散文里的裸号抓得住；
    ③ 形①②③ 在全仓判 ⇒ 代码件里的也抓得住；④ 围栏块 / 引号字面量 / 行内代码里的一律不算；
    ⑤ 制品产物 的生成物不算。
    """
    样本 = {
        "项目文档/样例.md": (
            "见 台" "账" " #12 那条。\n"
            "另见 未完成事项" ".md " "#" "7。\n"
            "还有裸的 #9 一处。\n"
        ),
        "前端呈现/样例.md": (
            "```text\n"
            "样例原文里的 #1 与 #2 都不算。\n"
            "```\n"
            "半角字面量 \"#60\" 也不算。\n"
            "行内代码 `#59` `#60` 也不算（程序文本）。\n"
        ),
        "构建装配/制品产物/扩展根声明.json": "\"落点\": \"台" "账" " #3\"\n",
        "运行内核/样例.rs": "// 这里写 台" "账" " #4 会被抓到\n",
    }
    匹配结果 = 扫台账号(样本)
    说明文字 = " | ".join("%s:%d %s" % (一条[0], 一条[1], 一条[2]) for 一条 in 匹配结果)

    def 那件(路径: str, 形式前缀: str = "") -> list:
        return [一条 for 一条 in 匹配结果 if 一条[0] == 路径 and 一条[2].startswith(形式前缀)]

    return [
        ("反向样本：形①②③ 带前缀的两种写法各抓得住（同一散文里两处）",
         len(那件("项目文档/样例.md", "形①②③")) == 2, 说明文字),
        ("反向样本：形④ 散文里的裸号抓得住（三处）",
         len(那件("项目文档/样例.md", "形④")) == 3, 说明文字),
        ("反向样本：形①②③ 在全仓判 ⇒ 代码件里的也抓得住",
         len(那件("运行内核/样例.rs", "形①②③")) == 1, 说明文字),
        ("正向样本：围栏块内的裸号不算 · 半角字面量不算 · 行内代码里的不算",
         not 那件("前端呈现/样例.md"), 说明文字),
        (f"排除：{制品产物段} 的生成物不算", not 那件("构建装配/制品产物/扩展根声明.json"), 说明文字),
    ]
