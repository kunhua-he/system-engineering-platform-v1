# 合成索引：给 `--自测` 的合成仓挂一份索引库（#225 的硬约束）
# ════════════════════════════════════════════════════════════════════════════
#
# **为什么必须要有它**：判据 ㉒ 的面已换成**代码地图索引**（读法见
# `开发工具/代码地图/索引库.全部定义`）。而索引是**整仓产出**的（`codegraph init <仓根>`）
# ⇒ `--自测` 的临时夹具仓没有索引 ⇒ 判据在夹具上会永远「未判」，而正向样本要求
# 「干净夹具上所有判据通过」—— 两者直接矛盾。解得开的那一步就是把「面」与「索引从哪来」
# **拆开**：真仓读真索引（tree-sitter 出的，最准），夹具仓读本件造的合成索引。
#
# ★ **合成索引的节点从哪来**（诚实登记）：夹具仓没有 tree-sitter 那份解析，所以合成索引由
#   本仓既有的**命名扫描**剥器从夹具源文件里抽标识符得出。⇒ 它只对**夹具**成立
#   （夹具是本仓自身造的，不是用户输入）；真仓一律读真索引。这不是「两条腿」：
#   **判据的面始终是索引**、读法只有一处（`索引库.全部定义`），本件只负责把索引放到
#   那个位置，不参与任何判定。

# 库文件名与**主人**（`开发工具/代码地图/落点.py::库文件名`，经 `常量` 转出）同一份；
# 目录名另取一个，**刻意不叫** `.codegraph` —— 免得将来有人把合成库当成真库读。
合成索引目录名 = "_合成索引_"
合成索引文件名 = 库文件名

# codegraph 的 `nodes` 表的列（本件只写上层读得到的那几列，其余留默认）。
_合成索引建表 = (
    "create table nodes (id text, kind text, name text, qualified_name text, "
    "file_path text, language text, start_line integer, end_line integer, "
    "start_column integer, end_column integer, signature text)",
    "create table edges (source text, target text, kind text, line integer, col integer)",
)

# 后缀 → 索引器认的语言名（只为如实填 `language` 列，不参与判定）。
_合成索引语言名 = {".rs": "rust", ".py": "python", ".js": "javascript",
              ".ts": "typescript", ".tsx": "typescript", ".vue": "vue"}


def _合成索引节点(件表: dict) -> list:
    """夹具的文件表 ⇒ codegraph 形状的节点行（每个标识符一行，与真索引同粒度）。

    抽法走 `命名扫描`（与判据 ㉒ 旧面的剥器**同一套**）：真索引的 `variable` 节点就覆盖到
    「声明过的名字」，而这里的剥器抽的也正是这些 —— 两边在夹具上读数一致。
    行号从**剥后的净文本**上数（长度不变 ⇒ 行号与原文对齐）。
    """
    from .命名扫描 import _标识符, _是自身成员访问, 剥后缀

    行表 = []
    for 键名 in sorted(件表):
        源文本 = 件表[键名]
        if not 源文本:
            continue
        源码后缀 = "." + 键名.rsplit(".", 1)[-1]
        净文本 = 剥后缀(源码后缀, 源文本)
        for 序号, 命中 in enumerate(
            命中 for 命中 in _标识符.finditer(净文本)
            if not (命中.start() > 0 and 净文本[命中.start() - 1] == "."
                    and not _是自身成员访问(净文本, 命中.start()))
        ):
            名称 = 命中.group(0)
            行号 = 净文本[: 命中.start()].count("\n") + 1
            列号 = 命中.start() - (净文本.rfind("\n", 0, 命中.start()) + 1)
            行表.append((
                "variable:%s:%d" % (键名, 序号),
                "variable", 名称, 名称, 键名, _合成索引语言名.get(源码后缀, ""),
                行号, 行号, 列号, 列号 + len(名称), "",
            ))
    return 行表


def 建合成索引(仓根: Path, 件表: dict) -> Path:
    """把 `件表` 写成一份索引库 ⇒ **库路径**（`Path`）。

    `件表` 必须是**当场那一份**（`上["文件"]` 的 `{键: 文本}`）—— 不能从 `干净合成仓()`
    重取：`--自测` 的反向样本是在 `造干净仓` **之后**才往夹具里注入违规的
    （实测：重取 ⇒ 注入件不在索引里 ⇒ ㉒ 的反向样本抓不到，三条断言全红）。

    写在**仓外**（`<仓根>._合成索引_/codegraph.db`）：写进被扫的树会多出一个目录，
    那样 ⑰（临时件）与 ⑳（运行数据）会拿它当对象 —— 面被自身改了，读数就不真。

    ★ **线程安全**（判据批是 32 路线程池，见 `验证.分片跑任务表`）：判据 ㉒/㊷ 会各自
    同时来取面 ⇒ 不串行化就会两个线程同时 `unlink` + 重建同一个库，`commit()` 当场
    `sqlite3.OperationalError: disk I/O error`（实测 32 线程并发 `ok 1 / err 31`）。
    本函数用模块级锁把「查缓存 → 建库 → 写缓存」整段串行化，并把**缓存收进本函数**
    （同一仓根只建一次，后到的线程直接命中缓存）⇒ 并发下退化为「一次建库 + 其余命中」。
    单线程行为逐字不变：第一趟建库、写缓存、返回同一路径。
    """
    import sqlite3

    键名 = str(仓根)
    with _合成索引锁:
        记住 = _合成索引缓存.get(键名)
        if 记住 is not None and 记住.is_file():
            return 记住
        动态库 = Path(str(仓根) + "." + 合成索引目录名) / 合成索引文件名
        动态库.parent.mkdir(parents=True, exist_ok=True)
        if 动态库.is_file():
            动态库.unlink()  # 每轮重建：同一夹具被跑多次时不许读到上一轮的节点
        连接 = sqlite3.connect(str(动态库))
        try:
            for 语句 in _合成索引建表:
                连接.execute(语句)
            连接.executemany("insert into nodes values (?,?,?,?,?,?,?,?,?,?,?)",
                           _合成索引节点(件表))
            连接.commit()
        finally:
            连接.close()
        _合成索引缓存[键名] = 动态库
        return 动态库


# 合成索引的按仓缓存（键 = 仓根路径）。**一次 `验证` 只建一次**：`上["文件"]`
# 在一次调用里不变，而 `数命中` / `命名扫描件` 会各取一次面 ⇒ 不缓存就白重建两遍。
# 不跨调用复用：`--自测` 的注入发生在两次 `验证` 之间（照 `跑一遍` 里「一次验证只读一次仓」同一理由）。
_合成索引缓存: dict = {}

# 建合成索引的模块级锁：判据批是 32 路线程池（`验证.分片跑任务表`），而 ㉒/㊷ 会同时
# 来取面 ⇒ 必须把「查缓存 → 建库 → 写缓存」整段串行化，否则并发重建同一库会
# `sqlite3.OperationalError: disk I/O error`（实测 32 线程 `ok 1 / err 31`）。
_合成索引锁 = threading.Lock()

# **哪些仓是夹具**（`造干净仓` 登记）。只给它们造合成索引 —— 真仓没有索引时**不许**造：
# 真仓缺索引是「代码地图没建」⇒ 那是**未判**；造一份合成索引会把真仓的符号面偷偷换掉，
# 而且会在仓外留一个 `<仓根>._合成索引_` 目录（垃圾）。夹具是**本仓自身造的**，
# 它的面由本仓包底才成立。
_夹具仓根集: set = set()


def 登记夹具仓根(仓根) -> None:
    """`造干净仓` 叫一声：这个仓是夹具（写面那一侧的**唯一**登记口）。"""
    _夹具仓根集.add(str(仓根))


def 索引陈旧读数(仓根: Path, 件表: dict) -> tuple:
    """被扫仓该读的那份索引**陈旧 / 不在**吗 ⇒ `(是否 fail-closed, 说明)`。

    **为什么要有这一件**（2026-09-30 收紧 · 判据假绿审计 ㉒/㊷）：定义面是**派生件**
    （`.codegraph/codegraph.db`，不进版本库、不随源码自动更新）⇒ 陈旧时判据要么假绿
    （新写的名看不见）要么假红（改好的名还在）。判定本体在主人件
    `开发工具/代码地图/索引库.索引陈旧`（**别在判据里内联**）；本函数只做一件事：
    **夹具仓不走它** —— 夹具的索引是 `建合成索引` 按**当场件表**现造的
    （落 `<仓根>._合成索引_/`）⇒ 恒新鲜，判它会把正向样本当场打红。
    """
    if str(仓根) in _夹具仓根集:
        return False, "合成索引（按当场件表现造）"
    import sys as _sys

    根目录 = str(常量.仓根 / "开发工具")
    if 根目录 not in _sys.path:
        _sys.path.insert(0, 根目录)
    import 代码地图.索引库 as 索引库

    return 索引库.索引陈旧(仓根, 件表)


def 索引路径(仓根: Path, 件表: dict, 检查: str) -> Path:
    """本仓**该读哪个索引**：真仓读真索引，**夹具仓**（无真索引）现场造一份合成索引。

    真库的落点是 `<被扫的仓>/.codegraph/codegraph.db`（**不是**判据自身所在那个仓的库 ——
    拿后者的库去扫夹具，读到的是真仓的符号，那是假绿）。返回 `Path`
    （`索引库.全部定义` 吃 `Path`）。

    真仓缺索引 ⇒ 返回那个**不存在的真路径**（`索引库.全部定义` 回空表 ⇒ 判据报**未判**）——
    那是诚实的读数，不是通过。不许拿合成索引顶替（那就把真仓的面换掉了）。

    ★ 2026-09-30 收紧（判据假绿审计 ㉒/㊷）：读之前先做**索引新鲜度自查** —— 库比源件旧
    （或**不在**）⇒ 报 `判不了`（fail-closed，阻断退出码），文案指路
    `python3 开发工具/代码地图.py 建`。定义面是**派生件**（不进版本库、不随源码自动更新），
    库旧时判据要么假绿（新写的名看不见）要么假红（改好的名还在）。判定本体在主人件
    `开发工具/代码地图/索引库.索引陈旧`（**别在判据里内联**）；本函数只负责「什么时候判它」。
    `检查` = 调用方那条判据的名字（未判读数要挂在它名下）—— **必传**，别给它默认值
    （漏传就静默少一道闸）。夹具仓的合成索引按**当场件表**现造 ⇒ 恒新鲜，不走这一步。
    """
    判定汇总 = 索引陈旧读数(仓根, 件表)
    if 判定汇总[0]:
        判不了(
            检查,
            "代码地图索引（.codegraph/codegraph.db）",
            f"判不了：{判定汇总[1]}",
            "定义面是**派生件**（不进版本库、不随源码自动更新）⇒ 库旧时新写的违规名看不见"
            "（假绿）、改好的名还在（假红），判据的读数就不真。修法：先跑 "
            "`python3 开发工具/代码地图.py 建`，再重跑 ⇒ 只能由维护方刷索引",
        )
    真库 = Path(str(仓根)) / 库目录名 / 库文件名
    if 真库.is_file():
        return 真库
    if str(仓根) not in _夹具仓根集:
        return 真库  # 真仓没索引 = 未判（调用方据空表报未判），不造合成索引
    # 建库 + 缓存都在 `建合成索引` 里、且持同一把模块级锁 ⇒ 并发下只建一次（见那里）。
    return 建合成索引(仓根, 件表)
