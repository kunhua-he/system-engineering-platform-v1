def 读一个文件(任务: tuple) -> tuple:
    """一个分片的全部重活：读字节 → 解 UTF-8 → 解 JSON。都在这里做，并行跑。"""
    仓根, 路径 = 任务
    键名 = 取相对路径(仓根, 路径)
    try:
        字节 = 路径.read_bytes()
    except OSError as 错误:
        return 键名, {"文本": None, "数据": None, "错误": f"读不动：{错误}"}
    try:
        源文本 = 字节.decode("utf-8")
    except UnicodeDecodeError as 错误:
        return 键名, {"文本": None, "数据": None, "错误": f"不是 UTF-8：{错误}"}
    配置表 = None
    错误 = None
    if 路径.suffix == ".json":
        try:
            配置表 = json.loads(源文本)
        except json.JSONDecodeError as 解析错:
            return 键名, {"文本": 源文本, "数据": None, "错误": f"JSON 解析失败：{解析错}"}
        if not isinstance(配置表, dict):
            return 键名, {
                "文本": 源文本,
                "数据": None,
                "错误": f"顶层不是对象（是 {type(配置表).__name__}）",
            }
    return 键名, {"文本": 源文本, "数据": 配置表, "错误": 错误}


def 并行读文件(仓根: Path, 路径表: list) -> dict:
    任务 = [(仓根, 路径) for 路径 in 路径表]
    with ThreadPoolExecutor(max_workers=并发度) as 线程池:
        return dict(线程池.map(读一个文件, 任务))


def 建上下文(仓根: Path) -> dict:
    契约根 = 仓根 / 契约目录名
    # 一次扫全，按文件分片并行读（读 + 解 UTF-8 + 解 JSON 都在分片里）；
    # 后面所有检查都在内存里做，不再回磁盘。
    契约件 = sorted(契约根.rglob("*.json")) if 契约根.is_dir() else []
    # `rglob` 不走 `跳过目录` / 临时件排除 ⇒ 这里按同一口径再筛一遍
    # （否则落进 `契约声明/` 的临时声明根仍会被读进来）。
    契约件 = [声明件 for 声明件 in 契约件 if not 是临时路径(取相对路径(仓根, 声明件))]
    源件 = [源路径 for 源路径 in 扫源文件(仓根) if 源路径.suffix != ".json"]
    全仓件表 = 并行读文件(仓根, 契约件 + 源件)

    平台声明 = 取文件键值(全仓件表, f"{契约目录名}/平台声明.json")
    号段图 = 取文件键值(全仓件表, 号段图路径)
    常量表 = 取文件键值(全仓件表, 常量表路径)
    作废 = 取文件键值(全仓件表, f"{契约目录名}/作废号表.json")
    冻结 = 取文件键值(全仓件表, f"{契约目录名}/冻结登记.json")

    编号表 = {}
    目录存在 = {}
    for 目录名 in 编号目录:
        目录存在[目录名] = (契约根 / 目录名).is_dir()
        记录表 = []
        路径前缀 = f"{契约目录名}/{目录名}/"
        for 键名 in sorted(全仓件表):
            if not 键名.startswith(路径前缀) or not 键名.endswith(".json"):
                continue
            记录表.append(
                {
                    "目录": 目录名,
                    "文件名": 键名.rsplit("/", 1)[1],
                    "键": 键名,
                    "字段": 编号字段[目录名],
                    "数据": 全仓件表[键名]["数据"],
                    "错误": 全仓件表[键名]["错误"],
                }
            )
        编号表[目录名] = 记录表

    return {
        "仓根": 仓根,
        "文件": 全仓件表,
        "平台": 平台声明,
        "号段图": 号段图,
        "常量表": 常量表,
        "作废": 作废,
        "冻结": 冻结,
        "编号表": 编号表,
        "编号目录存在": 目录存在,
        "包到层": 建包到层映射(全仓件表),
        "测试文件集": 建测试文件集(全仓件表),
    }


def 建包到层映射(全仓件表: dict) -> dict:
    """Cargo 包名 → 层。包名里的 `-` 换成 `_`（Rust 的 `use` 用下划线）。"""
    项表 = {}
    for 键名, 文件项 in 全仓件表.items():
        if not 键名.endswith("Cargo.toml") or 文件项["文本"] is None:
            continue
        名配 = re.search(r"^\s*name\s*=\s*\"([^\"]+)\"", 文件项["文本"], re.M)
        if not 名配:
            continue
        层级 = 路径到层(键名)
        if 层级:
            项表[名配.group(1).replace("-", "_")] = 层级
    return 项表


def 路径到层(键名: str) -> str:
    头部 = 键名.split("/", 1)[0]
    return 顶层目录到层.get(头部, "")


def 取文件键值(全仓件表: dict, 键名: str):
    文件项 = 全仓件表.get(键名)
    return None if 文件项 is None else 文件项["数据"]


