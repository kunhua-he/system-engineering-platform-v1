def 扫源文件(仓根: Path) -> list:
    """全仓源码文件（跳过生成物与参照物目录）。"""
    判定汇总 = []
    for 根目录, 目录表, 文件表 in os.walk(仓根):
        目录表[:] = [
            目录名
            for 目录名 in 目录表
            if 目录名 not in 跳过目录 and not 目录名.startswith(常量.临时目录前缀)
        ]
        for 名称 in 文件表:
            if 名称.endswith(扫描后缀):
                判定汇总.append(Path(根目录) / 名称)
    return 判定汇总


