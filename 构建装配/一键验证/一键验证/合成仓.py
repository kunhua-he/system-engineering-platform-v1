def 造干净仓(临根: Path) -> None:
    for 相对路径, 件内容 in 干净合成仓().items():
        路径 = 临根 / 相对路径
        路径.parent.mkdir(parents=True, exist_ok=True)
        路径.write_text(件内容, encoding="utf-8")
    # 登记成夹具仓：判据 ㉒ 的面是**索引**，而夹具仓没有索引（索引是整仓产出的）
    # ⇒ 只有这样登记过的仓，`读文件.索引路径` 才会给它现场造一份合成索引（#225 的硬约束）。
    # 真仓没索引 ⇒ 判据报**未判**（诚实读数），不许造合成索引顶替 —— 那会把真仓的面换掉。
    #
    # ★ 索引**不在造仓时建**：`--自测` 的注入发生在 `造干净仓` **之后**，那时建会漏掉注入件
    #   （实测：㉒ 的两条反向样本抓不到，三条断言全红）。改由 `读文件.索引路径`
    #   在**判据要读面那一刻**用当场件表建。
    from .读文件 import 登记夹具仓根

    登记夹具仓根(临根)
    # 夹具的**最小规则库**（名册 + 两张空基线）—— 判据 ㉒/㊷ 都从它读。
    # ★ 必须在**写盘之后、注入之前**建：名册取的是夹具的干净代码 ⇒ 注入件的名不在名册里。
    from .夹具规则库 import 建夹具规则库

    建夹具规则库(临根, 干净合成仓())
    # 四张判据基线（⑲/㉕/㊴/㊵）也住库 —— 建库之后写进去（名册已在建库时写入）。
    写夹具基线(临根)
