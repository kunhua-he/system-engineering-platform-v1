# -*- coding: utf-8 -*-
"""干净合成仓里 ㊸（接口面常量跨语言一致）的夹具（从 合成仓.py 拆出，控单件行数）。

`接口面夹具(节点件)` 收**基础节点件**：`契约声明/常量表.json` 要补一条「接口端口」
（判据 ㊸ 的端口一项按它的唯一来源取），`契约声明/src/声明数据.rs` 要补一条对应的生成物
常量（判据 ⑬② 要求常量表每条常量在生成物里有对应常量）—— 两处都**就地加**，不重抄基础件。
"""
from __future__ import annotations

import json

from .合成仓 import 转JSON文本
from .常量 import 接口面件, 命令行件


def 接口面夹具(节点件: dict) -> dict:
    """返回 {相对路径: 内容}：判据 ㊸ 在干净合成仓上必须过（两侧逐项一致）。"""
    常量表 = json.loads(节点件["契约声明/常量表.json"])
    常量表["常量"].append({"名": "接口端口", "值": 43110, "类型": "整数", "依据": "样例"})
    声明数据 = 节点件["契约声明/src/声明数据.rs"] + "pub const 底座接口端口: u16 = 43110;\n"
    return {
        "契约声明/常量表.json": 转JSON文本(常量表),
        "契约声明/src/声明数据.rs": 声明数据,
        接口面件: (
            "//! 样例：对外接口面常量（判据 ㊸/㊼ 的正向样本）。\n"
            'pub const 监听地址: &str = "127.0.0.1";\n'
            'pub const 路径_根: &str = "/接口";\n'
            'pub const 路径_能力: &str = "/接口/能力/";\n'
            'pub const 路径_调用: &str = "/接口/调用";\n'
            'pub const 路径_声明: &str = "/接口/声明";\n'
            # 判据 ㊼（案例布局与形状文档一致）的正向样本：三条案例布局常量
            # （值逐字出现在夹具库 `条款` 表的 `测试验证/案例/形状.md` §一里）。
            'pub const 案例根: &str = "测试验证/案例";\n'
            'pub const 案例回执件: &str = "运行回执.jsonl";\n'
            'pub const 案例声明件: &str = "案例.json";\n'
        ),
        命令行件: (
            '"""样例：命令行界面常量（判据 ㊸ 的正向样本）。"""\n'
            "默认端口 = 43110\n"
            '回环地址 = "127.0.0.1"\n'
            '路径_根 = "/接口"\n'
            '路径_能力 = "/接口/能力/"\n'
            '路径_调用 = "/接口/调用"\n'
            '路径_声明 = "/接口/声明"\n'
        ),
    }
