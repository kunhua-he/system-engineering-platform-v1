# -*- coding: utf-8 -*-
"""注入样本 · 判据 56（核心只放唯一物）· 判据 58（边界表达力）· 判据 59（件名与目录名禁形）。

三条合一件（拆法照 `注入_后缀与名册.py` 的先例）：都是本腿（B6 / B9）新立判据的身份证。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path

from .判据基线 import 库相对路径


# ── 判据 56：核心只放唯一物 ───────────────────────────────
# 反向样本的靶：把夹具库 `规则` 表某条唯一物的**落点**改成不存在的路径 ⇒ 当场红。
落点不存在样本 = "契约声明/落点不存在样本"


def 注入_唯一物落点不存在(临根: Path) -> str:
    """把夹具库第一条唯一物的 `依据`（落点）改成不存在的路径 ⇒ 判据 56 当场红。"""
    库件 = 临根 / 库相对路径
    if not 库件.is_file():
        return 落点不存在样本
    连接 = sqlite3.connect(库件)
    try:
        连接.execute(
            "update 规则 set 依据 = ? where 类 = '唯一物' and 编号 = '唯一物-1'",
            (落点不存在样本,))
        连接.commit()
    finally:
        连接.close()
    return 落点不存在样本


# ── 判据 58：边界表达力（内核零任务表）──────────────────────
# 反向样本的靶：往夹具 `运行内核/` 的一件里写一张任务表 ⇒ 当场红。
内核样本件 = "运行内核/调用调度/src/调度核心.rs"


def 注入_内核持任务表(临根: Path) -> str:
    """往夹具 `运行内核/` 的一件追加一张任务表 ⇒ 判据 58 当场红。"""
    路径 = 临根 / 内核样本件
    路径.write_text(
        路径.read_text(encoding="utf-8") + "\nstatic mut 任务表: u32 = 0;\n",
        encoding="utf-8",
    )
    return 内核样本件


# ── 判据 59：件名与目录名禁形 ─────────────────────────────
# 反向样本的靶：放一件**单汉字基名**（`壳.py`）⇒ 当场红（基线为空 ⇒ 新增即红）。
禁形件名样本 = "构建装配/样例/壳.py"


def 注入_件名落禁形(临根: Path) -> str:
    """放一件单汉字基名的 `.py` ⇒ 判据 59 当场红。"""
    路径 = 临根 / 禁形件名样本
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text("# 反向样本：单汉字件名\n", encoding="utf-8")
    return 禁形件名样本
