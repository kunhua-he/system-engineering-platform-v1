# -*- coding: utf-8 -*-
"""判据 ㊺：命名定义现状禁形 —— 库 `命名定义` 的 `现状` 列列出的旧名/禁形，不许再作标识符用。

依据：库 `规则` 表 `命名口径-1`（出现即须登记）与 `命名口径-4`（「名册里有定义的名一律放行」）。
**为什么要这一条**：`命名定义` 表的 `现状` 列（6265 行里 523 行非「名即语义」）此前**无任何代码读**
（只有 `查看.py` 把它当展示栏）⇒ 列出来的旧名/禁形没有任何闸拦着，必回潮。
本条的触发点是一个仍以旧名作标识符的名字（唯一名已裁为 `起始时刻`）：本条立时它在标识符面
仍有 18 处，已按唯一名改齐 —— 此后它不再出现。

**判什么**：把 `现状` 列里列出的禁形收成一个集合；凡在**命名面**（`.rs/.py/.js/.ts/.vue`）里
当**标识符**用的禁形，就是一处违规 —— **存量入基线、新增即红 · 基线只许减**。

**拆行口径**（`拆禁形`，一处定义）：
  · `现状` = `（名即语义）` / `已合规，不动` / 空 ⇒ 这一行没有禁形；
  · `现状` 含 `→`（形如 `待改名 → 新名`）⇒ 禁形 = `唯一名` 栏里的名（去掉箭头右侧的新名）；
  · 其余 ⇒ 禁形 = `现状` 栏里列出的名（去反引号 · 去括号注解 · 按 `·`/`、`/`,`/`/` 拆）。

**豁免**（口径与 `命名口径-4` 一致）：禁形若已登记为某一行的 `唯一名`，或属库 `命名例外`
（语言/协议/工具强加），则**一律放行** —— 名册里有定义的名一律放行。

**面各只一份**：命名件表复用 `判据_命名穷举.命名件表`；剥器复用 `命名扫描`（与判据 ㉒/㊷ 同一份）；
名册与例外复用 `命名穷举.读名册`（与判据 ㊷/写盘闸同一份）—— 本件不另写一套。

三元读数：**通过** = 命名面非空且无新增/超基线/陈旧；**失败** = 逐条报出；
**未判** = 命名面 0 个件，或名册读不动（**空集是未判，不是通过**）。
"""
from __future__ import annotations

import json
import re
import sqlite3
from pathlib import Path

from .小工具 import 判不了, 违规
from .常量 import 检查名
from . import 命名扫描
from .判据_命名穷举 import _取信息核心件, 命名件表


# 基线文件：**存量清单**（旧名/禁形还在用的那些）。判据读不到它就 fail-closed 报红。
禁形基线路径 = "构建装配/一键验证/命名禁形基线.json"


def 拆名(文本: str) -> list:
    """`现状` / `唯一名` 两栏的自由文本 ⇒ 名字表（去反引号 · 去括号注解 · 按分隔符拆）。"""
    净文本 = re.sub(r"（[^）]*）", "", 文本 or "")
    return [名字片.strip().strip("`") for 名字片 in re.split(r"[·、/,]", 净文本)
            if 名字片.strip().strip("`")]


def 拆禁形(现状: str, 唯一名: str) -> list:
    """一行 `命名定义` ⇒ 它列出的**禁形**（旧名）表。口径见件头「拆行口径」。"""
    现状 = (现状 or "").strip()
    if 现状 in ("（名即语义）", "已合规，不动", ""):
        return []
    if "→" in 现状:
        新名 = 拆名(现状.split("→", 1)[1])
        return [名字片 for 名字片 in 拆名(唯一名) if 名字片 not in 新名]
    return 拆名(现状)


def 读禁形行(树根) -> tuple:
    """读被扫仓的规则库 ⇒ `(禁形集, 错误或 None)`（读不动不抛，交错误回去）。"""
    穷举 = _取信息核心件("命名穷举")
    库件 = Path(树根) / 穷举.库相对路径
    if not 库件.is_file():
        return set(), f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute("select 语义,唯一名,现状 from 命名定义"))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return set(), f"`命名定义` 读不动：{错误}"
    禁形集 = set()
    for _语义, 唯一名, 现状 in 行表:
        禁形集.update(拆禁形(现状, 唯一名))
    return 禁形集, None


def 扫使用面(上层读数: dict) -> dict:
    """命名面里的每个**标识符** ⇒ `{名: {"处数", "样例"}}`（样例 = 件，报位置用）。"""
    使用表 = {}
    for 路径, 文本 in 命名件表(上层读数).items():
        后缀 = "." + 路径.rsplit(".", 1)[-1]
        for 出现名 in 命名扫描.抽标识符(命名扫描.剥后缀(后缀, 文本)):
            记录 = 使用表.setdefault(出现名, {"处数": 0, "样例": 路径})
            记录["处数"] += 1
    return 使用表


def 样本_禁形面(上层读数: dict) -> int:
    """对象数：命名面下的件数（0 ⇒ 未判：面空与走树坏了必须分得开）。"""
    return len(命名件表(上层读数))


def _读基线(基线件) -> tuple:
    """读基线 ⇒ `({禁形名: 处数}, 错误或 None)`。"""
    if not 基线件.is_file():
        return {}, f"基线文件不存在（{禁形基线路径}）"
    try:
        数据 = json.loads(基线件.read_text(encoding="utf-8"))
    except Exception as 错误:
        return {}, f"基线文件解析不了（{type(错误).__name__}）"
    项表 = {}
    for 基线条目 in 数据.get("条目") or []:
        try:
            项表[str(基线条目["禁形"])] = int(基线条目.get("处数", 0))
        except (KeyError, TypeError, ValueError):
            return {}, f"基线条目形状不对（{基线条目!r}）—— 要 禁形/处数 两键"
    return 项表, None


def 检查45_命名定义禁形(上层读数: dict) -> list:
    """命名定义现状禁形：`现状` 列列出的旧名/禁形不许再作标识符用（存量入基线、新增即红）。"""
    输出缓冲 = []
    件表 = 命名件表(上层读数)
    if not 件表:
        判不了(
            检查名[44],
            "命名面（`.rs` / `.py` / `.js` / `.ts` / `.vue`）",
            "命名面下 0 个件（判据没有可查的对象）—— 也可能是走树 / 索引坏了：那样恒为 0 命中 ⇒ 假绿",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一个没有命名件的仓天然是绿的，"
            "那不是本条判据的功劳 ⇒ 只能由判据作者确认命名面与后缀表",
        )
        return 输出缓冲
    穷举 = _取信息核心件("命名穷举")
    try:
        唯一名, 例外 = 穷举.读名册(上层读数["仓根"])
    except 穷举.名册读不动 as 错误:
        判不了(
            检查名[44],
            穷举.库相对路径,
            f"判不了：{错误}",
            "名册与例外是本条的**豁免依据**（命名口径-4：名册里有定义的名一律放行）⇒ 读不出就判不了。"
            "修法：把规则库补上（`python3 开发工具/信息核心/信息核心.py 建库`）⇒ 只能由维护方补",
        )
        return 输出缓冲
    禁形集, 错误 = 读禁形行(上层读数["仓根"])
    if 错误:
        return [
            违规(
                检查名[44],
                穷举.库相对路径,
                错误,
                "`命名定义` 的 `现状` 列是本条的**唯一对象**（禁形就从它来）⇒ 读不出就判不了。"
                "修法：把规则库补上（`python3 开发工具/信息核心/信息核心.py 建库`）⇒ 只能由维护方补",
            )
        ]
    基线表, 错误 = _读基线(上层读数["仓根"] / 禁形基线路径)
    if 错误:
        return [
            违规(
                检查名[44],
                禁形基线路径,
                错误,
                "「存量入基线、新增即红」要求先有存量清单；没有它，实测的全部存量会被算成"
                "「新增」⇒ 判据当场红一片，等于没上闸 ⇒ 只能由维护方登记",
            )
        ]
    使用表 = 扫使用面(上层读数)
    # 豁免：已登记为 `唯一名` 或属 `命名例外` 的禁形一律放行（命名口径-4）。
    实测 = {
        出现名: 记录
        for 出现名, 记录 in 使用表.items()
        if 出现名 in 禁形集 and 出现名 not in 唯一名 and 出现名 not in 例外
    }
    口径 = (
        "库 `规则` 表 `命名口径-4`：名册里有定义的名一律放行。`命名定义` 的 `现状` 列列的是"
        "旧名/禁形，唯一名在同行 `唯一名` 栏（含 `→` 的行：箭头右侧才是新名）。"
        "修法：把该处的标识符改成同行 `唯一名` 栏里的名（或按实际角色另取新名并登记）⇒ "
        "只能由该件的作者改"
    )
    for 出现名, 记录 in sorted(实测.items()):
        实际 = 记录["处数"]
        位置 = f"{记录['样例']}::{出现名}"
        登记 = 基线表.get(出现名)
        if 登记 is None:
            输出缓冲.append(
                违规(
                    检查名[44],
                    位置,
                    f"`现状` 列列为禁形的 `{出现名}` 仍作标识符用（{实际} 处），基线里没有它 ⇒ **新增即红**",
                    口径,
                )
            )
        elif 实际 > 登记:
            输出缓冲.append(
                违规(
                    检查名[44],
                    位置,
                    f"禁形 `{出现名}` 实测 {实际} 处 > 基线登记 {登记} 处 ⇒ **存量还在长**",
                    "基线是「存量不许再长」的闸，不是白名单。这一处已在基线里登记过，却又多了 ⇒ "
                    "要么改回去，要么在提交信息里说明为什么必须涨并同步登记 ⇒ 只能由该件的作者处置",
                )
            )
    # 反向：基线里登记着、实测却已经不出现（或低于登记）⇒ 「基线只许减」。
    for 出现名, 登记 in sorted(基线表.items()):
        实际 = 实测.get(出现名, {}).get("处数", 0)
        if 实际 == 0:
            输出缓冲.append(
                违规(
                    检查名[44],
                    f"命名面::{出现名}",
                    f"基线登记着禁形 `{出现名}`（{登记} 处），而实测这个名**已经不出现** ⇒ **陈旧登记**",
                    "「基线只许减」：改完了就该把登记删掉 —— 留着它，基线读数就不再是现状"
                    f"（读的人会以为债还在）⇒ 只能由维护方删（{禁形基线路径}）",
                )
            )
        elif 实际 < 登记:
            输出缓冲.append(
                违规(
                    检查名[44],
                    f"命名面::{出现名}",
                    f"基线登记禁形 `{出现名}` {登记} 处，实测只有 {实际} 处 ⇒ **登记没跟着减**",
                    "「基线只许减」：实测比登记低就该同步减下来。不减的话，这一处可以一路长回"
                    f"登记值而不报红 —— 那是「只增不减」的一个洞 ⇒ 只能由维护方改（{禁形基线路径}）",
                )
            )
    return 输出缓冲
