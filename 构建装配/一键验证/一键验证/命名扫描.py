# -*- coding: utf-8 -*-
r"""命名扫描：分语言剥注释与字符串，再抽标识符（判据 ㉒ 的解析器）。

依据：`项目文档/决策记录/2026-09-27_命名规范.md` §一（读数**必须剥注释与字符串**，
不拿散文里的字母充数）· §四.2（判据形状）· §三（两档口径）。

**为什么分语言**：剥注释与字符串是**词法**的事，各语言不一样 —— 拿 Rust 那套去扫 `.py`
（`#` 注释）或拿 `.py` 那套去扫 `.js`（模板串），要么剥不掉、要么剥错，两种都造**假红**
（本项目判据最反对的东西）。所以：

  · `.rs` —— 用仓内既有的 `剥字面量.去字面量`（Rust 的 `//` · `/* */`（可嵌套）· `r#"…"#` ·
    `'\u{…}'` 字形都在内）。**另补两处 Rust 专属的排除**（实测撞到的假红，见下）。
  · `.py` —— 本模块自带：`#` 行注释 + 三引号串（单引号三连 / 双引号三连）+ 普通引号（带 `r/b/f/u` 前缀）。
  · `.js` / `.ts` —— 本模块自带：`//` · `/* */` · `"…"` · `'…'` · `` `…` ``（模板串）+ 正则字面量。
  · `.vue` —— 只扫 `<script>…</script>` 块（模板散文不进标识符面）；本仓当前 0 个 `.vue`。

**两处 Rust 专属排除**（都是实测出来的假红，不是拍脑袋）：
  1. `'\u{0C}'` 这种带 `\u{…}` 转义的字符字面量 —— `去字面量` 的字符形只认 `'\X'`（单转义字符），
     认不出它 ⇒ 里面的 `0C` 会被当标识符数出来（实测 `小写出.rs` · `协议写出.rs` 各一处 `C`）。
     故先把 `b?'\u{…}'` 抹掉再交给 `去字面量`。
  2. 生命周期 `'a` · `'static` —— `'` 后面那个名字是生命周期参数，不是标识符；
     `去字面量` 只配对 `'x'`（有收尾引号）⇒ `'a` 会漏下 `a`。故按位置（前面是 `'`）抹掉。

**一处跨语言排除**：紧跟 `.` 的标识符是**成员/属性访问**（`re.S` · `self.出` · `项.名字`），
不是作者起的名字（决策记录 §二 点名的是「变量 · 参数 · 字段 · 类型 · 函数 · 测试名」）。
不排除的话，新写一处 `re.S` 就会假红 —— 那正是本判据要防的「假红工厂」。

**残余（如实登记，见 `--缺口`）**：`.js` 模板串的 `${…}` 表达式整段被抹（里面的单字母会漏）；
`.js` 正则字面量按「前一个非空白字符」的启发式识别，可能有漏网；`.vue` 只扫脚本块。
"""
from __future__ import annotations

import re

from .剥字面量 import _扫正则止, _前是表达式头, 扫正则区段, 去字面量


# ★ **规则谓词不在这里**（`命名后缀` `序数代称字` `词内序数代称` `含序数代称作标识符` `无义单字`
# `是单西文字母` `是命名件`）—— 它们是**命名规范的口径**，只有一份，落在
# `开发工具/代码地图/查名.py`。本件只管**解析器**：按语言剥注释与字符串 · 抽标识符。
# 判据 ㉒ 两边都用：规则从 `查名` 取，面用本件的剥器（它要能在**合成仓**上跑，见 `判据_命名.py`）。

# 标识符：字母 / 下划线 / 汉字 起头，后跟字母数字下划线汉字。
_标识符 = re.compile(r"[A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*")
# Rust：`'\u{0C}'` / `b'\u{8}'` 这类带 `\u{…}` 的字符字面量（`去字面量` 认不出，先抹）。
_Rust转义字符 = re.compile(r"b?'\\u\{[0-9A-Fa-f]+\}'")
# Rust：生命周期（`'` 后那个名字）。按位置抹 —— `'a` 的 `a` 不是标识符。
_Rust生命周期 = re.compile(r"(?<=')[A-Za-z_][0-9A-Za-z_]*")

# Python：三引号 / 普通引号，可带 `r/b/f/u` 前缀（大小写皆可，最多三个）。
_Python三引号 = re.compile(r'[rRbBuUfF]{0,3}("""|\'\'\')')
_Python引号 = re.compile(r'[rRbBuUfF]{0,3}("|\')')

# `.vue`：只取 `<script …>…</script>` 块（模板散文里有中文，但它不是标识符面）。
_Vue脚本块 = re.compile(r"<script[^>]*>(.*?)</script>", re.S | re.I)

# ── 局部绑定（判据 ㉒ 第四档的面）—— 分**单名形**与**多名形**两类：
#   单名形：一个匹配 = 一个名字（`let 名` · `for 名 in` · `catch (名)`）。
#   多名形：一个匹配 = 一段**绑定列表**，要拆（元组 `let (a, b)` · 闭包参 `|a, b|` ·
#           `Ok(名)` 模式 · Python 元组解包 · `with … as 名` · `lambda 名` · JS 解构）。
# ★ 口径仍是**宁漏不假红**：只收「长得像绑定」的形状，凡要先猜的一律不收（残余见 `扫局部绑定`）。
_名式 = r"[A-Za-z_\u4e00-\u9fff][\w\u4e00-\u9fff]*"

_单名形 = {
    ".rs": (
        re.compile(rf"\blet\s+(?:mut\s+)?({_名式})\s*(?::|=)"),
        re.compile(rf"\bfor\s+({_名式})\s+in\b"),
    ),
    ".py": (
        # 语句首的**纯赋值**（`名 = …`）；`名 += …` / `名 <= …` 不算（`名, 别 = …` 归多名形）。
        re.compile(rf"^[ \t]*({_名式})\s*(?::[^=\n]+)?=(?!=)", re.M),
    ),
    ".js": (
        re.compile(rf"\b(?:let|const|var)\s+({_名式})\s*(?:=|;|,)"),
        re.compile(rf"\bcatch\s*\(\s*({_名式})\s*\)"),
    ),
}

_多名形 = {
    ".rs": (
        re.compile(rf"\blet\s+(?:mut\s+)?\((?P<段>[^()\n]*)\)\s*(?::[^=\n]+)?="),
        re.compile(rf"\bfor\s+\((?P<段>[^()\n]*)\)\s+in\b"),
        re.compile(rf"\b(?:let|if\s+let|while\s+let)\s+(?:Some|Ok|Err)\s*\(\s*(?:mut\s+)?(?P<段>{_名式})\s*\)"),
        re.compile(rf"(?:^|[{{,;])\s*(?:Some|Ok|Err)\s*\(\s*(?:mut\s+)?(?P<段>{_名式})\s*\)\s*(?:=>|\{{)"),
        re.compile(r"(?:^|[=(,{;:])\s*\|(?P<段>[^|\n]{0,80})\|"),
    ),
    ".py": (
        re.compile(rf"^[ \t]*\(?(?P<段>{_名式}(?:\s*,\s*\(?{_名式}\)?)+)\)?\s*(?::[^=\n]+)?=(?!=)", re.M),
        re.compile(rf"\bfor\s+(?P<段>[^:\n]+?)\s+in\b"),
        re.compile(rf"^[ \t]*(?:async\s+)?(?:with|except)\b[^\n]*?\bas\s+(?P<段>{_名式})", re.M),
        re.compile(r"\blambda\s+(?P<段>[^:\n]*):"),
    ),
    ".js": (
        re.compile(r"\b(?:let|const|var)\s*[\{\[]\s*(?P<段>[^\}\]]*)[\}\]]"),
        re.compile(rf"\bfor\s*\(\s*(?:let|const|var)?\s*(?P<段>{_名式})\s+(?:of|in)\b"),
    ),
}


def 拆绑定名(绑定段: str) -> list:
    """把一段绑定列表（`a, (b, c), _`）拆成名字表 —— 括号抹平 · `mut`/`&`/类型标注剥掉 · `_` 丢弃。"""
    绑定段 = re.sub(r"[()\[\]{}]", " ", 绑定段)
    名字表 = []
    for 一片 in 绑定段.split(","):
        一片 = re.sub(r"^(?:mut|ref|const|let)\s+", "", 一片.strip())
        一片 = re.sub(r"\s*:\s*[^,]+$", "", 一片).strip()
        一片 = 一片.strip("&* \t")
        if re.fullmatch(_名式, 一片 or ""):
            名字表.append(一片)
    return 名字表

# ★ `/` 是「正则起始」还是「除号」的启发式 —— **只有一份**，在 `剥字面量._前是表达式头`
# （本件与 `剥字面量._剥注释与串` 都引它）。早先本件自带一份 `_正则前缀` / `_正则前缀词`，
# 与剥器那份是**同一职责的第二套实现**（拿 `剥字面量._剥注释与串` 剥字面量、却拿本件这套判 `/`，
# 两边必然漂）—— 收口时收成一处。


def _抹成空格(文本: str, 输出缓冲: list, 区间起点: int, 区间终点: int) -> None:
    """把 `[起, 止)` 抹成等长空格，**换行原样保留**（位置口径与 `剥字面量` 一致）。"""
    for 位置 in range(区间起点, min(区间终点, len(文本))):
        if 文本[位置] != "\n":
            输出缓冲[位置] = " "


def 剥Python(文本: str) -> str:
    """Python：剥 `#` 行注释与字符串（含三引号、`r/b/f/u` 前缀）。长度不变。"""
    输出缓冲 = list(文本)
    长度 = len(文本)
    游标 = 0
    while 游标 < 长度:
        字符 = 文本[游标]
        if 字符 == "#":
            行末 = 文本.find("\n", 游标)
            区间终点 = 长度 if 行末 < 0 else 行末
            _抹成空格(文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        命中 = _Python三引号.match(文本, 游标)
        if 命中:
            引号 = 命中.group(1)
            区间终点 = 文本.find(引号, 命中.end())
            区间终点 = 长度 if 区间终点 < 0 else 区间终点 + len(引号)
            _抹成空格(文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        命中 = _Python引号.match(文本, 游标)
        if 命中:
            引号 = 命中.group(1)
            步序 = 命中.end()
            while 步序 < 长度:
                if 文本[步序] == "\\":
                    步序 += 2
                    continue
                if 文本[步序] == 引号:
                    步序 += 1
                    break
                if 文本[步序] == "\n":
                    break
                步序 += 1
            _抹成空格(文本, 输出缓冲, 游标, 步序)
            游标 = 步序
            continue
        游标 += 1
    return "".join(输出缓冲)


def 扫正则字面量(文本: str) -> list:
    """位置无关地找 `/…/` 正则字面量 ⇒ `[(起始位, 字面量原文)]`。

    **认法只有一份**：`剥字面量.扫正则区段`（与 `剥字面量._剥注释与串` 剥字面量时引的是**同一条**
    `/` 启发式）—— 本件只做转口，不许再写第二套。早先本件自带 `_前是表达式头` 一套，
    与剥器那份是同一职责的两套实现（剥字面量走剥器、判 `/` 走本件）⇒ 收口时收成一处。

    **诚实登记的残余**：语句位置紧跟 `)` 的裸 `/…/`（`if (条件) /x$/;`）**不认** ——
    它与 `(a) / b` 的除法同形，认它会假红（口径同 `决策记录/2026-09-27_判据口径十一条.md` §三：
    宁可收窄并写明，不留「认不出但报绿」）。
    """
    return [(区间起点, 文本[区间起点:区间终点]) for 区间起点, 区间终点 in 扫正则区段(文本)]


def 剥JS(文本: str) -> str:
    """JS / TS：剥 `//` · `/* */` · `"…"` · `'…'` · 模板串 · 正则字面量。长度不变。"""
    输出缓冲 = list(文本)
    长度 = len(文本)
    游标 = 0
    while 游标 < 长度:
        字符 = 文本[游标]
        if 字符 == "/" and 游标 + 1 < 长度 and 文本[游标 + 1] == "/":
            行末 = 文本.find("\n", 游标)
            区间终点 = 长度 if 行末 < 0 else 行末
            _抹成空格(文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        if 字符 == "/" and 游标 + 1 < 长度 and 文本[游标 + 1] == "*":
            闭符 = 文本.find("*/", 游标 + 2)
            区间终点 = 长度 if 闭符 < 0 else 闭符 + 2
            _抹成空格(文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        if 字符 in "\"'`":
            步序 = 游标 + 1
            while 步序 < 长度:
                if 文本[步序] == "\\":
                    步序 += 2
                    continue
                if 文本[步序] == 字符:
                    步序 += 1
                    break
                步序 += 1
            _抹成空格(文本, 输出缓冲, 游标, 步序)
            游标 = 步序
            continue
        if 字符 == "/" and _前是表达式头(文本, 游标):
            区间终点 = _扫正则止(文本, 游标)
            if 区间终点 < 0:
                游标 += 1
                continue
            _抹成空格(文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        游标 += 1
    return "".join(输出缓冲)


def 剥Vue(文本: str) -> str:
    """`.vue`：只扫 `<script>…</script>` 块（模板散文不进标识符面）。"""
    return "\n".join(剥JS(命中.group(1)) for 命中 in _Vue脚本块.finditer(文本))


def _抹属性(文本: str) -> str:
    """把 Rust 属性 `#[…]` / `#![…]` 的内部抹成等长空格（**换行保留**，长度不变）。

    ★ 为什么要有它（2026-09-27 实测撞到的**假红**，不是理论）：
      属性里写的是**语言记法**，不是标识符。`#[repr(C)]` 的 `C` 是 ABI 记法，
      却被 `抽标识符` 当成「西文单字母」⇒ 实测三件 7 处假红
      （`契约声明/src/契约声明/{基础,命令,平台}形状.rs`），并因此白占三格基线登记。
      假红会让判据被绕过（`判据口径十一条.md` §十三）。

    方括号按**深度**配对（`#[cfg(all(feature = "x", not(y)))]` 里有嵌套圆括号，方括号不嵌套）；
    调用点已先 `去字面量` ⇒ 引号里的 `[` `]` 已抹空，不会咬错。
    """
    输出缓冲 = list(文本)
    长度 = len(文本)
    游标 = 0
    while 游标 < 长度:
        if 文本[游标] == "#":
            尾部 = 游标 + 1
            if 尾部 < 长度 and 文本[尾部] == "!":
                尾部 += 1  # `#![…]` 内层属性
            if 尾部 < 长度 and 文本[尾部] == "[":
                深度 = 0
                闭合位 = 尾部
                while 闭合位 < 长度:
                    if 文本[闭合位] == "[":
                        深度 += 1
                    elif 文本[闭合位] == "]":
                        深度 -= 1
                        if 深度 == 0:
                            break
                    闭合位 += 1
                区间终点 = min(闭合位 + 1, 长度)
                for 位置 in range(游标, 区间终点):
                    if 文本[位置] != "\n":
                        输出缓冲[位置] = " "
                游标 = 区间终点
                continue
        游标 += 1
    return "".join(输出缓冲)


def 剥后缀(后缀: str, 文本: str) -> str:
    """按后缀剥注释与字符串，返回**等长**净文本（`__init__` 之类无后缀的不收）。"""
    if 后缀 == ".rs":
        净文本 = _Rust转义字符.sub(lambda 命中: " " * len(命中.group(0)), 文本)
        净文本 = 去字面量(净文本)
        净文本 = _Rust生命周期.sub(lambda 命中: " " * len(命中.group(0)), 净文本)
        return _抹属性(净文本)
    if 后缀 == ".py":
        return 剥Python(文本)
    if 后缀 == ".vue":
        return 剥Vue(文本)
    return 剥JS(文本)


def _是自身成员访问(净文本: str, 区间起点: int) -> bool:
    """`净文本[区间起点:]` 这个标识符是不是 `self.` 后面的那一段（Rust/Python 同形，`&self.名` 也算）。

    **为什么要单列这一条**：`抽标识符` 把紧跟 `.` 的名字一律当「别人家的成员」排除 ——
    对 `模式.S` 是对的（`S` 不是作者起的名字），但对 `self.d` **是错的**：那是**本类型的成员定义**，
    正是命名规范要管的东西。实测漏了 `开发工具/取证/*/形状.py` 的 `self.d` / `self.e`
    （单字母成员名，判据 ㉒ 看不见 ⇒ 假阴性）。
    """
    if 区间起点 < 5 or 净文本[区间起点 - 5:区间起点] != "self.":
        return False
    前一位 = 净文本[区间起点 - 6] if 区间起点 >= 6 else ""
    return not (前一位.isalnum() or 前一位 == "_")


def 抽标识符(净文本: str) -> list:
    """净文本里的标识符表（**排除紧跟 `.` 的成员访问名**，但 `self.名` 除外 —— 见
    `_是自身成员访问`）。顺序即出现顺序。"""
    输出缓冲 = []
    for 命中 in _标识符.finditer(净文本):
        区间起点 = 命中.start()
        if 区间起点 > 0 and 净文本[区间起点 - 1] == "." and not _是自身成员访问(净文本, 区间起点):
            continue
        输出缓冲.append(命中.group(0))
    return 输出缓冲


def 有局部绑定(后缀: str, 文本: str) -> bool:
    """这段文本里有没有局部绑定（**判空集用**：面下一个绑定都没有 ⇒ 未判，不是通过）。

    走**与 `扫局部绑定` 同一套形状**（`_单名形` + `_多名形`）—— 这样「扫描器坏了」与
    「真的没有单字局部名」分得开：形状表一坏，空集那一关当场报未判，而不是静默报 0（假绿）。
    """
    净文本 = 剥后缀(后缀, 文本)
    return any(形状.search(净文本) for 形状 in _单名形表(后缀) + _多名形表(后缀))


def _单名形表(后缀: str) -> tuple:
    """按后缀选**单名形**表：`.rs` / `.py` 各一套，其余（`.js`/`.ts`/`.vue` 脚本块）共用 JS 那套。"""
    if 后缀 == ".rs":
        return _单名形[".rs"]
    if 后缀 == ".py":
        return _单名形[".py"]
    return _单名形[".js"]


def _多名形表(后缀: str) -> tuple:
    """按后缀选**多名形**表（选法与 `_单名形表` 同）。"""
    if 后缀 == ".rs":
        return _多名形[".rs"]
    if 后缀 == ".py":
        return _多名形[".py"]
    return _多名形[".js"]


def 扫局部绑定(后缀: str, 文本: str) -> list:
    """剥掉注释与字符串后，抽出**函数体内的局部绑定名** ⇒ `[(行号, 名)]`（只收单字）。

    **为何单开一面**：索引的**定义面不收局部名**（#226 实测：codegraph 不索引 Rust 的
    `let` 局部），形参面只扫签名 ⇒ 在 `.rs` 里新写 `let i = 1;`，两处都看不见（静默回潮）。
    面与判据 ㉒ 的第四档**共用这一份**（不另写一套）。

    **收哪些**（分两类，形状表见 `_单名形` / `_多名形` 的表头）：
      · `.rs`：`let` / `let mut` · `for … in` · 元组 `let (a, b)` / `for (a, b) in` ·
        `if let Some(名)` / `let Some(名) … else` · `match` 臂 `Ok(名) =>` · 闭包参 `|a, b|`
      · `.py`：语句首纯赋值 · 元组解包 `a, b = …` · 任何 `for X in`（含推导式；X 可为元组）·
        `with` / `except … as 名` · `lambda a, b:`
      · `.js` / `.ts` / `.vue`（脚本块）：`let` / `const` / `var` · 解构 `{a, b}` / `[a, b]` ·
        `catch (名)` · `for (const 名 of …)`

    **残余（如实登记；都是「收了就要猜」的形状，故不收）**：`.js` 模板串 `${…}` 里的表达式 ·
    Rust 宏体内的绑定 · f-string 内嵌表达式里的推导式目标（整段随字符串被抹）·
    `match` 的**裸标识符臂**（`名 => …`，可能是常量模式，收了会假红）。
    漏掉它们只会让读数**偏小**（少报存量），不会造假红 —— 这是本面选的口径。
    """
    净文本 = 剥后缀(后缀, 文本)
    绑定表 = []
    for 形状 in _单名形表(后缀):
        for 匹配 in 形状.finditer(净文本):
            绑定名 = 匹配.group(1)
            if len(绑定名) == 1 and 绑定名 != "_":
                绑定表.append((净文本.count("\n", 0, 匹配.start(1)) + 1, 绑定名))
    for 形状 in _多名形表(后缀):
        for 匹配 in 形状.finditer(净文本):
            行号 = 净文本.count("\n", 0, 匹配.start()) + 1
            for 绑定名 in 拆绑定名(匹配.group("段")):
                if len(绑定名) == 1 and 绑定名 != "_":
                    绑定表.append((行号, 绑定名))
    return sorted(绑定表)
