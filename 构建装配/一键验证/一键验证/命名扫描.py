# -*- coding: utf-8 -*-
r"""命名扫描：分语言剥注释与字符串，再抽标识符（判据 ㉒ 的解析器）。

依据：`项目文档/决策记录/2026-09-27_命名规范.md` §一（读数**必须剥注释与字符串**，
不拿散文里的字母充数）· §四.2（判据形状）· §三（两档口径）。

**为什么分语言**：剥注释与字符串是**词法**的事，各语言不一样 —— 拿 Rust 那套去扫 `.py`
（`#` 注释）或拿 `.py` 那套去扫 `.js`（模板串），要么剥不掉、要么剥错，两种都造**假红**
（本项目判据最反对的东西）。所以：

  · `.rs` —— 用仓内既有的 `剥字面量.去字面量`（Rust 的 `//` · `/* */`（可嵌套）· `r#"…"#` ·
    `'\u{…}'` 字形都在内）。**另补两处 Rust 专属的排除**（实测撞到的假红，见下）。
  · `.py` —— 本模块自带：`#` 行注释 + 三引号串（单引号三连 / 双引号三连）+ 普通引号（带 `r/b/f/u` 前缀）。
  · `.js` / `.ts` —— 本模块自带：`//` · `/* */` · `"…"` · `'…'` · `` `…` ``（模板串）+ 正则字面量。
  · `.vue` —— 只扫 `<script>…</script>` 块（模板散文不进标识符面）；本仓当前 0 个 `.vue`。

**两处 Rust 专属排除**（都是实测出来的假红，不是拍脑袋）：
  1. `'\u{0C}'` 这种带 `\u{…}` 转义的字符字面量 —— `去字面量` 的字符形只认 `'\X'`（单转义字符），
     认不出它 ⇒ 里面的 `0C` 会被当标识符数出来（实测 `小写出.rs` · `协议写出.rs` 各一处 `C`）。
     故先把 `b?'\u{…}'` 抹掉再交给 `去字面量`。
  2. 生命周期 `'a` · `'static` —— `'` 后面那个名字是生命周期参数，不是标识符；
     `去字面量` 只配对 `'x'`（有收尾引号）⇒ `'a` 会漏下 `a`。故按位置（前面是 `'`）抹掉。

**一处跨语言排除**：紧跟 `.` 的标识符是**成员/属性访问**（`re.S` · `self.出` · `项.名字`），
不是作者起的名字（决策记录 §二 点名的是「变量 · 参数 · 字段 · 类型 · 函数 · 测试名」）。
不排除的话，新写一处 `re.S` 就会假红 —— 那正是本判据要防的「假红工厂」。

**残余（如实登记，见 `--缺口`）**：`.js` 模板串的 `${…}` 表达式整段被抹（里面的单字母会漏）；
`.js` 正则字面量按「前一个非空白字符」的启发式识别，可能有漏网；`.vue` 只扫脚本块。
"""
from __future__ import annotations

import re

from .剥字面量 import _扫正则止, _前是表达式头, 扫正则区段, 去字面量


# ★ **规则谓词不在这里**（`命名后缀` `序数代称字` `词内序数代称` `含序数代称作标识符` `无义单字`
# `是单西文字母` `是命名件`）—— 它们是**命名规范的口径**，只有一份，落在
# `开发工具/代码地图/查名.py`。本件只管**解析器**：按语言剥注释与字符串 · 抽标识符。
# 判据 ㉒ 两边都用：规则从 `查名` 取，面用本件的剥器（它要能在**合成仓**上跑，见 `判据_命名.py`）。

# 标识符：字母 / 下划线 / 汉字 起头，后跟字母数字下划线汉字。
_标识符 = re.compile(r"[A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*")
# Rust：`'\u{0C}'` / `b'\u{8}'` 这类带 `\u{…}` 的字符字面量（`去字面量` 认不出，先抹）。
_Rust转义字符 = re.compile(r"b?'\\u\{[0-9A-Fa-f]+\}'")
# Rust：生命周期（`'` 后那个名字）。按位置抹 —— `'a` 的 `a` 不是标识符。
_Rust生命周期 = re.compile(r"(?<=')[A-Za-z_][0-9A-Za-z_]*")

# Python：三引号 / 普通引号，可带 `r/b/f/u` 前缀（大小写皆可，最多三个）。
_Python三引号 = re.compile(r'[rRbBuUfF]{0,3}("""|\'\'\')')
_Python引号 = re.compile(r'[rRbBuUfF]{0,3}("|\')')

# `.vue`：只取 `<script …>…</script>` 块（模板散文里有中文，但它不是标识符面）。
_Vue脚本块 = re.compile(r"<script[^>]*>(.*?)</script>", re.S | re.I)

# ── 局部绑定的**形状表**单开一件（`局部绑定形状.py`）：本件是剥器（词法），那张表是形状。
#   混在一件会把本件顶过 400 行硬数（`开发规范.md` §六）；面函数与 `拆绑定名` 留在本件。
from .局部绑定形状 import _名式, _单名形, _多名形, _要深度零


def 拆绑定名(绑定段: str) -> list:
    """把一段绑定列表（`a, (b, c), _`）拆成名字表 —— 括号抹平 · `mut`/`&`/类型标注剥掉 · `_` 丢弃。"""
    绑定段 = re.sub(r"[()\[\]{}]", " ", 绑定段)
    名字表 = []
    for 绑定片段 in 绑定段.split(","):
        绑定片段 = re.sub(r"^(?:mut|ref|const|let)\s+", "", 绑定片段.strip())
        绑定片段 = re.sub(r"\s*:\s*[^,]+$", "", 绑定片段).strip()
        绑定片段 = 绑定片段.strip("&* \t")
        if re.fullmatch(_名式, 绑定片段 or ""):
            名字表.append(绑定片段)
    return 名字表


def _括号深度(净文本: str) -> list:
    """逐位置的**括号深度**（下标 i = 位置 i **之前**的深度）：`(` `[` `{` 加一，`)` `]` `}` 减一。

    **为何要它**（2026-09-29 修实测假阳）：`.py` 的「语句首纯赋值」形是 `^[ \\t]*(名)\\s*…=(?!=)`，
    而 Python 多行调用的**续行行首长得一模一样** ⇒ 实测把 `encoding` · `cwd` · `capture_output` ·
    `ensure_ascii` · `text` · `file` 6 个**关键字实参**当成了局部绑定（假阳）。
    判定只有一条：那一行行首**在括号里**（深度 > 0）⇒ 是实参，不是绑定。

    ★ 只对 `.py` 用：Python 的块靠缩进（`{` 是字典/集合，不是块）；Rust/JS 的块是 `{}` ⇒
      `fn f() { let x = 1; }` 的 `let` 在深度 1，套这条会整批漏掉。
    """
    深度表 = [0] * (len(净文本) + 1)
    深度 = 0
    for 字节位置, 单字符 in enumerate(净文本):
        深度表[字节位置] = 深度
        if 单字符 in "([{":
            深度 += 1
        elif 单字符 in ")]}":
            深度 = 深度 - 1 if 深度 else 0
    深度表[len(净文本)] = 深度
    return 深度表

# ★ `/` 是「正则起始」还是「除号」的启发式 —— **只有一份**，在 `剥字面量._前是表达式头`
# （本件与 `剥字面量._剥注释与串` 都引它）。早先本件自带一份 `_正则前缀` / `_正则前缀词`，
# 与剥器那份是**同一职责的第二套实现**（拿 `剥字面量._剥注释与串` 剥字面量、却拿本件这套判 `/`，
# 两边必然漂）—— 收口时收成一处。


def _抹成空格(源文本: str, 输出缓冲: list, 区间起点: int, 区间终点: int) -> None:
    """把 `[起, 止)` 抹成等长空格，**换行原样保留**（位置口径与 `剥字面量` 一致）。"""
    for 字节位置 in range(区间起点, min(区间终点, len(源文本))):
        if 源文本[字节位置] != "\n":
            输出缓冲[字节位置] = " "


def 剥Python(源文本: str) -> str:
    """Python：剥 `#` 行注释与字符串（含三引号、`r/b/f/u` 前缀）。长度不变。"""
    输出缓冲 = list(源文本)
    文本长度 = len(源文本)
    游标 = 0
    while 游标 < 文本长度:
        单字符 = 源文本[游标]
        if 单字符 == "#":
            行末 = 源文本.find("\n", 游标)
            区间终点 = 文本长度 if 行末 < 0 else 行末
            _抹成空格(源文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        命中 = _Python三引号.match(源文本, 游标)
        if 命中:
            引号符 = 命中.group(1)
            区间终点 = 源文本.find(引号符, 命中.end())
            区间终点 = 文本长度 if 区间终点 < 0 else 区间终点 + len(引号符)
            _抹成空格(源文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        命中 = _Python引号.match(源文本, 游标)
        if 命中:
            引号符 = 命中.group(1)
            步序 = 命中.end()
            while 步序 < 文本长度:
                if 源文本[步序] == "\\":
                    步序 += 2
                    continue
                if 源文本[步序] == 引号符:
                    步序 += 1
                    break
                if 源文本[步序] == "\n":
                    break
                步序 += 1
            _抹成空格(源文本, 输出缓冲, 游标, 步序)
            游标 = 步序
            continue
        游标 += 1
    return "".join(输出缓冲)


def 扫正则字面量(源文本: str) -> list:
    """位置无关地找 `/…/` 正则字面量 ⇒ `[(起始位, 字面量原文)]`。

    **认法只有一份**：`剥字面量.扫正则区段`（与 `剥字面量._剥注释与串` 剥字面量时引的是**同一条**
    `/` 启发式）—— 本件只做转口，不许再写第二套。早先本件自带 `_前是表达式头` 一套，
    与剥器那份是同一职责的两套实现（剥字面量走剥器、判 `/` 走本件）⇒ 收口时收成一处。

    **诚实登记的残余**：语句位置紧跟 `)` 的裸 `/…/`（`if (条件) /x$/;`）**不认** ——
    它与 `(a) / b` 的除法同形，认它会假红（口径同 `决策记录/2026-09-27_判据口径十一条.md` §三：
    宁可收窄并写明，不留「认不出但报绿」）。
    """
    return [(区间起点, 源文本[区间起点:区间终点]) for 区间起点, 区间终点 in 扫正则区段(源文本)]


def 剥JS(源文本: str) -> str:
    """JS / TS：剥 `//` · `/* */` · `"…"` · `'…'` · 模板串 · 正则字面量。长度不变。"""
    输出缓冲 = list(源文本)
    文本长度 = len(源文本)
    游标 = 0
    while 游标 < 文本长度:
        单字符 = 源文本[游标]
        if 单字符 == "/" and 游标 + 1 < 文本长度 and 源文本[游标 + 1] == "/":
            行末 = 源文本.find("\n", 游标)
            区间终点 = 文本长度 if 行末 < 0 else 行末
            _抹成空格(源文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        if 单字符 == "/" and 游标 + 1 < 文本长度 and 源文本[游标 + 1] == "*":
            闭符 = 源文本.find("*/", 游标 + 2)
            区间终点 = 文本长度 if 闭符 < 0 else 闭符 + 2
            _抹成空格(源文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        if 单字符 in "\"'`":
            步序 = 游标 + 1
            while 步序 < 文本长度:
                if 源文本[步序] == "\\":
                    步序 += 2
                    continue
                if 源文本[步序] == 单字符:
                    步序 += 1
                    break
                步序 += 1
            _抹成空格(源文本, 输出缓冲, 游标, 步序)
            游标 = 步序
            continue
        if 单字符 == "/" and _前是表达式头(源文本, 游标):
            区间终点 = _扫正则止(源文本, 游标)
            if 区间终点 < 0:
                游标 += 1
                continue
            _抹成空格(源文本, 输出缓冲, 游标, 区间终点)
            游标 = 区间终点
            continue
        游标 += 1
    return "".join(输出缓冲)


def 剥Vue(源文本: str) -> str:
    """`.vue`：只扫 `<script>…</script>` 块（模板散文不进标识符面）。"""
    return "\n".join(剥JS(命中.group(1)) for 命中 in _Vue脚本块.finditer(源文本))


def _抹属性(源文本: str) -> str:
    """把 Rust 属性 `#[…]` / `#![…]` 的内部抹成等长空格（**换行保留**，长度不变）。

    ★ 为什么要有它（2026-09-27 实测撞到的**假红**，不是理论）：
      属性里写的是**语言记法**，不是标识符。`#[repr(C)]` 的 `C` 是 ABI 记法，
      却被 `抽标识符` 当成「西文单字母」⇒ 实测三件 7 处假红
      （`契约声明/src/契约声明/{基础,命令,平台}形状.rs`），并因此白占三格基线登记。
      假红会让判据被绕过（`判据口径十一条.md` §十三）。

    方括号按**深度**找配对界符（`#[cfg(all(feature = "x", not(y)))]` 里有嵌套圆括号，方括号不嵌套）；
    调用点已先 `去字面量` ⇒ 引号里的 `[` `]` 已抹空，不会咬错。
    """
    输出缓冲 = list(源文本)
    文本长度 = len(源文本)
    游标 = 0
    while 游标 < 文本长度:
        if 源文本[游标] == "#":
            尾部 = 游标 + 1
            if 尾部 < 文本长度 and 源文本[尾部] == "!":
                尾部 += 1  # `#![…]` 内层属性
            if 尾部 < 文本长度 and 源文本[尾部] == "[":
                深度 = 0
                闭合位 = 尾部
                while 闭合位 < 文本长度:
                    if 源文本[闭合位] == "[":
                        深度 += 1
                    elif 源文本[闭合位] == "]":
                        深度 -= 1
                        if 深度 == 0:
                            break
                    闭合位 += 1
                区间终点 = min(闭合位 + 1, 文本长度)
                for 字节位置 in range(游标, 区间终点):
                    if 源文本[字节位置] != "\n":
                        输出缓冲[字节位置] = " "
                游标 = 区间终点
                continue
        游标 += 1
    return "".join(输出缓冲)


def 剥后缀(源码后缀: str, 源文本: str) -> str:
    """按后缀剥注释与字符串，返回**等长**净文本（`__init__` 之类无后缀的不收）。"""
    if 源码后缀 == ".rs":
        净文本 = _Rust转义字符.sub(lambda 命中: " " * len(命中.group(0)), 源文本)
        净文本 = 去字面量(净文本)
        净文本 = _Rust生命周期.sub(lambda 命中: " " * len(命中.group(0)), 净文本)
        return _抹属性(净文本)
    if 源码后缀 == ".py":
        return 剥Python(源文本)
    if 源码后缀 == ".vue":
        return 剥Vue(源文本)
    return 剥JS(源文本)


def _是自身成员访问(净文本: str, 区间起点: int) -> bool:
    """`净文本[区间起点:]` 这个标识符是不是 `self.` 后面的那一段（Rust/Python 同形，`&self.名` 也算）。

    **为什么要单列这一条**：`抽标识符` 把紧跟 `.` 的名字一律当「别人家的成员」排除 ——
    对 `模式.S` 是对的（`S` 不是作者起的名字），但对 `self.d` **是错的**：那是**本类型的成员定义**，
    正是命名规范要管的东西。实测漏了 `开发工具/取证/*/形状.py` 的 `self.d` / `self.e`
    （单字母成员名，判据 ㉒ 看不见 ⇒ 假阴性）。
    """
    if 区间起点 < 5 or 净文本[区间起点 - 5:区间起点] != "self.":
        return False
    前一位 = 净文本[区间起点 - 6] if 区间起点 >= 6 else ""
    return not (前一位.isalnum() or 前一位 == "_")


def 抽标识符带位置(净文本: str) -> list:
    """净文本里的标识符 ⇒ `[(名, 起始位)]`（排除口径与 `抽标识符` 同一份）。

    **为什么要它**：落点表要逐处 `路径:行` —— 光有名不够，得有位才数得出行号。
    `抽标识符` 走它（排除紧跟 `.` 的成员访问 · `self.名` 例外 —— 只此一处，不各写一套）。
    """
    输出缓冲 = []
    for 标识符 in _标识符.finditer(净文本):
        区间起点 = 标识符.start()
        # ★ 2026-10-06 修：`..名`（区间运算符）不是成员访问 —— 只有前一个字符是 `.` **且再前一个不是 `.`**
        #   才算（实测 `for _ in 0..数量` 的 `数量` 被误排除 ⇒ 改名漏了它，编译不过）。
        if (区间起点 > 0 and 净文本[区间起点 - 1] == "." and 净文本[区间起点 - 2] != "."
                and not _是自身成员访问(净文本, 区间起点)):
            continue
        输出缓冲.append((标识符.group(0), 区间起点))
    return 输出缓冲


def 抽标识符(净文本: str) -> list:
    """净文本里的标识符表（**排除紧跟 `.` 的成员访问名**，但 `self.名` 除外 —— 见
    `_是自身成员访问`）。顺序即出现顺序。"""
    return [标识符[0] for 标识符 in 抽标识符带位置(净文本)]


def _扫全部绑定(源码后缀: str, 源文本: str) -> list:
    """剥掉注释与字符串后，抽出**全部局部绑定名** ⇒ `[(行号, 名)]`（**不过单字筛**）。

    ★ **只此一份**：`扫局部绑定`（按 `只单字` 筛）与 `有局部绑定`（判空集）都调它 ——
      形状表与剥器不许各写一套。
    """
    净文本 = 剥后缀(源码后缀, 源文本)
    深度表 = _括号深度(净文本) if 源码后缀 == ".py" else None
    绑定表 = []
    for 形状 in _单名形表(源码后缀):
        for 匹配结果 in 形状.finditer(净文本):
            if 深度表 is not None and 形状 in _要深度零 and 深度表[匹配结果.start()]:
                continue
            绑定表.append((净文本.count("\n", 0, 匹配结果.start(1)) + 1, 匹配结果.group(1)))
    for 形状 in _多名形表(源码后缀):
        for 匹配结果 in 形状.finditer(净文本):
            if 深度表 is not None and 形状 in _要深度零 and 深度表[匹配结果.start()]:
                continue
            行号 = 净文本.count("\n", 0, 匹配结果.start()) + 1
            for 绑定名 in 拆绑定名(匹配结果.group("段")):
                绑定表.append((行号, 绑定名))
    return sorted(绑定表)


def 有局部绑定(源码后缀: str, 源文本: str) -> bool:
    """这段文本里有没有局部绑定（**判空集用**：面下一个绑定都没有 ⇒ 未判，不是通过）。

    走**与 `扫局部绑定` 同一份**（`_扫全部绑定`）—— 这样「扫描器坏了」与「真的没有局部名」
    分得开：形状表 / 剥器一坏，空集那一关当场报未判，而不是静默报 0（假绿）。
    """
    return bool(_扫全部绑定(源码后缀, 源文本))


def _单名形表(源码后缀: str) -> tuple:
    """按后缀选**单名形**表：`.rs` / `.py` 各一套，其余（`.js`/`.ts`/`.vue` 脚本块）共用 JS 那套。"""
    if 源码后缀 == ".rs":
        return _单名形[".rs"]
    if 源码后缀 == ".py":
        return _单名形[".py"]
    return _单名形[".js"]


def _多名形表(源码后缀: str) -> tuple:
    """按后缀选**多名形**表（选法与 `_单名形表` 同）。"""
    if 源码后缀 == ".rs":
        return _多名形[".rs"]
    if 源码后缀 == ".py":
        return _多名形[".py"]
    return _多名形[".js"]


def 扫局部绑定(源码后缀: str, 源文本: str, 只单字: bool = True) -> list:
    """剥掉注释与字符串后，抽出**函数体内的局部绑定名** ⇒ `[(行号, 名)]`。

    `只单字=True`（判据 ㉒ 第四档的口径）只收单字；`False`（命名穷举的全名口径）收全部。

    **为何单开一面**：索引的**定义面不收局部名**（#226 实测：codegraph 不索引 Rust 的
    `let` 局部），形参面只扫签名 ⇒ 在 `.rs` 里新写 `let i = 1;`，两处都看不见（静默回潮）。
    面与判据 ㉒ 的第四档**共用这一份**（不另写一套）。

    **收哪些**（分两类，形状表见 `_单名形` / `_多名形` 的表头）：
      · `.rs`：`let` / `let mut` · `for … in` · 元组 `let (a, b)` / `for (a, b) in` ·
        `if let Some(名)` / `let Some(名) … else` · `match` 臂 `Ok(名) =>` · 闭包参 `|a, b|`
      · `.py`：语句首纯赋值 · 元组解包 `a, b = …` · 任何 `for X in`（含推导式；X 可为元组）·
        `with` / `except … as 名` · `lambda a, b:`
      · `.js` / `.ts` / `.vue`（脚本块）：`let` / `const` / `var` · 解构 `{a, b}` / `[a, b]` ·
        `catch (名)` · `for (const 名 of …)`

    **残余（如实登记；都是「收了就要猜」的形状，故不收）**：`.js` 模板串 `${…}` 里的表达式 ·
    Rust 宏体内的绑定 · f-string 内嵌表达式里的推导式目标（整段随字符串被抹）·
    `match` 的**裸标识符臂**（`名 => …`，可能是常量模式，收了会假红）。
    漏掉它们只会让读数**偏小**（少报存量），不会造假红 —— 这是本面选的口径。
    """
    return [(行号, 绑定名) for 行号, 绑定名 in _扫全部绑定(源码后缀, 源文本)
            if 绑定名 != "_" and (not 只单字 or len(绑定名) == 1)]
