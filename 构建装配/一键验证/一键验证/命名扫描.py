# -*- coding: utf-8 -*-
r"""命名扫描：分语言剥注释与字符串，再抽标识符（判据 ㉒ 的解析器）。

依据：`项目文档/决策记录/2026-09-27_命名规范.md` §一（读数**必须剥注释与字符串**，
不拿散文里的字母充数）· §四.2（判据形状）· §三（两档口径）。

**为什么分语言**：剥注释与字符串是**词法**的事，各语言不一样 —— 拿 Rust 那套去扫 `.py`
（`#` 注释）或拿 `.py` 那套去扫 `.js`（模板串），要么剥不掉、要么剥错，两种都造**假红**
（本项目判据最反对的东西）。所以：

  · `.rs` —— 用仓内既有的 `剥字面量.去字面量`（Rust 的 `//` · `/* */`（可嵌套）· `r#"…"#` ·
    `'\u{…}'` 字形都在内）。**另补两处 Rust 专属的排除**（实测撞到的假红，见下）。
  · `.py` —— 本模块自带：`#` 行注释 + 三引号串（单引号三连 / 双引号三连）+ 普通引号（带 `r/b/f/u` 前缀）。
  · `.js` / `.ts` —— 本模块自带：`//` · `/* */` · `"…"` · `'…'` · `` `…` ``（模板串）+ 正则字面量。
  · `.vue` —— 只扫 `<script>…</script>` 块（模板散文不进标识符面）；本仓当前 0 个 `.vue`。

**两处 Rust 专属排除**（都是实测出来的假红，不是拍脑袋）：
  1. `'\u{0C}'` 这种带 `\u{…}` 转义的字符字面量 —— `去字面量` 的字符形只认 `'\X'`（单转义字符），
     认不出它 ⇒ 里面的 `0C` 会被当标识符数出来（实测 `小写出.rs` · `协议写出.rs` 各一处 `C`）。
     故先把 `b?'\u{…}'` 抹掉再交给 `去字面量`。
  2. 生命周期 `'a` · `'static` —— `'` 后面那个名字是生命周期参数，不是标识符；
     `去字面量` 只配对 `'x'`（有收尾引号）⇒ `'a` 会漏下 `a`。故按位置（前面是 `'`）抹掉。

**一处跨语言排除**：紧跟 `.` 的标识符是**成员/属性访问**（`re.S` · `self.出` · `项.名字`），
不是作者起的名字（决策记录 §二 点名的是「变量 · 参数 · 字段 · 类型 · 函数 · 测试名」）。
不排除的话，新写一处 `re.S` 就会假红 —— 那正是本判据要防的「假红工厂」。

**残余（如实登记，见 `--缺口`）**：`.js` 模板串的 `${…}` 表达式整段被抹（里面的单字母会漏）；
`.js` 正则字面量按「前一个非空白字符」的启发式识别，可能有漏网；`.vue` 只扫脚本块。
"""
from __future__ import annotations

import re

from .剥字面量 import 去字面量


# 有标识符的语言后缀 —— 判据 ㉒ 的扫描面。`.css` / `.html` / `.sh` **没有标识符这回事**
# （决策记录 §一 的读数面就是「有标识符的语言」），扫它们就是假红 ⇒ 不收。
命名后缀 = (".rs", ".py", ".js", ".ts", ".vue")

# 天干十字：甲乙丙丁戊己庚辛壬癸（决策记录 §二「天干一律停用（作标识符）」）。
天干字 = "甲乙丙丁戊己庚辛壬癸"

# ★ **词内天干不算**（裁决 2026-09-27，`决策记录/2026-09-27_判据口径十一条.md` §十三）：
# 判的是「拿天干**当序数代称**」，不是「标识符里出现过某个天干字」——`自己` 里的 `己`
# 是词的一部分（有词典义），不是代称。**白名单是封闭的、且必须由实测得出**：
# 实测全仓含天干字的 63 个标识符里，只有 `自己` 这一类是词内字（10 处，全含 `自己`）；
# 其余 53 个都是代称（`甲` `数组甲` `乙父` `涨甲` …）。
# 要往这里加一条，先证明那个词**有词典义**且天干字在词内不表序 —— 别拿它当消音器。
词内天干 = ("自己",)


def 含天干作标识符(名: str) -> bool:
    """标识符里有没有「**当序数代称**的天干字」（词内的不算，见 `词内天干`）。"""
    余 = 名
    for 词 in 词内天干:
        余 = 余.replace(词, "")
    return any(字 in 天干字 for 字 in 余)

# 「无义中文单字」那一档（决策记录 §三 的 `出` `加` `取` `查` `判`）——
# **本判据不判它**（白名单/黑名单是开放的，判它必假红）；只用于「如实报读数」。
无义单字 = "出加做取查判"

# 标识符：字母 / 下划线 / 汉字 起头，后跟字母数字下划线汉字。
_标识符 = re.compile(r"[A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*")
# Rust：`'\u{0C}'` / `b'\u{8}'` 这类带 `\u{…}` 的字符字面量（`去字面量` 认不出，先抹）。
_Rust转义字符 = re.compile(r"b?'\\u\{[0-9A-Fa-f]+\}'")
# Rust：生命周期（`'` 后那个名字）。按位置抹 —— `'a` 的 `a` 不是标识符。
_Rust生命周期 = re.compile(r"(?<=')[A-Za-z_][0-9A-Za-z_]*")

# Python：三引号 / 普通引号，可带 `r/b/f/u` 前缀（大小写皆可，最多三个）。
_Py三引号 = re.compile(r'[rRbBuUfF]{0,3}("""|\'\'\')')
_Py引号 = re.compile(r'[rRbBuUfF]{0,3}("|\')')

# `.vue`：只取 `<script …>…</script>` 块（模板散文里有中文，但它不是标识符面）。
_Vue脚本块 = re.compile(r"<script[^>]*>(.*?)</script>", re.S | re.I)

# `.js` 正则字面量的**前一个非空白字符**：只有这几种不可能结束一个表达式 ⇒ 后面那个 `/` 是正则。
# 启发式取自 `常量.前端逻辑模式` 的同一思路（`=` / `return` / `(` 之后紧接 `/`）。
_正则前缀 = set("=(,:[!&|?{};")
_正则前缀词 = ("return", "typeof", "case", "in", "of", "do", "else", "yield", "await")


def _抹(文本: str, 出: list, 起: int, 止: int) -> None:
    """把 `[起, 止)` 抹成等长空格，**换行原样保留**（位置口径与 `剥字面量` 一致）。"""
    for 位 in range(起, min(止, len(文本))):
        if 文本[位] != "\n":
            出[位] = " "


def 剥Python(文本: str) -> str:
    """Python：剥 `#` 行注释与字符串（含三引号、`r/b/f/u` 前缀）。长度不变。"""
    出 = list(文本)
    长 = len(文本)
    指 = 0
    while 指 < 长:
        字 = 文本[指]
        if 字 == "#":
            行末 = 文本.find("\n", 指)
            止 = 长 if 行末 < 0 else 行末
            _抹(文本, 出, 指, 止)
            指 = 止
            continue
        配 = _Py三引号.match(文本, 指)
        if 配:
            引 = 配.group(1)
            终 = 文本.find(引, 配.end())
            终 = 长 if 终 < 0 else 终 + len(引)
            _抹(文本, 出, 指, 终)
            指 = 终
            continue
        配 = _Py引号.match(文本, 指)
        if 配:
            引 = 配.group(1)
            步 = 配.end()
            while 步 < 长:
                if 文本[步] == "\\":
                    步 += 2
                    continue
                if 文本[步] == 引:
                    步 += 1
                    break
                if 文本[步] == "\n":
                    break
                步 += 1
            _抹(文本, 出, 指, 步)
            指 = 步
            continue
        指 += 1
    return "".join(出)


def _前是表达式头(文本: str, 指: int) -> bool:
    """`文本[指]` 是 `/`：往前看第一个非空白 —— 它不可能结束一个表达式 ⇒ 这里是正则字面量。"""
    位 = 指 - 1
    while 位 >= 0 and 文本[位] in " \t":
        位 -= 1
    if 位 < 0:
        return True
    if 文本[位] in _正则前缀:
        return True
    if 文本[位].isalnum() or 文本[位] in "_$":
        词起 = 位
        while 词起 >= 0 and (文本[词起].isalnum() or 文本[词起] in "_$"):
            词起 -= 1
        return 文本[词起 + 1 : 位 + 1] in _正则前缀词
    return False


def 剥JS(文本: str) -> str:
    """JS / TS：剥 `//` · `/* */` · `"…"` · `'…'` · 模板串 · 正则字面量。长度不变。"""
    出 = list(文本)
    长 = len(文本)
    指 = 0
    while 指 < 长:
        字 = 文本[指]
        if 字 == "/" and 指 + 1 < 长 and 文本[指 + 1] == "/":
            行末 = 文本.find("\n", 指)
            止 = 长 if 行末 < 0 else 行末
            _抹(文本, 出, 指, 止)
            指 = 止
            continue
        if 字 == "/" and 指 + 1 < 长 and 文本[指 + 1] == "*":
            闭 = 文本.find("*/", 指 + 2)
            止 = 长 if 闭 < 0 else 闭 + 2
            _抹(文本, 出, 指, 止)
            指 = 止
            continue
        if 字 in "\"'`":
            步 = 指 + 1
            while 步 < 长:
                if 文本[步] == "\\":
                    步 += 2
                    continue
                if 文本[步] == 字:
                    步 += 1
                    break
                步 += 1
            _抹(文本, 出, 指, 步)
            指 = 步
            continue
        if 字 == "/" and _前是表达式头(文本, 指):
            步 = 指 + 1
            类内 = False
            while 步 < 长:
                if 文本[步] == "\\":
                    步 += 2
                    continue
                if 文本[步] == "[":
                    类内 = True
                elif 文本[步] == "]":
                    类内 = False
                elif 文本[步] == "/" and not 类内:
                    步 += 1
                    break
                elif 文本[步] == "\n":
                    break
                步 += 1
            _抹(文本, 出, 指, 步)
            指 = 步
            continue
        指 += 1
    return "".join(出)


def 剥Vue(文本: str) -> str:
    """`.vue`：只扫 `<script>…</script>` 块（模板散文不进标识符面）。"""
    return "\n".join(剥JS(命.group(1)) for 命 in _Vue脚本块.finditer(文本))


def _抹属性(文本: str) -> str:
    """把 Rust 属性 `#[…]` / `#![…]` 的内部抹成等长空格（**换行保留**，长度不变）。

    ★ 为什么要有它（2026-09-27 实测撞到的**假红**，不是理论）：
      属性里写的是**语言记法**，不是标识符。`#[repr(C)]` 的 `C` 是 ABI 记法，
      却被 `抽标识符` 当成「拉丁单字母」⇒ 实测三件 7 处假红
      （`契约声明/src/契约声明/{基础,命令,平台}形状.rs`），并因此白占三格基线登记。
      假红比不报更坏：它让判据被绕过（`判据的可信性.md` §十三）。

    方括号按**深度**配对（`#[cfg(all(feature = "x", not(y)))]` 里有嵌套圆括号，方括号不嵌套）；
    调用点已先 `去字面量` ⇒ 引号里的 `[` `]` 已抹空，不会咬错。
    """
    出 = list(文本)
    长 = len(文本)
    指 = 0
    while 指 < 长:
        if 文本[指] == "#":
            尾 = 指 + 1
            if 尾 < 长 and 文本[尾] == "!":
                尾 += 1  # `#![…]` 内层属性
            if 尾 < 长 and 文本[尾] == "[":
                深 = 0
                合 = 尾
                while 合 < 长:
                    if 文本[合] == "[":
                        深 += 1
                    elif 文本[合] == "]":
                        深 -= 1
                        if 深 == 0:
                            break
                    合 += 1
                止 = min(合 + 1, 长)
                for 位 in range(指, 止):
                    if 文本[位] != "\n":
                        出[位] = " "
                指 = 止
                continue
        指 += 1
    return "".join(出)


def 剥(后缀: str, 文本: str) -> str:
    """按后缀剥注释与字符串，返回**等长**净文本（`__init__` 之类无后缀的不收）。"""
    if 后缀 == ".rs":
        净 = _Rust转义字符.sub(lambda 命: " " * len(命.group(0)), 文本)
        净 = 去字面量(净)
        净 = _Rust生命周期.sub(lambda 命: " " * len(命.group(0)), 净)
        return _抹属性(净)
    if 后缀 == ".py":
        return 剥Python(文本)
    if 后缀 == ".vue":
        return 剥Vue(文本)
    return 剥JS(文本)


def _是自身成员访问(净: str, 起: int) -> bool:
    """`净[起:]` 这个标识符是不是 `self.` 后面的那一段（Rust/Python 同形，`&self.名` 也算）。

    **为什么要单列这一条**：`抽标识符` 把紧跟 `.` 的名字一律当「别人家的成员」排除 ——
    对 `模式.S` 是对的（`S` 不是作者起的名字），但对 `self.d` **是错的**：那是**本类型的成员定义**，
    正是命名规范要管的东西。实测漏了 `开发工具/取证/*/形状.py` 的 `self.d` / `self.e`
    （单字母成员名，判据 ㉒ 看不见 ⇒ 假阴性）。
    """
    if 起 < 5 or 净[起 - 5:起] != "self.":
        return False
    前一位 = 净[起 - 6] if 起 >= 6 else ""
    return not (前一位.isalnum() or 前一位 == "_")


def 抽标识符(净: str) -> list:
    """净文本里的标识符表（**排除紧跟 `.` 的成员访问名**，但 `self.名` 除外 —— 见
    `_是自身成员访问`）。顺序即出现顺序。"""
    出 = []
    for 命 in _标识符.finditer(净):
        起 = 命.start()
        if 起 > 0 and 净[起 - 1] == "." and not _是自身成员访问(净, 起):
            continue
        出.append(命.group(0))
    return 出


def 是单西文字母(名: str) -> bool:
    """单个**西文（拉丁）字母**的标识符（`f` `i` `n` … 大小写皆算；`_` 不算 —— 它不是字母）。"""
    return len(名) == 1 and 名.isascii() and 名.isalpha()


def 是命名件(键: str) -> bool:
    """判据 ㉒ 的扫描件：后缀在 `命名后缀` 里（`.css`/`.html`/`.sh` 不收）。"""
    return 键.endswith(命名后缀)
