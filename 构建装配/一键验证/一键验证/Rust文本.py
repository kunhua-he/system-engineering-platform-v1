# -*- coding: utf-8 -*-
"""Rust 文本的调用点识别（载入调用点 · 漏传上下文调用）。"""

from __future__ import annotations

import re


# 内核入口 `载入` 的**调用点**（判据 3 的读数）。
# 为什么要收窄到调用形（2026-09-25，依据：项目文档/设计文档/全局连接器与网关.md 第四节判据 3）：
#   原模式 `(?<![\w])载入\s*\(` 把**枚举解构**也算成调用点——实测 `装载失败::载入(内) => {`
#   （match 臂的**模式位**）被数成一处调用，两条腿各自用「不解构 + 改名」与
#   `装载失败::载入 { 0: 内 }` 绕开 ⇒ 绕的是**假阳性**，不是判据。
# 收窄口径（模式位 vs 表达式位）：
#   · 定义形 `fn 载入(` 不算；枚举变体**声明**（裸行 `载入(载入错误),`）不算；
#   · **模式位**不算：`载入(…)` 后面紧跟 `=>` / `|`，或它落在 `let` / `if let` / `while let`
#     的 `=` **左侧**（解构）——这三条就是「不在表达式位置」的可判信号；
#   · 其余（表达式位）才算调用点。
# 注：真调用点 `v1_loader::载入(声明, &台账)` **带路径前缀** ⇒ 不能用「前面有 `::` 就不算」
#   这条粗判（那会把真调用点一起毙掉）；「前面是不是类型路径」在词法上不可判（`v1_loader`
#   是模块、`装载失败` 是类型，都是路径），能判的是**位置**——枚举解构必在模式位。
_枚举变体声明形 = re.compile(r"^载入\s*\([^;]*\)\s*,?\s*$")


def _配平括号(文本: str, 开符: int) -> int:
    """`文本[开符]` 是 `(` ⇒ 返回与它配对的 `)` 的下标（配不平就返回 len）。"""
    深 = 0
    for 游标 in range(开符, len(文本)):
        if 文本[游标] == "(":
            深 += 1
        elif 文本[游标] == ")":
            深 -= 1
            if 深 == 0:
                return 游标
    return len(文本)


def 漏传上下文调用(源文本: str, 函数名: str = "并行生产区") -> list:
    """源文本里调用 `函数名` 却**没传** `测试文件集` 的 1 基行号表。

    为什么要有它：`并行生产区` 的 `测试文件集` 默认是空集 ⇒ 漏传时**整份夹具会被当生产代码**
    （实测：`检查13_常量表` 曾漏传 ⇒ 夹具里的同名常量被读成「在别处再定义」= 假红）。
    这是元判据「判据调上下文助手必须传全套上下文」的扫描器；**定义形不算**（只数调用）。
    按**位置**判（配平括号取出实参文本，看里面有没有 `测试文件集`），不按词命中。
    """
    出 = []
    模式 = re.compile(re.escape(函数名) + r"\s*\(")
    for 命 in 模式.finditer(源文本):
        if 源文本[: 命.start()].rstrip().endswith("def"):
            continue  # 定义形
        闭 = _配平括号(源文本, 源文本.find("(", 命.start()))
        参数 = 源文本[命.end() : 闭]
        if "测试文件集" not in 参数:
            出.append(源文本[: 命.start()].count("\n") + 1)
    return 出


def 载入调用点(文本: str) -> list:
    """返回 `载入` **调用点**的 1 基行号表（收窄口径见上方注释）。"""
    出 = []
    for 命 in re.finditer(r"(?<![\w])载入\s*\(", 文本):
        行起 = 文本.rfind("\n", 0, 命.start()) + 1
        行 = 文本[行起 : 文本.find("\n", 命.start())]
        if re.search(r"\bfn\s+载入\s*\(", 行):
            continue  # 定义形
        if _枚举变体声明形.match(行.strip()):
            continue  # 枚举变体声明（裸行）
        闭 = _配平括号(文本, 文本.find("(", 命.start()))
        尾紧 = 文本[闭 + 1 :].lstrip()
        if 尾紧.startswith("=>") or 尾紧.startswith("|"):
            continue  # 模式位：match 臂 / or-模式
        # `let` / `if let` / `while let` 的**模式**位：路径前有 `let` 且没有 `=`
        路径起 = 命.start()
        while 路径起 > 0 and (文本[路径起 - 1].isalnum() or 文本[路径起 - 1] in "_:"):
            路径起 -= 1
        界 = max(
            文本.rfind(";", 0, 路径起),
            文本.rfind("{", 0, 路径起),
            文本.rfind("}", 0, 路径起),
            文本.rfind("\n", 0, 路径起),
        )
        前置 = 文本[界 + 1 : 路径起]
        if re.search(r"\blet\b", 前置) and "=" not in 前置:
            continue  # let 的模式位
        出.append(文本[: 命.start()].count("\n") + 1)
    return 出
