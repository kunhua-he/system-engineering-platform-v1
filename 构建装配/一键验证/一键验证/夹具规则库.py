def 取命名后缀() -> tuple:
    """惰性取**命名后缀表**（`开发工具/代码地图/查名.py`）—— 口径只此一份。"""
    工具根 = Path(__file__).resolve().parents[3]
    根目录 = str(工具根 / "开发工具")
    if 根目录 not in sys.path:
        sys.path.insert(0, 根目录)
    import 代码地图.查名 as 查名

    return tuple(查名.命名后缀)


def 名册表(件表: dict) -> list:
    """夹具仓的干净代码里的**全部标识符** ⇒ 名册名表（排序去重）。

    用「全部标识符」而不是「三面绑定」：夹具的定义面靠**合成索引**（判据要读面那一刻才造，
    造仓时还没有）⇒ 只取绑定会漏掉模块级名，那会让正向样本当场红。
    """
    命名扫描 = 取命名扫描()
    后缀表 = 取命名后缀()
    名集 = set()
    for 路径, 文本 in 件表.items():
        if not 路径.endswith(后缀表):
            continue
        后缀 = "." + 路径.rsplit(".", 1)[-1]
        名集.update(命名扫描.抽标识符(命名扫描.剥后缀(后缀, 文本)))
    return sorted(名集)


def 同义种子(名表: list) -> list:
    """夹具仓的**同义已裁种子**：名册里全部正前缀对（前名 ⊂ 后名 为正前缀、余 ≤3 字、非编号）。

    超集于判据 52 的候选（它还叠 同区 / 互斥 / 同种类）⇒ 干净夹具上判据 52 必过（正向样本）。
    为何要它：判据 52 的口径是「未裁候选即红」，而干净夹具本无「已裁」概念 ⇒ 不种子就会当场红。
    """
    import re

    名序 = sorted(名表)
    对表 = []
    for 前名 in 名序:
        if len(前名) < 2:
            continue
        for 后名 in 名序:
            if 后名 == 前名 or not 后名.startswith(前名):
                continue
            余段 = 后名[len(前名):]
            if re.match(r"_?\d", 余段) or len(余段) > 3:
                continue
            对表.append((前名, 后名))
    return 对表


def 建夹具规则库(临根: Path, 件表: dict) -> Path:
    """在夹具仓里造一份最小规则库（名册 = 夹具干净代码的标识符；基线留空）⇒ 库路径。"""
    库件 = 临根 / 取表定义().库相对路径
    库件.parent.mkdir(parents=True, exist_ok=True)
    连接 = sqlite3.connect(库件)
    try:
        for 语句 in 取表定义().建表语句:
            连接.execute(语句)
        名册名表 = 名册表(件表)
        for 出现名 in 名册名表:
            连接.execute("insert or replace into 命名定义 values(?,?,?)",
                       (出现名, 出现名, "（名即语义）"))
        # 判据 52 的已裁种子：干净夹具的名册正前缀对（超集于候选）⇒ 正向样本必过。
        for 前名, 后名 in 同义种子(名册名表):
            连接.execute("insert or replace into 命名同义已裁 values(?,?,?)",
                       (前名, 后名, "误报"))
        # 判据 ㊼ 的**真源**是库 `条款` 表（`测试验证/案例/形状.md` §一）⇒ 夹具也得有一行，
        # 否则判据读不到 ⇒ 正向样本当场未判（元判据 ⑭ 不过）。正文只需含那三条布局值。
        from .判据_接口面常量 import 案例形状文档

        连接.execute("insert or replace into 条款 values(?,?,?,?,?)",
                   (案例形状文档, 1, "一 案例目录形状", 案例形状样本, "落点与规范"))
    finally:
        连接.commit()
        连接.close()
    return 库件
