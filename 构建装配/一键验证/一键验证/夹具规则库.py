def 名册表(件表: dict) -> list:
    """夹具仓的干净代码里的**全部标识符** ⇒ 名册名表（排序去重）。

    用「全部标识符」而不是「三面绑定」：夹具的定义面靠**合成索引**（判据要读面那一刻才造，
    造仓时还没有）⇒ 只取绑定会漏掉模块级名，那会让正向样本当场红。
    """
    命名扫描 = 取命名扫描()
    后缀表 = 取命名后缀()
    名集 = set()
    for 路径, 源文本 in 件表.items():
        if not 路径.endswith(后缀表):
            continue
        源码后缀 = "." + 路径.rsplit(".", 1)[-1]
        名集.update(命名扫描.抽标识符(命名扫描.剥后缀(源码后缀, 源文本)))
    return sorted(名集)


def 取落库写口():
    """惰性取**名册写口主人**（`开发工具/信息核心/落库.py`）。

    ★ 为何要它（2026-10-07 · 加固项 A3）：判据 55（名册新鲜度）比的是**写口会写进去的名集**
    对库 `命名出现` 的名集 —— 夹具仓要是不填 `命名出现`，正向样本就当场红（假红）。
    而填它的口径**必须与写口同一份**（`落库.写库名集`）—— 夹具**另行**推一套等于把正向样本
    的东西换成另一个东西。取法照 `取表定义` 的先例（惰性取 + 上门口那条路）。
    """
    工具根 = Path(__file__).resolve().parents[3]
    for 加目录 in (str(工具根 / "开发工具" / "信息核心"), str(工具根 / "开发工具"),
                 str(工具根 / "构建装配" / "一键验证")):
        if 加目录 not in sys.path:
            sys.path.insert(0, 加目录)
    import 落库

    return 落库


def 建夹具规则库(临根: Path, 件表: dict) -> Path:
    """在夹具仓里造一份最小规则库（名册 = 夹具干净代码的标识符；基线留空）⇒ 库路径。"""
    库件 = 临根 / 取表定义().库相对路径
    库件.parent.mkdir(parents=True, exist_ok=True)
    连接 = sqlite3.connect(库件)
    try:
        for 语句 in 取表定义().建表语句:
            连接.execute(语句)
        名册名表 = 名册表(件表)
        for 出现名 in 名册名表:
            连接.execute(
                "insert or replace into 命名登记(名字, 语义, 模式, 来源, 状态) values(?,?,?,?,?)",
                (出现名, 出现名, "对象+说明", "新定义", "合格"))
        # 判据 ㊼ 的**真源**是库 `条款` 表（`测试验证/案例/形状.md` §一）⇒ 夹具也得有一行，
        # 否则判据读不到 ⇒ 正向样本当场未判（元判据 ⑭ 不过）。正文只需含那三条布局值。
        from .判据_接口面常量 import 案例形状文档

        连接.execute("insert or replace into 条款 values(?,?,?,?,?)",
                   (案例形状文档, 1, "一 案例目录形状", 案例形状样本, "落点与规范"))
        # ★ 判据 56 的**真源**：唯一物清单（库 `规则` 表 `类`=`唯一物`）—— 夹具也得有 13 行，
        #   否则判据读不到 ⇒ 正向样本当场未判（元判据 ⑭ 不过）。落点按夹具自有路径给。
        连接.executemany("insert or replace into 规则 values(?,?,?,?,?)", 夹具唯一物清单)
        # ★ 2026-10-07（加固项 A3 · 判据 55）：`命名出现` 也得填 —— 填的口径**与写口同一份**
        #   （`落库.写库名集`），否则判据 55 在正向样本上会报「名册没跟上」（假红）。
        #   必须等 `命名登记` 插完再调（写口要读名册与例外两张表）。
        连接.commit()
        应写名集 = 取落库写口().写库名集(临根, 库件)
        连接.executemany(
            "insert into 命名出现(名字, 文件路径, 行号, 面) values(?,?,?,?)",
            [(出现名, "夹具", 1, "定义面") for 出现名 in sorted(应写名集)])
    finally:
        连接.commit()
        连接.close()
    return 库件
