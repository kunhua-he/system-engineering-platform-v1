运行数据基线路径 = "构建装配/一键验证/运行数据基线.json"

# 唯一解析器本人（它「自己拼」是它的职责，不算违规）。
运行数据根目录 = "运行内核/运行数据根/"

# 本条判据**自己的件**：模式定义与「口径说明 / 反向样本源」里必然写出那四个形的**字面量**
# （那是判据的眼睛，不是「落运行数据的节点」）⇒ 扫描面显式排除这两个**具名**件。
# **排除是窄的**：只按**本文件名**排；别的件里出现同样的字面量照样被抓（反向样本
# `注入_自拼运行数据路径` / `注入_临时根自建运行数据` 就是往夹具里塞**别的件**；
# 扫描器的单元身份证见 `自检_运行数据扫描`）。
判据自身件 = ("判据_运行数据.py", "注入_运行数据.py")

# 四个认的形（名字同时用作基线的键 · 违规文案里也用它）。
形_平台数据目录 = "平台数据目录拼路径"
形_自建子目录名 = "自建系统工程平台V1子目录名"
形_直读覆盖变量 = "直读V1_RUN_DATA_ROOT"
形_临时根 = "临时根拼路径"

_平台数据目录词 = re.compile(
    r"(data_local_dir|data_dir|XDG_DATA_HOME|LOCALAPPDATA|APPDATA|Application Support)"
)
_临时根词 = re.compile(r"(gettempdir|temp_dir|TMPDIR|/tmp)")
_路径拼接 = re.compile(r"(\.join\s*\(|Path\s*\(|PathBuf|os\.path\.join)")
# 形②：**以** `系统工程平台V1` 开头（不是「恰好等于」）—— 加后缀躲不过。
_自建子目录名 = re.compile(r'["\']系统工程平台V1')
_直读覆盖变量 = re.compile(r'["\']V1_RUN_DATA_ROOT["\']')


def 扫自拼(件表: dict) -> dict:
    """扫一遍（**生产区文本**）⇒ `{(路径, 形): 处数}`（四个形各数各的）。"""
    命中: dict = {}
    for 键 in sorted(件表):
        if 键.startswith(运行数据根目录):
            continue
        文本 = 件表[键]
        if not 文本:
            continue
        for 行 in 文本.split("\n"):
            见 = []
            if _平台数据目录词.search(行) and _路径拼接.search(行):
                见.append(形_平台数据目录)
            if _自建子目录名.search(行):
                见.append(形_自建子目录名)
            if _直读覆盖变量.search(行):
                见.append(形_直读覆盖变量)
            if _临时根词.search(行) and _路径拼接.search(行):
                见.append(形_临时根)
            for 形 in 见:
                命中[(键, 形)] = 命中.get((键, 形), 0) + 1
    return 命中


# 生产区读数在一次运行里不变（对象数与判定各取一次）⇒ 按仓根缓存。
# 键是**绝对路径**：`--自测` 每个夹具一个独立临时目录 ⇒ 不会串。
_运行数据面缓存: dict = {}


def 运行数据面(上: dict) -> dict:
    """扫描面：全仓代码件的**生产区**（跳过 `#[cfg(test)]` 区与整份夹具文件）。

    **排除本判据自己的件**（`判据自身件`）：模式定义与样本里必然出现那四个形的字面量 ——
    那是判据的眼睛，不是「落运行数据的节点」。不排的话，判据会把自己判红（实测撞到过）。
    """
    键 = str(上["仓根"])
    if 键 in _运行数据面缓存:
        return _运行数据面缓存[键]
    件表 = [
        (键_件, 项["文本"])
        for 键_件, 项 in 上["文件"].items()
        if 项.get("文本") is not None
        and 键_件.endswith(代码后缀)
        and 键_件.rsplit("/", 1)[-1] not in 判据自身件
    ]
    面 = 并行生产区(件表, 上.get("测试文件集") or frozenset(), 保串=True)
    _运行数据面缓存[键] = 面
    return 面


def 样本_运行数据面(上: dict) -> int:
    """对象数：扫描面下的代码件数（0 ⇒ 未判）。"""
    return len(运行数据面(上))


def _读基线(基线件) -> tuple:
    if not 基线件.is_file():
        return {}, f"基线文件不存在（{运行数据基线路径}）"
    try:
        数据 = json.loads(基线件.read_text(encoding="utf-8"))
    except Exception as 错:
        return {}, f"基线文件解析不了（{type(错).__name__}）"
    表 = {}
    for 条 in 数据.get("债务") or []:
        try:
            表[(str(条["路径"]), str(条["形"]))] = int(条.get("处数", 0))
        except (KeyError, TypeError, ValueError):
            return {}, f"基线条目形状不对（{条!r}）—— 要 路径/形/处数 三键"
    return 表, None


def 检查25_运行数据自拼路径(上: dict) -> list:
    """要落运行数据的节点必须调 `v1_dataroot`，0 处自己拼（存量入基线 · 基线只许减）。

    三元读数：**通过** = 扫描面非空且无新增/超基线/陈旧；**失败** = 逐条报出；
    **未判** = 扫描面下 0 个件，或基线读不到（「存量入基线」要求先有存量清单）。
    """
    出 = []
    件表 = 运行数据面(上)
    if not 件表:
        判不了(
            检查名[24],
            " · ".join(代码后缀),
            f"扫描面下 0 个代码件（后缀：{' · '.join(代码后缀)}）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一条代码件都没有的仓天然是绿的，"
            "那不是本条判据的功劳 ⇒ 只能由判据作者确认扫描面与后缀表",
        )
        return 出

    基线表, 错 = _读基线(上["仓根"] / 运行数据基线路径)
    if 错:
        return [
            违规(
                检查名[24],
                运行数据基线路径,
                错,
                "「存量入基线、新增即红」要求先有存量清单（决策记录 2026-09-27_运行数据根.md · "
                "判据口径十一条.md §十一）。没有它，实测的存量会被算成「新增」⇒ 判据当场红一片，"
                "等于没上闸。基线只能由**声明方**登记（谁欠的债谁登记）⇒ 只能由维护方补",
            )
        ]

    实测 = 扫自拼(件表)
    口径 = (
        "决策记录 2026-09-27_运行数据根.md：运行数据落点 = 平台数据目录 + `系统工程平台V1`，"
        "**唯一解析器** `运行内核/运行数据根/`（`确保子目录` / `子目录路径`）；§二：名字一律用"
        "**运行数据根**，不许叫「数据目录」「工作目录」「临时根」。要落运行数据的节点必须调它 —— "
        "自己拼 = 第二个来源 ⇒ 位置漂了没人拦。修法：改调 `v1_dataroot`（`确保子目录` / "
        "`子目录路径`）拿到那个路径 ⇒ 只能由该件的作者改"
    )
    for (路径, 形), 实际 in sorted(实测.items()):
        登记 = 基线表.get((路径, 形))
        if 登记 is None:
            出.append(
                违规(
                    检查名[24],
                    f"{路径}::{形}",
                    f"新增「{形}」（{实际} 处），基线里没有它 ⇒ **新增即红**",
                    口径,
                )
            )
        elif 实际 > 登记:
            出.append(
                违规(
                    检查名[24],
                    f"{路径}::{形}",
                    f"「{形}」实测 {实际} 处 > 基线登记 {登记} 处 ⇒ **存量还在长**",
                    "基线是「存量不许再长」的闸，不是白名单（照判据 ⑲/㉒）。这一处已在基线里"
                    "登记过，却又多了 ⇒ 要么改回去，要么在提交信息里说明为什么必须涨并同步登记 ⇒ "
                    "只能由该件的作者处置",
                )
            )

    # ── 基线里不许留**陈旧登记**（与判据 ⑲/㉒ 同一条）──
    for (路径, 形), 登记 in sorted(基线表.items()):
        实际 = 实测.get((路径, 形), 0)
        if 实际 == 0:
            出.append(
                违规(
                    检查名[24],
                    f"{路径}::{形}",
                    f"基线登记着「{形}」（{登记} 处），而实测这一处**已经不出现** ⇒ **陈旧登记**",
                    "「基线只许减」：改掉了就该把登记删掉。留着它，基线读数就不再是现状"
                    "（读的人会以为债还在），而且它白占一格上限 ⇒ "
                    f"只能由维护方删（{运行数据基线路径}）",
                )
            )
        elif 实际 < 登记:
            出.append(
                违规(
                    检查名[24],
                    f"{路径}::{形}",
                    f"基线登记「{形}」{登记} 处，实测只有 {实际} 处 ⇒ **登记没跟着减**",
                    "「基线只许减」：实测比登记低就该同步减下来。不减的话，这一处可以一路长回"
                    "登记值而不报红 —— 那是「只增不减」的一个洞 ⇒ "
                    f"只能由维护方改（{运行数据基线路径}）",
                )
            )
    return 出


def 自检_运行数据扫描() -> list:
    """扫描器的身份证（`判据的可信性.md` §三.5：判据的解析器自己也要有反向样本）。

    四问：① 四个形各抓得住（把同样的字面量放在**别的件**里 ⇒ 必被数出来）；
    ② **自排除是窄的**：排除只按本文件名 —— 唯一解析器本人（`运行内核/运行数据根/`）不算命中，
    而别的件里的同形字面量照抓；③ 形②**加后缀也抓得到**（`系统工程平台V1-演示`）；
    ④ 不误伤：无那四个形的普通件 ⇒ 0 命中。
    """
    样本 = {
        "运行内核/实例状态/src/自拼.rs": (
            "pub fn 自己拼() -> std::path::PathBuf {\n"
            '    let 根 = std::env::var("V1_RUN_DATA_ROOT").unwrap_or_default();\n'
            '    std::path::PathBuf::from(根).join("数据库")\n'
            "}\n"
        ),
        "运行内核/实例状态/src/自建.rs": 'pub const 默认目录名: &str = "系统工程平台V1";\n',
        "构建装配/样例/常量.py": (
            "from pathlib import Path\nimport tempfile\n"
            '暂存根 = Path(tempfile.gettempdir()) / "系统工程平台V1-演示"\n'
        ),
        "开发工具/样例.py": (
            "from pathlib import Path\n"
            '根 = Path(家目录) / "Library" / "Application Support" / "系统工程平台V1"\n'
        ),
        "运行内核/运行数据根/src/解析.rs": 'pub const 覆盖变量名: &str = "V1_RUN_DATA_ROOT";\n',
        "运行内核/实例状态/src/干净.rs": "pub fn 干净() -> u32 { 0 }\n",
    }
    命 = 扫自拼(样本)
    return [
        (
            "反向样本：直读覆盖变量 `V1_RUN_DATA_ROOT` 抓得住（且只在别的件里）",
            ("运行内核/实例状态/src/自拼.rs", 形_直读覆盖变量) in 命,
            f"命中表：{sorted(命)}",
        ),
        (
            "反向样本：自建 `系统工程平台V1` 子目录名 抓得住（含加后缀）",
            ("运行内核/实例状态/src/自建.rs", 形_自建子目录名) in 命,
            "别的件里写同样的目录名 ⇒ 必须被抓（证明自排除只排本文件、不排整类）",
        ),
        (
            "反向样本：临时根（`gettempdir`）拼路径 抓得住，且**加后缀的目录名一并抓**",
            ("构建装配/样例/常量.py", 形_临时根) in 命
            and ("构建装配/样例/常量.py", 形_自建子目录名) in 命,
            "`Path(tempfile.gettempdir()) / \"系统工程平台V1-演示\"` ⇒ 形④ 与 形② 各抓一处",
        ),
        (
            "反向样本：平台数据目录常量拼路径 抓得住",
            ("开发工具/样例.py", 形_平台数据目录) in 命,
            "平台数据目录词 + 路径拼接 ⇒ 必须被抓",
        ),
        (
            "唯一解析器本人不算命中（它的「自己拼」是职责）",
            not any(键.startswith(运行数据根目录) for 键, _形 in 命),
            f"命中表里不许有 {运行数据根目录}：{sorted(命)}",
        ),
        (
            "正向样本：普通件（无那四个形）0 命中",
            not any(键 == "运行内核/实例状态/src/干净.rs" for 键, _形 in 命),
            "不误伤普通件",
        ),
    ]
