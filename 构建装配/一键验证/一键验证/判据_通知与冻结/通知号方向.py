# -*- coding: utf-8 -*-
"""判据 ⑧：通知号落在对应方向的号段内。"""

from __future__ import annotations

from ..小工具 import 是整数, 段归属标签, 违规
from ..常量 import 号段图路径, 契约目录名, 检查名


def 检查8_通知号落在对应方向的号段内(上层读数: dict) -> list:
    输出缓冲 = []
    # 方向只取 下行 / 上行 两个值（§六：它是**协议方向**，不是号段名）。
    # 号段由**通知号本身**决定，依据 号段图.json 的通知号段（1–999 下行段 ·
    # 1000–1999 上行段 · 2000–2999 生命周期段）；生命周期段里两个方向都合法。
    合法方向 = ("下行", "上行")
    号段图 = 上层读数["号段图"] or {}
    段表 = []
    for 序, 段 in enumerate(号段图.get("通知号段") or []):
        if not isinstance(段, dict):
            continue
        起, 止 = 段.get("起"), 段.get("止")
        if 是整数(起) and 是整数(止) and 起 <= 止:
            段表.append((起, 止, 段归属标签(段)))

    for 记录 in 上层读数["编号表"]["通知号段"]:
        位置 = f"{契约目录名}/通知号段/{记录['文件名']}"
        if 记录["数据"] is None:
            输出缓冲.append(
                违规(
                    检查名[7],
                    位置,
                    f"这份通知声明读不出来（{记录['错误']}）",
                    f"通知号是宿主与扩展两侧的派发依据（lib.rs 通知函数）；"
                    f"这一份读不出来就等于这个号没登记，而号本身只有声明方知道 ⇒ 只能由声明方补",
                )
            )
            continue
        数据 = 记录["数据"]
        号值 = 数据.get("通知号")
        方向 = 数据.get("方向")
        if not 是整数(号值):
            输出缓冲.append(
                违规(
                    检查名[7],
                    f"{位置}:通知号",
                    f"通知号 缺失或不是整数（{号值!r}）",
                    f"§六：通知号就是文件名；字段缺了只能靠文件名，"
                    f"而文件名与字段谁是源判据没定 ⇒ 只能由声明方补",
                )
            )
            continue
        if 方向 not in 合法方向:
            输出缓冲.append(
                违规(
                    检查名[7],
                    f"{位置}:方向",
                    f"方向 是 {方向!r}，不在 {合法方向}（§六：方向是协议方向，不是号段名）",
                    f"方向决定宿主与扩展谁发谁收（lib.rs 通知函数两侧都按它派发）；"
                    f"写错的后果是派发反向，正确值只有协议设计方能定 ⇒ 只能由声明方补",
                )
            )
            continue
        命中 = [段项 for 段项 in 段表 if 段项[0] <= 号值 <= 段项[1]]
        if not 命中:
            输出缓冲.append(
                违规(
                    检查名[7],
                    位置,
                    f"通知号 {号值} 不落在 {号段图路径}:通知号段 的任何一段里",
                    f"§六：号段由通知号本身决定（1–999 下行段 · 1000–1999 上行段 · "
                    f"2000–2999 生命周期段）；号不在段里就没有方向依据，改号会撞已有含义 ⇒ 只能人来裁",
                )
            )
            continue
        起, 止, 段标签 = 命中[0]
        # 生命周期段（2000–2999）里两个方向都会出现：
        # 装载/卸载/退出/延迟释放是下行，延迟释放应答（2015）是上行。
        if 段标签 == "生命周期":
            允许 = 合法方向
        else:
            允许 = (段标签,)
        if 方向 not in 允许:
            输出缓冲.append(
                违规(
                    检查名[7],
                    f"{位置}:方向",
                    f"通知号 {号值} 落在 [{起},{止}]（{段标签}段），方向却写 {方向}",
                    f"方向是外部协议语义，宿主与扩展两侧都按它派发（lib.rs 通知函数 · 通知号段 模块）；"
                    f"改方向会让已在跑的对端行为反向，改号会撞已有含义 ⇒ 只能人来裁",
                )
            )
    return 输出缓冲


