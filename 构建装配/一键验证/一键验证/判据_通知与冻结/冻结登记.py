# -*- coding: utf-8 -*-
"""判据 ⑨：冻结登记（三键齐全 · 落点存在且单个 · 日期成形 · 形状指纹 · 段类型号登记三问）。"""

from __future__ import annotations

import re

from ..小工具 import 是整数, 违规
from ..冻结形状 import 算落点指纹
from ..常量 import 契约目录名, 检查名


def 检查9_冻结登记(上: dict) -> list:
    出 = []
    仓根 = 上["仓根"]
    位置 = f"{契约目录名}/冻结登记.json"
    冻结 = 上["冻结"]
    if 冻结 is None:
        return [
            违规(
                检查名[8],
                位置,
                "冻结登记.json 不存在或解析不了（第 9 项的唯一依据）",
                f"冻结项清单只在 冻结登记.json 一处（README 第八节：本文件不复述它）；它读不到，"
                f"「三键齐不齐 · 落点还指不指得到东西」就无从判，验证面自带一份清单就是第二个事实源 ⇒ 只能由声明方补",
            )
        ]

    冻结项 = 冻结.get("冻结项")
    if not isinstance(冻结项, list) or not 冻结项:
        出.append(
            违规(
                检查名[8],
                f"{位置}:冻结项",
                f"冻结项 不是非空列表（是 {type(冻结项).__name__}）",
                f"README 第八节：主结构冻结、演进只走旁路，冻结项清单只有 冻结登记.json 一处；"
                f"清单空了，这一项就没有任何可判的样本（判据的可信性.md 第二节：空集是未判，不是通过），"
                f"补哪些项是架构级盘点 ⇒ 只能人来裁",
            )
        )
    else:
        for 序, 项 in enumerate(冻结项):
            项位置 = f"{位置}:冻结项[{序}]"
            if not isinstance(项, dict):
                出.append(
                    违规(
                        检查名[8],
                        项位置,
                        f"不是对象（是 {type(项).__name__}）",
                        f"冻结项是 {{名称,内容,落点}} 三键对象；不是对象就读不出落点，"
                        f"「冻结的东西还在不在」判不了 ⇒ 只能由声明方补",
                    )
                )
                continue
            缺 = [键 for 键 in ("名称", "内容", "落点") if 键 not in 项]
            if 缺:
                出.append(
                    违规(
                        检查名[8],
                        f"{项位置}:{(' · '.join(缺))}",
                        f"缺 {(' · '.join(缺))}",
                        f"冻结项靠 落点 指到实际形状所在（README 第八节）；"
                        f"缺落点就没有对照物，缺内容就不知道冻的是什么，"
                        f"事后补内容要凭当时意图 ⇒ 只能由声明方补",
                    )
                )
                continue
            落点 = str(项["落点"])
            # README 第八节定死了 落点 的形状：**单个**落点，写法二选一
            #   `相对路径` 或 `相对路径::符号名`；**不许复合**（不许 `首件.md · 次目录`）。
            形状错 = None
            if "·" in 落点:
                形状错 = (
                    f"落点含复合分隔符「·」：{落点}",
                    f"README 第八节：落点必须是单个，不许复合（`首件.md · 次目录`）——"
                    f"复合落点让「这个冻结项在哪」变得不可判定，判据只能靠拆分隔符，"
                    f"而文件名里一旦出现同一个分隔符就误判。拆成几条冻结项还是留一条，"
                    f"是清单结构的裁决 ⇒ 只能人来裁",
                )
            elif 落点.count("::") > 1:
                形状错 = (
                    f"落点里有 {落点.count('::')} 个 `::`：{落点}",
                    f"README 第八节：写法只有两种（`相对路径` / `相对路径::符号名`）；"
                    f"多个 `::` 说明它是复合的，判据拆不出到底指哪一处 ⇒ 只能人来裁",
                )
            elif 落点.strip() == "":
                形状错 = (
                    "落点是空串",
                    f"空落点等于没指东西；该指哪儿只有冻结时在场的人知道 ⇒ 只能由声明方补",
                )
            elif 落点.startswith("/") or ".." in 落点.split("/"):
                形状错 = (
                    f"落点不是仓内相对路径：{落点}",
                    f"README 第八节：落点是 `相对路径`（相对仓根）；绝对路径或 `..` "
                    f"会让同一份登记在不同检出位置指到不同的东西 ⇒ 只能由声明方补",
                )
            if 形状错:
                出.append(违规(检查名[8], f"{项位置}:落点", 形状错[0], 形状错[1]))
                continue
            若路径, _, 符号 = 落点.partition("::")
            if "::" in 落点 and 符号.strip() == "":
                出.append(
                    违规(
                        检查名[8],
                        f"{项位置}:落点",
                        f"落点 {落点} 写了 `::` 但符号名是空的",
                        f"README 第八节：`相对路径::符号名` 的第二种写法必须给出符号名；"
                        f"空符号名指不出是文件里的哪一处 ⇒ 只能由声明方补",
                    )
                )
                continue
            实体 = 仓根 / 若路径
            if not 实体.exists():
                出.append(
                    违规(
                        检查名[8],
                        f"{项位置}:落点",
                        f"落点 {落点} 指的东西不存在（{若路径} 找不到）",
                        f"冻结项冻的是「别人已经依赖的形状」；落点消失意味着形状被搬走或删掉，"
                        f"而这是不是一次已登记的旁路演进，判据定不了 ⇒ 只能人来裁",
                    )
                )
                continue
            if 符号 and 实体.is_file():
                文本 = 上["文件"].get(若路径, {}).get("文本") or ""
                if 符号 not in 文本:
                    出.append(
                        违规(
                            检查名[8],
                            f"{项位置}:落点",
                            f"落点 {落点} 里的符号「{符号}」在 {若路径} 里找不到",
                            f"冻结的是具名形状（README 第八节：调用形状 · 契约主结构 …）；"
                            f"符号改名或消失都会让已按它写的读者失配，"
                            f"是还原还是补旁路登记，只有架构裁决能定 ⇒ 只能人来裁",
                        )
                    )
                    continue
                # ── 形状指纹比对（裁决 §十）──
                # 冻结的是**形状**（字段与顺序与类型），`内容` 是散文、散文判不了它。
                # 指纹口径：声明文本去注释、压空白后 sha256 前 16 位（`冻结形状.py`）。
                登记指纹 = 项.get("形状指纹")
                实得, 形状 = 算落点指纹(文本, 符号)
                if not isinstance(登记指纹, str) or not 登记指纹:
                    出.append(
                        违规(
                            检查名[8],
                            f"{项位置}:形状指纹",
                            f"落点是具名符号（{落点}），却没有 `形状指纹` 键",
                            f"README 第八节写的是「没有登记的形状变化，视为违规」——"
                            f"没有指纹，那条纪律就没有执行者（散文比对不了）。"
                            f"本项的形状指纹是 `{实得}`（照此补键即可）⇒ 只能由声明方补",
                        )
                    )
                elif 实得 is None:
                    出.append(
                        违规(
                            检查名[8],
                            f"{项位置}:形状指纹",
                            f"算不出指纹：{形状}",
                            f"落点写着 `路径::符号名`，就该能抽出它的声明文本；"
                            f"抽不出说明符号形状变了（例：从 `struct` 变成别的、或声明头改了写法）"
                            f"⇒ 是还原还是补旁路登记，只能人来裁",
                        )
                    )
                elif 实得 != 登记指纹:
                    出.append(
                        违规(
                            检查名[8],
                            f"{项位置}:形状指纹",
                            f"形状指纹不符：登记 `{登记指纹}` · 实测 `{实得}`",
                            f"实测的规范形状是：`{形状}`。冻结项冻的是「别人已经依赖的形状」，"
                            f"悄悄改字段/顺序/类型就破坏了那份依赖；"
                            f"改回去还是走旁路演进（登记 + 改指纹），只有架构裁决能定 ⇒ 只能人来裁",
                        )
                    )

    for 键名, 必填, 谁  in (
        ("旁路", ("冻的是什么", "为什么冻", "旁路走哪", "日期"), "README 第八节"),
        ("已收口旁路", ("缺口", "现象", "修法", "来源", "收口日期", "收口形态"), "冻结登记 已收口旁路 的形状"),
        ("待办旁路", ("缺口", "现象", "修法", "来源"), "冻结登记 待办旁路 的形状"),
    ):
        条目表 = 冻结.get(键名)
        if not isinstance(条目表, list):
            出.append(
                违规(
                    检查名[8],
                    f"{位置}:{键名}",
                    f"{键名} 不是列表（是 {type(条目表).__name__}）",
                    f"{谁} 定死了 {键名} 的形状；形状不对会让所有读它的地方"
                    f"（验证面 · 决策记录）读法分叉 ⇒ 只能由声明方补",
                )
            )
            continue
        for 序, 条 in enumerate(条目表):
            条位置 = f"{位置}:{键名}[{序}]"
            if not isinstance(条, dict):
                出.append(
                    违规(
                        检查名[8],
                        条位置,
                        f"不是对象（是 {type(条).__name__}）",
                        f"{谁} 的形状是多键对象；不是对象就读不出内容 ⇒ 只能由声明方补",
                    )
                )
                continue
            缺 = [键 for 键 in 必填 if 键 not in 条]
            if 缺:
                出.append(
                    违规(
                        检查名[8],
                        f"{条位置}:{(' · '.join(缺))}",
                        f"缺 {(' · '.join(缺))}（{谁} 要求：{(' · '.join(必填))}）",
                        f"旁路登记是「形状变化被允许」的唯一凭据（README 第八节："
                        f"没有登记的形状变化视为违规）；缺口与理由只能来自当时的裁决 ⇒ 只能由声明方补",
                    )
                )
                continue
            if 键名 == "旁路":
                日期 = str(条.get("日期", ""))
                if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", 日期):
                    出.append(
                        违规(
                            检查名[8],
                            f"{条位置}:日期",
                            f"日期 {日期!r} 不是 YYYY-MM-DD",
                            f"README 第八节要求每次冻结或旁路「记一行」带日期；"
                            f"日期只能来自当时的裁决时刻，事后补不出真实日期 ⇒ 只能由声明方补",
                        )
                    )

    # ── 段类型号登记（2026-09-27 新增；决策记录/2026-09-27_语言主线三缺口裁决.md §三）──
    #
    # 为什么必须有这一条：盘面段头里的段类型是 **u8（1 字节）**
    # （`u32 校验和 + u8 段类型 + 27 字节名称区 + u32 段名长 + u64 数据长 = 已冻结的 44`），
    # 而登记里曾写着「新增段类型号 256–258」—— **盘面上不存在的号**。
    # 这是契约层的自相矛盾（登记写了表示不了的号），也是 1106 的第三个障碍。
    # 三问：是 0–255 的整数 · 不撞已占用 · 容器形状真能表示。
    段登记 = 冻结.get("段类型号登记")
    if 段登记 is None:
        出.append(
            违规(
                检查名[8],
                f"{位置}:段类型号登记",
                "缺 `段类型号登记` 键（我们自身新增的段类型号没有机器可读的落点）",
                f"旁路条目「新增段类型号」只有散文，散文判不出「号在盘面上表示得了吗」——"
                f"实测正是这里漏过了一次：条目写 `256–258`，而盘面段类型是 u8，`256` 根本装不下。"
                f"号取哪几个是登记方的决定，但**登记必须机器可读** ⇒ 只能由声明方补",
            )
        )
    elif not isinstance(段登记, dict):
        出.append(
            违规(
                检查名[8],
                f"{位置}:段类型号登记",
                f"不是对象（是 {type(段登记).__name__}）",
                f"形状是 {{说明, 已占用, 新增, 落点}}；不是对象就读不出号 ⇒ 只能由声明方补",
            )
        )
    else:
        已占用 = 段登记.get("已占用")
        新增 = 段登记.get("新增")
        占号 = set()
        if isinstance(已占用, dict):
            for _族, 号表 in 已占用.items():
                if isinstance(号表, list):
                    占号.update(int(号) for 号 in 号表 if isinstance(号, int))
        # 容器形状的**声明值集**：从 `容器/形状.rs::段类型` 枚举的判别式里读。
        # 读实现而不是读另一份清单 —— 清单就是第二个事实源。
        形状路径 = "扩展根目录/原子支持库/编译器支持库/src/容器/形状.rs"
        形状文本 = (上["文件"].get(形状路径, {}) or {}).get("文本") or ""
        可表示 = set()
        if 形状文本:
            块 = re.search(r"pub enum 段类型\s*\{(.*?)\n\}", 形状文本, re.S)
            if 块:
                可表示 = {int(数字) for 数字 in re.findall(r"=\s*(\d+)\s*,", 块.group(1))}
        if not isinstance(新增, dict) or not 新增:
            出.append(
                违规(
                    检查名[8],
                    f"{位置}:段类型号登记:新增",
                    f"`新增` 不是非空对象（是 {type(新增).__name__}）",
                    f"空集不算通过（判据的可信性.md 第二节）；没有新增号就没有可判的样本 ⇒ 只能由声明方补",
                )
            )
        else:
            for 段名, 号 in 新增.items():
                条位置 = f"{位置}:段类型号登记:新增:{段名}"
                if not isinstance(号, int) or isinstance(号, bool):
                    出.append(
                        违规(
                            检查名[8],
                            条位置,
                            f"号不是整数（是 {type(号).__name__}）",
                            f"段类型号在盘面上是 u8 整数 ⇒ 只能由声明方补",
                        )
                    )
                    continue
                if not (0 <= 号 <= 255):
                    出.append(
                        违规(
                            检查名[8],
                            条位置,
                            f"号 {号} 超出 u8（盘面段类型是 1 字节，取值只能是 0–255）",
                            f"盘面段头是 `u32 校验和 + u8 段类型 + 27 字节名称区 + u32 段名长 "
                            f"+ u64 数据长 = 已冻结的 44` ⇒ 段类型字段只有 1 字节，`{号}` 在盘面上"
                            f"不存在。改宽度会让「反解 ∘ 生成 = 恒等」在 1444 个真文件上当场失效；"
                            f"故只能改号（取 u8 里的空洞）⇒ 只能由声明方补",
                        )
                    )
                    continue
                if 号 in 占号:
                    出.append(
                        违规(
                            检查名[8],
                            条位置,
                            f"号 {号} 与参照实现已占用的号相撞（已占用 {sorted(占号)}）",
                            f"新增段类型号的前提是「不动旧段」；占用参照实现的号就是改冻结形状 ⇒ "
                            f"只能由声明方补",
                        )
                    )
                    continue
                if 形状文本 and 号 not in 可表示:
                    出.append(
                        违规(
                            检查名[8],
                            条位置,
                            f"号 {号} 在容器形状里表示不了（{形状路径} 的 `段类型` 枚举没有这个判别式；"
                            f"现有 {sorted(可表示)}）",
                            f"登记说「允许新增这个段类型号」，而容器形状里没有它 ⇒ "
                            f"登记与形状是**同一件事两个说法**（判据的可信性.md §三.3）。"
                            f"两处必须一处为准：要么形状里补上这个号，要么登记改掉 ⇒ 只能由声明方补",
                        )
                    )
    return 出
