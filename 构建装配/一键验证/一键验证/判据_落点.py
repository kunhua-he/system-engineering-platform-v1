def _展开花括号(一条: str) -> list:
    """把 `a/{b,c}/d` 展开成 `[a/b/d, a/c/d]`（扫描面里就一层花括号）。"""
    一条 = str(一条)
    if "{" in 一条 and "}" in 一条:
        前, 后 = 一条.split("{", 1)
        中, 尾 = 后.split("}", 1)
        return [前 + 段.strip() + 尾 for 段 in 中.split(",")]
    return [一条]


# 落点存在性按 (仓根, 落点) 缓存：判据器的仓在一次运行里不变，而 `--自测` 会反复调本判据
# （每个夹具一次）—— 不缓存的话，同一批真实落点会被重复 glob 几十次（实测撞到过：
# `--自测` 因此被顶过 5 s 硬顶）。
_存在缓存: dict = {}


def 落点存在(仓根: Path, 一条: str) -> bool:
    """一条落点（文件 / 目录 / 花括号或通配模式）在被扫仓里找得到吗。"""
    键 = (str(仓根), str(一条))
    if 键 in _存在缓存:
        return _存在缓存[键]
    果 = False
    for 单 in _展开花括号(一条):
        单 = 单.strip().rstrip("/")
        if not 单:
            continue
        if any(符 in 单 for 符 in "*?["):
            if glob.glob(str(仓根 / 单), recursive=True):
                果 = True
                break
        elif (仓根 / 单).exists():
            果 = True
            break
    _存在缓存[键] = 果
    return 果


def 判据落点表(元数据: dict) -> list:
    """把判据元数据摊成 `[(判据名, 落点, 是什么)]`（扫描面 + 落点，一处定义）。"""
    出 = []
    for 名, 元 in 元数据.items():
        面 = 元.get("扫描面")
        for 条 in (面 if isinstance(面, (list, tuple)) else [面]):
            if 条:
                出.append((名, str(条), "扫描面"))
        for 条 in 元.get("落点") or ():
            出.append((名, str(条), "落点"))
    return 出


def 检查26_判据落点不悬空(上层读数: dict) -> list:
    """每个判据器的落点都还能找到（落点悬空即红）。

    三元读数：**通过** = 判据面非空且无悬空；**失败** = 逐条报出悬空落点；
    **未判** = 判据面为空（元数据读不到）。
    """
    出 = []
    元数据 = 上层读数.get("判据元数据覆盖") or 判据元数据
