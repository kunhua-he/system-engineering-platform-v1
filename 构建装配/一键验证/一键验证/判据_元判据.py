# -*- coding: utf-8 -*-
"""判据 ⑭：元判据（判据自己的身份证）。"""

from __future__ import annotations

from pathlib import Path

from .Rust文本 import 漏传上下文调用
from .判据元数据 import 判据元数据
from .小工具 import 违规
from .常量 import 检查名


# 本验证器自己的源码件（判据 ⑭-⑤ 按**位置**读它：合成仓里没有本件）。
本验证器源码件 = tuple(sorted(Path(__file__).resolve().parent.glob("*.py")))


def 检查14_元判据(上: dict) -> list:
    """判据检查器（判据的可信性.md 第六节）：五问。

    ① 每条判据都有反向样本与正向样本 ② 每条判据的输出是三元 ③ 每条判据声明了扫描面
    且扫描面下有实际存在的文件 ④ 一次运行里每一条已定义的判据都被执行过
    ⑤ 判据调 `并行生产区` 必须传全套上下文（未完成事项.md #46）。
    """
    出 = []
    元数据 = 上.get("判据元数据覆盖") or 判据元数据
    已执行 = set(上.get("已执行判据") or [])
    样本表 = set(上.get("样本清单") or [])

    # ① 每条判据都有反向样本与正向样本
    for 名, 元 in 元数据.items():
        缺 = []
        if not str(元.get("反向样本") or "").strip():
            缺.append("反向样本")
        elif 元["反向样本"] not in 样本表:
            缺.append(f"反向样本「{元['反向样本']}」不在样本清单里")
        if not str(元.get("正向样本") or "").strip():
            缺.append("正向样本")
        elif 元["正向样本"] not in 样本表:
            缺.append(f"正向样本「{元['正向样本']}」不在样本清单里")
        if 缺:
            出.append(
                违规(
                    检查名[13],
                    f"判据元数据:{名}",
                    f"缺 {(' · '.join(缺))}",
                    f"判据的可信性.md 第五节：每条判据必须成对（反向样本证明它不是空转、"
                    f"正向样本证明它不误报）；缺任一方 ⇒ 该判据「未验证」，"
                    f"它的「通过」不计入通过数。补哪一对样本要真造出可判的输入 ⇒ 只能由判据作者补",
                )
            )

    # ② 每条判据的输出是三元（有对象数读数 ⇒ 能报「扫描 0 项」）
    for 名, 元 in 元数据.items():
        if not callable(元.get("对象数")):
            出.append(
                违规(
                    检查名[13],
                    f"判据元数据:{名}:对象数",
                    "没有对象数读数（判据只能给「通过 / 失败」两条分支 ⇒ 二元口径）",
                    f"判据的可信性.md 第二节铁律：读数必须三元（通过 / 失败 / 未判）。"
                    f"没有对象数就读不出「扫描 0 项」，空集会被算成通过（假绿头号来源）⇒ "
                    f"只能由判据作者补一个「判据对象有多少个」的读数",
                )
            )

    # ③ 声明了扫描面，且扫描面下确有文件（0 个 ⇒ 要么报未判，要么是解析器/扫描面坏了）
    全键 = list(上["文件"])
    for 名, 元 in 元数据.items():
        面 = 元.get("扫描面")
        if not 面:
            出.append(
                违规(
                    检查名[13],
                    f"判据元数据:{名}:扫描面",
                    "没有声明扫描面",
                    f"判据的可信性.md 第三节来源 #2：「判据在」≠「判据覆盖」——"
                    f"不声明扫描面就判不出它到底扫了什么 ⇒ 只能由判据作者补",
                )
            )
            continue
        前缀表 = 面 if isinstance(面, (list, tuple)) else [面]
        实际 = 0
        for 条 in 前缀表:
            头 = 条.split("{", 1)[0].split("*", 1)[0].rstrip("/")
            if not 头:
                continue
            if 头.endswith(".json"):
                实际 += 1 if 头 in 上["文件"] else 0
            else:
                实际 += sum(1 for 键 in 全键 if 键.startswith(头 + "/") or 键 == 头)
        if 实际 == 0:
            出.append(
                违规(
                    检查名[13],
                    f"判据元数据:{名}:扫描面",
                    f"声明的扫描面下实际 0 个文件（扫描面：{面}）",
                    f"判据的可信性.md 第三节来源 #5：判据必须报「它读到了多少」；"
                    f"读数为 0 或「全部同一类」是可疑信号——要么判据的对象真的不存在（那该报未判）、"
                    f"要么扫描面写错了、要么解析器坏了。三者只能由判据作者分辨 ⇒ 只能由判据作者补",
                )
            )

    # ④ 一次运行里每一条已定义的判据都被执行过
    未跑 = sorted(set(元数据) - 已执行)
    if 未跑:
        出.append(
            违规(
                检查名[13],
                "一次运行:已执行判据",
                f"定义了但这次没跑的判据：{未跑}",
                f"判据的可信性.md 第三节来源 #3：判据写好了却从不执行 = 它不存在。"
                f"要么挂进 检查表、要么从判据元数据里删掉（不许留「写了不跑」的判据）⇒ 只能由判据作者改",
            )
        )

    # ⑤ 判据调 `并行生产区` 必须传全套上下文（未完成事项.md #46）
    #    漏传 `测试文件集` ⇒ 整份夹具被当生产代码（实测 检查13 曾漏传 ⇒ 假红）。
    # ⑤ 判据调 `并行生产区` 必须传全套上下文（未完成事项.md #46）
    #    漏传 `测试文件集` ⇒ 整份夹具被当生产代码（实测 检查13 曾漏传 ⇒ 假红）。
    #    按**位置**判：取本验证器**自己的源码**（本包下的 `.py`，不读被扫仓 —— 合成仓里没有
    #    本件，读被扫仓会在正向样本上假红），逐个调用点看实参里有没有 `测试文件集`。
    读了 = []
    for 件 in 本验证器源码件:
        try:
            读了.append((件, 件.read_text(encoding="utf-8")))
        except OSError:
            continue
    if not 读了:
        出.append(
            违规(
                检查名[13],
                str(Path(__file__).resolve().parent),
                "读不到本验证器自己的源码 ⇒ 判不了「并行生产区 是否漏传上下文」",
                "判据的可信性.md 第二节：判不了的如实报判不了，不许默默放过 ⇒ "
                "只能由判据作者确认本件可读（本包下的 `.py` 就是本验证器）",
            )
        )
    else:
        for 件, 文本 in 读了:
            for 行号 in 漏传上下文调用(文本):
                出.append(
                    违规(
                        检查名[13],
                        f"{件.name}:{行号}",
                        "调用 `并行生产区` 没传 `测试文件集`（用了默认空集 ⇒ 整份夹具会被当生产代码）",
                        "未完成事项.md #46：`并行生产区` 的 `测试文件集` 默认空集，漏传时夹具里的"
                        "常量/导出会被读成生产代码 ⇒ 假红（实测 检查13 曾漏传）。"
                        "传哪一份上下文（`上[\"测试文件集\"]`）是判据面口径 ⇒ 只能由该判据作者补参数",
                    )
                )
    return 出
