# -*- coding: utf-8 -*-
"""判据 51：命名一名多义 —— 同一 `唯一名` 的 ≥2 行语义所指不同（真多义）。

依据：库 `规则` 表 命名口径-22。判法只此一份（`命名判法.一名多义`）—— 写侧登记口也调它。
机械筛（先把重复登记剔出去）：(a) 子串包含 ⇒ 重复登记（归 ㊿）；(b) 旧编号形 ⇒ 改号遗留；
(c) 两语义措辞相似度 ≥0.6 ⇒ 重复登记；(d) 余下 ⇒ 真多义 ⇒ 红。
**三元读数**与存量形状同 ㊿（库 `命名多义基线`，只许减）。
"""
from __future__ import annotations

from .小工具 import 判不了, 违规
from .常量 import 检查名
from . import 命名判法
from .判据基线 import 读命名多义基线, 库相对路径


def 对象数_命名一名多义面(上层读数: dict) -> int:
    """对象数：库 `命名定义` 的行数（0 ⇒ 未判）。"""
    定义行表, _错误 = 命名判法.读命名定义(上层读数["仓根"])
    return len(定义行表)


def 检查51_命名一名多义(上层读数: dict) -> list:
    """命名一名多义：同一唯一名的 ≥2 行语义所指不同（存量入基线、新增即红 · 基线只许减）。"""
    输出缓冲 = []
    定义行表, 错误 = 命名判法.读命名定义(上层读数["仓根"])
    if 错误:
        return [违规(检查名[50], 库相对路径, f"判不了：{错误}",
                    "名册是本条的唯一对象（一名多义就从它来）⇒ 读不出就判不了。修法：把规则库补上"
                    "（`python3 开发工具/信息核心/信息核心.py 建库`）⇒ 只能由维护方补")]
    if not 定义行表:
        判不了(检查名[50], 库相对路径, "`命名定义` 0 行 —— 空名册（或库不在）",
              "判据的可信性.md 第二节：空集是**未判**，不是通过 ⇒ 只能由维护方确认规则库")
        return 输出缓冲
    实测表 = 命名判法.一名多义(定义行表)
    基线表, 错误 = 读命名多义基线(上层读数["仓根"])
    if 错误:
        return [违规(检查名[50], 库相对路径, 错误,
                    "「存量入基线、新增即红」要求先有存量清单 ⇒ 只能由维护方登记（库 `命名多义基线` 表）")]
    口径 = ("库 `规则` 表 命名口径-22：同一 `唯一名` 的 ≥2 行语义所指不同 = 真一名多义。修法：拆名 ——"
          "为每件不同的事各取一个精准名，逐符号（定义 + 引用）`v1_edit` 改，改完两个新名各登记一行"
          "⇒ 不许走 `功能=9`（命名口径-11）⇒ 只能由该件的作者改")
    for 唯一名, 多义表 in sorted(实测表.items()):
        实际 = len(多义表)
        登记 = 基线表.get(唯一名)
        if 登记 is None:
            输出缓冲.append(违规(检查名[50], f"命名定义::{唯一名}",
                f"新增一名多义：`{唯一名}` 挂 {实际} 行所指不同的语义，基线里没有它 ⇒ **新增即红**", 口径))
        elif 实际 > 登记:
            输出缓冲.append(违规(检查名[50], f"命名定义::{唯一名}",
                f"一名多义 `{唯一名}` 实测 {实际} 行 > 基线登记 {登记} 行 ⇒ **存量还在长**", 口径))
    for 唯一名, 登记 in sorted(基线表.items()):
        实际 = len(实测表.get(唯一名, []))
        if 实际 == 0:
            输出缓冲.append(违规(检查名[50], f"命名定义::{唯一名}",
                f"基线登记着一名多义 `{唯一名}`（{登记} 行），而实测已无 ⇒ **陈旧登记**",
                "「基线只许减」：拆完就该删登记 ⇒ 只能由维护方删（库 `命名多义基线` 表）"))
        elif 实际 < 登记:
            输出缓冲.append(违规(检查名[50], f"命名定义::{唯一名}",
                f"基线登记 `{唯一名}` {登记} 行，实测只有 {实际} 行 ⇒ **登记没跟着减**",
                "「基线只许减」：实测比登记低就该同步减下来 ⇒ 只能由维护方改（库 `命名多义基线` 表）"))
    return 输出缓冲
