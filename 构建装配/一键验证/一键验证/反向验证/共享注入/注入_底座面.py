# -*- coding: utf-8 -*-
"""注入样本 · 判据 ⑯ 的两处新面（单列一件，免把 `注入.py` 顶过 400 行）。

两个样本各证一处**新面承重**（面扩了必须有人证它真走到了 —— `判据元数据.py` 那条纪律）：
  · `注入_契约声明扩展名进名表` —— 证「名表并集」不是空转：扩展名只在**契约声明**里出现时，
    它也必须进名表（旧口径只取仓内目录名 ⇒ 那个名字根本不进表）；
  · `注入_声明面裸点名` —— 证「声明数据面」不是空转：`契约声明/` 里**裸点名**扩展必须当场红
    （旧口径整片排除 ⇒ 那一片没人看）。
"""
from __future__ import annotations

import json
from pathlib import Path

_样本件 = "运行内核/实例状态/src/扩展名样本.rs"


def 注入_契约声明扩展名进名表(临根: Path) -> str:
    """名表并集的反向样本：扩展名**只在契约声明里出现**时，底座点名它也必须红。

    做法：往 `冻结登记.json` 的旁路里写一条落点 `扩展根目录/组合模块库/样例模块/src/lib.rs`
    —— `样例模块` 没有目录（没有 `Cargo.toml`），只能从**契约声明**进名表（旧口径漏）。
    再在底座生产代码里点名它 ⇒ 判据 ⑯ 当场红（旧口径不会报：名表里没这个名）。
    """
    登记件 = 临根 / "契约声明" / "冻结登记.json"
    配置表 = json.loads(登记件.read_text(encoding="utf-8"))
    配置表["冻结例外"][0]["例外怎么走"] = "样例：落点 `扩展根目录/组合模块库/样例模块/src/lib.rs`"
    登记件.write_text(json.dumps(配置表, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    路径 = 临根 / _样本件
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "/// 反向样本：底座点名一个只在契约声明里出现过的扩展（判据 ⑯ 该抓）。\n"
        'pub const 样例模块名: &str = "样例模块";\n',
        encoding="utf-8",
    )
    return _样本件


def 注入_声明面裸点名(临根: Path) -> str:
    """声明数据面的反向样本：`契约声明/` 里**裸点名**扩展 ⇒ 判据 ⑯ 当场红。

    做法：往 `号段图.json` 的 `说明` 里写一个**裸**的扩展名（后面不是 `/`）—— 它不是路径
    的一段，是散文里点名（后人会照抄）。旧口径下 `契约声明/` 整片被排除 ⇒ 这处不报。
    """
    声明件 = 临根 / "契约声明" / "号段图.json"
    配置表 = json.loads(声明件.read_text(encoding="utf-8"))
    配置表["说明"] = 配置表.get("说明", "") + "（样例：样例支持库 提供语言能力）"
    声明件.write_text(json.dumps(配置表, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return "契约声明/号段图.json"
