# -*- coding: utf-8 -*-
"""注入样本 · 判据 70（唯一执行路径）。

三类实质旁路，一类一条（判据 70 的 `反向样本` 元数据逐字对齐第一条标题）：

  ① 第二调用腿：新件直接调 `调用能力(`（不经边界面 / 进程执行体）；
  ② 第二卸载口：新件直接调 `卸载扩展(`（绕过生命周期响应的公开卸载）；
  ③ 合法对照（**正向**）：在权威件路径上调用 —— 由 `合成仓.py` 提供，本文件不重复造。

注入的都是**可解析的真实调用形**（`对象.调用能力(…)`），不是散文字样 ——
剥注释与串之后仍然命中，所以红的是真调用点。
"""
from __future__ import annotations

from pathlib import Path


def 注入_旁路调用能力(临根: Path) -> str:
    """往合成仓放一个**第二调用腿**（新件直接调 `调用能力(`）⇒ 判据 70 当场红。"""
    路径 = 临根 / "对外接口面" / "网关" / "旁路调用腿.rs"
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "//! 反证样本：这个件不和任何权威件商量，直接调能力。\n"
        "pub fn 直接调(适配器: &v1_adapter::适配器) -> i32 {\n"
        "    let mut 返回槽 = v1_adapter::数据槽::零值();\n"
        "    适配器.调用能力(1001, &[], &mut 返回槽)\n"
        "}\n",
        encoding="utf-8")
    return "对外接口面/网关/旁路调用腿.rs"


def 注入_旁路卸载扩展(临根: Path) -> str:
    """往合成仓放一个**第二卸载口**（新件直接调 `卸载扩展(`）⇒ 判据 70 当场红。"""
    路径 = 临根 / "对外接口面" / "网关" / "旁路卸载口.rs"
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "//! 反证样本：绕过生命周期响应，另开一个卸载口。\n"
        "pub fn 直接卸(内核: &mut v1_kernel::内核, 标识串: &str) -> bool {\n"
        "    卸载扩展(内核, 标识串)\n"
        "}\n",
        encoding="utf-8")
    return "对外接口面/网关/旁路卸载口.rs"
