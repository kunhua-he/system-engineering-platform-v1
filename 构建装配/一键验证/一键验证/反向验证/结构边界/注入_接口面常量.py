# -*- coding: utf-8 -*-
"""注入样本 · 判据 ㊸（接口面常量跨语言一致）：把一侧的一项改掉 ⇒ 当场红。

反向样本注入到**干净合成仓**（不依赖仓库现状 ⇒ 可重复）。
"""
from __future__ import annotations

from pathlib import Path

from ...基础定义.常量 import 命令行件, 接口面件
from ...检查规则.结构边界.判据_网页端点 import 网页面件


def 注入_接口面常量不一致(临根: Path) -> str:
    """把合成仓前端件的 `路径_调用` 改一个字 ⇒ 判据 ㊸ 当场红（后端仍是原值）。

    专证这条判据不是空转：两侧各写一份，漂了必须有人抓。改的是**前端**那一侧
    （后端件的路径集合是 §二 冻结项，前端跟着它走）。
    """
    路径 = 临根 / 命令行件
    源文本 = 路径.read_text(encoding="utf-8")
    改后 = 源文本.replace('路径_调用 = "/接口/调用"', '路径_调用 = "/接口/调用错"', 1)
    assert 改后 != 源文本, "样本前置条件不成立：夹具前端件里没有 `路径_调用 = \"/接口/调用\"`"
    路径.write_text(改后, encoding="utf-8")
    return 命令行件


def 注入_案例布局不一致(临根: Path) -> str:
    """把合成仓后端件的 `案例回执件` 改一个字 ⇒ 判据 ㊼ 当场红（库 `条款` 里仍是原值）。

    专证这条判据不是空转：文档（库 `条款` 的 `测试验证/测试案例/形状.md` §一）与代码
    （`常量.rs`）各写一份，漂了必须有人抓。改的是**代码**那一侧。
    """
    路径 = 临根 / 接口面件
    源文本 = 路径.read_text(encoding="utf-8")
    改后 = 源文本.replace('pub const 案例回执件: &str = "运行回执.jsonl";',
                        'pub const 案例回执件: &str = "运行回执错.jsonl";', 1)
    assert 改后 != 源文本, "样本前置条件不成立：夹具后端件里没有 `案例回执件 = \"运行回执.jsonl\"`"
    路径.write_text(改后, encoding="utf-8")
    return 接口面件


