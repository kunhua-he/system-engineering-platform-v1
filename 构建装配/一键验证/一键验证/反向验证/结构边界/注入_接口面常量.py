    """把合成仓**网页件**的 `路径_调用` 改一个字 ⇒ 判据 ㊾ 当场红（权威侧仍是原值）。

    专证这条判据不是空转：网页应用与接口面各写一份端点路径，漂了必须有人抓。改的是
    **网页**那一侧（接口面 `常量.rs` 是权威，网页跟着它走）。
    """
    路径 = 临根 / 网页面件
    源文本 = 路径.read_text(encoding="utf-8")
