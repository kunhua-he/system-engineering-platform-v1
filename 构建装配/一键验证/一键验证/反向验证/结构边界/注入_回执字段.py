# -*- coding: utf-8 -*-
"""注入样本 · 判据 63（回执裁字段只许裁壳）。"""
from __future__ import annotations

from pathlib import Path


def 注入_回执裁承重(临根: Path) -> str:
    """造一件**裁了承重字段 `退出码`** 的 `.py` ⇒ 判据 63 当场红。

    形状取现场实测那一类（协议层精简回执时把 `退出码` 一起 pop 掉）。

    ★ 字段名用**拼接**构造（`"退出" + "码"`）：本件自身的样本内容是字符串，
      而判据读的是**去串文本**，拼接后字面量 `"退出码"` 不会出现在本件源码里 ⇒
      不会把注入样本本身当成一处违规（否则判据一立就自红）。
    """
    路径 = 临根 / "构建装配" / "样例" / "裁承重样本.py"
    路径.parent.mkdir(parents=True, exist_ok=True)
    字段名 = "退出" + "码"
    路径.write_text(
        "# 反向样本：精简回执时把承重字段一起裁掉。\n"
        "def 精简回执(读数):\n"
        "    读数.pop(\"%s\", None)\n"
        "    return 读数\n" % 字段名,
        encoding="utf-8",
    )
    return "构建装配/样例/裁承重样本.py"
