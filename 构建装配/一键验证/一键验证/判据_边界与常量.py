# -*- coding: utf-8 -*-
"""判据 ⑫⑬：边界纪律 · 常量表。

**判据 ⑫ 的两条 ①类子判据（判据 3「边界 0 业务判断」· 判据 4「边界 0 状态」）的处置**
（#33，2026-09-27）：
  理想迁法 = 结构约束（类型/编译期）——「边界层不许有业务判断、不许有状态」。
  但这两条是**否定存在性**（这个 crate 里 0 处 `if 号 ==` · 0 处模块级 `static`），
  编译期没有「断言某类构造在全 crate 不存在」的手段：`const _: () = assert!(…)` 只能断言
  **具体表达式**，扫不了全 crate；而它们又是宪法条文（边界无状态），不许删。
  ⇒ 按 #33 口径走「确实判不了」那一支：**写清为什么 + 留一条能跑的读数**。
  读数 = 本判据（`边界业务判断模式` / `边界状态模式`，扫描面 = `跨语言适配/` 的 `.rs`）
  ＋ `自测用例` 的两条反向样本（注入 `if 能力号 == 1` / `static 缓存` ⇒ 必红）。
  要上编译期，得由实现侧先把「边界无状态」做进类型（让状态写不出来）。
"""

from __future__ import annotations

import re

from .小工具 import 判不了, 是整数, 违规
from .常量 import Rust后缀, 对外边界符号, 常量表路径, 扩展根三类, 接缝符号, 检查名, 生成物相对路径, 是生成物, 生成物目录, 生成物后缀, 边界业务判断模式, 边界状态模式, 边界目录前缀
from .测试件 import 并行生产区, 收集导出


def 检查12_边界纪律(上: dict) -> list:
    """边界纪律（跨语言适配/边界协议/边界协议.md 第四节 判据 2 · 3 · 4 · 5）。

    与 ⑪ 的分工：⑪ 数**宿主侧对外边界**（全平台唯一，拓扑）；这里数**接缝**
    （每个扩展各一个）与边界自身的纪律（0 业务判断 · 0 状态 · 无第二个导出面）。
    """
    出 = []
    文件 = 上["文件"]
    # 代码后缀 用模块级那一份（一个地方定义）——原来这里是第二份，实测差点漂移。
    # Rust 类判据只收 `.rs`：⑫ 的子判据全是 Rust 词法
    # （`export_name` 属性 · `if 号 ==` · 模块级 `static`），拿它扫 `.py`/`.ts` 是跨语言借词法。

    扫描件源 = [
        (键, 项["文本"])
        for 键, 项 in 文件.items()
        if 键.endswith(Rust后缀)
        and 项["文本"] is not None
        and not 键.startswith(("构建装配/", "开发工具/"))
    ]
    代码件 = 并行生产区(扫描件源, 上["测试文件集"])

    # ── 2b 每个扩展恰好 1 个接缝导出（GetPlatformInfo）──
    扩展目录表 = {}
    for 键 in 文件:
        if not 键.endswith("Cargo.toml"):
            continue
        段 = 键.split("/")
        if len(段) >= 4 and 段[0] == "扩展根目录" and 段[1] in 扩展根三类:
            扩展目录表["/".join(段[:-1])] = True
    if not 扩展目录表:
        出.append(
        判不了(
            检查名[11],
            "扩展根目录/{原子支持库 · 组合模块库 · 技能封装库}/",
            "扫描 0 个扩展目录（找不到带 Cargo.toml 的扩展目录）",
            f"边界协议 第四节判据 2 要「每个扩展恰好 1 个导出」，判的对象是扩展目录；"
            f"目录为空 ⇒ 这条判据没有可判的样本（判据的可信性.md 第二节：空集是未判，不是通过）。"
            f"扩展由 扩展装载/ 按契约载入，验证面不替它建目录 ⇒ 只能由扩展作者落地",
        )
        )
    保串件 = 并行生产区(扫描件源, 上["测试文件集"], 保串=True)
    for 目录 in sorted(扩展目录表):
        本目录件 = {件键: 值 for 件键, 值 in 保串件.items() if 件键.startswith(目录 + "/")}
        导出表 = 收集导出(本目录件)
        名表 = sorted(导出表)
        if 名表 != [接缝符号]:
            情形 = (
                "一个导出都没有 ⇒ 接缝还没接上（扩展还没出 C ABI 面）"
                if not 名表
                else f"多出来的就是第二条接缝：{[导出名 for 导出名 in 名表 if 导出名 != 接缝符号]}"
            )
            命中处表 = [处 for 名 in 名表 for 处 in 导出表.get(名, [])]
            出.append(
                违规(
                    检查名[11],
                    f"{目录}/:导出符号"
                    + (f"（现有 {名表}：{' · '.join(命中处表) or '位置未取到'}）" if 名表 else ""),
                    f"这个扩展导出 {len(名表)} 个符号（判据要求恰好 1 个：`{接缝符号}`）："
                    f"{名表 or '无'}——{情形}",
                    f"边界协议 第二节：接缝只有一个符号 `{接缝符号}`，"
                    f"扩展要提供别的能力一律走命令表（平台信息.命令表 + 函数表），"
                    f"**不许再导出第二个符号**。多一个导出就是第二条接缝；"
                    f"补或撤只能由扩展作者改（底座不认识任何扩展）⇒ 只能由该扩展补",
                )
            )

    # ── 3 边界里 0 处业务判断 ──
    边界件 = {件键: 值 for 件键, 值 in 代码件.items() if 件键.startswith(边界目录前缀)}
    if not 边界件:
        出.append(
        判不了(
            检查名[11],
            边界目录前缀,
            "扫描 0 个生产代码文件（跨语言适配/ 下没有任何生产代码文件）",
            f"判据 3/4 要数的对象是「边界里的代码」；一个文件都没有 ⇒ 空集"
            f"（判据的可信性.md 第二节：空集是未判，不是通过）。"
            f"边界由 跨语言适配/适配器实现/ 落地 ⇒ 只能由该节点补",
        )
        )
    else:
        业务处 = []
        for 键, 文本 in 边界件.items():
            for 命 in 边界业务判断模式.finditer(文本):
                行起 = 文本.rfind("\n", 0, 命.start()) + 1
                业务处.append(
                    f"{键}:{文本[: 命.start()].count(chr(10)) + 1}"
                    f"（{文本[行起 : 文本.find(chr(10), 命.start())].strip()[:60]}）"
                )
        if 业务处:
            出.append(
                违规(
                    检查名[11],
                    f"{边界目录前缀}:业务判断",
                    f"边界里有 {len(业务处)} 处按号特例的业务判断：{业务处[:5]}",
                    f"边界协议 第四节判据 3 · 全局连接器与网关 第三节：网关只做协议翻译、"
                    f"连接器只做形状翻译，**两者都不做业务判断**；业务判断在内核与扩展里。"
                    f"边界一旦自己判，就与内核两套判定，必然漂移；"
                    f"搬去哪一层是结构裁决 ⇒ 只能人来裁",
                )
            )

        # ── 4 边界里 0 处状态 ──
        状态处 = []
        for 键, 文本 in 边界件.items():
            for 命 in 边界状态模式.finditer(文本):
                行起 = 文本.rfind("\n", 0, 命.start()) + 1
                状态处.append(
                    f"{键}:{文本[: 命.start()].count(chr(10)) + 1}"
                    f"（{文本[行起 : 文本.find(chr(10), 命.start())].strip()[:60]}）"
                )
        if 状态处:
            出.append(
                违规(
                    检查名[11],
                    f"{边界目录前缀}:模块级 static",
                    f"边界里有 {len(状态处)} 处模块级 static：{状态处[:5]}",
                    f"边界协议 第四节判据 4 · 全局连接器与网关 第六节：边界**不许持有状态**"
                    f"（持有状态就得管理它的生命周期，那是内核的事；带状态就无法重启、"
                    f"无法多实例）。要状态就用句柄（运行内核/实例状态），句柄是值不是指针 ⇒ "
                    f"把状态搬进内核还是改用句柄，是结构裁决 ⇒ 只能人来裁",
                )
            )

    # ── 5 不许出现第二个 extern "C" 导出面（按方向归类后各恰好一组）──
    全导出 = 收集导出(保串件)
    无名 = [名 for 名 in 全导出 if 名 != 接缝符号 and 名 not in 对外边界符号]
    if 无名:
        出.append(
            违规(
                检查名[11],
                f"全仓代码:导出符号（{sorted(全导出)}）",
                f"有 {len(无名)} 个导出既不是接缝 `{接缝符号}`、也不在对外边界四个符号里：{无名}",
                f"边界协议 第四节判据 5：导出属性**按方向归类后各恰好一组**——"
                f"向内只有 `{接缝符号}`（每个扩展一个）、向外只有那四个。"
                f"归不进任何方向的就是第二个导出面（开发规范 B5：不给任何语言开专用通道）。"
                f"撤掉还是并入既有面，是拓扑裁决 ⇒ 只能人来裁",
            )
        )
    return 出


def 检查13_常量表(上: dict) -> list:
    """常量表：① 同名常量不许在别处再定义 ② 每条常量在生成物里有对应常量或标「未定数」。

    （原「按值匹配：同一个字面量出现 ≥2 次即违规」已删——实测判不了归属：
    `1000` 被三个常量共用、`8` 命中 62 处、`10` 命中 20 处，绝大多数与常量无关。）
    """
    出 = []
    常量表 = 上["常量表"]
    if 常量表 is None:
        return [
            违规(
                检查名[12],
                常量表路径,
                "常量表.json 不存在或解析不了",
                f"常量表是「凡被两处以上引用的数」的唯一定义处；它读不到，"
                f"就没有任何依据判「某个数是不是被抄了两遍」 ⇒ 只能由声明方补",
            )
        ]
    条目表 = 常量表.get("常量")
    if not isinstance(条目表, list) or not 条目表:
        判不了(
            检查名[12],
            f"{常量表路径}:常量",
            f"扫描 0 条常量（`常量` 不是非空列表，是 {type(条目表).__name__}）",
            f"常量表空了，这一项就没有可判的样本（判据的可信性.md 第二节：空集是未判，不是通过）；"
            f"补哪些常量是盘点 ⇒ 只能人来裁",
        )
        return 出

    名表 = []
    值表 = {}
    for 序, 条 in enumerate(条目表):
        条位置 = f"{常量表路径}:常量[{序}]"
        if not isinstance(条, dict):
            出.append(
                违规(
                    检查名[12],
                    条位置,
                    f"不是对象（是 {type(条).__name__}）",
                    f"常量条目的形状是 {{名,值,类型,依据}}；不是对象就读不出名与值 ⇒ 只能由声明方补",
                )
            )
            continue
        缺 = [键 for 键 in ("名", "值", "类型", "依据") if 键 not in 条]
        if 缺:
            出.append(
                违规(
                    检查名[12],
                    f"{条位置}:{(' · '.join(缺))}",
                    f"缺 {(' · '.join(缺))}（常量条目的形状：名 · 值 · 类型 · 依据）",
                    f"依据 是「这个数为什么是这个数」的唯一记录（实测口径 · 判据出处）；"
                    f"事后补不出来 ⇒ 只能由声明方补",
                )
            )
            continue
        if 条["名"] in 名表:
            出.append(
                违规(
                    检查名[12],
                    f"{条位置}:名",
                    f"常量名「{条['名']}」重复（表里已有）",
                    f"同名两条会让「引用这个名字」指到哪个值变成二义；删哪一条都会改行为 ⇒ 只能人来裁",
                )
            )
        else:
            名表.append(条["名"])
        值 = 条["值"]
        if 值 is None:
            continue  # null = 未定数，合法（下面另判「有没有显式标注」）
        if not 是整数(值):
            出.append(
                违规(
                    检查名[12],
                    f"{条位置}:值",
                    f"值 是 {type(值).__name__}（{值!r}），不是整数也不是 null",
                    f"常量表的值要能被生成器写成 Rust 常量（lib.rs 全是定宽整数）；"
                    f"换成别的类型要先定契约形状 ⇒ 只能由声明方补",
                )
            )
            continue
        值表[条["名"]] = 值

    # ── ① 同名常量不许在别处再定义（实现侧必须引用本表生成的常量）──
    # 排除**生成物全集**（路由件 + 子件）：生成物正是这些常量的唯一来源，不是「别处」。
    # 写死单个路径（旧 `生成物相对路径`）会让拆出的子件掉出排除 ⇒ 生成物被当成「第二份定义」假红。
    排除 = {常量表路径} | {键 for 键 in 上["文件"] if 是生成物(键)}
    常量名模式 = (
        re.compile(
            r"(?m)^[ \t]*(?:pub(?:\([^)]*\))?[ \t]+)?const[ \t]+("
            + "|".join(re.escape(名) for 名 in 名表)
            + r")\b"
        )
        if 名表
        else None
    )
    if 常量名模式:
        扫描 = 并行生产区(
            [
                (键, 项["文本"])
                for 键, 项 in 上["文件"].items()
                if 键.endswith(".rs") and 项["文本"] is not None and 键 not in 排除
            ],
            # 整份夹具（父文件用 `#[cfg(test)] … mod …;` 挂进来的独立 .rs）也要跳过：
            # 它自己文件里没有 `#[cfg(test)]`，只按单文件看就是「生产代码」。
            # 实测：夹具里写 `const 号段类宽度: u32 = 1000;`（供测试断言用）会被读成
            # 「同名常量在别处再定义」⇒ 假红（`判据的可信性.md` §四.3）。
            上["测试文件集"],
        )
        for 键, 生产文本 in 扫描.items():
            for 命 in 常量名模式.finditer(生产文本):
                名 = 命.group(1)
                行号 = 生产文本[: 命.start()].count("\n") + 1
                行起 = 生产文本.rfind("\n", 0, 命.start()) + 1
                行止 = 生产文本.find("\n", 命.start())
                原文 = 上["文件"][键]["文本"]
                行文 = 原文[行起 : 行止 if 行止 >= 0 else len(原文)].strip()
                # 别名 ≠ 第二份定义。实测撞到过：
                #   `const 声明格式号: u32 = v1_contract::声明格式号;`
                #   （扩展根目录/原子支持库/编译器支持库/src/lib.rs::声明格式号 早先那处定义）
                # 右值**就是本表生成的那个常量本身**，它恰恰满足判据 ① 的后半句
                # 「实现侧必须引用本表生成的常量」——把它读成「又定义了一份」是判据读宽了。
                # 别名只许「右值末段路径名 == 常量名」（`甲::乙::声明格式号`），
                # 字面量 / 别的表达式一律仍算重定义（那才是会漂移的第二份）。
                定段 = 生产文本[命.start() :]
                分号 = 定段.find(";")
                等号 = 定段.find("=")
                右值 = (
                    定段[等号 + 1 : 分号].strip()
                    if 0 <= 等号 < 分号
                    else ""
                )
                右段 = 右值.split("::")
                if len(右段) >= 2 and 右段[-1].strip() == 名:
                    continue  # 别名：右值指向本表生成的同名常量，不是第二份定义
                出.append(
                    违规(
                        检查名[12],
                        f"{键}:{行号}:const {名}",
                        f"常量「{名}」在常量表里已定义（值 {值表.get(名)}），"
                        f"这里又定义了一份：`{行文}`",
                        f"常量表的判据 ①：同一个常量名不许在别处再定义，实现侧必须引用本表"
                        f"生成的常量（凡被两处以上引用的数都必须在常量表里定义、实现侧由生成器出常量、"
                        f"**禁手写**）。两处定义必然漂移（改一处不改另一处），"
                        f"而「手写的这份删掉后谁补上引用」要按生成物的收口说明走 ⇒ 只能由收口方按步骤改",
                    )
                )

    # ── ② 每条常量在生成物里要么有对应常量、要么有显式的「未定数」标注 ──
    # 落点是**生成物全集**（路由件 + 子件），不是某一个写死的路径 —— 写死路径，拆一次就
    # 静默丢覆盖面 / 假红（#230 记的正是这个病）。拼接全部生成物文本再找常量。
    生成物文本 = "".join(
        项["文本"] or ""
        for 键, 项 in sorted(上["文件"].items())
        if 是生成物(键)
    )
    生成物常量 = {
        配.group(1)
        for 配 in re.finditer(
            r"(?m)^[ \t]*pub const(?: fn)?[ \t]+([^\s:(<]+)", 生成物文本
        )
    }
    生成物面 = f"{生成物目录}/**/*{生成物后缀}"
    for 序, 条 in enumerate(条目表):
        if not isinstance(条, dict) or "名" not in 条:
            continue
        名 = 条["名"]
        # 对应常量：生成物里以这个名字结尾的常量（生成器用 `底座…` 前缀命名）
        命中 = sorted(常量名 for 常量名 in 生成物常量 if 常量名 == 名 or 常量名.endswith(名))
        if 命中:
            continue
        未定 = 条.get("值") is None and "未定数" in str(条.get("依据", ""))
        if 未定:
            continue  # 显式标了未定数 ⇒ 允许生成物里没有它
        出.append(
            违规(
                检查名[12],
                f"{常量表路径}:常量[{序}]:{名}",
                f"常量「{名}」（值 {条.get('值')!r}）在生成物 {生成物面} 里"
                f"既没有对应常量、也没有显式的「未定数」标注",
                f"常量表的判据 ②：本表每条常量在生成物里要么有对应常量、要么有显式的"
                f"「未定数」标注。没有它，实现侧只能手写（这正是判据 ① 抓出的那 8 处的来源）——"
                f"生成器要么给它出常量，要么把「未定数」标注出来；"
                f"哪一种由生成链决定 ⇒ 只能由生成器补",
            )
        )
    return 出
