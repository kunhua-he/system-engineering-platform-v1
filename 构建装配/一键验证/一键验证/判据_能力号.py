"""判据 ㊻：底座不硬写能力号 —— 底座代码面里 0 处出现**已声明的能力号**。

依据：`构建装配/一键验证/一键验证/常量.py` 里那条**诚实边界**（判据 ⑯ 只抓「点名扩展」，
只写编号不写名字的耦合抓不到 —— 例如前端把编译链 `1101→1102→…` 写成数组）；
`项目文档/决策记录/2026-09-27_判据口径十一条.md` §三（宁可收窄，不可错剥）。

**为什么要这一条**：底座要用某个能力，只能经**实时端点**取（`GET /接口` 回能力清单）
或经**调度**按号转发；把号抄进代码就是「加一个能力就要改底座」（破 README §五 硬边界 2）。
判据 ⑯ 管「名字」，本条管「号」—— 两条各管一面，不许互相代替。

**检测表**（只此一份，`已声明能力号`）：契约声明/能力声明/*.json 与
扩展根目录/<层>/<扩展名>/能力声明/*.json 里 `编号` ≥ 1000 的集合。
**为什么是「已声明」而不是「所有四位 `1xxx` 数」**：`\b1[0-9]{3}\b` 会把**另一个号空间**
的数（控件 id · 缓冲长度 · 号段边界）全算进来 —— 实测 `前端呈现/网页应用/对话框表.js`
一处就有 184 个控件 id。那不是能力号，判它就是假红（判据的可信性.md：判据不许是假红工厂）。

**面**：底座代码面（`底座代码树` − `底座代码面排除`）的**生产区**（保串 = 真：字符串里的
编号也算硬写 —— 历史上那处正是回执**文本**里的「编译链 1101→1102→1103→1106」）。
面复用 `判据_底座与树.底座扩展面`（与判据 ⑯ 同一处），不另写一份。

**机制照判据 ㊵**：存量入基线（库 `硬写能力号基线` 表）· 新增即红 · 超基线即红 ·
陈旧登记即红 · 基线只许减。**白名单**（空表 + 加词门槛）：键 `(件, 号)`；加词三条缺一不可 ——
① 该号在此处有**非能力**的语义（控件 id / 尺寸 / 号段边界 —— 与能力号只是数字相撞）；
② 该处**不参与**能力分派（不喂给调度、不在能力号表里）；③ 给出全仓实测读数。

三元读数：**通过** = 检测表非空且扫描面非空且无新增/超基线/陈旧；**失败** = 逐条报出；
**未判** = 检测表为空（一条能力都没声明）或扫描面 0 件（走树坏了也是 0）。
"""
