# 基线**住规则库**（`硬写能力号基线` 表）—— 不落外部 json（华哥 2026-09-29）。库路径只此一份。
硬写能力号基线路径 = 库相对路径


def 已声明能力号(上层读数: dict) -> set:
    """检测表（**只此一份**）：契约声明与扩展自报的已声明能力号（`编号` ≥ 1000 的整数）。

    两处取：① `契约声明/能力声明/*.json`（在 `上层读数["文件"]` 里）；
    ② `扩展根目录/<层>/<扩展名>/能力声明/*.json` —— 那一片**不进** `上层读数["文件"]`
    （它只收 `契约声明/**/*.json` 与仓内源件），而扩展的能力声明是**扩展自报的事实**
    ⇒ 从盘上现读（与判据 ⑰/⑳ 走树同一口径）。读不动/不是 JSON 就跳过（不是「能力号」）。
    """
    号集 = set()
    for 键名, 记录 in 上层读数["文件"].items():
        if not 键名.endswith(".json") or "/能力声明/" not in 键名:
            continue
        号集.update(_抽编号(记录.get("数据")))
    仓根 = Path(上层读数["仓根"])
    for 件路径 in sorted(仓根.glob("扩展根目录/*/*/能力声明/*.json")):
        try:
            数据 = json.loads(件路径.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        号集.update(_抽编号(数据))
    return 号集


def _抽编号(数据) -> set:
    """一条能力声明的 `编号`（≥ 1000 的整数）⇒ 单元素集或空集（两处取法共用）。"""
    if not isinstance(数据, dict):
        return set()
    号值 = 数据.get("编号")
    return {号值} if isinstance(号值, int) and 号值 >= 1000 else set()


def 底座代码面(上层读数: dict) -> dict:
    """面：底座代码面的**生产区**（保串 = 真）⇒ `{件: 文本}`（与判据 ⑯ 同一处口径）。"""
    from .判据_底座与树 import 底座扩展面

    return 底座扩展面(上层读数)["生产"]


def 扫硬写能力号(上层读数: dict) -> dict:
    """实测 ⇒ `{(件, 号): 处数}`（判定与冻结基线共用这一份 —— 不各写一套）。"""
    号集 = 已声明能力号(上层读数)
    实测 = {}
    for 键名, 文本 in 底座代码面(上层读数).items():
        for 号值 in sorted(号集):
            处数 = len(re.findall(r"(?<![0-9A-Za-z_])%d(?![0-9A-Za-z_])" % 号值, 文本))
            if 处数:
                实测[(键名, 号值)] = 处数
    return 实测


def 样本_硬写能力号面(上层读数: dict) -> int:
    """对象数：检测表里的能力号数（0 ⇒ 未判：一条能力都没声明，本条无对象）。"""
    return len(已声明能力号(上层读数))


def 检查46_底座不硬写能力号(上层读数: dict) -> list:
    """底座不硬写能力号：底座代码面里 0 处出现已声明能力号（存量入基线、新增即红 · 基线只许减）。"""
    输出缓冲 = []
    号集 = 已声明能力号(上层读数)
    if not 号集:
        判不了(
            检查名[45],
            "契约声明/能力声明/ · 扩展根目录/<层>/<扩展名>/能力声明/",
            "扫描 0 条已声明的能力（检测表为空）—— 空集上「0 处硬写」恒真 ⇒ 假绿",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。检测表 = 声明侧的能力号；"
            "一条都没有的仓天然是绿的 ⇒ 只能由声明侧落地（验证面不造声明）",
        )
        return 输出缓冲
    生产 = 底座代码面(上层读数)
    if not 生产:
        判不了(
            检查名[45],
            " · ".join(底座代码树),
            "底座代码面下 0 个代码件（扫描面坏了，或底座真的空了）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 ⇒ 只能由判据作者确认扫描面",
        )
        return 输出缓冲
    基线表, 错误 = 读硬写能力号基线(上层读数["仓根"])
    if 错误:
        return [
            违规(
                检查名[45],
                硬写能力号基线路径,
                错误,
                "「存量入基线、新增即红」要求先有存量清单（形状照判据 ㊵）；没有它，"
                "实测的全部存量会被算成「新增」⇒ 判据当场红一片，等于没上闸。"
                "基线只能由**声明方**登记（谁欠的债谁登记）⇒ 只能由维护方补"
                "（库 `硬写能力号基线` 表）",
            )
        ]
    实测 = 扫硬写能力号(上层读数)
    # 基线里的号是**十进制文本**（与报出的 `件::号` 同形），而实测的键是 int ⇒ 对陈旧那一循环
    # 要按文本对读，否则「已登记的号」全会被当成「已经不出现」（实测撞到过）。
    实测文本 = {(路径, str(号值)): 处数 for (路径, 号值), 处数 in 实测.items()}
    口径 = (
        "README §五「底座与扩展」硬边界 1/2：底座要用某个能力，只能经**实时端点**取"
        "（`GET /接口` 回能力清单）或经**调度**按号转发 —— 把号抄进代码就是「加一个能力就要"
        "改底座」（破硬边界 2）。判据 ⑯ 管「名字」，本条管「号」。"
        "修法：把那个号换成端点/契约查得的实时值 ⇒ 只能由该件作者改"
    )
    for (键名, 号值), 实际处数 in sorted(实测.items()):
        位置 = f"{键名}::{号值}"
        登记 = 基线表.get((键名, str(号值)))
        if 登记 is None:
            输出缓冲.append(
                违规(
                    检查名[45],
                    位置,
                    f"底座里硬写已声明能力号 `{号值}`（{实际处数} 处），基线里没有它 ⇒ **新增即红**",
                    口径,
                )
            )
        elif 实际处数 > 登记:
            输出缓冲.append(
                违规(
                    检查名[45],
                    位置,
                    f"硬写能力号 `{号值}` 实测 {实际处数} 处 > 基线登记 {登记} 处 ⇒ **存量还在长**",
                    "基线是「存量不许再长」的闸，不是白名单（形状照判据 ㊵）⇒ 要么改回去，"
                    "要么同步登记 ⇒ 只能由该件作者处置",
                )
            )
    for (键名, 号值), 登记 in sorted(基线表.items()):
        实际处数 = 实测文本.get((键名, 号值), 0)
        if 实际处数 == 0:
            输出缓冲.append(
                违规(
                    检查名[45],
                    f"{键名}::{号值}",
                    f"基线登记着硬写能力号 `{号值}`（{登记} 处），而实测**已经不出现** ⇒ **陈旧登记**",
                    "「基线只许减」：改掉了就该把登记删掉 ⇒ 只能由维护方删"
                    f"（{硬写能力号基线路径}）",
                )
            )
        elif 实际处数 < 登记:
            输出缓冲.append(
                违规(
                    检查名[45],
                    f"{键名}::{号值}",
                    f"基线登记硬写能力号 `{号值}` {登记} 处，实测只有 {实际处数} 处 ⇒ **登记没跟着减**",
                    "「基线只许减」：实测比登记低就该同步减下来，否则可以一路长回登记值而不报红 ⇒ "
                    f"只能由维护方改（{硬写能力号基线路径}）",
                )
            )
    return 输出缓冲
