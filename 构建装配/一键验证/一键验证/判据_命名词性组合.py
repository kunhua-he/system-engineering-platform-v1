# -*- coding: utf-8 -*-
"""判据 53：命名词性组合 —— 名成不成句（词性组合式，三档机械判法）。

依据：库 `规则` 表 命名口径-27 + 《词性组合式表》。判法只此一份（`命名判法.词性违规`）——
写侧登记口也调它。三档：① 动作族却切不出宾语（整名就是一个光杆动词）·
② 量名无对象（整名 = 数词 + 量词）· ③ 无主承载物名无限定词（整名是一个泛指承载物）。
**三元读数**与存量形状同 ㊿（库 `命名词性基线`，只许减）。
"""
from __future__ import annotations

from .小工具 import 判不了, 违规
from .常量 import 检查名
from . import 命名判法
from .判据基线 import 读命名词性基线, 库相对路径


def 对象数_命名词性面(上层读数: dict) -> int:
    """对象数：库 `命名定义` 的行数（0 ⇒ 未判）。"""
    定义行表, _错误 = 命名判法.读命名定义(上层读数["仓根"])
    return len(定义行表)


def 检查53_命名词性组合(上层读数: dict) -> list:
    """命名词性组合：名不成句（存量入基线、新增即红 · 基线只许减）。"""
    输出缓冲 = []
    定义行表, 错误 = 命名判法.读命名定义(上层读数["仓根"])
    if 错误:
        return [违规(检查名[52], 库相对路径, f"判不了：{错误}",
                    "名册是本条的唯一对象（词性组合就从它来）⇒ 读不出就判不了。修法：把规则库补上"
                    "（`python3 开发工具/信息核心/信息核心.py 建库`）⇒ 只能由维护方补")]
    if not 定义行表:
        判不了(检查名[52], 库相对路径, "`命名定义` 0 行 —— 空名册（或库不在）",
              "判据的可信性.md 第二节：空集是**未判**，不是通过 ⇒ 只能由维护方确认规则库")
        return 输出缓冲
    名册名集 = set()
    for _语义, 唯一名, _现状栏 in 定义行表:
        名册名集.update(命名判法.拆唯一名(唯一名))
    实测键集 = set(命名判法.词性违规(名册名集))
    基线表, 错误 = 读命名词性基线(上层读数["仓根"])
    if 错误:
        return [违规(检查名[52], 库相对路径, 错误,
                    "「存量入基线、新增即红」要求先有存量清单 ⇒ 只能由维护方登记（库 `命名词性基线` 表）")]
    口径 = ("库 `规则` 表 命名口径-27：动作名必带宾语 · 量名须有对象 · 承载物名须到具体物。"
          "修法：按它承载什么 / 干什么改名（`解析` ⇒ `解析协议值` · `数据` ⇒ `能力包件数据`）⇒ "
          "只能由该件的作者改")
    for 键名 in sorted(实测键集):
        出现名, 档位 = 键名
        if 键名 not in 基线表:
            输出缓冲.append(违规(检查名[52], f"命名定义::{出现名}",
                f"新增不成句的名：`{出现名}`（{档位}），基线里没有它 ⇒ **新增即红**", 口径))
    for 键名, 登记 in sorted(基线表.items()):
        if 键名 not in 实测键集:
            输出缓冲.append(违规(检查名[52], f"命名定义::{键名[0]}",
                f"基线登记着不成句的名 `{键名[0]}`（{键名[1]}，{登记} 处），而实测已无 ⇒ **陈旧登记**",
                "「基线只许减」：改完就该删登记 ⇒ 只能由维护方删（库 `命名词性基线` 表）"))
    return 输出缓冲
