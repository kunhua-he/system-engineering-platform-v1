# -*- coding: utf-8 -*-
"""条款文本 —— 库 `条款` 表（**已删 md 的唯一存本**）的行 ⇒ 「件」形状的文本。

**为什么要它**：全树 md 已删到只剩 `README.md` / `AGENTS.md`，旧 md 的正文**只住在**
`开发工具/信息核心/信息核心.db` 的 `条款` 表里（`表定义.分片源件表`：`文档路径` 是源件路径，
源件不在 ⇒ **保住库里的行** —— 库是它们的唯一存本）。

**为什么走树看不见它**：判据 ㊵/㊹ 的面是「逐字节全树文本」，而 `.db` 整份**不是合法 UTF-8**
（sqlite 头 + 页对齐的零字节）⇒ `判据_十干.十干面` 整份跳过它。于是那批正文成了**盲区**：
md 在的时候它在面里，删了之后就没人再看。本件把 `条款` 表的每一行拼成一件，补回那个面。

**读法只此一处**：本件按 `文档路径` + `序号` 拼出件名（`库::条款::<文档路径>::<序号>`），
文本 = 标题 + 换行 + 正文。判据 ㊵/㊹ 都调它，不各写一套。
库不在 / 读不动 ⇒ 交**空表**（判据按「空集是未判」处理，不在这里报红）。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path

from .判据基线 import 库相对路径


条款件前缀 = "库::条款::"


def 读条款件(树根) -> dict:
    """⇒ `{伪件名: 文本}`（`库::条款::<文档路径>::<序号>`）。库不在 / 读不动 ⇒ `{}`。"""
    库件 = Path(树根) / 库相对路径
    if not 库件.is_file():
        return {}
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute("select 文档路径, 序号, 标题, 正文 from 条款"))
        finally:
            连接.close()
    except sqlite3.Error:
        return {}
    件表 = {}
    for 文档路径, 序号, 标题, 正文 in 行表:
        件表[f"{条款件前缀}{文档路径}::{序号}"] = f"{标题 or ''}\n{正文 or ''}"
    return 件表
