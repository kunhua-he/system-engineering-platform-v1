# -*- coding: utf-8 -*-
"""判据 66：权威地图路径存在 —— 地图声明的权威件路径都在（删 / 改即红）。

依据：债务 598（权威源地图缺「路径存在性」机判，地图必随现量漂而无人报红）·
债务 596（权威源地图正文进库 `条款`，`AGENTS.md` 与服务提示词各留一行指针）。

**为什么要这一条**：本仓「告知性」文档（`AGENTS.md` 的权威件索引 · 库 `条款` 的权威源
地图）列出「去哪里取权威」的路径。件删了 / 改名了，那些路径**静默悬空** —— 新会话照它
去找会扑空，而闸 0 全绿。实测已漂两处（《派腿前置》写「唯一台账 = 未完成.json」而该件
已删；一份临时文档写「13 个工具」与现量不符）。

**地图清单落点**：库 `规则` 表 `类` = `权威地图`（一行一个权威件；`名` 列 = 那是什么权威，
`依据` 列 = 它的**落点路径**）。形状照判据 56（核心只放唯一物）—— 清单住库、每行落点在盘上。

**路径怎么算「在」**：本仓有的权威件是**已删 md**（正文住库 `条款` 表，盘上无件）⇒ 一条
`依据` 满足**任一**即算在：① 盘上真有这件；② 库 `条款` 表有这条 `文档路径` 的记录。
两处都匹配不到 ⇒ 悬空（必红）。

三元读数：**通过** = 清单非空 · 每行落点都在；**失败** = 逐条报出悬空的落点；
**未判** = 清单为空（0 行，空集不是通过）或库读不动。
"""
from __future__ import annotations

import sqlite3
from pathlib import Path

from .验证小工具 import 判不了, 违规
from .判据基线 import 库相对路径
from .常量 import 检查名

地图表 = "规则"
地图类 = "权威地图"


def 读权威地图(仓根) -> tuple:
    """⇒ `([(编号, 名, 依据)], 错误或 None)` —— 库不在 / 读不动交错误回去（fail-closed）。"""
    库件 = Path(仓根) / 库相对路径
    if not 库件.is_file():
        return [], f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute(
                "select 编号, 名, 依据 from %s where 类 = ?" % 地图表, (地图类,)))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return [], f"`{地图表}` 读不动：{错误}"
    return [(表行[0] or "", 表行[1] or "", 表行[2] or "") for 表行 in 行表], None


def 读条款路径集(仓根) -> tuple:
    """⇒ `({文档路径}, 错误或 None)` —— 已删 md 的正文住库 `条款` 表（把「库里的件」也算在）。"""
    库件 = Path(仓根) / 库相对路径
    if not 库件.is_file():
        return set(), f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute("select distinct 文档路径 from 条款"))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return set(), f"`条款` 读不动：{错误}"
    return {记录行[0] for 记录行 in 行表}, None


def 样本_权威地图面(上层读数: dict) -> int:
    """对象数：权威地图清单的条数（0 ⇒ 未判：清单没落库，本条无对象）。"""
    行表, _错误 = 读权威地图(上层读数["仓根"])
    return len(行表)


def 检查66_权威地图路径存在(上层读数: dict) -> list:
    """权威地图清单每行落点在盘上 / 库 `条款` 里存在（三元：通过 / 失败 / 未判）。"""
    输出缓冲 = []
    仓根 = Path(上层读数["仓根"])
    行表, 错误 = 读权威地图(仓根)
    if 错误:
        判不了(
            检查名[59],
            库相对路径,
            错误,
            "「权威地图清单」住库 `规则` 表 `类`=`权威地图` —— 读不动就判不了"
            "「每行落点在盘上」。库是唯一存本，只能由维护方补"
            "（`python3 开发工具/信息核心/信息核心.py 记规则 --类 权威地图 …`）",
        )
        return 输出缓冲
    if not 行表:
        判不了(
            检查名[59],
            库相对路径,
            "权威地图清单为空（库 `规则` 表 `类`=`权威地图` 0 行）—— 空集上子判据恒真 ⇒ 假绿",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。清单必须先落库"
            "（每条一个权威件）⇒ 只能由维护方登记",
        )
        return 输出缓冲
    条款路径集, 条款错误 = 读条款路径集(仓根)
    if 条款错误:
        判不了(
            检查名[59],
            库相对路径,
            条款错误,
            "权威件有两类存本：盘上的件与库 `条款` 表里已删 md 的正文。后一类读不动 ⇒ "
            "「悬空」判不出来（会把库里的件误报成悬空）⇒ 只能由维护方把库修可读",
        )
        return 输出缓冲
    口径 = (
        "权威地图是「去哪里取权威」的清单（正文住库 `条款` `项目文档/权威源地图.md`）；"
        "路径删了 / 改了 ⇒ 新会话照它去找会扑空而闸照旧绿。修法：把 `依据` 改成真实落点，"
        "或（该件真删了）把它从清单里撤掉 ⇒ 只能由该件的作者处置"
    )
    for 表行 in 行表:
        落点 = (表行[2] or "").strip()
        if not 落点:
            输出缓冲.append(违规(
                检查名[59], f"{地图表}:{表行[0]}",
                f"权威件「{表行[1]}」没有落点（`依据` 列空）—— 清单每行必须能指到一处落点",
                口径,
            ))
            continue
        if (仓根 / 落点).exists():
            continue
        if 落点 in 条款路径集:
            continue
        输出缓冲.append(违规(
            检查名[59], 落点,
            f"权威件「{表行[1]}」的落点 `{落点}` 在盘上不存在、也不在库 `条款` 表里（地图与盘面漂了）",
            口径,
        ))
    return 输出缓冲
