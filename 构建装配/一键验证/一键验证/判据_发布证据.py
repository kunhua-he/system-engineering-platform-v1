# -*- coding: utf-8 -*-
"""判据 67：发布证据与兼容矩阵 —— 四类材料收得成一份证据 · 兼容矩阵四维齐且旧样本不可变。

依据：架构收敛方案项 W07 · 发布验收（正式证据：证据绑定 源码 / 契约 / 制品 / 工具链 ·
缺材料阻断发布 · 发布证据可复现且缺材料不冒充通过）与 F04（新旧 宿主 / 调用方 / 制品 /
执行模式 兼容矩阵 · 旧样本不可变）。

**为什么要这一条**：四类指纹原先散在 `契约声明/冻结登记.json` 与取证样本里 —— 谁也没法一次
回答「这份发布绑的是哪份源、哪份契约、哪个制品、哪套工具链」；而兼容矩阵在盘上根本不存在
（全仓搜 `兼容矩阵` 零命中）⇒ 兼容结论只活在口头。这两件都是**只写一次就会漂**的登记：
没有判据守着，删了 / 改了没人知道，而闸 0 照旧绿。

**面**：`构建装配/上线切换/发布证据/`（采集口与兼容矩阵校验口）—— 从**被扫仓**取（真仓 /
反向样本的注入仓）；夹具仓是合成仓、没有本件 ⇒ 那条路判**未判**（不是通过）。
**规则**：
  · 兼容矩阵：`契约声明/兼容矩阵.json` 在位 · 四维（宿主 / 调用方 / 制品 / 执行模式）齐 ·
    每维带 `旧` / `新` / `兼容判定` / `落点` · `旧样本` 逐条指纹与盘上那份相符（不可变）
  · 发布证据：制品产物在时，四类材料（源码指纹 / 契约指纹 / 制品指纹 / 工具链）必须都取得到；
    制品产物不在 ⇒ 这半是**未判**（没构建过就没有证据可收，空集不是通过）
**三元读数**：通过 = 矩阵全项对 +（有制品时）四类材料齐；失败 = 逐条报出；未判 = 制品产物不在
（证据半）· `契约声明/兼容矩阵.json` 读不动（矩阵半）· 发布证据包载不动。

**假阴性面**（登记在案）：本判据只判「材料**取得到**、指纹**相符**」—— 材料本身够不够用
（比如工具链版本是否真能复现那个制品）不在本面；那是发布链上人的判断。
"""
from __future__ import annotations

import importlib
import sys
from pathlib import Path

from .验证小工具 import 判不了, 违规
from .常量 import 检查名

发布证据包相对路径 = "构建装配/上线切换/发布证据"
矩阵相对路径 = "契约声明/兼容矩阵.json"


def 载入发布证据(仓根) -> tuple:
    """从**被扫仓**取发布证据包 ⇒ `(证据包, 未采原因)`；载不动一律交原因回去（不静默当通过）。"""
    装载目录 = Path(仓根) / "构建装配" / "上线切换"
    if not (装载目录 / "发布证据" / "__init__.py").is_file():
        return None, "发布证据包不在（%s）" % (装载目录 / "发布证据")
    if str(装载目录) not in sys.path:
        sys.path.insert(0, str(装载目录))
    try:
        return importlib.import_module("发布证据"), ""
    except Exception as 错误:  # noqa: BLE001 —— 载入失败交未判，绝不静默当通过
        return None, "发布证据包载不动（%s）" % 错误


def 样本_发布证据面(上层读数: dict) -> int:
    """对象数：矩阵四维条数 + 旧样本条数（0 ⇒ 未判：矩阵没落盘，本条无对象）。"""
    证据包, 未采原因 = 载入发布证据(上层读数["仓根"])
    if 证据包 is None:
        return 0
    违规行, 矩阵 = 证据包.查矩阵()
    if 矩阵 is None:
        return 0
    return len(矩阵.get("四维") or []) + len(矩阵.get("旧样本") or [])


def 检查67_发布证据与兼容矩阵(上层读数: dict) -> list:
    """兼容矩阵四维齐 + 旧样本不可变；制品在时四类材料必须齐（三元：通过 / 失败 / 未判）。"""
    输出缓冲 = []
    证据包, 未采原因 = 载入发布证据(上层读数["仓根"])
    if 证据包 is None:
        判不了(
            检查名[60], 发布证据包相对路径, 未采原因,
            "本判据的对象是**本仓**的发布证据件 —— 它不在就判不了「四类材料收得成一份证据」；"
            "修法只能由该件的作者补",
        )
        return 输出缓冲
    矩阵违规行, 矩阵 = 证据包.查矩阵()
    if 矩阵 is None:
        判不了(
            检查名[60], 矩阵相对路径, "；".join(矩阵违规行),
            "兼容矩阵是声明侧唯一存本（`契约声明/兼容矩阵.json`）；它不在 / 读不动就判不了"
            "「四维齐、旧样本不可变」⇒ 只能由声明侧补（形状见 构建装配/上线切换/发布证据/兼容矩阵.py）",
        )
        return 输出缓冲
    矩阵口径 = (
        "兼容矩阵是「新旧 宿主 / 调用方 / 制品 / 执行模式 能不能一起跑」的唯一登记处"
        "（架构收敛方案项 F04）；缺维 / 缺字段 / 旧样本漂了 ⇒ 兼容结论不再成立而闸照旧绿。"
        "修法：补齐那一维的四栏，或（旧样本真该改时）同步改 `指纹` 并重走兼容评估 ⇒ "
        "只能由声明侧处置"
    )
    for 违规行 in 矩阵违规行:
        输出缓冲.append(违规(检查名[60], 矩阵相对路径, 违规行, 矩阵口径))
    材料, 缺项, 制品目录 = 证据包.采集()
    if 制品目录 is None:
        return 输出缓冲
    证据口径 = (
        "发布证据 = 源码指纹 + 契约指纹 + 制品指纹 + 工具链 四类同证（架构收敛方案项 W07 · 发布验收）；"
        "缺任一类 ⇒ 发布链上的「缺材料阻断」会拦（架构收敛方案项 W07）。修法：先构建制品再重采，"
        "或补齐清单里缺的那一项（`构建装配/上线切换/构建制品.py`）"
    )
    for 缺项行 in 缺项:
        输出缓冲.append(违规(检查名[60], 制品目录.name, "四类材料缺：" + 缺项行, 证据口径))
    return 输出缓冲
