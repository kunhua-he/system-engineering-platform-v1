# 依据：项目文档/设计文档/接口面形状.md §五（三条不许）。
#
# 原模式 `JSON\.parse|JSON\.stringify|校验|解析|生成|validate|parse\(` 是一袋**词**，
# 于是把**传输必需的编码**判成了违规：`前端呈现/网页应用/取接口.js` 里的 `JSON.stringify(文本)`
# 只把编辑区文本编成 JSON 字面量（不改内容 · 不看内容），却被数成一处「处理程序」。
# （实测更正 #176 的一处读法：命中处是**代码里的那个调用**，不是注释 —— 注释早被 `去字面量` 剥掉；
#  那条注释只是在**解释它不是违规**，所以整件事看起来像「辩解被判成了罪证」。）
#
# 口径（三段）：
#   · **解析 ⇒ 禁**：`JSON.parse` 把文本变成值 = 对内容作出判断 ⇒ 绕过网关直连声明，
#     前端与网关两套判定必然漂移（判据 6 的本意）。
#   · **序列化 ⇒ 允许**：`JSON.stringify` 只把文本**编码成 JSON 字面量**（转义引号/换行/反斜杠），
#     不改一个字节、不看内容、不认关键字——传输必需，不是处理程序（`前端呈现/说明.md` §三.1）。
#   · **其余同原则**：判断动词的**调用形** ⇒ 禁；纯搬运 / 编码 / 拼接 ⇒ 允许。
#   「调用形」是关键：裸词会把注释与同义串一起判红（实测），而 `校验(x)` 这种**调用**才是判断。
# `.html` 内联 `<script>` **已进扫描面**（判据_拓扑.py 取内联体）。
# ★ **本模式不是判据的全部覆盖面**：判据的真实面在 `判据_拓扑.前端命中`，本注释只管
#   `前端逻辑模式` 这一支。**别在本注释里写第二份覆盖面**。
# **正则字面量一律是数据、不是逻辑**（`剥字面量` 把 `/…/` 当字面量剥掉）⇒ 值位置那支
#   （`=` · `return` · `,` · `(` · `:` · `[` · `?` · `=>` 后紧接 `/`）**实测 0 命中**，
#   是**留着不删的兜底**；真正能打到的只有**调用形**（`.test(` · `.exec(` · `new RegExp(`）。
#   反向样本钉着这一点（`自检_前端.py`）。
# **仍不认的（诚实登记）**：语句位置紧跟 `)` 的裸 `/…/`（`if (条件) /x/.test(文);`）—— 与
# `(a) / b` 除法同形，认它会假红（`决策记录/2026-09-27_判据口径十一条.md` §三：
# 宁可收窄并写明，不留「认不出但报绿」）。
前端逻辑模式 = re.compile(
    r"JSON\s*\.\s*parse\b"  # 解析 JSON 文本（裁决点名的那一个）
    r"|\bDOMParser\b|\bparseFromString\b"  # 解析 HTML / XML 文本
    r"|\beval\s*\(|\bnew\s+Function\s*\("  # 动态求值：对内容作出判断的另一面
    r"|\bnew\s+RegExp\s*\(|\.[ \t]*(?:test|exec)\s*\("  # 正则判断（调用形）
    # 正则字面量在**值位置** —— 兜底支（实测 0 命中：剥器先把这些 `/…/` 剥走了，见文件头 ★）。
    # 只认这几种**不可能**是除法的前缀：`=` / `return` / `,` / `(` / `:` / `[` / `?` / `=>` 后紧接 `/`。
    r"|(?:=[ \t]*|return[ \t]+|,[ \t]*|\([ \t]*|:[ \t]*|\[[ \t]*|\?[ \t]*|=>[ \t]*)"
    r"/[^/*\s=][^\n]*?/[gimsuy]*"
    r"|[\w$]*(?:解析|校验|验证|生成|判断|检查|转换"  # 判断动词的**调用形**
    r"|parse|validate|generat|convert|regex|正则)[\w$]*\s*\("
)

