# -*- coding: utf-8 -*-
r"""引用扫描：`<名>.md §<节号>` 引用式的解析与「可解析」判定（判据 ㊴ 的解析器）。

依据：`项目文档/决策记录/2026-09-27_判据口径十一条.md` §十（落点写死的病）·
`项目文档/开发规范/开发规范.md` §八（测量与引用纪律）· 判据 ⑮（引用的**格式**）。

**为什么要这一条**：判据 ⑮ 只禁**按行号**引用、只规定引用的**格式**（源码 `路径::符号名` ·
文档 `路径 §节名`），**不判引用能不能解析到**。2026-09-28 文档瘦身删掉一批 `##` 节之后，
引用方（在 `.rs` · `.py` · `.json` · `.js` 与别的 `.md` 里）指向已不存在的节号 ——
而闸 0 全绿、无一处报红。本条把「能不能解析到」变成常驻判据。

**解析口径**（照一次性审计器 `断链扫.py`，并加两条**宁松不假红**的放宽）：

  1. **引用式**：同一行里 `<名>.md` 之后**紧邻**出现 `§<节号>`。节号 = 阿拉伯数码或中文数码
     （一…十四；`断链扫.py` 的中表只到十四）。`§X.Y` 按「第 X 节的子节 / 第 X 节的第 Y 条」
     两读都收 —— **只要节 X 在就算可解析**（本仓两种写法并存）。
  2. **紧邻**（本判据加的门）：`<名>.md` 与 `§` 之间只许夹空白 / 反引号 / 括号 / 顿逗
     （`_允许间隙`）。放宽它会把**跨行的上下文人名**（同一行前面点了一个件、§ 却指另一件）
     误当引用 ⇒ 成片假红。这一条是实测的归属假阳性来源。
  3. **归属**：§ 归**同行任一** `<名>.md` 候选件 —— 只要该行**任一**候选件有该节，或
     **所在件自身**有该节 ⇒ 可解析。只按「最近前导件名」归属会误报（实测：一行里两个件名，
     § 属前一个）。**全都对不上**才报红。
  4. **件名匹配**：完整相对路径后缀优先，再 basename 精确，再 basename 后缀（本仓引用常省
     日期前缀）。**匹配不到任何件** ⇒ 判不了（进 `未判表`，由判据 ㊴ 报**未判**）。
     ★ 2026-10-01 修（判据假绿审计 N2）：原先这里是 `continue` **静默跳过** —— 文档瘦身删净
     md 之后，「指向已删件」的引用整批不判（判过 20 处 · 跳过 640 处），判据却全绿。

**假阴性面（如实登记）**：同行别的件「碰巧也有同一节号」会掩盖真断链；件名匹配不到时进未判表；
`.js`/`.json`/`.toml` 里的引用只在同行判（跨行的指代判不了）。这些由基线 + 人工复核兜。
"""
from __future__ import annotations

import re
from pathlib import Path

# 中文数码 → 数（一…十四）。**与一次性审计器 `断链扫.py` 同表** —— 口径照抄，别自创。
中表 = {
    "一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6, "七": 7,
    "八": 8, "九": 9, "十": 10, "十一": 11, "十二": 12, "十三": 13, "十四": 14,
}

# 节标题：`## <数码>` 起头（`##` 后允许空白）。与 `断链扫.py::节号` 同一条。
_节首 = re.compile(r"^##\s*(十一|十二|十三|十四|十[一二三四五六七八九]?|[一二三四五六七八九]|[0-9]+)")

# 件名：以 `.md` 结尾、且不含空白 / 反引号 / 常见标点的连续串。与 `断链扫.py` 同一条。
件名式 = re.compile(r"([^\s`（）()【】\[\]，,、；;：:*'\"。]+\.md)")

# 节号式：`§` 后接中文数码或阿拉伯数码。与 `断链扫.py` 同一条。
节式 = re.compile(r"§\s*(十一|十二|十三|十四|十[一二三四五六七八九]?|[一二三四五六七八九]|[0-9]+)")

# 紧邻门允许的间隙字符（见文件头第 2 条）。
_允许间隙 = frozenset(" \t`（）()、，,　")


def 节号(标题行: str):
    """这一行若是节标题（`## <数码>` 起头）⇒ 返回它的节号，否则 None。"""
    命中 = _节首.match(标题行.strip())
    if not 命中:
        return None
    数码 = 命中.group(1)
    return int(数码) if 数码.isdigit() else 中表.get(数码)


def 节集(文本: str) -> set:
    """一份文本里**存在**的节号集合（只看 `##` 标题，与 `断链扫.py::节集` 同一条）。"""
    return {号值 for 号值 in (节号(标题行) for 标题行 in 文本.splitlines()) if 号值}


# 条款行的 `标题` 栏（已由 `建库` 剥掉 `# ` 前缀）—— 直接以数码起头。与 `_节首` 同一张数码表。
# `三·五` 这类子节标题取**主节号**（与磁盘口径一致：`## 三·五 …` 也按 3 计）。
_标题首 = re.compile(r"^(十一|十二|十三|十四|十[一二三四五六七八九]?|[一二三四五六七八九]|[0-9]+)")


def 标题节号(标题: str):
    """`条款` 行的 `标题` 栏 ⇒ 节号（不以数码起头 ⇒ None）。口径同 `节号`，只是没有 `##` 前缀。"""
    命中 = _标题首.match((标题 or "").strip())
    if not 命中:
        return None
    数码 = 命中.group(1)
    return int(数码) if 数码.isdigit() else 中表.get(数码)


def 条款节集(行表: list) -> dict:
    """`[(文档路径, 标题)]`（`条款` 表的行）⇒ `{文档路径: {节号}}`。

    md 已全量入库并删净之后，被引用的正文住 `条款` 表 —— 引用的「目标件」由此**解到库**
    （`文档路径` 当件名 · `标题` 起头数码当节号）。这样指向已删 `.md` 的引用不再一律落
    `未判`，而是与磁盘件同口径判「节在不在」（判据 ㊴ 的「悬空面」这才有对象）。
    """
    节集表 = {}
    for 文档路径, 标题 in 行表:
        号值 = 标题节号(标题)
        if 号值:
            节集表.setdefault(文档路径, set()).add(号值)
    return 节集表


def 候选件(件名: str, 件表: dict, 基名表: dict = None) -> list:
    """`件名`（一个 `.md` 件名）能对上的**候选件**（相对路径表）。

    三级：① 完整相对路径后缀（`k == 件名` 或 `k.endswith("/" + 件名)`）② basename 精确
    ③ basename 后缀 / 名字后缀（本仓引用常省日期前缀，如 `判据口径十一条.md` 指
    `2026-09-27_判据口径十一条.md`；也常带前导散文，如 `——见界面实测.md` 指 `界面实测.md`）。
    三级都空 ⇒ 返回 `[]`（判不了，见文件头第 4 条）。
    """
    基名表 = 基名表 if 基名表 is not None else {键名: Path(键名).name for 键名 in 件表}
    精确 = [键名 for 键名 in 件表 if 键名 == 件名 or 键名.endswith("/" + 件名)]
    if 精确:
        return 精确
    粗匹配 = [键名 for 键名 in 件表 if 基名表[键名] == 件名]
    if 粗匹配:
        return 粗匹配
    return [键名 for 键名 in 件表 if 基名表[键名].endswith(件名) or 件名.endswith(基名表[键名])]


def 扫引用(件表: dict, 自身算: bool = True, 任一候选: bool = True, 要求紧邻: bool = True,
          条款节集: dict = None) -> tuple:
    """扫一遍 `{相对路径: 文本}` ⇒ `(悬空表, 判过处数, 未判表)`。

    悬空表 = `[(本件, 行号, 名, 节号, 原文)]`（只收**目标件匹配得到、却无该节**的引用）。
    判过处数 = 真判过的引用处数（**判空集用** —— 解析器坏了也是 0 处，两者必须分得开）。
    未判表 = `[(本件, 行号, 名, 节号, 原文)]`（**目标件一件都匹配不到**的引用）。

    `条款节集` = `{文档路径: {节号}}`（`条款` 表里那些已删 `.md` 的正文）—— **磁盘件匹配不到时
      再拿它按同一套三级匹配解**：解得开且节在 ⇒ 可解析（与磁盘件同权）；解得开、节不在 ⇒
      悬空；两处都匹配不到 ⇒ 未判。不给它（`None`）⇒ 只按磁盘件判（自检样本的口径）。
    2026-10-01 修（判据假绿审计 N2）：原先候选件匹配不到即 `continue` **静默跳过**
      （判过 20 处 · 跳过 640 处），指向已删件的断链整批不判、判据却全绿；现进未判表由判据 ㊴
      报**未判**并写明跳过多少处，存量入基线（只许减）。
    2026-10-01 修（引用解到库）：未判面之上再叠**条款面** —— md 删净后正文住库，指向它的引用
      解到 `条款` 就能真判「节在不在」（判据 ㊴ 的「悬空面」这才有对象），存量按只许减入基线。

    三个开关**只给自检的承重证明用**（退回一步 ⇒ 必被误报），正常判定一律默认全开：
      · `自身算`：所在件自身有该节也算可解析（关掉 ⇒ 自引用样本必被误报）。
      · `任一候选`：同行任一候选件有该节即可（关掉 ⇒ 只看最近前导件名，实测的归属假阳性）。
      · `要求紧邻`：`<名>.md` 与 `§` 之间只许夹 `_允许间隙`（关掉 ⇒ 跨行上下文人名误当引用）。
    """
    条款节集 = 条款节集 or {}
    件全集 = list(dict.fromkeys(list(件表) + list(条款节集)))
    基名表 = {键名: Path(键名).name for 键名 in 件全集}
    节集缓存 = {键名: 节集(文本 or "") for 键名, 文本 in 件表.items()}
    for 键名, 号集 in 条款节集.items():
        节集缓存.setdefault(键名, set()).update(号集)
    悬空 = []
    判过 = 0
    未判表 = []
    for 本件 in sorted(件表):
        文本 = 件表[本件] or ""
        if "§" not in 文本:
            continue
        自身节集 = 节集缓存.get(本件, set())
        for 行号, 行文本 in enumerate(文本.splitlines(), 1):
            if "§" not in 行文本:
                continue
            锚表 = [(命中.end(), 命中.group(1).strip("`*（()")) for 命中 in 件名式.finditer(行文本)]
            if not 锚表:
                continue
            本行候选 = list(dict.fromkeys(
                键名 for _止位, 件名 in 锚表 for 键名 in 候选件(件名, 件全集, 基名表)
            ))
            for 命中 in 节式.finditer(行文本):
                数码 = 命中.group(1)
                号值 = int(数码) if 数码.isdigit() else 中表.get(数码)
                if 号值 is None:
                    continue
                前导 = [一项 for 一项 in 锚表 if 一项[0] <= 命中.start()]
                if not 前导:
                    continue
                if 要求紧邻 and not set(行文本[前导[-1][0]:命中.start()]) <= _允许间隙:
                    continue
                候选 = 本行候选 if 任一候选 else 候选件(前导[-1][1], 件全集, 基名表)
                if not 候选:
                    # 目标件匹配不到任何件 ⇒ 不是「可解析」，也不许静默 `continue`：
                    # 进未判表，由判据 ㊴ 报**未判**（存量入基线、只许减）。
                    未判表.append((本件, 行号, 前导[-1][1], 号值, 行文本.strip()[:160]))
                    continue
                判过 += 1
                if any(号值 in 节集缓存.get(键名, set()) for 键名 in 候选):
                    continue
                if 自身算 and 号值 in 自身节集:
                    continue
                悬空.append((本件, 行号, 前导[-1][1], 号值, 行文本.strip()[:160]))
    return 悬空, 判过, 未判表
