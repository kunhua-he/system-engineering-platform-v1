# -*- coding: utf-8 -*-
"""注入样本 · 判据 ㊵（零字面十干）。

反向样本注入到**干净合成仓**（不依赖仓库现状 ⇒ 可重复）。合成仓的
`构建装配/一键验证/十干基线.json` 是**空的**（合成仓里 0 处十干），
所以任何一处注入都必然是「新增」⇒ 当场红。

★ 十干字**按码位取**（`chr(0x7532)`）—— 本件自身也在判据 ㊵ 的扫描面内，
写整字会给**自身**造一处真违规（先例：`注入_行号引用` 把行号写成 `{12}`）。
"""
from __future__ import annotations

from pathlib import Path

# 十干字之首（按码位取，不写字面）。
_十干字首 = chr(0x7532)


def 注入_字面十干(临根: Path) -> str:
    """往合成仓的一个 `.md` 里写一个**字面十干** ⇒ 判据 ㊵ 当场红。

    注入的形状就是现场实测那一类（**散文 / 注释 / 字符串**里的十干 —— 正是判据 ㉒
    的标识符面拦不住的那一类）。目标件是一个**新 `.md`** ⇒ 必然是「新增」。
    """
    路径 = 临根 / "项目文档" / "十干样例.md"
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "样例：这一行里有一个字面十干 " + _十干字首 + "（判据 ㊵ 应当抓住它）。\n",
        encoding="utf-8",
    )
    return "项目文档/十干样例.md"
