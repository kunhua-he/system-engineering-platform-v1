# -*- coding: utf-8 -*-
"""注入样本 · 判据 ㊹（零字面禁译名）。

反向样本注入到**干净合成仓**（不依赖仓库现状 ⇒ 可重复）。合成仓的**夹具规则库**里
`禁译名基线` 表是**空的**（合成仓里 0 处禁译名），所以任何一处注入都必然是「新增」⇒ 当场红。

★ 禁译名二字**按码位取**（`chr(0x5E03)`）—— 本件自身也在判据 ㊹ 的扫描面内，
写整字会给**自身**造一处真违规（先例：`注入_十干` 把十干写成 `chr(0x7532)`）。
"""
from __future__ import annotations

from pathlib import Path

# 禁译名（按码位取，不写字面）。
_禁译名 = "".join(chr(码位) for 码位 in (0x5E03, 0x5C14))


def 注入_字面禁译名(临根: Path) -> str:
    """往合成仓的一个 `.md` 里写一个**字面禁译名** ⇒ 判据 ㊹ 当场红。

    注入的形状就是现场实测那一类（**散文 / 注释**里的译名 —— 判据 ㊵ 拦住的那一类
    在另一个词上的重现）。目标件是一个**新 `.md`** ⇒ 必然是「新增」。
    """
    路径 = 临根 / "项目文档" / "禁译名样例.md"
    路径.parent.mkdir(parents=True, exist_ok=True)
    路径.write_text(
        "样例：这一行里有一个字面禁译名 " + _禁译名 + "（判据 ㊹ 应当抓住它）。\n",
        encoding="utf-8",
    )
    return "项目文档/禁译名样例.md"
