"""判据 ㊸/㊼：接口面常量跨语言一致 · 案例布局与形状文档一致。

判据 ㊸：命令行界面不许另写一份接口面事实。

依据：复用性审计落点 §八 N4 —— HTTP 路由表跨语言一致（两侧漂了没人抓）。现状：
`对外接口面/调用接口面/src/常量.rs`
与 `前端呈现/命令行界面/命令行界面/常量.py` 是**同一事实的两份**（四个端点路径 · 端口 ·
监听地址），而全仓**没有任何判据**读它们做一致比对 ⇒ 两侧漂了没人抓。

**比哪几项 · 各在哪一侧**（先读清两侧各有什么，不把不是同一事实的项硬拉进来）：
  · **四条端点路径**（`路径_根` · `路径_能力` · `路径_调用` · `路径_声明`）—— 两件**同名**，
    逐名对读（后端件还有 8 条旁路路径，前端不实现 ⇒ 不在此列）。
  · **监听地址**（后端 `监听地址` / 前端 `回环地址`）—— 两件各有，逐项对读。
  · **接口端口** —— 后端**不在 常量.rs 里**：它是 `pub use v1_adapter::接口端口;` 的**再导出**，
    值住它的**唯一来源** `契约声明/常量表.json` 的「接口端口」条目（`常量.rs` 件头写明了
    这条来源）⇒ 端口这一项按那个唯一来源取，与前端 `默认端口` 对读。
  · **不比的项（确属另一面，如实登记）**：后端 `旁路端点表` 的 8 条旁路路径（案例 / 扩展 /
    导出 / 程序文本 / 菜单命令 / 生命周期 / 留痕）—— 命令行界面只实现 §二 那四个端点，旁路
    是网页应用那一面；前端 `端口环境变量`（部署侧口径）· `默认超时秒`（超时，不属路由事实）·
    `用法`（散文）—— 后端 常量.rs 里都没有对应项。

三元读数：**通过** = 可比项逐项一致；**失败** = 逐项报出差在哪一项；**未判** = 两侧件缺一侧
或可比项 0 条（判据的可信性.md 第二节：空集是未判，不是通过）。
"""
from __future__ import annotations

import re

from .小工具 import 判不了, 违规
from .常量 import 检查名, 常量表路径, 接口面件, 命令行件, 接口面路径名表


# 判据 ㊼ 的真源（库 `条款` 表的一节）与要比的三个布局项（**一处定义**）。
案例形状文档 = "测试验证/案例/形状.md"
案例布局项 = ("案例根", "案例回执件", "案例声明件")


def _取Rust串常量(源文本: str, 路径名: str):
    """Rust 件里 `pub const <名>: &str = "<值>";` 的值（取不到 ⇒ None）。"""
    匹配结果 = re.search(
        r'(?m)^[ \t]*pub const ' + re.escape(路径名) + r'\s*:\s*&str\s*=\s*"([^"]*)"\s*;', 源文本)
    return 匹配结果.group(1) if 匹配结果 else None


def _取Py串常量(源文本: str, 路径名: str):
    """Python 件里 `名 = "<值>"` 的值（取不到 ⇒ None）。"""
    匹配结果 = re.search(r'(?m)^[ \t]*' + re.escape(路径名) + r'\s*=\s*"([^"]*)"', 源文本)
    return 匹配结果.group(1) if 匹配结果 else None


def _取Py整数常量(源文本: str, 路径名: str):
    """Python 件里 `名 = <整数>` 的值（取不到 ⇒ None）。"""
    匹配结果 = re.search(r'(?m)^[ \t]*' + re.escape(路径名) + r'\s*=\s*(\d+)', 源文本)
    return int(匹配结果.group(1)) if 匹配结果 else None


def _取后端端口(上层读数: dict):
    """后端端口 —— 从它的**唯一来源** `契约声明/常量表.json` 取（`常量.rs` 件头写明的来源）。"""
    条目表 = (上层读数.get("常量表") or {}).get("常量")
    if not isinstance(条目表, list):
        return None
    for 常量条目 in 条目表:
        if isinstance(常量条目, dict) and 常量条目.get("名") == "接口端口":
            return 常量条目.get("值")
    return None


def 可比项(上层读数: dict) -> list:
    """两侧摊成 `[(项名, 后端值, 前端值, 后端出处, 前端出处)]` —— **判定与对象数共用这一份**。

    两侧任一缺该项 ⇒ 该项不进表（缺项由 `检查43` 按「可比项 0 条」报未判）。
    """
    全仓件表 = 上层读数["文件"]
    后端文本 = (全仓件表.get(接口面件) or {}).get("文本") or ""
    前端文本 = (全仓件表.get(命令行件) or {}).get("文本") or ""
    项表 = []
    for 路径名 in 接口面路径名表:
        后端值 = _取Rust串常量(后端文本, 路径名)
        前端值 = _取Py串常量(前端文本, 路径名)
        if 后端值 is not None and 前端值 is not None:
            项表.append((f"路径 {路径名}", 后端值, 前端值, 接口面件, 命令行件))
    后端地址 = _取Rust串常量(后端文本, "监听地址")
    前端地址 = _取Py串常量(前端文本, "回环地址")
    if 后端地址 is not None and 前端地址 is not None:
        项表.append(("监听地址", 后端地址, 前端地址, 接口面件, 命令行件))
    后端端口 = _取后端端口(上层读数)
    前端端口 = _取Py整数常量(前端文本, "默认端口")
    if 后端端口 is not None and 前端端口 is not None:
        项表.append(("接口端口", 后端端口, 前端端口, 常量表路径, 命令行件))
    return 项表


def 样本_接口面常量(上层读数: dict) -> int:
    """对象数：两侧**可比**的项数（0 ⇒ 未判，不报通过）。"""
    return len(可比项(上层读数))


def 检查43_接口面常量跨语言一致(上层读数: dict) -> list:
    """接口面常量跨语言一致：命令行界面与对外接口面的 路径 · 端口 · 监听地址逐项一致。"""
    输出缓冲 = []
    全仓件表 = 上层读数["文件"]
    缺件表 = [路径 for 路径 in (接口面件, 命令行件) if 路径 not in 全仓件表]
    if 缺件表:
        判不了(
            检查名[42],
            " · ".join(缺件表),
            f"两侧件缺 {len(缺件表)} 件：{缺件表} ⇒ 跨语言一致无从比对",
            "这条判据的对象就是那两件（后端 `对外接口面/调用接口面/src/常量.rs` · 前端 "
            "`前端呈现/命令行界面/命令行界面/常量.py`）；缺一件，另一件的值没有对照物 ⇒ "
            "空集是未判不是通过。补件或改落点（`常量.py` 的 `接口面件`/`命令行件`）"
            "⇒ 只能由该件的作者处置",
        )
        return 输出缓冲
    项表 = 可比项(上层读数)
    if not 项表:
        判不了(
            检查名[42],
            f"{接口面件} · {命令行件}",
            "两侧件都在，但一条可比项都取不到（四个路径常量 · 监听地址 · 端口全没读到）"
            "—— 也可能是**解析器坏了**（正则认不出 `pub const …: &str = …;` / `名 = …`）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。修法：查本件 "
            "`_取Rust串常量` / `_取Py串常量` / `_取Py整数常量` 的正则，或确认那两件"
            "确实还写着这几条常量 ⇒ 只能由判据作者确认",
        )
        return 输出缓冲
    for 项名, 后端值, 前端值, 后端处, 前端处 in 项表:
        if str(后端值) != str(前端值):
            输出缓冲.append(
                违规(
                    检查名[42],
                    f"{后端处} ↔ {前端处}",
                    f"{项名} 两侧不一致：后端 {后端值!r} · 前端 {前端值!r}",
                    "同一事实（HTTP 路由表：端点路径 · 端口 · 监听地址）在两处各写一份 ⇒ "
                    "改一处不改另一处就漂（上一版就是前端默认端口与网关端口不一致）。"
                    "以哪一侧为准要按契约（后端路径是 §二 冻结项 · 端口唯一来源是 "
                    "`契约声明/常量表.json`）⇒ 改哪边只能由两侧的作者定",
                )
            )
    return 输出缓冲


