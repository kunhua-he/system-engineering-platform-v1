# 判据 ㊼：案例布局与形状文档一致
#
# 依据：同一事实（案例目录布局）在**文档与代码**两处各写一份：
#   `对外接口面/调用接口面/src/常量.rs` 的 `案例根` / `案例回执件` / `案例声明件`
#   ↔ 库 `条款` 表 `测试验证/案例/形状.md` §一（案例目录形状）。
# 为什么只能立判据：真源在库（md 已全量入库并删净，Rust **不能 import**），而
#   `测试验证/案例/跑案例/` 是 bin-only（crate `v1-case-runner`，网关无法反向依赖它）⇒
#   两侧没有编译期联系，漂了没人抓（形状照判据 ㊸）。
# ══════════════════════════════════════════════════════════════════════════


def 读案例形状(仓根) -> tuple:
    """读库 `条款` 表的 `测试验证/案例/形状.md` §一（案例目录形状）⇒ `(正文, 错误或 None)`。"""
    import sqlite3
    from pathlib import Path

    from .判据基线 import 库相对路径

    库件 = Path(仓根) / 库相对路径
    if not 库件.is_file():
        return "", f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            行表 = list(连接.execute(
                "select 正文 from 条款 where 文档路径=? and 序号=1", (案例形状文档,)))
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return "", f"`条款` 读不动：{错误}"
    if not 行表:
        return "", f"库 `条款` 表里没有 `{案例形状文档}` §一"
    return 行表[0][0] or "", None


def 案例布局可比项(上层读数: dict) -> tuple:
    """两侧摊成 `[(项名, 后端值, 正文)]` ⇒ `(项表, 错误或 None)`（判定与对象数共用这一份）。

    取不到某一项 ⇒ 该项不进表（缺项由 `检查47` 按「可比项 0 条」报未判）。
    """
    源文本 = (上层读数["文件"].get(接口面件) or {}).get("文本") or ""
    正文, 错误 = 读案例形状(上层读数["仓根"])
    if 错误:
        return [], 错误
    项表 = []
    for 布局名 in 案例布局项:
        布局值 = _取Rust串常量(源文本, 布局名)
        if 布局值 is not None:
            项表.append((布局名, 布局值, 正文))
    return 项表, None


def 样本_案例布局(上层读数: dict) -> int:
    """对象数：能取到的案例布局项数（0 ⇒ 未判，不报通过）。"""
    项表, _错误 = 案例布局可比项(上层读数)
    return len(项表)


def 检查47_案例布局与形状文档一致(上层读数: dict) -> list:
    """案例布局与形状文档一致：`常量.rs` 的案例目录布局 ↔ 库 `条款` 的 `形状.md` §一。"""
    输出缓冲 = []
    if 接口面件 not in 上层读数["文件"]:
        判不了(
            检查名[46],
            接口面件,
            f"件不在（{接口面件}）⇒ 案例布局无从比对",
            "这条判据的对象就是那件（网关的案例布局常量）；缺一件，另一侧（库 `条款`）"
            "没有对照物 ⇒ 空集是未判不是通过。补件或改落点（`常量.py` 的 `接口面件`）"
            "⇒ 只能由该件的作者处置",
        )
        return 输出缓冲
    项表, 错误 = 案例布局可比项(上层读数)
    if 错误:
        return [
            违规(
                检查名[46],
                案例形状文档,
                错误,
                "案例布局的**真源在库 `条款` 表**（`测试验证/案例/形状.md` §一）—— md 已全量"
                "入库并删净，Rust 侧 import 不到 ⇒ 只能由判据对读。读不动就判不了。"
                "修法：把规则库补上（`python3 开发工具/信息核心/信息核心.py 建库`）"
                "⇒ 只能由维护方补",
            )
        ]
    if not 项表:
        判不了(
            检查名[46],
            接口面件,
            "案例布局项一条都取不到（`案例根` / `案例回执件` / `案例声明件` 全没读到）"
            "—— 也可能是**解析器坏了**（正则认不出 `pub const …: &str = …;`）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。修法：查本件 `_取Rust串常量` "
            "的正则，或确认那件确实还写着这几条常量 ⇒ 只能由判据作者确认",
        )
        return 输出缓冲
    for 布局名, 布局值, 正文 in 项表:
        if 布局值 not in 正文:
            输出缓冲.append(
                违规(
                    检查名[46],
                    f"{接口面件}::{布局名}",
                    f"案例布局 `{布局名}` = {布局值!r} 不在库 `条款` 的 `{案例形状文档}` §一里",
                    "同一事实（案例目录布局：根 · 回执件 · 案例声明件）在**文档与代码**两处各写"
                    "一份：真源在库 `条款` 表（md 已入库删净，Rust 不能 import），而"
                    "`v1-case-runner` 又是 bin-only（网关无法反向依赖）⇒ 只能由本判据钉住。"
                    "改一处不改另一处就漂 ⇒ 以哪侧为准要按契约 ⇒ 改哪边只能由两侧的作者定",
                )
            )
    return 输出缓冲
