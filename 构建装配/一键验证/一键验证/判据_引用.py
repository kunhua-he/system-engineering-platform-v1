# -*- coding: utf-8 -*-
r"""判据 ㊴：`路径 §节名` 引用可解析 —— 全树凡 `<名>.md §<节号>` 的引用，目标件里必须存在该节。

依据：`项目文档/决策记录/2026-09-27_判据口径十一条.md` §十 · `项目文档/开发规范/开发规范.md` §八 ·
判据 ⑮（引用的**格式**）。

**为什么要这一条**：判据 ⑮ 只禁**按行号**引用、只规定引用的**格式**（源码 `路径::符号名` ·
文档 `路径 §节名`），**不判引用能不能解析到**。2026-09-28 文档瘦身删掉一批 `##` 节之后，
引用方（在 `.rs` · `.py` · `.json` · `.js` 与别的 `.md` 里）指向已不存在的节号 ——
而闸 0 全绿、无一处报红。把口径变成常驻判据 ⇒ 引用一出现就红，不必等下一次批次清存量。

**形状照抄判据 ㉒**（`判据_命名.检查22_命名防回潮`）：基线文件 + 三条 ——
① 新增（基线里没有）⇒ 红 ② 基线里不许留**陈旧登记**（登记着却已不出现）⇒ 红。
**基线只许减**（引用的目标节补回 / 重指到存活权威后删登记，不许留）。
基线件 `引用基线.json`；读不到它就 fail-closed 报红。

**扫描面**：全树**含未跟踪件**（后缀 `.md`/`.rs`/`.py`/`.json`/`.js`/`.toml`；排除
`只读参考/` · `构建环境/` · `.git/` · `.codegraph/`）。解析口径（紧邻门 · 任一候选 · 自引用 ·
件名三级匹配 · 判不了跳过）全在 `引用扫描.py`，**一处实现**（本件不重写它）。

三元读数：**通过** = 扫描面非空且无新增/陈旧；**失败** = 逐条报出；
**未判** = 扫描面下 0 处可判的引用（那说明扫描面或解析器坏了，不是「没问题」）。
"""
from __future__ import annotations

from .小工具 import 判不了, 违规
from .常量 import 检查名, 排除目录
from .引用扫描 import 扫引用
from .判据基线 import 读引用基线, 库相对路径

# 基线**住规则库**（`引用基线` 表）—— 不再落外部 json（华哥 2026-09-29）。判据读不到库就
# fail-closed 报红 —— 「存量入基线」要求先有存量清单，没有它，实测的全部存量会被当成「新增」。
引用基线路径 = 库相对路径

# 扫描后缀（口径书点名的六个）与排除片段。片段形态**由段形态主人派生**（`常量.排除目录`
# ← `开发工具/代码地图/落点.py::排除目录`）—— 2026-09-30 收口：原先四份各写一份清单。
引用后缀 = (".md", ".rs", ".py", ".json", ".js", ".toml")
_排除路径片段 = tuple(f"/{目录名}/" for 目录名 in 排除目录)

# 扫描面 / 扫一遍的结果都在一次运行里不变（判定与对象数各取一次）⇒ 按仓根缓存
# （同 判据 ㊲/㊳ 的先例）。不跨调用复用：`--自测` 的注入发生在两次 `验证` 之间。
引用面缓存: dict = {}
_扫缓存: dict = {}


def 引用面(上层读数: dict) -> dict:
    """扫描面：全树**非排除目录**下、后缀在 `引用后缀` 里、且读到文本的件 ⇒ `{路径: 文本}`。"""
    键名 = str(上层读数["仓根"])
    if 键名 in 引用面缓存:
        return 引用面缓存[键名]
    扫描面 = {}
    for 路径, 一项 in 上层读数["文件"].items():
        文本 = 一项.get("文本")
        if 文本 is None or not 路径.endswith(引用后缀):
            continue
        if any(片段 in "/" + 路径 for 片段 in _排除路径片段):
            continue
        扫描面[路径] = 文本
    引用面缓存[键名] = 扫描面
    return 扫描面


def 扫引用面(上层读数: dict) -> tuple:
    """扫一遍扫描面 ⇒ `(悬空表, 判过处数)`（按仓根缓存）。"""
    键名 = str(上层读数["仓根"])
    if 键名 not in _扫缓存:
        _扫缓存[键名] = 扫引用(引用面(上层读数))
    return _扫缓存[键名]


def 样本_引用面(上层读数: dict) -> int:
    """对象数：扫描面下**真判过**的引用处数（0 ⇒ 未判：解析器坏了也是 0 处，两者必须分得开）。"""
    return 扫引用面(上层读数)[1]


def 检查39_引用可解析(上层读数: dict) -> list:
    """`路径 §节名` 引用可解析：存量入基线、新增即红、基线只许减。

    三元读数：**通过** = 扫描面非空且无新增/陈旧；**失败** = 逐条报出；
    **未判** = 扫描面下 0 处可判的引用（解析器坏了也是 0 处）。
    """
    输出缓冲 = []
    悬空表, 判过 = 扫引用面(上层读数)
    if not 判过:
        判不了(
            检查名[38],
            " · ".join(引用后缀),
            "扫描面下 0 处可判的引用（一件都没有的仓天然是绿的，那不是本条判据的功劳；"
            "也可能是**解析器坏了**：`引用扫描.py` 的 `件名式`/`节式`/`候选件` 一坏就恒为 0）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。修法：查 "
            "`构建装配/一键验证/一键验证/引用扫描.py` 的三条式与 `候选件` 三级匹配",
        )
        return 输出缓冲

    基线表, 错误 = 读引用基线(上层读数["仓根"])
    if 错误:
        return [
            违规(
                检查名[38],
                引用基线路径,
                错误,
                "「存量入基线、新增即红」要求先有存量清单（同判据 ㉒ 的形状）；没有它，"
                "实测的全部存量会被算成「新增」⇒ 判据当场红一片，等于没上闸。"
                "基线只能由**声明方**登记（谁欠的债谁登记）⇒ 只能由维护方补",
            )
        ]

    实测键 = {(本件, 件名, 节号) for 本件, _行号, 件名, 节号, _原文 in 悬空表}
    口径 = (
        "判据 ⑮ 只规定了引用的**格式**（`路径 §节名`），不判它能不能解析到；"
        "而目标件里没有这个节 ⇒ 读者照它去找**找不到**，然后不信判据（`判据的可信性.md` 第六节）。"
        "修法：把引用**重指到存活权威**（补回被删的节 / 改指那个内容现在的所在节），"
        "**不许把一个号换成另一个号**（那只是把悬空换个地方）⇒ 改指哪一处只有该件的作者能定"
    )
    for 本件, 行号, 件名, 节号, 原文 in 悬空表:
        if (本件, 件名, 节号) in 基线表:
            continue
        输出缓冲.append(
            违规(
                检查名[38],
                f"{本件}:{行号}",
                f"引用 `{件名} §{节号}` 解析不到（目标件里没有这个节；原文：{原文}）⇒ **新增即红**",
                口径,
            )
        )

    # ── 基线里不许留**陈旧登记**（与判据 ㉒/⑲ 同一条）──
    for 件路径, 件名, 节号 in sorted(基线表):
        if (件路径, 件名, 节号) in 实测键:
            continue
        输出缓冲.append(
            违规(
                检查名[38],
                f"{件路径}::{件名} §{节号}",
                f"基线登记着这处悬空（`{件名} §{节号}`），而实测这一处**已经不出现** ⇒ **陈旧登记**",
                "「基线只许减」：引用的目标节补回 / 重指到存活权威之后就该把登记删掉。留着它，"
                f"基线读数就不再是现状（读的人会以为债还在）⇒ 只能由维护方删（{引用基线路径}）",
            )
        )
    return 输出缓冲
