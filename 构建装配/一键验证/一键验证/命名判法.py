"""命名判法 —— 判据 A/B/C/D 的**唯一判定实现**（读侧闸 0 与写侧登记口共用一份）。

依据：库 `规则` 表 命名口径-20（同义异名）· 命名口径-21（重复登记）· 命名口径-22（一名多义）·
命名口径-27（取名先归族、名须合词性）。华哥 2026-10-05 裁定：命名规则一律强制、一律走闸门 ——
**同一份判法，两个挂点**：闸 0（读侧，拦存量回潮）+ 登记口（写侧，拦新写的坏名）。

四条判据的面与判法**只在本件写一次**；判据 A/B/C/D 与 `登记.py` 的写盘闸都调它，不许各写一套。

★ 面：A/B 的面是**库 `命名定义`**（名册）· C 的面是名册 × 代码地图索引 · D 的面是名册。
  库侧全是 `select`（毫秒级）—— 正是华哥说的「db 过闸门，本质上是快速的索引」。
"""
from __future__ import annotations

import bisect
import difflib
import re
import sqlite3
from pathlib import Path

from .判据基线 import 库相对路径
from .判据_命名_口径 import 数量代称式

# D · 词性组合三档的档名（基线表 `命名词性基线` 的 `档` 栏也用它）。
档_缺宾语 = "缺宾语"
档_量名无对象 = "量名无对象"
档_缺限定词 = "缺限定词"

# D · 词性组合的**机械词表**（口径见 `命名口径-27` 与《词性组合式表》）。
# ★ 只收**整名就是一个词**的形状：光杆动词（切不出宾语）· 无限定词的泛指承载物。
#   闭集 = 机械代理；语义结论（人判）住库 `规则`，新形状由评审兜。
光杆动词表 = frozenset(("解析", "生成", "检查", "编译", "自测", "抽干"))
泛指承载物表 = frozenset(("数据", "结果", "引用", "全部", "登记", "扩展根"))

_名分隔符 = re.compile(r"[·、/,]")
_归一待删符 = re.compile(r"[`\s·]")
_旧编号形状 = (
    re.compile(r"_\d+$"),
    re.compile(r"[一二三四五六七八九十]$"),
    re.compile(r"^真形状\d"),
    re.compile(r"^夹具[一二三四五六七八九十]"),
)


def _读行(树根, 语句: str) -> tuple:
    """只读跑一条 select ⇒ `(行表, 错误或 None)`（读不动交错误回去，不抛）。"""
    库件 = Path(树根) / 库相对路径
    if not 库件.is_file():
        return [], f"规则库不在（{库件}）"
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            return list(连接.execute(语句)), None
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return [], f"读不动：{错误}"


def 读命名定义(树根) -> tuple:
    """⇒ `([(语义, 唯一名, 现状)], 错误或 None)`（A/B/C/D 的公共对象）。"""
    return _读行(树根, "select 语义,唯一名,现状 from 命名定义")


def 读命名例外(树根) -> tuple:
    """⇒ `({名}, 错误或 None)`。"""
    行表, 错误 = _读行(树根, "select 名 from 命名例外")
    if 错误:
        return set(), 错误
    return {一行[0] for 一行 in 行表}, None


def 读同义已裁(树根) -> tuple:
    """⇒ `({(前名, 后名): 裁决}, 错误或 None)`（C 的 ⑤ 人判结论 + 存量）。"""
    行表, 错误 = _读行(树根, "select 前名,后名,裁决 from 命名同义已裁")
    if 错误:
        return {}, 错误
    return {(一行[0], 一行[1]): (一行[2] or "") for 一行 in 行表}, None


def 归一语义(文本: str) -> str:
    """去反引号 / 空白 / `·` —— 判「真子串包含」的归一（口径 = 命名口径-21）。"""
    return _归一待删符.sub("", 文本 or "")


def 拆唯一名(唯一名: str) -> list:
    """`唯一名` 栏 ⇒ 名表（按 `·` / `、` / `,` / `/` 拆，去反引号）。"""
    名字表 = []
    for 一片 in _名分隔符.split(唯一名 or ""):
        出现名 = 一片.strip().strip("`")
        if 出现名:
            名字表.append(出现名)
    return 名字表


def 是旧编号形(文本: str) -> bool:
    """旧编号形（`夹具四` / `真形状4` / `_数字尾` / 中文数词尾）⇒ 改号遗留的重复登记。"""
    return any(编号式.search(文本 or "") for 编号式 in _旧编号形状)


def 重复登记(行表: list) -> dict:
    """A · 重复登记：同一 `唯一名`（整串为键）的 ≥2 行语义里，∃ 两语义真子串包含。

    ⇒ `{唯一名整串: [(语义前, 语义后), …]}`（空表 = 无重复登记）。
    """
    按名 = {}
    for 语义, 唯一名, _现状栏 in 行表:
        按名.setdefault(唯一名, []).append(语义 or "")
    命中 = {}
    for 唯一名, 同义语义表 in 按名.items():
        if len(同义语义表) < 2:
            continue
        包含对表 = []
        for 左序号 in range(len(同义语义表)):
            for 右序号 in range(len(同义语义表)):
                if 左序号 == 右序号:
                    continue
                语义前, 语义后 = 归一语义(同义语义表[左序号]), 归一语义(同义语义表[右序号])
                if 语义前 and 语义前 != 语义后 and 语义前 in 语义后:
                    包含对表.append((同义语义表[左序号], 同义语义表[右序号]))
        if 包含对表:
            命中[唯一名] = 包含对表
    return 命中


def 一名多义(行表: list) -> dict:
    """B · 一名多义：同一 `唯一名` 的 ≥2 行语义所指不同（剔 子串包含 / 旧编号形 / 相似度 ≥0.6）。

    ⇒ `{唯一名整串: [语义, …]}`（空表 = 无真多义）。
    """
    重复表 = 重复登记(行表)
    按名 = {}
    for 语义, 唯一名, _现状栏 in 行表:
        按名.setdefault(唯一名, []).append(语义 or "")
    命中 = {}
    for 唯一名, 同义语义表 in 按名.items():
        if len(同义语义表) < 2 or 唯一名 in 重复表 or 是旧编号形(唯一名):
            continue
        归一表 = [归一语义(语义项) for 语义项 in 同义语义表]
        if any(not 归一文本 for 归一文本 in 归一表):
            continue
        最小相似度 = min(
            difflib.SequenceMatcher(None, 归一表[左序号], 归一表[右序号]).ratio()
            for 左序号 in range(len(归一表)) for 右序号 in range(左序号 + 1, len(归一表))
        )
        if 最小相似度 >= 0.6:
            continue
        命中[唯一名] = 同义语义表
    return 命中


def 顶层区(路径: str) -> str:
    """路径的顶层区（第一段目录名）。"""
    return (路径 or "").split("/", 1)[0]


def 同义候选(行表: list, 索引定义表: list) -> list:
    """C · 同义异名候选（机械 ①②③④；⑤ 同所指是人判，结论住库 `命名同义已裁`）。

    面 = 名册（`命名定义` 的唯一名）× 代码地图索引（名 → 件集 / 种类 / 有无主）。
    机械四条：① 前名是后名的正前缀（`命名口径-20` 的可机判近似）；② 同种类；
    ③ 两名定义件同属一个顶层区；④ 无一件同时定义两名（件集不相交）。
    ⇒ `[(前名, 后名), …]`（空表 = 无候选）。
    """
    名集 = set()
    for _语义, 唯一名, _现状栏 in 行表:
        名集.update(拆唯一名(唯一名))
    名序 = sorted(名集)
    名到件集, 名到种类, 有主名集 = {}, {}, set()
    for 索引条 in 索引定义表:
        名字 = 索引条.get("名字", "")
        名到件集.setdefault(名字, set()).add(索引条.get("路径", ""))
        名到种类.setdefault(名字, set()).add(索引条.get("种类", ""))
        限定名 = 索引条.get("限定名") or ""
        if "::" in 限定名 or "." in 限定名:
            有主名集.add(名字)
    候选表 = []
    # ★ 性能：名序已排序 ⇒ 用**前缀区间**（二分）取「以 前名 开头」的名，不再对全部名双重循环
    #   （实测 6735 名双重循环 6304 ms，把闸 0 顶过硬顶；前缀区间后 34 ms）。
    for 前名 in 名序:
        if len(前名) < 2 or 前名 in 有主名集:
            continue
        起点 = bisect.bisect_left(名序, 前名)
        终点 = bisect.bisect_left(名序, 前名 + "\U0010ffff")
        for 后名 in 名序[起点:终点]:
            if 后名 == 前名:
                continue
            余段 = 后名[len(前名):]
            if re.match(r"_?\d", 余段) or len(余段) > 3 or 后名 in 有主名集:
                continue
            件集前, 件集后 = 名到件集.get(前名, set()), 名到件集.get(后名, set())
            if not 件集前 or not 件集后 or 件集前 & 件集后:
                continue
            if not (名到种类.get(前名, set()) & 名到种类.get(后名, set())):
                continue
            if not ({顶层区(路径) for 路径 in 件集前} & {顶层区(路径) for 路径 in 件集后}):
                continue
            候选表.append((前名, 后名))
    return 候选表


def 词性违规(名集: set) -> list:
    """D · 词性组合（三档机械判法）⇒ `[(名, 档), …]`。

    ① 缺宾语：整名就是一个光杆动词（`解析` ⇒ 动作族却切不出宾语）；
    ② 量名无对象：整名 = 数词 + 量词（说「几个」不说「是什么」）；
    ③ 缺限定词：整名是一个无限定词的泛指承载物（`数据` `结果`）。
    """
    命中 = []
    for 名称 in sorted(名集):
        if 名称 in 光杆动词表:
            命中.append((名称, 档_缺宾语))
        elif 数量代称式.fullmatch(名称):
            命中.append((名称, 档_量名无对象))
        elif 名称 in 泛指承载物表:
            命中.append((名称, 档_缺限定词))
    return 命中
