# 判据的身份证（判据的可信性.md 第五节 · 第六节）
#
# 每条判据必须成对：反向样本（注入一个该抓的违规 ⇒ 必须报红且报对位置与原因）
# + 正向样本（一份干净输入 ⇒ 必须通过）。缺任一方 ⇒ 该判据「未验证」，
# 它的「通过」不计入通过数。
# 扫描面：判据声明它扫哪些路径与文件类型；判据自身的对象数为 0 时报
# 「扫描 0 项」= 未判（空集不算通过）。
#
# ★ **新增判据 / 给已有判据扩面（换面 · 加档），必须同时补反向样本** —— 扩面是「首冻放行」，
#   没有反向样本钉住，判据死了没人知道。
