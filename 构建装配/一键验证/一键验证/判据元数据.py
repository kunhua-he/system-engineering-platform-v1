def _样本_编号文件(上层读数):
    return sum(len(记录表) for 记录表 in 上层读数["编号表"].values())


def _样本_号段图(上层读数):
    号段图 = 上层读数["号段图"] or {}
    return sum(len(号段图.get(节键) or []) for 节键 in 号段图四节)


def _样本_能力声明(上层读数):
    return len(上层读数["编号表"]["能力声明"])


def _样本_错误码表(上层读数):
    return len(上层读数["编号表"]["错误码表"])


def _样本_通知号段(上层读数):
    return len(上层读数["编号表"]["通知号段"])


def _样本_冻结项(上层读数):
    冻结登记 = 上层读数["冻结"] or {}
    一项 = 冻结登记.get("冻结项")
    return len(一项) if isinstance(一项, list) else 0


def _样本_底座源文件(上层读数):
    return sum(
        1
        for 键名 in 上层读数["文件"]
        if 键名.endswith(".rs") and not 键名.startswith("扩展根目录/")
    )


def _样本_时间口径面(上层读数):
    """判据 ㉑ 的对象数：时间口径两个主人下的 `.rs` 件数（0 个 ⇒ 报未判，不报通过）。"""
    return sum(
        1 for 键名 in 上层读数["文件"]
        if 键名.endswith(".rs") and any(键名.startswith(扫描面 + "/") for 扫描面 in 时间口径面)
    )


def _样本_代码文件(上层读数):
    return sum(1 for 键名 in 上层读数["文件"] if 键名.endswith((".rs", ".py", ".ts", ".js", ".vue")))


def _样本_扩展目录(上层读数):
    return sum(
        1
        for 键名 in 上层读数["文件"]
        if 键名.endswith("Cargo.toml")
        and len(键名.split("/")) >= 4
        and 键名.split("/")[0] == "扩展根目录"
        and 键名.split("/")[1] in 扩展根三类
    )


def _样本_常量(上层读数):
    项表 = 上层读数["常量表"] or {}
    常量条目表 = 项表.get("常量")
    return len(常量条目表) if isinstance(常量条目表, list) else 0


def _样本_判据(上层读数):
    return len(上层读数.get("判据元数据覆盖") or 判据元数据)


def _样本_文档脚本(上层读数):
    """判据 ⑮ 的对象数：扫描面下的 `.md` / `.py` / `.rs` 件数（0 个 ⇒ 报未判，不报通过）。"""
    return sum(
        1
        for 键名, 一项 in 上层读数["文件"].items()
        if 键名.endswith(行号引用后缀) and 一项.get("文本") is not None
    )


def _样本_底座代码件(上层读数):
    """判据 ⑯ 的对象数：底座代码面下的代码件数（0 个 ⇒ 报未判，不报通过）。

    口径与 检查16 的扫描件源逐字一致（同一处定义），否则对象数会与判据实际扫的面漂移。
    """
    return sum(
        1
        for 键名, 一项 in 上层读数["文件"].items()
        if 一项.get("文本") is not None
        and 键名.endswith(代码后缀)
        and 键名.split("/")[0] in 底座代码树
        and not 键名.startswith(底座代码面排除)
    )


def _样本_仓树条目(上层读数):
    """判据 ⑰ 的对象数：源码树里被走到的条目数（目录 + 文件，排除 `.git`）。

    口径与 检查17 的实际遍历一致（它走全树，不看后缀）；0 个 ⇒ 报未判，不报通过。
    """
    仓根 = 上层读数["仓根"]
    条目个数 = 0
    for 根目录, 目录表, 文件表 in os.walk(仓根):
        目录表[:] = [目录名 for 目录名 in 目录表 if 目录名 != ".git"]
        条目个数 += len(目录表) + len(文件表)
    return 条目个数


def _样本_行数面(上层读数):
    """判据 ⑲ 的**对象数**：扫到的源码文件数（`.rs`/`.py`/`.js`/`.css`/`.html`/`.sh`/`.swift`）。

    与判定**同一处实现**（`开发工具/查文件行数/核心.py::收集源码`）—— 样本清单手写一份就是
    第二个事实源（判据的可信性.md §三.3）。为 0 ⇒ 报「扫描 0 项」= 未判（空集不算通过）。
    """
    try:
        return len(_行数工具(上层读数).收集源码(上层读数["仓根"]))
    except Exception:
        return 0


def _样本_本命令(上层读数):
    """判据 ⑱ 的**对象数**：被计量的命令条数 —— **恒为 1，不是扫描集**。

    ★ 这是本项目里唯一一条对象数不是「扫描集元素数」的判据，故在此说清：
      判据 ⑱ 的对象是「**本命令的这一次完整运行**」这**一个**对象（命令级硬顶，
      决策记录 §一「计量对象 = 一条命令的完整墙钟」），不是「扫了多少个文件」。
      所以它的对象数恒为 1：>0 ⇒ 本判据真判了（不会掉进「扫描 0 项 = 未判」）。
      它读的是**时钟**，不读文件 —— `扫描面` 那一栏按框架要求声明（检查14 ③ 要它非空），
      声明成「本命令所在的构建装配面」，**不代表本判据会去扫那些文件**。
    """
    return 1


