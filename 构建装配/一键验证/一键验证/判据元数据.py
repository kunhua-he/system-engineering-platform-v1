def _样本_编号文件(上):
    return sum(len(v) for v in 上["编号表"].values())


def _样本_号段图(上):
    图 = 上["号段图"] or {}
    return sum(len(图.get(k) or []) for k in 号段图四节)


def _样本_能力声明(上):
    return len(上["编号表"]["能力声明"])


def _样本_错误码表(上):
    return len(上["编号表"]["错误码表"])


def _样本_通知号段(上):
    return len(上["编号表"]["通知号段"])


def _样本_冻结项(上):
    冻 = 上["冻结"] or {}
    项 = 冻.get("冻结项")
    return len(项) if isinstance(项, list) else 0


def _样本_底座源文件(上):
    return sum(
        1
        for 键 in 上["文件"]
        if 键.endswith(".rs") and not 键.startswith("扩展根目录/")
    )


def _样本_时间口径面(上):
    """判据 ㉑ 的对象数：时间口径两个主人下的 `.rs` 件数（0 个 ⇒ 报未判，不报通过）。"""
    return sum(
        1 for 键 in 上["文件"]
        if 键.endswith(".rs") and any(键.startswith(面 + "/") for 面 in 时间口径面)
    )


def _样本_代码文件(上):
    return sum(1 for 键 in 上["文件"] if 键.endswith((".rs", ".py", ".ts", ".js", ".vue")))


def _样本_扩展目录(上):
    return sum(
        1
        for 键 in 上["文件"]
        if 键.endswith("Cargo.toml")
        and len(键.split("/")) >= 4
        and 键.split("/")[0] == "扩展根目录"
        and 键.split("/")[1] in 扩展根三类
    )


def _样本_常量(上):
    表 = 上["常量表"] or {}
    条 = 表.get("常量")
    return len(条) if isinstance(条, list) else 0


def _样本_判据(上):
    return len(上.get("判据元数据覆盖") or 判据元数据)


def _样本_文档脚本(上):
    """判据 ⑮ 的对象数：扫描面下的 `.md` / `.py` / `.rs` 件数（0 个 ⇒ 报未判，不报通过）。"""
    return sum(
        1
        for 键, 项 in 上["文件"].items()
        if 键.endswith(行号引用后缀) and 项.get("文本") is not None
    )


def _样本_底座代码件(上):
    """判据 ⑯ 的对象数：底座代码面下的代码件数（0 个 ⇒ 报未判，不报通过）。

    口径与 检查16 的扫描件源逐字一致（同一处定义），否则对象数会与判据实际扫的面漂移。
    """
    return sum(
        1
        for 键, 项 in 上["文件"].items()
        if 项.get("文本") is not None
        and 键.endswith(代码后缀)
        and 键.split("/")[0] in 底座代码树
        and not 键.startswith(底座代码面排除)
    )


def _样本_仓树条目(上):
    """判据 ⑰ 的对象数：源码树里被走到的条目数（目录 + 文件，排除 `.git`）。

    口径与 检查17 的实际遍历一致（它走全树，不看后缀）；0 个 ⇒ 报未判，不报通过。
    """
    仓根 = 上["仓根"]
    数 = 0
    for 根, 目录表, 文件表 in os.walk(仓根):
        目录表[:] = [d for d in 目录表 if d != ".git"]
        数 += len(目录表) + len(文件表)
    return 数


def _样本_行数面(上):
    """判据 ⑲ 的**对象数**：扫到的源码文件数（`.rs`/`.py`/`.js`/`.css`/`.html`/`.sh`/`.swift`）。

    与判定**同一处实现**（`开发工具/查文件行数/核心.py::收集源码`）—— 样本清单手写一份就是
    第二个事实源（判据的可信性.md §三.3）。为 0 ⇒ 报「扫描 0 项」= 未判（空集不算通过）。
    """
    try:
        return len(_行数工具(上).收集源码(上["仓根"]))
    except Exception:
        return 0


def _样本_本命令(上):
    """判据 ⑱ 的**对象数**：被计量的命令条数 —— **恒为 1，不是扫描集**。

    ★ 这是本项目里唯一一条对象数不是「扫描集元素数」的判据，故在此说清：
      判据 ⑱ 的对象是「**本命令的这一次完整运行**」这**一个**对象（命令级硬顶，
      决策记录 §一「计量对象 = 一条命令的完整墙钟」），不是「扫了多少个文件」。
      所以它的对象数恒为 1：>0 ⇒ 本判据真判了（不会掉进「扫描 0 项 = 未判」）。
      它读的是**时钟**，不读文件 —— `扫描面` 那一栏按框架要求声明（检查14 ③ 要它非空），
      声明成「本命令所在的构建装配面」，**不代表本判据会去扫那些文件**。
    """
    return 1


