# -*- coding: utf-8 -*-
"""命名面 —— 判据 ㉒ 里**索引看不见的那两层**（形参面 · 局部绑定面）。

**为何单开一件**：判据 ㉒ 的四个档里，前两档吃**索引的定义面**（`读索引定义` / `数命中`），
后两档吃**本包自身扫的面** —— 两件事关注点不同，混在一件里会把 `判据_命名.py` 顶过 400 行
硬数（`开发规范.md` §六）。故后两档连同它们的惰性入口搬到这里。

**面各只一份**（本件只是入口，不复制实现）：
  · 形参面 —— `开发工具/代码地图/形参面.py`（与 `代码地图.py 检形参` 同读它）；
  · 局部绑定面 —— 本包的 `命名扫描.扫局部绑定`（剥注释与字符串只此一份）。

**为何这两面非有不可**：索引的**定义面不收形参、也不收局部名**（#226 实测：codegraph
不索引 Rust 的 `let` 局部）⇒ 只判前两档的话，新写一个单字形参或 `let i = 1;` **不报红**
（`检名` 也看不见）—— 那是静默回潮。

依据：`项目文档/决策记录/2026-09-27_命名规范.md` §四.2 · §八.11。
"""

from . import 常量


def 取查名():
    """惰性取**命名规范的口径**（`开发工具/代码地图/查名.py`）—— 规则只此一份。

    取法照判据 ⑲ 引 `开发工具/查文件行数/核心.py` 的先例：**工具从「判据自身所在的仓」取**，
    不从被扫的仓取（夹具仓没有这些工具）。
    """
    import sys as _sys

    根目录 = str(常量.仓根目录 / "开发工具")
    if 根目录 not in _sys.path:
        _sys.path.insert(0, 根目录)
    import 代码地图.查名 as 查名

    return 查名


def 取形参面():
    """惰性取**形参面的扫描器**（`开发工具/代码地图/形参面.py`）。

    **面只此一份**：第三档与 `python3 开发工具/代码地图.py 检形参` 同读它，不许各写一套。
    """
    import sys as _sys

    根目录 = str(常量.仓根目录 / "开发工具")
    if 根目录 not in _sys.path:
        _sys.path.insert(0, 根目录)
    import 代码地图.形参面 as 形参面

    return 形参面


def 取命名扫描():
    """惰性取**局部绑定面的解析器**（本包的 `命名扫描.py`）—— 剥注释与字符串只此一份。

    本件**不另写剥器**（同一条口径两套代码 = 第二个事实源，早先 `_正则前缀` 就是这么漂的
    —— 见 `命名扫描.py` 里那段收口记）。
    """
    from . import 命名扫描

    return 命名扫描


def 逐命名件(上层读数: dict):
    """产出 `(路径, 文本)` —— 扫描面里的命名件（按 `查名.命名后缀` 筛）。

    **两个面共用这一道筛**（同一份面口径，不各写一遍）。
    """
    后缀 = 取查名().命名后缀
    for 路径, 一项 in 上层读数["文件"].items():
        文本 = 一项.get("文本")
        if 文本 is not None and 路径.endswith(后缀):
            yield 路径, 文本


def 数形参单字(上层读数: dict) -> tuple:
    """**形参面**（索引看不见的那一层）⇒ `(命中, 件数)`。

    命中 = `{(路径, 形参名): 处数}`；件数 = 面下**有函数头**的件数（**判空集用** ——
    扫描器坏了也是 0 命中，两者必须分得开）。

    面 = `取形参面()`：`.rs`/`.py` 的 `fn`/`def` 签名（**多行也认**）＋ JS 箭头 / 回调 / 闭包。
    文本取自 `上["文件"]`（与其余判据同一份面 ⇒ 夹具仓照跑，不需另造索引）。
    """
    形参面 = 取形参面()
    命中: dict = {}
    件数 = 0
    for 路径, 文本 in 逐命名件(上层读数):
        if 形参面.有函数头(路径, 文本):
            件数 += 1
        for _行, _函数名, 形参名 in 形参面.扫文本(路径, 文本):
            键名 = (路径, 形参名)
            命中[键名] = 命中.get(键名, 0) + 1
    return 命中, 件数


def 数局部单字(上层读数: dict) -> tuple:
    """**局部绑定面**（索引与形参面都看不见的那一层）⇒ `(命中, 件数)`。

    命中 = `{(路径, 名): 处数}`；件数 = 面下**有局部绑定**的件数（**判空集用** ——
    扫描器坏了也是 0 命中，两者必须分得开）。

    面 = `取命名扫描().扫局部绑定`：剥注释与字符串后抽 `let` / `let mut` / `for … in`（Rust）·
    语句首纯赋值 / `for … in`（Python）· `let`/`const`/`var` / `catch (名)`（JS）。
    """
    命名扫描 = 取命名扫描()
    命中: dict = {}
    件数 = 0
    for 路径, 文本 in 逐命名件(上层读数):
        件后缀 = "." + 路径.rsplit(".", 1)[-1]
        if 命名扫描.有局部绑定(件后缀, 文本):
            件数 += 1
        for _行, 绑定名 in 命名扫描.扫局部绑定(件后缀, 文本):
            命中键 = (路径, 绑定名)
            命中[命中键] = 命中.get(命中键, 0) + 1
    return 命中, 件数
