def 自检_前端语义判据() -> list:
    """⑪ 判据 6（前端零逻辑）**从词命中改成语义判**后的身份证（2026-09-27 收窄）。

    为什么单列：原模式 `JSON\\.parse|JSON\\.stringify|校验|解析|生成|validate|parse\\(` 是一袋词，
    它把 `前端呈现/网页应用/取接口.js` 里**传输必需的 `JSON.stringify(文本)`** 判成了违规
    收窄最怕**收过头**：把真解析一起放过 ⇒ 判据变成空转。
    故成对钉三层：
      · **反向样本**：注入一处**真 `JSON.parse`** ⇒ ⑪ 必须报红、且指到注入件；
      · **正向样本**：注入 `JSON.stringify` / 一段**解释自身不是违规的注释** / 纯拼接搬运 ⇒ 不许报红；
      · **#38 残留（正则字面量）**：源码里的 `/JSON.parse(/` 这类正则字面量 ⇒ 不许报
        （字面量的内容是数据）——修法在**剥离层**（`剥字面量._剥注释与串` 认 `/…/flags` 并剥掉）；
        成对钉：真的 `JSON.parse(` 调用 ⇒ 必报、字面量的调用形（`.test(` / `new RegExp(`）⇒ 仍报。
      · **承重证明（关/开对照）**：把判据临时关掉（模式换成永不匹配）再注入**同一处真解析**
        ⇒ 必须不报 —— 证明那处红**确实由本判据承重**，不是别的判据顺带报的。
    依据：项目文档/设计文档/判据的可信性.md §三.5（判据的解析器/模式也是假绿来源）。
    """
    import tempfile

    输出缓冲 = []
    注入件 = "前端呈现/网页应用/注入样例.js"

    def 断言(名称, 合格样本, 说明):
        输出缓冲.append((名称, 合格样本, 说明))

    # ── 第一层：纯文本（快，直接钉模式本身；样本取自现场实测的形状）──
    真解析 = 'export function 取值(文) { return JSON.parse(文); }\n'
    序列化 = 'export function 编码(文) { return JSON.stringify(文); }\n'
    辩解注释 = (
        "// `JSON.stringify` 只做编码：把文本编成 JSON 字面量，不改内容、不看内容。\n"
        "// 这里不解析、不校验 —— 任何判断都在后端。\n"
        "export function 编码(文) { return JSON.stringify(文); }\n"
    )
    搬运 = 'export function 拼(号, 文) { return "{" + 号 + ":" + 文 + "}"; }\n'
    词袋 = re.compile(r"JSON\.parse|JSON\.stringify|校验|解析|生成|validate|parse\(")

    def 命中(源文本, 模式=None):
        return [匹配结果.group(0) for 匹配结果 in (模式 or 常量.前端逻辑模式).finditer(生产区文本(源文本))]

    断言(
        "反向样本：真 `JSON.parse` ⇒ 新模式报（解析 = 对内容作出判断）",
        bool(命中(真解析)),
        f"命中 {命中(真解析)}（要求非空）",
    )
    断言(
        "正向样本：`JSON.stringify` ⇒ 新模式不报（序列化是传输必需的编码）",
        not 命中(序列化),
        f"命中 {命中(序列化)}（要求空）——它不看内容、不改内容",
    )
    断言(
        "正向样本：一段「解释自身不是违规」的注释 ⇒ 新模式不报",
        not 命中(辩解注释),
        f"命中 {命中(辩解注释)}（要求空）——#176 的病灶就在这里",
    )
    断言(
        "对照：同一份文本，**原词袋模式**报（证明收窄真治了那个病）",
        bool(命中(辩解注释, 词袋)) and not 命中(辩解注释),
        f"原模式命中 {命中(辩解注释, 词袋)} · 新模式命中 {命中(辩解注释)}",
    )
    断言(
        "正向样本：纯拼接搬运（编码传输串）⇒ 不报",
        not 命中(搬运),
        f"命中 {命中(搬运)}（要求空）——纯搬运/编码允许",
    )
    断言(
        "反向样本：正则**字面量本身**（赋给标识符 / 作实参 / `return` / 对象属性值 / 数组元素 / 三元分支 / 箭头体）⇒ 不报",
        not any(
            命中(样本)
            for 样本 in (
                "const 形 = /^[0-9]+$/;\n",
                "export function 判(s, 另) { return 查(s, /^[0-9]+$/); }\n",
                "const 表 = { 模式: /^[0-9]+$/ };\n",
                "const 表 = [/^[0-9]+$/, /^[a-z]+$/];\n",
                "export function 取(x) { return x ? /^[0-9]+$/ : /^[a-z]+$/; }\n",
                "const 判 = (s) => /^[0-9]+$/;\n",
            )
        ),
        "六种值位置各 0 处（要求全空）——字面量是**数据**：#38 的病灶正是把字面量里的字样当成逻辑",
    )
    断言(
        "正向样本：**除法**与含 `//` 的字符串/注释 ⇒ 不报（值位置的口径不许误伤它们）",
        not any(
            命中(样本)
            for 样本 in (
                "export function 比(a, b) { return a / b; }\n",
                "export function 比(a, b) { const 商 = a / b; return 商; }\n",
                "export function 比(a, b, c) { return a ? b / c : c / b; }\n",
                "export function 取(表, i, j) { return 表[i / j]; }\n",
                "// 注释里写 /^[0-9]+$/ 不算逻辑\n",
                'const 网址 = "https://example.com/a/b";\n',
            )
        ),
        "除法与注释/字符串不许被当成正则字面量",
    )
    断言(
        "反向样本：`DOMParser` / `eval(` / 正则 `.test(` 这类真判断 ⇒ 报",
        all(
            命中(样本)
            for 样本 in (
                "const 解 = new DOMParser();\n",
                "export function 跑(s) { return eval(s); }\n",
                "export function 判(s) { return /^[0-9]+$/.test(s); }\n",
            )
        ),
        "三种判断形各报一处（要求都非空）",
    )
    # ── #38 残留关闭：正则字面量里的字样**不许**被当成真调用 ──
    # 病灶：剥离器不认 `正则字面量` 这一种字面量 ⇒ 里面的 `JSON.parse(` 字样被语义判当成真调用
    # （实测：`const 形 = /JSON.parse(/;` 报出 `JSON.parse`）。修法在**剥离层**（`剥字面量._剥注释与串`
    # 认 `／…／flags` 并当字面量剥掉）—— 剥掉的只是**字面量的内容**，字面量的**调用形**
    # （`.test(` / `.exec(` / `new RegExp(`）一根毫毛不少（否则就是假阴性）。
    正则字面量样本 = {
        "值位（赋给标识符）": "const 形 = /JSON\\.parse\\(/;\n",
        "裸形": "const 形 = /JSON.parse(/;\n",
        "`||` 之后": "export function 判(s) { return 左值 || /JSON\\.parse\\(/; }\n",
        "作为实参": "export function 判(s) { return 查(s, /JSON\\.parse\\(/); }\n",
    }
    真解析样本 = (
        "export function 取值(文) { return JSON.parse(文); }\n",
        "const 值 = JSON.parse(文本);\n",
    )
    断言(
        "反向样本（#38 残留）：源码里的正则字面量 `/JSON\\.parse\\(/`（值位 / 裸形 / `||` 之后 / 作实参）⇒ 不报",
        not any(前端命中(生产区文本(样本)) for 样本 in 正则字面量样本.values()),
        f"四形命中：{ {名称: 前端命中(生产区文本(文本)) for 名称, 文本 in 正则字面量样本.items()} }"
        "（要求全空）——正则字面量的内容是**数据**，与字符串/注释里的同名字样同一条道理",
    )
    断言(
        "正向样本（#38 残留）：真的 `JSON.parse(` 调用（值位 / 裸调用）⇒ **必须**报"
        "（证明剥字面量没把判据改瞎）",
        all(前端命中(生产区文本(样本)) for 样本 in 真解析样本),
        f"两形命中：{ [前端命中(生产区文本(样本)) for 样本 in 真解析样本] }（要求都非空）",
    )
    断言(
        "正向样本（#38 残留）：剥字面量不许把字面量的**调用形**一起剥掉"
        "（`.test(` / `.exec(` / `new RegExp(` 仍报）",
        all(
            前端命中(生产区文本(样本))
            for 样本 in (
                "export function 判(s) { return /^[0-9]+$/.test(s); }\n",
                "export function 判(s) { return /^[a-z]+$/.exec(s); }\n",
                'const 形 = new RegExp("^[0-9]+$");\n',
            )
        ),
        "三种调用形各报一处（要求都非空）",
    )
    断言(
        "诚实登记（#38 残余）：紧跟 `)` 的**裸** `/…/`（语句位）⇒ 不认（与除法同形，认它必假红）；"
        "但它一旦被**调用**（`/…/.test(…)`）就由调用形那支接住 ⇒ 真判断不漏",
        前端命中(生产区文本("if (条件) /^x$/;\n")) == []
        and bool(前端命中(生产区文本("if (条件) /^x$/.test(文);\n"))),
        f"裸句位命中 {前端命中(生产区文本('if (条件) /^x$/;\n'))}（要求空）· "
        f"调用形命中 {前端命中(生产区文本('if (条件) /^x$/.test(文);\n'))}（要求非空）"
        "——前者是**已知残余**，不是绿（口径：决策记录/2026-09-27_判据口径十一条.md §三）",
    )
    断言(
        "正向样本（#38 残留）：除法与含 `//` 的字符串/注释⇒ 位置无关的扫描也不误伤",
        not any(
            前端命中(生产区文本(样本))
            for 样本 in (
                "export function 比(a, b) { return a / b; }\n",
                "export function 比(a, b) { const 商 = a / b; return 商; }\n",
                "export function 比(a, b, c) { return a / b / c; }\n",
                "// 注释里写 /^[0-9]+$/ 不算逻辑\n",
                'const 网址 = "https://example.com/a/b";\n',
            )
        ),
        "除法与注释/字符串里的 `/` 不许被当成正则字面量",
    )
    断言(
        "正向样本（#38 残留）：正则在**真调用**之后接除法（`JSON.parse(x) / y`）⇒ 只报调用，除法不被误剥",
        前端命中(生产区文本("const 商 = JSON.parse(文) / 2;\n")) == ["JSON.parse"],
        f"命中 {前端命中(生产区文本('const 商 = JSON.parse(文) / 2;\n'))}（要求恰为 ['JSON.parse']）",
    )

    # ── 第二层：端到端（注入到干净合成仓 ⇒ 跑真判据；含关/开对照）──
    def 跑自检(注入文, 关判据=False):
        with tempfile.TemporaryDirectory(prefix="一键验证前端语义-") as 临时目录:
            临根 = Path(临时目录) / "仓"
            造干净仓(临根)
            if 注入文 is not None:
                (临根 / 注入件).write_text(注入文, encoding="utf-8")
            原模式 = 常量.前端逻辑模式
            try:
                if 关判据:
                    常量.前端逻辑模式 = re.compile(r"(?!)")  # 永不匹配 = 判据关掉
                return 跑全量判据(临根, 两遍=False)
            finally:
                常量.前端逻辑模式 = 原模式

    def 读数(判定汇总):
        return [f"{前端明细项['位置']} ｜ {前端明细项['缺什么'][:70]}" for 前端明细项 in 取前端明细(判定汇总)]

    def 指到注入件(判定汇总):
        return any(
            注入件 in 前端明细项["位置"] or 注入件 in 前端明细项["缺什么"] for 前端明细项 in 取前端明细(判定汇总)
        )

    开启结果 = 跑自检(真解析)
    关闭结果 = 跑自检(真解析, 关判据=True)
    序列化果 = 跑自检(序列化)
    注释果 = 跑自检(辩解注释)
    基线 = 跑自检(None)

    断言(
        "反向样本（端到端）：干净仓 + 一处真 `JSON.parse` ⇒ ⑪ 判据 6 报红且指到注入件",
        len(取前端明细(开启结果)) == 1 and 指到注入件(开启结果),
        f"⑪ 报 {len(取前端明细(开启结果))} 条：{读数(开启结果)}",
    )
    断言(
        "承重证明（关/开对照）：判据关掉 + **同一处**真解析 ⇒ 不报",
        len(取前端明细(关闭结果)) == 0,
        f"关掉后 ⑪ 报 {len(取前端明细(关闭结果))} 条（要求 0）：{读数(关闭结果)}",
    )
    断言(
        "正向样本（端到端）：干净仓 + `JSON.stringify` ⇒ ⑪ 判据 6 不报",
        len(取前端明细(序列化果)) == 0,
        f"⑪ 报 {len(取前端明细(序列化果))} 条（要求 0）：{读数(序列化果)}",
    )
    断言(
        "正向样本（端到端）：干净仓 + 辩解注释 ⇒ ⑪ 判据 6 不报",
        len(取前端明细(注释果)) == 0,
        f"⑪ 报 {len(取前端明细(注释果))} 条（要求 0）：{读数(注释果)}",
    )
    断言(
        "基线：干净合成仓不注入 ⇒ ⑪ 判据 6 也不报（正向样本上不误报）",
        len(取前端明细(基线)) == 0,
        f"⑪ 报 {len(取前端明细(基线))} 条（要求 0）：{读数(基线)}",
    )
    return 输出缓冲


def 自检_前端内联脚本() -> list:
    """⑪-6 的 `.html` 内联 `<script>` 扫描面的身份证。

    反向样本：只含**内联** `<script>…JSON.parse(…)</script>` 的 `.html` ⇒ ⑪-6 必须报
    （证明内联脚本真进了扫描面）。
    正向样本：只含**外链** `<script src=…>`（外链由它自身的 `.js` 件覆盖），
    且**标记属性里**写了 `JSON.parse` 的字样 ⇒ ⑪-6 不报（证明只扫脚本体，不扫标记）。
    承重证明（关/开对照）：关掉 `前端逻辑模式` + 同一注入 ⇒ 不报。
    """
    import tempfile

    输出缓冲 = []
    注入件 = "前端呈现/网页应用/注入样例.html"
    反向文 = '<html><body><script>const x = JSON.parse("{}");</script></body></html>\n'
    正向文 = (
        '<html><body data-注="JSON.parse( 只是标记属性里的字样，不是脚本">\n'
        '<script type="module" src="应用.js"></script></body></html>\n'
    )

    def 跑自检(html文, 关判据=False):
        with tempfile.TemporaryDirectory(prefix="一键验证前端内联-") as 临时目录:
            临根 = Path(临时目录) / "仓"
            造干净仓(临根)
            if html文 is not None:
                (临根 / 注入件).write_text(html文, encoding="utf-8")
            原模式 = 常量.前端逻辑模式
            try:
                if 关判据:
                    常量.前端逻辑模式 = re.compile(r"(?!)")  # 永不匹配 = 判据关掉
                return 跑全量判据(临根, 两遍=False)
            finally:
                常量.前端逻辑模式 = 原模式

    开启结果 = 跑自检(反向文)
    关闭结果 = 跑自检(反向文, 关判据=True)
    正向结果 = 跑自检(正向文)
    输出缓冲.append(
        (
            "反向样本：`.html` 内联 `<script>` 里的真 `JSON.parse` ⇒ ⑪-6 报",
            len(取前端明细(开启结果)) >= 1,
            f"⑪ 报 {len(取前端明细(开启结果))} 条（要求 ≥1）",
        )
    )
    输出缓冲.append(
        (
            "承重证明（关/开对照）：关掉 `前端逻辑模式` + 同一注入 ⇒ 不报",
            len(取前端明细(关闭结果)) == 0,
            f"关掉后 ⑪ 报 {len(取前端明细(关闭结果))} 条（要求 0）",
        )
    )
    输出缓冲.append(
        (
            "正向样本：只含外链 `<script src=…>`（标记属性里有 `JSON.parse` 字样）⇒ 不报",
            len(取前端明细(正向结果)) == 0,
            f"⑪ 报 {len(取前端明细(正向结果))} 条（要求 0）——只扫脚本体，不扫标记",
        )
    )
    return 输出缓冲
