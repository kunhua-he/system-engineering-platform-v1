网址主机段式 = re.compile('\\b[a-zA-Z][a-zA-Z0-9+.-]*://[^\\s/`\'"<>?#]+')

def 是网址主机段(源码行,匹配结果):
    """仅识别协议后的主机与端口；远端路径内的源码行号仍须检查。"""
    return any(网址匹配.start()<=匹配结果.start() and 匹配结果.end()<=网址匹配.end()
               for 网址匹配 in 网址主机段式.finditer(源码行))

def _形二豁免(行表: list, 序号: int, 列号: int, 行号: int) -> str:
    """形二（`第 N 行`）的两条豁免，返回豁免理由（空串 = 不豁免）。**按位置判，不按词命中**。

    ① **节内表行**：紧邻前面有 `§节名`（如「§六 第 N 行」）⇒ 那是**表行 / 条号**，不是文件行号。
    ② **语料原文行**：本行紧跟一个围栏代码块（``` 收尾），且 N ≤ 该块的内容行数
       ⇒ 引的是**块内原文**（样本数据内容，不是代码定位）。
    """
    源码行 = 行表[序号]
    if "§" in 源码行[max(0, 列号 - 16) : 列号]:
        return "节内表行（紧邻前面有 §节名）"
    # 上一行是不是围栏块的收尾？
    上层读数 = 行表[序号 - 1].strip() if 序号 >= 1 else ""
    if 上层读数.startswith("```"):
        内容行数 = 0
        探位 = 序号 - 2
        while 探位 >= 0 and not 行表[探位].strip().startswith("```"):
            内容行数 += 1
            探位 -= 1
        if 探位 >= 0 and 行号 <= 内容行数:
            return f"语料原文行（紧跟围栏块，块内 {内容行数} 行）"
    return ""


def 检查15_禁按行号引用(上层读数: dict) -> list:
    """引用一律按符号：源码 `路径::符号名`，文档 `路径 §节名`。**禁按行号**。

    为什么：按行号引用**没人会去数，判据照报绿** —— 实测全仓数十处按行号引用源码，多数**已漂**
    （底座那处现是 `}`；`src/常量.rs` 与 `装载.rs` 连件都没了），而当时所有判据全绿。
    同一失效模式在 `.md` 里一样成立 ⇒ **md 行号引用同罪**。

    三元读数：**通过** = 扫描面非空且 0 命中；**失败** = 命中逐条报出（件 · 行 · 原文）；
    **未判** = 扫描面下 0 个件（那说明扫描面或后缀表坏了，不是「没问题」）。

    两条**允许**的引用（口径；两条都按**位置**判，不按词命中 —— 同 ⑪-3 / ⑪-4 的先例）：
    - **行号 = 1**：第 1 行**不可能漂**（前面插不进行），且生成物第 1 行是生成器契约固定的盖章行
      （先例：`测试验证/契约一致性/扫实现.py` 文件头注 4 与 `项目文档/设计文档/导出目标.md` §六 闸三）。
    - **语料文本行**：引的是语料 / 样本原文的行 —— 那是**样本数据内容**，不是代码定位。
      （中文扩展名的语料件天然不匹配形一；另收「路径落在语料目录」与「紧跟围栏块的 `第 N 行`」。）

    ★ **口径边界（2026-10-08 统一说明）**：形二（`第 N 行`）**不要求反引号** —— 它按**整行**匹配，
    注释 / 字符串 / 反引号里**一视同仁**（这正是「没人会去数 ⇒ 静默失效」的失效面：写在注释里的
    行号引用同样会漂）。三条**按位置**的豁免是：① N ≤ 1；② 行首附近有 `§节名`（节内表行 / 条号，
    不是文件行号）；③ 紧跟围栏代码块且 N ≤ 块内行数（语料原文行）。形三（`L` 前缀）才另加收窄
    （单个 `L<数字>` 与字段名分不开，只认区间形与紧跟「行」的）。
    """
    输出缓冲 = []
    件表 = {
        键名: 文件项["文本"]
        for 键名, 文件项 in 上层读数["文件"].items()
        if 键名.endswith(行号引用后缀) and 文件项.get("文本") is not None
    }
    理由 = (
        "按行号引用**没人会去数** ⇒ 源码一改它就静默失效、判据照报绿（实测多数已漂）。"
        "正解是引用**符号**：源码用 `路径::符号名`，文档用 `路径 §节名`。"
        "改哪一处、那个符号叫什么，只有该文件的作者能定 ⇒ 只能由作者改"
    )
    for 键名 in sorted(件表):
        行表 = 件表[键名].split("\n")
        for 序号, 源码行 in enumerate(行表):
            # ── 形一：`路径.扩展名:行号`（可带区间）──
            for 匹配结果 in 行号引用_路径.finditer(源码行):
                if 是网址主机段(源码行,匹配结果):
                    continue
                被引路径, 扩展名, 行号 = 匹配结果.group(1), 匹配结果.group(2), int(匹配结果.group(3))
                if 扩展名.isdigit():
                    continue  # `127.0.0.1:43110` 这类 IP:端口，不是文件引用
                if 行号 <= 1:
                    continue  # 豁免①：第 1 行不可能漂（生成物第 1 行是生成器契约固定）
                if 扩展名 in 语料后缀 or any(片段 in 被引路径 for 片段 in 语料路径片段):
                    continue  # 豁免②：语料 / 样本件（按**这一条引用自身的路径**判）
                输出缓冲.append(
                    违规(
                        检查名[14],
                        f"{键名} 第 {序号 + 1} 行",
                        f"按行号引用 `{匹配结果.group(0)}`（原文：{源码行.strip()[:90]}）",
                        理由,
                    )
                )
            # ── 形二：`第 N 行`（md 行号引用同罪）──
            for 匹配结果 in 行号引用_第几行.finditer(源码行):
                号表 = [int(号片) for 号片 in re.split(r"[/、,]", 匹配结果.group(1)) if 号片.strip().isdigit()]
                for 号值 in 号表:
                    if 号值 <= 1:
                        continue
                    豁免理由 = _形二豁免(行表, 序号, 匹配结果.start(), 号值)
                    if 豁免理由:
                        continue
                    输出缓冲.append(
                        违规(
                            检查名[14],
                            f"{键名} 第 {序号 + 1} 行",
                            f"按行号引用 `{匹配结果.group(0)}`（原文：{源码行.strip()[:90]}）",
                            理由,
                        )
                    )
            # ── 形三：`L` 前缀的行号记法（只认区间形与紧跟「行」的，见上面的收窄理由）──
            # 形三不捕获被引路径（`L` 记法本身不带路径）⇒ 语料豁免只能按整行判（宁可少豁免）。
            for 匹配结果 in 行号引用_L前缀.finditer(源码行):
                if int(匹配结果.group(1)) <= 1:
                    continue
                if 匹配结果.group(2) is None and "行" not in 源码行[匹配结果.end() : 匹配结果.end() + 3]:
                    continue  # 单个 `L<数字>`：与字段名分不开 ⇒ 不认（防假红）
                if any(片段 in 源码行 for 片段 in 语料路径片段):
                    continue
                输出缓冲.append(
                    违规(
                        检查名[14],
                        f"{键名} 第 {序号 + 1} 行",
                        f"按行号引用 `{匹配结果.group(0)}`（原文：{源码行.strip()[:90]}）",
                        理由,
                    )
                )
    if not 件表:
        判不了(
            检查名[14],
            "全仓",
            "扫描面下 0 个 `.md` / `.py` / `.rs` 件（判据没有可查的对象）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。要么扫描面 / 后缀表坏了、"
            "要么仓里真的一个件都没有 —— 两种都只能由判据作者确认（读数为 0 不许当成绿）",
        )
    return 输出缓冲



def 自检_网址主机判别():
    定位样本=[
        ("网址端口不是源码行号","https://EXAMPLE.COM:443/a",0),
        ("源码行号仍须拒绝","调度.rs:%d" % 443,1),
        ("网址路径内的源码行号仍须拒绝","https://example.com/src/调度.rs:%d" % 443,1),
        ("同一行有网址与真实引用只报真实引用","https://example.com:443/a 调度.rs:%d" % 443,1),
    ]
    输出缓冲=[]
    for 样本名,源码片段,期望条数 in 定位样本:
        读数={"文件":{"构建装配/定位片段.py":{"文本":源码片段}}}
        违规条目=检查15_禁按行号引用(读数)
        输出缓冲.append((样本名,len(违规条目)==期望条数,str(违规条目)))
    return 输出缓冲
