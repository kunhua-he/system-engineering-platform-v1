def _形二豁免(行表: list, 序: int, 列: int, 行号: int) -> str:
    """形二（`第 N 行`）的两条豁免，返回豁免理由（空串 = 不豁免）。**按位置判，不按词命中**。

    ① **节内表行**：紧邻前面有 `§节名`（如「§六 第 N 行」）⇒ 那是**表行 / 条号**，不是文件行号。
    ② **语料原文行**：本行紧跟一个围栏代码块（``` 收尾），且 N ≤ 该块的内容行数
       ⇒ 引的是**块内原文**（样本数据内容，不是代码定位）。
    """
    行 = 行表[序]
    if "§" in 行[max(0, 列 - 16) : 列]:
        return "节内表行（紧邻前面有 §节名）"
    # 上一行是不是围栏块的收尾？
    上 = 行表[序 - 1].strip() if 序 >= 1 else ""
    if 上.startswith("```"):
        内容行数 = 0
        i = 序 - 2
        while i >= 0 and not 行表[i].strip().startswith("```"):
            内容行数 += 1
            i -= 1
        if i >= 0 and 行号 <= 内容行数:
            return f"语料原文行（紧跟围栏块，块内 {内容行数} 行）"
    return ""


def 检查15_禁按行号引用(上: dict) -> list:
    """引用一律按符号：源码 `路径::符号名`，文档 `路径 §节名`。**禁按行号**。

    为什么：按行号引用**没人会去数，判据照报绿** —— 实测全仓数十处按行号引用源码，多数**已漂**
    （底座那处现是 `}`；`src/常量.rs` 与 `装载.rs` 连件都没了），而当时所有判据全绿。
    同一失效模式在 `.md` 里一样成立 ⇒ **md 行号引用同罪**。

    三元读数：**通过** = 扫描面非空且 0 命中；**失败** = 命中逐条报出（件 · 行 · 原文）；
    **未判** = 扫描面下 0 个件（那说明扫描面或后缀表坏了，不是「没问题」）。

    两条**允许**的引用（口径；两条都按**位置**判，不按词命中 —— 同 ⑪-3 / ⑪-4 的先例）：
    - **行号 = 1**：第 1 行**不可能漂**（前面插不进行），且生成物第 1 行是生成器契约固定的盖章行
      （先例：`测试验证/契约一致性/扫实现.py` 文件头注 4 与 `项目文档/设计文档/导出目标.md` §六 闸三）。
    - **语料文本行**：引的是语料 / 样本原文的行 —— 那是**样本数据内容**，不是代码定位。
      （中文扩展名的语料件天然不匹配形一；另收「路径落在语料目录」与「紧跟围栏块的 `第 N 行`」。）
    """
    出 = []
    件表 = {
        键: 项["文本"]
        for 键, 项 in 上["文件"].items()
        if 键.endswith(行号引用后缀) and 项.get("文本") is not None
    }
    理由 = (
        "按行号引用**没人会去数** ⇒ 源码一改它就静默失效、判据照报绿（实测多数已漂）。"
        "正解是引用**符号**：源码用 `路径::符号名`，文档用 `路径 §节名`。"
        "改哪一处、那个符号叫什么，只有该文件的作者能定 ⇒ 只能由作者改"
    )
    for 键 in sorted(件表):
        行表 = 件表[键].split("\n")
        for 序, 行 in enumerate(行表):
            # ── 形一：`路径.扩展名:行号`（可带区间）──
            for 命 in 行号引用_路径.finditer(行):
                被引路径, 扩展名, 行号 = 命.group(1), 命.group(2), int(命.group(3))
                if 扩展名.isdigit():
                    continue  # `127.0.0.1:43110` 这类 IP:端口，不是文件引用
                if 行号 <= 1:
                    continue  # 豁免①：第 1 行不可能漂（生成物第 1 行是生成器契约固定）
                if 扩展名 in 语料后缀 or any(片 in 被引路径 for 片 in 语料路径片段):
                    continue  # 豁免②：语料 / 样本件（按**这一条引用自己的路径**判）
                出.append(
                    违规(
                        检查名[14],
                        f"{键} 第 {序 + 1} 行",
                        f"按行号引用 `{命.group(0)}`（原文：{行.strip()[:90]}）",
                        理由,
                    )
                )
            # ── 形二：`第 N 行`（md 行号引用同罪）──
            for 命 in 行号引用_第几行.finditer(行):
                号表 = [int(x) for x in re.split(r"[/、,]", 命.group(1)) if x.strip().isdigit()]
                for 号 in 号表:
                    if 号 <= 1:
                        continue
                    免 = _形二豁免(行表, 序, 命.start(), 号)
                    if 免:
                        continue
                    出.append(
                        违规(
                            检查名[14],
                            f"{键} 第 {序 + 1} 行",
                            f"按行号引用 `{命.group(0)}`（原文：{行.strip()[:90]}）",
                            理由,
                        )
                    )
            # ── 形三：`L` 前缀的行号记法（只认区间形与紧跟「行」的，见上面的收窄理由）──
            # 形三不捕获被引路径（`L` 记法本身不带路径）⇒ 语料豁免只能按整行判（宁可少豁免）。
            for 命 in 行号引用_L前缀.finditer(行):
                if int(命.group(1)) <= 1:
                    continue
                if 命.group(2) is None and "行" not in 行[命.end() : 命.end() + 3]:
                    continue  # 单个 `L<数字>`：与字段名分不开 ⇒ 不认（防假红）
                if any(片 in 行 for 片 in 语料路径片段):
                    continue
                出.append(
                    违规(
                        检查名[14],
                        f"{键} 第 {序 + 1} 行",
                        f"按行号引用 `{命.group(0)}`（原文：{行.strip()[:90]}）",
                        理由,
                    )
                )
    if not 件表:
        判不了(
            检查名[14],
            "全仓",
            "扫描面下 0 个 `.md` / `.py` / `.rs` 件（判据没有可查的对象）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。要么扫描面 / 后缀表坏了、"
            "要么仓里真的一个件都没有 —— 两种都只能由判据作者确认（读数为 0 不许当成绿）",
        )
    return 出
