# -*- coding: utf-8 -*-
"""注入样本 · 命名口径四条（判据 ㊿/51/52/53）—— 反向样本注到干净合成仓（可重复）。

夹具的最小规则库里名册是从夹具干净代码派生的 ⇒ 注入件在 `造干净仓` 之后才落盘，
它的名不在名册里、也不在已裁种子 / 基线里 ⇒ 必然是「新增」⇒ 当场红。
"""
from __future__ import annotations

import sqlite3
import sys
from pathlib import Path


def _取库相对路径() -> str:
    """惰性取库路径（主人 = `表定义.库相对路径`）。"""
    工具根 = Path(__file__).resolve().parents[3]
    根目录 = str(工具根 / "开发工具" / "信息核心")
    if 根目录 not in sys.path:
        sys.path.insert(0, 根目录)
    import 表定义

    return 表定义.库相对路径


def _写定义行(临根: Path, 行表: list) -> Path:
    """往合成仓的 `命名定义` 塞几行 ⇒ 库路径。"""
    库件 = 临根 / _取库相对路径()
    连接 = sqlite3.connect(库件)
    try:
        for 语义, 唯一名 in 行表:
            连接.execute("insert or replace into 命名定义 values(?,?,?)",
                       (语义, 唯一名, "（名即语义）"))
        连接.commit()
    finally:
        连接.close()
    return 库件


def 注入_命名重复登记(临根: Path) -> str:
    """同一 `唯一名` 挂两条**同义**语义（真子串包含）⇒ 判据 ㊿ 当场红。"""
    _写定义行(临根, [("重复样本语义前", "`重复样本名`"),
                   ("重复样本语义前与细化", "`重复样本名`")])
    return "重复样本名"


def 注入_命名一名多义(临根: Path) -> str:
    """同一 `唯一名` 挂两条**所指不同**的语义（无子串、相似度 <0.6）⇒ 判据 51 当场红。"""
    _写定义行(临根, [("宿主编号", "`多义样本名`"),
                   ("留痕记录的耗时毫秒字段", "`多义样本名`")])
    return "多义样本名"


def 注入_命名同义异名(临根: Path) -> str:
    """往合成仓塞两个**正前缀名**（同区、不同件、同种类、都无主）并登记 ⇒ 判据 52 当场红。"""
    样本件前 = "运行内核/实例状态/src/同义样本前.rs"
    样本件后 = "运行内核/实例状态/src/同义样本后.rs"
    for 样本件, 样本名 in ((样本件前, "同义样本前"), (样本件后, "同义样本前细化")):
        路径 = 临根 / 样本件
        路径.parent.mkdir(parents=True, exist_ok=True)
        路径.write_text("pub fn %s() -> u32 { 1 }\n" % 样本名, encoding="utf-8")
    _写定义行(临根, [("同义样本前", "同义样本前"), ("同义样本前细化", "同义样本前细化")])
    return 样本件前


def 注入_命名词性组合(临根: Path) -> str:
    """往合成仓登记一个**光杆动词** `解析`（动作族却切不出宾语）⇒ 判据 53 当场红。"""
    _写定义行(临根, [("解析协议值", "解析")])
    return "解析"
