def 是整数(待处理值) -> bool:
    """真整数（bool 不算——它是 int 的子类，会把 True 当 1 蒙过去）。"""
    return isinstance(待处理值, int) and not isinstance(待处理值, bool)


def 取判据明细(判定汇总: dict, 检查: str) -> list:
    """从验证结果字典的 `失败` + `未判` 里筛出属于某条判据的明细（同一份筛选只此一处）。

    `结果` 的形状由 `验证.跑全量判据` 定（`失败` / `未判` 两条都是明细表）；
    明细是 `违规` / `判不了` 造的那种带 `检查` 的字典。
    """
    return [
        明细条
        for 明细条 in 判定汇总["失败"] + 判定汇总["未判"]
        if isinstance(明细条, dict) and 明细条["检查"] == 检查
    ]


def 违规(检查: str, 字节位置: str, 缺什么: str, 不能自愈: str) -> dict:
    return {"检查": 检查, "位置": 字节位置, "缺什么": 缺什么, "不能自愈": 不能自愈}


# 判据内部的「子判据空集」通道（判据的可信性.md 第二节：空集是未判，不是通过）。
# 为什么要有它：一条判据常常是好几条子判据合起来的（例：⑪ 有 6 条），
# 其中某一条的对象是空集时（例：`前端呈现/` 下 0 个源文件），
# 整条判据不能报「失败」（那不是违规），但也不能报「通过」（那是假绿）
# ⇒ 走这条通道，进「未判逐条」，与「整条判据的对象为空」并列展示。
#
# ★ 2026-09-27 起改成**每分片一份**（`threading.local`）：判据分片从线程池扩到**进程池**，
#   而进程之间不共享内存 —— 一个模块级全局在子进程里写、父进程读不到（子判据空集会**静默丢**，
#   那就是假绿）。改成「谁跑这条判据，谁自身清、自身收」：线程/进程两条路都成立，
#   且线程路不再有「共享列表 + 多线程 append」的竞态。
_本分片未判 = threading.local()


def 清未判() -> None:
    """清空**本分片**的未判桶（每条判据开跑前调一次）。"""
    _本分片未判.未判清单 = []


def 取未判() -> list:
    """取**本分片**的未判桶（跑完这条判据后调一次）。"""
    return list(getattr(_本分片未判, "未判清单", None) or [])


def 判不了(检查: str, 字节位置: str, 缺什么: str, 不能自愈: str) -> None:
    未判桶 = getattr(_本分片未判, "桶", None)
    if 未判桶 is None:
        未判桶 = []
        _本分片未判.未判清单 = 未判桶
    未判桶.append(
        {"检查": 检查, "位置": 字节位置, "缺什么": 缺什么, "不能自愈": 不能自愈,
         "分类": "缺件或半成品"}
    )


def 取相对路径(仓根: Path, 路径: Path) -> str:
    try:
        return 路径.relative_to(仓根).as_posix()
    except ValueError:
        return 路径.as_posix()


def 段归属标签(号段: dict) -> str:
    """号段表 `归属` 里 "：" 前那一段（方向标签 / 层级标签）。"""
    源文本 = str(号段.get("归属", ""))
    for 分隔 in ("：", ":"):
        if 分隔 in 源文本:
            return 源文本.split(分隔, 1)[0].strip()
    return 源文本.strip()


def 层级标签(源文本: str) -> str:
    """归属文案里的**层名**：切掉 "：" · "（" · "——" 之后的一切，再去掉 markdown 粗体标记。

    例：「内核自有（不对外）」→「内核自有」；
        「**核心支持库** —— 语言自身的能力（…）」→「核心支持库」；
        「三方封装 · 系统与环境（按**域**分段，以下同）」→「三方封装 · 系统与环境」；
        「下行：宿主 → 扩展」→「下行」。
    两个号空间（能力号 / 错误码段位）写同一层时，括号与破折号后的注解可以不同，层名必须相同。
    """
    源文本 = str(源文本)
    for 分隔 in ("：", ":"):
        if 分隔 in 源文本:
            源文本 = 源文本.split(分隔, 1)[0]
    源文本 = 源文本.split("（", 1)[0]
    for 破折 in ("——", "—", " -- ", " - "):
        if 破折 in 源文本:
            源文本 = 源文本.split(破折, 1)[0]
    return 源文本.replace("**", "").strip()
