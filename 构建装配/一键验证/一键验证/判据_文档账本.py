# -*- coding: utf-8 -*-
"""判据 ㊶：文档账本 —— 每一份 `.md` 都要在账本里定义「它表达什么权威」。

依据：华哥 2026-09-28 原话「每一个 md 的落盘（包含现在）都需要有一个账本给他定义这个 md
表达的是什么权威。**如果没有定义的，则表示随时可以删除**」·
`项目文档/决策记录/2026-09-28_文档账本.md`（本条的裁决）·
`项目文档/哲学.md` §三（md 权威分级）· `项目文档/开发规范/开发规范.md` §九（md 治理）。

**为什么要这一条**：md 的职责分几类（宪法 / 落点与规范 / 决策记录 / 取证实测 / 节点自述 / …），
但**没有一份账本说清哪份 md 是哪一类** —— 「这份 md 是什么权威」只靠人记。没有判据的纪律会漂
（`设计哲学.md` 根三）。账本 + 判据 = 这条口径有落点、可判。

**账本**：`项目文档/文档账本.json`。形状：

    { "说明": …, "权威档": [{档, 定义, 谁改}], "按路径定档": [{前缀, 档}], "件": [{路径, 档, 表达什么}] }

**判什么**（三元读数）：
- **通过** = 全树 `.md` 每一份都被账本定义（命中 `按路径定档` 一条规则，或有 `件` 里一条显式条目），
  且 `件` 里每一份都在盘上，且每条的 `档` 在 `权威档` 枚举内，且 `表达什么` 非空。
- **失败** = 逐条报出：未登记的 `.md` · 账本里的幽灵路径 · `档` 不在枚举内 · `表达什么` 空。
- **未判** = 全树 0 份 `.md`，或账本读不出 / 解析不了 / 没有 `权威档` 枚举。

**「未登记 ⇒ 可删」**：未登记的 `.md` 就是没定义权威的 —— 处置只有两条：登记（说清它是什么），或删。
"""
from __future__ import annotations

import json

from .小工具 import 判不了, 违规
from .常量 import 检查名


账本路径 = "项目文档/文档账本.json"
文档后缀 = ".md"


def 文档面(上层读数: dict) -> list:
    """扫描面：全树（`上层读数["文件"]`）里的 `.md` 件，按路径排序。"""
    return sorted(键名 for 键名 in 上层读数["文件"] if 键名.endswith(文档后缀))


def 样本_文档面(上层读数: dict) -> int:
    """对象数：全树 `.md` 件数（0 ⇒ 未判）。"""
    return len(文档面(上层读数))


def 读账本(上层读数: dict):
    """从**盘上**读账本（返回 `(账本 dict 或 None, 错误或 None)`）。

    为什么读盘不读内存映射：`上层读数["文件"]` 只含「`契约声明/` 的 JSON + 其余非 JSON 源件」
    （`读文件.py::建上下文` 的口径）⇒ **`契约声明/` 之外的 JSON 不在里面**。账本住在
    `项目文档/` 下，故必须直接读盘（同 `判据_元判据` 的「在盘」做法）。
    """
    路径 = 上层读数["仓根"] / 账本路径
    if not 路径.is_file():
        return None, f"账本 `{账本路径}` 不在盘上"
    try:
        文本 = 路径.read_text(encoding="utf-8")
    except OSError as 错误:
        return None, f"账本读不动：{错误}"
    try:
        数据 = json.loads(文本)
    except ValueError as 错误:
        return None, f"账本不是合法 JSON：{错误}"
    if not isinstance(数据, dict):
        return None, "账本不是 JSON 对象"
    return 数据, None


def 检查41_文档账本(上层读数: dict) -> list:
    """每一份 `.md` 都要在文档账本里有权威定义。

    三元读数：**通过** = 全树 `.md` 全被定义且账本无幽灵条目、档合法、表达什么非空；
    **失败** = 逐条报出；**未判** = 全树 0 份 `.md`，或账本读不出 / 解析不了 / 缺 `权威档`。
    """
    输出缓冲 = []
    文档面表 = 文档面(上层读数)
    if not 文档面表:
        判不了(
            检查名[40],
            "全树 `.md`",
            "全树 0 份 `.md`（扫描面为空）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过 —— 一份 md 都没有的仓，"
            "本条判据什么都没验 ⇒ 只能由判据作者确认扫描面",
        )
        return 输出缓冲
    账本, 错误 = 读账本(上层读数)
    if 错误:
        判不了(
            检查名[40],
            账本路径,
            f"判不了：{错误}",
            f"账本是本条的**唯一对象**（华哥 2026-09-28：没有定义的 md 随时可删）⇒ "
            f"读不出就判不了。修法：把 `{账本路径}` 补上并保证是合法 JSON ⇒ 只能由账本作者补",
        )
        return 输出缓冲
    档表 = 账本.get("权威档")
    if not isinstance(档表, list) or not 档表:
        判不了(
            检查名[40],
            账本路径,
            "账本里没有 `权威档` 枚举（或为空）",
            "没有档枚举 ⇒ 「档」这个词没有定义，本条判不了「档合不合法」⇒ 只能由账本作者补",
        )
        return 输出缓冲
    合法档 = {
        条目.get("档") for 条目 in 档表
        if isinstance(条目, dict) and isinstance(条目.get("档"), str) and 条目.get("档")
    }
    规则表 = [
        条目 for 条目 in (账本.get("按路径定档") or [])
        if isinstance(条目, dict) and isinstance(条目.get("前缀"), str) and 条目.get("前缀")
    ]
    件表 = 账本.get("件")
    if not isinstance(件表, list):
        判不了(
            检查名[40],
            账本路径,
            "账本里没有 `件` 列表",
            "账本的「逐件定义」在 `件` 里 ⇒ 读不到就判不了 ⇒ 只能由账本作者补",
        )
        return 输出缓冲

    登记 = {}
    for 条目 in 件表:
        if isinstance(条目, dict) and isinstance(条目.get("路径"), str) and 条目.get("路径"):
            登记[条目["路径"]] = 条目

    def 按规则定档(键名: str):
        for 条目 in 规则表:
            if 键名.startswith(条目["前缀"]):
                return 条目.get("档")
        return None

    # ① 未登记（华哥口径：没有定义的 ⇒ 随时可删）
    for 键名 in 文档面表:
        if 键名 in 登记:
            continue
        if 按规则定档(键名) in 合法档:
            continue
        输出缓冲.append(
            违规(
                检查名[40],
                键名,
                f"`{键名}` 不在文档账本里 ⇒ **没有权威定义**",
                "华哥 2026-09-28：没有定义的 md = 随时可以删除。处置只有两条："
                f"① 在 `{账本路径}` 的 `件` 里登记它（写清档与「表达什么」），或 ② 删掉它。"
                "（整目录同类的可以在 `按路径定档` 加一条规则）⇒ 只能由这份 md 的作者定",
            )
        )
    # ② 幽灵条目
    for 路径 in sorted(登记):
        if 路径 not in 上层读数["文件"]:
            输出缓冲.append(
                违规(
                    检查名[40],
                    路径,
                    f"账本登记了 `{路径}`，但盘上没有这份件（幽灵条目）",
                    "账本是「每份 md 的权威定义」的唯一落点；登记一份不存在的件 = 定义漂了 ⇒ "
                    "删掉这条登记（件改名了就改路径）",
                )
            )
    # ③ 档不合法 / 「表达什么」空
    for 路径 in sorted(登记):
        条目 = 登记[路径]
        档名 = 条目.get("档")
        if 档名 not in 合法档:
            输出缓冲.append(
                违规(
                    检查名[40],
                    路径,
                    f"`{路径}` 的档 `{档名}` 不在账本 `权威档` 枚举里（合法档：{sorted(合法档)}）",
                    "档是本账本的核心字段；自造一个档 = 权威分级失效 ⇒ 要么改用合法档，"
                    "要么在 `权威档` 里补定义（补定义要说明它权威到什么程度、谁改）",
                )
            )
        if not str(条目.get("表达什么") or "").strip():
            输出缓冲.append(
                违规(
                    检查名[40],
                    路径,
                    f"`{路径}` 没写「表达什么」",
                    "账本要回答的是「这个 md 表达的是什么权威」；不写「表达什么」等于没定义 ⇒ "
                    "补一句话（它是规范 / 读数 / 自述里的哪一种，管什么）",
                )
            )
    return 输出缓冲
