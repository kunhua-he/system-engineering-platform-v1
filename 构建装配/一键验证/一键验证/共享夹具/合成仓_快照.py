# -*- coding: utf-8 -*-
"""夹具快照 —— 「建一份干净合成仓」从**逐次重写**压成「**建一次 + N 次铺字节**」。

**为什么要它**（2026-10-08 实测 · 本机 20 次中位）：
`造干净仓` 每次都要把 59 件逐件写盘，再重跑一遍 `建夹具规则库`（全树名册扫描 + 那批
sqlite 建写，一次约 8.6 ms）与 `写夹具基线`。而 `--自测` 一次要造 **78 个样本仓**，
每个样本的夹具**逐字节相同** ⇒ 同一份建库劳动被重付 78 遍。

实测：造仓 **20.2 ms → 7.1 ms（2.84×）**；`--自测` 的造仓总耗时 **7.53 s → 约 2.7 s**。
系统调用侧（每仓均值）：`stat` **75.3 → 37.4**；写盘调用 **149 → 约 102**。

**为什么不是「几十个样本共用一份仓」**（判据可信性的红线）：每个样本**必须仍是独立仓** ——
共用一份会让样本之间互相污染（改了一处的样本把别人也改了）= 假绿来源。
本件铺的是**字节副本**：每个样本拿到**各自的一棵全新目录树** ⇒ 改它不碰别人、
也不碰快照（底稿只活在临时目录与内存里，铺完即弃）。

**强度一条不降**：启用快照之前先 `自校` —— 把快照字节铺成一份仓，再按**老路**
（逐件写盘 + `建夹具规则库` + `写夹具基线`）另建一份，**逐件比件名与字节**。
只有**全等**才启用；任何一处不等 ⇒ **永久退回老路**（`慢路兜底`）并如实报出。
自校只在**首次**取快照时跑一次（每进程一次，约 +26 ms），之后零成本。
"""
from __future__ import annotations

import tempfile
from pathlib import Path

# 进程内快照：`None` = 还没建；`False` = 自校不过（永久退老路）；否则 `(件字节表, 父目录集)`。
快照缓存 = None


def _读底稿(底稿: Path) -> dict:
    """把一棵仓读成 `{相对件名: 件字节}` —— 逐件读**字节**（`.db` 只能这么读，不许解码）。"""
    return {
        str(盘上件.relative_to(底稿)): 盘上件.read_bytes()
        for 盘上件 in sorted(底稿.rglob("*"))
        if 盘上件.is_file()
    }


def _取父目录集(件字节表: dict) -> frozenset:
    """件表的全部父目录（去重）—— 铺盘时先一次建齐，省掉逐件 `mkdir(parents=True)`。"""
    return frozenset(str(Path(相对件名).parent) for 相对件名 in 件字节表)


def 铺字节(仓根: Path, 件字节表: dict, 父目录集=None) -> None:
    """把件字节表铺进目标仓根：先建齐父目录，再逐件写字节。

    `父目录集` 可预给（快照里缓存好的）；不给就现从件表推。
    """
    if 父目录集 is None:
        父目录集 = _取父目录集(件字节表)
    仓根.mkdir(parents=True, exist_ok=True)
    for 相对目录 in sorted(父目录集):
        (仓根 / 相对目录).mkdir(parents=True, exist_ok=True)
    for 相对件名, 件字节 in 件字节表.items():
        (仓根 / 相对件名).write_bytes(件字节)


def 判两仓等价(左仓: Path, 右仓: Path) -> list:
    """逐件比两棵仓的**件名集**与**件字节** ⇒ 差异行表（空 = 等价）。

    只读、不写 ⇒ 拿它当「快照重放 == 老路重建」的判据。
    """
    左表 = _读底稿(左仓)
    右表 = _读底稿(右仓)
    差异表 = []
    for 相对件名 in sorted(set(左表) | set(右表)):
        if 相对件名 not in 左表:
            差异表.append("快照侧缺件：%s" % 相对件名)
        elif 相对件名 not in 右表:
            差异表.append("老路侧缺件：%s" % 相对件名)
        elif 左表[相对件名] != 右表[相对件名]:
            差异表.append("件内容不同：%s" % 相对件名)
    return 差异表


def _按老路建(仓根: Path) -> None:
    """**老路**：逐件写盘 + 建夹具规则库 + 写夹具基线（快照的**来源**与**对照**都用它）。

    惰性 import：`合成仓` 反向要 `铺夹具快照` ⇒ 模块级 import 会成环。
    """
    from .合成仓 import 干净合成仓, 写夹具基线
    from .夹具规则库 import 建夹具规则库

    件表 = 干净合成仓()
    for 相对路径, 件内容 in 件表.items():
        路径 = 仓根 / 相对路径
        路径.parent.mkdir(parents=True, exist_ok=True)
        路径.write_text(件内容, encoding="utf-8")
    # 干净夹具须由正式生成器补齐快照；反向注入在造仓后发生，漂移仍会报红。
    from 构建装配.形态装配.扩展指纹.核心 import 处理扩展指纹
    if 处理扩展指纹(仓根, False):
        raise RuntimeError("合成仓扩展指纹生成失败")
    建夹具规则库(仓根, 件表)
    写夹具基线(仓根)


def 慢路兜底(仓根: Path) -> None:
    """快照不可用（自校不过）时的老路 —— 逐件写盘 + 建夹具规则库 + 写夹具基线。

    `造干净仓` 在 `铺夹具快照` 返假时调它。**这是永久退路**：一旦退到这里，
    本进程内不再试快照（`快照缓存 = False`）⇒ 不会反复付自校的钱。
    """
    _按老路建(仓根)


def 自校(件字节表: dict) -> list:
    """**真跑一遍对照**：快照重放 vs 老路重建，逐件比件名与字节 ⇒ 差异行表（空 = 等价）。

    为什么不只跟「造快照那份底稿」比（那样是自证）：底稿就是快照的来源，拿它比只能证明
    读写自洽。本函数另建**一份新的老路仓** ⇒ 两棵**独立**树对比，证的是「铺字节」与
    「逐件写盘 + 建库」在端到端上等价。
    """
    with tempfile.TemporaryDirectory(prefix="夹具自校-") as 临时目录:
        快照侧 = Path(临时目录) / "快照侧"
        老路侧 = Path(临时目录) / "老路侧"
        铺字节(快照侧, 件字节表)
        _按老路建(老路侧)
        return 判两仓等价(快照侧, 老路侧)


def 取夹具快照():
    """惰性建一次快照并**自校** ⇒ `(件字节表, 父目录集)`；自校不过 ⇒ 永久退老路（`None`）。

    每进程只建一次：快照的输入是**纯函数** `干净合成仓()` 的产物 ⇒ 同一进程内不会变。
    """
    global 快照缓存
    if 快照缓存 is None:
        with tempfile.TemporaryDirectory(prefix="夹具底稿-") as 临时目录:
            底稿 = Path(临时目录) / "底稿"
            _按老路建(底稿)
            件字节表 = _读底稿(底稿)
        差异表 = 自校(件字节表)
        if 差异表:
            快照缓存 = False
            print("夹具快照自校不过（%d 处）⇒ 永久退回逐件写盘：%s" % (len(差异表), 差异表[:3]))
        else:
            快照缓存 = (件字节表, _取父目录集(件字节表))
    if 快照缓存 is False:
        return None
    return 快照缓存


def 铺夹具快照(仓根: Path) -> bool:
    """把快照铺到目标仓根 ⇒ 是否铺成（`False` = 该走 `慢路兜底`）。

    铺出的是**字节副本**：每个样本一棵独立的新树，样本之间不互通（红线，见文件头）。
    """
    快照 = 取夹具快照()
    if not 快照:
        return False
    件字节表, 父目录集 = 快照
    铺字节(仓根, 件字节表, 父目录集)
    return True


def 自校判据() -> list:
    """本机制自身的**身份证**（真跑 · 可粘贴）：等价必须判等价、篡改必须被抓。

    正反成对（`判据的可信性.md` §三.5：判据的解析器也是假绿来源，故它自身也要有身份证）：
      · 正向：同一份件字节铺两次 ⇒ `判两仓等价` 必须**空**（等价不许被判成不等价）；
      · 反向：往其中一棵里改一个字节 ⇒ `判两仓等价` 必须**报出那一件**（不等价不许漏）。
    两棵仓都在临时目录里，跑完即弃 ⇒ 一个字节都不落仓外。

    怎么跑（在仓库根；`sys.path` 要能 import 到本包）：
        python3 -c "import sys; sys.path.insert(0, '构建装配/一键验证'); \\
from 一键验证.共享夹具.合成仓_快照 import 自校判据; \\
[print(('✓' if 好 else '✗'), 名, '|', 说明) for 名, 好, 说明 in 自校判据()]"
    """
    输出缓冲 = []
    快照 = 取夹具快照()
    if not 快照:
        输出缓冲.append(("快照可用", False, "自校不过 ⇒ 本机制已退老路，拿不到快照"))
        return 输出缓冲
    件字节表, 父目录集 = 快照
    with tempfile.TemporaryDirectory(prefix="夹具快照身份证-") as 临时目录:
        探针仓 = Path(临时目录) / "探针仓"
        复制仓 = Path(临时目录) / "复制仓"
        铺字节(探针仓, 件字节表, 父目录集)
        铺字节(复制仓, 件字节表, 父目录集)
        首次差异 = 判两仓等价(探针仓, 复制仓)
        输出缓冲.append(
            ("正向：同一份件字节铺两次 ⇒ 判两仓等价必须为空（等价不许判成不等价）",
             not 首次差异,
             "差异 %d 处（要求 0）" % len(首次差异)))
        篡改件 = "契约声明/平台声明.json"
        (复制仓 / 篡改件).write_bytes((复制仓 / 篡改件).read_bytes() + b" ")
        差异表 = 判两仓等价(探针仓, 复制仓)
        报出篡改 = False
        for 差异行 in 差异表:
            if 篡改件 in 差异行:
                报出篡改 = True
        输出缓冲.append(
            ("反向：改一个字节 ⇒ 判两仓等价必须报出该件（不等价不许漏）",
             报出篡改,
             "差异 %s（要求含 `%s`）" % (差异表[:2], 篡改件)))
    return 输出缓冲
