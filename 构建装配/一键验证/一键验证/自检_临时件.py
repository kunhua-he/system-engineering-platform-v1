# -*- coding: utf-8 -*-
"""临时件扫描面排除的承重证明。"""

from __future__ import annotations

import tempfile
from pathlib import Path

from . import 常量

from .合成仓 import 造干净仓
from .常量 import 检查名
from .注入 import 注入_临时件落源码树
from .验证 import 验证


def 自检_临时件排除承重() -> list:
    """判据 ⑰ 的扫描面排除**承重证明**（关/开对照）。

    临时件落树里会让**别的**判据一起报假红（实测 ⑬ 报 9 条 · ⑮ 报 1 条）。
    本实现按 `_临时_` 前缀把临时件排除在扫描面外 —— 但「排除」本身也要有身份证：
      · 开着排除：注入 `_临时_` 临时根 ⇒ ⑬ / ⑮ 都不报（假红被挡住），⑰ 报（纪律仍钉住）；
      · 关掉排除（前缀换成永不匹配）：**同一注入** ⇒ ⑬ / ⑮ 必须报（证明排除真的在承重）。
    """
    import tempfile

    出 = []
    临时名 = 检查名[16]

    def 命中(结果, 名):
        return [
            条
            for 条 in 结果["失败"] + 结果["未判"]
            if isinstance(条, dict) and 条["检查"] == 名
        ]

    with tempfile.TemporaryDirectory(prefix="一键验证临时件承重-") as 临时:
        临根 = Path(临时) / "仓"
        造干净仓(临根)
        注入_临时件落源码树(临根)
        开 = 验证(临根, 两遍=False)
    出.append(
        (
            "反向样本：临时件在树里 ⇒ ⑰ 报（纪律钉住）",
            bool(命中(开, 临时名)),
            f"⑰ 报 {len(命中(开, 临时名))} 条（要求非空）",
        )
    )
    出.append(
        (
            "正向样本：临时件在树里 ⇒ ⑬ / ⑮ 都不报（扫描面排除生效）",
            not 命中(开, 检查名[12]) and not 命中(开, 检查名[14]),
            f"⑬ 报 {len(命中(开, 检查名[12]))} 条 · ⑮ 报 {len(命中(开, 检查名[14]))} 条（都要求 0）",
        )
    )
    # 关掉排除：同一注入，⑬ / ⑮ 必须报（先按正常前缀造好注入，再关排除重跑）
    with tempfile.TemporaryDirectory(prefix="一键验证临时件承重关-") as 临时:
        临根2 = Path(临时) / "仓"
        造干净仓(临根2)
        注入_临时件落源码树(临根2)
        原前缀 = 常量.临时目录前缀
        try:
            常量.临时目录前缀 = "\x00关掉排除"
            关 = 验证(临根2, 两遍=False)
        finally:
            常量.临时目录前缀 = 原前缀
    出.append(
        (
            "承重证明（关/开对照）：关掉排除 + 同一注入 ⇒ ⑬ / ⑮ 报（排除真的在挡假红）",
            bool(命中(关, 检查名[12])) or bool(命中(关, 检查名[14])),
            f"关掉后 ⑬ 报 {len(命中(关, 检查名[12]))} 条 · "
            f"⑮ 报 {len(命中(关, 检查名[14]))} 条（至少一个非空）",
        )
    )
    return 出
