from ..基础定义 import 判据取值常量


def 取查名():
    """惰性取**命名规范的口径**（`开发工具/代码地图/查名.py`）—— 规则只此一份。

    取法照判据 ⑲ 引 `开发工具/查文件行数/行数判据.py` 的先例：**工具从「判据自身所在的仓」取**，
    不从被扫的仓取（夹具仓没有这些工具）。
    """
    import sys as _sys

    根目录 = str(判据取值常量.仓根 / "开发工具")
    if 根目录 not in _sys.path:
        _sys.path.insert(0, 根目录)
    import 代码地图.查名 as 查名

    return 查名


def 逐命名件(上层读数: dict):
    """产出 `(路径, 文本)` —— 扫描面里的命名件（按 `查名.命名后缀` 筛）。

    面口径**只此一份**：后缀表由 `取查名()` 给（它是闸那份权威的转口）。
    """
    源码后缀 = 取查名().命名后缀
    for 路径, 文件项 in 上层读数["文件"].items():
        源文本 = 文件项.get("文本")
        if 源文本 is not None and 路径.endswith(源码后缀):
            yield 路径, 源文本
