# -*- coding: utf-8 -*-
"""冻结形状 —— 抽「落点符号的**声明文本**」并算形状指纹（判据 ⑨ 用）。

**为什么要有这一件**（裁决 `决策记录/2026-09-27_判据口径十一条.md` §十）：
`契约声明/冻结登记.json` 的 `冻结项` 里 `内容` 是散文，散文判不了「形状被悄悄改动」——
而「没有登记的形状变化视为违规」是那份登记自身写的纪律，没有指纹这条纪律就没有执行者。
指纹值 = `sha256(规范化后的声明文本)[:16]`。

**为什么指纹取「规范化后的声明文本」而不是原始字节**：冻的是**形状**（字段与顺序与类型），
不是注释与排版。拿原始字节算 ⇒ 改一处 `///` 注释就报「形状被改了」，那是假红；
假红会让这条判据被绕过（同 §十三 的理由）。规范化 = ① 去掉 `//` 与 `///` 注释
② 连续空白压成一个空格 ③ 首尾去空。

**不新造一套 Rust 解析**：本件只认四种声明头（`struct` / `enum` / `type` / `fn`）+
配对花括号（或到分号），与 `构造点.py::_抽平台信息字段` 同一个路子（那边只抽字段名，
这边要整段声明文本）。**不许 import `测试验证/契约一致性/扫实现/源码解析/符号解析.py`**：
闸 1 查声明侧、闸 2 查实现侧，闸 1 不调用闸 2（`扫实现/模块说明.py` 定的边界）。
"""

from __future__ import annotations

import hashlib
import re

# 声明头：`pub [unsafe] [extern "C"] (struct|enum|type|fn|const) 名`
_声明头 = re.compile(
    r"pub\s+(?:unsafe\s+)?(?:extern\s+\"[^\"]*\"\s+)?(struct|enum|type|fn|const)\s+"
    r"([A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*)"
)
_行注释 = re.compile(r"//[^\n]*")


def 去注释(源文本: str) -> str:
    """去掉 `//` 与 `///` 行注释（形状与注释无关；块注释本仓不用）。"""
    return _行注释.sub("", 源文本)


def _配括号(源文本: str, 开位置: int, 开符: str, 闭符: str) -> int:
    """返回与 `文本[开位置]`（= 开符）配对的闭符下标；找不到给 `len(文本)`。"""
    嵌套深度 = 0
    for 字节位置 in range(开位置, len(源文本)):
        if 源文本[字节位置] == 开符:
            嵌套深度 += 1
        elif 源文本[字节位置] == 闭符:
            嵌套深度 -= 1
            if 嵌套深度 == 0:
                return 字节位置
    return len(源文本)


def 抽符号声明文本(源文本: str, 符号名: str) -> "str | None":
    """从一份 `.rs` 文本里抽 `符号名` 的**声明文本**（含声明头到形状体结束）；抽不到给 `None`。

    认四种：`struct` / `enum` 到配对 `}`；`type` 到 `;`；`fn` 到配对 `}` 或 `;`（声明式）；
    `const` 到 `;`。**同名多处 ⇒ 取第一处**（冻结项的落点是「单个符号」，重名本身是缺陷，
    由别的判据去管）。
    """
    净文本 = 去注释(源文本)
    for 匹配结果 in _声明头.finditer(净文本):
        扩展种类, 名称 = 匹配结果.group(1), 匹配结果.group(2)
        if 名称 != 符号名:
            continue
        区间起点 = 匹配结果.start()
        体起 = 净文本.find("{", 匹配结果.end())
        分号 = 净文本.find(";", 匹配结果.end())
        if 扩展种类 in ("struct", "enum") and 体起 != -1:
            区间终点 = _配括号(净文本, 体起, "{", "}") + 1
        elif 扩展种类 == "fn" and 体起 != -1 and (分号 == -1 or 体起 < 分号):
            区间终点 = _配括号(净文本, 体起, "{", "}") + 1
        elif 分号 != -1:
            区间终点 = 分号 + 1
        else:
            区间终点 = len(净文本)
        return 净文本[区间起点:区间终点]
    return None


def 规范形状(声明文本: str) -> str:
    """规范化：连续空白压成一个空格、首尾去空（**注释已由 `抽符号声明文本` 去掉**）。"""
    return re.sub(r"\s+", " ", 声明文本).strip()


def 形状指纹(声明文本: str) -> str:
    """`sha256(规范形状)[:16]`（与生成器的 `源指纹()` 同一长度口径）。"""
    return hashlib.sha256(规范形状(声明文本).encode("utf-8")).hexdigest()[:16]


def 算落点指纹(文件文本: str, 符号名: str) -> "tuple[str | None, str]":
    """→ `(指纹, 说明)`；抽不到声明文本时指纹给 `None` 并在说明里写清为什么。"""
    声明 = 抽符号声明文本(文件文本, 符号名)
    if 声明 is None:
        return None, f"在文件里找不到 `pub struct/enum/type/fn/const {符号名}` 的声明"
    return 形状指纹(声明), 规范形状(声明)
