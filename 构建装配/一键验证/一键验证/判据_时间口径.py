# -*- coding: utf-8 -*-
"""判据 ㉑：时间口径（时间主人只用单调时钟 · 单位进名字）。"""

from __future__ import annotations

import re

from .小工具 import 判不了, 违规
from .常量 import 单位词表, 时间口径面, 检查名


# 标识符：以字母/下划线/汉字开头，后跟字母数字下划线汉字。
_标识符 = re.compile(r"[A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*")


def _去注释(源码行: str) -> str:
    """去掉行注释（`//` 之后）。本判据只看**代码里的标识符**，不看注释里的散文。"""
    注释起 = 源码行.find("//")
    return 源码行[:注释起] if 注释起 >= 0 else 源码行


# 「量」的声明形：常量 / 静态量（`const 名: 类型`）与结构体字段（`pub 名: 类型`）。
# 只认这两种 —— 段位名（`超时` 是 enum 变体）、测试函数名（`实测_空调用耗时量级`）**不是量**，
# 它们不承载「几毫秒还是几微秒」这件事（实测第一版按「名字里含超时/耗时」扫，误报三处）。
_常量声明 = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:const|static)\s+([0-9A-Za-z_\u4e00-\u9fff]+)")
_字段声明 = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)([0-9A-Za-z_\u4e00-\u9fff]+)\s*:")


# 第三种形：`pub use 模块::{名, 名};` —— 量的**定义处**可能不在这两个 crate 里。
# 实测（2026-09-27）：`单项超时毫秒` 现在的唯一来源是 `契约声明/常量表.json`（生成物），
# `调用调度` 只有一行 `pub use`（手写的那份早删了，因为「同一个常量名不许在别处再定义」）。
# ⇒ 只认 `const`/字段 会**漏掉真正的量**，判据报「找不到」而未判。
_再导出 = re.compile(r"^\s*pub\s+use\s+[^;{]*\{([^}]*)\}")


def _抽量名(文本: str) -> set:
    """抽**量**的名字：常量 / 静态量 · 结构体字段 · `pub use` 再导出的名字。段位名与函数名不在内。"""
    输出缓冲 = set()
    for 源码行 in 文本.split("\n"):
        代码行 = _去注释(源码行)
        for 格式器 in (_常量声明, _字段声明):
            匹配结果 = 格式器.match(代码行)
            if 匹配结果:
                输出缓冲.add(匹配结果.group(1))
        匹配结果 = _再导出.match(代码行)
        if 匹配结果:
            输出缓冲 |= {名字.strip() for 名字 in 匹配结果.group(1).split(",") if 名字.strip()}
    return 输出缓冲


def _抽标识符(文本: str) -> set:
    """抽全部标识符（只用来确认「主人还在」这一条 sanity，不用来判违规）。"""
    输出缓冲 = set()
    for 源码行 in 文本.split("\n"):
        for 匹配结果 in _标识符.finditer(_去注释(源码行)):
            输出缓冲.add(匹配结果.group(0))
    return 输出缓冲


def 检查21_时间口径(上层读数: dict) -> list:
    """时间口径：**时间主人只用单调时钟**（`Instant`）· **单位进名字**（超时=毫秒 · 留痕=微秒）。

    依据 `项目文档/决策记录/2026-09-27_补主人与核心预算.md` §一 第 3 条：时间口径的唯一主人是
    `调用调度`（超时）与 `调用留痕`（耗时）；一律 `std::time::Instant`（单调时钟），
    **不许用墙钟算耗时**（墙钟会跳）；单位：超时 = **毫秒** · 留痕 = **微秒**；
    超时基准 = **这一次调用**，不跨调用累积。

    为什么是**两条**而不是一条：① 墙钟禁令管「用哪个时钟」；② 单位进名字管「这个数是几毫秒还是几微秒」——
    后者是**名字里的单位**，不是注释里的散文。注释会被改掉，名字不会。

    三元读数：**通过** = 扫描面非空且 0 命中；**失败** = 命中逐条报出；
    **未判** = 扫描面下 0 个件，或两个量一个都找不到（那说明主人被搬走/改名，不是「没问题」）。
    """
    输出缓冲 = []
    件表 = {
        键名: 一项["文本"]
        for 键名, 一项 in 上层读数["文件"].items()
        if 键名.endswith(".rs")
        and any(键名.startswith(面 + "/") for 面 in 时间口径面)
        and 一项.get("文本") is not None
    }
    if not 件表:
        判不了(
            检查名[20],
            " · ".join(时间口径面),
            f"扫描面下 0 个 `.rs` 件（时间口径的两个主人：{' · '.join(时间口径面)}）",
            "判据的可信性.md 第二节：空集是**未判**，不是通过。要么扫描面坏了、"
            "要么主人被搬走 —— 两种都只能由该实现方确认（读数为 0 不许当成绿）",
        )
        return 输出缓冲

    for 键名 in sorted(件表):
        for 序号, 源码行 in enumerate(件表[键名].split("\n")):
            if "SystemTime" not in _去注释(源码行):
                continue
            输出缓冲.append(
                违规(
                    检查名[20],
                    f"{键名} 第 {序号 + 1} 行",
                    f"时间主人里出现墙钟 `SystemTime`（原文：{源码行.strip()[:80]}）",
                    "决策记录 2026-09-27_补主人与核心预算.md §一 第 3 条：时间口径一律 "
                    "`std::time::Instant`（单调时钟）—— **墙钟会跳**（对时 / 夏令时 / 手动改表），"
                    "用它算耗时或超时会让读数与事实相反。记「这件事发生在哪一刻」用墙钟没问题，"
                    "但那不属于本判据的两个主人（超时 · 耗时）⇒ 只能由该实现方改",
                )
            )

    缺单位 = []
    见过表 = {"超时": False, "耗时": False}
    for 键名 in sorted(件表):
        量名 = _抽量名(件表[键名])
        for 名称 in sorted(_抽标识符(件表[键名])):
            for 类别 in ("超时", "耗时"):
                if 类别 in 名称:
                    见过表[类别] = True   # sanity 用全部标识符：主人还在就够
        for 名称 in sorted(量名):
            for 类别 in ("超时", "耗时"):
                if 类别 in 名称 and not any(单位 in 名称 for 单位 in 单位词表):
                    缺单位.append((键名, 名称, 类别))
    for 键名, 名称, 类别 in 缺单位:
        输出缓冲.append(
            违规(
                检查名[20],
                f"{键名}::{名称}",
                f"{类别}量的名字 `{名称}` 里没有单位（认的单位词：{' · '.join(单位词表)}）",
                "决策记录 2026-09-27_补主人与核心预算.md §一 第 3 条：超时 = **毫秒** · 留痕 = **微秒**。"
                "单位必须进**名字**：注释会被改掉，名字不会 —— 名字里没单位，读的人只能去猜"
                "（「这个数是秒还是毫秒」猜错一次就是一次线上误判）⇒ 只能由该实现方改名",
            )
        )
    缺谁 = [类别 for 类别, 是否见过 in 见过表.items() if not 是否见过]
    if 缺谁:
        判不了(
            检查名[20],
            " · ".join(时间口径面),
            f"扫描面下找不到带「{'」「'.join(缺谁)}」的**量**（常量 / 字段）⇒ 单位进名字这一半判不了",
            "这两个量是时间口径**唯一主人**的公开面（调用调度 · 调用留痕）；一个都找不到，"
            "说明主人被搬走或改名了 ⇒ 只能由该实现方确认（找不到不许当成绿）",
        )
    return 输出缓冲
