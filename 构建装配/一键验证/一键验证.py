    # **不参与运行**」，验证器与生成器是开发期工具，不是平台运行时的一条腿。
    跳过工具目录 = ("构建装配/", "开发工具/")
    扫描件源 = [
        (键, 项["文本"])
        for 键, 项 in 文件.items()
        if 键.endswith(代码后缀)
        and 项["文本"] is not None
        and not 键.startswith(跳过工具目录)
    ]
    代码件 = 并行生产区(扫描件源, 上["测试文件集"])

    def 命中处(模式, 件表=None):
        处 = []
        for 键, 文本 in (代码件 if 件表 is None else 件表).items():
            for 命 in 模式.finditer(文本):
                处.append(f"{键}:{文本[: 命.start()].count(chr(10)) + 1}")
        return 处

    def 命中位置(标目: str, 处表: list) -> str:
        """位置字段：有命中就列出来（「哪个文件」要落在位置里），没有就给标目。"""
        if not 处表:
            return f"全仓代码:{标目}"
        return f"全仓代码:{标目}（命中 {len(处表)} 处：{' · '.join(处表)}）"

    # ── 1 对外监听恰好 1 处 ──
    监听 = 命中处(监听模式)
    if len(监听) != 1:
        情形 = (
            "一处都没有 ⇒ 不是「多了一条腿」，是「腿还没接上」（全局网关 尚未落地）"
            if not 监听
            else f"多出来的就是第二条腿：{监听[1:]}"
        )
        出.append(
            违规(
                检查名[10],
                命中位置("对外监听", 监听),
                f"对外监听 {len(监听)} 处（判据要求恰好 1 处）——{情形}",
                f"全局连接器与网关 第四节判据 1：对外监听是可数的出入口，必须恰好 1 个。"
                f"验证面不能替网关写一个监听点（那就是第二套实现）⇒ 只能由接口面节点落地；"
                f"若确实多了一处，摘掉哪一处是拓扑裁决 ⇒ 只能人来裁",
            )
        )

    # ── 2a 宿主侧「对外边界」恰好 1 组（三个符号；接缝 GetPlatformInfo 不算）──
    #     导出符号名写在字符串里 ⇒ 这一处必须用**保串**的生产区文本
    导出表 = 收集导出(并行生产区(扫描件源, 上["测试文件集"], 保串=True))
    对外名 = sorted(名 for 名 in 导出表 if 名 != 接缝符号)
    缺名 = [名 for 名 in 对外边界符号 if 名 not in 对外名]
    多名 = [名 for 名 in 对外名 if 名 not in 对外边界符号]
    if 缺名 or 多名:
        情形 = (
            f"一个都没导出 ⇒ 不是「多了一条腿」，是「腿还没接上」"
            f"（跨语言适配/适配器实现/ 只给了 Rust 安全入口，还没出 C ABI 面）"
            if not 对外名
            else f"多出来的就是第二条对外面：{多名}"
        )
        命中处表 = [处 for 名 in 多名 for 处 in 导出表.get(名, [])]
        出.append(
            违规(
                检查名[10],
                "全仓代码:宿主侧对外边界"
                + (f"（现有导出 {对外名}：{' · '.join(命中处表) or '位置未取到'}）" if 对外名 else ""),
                f"宿主侧对外边界符号 {len(对外名)} 个（判据要求恰好 1 组 = 三个："
                f"{(' · '.join(对外边界符号))}）：缺 {缺名 or '无'} · 多 {多名 or '无'}——{情形}",
                f"边界协议 第四节判据 1：对外边界是**三个符号**（读接口 / 调用 / 释放值），"
                f"不是一组同义词，也不含接缝 `{接缝符号}`（那是扩展 → 宿主方向，每个扩展各一个）。"
                f"少一个 ⇒ 那条腿还没接上；多一个 ⇒ 第二个对外面，等于给某语言开了专用通道"
                f"（开发规范 B5）。补或撤哪一处是拓扑裁决 ⇒ 只能由跨语言适配节点落地 / 人来裁",
            )
        )

    # ── 3 内核入口恰好 1 处调用 载入 ──
    #     只认**调用**：排除定义（`fn 载入(`）与枚举变体声明（`载入(载入错误),` 这种裸行）
    枚举变体形 = re.compile(r"^载入\s*\([^;]*\)\s*,?\s*$")
    载入处 = []
    for 键, 文本 in 代码件.items():
        for 命 in re.finditer(r"(?<![\w])载入\s*\(", 文本):
            行起 = 文本.rfind("\n", 0, 命.start()) + 1
            行 = 文本[行起 : 文本.find("\n", 命.start())]
            if re.search(r"\bfn\s+载入\s*\(", 行):
                continue  # 定义处
            if 枚举变体形.match(行.strip()):
                continue  # 枚举变体声明，不是调用
            载入处.append(f"{键}:{文本[: 命.start()].count(chr(10)) + 1}")
    if len(载入处) != 1:
        情形 = (
            "一处都没有 ⇒ 内核入口还没被接上（网关 / 连接器 尚未落地）"
            if not 载入处
            else f"多出来的就是第二条腿：{载入处[1:]}"
        )
        出.append(
            违规(
                检查名[10],
                命中位置("载入 调用点", 载入处),
                f"调用内核入口 `载入` 的处数 {len(载入处)}（判据要求恰好 1 处）——{情形}",
                f"判据 3：读契约 → 建注册表 → 交控制权 这条路只能有一条。"
                f"第二条调用点就是绕过网关的第二条腿。验证面不能替它补一条（第二套实现）⇒ "
                f"只能由 对外接口面 / 跨语言适配 落地；撤哪一处是拓扑裁决 ⇒ 只能人来裁",
            )
        )

    # ── 4 资源出入口恰好 1 处 ──
    资源处 = 命中处(资源出入口模式)
