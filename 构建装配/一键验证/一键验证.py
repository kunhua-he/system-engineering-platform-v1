def 去字面量(文本: str) -> str:
    """注释 · 字符串 · 字符字面量的内容换成等长空格（长度不变 ⇒ 行号与偏移仍对齐）。

    为什么要它：大括号配对与「这一段里有没有某名字」都要在**代码**上做，
    注释里写 `static 平台信息 {` 不算手写实现，字符串里的 `{` 不该参与配对。
    """
    净 = re.sub(r"/\*.*?\*/", lambda m: " " * len(m.group(0)), 文本, flags=re.S)
    净 = re.sub(r"//[^\n]*", lambda m: " " * len(m.group(0)), 净)
    净 = re.sub(r'r#*"[\s\S]*?"#*', lambda m: " " * len(m.group(0)), 净)
    净 = re.sub(r'b?"(?:\\.|[^"\\])*"', lambda m: " " * len(m.group(0)), 净)
    净 = re.sub(r"b?'(?:\\.|[^'\\])'", lambda m: " " * len(m.group(0)), 净)
    return 净


def cfg测试区(文本: str) -> list:
    """`#[cfg(test)]` 覆盖的字符区间表 [(起, 止)]（按大括号配对求边界）。"""
    净 = 去字面量(文本)
    区表 = []
    for 命 in re.finditer(r"#\[cfg\(test\)\]", 净):
        起 = 净.find("{", 命.end())
        if 起 < 0:
            continue
        深 = 0
        for i in range(起, len(净)):
            if 净[i] == "{":
                深 += 1
            elif 净[i] == "}":
                深 -= 1
                if 深 == 0:
                    区表.append((起, i))
                    break
    return 区表


构造模式 = re.compile(r"平台信息\s*\{")
具名项头 = re.compile(
    r"^([ \t]*)(?:pub(?:\([^)]*\))?[ \t]+)?(static|const|fn)[ \t]+([^\s:(<]+)"
)
# 这些出现在同一行且位于 平台信息 之前 ⇒ 它不是一个「构造」，而是类型声明/返回类型/impl 头
非构造标记 = ("->", "struct ", "enum ", "impl ", "trait ")
# 构造点前一个非空白字符只可能是这些（表达式位置）
构造前导 = ("=", "(", ",", "[", "{", ":")


def 找构造点(文本: str) -> list:
    """找出所有 `平台信息 { … }` **构造点**（不是类型声明、不是返回类型）。

    区分办法：同一行里 平台信息 之前出现 `->` / `struct` / `enum` / `impl` / `trait`
    的，是类型位置；前一个非空白字符不在 `= ( , [ { :` 里的，也不是构造。
    """
    净 = 去字面量(文本)
    区表 = cfg测试区(文本)
    行首表 = [0]
    for i, c in enumerate(净):
        if c == "\n":
            行首表.append(i + 1)

    def 行号(位: int) -> int:
        低, 高 = 0, len(行首表) - 1
        while 低 < 高:
            中 = (低 + 高 + 1) // 2
            if 行首表[中] <= 位:
                低 = 中
            else:
                高 = 中 - 1
        return 低 + 1

    def 行文(位: int) -> str:
        起 = 行首表[行号(位) - 1]
        止 = 文本.find("\n", 起)
        return 文本[起 : 止 if 止 >= 0 else len(文本)].strip()

    点表 = []
    for 命 in 构造模式.finditer(净):
        行 = 行号(命.start())
        行起 = 行首表[行 - 1]
        行内前文 = 净[行起 : 命.start()]
        if any(标 in 行内前文 for 标 in 非构造标记):
            continue
        前文紧 = 净[: 命.start()].rstrip()
        if not 前文紧 or 前文紧[-1] not in 构造前导:
            continue
        起 = 命.end() - 1
        深 = 0
        止 = None
        for i in range(起, len(净)):
            if 净[i] == "{":
                深 += 1
            elif 净[i] == "}":
                深 -= 1
                if 深 == 0:
                    止 = i
                    break
        if 止 is None:
            止 = len(净) - 1
        字段 = {}
        for 行文段 in 文本[起 + 1 : 止].splitlines():
            段 = 行文段.strip().rstrip(",")
            if not 段 or ":" not in 段:
                continue
            名, _, 值 = 段.partition(":")
            字段[名.strip()] = 值.strip()
        # 所属具名项：先看**本行**是不是项头（`static 底座存储: … = …(平台信息 {`）；
        # 否则用「往回找块开括号」定到所在块，再取该块的项头（`fn 夹具…() {`）。
        # 不按缩进猜——同一块里的兄弟 `static` 缩进相同，猜法会取错（实测撞到过）。
        具名 = ""
        行起位 = 行首表[行 - 1]
        同行前文 = 净[行起位 : 命.start()]
        配 = 具名项头.match(同行前文)
        if 配:
            具名 = 配.group(3)
        else:
            位 = 命.start()
            for _ in range(3):  # 最多上溯三层（mod 套 fn 之类）
                块起 = -1
                深 = 0
                for i in range(位 - 1, -1, -1):
                    if 净[i] == "}":
                        深 += 1
                    elif 净[i] == "{":
                        if 深 == 0:
                            块起 = i
                            break
                        深 -= 1
                if 块起 < 0:
                    break
                块行 = 行号(块起)
                块行起 = 行首表[块行 - 1]
                块上行 = 文本[块行起 : 文本.find("\n", 块行起) if 文本.find("\n", 块行起) >= 0 else len(文本)]
                配 = 具名项头.match(块上行)
                if 配:
                    具名 = 配.group(3)
                    break
                位 = 块起
        点表.append(
            {
                "行号": 行,
                "头行": 行文(命.start()),
                "字段": 字段,
                "测试区": any(a <= 命.start() <= b for a, b in 区表),
                "具名项": 具名,
            }
        )
    return 点表


def _抽版本三元组(文本: str, 常量名: str):
    """抽 `const 名: 版本三元组 = 版本三元组::新(主, 次, 修订, 构建);` → '主.次.修订.构建'。"""
    形 = re.compile(
        r"const\s+" + re.escape(常量名) + r"\s*:\s*版本三元组\s*=\s*版本三元组::新\s*\("
        r"\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,?\s*\)"
    )
    命中 = 形.search(文本)
    if not 命中:
        return None
    return ".".join(命中.group(i) for i in (1, 2, 3, 4))


def 跑生成器检查(仓根: Path, 生成器: Path) -> tuple:
    """调生成器自己的 --检查（§八：重新生成并与落盘件逐字节比对）。返回 (退出码, 输出摘要)。"""
    try:
        果 = subprocess.run(
            [sys.executable, str(生成器), "--检查"],
            cwd=str(仓根),
            capture_output=True,
            text=True,
            timeout=120,
        )
    except (OSError, subprocess.SubprocessError) as 错:
        return 127, f"起不动生成器：{错}"
    输出 = (果.stdout or "").strip() or (果.stderr or "").strip()
    return 果.returncode, 输出.replace("\n", " ／ ")[:400]


def _抽字节串常量(文本: str, 常量名: str):
    形 = re.compile(
        r"const\s+" + re.escape(常量名) + r'\s*:\s*[^=]+=\s*(?:b)?"((?:[^"\\]|\\.)*)"',
        re.S,
    )
    命中 = 形.search(文本)
    if not 命中:
        return None
    return _解Rust转义(命中.group(1))


_转义表 = {"0": "\0", "n": "\n", "t": "\t", "r": "\r", "\\": "\\", '"': '"', "'": "'"}


def _解Rust转义(原: str) -> str:
    """把 Rust 字面量里的转义还原（`\\0` → NUL），并去掉结尾 NUL（契约要的是 NUL 结尾串）。"""
    出 = []
    序 = 0
    while 序 < len(原):
        if 原[序] == "\\" and 序 + 1 < len(原):
            出.append(_转义表.get(原[序 + 1], 原[序 + 1]))
            序 += 2
        else:
            出.append(原[序])
            序 += 1
    return "".join(出).rstrip("\0")


def _抽整数常量(文本: str, 常量名: str, 类型名: str):
    形 = re.compile(
        r"const\s+" + re.escape(常量名) + r"\s*:\s*" + 类型名 + r"\s*=\s*([0-9_]+)"
    )
    命中 = 形.search(文本)
    if not 命中:
        return None
    try:
        return int(命中.group(1).replace("_", ""))
    except ValueError:
        return None


def _抽平台信息字段(文本: str) -> set:
    """从 契约声明/src/lib.rs 的 `pub struct 平台信息 { … }` 里抽字段名。"""
    形 = re.compile(r"pub\s+struct\s+平台信息\s*\{(.*?)\n\}", re.S)
    命中 = 形.search(文本)
    if not 命中:
        return set()
    字段 = set()
    for 行 in 命中.group(1).splitlines():
        行 = 行.split("//", 1)[0].strip()
        if 行.startswith("pub "):
            声明 = 行[4:].split(":", 1)[0].strip()
            if 声明:
                字段.add(声明)
    return 字段


def 建测试文件集(文件: dict) -> set:
    """整文件都是测试的 .rs（父模块用 `#[cfg(test)] mod X;` 把它挂进来）。

    为什么要它：夹具常被拆成单独文件（`#[path = "测试夹具.rs"] #[cfg(test)] mod 测试夹具;`），
    文件**自己**没有 `#[cfg(test)]` 属性 ⇒ 只看文件内会把它当生产代码（实测撞到过）。
    """
    出 = set()
    # 候选父：**同目录的每一个 .rs**，不只 lib/mod/main。
    # 为什么：实测撞到过 `运行内核/装载入口/src/装载测试.rs` 由**同目录的兄弟文件**
    # `装载.rs` 里的 `#[cfg(test)] #[path = "装载测试.rs"] mod 装载测试;` 挂进来；
    # 只看 lib.rs/mod.rs/main.rs 会漏掉它 ⇒ 夹具被当生产代码 ⇒ 假红。
    # （Rust 里 `#[path]` 是相对**当前文件所在目录**解析的，所以同目录任意 .rs 都可能是父。）
    同目录 = {}
    for 键, 项 in 文件.items():
        if not 键.endswith(".rs") or 项["文本"] is None:
            continue
        同目录.setdefault("/".join(键.split("/")[:-1]), []).append((键, 去字面量(项["文本"])))
    for 键, 项 in 文件.items():
        if not 键.endswith(".rs") or 项["文本"] is None:
            continue
        段 = 键.split("/")
        if len(段) < 2:
            continue
        目录 = "/".join(段[:-1])
        杆 = 段[-1][:-3]
        if 杆 in ("lib", "mod", "main"):
            continue
        形 = (
            r"#\[cfg\(test\)\]\s*(?:#\[[^\]]*\]\s*)*(?:pub(?:\([^)]*\))?\s+)?mod\s+"
            + re.escape(杆)
            + r"\s*;"
        )
        for 父键, 父净 in 同目录.get(目录, ()):
            if 父键 == 键:
                continue
            if re.search(形, 父净):
                出.add(键)
                break
    return 出


def 生产区文本(文本: str, 保串: bool = False) -> str:
    """去注释 + 抹掉 `#[cfg(test)]` 区 ⇒ 只剩生产代码。

    `保串=真` 时**保留字符串字面量**——数导出符号名必须保串（符号名就写在字符串里；
    实测撞到过：先去字面量会把 `export_name = "平台_调用"` 的名字抹成空白 ⇒ 数出 0 组）。
    """
    净 = 去字面量(文本) if not 保串 else 去注释保串(文本)
    出区 = list(净)
    for 起, 止 in cfg测试区(文本):
        for i in range(起, min(止 + 1, len(出区))):
            出区[i] = " "
    return "".join(出区)


def 去注释保串(文本: str) -> str:
    """去注释（长度不变），**字符串字面量原样保留**。"""
    净 = re.sub(r"/\*.*?\*/", lambda m: " " * len(m.group(0)), 文本, flags=re.S)
    return re.sub(r"//[^\n]*", lambda m: " " * len(m.group(0)), 净)


def 并行生产区(件表: list, 测试文件集=frozenset(), 保串: bool = False) -> dict:
    件表 = [(键, 文本) for 键, 文本 in 件表 if 文本 is not None]
    with ThreadPoolExecutor(max_workers=并发度) as 池:
        return dict(
            池.map(
                lambda 项: (
                    项[0],
                    "" if 项[0] in 测试文件集 else 生产区文本(项[1], 保串),
                ),
                件表,
            )
        )


def 收集导出(代码件: dict) -> dict:
    """导出符号名 → 出现处。`export_name` 取属性里的名字；`no_mangle` 取紧跟的 fn 名。"""
    出 = {}
    for 键, 文本 in 代码件.items():
        for 命 in 导出名模式.finditer(文本):
            行号 = 文本[: 命.start()].count("\n") + 1
            出.setdefault(命.group(1), []).append(f"{键}:{行号}")
        for 命 in re.finditer(r"#\[no_mangle\]", 文本):
            尾 = 文本[命.end() : 命.end() + 400]
            名配 = re.search(r"\bfn[ \t]+([A-Za-z_]\w*)", 尾)
            名 = 名配.group(1) if 名配 else "（未标名）"
            行号 = 文本[: 命.start()].count("\n") + 1
            出.setdefault(名, []).append(f"{键}:{行号}")
    return 出


def 检查11_拓扑唯一性(上: dict) -> list:
    """每类出入口恰好一个（项目文档/设计文档/全局连接器与网关.md 第四节）。

    六条子判据。判不了的**如实报「判不了 + 缺什么」**，不许写成判过了。
    """
    出 = []
    仓根 = 上["仓根"]
    文件 = 上["文件"]
    # 代码后缀 用模块级那一份（一个地方定义）——原来这里是第二份，实测差点漂移。

    # 生产区文本（去掉 #[cfg(test)] 区）——夹具不算平台代码。
