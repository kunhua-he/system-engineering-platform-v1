def 段归属标签(段: dict) -> str:
    """号段表 `归属` 里 "：" 前那一段（方向标签 / 层级标签）。"""
    文本 = str(段.get("归属", ""))
    for 分隔 in ("：", ":"):
        if 分隔 in 文本:
            return 文本.split(分隔, 1)[0].strip()
    return 文本.strip()


def 层级标签(文本: str) -> str:
    """归属文案里的**层名**：切掉 "：" · "（" · "——" 之后的一切，再去掉 markdown 粗体标记。

    例：「内核自有（不对外）」→「内核自有」；
        「**核心支持库** —— 语言自身的能力（…）」→「核心支持库」；
        「三方封装 · 系统与环境（按**域**分段，以下同）」→「三方封装 · 系统与环境」；
        「下行：宿主 → 扩展」→「下行」。
    两个号空间（能力号 / 错误码段位）写同一层时，括号与破折号后的注解可以不同，层名必须相同。
    """
    文本 = str(文本)
    for 分隔 in ("：", ":"):
        if 分隔 in 文本:
            文本 = 文本.split(分隔, 1)[0]
    文本 = 文本.split("（", 1)[0]
    for 破折 in ("——", "—", " -- ", " - "):
        if 破折 in 文本:
            文本 = 文本.split(破折, 1)[0]
    return 文本.replace("**", "").strip()


def 扫源文件(仓根: Path) -> list:
    """全仓源码文件（跳过生成物与参照物目录）。"""
    结果 = []
    for 根, 目录表, 文件表 in os.walk(仓根):
        目录表[:] = [d for d in 目录表 if d not in 跳过目录]
        for 名 in 文件表:
            if 名.endswith(扫描后缀):
                结果.append(Path(根) / 名)
    return 结果


