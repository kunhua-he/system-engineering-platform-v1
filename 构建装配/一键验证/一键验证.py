def 造干净仓(临根: Path) -> None:
    for 相对路径, 内容 in 干净合成仓().items():
        路径 = 临根 / 相对路径
        路径.parent.mkdir(parents=True, exist_ok=True)
        路径.write_text(内容, encoding="utf-8")


