                    f"前端直连内核、网关直连扩展实现都是跳层。"
                    f"（直接依赖 `{公共底层}` 不算跳层：它是两条链的公共底、自己没有依赖，"
                    f"README 第六节也把它列进了每一层的可依赖层。）"
                    f"改依赖方向是架构级改动；若这一条依赖其实该走中间层，"
                    f"补哪一层是拓扑裁决 ⇒ 只能人来裁",
