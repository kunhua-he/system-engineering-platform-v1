def 自测(源仓根: Path) -> int:
    """逐条判据跑「反向样本 + 正向样本」，并给出每条的身份证。"""
    import tempfile

    print("自测：逐条判据的身份证（反向样本必须报红且报对位置；正向样本必须通过）")
    print("")
    全过 = True
    命中表 = {}

    # ── 反向样本：注入到干净合成仓 ──
    for 名, 该报的检查, 注入, 该出现的路径 in 自测用例:
        with tempfile.TemporaryDirectory(prefix="一键验证反向样本-") as 临时:
            临根 = Path(临时) / "仓"
            造干净仓(临根)
            果 = 注入(临根)
            元数据覆盖 = 果 if isinstance(果, dict) else None
            结果 = 验证(临根, 元数据覆盖=元数据覆盖)
            退出码 = 0 if not 结果["失败"] else 1
            条表 = [条 for 条 in (结果["失败"] + 结果["未判"]) if isinstance(条, dict)]
            命中 = [条 for 条 in 条表 if 条["检查"] == 该报的检查]
            命中位置 = [条 for 条 in 命中 if 该出现的路径 in 条["位置"] or 该出现的路径 in 条["缺什么"]]
            理由合格 = [
                条
                for 条 in 命中位置
                if len(条["不能自愈"]) >= 30 and not any(话 in 条["不能自愈"] for 话 in 空话表)
            ]
            断言 = [
                ("① 退出码非 0", 退出码 != 0),
                (f"② 报出「{该报的检查}」且指到 {该出现的路径}", bool(命中位置)),
                ("③ 理由具体（≥30 字 · 不含空话）", bool(理由合格)),
            ]
            这轮过 = all(好 for _, 好 in 断言)
            全过 = 全过 and 这轮过
            命中表[该报的检查] = 命中表.get(该报的检查, 0) + (1 if 命中位置 else 0)
            print(f"【反向样本·{名}】→ {该出现的路径}    结果：{'过' if 这轮过 else '不过'}")
            for 名目, 好 in 断言:
                print(f"  {'✓' if 好 else '✗'} {名目}")
            for 条 in 命中位置[:2]:
                print(
                    f"  - {条['检查']} ｜ {条['位置']} ｜ 缺什么：{条['缺什么'][:120]} ｜ "
                    f"分类：{条.get('分类')}"
                )
            if not 命中位置:
                print("  实际：该判据没有报出这一条（断言②失败）")
            print("")

    # ── 正向样本：干净合成仓，不注入 ⇒ 所有判据必须通过 ──
    with tempfile.TemporaryDirectory(prefix="一键验证正向样本-") as 临时:
        临根 = Path(临时) / "仓"
        造干净仓(临根)
        结果 = 验证(临根)
    正过 = not 结果["失败"] and not 结果["未判"]
    全过 = 全过 and 正过
    print(f"【正向样本·干净合成仓】不注入任何东西    结果：{'过' if 正过 else '不过'}")
    print(
        f"  通过 {len(结果['通过'])} 项 · 失败 {len([x for x in 结果['失败'] if isinstance(x, str)])} 项 · "
        f"未判 {len([x for x in 结果['未判'] if isinstance(x, str)])} 项 · "
        f"疑似瞬时 {len(结果['疑似瞬时'])} 项"
    )
    if not 正过:
        for 条 in [x for x in 结果["失败"] + 结果["未判"] if isinstance(x, dict)][:6]:
            print(f"  ✗ 干净输入上仍报：{条['检查']} ｜ {条['位置']} ｜ 缺什么：{条['缺什么'][:160]}")
    print("")

    # ── 身份证总表：每条判据都必须有反向样本与正向样本 ──
    print("判据身份证（每条判据 反向样本 + 正向样本）：")
    缺证 = []
    for 名, _函数 in 检查表:
        元 = 判据元数据.get(名, {})
        反 = 元.get("反向样本")
        正 = 元.get("正向样本")
        有反 = bool(反) and 反 in {x[0] for x in 自测用例}
        有正 = bool(正) and 正 == "干净合成仓"
        if not (有反 and 有正):
            缺证.append(名)
        print(f"  {'✓' if (有反 and 有正) else '✗'} {名}")
        print(f"      反向样本：{反 or '（无）'}    正向样本：{正 or '（无）'}")
    if 缺证:
        全过 = False
        print(f"  缺身份证的判据：{缺证}")
    print("")
    print(
        f"自测{'全部通过' if 全过 else '有不过的用例'}："
        f"{len(自测用例)} 个反向样本 + 1 个正向样本"
    )
    return 0 if 全过 else 1


