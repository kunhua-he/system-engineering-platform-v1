def 跑一遍(仓根: Path, 元数据覆盖=None) -> dict:
    """跑一遍全部判据：返回 {检查名: 违规表} + 上下文。"""
    上 = 建上下文(仓根)
    if 元数据覆盖 is not None:
        上["判据元数据覆盖"] = 元数据覆盖
    上["样本清单"] = 样本清单
    上["已执行判据"] = [名 for 名, _ in 检查表]
    未判收集.clear()
    with ThreadPoolExecutor(max_workers=并发度) as 池:
        结果表 = list(池.map(lambda 项: 项[1](上), 检查表))
    子未判 = list(未判收集)
    return {
        "上": 上,
        "结果": {名: r for (名, _), r in zip(检查表, 结果表)},
        "子未判": 子未判,
    }


def 分类红(条: dict) -> str:
    """红的分类（判据的可信性.md 第四节来源 #1 + 半成品）：
    源码错 / 缺件或半成品。判法按「缺什么」里说的是不是「东西还没落地」。
    """
    文 = str(条.get("缺什么", "")) + str(条.get("不能自愈", ""))
    for 词 in ("不存在", "未落地", "还没接上", "一个都没", "一处都没有", "没有可判的样本",
               "找不到", "读不出来", "缺失", "还没出", "尚未落地", "0 个文件", "没有对应常量",
               "不新鲜", "过期", "滞后"):
        if 词 in 文:
            return "缺件或半成品"
    return "源码错"


def 验证(仓根: Path, 两遍=True, 元数据覆盖=None) -> dict:
    起 = time.perf_counter()
    第一 = 跑一遍(仓根, 元数据覆盖)
    第二 = 跑一遍(仓根, 元数据覆盖) if 两遍 else None
    耗时毫秒 = int((time.perf_counter() - 起) * 1000)

    上 = 第一["上"]
    元数据 = 上.get("判据元数据覆盖") or 判据元数据
    通过表, 失败表, 未判表, 瞬时表 = [], [], [], []
    for 名, _ in 检查表:
        违规表 = 第一["结果"].get(名) or []
        第二表 = (第二["结果"].get(名) or []) if 第二 else 违规表

        def 指纹(条):
            return (条["检查"], 条["位置"], 条["缺什么"])

        第二指纹 = {指纹(c) for c in 第二表}
        真红, 瞬时 = [], []
        for 条 in 违规表:
            if 指纹(条) in 第二指纹:
                真红.append(条)
            else:
                瞬时.append(条)
        瞬时.extend(c for c in 第二表 if 指纹(c) not in {指纹(x) for x in 违规表})

        对象数 = 元数据.get(名, {}).get("对象数")
        样本数 = 对象数(上) if callable(对象数) else None
        样本齐 = (
            元数据.get(名, {}).get("反向样本") in 样本清单
            and 元数据.get(名, {}).get("正向样本") in 样本清单
        )

        if 真红:
            失败表.append(名)
            for 条 in 真红:
                条.setdefault("分类", 分类红(条))
                条["_判据"] = 名
            失败表.extend(真红)
        elif 样本数 == 0:
            未判表.append(名)
            未判表.append(
                {
                    "检查": 名,
                    "位置": f"扫描面：{元数据.get(名, {}).get('扫描面')}",
                    "缺什么": "扫描 0 项（该判据的对象当前不存在）",
                    "不能自愈": "判据的可信性.md 第二节：空集是「未判」，不是「通过」——"
                    "对象不存在时这条判据什么都没验，算成通过就是假绿。"
                    "对象的落地不属验证面（验证面不造声明、不造扩展）⇒ 只能由对应节点补",
                    "分类": "缺件或半成品",
                    "_判据": 名,
                }
            )
        elif not 样本齐:
            未判表.append(名)
            未判表.append(
                {
                    "检查": 名,
                    "位置": f"判据元数据:{名}",
                    "缺什么": f"未验证：缺反向样本或正向样本（元数据："
                    f"反向「{元数据.get(名, {}).get('反向样本')}」· "
                    f"正向「{元数据.get(名, {}).get('正向样本')}」）",
                    "不能自愈": "判据的可信性.md 第五节：缺任一方 ⇒ 该判据「未验证」，"
                    "它的「通过」不计入通过数（没有自证能力的判据，不计入通过）⇒ "
                    "只能由判据作者补齐样本",
                    "分类": "源码错",
                    "_判据": 名,
                }
            )
        else:
            通过表.append(名)
    瞬时表 = [{**条, "分类": "疑似瞬时"} for 条 in 瞬时]
    # 子判据空集（判据内部的「这条子判据的对象是空集」）：并进未判逐条。
    # 两遍都出现才算（与红的「真红 / 疑似瞬时」同一条纪律）。
    子未判表 = 第一.get("子未判") or []
    if 第二 is not None:
        子指纹 = {(条["检查"], 条["位置"]) for 条 in (第二.get("子未判") or [])}
        子未判表 = [条 for 条 in 子未判表 if (条["检查"], 条["位置"]) in 子指纹]
    未判表.extend(子未判表)
    return {
        "通过": 通过表,
        "失败": 失败表,
        "未判": 未判表,
        "疑似瞬时": 瞬时表,
        "耗时毫秒": 耗时毫秒,
        "上下文": 上,
    }


def 打印(结果: dict, 流=None) -> None:
    流 = 流 or sys.stdout
    失败项 = [x for x in 结果["失败"] if isinstance(x, str)]
    # 未判按**判据**计（整条判据空集 + 判据内部的子判据空集都算这条判据有未判读数）。
    # 所以「通过 + 失败 + 未判」可能 > 判据总数：同一条判据可以既有真红、又有空集的子判据
    # （实测：⑪ 的判据 2a 真红、判据 6 的对象是空集）。
    未判项 = sorted(
        {x for x in 结果["未判"] if isinstance(x, str)}
        | {x["检查"] for x in 结果["未判"] if isinstance(x, dict)}
    )
    失败条 = [x for x in 结果["失败"] if isinstance(x, dict)]
    未判条 = [x for x in 结果["未判"] if isinstance(x, dict)]
    整条空集 = {x for x in 结果["未判"] if isinstance(x, str)}
    子空集 = [x for x in 未判条 if x["检查"] not in 整条空集]
    print(
        f"通过 {len(结果['通过'])} 项 · 失败 {len(失败项)} 项 · "
        f"未判 {len(未判项)} 项 · 疑似瞬时 {len(结果['疑似瞬时'])} 项 · "
        f"耗时 {结果['耗时毫秒']} ms",
        file=流,
    )
    if 失败条:
        print("", file=流)
        print(f"失败逐条（{len(失败条)} 条）：", file=流)
        for 条 in 失败条:
            print(
                f"- {条['检查']} ｜ {条['位置']} ｜ 缺什么：{条['缺什么']} ｜ "
                f"为什么不能自愈：{条['不能自愈']} ｜ 分类：{条.get('分类')}",
                file=流,
            )
    if 未判条:
        print("", file=流)
        print(
            f"未判逐条（{len(未判条)} 条：整条判据空集 {len(未判条) - len(子空集)} 条 · "
            f"子判据空集 {len(子空集)} 条 · 空集与判不了不算通过）：",
            file=流,
        )
        for 条 in 未判条:
            print(
                f"- {条['检查']} ｜ {条['位置']} ｜ 缺什么：{条['缺什么']} ｜ "
                f"为什么不能自愈：{条['不能自愈']} ｜ 分类：{条.get('分类')}",
                file=流,
            )
    if 结果["疑似瞬时"]:
        print("", file=流)
        print("疑似瞬时（两次运行结果不一致，不当阻断）：", file=流)
        for 条 in 结果["疑似瞬时"]:
            print(
                f"- {条['检查']} ｜ {条['位置']} ｜ 缺什么：{条['缺什么']} ｜ 分类：疑似瞬时",
                file=流,
            )


