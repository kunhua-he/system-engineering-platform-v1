# ★ 等待上界不是「预期耗时」，是**最坏路径**的容忍度 —— 必须小到「最坏仍在顶内」。
#   这条纪律的出处是 `构建装配/演示/常量.py` 的 `停等秒`（那条命令按它改过一次），本件同款。
#
# **最坏路径的算术**（切换档：停旧实例 → 起候选实例 → 停候选 → 在流量端口起目标）：
#   停 2 个实例 × 停等秒 + 等端口 2 次 × 健康超时秒 ≤ 5 秒
#   ⇒ 2×0.5 + 2×1.8 = **4.6 秒** ≤ 4.8（壳自门禁阈值 = 硬顶 5000 − 尾巴余量 200）✓
#
# **实测（2026-09-27，改之前）**：`上线切换.py 切换` 在「两个活实例、其中一个不响应 SIGTERM
# 要走强杀」这条最坏路径上 **6544 ms ⇒ 超顶**（那时 停等秒 = 5.0 · 健康超时秒 = 15.0 ——
# 光一个 `停等秒` 就顶破五秒，最坏路径的账是 2×5 + 2×15 = 40 秒）。同一次实测里
# `回退`（一个实例、干净 SIGTERM）= **910 ms** ⇒ 正常路径本来就在顶内，**超顶的是最坏路径**。
#
# **这两个值的依据（都是实测，不是拍的）**：
#   · 停等秒 0.5 —— 网关收到 SIGTERM 是**立即**走的（实测退出码 -15，正常路径 10 毫秒级）；
#     0.5 秒是「它正忙 / 正载入扩展」时的容忍度。不响应就得强杀，而强杀的代价就是这个数。
#   · 健康超时秒 1.8 —— 「起实例 + 等它打出 `监听 127.0.0.1:<端口>` + 健康检查 200」实测
#     合计约 600 毫秒 ⇒ 1.8 秒是 3 倍余量。
停等秒 = 0.5
健康超时秒 = 1.8

