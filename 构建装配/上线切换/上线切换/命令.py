"""三条命令 —— 装载 · 切换 · 回退（外加只读的现状）与命令行分派。

两处不是「第四条命令」，是**加模式 / 加账**（老仓《设计哲学》第 8 条②「底子不同但格式一样
⇒ 加模式变量」；依据 `决策记录/2026-09-27_待裁九项按老仓设计哲学裁决.md` 裁决 7 与 #81）：

  · **模式=停**：`切换 --模式=停` —— 与 切换/回退 **同一个底子**（停实例 + 处置流量口），
    只是「停完不起目标」这一个模式差异 ⇒ 由模式表达，命令表条目数不变（#79）。
  · **回退账**：「上一份」不再是栈深 1，而是有界账 `回退账.json` 的**账首**；
    账长 `回退账上限`、谁清、清到什么程度见 `落点环境落点环境常量.py` 与 `指针.py`（#81）。
"""

from .落点环境常量 import 回退账上限, 运行根
from .上线实例 import 停实例, 端口空着, 进程活着, 活着的实例, 起实例, 要求健康读数
from .指针 import 建运行子目录, 账首, 读指针, 读账, 清指针, 写指针, 记回退账
from .上线制品 import 制品不可变读数, 列制品, 读清单, 流量端口
from .输出 import 打印文本


def 命令装载(标识: str) -> int:
    打印文本("装载 {}".format(标识))
    不符项, 多余项, 缺件清单 = 制品不可变读数(标识)
    打印文本("  制品不可变判据：指纹不符 {} · 清单外文件 {} · 缺件 {}".format(len(不符项), len(多余项), len(缺件清单)))
    if 不符项 or 多余项 or 缺件清单:
        raise SystemExit("制品被改过，拒绝装载（制品不可变）：{} {} {}".format(不符项, 多余项, 缺件清单))
    已装载指针 = 读指针("已装载/{}".format(标识))
    if 已装载指针 and 进程活着(int(已装载指针["pid"])):
        打印文本("  幂等：已有实例 pid={} 端口={}".format(已装载指针["pid"], 已装载指针["端口"]))
        实例台账 = 已装载指针
    else:
        实例台账 = 起实例(标识, 0)
        打印文本("  实例 pid={} 端口={}（临时端口，流量不动）".format(实例台账["pid"], 实例台账["端口"]))
    要求健康读数(int(实例台账["端口"]))
    当前指针 = 读指针("当前")
    打印文本("  当前 = {}".format(当前指针.get("制品标识", "无")))
    return 0


def 落到流量端口(标识: str, 来源: str) -> int:
    """切换与回退共用的动作：停掉所有活着的实例 → 在流量端口上起目标 → 原子改「当前」。"""
    监听端口 = 流量端口()
    当前指针 = 读指针("当前")
    if 当前指针.get("制品标识") == 标识 and int(当前指针.get("端口") or 0) == 监听端口 and 进程活着(int(当前指针.get("pid") or 0)):
        打印文本("  幂等：当前已是它（pid={} 端口={}），只复核健康".format(当前指针.get("pid"), 监听端口))
        要求健康读数(监听端口)
        return 0

    停的 = []
    for 实例台账 in 活着的实例():
        停的.append("{}（pid {}：{}）".format(实例台账.get("制品标识"), 实例台账.get("pid"), 停实例(实例台账)))
        (运行根 / "已装载" / "{}.json".format(实例台账.get("制品标识"))).unlink(missing_ok=True)
    for 实例台账 in [当前指针]:
        if 实例台账.get("pid") and 进程活着(int(实例台账["pid"])):
            停的.append("当前（pid {}：{}）".format(实例台账.get("pid"), 停实例(实例台账)))
    打印文本("  停掉活着的实例 {} 个：{}".format(len(停的), " · ".join(停的) or "无"))

    try:
        实例台账 = 起实例(标识, 监听端口)
        打印文本("  实例 pid={} 端口={}（流量端口）".format(实例台账["pid"], 实例台账["端口"]))
        要求健康读数(监听端口)
    except BaseException:
        # 故障切换：旧「当前」已被停、新目标起不来 / 不健康 ⇒ 也要把旧「当前」记进回退账。
        # 不记的话 `回退`（不给参数）取的是更旧的账条 ⇒ 指错制品（形状.md §二：账首 =「上一份」）。
        记回退账(当前指针)
        raise

    写指针("当前", dict(实例台账, 来源=来源))
    记回退账(当前指针)
    打印文本("  当前 = {}（来源：{}）· 上一份 = {}".format(标识, 来源, 账首().get("制品标识", "无")))
    return 0


def 命令切换(标识: str) -> int:
    读清单(标识)  # 不在制品落点里即拒
    打印文本("切换 → {}".format(标识))
    if not (读指针("已装载/{}".format(标识)) or {}).get("pid"):
        打印文本("  目标还没装载过，先装载（预检）")
        命令装载(标识)
    return 落到流量端口(标识, "切换")


def 命令停() -> int:
    """模式=停：停掉所有活着的实例、让流量口空着；被停的那个记进回退账（回退能把它叫回来）。"""
    监听端口 = 流量端口()
    当前指针 = 读指针("当前")
    打印文本("停 → 让流量口 {} 空着".format(监听端口))

    停的 = []
    for 实例台账 in 活着的实例():
        停的.append("{}（pid {}：{}）".format(实例台账.get("制品标识"), 实例台账.get("pid"), 停实例(实例台账)))
        (运行根 / "已装载" / "{}.json".format(实例台账.get("制品标识"))).unlink(missing_ok=True)
    if 当前指针.get("pid") and 进程活着(int(当前指针["pid"])):
        停的.append("当前（pid {}：{}）".format(当前指针.get("pid"), 停实例(当前指针)))
    打印文本("  停掉活着的实例 {} 个：{}".format(len(停的), " · ".join(停的) or "无"))

    记回退账(当前指针)  # 刚才在服务的那个进账首 ⇒ 回退（不给参数）就是把它叫回来
    清指针("当前")  # 「当前」指空：没有任何实例持有流量口
    if not 端口空着(监听端口):
        raise SystemExit("停不干净：流量口 {} 仍被占用（有东西在听）".format(监听端口))
    打印文本("  流量口 {} 空着（无实例持有）· 上一份 = {}".format(监听端口, 账首().get("制品标识", "无")))
    return 0


def 命令回退(标识: str, 步序: int = 1) -> int:
    """回退：给标识就指到那一份；不给就取回退账（步=1 是账首「上一份」，步=N 是账里第 N 条）。"""
    来源 = "显式指定" if 标识 else ("上一份" if 步序 == 1 else "回退账第 {} 条".format(步序))
    if not 标识:
        台账 = 读账()
        if 步序 < 1:
            raise SystemExit("步数必须是正整数：{}".format(步序))
        if 步序 > len(台账):
            raise SystemExit("回退账只有 {} 条（上限 {}），给不出第 {} 条。账：{}\n可回退的制品：{}".format(
                len(台账), 回退账上限, 步序,
                " · ".join(台账项.get("制品标识", "") for 台账项 in 台账) or "（空账）",
                " · ".join(列制品()) or "（一份都没有）",
            ))
        标识 = 台账[步序 - 1].get("制品标识") or ""
    读清单(标识)  # 不在制品落点里即拒（回退到任意一份**已产出**的制品都行，不必先装载）
    打印文本("回退 → {}（来源：{}）".format(标识, 来源))
    return 落到流量端口(标识, "回退")


def 命令现状() -> int:
    当前指针 = 读指针("当前")
    台账 = 读账()
    打印文本("运行根 {}".format(运行根))
    打印文本("当前 制品={} pid={} 端口={}".format(当前指针.get("制品标识", "无"), 当前指针.get("pid", "-"), 当前指针.get("端口", "-")))
    打印文本("上一份 制品={}".format((台账[0] if 台账 else {}).get("制品标识", "无")))
    打印文本("回退账 {} 条（上限 {}）：{}".format(
        len(台账), 回退账上限, " · ".join(台账项.get("制品标识", "") for 台账项 in 台账) or "无"))
    存活 = 活着的实例()
    打印文本("活着的实例 {} 个：{}".format(len(存活), " · ".join("{}:{}".format(存活项.get("制品标识"), 存活项.get("pid")) for 存活项 in 存活) or "无"))
    打印文本("可回退的制品 {} 份：{}".format(len(列制品()), " · ".join(列制品()) or "无"))
    return 0


def 取选项(命令行参数: list, 名称: str) -> tuple:
    """从参数里摘出 `[--]名=值`（两种写法都认），返回 (值, 其余位置参数)。"""
    待处理值 = ""
    位置参数 = []
    for 参数词 in 命令行参数:
        for 参数前缀 in ("--{}=".format(名称), "{}=".format(名称)):
            if 参数词.startswith(参数前缀):
                待处理值 = 参数词[len(参数前缀):]
                break
        else:
            位置参数.append(参数词)
    return 待处理值, 位置参数


def 入口函数(命令行参数: list, 用法文: str) -> int:
    建运行子目录()
    if not 命令行参数:
        raise SystemExit(用法文)
    命令名, 其余参数 = 命令行参数[0], 命令行参数[1:]
    if 命令名 == "装载" and len(其余参数) == 1:
        return 命令装载(其余参数[0])
    if 命令名 == "切换":
        模式, 位置参数 = 取选项(其余参数, "模式")
        if 模式 in ("", "切换") and len(位置参数) == 1:
            return 命令切换(位置参数[0])
        if 模式 == "停" and not 位置参数:
            return 命令停()
    if 命令名 == "回退":
        步文, 位置参数 = 取选项(其余参数, "步")
        if len(位置参数) <= 1:
            步序 = 1
            if 步文:
                if not 步文.isdigit():
                    raise SystemExit("步数必须是正整数：--步={}".format(步文))
                步序 = int(步文)
            return 命令回退(位置参数[0] if 位置参数 else "", 步序)
    if 命令名 == "现状" and not 其余参数:
        return 命令现状()
    raise SystemExit(
        "用法：上线切换.py 装载 <制品标识> ｜ 切换 <制品标识> ｜ 切换 --模式=停 ｜ "
        "回退 [<制品标识>] [--步=N] ｜ 现状"
    )
