#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""构建制品 —— 一次构建产出的、**可装载的整包**（形状与判据见 形状.md §一）。

    python3 构建装配/上线切换/构建制品.py --预构建          # 环境步：编底座与扩展的 release 产物 + 写戳
    python3 构建装配/上线切换/构建制品.py [--变体 <名>] [--不含扩展]   # 命令本体：装配一份新制品
    python3 构建装配/上线切换/构建制品.py --检查 <制品标识>            # 只查不可变判据，不装配

落点：`构建装配/制品产物/<制品标识>/`。**制品标识不含时间戳、不含绝对路径**：

    制品标识 = <提交哈希 12 位>-<构建指纹 16 位>
    构建指纹 = sha256(规范文本)[:16]，规范文本 = profile + 变体 + 工具链 + 扩展根声明指纹
                                          + 逐行「相对路径 sha256(内容)」（按路径排序）

规范文本里**没有时间、没有绝对路径、没有机器名** ⇒ 同一份源在两台机器上产出同一个标识。
**制品不可变**：目标目录已存在即拒绝重建（不是覆盖）——判据见 `--检查`。

本件只做装配：读 `扩展装载/扩展根声明.json` + 取已编好的底座网关 + 取已编好的扩展可装载库，
把结果拼成整包。它**不改任何源文件**，也不生成声明（声明由 `构建装配/形态装配/` 生成）。

**构建段已移出命令路**：装配档**不编任何东西**，只比对 `--预构建` 留下的戳
（`构建缓存/预构建.json`，口径见 `构建制品/指纹.py::预构建指纹`）—— 戳与当前源不符即
fail-closed 指路。理由：装配带上构建段时首跑 5570 ms，越过五秒硬顶；而
`项目文档/决策记录/2026-09-27_所有运行五秒硬顶.md` §四 把「工具链一次性冷构建」划在命令之外
⇒ 那条冷构建必须能被**单独指名跑**，于是有了 `--预构建`（它按环境步报墙钟、不判顶）。

本文件是**路由**：解析命令行 → 调包里的公开面 → 打印。实现按关注点拆进同名字文件夹
`构建制品/`（一个关注点一个文件）。

**公开面逐字不变**（`开发规范.md` §六）：拆分前本文件是单件，`扩展产物` 等函数是它的模块级名字，
有别的件**进程内 import 本文件**再取（`构建装配/演示/装配.py::载入构建制品` 取 `扩展产物`）
⇒ 这里必须把包里的公开面**全导一遍**（`from 构建制品 import *`），只导 `main` 会把那条路静默断掉。

**五秒硬顶（壳自量自门禁）**：入口在**导入业务包之前**起表；装配/检查档走 `自门禁`，
`--预构建` 走 `报告环境步`（§四 的一次性冷构建，照实报墙钟但不判顶）。见 `构建装配/门禁/`。
"""

import sys
import time
from pathlib import Path

起 = time.monotonic()  # 壳起表点：必须在 import 业务包**之前**（见 构建装配/门禁/壳.py）

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # 仓根：取共享门禁
from 构建装配.门禁 import 报告环境步, 自门禁  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))

from 构建制品 import *  # noqa: E402,F401,F403 —— 再导出公开面（`构建制品/__init__.py::__all__`）
from 构建制品 import main  # noqa: E402

if __name__ == "__main__":
    if "--预构建" in sys.argv[1:]:
        sys.exit(
            报告环境步(
                起, main(),
                "构建制品 --预构建：编底座网关 + 扩展可装载库（§四 的一次性冷构建；命令本体不编任何东西）",
            )
        )
    sys.exit(
        自门禁(
            起, main(), 尾巴余量毫秒=200,
            修法="装配档已不含构建段 ⇒ 先量它到底慢在哪：制品内文件清单要算全树 sha256，"
                 "树大了它自身会超顶 —— 那时把清单改成增量（按 mtime 缓存），别把构建塞回命令路。",
        )
    )
