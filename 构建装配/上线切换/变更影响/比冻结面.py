# 越界种类 = 三种允许演进**之外**的形状变化（允许演进见 `契约声明/冻结登记.json` 的 `说明`）。
越界种类 = ("新增冻结项", "删除冻结项", "落点变更", "形状指纹变更")


def 取待查串(登记: dict) -> tuple:
    """冻结项落点拆成两份待查串：`(符号清单, 路径清单)`。

    影响面要按**落点自身**数引用件，而落点有两种写法：带 `::符号名` 的（按符号数）与只写
    件路径的（按路径数，如 `对外接口面/调用接口面/src/执行装配/分发.rs`）。早先只取带 `::` 的那几个
    ⇒ 只写路径的三条冻结项影响面恒报「0 件引用」，四栏等于缺一栏。
    """
    符号清单 = []
    路径清单 = []
    for 当前条目 in 登记.get("冻结项") or []:
        落点原文 = str(当前条目.get("落点", ""))
        if "::" in 落点原文:
            符号清单.append(落点原文.split("::")[1])
        路径清单.append(落点原文.split("::")[0])
    return 符号清单, 路径清单


def _索引冻结项(登记: dict) -> dict:
    return {str(当前条目.get("名称", "")): 当前条目 for 当前条目 in 登记.get("冻结项") or []}


# 兼容证据只**列举**前几条：有的冻结项被几十条旁路引到，全铺开一屏放不下，四栏反而
# 看不出「有几条」；末尾补「另有 N 条」把总数留住。
证据列举上限 = 3


def _找兼容证据(当前登记: dict, 冻结项名: str, 落点: str) -> str:
    """`旁路` / `已收口旁路` 里登记了这次变更的条目（按 冻结项名 或 落点 出现判）。"""
    证据列举 = []
    for 表段名 in ("旁路", "已收口旁路"):
        for 旁路条目 in 当前登记.get(表段名) or []:
            变更行全文 = " ".join(str(旁路条目.get(键名, "")) for 键名 in 旁路条目)
            if (冻结项名 and 冻结项名 in 变更行全文) or (落点 and 落点 in 变更行全文):
                小结文本 = str(旁路条目.get("冻的是什么") or 旁路条目.get("缺口") or "")[:40]
                证据列举.append(f"{表段名}·{小结文本}")
    列举正文 = 证据列举[:证据列举上限]
    if len(证据列举) > 证据列举上限:
        列举正文.append(f"另有 {len(证据列举) - 证据列举上限} 条")
    return " · ".join(列举正文)


def _影响面(符号名: str, 引用表: dict) -> str:
    引用件表 = 引用表.get(符号名) or []
    if not 引用件表:
        return f"{符号名 or '（该落点无具名符号）'} 被 0 件引用"
    return f"{符号名} 被 {len(引用件表)} 件引用（如 {引用件表[0]}）"


def _造变更行(变更种类: str, 冻结项名: str, 当前条目: dict, 当前登记: dict, 引用表: dict) -> dict:
    落点原文 = str(当前条目.get("落点", ""))
    件相对路径 = 落点原文.split("::")[0]
    符号名 = 落点原文.split("::")[1] if "::" in 落点原文 else 件相对路径
    旁路证据 = _找兼容证据(当前登记, 冻结项名, 落点原文)
    return {
        "变更项": f"{变更种类}：{冻结项名}",
        "影响面": _影响面(符号名, 引用表),
        "责任归属": f"{件相对路径 or '（无落点）'}（{取责任归属(件相对路径) or '无提交记录'}）",
        "兼容证据": 旁路证据 or "（无旁路登记）",
        "越界": 变更种类 in 越界种类 and not 旁路证据,
    }


def _比段类型号(基线登记: dict, 当前登记: dict) -> list:
    旧号表 = (基线登记.get("段类型号登记") or {}).get("新增") or {}
    新号表 = (当前登记.get("段类型号登记") or {}).get("新增") or {}
    return [
        {
            "变更项": f"新增段类型号：{号名} = {新号表[号名]}（{允许演进种类[1]}）",
            "影响面": "段类型号登记（判据 ⑨ 逐条核「不与已占用相撞 · 容器形状真能表示」）",
            "责任归属": str((当前登记.get("段类型号登记") or {}).get("落点", "")),
            "兼容证据": "允许演进（`契约声明/冻结登记.json` 的 `说明` 三种之一）",
            "越界": False,
        }
        for 号名 in sorted(新号表)
        if 号名 not in 旧号表
    ]


def _数旁路总和(登记: dict) -> int:
    return len(登记.get("旁路") or []) + len(登记.get("已收口旁路") or [])


def _比旁路条数(基线登记: dict, 当前登记: dict) -> list:
    """旁路条数的两种变化**分开报**：真新增（允许演进）与「旁路 → 已收口」归位。

    `旁路` 与 `已收口旁路` 是同一张登记的两个段（收口不删、只搬家）⇒ 判「有没有新增」
    必须按**两段总和**比；只比 `旁路` 一段会把「搬一条去已收口」误报成「新增一条旁路」。
    """
    旧旁路条数 = len(基线登记.get("旁路") or [])
    新旁路条数 = len(当前登记.get("旁路") or [])
    旧总和 = _数旁路总和(基线登记)
    新总和 = _数旁路总和(当前登记)
    if 新总和 > 旧总和:
        return [
            {
                "变更项": f"新增旁路字段：旁路登记总数 {旧总和} → {新总和} 条（{允许演进种类[2]}）",
                "影响面": "旁路登记表（判据 ⑨ 核三键齐全与落点存在）",
                "责任归属": "契约声明/冻结登记.json",
                "兼容证据": "允许演进（三种之一）",
                "越界": False,
            }
        ]
    if 新旁路条数 != 旧旁路条数:
        return [
            {
                "变更项": f"旁路归位：旁路 {旧旁路条数} → {新旁路条数} 条（两段总和 {新总和} 不变 ⇒ 是并入已收口）",
                "影响面": "旁路登记表（已收口旁路也是登记，不是删除）",
                "责任归属": "契约声明/冻结登记.json",
                "兼容证据": "允许演进（三种之一）",
                "越界": False,
            }
        ]
    return []


def 比冻结面(基线登记: dict, 当前登记: dict, 引用表: dict) -> dict:
    """→ `{"变更行表": [...], "越界条目": [...]}`；无变更时两张表都空。"""
    基线项表 = _索引冻结项(基线登记)
    当前项表 = _索引冻结项(当前登记)
    变更行表 = []
    for 冻结项名 in sorted(基线项表):
        if 冻结项名 not in 当前项表:
            变更行表.append(_造变更行("删除冻结项", 冻结项名, 基线项表[冻结项名], 当前登记, 引用表))
            continue
        for 变更种类, 键名 in (("落点变更", "落点"), ("形状指纹变更", "形状指纹")):
            if str(基线项表[冻结项名].get(键名, "")) != str(当前项表[冻结项名].get(键名, "")):
                变更行表.append(_造变更行(变更种类, 冻结项名, 当前项表[冻结项名], 当前登记, 引用表))
    for 冻结项名 in sorted(当前项表):
        if 冻结项名 not in 基线项表:
            变更行表.append(_造变更行("新增冻结项", 冻结项名, 当前项表[冻结项名], 当前登记, 引用表))
    变更行表.extend(_比段类型号(基线登记, 当前登记))
    变更行表.extend(_比旁路条数(基线登记, 当前登记))
    return {"变更行表": 变更行表, "越界条目": [变更行 for 变更行 in 变更行表 if 变更行["越界"]]}
