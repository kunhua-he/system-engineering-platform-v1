"""上线切换 —— 装载 · 切换 · 回退 三条命令（形状与判据见 形状.md §二）。

    python3 构建装配/上线切换/上线切换.py 装载 <制品标识>
    python3 构建装配/上线切换/上线切换.py 切换 <制品标识>
    python3 构建装配/上线切换/上线切换.py 切换 --模式=停          # 停掉实例、让流量口空着
    python3 构建装配/上线切换/上线切换.py 回退 [<制品标识>] [--步=N]   # 不给就用「上一份」（回退账首）
    python3 构建装配/上线切换/上线切换.py 现状

三条命令各做一件可数的事：

| 命令 | 做什么 | 流量 |
|---|---|---|
| 装载 | 起一份新制品（**临时端口**）→ 健康检查 → 记进已装载 | **不动** |
| 切换 | 停掉所有活着的实例 → 在**流量端口**上起目标 → 原子改「当前」 | 指过去 |
| 回退 | 同切换，但目标默认取「上一份」；**指定任意一份已产出制品**都行 | 指回去 |

**「停」是模式不是第四条命令**：`切换 --模式=停` —— 与 切换/回退 **同一个底子**（停实例 +
处置流量口），只差「停完不起目标」这一个模式（老仓《设计哲学》第 8 条②「底子不同但格式一样
⇒ 加模式变量」；依据 `决策记录/2026-09-27_待裁九项按老仓设计哲学裁决.md` 裁决 7）。
**「上一份」不是栈深 1**：它是一本**有界回退账**（`回退账.json`，上限见 `上线切换/常量.py`）
的账首；`回退 --步=N` 取账里第 N 条（#81）。

运行数据**不在源码树内**（README 第十节）：默认落系统临时目录，可用环境变量
`ZCODE_SWITCH_RUN_ROOT` 换。源码树里只有本文件、`构建制品.py`、三条 `.sh` 与 `形状.md`。
（环境变量名一律 **ASCII**：sh 不认非 ASCII 变量名 —— 实测过，用中文名时 `export` 不生效。）
"""

# 本文件是**路由**：把 `__doc__`（上面这段，也是「不给子命令」时打出的用法）原样交给包，
# 再调 `上线切换.命令.main`。实现按关注点拆进同名字文件夹 `上线切换/`。
import sys
import time
from pathlib import Path

起 = time.monotonic()  # 壳起表点：必须在 import 业务包**之前**（见 构建装配/门禁/壳.py）

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # 仓根：取共享门禁
from 构建装配.门禁 import 自门禁  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))

from 上线切换.命令 import main  # noqa: E402

if __name__ == "__main__":
    sys.exit(
        自门禁(
            起, main(sys.argv[1:], __doc__), 尾巴余量毫秒=200,
            修法="最坏路径的账在 上线切换/常量.py 的 `停等秒` / `健康超时秒` 上（停 2 个实例 + "
                 "等端口 2 次）；超顶先量是哪一段吃掉的（打印里每步都有读数），再缩那个上界 —— "
                 "别把等待改成无限等（那就把超顶换成了挂死）。",
        )
    )
