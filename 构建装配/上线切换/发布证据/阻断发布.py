"""阻断发布 —— 缺材料 ⇒ 非零退出（缺材料不冒充通过 —— 架构收敛方案项 W07 的发布侧卡点）。

口径：**发布**（上线 / 装载）这一步的前置是「四类材料齐」。任一类缺 —— 或证据件与现盘材料
不符 —— 就非零退出并逐条报「缺什么 / 怎么补」。原先只有取证样本报缺，发布链上没有卡点
⇒ 缺材料照样能装；本件就是那个卡点（`构建装配/上线切换/装载.sh` 在装载前调它）。

**不许降级**：读不动、解不开、键缺 —— 一律按缺处理（fail-closed），不回落成「跳过」。
"""

import json

from .常量 import 证据落点, 四类材料
from .正式证据 import 出证据


def 查缺项() -> tuple:
    """⇒ `(缺项, 证据)` —— 证据件在盘上就先核它，不在就现采一遍。"""
    if 证据落点.is_file():
        try:
            证据 = json.loads(证据落点.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as 错误:
            return ["证据件读不动（%s：%s）" % (证据落点, 错误)], None
        材料 = 证据.get("材料") or {}
        缺项 = [材料名 for 材料名 in 四类材料 if not 材料.get(材料名)]
        if 缺项:
            return ["证据件里缺：" + " / ".join(缺项)], 证据
        现采证据, 现缺项, 制品目录 = 出证据()
        if not 现缺项 and 现采证据 is not None and 现采证据["证据指纹"] != 证据.get("证据指纹"):
            return ["证据件与现盘材料不符（盘上材料变了而证据件没重采）—— 重跑 `发布证据.py` 再发布"], 证据
        return [], 证据
    证据, 缺项 = 出证据()
    return 缺项, 证据


def 打印阻断(缺项: list) -> None:
    print("阻断发布：四类正式材料缺 %d 项 —— 缺材料不冒充通过（架构收敛方案项 W07）。" % len(缺项), flush=True)
    for 缺项行 in 缺项:
        print("  · 缺：" + 缺项行, flush=True)
    print("  修法：先构建制品（构建装配/上线切换/构建制品.py），再 `发布证据.py` 采一遍；本命令非零退出。", flush=True)
