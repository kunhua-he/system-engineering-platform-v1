"""主流程 —— 命令行入口本体：检查一份已产出制品，或装配一份新制品。"""

import argparse
import json
import shutil
from pathlib import Path

from .命令 import 跑, 提交哈希, 工具链版本
from .常量 import 仓根, 制品落点, 扩展根声明, 底座目录, 底座根文件, 构建缓存, 源后缀, 预构建戳
from .扩展 import 扫扩展, 找扩展产物, 建扩展产物
from .指纹 import 预构建指纹, 源指纹
from .制品 import 制品内文件清单, 检查制品
from .输出 import 打印


def 预构建(纳入的扩展: list) -> int:
    """**环境步**：编底座网关 + 编每个扩展的可装载库 + 写戳。**不装配**（装配是命令本体的活）。

    为什么单独成一步（台账 #233 的落法）：构建段会让命令本体越过五秒硬顶，而
    `所有运行五秒硬顶.md` §四 把「工具链一次性冷构建」划在命令之外 ——
    但豁免要成立，那条冷构建必须**能被单独指名跑**，于是有了本步。
    本步的墙钟由入口按「环境步」如实报、**不判顶**（见 `构建装配/门禁/壳.py::报告环境步`）。
    """
    跑(["cargo", "build", "--locked", "--offline", "--release", "-p", "v1-gateway", "--example", "启动网关"], cwd=仓根)
    for 扩展 in 纳入的扩展:
        建扩展产物(扩展)
    预构建戳.parent.mkdir(parents=True, exist_ok=True)
    预构建戳.write_text(
        json.dumps(
            {
                "生成物": True,
                "说明": "环境步戳：只由 `构建制品.py --预构建` 写；装配档比对它，不符即拒绝装配（台账 #233）。",
                "算法": "sha256(profile + 工具链 + 逐行「相对路径 sha256(内容)」) —— 见 构建制品/指纹.py::预构建指纹",
                "预构建指纹": 预构建指纹(纳入的扩展),
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    打印("预构建完成：底座网关 + {} 个扩展 · 戳 {}".format(len(纳入的扩展), 预构建戳.relative_to(仓根).as_posix()))
    return 0


def 检查预构建(纳入的扩展: list) -> str:
    """命令本体用：比对戳。返回**问题说明**（空串 = 相符）。

    这一条是「制品里的二进制确实由当前源编出来」的**唯一保证** —— 靠手感（「我刚编过」）不算。
    """
    当前 = 预构建指纹(纳入的扩展)
    if not 预构建戳.is_file():
        return "没有预构建戳（{}）⇒ 产物与源的关系未知".format(预构建戳.relative_to(仓根).as_posix())
    try:
        戳 = json.loads(预构建戳.read_text(encoding="utf-8")).get("预构建指纹")
    except (OSError, ValueError) as 错:
        return "预构建戳读不出来（{}）".format(错)
    if 戳 != 当前:
        return "预构建戳与当前源不符（戳 {} · 当前 {}）".format((戳 or "（空）")[:16], 当前[:16])
    return ""


def main() -> int:
    解 = argparse.ArgumentParser(description="构建制品（可装载的整包）")
    解.add_argument("--变体", default=None, help="装配变体名（进构建指纹）")
    解.add_argument("--不含扩展", action="store_true", help="只装底座（形态裁剪：同一套源出另一种整包）")
    解.add_argument("--检查", default=None, help="只查一份已产出制品的不可变判据，不构建")
    解.add_argument("--预构建", action="store_true", help="环境步：只编底座与扩展的 release 产物 + 写戳，不装配")
    参 = 解.parse_args()

    if 参.检查:
        目录 = 制品落点 / 参.检查
        if not (目录 / "制品清单.json").is_file():
            打印("制品不存在或没有清单：{}".format(目录))
            return 1
        不符, 多余, 缺件 = 检查制品(目录)
        打印("制品 {} ｜ 指纹不符 {} ｜ 清单外文件 {} ｜ 缺件 {}".format(参.检查, len(不符), len(多余), len(缺件)))
        for 项 in 不符:
            打印("  不符 {}".format(项))
        for 项 in 多余:
            打印("  清单外 {}".format(项))
        for 项 in 缺件:
            打印("  缺件 {}".format(项))
        return 0 if not (不符 or 多余 or 缺件) else 1

    声明文本 = 扩展根声明.read_text(encoding="utf-8")
    声明 = json.loads(声明文本)
    变体 = 参.变体 or ("仅底座" if 参.不含扩展 else "全量")

    扫到的 = 扫扩展(声明)
    纳入的 = [] if 参.不含扩展 else 扫到的

    # 环境步在**算制品标识之前**分岔：它不装配，也不看制品是否已存在（它的产物是构建缓存）。
    if 参.预构建:
        return 预构建(扫到的)

    指纹 = 源指纹(声明文本, 纳入的, 变体)
    提交, 脏 = 提交哈希()
    标识 = "{}-{}".format(提交, 指纹[:16])
    目录 = 制品落点 / 标识

    if 目录.exists():
        打印("制品已存在，拒绝重建（制品不可变）：{}".format(目录))
        打印("  要重出请换变体名，或先删掉这一份（删 = 显式动作，不许覆盖）")
        return 1

    # ★ 命令本体**不编**（台账 #233）：构建段已移出命令路 ⇒ 这里只比对环境步留下的戳。
    问题 = 检查预构建(扫到的)
    if 问题:
        打印("✗ {} ⇒ 拒绝装配（制品里的二进制必须由当前源编出来）".format(问题))
        打印("  修法：先跑环境步 python3 构建装配/上线切换/构建制品.py --预构建")
        return 1

    目录.mkdir(parents=True)
    打印("制品标识 {}（提交 {} · 工作区{}）".format(标识, 提交, "脏" if 脏 else "干净"))

    # ── 1 底座网关：唯一对外门的可执行件（**只取不编** —— 编在环境步）──────────────
    入口 = 构建缓存 / "release" / "examples" / "启动网关"
    if not 入口.is_file():
        raise SystemExit(
            "找不到启动入口（没预构建 / 缓存被清）：{}\n"
            "  先跑环境步：python3 构建装配/上线切换/构建制品.py --预构建".format(入口)
        )
    shutil.copy2(入口, 目录 / "网关")
    (目录 / "网关").chmod(0o755)

    # ── 2 扩展：取已编好的可装载库，按种类摆进制品自己的扩展树（**只取不编**）─────────
    装入 = []
    for 扩展 in 纳入的:
        库 = 找扩展产物(扩展)
        # 制品内的种类目录名 = 扩展根声明里那个 目录 的**末段**（原子支持库 / 组合模块库 / 技能封装库）。
        # 与下面改写声明时用的是同一个名字 —— 两处不一致就是「制品自己找不到自己的扩展」（实测撞到过）。
        目标 = 目录 / "扩展" / Path(扩展["目录"]).name / 扩展["名"] / "{}{}".format(扩展["名"], 库.suffix)
        目标.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(库, 目标)
        装入.append({"种类": 扩展["种类"], "扩展目录": 扩展["名"], "制品内落点": 目标.relative_to(目录).as_posix()})
        打印("  装入扩展 {} → {}".format(扩展["落点"].relative_to(仓根).as_posix(), 装入[-1]["制品内落点"]))

    # ── 3 制品自己的扩展根声明：目录改指制品内，**形状不变** ─────────────────
    制品声明 = dict(声明)
    制品声明["说明"] = "制品内副本（生成物，禁手改）：目录已改指本制品内的 扩展/。源：扩展装载/扩展根声明.json"
    制品声明["路径基准"] = "工作目录"
    制品声明["种类"] = [
        dict(类, 目录="扩展/{}".format(Path(类.get("目录", "")).name)) for 类 in 声明.get("种类", [])
    ]
    (目录 / "扩展根声明.json").write_text(
        json.dumps(制品声明, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    # ── 4 制品清单 ───────────────────────────────────────────────────────────
    常量表 = json.loads((仓根 / "契约声明" / "常量表.json").read_text(encoding="utf-8"))
    端口 = next(条["值"] for 条 in 常量表["常量"] if 条["名"] == "接口端口")
    清单 = {
        "生成物": True,
        "禁手改": True,
        "说明": "制品清单 —— 一次构建产出的可装载整包的身份与内容。改它请改 构建装配/上线切换/构建制品.py（源）。",
        "制品标识": 标识,
        "提交哈希": 提交,
        "工作区脏": 脏,
        "装配变体": 变体,
        "构建指纹": 指纹,
        "构建指纹算法": "sha256(规范文本)[:16]；规范文本 = profile + 变体 + 工具链 + 扩展根声明指纹 + 装配器指纹 + 逐行「相对路径 sha256(内容)」（按路径排序）。不含时间、不含绝对路径、不含机器名。",
        "构建指纹范围": {"底座根文件": list(底座根文件), "底座目录": list(底座目录), "扩展": [项["扩展目录"] for 项 in 装入], "后缀": list(源后缀)},
        "构建工具链": 工具链版本(),
        "构建 profile": "release",
        "流量端口": 端口,
        "流量端口来源": "契约声明/常量表.json 的 常量[名=接口端口]（唯一定义处）",
        "启动入口": "网关",
        "启动命令": ["./网关", "--声明根", "扩展根声明.json", "--端口", "<N>"],
        "启动入口读数约定": "启动入口把实际端口打在 `监听 127.0.0.1:<端口>` 这一行上（上线切换靠它拿端口）。",
        "扫到的扩展": [
            {"种类": 项["种类"], "扩展目录": 项["名"], "源落点": 项["落点"].relative_to(仓根).as_posix()} for 项 in 扫到的
        ],
        "装入的扩展": 装入,
        "文件清单": 制品内文件清单(目录),
        "不可变判据": "① 文件清单里每个文件重算 sha256 都相符（0 处不符）② 制品目录里没有清单之外的文件（除 制品清单.json 本身）③ 标识 = 提交哈希 + 构建指纹，且不含时间戳 / 绝对路径。检查：python3 构建装配/上线切换/构建制品.py --检查 <制品标识>",
    }
    (目录 / "制品清单.json").write_text(json.dumps(清单, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    打印("制品落点 {}".format(目录.relative_to(仓根).as_posix()))
    打印("  文件 {} 个 · 装入扩展 {} 个 · 流量端口 {}".format(len(清单["文件清单"]), len(装入), 端口))
    return 0
