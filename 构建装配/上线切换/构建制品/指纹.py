"""指纹 —— 构建指纹：同一份源在两台机器上产出同一个标识。"""

import hashlib

from .常量 import 仓根, 底座目录, 底座根文件, 装配器入口
from .命令 import 工具链版本
from .源文件 import 取相对路径, 走源文件, 文件指纹


def 源件表(纳入的扩展: list) -> dict:
    """装配的**源件表**：相对路径 → 绝对路径（「影响制品内容」的那些件都在这里）。"""
    节点件 = {}
    # 装配器自身也是输入：**整包**（入口 + 同名字文件夹）—— 一改，同一个标识就不该再指同一份内容。
    # ★ 实测（2026-09-27）：拆包之后这里只哈希**入口** ⇒ 改子件不改标识 —— **标识在骗人**。
    #   所以按整包收：入口 + `构建制品/` 下全部源件（走 `走源文件`，与底座/扩展同一套收法）。
    节点件[取相对路径(装配器入口)] = 装配器入口
    # 装配器自身是 **Python**，而 `走源文件` 的 `源后缀` 是给底座/扩展的 Rust 件用的（不含 `.py`）
    # ⇒ 这里显式按 `*.py` 收整包，别指望那个后缀表。
    for 路径 in sorted((装配器入口.parent / "构建制品").rglob("*.py")):
        if "__pycache__" in 路径.parts:
            continue
        节点件[取相对路径(路径)] = 路径
    for 名称 in 底座根文件:
        路径 = 仓根 / 名称
        if 路径.is_file():
            节点件[名称] = 路径
    for 源根目录 in 底座目录:
        for 路径 in 走源文件(仓根 / 源根目录):
            节点件[取相对路径(路径)] = 路径
    for 扩展 in 纳入的扩展:
        for 路径 in 走源文件(扩展["落点"]):
            节点件[取相对路径(路径)] = 路径
    return 节点件


def 预构建指纹(纳入的扩展: list) -> str:
    """**环境步的戳**：只随「影响编出来的二进制」的那些东西变。

    与 `源指纹` 的差别只有两处，都是**有意**的：
      · **不含 `变体`** —— 变体只改制品的装配形态（装不装扩展、叫什么名），不改任何二进制的字节；
      · **不含 `扩展根声明` 的整份文本** —— 声明里的散文（说明等）改了，编出来的库不变。
    反过来 `源指纹` 必须比这里严：它是**制品标识**的输入，标识要能区分「同一批二进制、不同装配形态」。

    用途：`--预构建` 写它 · 装配档比它 ⇒ **二进制与源不符就 fail-closed**。
    """
    源码行 = ["profile=release", "工具链={}".format(工具链版本())]
    节点件 = 源件表(纳入的扩展)
    for 键名 in sorted(节点件):
        源码行.append("文件 {} {}".format(键名, 文件指纹(节点件[键名])))
    return hashlib.sha256("\n".join(源码行).encode("utf-8")).hexdigest()


def 源指纹(声明文本: str, 纳入的扩展: list, 变体: str) -> str:
    源码行 = [
        "profile=release",
        "变体={}".format(变体),
        "工具链={}".format(工具链版本()),
        "扩展根声明={}".format(hashlib.sha256(声明文本.encode("utf-8")).hexdigest()),
    ]
    节点件 = 源件表(纳入的扩展)
    for 键名 in sorted(节点件):
        源码行.append("文件 {} {}".format(键名, 文件指纹(节点件[键名])))
    return hashlib.sha256("\n".join(源码行).encode("utf-8")).hexdigest()
