/// 留痕关掉时调用照样成功；开着时耗时不变慢（**读数印在下面**）。
#[test]
fn 留痕不进关键路径_关掉照样成功_开着不变慢() {
    // 次数必须小于契约的 `配额上限`，否则量到的是「配额用尽」而不是留痕开销。
    const 循环次数: u32 = 8_000;
    const 容量: u32 = 4096;
    let 入参 = 文本入参();

    // 关：关口默认没有留痕缓冲。
    let (无痕关口, _) = 参照实现关口();
    let 区间起点 = Instant::now();
    for _ in 0..循环次数 {
        assert!(
            matches!(无痕关口.资源调用(参照实现号, 1, &入参), 关口结果::成功(_)),
            "留痕缺席时调用照样成功"
        );
    }
    let 关耗时 = 区间起点.elapsed();
    assert!(无痕关口.留痕读数(10).is_empty(), "没启用留痕 ⇒ 一条也没有");
    assert_eq!(无痕关口.留痕已丢弃(), 0);

    // 开：同样的声明、同样的黑盒，多一个留痕缓冲。
    let (mut 有痕关口, _) = 参照实现关口();
    有痕关口.启用留痕(容量, 丢弃策略::丢最旧);
    let 区间起点 = Instant::now();
    for _ in 0..循环次数 {
        assert!(matches!(
            有痕关口.资源调用(参照实现号, 1, &入参),
            关口结果::成功(_)
        ));
    }
    let 开耗时 = 区间起点.elapsed();

    println!(
        "留痕开销实测（各 {循环次数} 次）：关 {关耗时:?} / 开 {开耗时:?}；每次差 {:?}",
        开耗时.saturating_sub(关耗时) / 循环次数
    );
    assert!(
        开耗时 <= 关耗时 * 4 + Duration::from_millis(50),
        "留痕进了关键路径：关 {关耗时:?} / 开 {开耗时:?}"
    );

    // 而且它真的记下来了（不是「开了但没记」）。
    let 最近留痕 = 有痕关口.留痕读数(循环次数);
    assert_eq!(最近留痕.len(), 容量 as usize, "取最近 次数 条 = 缓冲容量");
    assert_eq!(有痕关口.留痕已丢弃(), u64::from(循环次数 - 容量));
    let 首条 = 最近留痕[0];
    assert_eq!(首条.调用类, 调用类::资源, "资源访问的判别是「资源」");
    assert_eq!(首条.资源号, 参照实现号);
    assert_eq!(首条.操作号, 1);
    assert_eq!(首条.能力号, 0, "资源访问时能力号位恒零");
    // 缓冲只留最近 `容量` 条 ⇒ `首条` 是**最旧那条留痕**，不是第 1 次调用。
    // 追踪号 0 基（`fetch_add` 返回旧值）⇒ 最旧那条 = 第 `次数-容量` 次调用。
    assert_eq!(
        首条.追踪号,
        u64::from(循环次数 - 容量),
        "最旧那条 = 第 {} 次调用",
        循环次数 - 容量 + 1
    );
    assert_eq!(
        最近留痕.last().expect("非空").追踪号,
        u64::from(循环次数) - 1,
        "最新那条 = 最后一次调用"
    );
    assert!(首条.是否自洽(), "判别与号位必须一致");
    assert_eq!(有痕关口.留痕不自洽数(), 0, "坏痕不许静默：一条都不许不自洽");
    assert_eq!(首条.结果码, 0, "成功记 0");
    assert_eq!(首条.实例号, 有痕关口.实例号());
    assert!(
        最近留痕.iter().all(|留痕项| 留痕项.入参指纹 == 首条.入参指纹),
        "同一张槽表 ⇒ 同一个指纹"
    );
    assert_eq!(首条.入参指纹, crate::关口::槽表指纹(&入参));
}

/// **每次访问留痕**：未声明的访问是安全事件，也要留痕（声明缺失 ⇒ 记）。
#[test]
fn 留痕_未声明的访问也留痕() {
    let mut 关口 = 资源网关口::空实例();
    关口.启用留痕(8, 丢弃策略::丢最旧);
    let 错误 = 取拒绝原因(关口.资源调用(参照实现号, 1, &文本入参()));
    assert_eq!(错误.取错误码(), 码_资源未声明);
    let 最近留痕 = 关口.留痕读数(1);
    assert_eq!(最近留痕.len(), 1, "未声明的访问必须留痕");
    assert_eq!(最近留痕[0].调用类, 调用类::资源);
    assert_eq!(最近留痕[0].资源号, 参照实现号);
    assert_eq!(最近留痕[0].操作号, 1);
    assert_eq!(最近留痕[0].能力号, 0);
    assert_eq!(最近留痕[0].追踪号, 0, "本实例第一条调用");
    assert!(最近留痕[0].是否自洽());
    assert_eq!(最近留痕[0].结果码, 码_资源未声明 as i32);
}

/// 声明说 `留痕: false` ⇒ 这条资源不记（关口开着也不记）。
#[test]
fn 留痕_声明说不留就不留() {
    let mut 声明 = 参照实现声明();
    声明.留痕 = false;
    let mut 关口 = 资源网关口::从声明根建关口(&[声明]).expect("合法");
    关口.绑定入口(参照实现号, Box::new(夹具黑盒::构造(参照实现号, 字节集)));
    关口.启用留痕(8, 丢弃策略::丢最旧);
    assert!(matches!(
        关口.资源调用(参照实现号, 1, &文本入参()),
        关口结果::成功(_)
    ));
    assert!(关口.留痕读数(8).is_empty(), "声明说不留就不留");
}

// ══ 五 多实例隔离：两份清单 / 两个关口互不影响 ═══════════════════════════

/// 不许落进程级全局：清单 · 账本 · 留痕 · 实例号全按实例持有。
#[test]
fn 多实例隔离_两份清单两个关口互不影响() {
    let (参照关口, _) = 参照实现关口();
    let 空关口 = 资源网关口::空实例(); // 另一份清单（空的）

    assert!(matches!(
        参照关口.资源调用(参照实现号, 1, &文本入参()),
        关口结果::成功(_)
    ));
    assert_eq!(
        取拒绝原因(空关口.资源调用(参照实现号, 1, &文本入参())).取错误码(),
        码_资源未声明
    );
    assert!(空关口.已声明资源().is_empty());

    // 配额账本按实例持有：末个打满，首个照常。
    let (打满关口, _) = 参照实现关口();
    for _ in 0..声明数据::配额上限 {
        assert!(matches!(
            打满关口.资源调用(参照实现号, 1, &文本入参()),
            关口结果::成功(_)
        ));
    }
    assert_eq!(
        取拒绝原因(打满关口.资源调用(参照实现号, 1, &文本入参())).取错误码(),
        声明数据::错误码_0005
    );
    assert!(
        matches!(参照关口.资源调用(参照实现号, 1, &文本入参()), 关口结果::成功(_)),
        "首个是另一本账本，不许被末个影响"
    );

    // 留痕缓冲按实例持有；实例号取自实例地址（不是全局计数器）。
    assert!(空关口.留痕读数(10).is_empty());
    assert_ne!(参照关口.实例号(), 空关口.实例号());
}

