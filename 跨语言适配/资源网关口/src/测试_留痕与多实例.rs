/// 不许自造第二套值形状：递进去的就是那一个槽，类型标签随槽走。
#[test]
fn 数据只走定长数据槽_类型标签随槽走() {
    let mut 关口 = 资源网关口::从声明根建关口(&[参照实现声明()]).expect("合法");
    let 容器盒 = 夹具黑盒::构造(参照实现号, 字节集);
    let 收到 = Arc::clone(&容器盒.收到的类型标签);
    关口.绑定入口(参照实现号, Box::new(容器盒));

    let 入参 = 数据槽::内联槽(源文本.into(), 0x1234_5678, 4);
    match 关口.资源调用(参照实现号, 1, &[入参]) {
        关口结果::成功(出参槽表) => {
            assert_eq!(出参槽表.len(), 1, "声明输出类型是 [字节集] ⇒ 一个出参槽");
            assert_eq!(出参槽表[0].类型标签, 字节集, "输出槽的类型标签来自声明的 输出类型");
            assert_eq!(出参槽表[0].槽值, 0x1234_5678, "内联值原样递过去，不另造一套值形状");
        }
        关口结果::失败(失败值) => panic!("必须成功，实际 {失败值:?}"),
    }
    assert_eq!(收到.load(Ordering::Relaxed), 源文本, "类型标签随槽进黑盒");
}

/// **不是第二个扩展装载器**：资源号与能力号是两个号空间，同一个数字互不相通。
#[test]
fn 资源号与能力号是两个号空间_同一个数字互不相通() {
    // 资源号 1001 落在「支持库能力号段 1000–6999」里 —— 但那是**能力号**空间。
    // 关口只按资源号段（1–9999）判，它不认识任何扩展、也不认能力号。
    let mut 声明 = 参照实现声明();
    声明.资源号 = 1001;
    let 关口 = 资源网关口::从声明根建关口(&[声明]).expect("资源号只按资源号段判");
    assert_eq!(关口.已声明资源()[0].资源号, 1001);

    // 保留值 0 与越界的 10000 被拒（`0` 是保留标签「空」，不是一个资源号）。
    for 号值 in [0, 10_000] {
        let mut 声明 = 参照实现声明();
        声明.资源号 = 号值;
        assert!(资源网关口::从声明根建关口(&[声明]).is_err(), "资源号 {号值} 必须被拒");
    }
}
