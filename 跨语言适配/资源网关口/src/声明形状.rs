/// 一条操作。
///
/// **`操作` 是白名单，不是能力清单**：没列出的操作**不存在** —— 关口不「尽力而为」，直接拒。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 操作声明 {
    pub 操作号: u32,
    pub 名: String,
    /// 输入类型标签。§三 的形状是**单数** ⇒ 每次调用恒一个入参槽（见文件头「落不下去 · 二」）。
    pub 输入类型: u32,
    /// 输出类型标签。`0`（空）表示这条操作不返回值 —— 那时输出槽必须是空槽。
    pub 输出类型: u32,
    /// 这条操作的时间预算（毫秒）。**`0` 即拒**：没有预算就是「默认允许」。
    ///
    /// 关口**执行**它（不是资源自己保证）：资源是黑盒，不能指望它守时。
    /// 进程内无法抢占执行方，所以「执行」= 判有没有越界并报码（与 `调用调度` 同一条口径）。
    pub 超时毫秒: u64,
    /// 这条操作需要哪些副作用。**旁路字段**（§三 没有它，§五 第 3 层就没有触发条件）。
    ///
    /// `None` = 漏写 ⇒ 声明被拒（[`声明判据::需要副作用未声明`]）；
    /// `Some(空)` = 明确声明「不碰任何副作用」。**不许给默认值**：默认空集 = 那条判据永远不触发。
    pub 需要副作用: Option<副作用集>,
}

impl 操作声明 {
    /// 这条操作需要的副作用。
    ///
    /// 漏写时按 [`副作用集::全`]（**fail-closed**：全要 ⇒ 任何一个开关是 `false` 就拒）。
    /// 正常情况下走不到这一支 —— [`资源声明::校验`] 已经把漏写的声明挡在建关口之前；
    /// 这里再兜一层，是为了「宁可拒也不放行」。
    pub fn 需要的副作用(&self) -> 副作用集 {
        self.需要副作用.unwrap_or(副作用集::全)
    }
}

/// 一条资源声明 —— 一个不透明外部东西的可公开自述。
///
/// 形状源：§三。字段名与 JSON 键**逐字对应**（与 `平台声明.json` ↔ `平台信息` 同一条口径）：
/// 键名换名就是又造一个「同一事实两个名字」的漂移点。
///
/// **本类型不解析 JSON**：JSON → 本类型是声明侧的生成物/装载动作，不是关口的职责
/// （同 `适配器实现`：声明在进程内就是契约结构）。关口收的是**声明的根**（一串本类型），
/// 默认的根是**空的** ⇒ 一切都拒。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 资源声明 {
    pub 资源号: u32,
    pub 标识: String,
    /// 资源种类（自由文本，如「不透明外部程序」）。
    ///
    /// **刻意不做成枚举**：种类会长，门不能跟着长；种类是**声明**里的事，不是拓扑里的事
    /// （`全局连接器与网关.md` 第六节）。
    pub 种类: String,
    pub 入口: 入口声明,
    /// 操作白名单。**没列出的操作不存在**。
    pub 操作: Vec<操作声明>,
    pub 允许: 允许表,
    pub 隔离: 隔离声明,
    /// 这条资源的访问要不要留痕。**与关口的留痕开关取与**：
    /// 关口没启用留痕 ⇒ 一条都不记（留痕缺席时调用照样成功）。
    pub 留痕: bool,
}

impl 资源声明 {
    /// 按 §三 的三条硬规则 + 自洽性校验。
    ///
    /// **fail-closed**：任一条不过即拒，不许半载（`扩展装载与开发标准.md` 2.3 同一条）。
    /// 返回的 [`声明失败`] 带**具体判据**，不是一句「不合法」。
    pub fn 校验(&self) -> Result<(), 声明失败> {
        let 出 = |判据: 声明判据| -> Result<(), 声明失败> {
            Err(声明失败 {
                资源号: self.资源号,
                判据,
            })
        };

        // 规则：资源号必须在资源号段内。`0` 是保留标签「空」，不是一个资源号
        // （与 `契约声明/格式说明.md` 第四节「不许复用已登记的标签」同一条规则）。
        if !资源号段.含(self.资源号) {
            return 出(声明判据::资源号不在号段内 {
                资源号: self.资源号,
                起: 资源号段.起,
                止: 资源号段.止,
            });
        }
        if self.标识.is_empty() {
            return 出(声明判据::标识为空);
        }
        if self.种类.is_empty() {
            return 出(声明判据::种类为空);
        }
        // 操作白名单为空 ⇒ 这个资源什么都做不了。留着它只会让「有这个资源」这句话骗人。
        if self.操作.is_empty() {
            return 出(声明判据::操作表为空);
        }
        // 规则 3：入口不写进声明仓。
        if let Some(路径) = &self.入口.路径 {
            return 出(声明判据::入口写进声明仓 { 路径: 路径.clone() });
        }
        // 隔离自洽：进程内没有边界，声明「崩了只影响自己」是假的。
        if self.隔离.载体 == 载体::进程内 && self.隔离.崩溃影响面 == 崩溃影响面::仅本资源 {
            return 出(声明判据::隔离不自洽 {
                载体: self.隔离.载体,
                崩溃影响面: self.隔离.崩溃影响面,
            });
        }

        let mut 已见操作号: Vec<u32> = Vec::with_capacity(self.操作.len());
        for 操作 in &self.操作 {
            if 已见操作号.contains(&操作.操作号) {
                return 出(声明判据::操作号重复 {
                    操作号: 操作.操作号,
                });
            }
            已见操作号.push(操作.操作号);

            if 操作.名.is_empty() {
                return 出(声明判据::操作名为空 {
                    操作号: 操作.操作号,
                });
            }
            if 操作.超时毫秒 == 0 {
                return 出(声明判据::超时为零 {
                    操作号: 操作.操作号,
                });
            }
            if 操作.需要副作用.is_none() {
                return 出(声明判据::需要副作用未声明 {
                    操作号: 操作.操作号,
                });
            }
        }
        Ok(())
    }

    /// 按操作号取一条操作。**白名单语义**：取不到就是「不存在」，不是「尽力而为」。
    ///
    /// 这里没有任何一个具体操作号参与判定 —— 只看这张表认不认这个号。
    pub fn 取操作(&self, 操作号: u32) -> Option<&操作声明> {
        self.操作.iter().find(|操作| 操作.操作号 == 操作号)
    }
}

