/// 边界载体（源：`现代架构落点.md` 第九节的四种载体 A / B / C / D）。
///
/// 载体**换了不改形状**（槽是自描述的）—— 这是 `边界协议.md` 第三节那一条。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 载体 {
    /// A：进程内 ABI。
    进程内,
    /// B：本机 IPC / 本机进程。
    本机进程,
    /// C：跨机网络。
    跨机网络,
    /// D：WASM 沙箱。
    沙箱,
}

/// 崩溃影响面。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 崩溃影响面 {
    /// 崩了只带走这一份资源。
    仅本资源,
    /// 崩了带走整个进程。
    整个进程,
}

/// `入口` —— **声明说「怎么调」，部署说「调哪一份」**（§三 规则 3）。
///
/// `路径` 是**部署方**填的定位串；**声明仓里必须为空**。留这个字段不是为了存值，
/// 是为了让那条规则**判得了**：填了即 [`声明判据::入口写进声明仓`] —— 而不是只在文档里
/// 写一句「不写进声明仓」。真正被调的那一份在 [`crate::部署绑定`] 里。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 入口声明 {
    pub 载体: 载体,
    /// 声明侧恒为 `None`。
    pub 路径: Option<String>,
}

impl 入口声明 {
    /// 声明侧的形状：只说载体，不填路径。
    pub const fn 仅载体(载体: 载体) -> Self {
        Self { 载体, 路径: None }
    }
}

/// `隔离` —— 资源实例与别人怎么隔开。
///
/// **进程内实现给不出隔离**：一个地址空间里没有边界，`载体::进程内` 却说
/// `崩溃影响面::仅本资源` 就是说谎（何况 release 档是 `panic = "abort"`，
/// 一次 panic 带走整个平台）。故 [`资源声明::校验`] 把这一组合判成
/// [`声明判据::隔离不自洽`] —— 这是这三个字段在本节点唯一能落成的样子：
/// **声明自洽性可判，隔离本身不可给**（要真隔离得换载体，见 `现代架构落点.md` 第九节）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 隔离声明 {
    pub 载体: 载体,
    pub 可重建: bool,
    pub 崩溃影响面: 崩溃影响面,
}

