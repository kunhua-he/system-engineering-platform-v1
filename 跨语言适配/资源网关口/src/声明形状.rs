//! 资源声明的形状与校验。
//!
//! 形状源：`项目文档/设计文档/资源网关口.md` 第三节（**形状冻结**）。本文件逐字照它落，
//! 并在下面两处如实标出「按那个形状落不下去」的地方 —— 不替它圆。
//!
//! # 三条硬规则（§三 逐条落地，不是注释）
//!
//! | 规则 | 落点 |
//! |---|---|
//! | **`操作` 是白名单，不是能力清单** —— 没列的**不存在** | [`资源声明::取操作`] 查不到即拒；关口不「尽力而为」 |
//! | **`允许` 全默认 false** —— 「默认能用」是最危险的默认值 | [`允许表::default`] 就是全否（测试 `允许表默认全否` 钉住） |
//! | **`入口` 不写进声明仓** | [`入口声明::路径`] 在声明侧必须为空，填了即 [`声明判据::入口写进声明仓`] |
//!
//! # 实测：按 §三 的形状有两处**落不下去**
//!
//! ## 一 `操作` 缺「需要副作用」⇒ §五 第 3 层拒绝没有触发条件
//!
//! §五 第 3 层要拒「声明里**没允许**的副作用」，依据是 `允许` 里是 `false`。但 `允许`
//! 只说这个资源**最多能碰什么**；而调用形状 `资源调用(资源号, 操作号, 输入槽表)` 里
//! **没有任何**「这一次要碰什么」的入参，`操作` 里也没有这个字段 ⇒ **第 3 层无从触发**：
//! 任何调用都找不出「它想读文件」这个事实。判据在，但覆盖不到它声称覆盖的东西。
//!
//! 故新增旁路字段 [`操作声明::需要副作用`]（**旁路字段是允许的三种演进方式之一**，
//! 但须登记进 `契约声明/冻结登记.json` —— 那是 `契约声明/` 的件，不在本节点手里）。
//! 类型取 `Option`：**「缺键」与「明确声明空集」必须分得开** —— 缺键是漏写（拒），
//! 空集是「这条操作不碰任何副作用」（合法）。这与 `契约声明/格式说明.md` 第四节
//! 「`0` 与没填在运行期不可区分」是同一个坑，不重踩。
//!
//! ## 二 `输入类型` 是**单数**，而调用形状传的是「输入**槽表**」
//!
//! §三 的形状是 `{ "输入类型": 4, "输出类型": 5 }` —— 一条操作一个输入类型；
//! §四 的调用形状却是 `(资源号, 操作号, 输入槽表)`。两者只有在「一次调用恰好一个入参槽」
//! 时才自洽。本关口按 §三 的字面落：**恒一个入参槽**（`输入槽表` 长度必须为 1）。
//! 多入参操作在冻结形状里**表达不出来** —— 要改形状，不是本节点能自己决定的范围。
//! 报错时 `输入形状不符` 的 `槽位 / 期望类型 / 实际类型` 三项把两种情形都说得清：
//! 少一个槽 ⇒ 那个位置是「空」（标签 `0`）；多一个槽 ⇒ 期望「没有槽」（标签 `0`）。

use v1_contract::{声明数据, 号段};

/// 资源号段 —— 资源号的合法区间。
///
/// 源：`契约声明/号段图.json` 的「资源号命名空间」（资源号 1–9999；1–8999 扩展自带资源 ·
/// 9000–9999 平台级资源）。
///
/// **缺口（实测）**：`号段图.json` 的 `资源号段` **没有进生成物**
/// （`契约声明/src/声明数据.rs` 里搜不到「资源号段」），运行期取不到 ⇒ 只能在这里写一份。
/// 这是「同一事实两个来源」，缺口在生成链，不在本 crate。
/// 另：那张图把资源号分成「扩展自带 / 平台级」两段，**这个归属运行期也取不到**
/// ⇒ 关口判不了「这个号该由扩展声明还是平台声明」。
pub const 资源号段: 号段 = 号段::新(1, 9999);

