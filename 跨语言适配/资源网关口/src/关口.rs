//! 资源网关口 —— **全平台唯一的资源出入口**。
//!
//! 裁定件：`项目文档/设计文档/资源网关口.md`。拓扑位置：`全局连接器与网关.md` 第二节那张图
//! 里「资源」那一侧的腿，对应**判据 4「全平台只有一个资源出入口」**（恰好 1 处读资源声明 /
//! 派发资源调用 —— 那一处就是本文件的 [`资源网关口::资源调用`]）。
//!
//! # 它是什么，不是什么
//!
//! | 是 | 不是 |
//! |---|---|
//! | 一个**无状态判定点**：按声明放行或拒绝 | 不是资源的实现（资源是不透明的外部东西） |
//! | **唯一**出入口：所有资源访问都经它 | 不是第二个扩展装载器（见下） |
//! | **默认拒绝**：默认清单为空 ⇒ 一切都拒 | 不是「尽力而为地猜黑盒」 |
//!
//! **不许把资源网关口做成第二个扩展装载器**（§七 最后一条）：扩展**提供能力**
//! （底座认识它的编号），资源**被访问**（底座不认识它的内部）。两者是接缝的两侧，
//! 不许合并。落点：本 crate **不依赖** `装载入口` / `统一注册表`，关口里没有「能力号」
//! 这个概念，也不认任何扩展名。见测试 `资源号与能力号是两个号空间_同一个数字互不相通`。
//!
//! # 唯一出入口的形状
//!
//! ```text
//! 读：资源声明根 → 有哪些资源、各自能做什么、入口绑没绑     （关口构造时一次，见 `从声明根`）
//! 调：(资源号, 操作号, 输入槽表) → 输出槽表 | 结构化错误     （`资源调用`）
//! ```
//!
//! 与能力调用**同一条形状**（按号 + 按契约行序填值 + 结构化结果）：资源不是第二套东西，
//! 是同一套东西的另一个被调方。数据只走定长数据槽（类型标签在槽内）——
//! 槽是自描述的，所以载体换了不用改形状。
//!
//! # 拒绝发生在哪一层（§五，逐层专属码）
//!
//! ```text
//! 1 清单里没有这个号          → 资源未声明   22
//! 2 操作白名单里没有这个操作号  → 操作未声明   23
//! 3 需要的副作用声明里没允许    → 副作用未允许 24
//! 4 入参槽类型与声明不符        → 输入形状不符 25
//! 5 部署没绑入口（文档未列）    → 入口未绑定   26
//! 6 黑盒写回的类型不符（未列）  → 输出形状不符 27
//! 7 黑盒自己报失败（未列）      → 资源执行失败 28
//! ```
//!
//! **关口里没有任何一个具体资源号参与判定**：七层全是按声明判的 —— 这一处是「谁认这个号
//! 就归谁」的查表，不是「如果号是 22 就特殊处理」。
//!
//! # 超时与配额**由关口执行**
//!
//! 资源是黑盒，不能指望它守时（§四）。所以：超时预算取自声明的 `超时毫秒`，
//! 配额取自契约常量 `配额上限` / `配额窗口毫秒`（源：生成物 `声明数据`），
//! 账本是**按实例持有**的 [`配额账本`]（同 `调用调度` 那一本，不另造第二套）。
//!
//! **进程内无法抢占执行方**，所以「执行超时」在本节点只能落成「判有没有越界并报码」——
//! 与 `调用调度` 同一条口径（它也是这么做的）。真正强杀要跨进程（`现代架构落点.md` 形态 2）。
//! 这一条在测试 `超时_由关口执行_专属码4` 里被钉住：报码的同时，执行方确实跑完了。
//!
//! # 留痕不进关键路径（`开发规范.md` B7）
//!
//! 每次访问留痕（谁 · 调什么 · 入参指纹 · 结果 · 耗时），走内核唯一的
//! [`留痕缓冲`]（不另造第二套留痕）：不取锁、不分配、不阻塞，满了按策略丢弃并计数。
//! **留痕缺席时调用照样成功**（关口默认没有留痕缓冲）；**留痕存在时调用不变慢**
//! （实测读数见测试 `留痕不进关键路径_关掉照样成功_开着不变慢`）。
//!
//! 容量**不由关口自设**：`契约声明/常量表.json` 的「留痕容量」是**未定数**（值 `null`）
//! ⇒ 关口不发明一个默认容量，由调用方在 [`资源网关口::启用留痕`] 里给。
//!
//! # 多实例安全（`开发规范.md` B6）
//!
//! 声明表 · 绑定表 · 账本 · 留痕缓冲**全是实例字段**，模块里**没有** `static mut`、
//! 没有单例、没有进程级计数。「唯一」指的是**拓扑上只有一条路**，不是「进程里只有一个对象」
//! （`全局连接器与网关.md` 第六节最后一条）。实例号取自实例自身的地址（不是全局计数器），
//! 所以两份关口天然互不可见。

