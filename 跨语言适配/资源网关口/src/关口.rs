/// 一次调用的结果。**失败是结构化错误，不是异常**（宪法「失败可编程处理」）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 关口结果 {
    成功(数据槽),
    失败(资源错误),
}

impl 关口结果 {
    /// 失败时的 4 位码；成功给 `None`。
    pub fn 错误码(&self) -> Option<u32> {
        match self {
           关口结果::成功(_) => None,
            关口结果::失败(错) => Some(错.码()),
        }
    }

    /// 失败时的结构化错误；成功给 `None`。
    pub fn 错误(&self) -> Option<资源错误> {
        match self {
            关口结果::成功(_) => None,
            关口结果::失败(错) => Some(*错),
        }
    }
}

/// 读侧一行：一条资源现在是什么样（§二 的 `docker inspect` 那一格）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 资源摘要 {
    pub 资源号: u32,
    pub 标识: String,
    pub 种类: String,
    /// **健康否**的落点：声明里有它、部署没绑入口 ⇒ 调了会拿「入口未绑定」。
    pub 已绑定入口: bool,
    pub 操作表: Vec<操作摘要>,
}

/// 读侧一行：一条操作。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 操作摘要 {
    pub 操作号: u32,
    pub 名: String,
    pub 输入类型: u32,
    pub 输出类型: u32,
    pub 超时毫秒: u64,
    /// **已按校验后的形态给**：漏写的那一支在这里读不到（漏写的声明建不进关口）。
    pub 需要副作用: 副作用集,
}

