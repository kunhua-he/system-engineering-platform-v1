use v1_dispatch::配额账本;
use v1_trace::{丢弃策略, 留痕, 留痕缓冲};

use crate::入口绑定::{部署绑定, 黑盒结果, 黑盒体};
use crate::声明形状::{声明失败, 声明判据, 操作声明, 副作用集, 资源声明};
