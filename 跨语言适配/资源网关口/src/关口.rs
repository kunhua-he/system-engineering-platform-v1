/// **全平台唯一的资源出入口**（拓扑判据 4）。
///
/// 状态随实例持有：声明表 · 部署绑定 · 配额账本 · 留痕缓冲。
/// 构造要**两样东西**：声明的根（有哪些资源）+ 部署绑定（各自真调哪一份）——
/// 因为 §三 规则 3 把入口挪出了声明仓（见 `入口绑定.rs`）。
pub struct 资源网关口 {
    声明表: Vec<资源声明>,
    绑定表: 部署绑定,
    账本: 配额账本,
    留痕: Option<留痕缓冲>,
}

impl 资源网关口 {
    /// **默认状态：清单为空 ⇒ 一切都拒。**
    ///
    /// 这不是「没配好」，这是本节点**正确的默认值**（§二：拒绝是默认值，不是异常）。
    /// 「不许运行参照实现」这条禁令的落点就在这——默认清单**不含**参照实现 ⇒ 关口拒。
    pub fn 空() -> Self {
        Self {
            声明表: Vec::new(),
            绑定表: 部署绑定::空(),
            账本: Self::新账本(),
            留痕: None,
        }
    }

    /// 从一个**声明的根**建关口：逐条校验，任一条不过即整体拒绝（**不许半载**）。
    ///
    /// 空的声明根**是合法的**（就是默认状态）——与 `适配器实现::装载声明根` 不同：
    /// 那里空根是错（没有注册表就没有可寻址的表），这里空根是**默认拒绝**。
    ///
    /// **本函数不解析 JSON**：声明在进程内就是 [`资源声明`]；JSON → 声明是声明侧的
    /// 生成物/装载动作（同 `适配器实现`：它也不解析 JSON）。见 crate 级缺口。
    ///
    /// 声明按给定次序进清单（清单次序 = 声明根次序），校验只按声明判、不看具体号。
    pub fn 从声明根(声明根: &[资源声明]) -> Result<Self, 声明失败> {
        let mut 关口 = Self::空();
        关口.声明表 = Vec::with_capacity(声明根.len());
        for 声明 in 声明根 {
            声明.校验()?;
            if 关口.声明表.iter().any(|已| 已.资源号 == 声明.资源号) {
                return Err(声明失败 {
                    资源号: 声明.资源号,
                    判据: 声明判据::资源号重复 {
                        资源号: 声明.资源号,
                    },
                });
            }
            关口.声明表.push(声明.clone());
        }
        Ok(关口)
    }

    /// **部署侧**：把一个资源号绑到真正被调的那一份（声明说「怎么调」，部署说「调哪一份」）。
    ///
    /// 绑一个**声明里没有的号**也允许：那是部署先摆好位、声明后到（或声明被删了）。
    /// 它不影响放行 —— 放行只按声明判（绑了也不许调没声明的号）。
    pub fn 绑定入口(&mut self, 资源号: u32, 调用体: Box<dyn 黑盒体>) {
        self.绑定表.绑定(资源号, 调用体);
    }

    /// 启用留痕：`容量` 条、满了按 `策略` 丢弃并计数。
    ///
    /// 容量由调用方给（契约里的「留痕容量」是未定数，关口不发明一个默认值）。
    /// 不调本函数 ⇒ 没有留痕 ⇒ **调用照样成功**（留痕不进关键路径）。
    pub fn 启用留痕(&mut self, 容量: u32, 策略: 丢弃策略) {
        self.留痕 = Some(留痕缓冲::新建(容量, 策略));
    }

    /// **读侧：现在有哪些资源、各自能做什么、入口绑没绑。**
    ///
    /// 与调侧**同一份数据**：摘要是当场从声明表与绑定表取出来的，不是另存的一份表 ——
    /// 所以清单里报出的资源号拿去 [`资源网关口::资源调用`] 必然走得通同一条路。
    pub fn 已声明资源(&self) -> Vec<资源摘要> {
        self.声明表
            .iter()
            .map(|声明| 资源摘要 {
                资源号: 声明.资源号,
                标识: 声明.标识.clone(),
                种类: 声明.种类.clone(),
                已绑定入口: self.绑定表.已绑定(声明.资源号),
                操作表: 声明.操作.iter().map(摘要一行).collect(),
            })
            .collect()
    }

    /// **调：`(资源号, 操作号, 输入槽表) -> 输出槽表 | 结构化错误`** —— 全平台唯一的那一处
    /// 资源出入口（拓扑判据 4）。
    ///
    /// 七层判定全在这里，次序固定、不许换：
    ///
    /// ```text
    /// 取声明 → 取操作 → 判副作用 → 校输入形状 → 取部署绑定 → 问配额 → 执行 → 判耗时 → 判输出形状
    /// ```
    ///
    /// - **不 panic**：所有失败都是 [`关口结果::失败`] 带专属码。
    /// - **不吞**：执行方报的失败原样转出，不改写成别的码。
    /// - **超时与配额由关口执行**，不看资源自述。
    pub fn 资源调用(&self, 资源号: u32, 操作号: u32, 输入槽表: &[数据槽]) -> 关口结果 {
        let 开始 = Instant::now();
        let 声明 = self.取声明(资源号);
        let 结果 = self.派发(声明, 资源号, 操作号, 输入槽表);

        // 留痕：不进关键路径（不取锁、不分配、不阻塞；没有缓冲就整段跳过）。
        // 该记不该记：有缓冲，且（声明缺失 ⇒ 记 —— 未声明的访问是安全事件；声明说 false ⇒ 不记）。
        if let Some(缓冲) = &self.留痕
            && 声明.is_none_or(|声明| 声明.留痕)
        {
            缓冲.记(留痕 {
                实例: self.实例号(),
                能力号: 资源号,
                入参指纹: 槽表指纹(输入槽表),
                结果码: 结果.错误码().map_or(0, |码| 码 as i32),
                耗时微秒: u64::try_from(开始.elapsed().as_micros()).unwrap_or(u64::MAX),
                追踪号: u64::from(操作号),
            });
        }
        结果
    }

    /// 本实例的实例号。**取自实例自身的地址** —— 不是全局计数器（`开发规范.md` B6：
    /// 状态显式持有，不落进程级全局）。
    pub fn 实例号(&self) -> u64 {
        core::ptr::from_ref(self) as u64
    }

    /// 读留痕：最近 `条数` 条，按时间序（旧在前）。
    ///
    /// **字段映射（既有件的形状装不下资源调用的两个号，见 crate 级缺口）**：
    /// `能力号` 这一格装的是**资源号**、`追踪号` 这一格装的是**操作号**。
    pub fn 留痕读数(&self, 条数: u32) -> Vec<留痕> {
        match &self.留痕 {
            Some(缓冲) => 缓冲.取最近(条数),
            None => Vec::new(),
        }
    }

    /// 因缓冲满（或没有缓冲）而未写进缓冲的条数。**丢痕不许静默**。
    pub fn 留痕已丢弃(&self) -> u64 {
        match &self.留痕 {
            Some(缓冲) => 缓冲.已丢弃(),
            None => 0,
        }
    }

    /// 已声明的资源份数。
    pub fn 已声明资源数(&self) -> usize {
        self.声明表.len()
    }

    // ── 内部：判定与派发 ────────────────────────────────────────────────────

    /// 一本新账本：上限与窗口**取自契约常量**（源：生成物 `声明数据`），
    /// 关口不给调用方另开一个「自设配额」的口 —— 那会让配额口径变成每处一套。
    ///
    /// 账本按资源号记账；这本账本**只装资源号**（另开一本、不与能力号混账：
    /// `号段图.json` 的「四个号空间互不相通」）。
    fn 新账本() -> 配额账本 {
        配额账本::新建(声明数据::配额上限, 声明数据::配额窗口毫秒)
    }

    /// 按号取声明。取不到给 `None` —— **不是 panic**，也不编一份空声明。
    fn 取声明(&self, 资源号: u32) -> Option<&资源声明> {
        self.声明表.iter().find(|声明| 声明.资源号 == 资源号)
    }

    /// 七层判定 + 执行。**不含留痕**（留痕在调用入口那一层，因为它要测整段耗时）。
    fn 派发(
        &self,
        声明: Option<&资源声明>,
        资源号: u32,
        操作号: u32,
        输入槽表: &[数据槽],
    ) -> 关口结果 {
        // 第 1 层：清单里没有这个号。
        let Some(声明) = 声明 else {
            return 关口结果::失败(资源错误::资源未声明 { 资源号 });
        };
        // 第 2 层：操作白名单里没有这个操作号。**不尽力而为**。
        let Some(操作) = 声明.取操作(操作号) else {
            return 关口结果::失败(资源错误::操作未声明 { 资源号, 操作号 });
        };
        // 第 3 层：这条操作需要的副作用，声明里没允许。
        for 项 in 操作.需要的副作用().逐个() {
            if !声明.允许.允许(项) {
                return 关口结果::失败(资源错误::副作用未允许 {
                    资源号,
                    操作号,
                    副作用: 项,
                });
            }
        }
        // 第 4 层：输入形状（类型标签与声明的 `输入类型` 不符）。
        let 输入槽 = match 校输入形状(资源号, 操作号, 操作.输入类型, 输入槽表) {
            Ok(槽) => 槽,
            Err(错) => return 关口结果::失败(错),
        };
        // 第 5 层：部署方没绑入口（声明说「怎么调」，部署说「调哪一份」）。
        let Some(黑盒) = self.绑定表.取(资源号) else {
            return 关口结果::失败(资源错误::入口未绑定 { 资源号 });
        };
        // 配额：关口执行。超了就**不许进执行方**（与 `调用调度` 同一条次序）。
        if !self.账本.准调(资源号) {
            return 关口结果::失败(资源错误::配额用尽 { 资源号 });
        }

        // 执行：递一个槽、收一个槽。执行方是黑盒，这里不假设它守时。
        let 起 = Instant::now();
        let mut 输出槽 = 数据槽::空槽();
        let 体结果 = 黑盒.调用(操作号, 输入槽, &mut 输出槽);
        let 实测毫秒 = u64::try_from(起.elapsed().as_millis()).unwrap_or(u64::MAX);
        self.账本.记账(资源号, 实测毫秒);

        // 执行方报的失败原样转出（不吞、不改写成别的码）。
        if let 黑盒结果::失败(错) = 体结果 {
            return 关口结果::失败(错);
        }
        // 超时：**判并报码**（进程内无法抢占，故只能判有没有越界）。
        if 实测毫秒 > 操作.超时毫秒 {
            return 关口结果::失败(资源错误::超时 {
                资源号,
                操作号,
                毫秒: 实测毫秒,
            });
        }
        // 输出形状：不判它，错值就会**静默**流进上层。
        if 输出槽.类型标签 != 操作.输出类型 {
            return 关口结果::失败(资源错误::输出形状不符 {
                资源号,
                操作号,
                期望类型: 操作.输出类型,
                实际类型: 输出槽.类型标签,
            });
        }
        关口结果::成功(输出槽)
    }
}

impl Default for 资源网关口 {
    /// 默认就是**空清单**（默认拒绝）。
    fn default() -> Self {
        Self::空()
    }
}

/// 手写 `Debug`：`黑盒体` 是 trait 对象、不带 `Debug`，所以不 derive。
/// 读得出来的只有**可数的三样**（声明份数 · 绑定份数 · 留痕开没开）—— 不打印内部指针。
impl core::fmt::Debug for 资源网关口 {
    fn fmt(&self, 形: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        形.debug_struct("资源网关口")
            .field("声明份数", &self.声明表.len())
            .field("绑定份数", &self.绑定表.已绑定份数())
            .field("留痕", &self.留痕.is_some())
            .finish()
    }
}

