/// **第 4 层**：校输入形状。成功时把那个槽**交出来**（省得调用方再按下标取一次）。
///
/// 契约：声明的 `输入类型` 是**单数** ⇒ 恒一个入参槽（见 `声明形状.rs` 文件头「落不下去 · 二」）。
/// 个数不符也报同一个码：它是「形状不合契约」的一种 —— `槽位` / `期望类型` / `实际类型`
/// 三项把「缺一个」与「多一个」都说得清。
fn 校输入形状(
    资源号: u32,
    操作号: u32,
    输入类型: u32,
    输入槽表: &[数据槽],
) -> Result<数据槽, 资源错误> {
    let 槽 = match 输入槽表 {
        [槽] => *槽,
        // 缺槽：那个位置是「空」（标签 0）。
        [] => {
            return Err(资源错误::输入形状不符 {
                资源号,
                操作号,
                槽位: 0,
                期望类型: 输入类型,
                实际类型: 数据槽::空槽().类型标签,
            });
        }
        // 多槽：期望「那个位置没有槽」（标签 0）。
        [_, 多出的, ..] => {
            return Err(资源错误::输入形状不符 {
                资源号,
                操作号,
                槽位: 1,
                期望类型: 数据槽::空槽().类型标签,
                实际类型: 多出的.类型标签,
            });
        }
    };
    if 槽.类型标签 != 输入类型 {
        return Err(资源错误::输入形状不符 {
            资源号,
            操作号,
            槽位: 0,
            期望类型: 输入类型,
            实际类型: 槽.类型标签,
        });
    }
    Ok(槽)
}

/// 入参指纹 —— 留痕要能说清「**调什么**」而不必存下整张槽表。
///
/// FNV-1a 逐字节滚过每个槽的定长字段（类型标签 · 标志 · 长度 · 值）。
/// 常数时间 · 不分配 · 同一张槽表必得同一个数（测试 `留痕_同一张槽表指纹相同` 钉住）。
pub(crate) fn 槽表指纹(槽表: &[数据槽]) -> u64 {
    const 基: u64 = 0xcbf2_9ce4_8422_2325;
    const 乘: u64 = 0x0000_0100_0000_01b3;
    let mut 指纹 = 基;
    for 槽 in 槽表 {
        let 字节 = 槽
            .类型标签
            .to_le_bytes()
            .into_iter()
            .chain(槽.标志.to_le_bytes())
            .chain(槽.保留.to_le_bytes())
            .chain(槽.长度.to_le_bytes())
            .chain(槽.值.to_le_bytes());
        for 一字节 in 字节 {
            指纹 ^= u64::from(一字节);
            指纹 = 指纹.wrapping_mul(乘);
        }
    }
    指纹
}
