//! 测试（整文件即测试，`lib.rs` 用 `#[cfg(test)] #[path]` 挂进来）。
//!
//! 每条分支都要有读数：本进程恒许 · 其他进程默认拒 · 显式放行才许 · 空实例最严 · 取名称对得上。
//! 另外一条是**判据的反向样本**：`允许其他进程 = true` 时其他进程**必须**放行
//! （写反成「恒拒」本用例当场红）。

use super::*;

// ── 一 默认拒绝 ───────────────────────────────────────────────────────────

#[test]
fn 默认值拒其他进程() {
    assert!(!允许来源表::default().允许其他进程);
    assert!(!允许来源表::default().是否允许来源(调用来源::其他进程));
    assert_eq!(
        来源与权限::空实例().其他进程权限(调用来源::其他进程),
        Err(来源拒绝::其他进程未允许)
    );
}

#[test]
fn 空实例就是最严的那个() {
    assert_eq!(来源与权限::空实例(), 来源与权限::仅本进程);
}

// ── 二 本进程是基线 ───────────────────────────────────────────────────────

#[test]
fn 本进程恒许_不看这一位() {
    assert!(来源与权限::仅本进程.其他进程权限(调用来源::本进程).is_ok());
    // 连「全拒」的默认值也拦不住本进程 —— 这一维管的不是它。
    assert!(允许来源表::仅本进程.是否允许来源(调用来源::本进程));
}

// ── 三 显式放行 ───────────────────────────────────────────────────────────

#[test]
fn 显式放行才许其他进程() {
    let 放行 = 来源与权限 {
        允许来源表: 允许来源表 {
            允许其他进程: true
        },
    };
    assert!(放行.其他进程权限(调用来源::其他进程).is_ok());
    // 本进程照样许（放行不放行它都在边界内）。
    assert!(放行.其他进程权限(调用来源::本进程).is_ok());
}

/// **反向样本**：放行后**必须**许 —— 把 `是否允许来源` 写成「恒拒」本用例当场红。
#[test]
fn 反向样本_放行后必须许() {
    let 放行 = 允许来源表 {
        允许其他进程: true
    };
    assert!(放行.是否允许来源(调用来源::其他进程));
}

// ── 四 名字对得上 ─────────────────────────────────────────────────────────

#[test]
fn 取名称对得上() {
    assert_eq!(调用来源::本进程.取名称(), "本进程");
    assert_eq!(调用来源::其他进程.取名称(), "其他进程");
    assert_eq!(来源拒绝::其他进程未允许.取名称(), "其他进程未允许");
}
