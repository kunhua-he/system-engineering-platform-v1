/// 规则 3：`入口` 不写进声明仓 —— 填了即拒（这条规则因此**判得了**，不只是注释）。
#[test]
fn 声明校验_入口写进声明仓即拒() {
    let mut 声明 = 参照实现声明();
    声明.入口.路径 = Some("/usr/local/bin/el.exe".to_owned());
    let 失败 = 声明.校验().expect_err("入口写进声明仓必须拒");
    assert!(matches!(失败.判据, 声明判据::入口写进声明仓 { .. }));
    assert_eq!(失败.取错误码(), 声明数据::错误码_13, "复用「声明不自洽」");
    assert!(失败.需人工() && !失败.可自愈());
}

