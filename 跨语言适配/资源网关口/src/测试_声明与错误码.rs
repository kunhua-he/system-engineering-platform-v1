#[test]
fn 声明校验_其余几条判据() {
    参照实现声明().校验().expect("原样合法");

    let mut 空操作 = 参照实现声明();
    空操作.操作.clear();
    assert!(matches!(
        空操作.校验().expect_err("操作表为空"),
        声明失败 {
            判据: 声明判据::操作表为空,
            ..
        }
    ));

    let mut 重号 = 参照实现声明();
    重号.操作[1].操作号 = 1;
    assert!(matches!(
        重号.校验().expect_err("操作号重复"),
        声明失败 {
            判据: 声明判据::操作号重复 { 操作号: 1 },
            ..
        }
    ));

    let mut 空名 = 参照实现声明();
    空名.操作[0].名 = String::new();
    assert!(matches!(
        空名.校验().expect_err("操作名为空"),
        声明失败 {
            判据: 声明判据::操作名为空 { .. },
            ..
        }
    ));

    let mut 空标识 = 参照实现声明();
    空标识.标识 = String::new();
    assert!(matches!(
        空标识.校验().expect_err("标识为空"),
        声明失败 {
            判据: 声明判据::标识为空,
            ..
        }
    ));

    let mut 空种类 = 参照实现声明();
    空种类.种类 = String::new();
    assert!(matches!(
        空种类.校验().expect_err("种类为空"),
        声明失败 {
            判据: 声明判据::种类为空,
            ..
        }
    ));
}

