// ══ 十 错误码：登记内容与三项业务判断 ═════════════════════════════════════

#[test]
fn 本关口错误码_七条齐全_段位与码自洽() {
    assert_eq!(关口段位, 0, "段位 0 = 底座自有（内核 ＋ 跨语言适配）");
    assert_eq!(本关口错误码.len(), 7);
    let 码表: Vec<u32> = 本关口错误码.iter().map(|项| 项.码).collect();
    assert_eq!(码表, vec![22, 23, 24, 25, 26, 27, 28]);
    // 码是**生成物**（源：契约声明/错误码表/0022–0028.json），这里不重算 ——
    // 早先写的是 `关口段位 * 号段类宽度 + 序号`，那是同一事实的第二个来源。
    assert_eq!(码_资源未声明, 声明数据::错误码_22);
    assert_eq!(码_资源执行失败, 声明数据::错误码_28);
    for 一项 in &本关口错误码 {
        assert_eq!(
            一项.段位,
            一项.码 / 声明数据::号段类宽度,
            "冗余登记项：段位必须等于「码 除以 号段类宽度」"
        );
        assert!(!一项.名称.is_empty() && !一项.说明.is_empty());
        assert!(!一项.归属.contains("借段"), "段位 0 就是本关口的归属，不许再写「借段」");
    }
    // 复用的三个底座自有码仍查得到（它们不在本关口错误码表里）。
    assert_eq!(
        内核自有登记(声明数据::错误码_4.取号值()).expect("超时").名称,
        "超时"
    );
    assert_eq!(
        内核自有登记(声明数据::错误码_5.取号值()).expect("配额用尽").名称,
        "配额用尽"
    );
    assert_eq!(
        内核自有登记(声明数据::错误码_13.取号值()).expect("声明不自洽").名称,
        "声明不自洽"
    );
    assert!(内核自有登记(1).is_none(), "没登记过的号不许编一条");
}

/// 四层各一条专属码：**互不相同**，且不与复用的内核码相撞。
#[test]
fn 四层专属码互不相同_且与复用的内核码不撞() {
    let 四层 = [
        码_资源未声明,
        码_操作未声明,
        码_副作用未允许,
        码_输入形状不符,
    ];
    for (序, 前层) in 四层.iter().enumerate() {
        for 后层 in &四层[序 + 1..] {
            assert_ne!(前层, 后层, "四层必须各有专属码，不许笼统报一个");
        }
    }
    let 复用 = [
        声明数据::错误码_4.取号值(),
        声明数据::错误码_5.取号值(),
        声明数据::错误码_13.取号值(),
    ];
    for 错误码 in &四层 {
        assert!(!复用.contains(错误码), "专属码不许与复用的内核码撞");
    }
}

/// 三项业务判断**到得了运行期**（不是注释）。
#[test]
fn 三项业务判断_到得了运行期() {
    let 业务判断 = 资源错误::副作用未允许 {
        资源号: 参照实现号,
        操作号: 1,
        副作用: 副作用::读文件,
    }
    .业务判断();
    assert!(业务判断.需人工, "放开一个副作用是安全裁决 ⇒ 需人工");
    assert!(!业务判断.可重试 && !业务判断.可自愈);

    let 业务判断 = 资源错误::超时 {
        资源号: 参照实现号,
        操作号: 1,
        毫秒: 9,
    }
    .业务判断();
    assert!(业务判断.可重试 && 业务判断.可自愈 && !业务判断.需人工, "与内核自有的「超时」逐项一致");

    assert!(资源错误::配额用尽 { 资源号: 参照实现号 }.业务判断().可重试);
    assert!(资源错误::入口未绑定 { 资源号: 参照实现号 }.业务判断().可重试);
}
