//! 副作用 · 允许 —— 「这个资源**最多**能碰哪几件事」。
//!
//! 本节的三条硬规则见 `声明形状.rs` 文件头（`允许` 全默认 false 是其中一条）。

// ════════════════════════════════════════════════════════════════════════════
// 副作用 · 允许
// ════════════════════════════════════════════════════════════════════════════

/// 副作用类 —— `允许` 里四个开关各自对应的那件事。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 副作用 {
    读文件,
    写文件,
    联网,
    派生进程,
}

impl 副作用 {
    /// 全部四种。**次序固定**：`副作用集::逐项取副作用` 按它报出「哪一个没被允许」。
    pub const 全部副作用: [副作用; 4] = [
        副作用::读文件,
        副作用::写文件,
        副作用::联网,
        副作用::派生进程,
    ];

    /// 名字（错误码说明与留痕里要能读到它）。
    pub const fn 取名称(&self) -> &'static str {
        match self {
            副作用::读文件 => "读文件",
            副作用::写文件 => "写文件",
            副作用::联网 => "联网",
            副作用::派生进程 => "派生进程",
        }
    }

    /// 它在位图里的那一位。
    const fn 取位掩码(&self) -> u8 {
        1 << (*self as u8)
    }
}

/// 副作用集 —— 位图。
///
/// **空集是合法值**：它表示「这条操作不碰任何副作用」。它与「没声明」不是一回事
/// （见 [`操作声明::需要副作用`]）。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 副作用集(u8);

impl 副作用集 {
    /// 空集：不碰任何副作用。
    pub const 空实例: Self = Self(0);
    /// 全集：四种全要。**只做 fail-closed 兜底用**（见 [`操作声明::需要的副作用`]）。
    pub const 全集: Self = Self(0b1111);

    /// 只含一项。
    pub const fn 造单项集(副作用项: 副作用) -> Self {
        Self(副作用项.取位掩码())
    }

    /// 这一项在不在集合里。
    pub const fn 包含(&self, 副作用项: 副作用) -> bool {
        self.0 & 副作用项.取位掩码() != 0
    }

    /// 并进一项。
    pub fn 并入副作用(&mut self, 副作用项: 副作用) {
        self.0 |= 副作用项.取位掩码();
    }

    /// 集合为空？
    pub const fn 是否空(&self) -> bool {
        self.0 == 0
    }

    /// 逐项列出（**次序固定**，取 [`副作用::全部`] 的次序）。
    pub fn 逐项取副作用(&self) -> impl Iterator<Item = 副作用> + '_ {
        副作用::全部副作用.into_iter().filter(move |项| self.包含(*项))
    }
}

/// `允许` —— 这个资源**最多**能碰哪几件事。
///
/// **四个开关全默认 `false`**（§三 规则 2）：要读文件就显式写 `true`，且要说明读哪个根。
/// 「默认能用」是最危险的默认值 —— 默认允许 = 每加一个资源都扩大攻击面。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 允许表 {
    pub 读文件: bool,
    pub 写文件: bool,
    pub 联网: bool,
    pub 派生进程: bool,
}

impl 允许表 {
    /// 全否 —— 这就是默认值。
    pub const 全否: Self = Self {
        读文件: false,
        写文件: false,
        联网: false,
        派生进程: false,
    };

    /// 这一项副作用**有没有被允许**。四个开关各管一件事，不互相顶替。
    pub const fn 是否允许副作用(&self, 副作用项: 副作用) -> bool {
        match 副作用项 {
            副作用::读文件 => self.读文件,
            副作用::写文件 => self.写文件,
            副作用::联网 => self.联网,
            副作用::派生进程 => self.派生进程,
        }
    }
}
