//! 声明失败 —— 一条声明没通过校验的**具体判据**。
//!
//! 逐条可判，不是一句「不合法」；错误码复用内核自有的 `13`「声明不自洽」。

use v1_contract::声明数据;

use super::载体与入口::{崩溃影响面, 载体类型};

// ════════════════════════════════════════════════════════════════════════════
// 声明失败
// ════════════════════════════════════════════════════════════════════════════

/// 一条声明没通过校验的**具体判据**。逐条可判，不是一句「不合法」。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 声明判据 {
    /// 资源号不在资源号段内（含保留值 `0`）。
    资源号不在号段内 { 资源号: u32, 段起点: u32, 段止: u32 },
    标识为空,
    种类为空,
    操作表为空,
    操作号重复 { 操作号: u32 },
    操作名为空 { 操作号: u32 },
    /// `超时毫秒 == 0`：没有预算 = 默认允许它跑到天荒地老。
    超时为零 { 操作号: u32 },
    /// `需要副作用` 漏写：§五 第 3 层会因此判不了。
    需要副作用未声明 { 操作号: u32 },
    /// `入口` 被写进了声明仓（§三 规则 3）。
    入口写进声明仓 { 路径: String },
    /// `隔离` 自相矛盾（进程内 + 崩了只影响自身）。
    隔离不自洽 {
        载体类型: 载体类型,
        崩溃影响面: 崩溃影响面,
    },
    /// 声明根里两条声明用了同一个资源号。
    资源号重复 { 资源号: u32 },
}

/// 一条声明没通过校验。
///
/// **错误码复用内核自有的 `13`「声明不自洽」**（段位 0）：声明不合法是同一类失败，
/// 不因为报在哪一层而换码（`契约声明/格式说明.md` 第五节）。
/// `判据` 字段说清是哪一条不过 —— 码与原因**分开**，正是「失败可编程处理」的形状。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 声明失败 {
    pub 资源号: u32,
    pub 判据: 声明判据,
}

impl 声明失败 {
    /// 错误码：复用 `13`「声明不自洽」（源：生成物 `声明数据::错误码_0013`）。
    pub const fn 取错误码(&self) -> u32 {
        声明数据::错误码_0013.取号值()
    }

    /// 错误码名称（同一来源：`契约声明/错误码表/0013.json`）。
    pub const fn 名称(&self) -> &'static str {
        "声明不自洽"
    }

    /// 三项业务判断（同 `契约声明/错误码表/0013.json`）。
    pub const fn 可重试(&self) -> bool {
        false
    }
    pub const fn 可自愈(&self) -> bool {
        false
    }
    pub const fn 需人工(&self) -> bool {
        true
    }
}
