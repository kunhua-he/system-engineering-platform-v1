//! 来源与权限 —— 「**谁在调**这个副作用能力」（架构收敛方案项 E06）。
//!
//! 与 [`副作用与允许`] 分工不同，别混：
//!
//! | 形状 | 回答的问题 |
//! |---|---|
//! | [`允许表`](super::副作用与允许::允许表) | 这个资源**最多**能碰哪几件事（读文件 / 写文件 / 联网 / 派生进程） |
//! | [`来源与权限`] | 这几件事**谁能**让它做（本进程 / 其他进程） |
//!
//! 「访问边界」只管住了**做什么**（副作用全默认 `false`）；「谁在调」这一维先前没有形状
//! ⇒ 任何来源都能调一个已允许的副作用能力，等于边界只有一半。本件补上另一半。
//!
//! # 两条硬规则
//!
//! 1. **默认拒绝**：`允许其他进程` 默认 `false` —— 与 [`允许表`](super::副作用与允许::允许表)
//!    「默认能用是最危险的默认值」同一条口径。要让别的进程调，**显式写 `true`**。
//! 2. **本进程是基线**：本进程**恒许**（它就在同一个边界里）；这一维管的是**别的进程**。
//!    故「默认拒绝」拒的是 `其他进程`，不是 `本进程`。
//!
//! # 本件不做（如实登记）
//!
//! - **不取真实来源**：谁是「其他进程」由宿主/关口在调用时判（本件只收一个已判好的
//!   [`调用来源`]）—— 本件是**形状与判据**，不碰进程表、不看 pid、不读 /proc。
//! - **不接进 `派发`**：调用形状 `资源调用(资源号, 操作号, 输入槽表)` 是冻结面，里面
//!   **没有**来源入参 ⇒ 「把来源喂进七层判定」要动冻结的调用形状，不在本腿最小修法内。

// ════════════════════════════════════════════════════════════════════════════
// 来源与权限
// ════════════════════════════════════════════════════════════════════════════

/// 调用来源 —— 这一次调用**是谁发的**。
///
/// 只分两种：`本进程`（同一边界内）与 `其他进程`（边界外）。**刻意不做成开区间**
/// （如「哪个 pid」）：来源只影响「要不要显式放行」这一个判断，多出来的信息没人用，
/// 多一维就是多一个漂移点。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 调用来源 {
    本进程,
    其他进程,
}

impl 调用来源 {
    /// 名字（错误说明与留痕里要能读到它）。
    pub const fn 取名称(&self) -> &'static str {
        match self {
            调用来源::本进程 => "本进程",
            调用来源::其他进程 => "其他进程",
        }
    }
}

/// 允许来源表 —— **谁能**让这个资源做它已允许的副作用。
///
/// **默认全否**：`允许其他进程` 默认 `false`（同 [`允许表`](super::副作用与允许::允许表)
/// 「默认能用是最危险的默认值」）。要放别的进程进来，显式写 `true`。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 允许来源表 {
    /// 要不要放「其他进程」进来。`false` = 只许本进程（**这就是默认值**）。
    pub 允许其他进程: bool,
}

impl 允许来源表 {
    /// 仅本进程 —— 这就是默认值（`允许其他进程 = false`）。
    pub const 仅本进程: Self = Self {
        允许其他进程: false,
    };

    /// 本进程恒许；其他进程**看这一位**。四个副作用开关怎么分工，这一位就怎么分工 ——
    /// 不互相顶替。
    pub const fn 是否允许来源(&self, 来源: 调用来源) -> bool {
        match 来源 {
            调用来源::本进程 => true,
            调用来源::其他进程 => self.允许其他进程,
        }
    }
}

/// 来源与权限 —— 一条资源声明对「谁在调」的答复。
///
/// 形状与 [`允许表`](super::副作用与允许::允许表) 平级：它也是资源声明的**一维**，
/// 与副作用那一维**取与**（两个都放行才算放行）。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct 来源与权限 {
    pub 允许来源表: 允许来源表,
}

impl 来源与权限 {
    /// 仅本进程 —— 这就是默认值（最严：其他进程一律拒）。
    pub const 仅本进程: Self = Self {
        允许来源表: 允许来源表::仅本进程,
    };

    /// 空实例 = 最严的那个（仅本进程）。与 [`允许表::全否`](super::副作用与允许::允许表::全否)
    /// 同一条口径：**默认值就是最严的那一个**，不是「不设限」。
    pub const fn 空实例() -> Self {
        Self::仅本进程
    }

    /// **来源检查位**：这个来源**能不能**让它做这件事。
    ///
    /// 这就是 E06 缺的那个判据 —— 返回 `Err` 即「拒」，调用方据此拦在副作用之前。
    /// `其他进程` 而 `允许其他进程 = false` ⇒ [`来源拒绝::其他进程未允许`]。
    pub const fn 其他进程权限(&self, 来源: 调用来源) -> Result<(), 来源拒绝> {
        if self.允许来源表.是否允许来源(来源) {
            Ok(())
        } else {
            Err(来源拒绝::其他进程未允许)
        }
    }
}

/// 来源被拒的原因。**结构化**（不是一个 `bool` 或一句文本）——
/// 调用方要能据它区分「来源不对」与「副作用没允许」这两类拒。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 来源拒绝 {
    /// 调用来自其他进程，而声明没显式放行（`允许其他进程 = false`）。
    其他进程未允许,
}

impl 来源拒绝 {
    /// 名字（错误说明与留痕里要能读到它）。
    pub const fn 取名称(&self) -> &'static str {
        match self {
            来源拒绝::其他进程未允许 => "其他进程未允许",
        }
    }
}
