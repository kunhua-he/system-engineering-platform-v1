//! 操作 · 资源声明 —— 一条资源声明的形状与校验。
//!
//! 本节的三条硬规则见 `声明形状.rs` 文件头（`操作` 是白名单不是能力清单是其中一条）。

use v1_contract::号段;

use super::失败::{声明失败, 声明判据};
use super::副作用与允许::{允许表, 副作用集};
use super::载体与入口::{入口声明, 崩溃影响面, 隔离声明, 载体};

/// 资源号段 —— 资源号的合法区间。
///
/// 源：`契约声明/号段图.json` 的「资源号命名空间」（资源号 1–9999；1–8999 扩展自带资源 ·
/// 9000–9999 平台级资源）。
///
/// **缺口（实测）**：`号段图.json` 的 `资源号段` **没有进生成物**
/// （`契约声明/src/声明数据.rs` 里搜不到「资源号段」），运行期取不到 ⇒ 只能在这里写一份。
/// 这是「同一事实两个来源」，缺口在生成链，不在本 crate。
/// 另：那张图把资源号分成「扩展自带 / 平台级」两段，**这个归属运行期也取不到**
/// ⇒ 关口判不了「这个号该由扩展声明还是平台声明」。
pub const 资源号段: 号段 = 号段::新(1, 9999);

