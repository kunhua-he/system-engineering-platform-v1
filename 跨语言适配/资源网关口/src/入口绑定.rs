//! 入口 —— **声明说「怎么调」，部署说「调哪一份」**（`资源网关口.md` 第三节 规则 3）。
//!
//! # `入口` 不写进声明仓，那它从哪来
//!
//! §三 的形状里有 `入口` 这个键，但它的 `路径` 明写「由部署方填，不写进声明仓」。
//! 于是「这个资源真被哪一份实现」这件事**不在声明里**，只有两个可能的地方：
//!
//! 1. **部署绑定**（本文件）—— 部署方在装配时把 `资源号 → 真正被调的那一份` 绑进关口。
//!    这是本节点的落点。
//! 2. 声明仓 —— **明确不做**：声明可公开、入口不公开，混在一起两边都做不好。
//!
//! 所以关口的构造要**两样东西**：一个**声明的根**（有哪些资源、各自能做什么）+ 一份
//! **部署绑定**（各自真调哪一份）。默认两样都是空的 ⇒ 一切都拒。
//!
//! 这与「资源是黑盒」是同一件事的两面：底座不知道那一份的内部，但必须知道**它在哪里**——
//! 而「在哪里」是部署的事实，不是声明的事实。
//!
//! # 进程内的那一份长什么样
//!
//! [`黑盒体`] 是**载体无关**的：进程内实现就是本 trait 的一个实现，**跨进程**实现是同一个
//! trait 的另一个实现（`跨进程体`，经 Unix socket 走**同一份**线协议）—— 形状不变，
//! 因为数据只走定长槽（`边界协议.md` 第三节）。进程池、WASM 沙箱仍未裁（见 crate 级缺口）。

use v1_contract::数据槽;

use crate::拒绝码::资源错误;

/// 真正被调的那一份。**不透明**：底座只按 `操作号` 递槽、收槽，不看它内部。
///
/// 实现方须守两条：
/// 1. **不许跨边界抛异常**（`边界协议.md` 第五节）：失败一律用 [`黑盒结果::失败`]。
/// 2. **不许指望自身守时**：超时由关口判（`资源网关口.md` 第四节最后一条）——
///    实现方跑多久是它的事，越界由关口报码。
pub trait 黑盒体 {
    /// 按操作号调一次。**表进表出**（§四：`(资源号, 操作号, 输入槽表) -> 输出槽表`）。
    ///
    /// `输入槽表` 已由关口校过形状（**逐位**对齐声明的 `输入类型` 表：个数与行序都对得上），
    /// 可以放心用；实现方须把结果**写进 `输出槽表`**（每个槽的类型标签用声明的 `输出类型`
    /// 表逐位对应的那一项）—— 表长为 0 即这条操作不返回值（那时 `输出类型` 也是空表）。
    fn 调用操作(&self, 操作号: u32, 输入槽表: &[数据槽], 输出槽表: &mut Vec<数据槽>) -> 黑盒结果;
}

/// 一次调用的结果。
///
/// **失败走返回值，不走异常**：一个适配器适配所有语言的前提正是**不假设对端运行时**。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 黑盒结果 {
    成功,
    /// 黑盒自身报失败。码由实现方给（通常是 [`资源错误::资源执行失败`]）。
    失败(资源错误),
}

/// 部署绑定 —— `资源号 → 真正被调的那一份`。
///
/// **状态随实例持有，不落进程级全局**（`开发规范.md` B6）：两份部署绑定天然互不可见，
/// 同进程里开两个关口就是两套互不干扰的绑定（多实例安全）。
///
/// 同一个资源号绑两次 ⇒ **后者取代前者**：部署可换一份（这正是声明里 `可重建` 的意思），
/// 换的过程不改声明 —— 声明没变、入口变了，两件事本来就该分开。
#[derive(Default)]
pub struct 部署绑定 {
    项表: Vec<(u32, Box<dyn 黑盒体>)>,
}

impl 部署绑定 {
    /// 空绑定：一条资源都没绑 ⇒ 任何调用都拿「入口未绑定」（若声明里有它）。
    pub fn 空实例() -> Self {
        Self { 项表: Vec::new() }
    }

    /// 绑一份。同一个号再绑即取代。
    pub fn 绑定资源(&mut self, 资源号: u32, 调用体: Box<dyn 黑盒体>) {
        if let Some(格子) = self.项表.iter_mut().find(|格子| 格子.0 == 资源号) {
            格子.1 = 调用体;
            return;
        }
        self.项表.push((资源号, 调用体));
    }

    /// 这个号绑过没有。**读侧要它**：声明里有、这里没有 ⇒ 这条资源是「调了会拒」的状态。
    pub fn 已绑定(&self, 资源号: u32) -> bool {
        self.项表.iter().any(|格子| 格子.0 == 资源号)
    }

    /// 已绑的份数（验证面用）。
    pub fn 已绑定份数(&self) -> usize {
        self.项表.len()
    }

    /// 按资源号取那一份。取不到给 `None`（**不是 panic**，也不是编一个空实现）。
    pub(crate) fn 按资源号取(&self, 资源号: u32) -> Option<&dyn 黑盒体> {
        self.项表
            .iter()
            .find(|格子| 格子.0 == 资源号)
            .map(|格子| 格子.1.as_ref())
    }
}
