/// 配额：打满契约常量 `配额上限` 之后，第 上限+1 次报「配额用尽」，且**不进黑盒**。
#[test]
fn 配额_由关口执行_专属码5() {
    let (关口, 调用计数) = 参照实现关口();
    let 截断上限 = 声明数据::配额上限;
    for 次版本 in 0..截断上限 {
        assert!(
            matches!(关口.资源调用(参照实现号, 1, &文本入参()), 关口结果::成功(_)),
            "第 {次版本} 次（上限 {截断上限} 未满）必须成功"
        );
    }
    let 错误 = 取拒绝原因(关口.资源调用(参照实现号, 1, &文本入参()));
    assert_eq!(错误, 资源错误::配额用尽 { 资源号: 参照实现号 });
    assert_eq!(错误.取错误码(), 声明数据::错误码_0005, "复用内核自有的「配额用尽」码");
    assert_eq!(调用计数.load(Ordering::Relaxed), 截断上限, "超配额那一次不许碰到黑盒");
}

