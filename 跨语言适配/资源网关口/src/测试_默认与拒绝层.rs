/// 第 4 层：输入形状不合契约（槽的类型标签与声明的 `输入类型` 不符）。
#[test]
fn 第4层_输入形状不符_专属码25() {
    let (关口, 计数) = 参照实现关口();
    // 操作 1 要「文本」，给一个「整数」槽。
    let 错 = 拒因(关口.资源调用(参照实现号, 1, &[数据槽::内联(整数.into(), 7, 0)]));
    assert_eq!(
        错,
        资源错误::输入形状不符 {
            资源号: 参照实现号,
            操作号: 1,
            槽位: 0,
            期望类型: 文本,
            实际类型: 整数,
        }
    );
    assert_eq!(错.码(), 码_输入形状不符);
    // 个数不符也归这一层（声明的 `输入类型` 是单数 ⇒ 恒一个入参槽）。
    assert_eq!(
        拒因(关口.资源调用(参照实现号, 1, &[])).码(),
        码_输入形状不符
    );
    assert_eq!(
        拒因(关口.资源调用(
            参照实现号,
            1,
            &[数据槽::内联(文本.into(), 0, 0), 数据槽::内联(文本.into(), 0, 0)]
        ))
        .码(),
        码_输入形状不符
    );
    assert_eq!(计数.load(Ordering::Relaxed), 0, "形状不合不许碰到黑盒");
}

// ══ 三 超时与配额：由关口执行，不由资源自己保证 ═════════════════════════

/// 超时：黑盒自己跑 5 毫秒、声明预算 1 毫秒 ⇒ 关口报码。
///
/// 同时钉住一条**实测事实**：进程内无法抢占执行方，所以「关口执行超时」只能是
/// 「判有没有越界并报码」—— 报码的同时黑盒确实跑完了（与 `调用调度` 同一条口径）。
#[test]
fn 超时_由关口执行_专属码4() {
    let mut 声明 = 参照实现声明();
    声明.操作[0].超时毫秒 = 1;
    let mut 关口 = 资源网关口::从声明根(&[声明]).expect("合法");
    let mut 盒 = 夹具黑盒::新(参照实现号, 字节集);
    盒.睡毫秒 = 5;
    let 计数 = Arc::clone(&盒.跑过);
    关口.绑定入口(参照实现号, Box::new(盒));

    let 错 = 拒因(关口.资源调用(参照实现号, 1, &文本入参()));
    assert_eq!(错.码(), 声明数据::错误码_4, "复用内核自有的「超时」码");
    match 错 {
        资源错误::超时 { 毫秒, .. } => assert!(毫秒 >= 5, "报的是实测耗时，实际 {毫秒}"),
        其它 => panic!("必须报超时，实际 {其它:?}"),
    }
    assert_eq!(
        计数.load(Ordering::Relaxed),
        1,
        "进程内无法抢占：报码的同时黑盒确实跑完了"
    );
}

/// 预算够时同一条调用照常成功 —— 超时判的是越界，不是「有睡眠就拒」。
#[test]
fn 超时_预算够时照常成功() {
    let mut 关口 = 资源网关口::从声明根(&[参照实现声明()]).expect("合法");
    let mut 盒 = 夹具黑盒::新(参照实现号, 字节集);
    盒.睡毫秒 = 5; // 声明预算是 5000 毫秒
    关口.绑定入口(参照实现号, Box::new(盒));
    assert!(matches!(
        关口.资源调用(参照实现号, 1, &文本入参()),
        关口结果::成功(_)
    ));
}

/// 配额：打满契约常量 `配额上限` 之后，第 上限+1 次报「配额用尽」，且**不进黑盒**。
#[test]
fn 配额_由关口执行_专属码5() {
    let (关口, 计数) = 参照实现关口();
    let 上限 = 声明数据::配额上限;
    for 次 in 0..上限 {
        assert!(
            matches!(关口.资源调用(参照实现号, 1, &文本入参()), 关口结果::成功(_)),
            "第 {次} 次（上限 {上限} 未满）必须成功"
        );
    }
    let 错 = 拒因(关口.资源调用(参照实现号, 1, &文本入参()));
    assert_eq!(错, 资源错误::配额用尽 { 资源号: 参照实现号 });
    assert_eq!(错.码(), 声明数据::错误码_5, "复用内核自有的「配额用尽」码");
    assert_eq!(计数.load(Ordering::Relaxed), 上限, "超配额那一次不许碰到黑盒");
}

