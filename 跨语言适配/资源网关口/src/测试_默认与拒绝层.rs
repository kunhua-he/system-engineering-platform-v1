/// 第 3 层：声明里没允许的副作用（`允许` 默认全 false）。**并给正向样本**证明这一层
/// 是按声明判的，不是硬编码。
#[test]
fn 第3层_声明里没允许的副作用_专属码24() {
    let mut 声明 = 参照实现声明();
    声明.操作[0].需要副作用 = Some(副作用集::单个(副作用::读文件));

    let 关口 = 资源网关口::从声明根(&[声明.clone()]).expect("声明本身合法");
    let 错 = 拒因(关口.资源调用(参照实现号, 1, &文本入参()));
    assert_eq!(
        错,
        资源错误::副作用未允许 {
            资源号: 参照实现号,
            操作号: 1,
            副作用: 副作用::读文件,
        }
    );
    assert_eq!(错.码(), 码_副作用未允许);

    // 把那个开关显式打开 ⇒ 同一条调用就通。
    声明.允许.读文件 = true;
    let mut 关口 = 资源网关口::从声明根(&[声明]).expect("声明本身合法");
    关口.绑定入口(参照实现号, Box::new(夹具黑盒::新(参照实现号, 字节集)));
    assert!(matches!(
        关口.资源调用(参照实现号, 1, &文本入参()),
        关口结果::成功(_)
    ));
}

