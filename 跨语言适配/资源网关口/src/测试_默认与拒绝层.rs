// ══ 一 默认状态：空清单 ⇒ 一切都拒（最重要的一条） ═══════════════════════

/// **清单为空 ⇒ 任何资源调用都被拒。** 这是默认状态，也是「不许运行参照实现」的落点。
#[test]
fn 默认清单为空_任何资源调用都被拒() {
    let 关口 = 资源网关口::空();
    assert!(关口.已声明资源().is_empty(), "默认清单必须是空的");
    assert_eq!(关口.已声明资源数(), 0);

    // 拿 §三 示例里的那个号、那个操作号去调 —— 必须被拒。
    for (资源号, 操作号) in [(参照实现号, 1), (参照实现号, 2), (1, 1), (9000, 7)] {
        let 错 = 拒因(关口.资源调用(资源号, 操作号, &文本入参()));
        assert_eq!(错.码(), 码_资源未声明, "默认状态必须报「资源未声明」");
        assert_eq!(错.资源号(), 资源号);
    }
}

/// 空的声明根**是合法的默认状态**，不是错误（与 `适配器实现` 的空根即拒不同）。
