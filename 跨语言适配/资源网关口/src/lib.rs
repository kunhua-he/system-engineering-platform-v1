//! 资源网关口 —— **全平台唯一的资源出入口**。
//!
//! 裁定件：`项目文档/设计文档/资源网关口.md`（资源声明 · 唯一出入口 · **默认拒绝** ·
//! 四层拒绝 · 隔离 · 留痕）。拓扑位置：`全局连接器与网关.md` 第二节那张图里「资源」那一侧
//! 的腿，对应**判据 4「全平台只有一个资源出入口」**（全仓恰好 1 处）。
//!
//! ```text
//! 不透明外部东西（黑盒）
//!      ↓  声明（说清它是什么、能做什么、怎么调、要什么、什么时候算超时）
//!   资源网关口  ← 本 crate：唯一出入口，按声明放行或拒绝
//!      ↓  定长数据槽（类型标签在槽内）
//!   调用方
//! ```
//!
//! # 一句话
//!
//! **看不见的东西不需要看懂，只需要能声明它、隔离它、拒绝它。**
//!
//! # 默认状态：空清单 ⇒ 一切都拒
//!
//! [`资源网关口::空`]（也就是 [`Default`]）就是**默认拒绝**：没有声明 ⇒ 没有资源 ⇒
//! 任何调用都拿 `22 资源未声明`。**拒绝不靠自觉，靠清单里没有。**
//!
//! 所以「不许运行参照实现」这条既有硬约束，落点就是这一条：默认清单**不含**参照实现
//! ⇒ 关口拒。要放行得**显式加一条资源声明**——那是一个有日期、有署名、可回滚的动作，
//! 不是一句注释。参照实现那条声明的示例形状只在文档里（§三），**不落进默认清单**。
//!
//! # 公开面
//!
//! | 件 | 是什么 |
//! |---|---|
//! | [`资源声明`] | 一条资源声明的形状 + 校验（§三 三条硬规则） |
//! | [`资源网关口`] | 唯一出入口：读声明根 · 派发 · 七层判定 · 超时 · 配额 · 留痕 |
//! | [`资源错误`] | 结构化错误 + **专属码** + 三项业务判断（可重试 · 可自愈 · 需人工） |
//! | [`部署绑定`] · [`黑盒体`] | 入口从部署来（§三 规则 3：入口不写进声明仓） |
//! | [`资源网关口::留痕读数`] | 谁 · 调什么 · 入参指纹 · 结果 · 耗时（**不进关键路径**） |
//!
//! # 缺口（如实登记，不假装覆盖了）
//!
//! 1. **JSON → 声明的生成链还没有。** §三 的形状是 JSON，而本 crate **不解析 JSON**
//!    （零第三方依赖，且不另造第二套解析器）。运行期收的是进程内的 [`资源声明`]
//!    （与 `适配器实现` 收进程内 `平台信息` 同一条口径）；「读 JSON 声明文件」那一步
//!    归声明侧的生成物/装载动作 —— 而 `对外接口面/声明编写面/` 现在是**空目录**
//!    ⇒ 这一步**没有落点**。所以「从一个声明的根读」目前读的是**调用方给的进程内声明根**。
//! 2. **四个专属码暂未登记**进 `契约声明/错误码表/`（登记只有声明编写面一条路，
//!    那个面还没建）。登记内容见 [`本关口错误码`]（登记处是 `契约声明/错误码表/0022`–`0028`）。
//! 3. **段位是借的**：`号段图.json` 的错误码段位图里没有「资源网关口」这一段，
//!    七个码落段位 0（底座自有：内核 ＋ 跨语言适配），已登记为 `0022`–`0028`（依据见 [`拒绝码`] 文件头）。
//! 4. **「隔离」那三个字段在进程内落不了地**：一个地址空间里没有边界，本节点只能判
//!    声明自洽（`载体::进程内` + `崩溃影响面::仅本资源` 即判不自洽），给不出隔离本身。
//! 5. **真跨进程的载体没有落点**：`黑盒体` 是载体无关的形状，但本节点只给了
//!    进程内这一条路（进程池 / WASM 沙箱未裁，见 `现代架构落点.md` 第十节）。
//! 6. **留痕的记录形状装不下两个号**：`留痕` 只有「能力号」一个号字段，而资源调用有
//!    「资源号 + 操作号」两个 ⇒ 关口把**资源号**放进 `能力号` 格、**操作号**放进
//!    `追踪号` 格（[`资源网关口::留痕读数`] 的文档写明映射）。修法在既有件（给 `留痕`
//!    加旁路字段），不在本 crate。
//! 7. **`资源号段` 的归属取不到** —— **2026-09-27 更正：这条已不成立**。
//!    实测 `契约声明/src/声明数据.rs::资源号段` 有生成物，且「扩展自带 / 平台级」两段**都在里面**
//!    （`扩展自带资源起/止` · `平台级资源起/止`）⇒ 关口拿得到归属。
//!    本 crate 的 `声明形状::资源号段` 也已改成**从生成物拼端点**，不再手写数字。

