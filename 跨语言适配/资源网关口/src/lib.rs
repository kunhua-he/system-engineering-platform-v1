    /// 留痕关掉时调用照样成功；开着时耗时不变慢（**读数印在下面**）。
    #[test]
    fn 留痕不进关键路径_关掉照样成功_开着不变慢() {
        // 次数必须小于契约的 `配额上限`，否则量到的是「配额用尽」而不是留痕开销。
        const 次数: u32 = 8_000;
        const 容量: u32 = 4096;
        let 入参 = 文本入参();

        // 关：关口默认没有留痕缓冲。
        let (关, _) = 参照实现关口();
        let 起 = Instant::now();
        for _ in 0..次数 {
            assert!(
                matches!(关.资源调用(参照实现号, 1, &入参), 关口结果::成功(_)),
                "留痕缺席时调用照样成功"
            );
        }
        let 关耗时 = 起.elapsed();
        assert!(关.留痕读数(10).is_empty(), "没启用留痕 ⇒ 一条也没有");
        assert_eq!(关.留痕已丢弃(), 0);

        // 开：同样的声明、同样的黑盒，多一个留痕缓冲。
        let (mut 开, _) = 参照实现关口();
        开.启用留痕(容量, 丢弃策略::丢最旧);
        let 起 = Instant::now();
        for _ in 0..次数 {
            assert!(matches!(
                开.资源调用(参照实现号, 1, &入参),
                关口结果::成功(_)
            ));
        }
        let 开耗时 = 起.elapsed();

        println!(
            "留痕开销实测（各 {次数} 次）：关 {关耗时:?} / 开 {开耗时:?}；每次差 {:?}",
            开耗时.saturating_sub(关耗时) / 次数
        );
        assert!(
            开耗时 <= 关耗时 * 4 + Duration::from_millis(50),
            "留痕进了关键路径：关 {关耗时:?} / 开 {开耗时:?}"
        );

        // 而且它真的记下来了（不是「开了但没记」）。
        let 条 = 开.留痕读数(次数);
        assert_eq!(条.len(), 容量 as usize, "取最近 次数 条 = 缓冲容量");
        assert_eq!(开.留痕已丢弃(), u64::from(次数 - 容量));
        let 首条 = 条[0];
        assert_eq!(首条.能力号, 参照实现号, "留痕的「能力号」这一格装的是资源号");
        assert_eq!(首条.追踪号, 1, "留痕的「追踪号」这一格装的是操作号");
        assert_eq!(首条.结果码, 0, "成功记 0");
        assert_eq!(首条.实例, 开.实例号());
        assert!(
            条.iter().all(|条| 条.入参指纹 == 首条.入参指纹),
            "同一张槽表 ⇒ 同一个指纹"
        );
        assert_eq!(首条.入参指纹, crate::关口::槽表指纹(&入参));
    }

