/// **同一组入参 · 两路各判一次 · 档位必须一致。**
///
/// 四组：① 缺一位 ② 多一位 ③ 个数对而逐位类型反了 ④ 全符。
/// 前三组两路都必须**拒**（且都在执行之前），第四组两路都必须**过**。
#[test]
fn 两路对同一入参判定一致() {
    let 组表: [(&str, Vec<数据槽>, bool); 4] = [
        ("缺一位", vec![构造入参槽(1, 11)], false),
        ("多一位", vec![构造入参槽(1, 11), 构造入参槽(2, 22), 构造入参槽(1, 33)], false),
        ("逐位类型反了", vec![构造入参槽(2, 11), 构造入参槽(1, 22)], false),
        ("全符", vec![构造入参槽(1, 11), 构造入参槽(2, 22)], true),
    ];
    for (组名, 入参, 应放过) in 组表 {
        let 通用路前 = 命令执行次数.load(Ordering::SeqCst);
        let 资源路前 = 资源执行次数.load(Ordering::SeqCst);
        let 通用路过 = matches!(通用路判(&入参), 调用结果::成功);
        let 资源路过 = 资源路判(&入参);
        assert_eq!(通用路过, 应放过, "通用路在「{组名}」这组上判定与对照表不符");
        assert_eq!(资源路过, 应放过, "资源路在「{组名}」这组上判定与对照表不符");
        assert_eq!(通用路过, 资源路过, "两路在「{组名}」这组上判定不一致（两路保障漂了）");
        // 拒的那几组：两路都必须在**执行之前**拒 —— 执行方次数一个都不许涨。
        if !应放过 {
            assert_eq!(命令执行次数.load(Ordering::SeqCst), 通用路前, "通用路拒了却已进执行方（「{组名}」）");
            assert_eq!(资源执行次数.load(Ordering::SeqCst), 资源路前, "资源路拒了却已进执行方（「{组名}」）");
        }
    }
}

/// 反向样本：两路各报**各自的**代号（不许把两路的码硬拉齐 —— 硬拉齐才是造第二套语义）。
///
/// 通用路报 `参数个数不符` / `输入形状不符` 段位、资源路报 `25 输入形状不符` 专属码；
/// 一致的是「都拒」这个档位，不是码值。这一条把口径钉在测试里，防后人误改成「码值相等」。
#[test]
fn 对照两路代号不相同() {
    let 缺一位入参 = vec![构造入参槽(1, 11)];
    assert_eq!(
        通用路判(&缺一位入参),
        调用结果::失败(调度错误::参数个数不符 { 声明: 2, 实际: 1 })
    );
    let 错类型入参 = vec![构造入参槽(2, 11), 构造入参槽(1, 22)];
    assert_eq!(
        通用路判(&错类型入参),
        调用结果::失败(调度错误::输入形状不符 { 位次: 0, 声明类型: 1, 实际类型: 2 })
    );
    match 造资源关口().资源调用(对照资源号, 1, &缺一位入参) {
        关口结果::失败(资源错误::输入形状不符 { 槽位, .. }) => {
            assert_eq!(槽位, 1, "资源路指向第一个缺的位置")
        }
        别的 => panic!("资源路应当报 25 输入形状不符，实际 {别的:?}"),
    }
}
