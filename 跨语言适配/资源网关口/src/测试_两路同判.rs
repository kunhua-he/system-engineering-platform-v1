//! 两路同判 —— 通用路（`调用调度`）与资源路（本关口）对**同一入参**判定是否同结果。
//!
//! 依据：债务 474（架构收敛方案项 6.1 + 12-高3「通用路与资源路两路保障一致」）。
//! 原文那条「通用路只查参数个数」的前提**已不成立** —— 实测通用路也逐位对类型
//! （`运行内核/调用调度/src/调度核心.rs`：按号取命令 → 校参数个数 → 校参数类型 → 问配额）。
//! 但两路**各判各的**、无一处比对 ⇒ 这条缺口要的正是一张**对照表**：
//! 同一组入参（缺槽 / 多槽 / 逐位类型不符 / 全符），两路的判定档位必须一致（都拒 / 都过）。
//!
//! 「一致」的口径（不把两路的代号硬拉齐）：
//! · **拒的档位** —— 两路都必须**在执行之前**拒（执行方一次都不许被调到）；
//! · **过的档位** —— 两路都必须放行并交回值。
//! 代号不同是本该如此（资源路专属码 `25` ↔ 通用路段位 `参数个数不符/输入形状不符`），
//! 拿代号硬拉齐反而是造第二套语义。
//!
//! 夹具只在本模块（一键验证判据 C：夹具不许被生产代码引用）。

