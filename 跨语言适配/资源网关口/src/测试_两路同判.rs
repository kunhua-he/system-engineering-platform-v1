/// 资源路的黑盒：与通用路的执行函数同一件事（写回一个值），且各记各的次数。
struct 对照黑盒;

impl 黑盒体 for 对照黑盒 {
    fn 调用操作(&self, _操作号: u32, 输入槽表: &[数据槽], 输出槽表: &mut Vec<数据槽>) -> 黑盒结果 {
        资源执行次数.fetch_add(1, Ordering::SeqCst);
        let 待处理值 = 输入槽表.first().map_or(0, |数据槽| 数据槽.槽值);
        输出槽表.clear();
        输出槽表.push(数据槽::内联槽(v1_contract::类型标签::构造(1), 待处理值 + 7, 0));
        黑盒结果::成功
    }
}

fn 造资源关口() -> 资源网关口 {
    let 声明 = 资源声明 {
        资源号: 对照资源号,
        标识: "对照资源".to_owned(),
        扩展种类: "不透明外部程序".to_owned(),
        入口: 入口声明::仅载体(载体类型::本机进程),
        操作表: vec![操作声明 {
            操作号: 1,
            名字: "对照操作".to_owned(),
            输入类型: 对照输入类型.to_vec(),
            输出类型: vec![1],
            超时毫秒: 5000,
            需要副作用: Some(副作用集::空实例),
        }],
        允许: 允许表::全否,
        资源隔离: 隔离声明 {
            载体类型: 载体类型::本机进程,
            可重建: true,
            崩溃影响面: 崩溃影响面::整个进程,
        },
        留痕: true,
    };
    let mut 关口 = 资源网关口::从声明根建关口(&[声明]).expect("对照声明必须过校验");
    关口.绑定入口(对照资源号, Box::new(对照黑盒));
    关口
}

/// 一槽：标签与值。
fn 构造入参槽(标签: u32, 值: u64) -> 数据槽 {
    数据槽::内联槽(v1_contract::类型标签::构造(标签), 值, 0)
}

/// 通用路：返回调用结果（两路的**判定档位**就从这个结果里取）。
fn 通用路判(入参: &[数据槽]) -> 调用结果 {
    let 账本 = 配额账本::构造(配额上限, 配额窗口毫秒);
    let 注册表 = 统一注册表::建表(&对照声明.0).expect("对照声明必须建得出表");
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 返回槽 是本栈上的可写槽；入参按契约填好。
    unsafe {
        v1_dispatch::调用命令(
            &注册表,
            &账本,
            v1_contract::能力号::构造(对照命令号),
            入参,
            &mut 返回槽,
        )
    }
}

/// 资源路：返回「是否放过」。
fn 资源路判(入参: &[数据槽]) -> bool {
    matches!(造资源关口().资源调用(对照资源号, 1, 入参), 关口结果::成功(_))
}

