/// 命令号（落在夹具能力号段 `1000–1999` 内）。
const 对照命令号: u32 = 1100;
/// 资源号（落在资源号段 `1–8999` 内）。
const 对照资源号: u32 = 3100;
/// 两路**共用**的输入类型表：两位，标签 `1` 与 `2`。
const 对照输入类型: [u32; 2] = [1, 2];

/// 执行方被调次数（证明「拒在执行之前」）。
static 资源执行次数: AtomicU32 = AtomicU32::new(0);
static 命令执行次数: AtomicU32 = AtomicU32::new(0);

unsafe extern "C-unwind" fn 对照命令函数(返回槽: *mut 数据槽, _参数个数: u32, _参数表: *const 数据槽) {
    命令执行次数.fetch_add(1, Ordering::SeqCst);
    // SAFETY: 调度核心保证 `返回槽` 可写。
    unsafe { 返回槽.write(数据槽::内联槽(v1_contract::类型标签::构造(1), 7, 0)) };
}

