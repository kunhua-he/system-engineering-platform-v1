//! 跨进程体的测试 —— **同读数**与**结构化拒绝**两条硬边界的反向样本。
//!
//! 依据：`临时件/W01_裁决_架构升级.md`（IPC 载体 = Unix socket；同一份调用语义，
//! **不另造第二套**）。本件只证两件事：
//!
//! 1. **同一条契约、同一入参 ⇒ 进程内孪生体与跨进程体返回码逐字一致**（跨进程那条路
//!    不引入任何额外的失败面 —— 这是「形状不变」这句的可验证含义）。
//! 2. **越界与截断一律结构化拒**：帧头声明的长度越界 ⇒ **先校界限、不分配**；
//!    半帧 ⇒ 结构化拒；有界队列满 ⇒ 〔线协议错误::队列已满〕。**不 panic、不静默截断。**
//!
//! 对端一律用 `v1_adapter::线协议` 的编解码函数应答 —— 夹具不手拼载荷，
//! 因为手拼载荷本身就是「第二套协议」（本腿正是要证明不造第二套）。
//! 只有「越界帧头」与「半帧」两个反向样本必须亲手写头 —— 它们验的正是收侧的界限校验。
//!
//! 夹具只住在本模块（一键验证判据 C：夹具不许被生产代码引用）。

use std::os::unix::net::UnixStream;
use std::thread;
use std::time::{Duration, Instant};

use v1_adapter::进程帧::{发送帧, 接收帧, 调用帧预算, 消息帧, 消息类别};
use v1_adapter::线协议::{单次调用槽数上限, 编码调用结果, 编码调用请求, 解码调用请求, 线协议错误, 线协议会话};
use v1_adapter::协议结果;
use v1_contract::{类型标签, 数据槽};

use crate::入口绑定::{黑盒体, 黑盒结果};
use crate::拒绝码::资源错误;
use crate::跨进程体::跨进程体;

/// 样例资源号（报失败的码要用它）。
const 样例资源号: u32 = 3001;
/// 会被对端回「成功」的操作号。
const 样例操作号: u32 = 1101;
/// 会被对端回「参数不合法」的操作号（**反向样本**）。
const 失败操作号: u32 = 1102;
/// 帧头字节数（与帧层盘面一致：魔数 4 + 版本 2 + 类别 2 + 标识 8 + 长度 4 + 预算 4）。
const 测试帧头字节数: usize = 24;
/// 一条声明得比上限还大的载荷长度（先校界限的**反向样本**）。
const 越界载荷长度: u32 = 8 * 1024 * 1024;

fn 建预算() -> 调用帧预算 {
    调用帧预算::创建(Instant::now() + Duration::from_millis(500)).unwrap()
}

fn 值槽(标注值: u64) -> 数据槽 {
    数据槽::内联槽(类型标签::构造(2), 标注值, 0)
}

fn 样例入参(轮次: u64) -> Vec<数据槽> {
    vec![数据槽::内联槽(类型标签::构造(1), 轮次 * 10, 0)]
}

/// 进程内孪生体（成功路）：与对端线程**同一算式**（返回值 = 首个入参槽值 + 操作号）。
struct 进程内样例体;

impl 黑盒体 for 进程内样例体 {
    fn 调用操作(&self, 操作号: u32, 输入槽表: &[数据槽], 输出槽表: &mut Vec<数据槽>) -> 黑盒结果 {
        输出槽表.push(值槽(输入槽表[0].槽值 + u64::from(操作号)));
        黑盒结果::成功
    }
}

/// 进程内孪生体（失败路）：同一份契约里「协议码非成功 ⇒ 返回槽置空」的进程内实现。
/// **它不是跨进程体的替代物，是它的对照物** —— 两边读数逐字一致才算「形状不变」。
struct 进程内失败体 {
    资源号: u32,
}

impl 黑盒体 for 进程内失败体 {
    fn 调用操作(&self, 操作号: u32, 输入槽表: &[数据槽], 输出槽表: &mut Vec<数据槽>) -> 黑盒结果 {
        // 与对端同判据：非成功一律把返回槽置空（不编一个值充数）。
        assert!(输入槽表.len() <= 1);
        输出槽表.push(数据槽::空槽());
        黑盒结果::失败(资源错误::资源执行失败 { 资源号: self.资源号, 操作号 })
    }
}

/// 同一条契约、同一入参 ⇒ 两条路的返回码与输出槽表都逐字一致。
#[test]
fn 进程内与跨进程逐字一致() {
    let (客户端通道, 服务通道) = UnixStream::pair().unwrap();
    // 对端：按收到的号值决定协议码 —— 与进程内那两份夹具同一张判据表。
    let 对端线程 = thread::spawn(move || {
        let mut 服务侧 = 服务通道;
        for 轮次 in 1..=3u64 {
            let 请求标识 = std::num::NonZeroU64::new(轮次).unwrap();
            let 请求帧 = 接收帧(&mut 服务侧, 请求标识, &mut 建预算()).unwrap();
            let (号值, 入参槽表) = 解码调用请求(&请求帧.载荷).unwrap();
            let (协议码值, 返回槽) = if 号值 == 失败操作号 {
                (协议结果::参数不合法, 数据槽::空槽())
            } else {
                (协议结果::成功, 值槽(入参槽表[0].槽值 + u64::from(号值)))
            };
            let 结果帧 = 消息帧 {
                消息类型: 消息类别::调用结果,
                请求标识,
                载荷: 编码调用结果(协议码值, &返回槽).unwrap(),
            };
            发送帧(&mut 服务侧, &结果帧, &mut 建预算()).unwrap();
        }
    });
    let 进程内体 = 进程内样例体;
    let 跨进程体实例 = 跨进程体::持通道(样例资源号, 客户端通道);
    for 轮次 in 1..=2u64 {
        let 入参 = 样例入参(轮次);
        let mut 进程内出 = Vec::new();
        let mut 跨进程出 = Vec::new();
        let 进程内果 = 进程内体.调用操作(样例操作号, &入参, &mut 进程内出);
        let 跨进程果 = 跨进程体实例.调用操作(样例操作号, &入参, &mut 跨进程出);
        assert_eq!(进程内果, 跨进程果);
        assert_eq!(进程内果, 黑盒结果::成功);
        assert_eq!(进程内出, 跨进程出);
        assert_eq!(跨进程出.len(), 1);
    }
    // 反向样本：对端回「参数不合法」⇒ 跨进程体的码与进程内孪生体**逐字一致**。
    let 进程内失败体 = 进程内失败体 { 资源号: 样例资源号 };
    let mut 进程内失败出 = Vec::new();
    let mut 跨进程失败出 = Vec::new();
    let 入参 = 样例入参(1);
    let 进程内失败果 = 进程内失败体.调用操作(失败操作号, &入参, &mut 进程内失败出);
    let 跨进程失败果 = 跨进程体实例.调用操作(失败操作号, &入参, &mut 跨进程失败出);
    assert_eq!(进程内失败果, 跨进程失败果);
    let 期望值 = 资源错误::资源执行失败 { 资源号: 样例资源号, 操作号: 失败操作号 };
    assert_eq!(进程内失败果, 黑盒结果::失败(期望值));
    let 失败码 = match 进程内失败果 {
        黑盒结果::失败(错误) => 错误.取错误码(),
        黑盒结果::成功 => panic!("对端回了非成功协议码，这里不该是成功"),
    };
    assert_eq!(失败码, 期望值.取错误码());
    assert_eq!(进程内失败出, 跨进程失败出);
    对端线程.join().unwrap();
}

/// 反向样本：通道断开后调用 ⇒ **结构化失败**（不是 panic、不是挂死）。
#[test]
fn 通道断开即结构化失败() {
    let (客户端通道, 服务通道) = UnixStream::pair().unwrap();
    drop(服务通道);
    let 跨进程体实例 = 跨进程体::持通道(样例资源号, 客户端通道);
    let mut 输出槽表 = Vec::new();
    let 结果码 = 跨进程体实例.调用操作(样例操作号, &[], &mut 输出槽表);
    assert_eq!(结果码, 黑盒结果::失败(资源错误::资源执行失败 { 资源号: 样例资源号, 操作号: 样例操作号 }));
    assert!(输出槽表.is_empty());
}

/// 请求标识单调递增且非零（回绕落 `MIN`，**不 panic**）。
#[test]
fn 请求标识单调递增且非零() {
    let (客户端通道, 服务通道) = UnixStream::pair().unwrap();
    drop(服务通道);
    let 跨进程体实例 = 跨进程体::持通道(样例资源号, 客户端通道);
    let 先前标识 = 跨进程体实例.取请求标识();
    let 后续标识 = 跨进程体实例.取请求标识();
    assert_ne!(先前标识.get(), 0);
    assert!(后续标识.get() > 先前标识.get());
}

/// 帧头声明的长度越界 ⇒ **先校界限、不分配**：立刻结构化拒，不等到预算耗尽。
#[test]
fn 越界载荷长度先校界限即拒() {
    let (客户端通道, 服务通道) = UnixStream::pair().unwrap();
    let 对端线程 = thread::spawn(move || {
        let mut 服务侧 = 服务通道;
        let mut 帧头 = [0u8; 测试帧头字节数];
        帧头[..4].copy_from_slice(b"V1IP");
        帧头[4..6].copy_from_slice(&1u16.to_le_bytes());
        帧头[6..8].copy_from_slice(&(消息类别::调用结果 as u16).to_le_bytes());
        帧头[8..16].copy_from_slice(&1u64.to_le_bytes());
        帧头[16..20].copy_from_slice(&越界载荷长度.to_le_bytes());
        帧头[20..24].copy_from_slice(&500u32.to_le_bytes());
        use std::io::Write;
        服务侧.write_all(&帧头).unwrap();
        服务侧.flush().unwrap();
        // 载荷**永不发出**：若收侧不是先校界限，就只能等到预算耗尽（500 ms）才返回。
        thread::sleep(Duration::from_millis(1500));
    });
    let mut 会话 = 线协议会话::新建(客户端通道);
    let 请求标识 = std::num::NonZeroU64::new(1).unwrap();
    let 起点 = Instant::now();
    let 结果码 = 会话.排队投递(请求标识);
    let 耗时 = 起点.elapsed();
    assert!(结果码.is_err());
    assert!(耗时 < Duration::from_millis(400), "越界声明应当立即拒，实测 {:?}", 耗时);
    对端线程.join().unwrap();
}

/// 半帧（帧头写一半就断）⇒ **结构化拒**，不 panic、不静默截断。
#[test]
fn 半帧即结构化拒() {
    let (客户端通道, 服务通道) = UnixStream::pair().unwrap();
    let 对端线程 = thread::spawn(move || {
        let mut 服务侧 = 服务通道;
        use std::io::Write;
        服务侧.write_all(&[0x56, 0x31, 0x49, 0x50, 1, 0, 2, 0, 1, 0, 0, 0]).unwrap();
        服务侧.flush().unwrap();
        drop(服务侧);
    });
    let mut 会话 = 线协议会话::新建(客户端通道);
    let 请求标识 = std::num::NonZeroU64::new(1).unwrap();
    assert!(会话.排队投递(请求标识).is_err());
    对端线程.join().unwrap();
}

/// 有界队列满 ⇒ **结构化拒**（不静默丢、不无限等）。
#[test]
fn 业务队列满即结构化拒() {
    let (客户端通道, 服务通道) = UnixStream::pair().unwrap();
    let 对端线程 = thread::spawn(move || {
        let mut 服务侧 = 服务通道;
        let 返回槽 = 数据槽::空槽();
        for 轮次 in 0..9 {
            let 消息体 = 消息帧 {
                消息类型: 消息类别::调用结果,
                请求标识: std::num::NonZeroU64::new(1).unwrap(),
                载荷: 编码调用结果(协议结果::成功, &返回槽).unwrap(),
            };
            发送帧(&mut 服务侧, &消息体, &mut 建预算()).unwrap();
            if 轮次 == 8 {
                thread::sleep(Duration::from_millis(300));
            }
        }
    });
    let mut 会话 = 线协议会话::新建(客户端通道);
    let 请求标识 = std::num::NonZeroU64::new(1).unwrap();
    let mut 已入队份数 = 0;
    let mut 最后一次错误 = None;
    for 轮次 in 0..9 {
        let _ = 轮次;
        match 会话.排队投递(请求标识) {
            Ok(()) => 已入队份数 += 1,
            Err(错误) => {
                最后一次错误 = Some(错误);
                break;
            }
        }
    }
    assert_eq!(已入队份数, 8);
    assert_eq!(最后一次错误, Some(线协议错误::队列已满));
    for 轮次 in 0..已入队份数 {
        let _ = 轮次;
        assert!(会话.取一件().is_some());
    }
    assert!(会话.取一件().is_none());
    对端线程.join().unwrap();
}

