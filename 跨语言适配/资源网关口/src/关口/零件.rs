/// 读侧一行：一条操作声明 → 摘要。
pub(super) fn 摘要一行(操作: &操作声明) -> 操作摘要 {
    操作摘要 {
        操作号: 操作.操作号,
        名: 操作.名.clone(),
        输入类型: 操作.输入类型.clone(),
        输出类型: 操作.输出类型.clone(),
        超时毫秒: 操作.超时毫秒,
        需要副作用: 操作.需要的副作用(),
    }
}

/// **第 4 层**：校输入形状。成功时把那张槽表**交出来**（省得调用方再按声明重取一次）。
///
/// 契约：声明的 `输入类型` 是**表**（§三 规则 4）⇒ 与输入槽表**逐位对齐**：
/// 个数与行序都是契约，不许尽力而为地补齐或截断。**个数不符与逐位不符报同一个码**
/// （[`资源错误::输入形状不符`]）—— 两者都是「形状不合契约」的一种；
/// `槽位` / `期望类型` / `实际类型` 三项把「缺一个 / 多一个 / 哪一位不对」都说得清：
/// 缺槽时那个位置期望有类型、实际是空槽（标签 `0`）；多槽时那个位置期望没有槽（标签 `0`）。
pub(super) fn 校输入形状<'a>(
    资源号: u32,
    操作号: u32,
    期望类型表: &[u32],
    输入槽表: &'a [数据槽],
) -> Result<&'a [数据槽], 资源错误> {
    // 个数不符：少槽 —— 指向**第一个缺的位置**，期望那里有槽、实际是空（标签 0）。
    if 输入槽表.len() < 期望类型表.len() {
        let 位 = 输入槽表.len();
        return Err(资源错误::输入形状不符 {
            资源号,
            操作号,
            槽位: 位 as u32,
            期望类型: 期望类型表[位],
            实际类型: 数据槽::空槽().类型标签.取(),
        });
    }
    // 个数不符：多槽 —— 指向**第一个多出来的位置**，期望那里没有槽（标签 0）。
    if 输入槽表.len() > 期望类型表.len() {
        let 位 = 期望类型表.len();
        return Err(资源错误::输入形状不符 {
            资源号,
            操作号,
            槽位: 位 as u32,
            期望类型: 数据槽::空槽().类型标签.取(),
            实际类型: 输入槽表[位].类型标签.取(),
        });
    }
    // 逐位对齐：类型标签按行序比。
    for (位, (槽, 期望)) in 输入槽表.iter().zip(期望类型表).enumerate() {
        if 槽.类型标签 != *期望 {
            return Err(资源错误::输入形状不符 {
                资源号,
                操作号,
                槽位: 位 as u32,
                期望类型: *期望,
                实际类型: 槽.类型标签.取(),
            });
        }
    }
    Ok(输入槽表)
}

/// **输出形状**：黑盒写回的输出槽表与声明的 `输出类型` 表**逐位对齐**。
///
/// 与 [`校输入形状`] 同一条口径（个数与逐位都判），但报**输出**专属码
/// （[`资源错误::输出形状不符`]）—— 那个码登记的形状**没有 `槽位` 字段**
/// （`拒绝码.rs::资源错误::输出形状不符`），故这里只给 `期望类型` / `实际类型`：
/// 个数不符时，期望 / 实际各指向「第一个多出来 / 缺的那个位置」的类型（空槽用标签 `0`）。
pub(super) fn 校输出形状(
    资源号: u32,
    操作号: u32,
    期望类型表: &[u32],
    输出槽表: &[数据槽],
) -> Result<(), 资源错误> {
    if 输出槽表.len() != 期望类型表.len() {
        let 空 = 数据槽::空槽().类型标签.取();
        return Err(资源错误::输出形状不符 {
            资源号,
            操作号,
            期望类型: 期望类型表.get(输出槽表.len()).copied().unwrap_or(空),
            实际类型: 输出槽表.get(期望类型表.len()).map_or(空, |槽| 槽.类型标签.取()),
        });
    }
    for (槽, 期望) in 输出槽表.iter().zip(期望类型表) {
        if 槽.类型标签 != *期望 {
            return Err(资源错误::输出形状不符 {
                资源号,
                操作号,
                期望类型: *期望,
                实际类型: 槽.类型标签.取(),
            });
        }
    }
    Ok(())
}

/// 入参指纹 —— 留痕要能说清「**调什么**」而不必存下整张槽表。
///
/// FNV-1a 逐字节滚过每个槽的定长字段（类型标签 · 标志 · 长度 · 值）。
/// 常数时间 · 不分配 · 同一张槽表必得同一个数（测试 `留痕_同一张槽表指纹相同` 钉住）。
pub(crate) fn 槽表指纹(槽表: &[数据槽]) -> u64 {
    const 基: u64 = 0xcbf2_9ce4_8422_2325;
    const 乘: u64 = 0x0000_0100_0000_01b3;
    let mut 指纹 = 基;
    for 槽 in 槽表 {
        let 字节 = 槽
            .类型标签
            .取()
            .to_le_bytes()
            .into_iter()
            .chain(槽.标志.to_le_bytes())
            .chain(槽.保留.to_le_bytes())
            .chain(槽.长度.to_le_bytes())
            .chain(槽.值.to_le_bytes());
        for 一字节 in 字节 {
            指纹 ^= u64::from(一字节);
            指纹 = 指纹.wrapping_mul(乘);
        }
    }
    指纹
}
