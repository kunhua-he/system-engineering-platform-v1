/// 一次调用的结果。**失败是结构化错误，不是异常**（宪法「失败可编程处理」）。
///
/// 成功带的是**输出槽表**（§四 的 `-> 输出槽表`，**表**）：一条操作可以返回 0 个、1 个
/// 或多个槽。表长为 0 即「这条操作不返回值」—— 与 `输出类型` 是空表一一对应，
/// 不再用「单值 `0`」表达「无输出」（那会与「填了标签 `0`」不可区分）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 关口结果 {
    成功(Vec<数据槽>),
    失败(资源错误),
}

impl 关口结果 {
    /// 失败时的 4 位码；成功给 `None`。
    pub fn 错误码(&self) -> Option<u32> {
        match self {
           关口结果::成功(_) => None,
            关口结果::失败(失败值) => Some(失败值.取错误码()),
        }
    }

    /// 失败时的结构化错误；成功给 `None`。
    pub fn 错误(&self) -> Option<资源错误> {
        match self {
            关口结果::成功(_) => None,
            关口结果::失败(失败值) => Some(*失败值),
        }
    }
}

/// 读侧一行：一条资源现在是什么样（§二 的 `docker inspect` 那一格）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 资源摘要 {
    pub 资源号: u32,
    pub 标识: String,
    pub 扩展种类: String,
    /// **健康否**的落点：声明里有它、部署没绑入口 ⇒ 调了会拿「入口未绑定」。
    pub 已绑定入口: bool,
    pub 操作表: Vec<操作摘要>,
}

/// 读侧一行：一条操作。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 操作摘要 {
    pub 操作号: u32,
    pub 名字: String,
    /// 输入类型标签**表**（逐位对齐调用时的输入槽表；空表 = 不要入参）。
    pub 输入类型: Vec<u32>,
    /// 输出类型标签**表**（逐位对齐返回的输出槽表；空表 = 不返回值）。
    pub 输出类型: Vec<u32>,
    pub 超时毫秒: u64,
    /// **已按校验后的形态给**：漏写的那一支在这里读不到（漏写的声明建不进关口）。
    pub 需要副作用: 副作用集,
}
