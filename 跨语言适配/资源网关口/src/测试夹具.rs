pub(crate) const 字节集: u32 = 声明数据::类型标签_0005;
pub(crate) const 整数: u32 = 声明数据::类型标签_0001;

/// 参照实现的资源号 —— 取自 §三 的形状示例。
pub(crate) const 参照实现号: u32 = 9001;

/// §三 的形状示例：参照实现。**只在夹具里，不进默认清单**（§六 的默认状态）。
///
/// 与 §三 的 JSON 逐字对应，只多一个**旁路字段** `需要副作用`（没有它 §五 第 3 层判不了）。
pub(crate) fn 参照实现声明() -> 资源声明 {
    资源声明 {
        资源号: 参照实现号,
        标识: "参照实现".to_owned(),
        种类: "不透明外部程序".to_owned(),
        入口: 入口声明::仅载体(载体::本机进程),
        操作: vec![
            操作声明 {
                操作号: 1,
                名: "文本转容器".to_owned(),
                输入类型: 文本,
                输出类型: 字节集,
                超时毫秒: 5000,
                需要副作用: Some(副作用集::空),
            },
            操作声明 {
                操作号: 2,
                名: "容器转文本".to_owned(),
                输入类型: 字节集,
                输出类型: 文本,
                超时毫秒: 5000,
                需要副作用: Some(副作用集::空),
            },
        ],
        允许: 允许表::全否,
        隔离: 隔离声明 {
            载体: 载体::本机进程,
            可重建: true,
            崩溃影响面: 崩溃影响面::仅本资源,
        },
        留痕: true,
    }
}

/// 一个可控的黑盒：按需睡觉 / 写错类型 / 报失败。`跑过` 记执行次数（证明它真被调了）。
pub(crate) struct 夹具黑盒 {
    pub(crate) 资源号: u32,
    pub(crate) 输出类型: u32,
    pub(crate) 睡毫秒: u64,
    pub(crate) 写错类型: bool,
    pub(crate) 报失败: bool,
    pub(crate) 跑过: Arc<AtomicU32>,
    pub(crate) 收到的类型标签: Arc<AtomicU32>,
}

impl 夹具黑盒 {
    pub(crate) fn 新(资源号: u32, 输出类型: u32) -> Self {
        Self {
            资源号,
            输出类型,
            睡毫秒: 0,
            写错类型: false,
            报失败: false,
            跑过: Arc::new(AtomicU32::new(0)),
            收到的类型标签: Arc::new(AtomicU32::new(0)),
        }
    }
}

impl 黑盒体 for 夹具黑盒 {
    fn 调用(&self, 操作号: u32, 输入槽: 数据槽, 输出槽: &mut 数据槽) -> 黑盒结果 {
        self.跑过.fetch_add(1, Ordering::Relaxed);
        self.收到的类型标签.store(输入槽.类型标签, Ordering::Relaxed);
        if self.睡毫秒 > 0 {
            std::thread::sleep(Duration::from_millis(self.睡毫秒));
        }
        if self.报失败 {
            return 黑盒结果::失败(资源错误::资源执行失败 {
                资源号: self.资源号,
                操作号,
            });
        }
        let 标签 = if self.写错类型 { 整数 } else { self.输出类型 };
        *输出槽 = 数据槽::内联(标签, 输入槽.值, 输入槽.长度);
        黑盒结果::成功
    }
}

/// 装好一个「有参照实现」的关口 + 那一次的调用计数。
pub(crate) fn 参照实现关口() -> (资源网关口, Arc<AtomicU32>) {
    let mut 关口 = 资源网关口::从声明根(&[参照实现声明()]).expect("§三 的示例声明必须过校验");
    let 盒 = 夹具黑盒::新(参照实现号, 字节集);
    let 计数 = Arc::clone(&盒.跑过);
    关口.绑定入口(参照实现号, Box::new(盒));
    (关口, 计数)
}

/// 一份「文本转容器」的入参：一个文本槽。
pub(crate) fn 文本入参() -> [数据槽; 1] {
    [数据槽::内联(文本, 0x1234_5678, 4)]
}

/// 断言这次调用被拒，并取出结构化错误。
pub(crate) fn 拒因(结果: 关口结果) -> 资源错误 {
    match 结果 {
        关口结果::失败(错) => 错,
        关口结果::成功(槽) => panic!("这次调用本该被拒，却成功了（返回槽 {槽:?}）"),
    }
}
