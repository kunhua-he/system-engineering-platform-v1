//! 跨进程体 —— [`黑盒体`] 的**跨进程**实现：同一条 trait、**同一份**线协议。
//!
//! 裁定：`临时件/W01_裁决_架构升级.md`（IPC 载体 = Unix domain socket；**同一份调用语义，
//! 不另造第二套**）。
//!
//! # 为什么这里能直接用 `v1_adapter::线协议`
//!
//! 线协议就是**同一份** `跨语言适配/边界协议/边界协议.md` 的运行期实现（帧头 · 槽盘面 ·
//! 结果码都只有那一份）。跨进程体要做的只是把 `(操作号, 输入槽表)` 摆进线协议的**一次调用**，
//! 再把回帧倒回 `输出槽表` —— **搬运**，不是编码。
//! 本件因此**一个字节都不亲手拼**：帧编解码、界限校验、槽盘面全走 `v1_adapter::线协议`；
//! 再造一套就是第二套协议。这也正是 `Cargo.toml` 里那条同层依赖（`v1-adapter`）唯一的理由。
//!
//! # 形状：`&self` 里的可变会话
//!
//! [`黑盒体::调用操作`] 取 `&self`（关口与部署绑定持有的是 `&dyn 黑盒体`），而线协议会话
//! 收发都要 `&mut self` ⇒ 会话住 `Mutex` 里，一次调用持锁到底（请求与回帧必须成对）。
//! **中毒不当宕机**：上一手哪怕 panic 过，也把会话取回来接着用（`unwrap_or_else` 取内层），
//! 失败仍走返回值。
//!
//! # 请求标识
//!
//! 每实例一个单调递增的 `u64`，经 `NonZeroU64::new(..).unwrap_or(NonZeroU64::MIN)` 变换 ——
//! 回绕到 0 时落到 `MIN`（1），**不 panic、不产生非法标识**。标识只供帧层配对，不带业务语义。
//!
//! # 失败一律走返回值
//!
//! 传输失败 / 通道断开 / 对端回帧不合规 ⇒ [`黑盒结果::失败`]
//! （码 = [`资源错误::资源执行失败`]），与 `入口绑定.rs` 写的两条实现方纪律
//! （不跨边界抛异常、不指望自身守时）同一条口径：**本件里没有任何 `panic!` 落点**。

use std::num::NonZeroU64;
use std::os::unix::net::UnixStream;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Mutex;

use v1_adapter::线协议::线协议会话;
use v1_adapter::协议结果;
use v1_contract::数据槽;

use crate::入口绑定::{黑盒体, 黑盒结果};
use crate::拒绝码::资源错误;

/// 挂在一条**已连通道**上的黑盒体：调用过线，结果过线，本件只搬运。
///
/// 资源号随实例持有（报失败要用它组码），操作号每次调用给 —— 两者都不落进程级全局。
///
/// # 输出契约（部署方注入）
///
/// `输出类型表` = 声明里那条操作的 `输出类型` 表（表，逐位对齐）。**本版线协议只带一个
/// 返回槽**，所以不注入它，本体就判不了「零输出凭空多一个槽」与「多输出被单槽截断」——
/// 那两条正是本件要补的资源语义。`None` = 未注入（旧调用方与既有测试）：保持**单槽原样
/// 搬运**，只加两条与声明无关的补正（空槽不当值 · 失败路径清空）。
pub struct 跨进程体 {
    资源号: u32,
    /// 声明里那条操作的 `输出类型` 表。`None` = 部署方未注入（见类型头）。
    输出类型表: Option<Vec<u32>>,
    会话锁: Mutex<线协议会话>,
    次序号: AtomicU64,
}

impl 跨进程体 {
    /// 从一条**已连**通道建体（连接由部署方拉起，本件不建连、不重连）。
    ///
    /// **不注入输出契约**：调用方拿不到声明时走这一口，语义 = 单槽原样搬运。
    pub fn 持通道(资源号: u32, 通道: UnixStream) -> Self {
        Self::新建(资源号, None, 通道)
    }

    /// 从一条**已连**通道建体，并注入声明的 `输出类型` 表（生产启用走这一口）。
    ///
    /// 注入了才判得出三条资源语义：零输出不许凭空多槽 · 多输出单槽协议载不动即明确拒 ·
    /// 逐位对齐声明的类型表。
    ///
    /// **资源号在这里校验**：不在资源号段内 ⇒ 拒建。这样本件错误文字里出现的资源号
    /// **有验证依据**（是部署方按声明给的、且过了号段判据），不是随手填的数。
    pub fn 持通道按契约(
        资源号: u32,
        输出类型表: Vec<u32>,
        通道: UnixStream,
    ) -> Result<Self, 资源错误> {
        if !crate::声明形状::资源号段.包含(v1_contract::号值::构造(资源号)) {
            return Err(资源错误::资源未声明 { 资源号 });
        }
        Ok(Self::新建(资源号, Some(输出类型表), 通道))
    }

    /// 本实例绑定的资源号（**已过号段判据**，见 [`跨进程体::持通道按契约`]）。
    /// 部署方拿它与声明对照，这就是「资源身份」的验证依据。
    pub fn 资源号(&self) -> u32 {
        self.资源号
    }

    /// 声明的输出位数：`None` = 未注入（按单槽原样搬运）；`Some(0)` = 零输出；`Some(n)` = n 位。
    fn 输出位数(&self) -> Option<usize> {
        self.输出类型表.as_ref().map(Vec::len)
    }

    fn 新建(资源号: u32, 输出类型表: Option<Vec<u32>>, 通道: UnixStream) -> Self {
        Self {
            资源号,
            输出类型表,
            会话锁: Mutex::new(线协议会话::新建(通道)),
            次序号: AtomicU64::new(0),
        }
    }

    /// 取下一个请求标识：单调递增，回绕到 0 时落到 `MIN`（**不 panic**）。
    pub fn 取请求标识(&self) -> NonZeroU64 {
        NonZeroU64::new(self.次序号.fetch_add(1, Ordering::Relaxed).wrapping_add(1))
            .unwrap_or(NonZeroU64::MIN)
    }

    /// 黑盒体这一层的失败只有这一个码：底座不认识它的内部。
    fn 报失败(&self, 操作号: u32) -> 黑盒结果 {
        黑盒结果::失败(资源错误::资源执行失败 { 资源号: self.资源号, 操作号 })
    }
}

impl 黑盒体 for 跨进程体 {
    fn 调用操作(&self, 操作号: u32, 输入槽表: &[数据槽], 输出槽表: &mut Vec<数据槽>) -> 黑盒结果 {
        let 请求标识 = self.取请求标识();
        let mut 会话 = self.会话锁.lock().unwrap_or_else(|错误| 错误.into_inner());
        if 会话.发起调用(请求标识, 操作号, 输入槽表).is_err() {
            return self.报失败(操作号);
        }
        match 会话.收调用结果(请求标识) {
            Ok((协议码值, 返回槽)) => {
                if 协议码值 != 协议结果::成功 {
                    // 协议只认 `{成功, 参数不合法}`：非成功一律是黑盒自身失败。
                    // **失败路径清空输出表**：半截 / 未验证的内容一个字都不许交给调用方。
                    输出槽表.clear();
                    return self.报失败(操作号);
                }
                self.收下返回槽(操作号, 返回槽, 输出槽表)
            }
            Err(_错误) => {
                // 传输失败同理：不许把上一手留在表里的东西当成本次结果交出去。
                输出槽表.clear();
                self.报失败(操作号)
            }
        }
    }
}

impl 跨进程体 {
    /// 成功路上的返回槽处置 —— 三条资源语义都在这里。
    ///
    /// 1. **零输出不许凭空多一个槽**：声明的 `输出类型` 是空表 ⇒ 本件**不 push**
    ///    （协议必须回一个槽，那是协议盘面的事；它不进调用方的表）。
    ///    这一条不是「丢弃」：空表就是「这条操作不返回值」，多写一位即 `27 输出形状不符`。
    /// 2. **多输出按契约行序完整返回**：本版线协议**只带一个返回槽**（`收调用结果` →
    ///    `(i32, 数据槽)`），声明要 n>1 位时本件**载不动** ⇒ 明确报失败，
    ///    **不许只交回第一位充数**（那是静默截断，比失败更坏）。
    ///    ★ 要真做多输出，得先由线协议扩成「槽表 + 数据区」——本件不复制一份协议。
    /// 3. **空槽不当值**：协议用一个空槽表示「无返回」，声明要 1 位时它不是那位值
    ///    （当值 push 会造出一个 `0` 号标签的假槽，上层判形状时才发现）。
    fn 收下返回槽(&self, 操作号: u32, 返回槽: 数据槽, 输出槽表: &mut Vec<数据槽>) -> 黑盒结果 {
        match self.输出位数() {
            // 未注入输出契约（旧调用方）：保持单槽原样搬运，一字不改。
            None => {
                输出槽表.push(返回槽);
                黑盒结果::成功
            }
            // 零输出：**不许凭空多一个槽**。协议回的那个槽不进调用方的表。
            Some(0) => 黑盒结果::成功,
            // 一位：与声明的类型表逐位对齐；空槽不是那位值。
            Some(1) => {
                if 返回槽.是否空() {
                    return self.报失败(操作号);
                }
                输出槽表.push(返回槽);
                黑盒结果::成功
            }
            // 多位：本版单槽协议载不动 ⇒ 明确拒（不截断、不补空槽）。
            Some(_) => self.报失败(操作号),
        }
    }
}
