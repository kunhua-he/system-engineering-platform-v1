/// 一次资源调用失败的结构化原因。
///
/// **不带异常、不带隐式通道**（`边界协议.md` 第五节）：它就是返回值的一部分。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 资源错误 {
    /// **第 1 层**：清单里没有这个号（依据：清单里没有它）。
    资源未声明 { 资源号: u32 },
    /// **第 2 层**：该资源的 `操作` 白名单里没有这个操作号。
    操作未声明 { 资源号: u32, 操作号: u32 },
    /// **第 3 层**：这条操作需要的副作用，声明里**没允许**。
    副作用未允许 {
        资源号: u32,
        操作号: u32,
        副作用: 副作用,
    },
    /// **第 4 层**：输入槽的形状与声明的 `输入类型` 不符。
    ///
    /// `槽位` 是出错的位置（0 起）；个数不符时它指向缺的那个位置 / 多出来的那个位置，
    /// `期望类型` / `实际类型` 里 `0`（空）表示「那个位置应当没有槽」或「那个位置没有槽」。
    输入形状不符 {
        资源号: u32,
        操作号: u32,
        槽位: u32,
        期望类型: u32,
        实际类型: u32,
    },
    /// **第五处**（文档未列）：声明里有这条资源，部署方没给它绑入口。
    入口未绑定 { 资源号: u32 },
    /// **第六处**（文档未列）：黑盒写回的输出槽类型与声明的 `输出类型` 不符。
    输出形状不符 {
        资源号: u32,
        操作号: u32,
        期望类型: u32,
        实际类型: u32,
    },
    /// **第七处**（文档未列）：黑盒自身报失败。底座不认识它的内部，故只有这一个码。
    资源执行失败 { 资源号: u32, 操作号: u32 },
    /// 这一项越过了声明的 `超时毫秒`（关口判并报码，**由关口执行**，不由资源保证）。
    超时 {
        资源号: u32,
        操作号: u32,
        毫秒: u64,
    },
    /// 该资源号在配额窗口内已用满 `配额上限`（关口执行）。
    配额用尽 { 资源号: u32 },
}

impl 资源错误 {
    /// 完整 4 位码。**这就是 `契约声明/错误码表/<码>.json` 的文件名**。
    pub const fn 取错误码(&self) -> u32 {
        match self {
            资源错误::资源未声明 { .. } => 码_资源未声明,
            资源错误::操作未声明 { .. } => 码_操作未声明,
            资源错误::副作用未允许 { .. } => 码_副作用未允许,
            资源错误::输入形状不符 { .. } => 码_输入形状不符,
            资源错误::入口未绑定 { .. } => 码_入口未绑定,
            资源错误::输出形状不符 { .. } => 码_输出形状不符,
            资源错误::资源执行失败 { .. } => 码_资源执行失败,
            资源错误::超时 { .. } => 声明数据::错误码_4.取号值(),
            资源错误::配额用尽 { .. } => 声明数据::错误码_5.取号值(),
        }
    }

    /// 码的名称。
    pub const fn 名称(&self) -> &'static str {
        match self {
            资源错误::资源未声明 { .. } => "资源未声明",
            资源错误::操作未声明 { .. } => "操作未声明",
            资源错误::副作用未允许 { .. } => "副作用未允许",
            资源错误::输入形状不符 { .. } => "输入形状不符",
            资源错误::入口未绑定 { .. } => "入口未绑定",
            资源错误::输出形状不符 { .. } => "输出形状不符",
            资源错误::资源执行失败 { .. } => "资源执行失败",
            资源错误::超时 { .. } => "超时",
            资源错误::配额用尽 { .. } => "配额用尽",
        }
    }

    /// **三项业务判断** —— 「失败可编程处理」的全部依据。验证面猜不出来，这是业务判断。
    pub const fn 业务判断(&self) -> 三项判断 {
        match self {
            // 加一条资源声明是一个有日期、有署名、可回滚的动作（§五），只能人来裁。
            资源错误::资源未声明 { .. } => 三项判断::仅人裁,
            // 改白名单 = 改声明，同上。
            资源错误::操作未声明 { .. } => 三项判断::仅人裁,
            // 放开一个副作用是安全裁决（默认拒绝的另一面）。
            资源错误::副作用未允许 { .. } => 三项判断::仅人裁,
            // 调用方填错了槽 —— 平台补不上，得人改调用方。
            资源错误::输入形状不符 { .. } => 三项判断::仅人裁,
            // 部署动作没做完：部署补上入口即可重试；平台自身补不上（那不是它的活）。
            资源错误::入口未绑定 { .. } => 三项判断 {
                可重试: true,
                可自愈: false,
                需人工: true,
            },
            // 黑盒返回了错的类型：可能是它坏了（重试有意义），也可能是声明写错了（要人看）。
            资源错误::输出形状不符 { .. } => 三项判断 {
                可重试: true,
                可自愈: false,
                需人工: true,
            },
            // 黑盒自身失败：重试有意义；平台补不上它的内部；先重试，不急着叫人。
            资源错误::资源执行失败 { .. } => 三项判断 {
                可重试: true,
                可自愈: false,
                需人工: false,
            },
            // 与内核自有的 `4` 逐项一致（超时是瞬时故障）。
            资源错误::超时 { .. } => 三项判断 {
                可重试: true,
                可自愈: true,
                需人工: false,
            },
            // 与内核自有的 `5` 逐项一致（窗口滚过去就好了）。
            资源错误::配额用尽 { .. } => 三项判断 {
                可重试: true,
                可自愈: true,
                需人工: false,
            },
        }
    }

    /// 这次失败涉及的资源号。
    pub const fn 资源号(&self) -> u32 {
        match self {
            资源错误::资源未声明 { 资源号 }
            | 资源错误::操作未声明 { 资源号, .. }
            | 资源错误::副作用未允许 { 资源号, .. }
            | 资源错误::输入形状不符 { 资源号, .. }
            | 资源错误::入口未绑定 { 资源号 }
            | 资源错误::输出形状不符 { 资源号, .. }
            | 资源错误::资源执行失败 { 资源号, .. }
            | 资源错误::超时 { 资源号, .. }
            | 资源错误::配额用尽 { 资源号 } => *资源号,
        }
    }
}

/// 三项业务判断 —— 「失败可编程处理」的落点。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 三项判断 {
    /// 重试有意义（例如瞬时故障）。
    pub 可重试: bool,
    /// 平台自身能补上，不需要人。
    pub 可自愈: bool,
    /// 只能由人裁决。
    pub 需人工: bool,
}

impl 三项判断 {
    /// 只能由人裁决（本关口新增码里最常出现的那一组）。
    pub const 仅人裁: Self = Self {
        可重试: false,
        可自愈: false,
        需人工: true,
    };
}

