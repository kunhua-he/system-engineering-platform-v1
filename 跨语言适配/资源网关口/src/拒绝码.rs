//! 关口抛出的结构化错误 —— **失败是可编程处理的数据，不是异常**。
//!
//! 一个错误码 = `码`（4 位：段位 × 1000 + 序号）+ `名称` + **三项业务判断**
//! （可重试 · 可自愈 · 需人工）。三项不是注释，是能读到的字段（[`错误码登记`]）。
//!
//! # 四处拒绝，四层专属码（`资源网关口.md` 第五节）
//!
//! | # | 拒绝什么 | 依据 | 专属码 |
//! |---|---|---|---|
//! | 1 | 没声明的**资源** | 清单里没有这个号 | `22` 资源未声明 |
//! | 2 | 没声明的**操作** | 该资源的 `操作` 白名单里没有这个操作号 | `23` 操作未声明 |
//! | 3 | 声明里**没允许的副作用** | `允许` 里是 `false`（默认全 false） | `24` 副作用未允许 |
//! | 4 | 输入**形状不合契约** | 槽的类型标签与声明的 `输入类型` 不符 | `25` 输入形状不符 |
//!
//! **逐层各有专属码，不许笼统报一个**：四层的可编程处置不同（第 1 层要人去加一条声明、
//! 第 2 层要人改白名单、第 3 层是安全裁决、第 4 层是调用方的 bug），合成一个码就等于
//! 把这四种处置重新揉回一句「失败了」。
//!
//! # 另有三处**文档未列**的失败（实测补的，各自专属码）
//!
//! | 码 | 名称 | 为什么非有不可 |
//! |---|---|---|
//! | `26` | 入口未绑定 | 声明里有这条资源、部署方没绑入口。**§三 规则 3 把入口挪出声明仓**，那一步就得有个「没挪到位」的码；没有它，调用方会拿到一个说不清的失败 |
//! | `27` | 输出形状不符 | 黑盒写回的输出槽类型与声明的 `输出类型` 不符。不判 ⇒ 错值**静默**流进上层 |
//! | `28` | 资源执行失败 | 黑盒自身报失败。底座**不认识它的内部**（§七 最后一条），所以只有这一个笼统码 —— 线索在留痕的入参指纹里 |
//!
//! # 复用底座自有的两个码（**不另造**）
//!
//! `4` 超时 · `5` 配额用尽 —— 同一个失败不因为报在哪一层而换码
//! （`契约声明/格式说明.md` 第五节）。**超时口径唯一**：不许资源自设一套。
//!
//! # 段位：**0 —— 底座自有**（2026-09-26 定，原先借段落 9）
//!
//! `契约声明/号段图.json` 的「错误码段位图」里，段位 `0` 的归属已改成
//! 「**底座自有** —— 内核 ＋ 跨语言适配（适配器 · **资源网关口**）」。
//!
//! **为什么只能是 0**：码是 4 位 = `段位 × 1000 + 序号` ⇒ 段位 ≤ 9，而 0–9 全已分配，
//! **没有空段位可分**。跨语言适配与内核一样是**随底座发布**的、不属于任何一段能力号段，
//! 故与内核共用段位 0。原先借段落 9（接口面与构建验证 · 工具类）—— 资源网关口不属于工具类，
//! 那是缺口不是归属。
//!
//! # 登记状态：**已登记**（2026-09-26）
//!
//! 七个码已按 `契约声明/错误码表/<码>.json` 的形状登记为 `0022`–`0028`
//! （段位 0 的码 = 序号；1–21 已被内核与适配层占用，故从 22 起）。
//! 码本身**改为引用生成物** `声明数据::错误码_0022…0028` —— 单一来源，不在本文件重算。
//!
//! 名称 / 说明 / 三项业务判断**一律取自生成物** `声明数据::错误码信息表`
//! （源：`契约声明/错误码表/00NN.json`，经 `构建装配/形态装配/生成声明.py` 出品）——
//! 本文件**不再手写文案**，同一事实只有一份。早先那七条手写副本已删。

use v1_contract::声明数据;

use crate::声明形状::副作用;

/// 本关口新增码所在的**段位** = 0（底座自有：内核 ＋ 跨语言适配）。依据见文件头。
pub const 关口段位: u32 = 0;

// 七个码**引用生成物**（源：`契约声明/错误码表/0022.json`…`0028.json`，
// 经 `构建装配/形态装配/生成声明.py` 出成 `错误码_<码>`）。
// **不在这里重算** —— 早先写的是 `关口段位 * 号段类宽度 + 序号`，那是第二个来源。
//
// 为什么是 22–28：段位 0 的码 = 序号（`段位 × 号段类宽度 + 序号`，段位 0 时前者为 0），
// 而 1–21 已被内核与适配层占用。**号只增不复用**，故从 22 起，且不许回头改小。

/// 第 1 层码：资源未声明。
pub const 码_资源未声明: u32 = 声明数据::错误码_0022.取号值();
/// 第 2 层码：操作未声明。
pub const 码_操作未声明: u32 = 声明数据::错误码_0023.取号值();
/// 第 3 层码：副作用未允许。
pub const 码_副作用未允许: u32 = 声明数据::错误码_0024.取号值();
/// 第 4 层码：输入形状不符。
pub const 码_输入形状不符: u32 = 声明数据::错误码_0025.取号值();
/// 第五处码：入口未绑定（文档未列）。
/// 第 5 层码（文档未列）：入口未绑定。
pub const 码_入口未绑定: u32 = 声明数据::错误码_0026.取号值();
/// 第 6 层码（文档未列）：输出形状不符。
pub const 码_输出形状不符: u32 = 声明数据::错误码_0027.取号值();
/// 第 7 层码（文档未列）：资源执行失败。
pub const 码_资源执行失败: u32 = 声明数据::错误码_0028.取号值();

/// 一次资源调用失败的结构化原因。
///
/// **不带异常、不带隐式通道**（`边界协议.md` 第五节）：它就是返回值的一部分。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 资源错误 {
    /// **第 1 层**：清单里没有这个号（依据：清单里没有它）。
    资源未声明 { 资源号: u32 },
    /// **第 2 层**：该资源的 `操作` 白名单里没有这个操作号。
    操作未声明 { 资源号: u32, 操作号: u32 },
    /// **第 3 层**：这条操作需要的副作用，声明里**没允许**。
    副作用未允许 {
        资源号: u32,
        操作号: u32,
        副作用: 副作用,
    },
    /// **第 4 层**：输入槽的形状与声明的 `输入类型` 不符。
    ///
    /// `槽位` 是出错的位置（0 起）；个数不符时它指向缺的那个位置 / 多出来的那个位置，
    /// `期望类型` / `实际类型` 里 `0`（空）表示「那个位置应当没有槽」或「那个位置没有槽」。
    输入形状不符 {
        资源号: u32,
        操作号: u32,
        槽位: u32,
        期望类型: u32,
        实际类型: u32,
    },
    /// **第五处**（文档未列）：声明里有这条资源，部署方没给它绑入口。
    入口未绑定 { 资源号: u32 },
    /// **第六处**（文档未列）：黑盒写回的输出槽类型与声明的 `输出类型` 不符。
    输出形状不符 {
        资源号: u32,
        操作号: u32,
        期望类型: u32,
        实际类型: u32,
    },
    /// **第七处**（文档未列）：黑盒自身报失败。底座不认识它的内部，故只有这一个码。
    资源执行失败 { 资源号: u32, 操作号: u32 },
    /// 这一项越过了声明的 `超时毫秒`（关口判并报码，**由关口执行**，不由资源保证）。
    超时 {
        资源号: u32,
        操作号: u32,
        毫秒数: u64,
    },
    /// 该资源号在配额窗口内已用满 `配额上限`（关口执行）。
    配额用尽 { 资源号: u32 },
}

impl 资源错误 {
    /// 完整 4 位码。**这就是 `契约声明/错误码表/<码>.json` 的文件名**。
    pub const fn 取错误码(&self) -> u32 {
        match self {
            资源错误::资源未声明 { .. } => 码_资源未声明,
            资源错误::操作未声明 { .. } => 码_操作未声明,
            资源错误::副作用未允许 { .. } => 码_副作用未允许,
            资源错误::输入形状不符 { .. } => 码_输入形状不符,
            资源错误::入口未绑定 { .. } => 码_入口未绑定,
            资源错误::输出形状不符 { .. } => 码_输出形状不符,
            资源错误::资源执行失败 { .. } => 码_资源执行失败,
            资源错误::超时 { .. } => 声明数据::错误码_0004.取号值(),
            资源错误::配额用尽 { .. } => 声明数据::错误码_0005.取号值(),
        }
    }

    /// 码的名称 —— 取自生成物 `声明数据::错误码信息表`（本文件不存文案）。
    pub fn 名称(&self) -> &'static str {
        查登记(self.取错误码()).map(|登记项| 登记项.名称).unwrap_or_default()
    }

    /// **三项业务判断** —— 「失败可编程处理」的全部依据，同样取自生成物。
    pub fn 取三项业务判断(&self) -> 三项业务判断 {
        match 查登记(self.取错误码()) {
            Some(登记) => 三项业务判断 {
                可重试: 登记.可重试,
                可自愈: 登记.可自愈,
                需人工: 登记.需人工,
            },
            None => 三项业务判断::仅人裁,
        }
    }

    /// 这次失败涉及的资源号。
    pub const fn 资源号(&self) -> u32 {
        match self {
            资源错误::资源未声明 { 资源号 }
            | 资源错误::操作未声明 { 资源号, .. }
            | 资源错误::副作用未允许 { 资源号, .. }
            | 资源错误::输入形状不符 { 资源号, .. }
            | 资源错误::入口未绑定 { 资源号 }
            | 资源错误::输出形状不符 { 资源号, .. }
            | 资源错误::资源执行失败 { 资源号, .. }
            | 资源错误::超时 { 资源号, .. }
            | 资源错误::配额用尽 { 资源号 } => *资源号,
        }
    }
}

/// 三项业务判断 —— 「失败可编程处理」的落点。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 三项业务判断 {
    /// 重试有意义（例如瞬时故障）。
    pub 可重试: bool,
    /// 平台自身能补上，不需要人。
    pub 可自愈: bool,
    /// 只能由人裁决。
    pub 需人工: bool,
}

impl 三项业务判断 {
    /// 只能由人裁决（本关口新增码里最常出现的那一组）。
    pub const 仅人裁: Self = Self {
        可重试: false,
        可自愈: false,
        需人工: true,
    };
}

/// 一条错误码的**登记内容**（运行期报错文案的副本）。**登记处**是 `契约声明/错误码表/`，
/// `契约声明/错误码表/<码>.json`（形状见 `契约声明/格式说明.md` 第五节）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 错误码登记 {
    /// 完整 4 位码，**就是文件名**。
    pub 码值: u32,
    pub 名称: &'static str,
    pub 说明文字: &'static str,
    /// 三项业务判断。
    pub 可重试: bool,
    pub 可自愈: bool,
    pub 需人工: bool,
    /// `码 // 号段类宽度` —— 冗余登记项，故意写出来供验证面交叉比对。
    pub 段位: u32,
    /// 段位归属文案（源：`契约声明/号段图.json` 的错误码段位图）。
    /// **本关口就在这个归属里**（段位 0 = 底座自有：内核 ＋ 跨语言适配）。
    pub 归属: &'static str,
}

/// 段位 0 的归属文案（源：`契约声明/号段图.json` 的错误码段位图）。
/// **本关口就在这个归属里**（2026-09-26 起）—— 早先这里写的是「借段落 9，归属不在图里」。
const 段位归属: &str = "底座自有 —— 内核 ＋ 跨语言适配（适配器 · 资源网关口）";

/// 本关口七个码的**登记内容** —— 一律取自生成物 `声明数据::错误码信息表`
/// （源：`契约声明/错误码表/0022`–`0028.json`）。本文件不再存一份文案。
pub fn 本关口错误码() -> [错误码登记; 7] {
    [
        查登记(码_资源未声明).expect("码 0022 已登记"),
        查登记(码_操作未声明).expect("码 0023 已登记"),
        查登记(码_副作用未允许).expect("码 0024 已登记"),
        查登记(码_输入形状不符).expect("码 0025 已登记"),
        查登记(码_入口未绑定).expect("码 0026 已登记"),
        查登记(码_输出形状不符).expect("码 0027 已登记"),
        查登记(码_资源执行失败).expect("码 0028 已登记"),
    ]
}

/// 按码查一条**已复用**的内核自有登记（超时 / 配额用尽 / 声明不自洽）——
/// 这三条不是本关口新增的，故不在 [`本关口错误码`] 里，文案同样取自生成物。
pub fn 内核自有登记(错误码: u32) -> Option<错误码登记> {
    match 错误码 {
        4 | 5 | 13 => 查登记(错误码),
        _ => None,
    }
}

/// 生成物里的 `名称` / `说明` 是 NUL 结尾的字节串指针 ⇒ 读成 `&'static str`。
///
/// # Safety
/// 指针必须指向**活得比调用方久**的字节串；本文件两处调用点都是生成物里的静态常量。
unsafe fn 读文案(指针: *const u8) -> &'static str {
    if 指针.is_null() {
        return "";
    }
    // SAFETY：调用点的指针都是生成物里的 `'static` 常量字节串（见 `# Safety`）。
    let 文案: &str = unsafe { core::ffi::CStr::from_ptr(指针 as *const core::ffi::c_char) }
        .to_str()
        .unwrap_or_default();
    文案
}

/// 归属文案：码 1–21 是内核自有的号，22 起是本关口新增的号（段位 0 两侧共用）。
fn 取归属(码值: u32) -> &'static str {
    if 码值 % 声明数据::号段类宽度 < 22 {
        "内核自有（不对外）"
    } else {
        段位归属
    }
}

/// 按码从生成物 `错误码信息表` 造一条登记内容 ⇒ `None` = 这个码没登记。
/// **同一事实只有一份**：文案与三项业务判断都住在 `契约声明/错误码表/<码>.json`。
pub fn 查登记(码值: u32) -> Option<错误码登记> {
    let 信息 = 声明数据::错误码信息表.iter().find(|信息项| 信息项.码值 == 码值)?;
    Some(错误码登记 {
        码值: 信息.码值,
        名称: unsafe { 读文案(信息.名称) },
        说明文字: unsafe { 读文案(信息.说明) },
        可重试: 信息.可重试 != 0,
        可自愈: 信息.可自愈 != 0,
        需人工: 信息.需人工 != 0,
        段位: 信息.段位,
        归属: 取归属(信息.码值),
    })
}
