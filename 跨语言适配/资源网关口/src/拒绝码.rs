//! 关口抛出的结构化错误 —— **失败是可编程处理的数据，不是异常**。
//!
//! 一个错误码 = `码`（4 位：段位 × 1000 + 序号）+ `名称` + **三项业务判断**
//! （可重试 · 可自愈 · 需人工）。三项不是注释，是能读到的字段（[`错误码登记`]）。
//!
//! # 四处拒绝，四层专属码（`资源网关口.md` 第五节）
//!
//! | # | 拒绝什么 | 依据 | 专属码 |
//! |---|---|---|---|
//! | 1 | 没声明的**资源** | 清单里没有这个号 | `22` 资源未声明 |
//! | 2 | 没声明的**操作** | 该资源的 `操作` 白名单里没有这个操作号 | `23` 操作未声明 |
//! | 3 | 声明里**没允许的副作用** | `允许` 里是 `false`（默认全 false） | `24` 副作用未允许 |
//! | 4 | 输入**形状不合契约** | 槽的类型标签与声明的 `输入类型` 不符 | `25` 输入形状不符 |
//!
//! **逐层各有专属码，不许笼统报一个**：四层的可编程处置不同（第 1 层要人去加一条声明、
//! 第 2 层要人改白名单、第 3 层是安全裁决、第 4 层是调用方的 bug），合成一个码就等于
//! 把这四种处置重新揉回一句「失败了」。
//!
//! # 另有三处**文档未列**的失败（实测补的，各自专属码）
//!
//! | 码 | 名称 | 为什么非有不可 |
//! |---|---|---|
//! | `26` | 入口未绑定 | 声明里有这条资源、部署方没绑入口。**§三 规则 3 把入口挪出声明仓**，那一步就得有个「没挪到位」的码；没有它，调用方会拿到一个说不清的失败 |
//! | `27` | 输出形状不符 | 黑盒写回的输出槽类型与声明的 `输出类型` 不符。不判 ⇒ 错值**静默**流进上层 |
//! | `28` | 资源执行失败 | 黑盒自身报失败。底座**不认识它的内部**（§七 最后一条），所以只有这一个笼统码 —— 线索在留痕的入参指纹里 |
//!
//! # 复用底座自有的两个码（**不另造**）
//!
//! `4` 超时 · `5` 配额用尽 —— 同一个失败不因为报在哪一层而换码
//! （`契约声明/格式说明.md` 第五节）。**超时口径唯一**：不许资源自设一套。
//!
//! # 段位：**0 —— 底座自有**（2026-09-26 定，原先借段落 9）
//!
//! `契约声明/号段图.json` 的「错误码段位图」里，段位 `0` 的归属已改成
//! 「**底座自有** —— 内核 ＋ 跨语言适配（适配器 · **资源网关口**）」。
//!
//! **为什么只能是 0**：码是 4 位 = `段位 × 1000 + 序号` ⇒ 段位 ≤ 9，而 0–9 全已分配，
//! **没有空段位可分**。跨语言适配与内核一样是**随底座发布**的、不属于任何一段能力号段，
//! 故与内核共用段位 0。原先借段落 9（接口面与构建验证 · 工具类）—— 资源网关口不属于工具类，
//! 那是缺口不是归属。
//!
//! # 登记状态：**已登记**（2026-09-26）
//!
//! 七个码已按 `契约声明/错误码表/<码>.json` 的形状登记为 `0022`–`0028`
//! （段位 0 的码 = 序号；1–21 已被内核与适配层占用，故从 22 起）。
//! 码本身**改为引用生成物** `声明数据::错误码_22…28` —— 单一来源，不在本文件重算。
//!
//! **仍有一处第二来源（如实登记，未消）**：本文件里的 `名称` / `说明` 文案与
//! `契约声明/错误码表/00NN.json` 是同一事实的两份。生成器目前**只出码不出文案**
//! （产物里 `pub const 错误码_N: u32 = N;`，名称与说明只在文档注释里）。
//! 消掉它要给生成器加一张 `错误码信息` 表并接进 `平台信息`（结构体已有，见
//! `契约声明/src/lib.rs` 的 `错误码信息`）。同样的问题在 `内核自有登记`（复用的 4 / 5 / 13）
//! 上**早就存在**，不是本次引入的。

