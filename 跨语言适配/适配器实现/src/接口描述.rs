//! 接口描述 —— 把适配器的读侧（`能力清单` + `能力契约`）写成 UTF-8 JSON。
//!
//! # 形状（与 `接口面形状.md` §三 的自描述根对齐，去掉 HTTP 专有字段）
//!
//! ```json
//! {
//!   "契约版本": { "主": 0, "次": 1, "修订": 0, "构建": 1 },
//!   "声明格式号": 1398362929,
//!   "能力": [
//!     { "编号": 0, "名称": "取平台信息", "参数个数": 1, "返回类型": 0,
//!       "说明": "…",
//!       "参数表": [ { "名称": "目标字宽", "类型标签": 0, "状态位": 0 } ],
//!       "可抛错误码": [ { "码": 1, "名称": "提供者未载入",
//!                        "可重试": true, "可自愈": true, "需人工": false } ] }
//!   ]
//! }
//! ```
//!
//! # 数据一律**现读**，不另存
//!
//! `能力` 数组就是 [`适配器::能力清单`] 的输出，逐条再去 [`适配器::能力契约`] 取
//! 参数表行序与可抛错误码 —— 与调侧同一个入口（读侧与调侧同一入口，清单里的编号拿去调必然走得通）。
//!
//! # 明确不做
//!
//! - **不出 `端点` 表**：端点是 HTTP 网关的事（`对外接口面`），边界层写它就是替上层定形状，
//!   且会变成第二份端点表。
//! - **不出参数的 `默认值`**：默认值不在调用方要读的东西里 —— 行序即契约，缺位写空槽
//!   （`接口面形状.md` §三），默认值是提供者自己的事。少一个字段，就少一处漂移。
//! - **不按能力筛可抛错误码**：`适配器::能力契约` 给的是**声明全表**（见该 crate 文件头缺口 3：
//!   按段位筛要除 `号段类宽度`，而那个数在 `装载入口` 里是私有的）。这里原样转出，不自己筛。
//! - **字段一律有值，只有一个例外**：`说明` 在「取不到契约」时给 `null`。`null` = 取不到值，
//!   `""` = 已知是空串 —— 跨语言里是两件事。其余字段都有确定的值（`返回类型 0` = 无返回值、
//!   `可抛错误码 []` = 没有可抛码）⇒ 不给它们加「可能为 null」这条每种语言都要判的分支。

use crate::小写出::{值, 写};
use crate::{参数摘要, 适配器, 错误码摘要};
use v1_contract::平台信息;

/// 写一份接口描述 JSON（**不含**结尾换行）。
pub fn 写描述(适配器: &适配器, 契约来源: &平台信息) -> String {
    let 版本 = 契约来源.实现版本;
    let 能力 = 适配器
        .能力清单()
        .into_iter()
        .map(|摘要| {
            let 契约 = 适配器.能力契约(摘要.编号);
            let (说明, 参数表, 可抛错误码) = match &契约 {
                Some(契) => (
                    值::文本(契.说明.clone()),
                    契.参数表.clone(),
                    契.可抛错误码.clone(),
                ),
                // 清单与契约走同一个注册表 ⇒ 正常装配下走不到这一支（注册表前后不一致才走到）。
                // 给 `null` 而**不是空串**：`null` = 取不到值，`""` = 已知是空串 ——
                // 跨语言里这是两件事（调用方要判的正是「这个字段有没有值」）。
                None => (值::空, Vec::new(), Vec::new()),
            };
            值::对象(vec![
                ("编号".to_owned(), 值::整数(摘要.编号 as i64)),
                ("名称".to_owned(), 值::文本(摘要.名称)),
                ("参数个数".to_owned(), 值::整数(摘要.参数个数 as i64)),
                ("返回类型".to_owned(), 值::整数(摘要.返回类型 as i64)),
                ("说明".to_owned(), 说明),
                ("参数表".to_owned(), 值::数组(参数表.iter().map(写参数).collect())),
                (
                    "可抛错误码".to_owned(),
                    值::数组(可抛错误码.iter().map(写错误码).collect()),
                ),
            ])
        })
        .collect();

    let 根 = 值::对象(vec![
        (
            "契约版本".to_owned(),
            值::对象(vec![
                ("主".to_owned(), 值::整数(版本.主 as i64)),
                ("次".to_owned(), 值::整数(版本.次 as i64)),
                ("修订".to_owned(), 值::整数(版本.修订 as i64)),
                ("构建".to_owned(), 值::整数(版本.构建 as i64)),
            ]),
        ),
        (
            "声明格式号".to_owned(),
            值::整数(契约来源.声明格式号 as i64),
        ),
        ("能力".to_owned(), 值::数组(能力)),
    ]);
    写(&根)
}

/// 参数表的一行。**行序即契约**（顺序由上层 `Vec` 的排列给出）。
fn 写参数(参: &参数摘要) -> 值 {
    值::对象(vec![
        ("名称".to_owned(), 值::文本(参.名称.clone())),
        ("类型标签".to_owned(), 值::整数(参.类型标签 as i64)),
        ("状态位".to_owned(), 值::整数(参.状态位 as i64)),
    ])
}

/// 可抛错误码的一条：`码` + 三项业务判断（失败可编程处理的落点）。
fn 写错误码(码: &错误码摘要) -> 值 {
    值::对象(vec![
        ("码".to_owned(), 值::整数(码.码 as i64)),
        ("名称".to_owned(), 值::文本(码.名称.clone())),
        ("可重试".to_owned(), 逻辑(码.可重试)),
        ("可自愈".to_owned(), 逻辑(码.可自愈)),
        ("需人工".to_owned(), 逻辑(码.需人工)),
    ])
}

fn 逻辑(是: bool) -> 值 {
    if 是 { 值::真 } else { 值::假 }
}
