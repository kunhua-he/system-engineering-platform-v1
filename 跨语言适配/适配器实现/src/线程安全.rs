//! 线程安全 —— 适配器为什么能 `Send` / `Sync`，以及本 crate 唯一的 `unsafe` 断言。
//!
//! # 为什么要有这一件
//!
//! `对外接口面/调用接口面/` 的 accept 循环一直是**单线程**的，根因不在网关：
//! 适配器**不是 `Send` / `Sync`** ⇒ 全平台只有一个适配器实例，网关没法把它搬进
//! 多个工作线程。网关**不许替下层 `unsafe impl Sync` 担保**（那是替别的 crate 断言
//! 一件自身验证不了的事）⇒ 修法只能在适配器这一层。
//!
//! # 适配器里三样共享状态，逐样说清为什么能跨线程
//!
//! | 字段 | 形状 | 为什么跨线程安全 |
//! |---|---|---|
//! | `装载单元s` | `Vec<装载单元>`（内含 `&'static 平台信息` 与 `注册表`） | 装载完成后**只读**：所有方法都以 `&self` 读它，没有任何一处写它。它指向的是 `'static` 静态只读数据（契约本身担保），不随线程变。 |
//! | `账本` | `配额账本`（内部 `Mutex`） | 已经是 `Sync`：可变计数在 `Mutex` 里，`&self` 共享是它设计好的用法。 |
//! | `通知` | `Mutex<通知账>` | 见下：`通知账` 里的 `RefCell` 只在本锁内被碰，锁把它的可变性串行化了。 |
//! | `留痕` | `Option<留痕缓冲>` | 已经是 `Sync`：环形缓冲逐字段原子，`记` 取 `&self`（见 `运行内核/调用留痕/`）。 |
//! | `追踪号` | `AtomicU64` | 原子量，本身就是为跨线程设计的。 |
//!
//! # `通知账` 为什么必须整包上锁
//!
//! `通知通道` 的端点表用 `RefCell` 持有（它的签名是 `&self`，而 `请求卸载` 要改表）。
//! `RefCell` **不是 `Sync`** —— 两个线程同时 `borrow_mut` 就是数据竞争。所以本 crate
//! 把「通知通道 + 按标识的索引」合成一个 [`通知账`]，整包放进一把 `Mutex`：
//!
//! - 所有对端点表的读写都**只在 `锁()` 的临界区里**发生 ⇒ `RefCell` 的可变性被串行化，
//!   数据竞争不可能发生；
//! - 临界区里会调扩展的 `通知函数`（`请求卸载` / `延迟释放协商`）。扩展**拿不到适配器句柄**
//!   （它是 C 函数指针，没有回手调适配器的通道）⇒ 不存在重入死锁；生命周期的调用本身
//!   是低频事件，占住锁的代价可忽略。
//!
//! # `通知标识项` 的裸指针为什么能跨线程
//!
//! `指针` 指向契约里的**静态只读 NUL 结尾串**（`平台信息.标识串`，契约规定终生有效、
//! 不许改）。静态只读数据天然可被任意线程读 ⇒ 跨线程共享安全。
//!
//! # 这一条 `unsafe` 的边界（如实写清，不假装覆盖了）
//!
//! 本文件是全 crate 唯一断言线程安全的地方，且只断言两件**本 crate 自身验证得了**的事：
//! ① `装载单元s` 装载后只读、指向静态数据；② `通知账` 的所有访问都在同一把 `Mutex` 内。
//! 它**不**担保下层 `通知通道` 自身对外线程安全（那要 `通知通道` 自身声明）——所以
//! 适配器对外只经**本层**的口暴露通知，不把 `通知通道` 裸交出去。

use std::sync::Mutex;

use v1_notify::通知通道;

use crate::适配器;

/// 通知端点的一个**索引项**：标识串（文本，供按标识查找）+ 契约里的静态指针。
///
/// 为什么要有它：`通知通道` 的公开口收的是 `*const u8`（标识串指针），而网关手里只有
/// **文本**（HTTP 请求体里那串十六进制）。本索引是「文本 → 指针」的翻译表，
/// **不是第二份端点表** —— 端点表的权威仍在 `通知通道` 里，本表只做查找。
pub(crate) struct 通知标识项 {
    pub(crate) 标识串: String,
    pub(crate) 指针: *const u8,
}

/// 通知账：通知通道 + 按标识的索引，**一起受同一把锁保护**（见文件头）。
pub(crate) struct 通知账 {
    pub(crate) 通道: 通知通道,
    pub(crate) 标识表: Vec<通知标识项>,
}

impl 通知账 {
    pub(crate) fn 新建() -> Self {
        Self {
            通道: 通知通道::新建(),
            标识表: Vec::new(),
        }
    }
}

/// `通知账` 跨线程移动：它只装静态只读指针、函数指针与一个端点表，没有线程亲和的资源。
///
/// # Safety
/// `通知账` 里没有任何绑定到创建线程的状态（没有线程局部、没有 OS 句柄、没有 `Rc`）。
/// 移动它到另一个线程不会破坏任何不变量。共享（`Sync`）不在这里断言 —— 由 `适配器`
/// 的 `unsafe impl Sync` 连同「一律经 `Mutex` 访问」一起担保。
unsafe impl Send for 通知账 {}

/// 适配器跨线程移动。
///
/// # Safety
/// `适配器` 的全部字段见文件头那张表：装载单元表只读且指向静态数据，账本与通知账各自
/// 受 `Mutex` 保护，留痕缓冲逐字段原子，追踪号是原子量。没有任何字段把可变状态裸暴露给
/// 并发访问。
unsafe impl Send for 适配器 {}

/// 适配器跨线程共享。
///
/// # Safety
/// 并发 `&适配器` 的所有路径都落在文件头那张表里：
/// - 读侧（能力清单 / 能力契约）只读 `装载单元s`，无写；
/// - 调侧只经 `账本`（内部 `Mutex`）与只读的注册表；
/// - 通知侧一律 `锁()` 后访问 `通知账`（唯一持有 `RefCell` 的地方）；
/// - 留痕侧只经原子的 `留痕缓冲`。
///
/// 因此不存在数据竞争。
unsafe impl Sync for 适配器 {}

/// 锁一把 `Mutex`，中毒也照用（锁中毒只说明别的线程 panic 过，被保护的数据本身没坏）。
///
/// 与 `运行内核/调用调度/src/配额记账.rs` 的处置同一口径：**不许因为中毒就崩**。
pub(crate) fn 取锁<'锁, 值>(锁句柄: &'锁 Mutex<值>) -> std::sync::MutexGuard<'锁, 值> {
    锁句柄.lock().unwrap_or_else(|中毒| 中毒.into_inner())
}
