//! 值归还 —— 跨边界「释放口」的**唯一实现**。
//!
//! # 它管什么
//!
//! C 符号 `平台_释放值` 与 Rust 面 [`适配器::释放值`] 都走本函数。调用方拿到一个带
//! `槽标志::所有权交出` 的返回槽（典型来源：某个外部支持库的 `写字节集` ——
//! `Box::into_raw(字节.into_boxed_slice())`），用过之后经这里归还。
//!
//! # 真回收（审计发现 1 的修法）
//!
//! 对「引用 + 所有权交出 + 槽值 != 0」的槽，先按「谁分配谁释放」（`边界协议.md` §三）
//! 把那块堆内存**真回收**，再清槽 —— 清槽在前会让这次回收失去地址。
//!
//! 回收式与外部支持库侧的 `释放返回字节`（`测试用例/夹具.rs::释放返回字节`）**逐字同一动作**：那是
//! **测试里**的同一件事，这里把它移到**生产口**。`Box<[u8]>` 走**进程级全局分配器**
//! （std 默认 `System`），与 `边界面.rs::平台_释放接口描述` 的 `Box::from_raw` **同一
//! 机制** —— 那条已证明可行。
//!
//! # 更正旧论证（「本边界放不了」是错的）
//!
//! 旧注释说「带所有权的槽本边界放不了，因为 `运行内核/内存分配器` 按实例记账」——
//! **论证有误**：它把「实例记账的内存分配器」与「进程级全局分配器」混为一谈。扩展经
//! `写字节集` 交出的是**后者**（`Box` = `System`），边界不需要任何实例账本就能回收它。
//! 故本函数**不再只清槽**。
//!
//! # 幂等
//!
//! 清槽即去掉「引用 + 所有权交出」标志 ⇒ 空槽再还一次不再命中回收分支，**不会二次释放**。

use crate::{适配器, 数据槽};

/// 归还槽值：跨边界「释放口」的**唯一实现**（C 符号与 Rust 面都走它）。
///
/// 语义：带所有权交出的引用槽**先真回收再清槽**（见文件头）；其余槽只清空。**幂等** ——
/// 清槽后标志已去，再还一次无事发生。
pub fn 归还槽值(数据槽: &mut 数据槽) {
    if 数据槽.是否引用() && 数据槽.交出了所有权() && 数据槽.槽值 != 0 {
        let 片段 =
            core::ptr::slice_from_raw_parts_mut(数据槽.槽值 as *mut u8, 数据槽.槽字节长度 as usize);
        // SAFETY: 契约保证「引用 + 所有权交出」的槽指向一块由 `Box<[u8]>` 交出的堆内存
        // （`写字节集` 与同形的产出方），长度逐字相同；本函数只对该槽命中一次
        // （清槽即去掉标志）⇒ 这一次 `Box::from_raw` 是唯一的一次释放。
        drop(unsafe { Box::from_raw(片段) });
    }
    *数据槽 = 数据槽::空槽();
}

impl 适配器 {
    /// Rust 级释放口：与 C 符号 `平台_释放值` **同语义**。
    ///
    /// 调用方拿到返回槽后，按槽标志判所有权；带 `槽标志::所有权交出` 的槽在用过之后
    /// 经本方法归还，内存按「谁分配谁释放」**真回收**（见文件头）。
    pub fn 释放值(&self, 数据槽: &mut 数据槽) {
        归还槽值(数据槽);
    }
}

/// **收下字节槽** —— 跨进程「值归还」的宿主侧落点：过线的字节在这里**材料化**成
/// 一块**宿主自有**的 `Box<[u8]>`，再用同一条 [`归还槽值`] 真回收。
///
/// # 为什么需要它（所有权单向那一条的落地）
///
/// `README.md` §三与前置裁决都定死：**跨进程传字节不传指针**。于是能力进程里那个
/// `Box<[u8]>` 在宿主侧是一个**地址失效**的悬空值 —— 拿它去 `Box::from_raw` 是 UB。
/// 本函数做两件事，恰好把这条路接回去：
///
/// 1. **材料化**：把过线来的字节拷成一块**宿主进程自行分配**的 `Box<[u8]>`；
/// 2. **交出所有权**：按 [`槽标志::引用`] + [`槽标志::所有权交出`] 造槽。
///
/// 这样拿到的槽与「进程内一次真调用」交出的槽**逐字段同形** ⇒ 调用方不必知道值从哪来：
/// 同一个 [`归还槽值`] 照常真回收（它只用到槽自带的地址与长度两字段）。
///
/// **传字节不传指针**不是一句口号，它的代价就在这里：一次过线拷贝。
/// 省掉拷贝就得让宿主解引用远端地址 —— 那正是反向样本（违所有权单向）。
pub fn 收下字节槽(标签: v1_contract::类型标签, 字节: &[u8]) -> 数据槽 {
    // `into_boxed_slice` 走标准库默认分配器（`System`）—— 与 `写字节集` 侧**同一机制**，
    // 故宿主侧 `Box::from_raw` 回收它成立（见文件头「真回收」）。
    let 字节块 = 字节.to_vec().into_boxed_slice();
    let 字节长度 = 字节块.len() as u64;
    let 槽值 = Box::into_raw(字节块) as *mut u8 as u64;
    数据槽::指针(标签, 槽值, 字节长度, true)
}
