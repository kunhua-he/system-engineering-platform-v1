//! 图任务的**节点时刻与执行批号**判据（`图任务测试` 的子模块）。
//!
//! 为什么单列一个文件：父件已经 653 行，再加这五条会越过 800 行上限；时刻相关判据
//! 是独立主题（单调钟、零时、没跑过就不写），拆开也不影响父子关系与夹具复用。
//!
//! 口径要点：时刻取单调钟、以该任务的提交时刻为零时；没真跑过的节点不许有任何时刻与批号
//! （写 0 冒充就是编造证据）。

use super::*;

// ── 节点时刻（开始微秒 / 结束微秒 / 执行批号）──────────────────────────────────
//
// 只报阶段名时，外部读不出「两条并行支的时间真重叠」「后继真等前驱结束」「同一个完成
// 事件没把节点启两次」—— 验收页只能永久记「看不见」。下面五条把这三格钉成可判读数。

/// 取一个节点的整行读数（图上每个节点都必须出现在快照里，查不到就是回执漏节点）。
fn 取节点读数<'a>(
    快照: &'a crate::任务对外::任务快照,
    标识: &str,
) -> &'a crate::任务对外::节点读数 {
    快照
        .节点读数(标识)
        .unwrap_or_else(|| panic!("节点 {标识} 必须在快照里：{:?}", 快照.节点读数表))
}

/// 取一个节点的时间区间；缺一端就 panic（真跑过的节点必须有两端）。
fn 取节点区间(快照: &crate::任务对外::任务快照, 标识: &str) -> (u64, u64) {
    let 项 = 取节点读数(快照, 标识);
    let 始 = 项
        .开始微秒
        .unwrap_or_else(|| panic!("节点 {标识} 真跑过，必须有开始微秒：{项:?}"));
    let 终 = 项
        .结束微秒
        .unwrap_or_else(|| panic!("节点 {标识} 真跑过，必须有结束微秒：{项:?}"));
    (始, 终)
}

#[test]
fn 菱形汇合两支区间真重叠() {
    let 适配器 = 计算适配器();
    // 两支都用慢叶子（各停 400 毫秒）：工作线程有两条，异键各占一条车道 ⇒ 区间必重叠。
    let 图 = [
        加一("起点", &[], 1),
        慢加一("左支", &["起点"], 0),
        慢加一("右支", &["起点"], 0),
        加法("汇合", &["左支", "右支"], &["左支", "右支"], &[]),
    ];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("菱形图必须受理");
    let 快照 = 等静止(&适配器, 任务标识);
    let (左始, 左终) = 取节点区间(&快照, "左支");
    let (右始, 右终) = 取节点区间(&快照, "右支");
    assert!(
        左始 <= 右终 && 右始 <= 左终,
        "两条并行支的区间必须有交（否则「并行」只是口头声明）：左 {左始}..{左终}，右 {右始}..{右终}"
    );
    let (汇始, _) = 取节点区间(&快照, "汇合");
    assert!(
        汇始 >= 左终 && 汇始 >= 右终,
        "汇合必须等两支都结束才起跑：汇合起点 {汇始}，左终 {左终}，右终 {右终}"
    );
}

#[test]
fn 串行链后继不早于前驱结束() {
    let 适配器 = 计算适配器();
    let 图 = [
        加一("示例节点1", &[], 1),
        加一("示例节点2", &["示例节点1"], 1),
        加一("示例节点3", &["示例节点2"], 1),
    ];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("串行链必须受理");
    let 快照 = 等静止(&适配器, 任务标识);
    let (_, 终1) = 取节点区间(&快照, "示例节点1");
    let (始2, 终2) = 取节点区间(&快照, "示例节点2");
    let (始3, 终3) = 取节点区间(&快照, "示例节点3");
    assert!(
        始2 >= 终1,
        "后继不许早于前驱结束：示例节点2 起点 {始2}，示例节点1 终点 {终1}"
    );
    assert!(
        始3 >= 终2,
        "后继不许早于前驱结束：示例节点3 起点 {始3}，示例节点2 终点 {终2}"
    );
    assert!(终1 <= 终2 && 终2 <= 终3, "串行链的结束时刻必须递增");
}

#[test]
fn 跳过节点没有时刻也没有批号() {
    let 适配器 = 计算适配器();
    // 桶号 33 专供本用例：跳过后继一次都不许真执行。
    let 图 = [
        拒算("坏节点", &[]),
        计数节点请求("跳过后继", &["坏节点"], 33),
    ];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("失败隔离图必须受理");
    let 快照 = 等静止(&适配器, 任务标识);

    let 坏 = 取节点读数(&快照, "坏节点");
    assert_eq!(坏.节点阶段, 调用节点阶段::失败);
    let (坏始, 坏终) = 取节点区间(&快照, "坏节点");
    assert!(坏终 >= 坏始, "失败节点也真跑过：终点不许早于起点");
    assert!(
        坏.执行批号.unwrap_or(0) > 0,
        "真执行过的节点必须带批号：{坏:?}"
    );

    let 跳 = 取节点读数(&快照, "跳过后继");
    assert_eq!(跳.节点阶段, 调用节点阶段::跳过);
    assert_eq!(
        跳.开始微秒, None,
        "被跳过的节点没有起跑，不许编一个开始时刻：{跳:?}"
    );
    assert_eq!(跳.结束微秒, None, "被跳过的节点没有结束时刻：{跳:?}");
    assert_eq!(
        跳.执行批号, None,
        "没执行就没有批号 —— 不许写 0 冒充真执行过：{跳:?}"
    );
    assert_eq!(计数读数(33), 0, "被跳过的节点一次都不许真执行");
}

#[test]
fn 成功节点必有两端且结束不早于开始() {
    let 适配器 = 计算适配器();
    let 图 = [
        加一("示例节点1", &[], 1),
        加一("示例节点2", &["示例节点1"], 1),
        加一("示例节点3", &["示例节点2"], 1),
    ];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("串行链必须受理");
    let 快照 = 等静止(&适配器, 任务标识);
    assert_eq!(快照.阶段, 调用任务阶段::成功);
    let 成功节点数 = 快照
        .节点读数表
        .iter()
        .filter(|项| 项.节点阶段 == 调用节点阶段::成功)
        .count();
    assert_eq!(成功节点数, 3, "三个节点都必须成功");
    for 项 in &快照.节点读数表 {
        let 始 = 项
            .开始微秒
            .unwrap_or_else(|| panic!("成功节点必须有开始微秒：{项:?}"));
        let 终 = 项
            .结束微秒
            .unwrap_or_else(|| panic!("成功节点必须有结束微秒：{项:?}"));
        assert!(终 >= 始, "结束不许早于开始：{项:?}");
        assert!(项.执行批号.unwrap_or(0) > 0, "成功节点必须带批号：{项:?}");
    }
}

#[test]
fn 未起跑节点不编时刻() {
    // 说明：提交就被拒的坏图拿不到任务标识，无从查回执（那条路不产生快照），所以这里钉
    // **能真实证明的那个不变量**：还在跑的节点没有结束时刻，等着前驱的节点三格全无。
    let 适配器 = 计算适配器();
    let 图 = [
        慢加一("起跑节点", &[], 1),
        加一("等着的节点", &["起跑节点"], 1),
    ];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("两节点图必须受理");
    let 快照 = 适配器
        .查询任务(任务标识, None)
        .expect("刚提交的任务必须查得到");
    let 跑 = 取节点读数(&快照, "起跑节点");
    assert!(
        跑.开始微秒.is_some(),
        "提交即起跑的节点必须已经有开始时刻：{跑:?}"
    );
    assert_eq!(跑.结束微秒, None, "还在跑就不许有结束时刻：{跑:?}");
    assert!(跑.执行批号.unwrap_or(0) > 0, "起跑的节点必须带批号：{跑:?}");
    let 等 = 取节点读数(&快照, "等着的节点");
    assert!(
        matches!(
            等.节点阶段,
            调用节点阶段::等待依赖 | 调用节点阶段::就绪 | 调用节点阶段::等资源
        ),
        "前驱没跑完，后继只能在这些阶段里：{等:?}"
    );
    assert_eq!(等.开始微秒, None, "没起跑就不许有开始时刻：{等:?}");
    assert_eq!(等.结束微秒, None, "没起跑就不许有结束时刻：{等:?}");
    assert_eq!(等.执行批号, None, "没起跑就不许有批号：{等:?}");
    let _ = 等静止(&适配器, 任务标识);
}
