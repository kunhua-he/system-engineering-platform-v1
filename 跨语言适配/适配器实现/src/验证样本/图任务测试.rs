//! 图任务对外面的测试 —— **整文件即测试**（`lib.rs` 用 `#[cfg(test)] #[path]` 挂进来）。
//!
//! | 判据 | 落点 |
//! |---|---|
//! | 单节点图 → 查询到成功 | `单节点图提交后查到成功` |
//! | 两节点依赖：下游拿得到上游产出 | `依赖边下游拿得到上游产出` |
//! | 菱形图并行且汇点收口 | `菱形图汇点收口` |
//! | 提交后立即查询必须是**非终态** | `提交后立即查询是非终态` |
//! | 取消：等待中置已取消 · 执行中不被伪造 | `取消只标等待中节点` |
//! | 释放终态任务 → 查询 None | `释放终态任务后查不到` |
//! | 同请求标识幂等 · 不同图冲突 | `同请求标识幂等` |
//! | 参数不符契约（业务拒绝）与执行崩溃分得开 | `参数不符契约在执行前就拒` |
//!
//! 叶子全是纯计算（夹具里的加一 / 加法 / 慢加一）：不碰文件、不碰网络、不碰模型。

use std::time::Duration;

use v1_contract::号段;
use v1_dispatch::{调用任务阶段, 调用节点阶段};

use crate::任务对外::{
    任务选项, 入参值, 图任务拒绝, 图任务节点请求, 节点输入引用
};
use crate::测试夹具::造计算声明;
use crate::适配器;

const 号段起点: u32 = 1000;

fn 计算适配器() -> 适配器 {
    适配器::装载声明根(&[
        crate::底座声明(),
        造计算声明(号段::构造(号段起点, 号段起点 + 99)),
    ])
    .expect("夹具声明必须载得进来")
}

fn 加一(节点: &str, 依赖: &[&str], 值: u64) -> 图任务节点请求 {
    图任务节点请求 {
        节点标识: node(节点),
        编号: 号段起点,
        命名值: vec![("加数".to_owned(), 入参值::内联(1, 值, 0))],
        依赖节点: 依赖.iter().map(|项| node(项)).collect(),
        输入引用: Vec::new(),
    }
}

fn node(名: &str) -> String {
    名.to_owned()
}

fn 加法(
    节点: &str, 依赖: &[&str], 引用: &[&str], 字面: &[(&str, u64)]
) -> 图任务节点请求 {
    图任务节点请求 {
        节点标识: node(节点),
        编号: 号段起点 + 1,
        命名值: 字面
            .iter()
            .map(|(名, 值)| ((*名).to_owned(), 入参值::内联(1, *值, 0)))
            .collect(),
        依赖节点: 依赖.iter().map(|项| node(项)).collect(),
        输入引用: 引用
            .iter()
            .enumerate()
            .map(|(位次, 来源)| 节点输入引用 {
                目标参数: if 位次 == 0 { "被加数" } else { "加数" }.to_owned(),
                来源节点: node(来源),
                来源参数: None,
            })
            .collect(),
    }
}

fn 慢加一(节点: &str, 依赖: &[&str], 值: u64) -> 图任务节点请求 {
    图任务节点请求 {
        节点标识: node(节点),
        编号: 号段起点 + 2,
        命名值: vec![("加数".to_owned(), 入参值::内联(1, 值, 0))],
        依赖节点: 依赖.iter().map(|项| node(项)).collect(),
        输入引用: Vec::new(),
    }
}

fn 等终态(适配器: &适配器, 任务标识: u64) -> crate::任务对外::任务快照 {
    适配器
        .等待任务(任务标识, Duration::from_secs(5))
        .expect("任务必须在表里")
}

#[test]
fn 单节点图提交后查到成功() {
    let 适配器 = 计算适配器();
    let 任务标识 = 适配器
        .提交任务图(&[加一("独节点", &[], 41)], 任务选项::不判重())
        .expect("单节点图必须受理");
    let 快照 = 等终态(&适配器, 任务标识);
    assert_eq!(快照.阶段, 调用任务阶段::成功, "单节点图必须跑到成功");
    assert_eq!(快照.节点阶段("独节点"), Some(调用节点阶段::成功));
    // 结果真算出来了：41 + 1。
    let 产出 = 适配器
        .任务节点产出(任务标识, "独节点")
        .expect("成功节点必须有产出槽");
    assert_eq!(产出.槽值, 42, "叶子必须真执行，不是兜底值");
}

#[test]
fn 依赖边下游拿得到上游产出() {
    let 适配器 = 计算适配器();
    let 图 = [
        加一("上游", &[], 41),
        加法("下游", &["上游"], &["上游"], &[("加数", 1)]),
    ];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("两节点图必须受理");
    let 快照 = 等终态(&适配器, 任务标识);
    assert_eq!(快照.阶段, 调用任务阶段::成功);
    let 产出 = 适配器
        .任务节点产出(任务标识, "下游")
        .expect("下游必须有产出槽");
    // 上游 41+1=42，下游 42+1=43 —— 下游拿的确实是上游那次执行的输出。
    assert_eq!(产出.槽值, 43, "下游必须吃到上游产出，不是下游的字面值");
}

#[test]
fn 菱形图汇点收口() {
    let 适配器 = 计算适配器();
    let 图 = [
        加一("根", &[], 1),
        加法("左", &["根"], &["根"], &[("加数", 0)]),
        加法("右", &["根"], &["根"], &[("加数", 5)]),
        加法("汇", &["左", "右"], &["左", "右"], &[]),
    ];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("菱形图必须受理");
    let 快照 = 等终态(&适配器, 任务标识);
    assert_eq!(快照.阶段, 调用任务阶段::成功);
    assert_eq!(快照.节点阶段表.len(), 4, "四个节点都要在快照里");
    let 产出 = 适配器
        .任务节点产出(任务标识, "汇")
        .expect("汇点必须有产出槽");
    // 根 1+1=2；左 2+0=2；右 2+5=7；汇 2+7=9。
    assert_eq!(产出.槽值, 9, "汇点必须拿到两条分支的产出");
}

#[test]
fn 提交后立即查询是非终态() {
    let 适配器 = 计算适配器();
    let 任务标识 = 适配器
        .提交任务图(&[慢加一("慢节点", &[], 1)], 任务选项::不判重())
        .expect("慢节点图必须受理");
    let 快照 = 适配器
        .查询任务(任务标识, None)
        .expect("刚提交的任务必须查得到");
    assert!(
        !快照.终态(),
        "提交后立刻查询绝不能是终态（那正是「假成功」的形态）：{:?}",
        快照.阶段
    );
    let 快照 = 等终态(&适配器, 任务标识);
    assert_eq!(快照.阶段, 调用任务阶段::成功, "慢节点最终必须成功");
}

#[test]
fn 取消只标等待中节点() {
    let 适配器 = 计算适配器();
    let 图 = [慢加一("在跑", &[], 1), 加一("等着", &["在跑"], 3)];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("两节点图必须受理");
    let 读数 = 适配器.取消任务(任务标识);
    assert!(读数.任务存在, "任务必须在表里");
    assert_eq!(读数.阶段, 调用任务阶段::已取消, "取消已受理即报已取消");
    assert!(
        读数.已取消节点.contains(&"等着".to_owned()),
        "等待中的节点必须被置成已取消：{:?}",
        读数.已取消节点
    );
    assert!(
        读数.在跑节点.contains(&"在跑".to_owned()),
        "执行中的节点必须在跑节点里：{:?}",
        读数.在跑节点
    );
    let 快照 = 适配器.查询任务(任务标识, None).expect("取消后仍查得到");
    assert_eq!(快照.节点阶段("等着"), Some(调用节点阶段::已取消));
    assert_ne!(
        快照.节点阶段("在跑"),
        Some(调用节点阶段::已取消),
        "执行中的节点不许被伪造成已取消"
    );
}

#[test]
fn 释放终态任务后查不到() {
    let 适配器 = 计算适配器();
    let 任务标识 = 适配器
        .提交任务图(&[加一("一格", &[], 1)], 任务选项::不判重())
        .expect("单节点图必须受理");
    assert!(!适配器.释放任务(任务标识), "在途任务不许释放");
    let _ = 等终态(&适配器, 任务标识);
    assert!(适配器.释放任务(任务标识), "终态任务必须可释放");
    assert!(
        适配器.查询任务(任务标识, None).is_none(),
        "释放后查询必须查不到（不是回一个空阶段）"
    );
    assert!(!适配器.释放任务(任务标识), "释放是幂等的：再释放回 false");
}

#[test]
fn 同请求标识幂等() {
    let 适配器 = 计算适配器();
    let 图 = [加一("幂等节点", &[], 7)];
    let 首个 = 适配器
        .提交任务图(&图, 任务选项::按请求("请求一"))
        .expect("首次提交必须受理");
    let 再次 = 适配器
        .提交任务图(&图, 任务选项::按请求("请求一"))
        .expect("同请求标识同图必须回原任务");
    assert_eq!(首个, 再次, "幂等：同请求标识 + 同图 ⇒ 同一任务标识");
    let 冲突 = 适配器.提交任务图(&[加一("幂等节点", &[], 8)], 任务选项::按请求("请求一"));
    assert!(
        matches!(冲突, Err(图任务拒绝::请求标识冲突 { .. })),
        "同请求标识不同图必须明确冲突：{冲突:?}"
    );
    let _ = 等终态(&适配器, 首个);
}

#[test]
fn 参数不符契约在执行前就拒() {
    let 适配器 = 计算适配器();
    let 坏名 = 图任务节点请求 {
        节点标识: "坏名".to_owned(),
        编号: 号段起点,
        命名值: vec![("不存在的参数".to_owned(), 入参值::内联(1, 1, 0))],
        依赖节点: Vec::new(),
        输入引用: Vec::new(),
    };
    let 拒 = 适配器
        .提交任务图(&[坏名], 任务选项::不判重())
        .expect_err("参数名不认识必须拒");
    assert!(matches!(拒, 图任务拒绝::节点参数不符契约 { .. }), "{拒:?}");
    assert_eq!(拒.节点标识(), Some("坏名"), "拒必须点名节点");
    assert!(拒.说明().contains("未知参数"), "{}", 拒.说明());

    let 坏号 = 图任务节点请求 {
        节点标识: "坏号".to_owned(),
        编号: 999_999,
        命名值: Vec::new(),
        依赖节点: Vec::new(),
        输入引用: Vec::new(),
    };
    let 拒 = 适配器
        .提交任务图(&[坏号], 任务选项::不判重())
        .expect_err("编号没人认领必须拒");
    assert!(matches!(拒, 图任务拒绝::节点参数不符契约 { .. }), "{拒:?}");
}
