/// 重复提交去重的**窗口边界**：记录被释放后，同一请求标识会重新执行。
///
/// 这不是「幂等失效」，是窗口的真实形状：去重键跟着任务记录一起回收（任务表有容量上限）。
/// 钉住它有两个用处：① 协议里的窗口说明有判据兜底，不至于文档写一套、实现另一套；
/// ② 将来持久化把窗口换成唯一索引时，这条会红——那时要改的是这条判据，不是悄悄放过去。
#[test]
fn 记录释放后同请求标识会重新执行() {
    let 适配器 = 计算适配器();
    let 图 = [加一("窗口节点", &[], 5)];
    let 首个 = 适配器
        .提交任务图(&图, 任务选项::按请求("窗口请求"))
        .expect("首次提交必须受理");
    let _ = 等终态(&适配器, 首个);
    assert!(适配器.释放任务(首个), "终态任务应当能释放（真删掉才回真）");
    assert!(
        适配器.查询任务(首个, None).is_none(),
        "释放后记录必须真没了"
    );
    let 再次 = 适配器
        .提交任务图(&图, 任务选项::按请求("窗口请求"))
        .expect("窗口外同标识必须能重新受理");
    assert_ne!(
        首个, 再次,
        "记录已回收 ⇒ 同请求标识重新执行，拿新的任务标识"
    );
    let _ = 等终态(&适配器, 再次);
}
