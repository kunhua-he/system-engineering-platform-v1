//! 图任务对外面的测试 —— **整文件即测试**（`lib.rs` 用 `#[cfg(test)] #[path]` 挂进来）。
//!
//! | 判据 | 落点 |
//! |---|---|
//! | 单节点图 → 查询到成功 | `单节点图提交后查到成功` |
//! | 两节点依赖：下游拿得到上游产出 | `依赖边下游拿得到上游产出` |
//! | 菱形图并行且汇点收口 | `菱形图汇点收口` |
//! | 提交后立即查询必须是**非终态** | `提交后立即查询是非终态` |
//! | 取消：等待中置已取消 · 执行中不被伪造 | `取消只标等待中节点` |
//! | 已成功任务再取消 ⇒ 幂等空操作、阶段不变 | `已成功任务再取消是幂等空操作` |
//! | 取消挡依赖链：后继节点**真没执行**（计数为 0） | `取消挡住依赖链后继节点不执行` |
//! | 取消赶不上快图 ⇒ 终态报成功（不按旗撒谎） | `取消赶不上快图终态仍报成功` |
//! | 取消两次幂等 | `重复取消幂等不改阶段` |
//! | 释放只对终态开口（取消后仍要等收口） | `释放只对终态开口` |
//! | 释放终态任务 → 查询 None | `释放终态任务后查不到` |
//! | 同请求标识幂等 · 不同图冲突 | `同请求标识幂等` |
//! | 参数不符契约（业务拒绝）与执行崩溃分得开 | `参数不符契约在执行前就拒` |
//! | 扩展回业务错误码（协议成功 + 错误槽）⇒ 节点失败、任务失败 | `失败节点如实报失败` |
//! | 失败节点的后代跳过且**真没执行**（计数为 0） | `失败节点后继被跳过且没执行` |
//! | 失败只影响后代，兄弟分支照常成功 | `失败节点的兄弟分支不受影响` |
//! | 同一失败入参：图路径与单能力路径判定一致 | `图路径与单能力路径对同一失败入参判定一致` |
//!
//! 叶子全是纯计算（夹具里的加一 / 加法 / 慢加一 / 计数 / 拒算）：不碰文件、不碰网络、不碰模型。

use std::time::Duration;

use v1_contract::号段;
use v1_dispatch::{调用任务阶段, 调用节点阶段};

use crate::任务对外::{
    任务选项, 入参值, 图任务拒绝, 图任务节点请求, 节点输入引用
};
use crate::测试夹具::{计数读数, 造计算声明};
use crate::适配器;

const 号段起点: u32 = 1000;

fn 计算适配器() -> 适配器 {
    适配器::装载声明根(&[
        crate::底座声明(),
        造计算声明(号段::构造(号段起点, 号段起点 + 99)),
    ])
    .expect("夹具声明必须载得进来")
}

fn 加一(节点: &str, 依赖: &[&str], 值: u64) -> 图任务节点请求 {
    图任务节点请求 {
        节点标识: node(节点),
        编号: 号段起点,
        命名值: vec![("加数".to_owned(), 入参值::内联(1, 值, 0))],
        依赖节点: 依赖.iter().map(|项| node(项)).collect(),
        输入引用: Vec::new(),
    }
}

fn node(名: &str) -> String {
    名.to_owned()
}

fn 加法(
    节点: &str, 依赖: &[&str], 引用: &[&str], 字面: &[(&str, u64)]
) -> 图任务节点请求 {
    图任务节点请求 {
        节点标识: node(节点),
        编号: 号段起点 + 1,
        命名值: 字面
            .iter()
            .map(|(名, 值)| ((*名).to_owned(), 入参值::内联(1, *值, 0)))
            .collect(),
        依赖节点: 依赖.iter().map(|项| node(项)).collect(),
        输入引用: 引用
            .iter()
            .enumerate()
            .map(|(位次, 来源)| 节点输入引用 {
                目标参数: if 位次 == 0 { "被加数" } else { "加数" }.to_owned(),
                来源节点: node(来源),
            })
            .collect(),
    }
}

fn 慢加一(节点: &str, 依赖: &[&str], 值: u64) -> 图任务节点请求 {
    图任务节点请求 {
        节点标识: node(节点),
        编号: 号段起点 + 2,
        命名值: vec![("加数".to_owned(), 入参值::内联(1, 值, 0))],
        依赖节点: 依赖.iter().map(|项| node(项)).collect(),
        输入引用: Vec::new(),
    }
}

/// 计数节点：入参「加数」在这里当**桶号**，叶子每执行一次该桶 +1。
fn 计数节点请求(节点: &str, 依赖: &[&str], 桶: u64) -> 图任务节点请求 {
    图任务节点请求 {
        节点标识: node(节点),
        编号: 号段起点 + 3,
        命名值: vec![("加数".to_owned(), 入参值::内联(1, 桶, 0))],
        依赖节点: 依赖.iter().map(|项| node(项)).collect(),
        输入引用: Vec::new(),
    }
}

fn 等终态(适配器: &适配器, 任务标识: u64) -> crate::任务对外::任务快照 {
    适配器
        .等待任务(任务标识, Duration::from_secs(5))
        .expect("任务必须在表里")
}

/// 等整张图**静止**（终态且没有执行中 / 收尾中的节点）。
///
/// 为什么不能只等 `等终态`：任务阶段「有失败即失败」是 fail-fast 的刻意口径 —— 一条分支
/// 失败时任务已经报终态，而独立分支可能还在跑。断言兄弟分支的终态必须先等它真跑完，
/// 否则测的是调度时序、不是行为。
fn 等静止(适配器: &适配器, 任务标识: u64) -> crate::任务对外::任务快照 {
    let 起点 = std::time::Instant::now();
    loop {
        let 快照 = 适配器.查询任务(任务标识, None).expect("任务必须在表里");
        let 在跑 = 快照
            .节点读数表
            .iter()
            .any(|项| matches!(项.节点阶段, 调用节点阶段::执行中 | 调用节点阶段::收尾中));
        if 快照.终态() && !在跑 {
            return 快照;
        }
        assert!(
            起点.elapsed() < Duration::from_secs(5),
            "任务必须静止：{:?}",
            快照.节点读数表
        );
        std::thread::sleep(Duration::from_millis(2));
    }
}

/// 拒算节点：叶子必回 4 位错误码（业务失败在返回槽里，协议层成功）。
fn 拒算(节点: &str, 依赖: &[&str]) -> 图任务节点请求 {
    图任务节点请求 {
        节点标识: node(节点),
        编号: 号段起点 + 4,
        命名值: vec![("加数".to_owned(), 入参值::内联(1, 1, 0))],
        依赖节点: 依赖.iter().map(|项| node(项)).collect(),
        输入引用: Vec::new(),
    }
}

/// 单能力路径对同一入参的判定：`(这次调用算不算成功, 业务错误码)`。
///
/// 口径与接口面一致：`转发结果::成功` 只是协议层，返回槽是**错误槽**就说明业务失败 ——
/// 这正是图路径必须给出同一答案的那条判据。
fn 单能力判定(
    适配器: &适配器, 编号: u32, 入参: &[crate::数据槽]
) -> (bool, Option<u32>) {
    let mut 槽 = crate::数据槽::空槽();
    let 读数 = 适配器.调用能力(编号, 入参, &mut 槽);
    if 槽.类型标签 == v1_contract::声明数据::类型标签_4294967295 {
        return (false, u32::try_from(槽.槽值).ok());
    }
    (matches!(读数, crate::转发结果::成功(_)), None)
}

#[test]
fn 失败节点如实报失败() {
    let 适配器 = 计算适配器();
    let 任务标识 = 适配器
        .提交任务图(&[拒算("坏节点", &[])], 任务选项::不判重())
        .expect("单节点图必须受理");
    let 快照 = 等终态(&适配器, 任务标识);
    assert_eq!(
        快照.节点阶段("坏节点"),
        Some(调用节点阶段::失败),
        "扩展回了错误码就是节点失败 —— 记成成功正是本用例要钉死的缺陷"
    );
    assert_eq!(
        快照.阶段,
        调用任务阶段::失败,
        "有节点失败，任务阶段必须报失败"
    );
    let 读数 = 快照.错误.expect("失败任务必须给出失败读数");
    assert_eq!(读数.节点标识, "坏节点", "失败读数必须点名失败的节点");
    assert!(
        读数.说明.contains("2001"),
        "失败说明必须带上扩展回的业务码：{}",
        读数.说明
    );
    assert!(
        适配器.任务节点产出(任务标识, "坏节点").is_none(),
        "失败节点不许留下产出槽（否则下游会拿到一个错误槽当值）"
    );
}

#[test]
fn 失败节点后继被跳过且没执行() {
    let 适配器 = 计算适配器();
    // 桶号按测试分账：本用例用 31，正对照用 32。
    let 图 = [拒算("坏", &[]), 计数节点请求("后继", &["坏"], 31)];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("依赖链必须受理");
    let 快照 = 等终态(&适配器, 任务标识);
    assert_eq!(快照.节点阶段("坏"), Some(调用节点阶段::失败));
    assert_eq!(
        快照.节点阶段("后继"),
        Some(调用节点阶段::跳过),
        "失败节点的后代必须跳过，不许照常执行：{:?}",
        快照.节点读数表
    );
    assert_eq!(快照.阶段, 调用任务阶段::失败, "跳过不是成功");
    assert_eq!(计数读数(31), 0, "被跳过的节点一次都不许真执行");

    // 正对照：同一条计数能力没有坏上游时确实会执行 —— 否则上面的 0 是假绿。
    let 对照 = 适配器
        .提交任务图(&[计数节点请求("活口", &[], 32)], 任务选项::不判重())
        .expect("单节点计数图必须受理");
    assert_eq!(
        等终态(&适配器, 对照).阶段,
        调用任务阶段::成功,
        "正对照必须成功"
    );
    assert_eq!(计数读数(32), 1, "正对照必须真执行一次");
}

#[test]
fn 失败节点的兄弟分支不受影响() {
    let 适配器 = 计算适配器();
    let 图 = [拒算("坏", &[]), 加一("好", &[], 41)];
    let 任务标识 = 适配器
        .提交任务图(&图, 任务选项::不判重())
        .expect("两条独立分支必须受理");
    let 快照 = 等静止(&适配器, 任务标识);
    assert_eq!(快照.节点阶段("坏"), Some(调用节点阶段::失败));
    assert_eq!(
        快照.节点阶段("好"),
        Some(调用节点阶段::成功),
        "失败只影响后代，兄弟分支必须照常成功：{:?}",
        快照.节点读数表
    );
    let 产出 = 适配器
        .任务节点产出(任务标识, "好")
        .expect("兄弟分支必须留下产出槽");
    assert_eq!(产出.槽值, 42, "兄弟分支必须真算出来");
    assert_eq!(快照.阶段, 调用任务阶段::失败, "独立分支成功不改任务失败");
}

#[test]
fn 图路径与单能力路径对同一失败入参判定一致() {
    let 适配器 = 计算适配器();
    let 入参 = [crate::数据槽::内联槽(
        v1_contract::声明数据::类型标签_0001,
        1,
        0,
    )];
    let (单能力成功, 单能力码) = 单能力判定(&适配器, 号段起点 + 4, &入参);
    assert!(
        !单能力成功,
        "先得证明这条入参在单能力路径上确实是失败（否则本用例无意义）"
    );
    assert_eq!(
        单能力码,
        Some(crate::测试夹具::夹具拒算码),
        "单能力路径给出的业务码"
    );

    let 任务标识 = 适配器
        .提交任务图(&[拒算("同参节点", &[])], 任务选项::不判重())
        .expect("单节点图必须受理");
    let 快照 = 等终态(&适配器, 任务标识);
    let 图成功 = 快照.节点阶段("同参节点") == Some(调用节点阶段::成功);
    assert_eq!(
        图成功,
        单能力成功,
        "同一失败入参：图路径判 {:?}，单能力路径判 {:?} —— 两条路必须逐字一致",
        快照.节点阶段("同参节点"),
        单能力成功
    );
    assert_eq!(快照.阶段, 调用任务阶段::失败);
}

