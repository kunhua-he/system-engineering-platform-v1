//! 未知语义的判据 —— **状态机只放确认过的节点**。
//!
//! | 判据 | 落点 |
//! |---|---|
//! | 超时 ⇒ 节点未知、整图未确认 | `超时判未知不许判失败` |
//! | 执行体崩溃 ⇒ 未知 | `执行体崩溃判未知` |
//! | 业务失败（错误槽）仍是确认失败 | `业务失败仍是确认失败` |
//! | 执行前判掉的失败仍是确认失败 | `执行前失败不算未知` |
//! | 未确认带得出未知节点清单与来源段位 | `未确认带未知节点与段位` |
//!
//! 为什么这几条必须由本件守着：内核只有「成功 / 失败」两格，它的 `超时` 注释写的是
//! 「可能还在跑」、`扩展执行崩溃` 写的是「可能已经改了扩展内部状态」—— 拿这两格当失败
//! 用，就是替能力宣布结局。本平台的判据是「只有确认过的」，所以它们必须落未知。

use std::sync::Arc;
use std::time::Duration;

use v1_contract::数据槽;
use v1_dispatch::{调度错误, 调用节点阶段};

use crate::调用任务装配::{
    任务结局, 叶子产出, 叶子执行口, 叶子标记, 叶子请求, 执行单次, 节点素材,
};

fn 请求(节点: &str) -> 叶子请求 {
    叶子请求 {
        节点标识: 节点.to_owned(),
        执行批号: 0,
        编号: 0,
        入参: Vec::new(),
    }
}

fn 素材(节点: &str, 依赖: &[&str]) -> 节点素材 {
    节点素材 {
        节点标识: 节点.to_owned(),
        依赖节点: 依赖.iter().map(|名| (*名).to_owned()).collect(),
        资源键: vec![format!("键/{节点}")],
        请求: 请求(节点),
    }
}

fn 失败产出(段位: 调度错误) -> 叶子产出 {
    叶子产出 {
        结果: crate::转发结果::失败(段位),
        槽: 数据槽::空槽(),
        业务错误码: None,
    }
}

/// 按节点标识定产出的假叶子（只测适配器怎么解释产出，不测能力本身）。
struct 定产出叶子 {
    标记: Arc<叶子标记>,
}

impl 叶子执行口 for 定产出叶子 {
    fn 标记(&self) -> &叶子标记 {
        &self.标记
    }

    fn 执行(&self, 请求: &叶子请求) -> 叶子产出 {
        match 请求.节点标识.as_str() {
            "超时节点" => 失败产出(调度错误::超时 { 毫秒数: 120_000 }),
            "崩溃节点" => 失败产出(调度错误::扩展执行崩溃),
            "执行前失败节点" => 失败产出(调度错误::参数个数不符 {
                声明: 1,
                实际: 2,
            }),
            // 业务失败：协议成功，但返回槽是错误码（4 位业务码在槽里，段位为空）。
            "业务失败节点" => 叶子产出 {
                结果: crate::转发结果::成功(数据槽::空槽()),
                槽: 数据槽::空槽(),
                业务错误码: Some(2001),
            },
            _ => 叶子产出 {
                结果: crate::转发结果::成功(数据槽::空槽()),
                槽: 数据槽::空槽(),
                业务错误码: None,
            },
        }
    }
}

fn 跑(素材表: Vec<节点素材>) -> 任务结局 {
    执行单次(
        素材表,
        Arc::new(定产出叶子 {
            标记: Arc::new(叶子标记::新建()),
        }),
        "未知语义任务",
        Duration::from_secs(5),
    )
    .expect("装配与收口都必须成功")
}

#[test]
fn 超时判未知不许判失败() {
    let 结局 = 跑(vec![素材("超时节点", &[])]);
    match 结局 {
        任务结局::未确认 {
            未知节点,
            段位,
            说明,
        } => {
            assert_eq!(未知节点, vec!["超时节点".to_owned()]);
            assert_eq!(段位, Some(调度错误::超时 { 毫秒数: 120_000 }));
            assert!(说明.contains("超时节点"), "说明要点名节点：{说明}");
            assert!(
                说明.contains("不下结论"),
                "说明要讲清平台为什么不下结论：{说明}"
            );
        }
        别的 => panic!("超时只能判未确认 —— 说失败就是替能力宣布结局：{别的:?}"),
    }
}

#[test]
fn 执行体崩溃判未知() {
    let 结局 = 跑(vec![素材("崩溃节点", &[])]);
    match 结局 {
        任务结局::未确认 { 未知节点, .. } => {
            assert_eq!(未知节点, vec!["崩溃节点".to_owned()])
        }
        别的 => panic!("执行体崩溃只能判未确认：{别的:?}"),
    }
}

#[test]
fn 业务失败仍是确认失败() {
    let 结局 = 跑(vec![素材("业务失败节点", &[])]);
    match 结局 {
        任务结局::失败 { 错误, 说明, .. } => {
            assert_eq!(错误, None, "业务失败没有调度段位，不许借一个顶上");
            assert!(说明.contains("2001"), "说明要带扩展回的业务码：{说明}");
        }
        别的 => panic!("扩展回了错误槽就是确认失败：{别的:?}"),
    }
}

#[test]
fn 执行前失败不算未知() {
    let 结局 = 跑(vec![素材("执行前失败节点", &[])]);
    match 结局 {
        任务结局::失败 { 错误, .. } => assert_eq!(
            错误,
            Some(调度错误::参数个数不符 {
                声明: 1, 实际: 2
            }),
            "一次都没进扩展 ⇒ 确认失败，段位照原样带出"
        ),
        别的 => panic!("执行前判掉的失败不许算未知：{别的:?}"),
    }
}

/// 前驱未知时后继不许被当成「前驱成功」推起来 —— 只能跳过（拿不到有效输入是确定的）。
#[test]
fn 前驱未知后继跳过() {
    let 结局 = 跑(vec![素材("超时节点", &[]), 素材("后继节点", &["超时节点"])]);
    match 结局 {
        任务结局::未确认 { 未知节点, .. } => {
            assert_eq!(
                未知节点,
                vec!["超时节点".to_owned()],
                "未知只记真未知的那一个"
            );
        }
        别的 => panic!("有未知节点的图只能判未确认：{别的:?}"),
    }
}

#[test]
fn 未确认带未知节点与段位() {
    let 结局 = 跑(vec![素材("超时节点", &[]), 素材("崩溃节点", &[])]);
    match 结局 {
        任务结局::未确认 {
            未知节点, 段位,
        ..
        } => {
            assert_eq!(未知节点.len(), 2, "两个都未知：{未知节点:?}");
            assert!(未知节点.contains(&"超时节点".to_owned()));
            assert!(未知节点.contains(&"崩溃节点".to_owned()));
            assert!(段位.is_some(), "来源段位不许丢：调用方靠它决定重发还是核对");
        }
        别的 => panic!("{别的:?}"),
    }
}

/// 节点阶段这一格也要对：记录里是未知，不是失败（内核那格才是失败）。
#[test]
fn 未确认时节点记录写未知() {
    let 素材表 = vec![素材("超时节点", &[])];
    let 实例 = crate::调用任务装配::调度实例::装配(
        素材表,
        Arc::new(定产出叶子 {
            标记: Arc::new(叶子标记::新建()),
        }),
        "未知语义节点阶段",
    )
    .expect("装配必须成功");
    实例.提交().expect("提交必须成功");
    let 结局 = 实例.等待任务(Duration::from_secs(5)).expect("必须收口");
    assert!(matches!(结局, 任务结局::未确认 { .. }), "{结局:?}");
    assert_eq!(
        实例.记录节点阶段("超时节点"),
        Some(调用节点阶段::未知),
        "记录里必须写未知"
    );
    assert_eq!(
        实例.节点阶段("超时节点"),
        Some(调用节点阶段::失败),
        "内核那格仍是失败（只有两格），但对外报的是记录那本账"
    );
}
