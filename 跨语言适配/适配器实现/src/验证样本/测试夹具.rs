/// 零参执行函数（夹具用；真实现的执行函数不许留空指针，这里只为能建表）。
unsafe extern "C-unwind" fn 夹具零参(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    let _ = (参数个数, 参数表);
    if !返回槽.is_null() {
        // SAFETY: 空指针已挡；非空由调用契约保证可写。
        unsafe {
            *返回槽 = 数据槽::内联槽(v1_contract::声明数据::类型标签_0001, 1, 0)
        };
    }
}

