/// 回显执行函数：把第 0 个入参槽**原样**（标签 · 值 · 长度）写回返回槽。
///
/// 它证「转发路不解释槽的类型标签」：递进去一个「句柄」槽，回来的还是那个字节值。
unsafe extern "C-unwind" fn 夹具回显第零槽(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    if 返回槽.is_null() || 参数个数 == 0 || 参数表.is_null() {
        return;
    }
    // SAFETY: 参数个数 > 0 且参数表非空 ⇒ 第 0 项可读；返回槽 由调用契约保证可写。
    let 数据槽 = unsafe { *参数表 };
    unsafe {
        *返回槽 = 数据槽::内联槽(数据槽.类型标签, 数据槽.槽值, 数据槽.槽字节长度)
    };
}

