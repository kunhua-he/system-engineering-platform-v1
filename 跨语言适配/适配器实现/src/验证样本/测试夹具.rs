// 纯计算夹具（图任务测试用）
//
// 图任务要「后一个节点吃前一个节点的输出」，需要一条**入参与返回同一类型**的能力。
// 契约里只有底座命令 0（入参空槽、返回引用），撑不起依赖边 ⇒ 这里造一份纯计算扩展：
// 加一 / 加法 / 慢加一，全部只在整数上算，不碰文件、不碰网络、不碰模型。
// ════════════════════════════════════════════════════════════════════════════

/// 读第 `位次` 个入参槽的整数值（个数不足给 0，不 panic）。
///
/// # Safety
///
/// `参数个数` 与 `参数表` 由调用契约保证：个数 > 位次 时第 `位次` 项可读。
unsafe fn 整数入参(参数个数: u32, 参数表: *const 数据槽, 位次: u32) -> u64 {
    if 位次 >= 参数个数 || 参数表.is_null() {
        return 0;
    }
    // SAFETY: 位次 < 个数 且 参数表 非空 ⇒ 该槽可读。
    unsafe { *参数表.add(位次 as usize) }.槽值
}

/// 写回一个整数值槽。
///
/// # Safety
///
/// `返回槽` 由调用契约保证可写（非空）。
unsafe fn 写整数(返回槽: *mut 数据槽, 值: u64) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 非空即由调用契约保证可写。
    unsafe {
        *返回槽 = 数据槽::内联槽(v1_contract::声明数据::类型标签_0001, 值, 0)
    };
}

unsafe extern "C-unwind" fn 夹具加一(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    // SAFETY: 入参读数与写回都按调用契约的前提出牌。
    let 值 = unsafe { 整数入参(参数个数, 参数表, 0) };
    unsafe { 写整数(返回槽, 值 + 1) };
}

unsafe extern "C-unwind" fn 夹具加法(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    // SAFETY: 同上。
    let 左值 = unsafe { 整数入参(参数个数, 参数表, 0) };
    // SAFETY: 同上。
    let 右值 = unsafe { 整数入参(参数个数, 参数表, 1) };
    unsafe { 写整数(返回槽, 左值 + 右值) };
}

/// 慢加一：先停 400 毫秒再算 —— 给「提交后立刻查询必须是非终态」「取消只标执行中节点」两条
/// 判据一个稳定的观察窗（不靠运气抢时序）。
unsafe extern "C-unwind" fn 夹具慢加一(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    std::thread::sleep(std::time::Duration::from_millis(400));
    // SAFETY: 同上。
    let 值 = unsafe { 整数入参(参数个数, 参数表, 0) };
    unsafe { 写整数(返回槽, 值 + 1) }
}

/// 执行计数器：桶 → 该桶已被真执行过的次数。
///
/// 为什么要有它：判「取消把没开始的节点真挡住了」不能只看阶段 —— 阶段是视图，
/// 执行次数是事实。入参「加数」在这里当**桶号**用，调用方按桶分账（测试并行跑时
/// 桶号互不相同即互不干扰）。计数只加在叶子执行里，`装配层` 造不出来。
static 计数表: std::sync::Mutex<Vec<u64>> = std::sync::Mutex::new(Vec::new());

/// 读某桶的执行次数（没执行过 = 0）。
pub(crate) fn 计数读数(桶: usize) -> u64 {
    let 表 = 计数表.lock().unwrap_or_else(|中毒| 中毒.into_inner());
    表.get(桶).copied().unwrap_or(0)
}

/// 夹具计数：入参「加数」= 桶号；该桶 +1 后把次数当返回值写回。
unsafe extern "C-unwind" fn 夹具计数(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    // SAFETY: 同 `夹具加一`。
    let 桶 = unsafe { 整数入参(参数个数, 参数表, 0) } as usize;
    let 次数 = {
        let mut 表 = 计数表.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        if 表.len() <= 桶 {
            表.resize(桶 + 1, 0);
        }
        表[桶] = 表[桶].saturating_add(1);
        表[桶]
    };
    unsafe { 写整数(返回槽, 次数) }
}

/// 夹具拒算：**必定失败**的纯计算叶子 —— 按平台口径把业务失败写在**返回槽**里
/// （`类型标签 = 错误`、`值 = 4 位码`），协议层仍是「成功」。
///
/// 为什么要有它：真实扩展就是这样报失败的（如 `6110` 的 6102、`3113` 的 3001），
/// 而「转发成功 + 错误槽」这一形状正是调用方最容易记成成功的地方 —— 图任务的失败传播
/// 与失败隔离要靠它钉死，不能只靠「执行崩溃」那一路。
fn 写错误槽(返回槽: *mut 数据槽, 码: u32) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 非空即由调用契约保证可写。
    unsafe {
        *返回槽 = 数据槽::内联槽(v1_contract::声明数据::类型标签_4294967295, u64::from(码), 0)
    };
}

unsafe extern "C-unwind" fn 夹具拒算(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    let _ = unsafe { 整数入参(参数个数, 参数表, 0) };
    写错误槽(返回槽, 夹具拒算码);
}

