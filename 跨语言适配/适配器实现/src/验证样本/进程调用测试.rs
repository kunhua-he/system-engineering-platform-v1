//! 进程调用测试 —— 子进程执行路的**验收读数**（整文件即测试）。
//!
//! 验收行原文：「杀能力子进程后调用得结构化 `0034`（不是 panic）；
//! 同一条契约在进程内 / 跨进程下错误码逐字一致」。本件就是那两句话的读数。
//!
//! # 对端是一个**真子进程**，不是 mock
//!
//! 测试起的是一个真 `sh`（拿它当能力进程），走真 `UnixStream`、真帧、真协议。
//! 用一个真 shell 当对端是有意的：本腿要验的是**载体**（进程没了怎么办），
//! mock 一个「假装崩了」的对端恰好验不到载体 —— 而载体才是本腿交付的东西。

