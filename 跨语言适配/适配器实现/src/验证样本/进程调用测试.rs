#[test]
fn 同域事务排队计入总预算() {
    let (宿主端, 对端) = UnixStream::pair().unwrap();
    let mut 域表 = 跨进程域表::创建(进程池配置::default());
    let 标识 = 造标识();
    域表.登记已连域(标识.clone(), 宿主端).unwrap();
    let 句柄 = 域表.取句柄(&标识).unwrap();
    let 预算 = 调用帧预算::创建(Instant::now() + Duration::from_millis(200)).unwrap();
    let 事务守卫 = 句柄.锁事务(&预算).unwrap();
    let 排队预算 = 调用帧预算::创建(Instant::now() + Duration::from_millis(30)).unwrap();
    assert!(matches!(句柄.锁事务(&排队预算), Err(进程池错误::预算耗尽)));
    drop(事务守卫);
    assert!(句柄.锁事务(&预算).is_ok());
    drop(对端);
}

/// 一个**真应答**的对端：在另一条线程上按协议回两帧（通知回执 + 调用结果）。
///
/// 它拿到宿主端那条 `UnixStream` 后：收通知帧答回执、收调用帧答一个内联槽
/// （值 = 调用方给的回值）。宿主侧就能断言「真往返拿到了值」。
fn 起应答环(宿主端: UnixStream, 回值: u64) -> thread::JoinHandle<()> {
    let mut 对端 = 宿主端;
    thread::spawn(move || {
        let Ok(mut 预算) = 调用帧预算::创建(Instant::now() + Duration::from_millis(1500)) else {
            return;
        };
        // 第一条：装载初始化重放（通知帧）。答它的回执 —— 重放路径要收得到。
        if let Ok(收到帧) = 接收帧(&mut 对端, NonZeroU64::new(1).unwrap(), &mut 预算) {
            let 回执 = 消息帧 {
                消息类型: 消息类别::通知回执,
                请求标识: 收到帧.请求标识,
                载荷: Vec::new(),
            };
            let _ = 发送帧(&mut 对端, &回执, &mut 预算);
        }
        // 第二条：真调用。解出请求头（证明过的是同一份线协议），再回一个值槽。
        let Ok(调用帧) = 接收帧(&mut 对端, NonZeroU64::new(2).unwrap(), &mut 预算) else {
            return;
        };
        if 解码调用请求(&调用帧.载荷).is_err() {
            return;
        }
        let 回槽 = 数据槽::内联槽(类型标签::构造(1), 回值, 0);
        let Ok(载荷) = 编码调用结果(协议结果::成功, &回槽) else {
            return;
        };
        let 回帧 = 消息帧 { 消息类型: 消息类别::调用结果, 请求标识: 调用帧.请求标识, 载荷 };
        let _ = 发送帧(&mut 对端, &回帧, &mut 预算);
    })
}

#[test]
fn 跨进程往返_真收到回值() {
    // 对端不是拉起的子进程，而是本进程内的一条线程 —— 它证明的是「送一调用」这条路
    // （编码 → 帧 → 收帧 → 解码）真能往返；进程拉起那一段由进程池测试覆盖。
    let (宿主端, 对端) = UnixStream::pair().unwrap();
    let 等着 = 起应答环(对端, 6161);
    let mut 域表 = 跨进程域表::创建(进程池配置::default());
    let 标识 = 造标识();
    域表.登记已连域(标识.clone(), 宿主端).unwrap();
    let 回值 = 域表.送一调用(&标识, 1101, &[数据槽::空槽()]);
    let _ = 等着.join();
    match 回值 {
        Ok(槽体) => {
            assert_eq!(槽体.槽值, 6161, "必须收到对端真回的那个值，不是兜底值");
            assert_eq!(槽体.类型标签.取号值(), 1);
        }
        Err(码值) => panic!("这条路必须能往返；拿到了错误码 {码值}"),
    }
}

/// 一条**慢应答**环：收下调用后先睡一会儿再回结果。
///
/// 用它造「一个慢域」：宿主侧真发出调用后卡在收帧上；同一条线程里对健康域发调用，
/// 若域表锁被慢域持着，健康域就会被拖到慢域醒来 —— 那就是本测试要拒的旧行为。
fn 起慢应答环(宿主端: UnixStream, 回值: u64, 拖延: Duration) -> thread::JoinHandle<()> {
    let mut 对端 = 宿主端;
    thread::spawn(move || {
        let Ok(mut 预算) = 调用帧预算::创建(Instant::now() + Duration::from_millis(3000)) else {
            return;
        };
        if let Ok(收到帧) = 接收任意帧(&mut 对端, &mut 预算) {
            let 回执 = 消息帧 {
                消息类型: 消息类别::通知回执,
                请求标识: 收到帧.请求标识,
                载荷: Vec::new(),
            };
            let _ = 发送帧(&mut 对端, &回执, &mut 预算);
        }
        if let Ok(调用帧) = 接收任意帧(&mut 对端, &mut 预算) {
            thread::sleep(拖延);
            let 回槽 = 数据槽::内联槽(类型标签::构造(1), 回值, 0);
            if let Ok(载荷) = 编码调用结果(协议结果::成功, &回槽) {
                let 回帧 = 消息帧 { 消息类型: 消息类别::调用结果, 请求标识: 调用帧.请求标识, 载荷 };
                let _ = 发送帧(&mut 对端, &回帧, &mut 预算);
            }
        }
    })
}

/// 一条**快应答**环：收到调用立即回（健康域）。
fn 起快应答环(宿主端: UnixStream, 回值: u64) -> thread::JoinHandle<()> {
    起慢应答环(宿主端, 回值, Duration::from_millis(0))
}

#[test]
fn 慢域不阻塞健康域_锁收窄验收() {
    // ★ 冻结件 §五 验收行：一个慢域 + 一个健康域同时调用，健康域不被拖住。
    //
    // 现场：慢域的对端拖延 800 ms；健康域立即答。若域表锁被慢域持着（旧行为），
    // 健康域的调用会排到慢域之后 ⇒ 耗时 > 800 ms。收窄后健康域应远早于慢域完成。
    let (慢宿主端, 慢对端) = UnixStream::pair().unwrap();
    let (快宿主端, 快对端) = UnixStream::pair().unwrap();
    let 慢等 = 起慢应答环(慢对端, 1111, Duration::from_millis(800));
    let 快等 = 起快应答环(快对端, 2222);
    let mut 域表本体 = 跨进程域表::创建(进程池配置::default());
    let 慢标识 = 执行域标识 {
        适配器实例号: 7, 扩展标识串: String::from("扩展慢"), 制品版本: (1, 0, 0),
    };
    let 快标识 = 执行域标识 {
        适配器实例号: 7, 扩展标识串: String::from("扩展快"), 制品版本: (1, 0, 0),
    };
    域表本体.登记已连域(慢标识.clone(), 慢宿主端).unwrap();
    域表本体.登记已连域(快标识.clone(), 快宿主端).unwrap();
    let 域表 = std::sync::Arc::new(域表本体);
    // 慢域先发（它的收发在本域那把锁里等）。
    let 慢域表 = std::sync::Arc::clone(&域表);
    let 慢标识副本 = 慢标识.clone();
    let 慢任务 = thread::spawn(move || {
        let 开始 = Instant::now();
        let 读数 = 慢域表.送一调用(&慢标识副本, 1101, &[数据槽::空槽()]);
        (读数, 开始.elapsed())
    });
    // 健康域稍后发：它必须在慢域醒来之前回来。
    thread::sleep(Duration::from_millis(80));
    let 快开始 = Instant::now();
    let 快读数 = 域表.送一调用(&快标识, 1101, &[数据槽::空槽()]);
    let 快耗时 = 快开始.elapsed();
    let (慢读数, 慢耗时) = 慢任务.join().unwrap();
    let _ = 慢等.join();
    let _ = 快等.join();
    assert_eq!(快读数.unwrap().槽值, 2222, "健康域必须拿到本域的回值");
    assert_eq!(慢读数.unwrap().槽值, 1111, "慢域也拿到本域的回值");
    assert!(快耗时 < Duration::from_millis(500), "健康域被拖住了：耗时 {快耗时:?}（慢域睡 800 ms）");
    assert!(慢耗时 >= Duration::from_millis(700), "慢域本就该慢：{慢耗时:?}");
}

