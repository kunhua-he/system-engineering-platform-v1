/// 从源码文本里抽**导出属性**里的符号名。
///
/// 口径与一键验证一致：只认 `#[unsafe(export_name = "…")]` / `#[export_name = "…")]`
/// 这种**属性**形（光写 `extern "C"` 会被 mangled、不算导出），并先**去行注释**
/// （注释里提一句 `export_name = "…"` 不算导出）。
fn 扫导出名(源文本: &str) -> Vec<String> {
    let 净文本 = 去行注释(源文本);
    let 格式器 = ["#[unsafe(export_name = \"", "#[export_name = \""];
    let mut 输出缓冲 = Vec::new();
    let mut 剩余文本 = 净文本.as_str();
    loop {
        let mut 最优位 = usize::MAX;
        let mut 最优前 = "";
        for 一个前缀 in 格式器 {
            if let Some(字节位置) = 剩余文本.find(一个前缀) && 字节位置 < 最优位 {
                最优位 = 字节位置;
                最优前 = 一个前缀;
            }
        }
        if 最优位 == usize::MAX {
            break;
        }
        let 尾部 = &剩余文本[最优位 + 最优前.len()..];
        let Some(闭引号位) = 尾部.find('"') else { break };
        输出缓冲.push(尾部[..闭引号位].to_owned());
        剩余文本 = &尾部[闭引号位 + 1..];
    }
    输出缓冲
}

/// 去行注释（长度无关；本文件只拿它避免「注释里的 `export_name`」被当导出）。
fn 去行注释(源文本: &str) -> String {
    let mut 输出缓冲 = String::with_capacity(源文本.len());
    for 源码行 in 源文本.lines() {
        match 源码行.find("//") {
            Some(字节位置) => 输出缓冲.push_str(&源码行[..字节位置]),
            None => 输出缓冲.push_str(源码行),
        }
        输出缓冲.push('\n');
    }
    输出缓冲
}

