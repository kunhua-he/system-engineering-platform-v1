// ════════════════════════════════════════════════════════════════════════════
// 泄漏读数：用**计数全局分配器**量「取 N 次之后活字节净增长」
//
// 读数命令（同一把尺；`--test-threads=1` 免得别的用例的分配混进来）：
//     cargo test -p v1-adapter --lib 读数_ -- --ignored --nocapture --test-threads=1
//
// 一个用例里量两个方向（对照着看才有意义）：
//   · 不归还：取 N 次、一次都不还 ⇒ 净增长 ≈ N × 单份字节（**泄漏**）
//   · 按协议归还：取 N 次、每次当即还 ⇒ 净增长 ≈ 0（**不涨**）
//
// 反向样本（把修复回退：`平台_取接口描述` 改回 `Box::leak`、`平台_释放接口描述` 改空操作）
// ⇒ 「按协议归还」那一行**又涨**。
//
// 计数分配器只在本测试二进制里生效（`#[global_allocator]` 是 crate 级，不进生产库）。
// ════════════════════════════════════════════════════════════════════════════

use core::alloc::{GlobalAlloc, Layout};
use core::sync::atomic::{AtomicUsize, Ordering};
use std::alloc::System;

/// 活字节（alloc 加、dealloc 减）。**只在测试二进制里**，不是生产状态。
static 泄漏读数_活字节: AtomicUsize = AtomicUsize::new(0);

/// 计数分配器要**盯住**的那一个地址（0 = 不盯）。
///
/// 用途：审计发现 1 的**身份证** —— 证「指定返回地址真的发生了 free」，而不是只证「槽空了」。
/// 旧行为（只清槽）下这条恒为 0，根因即于此可见。
static 泄漏读数_盯住地址: AtomicUsize = AtomicUsize::new(0);

/// 被盯地址上的 `dealloc` 命中数（命中即 +1）。
static 泄漏读数_命中次数: AtomicUsize = AtomicUsize::new(0);

struct 泄漏读数_计数分配器;

unsafe impl GlobalAlloc for 泄漏读数_计数分配器 {
    unsafe fn alloc(&self, 内存布局: Layout) -> *mut u8 {
        let 指针 = unsafe { System.alloc(内存布局) };
        if !指针.is_null() {
            泄漏读数_活字节.fetch_add(内存布局.size(), Ordering::SeqCst);
        }
        指针
    }
    unsafe fn dealloc(&self, 指针: *mut u8, 内存布局: Layout) {
        if 指针 as usize != 0 && 指针 as usize == 泄漏读数_盯住地址.load(Ordering::SeqCst) {
            泄漏读数_命中次数.fetch_add(1, Ordering::SeqCst);
        }
        unsafe { System.dealloc(指针, 内存布局) };
        泄漏读数_活字节.fetch_sub(内存布局.size(), Ordering::SeqCst);
    }
}

#[global_allocator]
static 泄漏读数_分配器: 泄漏读数_计数分配器 = 泄漏读数_计数分配器;

fn 泄漏读数_读活字节() -> usize {
    泄漏读数_活字节.load(Ordering::SeqCst)
}

/// 让计数分配器盯住 `堆地址`，并把命中数清零。
///
/// 只在**单用例内**用：全局地址复用可能让别的用例的分配/释放也落在同一地址上，
/// 故本腿只在该地址**还活着**（负向）或**由本用例泄露、不会被别处释放**（正向）时断言。
pub(crate) fn 泄漏读数_盯住(堆地址: usize) {
    泄漏读数_命中次数.store(0, Ordering::SeqCst);
    泄漏读数_盯住地址.store(堆地址, Ordering::SeqCst);
}

/// 读被盯地址上的 `dealloc` 命中数。
pub(crate) fn 泄漏读数_命中() -> usize {
    泄漏读数_命中次数.load(Ordering::SeqCst)
}

/// 一次「取接口描述」拿到的字节数（顺手归还，不留账）。
fn 泄漏读数_单份字节() -> usize {
    let mut 槽字节长度: u32 = 0;
    // SAFETY: 长 可写；返回的缓冲随即归还。
    let 首字节 = unsafe { 平台_取接口描述(&mut 槽字节长度) };
    assert!(!首字节.is_null(), "平台自身的声明必然载得进来 ⇒ 不许给空指针");
    assert!(槽字节长度 > 0, "空集不算通过：一份描述必须非空");
    // SAFETY: 首/长 是上面那次调用交出的一对，尚未归还。
    unsafe { 平台_释放接口描述(首字节, 槽字节长度) };
    槽字节长度 as usize
}

/// 读数：不归还 ⇒ 活字节随 N 线性增长；按协议归还 ⇒ 不涨。
///
/// **`#[ignore]` 的理由**：本用例量的是**进程级**活字节，别的用例并行跑时它们的分配会混进来
/// ⇒ 必须单跑。读数命令见文件末那一段注释（`--ignored --nocapture --test-threads=1`）。
#[ignore = "读数用例：量进程级活字节，必须 --test-threads=1 单跑（见文件末注释）"]
#[test]
fn 读数_取多次_不归还涨_归还平() {
    const 重复轮数: usize = 2000;
    let 单份 = 泄漏读数_单份字节();

    // ── 方向一：不归还（**修前/回退** 的读数） ──
    let 不归还前基线 = 泄漏读数_读活字节();
    for _ in 0..重复轮数 {
        let mut 槽字节长度: u32 = 0;
        // SAFETY: 长 可写；本样本**故意不归还**（就是要量泄漏）。
        let 首字节 = unsafe { 平台_取接口描述(&mut 槽字节长度) };
        assert!(!首字节.is_null());
        core::hint::black_box(首字节);
    }
    let 不归还净增 = 泄漏读数_读活字节().saturating_sub(不归还前基线);
    println!("[读数] 取 {重复轮数} 次不归还：单份 {单份} 字节 · 活字节净增 {不归还净增} 字节（≈ {重复轮数}×{单份}）");
    assert!(
        不归还净增 >= 重复轮数 * 单份,
        "不归还就必须涨：实测 {不归还净增}，期望 ≥ {}（N × 单份）",
        重复轮数 * 单份
    );

    // ── 方向二：按协议归还（**修后** 的读数） ──
    let 归还前基线 = 泄漏读数_读活字节();
    for _ in 0..重复轮数 {
        let mut 槽字节长度: u32 = 0;
        // SAFETY: 长 可写；返回的缓冲当即归还。
        let 首字节 = unsafe { 平台_取接口描述(&mut 槽字节长度) };
        assert!(!首字节.is_null());
        // SAFETY: 首/长 是上面那次调用交出的一对，尚未归还。
        unsafe { 平台_释放接口描述(首字节, 槽字节长度) };
    }
    let 归还净增 = 泄漏读数_读活字节().saturating_sub(归还前基线);
    println!("[读数] 取 {重复轮数} 次按协议归还：单份 {单份} 字节 · 活字节净增 {归还净增} 字节");
    assert!(
        归还净增 < 单份,
        "按协议归还就不该涨（容差 < 一份）：实测 {归还净增}，单份 {单份}"
    );
}

// ════════════════════════════════════════════════════════════════════════════
// 判据：入参上界 · 对齐（口子 M2 · C ABI 全信任调用方）
//
// 导出面原先只有空指针检查，**没有上界、没有对齐** ⇒ 调用方给的个数与指针落位一路被当成
// 可信。本组把两件事钉住：越界即拒 · 未对齐即拒（都是 fail-closed 回错误码）。
// 上界**只引用既有常量**（`线协议::单次调用槽数上限`，与过线那一侧同一个数），不另写数。
// ════════════════════════════════════════════════════════════════════════════

// 上界源 = 线协议过线那一侧的同一条上界（本件不另写数）。
use crate::线协议::单次调用槽数上限;

/// 造一个**未对齐**的槽指针：拿一块按 8 对齐的真缓冲，把指针**抬升 1 字节**。
///
/// 为什么用真缓冲而不是硬编一个地址：真缓冲保证「抬升后的地址落在可读内存里」⇒ 样本只在
/// 边界层的对齐判据上被拒，不是靠一个野地址取胜。
fn 造错位槽指针(缓冲: &mut [u64; 8]) -> *mut 数据槽 {
    // SAFETY: 缓冲 是活的 `[u64; 8]`（对齐 8）⇒ 抬升 1 字节后仍落在它内部，可读可写。
    unsafe { (缓冲.as_mut_ptr() as *mut u8).add(1) as *mut 数据槽 }
}

/// 判据：**越界入参被拒**（上界 = `单次调用槽数上限`）。
///
/// 反向样本（**修前必红**）：修前本边界没有上界，`参数个数` 一路交给调度层 —— 取一个
/// **不存在的号**，那条路给「协议层成功 + 返回槽里的业务错误码」；修后上界在**边界层**
/// 当场拒 ⇒ 「协议层参数不合法 + 返回槽置空」。两条路**读数不同形**，判据才分得出修没修。
///
/// 参数表给**真实可读**的 `上界 + 1` 个槽（不是悬垂指针）：修前那条路会真读它们 ⇒
/// 本样本在修前也是安全的，不为换一条红去制造 UB。
#[test]
fn 调用_越界参数个数被拒() {
    let 越界个数 = 单次调用槽数上限 + 1;
    let 越界槽表 = vec![数据槽::空槽(); 越界个数];
    let mut 越界返回槽 = 数据槽::空槽();
    // SAFETY: 越界槽表 真实有 越界个数 个可读槽；越界返回槽 可写。
    let 越界返回码 =
        unsafe { 平台_调用(9999, 越界个数 as u32, 越界槽表.as_ptr(), &mut 越界返回槽) };
    assert_eq!(越界返回码, 协议结果::参数不合法, "越界入参必须在边界层被拒");
    assert!(越界返回槽.是否空(), "拒了就要置空返回槽，不把半成品交出去");

    // ── 反向样本：**上界内**必须照常放行（同号值，只把个数收到上界内）──
    // 判据非空转：上一条「拒」若对一切入参都拒，这一段就会跟着红。
    let mut 上界内返回槽 = 数据槽::空槽();
    // SAFETY: 个数 0 + 空参数表（合法形状）；上界内返回槽 可写。
    let 上界内返回码 = unsafe { 平台_调用(9999, 0, core::ptr::null(), &mut 上界内返回槽) };
    assert_eq!(上界内返回码, 协议结果::成功, "上界内不许被上界判据拦下");
    assert!(!上界内返回槽.是否空(), "未命中的业务失败要给可读的结构化错误码");
    assert_eq!(
        上界内返回槽.槽值,
        u64::from(声明数据::错误码_0001.取号值()),
        "「提供者未载入」的 4 位码"
    );
}

/// 判据：**未对齐指针被拒**（入参指针落错位 ⇒ fail-closed，不碰内存）。
///
/// 与上一条的分工：上一条管「个数」，本条管「落位」。两条都必须在**边界层**当场拦下 ——
/// 放到下游就是拿未对齐地址去解引用（UB）。
///
/// **诚实登记**：本样本断言的是**修后**的读数。修前那条路会对未对齐指针直接解引用
/// （未定义行为，可能段错误），故它**不作为「修前必红」的可跑反证** —— 那条红由
/// `调用_越界参数个数被拒` 承担（那条修前安全且可跑）。本条的判据非空转由上面那条
/// 「上界内照常放行」的正向样本共同钉住。
#[test]
fn 调用_未对齐指针被拒() {
    let mut 对齐缓冲 = [0u64; 8];
    let 错位参数表 = 造错位槽指针(&mut 对齐缓冲);
    let mut 错位返回槽 = 数据槽::空槽();
    // SAFETY: 错位参数表 落在活缓冲内部（可读），但落位未对齐；本函数按对齐判据当场拒，
    // 不解引用它。错位返回槽 可写且已对齐。
    let 错位返回码 = unsafe { 平台_调用(9999, 1, 错位参数表, &mut 错位返回槽) };
    assert_eq!(错位返回码, 协议结果::参数不合法, "未对齐的参数表必须在边界层被拒");
    assert!(错位返回槽.是否空(), "拒了就要置空返回槽");

    // 返回槽落错位：同样当场拒（**不写**那个未对齐地址）。
    let mut 对齐缓冲 = [0u64; 8];
    let 错位返回槽指针 = 造错位槽指针(&mut 对齐缓冲);
    // SAFETY: 个数 0 + 空参数表；错位返回槽指针 未对齐 ⇒ 本函数按对齐判据当场拒，不写它。
    let 槽错位码 = unsafe { 平台_调用(9999, 0, core::ptr::null(), 错位返回槽指针) };
    assert_eq!(槽错位码, 协议结果::参数不合法, "未对齐的返回槽必须在边界层被拒");
}

/// 判据：描述口与释放口**未对齐指针不崩**（fail-closed：给空指针 / 什么都不做）。
///
/// 两个口都是「没有报错通道」的形状（`平台_释放值` 返回 `void`、`平台_取接口描述` 只能靠
/// 空指针表达拒绝）⇒ fail-closed 的读数就是「不崩、不写内存、不交出缓冲」。
#[test]
fn 描述与释放口_未对齐指针被拒() {
    let mut 对齐缓冲 = [0u64; 8];
    let 错位槽指针 = 造错位槽指针(&mut 对齐缓冲);
    // SAFETY: 错位槽指针 未对齐；本函数按对齐判据当场返回，不碰内存。
    unsafe { 平台_释放值(错位槽指针) };

    let mut 对齐缓冲 = [0u64; 8];
    let 错位长度指针 = 造错位槽指针(&mut 对齐缓冲) as *mut u32;
    // SAFETY: 错位长度指针 未对齐；本函数按对齐判据当场返回空指针，不写内存。
    let 输出缓冲 = unsafe { 平台_取接口描述(错位长度指针) };
    assert!(输出缓冲.is_null(), "长度指针落错位 ⇒ 不交出缓冲（无法安全报告长度）");
}
