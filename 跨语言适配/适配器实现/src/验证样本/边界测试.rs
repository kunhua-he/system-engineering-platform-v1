/// 判据：长度出参**正确**（等于 JSON 的字节数），且与 Rust 级读数逐字节相同。
#[test]
fn 取接口描述_长度出参等于字节数() {
    let mut 槽字节长度: u32 = 0;
    // SAFETY: 长 是本函数里的可写 u32（`平台_取接口描述` 的 Safety 契约）。
    let 首字节 = unsafe { 平台_取接口描述(&mut 槽字节长度) };
    assert!(!首字节.is_null(), "有接口可描述 ⇒ 不许给空指针");
    assert!(槽字节长度 > 0, "空集不算通过：描述必须非空");

    // 逐字节读到 NUL：长度出参必须真是这段字节的长度，不是别的数。
    let mut 已读字节数 = 0usize;
    loop {
        // SAFETY: 首 指向本函数刚拿到、尚未归还的缓冲（`边界面.rs` 文件头「所有权」），按协议 NUL 结尾。
        let 字符表 = unsafe { *首字节.add(已读字节数) };
        if 字符表 == 0 {
            break;
        }
        已读字节数 += 1;
    }
    assert_eq!(已读字节数, 槽字节长度 as usize, "长度出参必须等于 JSON 的字节数");

    // 与 Rust 级同源读数比对（导出符号交出的就是同一份描述的字节）。
    let 边界 = 对外边界::构造(&[v1_loader::底座声明()]).expect("底座自身的声明必须载得进来");
    let 期望 = 边界.取接口描述();
    assert_eq!(槽字节长度 as usize, 期望.len(), "长度出参与 Rust 级读数必须同数");
    // SAFETY: 同上（首 指向 长 字节可读的缓冲）。
    let 字节 = unsafe { core::slice::from_raw_parts(首字节 as *const u8, 槽字节长度 as usize) };
    assert_eq!(字节, 期望.as_bytes(), "导出符号交出的字节必须与 Rust 级读数逐字节相同");

    // ── 反向样本：判据对长度敏感 —— 少报 1 字节，比对必挂 ──
    assert_ne!(
        &字节[..字节.len() - 1],
        期望.as_bytes(),
        "反向样本：少一字节就不相等 ⇒ 「长度正确」这条判据不是空转"
    );

    // 用完归还（缓冲归调用方，见文件头「所有权」）。
    // SAFETY: 首/长 是上面那次 `平台_取接口描述` 交出的一对，尚未归还。
    unsafe { 平台_释放接口描述(首字节, 槽字节长度) };
}

