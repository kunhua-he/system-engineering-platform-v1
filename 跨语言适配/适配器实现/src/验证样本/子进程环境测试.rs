//! 子进程环境测试 —— 收敛项 G07 的**验收读数**（整文件即测试）。
//!
//! 本件盯的是那三条口径能不能被验出来：**默认不继承**（子进程拿空环境）、
//! **白名单只透传点名的**、**秘密胜过父环境同名**，以及**三类危险动作未授权即拒**。
//!
//! # 对端是一个**真子进程**，不是 mock
//!
//! 拉的是真 `/bin/sh`，它把自身环境打到标准输出（`stdout` 已被接成本腿那条 `UnixStream`）——
//! 本腿把通道读回来，看的就是**子进程真实拿到的那份环境**。
//! mock 一个「假装没继承」的子进程恰好验不到本件要验的东西。
//!
//! # 探针用 `PATH` / `HOME` 这两个父进程必有的变量
//!
//! 一是它们一定存在（不依赖另造变量），二是避开 `set_var` 的进程级竞争
//! （多条样本并行跑时互相污染）。

use std::io::Read;
use std::os::unix::net::UnixStream;

use crate::进程池::{全放行名, 生成进程按前提, 危险动作, 子进程前提, 进程池错误};

/// 打环境进程：`sh` 把自身环境逐行打到 stdout（= 本腿那条通道）。
///
/// `env` 用**绝对路径**：默认前提会给子进程空环境，那时它没有 `PATH` 可查，
/// 写裸 `env` 会因找不到命令而什么都打不出来（样本就验不到东西了）。
fn 打环境进程() -> (&'static str, Vec<String>) {
    ("/bin/sh", vec![String::from("-c"), String::from("/usr/bin/env")])
}

/// 读通道文本：把子进程写进通道的东西收完（它写完自行退出）。
fn 读通道文本(子进程通道: &mut UnixStream) -> String {
    let mut 环境文本 = String::new();
    let _ = 子进程通道.read_to_string(&mut 环境文本);
    环境文本
}

/// 拉一个子进程，把它拿到的环境读回来。
fn 取子进程环境(前提: &子进程前提) -> String {
    let (程序, 启动参数) = 打环境进程();
    let (mut 子进程, mut 子进程通道) = 生成进程按前提(程序, &启动参数, 前提).unwrap();
    let 环境文本 = 读通道文本(&mut 子进程通道);
    let _ = 子进程.wait();
    环境文本
}

#[test]
fn 默认前提给子进程空环境() {
    // ★ 修前必红：旧 `生成进程` 用 `Command::new` 起子进程、**不 `env_clear`**
    // ⇒ 子进程继承父进程全环境。本样本拉一个默认前提的子进程，看父进程那两个
    // 「一定有」的变量有没有漏进去 —— 漏了就是那条旧行为还在。
    let 环境文本 = 取子进程环境(&子进程前提::默认前提());
    assert!(!环境文本.contains("PATH="), "默认前提不该透传 PATH，实得环境：\n{环境文本}");
    assert!(!环境文本.contains("HOME="), "默认前提不该透传 HOME，实得环境：\n{环境文本}");
}

#[test]
fn 白名单透传指定变量() {
    // 白名单是「**允许**透传」：点名 PATH 就只拿 PATH，没点名的 HOME 照旧不给。
    let mut 前提 = 子进程前提::默认前提();
    前提.收编白名单("PATH");
    let 环境文本 = 取子进程环境(&前提);
    assert!(环境文本.contains("PATH="), "点名了 PATH 就该透传，实得环境：\n{环境文本}");
    assert!(!环境文本.contains("HOME="), "没点名的 HOME 不该透传，实得环境：\n{环境文本}");
    assert_eq!(前提.白名单条数(), 1);
}

#[test]
fn 秘密胜过父环境同名() {
    // 秘密是**显式绑定的那一份**，不是「碰巧父环境里也有」的那一份：
    // 同一个名字既在白名单又在秘密里 ⇒ 子进程拿到的是秘密值。
    let mut 前提 = 子进程前提::默认前提();
    前提.收编白名单("PATH");
    前提.收编秘密("PATH", "/秘密路径");
    前提.授权收编(危险动作::投放秘密);
    let 环境文本 = 取子进程环境(&前提);
    assert!(环境文本.contains("PATH=/秘密路径"), "秘密值必须胜过父环境同名值，实得环境：\n{环境文本}");
    assert_eq!(前提.秘密条数(), 1);
}

#[test]
fn 未授权派生不拉起进程() {
    // ★ 验收口径「**一个进程都不拉**」：不给 `派生进程` 授权 ⇒ 结构化拒，
    // 且判定在 `spawn` 之前（下面这个调用若返回 `Ok` 就说明真拉起来了）。
    let 前提 = 子进程前提 { 白名单: Vec::new(), 秘密: Vec::new(), 授权: Vec::new() };
    let (程序, 启动参数) = 打环境进程();
    assert!(
        matches!(生成进程按前提(程序, &启动参数, &前提), Err(进程池错误::未授权派生进程)),
        "未授权派生必须结构化拒，不许拉起进程"
    );
}

#[test]
fn 未授权继承全环境() {
    // 白名单里写了通配名却没放行 `继承全环境` ⇒ 拒。**不静默收窄成「只传白名单里的」**：
    // 那会让调用方以为全环境已生效。
    let mut 前提 = 子进程前提::默认前提();
    前提.收编白名单(全放行名);
    let (程序, 启动参数) = 打环境进程();
    assert!(
        matches!(生成进程按前提(程序, &启动参数, &前提), Err(进程池错误::未授权继承全环境)),
        "要全放行却没授权 ⇒ 必须结构化拒，不许静默收窄"
    );
}

#[test]
fn 未授权投放秘密() {
    // 带了秘密却没放行 `投放秘密` ⇒ 拒。**不静默丢弃秘密**：
    // 静默丢弃 = 子进程起来却拿不到该拿的凭据，而调用方看到的是一句「拉起来了」。
    let mut 前提 = 子进程前提::默认前提();
    前提.收编秘密("V1_探针秘密", "值");
    let (程序, 启动参数) = 打环境进程();
    assert!(
        matches!(生成进程按前提(程序, &启动参数, &前提), Err(进程池错误::未授权投放秘密)),
        "带秘密却没授权 ⇒ 必须结构化拒，不许静默丢弃"
    );
}

#[test]
fn 全放行授权后子进程拿到父环境() {
    // 正样本：真给了两项授权 ⇒ 子进程拿到父进程那份（本件不是「一律空环境」的死闸）。
    let mut 前提 = 子进程前提::默认前提();
    前提.收编白名单(全放行名);
    前提.授权收编(危险动作::继承全环境);
    let 环境文本 = 取子进程环境(&前提);
    assert!(环境文本.contains("PATH="), "已授权全放行就该拿到 PATH，实得环境：\n{环境文本}");
}

#[test]
fn 前提指纹随前提变() {
    // 指纹是「同域重复登记时判前提变没变」的判据：前提不同 ⇒ 指纹必须不同
    // （否则同域换了环境口径也会被当成「已在」而静默沿用旧进程）。
    let 默认前提 = 子进程前提::默认前提();
    let mut 别的前提 = 子进程前提::默认前提();
    别的前提.收编白名单("PATH");
    assert_ne!(默认前提.前提指纹(), 别的前提.前提指纹(), "白名单变了指纹必须跟着变");
    let 同一份前提 = 子进程前提::默认前提();
    assert_eq!(默认前提.前提指纹(), 同一份前提.前提指纹(), "同内容必须同指纹");
}
