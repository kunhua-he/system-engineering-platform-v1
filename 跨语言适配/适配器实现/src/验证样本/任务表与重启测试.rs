//! 任务表语义与重启对账的判据 —— **整文件即测试**（`lib.rs` 用 `#[cfg(test)] #[path]` 挂进来）。
//!
//! 两件事放在一起是因为它们同属「任务表这个容器的行为」：淘汰、判重、落盘、重启后还能问什么。
//!
//! 与 `图任务测试.rs` 分开的理由是行数硬数（单源文件 ≤800 行），不是关注点不同：
//! 这里验的是「跨进程还能信多少」，那边验的是「图怎么跑」。
//!
//! | 判据 | 落点 |
//! |---|---|
//! | 重启后仍查得到上一个进程的任务（终态原样、不给时刻） | `重启后仍查得到上一个进程的任务` |
//! | 重启后同请求标识仍幂等、新号不与历史号相撞 | `重启后同请求标识仍幂等且号不撞` |
//! | 重启对账：在途任务判失败，不猜成功 | `重启后在途任务报失败` |
//! | 重启后释放真删（再重启也不冒出来） | `重启后释放上个进程的任务` |
//! | **两张图的节点时刻跨任务可比**（零时是进程，不是任务提交） | `两张图的时刻跨任务可比` |
//! | 表满之后新任务不会被这一轮清扫淘汰 | `表满时新任务不会当场被淘汰` |

use std::path::{Path, PathBuf};

use v1_contract::号段;
use v1_dispatch::{调用任务阶段, 调用节点阶段};

use crate::任务对外::{
    任务落盘 as 运行态落盘, 任务选项, 入参值, 图任务节点请求
};
use crate::测试夹具::造计算声明;
use crate::适配器;

const 号段起点: u32 = 1000;

/// 计算声明的适配器（与 `图任务测试.rs` 同一份夹具，各自建一份：两个文件不互相依赖）。
fn 计算适配器() -> 适配器 {
    适配器::装载声明根(&[
        crate::底座声明(),
        造计算声明(号段::构造(号段起点, 号段起点 + 99)),
    ])
    .expect("夹具声明必须载得进来")
}

/// 单节点图：加一。
fn 加一(节点: &str, 值: u64) -> 图任务节点请求 {
    图任务节点请求 {
        节点标识: 节点.to_owned(),
        编号: 号段起点,
        命名值: vec![("加数".to_owned(), 入参值::内联(1, 值, 0))],
        依赖节点: Vec::new(),
        输入引用: Vec::new(),
    }
}

fn 等终态(器: &适配器, 任务标识: u64) -> crate::任务对外::任务快照 {
    器.等待任务(任务标识, std::time::Duration::from_secs(5))
        .expect("任务必须在表里")
}

/// 开一台「同一个落盘、全新进程」的适配器。
fn 重启一遍(路径: &Path) -> 适配器 {
    let mut 器 = 计算适配器();
    器.接上指定落盘(std::sync::Arc::new(运行态落盘::指定路径(
        路径.to_path_buf(),
    )));
    器
}

/// 临时落盘路径（一个判据一个文件，跑完即删）。
fn 落盘路径(名: &str) -> PathBuf {
    std::env::temp_dir().join(format!(
        "图任务_{名}_{}_{}.jsonl",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|时长| 时长.as_nanos())
            .unwrap_or(0)
    ))
}

/// 判据：**换一个进程（新适配器）只靠落盘，仍查得到上一个进程跑完的任务**。
#[test]
fn 重启后仍查得到上一个进程的任务() {
    let 路径 = 落盘路径("重启查得");
    let 前 = 重启一遍(&路径);
    let 号 = 前
        .提交任务图(&[加一("重启节点", 3)], 任务选项::按请求("跨重启请求"))
        .expect("必须受理");
    assert_eq!(等终态(&前, 号).阶段, 调用任务阶段::成功);
    drop(前);

    let 后 = 重启一遍(&路径);
    let 快照 = 后
        .查询任务(号, None)
        .expect("重启后必须还查得到（落盘就是为这个）");
    assert_eq!(快照.阶段, 调用任务阶段::成功, "终态原样带回来");
    assert_eq!(快照.节点读数表.len(), 1);
    assert_eq!(快照.节点读数表[0].节点阶段, 调用节点阶段::成功);
    assert!(
        快照.节点读数表[0].开始微秒.is_none(),
        "跨进程不给时刻：那是实例内单调钟，编一个出来就是假证据"
    );
    let _ = std::fs::remove_file(路径);
}

/// 判据：**重启后同请求标识仍幂等，且新号绝不与历史号相撞**。
#[test]
fn 重启后同请求标识仍幂等且号不撞() {
    let 路径 = 落盘路径("重启幂等");
    let 图 = [加一("重启幂等节点", 11)];
    let mut 前 = 计算适配器();
    前.接上指定落盘(std::sync::Arc::new(运行态落盘::指定路径(
        路径.clone(),
    )));
    let 号 = 前
        .提交任务图(&图, 任务选项::按请求("跨重启幂等"))
        .expect("必须受理");
    assert_eq!(等终态(&前, 号).阶段, 调用任务阶段::成功);
    drop(前);

    let 后 = 重启一遍(&路径);
    let 再次 = 后
        .提交任务图(&图, 任务选项::按请求("跨重启幂等"))
        .expect("重启后同标识同图必须回原任务，不许重跑");
    assert_eq!(再次, 号, "跨重启幂等：回原任务标识");

    let 新号 = 后
        .提交任务图(&图, 任务选项::按请求("跨重启新图"))
        .expect("新请求标识必须受理");
    assert!(
        新号 > 号,
        "重启后发号必须接在历史最大号之后：{新号} 不大于 {号}"
    );
    let _ = 等终态(&后, 新号);
    let _ = std::fs::remove_file(路径);
}

/// 判据：重启时上一个进程还在跑的任务 —— **判未确认，既不猜成功也不猜失败**。
///
/// 这一条以前断言「判失败」，改成未确认的理由：进程消失只证明「没人回报」，
/// 不证明能力没做成（它可能早已跑完、副作用也落了）。状态机只收确认过的东西。
#[test]
fn 重启后在途任务报未确认() {
    let 路径 = 落盘路径("重启对账");
    let 落盘 = 运行态落盘::指定路径(路径.clone());
    落盘.追加(
        9001,
        Some("在途请求"),
        1234,
        调用任务阶段::执行中,
        &[
            ("跑着的".to_owned(), 调用节点阶段::执行中),
            ("没起的".to_owned(), 调用节点阶段::等待依赖),
        ]
        .into_iter()
        .collect(),
    ).unwrap();
    drop(落盘);
    let 后 = 重启一遍(&路径);
    let 快照 = 后.查询任务(9001, None).expect("在途任务重启后也要查得到");
    assert_eq!(
        快照.阶段,
        调用任务阶段::未确认,
        "在途任务重启后只能是未确认：判失败是猜，判成功是伪造"
    );
    // 未知**不写失败读数**：没有失败，就不许摆一份失败出来（那正是把猜测装成事实）。
    assert!(
        快照.错误.is_none(),
        "未确认任务不许带失败读数（那等于说有节点确认失败）"
    );
    let 节点 = |名: &str| {
        快照
            .节点读数表
            .iter()
            .find(|行| 行.节点标识 == 名)
            .map(|行| 行.节点阶段)
    };
    assert_eq!(
        节点("跑着的"),
        Some(调用节点阶段::未知),
        "在跑的那个只能报未知：没有任何回报能证明它做成了或没做成"
    );
    assert_eq!(
        节点("没起的"),
        Some(调用节点阶段::已取消),
        "从未进入执行中 ⇒ 确定没跑 ⇒ 确认取消"
    );
    let _ = std::fs::remove_file(路径);
}

/// 判据：**重启后释放上一个进程的任务 → 真删；再重启一次也不许冒出来**。
#[test]
fn 重启后释放上个进程的任务() {
    let 路径 = 落盘路径("重启释放");
    let 前 = 重启一遍(&路径);
    let 号 = 前
        .提交任务图(&[加一("释放节点", 4)], 任务选项::按请求("跨重启释放"))
        .expect("必须受理");
    assert_eq!(等终态(&前, 号).阶段, 调用任务阶段::成功);
    drop(前);

    let 后 = 重启一遍(&路径);
    assert!(后.查询任务(号, None).is_some(), "先得查得到");
    assert!(
        后.释放任务(号),
        "终态任务必须能释放（哪怕它来自上一个进程）"
    );
    assert!(后.查询任务(号, None).is_none(), "释放后本进程必须查不到");
    drop(后);

    let 再后 = 重启一遍(&路径);
    assert!(
        再后.查询任务(号, None).is_none(),
        "释放必须落盘：再重启一次也不许冒出来"
    );
    let _ = std::fs::remove_file(路径);
}

/// 判据：**两张先后提交的图，节点时刻放在一起能比**。
///
/// 零时若是「本任务提交」，两次提交各自的 `开始微秒` 都从 0 起算，放在一起比出来的结论是假的
/// （第二张图看着总在第一张之前）。零时改成进程之后，后一张的起点必然不早于前一张的终点。
#[test]
fn 两张图的时刻跨任务可比() {
    let 测试适配器 = 计算适配器();
    let 首号 = 测试适配器
        .提交任务图(&[加一("先跑节点", 1)], 任务选项::按请求("先跑"))
        .expect("首图必须受理");
    let 首 = 等终态(&测试适配器, 首号);
    let 次号 = 测试适配器
        .提交任务图(&[加一("后跑节点", 2)], 任务选项::按请求("后跑"))
        .expect("次图必须受理");
    let 次 = 等终态(&测试适配器, 次号);
    for 任务编号 in [首号, 次号] {
        let mut 任务记录表 = 测试适配器.任务表.lock().unwrap();
        let 任务条目 = 任务记录表.取(任务编号).unwrap();
        let 真实偏移 = u64::try_from(任务条目.实例.任务零时().saturating_duration_since(测试适配器.进程零时).as_micros()).unwrap();
        assert_eq!(任务条目.提交微秒, 真实偏移, "公开时刻须精确复用实例零时，不取提交后采样");
    }
    let 首记 = &首.节点读数表[0];
    let 次记 = &次.节点读数表[0];
    let 首次止 = 首记.结束微秒.expect("首图真跑过，必须给结束时刻");
    let 次起 = 次记.开始微秒.expect("次图真跑过，必须给开始时刻");
    assert!(
        次起 >= 首次止,
        "两张图的时刻必须跨任务可比：后图的起点 {次起} 早于前图的终点 {首次止} ⇒ 零时还是本任务提交"
    );
    assert!(
        首记.开始微秒.unwrap_or(0) > 0,
        "零时是进程装载那一刻，首图起点不该是 0"
    );
}

/// 判据：**表满之后刚提交的任务不会被当场清扫掉**。
///
/// 老实现的 `末次访问` 初值是 0、插入时不刷新 ⇒ 刚插进来的任务在淘汰序里是「最老」的，表一满就第一个被扔。症状是「提交回 200 带任务标识，紧接着查询说查不到」，且只在跑久了之后出现。
#[test]
fn 表满时新任务不会当场被淘汰() {
    let 器 = 计算适配器();
    {
        let mut 表 = 器.任务表.lock().expect("任务表锁");
        表.设容量(3);
    }
    /* 先塞满三条并等它们进终态：只有终态任务才可淘汰，这样才能把「表满」这个条件造出来。 */
    for 序 in 0..3 {
        let 号 = 器
            .提交任务图(
                &[加一("填表节点", 序)],
                任务选项::按请求(format!("填表{序}")),
            )
            .expect("填表提交必须受理");
        assert_eq!(等终态(&器, 号).阶段, 调用任务阶段::成功);
    }
    let 新号 = 器
        .提交任务图(&[加一("新来节点", 9)], 任务选项::按请求("新来"))
        .expect("表满时提交仍必须受理");
    let 快照 = 器
        .查询任务(新号, None)
        .expect("刚提交的任务必须查得到：清扫不许把刚插进来的当最老扔掉");
    assert_eq!(快照.阶段, 调用任务阶段::成功);
}

#[test]
fn 释放墓碑写失败保留记录判重与实例() {
    let 释放故障路径 = 落盘路径("释放故障");
    let 释放故障适配器 = 重启一遍(&释放故障路径);
    let 释放故障任务号 = 释放故障适配器
        .提交任务图(&[加一("释放故障节点", 19)], 任务选项::按请求("释放故障请求"))
        .unwrap();
    assert_eq!(等终态(&释放故障适配器, 释放故障任务号).阶段, 调用任务阶段::成功);
    let 故障前日志文本 = std::fs::read_to_string(&释放故障路径).unwrap();

    // 将真实运行日志路径替换成同名目录：墓碑追加会命中文件打开错误。
    std::fs::remove_file(&释放故障路径).unwrap();
    std::fs::create_dir(&释放故障路径).unwrap();
    assert!(!释放故障适配器.释放任务(释放故障任务号), "墓碑持久化失败不得回报释放成功");
    assert_eq!(
        释放故障适配器.查询任务(释放故障任务号, None).unwrap().阶段,
        调用任务阶段::成功,
        "墓碑失败时任务记录与执行实例归属必须保留"
    );
    assert!(
        释放故障适配器
            .提交任务图(&[加一("释放故障节点", 19)], 任务选项::按请求("释放故障请求"))
            .is_err(),
        "粘存的存储故障必须挡新准入，不能让重提绕过落盘故障"
    );
    drop(释放故障适配器);

    // 恢复原有有效日志，再启动新实例核持久层未出现墓碑。
    std::fs::remove_dir(&释放故障路径).unwrap();
    std::fs::write(&释放故障路径, 故障前日志文本).unwrap();
    let 释放故障重启适配器 = 重启一遍(&释放故障路径);
    assert_eq!(
        释放故障重启适配器.查询任务(释放故障任务号, None).unwrap().阶段,
        调用任务阶段::成功,
        "未写成的墓碑不能在重启恢复时伪造释放"
    );
    assert_eq!(
        释放故障重启适配器
            .提交任务图(&[加一("释放故障节点", 19)], 任务选项::按请求("释放故障请求"))
            .unwrap(),
        释放故障任务号,
        "重启后未持久化墓碑，原判重关联必须仍有效"
    );
    drop(释放故障重启适配器);
    let _ = std::fs::remove_file(释放故障路径);
}

#[test]
fn 可靠墓碑使显式释放与淘汰不复活() {
    let 路径 = 落盘路径("可靠墓碑");
    let 前 = 重启一遍(&路径);
    前.任务表.lock().unwrap().设容量(1);
    let 图 = [加一("墓碑节点", 9)];
    let 首号 = 前.提交任务图(&图, 任务选项::按请求("墓碑首请求")).unwrap();
    assert_eq!(等终态(&前, 首号).阶段, 调用任务阶段::成功);
    let 次号 = 前.提交任务图(&图, 任务选项::按请求("墓碑次请求")).unwrap();
    assert_eq!(等终态(&前, 次号).阶段, 调用任务阶段::成功);
    assert!(前.查询任务(首号, None).is_none());
    assert!(前.释放任务(次号));
    drop(前);
    let 后 = 重启一遍(&路径);
    assert!(后.查询任务(首号, None).is_none());
    assert!(后.查询任务(次号, None).is_none());
    for 请求标识 in ["墓碑首请求", "墓碑次请求"] {
        let 新号 = 后.提交任务图(&图, 任务选项::按请求(请求标识)).unwrap();
        assert!(新号 > 次号);
        assert_eq!(等终态(&后, 新号).阶段, 调用任务阶段::成功);
    }
    let _ = std::fs::remove_file(路径);
}

#[test]
fn 未确认释放不删除重放凭据() {
    let 路径 = 落盘路径("未知凭据");
    let 图 = [加一("未知凭据节点", 1)];
    let 前 = 重启一遍(&路径);
    let 号 = 前.提交任务图(&图, 任务选项::按请求("未知凭据请求")).unwrap();
    assert_eq!(等终态(&前, 号).阶段, 调用任务阶段::成功);
    drop(前);
    let 落盘 = 运行态落盘::指定路径(路径.clone());
    let mut 快照 = 落盘.读回().unwrap();
    let 恢复 = 快照.任务.get_mut(&号).unwrap();
    恢复.阶段 = 调用任务阶段::未确认;
    for 节点阶段 in 恢复.节点.values_mut() { *节点阶段 = 调用节点阶段::未知; }
    落盘.追加(号, 恢复.请求标识.as_deref(), 恢复.摘要, 恢复.阶段, &恢复.节点).unwrap();
    drop(落盘);
    let 后 = 重启一遍(&路径);
    assert!(!后.释放任务(号));
    drop(后);
    let 再后 = 重启一遍(&路径);
    assert_eq!(再后.提交任务图(&图, 任务选项::按请求("未知凭据请求")).unwrap(), 号);
    assert_eq!(再后.查询任务(号, None).unwrap().阶段, 调用任务阶段::未确认);
    let _ = std::fs::remove_file(路径);
}
