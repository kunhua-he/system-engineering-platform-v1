/// 池操作的结构化失败。**不 panic**（跨边界不许抛异常）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 进程池错误 {
    域不存在,
    熔断中,
    拉起失败,
    /// 通道断开（EOF 或传输错）：**崩溃的现场证据**。
    ///
    /// 与 `拉起失败` 分开：拉起失败是「没拉起来」（进程可能好着，是部署参数不对），
    /// 通道断开是「拉起来过、现在没了」—— 只有后者才构成崩溃计数。
    通道断开,
    /// 预算耗尽：进程**还活着**，但没在预算内答。
    ///
    /// 与 `通道断开` 严格分开（这是 `0034` 与 `0004` 两码的分界线）：
    /// 一个是「进程没了」，一个是「进程活着但没答」—— 前者要查它为什么崩，后者重试或加预算。
    预算耗尽,
}

/// 一次监督的判读。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 监督判读 {
    pub 仍在运行: bool,
    pub 已重拉: bool,
    pub 连续崩溃次数: u32,
    pub 熔断中: bool,
}

/// 一个执行域的工作进程：子进程 + 与它相连的通道 + 退避账。
///
/// **锁包（`pub(crate)`）**：跨域不共享，只有 [`域句柄`]（子件）与 [`进程池`] 读它。
/// 它从私有提到 crate 可见，是因为拆件后 [`域句柄`] 与之**不在同一个模块**了 ——
/// 子件亮着 `pub(crate)` 的字段与方法却持一个更私有类型时，编译器会报「类型比项更私有」。
pub(crate) struct 工作进程 {
    子进程: Child,
    通道: UnixStream,
    进程组号: i32,
    /// 本实例的**代次**：每次（重）拉起取一个新值 ⇒ 旧句柄永不误命中新任务。
    实例代次: u64,
    运行中: bool,
    连续崩溃次数: u32,
    下次允许拉起: Instant,
    熔断截至: Option<Instant>,
    装载已重放: bool,
}

/// 一个域格：标识 + **自持锁**的工作进程。域表锁只用于找到这一格，不用于收发。
pub(crate) struct 域格 {
    标识: 执行域标识,
    工作: Arc<Mutex<工作进程>>,
    事务锁: Arc<Mutex<()>>,
}

