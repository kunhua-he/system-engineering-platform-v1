/// 进程池：`执行域标识 → 工作进程` 的实例表。**不落 static**。
///
/// 表在 `Mutex` 里，但那把锁**只用于增删 / 取格**（一次短锁），**收发一律不持表锁**
/// （冻结件 §五）—— 故本件的方法收 `&self` 而非 `&mut self`。
pub struct 进程池 {
    配置: 进程池配置,
    域表: Mutex<Vec<域格>>,
    /// 上次分配的实例代次（同进程内也强制单调递增）。**跨域共享**（`Arc`）。
    上次代次: Arc<Mutex<u64>>,
}

/// 拉起一个工作进程：UnixStream 一对，子端接它自身的 stdin/stdout，宿主端留在池里。
fn 生成进程(启动程序: &str, 启动参数: &[String]) -> Result<(Child, UnixStream), 进程池错误> {
    let (主机端, 子进程端) = UnixStream::pair().map_err(|_| 进程池错误::拉起失败)?;
    let 子读端 = 子进程端.try_clone().map_err(|_| 进程池错误::拉起失败)?;
    let mut 命令 = Command::new(启动程序);
    命令
        .args(启动参数)
        .stdin(Stdio::from(OwnedFd::from(子进程端)))
        .stdout(Stdio::from(OwnedFd::from(子读端)))
        .stderr(Stdio::null())
        .process_group(0);
    let 子进程 = 命令.spawn().map_err(|_| 进程池错误::拉起失败)?;
    Ok((子进程, 主机端))
}

/// 往一个已有格子里装一个新拉起的进程（拉起 / 重拉共用）。
fn 装新进程(
    工作: &mut 工作进程,
    子进程: Child,
    通道: UnixStream,
    实例代次: u64,
) -> Result<(), 进程池错误> {
    let 进程组号 = i32::try_from(子进程.id()).map_err(|_| 进程池错误::拉起失败)?;
    工作.子进程 = 子进程;
    工作.通道 = 通道;
    工作.进程组号 = 进程组号;
    工作.实例代次 = 实例代次;
    工作.运行中 = true;
    工作.装载已重放 = false;
    Ok(())
}

/// 查实一次崩溃：只在「上一次查时还在跑」时计数，**幂等**（连查两次不多记）。
fn 查实崩溃(配置: 进程池配置, 工作: &mut 工作进程) {
    if !工作.运行中 {
        return;
    }
    if let Ok(Some(_)) = 工作.子进程.try_wait() {
        let 现在时刻 = Instant::now();
        工作.运行中 = false;
        工作.连续崩溃次数 = 工作.连续崩溃次数.saturating_add(1);
        let 位移 = 工作.连续崩溃次数.saturating_sub(1).min(20);
        let 毫秒 = 配置.退避基数毫秒.saturating_mul(1u64 << 位移).min(配置.退避上限毫秒);
        工作.下次允许拉起 = 现在时刻 + Duration::from_millis(毫秒);
        if 工作.连续崩溃次数 >= 配置.重启预算 {
            工作.熔断截至 = Some(现在时刻 + Duration::from_millis(配置.熔断时长毫秒));
        }
        工作.装载已重放 = false;
    }
}

/// 给一次判读（不改状态）。
fn 判读格子(工作: &工作进程, 现在时刻: Instant) -> 监督判读 {
    监督判读 {
        仍在运行: 工作.运行中,
        已重拉: false,
        连续崩溃次数: 工作.连续崩溃次数,
        熔断中: 工作.熔断截至.map_or(false, |熔断截至| 现在时刻 < 熔断截至),
    }
}

impl 进程池 {
    /// 建一个空池（一份部署配置）。
    pub fn 新建(配置: 进程池配置) -> Self {
        Self { 配置, 域表: Mutex::new(Vec::new()), 上次代次: Arc::new(Mutex::new(0)) }
    }

    /// 已建域数（验证面用）。
    pub fn 已建域数(&self) -> usize {
        取锁(&self.域表).len()
    }

    /// 这个域建过没有。
    pub fn 含域(&self, 标识: &执行域标识) -> bool {
        self.取域句柄(标识).is_some()
    }

    /// **取域句柄**（**短锁**：只在这一刻持表锁，交出句柄后立刻放）。
    ///
    /// 这是「域表锁只用于取引用」的唯一取口；拿到句柄后的长执行不再碰表锁。
    pub fn 取域句柄(&self, 标识: &执行域标识) -> Option<域句柄> {
        取锁(&self.域表)
            .iter()
            .find(|格子| &格子.标识 == 标识)
            .map(|格子| 域句柄 {
                配置: self.配置,
                工作: Arc::clone(&格子.工作),
                代次源: Arc::clone(&self.上次代次),
                事务锁: Arc::clone(&格子.事务锁),
            })
    }

    /// 取一个**跨重启不复用**的实例代次（以墙钟纳秒为源，且强制比上次大）。
    ///
    /// 停机恢复后重建的池从新的墙钟起点再取 ⇒ 旧代次永不与新一代次相等
    /// （旧句柄永不误命中新任务；W01「重放及引用归属」）。
    fn 取单调代次(&self) -> u64 {
        let 墙钟 = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|时长| 时长.as_nanos() as u64)
            .unwrap_or(0);
        let mut 上次 = 取锁(&self.上次代次);
        let 代次 = 墙钟.max(上次.saturating_add(1));
        *上次 = 代次;
        代次
    }

    /// 造一格（新拉起的进程）。
    fn 造格(标识: 执行域标识, 子进程: Child, 通道: UnixStream, 实例代次: u64)
        -> Result<域格, 进程池错误>
    {
        let 进程组号 = i32::try_from(子进程.id()).map_err(|_| 进程池错误::拉起失败)?;
        Ok(域格 {
            标识,
            事务锁: Arc::new(Mutex::new(())),
            工作: Arc::new(Mutex::new(工作进程 {
                子进程,
                通道,
                进程组号,
                实例代次,
                运行中: true,
                连续崩溃次数: 0,
                下次允许拉起: Instant::now(),
                熔断截至: None,
                装载已重放: false,
            })),
        })
    }

    /// 保证这个域在跑：没有则拉起；崩了则按退避 / 熔断决定能不能重拉。
    ///
    /// 已存在 ⇒ 转 [`域句柄::保证在`]（只持该域锁）；不存在 ⇒ 拉起后插格（一次短表锁）。
    pub fn 保证域在(
        &self,
        标识: &执行域标识,
        启动程序: &str,
        启动参数: &[String],
    ) -> Result<(), 进程池错误> {
        if let Some(句柄) = self.取域句柄(标识) {
            return 句柄.保证在(启动程序, 启动参数);
        }
        let (子进程, 通道) = 生成进程(启动程序, 启动参数)?;
        let 实例代次 = self.取单调代次();
        let 新格 = Self::造格(标识.clone(), 子进程, 通道, 实例代次)?;
        let mut 表 = 取锁(&self.域表);
        if 表.iter().any(|格子| &格子.标识 == 标识) {
            // 别人已插：丢掉我们这份（连同它拉起的进程，不留孤儿）。
            let 孤儿 = 新格;
            drop(表);
            回收::回收孤儿(&孤儿);
            return Ok(());
        }
        表.push(新格);
        Ok(())
    }

    /// 收下一个**已连好的域**：对端由别人拉起（宿主已代拉 / 验证面的应答环），
    /// 池只接管它的通道与退避账。
    ///
    /// 与 [`进程池::保证域在`] 的分工：那个自行 `spawn`，这个只登记 —— 验证面要验
    /// 「通道断了会怎样」时，不需要一个真子进程来陪。
    ///
    /// 子进程用一个**长命占位**：它是为了让 `try_wait` / 击杀有东西可查，不接数据通道
    /// （数据通道是调用方给的那条）。两条通道分开是有意的 —— 占位进程写不到本流上去。
    pub fn 收下已连域(
        &self,
        标识: 执行域标识,
        宿主端: UnixStream,
        部署: crate::进程调用::域部署,
    ) -> Result<(), 进程池错误> {
        if self.含域(&标识) {
            return Err(进程池错误::域不存在);
        }
        let (子进程, _) = 生成进程(&部署.启动程序, &部署.启动参数)?;
        let 实例代次 = self.取单调代次();
        let 进程组号 = i32::try_from(子进程.id()).map_err(|_| 进程池错误::拉起失败)?;
        取锁(&self.域表).push(域格 {
            标识,
            事务锁: Arc::new(Mutex::new(())),
            工作: Arc::new(Mutex::new(工作进程 {
                子进程,
                通道: 宿主端,
                进程组号,
                实例代次,
                运行中: true,
                连续崩溃次数: 0,
                下次允许拉起: Instant::now(),
                熔断截至: None,
                装载已重放: false,
            })),
        });
        Ok(())
    }

    /// 崩溃重拉：查实崩溃后，按退避 / 重启预算 / 熔断决定能否再拉一个。
    pub fn 崩溃重拉(
        &self,
        标识: &执行域标识,
        启动程序: &str,
        启动参数: &[String],
    ) -> Result<监督判读, 进程池错误> {
        let 句柄 = self.取域句柄(标识).ok_or(进程池错误::域不存在)?;
        let mut 工作 = 句柄.锁();
        查实崩溃(句柄.配置, &mut 工作);
        let 现在时刻 = Instant::now();
        if 工作.运行中 {
            return Ok(判读格子(&工作, 现在时刻));
        }
        if 工作.熔断截至.map_or(false, |熔断截至| 现在时刻 < 熔断截至) {
            return Err(进程池错误::熔断中);
        }
        if 现在时刻 < 工作.下次允许拉起 {
            return Err(进程池错误::拉起失败);
        }
        let (子进程, 通道) = 生成进程(启动程序, 启动参数)?;
        装新进程(&mut 工作, 子进程, 通道, 句柄.取单调代次())?;
        let mut 判读 = 判读格子(&工作, Instant::now());
        判读.已重拉 = true;
        Ok(判读)
    }
}

