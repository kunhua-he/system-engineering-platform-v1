//! 线协议 —— 在 Unix domain socket 上承载**同一份** `跨语言适配/边界协议/边界协议.md`
//! 的调用语义。
//!
//! 依据：`临时件/W01_裁决_架构升级.md`（IPC 载体 = Unix domain socket；同一份调用语义，
//! 不另造第二套）· `临时件/派活_W/W04a_进程池与线协议.md` ·
//! `临时件/落点/307收尾_接口冻结.md`（数据过线口径）。
//!
//! # 只这一份语义
//!
//! 调用形状逐字照协议：**按号 + 按契约行序填值 + 结构化结果**
//! （`(号, 参数个数, 参数表) → 返回槽`），协议层结果码**恰好 `{成功 = 0, 参数不合法 = -1}`**
//! （唯一来源 = [`crate::协议结果`]，`边界协议.md` §三·一 的数值冻结）。
//! 本件**不自带第二套协议**：帧编解码一律走 [`crate::进程帧`]，本件只把「边界协议的一次调用」
//! 摆进帧的载荷里。
//!
//! # 盘面（沿用帧头 24 字节）
//!
//! ```text
//! 调用请求载荷 = 请求头(号值 u32 · 参数个数 u32) ‖ 逐槽(单槽盘面 24 字节) ‖ 数据区
//! 调用结果载荷 = 协议码(i32) ‖ 返回槽(单槽盘面 24 字节) ‖ 数据区
//! ```
//!
//! 槽的盘面 = `类型标签 u32 · 槽标志位 u16 · 保留 u16 · 槽字节长度 u64 · 槽值 u64`
//! —— 与 `数据槽` 的 `repr(C)` 布局逐字段对应。**槽盘面一字不改**：带数据的槽（文本 /
//! 字节集）把 `槽值` 字段填成**数据区内的偏移**，字节本体追加在**全部槽之后**的数据区里。
//!
//! # 旧格式兼容（两种都收）
//!
//! 无数据区 = 旧格式（本版之前的全部内联槽）。解码时按**长度自描述**：
//! `载荷长度 == 头部 + 槽数×24` ⇒ 无数据区；多于 ⇒ 有数据区。帧头协议版本号**不动**
//! （这是同一版内的载荷扩展，将来再改走新版本号）。
//!
//! # 先校界限再分配（W01 裁决 3 · 冻结件 §二 四条）
//!
//! ① 槽数 ≤ [`单次调用槽数上限`] ② 头部 + 槽数×24 ≤ 载荷长 ③ 每个带数据槽的
//! 「偏移 + 长度」≤ 数据区长 ④ 累计数据字节 ≤ [`crate::进程帧::调用载荷上限`]。
//! 四条任一不过 ⇒ **结构化拒**，绝不按声明的长度盲目分配。
//!
//! # 有界队列与结构化拒绝
//!
//! 收进队列用 [`有界帧队列`]（内核帧层，容量固定）。**满则结构化拒绝**
//! （[`线协议错误::队列已满`]），**不静默丢、不无限等**；控制消息另走控制队列（帧层已分）。
//!
//! # 诚实边界（本版承载范围）
//!
//! 过线的槽承载：**内联值**（整数 · 错误码 · 空槽，值 ≤ 8 字节）· **文本**（类型标签 4）·
//! **字节集**（类型标签 5）· **空文本 / 空字节集**（引用 + 长度 0，与「空槽」是两回事）。
//! **尚无正式编码的结构类型**明确拒（[`线协议错误::结构未支持`]）——不做「尽力而为」的
//! 字节搬运。**句柄**（类型标签 6 / 任务句柄 7）不许当普通整数过线：跨域后域与代次校验
//! 不具备，一律 [`线协议错误::句柄不支持跨域`]；**内联的 6 号槽在进程内路照旧**。
//!
//! 接收侧把过线字节**材料化**成宿主自有 `Box<[u8]>`（[`crate::值归还::收下字节槽`]），
//! **不依赖远端存活**。扩展侧的收调用循环在 [`crate::工作进程`]（同一 crate 复用本件，
//! 不另造第二份编解码）。

