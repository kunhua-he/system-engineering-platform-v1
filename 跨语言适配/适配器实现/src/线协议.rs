//! 线协议 —— 在 Unix domain socket 上承载**同一份** `跨语言适配/边界协议/边界协议.md`
//! 的调用语义。
//!
//! 依据：`临时件/W01_裁决_架构升级.md`（IPC 载体 = Unix domain socket；同一份调用语义，
//! 不另造第二套）· `临时件/派活_W/W04a_进程池与线协议.md`。
//!
//! # 只这一份语义
//!
//! 调用形状逐字照协议：**按号 + 按契约行序填值 + 结构化结果**
//! （`(号, 参数个数, 参数表) → 返回槽`），协议层结果码**恰好 `{成功 = 0, 参数不合法 = -1}`**
//! （唯一来源 = [`crate::协议结果`]，`边界协议.md` §三·一 的数值冻结）。
//! 本件**不自带第二套协议**：帧编解码一律走 [`crate::进程帧`]，本件只把「边界协议的一次调用」
//! 摆进帧的载荷里。
//!
//! # 盘面（沿用帧头 24 字节）
//!
//! ```text
//! 调用请求载荷 = 请求头(号值 u32 · 参数个数 u32) ‖ 逐槽(单槽盘面 24 字节)
//! 调用结果载荷 = 协议码(i32) ‖ 返回槽(单槽盘面 24 字节)
//! ```
//!
//! 槽的盘面 = `类型标签 u32 · 槽标志位 u16 · 保留 u16 · 槽字节长度 u64 · 槽值 u64`
//! —— 与 `数据槽` 的 `repr(C)` 布局逐字段对应。**先校界限再分配**（W01 裁决 3）：
//! 读头先判长度，越界即拒，绝不按声明的长度盲目分配。
//!
//! # 有界队列与结构化拒绝
//!
//! 收进队列用 [`有界帧队列`]（内核帧层，容量固定）。**满则结构化拒绝**
//! （[`线协议错误::队列已满`]），**不静默丢、不无限等**；控制消息另走控制队列（帧层已分）。
//!
//! # 诚实边界（本版承载范围）
//!
//! 过线的槽**只承载内联值**（整数 · 句柄 · 错误码 · 空槽，值 ≤ 8 字节）。
//! **含数据的引用槽**（文本 / 字节集，`槽字节长度 > 0` 且带引用标志）在本版**结构化拒绝**
//! （[`线协议错误::含引用槽`]）—— 把数据搬过线要另定搬运口径，不属本版；**不静默截断**。
//! 收侧同理：本版 [`线协议会话`] 是**宿主侧**会话（发调用 / 收带同一请求标识的回帧），
//! 扩展侧的收调用循环由扩展自身实现（本 crate 不认识任何扩展）。

use std::io;
use std::num::NonZeroU64;
use std::os::unix::net::UnixStream;
use std::time::{Duration, Instant};

use v1_contract::{类型标签, 数据槽};

use crate::进程帧::{调用帧预算, 有界帧队列, 接收帧, 发送帧, 消息帧, 消息类别};
// 协议层结果码**只此一份**：`边界面::协议结果`（`边界协议.md` §三·一 的运行期实现）——
// 本件不自造第二套 `成功/参数不合法`。
use crate::协议结果;

/// 请求头字节数（号值 u32 · 参数个数 u32）。
pub const 请求头字节数: usize = 8;
/// 结果头的字节数（协议码 i32）。
pub const 结果头字节数: usize = 4;
/// 单个槽的盘面字节数（4 + 2 + 2 + 8 + 8）。
pub const 单槽盘面字节数: usize = 24;
/// 单次调用的槽数上限（先校界限再分配的上界之一）。
pub const 单次调用槽数上限: usize = 1024;
/// 本件发/收回帧的预算（毫秒）。**≤ 五秒硬顶**。
const 短预算毫秒: u64 = 200;

/// 线协议的结构化失败。**不 panic**（跨边界不许抛异常）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 线协议错误 {
    载荷过短,
    槽数越界,
    含引用槽,
    结果头不符,
    协议码越界,
    非调用结果帧,
    非通知回执帧,
    队列已满,
    传输失败,
}

impl From<io::Error> for 线协议错误 {
    fn from(_错误: io::Error) -> Self {
        线协议错误::传输失败
    }
}

/// 造一个本件的短预算（发/收回帧共用）。
fn 短预算() -> Result<调用帧预算, 线协议错误> {
    调用帧预算::创建(Instant::now() + Duration::from_millis(短预算毫秒)).map_err(线协议错误::from)
}

/// 写一个槽的盘面（内联槽；引用槽带数据即拒）。
fn 写一个槽(缓冲: &mut Vec<u8>, 槽项: &数据槽) -> Result<(), 线协议错误> {
    if 槽项.是否引用() && 槽项.槽字节长度 != 0 {
        return Err(线协议错误::含引用槽);
    }
    缓冲.extend_from_slice(&槽项.类型标签.取号值().to_le_bytes());
    缓冲.extend_from_slice(&槽项.槽标志位.to_le_bytes());
    缓冲.extend_from_slice(&槽项.保留.to_le_bytes());
    缓冲.extend_from_slice(&槽项.槽字节长度.to_le_bytes());
    缓冲.extend_from_slice(&槽项.槽值.to_le_bytes());
    Ok(())
}

/// 读一个槽的盘面（恰好 [`单槽盘面字节数`] 字节）。
fn 读一个槽(字节: &[u8]) -> 数据槽 {
    数据槽 {
        类型标签: 类型标签::构造(u32::from_le_bytes(字节[0..4].try_into().unwrap())),
        槽标志位: u16::from_le_bytes(字节[4..6].try_into().unwrap()),
        保留: u16::from_le_bytes(字节[6..8].try_into().unwrap()),
        槽字节长度: u64::from_le_bytes(字节[8..16].try_into().unwrap()),
        槽值: u64::from_le_bytes(字节[16..24].try_into().unwrap()),
    }
}

/// 编码一次调用请求：`请求头 ‖ 逐槽`。越界或含引用槽即结构化拒。
pub fn 编码调用请求(号值: u32, 参数槽表: &[数据槽]) -> Result<Vec<u8>, 线协议错误> {
    if 参数槽表.len() > 单次调用槽数上限 {
        return Err(线协议错误::槽数越界);
    }
    let mut 缓冲 = Vec::with_capacity(请求头字节数 + 参数槽表.len() * 单槽盘面字节数);
    缓冲.extend_from_slice(&号值.to_le_bytes());
    缓冲.extend_from_slice(&(参数槽表.len() as u32).to_le_bytes());
    for 槽项 in 参数槽表 {
        写一个槽(&mut 缓冲, 槽项)?;
    }
    Ok(缓冲)
}

/// 解码一次调用请求。**先校界限（长度）再分配**。
pub fn 解码调用请求(载荷: &[u8]) -> Result<(u32, Vec<数据槽>), 线协议错误> {
    if 载荷.len() < 请求头字节数 {
        return Err(线协议错误::载荷过短);
    }
    let 号值 = u32::from_le_bytes(载荷[0..4].try_into().unwrap());
    let 参数个数 = u32::from_le_bytes(载荷[4..8].try_into().unwrap()) as usize;
    if 参数个数 > 单次调用槽数上限 {
        return Err(线协议错误::槽数越界);
    }
    let 应有字节 = 请求头字节数 + 参数个数 * 单槽盘面字节数;
    if 载荷.len() != 应有字节 {
        return Err(线协议错误::载荷过短);
    }
    let mut 参数槽表 = Vec::with_capacity(参数个数);
    for 序号 in 0..参数个数 {
        let 起 = 请求头字节数 + 序号 * 单槽盘面字节数;
        参数槽表.push(读一个槽(&载荷[起..起 + 单槽盘面字节数]));
    }
    Ok((号值, 参数槽表))
}

/// 编码一次调用结果：`协议码 ‖ 返回槽`。
pub fn 编码调用结果(协议码值: i32, 返回槽: &数据槽) -> Result<Vec<u8>, 线协议错误> {
    if 返回槽.是否引用() && 返回槽.槽字节长度 != 0 {
        return Err(线协议错误::含引用槽);
    }
    let mut 缓冲 = Vec::with_capacity(结果头字节数 + 单槽盘面字节数);
    缓冲.extend_from_slice(&协议码值.to_le_bytes());
    写一个槽(&mut 缓冲, 返回槽)?;
    Ok(缓冲)
}

/// 解码一次调用结果。协议码**恰好 `{0, -1}`**，出现第三个数即拒。
pub fn 解码调用结果(载荷: &[u8]) -> Result<(i32, 数据槽), 线协议错误> {
    if 载荷.len() != 结果头字节数 + 单槽盘面字节数 {
        return Err(线协议错误::结果头不符);
    }
    let 协议码值 = i32::from_le_bytes(载荷[0..4].try_into().unwrap());
    if 协议码值 != 协议结果::成功 && 协议码值 != 协议结果::参数不合法 {
        return Err(线协议错误::协议码越界);
    }
    Ok((协议码值, 读一个槽(&载荷[结果头字节数..])))
}

/// 宿主侧的线协议会话：在一条 `UnixStream` 上收发帧，收件落**有界队列**。
pub struct 线协议会话 {
    通道: UnixStream,
    待办队列: 有界帧队列,
}

impl 线协议会话 {
    /// 从一条已连通道建会话（业务队列按帧层容量）。
    pub fn 新建(通道: UnixStream) -> Self {
        Self { 通道, 待办队列: 有界帧队列::业务队列() }
    }

    /// 发起一次调用：编码 `(号值, 参数槽表)` → `调用` 帧 → 发出。
    pub fn 发起调用(
        &mut self,
        请求标识: NonZeroU64,
        号值: u32,
        参数槽表: &[数据槽],
    ) -> Result<(), 线协议错误> {
        let 载荷 = 编码调用请求(号值, 参数槽表)?;
        let 消息体 = 消息帧 { 消息类型: 消息类别::调用, 请求标识, 载荷 };
        发送帧(&mut self.通道, &消息体, &mut 短预算()?)?;
        Ok(())
    }

    /// 收一次调用结果（同一请求标识）→ `(协议码, 返回槽)`。收到别的类别的帧即拒。
    pub fn 收调用结果(
        &mut self,
        请求标识: NonZeroU64,
    ) -> Result<(i32, 数据槽), 线协议错误> {
        let 消息体 = 接收帧(&mut self.通道, 请求标识, &mut 短预算()?)?;
        if 消息体.消息类型 != 消息类别::调用结果 {
            return Err(线协议错误::非调用结果帧);
        }
        解码调用结果(&消息体.载荷)
    }

    /// 确认装载初始化：发一条**通知号 2000** 的通知帧（重放只放装载初始化）。
    pub fn 确认装载初始化(&mut self, 请求标识: NonZeroU64) -> Result<(), 线协议错误> {
        let 载荷 = v1_contract::声明数据::通知号_2000.to_le_bytes().to_vec();
        let 消息体 = 消息帧 { 消息类型: 消息类别::通知, 请求标识, 载荷 };
        发送帧(&mut self.通道, &消息体, &mut 短预算()?)?;
        Ok(())
    }

    /// 收装载初始化的回执（同一请求标识）。收到别的类别即拒。
    pub fn 收通知回执(&mut self, 请求标识: NonZeroU64) -> Result<(), 线协议错误> {
        let 消息体 = 接收帧(&mut self.通道, 请求标识, &mut 短预算()?)?;
        if 消息体.消息类型 != 消息类别::通知回执 {
            return Err(线协议错误::非通知回执帧);
        }
        Ok(())
    }

    /// 排队投递：收一件落**有界队列**。**满则结构化拒绝**（不静默丢、不无限等）。
    pub fn 排队投递(&mut self, 请求标识: NonZeroU64) -> Result<(), 线协议错误> {
        let 消息体 = 接收帧(&mut self.通道, 请求标识, &mut 短预算()?)?;
        self.待办队列.尝试入队(消息体).map_err(|_| 线协议错误::队列已满)
    }

    /// 取一件已排队的消息（无则 `None`）。
    pub fn 取一件(&mut self) -> Option<消息帧> {
        self.待办队列.取队首()
    }
}
