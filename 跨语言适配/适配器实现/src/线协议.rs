const 标签_文本: u32 = v1_contract::声明数据::类型标签_0004.取号值();
const 标签_字节集: u32 = v1_contract::声明数据::类型标签_0005.取号值();
const 标签_句柄: u32 = v1_contract::声明数据::类型标签_0006.取号值();
const 标签_任务句柄: u32 = v1_contract::声明数据::类型标签_0007.取号值();

/// 线协议的结构化失败。**不 panic**（跨边界不许抛异常）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 线协议错误 {
    载荷过短,
    槽数越界,
    /// 槽自称「引用 + 长度 > 0」，却没给出可读地址（空指针）。
    ///
    /// 本版**不再**因「引用槽带数据」报它 —— 带数据的文本 / 字节集走外挂数据区。
    含引用槽,
    结果头不符,
    协议码越界,
    非调用结果帧,
    非通知回执帧,
    队列已满,
    传输失败,
    /// 结构类型尚无正式编码：明确拒，不做「尽力而为」的字节搬运。
    结构未支持,
    /// 句柄（类型标签 6 / 任务句柄 7）不许当普通整数跨域：跨域后域与代次校验不具备。
    句柄不支持跨域,
    /// 带数据槽的「偏移 + 长度」越出数据区（先校界限再分配的第 ③ 条）。
    数据区越界,
    /// 带数据槽的累计字节超过单次调用上限（第 ④ 条）。
    累计超上限,
    /// 编码出的载荷超过**单帧上限**（与帧层同一个数，见 [`crate::进程帧::单帧载荷上限`]）。
    ///
    /// 与 `0004 超时` / `0034 崩溃` 分开：这是**本侧载荷形状**问题（输入形状不符），
    /// 不是进程状态问题 —— 不混进那两个码。
    载荷过大,
}

impl From<io::Error> for 线协议错误 {
    fn from(_错误: io::Error) -> Self {
        线协议错误::传输失败
    }
}

/// 造一个本件的短预算（发/收回帧共用）。
fn 短预算() -> Result<调用帧预算, 线协议错误> {
    调用帧预算::创建(Instant::now() + Duration::from_millis(短预算毫秒)).map_err(线协议错误::from)
}

/// 一份**已材料化槽表**的守卫：中途报错时把已造出的本地 `Box<[u8]>` 全部归还。
///
/// 为什么必须有：解码是**逐个槽**做的，第 N 个槽越界时前 N-1 个槽已经各自造了一块宿主
/// 内存（[`收下字节槽`]）。`数据槽` 是 `Copy` 的裸指针 —— 直接 `?` 返回就是**泄漏**
/// （冻结件 §二「失败路径也必须清理」）。守卫在 Drop 里逐个 [`crate::值归还::归还槽值`]。
struct 槽表守卫(Vec<数据槽>);

impl 槽表守卫 {
    fn 新建(容量: usize) -> Self {
        Self(Vec::with_capacity(容量))
    }

    fn 收下(&mut self, 槽项: 数据槽) {
        self.0.push(槽项);
    }

    /// 取走成果：取出后守卫不再持有 ⇒ Drop 不归还（成功的槽归调用方）。
    fn 取走(&mut self) -> Vec<数据槽> {
        core::mem::take(&mut self.0)
    }
}

impl Drop for 槽表守卫 {
    fn drop(&mut self) {
        for 槽项 in self.0.iter_mut() {
            crate::值归还::归还槽值(槽项);
        }
    }
}

/// **本版线协议能承载的类型标签集** —— 一张声明的能力表，不是散在各处的分支。
///
/// 为什么这张表住在边界：线格式是边界自身的产物（内核不知道线格式，它的槽是内存里的
/// 定长结构与字节集的引用）。所以「哪种标签编得进本版帧」是**协议翻译能力**，不是业务判断 ——
/// 与「按能力号分派到哪个执行体」那类判断不同，后者住内核与扩展。
///
/// 为什么写成表而不是一串相等比较：后者每加一种可承载类型就要再添一条分支，读的人
/// 无法一眼看出「本版到底支持哪些」；列表一处列清，能力边界就是读得到的。
const 可过线标签: [u32; 2] = [标签_文本, 标签_字节集];

/// **明确拒过线的标签**：句柄（6）与任务句柄（7）。
///
/// 两者跨域后「域 + 代次」校验不具备（句柄的含义住在它被发出的那个进程里），
/// 当普通整数搬过去只会让人拿到一个看似合法、实则无处可用的数 ⇒ 一律拒。
const 拒过线标签: [u32; 2] = [标签_句柄, 标签_任务句柄];

/// 校验一个**带数据**的引用槽的类型标签（③ 条之外的类型面判据）。
fn 校带数据标签(标签值: u32) -> Result<(), 线协议错误> {
    if 拒过线标签.contains(&标签值) {
        return Err(线协议错误::句柄不支持跨域);
    }
    if !可过线标签.contains(&标签值) {
        return Err(线协议错误::结构未支持);
    }
    Ok(())
}

/// 校验一个**非引用（内联）**槽的类型标签：只挡 [`拒过线标签`]（句柄 6 / 任务句柄 7）。
///
/// 为什么单列一条：内联槽没有数据区可依，[`校带数据标签`] 那条路（引用槽）覆盖不到它；
/// 而句柄的正常形状**正是内联**（`内联槽(0006, 7, 0)`）—— 不校就等于把句柄值当普通整数
/// 放它过线。其余内联标签（空 0 · 整数 1 · 结构类型 2/3 · 错误 4294967295）照放行。
fn 校内联拒过线标签(标签值: u32) -> Result<(), 线协议错误> {
    if 拒过线标签.contains(&标签值) {
        return Err(线协议错误::句柄不支持跨域);
    }
    Ok(())
}

/// 写一个槽的盘面。带数据的引用槽（文本 / 字节集）把字节追加进 `数据区`，`槽值` 填偏移。
fn 写一个槽(
    缓冲: &mut Vec<u8>,
    数据区: &mut Vec<u8>,
    槽项: &数据槽,
) -> Result<(), 线协议错误> {
    if 槽项.是否引用() && 槽项.槽字节长度 != 0 {
        if 槽项.槽值 == 0 {
            return Err(线协议错误::含引用槽);
        }
        校带数据标签(槽项.类型标签.取号值())?;
        // SAFETY: 契约保证「引用 + 长度 > 0」的槽指向一块长度逐字相符的可读内存
        // （`写字节集` 与同形的产出方）。本函数只读、只读这一遍。
        let 数据 = unsafe {
            core::slice::from_raw_parts(槽项.槽值 as *const u8, 槽项.槽字节长度 as usize)
        };
        缓冲.extend_from_slice(&槽项.类型标签.取号值().to_le_bytes());
        缓冲.extend_from_slice(&槽项.槽标志位.to_le_bytes());
        缓冲.extend_from_slice(&槽项.保留.to_le_bytes());
        缓冲.extend_from_slice(&槽项.槽字节长度.to_le_bytes());
        缓冲.extend_from_slice(&(数据区.len() as u64).to_le_bytes());
        数据区.extend_from_slice(数据);
        return Ok(());
    }
    // 空文本 / 空字节集（引用 + 长度 0）是**合法值**，与「空槽」分开；但没有数据可搬
    // ⇒ 槽值写 0（**不写指针**：远端地址过线就是反向样本）。
    //
    // 非引用（内联）槽同样要过**拒过线标签**校：句柄（6）/ 任务句柄（7）的正常形状就是内联
    // （`内联槽(0006, 7, 0)`）—— 不校就会被当普通整数跨域搬运。其余内联标签照放行。
    校内联拒过线标签(槽项.类型标签.取号值())?;
    let 落盘槽值 = if 槽项.是否引用() { 0 } else { 槽项.槽值 };
    缓冲.extend_from_slice(&槽项.类型标签.取号值().to_le_bytes());
    缓冲.extend_from_slice(&槽项.槽标志位.to_le_bytes());
    缓冲.extend_from_slice(&槽项.保留.to_le_bytes());
    缓冲.extend_from_slice(&槽项.槽字节长度.to_le_bytes());
    缓冲.extend_from_slice(&落盘槽值.to_le_bytes());
    Ok(())
}

/// 读一个槽的盘面（恰好 [`单槽盘面字节数`] 字节）+ 按需从 `数据区` 材料化字节。
///
/// **先校界限再分配**：偏移与长度都先判在数据区内，才调 [`收下字节槽`] 造内存。
fn 读一个槽(
    盘面: &[u8],
    数据区: &[u8],
    累计字节: &mut usize,
) -> Result<数据槽, 线协议错误> {
    let 标签 = 类型标签::构造(u32::from_le_bytes(盘面[0..4].try_into().unwrap()));
    let 槽标志位 = u16::from_le_bytes(盘面[4..6].try_into().unwrap());
    let 保留 = u16::from_le_bytes(盘面[6..8].try_into().unwrap());
    let 槽字节长度 = u64::from_le_bytes(盘面[8..16].try_into().unwrap());
    let 槽值 = u64::from_le_bytes(盘面[16..24].try_into().unwrap());
    let 槽项 = 数据槽 { 类型标签: 标签, 槽标志位, 保留, 槽字节长度, 槽值 };
    if !槽项.是否引用() {
        // 非引用（内联）槽也要过同一道拒过线标签校：句柄 6 / 任务句柄 7 的正常形状就是内联。
        校内联拒过线标签(标签.取号值())?;
        return Ok(槽项);
    }
    // 引用 + 长度 0：空文本 / 空字节集（合法值）⇒ 本地材料化一块零长 Box，不依赖远端存活。
    if 槽字节长度 == 0 {
        校带数据标签(标签.取号值())?;
        return Ok(收下字节槽(标签, &[]));
    }
    校带数据标签(标签.取号值())?;
    // ③ 偏移 + 长度 ≤ 数据区长；② 已在调用方校过。
    let 起 = usize::try_from(槽值).map_err(|_| 线协议错误::数据区越界)?;
    let 长 = usize::try_from(槽字节长度).map_err(|_| 线协议错误::数据区越界)?;
    let 止 = 起.checked_add(长).ok_or(线协议错误::数据区越界)?;
    if 止 > 数据区.len() {
        return Err(线协议错误::数据区越界);
    }
    // ④ 累计 ≤ 既有一致调用上限。
    *累计字节 = 累计字节.checked_add(长).ok_or(线协议错误::累计超上限)?;
    if *累计字节 > crate::进程帧::调用载荷上限 {
        return Err(线协议错误::累计超上限);
    }
    Ok(收下字节槽(标签, &数据区[起..止]))
}

/// 编码一次调用请求：`请求头 ‖ 逐槽 ‖ 数据区`。越界或不可承载的槽即结构化拒。
///
/// **发送侧清理**：本函数**不产生**临时堆值 —— 槽里的字节直接拷进 `缓冲`（一个 `Vec`），
/// 成功与失败两条路都由它的 `Drop` 收尾，**不泄漏**。入参槽的所有权仍归调用方，
/// 由调用方经 [`crate::值归还::归还槽值`] 归还（谁分配谁释放）。
pub fn 编码调用请求(号值: u32, 参数槽表: &[数据槽]) -> Result<Vec<u8>, 线协议错误> {
    if 参数槽表.len() > 单次调用槽数上限 {
        return Err(线协议错误::槽数越界);
    }
    // ★ **先判长度再复制**（与解码侧同口径）：按各带数据槽**声明的**长度先累计一次，
    //   越过调用载荷上限 / 单帧上限当场结构化拒 —— 不先 `extend_from_slice` 复制一大块
    //   再被帧层拒（旧形状会把一次大载荷白复制一遍，还被误报成 `0004` / `0034`）。
    let mut 累计字节 = 0usize;
    for 槽项 in 参数槽表 {
        if 槽项.是否引用() && 槽项.槽字节长度 != 0 {
            累计字节 = 累计字节
                .checked_add(usize::try_from(槽项.槽字节长度).unwrap_or(usize::MAX))
                .ok_or(线协议错误::累计超上限)?;
        }
    }
    if 累计字节 > crate::进程帧::调用载荷上限 {
        return Err(线协议错误::累计超上限);
    }
    if 请求头字节数 + 参数槽表.len() * 单槽盘面字节数 + 累计字节
        > crate::进程帧::单帧载荷上限
    {
        return Err(线协议错误::载荷过大);
    }
    let mut 缓冲 = Vec::with_capacity(请求头字节数 + 参数槽表.len() * 单槽盘面字节数);
    let mut 数据区 = Vec::new();
    缓冲.extend_from_slice(&号值.to_le_bytes());
    缓冲.extend_from_slice(&(参数槽表.len() as u32).to_le_bytes());
    for 槽项 in 参数槽表 {
        写一个槽(&mut 缓冲, &mut 数据区, 槽项)?;
    }
    缓冲.extend_from_slice(&数据区);
    Ok(缓冲)
}

/// 解码一次调用请求。**先校界限（长度）再分配**。旧格式（无数据区）与带数据区**两种都收**。
pub fn 解码调用请求(载荷: &[u8]) -> Result<(u32, Vec<数据槽>), 线协议错误> {
    if 载荷.len() < 请求头字节数 {
        return Err(线协议错误::载荷过短);
    }
    let 号值 = u32::from_le_bytes(载荷[0..4].try_into().unwrap());
    let 参数个数 = u32::from_le_bytes(载荷[4..8].try_into().unwrap()) as usize;
    if 参数个数 > 单次调用槽数上限 {
        return Err(线协议错误::槽数越界);
    }
    let 槽区字节 = 参数个数.checked_mul(单槽盘面字节数).ok_or(线协议错误::槽数越界)?;
    let 槽区止 = 请求头字节数.checked_add(槽区字节).ok_or(线协议错误::载荷过短)?;
    if 载荷.len() < 槽区止 {
        return Err(线协议错误::载荷过短);
    }
    // 等于 ⇒ 无数据区（旧格式）；多于 ⇒ 有数据区。**两种都收**。
    let 数据区 = &载荷[槽区止..];
    let mut 累计字节 = 0usize;
    let mut 守卫 = 槽表守卫::新建(参数个数);
    for 序号 in 0..参数个数 {
        let 起 = 请求头字节数 + 序号 * 单槽盘面字节数;
        守卫.收下(读一个槽(&载荷[起..起 + 单槽盘面字节数], 数据区, &mut 累计字节)?);
    }
    Ok((号值, 守卫.取走()))
}

/// 编码一次调用结果：`协议码 ‖ 返回槽 ‖ 数据区`。
pub fn 编码调用结果(协议码值: i32, 返回槽: &数据槽) -> Result<Vec<u8>, 线协议错误> {
    // 先判长度再复制：一个返回槽声明的字节长度先累计，越过单帧上限当场结构化拒
    // （与编码请求同口径；一个槽的结果载荷不可能越过调用载荷上限，只校单帧）。
    if 返回槽.是否引用() && 返回槽.槽字节长度 != 0 {
        let 累计字节 = usize::try_from(返回槽.槽字节长度).unwrap_or(usize::MAX);
        if 结果头字节数 + 单槽盘面字节数 + 累计字节 > crate::进程帧::单帧载荷上限 {
            return Err(线协议错误::载荷过大);
        }
    }
    let mut 缓冲 = Vec::with_capacity(结果头字节数 + 单槽盘面字节数);
    let mut 数据区 = Vec::new();
    缓冲.extend_from_slice(&协议码值.to_le_bytes());
    写一个槽(&mut 缓冲, &mut 数据区, 返回槽)?;
    缓冲.extend_from_slice(&数据区);
    Ok(缓冲)
}

/// 解码一次调用结果。协议码**恰好 `{0, -1}`**，出现第三个数即拒。旧格式与数据区两种都收。
pub fn 解码调用结果(载荷: &[u8]) -> Result<(i32, 数据槽), 线协议错误> {
    let 槽区止 = 结果头字节数 + 单槽盘面字节数;
    if 载荷.len() < 槽区止 {
        return Err(线协议错误::结果头不符);
    }
    let 协议码值 = i32::from_le_bytes(载荷[0..4].try_into().unwrap());
    if 协议码值 != 协议结果::成功 && 协议码值 != 协议结果::参数不合法 {
        return Err(线协议错误::协议码越界);
    }
    let mut 累计字节 = 0usize;
    Ok((协议码值, 读一个槽(&载荷[结果头字节数..槽区止], &载荷[槽区止..], &mut 累计字节)?))
}

/// 清理一份**临时值副本**：序列化 / 执行结束之后（成功或失败）由发送方按原所有权约定归还。
///
/// 用在哪：接收侧把过线字节材料化成一份**临时副本**（[`收下字节槽`]）供本次执行用，
/// 执行完这份副本就没了 —— 由本函数逐个 [`crate::值归还::归还槽值`] 真回收
/// （冻结件 §二「入参副本活到本次执行结束」那一行）。**幂等**：还过的槽再还一次无事发生。
pub fn 清理临时入参(入参副本: &mut [数据槽]) {
    for 槽项 in 入参副本.iter_mut() {
        crate::值归还::归还槽值(槽项);
    }
}

/// 宿主侧的线协议会话：在一条 `UnixStream` 上收发帧，收件落**有界队列**。
pub struct 线协议会话 {
    通道: UnixStream,
    待办队列: 有界帧队列,
}

impl 线协议会话 {
    /// 从一条已连通道建会话（业务队列按帧层容量）。
    pub fn 新建(通道: UnixStream) -> Self {
        Self { 通道, 待办队列: 有界帧队列::业务队列() }
    }

    /// 发起一次调用：编码 `(号值, 参数槽表)` → `调用` 帧 → 发出。
    pub fn 发起调用(
        &mut self,
        请求标识: NonZeroU64,
        号值: u32,
        参数槽表: &[数据槽],
    ) -> Result<(), 线协议错误> {
        let 载荷 = 编码调用请求(号值, 参数槽表)?;
        let 消息体 = 消息帧 { 消息类型: 消息类别::调用, 请求标识, 载荷 };
        发送帧(&mut self.通道, &消息体, &mut 短预算()?)?;
        Ok(())
    }

    /// 收一次调用结果（同一请求标识）→ `(协议码, 返回槽)`。收到别的类别的帧即拒。
    pub fn 收调用结果(
        &mut self,
        请求标识: NonZeroU64,
    ) -> Result<(i32, 数据槽), 线协议错误> {
        let 消息体 = 接收帧(&mut self.通道, 请求标识, &mut 短预算()?)?;
        if 消息体.消息类型 != 消息类别::调用结果 {
            return Err(线协议错误::非调用结果帧);
        }
        解码调用结果(&消息体.载荷)
    }

    /// 确认装载初始化：发一条**通知号 2000** 的通知帧（重放只放装载初始化）。
    pub fn 确认装载初始化(&mut self, 请求标识: NonZeroU64) -> Result<(), 线协议错误> {
        let 载荷 = v1_contract::声明数据::通知号_2000.to_le_bytes().to_vec();
        let 消息体 = 消息帧 { 消息类型: 消息类别::通知, 请求标识, 载荷 };
        发送帧(&mut self.通道, &消息体, &mut 短预算()?)?;
        Ok(())
    }

    /// 收装载初始化的回执（同一请求标识）。收到别的类别即拒。
    pub fn 收通知回执(&mut self, 请求标识: NonZeroU64) -> Result<(), 线协议错误> {
        let 消息体 = 接收帧(&mut self.通道, 请求标识, &mut 短预算()?)?;
        if 消息体.消息类型 != 消息类别::通知回执 {
            return Err(线协议错误::非通知回执帧);
        }
        Ok(())
    }

    /// 排队投递：收一件落**有界队列**。**满则结构化拒绝**（不静默丢、不无限等）。
    pub fn 排队投递(&mut self, 请求标识: NonZeroU64) -> Result<(), 线协议错误> {
        let 消息体 = 接收帧(&mut self.通道, 请求标识, &mut 短预算()?)?;
        self.待办队列.尝试入队(消息体).map_err(|_| 线协议错误::队列已满)
    }

    /// 取一件已排队的消息（无则 `None`）。
    pub fn 取一件(&mut self) -> Option<消息帧> {
        self.待办队列.取队首()
    }
}
