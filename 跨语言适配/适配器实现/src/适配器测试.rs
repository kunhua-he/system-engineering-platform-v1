/// 用底座自己的声明建适配器，**真调一次**（走 `调用调度::调用` 全路径）。
#[test]
fn 装载_底座声明_转发调用走全路径() {
    let 适配器 = 适配器::装载(v1_loader::底座声明()).expect("底座自己的声明必须载得进来");
    assert_eq!(适配器.已装载声明数(), 1);

    let 入参 = 底座入参();
    let mut 返回槽 = 数据槽::空槽();
    match 适配器.调用能力(0, &入参, &mut 返回槽) {
        转发结果::成功(槽) => {
            assert_eq!(槽, 返回槽, "结果里的槽与返回槽是同一次写入的两个视图");
            assert!(槽.是否引用(), "底座命令 0 返回的是契约主结构指针");
            assert_eq!(
                槽.值,
                v1_loader::取平台信息() as u64,
                "必须真调到执行函数，而不是拿到兜底值"
            );
        }
        转发结果::失败(错) => panic!("底座命令 0 必须调得通，却报 {错:?}"),
    }
}

/// **多实例隔离**：两个适配器各持一本账本；一本打满配额，另一本照常成功。
///
/// 账本若落进程级全局，这条必挂。打满用的是**内核常量** `配额上限`，
/// 所以本用例同时钉住了「适配器的配额口径 = `调用调度` 的那个数」。
#[test]
fn 多实例隔离_一本打满配额不影响另一本() {
    let 甲 = 适配器::装载(v1_loader::底座声明()).expect("甲");
    let 乙 = 适配器::装载(v1_loader::底座声明()).expect("乙");
    let 入参 = 底座入参();
    let mut 返回槽 = 数据槽::空槽();

    for 次 in 0..配额上限 {
        match 甲.调用能力(0, &入参, &mut 返回槽) {
            转发结果::成功(_) => {}
            转发结果::失败(错) => {
                panic!("第 {次} 次（上限 {配额上限} 未满）必须成功，却报 {错:?}")
            }
        }
    }
    match 甲.调用能力(0, &入参, &mut 返回槽) {
        转发结果::失败(调度错误::配额用尽) => {}
        其它 => panic!("甲打满配额后必须报「配额用尽」，实际 {其它:?}"),
    }

    // 乙是另一本账本：同一号、同一份声明，不许被甲影响。
    match 乙.调用能力(0, &入参, &mut 返回槽) {
        转发结果::成功(_) => {}
        转发结果::失败(错) => panic!("乙是另一本账本，不许被甲影响，却报 {错:?}"),
    }
}

/// **未命中返回空**：调一个不存在的号 ⇒ 结构化错误，不是 panic。
#[test]
fn 未命中号_返回结构化错误不是崩溃() {
    let 适配器 = 适配器::装载(v1_loader::底座声明()).expect("底座");
    // 先放脏值：失败必须把它盖成空值，不许留给调用方。
    let mut 返回槽 = 数据槽::内联(v1_contract::声明数据::类型标签_0001, 123, 0);
    match 适配器.调用能力(9999, &[], &mut 返回槽) {
        转发结果::失败(调度错误::提供者未载入 { 号 }) => assert_eq!(号, 9999),
        其它 => panic!("未命中必须报「提供者未载入」，实际 {其它:?}"),
    }
    assert!(返回槽.是否空(), "未命中返回空（宪法第 6 条）");
}

