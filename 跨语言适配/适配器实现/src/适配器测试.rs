/// **追加装载**：对已存在的适配器再载入一份声明 —— **只追加，不重建**。
///
/// 钉两条：① 新声明真进来了（已装载声明数 +1、能力清单 +1）；
/// ② 已有状态**不被清掉**（留痕开关 · 追踪号这些「重建就会丢」的东西照旧）。
#[test]
fn 追加装载_只追加不重建_已有状态不丢() {
    use crate::测试夹具::造扩展声明_带句柄槽;
    let 首声明 = 造扩展声明(号段::新建(1000, 1099));
    let mut 适配器 = 适配器::装载声明根(&[v1_loader::底座声明(), 首声明]).expect("底座 + 首扩展");
    assert_eq!(适配器.已装载声明数(), 2);
    let 能力数_前 = 适配器.能力清单().len();

    // 让「重建会丢」的状态留下痕迹：开留痕、调一次（追踪号从 0 起）。
    适配器.启用留痕(8, 丢弃策略::丢最旧);
    let 入参 = 底座入参();
    let mut 返回槽 = 数据槽::空槽();
    let _ = 适配器.调用能力(0, &入参, &mut 返回槽);
    assert_eq!(适配器.取留痕(10)[0].追踪号, 0);

    // 追加一份**标识串不同、号段不冲突**的声明。
    let 次声明 = 造扩展声明_带句柄槽(号段::新建(1100, 1199));
    assert!(!适配器.已装载标识(次声明), "还没载入过");
    适配器.追加装载(次声明).expect("追加装载必须成功");

    assert_eq!(适配器.已装载声明数(), 3, "只追加：底座 + 首扩展 + 次扩展");
    assert_eq!(适配器.能力清单().len(), 能力数_前 + 1, "新扩展的能力进了清单");
    assert!(适配器.已装载标识(次声明), "追加后应在台账里");
    assert!(适配器.留痕已启用(), "追加装载不许重建（重建会丢留痕开关）");
    let _ = 适配器.调用能力(0, &入参, &mut 返回槽);
    assert_eq!(适配器.取留痕(10)[1].追踪号, 1, "追踪号接着走，没被重建清零");
}

/// **追加装载的判重**：同一份声明载两次 ⇒ 第二次被台账挡下（判定 ② 标识串唯一）。
#[test]
fn 追加装载_同一标识串载两次被挡() {
    let 首声明 = 造扩展声明(号段::新建(1000, 1099));
    let mut 适配器 = 适配器::装载声明根(&[v1_loader::底座声明(), 首声明]).expect("底座 + 首扩展");
    assert!(适配器.已装载标识(首声明));
    assert!(适配器.追加装载(首声明).is_err(), "同标识串第二次必须被挡（判定 ②）");
}
