/// **实测事实**：声明根里每份声明的命令编号都**取自声明**（`命令信息.编号`），不是表内下标。
///
/// 直接后果：底座命令编号 0、扩展命令编号 1000 ⇒ 两份声明**不再都从 0 起**，
/// 同一个适配器里也不再重号。编号显式化的裁决与代价见
/// `项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 1。
#[test]
fn 实测_命令编号来自声明() {
    let 扩展 = 造扩展声明(号段::新(1000, 1999));
    let 适配器 = 适配器::装载声明根(&[v1_loader::底座声明(), 扩展]).expect("两份都该载得进来");

    let 清单 = 适配器.能力清单();
    assert_eq!(清单.len(), 2, "两份声明各 1 条命令");
    assert_eq!(清单[0].编号, 0, "底座命令编号取自声明");
    assert_eq!(清单[1].编号, 1000, "扩展命令编号取自声明（不是表内下标 0）");
    assert_ne!(
        清单[0].编号, 清单[1].编号,
        "编号来自声明 ⇒ 两份声明不再都从 0 起"
    );
}

/// **实测事实（第二处）**：占 `1xxx` 号段的扩展，带 `错误` 状态位的命令**能载入**。
