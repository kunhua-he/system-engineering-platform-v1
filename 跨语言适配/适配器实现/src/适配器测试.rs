/// **读侧与调侧同一入口**：清单里的编号拿去调，必须走通。
#[test]
fn 读侧与调侧同一入口_清单里的编号能走通() {
    let 适配器 = 适配器::装载(v1_loader::底座声明()).expect("底座");
    let 清单 = 适配器.能力清单();
    assert_eq!(清单.len(), 1, "底座声明只有 1 条命令");
    let 摘要 = &清单[0];
    assert_eq!(摘要.参数个数, 1);
    assert!(!摘要.名称.is_empty(), "名称必须从声明的静态串现读出来");

    // 拿读出来的编号去调：读与调是同一条路，不是两份数据源。
    let 入参 = vec![数据槽::内联(v1_contract::声明数据::类型标签_0000, 64, 0); 摘要.参数个数 as usize];
    let mut 返回槽 = 数据槽::空槽();
    match 适配器.调用能力(摘要.编号, &入参, &mut 返回槽) {
        转发结果::成功(_) => {}
        转发结果::失败(错) => panic!("读侧报出的编号必须调得通，却报 {错:?}"),
    }
}

/// 读侧「某条能力的完整契约」：参数表**行序** · 返回 · 可抛错误码。
#[test]
fn 读侧_能力契约给出行序与可抛错误码() {
    let 适配器 = 适配器::装载(v1_loader::底座声明()).expect("底座");
    let 契约 = 适配器.能力契约(0).expect("0 号是底座的命令");

    assert_eq!(契约.参数表.len(), 1, "行序即契约：底座命令 0 有 1 行");
    assert_eq!(契约.参数表[0].名称, "目标字宽", "行序里的名字取自声明，不另存");
    assert_eq!(契约.返回类型, 0, "0 = 无返回值");

    assert!(!契约.可抛错误码.is_empty(), "声明的错误码表非空");
    assert!(
        契约
            .可抛错误码
            .iter()
            .any(|码| 码.码 == v1_contract::声明数据::错误码_1),
        "「提供者未载入」必须在可抛错误码里"
    );
    assert!(
        契约
            .可抛错误码
            .iter()
            .any(|码| 码.可重试 || 码.可自愈 || 码.需人工),
        "三项业务判断必须到得了运行期（否则它们只是注释）"
    );

    // 未命中给 None，不是 panic，也不编一份空契约。
    assert!(适配器.能力契约(9999).is_none());
}
