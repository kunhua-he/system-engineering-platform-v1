/// 台账真的在判：扩展声明撞底座自占的那一段 ⇒ 载入阶段就拒（不是建表阶段）。
///
/// 撞的那一段**取自生成物**（`声明数据::底座能力号段`，源 = `平台声明.json`），
/// 不在这里另写一份号段值 —— 手写就是同一事实的第二个来源。
///
/// 本样本**只**撞号段：夹具的 `编号 = 号段.起`（落在它自身申报的号段内 ⇒ ⑥ 的「编号越界」
/// 不成立），且 `状态位 = 0`（非错误项 ⇒ ⑥ 的「错误项段位未登记」不成立）。
/// ⇒ 断言的是**号段冲突本身**，**不依赖**步骤顺序（③ 先于 ⑥ 的显式口径见
/// `扩展装载/载入约定/载入判定.json` 的 `判定顺序的优先级`）。「两者都响」的样本见下一条。
#[test]
fn 装载_扩展撞底座号段即拒() {
    let 底座段 = v1_contract::声明数据::底座能力号段[0];
    let 扩展 = 造扩展声明(底座段);
    match 适配器::装载声明根(&[v1_loader::底座声明(), 扩展]) {
        Err(装载失败::载入(载入错误::号段冲突 { 起, 止 })) => {
            assert_eq!((起, 止), (底座段.起.取号值(), 底座段.止.取号值()));
        }
        Err(其它) => panic!("撞底座已占号段必须在判定阶段被拒，实际 {其它:?}"),
        Ok(_) => panic!("撞底座已占号段必须在判定阶段被拒，却装载成功了"),
    }
}

/// **③ 先于 ⑥ 的身份证**：同一份夹具**同时**成立两件事 ——
/// ① 撞号段：`编号 = 号段.起 = 0` 落在底座已占段 `[0, 999]` 内；
/// ② 声明不自洽：`状态位 = 命令状态::错误`（错误项），而它的段位 `0` **没**在夹具的
///    `错误段位表 = [1]` 里登记（`运行内核/装载入口/src/声明校验.rs::能力段位已登记` 那一支）。
///
/// ⇒ 断言报的是**号段冲突**。这证明「号段冲突（③）**先于**声明自洽（⑥）」是**实现里的事实**，
/// 而不是靠「⑥ 恰好不响」的顺序巧合 —— 把判定顺序反过来，本样本当场红（上一条样本做不到这一点，
/// 它只有一个条件成立）。
#[test]
fn 装载_同时撞号段与不自洽_先报号段冲突() {
    let 底座段 = v1_contract::声明数据::底座能力号段[0];
    let 扩展 = 造扩展声明_带状态位(底座段, v1_contract::命令状态::错误);
    match 适配器::装载声明根(&[v1_loader::底座声明(), 扩展]) {
        Err(装载失败::载入(载入错误::号段冲突 { 起, 止 })) => {
            assert_eq!((起, 止), (底座段.起.取号值(), 底座段.止.取号值()));
        }
        Err(装载失败::载入(载入错误::声明不自洽 { 命令号 })) => panic!(
            "③ 号段冲突必须先于 ⑥ 声明自洽：本样本两者都成立，却报了 声明不自洽（命令号 {}）\
             ⇒ 判定顺序退化成依赖实现顺序了（口径见 载入判定.json 的 `判定顺序的优先级`）",
            命令号.取号值()
        ),
        Err(其它) => panic!("撞底座已占号段必须在判定阶段被拒，实际 {其它:?}"),
        Ok(_) => panic!("撞底座已占号段必须在判定阶段被拒，却装载成功了"),
    }

    // **本样本不是空转的自证**：同一份「错误项」夹具换个**不撞**的号段（段位 3 不在夹具的
    // `错误段位表 = [1]` 里 ⇒ ⑥ 仍成立，而 ③ 不成立）⇒ 报的必须是 **⑥ 声明不自洽**。
    // 没有这一句，上面那条断言可能是空转的（万一「错误项段位未登记」那一支根本不会响，
    // 报号段冲突就毫不稀奇 —— `判据的可信性.md` §三 的假绿来源 1：判据是空转的）。
    let 不撞段 = 号段::新建(3000, 3999);
    let 扩展2 = 造扩展声明_带状态位(不撞段, v1_contract::命令状态::错误);
    match 适配器::装载声明根(&[v1_loader::底座声明(), 扩展2]) {
        Err(装载失败::载入(载入错误::声明不自洽 { .. })) => {}
        Err(其它) => panic!("③ 不成立时 ⑥ 必须报 声明不自洽，实际 {其它:?}"),
        Ok(_) => panic!("错误项而它的段位未登记 ⇒ ⑥ 必须拒，却装载成功了"),
    }
}

