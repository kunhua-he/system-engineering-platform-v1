/// 台账真的在判：扩展声明撞底座自占的那一段 ⇒ 载入阶段就拒（不是建表阶段）。
///
/// 撞的那一段**取自生成物**（`声明数据::底座能力号段`，源 = `平台声明.json`），
/// 不在这里另写一份号段值 —— 手写就是同一事实的第二个来源。
#[test]
fn 装载_扩展撞底座号段即拒() {
    let 底座段 = v1_contract::声明数据::底座能力号段[0];
    let 扩展 = 造扩展声明(底座段);
    match 适配器::装载声明根(&[v1_loader::底座声明(), 扩展]) {
        Err(装载失败::载入(载入错误::号段冲突 { 起, 止 })) => {
            assert_eq!((起, 止), (底座段.起, 底座段.止));
        }
        Err(其它) => panic!("撞底座已占号段必须在判定阶段被拒，实际 {其它:?}"),
        Ok(_) => panic!("撞底座已占号段必须在判定阶段被拒，却装载成功了"),
    }
}

/// **声明根**：底座在前、扩展在后，序贯走完同一个台账 —— 「一个扩展怎么加进去」的现成口。
#[test]
fn 声明根_底座与扩展序贯装载_台账口可用() {
    let 扩展 = 造扩展声明(号段::新(1000, 1999));
    let 适配器 = 适配器::装载声明根(&[v1_loader::底座声明(), 扩展])
        .expect("底座在前、扩展在后，六步必须全过");

    assert_eq!(适配器.已装载声明数(), 2);
    assert_eq!(适配器.能力清单().len(), 2, "两份声明各 1 条命令");

    // 路由到「认这个号」的那一份。号 0 只有底座的命令表认（底座命令 0 收 1 个入参）。
    let 入参 = 底座入参();
    let mut 返回槽 = 数据槽::空槽();
    match 适配器.调用能力(0, &入参, &mut 返回槽) {
        转发结果::成功(槽) => assert_eq!(槽.值, v1_loader::取平台信息() as u64),
        转发结果::失败(错) => panic!("号 0 必须由第一份认领，却报 {错:?}"),
    }
}

/// **实测事实**：声明根里每份声明的命令编号都从**表内下标 0** 起。
///
/// 直接后果：一份扩展的能力在同一个适配器里与底座的命令**重号**（都从 0 起），
/// 按「谁认这个号」路由时永远归第一份 ⇒ 扩展的命令够不着。
///
/// 这不是适配器的判断，是两条口径并存的必然后果：`装载入口` 的「命令编号 = 命令表下标」
/// 与 `字段名册与引用方式.md` 的「编号 = 能力号（如 1001）」。修法在既有件
/// （`装载入口` / `统一注册表` / 号段图），不在本 crate —— 这里只把事实钉住，
/// 免得它悄悄变成「已经好了」。
#[test]
fn 实测_声明根里每份声明的命令编号都从表内下标0起() {
    let 扩展 = 造扩展声明(号段::新(1000, 1999));
    let 适配器 = 适配器::装载声明根(&[v1_loader::底座声明(), 扩展]).expect("两份都该载得进来");

    let 清单 = 适配器.能力清单();
    assert_eq!(清单.len(), 2, "两份声明各 1 条命令");
    assert_eq!(
        清单[0].编号, 清单[1].编号,
        "实测：两份声明的命令编号都是各自命令表的下标（都从 0 起）——\
         扩展占 1xxx 号段这件事没有落到命令编号上"
    );
}

/// **实测事实（第二处）**：占 `1xxx` 号段的扩展，只要有一条命令带 `错误` 状态位，
/// 就必然被 `判声明自洽` 判成 `声明不自洽 { 命令号: 0 }`。
///
/// 原因：`装载入口` 的段位口径是 `命令编号 / 号段类宽度`，而「命令编号 = 命令表下标」
/// ⇒ 命令 0 的段位恒为 0；可扩展声明登记的是段位 1（`1xxx` 的首位）。
/// 于是「错误段位表 = 本声明占哪几个段位」这句话在**错误项命令**上判不成立 ——
/// 除非每条错误项命令都恰好落在下标 0。
///
/// `装载入口` 自己的样本（能力号段 1000–1999 + 错误段位表 [1]）就是这个组合，
/// 只是它的样本命令 `状态位 = 0` 才没撞上。修法在既有件（要么编号 = 能力号，
/// 要么段位从声明的号段算），不在本 crate —— 这里只把事实钉住。
#[test]
fn 实测_占1xxx号段的错误项命令因编号从0起而判不自洽() {
    let 扩展 = 造扩展声明带状态位(
        号段::新(1000, 1999),
        v1_contract::命令状态::错误,
    );
    match 适配器::装载声明根(&[v1_loader::底座声明(), 扩展]) {
        Err(装载失败::载入(载入错误::声明不自洽 { 命令号 })) => assert_eq!(命令号, 0),
        Err(其它) => panic!("实测口径是「声明不自洽」，实际报 {其它:?}"),
        Ok(_) => panic!("实测口径是「声明不自洽」，却装载成功了 —— 口径已变，须回看缺口 2"),
    }
}

