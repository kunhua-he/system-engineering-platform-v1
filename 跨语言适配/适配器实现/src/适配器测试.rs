/// 读侧「某条能力的完整契约」：参数表**行序** · 返回 · **这条命令自身的**可抛错误码。
///
/// `可抛错误码` 是命令自身的那张（底座命令 0 的执行函数不抛错 ⇒ 空表，**不是**声明全表）；
/// 声明的错误码全表走 [`适配器::声明错误码表`]，「失败可编程处理」的三项在那儿。
#[test]
fn 读侧_能力契约给出行序与可抛错误码() {
    let 适配器 = 适配器::装载(v1_loader::底座声明()).expect("底座");
    let 契约 = 适配器.能力契约(0).expect("0 号是底座的命令");

    assert_eq!(契约.参数表.len(), 1, "行序即契约：底座命令 0 有 1 行");
    assert_eq!(契约.参数表[0].名称, "目标字宽", "行序里的名字取自声明，不另存");
    assert_eq!(契约.返回类型, 0, "0 = 无返回值");

    assert!(
        契约.可抛错误码.is_empty(),
        "底座命令 0 自身的可抛码是空表（执行函数不抛错）—— 不许拿声明全表顶"
    );

    // 声明全表另有其口：非空，且「提供者未载入」在里面（三项业务判断到得了运行期）。
    let 全表 = 适配器.声明错误码表(0);
    assert!(!全表.is_empty(), "声明的错误码表非空");
    assert!(
        全表.iter().any(|错误码项| 错误码项.码 == v1_contract::声明数据::错误码_1),
        "「提供者未载入」必须在声明的错误码表里"
    );
    assert!(
        全表.iter().any(|错误码项| 错误码项.可重试 || 错误码项.可自愈 || 错误码项.需人工),
        "三项业务判断必须到得了运行期（否则它们只是注释）"
    );

    // 未命中给 None，不是 panic，也不编一份空契约。
    assert!(适配器.能力契约(9999).is_none());
}

/// **反向样本**：命令**自身的**可抛码（`[1001]`）比声明全表（`[1001, 1002, 1003]`）少 ⇒
/// `能力契约.可抛错误码` 只许交出**它自身那一个**。
///
/// 把 `读命令可抛错误码` 换回 `读错误码表`（即收窄前那一版）⇒ 本样本当场红（会拿到三个）。
#[test]
fn 读侧_可抛错误码只给这条命令自身的不是声明全表() {
    let 适配器 = 适配器::装载(造扩展声明_命令可抛码少于全表(号段::新建(1000, 1999)))
        .expect("夹具声明必须载得进来");
    let 契约 = 适配器.能力契约(1000).expect("编号 1000 已被夹具声明认领");

    let 自身的: Vec<u32> = 契约.可抛错误码.iter().map(|错误码项| 错误码项.码).collect();
    assert_eq!(自身的, vec![1001], "只许给这条命令自身登记的那一个，不是声明全表");

    // 名称与三项业务判断从**声明全表**现查（内容只有一份），不是编的。
    let 这条错误码 = &契约.可抛错误码[0];
    assert_eq!(这条错误码.名称, "夹具码一");
    assert!(这条错误码.可重试 && 这条错误码.可自愈 && !这条错误码.需人工);

    // 声明全表另走一个口：三个都在 —— 两个落点各司其职，不是把全表藏起来。
    let 全表: Vec<u32> = 适配器.声明错误码表(1000).iter().map(|错误码项| 错误码项.码).collect();
    assert_eq!(全表, vec![1001, 1002, 1003]);
}

