/// Rust 级释放口：与 C 符号 `平台_释放值` **同语义** —— 清空槽、幂等。
#[test]
fn 释放值_与平台释放值同语义_清空且幂等() {
    let 适配器 = 适配器::装载(v1_loader::底座声明()).expect("底座");
    let mut 数据槽 = 数据槽::指针(4.into(), 0x1234, 16, true);
    assert!(数据槽.交出了所有权(), "前提：这个槽带「所有权交出」");
    适配器.释放值(&mut 数据槽);
    assert!(数据槽.是否空(), "归还后是空槽");
    // 幂等：再还一次不崩、仍是空槽。
    适配器.释放值(&mut 数据槽);
    assert!(数据槽.是否空());
}

/// 留痕：`装载` 不开口；启用后调用路写一条，字段完整、可按号读回。
#[test]
fn 留痕_装载不开口_启用后调用路写一条() {
    let mut 适配器 = 适配器::装载(v1_loader::底座声明()).expect("底座");
    assert!(!适配器.留痕已启用(), "`适配器::装载` 不开口（装配侧才开）");
    assert!(适配器.取留痕(10).is_empty(), "没启用 ⇒ 一条也没有");
    assert_eq!(适配器.留痕已丢弃(), 0);

    适配器.启用留痕(8, 丢弃策略::丢最旧);
    assert!(适配器.留痕已启用());

    let 入参 = 底座入参();
    let mut 返回槽 = 数据槽::空槽();
    let _ = 适配器.调用能力(0, &入参, &mut 返回槽);

    let 一条 = 适配器.取留痕(10);
    assert_eq!(一条.len(), 1, "调用一次 ⇒ 恰好一条");
    assert_eq!(一条[0].能力号, 0);
    assert_eq!(一条[0].追踪号, 0, "本实例第一条");
    assert_eq!(一条[0].调用类, 调用类::能力, "能力调用的判别是「能力」");
    assert_eq!(一条[0].资源号, 0, "能力调用不涉及资源");
    assert_eq!(一条[0].操作号, 0, "能力调用不涉及资源操作");
    assert!(一条[0].是否自洽(), "判别与号位必须一致");
    assert_eq!(一条[0].结果码, 0, "成功 = 0");
    assert_eq!(一条[0].实例, &适配器 as *const 适配器 as u64, "实例号 = 本实例地址");
    assert_ne!(一条[0].入参指纹, 0, "指纹必须填（非零，避免与「没填」混淆）");

    // 再调一次：第二条，追踪号递增（单调，不落进程级全局）。
    let _ = 适配器.调用能力(0, &入参, &mut 返回槽);
    let 一条 = 适配器.取留痕(10);
    assert_eq!(一条.len(), 2);
    assert_eq!(一条[1].追踪号, 1);
}

