//! 调用任务装配 —— 把一次调用归一成任务图、交给调度器、同步等回结果。
//!
//! # 一件一件事
//!
//! | 件 | 管什么 |
//! |---|---|
//! | [`调度实例`](调度实例.rs) | 一张图一个实例：装配 · 提交 · 等结局 · 停机合流 |
//! | [`图驱动`](图驱动.rs) | 实例内部状态 · 工作线程循环 · 收口判据 |
//! | [`叶子执行`](叶子执行.rs) | **唯一**可进原池/调度核心的业务叶子 + 防递归标记 |
//! | [`资源接线`](资源接线.rs) | 资源键推导 + 提供者试取回调（不另建占用表） |
//! | [`任务跟踪`](任务跟踪.rs) | 生成中的查询/取消/释放（生成中不算成功） |
//! | [`任务存储`](任务存储.rs) | 内存任务记录 + 可注入存储回调（真库走注入） |
//!
//! # 判据
//!
//! - **只剩一条业务叶子**：进扩展的地方只有 [`叶子执行`](叶子执行.rs)，
//!   `适配器::调用能力带追踪` 已不再直接调调度核心。
//! - **不持宿主**：执行侧拿的是叶子执行口（真实现里是执行快照），不成 `Arc` 环。
//! - **不改内核**：调度器、资源车道、状态机全部来自 `v1_dispatch`，本层只装配。

