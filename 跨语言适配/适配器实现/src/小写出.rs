//! JSON 写出 —— **手写，零第三方依赖**（本仓硬规矩：进制品的形态零第三方依赖）。
//!
//! # 只做接口描述用得到的那几样
//!
//! 形状**恰好六种**：对象 · 数组 · 文本 · 整数 · 逻辑 · 空值。够写
//! `平台_取接口描述` 的返回体，不多做一样。
//!
//! # 明确不做（写清边界，免得它悄悄长成「通用 JSON 库」）
//!
//! | 不做 | 为什么 |
//! |---|---|
//! | **不解析** | 边界只**写**不读。要读 JSON 的是调用方，不是平台 |
//! | **不支持注释** | JSON 标准里没有注释；支持它就是自造方言 |
//! | **不支持浮点** | 接口描述里一个浮点都没有（编号 · 个数 · 类型标签 · 状态位 · 码全是整数）⇒ 不引 `f64`，也就不会碰上 `NaN` / `Infinity` 这类非法 JSON 值 |
//! | **不转 `\uXXXX`** | 非 ASCII 原样走 UTF-8（`接口面形状.md` 的响应体声明 `charset=utf-8`）。转义会让体积大三倍且更难读 |
//! | **不排序键** | 键序 = 插入序（对象是 `Vec`，不是哈希表）⇒ 同一份数据两次序列化逐字节相同（确定性优先） |
//!
//! 字符串转义**只做必须做的**：`"` `\` 与 `U+0000..U+001F` 控制字符。其余字符原样。
//! 少转一个控制字符就产出非法 JSON，多转一个就是无谓体积。

/// 接口描述用得到的值形状。**六种就是六种**。
pub enum JSON值 {
    空值,
    逻辑真,
    逻辑假,
    整数(i64),
    文本(String),
    数组(Vec<JSON值>),
    /// 键序 = 插入序（见文件头：确定性）。
    对象(Vec<(String, JSON值)>),
}

/// 序列化为**缩进版**（两空格）JSON 文本，**不含**结尾换行。
///
/// 缩进的理由与 `接口面形状.md` 同一条：根端点的返回是给人也是给 agent 读的说明书，
/// 压成一行就丢掉了这层用途。
pub fn 写协议值(值: &JSON值) -> String {
    let mut 出 = String::new();
    写值(&mut 出, 值, 0);
    出
}

/// 缩进一个单位（两空格）并换行。**公开**：`对外接口面/调用接口面/src/协议写出.rs` 也用它 ——
/// 同一套排版只许有一份实现。
pub fn 缩进(出: &mut String, 层: usize) {
    出.push('\n');
    for _ in 0..层 {
        出.push_str("  ");
    }
}

fn 写值(出: &mut String, 值: &JSON值, 层: usize) {
    match 值 {
        JSON值::空值 => 出.push_str("null"),
        JSON值::逻辑真 => 出.push_str("true"),
        JSON值::逻辑假 => 出.push_str("false"),
        JSON值::整数(数) => 出.push_str(&数.to_string()),
        JSON值::文本(文) => 写文本(出, 文),
        JSON值::数组(项) => {
            if 项.is_empty() {
                出.push_str("[]");
                return;
            }
            出.push('[');
            for (序, 一) in 项.iter().enumerate() {
                if 序 > 0 {
                    出.push(',');
                }
                缩进(出, 层 + 1);
                写值(出, 一, 层 + 1);
            }
            缩进(出, 层);
            出.push(']');
        }
        JSON值::对象(成员) => {
            if 成员.is_empty() {
                出.push_str("{}");
                return;
            }
            出.push('{');
            for (序, (键, 一)) in 成员.iter().enumerate() {
                if 序 > 0 {
                    出.push(',');
                }
                缩进(出, 层 + 1);
                写文本(出, 键);
                出.push_str(": ");
                写值(出, 一, 层 + 1);
            }
            缩进(出, 层);
            出.push('}');
        }
    }
}

/// 写一个 JSON 字符串：只转 `"` `\` 与 `U+0000..U+001F`（见文件头）。
/// 把一个字符串按 JSON 规则转义着写进去。**公开**：转义表是**正确性资产**
/// （少转一个控制字符就产出非法 JSON）⇒ 只许有一份，上层复用本函数。
pub fn 写文本(出: &mut String, 文: &str) {
    出.push('"');
    for 字 in 文.chars() {
        match 字 {
            '"' => 出.push_str("\\\""),
            '\\' => 出.push_str("\\\\"),
            '\n' => 出.push_str("\\n"),
            '\r' => 出.push_str("\\r"),
            '\t' => 出.push_str("\\t"),
            '\u{08}' => 出.push_str("\\b"),
            '\u{0C}' => 出.push_str("\\f"),
            // 其余控制字符必须转义（裸控制字符不是合法 JSON）。
            字 if (字 as u32) < 0x20 => 出.push_str(&format!("\\u{:04x}", 字 as u32)),
            字 => 出.push(字),
        }
    }
    出.push('"');
}
