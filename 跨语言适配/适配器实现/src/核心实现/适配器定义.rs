//! 核心实现 · 适配器本体 —— 一个已装载单元与那个**全平台唯一的适配器**。
//!
//! 本件从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现），
//! **纯搬家**：类型名、字段、方法体、文档一字不改。字段可见性由「私有」放宽为
//! `pub(crate)` —— 读侧（`契约读取.rs`）· 通知腿（`通知口.rs`）· 留痕腿（`留痕口.rs`）·
//! 释放口（`值归还.rs`）都在**同 crate 的兄弟模块**里写 `impl 适配器` 并直接读这些字段，
//! 而字段私有只在「定义它的模块及其后代」里可见 —— 本类型搬进子模块后，
//! 兄弟模块不再是它的后代，故必须 `pub(crate)`。**对外公开面不变**（字段原本就私有，
//! 外部调用方只能经方法访问）。

use std::sync::{Arc, Mutex};
use std::sync::atomic::{AtomicU64, AtomicUsize};

use v1_contract::{能力号, 已载入台账, 平台信息, 数据槽};
use v1_dispatch::{配额窗口毫秒, 配额账本, 调用结果};
use v1_registry::统一注册表;
use v1_trace::留痕缓冲;

use crate::契约读取::读契约串;
use crate::线程安全::{取锁, 通知账, 通知标识项};

use super::形状::{装载失败, 转发结果};

/// 一个已装载声明：一份声明 + 它建出的注册表。
///
/// 为什么要连声明一起留：读侧要的「可抛错误码」在 `平台信息.错误码表` 字段里，
/// 而 [`注册表`] 只把四张表收进去、不公开 `错误码表`（见文件头缺口 3）。
pub(crate) struct 已装载声明 {
    pub(crate) 声明: &'static 平台信息,
    pub(crate) 注册表: 统一注册表,
}

/// **全平台唯一的适配器**：读契约 → 装载内核 → 转发调用。
///
/// 形状是「一个实例一套东西」：装载单元表 + 一本配额账本 + 一条通知账 + 一条留痕缓冲。
/// **没有任何进程级 `static`**，所以同进程里开两份适配器就是两个互不干扰的配额域
/// 与两条互不串的通知端点表（多实例安全）。
///
/// # 线程安全
///
/// 本类型 `Send` + `Sync`：网关才能把**同一个适配器**交给多个工作线程并发收连接。
/// 断言的依据与边界逐条写在 `线程安全.rs` 的文件头（这是全 crate 唯一一条 `unsafe`
/// 线程安全断言）；三个可变点各自的同步方式：
///
/// - `账本`：`配额账本` 内部用 `Mutex`（它本来就是为 `&self` 共享设计的）；
/// - `通知`：通知通道（内含 `RefCell`）与按标识的索引合起来放进一把 `Mutex`；
/// - `留痕`：`留痕缓冲` 逐字段原子，`追加一条` 取 `&self`；`追踪号` 是 `AtomicU64`。
///
/// `装载单元s` 与 `台账` 在**装载完成后只读**（且指向 `'static` 静态数据，并发读无写）；
/// 运行期的 [`适配器::追加装载`] 要写它们，故取 `&mut self` —— 由调用方（网关的 `RwLock`）
/// 持写锁保证独占，`&self` 下仍然无写。
///
/// 账本的上限与窗口**取自 `调用调度` 的常量**（[`配额上限`] · [`配额窗口毫秒`]）：
/// 适配器不给调用方另开一个「自设配额」的口 —— 那会让配额口径变成每处一套，
/// 与「单项超时口径唯一」同一条理由。
pub struct 适配器 {
    /// 路由表：每份已装载声明一个 `Arc` 单元。**执行引用 = 本表的快照**（`Clone` 深拷本表）：
    /// 在途执行持一份独立快照，运行期装载只换主实例的表 ⇒ 旧链排空、互不串。
    pub(crate) 装载单元s: Vec<Arc<已装载声明>>,
    /// 已载入台账：标识串唯一 / 号段不冲突 / 依赖都在（判定 ②③⑤）的**唯一判据**。
    ///
    /// **按实例持有**（不落进程级全局，宪法三条补缺陷：状态显式持有为句柄）。
    /// `装载声明根` 建它、`追加装载` 用它 —— 运行期追加装载靠它判重与判冲突，
    /// 故必须**存进结构**（早先它是 `装载声明根` 里的局部变量，装完即丢）。
    /// **随 `Clone` 由路由表重建**（见 `由装载单元重建台账`）：候选切换要能在独立副本上
    /// 摘旧装新，不能改到主实例的账。
    pub(crate) 台账: v1_loader::载入台账,
    /// 配额账本：**跨版本共享**（`Arc`）—— 运行期升级不许把配额读数清零。
    pub(crate) 账本: Arc<配额账本>,
    /// 通知口：已载入扩展申报的 `通知函数` 在这里注册成端点，
    /// 生命周期通知（装载/卸载/退出）才送得到扩展。通道与按标识的索引同一把锁。
    /// **跨版本共享**（`Arc`）—— 通知端点表是实例级的，不随一次装载换本。
    pub(crate) 通知: Arc<Mutex<通知账>>,
    /// 调用留痕：`装载` 不开口，装配侧按契约常量 `留痕容量` 给容量即开。
    /// **跨版本共享**（`Arc`）—— 运行期装载不许把调用留痕抹掉。
    pub(crate) 留痕: Option<Arc<留痕缓冲>>,
    /// 本实例单调递增的调用序号（留痕的 `追踪号`）。**不是进程级全局**。跨版本共享。
    pub(crate) 追踪号: Arc<AtomicU64>,
    /// **在途执行引用数**：正在执行（`调用能力` 已进未出）的引用条数。
    /// 执行引用 = 路由快照（`Clone` 出的适配器）⇒ 在途引用有效期间旧链不被换、不销毁；
    /// 这就是 W01 裁的「执行租约」——租约在途期间宿主不得卸载动态库或销毁其上下文。
    /// 跨版本共享（`Arc`）：装载/卸载看的是同一个计数。
    pub(crate) 在途执行数: Arc<AtomicUsize>,
    /// **跨进程执行域表**：登记了域的号走工作进程，没登记的号走进程内转发（原路一字不动）。
    ///
    /// 按实例持有（`Arc<Mutex<..>>`，与 `通知` 同一形状）：`调用能力` 取 `&self`，
    /// 而登记域与发帧都要可变 ⇒ 这个字段自持一把锁。**不落 static**（同进程两份适配器
    /// 就是两套互不可见的执行域）。
    ///
    /// `None` = 本实例从不跨进程（默认）：那时连一把锁都不花，进程内路一分钱不多。
    #[cfg(unix)]
    pub(crate) 跨进程: Option<Arc<Mutex<crate::进程调用::跨进程域表>>>,
    /// 本实例的**适配器实例号**（跨进程执行域标识的头一个分量）。
    /// 取一个单调值，不落 static；同进程两份适配器天然不同号。
    pub(crate) 实例号: u64,
}

impl 适配器 {
    /// 装载**一个**声明：建台账 → 判定 → 载入 → 持有注册表。
    ///
    /// 台账从**空**起步（[`载入台账::空实例`](v1_loader::载入台账::空实例)），载入成功后由本函数调
    /// [`载入台账::登记标识串`](v1_loader::载入台账::登记标识串) 记进去。**不许**用
    /// [`载入台账::新建`](v1_loader::载入台账::新建) 起步：那会预置底座自身的
    /// 占用，于是**底座自身的声明**在判定 ② 就被判成「冒用底座身份 / 已在台账里」而载不进来。
    pub fn 装载(声明: &'static 平台信息) -> Result<Self, 装载失败> {
        Self::装载声明根(&[声明])
    }

    /// 装载一个**声明根**（一串声明）：按给定顺序**序贯**走完台账，每份一个注册表。
    ///
    /// # 顺序即依赖序
    ///
    /// 台账是「谁已经载入了」的唯一判据（判定 ②③⑤ 全走它），而 [`载入台账`] 的
    /// [`登记标识串`](v1_loader::载入台账::登记标识串) 由**调用方**在载入成功后调（`载入声明` 收的是只读的
    /// `&dyn 已载入台账`，改不了台账）。所以「一个扩展怎么加进去」的现成口就是这里：
    ///
    /// ```text
    /// 台账 = 载入台账::空实例()
    /// 逐份声明：  载入声明(声明, &台账)?  →  台账.登记标识串(声明)
    /// ```
    ///
    /// 底座排在最前（扩展的 ⑤ 依赖清单要能命中它），后面的扩展自然看得见前面的。
    /// 这样既不需要 `载入台账::新建()` 那个「预置底座」的特例，也不给底座开特例分支。
    ///
    /// # 编号与路由
    ///
    /// 每份声明的命令编号都**取自声明**（`命令信息.编号`），注册表按编号二分查找认领；
    /// 转发调用按「**谁认这个号就归谁**」路由（第一份认领者胜），实测见测试
    /// `实测_命令编号来自声明`。编号是否落在声明号段内的校验在既有件（`装载入口`），不在本 crate。
    pub fn 装载声明根(声明根: &[&'static 平台信息]) -> Result<Self, 装载失败> {
        if 声明根.is_empty() {
            return Err(装载失败::空声明根);
        }
        // 台账**按实例建**，不落进程级全局（宪法三条补缺陷：状态显式持有为句柄）。
        // 它**存进结构**（不是局部变量）—— 运行期 `追加装载` 要用它判 ②③⑤。
        let mut 适配器 = Self {
            装载单元s: Vec::with_capacity(声明根.len()),
            台账: v1_loader::载入台账::空实例(),
            账本: Arc::new(配额账本::构造(crate::配额上限, 配额窗口毫秒)),
            通知: Arc::new(Mutex::new(通知账::构造())),
            留痕: None,
            追踪号: Arc::new(AtomicU64::new(0)),
            在途执行数: Arc::new(AtomicUsize::new(0)),
            #[cfg(unix)]
            跨进程: None,
            实例号: crate::进程调用::取实例号(),
        };
        for 声明 in 声明根.iter().copied() {
            适配器.装载一份(声明)?;
        }
        Ok(适配器)
    }

    /// **运行期追加装载**：对**已存在**的适配器再载入一份声明
    /// （台账 237「不重启网关载入新扩展」）。
    ///
    /// 取 `&mut self`（由调用方持写锁）：**不在适配器内部加锁** —— 那会推翻
    /// 「`装载单元s` 装载完成后只读、并发读无写」这条不变量。写只在 `&mut` 下发生，
    /// 调用方以写锁保证独占，故并发读仍然无写。
    ///
    /// **只追加，不重建**：重建 [`适配器::装载声明根`] 会清掉 `账本`（配额读数）·
    /// `留痕`（调用留痕）· `追踪号` —— 运行期装载**不该**把调用留痕抹掉。
    /// 判定 ②③⑤ 全走结构里那本 `台账`。
    pub fn 追加装载(&mut self, 声明: &'static 平台信息) -> Result<(), 装载失败> {
        self.装载一份(声明)
    }

    /// 这份声明的标识串是不是**已在**台账里（运行期装载据此跳过已载入的候选，保持幂等）。
    pub fn 已装载标识(&self, 声明: &平台信息) -> bool {
        self.台账.是否已载入(声明.标识串)
    }

    /// **收回装载**：把一份已装载声明从路由与台账里摘掉（卸载的第二步）。
    ///
    /// 与 [`适配器::追加装载`] 对称（一个加、一个减），取 `&mut self`：写 `装载单元s` 与
    /// `台账`，由调用方持写锁保证独占，中途不释放（不许并发调用挤进来）。
    ///
    /// 做两样：
    /// ① 从 `装载单元s` 摘掉那个单元（[`适配器::取注册表`] 不再认它的号）；
    /// ② 从 `台账` 注销它的标识串与号段（否则同一身份永远重载不进来，判定 ② 报「标识串非法」）。
    ///
    /// 返回是否真摘了一个。两条保护：
    /// - **底座声明永不摘**（它是宿主自身，路由与读侧按 `装载单元s[0]` 兜底，摘了会让那些索引越界）；
    /// - **最后一份不摘**（保「`装载单元s` 非空」这条不变量）。
    pub fn 收回装载(&mut self, 声明: &'static 平台信息) -> bool {
        if core::ptr::eq(声明, v1_loader::底座声明()) || self.装载单元s.len() <= 1 {
            return false;
        }
        let Some(装载位置) = self
            .装载单元s
            .iter()
            .position(|装载单元| core::ptr::eq(装载单元.声明, 声明))
        else {
            return false;
        };
        let 已卸载声明 = self.装载单元s.remove(装载位置).声明;
        self.台账.注销标识串(已卸载声明);
        true
    }

    /// 按标识串文本找那份已装载声明（卸载口用；找不到给 `None`）。
    ///
    /// 按**声明自身的标识串文本**认那一份（不按下标：下标会随别的装卸漂移）。
    pub(crate) fn 按标识找声明(&self, 本扩展标识串: &str) -> Option<&'static 平台信息> {
        self.装载单元s.iter().find_map(|装载单元| {
            let 声明 = 装载单元.声明;
            if 声明.标识串.is_null() {
                return None;
            }
            // SAFETY: 契约保证 标识串 是静态只读 NUL 结尾串。
            (unsafe { 读契约串(声明.标识串) } == 本扩展标识串).then_some(声明)
        })
    }

    /// 装载**一份**声明：判定 + 载入 + 登记台账 + 登记通知端点 + 持有注册表。
    ///
    /// **全平台唯一的那一处 `载入声明`**（拓扑判据第 3 条）：[`适配器::装载声明根`] 与
    /// [`适配器::追加装载`] 都走这里，故全仓只有本函数调 `v1_loader::载入声明`。
    /// 判定不过就整体失败，不留半个装载单元。
    pub(crate) fn 装载一份(&mut self, 声明: &'static 平台信息) -> Result<(), 装载失败> {
        // 全平台唯一的那一处 `载入声明`（拓扑判据第 3 条）。
        let 项表 = v1_loader::载入声明(声明, &self.台账).map_err(装载失败::载入失败)?;
        self.台账.登记标识串(声明);
        // 通知口：装载时把**非底座**声明申报的 `通知函数` 登记成端点
        // —— 「申报了就送得到」。底座是宿主自身（它发通知，不是收通知的扩展端点），不登记。
        if !core::ptr::eq(声明, v1_loader::底座声明())
            && let Some(端点函数) = 声明.通知函数
        {
            let mut 通知 = 取锁(&self.通知);
            通知.通道实例.注册通知端点(声明.标识串, 端点函数);
            // 索引：文本 → 指针（HTTP 面只有文本）。空标识串不进索引（无法寻址）。
            if !声明.标识串.is_null() {
                // SAFETY: 契约保证 标识串 是静态只读 NUL 结尾串。
                let 源文本 = unsafe { 读契约串(声明.标识串) };
                if !源文本.is_empty() && !通知.标识表.iter().any(|标识项| 标识项.本扩展标识串 == 源文本) {
                    通知.标识表.push(通知标识项 {
                        本扩展标识串: 源文本,
                        指针: 声明.标识串,
                    });
                }
            }
        }
        self.装载单元s.push(Arc::new(已装载声明 {
            声明,
            注册表: 项表,
        }));
        // 2000 装载：装载单元已成形、端点已登记，再通知扩展一次（「被载入后收到一次」）。
        // 不在临界区里调扩展（`注册通知端点` 那段锁已释放）；底座不发（它发通知，不是收通知的端点）。
        if !core::ptr::eq(声明, v1_loader::底座声明()) && 声明.通知函数.is_some() {
            self.装载通知(声明.标识串);
        }
        Ok(())
    }

    /// **转发调用**：`(能力号, 参数, 返回槽) -> 结构化结果`。
    ///
    /// 必须经 [`v1_dispatch::调用`] —— 本函数**不自行取号、不自行校参数、不自行问配额**：
    /// 那四件事（超时 · 配额 · 占位兜底 · 已废止判定）只有一份实现，在调度层。
    ///
    /// 失败一律是结构化段位（含未命中 ⇒
    /// [`调度错误::提供者未载入`](v1_dispatch::调度错误::提供者未载入)），**不 panic**；
    /// 失败时返回槽由调度层置空（宪法第 6 条「未命中返回空」）。
    ///
    /// # 参数约定（调用方须保证）
    ///
    /// `参数` 的每个槽都已按 `能力契约::参数表` 的**行序**填好；个数与声明一致。
    /// 个数不符不会崩，会拿到
    /// [`调度错误::参数个数不符`](v1_dispatch::调度错误::参数个数不符)。
    pub fn 调用能力(&self, 编号: u32, 入参: &[数据槽], 返回槽: &mut 数据槽) -> 转发结果 {
        let (转发, 追踪号值) = self.调用能力带追踪(编号, 入参, 返回槽);
        let _ = 追踪号值; // 只借不读：本口不回报追踪号（要号的走 调用能力带追踪）。
        转发
    }

    /// 同 [`适配器::调用能力`]，但**把这次的追踪号一并交回**。
    ///
    /// # 为什么追踪号要在**调用开头**取（而不是写留痕时才取）
    ///
    /// §9.2「结构化结果保留成功或失败、值或错误码、**追踪标识**」要求调用应答带追踪标识。
    /// 若追踪号仍只在 `记一条留痕` 里 `fetch_add`，那它就晚于应答组装 —— 应答拿不到、
    /// 只能再补一个号：**留痕与应答两套号**，正是「同一事实两处来源」的形态。
    /// ⇒ 号在进调用时取一次，既写进留痕、又随结果交回，两处**同一个号**。
    ///
    /// 没启用留痕时**不取号**（`追踪号` 恒 `0`）——留痕关着就没有「第几条留痕」这件事，
    /// 报一个号反而是编的。号位与 [`适配器::留痕已启用`] 同一判据。
    pub fn 调用能力带追踪(
        &self,
        编号: u32,
        入参: &[数据槽],
        返回槽: &mut 数据槽,
    ) -> (转发结果, u64) {
        // 号空间：本函数是**跨语言边界**（外面给的是裸 `u32`）⇒ 在这里包一次，往内一律走
        // `能力号`；留痕口要的仍是裸号，故它拿 `编号`。
        let 号值 = 能力号::构造(编号);
        let 区间起点 = std::time::Instant::now();
        // 追踪号：**进来就取**（见本函数头）——留痕与调用应答共用这一个号。
        let 追踪号值 = if self.留痕.is_some() {
            self.追踪号.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
        } else {
            0
        };
        // 在途引用：进来加一、出去减一（RAII，含早退路径）。执行期间主实例若装载/卸载，
        // 本调用仍持本次的路由快照（`&self` 就是快照）⇒ 旧链不换、不销毁。
        let 在途守卫 = crate::候选发布::在途引用::取得(&self.在途执行数);
        let _ = &在途守卫; // 只借不读：守卫活到函数末尾，Drop 时释放（RAII）。
        // 跨进程执行域：这个号**登记过域**就走工作进程（载体隔离），没登记就走下面那条
        // 进程内原路。两条路的返回形状逐字一致（都是 `转发结果`，失败都在返回槽里）⇒
        // 「进程内 / 跨进程同读数」不是巧合，是同一套协议在两种载体上的必然。
        #[cfg(unix)]
        let 跨进程读数 = self.调用跨进程(号值, 入参, 返回槽);
        #[cfg(not(unix))]
        let 跨进程读数: Option<转发结果> = None;
        let 转发 = match 跨进程读数 {
            Some(转发值) => 转发值,
            None => {
                let 项表 = self.取注册表(号值);
                // SAFETY: `返回槽` 是本函数独占的可写槽（`&mut` 保证）；`参数` 由调用方按契约填好。
                let 关口结果 =
                    unsafe { v1_dispatch::调用命令(项表, &*self.账本, 号值, 入参, 返回槽 as *mut 数据槽) };
                match 关口结果 {
                    调用结果::成功 => 转发结果::成功(*返回槽),
                    调用结果::失败(失败值) => 转发结果::失败(失败值),
                }
            }
        };
        // 留痕：调用**返回之后**记一条，不进关键路径（`留痕缓冲::追加一条` 不取锁、
        // 不分配、不阻塞）。没启用留痕时它是空操作，调用结果不受影响。
        let 耗时微秒 = u64::try_from(区间起点.elapsed().as_micros()).unwrap_or(u64::MAX);
        self.记一条留痕(编号, 入参, &转发, 耗时微秒, 追踪号值);
        (转发, 追踪号值)
    }

}
