//! 候选发布与版本切换 —— 执行引用快照 · 在途引用 · 同身份新版切换。
//!
//! 依据：`临时件/W01_裁决_架构升级.md` 六项未定项（重放及引用归属 · 进程池粒度）·
//! `临时件/派活_W/W05_生命周期与切换.md`。
//!
//! # 执行引用 = 路由快照
//!
//! `适配器::clone` 深拷路由表（每单元 `Arc` 克隆，不复制注册表）、由路由表**重建**独立台账；
//! 配额账本 · 通知账 · 留痕 · 追踪号 · 在途计数**共享**（实例级）。装载/卸载改的是路由表与
//! 台账（必须每副本一份），配额 / 留痕 / 通知是实例级事实（换版本不许清零、不许丢端点、
//! 不许抹痕）⇒ 快照天然给出「旧链排空」（在途持旧快照）与「候选不污染主实例」。
//!
//! # 在途引用与执行租约
//!
//! [`在途引用`] 是 RAII 守卫：`调用能力` 进来加一、出去减一。执行引用有效期间宿主不得换链 /
//! 卸载（W01 裁的「执行租约」）—— 守卫把「在途」变成一个可观察、必然释放的计数。
//!
//! # 候选发布（失败候选不发布）
//!
//! [`适配器::追加候选`] / [`适配器::升级候选`] 都在**副本**上装载：成功交出新适配器（由调用方
//! 发布），失败 ⇒ `Err`，主实例一个字段不改。同身份新版走 [`适配器::升级候选`]：先摘旧身份、
//! 再装新声明；[`适配器::升级装载`] 就地整体替换。

use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};

use v1_contract::平台信息;

use crate::适配器;
use crate::契约读取::读契约串;
use crate::装载失败;
use crate::核心实现::适配器定义::已装载声明;

/// `Clone` = **执行引用快照**：深拷路由表（每单元 `Arc` 克隆，不复制注册表）、
/// 由路由表**重建**独立台账；配额账本 · 通知账 · 留痕 · 追踪号 · 在途计数**共享**（实例级）。
///
/// 为什么这样切：装载/卸载改的是路由表与台账（这两个**必须每副本一份**，候选才摘得动、
/// 换得掉）；而配额 / 留痕 / 通知是**实例级事实**，换版本不许清零、不许丢端点、不许抹痕。
/// ⇒ 快照天然给出「旧链排空」（在途持旧快照）与「候选不污染主实例」。
impl Clone for 适配器 {
    fn clone(&self) -> Self {
        Self {
            装载单元s: self.装载单元s.clone(),
            台账: 由装载单元重建台账(&self.装载单元s),
            账本: Arc::clone(&self.账本),
            通知: Arc::clone(&self.通知),
            留痕: self.留痕.clone(),
            追踪号: Arc::clone(&self.追踪号),
            在途执行数: Arc::clone(&self.在途执行数),
        }
    }
}

/// 由路由表重建一本台账：逐单元 `登记标识串`（标识串 + 号段 + 类型标签）。
///
/// 台账的权威内容就是「已载入声明集」的占用；路由表是同一份事实的另一面 ⇒ 重建等价于原台账
/// （判定只看向量成员，不看向量序）。`载入台账` 自身不可克隆（字段私有），
/// 故走这条等价重建，不去改 `运行内核/装载入口` 的公开面。
fn 由装载单元重建台账(装载单元s: &[Arc<已装载声明>]) -> v1_loader::载入台账 {
    let mut 台账 = v1_loader::载入台账::空实例();
    for 装载单元 in 装载单元s {
        台账.登记标识串(装载单元.声明);
    }
    台账
}

/// 在途引用守卫：构造即加一，`Drop` 即减一（RAII，含早退与展开路径）。
///
/// 执行引用有效期间宿主不得换链 / 卸载 —— 守卫把「在途」这件事变成一个可观察、必然释放的计数。
pub(crate) struct 在途引用 {
    引用计数: Arc<AtomicUsize>,
}

impl 在途引用 {
    pub(crate) fn 取得(引用计数: &Arc<AtomicUsize>) -> Self {
        引用计数.fetch_add(1, Ordering::AcqRel);
        Self { 引用计数: Arc::clone(引用计数) }
    }
}

impl Drop for 在途引用 {
    fn drop(&mut self) {
        self.引用计数.fetch_sub(1, Ordering::AcqRel);
    }
}

impl 适配器 {
    /// 当前在途执行引用数（就绪/切换读数用；执行引用有效期间 > 0）。
    pub fn 在途执行数(&self) -> usize {
        self.在途执行数.load(Ordering::Acquire)
    }

    /// 公开口：按**声明自身**的标识串找已装载的旧声明（同身份判定 / 版本切换用）。
    /// 新声明还没进表 ⇒ 找到的必是旧版；找不到给 `None`。
    pub fn 找同身份声明(&self, 声明: &平台信息) -> Option<&'static 平台信息> {
        if 声明.标识串.is_null() {
            return None;
        }
        // SAFETY: 契约保证 标识串 是静态只读 NUL 结尾串。
        let 本扩展标识串 = unsafe { 读契约串(声明.标识串) };
        self.按标识找声明(&本扩展标识串)
    }

    /// 按标识串文本找单元位（候选切换用；找不到 `None`）。
    pub(crate) fn 找单元位(&self, 本扩展标识串: &str) -> Option<usize> {
        self.装载单元s.iter().position(|装载单元| {
            let 声明 = 装载单元.声明;
            // SAFETY: 契约保证 标识串 是静态只读 NUL 结尾串。
            !声明.标识串.is_null() && unsafe { 读契约串(声明.标识串) } == 本扩展标识串
        })
    }

    /// 摘掉第 `位置` 个单元并注销它的台账占用（候选切换用）。底座与最后一份受保护，返回是否真摘。
    pub(crate) fn 摘单元(&mut self, 位置: usize) -> bool {
        if self.装载单元s.len() <= 1 || 位置 >= self.装载单元s.len() {
            return false;
        }
        let 声明 = self.装载单元s[位置].声明;
        if core::ptr::eq(声明, v1_loader::底座声明()) {
            return false;
        }
        self.装载单元s.remove(位置);
        self.台账.注销标识串(声明);
        true
    }

    /// **追加候选**：在副本上装一份新声明，成功交出新适配器（由调用方发布）。
    /// 失败 ⇒ `Err`，本适配器一个字段不改（**失败候选不发布**）。
    pub fn 追加候选(&self, 声明: &'static 平台信息) -> Result<Self, 装载失败> {
        let mut 候选 = self.clone();
        候选.装载一份(声明)?;
        Ok(候选)
    }

    /// **升级候选（同身份新版）**：副本上先摘同标识串的旧单元、再装新声明。
    /// 新声明的标识串必须已在本实例（否则不是升级）⇒ 找不到即 `Err`。
    /// 校验不过 ⇒ `Err`，主实例不受影响（**失败候选不发布**）。
    pub fn 升级候选(&self, 声明: &'static 平台信息) -> Result<Self, 装载失败> {
        if 声明.标识串.is_null() {
            return Err(装载失败::载入失败(v1_loader::载入错误::标识串非法));
        }
        // SAFETY: 契约保证 标识串 是静态只读 NUL 结尾串。
        let 本扩展标识串 = unsafe { 读契约串(声明.标识串) };
        let Some(位置) = self.找单元位(&本扩展标识串) else {
            return Err(装载失败::载入失败(v1_loader::载入错误::标识串非法));
        };
        let mut 候选 = self.clone();
        if !候选.摘单元(位置) {
            return Err(装载失败::载入失败(v1_loader::载入错误::标识串非法));
        }
        候选.装载一份(声明)?;
        Ok(候选)
    }

    /// **升级装载（同身份新版，就地发布）**：候选成功再整体替换（**失败候选不发布**）。
    /// 旧链排空由快照给出：在途执行持独立的旧快照，本函数只换主实例的路由表。
    pub fn 升级装载(&mut self, 声明: &'static 平台信息) -> Result<(), 装载失败> {
        let 候选 = self.升级候选(声明)?;
        *self = 候选;
        Ok(())
    }
}
