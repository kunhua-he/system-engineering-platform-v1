/// 判据：本 crate 生产代码里导出符号**恰好一组四个**，且**不含**接缝 `GetPlatformInfo`。
#[test]
fn 导出符号_恰好四个且不含接缝() {
    let 允许: Vec<String> = ["平台_取接口描述", "平台_调用", "平台_释放值", "平台_释放接口描述"]
        .iter()
        .map(|名| (*名).to_owned())
        .collect();

    let mut 名称 = Vec::new();
    for (_, 文) in 生产源 {
        名称.extend(扫导出名(文));
    }
    assert_eq!(名称.len(), 4, "四个符号各恰好一次（重复导出同一名也是多条腿）：{名称:?}");

    let mut 去重 = 名称.clone();
    去重.sort();
    去重.dedup();
    assert_eq!(去重, 允许, "导出符号恰好这四个，一个不多一个不少");

    assert!(
        !名称.iter().any(|一| 一 == "GetPlatformInfo"),
        "接缝是**反方向**（扩展 → 宿主），本边界不许导出它"
    );
    for (文件, 文) in 生产源 {
        assert!(
            !文.contains("#[no_mangle]"),
            "{文件} 不许用 `#[no_mangle]`（导出只走 `export_name` 这一条路）"
        );
    }

    // ── 反向样本：判据不是空转 ──
    let 注入多余 = r#"#[unsafe(export_name = "平台_多一个")]
pub extern "C" fn 多余() -> usize { 0 }"#;
    let 抓到 = 扫导出名(注入多余);
    assert_eq!(抓到, vec!["平台_多一个".to_owned()], "反向样本：多余的导出必须被扫出来");
    assert!(!允许.contains(&抓到[0]), "它不在允许集里 ⇒ 判据会报红（这正是它该抓的违规）");

    let 注入接缝 = r#"#[unsafe(export_name = "GetPlatformInfo")]
pub extern "C" fn 取() {}"#;
    assert!(
        扫导出名(注入接缝).iter().any(|一| 一 == "GetPlatformInfo"),
        "反向样本：接缝符号也必须被扫出来（否则「不含 GetPlatformInfo」是空话）"
    );

    // 注释里提一句不算导出（去行注释真的生效）。
    assert!(扫导出名("// #[unsafe(export_name = \"平台_注释里\")]\n").is_empty());
}

