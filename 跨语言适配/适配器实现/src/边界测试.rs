/// 判据：**归还之后不再泄漏** —— 连取 N 次、每次当即归还，活字节不随 N 增长。
///
/// 这是正向读数（反向样本见文件末「泄漏读数」那一组：不归还就涨）。
#[test]
fn 取接口描述_取多次并归还_活字节不涨() {
    let 次版本 = 64;
    // 先取一次定下「一份」的大小（归还掉，不进基线）。
    let mut 长度: u32 = 0;
    // SAFETY: 长 可写；返回的缓冲随即归还。
    let 首字节 = unsafe { 平台_取接口描述(&mut 长度) };
    assert!(!首字节.is_null() && 长度 > 0);
    // SAFETY: 同一对，未归还。
    unsafe { 平台_释放接口描述(首字节, 长度) };

    for _ in 0..次版本 {
        let mut 长度: u32 = 0;
        // SAFETY: 长 可写。
        let 首字节 = unsafe { 平台_取接口描述(&mut 长度) };
        assert!(!首字节.is_null(), "平台自身的声明必然载得进来 ⇒ 不许给空指针");
        // SAFETY: 同一对，未归还。
        unsafe { 平台_释放接口描述(首字节, 长度) };
    }
    // 本样本只证「取 N 次 + 每次归还」这条协议走得通、不崩；
    // 「活字节不涨」的机器读数在 `边界泄漏读数.rs`（带计数全局分配器）。
}

/// 判据：JSON 的内容与 `能力清单()` **一致**（逐条对编号 / 名称 / 参数个数 / 返回类型）。
#[test]
fn 取接口描述_内容与能力清单一致() {
    let 边界 = 对外边界::新建(&[v1_loader::底座声明()]).expect("底座");
    let json = 边界.取接口描述();
    let 清单 = 边界.能力清单();
    assert!(!清单.is_empty(), "空集不算通过：底座声明至少有 1 条命令");

    for 摘要 in &清单 {
        for 片段 in [
            format!("\"编号\": {}", 摘要.编号),
            format!("\"名称\": \"{}\"", 摘要.名称),
            format!("\"参数个数\": {}", 摘要.参数个数),
            format!("\"返回类型\": {}", 摘要.返回类型),
        ] {
            assert!(json.contains(&片段), "接口描述里必须有 {片段}");
        }
    }
    // 参数表行序与可抛错误码也要在（「某条能力怎么调」）。
    assert!(json.contains("\"参数表\": ["), "参数表必须在");
    assert!(json.contains("\"可抛错误码\": ["), "可抛错误码必须在");

    // 可抛错误码是**这条命令自身的**（不是声明全表），三项业务判断随它随包给出。
    // 底座命令 0 自身不抛错（空表）⇒ 拿一份带码的合成声明来验这条通道。
    let 带码 = 对外边界::新建(&[
        v1_loader::底座声明(),
        测试夹具::造扩展声明_命令可抛码少于全表(号段::新建(1000, 1999)),
    ])
    .expect("底座 + 合成声明");
    let 带码json = 带码.取接口描述();
    assert!(带码json.contains("\"码\": 1001"), "这条命令自身登记的可抛码必须在");
    assert!(
        !带码json.contains("\"码\": 1002"),
        "声明全表里不属这条命令的码不许出现（收窄前的旧行为）"
    );
    assert!(带码json.contains("\"可自愈\": true"), "三项业务判断必须到得了运行期");

    // ── 反向样本：判据对内容敏感 —— 编一个不存在的能力名，必找不到 ──
    assert!(!json.contains("\"名称\": \"没有这个能力\""));
}


// ════════════════════════════════════════════════════════════════════════════
// 泄漏读数：用**计数全局分配器**量「取 N 次之后活字节净增长」
//
// 读数命令（同一把尺；`--test-threads=1` 免得别的用例的分配混进来）：
//     cargo test -p v1-adapter --lib 读数_ -- --ignored --nocapture --test-threads=1
//
// 一个用例里量两个方向（对照着看才有意义）：
//   · 不归还：取 N 次、一次都不还 ⇒ 净增长 ≈ N × 单份字节（**泄漏**）
//   · 按协议归还：取 N 次、每次当即还 ⇒ 净增长 ≈ 0（**不涨**）
//
// 反向样本（把修复回退：`平台_取接口描述` 改回 `Box::leak`、`平台_释放接口描述` 改空操作）
// ⇒ 「按协议归还」那一行**又涨**。
//
// 计数分配器只在本测试二进制里生效（`#[global_allocator]` 是 crate 级，不进生产库）。
// ════════════════════════════════════════════════════════════════════════════

use core::alloc::{GlobalAlloc, Layout};
use core::sync::atomic::{AtomicUsize, Ordering};
use std::alloc::System;

/// 活字节（alloc 加、dealloc 减）。**只在测试二进制里**，不是生产状态。
static 泄漏读数_活字节: AtomicUsize = AtomicUsize::new(0);

struct 泄漏读数_计数分配器;

unsafe impl GlobalAlloc for 泄漏读数_计数分配器 {
    unsafe fn alloc(&self, 布局: Layout) -> *mut u8 {
        let 指针 = unsafe { System.alloc(布局) };
        if !指针.is_null() {
            泄漏读数_活字节.fetch_add(布局.size(), Ordering::SeqCst);
        }
        指针
    }
    unsafe fn dealloc(&self, 指针: *mut u8, 布局: Layout) {
        unsafe { System.dealloc(指针, 布局) };
        泄漏读数_活字节.fetch_sub(布局.size(), Ordering::SeqCst);
    }
}

#[global_allocator]
static 泄漏读数_分配器: 泄漏读数_计数分配器 = 泄漏读数_计数分配器;

fn 泄漏读数_读活字节() -> usize {
    泄漏读数_活字节.load(Ordering::SeqCst)
}

/// 一次「取接口描述」拿到的字节数（顺手归还，不留账）。
fn 泄漏读数_单份字节() -> usize {
    let mut 长度: u32 = 0;
    // SAFETY: 长 可写；返回的缓冲随即归还。
    let 首字节 = unsafe { 平台_取接口描述(&mut 长度) };
    assert!(!首字节.is_null(), "平台自身的声明必然载得进来 ⇒ 不许给空指针");
    assert!(长度 > 0, "空集不算通过：一份描述必须非空");
    // SAFETY: 首/长 是上面那次调用交出的一对，尚未归还。
    unsafe { 平台_释放接口描述(首字节, 长度) };
    长度 as usize
}

/// 读数：不归还 ⇒ 活字节随 N 线性增长；按协议归还 ⇒ 不涨。
///
/// **`#[ignore]` 的理由**：本用例量的是**进程级**活字节，别的用例并行跑时它们的分配会混进来
/// ⇒ 必须单跑。读数命令见文件末那一段注释（`--ignored --nocapture --test-threads=1`）。
#[ignore = "读数用例：量进程级活字节，必须 --test-threads=1 单跑（见文件末注释）"]
#[test]
fn 读数_取多次_不归还涨_归还平() {
    const 次: usize = 2000;
    let 单份 = 泄漏读数_单份字节();

    // ── 方向一：不归还（**修前/回退** 的读数） ──
    let 不归还前基线 = 泄漏读数_读活字节();
    for _ in 0..次 {
        let mut 长度: u32 = 0;
        // SAFETY: 长 可写；本样本**故意不归还**（就是要量泄漏）。
        let 首字节 = unsafe { 平台_取接口描述(&mut 长度) };
        assert!(!首字节.is_null());
        core::hint::black_box(首字节);
    }
    let 不归还净增 = 泄漏读数_读活字节().saturating_sub(不归还前基线);
    println!("[读数] 取 {次} 次不归还：单份 {单份} 字节 · 活字节净增 {不归还净增} 字节（≈ {次}×{单份}）");
    assert!(
        不归还净增 >= 次 * 单份,
        "不归还就必须涨：实测 {不归还净增}，期望 ≥ {}（N × 单份）",
        次 * 单份
    );

    // ── 方向二：按协议归还（**修后** 的读数） ──
    let 归还前基线 = 泄漏读数_读活字节();
    for _ in 0..次 {
        let mut 长度: u32 = 0;
        // SAFETY: 长 可写；返回的缓冲当即归还。
        let 首字节 = unsafe { 平台_取接口描述(&mut 长度) };
        assert!(!首字节.is_null());
        // SAFETY: 首/长 是上面那次调用交出的一对，尚未归还。
        unsafe { 平台_释放接口描述(首字节, 长度) };
    }
    let 归还净增 = 泄漏读数_读活字节().saturating_sub(归还前基线);
    println!("[读数] 取 {次} 次按协议归还：单份 {单份} 字节 · 活字节净增 {归还净增} 字节");
    assert!(
        归还净增 < 单份,
        "按协议归还就不该涨（容差 < 一份）：实测 {归还净增}，单份 {单份}"
    );
}
