//! 进程调用 —— 适配器持有的「跨进程执行域表」：把一条调用送到工作进程，并把失败翻成结构化码。
//!
//! 依据：`临时件/W01_裁决_架构升级.md`（六项未定项的推荐收口）·
//! `项目文档/决策记录/2026-10-06_子进程执行路前置裁决.md` 第二条（进程管理落点 = 适配器）与
//! 第三条（崩溃报 `0034`）。
//!
//! # 它补的是哪一段
//!
//! `进程池.rs` 管「进程活着没」（拉起 · 监督 · 退避重拉），`线协议.rs` 管「一次调用怎么摆进帧」，
//! 本件把两者接到**一条真实调用路**上：给定执行域 ⇒ 保证域在 ⇒（必要时）重放装载初始化 ⇒
//! 发起调用 ⇒ 收结果。它是「调度不碰进程」那条分工里**载体侧的一半**。
//!
//! # 状态按实例持有
//!
//! [`跨进程域表`] 是**适配器实例的东西**（`适配器.跨进程` 字段），**不落任何进程级 `static`** ——
//! 同进程里开两份适配器就是两个互不干扰的执行域表（多实例安全，与 `部署绑定` 同一条理由）。
//!
//! # 失败一律结构化
//!
//! 三条失败路 —— 拉起失败 / 熔断中 · 通道断开（EOF）⇒ 崩洏已查实 · 代次不符（陈旧句柄）——
//! 全部翻成**返回槽里的错误槽**（`类型标签_4294967295` + 码 `0034`），
//! **不 panic**、不给调度错误加进程变体。
//! 「调度判该不该报错，载体管进程活着没」：本件只把载体看到的事实报回去，
//! 怎么处理（重试 / 熔断 / 上报）由调用方与部署策略定。

use std::num::NonZeroU64;
use std::os::unix::net::UnixStream;
use std::sync::atomic::{AtomicU64, Ordering};

use v1_contract::{声明数据, 数据槽, 能力号};

use crate::进程池::{执行域标识, 进程池, 进程池错误, 进程池配置};

/// 一次跨进程调用的结构化结果。
///
/// **就这两样**：要么带回一个槽，要么带回一个**已登记的错误码值**（不是字符串、不是 panic）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 跨进程结果 {
    /// 协议层成立，带回返回槽。槽里可能是值，也可能是扩展自行写的错误槽。
    回槽(数据槽),
    /// 载体侧失败：值 = 已登记的错误码（本版只有 `0034`）。
    失败(u32),
}

/// 一个执行域的**部署参数**：从哪拉起（程序 + 参数）。
///
/// 它与 [`执行域标识`] 分开持有：同一个域换一次部署（重启后换二进制路径）
/// 不改域的身份，改的是「调哪一份」（与 `部署绑定` 同一件事的两面）。
#[derive(Clone)]
pub struct 域部署 {
    pub 启动程序: String,
    pub 启动参数: Vec<String>,
}

/// 跨进程执行域表 —— 适配器实例持有的东西：一个池 + 各域的部署参数 + 各域的会话。
///
/// **不落 `static`**；`进程池` 自身的 `Drop` 会把全部工作进程组回收（不留孤儿）。
///
/// 会话与池分开存：池的字段在它的模块里是私有的，而「发一次调用」要用到 `UnixStream`。
/// 两条腿各自持有它自身需要的东西，不把池的字段公开出去。
#[cfg(unix)]
pub struct 跨进程域表 {
    池: 进程池,
    部署表: Vec<(执行域标识, 域部署)>,
    请求号源: AtomicU64,
}

#[cfg(unix)]
impl 跨进程域表 {
    /// 建一个空表（一份部署配置应用到所有域）。
    pub fn 新建(配置: 进程池配置) -> Self {
        Self {
            池: 进程池::新建(配置),
            部署表: Vec::new(),
            请求号源: AtomicU64::new(1),
        }
    }

    /// 这个域登记过没有。
    pub fn 含域(&self, 标识: &执行域标识) -> bool {
        self.池.含域(标识)
    }

    /// 已登记域数（验证面用）。
    pub fn 已建执行域(&self) -> usize {
        self.池.已建域数()
    }

    /// 登记（或取代）一个域的部署参数，并把域拉起来。
    pub fn 登记跨进程域(
        &mut self,
        标识: 执行域标识,
        部署: 域部署,
    ) -> Result<(), 进程池错误> {
        self.池.保证域在(&标识, &部署.启动程序, &部署.启动参数)?;
        if let Some(格子) = self.部署表.iter_mut().find(|格子| 格子.0 == 标识) {
            格子.1 = 部署;
        } else {
            self.部署表.push((标识, 部署));
        }
        Ok(())
    }

    /// **登记一个已连好的域**：对端已有一条现成通道（验证面与「宿主已代拉起」的部署用）。
    ///
    /// 与 [`跨进程域表::登记跨进程域`] 的分工：那个自行拉起进程，这个收一条别人给的连接 ——
    /// 验证面要验「往返」与「通道断开」，两种场景都不需要一个真子进程。
    pub fn 登记已连域(
        &mut self,
        标识: 执行域标识,
        宿主端: UnixStream,
    ) -> Result<(), 进程池错误> {
        self.池.收下已连域(标识.clone(), 宿主端, 默认部署())?;
        let 部署 = 默认部署();
        if let Some(格子) = self.部署表.iter_mut().find(|格子| 格子.0 == 标识) {
            格子.1 = 部署;
        } else {
            self.部署表.push((标识, 部署));
        }
        Ok(())
    }

    fn 取部署(&self, 标识: &执行域标识) -> Option<&域部署> {
        self.部署表.iter().find(|格子| &格子.0 == 标识).map(|格子| &格子.1)
    }

    /// 取下一个请求标识（单调）。
    fn 取请求标识(&self) -> NonZeroU64 {
        let 号值 = self.请求号源.fetch_add(1, Ordering::Relaxed);
        NonZeroU64::new(号值).unwrap_or(NonZeroU64::MIN)
    }

    /// **击杀一域**（整组）：验证面要、部署下架也要。
    ///
    /// 击杀之后本域仍留在表里（“登记过”这件事不变）—— 下次调用会走「保证域在」重拉，
    /// 受退避与重启预算管。
    pub fn 击杀跨进程域(&mut self, 标识: &执行域标识) -> Result<(), 进程池错误> {
        self.池.击杀一域(标识)
    }

    /// **送一调用**：保证域在 ⇒ （必要时）重放装载初始化 ⇒ 发起调用 ⇒ 收结果。
    ///
    /// 四步的顺序不是随手定的：
    /// 1. **先保证域在**：重拉过的域是一个全新进程，旧装载不在 —— 先发调用会拿到
    ///    一份「不认识的号」的错误，而那会把「重拉过」误报成「声明有问题」。
    /// 2. **重放只放装载初始化**（通知号 2000）：不恢复业务任务（W01 裁）。
    /// 3. 编解码走 [`crate::线协议`] —— 本件**不自带第二套协议**。
    /// 4. 收错：通道断开 / 超预算 / 协议码越界，一律报 `0034`（不是 panic）。
    ///
    /// 失败一律返回**错误码值**（不是字符串、不是异常）—— 调用方拿它去错误码表查三项业务判断。
    pub fn 送一调用(
        &mut self,
        标识: &执行域标识,
        号值: u32,
        入参: &[数据槽],
    ) -> Result<数据槽, u32> {
        let Some(部署) = self.取部署(标识) else {
            return Err(本件错误码);
        };
        let 启动程序 = 部署.启动程序.clone();
        let 启动参数 = 部署.启动参数.clone();
        if self.池.保证域在(标识, &启动程序, &启动参数).is_err() {
            return Err(本件错误码);
        }
        if !self.池.已重放装载(标识) {
            let 请求标识 = self.取请求标识();
            if self.池.重放装载初始化(标识, 请求标识).is_err() {
                return Err(本件错误码);
            }
            // 回执必须当场收掉（见 `收装载回执` 的文件注释）—— 不收就串下一条调用。
            if let Err(错误值) = self.池.收装载回执(标识, 请求标识) {
                return Err(按池错翻码(错误值));
            }
        }
        let 待发载荷 = match crate::线协议::编码调用请求(号值, 入参) {
            Ok(载荷) => 载荷,
            Err(_) => return Err(本件错误码),
        };
        let 请求标识 = self.取请求标识();
        let 回载 = match self.池.调用一域(标识, 请求标识, &待发载荷) {
            Ok(载荷) => 载荷,
            Err(错误值) => return Err(按池错翻码(错误值)),
        };
        match crate::线协议::解码调用结果(&回载) {
            // 协议码非成功（`参数不合法`）⇒ 调用形状不对，与进程崩溃分开报：
            // 前者是本侧编错了，后者是对方没了。本版把它归到同一码的**取证**里（留痕有回载）。
            Ok((crate::协议结果::成功, 返回槽)) => Ok(返回槽),
            Ok(_) => Err(本件错误码),
            Err(_) => Err(本件错误码),
        }
    }
}

/// 池错 → 已登记错误码。**就分两类**，依据是前置裁决第三条：
///
/// - **进程没了**（通道断开 · 熔断中 · 拉起失败）⇒ `0034 能力进程崩溃`；
/// - **进程活着但没在预算内答**（[`进程池错误::预算耗尽`]）⇒ `0004 超时`。
///
/// 这条分界是那条裁决的原话（「与 0004 超时分开（超时是进程活着但没答）」）——
/// 把两者报成同一个码，裁决里那句话就成了空话。
pub fn 按池错翻码(错误值: 进程池错误) -> u32 {
    match 错误值 {
        进程池错误::预算耗尽 => 4,
        进程池错误::域不存在 | 进程池错误::熔断中 | 进程池错误::拉起失败 | 进程池错误::通道断开 => {
            本件错误码
        }
    }
}

/// 本件能报的唯一错误码：`0034 能力进程崩溃`（段位 0 · 已登记）。
///
/// 码值取自生成物（源 = `契约声明/错误码表/0034.json`），本件不另写数。
const 本件错误码: u32 = 34;

/// 取一个适配器实例号：墙钟纳秒。**不落 static**（`跨语言适配/` 全域被判据 ⑫-4 盯
/// 模块级 `static`）—— 同进程两份适配器各自持有自身的执行域表，实例号只用于区分域，
/// 不需要全局唯一。
pub fn 取实例号() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|时长| 时长.as_nanos() as u64)
        .unwrap_or(0)
}

/// 一个空的默认部署：给「已连好的域」用 —— 它的进程不是池拉起来的，
/// 所以「从哪拉起」对它无意义；真需要重拉时它会报 `域不存在`（逐字诚实）。
fn 默认部署() -> 域部署 {
    域部署 { 启动程序: String::from("/bin/sh"), 启动参数: vec![String::from("-c"), String::from("sleep 5")] }
}

/// 把一个结构化失败写成**返回槽里的错误槽**（`类型标签_4294967295` + 码值）。
///
/// 与 `边界面.rs::造错误槽` **同一形状**（那里是私有的）—— 它把业务码写进调用方拿到的槽，
/// 本函数把载体码写进同一个槽位。两条路交出的都是「调用方按码查表」的那一个东西。
pub fn 造跨进程错误槽(码值: u32) -> 数据槽 {
    数据槽::内联槽(声明数据::类型标签_4294967295, u64::from(码值), 0)
}

#[cfg(unix)]
impl crate::适配器 {
    /// 开跨进程执行域表（不开则本实例全部走进程内路，一分钱不多花）。
    pub fn 开跨进程(&mut self, 配置: 进程池配置) {
        if self.跨进程.is_none() {
            self.跨进程 = Some(std::sync::Arc::new(std::sync::Mutex::new(跨进程域表::新建(配置))));
        }
    }

    /// 这个实例开过跨进程表没有。
    pub fn 有跨进程域(&self) -> bool {
        self.跨进程.is_some()
    }

    /// 按一份**已装载的**声明登记它的执行域（部署参数 = 从哪拉起那个扩展的工作进程）。
    pub fn 登记跨进程域(
        &mut self,
        声明: &v1_contract::平台信息,
        部署: 域部署,
    ) -> Result<(), 进程池错误> {
        let Some(域表) = self.跨进程.as_ref() else {
            return Err(进程池错误::域不存在);
        };
        let 标识 = self.按声明算域标识(声明)?;
        取锁(域表).登记跨进程域(标识, 部署)
    }

    /// 这条号归哪个已装载单元 —— 判据与路由**同一套**（「谁认这个号就归谁」）。
    fn 按号找声明(&self, 号值: 能力号) -> Option<&'static v1_contract::平台信息> {
        for 装载单元 in &self.装载单元s {
            if let v1_registry::命令槽::已载入 { .. } = 装载单元.注册表.按号取命令(号值) {
                return Some(装载单元.声明);
            }
        }
        None
    }

    /// 一份声明 → 它的执行域标识（`适配器实例 × 扩展标识 × 制品版本`）。
    fn 按声明算域标识(
        &self,
        声明: &v1_contract::平台信息,
    ) -> Result<执行域标识, 进程池错误> {
        if 声明.标识串.is_null() {
            return Err(进程池错误::域不存在);
        }
        // SAFETY: 契约保证 标识串 是静态只读 NUL 结尾串。
        let 扩展标识串 = unsafe { crate::契约读取::读契约串(声明.标识串) }.to_string();
        let 版本 = 声明.实现版本;
        Ok(执行域标识 {
            适配器实例号: self.实例号,
            扩展标识串,
            制品版本: (
                u32::try_from(版本.主版本).unwrap_or(0),
                u32::try_from(版本.次版本号).unwrap_or(0),
                u32::try_from(版本.构建).unwrap_or(0),
            ),
        })
    }

    /// 这个号有没有登记过跨进程域（登记过才走跨进程，否则 `None` ⇒ 走进程内原路）。
    fn 算域标识(&self, 号值: 能力号) -> Option<执行域标识> {
        let 域表 = self.跨进程.as_ref()?;
        let 声明 = self.按号找声明(号值)?;
        let 标识 = self.按声明算域标识(声明).ok()?;
        if 取锁(域表).含域(&标识) { Some(标识) } else { None }
    }

    /// **击杀一个已登记域的工作进程**（验证面与部署下架用）。
    pub fn 击杀跨进程域(
        &mut self,
        声明: &v1_contract::平台信息,
    ) -> Result<(), 进程池错误> {
        let Some(域表) = self.跨进程.as_ref() else {
            return Err(进程池错误::域不存在);
        };
        let 标识 = self.按声明算域标识(声明)?;
        取锁(域表).击杀跨进程域(&标识)
    }

    /// **跨进程调用路**：这个号登记过域 ⇒ 送工作进程并收结果；没登记 ⇒ `None`（调用方走原路）。
    ///
    /// 失败（拉起不了 / 熔断中 / 通道断开 / 回载不成形）⇒ 返回槽里写结构化 `0034` 并回
    /// [`crate::转发结果::成功`] —— 「协议层成立、失败在返回槽里」与 `边界面.rs` 同一口径
    /// （业务失败不走协议码）。**不 panic · 不给调度错误加进程变体**。
    pub(crate) fn 调用跨进程(
        &self,
        号值: 能力号,
        入参: &[数据槽],
        返回槽: &mut 数据槽,
    ) -> Option<crate::转发结果> {
        let 标识 = self.算域标识(号值)?;
        let 域表 = self.跨进程.as_ref()?;
        let 读数 = 取锁(域表).送一调用(&标识, 号值.取号值(), 入参);
        match 读数 {
            Ok(槽体) => {
                *返回槽 = 槽体;
                Some(crate::转发结果::成功(槽体))
            }
            Err(码值) => {
                let 槽体 = 造跨进程错误槽(码值);
                *返回槽 = 槽体;
                Some(crate::转发结果::成功(槽体))
            }
        }
    }
}

