/// 一个已装载单元：一份声明 + 它建出的注册表。
///
/// 为什么要连声明一起留：读侧要的「可抛错误码」在 `平台信息.错误码表` 字段里，
/// 而 [`注册表`] 只把四张表收进去、不公开 `错误码表`（见文件头缺口 3）。
struct 装载单元 {
    声明: &'static 平台信息,
    注册表: 注册表,
}

/// **全平台唯一的适配器**：读契约 → 装载内核 → 转发调用。
///
/// 形状是「一个实例一套东西」：装载单元表 + 一本配额账本 + 一条通知账 + 一条留痕缓冲。
/// **没有任何进程级 `static`**，所以同进程里开两份适配器就是两个互不干扰的配额域
/// 与两条互不串的通知端点表（多实例安全）。
///
/// # 线程安全（台账 #132）
///
/// 本类型 `Send` + `Sync`：网关才能把**同一个适配器**交给多个工作线程并发收连接。
/// 断言的依据与边界逐条写在 `线程安全.rs` 的文件头（这是全 crate 唯一一条 `unsafe`
/// 线程安全断言）；三个可变点各自的同步方式：
///
/// - `账本`：`配额账本` 内部用 `Mutex`（它本来就是为 `&self` 共享设计的）；
/// - `通知`：通知通道（内含 `RefCell`）与按标识的索引合起来放进一把 `Mutex`；
/// - `留痕`：`留痕缓冲` 逐字段原子，`记` 取 `&self`；`追踪号` 是 `AtomicU64`。
///
/// `装载单元s` 装载完成后**只读**，且指向 `'static` 静态数据 —— 并发读无写。
///
/// 账本的上限与窗口**取自 `调用调度` 的常量**（[`配额上限`] · [`配额窗口毫秒`]）：
/// 适配器不给调用方另开一个「自设配额」的口 —— 那会让配额口径变成每处一套，
/// 与「单项超时口径唯一」同一条理由。
pub struct 适配器 {
    装载单元s: Vec<装载单元>,
    账本: 配额账本,
    /// 通知口（台账 #80）：已载入扩展申报的 `通知函数` 在这里注册成端点，
    /// 生命周期通知（装载/卸载/退出）才送得到扩展。通道与按标识的索引同一把锁。
    通知: Mutex<通知账>,
    /// 调用留痕（台账 #99）：`装载` 不开口，装配侧按契约常量 `留痕容量` 给容量即开。
    留痕: Option<留痕缓冲>,
    /// 本实例单调递增的调用序号（留痕的 `追踪号`）。**不是进程级全局**。
    追踪号: AtomicU64,
}

impl 适配器 {
    /// 装载**一个**声明：建台账 → 判定 → 载入 → 持有注册表。
    ///
    /// 台账从**空**起步（[`载入台账::空`]），载入成功后由本函数调
    /// [`载入台账::登记`] 记进去。**不许**用 [`载入台账::新`] 起步：那会预置底座自己的
    /// 占用，于是**底座自己的声明**在判定 ② 就被判成「冒用底座身份 / 已在台账里」而载不进来。
    pub fn 装载(声明: &'static 平台信息) -> Result<Self, 装载失败> {
        Self::装载声明根(&[声明])
    }

    /// 装载一个**声明根**（一串声明）：按给定顺序**序贯**走完台账，每份一个注册表。
    ///
    /// # 顺序即依赖序
    ///
    /// 台账是「谁已经载入了」的唯一判据（判定 ②③⑤ 全走它），而 [`载入台账`] 的
    /// [`登记`](载入台账::登记) 由**调用方**在载入成功后调（`载入` 收的是只读的
    /// `&dyn 已载入台账`，改不了台账）。所以「一个扩展怎么加进去」的现成口就是这里：
    ///
    /// ```text
    /// 台账 = 载入台账::空()
    /// 逐份声明：  载入(声明, &台账)?  →  台账.登记(声明)
    /// ```
    ///
    /// 底座排在最前（扩展的 ⑤ 依赖清单要能命中它），后面的扩展自然看得见前面的。
    /// 这样既不需要 `载入台账::新()` 那个「预置底座」的特例，也不给底座开特例分支。
    ///
    /// # 编号与路由
    ///
    /// 每份声明的命令编号都**取自声明**（`命令信息.编号`），注册表按编号二分查找认领；
    /// 转发调用按「**谁认这个号就归谁**」路由（第一份认领者胜），实测见测试
    /// `实测_命令编号来自声明`。编号是否落在声明号段内的校验在既有件（`装载入口`），不在本 crate。
    pub fn 装载声明根(声明根: &[&'static 平台信息]) -> Result<Self, 装载失败> {
        if 声明根.is_empty() {
            return Err(装载失败::空声明根);
        }
        // 台账**按实例**建，不落进程级全局（宪法三条补缺陷：状态显式持有为句柄）。
        let mut 台账 = 载入台账::空();
        let mut 装载单元s = Vec::with_capacity(声明根.len());
        // 通知口（台账 #80）：装载时把**非底座**声明申报的 `通知函数` 登记成端点
        // —— 「申报了就送得到」。底座是宿主自己（它发通知，不是收通知的扩展端点），不登记。
        let mut 通知 = 通知账::新建();
        for 声明 in 声明根.iter().copied() {
            // 全平台唯一的那一处 `载入`（拓扑判据第 3 条）。判定不过就整体失败，不留半个适配器。
            let 表 = v1_loader::载入(声明, &台账).map_err(装载失败::载入)?;
            台账.登记(声明);
            if !core::ptr::eq(声明, v1_loader::底座声明())
                && let Some(函数) = 声明.通知函数
            {
                通知.通道.注册(声明.标识串, 函数);
                // 索引：文本 → 指针（HTTP 面只有文本）。空标识串不进索引（无法寻址）。
                if !声明.标识串.is_null() {
                    // SAFETY: 契约保证 标识串 是静态只读 NUL 结尾串。
                    let 文本 = unsafe { 读契约串(声明.标识串) };
                    if !文本.is_empty() {
                        通知.标识表.push(线程安全::通知标识项 {
                            标识串: 文本,
                            指针: 声明.标识串,
                        });
                    }
                }
            }
            装载单元s.push(装载单元 {
                声明,
                注册表: 表,
            });
        }
        Ok(Self {
            装载单元s,
            账本: 配额账本::新建(配额上限, 配额窗口毫秒),
            通知: Mutex::new(通知),
            留痕: None,
            追踪号: AtomicU64::new(0),
        })
    }

    /// **转发调用**：`(能力号, 参数, 返回槽) -> 结构化结果`。
    ///
    /// 必须经 [`v1_dispatch::调用`] —— 本函数**不自己取号、不自己校参数、不自己问配额**：
    /// 那四件事（超时 · 配额 · 占位兜底 · 已废止判定）只有一份实现，在调度层。
    ///
    /// 失败一律是结构化段位（含未命中 ⇒ [`调度错误::提供者未载入`]），**不 panic**；
    /// 失败时返回槽由调度层置空（宪法第 6 条「未命中返回空」）。
    ///
    /// # 参数约定（调用方须保证）
    ///
    /// `参数` 的每个槽都已按 [`能力契约::参数表`] 的**行序**填好；个数与声明一致。
    /// 个数不符不会崩，会拿到 [`调度错误::参数个数不符`]。
    pub fn 调用能力(&self, 号: u32, 参数: &[数据槽], 返回槽: &mut 数据槽) -> 转发结果 {
        let 表 = self.取注册表(号);
        let 起 = std::time::Instant::now();
        // SAFETY: `返回槽` 是本函数独占的可写槽（`&mut` 保证）；`参数` 由调用方按契约填好。
        let 结果 = unsafe { v1_dispatch::调用(表, &self.账本, 号, 参数, 返回槽 as *mut 数据槽) };
        let 转发 = match 结果 {
            调用结果::成功 => 转发结果::成功(*返回槽),
            调用结果::失败(错) => 转发结果::失败(错),
        };
        // 留痕（台账 #99）：调用**返回之后**记一条，不进关键路径（`留痕缓冲::记` 不取锁、
        // 不分配、不阻塞）。没启用留痕时它是空操作，调用结果不受影响。
        let 耗时微秒 = u64::try_from(起.elapsed().as_micros()).unwrap_or(u64::MAX);
        self.记一条留痕(号, 参数, &转发, 耗时微秒);
        转发
    }
}

