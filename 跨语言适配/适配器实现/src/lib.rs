//! 适配器实现 —— 全平台唯一的适配器：**读契约 → 装载内核 → 转发调用**。
//!
//! 宪法第 9 条「一个适配器适配所有语言」的落点：任何语言、任何上层，都只经这一条腿进内核。
//! 它自己**不做业务判断**，只做形状翻译与转发。
//!
//! # 与拓扑判据的关系（`项目文档/设计文档/全局连接器与网关.md` 第四节）
//!
//! 本 crate 就是那张图里的「**全局连接器**」。与它直接相关的是判据第 3 条：
//! **全平台只有一个内核入口**（读契约 → 建注册表 → 交控制权），恰好 1 处调用 `载入` ——
//! 那一处就是 [`适配器::装载声明根`]。判据第 2 条（唯一的导出 C ABI 边界）**不在本 crate**：
//! 导出符号在 `装载入口`（`GetPlatformInfo`），本 crate **不导出任何符号**。
//!
//! 第五节「不让网关或连接器持有状态」说的是**不许用全局单例实现全局唯一**：本 crate 的
//! 账本按实例持有（[`适配器`] 的私有字段），不落任何进程级 `static` ⇒ 同进程开几份适配器
//! 就是几个互不干扰的配额域（判据第 5 条「同一对层之间不许有两条边」也据此成立：
//! 多实例不等于第二条腿）。
//!
//! # 三件事，三条不许
//!
//! 1. **装载**：读一个声明（或声明根）→ 建台账 → [`v1_loader::载入`] → 持有 [`注册表`]。
//! 2. **转发调用**：必须经 [`v1_dispatch::调用`] —— **不许**绕过它直接调执行函数。
//!    绕过去就绕掉了单项超时 · 资源配额 · 占位兜底 · 已废止判定四件事。
//! 3. **读侧**：使用角色的「读」与「调」走**同一个入口** —— 能力清单是当场从 [`注册表`]
//!    取出来的，不是另存的一份表。
//!
//! **不许在适配器里写业务判断**：它只翻译形状。任何「如果编号是 X 就特殊处理」都是缺陷。
//! 本文件的生产代码里**没有任何一个具体能力编号参与判定** —— 路由只看「这一份认不认这个号」。
//!
//! # 契约从哪来
//!
//! **不解析任何 JSON**：声明在进程内就是契约的 [`平台信息`]（冻结的 C 结构），底座那份由
//! `装载入口` 提供（[`v1_loader::底座声明`]）；契约派生的常量取 `v1_contract::声明数据`
//! （生成物）。适配器**不重定义任何形状**，也不另存一份能力表。
//!
//! # 缺口（如实登记，不假装覆盖了）
//!
//! 1. **`契约声明/常量表.json` 在运行期取不到。** 那张表自称「全平台常量的唯一定义处」，
//!    但生成物（`契约声明/src/声明数据.rs`）**一个都没出**：只出了 `声明格式号` 与
//!    `目标字宽`，`单项超时毫秒` / `配额窗口毫秒` / `配额上限` / `号段类宽度` 都不在其中。
//!    运行期唯一可用的来源是 `调用调度` 里**手写**的三个常量（值相同、来源不同 ⇒
//!    正是那张表自己禁止的「同一事实两个来源」）。适配器只能引用内核常量，**不写第三份**；
//!    缺口在生成链，不在本 crate。
//! 2. **能力编号与号段对不上**（实测，见测试 `实测_声明根里每份声明的命令编号都从表内下标0起`）。
//!    `装载入口` 定「命令编号 = 命令表下标（0 起）」，而 `项目文档/设计文档/字段名册与引用方式.md`
//!    与 `契约声明/格式说明.md` 第三节把「编号」定成 `1001` 这种**能力号**。两条口径同时成立，
//!    要求每份声明都有一张 1001 项的稠密命令表。⇒ 同一个适配器里装多份声明时，
//!    **每份的命令编号都从 0 起**，扩展占 1xxx 号段这件事没有落到编号上。
//! 3. **可抛错误码没有现成口。** 读侧要的「某条能力的可抛错误码」只能从声明的 `错误码表`
//!    字段现读（[`注册表`] 不公开它，`装载入口` 也没给读侧口）。适配器按**声明全表**给，
//!    **不按能力段位再筛**：筛要除 `号段类宽度`，而那个数在 `装载入口` 里是私有常量
//!    （见该 crate 的缺口 6），任何别的 crate 都取不到。
//! 4. **没有热载入口。** [`注册表`] 只能由一份声明一次性建出，不能增量合并；要再装一份声明，
//!    只能由调用方持有 `载入台账` 再走一遍 [`适配器::装载声明根`]。本 crate **不持有台账**
//!    （拓扑：连接器不持有状态），故「已装好的适配器再热载入一份」留作待办。

pub use v1_contract::{已载入台账, 平台信息, 数据槽};
pub use v1_dispatch::{调度错误, 调用结果};
pub use v1_loader::{载入错误, 载入台账};
pub use v1_registry::注册表;

/// 平台级常量（源：`契约声明/常量表.json`，经生成物 `声明数据`）。
///
/// **为什么由本层转出去**：`对外接口面` 的唯一腿是本层（不许跳层，`README.md` 第六节），
/// 它拿不到 `契约声明`。所以这两个常量由本层**再导出同一份** —— 不是第二份定义。
/// 早先接口面自己在 `src/常量.rs` 里手写了一遍（`接口端口 = 43110` / `号段类宽度 = 1000`），
/// 验证器 ⑬「同名常量不许在别处再定义」当场报红两条（2026-09-26）。
pub use v1_contract::声明数据::{号段类宽度, 接口端口};

use v1_dispatch::{配额上限, 配额窗口毫秒, 配额账本};
use v1_registry::{命令槽, 命令信息};

