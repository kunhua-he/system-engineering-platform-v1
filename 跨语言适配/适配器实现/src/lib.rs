/// 装载失败。**结构化**：说清是哪一步、缺什么，不是 `false`。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 装载失败 {
    /// 判定六步里某一步不过（含建表失败）。原样转出 `装载入口` 的段位，不吞、不改写。
    载入(载入错误),
    /// 声明根是空的：一份声明都没有。**不是崩溃**，是明确的调用方错误——
    /// 没有注册表就没有可寻址的表，转发调用无处可去。
    空声明根,
}

/// 转发结果。**结构化**：成功带返回槽，失败带 [`调度错误`] 段位。
///
/// 成功里那个槽与调用方传进来的 `返回槽` 是**同一次写入的两个视图**（[`数据槽`] 是 24 字节
/// 定长值，复制一份不改所有权语义）：所有权仍按槽内的 `槽标志::所有权交出` 判，只释放一次。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 转发结果 {
    成功(数据槽),
    失败(调度错误),
}

/// 能力摘要 —— 读侧「有哪些能力」的一行。**四样就是四样**，不多给。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 能力摘要 {
    /// 编号（取自声明的 `命令信息.编号`，**不是**命令表下标）。
    pub 编号: u32,
    /// 名称（从声明的静态 NUL 结尾串现读，不是另存的一份）。
    pub 名称: String,
    /// 参数个数 = 参数表行数。**行序即契约**。
    pub 参数个数: u32,
    /// 返回类型标签；`0` = 无返回值。
    pub 返回类型: u32,
}

/// 参数摘要 —— 参数表的一行。**行序即契约**，顺序由 [`能力契约::参数表`] 的排列给出。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 参数摘要 {
    pub 名称: String,
    /// 类型标签，必须能在 `契约声明/类型声明/` 里查到。
    pub 类型标签: u32,
    pub 状态位: u16,
    pub 默认值: 数据槽,
}

/// 错误码摘要 —— 「失败可编程处理」的落点：拿到码要能查到这三项业务判断。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 错误码摘要 {
    pub 码: u32,
    pub 名称: String,
    pub 说明: String,
    pub 可重试: bool,
    pub 可自愈: bool,
    pub 需人工: bool,
}

/// 某条能力的**完整契约**：参数表行序 · 返回 · 可抛错误码。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 能力契约 {
    pub 编号: u32,
    pub 名称: String,
    pub 说明: String,
    /// **行序即契约**：调用方按本向量的顺序填 `参数`。
    pub 参数表: Vec<参数摘要>,
    /// 返回类型标签；`0` = 无返回值。
    pub 返回类型: u32,
    /// 本声明登记过的错误码（见文件头缺口 3：未按能力段位再筛）。
    pub 可抛错误码: Vec<错误码摘要>,
}

