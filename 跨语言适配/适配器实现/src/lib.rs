//! 适配器实现 —— 全平台唯一的适配器：**读契约 → 装载内核 → 转发调用**。
//!
//! 宪法第 9 条「一个适配器适配所有语言」的落点：任何语言、任何上层，都只经这一条腿进内核。
//! 它自身**不做业务判断**，只做形状翻译与转发。
//!
//! # 与拓扑判据的关系（`项目文档/设计文档/全局连接器与网关.md` 第四节）
//!
//! 本 crate 就是那张图里的「**全局连接器**」。判据第 3 条：**全平台只有一个内核入口**，
//! 恰好 1 处调用 `载入` —— 那一处就是 [`适配器::装载声明根`]。判据第 2 条（唯一的导出
//! C ABI 边界）**不在本 crate**：导出符号在 `装载入口`（`GetPlatformInfo`）。
//! 第五节「不让连接器持有状态」说的是**不许用全局单例实现全局唯一**：本 crate 的账本按
//! 实例持有（[`适配器`] 的字段），不落任何进程级 `static` ⇒ 同进程开几份适配器就是几个
//! 互不干扰的配额域。
//!
//! # 四件事，三条不许
//!
//! 1. **装载**：读一个声明（或声明根）→ 建台账 → [`v1_loader::载入`] → 持有 [`注册表`]。
//! 2. **转发调用**：必须经 [`v1_dispatch::调用`] —— **不许**绕过它直接调执行函数。
//! 3. **读侧**：使用角色的「读」与「调」走**同一个入口**，能力清单当场从 [`注册表`] 取出。
//! 4. **通知**：装载时把扩展申报的 `通知函数` 登记成端点；生命周期通知（装载/卸载/退出）
//!    经 [`适配器::请求卸载`] · [`适配器::延迟释放协商`] 送得到扩展（实现在 `通知口.rs`）。
//!
//! **不许在适配器里写业务判断**：它只翻译形状，路由只看「这一份认不认这个号」。
//! **不解析任何 JSON**：声明在进程内就是契约的 [`平台信息`]（冻结的 C 结构），底座那份由
//! `装载入口` 提供（[`v1_loader::底座声明`]）；契约派生的常量取生成物 `v1_contract::声明数据`。
//! 缺口逐条见 `项目文档/未完成事项.md` 与各件的文件头（一份事实一个落点）。

