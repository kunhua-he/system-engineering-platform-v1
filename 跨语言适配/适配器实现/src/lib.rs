/// 一个已装载单元：一份声明 + 它建出的注册表。
///
/// 为什么要连声明一起留：读侧要的「可抛错误码」在 `平台信息.错误码表` 字段里，
/// 而 [`注册表`] 只把四张表收进去、不公开 `错误码表`（见文件头缺口 3）。
struct 装载单元 {
    声明: &'static 平台信息,
    注册表: 注册表,
}

/// **全平台唯一的适配器**：读契约 → 装载内核 → 转发调用。
///
/// 形状是「一个实例一套东西」：装载单元表 + 一本配额账本。**没有任何进程级 `static`**，
/// 所以同进程里开两份适配器就是两个互不干扰的配额域（多实例安全）。
///
/// 账本的上限与窗口**取自 `调用调度` 的常量**（[`配额上限`] · [`配额窗口毫秒`]）：
/// 适配器不给调用方另开一个「自设配额」的口 —— 那会让配额口径变成每处一套，
/// 与「单项超时口径唯一」同一条理由。
pub struct 适配器 {
    装载单元s: Vec<装载单元>,
    账本: 配额账本,
}

impl 适配器 {
    /// 装载**一个**声明：建台账 → 判定 → 载入 → 持有注册表。
    ///
    /// 台账从**空**起步（[`载入台账::空`]），载入成功后由本函数调
    /// [`载入台账::登记`] 记进去。**不许**用 [`载入台账::新`] 起步：那会预置底座自己的
    /// 占用，于是**底座自己的声明**在判定 ② 就被判成「冒用底座身份 / 已在台账里」而载不进来。
    pub fn 装载(声明: &'static 平台信息) -> Result<Self, 装载失败> {
        Self::装载声明根(&[声明])
    }

    /// 装载一个**声明根**（一串声明）：按给定顺序**序贯**走完台账，每份一个注册表。
    ///
    /// # 顺序即依赖序
    ///
    /// 台账是「谁已经载入了」的唯一判据（判定 ②③⑤ 全走它），而 [`载入台账`] 的
    /// [`登记`](载入台账::登记) 由**调用方**在载入成功后调（`载入` 收的是只读的
    /// `&dyn 已载入台账`，改不了台账）。所以「一个扩展怎么加进去」的现成口就是这里：
    ///
    /// ```text
    /// 台账 = 载入台账::空()
    /// 逐份声明：  载入(声明, &台账)?  →  台账.登记(声明)
    /// ```
    ///
    /// 底座排在最前（扩展的 ⑤ 依赖清单要能命中它），后面的扩展自然看得见前面的。
    /// 这样既不需要 `载入台账::新()` 那个「预置底座」的特例，也不给底座开特例分支。
    ///
    /// # 已知限制（见文件头缺口 2）
    ///
    /// 每份声明的命令编号都从命令表下标 0 起，所以多份声明里「号 0」是重号的；
    /// 转发调用按「**谁认这个号就归谁**」路由（第一份认领者胜），实测见测试
    /// `实测_声明根里每份声明的命令编号都从表内下标0起`。修法在既有件，不在本 crate。
    pub fn 装载声明根(声明根: &[&'static 平台信息]) -> Result<Self, 装载失败> {
        if 声明根.is_empty() {
            return Err(装载失败::空声明根);
        }
        // 台账**按实例**建，不落进程级全局（宪法三条补缺陷：状态显式持有为句柄）。
        let mut 台账 = 载入台账::空();
        let mut 装载单元s = Vec::with_capacity(声明根.len());
        for 声明 in 声明根.iter().copied() {
            // 全平台唯一的那一处 `载入`（拓扑判据第 3 条）。判定不过就整体失败，不留半个适配器。
            let 表 = v1_loader::载入(声明, &台账).map_err(装载失败::载入)?;
            台账.登记(声明);
            装载单元s.push(装载单元 {
                声明,
                注册表: 表,
            });
        }
        Ok(Self {
            装载单元s,
            账本: 配额账本::新建(配额上限, 配额窗口毫秒),
        })
    }

    /// **转发调用**：`(能力号, 参数, 返回槽) -> 结构化结果`。
    ///
    /// 必须经 [`v1_dispatch::调用`] —— 本函数**不自己取号、不自己校参数、不自己问配额**：
    /// 那四件事（超时 · 配额 · 占位兜底 · 已废止判定）只有一份实现，在调度层。
    ///
    /// 失败一律是结构化段位（含未命中 ⇒ [`调度错误::提供者未载入`]），**不 panic**；
    /// 失败时返回槽由调度层置空（宪法第 6 条「未命中返回空」）。
    ///
    /// # 参数约定（调用方须保证）
    ///
    /// `参数` 的每个槽都已按 [`能力契约::参数表`] 的**行序**填好；个数与声明一致。
    /// 个数不符不会崩，会拿到 [`调度错误::参数个数不符`]。
    pub fn 调用能力(&self, 号: u32, 参数: &[数据槽], 返回槽: &mut 数据槽) -> 转发结果 {
        let 表 = self.取注册表(号);
        // SAFETY: `返回槽` 是本函数独占的可写槽（`&mut` 保证）；`参数` 由调用方按契约填好。
        let 结果 = unsafe { v1_dispatch::调用(表, &self.账本, 号, 参数, 返回槽 as *mut 数据槽) };
        match 结果 {
            调用结果::成功 => 转发结果::成功(*返回槽),
            调用结果::失败(错) => 转发结果::失败(错),
        }
    }

    /// 读侧「有哪些能力」：编号 · 名称 · 参数个数 · 返回类型。
    ///
    /// **与调侧同一个入口**：清单是当场遍历 [`注册表`] 取出来的（`按号取命令`），
    /// 不是另存的一份表 —— 所以清单里的编号拿去 [`适配器::调用能力`] 必然走得通同一条路。
    pub fn 能力清单(&self) -> Vec<能力摘要> {
        let mut 出 = Vec::new();
        for 单元 in &self.装载单元s {
            for 编号 in 0..单元.注册表.命令数() {
                if let 命令槽::已载入 { 声明, .. } = 单元.注册表.按号取命令(编号) {
                    出.push(能力摘要 {
                        编号,
                        // SAFETY: 契约保证一切串都是静态只读 NUL 结尾串。
                        名称: unsafe { 读契约串(声明.名称) },
                        参数个数: 声明.参数个数,
                        返回类型: 声明.返回类型,
                    });
                }
            }
        }
        出
    }

    /// 读侧「某条能力的完整契约」：参数表行序 · 返回 · 可抛错误码。
    ///
    /// 未命中给 `None`（**不是 panic**，也不编一份空契约）：这个号没被任何已装载声明认领。
    pub fn 能力契约(&self, 号: u32) -> Option<能力契约> {
        for 单元 in &self.装载单元s {
            if let 命令槽::已载入 { 声明, .. } = 单元.注册表.按号取命令(号) {
                return Some(能力契约 {
                    编号: 号,
                    // SAFETY: 契约保证一切串都是静态只读 NUL 结尾串。
                    名称: unsafe { 读契约串(声明.名称) },
                    // SAFETY: 同上。
                    说明: unsafe { 读契约串(声明.说明) },
                    参数表: 读参数表(声明),
                    返回类型: 声明.返回类型,
                    可抛错误码: 读错误码表(单元.声明),
                });
            }
        }
        None
    }

    /// 已装载的声明份数（验证面用：确认声明根是序贯装进来的）。
    pub fn 已装载声明数(&self) -> usize {
        self.装载单元s.len()
    }

    /// 某个能力号累计的真实耗时（毫秒）。取自**本实例**那本账本，不是进程级读数。
    pub fn 累计耗时毫秒(&self, 号: u32) -> u64 {
        self.账本.累计耗时毫秒(号)
    }

    /// 路由：**谁认这个号就归谁**。
    ///
    /// 这不是业务判断 —— 代码里没有任何一个具体编号，只看「这一份的注册表认不认」。
    /// 都不认时交给第一份：它照样给占位项 ⇒ 明确段位「提供者未载入」，**不是崩溃**。
    ///
    /// `装载单元s` 非空由 [`适配器::装载声明根`] 保证（空声明根在构造期就被拒）。
    fn 取注册表(&self, 号: u32) -> &注册表 {
        for 单元 in &self.装载单元s {
            if let 命令槽::已载入 { .. } = 单元.注册表.按号取命令(号) {
                return &单元.注册表;
            }
        }
        &self.装载单元s[0].注册表
    }
}

// ════════════════════════════════════════════════════════════════════════════
// 形状翻译的零件（读侧）
//
// 一律**现读**声明的静态字段，不缓存、不另存。契约规定一切串都是静态只读的 NUL 结尾串、
// 一切表段都指向静态只读数组 —— 与 `装载入口` / `统一注册表` 的前提同一份。
// ════════════════════════════════════════════════════════════════════════════

/// 契约串的读取上限（防呆：扫不到 NUL 就当读不出，不去 `from_raw_parts` 一个巨数）。
const 契约串上限: usize = 4096;

/// 读一个契约串（静态只读 NUL 结尾）。空指针 / 超上限仍无 NUL ⇒ 空串。
///
/// # Safety
///
/// `指针` 要么为空，要么指向**至少 `契约串上限` 字节可读**的静态数据。
unsafe fn 读契约串(指针: *const u8) -> String {
    if 指针.is_null() {
        return String::new();
    }
    let mut 长 = 0usize;
    while 长 < 契约串上限 {
        // SAFETY: 由调用方保证 指针..指针+契约串上限 可读。
        if unsafe { *指针.add(长) } == 0 {
            break;
        }
        长 += 1;
    }
    if 长 == 契约串上限 {
        return String::new();
    }
    // SAFETY: 已扫到 NUL，前 长 字节可读且不再变动（静态数据）。
    let 字节 = unsafe { core::slice::from_raw_parts(指针, 长) };
    String::from_utf8_lossy(字节).into_owned()
}

/// 命令的参数表 → 参数摘要（**行序原样保留**：调用方按这个顺序填值）。
fn 读参数表(命令: &命令信息) -> Vec<参数摘要> {
    if 命令.参数个数 == 0 || 命令.参数表.is_null() {
        return Vec::new();
    }
    // SAFETY: 契约保证 参数表 指向静态只读数组，长度 = 参数个数
    //（`注册表::建表` 已核过「项数 > 0 却给空项表」这一条）。
    let 表 = unsafe { core::slice::from_raw_parts(命令.参数表, 命令.参数个数 as usize) };
    表.iter()
        .map(|参| 参数摘要 {
            // SAFETY: 契约保证一切串都是静态只读 NUL 结尾串。
            名称: unsafe { 读契约串(参.名称) },
            类型标签: 参.类型标签,
            状态位: 参.状态位,
            默认值: 参.默认值,
        })
        .collect()
}

/// 声明的错误码表 → 错误码摘要。
///
/// 用**声明自己的**错误码表（底座那份就是生成物 `错误码信息表`），不另存一份表。
fn 读错误码表(声明: &平台信息) -> Vec<错误码摘要> {
    // 按字段取值，不搬整个 `表段`：`表段<T>` 只在 `T: Copy` 时才 `Copy`，而 `错误码信息`
    // 带裸指针、不是 `Copy`（与 `统一注册表::切片` 同一理由）。
    let 项数 = 声明.错误码表.项数;
    let 项表 = 声明.错误码表.项表;
    if 项数 == 0 || 项表.is_null() {
        return Vec::new();
    }
    // SAFETY: 契约保证 错误码表 指向静态只读数组。
    let 表 = unsafe { core::slice::from_raw_parts(项表, 项数 as usize) };
    表.iter()
        .map(|码| 错误码摘要 {
            码: 码.码,
            // SAFETY: 契约保证一切串都是静态只读 NUL 结尾串。
            名称: unsafe { 读契约串(码.名称) },
            // SAFETY: 同上。
            说明: unsafe { 读契约串(码.说明) },
            可重试: 码.可重试 != 0,
            可自愈: 码.可自愈 != 0,
            需人工: 码.需人工 != 0,
        })
        .collect()
}

