//! 留痕口 —— 调用路写留痕 + 公开面给「取留痕」的口（台账 #99）。
//!
//! # 缺的是什么
//!
//! README 第三节承诺「**跨边界可追溯**：每次调用留痕（谁 · 调什么 · 入参指纹 · 结果 ·
//! 耗时），且留痕本身不阻塞调用」。而实测适配器源码里对 `留痕` / `v1_trace` 的引用数
//! **= 0**，公开面也没有取留痕的口 ⇒ 这条承诺没兑现。本文件补上这条腿。
//!
//! # 形状（不另造第二套）
//!
//! 直接用内核节点 `运行内核/调用留痕/` 的 [`留痕缓冲`]（与 `资源网关口` 同一份），
//! 逐字段对应：
//!
//! | 留痕字段 | 本层填什么 |
//! |---|---|
//! | `实例` | 适配器实例的地址（同进程多实例互不污染，不是全局计数器） |
//! | `能力号` | 这一次调用的号 |
//! | `入参指纹` | 全部入参槽的 FNV-1a 指纹（只看形状，不解释语义） |
//! | `结果码` | 成功 = `0`；失败 = 4 位业务错误码（含「转发成功但返回槽是错误槽」） |
//! | `耗时微秒` | 这一次 `调用能力` 的墙钟耗时 |
//! | `追踪号` | 本实例单调递增的调用序号 |
//! | `调用类` | 恒 `能力`（能力调用；资源访问走 `资源网关口` 那一条） |
//! | `资源号` | 恒 `0`（能力调用不涉及资源） |
//! | `操作号` | 恒 `0`（能力调用不涉及资源操作） |
//!
//! # 不进关键路径
//!
//! [`留痕缓冲::记`] 不取锁、不分配、不阻塞，满了按策略丢弃并计数
//! （`运行内核/调用留痕/` 文件头）。本层只在调用返回后调一次，**不改变调用结果**。
//!
//! # 容量为什么是构造参数
//!
//! `契约声明/常量表.json` 的「留痕容量」**已定数**（10000，台账 #26 已裁）⇒ 本层仍
//! **不发明默认值**（与 `资源网关口` 同一条纪律：契约是唯一的数源），容量由装配侧从
//! 契约常量取来给：[`适配器::启用留痕`]。生产装配在 `服务::绑定并托管` 里已按它开
//! ⇒ README §三「每次调用留痕」在生产路径成立；`适配器::装载` 自己不开口。

use std::sync::atomic::Ordering;

use v1_contract::声明数据;
use v1_trace::{丢弃策略, 留痕, 留痕缓冲};

use crate::边界面::业务错误码;
use crate::{适配器, 数据槽, 转发结果};

/// 入参指纹的偏移基数（FNV-1a 64 位）。**只做指纹**，不做加密。
const 指纹基数: u64 = 0xcbf2_9ce4_8422_2325;
/// FNV-1a 64 位的质数。
const 指纹质数: u64 = 0x0000_0100_0000_01b3;

impl 适配器 {
    /// 启用留痕（台账 #99）。容量由调用方给 —— **契约里那个数是未定数**，本层不发明
    /// 默认值（见文件头「容量为什么是构造参数」）。默认不启用。
    pub fn 启用留痕(&mut self, 容量: u32, 策略: 丢弃策略) {
        self.留痕 = Some(留痕缓冲::新建(容量, 策略));
    }

    /// 留痕开了没有（装配侧与验证面用）。
    pub fn 留痕已启用(&self) -> bool {
        self.留痕.is_some()
    }

    /// 取最近 `条数` 条留痕，**按时间序**（旧在前、新在后）。没启用 ⇒ 空表。
    pub fn 取留痕(&self, 条数: u32) -> Vec<留痕> {
        self.留痕
            .as_ref()
            .map_or_else(Vec::new, |缓冲| 缓冲.取最近(条数))
    }

    /// 因缓冲满而丢弃的留痕条数。**必须能读到**，否则丢痕是静默的。
    pub fn 留痕已丢弃(&self) -> u64 {
        self.留痕.as_ref().map_or(0, 留痕缓冲::已丢弃)
    }

    /// 记一条留痕。**调用路唯一的写点**，只在调用返回后调一次。
    pub(crate) fn 记一条留痕(
        &self,
        能力号: u32,
        参数: &[数据槽],
        结果: &转发结果,
        耗时微秒: u64,
    ) {
        let Some(缓冲) = self.留痕.as_ref() else {
            // 没启用 ⇒ 一条不记，也不计数（丢弃数只统计「启用后没写进去的」）。
            return;
        };
        缓冲.记(留痕::能力调用(
            self as *const 适配器 as u64,
            能力号,
            指纹(参数),
            结果码(结果),
            耗时微秒,
            self.追踪号.fetch_add(1, Ordering::Relaxed),
        ));
    }
}

/// 全部入参槽的 FNV-1a 指纹。**只看槽的字节**，不解释类型、不解引用指针。
fn 指纹(参数: &[数据槽]) -> u64 {
    let mut 指纹值 = 指纹基数;
    for 槽 in 参数 {
        for 字节 in 槽字段字节(槽) {
            指纹值 ^= u64::from(字节);
            指纹值 = 指纹值.wrapping_mul(指纹质数);
        }
    }
    指纹值
}

/// 一个槽的字段字节（定长、按字段顺序）。**不碰 `值` 指向的内存** ——
/// 指针值本身进指纹就够了，解引用会引入越界风险且不改变「入参不同指纹不同」这条性质。
fn 槽字段字节(槽: &数据槽) -> impl Iterator<Item = u8> {
    let 部件: [u64; 3] = [
        u64::from(槽.类型标签) | (u64::from(槽.标志) << 32) | (u64::from(槽.保留) << 48),
        槽.长度,
        槽.值,
    ];
    // `flat_map` + `to_le_bytes`：字节序固定，跨机器指纹一致（指纹要能比对）。
    部件.into_iter().flat_map(u64::to_le_bytes)
}

/// 这次调用的 4 位结果码：成功 = `0`；失败 = 业务错误码。
///
/// 「转发成功但返回槽是错误槽」也要报码 —— 那正是 `响应.rs::组装` 读槽的理由，
/// 留痕若只看 `转发结果` 就会把它记成成功（假读数）。
fn 结果码(结果: &转发结果) -> i32 {
    match 结果 {
        转发结果::成功(槽) if 槽.类型标签 == 声明数据::类型标签_4294967295 => {
            i32::try_from(u32::try_from(槽.值).unwrap_or(0)).unwrap_or(0)
        }
        转发结果::成功(_) => 0,
        转发结果::失败(错) => i32::try_from(业务错误码(*错)).unwrap_or(0),
    }
}
