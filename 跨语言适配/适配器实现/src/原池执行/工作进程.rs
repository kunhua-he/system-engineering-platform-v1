//! 工作进程 —— **扩展侧**的收调用循环：解调用帧 → 查注册表 → 调执行函数 → 编结果帧回。
//!
//! 依据：`临时件/落点/307收尾_接口冻结.md`（工作进程形状 · 唯一编解码）。
//!
//! # 它补的是哪一段
//!
//! `线协议.rs` 文件头原文写着「扩展侧的收调用循环由扩展自身实现（本 crate 不认识任何扩展）」
//! —— 而它**一直没被实现**。本件就是那一段：工作进程**复用** [`crate::线协议`] 的编解码
//! （同 crate ⇒ 天然共用一份，不会漂），只做「收 / 查 / 调 / 回」四步。
//!
//! # 唯一编解码（不许两份）
//!
//! 载荷的编解码**只有** [`crate::线协议`] 一份；帧的读写**只有** [`crate::进程帧`] 一份。
//! 本件一行编解码都不自带 —— 自带一份就是第二套协议。
//!
//! # 装载与调度也各只一条腿
//!
//! 装载走 [`crate::适配器::装载声明根`]（**全仓唯一**调 `载入声明` 的那一处），
//! 调度走 [`crate::适配器::调用能力`] —— 本件**不自查注册表、不直接调执行函数**。
//! 重走一遍就是绕过网关的第二条腿（判据 ⑪ 数的就是它）。
//!
//! # 形状（冻结件 §三）
//!
//! ```text
//! ① 接 stdout/stdin 上那条 UnixStream（进程池用 Stdio 接的）
//! ② dlopen 真制品：解包能力码段到缓存 → dlopen → dlsym("GetPlatformInfo") → 取声明
//! ③ 收帧循环：解调用帧 → 查注册表 → 调执行函数 → 编结果帧 → 回
//! ④ 收通知帧（2000 装载初始化 / 2001 卸载）→ 回通知回执
//! ⑤ 崩溃：进程消失即宿主侧查实崩溃，工作进程侧**不做自杀 / 重拉**
//! ```
//!
//! # 所有权（冻结件 §二）
//!
//! 收侧把过线字节**材料化**成宿主自有 `Box<[u8]>`（[`crate::值归还::收下字节槽`]）——
//! 入参副本活到**本次执行结束**，执行完（成功或失败两条路）由 [`crate::线协议::清理临时入参`]
//! 真回收。返回值序列化完成后同样按原所有权约定清理（[`crate::值归还::归还槽值`]）。
//!
//! # 为什么不在这里自杀 / 重拉
//!
//! 「崩溃检出」是**宿主侧**的事（`进程池::查实崩溃` 看子进程退出码）。工作进程自行重拉
//! 自身会让宿主看不到崩溃现场，退避与熔断也无从谈起 —— 故本件只做「收 / 查 / 调 / 回」。

