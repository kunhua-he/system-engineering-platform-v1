/// 接缝符号名（冻结，`边界协议.md` §二）。
const 接缝符号名: &str = "GetPlatformInfo";

/// 工作进程的结构化失败。**不 panic**（跨边界不许抛异常）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 工作进程错误 {
    /// 制品读不到 / 不是能力包件 / 段指纹不符（[`crate::装载件缓存::解包到缓存`] 的原因串）。
    制品不可用(String),
    /// `dlopen` 失败。
    装载失败(String),
    /// 取不到接缝符号，或接缝返回空指针。
    接缝缺失(String),
    /// 声明判定不过（标识串 / 号段 / 建表）。
    声明不可用(String),
    /// 收帧失败（通道断开 / 超预算 / 帧不合形）。
    收帧失败,
    /// 送帧失败。
    送帧失败,
}

/// dlopen 后取接缝声明：解包能力码段到仓外缓存 → `dlopen` → `dlsym("GetPlatformInfo")`。
///
/// **不复制** `扫扩展根`：制品路径由**调用方**给（本件不扫目录、不认后缀表、不认任何扩展名）。
/// 解包那一段走本 crate 既有的 [`crate::装载件缓存::解包到缓存`]（唯一实现）。
///
/// # 库的生命周期
///
/// `dlopen` 之后**不 `dlclose`**：取接缝要 `&'static`，句柄得活到进程结束；
/// 卸载走生命周期通知 `2001`，不是 `dlclose`（与 `扫扩展根.rs` 同一条处置）。
pub fn 装载支持库(
    制品路径: &Path,
    缓存根目录: &Path,
) -> Result<&'static 平台信息, 工作进程错误> {
    let 落盘路径 = crate::装载件缓存::解包到缓存(制品路径, 缓存根目录)
        .map_err(工作进程错误::制品不可用)?;
    let 路径串 = CString::new(落盘路径.as_os_str().as_encoded_bytes())
        .map_err(|_| 工作进程错误::装载失败(String::from("库路径含 NUL")))?;
    // SAFETY: 路径串是 NUL 结尾的合法 C 串；句柄只装载不释放（本进程活到被宿主回收）。
    let 句柄 = unsafe { dlopen(路径串.as_ptr(), RTLD_NOW) };
    if 句柄.is_null() {
        return Err(工作进程错误::装载失败(最近装载错误()));
    }
    let 符号名 = CString::new(接缝符号名).map_err(|_| 工作进程错误::接缝缺失(String::from("符号名含 NUL")))?;
    // SAFETY: 句柄非空（上面已挡）；符号名是合法 C 串。
    let 符号指针 = unsafe { dlsym(句柄, 符号名.as_ptr()) };
    if 符号指针.is_null() {
        return Err(工作进程错误::接缝缺失(最近装载错误()));
    }
    // SAFETY: 接缝形状由 `边界协议.md` §二 冻结：`const 平台信息* GetPlatformInfo(void)`。
    let 取平台信息: extern "C" fn() -> *const 平台信息 = unsafe { core::mem::transmute(符号指针) };
    let 指针 = 取平台信息();
    if 指针.is_null() {
        return Err(工作进程错误::接缝缺失(String::from("GetPlatformInfo 返回空指针")));
    }
    // SAFETY: 接缝规定「返回静态常量指针，终生有效；调用方不得释放、不得修改」
    // ⇒ 解引用得到 `'static` 只读引用是契约本身担保的事。
    Ok(unsafe { &*指针 })
}


/// 工作进程 —— 一个执行域一个实例：持有通道 + 一个适配器（装载 + 调度都走它）。
///
/// **不落 `static`**：同进程开两份就是两个互不干扰的工作进程（与 `进程池` 同一条纪律）。
pub struct 工作进程 {
    流通道: UnixStream,
    /// 本进程的适配器：**唯一**的装载腿与调度腿（本件不另走一条）。
    适配器: 适配器,
    /// 本进程装载的模块执行体（**按实例持有**，不落 `static`）：号来自制品段 16 的接口说明。
    ///
    /// 用 `BTreeMap` 而不是线性表：查号是**键取**，边界件里不出现按号比较（判据 ⑫）。
    模块执行体表: std::collections::BTreeMap<u32, 模块执行体项>,
    /// 已回传给宿主的最高追踪号（水印）：只回传比它新的那几条。
    ///
    /// 用「水印 + 既有留痕缓冲」当队列，**不另建第二份缓冲**：本进程留痕缓冲本身就是有界的
    /// （容量 = 契约常量 `留痕容量`，满了按策略丢）。
    已回传追踪号: Option<u64>,
}

impl 工作进程 {
    /// 装载真制品 → 判定 → 建注册表 → 接上通道（**全部就绪后才交出一个工作进程**）。
    ///
    /// 「声明不可用」与「制品不可用」分开报：前者是声明自身站不住（判定六步不过），
    /// 后者是制品本身不是可装载件 —— 两类故障的处置完全不同。
    pub fn 创建(
        流通道: UnixStream,
        支持库制品表: &[&Path],
        模块制品: Option<&Path>,
        缓存根目录: &Path,
    ) -> Result<Self, 工作进程错误> {
        let mut 声明表: Vec<&'static 平台信息> = Vec::with_capacity(支持库制品表.len() + 1);
        // 底座声明排在最前（与网关装配同一条顺序：扩展的依赖清单要能命中它）——
        // 同时也是「零支持库」那一形的合法声明根（空声明根会被装载入口拒成「空声明根」）。
        声明表.push(crate::底座声明());
        for 制品路径 in 支持库制品表 {
            声明表.push(装载支持库(制品路径, 缓存根目录)?);
        }
        // 装载走**全仓唯一那条腿**（[`适配器::装载声明根`]）：本件不直接调内核入口。
        let mut 适配器 = 适配器::装载声明根(&声明表)
            .map_err(|错误| 工作进程错误::声明不可用(format!("{错误:?}")))?;
        // **本进程留痕必须开**：内层调用（模块 → 宿主回调 → 支持库）记在本进程适配器上，
        // 不开就一条都没有。容量取契约常量 `留痕容量`（唯一数源），本件不发明默认值。
        适配器.启用留痕(crate::留痕容量, crate::丢弃策略::丢最旧);
        let mut 模块执行体表: std::collections::BTreeMap<u32, 模块执行体项> =
            std::collections::BTreeMap::new();
        if let Some(模块制品路径) = 模块制品 {
            // 号与**参数类型号表**都只从制品段 16 读（不写号表、不认模块名）。
            let 模块接口组 = crate::模块执行体装载::取模块接口组(模块制品路径)
                .map_err(|错误| 工作进程错误::制品不可用(format!("{错误:?}")))?;
            let 平台身份 = crate::模块执行体装载::本机平台身份().map_err(工作进程错误::制品不可用)?;
            let 能力号表: Vec<u32> = 模块接口组.iter().map(|说明| 说明.编号).collect();
            let mut 按号执行体 = crate::模块执行体装载::装载模块执行体组(模块制品路径, 缓存根目录, &平台身份, &能力号表)
                .map_err(|错误| 工作进程错误::制品不可用(format!("{错误:?}")))?;
            for 模块接口说明 in 模块接口组 {
            let 模块号 = 模块接口说明.编号;
            let 模块参数表: Vec<u32> = 模块接口说明
                .参数表
                .iter()
                .map(|参数项| 参数项.类型标签)
                .collect();
            let 执行体 = 按号执行体.remove(&模块号).ok_or_else(|| 工作进程错误::制品不可用(format!("模块执行体表缺能力{模块号}")))?;
            let 模块项 = 模块执行体项 {
                参数类型号表: 模块参数表,
                // 返回类型号也**只从段 16 读**（不写号表）：执行体交出的槽要按它校验。
                返回类型号: 模块接口说明.返回类型,
                执行体,
            };
            if 模块执行体表.insert(模块号, 模块项).is_some() {
                return Err(工作进程错误::制品不可用(format!("模块号 {模块号} 重复登记")));
            }
            }
        }
        Ok(Self { 流通道, 适配器, 模块执行体表, 已回传追踪号: None })
    }

    /// 本进程的适配器（验证面用）。
    pub fn 适配器(&self) -> &适配器 {
        &self.适配器
    }

    /// **起工作循环**：收到什么就答什么，直到通道断开（或对端不再送帧）。
    ///
    /// 返回 `Ok(())` = 通道断开（对端关了 / 进程被回收）—— **不是错误**：工作进程侧
    /// 不做自杀 / 重拉，退出即退出，崩溃检出归宿主侧 [`crate::进程池`]。
    pub fn 起工作循环(&mut self) -> Result<(), 工作进程错误> {
        loop {
            // 空闲等待不消耗单帧预算；首字节到达后才开始有界读帧。
            self.流通道.set_nonblocking(false).map_err(|_| 工作进程错误::收帧失败)?;
            let mut 首字节 = [0u8; 1];
            match self.流通道.read_exact(&mut 首字节) {
                Ok(()) => {},
                Err(错误) if 错误.kind() == std::io::ErrorKind::UnexpectedEof => return Ok(()),
                Err(_) => return Err(工作进程错误::收帧失败),
            }
            let mut 预算 = 本轮预算()?;
            let 帧体 = 接收续帧(&mut self.流通道, &mut 预算, Some(首字节[0]))
                .map_err(|_| 工作进程错误::收帧失败)?;
            match 帧体.消息类型 {
                消息类别::调用 => {
                    if self.答一次调用(&帧体).is_err() {
                        return Err(工作进程错误::送帧失败);
                    }
                }
                消息类别::通知 => {
                    if self.答通知(&帧体).is_err() {
                        return Err(工作进程错误::送帧失败);
                    }
                }
                // 其它类别不该送到工作进程：原样答一个回执（fail-closed，不静默丢）。
                _ => {
                    if self.回一帧(帧体.请求标识, 消息类别::通知回执, Vec::new()).is_err() {
                        return Err(工作进程错误::送帧失败);
                    }
                }
            }
        }
    }

    /// 答一次调用：解码 → 查注册表 → 调执行函数 → 编结果帧 → 回。
    fn 答一次调用(&mut self, 帧体: &消息帧) -> Result<(), 工作进程错误> {
        let Ok((号值, mut 入参槽表)) = 解码调用请求(&帧体.载荷) else {
            // 载荷不成形 ⇒ 协议码「参数不合法」（**不是**业务错误码）。
            return self.回结果(帧体.请求标识, 协议结果::参数不合法, &数据槽::空槽());
        };
        let mut 返回槽 = self.执行一次(号值, &mut 入参槽表);
        // 返回可能借用了输入副本：必须先按唯一协议编码，再归还内存。
        let 返回载荷 = 编码调用结果(协议结果::成功, &返回槽);
        if 返回槽.是否引用() && 入参槽表.iter().any(|入参槽|
            入参槽.是否引用() && 入参槽.槽值 == 返回槽.槽值)
        {
            // 同一分配由输入清理口归还一次，返回副本不得重复释放。
            返回槽 = 数据槽::空槽();
        }
        crate::值归还::归还槽值(&mut 返回槽);
        清理临时入参(&mut 入参槽表);
        self.回传新增留痕(帧体);
        let 返回载荷 = 返回载荷.map_err(|_| 工作进程错误::送帧失败)?;
        self.回一帧(帧体.请求标识, 消息类别::调用结果, 返回载荷)
    }

    /// 调一次能力。**走适配器**（[`适配器::调用能力`]）—— 本件不自查注册表、
    /// 不直接调执行函数：重走一遍就是绕过网关的第二条腿（判据 ⑪）。
    ///
    /// 失败（含未命中 / 参数个数不符）一律是**结构化段位且失败在返回槽里**，
    /// 与进程内路逐字一致 —— 因为这就是同一条路。
    fn 执行一次(&self, 号值: u32, 入参槽表: &mut [数据槽]) -> 数据槽 {
        // 模块号命中本进程装载的模块执行体 ⇒ 走**同一个 native 入口**（不新开调度腿）。
        if let Some(模块项) = self.模块执行体表.get(&号值) {
            let 参数类型号表 = &模块项.参数类型号表;
            // **形状先判**：模块没有挂在网关契约表里的声明，个数/类型不符若留给执行体回报，
            // 只会被压成「执行失败 1」⇒ 报成 `0035`（看着像崩溃）。这里按段 16 的参数表判，
            // 不符一律 `25 输入形状不符`（本侧输入问题，不是进程崩了）。
            if 入参槽表.len() != 参数类型号表.len() {
                return crate::进程调用::造跨进程错误槽(输入形状错误码);
            }
            for (槽项, 参数类型号) in 入参槽表.iter_mut().zip(参数类型号表) {
                if 槽项.类型标签.取号值() != *参数类型号 {
                    return crate::进程调用::造跨进程错误槽(输入形状错误码);
                }
                // **整数槽宽度归一到契约宽度 8**：模块 ABI 的 `取槽整数` 逐字校 `槽字节长度 == 8`
                // （构建侧生成物），而 HTTP 侧构造的内联整数槽宽度为 0（`槽编码::内联槽`）。
                // 只在模块这条腿上补宽度 —— 不改编码器、不改生成器，支持库那条路一分未动。
                if 槽项.类型标签 == 整数类型标签 && 槽项.槽字节长度 == 0 {
                    槽项.槽字节长度 = 8;
                }
            }
            // **实例上下文只借本栈帧**：指向本工作进程的**唯一**适配器（不落 `static` /
            // `thread_local`，也不往参数表塞内部地址）。宿主回调据此转调 `适配器::调用能力`
            // —— 组合链（模块 → 宿主 → 支持库）走的就是这一条，不复制注册表。
            let 返回类型号 = 模块项.返回类型号;
            if !模块项.执行体.有带上下文入口() {
                // **旧四参入口**（制品没带 `v1_module_exec_ctx`）：整数能力那条冻结语义原样跑
                // （7950 就是这一条）；复合返回没有上下文位可放 ⇒ 明确判失败，不硬塞整数。
                if 返回类型号 != 1 {
                    eprintln!(
                        "模块声明返回类型 {返回类型号}，但制品没有 v1_module_exec_ctx 入口 ⇒ 整槽返回不可用"
                    );
                    return crate::进程调用::造跨进程错误槽(扩展执行失败错误码);
                }
                return match 模块项.执行体.调用(入参槽表, 拒绝宿主回调) {
                    Ok(整数结果) => 数据槽::内联槽(整数类型标签, 整数结果 as u64, 0),
                    Err(执行错误) => {
                        eprintln!("模块执行体回报失败：{执行错误:?}（入参 {} 个）", 入参槽表.len());
                        crate::进程调用::造跨进程错误槽(扩展执行失败错误码)
                    }
                };
            }
            let mut 调用上下文 = 模块调用上下文 {
                适配器引用: &self.适配器, 临时返回槽: Vec::new(), 保留返回指针: 0,
            };
            let 上下文 = (&mut 调用上下文 as *mut 模块调用上下文<'_>).cast::<c_void>();
            let 执行结果 = 模块项.执行体.调用返回槽(上下文, 入参槽表, 适配器宿主回调);
            调用上下文.保留返回指针 = 执行结果.as_ref().ok()
                .filter(|槽项| 槽项.类型标签.取号值() == 返回类型号 && 槽项.是否引用())
                .map_or(0, |槽项| 槽项.槽值);
            return match 执行结果 {
                Ok(返回槽) => 调用上下文.收束模块返回(返回槽, 入参槽表, 返回类型号),
                // 宿主回调报上来的**真实业务原码**（1001 / 1100 …）—— 不压成 `0035`。
                Err(模块装载错误::执行失败(码值)) if 码值 > 0 => {
                    crate::进程调用::造跨进程错误槽(码值 as u32)
                }
                Err(执行错误) => {
                    eprintln!("模块执行体回报失败：{执行错误:?}（入参 {} 个）", 入参槽表.len());
                    crate::进程调用::造跨进程错误槽(扩展执行失败错误码)
                }
            };
        }
        let mut 返回槽 = 数据槽::空槽();
        match self.适配器.调用能力(号值, 入参槽表, &mut 返回槽) {
            转发结果::成功(槽体) => 槽体,
            转发结果::失败(错误) => crate::进程调用::造跨进程错误槽(
                crate::边界面::业务错误码(错误)
            ),
        }
    }

    /// 把本进程新记的内层调用留痕经**同一条 IPC** 回传宿主（只读旁路）。
    ///
    /// 有界：一次最多取 [`回传留痕条数`] 条（比它更早的旧条已被本进程缓冲按策略丢弃）；
    /// 发不出去就**只丢不回退** —— 留痕不进关键路径，绝不因为留痕发不出去把这次调用判失败。
    fn 回传新增留痕(&mut self, 帧体: &消息帧) {
        for 留痕项 in self.适配器.取留痕(回传留痕条数) {
            if self.已回传追踪号.is_some_and(|已回传| 留痕项.追踪号 <= 已回传) {
                continue;
            }
            self.已回传追踪号 = Some(留痕项.追踪号);
            let 载荷 = crate::进程帧::编码留痕记录(&留痕项);
            let Ok(mut 预算) = 本轮预算() else {
                return;
            };
            let 回传帧 = 消息帧 { 消息类型: 消息类别::留痕记录, 请求标识: 帧体.请求标识, 载荷 };
            if 发送帧(&mut self.流通道, &回传帧, &mut 预算).is_err() {
                return;
            }
        }
    }

    /// 答通知帧（2000 装载初始化 / 2001 卸载）→ 回通知回执。
    ///
    /// 工作进程**不 `dlclose`**：卸载是生命周期通知，不是卸载动态库（与 `扫扩展根.rs` 同）。
    fn 答通知(&mut self, 帧体: &消息帧) -> Result<(), 工作进程错误> {
        let 载荷 = 帧体.载荷.get(..4).map(|四字节| {
            u32::from_le_bytes(四字节.try_into().unwrap_or([0; 4]))
        });
        let _ = 载荷; // 通知号：2000 / 2001 都只答回执（工作进程侧不另做动作）。
        self.回一帧(帧体.请求标识, 消息类别::通知回执, Vec::new())
    }

    /// 编一次调用结果帧并回。
    fn 回结果(
        &mut self,
        请求标识: std::num::NonZeroU64,
        协议码值: i32,
        返回槽: &数据槽,
    ) -> Result<(), 工作进程错误> {
        let 载荷 = 编码调用结果(协议码值, 返回槽).map_err(|_| 工作进程错误::送帧失败)?;
        // 序列化完成后按原所有权约定清理临时值（返回槽若是扩展交出的引用槽，
        // 字节已拷进载荷 ⇒ 这块内存到此归还，失败路径也走同一条收尾）。
        let mut 清理槽 = *返回槽;
        crate::值归还::归还槽值(&mut 清理槽);
        self.回一帧(请求标识, 消息类别::调用结果, 载荷)
    }

    /// 送一帧（本件唯一的发送口）。
    fn 回一帧(
        &mut self,
        请求标识: std::num::NonZeroU64,
        帧类别: 消息类别,
        载荷: Vec<u8>,
    ) -> Result<(), 工作进程错误> {
        let mut 预算 = 本轮预算()?;
        let 帧体 = 消息帧 { 消息类型: 帧类别, 请求标识, 载荷 };
        发送帧(&mut self.流通道, &帧体, &mut 预算).map_err(|_| 工作进程错误::送帧失败)
    }
}

/// 一条已装载的模块执行体：段 16 的**参数类型号表** + **返回类型号** + 入口。
///
/// 表与入口同住一格：形状校验与调用必须用**同一份**声明，分开放就有漂移风险。
struct 模块执行体项 {
    参数类型号表: Vec<u32>,
    /// 段16声明的返回类型；实际返回槽必须逐字匹配，不压缩成整数。
    返回类型号: u32,
    执行体: crate::模块执行体装载::已装载执行体,
}

/// 旧四参整数入口的类型标签；带上下文入口沿完整返回槽传值。
const 整数类型标签: v1_contract::类型标签 = v1_contract::类型标签(1);

/// 模块执行体自身失败 ⇒ `0035 扩展执行崩溃`（已登记，**不新增错误码**）。
const 扩展执行失败错误码: u32 = 35;

/// 本侧输入形状不符 ⇒ `25 输入形状不符`（与跨进程载体同一码：**本侧参数问题不是进程崩了**）。
const 输入形状错误码: u32 = 25;

/// 错误码槽的类型标签（`0xFFFFFFFF`）—— 支持库把失败写进返回槽时用它标形状。
const 错误码类型标签: v1_contract::类型标签 =
    v1_contract::声明数据::类型标签_4294967295;

/// 宿主回调 —— **旧四参入口那条路**专用：冻结 ABI 没有 `userdata`，实例上下文没有合法透传路
/// （不许 `static` / `thread_local` 存适配器，也不许往参数表塞内部地址）。
///
/// 故旧入口若真调回调，一律回协议码 `-1`（参数不合法）—— **诚实拒绝**，不伪造「组合支持库已通」。
/// 组合链走的是 [`适配器宿主回调`]（带上下文那一路）。
extern "C" fn 拒绝宿主回调(
    宿主号: u32,
    入参指针: *const 数据槽,
    入参个数: usize,
    返回指针: *mut 数据槽,
) -> i32 {
    let _ = (宿主号, 入参指针, 入参个数, 返回指针);
    -1
}

/// 模块单次调用的资源归属：中间返回值在调用结束统一归还，最终返回值交外层。
struct 模块调用上下文<'上下文> {
    适配器引用: &'上下文 适配器,
    临时返回槽: Vec<数据槽>,
    保留返回指针: u64,
}


impl 模块调用上下文<'_> {
    fn 收束模块返回(&mut self, 返回槽: 数据槽, 入参槽表: &[数据槽], 返回类型号: u32) -> 数据槽 {
        if 返回槽.类型标签.取号值() != 返回类型号 {
            eprintln!("模块执行体返回标签不符：声明 {返回类型号} · 实得 {}（入参 {} 个）",
                返回槽.类型标签.取号值(), 入参槽表.len());
            // 输入由输入清理口持有；宿主临时槽由本上下文持有，新交出槽才补入唯一归还口。
            if 返回槽.是否引用() && 返回槽.交出了所有权()
                && !入参槽表.iter().any(|入参槽| 入参槽.是否引用() && 入参槽.槽值 == 返回槽.槽值)
                && !self.临时返回槽.iter().any(|槽项| 槽项.是否引用() && 槽项.槽值 == 返回槽.槽值)
            {
                self.临时返回槽.push(返回槽);
            }
            return crate::进程调用::造跨进程错误槽(扩展执行失败错误码);
        }
        返回槽
    }
}

impl Drop for 模块调用上下文<'_> {
    fn drop(&mut self) {
        let mut 已归还地址 = std::collections::BTreeSet::new();
        for 槽项 in &mut self.临时返回槽 {
            if 槽项.槽值 != self.保留返回指针 && 已归还地址.insert(槽项.槽值) {
                crate::值归还::归还槽值(槽项);
            }
        }
    }
}

/// 宿主回调 —— **转调本实例唯一适配器**（`适配器::调用能力`），不复制注册表、不另开调度腿。
///
/// 上下文由 [`工作进程::执行一次`] 借出（指向本工作进程的适配器，**只在一次调用栈帧内有效**）；
/// 模块与回调都不缓存、不释放它。返回 `0` = 成功；非零 = 业务原码（与进程内路同一条路：
/// 生成侧 `错误码转返回码` 按位原样上抛 ⇒ 1001 / 1100 不压成 1）。
extern "C" fn 适配器宿主回调(
    上下文: *mut c_void,
    能力号: u32,
    入参指针: *const 数据槽,
    入参个数: usize,
    返回槽指针: *mut 数据槽,
) -> i32 {
    if 上下文.is_null() || 返回槽指针.is_null() {
        return 输入形状错误码 as i32;
    }
    if 入参个数 != 0 && 入参指针.is_null() {
        return 输入形状错误码 as i32;
    }
    // SAFETY: 上下文由执行一次的栈帧持有；只借出适配器并记录本次临时返回值；
    // 入参指针 / 个数由执行体按其段 16 参数表给出（同一次栈帧内有效）。
    let 调用上下文 = unsafe { &mut *(上下文 as *mut 模块调用上下文<'_>) };
    let 适配器引用 = 调用上下文.适配器引用;
    let 入参槽表: &[数据槽] = if 入参个数 == 0 {
        &[]
    } else {
        unsafe { std::slice::from_raw_parts(入参指针, 入参个数) }
    };
    let mut 返回槽 = 数据槽::空槽();
    match 适配器引用.调用能力(能力号, 入参槽表, &mut 返回槽) {
        转发结果::成功(槽体) => {
            // 支持库把失败写在返回槽里（错误槽：标签 `0xFFFFFFFF`、内联值 = 码）时，回调必须把它
            // 翻成**非零返回码**：模块的生成包装只在非零时判 `宿主失败(码)`；不翻就会被当成结果
            // 交出去、再被返回类型校验压成 `1`（原码 1001 / 1100 就丢了）。
            if 槽体.类型标签 == 错误码类型标签 {
                let 码值 = 槽体.槽值 as u32;
                // SAFETY: 返回槽指针由执行体给出（非空已挡），同一次栈帧内有效。
                unsafe { 返回槽指针.write(槽体) };
                return 码值 as i32;
            }
            if 槽体.是否引用() && 槽体.交出了所有权()
                && !入参槽表.iter().any(|入参槽| 入参槽.是否引用() && 入参槽.槽值 == 槽体.槽值)
            {
                调用上下文.临时返回槽.push(槽体);
            }
            // SAFETY: 同上。
            unsafe { 返回槽指针.write(槽体) };
            0
        }
        转发结果::失败(错误) => {
            let 码值 = crate::边界面::业务错误码(错误) as i32;
            // SAFETY: 同上。
            unsafe { 返回槽指针.write(返回槽) };
            码值
        }
    }
}

/// 造一轮的收发预算（每轮独立，**不跨轮累积**）。
fn 本轮预算() -> Result<调用帧预算, 工作进程错误> {
    调用帧预算::创建(Instant::now() + Duration::from_millis(循环预算毫秒))
        .map_err(|_| 工作进程错误::收帧失败)
}

#[cfg(test)]
#[test]
fn 模块标签拒绝四类所有权逐址只还一次() {
    use crate::边界测试::{泄漏读数_盯住, 泄漏读数_命中};
    let 适配器引用 = 适配器::装载声明根(&[crate::底座声明()]).unwrap();
    for 场景编号 in 0..6 {
        let mut 返回槽 = crate::值归还::收下字节槽(v1_contract::类型标签::构造(5), "模块归还验证".as_bytes());
        let mut 调用上下文 = 模块调用上下文 {
            适配器引用: &适配器引用, 临时返回槽: Vec::new(), 保留返回指针: 0,
        };
        let mut 入参槽表 = Vec::new();
        if 场景编号 == 1 { 入参槽表.push(返回槽); }
        if 场景编号 == 2 || 场景编号 == 4 || 场景编号 == 5 {
            调用上下文.临时返回槽.push(返回槽);
        }
        if 场景编号 == 5 { 调用上下文.临时返回槽.push(返回槽); }
        let 槽体 = if 场景编号 == 3 {
            数据槽::指针(返回槽.类型标签, 返回槽.槽值, 返回槽.槽字节长度, false)
        } else { 返回槽 };
        泄漏读数_盯住(返回槽.槽值 as usize);
        if 场景编号 == 4 { 调用上下文.保留返回指针 = 返回槽.槽值; }
        let 槽体 = 调用上下文.收束模块返回(槽体, &入参槽表, if 场景编号 == 4 { 5 } else { 4 });
        if 场景编号 == 4 { assert_eq!(槽体, 返回槽); }
        else { assert_eq!(槽体, crate::进程调用::造跨进程错误槽(扩展执行失败错误码)); }
        drop(调用上下文);
        let 释放次数 = 泄漏读数_命中();
        // 清除观察地址，后续分配器复用同址不得污染本次读数。
        泄漏读数_盯住(0);
        if 场景编号 == 1 {
            assert_eq!(释放次数, 0, "输入别名只能由输入清理口归还");
            泄漏读数_盯住(返回槽.槽值 as usize);
            清理临时入参(&mut 入参槽表);
            let 释放次数 = 泄漏读数_命中();
            泄漏读数_盯住(0);
            assert_eq!(释放次数, 1);
        } else if 场景编号 == 3 || 场景编号 == 4 {
            assert_eq!(释放次数, 0, "借用或成功交出返回值不由上下文释放");
            泄漏读数_盯住(返回槽.槽值 as usize);
            crate::值归还::归还槽值(&mut 返回槽);
            let 释放次数 = 泄漏读数_命中();
            泄漏读数_盯住(0);
            assert_eq!(释放次数, 1);
        } else {
            // 反向样本失败时也先归还分配，测试不会留下堆块。
            if 释放次数 == 0 { crate::值归还::归还槽值(&mut 返回槽); }
            assert_eq!(释放次数, 1, "场景{场景编号}新槽、登记槽或重复登记只能归还一次");
        }
    }
}
