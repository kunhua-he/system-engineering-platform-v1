//! 进程池 · 帧收发 —— 池面那些「在通道上读写一帧」的方法。
//!
//! 从 `进程池.rs` 拆出（单源 ≤ 400 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管**进程**（拉起 · 监督 · 退避 · 熔断），子件管**帧**（发/收/重放/回执）。
//! 两者是同一件事的两个面：崩溃检出靠帧层的 EOF，帧层报什么错靠进程活没活。
//!
//! 子件能读父件的私有字段（Rust 隐私：子模块看得见祖先的私有项）。
//!
//! # 锁收窄（冻结件 §五 末行）
//!
//! 本件的每个方法都**只持该域本域那把锁**（`域句柄.锁()`）—— 域表锁早已在
//! `取域句柄` 那一步放掉。故**一个慢域阻塞不了健康域**：慢域的收发在本域锁里等，
//! 健康域拿本域句柄各走各的。
//!
//! # 预算：**共用剩余**，不因进入下一阶段重置（冻结件 §五）
//!
//! 每个方法都收一条**调用方给的** [`调用帧预算`]：长调用路（`跨进程域表` 那条）
//! 从保证域在开始造一条，重放 / 收执 / 发 / 收**共用同一条** ⇒ 一条调用从排队到收完
//! 只花一份时限，不会每进一个阶段就把时钟拨回去。

use std::num::NonZeroU64;
use std::time::{Duration, Instant};

use crate::进程帧::调用帧预算;

use super::{域句柄, 查实崩溃, 进程池错误, 重放预算毫秒};

impl 域句柄 {
    /// **发一条调用帧**（按调用方给的预算）。**通道断开 ⇒ 查实崩溃再报码**（不是直报）：
    /// EOF 是「可能崩了」的现场，真崩没崩由 `查实崩溃` 看子进程退出码定；
    /// 查实了才计崩溃次数。
    pub(crate) fn 发一调用帧按预算(
        &self,
        请求标识: NonZeroU64,
        待发载荷: &[u8],
        budget: &mut 调用帧预算,
    ) -> Result<(), 进程池错误> {
        // ★ **先判长度再复制**：超过单帧上限的载荷当场结构化拒 —— 不先 `to_vec()` 复制一整块
        //   再让帧层拒（旧形状：大载荷白复制一次，还被误报成通道错）。
        if 待发载荷.len() > crate::进程帧::单帧载荷上限 {
            return Err(进程池错误::载荷过大);
        }
        let mut 工作 = self.互斥锁();
        if !工作.运行中 {
            return Err(进程池错误::通道断开);
        }
        let 调用帧 = crate::进程帧::消息帧 {
            消息类型: crate::进程帧::消息类别::调用,
            请求标识,
            载荷: 待发载荷.to_vec(),
        };
        let 执行结果 = crate::进程帧::发送帧(&mut 工作.流通道, &调用帧, budget);
        if 执行结果.is_err() {
            return Err(废弃失步通道(self.配置, &mut 工作));
        }
        Ok(())
    }

    /// **收一条调用回帧**（按调用方给的预算）。回帧不成形 ⇒ 查实崩溃再按存活判错。
    pub(crate) fn 收一调用回帧按预算(
        &self,
        请求标识: NonZeroU64,
        budget: &mut 调用帧预算,
        收痕口: Option<&dyn Fn(&v1_trace::留痕)>,
    ) -> Result<Vec<u8>, 进程池错误> {
        let mut 工作 = self.互斥锁();
        if !工作.运行中 {
            return Err(进程池错误::通道断开);
        }
        loop {
            match crate::进程帧::接收帧(&mut 工作.流通道, 请求标识, budget) {
                Ok(帧体) if 帧体.消息类型 == crate::进程帧::消息类别::调用结果 =>
                {
                    return Ok(帧体.载荷);
                }
                // **内层留痕**（工作进程 → 宿主，只读旁路）：先收进本实例缓冲，再继续等结果。
                // 不改调用结果、不额外往返；帧不成形就丢这一条（不猜）。
                Ok(帧体) if 帧体.消息类型 == crate::进程帧::消息类别::留痕记录 => {
                    if let (Some(收痕口), Some(留痕项)) =
                        (收痕口, crate::进程帧::解码留痕记录(&帧体.载荷))
                    {
                        收痕口(&留痕项);
                    }
                }
                Ok(_) | Err(_) => {
                    return Err(废弃失步通道(self.配置, &mut 工作));
                }
            }
        }
    }

    /// 收装载初始化的回执（与重放配对的那一帧，按调用方给的预算）。
    ///
    /// # 为什么必须收（不是可选）
    ///
    /// 重放只发不回，回帧就留在通道里 —— 下一条调用去读时先读到它，请求标识对不上
    /// ⇒ 当场报「请求、长度或预算不符」。表现为「重拉过的域第一次调用必失败」，
    /// 而报的还是一个看不出来源的错（实测：本条腿初版就是这形状）。
    ///
    /// 口径：回执是**重放成功**的判据（拆解件那行原文：「重拉后通知端点数恢复、回执成功」）。
    /// 收不到 ⇒ 这个域不算重放完成，报 [`进程池错误::通道断开`]。
    pub(crate) fn 收装载回执按预算(
        &self,
        请求标识: NonZeroU64,
        budget: &mut 调用帧预算,
    ) -> Result<(), 进程池错误> {
        let mut 工作 = self.互斥锁();
        if !工作.运行中 {
            return Err(进程池错误::通道断开);
        }
        match crate::进程帧::接收帧(&mut 工作.流通道, 请求标识, budget) {
            Ok(帧体) if 帧体.消息类型 == crate::进程帧::消息类别::通知回执 => {
                工作.装载已重放 = true;
                Ok(())
            }
            _ => Err(废弃失步通道(self.配置, &mut 工作)),
        }
    }

    /// 重放装载初始化：向这个域发一条**通知号 2000** 的帧（不恢复业务任务，按调用方给的预算）。
    pub(crate) fn 重放装载初始化按预算(
        &self,
        请求标识: NonZeroU64,
        budget: &mut 调用帧预算,
    ) -> Result<(), 进程池错误> {
        let mut 工作 = self.互斥锁();
        if !工作.运行中 {
            return Err(进程池错误::通道断开);
        }
        let 通知帧 = crate::进程帧::消息帧 {
            消息类型: crate::进程帧::消息类别::通知,
            请求标识,
            载荷: v1_contract::声明数据::通知号_2000.to_le_bytes().to_vec(),
        };
        if crate::进程帧::发送帧(&mut 工作.流通道, &通知帧, budget).is_err() {
            return Err(废弃失步通道(self.配置, &mut 工作));
        }
        Ok(())
    }

    /// **调用一域**：自造一条独立预算，发一条调用帧、收同标识的回帧（验证面与单步调用用）。
    ///
    /// 长调用路（`跨进程域表`）走 [`域句柄::发一调用帧按预算`] +
    /// [`域句柄::收一调用回帧按预算`] 共用一条预算。
    ///
    /// 载荷的编解码**不在这里**（本件不认任何协议语义）—— 调用方给的是已编好的载荷，
    /// 收到的也是裸载荷。为什么这样切：帧层与线协议层各管各的，`线协议.rs` 已经做了
    /// 「调用形状 ↔ 载荷」的翻译，本件再做一次就是第二套。
    pub fn 调用一域(
        &self,
        请求标识: NonZeroU64,
        待发载荷: &[u8],
    ) -> Result<Vec<u8>, 进程池错误> {
        let mut 预算 = 自造预算()?;
        let 事务守卫 = self.锁事务(&预算)?;
        let _ = &事务守卫;
        self.发一调用帧按预算(请求标识, 待发载荷, &mut 预算)?;
        self.收一调用回帧按预算(请求标识, &mut 预算, None)
    }
}

/// 通道出错后**按进程死没死**分开报：死了 = 崩溃，没死 = 预算耗尽。
///
/// 这条分界不是措辞游戏：`0034 能力进程崩溃` 的说明里明写「与 0004 超时分开
/// （超时是进程活着但没答）」—— 把两者报成同一个码，那条说明就成了空话。
fn 按存活判错(工作: &super::工作进程) -> 进程池错误 {
    if 工作.运行中 {
        进程池错误::预算耗尽
    } else {
        进程池错误::通道断开
    }
}

/// 造一条本件自用的短预算（≤ 五秒硬顶）。
fn 自造预算() -> Result<调用帧预算, 进程池错误> {
    let 截止 = Instant::now() + Duration::from_millis(重放预算毫秒);
    调用帧预算::创建(截止).map_err(|_| 进程池错误::拉起失败)
}

/// 故障处置与停止状态同持本域锁；只弃通道、不重放已发业务调用。
fn 废弃失步通道(
    配置: super::进程池配置, 工作: &mut super::工作进程
) -> 进程池错误 {
    废弃失步通道按回收(配置, 工作, |工作| {
        super::击杀并确认退出(工作, super::默认确认预算毫秒)
    })
}

/// 失步后的处置：弃通道 → 强杀 → **按收尸结论定报什么错**。
///
/// 为什么必须分两种报：`通道断开` 的说明是「拉起来过、现在没了」，那是**确认过**的
/// 事实；收尸没收着时进程可能还活着，报同一个码等于把未知当已死，上游会立刻重发或
/// 重拉，第二个工作进程就与旧进程同域并存。未确认一律报
/// [`进程池错误::未确认退场`]：归属与额度都留着，重拉由
/// `域句柄定义.rs::保证在按前提` 的 `回收已确认` 闸继续挡住，直到真收着尸。
///
/// 回收动作做成入参，只为让「收尸没成功」这条支路能被确定性验证
/// （真 SIGKILL 无法稳定复现收不到尸）。
fn 废弃失步通道按回收(
    配置: super::进程池配置,
    工作: &mut super::工作进程,
    回收动作: impl FnOnce(&mut super::工作进程) -> super::回收结局,
) -> 进程池错误 {
    查实崩溃(配置, 工作);
    let 错误 = 按存活判错(工作);
    let _ = 工作.流通道.shutdown(std::net::Shutdown::Both);
    工作.装载已重放 = false;
    let 结局 = 回收动作(工作);
    工作.运行中 = false;
    if 结局 == super::回收结局::未确认退出 || !工作.回收已确认 {
        return 进程池错误::未确认退场;
    }
    错误
}

#[cfg(test)]
mod 退场判据测试 {
    use super::*;
    use crate::进程池::{进程池, 进程池配置, 执行域标识};

    fn 建一域() -> (进程池, 执行域标识) {
        let 执行池 = 进程池::创建(进程池配置::default());
        let 域标识 = 执行域标识 {
            适配器实例号: 93,
            扩展标识串: String::from("退场判据验证"),
            制品版本: (1, 0, 0),
        };
        执行池.保证域在(&域标识, "/bin/cat", &[]).unwrap();
        (执行池, 域标识)
    }

    /// 收尸没收着 ⇒ 不许当成「确认死了」，也不许丢归属与额度。
    #[test]
    fn 收尸未确认报未确认退场且保留归属() {
        let (执行池, 域标识) = 建一域();
        let 句柄 = 执行池.取域句柄(&域标识).unwrap();
        let 错误 = {
            let mut 工作 = 句柄.互斥锁();
            废弃失步通道按回收(进程池配置::default(), &mut 工作, |_| {
                super::super::回收结局::未确认退出
            })
        };
        let 保留归属 = 执行池.含域(&域标识);
        let 保留额度 = 执行池.活进程数();
        assert_eq!(
            错误,
            进程池错误::未确认退场,
            "未确认退场必须单独报，不能报成通道断开或预算耗尽"
        );
        assert!(
            保留归属 && 保留额度 == 1,
            "未确认退场不能丢归属，也不能提前归还额度"
        );
        let _ = 句柄.击杀并报结局();
        drop(句柄);
        assert!(执行池.移除一域(&域标识));
        assert_eq!(执行池.活进程数(), 0);
    }

    /// 真收着尸 ⇒ 仍按存活判错（通道断开 / 预算耗尽），不得一律升级成未确认。
    #[test]
    fn 收尸确认后沿用按存活判错() {
        let (执行池, 域标识) = 建一域();
        let 句柄 = 执行池.取域句柄(&域标识).unwrap();
        let 错误 = {
            let mut 工作 = 句柄.互斥锁();
            废弃失步通道按回收(进程池配置::default(), &mut 工作, |工作| {
                super::super::击杀并确认退出(工作, super::super::默认确认预算毫秒)
            })
        };
        assert!(
            错误 == 进程池错误::预算耗尽 || 错误 == 进程池错误::通道断开,
            "收尸确认后应沿用按存活判错，实报 {错误:?}"
        );
        drop(句柄);
        let _ = 执行池.移除一域(&域标识);
        assert_eq!(执行池.活进程数(), 0);
    }
}
