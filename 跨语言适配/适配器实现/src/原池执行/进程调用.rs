//! 进程调用 —— 适配器持有的「跨进程执行域表」：把一条调用送到工作进程，并把失败翻成结构化码。
//!
//! 依据：`临时件/W01_裁决_架构升级.md`（六项未定项的推荐收口）·
//! `项目文档/决策记录/2026-10-06_子进程执行路前置裁决.md` 第二条（进程管理落点 = 适配器）与
//! 第三条（崩溃报 `0034`）。
//!
//! # 它补的是哪一段
//!
//! `进程池.rs` 管「进程活着没」（拉起 · 监督 · 退避重拉），`线协议.rs` 管「一次调用怎么摆进帧」，
//! 本件把两者接到**一条真实调用路**上：给定执行域 ⇒ 保证域在 ⇒（必要时）重放装载初始化 ⇒
//! 发起调用 ⇒ 收结果。它是「调度不碰进程」那条分工里**载体侧的一半**。
//!
//! # 状态按实例持有
//!
//! [`跨进程域表`] 是**适配器实例的东西**（`适配器.跨进程` 字段），**不落任何进程级 `static`** ——
//! 同进程里开两份适配器就是两个互不干扰的执行域表（多实例安全，与 `部署绑定` 同一条理由）。
//!
//! # 失败一律结构化
//!
//! 三条失败路 —— 拉起失败 / 熔断中 · 通道断开（EOF）⇒ 崩洏已查实 · 代次不符（陈旧句柄）——
//! 全部翻成**返回槽里的错误槽**（`类型标签_4294967295` + 码 `0034`），
//! **不 panic**、不给调度错误加进程变体。
//! 「调度判该不该报错，载体管进程活着没」：本件只把载体看到的事实报回去，
//! 怎么处理（重试 / 熔断 / 上报）由调用方与部署策略定。

use std::num::NonZeroU64;
use std::os::unix::net::UnixStream;
use std::sync::Arc;
use std::sync::atomic::{AtomicU64, Ordering};

use v1_contract::{声明数据, 数据槽};

use crate::进程池::{启动握手预算毫秒, 域句柄, 执行域标识, 进程池, 进程池错误, 进程池配置};

/// 一次跨进程调用的结构化结果。
///
/// **就这两样**：要么带回一个槽，要么带回一个**已登记的错误码值**（不是字符串、不是 panic）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 跨进程结果 {
    /// 协议层成立，带回返回槽。槽里可能是值，也可能是扩展自行写的错误槽。
    回槽(数据槽),
    /// 载体侧失败：值 = 已登记的错误码（本版只有 `0034`）。
    失败(u32),
}

/// 一个执行域的**部署参数**：从哪拉起（程序 + 参数）。
///
/// 它与 [`执行域标识`] 分开持有：同一个域换一次部署（重启后换二进制路径）
/// 不改域的身份，改的是「调哪一份」（与 `部署绑定` 同一件事的两面）。
#[derive(Clone, PartialEq, Eq)]
pub struct 域部署 {
    pub 启动程序: String,
    pub 启动参数: Vec<String>,
}

/// 跨进程执行域表 —— 适配器实例持有的东西：一个池 + 各域的部署参数 + 各域的会话。
///
/// **不落 `static`**；`进程池` 自身的 `Drop` 会把全部工作进程组回收（不留孤儿）。
///
/// 会话与池分开存：池的字段在它的模块里是私有的，而「发一次调用」要用到 `UnixStream`。
/// 两条腿各自持有它自身需要的东西，不把池的字段公开出去。
#[cfg(unix)]
pub struct 跨进程域表 {
    执行池: Arc<进程池>,
    部署表: Vec<(执行域标识, Arc<域登记>)>,
    回收通知: Arc<回收信号>,
    回收线程: Option<std::thread::JoinHandle<()>>,
    /// 模块能力的号 → 它所属的执行域（**通用模块身份登记**）。
    ///
    /// 支持库与模块是**两种身份**，但归**同一个**域表、同一个进程池、同一个工作进程启动器。
    /// 模块没有 `GetPlatformInfo` 声明 ⇒ 走不了「按声明算域标识」那条路（那要 `&'static 平台信息`），
    /// 它的身份来自**包声明**（标识串 + 实现版本）与**制品段 16**（能力号），登记时记在这里，
    /// 路由时按号命中 —— 不猜、不写号表。
    模块路由表: std::collections::BTreeMap<u32, 执行域标识>,
    /// 请求标识号源。`Arc` 是为了能**脱离表锁**单独取出（见 [`跨进程域表::取号源`]）——
    /// 长执行不持表锁，就不能再靠 `&self` 拿它。
    请求号源: Arc<AtomicU64>,
}

#[cfg(unix)]
impl 跨进程域表 {
    /// 建一个空表（一份部署配置应用到所有域）。
    pub fn 创建(配置: 进程池配置) -> Self {
        Self {
            执行池: Arc::new(进程池::创建(配置)),
            回收通知: Arc::new(回收信号::创建()),
            回收线程: None,
            部署表: Vec::new(),
            模块路由表: std::collections::BTreeMap::new(),
            请求号源: Arc::new(AtomicU64::new(1)),
        }
    }

    /// 这个域登记过没有。
    pub fn 含域(&self, 标识: &执行域标识) -> bool {
        self.部署表.iter().any(|格子| &格子.0 == 标识)
    }

    /// 已登记域数（验证面用）。
    pub fn 已建执行域(&self) -> usize {
        self.执行池.已建域数()
    }

    /// 只登记已验制品的部署事实，不启动业务进程。
    pub fn 登记跨进程域(
        &mut self, 标识: 执行域标识, 部署: 域部署,
    ) -> Result<(), 进程池错误> {
        if 部署.启动程序.is_empty() { return Err(进程池错误::拉起失败); }
        if let Some(格子) = self.部署表.iter().find(|格子| 格子.0 == 标识) {
            return if 格子.1.部署 == 部署 { Ok(()) } else { Err(进程池错误::部署参数不符) };
        }
        let 登记 = 域登记::创建(标识.clone(), 部署, Arc::clone(&self.执行池), Arc::clone(&self.回收通知));
        self.部署表.push((标识, 登记));
        Ok(())
    }

    /// **装载初始化握手**（重放装载初始化 + 收装载回执）——**由调用方在短表锁里先取好
    /// 句柄与号源**，本函数只锁**该域那一把事务锁**。
    ///
    /// 为什么不收 `&self`：收 `&self` 就要求调用方**持着域表锁**才能调它，而握手是
    /// **长执行**（拉起 + 装帧，可达一条调用预算）⇒ 装载期间全部域（含健康域）的调用都被
    /// 那一把表锁挡住（本件 3071）。收「句柄 + 号源」把长执行收窄到该域，
    /// 与 `送一登记调用` 同一条处置。
    #[cfg(test)]
    pub(crate) fn 初始化一域按句柄(
        句柄: &域句柄,
        号源: &AtomicU64,
    ) -> Result<(), 进程池错误> {
        let 起点 = std::time::Instant::now();
        // **握手用启动预算**（不是调用预算）：这一段量的是「进程从 exec 到答第一帧」，
        // 包含解包 + 两次 dlopen + 建注册表；拿调用预算（1000）量它，冷启动就把预算吃光，
        // 报出来只剩「预算耗尽」，节点不可判（反馈 4786）。
        let mut 预算 = crate::进程帧::调用帧预算::创建(
            std::time::Instant::now() + std::time::Duration::from_millis(启动握手预算毫秒),
        ).map_err(|_| 进程池错误::拉起失败)?;
        let 事务守卫 = 句柄.锁事务(&预算)?;
        let _ = &事务守卫;
        let 请求标识 = 取请求标识(号源);
        let 握手 = 句柄
            .重放装载初始化按预算(请求标识, &mut 预算)
            .and_then(|()| 句柄.收装载回执按预算(请求标识, &mut 预算));
        握手.map_err(|错误值| 按握手错翻(错误值, 起点.elapsed().as_millis() as u64))
    }

    /// **登记一个已连好的域**：对端已有一条现成通道（验证面与「宿主已代拉起」的部署用）。
    ///
    /// 与 [`跨进程域表::登记跨进程域`] 的分工：那个自行拉起进程，这个收一条别人给的连接 ——
    /// 验证面要验「往返」与「通道断开」，两种场景都不需要一个真子进程。
    pub fn 登记已连域(
        &mut self,
        标识: 执行域标识,
        宿主端: UnixStream,
    ) -> Result<(), 进程池错误> {
        self.执行池.收下已连域(标识.clone(), 宿主端, 默认部署())?;
        let 部署 = 默认部署();
        let 登记 = 域登记::创建(标识.clone(), 部署, Arc::clone(&self.执行池), Arc::clone(&self.回收通知));
        self.部署表.push((标识, 登记));
        Ok(())
    }

    /// 取一份**部署参数副本**（克隆）：长执行要脱离表锁，就不能只借它的引用。
    fn 取登记(&self, 标识: &执行域标识) -> Option<Arc<域登记>> {
        self.部署表.iter().find(|格子| &格子.0 == 标识).map(|格子| Arc::clone(&格子.1))
    }

    /// 取请求标识号源（`Arc`）：脱离表锁后用。
    pub fn 取号源(&self) -> Arc<AtomicU64> {
        Arc::clone(&self.请求号源)
    }

    /// 取域句柄（短口：长执行靠它，不再持表锁）。
    pub fn 取句柄(&self, 标识: &执行域标识) -> Option<域句柄> {
        self.执行池.取域句柄(标识)
    }

    /// **击杀一域**（整组）：验证面要、部署下架也要。
    ///
    /// 击杀之后本域仍留在表里（“登记过”这件事不变）—— 下次调用会走「保证域在」重拉，
    /// 受退避与重启预算管。
    pub fn 击杀跨进程域(&self, 标识: &执行域标识) -> Result<(), 进程池错误> {
        if !self.含域(标识) { return Err(进程池错误::域不存在); }
        if !self.执行池.含域(标识) { return Ok(()); }
        self.执行池.击杀一域(标识)
    }

    /// **移除一域**（切换后回收旧版 / 部署下架）：杀进程组 + 摘域格 + 摘部署表。
    ///
    /// 与 [`跨进程域表::击杀跨进程域`] 分开：击杀留格留部署表（下次调用重拉）；移除把两本账都摘。
    /// 返回是否真摘过（没这域 ⇒ `false`，不假装）。
    pub fn 移除一域(&mut self, 标识: &执行域标识) -> bool {
        let 已登记 = self.含域(标识);
        if let Some(登记) = self.取登记(标识) { 登记.注销(); }
        self.回收通知.唤醒();
        let 已回收 = self.执行池.移除一域(标识);
        if !已回收 && self.执行池.含域(标识) { return false; }
        self.部署表.retain(|格子| &格子.0 != 标识);
        self.模块路由表.retain(|_, 域标识| 域标识 != 标识);
        已回收 || 已登记
    }

    /// 记一条**模块路由**（号 → 执行域）。同一个号只留一条（重复登记以最后一次为准）。
    pub fn 登记模块路由(&mut self, 号值: u32, 标识: 执行域标识) {
        self.模块路由表.insert(号值, 标识);
    }

    /// 这个号属于哪个已登记的模块域（没登记过 ⇒ `None`，调用方走声明那条路）。
    pub fn 取模块域标识(&self, 号值: u32) -> Option<执行域标识> {
        self.模块路由表.get(&号值).cloned()
    }

    /// 摘掉一个号的模块路由并回收它的域（卸载：杀进程组 + 摘域格 + 摘部署表）。
    ///
    /// 返回是否真回收过（没这条路由 ⇒ `false`，不假装）。
    pub fn 移除模块域(&mut self, 号值: u32) -> bool {
        let Some(标识) = self.取模块域标识(号值) else {
            return false;
        };
        self.模块路由表.retain(|_, 域标识| *域标识 != 标识);
        self.移除一域(&标识)
    }

    /// **送一调用**：保证域在 ⇒ （必要时）重放装载初始化 ⇒ 发起调用 ⇒ 收结果。
    ///
    /// 四步的顺序不是随手定的：
    /// 1. **先保证域在**：重拉过的域是一个全新进程，旧装载不在 —— 先发调用会拿到
    ///    一份「不认识的号」的错误，而那会把「重拉过」误报成「声明有问题」。
    /// 2. **重放只放装载初始化**（通知号 2000）：不恢复业务任务（W01 裁）。
    /// 3. 编解码走 [`crate::线协议`] —— 本件**不自带第二套协议**。
    /// 4. 收错：通道断开 / 超预算 / 协议码越界，一律报 `0034`（不是 panic）。
    ///
    /// 失败一律返回**错误码值**（不是字符串、不是异常）—— 调用方拿它去错误码表查三项业务判断。
    /// **送一调用**：保证域在 ⇒ （必要时）重放装载初始化 ⇒ 发起调用 ⇒ 收结果。
    ///
    /// 本方法是**直接持有本表**（不走 `Arc<Mutex<..>>`）的调用口（验证面用）。
    /// 经适配器走的调用路见 `适配器::调用跨进程`（那里先取引用、放掉表锁，再调
    /// [`送一登记调用`]）—— 两条路**同一份编排**，不各写一遍。
    pub fn 送一调用(
        &self,
        标识: &执行域标识,
        号值: u32,
        入参: &[数据槽],
    ) -> Result<数据槽, u32> {
        let Some(登记) = self.取登记(标识) else { return Err(本件错误码); };
        送一登记调用(&登记, &self.请求号源, 号值, 入参, None)
    }
}

/// 取下一个请求标识（单调）。
fn 取请求标识(号源: &AtomicU64) -> NonZeroU64 {
    let 号值 = 号源.fetch_add(1, Ordering::Relaxed);
    NonZeroU64::new(号值).unwrap_or(NonZeroU64::MIN)
}

/// **送一调用的编排**（句柄形态）：保证域在 ⇒ 重放装载 ⇒ 发 ⇒ 收 ⇒ 解码。
///
/// **不持任何表锁** —— 句柄自带该域的锁（冻结件 §五「长执行锁收窄到该域」）。
/// 一个慢域阻塞不了健康域：慢域在它本域那把锁里等，健康域拿本域句柄各走各的。
///
/// 四步的顺序不是随手定的：
/// 1. **先保证域在**：重拉过的域是一个全新进程，旧装载不在 —— 先发调用会拿到
///    一份「不认识的号」的错误，而那会把「重拉过」误报成「声明有问题」。
/// 2. **重放只放装载初始化**（通知号 2000）：不恢复业务任务（W01 裁）。
/// 3. 编解码走 [`crate::线协议`] —— 本件**不自带第二套协议**。
/// 4. **错误分级**（冻结件 §五）：本地参数 / 编码错报 `25`；活进程超时报 `0004`；
///    已确认退出报 `0034`；回帧不成形报 `27`。
fn 送一登记调用(
    登记: &Arc<域登记>,
    号源: &AtomicU64,
    号值: u32,
    入参: &[数据槽],
    收痕口: Option<&dyn Fn(&v1_trace::留痕)>,
) -> Result<数据槽, u32> {
    // **本地编码先做**：参数不合法 / 编不出来 / 载荷过大是本侧的错，与「进程崩了」是两件事
    // （冻结件 §五 第 1 条）⇒ 当场报 `25 输入形状不符`，**不报 `0034`**。
    // 这一步必须在拉起进程之前 —— 本侧参数就是错的，拉起对方纯属白花。
    let 待发载荷 = crate::线协议::编码调用请求(号值, 入参).map_err(|_| 本地参数错误码)?;
    let 总期限 = std::time::Instant::now() + std::time::Duration::from_millis(启动握手预算毫秒 + 调用预算毫秒);
    let 调用租约 = 登记.领用(总期限).map_err(按池错翻码)?;
    let _ = &调用租约;
    let 句柄 = 登记.取调用句柄(总期限).map_err(按池错翻码)?;
    let mut 预算 = crate::进程帧::调用帧预算::创建(总期限).map_err(|_| 本件错误码)?;
    let 事务守卫 = 句柄.锁事务(&预算).map_err(按池错翻码)?;
    let _ = &事务守卫;
    if let Err(错误值) = 登记.保证调用进程(&句柄) {
        return Err(按池错翻码(错误值));
    }
    if !句柄.已重放装载() {
        预算 = 分段预算(总期限, 启动握手预算毫秒)?;
        let 请求标识 = 取请求标识(号源);
        if let Err(错误值) = 句柄.重放装载初始化按预算(请求标识, &mut 预算) {
            return Err(按池错翻码(错误值));
        }
        // 回执必须当场收掉（见 `收装载回执` 的文件注释）—— 不收就串下一条调用。
        if let Err(错误值) = 句柄.收装载回执按预算(请求标识, &mut 预算) {
            return Err(按池错翻码(错误值));
        }
    }
    预算 = 分段预算(总期限, 调用预算毫秒)?;
    let 请求标识 = 取请求标识(号源);
    if let Err(错误值) = 句柄.发一调用帧按预算(请求标识, &待发载荷, &mut 预算) {
        return Err(按池错翻码(错误值));
    }
    // ★ **已发出调用**：从这里往下，失败**一律不宣称未执行、不自动重放**（冻结件 §五）。
    // 结果丢了就报结构化失败；要不要重试是调用方与部署策略的事，不是载体的事
    // （「调度判该不该报错，载体管进程活着没」）。
    let 回载 = match 句柄.收一调用回帧按预算(请求标识, &mut 预算, 收痕口) {
        Ok(载荷) => 载荷,
        Err(错误值) => return Err(按池错翻码(错误值)),
    };
    收束协议回槽(crate::线协议::解码调用结果(&回载))
}

fn 收束协议回槽(解码读数: Result<(i32, 数据槽), crate::线协议::线协议错误>) -> Result<数据槽, u32> {
    match 解码读数 {
        Ok((crate::协议结果::成功, 返回槽)) => Ok(返回槽),
        // 协议码 `参数不合法`：对方说「你这条调用形状不对」——**本地参数面**的事，
        // 不是进程崩溃（冻结件 §五 第 1 条）⇒ 报 `25`，不报 `0034`。
        Ok((_, mut 返回槽)) => {
            crate::值归还::归还槽值(&mut 返回槽);
            Err(本地参数错误码)
        },
        // 回帧能收到（进程活着、通道没断）但载荷不成形：**协议失败**，
        // 与「进程没了」分开 ⇒ 报 `27 输出形状不符`（对方交出的东西不合契约）。
        Err(_) => Err(回帧不合形错误码),
    }
}

