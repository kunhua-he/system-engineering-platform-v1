/// 一个执行域的工作进程：子进程 + 与它相连的通道 + 退避账。
///
/// **锁包（`pub(crate)`）**：跨域不共享，只有 [`域句柄`]（子件）与 [`进程池`] 读它。
/// 它从私有提到 crate 可见，是因为拆件后 [`域句柄`] 与之**不在同一个模块**了 ——
/// 子件亮着 `pub(crate)` 的字段与方法却持一个更私有类型时，编译器会报「类型比项更私有」。
pub(crate) struct 工作进程 {
    子进程: Child,
    流通道: UnixStream,
    进程组号: i32,
    /// 本实例的**代次**：每次（重）拉起取一个新值 ⇒ 旧句柄永不误命中新任务。
    ///
    /// **依赖（C6，不私造）**：当前**无消费者** —— 句柄（类型标签 6）/ 任务句柄（7）在
    /// `线协议` 被**整体拒过线**（[`crate::线协议::线协议错误::句柄不支持跨域`]），代次校验
    /// 没有跨域句柄可校，故安全成立。将来要放行跨域句柄，才由「域 + 代次」校把它接上；
    /// 在那之前不建第二套句柄表。
    实例代次: u64,
    /// 本实例**拉起时的部署指纹**（启动程序 + 启动参数）。**单次语义**的判据：
    /// 运行中且收到不同指纹的登记 ⇒ 结构化拒（见 [`部署指纹`] 与 `域句柄::保证在`）。
    部署指纹: u64,
    /// 本实例**拉起时的前提指纹**（白名单 + 秘密 + 授权）。与 `部署指纹` 并列的
    /// **单次语义**判据：运行中且收到不同前提 ⇒ 结构化拒（同域不混两套环境口径）。
    ///
    /// 为什么不并进 `部署指纹`：那个指纹已经在对外口上（`部署指纹` 是 `pub`），
    /// 并进去会连带它的全部调用点与既有读数；前提是新加的一层，单独一个标量即可。
    前提指纹: u64,
    运行中: bool,
    连续崩溃次数: u32,
    下次允许拉起: Instant,
    熔断截至: Option<Instant>,
    装载已重放: bool,
    回收已确认: bool,
    额度租约: Option<进程额度租约>,
}

