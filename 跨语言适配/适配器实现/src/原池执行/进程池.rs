/// 单次装载初始化重放的帧预算（毫秒）。**≤ 五秒硬顶**。
///
/// 预算覆盖的是「工作进程从 exec 到答第一帧」：解包 + `dlopen` 模块执行体，**以及**
/// 声明依赖的支持库（组合模块要两者都在同一个工作进程里装好）。实测冷缓存下
/// 只装模块一份时 200 ms 勉强够，加上一份 400 KB 支持库后握手必超时（真原码：
/// `模块执行域登记失败：预算耗尽`）⇒ 抬到 1500 ms，仍远低于五秒硬顶。
pub(crate) const 重放预算毫秒: u64 = 1500;

/// **装载初始化握手预算**（毫秒）：工作进程从 `exec` 到答第一帧（解包 + `dlopen` 模块执行体
