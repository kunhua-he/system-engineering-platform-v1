//! 进程池 —— 跨进程执行域的拉起 · 监督 · 崩溃重拉。
//!
//! 依据：`临时件/W01_裁决_架构升级.md` 六项未定项（进程池粒度 · 反复崩溃）·
//! `临时件/派活_W/W04a_进程池与线协议.md` · `临时件/落点/307收尾_接口冻结.md`（锁收窄）。
//!
//! # 一个执行域一个工作进程
//!
//! 执行域按 `适配器实例 × 扩展标识 × 制品版本` 划分（[`执行域标识`]）：不混装无关扩展，
//! 扩展未声明可并发时**不擅自并发**。**状态按实例持有**（[`进程池`] 的字段），
//! 不落任何进程级 `static` —— 同进程开两份池就是两个互不干扰的执行域表。
//!
//! # 锁收窄：一把表锁不阻塞全部域（冻结件 §五 末行）
//!
//! **每个域自持一把锁**（[`域格`] 里的 `Arc<Mutex<工作进程>>`），域表锁**只用于取域格**
//! （一次短锁）。长执行（收发）只持**该域**的锁（[`域句柄`]）⇒ 一个慢域阻塞不了健康域。
//! 早先整表一把 `Mutex`、收发持表锁 ⇒ 一个慢域把全部域拖住（本轮修的就是这一条）。
//!
//! # 反复崩溃：退避 · 重启预算 · 熔断
//!
//! 阈值属部署配置（[`进程池配置`]）。每查实一次崩溃，连续计数加一、退避按指数推进，
//! 越过重启预算即熔断一段时间；熔断期内不许再拉起。
//!
//! # 重放：只重放装载初始化
//!
//! 工作进程重拉后只重放**装载初始化**（通知号 2000，见 [`域句柄::重放装载初始化`]），
//! **不恢复业务任务**（业务是否重试由调用与能力保障决定，内核不替业务重试）。

