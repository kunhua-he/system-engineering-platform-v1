impl 进程池 {
    /// 建一个空池（一份部署配置）。
    pub fn 创建(配置: 进程池配置) -> Self {
        Self { 配置, 域表: Mutex::new(Vec::new()), 创建锁: Mutex::new(()), 活进程数: Arc::new(std::sync::atomic::AtomicU32::new(0)), 动态预算: Arc::new(Mutex::new(动态预算::动态预算状态::default())), 上次代次: Arc::new(Mutex::new(0)) }
    }

    /// 已建域数（验证面用）。
    pub fn 已建域数(&self) -> usize {
        取锁(&self.域表).len()
    }

    /// 域表满没满（架构收敛方案项 18.3-4：子进程数上限）。
    ///
    /// 每个执行域一个工作进程 ⇒ 域表条数就是**活着的子进程数**。
    /// 判定放在**拉起之前**（与 `子进程前提::校验派生` 同一条：拒的时候一个进程都不拉）。
    fn 域表已满(&self) -> bool {
        self.活进程数.load(std::sync::atomic::Ordering::Acquire) >= self.当前进程预算().0
    }

    pub fn 活进程数(&self) -> usize {
        self.活进程数.load(std::sync::atomic::Ordering::Acquire) as usize
    }

    /// 这个域建过没有。
    pub fn 含域(&self, 标识: &执行域标识) -> bool {
        self.取域句柄(标识).is_some()
    }

    /// **取域句柄**（**短锁**：只在这一刻持表锁，交出句柄后立刻放）。
    ///
    /// 这是「域表锁只用于取引用」的唯一取口；拿到句柄后的长执行不再碰表锁。
    pub fn 取域句柄(&self, 标识: &执行域标识) -> Option<域句柄> {
        取锁(&self.域表)
            .iter()
            .find(|格子| &格子.标识 == 标识)
            .map(|格子| 域句柄 {
                配置: self.配置,
                活进程数: Arc::clone(&self.活进程数),
            动态预算: Arc::clone(&self.动态预算),
                工作: Arc::clone(&格子.工作),
                代次源: Arc::clone(&self.上次代次),
                事务锁: Arc::clone(&格子.事务锁),
            })
    }

    /// 取一个**跨重启不复用**的实例代次（以墙钟纳秒为源，且强制比上次大）。
    ///
    /// 停机恢复后重建的池从新的墙钟起点再取 ⇒ 旧代次永不与新一代次相等
    /// （旧句柄永不误命中新任务；W01「重放及引用归属」）。
    fn 取单调代次(&self) -> u64 {
        let 墙钟 = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|时长| 时长.as_nanos() as u64)
            .unwrap_or(0);
        let mut 上次 = 取锁(&self.上次代次);
        let 代次 = 墙钟.max(上次.saturating_add(1));
        *上次 = 代次;
        代次
    }

    /// 造一格（新拉起的进程）。
    fn 造格(
        标识: 执行域标识,
        子进程: Child,
        通信通道: UnixStream,
        实例代次: u64,
        指纹: u64,
        前提指纹: u64,
        额度租约: 进程额度租约,
    ) -> Result<域格, 进程池错误> {
        let 进程组号 = i32::try_from(子进程.id()).map_err(|_| 进程池错误::拉起失败)?;
        Ok(域格 {
            标识,
            事务锁: Arc::new(Mutex::new(())),
            工作: Arc::new(Mutex::new(工作进程 {
                子进程,
                流通道: 通信通道,
                进程组号,
                实例代次,
                部署指纹: 指纹,
                前提指纹,
                运行中: true,
                连续崩溃次数: 0,
                下次允许拉起: Instant::now(),
                熔断截至: None,
                装载已重放: false,
                回收已确认: false,
                额度租约: Some(额度租约),
            })),
        })
    }

    /// 崩溃重拉：查实崩溃后，按退避 / 重启预算 / 熔断决定能否再拉一个。
    pub fn 崩溃重拉(
        &self,
        标识: &执行域标识,
        启动程序: &str,
        启动参数: &[String],
    ) -> Result<监督判读, 进程池错误> {
        let 句柄 = self.取域句柄(标识).ok_or(进程池错误::域不存在)?;
        let mut 工作 = 句柄.互斥锁();
        查实崩溃(句柄.配置, &mut 工作);
        let 现在时刻 = Instant::now();
        if 工作.运行中 {
            return Ok(判读格子(&工作, 现在时刻));
        }
        if 工作.熔断截至.is_some_and(|熔断截至| 现在时刻 < 熔断截至) {
            return Err(进程池错误::熔断中);
        }
        if 现在时刻 < 工作.下次允许拉起 {
            return Err(进程池错误::拉起失败);
        }
        if !工作.回收已确认 {
            let _ = 击杀并确认退出(&mut 工作, 默认确认预算毫秒);
            if !工作.回收已确认 { return Err(进程池错误::拉起失败); }
        }
        let 额度租约 = 申请进程额度(&self.活进程数, &self.动态预算, self.配置.子进程数上限)?;
        let (子进程, 流通道) = 生成进程(启动程序, 启动参数)?;
        // 崩溃后重拉：此刻**不在运行**，按传入参数重拉并刷新指纹（「运行中且指纹不同才拒」）。
        // 前提指纹同样刷新：本路走默认前提（`生成进程` 用的就是它），故取默认前提的指纹 ——
        // 与 `生成进程` 的入参是同一份，不给本路另算一套口径。
        装新进程(
            &mut 工作,
            子进程,
            流通道,
            句柄.取单调代次(),
            部署指纹(启动程序, 启动参数),
            (子进程前提::默认前提().前提指纹(), 额度租约),
        )?;
        let mut 判读 = 判读格子(&工作, Instant::now());
        判读.已重拉 = true;
        Ok(判读)
    }
}

