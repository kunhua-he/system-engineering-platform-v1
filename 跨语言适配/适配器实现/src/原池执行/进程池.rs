/// 池操作的结构化失败。**不 panic**（跨边界不许抛异常）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 进程池错误 {
    域不存在,
    熔断中,
    拉起失败,
    /// 通道断开（EOF 或传输错）：**崩溃的现场证据**。
    ///
    /// 与 `拉起失败` 分开：拉起失败是「没拉起来」（进程可能好着，是部署参数不对），
    /// 通道断开是「拉起来过、现在没了」—— 只有后者才构成崩溃计数。
    通道断开,
    /// 预算耗尽：进程**还活着**，但没在预算内答。
    ///
    /// 与 `通道断开` 严格分开（这是 `0034` 与 `0004` 两码的分界线）：
    /// 一个是「进程没了」，一个是「进程活着但没答」—— 前者要查它为什么崩，后者重试或加预算。
    预算耗尽,
    /// **装载初始化握手超预算**：进程已拉起、仍在装载（`exec` + `dlopen` 模块执行体与依赖
    /// 支持库），但没在**启动握手预算**内答第一帧。
    ///
    /// 与 [`进程池错误::预算耗尽`] 分开：那个是「已就绪域的一条调用没在调用预算内答」，
    /// 这个是「进程启动阶段超时」——节点、预算、处置都不同。带读数是为了不再让上游
    /// 只能写一句「预算耗尽」：节点（装载初始化握手）· 预算 · 实际三样都得能点名。
    启动握手超预算 { 预算毫秒: u64, 已用毫秒: u64 },
    /// 待发载荷超过单帧上限：**本侧载荷形状**问题（与帧层同一个数，见
    /// [`crate::进程帧::单帧载荷上限`]），不当通道错报 —— 不混进 `0004 超时` / `0034 崩溃`。
    载荷过大,
    /// 同域**运行中**却给了不同部署参数（启动程序 / 启动参数变了）⇒ 结构化拒。
    ///
    /// **单次语义**（本域裁的口径）：一个域的部署在**首次拉起**时定下；运行中的域不许
    /// 静默换部署表（否则旧 worker 继续服务、下次重拉才用新参 = 同域两套部署口径）。
    部署参数不符,
    /// **子进程数已满**：池里活着的域（= 工作进程）已达 [`进程池配置::子进程数上限`] ⇒
    /// 结构化拒，**且一个新进程都不拉**（判定在 `spawn` 之前，与「未授权派生」同一条）。
    ///
    /// 与 `拉起失败` 分开：拉起失败是「想拉但没拉起来」（部署参数或环境有问题），
    /// 本变体是「**没想拉** —— 预算已满」。两者处置不同：前者查部署，后者清池或改预算。
    子进程数已满,
    /// 未授权**派生进程**：前提里没放行 [`危险动作::派生进程`] ⇒ 结构化拒，
    /// **且一个子进程都不拉**（判定在 `spawn` 之前，见 [`子进程前提::校验派生`]）。
    ///
    /// 为什么单独一个变体而不是拿 `拉起失败` 顶：两者对调用方的意义完全不同 ——
    /// `拉起失败` 是「想拉但没拉起来」（部署参数或环境有问题），本变体是
    /// 「**压根没打算让你拉**」（授权面的事）。报成同一个码，调用方就会去查二进制路径。
    未授权派生进程,
    /// 未授权**继承全环境**：白名单里写了 [`全放行名`] 却没放行 [`危险动作::继承全环境`]。
    ///
    /// **不静默收窄成「只传白名单里的」**：那会让调用方以为全环境已生效。
    未授权继承全环境,
    /// 未授权**投放秘密**：带了 [`子进程前提::秘密`] 却没放行 [`危险动作::投放秘密`]。
    ///
    /// 同样**不静默丢弃秘密**：静默丢弃 = 子进程起来却拿不到该拿的凭据，
    /// 而调用方看到的是一句「拉起来了」。
    未授权投放秘密,
}

