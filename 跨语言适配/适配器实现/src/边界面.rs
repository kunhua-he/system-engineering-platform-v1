//! 对外边界 —— 全平台唯一的 **C ABI 边界**（`边界协议.md` §三）。
//!
//! 恰好一组三个符号，签名逐字照 `边界协议.md` §三（冻结项，不许改）：
//!
//! ```c
//! const char* 平台_取接口描述(uint32_t* 长度);      // UTF-8 JSON；长度由出参带回
//! int32_t     平台_调用(uint32_t 号, uint32_t 参数个数, const 数据槽* 参数表, 数据槽* 返回槽);
//! void        平台_释放值(数据槽* 值);
//! ```
//!
//! 符号名是 ASCII（`#[unsafe(export_name = "…")]`），Rust 函数名是中文 —— 这是
//! `代码形态分工.md` 例外表里那条「导出的 ABI 符号用 ASCII」（别的语言要按名字绑）。
//!
//! # 三个方向不许混（`边界协议.md` §一）
//!
//! 本文件是**宿主 → 外面**（向外）那一个方向；`装载入口` 的 `GetPlatformInfo` 是
//! **扩展 → 宿主**（向内）的**接缝**，每个扩展各一个。两者形状完全不同，
//! 本边界**不含也不导出** `GetPlatformInfo`。
//!
//! # 边界无状态（判据 4）
//!
//! 本文件生产代码里**没有一个模块级 `static`**（一键验证 ⑫ 会数），也没有加锁：
//! 三个导出函数每次调用**当场**从平台自己的声明根建一个 [`对外边界`]，用完即弃。
//! 所以：
//!
//! - **可重入**：并发调用互不共享任何东西（各建各的注册表与账本）。
//! - **多实例**：`对外边界::新建(声明根)` 一个实例一套东西，两个实例互不可见。
//!
//! 代价如实登记（**缺口 2**）：无状态 ⇒ 配额账本与执行耗时读数**不跨调用累积**，
//! 每次 `平台_调用` 都是一本新账。要跨调用记账就得让边界持有状态（句柄或全局），
//! 两条都与「边界无状态」冲突 ⇒ 留待契约侧裁（见文件末「缺口」）。
//!
//! # 所有权：`平台_取接口描述` 的缓冲区**静态终生有效**（写死一种，说明理由）
//!
//! **选定：本边界交出的每一块内存都是「静态终生有效」——谁都不释放，`平台_释放值` 也不释放。**
//!
//! 理由（三条，缺一条这个选择就不成立）：
//!
//! 1. **无状态 ⇒ 没有可查账的分配器实例。** 平台唯一的跨边界分配器是
//!    `运行内核/内存分配器`（`v1-alloc`），但它按**实例**持有账本（地址 → 长度），
//!    `释放` 先查账、账上没有的地址一律拒绝。边界不持有任何实例 ⇒ 后续那次
//!    `平台_释放值` 找不到当初分配的那本账 ⇒ **它放不了任何东西**。
//! 2. **让边界能释放只有两条路，两条都越权**：① 给 `平台_释放值` 加一个句柄参数
//!    —— 那是改**冻结签名**（`边界协议.md` §三）；② 让边界持一个模块级全局分配器
//!    —— 那是违反**边界无状态**（判据 4，一键验证 ⑫ 会当场报红）。
//! 3. **与接缝同一条口径。** `边界协议.md` §二 对 `GetPlatformInfo` 的返回已定死
//!    「静态常量指针，终生有效；调用方不得释放、不得修改」。本边界对它交出的
//!    接口描述采用**同一条口径**，于是「跨边界只有一条所有权规则」这句话在两边都成立。
//!
//! 于是 `平台_释放值` 的行为与之一致：**它不调用任何释放器**，只把槽清空
//! （[`对外边界::释放值`]）。第二次再还同一个槽是**幂等**的——槽已经是空槽，
//! 再清一次还是空槽，不会二次释放任何一块（因为一块也没释放过）。
//! 这是「要么幂等、要么结构化报错」二选一里的**幂等**那一支：`void` 返回没有报错通道，
//! 所以只能幂等。
//!
//! 代价如实登记（**缺口 1**）：接口描述每次调用泄漏一份缓冲（调用方应只调一次并缓存，
//! 这也是 `接口面形状.md` §一「agent 的第一次调用是 `GET /接口`」的用法）；
//! 扩展经 `平台_调用` 交出的**带所有权**的槽（`槽标志::所有权交出`）本边界同样放不了
//! —— 它的释放口在提供者/卸载那条路上，不在这个无状态边界里。
//!
//! ## 缺口 1 的收口分析（台账 #17：能不能「缓存一次」而不改冻结签名）
//!
//! **结论：不改冻结签名就没有可用的缓存路径。** 逐条排除：
//!
//! - 缓冲要活到下一次调用，就必须有地方**持有**它。本函数**没有句柄参数**（签名冻结）
//!   ⇒ 唯一能持有的地方是**模块级状态**（`static` / `thread_local`）。
//! - 而「边界无状态」是判据 4，一键验证 ⑫-4 会数模块级 `static` ⇒ 加缓存就是**当场报红**，
//!   与「让边界持全局分配器来释放」是同一类越权（文件头「所有权」第 2 条已列）。
//! - 逐次缓存（第二次调用复用第一次的缓冲）也解决不了：返回值必须**终生有效**，
//!   复用一份可变缓冲就得在写新内容时让旧指针失效 —— 那会把「静态终生有效」改成
//!   「下一次调用前有效」，是**改冻结件的承诺**，比泄漏更坏。
//!
//! ⇒ 泄漏的**正解在调用方**：调一次、把指针与长度缓存起来（文件头「所有权」第 3 条
//! 已按 `GetPlatformInfo` 的同一条口径写明「调用方不得释放、不得修改」）。本边界
//! **不硬改**：不缓存、不加句柄、不放开无状态。读数：每次调用泄漏 `json.len()` 字节
//! （本边界不测这个数——它是调用次数的函数，不是常量；调用一次就恒定一份）。
//!
//! # 缺口（如实登记，不假装覆盖了）
//!
//! 1. **本边界放不了动态内存**（见上）。要它真能放，需要契约侧改冻结签名或放开无状态。
//! 2. **无状态 ⇒ 记账不跨调用**（见上）。
//! 3. **协议层结果码的数值已冻在契约侧**（台账 #16 已收口）：`边界协议.md` §三·一
//!    给了 `成功 = 0` · `参数不合法 = -1`，**契约侧是唯一定义处**；[`协议结果`] 是运行期
//!    引用，值必须与契约逐字一致。改数走冻结登记旁路，再同步这里，不许只改一处。
//! 4. **导出符号绑定的是平台自己的声明根**（[`v1_loader::底座声明`]）：三个符号
//!    **没有句柄参数**（签名冻结），所以只能绑平台自己那份声明。扩展的能力要经
//!    [`对外边界::新建`]（Rust 级、收声明根）暴露 —— C ABI 这一面**看不到扩展**。
//!    要把扩展也带出去，得给符号加句柄或让边界持有装配好的声明根，两条都触上面第 2 条。

use crate::接口描述;
use crate::{能力摘要, 适配器, 平台信息, 装载失败, 数据槽, 转发结果};
use core::ffi::c_char;
use v1_contract::声明数据;
use v1_dispatch::调度错误;

/// 协议层结果码 —— `int32_t` **只**表达这两件事（`边界协议.md` §三）。
///
/// **契约侧是唯一定义处**：`跨语言适配/边界协议/边界协议.md` §三·一 已把这两个数
/// 冻上（台账 #16），本模块是**运行期引用**，值必须与契约逐字一致。改数 = 改契约
/// （走冻结登记的旁路），再同步这里；**不许**只改一处。
///
/// 业务失败**不许**用它们表达 —— 业务失败一律走返回槽里的结构化错误码。
pub mod 协议结果 {
    /// 调用在**协议层**成立（返回槽里可能是值，也可能是结构化错误码 —— 那要读返回槽）。
    pub const 成功: i32 = 0;
    /// 参数不合法：返回槽为空 / `参数个数 > 0` 却给了空参数表 / 参数个数与声明不符。
    pub const 参数不合法: i32 = -1;
}

/// 一个边界实例：**一个声明根一套东西**，没有任何进程级 `static`。
///
/// `契约来源` = 声明根的第一份（装配约定「底座排在最前」）：接口描述要的
/// `契约版本` 与 `声明格式号` 从它上面**现读**，边界不自己去取声明
/// （谁把声明递进来是装配那条腿的事）。
pub struct 对外边界 {
    适配器: 适配器,
    契约来源: &'static 平台信息,
}

impl 对外边界 {
    /// 从声明根建一个边界实例（空的声明根即拒 —— 没有注册表就没有可寻址的表）。
    pub fn 新建(声明根: &[&'static 平台信息]) -> Result<Self, 装载失败> {
        let 契约来源 = *声明根.first().ok_or(装载失败::空声明根)?;
        Ok(Self {
            适配器: 适配器::装载声明根(声明根)?,
            契约来源,
        })
    }

    /// 读：有哪些能力、某条能力怎么调 —— UTF-8 JSON（**不含**结尾换行）。
    ///
    /// 返回的 `String` 由调用方持有；导出符号 [`平台_取接口描述`] 把它泄漏成
    /// **静态终生有效**的缓冲再交出去（见文件头「所有权」）。
    pub fn 取接口描述(&self) -> String {
        接口描述::写描述(&self.适配器, self.契约来源)
    }

    /// 读侧能力清单（与 [`适配器::能力清单`] 同一条路，供验证面比对接口描述）。
    pub fn 能力清单(&self) -> Vec<能力摘要> {
        self.适配器.能力清单()
    }

    /// 调：按号 + 按契约行序填值。**协议层结果**由返回值给，**业务失败**在返回槽里。
    ///
    /// - 成功（返回 [`协议结果::成功`]）⇒ 返回槽里是**值**。
    /// - 参数个数不符（返回 [`协议结果::参数不合法`]）⇒ 返回槽置空。参数个数不符是
    ///   **调用形状**不对，属协议层，故不塞进返回槽（这一支由调度层的判据给出，边界不重判）。
    /// - 其余业务失败（未命中 · 已废止 · 超时 · 配额用尽）⇒ 返回 [`协议结果::成功`]，
    ///   **失败在返回槽里**：`类型标签 = 类型标签_4294967295`（错误），`值 = 4 位码`
    ///   （`段位 × 1000 + 序号`）。三项业务判断（可重试 / 可自愈 / 需人工）由
    ///   `平台_取接口描述` 的 `可抛错误码` 表随包给出。
    pub fn 调用(&self, 号: u32, 参数: &[数据槽], 返回槽: &mut 数据槽) -> i32 {
        match self.适配器.调用能力(号, 参数, 返回槽) {
            转发结果::成功(_) => 协议结果::成功,
            转发结果::失败(调度错误::参数个数不符 { .. }) => {
                *返回槽 = 数据槽::空槽();
                协议结果::参数不合法
            }
            转发结果::失败(错) => {
                *返回槽 = 错误槽(业务错误码(错));
                协议结果::成功
            }
        }
    }

    /// 还：把调用方拿到的值的所有权交回。**幂等**（见文件头「所有权」）。
    ///
    /// 本边界交出的东西都是静态终生有效的 ⇒ 本函数**不调用任何释放器**，
    /// 只把槽清空。空指针与「已经是空槽」都当无事发生（重复归还不崩、不会二次释放）。
    ///
    /// 实现只有一份：[`crate::值归还::归还槽值`] —— Rust 面的 [`crate::适配器::释放值`]
    /// 走的是同一个函数，两条口同语义（台账 #98）。
    pub fn 释放值(槽: &mut 数据槽) {
        crate::值归还::归还槽值(槽);
    }
}

/// 业务失败的返回槽：`类型标签 = 错误`，`值 = 4 位码`（`段位 × 1000 + 序号`）。
///
/// 4 位码是**声明侧登记过**的（`契约声明/错误码表/`）：调用方拿 `码` 去
/// `平台_取接口描述` 的 `可抛错误码` 表里查那三项业务判断。
fn 错误槽(码: u32) -> 数据槽 {
    数据槽::内联(声明数据::类型标签_4294967295.into(), 码 as u64, 0)
}

/// `调度错误` → 4 位码。**码值只有一个来源**：生成物 `v1_contract::声明数据`
/// （源 = `契约声明/错误码表/*.json`），这里只做「段位 → 码」的对位，不另写数。
///
/// `pub(crate)`：调用留痕（`留痕口.rs`）要用同一个对位，不许在别处再写一张。
pub(crate) fn 业务错误码(错: 调度错误) -> u32 {
    match 错 {
        调度错误::提供者未载入 { .. } => 声明数据::错误码_1,
        调度错误::命令已废止 { .. } => 声明数据::错误码_2,
        调度错误::参数个数不符 { .. } => 声明数据::错误码_3,
        调度错误::超时 { .. } => 声明数据::错误码_4,
        调度错误::配额用尽 => 声明数据::错误码_5,
    }
}

/// 导出符号绑定的边界实例：平台自己的声明根（见文件头缺口 4）。
///
/// **载不进来就报「提供者未载入」**：没有可寻址的表 ⇒ 每个号都未命中，
/// 与调度层对未命中号的口径一致。这不是正常路径（平台自己的声明必然载得进来，
/// `适配器测试.rs` 已钉住），故不 panic（跨边界 panic 是明令禁止的）。
fn 默认边界() -> Option<对外边界> {
    对外边界::新建(&[v1_loader::底座声明()]).ok()
}

/// 读接口描述：UTF-8 JSON，长度由出参带回。
///
/// # 所有权（**写死一种**，理由见文件头）
///
/// 返回的缓冲**静态终生有效**：调用方**不得释放、不得修改**，`平台_释放值` 也不释放它。
/// 每次调用泄漏一份（调用方应只调一次并缓存）。
///
/// # Safety
///
/// `长度` 要么为空指针，要么指向**一个可写的 `u32`**。
/// 长度为 null ⇒ 无法报告长度 ⇒ 返回空指针（不交出一个不可读的缓冲），**不崩**。
#[unsafe(export_name = "平台_取接口描述")]
pub unsafe extern "C" fn 平台_取接口描述(长度: *mut u32) -> *const c_char {
    if 长度.is_null() {
        return core::ptr::null();
    }
    let json = match 默认边界() {
        Some(边界) => 边界.取接口描述(),
        // 平台自己的声明载不进来 ⇒ 没有可描述的接口：给一个**合法**的空对象，
        // 而不是半个形状（少一个字段的 JSON 比空对象更难判）。
        None => String::from("{}"),
    };
    let 字节 = json.into_bytes();
    if 字节.len() > u32::MAX as usize {
        return core::ptr::null();
    }
    let 长 = 字节.len() as u32;
    let 泄漏: &'static mut [u8] = Box::leak(字节.into_boxed_slice());
    // SAFETY: 长度 非空（上面已挡）；调用方按本函数的 Safety 契约保证它可写。
    unsafe { *长度 = 长 };
    泄漏.as_ptr() as *const c_char
}

/// 调用：按号 + 按契约行序填值。
///
/// 返回值只表达**协议层**结果（[`协议结果`]）；业务失败在返回槽里（见 [`对外边界::调用`]）。
///
/// # Safety
///
/// - `返回槽` 要么为空指针（此时返回 [`协议结果::参数不合法`]，不写任何内存），
///   要么指向**一个可写的 [`数据槽`]**。
/// - `参数表` 要么为空指针（此时 `参数个数` 必须为 0），要么指向**至少 `参数个数` 个可读的 [`数据槽`]**。
#[unsafe(export_name = "平台_调用")]
pub unsafe extern "C" fn 平台_调用(
    号: u32,
    参数个数: u32,
    参数表: *const 数据槽,
    返回槽: *mut 数据槽,
) -> i32 {
    if 返回槽.is_null() {
        return 协议结果::参数不合法;
    }
    // SAFETY: 返回槽 非空；调用方按本函数的 Safety 契约保证它可写。
    let 槽 = unsafe { &mut *返回槽 };
    if 参数个数 > 0 && 参数表.is_null() {
        *槽 = 数据槽::空槽();
        return 协议结果::参数不合法;
    }
    let 参数: &[数据槽] = if 参数个数 == 0 {
        &[]
    } else {
        // SAFETY: 参数表 非空；调用方按本函数的 Safety 契约保证它有 参数个数 个可读槽。
        unsafe { core::slice::from_raw_parts(参数表, 参数个数 as usize) }
    };
    let Some(边界) = 默认边界() else {
        *槽 = 错误槽(声明数据::错误码_1);
        return 协议结果::成功;
    };
    边界.调用(号, 参数, 槽)
}

/// 还值：把调用方拿到的值的所有权交回。**幂等**（见文件头「所有权」）。
///
/// # Safety
///
/// `值` 要么为空指针（此时什么都不做），要么指向**一个可写的 [`数据槽`]**。
#[unsafe(export_name = "平台_释放值")]
pub unsafe extern "C" fn 平台_释放值(值: *mut 数据槽) {
    if 值.is_null() {
        return;
    }
    // SAFETY: 值 非空；调用方按本函数的 Safety 契约保证它可写。
    对外边界::释放值(unsafe { &mut *值 });
}
