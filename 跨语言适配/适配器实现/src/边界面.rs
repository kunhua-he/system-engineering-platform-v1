//! 对外边界 —— 全平台唯一的 **C ABI 边界**（`边界协议.md` §三）。
//!
//! 恰好一组**四个**符号，签名逐字照 `边界协议.md` §三（冻结项，不许改）：
//!
//! ```c
//! const char* 平台_取接口描述(uint32_t* 长度);      // UTF-8 JSON；长度由出参带回
//! int32_t     平台_调用(uint32_t 号, uint32_t 参数个数, const 数据槽* 参数表, 数据槽* 返回槽);
//! void        平台_释放值(数据槽* 值);
//! void        平台_释放接口描述(const char* 缓冲, uint32_t 长度);  // 还 平台_取接口描述 的缓冲
//! ```
//!
//! 符号名是 ASCII（`#[unsafe(export_name = "…")]`），Rust 函数名是中文 —— 这是
//! `代码形态分工.md` 例外表里那条「导出的 ABI 符号用 ASCII」（别的语言要按名字绑）。
//!
//! # 接缝与边界的冻结声明（判据 ㉙ 的落点）
//!
//! 形状**冻结**，演进只走 `契约声明/冻结登记.json` 的旁路登记：
//!
//! - **接缝符号名**（扩展 → 宿主）：`GetPlatformInfo`，每个扩展恰好 1 个。
//! - **参照实现的对应符号**：`GetNewInf` —— **明示不复刻**（我方结构偏离参照实现，
//!   裁决见 `条款` 表 · `项目文档/决策记录/2026-09-27_接缝结构不复刻.md`）。
//! - **对外边界符号名**：本文件那四个，冻结。
//!
//! # 三个方向不许混（`边界协议.md` §一）
//!
//! 本文件是**宿主 → 外面**（向外）那一个方向；`装载入口` 的 `GetPlatformInfo` 是
//! **扩展 → 宿主**（向内）的**接缝**，每个扩展各一个。两者形状完全不同，
//! 本边界**不含也不导出** `GetPlatformInfo`。
//!
//! # 边界无状态（判据 4）
//!
//! 本文件生产代码里**没有一个模块级 `static`**（一键验证 ⑫ 会数），也没有加锁：
//! 三个导出函数每次调用**当场**从平台自身的声明根建一个 [`对外边界`]，用完即弃。
//! 所以：
//!
//! - **可重入**：并发调用互不共享任何东西（各建各的注册表与账本）。
//! - **多实例**：`对外边界::新建(声明根)` 一个实例一套东西，两个实例互不可见。
//!
//! 代价如实登记（**缺口 2**）：无状态 ⇒ 配额账本与执行耗时读数**不跨调用累积**，
//! 每次 `平台_调用` 都是一本新账。要跨调用记账就得让边界持有状态（句柄或全局），
//! 两条都与「边界无状态」冲突。
//!
//! # 记账不跨调用：**有意为之**（2026-09-27 已裁）
//!
//! 上面那条代价**不是缺陷，是裁决**：每次 `平台_调用` 当场建新适配器、新账 ⇒ 配额账本与
//! 耗时读数不跨调用累积 —— 调用之间**无共享状态**，正是「**不产生第二条腿**」在运行期的样子
//! （老仓 1.2 / 1.3：同一件事存在两套以上实现即缺陷；状态显式持有为句柄，不落隐式全局）。
//! 要让读数跨调用累积，就必须在边界里存一份状态（`static` / 全局 / 句柄）—— 那正是第二条状态腿。
//! **跨调用记账并非做不到，只是不在这层做**：`调用留痕`（逐条记耗时）与两个账本
//! （适配器/关口各持一本）已经按实例记下了。故**接受现状，不改任何逻辑**；
//! 裁决见 `项目文档/决策记录/2026-09-27_无状态边界与配额读数裁决.md`。
//!
//! **能跑的读数**（同一入参两次调用读数一致）：`cargo test -p v1-adapter 无状态_连发两次调用互不影响`
//! —— 该测试断言 `(首个, 首槽) == (次个, 次槽)`（同一入参两次调用**逐位相同**），中间还插一次失败调用
//! 证明不串味；并给**反向样本**：持有状态的适配器打满配额后第 N+1 次会变（「两次一致」对状态敏感）。
//! 同族的实例读数见 [`crate::边界面`] 文件末缺口 4 的「两个实例」那一条。
//!
//! # 所有权：`平台_取接口描述` 交出的缓冲**归调用方**（用完必须还）
//!
//! **选定：`平台_取接口描述` 交出的缓冲归调用方所有；调用方用完调
//! [`平台_释放接口描述`] 还。** 这是「谁分配谁释放」（`边界协议.md` §三 所有权那一行）
//! 在本边界的落地。
//!
//! 为什么不「静态终生有效」：那要每次调用 `Box::leak` 一份 ⇒ **调用 N 次就泄漏 N 份**。
//! 而「缓存一份、复用」要**模块级状态**（`static` / `thread_local`）—— 那是违反
//! **边界无状态**（判据 4，一键验证 ⑫-4 会当场报红）。
//!
//! 为什么是**新增一个符号**、不给 `平台_释放值` 加句柄：`边界协议.md` §三 开头定死
//! 「只许新增旁路字段与新增符号，不许改旧符号语义」。加句柄是改旧符号；新增
//! `平台_释放接口描述` 是**加一个符号**，读符号的名字与参数形状一字不动。
//! 只动了 §三「所有权」那一行的语义（由「静态终生有效」改成「调用方持有、用完还」），
//! 已在 `契约声明/冻结登记.json` 登记旁路。
//!
//! `平台_释放值` 的语义**不变**：它管的是**数据槽**（`平台_调用` 交出的值），
//! 与接口描述的缓冲是两件事、两个符号。它仍只把槽清空、仍幂等。
//!
//! 代价如实登记：接口描述的缓冲不再泄漏（调用方按协议还即可）；扩展经 `平台_调用`
//! 交出的**带所有权**的槽（`槽标志::所有权交出`）本边界仍放不了 —— 它的释放口在
//! 提供者/卸载那条路上，不在这个无状态边界里（**缺口 1**）。
//!
//! # 缺口（如实登记，不假装覆盖了）
//!
//! 1. **`平台_调用` 交出的带所有权的槽，本边界放不了**（见上）。要它真能放，需要契约侧
//!    改冻结签名或放开无状态。
//! 2. **无状态 ⇒ 记账不跨调用** —— **已裁（2026-09-27）：有意为之，接受现状**，见文件头
//!    「记账不跨调用」那一节；它不是缺陷，要跨调用累积就得在边界存第二条状态腿。
//!    裁决的完整理由与被否决的四个选项见 `项目文档/决策记录/2026-09-27_无状态边界与配额读数裁决.md`。
//! 3. **协议层结果码的数值已冻在契约侧**：`边界协议.md` §三·一
//!    给了 `成功 = 0` · `参数不合法 = -1`，**契约侧是唯一定义处**；[`协议结果`] 是运行期
//!    引用，值必须与契约逐字一致。改数走冻结登记旁路，再同步这里，不许只改一处。
//! 4. **导出符号绑定的是平台自身的声明根**（[`v1_loader::底座声明`]）：四个符号
//!    **没有句柄参数**（签名冻结），所以只能绑平台自身那份声明。扩展的能力要经
//!    [`对外边界::新建`]（Rust 级、收声明根）暴露。
//!
//!    **已裁（2026-09-27）：句柄走参数表里的一个槽，调用形状三参数逐字不动。**
//!    不给符号加第四个参数（那要新开一种冻结演进，是宪法级动作）；改为**需要区分实例的
//!    能力，在它自身的参数表里收一个「句柄」槽** —— 宪法 3「类型标签在槽内」，句柄本来就是
//!    一种槽标签。`输入类型` 改表之后这件事**天然成立**：多一个入参槽即可，形状一个字不动。
//!    裁决见 `项目文档/决策记录/2026-09-27_待裁九项按老仓设计哲学裁决.md` 裁决 2。
//!
//!    **能跑的读数**（「两个实例」）：
//!    - `cargo test -p v1-adapter 无状态_两个实例两份声明根互不干扰` —— 用两份声明根各建
//!      一个 [`对外边界`]（首个只装底座 · 次个多装一份扩展），断言能力清单 `1 vs 2`、描述不同，
//!      并给反向样本（**同一份**声明根的两个实例必须逐字节相同，差异才归因于声明根）。
//!    - `cargo test -p v1-adapter 句柄槽_同一调用形状按句柄值区分两个实例` —— 同一份声明、
//!      同一个号、同一条调用形状，按**参数表里的句柄槽**的值区分两个实例（这条是 #18 的主体）。
//!    - `cargo test -p v1-adapter 句柄槽_平台_调用接受带句柄标签的入参槽`（C ABI 面的读数）。
//!    **C ABI 这一面不需要多一个参数**：四个导出符号是**全平台一组**、绑平台自身的声明根（上面第 2 条
//!    边界无状态），多实例差异经**参数表里的句柄槽**表达，不经符号参数表达。

use crate::接口描述;
use crate::{能力摘要, 适配器, 平台信息, 装载失败, 数据槽, 转发结果};
use core::ffi::c_char;
use v1_contract::声明数据;
use v1_dispatch::调度错误;

/// 协议层结果码 —— `int32_t` **只**表达这两件事（`边界协议.md` §三）。
///
/// **契约侧是唯一定义处**：`跨语言适配/边界协议/边界协议.md` §三·一 已把这两个数
/// 冻上，本模块是**运行期引用**，值必须与契约逐字一致。改数 = 改契约
/// （走冻结登记的旁路），再同步这里；**不许**只改一处。
///
/// 业务失败**不许**用它们表达 —— 业务失败一律走返回槽里的结构化错误码。
pub mod 协议结果 {
    /// 调用在**协议层**成立（返回槽里可能是值，也可能是结构化错误码 —— 那要读返回槽）。
    pub const 成功: i32 = 0;
    /// 参数不合法：返回槽为空 / `参数个数 > 0` 却给了空参数表 / 参数个数与声明不符。
    pub const 参数不合法: i32 = -1;
}

/// 一个边界实例：**一个声明根一套东西**，没有任何进程级 `static`。
///
/// `契约来源` = 声明根的第一份（装配约定「底座排在最前」）：接口描述要的
/// `契约版本` 与 `声明格式号` 从它上面**现读**，边界不自行去取声明
/// （谁把声明递进来是装配那条腿的事）。
pub struct 对外边界 {
    适配器: 适配器,
    契约来源: &'static 平台信息,
}

impl 对外边界 {
    /// 从声明根建一个边界实例（空的声明根即拒 —— 没有注册表就没有可寻址的表）。
    pub fn 新建(声明根: &[&'static 平台信息]) -> Result<Self, 装载失败> {
        let 契约来源 = *声明根.first().ok_or(装载失败::空声明根)?;
        Ok(Self {
            适配器: 适配器::装载声明根(声明根)?,
            契约来源,
        })
    }

    /// 读：有哪些能力、某条能力怎么调 —— UTF-8 JSON（**不含**结尾换行）。
    ///
    /// 返回的 `String` 由调用方持有；导出符号 [`平台_取接口描述`] 把它交给调用方
    /// （缓冲归调用方，用完调 [`平台_释放接口描述`] 还 —— 见文件头「所有权」）。
    pub fn 取接口描述(&self) -> String {
        接口描述::写描述(&self.适配器, self.契约来源)
    }

    /// 读侧能力清单（与 [`适配器::能力清单`] 同一条路，供验证面比对接口描述）。
    pub fn 能力清单(&self) -> Vec<能力摘要> {
        self.适配器.能力清单()
    }

    /// 调：按号 + 按契约行序填值。**协议层结果**由返回值给，**业务失败**在返回槽里。
    ///
    /// - 成功（返回 [`协议结果::成功`]）⇒ 返回槽里是**值**。
    /// - 参数个数不符（返回 [`协议结果::参数不合法`]）⇒ 返回槽置空。参数个数不符是
    ///   **调用形状**不对，属协议层，故不塞进返回槽（这一支由调度层的判据给出，边界不重判）。
    /// - 其余业务失败（未命中 · 已废止 · 超时 · 配额用尽）⇒ 返回 [`协议结果::成功`]，
    ///   **失败在返回槽里**：`类型标签 = 类型标签_4294967295`（错误），`值 = 4 位码`
    ///   （`段位 × 1000 + 序号`）。三项业务判断（可重试 / 可自愈 / 需人工）由
    ///   `平台_取接口描述` 的 `可抛错误码` 表随包给出。
    pub fn 调用(&self, 号值: u32, 参数: &[数据槽], 返回槽: &mut 数据槽) -> i32 {
        match self.适配器.调用能力(号值, 参数, 返回槽) {
            转发结果::成功(_) => 协议结果::成功,
            转发结果::失败(调度错误::参数个数不符 { .. }) => {
                *返回槽 = 数据槽::空槽();
                协议结果::参数不合法
            }
            转发结果::失败(错) => {
                *返回槽 = 造错误槽(业务错误码(错));
                协议结果::成功
            }
        }
    }

    /// 还：把调用方拿到的值的所有权交回。**幂等**（见文件头「所有权」）。
    ///
    /// 本边界交出的东西都是静态终生有效的 ⇒ 本函数**不调用任何释放器**，
    /// 只把槽清空。空指针与「已经是空槽」都当无事发生（重复归还不崩、不会二次释放）。
    ///
    /// 实现只有一份：[`crate::值归还::归还槽值`] —— Rust 面的 [`crate::适配器::释放值`]
    /// 走的是同一个函数，两条口同语义。
    pub fn 释放值(数据槽: &mut 数据槽) {
        crate::值归还::归还槽值(数据槽);
    }
}

/// 业务失败的返回槽：`类型标签 = 错误`，`值 = 4 位码`（`段位 × 1000 + 序号`）。
///
/// 4 位码是**声明侧登记过**的（`契约声明/错误码表/`）：调用方拿 `码` 去
/// `平台_取接口描述` 的 `可抛错误码` 表里查那三项业务判断。
fn 造错误槽(错误码: u32) -> 数据槽 {
    数据槽::内联(声明数据::类型标签_4294967295, 错误码 as u64, 0)
}

/// `调度错误` → 4 位码。**码值只有一个来源**：生成物 `v1_contract::声明数据`
/// （源 = `契约声明/错误码表/*.json`），这里只做「段位 → 码」的对位，不另写数。
///
/// `pub(crate)`：调用留痕（`留痕口.rs`）要用同一个对位，不许在别处再写一张。
pub(crate) fn 业务错误码(错误: 调度错误) -> u32 {
    match 错误 {
        调度错误::提供者未载入 { .. } => 声明数据::错误码_1.取号值(),
        调度错误::命令已废止 { .. } => 声明数据::错误码_2.取号值(),
        调度错误::参数个数不符 { .. } => 声明数据::错误码_3.取号值(),
        调度错误::超时 { .. } => 声明数据::错误码_4.取号值(),
        调度错误::配额用尽 => 声明数据::错误码_5.取号值(),
    }
}

/// 导出符号绑定的边界实例：平台自身的声明根（见文件头缺口 4）。
///
/// **载不进来就报「提供者未载入」**：没有可寻址的表 ⇒ 每个号都未命中，
/// 与调度层对未命中号的口径一致。这不是正常路径（平台自身的声明必然载得进来，
/// `适配器测试.rs` 已钉住），故不 panic（跨边界 panic 是明令禁止的）。
fn 默认边界() -> Option<对外边界> {
    对外边界::新建(&[v1_loader::底座声明()]).ok()
}

/// 读接口描述：UTF-8 JSON，长度由出参带回。
///
/// # 所有权（**写死一种**，理由见文件头）
///
/// 返回的缓冲**归调用方**：调用方用完必须调 [`平台_释放接口描述`] 还（`(缓冲, 长度)`
/// 成对给回）。**不还就是泄漏一份** —— 但那是调用方不守约，不再是本边界每次调用无条件泄漏。
///
/// # Safety
///
/// `长度` 要么为空指针，要么指向**一个可写的 `u32`**。
/// 长度为 null ⇒ 无法报告长度 ⇒ 返回空指针（不交出一个不可读的缓冲），**不崩**。
#[unsafe(export_name = "平台_取接口描述")]
pub unsafe extern "C" fn 平台_取接口描述(长度: *mut u32) -> *const c_char {
    if 长度.is_null() {
        return core::ptr::null();
    }
    let json = match 默认边界() {
        Some(边界) => 边界.取接口描述(),
        // 平台自身的声明载不进来 ⇒ 没有可描述的接口：给一个**合法**的空对象，
        // 而不是半个形状（少一个字段的 JSON 比空对象更难判）。
        None => String::from("{}"),
    };
    let 字节 = json.into_bytes();
    if 字节.len() > u32::MAX as usize {
        return core::ptr::null();
    }
    let 字节长度 = 字节.len() as u32;
    // 所有权交给调用方：`Box<[u8]>` 转成裸指针，调用方用 `平台_释放接口描述(指针, 长度)` 还。
    let 指针 = Box::into_raw(字节.into_boxed_slice()).cast::<u8>();
    // SAFETY: 长度 非空（上面已挡）；调用方按本函数的 Safety 契约保证它可写。
    unsafe { *长度 = 字节长度 };
    指针 as *const c_char
}

/// 还：把 [`平台_取接口描述`] 交出的缓冲还给边界。
///
/// 参数成对：`(缓冲, 长度)` 必须与 `平台_取接口描述` 交出的那一对**逐字相同**
/// （长度是重建 `Box<[u8]>` 的必需信息）。**空指针当无事发生**；同一对还两次是
/// **二次释放**（未定义行为）—— 本函数是 `void`、没有报错通道，故按 `边界协议.md` §三
/// 的口径由调用方守约「谁分配谁释放、只还一次」。
///
/// # Safety
///
/// `缓冲` 要么为空指针（此时什么都不做），要么是 [`平台_取接口描述`] 交出、**尚未归还**的
/// 指针，且 `长度` 是它当时的字节数。
#[unsafe(export_name = "平台_释放接口描述")]
pub unsafe extern "C" fn 平台_释放接口描述(缓冲: *const c_char, 长度: u32) {
    if 缓冲.is_null() {
        return;
    }
    let 切片 = core::ptr::slice_from_raw_parts_mut(缓冲 as *mut u8, 长度 as usize);
    // SAFETY: 缓冲 由 平台_取接口描述 的 `Box<[u8]>` 转出，长度逐字相同；
    // 调用方按 Safety 契约只还一次 ⇒ 这一次 `Box::from_raw` 是唯一的一次释放。
    drop(unsafe { Box::from_raw(切片) });
}

/// 调用：按号 + 按契约行序填值。
///
/// 返回值只表达**协议层**结果（[`协议结果`]）；业务失败在返回槽里（见 [`对外边界::调用`]）。
///
/// # Safety
///
/// - `返回槽` 要么为空指针（此时返回 [`协议结果::参数不合法`]，不写任何内存），
///   要么指向**一个可写的 [`数据槽`]**。
/// - `参数表` 要么为空指针（此时 `参数个数` 必须为 0），要么指向**至少 `参数个数` 个可读的 [`数据槽`]**。
#[unsafe(export_name = "平台_调用")]
pub unsafe extern "C" fn 平台_调用(
    号值: u32,
    参数个数: u32,
    参数表: *const 数据槽,
    返回槽: *mut 数据槽,
) -> i32 {
    if 返回槽.is_null() {
        return 协议结果::参数不合法;
    }
    // SAFETY: 返回槽 非空；调用方按本函数的 Safety 契约保证它可写。
    let 数据槽 = unsafe { &mut *返回槽 };
    if 参数个数 > 0 && 参数表.is_null() {
        *数据槽 = 数据槽::空槽();
        return 协议结果::参数不合法;
    }
    let 参数: &[数据槽] = if 参数个数 == 0 {
        &[]
    } else {
        // SAFETY: 参数表 非空；调用方按本函数的 Safety 契约保证它有 参数个数 个可读槽。
        unsafe { core::slice::from_raw_parts(参数表, 参数个数 as usize) }
    };
    let Some(边界) = 默认边界() else {
        *数据槽 = 造错误槽(声明数据::错误码_1.取号值());
        return 协议结果::成功;
    };
    边界.调用(号值, 参数, 数据槽)
}

/// 还值：把调用方拿到的值的所有权交回。**幂等**（见文件头「所有权」）。
///
/// # Safety
///
/// `槽指针` 要么为空指针（此时什么都不做），要么指向**一个可写的 [`数据槽`]**。
#[unsafe(export_name = "平台_释放值")]
pub unsafe extern "C" fn 平台_释放值(槽指针: *mut 数据槽) {
    if 槽指针.is_null() {
        return;
    }
    // SAFETY: 槽指针 非空；调用方按本函数的 Safety 契约保证它可写。
    对外边界::释放值(unsafe { &mut *槽指针 });
}
