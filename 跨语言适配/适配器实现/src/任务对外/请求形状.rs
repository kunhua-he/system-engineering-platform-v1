//! 任务对外 · 请求形状 —— 对外数据结构的**唯一**声明处（纯数据，无行为）。
//!
//! 三种角色共用本件：接口面把协议体翻成这里的节点请求；本面的任务表交回快照与读数；
//! 拒绝形状只走 [`图任务拒绝`]（**不新增错误码段** —— 图任务族的码还没登记）。

use v1_dispatch::{调用任务阶段, 调用节点阶段};

use crate::数据槽;

/// 一个入参值的**所有权形态**。
///
/// 为什么不直接收 [`数据槽`]：槽里的文本/字节集是指针，指针不持有数据。图任务**跨过提交调用**
/// 才执行（异步），调用方栈上的那份数据早没了 ⇒ 必须由本面持有一份。执行时才 `取槽`，
/// 指针指的就是本面持有的这块数据。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 入参值 {
    /// 定长内联值（整数 / 双精度位型 / 逻辑 / 句柄 / 空槽）。
    内联 {
        标签: u32, 槽值: u64, 字节长度: u64
    },
    /// 文本（UTF-8 字节由本面持有）。
    文本(String),
    /// 字节集。
    字节(Vec<u8>),
    /// 复合载荷（列表 / 字典 / JSON 值 / 结果结构）：标签由来源给，字节由本面持有。
    载荷 { 标签: u32, 数据: Vec<u8> },
}

impl 入参值 {
    pub fn 内联(标签: u32, 槽值: u64, 字节长度: u64) -> Self {
        入参值::内联 {
            标签,
            槽值,
            字节长度,
        }
    }

    pub fn 文本(文本: impl Into<String>) -> Self {
        入参值::文本(文本.into())
    }

    pub fn 字节(字节: Vec<u8>) -> Self {
        入参值::字节(字节)
    }

    pub fn 载荷(标签: u32, 数据: Vec<u8>) -> Self {
        入参值::载荷 { 标签, 数据 }
    }

    /// 声明登记的默认值（静态只读槽）原样收下。
    pub fn 由槽(槽: 数据槽) -> Self {
        if 槽.是否引用() {
            // 引用形态的默认值指向静态数据（声明持有），只能按字节长度复制一次。
            // 空长度 ⇒ 没有可复制的字节，按空槽处理（不编一个假指针）。
            if 槽.槽字节长度 == 0 {
                return 入参值::内联(0, 0, 0);
            }
            let 起点 = 槽.槽值 as *const u8;
            // SAFETY: 声明登记的默认值指向静态只读数据，长度由声明给出（契约：一切串都带长度）。
            let 字节 = unsafe { core::slice::from_raw_parts(起点, 槽.槽字节长度 as usize) };
            return 入参值::载荷 {
                标签: 槽.类型标签.取号值(),
                数据: 字节.to_vec(),
            };
        }
        入参值::内联(槽.类型标签.取号值(), 槽.槽值, 槽.槽字节长度)
    }

    /// 取一个可交给执行侧的槽。文本 / 字节 / 载荷的指针指向本值持有的缓冲
    /// ⇒ 本值活着，指针才有效（调用方必须保证执行期间本值不被替换）。
    pub fn 取槽(&self) -> 数据槽 {
        match self {
            入参值::内联 {
                标签,
                槽值,
                字节长度,
            } => 数据槽::内联槽((*标签).into(), *槽值, *字节长度),
            入参值::文本(文本) => 数据槽::指针(
                crate::声明数据::类型标签_0004,
                文本.as_ptr() as u64,
                文本.len() as u64,
                false,
            ),
            入参值::字节(字节) => 数据槽::指针(
                crate::声明数据::类型标签_0005,
                字节.as_ptr() as u64,
                字节.len() as u64,
                false,
            ),
            入参值::载荷 { 标签, 数据 } => 数据槽::指针(
                (*标签).into(),
                数据.as_ptr() as u64,
                数据.len() as u64,
                false,
            ),
        }
    }
}

/// 一项输入引用：本节点的某个参数取上游节点的产出。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 节点输入引用 {
    pub 目标参数: String,
    pub 来源节点: String,
}

/// 一个节点的请求（**接口面翻好的形态**，不是协议体）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 图任务节点请求 {
    pub 节点标识: String,
    pub 编号: u32,
    /// 命名形态入参：参数名 → 值。行序在 [`节点计划`](super::节点计划) 里按契约映射。
    pub 命名值: Vec<(String, 入参值)>,
    pub 依赖节点: Vec<String>,
    pub 输入引用: Vec<节点输入引用>,
}

/// 一次提交的选项。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 任务选项 {
    /// 调用方的幂等键。`None` = 不判重（每次都是新任务）。
    pub 请求标识: Option<String>,
}

impl 任务选项 {
    pub fn 按请求(请求标识: impl Into<String>) -> Self {
        Self {
            请求标识: Some(请求标识.into()),
        }
    }

    pub fn 不判重() -> Self {
        Self::default()
    }
}

/// 图任务被拒的类别。
///
/// 名字与 `契约声明/调用任务协议.json` 的「错误类别」逐字对齐（图形不合法 · 请求标识冲突 ·
/// 存储不可用）；**不带码**：这一族的码还没登记，编一个号等于让调用方拿到查不到名字的号。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 图任务拒绝 {
    /// 图本身不成立（空表 · 重复标识 · 未知依赖 · 有环）。
    图形不合法 { 说明: String },
    /// 同请求标识但图摘要不同。
    请求标识冲突 { 请求标识: String },
    /// 节点参数与契约不符（业务拒绝）：编号没人认领 · 参数名不认识 · 缺参数无默认值 ·
    /// 引用指向非法来源。**与执行崩溃分开**：这一类在执行前就定，重试永远是同一结果。
    节点参数不符契约 {
        节点标识: String, 说明: String
    },
    /// 任务表 / 调度装配不可写：不受理，也不假装已接收。
    存储不可用 { 说明: String },
}

impl 图任务拒绝 {
    pub fn 名称(&self) -> &'static str {
        match self {
            Self::图形不合法 { .. } => "图形不合法",
            Self::请求标识冲突 { .. } => "请求标识冲突",
            Self::节点参数不符契约 { .. } => "节点参数不符契约",
            Self::存储不可用 { .. } => "存储不可用",
        }
    }

    /// 一句可读说明（回执的 `说明` 字段）。
    pub fn 说明(&self) -> String {
        match self {
            Self::图形不合法 { 说明 } => format!("图形不合法：{说明}"),
            Self::请求标识冲突 { 请求标识 } => format!(
                "请求标识冲突：请求标识「{请求标识}」已用于另一张图 —— \
                 同一个请求标识只能指同一张图（幂等键不是复用键）"
            ),
            Self::节点参数不符契约 {
                节点标识, 说明
            } => {
                format!("节点「{节点标识}」的参数不符契约：{说明}")
            }
            Self::存储不可用 { 说明 } => format!("存储不可用：{说明}"),
        }
    }

    /// 出错落在哪个节点（`None` = 整张图层面）。
    pub fn 节点标识(&self) -> Option<&str> {
        match self {
            Self::节点参数不符契约 { 节点标识, .. } => Some(节点标识),
            _ => None,
        }
    }
}

/// 失败节点的读数（查询回执的 `错误` 用）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 节点失败读数 {
    pub 节点标识: String,
    pub 说明: String,
}

/// 一张任务的当前状态（**查询与等待共用的形状**）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 任务快照 {
    pub 任务标识: u64,
    pub 阶段: 调用任务阶段,
    /// 按节点表原序；查询收窄时只留被点名的那个。
    pub 节点读数表: Vec<节点读数>,
    /// 有失败节点才给 —— 成功与失败不能同时为真。
    pub 错误: Option<节点失败读数>,
}

/// 一个节点在快照里的一行：阶段 **+** 真跑过的区间与代次。
///
/// 为什么时刻要挂在快照上：只报阶段名时，外部读不出「两条并行支的时间真重叠」、
/// 「后继真等前驱结束」这类事实，验收页只能永久记「看不见」。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 节点读数 {
    pub 节点标识: String,
    pub 节点阶段: 调用节点阶段,
    /// 真起跑那一刻（本任务提交时刻为零时的微秒数）；没起跑就 `None`，不写 0。
    pub 开始微秒: Option<u64>,
    /// 执行收尾那一刻；没跑完（含还没起跑）就 `None`。
    pub 结束微秒: Option<u64>,
    /// 真执行的那一代批号（内核启动节点时发的同一个号）；没起跑就 `None`。
    pub 执行批号: Option<u64>,
}

impl 任务快照 {
    pub fn 终态(&self) -> bool {
        matches!(
            self.阶段,
            调用任务阶段::成功 | 调用任务阶段::失败 | 调用任务阶段::已取消
        )
    }

    /// 某个节点的阶段（收窄查询的读数口）。
    pub fn 节点阶段(&self, 节点标识: &str) -> Option<调用节点阶段> {
        self.节点读数(节点标识).map(|项| 项.节点阶段)
    }

    /// 某个节点的整行读数（阶段 + 区间 + 代次）；查不到就 `None`。
    pub fn 节点读数(&self, 节点标识: &str) -> Option<&节点读数> {
        self.节点读数表.iter().find(|项| 项.节点标识 == 节点标识)
    }
}

/// 一次取消的读数。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 取消读数 {
    pub 任务标识: u64,
    /// 任务表里原本有没有这条任务（没有就什么都不改）。
    pub 任务存在: bool,
    pub 阶段: 调用任务阶段,
    /// 本次被置成「已取消」的节点（等待中 / 就绪 / 等资源的那批）。
    pub 已取消节点: Vec<String>,
    /// 执行中 / 收尾中的节点：**只标记，不伪造** —— 真实收口后才回收资源。
    pub 在跑节点: Vec<String>,
}
