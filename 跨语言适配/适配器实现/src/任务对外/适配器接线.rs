//! 任务对外 · 适配器接线 —— `适配器` 上的五个公开方法。
//!
//! ```text
//! 提交任务图(节点表, 任务选项)      -> Result<任务标识, 图任务拒绝>
//! 查询任务(任务标识, 可选节点标识)  -> Option<任务快照>
//! 等待任务(任务标识, 时限)          -> Option<任务快照>       （等不到回当前快照）
//! 取消任务(任务标识, 等待窗口)      -> 取消读数
//! 释放任务(任务标识)                -> bool                  （只对终态任务开口）
//! ```
//!
//! # 锁的边界
//!
//! 任务表的锁**不跨业务调用持有**：取条目 → 放锁 → 向调度实例要阶段。实例另有一把锁，
//! 两把锁从不嵌套同向（实例一侧从不回头取任务表），所以不会互相等死。

use std::sync::{Arc, Mutex, MutexGuard};
use std::time::{Duration, Instant};

use v1_dispatch::{调用任务阶段, 调用节点阶段};

use crate::调用任务装配::{叶子执行口, 装配错误, 调度实例};

use super::叶子::图任务叶子;
use super::形状::{
    任务快照, 任务选项, 取消读数, 图任务拒绝, 图任务节点请求, 节点失败读数, 节点读数,
};
use super::落盘注入;
use super::表::{
    任务条目, 任务表, 取消, 在跑节点, 等收口, 造快照, 阶段, 默认任务容量
};
use super::计划;

/// 等待时的轮询间隔：短到「等到了立刻回」，长到不空转烧 CPU。
const 轮询间隔: Duration = Duration::from_millis(2);

/// 取任务表的锁（中毒也拿回来：一条坏记录不许让整张表永久不可用）。
pub(crate) fn 取任务表锁(表: &Mutex<任务表>) -> MutexGuard<'_, 任务表> {
    表.lock().unwrap_or_else(|中毒| 中毒.into_inner())
}

impl crate::适配器 {
    /// 提交一张图：发号 → 建计划 → 装配调度实例 → 提交 → 入表。
    pub fn 提交任务图(
        &self,
        节点表: &[图任务节点请求],
        选项: 任务选项,
    ) -> Result<u64, 图任务拒绝> {
        if let Some(错误) = self.重启快照.lock().unwrap_or_else(|中毒| 中毒.into_inner()).故障.clone() { return Err(图任务拒绝::存储不可用 { 说明: 错误 }); }
        if let Some(落盘) = &self.运行态 { 落盘.检查().map_err(|错误| 图任务拒绝::存储不可用 { 说明: 错误 })?; }
        let 建图 = 计划::建任务图(self, 节点表, self.实例号)?;
        let mut 表 = 取任务表锁(&self.任务表);
        if let Some(落盘) = &self.运行态 { 表.接上落盘(Arc::clone(落盘)); }
        // 判重先看内存，再看重启快照：上一个进程受理过的请求标识也算数
        // （否则重启后同一个请求标识会被当成新图，重跑一遍）。
        let 重启判重 = 选项.请求标识.as_deref().and_then(|键| {
            self.重启快照
                .lock()
                .ok()
                .and_then(|快照| 快照.幂等.get(键).copied())
        });
        let 命中 = 选项.请求标识.as_deref().and_then(|键| {
            表.按请求标识(键)
                .map(|号| (号, 表.摘要(号)))
                .or_else(|| 重启判重.map(|(号, 摘要)| (号, Some(摘要))))
        });
        if let Some((既有, 既有摘要)) = 命中 {
            if 既有摘要 == Some(建图.摘要) {
                // 幂等：同请求标识 + 同图 ⇒ 原任务标识（重试不重开一张图）。
                return Ok(既有);
            }
            return Err(图任务拒绝::请求标识冲突 {
                请求标识: 选项.请求标识.unwrap_or_default(),
            });
        }
        let 任务标识 = 表.发号();
        let 产出表 = std::sync::Arc::new(Mutex::new(Default::default()));
        let 失败表 = std::sync::Arc::new(Mutex::new(Default::default()));
        let mut 执行快照 = self.clone();
        // 执行快照仅持路由，不强持任务表或持久写者，避免任务所有权成环。
        执行快照.任务表 = Arc::new(Mutex::new(任务表::新建(默认任务容量)));
        执行快照.运行态 = None;
        let 执行口: std::sync::Arc<dyn 叶子执行口> = std::sync::Arc::new(图任务叶子::新建(
            执行快照,
            self.叶子标记.clone(),
            建图.计划表,
            产出表.clone(),
            失败表.clone(),
        ));
        // 生产启动先接存储；纯内存仅留给未接生产存储的装配与测试。
        let 注入: Option<Box<dyn crate::调用任务装配::任务存储回调>> =
            self.运行态.as_ref().map(|落盘| {
                Box::new(落盘注入::新建(
                    Arc::clone(落盘),
                    选项.请求标识.clone(),
                    建图.摘要,
                )) as Box<dyn crate::调用任务装配::任务存储回调>
            });
        let 实例 = 调度实例::装配带注入(建图.素材表, 执行口, &任务标识.to_string(), 注入)
            .map_err(拒绝映射)?;
        实例.提交().map_err(拒绝映射)?;
        let 实例 = std::sync::Arc::new(实例);
        let 提交微秒 = u64::try_from(实例.任务零时().saturating_duration_since(self.进程零时).as_micros()).unwrap_or(u64::MAX);
        表.插入(任务条目 {
            任务标识,
            请求标识: 选项.请求标识,
            摘要: 建图.摘要,
            实例,
            节点标识表: 建图.节点标识表,
            取消: false,
            提交微秒,
            末次访问: 0,
            失败表,
            产出表,
        });
        表.清扫();
        Ok(任务标识)
    }

    /// 查询：任务不在表里 ⇒ `None`（不是「空表」：查无此任务要说得出）。
    pub fn 查询任务(
        &self, 任务标识: u64, 节点标识: Option<&str>
    ) -> Option<任务快照> {
        {
            let mut 表 = 取任务表锁(&self.任务表);
            if let Some(条目) = 表.取(任务标识) {
                return 造快照(条目, 节点标识);
            }
        }
        // 内存里没有 ⇒ 可能是上一个进程受理的：从重启快照回答（终态 + 对账结论）。
        // **不编造时刻**：那些时刻是实例内单调钟，跨进程没有意义，故一律不给。
        let 快照 = self.重启快照.lock().ok()?;
        恢复任务快照(任务标识, 快照.任务.get(&任务标识), 节点标识)
    }

    /// 等待：窗口内等到终态就回它；等不到回**当前**快照（不编「跑完了」）。
    pub fn 等待任务(&self, 任务标识: u64, 时限: Duration) -> Option<任务快照> {
        let 起点 = Instant::now();
        loop {
            let 快照 = self.查询任务(任务标识, None)?;
            if 快照.终态() {
                return Some(快照);
            }
            let 剩余 = 时限.checked_sub(起点.elapsed())?;
            std::thread::sleep(轮询间隔.min(剩余));
        }
    }

    /// 取消：等待中的节点置「已取消」，执行中的只标记。
    ///
    /// 两档只差「回执什么时候来」，判定本身在 `任务表::等收口`：接缝层只转调，不做业务判断
    /// （闸 ⑫ 的口径）。窗口由接口面给 —— 五秒硬顶是那一层的规矩，本层不复制一份。
    pub fn 取消任务(&self, 任务标识: u64, 等待窗口: Option<Duration>) -> 取消读数 {
        let 读数 = {
            let mut 表 = 取任务表锁(&self.任务表);
            match 表.取(任务标识) {
                Some(条目) => 取消(条目),
                None => 取消读数 {
                    任务标识,
                    任务存在: false,
                    阶段: 调用任务阶段::已取消,
                    已取消节点: Vec::new(),
                    在跑节点: Vec::new(),
                },
            }
        };
        等收口(&self.任务表, 读数, 等待窗口)
    }

    /// 释放：只对**已终态且无在跑节点**的任务开口。返回「真释放了没有」。
    pub fn 释放任务(&self, 任务标识: u64) -> bool {
        let mut 表 = 取任务表锁(&self.任务表);
        let 可释放 = 表.取(任务标识).is_some_and(|条目| {
            let 阶段 = 阶段(条目);
            matches!(
                阶段,
                调用任务阶段::成功 | 调用任务阶段::失败 | 调用任务阶段::已取消
            ) && 在跑节点(条目).is_empty()
        });
        if 可释放 {
            let 成了 = 表.移除(任务标识);
            drop(表);
            return 成了;
        }
        drop(表);
        // 内存里没有 ⇒ 可能是上一个进程受理的任务：从重启快照里真删掉，
        // 并落一条释放标记（否则重启之后它又冒出来，等于释放没生效）。
        let Ok(mut 快照) = self.重启快照.lock() else {
            return false;
        };
        let Some(恢复) = 快照.任务.get(&任务标识) else { return false; };
        if 恢复.阶段 == 调用任务阶段::未确认 || 恢复.节点.values().any(|阶段| *阶段 == 调用节点阶段::未知) { return false; }
        if let Some(落盘) = self.运行态.as_ref()
            && 落盘.追加释放(任务标识, 恢复.请求标识.as_deref()).is_err()
        {
            return false;
        }
        快照.任务.remove(&任务标识);
        快照.幂等.retain(|_, 凭据| 凭据.0 != 任务标识);
        true
    }

    /// 某个节点的产出槽（任务成功收口后读；没有就 `None`，不编一个空值）。
    pub fn 任务节点产出(
        &self, 任务标识: u64, 节点标识: &str
    ) -> Option<crate::数据槽> {
        let mut 表 = 取任务表锁(&self.任务表);
        let 条目 = 表.取(任务标识)?;
        let 产出表 = std::sync::Arc::clone(&条目.产出表);
        drop(表);
        产出表.lock().ok()?.get(节点标识).copied()
    }

    /// 当前任务表条数（观测与容量判据用）。
    pub fn 任务表条数(&self) -> usize {
        取任务表锁(&self.任务表).条数()
    }

    /// 任务表容量（部署侧要调时给）。
    pub fn 任务表容量(&self) -> usize {
        默认任务容量
    }
}

/// 装配错误 → 图任务拒绝（**不新增错误码段**：拒绝只分「业务拒绝 / 存储不可用」两类）。
fn 拒绝映射(错误: 装配错误) -> 图任务拒绝 {
    match 错误 {
        装配错误::图校验失败(_) | 装配错误::空素材表 | 装配错误::叶子内重入 => {
            图任务拒绝::图形不合法 {
                说明: format!("{错误:?}"),
            }
        }
        其余 => 图任务拒绝::存储不可用 {
            说明: format!("{其余:?}"),
        },
    }
}

/// 把**重启快照**里的一条恢复成回执快照。
///
/// 只给阶段，不给时刻与批号：那些是实例内的单调钟读数，跨进程没有可比性 —— 编一个出来
/// 就是假证据。失败读数只对「真有确认失败」的任务给 —— 重启前在跑的节点现在报「未知」，
/// 不摆失败读数：没有失败就不许装一份出来。
fn 恢复任务快照(
    任务标识: u64,
    恢复: Option<&super::恢复任务>,
    收窄: Option<&str>,
) -> Option<任务快照> {
    let 恢复 = 恢复?;
    let 节点读数表: Vec<节点读数> = 恢复
        .节点
        .iter()
        .filter(|(标识, _)| 收窄.is_none_or(|要| 要 == 标识.as_str()))
        .map(|(标识, 阶段)| 节点读数 {
            节点标识: 标识.clone(),
            节点阶段: *阶段,
            开始微秒: None,
            结束微秒: None,
            执行批号: None,
        })
        .collect();
    if 节点读数表.is_empty() {
        return None;
    }
    let 错误 = (恢复.阶段 == 调用任务阶段::失败).then(|| 节点失败读数 {
        说明: "内核记了这个任务的失败读数，节点明细见节点表".to_owned(),
        // 有具体失败的节点就点名它；整图级中断（没有单点可指）就用「任务」当锚。
        节点标识: 节点读数表
            .iter()
            .find(|行| 行.节点阶段 == 调用节点阶段::失败)
            .map(|行| 行.节点标识.clone())
            .unwrap_or_else(|| "任务".to_owned()),
    });
    Some(任务快照 {
        任务标识,
        阶段: 恢复.阶段,
        节点读数表,
        错误,
    })
}
