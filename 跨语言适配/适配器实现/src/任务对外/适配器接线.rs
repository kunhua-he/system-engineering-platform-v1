//! 任务对外 · 适配器接线 —— `适配器` 上的五个公开方法。
//!
//! ```text
//! 提交任务图(节点表, 任务选项)      -> Result<任务标识, 图任务拒绝>
//! 查询任务(任务标识, 可选节点标识)  -> Option<任务快照>
//! 等待任务(任务标识, 时限)          -> Option<任务快照>       （等不到回当前快照）
//! 取消任务(任务标识)                -> 取消读数
//! 释放任务(任务标识)                -> bool                  （只对终态任务开口）
//! ```
//!
//! # 锁的边界
//!
//! 任务表的锁**不跨业务调用持有**：取条目 → 放锁 → 向调度实例要阶段。实例另有一把锁，
//! 两把锁从不嵌套同向（实例一侧从不回头取任务表），所以不会互相等死。

use std::sync::{Mutex, MutexGuard};
use std::time::{Duration, Instant};

use v1_dispatch::调用任务阶段;

use crate::调用任务装配::{叶子执行口, 装配错误, 调度实例};

use super::叶子::图任务叶子;
use super::形状::{
    任务快照, 任务选项, 取消读数, 图任务拒绝, 图任务节点请求
};
use super::表::{
    任务条目, 任务表, 取消, 在跑节点, 造快照, 阶段, 默认任务容量
};
use super::计划;

/// 等待时的轮询间隔：短到「等到了立刻回」，长到不空转烧 CPU。
const 轮询间隔: Duration = Duration::from_millis(2);

/// 取任务表的锁（中毒也拿回来：一条坏记录不许让整张表永久不可用）。
pub(crate) fn 取任务表锁(表: &Mutex<任务表>) -> MutexGuard<'_, 任务表> {
    表.lock().unwrap_or_else(|中毒| 中毒.into_inner())
}

impl crate::适配器 {
    /// 提交一张图：发号 → 建计划 → 装配调度实例 → 提交 → 入表。
    pub fn 提交任务图(
        &self,
        节点表: &[图任务节点请求],
        选项: 任务选项,
    ) -> Result<u64, 图任务拒绝> {
        let 建图 = 计划::建任务图(self, 节点表, self.实例号)?;
        let mut 表 = 取任务表锁(&self.任务表);
        if let Some(请求标识) = 选项.请求标识.as_deref()
            && let Some(既有) = 表.按请求标识(请求标识)
        {
            if 表.摘要(既有) == Some(建图.摘要) {
                // 幂等：同请求标识 + 同图 ⇒ 原任务标识（重试不重开一张图）。
                return Ok(既有);
            }
            return Err(图任务拒绝::请求标识冲突 {
                请求标识: 请求标识.to_owned(),
            });
        }
        let 任务标识 = 表.发号();
        let 产出表 = std::sync::Arc::new(Mutex::new(Default::default()));
        let 失败表 = std::sync::Arc::new(Mutex::new(Default::default()));
        let 执行口: std::sync::Arc<dyn 叶子执行口> = std::sync::Arc::new(图任务叶子::新建(
            self.clone(),
            self.叶子标记.clone(),
            建图.计划表,
            产出表.clone(),
            失败表.clone(),
        ));
        let 实例 = 调度实例::装配(建图.素材表, 执行口, &任务标识.to_string()).map_err(拒绝映射)?;
        实例.提交().map_err(拒绝映射)?;
        let 实例 = std::sync::Arc::new(实例);
        表.插入(任务条目 {
            任务标识,
            请求标识: 选项.请求标识,
            摘要: 建图.摘要,
            实例,
            节点标识表: 建图.节点标识表,
            取消: false,
            末次访问: 0,
            失败表,
            产出表,
        });
        表.清扫();
        Ok(任务标识)
    }

    /// 查询：任务不在表里 ⇒ `None`（不是「空表」：查无此任务要说得出）。
    pub fn 查询任务(
        &self, 任务标识: u64, 节点标识: Option<&str>
    ) -> Option<任务快照> {
        let mut 表 = 取任务表锁(&self.任务表);
        let 条目 = 表.取(任务标识)?;
        造快照(条目, 节点标识)
    }

    /// 等待：窗口内等到终态就回它；等不到回**当前**快照（不编「跑完了」）。
    pub fn 等待任务(&self, 任务标识: u64, 时限: Duration) -> Option<任务快照> {
        let 起点 = Instant::now();
        loop {
            let 快照 = self.查询任务(任务标识, None)?;
            if 快照.终态() {
                return Some(快照);
            }
            let 剩余 = 时限.checked_sub(起点.elapsed())?;
            std::thread::sleep(轮询间隔.min(剩余));
        }
    }

    /// 取消：等待中的节点置「已取消」，执行中的只标记。
    pub fn 取消任务(&self, 任务标识: u64) -> 取消读数 {
        let mut 表 = 取任务表锁(&self.任务表);
        match 表.取(任务标识) {
            Some(条目) => 取消(条目),
            None => 取消读数 {
                任务标识,
                任务存在: false,
                阶段: 调用任务阶段::已取消,
                已取消节点: Vec::new(),
                在跑节点: Vec::new(),
            },
        }
    }

    /// 释放：只对**已终态且无在跑节点**的任务开口。返回「真释放了没有」。
    pub fn 释放任务(&self, 任务标识: u64) -> bool {
        let mut 表 = 取任务表锁(&self.任务表);
        let 可释放 = 表.取(任务标识).is_some_and(|条目| {
            let 阶段 = 阶段(条目);
            matches!(
                阶段,
                调用任务阶段::成功 | 调用任务阶段::失败 | 调用任务阶段::已取消
            ) && 在跑节点(条目).is_empty()
        });
        if !可释放 {
            return false;
        }
        表.移除(任务标识)
    }

    /// 某个节点的产出槽（任务成功收口后读；没有就 `None`，不编一个空值）。
    pub fn 任务节点产出(
        &self, 任务标识: u64, 节点标识: &str
    ) -> Option<crate::数据槽> {
        let mut 表 = 取任务表锁(&self.任务表);
        let 条目 = 表.取(任务标识)?;
        let 产出表 = std::sync::Arc::clone(&条目.产出表);
        drop(表);
        产出表.lock().ok()?.get(节点标识).copied()
    }

    /// 当前任务表条数（观测与容量判据用）。
    pub fn 任务表条数(&self) -> usize {
        取任务表锁(&self.任务表).条数()
    }

    /// 任务表容量（部署侧要调时给）。
    pub fn 任务表容量(&self) -> usize {
        默认任务容量
    }
}

/// 装配错误 → 图任务拒绝（**不新增错误码段**：拒绝只分「业务拒绝 / 存储不可用」两类）。
fn 拒绝映射(错误: 装配错误) -> 图任务拒绝 {
    match 错误 {
        装配错误::图校验失败(_) | 装配错误::空素材表 | 装配错误::叶子内重入 => {
            图任务拒绝::图形不合法 {
                说明: format!("{错误:?}"),
            }
        }
        其余 => 图任务拒绝::存储不可用 {
            说明: format!("{其余:?}"),
        },
    }
}
