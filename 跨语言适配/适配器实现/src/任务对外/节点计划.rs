//! 任务对外 · 节点计划 —— 命名值按契约映射成行序 + 输入引用补位表 + 资源键。
//!
//! # 行序只有一份来源
//!
//! 「参数名 → 第几行」这件事**不在本件另写一张表**：它由
//! [`适配器::能力契约`](crate::适配器::能力契约) 的 `参数表` 行序给出 —— 与单能力路径
//! 用的是同一份契约读数。本件只做「按那张表逐行取」，绝不按名字猜位次。
//!
//! # 为什么入参在执行时才成槽
//!
//! 图任务跨过提交调用才执行；槽里的文本是指针，指向调用方的栈早没了。故本件交出的是一份
//! **本面持有**的 [`入参值`] 计划，叶子执行时才 `取槽`（指针指向计划里的那块缓冲）。
//!
//! # 业务拒绝与执行崩溃分界
//!
//! 这里判的都是「执行前就能定、重试永远同一结果」的事：编号没人认领 · 参数名不认识 ·
//! 缺参数且无默认值 · 引用指向非法来源 ⇒ [`图任务拒绝::节点参数不符契约`]。
//! 执行期才出的事（上游产出取不到 · 执行体崩）留在叶子里，落成节点失败。

use std::collections::{BTreeMap, BTreeSet};
use std::sync::Arc;

use crate::{数据槽, 适配器};

use super::形状::{入参值, 图任务拒绝, 图任务节点请求};
use crate::调用任务装配::{叶子请求, 节点素材, 资源键};

/// 一处引用补位：执行时把上游产出槽放到本节点入参的第 `行序` 位。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct 补位 {
    pub 行序: usize,
    pub 来源节点: String,
}

/// 一个节点的执行计划：编号 + 行序入参 + 补位。
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct 节点计划 {
    pub 编号: u32,
    pub 入参: Vec<入参值>,
    pub 补位: Vec<补位>,
}

/// 建图的产物：调度素材 + 执行计划 + 节点原序 + 图摘要。
pub(crate) struct 建图结果 {
    pub 素材表: Vec<节点素材>,
    pub 计划表: Arc<BTreeMap<String, 节点计划>>,
    pub 节点标识表: Vec<String>,
    pub 摘要: u64,
}

/// 资源键的提供者标识：图任务的节点各占一条车道（异节点并行、同节点串行）。
const 提供者: &str = "图任务";

/// 把接口面翻好的节点请求建成调度素材与执行计划。
pub(crate) fn 建任务图(
    适配器: &适配器,
    节点表: &[图任务节点请求],
    实例号: u64,
) -> Result<建图结果, 图任务拒绝> {
    if 节点表.is_empty() {
        return Err(图任务拒绝::图形不合法 {
            说明: "空节点表：图任务至少一个节点（空图没有可调度的事情）".to_owned(),
        });
    }
    let mut 已见 = BTreeSet::new();
    for 节点 in 节点表 {
        if 节点.节点标识.trim().is_empty() {
            return Err(图任务拒绝::图形不合法 {
                说明: "节点标识 是空串：空标识指不出依赖它的节点".to_owned(),
            });
        }
        if !已见.insert(节点.节点标识.as_str()) {
            return Err(图任务拒绝::图形不合法 {
                说明: format!("节点标识「{}」重复：同一标识指出两个节点", 节点.节点标识),
            });
        }
    }
    let mut 素材表 = Vec::with_capacity(节点表.len());
    let mut 计划表 = BTreeMap::new();
    let mut 摘要 = 1469598103934665603_u64;
    for 节点 in 节点表 {
        摘要 = 摘要一步(摘要, &节点.节点标识);
        摘要 = 摘要一步(摘要, &节点.编号.to_string());
        for 依赖 in &节点.依赖节点 {
            摘要 = 摘要一步(摘要, 依赖);
        }
        let 计划 = 建节点计划(适配器, 节点表, 节点)?;
        for 值 in &计划.入参 {
            摘要 = 摘要一步(摘要, &format!("{值:?}"));
        }
        素材表.push(节点素材 {
            节点标识: 节点.节点标识.clone(),
            依赖节点: 节点.依赖节点.clone(),
            资源键: 资源键::推导(实例号, 提供者, 0, &节点.节点标识).车道键(),
            // 入参在执行时才成槽（见文件头）：这里留空，叶子按计划现填。
            请求: 叶子请求 {
                节点标识: 节点.节点标识.clone(),
                执行批号: 0,
                编号: 节点.编号,
                入参: Vec::new(),
            },
        });
        计划表.insert(节点.节点标识.clone(), 计划);
    }
    Ok(建图结果 {
        素材表,
        计划表: Arc::new(计划表),
        节点标识表: 节点表.iter().map(|节点| 节点.节点标识.clone()).collect(),
        摘要,
    })
}

/// 一个节点：按契约参数表逐行取值（字面值 / 引用补位 / 声明默认值）。
fn 建节点计划(
    适配器: &适配器,
    节点表: &[图任务节点请求],
    节点: &图任务节点请求,
) -> Result<节点计划, 图任务拒绝> {
    let 报 = |说明: String| 图任务拒绝::节点参数不符契约 {
        节点标识: 节点.节点标识.clone(),
        说明,
    };
    let Some(契约) = 适配器.能力契约(节点.编号) else {
        return Err(报(format!(
            "编号 {} 没有被任何已装载声明认领（同单能力路径的口径：未载入不是崩溃）",
            节点.编号
        )));
    };
    let 可用名: Vec<&str> = 契约.参数表.iter().map(|行| 行.名称.as_str()).collect();
    for (名, _) in &节点.命名值 {
        if !可用名.contains(&名.as_str()) {
            return Err(报(format!(
                "未知参数「{名}」（名字逐字比，不许按前缀或近似猜）。可用的名字：{}",
                可用名.join(" · ")
            )));
        }
    }
    let 前驱 = 传递前驱(节点表, 节点);
    let mut 已用目标 = BTreeSet::new();
    for 引用 in &节点.输入引用 {
        if !可用名.contains(&引用.目标参数.as_str()) {
            return Err(报(format!(
                "输入引用的目标参数「{}」不在本能力的参数表里。可用的名字：{}",
                引用.目标参数,
                可用名.join(" · ")
            )));
        }
        if !已用目标.insert(引用.目标参数.as_str()) {
            return Err(报(format!(
                "输入引用的目标参数「{}」被引用了两次：一个参数只能有一个来源",
                引用.目标参数
            )));
        }
        if 节点.命名值.iter().any(|(名, _)| *名 == 引用.目标参数) {
            return Err(报(format!(
                "目标参数「{}」同时给了字面值与引用：两种给法给同一件事，运行期听谁的没有答案",
                引用.目标参数
            )));
        }
        if 引用.来源节点 == 节点.节点标识 || !前驱.contains(&引用.来源节点) {
            return Err(报(format!(
                "输入引用的来源节点「{}」不是本节点的传递前驱：引用只许指向上游",
                引用.来源节点
            )));
        }
    }
    let mut 入参 = Vec::with_capacity(契约.参数表.len());
    let mut 补位 = Vec::new();
    for (行序, 参数行) in 契约.参数表.iter().enumerate() {
        if let Some((_, 值)) = 节点.命名值.iter().find(|(名, _)| *名 == 参数行.名称) {
            入参.push(值.clone());
            continue;
        }
        if let Some(引用) = 节点
            .输入引用
            .iter()
            .find(|引用| 引用.目标参数 == 参数行.名称)
        {
            入参.push(入参值::内联(0, 0, 0));
            补位.push(补位 {
                行序,
                来源节点: 引用.来源节点.clone(),
            });
            continue;
        }
        if 参数行.默认值.是否空() {
            return Err(报(format!(
                "缺参数「{}」：这一行没有声明默认值，命名形态不许静默补空槽。可用的名字：{}",
                参数行.名称,
                可用名.join(" · ")
            )));
        }
        入参.push(入参值::由槽(参数行.默认值));
    }
    Ok(节点计划 {
        编号: 节点.编号,
        入参,
        补位,
    })
}

/// 本节点的传递前驱（沿依赖往上走，含直接依赖）。
fn 传递前驱(
    节点表: &[图任务节点请求], 节点: &图任务节点请求
) -> BTreeSet<String> {
    let 表: BTreeMap<&str, &图任务节点请求> =
        节点表.iter().map(|项| (项.节点标识.as_str(), 项)).collect();
    let mut 前驱 = BTreeSet::new();
    let mut 待走: Vec<&str> = 节点.依赖节点.iter().map(String::as_str).collect();
    while let Some(当前) = 待走.pop() {
        if !前驱.insert(当前.to_owned()) {
            continue;
        }
        if let Some(上游) = 表.get(当前) {
            待走.extend(上游.依赖节点.iter().map(String::as_str));
        }
    }
    前驱
}

/// FNV-1a 一步：图摘要只用它判「同请求标识是否同一张图」，不是安全哈希。
fn 摘要一步(累计: u64, 文本: &str) -> u64 {
    let mut 值 = 累计;
    for 字节 in 文本.as_bytes() {
        值 ^= u64::from(*字节);
        值 = 值.wrapping_mul(1099511628211);
    }
    值
}

/// 声明默认值里的空槽判定（与接口面 `参数行.默认值.是否空()` 同一口径）。
#[allow(dead_code)]
fn 默认值非空(槽: 数据槽) -> bool {
    !槽.是否空()
}
