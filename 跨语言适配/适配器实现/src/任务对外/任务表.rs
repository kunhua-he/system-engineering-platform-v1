//! 任务对外 · 任务表 —— 发号 · 判重 · 快照 · 取消 · 释放 · 收口清扫。
//!
//! # 上限与清扫（不许跑一晚就漏内存）
//!
//! 表有容量（[`默认任务容量`]）。超容量时**只淘汰终态任务**，按最近最少用丢记录；
//! 在跑的任务一条都不动（丢它的记录等于把还在执行的图变成孤儿：没有口能查到、也停不掉）。
//! 淘汰**只丢记录不丢正在跑的实例**：条目一丢，实例 `Drop` 即停机合流，而那条路只有终态才走。
//!
//! # 判重窗口（这是契约，不是实现细节）
//!
//! 判重键（`请求标识`）**跟着记录一起回收**：条目被淘汰或显式释放，键就没了。
//! 于是「同标识不重跑」只在**任务表容量内**成立，且不跨进程重启。
//! 这不是偷懒：留一个指向已回收记录的长命键，调用方会拿到查不到的任务标识；
//! 而把键单独存成永久表，就要求同时落盘（运行态还没落盘，见方案单「持久化」那一批）。
//! 窗口形状已写进 `契约声明/调用任务协议.json` 的 `请求标识` 说明，并有判据钉住边界
//! （`记录释放后同请求标识会重新执行`）。
//!
//! # 阶段的唯一来源
//!
//! 阶段**只由节点真实终态推**（[`阶段`]），不读「取消旗」这一格 —— 旗只回答
//! 「调用方要不要停」，回答不了「跑到哪了」。旧写法「旗一置就报已取消」让一张已经
//! 全部跑完的图被报成已取消，正是本件要修的那类谎。
//!
//! # 取消语义（四句）
//!
//! 1. 任务已终态（成功 / 失败）⇒ 取消是**幂等空操作**：回当前真实阶段、不动旗、
//!    不列已取消节点（图都跑完了，取消是假动作）。
//! 2. 未终态时取消：已终态节点照实报；执行中 / 收尾中的节点**只标记**（不伪造已取消）；
//!    等待依赖 / 就绪 / 等资源的节点**真被挡住**（实例侧挡板不许再启动），视图报「已取消」。
//! 3. 阶段收口按节点真实终态推：无已取消节点且全部成功 ⇒ 成功；有已取消且有失败 ⇒ 失败；
//!    真取消了节点（且无在跑）⇒ 已取消。
//! 4. 释放只对**已终态且无在跑节点**的任务开口。

use std::collections::BTreeMap;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

use v1_dispatch::{调用任务阶段, 调用节点阶段};

use crate::数据槽;

use crate::调用任务装配::调度实例;

use super::形状::{任务快照, 取消读数, 节点失败读数, 节点读数};

/// 任务表容量（超了按最近最少用淘汰**终态**任务）。
pub(crate) const 默认任务容量: usize = 128;

/// 一条任务记录。**只有任务表持有它**：丢了就再没有口能查到这张图。
pub(crate) struct 任务条目 {
    pub 任务标识: u64,
    pub 请求标识: Option<String>,
    /// 图摘要（判「同请求标识是不是同一张图」）。
    pub 摘要: u64,
    pub 实例: Arc<调度实例>,
    pub 节点标识表: Vec<String>,
    pub 取消: bool,
    /// 本任务提交那一刻相对**进程零时**的微秒数。
    ///
    /// 为什么要它：内核给的 `开始微秒/结束微秒` 以本任务提交为零点，跨任务比不了。
    /// 把它加上这个数，回执里的时刻就成了「相对进程零时」的单调微秒 ——
    /// **同一进程内的任意两个任务可比**（验收页要证「两张图真并发」就靠这条），
    /// 跨进程仍不可比（也不该比：那是另一个进程的单调钟）。
    pub 提交微秒: u64,
    pub 末次访问: u64,
    pub 失败表: Arc<Mutex<BTreeMap<String, String>>>,
    /// 逐节点产出槽：引用补位从这里取，也是「上图结果」的唯一来源。
    pub 产出表: Arc<Mutex<BTreeMap<String, 数据槽>>>,
}

/// 任务表本体（**按适配器实例持有**，跨执行快照共享）。
pub(crate) struct 任务表 {
    条目: BTreeMap<u64, 任务条目>,
    幂等: BTreeMap<String, u64>,
    下一号: AtomicU64,
    访问序: u64,
    容量: usize,
}

impl 任务表 {
    /// 判据用：把容量调小，好在几秒钟内跑出「表满」这个条件（生产容量不从这里来）。
    #[cfg(test)]
    pub(crate) fn 设容量(&mut self, 容量: usize) {
        self.容量 = 容量;
    }

    pub(crate) fn 新建(容量: usize) -> Self {
        Self {
            条目: BTreeMap::new(),
            幂等: BTreeMap::new(),
            下一号: AtomicU64::new(1),
            访问序: 0,
            容量: 容量.max(1),
        }
    }

    /// 发号：**实例内单调**（原子量，跨快照共享同一条序列）。
    pub(crate) fn 发号(&self) -> u64 {
        self.下一号.fetch_add(1, Ordering::Relaxed)
    }

    /// 把计数器抬到「至少从这里接着发」（重启时用：历史号不许再发一遍）。
    ///
    /// **只抬不降**：进程内已经发过的号绝不回收，哪怕落盘的更小。
    pub(crate) fn 设起始号(&self, 起始: u64) {
        self.下一号.fetch_max(起始, Ordering::Relaxed);
    }

    pub(crate) fn 按请求标识(&self, 请求标识: &str) -> Option<u64> {
        self.幂等.get(请求标识).copied()
    }

    pub(crate) fn 摘要(&self, 任务标识: u64) -> Option<u64> {
        self.条目.get(&任务标识).map(|条目| 条目.摘要)
    }

    /// 插入一条记录，并把它的末次访问刷新到最年轻。
    ///
    /// **这一下必须刷**：`末次访问` 的初值是 0，若插入时不刷新，刚插进来的任务在淘汰序里是
    /// 「最老」的那个 —— 表一旦满了，清扫第一个就把它扔掉。症状极隐蔽：提交回 200 带任务标识，
    /// 紧接着的查询却回「任务表里查不到它（存储不可用）」，而且**只在表满之后才出现**
    /// （跑得越久越容易中）。批五（持久化）把提交频率压上去之后才稳定复现。
    pub(crate) fn 插入(&mut self, mut 条目: 任务条目) {
        self.访问序 += 1;
        条目.末次访问 = self.访问序;
        if let Some(请求标识) = 条目.请求标识.clone() {
            self.幂等.insert(请求标识, 条目.任务标识);
        }
        self.条目.insert(条目.任务标识, 条目);
    }

    /// 取条目并刷新末次访问（淘汰按它排）。
    pub(crate) fn 取(&mut self, 任务标识: u64) -> Option<&mut 任务条目> {
        self.访问序 += 1;
        let 序 = self.访问序;
        let 条目 = self.条目.get_mut(&任务标识)?;
        条目.末次访问 = 序;
        Some(条目)
    }

    /// 释放一条记录（**连同它的判重键**——键与记录同生同灭，见文件头「判重窗口」）：
    /// 返回「原本在不在」。
    pub(crate) fn 移除(&mut self, 任务标识: u64) -> bool {
        let Some(条目) = self.条目.remove(&任务标识) else {
            return false;
        };
        if let Some(请求标识) = 条目.请求标识 {
            self.幂等.remove(&请求标识);
        }
        true
    }

    pub(crate) fn 条数(&self) -> usize {
        self.条目.len()
    }

    /// 收口清扫：超容量时淘汰**终态且无在跑节点**的任务，按最近最少用先丢。
    pub(crate) fn 清扫(&mut self) {
        while self.条目.len() > self.容量 {
            let 候选 = self
                .条目
                .values()
                .filter(|条目| 可淘汰(条目))
                .min_by_key(|条目| 条目.末次访问)
                .map(|条目| 条目.任务标识);
            let Some(候选) = 候选 else {
                // 一条都不可淘汰（全在跑）：不再硬塞 —— 宁可超容量也不丢在跑的图。
                return;
            };
            self.移除(候选);
        }
    }
}

/// 能不能淘汰：终态**且**没有执行中 / 收尾中的节点。
fn 可淘汰(条目: &任务条目) -> bool {
    let 阶段 = 阶段(条目);
    matches!(
        阶段,
        调用任务阶段::成功 | 调用任务阶段::失败 | 调用任务阶段::已取消
    ) && 在跑节点(条目).is_empty()
}

/// 执行中 / 收尾中的节点（取消只标记它们，真实收口后才算停）。
pub(crate) fn 在跑节点(条目: &任务条目) -> Vec<String> {
    条目
        .节点标识表
        .iter()
        .filter(|标识| {
            matches!(
                条目.实例.节点阶段(标识),
                Some(调用节点阶段::执行中 | 调用节点阶段::收尾中)
            )
        })
        .cloned()
        .collect()
}

/// 一个节点**报出去**的阶段（快照与阶段推算共用这一处，不许两套口径）。
///
/// 取消旗只做一件事：把**没开始**（等待依赖 / 就绪 / 等资源）的节点报成「已取消」。
/// 已终态（成功 / 失败 / 跳过）与已起跑（执行中 / 收尾中）的节点**照实报** ——
/// 跃迁表里这些跃迁虽合法，但「执行体还没退场就宣布已取消」是伪造，不是取消。
pub(crate) fn 节点报读(条目: &任务条目, 标识: &str) -> 调用节点阶段 {
    match (条目.取消, 条目.实例.节点阶段(标识)) {
        (_, Some(阶段))
            if matches!(
                阶段,
                调用节点阶段::执行中
                    | 调用节点阶段::收尾中
                    | 调用节点阶段::成功
                    | 调用节点阶段::失败
                    | 调用节点阶段::跳过
            ) =>
        {
            阶段
        }
        (true, _) => 调用节点阶段::已取消,
        (false, Some(阶段)) => 阶段,
        (false, None) => 调用节点阶段::等待依赖,
    }
}

/// 任务阶段：**按节点真实终态推**（不看取消旗本身）。
///
/// 顺序即判据：有失败 ⇒ 失败（独立分支照实保留）；有在跑 ⇒ 执行中（还没收口，不提前宣布）；
/// 真取消了节点 ⇒ 已取消；全部成功 ⇒ 成功。都不是就交回内核 / 记录那份（排队中 · 收尾中等）。
pub(crate) fn 阶段(条目: &任务条目) -> 调用任务阶段 {
    let mut 有取消 = false;
    let mut 有在跑 = false;
    let mut 全成功 = true;
    for 标识 in &条目.节点标识表 {
        match 节点报读(条目, 标识) {
            调用节点阶段::失败 => return 调用任务阶段::失败,
            调用节点阶段::执行中 | 调用节点阶段::收尾中 => 有在跑 = true,
            调用节点阶段::已取消 | 调用节点阶段::跳过 => 有取消 = true,
            调用节点阶段::成功 => {}
            调用节点阶段::等待依赖 | 调用节点阶段::就绪 | 调用节点阶段::等资源 => {
                全成功 = false
            }
        }
    }
    if 有在跑 {
        // 取消旗置了但节点还没收口 ⇒ 「收尾中」：它不是「已取消」（节点还在跑、结果还没定），
        // 也不是「执行中」（不再启动新节点了）。这三句是这一档的全部意义。
        if 条目.取消 {
            return 调用任务阶段::收尾中;
        }
        return 调用任务阶段::执行中;
    }
    if 有取消 {
        return 调用任务阶段::已取消;
    }
    if 全成功 {
        return 调用任务阶段::成功;
    }
    match 条目.实例.记录阶段() {
        Some(阶段)
            if matches!(
                阶段,
                调用任务阶段::成功 | 调用任务阶段::失败 | 调用任务阶段::已取消
            ) =>
        {
            阶段
        }
        _ => 条目.实例.调度器阶段(),
    }
}

/// 造一张快照。`收窄` 给了就只留那个节点；节点不在本任务 ⇒ `None`（不是空表）。
pub(crate) fn 造快照(条目: &任务条目, 收窄: Option<&str>) -> Option<任务快照> {
    let 阶段 = 阶段(条目);
    let mut 节点读数表 = Vec::with_capacity(条目.节点标识表.len());
    for 标识 in &条目.节点标识表 {
        let 报 = 节点报读(条目, 标识);
        if 收窄.is_some_and(|要| 要 != 标识) {
            continue;
        }
        // 时刻只读实例落下的那一条：没起跑 ⇒ `None`（回执里三格一个都不出现）。
        let 时刻 = 条目.实例.节点时刻(标识);
        节点读数表.push(节点读数 {
            节点标识: 标识.clone(),
            节点阶段: 报,
            开始微秒: 时刻.map(|项| 条目.提交微秒.saturating_add(项.开始微秒)),
            结束微秒: 时刻
                .and_then(|项| 项.结束微秒)
                .map(|止| 条目.提交微秒.saturating_add(止)),
            执行批号: 时刻.map(|项| 项.执行批号),
        });
    }
    if 节点读数表.is_empty() {
        return None;
    }
    Some(任务快照 {
        任务标识: 条目.任务标识,
        阶段,
        节点读数表,
        错误: 失败读数(条目, 收窄),
    })
}

/// 失败读数：有失败节点才给（成功与失败不能同时为真）。
fn 失败读数(条目: &任务条目, 收窄: Option<&str>) -> Option<节点失败读数> {
    let 表 = 条目.失败表.lock().ok()?;
    let (节点标识, 说明) = 表
        .iter()
        .find(|(标识, _)| 收窄.is_none_or(|要| 要 == 标识.as_str()))?;
    Some(节点失败读数 {
        节点标识: 节点标识.clone(),
        说明: 说明.clone(),
    })
}

/// 取消一条任务：已终态即**幂等空操作**，否则置旗、叫实例挡住未启动的节点。
///
/// 返回读数里 `阶段` 是**受理后的事实**：已终态（成功 / 失败）⇒ 回那个真实阶段；
/// 受理了取消 ⇒ 「已取消」。真正的收口读数以 [`阶段`] 为准（它按节点终态推）。
pub(crate) fn 取消(条目: &mut 任务条目) -> 取消读数 {
    let 现阶段 = 阶段(条目);
    if matches!(现阶段, 调用任务阶段::成功 | 调用任务阶段::失败) {
        // 图都跑完了：不动旗、不列已取消节点 —— 取消对终态任务是假动作。
        return 取消读数 {
            任务标识: 条目.任务标识,
            任务存在: true,
            阶段: 现阶段,
            已取消节点: Vec::new(),
            在跑节点: Vec::new(),
        };
    }
    条目.取消 = true;
    // 叫实例关掉启动口：还没起跑的节点从此一个都不许启动（挡板在 `图驱动::冲刷`）。
    条目.实例.请求取消();
    let 在跑 = 在跑节点(条目);
    let 已取消节点 = 条目
        .节点标识表
        .iter()
        .filter(|标识| 节点报读(条目, 标识) == 调用节点阶段::已取消)
        .cloned()
        .collect::<Vec<String>>();
    取消读数 {
        任务标识: 条目.任务标识,
        任务存在: true,
        阶段: 阶段(条目),
        已取消节点,
        在跑节点: 在跑,
    }
}

/// `等收口` 档：在窗口内观察，直到任务不再停在「收尾中」。
///
/// **只观察、不改状态**：收口由在跑节点跑完自然发生，这里一个字节都不写。
/// 为什么归本件：这是存储层的等待策略（拿锁、看阶段、放锁、再睡），接缝层只该转调它；
/// 判断留在接缝层，就会与内核两套判定，必然漂移。
pub(crate) fn 等收口(
    表锁: &Mutex<任务表>,
    读数: 取消读数,
    窗口: Option<Duration>,
) -> 取消读数 {
    // 窗口是 `None` 就不等（「放弃」档），是 `Some` 才等（「等收口」档）。
    // 档位名字怎么翻成窗口是**协议翻译**，在接口面做；本件只认窗口，不认档位名。
    let Some(窗口) = 窗口 else {
        return 读数;
    };
    if 读数.阶段 != 调用任务阶段::收尾中 {
        return 读数;
    }
    let 起点 = Instant::now();
    loop {
        let Some(剩余) = 窗口.checked_sub(起点.elapsed()) else {
            return 读数;
        };
        std::thread::sleep(Duration::from_millis(2).min(剩余));
        let 现 = {
            let mut 表 = 表锁.lock().unwrap_or_else(|中毒| 中毒.into_inner());
            表.取(读数.任务标识).map(|条目| 阶段(条目))
        };
        match 现 {
            Some(阶段) if 阶段 != 调用任务阶段::收尾中 => {
                return 取消读数 { 阶段, ..读数 };
            }
            Some(_) => {}
            // 记录没了（被释放）⇒ 照实回取消那一刻的读数，不编一个新阶段。
            None => return 读数,
        }
    }
}
