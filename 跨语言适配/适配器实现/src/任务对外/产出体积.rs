//! 任务对外 · 产出体积 —— 单个产出槽的字节上限（§3.7：先量真实分布，再立限）。
//!
//! # 为什么要有上限
//!
//! 产出槽是「上游的结果原样留给下游」，它在内存里就是整段数据。没有上限时，一个节点
//! 的产出可以把进程内存吃掉一半，而调用方看不出来——它只看到「图在跑」。
//!
//! # 实测分布（2026-11-06，真实调用，不是估算）
//!
//! | 能力 | 输入规模 | 返回槽字节 |
//! |---|---|---|
//! | 3112 受控读文件 | 324KB 文本 | **480,032** |
//! | 4001 字符编码转换 | 6,000 字符 → GBK | 10,700 |
//! | 2519 一次对话 | 一句提问 | 268 |
//! | 1108 程序文本 | — | 38 |
//! | 1329 随机数 | — | 74 |
//! | 6110 公式求值 | `1+2*3` | 33 |
//! | 3113 受控原子写入 | 108K 字符 | 36 |
//!
//! 另有三个大输入能力**在入口就拒**（不是我们这层的事，记在这里免得误判成本层上限）：
//! 4601 摘要 108K 原文 ⇒ `资源受限`；4001 转换 108K ⇒ `字符编解码资源受限`；
//! 3113 写 2MB ⇒ `资源受限`。
//!
//! # 定值
//!
//! `单槽字节上限` = 2 MiB = 最大实测 480,032 字节的 **4.37 倍**（口径要求「不少于 4 倍」）。
//! 超出就**明确失败**：不静默占用，也不截断——截断的结果看起来像「能力只返回了这么多」，
//! 那是最坏的一种谎。

/// 单个产出槽的字节上限（2 MiB）。
pub(crate) const 单槽字节上限: u64 = 2 * 1024 * 1024;

/// 超限说明；没超就 `None`（判据只看这一处，不散落成好几份比较）。
pub(crate) fn 超限说明(字节: u64) -> Option<String> {
    if 字节 <= 单槽字节上限 {
        return None;
    }
    Some(format!(
        "上游产出超上限：这一槽 {字节} 字节 > 上限 {单槽字节上限} 字节（2 MiB）。\
         不截断是因为截断看起来像「能力只返回了这么多」；要传大结果请让能力落盘后传路径"
    ))
}

#[cfg(test)]
mod 测试 {
    use super::*;

    /// 判据：上限是**闭区间**——正好等于上限要放行，多一个字节才拒。
    #[test]
    fn 上限含边界且超一字节就拒() {
        assert_eq!(超限说明(0), None);
        assert_eq!(超限说明(单槽字节上限), None, "正好等于上限必须放行");
        let 说明 = 超限说明(单槽字节上限 + 1).expect("超一字节必须拒");
        assert!(
            说明.contains(&(单槽字节上限 + 1).to_string())
                && 说明.contains(&单槽字节上限.to_string()),
            "说明里要同时给出实测字节与上限：{说明}"
        );
        assert!(说明.contains("不截断"), "必须说清为什么不截断：{说明}");
    }
}
