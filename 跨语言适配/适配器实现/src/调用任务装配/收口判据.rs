//! 调用任务装配 · 收口判据 —— **决定结局的两个纯函数**（不碰锁、不碰线程、不碰存储）。
//!
//! 抽出来的理由：这两条规则以前散在 `图驱动` 里，与「进程怎么推图」混在一起，
//! 想单独验证就必须先起线程。现在它们是纯函数，判据直接钉在口径上。
//!
//! # 两条口径
//!
//! 1. **内核收没收到这次完成事件**：只有「节点真离开执行中」才算收到。内核回 `Err`
//!    或回 `Ok` 但节点仍停在执行中，都是**拒收**——那种情况下这次产出不可信。
//! 2. **终态不可逆**：内核判整图成功之后，任何节点级失败读数都不许把结局翻成失败。
//!    成功就是成功；迟到的完成事件只丢弃，不追认、不推翻。

use v1_contract::数据槽;
use v1_dispatch::{调用任务阶段, 调用节点阶段};

use super::图驱动::节点失败;
use super::实例::任务结局;

/// 内核这次到底收没收到完成事件。
///
/// 返回 `(可读说明, 是否拒收)`：收下了就是 `(None, false)`，否则说明必带原因。
/// 判据看的是**调用之后的节点阶段**：内核静默丢弃时返回的是空决策，不报错，
/// 只有阶段没离开「执行中」才暴露得出这件事。
pub(super) fn 内核收下了<T, E: std::fmt::Debug>(
    结果: Result<T, E>,
    调用后阶段: Option<调用节点阶段>,
) -> (Option<String>, bool) {
    match 结果 {
        Ok(_) => {
            if 调用后阶段 == Some(调用节点阶段::执行中) {
                (
                    Some("内核未接受本次完成事件：节点阶段仍停在执行中".to_owned()),
                    true,
                )
            } else {
                (None, false)
            }
        }
        Err(错误) => (
            Some(format!(
                "内核拒绝登记完成事件（{错误:?}）：节点阶段停在执行中"
            )),
            true,
        ),
    }
}

/// 定结局：任务阶段是内核的权威读数，节点级失败读数只在**内核也判失败**时才出声。
///
/// 顺序写死，别改：成功 → 已取消 → 节点失败 → 裸失败 → 还在跑。
/// 为什么成功排最前：内核已经收口成成功，说明每个节点都按真实终态记过账；
/// 此时任何「失败表」条目只可能来自迟到/重复的完成事件——拿它翻盘就是让后到者冒充事实。
pub(super) fn 定结局(
    任务阶段: 调用任务阶段,
    失败表: &std::collections::BTreeMap<String, 节点失败>,
    首槽: 数据槽,
) -> Option<任务结局> {
    if 任务阶段 == 调用任务阶段::成功 {
        return Some(任务结局::成功(首槽));
    }
    if 任务阶段 == 调用任务阶段::已取消 {
        return Some(任务结局::已取消);
    }
    if let Some(失败) = 失败表.values().next() {
        return Some(任务结局::失败 {
            错误: 失败.段位,
            说明: 失败.说明.clone(),
            槽: 首槽,
        });
    }
    if 任务阶段 == 调用任务阶段::失败 {
        return Some(任务结局::失败 {
            错误: None,
            说明: "内核判整图失败，但本层没有节点级失败读数".to_owned(),
            槽: 首槽,
        });
    }
    None
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use std::collections::BTreeMap;

    fn 失败条目(说明: &str) -> 节点失败 {
        节点失败 {
            段位: Some(v1_dispatch::调度错误::扩展执行崩溃),
            说明: 说明.to_owned(),
        }
    }

    #[test]
    fn 内核回成功且节点已离开执行中才算收下() {
        let (说明, 拒收) = 内核收下了(
            Ok::<(), v1_dispatch::调度错误>(()),
            Some(调用节点阶段::成功),
        );
        assert!(!拒收, "节点已离开执行中，必须算收下");
        assert_eq!(说明, None);
    }

    #[test]
    fn 内核回成功但节点仍停在执行中算拒收() {
        let (说明, 拒收) = 内核收下了(
            Ok::<(), v1_dispatch::调度错误>(()),
            Some(调用节点阶段::执行中),
        );
        assert!(拒收, "阶段没动 = 内核静默忽略了这次事件，必须算拒收");
        assert!(说明.unwrap_or_default().contains("执行中"));
    }

    #[test]
    fn 内核回错误算拒收并带上错误() {
        let (说明, 拒收) = 内核收下了(
            Err::<(), _>(v1_dispatch::调度错误::配额用尽),
            Some(调用节点阶段::执行中),
        );
        assert!(拒收);
        let 文 = 说明.unwrap_or_default();
        assert!(文.contains("拒绝登记"), "{文}");
    }

    #[test]
    fn 整图成功后节点级失败读数不许翻盘() {
        let mut 失败表 = BTreeMap::new();
        失败表.insert("迟到节点".to_owned(), 失败条目("迟到完成事件"));
        let 结局 = 定结局(调用任务阶段::成功, &失败表, 数据槽::空槽());
        assert!(
            matches!(结局, Some(任务结局::成功(_))),
            "内核已判成功，失败表里的迟到条目不许把结局翻成失败：{结局:?}"
        );
    }

    #[test]
    fn 整图失败时失败读数带出原始说明() {
        let mut 失败表 = BTreeMap::new();
        失败表.insert("节点一".to_owned(), 失败条目("业务码 2001"));
        let 结局 = 定结局(调用任务阶段::失败, &失败表, 数据槽::空槽());
        match 结局 {
            Some(任务结局::失败 { 说明, .. }) => assert_eq!(说明, "业务码 2001"),
            其他 => panic!("必须是失败：{其他:?}"),
        }
    }

    #[test]
    fn 已取消优先于节点失败读数() {
        let mut 失败表 = BTreeMap::new();
        失败表.insert("节点一".to_owned(), 失败条目("跑完但已取消"));
        let 结局 = 定结局(调用任务阶段::已取消, &失败表, 数据槽::空槽());
        assert!(
            matches!(结局, Some(任务结局::已取消)),
            "取消是调用方要的结论，节点失败读数不改写它：{结局:?}"
        );
    }

    #[test]
    fn 还在跑就还不定结局() {
        let 结局 = 定结局(调用任务阶段::执行中, &BTreeMap::new(), 数据槽::空槽());
        assert!(结局.is_none(), "没到终态不许编结局");
    }

    #[test]
    fn 内核判失败但没节点读数时也要给失败() {
        let 结局 = 定结局(调用任务阶段::失败, &BTreeMap::new(), 数据槽::空槽());
        match 结局 {
            Some(任务结局::失败 { 说明, 错误, .. }) => {
                assert!(说明.contains("内核判整图失败"), "{说明}");
                assert!(错误.is_none());
            }
            其他 => panic!("必须是失败：{其他:?}"),
        }
    }
}
