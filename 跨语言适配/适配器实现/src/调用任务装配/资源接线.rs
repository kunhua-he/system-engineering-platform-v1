//! 调用任务装配 · 资源接线 —— 资源键推导（**只回答「键是什么」**）。
//!
//! # 两条已定口径
//!
//! 1. **四段一起才唯一**：实例 / 提供者 / 代次 / 真实句柄。
//! 2. **图任务路径每个节点一条独属车道**（[`图任务车道键`]）：同一张图里任意两个节点的键都不同。
//!
//! # 为什么没有「提供者试取」回调了
//!
//! 曾经有一份 `提供者试取` + `不给资源` + `提供者凭据`：本意是「问提供者这条资源现在给不给」。
//! 但驱动 `冲刷` **从来不用它** —— 同键怎么排、什么时候放行，驱动按「执行中节点所占的键」
//! 驱动挡一道就定了，问提供者一遍等于问同一个问题的第二遍。**没人调用的口就是垃圾**，已删。
//!
//! # 「等资源」阶段为什么在图任务路径不可达
//!
//! 键里含节点标识 ⇒ 节点之间不共用车道 ⇒ 驱动那道闸永远挡不到人。
//! 内核那一档（`启动节点` 见冲突置「等资源」）留着当**安全网**：真有人把共用键塞进来，
//! 它会让节点停在等资源而不是双启。但要让它有意义，得先有调用方声明「这几个节点抢同一样
//! 东西」—— 协议里没有这个字段，所以不造。真要按能力共用车道，那是加字段那一批的事，
//! 报队位跟着一起做；现在报一个永远为空的字段就是垃圾。

const 图任务提供者: &str = "图任务";

/// 一条资源键。四段**逐段**参与比较：实例号隔开多实例，提供者标识隔开扩展，
/// 代次隔开同一扩展的前后两版，句柄隔开同版里的不同实体。
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct 资源键 {
    pub 实例号: u64,
    pub 提供者标识: String,
    pub 代次: u32,
    pub 句柄: String,
}

impl 资源键 {
    pub fn 推导(实例号: u64, 提供者标识: &str, 代次: u32, 句柄: &str) -> Self {
        Self {
            实例号,
            提供者标识: 提供者标识.to_owned(),
            代次,
            句柄: 句柄.to_owned(),
        }
    }

    /// 键的**文本形态**（留痕、日志与试取回调共用一种写法，不许两处各拼一种）。
    pub fn 键文本(&self) -> String {
        format!(
            "{}/{}/{}/{}",
            self.实例号, self.提供者标识, self.代次, self.句柄
        )
    }

    /// 交给内核资源车道的键表：一条资源键就是车道上的一个闸位。
    ///
    /// 返回 `Vec` 而不是单值，是因为一个节点可能同时占多样资源（图侧就是这么传的）；
    /// 单资源的情形只是**一项**，不是特例分支。
    pub fn 车道键(&self) -> Vec<String> {
        vec![self.键文本()]
    }
}

/// 图任务的节点车道键：**每个节点一条独属车道**。
///
/// 实例号隔开多实例，节点标识隔开图内节点 —— 两段一起保证「同图内任意两节点的键不同」，
/// 这是「不存在同键争用」的来源，不是巧合。
pub fn 图任务车道键(实例号: u64, 节点标识: &str) -> Vec<String> {
    资源键::推导(实例号, 图任务提供者, 0, 节点标识).车道键()
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 四段任一不同就是不同键() {
        let 样本键 = 资源键::推导(1, "提供者", 0, "句柄");
        let 同 = 资源键::推导(1, "提供者", 0, "句柄");
        let 异实例 = 资源键::推导(2, "提供者", 0, "句柄");
        let 异代次 = 资源键::推导(1, "提供者", 1, "句柄");
        let 异句柄 = 资源键::推导(1, "提供者", 0, "别的句柄");
        assert_eq!(样本键, 同, "四段全同才是同一条资源");
        assert_ne!(样本键, 异实例);
        assert_ne!(样本键, 异代次);
        assert_ne!(样本键, 异句柄);
        assert_eq!(样本键.键文本(), "1/提供者/0/句柄");
        assert_eq!(样本键.车道键(), vec!["1/提供者/0/句柄".to_owned()]);
    }

    /// 判据：图任务的车道**节点独属** —— 同图任意两节点键不同，同一节点键稳定。
    /// 这条同时钉住「不存在同键争用 ⇒ 队位没有主体」，别处再想加「排队位次」字段时先来读它。
    #[test]
    fn 图任务车道键节点独属() {
        let 键一 = 图任务车道键(1, "节点一");
        let 键二 = 图任务车道键(1, "节点二");
        assert_ne!(
            键一, 键二,
            "同图两节点不许共用车道（共用就会串行、还谈得上排队）"
        );
        assert_eq!(键一, 图任务车道键(1, "节点一"), "同一节点重复推导必须同键");
        assert_eq!(
            键一,
            vec!["1/图任务/0/节点一".to_owned()],
            "键形态写死，改动等于改契约"
        );
        assert_ne!(键一, 图任务车道键(2, "节点一"), "实例号必须隔开两个实例");
    }
}
