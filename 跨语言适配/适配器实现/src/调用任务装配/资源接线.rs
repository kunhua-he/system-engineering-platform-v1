//! 调用任务装配 · 资源接线 —— 资源键推导 + 提供者试取回调。
//!
//! # 只做两件，不做第三件
//!
//! 1. **推导资源键**：四段一起才唯一 —— 实例 / 提供者 / 代次 / 真实句柄。
//! 2. **给提供者一条试取回调**：问「这一条资源现在能不能给我」。
//!
//! **不另建提供者占用表**：占用与排队由内核 `调用资源车道` 判定（同键先进先出、
//! 异键互不相干）。本件再存一份占用表就是同一事实的第二来源，两处置信必然漂移。
//! 本件只回答「键是什么」，不回答「谁能进」。

/// 一条资源键。四段**逐段**参与比较：实例号隔开多实例，提供者标识隔开扩展，
/// 代次隔开同一扩展的前后两版，句柄隔开同版里的不同实体。
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct 资源键 {
    pub 实例号: u64,
    pub 提供者标识: String,
    pub 代次: u32,
    pub 句柄: String,
}

impl 资源键 {
    pub fn 推导(实例号: u64, 提供者标识: &str, 代次: u32, 句柄: &str) -> Self {
        Self {
            实例号,
            提供者标识: 提供者标识.to_owned(),
            代次,
            句柄: 句柄.to_owned(),
        }
    }

    /// 键的**文本形态**（留痕、日志与试取回调共用一种写法，不许两处各拼一种）。
    pub fn 键文本(&self) -> String {
        format!(
            "{}/{}/{}/{}",
            self.实例号, self.提供者标识, self.代次, self.句柄
        )
    }

    /// 交给内核资源车道的键表：一条资源键就是车道上的一个闸位。
    ///
    /// 返回 `Vec` 而不是单值，是因为一个节点可能同时占多样资源（图侧就是这么传的）；
    /// 单资源的情形只是**一项**，不是特例分支。
    pub fn 车道键(&self) -> Vec<String> {
        vec![self.键文本()]
    }
}

/// 提供者试取的结果：拿到了就给出凭据（凭据里带的就是那条键）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 提供者凭据 {
    pub 资源键: 资源键,
}

/// 提供者试取回调。
///
/// 只回答「这一条资源现在给不给」；**排队与先进先出不在这里**（内核资源车道判）。
/// 返回 `None` = 这一条现在取不到，调度侧把节点留在「等资源」，不当作失败。
pub trait 提供者试取 {
    fn 试取(&self, 键: &资源键) -> Option<提供者凭据>;
}

/// 永远给不出资源的提供者（装配侧没接线时的显式默认：宁可排队，不放行）。
#[derive(Debug, Default)]
pub struct 不给资源;

impl 提供者试取 for 不给资源 {
    fn 试取(&self, _键: &资源键) -> Option<提供者凭据> {
        None
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 四段任一不同就是不同键() {
        let 样本键 = 资源键::推导(1, "提供者", 0, "句柄");
        let 同 = 资源键::推导(1, "提供者", 0, "句柄");
        let 异实例 = 资源键::推导(2, "提供者", 0, "句柄");
        let 异代次 = 资源键::推导(1, "提供者", 1, "句柄");
        let 异句柄 = 资源键::推导(1, "提供者", 0, "别的句柄");
        assert_eq!(样本键, 同, "四段全同才是同一条资源");
        assert_ne!(样本键, 异实例);
        assert_ne!(样本键, 异代次);
        assert_ne!(样本键, 异句柄);
        assert_eq!(样本键.键文本(), "1/提供者/0/句柄");
        assert_eq!(样本键.车道键(), vec!["1/提供者/0/句柄".to_owned()]);
    }

    #[test]
    fn 默认提供者不放行() {
        assert_eq!(不给资源.试取(&资源键::推导(1, "p", 0, "h")), None);
    }
}
