//! 调用任务装配 · 未知判定 —— 什么时候**只是「不知道」**，不是「确认没做成」。
//!
//! # 这一件为什么必须存在
//!
//! 内核的错误枚举已经替两种情况写明了性质，本件只是把那段注释变成判据：
//!
//! - `超时 { 毫秒数 }`：执行方**没在预算内答**，「可能还在跑」；
//! - `扩展执行崩溃`：**已经进扩展**了，「可能已经改了扩展内部状态」。
//!
//! 两者的共同点：既没有成功证据，也没有「没做成」的证据。把这两种记成节点「失败」，
//! 就是拿平台的记账口径替能力宣布结局 —— **猜**。判据表里只放确认过的东西，
//! 所以它们进「未知」，任务收口成「未确认」。
//!
//! # 为什么其余段位不算未知
//!
//! `提供者未载入` / `命令已废止` / `参数个数不符` / `输入形状不符` 都是**执行前**判掉的：
//! 一次都没进扩展，扩展状态一点没动 ⇒ 确认失败。把确认的失败说成未知，同样是失真。

use v1_dispatch::调度错误;

use super::叶子执行::叶子产出;

/// 这次产出算不算「结果未知」。
///
/// 只看段位，不看返回值：协议成功就是成功（那有产出槽为证），失败里只有上面那两种
/// 属于「不知道」。
pub(super) fn 结果未知(产出: &叶子产出) -> bool {
    matches!(
        产出.错误(),
        Some(调度错误::超时 { .. } | 调度错误::扩展执行崩溃)
    )
}

/// 未知节点的说明（回执与落盘共用这一句，不出现两套口径）。
pub(super) fn 说明(节点标识: &str, 原因: Option<&调度错误>) -> String {
    let 缘由 = match 原因 {
        Some(调度错误::超时 { 毫秒数 }) => {
            format!("等到 {毫秒数} 毫秒仍未拿到结果，能力可能仍在执行")
        }
        Some(调度错误::扩展执行崩溃) => {
            "执行体已崩溃，是否已产生副作用无法确认".to_owned()
        }
        _ => "没有任何一方的回报能证明它做成了或没做成".to_owned(),
    };
    format!("节点「{节点标识}」结果未知：{缘由}；平台不下结论，须先核对执行凭据，不自动重发")
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use crate::转发结果;
    use v1_contract::数据槽;

    fn 产出(段位: 调度错误) -> 叶子产出 {
        叶子产出 {
            结果: 转发结果::失败(段位),
            槽: 数据槽::空槽(),
            业务错误码: None,
        }
    }

    #[test]
    fn 超时算未知() {
        assert!(结果未知(&产出(调度错误::超时 { 毫秒数: 120_000 })));
    }

    #[test]
    fn 执行体崩溃算未知() {
        assert!(结果未知(&产出(调度错误::扩展执行崩溃)));
    }

    #[test]
    fn 执行前判掉的失败不算未知() {
        for 段位 in [
            调度错误::配额用尽,
            调度错误::参数个数不符 {
                声明: 1, 实际: 2
            },
            调度错误::输入形状不符 {
                位次: 0,
                声明类型: 4,
                实际类型: 1,
            },
        ] {
            assert!(!结果未知(&产出(段位)), "执行前判掉的失败不许算未知");
        }
    }

    #[test]
    fn 说明带上节点名与缘由() {
        let 文 = 说明("慢节点", Some(&调度错误::超时 { 毫秒数: 5000 }));
        assert!(文.contains("慢节点"), "{文}");
        assert!(文.contains("5000"), "{文}");
        assert!(文.contains("不下结论"), "{文}");
    }
}
