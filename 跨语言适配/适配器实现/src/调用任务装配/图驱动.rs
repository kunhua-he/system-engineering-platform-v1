//! 调用任务装配 · 图驱动 —— 实例内部状态与工作线程循环（调度器就住在这里）。
//!
//! `调度实例.rs` 答「怎么装配、怎么等、怎么停」（对外形状），本件答「线程怎么把图推到底」
//! （对内状态）。混在一件会超 200 行，长文件会把「锁在哪、谁改阶段」埋进噪声里。

use std::collections::{BTreeMap, VecDeque};
use std::sync::{Arc, Condvar, Mutex, MutexGuard};
use std::time::Instant;

use v1_contract::数据槽;
use v1_dispatch::{
    节点完成事件, 调度决策, 调度错误, 调用任务调度器, 调用任务阶段, 调用状态存储回调, 调用节点阶段,
};

use super::任务跟踪::任务跟踪表;
use super::叶子执行::{叶子产出, 叶子执行口, 叶子请求};
use super::存储::任务存储;
use super::实例::{任务结局, 节点素材, 装配错误};
use super::收口判据::{内核收下了, 定结局};

pub(super) struct 工作项 {
    节点标识: String,
    执行批号: u64,
    请求: 叶子请求,
}

/// 一个节点**真跑过**的区间与代次（回执里 `开始微秒 / 结束微秒 / 执行批号` 三格的源）。
///
/// 三项都只在**真起跑**之后才存在：没起跑的节点在时刻表里根本没有这一项 ⇒ 回执里
/// 三格一个都不出现。这样「没发生的事」不会被写成 `0` 或 `null` 冒充发生过。
///
/// 时刻取**单调钟**（[`Instant`]），零时 = 本任务的提交时刻：系统时间会被校时前后跳，
/// 拿它算区间会造出「结束早于开始」的假证据。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 节点时刻 {
    /// 真起跑那一刻（零时起的微秒数）。
    pub 开始微秒: u64,
    /// 执行收尾那一刻；还在跑就是 `None`。
    pub 结束微秒: Option<u64>,
    /// 真执行的那一代批号（内核启动节点时发的同一个号，不另发）。
    pub 执行批号: u64,
}

/// 驱动侧的一条节点失败读数。
///
/// `段位` 为 `None` 表示**业务失败**（扩展把失败写在返回槽里，协议层照旧成功）：
/// 那种失败没有调度段位可用，如实留空，不拿一个不相干的段位顶上；
/// 说明里带着扩展回的 4 位业务码。
pub(super) struct 节点失败 {
    pub(super) 段位: Option<调度错误>,
    pub(super) 说明: String,
}

pub(super) struct 实例状态 {
    pub(super) 调度器: 调用任务调度器,
    pub(super) 素材表: BTreeMap<String, 节点素材>,
    pub(super) 待执行: VecDeque<工作项>,
    pub(super) 槽表: BTreeMap<String, 数据槽>,
    pub(super) 失败表: BTreeMap<String, 节点失败>,
    /// 结果未知的节点：既没成功证据也没失败证据（超时、执行体崩溃）。
    ///
    /// 与 `失败表` **并列而不是合并**：合并就等于替能力宣布结局（猜）。
    /// 收口时这一表非空即整图「未确认」，除非另有确认失败。
    pub(super) 未知表: BTreeMap<String, (String, 调度错误)>,
    pub(super) 结局: Option<任务结局>,
    pub(super) 停止: bool,
    /// 取消请求：**挂在实例上**（不落模块 static —— 同进程两张图必须互不可见）。
    pub(super) 请求取消: bool,
    pub(super) 记录: 任务存储,
    pub(super) 跟踪: 任务跟踪表,
    /// 本任务零时（单调钟）：`开始微秒 / 结束微秒` 的基准点，不用系统时间。
    pub(super) 零时: Instant,
    /// 逐节点的真跑区间与代次。**只有起跑过的节点才有一项**（没起跑就没有，不编 0）。
    pub(super) 时刻表: BTreeMap<String, 节点时刻>,
}

/// 单调钟读数 → 本任务零时起的微秒数（溢出只会出现在三百年的任务上，按上限截住）。
fn 零时微秒(零时: Instant) -> u64 {
    u64::try_from(零时.elapsed().as_micros()).unwrap_or(u64::MAX)
}

impl 实例状态 {
    /// 把可启动的节点各试启动一次；启动成功的进待执行队。
    ///
    /// **同键先在闸外排队**：内核 `启动节点` 只认「就绪」，冲突递进去会被置成「等资源」，
    /// 而内核没有「等资源 → 就绪」的口（冻结件不补）⇒ 那个节点永远起不来。故驱动按
    /// 「执行中节点所占的键」挡一道，冲突的留在**就绪**，占用者收口后按图序再来 ——
    /// 这就是同键先进先出。闸只是执行面的**视图**（由阶段现算），不是第二份占用表。
    pub(super) fn 冲刷(&mut self) -> Result<(), 装配错误> {
        // 取消挡板：收到取消请求后**一个节点都不再启动**。
        //
        // 为什么挡在这里而不是逐节点拦：内核 `启动节点` 只认「就绪」，本驱动是唯一启动口
        // （`冲刷` 覆盖提交与每次完成后的重试）⇒ 一个判断就够，不会漏启动路径。
        // 已经在「执行中」的节点（含已进待执行队的那批）照实跑完并照实收口 ——
        // 取消只**标记**它们，不伪造「已取消」（跃迁表里执行中 → 已取消虽合法，
        // 但那是执行体真退场之后的事，不是驱动能替它宣布的）。
        if let Some(错误) = self.记录.故障() { return Err(装配错误::存储错误(错误)); }
        if self.请求取消 {
            return Ok(());
        }
        let 标识表: Vec<String> = self.素材表.keys().cloned().collect();
        let mut 占用键: BTreeMap<String, usize> = BTreeMap::new();
        for 标识 in &标识表 {
            if self.调度器.节点阶段(标识) != Some(调用节点阶段::执行中) {
                continue;
            }
            for 键 in &self.素材表[标识].资源键 {
                *占用键.entry(键.clone()).or_insert(0) += 1;
            }
        }
        for 标识 in 标识表 {
            if self.调度器.节点阶段(&标识) != Some(调用节点阶段::就绪) {
                continue;
            }
            let 资源键 = self.素材表[&标识].资源键.clone();
            if 资源键.iter().any(|键| 占用键.contains_key(键)) {
                continue;
            }
            for 键 in &资源键 {
                *占用键.entry(键.clone()).or_insert(0) += 1;
            }
            let 决策 = self
                .调度器
                .启动节点(&标识, 资源键)
                .map_err(装配错误::调度器错误)?;
            let Some(调度决策::启动 { 执行批号, .. }) = 决策 else {
                continue;
            };
            let 请求 = self.素材表[&标识].请求.clone();
            let 工作 = 工作项 { 节点标识: 标识.clone(), 执行批号, 请求 };
            // 先在实例锁内登记与排队；持锁期间工作线程不能认领，持久意图失败时可确定尚未入叶子。
            self.跟踪.登记生成中(&标识, 执行批号);
            self.待执行.push_back(工作);
            self.记录.保存节点状态(&标识, 调用节点阶段::执行中, 执行批号)
                .map_err(装配错误::存储错误)?;

        }
        Ok(())
    }

    /// 一次完成：内核接受 → 登记跟踪与结果 → 落记录 → 重试启动 → 收口。
    ///
    /// 成败判据是 [`叶子产出::节点成功`]（协议成功 **且** 返回槽不是错误槽），
    /// 不是协议层的 `成功` —— 扩展回业务错误码同样是节点失败。
    pub(super) fn 记账完成(&mut self, 工作: &工作项, 产出: 叶子产出) -> bool {
        self.记账完成_带判据(工作, 产出, true)
    }

    /// 重入被拒时的记账：**一次都没进扩展**，所以是确认失败，不许算未知。
    pub(super) fn 记账未执行(&mut self, 工作: &工作项) -> bool {
        let 产出 = 叶子产出 {
            结果: crate::转发结果::失败(调度错误::扩展执行崩溃),
            槽: 数据槽::空槽(),
            业务错误码: None,
        };
        self.记账完成_带判据(工作, 产出, false)
    }

    /// 持久故障使工作在进入叶子前终止；用内核接受边界闭合，不伪造能力失败或未知。
    fn 记账存储未执行(&mut self, 工作: &工作项) {
        let 事件 = 节点完成事件 { 节点标识: 工作.节点标识.clone(), 执行批号: 工作.执行批号, 成功: false };
        if !matches!(self.报完成(事件.clone()), Ok(true)) { return; }
        self.跟踪.登记完成(&事件);
        self.失败表.insert(工作.节点标识.clone(), 节点失败 {
            段位: None, 说明: "持久保存故障阻止节点进入叶子；确认未执行".to_owned(),
        });
    }

    /// 只收束尚未交给叶子的工作；已被工作线程认领的节点继续等待真实退场。
    pub(super) fn 收束存储故障(&mut self) {
        self.请求取消 = true;
        while let Some(工作) = self.待执行.pop_front() { self.记账存储未执行(&工作); }
        while let Some(标识) = self.素材表.keys().find(|标识| self.调度器.节点阶段(标识) == Some(调用节点阶段::就绪)).cloned() {
            let 资源键 = self.素材表[&标识].资源键.clone();
            let Ok(Some(调度决策::启动 { 执行批号, .. })) = self.调度器.启动节点(&标识, 资源键) else { break; };
            let 工作 = 工作项 { 节点标识: 标识.clone(), 执行批号, 请求: self.素材表[&标识].请求.clone() };
            self.跟踪.登记生成中(&标识, 执行批号);
            self.记账存储未执行(&工作);
        }
        self.收口();
    }

    /// 真正取得叶子执行权后才记录开始时刻；排队未执行节点没有时刻。
    pub(super) fn 记开始时刻(&mut self, 工作: &工作项) {
        self.时刻表.insert(工作.节点标识.clone(), 节点时刻 {
            开始微秒: 零时微秒(self.零时), 结束微秒: None, 执行批号: 工作.执行批号,
        });
    }

    fn 记账完成_带判据(
        &mut self, 工作: &工作项, 产出: 叶子产出, 允许未知: bool
    ) -> bool {
        let 节点成功 = 产出.节点成功();
        // 结果未知：拿不到任何一方的回报（超时/执行体崩溃）。**不写失败表、记录写未知** ——
        // 内核那格仍会记「失败」（它只有成功/失败两格，且这是冻结件），
        // 但平台对外一律报未知：替能力宣布结局就是猜。
        let 段位 = 产出.错误();
        let 未知 = 允许未知 && !节点成功 && super::未知判定::结果未知(&产出);
        let 事件 = 节点完成事件 {
            节点标识: 工作.节点标识.clone(),
            执行批号: 工作.执行批号,
            成功: 节点成功,
        };
        // 接受是投影的唯一提交边界；重复与迟到空决策严格零写。
        match self.报完成(事件.clone()) {
            Ok(true) => {}
            Ok(false) => return false,
            Err(说明) => {
                eprintln!("内部一致性异常：{说明}");
                return false;
            }
        }
        self.跟踪.登记完成(&事件);
        if let Some(时刻条目) = self.时刻表.get_mut(&工作.节点标识)
            && 时刻条目.执行批号 == 工作.执行批号
        {
            时刻条目.结束微秒 = Some(零时微秒(self.零时));
        }
        if 未知 {
            self.未知表.insert(
                工作.节点标识.clone(),
                (
                    super::未知判定::说明(&工作.节点标识, 段位.as_ref()),
                    段位.unwrap_or(调度错误::扩展执行崩溃),
                ),
            );
        }
        if !节点成功 && !未知 {
            self.失败表.insert(
                工作.节点标识.clone(),
                节点失败 {
                    // 业务失败没有段位（`None`，码在说明里）；协议失败用它的段位。
                    段位: 产出.错误(),
                    说明: 产出.失败说明(),
                },
            );
        }
        self.槽表.insert(工作.节点标识.clone(), 产出.槽);
        // 记录里写什么，对外就报什么：未知写未知，其余照内核。内核那格只有成功/失败，
        // 把它当唯一口径就会把「不知道」写成「失败」。
        let 记录阶段 = if 未知 {
            Some(调用节点阶段::未知)
        } else {
            self.调度器.节点阶段(&工作.节点标识)
        };
        if let Some(阶段) = 记录阶段 {
            let _ = self.记录.保存节点状态(&工作.节点标识, 阶段, 工作.执行批号);
        }
        if matches!(self.冲刷(), Err(装配错误::存储错误(_))) { self.收束存储故障(); }
        self.收口();
        true
    }

    /// 空决策是幂等忽略；真正错误另报内部一致性异常，不记能力失败。
    fn 报完成(&mut self, 事件: 节点完成事件) -> Result<bool, String> {
        let 标识 = 事件.节点标识.clone();
        let 决策 = self
            .调度器
            .处理完成(事件)
            .map_err(|错误| format!("内核拒绝登记完成事件：{错误:?}"))?;
        if 决策.is_empty() {
            return Ok(false);
        }
        let (说明, 拒收) = 内核收下了(
            Ok::<_, v1_dispatch::调度器错误>(决策),
            self.调度器.节点阶段(&标识),
        );
        if 拒收 {
            return Err(说明.unwrap_or_default());
        }
        Ok(!拒收)
    }

    /// 收口：跟踪表没有「生成中」且任务到终态 ⇒ 定结局（生成中一律不算成功）。
    ///
    /// 判定本身在 [`收口判据::定结局`]（纯函数，判据直接钉口径）；本件只管取出三样输入。
    pub(super) fn 收口(&mut self) {
        if self.结局.is_some() || !self.跟踪.全部已收口() {
            return;
        }
        let Some(结局) = 定结局(
            self.调度器.任务阶段(),
            &self.失败表,
            &self.未知表,
            self.首个槽(),
        ) else {
            return;
        };
        let 阶段 = match 结局 {
            任务结局::成功(_) => 调用任务阶段::成功,
            任务结局::失败 { .. } => 调用任务阶段::失败,
            任务结局::已取消 => 调用任务阶段::已取消,
            任务结局::未确认 { .. } => 调用任务阶段::未确认,
        };
        if let Err(错误) = self.记录.设置任务阶段(阶段) {
            self.结局 = Some(任务结局::未确认 { 未知节点: Vec::new(), 说明: format!("持久保存失败：{错误:?}"), 段位: None });
            return;
        }
        self.结局 = Some(结局);
    }

    fn 首个槽(&self) -> 数据槽 {
        self.槽表
            .values()
            .next()
            .copied()
            .unwrap_or_else(数据槽::空槽)
    }
}

/// 工作线程循环：取项 → 执行叶子（锁外）→ 记账 → 唤醒。
pub(super) fn 工作循环(
    实例: &Arc<(Mutex<实例状态>, Condvar)>, 执行口: &dyn 叶子执行口
) {
    loop {
        let Some(工作) = 取出一项(实例) else {
            return;
        };
        // 锁已放：叶子在锁外跑（一个慢叶子不阻塞别的线程登记）。
        // 守卫拿不到 = 本线程已在本实例的叶子里（嵌套提交被拒）：**一次都没进扩展**，
        // 所以走 `记账未执行`（确认失败），不许借「扩展执行崩溃」这个段位混成「未知」。
        let 守卫 = 执行口.标记().进入();
        let 产出 = if 守卫.is_some() {
            { 取锁(实例).记开始时刻(&工作); }
            Some(执行口.执行(&工作.请求))
        } else { None };
        {
            let mut 状态 = 取锁(实例);
            match 产出 {
                Some(产出) => {
                    if 状态.记账完成(&工作, 产出) {
                        执行口.接受产出(&工作.请求, &产出);
                    }
                }
                None => {
                    状态.记账未执行(&工作);
                }
            }
        }
        实例.1.notify_all();
    }
}

/// 停下时取出一项：没有工作即是「停机」信号。
fn 取出一项(实例: &Arc<(Mutex<实例状态>, Condvar)>) -> Option<工作项> {
    let mut 状态 = 取锁(实例);
    while 状态.待执行.is_empty() && !状态.停止 {
        状态 = 实例.1.wait(状态).unwrap_or_else(|中毒| 中毒.into_inner());
    }
    if 状态.记录.故障().is_some() { return None; }
    状态.待执行.pop_front()
}

/// 取锁：锁中毒也拿回来（调度路径不因一次 panic 永久不可用）。
pub(super) fn 取锁(实例: &Arc<(Mutex<实例状态>, Condvar)>) -> MutexGuard<'_, 实例状态> {
    实例.0.lock().unwrap_or_else(|中毒| 中毒.into_inner())
}

