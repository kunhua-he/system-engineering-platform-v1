//! 调用任务装配 · 任务跟踪 —— 异步任务（如「生成中」）的查询 / 取消 / 释放接线。
//!
//! # 一条硬判据
//!
//! **「生成中」不算节点成功**：异步任务交出的是「还在跑」，不是「跑完了」。
//! 把生成中当成功，等于让调用方拿着一个没有结果的槽去用 ——
//! [`任务跟踪表::算成功`] 与 [`任务跟踪表::全部已收口`] 就是这条判据的两个落点。
//!
//! # 与内核的关系
//!
//! 本件实现内核的 [`异步跟踪回调`]：`调度实例` 在执行前登记「生成中」，完成后登记事件。
//! 表**按实例一张**（一个任务一张表），不落进程级全局。

use std::collections::BTreeMap;

use v1_dispatch::{异步跟踪回调, 节点完成事件};

/// 跟踪项的阶段。**四态**，没有第五个。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 跟踪阶段 {
    /// 已发出、还没回来（异步任务在跑）。
    生成中,
    /// 回来了，拿到结果。
    已完成,
    /// 回来了，但是失败。
    已失败,
    /// 被取消：调用方不再等结果。
    已取消,
}

/// 跟踪错误。**结构化**：查不到项、项已释放都要能分得开。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 跟踪错误 {
    未知节点(String),
    状态不可取消(跟踪阶段),
}

#[derive(Debug, Clone, Copy)]
struct 跟踪项 {
    阶段: 跟踪阶段,
    执行批号: u64,
}

/// 一个任务的跟踪表：任务标识 + 逐节点跟踪项。
#[derive(Debug)]
pub struct 任务跟踪表 {
    节点项: BTreeMap<String, 跟踪项>,
}

impl 任务跟踪表 {
    pub fn 新建() -> Self {
        Self {
            节点项: BTreeMap::new(),
        }
    }

    /// 登记「生成中」（异步任务发出后立刻调）。
    pub fn 登记生成中(&mut self, 节点标识: &str, 执行批号: u64) {
        self.节点项.insert(
            节点标识.to_owned(),
            跟踪项 {
                阶段: 跟踪阶段::生成中,
                执行批号,
            },
        );
    }

    /// 查询一项的阶段（查不到给 `None`，不编一个默认值）。
    pub fn 查询(&self, 节点标识: &str) -> Option<跟踪阶段> {
        self.节点项.get(节点标识).map(|项| 项.阶段)
    }

    /// 取消：调用方不再等这一项。已收口的项不许取消（结果已经在手里，取消是假动作）。
    pub fn 取消(&mut self, 节点标识: &str) -> Result<(), 跟踪错误> {
        let Some(项) = self.节点项.get_mut(节点标识) else {
            return Err(跟踪错误::未知节点(节点标识.to_owned()));
        };
        if !matches!(项.阶段, 跟踪阶段::生成中) {
            return Err(跟踪错误::状态不可取消(项.阶段));
        }
        项.阶段 = 跟踪阶段::已取消;
        Ok(())
    }

    /// 释放一项的跟踪痕迹（结果已交给调用方之后调）。返回「原本在不在」。
    pub fn 释放(&mut self, 节点标识: &str) -> bool {
        self.节点项.remove(节点标识).is_some()
    }

    /// 登记完成（内核事件进来）。**批号对不上就丢弃**（重放不覆盖新一轮）。
    pub fn 登记完成(&mut self, 事件: &节点完成事件) {
        let Some(项) = self.节点项.get_mut(&事件.节点标识) else {
            return;
        };
        // 只从「生成中」转出：已收口的项重放不再改结论（重放不双计）。
        if 项.执行批号 != 事件.执行批号 || !matches!(项.阶段, 跟踪阶段::生成中)
        {
            return;
        }
        项.阶段 = if 事件.成功 {
            跟踪阶段::已完成
        } else {
            跟踪阶段::已失败
        };
    }

    /// 还有没有「生成中」的项。**有就说明任务没跑完**。
    pub fn 全部已收口(&self) -> bool {
        !self
            .节点项
            .values()
            .any(|项| matches!(项.阶段, 跟踪阶段::生成中))
    }

    /// 这一项**算不算成功**：「生成中」不算，取消也不算 —— 只有「已完成」算。
    pub fn 算成功(&self, 节点标识: &str) -> bool {
        matches!(self.查询(节点标识), Some(跟踪阶段::已完成))
    }
}

impl 异步跟踪回调 for 任务跟踪表 {
    type 错误 = 跟踪错误;

    fn 登记执行(&mut self, 节点标识: &str, 执行批号: u64) -> Result<(), Self::错误> {
        self.登记生成中(节点标识, 执行批号);
        Ok(())
    }

    fn 登记完成(&mut self, 事件: &节点完成事件) -> Result<(), Self::错误> {
        任务跟踪表::登记完成(self, 事件);
        Ok(())
    }
}
