//! 调用任务装配 · 叶子执行 —— **唯一**可进原池/调度核心的业务叶子。
//!
//! # 为什么只许一处
//!
//! 调用路径上「真正进扩展」的入口全平台只许一个：这里。`调度实例` 把工作项交给
//! [`叶子执行口`]，实现体在 [`适配器叶子`] 里，落的还是原来那一处
//! [`v1_dispatch::调用命令`]（判定顺序、配额、超时口径一份不改）。
//!
//! # 防递归标记
//!
//! 叶子执行期间**禁止再提交任务图**：那会把调用路径套成环（一次调用再提交一张图，
//! 图里再提交……）。标记由**叶子实例持有** —— 一个线程标识集合（`叶子标记`），
//! [`叶子标记::在叶子内`] 给提交口判。被判到不是崩溃 —— 提交口拒掉，叶子回 `扩展执行崩溃` 段位
//! （既有段位里唯一表示「已进扩展且结果不可信」的，不新增段位、不改内核）。
//!
//! # 不持宿主
//!
//! [`适配器叶子`] 持的是**执行快照**（路由表深拷出来的那份 `适配器`，见
//! `候选发布.rs` 的 `Clone`），不是宿主实例本身 ⇒ 与 `调度实例` 之间不构成 `Arc` 环。

use std::collections::HashSet;
use std::sync::{Arc, Mutex};
use std::thread::ThreadId;

use v1_contract::数据槽;
use v1_dispatch::调度错误;

use crate::{转发结果, 适配器};

use super::实例::{任务结局, 执行单次, 节点素材, 装配错误};

/// 叶子标记：哪些线程此刻正在叶子内。**由实例持有**，不是模块级 static
/// —— 边界纪律要求接缝里 0 状态，状态只能挂在被拥有的实例上。
#[derive(Debug, Default)]
pub struct 叶子标记 {
    在跑: Arc<Mutex<HashSet<ThreadId>>>,
}

impl Clone for 叶子标记 {
    /// 共享同一份在跑集合：执行快照（`Clone` 出的适配器）与主实例共用一把标记
    /// —— 否则每次快照都换一把新标记，递归就漏判了。
    fn clone(&self) -> Self {
        Self {
            在跑: Arc::clone(&self.在跑),
        }
    }
}

impl 叶子标记 {
    pub fn 新建() -> Self {
        Self::default()
    }

    /// 本线程此刻是否在叶子内。提交口用它挡递归。
    pub fn 在叶子内(&self) -> bool {
        let 集 = self.在跑.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        集.contains(&std::thread::current().id())
    }

    /// 进入叶子。已在本实例的叶子里 ⇒ `None`（嵌套进入是编程错误，调用方据此拒绝）。
    pub fn 进入(&self) -> Option<叶子守卫<'_>> {
        let 本线程 = std::thread::current().id();
        {
            let mut 集 = self.在跑.lock().unwrap_or_else(|中毒| 中毒.into_inner());
            if !集.insert(本线程) {
                return None;
            }
        }
        Some(叶子守卫 {
            标记: self,
            线程: 本线程,
        })
    }

    /// 此刻在叶子内的线程数（观测用）。
    pub fn 在跑线程数(&self) -> usize {
        self.在跑
            .lock()
            .unwrap_or_else(|中毒| 中毒.into_inner())
            .len()
    }
}

/// 叶子的作用域守卫：`进入` 得 `Some`，`Drop` 时退出本线程。
pub struct 叶子守卫<'a> {
    标记: &'a 叶子标记,
    线程: ThreadId,
}

impl Drop for 叶子守卫<'_> {
    fn drop(&mut self) {
        let mut 集 = self
            .标记
            .在跑
            .lock()
            .unwrap_or_else(|中毒| 中毒.into_inner());
        集.remove(&self.线程);
    }
}

/// 一次叶子的请求：**自足**（节点标识 · 执行批号 · 编号 · 入参快照）。
///
/// 入参是**值快照**（`数据槽` 是定长值）：工作项跨线程时不必回借调用方的栈，
/// 也不持有任何宿主句柄。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 叶子请求 {
    pub 节点标识: String,
    pub 执行批号: u64,
    pub 编号: u32,
    pub 入参: Vec<数据槽>,
}

/// 叶子的产出：结果段位 + 执行函数写出的那个槽。
///
/// 槽跟着结果一起交回，调用口原样写回调用方的返回槽 —— **成功失败两条路的槽语义与
/// 原路逐字一致**（预执行失败是空槽，执行后失败是执行方留下的那半个值）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 叶子产出 {
    pub 结果: 转发结果,
    pub 槽: 数据槽,
}

impl 叶子产出 {
    pub fn 成功(&self) -> bool {
        matches!(self.结果, 转发结果::成功(_))
    }

    pub fn 错误(&self) -> Option<调度错误> {
        match self.结果 {
            转发结果::成功(_) => None,
            转发结果::失败(段位) => Some(段位),
        }
    }
}

/// 叶子执行口：调度实例只认这一条口，具体是谁由装配侧给。
pub trait 叶子执行口: Send + Sync {
    fn 执行(&self, 请求: &叶子请求) -> 叶子产出;

    /// 本条口所属的防递归标记（由实例持有；调度实例提交前问它）。
    fn 标记(&self) -> &叶子标记;
}

/// 真叶子：持执行快照，落原池调度核心。
pub struct 适配器叶子 {
    快照: 适配器,
    标记: 叶子标记,
}

impl 适配器叶子 {
    pub fn 由快照(快照: 适配器, 标记: 叶子标记) -> Self {
        Self { 快照, 标记 }
    }
}

impl 叶子执行口 for 适配器叶子 {
    fn 执行(&self, 请求: &叶子请求) -> 叶子产出 {
        执行原始池(&self.快照, 请求.编号, &请求.入参)
    }

    fn 标记(&self) -> &叶子标记 {
        &self.标记
    }
}

/// 原 `调用能力带追踪` 的执行体（**纯搬家**：跨进程域 → 原池调度核心）。
///
/// 追踪号、在途引用、留痕**不在这里**：那三样属于调用入口（追踪号必须与应答同号），
/// 留在 `适配器定义.rs`。本函数只做「把调用交给内核」，一次不多一次不少。
pub(crate) fn 执行原始池(
    快照: &适配器, 编号: u32, 入参: &[数据槽]
) -> 叶子产出 {
    let 号值 = v1_contract::能力号::构造(编号);
    let mut 槽 = 数据槽::空槽();
    #[cfg(unix)]
    let 跨进程读数 = 快照.调用跨进程(号值, 入参, &mut 槽);
    #[cfg(not(unix))]
    let 跨进程读数: Option<转发结果> = None;
    let 结果 = match 跨进程读数 {
        Some(转发值) => 转发值,
        None => {
            let 项表 = 快照.取注册表(号值);
            // SAFETY: `槽` 是本函数独占的可写槽；`入参` 由调用方按契约填好。
            let 关口结果 = unsafe {
                v1_dispatch::调用命令(项表, &*快照.账本, 号值, 入参, &mut 槽 as *mut 数据槽)
            };
            match 关口结果 {
                v1_dispatch::调用结果::成功 => 转发结果::成功(槽),
                v1_dispatch::调用结果::失败(失败值) => 转发结果::失败(失败值),
            }
        }
    };
    叶子产出 { 结果, 槽 }
}

/// 单能力 → 单节点图 → 调度器 → 同步等结局。
///
/// 归一化只在这里：**一次调用就是一张一格图**（无依赖 ⇒ 无跳过来源、无并行分支）。
/// 装配层自身的错误映射到既有段位，不新增段位（内核与契约都不许改）：
/// - 等超时 ⇒ `调度错误::超时`（毫秒数取内核唯一那份口径）；
/// - 其余装配错误（含「叶子内再提交」被拒）⇒ `调度错误::扩展执行崩溃`
///   —— 这是既有段位里唯一表示「已进扩展且结果不可信」的。
pub fn 执行单能力(
    快照: 适配器,
    标记: 叶子标记,
    编号: u32,
    入参: &[数据槽],
    实例号: u64,
) -> 任务结局 {
    let 请求 = 叶子请求 {
        节点标识: "单能力".to_owned(),
        执行批号: 0,
        编号,
        入参: 入参.to_vec(),
    };
    let 资源键 = super::资源接线::资源键::推导(实例号, "原池", 0, &编号.to_string());
    let 素材 = 节点素材::单能力(请求, 资源键.车道键());
    let 执行口: std::sync::Arc<dyn 叶子执行口> =
        std::sync::Arc::new(适配器叶子::由快照(快照, 标记));
    执行单次(
        vec![素材],
        执行口,
        "单能力调用",
        crate::调用任务装配::等待时限(),
    )
    .unwrap_or_else(|错误| 任务结局::失败 {
        错误: 装配错误段位(&错误),
        槽: 数据槽::空槽(),
    })
}

fn 装配错误段位(错误: &装配错误) -> 调度错误 {
    match 错误 {
        装配错误::任务超时 => 调度错误::超时 {
            毫秒数: v1_dispatch::单项超时毫秒,
        },
        _ => 调度错误::扩展执行崩溃,
    }
}
