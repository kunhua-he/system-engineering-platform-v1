#[test]
fn 同域重复登记不同部署参数结构化拒() {
    // G1 单次语义：域运行中再给一份**不同**的部署参数 ⇒ 结构化拒
    // （部署表不动、旧进程继续服务）。
    let 域池 = 进程池::创建(进程池配置::default());
    let 标识 = 造标识(6);
    let (程序, 启动参数) = 慢进程();
    域池.保证域在(&标识, 程序, &启动参数).unwrap();
    // 同一份参数重复登记 ⇒ 幂等 Ok。
    assert_eq!(域池.保证域在(&标识, 程序, &启动参数), Ok(()));
    // 不同参数（换了启动参数）⇒ 拒；旧进程继续服务、不新增域。
    let 别的参数 = vec![String::from("-c"), String::from("sleep 6")];
    assert_eq!(域池.保证域在(&标识, 程序, &别的参数), Err(进程池错误::部署参数不符));
    assert_eq!(域池.已建域数(), 1, "被拒的登记不新增域");
}

