#[test]
fn 同域重复登记不同部署参数结构化拒() {
    // G1 单次语义：域运行中再给一份**不同**的部署参数 ⇒ 结构化拒
    // （部署表不动、旧进程继续服务）。
    let mut 域池 = 进程池::新建(进程池配置::default());
    let 标识 = 造标识(6);
    let (程序, 启动参数) = 慢进程();
    域池.保证域在(&标识, 程序, &启动参数).unwrap();
    // 同一份参数重复登记 ⇒ 幂等 Ok。
    assert_eq!(域池.保证域在(&标识, 程序, &启动参数), Ok(()));
    // 不同参数（换了启动参数）⇒ 拒；旧进程继续服务、不新增域。
    let 别的参数 = vec![String::from("-c"), String::from("sleep 6")];
    assert_eq!(域池.保证域在(&标识, 程序, &别的参数), Err(进程池错误::部署参数不符));
    assert_eq!(域池.已建域数(), 1, "被拒的登记不新增域");
}

#[test]
fn 移除一域摘表并回收进程() {
    // C4：移除一域 = 摘域格 + 杀进程组（与「击杀」不同：击杀留格）。
    let mut 域池 = 进程池::新建(进程池配置::default());
    let 标识 = 造标识(7);
    let (程序, 启动参数) = 慢进程();
    域池.保证域在(&标识, 程序, &启动参数).unwrap();
    assert!(域池.移除一域(&标识), "有这域 ⇒ 真摘");
    assert!(!域池.含域(&标识), "移除后域格摘掉");
    assert_eq!(域池.已建域数(), 0);
    assert!(!域池.移除一域(&标识), "再移除 ⇒ false（不假装）");
}

/// 造一个**已连好通道的空域**（对端是本进程内一条 `UnixStream`，不拉真子进程）：
/// 发送侧那支只需「有一个域 + 一条真通道」，对端谁答不重要 —— 本件只管发。
fn 造发送侧域(实例号: u64) -> (进程池, 执行域标识, UnixStream) {
    let (宿主端, 对端) = UnixStream::pair().unwrap();
    let 域池 = 进程池::新建(进程池配置::default());
    let 标识 = 造标识(实例号);
    let (程序, 启动参数) = 慢进程();
    let 部署 = crate::进程调用::域部署 { 启动程序: String::from(程序), 启动参数 };
    域池.收下已连域(标识.clone(), 宿主端, 部署).unwrap();
    (域池, 标识, 对端)
}

/// 一条 3 秒的测试预算（发一条大帧要跨多轮写，200 毫秒不够）。
fn 造长预算() -> crate::进程帧::调用帧预算 {
    crate::进程帧::调用帧预算::创建(Instant::now() + Duration::from_millis(3000)).unwrap()
}

#[test]
fn 发送侧超单帧上限结构化过大() {
    // ★ 发送侧**先判长度再复制**：超过单帧上限的待发载荷当场结构化拒，
    //   不先 `to_vec()` 复制一整块再让帧层拒（旧形状：大载荷白复制一次，还被误报成通道错）。
    //   上界**只引用** `crate::进程帧::单帧载荷上限` —— 另写一个数就是第二套口径。
    let (域池, 标识, 对端) = 造发送侧域(8);
    assert!(域池.含域(&标识), "空域要真登记进池");
    let 句柄 = 域池.取域句柄(&标识).unwrap();
    let 待发载荷 = vec![7u8; crate::进程帧::单帧载荷上限 + 1];
    let 发送回执 =
        句柄.发一调用帧按预算(NonZeroU64::new(1).unwrap(), &待发载荷, &mut 造长预算());
    drop(对端);
    assert_eq!(发送回执, Err(进程池错误::载荷过大), "超上限必须结构化拒，不当通道错报");
}

#[test]
fn 发送侧恰好单帧上限不判过大() {
    // 边界正样本：长度**正好**等于上限不许被判成 `载荷过大` —— 防把守卫写成 `>=`（那会误伤合法上界）。
    // 最小构造：对端当场关掉 ⇒ 发送必报别的错（通道断开 / 预算耗尽），但**不许**是 `载荷过大`。
    // 这样不依赖对端读走多少字节，也不养排空线程（通道生命周期不是本样本要验的事）。
    let (域池, 标识, 对端) = 造发送侧域(9);
    assert!(域池.含域(&标识));
    let 句柄 = 域池.取域句柄(&标识).unwrap();
    drop(对端);
    let 待发载荷 = vec![7u8; crate::进程帧::单帧载荷上限];
    let 发送回执 =
        句柄.发一调用帧按预算(NonZeroU64::new(2).unwrap(), &待发载荷, &mut 造长预算());
    assert!(发送回执 != Err(进程池错误::载荷过大), "恰好等于上限不许判过大：{发送回执:?}");
}
