#[test]
fn 读不出读数不声称回落() {
    // 口径：`进程组 = None`（本平台读不出）⇒ **不**能说「已回落」——
    // 把不可判说成零占用，正是本口要防的那种假绿。
    let 不可判 = 域资源读数 { 实例代次: 7, 在跑: false, 进程组: None };
    assert!(!不可判.已回落(), "不可判不许当零占用");
    assert!(域资源读数 { 进程组: Some(Default::default()), ..不可判 }.已回落());
}

#[test]
fn 活着域读数为真且非零() {
    // **反向样本**：把读数口写成恒零（缺口未修时的等价形态）⇒ 本样本当场红。
    // 本样本是「读数真读了内核」的唯一凭据 —— 不看进程杀没杀。
    let 执行池 = 进程池::创建(进程池配置::default());
    let 标识 = 造标识(32);
    let (程序, 启动参数) = 带孙进程();
    执行池.保证域在(&标识, 程序, &启动参数).unwrap();
    let 读数 = 执行池.取域资源读数(&标识).unwrap();
    assert!(读数.在跑);
    if !读数可判() {
        assert!(读数.进程组.is_none(), "读不出必须如实报 None，不许静默给零");
        return;
    }
    let 进程组 = 读数.进程组.expect("macOS 64 位给得出读数");
    assert!(进程组.进程数 >= 1, "域里至少有一个进程：{进程组:?}");
    assert!(进程组.句柄数 >= 1, "活着的工作进程至少持着标准输入输出：{进程组:?}");
    assert!(进程组.常驻字节 > 0, "常驻内存为 0 = 读数没真读：{进程组:?}");
    assert!(!读数.已回落(), "还在跑的域不许算已回落");
}

#[test]
fn 停机后读数回落为零() {
    // 停机 / 回退后的读数：账上说不在跑，四类读数也逐项回落到零。
    let 执行池 = 进程池::创建(进程池配置::default());
    let 标识 = 造标识(33);
    let (程序, 启动参数) = 带孙进程();
    执行池.保证域在(&标识, 程序, &启动参数).unwrap();
    let 停机前读数 = 执行池.取域资源读数(&标识).unwrap();
    执行池.击杀一域(&标识).unwrap();
    let 停机后读数 = 执行池.取域资源读数(&标识).unwrap();
    assert!(!停机后读数.在跑);
    assert_eq!(停机后读数.实例代次, 停机前读数.实例代次, "停机不改代次（还是那一批进程）");
    if !读数可判() {
        assert!(!停机后读数.已回落(), "读不出就不许声称回落（与上面那条同一口径）");
        return;
    }
    assert!(停机后读数.已回落(), "停机后四类读数必须逐项回落：{停机后读数:?}");
}

#[test]
fn 重启换代次且读数归新进程() {
    // 重启后的读数：代次变大（旧句柄永不误命中新任务），读数记在新那一批上。
    let 配置 = 进程池配置 { 退避基数毫秒: 0, 退避上限毫秒: 0, ..进程池配置::default() };
    let 执行池 = 进程池::创建(配置);
    let 标识 = 造标识(34);
    let (程序, 启动参数) = 短命进程();
    执行池.保证域在(&标识, 程序, &启动参数).unwrap();
    let 停机前读数 = 执行池.取域资源读数(&标识).unwrap();
    std::thread::sleep(Duration::from_millis(80));
    let 判读 = 执行池.崩溃重拉(&标识, 程序, &启动参数).unwrap();
    assert!(判读.已重拉);
    let 重启后读数 = 执行池.取域资源读数(&标识).unwrap();
    assert!(重启后读数.在跑);
    assert!(
        重启后读数.实例代次 > 停机前读数.实例代次,
        "重拉必须换新代次：前 {} · 后 {}",
        停机前读数.实例代次,
        重启后读数.实例代次
    );
}

#[test]
fn 升级换域后池读数只算新域() {
    // 升级 / 回退 = 摘掉旧版域 + 拉起新版域：池读数里旧版不再占数，新代次更大。
    let 执行池 = 进程池::创建(进程池配置::default());
    let 旧标识 = 造标识(35);
    let (程序, 启动参数) = 带孙进程();
    执行池.保证域在(&旧标识, 程序, &启动参数).unwrap();
    let 旧读数 = 执行池.取域资源读数(&旧标识).unwrap();
    assert!(执行池.移除一域(&旧标识), "有这域 ⇒ 真摘");
    let 空池 = 执行池.取池资源读数();
    assert_eq!(空池.域数, 0, "旧版域摘掉后池里不再有它");
    assert_eq!(空池.不可判域数, 0);
    if 读数可判() {
        assert_eq!(空池.进程数, 0, "旧版进程组回收后池读数归零：{空池:?}");
        assert_eq!(空池.常驻字节, 0, "旧版内存不许还挂在池读数上：{空池:?}");
    }
    let 新标识 = 造标识(36);
    执行池.保证域在(&新标识, 程序, &启动参数).unwrap();
    let 新读数 = 执行池.取域资源读数(&新标识).unwrap();
    assert!(新读数.实例代次 > 旧读数.实例代次, "重拉必须换新代次");
    let 新池 = 执行池.取池资源读数();
    assert_eq!(新池.域数, 1);
    if 读数可判() {
        assert!(新池.进程数 >= 1, "新版进程组要真在池读数里");
    }
}


