/// 一个带孙进程的域（进程组里不止一个进程 ⇒ 「进程数」那一类真被数到）。
fn 带孙进程() -> (&'static str, Vec<String>) {
    ("/bin/sh", vec![String::from("-c"), String::from("sleep 5 & sleep 5 & wait")])
}

/// 本平台给不给得出读数 —— 给不出就不硬断言四类读数（那会变成假红）。
fn 读数可判() -> bool {
    cfg!(all(target_os = "macos", target_pointer_width = "64"))
}

