//! 值归还 —— 跨边界「释放口」的**唯一实现**。
//!
//! # 缺的是什么
//!
//! C 符号 `平台_释放值` 一直有（`边界面.rs`，判据 ⑪-2a 已验），但 Rust 面的
//! `适配器` 类型**没有对应方法** ⇒ 调用方拿到一个带 `槽标志::所有权交出` 的返回槽，
//! 却无处归还。案例跑器按槽语义不释放（短命进程，泄漏可忽略），但那是绕开缺口，
//! 不是缺口闭合。
//!
//! # 与 C 符号同语义（写死一种，理由与 `边界面.rs` 文件头同）
//!
//! 本边界交出的每一块内存都是**静态终生有效**的 ⇒ [`归还槽值`] **不调用任何释放器**，
//! 只把槽清空；空槽再还一次是**幂等**的，不会二次释放任何一块。
//!
//! 这不是偷懒：平台唯一的跨边界分配器 `运行内核/内存分配器` 按**实例**持有账本
//! （地址 → 长度），边界不持有任何实例 ⇒ 后续那次释放找不到当初分配的那本账，
//! **它放不了任何东西**。让边界真能释放的两条路（给符号加句柄 / 让边界持全局分配器）
//! 分别改了冻结签名与违反边界无状态 ⇒ 两条都越权（详见 `边界面.rs` 文件头「所有权」）。
//!
//! **所以「返回槽带所有权交出」这件事的释放口在提供者/卸载那条路上**，不在这个
//! 无状态边界里 —— 本件给的是**同一个语义**的 Rust 面入口，让 Rust 调用方不必绕层去
//! 调内存分配器（那是跳层）。

use crate::{适配器, 数据槽};

/// 归还槽值：跨边界「释放口」的**唯一实现**（C 符号与 Rust 面都走它）。
///
/// 语义与 `平台_释放值` 逐字一致：把槽清空，**幂等**，不调用任何释放器。
pub fn 归还槽值(数据槽: &mut 数据槽) {
    *数据槽 = 数据槽::空槽();
}

impl 适配器 {
    /// Rust 级释放口：与 C 符号 `平台_释放值` **同语义**。
    ///
    /// 调用方拿到返回槽后，按槽标志判所有权；带 `槽标志::所有权交出` 的槽在用过之后
    /// 经本方法归还。**不绕层去调 `运行内核/内存分配器`**（那是跳层，见文件头）。
    pub fn 释放值(&self, 数据槽: &mut 数据槽) {
        归还槽值(数据槽);
    }
}
