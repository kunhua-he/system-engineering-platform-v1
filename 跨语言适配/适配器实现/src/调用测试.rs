/// 判据：多线程并发调 `平台_调用`，结果与单线程**逐位一致**（边界不加锁、不共享状态）。
#[test]
fn 可重入_多线程并发调用结果一致() {
    let 单线程 = {
        let 入参 = 底座入参();
        let mut 数据槽 = 数据槽::空槽();
        // SAFETY: 入参 1 个可读槽；槽 可写。
        let 协议返回码 = unsafe { 平台_调用(0, 1, 入参.as_ptr(), &mut 数据槽) };
        (协议返回码, 数据槽)
    };

    let 线程数 = 4usize;
    let 每线程 = 25usize;
    let 线程句柄: Vec<_> = (0..线程数)
        .map(|_| {
            std::thread::spawn(move || {
                let 入参 = 底座入参();
                let mut 输出缓冲 = Vec::with_capacity(每线程);
                for _ in 0..每线程 {
                    let mut 数据槽 = 数据槽::空槽();
                    // SAFETY: 入参 1 个可读槽；槽 是本线程自身的可写槽。
                    let 协议返回码 = unsafe { 平台_调用(0, 1, 入参.as_ptr(), &mut 数据槽) };
                    输出缓冲.push((协议返回码, 数据槽));
                }
                输出缓冲
            })
        })
        .collect();

    let mut 全部结果 = Vec::new();
    for 一个句柄 in 线程句柄 {
        全部结果.extend(一个句柄.join().expect("并发调用不许 panic"));
    }
    assert_eq!(全部结果.len(), 线程数 * 每线程, "空集不算通过：并发结果必须真有这么多条");
    assert!(结果全一致(&全部结果), "并发调用必须彼此逐位一致");
    for 一项 in &全部结果 {
        assert_eq!(*一项, 单线程, "并发结果必须与单线程逐位一致");
    }

    // ── 反向样本：判据不是空转，空集也不算通过 ──
    assert!(
        !结果全一致(&[(0, 数据槽::空槽()), (协议结果::参数不合法, 数据槽::空槽())]),
        "反向样本：喂一组不一致结果 ⇒ 判据报红"
    );
    assert!(!结果全一致(&[]), "空集不许算通过");
}

/// 判据：一组结果非空且逐位相同。
fn 结果全一致(结果: &[(i32, 数据槽)]) -> bool {
    !结果.is_empty() && 结果.iter().all(|一项| *一项 == 结果[0])
}

