/// 判据：连发两次同参调用**逐位相同**；中间插一次失败调用也不串味。
#[test]
fn 无状态_连发两次调用互不影响() {
    let 入参 = 底座入参();
    let mut 首槽 = 数据槽::空槽();
    // SAFETY: 入参 1 个可读槽；首槽 可写。
    let 首调结果 = unsafe { 平台_调用(0, 1, 入参.as_ptr(), &mut 首槽) };
    // 中间插一次**失败**调用（不存在的号）：若边界有 `last_error` 一类状态，下一次会被串味。
    let mut 错槽 = 数据槽::空槽();
    // SAFETY: 0 个参数 + 空参数表；错槽 可写。
    let _ = unsafe { 平台_调用(9999, 0, core::ptr::null(), &mut 错槽) };
    let mut 次槽 = 数据槽::空槽();
    // SAFETY: 同上。
    let 次调结果 = unsafe { 平台_调用(0, 1, 入参.as_ptr(), &mut 次槽) };
    assert_eq!((首调结果, 首槽), (次调结果, 次槽), "两次同参调用必须逐位相同（无状态）");

    // ── 反向样本：**有状态**的适配器会串味 ──
    // 同一本配额账本打满后，第 N+1 次报「配额用尽」⇒ 上面那条「两次一致」对状态是敏感的。
    let 有状态 = 适配器::装载(v1_loader::底座声明()).expect("底座");
    let mut 数据槽 = 数据槽::空槽();
    for _ in 0..配额上限 {
        assert!(matches!(有状态.调用能力(0, &入参, &mut 数据槽), 转发结果::成功(_)));
    }
    assert!(
        matches!(
            有状态.调用能力(0, &入参, &mut 数据槽),
            转发结果::失败(调度错误::配额用尽)
        ),
        "反向样本：持有状态的适配器第 N+1 次会变 ⇒ 「两次一致」不是空转"
    );
}

/// 判据：两个实例（两份声明根）**互不干扰**。
#[test]
fn 无状态_两个实例两份声明根互不干扰() {
    assert!(
        matches!(对外边界::新建(&[]), Err(装载失败::空声明根)),
        "空声明根即拒（没有注册表就没有可寻址的表）"
    );

    let 扩展 = 造扩展声明(号段::新建(1000, 1999));
    let 首边界 = 对外边界::新建(&[v1_loader::底座声明()]).expect("首个");
    let 次边界 = 对外边界::新建(&[v1_loader::底座声明(), 扩展]).expect("次个");

    assert_eq!(首边界.能力清单().len(), 1, "首个只装底座");
    assert_eq!(次边界.能力清单().len(), 2, "次个多装一份扩展 ⇒ 多一条命令");
    assert_ne!(首边界.取接口描述(), 次边界.取接口描述(), "两份声明根的描述必须不同");

    // ── 反向样本：**同一份**声明根建的两个实例必须逐字节相同 ──
    // 这样上面那条差异才归因于声明根，而不是「任何两个实例都不同」这种空话。
    let 同根边界 = 对外边界::新建(&[v1_loader::底座声明()]).expect("末个");
    assert_eq!(首边界.取接口描述(), 同根边界.取接口描述(), "同一份声明根 ⇒ 描述逐字节相同");
    assert_eq!(首边界.能力清单(), 同根边界.能力清单());
}

