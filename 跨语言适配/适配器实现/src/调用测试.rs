/// 判据：成功路径（协议层成功 + 返回槽里是**真调到执行函数**拿到的值）。
#[test]
fn 调用_成功路径() {
    let 入参 = 底座入参();
    let mut 数据槽 = 数据槽::空槽();
    // SAFETY: 入参 是 1 个可读槽、槽 可写；个数与声明一致（1）。
    let 协议返回码 = unsafe { 平台_调用(0, 入参.len() as u32, 入参.as_ptr(), &mut 数据槽) };
    assert_eq!(协议返回码, 协议结果::成功, "协议层必须成立");
    assert!(数据槽.是否引用(), "底座命令 0 返回的是契约主结构指针");
    assert_eq!(数据槽.值, v1_loader::取平台信息() as u64, "必须真调到执行函数，不是兜底值");
}

/// 判据：参数个数不符 ⇒ `int32_t` 报**参数不合法**（调用形状不对，属协议层）。
#[test]
fn 调用_参数个数不符报参数不合法() {
    let mut 数据槽 = 数据槽::空槽();
    // SAFETY: 个数 0 + 空参数表（合法形状）；槽 可写。
    let 协议返回码 = unsafe { 平台_调用(0, 0, core::ptr::null(), &mut 数据槽) };
    assert_eq!(协议返回码, 协议结果::参数不合法, "参数个数不符是协议层失败");
    assert!(数据槽.是否空(), "协议层失败必须置空返回槽");

    // 个数 > 0 却给空参数表：同一个协议层口径。
    // SAFETY: 空参数表由本函数当场挡下（不读它）；槽 可写。
    let 码2 = unsafe { 平台_调用(0, 1, core::ptr::null(), &mut 数据槽) };
    assert_eq!(码2, 协议结果::参数不合法);

    // 返回槽为空指针：不写任何内存，也只报协议层参数不合法。
    // SAFETY: 返回槽为空指针由本函数当场挡下。
    let 码3 = unsafe { 平台_调用(0, 0, core::ptr::null(), core::ptr::null_mut()) };
    assert_eq!(码3, 协议结果::参数不合法);
}

/// 判据：**不存在的号 ⇒ `int32_t` 报成功，业务失败在返回槽里**（本项目反复强调的口径）。
#[test]
fn 调用_不存在的号_返回码成功且业务失败在返回槽() {
    let mut 数据槽 = 数据槽::空槽();
    // SAFETY: 0 个参数 + 空参数表；槽 可写。
    let 协议返回码 = unsafe { 平台_调用(9999, 0, core::ptr::null(), &mut 数据槽) };
    assert_eq!(协议返回码, 协议结果::成功, "业务失败**不许**塞进返回码");
    assert_eq!(
        数据槽.类型标签,
        v1_contract::声明数据::类型标签_4294967295,
        "错误槽的类型标签是「错误」"
    );
    assert_eq!(
        数据槽.值,
        u64::from(v1_contract::声明数据::错误码_1.取号值()),
        "「提供者未载入」的 4 位码"
    );
    assert!(!数据槽.是否空(), "业务失败必须给出可读的结构化错误码");

    // 三项业务判断由接口描述随包给出（否则它们只是注释）。
    // 底座命令 0 自身**不抛错**（可抛码空表）⇒ 拿一份带码的合成声明来验这条通道。
    let 边界 = 对外边界::新建(&[
        v1_loader::底座声明(),
        造扩展声明_命令可抛码少于全表(号段::新建(1000, 1999)),
    ])
    .expect("底座 + 合成声明");
    let json = 边界.取接口描述();
    assert!(
        json.contains("\"码\": 1001"),
        "这条命令自身登记的可抛码必须随包给出（含三项业务判断）"
    );

    // ── 反向样本：把业务失败塞进返回码 —— 判据必须抓得到 ──
    let 违规返回码 = v1_contract::声明数据::错误码_1.取号值() as i32;
    assert!(
        业务失败塞进了返回码(违规返回码, &数据槽),
        "反向样本：返回码 = 业务码 且返回槽是错误槽 ⇒ 判据报红"
    );
    assert!(!业务失败塞进了返回码(协议返回码, &数据槽), "正向：真实调用不是这个形状");
}

/// 判据：返回码不是协议层的「成功」，返回槽里却是结构化错误码 ⇒ 业务失败被塞进了返回码。
