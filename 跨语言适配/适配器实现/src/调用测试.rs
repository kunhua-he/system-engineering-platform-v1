/// 判据：还回去之后再还一次**不崩**（幂等 —— `void` 返回没有报错通道，故只能幂等）。
#[test]
fn 释放值_幂等_还两次不崩() {
    let mut 数据槽 = 数据槽::指针(v1_contract::声明数据::类型标签_0005.into(), 0x1234, 8, true);
    assert!(!数据槽.是否空(), "样本必须先是非空槽，否则这条判据是空集");
    // SAFETY: 槽 可写。
    unsafe { 平台_释放值(&mut 数据槽) };
    assert!(数据槽.是否空(), "归还后槽必须为空");
    // 第二次归还同一个槽：幂等（不崩、不二次释放任何一块）。
    // SAFETY: 槽 可写。
    unsafe { 平台_释放值(&mut 数据槽) };
    assert!(数据槽.是否空(), "再还一次仍是空槽");
    // 空指针：什么都不做。
    // SAFETY: 空指针由本函数当场挡下。
    unsafe { 平台_释放值(core::ptr::null_mut()) };

    // ── 反向样本：「二次释放同一块」**是**能被抓到的（拿一本假账试）──
    // 所以「本边界不释放 ⇒ 不会二次释放」不是空话，而是一条可判的性质。
    let mut 假账 = 假分配器::新建();
    let 地址 = 假账.分配假地址();
    assert_eq!(假账.释放活块(地址), Ok(()));
    assert_eq!(假账.释放活块(地址), Err("重复释放"), "反向样本：二次释放必须被抓到");
}

/// 一本**假**分配器（只在测试里用）：证明「二次释放同一块」是可判的。
///
/// 本边界**不持有它** —— 它只给上面那条断言当反向样本（真分配器是
/// `运行内核/内存分配器`，它按实例持有账本，边界无状态 ⇒ 见 `边界面.rs` 文件头）。
struct 假分配器 {
    活块: Vec<u64>,
}

impl 假分配器 {
    fn 新建() -> Self {
        Self { 活块: Vec::new() }
    }

    fn 分配假地址(&mut self) -> u64 {
        let 地址 = 0x1000 + self.活块.len() as u64;
        self.活块.push(地址);
        地址
    }

    fn 释放活块(&mut self, 地址: u64) -> Result<(), &'static str> {
        match self.活块.iter().position(|块地址| *块地址 == 地址) {
            Some(位置) => {
                self.活块.remove(位置);
                Ok(())
            }
            None => Err("重复释放"),
        }
    }
}

