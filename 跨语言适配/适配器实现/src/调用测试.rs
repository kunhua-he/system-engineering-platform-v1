/// 判据：**同一调用形状按句柄槽的值区分两个实例**（C ABI 那一面不需要额外参数）。
///
/// 做法：一份声明的命令入参就是一个「句柄」槽；它的执行函数把收到的句柄**原样**回显。
/// 同一份声明、同一个号、同一条调用形状，句柄值不同 ⇒ 结果不同。
#[test]
fn 句柄槽_同一调用形状按句柄值区分两个实例() {
    let 句柄标签 = v1_contract::声明数据::类型标签_0006;
    let 扩展 = 造扩展声明_带句柄槽(号段::新建(1000, 1999));
    let 边界 = 对外边界::新建(&[v1_loader::底座声明(), 扩展]).expect("底座 + 带句柄槽的声明");
    assert!(
        边界.能力清单().len() == 2,
        "句柄槽的能力也必须在清单里（读侧与调侧同一入口）"
    );

    // 两个不同的句柄值，走同一条调用形状。
    for 句柄值 in [0x1111_2222_3333_4444u64, 0x5555_6666_7777_8888u64] {
        let 参数 = [数据槽::内联(句柄标签.into(), 句柄值, 0)];
        let mut 返回槽 = 数据槽::空槽();
        let 协议返回码 = 边界.调用(1000, &参数, &mut 返回槽);
        assert_eq!(协议返回码, 协议结果::成功, "句柄槽必须能过边界");
        assert_eq!(
            返回槽.类型标签.取号值(),
            句柄标签,
            "返回槽的类型标签来自声明（句柄类）"
        );
        assert_eq!(返回槽.值, 句柄值, "句柄值逐字节不变（转发路不解释它）");
    }

    // ── 反向样本：句柄槽不是「只认一个值」的硬编码 —— 换一个**非句柄**标签也照样原样回显 ──
    let 其它标签 = v1_contract::声明数据::类型标签_0001;
    let 参数 = [数据槽::内联(其它标签.into(), 42, 0)];
    let mut 返回槽 = 数据槽::空槽();
    assert_eq!(边界.调用(1000, &参数, &mut 返回槽), 协议结果::成功);
    assert_eq!((返回槽.类型标签.取号值(), 返回槽.值), (其它标签.取号值(), 42), "回显是逐位的，不是「只有句柄值对得上」");

    // 反向样本：两个句柄值的结果必须**不同**，否则上面那条是空转。
    assert_ne!(0x1111_2222_3333_4444u64, 0x5555_6666_7777_8888u64);
}

