//! 模块执行体装载 —— 段 `20` 里的**本机机器码** → `dlopen` → 取入口 → 调用。
//!
//! 依据 `项目文档/决策记录/2026-10-12_模块执行体承载与编译裁决.md`：
//! 执行体放段 `20` · 构建侧编译 · 制品带平台身份（**不匹配即拒**）。
//! 入口**形状与符号名**住契约层（`v1_contract::容器::执行体载荷`）—— 构建侧按它导出、
//! 本件按它取，只此一份。
//!
//! # 本件只做「制品 → 能调的入口」
//!
//! 「子进程里怎么跑这条调用」是**跨进程执行域**的事（`进程池.rs` / `工作进程.rs`）。
//! 本件把「制品 → 能调的入口」做成一个可复用的口，执行域按需取用。
//!
//! # 平台身份从哪来
//!
//! [`本机平台身份`] 由 `std::env::consts` 的 `ARCH` / `OS` 拼出目标三元组。
//! **认不出的 OS ⇒ 明确失败**（不猜、不回落）—— 判错的代价是「本该拒的装上了」。

use std::ffi::{CString, c_void};
use std::path::Path;

use v1_contract::容器::{上下文入口符号, 入口符号};
use v1_contract::数据槽;

use crate::动态库口::{RTLD_NOW, dlopen, dlsym, 最近装载错误};

/// 宿主回调 —— 模块执行体向平台要别的能力时走这里（C-ABI，形状由构建侧生成的入口包装冻结）。
pub type 宿主回调 = extern "C" fn(u32, *const 数据槽, usize, *mut 数据槽) -> i32;

/// **带上下文的**宿主回调 —— 第一参是调用方实例上下文（**只借不交**：活到一次调用栈帧）。
///
/// 与四参 [`宿主回调`] 是**两个型**，不是它的替换：旧符号 / 旧签名 / 旧含义一字不动
/// （六参原型住 `契约声明::容器::执行体载荷`）。模块与回调都不解释、不缓存、不释放上下文
/// ⇒ 不需要 `static` / `thread_local`，也不拿类型标签塞伪参数。
pub type 带上下文宿主回调 =
    extern "C" fn(*mut c_void, u32, *const 数据槽, usize, *mut 数据槽) -> i32;

/// 模块装载的结构化失败。**不 panic**（跨边界不许抛异常）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 模块装载错误 {
    /// 制品读不到 / 不是能力包件 / 段指纹不符 / 平台身份不符（`装载件缓存` 的原因串）。
    制品不可用(String),
    /// `dlopen` 失败。
    装载失败(String),
    /// 取不到入口符号。
    入口缺失(String),
    /// 调用返回非零 —— 执行体回报的失败码。
    执行失败(i32),
}

/// 已装载的模块执行体 —— 拿着入口函数指针。
///
/// # 库的生命周期
///
/// **不 `dlclose`**：入口要活到调用方用完；卸载走生命周期通知，不是卸载动态库
/// （与 `工作进程.rs` · `扫扩展根.rs` 同一条处置）。
pub struct 已装载执行体 {
    执行: extern "C" fn(宿主回调, *const 数据槽, usize, *mut 数据槽) -> i32,
    /// 带上下文入口（`v1_module_exec_ctx`）—— 取不到就是 `None`（旧制品只有四参入口）。
    ///
    /// **不回落**：组合调用要实例上下文，四参入口物理上没位置放它 —— 拿旧入口假装通了
    /// 就是伪造「组合支持库已通」，故 [`已装载执行体::调用返回槽`] 在 `None` 时明确失败。
    执行带上下文: Option<
        extern "C" fn(
            *mut c_void,
            带上下文宿主回调,
            *const 数据槽,
            usize,
            *mut 数据槽,
        ) -> i32,
    >,
}

impl 已装载执行体 {
    /// 调一次：入参槽进、返回槽出。返回码 `0` = 成功；非零 = 执行体回报的失败码。
    ///
    /// **旧四参 ABI 原样保留**：返回值仍压成 `i64`（整数能力那条冻结含义）。
    /// 复合返回（103）走 [`已装载执行体::调用返回槽`]，两条路不混。
    pub fn 调用(&self, 入参: &[数据槽], 宿主函数: 宿主回调) -> Result<i64, 模块装载错误> {
        let mut 返回槽 = 数据槽::空槽();
        let 返回码 = (self.执行)(宿主函数, 入参.as_ptr(), 入参.len(), &mut 返回槽);
        if 返回码 != 0 {
            return Err(模块装载错误::执行失败(返回码));
        }
        Ok(返回槽.槽值 as i64)
    }

    /// 这条执行体有没有带上下文入口（`v1_module_exec_ctx`）。
    ///
    /// 调用方据此选路：有 ⇒ 走 [`已装载执行体::调用返回槽`]（整槽 + 实例上下文）；
    /// 没有 ⇒ 只能走冻结的旧四参 [`已装载执行体::调用`]（整数能力那条），
    /// **不假装组合链已通**（旧入口物理上放不下上下文）。
    pub fn 有带上下文入口(&self) -> bool {
        self.执行带上下文.is_some()
    }

    /// 调一次（**带实例上下文 · 整槽返回**）：入参槽进、**完整返回槽**出。
    ///
    /// 与 [`已装载执行体::调用`] 的分工：那条是冻结的四参 ABI（返回值压成 `i64`，只够整数能力）；
    /// 组合链要的是「模块 → 宿主 → 支持库 → 复合结果」⇒ 必须走六参入口，并把**整个槽**
    /// （标签 / 长度 / 所有权）原样交回，不压整数、不重造槽。
    ///
    /// `上下文` 只借一次调用：模块与回调都不解释、不缓存、不释放。
    pub fn 调用返回槽(
        &self,
        上下文: *mut c_void,
        入参: &[数据槽],
        宿主函数: 带上下文宿主回调,
    ) -> Result<数据槽, 模块装载错误> {
        let Some(执行带上下文) = self.执行带上下文 else {
            return Err(模块装载错误::入口缺失(String::from(
                "制品没有 v1_module_exec_ctx 入口（组合调用要实例上下文，四参入口放不下）",
            )));
        };
        let mut 返回槽 = 数据槽::空槽();
        let 返回码 = 执行带上下文(上下文, 宿主函数, 入参.as_ptr(), 入参.len(), &mut 返回槽);
        if 返回码 != 0 {
            return Err(模块装载错误::执行失败(返回码));
        }
        Ok(返回槽)
    }
}

/// 装载：模块制品 → 段 `20` → 判平台身份 → 落缓存 → `dlopen` → 取入口。
///
/// 前三步走本 crate 既有的 [`crate::装载件缓存::解包模块执行体到缓存`]（**唯一实现**）。
pub fn 装载模块执行体(
    制品路径: &Path,
    缓存根目录: &Path,
    当前平台身份: &str,
) -> Result<已装载执行体, 模块装载错误> {
    按符号装载模块执行体(制品路径, 缓存根目录, 当前平台身份, 入口符号, 上下文入口符号)
}

/// 一个包只解包、校验、打开一次；逐号取真函数，不按能力数重复读整件。
pub fn 装载模块执行体组(制品路径: &Path, 缓存根目录: &Path, 当前平台身份: &str, 能力号表: &[u32]) -> Result<std::collections::BTreeMap<u32, 已装载执行体>, 模块装载错误> {
    if 能力号表.is_empty() { return Err(模块装载错误::制品不可用("模块能力号表为空".to_owned())); }
    let 句柄 = 打开模块执行库(制品路径, 缓存根目录, 当前平台身份)?;
    let mut 执行体表 = std::collections::BTreeMap::new();
    for 能力号 in 能力号表 {
        let 执行入口名 = v1_contract::容器::模块能力入口符号(*能力号, false);
        let 上下文入口名 = v1_contract::容器::模块能力入口符号(*能力号, true);
        let 执行体 = 从句柄取模块执行体(句柄, &执行入口名, &上下文入口名)?;
        if !执行体.有带上下文入口() { return Err(模块装载错误::入口缺失(format!("模块能力{能力号}缺带上下文入口"))); }
        if 执行体表.insert(*能力号, 执行体).is_some() { return Err(模块装载错误::制品不可用(format!("模块能力号{能力号}重复"))); }
    }
    Ok(执行体表)
}

fn 按符号装载模块执行体(制品路径: &Path, 缓存根目录: &Path, 当前平台身份: &str, 执行入口名: &str, 上下文入口名: &str) -> Result<已装载执行体, 模块装载错误> {
    let 句柄 = 打开模块执行库(制品路径, 缓存根目录, 当前平台身份)?;
    从句柄取模块执行体(句柄, 执行入口名, 上下文入口名)
}

fn 打开模块执行库(制品路径: &Path, 缓存根目录: &Path, 当前平台身份: &str) -> Result<*mut c_void, 模块装载错误> {
    let 落盘路径 = crate::装载件缓存::解包模块执行体到缓存(制品路径, 缓存根目录, 当前平台身份)
        .map_err(模块装载错误::制品不可用)?;
    let 路径串 = CString::new(落盘路径.as_os_str().as_encoded_bytes())
        .map_err(|_| 模块装载错误::装载失败(String::from("库路径含 NUL")))?;
    // SAFETY: 路径串是 NUL 结尾的合法 C 串；句柄只装载不释放（活到进程结束）。
    let 句柄 = unsafe { dlopen(路径串.as_ptr(), RTLD_NOW) };
    if 句柄.is_null() {
        return Err(模块装载错误::装载失败(最近装载错误()));
    }
    Ok(句柄)
}

fn 从句柄取模块执行体(句柄: *mut c_void, 执行入口名: &str, 上下文入口名: &str) -> Result<已装载执行体, 模块装载错误> {
    let 符号名 = CString::new(执行入口名)
        .map_err(|_| 模块装载错误::入口缺失(String::from("符号名含 NUL")))?;
    // SAFETY: 句柄非空（上面已挡）；符号名是合法 C 串。
    let 符号指针 = unsafe { dlsym(句柄, 符号名.as_ptr()) };
    if 符号指针.is_null() {
        return Err(模块装载错误::入口缺失(最近装载错误()));
    }
    // SAFETY: 入口形状由构建侧生成的包装冻结（见 `编译本机源码.rs`）——
    // 四个参数：宿主回调、入参槽指针、入参个数、返回槽指针；返回 `i32`。
    let 执行: extern "C" fn(宿主回调, *const 数据槽, usize, *mut 数据槽) -> i32 =
        unsafe { core::mem::transmute(符号指针) };
    // **先取带上下文入口**（六参）：取不到留 `None`，由 `调用返回槽` 明确拒绝 ——
    // 不回落旧入口（旧入口没有上下文位，回落就是伪造组合已通）。
    let 上下文符号名 = CString::new(上下文入口名)
        .map_err(|_| 模块装载错误::入口缺失(String::from("符号名含 NUL")))?;
    // SAFETY: 句柄非空（上面已挡）；符号名是合法 C 串。
    let 上下文符号指针 = unsafe { dlsym(句柄, 上下文符号名.as_ptr()) };
    let 执行带上下文 = if 上下文符号指针.is_null() {
        None
    } else {
        // SAFETY: 六参形状由构建侧生成的 `v1_module_exec_ctx` 包装冻结：
        // 上下文、带上下文宿主回调、入参槽指针、入参个数、返回槽指针；返回 `i32`。
        Some(unsafe {
            core::mem::transmute::<
                *mut c_void,
                extern "C" fn(
                    *mut c_void,
                    带上下文宿主回调,
                    *const 数据槽,
                    usize,
                    *mut 数据槽,
                ) -> i32,
            >(上下文符号指针)
        })
    };
    Ok(已装载执行体 { 执行, 执行带上下文 })
}

/// 取模块制品**声明的接口说明**（段 `16` 的唯一读法：编号 + 参数表 + 返回类型）。
///
/// 生产接入的号与**参数类型号表**都只从这里来：核心不写号表、不认模块名（判据 ⑯）。
pub fn 取模块接口组(制品路径: &Path) -> Result<Vec<v1_contract::接口说明段::接口说明>, 模块装载错误> {
    let 制品字节 = std::fs::read(制品路径)
        .map_err(|错误| 模块装载错误::制品不可用(format!("读不到制品：{错误}")))?;
    let 三段 = v1_contract::容器::解包(&制品字节)
        .map_err(|错误| 模块装载错误::制品不可用(format!("不是能力包件：{错误:?}")))?;
    v1_contract::接口说明段::解码接口组(&三段.接口说明段)
        .ok_or_else(|| 模块装载错误::制品不可用(String::from("接口说明段解不开")))
}

/// 取模块制品**声明的编号**（段 `16` 接口说明的唯一读法）。
pub fn 取模块编号(制品路径: &Path) -> Result<u32, 模块装载错误> {
    let 说明表 = 取模块接口组(制品路径)?;
    if 说明表.len() != 1 { return Err(模块装载错误::制品不可用("模块含多能力，请按接口组取编号".to_owned())); }
    Ok(说明表[0].编号)
}

/// 本机平台身份 —— 目标三元组，由 `std::env::consts` 的 `ARCH` / `OS` 拼出。
///
/// **认不出的 OS ⇒ 明确失败**（不猜、不回落）：判错的代价是「本该拒的装上了」。
pub fn 本机平台身份() -> Result<String, String> {
    let 架构 = std::env::consts::ARCH;
    let 系统 = std::env::consts::OS;
    let 系统尾段 = match 系统 {
        "macos" => "apple-darwin",
        "linux" => "unknown-linux-gnu",
        "windows" => "pc-windows-msvc",
        _ => return Err(format!("认不出本机 OS：{系统}")),
    };
    Ok(format!("{架构}-{系统尾段}"))
}
