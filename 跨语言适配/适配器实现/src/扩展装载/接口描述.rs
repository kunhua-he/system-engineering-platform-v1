//! 接口描述 —— 把适配器的读侧（`能力清单` + `能力契约`）写成 UTF-8 JSON。
//!
//! # 形状（与 `接口面形状.md` §三 的自描述根对齐，去掉 HTTP 专有字段）
//!
//! ```json
//! {
//!   "契约版本": { "主": 0, "次": 1, "构建": 1 },
//!   "声明格式号": 1398362929,
//!   "执行模式": { "说明": "…", "跨进程执行域": false },
//!   "超时保障": { "单项超时毫秒": 1000, "来源": "…" },
//!   "恢复能力": { "重启预算": 5, "退避基数毫秒": 50, … },
//!   "消息大小": { "单帧载荷上限": 1048576, "调用载荷上限": 4194304 },
//!   "隔离边界": "…（进程隔离只隔执行载体，不是文件/网络/密钥沙箱）",
//!   "能力": [
//!     { "编号": 0, "名称": "取平台信息", "参数个数": 1, "返回类型": 0,
//!       "说明": "…",
//!       "参数表": [ { "名称": "目标字宽", "类型标签": 0, "状态位": 0 } ],
//!       "可抛错误码": [ { "码": 1, "名称": "提供者未载入",
//!                        "可重试": true, "可自愈": true, "需人工": false } ] }
//!   ]
//! }
//! ```
//!
//! # 数据一律**现读**，不另存
//!
//! `能力` 数组就是 [`适配器::能力清单`] 的输出，逐条再去 [`适配器::能力契约`] 取
//! 参数表行序与可抛错误码 —— 与调侧同一个入口（读侧与调侧同一入口，清单里的编号拿去调必然走得通）。
//!
//! # 明确不做
//!
//! - **不出 `端点` 表**：端点是 HTTP 网关的事（`对外接口面`），边界层写它就是替上层定形状，
//!   且会变成第二份端点表。
//! - **不出参数的 `默认值`**：默认值不在调用方要读的东西里 —— 行序即契约，缺位写空槽
//!   （`接口面形状.md` §三），默认值是提供者自身的事。少一个字段，就少一处漂移。
//! - **可抛错误码按命令给**：`适配器::能力契约` 给的是**这条命令自身**声明的可抛码
//!   （源 = `命令信息.可抛错误码`），名称与三项业务判断从声明 `错误码表` 现查。
//!   声明全表另有其口（`适配器::声明错误码表`），是**调度层**那些码的落点 —— 这里原样转出，
//!   不自行筛。
//! - **字段一律有值，只有一个例外**：`说明` 在「取不到契约」时给 `null`。`null` = 取不到值，
//!   `""` = 已知是空串 —— 跨语言里是两件事。其余字段都有确定的值（`返回类型 0` = 无返回值、
//!   `可抛错误码 []` = 没有可抛码）⇒ 不给它们加「可能为 null」这条每种语言都要判的分支。

use crate::接口描述写出::{JSON值, 写协议值};
use crate::{参数摘要, 适配器, 错误码摘要};
use v1_contract::声明数据::单项超时毫秒;
use v1_contract::平台信息;
#[cfg(unix)]
use crate::进程池::{
    默认退避上限毫秒, 默认退避基数毫秒, 默认重启预算, 默认熔断时长毫秒,
};
#[cfg(unix)]
use crate::进程帧::{单帧载荷上限, 调用载荷上限};

/// 写一份接口描述 JSON（**不含**结尾换行）。
pub fn 写描述(适配器: &适配器, 契约来源: &平台信息) -> String {
    let 版本 = 契约来源.实现版本;
    let 能力 = 适配器
        .能力清单()
        .into_iter()
        .map(|能力条目| {
            let 契约 = 适配器.能力契约(能力条目.编号);
            let (说明文字, 参数表, 可抛错误码) = match &契约 {
                Some(契约内容) => (
                    JSON值::文本值(契约内容.说明文字.clone()),
                    契约内容.参数表.clone(),
                    契约内容.可抛错误码.clone(),
                ),
                // 清单与契约走同一个注册表 ⇒ 正常装配下走不到这一支（注册表前后不一致才走到）。
                // 给 `null` 而**不是空串**：`null` = 取不到值，`""` = 已知是空串 ——
                // 跨语言里这是两件事（调用方要判的正是「这个字段有没有值」）。
                None => (JSON值::空值项, Vec::new(), Vec::new()),
            };
            JSON值::对象值(vec![
                ("编号".to_owned(), JSON值::整数项(能力条目.编号 as i64)),
                ("名称".to_owned(), JSON值::文本值(能力条目.名称)),
                ("参数个数".to_owned(), JSON值::整数项(能力条目.参数个数 as i64)),
                ("返回类型".to_owned(), JSON值::整数项(能力条目.返回类型 as i64)),
                ("说明".to_owned(), 说明文字),
                ("参数表".to_owned(), JSON值::数组值(参数表.iter().map(写参数).collect())),
                (
                    "可抛错误码".to_owned(),
                    JSON值::数组值(可抛错误码.iter().map(渲染错误码值).collect()),
                ),
            ])
        })
        .collect();

    let mut 根项 = vec![
        (
            "契约版本".to_owned(),
            JSON值::对象值(vec![
                ("主".to_owned(), JSON值::整数项(版本.主版本 as i64)),
                ("次".to_owned(), JSON值::整数项(版本.次版本号 as i64)),
                ("构建".to_owned(), JSON值::整数项(版本.构建 as i64)),
            ]),
        ),
        (
            "声明格式号".to_owned(),
            JSON值::整数项(i64::from(契约来源.声明格式号.取号值())),
        ),
        ("能力".to_owned(), JSON值::数组值(能力)),
    ];
    根项.extend(执行能力四项(适配器));
    写协议值(&JSON值::对象值(根项))
}

/// 平台执行能力四项 —— 自描述要写清的四项：执行模式 · 超时保障 · 恢复能力 · 消息大小。
///
/// **值一律现读具名常量，不在这里写第二份数字**：
///
/// | 项 | 真源 |
/// |---|---|
/// | 执行模式 | 本实例**真的**开没开跨进程执行域表（`适配器::有跨进程域`，现读） |
/// | 超时保障 | `契约声明/常量表.json` 的 `单项超时毫秒` |
/// | 恢复能力 | `进程池.rs` 的退避 / 重启预算 / 熔断四个具名常量 |
/// | 消息大小 | `进程帧.rs` 的单帧 / 单次调用两个具名常量 |
///
/// **隔离边界如实说明**：进程隔离只隔**执行载体** —— 工作进程崩溃与内存不牵连宿主；
/// 它**不是**文件 / 网络 / 密钥沙箱：工作进程与宿主同权限、同文件系统、同网络。
/// 底座只守一条底线「不造成系统性破坏」，不把「相对安全」说成绝对边界。
fn 执行能力四项(适配器: &适配器) -> Vec<(String, JSON值)> {
    #[cfg(unix)]
    let 跨进程启用 = 适配器.有跨进程域();
    #[cfg(not(unix))]
    let 跨进程启用 = false;
    let 执行模式说明 = if 跨进程启用 {
        "按号：登记过执行域的号走工作进程（跨进程执行域）；其余走进程内转发"
    } else {
        "全部走进程内转发（本实例未开跨进程执行域表）"
    };
    #[cfg(unix)]
    let 恢复读数 = JSON值::对象值(vec![
        ("重启预算".to_owned(), JSON值::整数项(i64::from(默认重启预算))),
        ("退避基数毫秒".to_owned(), JSON值::整数项(默认退避基数毫秒 as i64)),
        ("退避上限毫秒".to_owned(), JSON值::整数项(默认退避上限毫秒 as i64)),
        ("熔断时长毫秒".to_owned(), JSON值::整数项(默认熔断时长毫秒 as i64)),
        (
            "适用".to_owned(),
            JSON值::文本值("仅跨进程执行域；进程内转发不经进程池".to_owned()),
        ),
    ]);
    #[cfg(not(unix))]
    let 恢复读数 = JSON值::对象值(vec![(
        "说明".to_owned(),
        JSON值::文本值("非 unix 平台：跨进程执行域整支不存在，无进程池恢复机制".to_owned()),
    )]);
    #[cfg(unix)]
    let 消息读数 = JSON值::对象值(vec![
        ("单帧载荷上限".to_owned(), JSON值::整数项(单帧载荷上限 as i64)),
        ("调用载荷上限".to_owned(), JSON值::整数项(调用载荷上限 as i64)),
        (
            "适用".to_owned(),
            JSON值::文本值("仅跨进程执行域的工作进程线协议".to_owned()),
        ),
    ]);
    #[cfg(not(unix))]
    let 消息读数 = JSON值::对象值(vec![(
        "说明".to_owned(),
        JSON值::文本值("非 unix 平台：跨进程执行域整支不存在，无线协议消息上限".to_owned()),
    )]);
    vec![
        (
            "执行模式".to_owned(),
            JSON值::对象值(vec![
                ("说明".to_owned(), JSON值::文本值(执行模式说明.to_owned())),
                (
                    "跨进程执行域".to_owned(),
                    if 跨进程启用 { JSON值::真值 } else { JSON值::假值 },
                ),
            ]),
        ),
        (
            "超时保障".to_owned(),
            JSON值::对象值(vec![
                ("单项超时毫秒".to_owned(), JSON值::整数项(单项超时毫秒 as i64)),
                (
                    "来源".to_owned(),
                    JSON值::文本值(
                        "契约声明/常量表.json 的 单项超时毫秒；全平台唯一口径".to_owned(),
                    ),
                ),
            ]),
        ),
        ("恢复能力".to_owned(), 恢复读数),
        ("消息大小".to_owned(), 消息读数),
        (
            "隔离边界".to_owned(),
            JSON值::文本值(
                "进程隔离只隔执行载体（工作进程崩溃与内存不牵连宿主）；它不是文件 / 网络 / 密钥沙箱：工作进程与宿主同权限、同文件系统、同网络。".to_owned(),
            ),
        ),
    ]
}

/// 参数表的一行。**行序即契约**（顺序由上层 `Vec` 的排列给出）。
fn 写参数(入参: &参数摘要) -> JSON值 {
    JSON值::对象值(vec![
        ("名称".to_owned(), JSON值::文本值(入参.名称.clone())),
        ("类型标签".to_owned(), JSON值::整数项(入参.类型标签 as i64)),
        ("状态位".to_owned(), JSON值::整数项(入参.状态位 as i64)),
    ])
}

/// 可抛错误码的一条：`码` + 三项业务判断（失败可编程处理的落点）。
fn 渲染错误码值(错误码: &错误码摘要) -> JSON值 {
    JSON值::对象值(vec![
        ("码".to_owned(), JSON值::整数项(错误码.码值 as i64)),
        ("名称".to_owned(), JSON值::文本值(错误码.名称.clone())),
        ("可重试".to_owned(), 真假值转线上值(错误码.可重试)),
        ("可自愈".to_owned(), 真假值转线上值(错误码.可自愈)),
        ("需人工".to_owned(), 真假值转线上值(错误码.需人工)),
    ])
}

fn 真假值转线上值(真假值: bool) -> JSON值 {
    if 真假值 { JSON值::真值 } else { JSON值::假值 }
}
