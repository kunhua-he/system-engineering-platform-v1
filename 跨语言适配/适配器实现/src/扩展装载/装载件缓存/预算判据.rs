//! 装载件缓存 · 预算判据 —— 落盘前的两条上限（磁盘预算 · 缓存条目上限）。
//!
//! 从 `装载件缓存.rs` 拆出（单源 ≤ 800 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管「从盘上取一份字节」（来源 / 内容 / 名 / 写），本件管「这份字节**准不准落盘**」——
//! 即架构收敛方案项 G10 的磁盘预算与 18.3-4 的数量上限。
//!
//! 子件能读父件的私有项（Rust 隐私：子模块看得见祖先的私项）。

use std::fs;
use std::path::Path;

use v1_contract::声明数据;

use super::缓存条目上限;

/// **缓存账** —— 缓存目录里现有多少条缓存件、共占多少字节（跳过 `.临时` 残件）。
///
/// 读不到目录 ⇒ `(0, 0)`（没有缓存根 = 还没有占，不是错误）。
fn 缓存目录账(缓存根目录: &Path) -> (usize, u64) {
    let Ok(读目录) = fs::read_dir(缓存根目录) else {
        return (0, 0);
    };
    let mut 缓存件条数 = 0usize;
    let mut 字节数 = 0u64;
    for 明细条目 in 读目录.flatten() {
        if 明细条目.file_name().to_string_lossy().ends_with(".临时") {
            continue;
        }
        let Ok(文件属性) = 明细条目.metadata() else {
            continue;
        };
        if 文件属性.is_file() {
            缓存件条数 += 1;
            字节数 += 文件属性.len();
        }
    }
    (缓存件条数, 字节数)
}

/// **落盘前判预算**（架构收敛方案项 G10 的两条：磁盘预算 + 缓存条目上限）。
///
/// 两条都是**上限**不是**目标**：正常装载摸不到它们；摸到了就是「这台机器上这个执行域
/// 的落盘不该再涨」。判定在**写之前**（不是写完再删）—— 与 `读制品有上限` 同一条
/// 「先判再分配」：拒的时候一个字节都不落。
pub(crate) fn 判缓存预算(缓存根目录: &Path, 本件字节: u64) -> Result<(), String> {
    let (缓存件条数, 已占字节) = 缓存目录账(缓存根目录);
    if 缓存件条数 >= 缓存条目上限 {
        return Err(format!(
            "缓存目录已有 {缓存件条数} 条缓存件，达上限 {缓存条目上限} ⇒ 不再落盘（缓存件按内容指纹定键、永不自动删；请清缓存或改预算）"
        ));
    }
    if 已占字节 + 本件字节 > 声明数据::磁盘预算 {
        return Err(format!(
            "缓存目录已占 {已占字节} 字节，再加本件 {本件字节} 字节会超过磁盘预算 {} 字节 ⇒ 不再落盘",
            声明数据::磁盘预算
        ));
    }
    Ok(())
}

#[cfg(test)]
mod 预算测试 {
    use super::*;

    /// **缓存条目上限**：缓存目录已有 `缓存条目上限` 条缓存件 ⇒ 再落盘一律拒。
    ///
    /// 缓存件按内容指纹定键、**永不自动删** —— 没有这条上界，反复换制品会把目录撑到无界。
    #[test]
    fn 缓存条目达上限即拒() {
        let 缓存目录 = std::env::temp_dir()
            .join(format!("装载件缓存预算-条数-{}", std::process::id()));
        let _ = fs::remove_dir_all(&缓存目录);
        fs::create_dir_all(&缓存目录).unwrap();
        for 序号 in 0..缓存条目上限 {
            fs::write(缓存目录.join(format!("占位{序号}")), b"x").unwrap();
        }
        let 拒因 = 判缓存预算(&缓存目录, 1).unwrap_err();
        assert!(拒因.contains("达上限"), "该报缓存条目达上限：{拒因}");
        let _ = fs::remove_dir_all(&缓存目录);
    }

    /// **磁盘预算**：缓存目录已占字节 + 本件字节越过 `磁盘预算` ⇒ 拒（判在写之前）。
    #[test]
    fn 磁盘预算越界即拒() {
        let 缓存目录 = std::env::temp_dir()
            .join(format!("装载件缓存预算-磁盘-{}", std::process::id()));
        let _ = fs::remove_dir_all(&缓存目录);
        fs::create_dir_all(&缓存目录).unwrap();
        fs::write(缓存目录.join("占位"), b"x").unwrap();
        assert!(判缓存预算(&缓存目录, 声明数据::磁盘预算 - 1).is_ok(), "预算内该放行");
        let 拒因 = 判缓存预算(&缓存目录, 声明数据::磁盘预算).unwrap_err();
        assert!(拒因.contains("磁盘预算"), "该报超磁盘预算：{拒因}");
        let _ = fs::remove_dir_all(&缓存目录);
    }
}
