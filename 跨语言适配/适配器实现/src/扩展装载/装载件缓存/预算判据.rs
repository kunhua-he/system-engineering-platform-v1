//! 装载件缓存 · 预算判据 —— 落盘前的两条上限（磁盘预算 · 缓存条目上限），到线**自我恢复**。
//!
//! 从 `装载件缓存.rs` 拆出（单源 ≤ 800 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管「从盘上取一份字节」（来源 / 内容 / 名 / 写），本件管「这份字节**准不准落盘**」——
//! 即架构收敛方案项 G10 的磁盘预算与 18.3-4 的数量上限。
//!
//! # 到线不是拒服务
//!
//! 缓存件按内容指纹定键、键随内容变 ⇒ 反复构建会把目录堆到上限。旧形状在这里**硬拒**
//! （「不再落盘，请清缓存」）—— 它把「缓存满了」变成「服务起不来」，而缓存本来是**可丢 · 可重建**的
//! （父件文件头）。故到线一律**按最旧优先淘汰**：先清 `.临时` 残件，再按修改时刻从旧到新删，
//! 腾到线下继续落盘。只有**单件自身就超磁盘预算**才报错 —— 那种件腾多少位都装不下。
//!
//! 子件能读父件的私有项（Rust 隐私：子模块看得见祖先的私项）。

use std::fs;
use std::path::{Path, PathBuf};
use std::time::SystemTime;

use v1_contract::声明数据;

use super::缓存条目上限;

/// **在写件不算脏件** —— `.临时` 件的修改时刻落在这条线内，视为别的执行域正在写它。
///
/// **为什么要有**：`.临时` 件在正常落盘期间本来就存在（`写入缓存件` 写临时件 → `hard_link` 发布）。
/// 一律删会把并发写方的临时件删掉，让它的原子发布当场 `NotFound`（`同键并发只见完整制品` 就是这么红起来的）。
/// 一次落盘是毫秒级，300 秒只是「明显不是正在写」那条线，不是「优化」那条线。
const 临时件陈旧秒数: u64 = 300;

/// 一条缓存件的读数：落点路径 · 字节数 · 修改时刻。
struct 缓存件读数 {
    路径: PathBuf,
    字节: u64,
    修改时刻: SystemTime,
}

/// **腾位读数** —— 这一趟腾掉了什么：清了几件 `.临时` 残件、淘汰了几件缓存件。
pub(crate) struct 腾位读数 {
    pub 清临时数: usize,
    pub 淘汰数: usize,
}

/// **缓存账** —— 缓存目录里现有多少条缓存件、共占多少字节、每件的（路径 · 字节 · 修改时刻）。
///
/// 跳过 `.临时` 残件：它们不是缓存件，是中断写入的垃圾（不算条数、不算占用，由腾位清掉）。
/// 读不到目录 ⇒ `(0, 0, 空表)`（没有缓存根 = 还没有占，不是错误）。
fn 缓存目录账(缓存根目录: &Path) -> (usize, u64, Vec<缓存件读数>) {
    let Ok(读目录) = fs::read_dir(缓存根目录) else {
        return (0, 0, Vec::new());
    };
    let mut 明细表: Vec<缓存件读数> = Vec::new();
    for 明细条目 in 读目录.flatten() {
        if 明细条目.file_name().to_string_lossy().ends_with(".临时") {
            continue;
        }
        let Ok(文件属性) = 明细条目.metadata() else {
            continue;
        };
        if !文件属性.is_file() {
            continue;
        }
        明细表.push(缓存件读数 {
            路径: 明细条目.path(),
            字节: 文件属性.len(),
            修改时刻: 文件属性.modified().unwrap_or(SystemTime::UNIX_EPOCH),
        });
    }
    let 字节数 = 明细表.iter().map(|缓存件| 缓存件.字节).sum();
    (明细表.len(), 字节数, 明细表)
}

/// **扫 `.临时` 件** —— 交回**陈旧残件**的路径（在写件不交：别人正写着，删它就是拆别人的原子发布）。
///
/// 证不出「陈旧」的一律当在写件（修改时刻读不到 / 落在未来）：宁可留下一件垃圾，也不拆别人的原子发布。
fn 扫陈旧临时件(缓存根目录: &Path, 现在: SystemTime) -> Vec<PathBuf> {
    let Ok(读目录) = fs::read_dir(缓存根目录) else {
        return Vec::new();
    };
    let mut 陈旧残件: Vec<PathBuf> = Vec::new();
    for 明细条目 in 读目录.flatten() {
        if !明细条目.file_name().to_string_lossy().ends_with(".临时") {
            continue;
        }
        let Ok(文件属性) = 明细条目.metadata() else {
            continue;
        };
        if !文件属性.is_file() {
            continue;
        }
        // 证不出「陈旧」就当在写件：恰在本函数取 `现在` 之后由别的执行域新建的临时件，
        // 修改时刻会比 `现在` 还新（`duration_since` 于是失败）—— 删它等于拆别人的原子发布。
        let 还很新 = 文件属性
            .modified()
            .ok()
            .and_then(|时刻| 现在.duration_since(时刻).ok())
            .is_none_or(|已过| 已过.as_secs() < 临时件陈旧秒数);
        if !还很新 {
            陈旧残件.push(明细条目.path());
        }
    }
    陈旧残件
}

/// **清缓存腾位** —— 把缓存目录腾到「装得下本件」为止，交回这一趟腾掉了什么。
///
/// 两步：① 先删陈旧 `.临时` 残件（中断写入的垃圾：不占条数却永久占盘）；② 再按修改时刻
/// **最旧优先**逐件删，直到 `条数 + 1 ≤ 上限` 且 `已占 + 本件 ≤ 磁盘预算`。
///
/// **删失败就跳过**（权限 / 被占用）：一件删不掉不该让整趟腾位停下 —— 跳过它继续腾下一件；
/// 腾到腾不动了由 [`判缓存预算`] 如实报出，不在这里吞掉结论。
pub(crate) fn 清缓存腾位(缓存根目录: &Path, 本件字节: u64) -> 腾位读数 {
    let mut 读数 = 腾位读数 {
        清临时数: 0,
        淘汰数: 0,
    };
    for 残件路径 in 扫陈旧临时件(缓存根目录, SystemTime::now()) {
        if fs::remove_file(&残件路径).is_ok() {
            读数.清临时数 += 1;
        }
    }
    let (mut 条数, mut 已占字节, mut 明细表) = 缓存目录账(缓存根目录);
    明细表.sort_by(|前件, 后件| {
        前件.修改时刻
            .cmp(&后件.修改时刻)
            .then_with(|| 前件.路径.cmp(&后件.路径))
    });
    for 缓存件 in 明细表 {
        if 条数 < 缓存条目上限 && 已占字节 + 本件字节 <= 声明数据::磁盘预算 {
            break;
        }
        if fs::remove_file(&缓存件.路径).is_ok() {
            读数.淘汰数 += 1;
            条数 = 条数.saturating_sub(1);
            已占字节 = 已占字节.saturating_sub(缓存件.字节);
        }
    }
    读数
}

/// **落盘前判预算**（架构收敛方案项 G10 的两条：磁盘预算 + 缓存条目上限）。
///
/// 两条都是上限不是目标：正常装载摸不到它们。摸到了**先腾位再判** —— 到线不等于不能落盘，
/// 缓存可丢可重建，腾掉最旧的继续落（见本件文件头「到线不是拒服务」）。
///
/// 唯一还报错的情形是**本件自身就超磁盘预算**：那种件把整个缓存删空也装不下，
/// 腾位不是它的解法，只能如实拒 —— 且拒之前一件都不删（不白搭别人的缓存）。
pub(crate) fn 判缓存预算(缓存根目录: &Path, 本件字节: u64) -> Result<(), String> {
    if 本件字节 > 声明数据::磁盘预算 {
        return Err(format!(
            "单件 {本件字节} 字节超过磁盘预算 {} 字节 ⇒ 不落盘（腾位救不了：把整个缓存删空也装不下它）",
            声明数据::磁盘预算
        ));
    }
    let 腾位 = 清缓存腾位(缓存根目录, 本件字节);
    let (缓存件条数, 已占字节, _) = 缓存目录账(缓存根目录);
    if 缓存件条数 + 1 > 缓存条目上限 || 已占字节 + 本件字节 > 声明数据::磁盘预算 {
        return Err(format!(
            "缓存目录腾位后仍装不下本件 {本件字节} 字节：清临时 {} 件 · 淘汰 {} 件后仍余 {缓存件条数} 条（上限 {缓存条目上限}）· {已占字节} 字节（磁盘预算 {} 字节）⇒ 不落盘",
            腾位.清临时数,
            腾位.淘汰数,
            声明数据::磁盘预算
        ));
    }
    Ok(())
}

#[cfg(test)]
mod 预算测试 {
    use super::super::{由内容算, 解包到缓存};
    use super::*;
    use std::time::Duration;
    use v1_contract::容器;

    struct 测试目录 {
        目录根: PathBuf,
    }
    impl Drop for 测试目录 {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.目录根);
        }
    }
    /// 建一套「制品根 + 缓存目录」的夹具（缓存目录预建好，与生产落点同形）。
    fn 建缓存目录() -> 测试目录 {
        for 临时序号 in 0..128 {
            let 时间戳 = SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|已过| 已过.as_nanos())
                .unwrap_or(0);
            let 目录根 = std::env::temp_dir().canonicalize().unwrap().join(format!(
                "装载件缓存预算-{}-{时间戳}-{临时序号}",
                std::process::id()
            ));
            match fs::create_dir(&目录根) {
                Ok(()) => {
                    fs::create_dir(目录根.join("缓存")).unwrap();
                    return 测试目录 { 目录根 };
                }
                Err(错误) if 错误.kind() == std::io::ErrorKind::AlreadyExists => continue,
                Err(错误) => panic!("创建测试目录失败：{错误}"),
            }
        }
        panic!("测试目录竞争次数超限")
    }
    /// 造一件旧缓存件：`set_len` 出稀疏件（字节数算得够、真占盘近乎零），修改时刻拨到指定处。
    fn 造旧件(路径: &Path, 字节数: u64, 时刻: SystemTime) {
        let 缓存文件 = fs::File::create(路径).unwrap();
        缓存文件.set_len(字节数).unwrap();
        缓存文件
            .set_times(fs::FileTimes::new().set_modified(时刻))
            .unwrap();
    }

    /// **缓存条目达上限 ⇒ 淘汰最旧的之后仍能落盘**。
    ///
    /// 旧口径是「到上限即拒」，那等于把「缓存满了」变成「服务起不来」（2026-10-28 实测：目录到 256 条后
    /// 门禁装载当场失败，看起来像代码坏了）。回归钉两点：条数仍 ≤ 上限**且**最旧那件真被删、次旧还在
    /// —— 证明是「按最旧淘汰到够位」，不是「清空整目录」也不是「一件没删」。
    #[test]
    fn 缓存条目达上限_淘汰最旧后仍可落盘() {
        let 测试根 = 建缓存目录();
        let 缓存目录 = 测试根.目录根.join("缓存");
        let 现在 = SystemTime::now();
        for 序号 in 0..缓存条目上限 {
            let 时刻 = 现在 - Duration::from_secs((缓存条目上限 - 序号) as u64);
            造旧件(&缓存目录.join(format!("旧件{序号:04}")), 1, 时刻);
        }
        let 最旧 = 缓存目录.join("旧件0000");
        let 次旧 = 缓存目录.join("旧件0001");
        assert!(最旧.exists() && 次旧.exists());
        let 制品文件 = 测试根.目录根.join("样例.支持库制品");
        fs::write(&制品文件, 容器::装包(b"interface", b"native-code")).unwrap();
        let 落点 = 解包到缓存(&制品文件, &缓存目录)
            .expect("到上限必须靠自身腾位落下去，不是拒服务");
        assert_eq!(fs::read(&落点).unwrap(), b"native-code");
        assert!(!最旧.exists(), "最旧的那件该被淘汰：{}", 最旧.display());
        assert!(次旧.exists(), "只该淘汰到够位为止，却多删了：{}", 次旧.display());
        let 条数 = fs::read_dir(&缓存目录).unwrap().count();
        assert!(条数 <= 缓存条目上限, "条数 {条数} 越上限 {}", 缓存条目上限);
    }

    /// **脏件（①）**：陈旧 `.临时` 残件被清掉；**在写的那件不动** —— 删它会拆掉并发写方的原子发布。
    #[test]
    fn 陈旧临时残件清掉而在写件保留() {
        let 测试根 = 建缓存目录();
        let 缓存目录 = 测试根.目录根.join("缓存");
        let 现在 = SystemTime::now();
        let 残件 = 缓存目录.join(".中断写入.临时");
        造旧件(&残件, 8, 现在 - Duration::from_secs(临时件陈旧秒数 * 4));
        let 在写件 = 缓存目录.join(".正在写.临时");
        造旧件(&在写件, 8, 现在);
        assert!(判缓存预算(&缓存目录, 1).is_ok());
        assert!(!残件.exists(), "陈旧残件该被清掉：{}", 残件.display());
        assert!(在写件.exists(), "在写的临时件不许删（并发写方的原子发布靠它）");
    }

    /// **磁盘预算**：造两件过半预算的件 ⇒ 超预算 ⇒ 淘汰最旧的之后照样落盘。
    #[test]
    fn 磁盘预算超额_淘汰最旧后落盘成功() {
        let 测试根 = 建缓存目录();
        let 缓存目录 = 测试根.目录根.join("缓存");
        let 现在 = SystemTime::now();
        let 每件字节 = 声明数据::磁盘预算 / 2 + 1;
        造旧件(&缓存目录.join("旧件先"), 每件字节, 现在 - Duration::from_secs(60));
        造旧件(&缓存目录.join("旧件后"), 每件字节, 现在 - Duration::from_secs(30));
        assert!(
            判缓存预算(&缓存目录, 1).is_ok(),
            "超磁盘预算该靠腾位解决，不是拒服务"
        );
        assert!(!缓存目录.join("旧件先").exists(), "最旧的先淘汰");
        assert!(缓存目录.join("旧件后").exists(), "腾到够位就停，不多删");
        let 制品文件 = 测试根.目录根.join("样例.支持库制品");
        fs::write(&制品文件, 容器::装包(b"interface", b"native-code")).unwrap();
        let 落点 = 解包到缓存(&制品文件, &缓存目录).expect("腾位之后这条链照旧走得通");
        assert_eq!(fs::read(&落点).unwrap(), b"native-code");
    }

    /// **唯一还报错的**：单件自身就超磁盘预算 ⇒ 拒，文案点明「单件」（不再喊「请清缓存」这种要人手干的）。
    #[test]
    fn 单件自身超磁盘预算_仍报错且点名单件() {
        let 测试根 = 建缓存目录();
        let 缓存目录 = 测试根.目录根.join("缓存");
        造旧件(&缓存目录.join("旧件"), 1, SystemTime::now());
        let 拒因 = 判缓存预算(&缓存目录, 声明数据::磁盘预算 + 1).unwrap_err();
        assert!(拒因.contains("单件"), "该点名「单件」：{拒因}");
        assert!(拒因.contains("磁盘预算"), "该点名「磁盘预算」：{拒因}");
        assert!(
            缓存目录.join("旧件").exists(),
            "本件装不下时不许白删别人的缓存件"
        );
    }

    /// **脏件（②）**：命中后校验不过（长度不符 / 内容不符）⇒ 删该件当未命中、按原路重写，条数不涨。
    #[test]
    fn 脏缓存件当未命中重写且条数不增() {
        let 测试根 = 建缓存目录();
        let 缓存目录 = 测试根.目录根.join("缓存");
        let 制品文件 = 测试根.目录根.join("样例.支持库制品");
        fs::write(&制品文件, 容器::装包(b"interface", b"native-code")).unwrap();
        let 落点 = 缓存目录.join(由内容算(b"native-code"));
        for 脏字节 in [b"broken".as_slice(), b"native-kode".as_slice()] {
            fs::write(&落点, 脏字节).unwrap();
            let 重写落点 = 解包到缓存(&制品文件, &缓存目录)
                .expect("脏件该当未命中重写，不是报错");
            assert_eq!(重写落点, 落点, "重写落在同一个内容定键上");
            assert_eq!(
                fs::read(&落点).unwrap(),
                b"native-code",
                "脏件该被正确内容换掉"
            );
            assert_eq!(
                fs::read_dir(&缓存目录).unwrap().count(),
                1,
                "重写不该多出一件"
            );
        }
    }
}
