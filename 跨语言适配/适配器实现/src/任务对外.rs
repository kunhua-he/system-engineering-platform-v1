//! 任务对外 —— 图任务的**对外面**：提交 · 查询 · 取消 · 释放 · 等待。
//!
//! # 只做接线，不做调度
//!
//! 图的推进、状态机、资源车道全在 `运行内核/调用调度`（经
//! [`调用任务装配`](crate::调用任务装配) 装配成 [`调度实例`](crate::调用任务装配::调度实例)）。
//! 本面管三件**实例级**的事实：
//!
//! 1. **任务表**：任务标识 → 任务条目（实例 · 节点表 · 取消旗 · 失败表 · 末次访问），
//!    带容量与收口清扫（跑一晚不许变成内存泄漏）。
//! 2. **幂等**：同 `请求标识` + 同图摘要 ⇒ 回原任务标识；同标识不同图 ⇒ 明确冲突。
//! 3. **输入引用**：上游节点的产出槽在**执行时**取出填进下游行序；取不到就节点失败，
//!    **不编值**。
//!
//! # 状态挂实例，不落 static
//!
//! 任务表是 `Arc<Mutex<..>>`，按适配器实例持有、跨执行快照共享（与 `在途执行数` 同一理由：
//! 换一版声明不该把在途任务抹掉）。模块级 static 会让同进程两份适配器共用一张表 —— 那正是
//! 判据 4「接缝 0 状态」要挡的形态。
//!
//! # 件与分工
//!
//! | 件 | 管什么 |
//! |---|---|
//! | [`请求形状`](请求形状.rs) | 对外数据结构：节点请求 · 入参值 · 快照 · 取消读数 · 拒绝 |
//! | [`节点计划`](节点计划.rs) | 命名值按契约映射成行序 + 引用补位表 + 资源键 |
//! | [`图任务叶子`](图任务叶子.rs) | 唯一叶子：执行时补引用、执行后登记产出与失败 |
//! | [`任务表`](任务表.rs) | 发号 · 幂等 · 快照 · 取消 · 释放 · 淘汰 |
//! | [`适配器接线`](适配器接线.rs) | `适配器` 上的五个公开方法（提交 / 查询 / 取消 / 释放 / 等待） |

