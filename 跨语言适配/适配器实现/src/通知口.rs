//! 通知口 —— 适配器的通知腿。
//!
//! 适配器公开面没有通知口 ⇒ 扩展就算申报了生命周期号段也送不到
//! （现在就绪/健康读数只能走旁路 `GET /接口` + 启动 stdout）。本文件补上这条腿：
//!
//! ```text
//! 装载声明根   →  扩展申报的 `通知函数` 登记成端点（「申报了就送得到」）
//! 请求卸载     →  发 `2001 卸载`；扩展回 `2015` ⇒ 请求延迟释放（端点保留，允许被拒绝）
//! 延迟释放协商 →  引用清零后发 `2003 延迟释放`；回成功 ⇒ **完整收回**
//! ```
//!
//! 本层**只做形状翻译**：没有一处按具体通知号写特例（`2001` / `2003` 由 `通知通道` 定）。
//!
//! # 两种入口：按指针（C 面）与按标识（文本面）
//!
//! `通知通道` 的公开口收的是 `*const u8`（契约里的静态标识串指针）。Rust 调用方与
//! HTTP 面手里只有**文本** ⇒ 本层再给一组**按标识**的入口（`请求卸载按标识` 等），
//! 用 [`通知账`] 的索引把文本翻成指针。索引**不是第二份端点表**：端点表的权威仍在
//! `通知通道` 里，索引只做「文本 → 指针」的查找（见 `线程安全.rs`）。
//!
//! # 状态在哪
//!
//! 端点表在 [`通知通道`](crate::通知通道) 里，索引在 [`通知账`] 里，两者**同一把锁**
//! （`适配器.通知`）。本层不另存任何状态。

use v1_notify::{派发结果, 通知函数};

use crate::线程安全::{通知标识项, 取锁};
use crate::适配器;

impl 适配器 {
    /// 通知口：已注册的通知端点数（验证面用；不参与派发）。
    pub fn 通知端点数(&self) -> u32 {
        取锁(&self.通知).通道实例.端点数()
    }

    /// 通知口：补登记一个通知端点。装载时已自动登记**申报过** `通知函数` 的扩展，
    /// 这里给「声明里没带、由部署侧补挂」的端点用。重复标识串保留先注册的那个。
    ///
    /// 签名从 `&mut self` 改成 `&self`：索引与端点表都在 `Mutex` 里，改表不再需要独占借用。
    // 与 `通知通道::注册通知端点` 同一条处置：本函数确实会读 `标识串` 指向的字节（契约保证它是
    // 静态只读 NUL 结尾串，`读契约串` 自带长度上限兜底），故保持安全函数、显式登记例外。
    #[allow(clippy::not_unsafe_ptr_arg_deref)]
    pub fn 注册通知端点(&self, 本扩展标识串: *const u8, 端点函数: 通知函数) {
        if 本扩展标识串.is_null() {
            return;
        }
        let mut 通知账本 = 取锁(&self.通知);
        // 索引先记：文本 → 指针。已在表里的标识串不记第二次（与端点表同一条「标识串唯一」）。
        // SAFETY: 标识串按契约是静态只读 NUL 结尾串（注册方保证）。
        let 源文本 = unsafe { crate::契约读取::读契约串(本扩展标识串) };
        if !通知账本.标识表.iter().any(|标识项| 标识项.本扩展标识串 == 源文本) {
            通知账本.标识表.push(通知标识项 { 本扩展标识串: 源文本, 指针: 本扩展标识串 });
        }
        通知账本.通道实例.注册通知端点(本扩展标识串, 端点函数);
    }

    /// 通知口：宿主 → 扩展的**派发下行通知**（通知号 1–999）。号不在下行段 / 没有接收方
    /// ⇒ [`派发结果::未命中`]（宪法第 6 条：未命中不是错误）。
    ///
    /// # Safety
    /// `参数一` / `参数二` 的含义由号段决定，调用方必须按号段约定传。
    pub unsafe fn 下行通知(&self, 通知号: u32, 参数一: usize, 参数二: usize) -> 派发结果 {
        // SAFETY: 由调用方按号段约定保证参数含义。
        // 边界处包一次：C ABI 那面收的是裸 `u32`，公开签名不动，内里走号空间型。
        unsafe { 取锁(&self.通知).通道实例.派发下行通知(v1_contract::通知号::构造(通知号), 参数一, 参数二) }
    }

    /// 通知口：**装载通知**（发 `2000 装载`）—— 扩展被载入后宿主通知它一次。
    ///
    /// 结局同 [`适配器::下行通知`]：端点回 `失败` ⇒ `失败`；回 `延迟释放` ⇒ `请求延迟释放`；
    /// 全部成功 ⇒ `成功`；该标识串没有端点 ⇒ `未命中`（不是错误）。**不收回端点**（与卸载不同）。
    ///
    /// `标识串` 必须指向 NUL 结尾的字节串（契约：标识串 = 32 位十六进制 + NUL）。
    pub fn 装载通知(&self, 本扩展标识串: *const u8) -> 派发结果 {
        取锁(&self.通知).通道实例.装载(本扩展标识串)
    }

    /// 通知口：**卸载请求**（发 `2001 卸载`）。扩展可回 `2015` 拒绝。
    ///
    /// - 端点不存在 ⇒ `未命中`（不是错误）。
    /// - 回 `2015` ⇒ [`派发结果::请求延迟释放`]：**允许被拒绝**，端点保留。
    /// - 回成功 ⇒ [`派发结果::成功`]：**完整卸载**（端点 + 路由 + 台账身份，同一把写锁下）。
    /// - 其余（含失败）⇒ [`派发结果::失败`]：fail-closed，端点保留。
    ///
    /// 取 `&mut self`、与 [`适配器::请求卸载按标识`] **同一实现**：把指针里的文本读出后走同一条
    /// 完整卸载路（**不许两套卸载语义**）。
    ///
    /// `标识串` 必须指向 NUL 结尾的字节串（契约：标识串 = 32 位十六进制 + NUL）。
    pub fn 请求卸载(&mut self, 本扩展标识串: *const u8) -> 派发结果 {
        self.问卸载指针(本扩展标识串, |通道实例, 指针| 通道实例.请求卸载(指针))
    }

    /// 通知口：**延迟释放协商**（⑥）—— 引用清零后宿主再问一次（发 `2003 延迟释放`）。
    ///
    /// 结局同 [`适配器::请求卸载`]：只有回成功才完整收回。与 `请求卸载` 分两个通知号，是因为
    /// 契约把「初次请求」(`2001`) 与「引用清零后的复核」(`2003`) 定成两个号。
    ///
    /// `标识串` 必须指向 NUL 结尾的字节串。
    pub fn 延迟释放协商(&mut self, 本扩展标识串: *const u8) -> 派发结果 {
        self.问卸载指针(本扩展标识串, |通道实例, 指针| 通道实例.延迟释放协商(指针))
    }

    // ── 按标识（文本）的入口：HTTP 面与 Rust 调用方走这一组 ──────────────────────

    /// 通知口：按**标识串文本**请求卸载。标识没注册过 ⇒ `未命中`（不是错误）。
    ///
    /// **卸载是完整状态转换**（不只是摘通知端点）：扩展回成功 ⇒ 同一写借用下一次做完两样 ——
    /// 摘通知端点索引 → [`适配器::收回装载`]（收回路由 + 注销台账身份）。
    /// 完成后该能力不再可调，且**同一身份可重新装载**（不再报「标识串非法」）。
    ///
    /// 取 `&mut self`：与 [`适配器::追加装载`] 对称，两者都改 `装载单元s` 与 `台账`，
    /// 由调用方（网关的 `RwLock`）持**写锁**保证独占，中途不释放（不许并发调用挤进来）。
    pub fn 请求卸载按标识(&mut self, 本扩展标识串: &str) -> 派发结果 {
        self.问卸载按标识(本扩展标识串, |通道实例, 指针| 通道实例.请求卸载(指针))
    }

    /// 通知口：按**标识串文本**做延迟释放协商。语义同 [`适配器::请求卸载按标识`]（也是完整卸载）。
    pub fn 延迟释放协商按标识(&mut self, 本扩展标识串: &str) -> 派发结果 {
        self.问卸载按标识(本扩展标识串, |通道实例, 指针| 通道实例.延迟释放协商(指针))
    }

    /// 指针形卸载：把指针里的文本读出后走 [`适配器::问卸载按标识`] —— **同一完整卸载实现**。
    ///
    /// 与 `按标识` 入口共用同一条路：指针形不再是“只摘端点”的第二套语义。空指针 ⇒ `未命中`。
    fn 问卸载指针(
        &mut self,
        本扩展标识串: *const u8,
        询问函数: impl FnOnce(&v1_notify::通知通道, *const u8) -> 派发结果,
    ) -> 派发结果 {
        if 本扩展标识串.is_null() {
            return 派发结果::未命中;
        }
        // SAFETY: 调用方按契约保证 标识串 指向静态只读 NUL 结尾串。
        let 源文本 = unsafe { crate::契约读取::读契约串(本扩展标识串) };
        self.问卸载按标识(&源文本, 询问函数)
    }

    /// 已注册端点的**标识串文本**（就绪/健康读数用；顺序 = 注册顺序）。
    ///
    /// 与 [`适配器::通知端点数`] 同源：都是同一把锁下的同一份账（索引与端点表同步增删）。
    pub fn 通知端点标识串(&self) -> Vec<String> {
        取锁(&self.通知)
            .标识表
            .iter()
            .map(|标识项| 标识项.本扩展标识串.clone())
            .collect()
    }

    /// 问卸载的共用体：文本 → 指针 → 问通道 → 成功则**完整收回**。
    ///
    /// 收回两样（都在调用方同一把写锁下，中途不释放）：
    /// ① 通知端点：`通知通道` 已摘，本层同步摘索引（否则就绪读数会虚高）；
    /// ② 路由 + 装载身份：交 [`适配器::收回装载`]（从 `装载单元s` 摘注册表 + 注销台账）。
    ///
    /// **只有成功才收回**：`请求延迟释放`（允许被拒绝）/ `失败`（fail-closed）/ `未命中`
    /// 都原样保留全部状态。
    fn 问卸载按标识(
        &mut self,
        本扩展标识串: &str,
        询问函数: impl FnOnce(&v1_notify::通知通道, *const u8) -> 派发结果,
    ) -> 派发结果 {
        let 关口结果 = {
            let mut 通知账本 = 取锁(&self.通知);
            let Some(字节位置) = 通知账本
                .标识表
                .iter()
                .position(|标识项| 标识项.本扩展标识串 == 本扩展标识串)
            else {
                return 派发结果::未命中;
            };
            let 指针 = 通知账本.标识表[字节位置].指针;
            let 关口结果 = 询问函数(&通知账本.通道实例, 指针);
            if 关口结果 == 派发结果::成功 {
                // 端点已由 `通知通道` 摘掉，索引同步摘掉（否则就绪读数会虚高）。
                通知账本.标识表.remove(字节位置);
            }
            关口结果
        };
        if 关口结果 == 派发结果::成功
            && let Some(已卸载声明) = self.按标识找声明(本扩展标识串)
        {
            // 收回路由 + 注销装载身份（底座与最后一份由 `收回装载` 保护，不摘）。
            self.收回装载(已卸载声明);
        }
        关口结果
    }
}
