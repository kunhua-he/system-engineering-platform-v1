//! 进程调用 · 适配器口 —— 适配器实例怎么开跨进程域表 · 登记域 · 把一条调用路由过去。
//!
//! 从 `进程调用.rs` 拆出（单源 ≤ 400 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管**表**（跨进程域表：建表 · 登记 · 取句柄 · 送一调用），本件管**适配器实例的口**
//! —— 开表 · 算域标识 · 调用跨进程（路由）。
//!
//! 子件能读父件的私有项（Rust 隐私：子模块看得见祖先的私项）—— 故本件直接用
//! 父件的 `送一调用按句柄` / `造跨进程错误槽` / `域部署` / `跨进程域表`，父件无需开口子。

use crate::进程池::{执行域标识, 进程池错误, 进程池配置};

use super::{送一调用按句柄, 造跨进程错误槽, 域部署, 跨进程域表};

#[cfg(unix)]
impl crate::适配器 {
    /// 开跨进程执行域表（不开则本实例全部走进程内路，一分钱不多花）。
    pub fn 开跨进程(&mut self, 配置: 进程池配置) {
        if self.跨进程.is_none() {
            self.跨进程 =
                Some(std::sync::Arc::new(std::sync::Mutex::new(跨进程域表::创建(配置))));
        }
    }

    /// 这个实例开过跨进程表没有。
    pub fn 有跨进程域(&self) -> bool {
        self.跨进程.is_some()
    }

    /// 按一份**已装载的**声明登记它的执行域（部署参数 = 从哪拉起那个扩展的工作进程）。
    ///
    /// **域表锁只包登记，不包握手**（本件 3071）：登记改完部署表当场放锁；随后的装载
    /// 初始化握手是长执行（拉起 + 装帧，可达一条调用预算），只锁**该域那一格的事务锁** ——
    /// 否则装载期间全部域（含健康域）的调用都被那一把表锁挡住。
    /// 收 `&self`（登记与握手都只经 `Arc<Mutex<..>>` 改域表，不动本实例别的字段）。
    pub fn 登记跨进程域(
        &self,
        声明: &v1_contract::平台信息,
        部署: 域部署,
    ) -> Result<(), 进程池错误> {
        let 标识 = self.按声明算域标识(声明)?;
        self.登记域并握手(标识, 部署)
    }

    /// **通用注册核心**：登记一条域（短表锁）+ 装载初始化握手（长执行只锁该域）。
    ///
    /// 支持库（按声明算身份）与模块（按包声明 + 段 16 算身份）**共用**这一段 ——
    /// 不复制第二套池、不复制第二套握手。
    fn 登记域并握手(&self, 标识: 执行域标识, 部署: 域部署) -> Result<(), 进程池错误> {
        let Some(域表) = self.跨进程.as_ref() else {
            return Err(进程池错误::域不存在);
        };
        // ① 登记改部署表：只持短表锁。
        {
            let mut 登记锁 = 取锁(域表);
            登记锁.登记跨进程域(标识.clone(), 部署)?;
        }
        // ② 握手不持表锁：短锁内取本域句柄与号源，长执行收窄到该域事务锁。
        let (句柄, 号源) = {
            let 域表锁 = 取锁(域表);
            (域表锁.取句柄(&标识), 域表锁.取号源())
        };
        let Some(句柄) = 句柄 else {
            return Err(进程池错误::域不存在);
        };
        if let Err(错误) = 跨进程域表::初始化一域按句柄(&句柄, 号源.as_ref()) {
            let _ = 取锁(域表).击杀跨进程域(&标识);
            return Err(错误);
        }
        Ok(())
    }

    /// **通用模块身份登记**：把一条模块能力登记成既有跨进程域（同一个池、同一个启动器）。
    ///
    /// 身份三件都**从盘上读出来**（不写号表、不认模块名）：
    /// - `模块身份串` = 模块 `包声明.json` 的 `标识串`；
    /// - `制品版本` = 同件的 `实现版本` 三元组；
    /// - `能力号` = 制品**段 16 接口说明**的 `编号`。
    ///
    /// 与 [`适配器::登记跨进程域`]（支持库）**共用** [`适配器::登记域并握手`]，不复制第二套池；
    /// 差别只在「身份从哪来」与「号怎么路由」（模块记路由表，声明按号找声明）。
    pub fn 登记模块跨进程域(
        &self,
        模块身份串: &str,
        制品版本: (u32, u32, u32),
        能力号: u32,
        部署: 域部署,
    ) -> Result<(), 进程池错误> {
        if 模块身份串.is_empty() {
            return Err(进程池错误::域不存在);
        }
        let 模块域标识 = 执行域标识 {
            适配器实例号: self.实例号,
            扩展标识串: 模块身份串.to_owned(),
            制品版本,
        };
        self.登记域并握手(模块域标识.clone(), 部署)?;
        // 握手成功才记路由：域没起来就记路由，调用会打到不存在的域。
        if let Some(域表) = self.跨进程.as_ref() {
            取锁(域表).登记模块路由(能力号, 模块域标识);
        }
        Ok(())
    }

    /// 这条号归哪个已装载单元 —— 判据与路由**同一套**（「谁认这个号就归谁」）。
    fn 按号找声明(&self, 号值: v1_contract::能力号) -> Option<&'static v1_contract::平台信息> {
        for 装载单元 in &self.装载单元s {
            if let v1_registry::命令槽::已载入 { .. } = 装载单元.注册表.按号取命令(号值) {
                return Some(装载单元.声明);
            }
        }
        None
    }

    /// 一份声明 → 它的执行域标识（`适配器实例 × 扩展标识 × 制品版本`）。
    fn 按声明算域标识(
        &self,
        声明: &v1_contract::平台信息,
    ) -> Result<执行域标识, 进程池错误> {
        if 声明.标识串.is_null() {
            return Err(进程池错误::域不存在);
        }
        // SAFETY: 契约保证 标识串 是静态只读 NUL 结尾串。
        let 扩展标识串 = unsafe { crate::契约读取::读契约串(声明.标识串) }.to_string();
        let 版本 = 声明.实现版本;
        Ok(执行域标识 {
            适配器实例号: self.实例号,
            扩展标识串,
            制品版本: (
                u32::try_from(版本.主版本).unwrap_or(0),
                u32::try_from(版本.次版本号).unwrap_or(0),
                u32::try_from(版本.构建).unwrap_or(0),
            ),
        })
    }

    /// 这个号有没有登记过跨进程域（登记过才走跨进程，否则 `None` ⇒ 走进程内原路）。
    fn 算域标识(&self, 号值: v1_contract::能力号) -> Option<执行域标识> {
        let 域表 = self.跨进程.as_ref()?;
        // **模块身份先命中**：模块的号不在任何已装载声明里（模块不是支持库声明），
        // 它的路由只在模块路由表里；命中就送工作进程，命中不到才回声明那条路。
        {
            let 域表锁 = 取锁(域表);
            if let Some(标识) = 域表锁.取模块域标识(号值.取号值())
                && 域表锁.含域(&标识)
            {
                return Some(标识);
            }
        }
        let 声明 = self.按号找声明(号值)?;
        let 标识 = self.按声明算域标识(声明).ok()?;
        if 取锁(域表).含域(&标识) { Some(标识) } else { None }
    }

    /// **击杀一个已登记域的工作进程**（验证面与部署下架用）。
    pub fn 击杀跨进程域(
        &mut self,
        声明: &v1_contract::平台信息,
    ) -> Result<(), 进程池错误> {
        let Some(域表) = self.跨进程.as_ref() else {
            return Err(进程池错误::域不存在);
        };
        let 标识 = self.按声明算域标识(声明)?;
        取锁(域表).击杀跨进程域(&标识)
    }

    /// **移除一个已登记域**（切换后回收旧版 / 部署下架）：杀进程组 + 摘域格 + 摘部署表。
    ///
    /// 与 [`适配器::击杀跨进程域`] 分开：击杀只杀进程、留登记（下次调用重拉）；移除把登记也摘。
    /// 取 `&self`：只经 `Arc<Mutex<..>>` 改域表，与 [`适配器::调用跨进程`] 同一把锁。
    pub fn 移除跨进程域(&self, 声明: &v1_contract::平台信息) -> bool {
        let Some(域表) = self.跨进程.as_ref() else {
            return false;
        };
        let Ok(标识) = self.按声明算域标识(声明) else {
            return false;
        };
        取锁(域表).移除一域(&标识)
    }

    /// **卸载一个模块域**（按能力号）：杀进程组 + 摘域格 + 摘部署表 + 摘路由。
    ///
    /// 与 [`适配器::移除跨进程域`] 对称：那条按声明算身份，这条按号找路由 ——
    /// 模块没有声明，卸载口只给得出号。
    pub fn 移除模块跨进程域(&self, 能力号: u32) -> bool {
        let Some(域表) = self.跨进程.as_ref() else {
            return false;
        };
        取锁(域表).移除模块域(能力号)
    }

    /// 这个号登记过模块域没有（验证面读）。
    pub fn 模块域已登记(&self, 能力号: u32) -> bool {
        let Some(域表) = self.跨进程.as_ref() else {
            return false;
        };
        取锁(域表).取模块域标识(能力号).is_some()
    }

    /// **跨进程调用路**：这个号登记过域 ⇒ 送工作进程并收结果；没登记 ⇒ `None`（调用方走原路）。
    ///
    /// 失败（拉起不了 / 熔断中 / 通道断开 / 回载不成形）⇒ 返回槽里写结构化 `0034` 并回
    /// [`crate::转发结果::成功`] —— 「协议层成立、失败在返回槽里」与 `边界面.rs` 同一口径
    /// （业务失败不走协议码）。**不 panic · 不给调度错误加进程变体**。
    pub(crate) fn 调用跨进程(
        &self,
        号值: v1_contract::能力号,
        入参: &[v1_contract::数据槽],
        返回槽: &mut v1_contract::数据槽,
    ) -> Option<crate::转发结果> {
        let 标识 = self.算域标识(号值)?;
        let 域表 = self.跨进程.as_ref()?;
        // ★ **锁收窄**（冻结件 §五 末行）：域表锁**只用于取引用**（部署副本 + 域句柄 +
        // 号源），三样一次取出后**当场放锁**；长执行（收发）**不持表锁** ——
        // 否则一个慢域把全部域阻塞。句柄自带该域的互斥，慢域只锁本域那一格。
        let (部署, 句柄, 号源) = {
            let 域表锁 = 取锁(域表);
            let 部署 = 域表锁.取部署(&标识)?;
            let 句柄 = 域表锁.取句柄(&标识)?;
            (部署, 句柄, 域表锁.取号源())
        };
        // 内层留痕回传口：工作进程经 `留痕记录` 帧送来的记录，收进本实例同一份留痕缓冲
        // （唯一写口）。没开留痕时 `收下外来留痕` 一条不收（与本地同口径）。
        let 收痕口 = |留痕项: &v1_trace::留痕| self.收下外来留痕(留痕项);
        let 读数 = 送一调用按句柄(&句柄, &部署, &号源, 号值.取号值(), 入参, Some(&收痕口));
        match 读数 {
            Ok(槽体) => {
                *返回槽 = 槽体;
                Some(crate::转发结果::成功(槽体))
            }
            Err(码值) => {
                let 槽体 = 造跨进程错误槽(码值);
                *返回槽 = 槽体;
                Some(crate::转发结果::成功(槽体))
            }
        }
    }
}

use crate::线程安全::取锁;
