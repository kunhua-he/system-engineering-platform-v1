/// 判据：字符串转义**只做必须做的**（`"` `\` 与 `U+0000..U+001F`），非 ASCII 原样 UTF-8。
#[test]
fn 小写出_转义_引号反斜杠控制字符都转() {
    assert_eq!(
        写(&值::文本("a\"b\\c\nd\u{1}".to_owned())),
        r#""a\"b\\c\nd\u0001""#
    );
    // 非 ASCII 原样走 UTF-8（不转 `\uXXXX`）。
    assert_eq!(写(&值::文本("接口".to_owned())), "\"接口\"");

    // ── 反向样本：裸控制字符**不许**出现在输出里（它就是非法 JSON 的来源）──
    let 输出 = 写(&值::文本("\u{0}\u{1f}".to_owned()));
    assert!(
        !输出.chars().any(|字| (字 as u32) < 0x20),
        "输出里不许有裸控制字符"
    );
    assert!(输出.contains("\\u0000") && 输出.contains("\\u001f"));
}

/// 判据：六种形状各写对；键序 = 插入序 ⇒ 同一份数据两次序列化逐字节相同。
#[test]
fn 小写出_形状与确定性() {
    assert_eq!(写(&值::空), "null");
    assert_eq!(写(&值::真), "true");
    assert_eq!(写(&值::假), "false");
    assert_eq!(写(&值::整数(-7)), "-7");
    assert_eq!(写(&值::数组(Vec::new())), "[]");
    assert_eq!(写(&值::对象(Vec::new())), "{}");

    let 造 = || {
        值::对象(vec![
            ("首项".to_owned(), 值::整数(1)),
            ("次项".to_owned(), 值::数组(vec![值::真])),
        ])
    };
    assert_eq!(写(&造()), 写(&造()), "同一份数据两次序列化逐字节相同");
    assert_eq!(写(&造()), "{\n  \"首项\": 1,\n  \"次项\": [\n    true\n  ]\n}");
}

/// 判据：`平台_取接口描述` 交出的 JSON **括号与引号成对**（结构上不是半个形状）。
#[test]
fn 接口描述_括号与引号成对() {
    let 边界 = 对外边界::新建(&[v1_loader::底座声明()]).expect("底座");
    assert!(括号引号成对(&边界.取接口描述()), "真输出必须成对");

    // ── 反向样本：判据不是空转 ──
    assert!(括号引号成对("{ \"首项\": [1, 2] }"), "正向：平衡输入判通过");
    assert!(!括号引号成对("{ \"首项\": [1, 2] "), "反向样本：少一个 `}}` 必须判不通过");
    assert!(!括号引号成对("{ \"首项\": \"未闭合 }"), "反向样本：串没闭合必须判不通过");
    assert!(!括号引号成对("{ \"首项\": [1, 2} ]"), "反向样本：括号交叉必须判不通过");
}

/// 判据：`{}` `[]` 成对 · 字符串闭合（**只做平衡检查，不是解析器** —— 文件头写明不解析）。
fn 括号引号成对(文本: &str) -> bool {
    let mut 栈: Vec<char> = Vec::new();
    let mut 在串 = false;
    let mut 转义 = false;
    for 字 in 文本.chars() {
        if 在串 {
            if 转义 {
                转义 = false;
            } else if 字 == '\\' {
                转义 = true;
            } else if 字 == '"' {
                在串 = false;
            }
            continue;
        }
        match 字 {
            '"' => 在串 = true,
            '{' | '[' => 栈.push(字),
            '}' if 栈.pop() != Some('{') => return false,
            ']' if 栈.pop() != Some('[') => return false,
            _ => {}
        }
    }
    栈.is_empty() && !在串
}
