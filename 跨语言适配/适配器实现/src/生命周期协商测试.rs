//! ④⑤⑥ 的**真跑**读数 —— 扩展申报生命周期通知号段 → 适配器通知口登记端点 →
//! 请求卸载被拒（回 `2015`）→ 引用清零后复核 → 收回。
//!
//! 整文件即测试（`lib.rs` 用 `#[cfg(test)] #[path]` 挂进来）。跑法（看逐步打印的读数）：
//!
//! ```text
//! cargo test -p v1-adapter --locked 生命周期_申报号段到优雅卸载真跑通 -- --nocapture
//! ```
//!
//! 为什么算「真跑」：它建一份**真的** `平台信息`（与扩展经 `GetPlatformInfo` 交出的同一形状），
//! 走 [`适配器::装载声明根`] 全路径（判定六步 + 建表 + 通知口登记），再真的发 `2001` / `2003`。
//! 不是断言某个常量。

use core::sync::atomic::{AtomicUsize, Ordering};

use super::*;
use v1_contract::{号段, 表段, 版本三元组, 执行函数};

/// 扩展标识串（32 位十六进制 + NUL；与底座身份不同）。
static 扩展标识串: &[u8] = b"a1b2c3d4e5f60718293a4b5c6d7e8f90\0";
/// 扩展的能力号段：1xxx（与底座 0xxx 不冲突）。
static 能力号段表: [号段; 1] = [号段::新(1000, 1999)];
/// 扩展申报的**生命周期通知号段**：与底座预置的 2000–2999 同段。
static 通知号段表: [号段; 1] = [号段::新(2000, 2999)];
/// 错误段位表：段位 1（能力号段 1xxx 的首位）。
static 错误段位表: [u32; 1] = [1];

/// 「按指针」那条测试用的在飞引用计数：0 = 还有引用（拒绝卸载），非 0 = 已清零（放行）。
static 在飞引用: AtomicUsize = AtomicUsize::new(0);
/// 该测试收到通知的次数（读数用）。
static 收到通知: AtomicUsize = AtomicUsize::new(0);

/// 「按指针」那条测试的通知函数：`2001 卸载` / `2003 延迟释放` 时，若还有在飞引用 ⇒ 回 `2015` 拒绝。
unsafe extern "C" fn 扩展通知(通知号: v1_contract::通知号, _参数一: usize, _参数二: usize) -> isize {
    收到通知.fetch_add(1, Ordering::SeqCst);
    if matches!(通知号, 生命周期通知::卸载 | 生命周期通知::延迟释放)
        && 在飞引用.load(Ordering::SeqCst) == 0
    {
        通知返回::延迟释放
    } else {
        通知返回::成功
    }
}

/// 「按标识」那条测试的通知函数：**始终放行**（它验的是「按标识」那条路，与在飞引用无关）。
///
/// 两条测试各用**自身的通知函数**（故各用自身的 static）⇒ 不共享可变全局，可并行跑。
/// 此前两条共用一个 `static 在飞引用` ⇒ 并行时互相污染，谁先 store 谁说话，红在谁身上随机。
unsafe extern "C" fn 扩展通知放行(_通知号: v1_contract::通知号, _参数一: usize, _参数二: usize) -> isize {
    通知返回::成功
}

/// 演示扩展的执行函数（零参，回空）。
unsafe extern "C" fn 演示执行(_返回槽: *mut 数据槽, _参数个数: u32, _参数表: *const 数据槽) {}

/// 造一份演示扩展声明：能力 1xxx + **申报生命周期通知段 2000–2999** + 带给定的通知函数。
fn 造生命周期扩展(通知: unsafe extern "C" fn(v1_contract::通知号, usize, usize) -> isize) -> &'static 平台信息 {
    let 命令表: &'static [v1_registry::命令信息] = Box::leak(Box::new([v1_registry::命令信息 {
        名称: c"演示命令".as_ptr().cast::<u8>(),
        说明: c"演示扩展自用。".as_ptr().cast::<u8>(),
        类别: 0,
        状态位: 0,
        返回类型: v1_contract::类型标签::新(0),
        用户级别: 0,
        参数个数: 0,
        参数表: core::ptr::null(),
        编号: v1_contract::能力号::新(1000),
        可抛错误码: 表段::空(),
    }]));
    let 函数表: &'static [执行函数] = Box::leak(Box::new([演示执行 as 执行函数]));
    Box::leak(Box::new(平台信息 {
        声明格式号: v1_contract::声明格式号,
        目标字宽: v1_contract::声明数据::底座目标字宽,
        保留: 0,
        标识串: 扩展标识串.as_ptr(),
        实现版本: 版本三元组::新(1, 0, 0, 0),
        要求宿主版本: 版本三元组::新(1, 0, 0, 0),
        要求内核版本: 版本三元组::新(1, 0, 0, 0),
        名称: c"生命周期演示扩展".as_ptr().cast::<u8>(),
        说明: c"只演示生命周期通知，不参与平台语义。".as_ptr().cast::<u8>(),
        状态位: 0,
        类型表: 表段::空(),
        命令表: 表段::新(命令表.as_ptr(), 1),
        函数表: 函数表.as_ptr(),
        常量表: 表段::空(),
        通知函数: Some(通知),
        依赖清单: 表段::空(),
        能力号段: 表段::新(能力号段表.as_ptr(), 1),
        通知号段: 表段::新(通知号段表.as_ptr(), 1),
        错误段位表: 表段::新(错误段位表.as_ptr(), 1),
        错误码表: 表段::空(),
        命令类别表: 表段::空(),
        要求权限: 表段::空(),
    }))
}

#[test]
fn 生命周期_申报号段到优雅卸载真跑通() {
    在飞引用.store(0, Ordering::SeqCst);
    收到通知.store(0, Ordering::SeqCst);
    let 扩展 = 造生命周期扩展(扩展通知);

    // ④：扩展申报通知号段 [2000,2999]（与底座预置占用同段）——必须载得进来。
    // 旧行为：这里会被判 `号段冲突 { 2000, 2999 }`。
    let 适配器 = 适配器::装载声明根(&[v1_loader::底座声明(), 扩展])
        .expect("④ 扩展申报生命周期通知号段必须载得进来");
    println!(
        "④ 扩展申报通知号段 [2000,2999] → 装载成功（已装载声明 {} 份）",
        适配器.已装载声明数()
    );

    // ⑤：适配器通知口在装载时已把申报过的通知函数登记成端点（「申报了就送得到」）。
    println!("⑤ 适配器通知口已注册端点 {} 个", 适配器.通知端点数());
    assert_eq!(适配器.通知端点数(), 1, "恰好 1 个扩展端点（底座不算端点）");

    // ⑥-1：请求卸载（发 2001）——扩展还有在飞引用，回 2015 拒绝。
    let 结局 = 适配器.请求卸载(扩展.标识串);
    println!(
        "⑥-1 请求卸载（发 2001）→ 扩展回 2015 → 派发结果 {结局:?}（端点仍 {} 个）",
        适配器.通知端点数()
    );
    assert_eq!(结局, 派发结果::请求延迟释放);
    assert_eq!(适配器.通知端点数(), 1, "被拒的卸载必须原样保留端点");

    // ⑥-2：引用清零后复核（发 2003）——扩展回成功，端点收回。
    在飞引用.store(1, Ordering::SeqCst);
    let 结局 = 适配器.延迟释放协商(扩展.标识串);
    println!(
        "⑥-2 引用清零后复核（发 2003）→ 扩展回成功 → 派发结果 {结局:?}（端点剩 {} 个）",
        适配器.通知端点数()
    );
    assert_eq!(结局, 派发结果::成功);
    assert_eq!(适配器.通知端点数(), 0, "放行即收回：端点摘掉");
    println!("扩展共收到通知 {} 次", 收到通知.load(Ordering::SeqCst));
}

/// **按标识（文本）的卸载路**（HTTP 面走的就是这一组）：
/// 文本 → 指针 → 问通道 → 成功摘索引；标识没注册过 ⇒ `未命中`（不是错误）。
#[test]
fn 生命周期_按标识文本请求卸载真跑通() {
    let 扩展 = 造生命周期扩展(扩展通知放行);
    let 适配器 = 适配器::装载声明根(&[v1_loader::底座声明(), 扩展])
        .expect("扩展申报生命周期通知号段必须载得进来");

    // 文本来自契约里的标识串（去 NUL）—— 与 HTTP 面请求体里那串同形。
    let 标识文本 = core::str::from_utf8(&扩展标识串[..扩展标识串.len() - 1]).expect("标识串是 ASCII");
    assert_eq!(适配器.通知端点标识串(), vec![标识文本.to_owned()], "索引与端点表同源");

    // 没注册过的标识 ⇒ 未命中（宪法第 6 条：未命中不是错误）。
    assert_eq!(适配器.请求卸载按标识("ffffffffffffffffffffffffffffffff"), 派发结果::未命中);
    assert_eq!(适配器.通知端点数(), 1, "未命中不动端点表");

    // 已注册的标识 ⇒ 走真卸载：扩展回成功 ⇒ 收回，索引与端点表一起清。
    assert_eq!(适配器.请求卸载按标识(标识文本), 派发结果::成功);
    assert_eq!(适配器.通知端点数(), 0, "放行即收回：端点摘掉");
    assert!(适配器.通知端点标识串().is_empty(), "索引同步摘掉，就绪读数不虚高");
    println!("按标识卸载：{标识文本} → 成功，端点剩 0 个");
}
