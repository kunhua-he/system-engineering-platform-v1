/// 扩展的能力号段：1xxx（与底座 0xxx 不冲突）。
static 能力号段表: [号段; 1] = [号段::构造(1000, 1999)];
/// 扩展申报的**生命周期通知号段**：已登记生命周期号的上界 = 2015（闭集，2026-10-07 收紧）。
static 通知号段表: [号段; 1] = [号段::构造(2000, 2015)];
/// 错误段位表：段位 1（能力号段 1xxx 的首位）。
