/// 「按指针」那条测试用的在飞引用计数：0 = 还有引用（拒绝卸载），非 0 = 已清零（放行）。
static 在飞引用计数: AtomicUsize = AtomicUsize::new(0);
/// 该测试收到通知的次数（读数用）。
