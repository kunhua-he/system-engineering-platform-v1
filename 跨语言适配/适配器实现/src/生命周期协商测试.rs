/// **8.验收 · 生命周期交错端到端样本** —— 方案 §8.2 的验收句「调用、取消、装载、卸载和重启
/// 交错时，不提前释放、不串实例、不误用旧句柄；未完成卸载能返回明确状态而不是假成功」与
/// §13 阶段3 的「交错调用不误释放、不串状态、不假恢复」，在本样本里**真串一遍**（两份实例并存）：
///
/// ① 装载两份扩展（各占一段）→ ② 两份能力都可调（不串实例）→
/// ③ 卸载**被拒**（在飞引用未清零）⇒ 返回**明确状态**（不是假成功）· 份数与端点原样保留 ·
///    能力**照旧可调**（不提前释放）· 另一份一点不动（不串状态）→
/// ④ 引用清零后复核 ⇒ **真收回**（能力报 `提供者未载入` · 份数减一 · 旧端点摘掉 ⇒ 不误用旧句柄），
///    另一份照旧 →
/// ⑤ 重启 = 同身份重装 ⇒ **真恢复**（能力与端点都回来 ⇒ 不假恢复）。
#[test]
fn 交错_调用装载卸载重装交错不误释放不串状态() {
    交错首在飞.store(0, Ordering::SeqCst);
    let 首扩展 = 造交错扩展(交错首标识串, 1000, &交错首号段表, 交错首通知);
    let 次扩展 = 造交错扩展(交错次标识串, 2500, &交错次号段表, 交错次通知);
    let mut 适配器 = 适配器::装载声明根(&[v1_loader::底座声明(), 首扩展, 次扩展])
        .expect("两份扩展各占一段 ⇒ 都该载得进来");
    assert_eq!(适配器.已装载声明数(), 3, "底座 + 两份扩展");
    assert_eq!(适配器.通知端点数(), 2, "两份扩展各一个端点（底座不算端点）");

    let 首扩展标识 =
        core::str::from_utf8(&交错首标识串[..交错首标识串.len() - 1]).expect("标识串是 ASCII");
    let 次扩展标识 =
        core::str::from_utf8(&交错次标识串[..交错次标识串.len() - 1]).expect("标识串是 ASCII");

    // ② 调用：两份能力各自认各自的号（不串实例）。
    let mut 返回槽 = 数据槽::空槽();
    assert!(
        matches!(适配器.调用能力(1000, &[], &mut 返回槽), 转发结果::成功(_)),
        "首扩展能力该调得通"
    );
    assert!(
        matches!(适配器.调用能力(2500, &[], &mut 返回槽), 转发结果::成功(_)),
        "次扩展能力该调得通"
    );

    // ③ 卸载**被拒**：在飞引用未清零 ⇒ 明确状态（请求延迟释放），不是假成功。
    let 卸载前声明数 = 适配器.已装载声明数();
    assert_eq!(
        适配器.请求卸载按标识(首扩展标识),
        派发结果::请求延迟释放,
        "未完成卸载必须返回明确状态，不许假成功"
    );
    assert_eq!(适配器.已装载声明数(), 卸载前声明数, "被拒的卸载不许动份数");
    assert_eq!(适配器.通知端点数(), 2, "被拒的卸载必须原样保留端点（不误用旧句柄）");
    assert!(
        matches!(适配器.调用能力(1000, &[], &mut 返回槽), 转发结果::成功(_)),
        "卸载未完成 ⇒ 不许提前释放"
    );
    assert!(
        matches!(适配器.调用能力(2500, &[], &mut 返回槽), 转发结果::成功(_)),
        "摘一份不许动另一份（不串实例）"
    );

    // ④ 引用清零后复核 ⇒ 真收回：路由 + 台账身份 + 端点一起走（同一把写锁下）。
    交错首在飞.store(1, Ordering::SeqCst);
    assert_eq!(适配器.请求卸载按标识(首扩展标识), 派发结果::成功);
    match 适配器.调用能力(1000, &[], &mut 返回槽) {
        转发结果::失败(调度错误::提供者未载入 { 能力号: 未命中号 }) => {
            assert_eq!(未命中号.取号值(), 1000)
        }
        其余值 => panic!("收回后该号必须报「提供者未载入」，实际 {其余值:?}"),
    }
    assert_eq!(适配器.已装载声明数(), 卸载前声明数 - 1, "收回后份数减一");
    assert_eq!(适配器.通知端点数(), 1, "旧端点摘掉（不误用旧句柄）");
    assert_eq!(
        适配器.通知端点标识串(),
        vec![次扩展标识.to_owned()],
        "剩下的只能是次扩展的端点"
    );
    assert!(
        matches!(适配器.调用能力(2500, &[], &mut 返回槽), 转发结果::成功(_)),
        "另一份实例一点不受影响（不串状态）"
    );

    // ⑤ 重启 = 同身份重装 ⇒ **真恢复**（不假恢复）：能力与端点都回来。
    适配器.追加装载(首扩展).expect("同一身份重装必须成功（台账身份已注销）");
    assert_eq!(适配器.已装载声明数(), 卸载前声明数, "重装后份数回位");
    assert_eq!(适配器.通知端点数(), 2, "重装后端点回位");
    assert!(
        matches!(适配器.调用能力(1000, &[], &mut 返回槽), 转发结果::成功(_)),
        "重装后能力必须真恢复"
    );
    println!(
        "交错样本：装载 2 份 → 卸载被拒（明确状态）→ 复核真收回 → 重装真恢复；首扩展共收到通知 {} 次",
        交错首收到.load(Ordering::SeqCst)
    );
}
