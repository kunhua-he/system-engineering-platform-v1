//! 测试夹具 —— **整文件即测试**（`lib.rs` 用 `#[cfg(test)] #[path]` 挂进来）。
//!
//! 为什么单列一个文件：`适配器测试.rs` 与 `边界测试.rs` 两份测试都要用同一份夹具，
//! 各写一份就是「同一件事两种形态」（`代码形态分工.md` 第五节硬判据 1）。
//! 具名 + 只在 `#[cfg(test)]` 里用（一键验证的判据 C：夹具不许被生产代码引用）。

use v1_contract::{
    号段, 参数信息, 执行函数, 数据槽, 平台信息, 版本三元组, 版本要求, 表段, 能力号, 类型标签, 错误码, 错误码信息,
};
use v1_registry::命令信息;

/// 底座命令 0 的入参（1 个，类型标签 0 = 空，与声明一致）。
pub(crate) fn 底座入参() -> [数据槽; 1] {
    [数据槽::内联槽(v1_contract::声明数据::类型标签_0000, 64, 0)]
}

/// 零参执行函数（夹具用；真实现的执行函数不许留空指针，这里只为能建表）。
unsafe extern "C-unwind" fn 夹具零参(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    let _ = (参数个数, 参数表);
    if !返回槽.is_null() {
        // SAFETY: 空指针已挡；非空由调用契约保证可写。
        unsafe { *返回槽 = 数据槽::内联槽(v1_contract::声明数据::类型标签_0001, 1, 0) };
    }
}

/// 一份**六步全过**的最小扩展声明（占能力号段 = 传入的 `号段`）。
pub(crate) fn 造扩展声明(号段: 号段) -> &'static 平台信息 {
    造扩展声明_带状态位(号段, 0)
}

/// 同 `造扩展声明`，但可指定命令的状态位（测「错误项」那一支用）。
pub(crate) fn 造扩展声明_带状态位(号段: 号段, 状态位: u16) -> &'static 平台信息 {
    造声明(号段, 状态位, &[], &[])
}

/// 命令**自身的**可抛码（`[1001]`）比声明**全表**（`[1001, 1002, 1003]`）少。
