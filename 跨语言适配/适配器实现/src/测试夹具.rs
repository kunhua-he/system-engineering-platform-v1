//! 测试夹具 —— **整文件即测试**（`lib.rs` 用 `#[cfg(test)] #[path]` 挂进来）。
//!
//! 为什么单列一个文件：`适配器测试.rs` 与 `边界测试.rs` 两份测试都要用同一份夹具，
//! 各写一份就是「同一件事两种形态」（`代码形态分工.md` 第五节硬判据 1）。
//! 具名 + 只在 `#[cfg(test)]` 里用（一键验证的判据 C：夹具不许被生产代码引用）。

use v1_contract::{号段, 表段, 版本三元组, 执行函数, 数据槽, 平台信息};
use v1_registry::命令信息;

/// 底座命令 0 的入参（1 个，类型标签 0 = 空，与声明一致）。
pub(crate) fn 底座入参() -> [数据槽; 1] {
    [数据槽::内联(v1_contract::声明数据::类型标签_0000, 64, 0)]
}

/// 零参执行函数（夹具用；真实现的执行函数不许留空指针，这里只为能建表）。
unsafe extern "C" fn 夹具零参(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    let _ = (参数个数, 参数表);
    if !返回槽.is_null() {
        // SAFETY: 空指针已挡；非空由调用契约保证可写。
        unsafe { *返回槽 = 数据槽::内联(v1_contract::声明数据::类型标签_0001, 1, 0) };
    }
}

/// 一份**六步全过**的最小扩展声明（占能力号段 = 传入的 `号段`）。
pub(crate) fn 造扩展声明(号段: 号段) -> &'static 平台信息 {
    造扩展声明带状态位(号段, 0)
}

/// 同 `造扩展声明`，但可指定命令的状态位（测「错误项」那一支用）。
pub(crate) fn 造扩展声明带状态位(号段: 号段, 状态位: u16) -> &'static 平台信息 {
    /// 扩展的标识串（32 位十六进制 + NUL；与底座身份不同）。
    static 扩展标识串: &[u8] = b"11223344556677889900aabbccddeeff\0";
    /// 扩展登记的段位：1（能力号段 1xxx 的首位）。
    static 错误段位表: [u32; 1] = [1];

    let 号段表: &'static [号段] = Box::leak(Box::new([号段]));
    let 命令表: &'static [命令信息] = Box::leak(Box::new([命令信息 {
        名称: c"夹具命令".as_ptr().cast::<u8>(),
        说明: c"夹具自用，不参与平台语义。".as_ptr().cast::<u8>(),
        类别: 0,
        状态位,
        返回类型: 0,
        用户级别: 0,
        参数个数: 0,
        参数表: core::ptr::null(),
        // 显式命令编号：取**传入号段的 `起`**（不写字面量 —— 本夹具是按号段参数化的，
        // 写死 1000 时换号段调用（如 `适配器测试.rs` 用底座号段 [0,999] 调）就又越界）。
        // 编号必须落在本声明申报的能力号段内，越界即 `声明不自洽`
        //（`项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 5）。
        编号: 号段.起,
        // 本命令不抛错（空表 = 不抛，不是漏写）。
        可抛错误码: 表段::空(),
    }]));
    let 函数表: &'static [执行函数] = Box::leak(Box::new([夹具零参 as 执行函数]));
    Box::leak(Box::new(平台信息 {
        声明格式号: v1_contract::声明格式号,
        目标字宽: v1_contract::声明数据::底座目标字宽,
        保留: 0,
        标识串: 扩展标识串.as_ptr(),
        实现版本: 版本三元组::新(1, 0, 0, 0),
        要求宿主版本: 版本三元组::新(1, 0, 0, 0),
        要求内核版本: 版本三元组::新(1, 0, 0, 0),
        名称: c"夹具扩展".as_ptr().cast::<u8>(),
        说明: c"测试夹具自用，不参与平台语义。".as_ptr().cast::<u8>(),
        状态位: 0,
        类型表: 表段::空(),
        命令表: 表段::新(命令表.as_ptr(), 1),
        函数表: 函数表.as_ptr(),
        常量表: 表段::空(),
        通知函数: None,
        依赖清单: 表段::空(),
        能力号段: 表段::新(号段表.as_ptr(), 1),
        通知号段: 表段::空(),
        错误段位表: 表段::新(错误段位表.as_ptr(), 1),
        错误码表: 表段::空(),
    }))
}
