/// 造声明的本体：号段 · 命令状态位 · 命令自身的可抛码 · 声明错误码全表。
fn 造声明(号段: 号段, 状态位: u16, 可抛码: &'static [错误码], 全表: &'static [错误码信息]) -> &'static 平台信息 {
    /// 扩展的标识串（32 位十六进制 + NUL；与底座身份不同）。
    static 扩展标识串: &[u8] = b"11223344556677889900aabbccddeeff\0";
    /// 扩展登记的段位：1（能力号段 1xxx 的首位）。
    static 错误段位表: [u32; 1] = [1];

    let 可抛段 = if 可抛码.is_empty() {
        表段::空实例()
    } else {
        表段::构造(可抛码.as_ptr(), 可抛码.len() as u32)
    };
    let 全表段 = if 全表.is_empty() {
        表段::空实例()
    } else {
        表段::构造(全表.as_ptr(), 全表.len() as u32)
    };
    let 号段表: &'static [号段] = Box::leak(Box::new([号段]));
    let 命令表: &'static [命令信息] = Box::leak(Box::new([命令信息 {
        名称: c"夹具命令".as_ptr().cast::<u8>(),
        说明: c"夹具自用，不参与平台语义。".as_ptr().cast::<u8>(),
        类别号: 0,
        状态位,
        返回类型: 类型标签::构造(0),
        用户级别: 0,
        参数个数: 0,
        参数表: core::ptr::null(),
        // 显式命令编号：取**传入号段的 `起`**（不写字面量 —— 本夹具是按号段参数化的，
        // 写死 1000 时换号段调用（如 `适配器测试.rs` 用底座号段 [0,999] 调）就又越界）。
        // 编号必须落在本声明申报的能力号段内，越界即 `声明不自洽`
        //（`项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 5）。
        编号: 能力号::构造(号段.段起点.取号值()),
        // 本命令的可抛码（空表 = 不抛，不是漏写）。
        可抛错误码: 可抛段,
    }]));
    let 执行函数表: &'static [执行函数] = Box::leak(Box::new([夹具零参 as 执行函数]));
    Box::leak(Box::new(平台信息 {
        声明格式号: v1_contract::声明格式号,
        目标字宽: v1_contract::声明数据::底座目标字宽,
        保留: 0,
        标识串: 扩展标识串.as_ptr(),
        实现版本: 版本三元组::构造(1, 0, 0),
        要求宿主版本: 版本要求::构造(1, 0),
        要求内核版本: 版本要求::构造(1, 0),
        名称: c"夹具扩展".as_ptr().cast::<u8>(),
        说明: c"测试夹具自用，不参与平台语义。".as_ptr().cast::<u8>(),
        状态位: 0,
        类型表: 表段::空实例(),
        命令表: 表段::构造(命令表.as_ptr(), 1),
        函数表: 执行函数表.as_ptr(),
        常量表: 表段::空实例(),
        通知函数: None,
        依赖清单: 表段::空实例(),
        能力号段: 表段::构造(号段表.as_ptr(), 1),
        通知号段: 表段::空实例(),
        错误段位表: 表段::构造(错误段位表.as_ptr(), 1),
        错误码表: 全表段,
        命令类别表: 表段::空实例(),
        要求权限: 表段::空实例(),
        依赖版本要求: 表段::空实例(),
    }))
}

