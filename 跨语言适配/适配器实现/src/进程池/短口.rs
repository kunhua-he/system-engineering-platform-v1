//! 进程池 · 短口 —— 池面上「按标识」进出的一律口子。
//!
//! 从 `进程池.rs` 拆出（单源 ≤ 400 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管**表与进程**（建格 · 取格 · 退避账 · 重拉），本件管**按标识的薄转发** ——
//! 每条都是「取句柄（一次短表锁）→ 交给 [`域句柄`](super::域句柄) 做长执行」。
//!
//! 正因如此，「慢域阻塞不了健康域」这条性质不因拆件而变：本件的每个方法都
//! **不持表锁做长执行**（冻结件 §五：域表锁只用于取引用）。

use std::num::NonZeroU64;
use std::time::{Duration, Instant};

use crate::进程帧::调用帧预算;

use super::{重放预算毫秒, 执行域标识, 域资源读数, 监督判读, 进程池, 进程池错误};

impl 进程池 {
    /// 这个域的装载初始化重放过没有。
    pub fn 已重放装载(&self, 标识: &执行域标识) -> bool {
        self.取域句柄(标识).map_or(false, |句柄| 句柄.已重放装载())
    }

    /// 重放装载初始化。
    pub fn 重放装载初始化(
        &self,
        标识: &执行域标识,
        请求标识: NonZeroU64,
    ) -> Result<(), 进程池错误> {
        let 句柄 = self.取域句柄(标识).ok_or(进程池错误::域不存在)?;
        let mut 预算 =
            调用帧预算::创建(Instant::now() + Duration::from_millis(重放预算毫秒))
                .map_err(|_| 进程池错误::拉起失败)?;
        句柄.重放装载初始化按预算(请求标识, &mut 预算)
    }

    /// 收装载回执。
    pub fn 收装载回执(
        &self,
        标识: &执行域标识,
        请求标识: NonZeroU64,
    ) -> Result<(), 进程池错误> {
        let 句柄 = self.取域句柄(标识).ok_or(进程池错误::域不存在)?;
        let mut 预算 =
            调用帧预算::创建(Instant::now() + Duration::from_millis(重放预算毫秒))
                .map_err(|_| 进程池错误::拉起失败)?;
        句柄.收装载回执按预算(请求标识, &mut 预算)
    }

    /// 调用一域（单步调用用）。
    pub fn 调用一域(
        &self,
        标识: &执行域标识,
        请求标识: NonZeroU64,
        待发载荷: &[u8],
    ) -> Result<Vec<u8>, 进程池错误> {
        let 句柄 = self.取域句柄(标识).ok_or(进程池错误::域不存在)?;
        句柄.调用一域(请求标识, 待发载荷)
    }

    /// 监督一次：查实崩溃、给判读。不重拉。
    pub fn 监督一域(&self, 标识: &执行域标识) -> Result<监督判读, 进程池错误> {
        self.取域句柄(标识).map(|句柄| 句柄.监督()).ok_or(进程池错误::域不存在)
    }

    /// 击杀一个域（整组），并回收它的进程。
    pub fn 击杀一域(&self, 标识: &执行域标识) -> Result<(), 进程池错误> {
        self.取域句柄(标识).map_or(Err(进程池错误::域不存在), |句柄| 句柄.击杀())
    }

    /// 取一个域**此刻**的资源读数（进程 · 文件 · 句柄 · 内存四类，现读内核）。
    ///
    /// 停机 / 重启 / 升级 / 回退之后「资源还回去了没有」看它；域不在表里 ⇒ 结构化拒。
    pub fn 取域资源读数(&self, 标识: &执行域标识) -> Result<域资源读数, 进程池错误> {
        self.取域句柄(标识).map(|句柄| 句柄.取资源读数()).ok_or(进程池错误::域不存在)
    }
}
