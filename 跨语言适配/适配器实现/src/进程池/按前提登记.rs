//! 进程池 · 按前提登记 —— 「拉起一个域时给它什么环境」那两口（首拉与收编已连域）。
//!
//! 从 `进程池.rs` 拆出（单源 ≤ 400 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管**表与账**（建格 · 取格 · 退避账 · 重拉），本件管**前提**（环境口径）——
//! 每个 `*按前提` 口都配一个用默认前提的壳，两个壳与两个本体写在一处。
//!
//! **为什么前提必须在拉起之前生效**：它决定子进程拿到什么环境（[`子进程前提`]），
//! 进程一旦起来就无法补 —— 所以判定与装环境都在 `spawn` 之前（见 [`生成进程按前提`]）。
//!
//! 子件能读父件的私有项（Rust 隐私：子模块看得见祖先的私项）。

use std::os::unix::net::UnixStream;
use std::sync::{Arc, Mutex};
use std::time::Instant;

use crate::线程安全::取锁;

use super::{
    子进程前提, 工作进程, 生成进程按前提, 域格, 执行域标识, 部署指纹, 进程池, 进程池错误,
};

impl 进程池 {
    /// 保证这个域在跑：没有则拉起；崩了则按退避 / 熔断决定能不能重拉。
    ///
    /// **默认前提**（只授权派生进程 + 空环境）—— 与 [`进程池::保证域在按前提`] 同一份实现。
    pub fn 保证域在(
        &self,
        标识: &执行域标识,
        启动程序: &str,
        启动参数: &[String],
    ) -> Result<(), 进程池错误> {
        self.保证域在按前提(标识, 启动程序, 启动参数, &子进程前提::默认前提())
    }

    /// 保证这个域在跑（**按前提**）：没有则拉起；崩了则按退避 / 熔断决定能不能重拉。
    ///
    /// 已存在 ⇒ 转 [`域句柄::保证在按前提`]（只持该域锁）；不存在 ⇒ 拉起后插格（一次短表锁）。
    /// **前提在真拉起之前就要生效** —— 它是「给子进程什么环境」的判据，拉起之后无法补。
    pub fn 保证域在按前提(
        &self,
        标识: &执行域标识,
        启动程序: &str,
        启动参数: &[String],
        前提: &子进程前提,
    ) -> Result<(), 进程池错误> {
        if let Some(句柄) = self.取域句柄(标识) {
            return 句柄.保证在按前提(启动程序, 启动参数, 前提);
        }
        // 子进程数上限：**拉之前**判 —— 满了就一个新进程都不拉（架构收敛方案项 18.3-4）。
        if self.域表已满() {
            return Err(进程池错误::子进程数已满);
        }
        let (子进程, 通信通道) = 生成进程按前提(启动程序, 启动参数, 前提)?;
        let 实例代次 = self.取单调代次();
        let 新格 = Self::造格(
            标识.clone(),
            子进程,
            通信通道,
            实例代次,
            部署指纹(启动程序, 启动参数),
            前提.前提指纹(),
        )?;
        let mut 域表锁 = 取锁(&self.域表);
        if 域表锁.iter().any(|格子| &格子.标识 == 标识) {
            // 别人已插：丢掉我们这份（连同它拉起的进程，不留孤儿）。
            let 孤儿 = 新格;
            drop(域表锁);
            super::回收::回收孤儿(&孤儿);
            return Ok(());
        }
        域表锁.push(新格);
        Ok(())
    }

    /// 收下一个**已连好的域**：对端由别人拉起（宿主已代拉 / 验证面的应答环），
    /// 池只接管它的通道与退避账。
    ///
    /// 与 [`进程池::保证域在`] 的分工：那个自行 `spawn`，这个只登记 —— 验证面要验
    /// 「通道断了会怎样」时，不需要一个真子进程来陪。
    ///
    /// 子进程用一个**长命占位**：它是为了让 `try_wait` / 击杀有东西可查，不接数据通道
    /// （数据通道是调用方给的那条）。两条通道分开是有意的 —— 占位进程写不到本流上去。
    pub fn 收下已连域(
        &self,
        标识: 执行域标识,
        宿主端: UnixStream,
        部署: crate::进程调用::域部署,
    ) -> Result<(), 进程池错误> {
        self.收下已连域按前提(标识, 宿主端, 部署, &子进程前提::默认前提())
    }

    /// 收下一个**已连好的域**（**按前提**）：占位进程也按前提拉起（同一份环境口径）。
    ///
    /// 对端由别人拉起，但那个占位进程是**本件拉**的 ⇒ 它同样要走前提判定：
    /// 未授权派生时连占位都不拉（否则「授权」只挡住了主路、侧路照旧起进程）。
    pub fn 收下已连域按前提(
        &self,
        标识: 执行域标识,
        宿主端: UnixStream,
        部署: crate::进程调用::域部署,
        前提: &子进程前提,
    ) -> Result<(), 进程池错误> {
        if self.含域(&标识) {
            return Err(进程池错误::域不存在);
        }
        // 占位进程也是子进程 ⇒ 同一条上限（侧路不许绕）。
        if self.域表已满() {
            return Err(进程池错误::子进程数已满);
        }
        let (子进程, _) = 生成进程按前提(&部署.启动程序, &部署.启动参数, 前提)?;
        let 实例代次 = self.取单调代次();
        let 进程组号 = i32::try_from(子进程.id()).map_err(|_| 进程池错误::拉起失败)?;
        取锁(&self.域表).push(域格 {
            标识,
            事务锁: Arc::new(Mutex::new(())),
            工作: Arc::new(Mutex::new(工作进程 {
                子进程,
                流通道: 宿主端,
                进程组号,
                实例代次,
                部署指纹: 部署指纹(&部署.启动程序, &部署.启动参数),
                前提指纹: 前提.前提指纹(),
                运行中: true,
                连续崩溃次数: 0,
                下次允许拉起: Instant::now(),
                熔断截至: None,
                装载已重放: false,
            })),
        });
        Ok(())
    }
}
