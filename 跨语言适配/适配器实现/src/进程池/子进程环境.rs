//! 进程池 · 子进程环境 —— 白名单 · 秘密绑定 · 危险动作授权（收敛项 G07）。
//!
//! 依据：架构收敛方案项 G07。修前本 crate 里这三样**一处落点都没有**
//! （`rg -n '环境变量|秘密|危险动作|授权' 跨语言适配/适配器实现/src` 退出码 1）：
//! [`生成进程`](super::进程装配) 用 `Command::new` 起子进程、**不 `env_clear`**
//! ⇒ 子进程继承父进程**全环境**（含一切秘密），拉进程前也没有任何授权判定。
//!
//! # 三条口径
//!
//! 1. **默认不继承**：白名单为空 ⇒ 子进程拿**空环境**。理由与错误码 `0024` 同一句——
//!    「默认能用是最危险的默认值」。要透传哪个变量就显式写进白名单。
//! 2. **秘密按名单投放、且胜过父环境同名值**：秘密是**显式绑定的那一份**，
//!    不是「碰巧父环境里也有」的那一份 —— 投放顺序排在父环境项**之后**。
//! 3. **危险动作逐项授权**：三类动作（派生进程 · 继承全环境 · 投放秘密）各判一次，
//!    **未授权一律结构化拒**，**不静默收窄、不静默降级** —— 静默收窄会让调用方
//!    以为配置生效了（「不许静默降级」同一条）。
//!
//! # 底线：这是**相对安全**的一层（不许包装成绝对边界）
//!
//! 本件管的只是「本进程拉子进程时给它什么环境」——**不是沙箱、不是权限系统**，
//! 也不声称能挡住一个已经拿到本进程执行权的对手。它守的底线只有一条：
//! **不因默认值把父进程的全环境（含秘密）白送给子进程**。需要更严或更宽的边界，
//! 由调用方**传前提**选择（见 [`子进程前提`]）。

use std::process::Command;

use super::进程池错误;

/// 通配名：白名单里写它 = 「要透传全部父环境变量」。
///
/// 单独设一个通配名而不是「白名单为空就全给」：后者会让**空名单**（最省事的写法）
/// 变成最宽的授权 —— 正是本件要堵的那条默认值。
pub const 全放行名: &str = "*";

/// 三类**危险动作**：逐项授权，未授权即拒。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 危险动作 {
    /// 拉起一个子进程。
    ///
    /// 默认**给**（跨进程执行域的本职就是拉工作进程）—— 但不设成「无法关闭」：
    /// 调用方可以不给它，那样 [`生成进程`](super::进程装配) 当场结构化拒且**不拉起进程**。
    派生进程,
    /// 把父进程**全部**环境变量透传给子进程（白名单里写 [`全放行名`] 才用得上）。
    继承全环境,
    /// 把 [`子进程前提::秘密`] 里的值投放给子进程。
    投放秘密,
}

/// 一个子进程的**前提**：拿什么环境拉起它。
///
/// 三样各自独立：`白名单` 管透传哪些父环境变量，`秘密` 管显式绑定的键值，
/// `授权` 管上面三类危险动作放不放行。**默认前提 = 只授权派生进程 + 空白名单 + 空秘密**
/// ⇒ 子进程拿空环境（最窄的那个默认值）。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 子进程前提 {
    /// 允许透传的**父环境变量名**（不含通配名时逐项取值）。
    pub 白名单: Vec<String>,
    /// 显式绑定的**秘密**键值（要授权 [`危险动作::投放秘密`] 才投）。
    pub 秘密: Vec<(String, String)>,
    /// 放行的危险动作。
    pub 授权: Vec<危险动作>,
}

impl 子进程前提 {
    /// 默认前提：只授权 [`危险动作::派生进程`]，白名单与秘密都空（子进程拿空环境）。
    pub fn 默认前提() -> Self {
        Self { 白名单: Vec::new(), 秘密: Vec::new(), 授权: vec![危险动作::派生进程] }
    }

    /// 这个动作放行了没有。
    pub fn 含授权(&self, 动作: 危险动作) -> bool {
        self.授权.contains(&动作)
    }

    /// 收编一个危险动作（幂等）。
    pub fn 授权收编(&mut self, 动作: 危险动作) {
        if !self.含授权(动作) {
            self.授权.push(动作);
        }
    }

    /// 收编一个白名单变量名（幂等）。
    pub fn 收编白名单(&mut self, 环境名: &str) {
        if !self.白名单.iter().any(|已有名| 已有名 == 环境名) {
            self.白名单.push(String::from(环境名));
        }
    }

    /// 收编一条秘密（同键覆盖旧值，幂等）。
    pub fn 收编秘密(&mut self, 秘密名: &str, 秘密值: &str) {
        match self.秘密.iter_mut().find(|(已有名, _)| 已有名 == 秘密名) {
            Some(格子) => 格子.1 = String::from(秘密值),
            None => self.秘密.push((String::from(秘密名), String::from(秘密值))),
        }
    }

    /// 白名单条数（验证面读）。
    pub fn 白名单条数(&self) -> usize {
        self.白名单.len()
    }

    /// 秘密条数（验证面读）。
    pub fn 秘密条数(&self) -> usize {
        self.秘密.len()
    }

    /// 前提的**指纹**：同域重复登记时据此判「前提变没变」（与 [`部署指纹`](super::部署指纹)
    /// 同一算法、同一理由：域格只存一个可比的标量，指纹不必跨进程稳定）。
    ///
    /// 为什么不把前提并进 `部署指纹`：那个函数已经是对外可见的口，改签名会连带
    /// 它的全部调用点；前提是新加的一层，单独一个指纹即可表达「这一层变了」。
    pub fn 前提指纹(&self) -> u64 {
        const 质数: u64 = 0x0000_0100_0000_01b3;
        let mut 指纹 = 0xcbf2_9ce4_8422_2325u64;
        let mut 收一段 = |片段: &str| {
            for 字节 in 片段.as_bytes().iter().copied().chain(core::iter::once(0u8)) {
                指纹 ^= u64::from(字节);
                指纹 = 指纹.wrapping_mul(质数);
            }
        };
        for 环境名 in &self.白名单 {
            收一段(环境名);
        }
        for (秘密名, 秘密值) in &self.秘密 {
            收一段(秘密名);
            收一段(秘密值);
        }
        for 动作 in &self.授权 {
            收一段(match 动作 {
                危险动作::派生进程 => "派生进程",
                危险动作::继承全环境 => "继承全环境",
                危险动作::投放秘密 => "投放秘密",
            });
        }
        指纹
    }

    /// 要透传全部父环境变量（白名单里写了 [`全放行名`]）。
    fn 要继承全环境(&self) -> bool {
        self.白名单.iter().any(|环境名| 环境名 == 全放行名)
    }

    /// **派生前的授权判定**：没授权 [`危险动作::派生进程`] ⇒ 结构化拒。
    ///
    /// 单独成一个口：拉进程的每一步（首拉 / 重拉 / 收下已连域）都要在**真拉起之前**
    /// 判一次 —— 判定放在 [`把环境装进命令`](Self::把环境装进命令) 里就晚了，
    /// 那时进程参数已经成形（而「不拉起进程」是本条的验收口径）。
    pub fn 校验派生(&self) -> Result<(), 进程池错误> {
        if self.含授权(危险动作::派生进程) {
            Ok(())
        } else {
            Err(进程池错误::未授权派生进程)
        }
    }

    /// 把前提**装进命令**：清环境 → 按名单透传父环境 → 投放秘密（后者胜过同名）。
    ///
    /// 三道判定都在**写命令之前**：要全放行却没授权、或带了秘密却没授权 ⇒ 结构化拒，
    /// **不写半个变量**（不许「先把能投的投了、再报错」—— 那是静默降级）。
    pub fn 把环境装进命令(&self, 命令: &mut Command) -> Result<(), 进程池错误> {
        if self.要继承全环境() && !self.含授权(危险动作::继承全环境) {
            return Err(进程池错误::未授权继承全环境);
        }
        if !self.秘密.is_empty() && !self.含授权(危险动作::投放秘密) {
            return Err(进程池错误::未授权投放秘密);
        }
        // 先清空：不 `env_clear` 就是继承父进程全环境（本件要堵的那条默认值）。
        命令.env_clear();
        if self.要继承全环境() {
            // 已授权全放行 ⇒ 逐条透传父环境（`envs` 与逐条 `env` 同语义）。
            命令.envs(std::env::vars());
        } else {
            for 环境名 in &self.白名单 {
                // 白名单是「**允许**透传」不是「必须存在」：父环境没有这一项就跳过
                // （不算降级 —— 没有任何一个值因为这条而被换掉）。
                if let Ok(环境值) = std::env::var(环境名) {
                    命令.env(环境名, 环境值);
                }
            }
        }
        // 秘密**排在父环境项之后** ⇒ 同名时秘密值胜（「显式绑定的那一份」）。
        for (秘密名, 秘密值) in &self.秘密 {
            命令.env(秘密名, 秘密值);
        }
        Ok(())
    }
}
