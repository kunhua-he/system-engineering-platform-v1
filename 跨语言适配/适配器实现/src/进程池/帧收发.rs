//! 进程池 · 帧收发 —— 池面那些「在通道上读写一帧」的方法。
//!
//! 从 `进程池.rs` 拆出（单源 ≤ 400 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管**进程**（拉起 · 监督 · 退避 · 熔断），子件管**帧**（发/收/重放/回执）。
//! 两者是同一件事的两个面：崩溃检出靠帧层的 EOF，帧层报什么错靠进程活没活。
//!
//! 子件能读父件的私有字段（Rust 隐私：子模块看得见祖先的私有项）。
//!
//! # 锁收窄（冻结件 §五 末行）
//!
//! 本件的每个方法都**只持该域本域那把锁**（`域句柄.锁()`）—— 域表锁早已在
//! `取域句柄` 那一步放掉。故**一个慢域阻塞不了健康域**：慢域的收发在本域锁里等，
//! 健康域拿本域句柄各走各的。
//!
//! # 预算：**共用剩余**，不因进入下一阶段重置（冻结件 §五）
//!
//! 每个方法都收一条**调用方给的** [`调用帧预算`]：长调用路（`跨进程域表` 那条）
//! 从保证域在开始造一条，重放 / 收执 / 发 / 收**共用同一条** ⇒ 一条调用从排队到收完
//! 只花一份时限，不会每进一个阶段就把时钟拨回去。

use std::num::NonZeroU64;
use std::time::{Duration, Instant};

use crate::进程帧::调用帧预算;

use super::{域句柄, 重放预算毫秒, 查实崩溃, 进程池错误};

impl 域句柄 {
    /// **发一条调用帧**（按调用方给的预算）。**通道断开 ⇒ 查实崩溃再报码**（不是直报）：
    /// EOF 是「可能崩了」的现场，真崩没崩由 `查实崩溃` 看子进程退出码定；
    /// 查实了才计崩溃次数。
    pub(crate) fn 发一调用帧按预算(
        &self,
        请求标识: NonZeroU64,
        待发载荷: &[u8],
        budget: &mut 调用帧预算,
    ) -> Result<(), 进程池错误> {
        let mut 工作 = self.锁();
        let 调用帧 = crate::进程帧::消息帧 {
            消息类型: crate::进程帧::消息类别::调用,
            请求标识,
            载荷: 待发载荷.to_vec(),
        };
        let 结果 = crate::进程帧::发送帧(&mut 工作.通道, &调用帧, budget);
        if 结果.is_err() {
            查实崩溃(self.配置, &mut 工作);
            return Err(按存活判错(&工作));
        }
        Ok(())
    }

    /// **收一条调用回帧**（按调用方给的预算）。回帧不成形 ⇒ 查实崩溃再按存活判错。
    pub(crate) fn 收一调用回帧按预算(
        &self,
        请求标识: NonZeroU64,
        budget: &mut 调用帧预算,
    ) -> Result<Vec<u8>, 进程池错误> {
        let mut 工作 = self.锁();
        match crate::进程帧::接收帧(&mut 工作.通道, 请求标识, budget) {
            Ok(帧体) if 帧体.消息类型 == crate::进程帧::消息类别::调用结果 => Ok(帧体.载荷),
            _ => {
                查实崩溃(self.配置, &mut 工作);
                Err(按存活判错(&工作))
            }
        }
    }

    /// 收装载初始化的回执（与重放配对的那一帧，按调用方给的预算）。
    ///
    /// # 为什么必须收（不是可选）
    ///
    /// 重放只发不回，回帧就留在通道里 —— 下一条调用去读时先读到它，请求标识对不上
    /// ⇒ 当场报「请求、长度或预算不符」。表现为「重拉过的域第一次调用必失败」，
    /// 而报的还是一个看不出来源的错（实测：本条腿初版就是这形状）。
    ///
    /// 口径：回执是**重放成功**的判据（拆解件那行原文：「重拉后通知端点数恢复、回执成功」）。
    /// 收不到 ⇒ 这个域不算重放完成，报 [`进程池错误::通道断开`]。
    pub(crate) fn 收装载回执按预算(
        &self,
        请求标识: NonZeroU64,
        budget: &mut 调用帧预算,
    ) -> Result<(), 进程池错误> {
        let mut 工作 = self.锁();
        match crate::进程帧::接收帧(&mut 工作.通道, 请求标识, budget) {
            Ok(帧体) if 帧体.消息类型 == crate::进程帧::消息类别::通知回执 => Ok(()),
            _ => {
                查实崩溃(self.配置, &mut 工作);
                Err(按存活判错(&工作))
            }
        }
    }

    /// 重放装载初始化：向这个域发一条**通知号 2000** 的帧（不恢复业务任务，按调用方给的预算）。
    pub(crate) fn 重放装载初始化按预算(
        &self,
        请求标识: NonZeroU64,
        budget: &mut 调用帧预算,
    ) -> Result<(), 进程池错误> {
        let mut 工作 = self.锁();
        let 通知帧 = crate::进程帧::消息帧 {
            消息类型: crate::进程帧::消息类别::通知,
            请求标识,
            载荷: v1_contract::声明数据::通知号_2000.to_le_bytes().to_vec(),
        };
        crate::进程帧::发送帧(&mut 工作.通道, &通知帧, budget)
            .map_err(|_| 进程池错误::通道断开)?;
        工作.装载已重放 = true;
        Ok(())
    }

    /// **调用一域**：自造一条独立预算，发一条调用帧、收同标识的回帧（验证面与单步调用用）。
    ///
    /// 长调用路（`跨进程域表`）走 [`域句柄::发一调用帧按预算`] +
    /// [`域句柄::收一调用回帧按预算`] 共用一条预算。
    ///
    /// 载荷的编解码**不在这里**（本件不认任何协议语义）—— 调用方给的是已编好的载荷，
    /// 收到的也是裸载荷。为什么这样切：帧层与线协议层各管各的，`线协议.rs` 已经做了
    /// 「调用形状 ↔ 载荷」的翻译，本件再做一次就是第二套。
    pub fn 调用一域(
        &self,
        请求标识: NonZeroU64,
        待发载荷: &[u8],
    ) -> Result<Vec<u8>, 进程池错误> {
        let mut 预算 = 自造预算()?;
        self.发一调用帧按预算(请求标识, 待发载荷, &mut 预算)?;
        self.收一调用回帧按预算(请求标识, &mut 预算)
    }
}

/// 通道出错后**按进程死没死**分开报：死了 = 崩溃，没死 = 预算耗尽。
///
/// 这条分界不是措辞游戏：`0034 能力进程崩溃` 的说明里明写「与 0004 超时分开
/// （超时是进程活着但没答）」—— 把两者报成同一个码，那条说明就成了空话。
fn 按存活判错(工作: &super::工作进程) -> 进程池错误 {
    if 工作.运行中 { 进程池错误::预算耗尽 } else { 进程池错误::通道断开 }
}

/// 造一条本件自用的短预算（≤ 五秒硬顶）。
fn 自造预算() -> Result<调用帧预算, 进程池错误> {
    let 截止 = Instant::now() + Duration::from_millis(重放预算毫秒);
    调用帧预算::创建(截止).map_err(|_| 进程池错误::拉起失败)
}
