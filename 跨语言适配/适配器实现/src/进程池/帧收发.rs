//! 进程池 · 帧收发 —— 池面那四条「在通道上读写一帧」的方法。
//!
//! 从 `进程池.rs` 拆出（单源 ≤ 400 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管**进程**（拉起 · 监督 · 退避 · 熔断），子件管**帧**（发/收/重放/回执）。
//! 两者是同一件事的两个面：崩溃检出靠帧层的 EOF，帧层报什么错靠进程活没活。
//!
//! 子件能读父件的私有字段（Rust 隐私：子模块看得见祖先的私有项）—— 故本件直接读写
//! `域表` / `工作进程`，不需要父件为它开任何口子。

use std::num::NonZeroU64;
use std::time::{Duration, Instant};

use super::{重放预算毫秒, 执行域标识, 进程池, 进程池错误};

impl 进程池 {
    /// **调用一域**：发一条调用帧、收同标识的回帧（`帧与背压` 的调用路）。
    ///
    /// 载荷的编解码**不在这里**（本件不认任何协议语义）—— 调用方给的是已编好的载荷，
    /// 收到的也是裸载荷。为什么这样切：帧层与线协议层各管各的，`线协议.rs` 已经做了
    /// 「调用形状 ↔ 载荷」的翻译，本件再做一次就是第二套。
    ///
    /// **通道断开 ⇒ 查实崩溃再报码**（不是直报）：EOF 是「可能崩了」的现场，
    /// 真崩没崩由 `进程池::查实崩溃` 看子进程退出码定；查实了才计崩溃次数。
    pub fn 调用一域(
        &mut self,
        标识: &执行域标识,
        请求标识: NonZeroU64,
        待发载荷: &[u8],
    ) -> Result<Vec<u8>, 进程池错误> {
        let 位置 = self.取域位置(标识).ok_or(进程池错误::域不存在)?;
        let 调用帧 = crate::进程帧::消息帧 {
            消息类型: crate::进程帧::消息类别::调用,
            请求标识,
            载荷: 待发载荷.to_vec(),
        };
        if self.送一帧(位置, &调用帧).is_err() {
            self.报帧错(位置);
            return Err(self.按存活判错(位置));
        }
        match self.收一帧(位置, 请求标识) {
            Ok(帧体) if 帧体.消息类型 == crate::进程帧::消息类别::调用结果 => Ok(帧体.载荷),
            _ => {
                self.报帧错(位置);
                Err(self.按存活判错(位置))
            }
        }
    }

    /// 收装载初始化的回执（与重放配对的那一帧）。
    ///
    /// # 为什么必须收（不是可选）
    ///
    /// 重放只发不回，回帧就留在通道里 —— 下一条调用去读时先读到它，请求标识对不上
    /// ⇒ 当场报「请求、长度或预算不符」。表现为「重拉过的域第一次调用必失败」，
    /// 而报的还是一个看不出来源的错（实测：本条腿初版就是这形状）。
    ///
    /// 口径：回执是**重放成功**的判据（拆解件那行原文：「重拉后通知端点数恢复、回执成功」）。
    /// 收不到 ⇒ 这个域不算重放完成，报 [`进程池错误::通道断开`]。
    pub fn 收装载回执(
        &mut self,
        标识: &执行域标识,
        请求标识: NonZeroU64,
    ) -> Result<(), 进程池错误> {
        let 位置 = self.取域位置(标识).ok_or(进程池错误::域不存在)?;
        match self.收一帧(位置, 请求标识) {
            Ok(帧体) if 帧体.消息类型 == crate::进程帧::消息类别::通知回执 => Ok(()),
            _ => {
                self.报帧错(位置);
                Err(self.按存活判错(位置))
            }
        }
    }

    /// 重放装载初始化：向这个域发一条**通知号 2000** 的帧（不恢复业务任务）。
    pub fn 重放装载初始化(
        &mut self,
        标识: &执行域标识,
        请求标识: NonZeroU64,
    ) -> Result<(), 进程池错误> {
        let 位置 = self.取域位置(标识).ok_or(进程池错误::域不存在)?;
        let 通知帧 = crate::进程帧::消息帧 {
            消息类型: crate::进程帧::消息类别::通知,
            请求标识,
            载荷: v1_contract::声明数据::通知号_2000.to_le_bytes().to_vec(),
        };
        self.送一帧(位置, &通知帧)?;
        self.域表[位置].1.装载已重放 = true;
        Ok(())
    }

    /// 发一帧（本件唯一的发送口，四条方法共用一份预算造法）。
    fn 送一帧(&mut self, 位置: usize, 帧体: &crate::进程帧::消息帧) -> Result<(), 进程池错误> {
        let 截止 = Instant::now() + Duration::from_millis(重放预算毫秒);
        let mut 预算 =
            crate::进程帧::调用帧预算::创建(截止).map_err(|_| 进程池错误::拉起失败)?;
        crate::进程帧::发送帧(&mut self.域表[位置].1.通道, 帧体, &mut 预算)
            .map_err(|_| 进程池错误::通道断开)
    }

    /// 收一帧（本件唯一的接收口）。
    fn 收一帧(
        &mut self,
        位置: usize,
        请求标识: NonZeroU64,
    ) -> Result<crate::进程帧::消息帧, 进程池错误> {
        let 截止 = Instant::now() + Duration::from_millis(重放预算毫秒);
        let mut 预算 =
            crate::进程帧::调用帧预算::创建(截止).map_err(|_| 进程池错误::拉起失败)?;
        crate::进程帧::接收帧(&mut self.域表[位置].1.通道, 请求标识, &mut 预算)
            .map_err(|_| 进程池错误::通道断开)
    }

    /// 帧层报错后的统一收尾：**查实崩溃**（只在这一刻真得看子进程）。
    fn 报帧错(&mut self, 位置: usize) {
        self.查实崩溃(位置);
    }

    /// 通道出错后**按进程死没死**分开报：死了 = 崩溃，没死 = 预算耗尽。
    ///
    /// 这条分界不是措辞游戏：`0034 能力进程崩溃` 的说明里明写「与 0004 超时分开
    /// （超时是进程活着但没答）」—— 把两者报成同一个码，那条说明就成了空话。
    fn 按存活判错(&self, 位置: usize) -> 进程池错误 {
        if self.域表[位置].1.运行中 { 进程池错误::预算耗尽 } else { 进程池错误::通道断开 }
    }
}
