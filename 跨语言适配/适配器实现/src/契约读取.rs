// 读侧公开面（从 `lib.rs` 搬来：那是路由，本文件是读侧零件）
// ════════════════════════════════════════════════════════════════════════════

impl 适配器 {
    /// 读侧「有哪些能力」：编号 · 名称 · 参数个数 · 返回类型。
    ///
    /// **与调侧同一个入口**：清单是当场遍历 [`注册表`] 取出来的，不是另存的一份表 ——
    /// 所以清单里的编号拿去 [`适配器::调用能力`] 必然走得通同一条路。
    ///
    /// **枚举按位、报号按声明**：`按位取命令` 走的是「表里有哪些」，编号一律报声明里的
    /// `命令信息.编号` —— 不把位置当编号（位置只在「编号 = 下标」的巧合下才等于编号）。
    pub fn 能力清单(&self) -> Vec<能力摘要> {
        let mut 输出缓冲 = Vec::new();
        for 单元 in &self.装载单元s {
            for 位置 in 0..单元.注册表.命令数() {
                if let 命令槽::已载入 { 声明, .. } = 单元.注册表.按位取命令(位置) {
                    输出缓冲.push(能力摘要 {
                        编号: 声明.编号.取号值(),
                        // SAFETY: 契约保证一切串都是静态只读 NUL 结尾串。
                        名称: unsafe { 读契约串(声明.名称) },
                        参数个数: 声明.参数个数,
                        返回类型: 声明.返回类型.取号值(),
                    });
                }
            }
        }
        输出缓冲
    }

    /// 读侧「某条能力的完整契约」：参数表行序 · 返回 · **这条命令自身的**可抛错误码。
    ///
    /// `可抛错误码` 取命令的 `命令信息.可抛错误码`（`格式说明.md` §三 按命令登记的那张），
    /// 不是声明全表 —— 声明全表经 [`适配器::声明错误码表`] 取（那是**调度层**的码的落点）。
    ///
    /// 未命中给 `None`（**不是 panic**，也不编一份空契约）：这个号没被任何已装载声明认领。
    pub fn 能力契约(&self, 编号: u32) -> Option<能力契约> {
        // 号空间：本函数是**跨语言边界**（外面给的是裸 `u32`）⇒ 在这里包一次，往内一律走
        // `能力号`。公开签名不动 ⇒ 外部调用点不受影响（边界转换一次即够）。
        let 号值 = 能力号::新建(编号);
        for 单元 in &self.装载单元s {
            if let 命令槽::已载入 { 声明, .. } = 单元.注册表.按号取命令(号值) {
                return Some(能力契约 {
                    编号,
                    // SAFETY: 契约保证一切串都是静态只读 NUL 结尾串。
                    名称: unsafe { 读契约串(声明.名称) },
                    // SAFETY: 同上。
                    说明文字: unsafe { 读契约串(声明.说明) },
                    参数表: 读参数表(声明),
                    返回类型: 声明.返回类型.取号值(),
                    可抛错误码: 读命令可抛错误码(单元.声明, 声明),
                });
            }
        }
        None
    }

    /// 某个号**所属声明**的错误码全表（`平台信息.错误码表`）。
    ///
    /// 与 [`适配器::能力契约`] 的分工：那个给「这条命令自身声明的可抛码」，本口给
    /// 「这份声明登记过的全部码」。**调度层**产生的码（提供者未载入 / 已废止 / 参数个数
    /// 不符 / 超时 / 配额用尽，段位 0）不属任何一条命令，上层要查它们的名称与三项业务判断
    /// 只能走本口。
    ///
    /// 未命中的号交给**第一份**声明的全表（与 [`适配器::取注册表`] 同一口径：都不认时
    /// 照样给一份可查的表，不给空 —— 空表会把「码没登记」与「这里取不到」混成一件）。
    pub fn 声明错误码表(&self, 编号: u32) -> Vec<错误码摘要> {
        let 号值 = 能力号::新建(编号);   // 跨语言边界：包一次，往内走 `能力号`
        for 单元 in &self.装载单元s {
            if let 命令槽::已载入 { .. } = 单元.注册表.按号取命令(号值) {
                return 读错误码表(单元.声明);
            }
        }
        读错误码表(self.装载单元s[0].声明)
    }

    /// 已装载的声明份数（验证面用：确认声明根是序贯装进来的）。
    pub fn 已装载声明数(&self) -> usize {
        self.装载单元s.len()
    }

    /// 某个能力号累计的真实耗时（毫秒）。取自**本实例**那本账本，不是进程级读数。
    pub fn 累计耗时毫秒(&self, 编号: u32) -> u64 {
        self.账本.累计耗时毫秒(能力号::新建(编号))
    }

    /// 路由：**谁认这个号就归谁**。
    ///
    /// 这不是业务判断 —— 代码里没有任何一个具体编号，只看「这一份的注册表认不认」。
    /// 都不认时交给第一份：它照样给占位项 ⇒ 明确段位「提供者未载入」，**不是崩溃**。
    ///
    /// `装载单元s` 非空由 [`适配器::装载声明根`] 保证（空声明根在构造期就被拒）。
    pub(crate) fn 取注册表(&self, 号值: 能力号) -> &统一注册表 {
        for 单元 in &self.装载单元s {
            if let 命令槽::已载入 { .. } = 单元.注册表.按号取命令(号值) {
                return &单元.注册表;
            }
        }
        &self.装载单元s[0].注册表
    }
}
