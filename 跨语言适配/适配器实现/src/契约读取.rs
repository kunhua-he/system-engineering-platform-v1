//! 形状翻译的零件（读侧）—— 现读声明的静态字段，**不缓存、不另存**。
//!
//! 契约规定一切串都是静态只读的 NUL 结尾串、一切表段都指向静态只读数组 ——
//! 与 `装载入口` / `统一注册表` 的前提同一份。
//!
//! 为什么单列一个文件：`lib.rs` 是路由（声明子模块 · 再导出公开面 · 零实现），
//! 单个源文件 ≤ 400 行是硬规矩（`开发规范.md` 第六节）。

use crate::{参数摘要, 错误码摘要, 能力契约, 能力摘要, 适配器};
use v1_contract::{能力号, 平台信息};
use v1_registry::{命令信息, 命令槽, 统一注册表};

// 契约串读法**全平台只有一份**：`运行内核/装载入口/src/读数.rs`（`读串` + `读契约串`，
// 上限 `契约串上限` = 4096，越界 / 无 NUL ⇒ 空串，**不 panic**）。本件不再自带扫描循环，
// 只把那份再导出 —— `crate::契约读取::读契约串` 这个路径逐字不变（`通知口` / `适配器定义` 按它取）。
pub(crate) use v1_loader::读契约串;

/// 命令的参数表 → 参数摘要（**行序原样保留**：调用方按这个顺序填值）。
pub(crate) fn 读参数表(命令: &命令信息) -> Vec<参数摘要> {
    if 命令.参数个数 == 0 || 命令.参数表.is_null() {
        return Vec::new();
    }
    // SAFETY: 契约保证 参数表 指向静态只读数组，长度 = 参数个数
    //（`注册表::建表` 已核过「项数 > 0 却给空项表」这一条）。
    let 项表 = unsafe { core::slice::from_raw_parts(命令.参数表, 命令.参数个数 as usize) };
    项表.iter()
        .map(|参数| 参数摘要 {
            // SAFETY: 契约保证一切串都是静态只读 NUL 结尾串。
            名称: unsafe { 读契约串(参数.名称) },
            类型标签: 参数.类型标签.取号值(),
            状态位: 参数.状态位,
            默认值: 参数.默认值,
        })
        .collect()
}

/// 声明的错误码表 → 错误码摘要（**声明的全表**，不是某条命令自身的）。
///
/// 用**声明自身的**错误码表（底座那份就是生成物 `错误码信息表`），不另存一份表。
/// 谁要「这条命令自身的可抛码」用 [`读命令可抛错误码`]；谁要查**调度层**产生的码
/// （段位 0，不属任何命令）的名称与三项业务判断，走 [`适配器::声明错误码表`]。
pub(crate) fn 读错误码表(声明: &平台信息) -> Vec<错误码摘要> {
    // 按字段取值，不搬整个 `表段`：`表段<T>` 只在 `T: Copy` 时才 `Copy`，而 `错误码信息`
    // 带裸指针、不是 `Copy`（与 `统一注册表::切片` 同一理由）。
    let 项数 = 声明.错误码表.项数;
    let 项表 = 声明.错误码表.项表;
    if 项数 == 0 || 项表.is_null() {
        return Vec::new();
    }
    // SAFETY: 契约保证 错误码表 指向静态只读数组。
    let 项表 = unsafe { core::slice::from_raw_parts(项表, 项数 as usize) };
    项表.iter()
        .map(|错误码| 错误码摘要 {
            码: 错误码.码,
            // SAFETY: 契约保证一切串都是静态只读 NUL 结尾串。
            名称: unsafe { 读契约串(错误码.名称) },
            // SAFETY: 同上。
            说明文字: unsafe { 读契约串(错误码.说明) },
            可重试: 错误码.可重试 != 0,
            可自愈: 错误码.可自愈 != 0,
            需人工: 错误码.需人工 != 0,
        })
        .collect()
}

/// **某条命令自身登记的可抛错误码** → 错误码摘要。
///
/// 命令的 `可抛错误码` 是一张**码号表**（`表段<错误码>`，源 = 声明里
/// `能力声明/<编号>.json` 的「可抛错误码」）；名称与三项业务判断从**声明的 `错误码表`**
/// 现查（内容只有那一份）。⇒ 交出去的是**这条命令自身的**码，不是声明全表。
///
/// 声明自洽时每个码都能在错误码表里查到；查不到（声明违反自洽）**不编名字**：
/// 给空名与三项 `false`，把「这个码登记缺失」暴露在返回里，不静默丢码。
pub(crate) fn 读命令可抛错误码(声明: &平台信息, 命令: &命令信息) -> Vec<错误码摘要> {
    // 按字段取值（同 `读错误码表` 的理由：`表段<T>` 只在 `T: Copy` 时才 `Copy`）。
    let 项数 = 命令.可抛错误码.项数;
    let 项表 = 命令.可抛错误码.项表;
    if 项数 == 0 || 项表.is_null() {
        return Vec::new();
    }
    // SAFETY: 契约保证 可抛错误码 指向静态只读数组，长度 = 项数。
    let 码号表 = unsafe { core::slice::from_raw_parts(项表, 项数 as usize) };
    let 全表 = 读错误码表(声明);
    码号表
        .iter()
        .map(|错误码| {
            let 号值 = 错误码.取号值();
            全表
                .iter()
                .find(|错误码项| 错误码项.码 == 号值)
                .cloned()
                .unwrap_or(错误码摘要 {
                    码: 号值,
                    名称: String::new(),
                    说明文字: String::new(),
                    可重试: false,
                    可自愈: false,
                    需人工: false,
                })
        })
        .collect()
}

