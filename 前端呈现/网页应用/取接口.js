// 接口面客户端 —— §二 四个冻结端点 + §七 工具族旁路（案例 / 导出 / 程序文本 / 菜单命令 / 列扩展），
// 同源相对路径，端口不写死。
//
// 路径逐字照 `项目文档/设计文档/接口面形状.md` §二（四个冻结端点）与 §七（工具族旁路）。
// **不写端口、不写主机**：
// 端口只有一个来源（`契约声明/常量表.json` 的「接口端口」），前端再写一份就是第二个来源。
// 浏览器会把非 ASCII 路径按 URL 规范编码成 `/%E6%8E%A5%E5%8F%A3`，接口面已做百分号解码。
//
// **本文件名刻意不叫 `接口.js`**：`接口.js` 在浏览器里就是 `/接口.js`，与冻结的端点前缀 `/接口`
// 同前缀；同源托管若按前缀分流（而不是按整段路径相等），静态件会被当成接口请求吃掉。
// 实测撞到过：取证用的同源反代按前缀分流，`/接口.js` 被转给了接口面、回 404，页面模块全挂。
// 接口面自身的路由是按整段路径相等的（`对外接口面/调用接口面/src/路由.rs`），不受影响；
// 但把文件名挪开，任何分流方式都不会再踩到它。

const 路径_根 = "/接口";
const 路径_能力 = "/接口/能力/";
const 路径_调用 = "/接口/调用";
const 路径_声明 = "/接口/声明";
const 路径_扩展 = "/接口/扩展";
// §七 工具族的其余四个（旁路端点；形状见 `接口面形状.md` §七 那张表）。
const 路径_案例 = "/接口/案例";
const 路径_案例跑 = "/接口/案例/跑";
const 路径_导出 = "/接口/导出";
const 路径_程序文本 = "/接口/程序文本";
const 路径_菜单命令 = "/接口/菜单命令";

/** `GET /接口` → 自描述根。 */
export async function 取根() {
  return 取应答(路径_根);
}

/**
 * `GET /接口/扩展` → 三类扩展清单（支持库 / 模块 / 技能）。
 *
 * **为什么要它**：`GET /接口` 只回能力的编号与名称，不回「这个能力属于哪个扩展」——
 * 没有它，左栏那棵树就只有叶子、没有枝。以前前端把扩展名与号段抄成常量，
 * 代价是加一个扩展就要改底座（破 README §五 硬边界 2），且底座里出现扩展的名字
 * 本身就破硬边界 1 ⇒ 改走这个端点（判据 ⑯ 守着这条）。
 */
export async function 取扩展() {
  return 取应答(路径_扩展);
}

/** `GET /接口/能力/<编号>` → 单条能力的完整契约。 */
export async function 取能力(编号) {
  return 取应答(路径_能力 + 编号);
}

/** `POST /接口/调用`。`体文` 是调用方拼好的请求体原文，**原样发出**。 */
export async function 调用能力(体文) {
  return 发请求(路径_调用, 体文);
}

/** `POST /接口/声明`。`体文` 原样发出。 */
export async function 写声明(体文) {
  return 发请求(路径_声明, 体文);
}

/**
 * §七 工具族旁路端点的薄封装。每个函数只做一件事：把参数**编码成请求体原文**（`JSON.stringify`
 * 是这里唯一的「编码」，理由同 `拼文本调用体`）并发出去，应答原样带回 —— 不判内容、不看键名。
 *
 * 请求体形状逐字照 `接口面形状.md` §七：`{"案例标识":"…"}` · `{"目标":"…","标识":…}` ·
 * `{"动作":"读|写","路径":"…","正文":"…"}` · `{"编号":"0xe100"}`。**合法性一律在后端判**
 * （不合法 ⇒ HTTP 400，业务失败 ⇒ 真错误码如 9001/9002/9004/9005/9008–9012）—— 本页不预判、不吞错。
 */

/** `GET /接口/案例` → 案例清单 + 每个案例的最新回执。 */
export async function 取案例() {
  return 取应答(路径_案例);
}

/** `POST /接口/案例/跑`，体 `{"案例标识":"…"}`。 */
export async function 跑案例(标识) {
  return 发请求(路径_案例跑, '{"案例标识":' + JSON.stringify(标识) + "}");
}

/**
 * `POST /接口/导出`，体 `{"目标":"…"}`（`标识` 给了才带上）。
 * `目标` 的五种取值由调用方给（本页不在这里判它合不合法 —— 非法由后端回 `9004`）。
 */
export async function 发导出(导出目标, 标识) {
  const 尾部 = 标识 ? ',"标识":' + JSON.stringify(标识) : "";
  return 发请求(路径_导出, '{"目标":' + JSON.stringify(导出目标) + 尾部 + "}");
}

/**
 * `POST /接口/程序文本`，体 `{"动作":"读"|"写","路径":"…","正文":"…"}`。
 *
 * `路径` 由**调用方自带**（裁决定落点 = 调用方自带路径，底座不新增目录约定、无隐式兜底）；
 * `正文` 只在 `写` 时给。本页只把参数编码成请求体原文（`JSON.stringify` 是这里唯一的编码），
 * 合法性一律在后端判（路径空 / 后缀不符 / 不存在 / 读不到 / 写不到各回一个明确码）。
 */
export async function 发程序文本(动作, 路径, 正文) {
  const 尾部 = 正文 === undefined ? "" : ',"正文":' + JSON.stringify(正文);
  return 发请求(路径_程序文本, '{"动作":' + JSON.stringify(动作)
    + ',"路径":' + JSON.stringify(路径 || "") + 尾部 + "}");
}

/** `POST /接口/菜单命令`，体 `{"编号":"0xe100"}`。后端此刻一律回 `9001`，本页如实显示。 */
export async function 发菜单命令(编号) {
  return 发请求(路径_菜单命令, '{"编号":' + JSON.stringify(编号) + "}");
}

/** 契约里的类型标签：`4` = 文本 · `0` = 空（`契约声明/类型声明/0004.json` · `0000.json`）。 */
export const 类型标签 = { 空标签: 0, 源文本: 4 };

/**
 * 拼一条「首实参是程序文本」的调用体。
 *
 * `参数个数` 由**契约**给（`GET /接口` 的 `参数个数`），本页不预设它一定是 1：
 * 首行放文本，其余位次按契约行序补空位（`{"类型标签":0,"值":0}`）——
 * 空位也要占一行，省略位次就是改行序（判据见 `项目文档/设计文档/接口面形状.md` §三）。
 * 这样后端给某个能力追加参数（例如语义分析要的几张表），本页一行不用改。
 *
 * `JSON.stringify` 在这里**只做一件事**：把编辑区里的文本编码成 JSON 字符串字面量
 * （引号 · 换行 · 反斜杠要按 JSON 规则转义，否则体本身就不合法）。
 * 它不改文本一个字节、不看文本内容、不认任何关键字 —— 不是「处理程序」，是编码传输串。
 */
export function 拼文本调用体(编号, 源文本, 参数个数) {
  const 待处理值 = [{ 类型标签: 类型标签.源文本, 值: 源文本 }];
  const 位次 = Math.max(1, Number(参数个数) || 1);
  for (let 项下标 = 1; 项下标 < 位次; 项下标 += 1) 待处理值.push({ 类型标签: 类型标签.空标签, 值: 0 });
  return '{"编号":' + 编号 + ',"值":' + JSON.stringify(待处理值) + "}";
}

/**
 * 同源只读取一份静态件（**不是端点**：这里读的是静态托管那一侧的普通文件）。
 *
 * 只把状态码与原文带回去，不认扩展名、不看内容。取不到就把取不到的原因原样摆出来。
 */
export async function 取静态件(路径) {
  const 造应答 = await fetch(路径, { headers: { Accept: "text/plain, */*" } });
  return { 状态: 造应答.status, 应答文本: await 造应答.text() };
}

async function 取应答(路径) {
  const 造应答 = await fetch(路径, { headers: { Accept: "application/json" } });
  return 收应答(造应答);
}

async function 发请求(路径, 体文) {
  const 造应答 = await fetch(路径, {
    method: "POST",
    headers: { "Content-Type": "application/json; charset=utf-8" },
    body: 体文,
  });
  return 收应答(造应答);
}

// 收一条应答。**本页不看键名、不判定内容**：只把状态码与原文带回去。
// 体用 `clone().json()` 试一次；拿不到就当原文摆出来（例如静态服务把 /接口 当文件找、
// 回一段 HTML —— 那是同源托管没接上，不是本页能修的事）。
async function 收应答(造应答) {
  let 应答体 = null;
  try {
    应答体 = await 造应答.clone().json();
  } catch {
    应答体 = null;
  }
  const 源文本 = await 造应答.text();
  return { 状态: 造应答.status, 报文体: 应答体, 应答文本: 源文本 };
}
