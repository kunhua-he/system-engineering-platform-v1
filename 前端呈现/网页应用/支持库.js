// 支持库 / 能力浏览 —— 把两个只读端点的结果摆清楚。
//
//   `GET /接口`            → 端点表 + 能力全量清单 + 契约版本 + 端口来源
//   `GET /接口/能力/<编号>` → 单条能力的完整契约：参数表（**行序即契约**）· 返回表 ·
//                            **可抛错误码**（每项带 可重试 / 可自愈 / 需人工）
//
// 摆法一律走 `呈现.js`：不看键名，只看值的类型。所以后端加字段本页不改一行。

import { 取根, 取能力 } from "./取接口.js";
import { 摆应答, 摆消息, 写状态 } from "./呈现.js";

export function 装支持库(取) {
  const 清单果 = 取("清单果");
  const 契约果 = 取("契约果");

  async function 取清单() {
    const 状态 = 取("清单状态");
    const 连 = 取("连接状态");
    写状态(状态, "请求中…");
    try {
      const 应答 = await 取根();
      摆应答(清单果, 应答);
      // HTTP 状态只表达「请求本身合不合法」：非 200 说明请求没走到端点（业务失败一律 200）。
      // 所以这里按状态码判「连上了没有」是传输层的事，不是对契约的解释。
      if (应答.状态 === 200) {
        写状态(状态, "已回", true);
        连.textContent = "网关已回";
        连.className = "状态 好";
      } else {
        写状态(状态, "HTTP " + 应答.状态, false);
        连.textContent = "网关连不上（HTTP " + 应答.状态 + "）";
        连.className = "状态 坏";
      }
    } catch (错) {
      摆消息(
        清单果,
        "发不出去：" + 错.message +
        "。本页用同源相对路径调 /接口，所以它必须由接口面同源托管（或由同源反代把 /接口 转给接口面）才调得通。"
      );
      写状态(状态, "失败", false);
      连.textContent = "网关连不上";
      连.className = "状态 坏";
    }
  }

  async function 取契约() {
    const 状态 = 取("契约状态");
    const 编号 = 取("契约编号").value.trim();
    写状态(状态, "请求中…");
    try {
      const 应答 = await 取能力(编号);
      摆应答(契约果, 应答);
      写状态(状态, 应答.状态 === 200 ? "已回" : "HTTP " + 应答.状态, 应答.状态 === 200);
    } catch (错) {
      摆消息(契约果, "发不出去：" + 错.message);
      写状态(状态, "失败", false);
    }
  }

  取("清单按钮").addEventListener("click", 取清单);
  取("契约按钮").addEventListener("click", 取契约);

  return { 取清单, 取契约 };
}
