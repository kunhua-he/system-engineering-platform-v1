// 应用 —— 接线。各个部分各自一个文件，本文件只把它们接到 DOM 上。
//
// 部分（判据：`项目文档/决策记录/2026-09-26_前端是网页版编译器.md` §一）：
//   ① 编辑器（编辑器.js）      ② 编译（编译.js）        ③ 运行/结果（index.html 里照实写）
//   ④ 案例库（案例库.js）      ⑤ 支持库/能力（支持库.js） ⑥ 调试（调试.js）
//   ⑦ 导出目标（导出目标.js）—— 五种出口这一个选择；没有导出端点，所以它不导出任何东西
//   ⑧ 菜单栏（菜单栏.js）—— 10 个顶层 / 181 项，1:1 取自 e.exe 的菜单资源 127
//   ⑨ 对话框（对话框.js）—— 判定进前端的 18 个，布局 1:1 取自资源类型 5
//   ⑩ 支持库树（支持库树.js）—— 左栏组件箱：号段 → 扩展 → 能力，叶子来自 `GET /接口`
//   ⑪ 底部 8 页签（底部页签.js）· 工具条（工具栏.js）· 窗口设计视图（设计视图.js）
//   ⑫ 剪辑历史（剪辑历史.js）—— 本页动作流水
//
// 本文件里没有一条业务分支：按钮点了就把活交给上面那些文件。

import { 装编辑器 } from "./编辑器.js";
import { 摆空状态, 跑编译, 跑诊断, 拉编译链, 链表 } from "./编译.js";
import { 装案例库 } from "./案例库.js";
import { 装支持库视图 } from "./支持库.js";
import { 装导出目标 } from "./导出目标.js";
import { 装调试 } from "./调试.js";
import { 装菜单栏 } from "./菜单栏.js";
import { 装程序文本 } from "./程序文本.js";
import { 装对话框 } from "./对话框.js";
import { 装支持库树 } from "./支持库树.js";
import { 装底页签 } from "./底部页签.js";
import { 装工具栏 } from "./工具栏.js";
import { 装设计视图 } from "./设计视图.js";
import { 装剪辑历史, 记流水 } from "./剪辑历史.js";

const 取元素 = (编号) => document.getElementById(编号);

const { 编辑, 载入示例, 清空 } = 装编辑器(取元素);

装剪辑历史();
const { 切页签 } = 装底页签();
const 支持库面板 = 装支持库视图(取元素);
const 支持库树 = 装支持库树(取元素, { 切页签, 取契约: 支持库面板.取契约 });
const 设计视图 = 装设计视图(取元素, {
  切页签,
  取清单: 支持库面板.取清单,
  取契约: 支持库面板.取契约,
  跑编译: () => 跑编译(取元素, 编辑),
  跑诊断: () => 跑诊断(取元素, 编辑),
});

// ── 视图切换：代码视图 ↔ 窗口设计视图（两视图共用标题栏 / 菜单栏 / 工具条）──────
let 视图 = "代码";
function 切视图() {
  视图 = 视图 === "代码" ? "设计" : "代码";
  const 设计态 = 视图 === "设计";
  document.body.classList.toggle("视图-设计", 设计态);
  document.body.classList.toggle("视图-代码", !设计态);
  取元素("代码面").hidden = 设计态;
  取元素("画布面").hidden = !设计态;
  取元素("设计面") && (取元素("设计面").hidden = !设计态);
  取元素("编辑页签").hidden = 设计态;
  取元素("设计页签").hidden = !设计态;
  取元素("视图按钮").textContent = 设计态 ? "代码视图" : "窗口设计视图";
  if (设计态) 设计视图.重绘();
  记流水("视图", "切到" + (设计态 ? "窗口设计视图" : "代码视图") + "（左栏 "
    + (设计态 ? "属性面板" : "支持库树") + " · 中栏 " + (设计态 ? "窗体画布" : "代码编辑区")
    + (设计态 ? " · 右栏 组件箱" : "") + "）");
}

装工具栏(取元素, {
  编辑,
  载入示例,
  清空,
  跑编译: () => 跑编译(取元素, 编辑),
  跑诊断: () => 跑诊断(取元素, 编辑),
  取清单: 支持库面板.取清单,
  取契约: 支持库面板.取契约,
  切页签,
  切视图,
  记流水,
});

装案例库(取元素, 编辑);
装导出目标(取元素, 编辑);
装程序文本(取元素);
装调试(取元素);
装菜单栏(取元素, 编辑, { 切页签 });
装对话框(取元素);

// ── 左栏底部那三条页签（参考图 y=544..565 的「支持库 · 程序 · 属性」那一格）──
for (const 按钮 of 取元素("左页签带").querySelectorAll(".页签")) {
  按钮.addEventListener("click", () => {
    // 设计视图下这三格被属性面板占着（参考图里那条页签也还在）—— 点它就切回代码视图再看那一格，
    // 否则点下去什么都不变，那就是个假按钮。
    if (视图 === "设计") 切视图();
    for (const 页签 of 取元素("左页签带").querySelectorAll(".页签")) 页签.classList.toggle("选", 页签 === 按钮);
    for (const 左格 of document.querySelectorAll(".左格")) 左格.classList.toggle("选", 左格.id === 按钮.dataset.左);
  });
}

取元素("视图按钮").addEventListener("click", 切视图);
取元素("编译按钮").addEventListener("click", () => 跑编译(取元素, 编辑));
// 「提示」那一栏里那个按钮也得接上 —— 不接就是**空响的按钮**（画了却点不动），
// 与左栏树那个折标同一条纪律：指示符/按钮是给用户的承诺，承诺了就得真做。
取元素("诊断按钮").addEventListener("click", () => 跑诊断(取元素, 编辑));

// 初始状态：诊断面板给一句人话（不留白屏）；左栏那棵树、编译链、与「变量表」「搜寻1」
// 都顺手拉一次清单 —— 吃的是同一次 `GET /接口` 的读数（编译链另要逐条读单条契约拿参数类型），
// 拉通/拉不通都会写在树的脚注、页头的连接状态与最底那条状态条上。
摆空状态(取元素);
支持库面板.取清单().then(() => 支持库树.拉清单()).then(() => 拉编译链()).then(() => {
  // 两个编号框的初值也实时取：链上第一步的编号（本页不写死一个能力编号）。
  if (链表.length) {
    取元素("调用编号").value = String(链表[0].编号);
    取元素("契约编号").value = String(链表[0].编号);
  }
  记流水("启动", "左栏组件箱已按号段折好（叶子来自 GET /接口）· 编译链已按契约实时取 · 变量表 / 搜寻1 同出这一次读数");
});
