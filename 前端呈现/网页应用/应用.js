//
// 六个部分（判据：`项目文档/决策记录/2026-09-26_前端是网页版编译器.md` §一）：
//   ① 编辑器（编辑器.js）      ② 编译（编译.js）        ③ 运行/结果（index.html 里照实写）
//   ④ 案例库（案例库.js）      ⑤ 支持库/能力（支持库.js） ⑥ 调试（调试.js）
//
// 本文件里没有一条业务分支：按钮点了就把活交给上面那六个文件。

import { 装编辑器 } from "./编辑器.js";
import { 摆空状态, 跑编译, 跑诊断 } from "./编译.js";
import { 装案例库 } from "./案例库.js";
import { 装支持库 } from "./支持库.js";
import { 装调试 } from "./调试.js";

const 取 = (编号) => document.getElementById(编号);

const { 编辑 } = 装编辑器(取);

装案例库(取, 编辑);
const 支持库 = 装支持库(取);
装调试(取);

取("编译按钮").addEventListener("click", () => 跑编译(取, 编辑));
取("诊断按钮").addEventListener("click", () => 跑诊断(取, 编辑));

// 初始状态：诊断面板给一句人话（不留白屏）；支持库那一栏顺手探一次根端点，
// 探通/探不通都会写在页头的「连接状态」上。
摆空状态(取);
支持库.取清单();
