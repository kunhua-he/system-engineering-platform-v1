// 编辑器 —— 写 `.程序文本` 的那个文本区。
//
// 它做的事只有四件，**一件都不多**：
//   ① `Tab` 插 4 个半角空格（挡住浏览器默认的换焦点）；
//   ② 行号栏跟着行数走（只报位置，不认内容）；
//   ③ 报光标位置与字符数；
//   ④ 载入语料：经 `POST /接口/程序文本` 真读调用方给的路径（空路径 = 内置模板，不调端点）。
//
// **没有语法高亮，也没有任何别的「智能」** —— 不做自动缩进、不做括号配对、不做补全。
// 编辑器只是文本区：程序文本的解释权全在后端（判据：`项目文档/设计文档/接口面形状.md` §五）。

import { 发程序文本 } from "./取接口.js";
import { 摘要, 写状态 } from "./呈现.js";

/** 本页内置的极小模板 —— 不是语料，只是让编辑区一开始不空着。 */
const 模板 = [
  ".版本 2",
  "",
  ".程序集 程序集1",
  "",
  ".子程序 样例, 整数",
  "    返回 1",
  "",
].join("\n");

/**
 * 载入示例的清单：`[标签, 路径]`。**路径由本页（调用方）自带** —— 裁决
 * （`项目文档/决策记录/2026-09-28_华哥的尺子与七条裁决.md` §二 206 行）定「项目/程序文本
 * 那一层」的落点 = **调用方自带路径**（底座不新增目录约定、无隐式兜底），故清单也由调用方给。
 *
 * 空串路径 = 内置模板（**没有落点**，不调端点）；非空路径 = 经 `POST /接口/程序文本` 真读。
 *
 * **曾经**这里列了 6 条指向仓内**语料目录**的入口，两条都站不住、已撤：
 *  1. **取不到**：那 6 条走静态托管直接取件，而托管根是 `前端呈现/网页应用` ⇒ 仓内路径恒 404；
 *  2. **破硬边界**：那 6 条路径里出现了某个扩展的名字与它的私有目录（README §五 硬边界 1）。
 *
 * 现在这条路改走**端点**（不再直取静态件 ⇒ 没有 404 问题），且清单里**不出现任何扩展名**
 * （不破硬边界）—— 只列仓内既有的 `.程序文本` 件。
 */
export const 示例表 = [
  ["本页内置的极小模板（不是语料）", ""],
  ["仓内真程序文本（测试验证/案例/真程序文本/输入.程序文本）", "测试验证/案例/真程序文本/输入.程序文本"],
];

/**
 * 读「示例选」当前选中那条的路径（空串 = 内置模板，没有落点）。
 * `选中` 是「示例选」这个 `<select>` 节点。
 */
export function 选中路径(选中) {
  const 位 = Number(选中 && 选中.value) || 0;
  const 行 = 示例表[位] || 示例表[0];
  return 行 ? 行[1] : "";
}

/** 取编辑区原文。 */
export function 取文本(编辑) {
  return 编辑.value;
}

/** 往编辑区放文本（**原样**，不规范化换行、不动缩进）。 */
export function 置文本(编辑, 文本) {
  编辑.value = 文本 === undefined || 文本 === null ? "" : String(文本);
  编辑.dispatchEvent(new Event("input"));
}

/**
 * 装好编辑器。返回 `{ 编辑, 重绘 }`。
 * `取元素` 是 `(id) => 节点`，由 `应用.js` 给（本文件不认 id 字符串之外的页面结构）。
 */
export function 装编辑器(取元素) {
  const 编辑 = 取元素("编辑区");
  const 号 = 取元素("行号");
  const 行列 = 取元素("行列读数");
  const 字数 = 取元素("字数读数");

  function 刷光标() {
    const 前 = 编辑.value.slice(0, 编辑.selectionStart);
    const 行 = 前.split("\n").length;
    const 列 = 前.length - (前.lastIndexOf("\n") + 1) + 1;
    行列.textContent = 行 + " : " + 列;
  }

  function 重绘() {
    const 文 = 编辑.value;
    const 行数 = 文.split("\n").length;
    if (号.dataset.行数 !== String(行数)) {
      号.dataset.行数 = String(行数);
      const 表 = [];
      for (let 序 = 1; 序 <= 行数; 序 += 1) 表.push(String(序));
      号.textContent = 表.join("\n");
    }
    字数.textContent = String(文.length);
    刷光标();
  }

  编辑.addEventListener("input", 重绘);
  编辑.addEventListener("keyup", 刷光标);
  编辑.addEventListener("click", 刷光标);
  编辑.addEventListener("scroll", () => {
    号.scrollTop = 编辑.scrollTop;
  });

  编辑.addEventListener("keydown", (事件) => {
    if (事件.key !== "Tab" || 事件.ctrlKey || 事件.metaKey || 事件.altKey) return;
    事件.preventDefault();
    编辑.setRangeText("    ", 编辑.selectionStart, 编辑.selectionEnd, "end");
    重绘();
  });

  // 示例下拉与载入按钮
  const 选 = 取元素("示例选");
  const 状态 = 取元素("工具状态");
  示例表.forEach(([标签], 位置) => {
    const 项 = document.createElement("option");
    项.value = String(位置);
    项.textContent = 标签;
    选.append(项);
  });

  // 工具条的「打开」也走这里，所以只写一份（载入示例）。
  // 有路径 ⇒ 经 `POST /接口/程序文本` 真读；空路径 ⇒ 内置模板（没有落点，不调端点）。
  async function 载入示例() {
    const 路径 = 选中路径(选);
    if (!路径) {
      置文本(编辑, 模板);
      写状态(状态, "已载入内置模板（没有落点，不是语料）", true);
      return "已载入内置模板（不是语料）";
    }
    写状态(状态, "载入中… " + 路径);
    const 应答 = await 发程序文本("读", 路径);
    const 数据 = 应答.体 && 应答.体.数据;
    if (摘要(应答.体).类 === "好" && 数据 && typeof 数据.文本 === "string") {
      置文本(编辑, 数据.文本);
      写状态(状态, "已载入 " + 路径 + "（" + 数据.字符数 + " 字符）", true);
      return "已载入 " + 路径;
    }
    // 失败：把真错误码原样报出来（后端逐种失败各报一个明确码）。
    const 码 = 应答.体 && 应答.体.错误 && 应答.体.错误.码;
    写状态(状态, "载入失败 · HTTP " + 应答.状态 + (码 === undefined ? "" : " · 码 " + 码), false);
    return "载入失败 · HTTP " + 应答.状态 + (码 === undefined ? "" : " · 码 " + 码);
  }

  // 工具条的「新建」「清空」都走这里。
  function 清空编辑() {
    置文本(编辑, "");
    写状态(取元素("工具状态"), "已清空（0 字符）", true);
    return "已清空（0 字符）";
  }

  取元素("载入按钮").addEventListener("click", () => {
    载入示例().catch((错误) => 写状态(状态, "载入失败：" + 错误.message, false));
  });
  取元素("清空按钮").addEventListener("click", 清空编辑);

  重绘();
  return { 编辑, 重绘, 载入示例, 清空: 清空编辑 };
}
