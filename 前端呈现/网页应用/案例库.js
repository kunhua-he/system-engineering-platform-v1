// 案例库 —— 案例族（列 / 跑 / 回执）接 §七 工具族端点 + 一个通用同源只读口。
//
// 案例族的正路是 §七 的两个旁路端点（形状见 `项目文档/设计文档/接口面形状.md` §七）：
//   `GET  /接口/案例`     → 案例清单；每项带「有没有回执」「最新回执」
//   `POST /接口/案例/跑`  → 跑一个案例，回执随应答带回
// **判定全在后端**：案例根读不到回 `9002`、回执缺失回 `9003` —— 本页不预判、不吞错，
// 把结构化回执原样摆出来（`呈现.js` 不看键名，只看值的类型）。
//
// 「读回执 / 看最新回执」就是上面两个应答里的 `最新回执` / `回执` 那一项：通用渲染器
// 把它连同错误码一起摆出来，本页不另写一份回执读法（后端加字段，本页不改一行）。
//
// 通用同源只读口（`读件*` 那几个 id）保留：它读的是静态托管那一侧的普通文件，不是端点、
// 不是业务。案例根与回执件的仓内相对路径是 `测试验证/案例/`。
//
// 注：源码里写全这个路径，靠的是 `自检.sh` 的判据已从「词命中」改成「位置判据」
// —— 路径里的「验证」是名词，不再被当成「前端在做验证」。

import { 取静态件, 取案例, 跑案例 } from "./取接口.js";
import { 建元素, 清空容器, 摆静态件, 摆应答, 摆消息, 取应答摘要, 写状态 } from "./呈现.js";
import { 置文本 } from "./编辑器.js";
import { 记流水 } from "./剪辑历史.js";

/** 把用户敲的路径补成同源绝对路径（只补一个前导斜杠，其余原样）。 */
function 补成绝对路径(文本) {
  const 净文本 = (文本 || "").trim();
  if (!净文本) return "";
  return 净文本.startsWith("/") ? 净文本 : "/" + 净文本;
}

/** 按值的类型给一句状态（成功 / 失败），**不读键名**（同 `呈现.js::取应答摘要`）。 */
function 报状态(状态, 造应答, 尾部) {
  const 摘要结果 = 取应答摘要(造应答.体);
  写状态(状态, "HTTP " + 造应答.状态 + " · " + 摘要结果.词 + (尾部 ? " · " + 尾部 : ""),
    摘要结果.类 === "好" ? true : 摘要结果.类 === "坏" ? false : undefined);
  return 摘要结果;
}

export function 装案例库(取元素, 编辑) {
  // ── 案例族 ─────────────────────────────────────────────────────────────
  const 状态 = 取元素("案例状态");
  const 结果 = 取元素("案例果");

  async function 列案例() {
    清空容器(结果);
    写状态(状态, "取案例清单中…");
    try {
      const 造应答 = await 取案例();
      摆应答(结果, 造应答);
      const 摘要结果 = 报状态(状态, 造应答);
      记流水("案例", "列案例 · HTTP " + 造应答.状态 + " · " + 摘要结果.词);
    } catch (错误) {
      摆消息(结果, "发不出去：" + 错误.message);
      写状态(状态, "发不出去", false);
    }
  }

  async function 跑一个案例() {
    const 标识 = 取元素("案例标识").value.trim();
    if (!标识) {
      写状态(状态, "先填一个案例标识（一个目录名，不含路径分隔符）", false);
      return;
    }
    清空容器(结果);
    写状态(状态, "跑 " + 标识 + " …");
    try {
      const 造应答 = await 跑案例(标识);
      摆应答(结果, 造应答);
      const 摘要结果 = 报状态(状态, 造应答);
      记流水("案例", "跑案例 " + 标识 + " · HTTP " + 造应答.状态 + " · " + 摘要结果.词);
    } catch (错误) {
      摆消息(结果, "发不出去：" + 错误.message);
      写状态(状态, "发不出去", false);
    }
  }

  取元素("案例列按钮").addEventListener("click", 列案例);
  取元素("案例跑按钮").addEventListener("click", 跑一个案例);
  取元素("案例标识").addEventListener("keydown", (事件) => {
    if (事件.key === "Enter") 跑一个案例();
  });

  // ── 通用同源只读口（静态件，不是端点）──────────────────────────────────
  const 路框 = 取元素("读件路");
  const 读果 = 取元素("读件果");
  const 读状态 = 取元素("读件状态");
  let 上次文 = null;

  取元素("读件按钮").addEventListener("click", async () => {
    const 路径 = 补成绝对路径(路框.value);
    if (!路径) {
      写状态(读状态, "先填一个仓内相对路径", false);
      return;
    }
    写状态(读状态, "读 " + 路径 + " …");
    try {
      const 节点件 = await 取静态件(路径);
      上次文 = 节点件.状态 === 200 ? 节点件.文 : null;
      摆静态件(读果, 路径, 节点件);
      写状态(读状态, 节点件.状态 === 200 ? "已回 " + 节点件.文.length + " 字符" : "HTTP " + 节点件.状态, 节点件.状态 === 200);
    } catch (错误) {
      上次文 = null;
      清空容器(读果);
      读果.append(建元素("p", "提示 坏", "发不出去：" + 错误.message));
      写状态(读状态, "发不出去", false);
    }
  });

  取元素("载入读件").addEventListener("click", () => {
    if (上次文 === null) {
      写状态(读状态, "还没取到东西 —— 先点「同源只读取回原文」", false);
      return;
    }
    置文本(编辑, 上次文);
    写状态(读状态, "已载入编辑器（" + 上次文.length + " 字符）", true);
  });
}
