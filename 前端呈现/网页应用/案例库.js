// 案例库 —— 面板 + 一个同源只读口。
//
// **面板本体读不了案例目录**，这是实测出来的缺口，不是没做：
// `GET /接口/案例` 与 `POST /接口/案例/跑` 是 §七 的工具族旁路端点（端点表见「变量表」），
// **本面板还没接它们**；而同源静态托管那一侧只托管前端自己的件（`常量.rs::静态根`），
// 所以仓内路径 `/测试验证/案例/…` 一律 404。⇒ 本面板**不列案例、不跑案例**，
// 摆一个按不动的按钮就是假成功。
//
// 能给的是一个**通用只读口**：把仓内相对路径敲进来，同源取回原文原样摆出来。
// 它不认扩展名、不看内容、不判定，所以它既不是端点，也不是业务。
// 案例根的仓内相对路径就是 `测试验证/案例/`（回执是它下面的 `运行回执.jsonl`）。
//
// 注：源码里写全这个路径，靠的是 `自检.sh` 的判据已从「词命中」改成「位置判据」
// （`未完成事项.md` #161）—— 路径里的「验证」是名词，不再被当成「前端在做验证」。

import { 取静态件 } from "./取接口.js";
import { 建, 清空, 摆件, 写状态 } from "./呈现.js";
import { 置文本 } from "./编辑器.js";

/** 把用户敲的路径补成同源绝对路径（只补一个前导斜杠，其余原样）。 */
function 成路(文) {
  const 净 = (文 || "").trim();
  if (!净) return "";
  return 净.startsWith("/") ? 净 : "/" + 净;
}

export function 装案例库(取, 编辑) {
  const 路框 = 取("读件路");
  const 果 = 取("读件果");
  const 状态 = 取("读件状态");
  let 上次文 = null;

  取("读件按钮").addEventListener("click", async () => {
    const 路 = 成路(路框.value);
    if (!路) {
      写状态(状态, "先填一个仓内相对路径", false);
      return;
    }
    写状态(状态, "取 " + 路 + " …");
    try {
      const 件 = await 取静态件(路);
      上次文 = 件.状态 === 200 ? 件.文 : null;
      摆件(果, 路, 件);
      写状态(状态, 件.状态 === 200 ? "已回 " + 件.文.length + " 字符" : "HTTP " + 件.状态, 件.状态 === 200);
    } catch (错) {
      上次文 = null;
      清空(果);
      果.append(建("p", "提示 坏", "发不出去：" + 错.message));
      写状态(状态, "发不出去", false);
    }
  });

  取("载入读件").addEventListener("click", () => {
    if (上次文 === null) {
      写状态(状态, "还没取到东西 —— 先点「同源只读取回原文」", false);
      return;
    }
    置文本(编辑, 上次文);
    写状态(状态, "已载入编辑器（" + 上次文.length + " 字符）", true);
  });
}
