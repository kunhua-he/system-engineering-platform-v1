/** 当前选中的那一条（下拉的 value 是表内位次，不是名字）。 */
function 选中(取元素) {
  const 位 = Number(取元素("出口选").value || 0);
  return 出口表[位] || 出口表[0];
}

/** 摆当前选择的那张卡：文档定了什么就摆什么，本页不添一个字段。 */
function 摆卡(取元素) {
  const 盒 = 取元素("出口卡");
  const 项 = 选中(取元素);
  清空(盒);
  const 行 = (键, 值, 类名) => {
    const 节 = 建("div", "键值行");
    节.append(建("div", "键", 键));
    节.append(建("div", 类名 || "内", 值));
    盒.append(节);
  };
  行("产物形态", 项.形态);
  行("号段", 项.号段);
  行("落点（仓内相对路径）", 项.落点);
  行("现状（照 导出目标.md §二）", 项.现状);
  行("能不能导", 项.卡在哪, "内 卡点");
  if (项.注) 盒.append(建("p", "提示", 项.注));
}

/**
 * 真调一次编译链，把「死在哪一步 · HTTP 几 · 码几」原样摆出来。
 *
 * 本页**不复刻编译面板**：它复用 `编译.js` 的 `链表`（同样是 `GET /接口` 实时取的），
 * 只报一个读数 —— 导出要的正是这个前提（先把声明与最小代码编成产物），所以碰到第一个坏步就停。
 * 判定仍全在后端：本页只把 `false` 认成坏、把值原样摆出来（`前端呈现/说明.md` §四 第 1 条）。
 */
async function 探一次(取元素, 编辑) {
  const 状态 = 取元素("出口状态");
  const 果 = 取元素("出口探果");
  const 项 = 选中(取元素);
  const 文本 = 编辑.value;
  清空(果);
  写状态(状态, "真调编译链中…");

  const 链错 = 链表.length ? null : await 拉链();
  if (链错) {
    写状态(状态, 链错, false);
    果.append(建("p", "提示 坏", "编译链取不到：" + 链错 + "。链从 `GET /接口` 实时取，取不到就没有可探的前提。"));
    return;
  }

  let 死 = null;
  let 末 = null;
  for (let 位 = 0; 位 < 链表.length; 位 += 1) {
    const 名 = 链表[位].名称;
    const 编号 = 链表[位].编号;
    let 应答 = null;
    try {
      应答 = await 调用能力(拼文本调用体(编号, 文本, 链表[位].参数个数));
    } catch (错) {
      写状态(状态, "发不出去", false);
      果.append(
        建("p", "提示 坏", "请求没能送出去：" + 错.message + "。本页用同源相对路径调 /接口，网关没接上就取不到任何读数 —— 这也是真读数。")
      );
      return;
    }
    末 = 应答;
    const 词 = 应答.状态 === 200 ? 摘要(应答.体) : { 词: "HTTP " + 应答.状态, 类: "坏" };
    if (词.类 === "坏") {
      死 = { 位, 名, 编号, 应答 };
      break;
    }
  }

  const 行 = 建("div", "行内");
  if (死) {
    行.append(建("span", "假", "死在第 " + (死.位 + 1) + " 步 · " + 死.名 + "（编号 " + 死.编号 + "）"));
    写状态(状态, "编译链死在第 " + (死.位 + 1) + " 步 · " + 死.名, false);
  } else {
    行.append(建("span", "真", "链上 " + 链表.length + " 步都回了"));
    写状态(状态, "链上 " + 链表.length + " 步都回了", true);
  }
  摆行内(行, (死 ? 死.应答 : 末).体);
  果.append(行);

  const 盒 = 建("div", "果");
  摆应答(盒, 死 ? 死.应答 : 末);
  果.append(盒);

  果.append(
    建("p", "提示 坏", "当前选择「" + 项.名 + "」——" + 项.卡在哪 + "。上面那行是此刻真调回来的读数（成功 false 后面那段「错误」里的 码 与 名称 就是死因），不是本页写的结论。")
  );
}

/**
 * 触发一次真导出：`POST /接口/导出`，体 `{"目标":"<选中的出口>"}`（`标识` 框填了才带上）。
 *
 * **本页不判目标合不合法、不判这条出口通没通** —— 目标名取自本页那张表（表是照文档写的），
 * 判定全在后端：非法目标回 `9004`、导出动作失败 / 出口无落点回 `9005`。回执里的
 * `程序` · `参数` · `退出码` · `标准输出` · `标准错误` 与真错误码一律原样摆出来，**不吞错**。
 */
async function 触发导出(取元素) {
  const 状态 = 取元素("导出状态");
  const 果 = 取元素("导出果");
  const 项 = 选中(取元素);
  const 标识 = 取元素("导出标识").value.trim();
  清空(果);
  写状态(状态, "导出「" + 项.名 + "」中…");
  try {
    const 应答 = await 发导出(项.名, 标识);
    摆应答(果, 应答);
    const 词 = 摘要(应答.体);
    写状态(状态, "HTTP " + 应答.状态 + " · " + 词.词,
      词.类 === "好" ? true : 词.类 === "坏" ? false : undefined);
    记("导出", "目标 " + 项.名 + (标识 ? " · 标识 " + 标识 : "") + " · HTTP " + 应答.状态 + " · " + 词.词);
  } catch (错) {
    果.append(建("p", "提示 坏", "发不出去：" + 错.message));
    写状态(状态, "发不出去", false);
  }
}

/** 装好导出目标这一区：下拉五个选项 + 一个真调按钮。 */
export function 装导出目标(取元素, 编辑) {
  const 选 = 取元素("出口选");
  出口表.forEach((项, 位) => {
    const 项节 = document.createElement("option");
    项节.value = String(位);
    项节.textContent = 项.名 + " · " + 项.号段;
    选.append(项节);
  });
  选.addEventListener("change", () => 摆卡(取元素));
  取元素("探出口按钮").addEventListener("click", () => 探一次(取元素, 编辑));
  取元素("导出按钮").addEventListener("click", () => 触发导出(取元素));
  摆卡(取元素);
  return { 摆卡 };
}
