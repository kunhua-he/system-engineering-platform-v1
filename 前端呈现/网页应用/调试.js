// 调试（维护者用）—— 上一版那两个「调用」与「声明」的块，原样保留功能，降级到这一页。
//
// 定位：这两个是**维护者用的**（`项目文档/决策记录/2026-09-26_前端是网页版编译器.md` §一：
// 「上一版做的能力清单/调用/声明不删，降级成其中的『调试』页」）。主线是编辑器与编译。
//
// 本文件的全部工作：**收输入 · 拼请求体原文 · 发出去 · 把应答交给 呈现.js 摆出来**。
// 这里没有一条分支在问「这个值对不对」「这个编号合不合法」——那些是后端的事，
// 前端再问一次就是第二套判定（`接口面形状.md` §五 三条不许之一）。
//
// 请求体是**拼字符串**拼出来的：敲什么就原样进体。所以敲了不合法的东西，后端回 400，
// 本页把它摆出来 —— 这正是「判定在后端」该有的样子。

import { 调用能力, 写声明 } from "./取接口.js";
import { 建元素, 摆应答, 摆消息, 写状态 } from "./呈现.js";

export function 装调试(取元素) {
  // ── 调用 ────────────────────────────────────────────────────────────────
  function 加值行(标签初值 = "0", 值初值 = "0") {
    const 源码行 = 建元素("div", "值行");
    const 序号 = 建元素("span", "序");
    const 标签 = 建元素("input", "标签");
    标签.type = "text";
    标签.inputMode = "numeric";
    标签.value = 标签初值;
    const 待处理值 = 建元素("input", "值");
    待处理值.type = "text";
    待处理值.value = 值初值;
    待处理值.placeholder = '值的原文：文本带引号如 "你好"；字节集填 base64 如 "aGk="；整数填 0';
    const 删除钮 = 建元素("button", "次 小", "删");
    删除钮.addEventListener("click", () => {
      源码行.remove();
      重排值行();
      刷调用预览();
    });
    源码行.append(序号, 标签, 待处理值, 删除钮);
    取元素("值行容器").append(源码行);
    重排值行();
    刷调用预览();
  }

  function 重排值行() {
    [...取元素("值行容器").querySelectorAll(".值行")].forEach((源码行, 位置) => {
      源码行.querySelector(".序").textContent = String(位置 + 1);
    });
  }

  function 取调用体文() {
    const 编号 = 取元素("调用编号").value.trim();
    const 一项 = [...取元素("值行容器").querySelectorAll(".值行")].map((源码行) => {
      const 标签 = 源码行.querySelector(".标签").value.trim();
      const 待处理值 = 源码行.querySelector(".值").value.trim();
      return '{"类型标签":' + 标签 + ',"值":' + 待处理值 + "}";
    });
    return '{"编号":' + 编号 + ',"值":[' + 一项.join(",") + "]}";
  }

  function 刷调用预览() {
    取元素("调用体文").textContent = 取调用体文();
  }

  async function 发调用() {
    const 结果 = 取元素("调用果");
    const 体文 = 取调用体文();
    刷调用预览();
    写状态(取元素("调用状态"), "请求中…");
    try {
      const 造应答 = await 调用能力(体文);
      摆应答(结果, 造应答);
      写状态(取元素("调用状态"), 造应答.状态 === 200 ? "已回" : "HTTP " + 造应答.状态, 造应答.状态 === 200);
    } catch (错误) {
      摆消息(结果, "发不出去：" + 错误.message);
      写状态(取元素("调用状态"), "失败", false);
    }
  }

  // ── 声明 ────────────────────────────────────────────────────────────────
  function 取声明体文() {
    return (
      '{"类别":' + 取元素("声明类别").value.trim() +
      ',"编号":' + 取元素("声明编号").value.trim() +
      ',"正文":' + 取元素("声明正文").value.trim() + "}"
    );
  }

  function 刷声明预览() {
    取元素("声明体文").textContent = 取声明体文();
  }

  async function 发声明() {
    const 结果 = 取元素("声明果");
    const 体文 = 取声明体文();
    刷声明预览();
    写状态(取元素("声明状态"), "请求中…");
    try {
      const 造应答 = await 写声明(体文);
      摆应答(结果, 造应答);
      写状态(取元素("声明状态"), 造应答.状态 === 200 ? "已回" : "HTTP " + 造应答.状态, 造应答.状态 === 200);
    } catch (错误) {
      摆消息(结果, "发不出去：" + 错误.message);
      写状态(取元素("声明状态"), "失败", false);
    }
  }

  // ── 接线 ────────────────────────────────────────────────────────────────
  取元素("调用按钮").addEventListener("click", 发调用);
  取元素("声明按钮").addEventListener("click", 发声明);
  取元素("加行按钮").addEventListener("click", () => 加值行());

  取元素("调用编号").addEventListener("input", 刷调用预览);
  取元素("值行容器").addEventListener("input", 刷调用预览);
  for (const 号值 of ["声明类别", "声明编号", "声明正文"]) {
    取元素(号值).addEventListener("input", 刷声明预览);
  }

  加值行();
  刷声明预览();
}
