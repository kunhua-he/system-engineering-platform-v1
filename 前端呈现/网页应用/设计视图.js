// 设计视图 —— 窗口设计视图那三栏：左=属性面板 · 中=窗体画布 · 右=组件箱。
//
// 形状逐像素取自第二张截图（`项目文档/参考/易语言IDE_窗口设计区_截图.png`）：三栏宽度 ·
// 属性名列底 #d0dee3 / 值列底 #ffffff · 行距 17 · 画布底 #a0a0a0 · 组件箱底 #f0f0f0。
// 属性名那一列**逐字照抄参考图**（名称 · 备注 · 左边 · 顶边 · 宽度 · 高度 · 标记 · 可视 ·
// 禁止 · 鼠标指针 · 默认类型 · 字体 · 界面风格 · 矩形），末行那句「在此处选择加入事件处理子程序」也照抄。
//
// **值全部是真实的**：左边/顶边/宽度/高度读的是控件在窗体里的实际几何，可视/禁止读的是
// DOM 自身的状态，字体读的是 `getComputedStyle`。本平台没有这一层属性的（界面风格），
// 值就写「（本平台没有这一层）」—— 不编一个值出来。
//
// 组件箱摆的是**我们自身的能力**（`GET /接口` 实时应答），不是易语言那套控件名：
//   · 基本组件 = 底座自有（号段 0–999）的能力
//   · 扩展组件 = 从扩展根热载入的能力（号段 1000–9999）
//
// **拖放出代码不做**：它依赖运行时控件库（界面与呈现，号段 6000–6999 的窗口/按钮/编辑框
// 能力编号一个都还没有）与代码生成器（本仓没有这一层）—— 语言主线（含语义分析与编译）
// 已于 2026-09-28 落地，不再是卡点。画布上如实标注这一句，见 `画布注`。

import { 取根, 取能力 } from "./取接口.js";
import { 建元素, 清空容器, 写状态 } from "./呈现.js";
import { 找段, 找扩展, 拉扩展表 } from "./号段表.js";
import { 画图标 } from "./图标.js";

/** 属性名列：逐字照抄参考图那一列，行序也一样。 */
export const 属性名表 = ["名称", "备注", "左边", "顶边", "宽度", "高度", "标记", "可视",
  "禁止", "鼠标指针", "默认类型", "字体", "界面风格", "矩形"];

export function 装设计视图(取元素, 钩子) {
  const 属表 = 取元素("属表");
  const 属头名 = 取元素("属头名");
  const 属头类 = 取元素("属头类");
  const 组件箱 = 取元素("组件箱");
  const 窗体身 = 取元素("窗体身");
  const 画布 = 取元素("画布");
  let 选中 = null;
  let 能表 = [];

  // ── 属性面板 ───────────────────────────────────────────────────────────
  function 摆属性(键值对) {
    属头名.textContent = 键值对.名;
    属头类.textContent = 键值对.类;
    清空容器(属表);
    for (const 名称 of 属性名表) {
      const 源码行 = 建元素("div", "属行");
      源码行.append(建元素("div", "属名", 名称));
      源码行.append(建元素("div", "属值", String(键值对.值[名称] ?? "（空）")));
      属表.append(源码行);
    }
  }

  /** 从一个真 DOM 控件读它的属性值 —— 几何读实际盒子，状态读 DOM 自身。 */
  function 读件属性(元素, 名称, 类别) {
    const 窗体矩形 = 窗体身.getBoundingClientRect();
    const 容器盒 = 元素.getBoundingClientRect();
    const 算得样式 = getComputedStyle(元素);
    return {
      名: 名称, 类: 类别,
      值: {
        名称: 元素.id || "（未命名）",
        备注: 元素.title || "（空）",
        左边: Math.round(容器盒.left - 窗体矩形.left),
        顶边: Math.round(容器盒.top - 窗体矩形.top),
        宽度: Math.round(容器盒.width),
        高度: Math.round(容器盒.height),
        标记: 元素.dataset.标记 || "（空）",
        可视: 算得样式.visibility === "hidden" || 算得样式.display === "none" ? "假" : "真",
        禁止: 元素.disabled ? "真" : "假",
        鼠标指针: 算得样式.cursor,
        默认类型: 元素.tagName.toLowerCase() === "button" ? (元素.type || "submit") : "（无）",
        字体: 算得样式.fontFamily.split(",")[0] + ", " + 算得样式.fontSize,
        界面风格: "（本平台没有这一层）",
        矩形: [Math.round(容器盒.left - 窗体矩形.left), Math.round(容器盒.top - 窗体矩形.top),
          Math.round(容器盒.width), Math.round(容器盒.height)].join(", "),
      },
    };
  }

  /** 从一个能力读它的属性 —— 能读的都是应答里真有的字段，读不到的老实写「（应答里没有）」。 */
  function 读能属性(能力) {
    const 编号 = Number(能力.编号);
    const 号段 = 找段(编号);
    const 扩展 = 找扩展(编号);
    return {
      名: String(能力.名称), 类: "能力 " + 编号,
      值: {
        名称: String(能力.名称),
        备注: "号段 " + (号段 ? 号段.名 + "（" + 号段.段起点 + "–" + 号段.止 + "）" : "（落不进任何一段）"),
        左边: "（不适用：能力没有屏幕位置）",
        顶边: "（不适用：能力没有屏幕位置）",
        宽度: String(能力.参数个数) + " 个参数",
        高度: "返回类型 " + String(能力.返回类型),
        标记: 扩展 ? 扩展.名 + " · " + 扩展.种类 : "底座自有",
        可视: "真（GET /接口 回了它）",
        禁止: "假",
        鼠标指针: "（不适用）",
        默认类型: "（不适用）",
        字体: "（不适用）",
        界面风格: "（本平台没有这一层）",
        矩形: "（不适用）",
      },
    };
  }

  function 选件(元素, 名称, 类别) {
    if (选中) 选中.classList.remove("选");
    选中 = 元素;
    if (元素) 元素.classList.add("选");
    摆属性(读件属性(元素, 名称, 类别));
  }

  // ── 窗体画布：控件是真 DOM，每一个都有真动作 ─────────────────────────
  function 摆控件(元素, 左边距, 顶边距, 宽度, 高度, 类别) {
    元素.style.position = "absolute";
    元素.style.left = 左边距 + "px";
    元素.style.top = 顶边距 + "px";
    元素.style.width = 宽度 + "px";
    元素.style.height = 高度 + "px";
    // 空类名不往下加：`classList.add("")` 会抛 DOMTokenList 的错（实测撞到过）。
    if (类别) 元素.classList.add(类别);
    return 元素;
  }

  function 装画布() {
    清空容器(窗体身);
    const 标签件 = 建元素("div", "窗件 标签", "系统工程平台 · 窗体1（只摆形状：拖放出代码不做，缺控件库 · 代码生成器）");
    标签件.id = "标签_题";
    摆控件(标签件, 8, 6, 470, 16, "标签");
    窗体身.append(标签件);

    const 钮表 = [
      ["按钮_清单", "取清单", () => { 钩子.切页签("搜寻1"); return 钩子.取清单(); }],
      ["按钮_契约", "取契约", () => { 钩子.切页签("搜寻2"); return 钩子.取契约(取元素("契约编号").value.trim()); }],
      ["按钮_编译", "编译", () => { 钩子.切页签("提示"); return 钩子.跑编译(); }],
      ["按钮_诊断", "诊断", () => { 钩子.切页签("提示"); return 钩子.跑诊断(); }],
    ];
    钮表.forEach(([号值, 文本, 动作], 位置) => {
      const 按钮 = 建元素("button", "窗件", 文本);
      按钮.id = 号值;
      摆控件(按钮, 8 + 位置 * 92, 30, 86, 24, "");
      按钮.addEventListener("click", (界面事件) => { 界面事件.stopPropagation(); 动作(); });
      按钮.addEventListener("mousedown", (界面事件) => { 界面事件.stopPropagation(); 选件(按钮, 文本, "按钮"); });
      窗体身.append(按钮);
    });

    const 项表 = 建元素("div", "窗件 表格");
    项表.id = "表格_清单";
    摆控件(项表, 8, 62, 486, 250, "表格");
    项表.title = "能力清单（真调 GET /接口 的结果）";
    项表.addEventListener("mousedown", (界面事件) => { 界面事件.stopPropagation(); 选件(项表, "能力清单表", "表格"); });
    窗体身.append(项表);
  }

  /** 往窗体那张表里填能力清单 —— 数据来自真应答，本页不编行。 */
  function 填表(项表) {
    if (!项表) return;
    const 头部 = 建元素("div", "表格行 表头");
    for (const 名称 of ["编号", "名称", "参数个数", "返回类型"]) 头部.append(建元素("span", null, 名称));
    清空容器(项表);
    项表.append(头部);
    for (const 能力 of 能表) {
      const 源码行 = 建元素("div", "表格行");
      for (const 待处理值 of [能力.编号, 能力.名称, 能力.参数个数, 能力.返回类型]) 源码行.append(建元素("span", null, String(待处理值)));
      项表.append(源码行);
    }
  }

  // ── 组件箱：基本组件（0–999）/ 扩展组件（1000–9999）───────────────────
  function 摆组件箱() {
    清空容器(组件箱);
    const 组件组 = [
      ["基本组件 · 底座自有（0–999）", 能表.filter((能力) => Number(能力.编号) <= 999), "能力"],
      ["扩展组件 · 扩展根热载入（1000–9999）", 能表.filter((能力) => Number(能力.编号) >= 1000), "模块"],
    ];
    for (const [名称, 项表, 图名] of 组件组) {
      组件箱.append(建元素("div", "箱组", 名称 + "（" + 项表.length + "）"));
      if (!项表.length) {
        组件箱.append(建元素("div", "箱空", "本类此刻 0 条 —— 应答里没有落在这段的编号"));
        continue;
      }
      const 格容器 = 建元素("div", "箱格");
      for (const 能力 of 项表) {
        const 按钮 = 建元素("button", "箱件");
        按钮.type = "button";
        按钮.title = String(能力.编号) + " " + String(能力.名称) + "（点一下：属性面板看它，并真调它的契约）";
        按钮.append(画图标(图名));
        按钮.addEventListener("click", () => 点箱件(按钮, 能力));
        格容器.append(按钮);
      }
      组件箱.append(格容器);
    }
  }

  async function 点箱件(按钮, 能力) {
    if (选中) 选中.classList.remove("选");
    选中 = null;
    按钮.classList.add("选");
    摆属性(读能属性(能力));
    取元素("契约编号").value = String(能力.编号);
    钩子.切页签("搜寻2");
    await 钩子.取契约(String(能力.编号));
  }

  /** 拉一次清单：填画布那张表 + 摆组件箱。 */
  async function 重绘() {
    装画布();
    try {
      // 扩展分组实时取（判据 ⑯：底座不许点名扩展）；取不到就当「没有扩展这一层」，不拦着能力表。
      await 拉扩展表();
      const 造应答 = await 取根();
      if (造应答.状态 !== 200 || !造应答.体 || !Array.isArray(造应答.体.能力)) {
        能表 = [];
        摆组件箱();
        填表(取元素("表格_清单"));
        return;
      }
      能表 = 造应答.体.能力;
      摆组件箱();
      填表(取元素("表格_清单"));
      if (!选中) 摆属性(读件属性(取元素("表格_清单"), "能力清单表", "表格"));
    } catch {
      能表 = [];
      摆组件箱();
      填表(取元素("表格_清单"));
    }
  }

  return { 重绘, 摆属性, 选件, 读件属性 };
}
