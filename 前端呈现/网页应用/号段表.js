//
// 两个来源：
//   · 号段骨架：`契约声明/号段图.json` 的 `能力号段`（起 / 止 / 归属）—— 静态抄件。
//     抄的是**底座自身的**布局声明（不是某个扩展的），且它没有对应端点；
//     漂移由 判据 ⑬（常量表）在编译期挡，不靠本页。
//   · 扩展分组：`GET /接口/扩展`（§七 端点）的 `种类[].扩展[]` —— **实时取，不抄**。
//
// 本件曾经把唯一一条扩展（名字 + `1100–1199`）抄成常量，理由写在旧注释里：
// 「冻结的四个端点里没有『扩展清单』」。**那个理由已过期** —— §七 的 `GET /接口/扩展`
// 早就回了 `种类[].扩展[].名称` 与 `能力号段`（实测：支持库 → 1 条）。
// 抄一份的代价是「加一个扩展就要改底座」（README §五 硬边界 2），
// 而且底座里出现扩展的名字本身就破硬边界 1 ⇒ 已改成实时取（判据 ⑯ 守着这条）。
//
// 纪律：本件只给「哪一段叫什么、哪一段归谁」，**不给任何能力名**——
// 能力名一律来自 `GET /接口` 的实时应答，所以后端给能力改名，本页一行都不用动。
// 这与 `菜单表.js` 抄 e.exe 菜单资源 127 是同一个做派：抄的是**资源的形状**，不是业务。

