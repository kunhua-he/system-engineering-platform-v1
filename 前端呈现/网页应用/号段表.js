/**
 * 已装载的扩展：名字 + 它占的号段 + 种类。**由 `拉扩展表()` 在启动时从端点填。**
 *
 * 空数组 = 还没拉（或端点没回）—— 此时 `找扩展` 一律回 `null`，
 * 界面表现为「能力都直挂在号段下、没有扩展这一层」，**不是崩**。
 * 这也正是扩展缺了时底座该有的样子（README §五 硬边界 3：扩展缺了底座照跑）。
 */
export const 扩展表 = [];

/**
 * 拉一次扩展清单，填 `扩展表`。返回 `null` = 填上了；否则返回一句为什么没填上。
 *
 * 形状逐字照 `对外接口面/调用接口面/src/工具响应_扩展.rs` 的 `组列扩展`（**实测键集**）：
 *   `{ 扩展根声明, 种类: [ { 种类, 目录, 扩展: [ { 扩展目录, 名称, 标识串, 能力号段, 声明落点 } ] } ] }`
 * **没有 `扩展根` 这个键** —— 已把它从 `扩展根声明.json` 删掉（它在载入路径上
 * 没有可数读方，是 `种类[].目录` 首段的冗余副本），该面也不再返回它。
 * 本件只取 `名称` / `能力号段` / `种类` 三样 —— 多取一个字段就是多一处耦合。
 * 一个扩展带几段号段就摊成几条（`找扩展` 按区间查，摊平了才对得上）。
 */
export async function 拉扩展表() {
  const 应答 = await 取扩展();
  if (应答.状态 !== 200 || !应答.体 || !Array.isArray(应答.体.种类)) {
    return "GET /接口/扩展 没回出扩展清单（HTTP " + 应答.状态 + "）";
  }
  扩展表.length = 0;
  for (const 类 of 应答.体.种类) {
    for (const 扩 of 类.扩展 || []) {
      for (const 段 of 扩.能力号段 || []) {
        扩展表.push({
          名: String(扩.名称),
          种类: String(类.种类),
          起: Number(段.起),
          止: Number(段.止),
        });
      }
    }
  }
  return null;
}

/** 一个编号落在哪一段。落不进任何一段就回 `null`（洞是合法的：号只增不复用）。 */
export function 找段(编号) {
  return 号段.find((号段) => 编号 >= 号段.起 && 编号 <= 号段.止) || null;
}

/** 一个编号落在哪个扩展里。落不进任何扩展就回 `null`（底座自有那一段、或清单还没拉到时）。 */
export function 找扩展(编号) {
  return 扩展表.find((扩展) => 编号 >= 扩展.起 && 编号 <= 扩展.止) || null;
}
