// 编译 —— 把编辑区的文本**逐级**送进链路，每一步都摆出它自身的结果。
//
// 逐级（不是一步到底）是判据要求的：一步到底就看不见死在哪一层
// （`项目文档/决策记录/2026-09-26_前端是网页版编译器.md` §一）。
//
// 本文件里**没有一条分支在问「这个结果对不对」**：成功还是失败由后端说了算，
// 本页只把 `false` 认成失败、`true` 认成成功（按值的类型，不按键名），
// 剩下的原文一律原样摆出来。
//
// **链与编号都是实时取的，本文件不写一个能力编号、也不写一个能力名**（`拉链()`）：
// 判据是**契约形状**而不是点名 —— 一个能力只要它的**参数表第一行是文本（类型标签 4）**，
// 它就吃本编辑器这份 `程序文本`，于是它就在链上；顺序＝`GET /接口` 能力清单的返回顺序。
// 所以后端加一个编译能力、给某一步追加参数、或重排编号，本页一行都不用改
// （README §五 硬边界 2：改一个扩展不用动底座）。判据 ⑯ 只抓「点名」，
// 抓不到只写编号的耦合 —— 这一处正是它抓不到的那一半。
//
// 现状（**实测，curl 打真网关逐条量过**，2026-09-27）—— 这里只记「怎么读」，不记死读数：
// 链上每一步的成败与码由 `跑编译()` 的逐级读数给出，页面上的「诊断 · 逐级读数」那一栏
// 就是它。此刻真读数：首两段（词法 · 语法）成功；语义那一步回 `码 1 提供者未载入`；
// 诊断那一步成功（回一个零字节集 = 它覆盖到的阶段全过，**不是**「编译成功」）。
// 这段会随后端变，页头与它不一致时**以逐级读数为准**。

import { 取根, 取能力, 拼文本调用体, 调用能力 } from "./取接口.js";
import { 建, 清空, 摆应答, 摆行内, 摘要, 写状态 } from "./呈现.js";

/**
 * 编译链：**从端点实时取**（`拉链()` 填），本页不写一个编号、不写一个名字。
 * 每项 `{ 编号, 名称, 参数个数 }` —— 名称来自 `GET /接口`，参数个数来自同一次应答。
 */
export const 链表 = [];

/** 链末一步。**不预设它是哪一条** —— 按后端给的顺序取最后一个。 */
export function 链末() {
  return 链表.length ? 链表[链表.length - 1] : null;
}

/**
 * 拉一次链：`GET /接口` 拿候选（`参数个数 ≥ 1` 的），再逐条 `GET /接口/能力/<编号>`
 * 读它的**参数表**，只留「第一行是文本」的那些。返回 `null` = 拉到了；否则返回一句为什么。
 *
 * 为什么必须读契约而不是只看 `GET /接口`：清单里只有 `参数个数`，没有参数类型 ——
 * 类型在单条契约里。多花 N 次请求，换来「本页不认识任何一条编译能力」。
 */
export async function 拉链() {
  let 应答 = null;
  try {
    应答 = await 取根();
  } catch (错) {
    链表.length = 0;
    return "发不出去：" + 错.message;
  }
  if (应答.状态 !== 200 || !应答.体 || !Array.isArray(应答.体.能力)) {
    链表.length = 0;
    return "GET /接口 没回出能力清单（HTTP " + 应答.状态 + "）";
  }
  const 收 = [];
  for (const 能 of 应答.体.能力) {
    const 编号 = Number(能.编号);
    const 参个数 = Number(能.参数个数);
    if (!(参个数 >= 1)) continue;
    let 契 = null;
    try {
      契 = await 取能力(编号);
    } catch {
      continue;
    }
    const 参数表 = 契.状态 === 200 && 契.体 && 契.体.契约 ? 契.体.契约.参数表 || [] : [];
    if (!参数表.length) continue;
    if (Number(参数表[0].类型标签) !== 4) continue; // 4 = 文本（`契约声明/类型声明/0004.json`）
    收.push({ 编号, 名称: String(能.名称), 参数个数: 参个数 });
  }
  链表.length = 0;
  链表.push(...收);
  if (!链表.length) return "能力清单里没有「首参是程序文本」的能力（链为空）";
  return null;
}

/** 链没取到就取一次；返回 `null` = 可以跑，否则返回一句为什么。 */
async function 确保链() {
  if (链表.length) return null;
  return 拉链();
}

/** 还没编译时的空状态（人话 + 下一步），**不留白屏、不转圈**。 */
export function 摆空状态(取元素) {
  const 列表 = 取元素("步列表");
  清空(列表);
  const 盒 = 建("div", "空状态");
  盒.append(建("b", null, "还没编译"));
  盒.append(
    建("p", null, "点上方「编译」，编辑器里的文本会按 `GET /接口` 给的顺序逐级送进链路，每一步的结果各自成一块。")
  );
  盒.append(建("p", null, "链上有哪几步、顺序如何、每一步叫什么，都实时取自端点 —— 本页不写死一条编译链。"));
  列表.append(盒);
}

/** 一步的卡片。返回 `{ 卡, 体, 徽标 }`。 */
function 建步卡(列表, 位, 名, 编号) {
  const 卡 = 建("div", "步卡");
  const 头 = 建("div", "步卡头");
  头.append(建("span", "步名", "第 " + (位 + 1) + " 步 · " + 名));
  头.append(建("span", "步号", "编号 " + 编号));
  const 徽标 = 建("span", "徽标 灰", "请求中…");
  头.append(徽标);
  const 体 = 建("div", "步体");
  卡.append(头, 体);
  列表.append(卡);
  return { 卡, 体, 徽标 };
}

/** 把一条应答摆进步卡：先一行内联读数，再可展开的完整应答。 */
function 摆步果(体, 应答) {
  const 行 = 建("div", "行内");
  摆行内(行, 应答.体);
  体.append(行);
  const 详 = 建("details", "原文盒");
  详.append(建("summary", null, "这一步的应答（结构化 + 原文）"));
  const 盒 = 建("div", "果");
  摆应答(盒, 应答);
  详.append(盒);
  体.append(详);
}

/**
 * 跑一遍编译：把链上每一步逐级调一遍，每步各自成块；最后再单独调一次链末那一步。
 * 各步都吃同一份文本，所以**不提前中断**：哪一步失败就在那一步标红，其余照跑照摆。
 */
export async function 跑编译(取元素, 编辑) {
  const 文本 = 编辑.value;
  const 列表 = 取元素("步列表");
  const 状态 = 取元素("诊断状态");
  const 工具 = 取元素("工具状态");
  const 输出 = 取元素("输出体");
  const 输出状态 = 取元素("输出状态");
  清空(列表);
  清空(输出);
  写状态(状态, "编译中…");
  写状态(工具, "编译中…");
  写状态(输出状态, "编译中…");

  const 链错 = await 确保链();
  if (链错) {
    写状态(状态, 链错, false);
    写状态(工具, 链错, false);
    写状态(输出状态, 链错, false);
    列表.append(建("p", "提示 坏", "编译链取不到：" + 链错 + "。链是从 `GET /接口` 实时取的，取不到就没有可跑的步骤 —— 这是真读数。"));
    return;
  }

  let 首个坏 = null;
  let 网络断 = false;

  for (let 位 = 0; 位 < 链表.length; 位 += 1) {
    const 步 = 链表[位];
    const 名 = 步.名称;
    const 编号 = 步.编号;
    const 卡 = 建步卡(列表, 位, 名, 编号);
    let 应答 = null;
    try {
      应答 = await 调用能力(拼文本调用体(编号, 文本, 步.参数个数));
    } catch (错) {
      网络断 = true;
      卡.卡.classList.add("坏");
      卡.徽标.className = "徽标 坏";
      卡.徽标.textContent = "发不出去";
      卡.体.append(建("p", "提示 坏", "请求没能送出去：" + 错.message));
      break;
    }
    // 「输出」那一格：每一步的原样应答原文，一行一步（不加工、不截断）。
    输出.append(建("div", "行内", "第 " + (位 + 1) + " 步 · " + 名 + "（编号 " + 编号
      + "）· HTTP " + 应答.状态));
    输出.append(建("pre", "原文", 应答.文));
    const 词 = 应答.状态 === 200 ? 摘要(应答.体) : { 词: "HTTP " + 应答.状态, 类: "坏" };
    卡.徽标.className = "徽标 " + 词.类;
    卡.徽标.textContent = 词.词;
    if (词.类 === "好") 卡.卡.classList.add("好");
    if (词.类 === "坏") {
      卡.卡.classList.add("坏");
      if (!首个坏) 首个坏 = "第 " + (位 + 1) + " 步 · " + 名 + "（编号 " + 编号 + "）";
    }
    摆步果(卡.体, 应答);
  }

  if (网络断) {
    写状态(状态, "网关连不上", false);
    写状态(工具, "网关连不上", false);
    写状态(输出状态, "网关连不上", false);
    取元素("连接状态").textContent = "网关连不上";
    取元素("连接状态").className = "状态 坏";
    取元素("条_连接").textContent = "连不上";
    取元素("条_连接").className = "状态 坏";
    return;
  }

  const 步数 = "链上 " + 链表.length + " 步";
  if (首个坏) {
    写状态(状态, "死在第 " + 首个坏.replace("第 ", ""), false);
    写状态(工具, "编译没走通：死在第 " + 首个坏.replace("第 ", ""), false);
    写状态(输出状态, "编译没走通：死在第 " + 首个坏.replace("第 ", ""), false);
  } else {
    写状态(状态, 步数 + "都回了", true);
    写状态(工具, "编译" + 步数 + "都回了", true);
    写状态(输出状态, 步数 + "都回了", true);
  }

  await 跑诊断(取元素, 编辑);
}

/**
 * 单独调一次**链末那一步**（此刻是「诊断」），把它的结果与结构化错误码摆出来。
 *
 * **本页不预设哪一步是诊断**：它取的是后端给的顺序里最后那一条。所以后端加一条编译能力
 * 排在诊断后面，本页的读数就跟着走，不写死编号（判据 ⑯ 抓不到的那一半）。
 */
export async function 跑诊断(取元素, 编辑) {
  const 文本 = 编辑.value;
  const 果 = 取元素("诊断果");
  const 状态 = 取元素("诊断果状态");
  const 链错 = await 确保链();
  if (链错) {
    清空(果);
    果.append(建("p", "提示 坏", "编译链取不到：" + 链错));
    写状态(状态, 链错, false);
    return;
  }
  const 末 = 链末();
  写状态(状态, "请求中…");
  let 应答 = null;
  try {
    应答 = await 调用能力(拼文本调用体(末.编号, 文本, 末.参数个数));
  } catch (错) {
    清空(果);
    果.append(建("p", "提示 坏", "请求没能送出去：" + 错.message));
    写状态(状态, "发不出去", false);
    return;
  }
  const 词 = 应答.状态 === 200 ? 摘要(应答.体) : { 词: "HTTP " + 应答.状态, 类: "坏" };
  写状态(状态, "链末一步 · " + 末.名称 + "（编号 " + 末.编号 + "）· HTTP " + 应答.状态
    + " · " + 词.词, 词.类 === "坏" ? false : true);
  清空(果);
  const 行 = 建("div", "行内");
  摆行内(行, 应答.体);
  果.append(行);
  const 盒 = 建("div", "果");
  摆应答(盒, 应答);
  果.append(盒);
}
