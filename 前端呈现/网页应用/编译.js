// 编译 —— 把编辑区的文本**逐级**送进链路，每一步都摆出它自己的结果。
//
// 逐级（不是一步到底）是判据要求的：一步到底就看不见死在哪一层
// （`项目文档/决策记录/2026-09-26_前端是网页版编译器.md` §一）。
//
// 本文件里**没有一条分支在问「这个结果对不对」**：成功还是失败由后端说了算，
// 本页只把 `false` 认成失败、`true` 认成成功（按值的类型，不按键名），
// 剩下的原文一律原样摆出来。
//
// 现状（**实测，curl 打真网关逐条量过** —— 原来这几行写反了，2026-09-27 改）：
//   `1101` 词法分析 · `1102` 语法分析   → HTTP 200 且 **`成功=true`**，真回一段记录流字节集
//   `1103` 语义分析 · `1106` 编译 · `1107` 诊断 → HTTP 200 且 **`成功=false` `码 1 提供者未载入`**
//   `1104` 容器互操作两个 → HTTP 200 且 `成功=false` **`码 1135 参数槽不符`**（不是「未载入」：
//     它们参数表不同，是另一条路，拿本编辑器这份文本去喂本来就不对位）
// 所以这条链是**前两步通、第三步起断**。点「编译」看到的就是这条链此刻的真读数。

import { 拼文本调用体, 调用能力 } from "./取接口.js";
import { 建, 清空, 摆应答, 摆行内, 摘要, 写状态 } from "./呈现.js";

/** 编译链路的四步，**顺序即依赖序**。四步都吃同一份 `程序文本`（契约里四者的参数表都是它）。 */
export const 步表 = [
  ["词法分析", 1101],
  ["语法分析", 1102],
  ["语义分析", 1103],
  ["编译", 1106],
];

/** 诊断那一步的编号。 */
export const 诊断编号 = 1107;

/** 还没编译时的空状态（人话 + 下一步），**不留白屏、不转圈**。 */
export function 摆空状态(取) {
  const 列表 = 取("步列表");
  清空(列表);
  const 盒 = 建("div", "空状态");
  盒.append(建("b", null, "还没编译"));
  盒.append(
    建("p", null, "点上方「编译」，编辑器里的文本会按 词法分析 → 语法分析 → 语义分析 → 编译 逐级送进链路，每一步的结果各自成一块。")
  );
  盒.append(建("p", null, "现在这条链是前两步通、第三步起断（`1103` 语义分析回结构化失败）—— 见页头那句现状。"));
  列表.append(盒);
}

/** 一步的卡片。返回 `{ 卡, 体, 徽标 }`。 */
function 建步卡(列表, 位, 名, 编号) {
  const 卡 = 建("div", "步卡");
  const 头 = 建("div", "步卡头");
  头.append(建("span", "步名", "第 " + (位 + 1) + " 步 · " + 名));
  头.append(建("span", "步号", "编号 " + 编号));
  const 徽标 = 建("span", "徽标 灰", "请求中…");
  头.append(徽标);
  const 体 = 建("div", "步体");
  卡.append(头, 体);
  列表.append(卡);
  return { 卡, 体, 徽标 };
}

/** 把一条应答摆进步卡：先一行内联读数，再可展开的完整应答。 */
function 摆步果(体, 应答) {
  const 行 = 建("div", "行内");
  摆行内(行, 应答.体);
  体.append(行);
  const 详 = 建("details", "原文盒");
  详.append(建("summary", null, "这一步的应答（结构化 + 原文）"));
  const 盒 = 建("div", "果");
  摆应答(盒, 应答);
  详.append(盒);
  体.append(详);
}

/**
 * 跑一遍编译：逐级调四步，每步各自成块；再调一次 `1107` 诊断。
 * 四步都吃同一份文本，所以**不提前中断**：哪一步失败就在那一步标红，其余照跑照摆。
 */
export async function 跑编译(取, 编辑) {
  const 文本 = 编辑.value;
  const 列表 = 取("步列表");
  const 状态 = 取("诊断状态");
  const 工具 = 取("工具状态");
  const 输出 = 取("输出体");
  const 输出状态 = 取("输出状态");
  清空(列表);
  清空(输出);
  写状态(状态, "编译中…");
  写状态(工具, "编译中…");
  写状态(输出状态, "编译中…");

  let 首个坏 = null;
  let 网络断 = false;

  for (let 位 = 0; 位 < 步表.length; 位 += 1) {
    const 名 = 步表[位][0];
    const 编号 = 步表[位][1];
    const 卡 = 建步卡(列表, 位, 名, 编号);
    let 应答 = null;
    try {
      应答 = await 调用能力(拼文本调用体(编号, 文本));
    } catch (错) {
      网络断 = true;
      卡.卡.classList.add("坏");
      卡.徽标.className = "徽标 坏";
      卡.徽标.textContent = "发不出去";
      卡.体.append(建("p", "提示 坏", "请求没能送出去：" + 错.message));
      break;
    }
    // 「输出」那一格：每一步的原样应答原文，一行一步（不加工、不截断）。
    输出.append(建("div", "行内", "第 " + (位 + 1) + " 步 · " + 名 + "（编号 " + 编号
      + "）· HTTP " + 应答.状态));
    输出.append(建("pre", "原文", 应答.文));
    const 词 = 应答.状态 === 200 ? 摘要(应答.体) : { 词: "HTTP " + 应答.状态, 类: "坏" };
    卡.徽标.className = "徽标 " + 词.类;
    卡.徽标.textContent = 词.词;
    if (词.类 === "好") 卡.卡.classList.add("好");
    if (词.类 === "坏") {
      卡.卡.classList.add("坏");
      if (!首个坏) 首个坏 = "第 " + (位 + 1) + " 步 · " + 名 + "（编号 " + 编号 + "）";
    }
    摆步果(卡.体, 应答);
  }

  if (网络断) {
    写状态(状态, "网关连不上", false);
    写状态(工具, "网关连不上", false);
    写状态(输出状态, "网关连不上", false);
    取("连接状态").textContent = "网关连不上";
    取("连接状态").className = "状态 坏";
    取("条_连接").textContent = "连不上";
    取("条_连接").className = "状态 坏";
    return;
  }

  if (首个坏) {
    写状态(状态, "死在第 " + 首个坏.replace("第 ", ""), false);
    写状态(工具, "编译没走通：死在第 " + 首个坏.replace("第 ", ""), false);
    写状态(输出状态, "编译没走通：死在第 " + 首个坏.replace("第 ", ""), false);
  } else {
    写状态(状态, "四步都回了", true);
    写状态(工具, "编译四步都回了", true);
    写状态(输出状态, "四步都回了", true);
  }

  await 跑诊断(取, 编辑);
}

/** 调一次 `1107` 诊断，把它的结果与结构化错误码摆出来。 */
export async function 跑诊断(取, 编辑) {
  const 文本 = 编辑.value;
  const 果 = 取("诊断果");
  const 状态 = 取("诊断果状态");
  写状态(状态, "请求中…");
  let 应答 = null;
  try {
    应答 = await 调用能力(拼文本调用体(诊断编号, 文本));
  } catch (错) {
    清空(果);
    果.append(建("p", "提示 坏", "请求没能送出去：" + 错.message));
    写状态(状态, "发不出去", false);
    return;
  }
  const 词 = 应答.状态 === 200 ? 摘要(应答.体) : { 词: "HTTP " + 应答.状态, 类: "坏" };
  写状态(状态, "HTTP " + 应答.状态 + " · " + 词.词, 词.类 === "坏" ? false : true);
  清空(果);
  const 行 = 建("div", "行内");
  摆行内(行, 应答.体);
  果.append(行);
  const 盒 = 建("div", "果");
  摆应答(盒, 应答);
  果.append(盒);
}
