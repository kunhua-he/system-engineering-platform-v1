// 程序文本 —— 接 §七 旁路端点 `POST /接口/程序文本`（体 `{"动作":"读"|"写","路径":"…","正文":"…"}`）。
//
// 落点已裁（`项目文档/决策记录/2026-09-28_华哥的尺子与七条裁决.md` §二 206 行）：
// 「项目/程序文本那一层」= **调用方自带路径** —— 本页（调用方）用「载入示例」那个下拉选的路径。
// **本页不猜路径**：没选带路径的语料就原样把后端的 `9008 程序文本路径为空` 摆出来，
// 不假装成功、不吞掉错误码。
//
// 本文件只做两件事：把「读 / 写」两个动作发出去 · 把应答原样交给 `呈现.js` 摆出来。
// 没有一条分支在问「这个动作对不对」—— 那是后端的闭合枚举判定（非法 ⇒ HTTP 400）。

import { 发程序文本 } from "./取接口.js";
import { 选中路径 } from "./编辑器.js";
import { 摆应答, 摆消息, 摘要, 写状态, 清空 } from "./呈现.js";
import { 记流水 } from "./剪辑历史.js";

export function 装程序文本(取元素) {
  const 状态 = 取元素("程序文本状态");
  const 果 = 取元素("程序文本果");
  const 选 = 取元素("示例选");
  const 编辑 = 取元素("编辑区");

  async function 发动作(动作) {
    // 路径由调用方给：取「载入示例」下拉选中的那条；没选带路径的语料就发空串（后端回 9008）。
    const 路径 = 选中路径(选);
    const 正文 = 动作 === "写" ? 编辑.value : undefined;
    清空(果);
    写状态(状态, 动作 + " " + (路径 || "（未选路径）") + " 中…");
    try {
      const 应答 = await 发程序文本(动作, 路径, 正文);
      摆应答(果, 应答);
      const 词 = 摘要(应答.体);
      写状态(状态, "HTTP " + 应答.状态 + " · " + 词.词,
        词.类 === "好" ? true : 词.类 === "坏" ? false : undefined);
      记流水("程序文本", 动作 + " · " + (路径 || "（未选路径）") + " · HTTP " + 应答.状态 + " · " + 词.词);
    } catch (错) {
      摆消息(果, "发不出去：" + 错.message);
      写状态(状态, "发不出去", false);
    }
  }

  取元素("程序文本读").addEventListener("click", () => 发动作("读"));
  取元素("程序文本写").addEventListener("click", () => 发动作("写"));
}
