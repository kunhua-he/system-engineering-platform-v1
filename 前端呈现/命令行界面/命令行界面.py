#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""命令行界面 —— 对外接口面的**纯转发客户端**（人工界面，可整体替换）。

上级：系统工程平台 V1 ／ 落点：`前端呈现/命令行界面/`
相关：`项目文档/设计文档/接口面形状.md`（四个端点，冻结）· `两个角色与接口面.md`（维护角色判据）·
      `代码形态分工.md` 第一节表 6（本落点形态 = shell 胶水 + 调接口面的 HTTP，**CLI 里 0 处判断**）

# 它是什么

**只做两件事**：把命令行参数拼成接口面认的 HTTP 请求；把接口面的返回格式化成人能读的字。

# 它明确不是什么（硬约束，逐条守住）

| 不许 | 本文件怎么守 |
|---|---|
| 不许解析契约 | 本文件里搜不到任何「按契约行序校验」「按编号查能力」的代码；`契约` 子命令把返回**原样**漂亮打印 |
| 不许生成 / 不许校验 | 不判断编号存不存在、不判断值的个数对不对、不判断值的类型对不对 —— 这些**全在后端**（接口面 + 调度层） |
| 不许引入第三方依赖 | 只用标准库 `urllib.request` / `json` / `base64` / `os` / `sys`（**不用 `requests`**） |
| 不许写死端口 | 端口来源三档：命令行 `--端口 N` > 环境变量 `V1_GATEWAY_PORT`（兼容 `接口端口`）> 默认 43110 |
| 地址只许回环 | 主机恒为 `127.0.0.1`，**不提供改主机的口**（接口面不做鉴权，故只对本机开放） |

# 四个端点（`接口面形状.md` §二，冻结；一个不多一个不少）

| 子命令 | 方法 路径 |
|---|---|
| `清单` | `GET  /接口` |
| `契约 <编号>` | `GET  /接口/能力/<编号>` |
| `调用 <编号> <值…>` | `POST /接口/调用` |
| `声明 <文件>` | `POST /接口/声明` |

# 值的写法（`调用` 用；`值` 按契约**行序**对位，不省略位次）

| 写法 | 发出的槽 |
|---|---|
| `-` 或 `空` | `{"类型标签":0,"值":0}`（空槽） |
| 裸值（不含 `:`） | `{"类型标签":4,"值":"<裸值>"}`（文本；**接口面不猜类型，故这里要一个显式默认**） |
| `标签:值` | `{"类型标签":<标签>,"值":<按标签成形>}` |
| `@路径` | `{"类型标签":5,"值":"<文件字节的 base64>"}`（字节集；base64 是传输编码，不是业务） |

`标签` 是十进制数。标签 → JSON 形状**实测**（以后端 400 的说明文为准）：`0`=0 · `1` 整数=数 ·
`2` 双精度=数 · `3` 逻辑=`0`/`1`（**不是 JSON 布尔**；本界面把 `真`/`假` 换成 `1`/`0`）·
`4` 文本=字符串 · `5` 字节集=base64 字符串 · `6` 句柄=非负整数 · 其余标签原样透传（面回 400「形状未定义」）。

# 退出码

`0` 成功 · `1` 业务失败（`成功: false` 且有 `错误`）· `2` 用法错（本地参数写错）· `3` 连不上 / 应答不是 JSON。

用法：`命令行界面.py --帮助`
"""

import base64
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request

# ════════════════════════════════════════════════════════════════════════════
# 连接参数 —— 端口三档来源，主机恒回环（都不写死在唯一一处）
# ════════════════════════════════════════════════════════════════════════════

默认端口 = 43110
端口环境变量 = ("V1_GATEWAY_PORT", "接口端口")
回环地址 = "127.0.0.1"
默认超时秒 = 10.0

# 本次真正用的端口（main 里定下来）。**只为把报错话说准**：连不上时要说清是哪个端口连不上，
# 报默认值会指错方向（端口可能是 --端口 或环境变量给的）。
当前端口 = 默认端口

# 四个端点（`接口面形状.md` §二）。路径里的非 ASCII 由 `取URL` 百分号编码。
路径_根 = "/接口"
路径_能力 = "/接口/能力/"
路径_调用 = "/接口/调用"
路径_声明 = "/接口/声明"

用法 = """命令行界面 —— 对外接口面的纯转发客户端（零业务逻辑）

用法
  命令行界面.py 清单 [选项]                 GET  /接口            自描述根：端点表 + 能力全量清单
  命令行界面.py 契约 <编号> [选项]           GET  /接口/能力/<编号> 单条能力的契约（行序即契约）
  命令行界面.py 调用 <编号> <值…> [选项]     POST /接口/调用        值按契约行序
  命令行界面.py 声明 <文件> [选项]           POST /接口/声明        体 = 文件原文，**原样转发、不校验**

选项
  --端口 N        接口面监听的端口（默认 43110，可用环境变量 V1_GATEWAY_PORT 覆盖）
  --显示请求      把真实发出的请求行与请求体打到 stderr（stdout 保持干净）
  --帮助          本说明

值的写法（`调用` 用）
  -  或  空        空槽        {"类型标签":0,"值":0}
  裸值            文本        {"类型标签":4,"值":"<裸值>"}
  标签:值         显式槽      {"类型标签":标签,"值":…}（标签是十进制数）
  @路径           字节集      {"类型标签":5,"值":"<文件字节的 base64>"}

  标签与 JSON 形状（实测，后端 400 说明文为准）：0 空槽=0 · 1 整数=数 · 2 双精度=数 ·
  3 逻辑=0/1（**不是 JSON 布尔**，写 真/假 由本界面换成 0/1）· 4 文本=字符串 ·
  5 字节集=base64 字符串 · 6 句柄=非负整数 · 其余标签原样透传（面会回 400「形状未定义」）

退出码
  0 成功 · 1 业务失败（成功:false）· 2 用法错 · 3 连不上 / 应答不是 JSON
"""


def 取端口(参数: list) -> int:
    """端口：命令行 > 环境变量 > 默认。返回 `(端口, 剩余参数)`。"""
    剩余 = []
    端口 = None
    位 = 0
    while 位 < len(参数):
        这项 = 参数[位]
        if 这项 == "--端口":
            if 位 + 1 >= len(参数):
                raise 用法错("--端口 后面要给一个数")
            端口 = 取端口数(参数[位 + 1])
            位 += 2
            continue
        if 这项.startswith("--端口="):
            端口 = 取端口数(这项.split("=", 1)[1])
            位 += 1
            continue
        剩余.append(这项)
        位 += 1
    if 端口 is not None:
        return 端口, 剩余
    for 名 in 端口环境变量:
        原值 = os.environ.get(名)
        if 原值:
            return 取端口数(原值), 剩余
    return 默认端口, 剩余


def 取端口数(原值: str) -> int:
    数 = int(原值.strip())
    if not (0 < 数 < 65536):
        raise 用法错("端口必须在 1–65535：{}".format(原值))
    return 数


class 用法错(Exception):
    """本地参数写错 —— 与后端的业务失败无关。"""


# ════════════════════════════════════════════════════════════════════════════
# HTTP —— 手写两件：发一条请求、收一条应答（只用标准库）
# ════════════════════════════════════════════════════════════════════════════

def 取URL(端口: int, 路径: str) -> str:
    """拼 URL。路径**百分号编码**：接口面路径是非 ASCII，而 HTTP 请求行只许 ASCII
    （`路由.rs` 文件头：浏览器与 fetch 也是这么发的，网关负责解码）。"""
    return "http://{}:{}{}".format(回环地址, 端口, urllib.parse.quote(路径, safe="/"))


def 发(端口: int, 方法: str, 路径: str, 体文本: str, 显示请求: bool) -> tuple:
    """发一条请求 → `(状态码, 应答体文本)`。**不解析、不校验**，只搬运。"""
    数据 = 体文本.encode("utf-8") if 体文本 is not None else None
    请求 = urllib.request.Request(取URL(端口, 路径), data=数据, method=方法)
    请求.add_header("Accept", "application/json")
    if 数据 is not None:
        请求.add_header("Content-Type", "application/json; charset=utf-8")
    if 显示请求:
        行 = "{} {} HTTP/1.1".format(方法, urllib.parse.quote(路径, safe="/"))
        print("> " + 行, file=sys.stderr)
        print("> Host: {}:{}".format(回环地址, 端口), file=sys.stderr)
        if 数据 is not None:
            print("> Content-Length: {}".format(len(数据)), file=sys.stderr)
            print("> {}".format(体文本), file=sys.stderr)
    try:
        with urllib.request.urlopen(请求, timeout=默认超时秒) as 应答:
            return 应答.status, 应答.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as 错:
        # 4xx 是**协议层**失败（请求本身不合法），体里仍是一份 JSON 说明。
        return 错.code, 错.read().decode("utf-8", "replace")


def 连不上(端口: int, 原因) -> int:
    print("连不上 http://{}:{} —— 接口面没起？".format(回环地址, 端口))
    print("  原因：{}".format(原因))
    print("  端口来源：--端口 > 环境变量 {} > 默认 {}".format(
        " / ".join(端口环境变量), 默认端口))
    return 3


# ════════════════════════════════════════════════════════════════════════════
# 显示 —— 只格式化，不判断（判断全在后端；这里只把它的判断摆清楚）
# ════════════════════════════════════════════════════════════════════════════

def 是(值) -> str:
    return "是" if 值 is True else ("否" if 值 is False else str(值))


def 漂亮(值) -> str:
    return json.dumps(值, ensure_ascii=False, indent=2)


def 印应答(状态: int, 体文本: str) -> int:
    """打印一条应答。返回退出码。**只按后端给的判定分支**，不自己判成功失败。"""
    状态行 = "HTTP {}".format(状态)
    try:
        体 = json.loads(体文本)
    except ValueError:
        print(状态行 + " —— 应答不是合法 JSON，原样贴出：")
        print(体文本)
        return 3
    if isinstance(体, dict) and 体.get("成功") is False:
        return 印失败(状态行, 体)
    if 状态 >= 400:
        print(状态行 + " —— 请求本身不合法（协议层，不是业务失败）")
    else:
        print(状态行)
    print(漂亮(体))
    return 0


def 印失败(状态行: str, 体: dict) -> int:
    """失败显示 —— `接口面形状.md` §三：`成功:false` + 错误码 + 三项业务判断。"""
    print(状态行 + "  成功：否")
    if isinstance(体.get("错误"), dict):
        错误 = 体["错误"]
        print("  错误码：{}".format(错误.get("码")))
        print("  段位  ：{}".format(错误.get("段位")))
        print("  名称  ：{}".format(错误.get("名称") or "（未登记，后端没编名字）"))
        print("  可重试：{}".format(是(错误.get("可重试"))))
        print("  可自愈：{}".format(是(错误.get("可自愈"))))
        print("  需人工：{}".format(是(错误.get("需人工"))))
        if "已登记" in 错误:
            print("  已登记：{}（旁路项；否 = 这个码在已装载声明里查不到，是一条缺陷证据）"
                  .format(是(错误.get("已登记"))))
    elif isinstance(体.get("校验"), list):
        # `POST /接口/声明` 的失败形状（§四）：逐条「项 · 缺什么 · 为什么不能自愈」。
        print("  校验（{} 条）：".format(len(体["校验"])))
        for 序号, 条 in enumerate(体["校验"], 1):
            print("   {}. 项：{}".format(序号, 条.get("项")))
            print("      缺什么：{}".format(条.get("缺什么")))
            print("      为什么不能自愈：{}".format(条.get("为什么不能自愈")))
    elif "协议错误" in 体:
        print("  协议错误：{}".format(体["协议错误"]))
    else:
        print("  返回体：")
        print(漂亮(体))
    if "耗时微秒" in 体:
        print("  耗时微秒：{}".format(体["耗时微秒"]))
    return 1


def 印调用成功(状态: int, 体: dict) -> int:
    """成功显示 —— `接口面形状.md` §三：`成功: true` + `值`（每项自带 `类型标签`）+ `耗时微秒`。
    槽里若还有旁路项（实测有 `引用` · `长度`），一并摆出来：**不吞后端给的事实**。"""
    print("HTTP {}  成功：是".format(状态))
    for 序号, 槽 in enumerate(体.get("值") or []):
        if not isinstance(槽, dict):
            print("  值[{}]：{}".format(序号, 槽))
            continue
        原值 = 槽.get("值")
        标注 = ""
        if 槽.get("类型标签") == 5 and isinstance(原值, str):
            标注 = "（base64，{} 字符）".format(len(原值))
        旁路 = "".join(
            "  {}={}".format(键, json.dumps(值, ensure_ascii=False))
            for 键, 值 in 槽.items() if 键 not in ("类型标签", "值")
        )
        print("  值[{}]  类型标签={}{}{}".format(序号, 槽.get("类型标签"), 标注, 旁路))
        print("        {}".format(原值))
    for 键 in 体:
        if 键 not in ("成功", "值"):
            print("  {}：{}".format(键, json.dumps(体[键], ensure_ascii=False)))
    return 0


# ════════════════════════════════════════════════════════════════════════════
# 拼请求体 —— 唯一的「成形」动作：把命令行参数摆成冻结的请求形状
# ════════════════════════════════════════════════════════════════════════════

def 拼值(参数: str) -> dict:
    """一个值参数 → 一个槽。**不查契约**：标签与值都由调用方写出来。

    标签 → JSON 形状，只有**传输层**那一层映射（`接口面形状.md` §三：文本 ⇒ JSON 字符串；
    字节集 ⇒ base64 字符串；两者靠标签区分）。**实测补齐**（后端返回的 400 说明文，见报告）：
    `逻辑` 的值必须是 `0`/`1` **数字**（JSON 布尔被 400 拒）· `句柄` 必须是非负整数 ·
    未登记的标签面一律 400「形状未定义」⇒ 本文件对未登记标签**原样透传、不猜**。
    """
    if 参数 in ("-", "空"):
        return {"类型标签": 0, "值": 0}
    if 参数.startswith("@"):
        路径 = 参数[1:]
        with open(路径, "rb") as 文件:
            字节 = 文件.read()
        return {"类型标签": 5, "值": base64.b64encode(字节).decode("ascii")}
    if ":" not in 参数:
        return {"类型标签": 4, "值": 参数}
    标签文, _, 值文 = 参数.partition(":")
    标签 = int(标签文)
    if 标签 == 0:
        return {"类型标签": 0, "值": 0}
    if 标签 in (1, 6, 4294967295):  # 整数 · 句柄 · 错误（段位）—— 都是 JSON 数
        return {"类型标签": 标签, "值": int(值文)}
    if 标签 == 2:
        return {"类型标签": 2, "值": float(值文)}
    if 标签 == 3:
        低 = 值文.strip().lower()
        if 低 in ("真", "true", "1", "是"):
            return {"类型标签": 3, "值": 1}
        if 低 in ("假", "false", "0", "否"):
            return {"类型标签": 3, "值": 0}
        raise 用法错("逻辑值只认 真/假/true/false/1/0：{}".format(值文))
    # 4 文本 · 5 字节集（base64 原样透传）· 其余标签原样透传 —— 不解释未登记的标签。
    return {"类型标签": 标签, "值": 值文}


# ════════════════════════════════════════════════════════════════════════════
# 五条命令
# ════════════════════════════════════════════════════════════════════════════

def 命令清单(端口: int, 显示: bool) -> int:
    状态, 体 = 发(端口, "GET", 路径_根, None, 显示)
    return 印应答(状态, 体)


def 命令契约(端口: int, 参数: list, 显示: bool) -> int:
    if len(参数) != 1:
        raise 用法错("契约 要一个编号：契约 <编号>")
    状态, 体 = 发(端口, "GET", 路径_能力 + 参数[0], None, 显示)
    return 印应答(状态, 体)


def 命令调用(端口: int, 参数: list, 显示: bool) -> int:
    if len(参数) < 1:
        raise 用法错("调用 要一个编号：调用 <编号> <值…>")
    编号文, 值参数 = 参数[0], 参数[1:]
    编号 = int(编号文)  # 只做「是不是十进制数」的搬运，不查它存不存在（那是后端的判）
    体 = {"编号": 编号, "值": [拼值(一项) for 一项 in 值参数]}
    体文本 = json.dumps(体, ensure_ascii=False)
    状态, 应答 = 发(端口, "POST", 路径_调用, 体文本, 显示)
    try:
        解析后 = json.loads(应答)
    except ValueError:
        print("HTTP {} —— 应答不是合法 JSON，原样贴出：".format(状态))
        print(应答)
        return 3
    if 解析后.get("成功") is True:
        return 印调用成功(状态, 解析后)
    return 印失败("HTTP {}".format(状态), 解析后)


def 命令声明(端口: int, 参数: list, 显示: bool) -> int:
    if len(参数) != 1:
        raise 用法错("声明 要一个文件：声明 <文件>")
    # **原样转发**：不解析、不校验（面校验是后端的事，前端校验就是第二条腿）。
    with open(参数[0], "rb") as 文件:
        体文本 = 文件.read().decode("utf-8")
    状态, 体 = 发(端口, "POST", 路径_声明, 体文本, 显示)
    return 印应答(状态, 体)


命令表 = {
    "清单": lambda 端口, 参数, 显示: 命令清单(端口, 显示),
    "契约": 命令契约,
    "调用": 命令调用,
    "声明": 命令声明,
}


def main(参数: list) -> int:
    global 当前端口
    参数 = list(参数)
    显示 = "--显示请求" in 参数
    参数 = [一项 for 一项 in 参数 if 一项 != "--显示请求"]
    if not 参数 or 参数[0] in ("--帮助", "-h", "--help", "帮助"):
        print(用法, end="")
        return 0
    命令 = 参数[0]
    if 命令 not in 命令表:
        raise 用法错("不认识这条命令：{}（只认 清单 / 契约 / 调用 / 声明）".format(命令))
    端口, 剩余 = 取端口(参数[1:])
    当前端口 = 端口
    return 命令表[命令](端口, 剩余, 显示)


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except 用法错 as 错:
        print("用法错：{}".format(错), file=sys.stderr)
        print("（本地参数写错，不是后端的判断）", file=sys.stderr)
        sys.exit(2)
    except FileNotFoundError as 错:
        print("文件读不到：{}".format(错), file=sys.stderr)
        sys.exit(2)
    except urllib.error.URLError as 错:
        # 报的是**本次真正用的那个端口**（可能是 --端口 或环境变量给的），不报默认值。
        sys.exit(连不上(当前端口, 错.reason if hasattr(错, "reason") else 错))
    except ValueError as 错:
        print("用法错：{}（编号与端口必须是十进制数）".format(错), file=sys.stderr)
        sys.exit(2)
