#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""命令行界面 —— 对外接口面的**纯转发客户端**（人工界面，可整体替换）。

上级：系统工程平台 V1 ／ 落点：`前端呈现/命令行界面/`
相关：`项目文档/设计文档/接口面形状.md`（四个端点，冻结）· `两个角色与接口面.md`（维护角色判据）·
      `代码形态分工.md` 第一节表 6（本落点形态 = shell 胶水 + 调接口面的 HTTP，**CLI 里 0 处判断**）

# 它是什么

**只做两件事**：把命令行参数拼成接口面认的 HTTP 请求；把接口面的返回格式化成人能读的字。

# 它明确不是什么（硬约束，逐条守住）

| 不许 | 本文件怎么守 |
|---|---|
| 不许解析契约 | 本文件里搜不到任何「按契约行序校验」「按编号查能力」的代码；`契约` 子命令把返回**原样**漂亮打印 |
| 不许生成 / 不许校验 | 不判断编号存不存在、不判断值的个数对不对、不判断值的类型对不对 —— 这些**全在后端**（接口面 + 调度层） |
| 不许引入第三方依赖 | 只用标准库 `urllib.request` / `json` / `base64` / `os` / `sys`（**不用 `requests`**） |
| 不许写死端口 | 端口来源三档：命令行 `--端口 N` > 环境变量 `V1_GATEWAY_PORT` > 默认 43110。**全平台唯一名只有一个，落点就是下面的 `端口环境变量`**（`接口面形状.md` §六）；名字是 ASCII —— 非 ASCII 变量名在 `sh` 下设不了（`V1_RUN_DATA_ROOT` 同口径）。**读它的就两处**：本界面与部署侧 `构建装配/上线切换/上线切换/制品.py::流量端口`（端口名收口）；Rust 网关自身不读环境变量，它的端口只从命令行 `--端口` 取（`启动网关.rs`） |
| 地址只许回环 | 主机恒为 `127.0.0.1`，**不提供改主机的口**（接口面不做鉴权，故只对本机开放） |

# 四个端点（`接口面形状.md` §二，冻结；一个不多一个不少）

| 子命令 | 方法 路径 |
|---|---|
| `清单` | `GET  /接口` |
| `契约 <编号>` | `GET  /接口/能力/<编号>` |
| `调用 <编号> <值…>` | `POST /接口/调用` |
| `声明 <文件>` | `POST /接口/声明` |

# 值的写法（`调用` 用；`值` 按契约**行序**对位，不省略位次）

| 写法 | 发出的槽 |
|---|---|
| `-` 或 `空` | `{"类型标签":0,"值":0}`（空槽） |
| 裸值（不含 `:`） | `{"类型标签":4,"值":"<裸值>"}`（文本；**接口面不猜类型，故这里要一个显式默认**） |
| `标签:值` | `{"类型标签":<标签>,"值":<按标签成形>}` |
| `@路径` | `{"类型标签":5,"值":"<文件字节的 base64>"}`（字节集；base64 是传输编码，不是业务） |

`标签` 是十进制数。标签 → JSON 形状**实测**（以后端 400 的说明文为准）：`0`=0 · `1` 整数=数 ·
`2` 双精度=数 · `3` 逻辑=`0`/`1`（**不是 JSON 的真/假**；本界面把 `真`/`假` 换成 `1`/`0`）·
`4` 文本=字符串 · `5` 字节集=base64 字符串 · `6` 句柄=非负整数 · 其余标签原样透传（面回 400「形状未定义」）。

# 退出码

`0` 成功 · `1` 业务失败（`成功: false` 且有 `错误`）· `2` 用法错（本地参数写错）· `3` 连不上 / 应答不是 JSON。

用法：`命令行界面.py --帮助`
"""

# 本文件是**路由**：把参数交给包里的 `命令行界面.命令.跑命令行`（含退出码与全部子命令）。
# 实现按关注点拆进同名字文件夹 `命令行界面/`。
import sys
import time
from pathlib import Path

起始时刻 = time.monotonic()  # 壳起表点：必须在 import 业务包**之前**（见 构建装配/门禁/壳.py）

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # 仓根：取共享门禁
from 构建装配.门禁 import 自门禁  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))

from 命令行界面.命令 import 跑命令行  # noqa: E402

if __name__ == "__main__":
    # ★ `跑命令行` **自身就 `sys.exit(退出码)`**（它的退出码语义见上面「# 退出码」，含四类错的映射）
    #   ⇒ 直接 `自门禁(起始时刻, 跑命令行(...))` 是**死代码**：`跑命令行` 一进去就退出，门禁那行永远跑不到。
    #   实测证据：加壳后跑反向样本 `V1_CMD_SLOW_MS=5200 … --帮助` ⇒ 69 ms · 退出码 0（**不红**）。
    #   故这里**接住它带的退出码**再交给门禁 —— 退出码照它算出来的保留，壳只负责「超顶即红」。
    退出码 = 0
    try:
        跑命令行(sys.argv[1:])
    except SystemExit as 退出异常:
        退出码 = 退出异常.code if isinstance(退出异常.code, int) else 1
    sys.exit(
        自门禁(
            起始时刻, 退出码, 尾巴余量毫秒=200,
            修法="本件是纯转发客户端，墙钟由网关应答决定 —— 超顶先看是哪个端点在慢"
                 "（后端节点的事），别在本件加超时去掩盖它。",
        )
    )
