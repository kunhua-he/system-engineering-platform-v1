#!/bin/sh
# 启动桌面薄壳 —— 把 `前端呈现/网页应用/` 装进系统 WebView。
#
# **端口只有一个来源**：`契约声明/常量表.json` 的「接口端口」。本脚本从那里现读，
# 不在这里再写一份（`接口面形状.md` §一：端口只有一个来源；上一版就是两头各写一份）。
#
# 用法：
#   sh 前端呈现/桌面应用/启动.sh                # 按契约端口拼 http://127.0.0.1:<接口端口>/
#   sh 前端呈现/桌面应用/启动.sh http://主机:端口/   # 直接给 URL（同源反代时用这个）
#
# 前置：网页应用必须**由接口面同源托管**（或由同源反代把 /接口 转给接口面），
#       否则壳里加载得到页面、却调不通接口。见 前端呈现/说明.md。
#
# 注：变量名一律 ASCII —— sh 不认中文标识符（工具链强制）。

set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "${HERE}/../.." && pwd)"

if [ "$#" -ge 1 ]; then
  URL="$1"
else
  PORT="$(grep -A2 '"名": "接口端口"' "${ROOT}/契约声明/常量表.json" \
    | grep '"值"' | head -1 | sed 's/[^0-9]//g')"
  if [ -z "${PORT}" ]; then
    echo "启动.sh：从 契约声明/常量表.json 读不到「接口端口」。" >&2
    echo "         请直接给 URL：sh 启动.sh http://主机:端口/" >&2
    exit 1
  fi
  URL="http://127.0.0.1:${PORT}/"
fi

echo "薄壳载入：${URL}"
echo "（解释执行 壳.swift，无构建产物；窗口一关即退出）"
exec swift "${HERE}/壳.swift" "${URL}"
