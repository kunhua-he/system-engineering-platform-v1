//! 启动网关 —— **生产启动入口**（装配节点）。一条链，四步，一步不少
//! （形状与判据：`构建装配/上线切换/形状.md` §四）：
//!
//! ```text
//! 读 扩展装载/扩展根声明.json  →  扫扩展根 + 调接缝 GetPlatformInfo  →  递给 服务::绑定  →  起监听
//! ```
//!
//! # 为什么必须有这个节点
//!
//! `服务::绑定` 要的**声明根由调用方注入**，而网关**自身去找声明就是跳层**
//! （`对外接口面/调用接口面/src/lib.rs` 缺口 4 的原话）。所以「谁读扩展根声明、谁调
//! `GetPlatformInfo`、谁把声明根递进去」必须有装配侧的一个节点承接 —— 就是本文件。
//! 它落在 `examples/`：**一个 example，不是新 workspace 成员** ⇒ 根 `Cargo.toml` /
//! `Cargo.lock` 一行不动。
//!
//! # 三条硬边界（README 第五节）在这里怎么成立
//!
//! 1. **底座不认识任何扩展**：本文件里没有任何扩展的名字、路径或特例分支 —— 扫到谁就是谁。
//! 2. **改一个扩展不用动底座**：加一个扩展 = 往扩展根里放一个目录，本文件一行不改。
//! 3. **扩展缺了底座照跑**：逐个试装，装不进的**剔除并报原因**，最终用剩下的声明根起服务。
//!
//! # 用法与两处破口
//!
//! `启动网关 [--声明根 <路径>] [--后缀表 <路径>] [--缓存根 <目录>] [--端口 <N>] [--静态根 <目录>] [--工具根 <目录>]`。
//! `--声明根` 默认 `扩展装载/扩展根声明.json`（相对**当前工作目录**）；`--后缀表` 默认
//! `扩展装载/后缀表.json`（同相对 cwd；它判「哪些件是可装载候选」，是**唯一权威**）；`--缓存根`
//! 是**解包物（能力码段）的落点**，不给就用适配器默认（运行数据根的缓存类 · 唯一物）；`--端口` 不给就用
//! 契约默认端口，给 `0` 让 OS 分配（装载预检用）；`--静态根` 不给就用 `常量.rs` 的 `静态根`
//! （`前端呈现/网页应用`，同相对 cwd）—— 它是 `接口面形状.md` §五 的**托管目录**；
//! `--工具根` 不给就用 `常量.rs` 的 `工具根默认`（`.`，即进程工作目录）—— 它是 §七 工具族的
//! **部署事实**（案例库 · 扩展根声明 · 外部 CLI 的所在）。这些同类：都是部署事实，由装配侧注入，
//! 网关不替它猜。
//!
//! **为什么「静态根 / 工具根」要与「声明根」分开注**（实测，2026-09-27）：上线切换必须
//! `cwd=制品目录`（制品内 `扩展根声明.json` 的 `路径基准` 就是「工作目录」、`种类[].扩展落点`
//! 指的是制品内的 `扩展/`），而静态件与案例库住在**仓根**。两个口径冲突，故各归各的部署事实
//! 注入，不互相借 cwd —— 早先只给 `cwd=制品目录` ⇒ `GET /` 全 `404`、`GET /接口/案例` 恒 `9002`。
//!
//! 实际端口打在 `监听 127.0.0.1:<端口>` 一行上 —— 上线切换靠它拿端口。
//!
//! 底座声明经 `v1_adapter::底座声明` 取（`v1_adapter` 再导出 `v1_loader::底座声明`）——
//! 本 crate 的 `Cargo.toml` 里**没有 `v1-loader` 依赖**：拿底座声明一律走适配器那条边，
//! 不走「底座声明直连内核」的跳层边（那条边 2026-09-27 已拆）。
//!
//! # 本文件是路由
//!
//! 一个关注点一个件，放同名字文件夹 `启动网关/`：`扫根.rs`（转调 `v1_gateway::扫扩展根`）·
//! `接缝.rs`（转调同上）· `装配.rs`（四步链本体）。
//! 本文件只做 `mod` 声明与 `main` 的一行转调 —— **CLI 与行为逐字不变**。
//!
//! **2026-09-28**：`JSON读取.rs` 已删 —— 扩展根声明的读法搬进
//! `对外接口面/调用接口面/src/执行装配/扫扩展根.rs::读声明根`（启动装配与运行期装载同读一份，台账 237）。

