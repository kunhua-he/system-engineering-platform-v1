//! 启动网关 · 装配 —— 四步链的接线：读扩展根声明 → 扫扩展根 + 调接缝 → 递给 `服务::绑定` → 起监听。
//!
//! 从 `examples/启动网关.rs` 搬来（那是装配入口，本件是它的一个关注点；**纯搬家**）。
//! 形状与判据：`构建装配/上线切换/形状.md` §四。
//!
//! **2026-09-28 收一处**：扫描规则与 `dlopen`/取接缝都在
//! `对外接口面/调用接口面/src/扫扩展根.rs`（`v1_gateway::扫扩展根`）——
//! **启动装配与运行期装载（`POST /接口/生命周期` 动作=装载）同读一份**；
//! 本件只做「试装 + 剔除并报因」，并把 `--声明根` 注入服务（运行期重扫的落点）。

use std::env;
use std::fs;
use std::path::PathBuf;

use v1_adapter::{适配器, 平台信息, 装载失败, 载入错误};
use v1_gateway::依赖序装载::{按依赖序装载, 试装结局};
use v1_gateway::扫扩展根::{读后缀表, 读声明根};
use v1_gateway::{启动失败, 服务};

use crate::扫根::列子目录;
use crate::接缝::取扩展声明;

/// 失败 → 一句可读的原因（**不吞段位**：失败是结构化的，这里只做转写，不做判断）。
///
/// 这里**不解构** `装载失败` 的变体：解构要写出「载入 + 左括号」这个形状，而判据 ⑪ 数的正是
/// 「调用内核入口 载入 的处数」（`一键验证.py` 的模式），会被数成第二条腿（实测撞到）。
fn 说清启动失败(错误: &启动失败) -> String {
    match 错误 {
        启动失败::装载(错误) => format!("装载失败：{错误:?}"),
        启动失败::绑定(错误) => format!("端口绑不上：{错误}"),
    }
}

fn 取值(名称: &str) -> Option<String> {
    let 命令行参数: Vec<String> = env::args().collect();
    命令行参数.iter().position(|参数项| 参数项 == 名称).and_then(|位次| 命令行参数.get(位次 + 1).cloned())
}

/// 跑完整条链。命令行参数、端口与日志输出**逐字不变**（上线切换靠 `监听 127.0.0.1:<端口>` 一行拿端口）。
pub(crate) fn 跑网关() -> Result<(), String> {
    let 声明根路径 =
        PathBuf::from(取值("--声明根").unwrap_or_else(|| "扩展装载/扩展根声明.json".to_owned()));
    let 监听端口: Option<u16> = match 取值("--端口") {
        Some(源文本) => Some(源文本.parse::<u16>().map_err(|_| format!("--端口 不是整数：{源文本}"))?),
        None => None,
    };
    // §五 的静态托管根：不给就用契约侧常量（相对 cwd），给了就注入 ——
    // 与 `--声明根` 同一口径（都是部署事实，装配侧说了算）。
    let 静态根 = 取值("--静态根");
    // §七 工具族的工具根（案例库 / 扩展根声明 / 外部 CLI 的所在）：同上，不给就用 cwd。
    // 单列一个口是因为它**可以与静态根不同根**：上线切换的 cwd 是制品目录（扩展在那儿），
    // 而静态件与案例库在仓根（见文件头「为什么两处要与声明根分开注」）。
    let 工具根 = 取值("--工具根");

    // ── 第一步：读扩展根声明 ────────────────────────────────────────────────
    // 读法只有一份：`v1_gateway::扫扩展根::读声明根`（启动装配与运行期装载同读一份）。
    let 源文本 = fs::read_to_string(&声明根路径)
        .map_err(|错误| format!("读不到扩展根声明 {}：{错误}", 声明根路径.display()))?;
    let 声明根扫描 = 读声明根(&源文本)?;
    // 后缀表（**唯一权威**）：候选资格由它判（`制品后缀`），与 `--声明根` 同一条约定 ——
    // 装配侧说了算；不给就用仓根那份（相对**当前工作目录**）。本件不持有任何后缀。
    // 文本同时留给服务持有：运行期重扫与启动装配判候选用同一份后缀集（唯一权威）。
    let 文本值 = fs::read_to_string(
        取值("--后缀表").unwrap_or_else(|| "扩展装载/后缀表.json".to_owned()),
    )
    .map_err(|错误| format!("读不到后缀表：{错误}"))?;
    let 后缀表 = 读后缀表(&文本值)?;
    // 解包物（能力码段）落点：部署侧给了 `--缓存根` 就用它（与 `--声明根` 同形）；
    // 不给就用适配器的默认（运行数据根的缓存类，唯一物）—— `对外接口面` 按层序拿不到
    // 运行内核（跳层）⇒ 由它唯一的腿提供这一口。两者都拿不到 ⇒ fail-closed。
    let 缓存根目录 = match 取值("--缓存根") {
        Some(根目录) => Some(PathBuf::from(根目录)),
        None => v1_adapter::装载件缓存::默认缓存根目录(),
    }
    .ok_or_else(|| "解析不出运行数据根：解包物无处可落（不退回源码树 / `/tmp`）".to_owned())?;
    println!(
        "扩展根声明 {} · 种类 {} 类",
        fs::canonicalize(&声明根路径)
            .map(|路径| 路径.display().to_string())
            .unwrap_or_else(|_| 声明根路径.display().to_string()),
        声明根扫描.种类数
    );

    // ── 第二步：扫扩展根 + 调接缝 GetPlatformInfo ──────────────────────────
    //
    // 扫描规则（扫哪些目录 · 找什么 · 取接缝）都在 `v1_gateway::扫扩展根::读声明根`
    // （与装配侧 `构建装配/上线切换/构建制品/扩展.py::扫扩展` 同一条规则；启动装配与
    // 运行期装载同读一份）。本步只做「试装 + 剔除并报因」。
    let mut 声明候选: Vec<&'static 平台信息> = vec![v1_adapter::底座声明()];
    // 声明 + 它的落点目录：**跨进程部署配置校验要用它**（判「这条配置配的是哪一份已装载
    // 声明、它的制品在不在那个落点里」）。本件不猜落点。
    let mut 已装声明落点: Vec<(&'static 平台信息, String)> = Vec::new();
    let mut 剔除的: Vec<(String, String)> = Vec::new();
    // 取到接缝的候选：**按依赖序多趟试装**（台账 C04）—— 装配期与热装载同读
    // `v1_gateway::依赖序装载` 那一份，两路的拓扑保证才等价。
    // 依赖者排在依赖者之前时，本趟判 ⑤ 不过，下趟依赖者已进 声明候选 即能装上 ——
    // 依赖序不再随扫根的名字序飘（源：`扫扩展根.rs::列子目录`「按名字排序」）。
    let mut 待装候选表: Vec<(&'static 平台信息, String)> = Vec::new();
    for 扩展根目录 in &声明根扫描.目录s {
        if !扩展根目录.is_dir() {
            println!("跳过 {}：目录不存在", 扩展根目录.display());
            continue;
        }
        for 子目录项 in 列子目录(扩展根目录) {
            let 落点 = 子目录项.display().to_string();
            match 取扩展声明(&子目录项, &后缀表, &缓存根目录) {
                Err(失败原因) => 剔除的.push((落点, 失败原因)),
                Ok(声明) => 待装候选表.push((声明, 落点)),
            }
        }
    }
    let 依赖序结果 = 按依赖序装载(
        待装候选表,
        &mut |声明, 落点| {
            // 试装：拿**同一个** `适配器::装载声明根` 走一遍（与 `服务::绑定` 内部
            // 用的是同一条装载路，不另写一套）。装得上才算这份声明根的一份。
            let mut 试装候选 = 声明候选.clone();
            试装候选.push(声明);
            match 适配器::装载声明根(&试装候选) {
                Ok(_) => {
                    声明候选.push(声明);
                    已装声明落点.push((声明, 落点.to_owned()));
                    试装结局::装上
                }
                // 本趟缺依赖 ⇒ 延后一趟（依赖者装上了它就能装）。
                Err(装载失败::载入失败(载入错误::依赖缺失)) => 试装结局::缺依赖,
                Err(错误) => 试装结局::硬失败(说清启动失败(&启动失败::装载(错误))),
            }
        },
        &说清启动失败(&启动失败::装载(装载失败::载入失败(载入错误::依赖缺失))),
    );
    let 装上的: Vec<String> = 依赖序结果.装上;
    剔除的.extend(依赖序结果.剔除);
    println!(
        "扫到扩展 {} 个（装上 {} · 剔除 {}）",
        装上的.len() + 剔除的.len(),
        装上的.len(),
        剔除的.len()
    );
    for 落点 in &装上的 {
        println!("  装上 {落点}");
    }
    for (落点, 失败原因) in &剔除的 {
        println!("  剔除 {落点}：{失败原因}");
    }

    // ── 第三步：递给 服务::绑定（静态托管根给了就注入，见 `接口面形状.md` §五）────
    let 服务 = match 监听端口 {
        Some(号值) => 服务::绑定端口(&声明候选, 号值),
        None => 服务::绑定默认端口(&声明候选),
    }
    .map_err(|错误| format!("起服务失败：{}", 说清启动失败(&错误)))?;
    // 声明根路径是运行期装载（`POST /接口/生命周期` 动作=装载）**重扫**的落点：
    // 与 静态根 / 工具根 同一条约定（部署事实 · 装配侧说了算），由本入口注入。
    // **后缀表文本也随服务持有**：运行期重扫与启动装配判候选用的是同一份后缀集。
    let 服务 = 服务.声明根(&声明根路径).后缀表(文本值).缓存根目录(缓存根目录);
    let 服务 = match 静态根 {
        Some(根目录) => 服务.托管静态根(根目录),
        None => 服务,
    };
    let 服务 = match 工具根 {
        Some(根目录) => 服务.工具根(根目录),
        None => 服务,
    };
    // 资源声明根：与 `--声明根` / `--静态根` / `--工具根` 同一条约定 —— 部署事实、
    // 装配侧说了算。**不给就一条资源都不声明** ⇒ 关口默认拒绍（空清单 = 什么都拒）。
    // 配了就现场建关口（读 JSON → 校验声明 → 逐条绑适配器入口），共享出去之前注入。
    let mut 服务 = 服务;
    if let Some(资源声明根路径) = 取值("--资源声明根") {
        let 资源声明根文本 = fs::read_to_string(&资源声明根路径)
            .map_err(|错误| format!("读不到资源声明根 {资源声明根路径}：{错误}"))?;
        let 关口 = v1_gateway::资源装配::建资源关口(&资源声明根文本, &服务.适配器())
            .map_err(|错误| format!("建资源关口失败：{错误}"))?;
        println!(
            "资源声明根 {资源声明根路径} · 声明 {} 条（未绑入口的调了会拿「入口未绑定」）",
            关口.已声明资源数()
        );
        服务.注入资源关口(关口);
    }

    // 跨进程执行域：**由部署配置注入**（冻结件 §四）。与 `--声明根` / `--静态根` / `--工具根`
    // 同一条约定 —— 部署事实、装配侧说了算、网关不替它猜。**不给就一条都不登记** ⇒ 全部
    // 走进程内（默认进程内，选了才跨进程）。配置里的扩展名来自**配置文件**，本件零字面。
    // 给了配置口才开跨进程表；没给 ⇒ 一条都不登记，全部走进程内原路（一分钱不多花）。
    if let Some(配置路径) = 取值("--跨进程配置") {
        let 配置文本 = fs::read_to_string(&配置路径)
            .map_err(|错误| format!("读不到跨进程部署配置 {配置路径}：{错误}"))?;
        let 部署 = v1_gateway::读部署配置(&配置文本)?;
        let 条目数 = 部署.条目表.len();
        let 结局表 = 服务.注入跨进程域(部署, &已装声明落点);
        println!("跨进程部署配置 {配置路径} · 条目 {条目数} 条");
        for (标识串, 结局) in &结局表 {
            match 结局 {
                v1_gateway::条目结局::已登记 => println!("  跨进程 {标识串}：已登记执行域"),
                v1_gateway::条目结局::走进程内 => {
                    println!("  跨进程 {标识串}：未给工作进程路径 ⇒ 走进程内（不猜）")
                }
                v1_gateway::条目结局::拒收(拒收原因) => println!("  跨进程 {标识串}：拒收（{拒收原因}）"),
            }
        }
    }

    // ── 第四步：起监听（这一行是给上线切换读的：它靠它拿实际端口）──────────
    println!("监听 127.0.0.1:{}", 服务.监听端口());
    println!("静态托管根 {}（`GET /` 从这里回 index.html）", 服务.静态根().display());
    println!("工具根 {}（§七 工具族的案例库 / 扩展根声明 / 外部 CLI 从这里取）", 服务.取工具根().display());
    println!(
        "声明根 {} 份 · 能力清单 {} 条",
        服务.适配器().已装载声明数(),
        服务.适配器().能力清单().len()
    );
    let _ = 服务.跑服务();
    Ok(())
}
