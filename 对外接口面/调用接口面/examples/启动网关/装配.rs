//! 启动网关 · 装配 —— 四步链的接线：读扩展根声明 → 扫扩展根 + 调接缝 → 递给 `服务::绑定` → 起监听。
//!
//! 从 `examples/启动网关.rs` 搬来（那是装配入口，本件是它的一个关注点；**纯搬家**）。
//! 形状与判据：`构建装配/上线切换/形状.md` §四。
//!
//! **2026-09-27 非纯搬一处**：第二步扫候选收窄到 `可装载件 = true`
//! （缺键 / 非布尔 ⇒ fail-closed 指路），与装配侧 `扩展.py::可装载种类` 同一条规则。
//! 细节见 `跑网关()` 内第二步那段注释。

use std::env;
use std::fs;
use std::path::PathBuf;

use v1_adapter::{适配器, 平台信息};
use v1_gateway::{启动失败, 服务};

use crate::JSON读取::读器;
use crate::扫根::子目录;
use crate::接缝::取扩展声明;

/// 失败 → 一句可读的原因（**不吞段位**：失败是结构化的，这里只做转写，不做判断）。
///
/// 这里**不解构** `装载失败` 的变体：解构要写出「载入 + 左括号」这个形状，而判据 ⑪ 数的正是
/// 「调用内核入口 载入 的处数」（`一键验证.py` 的模式），会被数成第二条腿（实测撞到）。
fn 说清启动失败(错误: &启动失败) -> String {
    match 错误 {
        启动失败::装载(错) => format!("装载失败：{错:?}"),
        启动失败::绑定(错) => format!("端口绑不上：{错}"),
    }
}

fn 取值(名称: &str) -> Option<String> {
    let 参数: Vec<String> = env::args().collect();
    参数.iter().position(|一项| 一项 == 名称).and_then(|位置| 参数.get(位置 + 1).cloned())
}

/// 跑完整条链。命令行参数、端口与日志输出**逐字不变**（上线切换靠 `监听 127.0.0.1:<端口>` 一行拿端口）。
pub(crate) fn 跑网关() -> Result<(), String> {
    let 声明根路径 =
        PathBuf::from(取值("--声明根").unwrap_or_else(|| "扩展装载/扩展根声明.json".to_owned()));
    let 端口: Option<u16> = match 取值("--端口") {
        Some(文) => Some(文.parse::<u16>().map_err(|_| format!("--端口 不是整数：{文}"))?),
        None => None,
    };
    // §五 的静态托管根：不给就用契约侧常量（相对 cwd），给了就注入 ——
    // 与 `--声明根` 同一口径（都是部署事实，装配侧说了算）。
    let 静态根 = 取值("--静态根");
    // §七 工具族的工具根（案例库 / 扩展根声明 / 外部 CLI 的所在）：同上，不给就用 cwd。
    // 单列一个口是因为它**可以与静态根不同根**：上线切换的 cwd 是制品目录（扩展在那儿），
    // 而静态件与案例库在仓根（见文件头「为什么两处要与声明根分开注」）。
    let 工具根 = 取值("--工具根");

    // ── 第一步：读扩展根声明 ────────────────────────────────────────────────
    let 文本 = fs::read_to_string(&声明根路径)
        .map_err(|错误| format!("读不到扩展根声明 {}：{错误}", 声明根路径.display()))?;
    let 根目录 = 读器::新建(&文本)
        .读一个值()
        .map_err(|错误| format!("扩展根声明不是合法 JSON：{错误}"))?;
    let 种类 = 根目录
        .取成员("种类")
        .and_then(|待处理值| 待处理值.取数组())
        .ok_or_else(|| "扩展根声明缺 `种类` 段".to_owned())?;
    println!(
        "扩展根声明 {} · 种类 {} 类",
        fs::canonicalize(&声明根路径)
            .map(|路径| 路径.display().to_string())
            .unwrap_or_else(|_| 声明根路径.display().to_string()),
        种类.len()
    );

    // ── 第二步：扫扩展根 + 调接缝 GetPlatformInfo ──────────────────────────
    //
    // **候选面收窄到 `可装载件 = true`**（2026-09-27 裁）：与装配侧
    // `构建装配/上线切换/构建制品/扩展.py::可装载种类` 走**同一条规则** —— 只有
    // `可装载件 = true` 的种类（支持库）的直接子目录才是可装载件候选；模块（组装件）
    // 与技能（声明/工作流）**不编可装载库、不 dlopen**，不进候选。旧口径按
    // `种类[].目录` **全扫**，会把模块/技能也当候选去 `dlopen`，那正是老仓 7.1④ 要撤的旁路。
    //
    // `可装载件` **缺键 / 非布尔 ⇒ fail-closed 指路，不给默认值**（与装配侧逐字同一条
    // 规则）：默认 `true` 会把旁路放回来，默认 `false` 会把支持库静默漏掉。
    let mut 候选: Vec<&'static 平台信息> = vec![v1_adapter::底座声明()];
    let mut 装上的: Vec<String> = Vec::new();
    let mut 剔除的: Vec<(String, String)> = Vec::new();
    for 类别 in 种类 {
        let 类名 = 类别.取成员("种类").and_then(|待处理值| 待处理值.取字符串()).unwrap_or("?");
        let Some(可装载) = 类别.取成员("可装载件").and_then(|待处理值| 待处理值.布尔()) else {
            return Err(format!(
                "扩展根声明的 种类[{类名}] 缺 `可装载件`（或不是布尔）。\n  \
                 这个键决定「这一类的直接子目录要不要当可装载件候选」（支持库 true · \
                 模块/技能 false）；不给默认值——默认 true 会把旁路放回来，默认 false \
                 会把支持库静默漏掉。见 扩展装载/扩展根声明.json 的种类[].可装载件"
            ));
        };
        if !可装载 {
            continue;
        }
        let Some(目录) = 类别.取成员("目录").and_then(|待处理值| 待处理值.取字符串()) else {
            continue;
        };
        let 目录 = PathBuf::from(目录);
        if !目录.is_dir() {
            println!("跳过 {}：目录不存在", 目录.display());
            continue;
        }
        for 子目录项 in 子目录(&目录) {
            let 落点 = 子目录项.display().to_string();
            match 取扩展声明(&子目录项) {
                Err(原因) => 剔除的.push((落点, 原因)),
                Ok(声明) => {
                    // 试装：拿**同一个** `适配器::装载声明根` 走一遍（与 `服务::绑定` 内部
                    // 用的是同一条装载路，不另写一套）。装得上才算这份声明根的一份。
                    let mut 试装候选 = 候选.clone();
                    试装候选.push(声明);
                    match 适配器::装载声明根(&试装候选) {
                        Ok(_) => {
                            候选.push(声明);
                            装上的.push(落点);
                        }
                        Err(错) => 剔除的.push((落点, 说清启动失败(&启动失败::装载(错)))),
                    }
                }
            }
        }
    }
    println!(
        "扫到扩展 {} 个（装上 {} · 剔除 {}）",
        装上的.len() + 剔除的.len(),
        装上的.len(),
        剔除的.len()
    );
    for 落点 in &装上的 {
        println!("  装上 {落点}");
    }
    for (落点, 原因) in &剔除的 {
        println!("  剔除 {落点}：{原因}");
    }

    // ── 第三步：递给 服务::绑定（静态托管根给了就注入，见 `接口面形状.md` §五）────
    let 服务 = match 端口 {
        Some(号) => 服务::绑定(&候选, 号),
        None => 服务::绑定默认端口(&候选),
    }
    .map_err(|错误| format!("起服务失败：{}", 说清启动失败(&错误)))?;
    let 服务 = match 静态根 {
        Some(根) => 服务.托管静态根(根),
        None => 服务,
    };
    let 服务 = match 工具根 {
        Some(根) => 服务.工具根(根),
        None => 服务,
    };

    // ── 第四步：起监听（这一行是给上线切换读的：它靠它拿实际端口）──────────
    println!("监听 127.0.0.1:{}", 服务.端口());
    println!("静态托管根 {}（`GET /` 从这里回 index.html）", 服务.静态根().display());
    println!("工具根 {}（§七 工具族的案例库 / 扩展根声明 / 外部 CLI 从这里取）", 服务.取工具根().display());
    println!(
        "声明根 {} 份 · 能力清单 {} 条",
        服务.适配器().已装载声明数(),
        服务.适配器().能力清单().len()
    );
    let _ = 服务.跑服务();
    Ok(())
}
