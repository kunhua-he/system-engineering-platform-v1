//! 契约响应 —— **读侧**根端点（`自描述根`）。
//!
//! 从 `响应.rs` 拆出（单源文件 ≤ 400 行是硬规矩，`开发规范.md` 第六节）；
//! 形状逐字照 `项目文档/设计文档/接口面形状.md` §三。

use crate::协议值::协议值;
use crate::常量::{端点表, 端口来源, 旁路端点表};
use v1_adapter::{适配器, 版本三元组};
use v1_adapter::声明数据::单项超时毫秒;
#[cfg(unix)]
use v1_adapter::进程池::{
    默认退避上限毫秒, 默认退避基数毫秒, 默认重启预算, 默认熔断时长毫秒,
};
#[cfg(unix)]
use v1_adapter::进程帧::{单帧载荷上限, 调用载荷上限};

/// `GET /接口` → 自描述根（§三）。
///
/// `契约版本` 与 `声明格式号` 从**注入的声明**上现读（网关在构造时取下的标量快照，
/// 见 `网关.rs::服务::契约身份`）。为什么不直接存 `&'static 平台信息`：那个引用带裸指针、
/// 不是 `Sync`，会让 `服务` 不能跨线程共享（并发收连接要的正是共享 `服务`）；
/// 声明是静态只读的 ⇒ 标量快照与现读等价。两者都不另存第二份事实。
///
/// `实际端口` 是**旁路字段**（冻结件允许新增）：报的是**真正绑上的端口**，不是常量。
/// 为什么值得加：判据是「第一次用不需要读文档就能调对」，而「端口在哪」正是那件
/// 不读文档会卡住的事；报常量会在测试与多实例下报出一个**假事实**。
///
/// `契约身份`（§32.4）**已经由现有的两个键给出**：`契约版本` 与 `声明格式号` 就是网关
/// 当前据以服务的契约身份快照 ⇒ 本端点**不再新增一个重复的快照字段**（同一事实两份 = 缺陷）。
/// Agent 先取契约、随后调用时，可拿这两个键与调用时机对照；**扩展级**的身份（哪个扩展的
/// 哪份制品）由适配器公开面按能力号给（`适配器::能力身份`）—— 走调用 / 能力契约应答里的
/// `扩展身份` 旁路键带回，不在根端点的每个能力条目上再堆一遍（那是同一事实两份）。
pub fn 自描述根(
    契约版本: &版本三元组,
    声明格式号: u32,
    适配器: &适配器,
    实际端口: u16,
) -> 协议值 {
    let 版本 = 契约版本;
    #[cfg(unix)]
    let 跨进程启用 = 适配器.有跨进程域();
    #[cfg(not(unix))]
    let 跨进程启用 = false;
    let mut 根项 = vec![
        (
            "契约版本".to_owned(),
            协议值::对象值(vec![
                ("主".to_owned(), 协议值::整数项(i64::from(版本.主版本))),
                ("次".to_owned(), 协议值::整数项(i64::from(版本.次版本号))),
                ("构建".to_owned(), 协议值::整数项(i64::from(版本.构建))),
            ]),
        ),
        (
            "声明格式号".to_owned(),
            协议值::整数项(i64::from(声明格式号)),
        ),
        ("端口来源".to_owned(), 协议值::文本值(端口来源.to_owned())),
        (
            "实际端口".to_owned(),
            协议值::整数项(i64::from(实际端口)),
        ),
        (
            "端点".to_owned(),
            协议值::数组值(
                端点表
                    .iter()
                    .map(|(请求方法, 路径, 说明文字)| {
                        协议值::对象值(vec![
                            ("方法".to_owned(), 协议值::文本值((*请求方法).to_owned())),
                            ("路径".to_owned(), 协议值::文本值((*路径).to_owned())),
                            ("说明".to_owned(), 协议值::文本值((*说明文字).to_owned())),
                        ])
                    })
                    .collect(),
            ),
        ),
        // **旁路端点**（§七 工具族）—— 与 `端点` 分开一个键，因为 §二 那张四个端点的表是
        // **冻结项**（冻结项只许新增旁路字段、不许改旧字段含义）：把新端点塞进 `端点` 数组
        // 就是改了那张表的含义。分开之后，只读 `端点` 的旧读者读到的东西**逐字不变**，
        // 而第一次用的人照样一次拿全（判据：根端点自身就是说明书）。
        (
            "旁路端点".to_owned(),
            协议值::数组值(
                旁路端点表
                    .iter()
                    .map(|(请求方法, 路径, 说明文字)| {
                        协议值::对象值(vec![
                            ("方法".to_owned(), 协议值::文本值((*请求方法).to_owned())),
                            ("路径".to_owned(), 协议值::文本值((*路径).to_owned())),
                            ("说明".to_owned(), 协议值::文本值((*说明文字).to_owned())),
                        ])
                    })
                    .collect(),
            ),
        ),
        (
            "能力".to_owned(),
            // **全量**，不是首页（§三：未载入的扩展其能力不在表里；不做分页）。
            // 清单是**当场**从适配器取的 —— 与调侧同一个入口，不另存一份表。
            协议值::数组值(
                适配器
                    .能力清单()
                    .iter()
                    .map(|能力摘要| {
                        协议值::对象值(vec![
                            ("编号".to_owned(), 协议值::整数项(i64::from(能力摘要.编号))),
                            ("名称".to_owned(), 协议值::文本值(能力摘要.名称.clone())),
                            (
                                "参数个数".to_owned(),
                                协议值::整数项(i64::from(能力摘要.参数个数)),
                            ),
                            (
                                "返回类型".to_owned(),
                                协议值::整数项(i64::from(能力摘要.返回类型)),
                            ),
                        ])
                    })
                    .collect(),
            ),
        ),
    ];
    根项.extend(执行能力四项(跨进程启用));
    协议值::对象值(根项)
}

/// 平台执行能力四项 —— 自描述要写清的四项：执行模式 · 超时保障 · 恢复能力 · 消息大小。
///
/// **值一律现读具名常量，不在这里写第二份数字**：
///
/// | 项 | 真源 |
/// |---|---|
/// | 执行模式 | 本实例**真的**开没开跨进程执行域表（`适配器::有跨进程域`，现读） |
/// | 超时保障 | `契约声明/常量表.json` 的 `单项超时毫秒`（经适配器再导出） |
/// | 恢复能力 | `进程池.rs` 的退避 / 重启预算 / 熔断四个具名常量 |
/// | 消息大小 | `进程帧.rs` 的单帧 / 单次调用两个具名常量 |
///
/// **隔离边界如实说明**：进程隔离只隔**执行载体** —— 工作进程崩溃与内存不牵连宿主；
/// 它**不是**文件 / 网络 / 密钥沙箱：工作进程与宿主同权限、同文件系统、同网络。
/// 底座只守一条底线「不造成系统性破坏」，不把「相对安全」说成绝对边界。
fn 执行能力四项(跨进程启用: bool) -> Vec<(String, 协议值)> {
    let 执行模式说明 = if 跨进程启用 {
        "按号：登记过执行域的号走工作进程（跨进程执行域）；其余走进程内转发"
    } else {
        "全部走进程内转发（本实例未开跨进程执行域表）"
    };
    #[cfg(unix)]
    let 恢复读数 = 协议值::对象值(vec![
        ("重启预算".to_owned(), 协议值::整数项(i64::from(默认重启预算))),
        ("退避基数毫秒".to_owned(), 协议值::整数项(默认退避基数毫秒 as i64)),
        ("退避上限毫秒".to_owned(), 协议值::整数项(默认退避上限毫秒 as i64)),
        ("熔断时长毫秒".to_owned(), 协议值::整数项(默认熔断时长毫秒 as i64)),
        (
            "适用".to_owned(),
            协议值::文本值("仅跨进程执行域；进程内转发不经进程池".to_owned()),
        ),
    ]);
    #[cfg(not(unix))]
    let 恢复读数 = 协议值::对象值(vec![(
        "说明".to_owned(),
        协议值::文本值("非 unix 平台：跨进程执行域整支不存在，无进程池恢复机制".to_owned()),
    )]);
    #[cfg(unix)]
    let 消息读数 = 协议值::对象值(vec![
        ("单帧载荷上限".to_owned(), 协议值::整数项(单帧载荷上限 as i64)),
        ("调用载荷上限".to_owned(), 协议值::整数项(调用载荷上限 as i64)),
        (
            "适用".to_owned(),
            协议值::文本值("仅跨进程执行域的工作进程线协议".to_owned()),
        ),
    ]);
    #[cfg(not(unix))]
    let 消息读数 = 协议值::对象值(vec![(
        "说明".to_owned(),
        协议值::文本值("非 unix 平台：跨进程执行域整支不存在，无线协议消息上限".to_owned()),
    )]);
    vec![
        (
            "执行模式".to_owned(),
            协议值::对象值(vec![
                ("说明".to_owned(), 协议值::文本值(执行模式说明.to_owned())),
                (
                    "跨进程执行域".to_owned(),
                    if 跨进程启用 { 协议值::真值 } else { 协议值::假值 },
                ),
            ]),
        ),
        (
            "超时保障".to_owned(),
            协议值::对象值(vec![
                ("单项超时毫秒".to_owned(), 协议值::整数项(单项超时毫秒 as i64)),
                (
                    "来源".to_owned(),
                    协议值::文本值(
                        "契约声明/常量表.json 的 单项超时毫秒；全平台唯一口径".to_owned(),
                    ),
                ),
            ]),
        ),
        ("恢复能力".to_owned(), 恢复读数),
        ("消息大小".to_owned(), 消息读数),
        (
            "隔离边界".to_owned(),
            协议值::文本值(
                "进程隔离只隔执行载体（工作进程崩溃与内存不牵连宿主）；它不是文件 / 网络 / 密钥沙箱：工作进程与宿主同权限、同文件系统、同网络。".to_owned(),
            ),
        ),
    ]
}
