//! 工具根守卫 —— §七 `POST /接口/程序文本` 的**安全前提**（口径：`项目文档/决策记录/2026-09-28_安全边界.md` §一）。
//!
//! # 这个件补的是什么
//!
//! 该端点原先**真读 / 真写调用方自带的任意路径**，没有任何上界：请求体里给一个绝对路径
//! 就能读到盘上任何一处、写到盘上任何一处。`项目文档/决策记录/2026-09-28_安全边界.md` §一
//! 把「经边界的输入」定为**不可信**，故这条路缺的是一条**上界**与一条 **fail-closed**。
//!
//! # 上界怎么定（口径：相对安全，不是绝对边界）
//!
//! 底座面向本地私有部署（派活信 §五 第 6 条）⇒ 只守一条底线「不造成系统性破坏」：
//!
//! · **默认最紧**：请求体不给 `权限` 时按 `只读` 走 —— 只读盘，不写盘。
//! · **上界 = 工具根**：规范化后的路径必须落在注入的 `工具根` 之内。
//!   工具根是 §七 工具族的**部署事实**（`网关.rs` 的 `服务::工具根`），
//!   程序文本那一层本来也是相对它解的 ⇒ 上界与既有落点同一条约定，不另立第二个根。
//! · **要写就显式传参**：请求体给 `权限: "读写"` 才放行写动作。
//!
//! # 为什么用**词法**规范化，不用 `canonicalize`
//!
//! `std::fs::canonicalize` 要求路径**已在盘上**：写一个新件时父目录可能还不存在，
//! 它会失败。而失败时若「放行」就是 fail-open —— 一个会读盘失败的路径反而绕过了守卫。
//! 词法规范化只看字符串（`.` 与 `..` 段按词法折叠），**不碰盘**，故守卫的判定与盘面无关。

use std::ffi::OsString;
use std::path::{Component, Path, PathBuf};

/// 程序文本端点的**权限等级** —— 请求体里的可选键 `权限` 的取值域（闭合枚举）。
///
/// 为什么默认是最紧的一档而不是最松：`安全边界.md` §一 把经边界的输入定为不可信，
/// 而「缺键」是这条不可信输入最常见的一种 ⇒ 缺键必须落到**最紧**那一档，
/// 缺省松一档等于把「忘写一个键」变成一次越权。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 权限等级 {
    /// 只允许读（缺键时的档）。
    只读,
    /// 读与写都允许（要显式传参才到这档）。
    读写,
}

impl 权限等级 {
    /// 缺键时给的档：**最紧**那一档。
    pub const 默认: 权限等级 = 权限等级::只读;

    /// 权限等级的名字（回执里如实报出用的是哪一档）。
    pub fn 取名称(self) -> &'static str {
        match self {
            权限等级::只读 => "只读",
            权限等级::读写 => "读写",
        }
    }

    /// 本档允不允许写动作。
    pub fn 允许写(self) -> bool {
        matches!(self, 权限等级::读写)
    }
}

/// 路径守卫 —— 把调用方给的路径词法规范化后判它落不落在允许根内。
///
/// 回 `Err` 时带一句**具体为什么**（回执要「缺什么 / 为什么」有内容，
/// 不许一个「越界」两字糊过去）。
///
/// 两种越界各报各的：
///
/// · **绝对路径**：规范化后必须落在规范根之内；不在 ⇒ 拒。
/// · **相对路径**：规范化时爬到根之上（`..` 比已见过的普通段还多）⇒ 拒。
///   规范化成功时结果**不带前导 `..`**，故 join 根之后必在根内 —— 不必再比一次。
///
/// # 判定用规范根，**回带用注入根**
///
/// 判定必须拿规范根比（否则 `/var` 与 `/private/var` 这类同一处的两种写法会被判成越界）；
/// 但回来的路径要拼在**注入的那个根**上 —— 否则回执里的 `路径` 会带着规范根的写法，
/// 而 `取相对路径` 拿的是注入根，剥不掉前缀 ⇒ 回执里会突然出现一条绝对路径（读数前后不一）。
/// 两条路指的是同一处，只是写法统一到调用方看见的那一个根上。
pub fn 判路径在根内(允许根: &Path, 给定: &str) -> Result<PathBuf, String> {
    let 规范根 = 规范根路径(允许根);
    let 给定路径 = Path::new(给定);
    match 词法规范化(给定路径) {
        None => Err(format!(
            "相对路径爬到允许根之上（`..` 比已见过的普通段还多）⇒ 越界；允许根：{}",
            规范根.display()
        )),
        Some(规范给定) if 规范给定.is_absolute() => match 规范给定.strip_prefix(&规范根) {
            Ok(根内相对) => Ok(允许根.join(根内相对)),
            Err(_) => Err(format!(
                "绝对路径不在允许根内 ⇒ 越界；允许根：{}",
                规范根.display()
            )),
        },
        Some(规范给定) => Ok(允许根.join(规范给定)),
    }
}

/// 允许根的规范化：能 `canonicalize` 就用它（把符号链接也折掉），
/// 失败就退回词法规范化 —— **不 panic、不 fail-open**。
///
/// 允许根是注入的部署事实，生产里必然在盘上；测试里是刚建出来的临时目录。
/// 两条路都拿不到时退回词法结果，仍然是一个确定的路径（比 panic 好：
/// 守卫是安全前提，崩掉等于把端点整个打死）。
fn 规范根路径(允许根: &Path) -> PathBuf {
    if let Ok(已规范) = std::fs::canonicalize(允许根) {
        return 已规范;
    }
    词法规范化(允许根).unwrap_or_else(|| 允许根.to_path_buf())
}

/// 词法规范化：把 `.` 与 `..` 段按词法折叠（**不碰盘**）。
///
/// 回 `None` 只表示一件事：**相对路径爬到了根之上**（`..` 比已见过的普通段还多）
/// —— 那正是越界，故与 `Some` 分开表达，不静默丢掉多出来的 `..`。
///
/// 绝对路径爬到根之上（如 `/../x`）**不是**越界：POSIX 里 `/..` 就是 `/`，
/// 故根之上仍是根，多出来的 `..` 忽略掉，结果照样以根开头。
fn 词法规范化(路径: &Path) -> Option<PathBuf> {
    let mut 是绝对 = false;
    let mut 段表: Vec<OsString> = Vec::new();
    for 路径段 in 路径.components() {
        match 路径段 {
            Component::Prefix(前缀) => 段表.push(前缀.as_os_str().to_owned()),
            Component::RootDir => 是绝对 = true,
            Component::CurDir => {}
            Component::ParentDir => {
                if 段表.pop().is_none() && !是绝对 {
                    return None;
                }
            }
            Component::Normal(名) => 段表.push(名.to_owned()),
        }
    }
    let mut 折叠结果 = PathBuf::new();
    if 是绝对 {
        折叠结果.push(Component::RootDir.as_os_str());
    }
    for 一段 in 段表 {
        折叠结果.push(一段);
    }
    Some(折叠结果)
}
