//! 报文边界校验 —— 跨源副作用请求防护（审计发现2 · P1）。
//!
//! # 它挡的是什么（且**只**挡什么）
//!
//! 回环口不做鉴权（`接口面形状.md` §一「第一次用不需要读文档就能调对」），而**不做 CORS ≠ 拒绝
//! 跨源请求**：浏览器允许访问回环服务时，别的站点可以替用户发一条写请求（CSRF）。故在**协议层**
//! 加一道**形状校验**（不是鉴权）：
//!
//! | 条件 | 结果 |
//! |---|---|
//! | `Host` 带值且非本机（`127.0.0.1` / `localhost` / `[::1]`，端口任意） | 拒（400） |
//! | `Origin` 带值且非本机 | 拒（400） |
//! | **无 `Origin`**（命令行 / 脚本） | **照旧放行** |
//! | 收体端点（副作用 JSON 端点）的 `Content-Type` 不是 `application/json` | 拒（400） |
//!
//! # 三条纪律
//!
//! 1. **不加鉴权** —— 不要求先拿 token（产品约定不动），只多一层形状校验。
//! 2. **不推 `Origin` 就是同源 / 非浏览器** —— 命令行 `curl` / 本仓的 `urllib` 客户端都不发
//!    `Origin`，它们一律放行；被挡住的只有「浏览器替**别的站点**发的」那一类。
//! 3. **拒一律 400**（协议层），不是 5xx、不是业务错误对象 —— 请求形状不合法是协议层的事
//!    （`分发.rs` 文件头那张表）。
//!
//! 依据：`README.md` §十 同族纪律「边界不许替调用方猜」——外源形状的请求不能当本机请求执行。

use crate::报文读写::报文;

/// 副作用端点要的唯一内容类型。`; charset=…` 后缀**容忍**（浏览器与 `fetch` 默认会带）。
const 应用JSON: &str = "application/json";

/// 本机回环认的站点名（不带端口）。IPv6 的 `::1` **两种写法都认**（方括号是 URL 要求，
/// 裸写是 `Host` 头的另一种常见形状）。
const 本机站点名: [&str; 3] = ["127.0.0.1", "localhost", "::1"];

/// 校验一条报文的边界。**通过给 `Ok(())`，不通过给一句可读说明**（⇒ 400）。
///
/// `收体` = 本端点收不收报文体（[`crate::端点路由::端点::收体`]）—— 只有收体的端点才判
/// `Content-Type`：`GET` 不带体，没有内容类型可言，拿它判就是给不存在的标的值提要求。
pub(crate) fn 校验边界(报文: &报文, 收体: bool) -> Result<(), String> {
    // ① `Host` 非本机 ⇒ 拒。空 `Host` 不判：本面不做连接管理，也不替调用方补它。
    if !报文.主机.is_empty() && !是本机站点(&报文.主机) {
        return Err(format!(
            "Host 头指的不是本机（{}）—— 本面只监听回环，也只接受点向本机的请求。\
             本机写法：127.0.0.1 / localhost / [::1]（端口任意）。",
            报文.主机
        ));
    }
    // ② `Origin` 带值且非本机 ⇒ 拒（跨源副作用请求）。**无 `Origin` 一律放行**（命令行 / 脚本）。
    if !报文.来源站点.is_empty() && !是本机站点(&报文.来源站点) {
        return Err(format!(
            "Origin 头指的不是本机（{}）—— 浏览器替**别的站点**发的副作用请求一律拒。\
             命令行 / 脚本不发 Origin，照旧放行（本面不加鉴权）。",
            报文.来源站点
        ));
    }
    // ③ 收体端点严格 `application/json`（`; charset=…` 后缀容忍）。
    if 收体 && 取主类型(&报文.内容类型) != 应用JSON {
        return Err(format!(
            "Content-Type 必须是 {应用JSON}（可选 `; charset=…`）—— 实际是「{}」；\
             发副作用请求就要声明它是 JSON，不能拿 text/plain 包一份 JSON 体。",
            if 报文.内容类型.is_empty() {
                "（缺 Content-Type）"
            } else {
                报文.内容类型.as_str()
            }
        ));
    }
    Ok(())
}

/// 判一块站点文本（`Host` 头或 `Origin` 头）指的是不是本机回环。
///
/// `Origin` 的形状是 `<方案>://<主机>[:端口]`（`https://attacker.example`）；
/// `Host` 的形状是 `<主机>[:端口]`（`127.0.0.1:43110`）。两者**先剥方案、再剥路径、再剥端口**，
/// 剩下的主机段拿 [`本机站点名`] 逐项比。
fn 是本机站点(站点文本: &str) -> bool {
    let 站点文本 = 站点文本.trim();
    // 剥方案（`http://` / `https://`）：只认这两条 —— `Origin` 只有这两种方案。
    let 余下 = 站点文本
        .strip_prefix("http://")
        .or_else(|| 站点文本.strip_prefix("https://"))
        .unwrap_or(站点文本);
    // 剥路径（`http://主机/随便`）：取第一个 `/` 之前那一段。
    let 权限段 = 余下.split('/').next().unwrap_or(余下);
    let 主机段 = 去端口(权限段);
    本机站点名.iter().any(|候选项| 主机段.eq_ignore_ascii_case(候选项))
}

/// 从「主机[:端口]」里剥掉端口与 IPv6 的方括号 ⇒ 主机段（比较用）。
///
/// `[::1]:43110` → `::1` · `127.0.0.1:43110` → `127.0.0.1` · `attacker.example` → `attacker.example`。
/// **只按位置剥**：方括号在就有闭括号，没有就取第一个 `:` 之前那一段（IPv6 主机段里的 `:` 都在方括号内）。
fn 去端口(权限段: &str) -> &str {
    if let Some(内层起) = 权限段.strip_prefix('[') {
        let 闭括号位 = 内层起.find(']').map_or(内层起.len(), |位置| 位置);
        return &内层起[..闭括号位];
    }
    权限段.split(':').next().unwrap_or(权限段)
}

/// 取内容类型的主类型（`application/json; charset=utf-8` → `application/json`）。
///
/// 分号之后是参数（`charset` 等），与媒体类型无关 ⇒ 只比**分号之前**那一段，且**大小写不敏感**
/// （HTTP 媒体类型大小写不敏感）。
fn 取主类型(内容类型: &str) -> &str {
    内容类型.split(';').next().unwrap_or("").trim()
}
