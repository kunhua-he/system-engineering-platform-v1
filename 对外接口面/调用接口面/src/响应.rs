//! 响应组装 —— 每个端点返回什么，**逐字照 `项目文档/设计文档/接口面形状.md`**。
//!
//! 这是本 crate 里唯一「有形状」的地方：端点的返回体是**冻结项**，只许新增旁路字段。
//! 每个函数的返回值都逐条对着冻结件那一节写，注释里点明对着哪一节。
//!
//! # 一次返回必须同时回答三件事（§三 的判据）
//!
//! | 问 | 答在哪 |
//! |---|---|
//! | 成功没成功 | `成功` 逻辑型，不靠猜、不靠异常 |
//! | 拿到什么 | `值` 数组，每项自带 `类型标签`，不需要二次解析 |
//! | 失败为什么 | `错误.码`，且四项登记随包带回 |
//!
//! **判据**：把这个返回原文直接喂给另一个 agent，它不需要额外上下文就能决定下一步做什么。
//! 所以根端点（`GET /接口`）本身就是说明书：`端点` 表 + `能力` 全量清单 + `契约版本`
//! + `端口来源`，一次给全，不留下「还得再读一份文档」这一步。
//!
//! 第一行（「成功没成功」）**要读返回槽**：执行函数把业务失败写在槽里，`转发结果::成功`
//! 只担保协议层成立 —— 见 [`组装应答`] 的注释（那是本文件的判据落点）。

use crate::协议值::协议值;
use crate::常量::{端点表, 端口来源, 旁路端点表};
use crate::槽编码;
use crate::错误形状::{self, 错误对象};
use crate::请求::调用请求;
use v1_adapter::{适配器, 版本三元组, 转发结果};

/// `GET /接口` → 自描述根（§三）。
///
/// `契约版本` 与 `声明格式号` 从**注入的声明**上现读（网关在构造时取下的标量快照，
/// 见 `网关.rs::服务::契约身份`）。为什么不直接存 `&'static 平台信息`：那个引用带裸指针、
/// 不是 `Sync`，会让 `服务` 不能跨线程共享（并发收连接要的正是共享 `服务`）；
/// 声明是静态只读的 ⇒ 标量快照与现读等价。两者都不另存第二份事实。
///
/// `实际端口` 是**旁路字段**（冻结件允许新增）：报的是**真正绑上的端口**，不是常量。
/// 为什么值得加：判据是「第一次用不需要读文档就能调对」，而「端口在哪」正是那件
/// 不读文档会卡住的事；报常量会在测试与多实例下报出一个**假事实**。
pub fn 自描述根(
    契约版本: &版本三元组,
    声明格式号: u32,
    适配器: &适配器,
    实际端口: u16,
) -> 协议值 {
    let 版本 = 契约版本;
    协议值::对象值(vec![
        (
            "契约版本".to_owned(),
            协议值::对象值(vec![
                ("主".to_owned(), 协议值::整数项(i64::from(版本.主版本))),
                ("次".to_owned(), 协议值::整数项(i64::from(版本.次版本号))),
                ("构建".to_owned(), 协议值::整数项(i64::from(版本.构建))),
            ]),
        ),
        (
            "声明格式号".to_owned(),
            协议值::整数项(i64::from(声明格式号)),
        ),
        ("端口来源".to_owned(), 协议值::文本值(端口来源.to_owned())),
        (
            "实际端口".to_owned(),
            协议值::整数项(i64::from(实际端口)),
        ),
        (
            "端点".to_owned(),
            协议值::数组值(
                端点表
                    .iter()
                    .map(|(请求方法, 路径, 说明文字)| {
                        协议值::对象值(vec![
                            ("方法".to_owned(), 协议值::文本值((*请求方法).to_owned())),
                            ("路径".to_owned(), 协议值::文本值((*路径).to_owned())),
                            ("说明".to_owned(), 协议值::文本值((*说明文字).to_owned())),
                        ])
                    })
                    .collect(),
            ),
        ),
        // **旁路端点**（§七 工具族）—— 与 `端点` 分开一个键，因为 §二 那张四个端点的表是
        // **冻结项**（冻结项只许新增旁路字段、不许改旧字段含义）：把新端点塞进 `端点` 数组
        // 就是改了那张表的含义。分开之后，只读 `端点` 的旧读者读到的东西**逐字不变**，
        // 而第一次用的人照样一次拿全（判据：根端点自身就是说明书）。
        (
            "旁路端点".to_owned(),
            协议值::数组值(
                旁路端点表
                    .iter()
                    .map(|(请求方法, 路径, 说明文字)| {
                        协议值::对象值(vec![
                            ("方法".to_owned(), 协议值::文本值((*请求方法).to_owned())),
                            ("路径".to_owned(), 协议值::文本值((*路径).to_owned())),
                            ("说明".to_owned(), 协议值::文本值((*说明文字).to_owned())),
                        ])
                    })
                    .collect(),
            ),
        ),
        (
            "能力".to_owned(),
            // **全量**，不是首页（§三：未载入的扩展其能力不在表里；不做分页）。
            // 清单是**当场**从适配器取的 —— 与调侧同一个入口，不另存一份表。
            协议值::数组值(
                适配器
                    .能力清单()
                    .iter()
                    .map(|能力摘要| {
                        协议值::对象值(vec![
                            ("编号".to_owned(), 协议值::整数项(i64::from(能力摘要.编号))),
                            ("名称".to_owned(), 协议值::文本值(能力摘要.名称.clone())),
                            (
                                "参数个数".to_owned(),
                                协议值::整数项(i64::from(能力摘要.参数个数)),
                            ),
                            (
                                "返回类型".to_owned(),
                                协议值::整数项(i64::from(能力摘要.返回类型)),
                            ),
                        ])
                    })
                    .collect(),
            ),
        ),
    ])
}

/// `GET /接口/能力/<编号>` → 单条能力的完整契约（§二：参数表**行序即契约** · 返回表 ·
/// 可抛错误码）。
///
/// 未命中的号**不是 404**：路径是存在的、请求也是合法的，是**这个号没人认领**。
/// 按 §三 的失败形状给 `成功: false` + `码 1 提供者未载入` —— 与调侧同一个段位，
/// 读侧与调侧同一条路（宪法第 6 条：未命中返回空，不是报错）。
pub fn 能力契约(适配器: &适配器, 编号: u32) -> 协议值 {
    let Some(契约) = 适配器.能力契约(编号) else {
        return 造失败应答(&错误对象::由错误码(适配器, 编号, 错误形状::码值::提供者未载入), None);
    };
    协议值::对象值(vec![
        ("成功".to_owned(), 协议值::真值),
        (
            "契约".to_owned(),
            协议值::对象值(vec![
                ("编号".to_owned(), 协议值::整数项(i64::from(契约.编号))),
                ("名称".to_owned(), 协议值::文本值(契约.名称)),
                ("说明".to_owned(), 协议值::文本值(契约.说明文字)),
                (
                    "参数表".to_owned(),
                    协议值::数组值(
                        契约
                            .参数表
                            .iter()
                            .map(|入参| {
                                协议值::对象值(vec![
                                    ("名称".to_owned(), 协议值::文本值(入参.名称.clone())),
                                    (
                                        "类型标签".to_owned(),
                                        协议值::整数项(i64::from(入参.类型标签)),
                                    ),
                                    ("状态位".to_owned(), 协议值::整数项(i64::from(入参.状态位))),
                                    ("默认值".to_owned(), 槽编码::到协议值(&入参.默认值)),
                                ])
                            })
                            .collect(),
                    ),
                ),
                (
                    "返回类型".to_owned(),
                    协议值::整数项(i64::from(契约.返回类型)),
                ),
                (
                    "可抛错误码".to_owned(),
                    协议值::数组值(
                        契约
                            .可抛错误码
                            .iter()
                            .map(|错误码| {
                                错误对象 {
                                    码值: 错误码.码值,
                                    // `段位` 是旁路项：适配器的 `错误码摘要` 没给这一项，
                                    // 按契约口径 `段位 = 码 / 号段类宽度` 导出（见 `错误形状.rs`）。
                                    段位: 错误码.码值 / crate::常量::号段类宽度,
                                    名称: 错误码.名称.clone(),
                                    可重试: 错误码.可重试,
                                    可自愈: 错误码.可自愈,
                                    需人工: 错误码.需人工,
                                    已登记: true,
                                }
                                .到协议值()
                            })
                            .collect(),
                    ),
                ),
            ]),
        ),
    ])
}

/// `POST /接口/调用` → 结构化结果（§三）。
///
/// **所有请求都转调适配器**：本函数不取号、不校参数、不问配额 ——
/// 那四件事（超时 · 配额 · 占位兜底 · 已废止判定）只有一份实现，在调度层。
/// 这里只做三件形状翻译：入参 JSON → 槽（`请求.rs`），返回槽 → JSON（`槽编码.rs`），
/// 组装完后**把返回槽归还**（带所有权交出的堆块真回收 —— 审计发现 1，见下）；
/// 「成功没成功」的判定在 [`组装应答`]（那里要读返回槽，见它的文件注释）。
pub fn 调用(适配器: &适配器, 请求: &调用请求) -> 协议值 {
    let 数据槽: Vec<v1_adapter::数据槽> = 请求.值.iter().map(crate::槽编码::槽源::取槽).collect();
    let mut 返回槽 = v1_adapter::数据槽::空槽();
    let 区间起点 = std::time::Instant::now();
    let 调用读数 = 适配器.调用能力(请求.编号, &数据槽, &mut 返回槽);
    let 耗时微秒 = 区间起点.elapsed().as_micros().min(u128::from(u64::MAX)) as u64;
    let 应答 = 组装应答(适配器, 请求.编号, 调用读数, 耗时微秒);
    // **响应组装完成后真回收返回槽**（审计发现 1）：响应路径与 `平台_释放值` 走**同一个**
    // 回收口（`v1_adapter::归还槽值`）。此时字节已由 `槽编码::到协议值` 读进应答（字节集走
    // base64）⇒ 堆块不再需要。带所有权交出的引用槽若不清，每调一次返字节集的能力就泄一块。
    // `返回槽` 是本函数的局部量 ⇒ 本函数就是它的所有者，在这里回收是「谁分配谁释放」。
    // 这一处同时覆盖成功与失败两支：超时那支（`调度核心.rs` 不清返回槽）也会留下带所有权的槽。
    // 非引用槽（错误槽 / 内联槽 / 静态无所有权槽）不命中回收分支，幂等且不二次释放。
    v1_adapter::归还槽值(&mut 返回槽);
    应答
}

/// 把一次**转发结果**组装成顶层返回 —— **「成功没成功」由这里判**。
///
/// §三 的判据是「成功没成功 —— `成功` 逻辑型，不靠猜」（`项目文档/设计文档/接口面形状.md`）。
/// 而执行函数把业务失败**写在返回槽里**（`类型标签 = 错误（4294967295）` · `值 = 4 位码`；
/// 三处同形：`运行内核/统一注册表/src/占位项.rs` · `跨语言适配/适配器实现/src/边界面.rs` ·
/// `编译器支持库/src/lib.rs::写错误码`），适配器的 `转发结果::成功` 只担保**协议层**成立。
/// ⇒ 顶层 `成功` 必须**读槽**：是错误槽就按失败组装（六项从声明现读，同 `造失败应答` 那一支）。
/// 只认 `转发结果::失败` 就会把「转发成功、返回槽是错误槽」报成 `成功: true` —— 与 §三 直接相抵。
pub(crate) fn 组装应答(适配器: &适配器, 被调号: u32, 调用读数: 转发结果, 耗时微秒: u64) -> 协议值 {
    match 调用读数 {
        转发结果::成功(数据槽) => match 错误槽的码(&数据槽) {
            Some(错误码) => 造失败应答(&错误对象::由错误码(适配器, 被调号, 错误码), Some(耗时微秒)),
            None => 协议值::对象值(vec![
                ("成功".to_owned(), 协议值::真值),
                (
                    "值".to_owned(),
                    协议值::数组值(vec![槽编码::到协议值(&数据槽)]),
                ),
                ("耗时微秒".to_owned(), 耗时(耗时微秒)),
            ]),
        },
        转发结果::失败(错误) => 造失败应答(
            &错误对象::由调度错误(适配器, 被调号, 错误),
            Some(耗时微秒),
        ),
    }
}

/// 返回槽是不是**错误槽**？是则给出它带的 4 位错误码（`段位 × 1000 + 序号`）。
///
/// 错误槽一律是**内联**的 `(类型标签 = 错误, 值 = 码)`（三处写方同形，见 [`组装应答`] 的注释），
/// 故只看类型标签：`值` 超出 32 位即槽写坏了 —— **仍判失败**（坏槽不许当成功），
/// 码报 `0`（未登记）把缺陷暴露在返回里，不编一个名字（`错误形状.rs` 文件头：取不到登记时不编名字）。
fn 错误槽的码(数据槽: &v1_adapter::数据槽) -> Option<u32> {
    if 数据槽.类型标签 != crate::常量::类型标签::错误 {
        return None;
    }
    Some(u32::try_from(数据槽.槽值).unwrap_or(0))
}

/// `POST /接口/声明` → **未实现**（结构化错误，不硬凑一个落盘实现）。
///
/// 为什么不在调用接口面里实现：写声明 = **面校验 + 落盘**，是独立的一件活
/// （`对外接口面/声明编写面/`）。在这里写一个「差不多能用」的落盘就是**第二条腿** ——
/// 两套实现必然分叉，而 `契约声明/` 只能有一个写入口（`接口面形状.md` §四 硬规则 1）。
///
/// 形状照 §四 的**面校验失败**：`成功: false` + `校验[]`，每项说清
/// `项 · 缺什么 · 为什么不能自愈`。§四 明令「`为什么不能自愈` 不许写『需要人工确认』
/// 这种废话」，所以这里写的是**挡住自动补全的那一个事实**：没有落盘实现，而落盘不是
/// 本端点能自愈的（自愈要写文件，写文件就是声明编写面的职责）。
pub fn 声明未实现() -> 协议值 {
    let 造校验项 = |项名: &str, 缺什么: &str, 为什么: &str| {
        协议值::对象值(vec![
            ("项".to_owned(), 协议值::文本值(项名.to_owned())),
            ("缺什么".to_owned(), 协议值::文本值(缺什么.to_owned())),
            ("为什么不能自愈".to_owned(), 协议值::文本值(为什么.to_owned())),
        ])
    };
    协议值::对象值(vec![
        ("成功".to_owned(), 协议值::假值),
        (
            "校验".to_owned(),
            协议值::数组值(vec![造校验项(
                "声明编写面（本端点）",
                "落盘实现：本端点本轮只返回「未实现」，没有把 正文 写进 契约声明/ 的那条腿。\
                 端点 · 请求体形状（类别 · 编号 · 正文）已按 接口面形状.md §四 就位，缺的是面校验与落盘。",
                "声明编写面是独立的一个节点（对外接口面/声明编写面/）；在调用接口面里补一个落盘\
                 就是同一件事的第二套实现，而 契约声明/ 只许有一个写入口（接口面形状.md §四 硬规则 1）。\
                 本端点也不许替调用方分配 编号：自动分配只从该层号段的空洞里取，那要读 号段图.json，\
                 而那份布局不进 平台信息、适配器公开面也拿不到。",
            )]),
        ),
    ])
}

/// 造失败应答（§三）：`成功: false` + `错误` 六项 + `耗时微秒`。
fn 造失败应答(错误: &错误对象, 耗时微秒: Option<u64>) -> 协议值 {
    let mut 对象成员 = vec![
        ("成功".to_owned(), 协议值::假值),
        ("错误".to_owned(), 错误.到协议值()),
    ];
    if let Some(微秒) = 耗时微秒 {
        对象成员.push(("耗时微秒".to_owned(), 耗时(微秒)));
    }
    协议值::对象值(对象成员)
}

fn 耗时(微秒: u64) -> 协议值 {
    match i64::try_from(微秒) {
        Ok(整数值) => 协议值::整数项(整数值),
        Err(_) => 协议值::无符号值(微秒),
    }
}
