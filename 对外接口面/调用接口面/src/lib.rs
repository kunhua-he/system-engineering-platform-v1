//! 调用接口面 —— **全平台唯一的对外门**（`全局连接器与网关.md` 里的「全局网关」）。
//!
//! 职责只有两件：**协议翻译**（HTTP/JSON ↔ 定长槽）+ **转调适配器**。它**自己不做业务判断**。
//!
//! # 拓扑位置（`全局连接器与网关.md` 第二节）
//!
//! ```text
//! 前端呈现（纯 UI）── 同源相对路径 ──▶ 本面 ──唯一腿──▶ 跨语言适配/适配器实现 ──▶ 运行内核
//! ```
//!
//! 三条不许，本 crate 逐条守住：
//!
//! 1. **不许跳层**：本 crate 的 `[dependencies]` 只有 `v1-adapter` 一条边
//!    （相邻两层、方向向下）。不依赖 `契约声明/` · `运行内核/` —— 那会跳过中间层，
//!    而「第二条腿的真身就是跳过中间层」。
//! 2. **不许绕过适配器直连内核或扩展**：`能力清单` · `能力契约` · `调用能力` 三个口
//!    **一律复用**，本 crate 不另存一份能力表、不自己取号、不自己校参数、不自己问配额。
//! 3. **不做第二个对外门**：本 crate 里 `TcpListener::bind` 恰好 1 处（`网关.rs`）。
//!
//! # 端到端形状（冻结件 `项目文档/设计文档/接口面形状.md`）
//!
//! 四个端点，一个不多一个不少：
//!
//! | 方法 | 路径 | 做什么 |
//! |---|---|---|
//! | `GET` | `/接口` | 自描述根：端点表 + 能力总清单 + 契约版本 + 端口来源 |
//! | `GET` | `/接口/能力/<编号>` | 单条能力的完整契约：参数表（行序即契约）· 返回表 · 可抛错误码 |
//! | `POST` | `/接口/调用` | 体 `{"编号":N,"值":[{类型标签,值},…]}` → 结构化结果 |
//! | `POST` | `/接口/声明` | **本轮未实现**（结构化错误点名这件事；见 `响应::声明未实现`） |
//!
//! **业务失败一律 HTTP 200 + `"成功": false` + 结构化错误对象**（六项：码 · 段位 · 名称 ·
//! 可重试 · 可自愈 · 需人工）。**不许抛 HTTP 5xx** —— 失败是可编程处理的数据，
//! 塞进状态码就等于让调用方去解析协议层。HTTP 状态码只表达「请求本身合不合法」。
//!
//! # 文件分工（本文件是路由：声明子模块 · 再导出公开面 · 零实现）
//!
//! - `网关.rs` —— 唯一的对外监听 · 手写 HTTP/1.1 · 启动与应答循环
//! - `路由.rs` —— 方法与路径 → 端点（纯形状，含百分号编码的路径）
//! - `分发.rs` —— 四个端点的分发 + HTTP 状态码的口径
//! - `请求.rs` —— `POST /接口/调用` 的体 → 编号 + 按行序的槽源
//! - `响应.rs` —— 每个端点返回什么（逐字照冻结件）
//! - `槽编码.rs` —— 协议形状 ↔ 定长数据槽（本 crate 唯一的 `unsafe` 在它里面）
//! - `错误形状.rs` —— 调度段位 → 六项错误对象 · 协议层失败的形状
//! - `常量.rs` —— 契约级常量（**四处占位**，缺口逐条登记在它的文件头）
//! - `协议值.rs` · `协议解析.rs` · `协议写出.rs` · `转码.rs` —— 手写的 JSON 与 base64
//!
//! # 缺口（如实登记，不假装覆盖了）
//!
//! 1. **契约常量到不了运行期**（四处：`接口端口` · `号段类宽度` · 类型标签语义 ·
//!    `调度错误 → 错误码`）。四处占位都写在 `常量.rs` 与 `错误形状.rs` 的文件头，
//!    每处都写明「待生成物/适配器出什么之后改成引用」。修法在生成链与适配器公开面。
//! 2. **适配器没有释放口**：返回槽若带 `槽标志::所有权交出`，内存归调用方，但适配器
//!    公开面没有 `平台_释放值` 那个口，网关不许自己去调内存分配器（跳层）。
//!    实测路径上（底座命令 0）返回的是静态指针、未交出所有权，故当前不泄漏。
//! 3. **适配器不是 `Send` / `Sync`**：所以本轮的 accept 循环是单线程的（见 `网关.rs` 文件头）。
//!    网关不许替下层 `unsafe impl Sync` 担保。
//! 4. **生产启动入口未接**：网关要的声明根由**调用方注入**（`服务::绑定`），
//!    「谁把底座声明递进来」属装配与扩展装载那条腿。本 crate 不自己去取声明 ——
//!    自己去找就是跳层。

