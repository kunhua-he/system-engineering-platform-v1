//! 依赖序装载的判据（台账 C04）：多趟拓扑序 · 有界零进展 · 硬失败不重试。
//!
//! 本件**不碰真扩展**：试装是闭包、声明只当不透明句柄 ⇒ 拿 `底座声明()` 当句柄，
//! 落点串区分身份（本件算法不读声明内容）。这样测的是**算法本身**，不是装载器。
//!
//! 为什么必须有这一件：台账 C04 的缺口正是「两条路的拓扑保证不等价」——
//! 热装载侧原先一趟定论（缺依赖当场剔除）。本条样本里「依赖者排在依赖者之前」
//! 的用例就是那个缺口的**反证**：一趟定论会把它误剔除。

use crate::依赖序装载::{按依赖序装载, 试装结局};

/// 造候选表：全部用同一个声明句柄，靠落点串区分身份。
fn 造候选表(落点表: &[&str]) -> Vec<(&'static v1_adapter::平台信息, String)> {
    落点表.iter().map(|落点| (v1_adapter::底座声明(), (*落点).to_owned())).collect()
}

/// **依赖者排在依赖者之前**也要装上：一趟定论会误剔除，多趟才能等来依赖。
#[test]
fn 依赖序_依赖在后仍能装上() {
    let 待装候选表 = 造候选表(&["依赖者", "被依赖者"]);
    let mut 已装表: Vec<String> = Vec::new();
    let 装载结果 = 按依赖序装载(
        待装候选表,
        &mut |_, 落点| {
            if 落点 == "依赖者" && !已装表.iter().any(|已装项| 已装项 == "被依赖者") {
                return 试装结局::缺依赖;
            }
            已装表.push(落点.to_owned());
            试装结局::装上
        },
        "缺依赖：依赖不在扩展根里",
    );
    assert_eq!(
        装载结果.装上,
        vec!["被依赖者".to_owned(), "依赖者".to_owned()],
        "拓扑序：依赖者排在前面也要等被依赖者先装上"
    );
    assert!(装载结果.剔除.is_empty(), "两条最终都装上了，不许有剔除");
}

/// 整趟零进展 ⇒ 立即停（不空转），残留一律按缺依赖报出（**不静默丢**）。
#[test]
fn 依赖序_整趟零进展不空转() {
    let 待装候选表 = 造候选表(&["等门禁的", "等索引的"]);
    let mut 试装趟数 = 0;
    let 装载结果 = 按依赖序装载(
        待装候选表,
        &mut |_, _| {
            试装趟数 += 1;
            试装结局::缺依赖
        },
        "缺依赖：依赖不在扩展根里",
    );
    assert_eq!(试装趟数, 2, "零进展即停：只试装一趟（2 条），不空转第二趟");
    assert_eq!(装载结果.剔除.len(), 2, "残留两条都报出，不静默丢");
    assert!(
        装载结果.剔除.iter().all(|(_, 失败原因)| 失败原因.contains("依赖不在扩展根里")),
        "零进展残留的原因串用调用方给的那句"
    );
    assert!(装载结果.装上.is_empty());
}

/// 硬失败（形状不符 · 号段冲突 · 候选未发布…）**当场定论，不重试**。
#[test]
fn 依赖序_硬失败不重试() {
    let 待装候选表 = 造候选表(&["坏的", "好的"]);
    let mut 试装趟数 = 0;
    let 装载结果 = 按依赖序装载(
        待装候选表,
        &mut |_, 落点| {
            试装趟数 += 1;
            if 落点 == "坏的" {
                试装结局::硬失败("形状不符".to_owned())
            } else {
                试装结局::装上
            }
        },
        "缺依赖：依赖不在扩展根里",
    );
    assert_eq!(试装趟数, 2, "硬失败当场定论：一趟就够，不许再试一遍");
    assert_eq!(装载结果.剔除, vec![("坏的".to_owned(), "形状不符".to_owned())]);
    assert_eq!(装载结果.装上, vec!["好的".to_owned()]);
}

/// 已在与切换**各归各类**（不归到装上，也不归到剔除）。
#[test]
fn 依赖序_已在与切换各归一类() {
    let 待装候选表 = 造候选表(&["已装的", "要换的"]);
    let 装载结果 = 按依赖序装载(
        待装候选表,
        &mut |_, 落点| {
            if 落点 == "已装的" {
                试装结局::已在
            } else {
                试装结局::切换 { 物理回收: true }
            }
        },
        "缺依赖：依赖不在扩展根里",
    );
    assert_eq!(装载结果.已在, vec!["已装的".to_owned()]);
    assert_eq!(装载结果.切换, vec![("要换的".to_owned(), true)], "切换要带物理回收读数");
    assert!(装载结果.装上.is_empty() && 装载结果.剔除.is_empty());
}
