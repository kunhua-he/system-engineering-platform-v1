//! 生命周期响应 · 就绪读数 —— 一份 `GET /接口/生命周期` 读什么、怎么判「可用」。
//!
//! 从 `生命周期响应.rs` 拆出（单源 ≤ 500 行 · 拆法按关注点）：本件只回答**读数**
//! （已装载声明数 / 通知端点数 / 已注册标识串 / 技能账 / 逐份就绪），不碰装载与卸载。
//!
//! # 就绪口径只有一条
//!
//! 「这份到底可不可用」不看装载成功，只看**当场**能力清单里有没有它号段内的号
//! （§32.2 装载成功 ≠ 目标可用）。号段为空（技能 / 无命令的模块）⇒ 如实报
//! `无号段无从判`，**不编 false**（§32.4）。

use std::path::Path;
use std::time::Instant;

use v1_adapter::适配器;

use super::判定层级::{判定层级, 接入回执};
use crate::协议值::协议值;
use crate::工具响应::{造成功应答, 造键文对};

/// `GET /接口/生命周期` → 就绪/健康读数。
///
/// 读数取自**生命周期那本账**（通知端点表）与已装载声明表，不是另存一份健康表：
/// 端点表就是「哪些扩展收得到生命周期通知」的唯一事实源。
pub(crate) fn 读数(适配器: &适配器, 工具根: &Path) -> 协议值 {
    let 区间起点 = Instant::now();
    let mut 本扩展标识串: Vec<协议值> = 适配器
        .通知端点标识串()
        .into_iter()
        .map(协议值::文本值)
        .collect();
    // **模块也要点名**：模块没有通知端点（它不是支持库声明），但「登记了必须看得见」——
    // 不补这一段，装了 10 个模块的实例读出来就是「已注册标识串 0」。
    本扩展标识串.extend(
        适配器
            .取模块读面()
            .into_iter()
            .map(|读面项| 协议值::文本值(读面项.标识串)),
    );
    // §32.2：装载成功 ≠ 目标可用。就绪读数的真承重点在**逐份声明**：装的是哪一版、
    // 占哪几段号、号段内有没有号真可寻址。数据只从适配器现读（不另存一份表）。
    let 已可寻址号: Vec<u32> = 适配器
        .能力清单()
        .iter()
        .map(|能力摘要项| 能力摘要项.编号)
        .collect();
    let mut 逐份就绪: Vec<协议值> = 适配器
        .声明就绪表()
        .into_iter()
        .map(|就绪读数| 声明就绪项(&就绪读数, &已可寻址号))
        .collect();
    // 模块与支持库**同一份就绪口径**：号段由制品段 16 的能力号逐个成段（每个号一段），
    // 「是否可用」仍看同一份 `已可寻址号`（那份就是 `能力清单` 的号集）。
    逐份就绪.extend(
        适配器
            .取模块读面()
            .iter()
            .map(|读面项| 模块就绪项(读面项, &已可寻址号)),
    );
    造成功应答(
        协议值::对象值(vec![
            (
                "已装载声明数".to_owned(),
                协议值::无符号值(适配器.已装载声明数() as u64),
            ),
            (
                "通知端点数".to_owned(),
                协议值::无符号值(u64::from(适配器.通知端点数())),
            ),
            ("已注册标识串".to_owned(), 协议值::数组值(本扩展标识串)),
            // 三类扩展里唯一「不执行」的那一类：技能没有码段、不进 dlopen，也**不进能力清单**
            // （它不是可调能力）。但「登记了必须看得见」——按段 19 可读与否逐条列出。
            (
                "技能账".to_owned(),
                协议值::数组值(crate::工具响应::列技能读面(工具根)),
            ),
            // 旁路字段（§32.2 就绪判定 + §22.4 装载成功≠目标可用）：
            // 逐份声明的身份/版本/号段，带「这份到底可不可用」的机器可判位。
            ("逐份就绪".to_owned(), 协议值::数组值(逐份就绪)),
            (
                "跨进程登记数".to_owned(),
                协议值::无符号值(适配器.跨进程登记数() as u64),
            ),
            (
                "跨进程运行数".to_owned(),
                协议值::无符号值(适配器.跨进程运行数() as u64),
            ),
            // 旁路字段（§22.4 五级区分）：本地自检 ≠ 构建 ≠ 准入 ≠ 就绪 ≠ 调用成功。
            ("判定层级".to_owned(), 判定层级(适配器)),
            // 旁路字段（方案 §27 十二类接入回执）：小事也必须交代清楚 ——
            // 逐类给「已判 · 说明 · 证据口」，不把「本面判不了」当成真或假。
            ("接入回执".to_owned(), 接入回执(适配器, &已可寻址号)),
        ]),
        &区间起点,
    )
}

/// 一份声明的就绪读数 → JSON：身份（标识串 + 版本三元组）· 能力号段 · `是否可用` 位。
///
/// `是否可用` 取**一条不会假报的判据**（照 `工具响应_扩展.rs` 已用过的那条）：本份声明的
/// 能力号段里有没有号真出现在**当场**的能力清单里。号段为空（技能 / 无命令的模块）⇒
/// 本面无从判它装没装，如实报 `无号段无从判` 第三个值，**不编 false**
/// （§32.4：能力不存在与暂时未就绪要分得开）。
fn 声明就绪项(就绪读数: &v1_adapter::声明就绪, 已可寻址号: &[u32]) -> 协议值 {
    let 号段内可寻址号数: usize = 就绪读数
        .能力号段
        .iter()
        .map(|号段项: &[u32; 2]| {
            已可寻址号
                .iter()
                .filter(|编号| **编号 >= 号段项[0] && **编号 <= 号段项[1])
                .count()
        })
        .sum();
    let (是否可用, 就绪判据) = if 就绪读数.能力号段.is_empty() {
        (false, "无号段无从判")
    } else if 号段内可寻址号数 == 0 {
        (false, "号段内无一号可寻址")
    } else {
        (true, "号段内有号可寻址")
    };
    协议值::对象值(vec![
        造键文对("标识串", &就绪读数.标识串),
        ("版本".to_owned(), 版本项(&就绪读数.实现版本)),
        (
            "能力号段".to_owned(),
            协议值::数组值(就绪读数.能力号段.iter().map(号段对).collect()),
        ),
        (
            "是否可用".to_owned(),
            crate::线上逻辑值::真假值转线上值(是否可用),
        ),
        造键文对("就绪判据", 就绪判据),
        (
            "号段内可寻址号数".to_owned(),
            协议值::无符号值(号段内可寻址号数 as u64),
        ),
    ])
}

/// 一个**模块**的就绪读数 —— 与 [`声明就绪项`] 同形状（键名一字不差），
/// 差别只在号段来源：模块没有 `平台信息`，它的号段就是段 16 里每个能力号各成一段
/// （`[号, 号]`），这样「号段内可寻址号数」与支持库口径可比。
fn 模块就绪项(
    读面项: &v1_adapter::模块读面登记, 已可寻址号: &[u32]
) -> 协议值 {
    let 能力号表: Vec<u32> = 读面项
        .接口说明表
        .iter()
        .map(|接口说明项| 接口说明项.编号)
        .collect();
    let 号段内可寻址号数 = 能力号表
        .iter()
        .filter(|编号| 已可寻址号.contains(编号))
        .count();
    let (是否可用, 就绪判据) = if 能力号表.is_empty() {
        (false, "无号段无从判")
    } else if 号段内可寻址号数 == 0 {
        (false, "号段内无一号可寻址")
    } else {
        (true, "号段内有号可寻址")
    };
    协议值::对象值(vec![
        造键文对("标识串", &读面项.标识串),
        (
            "版本".to_owned(),
            版本项(&v1_adapter::版本三元组 {
                主版本: 读面项.版本.0 as i32,
                次版本号: 读面项.版本.1 as i32,
                构建: 读面项.版本.2 as i32,
            }),
        ),
        (
            "能力号段".to_owned(),
            协议值::数组值(
                能力号表
                    .iter()
                    .map(|编号| {
                        协议值::数组值(vec![
                            协议值::无符号值(u64::from(*编号)),
                            协议值::无符号值(u64::from(*编号)),
                        ])
                    })
                    .collect(),
            ),
        ),
        (
            "是否可用".to_owned(),
            crate::线上逻辑值::真假值转线上值(是否可用),
        ),
        造键文对("就绪判据", 就绪判据),
        (
            "号段内可寻址号数".to_owned(),
            协议值::无符号值(号段内可寻址号数 as u64),
        ),
    ])
}

/// 一段能力号段 `[段起点, 段止]` → JSON 二元数组。
fn 号段对(号段项: &[u32; 2]) -> 协议值 {
    协议值::数组值(vec![
        协议值::无符号值(u64::from(号段项[0])),
        协议值::无符号值(u64::from(号段项[1])),
    ])
}

/// 版本三元组 → JSON 对象（主 · 次 · 构建）。
fn 版本项(版本: &v1_adapter::版本三元组) -> 协议值 {
    协议值::对象值(vec![
        ("主".to_owned(), 协议值::整数项(i64::from(版本.主版本))),
        ("次".to_owned(), 协议值::整数项(i64::from(版本.次版本号))),
        ("构建".to_owned(), 协议值::整数项(i64::from(版本.构建))),
    ])
}
