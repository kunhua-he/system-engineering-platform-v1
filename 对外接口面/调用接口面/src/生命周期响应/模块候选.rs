//! 模块候选身份 —— 从盘上读出一个模块候选的**身份**（标识串 / 版本 / 能力号 / 制品路径）。
//!
//! 从 `生命周期响应.rs` 拆出（单源 ≤ 800 行 · 拆法按关注点）：父件管**装载回执**
//! （装上 / 已在 / 剔除），本件管**候选身份的 fail-closed 判读**。
//!
//! # 五问（**不看编号大小、不按名字认**）
//!
//! 1. 目录内**恰好一个**模块制品（`取模块接口说明` 已判「恰好一个」）；
//! 2. 段指纹与内容相符（`校验模块制品指纹`；`None` = 不是本形状 ⇒ 拒）；
//! 3. 包声明读得出 `标识串` / `实现版本`（身份不是猜的）；
//! 4. 能力声明**恰好一份**，且编号 = 制品段 16 的编号 —— 一个执行体一个能力，
//!    声明含多能力时执行体**没有分派入口** ⇒ 必须明确拒绝（不能把多个号都路由到同一个函数）；
//! 5. 返回类型在当前整槽执行链支持范围内；标签、长度与所有权沿同一IPC传递。

use std::fs;
use std::path::{Path, PathBuf};

use crate::跨进程装配::模块身份;
use crate::模块制品;
use crate::协议值::协议值;

/// 一个模块候选目录 → 它的**身份**，判不过一律给因。
pub(super) fn 模块候选身份(
    模块目录: &Path,
    后缀表: &crate::扫扩展根::后缀表,
) -> Result<模块身份, String> {
    let Some(模块制品后缀) = 后缀表.取种类后缀("模块") else {
        return Err("后缀表没有「模块」一栏：判不了模块制品".to_owned());
    };
    let 模块接口说明 = 模块制品::取模块接口说明(模块目录, 模块制品后缀)?;
    let 指纹相符 = 模块制品::校验模块制品指纹(模块目录, 模块制品后缀)
        .ok_or_else(|| "模块制品不是本形状的包（段指纹读不出）".to_owned())?;
    if !指纹相符 {
        return Err("模块制品段指纹与内容不符（被换过）".to_owned());
    }
    let 依赖表达 = 模块制品::取模块依赖表达(模块目录)?;
    let 能力声明表 = 能力声明编号表(模块目录)?;
    if 能力声明表.len() != 1 {
        return Err(format!(
            "模块声明含 {} 个能力（执行体单入口不分派 ⇒ 本批只支持恰好 1 个）",
            能力声明表.len()
        ));
    }
    if 能力声明表[0] != 模块接口说明.编号 {
        return Err(format!(
            "声明编号 {} 与制品段 16 编号 {} 不符",
            能力声明表[0], 模块接口说明.编号
        ));
    }
    // 与已实证的本机生成形状对齐，非支持标签仍明确拒绝。
    if ![1, 4, v1_adapter::复合值载荷::列表标签,
        v1_adapter::复合值载荷::结果结构标签].contains(&模块接口说明.返回类型)
    {
        return Err(format!(
            "当前模块整槽链只支持整数、文本、列表和结果结构（声明返回类型 {}）",
            模块接口说明.返回类型
        ));
    }
    Ok(模块身份 {
        标识串: 依赖表达.标识串,
        版本: 模块实现版本(模块目录)?,
        能力号: 模块接口说明.编号,
        制品路径: 模块制品路径(模块目录, 模块制品后缀)?,
        // 依赖表达随身份一起交出去：解析依赖制品要用**声明侧**的清单与版本门槛（不猜）。
        依赖清单: 依赖表达.依赖清单,
        依赖版本要求: 依赖表达.依赖版本要求,
    })
}

/// 模块目录 → 能力声明编号表（`能力声明/<编号>.json`，**只认文件名的编号段**）。
///
/// 目录缺席 ⇒ 空表（不是错：没有声明就没能力，上层按「恰好 1 个」拒）。
fn 能力声明编号表(模块目录: &Path) -> Result<Vec<u32>, String> {
    let 声明目录 = 模块目录.join("能力声明");
    let Ok(目录读器) = fs::read_dir(&声明目录) else {
        return Ok(Vec::new());
    };
    let mut 编号表: Vec<u32> = Vec::new();
    for 目录项 in 目录读器.filter_map(|目录项| 目录项.ok()) {
        let 路径 = 目录项.path();
        if 路径.extension().and_then(std::ffi::OsStr::to_str) != Some("json") {
            continue;
        }
        let Some(编号文本) = 路径.file_stem().and_then(std::ffi::OsStr::to_str) else {
            continue;
        };
        let Ok(编号) = 编号文本.parse::<u32>() else {
            return Err(format!("能力声明文件名不是编号：{}", 路径.display()));
        };
        编号表.push(编号);
    }
    编号表.sort_unstable();
    Ok(编号表)
}

/// 模块目录 → `包声明.json` 的 `实现版本`（主 · 次 · 构建）。
fn 模块实现版本(模块目录: &Path) -> Result<(u32, u32, u32), String> {
    let 声明件 = 模块目录.join(crate::常量::扩展声明件);
    let 声明文本 =
        fs::read_to_string(&声明件).map_err(|错误| format!("读不到 {}：{错误}", 声明件.display()))?;
    let 声明值 = crate::协议解析::解析协议值(&声明文本)
        .map_err(|错误| format!("{} 不是合法 JSON：{}", 声明件.display(), 错误.说明文字))?;
    let 版本值 = 声明值
        .取成员("实现版本")
        .ok_or_else(|| format!("{} 缺 实现版本", 声明件.display()))?;
    let 取段 = |键名: &str| -> Result<u32, String> {
        版本值
            .取成员(键名)
            .and_then(协议值::取无符号)
            .and_then(|号值| u32::try_from(号值).ok())
            .ok_or_else(|| format!("{} 的 实现版本.{键名} 缺失或非整数", 声明件.display()))
    };
    Ok((取段("主")?, 取段("次")?, 取段("构建")?))
}

/// 模块目录 → 那一个模块制品的路径（**恰好一个**，多一个就拒 —— 不取第一个）。
fn 模块制品路径(模块目录: &Path, 模块制品后缀: &str) -> Result<PathBuf, String> {
    let 模块制品文件表: Vec<PathBuf> = fs::read_dir(模块目录)
        .map_err(|错误| format!("读不到目录：{错误}"))?
        .filter_map(|目录项| 目录项.ok())
        .map(|目录项| 目录项.path())
        .filter(|路径| 模块制品::是模块制品(路径, 模块制品后缀))
        .collect();
    if 模块制品文件表.len() != 1 {
        return Err(format!("模块制品 {} 个（要求恰好 1 个）", 模块制品文件表.len()));
    }
    Ok(模块制品文件表[0].clone())
}
