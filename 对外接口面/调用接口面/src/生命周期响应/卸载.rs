//! 生命周期响应 · 卸载 —— `POST /接口/生命周期 {动作:卸载}` 的完整状态转换。
//!
//! 从 `生命周期响应.rs` 拆出（单源 ≤ 500 行 · 拆法按关注点）：① 先 `2001` 协商
//! （扩展可回 `2015` 请求延迟释放）→ ② 等在途执行引用归零（**有界**）→ ③ 延迟释放才
//! 复核 `2003` → ④ **成功才杀域**并摘登记账。
//!
//! 顺序不可换：在途调用持旧路由快照，先杀域会把在途调用连带杀死（报 `0034`）。
//! 结局一律放进 `数据.派发结果` 如实报，**不编错误码**（见父件文件头）。

use std::time::{Duration, Instant};

use v1_adapter::{派发结果, 适配器};

use crate::协议值::协议值;
use crate::工具响应::{造成功应答, 造键文对};

/// 卸载时**等在途执行引用归零**的上限（毫秒）。**≤ 五秒硬顶**。
const 卸载等待毫秒: u64 = 2000;

/// 等到本实例在途执行引用归零（**有界**：超过卸载等待上限即返回，不无限等）。
///
/// 为什么必须等：在途调用持旧路由快照，若此刻杀执行域，在途调用会连带被杀（报 `0034`）。
/// 等待有界，超时如实返回（调用方按现状报读数）—— 不无限阻塞网关工作线程。
#[cfg(unix)]
fn 等在途归零(适配器: &适配器) {
    let 截止 = Instant::now() + Duration::from_millis(卸载等待毫秒);
    while 适配器.在途执行数() > 0 && Instant::now() < 截止 {
        std::thread::sleep(Duration::from_millis(1));
    }
}

/// `POST /接口/生命周期`（`动作 = 卸载`）→ 触发卸载并如实报结局（见文件头）。
///
/// 取 `&mut 适配器`：卸载是**完整状态转换**（摘通知端点 + 收回路由 + 注销台账身份，见
/// `适配器::请求卸载按标识`）⇒ 调用方（网关的 `RwLock`）必须持**写锁**，与 `装载` 对称。
///
/// `启用状态` = 跨进程生产启用状态（`None` = 全部走进程内）。**卸载即注销执行域**：
/// 与装载对称、判据同源（`跨进程装配::启用状态::卸载注销`），不另造一套生命周期。
/// 声明由登记账里记的**落点目录**现取（同一个装载器 ⇒ 拿到的是同一份声明）。
#[cfg(unix)]
pub(crate) fn 卸载扩展(
    适配器: &mut 适配器,
    本扩展标识串: &str,
    mut 启用状态: Option<&mut crate::跨进程装配::启用状态>,
) -> 协议值 {
    let 区间起点 = Instant::now();
    // **模块域卸载**：模块没有 `GetPlatformInfo`，`2001` 协商送不到它（结局必是 `未命中`）。
    // 它的卸载 = 宿主回收工作进程组（模块侧不留状态）—— 登记账命中即真回收，回执键仍用既有那几个。
    if 启用状态
        .as_deref()
        .is_some_and(|状态| 状态.模块已登记(本扩展标识串))
    {
        let 物理回收 = 启用状态
            .as_deref_mut()
            .is_some_and(|状态| 状态.卸载注销(适配器, 本扩展标识串));
        return 造成功应答(
            协议值::对象值(vec![
                造键文对("标识串", 本扩展标识串),
                造键文对("派发结果", "成功"),
                ("逻辑卸载".to_owned(), 协议值::无符号值(1)),
                ("物理回收".to_owned(), 协议值::无符号值(u64::from(物理回收))),
                (
                    "通知端点数".to_owned(),
                    协议值::无符号值(u64::from(适配器.通知端点数())),
                ),
                (
                    "已装载声明数".to_owned(),
                    协议值::无符号值(适配器.已装载声明数() as u64),
                ),
            ]),
            &区间起点,
        );
    }
    // ① **先 2001 协商**（不杀域）：扩展可回 `2015` 请求延迟释放。逻辑卸载（摘通知端点 +
    //    收回路由 + 注销台账身份）在**成功**时由这一步完成 —— 但**物理回收（杀域）一律后置**。
    let 首结局 = 适配器.请求卸载按标识(本扩展标识串);
    let mut 结局 = 首结局;
    // ② 被延迟释放，或本实例还有在途执行引用 ⇒ **等在途归零**再往下：在途调用持旧快照，
    //    此刻杀域会把在途调用连带杀死（报 0034），`2001/2015` 的协商也就成了空话。
    if 结局 == 派发结果::请求延迟释放 || 适配器.在途执行数() > 0 {
        等在途归零(适配器);
        // ③ 引用清零后**复核**（发 2003）—— 只有初次请求被延迟释放才需要复核。
        if 首结局 == 派发结果::请求延迟释放 {
            结局 = 适配器.延迟释放协商按标识(本扩展标识串);
        }
    }
    // ④ **成功才杀域**（一律后置）+ 摘登记账：按登记账里的落点、用同一个装载器取回声明。
    let mut 物理回收 = false;
    if 结局 == 派发结果::成功
        && let Some(状态) = 启用状态
    {
        物理回收 = 状态.卸载注销(适配器, 本扩展标识串);
    }
    造成功应答(
        协议值::对象值(vec![
            造键文对("标识串", 本扩展标识串),
            造键文对("派发结果", 结局名(结局)),
            (
                "逻辑卸载".to_owned(),
                协议值::无符号值(u64::from(结局 == 派发结果::成功)),
            ),
            ("物理回收".to_owned(), 协议值::无符号值(u64::from(物理回收))),
            (
                "通知端点数".to_owned(),
                协议值::无符号值(u64::from(适配器.通知端点数())),
            ),
            (
                "已装载声明数".to_owned(),
                协议值::无符号值(适配器.已装载声明数() as u64),
            ),
        ]),
        &区间起点,
    )
}

/// `派发结果` → 可读名（契约 `通知返回` 与 `派发结果` 的结局名逐字）。
fn 结局名(结局: 派发结果) -> &'static str {
    match 结局 {
        派发结果::成功 => "成功",
        派发结果::请求延迟释放 => "请求延迟释放",
        派发结果::失败 => "失败",
        派发结果::未命中 => "未命中",
    }
}
