//! 生命周期响应 · 判定层级与接入回执 —— 一次读数里「走到哪一级」的如实交代。
//!
//! 从 `生命周期响应.rs` 拆出（单源 ≤ 500 行 · 拆法按关注点）：§22.4 五级区分与
//! 方案 §18.3-6 四类合成一条**七级链**，再把方案 §27 的**十二类**接入回执逐类摆出。
//!
//! 能现判的现判，判不了的标 `已判 = false` 并写**证据在哪** —— 不假报绿灯，
//! 也不把「本面判不了」当成真或假。

use crate::协议值::协议值;
use crate::工具响应::造键文对;
use v1_adapter::适配器;

/// 判定层级 —— 两种拟制一表两读：§22.4 五级区分（本地自检 ≠ 构建 ≠ 准入 ≠ 就绪 ≠ 调用成功）
/// 与 方案 §18.3-6 四类（扩展自检 / 平台准入 / 部署成功 / 业务执行成功 **必须分别判定**）。
/// 合成一条**七级链**，让两者各自的每一档都各自有可判位：
///
/// ```text
/// 本地自检 → 构建 → 准入 → 部署 → 就绪 → 业务执行 → 调用成功
/// ```
///
/// 为什么单开这一层：顶层 `成功: true`（与本端点的装载路）只说明**这条路走通了**，
/// 不等于目标可用；而可用本身又分多个更早的阶段。逐级各给 `已判` 与 `说明`：
/// 本案能现判的现判，不能现判的**如实标未判**并写明为什么（不假报绿灯）。
///
/// **四种「成功」必须分得开（18.3-6）**：自检通过 ≠ 准入通过 ≠ 部署成功 ≠ 业务执行成功。
/// 本面能现判的只有「本地自检」（声明已载入，六步跑过）与「就绪」（能力清单里有号可寻址）；
/// 其余各级的判据不在网关本进程内，逐级如实写**证据在哪**（供调用方去拿），
/// 不因为“本面判不了”就把它当成真或假。
pub(super) fn 判定层级(适配器: &适配器) -> 协议值 {
    let 可寻址 = !适配器.能力清单().is_empty();
    协议值::数组值(vec![
        层级项(
            "本地自检",
            true,
            "声明已载入且号段无冲突：装载入口六步判定跑过（标识串 / 号段 / 宿主版本 / 依赖 / 自洽）",
        ),
        层级项(
            "构建",
            false,
            "构建制品（cargo）不在网关本进程内，本面无从现判 —— 要看请跑 `测试验证/测试案例/` 的对应案例",
        ),
        层级项(
            "准入",
            false,
            "准入判据（`测试验证/准入判据/`）是独立夹具，不在网关本进程内，本面无从现判",
        ),
        层级项(
            "部署",
            false,
            "部署成功（制品已落到扩展根、环境就绪可被扫到）看的是装配侧的产物与落点，本面只管运行期，无从现判",
        ),
        层级项(
            "就绪",
            可寻址,
            if 可寻址 {
                "当场能力清单非空 ⇒ 至少一份声明的号段内有号可寻址"
            } else {
                "能力清单为空：没有号可寻址（声明载入数不为零也还不等于可用）"
            },
        ),
        层级项(
            "业务执行",
            false,
            "业务执行成功 = 真发起过一次业务调用并拿到应答（不只看能力已载入）—— 那要看 `POST /接口/调用` 与 `GET /接口/留痕`",
        ),
        层级项(
            "调用成功",
            false,
            "本面不看有没有真调成功 —— 那要看 `POST /接口/调用` 的实际应答与 `GET /接口/留痕`",
        ),
    ])
}

/// 接入回执 —— 方案 §27「小事也必须交代清楚的接入回执（十二类问题）」。
///
/// 十二类逐类给四个机器可判字段（`类目` · `已判` · `说明` · `证据口`），
/// **能现判的现判，判不了的如实标未判并指路** —— 不因为本面判不了就当它真或假
/// （同 [`判定层级`] 的如实档口径）。
///
/// 为什么单开这一层：就绪读数只覆盖「就绪」半档，读的人拿到一次 `GET /接口/生命周期`
/// 却看不到「身份/兼容/能力/依赖/构建/副作用/运行/观测/资源/升级/验证」这十一类的结论
/// —— 十二类里只有一档有落点。本层把十二类**逐类**摆出来（缺哪一类是可数的）。
pub(super) fn 接入回执(适配器: &适配器, 已可寻址号: &[u32]) -> 协议值 {
    let 声明数 = 适配器.已装载声明数();
    let 有声明 = 声明数 > 0;
    let 有可寻址 = !已可寻址号.is_empty();
    let 在途 = 适配器.在途执行数();
    协议值::数组值(vec![
        类目项(
            "身份",
            有声明,
            if 有声明 {
                "逐份声明的 标识串 + 实现版本三元组 已在 `逐份就绪` 里（当场现读）"
            } else {
                "一份声明都没装：没有身份可判"
            },
            "GET /接口/生命周期 → 数据.逐份就绪",
        ),
        类目项(
            "兼容",
            false,
            "宿主/内核版本与目标字宽在执行前可判（装载入口六步判定 ④ 及平台层），但本面只看装载后的现量 —— 要看拒因请查装载回执的 `剔除[].原因`",
            "POST /接口/生命周期 动作=装载 → 数据.剔除",
        ),
        类目项(
            "能力",
            有可寻址,
            if 有可寻址 {
                "能力清单非空：至少一号可寻址（可调）"
            } else {
                "能力清单为空：没有号可寻址（声明载入数不为零也还不等于可调）"
            },
            "GET /接口/搜索 或 POST /接口/调用",
        ),
        类目项(
            "依赖",
            false,
            "依赖版本比对口在装载入口（`依赖校验.rs::依赖清单合法`），本面判不了 —— 缺依赖的候选取装载回执里 `剔除[].原因`（依赖缺失会多趟试装）",
            "POST /接口/生命周期 动作=装载 → 数据.剔除",
        ),
        类目项(
            "构建",
            false,
            "构建（cargo）不在网关本进程内，本面无从现判 —— 要看请跑 `测试验证/测试案例/`",
            "测试验证/测试案例/（cargo）",
        ),
        类目项(
            "副作用",
            false,
            "某次调用是否已真执行（副作用是否可能已落）看失败应答的 `重试判据`（执行阶段 / 可能已执行 / 结果确定）；本面不替它判",
            "POST /接口/调用 失败应答 → 错误.重试判据 · GET /接口/留痕",
        ),
        类目项(
            "运行",
            true,
            if 在途 > 0 {
                "此刻有在途执行引用（本面当场现读）"
            } else {
                "此刻无在途执行引用（本面当场现读；0 不等于从未跑过 —— 历史看留痕）"
            },
            "GET /接口/生命周期 → 数据.在途执行数（本读数）· GET /接口/留痕",
        ),
        类目项(
            "就绪",
            有可寻址,
            "逐份的 `是否可用`（号段内有号可寻址）见 `逐份就绪`；顶层成功只说装载这条路走通了",
            "GET /接口/生命周期 → 数据.逐份就绪[].是否可用",
        ),
        类目项(
            "观测",
            true,
            "每次调用留痕（谁 · 调什么 · 入参指纹 · 结果 · 耗时 · 追踪号），应答与留痕同号；开没开看 `已启用`",
            "GET /接口/留痕",
        ),
        类目项(
            "资源",
            true,
            "存活分配计数与资源面读数（跨分配器，调用前后各读一次、差为 0 即无泄漏）",
            "GET /接口/资源读数",
        ),
        类目项(
            "升级",
            false,
            "同身份新版的候选/切换/回滚由 `POST /接口/生命周期 动作=装载` 承担；本面不报「升没升级」（那是一次装载动作，不是一份常驻状态）",
            "POST /接口/生命周期 动作=装载 → 数据.切换 / 数据.装上",
        ),
        类目项(
            "验证",
            false,
            "发布验收（T01–T09）与准入判据是独立夹具，不在网关本进程内，本面无从现判",
            "测试验证/准入判据/ · 测试验证/测试案例/",
        ),
    ])
}

/// 一类接入交代 → JSON：`类目` · `已判` · `说明` · `证据口`。
///
/// 四键**齐全可机器判**：缺一类的 `已判`、或漏了 `证据口`，读的人无从判断。
fn 类目项(类目: &str, 已判: bool, 说明: &str, 证据口: &str) -> 协议值 {
    协议值::对象值(vec![
        造键文对("类目", 类目),
        ("已判".to_owned(), crate::线上逻辑值::真假值转线上值(已判)),
        造键文对("说明", 说明),
        造键文对("证据口", 证据口),
    ])
}

/// 一级判定 → JSON：`层级` · `已判` · `说明`。
fn 层级项(层级: &str, 已判: bool, 说明: &str) -> 协议值 {
    协议值::对象值(vec![
        造键文对("层级", 层级),
        ("已判".to_owned(), crate::线上逻辑值::真假值转线上值(已判)),
        造键文对("说明", 说明),
    ])
}
