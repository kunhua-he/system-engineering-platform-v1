//! 生命周期响应 · 装载回执 —— `POST /接口/生命周期 {动作:装载}`：重扫扩展根、多趟试装。
//!
//! 从 `生命周期响应.rs` 拆出（单源 ≤ 500 行 · 拆法按关注点）：本件只出**回执**
//! （`扫到` / `装上` / `切换` / `已在` / `剔除`），不重启网关、不重建适配器。
//!
//! 拓扑保证与启动装配等价：与 `examples/启动网关/装配.rs` 同读 `crate::依赖序装载`，
//! 缺依赖**延后一趟**而不是当场剔除（台账 C04）。

use std::fs;
use std::path::{Path, PathBuf};
use std::time::Instant;

use v1_adapter::适配器;

use super::模块候选::模块候选身份;
use crate::依赖序装载::{按依赖序装载, 试装结局};
use crate::工具响应::{造成功应答, 造键文对};
use crate::协议值::协议值;
use crate::跨进程装配::条目结局;
use crate::{模块制品, 扫扩展根};

/// `POST /接口/生命周期`（`动作 = 装载`）→ 重扫扩展根、对**新**候选 `追加装载`（台账 237）。
///
/// **不重启网关**：只对**已存在**的适配器追加（[`适配器::追加装载`] 取 `&mut`，调用方持写锁），
/// **不重建** —— 重建会清掉配额账本与调用留痕。
///
/// **拓扑保证与启动装配等价**（台账 C04）：候选按依赖序**多趟**试装，与
/// `examples/启动网关/装配.rs` 同读 `crate::依赖序装载` 那一份 —— 依赖者排在依赖者之前时，
/// 本趟缺依赖、下趟依赖者已装上即能装。缺依赖不再当成「一次定论的剔除」。
///
/// 结局一律顶层 `成功: true`：新候选一个都没有 ⇒ **未命中不是失败**（照卸载的既有口径）；
/// 单个候选取接缝 / 追加装载失败 ⇒ 落「剔除」如实报出（不静默吞因、不整体失败）。
///
/// `声明根` 与 `源文本`（后缀表文本）都是装配侧注入的部署事实（`服务::声明根` /
/// `服务::后缀表`）；没注入就 fail-closed 指路。`缓存根目录` 不给就用适配器的默认
/// （运行数据根的缓存类）—— 与两者同一条约定：不退回源码树、不退回 `/tmp`。
///
/// `启用状态` = 跨进程生产启用状态（`None` = 全部走进程内）。**装载 / 切换按同一份判据
/// 登记执行域**：只有登记成功（工作进程装载成功 + 初始化回执确认）才算发布；登记不上 ⇒
/// 该候选**不发布**（既不替换旧版本，也不回退进程内 —— 见 `跨进程装配::校验并登记一条`）。
#[cfg(unix)]
pub(crate) fn 装载(
    适配器: &mut 适配器,
    声明根: Option<&Path>,
    源文本: Option<&str>,
    缓存根目录: Option<&Path>,
    mut 启用状态: Option<&mut crate::跨进程装配::启用状态>,
) -> 协议值 {
    let 区间起点 = Instant::now();
    let Some(声明根) = 声明根 else {
        return 造成功应答(
            协议值::对象值(vec![
                造键文对("动作", "装载"),
                (
                    "说明".to_owned(),
                    协议值::文本值(
                        "声明根未注入：服务没拿到扩展根声明路径，无法重扫。装配侧请调 \
                         服务::声明根（examples/启动网关 注入 --声明根）。"
                            .to_owned(),
                    ),
                ),
            ]),
            &区间起点,
        );
    };
    let Some(源文本) = 源文本 else {
        return 造成功应答(
            协议值::对象值(vec![
                造键文对("动作", "装载"),
                (
                    "说明".to_owned(),
                    协议值::文本值(
                        "后缀表未注入：没拿到 `扩展装载/后缀表.json` 的文本，无法判候选。"
                            .to_owned(),
                    ),
                ),
            ]),
            &区间起点,
        );
    };
    let 后缀表 = match 扫扩展根::读后缀表(源文本) {
        Ok(后缀表) => 后缀表,
        Err(说明文字) => {
            return 造成功应答(
                协议值::对象值(vec![造键文对("动作", "装载"), 造键文对("说明", &说明文字)]),
                &区间起点,
            );
        }
    };
    // 解包物落点：注入的优先；没注入就用适配器的默认（运行数据根的缓存类）。
    // 解析不出根 ⇒ fail-closed 指路（不许退回源码树 / `/tmp`）。
    let 缓存根目录 = match 缓存根目录.map(PathBuf::from).or_else(v1_adapter::装载件缓存::默认缓存根目录) {
        Some(缓存根目录) => 缓存根目录,
        None => {
            return 造成功应答(
                协议值::对象值(vec![
                    造键文对("动作", "装载"),
                    (
                        "说明".to_owned(),
                        协议值::文本值(
                            "解析不出运行数据根：解包物无处可落（不退回源码树 / `/tmp`）。\
                             装配侧请调 服务::缓存根目录 注入落点。"
                                .to_owned(),
                        ),
                    ),
                ]),
                &区间起点,
            );
        }
    };
    let 文本值 = match fs::read_to_string(声明根) {
        Ok(文本值) => 文本值,
        Err(错误) => {
            return 造成功应答(
                协议值::对象值(vec![
                    造键文对("动作", "装载"),
                    造键文对("说明", &format!("读不到扩展根声明 {}：{错误}", 声明根.display())),
                ]),
                &区间起点,
            );
        }
    };
    let 扫描 = match 扫扩展根::读声明根(&文本值) {
        Ok(扫描) => 扫描,
        Err(说明文字) => {
            return 造成功应答(
                协议值::对象值(vec![造键文对("动作", "装载"), 造键文对("说明", &说明文字)]),
                &区间起点,
            );
        }
    };
    let mut 装上: Vec<协议值> = Vec::new();
    let mut 切换: Vec<协议值> = Vec::new();
    let mut 已在: Vec<协议值> = Vec::new();
    let mut 剔除: Vec<协议值> = Vec::new();
    // 取到接缝的候选：**按依赖序多趟试装**（台账 C04）—— 与启动装配
    // （`examples/启动网关/装配.rs`）同读 `crate::依赖序装载` 那一份。
    // **两路的拓扑保证必须等价**：同一份扩展根，装配期装得上、热装载也得装得上
    // （依赖者排在依赖者之前时，本趟缺依赖、下趟依赖者已装上即能装）。
    let mut 待装候选表: Vec<(&'static v1_adapter::平台信息, String)> = Vec::new();
    // **模块候选另收一表**（债务 374 真接入）：模块的制品里没有本机机器码
    // （三段 = 接口说明 16 · 本机执行体 20 · 指纹 18），底座不 `dlopen` 它 —— 走子进程 + IPC
    // （`项目文档/决策记录/2026-10-06_模块执行路线澄清.md`）。它的**依赖表达在声明侧**
    // （同目录 `包声明.json` 的 依赖清单 / 依赖版本要求），判据与支持库那条路**同一份**
    // （`依赖校验.rs` 的四问 · 文本入口）。**扫到就收下、判放在试装之后** —— 依赖要在
    // 「这一趟装完的台账」上判，先判会把本趟才装上的支持库误报成「不在台账里」（假红）。
    let mut 模块候选表: Vec<(PathBuf, String, String)> = Vec::new();
    for 扩展根目录 in &扫描.目录s {
        if !扩展根目录.is_dir() {
            continue;
        }
        for 子目录项 in 扫扩展根::列子目录(扩展根目录) {
            let 落点 = 子目录项.display().to_string();
            match 扫扩展根::取扩展声明(&子目录项, &后缀表, &缓存根目录) {
                Err(失败原因) => {
                    if 模块制品::是模块候选(&子目录项, &后缀表) {
                        模块候选表.push((子目录项, 落点, 失败原因));
                    } else {
                        剔除.push(剔除条(&落点, &失败原因));
                    }
                }
                Ok(声明) => 待装候选表.push((声明, 落点)),
            }
        }
    }
    let 依赖序结果 = 按依赖序装载(
        待装候选表,
        &mut |声明, 落点| {
            // 已在表里 ⇒ 看是不是**同身份新版**：同身份同版本 = 已在（幂等跳过）；
            // 同身份新版本 = **版本切换**。
            let 旧版本 = 适配器.找同身份声明(声明).map(|旧声明| 旧声明.实现版本);
            if 旧版本 == Some(声明.实现版本) {
                return 试装结局::已在;
            }
            // **候选门**：先按部署配置登记执行域（拉起工作进程 + 初始化回执确认）。
            // 登记不上 ⇒ 候选**不发布** —— 既不替换旧版本，也不回退进程内。
            if let Some(状态) = 启用状态.as_deref_mut()
                && let crate::跨进程装配::条目结局::拒收(拒收原因) = 状态.装载登记(适配器, 声明, 落点) {
                    return 试装结局::硬失败(format!("跨进程候选未发布：{拒收原因}"));
                }
            match 旧版本 {
                // 同身份新版 ⇒ `适配器::升级装载` 那条路（先摘旧身份、再装新声明）。
                Some(_) => {
                    // 旧版声明：升级后它已不在路由里，但指针仍 `'static`，可算旧域标识。
                    let 旧声明 = 适配器.找同身份声明(声明);
                    match 适配器.升级装载(声明) {
                        Ok(()) => {
                            // **切换成功**：回收旧版执行域（杀进程组 + 摘域格 + 摘部署表）。
                            let 物理回收 = 旧声明
                                .map(|旧声明| 适配器.移除跨进程域(旧声明))
                                .unwrap_or(false);
                            试装结局::切换 { 物理回收 }
                        }
                        Err(错误) => {
                            // **切换失败回滚新域**：候选未发布 ⇒ 把新域登记撤掉（否则孤儿域）。
                            let 物理回收 = 适配器.移除跨进程域(声明);
                            试装结局::硬失败(format!(
                                "{错误:?}（已回滚新域：物理回收={物理回收}）"
                            ))
                        }
                    }
                }
                None => match 适配器.追加装载(声明) {
                    Ok(()) => 试装结局::装上,
                    // **缺依赖 ⇒ 延后一趟**（不是硬失败）：多趟才等得来依赖。
                    // 判据同源：装载入口的判定 ⑤ 回 `载入错误::依赖缺失`。
                    Err(v1_adapter::装载失败::载入失败(v1_adapter::载入错误::依赖缺失)) => {
                        试装结局::缺依赖
                    }
                    Err(错误) => 试装结局::硬失败(format!("{错误:?}")),
                },
            }
        },
        // 整趟零进展的残留：真缺依赖（不在扩展根里 / 名字写错）⇒ 按缺依赖如实报出。
        &format!("{:?}", v1_adapter::装载失败::载入失败(v1_adapter::载入错误::依赖缺失)),
    );
    for 落点 in 依赖序结果.装上 {
        装上.push(协议值::文本值(落点));
    }
    for (落点, 物理回收) in 依赖序结果.切换 {
        切换.push(切换条(&落点, 物理回收));
    }
    for 落点 in 依赖序结果.已在 {
        已在.push(协议值::文本值(落点));
    }
    for (落点, 失败原因) in 依赖序结果.剔除 {
        剔除.push(剔除条(&落点, &失败原因));
    }
    // **模块候选：真登记执行域**（复用 `装上` 键，**不新增响应键**）。
    //
    // 支持库与模块是**两种身份**，但走**同一个**域表 / 进程池 / 工作进程启动器
    // （`跨进程装配::启用状态::装载模块登记`）。登记成功才算「装上」；判不过一律 `剔除` 并给因
    // —— fail-closed 不变，**不看编号大小**。
    // 依赖放在试装之后判：判据要的是「这一趟装完的台账」（先判会把本趟才装上的支持库误报成不在台账）。
    for (子目录项, 落点, 底座说明) in &模块候选表 {
        let 依赖判读 = 模块制品::判模块依赖(子目录项, 适配器.依赖台账());
        let 结局 = match (模块候选身份(子目录项, &后缀表), 依赖判读) {
            (Err(拒收原因), _) => 条目结局::拒收(format!("模块候选：{拒收原因}（{底座说明}）")),
            (Ok(_), Err(依赖原因)) => 条目结局::拒收(format!(
                "模块候选：依赖清单不过（{依赖原因}）（{底座说明}）"
            )),
            (Ok(模块条目), Ok(_)) => {
                // **依赖解析**：声明侧的依赖清单 → 部署条目（标识串 / 版本 / 制品路径）→ 制品表。
                // 缺依赖 / 版本不符 / 歧义 / 制品缺失一律拒；解析出的制品交给工作进程
                // 用**既有装载腿**在同进程内装载（不新开进程池、不猜路径）。
                let 依赖解析 = 启用状态
                    .as_deref()
                    .ok_or_else(|| {
                        "模块候选：未注入跨进程部署配置（模块只能走工作进程）".to_owned()
                    })
                    .and_then(|状态| 状态.解析依赖制品(&模块条目));
                match 依赖解析 {
                    Err(拒收原因) => 条目结局::拒收(format!("模块候选：{拒收原因}")),
                    Ok(依赖制品表) => match 启用状态.as_deref_mut() {
                        None => 条目结局::拒收(
                            "模块候选：未注入跨进程部署配置（模块只能走工作进程）".to_owned(),
                        ),
                        Some(状态) => {
                            状态.装载模块登记(适配器, &模块条目, 落点, &依赖制品表)
                        }
                    },
                }
            }
        };
        match 结局 {
            条目结局::已登记 => 装上.push(协议值::文本值(落点.clone())),
            条目结局::拒收(拒收原因) => 剔除.push(剔除条(落点, &拒收原因)),
            条目结局::走进程内 => 剔除.push(剔除条(
                落点,
                "模块候选：部署配置把它判成走进程内 —— 模块没有进程内路（底座不 dlopen 模块）",
            )),
        }
    }
    let 扫到 = (装上.len() + 切换.len() + 已在.len() + 剔除.len()) as u64;
    造成功应答(
        协议值::对象值(vec![
            造键文对("动作", "装载"),
            ("扫到".to_owned(), 协议值::无符号值(扫到)),
            ("装上".to_owned(), 协议值::数组值(装上)),
            ("切换".to_owned(), 协议值::数组值(切换)),
            ("已在".to_owned(), 协议值::数组值(已在)),
            ("剔除".to_owned(), 协议值::数组值(剔除)),
        ]),
        &区间起点,
    )
}

/// 一条剔除记录：`{落点, 原因}`（不静默吞因）。
fn 剔除条(落点: &str, 失败原因: &str) -> 协议值 {
    协议值::对象值(vec![
        ("落点".to_owned(), 协议值::文本值(落点.to_owned())),
        ("原因".to_owned(), 协议值::文本值(失败原因.to_owned())),
    ])
}

/// 一条切换记录：`{落点, 物理回收}` —— 逻辑卸载（换路由）与物理回收（杀旧域）分别出读数。
fn 切换条(落点: &str, 物理回收: bool) -> 协议值 {
    协议值::对象值(vec![
        ("落点".to_owned(), 协议值::文本值(落点.to_owned())),
        (
            "物理回收".to_owned(),
            if 物理回收 { 协议值::真值 } else { 协议值::假值 },
        ),
    ])
}
