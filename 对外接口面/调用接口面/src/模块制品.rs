//! 模块制品 —— `.模块制品`（能力包件）的**底座侧读法**。
//!
//! 支持库的制品是本机动态库（`dlopen` + 接缝 `GetPlatformInfo`，见 [`扫扩展根`](crate::扫扩展根)）；
//! **模块的制品不是** —— 它是**能力包件**（段流容器：接口说明段 · 能力码段 · 指纹段），
//! 拿它去 `dlopen` 必然失败。模块的「怎么调」只能从**接口说明段**读出来
//! （`扩展装载/后缀表.json` 的 `载入`：底座解析制品 → 取接口说明段）。
//!
//! # 本件只解析，不执行
//!
//! 模块的执行路线是**子进程 + IPC**（`项目文档/决策记录/2026-10-06_模块执行路线澄清.md`），
//! 不属本件。本件只回答一件事：**这份制品说它是什么能力、怎么调**。
//!
//! # 容器与编码都不在本件重写
//!
//! 能力包件三段的编解码**只此一份**，在契约层（`契约声明/src/契约声明/容器.rs`）；
//! 接口说明六字段的编解码也只此一份（`契约声明/src/契约声明/接口说明段.rs`）。
//! 本件经**适配器**（本 crate 的唯一腿）取那两份 —— 不跳层、不抄一份。

use std::fs;
use std::path::{Path, PathBuf};

use v1_adapter::容器;
use v1_adapter::接口说明段;

/// 模块制品的后缀。**唯一权威 = `扩展装载/后缀表.json`**（`三类扩展[种类=模块].制品后缀`；
/// 容器 = 能力包件）。
///
/// ★ 如实登记：本常量是那份表的**副本**，与 `扫扩展根.rs::库后缀` 同属「后缀表还没接进底座」
/// 那一档 —— 后缀表的可数判据 ①（全仓 0 处系统原生动态库后缀）明写「两个读方的同一条
/// 判据**随切面腿立**」⇒ 接表是那条切面腿的活，不是本件顺手做的（顺手做就是两处各接一半）。
pub const 模块制品后缀: &str = ".模块制品";

/// 是不是模块制品（按后缀找，不按名字找 —— 名字里会有模块名，底座不许认名字）。
pub fn 是模块制品(路径: &Path) -> bool {
    let 名称 = 路径.file_name().and_then(|名称| 名称.to_str());
    路径.is_file() && 名称.is_some_and(|名称| 名称.ends_with(模块制品后缀))
}

/// 一个模块目录 → 它的接口说明。
///
/// 三步缺一步即「不是模块」：① 目录内**恰好一个** `.模块制品`；② 它是能力包件
/// （三段齐 · 段类型各就各位）；③ 接口说明段解得开六字段（非空字节集必须**正好**解完，
/// 剩余一字节即拒）。
///
/// **只解析**：不执行、不调用、不装载。失败一律给一句可读原因（与 `取扩展声明` 同形）——
/// 扫描面上「这一个子目录不是模块」是**正常结局**，不该中断别的子目录（同 `后缀表.json`
/// 的「缺了照跑」）。
pub fn 取模块接口说明(模块目录: &Path) -> Result<接口说明段::接口说明, String> {
    let 制品文件: Vec<PathBuf> = fs::read_dir(模块目录)
        .map_err(|错误| format!("读不到目录：{错误}"))?
        .filter_map(|目录项| 目录项.ok())
        .map(|目录项| 目录项.path())
        .filter(|路径| 是模块制品(路径))
        .collect();
    if 制品文件.len() != 1 {
        return Err(format!("模块制品 {} 个（要求恰好 1 个）", 制品文件.len()));
    }
    let 制品字节 = fs::read(&制品文件[0]).map_err(|错误| format!("读不到制品：{错误}"))?;
    let 三段 = 容器::解包(&制品字节).map_err(|错误| format!("不是能力包件：{错误:?}"))?;
    接口说明段::解码(&三段.接口说明段)
        .ok_or_else(|| "接口说明段解不开（截断 / 尾部多余字节 / 不是合法 UTF-8）".to_owned())
}

/// 一个模块目录 → 制品字节的**段指纹**是否与内容相符（旁路校验，缺了不影响解析）。
///
/// `None` = 不是本形状的包；`Some(真)` = 两段都没被换过；`Some(假)` = 被换过。
pub fn 校验模块制品指纹(模块目录: &Path) -> Option<bool> {
    let 制品文件: Vec<PathBuf> = fs::read_dir(模块目录).ok()?
        .filter_map(|目录项| 目录项.ok())
        .map(|目录项| 目录项.path())
        .filter(|路径| 是模块制品(路径))
        .collect();
    if 制品文件.len() != 1 {
        return None;
    }
    let 制品字节 = fs::read(&制品文件[0]).ok()?;
    容器::校验段指纹(&制品字节)
}

#[cfg(test)]
mod 模块制品测试 {
    use super::*;

    /// 仓根（测试与 crate 同一棵树）。
    fn 取仓根() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    /// 按**扩展根声明**扫出的全部模块目录 —— **不点名任何扩展**（README 硬边界 1）。
    ///
    /// 扫法与运行期同一条：`读声明根` 给要扫的目录，`列子目录` 给候选，
    /// 候选里有没有模块制品由 `是模块制品` 判（按后缀找，不按名字找）。
    fn 全部模块目录() -> Vec<PathBuf> {
        let 声明件 = 取仓根().join("扩展装载/扩展根声明.json");
        let 源文本 = fs::read_to_string(&声明件).expect("读扩展根声明");
        let 扫描读数 = crate::扫扩展根::读声明根(&源文本).expect("解扩展根声明");
        let mut 输出表 = Vec::new();
        for 落点 in &扫描读数.目录s {
            for 子目录 in crate::扫扩展根::列子目录(&取仓根().join(落点)) {
                let 有制品 = fs::read_dir(&子目录)
                    .map(|读器| 读器.flatten().any(|目录项| 是模块制品(&目录项.path())))
                    .unwrap_or(false);
                if 有制品 {
                    输出表.push(子目录);
                }
            }
        }
        输出表
    }

    /// 拿**真制品**验一条：按声明扫出来的每个模块目录，制品解出的接口说明段
    /// 必须与**同一目录下**的 `能力声明/<编号>.json` 逐字段一致。
    ///
    /// **比到的字段（写实，别照着注释想当然）**：`编号` · `名称` · `说明` · `返回类型` —— 逐字段
    /// 相等；`参数表` —— 先比行数（行序即契约），再逐位比 `名称` 与 `类型标签`；
    /// `可抛错误码` —— 先比条数，再逐位比 `码值`（对照物是声明的 `码`）。另加**指纹段**校验。
    ///
    /// ★ **已知未覆盖**：本仓唯一的模块样本，其 `可抛错误码` 是**空表**（它的 `说明/使用说明.md`
    /// 解释了为什么没有 `错误码表/`），所以「逐位比码值」那一段**在当前样本上不执行** ——
    /// 比对代码已就位，样本没覆盖它。要真覆盖，得先有一个会抛码的模块样本。
    ///
    /// 制品不是手写的 —— 它由 `examples/出模块制品.rs` 跑真 1106 链产出（本体是同目录的 `.程序文本`）。
    /// 声明件按**编号**从同目录的 `能力声明/` 取，不点名任何扩展（README 硬边界 1）。
    #[test]
    fn 真制品_接口说明段与能力声明逐字段一致() {
        let 模块目录表 = 全部模块目录();
        assert!(!模块目录表.is_empty(), "按声明扫不到任何模块 —— 要么声明变了，要么样本没了");
        for 模块目录 in &模块目录表 {
            let 说明 = 取模块接口说明(模块目录)
                .unwrap_or_else(|错误| panic!("{}：{错误}", 模块目录.display()));
            let 声明件 = 模块目录.join(format!("能力声明/{}.json", 说明.编号));
            let 声明文本 = fs::read_to_string(&声明件)
                .unwrap_or_else(|错误| panic!("{}：{错误}", 声明件.display()));
            let 声明值 = crate::协议解析::解析协议值(&声明文本)
                .unwrap_or_else(|错误| panic!("{}：{}", 声明件.display(), 错误.说明文字));
            let 取文本 = |键名: &str| {
                声明值.取成员(键名).and_then(|待处理值| 待处理值.取文本()).unwrap_or_default().to_owned()
            };
            assert_eq!(
                Some(u64::from(说明.编号)),
                声明值.取成员("编号").and_then(|待处理值| 待处理值.取无符号()),
                "编号"
            );
            assert_eq!(说明.名称, 取文本("名称"), "名称");
            assert_eq!(说明.说明, 取文本("说明"), "说明");
            assert_eq!(
                Some(u64::from(说明.返回类型)),
                声明值.取成员("返回类型").and_then(|待处理值| 待处理值.取无符号()),
                "返回类型"
            );
            let 声明参数表 = 声明值.取成员("参数表").and_then(|待处理值| 待处理值.取数组()).unwrap_or_default();
            assert_eq!(说明.参数表.len(), 声明参数表.len(), "参数表行数（行序即契约）");
            for (位次, 参数项) in 说明.参数表.iter().enumerate() {
                let 声明项 = &声明参数表[位次];
                assert_eq!(
                    参数项.名称,
                    声明项.取成员("名称").and_then(|待处理值| 待处理值.取文本()).unwrap_or_default(),
                    "参数表第 {位次} 位的名称"
                );
                assert_eq!(
                    Some(u64::from(参数项.类型标签)),
                    声明项.取成员("类型标签").and_then(|待处理值| 待处理值.取无符号()),
                    "参数表第 {位次} 位的类型标签"
                );
            }
            let 声明码表 = 声明值.取成员("可抛错误码").and_then(|待处理值| 待处理值.取数组()).unwrap_or_default();
            assert_eq!(说明.可抛错误码.len(), 声明码表.len(), "可抛错误码条数");
            for (位次, 错误项) in 说明.可抛错误码.iter().enumerate() {
                assert_eq!(
                    Some(u64::from(错误项.码值)),
                    声明码表[位次].取成员("码").and_then(|待处理值| 待处理值.取无符号()),
                    "可抛错误码第 {位次} 位的码"
                );
            }
            assert_eq!(
                校验模块制品指纹(模块目录),
                Some(true),
                "{}：指纹段与内容不符",
                模块目录.display()
            );
        }
    }

    /// 反向样本：目录里**没有**模块制品 ⇒ 报「0 个」，不是「当成模块」。
    #[test]
    fn 空目录_报零个而不是当模块() {
        let 临目录 = std::env::temp_dir().join("v1_模块制品测试_空");
        let _ = fs::remove_dir_all(&临目录);
        fs::create_dir_all(&临目录).expect("建临时目录");
        let 错误 = 取模块接口说明(&临目录).expect_err("空目录不该解出接口说明");
        assert!(错误.contains("0 个"), "该报「0 个」，实际：{错误}");
        let _ = fs::remove_dir_all(&临目录);
    }

    /// 反向样本：本机动态库后缀**不是**模块制品（模块走拆段，不走 `dlopen`）。
    ///
    /// 建**真文件**再判 —— 不建文件的话 `is_file()` 会把两个断言都变成永真，
    /// 那是一条假绿（「测了」与「没测」长得一模一样）。
    #[test]
    fn 动态库后缀_不算模块制品() {
        let 临目录 = std::env::temp_dir().join("v1_模块制品测试_后缀");
        let _ = fs::remove_dir_all(&临目录);
        fs::create_dir_all(&临目录).expect("建临时目录");
        let 动态库 = 临目录.join("某库.dylib");
        let 模块件 = 临目录.join("某模块.模块制品");
        fs::write(&动态库, b"").expect("建动态库样本");
        fs::write(&模块件, b"").expect("建模块制品样本");
        assert!(!是模块制品(&动态库), ".dylib 不是模块制品");
        assert!(!是模块制品(&临目录.join("某库.so")), "不存在的件不是模块制品");
        assert!(是模块制品(&模块件), ".模块制品 是模块制品");
        let _ = fs::remove_dir_all(&临目录);
    }
}

