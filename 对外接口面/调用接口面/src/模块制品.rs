//! 模块制品 —— `.模块制品`（能力包件）的**底座侧读法**。
//!
//! 支持库的制品也**不是**直接可 `dlopen` 的 —— 它同样是能力包件，底座先按容器解包取
//! **能力码段**、落一份仓外缓存件、再 `dlopen`（见 [`扫扩展根`](crate::扫扩展根)）；
//! **模块的制品不同**：它的能力码段是 WebAssembly（不是本机机器码），底座**不**装载它 ——
//! 模块的「怎么调」只能从**接口说明段**读出来
//! （`扩展装载/后缀表.json` 的 `载入`：底座解析制品 → 取接口说明段）。
//!
//! # 本件只解析，不执行
//!
//! 模块的执行路线是**子进程 + IPC**（`项目文档/决策记录/2026-10-06_模块执行路线澄清.md`），
//! 不属本件。本件只回答一件事：**这份制品说它是什么能力、怎么调**。
//!
//! # 容器与编码都不在本件重写
//!
//! 能力包件三段的编解码**只此一份**，在契约层（`契约声明/src/契约声明/容器.rs`）；
//! 接口说明六字段的编解码也只此一份（`契约声明/src/契约声明/接口说明段.rs`）。
//! 本件经**适配器**（本 crate 的唯一腿）取那两份 —— 不跳层、不抄一份。

use std::fs;
use std::path::{Path, PathBuf};

use v1_adapter::容器;
use v1_adapter::接口说明段;
use v1_adapter::{依赖清单合法文本, 已载入台账, 版本要求};

/// 是不是本种类的制品（按后缀找，不按名字找 —— 名字里会有模块名，底座不许认名字）。
///
/// `后缀项` 由**唯一权威** `扩展装载/后缀表.json` 解出（`读后缀表` 的 `取种类后缀("模块")`）——
/// 本件**不持有**任何后缀（判据 ③：全仓不许有第二处后缀表）。
pub fn 是模块制品(路径: &Path, 后缀项: &str) -> bool {
    let 名称 = 路径.file_name().and_then(|名称| 名称.to_str());
    路径.is_file() && 名称.is_some_and(|名称| 名称.ends_with(后缀项))
}

/// 一个**子目录**是不是模块候选 —— 「目录内恰好一个本平台制品（三类后缀都算），且那一个是模块制品」。
///
/// 与 [`是模块制品`] 的分工：那个只问「单个文件算不算模块制品」；本函数问**整个目录的候选资格** ——
/// 一个目录里混了两个制品时它不是任何一类的合法候选（`取扩展声明` 会报「本平台制品 2 个」），
/// 本函数也必须回「不是」，否则装载动作会把一个错件当模块报出去。
///
/// `后缀表` 是**唯一权威** `扩展装载/后缀表.json` 的读法（`扫扩展根::读后缀表`）——
/// 模块那一项由 `取种类后缀("模块")` 取，本件**不持有**任何后缀字面（判据 ③）。
pub fn 是模块候选(子目录: &Path, 后缀表: &crate::扫扩展根::后缀表) -> bool {
    let Some(模块后缀) = 后缀表.取种类后缀("模块") else {
        return false;
    };
    let Ok(目录读器) = fs::read_dir(子目录) else {
        return false;
    };
    let 制品文件: Vec<PathBuf> = 目录读器
        .filter_map(|目录项| 目录项.ok())
        .map(|目录项| 目录项.path())
        .filter(|路径| crate::扫扩展根::是制品(路径, 后缀表))
        .collect();
    制品文件.len() == 1 && 是模块制品(&制品文件[0], 模块后缀)
}

/// 一个模块目录 → 它的接口说明。
///
/// 三步缺一步即「不是模块」：① 目录内**恰好一个**本种类制品（后缀由 `后缀项` 给）；② 它是能力包件
/// （三段齐 · 段类型各就各位）；③ 接口说明段解得开六字段（非空字节集必须**正好**解完，
/// 剩余一字节即拒）。
///
/// **只解析**：不执行、不调用、不装载。失败一律给一句可读原因（与 `取扩展声明` 同形）——
/// 扫描面上「这一个子目录不是模块」是**正常结局**，不该中断别的子目录（同 `后缀表.json`
/// 的「缺了照跑」）。
pub fn 取模块接口说明(模块目录: &Path, 后缀项: &str) -> Result<Vec<接口说明段::接口说明>, String> {
    let 制品文件: Vec<PathBuf> = fs::read_dir(模块目录)
        .map_err(|错误| format!("读不到目录：{错误}"))?
        .filter_map(|目录项| 目录项.ok())
        .map(|目录项| 目录项.path())
        .filter(|路径| 是模块制品(路径, 后缀项))
        .collect();
    if 制品文件.len() != 1 {
        return Err(format!("模块制品 {} 个（要求恰好 1 个）", 制品文件.len()));
    }
    let 制品字节 = fs::read(&制品文件[0]).map_err(|错误| format!("读不到制品：{错误}"))?;
    let 三段 = 容器::解包(&制品字节).map_err(|错误| format!("不是能力包件：{错误:?}"))?;
    接口说明段::解码接口组(&三段.接口说明段)
        .ok_or_else(|| "接口说明段解不开（截断 / 尾部多余字节 / 不是合法 UTF-8）".to_owned())
}

/// 一个模块目录 → 制品字节的**段指纹**是否与内容相符（旁路校验，缺了不影响解析）。
///
/// `None` = 不是本形状的包；`Some(真)` = 两段都没被换过；`Some(假)` = 被换过。
pub fn 校验模块制品指纹(模块目录: &Path, 后缀项: &str) -> Option<bool> {
    let 制品文件: Vec<PathBuf> = fs::read_dir(模块目录).ok()?
        .filter_map(|目录项| 目录项.ok())
        .map(|目录项| 目录项.path())
        .filter(|路径| 是模块制品(路径, 后缀项))
        .collect();
    if 制品文件.len() != 1 {
        return None;
    }
    let 制品字节 = fs::read(&制品文件[0]).ok()?;
    容器::校验段指纹(&制品字节)
}

/// 模块声明的**依赖表达** —— `包声明.json` 的 `标识串` / `依赖清单` / `依赖版本要求` 三栏。
///
/// **为什么读声明而不是读制品**：`.模块制品` 的段是**固定的三段**（接口说明 `16` · 本机执行体 `20` ·
/// 指纹 `18`，`扩展装载/后缀表.json`），接口说明段又固定六字段（逐条对齐 `能力声明/<编号>.json`）
/// ⇒ **制品里没有依赖清单的承载位**。依赖是**声明侧**的事（与支持库同一处：`包声明.json`），
/// 制品只承载「怎么调」与「执行体」。
pub struct 模块依赖表达 {
    /// 声明那条标识串（32 位十六进制）。
    pub 标识串: String,
    /// 本模块依赖哪些扩展（32 位十六进制标识串表）。
    pub 依赖清单: Vec<String>,
    /// 与 `依赖清单` 按下标一一对应的版本门槛（两段：主 · 次）。
    pub 依赖版本要求: Vec<版本要求>,
}

/// 一个模块目录 → 它的依赖表达（读同目录的 `包声明.json`）。
///
/// 三栏都缺不了：`标识串` 缺席 ⇒ 报因（判不了「不含自身」）；`依赖清单` 缺席 ⇒ 当空表
/// （与 `必备件.json` 的「空表 = 不依赖任何东西」同义，不是漏写）；`依赖版本要求` 缺席 ⇒ 当空表。
///
/// **只读，不判**（判在 [`判模块依赖`]）：失败一律给一句可读原因（与 `取模块接口说明` 同形）。
pub fn 取模块依赖表达(模块目录: &Path) -> Result<模块依赖表达, String> {
    let 声明件 = 模块目录.join(crate::常量::扩展声明件);
    let 声明文本 =
        fs::read_to_string(&声明件).map_err(|错误| format!("读不到 {}：{错误}", 声明件.display()))?;
    let 声明值 = crate::协议解析::解析协议值(&声明文本)
        .map_err(|错误| format!("{} 不是合法 JSON：{}", 声明件.display(), 错误.说明文字))?;
    let 标识串 = 声明值
        .取成员("标识串")
        .and_then(|待处理值| 待处理值.取文本())
        .ok_or_else(|| format!("{} 缺 标识串（声明不自洽）", 声明件.display()))?
        .to_owned();
    let mut 依赖清单: Vec<String> = Vec::new();
    if let Some(依赖项表) = 声明值.取成员("依赖清单").and_then(|待处理值| 待处理值.取数组()) {
        for 依赖项 in 依赖项表 {
            let 依赖串 = 依赖项
                .取文本()
                .ok_or_else(|| format!("{} 的 依赖清单 里有一项不是文本", 声明件.display()))?;
            依赖清单.push(依赖串.to_owned());
        }
    }
    let mut 依赖版本要求: Vec<版本要求> = Vec::new();
    if let Some(要求项表) = 声明值.取成员("依赖版本要求").and_then(|待处理值| 待处理值.取数组()) {
        for 要求项 in 要求项表 {
            let 主版本 = 要求项.取成员("主").and_then(|待处理值| 待处理值.取无符号());
            let 次版本 = 要求项.取成员("次").and_then(|待处理值| 待处理值.取无符号());
            let (Some(主版本), Some(次版本)) = (主版本, 次版本) else {
                return Err(format!("{} 的 依赖版本要求 里有一项缺 主 或 次", 声明件.display()));
            };
            let (Ok(主版本), Ok(次版本)) = (i32::try_from(主版本), i32::try_from(次版本)) else {
                return Err(format!("{} 的 依赖版本要求 里有一项超出范围", 声明件.display()));
            };
            依赖版本要求.push(版本要求::构造(主版本, 次版本));
        }
    }
    Ok(模块依赖表达 { 标识串, 依赖清单, 依赖版本要求 })
}

/// 判一个模块目录的**依赖表达** —— 判据**同一份**（`依赖清单合法文本`，与支持库那条路共用）。
///
/// `Ok(表达)` = 依赖全在台账里且版本够（或本模块不依赖任何东西）；`Err(原因)` = 不过。
/// 不过一律给一句可读原因（**不静默**）：调用方据此把这条模块候选报出去。
pub fn 判模块依赖(模块目录: &Path, 台账: &dyn 已载入台账) -> Result<模块依赖表达, String> {
    let 依赖表达 = 取模块依赖表达(模块目录)?;
    if !依赖清单合法文本(&依赖表达.标识串, &依赖表达.依赖清单, &依赖表达.依赖版本要求, 台账) {
        return Err(format!(
            "依赖清单不过（{} 项依赖里至少一项不在台账 / 版本不足 / 形状不符 / 重复 / 含自身）",
            依赖表达.依赖清单.len()
        ));
    }
    Ok(依赖表达)
}

