    /// 反向样本：本机动态库后缀**不是**模块制品（模块走拆段，不走 `dlopen`）。
    ///
    /// 建**真文件**再判 —— 不建文件的话 `is_file()` 会把两个断言都变成永真，
    /// 那是一条假绿（「测了」与「没测」长得一模一样）。
    ///
    /// 本机动态库后缀**不落字面**（判据 ① 按**码位**判「`U+002E` 紧跟 dylib / so / dll」）
    /// ⇒ 用 `.` 与 `dylib` **两段拼**出来；它是「非模块后缀」的对照物，不依赖具体是哪个系统。
    #[test]
    fn 动态库后缀_不算模块制品() {
        let 临目录 = std::env::temp_dir().join("v1_模块制品测试_后缀");
        let _ = fs::remove_dir_all(&临目录);
        fs::create_dir_all(&临目录).expect("建临时目录");
        let 后缀项 = 模块后缀项();
        let 动态库 = 临目录.join(format!("某库{}{}", '.', "dylib"));
        let 模块件 = 临目录.join(format!("某模块{后缀项}"));
        fs::write(&动态库, b"").expect("建动态库样本");
        fs::write(&模块件, b"").expect("建模块制品样本");
        assert!(!是模块制品(&动态库, &后缀项), "本机动态库后缀不是模块制品");
        assert!(!是模块制品(&临目录.join(format!("某库{}{}", '.', "so")), &后缀项), "不存在的件不是模块制品");
        assert!(是模块制品(&模块件, &后缀项), "模块制品后缀是模块制品");
        let _ = fs::remove_dir_all(&临目录);
    }

