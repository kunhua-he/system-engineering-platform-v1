    /// 台账：底座已预置（与装载入口的「标准台账」同一构造口）。
    fn 标准台账() -> v1_adapter::载入台账 {
        v1_adapter::载入台账::构造()
    }

    /// 底座标识串的**文本**形（32 位十六进制，不带 NUL）—— 声明侧写的就是这个形状。
    fn 底座标识文本() -> String {
        String::from_utf8_lossy(v1_adapter::声明数据::底座标识串内容).into_owned()
    }

    /// 模块自身的标识串文本（32 位十六进制）—— **不等于底座**。
    ///
    /// 样本里「自身」与「依赖」必须分开写：写成一个就成了「含自身」，那一问会先把它拦下，
    /// 于是「在台账里」与「版本够」这两问永远测不到（实测教训：三条用例曾因这一个样本退化成假绿）。
    fn 模块自身标识() -> &'static str {
        "a9f29510f9a555bd855fbed911fc2f0a"
    }

    /// 造一个**临时模块目录**：只写本测试要的那份 `包声明.json`。
    fn 造模块目录(名字: &str, 声明文本: &str) -> PathBuf {
        let 模块目录 = std::env::temp_dir().join(format!("v1_模块依赖测试_{名字}"));
        let _ = fs::remove_dir_all(&模块目录);
        fs::create_dir_all(&模块目录).expect("建临时模块目录");
        fs::write(模块目录.join(crate::常量::扩展声明件), 声明文本).expect("写包声明");
        模块目录
    }

    /// 一份**合成包声明**：只给依赖表达那三栏（其余栏本判据不读）。
    fn 合成包声明(标识串: &str, 依赖清单项: &[&str], 要求项: &[(i32, i32)]) -> String {
        let mut 依赖串表: Vec<String> = Vec::new();
        for 依赖串 in 依赖清单项 {
            依赖串表.push(format!("\"{依赖串}\""));
        }
        let mut 版本要求表: Vec<String> = Vec::new();
        for (主号, 次号) in 要求项 {
            版本要求表.push(format!("{{\"主\":{主号},\"次\":{次号}}}"));
        }
        format!(
            "{{\"标识串\":\"{标识串}\",\"依赖清单\":[{}],\"依赖版本要求\":[{}]}}",
            依赖串表.join(","),
            版本要求表.join(",")
        )
    }

