//! 资源调用响应 —— `POST /接口/资源调用` 的对外形状。
//!
//! # 它答的是哪一问
//!
//! `POST /接口/调用` 走的是**能力号**那条腿；资源号是**另一个号空间**
//! （`契约声明/号段图.json`「四个号空间互不相通」）⇒ 资源调用另开这一个旁路端点，
//! 转调的是**资源网关口**（全平台唯一的资源出入口，`资源网关口::资源调用`）。
//!
//! ```json
//! { "成功": true,  "值": [ { "类型标签": 5, "值": "<base64>" } ], "耗时微秒": N }
//! { "成功": false, "错误": { 码 · 段位 · 名称 · 可重试 · 可自愈 · 需人工 · 已登记 },
//!   "重试判据": { … }, "耗时微秒": N }
//! ```
//!
//! # 三条资源语义都出在这里的读数
//!
//! 发布验收 `必证七_资源语义` 要的三条（零输出 / 多输出拒绝 / 失败清空）**都经本端点**
//! 出生产读数 —— 不再靠 crate 级测试「推定」：
//!
//! 1. **零输出**：声明的 `输出类型` 是空表 ⇒ 成功应答的 `值` 是**空数组**
//!    （不是「一个空槽」）。
//! 2. **多输出拒绝**：声明要 n>1 位 ⇒ 黑盒体载不动（一次调用只回一个槽）⇒ `成功: false`
//!    + `错误.码 = 28 资源执行失败`（**不静默截断**）。
//! 3. **失败清空**：转调失败 ⇒ `成功: false`，`值` 键**不出现**（半截内容一个字都不交出）。
//!
//! # 失败一律回**真错误码**（段位 0 的 22–28，源 = `契约声明/错误码表/`）
//!
//! 六项（`码 · 段位 · 名称 · 可重试 · 可自愈 · 需人工`）当场从适配器现读，
//! **不另存一份表**；`重试判据` 把「这次失败有没有进执行方」翻译成机器可判的三项
//! （与 `/接口/调用` 同一口径）。

use std::time::Instant;

use v1_adapter::适配器;
use v1_resource_gateway::{关口结果, 资源错误, 资源网关口};

use crate::错误形状::{错误对象, 重试判据};
use crate::协议值::协议值;
use crate::资源调用请求::资源调用请求;

/// `POST /接口/资源调用` → 结构化结果。
///
/// **所有请求都转调资源网关口**：本函数不按号特判、不认任何具体资源号 ——
/// 七层判定（未声明 / 操作未声明 / 副作用未允许 / 输入形状不符 / 入口未绑定 /
/// 输出形状不符 / 资源执行失败）只有一份实现，在关口里。
///
/// 这里只做两件形状翻译：入参 JSON → 槽（`资源调用请求.rs`），输出槽表 → JSON
/// （`槽编码.rs`），并把输出槽**归还**（谁分配谁释放，与 `/接口/调用` 同一口径）。
pub fn 资源调用(适配器: &适配器, 关口: &资源网关口, 请求: &资源调用请求) -> 协议值 {
    let 输入槽表: Vec<v1_adapter::数据槽> = 请求
        .输入槽表
        .iter()
        .map(crate::槽编码::槽源::取槽)
        .collect();
    let 区间起点 = Instant::now();
    let 关口结果值 = 关口.资源调用(请求.资源号, 请求.操作号, &输入槽表);
    let 耗时微秒 = 区间起点.elapsed().as_micros().min(u128::from(u64::MAX)) as u64;
    match 关口结果值 {
        关口结果::成功(mut 输出槽表) => {
            let 值项 = 取值项表(&输出槽表);
            // 输出槽读完就归还：带所有权交出的堆块真回收（与 `响应.rs::调用` 同一条）。
            for 槽项 in 输出槽表.iter_mut() {
                v1_adapter::归还槽值(槽项);
            }
            造成功应答(值项, 耗时微秒)
        }
        关口结果::失败(失败值) => 造资源失败应答(适配器, &失败值, 耗时微秒),
    }
}

/// 输出槽表 → 协议值项表（每项自带 `类型标签`，调用方不需二次解析）。
fn 取值项表(输出槽表: &[v1_adapter::数据槽]) -> 协议值 {
    协议值::数组值(输出槽表.iter().map(crate::槽编码::到协议值).collect())
}

/// 成功应答：`成功: true` + `值` + `耗时微秒`（与 §三 的槽数组同形）。
fn 造成功应答(值项: 协议值, 耗时微秒: u64) -> 协议值 {
    协议值::对象值(vec![
        ("成功".to_owned(), 协议值::真值),
        ("值".to_owned(), 值项),
        ("耗时微秒".to_owned(), 耗时到协议值(耗时微秒)),
    ])
}

/// 失败应答：`成功: false` + `错误` 七项 + `重试判据` + `耗时微秒`。
///
/// **不给 `值` 键** —— 失败路径的清空语义就落在这里（半截内容一个字都不交出）。
fn 造资源失败应答(适配器: &适配器, 失败值: &资源错误, 耗时微秒: u64) -> 协议值 {
    协议值::对象值(vec![
        ("成功".to_owned(), 协议值::假值),
        (
            "错误".to_owned(),
            错误对象::由错误码(适配器, 0, 失败值.取错误码()).到协议值(),
        ),
        ("重试判据".to_owned(), 资源错误转重试判据(失败值).到协议值()),
        ("耗时微秒".to_owned(), 耗时到协议值(耗时微秒)),
    ])
}

/// 资源失败发生在哪一步 —— 与 `/接口/调用` 的 [`重试判据::由调度错误`] 同一口径
/// （语义源见 `2026-10-07_核心架构收敛方案` §九.3：**超时 = 结果未知，不自动重放**）。
///
/// 分档只看关口七层判定里**哪一层**拒的，不散到调用点：
///
/// - 第 1–5 层（未声明 / 操作未声明 / 副作用未允许 / 输入形状不符 / 入口未绑定）与
///   配额用尽**都在进执行方之前**返回 ⇒ 确定没执行。
/// - 第 6–7 层（输出形状不符 / 资源执行失败）是执行方**已经跑过**才报的 ⇒ 副作用可能已落，
///   但结局确定（它自身报了）。
/// - 超时是**执行已发生而未拿到结果** ⇒ 结果未知，不自动重放。
fn 资源错误转重试判据(失败值: &资源错误) -> 重试判据 {
    match 失败值 {
        资源错误::超时 { .. } => 重试判据::超时结果未知(),
        资源错误::输出形状不符 { .. } | 资源错误::资源执行失败 { .. } => 重试判据::扩展已回错误码(),
        资源错误::资源未声明 { .. }
        | 资源错误::操作未声明 { .. }
        | 资源错误::副作用未允许 { .. }
        | 资源错误::输入形状不符 { .. }
        | 资源错误::入口未绑定 { .. }
        | 资源错误::配额用尽 { .. } => 重试判据::未进入扩展(),
    }
}

/// 耗时微秒 → 协议整数（超出 `i64` 才走无符号那一支，与 `工具响应.rs` 同口径）。
fn 耗时到协议值(耗时微秒: u64) -> 协议值 {
    match i64::try_from(耗时微秒) {
        Ok(整数值) => 协议值::整数项(整数值),
        Err(_) => 协议值::无符号值(耗时微秒),
    }
}
