//! 网关 —— **全平台唯一的对外监听**（`全局连接器与网关.md` 第四节判据 1：全仓搜监听调用点，
//! 恰好 1 处；那一处就是本文件的 `TcpListener::bind`）。
//!
//! # 只监听回环
//!
//! `接口面形状.md` §一：判据是「第一次用不需要读文档就能调对」，而「要先拿 token」正好违反
//! 它 ⇒ **不做鉴权**。没有鉴权就必须只对本机开放，故地址是 `127.0.0.1`
//! （`常量.rs` 的 `监听地址`），**不提供改成 0.0.0.0 的口**。
//!
//! # 手写 HTTP/1.1，零第三方依赖
//!
//! 本仓硬规矩：进制品的形态必须零第三方依赖。HTTP 只用到一小块（请求行 · 头 · 定长体 ·
//! 一行响应头），手写比引一个运行时更可判。
//!
//! **明确不做**（都是 `接口面形状.md` §一 判据的直接后果，不是偏好）：
//!
//! - 不做握手 / 会话 / 连接管理：每次应答都带 `Connection: close` 并关闭连接。入口无状态。
//! - 不做 `Transfer-Encoding: chunked`：收到即 400（要支持它就得做流式状态机 = 连接管理）。
//! - 不做 `keep-alive` / `pipelining`：一个连接一个请求，读到定长体为止，余料丢弃。
//! - 不做鉴权 / 不做 CORS：静态文件与前端同源，同源不需要 CORS。
//!
//! # §五 的静态托管就在这一个监听上
//!
//! `接口面形状.md` §五 定「静态文件（前端自身的件）由接口面进程托管，**同源**」——
//! 它落在这里：同一个 `TcpListener`、同一个 accept 循环，**不开第二个监听口**
//! （判据 ⑪「对外监听恰好 1 处」；独立 dev server 就是第二个口）。托管根是注入的
//! 部署事实（[`服务::托管静态根`]），件怎么取、哪些路径不许取见 `静态件.rs`。
//!
//! # 并发收连接
//!
//! accept 循环**并发**：起 N 个工作线程（[`服务::跑并发`]），每个各自 `accept` 并处理，
//! 处理完再 `accept` 下一个。N 由 [`默认并发线程数`] 给（本机可用并行度），或由调用方指定。
//!
//! 根因修在**适配器**：适配器已声明 `Send` + `Sync`（`跨语言适配/适配器实现/src/线程安全.rs`）
//! ⇒ 网关能共享同一个适配器。网关这边**一条 `unsafe` 都没有**：`服务` 自动 `Sync`，
//! 因为契约身份是标量快照（不是带裸指针的 `&'static 平台信息`），其余字段是原子/`PathBuf`。
//!
//! 每个连接仍设读写超时（`读超时毫秒`）：一个挂住的客户端最多挡住一个工作线程一次超时的
//! 时长，不再挡住整个门。

use crate::协议解析;
use crate::分发::{应答, 处理, 拒绝状态码};
use crate::报文读写::{报文, 读报文, 写响应};
use crate::路由;
use crate::常量::{监听地址, 接口端口, 工具根默认, 静态根};
use std::net::{TcpListener, TcpStream};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::time::Duration;
use v1_adapter::{版本三元组, 平台信息, 适配器, 丢弃策略, 留痕容量};

/// 单次连接的读写超时（毫秒）。**旁路常量**：它不是契约里的数，是本面的防挂死策略。
const 读超时毫秒: u64 = 2_000;

/// 绑定失败 —— 结构化，说清是哪一步。
#[derive(Debug)]
pub enum 启动失败 {
    /// 装载失败（原样转出适配器的段位，不吞、不改写）。
    装载(v1_adapter::装载失败),
    /// 端口绑不上（已被占用 / 权限不足）。
    绑定(std::io::Error),
}

/// 根端点要的契约身份 —— 从**注入的声明**上现读后存下的标量快照（版本 + 格式号）。
///
/// 为什么存标量、不存 `&'static 平台信息`：后者带裸指针、**不是 `Sync`**，
/// 会让整个 [`服务`] 不能跨线程共享 —— 而并发收连接要的正是共享 `服务`。
/// 声明是静态只读的 ⇒ 标量快照与现读等价，不是第二份事实。
#[derive(Clone, Copy, Debug)]
pub struct 契约身份 {
    pub 版本: 版本三元组,
    pub 声明格式号: u32,
}

/// 已绑定的对外门。**一个实例一套东西**：适配器 + 监听 + 契约身份 + 静态托管根 + 工具根，
/// **没有任何进程级 `static`** ⇒ 同进程开两份就是两个互不干扰的门（多实例安全）。
///
/// # 线程安全
///
/// 本类型 `Sync`（**没有一条 `unsafe` 断言**）：适配器已由 `跨语言适配/适配器实现/`
/// 自身声明 `Send` + `Sync`；契约身份是标量快照（不是 `&'static 平台信息`）；
/// 两个路径是 `PathBuf`；停止标志是原子量。所以 [`服务::跑并发`] 能把 `&服务`
/// 交给多个工作线程 —— 网关**不替下层断言任何它验证不了的事**。
///
/// `契约身份` 是**注入的声明**（声明根的第一份，适配器约定「底座排在最前」）：
/// 根端点要的 `契约版本` 与 `声明格式号` 从它上面现读。网关**不自行去取声明** ——
/// 「谁把声明递进来」是装配与扩展装载那条腿的事，网关自身去找就是跳层。
///
/// `静态根` 是 §五 的**托管目录**（前端自身的件住的地方），同样是**注入的部署事实**：
/// 默认是 `常量.rs` 的 `静态根`（相对进程工作目录），装配侧要换根就调
/// [`服务::托管静态根`]。网关不替它猜一个位置（猜错就是「页面打得开、件取不到」）。
///
/// `工具根` 是 §七 工具族的**部署事实**（案例库 · 扩展根声明 · 外部 CLI 的所在），
/// 默认是进程工作目录（仓根口径，与 `静态根` 同一条约定），装配侧要换就调 [`服务::工具根`]。
pub struct 服务 {
    适配器: 适配器,
    契约身份: 契约身份,
    静态根: PathBuf,
    工具根: PathBuf,
    监听: TcpListener,
    端口: u16,
    /// 停止标志（[`服务::请求停止`] 置位；工作线程据此退出）。
    停止: AtomicBool,
    /// 已起的工作线程数（`请求停止` 按它叫醒同样多次，把阻塞在 `accept` 上的线程放出来）。
    并发线程数: AtomicUsize,
}

impl 服务 {
    /// 装载声明根 → 绑定 `127.0.0.1:端口`。静态托管根取 [`静态根`]（相对进程工作目录）。
    ///
    /// `端口` 传 `0` 让 OS 分配（测试与多实例用；实际端口由 [`服务::端口`] 报出）。
    pub fn 绑定(声明根: &[&'static 平台信息], 端口: u16) -> Result<Self, 启动失败> {
        Self::绑定并托管(声明根, 端口, PathBuf::from(静态根))
    }

    /// 用契约里的默认端口绑定（`常量.rs` 的 `接口端口`，来源 `契约声明/常量表.json`）。
    pub fn 绑定默认端口(声明根: &[&'static 平台信息]) -> Result<Self, 启动失败> {
        Self::绑定(声明根, 接口端口)
    }

    /// 绑定并**显式指定**静态托管根（装配侧注入；测试也走这一口）。
    ///
    /// 为什么托管根要能注入：它是**部署事实**（前端自身的件住哪），与声明根同类 ——
    /// 编进制品（`env!("CARGO_MANIFEST_DIR")`）会让制品带上构建机的绝对路径，
    /// 而制品要「按体积与确定性优先」（根 `Cargo.toml` 的 release 段）。
    pub fn 绑定并托管(
        声明根: &[&'static 平台信息],
        端口: u16,
        托管根: impl Into<PathBuf>,
    ) -> Result<Self, 启动失败> {
        let 契约来源 = *声明根
            .first()
            .ok_or(启动失败::装载(v1_adapter::装载失败::空声明根))?;
        // 根端点要的契约身份：从注入的声明上现读成标量（见 `契约身份` 的理由）。
        let 契约身份 = 契约身份 {
            版本: 契约来源.实现版本,
            声明格式号: 契约来源.声明格式号.取(),
        };
        // 唯一腿：所有请求都转调它（`适配器::装载声明根` 是全平台唯一的那一处 `载入`）。
        let mut 适配器 = 适配器::装载声明根(声明根).map_err(启动失败::装载)?;
        // 留痕：容量取自契约常量 `留痕容量` ⇒ README §三「每次调用留痕」在
        // **生产装配**里成立（`适配器::装载` 自身不发明容量，装配侧给 —— 见 `留痕口.rs`）。
        // 不进关键路径（不取锁、不等待、不分配）；满了丢最旧并计数（丢痕不许静默）。
        适配器.启用留痕(留痕容量, 丢弃策略::丢最旧);
        let 监听 = TcpListener::bind((监听地址, 端口)).map_err(启动失败::绑定)?;
        let 端口 = 监听.local_addr().map_err(启动失败::绑定)?.port();
        Ok(Self {
            适配器,
            契约身份,
            静态根: 托管根.into(),
            工具根: PathBuf::from(工具根默认),
            监听,
            端口,
            停止: AtomicBool::new(false),
            并发线程数: AtomicUsize::new(1),
        })
    }

    /// 换静态托管根（装配侧的口）。**`/` 与前端自身的件从这一刻起从新根取**。
    ///
    /// 为什么是「换」而不是构造参数：托管根与声明根不同 —— 声明根缺了根本起不来服务，
    /// 而托管根缺了只是 `/` 回 404（前端没有同源的家），服务照样能跑、接口照样能调。
    pub fn 托管静态根(mut self, 根: impl Into<PathBuf>) -> Self {
        self.静态根 = 根.into();
        self
    }

    /// 换工具根（装配侧的口）。**§七 工具族的案例库 / 扩展根 / 外部 CLI 从这一刻起从新根取。**
    ///
    /// 与 `托管静态根` 同一形状、同一理由：工具根是**部署事实**（不是契约里的数），
    /// 缺了只是那些旁路端点回真错误码（9002 / 9007 / 9005），服务照样能跑。
    pub fn 工具根(mut self, 根: impl Into<PathBuf>) -> Self {
        self.工具根 = 根.into();
        self
    }

    /// 工具根（§七）。装配侧与测试读它来判「工具族接上了没有」。
    pub fn 取工具根(&self) -> &Path {
        &self.工具根
    }

    /// 启用调用留痕：容量与策略由装配侧给（生产装配在 [`服务::绑定并托管`]
    /// 里用契约常量 `留痕容量` + `丢最旧` 开；本口留给要换容量/策略的装配方）。
    ///
    /// 必须在**共享出去之前**调（`&mut self`）；开与不开发影响的是
    /// `GET /接口/留痕` 有没有内容，不影响任何调用结果（留痕不进关键路径）。
    pub fn 启用留痕(&mut self, 容量: u32, 策略: v1_adapter::丢弃策略) {
        self.适配器.启用留痕(容量, 策略);
    }

    /// **真正绑上的端口**。根端点的 `实际端口` 报的就是它（不报常量：测试与多实例下
    /// 报常量就是一个假事实）。
    pub fn 端口(&self) -> u16 {
        self.端口
    }

    /// 静态托管的根（`接口面形状.md` §五）。装配侧与测试读它来判「托管接上了没有」。
    pub fn 静态根(&self) -> &Path {
        &self.静态根
    }

    /// 唯一腿（验证面与装配用）。
    pub fn 适配器(&self) -> &适配器 {
        &self.适配器
    }

    /// 接受一个连接、处理一次、关闭。**一个连接一个请求**（不做连接管理）。
    ///
    /// 单列一个口（而不是只给 `跑`）：它让「真起服务真发请求」的测试不必开线程 ——
    /// 客户端先 `connect`（内核的 accept 队列会接住），再调本函数，再读应答。
    pub fn 处理一个连接(&self) -> std::io::Result<()> {
        let (mut 流, _) = self.监听.accept()?;
        let 超时 = Some(Duration::from_millis(读超时毫秒));
        流.set_read_timeout(超时)?;
        流.set_write_timeout(超时)?;
        let 应答 = match 读报文(&mut 流) {
            Ok(报文) => self.应答(&报文),
            // 请求本身不合法 ⇒ 400（**协议层**失败，不是业务失败）。
            Err(说明) => 应答::协议(400, &说明),
        };
        写响应(&mut 流, &应答)
    }

    /// 一直服务下去（生产入口；`跑` 不返回 `Ok`）。
    ///
    /// 并发度取自本机可用并行度（[`默认并发线程数`]）—— 单线程 accept 是缺陷，
    /// 修法是并发，不是等。要指定线程数用 [`服务::跑并发`]。
    pub fn 跑(&self) -> std::io::Result<()> {
        self.跑并发(默认并发线程数())
    }

    /// **并发收连接**：起 `工作线程数` 个工作线程，每个各自 `accept` 并处理，
    /// 处理完再 `accept` 下一个。`accept` 由内核串行化派发，N 个线程 = 最多 N 条连接同时在处理。
    ///
    /// 为什么可以共享 `&self`：适配器已声明 `Send` + `Sync`（`线程安全.rs`），`服务` 其余
    /// 字段都是标量/原子/`PathBuf`/`TcpListener` ⇒ `服务` 自动 `Sync`（无 `unsafe`）。
    ///
    /// 用 `std::thread::scope`：工作线程借用 `&self`，作用域结束时必然汇合 ——
    /// 不需要 `Arc`，也不留游离线程。要它停下来调 [`服务::请求停止`]。
    ///
    /// 生产里它不返回 `Ok`（除非被 `请求停止` 叫停）；`工作线程数` 至少 1。
    pub fn 跑并发(&self, 工作线程数: usize) -> std::io::Result<()> {
        let 线程数 = 工作线程数.max(1);
        self.并发线程数.store(线程数, Ordering::Release);
        std::thread::scope(|作用域| {
            let mut 把手 = Vec::with_capacity(线程数);
            for _ in 0..线程数 {
                把手.push(作用域.spawn(|| self.工作循环()));
            }
            for 手 in 把手 {
                // 工作线程不 panic（`工作循环` 只吞 io 错误）；真 panic 了也不许把
                // 汇合变成二次 panic —— 记下、继续汇合其余线程。
                let _ = 手.join();
            }
        });
        Ok(())
    }

    /// 请求停止（**服务级**停止口，不是「卸载」）：置标志 + 叫醒阻塞在
    /// `accept` 上的工作线程，让 [`服务::跑并发`] 返回。
    ///
    /// 为什么叫醒要「连一下」：`accept` 是阻塞调用，光置标志唤不醒它。连 `并发线程数` 次
    /// 短连接，每个被阻塞的线程各接住一条，随即看到标志并退出。
    pub fn 请求停止(&self) {
        self.停止.store(true, Ordering::Release);
        let 次数 = self.并发线程数.load(Ordering::Acquire).max(1);
        for _ in 0..次数 {
            let _ = TcpStream::connect((监听地址, self.端口));
        }
    }

    /// 一个工作线程的循环：`accept` → 处理 → 再看停止标志。
    ///
    /// 瞬时 io 错误（连接中断 / 超时）**不许把整个门带走**：歇 1 毫秒再来。
    /// 只有在停止标志已置位时才退出。
    fn 工作循环(&self) {
        while !self.停止.load(Ordering::Acquire) {
            match self.处理一个连接() {
                Ok(()) => {}
                Err(_错) => {
                    if self.停止.load(Ordering::Acquire) {
                        break;
                    }
                    // 瞬时错误（连接中断 / 超时）不许把门带走，也不许空转烧 CPU：歇 1 毫秒。
                    std::thread::sleep(Duration::from_millis(1));
                }
            }
        }
    }

    /// 一次请求 → 一次应答。**纯分发**：先认端点，再交给 `端点::处理`。
    fn 应答(&self, 报文: &报文) -> 应答 {
        let 落点 = match 路由::认(&报文.方法, &报文.目标) {
            Ok(落点) => 落点,
            Err(拒绝) => return 应答::协议(拒绝状态码(&拒绝), &拒绝.说明()),
        };
        // 请求体只对**收体的端点**解析：GET 的体与本面无关，不去判它。
        // 旁路端点里，收体的那些同样走这里（§七 + 生命周期卸载）。
        let 体 = match 落点 {
            crate::路由::端点::调用
            | crate::路由::端点::声明
            | crate::路由::端点::案例跑
            | crate::路由::端点::导出
            | crate::路由::端点::程序文本
            | crate::路由::端点::菜单命令
            | crate::路由::端点::生命周期卸载 => match 协议解析::解析(&报文.体) {
                Ok(体) => Some(体),
                Err(错) => {
                    return 应答::协议(
                        400,
                        &format!("请求体不是合法 JSON：{}（第 {} 字节）", 错.说明, 错.位置),
                    );
                }
            },
            _ => None,
        };
        处理(
            &self.适配器,
            &self.契约身份,
            self.端口,
            &self.静态根,
            &self.工具根,
            落点,
            体.as_ref(),
        )
    }
}

/// 默认并发线程数：本机可用并行度，取不到就退到 1。
///
/// **不是契约里的数**（不进 `常量表.json`）：它是部署事实 —— 由跑它的机器决定，
/// 与「端口只有一个来源」不同（端口是契约事实）。取不到可用并行度时退 1 = 退回旧行为，
/// 不猜一个数。
pub fn 默认并发线程数() -> usize {
    std::thread::available_parallelism()
        .map(|并行度| 并行度.get())
        .unwrap_or(1)
}
