/// **线程池打满时健康请求仍有界返回**（本件 3072）。
///
/// 高并发不成立时报告过的现象：「≥ N 并发慢调用 ⇒ 健康请求堵在内核 accept 队列」。
/// 本样本把那条现象钉成**可判的验收句**：一条连接一条工作线程，每个连接最多占用一条
/// 线程到读写超时（本面读超时 = 2 秒）—— 占满 N 条线程后，第 N+1 条健康请求会排在
/// accept 队列里，但它**不许被丢、也不许无限等**；一旦有工作线程按超时释放，
/// 健康请求必须拿到正确应答。
///
/// 反证：若把「排队」错写成「丢连接」（或排队期无界），本用例会拿不到应答 / 超时判红。
#[test]
fn 线程池打满时健康请求仍有界返回() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 监听端口 = 服务.监听端口();
    // 先占满工作线程：N 条连接**只连不发完整请求**，读报文会在读写超时（2 秒）后放行该线程。
    let mut 占位连接 = Vec::with_capacity(服务端工作线程数);
    for _ in 0..服务端工作线程数 {
        占位连接.push(
            TcpStream::connect((监听地址, 监听端口)).expect("监听已 bind，占位连接必须连得上"),
        );
    }
    let 起点 = Instant::now();
    std::thread::scope(|作用域| {
        let 服务引用 = &服务;
        let 服务线程 = 作用域.spawn(move || {
            let _ = 服务引用.跑并发(服务端工作线程数);
        });
        // 健康请求：排在 accept 队列里，等工作线程按超时释放后才被收下。
        let 健康线程 = 作用域.spawn(move || {
            发到端口(监听端口, &取请求(&format!("/接口/能力/{编号}")))
        });
        let 造应答 = 健康线程.join().expect("客户端不许 panic");
        let 耗时 = 起点.elapsed();
        assert_eq!(造应答.状态, 200, "打满期健康请求也得走通：\n{}", 造应答.报文体);
        let 契约 = 造应答.取成员("契约");
        assert_eq!(无符号值(&契约, "编号"), u64::from(编号), "读回的编号必须是自身要的那一个");
        // 有界不是无界：读写超时 2 秒，留一倍余量。真无界（或丢连接）这里拿不到应答。
        assert!(
            耗时 < Duration::from_millis(4000),
            "打满期健康请求必须**有界**返回（读写超时为上限），实际 {耗时:?}"
        );
        // 收尾：放掉占位连接 + 停服务，让跑并发那条线程汇合。
        drop(占位连接);
        服务.请求停止();
        服务线程.join().expect("服务线程必须被 请求停止 叫醒");
    });
}

// ── 读侧失败的三类**可编程区分**（状态码仍 400，正文多一个 `种类`）──
//
// 三条正向样本各打一类失败；一条反向守卫钉住「只有读报文失败那一支带 `种类`」。
// 种类名逐字比对（与 `报文错误::种类名` 同一口径），不靠人眼看正文；
// 反向样本：把 `网关.rs` 的 `协议错误带种类` 改回 `协议错误` ⇒ 前两条当场红。

/// 半截头停到读超时 ⇒ 400 且 `种类 == "读超时"`（慢客户端 ≠ 非法报文）。
#[test]
fn 报文错误_半截头停到超时_种类是读超时() {
    let 服务 = 起服务();
    // 只有请求行 + 一个头，**不给空行** ⇒ 服务端 read 阻塞到 `读超时毫秒`（2 s）。
    let 半截头 = "GET /接口 HTTP/1.1\r\nHost: 127.0.0.1\r\n";
    let 区间起点 = Instant::now();
    let 应答 = 发请求(&服务, 半截头);
    let 耗时 = 区间起点.elapsed();
    assert_eq!(应答.状态, 400, "读侧失败仍是 400（不加 408）：\n{}", 应答.报文体);
    assert_eq!(
        应答.取文本("种类"),
        "读超时",
        "慢客户端必须与非法报文分开：\n{}",
        应答.报文体
    );
    assert!(!应答.取文本("协议错误").is_empty(), "可读说明照旧在：\n{}", 应答.报文体);
    assert!(
        耗时 >= Duration::from_millis(1_000),
        "本样本要真走到读超时（非立即拒），实际 {耗时:?}"
    );
}

