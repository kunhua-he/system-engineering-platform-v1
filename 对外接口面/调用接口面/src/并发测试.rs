/// 对端**受控半关闭写侧** ⇒ 400 且 `种类 == "对端断开"`，且应答真能读回（EOF 分类不是猜的）。
#[test]
fn 报文错误_对端半关闭写侧_种类是对端断开() {
    let 服务 = 起服务();
    let mut 输出流 = TcpStream::connect((监听地址, 服务.监听端口())).expect("监听已 bind");
    {
        use std::io::Write as _;
        输出流.write_all("GET /接口 HTTP/1.1\r\nHost: 127.0.0.1\r\n".as_bytes()).expect("写半截头");
        输出流.flush().expect("刷请求");
    }
    // **只关写侧**：对端不会再发（服务端 read 得 EOF），但读侧仍开着 ⇒ 应答能读回来。
    输出流.shutdown(std::net::Shutdown::Write).expect("半关闭写侧");
    服务.处理一个连接().expect("服务必须处理一次");
    let mut 缓冲 = Vec::new();
    std::io::Read::read_to_end(&mut 输出流, &mut 缓冲).expect("读应答");
    let 应答 = 解析应答(&缓冲);
    assert_eq!(应答.状态, 400, "{}", 应答.报文体);
    assert_eq!(
        应答.取文本("种类"),
        "对端断开",
        "EOF 必须与协议不合法分开：\n{}",
        应答.报文体
    );
}

/// 反向守卫：**非读侧失败不带 `种类`**（成功应答与路由类 404 都走既有 `协议错误`）。
#[test]
fn 报文错误_非读侧失败不带种类() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 正常应答 = 发请求(&服务, &取请求(&format!("/接口/能力/{编号}")));
    assert_eq!(正常应答.状态, 200, "{}", 正常应答.报文体);
    assert!(
        正常应答.找成员("种类").is_none(),
        "成功应答不许带 种类：\n{}",
        正常应答.报文体
    );
    let 未知 = 发请求(&服务, &取请求("/接口/没有这个端点"));
    assert_eq!(未知.状态, 404, "{}", 未知.报文体);
    assert!(
        未知.找成员("种类").is_none(),
        "路由类协议错误不许带 种类（只有读报文失败那一支有）：\n{}",
        未知.报文体
    );
}
