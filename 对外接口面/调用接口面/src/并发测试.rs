//! 并发收连接与互不串味 —— **可跑验证**。
//!
//! # 它证什么
//!
//! 「高并发不成立：网关单线程 accept（根因在适配器，不在网关）」。
//! 本文件同时证两件：
//!
//! 1. **并发收连接真的发生了**：服务端用 [`crate::服务::跑并发`] 起 4 个工作线程，
//!    客户端起 12 条连接**同时**打 —— 连接数 > 工作线程数，逼出「一个线程处理完再接下一个」
//!    之外的真正并发。
//! 2. **互不串味、结果正确**：每条连接带一个**只属于自身**的请求（按契约填满 ⇒ 成功；
//!    少填一位 ⇒ 参数个数不符 码 3），结局必须各归各的连接 —— 串味会把其中一种报成另一种。
//!    另发一条只读请求，钉住「读与调同一条路」在并发下同样成立（读回的编号必须是自身要的）。
//!
//! # 为什么服务端线程与客户端线程都要开
//!
//! `服务::跑并发` 会**阻塞**到 [`crate::服务::请求停止`] 被调用，所以它得在自身的线程里跑；
//! 客户端也只能自身开线程（`测试夹具::发请求` 自带一次 `处理一个连接`，与并发的服务端会抢同一个
//! 连接，故这里用纯客户端 [`crate::测试夹具::发到端口`]）。

use std::sync::atomic::{AtomicUsize, Ordering};

use crate::测试夹具::{
    发到端口, 取请求, 交POST请求, 取逻辑值, 第一个能力号, 源文本, 无符号值, 取成员数组, 起服务,
};

/// 客户端连接数（**故意大于**工作线程数：让「排队 + 并发」都走到）。
const 客户端数: usize = 12;
/// 服务端工作线程数。
const 服务端工作线程数: usize = 4;

/// 12 条连接同时调用：成功与失败各归各的连接，读回的编号是自身要的。
#[test]
fn 并发_多连接同时调用互不串味() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 参数个数 = 服务
        .适配器()
        .能力契约(编号)
        .expect("契约")
        .参数表
        .len();
    let 监听端口 = 服务.监听端口();
    let 完成数 = &AtomicUsize::new(0);

    std::thread::scope(|作用域| {
        let 服务引用 = &服务;
        let 服务线程 = 作用域.spawn(move || {
            let _ = 服务引用.跑并发(服务端工作线程数);
        });

        let mut 客户端 = Vec::with_capacity(客户端数);
        for 序号 in 0..客户端数 {
            客户端.push(作用域.spawn(move || {
                // 偶序：按契约行序填满 ⇒ 成功；奇序：少填一位 ⇒ 参数个数不符（码 3）。
                let 本次参数个数 = if 序号 % 2 == 0 {
                    参数个数
                } else {
                    参数个数.saturating_sub(1)
                };
                let 空槽文本 = "{\"类型标签\":0,\"值\":0}";
                let 值数组文本 = vec![空槽文本; 本次参数个数].join(",");
                let 请求体 = format!("{{\"编号\":{编号},\"值\":[{值数组文本}]}}");
                let 造应答 = 发到端口(监听端口, &交POST请求("/接口/调用", &请求体));
                assert_eq!(造应答.状态, 200, "序号 {序号}：业务失败也是 200");
                if 序号 % 2 == 0 {
                    assert!(造应答.取逻辑值("成功"), "序号 {序号}（填满）必须成功：\n{}", 造应答.报文体);
                    assert!(!造应答.取数组("值").is_empty(), "序号 {序号}：成功必须带值");
                } else {
                    assert!(!造应答.取逻辑值("成功"), "序号 {序号}（少填）必须失败：\n{}", 造应答.报文体);
                    let 错误 = 造应答.取成员("错误");
                    assert_eq!(无符号值(&错误, "码"), 3, "序号 {序号}：参数个数不符");
                    assert_eq!(源文本(&错误, "名称"), "参数个数不符");
                    assert!(
                        取逻辑值(&错误, "已登记"),
                        "序号 {序号}：码 3 必须从声明现读到登记项"
                    );
                }

                // 再发一条只读请求：并发下「读与调同一条路」照样成立。
                let 造应答 = 发到端口(监听端口, &取请求(&format!("/接口/能力/{编号}")));
                assert_eq!(造应答.状态, 200, "序号 {序号}");
                let 契约 = 造应答.取成员("契约");
                assert_eq!(
                    无符号值(&契约, "编号"),
                    u64::from(编号),
                    "序号 {序号}：读回的编号必须是自身要的那一个"
                );
                assert_eq!(
                    取成员数组(&契约, "参数表").len(),
                    参数个数,
                    "序号 {序号}：参数表行数必须与契约一致"
                );
                完成数.fetch_add(1, Ordering::SeqCst);
            }));
        }
        for 线程把手 in 客户端 {
            线程把手.join().expect("客户端不许 panic");
        }
        assert_eq!(
            完成数.load(Ordering::SeqCst),
            客户端数,
            "每条连接都必须拿到自身的应答"
        );

        // 停服务：置标志 + 叫醒阻塞在 accept 上的工作线程。
        服务.请求停止();
        服务线程.join().expect("服务线程必须被 请求停止 叫醒");
    });
}

/// 默认并发线程数**至少 1**（取不到可用并行度就退 1，不猜一个数）。
#[test]
fn 默认并发线程数_至少一() {
    assert!(crate::默认并发线程数() >= 1);
}
