//! JSON 值模型 —— 手写，零第三方依赖（本仓硬规矩：进制品的形态必须零第三方依赖）。
//!
//! **对象用 `Vec<(键, 值)>` 而不是哈希表**，两个理由：
//!
//! 1. 键序稳定 ⇒ 同一份请求两次序列化**逐字节相同**（`开发规范.md`「确定性优先」）。
//! 2. 只读实现（本 crate 只用 JSON 收发小对象）不需要哈希；少一个数据结构少一处不一致。
//!
//! 键查找是线性扫（对象都只有几个键）；**不静默取重复键的第一个**——
//! 重复键是请求形状不合法，由解析层当场拒（见 `协议解析.rs`）。

/// 一个 JSON 值。**只做形状**：不解释键的含义，那是各端点自身的事。
///
/// 实现 `PartialEq` 是为了验证面能直接比两次应答的值数组（「入口无状态」那条判据：
/// 同一条请求两次的结果必须逐字段相同）。
#[derive(Debug, Clone, PartialEq)]
pub enum 协议值 {
    空值,
    真,
    假,
    整数(i64),
    /// 超出 `i64::MAX` 但仍在 64 位无符号范围内的整数。
    ///
    /// 为什么要单列一支：`数据槽.值` 是 `u64`，句柄就是「只传数值的不透明值」，
    /// 一个高位句柄塞进 `i64` 会被静默改写 —— 那是把语义改错，不是丢精度。
    无符号(u64),
    小数(f64),
    文本(String),
    数组(Vec<协议值>),
    /// 键序 = 插入序，重复键在解析层就被拒。
    对象(Vec<(String, 协议值)>),
}

impl 协议值 {
    /// 按名取一个成员。非对象、无此键、值为 `null` 都给 `None`
    /// （`null` 在契约里是「编号留空」这类**显式空位**，不是「有这个键」）。
    pub fn 取成员(&self, 键名: &str) -> Option<&协议值> {
        match self {
            协议值::对象(成员) => 成员
                .iter()
                .find(|(名称, _)| 名称 == 键名)
                .map(|(_, 待处理值)| 待处理值)
                .filter(|待处理值| !matches!(待处理值, 协议值::空值)),
            _ => None,
        }
    }

    /// 这个键在不在（含值为 `null` 的情形）。`POST /接口/声明` 的 `编号: null` 靠它。
    pub fn 是否含键(&self, 键名: &str) -> bool {
        match self {
            协议值::对象(成员) => 成员.iter().any(|(名称, _)| 名称 == 键名),
            _ => false,
        }
    }

    pub fn 是空(&self) -> bool {
        matches!(self, 协议值::空值)
    }

    pub fn 取文本(&self) -> Option<&str> {
        match self {
            协议值::文本(文) => Some(文),
            _ => None,
        }
    }

    pub fn 取数组(&self) -> Option<&[协议值]> {
        match self {
            协议值::数组(项) => Some(项),
            _ => None,
        }
    }

    /// 取一个非负整数（`编号` · `类型标签` · `长度` 一类）。
    ///
    /// **只收整数，不收小数**：`1.0` 与 `1` 在 JSON 里是两种形状，
    /// 「形状不合法」当场报 400，比替调用方猜一个 `1` 更可解释。
    /// 负值也拒——编号 / 标签 / 长度都不是负的。
    pub fn 取无符号(&self) -> Option<u64> {
        match self {
            协议值::整数(数) if *数 >= 0 => Some(*数 as u64),
            协议值::无符号(数) => Some(*数),
            _ => None,
        }
    }

    /// 取一个 64 位有符号整数（`类型标签 1 = 整数` 的入参）。
    pub fn 取有符号(&self) -> Option<i64> {
        match self {
            协议值::整数(数) => Some(*数),
            协议值::无符号(数) => i64::try_from(*数).ok(),
            _ => None,
        }
    }

    /// 取一个数值（`类型标签 2 = 双精度` 的入参）。整数与小数都收。
    pub fn 取数值(&self) -> Option<f64> {
        match self {
            协议值::整数(数) => Some(*数 as f64),
            协议值::无符号(数) => Some(*数 as f64),
            协议值::小数(数) => Some(*数),
            _ => None,
        }
    }
}
