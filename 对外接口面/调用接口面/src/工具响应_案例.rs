//! §七 案例族：`GET /接口/案例`（列案例）· `POST /接口/案例/跑`（跑案例）。
//!
//! 返回组装只走共用件（`super::造成功应答` / `super::造失败应答` / `造键文对` / `取相对路径` / `读JSON件` / `列子目录`）
//! —— 形状与这一族码的口径全在 `工具响应.rs` 的文件头，本件不另立一套。

use super::{列子目录, 造失败应答, 造键文对, 造成功应答, 取相对路径, 读JSON件};
use crate::常量::{self, 工具码};
use crate::协议值::协议值;
use crate::工具链;
use std::path::Path;
use std::time::Instant;
use v1_adapter::适配器;

// ════════════════════════════════════════════════════════════════════════════
// 二 案例族：`GET /接口/案例` · `POST /接口/案例/跑`
// ════════════════════════════════════════════════════════════════════════════

/// 读 `运行回执.jsonl`：**一行一条，按行序**。坏行给 `None`（**不跳过**——
/// 跳过后行号就与文件对不上，「跑前几行、跑后几行」这条判据会静默错位）。
fn 读回执行(案例根: &Path) -> Vec<Option<协议值>> {
    let 路径 = 案例根.join(常量::案例回执件);
    let Ok(文本) = std::fs::read_to_string(&路径) else {
        // 件不存在 = 从没跑过。**这不是失败**（列案例照样列得出来），故给空表。
        return Vec::new();
    };
    文本
        .lines()
        .filter(|源码行| !源码行.trim().is_empty())
        .map(|源码行| crate::协议解析::解析协议值(源码行).ok())
        .collect()
}

/// 回执里某个案例名最近一条读数（取**最后**一条：回执是追加式的）。
fn 最新回执<'行表>(
    行表: &'行表 [Option<协议值>],
    案例名: &str,
) -> Option<&'行表 协议值> {
    行表.iter().rev().find_map(|源码行| {
        源码行.as_ref()
            .filter(|待处理值| 待处理值.取成员("案例名").and_then(协议值::取文本) == Some(案例名))
    })
}

/// `GET /接口/案例` → 案例清单（每个案例带「有没有回执」）。
///
/// **失败码 `9002 案例不存在`**：案例根读不到 ⇒ 整个案例库都不存在，
/// 于是「请求的案例标识在案例库里查不到」对**每一个**标识都成立 —— 这正是 9002 的说明。
/// （`9003` 是另一件事：「跑过但没回执」，只有跑案例端点会回它。）
pub fn 列案例(适配器: &适配器, 工具根: &Path) -> 协议值 {
    let 区间起点 = Instant::now();
    let 案例根 = 工具根.join(常量::案例根);
    let 目录表 = match 列子目录(&案例根) {
        Ok(项表) => 项表,
        Err(说明文字) => {
            return 造失败应答(
                适配器,
                工具码::案例不存在,
                Some(协议值::对象(vec![
                    造键文对("案例根", &取相对路径(工具根, &案例根)),
                    造键文对("缺什么", &说明文字),
                ])),
                &区间起点,
            );
        }
    };

    let 行表 = 读回执行(&案例根);
    let 坏行数 = 行表.iter().filter(|源码行| 源码行.is_none()).count();
    let mut 案例表 = Vec::new();
    for 标识 in 目录表 {
        let 声明件 = 案例根.join(&标识).join(常量::案例声明件);
        // 没有 `案例.json` 的子目录**不是案例**（案例根下还有一个 `跑案例/` 是 crate 目录）——
        // 那不是「坏了」，是「不是案例」，故跳过。
        if !声明件.is_file() {
            continue;
        }
        // 有 `案例.json` 却读不了 ⇒ **如实列出来**（不静默跳过：跳过就是把它藏起来）。
        let 声明 = match 读JSON件(&声明件) {
            Ok(声明) => 声明,
            Err(说明文字) => {
                案例表.push(协议值::对象(vec![
                    造键文对("案例标识", &标识),
                    造键文对("案例名", &标识),
                    ("有回执".to_owned(), 协议值::假值),
                    ("最新回执".to_owned(), 协议值::空值项),
                    造键文对("声明读不到", &说明文字),
                ]));
                continue;
            }
        };
        let 案例名 = 声明
            .取成员("案例名")
            .and_then(协议值::取文本)
            .unwrap_or(&标识)
            .to_owned();
        let 回执 = 最新回执(&行表, &案例名);
        let mut 成员 = vec![
            造键文对("案例标识", &标识),
            造键文对("案例名", &案例名),
            (
                "有回执".to_owned(),
                if 回执.is_some() {
                    协议值::真值
                } else {
                    协议值::假值
                },
            ),
        ];
        if let Some(说明文字) = 声明.取成员("说明").and_then(协议值::取文本) {
            成员.push(造键文对("说明", 说明文字));
        }
        match 回执 {
            Some(待处理值) => 成员.push(("最新回执".to_owned(), 待处理值.clone())),
            None => 成员.push(("最新回执".to_owned(), 协议值::空值项)),
        }
        案例表.push(协议值::对象(成员));
    }

    造成功应答(
        协议值::对象(vec![
            造键文对("案例根", &取相对路径(工具根, &案例根)),
            造键文对("回执件", 常量::案例回执件),
            (
                "回执行数".to_owned(),
                协议值::整数(行表.len() as i64),
            ),
            (
                "坏回执行数".to_owned(),
                协议值::整数(坏行数 as i64),
            ),
            ("案例".to_owned(), 协议值::数组(案例表)),
        ]),
        &区间起点,
    )
}

/// `POST /接口/案例/跑` → 转调 `v1-case-runner`，只认**它这次新落的那一行**回执。
///
/// 三种结局，三种码：
///
/// | 观测到 | 回 | 为什么是这一个码 |
/// |---|---|---|
/// | 案例目录里没有 `案例.json` | `9002 案例不存在` | 标识查不到 |
/// | 跑者起不来 / 新行里没有本案例 | `9003 案例回执缺失` | 判据要的是「案例 + 回执」两件齐 |
/// | 新行里有本案例 | 成功 | `案例结果` 单独报「通过 / 失败」——**不把案例的失败写成动作的失败**（同 `形状.md` §二：调用结果与符合期望是两个字段） |
pub fn 跑案例(适配器: &适配器, 工具根: &Path, 案例标识: &str) -> 协议值 {
    let 区间起点 = Instant::now();
    let 案例根 = 工具根.join(常量::案例根);
    let 声明件 = 案例根.join(案例标识).join(常量::案例声明件);
    if !声明件.is_file() {
        return 造失败应答(
            适配器,
            工具码::案例不存在,
            Some(协议值::对象(vec![
                造键文对("案例标识", 案例标识),
                造键文对("案例根", &取相对路径(工具根, &案例根)),
                造键文对(
                    "缺什么",
                    &format!("案例库里没有这个标识（该目录下没有 {}）", 常量::案例声明件),
                ),
            ])),
            &区间起点,
        );
    }
    let 案例名 = 读JSON件(&声明件)
        .ok()
        .and_then(|待处理值| 待处理值.取成员("案例名").and_then(协议值::取文本).map(str::to_owned))
        .unwrap_or_else(|| 案例标识.to_owned());

    // 跑前先数行：**只认新增的行**。不数行的话，「跑完了但没落回执」会被上一次的旧回执
    // 掩盖成成功 —— 那正是 9003 要防的假绿。
    let 跑前行数 = 读回执行(&案例根).len();
    let 跑者 = 工具根.join(常量::案例跑者);
    let 读数 = match 工具链::跑命令取读数(&跑者, &[], 工具根) {
        Ok(读数) => 读数,
        Err(错误) => {
            return 造失败应答(
                适配器,
                工具码::案例回执缺失,
                Some(协议值::对象(vec![
                    造键文对("案例标识", 案例标识),
                    造键文对("案例跑者", &取相对路径(工具根, &跑者)),
                    造键文对("失败因", 错误.失败因()),
                    造键文对("缺什么", &错误.to_string()),
                ])),
                &区间起点,
            );
        }
    };

    let 行表 = 读回执行(&案例根);
    let 新行: Vec<Option<协议值>> = 行表.into_iter().skip(跑前行数).collect();
    let 本案例 = 新行.iter().rev().find_map(|源码行| {
        源码行.as_ref()
            .filter(|待处理值| 待处理值.取成员("案例名").and_then(协议值::取文本) == Some(案例名.as_str()))
    });

    match 本案例 {
        Some(回执) => {
            let 案例结果 = 回执.取成员("结果").cloned().unwrap_or(协议值::空值项);
            造成功应答(
                协议值::对象(vec![
                    造键文对("案例标识", 案例标识),
                    造键文对("案例名", &案例名),
                    ("案例结果".to_owned(), 案例结果),
                    ("回执".to_owned(), 回执.clone()),
                    (
                        "案例跑者退出码".to_owned(),
                        协议值::整数(i64::from(读数.退出码)),
                    ),
                ]),
                &区间起点,
            )
        }
        None => 造失败应答(
            适配器,
            工具码::案例回执缺失,
            Some(协议值::对象(vec![
                造键文对("案例标识", 案例标识),
                造键文对("案例名", &案例名),
                造键文对("案例跑者", &取相对路径(工具根, &跑者)),
                (
                    "案例跑者退出码".to_owned(),
                    协议值::整数(i64::from(读数.退出码)),
                ),
                造键文对("案例跑者标准输出", &读数.标准输出),
                造键文对("案例跑者标准错误", &读数.标准错误),
                造键文对(
                    "缺什么",
                    &format!(
                        "跑了但 {} 里没有本案例的新回执行（跑前 {} 行 · 新行 {} 条）",
                        常量::案例回执件,
                        跑前行数,
                        新行.len()
                    ),
                ),
            ])),
            &区间起点,
        ),
    }
}
