//! §七 列扩展：`GET /接口/扩展`（支持库 · 模块 · 技能三类清单）。
//!
//! 返回组装只走共用件（`super::成功` / `super::失败` / `键文` / `相对` / `读JSON件` / `列子目录`）
//! —— 形状与这一族码的口径全在 `工具响应.rs` 的文件头，本件不另立一套。

use super::{列子目录, 失败, 键文, 成功, 相对, 读JSON件};
use crate::常量::{self, 工具码};
use crate::协议值::协议值;
use std::path::Path;
use std::time::Instant;
use v1_adapter::适配器;

// ════════════════════════════════════════════════════════════════════════════
// 三 列扩展：`GET /接口/扩展`
// ════════════════════════════════════════════════════════════════════════════

/// `GET /接口/扩展` → 支持库 / 模块 / 技能三类清单。
///
/// **失败时一条都不返回**（`9007` 的说明：残缺清单比空清单更危险 —— 调用方会以为就这些）。
/// 故本函数只有两个出口：全量 `数据`，或**没有 `数据.种类`** 的结构化失败回执。
///
/// 判定只做**结构**（面只做结构校验，不做业务判断 —— §四 硬规则 2）：
/// 扩展根声明读得到、三类目录都在、每个扩展有 `包声明.json` 且它解得出 `名称` 与 `能力号段`。
/// **不判号段归属**（那是装载入口判定第 4 步的活，在这里再判一次就是第二套实现）。
pub fn 列扩展(适配器: &适配器, 工具根: &Path) -> 协议值 {
    let 起 = Instant::now();
    match 组列扩展(工具根) {
        Ok(数据) => 成功(数据, &起),
        Err(说明) => 失败(
            适配器,
            工具码::列扩展失败,
            Some(协议值::对象(vec![
                键文("扩展根声明", 常量::扩展根声明),
                键文("缺什么", &说明),
                键文(
                    "为什么失败时不返回部分清单",
                    "残缺清单比空清单更危险：调用方会以为「就这些」，于是把漏掉的那几个当成不存在",
                ),
            ])),
            &起,
        ),
    }
}

fn 组列扩展(工具根: &Path) -> Result<协议值, String> {
    let 声明 = 读JSON件(&工具根.join(常量::扩展根声明))?;
    let 路径基准 = 声明
        .取成员("路径基准")
        .and_then(协议值::取文本)
        .ok_or_else(|| format!("{} 缺 路径基准（文本）", 常量::扩展根声明))?;
    if 路径基准 != "工作目录" {
        return Err(format!(
            "路径基准 = {路径基准}，本面只认「工作目录」（{} 的既有口径）",
            常量::扩展根声明
        ));
    }
    let 种类表 = 声明
        .取成员("种类")
        .and_then(协议值::取数组)
        .ok_or_else(|| format!("{} 缺 种类（数组）", 常量::扩展根声明))?;

    // 种类[].目录 相对 路径基准（= 工作目录）解析 —— `examples/启动网关.rs` 同口径且跑通，
    // 它从不读 `扩展根`。`扩展根` 键已从 `扩展根声明.json` **删掉**了
    //（该键在载入路径上无可数读方，是 种类[].目录 首段的冗余副本）⇒ 本面**不再要求、
    // 不再读取、不再 join 它**：`目录` 已经是相对工作目录的完整路径。
    let mut 种类出 = Vec::new();
    for 条 in 种类表 {
        let 名 = 条
            .取成员("种类")
            .and_then(协议值::取文本)
            .ok_or_else(|| format!("{} 的种类[] 里有条目缺 种类（文本）", 常量::扩展根声明))?;
        let 目录 = 条
            .取成员("目录")
            .and_then(协议值::取文本)
            .ok_or_else(|| format!("种类「{名}」缺 目录（文本）"))?;
        let 全 = 工具根.join(目录);
        let 子目录 = 列子目录(&全).map_err(|说明| format!("种类「{名}」的目录 {目录}：{说明}"))?;

        let mut 扩展出 = Vec::new();
        for 扩展目录 in 子目录 {
            let 声明件 = 全.join(&扩展目录).join(常量::扩展声明件);
            let 包 = 读JSON件(&声明件)
                .map_err(|说明| format!("扩展「{扩展目录}」{说明}（声明缺失）"))?;
            let 名称 = 包
                .取成员("名称")
                .and_then(协议值::取文本)
                .ok_or_else(|| format!("扩展「{扩展目录}」的 包声明.json 缺 名称（声明不自洽）"))?;
            let 号段 = 包
                .取成员("能力号段")
                .and_then(协议值::取数组)
                .ok_or_else(|| format!("扩展「{扩展目录}」的 包声明.json 缺 能力号段（声明不自洽）"))?;
            let 标识串 = 包
                .取成员("标识串")
                .and_then(协议值::取文本)
                .unwrap_or("");
            扩展出.push(协议值::对象(vec![
                键文("扩展目录", &扩展目录),
                键文("名称", 名称),
                键文("标识串", 标识串),
                ("能力号段".to_owned(), 协议值::数组(号段.to_vec())),
                键文("声明落点", &相对(工具根, &声明件)),
            ]));
        }
        种类出.push(协议值::对象(vec![
            键文("种类", 名),
            键文("目录", 目录),
            ("扩展".to_owned(), 协议值::数组(扩展出)),
        ]));
    }

    Ok(协议值::对象(vec![
        // 不再返回 `扩展根`：那个键已从 `扩展根声明.json` 删除（无可数读方）。
        // 报一个空串或从 `目录` 首段反推都是**编事实**；路径基准由 `种类[].目录` 自带。
        键文("扩展根声明", 常量::扩展根声明),
        ("种类".to_owned(), 协议值::数组(种类出)),
    ]))
}
