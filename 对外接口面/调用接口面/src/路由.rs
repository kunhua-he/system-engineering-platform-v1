//! 路由 —— **方法与路径 → 端点**。纯形状，不含任何业务判断。
//!
//! 判据（`全局连接器与网关.md` 第四节第 3 条）：**边界里 0 处业务判断**。
//! 本文件里搜不到「编号等于某个值就特殊处理」这类特例分支 —— 路由只看「路径对不对上、方法对不对上」，
//! 编号是不是有效由调度判（`提供者未载入` 就是它的段位）。
//!
//! # 为什么要百分号解码
//!
//! 冻结件的路径是 `/接口`（非 ASCII）。浏览器与 `fetch` 按 URL 规范会把非 ASCII 路径
//! **百分号编码**成 `/%E6%8E%A5%E5%8F%A3`。不解码，前端按同源相对路径发的请求**全部 404**，
//! 而前端是纯 UI、不许自己编码 —— 解码只能在网关这一层做（它就是协议层）。
//!
//! # 为什么方法不匹配给 405 而不是 404
//!
//! HTTP 状态码在本面只表达「请求本身合不合法」。路径存在而方法不对，是**请求不合法**的
//! 一种，405 正好说这件事；报 404 会把「路径写错了」与「方法写错了」混成一种。

use crate::常量::{路径_根, 路径_能力, 路径_调用, 路径_声明};
use crate::转码::百分号解码;

/// 四个端点，一个不多一个不少（`接口面形状.md` §二）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 端点 {
    自描述根,
    能力契约 { 编号: u32 },
    调用,
    声明,
}

/// 请求本身不合法 —— 每一种都对应一个 HTTP 状态码，**都不是业务失败**。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 拒绝 {
    /// 路径不在端点表里 ⇒ 404。
    路径不存在,
    /// 路径里的百分号编码不是合法 UTF-8 ⇒ 400。
    路径解码失败,
    /// `/接口/能力/<编号>` 的编号不是十进制数 ⇒ 400。
    编号不是十进制数,
    /// 路径在端点表里，但方法不对 ⇒ 405（`允许` 是正确的方法）。
    方法不许 { 允许: &'static str },
}

impl 拒绝 {
    /// 协议错误的可读说明。
    pub fn 说明(&self) -> String {
        match self {
            拒绝::路径不存在 => "路径不在端点表里（GET /接口 给出全部端点）".to_owned(),
            拒绝::路径解码失败 => "路径的百分号编码不是合法 UTF-8".to_owned(),
            拒绝::编号不是十进制数 => "/接口/能力/<编号> 的 <编号> 必须是十进制整数".to_owned(),
            拒绝::方法不许 { 允许 } => format!("本路径只接受 {允许}"),
        }
    }
}

/// 认一条请求。**先解路径，再比方法**：路径不在表里就是 404，与方法无关。
pub fn 认(方法: &str, 目标: &str) -> Result<端点, 拒绝> {
    let 路径 = 取路径(目标);
    let 路径 = 百分号解码(路径).map_err(|_| 拒绝::路径解码失败)?;
    let 方法 = 方法.to_ascii_uppercase();

    if 路径 == 路径_根 {
        return 要方法(&方法, "GET").map(|()| 端点::自描述根);
    }
    if 路径 == 路径_调用 {
        return 要方法(&方法, "POST").map(|()| 端点::调用);
    }
    if 路径 == 路径_声明 {
        return 要方法(&方法, "POST").map(|()| 端点::声明);
    }
    if let Some(尾) = 路径.strip_prefix(路径_能力) {
        要方法(&方法, "GET")?;
        let 编号 = 尾.parse::<u32>().map_err(|_| 拒绝::编号不是十进制数)?;
        return Ok(端点::能力契约 { 编号 });
    }
    Err(拒绝::路径不存在)
}

fn 要方法(实际: &str, 允许: &'static str) -> Result<(), 拒绝> {
    if 实际 == 允许 {
        Ok(())
    } else {
        Err(拒绝::方法不许 { 允许 })
    }
}

/// 从请求目标里取路径：去掉查询串；`absolute-form`（`http://主机/路径`）也认。
fn 取路径(目标: &str) -> &str {
    let 目标 = 目标
        .strip_prefix("http://")
        .or_else(|| 目标.strip_prefix("https://"))
        .and_then(|余| 余.find('/').map(|位| &余[位..]))
        .unwrap_or(目标);
    match 目标.find('?') {
        Some(位) => &目标[..位],
        None => 目标,
    }
}

#[cfg(test)]
mod 路由测试 {
    use super::*;

    #[test]
    fn 四个端点都认得出来_含百分号编码与查询串() {
        assert_eq!(认("GET", "/接口"), Ok(端点::自描述根));
        assert_eq!(认("get", "/%E6%8E%A5%E5%8F%A3"), Ok(端点::自描述根));
        assert_eq!(认("GET", "/接口?随便=1"), Ok(端点::自描述根));
        // 绝对形式（`http://主机/路径`）：端口从常量取，**不写死字面量**。
        let 绝对 = format!("http://127.0.0.1:{}{路径_根}", crate::常量::接口端口);
        assert_eq!(认("GET", &绝对), Ok(端点::自描述根));
        assert_eq!(认("GET", "/接口/能力/1105"), Ok(端点::能力契约 { 编号: 1105 }));
        assert_eq!(
            认("GET", "/%E6%8E%A5%E5%8F%A3/%E8%83%BD%E5%8A%9B/0"),
            Ok(端点::能力契约 { 编号: 0 })
        );
        assert_eq!(认("POST", "/接口/调用"), Ok(端点::调用));
        assert_eq!(认("POST", "/接口/声明"), Ok(端点::声明));
    }

    #[test]
    fn 不合法请求_各给各的拒绝() {
        assert_eq!(认("GET", "/接口/没有这个"), Err(拒绝::路径不存在));
        assert_eq!(认("GET", "/"), Err(拒绝::路径不存在));
        assert_eq!(认("GET", "/接口/能力/abc"), Err(拒绝::编号不是十进制数));
        assert_eq!(认("GET", "/接口/能力/"), Err(拒绝::编号不是十进制数));
        assert_eq!(认("GET", "/接口/能力/-1"), Err(拒绝::编号不是十进制数));
        assert_eq!(
            认("GET", "/接口/能力/99999999999"),
            Err(拒绝::编号不是十进制数)
        );
        assert_eq!(
            认("POST", "/接口"),
            Err(拒绝::方法不许 { 允许: "GET" })
        );
        assert_eq!(
            认("GET", "/接口/调用"),
            Err(拒绝::方法不许 { 允许: "POST" })
        );
        assert_eq!(认("GET", "/%zz"), Err(拒绝::路径解码失败));
    }
}
