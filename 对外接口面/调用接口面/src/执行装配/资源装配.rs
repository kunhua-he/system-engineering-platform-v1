//! 资源装配 —— 读**资源声明根**（部署侧 JSON）→ 资源网关口（声明 + 部署绑定）。
//!
//! # 为什么这一步落在装配侧、不在关口里
//!
//! 关口 `v1_resource_gateway` **不解析 JSON**（零第三方依赖，且不另造第二套解析器）：
//! 「JSON → 资源声明」这一步归**声明侧的生成物 / 装载动作**（见该 crate 文件头缺口 1）。
//! 本件就是那一步的落点，与 `扫扩展根.rs` 同一条约定 —— 装配读声明、网关不替它猜。
//!
//! # 一份配置，两个面
//!
//! ```text
//! { "资源声明": [ { "资源号": …, "标识": …, "扩展种类": …, "载体": "本机进程",
//!                  "崩溃影响面": "整个进程", "可重建": true, "留痕": false,
//!                  "允许": { "读文件": false, "写文件": false, "联网": false, "派生进程": false },
//!                  "操作": [ { "操作号": …, "名字": …, "输入类型": [4], "输出类型": [5],
//!                             "超时毫秒": 2000, "需要副作用": [] } ] } ],
//!   "资源绑定": [ { "资源号": …, "操作到能力": [ { "操作号": …, "能力号": … } ] } ] }
//! ```
//!
//! `资源声明` = 声明侧（有哪些资源、各自能做什么）；`资源绑定` = 部署侧（各自真调哪一份）——
//! 与 §三 规则 3「入口不写进声明仓」同一件事：声明可公开、入口不公开。
//!
//! # 生产调用面走**适配器**
//!
//! 资源号与能力号是两个号空间（`号段图.json` 的「四个号空间互不相通」）。部署绑定逐条给出
//! 「这条操作真调哪个能力号」，[`适配器资源体`] 就按它转调适配器 —— 资源调用因此走的是
//! **同一条生产调用路**（适配器 → 扩展），不是第二条腿。

use std::sync::Arc;

use v1_adapter::{适配器, 数据槽, 转发结果};
use v1_resource_gateway::入口绑定::{黑盒体, 黑盒结果};
use v1_resource_gateway::{
    允许表, 副作用, 副作用集, 入口声明, 崩溃影响面, 操作声明, 载体类型, 资源声明, 资源错误,
    资源网关口, 隔离声明,
};

use crate::协议值::协议值;

// ════════════════════════════════════════════════════════════════════════════
// 一 形状：声明根 + 部署绑定
// ════════════════════════════════════════════════════════════════════════════

/// 资源声明根 —— **声明表**（有哪些资源）＋ **部署绑定表**（各自真调哪一份）。
///
/// 两表同源一份配置、分开两个面：声明可公开、入口不公开（§三 规则 3）。
pub struct 资源声明根 {
    pub 资源声明表: Vec<资源声明>,
    pub 资源绑定表: Vec<资源绑定项>,
}

/// 一条部署绑定：资源号 + 「操作号 → 能力号」映射。
///
/// 映射**逐操作给**，不给一条「整资源一个能力号」的粗口：一条资源的不同操作本来就
/// 可以落在不同能力上（声明里 `操作` 是白名单，不是同一件事的多种叫法）。
pub struct 资源绑定项 {
    pub 资源号: u32,
    pub 操作到能力: Vec<(u32, u32)>,
}

// ════════════════════════════════════════════════════════════════════════════
// 二 读：JSON 文本 → 声明根（fail-closed，逐键点名）
// ════════════════════════════════════════════════════════════════════════════

/// 读**资源声明根文本** → [`资源声明根`]。文本进来、`Result` 出去、fail-closed。
///
/// 复用 `crate::协议解析::解析协议值`（与 `读声明根` / `读部署配置` 同一份解析器，
/// 不另写第二套 JSON）。**不认任何扩展名**：只认键的形状。
pub fn 读资源声明根(源文本: &str) -> Result<资源声明根, String> {
    let 根值 = crate::协议解析::解析协议值(源文本).map_err(|错误| {
        format!(
            "资源声明根不是合法 JSON：{}（第 {} 字节）",
            错误.说明文字, 错误.出错位置
        )
    })?;
    let 声明项表 = 根值
        .取成员("资源声明")
        .and_then(协议值::取数组)
        .ok_or_else(|| "资源声明根缺 `资源声明` 数组".to_owned())?;
    let mut 资源声明表 = Vec::with_capacity(声明项表.len());
    for 声明项 in 声明项表 {
        资源声明表.push(读一条声明(声明项)?);
    }
    let mut 资源绑定表 = Vec::new();
    if let Some(绑定项表) = 根值.取成员("资源绑定") {
        let 绑定项表 = 绑定项表
            .取数组()
            .ok_or_else(|| "`资源绑定` 要是数组".to_owned())?;
        for 绑定项 in 绑定项表 {
            资源绑定表.push(读一条绑定(绑定项)?);
        }
    }
    Ok(资源声明根 {
        资源声明表,
        资源绑定表,
    })
}

/// 读**一条资源声明**（声明侧）。键名与 `资源声明` 字段逐字对应。
fn 读一条声明(声明项: &协议值) -> Result<资源声明, String> {
    let 资源号 = 取号值(声明项, "资源号")?;
    let 资源号 = u32::try_from(资源号).map_err(|_| format!("资源号超出 32 位：{资源号}"))?;
    let 操作项表 = 声明项
        .取成员("操作")
        .and_then(协议值::取数组)
        .ok_or_else(|| format!("资源 {资源号} 缺 `操作` 数组"))?;
    let mut 操作表 = Vec::with_capacity(操作项表.len());
    for 操作项 in 操作项表 {
        操作表.push(读一条操作(资源号, 操作项)?);
    }
    let 载体值 = 读载体名(声明项)?;
    Ok(资源声明 {
        资源号,
        标识: 取文本(声明项, "标识")?,
        扩展种类: 取文本(声明项, "扩展种类")?,
        入口: 入口声明::仅载体(载体值),
        操作表,
        允许: 读允许表(声明项),
        资源隔离: 隔离声明 {
            载体类型: 载体值,
            可重建: 取真假(声明项, "可重建", false),
            崩溃影响面: 读影响面名(声明项)?,
        },
        留痕: 取真假(声明项, "留痕", false),
    })
}

/// 读**一条操作**（声明侧）。键名与 `操作声明` 字段逐字对应。
fn 读一条操作(资源号: u32, 操作项: &协议值) -> Result<操作声明, String> {
    let 操作号 = 取号值(操作项, "操作号")?;
    let 操作号 =
        u32::try_from(操作号).map_err(|_| format!("资源 {资源号} 的操作号超出 32 位：{操作号}"))?;
    Ok(操作声明 {
        操作号,
        名字: 取文本(操作项, "名字")?,
        输入类型: 取号值表(操作项, "输入类型")?,
        输出类型: 取号值表(操作项, "输出类型")?,
        超时毫秒: 取号值(操作项, "超时毫秒")?,
        需要副作用: Some(读副作用集(操作项)?),
    })
}

/// 读 `需要副作用`：**必须有这个键**（漏写即拒 —— 与关口同一条 fail-closed）。
///
/// 空数组是合法值（「这条操作不碰任何副作用」）；缺键不是。
fn 读副作用集(操作项: &协议值) -> Result<副作用集, String> {
    let 名字表 = 操作项
        .取成员("需要副作用")
        .and_then(协议值::取数组)
        .ok_or_else(|| "操作缺 `需要副作用` 数组（漏写即拒，空数组表示不碰任何副作用）".to_owned())?;
    let mut 副作用集值 = 副作用集::空实例;
    for 名字项 in 名字表 {
        let 副作用名 = 名字项
            .取文本()
            .ok_or_else(|| "`需要副作用` 每一项要是副作用名文本".to_owned())?;
        副作用集值.并入副作用(取副作用(副作用名)?);
    }
    Ok(副作用集值)
}

/// 副作用名 → 副作用（**闭合枚举**，不许按前缀猜）。
fn 取副作用(副作用名: &str) -> Result<副作用, String> {
    match 副作用名 {
        "读文件" => Ok(副作用::读文件),
        "写文件" => Ok(副作用::写文件),
        "联网" => Ok(副作用::联网),
        "派生进程" => Ok(副作用::派生进程),
        其它值 => Err(format!(
            "副作用只认 读文件 / 写文件 / 联网 / 派生进程，实际：{其它值}"
        )),
    }
}

/// 读 `允许`：四个开关**全默认 false**（与关口同一条默认值 —— 「默认能用」是最危险的默认值）。
fn 读允许表(声明项: &协议值) -> 允许表 {
    let Some(允许值) = 声明项.取成员("允许") else {
        return 允许表::全否;
    };
    允许表 {
        读文件: 取真假(允许值, "读文件", false),
        写文件: 取真假(允许值, "写文件", false),
        联网: 取真假(允许值, "联网", false),
        派生进程: 取真假(允许值, "派生进程", false),
    }
}

/// 读 `载体`（**闭合枚举**，不许按前缀猜）。
fn 读载体名(声明项: &协议值) -> Result<载体类型, String> {
    let 载体名 = 取文本(声明项, "载体")?;
    match 载体名.as_str() {
        "进程内" => Ok(载体类型::进程内),
        "本机进程" => Ok(载体类型::本机进程),
        "跨机网络" => Ok(载体类型::跨机网络),
        "沙箱" => Ok(载体类型::沙箱),
        其它值 => Err(format!(
            "载体只认 进程内 / 本机进程 / 跨机网络 / 沙箱，实际：{其它值}"
        )),
    }
}

/// 读 `崩溃影响面`（**闭合枚举**，不许按前缀猜）。
fn 读影响面名(声明项: &协议值) -> Result<崩溃影响面, String> {
    let 影响面名 = 取文本(声明项, "崩溃影响面")?;
    match 影响面名.as_str() {
        "仅本资源" => Ok(崩溃影响面::仅本资源),
        "整个进程" => Ok(崩溃影响面::整个进程),
        其它值 => Err(format!(
            "崩溃影响面只认 仅本资源 / 整个进程，实际：{其它值}"
        )),
    }
}

/// 读**一条部署绑定**（部署侧）：资源号 + 「操作号 → 能力号」映射。
fn 读一条绑定(绑定项: &协议值) -> Result<资源绑定项, String> {
    let 资源号 = 取号值(绑定项, "资源号")?;
    let 资源号 = u32::try_from(资源号).map_err(|_| format!("绑定的资源号超出 32 位：{资源号}"))?;
    let 映射项表 = 绑定项
        .取成员("操作到能力")
        .and_then(协议值::取数组)
        .ok_or_else(|| format!("绑定 {资源号} 缺 `操作到能力` 数组"))?;
    let mut 操作到能力 = Vec::with_capacity(映射项表.len());
    for 映射项 in 映射项表 {
        let 操作号 = 取号值(映射项, "操作号")?;
        let 能力号 = 取号值(映射项, "能力号")?;
        操作到能力.push((
            u32::try_from(操作号).map_err(|_| format!("绑定的操作号超出 32 位：{操作号}"))?,
            u32::try_from(能力号).map_err(|_| format!("绑定的能力号超出 32 位：{能力号}"))?,
        ));
    }
    Ok(资源绑定项 {
        资源号,
        操作到能力,
    })
}

/// 取一个必须存在的非负整数键。
fn 取号值(待处理项: &协议值, 键名: &str) -> Result<u64, String> {
    待处理项
        .取成员(键名)
        .and_then(协议值::取无符号)
        .ok_or_else(|| format!("缺 {键名}，或它不是非负整数"))
}

/// 取一个必须存在的文本键。
fn 取文本(待处理项: &协议值, 键名: &str) -> Result<String, String> {
    待处理项
        .取成员(键名)
        .and_then(协议值::取文本)
        .map(str::to_owned)
        .ok_or_else(|| format!("缺 {键名}，或它不是文本"))
}

/// 取一个必须存在的**非负整数数组**键（类型标签表一类）。
fn 取号值表(待处理项: &协议值, 键名: &str) -> Result<Vec<u32>, String> {
    let 项表 = 待处理项
        .取成员(键名)
        .and_then(协议值::取数组)
        .ok_or_else(|| format!("缺 {键名}，或它不是数组"))?;
    let mut 号值表 = Vec::with_capacity(项表.len());
    for 子项 in 项表 {
        let 号值 = 子项
            .取无符号()
            .ok_or_else(|| format!("{键名} 的每一项要是非负整数"))?;
        号值表.push(u32::try_from(号值).map_err(|_| format!("{键名} 里 {号值} 超出 32 位"))?);
    }
    Ok(号值表)
}

/// 取一个逻辑键（缺键 / 非逻辑 ⇒ 给缺省值）。**只用于开关位** —— 默认 `false` 是安全侧。
fn 取真假(待处理项: &协议值, 键名: &str, 缺省值: bool) -> bool {
    match 待处理项.取成员(键名) {
        Some(协议值::真值) => true,
        Some(协议值::假值) => false,
        _ => 缺省值,
    }
}

// ════════════════════════════════════════════════════════════════════════════
// 三 建关口：声明根 + 部署绑定 → 资源网关口
// ════════════════════════════════════════════════════════════════════════════

/// 建**资源网关口**：声明根 + 部署绑定（每条绑定绑一个 [`适配器资源体`]）。
///
/// 声明任一条不自洽 ⇒ **整批拒**（`从声明根建关口` 的 fail-closed，不许半载）。
/// 没绑的资源照旧进声明表 —— 放行只按声明判，绑了才可调（调没绑的拿「入口未绑定」）。
pub fn 建资源关口(源文本: &str, 适配器: &Arc<适配器>) -> Result<资源网关口, String> {
    let 声明根 = 读资源声明根(源文本)?;
    let mut 关口 = 资源网关口::从声明根建关口(&声明根.资源声明表)
        .map_err(|错误| format!("资源声明不自洽：{错误:?}"))?;
    for 绑定项 in &声明根.资源绑定表 {
        关口.绑定入口(
            绑定项.资源号,
            Box::new(适配器资源体 {
                适配器: Arc::clone(适配器),
                资源号: 绑定项.资源号,
                操作到能力: 绑定项.操作到能力.clone(),
                输出位数表: 取输出位数表(&声明根.资源声明表, 绑定项.资源号),
            }),
        );
    }
    Ok(关口)
}

/// 这条资源的「操作号 → 声明输出位数」表（`0` = 不返回值）。
fn 取输出位数表(资源声明表: &[资源声明], 资源号: u32) -> Vec<(u32, usize)> {
    资源声明表
        .iter()
        .find(|声明项| 声明项.资源号 == 资源号)
        .map(|声明项| {
            声明项
                .操作表
                .iter()
                .map(|操作项| (操作项.操作号, 操作项.输出类型.len()))
                .collect()
        })
        .unwrap_or_default()
}

// ════════════════════════════════════════════════════════════════════════════
// 四 生产调用面：适配器资源体
// ════════════════════════════════════════════════════════════════════════════

/// **生产调用面**：把一次资源操作转调适配器（操作号经部署绑定映射到能力号）。
///
/// 资源号与能力号是两个号空间，本件只做**映射与搬运**：槽表的形状由资源网关口
/// （`校输入形状` / `校输出形状`）判，本件不另判一套。
///
/// # 三条资源语义都落在本件
///
/// 1. **零输出不许凭空多一个槽**：声明的 `输出类型` 是空表 ⇒ 本件**不写输出槽表**
///    （适配器仍会回一个槽，那个槽按「谁分配谁释放」当场归还，不进调用方的表）。
/// 2. **多输出拒绝**：声明要 n>1 位时本件**载不动**（适配器一次调用只回一个槽）⇒ 明确报
///    `资源执行失败`，不许只交回第一位充数（那是静默截断，比失败更坏）。
/// 3. **失败路径清空**：转调失败 / 返回槽为空 ⇒ **先清空输出槽表**再报失败，
///    半截内容一个字都不交给调用方。
///
/// `Send + Sync`（`黑盒体` 的 supertrait）：它只持 `Arc<适配器>` 与两个表，没有可变共享态。
pub struct 适配器资源体 {
    pub 适配器: Arc<适配器>,
    pub 资源号: u32,
    pub 操作到能力: Vec<(u32, u32)>,
    pub 输出位数表: Vec<(u32, usize)>,
}

impl 黑盒体 for 适配器资源体 {
    fn 调用操作(&self, 操作号: u32, 输入槽表: &[数据槽], 输出槽表: &mut Vec<数据槽>) -> 黑盒结果 {
        let Some(能力号) = self.取能力号(操作号) else {
            // 声明里有这条操作、部署没绑它 ⇒ 明确失败，不猜一个能力号。
            输出槽表.clear();
            return 黑盒结果::失败(资源错误::资源执行失败 {
                资源号: self.资源号,
                操作号,
            });
        };
        let mut 返回槽 = 数据槽::空槽();
        let 转发读数 = self.适配器.调用能力(能力号, 输入槽表, &mut 返回槽);
        // 两级失败：调度层拒（未载入 / 已废止 / 个数不符 / 超时 / 配额）与扩展回的**错误槽** ——
        // 两者都是「这次资源操作没成」，对调用方是同一档（`资源执行失败`，专属码 28）。
        if !matches!(转发读数, 转发结果::成功(_))
            || 返回槽.类型标签.取号值() == crate::契约级常量::类型标签::错误
        {
            输出槽表.clear();
            v1_adapter::归还槽值(&mut 返回槽);
            return 黑盒结果::失败(资源错误::资源执行失败 {
                资源号: self.资源号,
                操作号,
            });
        }
        match self.取输出位数(操作号) {
            // 零输出：协议回的那个槽不进调用方的表（按谁分配谁释放当场归还）。
            0 => {
                v1_adapter::归还槽值(&mut 返回槽);
                黑盒结果::成功
            }
            // 一位：与声明的类型表逐位对齐；空槽不是那位值。
            1 => {
                if 返回槽.是否空() {
                    return 黑盒结果::失败(资源错误::资源执行失败 {
                        资源号: self.资源号,
                        操作号,
                    });
                }
                输出槽表.push(返回槽);
                黑盒结果::成功
            }
            // 多位：一次调用只回一个槽 ⇒ 载不动，明确拒（不截断、不补空槽）。
            _ => {
                输出槽表.clear();
                v1_adapter::归还槽值(&mut 返回槽);
                黑盒结果::失败(资源错误::资源执行失败 {
                    资源号: self.资源号,
                    操作号,
                })
            }
        }
    }
}

impl 适配器资源体 {
    /// 操作号 → 能力号（部署绑定给；取不到 ⇒ 这条操作没被绑）。
    fn 取能力号(&self, 操作号: u32) -> Option<u32> {
        self.操作到能力
            .iter()
            .find(|映射项| 映射项.0 == 操作号)
            .map(|映射项| 映射项.1)
    }

    /// 操作号 → 声明输出位数。取不到按 `1` 读：没声明的位次由关口的输出形状判据兜。
    fn 取输出位数(&self, 操作号: u32) -> usize {
        self.输出位数表
            .iter()
            .find(|位数项| 位数项.0 == 操作号)
            .map_or(1, |位数项| 位数项.1)
    }
}
