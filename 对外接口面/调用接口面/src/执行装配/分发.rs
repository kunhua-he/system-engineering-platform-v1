/// 一次应答：HTTP 状态码 + 内容类型 + 体（已序列化）。
///
/// **体是字节**（不是 `String`）：§五 的静态托管要原样交出前端自身的件
/// （`index.html` · `页面样式.css` · `*.js`），它们**不是 JSON**，而 §三 的四个端点一律 JSON。
/// 内容类型随体一起走，写响应那一处不再假定 JSON。
#[derive(Debug, Clone)]
pub struct 造应答 {
    pub 状态: u16,
    pub 内容类型: &'static str,
    pub 报文体: Vec<u8>,
}

impl 造应答 {
    /// 请求合法 ⇒ 200（**业务失败也走这里**）。
    pub fn 正常态(待处理值: &协议值) -> Self {
        Self {
            状态: 200,
            内容类型: 内容类型_JSON,
            报文体: crate::协议写出::写协议值(待处理值).into_bytes(),
        }
    }

    /// 请求本身不合法 ⇒ 4xx，体里给一句可读说明（**没有业务错误对象**，
    /// 编一个 `码` 出来就是伪造业务数据）。
    pub fn 协议错误(状态: u16, 说明文字: &str) -> Self {
        Self {
            状态,
            内容类型: 内容类型_JSON,
            报文体: crate::协议写出::写协议值(&crate::错误形状::协议错误(说明文字)).into_bytes(),
        }
    }

    /// 协议层失败 + **机器可判的 `种类`**（只给读报文失败那一路用）。
    ///
    /// 状态仍 400、正文仍带 `成功` / `协议错误` 两键 ⇒ 冻结的码值集合与既有键一字不动，
    /// 只多一个旁路字段（`错误形状::协议错误带种类`）。别处请求形状类失败继续走
    /// `协议错误`（正文不变、**不带** `种类`）。
    pub fn 协议错误带种类(状态: u16, 说明文字: &str, 种类文本: &str) -> Self {
        Self {
            状态,
            内容类型: 内容类型_JSON,
            报文体: crate::协议写出::写协议值(&crate::错误形状::协议错误带种类(
                说明文字, 种类文本,
            ))
            .into_bytes(),
        }
    }

    /// 静态件（`接口面形状.md` §五）：**原样交出**，内容类型随扩展名（`静态件.rs`）。
    pub fn 静态件应答(静态件: crate::静态件::静态件) -> Self {
        Self {
            状态: 200,
            内容类型: 静态件.内容类型,
            报文体: 静态件.字节,
        }
    }
}

/// 一次请求的**部署环境**（六件）：适配器 · 资源网关口 · 契约身份 · 端口 · 静态根 · 工具根。
///
/// 六件都来自网关的**部署事实**，与请求本身（`端点` / `请求体`）不同源 ⇒ 单独一捆，
/// 免得 `处理请求` 的形参越过严格 Clippy 的七参上限（`clippy::too_many_arguments`）。
/// 全是引用或 `Copy` 标量（`适配器` / `资源关口` 是调用方**锁外**取的 `Arc` 快照）
/// ⇒ 本结构 `Copy`，借用不延长任何锁的寿命。
#[derive(Clone, Copy)]
pub struct 请求环境<'a> {
    pub 适配器: &'a 适配器,
    pub 资源关口: &'a 资源网关口,
    pub 契约身份: &'a 契约身份,
    pub 实际端口: u16,
    pub 静态根: &'a Path,
    pub 工具根: &'a Path,
}

/// 一次请求的落点。**纯分发**：不取号、不校参数、不问配额，全在适配器与调度层。
///
/// `静态根` 是 §五 的托管目录（装配侧注入，见 `网关.rs` 的 `服务::托管静态根`）——
/// 只在这一个落点上用得到，故由调用方递进来，不在本模块存一份。
///
/// `工具根` 是 §七 工具族的**部署事实**（案例库 · 扩展根声明 · 外部 CLI 的所在；
/// 见 `网关.rs` 的 `服务::工具根`），同样由调用方递进来。
pub fn 处理请求(环境: 请求环境<'_>, 端点: 端点, 请求体: Option<&协议值>) -> 造应答 {
    let 请求环境 { 适配器, 资源关口, 契约身份, 实际端口, 静态根, 工具根 } = 环境;
    match 端点 {
        端点::自描述根 => 造应答::正常态(&响应::自描述根(
            &契约身份.版本,
            契约身份.声明格式号,
            适配器,
            实际端口,
        )),
        端点::能力契约 { 编号 } => 造应答::正常态(&响应::能力契约(适配器, 编号, 契约身份)),
        // 检索：一条路径两种用法 —— 查询串里有 关键词 ⇒ 搜索；否则有 路径 ⇒ 索引；
        // 两个键都没有 ⇒ 400（`解析检索` 把两种用法都说清）。分派判在协议层，不在路由层。
        端点::检索 { 查询串 } => match 请求::解析检索(&查询串) {
            Ok(请求::检索请求::搜索(请求)) => 造应答::正常态(&crate::搜索响应::搜索(适配器, &请求)),
            Ok(请求::检索请求::索引(请求)) => {
                let 区间起点 = std::time::Instant::now();
                let 应答 = match crate::索引响应::读取索引(工具根, &请求) {
                    Ok(索引数据) => 工具响应::造成功应答(索引数据, &区间起点),
                    Err(说明) => 工具响应::造失败应答(适配器, crate::契约级常量::工具码::列扩展失败,
                        Some(协议值::对象值(vec![("缺什么".to_owned(), 协议值::文本值(说明))])), &区间起点),
                };
                造应答::正常态(&应答)
            }
            Err(说明) => 造应答::协议错误(400, &说明),
        },
        端点::调用 => match 请求体 {
            None => 造应答::协议错误(400, "POST /接口/调用 必须有请求体"),
            Some(请求体) => match 请求::解析调用(请求体) {
                // 命名形态在这里映射成行序（E02）：形状层判完再按契约映射 ——
                // 映射缺不了契约，故它不能在 `解析调用`（纯协议层、无适配器）里做。
                Ok(mut 请求) => match 请求::按契约映射(适配器, &mut 请求) {
                    Ok(()) => 造应答::正常态(&响应::调用(适配器, &请求, 契约身份)),
                    Err(错误) => 造应答::协议错误(400, &错误.可读说明()),
                },
                Err(错误) => 造应答::协议错误(400, &错误.可读说明()),
            },
        },
        端点::声明 => match 请求体 {
            // 只判协议层：体得是一个 JSON 对象（§四 冻结的请求形状就是对象）。
            // 再往下（类别 · 编号 · 正文 逐项校验）是**声明编写面**的活 ——
            // 在调用接口面里写一遍就是同一件事的第二套实现。
            None => 造应答::协议错误(400, "POST /接口/声明 必须有请求体"),
            Some(协议值::对象值(_)) => 造应答::正常态(&响应::声明未实现()),
            Some(_) => 造应答::协议错误(400, "请求体必须是对象：{\"类别\":…,\"编号\":…,\"正文\":…}"),
        },
        // §五 的静态托管：托管根下没有这个件就是 404（**不列表、不重写**，见 `静态件.rs`）。
        端点::静态件 { 路径 } => match crate::静态件::取静态件(静态根, &路径) {
            Some(静态件) => 造应答::静态件应答(静态件),
            None => 造应答::协议错误(
                404,
                &format!(
                    "静态托管根下没有这个件：{路径}。本面只托管前端自身的件（`接口面形状.md` §五），\
                     根下没有的路径一律 404；端点表见 GET /接口。"
                ),
            ),
        },
        // ── §七 工具族（新增旁路）────────────────────────────────────────────
        // 四个 POST 端点都**先判请求体形状**（⇒ 400），再交给工具响应组装 ——
        // 与 §三 的 `/接口/调用` 同一条分工（`请求.rs` 文件头）：业务失败回**真错误码**，
        // 只有「请求体形状不合法」才是 400。
        端点::案例清单 => 造应答::正常态(&工具响应::列案例(适配器, 工具根)),
        端点::扩展清单 => 造应答::正常态(&工具响应::列扩展(适配器, 工具根)),
        端点::案例跑 => 要请求体(请求体, "POST /接口/案例/跑", |请求体| {
            请求::解析案例标识(请求体).map(|标识| 工具响应::跑案例(适配器, 工具根, &标识))
        }),
        // 文件：导出 / 读 / 写三种动作同住一条路径 —— 按体里 `动作` 分派（`解析文件`）。
        // 动作不是这三个值 ⇒ `解析文件` 报 400 并列出闭合枚举（不是业务失败，不是 9004）。
        端点::文件 => 要请求体(请求体, "POST /接口/运维/文件", |请求体| {
            match 请求::解析文件(请求体)? {
                请求::文件请求::导出(请求) => Ok(工具响应::处理导出(适配器, 工具根, &请求)),
                请求::文件请求::程序文本(请求) => Ok(工具响应::程序文本(适配器, 工具根, &请求)),
            }
        }),
        端点::菜单命令 => 要请求体(请求体, "POST /接口/菜单命令", |请求体| {
            请求::解析菜单命令(请求体).map(|编号| 工具响应::菜单命令(适配器, 工具根, &编号))
        }),
        // ── 生命周期族与留痕 ────────────────────────────────
        // 就绪/健康读数走生命周期正路（通知端点表）。
        // ★ `POST /接口/生命周期`（装载 / 卸载）**不由本函数处理**：两者都改适配器状态
        //   （`追加装载` / 完整卸载都取 `&mut`）⇒ 由网关持写锁那一支先接走（见 `网关.rs`）。
        //   本臂只在「线序接错」时被走到：fail-closed 报明，不猜、不静默当别的动作。
        端点::生命周期读数 => 造应答::正常态(&生命周期响应::读数(适配器, 工具根)),
        端点::生命周期动作 => 造应答::协议错误(
            400,
            "POST /接口/生命周期 的装载/卸载由网关持写锁那一支处理——本分发臂不该被走到",
        ),
        // 观测：资源读数与留痕**一次回两块**（`数据` = {资源, 留痕}）—— 一次读拿到两个面，
        // 不各自一个端点（两块各自取子应答的 `数据` 成员，见 `资源响应::观测`）。
        端点::观测 => 造应答::正常态(&资源响应::观测(资源关口, 适配器)),
        // 旁路 · 资源调用：`POST /接口/资源调用`（资源的生产调用面）。
        // 资源号与能力号是两个号空间 ⇒ 走资源网关口唯一出入口，不搭 `/接口/调用` 那条腿。
        // 旁路 · 技能取文：`GET /接口/技能/取文/<编号>`（按技能能力号取回本体段 19 的 md 正文）。
        // 不收体（GET）；号已由路由解成 `u32`，这里只做「定位 + 取文」。
        端点::技能取文 { 编号 } => 造应答::正常态(&工具响应::技能取文(适配器, 工具根, 编号)),
        端点::资源调用 => match 请求体 {
            None => 造应答::协议错误(400, "POST /接口/资源调用 必须有请求体"),
            Some(请求体) => match crate::资源调用请求::解析资源调用(请求体) {
                Ok(请求) => 造应答::正常态(&crate::资源调用响应::资源调用(适配器, 资源关口, &请求)),
                Err(错误) => 造应答::协议错误(400, &错误.可读说明()),
            },
        },
    }
}

/// 收体端点的一段固定流程：**体在不在 → 形状合不合法 → 交给业务**。
///
/// 四个旁路 POST 端点逐字重复这五行的形状与 §三 的 `/接口/调用` 完全一样；
/// 抽成一处是为了让「400 只有一种来源」这件事只有一处实现。
fn 要请求体(
    请求体: Option<&协议值>,
    端点名: &str,
   业务: impl FnOnce(&协议值) -> Result<协议值, String>,
) -> 造应答 {
    match 请求体 {
        None => 造应答::协议错误(400, &format!("{端点名} 必须有请求体")),
        Some(请求体) => match 业务(请求体) {
            Ok(待处理值) => 造应答::正常态(&待处理值),
            Err(说明文字) => 造应答::协议错误(400, &说明文字),
        },
    }
}

/// 生命周期动作（`POST /接口/生命周期`）的**写锁分发**：装载与卸载都改适配器状态
/// （`追加装载` / 完整卸载都取 `&mut`）⇒ 由本函数持**写锁**把 `&mut 适配器` 交给
/// [`生命周期响应`]，中途不释放（不许并发调用挤进来）。
///
/// 两支：`动作 = 装载` ⇒ 重扫扩展根（部署事实 `声明根` / `后缀表源文本` / `缓存根` 由网关注入）；
/// 其余动作 = **卸载** ⇒ 先判请求体形状（⇒ 400），再走完整卸载（`生命周期响应::卸载扩展`）。
///
/// `启用状态` = 跨进程生产启用状态（`None` = 没注入部署配置 ⇒ 全部走进程内原路）。
/// **装载 / 切换按同一份判据登记执行域，卸载注销域** —— 复用既有生命周期实现，
/// 不另造一套（冻结件 §四「运行期装载 / 切换 / 卸载同一规则」）。
#[cfg(unix)]
pub fn 处理生命周期动作(
    适配器: &mut 适配器,
    请求体: Option<&协议值>,
    声明根: Option<&Path>,
    后缀表源文本: Option<&str>,
    缓存根: Option<&Path>,
    启用状态: Option<&mut crate::跨进程装配::启用状态>,
) -> 造应答 {
    if 请求体.is_some_and(请求::是装载动作) {
        return 造应答::正常态(&生命周期响应::装载(
            适配器,
            声明根,
            后缀表源文本,
            缓存根,
            启用状态,
        ));
    }
    match 请求体 {
        None => 造应答::协议错误(400, "POST /接口/生命周期 必须有请求体"),
        Some(请求体) => match 请求::解析卸载(请求体) {
            Ok(本扩展标识串) => {
                造应答::正常态(&生命周期响应::卸载扩展(适配器, &本扩展标识串, 启用状态))
            }
            Err(说明文字) => 造应答::协议错误(400, &说明文字),
        },
    }
}

/// 非 unix 平台：跨进程执行域整支不存在（`进程池` 与 `跨进程装配` 都 `#[cfg(unix)]`）
/// ⇒ 生命周期动作逐字保持原行为（不登记、不注销）。
#[cfg(not(unix))]
pub fn 处理生命周期动作(
    适配器: &mut 适配器,
    请求体: Option<&协议值>,
    声明根: Option<&Path>,
    后缀表源文本: Option<&str>,
    缓存根: Option<&Path>,
) -> 造应答 {
    if 请求体.is_some_and(请求::是装载动作) {
        return 造应答::正常态(&生命周期响应::装载(
            适配器,
            声明根,
            后缀表源文本,
            缓存根,
        ));
    }
    match 请求体 {
        None => 造应答::协议错误(400, "POST /接口/生命周期 必须有请求体"),
        Some(请求体) => match 请求::解析卸载(请求体) {
            Ok(本扩展标识串) => 造应答::正常态(&生命周期响应::卸载扩展(适配器, &本扩展标识串)),
            Err(说明文字) => 造应答::协议错误(400, &说明文字),
        },
    }
}

/// 拒绝 → HTTP 状态码（**只表达请求合不合法**，见文件头）。
pub fn 拒绝状态码(拒绝: &拒绝) -> u16 {
    match 拒绝 {
        拒绝::路径不存在 => 404,
        拒绝::路径解码失败 | 拒绝::编号不是十进制数 => 400,
        拒绝::方法不许 { .. } => 405,
    }
}
