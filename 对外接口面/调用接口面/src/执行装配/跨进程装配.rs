/// 一条部署条目 —— 「哪个扩展（已校验身份 + 版本 + 制品）从哪拉起工作进程」。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 跨进程条目 {
    /// 扩展标识串（与声明里的 `标识串` 逐字相等才算对得上）。
    pub 标识串: String,
    /// 制品版本三元组（与声明的 `实现版本` 逐段相等）。
    pub 版本: (i32, i32, i32),
    /// 实际制品路径（**必须真实存在**，且落在该扩展的落点目录里）。
    pub 制品路径: PathBuf,
    /// 工作进程可执行路径（**由配置给，本件不猜**；空 ⇒ 该扩展走进程内）。
    pub 启动程序: String,
    /// 工作进程启动参数。
    pub 启动参数: Vec<String>,
}

/// 一条**模块身份** —— 模块不是支持库声明：身份来自 `包声明.json` 的 `标识串` / `实现版本`，
/// 能力号来自制品**段 16**，制品路径 = 落点目录里那一个模块制品。
///
/// 四件都是**读出来的**：本件不写号表、不认模块名。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 模块身份 {
    pub 标识串: String,
    pub 版本: (u32, u32, u32),
    pub 能力号表: Vec<u32>,
    pub 制品路径: PathBuf,
    /// 声明侧 `包声明.json` 的 `依赖清单`（32 位十六进制标识串表）—— 该模块声明的依赖（要哪些扩展）。
    ///
    /// 与 `依赖版本要求` **按下标一一对应**；空表 = 不依赖任何扩展（与支持库那条路同义）。
    pub 依赖清单: Vec<String>,
    /// 与 `依赖清单` 按下标一一对应的版本门槛（两段：主 · 次）。
    pub 依赖版本要求: Vec<版本要求>,
}

/// 一份跨进程部署配置：条目表 + 进程池阈值（阈值属部署配置，W01）。
///
/// **不 `derive(Debug)`**：`进程池配置` 不带 `Debug`（它是载体侧的形状），本件不为打印
/// 去改下层。要打印逐条结局用 [`条目结局`]。
#[derive(Clone)]
pub struct 跨进程部署 {
    pub 条目表: Vec<跨进程条目>,
    pub 配置: 进程池配置,
}

impl 跨进程部署 {
    /// 按标识串找条目（找不到 ⇒ 这个扩展走进程内）。
    pub fn 按标识串取(&self, 本扩展标识串: &str) -> Option<&跨进程条目> {
        self.条目表.iter().find(|明细条目| 明细条目.标识串 == 本扩展标识串)
    }
}

/// 登记一条条目的结局 —— **逐条如实报出**，不静默吞因、不整体失败。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 条目结局 {
    /// 已登记执行域（这条扩展走跨进程）。
    已登记,
    /// 配置没给工作进程路径，或配置里没有这条 ⇒ 该扩展**走进程内**（不猜）。
    走进程内,
    /// 校验不过或拉起失败 ⇒ **拒收**（附原因）。拒收的条目不登记、不发布。
    拒收(String),
}

/// 读**部署配置文本** → [`跨进程部署`]（文本进来、`Result` 出去、fail-closed）。
///
/// 复用 `crate::协议解析::解析协议值`（与 `读声明根` / `读后缀表` 同一份解析器，
/// 不另写第二套 JSON）。**不认任何扩展名**：只认键的形状。
pub fn 读部署配置(源文本: &str) -> Result<跨进程部署, String> {
    let 根值 = 解析协议值(源文本).map_err(|错误| {
        format!("部署配置不是合法 JSON：{}（第 {} 字节）", 错误.说明文字, 错误.出错位置)
    })?;
    let 条目值表 = 根值
        .取成员("跨进程")
        .and_then(协议值::取数组)
        .ok_or_else(|| "部署配置缺 `跨进程` 数组".to_owned())?;
    let mut 条目表 = Vec::with_capacity(条目值表.len());
    for 条目值 in 条目值表 {
        let 标识串 = 条目值
            .取成员("标识串")
            .and_then(协议值::取文本)
            .filter(|文本载荷| !文本载荷.is_empty())
            .ok_or_else(|| "跨进程条目缺非空 `标识串`".to_owned())?
            .to_owned();
        let 版本值 = 条目值.取成员("版本").ok_or_else(|| "跨进程条目缺 `版本`".to_owned())?;
        let 取段 = |键名: &str| -> Result<i32, String> {
            版本值
                .取成员(键名)
                .and_then(协议值::取无符号)
                .and_then(|号值| i32::try_from(号值).ok())
                .ok_or_else(|| format!("跨进程条目 `版本.{键名}` 缺失或非整数"))
        };
        let 版本 = (取段("主版本")?, 取段("次版本号")?, 取段("构建")?);
        let 制品路径 = 条目值
            .取成员("制品路径")
            .and_then(协议值::取文本)
            .filter(|文本载荷| !文本载荷.is_empty())
            .ok_or_else(|| "跨进程条目缺非空 `制品路径`".to_owned())?;
        let 启动程序 = 条目值
            .取成员("启动程序")
            .and_then(协议值::取文本)
            .unwrap_or("")
            .to_owned();
        let 启动参数 = 条目值
            .取成员("启动参数")
            .and_then(协议值::取数组)
            .map(|参数表| {
                参数表
                    .iter()
                    .filter_map(协议值::取文本)
                    .map(str::to_owned)
                    .collect()
            })
            .unwrap_or_default();
        条目表.push(跨进程条目 {
            标识串,
            版本,
            制品路径: PathBuf::from(制品路径),
            启动程序,
            启动参数,
        });
    }
    Ok(跨进程部署 { 条目表, 配置: 读进程池阈值(&根值) })
}

/// 进程池阈值：不给就用 `进程池配置::default()`（**不发明数**）。
fn 读进程池阈值(根值: &协议值) -> 进程池配置 {
    let 默认 = 进程池配置::default();
    let 取毫秒 = |键名: &str, 兜底: u64| -> u64 {
        根值.取成员(键名).and_then(协议值::取无符号).unwrap_or(兜底)
    };
    let 取预算 = |键名: &str, 兜底: u32| -> u32 {
        根值
            .取成员(键名)
            .and_then(协议值::取无符号)
            .and_then(|号值| u32::try_from(号值).ok())
            .unwrap_or(兜底)
    };
    进程池配置 {
        退避基数毫秒: 取毫秒("退避基数毫秒", 默认.退避基数毫秒),
        退避上限毫秒: 取毫秒("退避上限毫秒", 默认.退避上限毫秒),
        重启预算: 取预算("重启预算", 默认.重启预算),
        熔断时长毫秒: 取毫秒("熔断时长毫秒", 默认.熔断时长毫秒),
        子进程数上限: 取预算("子进程数上限", 默认.子进程数上限),
    }
}

/// 取一份声明里的标识串文本（契约串读法：静态只读 NUL 结尾串）。
///
/// 与 `扫扩展根.rs::最近错误` 同一读法（`CStr`），本件不另立一套。
pub fn 取声明标识串(声明: &平台信息) -> Option<String> {
    if 声明.标识串.is_null() {
        return None;
    }
    // 契约里 `标识串` 的型是 `*const u8`，而 `CStr` 要 `*const c_char`（本平台即 `i8`）——
    // 这里只换指针的型，不动被指字节。
    // SAFETY: 契约保证 `标识串` 是静态只读 NUL 结尾串，终生有效。
    Some(unsafe { CStr::from_ptr(声明.标识串.cast::<std::ffi::c_char>()) }.to_string_lossy().into_owned())
}

