/// 生产启用状态 —— 挂在 [`crate::服务`] 上的**一份**部署配置与它的登记账。
///
/// 三处入口（启动装配 · 运行期装载 / 切换 · 卸载）**共用本件**，所以判据只有一份。
/// **只存字符串**（不存 `&'static 平台信息`）：声明在那一刻由调用方递进来。
pub struct 启用状态 {
    部署: 跨进程部署,
    /// 已登记的 `(标识串, 落点目录)`（**登记成功才算**）。
    ///
    /// 为什么要连落点一起记：卸载只给一个**标识串**，而注销执行域要那份声明的
    /// `&'static 平台信息`（`适配器::击杀跨进程域` 要它）。本件**不存裸指针**（声明带
    /// 裸指针、不是 `Send`/`Sync`，存进 [`crate::服务`] 会让服务不能跨线程共享）——
    /// 改为记下落点，卸载时用**同一个装载器**（`扫扩展根::取扩展声明`）把声明取回来。
    /// 同一个库 `dlopen` 两次拿到同一个静态指针 ⇒ 与当初登记的是同一份声明。
    已登记: Vec<(String, String)>,
    /// 已登记的模块域 `(模块身份串, 落点目录, 能力号)` —— 模块没有声明可回取，
    /// 卸载只能按**号**回收（`适配器::移除模块跨进程域`）。
    已登记模块表: Vec<(String, String, u32)>,
    /// 卸载时**把声明取回来**要用的两个部署事实（与 `服务` 上那两个同源，装配侧注入）。
    /// 缺任一个 ⇒ 卸载只能摘登记账、注销不了域（如实返回 `false`，不假装）。
    后缀表文本: Option<String>,
    缓存根: Option<PathBuf>,
}

impl 启用状态 {
    /// 从一份部署配置建状态（登记账起手为空）。
    pub fn 创建(部署: 跨进程部署) -> Self {
        Self {
            部署,
            已登记: Vec::new(),
            已登记模块表: Vec::new(),
            后缀表文本: None,
            缓存根: None,
        }
    }

    /// 注入卸载取声明要用的两个部署事实（**同一个装载器**：后缀表 + 缓存根）。
    pub fn 装载依据(mut self, 后缀表文本: Option<String>, 缓存根: Option<PathBuf>) -> Self {
        self.后缀表文本 = 后缀表文本;
        self.缓存根 = 缓存根;
        self
    }

    /// 部署配置的条目数（装配侧与验证面读）。
    pub fn 条目数(&self) -> usize {
        self.部署.条目表.len()
    }

    /// 已登记执行域的条数（验证面读）。
    pub fn 已登记数(&self) -> usize {
        self.已登记.len()
    }

    /// 这条标识串登记过执行域没有。
    pub fn 已登记(&self, 本扩展标识串: &str) -> bool {
        self.已登记.iter().any(|(标识项, _)| 标识项 == 本扩展标识串)
    }

    /// 已登记模块域的条数（验证面读）。
    pub fn 已登记模块数(&self) -> usize {
        self.已登记模块表.len()
    }

    /// 这条模块身份串的域登记过没有。
    pub fn 模块已登记(&self, 模块身份串: &str) -> bool {
        self.已登记模块表
            .iter()
            .any(|模块登记项| 模块登记项.0 == 模块身份串)
    }

    /// 模块域的工作进程可执行：**复用部署配置已有的可执行路径**（不新增「模块路径」一栏）。
    ///
    /// 先按模块身份串找条目；没有就用配置里**第一条给了可执行路径**的条目作默认来源。
    /// 一条都没有 ⇒ `None` ⇒ 拒收（**不猜路径**）。
    fn 模块启动程序(&self, 模块身份串: &str) -> Option<String> {
        if let Some(明细条目) = self.部署.按标识串取(模块身份串)
            && !明细条目.启动程序.is_empty()
        {
            return Some(明细条目.启动程序.clone());
        }
        self.部署
            .条目表
            .iter()
            .map(|明细条目| 明细条目.启动程序.as_str())
            .find(|启动程序| !启动程序.is_empty())
            .map(str::to_owned)
    }

    /// 这条标识串的落点目录（卸载要它把声明取回来）。
    pub fn 落点(&self, 本扩展标识串: &str) -> Option<&str> {
        self.已登记
            .iter()
            .find(|(标识项, _)| 标识项 == 本扩展标识串)
            .map(|(_, 落点)| 落点.as_str())
    }

    /// 启动装配 / 运行期装载**共用**：逐条校验 + 登记，逐条报结局。
    ///
    /// `已装声明` = 那一刻的 `(声明, 落点目录)` 表 —— 校验要用它判「这条配置配的是
    /// 哪一份声明、它的制品在不在那个落点里」。**本件不猜落点**。
    pub fn 注入(
        &mut self,
        适配器: &mut 适配器,
        已装声明: &[(&'static 平台信息, String)],
    ) -> Vec<(String, 条目结局)> {
        let 配置 = self.部署.配置;
        // 条目表先克隆一份：登记要 `&mut self` 记账，不能同时借着它遍历。
        let 条目表 = self.部署.条目表.clone();
        let mut 读数: Vec<(String, 条目结局)> = Vec::with_capacity(条目表.len());
        for 明细条目 in &条目表 {
            let 命中 = 已装声明
                .iter()
                .find(|(声明, _)| 取声明标识串(声明).as_deref() == Some(明细条目.标识串.as_str()));
            let 结局 = match 命中 {
                Some((声明, 落点)) => {
                    let 结局 = 校验并登记一条(适配器, 配置, 明细条目, 声明, 落点);
                    if 结局 == 条目结局::已登记 {
                        self.记账(明细条目.标识串.clone(), 落点.clone());
                    }
                    结局
                }
                None => 条目结局::拒收("已装载声明里没有这个标识串".to_owned()),
            };
            读数.push((明细条目.标识串.clone(), 结局));
        }
        读数
    }

    /// 记一条登记（**同一个标识串只记一次**）。
    fn 记账(&mut self, 标识串: String, 落点: String) {
        if let Some(格子) = self.已登记.iter_mut().find(|(标识项, _)| 标识项 == &标识串) {
            格子.1 = 落点;
            return;
        }
        self.已登记.push((标识串, 落点));
    }

    /// 运行期**装载**一份新声明：按同一份配置校验 + 登记。
    ///
    /// **只有 [`条目结局::已登记`] 才算发布成功**；拒收 ⇒ 调用方**不发布**这份候选
    /// （既不替换旧版本，也不回退进程内 —— 见 [`校验并登记一条`]）。
    pub fn 装载登记(
        &mut self,
        适配器: &mut 适配器,
        声明: &'static 平台信息,
        落点: &str,
    ) -> 条目结局 {
        let 标识串 = 取声明标识串(声明).unwrap_or_default();
        let Some(明细条目) = self.部署.按标识串取(&标识串) else {
            // 配置里没这条 ⇒ 该扩展走进程内（默认进程内，选了才跨进程）。
            return 条目结局::走进程内;
        };
        let 明细条目 = 明细条目.clone();
        let 结局 = 校验并登记一条(适配器, self.部署.配置, &明细条目, 声明, 落点);
        if 结局 == 条目结局::已登记 {
            self.记账(标识串, 落点.to_owned());
        }
        结局
    }

    /// 按**已部署条目**解析模块的依赖制品表：`依赖清单` 里的每条标识串 → 部署条目 → 制品路径。
    ///
    /// 判据（任一不过 ⇒ 拒收并给因，**不猜路径**）：
    /// 1. 每条依赖在部署条目表里**恰好命中一条**（零条 = 缺依赖；多条 = 歧义）；
    /// 2. 条目版本**满足**声明侧的版本门槛（`版本三元组::满足`，与装载入口同一份比较）；
    /// 3. 条目给的制品**真实存在**。
    ///
    /// 依赖的支持库由**同一个工作进程**用既有装载腿装载（启动参数第二栏），不新开进程池。
    pub fn 解析依赖制品(&self, 模块条目: &模块身份) -> Result<Vec<PathBuf>, String> {
        let mut 制品表: Vec<PathBuf> = Vec::with_capacity(模块条目.依赖清单.len());
        for (依赖位次, 依赖串) in 模块条目.依赖清单.iter().enumerate() {
            let 要求 = 模块条目.依赖版本要求.get(依赖位次);
            let 命中表: Vec<&跨进程条目> = self
                .部署
                .条目表
                .iter()
                .filter(|明细条目| 明细条目.标识串 == *依赖串)
                .collect();
            match 命中表.len() {
                0 => {
                    return Err(format!(
                        "依赖 {依赖串} 不在部署条目表里（缺依赖制品路径，无法在工作进程内装载）"
                    ));
                }
                1 => {}
                份数 => {
                    return Err(format!(
                        "依赖 {依赖串} 在部署条目表里命中 {份数} 条（要求唯一匹配）"
                    ));
                }
            }
            let 命中条目 = 命中表[0];
            if let Some(要求) = 要求 {
                let 当前版本 = v1_adapter::版本三元组::构造(
                    命中条目.版本.0,
                    命中条目.版本.1,
                    命中条目.版本.2,
                );
                if !当前版本.满足(要求) {
                    return Err(format!(
                        "依赖 {依赖串} 的部署版本 {}.{}.{} 不满足声明要求 {}.{}",
                        命中条目.版本.0,
                        命中条目.版本.1,
                        命中条目.版本.2,
                        要求.主版本,
                        要求.次版本号
                    ));
                }
            }
            if !命中条目.制品路径.is_file() {
                return Err(format!(
                    "依赖 {依赖串} 的制品路径不存在：{}",
                    命中条目.制品路径.display()
                ));
            }
            制品表.push(命中条目.制品路径.clone());
        }
        Ok(制品表)
    }

    /// 运行期**装载一个模块**：按同一份部署事实登记执行域（**同一个池、同一个启动器**）。
    ///
    /// 判据（任一不过 ⇒ 拒收，不发布）：
    /// 1. 制品真实存在且落在它的落点目录里（与支持库同一份 `校制品落点`）；
    /// 2. 部署配置给得出工作进程可执行路径 —— **复用已有路径**，不为模块新增一栏；
    /// 3. 缓存根已注入（工作进程要它解包模块执行体）；
    /// 4. 依赖制品表由调用方按声明算好（本件不猜）。
    pub fn 装载模块登记(
        &mut self,
        适配器: &mut 适配器,
        模块条目: &模块身份,
        模块落点: &str,
        依赖制品表: &[PathBuf],
    ) -> 条目结局 {
        if let Err(拒收原因) = 校制品落点(&模块条目.制品路径, 模块落点) {
            return 条目结局::拒收(拒收原因);
        }
        let Some(启动程序) = self.模块启动程序(&模块条目.标识串) else {
            return 条目结局::拒收("部署配置没给工作进程可执行路径（模块不猜路径）".to_owned());
        };
        let Some(缓存根) = self.缓存根.clone() else {
            return 条目结局::拒收("缓存根未注入：工作进程无处解包模块执行体".to_owned());
        };
        // 启动参数 = 既有工作进程例子的三栏形状：`<模块制品> <支持库制品,逗号分隔|-> <缓存根>`。
        let 模块依赖栏 = if 依赖制品表.is_empty() {
            String::from("-")
        } else {
            依赖制品表
                .iter()
                .map(|制品路径| 制品路径.display().to_string())
                .collect::<Vec<_>>()
                .join(",")
        };
        let 模块域部署 = 域部署 {
            启动程序,
            启动参数: vec![
                模块条目.制品路径.display().to_string(),
                模块依赖栏,
                缓存根.display().to_string(),
            ],
        };
        // **可读面先取**：段 16 读不出来就不发布 —— 否则会出现「调得通、看不见」。
        let 接口说明表 = match v1_adapter::模块执行体装载::取模块接口组(&模块条目.制品路径) {
            Ok(接口说明表) => 接口说明表,
            Err(错误) => {
                return 条目结局::拒收(format!(
                    "模块接口说明读不出（登记了也看不见，故不发布）：{错误:?}"
                ));
            }
        };
        if !适配器.有跨进程域() {
            适配器.开跨进程(self.部署.配置);
        }
        match 适配器.登记模块能力组(&模块条目.标识串, 模块条目.版本, &模块条目.能力号表, 模块域部署) {
            Ok(()) => {
                适配器.登记模块读面(&模块条目.标识串, 模块条目.版本, 接口说明表);
                self.记账模块(模块条目.标识串.clone(), 模块落点.to_owned(), 模块条目.能力号表[0]);
                条目结局::已登记
            }
            Err(错误) => 条目结局::拒收(format!("登记模块执行域失败：{错误:?}")),
        }
    }

    /// 记一条模块登记（**同一个身份串只记一次**；号与落点随最新一次）。
    fn 记账模块(&mut self, 模块身份串: String, 模块落点: String, 模块能力号: u32) {
        if let Some(模块登记项) = self
            .已登记模块表
            .iter_mut()
            .find(|模块登记项| 模块登记项.0 == 模块身份串)
        {
            模块登记项.1 = 模块落点;
            模块登记项.2 = 模块能力号;
            return;
        }
        self.已登记模块表
            .push((模块身份串, 模块落点, 模块能力号));
    }

    /// 运行期**卸载**：按**标识串**注销它的执行域（注销后该号回进程内原路 —— 正是卸载的语义）。
    ///
    /// 与 [`启用状态::装载登记`] 对称（一个登记、一个注销），判据同源。
    ///
    /// 声明由 `取声明` 现取（卸载口只给标识串）：取不到（扩展根没了 / 制品没了）⇒ 如实返回
    /// `false`，**不假装注销过**。登记账里那一条仍摘掉 —— 它的域已不可寻，留着只会骗人。
    pub fn 卸载注销(&mut self, 适配器: &mut 适配器, 本扩展标识串: &str) -> bool {
        // **模块域先摘**（模块没有声明，取不回 `&'static 平台信息`，只能按号回收）：
        // 杀进程组 + 摘域格 + 摘部署表 + 摘路由，与支持库那条路同一个池。
        let 模块能力号 = self
            .已登记模块表
            .iter()
            .find(|模块登记项| 模块登记项.0 == 本扩展标识串)
            .map(|模块登记项| 模块登记项.2);
        self.已登记模块表
            .retain(|模块登记项| 模块登记项.0 != 本扩展标识串);
        if let Some(号值) = 模块能力号
            && 适配器.有跨进程域()
        {
            return 适配器.移除模块跨进程域(号值);
        }
        let 落点 = self.落点(本扩展标识串).map(str::to_owned);
        let 有登记 = self.已登记(本扩展标识串);
        self.已登记.retain(|(标识项, _)| 标识项 != 本扩展标识串);
        if !有登记 || !适配器.有跨进程域() {
            return false;
        }
        // 声明现取：同一个装载器、同一份后缀表与缓存根 ⇒ 同一个库拿到同一个静态指针。
        let (Some(落点), Some(后缀表文本), Some(缓存根)) =
            (落点, self.后缀表文本.as_deref(), self.缓存根.as_deref())
        else {
            return false;
        };
        let Ok(后缀表) = crate::扫扩展根::读后缀表(后缀表文本) else { return false };
        let Ok(声明) =
            crate::扫扩展根::取扩展声明(Path::new(&落点), &后缀表, 缓存根)
        else {
            return false;
        };
        适配器.击杀跨进程域(声明).is_ok()
    }
}
