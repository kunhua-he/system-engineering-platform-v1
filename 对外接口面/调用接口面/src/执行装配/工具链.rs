//! 工具链转调 —— §七 工具族端点背后的**外部 CLI**。
//!
//! # 它转调的是什么（以及**不是**什么）
//!
//! 转调的是**构建 / 验证工具链**（`v1-case-runner` · `构建装配/上线切换/构建制品.py`），
//! **不是能力**。能力的唯一腿仍是 `跨语言适配/适配器实现/`（`分发.rs` 的 `端点::调用`），
//! 本文件与它没有任何交集 —— 本文件里没有 `适配器` 这个词。
//!
//! 判据（`项目文档/设计文档/接口面形状.md` §五 三条不许 第 2 条）：接口面不许绕过适配器
//! 直连**扩展实现**。而案例跑者自身就是经适配器装载并调用的（`测试验证/测试案例/形状.md` §六：
//! 它的 `[dependencies]` 里只有 `v1-adapter` 那条腿）——本面调它，等于经它再走同一条腿。
//!
//! # 为什么用 `std::process::Command`
//!
//! 本仓硬规矩：进制品的形态**零第三方依赖**。`std::process` 是标准库，
//! 而「起一个外部命令并读它的退出码」这件事没有别的形状。
//!
//! # 退出码是**读数**，不是判断
//!
//! 本文件**只把退出码原样带回**（`读数.退出码`），不在这里判「成没成」——
//! 「哪个退出码算失败」是各端点自身的口径（见 `工具响应.rs`），且各端点的失败码不同。
//! 在这里判一次就是把口径分叉成两处。
//!
//! # 超时：请求路只跑短活（长活不许走这条路）
//!
//! 本文件给每次执行设 **5 秒**上限（全项目超时设置上限，见 `项目文档/决策记录/
//! 2026-09-27_所有运行五秒硬顶.md`）；超上限即**结构化超时**（`命令错误::超时`），
//! 子进程被杀，调用方当场拿到失败而不是被挂住。
//!
//! **长活（制品装配器要跑 `cargo build --release`，分钟量级）不许走这条请求路** ——
//! 否则 N 个工作线程会被打满。它该走异步路（提交 + 轮询），那是**另一条腿的活**；
//! 在那之前，本路对长活**当场超时**（fail-closed），不静默挂住。
//! 口径已落库（`规则` 表）：请求路不许跑长活。

use std::io::Read;
use std::path::Path;
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

/// 跑一条外部命令的执行上限（毫秒）。
///
/// **旁路常量**：不是契约里的数，是本面的防挂死策略。全项目超时设置上限 5 秒
/// （`项目文档/决策记录/2026-09-27_所有运行五秒硬顶.md`）⇒ 取满 5 秒。
/// 案例跑者实测 50 ms 量级；**长活不许走这条请求路**（见文件头「超时」）。
const 跑命令超时毫秒: u64 = 5_000;

/// 跑命令失败。**起不来**与**超时**是两件事，调用方要能分开（不许合成一个字符串）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 命令错误 {
    /// 进程起不来（件不存在 / 没有执行权限 / PATH 找不到）。
    起不来 { 程序: String, 说明文字: String },
    /// 进程在 [`跑命令超时毫秒`] 内没退出，已被杀掉。
    超时 { 程序: String, 上限毫秒: u64 },
}

impl 命令错误 {
    /// 失败因的短名（给回执的结构化字段用，与 `Display` 同一口径）。
    pub fn 失败因(&self) -> &'static str {
        match self {
            Self::起不来 { .. } => "起不来",
            Self::超时 { .. } => "超时",
        }
    }
}

impl std::fmt::Display for 命令错误 {
    fn fmt(&self, 格式器: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::起不来 { 程序, 说明文字 } => write!(格式器, "起不了 {程序}：{说明文字}"),
            Self::超时 { 程序, 上限毫秒 } => {
                write!(格式器, "跑命令超时：{程序} 在 {上限毫秒} 毫秒内没退出（已杀）")
            }
        }
    }
}

/// 一次外部命令的读数。
#[derive(Debug, Clone)]
pub struct 读数 {
    /// 进程退出码。**被信号杀掉时是 `-1`**（`ExitStatus::code()` 给 `None`），
    /// 不编一个 `0` 出来 —— 编 `0` 就是把「没跑成」写成「跑成了」。
    pub 退出码: i32,
    pub 标准输出: String,
    pub 标准错误: String,
}

impl 读数 {
    /// 退出码是不是 `0`。各端点用它，但**失败码由各端点自身定**（本文件不判）。
    pub fn 是否成功(&self) -> bool {
        self.退出码 == 0
    }
}

/// 跑一条外部命令。**5 秒硬顶，且覆盖执行与输出收尾**（见文件头「超时」）：超上限即结构化超时。
///
/// `程序` 可以是绝对路径（案例跑者）或命令名（`python3`，按 PATH 解析）。
/// `工作目录` 是**注入的部署事实**（`服务::工具根`）—— 相对参数按它解，
/// 与 §五 静态托管「相对进程工作目录」同一口径。
///
/// # deadline 同时管两段（审计发现6 · P2）
///
/// 原先的循环靠 `子进程.try_wait()` 判退出后 **无期限 `join`** 抽干线程，理据是「子进程已退出
/// ⇒ 管道写端已关」—— **那个前提是错的**：孙进程可以继承并持有写端（审计实测
/// `/bin/sh -c 'sleep 7 & exit 0'` 父进程当场退出，函数却约 7.01 秒后才返回 `Ok`）。
/// 现在同一把 deadline 管两段：
///
/// 1. **执行段**：轮询 `try_wait` 直到退出或到期；
/// 2. **收尾段**：抽干线程把字节通过通道**发回主线程**（不再是 `join`），主线程只在
///    **剩余期限内**收（见 `收有界`）；过期即**结构化超时**并弃句柄（旧先例：超时路不 join）。
///
/// 失败分两种（[`命令错误`]）：**起不来**（件不存在 / 没有执行权限）与**超时**，
/// 调用方要能分开 —— 「跑者不存在」「跑了但超时」「跑了但退出码非零」是三件事。
pub fn 跑命令取读数(程序: &Path, 命令行参数: &[&str], 工作目录: &Path) -> Result<读数, 命令错误> {
    let mut 子进程 = Command::new(程序)
        .args(命令行参数)
        .current_dir(工作目录)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|错误| 命令错误::起不来 {
            程序: 程序.display().to_string(),
            说明文字: 错误.to_string(),
        })?;
    // 管道**并发抽干**：不抽的话子进程写满管道缓冲就阻塞，超时会被误报成「挂住」。
    // 抽干线程读完把字节**发回主线程**（不是 join）：主线程据此对**收尾**也上同一把 deadline。
    // 两路各用一条通道 —— 合成一路会让「输出先完、错误随后」的读数被错位归到同一路。
    let (输出发送端, 输出接收端) = std::sync::mpsc::channel();
    let (错误发送端, 错误接收端) = std::sync::mpsc::channel();
    let 抽输出 = 子进程.stdout.take().map(|管道| {
        std::thread::spawn(move || {
            let _ = 输出发送端.send(抽干管道(管道));
        })
    });
    let 抽错误 = 子进程.stderr.take().map(|管道| {
        std::thread::spawn(move || {
            let _ = 错误发送端.send(抽干管道(管道));
        })
    });
    let 期限 = Instant::now() + Duration::from_millis(跑命令超时毫秒);
    let 退出码 = loop {
        match 子进程.try_wait() {
            Ok(Some(状态)) => break 状态.code().unwrap_or(-1),
            Ok(None) => {}
            Err(错误) => {
                let _ = 子进程.kill();
                let _ = 子进程.wait();
                return Err(命令错误::起不来 {
                    程序: 程序.display().to_string(),
                    说明文字: 错误.to_string(),
                });
            }
        }
        if Instant::now() >= 期限 {
            let _ = 子进程.kill();
            let _ = 子进程.wait();
            return Err(命令错误::超时 {
                程序: 程序.display().to_string(),
                上限毫秒: 跑命令超时毫秒,
            });
        }
        std::thread::sleep(Duration::from_millis(10));
    };
    // ── 收尾段也受**同一把 deadline**（发现6）：孙进程可继承管道写端，退出不等于写端已关。
    // 句柄**不 join**（超时即弃，与旧「超时路不 join」同一取舍）—— 两路各自在期限内收。
    drop(抽输出);
    drop(抽错误);
    let 标准输出 = 收有界(&输出接收端, 期限).ok_or_else(|| 命令错误::超时 {
        程序: 程序.display().to_string(),
        上限毫秒: 跑命令超时毫秒,
    })?;
    let 标准错误 = 收有界(&错误接收端, 期限).ok_or_else(|| 命令错误::超时 {
        程序: 程序.display().to_string(),
        上限毫秒: 跑命令超时毫秒,
    })?;
    Ok(读数 {
        退出码,
        标准输出: 转文本(&标准输出),
        标准错误: 转文本(&标准错误),
    })
}

/// 抽干一个子进程管道到字节集（读到 EOF 为止；坏字节不丢）。
fn 抽干管道(mut 管道: impl Read) -> Vec<u8> {
    let mut 缓冲 = Vec::new();
    let _ = 管道.read_to_end(&mut 缓冲);
    缓冲
}

/// 在 `期限` 内收一路抽干结果。**到期给 `None`**（调用方据此报结构化超时，弃句柄不 join）。
///
/// 两种结局分开（不合成一个 `None`）：**到期**才配报超时；**发送端已断**（抽干线程自行结束
/// 却没交回字节）说明它已经停了，再等也无用 ⇒ 如实给空字节集，不把它也报成超时。
///
/// 两路（输出 / 错误）**共用同一把绝对 deadline** —— 各给一个相对时长会让总时长翻倍，
/// 那就把硬顶让给了被调方。
fn 收有界(接收端: &std::sync::mpsc::Receiver<Vec<u8>>, 期限: Instant) -> Option<Vec<u8>> {
    use std::sync::mpsc::RecvTimeoutError;
    let 剩余时限 = 期限.saturating_duration_since(Instant::now());
    match 接收端.recv_timeout(剩余时限) {
        Ok(字节集) => Some(字节集),
        Err(RecvTimeoutError::Disconnected) => Some(Vec::new()),
        Err(RecvTimeoutError::Timeout) => None,
    }
}

/// 子进程的输出按 UTF-8 解。**坏字节不丢**（`from_utf8_lossy`）：
/// 丢字节会让回执里的读数与实际不符，而回执的用途正是「事后能查」。
fn 转文本(字节: &[u8]) -> String {
    String::from_utf8_lossy(字节).trim().to_owned()
}

#[cfg(test)]
mod 测试 {
    use super::*;

    /// **反向样本（跑命令无超时）**：一条跑 30 秒的命令必须在 5 秒硬顶内被结构化拒绝，
    /// 不许把调用方挂住（修前 `Command::output()` 会一直等到它跑完）。
    #[test]
    fn 跑命令_长活超时即拒() {
        let 起点 = Instant::now();
        let 结局 = 跑命令取读数(Path::new("/bin/sleep"), &["30"], Path::new("."));
        let 耗时 = 起点.elapsed();
        match 结局 {
            Err(命令错误::超时 { 上限毫秒, .. }) => assert_eq!(上限毫秒, 跑命令超时毫秒),
            Err(其余值) => panic!("必须是结构化超时，实际报：{其余值:?}"),
            Ok(读数) => panic!("长活必须超时，实际拿到读数：{读数:?}"),
        }
        assert!(耗时 < Duration::from_secs(6), "超时判定要快，实测 {耗时:?}");
    }

    /// 正向样本：一条短命令正常跑完，读数带退出码与输出（超时路不许把正常路弄坏）。
    #[test]
    fn 跑命令_短活正常返回() {
        let 读数 = 跑命令取读数(Path::new("/bin/echo"), &["好"], Path::new(".")).expect("echo 该跑得成");
        assert_eq!(读数.退出码, 0);
        assert_eq!(读数.标准输出, "好");
    }

    /// **反向样本（管道收尾也受硬顶 · 审计发现6）**：父进程当场退出，而**孙进程继承并持有管道
    /// 写端**（`sleep 7 &`）。旧实现「子进程退出 ⇒ 写端已关」的前提不成立 ⇒ 无期限 join 抽干
    /// 线程，实测约 7.01 秒才返回 `Ok`，越过 5 秒硬顶。本用例钉住「收尾段与执行段共用同一把
    /// deadline」：必须在硬顶内返回**结构化超时**，不许挂住、不许返回旧读数。
    #[test]
    fn 跑命令_孙进程持管道仍按硬顶超时() {
        let 起点 = Instant::now();
        let 结局 = 跑命令取读数(Path::new("/bin/sh"), &["-c", "sleep 7 & exit 0"], Path::new("."));
        let 耗时 = 起点.elapsed();
        match 结局 {
            Err(命令错误::超时 { 上限毫秒, .. }) => assert_eq!(上限毫秒, 跑命令超时毫秒),
            Err(其余值) => panic!("必须是结构化超时，实际报：{其余值:?}"),
            Ok(读数) => panic!("孙进程持管道必须超时，实际拿到读数：{读数:?}"),
        }
        assert!(耗时 < Duration::from_secs(6), "超时判定要快，实测 {耗时:?}");
    }
}
