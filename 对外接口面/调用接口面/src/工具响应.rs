//! 工具族端点的返回组装 —— 逐条照 `项目文档/设计文档/接口面形状.md` §七。
//!
//! # 这一族为什么长这样（与 §三 的差别，一条一条说清）
//!
//! §三 的四个端点返回的是**能力调用的结果**：`值` 是「带类型标签的定长槽」数组。
//! §七 的六个端点返回的是**工具链的读数**（案例清单 · 回执 · 子进程退出码 · 扩展清单）——
//! 它们**不是槽**，硬塞进 `值` 就等于给 `值` 编一个「有时是槽、有时是对象」的第二含义
//! （同一件事两套形状）。故 §七 一律用**旁路字段 `数据`** 承载载荷：
//!
//! ```text
//! { "成功": true,  "数据": { … }, "耗时微秒": N }
//! { "成功": false, "错误": { 码 · 段位 · 名称 · 可重试 · 可自愈 · 需人工 · 已登记 },
//!   "数据": { … }, "耗时微秒": N }
//! ```
//!
//! §三 那三问（成功没成功 · 拿到什么 · 失败为什么）照旧被回答：`成功` / `数据` / `错误.码`。
//! **失败时的 `数据` 是结构化回执**（说清缺什么裁决、哪一步失败、子进程退出码是多少），
//! 不是「失败就不给信息」——那正是 `9001` 与 `9008`–`9012` 这一族码存在的理由。
//!
//! # 失败一律回**真错误码**
//!
//! 这一族码（段位 9）的唯一来源是 `契约声明/错误码表/9xxx.json`（`常量.rs::工具码`）。**不许自造码、
//! 不许把失败写成成功。** 每一条 `失败(…)` 的调用点旁边都写清「为什么是这一个码」。
//!
//! # 一处结构性限制（如实登记，不假装覆盖了）
//!
//! `错误对象::由码` 要一个「查找提示号」（先看这个号自身的契约，再看全清单）。本族的失败
//! **不是某条能力的失败**，故提示号给 `0`（底座自身的第一条命令）——它只是查找提示，
//! 不是判定依据（`错误形状.rs` 的文件头就是这么定的）。段位 9 的登记项因此能被找到，
//! 回执里的 `名称` / 三项业务判断都从声明现读。
//!
//! # 文件分工（本文件是路由：共用组装件 + 声明子模块 · 再导出公开面）
//!
//! 本文件原先是 757 行的单件（超 400 行上限），按端点族拆开 —— 每个子件只装一族端点的
//! 返回组装，共用件（`成功` / `失败` / `耗时` / 路径与 JSON 读法）只在本文件一份：
//!
//! - `工具响应_案例.rs` —— 案例族：`GET /接口/案例` · `POST /接口/案例/跑`
//! - `工具响应_扩展.rs` —— 列扩展：`GET /接口/扩展`
//! - `工具响应_导出.rs` —— 导出族：`POST /接口/导出`
//! - `工具响应_未落.rs` —— 两条旁路端点：`POST /接口/程序文本`（真读 / 真写，9008–9012）· `POST /接口/菜单命令`（9001）
//!
//! 拆件只动**文件边界**：六个端点的返回形状与七个码**一个都没动**。

