/// **连发两个请求，互不影响**：先失败后成功，成功的那条与单独发时逐字段相同。
/// 同一条请求发两次，结果也必须逐字段相同（入口不留上次的痕迹）。
#[test]
fn 无状态_连发两个请求互不影响() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 参数个数 = 服务.适配器().能力契约(编号).expect("契约").参数表.len();
    let 空位 = "{\"类型标签\":0,\"值\":0}";
    let 好体 = format!(
        "{{\"编号\":{编号},\"值\":[{}]}}",
        vec![空位; 参数个数].join(",")
    );

    // 先来一条失败的：它不许在入口留下任何痕迹。
    let 坏甲 = 发(&服务, &交请求("/接口/调用", "{\"编号\":999999,\"值\":[]}"));
    assert!(!坏甲.取布尔("成功"));
    let 坏乙 = 发(&服务, &交请求("/接口/调用", "{\"编号\":999999,\"值\":[]}"));
    assert_eq!(
        坏甲.取("错误"),
        坏乙.取("错误"),
        "同一个失败两次必须逐字段相同（无状态）"
    );

    // 再来两条成功的：逐字段相同（`耗时微秒` 是唯一的时变量，不参与比对）。
    let 好甲 = 发(&服务, &交请求("/接口/调用", &好体));
    let 好乙 = 发(&服务, &交请求("/接口/调用", &好体));
    assert!(好甲.取布尔("成功") && 好乙.取布尔("成功"));
    assert_eq!(好甲.取("值"), 好乙.取("值"), "无状态：值不许随请求次序变");
    assert_eq!(好甲.取("值"), 发(&服务, &交请求("/接口/调用", &好体)).取("值"));
}

/// **多实例**：同进程开两个服务（各自一份适配器、各自一本配额账本），互不干扰。
///
/// 这条同时钉住「唯一对外门不等于全局单例」：`全局连接器与网关.md` 第六节
/// 「不用全局单例实现全局唯一」—— 用单例实现唯一性就同时丢掉了多实例安全。
#[test]
fn 多实例_两个服务互不干扰() {
    let 甲 = 起服务();
    let 乙 = 起服务();
    assert_ne!(甲.端口(), 乙.端口(), "两个实例各绑一个端口");

    let 编号 = 第一个能力号(&甲);
    发(&甲, &交请求("/接口/调用", "{\"编号\":999999,\"值\":[]}"));
    let 应答 = 发(&乙, &取请求(&format!("/接口/能力/{编号}")));
    assert_eq!(应答.状态, 200);
    assert!(应答.取布尔("成功"), "乙不许被甲的失败影响");
}
