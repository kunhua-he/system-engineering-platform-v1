//! 搜索响应 —— `GET /接口/搜索` 的对外形状。
//!
//! **同源**：命中表取自 `适配器::能力清单()` —— 与 `POST /接口/调用` 走的是同一份已载入台账
//! （读侧与调侧同一入口）。不另扫盘、不另建索引：另建一份就是第二个事实源，
//! 而它一定会与「实际能不能调」分叉。
//!
//! 匹配面（三条，都不猜）：
//!
//! 1. `名称` 含关键词（子串）。
//! 2. `编号` 的十进制文本含关键词（想找「1324」直接搜得到）。
//! 3. 契约的 `说明文字` 含关键词 —— 说明**不在** `能力摘要` 里（那四样就是四样），
//!    所以按需取契约：名称/编号已命中就不取（省一次读）。
//!
//! 分页是**上下文预算**：一次只回 `一次条数` 条，但把 `命中总数` / `下页起始` / `截断`
//! 一并给全 —— 调用方能据此决定还要不要下一页，而不是被无声截断。

use crate::协议值::协议值;
use crate::搜索请求::搜索请求;
use crate::工具响应::造成功应答;
use std::time::Instant;
use v1_adapter::{能力摘要, 适配器};

/// `GET /接口/搜索` 的应答。
pub fn 搜索(适配器: &适配器, 请求: &搜索请求) -> 协议值 {
    let 区间起点 = Instant::now();
    let 能力清单 = 适配器.能力清单();
    let 命中表: Vec<&能力摘要> = 能力清单
        .iter()
        .filter(|能力行| 命中(适配器, 能力行, &请求.关键词))
        .collect();
    let 命中总数 = 命中表.len();
    let 起点 = (请求.起始 as usize).min(命中总数);
    let 末位 = (起点 + 请求.一次条数 as usize).min(命中总数);
    let 还有下一页 = 末位 < 命中总数;
    造成功应答(
        协议值::对象值(vec![
            ("关键词".to_owned(), 协议值::文本值(请求.关键词.clone())),
            ("命中总数".to_owned(), 协议值::无符号值(命中总数 as u64)),
            ("起始".to_owned(), 协议值::无符号值(请求.起始 as u64)),
            ("本页条数".to_owned(), 协议值::无符号值((末位 - 起点) as u64)),
            (
                "下页起始".to_owned(),
                if 还有下一页 {
                    协议值::无符号值(末位 as u64)
                } else {
                    协议值::空值项
                },
            ),
            (
                "截断".to_owned(),
                if 还有下一页 {
                    协议值::真值
                } else {
                    协议值::假值
                },
            ),
            (
                "命中".to_owned(),
                协议值::数组值(
                    命中表[起点..末位]
                        .iter()
                        .map(|能力行| 造命中(能力行))
                        .collect(),
                ),
            ),
        ]),
        &区间起点,
    )
}

/// 一行命中：四样与 `能力摘要` 同形（不多给）。
fn 造命中(能力行: &能力摘要) -> 协议值 {
    协议值::对象值(vec![
        ("编号".to_owned(), 协议值::无符号值(能力行.编号 as u64)),
        ("名称".to_owned(), 协议值::文本值(能力行.名称.clone())),
        ("参数个数".to_owned(), 协议值::无符号值(能力行.参数个数 as u64)),
        (
            "返回类型".to_owned(),
            协议值::无符号值(能力行.返回类型 as u64),
        ),
    ])
}

/// 一条摘要命不命中。`名称`/`编号` 先判；都没中才去取契约看 `说明文字`。
fn 命中(适配器: &适配器, 能力行: &能力摘要, 关键词: &str) -> bool {
    if 能力行.名称.contains(关键词) || 能力行.编号.to_string().contains(关键词) {
        return true;
    }
    match 适配器.能力契约(能力行.编号) {
        Some(契约) => 契约.说明文字.contains(关键词),
        None => false,
    }
}
