//! 工具链转调 —— §七 工具族端点背后的**外部 CLI**。
//!
//! # 它转调的是什么（以及**不是**什么）
//!
//! 转调的是**构建 / 验证工具链**（`v1-case-runner` · `构建装配/上线切换/构建制品.py`），
//! **不是能力**。能力的唯一腿仍是 `跨语言适配/适配器实现/`（`分发.rs` 的 `端点::调用`），
//! 本文件与它没有任何交集 —— 本文件里没有 `适配器` 这个词。
//!
//! 判据（`项目文档/设计文档/接口面形状.md` §五 三条不许 第 2 条）：接口面不许绕过适配器
//! 直连**扩展实现**。而案例跑者自己就是经适配器装载并调用的（`测试验证/案例/形状.md` §六：
//! 它的 `[dependencies]` 里只有 `v1-adapter` 那条腿）——本面调它，等于经它再走同一条腿。
//!
//! # 为什么用 `std::process::Command`
//!
//! 本仓硬规矩：进制品的形态**零第三方依赖**。`std::process` 是标准库，
//! 而「起一个外部命令并读它的退出码」这件事没有别的形状。
//!
//! # 退出码是**读数**，不是判断
//!
//! 本文件**只把退出码原样带回**（`读数.退出码`），不在这里判「成没成」——
//! 「哪个退出码算失败」是各端点自己的口径（见 `工具响应.rs`），且各端点的失败码不同。
//! 在这里判一次就是把口径分叉成两处。
//!
//! # 一处如实登记的缺口
//!
//! **超时**：本文件不设执行上限。案例跑者实测 50 ms 量级，但制品装配器要跑
//! `cargo build --release`（分钟量级）。给不给上限、给多少，是部署策略而不是契约里的数
//! ⇒ 未裁，如实登记在 `接口面形状.md` §七 的「缺口」。**不静默给一个数**：
//! 猜一个上限会在慢机器上把真成功报成失败（假红），而假红会训练人忽略红灯。

use std::path::Path;
use std::process::Command;

/// 一次外部命令的读数。
#[derive(Debug, Clone)]
pub struct 读数 {
    /// 进程退出码。**被信号杀掉时是 `-1`**（`ExitStatus::code()` 给 `None`），
    /// 不编一个 `0` 出来 —— 编 `0` 就是把「没跑成」写成「跑成了」。
    pub 退出码: i32,
    pub 标准输出: String,
    pub 标准错误: String,
}

impl 读数 {
    /// 退出码是不是 `0`。各端点用它，但**失败码由各端点自己定**（本文件不判）。
    pub fn 成功(&self) -> bool {
        self.退出码 == 0
    }
}

/// 跑一条外部命令。
///
/// `程序` 可以是绝对路径（案例跑者）或命令名（`python3`，按 PATH 解析）。
/// `工作目录` 是**注入的部署事实**（`服务::工具根`）—— 相对参数按它解，
/// 与 §五 静态托管「相对进程工作目录」同一口径。
///
/// 起不来的原因（件不存在 / 没有执行权限）**原样带回**，不吞：
/// 「跑者不存在」与「跑者跑了但退出码非零」是两件事，调用方要能分开。
pub fn 跑(程序: &Path, 参数: &[&str], 工作目录: &Path) -> Result<读数, String> {
    let 出 = Command::new(程序)
        .args(参数)
        .current_dir(工作目录)
        .output()
        .map_err(|错| format!("起不了 {}：{错}", 程序.display()))?;
    Ok(读数 {
        退出码: 出.status.code().unwrap_or(-1),
        标准输出: 转文本(&出.stdout),
        标准错误: 转文本(&出.stderr),
    })
}

/// 子进程的输出按 UTF-8 解。**坏字节不丢**（`from_utf8_lossy`）：
/// 丢字节会让回执里的读数与实际不符，而回执的用途正是「事后能查」。
fn 转文本(字节: &[u8]) -> String {
    String::from_utf8_lossy(字节).trim().to_owned()
}
