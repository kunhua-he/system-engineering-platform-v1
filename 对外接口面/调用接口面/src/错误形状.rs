//! 失败形状 —— **业务失败一律 HTTP 200 + `"成功": false` + 结构化错误对象**。
//!
//! 冻结件 `接口面形状.md` §三：
//!
//! ```text
//! { "成功": false,
//!   "错误": { "码": 1, "段位": 0, "名称": "提供者未载入",
//!             "可重试": false, "可自愈": true, "需人工": false },
//!   "耗时微秒": 8 }
//! ```
//!
//! **失败不抛 HTTP 5xx。** 理由是宪法级的：失败是**可编程处理的数据**。塞进 HTTP 状态码
//! 就等于让调用方去解析协议层，而协议层不该承载业务。HTTP 状态码在本面只表达一件事：
//! **请求本身合不合法**（400 / 404 / 405），见 `端点.rs`。
//!
//! # 六项从哪来（一处缺口，如实登记）
//!
//! `码 · 名称 · 可重试 · 可自愈 · 需人工` 五项**当场从适配器取**——`适配器::能力契约` 的
//! `可抛错误码` 就是声明的错误码表，不另存一份表（同一入口，与 `能力清单` 同一条理由）。
//!
//! 两处取不到，只能由网关补：
//!
//! 1. **`码` 本身**：`调度错误` 的五个变体**不带码**，适配器也没有「调度错误 → 错误码」
//!    这个口。⇒ 下面这五个数只能写在这里，**是同一事实的第二来源**（唯一来源是
//!    `契约声明/错误码表/*.json`）。修法在适配器（给它一个口）或 `调度错误`（变体带码），
//!    不在网关里再抄一张六项表。
//! 2. **`段位`**：`错误码摘要` 没有这一项（`错误码信息` 结构里有）。段位是 `码` 的纯函数，
//!    故按契约口径 `段位 = 码 / 号段类宽度` 除一次（`号段类宽度` 本身也是占位常量，
//!    见 `常量.rs`）。
//!
//! 取不到登记时（某个码不在任何已装载声明的错误码表里）**不编一个名字**：
//! `名称` 留空、三项置 `false`，并加一个旁路字段 `已登记: false` 把缺口暴露在返回里
//! （冻结件允许新增旁路字段）。编一个名字等于把「未登记」这件事藏起来。

use super::线上逻辑值::真假值转线上值;
use crate::协议值::协议值;
use crate::常量::号段类宽度;
use v1_adapter::{适配器, 调度错误, 错误码摘要};

/// `调度错误` 的五个变体对应的错误码。
///
/// **待适配器给出「调度错误 → 错误码」的口后改成引用**。五个数的唯一来源是
/// `契约声明/错误码表/*.json`（文件名就是码）。
pub(crate) mod 码值 {
    /// 提供者未载入。
    pub const 提供者未载入: u32 = 1;
    /// 命令已废止。
    pub const 命令已废止: u32 = 2;
    /// 参数个数不符。
    pub const 参数个数不符: u32 = 3;
    /// 输入形状不符（入参槽的类型标签与声明的参数表对应行不符）。
    /// 与「参数个数不符」（码 3）分开：个数对而类型错是另一件事。
    pub const 输入形状不符: u32 = 25;
    /// 超时。
    pub const 超时: u32 = 4;
    /// 配额用尽。
    pub const 配额用尽: u32 = 5;
    /// 扩展执行崩溃（扩展的执行函数 panic，被调度层接住）。
    /// 与「超时」（码 4）分开：那是没在预算内答，本码是它崩了；
    /// 与「提供者未载入」（码 1）分开：那是没进扩展，本码是已经进去了。
    pub const 扩展执行崩溃: u32 = 35;
}

/// 一个结构化的失败 —— 冻结件要的六项（+ 一个旁路项）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 错误对象 {
    pub 码值: u32,
    pub 段位: u32,
    pub 名称: String,
    pub 可重试: bool,
    pub 可自愈: bool,
    pub 需人工: bool,
    /// 旁路字段：这个码在**任何一份已装载声明**的错误码表里都没登记。
    /// 契约规定「未登记的错误码不许抛出」⇒ 出现 `false` 即是一条缺陷证据，不是正常态。
    pub 已登记: bool,
}

impl 错误对象 {
    /// 由调度段位 + 适配器当场取到的登记项成形。
    ///
    /// `被调号` 只作**查找提示**（先看这个号自身的契约），不是判定依据 ——
    /// 代码里没有任何一个具体能力编号。
    pub fn 由调度错误(适配器: &适配器, 被调号: u32, 错误: 调度错误) -> Self {
        let 错误码 = match 错误 {
            调度错误::提供者未载入 { .. } => 码值::提供者未载入,
            调度错误::命令已废止 { .. } => 码值::命令已废止,
            调度错误::参数个数不符 { .. } => 码值::参数个数不符,
            调度错误::输入形状不符 { .. } => 码值::输入形状不符,
            调度错误::超时 { .. } => 码值::超时,
            调度错误::配额用尽 => 码值::配额用尽,
            调度错误::扩展执行崩溃 => 码值::扩展执行崩溃,
        };
        Self::由错误码(适配器, 被调号, 错误码)
    }

    /// 由一个错误码成形：登记项从适配器取，段位按契约口径导出。
    pub fn 由错误码(适配器: &适配器, 被调号: u32, 错误码: u32) -> Self {
        let 登记 = 查登记(适配器, 被调号, 错误码);
        Self {
            码值: 错误码,
            段位: 错误码 / 号段类宽度,
            名称: 登记.as_ref().map_or_else(String::new, |登记项| 登记项.名称.clone()),
            可重试: 登记.as_ref().is_some_and(|登记项| 登记项.可重试),
            可自愈: 登记.as_ref().is_some_and(|登记项| 登记项.可自愈),
            需人工: 登记.as_ref().is_some_and(|登记项| 登记项.需人工),
            已登记: 登记.is_some(),
        }
    }

    /// → JSON 对象（键序与冻结示例一致）。
    pub fn 到协议值(&self) -> 协议值 {
        协议值::对象值(vec![
            ("码".to_owned(), 协议值::整数项(i64::from(self.码值))),
            ("段位".to_owned(), 协议值::整数项(i64::from(self.段位))),
            ("名称".to_owned(), 协议值::文本值(self.名称.clone())),
            ("可重试".to_owned(), 真假值转线上值(self.可重试)),
            ("可自愈".to_owned(), 真假值转线上值(self.可自愈)),
            ("需人工".to_owned(), 真假值转线上值(self.需人工)),
            ("已登记".to_owned(), 真假值转线上值(self.已登记)),
        ])
    }
}

/// 在**被调号所属声明**的错误码全表里找这个码的登记项。**当场取，不缓存、不另存一份表。**
///
/// 走 [`适配器::声明错误码表`]（`平台信息.错误码表` 全表），不走 `能力契约.可抛错误码` ——
/// 后者是**这条命令自身**登记的可抛码（源 = `命令信息.可抛错误码`），而这里要查的多是
/// **调度层**产生的码（提供者未载入 / 已废止 / 参数个数不符 / 超时 / 配额用尽，段位 0），
/// 它们**不属任何一条命令** ⇒ 只能从声明全表里查。
///
/// 全都不认时给 `None` ⇒ 调用方据此把 `已登记` 置 `false`（**不编一个名字**）。
fn 查登记(适配器: &适配器, 被调号: u32, 错误码: u32) -> Option<错误码摘要> {
    适配器
        .声明错误码表(被调号)
        .into_iter()
        .find(|错误码项| 错误码项.码值 == 错误码)
        .or_else(|| 适配器.声明错误码表(0).into_iter().find(|错误码项| 错误码项.码值 == 错误码))
}

/// 失败之后能不能重试 —— **机器可判的三项**（`2026-10-07_核心架构收敛方案` §九.2/§九.3 · §32.4）。
///
/// # 为什么要有它（缺口，如实登记）
///
/// §九.2 明写：「需要判断重试时，表达执行阶段、结果是否确定和重试前提」。
/// 六项里只有 `可重试` 一个逻辑值 —— 它出自**声明的错误码表**（`错误码表/0004.json` 的
/// `可重试: true`），说的是「这个码在契约里允许重试」，**说不出**「这一次到底有没有进入
/// 扩展」：超时（码 4）与提供者未载入（码 1）在契约里都可重试，但前者**执行已经发生、
/// 副作用可能已落**，后者**确定没进扩展**。§九.3 那张表把两者分得清清楚楚
/// （「执行前拒绝」vs「超时、断线或崩溃，不能确认副作用是否发生 ⇒ 返回结果未知，不自动重放」）。
/// 只报 `可重试: true`，Agent 就会把「结果未知」当成「可以安全重放」—— 那正是 §九.3 禁止的。
///
/// # 值的来源（不新造语义，只把调度核心已有的事实暴露出来）
///
/// `运行内核/调用调度/src/调度核心.rs` 的判定顺序是**冻结的**：
/// `按号取命令 → 判未载入/废止 → 校个数 → 校类型 → 问配额 → 执行 → 记账超时`。
/// 前五步**都在 `执行(...)` 之前返回**（且都 `置空返回槽`），只有**超时**是执行**之后**
/// 才判的（且**不清返回槽** —— 执行方可能已交出所有权）。⇒ 「有没有进入扩展」这件事
/// 调度层**本来就分得开**，本结构只把它翻译成对外的三个字段，不重新判定任何一次失败。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 重试判据 {
    /// 这次失败发生在哪一步（闭合三值，见 [`执行阶段`]）。
    pub 执行阶段: 执行阶段,
    /// **扩展的副作用是否可能已经发生**。`执行阶段 = 已进入扩展` ⇒ 真（执行已发起，
    /// 无论扩展回的是错误码还是我们判的超时）；其余为假。
    pub 可能已执行: bool,
    /// **扩展的最终结果是否已知**。超时 ⇒ 假（执行已发生而我们没拿到结果，§九.3 的
    /// 「结果未知」）；扩展回了结构化错误码 ⇒ 真（它自身报了结局）；未进入扩展 ⇒ 真
    /// （确定没执行，结果就是没执行）。
    pub 结果确定: bool,
}

/// 失败发生在哪一步（闭合三值）。**不许按前缀猜**，读的人按整词比。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 执行阶段 {
    /// 执行前拒绝：调度在 `执行(...)` 之前就返回了（未载入 / 已废止 / 参数个数不符 /
    /// 输入形状不符 / 配额用尽）⇒ **确定没有进入扩展**，重试按既有错误语义判。
    未进入扩展,
    /// 执行已经发起：扩展回了结构化错误码，或我们判了超时。
    已进入扩展,
    /// 本失败**不是一次能力调用**（工具族的段位 9 码）——「进入扩展」对它无意义。
    非能力调用,
}

impl 重试判据 {
    /// 执行前拒绝 ⇒ 确定没进扩展、结果确定（§九.3 第一行）。
    pub fn 未进入扩展() -> Self {
        Self { 执行阶段: 执行阶段::未进入扩展, 可能已执行: false, 结果确定: true }
    }

    /// 扩展回了结构化错误码 ⇒ 副作用可能已落，但**结果确定**（它自身报了结局）。
    pub fn 扩展已回错误码() -> Self {
        Self { 执行阶段: 执行阶段::已进入扩展, 可能已执行: true, 结果确定: true }
    }

    /// 超时 ⇒ **结果未知**（§九.3 第三行：返回结果未知，不自动重放）。
    pub fn 超时结果未知() -> Self {
        Self { 执行阶段: 执行阶段::已进入扩展, 可能已执行: true, 结果确定: false }
    }

    /// 不是能力调用（工具族 / 网关面）⇒ 「进入扩展」不适用；这两个逻辑值按
    /// **扩展副作用**的口径给假 / 真（本面判的是扩展有没有被进入，不是工具链自身有没有动盘）。
    pub fn 非能力调用() -> Self {
        Self { 执行阶段: 执行阶段::非能力调用, 可能已执行: false, 结果确定: true }
    }

    /// 由**调度错误**定档 —— 只看它是「执行前返回的五个」还是「执行后判的超时」。
    ///
    /// 依据是 `调度核心.rs` 的判定顺序（见 [`重试判据`] 文件头）：五个非超时错误一律在
    /// `执行(...)` 之前 `return`，超时在执行之后。分档表只此一处，不散到调用点。
    pub fn 由调度错误(错误: 调度错误) -> Self {
        match 错误 {
            调度错误::超时 { .. } => Self::超时结果未知(),
            调度错误::扩展执行崩溃 => Self::扩展已回错误码(),
            调度错误::提供者未载入 { .. }
            | 调度错误::命令已废止 { .. }
            | 调度错误::参数个数不符 { .. }
            | 调度错误::输入形状不符 { .. }
            | 调度错误::配额用尽 => Self::未进入扩展(),
        }
    }

    /// → JSON 对象。三个键名都是**读侧直接判的机器字段**，不是散文。
    pub fn 到协议值(&self) -> 协议值 {
        协议值::对象值(vec![
            (
                "执行阶段".to_owned(),
                协议值::文本值(match self.执行阶段 {
                    执行阶段::未进入扩展 => "未进入扩展",
                    执行阶段::已进入扩展 => "已进入扩展",
                    执行阶段::非能力调用 => "非能力调用",
                }
                .to_owned()),
            ),
            ("可能已执行".to_owned(), 真假值转线上值(self.可能已执行)),
            ("结果确定".to_owned(), 真假值转线上值(self.结果确定)),
        ])
    }
}

/// 协议层失败（HTTP 400 / 404 / 405）的返回体。
///
/// **与业务失败分开**：这里没有 `错误` 对象——协议层失败不是「某条能力失败」，
/// 编一个 `码` 出来就是伪造业务数据。HTTP 状态码本身就表达了这个判定，
/// `协议错误` 只是一句可读的说明（旁路字段，冻结件允许新增）。
pub fn 协议错误(说明文字: &str) -> 协议值 {
    协议值::对象值(vec![
        ("成功".to_owned(), 协议值::假值),
        ("协议错误".to_owned(), 协议值::文本值(说明文字.to_owned())),
    ])
}
