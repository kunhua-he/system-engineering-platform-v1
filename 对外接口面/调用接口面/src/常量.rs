/// 端点表 —— `接口面形状.md` §二 的四个端点，**一个不多一个不少**。
///
/// 根端点把这张表原样交出去：agent 的第一次调用就是 `GET /接口`，
/// 它的返回里同时给出「有哪些端点」和「有哪些能力」（§一 判据的直接后果）。
pub const 端点表: [(&str, &str, &str); 4] = [
    ("GET", "/接口", "本清单"),
    ("GET", "/接口/能力/<编号>", "单条能力的契约"),
    (
        "POST",
        "/接口/调用",
        "体：{\"编号\":N,\"值\":[...]}；值按契约行序",
    ),
    ("POST", "/接口/声明", "写声明；面校验通过才落盘"),
];

/// 根端点的路径前缀。**路由只看它**，不出现任何一个具体能力编号（判据：0 处业务判断）。
pub const 路径_根: &str = "/接口";
/// 单条能力契约的路径前缀。
pub const 路径_能力: &str = "/接口/能力/";
/// 调用端点的路径。
pub const 路径_调用: &str = "/接口/调用";
/// 声明端点的路径。
pub const 路径_声明: &str = "/接口/声明";
