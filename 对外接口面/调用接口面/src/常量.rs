//! 契约级常量 —— 网关必须知道、但**没有任何公开面给得出**的那几个数。
//!
//! # 为什么会有这个文件（缺口登记，不是设计选择）
//!
//! 任务书要求「端口从生成物取，不许在代码里写 `43110` 字面量」。实测：`契约声明/常量表.json`
//! 里**有** `接口端口 = 43110`，但生成物 `契约声明/src/声明数据.rs` **一个常量表项都没出**
//! ——只出了 `声明格式号` 与 `目标字宽`。所以运行期取不到它，生成链上的缺口不在网关这一层。
//!
//! 同一个缺口有**四处实例**，都在本文件与 `错误形状.rs` 里（每一处都按任务书的要求
//! **用具名常量占位 + 写明「待生成物出 X 后改成引用」**，不静默硬写）：
//!
//! | # | 常量 | 唯一来源 | 生成物现状 |
//! |---|---|---|---|
//! | 1 | `接口端口` | `契约声明/常量表.json.接口端口` | 未生成 |
//! | 2 | `号段类宽度` | `契约声明/常量表.json.号段类宽度` | 未生成 |
//! | 3 | 类型标签语义（`文本 = 4` · `字节集 = 5` …） | `契约声明/类型声明/*.json` | 生成了数值常量，但适配器公开面**不给语义**（`参数摘要.类型标签` 只有数） |
//! | 4 | `调度错误` → 错误码 | `契约声明/错误码表/*.json` | 适配器**没有这个口**（`调度错误` 变体不带码）——见 `错误形状.rs` |
//!
//! 四处都是同一件事：**网关要的契约常量，只有「契约声明」有，而到运行期的那条路断了**。
//! 修法在生成链与适配器公开面，不在网关里再抄一份。

// ════════════════════════════════════════════════════════════════════════════
// 一 端口
// ════════════════════════════════════════════════════════════════════════════

/// 对外接口面监听的端口。
///
/// **唯一来源**是 `契约声明/常量表.json` 的「接口端口」条目 —— 经生成物与适配器
/// **再导出**到本层（本层不许跳层去拿 `契约声明`）。
///
/// 早先这里是 `pub const 接口端口: u16 = 43110;` 的**具名占位**（硬编码字面量）——
/// 验证器 ⑬「同名常量不许在别处再定义」当场报红（2026-09-26）。改成 `use` 后
/// 本文件不再有这个常量的定义处。
pub use v1_adapter::接口端口;

/// 监听地址。**只监听回环**：本面不做鉴权（`接口面形状.md` §一：判据是「第一次用不读文档
/// 就能调对」，而「要先拿 token」正好违反它）。没有鉴权就必须只对本机开放。
pub const 监听地址: &str = "127.0.0.1";

/// 端口来源 —— 根端点里必须带的那句话（`接口面形状.md` §三 冻结示例，逐字照抄）。
///
/// **实测矛盾（原样登记，不替它圆）**：这句话说端口在 `契约声明/平台声明.json`，
/// 而实测 `平台声明.json` **没有** `接口端口` 字段，它只在 `契约声明/常量表.json` 里。
/// 冻结件不许改字面，故这里逐字照抄并把这个矛盾报出来。
pub const 端口来源: &str = "契约声明/平台声明.json 的 接口端口；前端一律用同源相对路径，不写死";

// ════════════════════════════════════════════════════════════════════════════
// 二 号段类宽度（错误码 → 段位）
// ════════════════════════════════════════════════════════════════════════════

/// 号段类宽度：`码 = 段位 × 号段类宽度 + 序号`（`契约声明/src/lib.rs` 的口径）。
///
/// **唯一来源**是 `契约声明/常量表.json` 的「号段类宽度」条目 —— 经生成物与适配器
/// **再导出**到本层（同 `接口端口`）。
///
/// 为什么网关要它：错误体里的 `段位` 项。适配器的 `错误码摘要` 给了 `码 · 名称 · 说明 ·
/// 可重试 · 可自愈 · 需人工`，**唯独没给 `段位`**（而 `错误码信息` 结构里是有这一项的）。
/// 段位是 `码` 的纯函数，故这里按契约口径除一次，不另抄一张码表。
pub use v1_adapter::号段类宽度;

// ════════════════════════════════════════════════════════════════════════════
// 三 类型标签
// ════════════════════════════════════════════════════════════════════════════

/// 各数据类型的**显式类型标签**（唯一来源：`契约声明/类型声明/*.json`）。
///
/// **待生成物与适配器给出语义后改成引用**。适配器的公开面只给得出「某个参数的类型标签是
/// 几」（`参数摘要.类型标签`），给不出「哪个标签是文本、哪个是字节集」——而
/// `接口面形状.md` §三 冻结的请求形状正是「文本 ⇒ JSON 字符串；字节集 ⇒ base64 字符串。
/// 两者靠 `类型标签` 区分」。**不给语义，这条冻结形状就落不下去**，故只能在这里点名。
///
/// 这**不是**业务判断：网关不看「编号是不是 X」，只看「这个标签的 JSON 形状是什么」——
/// 是协议翻译。未登记的标签一律 400（形状未定义，猜一个就是把语义改错）。
pub mod 类型标签 {
    pub const 空: u32 = 0;
    pub const 整数: u32 = 1;
    pub const 双精度: u32 = 2;
    pub const 逻辑: u32 = 3;
    pub const 文本: u32 = 4;
    pub const 字节集: u32 = 5;
    pub const 句柄: u32 = 6;
    /// 保留标签：内核错误用它把失败写进返回槽，值是错误段位。
    pub const 错误: u32 = 4294967295;
}

