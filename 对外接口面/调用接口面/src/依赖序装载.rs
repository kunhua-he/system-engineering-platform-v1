//! 依赖序装载 —— 「按依赖序多趟试装」的**唯一实现**（启动装配与热装载同读一份）。
//!
//! 台账 C04 的两半：**启动依赖重试**与**热装载同等拓扑保证**。此前两处各写一套：
//! 装配侧（`examples/启动网关/装配.rs`）自写了一个多趟 loop，热装载侧
//! （`src/生命周期响应.rs` 的装载口）**一次定论**（缺依赖当场剔除）⇒ 同一份扩展根，
//! 启动装配能装上、热装载装不上 —— 两条路的拓扑保证不等价。本件把那段算法收成一份。
//!
//! # 口径
//!
//! - **多趟**：本趟缺依赖的候选延后一趟 —— 前一趟装上的依赖者可能正是它等的那个。
//! - **有界**：整趟零进展即停（不空转）⇒ 残留一律按缺依赖报出，**不静默丢**。
//! - **顺序无关**：装载序不随扫根的名字序飘（依赖关系说了算）。
//! - **不判依赖**：本件不读依赖清单、不碰台账、不认任何扩展名 —— 「这一份装不装得上」
//!   由调用方的试装闭包答。这是拓扑序与装载判定的分工：本件只管「谁先谁后、要不要再来一趟」。
//! - **措辞归调用方**：零进展残留的原因串由调用方给（只有它才知道本层的失败形状），
//!   本件不替它拼 `载入错误` 的 Debug 形状。

use v1_adapter::平台信息;

/// 一次试装的结局。
pub enum 试装结局 {
    /// 这一份装上了。
    装上,
    /// 同身份新版换掉了旧版（`物理回收` = 旧执行域是否真被回收）。
    切换 { 物理回收: bool },
    /// 已在（同身份同版本，幂等跳过）。
    已在,
    /// 缺依赖 —— 本趟装不上，**延后一趟**。
    缺依赖,
    /// 硬失败（形状不符 · 号段冲突 · 候选未发布…）—— 当场剔除，**不重试**。
    硬失败(String),
}

/// 多趟跑完的分类结果（四类与 [`试装结局`] 一一对应，落点用调用方给的串）。
#[derive(Default)]
pub struct 依赖序结果 {
    pub 装上: Vec<String>,
    pub 切换: Vec<(String, bool)>,
    pub 已在: Vec<String>,
    pub 剔除: Vec<(String, String)>,
}

/// 按依赖序多趟试装。
///
/// `候选表` = `(声明, 落点)` 对（落点只当读数与报因用）；`试装` = 调用方的一次试装；
/// `缺依赖说明` = 零进展残留的原因串。返回四类结果，**一条都不丢**。
pub fn 按依赖序装载(
    候选表: Vec<(&'static 平台信息, String)>,
    试装: &mut dyn FnMut(&'static 平台信息, &str) -> 试装结局,
    缺依赖说明: &str,
) -> 依赖序结果 {
    let mut 装载结果 = 依赖序结果::default();
    let mut 未装候选 = 候选表;
    loop {
        let 本趟起点 = 未装候选.len();
        let mut 暂存: Vec<(&'static 平台信息, String)> = Vec::new();
        for (声明, 落点) in 未装候选.drain(..) {
            match 试装(声明, &落点) {
                试装结局::装上 => 装载结果.装上.push(落点),
                试装结局::切换 { 物理回收 } => 装载结果.切换.push((落点, 物理回收)),
                试装结局::已在 => 装载结果.已在.push(落点),
                试装结局::缺依赖 => 暂存.push((声明, 落点)),
                试装结局::硬失败(拒收原因) => 装载结果.剔除.push((落点, 拒收原因)),
            }
        }
        if 暂存.is_empty() {
            break;
        }
        if 暂存.len() == 本趟起点 {
            // 整趟零进展：真缺依赖（依赖不在扩展根里 / 名字写错），不空转。
            for (_, 落点) in 暂存.drain(..) {
                装载结果.剔除.push((落点, 缺依赖说明.to_owned()));
            }
            break;
        }
        未装候选 = 暂存;
    }
    装载结果
}
