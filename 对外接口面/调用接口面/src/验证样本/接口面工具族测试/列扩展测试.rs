/// `GET /接口/运维/检索`（不带查询键） 的**正向样本**：声明齐、三类目录都在 ⇒ 给出三类清单。
#[test]
fn 列扩展_声明齐时给出三类清单() {
    let 根目录 = 临时仓根::构造("扩展成功");
    根目录.写文件("扩展装载/扩展根声明.json", 夹具扩展根声明);
    根目录.写文件(
        "扩展根目录/原子支持库/某支持库/包声明.json",
        "{\"名称\":\"某支持库\",\"标识串\":\"v1-某\",\"能力号段\":[{\"起\":1000,\"止\":1999}]}",
    );
    根目录.建目录("扩展根目录/组合模块库");
    根目录.建目录("扩展根目录/技能封装库");

    let 服务 = 起服务带工具根(根目录.取路径());
    let 造应答 = 发请求(&服务, &取请求("/接口/运维/检索"));
    let 应答数据 = 取成功数据(&造应答);

    let 扩展种类 = 取成员数组(&应答数据, "种类");
    assert_eq!(扩展种类.len(), 3, "支持库 · 模块 · 技能三类都得在：\n{}", 造应答.报文体);
    assert_eq!(源文本(&扩展种类[0], "种类"), "支持库");
    let 扩展 = 取成员数组(&扩展种类[0], "扩展");
    assert_eq!(扩展.len(), 1, "原子支持库下有一个扩展：\n{}", 造应答.报文体);
    assert_eq!(源文本(&扩展[0], "名称"), "某支持库");
    assert_eq!(
        取成员数组(&扩展[0], "能力号段").len(),
        1,
        "号段按声明原样交出（面不判归属）"
    );
}

