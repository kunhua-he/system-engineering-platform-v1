/// `GET /接口/运维/检索`（不带查询键） 的**就绪判定**（§32.2：发现结果只能展示与当前查询语义相符的状态；
/// 「声明合法」与「已就绪」必须可区分）。
///
/// 样本摆一个**声明在盘上、号段指向一个没人装载的号**的扩展 ⇒ 它必须报
/// `是否就绪: false` + 空 `已就绪能力号`（**声明合法但不就绪**）——
/// 这正是 §32.4「能力不存在与暂时未就绪分别可判」要的那一格。
#[test]
fn 列扩展_声明合法但不就绪时如实报假() {
    let 根目录 = 临时仓根::构造("就绪");
    根目录.写文件("扩展装载/扩展根声明.json", 夹具扩展根声明);
    // 号段 900000–900099：适配器（只有底座声明）的能力清单里**一个号都没有**。
    根目录.写文件(
        "扩展根目录/原子支持库/未装载的支持库/包声明.json",
        "{\"名称\":\"未装载的支持库\",\"标识串\":\"v1-未装载\",\"能力号段\":[{\"起\":900000,\"止\":900099}]}",
    );
    根目录.建目录("扩展根目录/组合模块库");
    根目录.建目录("扩展根目录/技能封装库");

    let 服务 = 起服务带工具根(根目录.取路径());
    let 造应答 = 发请求(&服务, &取请求("/接口/运维/检索"));
    let 应答数据 = 取成功数据(&造应答);
    let 扩展 = 取成员数组(&取成员数组(&应答数据, "种类")[0], "扩展");
    assert_eq!(扩展.len(), 1, "原子支持库下有一个扩展：\n{}", 造应答.报文体);
    let 本扩展 = &扩展[0];
    assert!(
        !取逻辑值(本扩展, "是否就绪"),
        "号段里没有一号在适配器能力清单里 ⇒ 声明合法但**不就绪**：\n{}",
        造应答.报文体
    );
    assert_eq!(
        取成员数组(本扩展, "已就绪能力号").len(),
        0,
        "一个号都没装载 ⇒ 已就绪能力号必须是空表"
    );
    assert_eq!(
        源文本(本扩展, "就绪判据"),
        "号段内无一号可寻址",
        "就绪判据必须说清是据哪一条判的（不是编一个 false）"
    );
}

