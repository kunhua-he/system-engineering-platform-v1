/// `9013 程序文本越界`：绝对路径不在允许根（工具根）内 ⇒ 拒。
///
/// 反向样本要的是**修前必红、修后必绿**：修前这条会真读到工具根外的那份件（或报 9009），
/// 修后一律 9013。两条路径都试：根外的绝对路径、爬到根之上的相对路径。
#[test]
fn 反向_9013_程序文本越界() {
    let 根目录 = 临时仓根::构造("9013");
    // 在工具根之外另造一个目录，把它的绝对路径拿去请求。
    let 根外目录 = std::env::temp_dir().join(format!("v1-接口面工具族-根外-{}", std::process::id()));
    std::fs::create_dir_all(&根外目录).expect("建根外目录");
    let 根外件 = 根外目录.join("根外件.程序文本");
    std::fs::write(&根外件, ".版本 2\n").expect("写根外件");
    let 服务 = 起服务带工具根(根目录.取路径());
    for 越界路径 in [
        根外件.to_string_lossy().to_string(),
        "../爬到根之上.程序文本".to_owned(),
    ] {
        let 请求体 = format!("{{\"动作\":\"读\",\"路径\":{}}}", 转义JSON串(&越界路径));
        let 造应答 = 发请求(&服务, &交POST请求("/接口/运维/程序文本", &请求体));
        断言失败码(&造应答, 9013);
        let 回执数据 = 造应答.取成员("数据");
        assert!(
            源文本(&回执数据, "为什么").contains("越界"),
            "9013 的回执必须说清是越界：\n{}",
            造应答.报文体
        );
        assert!(
            源文本(&回执数据, "缺什么").contains("工具根"),
            "9013 的回执必须说清缺的是「落在工具根之内的路径」：\n{}",
            造应答.报文体
        );
    }
    let _ = std::fs::remove_dir_all(&根外目录);
}

/// `9014 程序文本只读`：写动作没显式升档 ⇒ 默认最紧（只读）不许写。
///
/// 这条钉的是「**默认最紧**」：不给 `权限` 就是不许写，不是一个「默认允许」。
#[test]
fn 反向_9014_程序文本只读() {
    let 根目录 = 临时仓根::构造("9014");
    let 服务 = 起服务带工具根(根目录.取路径());
    for 请求体 in [
        "{\"动作\":\"写\",\"路径\":\"新件.程序文本\",\"正文\":\"x\"}",
        "{\"动作\":\"写\",\"路径\":\"新件.程序文本\",\"正文\":\"x\",\"权限\":\"只读\"}",
    ] {
        let 造应答 = 发请求(&服务, &交POST请求("/接口/运维/程序文本", 请求体));
        断言失败码(&造应答, 9014);
        let 回执数据 = 造应答.取成员("数据");
        assert_eq!(源文本(&回执数据, "权限"), "只读");
        assert!(
            源文本(&回执数据, "为什么").contains("读写"),
            "9014 的回执必须指路（要写就给 读写）：\n{}",
            造应答.报文体
        );
    }
    // 真不许写：这一条过后盘上不该出现那个件。
    assert!(
        !根目录.取路径().join("新件.程序文本").exists(),
        "9014 必须真的不写盘"
    );
}

/// 正反成对：写一份 `.程序文本` 再读回来（裁决：真读 / 真写调用方自带路径）。
///
/// 写那一步**显式给 `读写`**：默认最紧那一档不许写（`9014`）。读回来那一步不必给权限。
#[test]
fn 程序文本_写了再读回来() {
    let 根目录 = 临时仓根::构造("往返");
    let 服务 = 起服务带工具根(根目录.取路径());

    let 写应答 = 发请求(
        &服务,
        &交POST请求(
            "/接口/运维/程序文本",
            "{\"动作\":\"写\",\"路径\":\"示例.程序文本\",\"正文\":\".版本 2\\n\",\"权限\":\"读写\"}",
        ),
    );
    let 应答数据 = 取成功数据(&写应答);
    assert_eq!(源文本(&应答数据, "动作"), "写");
    assert_eq!(源文本(&应答数据, "路径"), "示例.程序文本");

    let 读应答 = 发请求(
        &服务,
        &交POST请求("/接口/运维/程序文本", "{\"动作\":\"读\",\"路径\":\"示例.程序文本\"}"),
    );
    let 应答数据 = 取成功数据(&读应答);
    assert_eq!(源文本(&应答数据, "动作"), "读");
    assert_eq!(源文本(&应答数据, "文本"), ".版本 2\n");
}

/// 把一段文本包成 JSON 字符串（越界样本要把盘上路径拼进请求体）。
///
/// 只处理本文件用到的两个转义（反斜杠与引号）：请求体是本件手写拼的，不是通用序列化器。
fn 转义JSON串(原文: &str) -> String {
    let 转义后 = 原文.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{转义后}\"")
}
