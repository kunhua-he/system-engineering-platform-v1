//! 程序文本端点测试 —— §七 旁路 `POST /接口/运维/程序文本` 的**真读 / 真写**与**逐种失败码**。
//!
//! 落点已裁（`项目文档/决策记录/2026-09-28_华哥的尺子与七条裁决.md` §二 206 行）：
//! 「项目/程序文本那一层」= **调用方自带路径**。本件对着裁决 §三 第一原则「错误必须立刻可见」
//! ——七条失败各一个明确码（`9008`–`9014`），外加一条往返正向。
//!
//! **安全前提那两条（口径：`项目文档/决策记录/2026-09-28_安全边界.md` §一）**：`9013 程序文本越界`（路径落在工具根之外）
//! 与 `9014 程序文本只读`（写动作未显式升档）。两条都是**反向样本**：修前必红、修后必绿。
//! 同时给一条正向（`程序文本_写了再读回来`）防「矫枉过正」——把端点整个禁掉也能让反向全绿。
//!
//! 拆件理由：这七条加进 `接口面工具族测试.rs` 会让它超 400 行硬数（`开发规范.md` §六）
//! ⇒ 按测试主题拆出本件；夹具与断言小件仍在父件（子件 `use super::…`）。
//! 判据口径与父件同：**每条反向样本都断言「码本身」**（不是只断言「失败了」）。

use crate::测试夹具::{发请求, 交POST请求, 起服务, 起服务带工具根, 源文本};
use super::{临时仓根, 取成功数据, 断言失败码};

/// `9008 程序文本路径为空`：缺 `路径` 或给空串 ⇒ 业务失败（不是 400）。
#[test]
fn 反向_9008_程序文本路径为空() {
    let 服务 = 起服务();
    for 请求体 in ["{\"动作\":\"读\"}", "{\"动作\":\"读\",\"路径\":\"\"}"] {
        let 造应答 = 发请求(&服务, &交POST请求("/接口/运维/程序文本", 请求体));
        断言失败码(&造应答, 9008);
        assert!(
            源文本(&造应答.取成员("数据"), "缺什么").contains("路径"),
            "9008 的回执必须说清缺的是路径：\n{}",
            造应答.报文体
        );
    }
}

