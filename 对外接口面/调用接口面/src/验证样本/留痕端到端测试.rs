//! 留痕端到端 —— 真发一次调用，再取回**非空**留痕，逐项核它对不对。
//!
//! # 缺的是什么（反馈 432 · 来源 111）
//!
//! `GET /接口/留痕` 的 HTTP 路已在（`网关.rs` 装配侧按契约常量开留痕 · `端点路由.rs` 认它），
//! 但判据只到「装配侧已开 + 空表」（`生命周期测试.rs::留痕_装配侧已开且如实报启用`）——
//! **内容对不对没有判据**：不写留痕、字段写错、号位写串，那条空表例照样绿。
//! 本件把内容钉死：真调用 → 取留痕 → 九键与**这一次调用**逐项对得上。
//!
//! # 九键 = 对外形状（`留痕响应.rs` 文件头那段 JSON）
//!
//! `实例` · `调用类` · `能力号` · `资源号` · `操作号` · `入参指纹` · `结果码` ·
//! `耗时微秒` · `追踪号`。本件核**键集恰好这九个**（多一个少一个都是改了对外形状 ——
//! 要回来改这里并在 `契约声明/冻结登记.json` 登记），并逐项核值关系。
//!
//! 数据层的第四个旁路字段 `查询结论`（三值闭合：`记录不存在` / `已有失败` / `全部成功`）
//! 也在本件核 —— 它不是**条目**的键，是 `数据` 的键（条目仍是九键，一字未动）。
//!
//! # 三条真实口径（不许假设）
//!
//! 1. **不假设哪条能力一定成功**：期望结果码从**这一次真应答**读（成功 ⇒ `0`，失败 ⇒ `错误.码`）。
//! 2. **不假设追踪号从几起**：本件起服务后先发调用，按「实例级单调递增」核
//!    （`留痕口.rs` 的 `追踪号` 是实例字段，不是进程级全局）。
//! 3. **入参指纹是入参的函数**：**同参两次真调用的指纹必须相等**（`核同参指纹` 拿两条真读数互比，
//!    不是从期望里抄）· 不同入参（位数不同）不同 · 两者都非零 —— 三条一起才证它不是常量、
//!    不是零、不是「永远一样」。
//!
//! # 正反样本
//!
//! 主例是正样本（真链路）；`留痕_核验判据抓得住缺痕与字段写错` 是**承重证明**：
//! 把真读数按「去写留痕 / 清空 / 字段写错 / 号位串味」逐个改坏，同一条核验判据必须当场判不合格。

use crate::协议值::协议值;
use crate::测试夹具::{
    发请求, 取请求, 交POST请求, 取逻辑值, 无符号值, 取成员数组, 第一个能力号, 起服务,
};

/// 一个空位槽的 JSON 文本（`接口面形状.md` §三：空位也必须写出来，不许省略位次）。
const 空槽文本: &str = r#"{"类型标签":0,"值":0}"#;

/// 九键的键集 —— 对外形状（`留痕响应.rs` 文件头那段 JSON）。
const 留痕九键: [&str; 9] = [
    "实例", "调用类", "能力号", "资源号", "操作号", "入参指纹", "结果码", "耗时微秒", "追踪号",
];

/// 造一条 `POST /接口/调用` 的请求体：编号 + 按契约行序的槽文本表。
fn 造调用体(编号: u32, 槽表文本: &[&str]) -> String {
    format!("{{\"编号\":{编号},\"值\":[{}]}}", 槽表文本.join(","))
}

/// 取 `GET /接口/留痕` 的 `数据` 对象（不是成功就挂，带原文）。
fn 取留痕数据(服务: &crate::网关::服务) -> 协议值 {
    let 造应答 = 发请求(服务, &取请求("/接口/留痕"));
    assert_eq!(造应答.状态, 200, "取留痕是只读端点：\n{}", 造应答.报文体);
    assert!(造应答.取逻辑值("成功"), "取留痕必须成功：\n{}", 造应答.报文体);
    造应答.取成员("数据")
}

/// 这一次调用的期望结果码：成功 ⇒ `0`；失败 ⇒ 真应答里的 `错误.码`。
///
/// **不写死**：`留痕口.rs::结果码` 与 `响应.rs` 读的是同一次调用的同一份转发结果，
/// 故两者必须一致 —— 「留痕的结果码与调用应答一致」本身就是一条判据。
fn 期望结果码(造应答: &crate::测试夹具::收到应答) -> i64 {
    if 造应答.取逻辑值("成功") {
        return 0;
    }
    let 错误 = 造应答.取成员("错误");
    i64::try_from(无符号值(&错误, "码")).expect("4 位错误码装得进 i64")
}

/// 整段请求的墙钟上界（微秒）—— 留痕的 `耗时微秒` 是它的子集，故不许超过它。
fn 取耗时上界(区间起点: std::time::Instant) -> u64 {
    u64::try_from(区间起点.elapsed().as_micros()).unwrap_or(u64::MAX)
}

/// 一条留痕的**期望读数** —— 与一次真实调用逐项对应。
#[derive(Clone, Copy)]
struct 期望留痕 {
    实例号: u64,
    能力号: u64,
    入参指纹: u64,
    结果码: i64,
    追踪号: u64,
    /// 耗时微秒的上界：这一次调用的耗时是整段请求墙钟的子集。
    耗时上界微秒: u64,
}

/// 核一条留痕条目：**九键键集恰好**，且九项值与期望逐项对得上。
///
/// 返回 `Err(不合格原因)` 而不是当场 panic：反向样本要靠它给出「为什么这条被判不合格」；
/// 正样本再用 `unwrap_or_else` 把理由打进 panic 文案。
fn 核留痕条目(留痕条目: &协议值, 期望: &期望留痕) -> Result<(), String> {
    let 协议值::对象值(对象成员) = 留痕条目 else {
        return Err(format!("留痕条目必须是对象，实际 {留痕条目:?}"));
    };
    let 键集: Vec<&str> = 对象成员.iter().map(|(键名, _)| 键名.as_str()).collect();
    let 缺键: Vec<&str> = 留痕九键.iter().copied().filter(|键名| !键集.contains(键名)).collect();
    let 多键: Vec<&str> = 键集.iter().copied().filter(|键名| !留痕九键.contains(键名)).collect();
    if !缺键.is_empty() || !多键.is_empty() {
        return Err(format!("九键键集不对：缺 {缺键:?} · 多 {多键:?}"));
    }
    let 取数 = |键名: &str| 留痕条目.取成员(键名).and_then(协议值::取无符号);
    let 实例号 = 取数("实例").ok_or("实例 不是非负整数")?;
    if 实例号 == 0 {
        return Err("实例 = 0：留痕的「谁」必须绑在真实适配器实例上".to_owned());
    }
    if 实例号 != 期望.实例号 {
        return Err(format!("实例 {实例号} != 期望 {}", 期望.实例号));
    }
    let 调用类 = 留痕条目.取成员("调用类").and_then(协议值::取文本).unwrap_or("");
    if 调用类 != "能力" {
        return Err(format!("调用类「{调用类}」!=「能力」（留痕口只写能力调用）"));
    }
    let 能力号 = 取数("能力号").ok_or("能力号 不是非负整数")?;
    if 能力号 != 期望.能力号 {
        return Err(format!("能力号 {能力号} != 期望 {}", 期望.能力号));
    }
    for 恒零键 in ["资源号", "操作号"] {
        let 号值 = 取数(恒零键).ok_or_else(|| format!("{恒零键} 不是非负整数"))?;
        if 号值 != 0 {
            return Err(format!("{恒零键} = {号值}：能力调用时它恒 0（号位互斥）"));
        }
    }
    let 入参指纹 = 取数("入参指纹").ok_or("入参指纹 不是非负整数")?;
    if 入参指纹 != 期望.入参指纹 {
        return Err(format!("入参指纹 {入参指纹} != 期望 {}", 期望.入参指纹));
    }
    let 结果码 = 留痕条目.取成员("结果码").and_then(协议值::取有符号).ok_or("结果码 不是整数")?;
    if 结果码 != 期望.结果码 {
        return Err(format!("结果码 {结果码} != 期望 {}", 期望.结果码));
    }
    let 耗时微秒 = 取数("耗时微秒").ok_or("耗时微秒 不是非负整数")?;
    if 耗时微秒 > 期望.耗时上界微秒 {
        return Err(format!("耗时微秒 {耗时微秒} > 整段请求墙钟 {}", 期望.耗时上界微秒));
    }
    let 追踪号 = 取数("追踪号").ok_or("追踪号 不是非负整数")?;
    if 追踪号 != 期望.追踪号 {
        return Err(format!("追踪号 {追踪号} != 期望 {}", 期望.追踪号));
    }
    Ok(())
}

/// 核整个 `数据`：已启用 · 条数 · 已丢弃 · 留痕数组长度与逐条内容 · 查询结论。
fn 核留痕数据(留痕读数: &协议值, 期望表: &[期望留痕]) -> Result<(), String> {
    if !取逻辑值(留痕读数, "已启用") {
        return Err("已启用 = false：装配侧没按契约常量开留痕（去写留痕的一种形态）".to_owned());
    }
    let 留痕条数 = 无符号值(留痕读数, "条数");
    if 留痕条数 != 期望表.len() as u64 {
        return Err(format!("条数 {留痕条数} != 期望 {}", 期望表.len()));
    }
    let 已丢弃条数 = 无符号值(留痕读数, "已丢弃");
    if 已丢弃条数 != 0 {
        return Err(format!("已丢弃 {已丢弃条数} != 0（容量内不许丢）"));
    }
    // 旁路字段 `查询结论`：**从期望表重算**（真源 = 每条的结果码），不抄真读数。
    let 查询结论文本 = 留痕读数.取成员("查询结论").and_then(协议值::取文本).unwrap_or("");
    let 期望查询结论 = 重算查询结论(期望表);
    if 查询结论文本 != 期望查询结论 {
        return Err(format!(
            "查询结论「{查询结论文本}」!= 该报的「{期望查询结论}」（按这批记录的结果码重算）"
        ));
    }
    let 留痕表 = 取成员数组(留痕读数, "留痕");
    if 留痕表.len() != 期望表.len() {
        return Err(format!("留痕数组长度 {} != 期望 {}", 留痕表.len(), 期望表.len()));
    }
    for (位次, (留痕条目, 期望)) in 留痕表.iter().zip(期望表).enumerate() {
        if let Err(不合格原因) = 核留痕条目(留痕条目, 期望) {
            return Err(format!("第 {位次} 条：{不合格原因}"));
        }
    }
    Ok(())
}

/// 留痕表**前两条**（同参两次调用）的入参指纹必须相等 —— 非确定性指纹在这里当场红。
///
/// 为什么单开这一条：`核留痕条目` 的期望指纹是**从观测值抄来的** ⇒ 它只证「读数与期望对得上」，
/// 证不了「指纹由入参决定」。同参两次必须给出同一个指纹，那条关系只能拿两条**真读数**互比。
fn 核同参指纹(留痕表: &[协议值]) -> Result<(), String> {
    let 取指纹 = |位次: usize| {
        留痕表
            .get(位次)
            .and_then(|留痕条目| 留痕条目.取成员("入参指纹"))
            .and_then(协议值::取无符号)
            .ok_or_else(|| format!("第 {位次} 条没有 入参指纹"))
    };
    let 首指纹 = 取指纹(0)?;
    let 次指纹 = 取指纹(1)?;
    if 首指纹 == 0 || 次指纹 == 0 {
        return Err(format!("同参指纹出现 0：{首指纹} / {次指纹}"));
    }
    if 首指纹 != 次指纹 {
        return Err(format!("同参两次调用的指纹不同：{首指纹} vs {次指纹}（指纹非确定性）"));
    }
    Ok(())
}

/// 这一批记录该报什么 `查询结论` —— **真源是每条的结果码**（与写侧 `留痕响应.rs::取查询结论`
/// 同一条口径，这里独立重算，不从线上读数抄）。
///
/// 三值互斥且穷尽：空表 ⇒ `记录不存在` · 有一条非零 ⇒ `已有失败` · 其余 ⇒ `全部成功`。
fn 重算查询结论(期望表: &[期望留痕]) -> &'static str {
    if 期望表.is_empty() {
        return "记录不存在";
    }
    if 期望表.iter().any(|期望| 期望.结果码 != 0) {
        "已有失败"
    } else {
        "全部成功"
    }
}

/// 把一条留痕对象里的某个键换成新值（**只给反向样本用**，键序保持）。
fn 换留痕字段(留痕条目: &协议值, 键名: &str, 新字段值: 协议值) -> 协议值 {
    let 协议值::对象值(对象成员) = 留痕条目 else {
        panic!("留痕条目必须是对象，实际 {留痕条目:?}");
    };
    协议值::对象值(
        对象成员
            .iter()
            .map(|(成员键, 成员值)| {
                (成员键.clone(), if 成员键.as_str() == 键名 { 新字段值.clone() } else { 成员值.clone() })
            })
            .collect(),
    )
}

/// 抽掉一条留痕对象里的某个键（**只给反向样本用**）。
fn 抽留痕字段(留痕条目: &协议值, 键名: &str) -> 协议值 {
    let 协议值::对象值(对象成员) = 留痕条目 else {
        panic!("留痕条目必须是对象，实际 {留痕条目:?}");
    };
    协议值::对象值(对象成员.iter().filter(|(成员键, _)| 成员键.as_str() != 键名).cloned().collect())
}

/// 在一条留痕对象尾部追加一个键（**只给反向样本用**：多一个键 = 改了对外形状）。
fn 追加留痕字段(留痕条目: &协议值, 键名: &str, 新字段值: 协议值) -> 协议值 {
    let 协议值::对象值(对象成员) = 留痕条目 else {
        panic!("留痕条目必须是对象，实际 {留痕条目:?}");
    };
    let mut 新对象成员 = 对象成员.clone();
    新对象成员.push((键名.to_owned(), 新字段值));
    协议值::对象值(新对象成员)
}

/// **正样本（真链路）**：真发三次 `POST /接口/调用`（**同参两次** + 换号一次），
/// 再 `GET /接口/留痕` —— 条数 · 追踪号序列 · 九键值与这三次调用逐项对得上，
/// 且**同参两次的入参指纹必须相等**（生产观测，不是从期望里抄的）。
#[test]
fn 留痕_真调用后取回非空记录且九键与调用对得上() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 实例号 = std::sync::Arc::as_ptr(&服务.适配器()) as u64;
    assert_ne!(实例号, 0, "适配器实例地址非零（留痕的「谁」靠它）");

    // 按契约行序填满（空位写空槽）。成功与否按**真应答**判，不假设。
    let 参数个数 = 服务.适配器().能力契约(编号).expect("契约").参数表.len();
    let 空槽表 = vec![空槽文本; 参数个数];
    let 起点 = std::time::Instant::now();
    // **同参两次**（同一入参发两遍）—— 指纹稳定性只能拿这两条真读数互比。
    let 应答同参前 = 发请求(&服务, &交POST请求("/接口/调用", &造调用体(编号, &空槽表)));
    let 应答同参后 = 发请求(&服务, &交POST请求("/接口/调用", &造调用体(编号, &空槽表)));
    // 换一个**没人认领**的号 + 空入参 ⇒ 未载入，入参指纹也随之变。
    let 应答异参 = 发请求(&服务, &交POST请求("/接口/调用", &造调用体(999999, &[])));
    assert_eq!(应答同参前.状态, 200, "业务结局在数据里，不在状态码：\n{}", 应答同参前.报文体);
    assert_eq!(应答同参后.状态, 200, "业务结局在数据里，不在状态码：\n{}", 应答同参后.报文体);
    assert_eq!(应答异参.状态, 200, "未命中不是协议失败：\n{}", 应答异参.报文体);
    assert_eq!(
        期望结果码(&应答同参前),
        期望结果码(&应答同参后),
        "同参两次的真结局必须一致（否则这条同参对照本身不可靠）"
    );
    let 耗时上界 = 取耗时上界(起点);

    let 留痕读数 = 取留痕数据(&服务);
    let 留痕表 = 取成员数组(&留痕读数, "留痕");
    assert_eq!(留痕表.len(), 3, "真调用三次 ⇒ 恰好三条（要补的正是「非空 + 同参稳定」这两条）");
    // **生产观测**：同参两次的入参指纹必须相等（非确定性指纹在这里当场红）。
    核同参指纹(&留痕表).unwrap_or_else(|不合格原因| panic!("{不合格原因}"));
    let 指纹同参 = 无符号值(&留痕表[0], "入参指纹");
    let 指纹异参 = 无符号值(&留痕表[2], "入参指纹");
    assert_ne!(指纹同参, 0, "入参指纹 = 0 ⇒ 不是按入参算出来的");
    assert_ne!(指纹异参, 0, "空入参也有指纹（FNV-1a 偏移基数），不是 0");
    assert_ne!(指纹同参, 指纹异参, "入参位数不同（参数个数 vs 0）⇒ 指纹必须不同");

    let 期望表 = [
        期望留痕 { 实例号, 能力号: u64::from(编号), 入参指纹: 指纹同参, 结果码: 期望结果码(&应答同参前), 追踪号: 0, 耗时上界微秒: 耗时上界 },
        期望留痕 { 实例号, 能力号: u64::from(编号), 入参指纹: 指纹同参, 结果码: 期望结果码(&应答同参后), 追踪号: 1, 耗时上界微秒: 耗时上界 },
        期望留痕 { 实例号, 能力号: 999999, 入参指纹: 指纹异参, 结果码: 期望结果码(&应答异参), 追踪号: 2, 耗时上界微秒: 耗时上界 },
    ];
    assert_ne!(期望表[0].结果码, 期望表[2].结果码, "同参与异参的结果码不同 ⇒ 这条对照有分辨力");
    核留痕数据(&留痕读数, &期望表)
        .unwrap_or_else(|不合格原因| panic!("留痕内容与这三次调用对不上：{不合格原因}\n{留痕读数:?}"));
}

/// **多实例**：两个服务的留痕账**互不串味** —— 各自的条数只算它那份、`实例` 各是它那份的、
/// `追踪号` 各自从 0 起（不是进程级全局）。
///
/// 对着的判据：README §三「多实例安全：状态显式持有，不落进程级全局」。
#[test]
fn 留痕_两个实例各自记账互不串味() {
    let 被测服务 = 起服务();
    let 对照服务 = 起服务();
    let 被测编号 = 第一个能力号(&被测服务);
    let 被测实例号 = std::sync::Arc::as_ptr(&被测服务.适配器()) as u64;
    let 对照实例号 = std::sync::Arc::as_ptr(&对照服务.适配器()) as u64;
    assert_ne!(被测实例号, 对照实例号, "两份服务是两份适配器");

    let 被测空槽表 = vec![空槽文本; 被测服务.适配器().能力契约(被测编号).expect("契约").参数表.len()];
    let 起点 = std::time::Instant::now();
    发请求(&被测服务, &交POST请求("/接口/调用", &造调用体(被测编号, &被测空槽表)));
    发请求(&被测服务, &交POST请求("/接口/调用", &造调用体(被测编号, &被测空槽表)));
    // 对照服务只调一次：若两边共用一条缓冲，它的条数会是 3（被测那两条也在）。
    发请求(&对照服务, &交POST请求("/接口/调用", &造调用体(第一个能力号(&对照服务), &[])));
    let 耗时上界 = 取耗时上界(起点);

    let 被测读数 = 取留痕数据(&被测服务);
    assert_eq!(无符号值(&被测读数, "条数"), 2, "被测服务只记它那两次");
    let 被测留痕表 = 取成员数组(&被测读数, "留痕");
    for (位次, 留痕条目) in 被测留痕表.iter().enumerate() {
        assert_eq!(无符号值(留痕条目, "实例"), 被测实例号, "被测的每条都绑被测实例");
        assert_eq!(无符号值(留痕条目, "追踪号"), 位次 as u64, "本实例的追踪号从 0 起、逐条递增");
        assert!(无符号值(留痕条目, "耗时微秒") <= 耗时上界, "耗时是整段请求墙钟的子集");
    }

    // 这两条是**同一入参**发的两遍 ⇒ 指纹必须相等（同参稳定，生产观测）。
    核同参指纹(&被测留痕表).unwrap_or_else(|不合格原因| panic!("被测服务：{不合格原因}"));

    let 对照读数 = 取留痕数据(&对照服务);
    assert_eq!(无符号值(&对照读数, "条数"), 1, "对照服务只记它那一次（不是共用一条缓冲）");
    let 对照留痕表 = 取成员数组(&对照读数, "留痕");
    assert_eq!(无符号值(&对照留痕表[0], "实例"), 对照实例号, "对照的实例与被测不同");
    assert_eq!(无符号值(&对照留痕表[0], "追踪号"), 0, "追踪号按实例从 0 起，不是进程级全局");
}

/// **三值闭合**：`查询结论` 在真链路上逐个值都出得来，且每次都等于按**真读数**的结果码重算的值。
///
/// 为什么单开一条：`核留痕数据` 的期望结论是**从期望表算的**，它证不了「三个值都真出得来」。
/// 这里只拿**必然性**建样本，不靠「这次恰好成功」：`记录不存在` 用从未调用过的服务；
/// `已有失败` 用没人认领的号真调一次（结果码必然非零）；`全部成功` 那一档按真读数选档。
#[test]
fn 留痕_查询结论三值闭合且与真记录一致() {
    // ① 记录不存在：从未发生过调用的服务（真链路隔离夹具，不碰生产路径）。
    let 空服务 = 起服务();
    let 空读数 = 取留痕数据(&空服务);
    assert_eq!(无符号值(&空读数, "条数"), 0);
    assert_eq!(
        空读数.取成员("查询结论").and_then(协议值::取文本),
        Some("记录不存在"),
        "一条记录都没有 ⇒ 查询结论必须是「记录不存在」"
    );

    // ② 已有失败：拿一个没人认领的号真调一次 ⇒ 结果码 = 1（提供者未载入），必然非零。
    let 失败服务 = 起服务();
    let 失败应答 = 发请求(&失败服务, &交POST请求("/接口/调用", &造调用体(999999, &[])));
    assert!(!失败应答.取逻辑值("成功"), "没人认领的号 ⇒ 必然失败（本档靠这条必然性）");
    let 失败读数 = 取留痕数据(&失败服务);
    let 失败表 = 取成员数组(&失败读数, "留痕");
    assert_eq!(失败表.len(), 1, "只调了一次");
    let 失败码 = 失败表[0].取成员("结果码").and_then(协议值::取有符号).expect("结果码");
    assert_ne!(失败码, 0, "真读数的结果码非零 ⇒ 这一档才是「已有失败」");
    assert_eq!(
        失败读数.取成员("查询结论").and_then(协议值::取文本),
        Some("已有失败"),
        "记录里有非零结果码 ⇒ 查询结论必须是「已有失败」"
    );

    // ③ 全成功那一档：只发一条调用，按**真读数**的结果码选该报哪个值。
    let 单条服务 = 起服务();
    let 编号 = 第一个能力号(&单条服务);
    let 空槽表 = vec![空槽文本; 单条服务.适配器().能力契约(编号).expect("契约").参数表.len()];
    let 单条应答 = 发请求(&单条服务, &交POST请求("/接口/调用", &造调用体(编号, &空槽表)));
    let 单条读数 = 取留痕数据(&单条服务);
    let 单条表 = 取成员数组(&单条读数, "留痕");
    assert_eq!(单条表.len(), 1);
    let 单条码 = 单条表[0].取成员("结果码").and_then(协议值::取有符号).expect("结果码");
    let 该报 = if 单条码 == 0 { "全部成功" } else { "已有失败" };
    assert_eq!(
        单条读数.取成员("查询结论").and_then(协议值::取文本),
        Some(该报),
        "查询结论必须与真读数的结果码（{单条码}）一致"
    );
    assert_eq!(
        单条应答.取逻辑值("成功"),
        单条码 == 0,
        "留痕的结果码与调用应答的成功位必须一致"
    );
}

/// **承重证明（反向样本）**：把**真读数**按「去写留痕 / 清空 / 字段写错 / 号位串味 / 缺键 /
/// 多键 / 同参不同指纹」逐个改坏，**同一条核验判据**必须当场判不合格 —— 否则主例的绿是假绿。
///
/// 只在内存里改这份真读数的副本；「无痕」那一档另起一个**隔离服务**当夹具：
/// 不碰生产路径、不删任何东西、不改任何生产件。
#[test]
fn 留痕_核验判据抓得住缺痕与字段写错() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 实例号 = std::sync::Arc::as_ptr(&服务.适配器()) as u64;
    let 空槽表 = vec![空槽文本; 服务.适配器().能力契约(编号).expect("契约").参数表.len()];
    let 起点 = std::time::Instant::now();
    let 应答 = 发请求(&服务, &交POST请求("/接口/调用", &造调用体(编号, &空槽表)));
    let 耗时上界 = 取耗时上界(起点);

    let 留痕读数 = 取留痕数据(&服务);
    let 真留痕条目 = 取成员数组(&留痕读数, "留痕").into_iter().next().expect("真调用过 ⇒ 至少一条");
    let 期望 = 期望留痕 {
        实例号,
        能力号: u64::from(编号),
        入参指纹: 无符号值(&真留痕条目, "入参指纹"),
        结果码: 期望结果码(&应答),
        追踪号: 0,
        耗时上界微秒: 耗时上界,
    };

    // 正样本：真读数 + 真期望 ⇒ 必须合格（否则下面的反向样本无从谈起）。
    核留痕条目(&真留痕条目, &期望)
        .unwrap_or_else(|不合格原因| panic!("真读数被判不合格：{不合格原因}\n{真留痕条目:?}"));

    // 反向样本表：每一行一个**改坏方式**，同一条判据必须抓到。
    let 改坏表 = [
        ("实例清零", 换留痕字段(&真留痕条目, "实例", 协议值::无符号值(0))),
        ("调用类写成资源", 换留痕字段(&真留痕条目, "调用类", 协议值::文本值("资源".to_owned()))),
        ("能力号改错", 换留痕字段(&真留痕条目, "能力号", 协议值::无符号值(期望.能力号 ^ 1))),
        ("资源号串味", 换留痕字段(&真留痕条目, "资源号", 协议值::无符号值(9))),
        ("操作号串味", 换留痕字段(&真留痕条目, "操作号", 协议值::无符号值(1))),
        ("入参指纹改错", 换留痕字段(&真留痕条目, "入参指纹", 协议值::无符号值(期望.入参指纹 ^ 1))),
        ("结果码写错", 换留痕字段(&真留痕条目, "结果码", 协议值::整数项(期望.结果码 ^ 1))),
        ("耗时微秒超墙钟", 换留痕字段(&真留痕条目, "耗时微秒", 协议值::无符号值(耗时上界 + 1))),
        ("追踪号错位", 换留痕字段(&真留痕条目, "追踪号", 协议值::无符号值(期望.追踪号 + 1))),
        ("缺 追踪号 键", 抽留痕字段(&真留痕条目, "追踪号")),
        ("多一个旁路键", 追加留痕字段(&真留痕条目, "旁路字段", 协议值::无符号值(1))),
    ];
    for (改坏方式, 改坏件) in &改坏表 {
        assert!(
            核留痕条目(改坏件, &期望).is_err(),
            "「{改坏方式}」必须被核验判据抓到（否则主例是假绿）：\n{改坏件:?}"
        );
    }

    // 「查询结论」写错 / 缺键 必须被抓到 —— 这一档是**数据层**的键（不在条目九键里）。
    let 真结论 = 重算查询结论(&[期望]);
    let 错结论 = if 真结论 == "全部成功" { "已有失败" } else { "全部成功" };
    let 结论写错 = 换留痕字段(&留痕读数, "查询结论", 协议值::文本值(错结论.to_owned()));
    assert!(
        核留痕数据(&结论写错, &[期望]).is_err(),
        "查询结论写错（真值「{真结论}」写成「{错结论}」）必须被判不合格"
    );
    let 结论缺键 = 抽留痕字段(&留痕读数, "查询结论");
    assert!(
        核留痕数据(&结论缺键, &[期望]).is_err(),
        "缺 查询结论 键（读不出结论）必须被判不合格"
    );

    // 「去写留痕」的三种形态：整条没了（空表）· 开关没开（已启用 false）·
    // **真链路隔离夹具**（另起一个从未发生过调用的服务 ⇒ 留痕天然是空的）。
    let 空表读数 = 换留痕字段(&换留痕字段(&留痕读数, "条数", 协议值::无符号值(0)), "留痕", 协议值::数组值(vec![]));
    assert!(核留痕数据(&空表读数, &[期望]).is_err(), "去写留痕（空表）必须被抓到");
    let 未开读数 = 换留痕字段(&留痕读数, "已启用", 协议值::假值);
    assert!(核留痕数据(&未开读数, &[期望]).is_err(), "没开留痕必须被抓到");
    // 隔离夹具：第二个服务一次调用都没发 ⇒ 它那份留痕读数是「无痕」的真形状；
    // 拿它去过同一条核验判据必须不合格 —— 这就是「不写留痕被本件捕获」的真读数。
    let 未调用服务 = 起服务();
    let 未调用读数 = 取留痕数据(&未调用服务);
    assert!(
        核留痕数据(&未调用读数, &[期望]).is_err(),
        "从未发生过调用（去写留痕）必须被判不合格"
    );

    // 「同参却给出不同指纹」（指纹非确定性）必须被捕获 —— **内存变体**：
    // 同一份真读数复制两份 ⇒ 合格；把第二份的指纹改掉 ⇒ 必须判不合格。
    // ★ 本档**不声称生产突变已测**：只在内存里改这份读数的副本。
    let 同参表 = [真留痕条目.clone(), 真留痕条目.clone()];
    核同参指纹(&同参表).expect("同一份真读数复制两份必须判合格");
    let 指纹改坏 = 无符号值(&真留痕条目, "入参指纹") ^ 1;
    let 错指纹表 = [
        真留痕条目.clone(),
        换留痕字段(&真留痕条目, "入参指纹", 协议值::无符号值(指纹改坏)),
    ];
    assert!(
        核同参指纹(&错指纹表).is_err(),
        "同参却不同指纹（非确定性）必须被捕获，否则「同参稳定」那条断言是假绿"
    );
}
