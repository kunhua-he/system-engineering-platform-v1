//! 槽编码 —— **协议形状 ↔ 定长数据槽**。这是网关做的全部工作：翻译形状，不判断业务。
//!
//! `接口面形状.md` §三 冻结的两句话就是本文件的两半：
//!
//! - 入：`值` 是**带类型标签的定长槽**；`文本 ⇒ 值 是 JSON 字符串（UTF-8，长度由 JSON 自带）`；
//!   `字节集 ⇒ 值 是 base64 字符串`。**两者靠 类型标签 区分，不靠形状猜。**
//! - 出：每个返回值项自带 `类型标签`，调用方不需要二次解析。
//!
//! # 指针只在这里出现，只有一处 `unsafe`
//!
//! 文本与字节集在槽里是**指针 + 长度**（契约：一切串都带长度）。JSON 里是字符串。
//! 两头之间的那一跳只能在网关做，且必须**当场**做：`槽源` 持有源数据，`取槽` 产出的指针
//! 指向它 —— 源数据活着，指针才有效。
//!
//! # 登记为待办的两件事（不静默）
//!
//! 1. **交出所有权的返回值没有释放口。** 若返回槽带 `槽标志::所有权交出`，内存归调用方，
//!    必须还（宪法第 4 条：谁分配谁释放）。但适配器的公开面**没有释放口**
//!    （`平台_释放值` 也不在适配器里），网关不许自身去调内存分配器（那是跳层）。
//!    ⇒ 只如实转出槽的形状，**不释放**；实测路径上（底座命令 0）返回的是静态指针、
//!    未交出所有权，故当前不泄漏。修法：适配器给出释放口。
//! 2. **指针型返回值只有 `文本` / `字节集` 能跨 HTTP 边界。** 其余（例如底座命令 0 返回的
//!    `类型标签 0 + 引用` 的契约主结构指针）在 JSON 里无法表达，只能给地址 +
//!    `引用` / `长度` 两个旁路字段。`接口面形状.md` §六 #3 把「大返回走 JSON base64 还是
//!    直传二进制」列为**未裁**，这里按未裁处理：不猜、不编。

use crate::协议值::协议值;
use crate::常量::类型标签;
use crate::转码::{base64编码, base64解码};
use v1_adapter::数据槽;

/// 请求形状不合法（⇒ HTTP 400）。**带位次**：`值` 数组的第几项，是定位成本最低的信息。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 请求形状错误 {
    /// 出在 `值` 数组的第几位（`None` = 不在数组里）。
    pub 位次: Option<usize>,
    pub 说明文字: String,
}

impl 请求形状错误 {
    pub fn 构造(位次: Option<usize>, 说明文字: impl Into<String>) -> Self {
        Self {
            位次,
            说明文字: 说明文字.into(),
        }
    }

    /// 一句话说明（协议错误的返回体用它）。
    pub fn 可读说明(&self) -> String {
        match self.位次 {
            Some(序号) => format!("值[{序号}]：{}", self.说明文字),
            None => self.说明文字.clone(),
        }
    }
}

/// 一个入参槽的**源数据**。
///
/// 为什么不让 `数据槽` 直接持有：文本与字节集在槽里是裸指针，指针不持有数据 ——
/// 数据必须由调用方（本枚举）保活到调用返回为止。这是跨边界所有权口径在宿主侧的形态。
#[derive(Debug, Clone)]
pub enum 槽源 {
    无源,
    内联槽 {
        标签: u32,
        槽值: u64,
        槽字节长度: u64,
    },
    文本值(String),
    字节(Vec<u8>),
}

impl 槽源 {
    /// 取一个可交给适配器的槽。文本/字节集给**不交出所有权**的指针
    /// （数据归本枚举，调用返回后由 Rust 析构 —— 与「谁分配谁释放」一致）。
    pub fn 取槽(&self) -> 数据槽 {
        match self {
            槽源::无源 => 数据槽::空槽(),
            槽源::内联槽 { 标签, 槽值, 槽字节长度 } => 数据槽::内联槽((*标签).into(), *槽值, *槽字节长度),
            槽源::文本值(文本值) => 数据槽::指针(
                类型标签::文本值.into(),
                文本值.as_ptr() as u64,
                文本值.len() as u64,
                false,
            ),
            槽源::字节(字节) => 数据槽::指针(
                类型标签::字节集.into(),
                字节.as_ptr() as u64,
                字节.len() as u64,
                false,
            ),
        }
    }
}

/// 一个 `值` 项 → 槽源。形状不合法即 `Err`（**不猜**：猜一个就是把语义改错）。
pub fn 由协议值(待处理值: &协议值, 位次: usize) -> Result<槽源, 请求形状错误> {
    let 出错位置 = Some(位次);
    let 标签 = 待处理值
        .取成员("类型标签")
        .and_then(协议值::取无符号)
        .ok_or_else(|| {
            请求形状错误::构造(出错位置, "每一项必须是 {\"类型标签\":N,\"值\":V}，且 类型标签 是非负整数")
        })?;
    let 标签 = u32::try_from(标签)
        .map_err(|_| 请求形状错误::构造(出错位置, "类型标签 超出 32 位，不是本平台的标签"))?;
    let 值槽 = 待处理值.取成员("值").ok_or_else(|| {
        请求形状错误::构造(
            出错位置,
            "缺少 值：空位也必须写 {\"类型标签\":0,\"值\":0}，省略位次就是改行序",
        )
    })?;

    match 标签 {
        类型标签::无值 => {
            let 空槽值 = 值槽
                .取无符号()
                .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 0（空）的值必须是整数 0"))?;
            if 空槽值 != 0 {
                return Err(请求形状错误::构造(
                    出错位置,
                    "类型标签 0 是空槽，值必须是 0（要给值请用对应的类型标签）",
                ));
            }
            Ok(槽源::无源)
        }
        类型标签::整数标签 => {
            let 槽内数值 = 值槽
                .取有符号()
                .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 1（整数）的值必须是 64 位整数"))?;
            Ok(内联槽(类型标签::整数标签, 槽内数值 as u64))
        }
        类型标签::双精度 => {
            let 槽内数值 = 值槽
                .取数值()
                .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 2（双精度）的值必须是数值"))?;
            Ok(内联槽(类型标签::双精度, 槽内数值.to_bits()))
        }
        类型标签::逻辑型 => {
            let 槽内数值 = 值槽
                .取无符号()
                .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 3（逻辑型）的值必须是 0 或 1"))?;
            if 槽内数值 > 1 {
                return Err(请求形状错误::构造(出错位置, "类型标签 3（逻辑型）的值只能是 0 或 1"));
            }
            Ok(内联槽(类型标签::逻辑型, 槽内数值))
        }
        类型标签::文本值 => {
            let 文本值 = 值槽
                .取文本()
                .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 4（文本）的值必须是 JSON 字符串"))?;
            Ok(槽源::文本值(文本值.to_owned()))
        }
        类型标签::字节集 => {
            let 文本值 = 值槽.取文本().ok_or_else(|| {
                请求形状错误::构造(出错位置, "类型标签 5（字节集）的值必须是 base64 字符串")
            })?;
            let 字节 = base64解码(文本值)
                .map_err(|错误| 请求形状错误::构造(出错位置, format!("字节集不是合法 base64：{}", 错误.说明文字)))?;
            Ok(槽源::字节(字节))
        }
        类型标签::句柄 => {
            let 槽内数值 = 值槽
                .取无符号()
                .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 6（句柄）的值必须是非负整数"))?;
            Ok(内联槽(类型标签::句柄, 槽内数值))
        }
        类型标签::错误 => {
            let 槽内数值 = 值槽
                .取无符号()
                .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 4294967295（错误）的值必须是非负整数"))?;
            Ok(内联槽(类型标签::错误, 槽内数值))
        }
        _ => Err(请求形状错误::构造(
            出错位置,
            format!("类型标签 {标签} 未登记：它的 JSON 形状未定义，面不能猜着编码"),
        )),
    }
}

fn 内联槽(标签: u32, 待处理值: u64) -> 槽源 {
    槽源::内联槽 {
        标签,
        槽值: 待处理值,
        槽字节长度: 0,
    }
}

/// 一个出参槽 → `值` 项。**每一项都是 `{"类型标签": T, "值": V}` 的形状** ——
/// 冻结件 §三 的判据是「每一项自带 `类型标签`，不需要二次解析」，
/// 所以内联槽也要带标签，**不许**退化成裸数字（退化了调用方就得猜）。
///
/// 内联槽按类型标签解释；引用槽只有 `文本` / `字节集` 能跨边界（见文件头待办 2）。
pub fn 到协议值(数据槽: &数据槽) -> 协议值 {
    if 数据槽.是否引用() {
        return 引用槽到协议值(数据槽);
    }
    let 待处理值 = match 数据槽.类型标签.取号值() {
        类型标签::无值 => 协议值::整数项(0),
        类型标签::双精度 => 协议值::小数(f64::from_bits(数据槽.槽值)),
        类型标签::整数标签 => 协议值::整数项(数据槽.槽值 as i64),
        _ => 造数值(数据槽.槽值),
    };
    造槽项(数据槽.类型标签.取号值(), 待处理值)
}

/// 一个 `值` 项的标准形状。
fn 造槽项(标签: u32, 待处理值: 协议值) -> 协议值 {
    协议值::对象值(vec![
        ("类型标签".to_owned(), 造数值(u64::from(标签))),
        ("值".to_owned(), 待处理值),
    ])
}

/// 引用槽 → JSON。地址为 0 或长度为 0 时**不碰指针**（空指针不许解引用）。
fn 引用槽到协议值(数据槽: &数据槽) -> 协议值 {
    let 槽字节长度 = usize::try_from(数据槽.槽字节长度).unwrap_or(0);
    if 数据槽.槽值 == 0 || 槽字节长度 == 0 {
        return 引用形状(数据槽, 0);
    }
    // SAFETY: 契约规定引用槽的 `值` 是有效地址、`长度` 是它的字节数，且在调用返回后仍有效
    // （调用方持有数据）。上面已挡掉空指针与零长度。
    let 字节 = unsafe { core::slice::from_raw_parts(数据槽.槽值 as *const u8, 槽字节长度) };
    match 数据槽.类型标签.取号值() {
        // 文本槽按 UTF-8 解；解不出时用替换字符（**不静默丢字节**）——
        // 那是提供方违反了「文本 = UTF-8」这条契约，替换字符在返回里看得见。
        类型标签::文本值 => 造槽项(
            类型标签::文本值,
            协议值::文本值(String::from_utf8_lossy(字节).into_owned()),
        ),
        类型标签::字节集 => 造槽项(类型标签::字节集, 协议值::文本值(base64编码(字节))),
        _ => 引用形状(数据槽, 数据槽.槽字节长度),
    }
}

/// 指针型返回值**跨不过 HTTP 边界**时的形状：给地址 + `引用` / `长度` 两个旁路字段，
/// 让「这里有一个指针」这件事在返回里看得见，而不是静默丢掉。
fn 引用形状(数据槽: &数据槽, 槽字节长度: u64) -> 协议值 {
    协议值::对象值(vec![
        ("类型标签".to_owned(), 造数值(u64::from(数据槽.类型标签.取号值()))),
        ("值".to_owned(), 造数值(数据槽.槽值)),
        ("引用".to_owned(), 协议值::真值),
        ("长度".to_owned(), 造数值(槽字节长度)),
    ])
}

fn 造数值(整数值: u64) -> 协议值 {
    match i64::try_from(整数值) {
        Ok(整数值) => 协议值::整数项(整数值),
        Err(_) => 协议值::无符号值(整数值),
    }
}
