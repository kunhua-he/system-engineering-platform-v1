//! 留痕端点 —— `GET /接口/留痕`。
//!
//! README 第三节承诺「跨边界可追溯：每次调用留痕（谁 · 调什么 · 入参指纹 · 结果 · 耗时）」。
//! 适配器的调用路已写留痕（`跨语言适配/适配器实现/src/留痕口.rs`），本件把取用口
//! 接到对外面上。
//!
//! # 形状
//!
//! ```json
//! { "成功": true,
//!   "数据": { "已启用": true, "条数": 2, "已丢弃": 0,
//!             "留痕": [ { "实例": …, "调用类": "能力", "能力号": 0, "资源号": 0,
//!                         "操作号": 0, "入参指纹": …, "结果码": 0,
//!                         "耗时微秒": 12, "追踪号": 0 } ] },
//!   "耗时微秒": 3 }
//! ```
//!
//! # 两条如实口径
//!
//! 1. **开不开由装配侧决定**：生产装配（`服务::绑定并托管`）按契约常量 `留痕容量` 开留痕
//!    （= 10000）⇒ 正常起服务时 `已启用` 报 `true`；装配方不调
//!    `服务::启用留痕`（或 `适配器::装载` 后没开）则报 `false`、`留痕` 为空表。
//!    这不是「取不到」，是「没开」—— 两者必须分得开（旁路字段 `已启用`）。
//! 2. **取最近全部**：不给条数参数就不设人为上限 —— 上限由留痕缓冲自身的容量决定
//!    （`取最近(u32::MAX)` 会被缓冲夹到有效条数）。**不发明一个「最近 N 条」的数**。
//!
//! 形状与共用件口径全在 `工具响应.rs` 的文件头，本件不另立一套。

use super::工具响应::成功;
use crate::协议值::协议值;
use std::time::Instant;
use v1_adapter::{适配器, 留痕, 调用类};

/// `GET /接口/留痕` → 最近留痕（时间序：旧在前、新在后）。
pub fn 取留痕(适配器: &适配器) -> 协议值 {
    let 区间起点 = Instant::now();
    let 留痕清单 = 适配器.取留痕(u32::MAX);
    let 留痕表: Vec<协议值> = 留痕清单.iter().map(一条).collect();
    成功(
        协议值::对象(vec![
            ("已启用".to_owned(), 逻辑型值(适配器.留痕已启用())),
            ("条数".to_owned(), 协议值::无符号(留痕清单.len() as u64)),
            (
                "已丢弃".to_owned(),
                协议值::无符号(适配器.留痕已丢弃()),
            ),
            ("留痕".to_owned(), 协议值::数组(留痕表)),
        ]),
        &区间起点,
    )
}

/// 一条留痕 → JSON 对象。字段名与 `运行内核/调用留痕/` 的 `留痕` 逐字一致。
///
/// `调用类` 是判别位（`能力` / `资源`），读的人**先看它再取号**：能力调用看 `能力号`、
/// 资源访问看 `资源号` + `操作号`；另一个号位必然是 `0`（`留痕::自洽`）。
fn 一条(一条: &留痕) -> 协议值 {
    协议值::对象(vec![
        ("实例".to_owned(), 协议值::无符号(一条.实例)),
        ("调用类".to_owned(), 协议值::文本(调用类文本(一条.调用类))),
        (
            "能力号".to_owned(),
            协议值::无符号(u64::from(一条.能力号.取号值())),
        ),
        (
            "资源号".to_owned(),
            协议值::无符号(u64::from(一条.资源号.取号值())),
        ),
        (
            "操作号".to_owned(),
            协议值::无符号(u64::from(一条.操作号.取号值())),
        ),
        ("入参指纹".to_owned(), 协议值::无符号(一条.入参指纹)),
        (
            "结果码".to_owned(),
            协议值::整数(i64::from(一条.结果码)),
        ),
        ("耗时微秒".to_owned(), 协议值::无符号(一条.耗时微秒)),
        ("追踪号".to_owned(), 协议值::无符号(一条.追踪号)),
    ])
}

/// 调用类的文本名（JSON 里给人看，不用裸数字）。
fn 调用类文本(类别: 调用类) -> String {
    match 类别 {
        调用类::能力 => "能力".to_owned(),
        调用类::资源 => "资源".to_owned(),
    }
}

fn 逻辑型值(待处理值: bool) -> 协议值 {
    if 待处理值 {
        协议值::逻辑真
    } else {
        协议值::逻辑假
    }
}
