//! 留痕端点 —— `GET /接口/留痕`。
//!
//! README 第三节承诺「跨边界可追溯：每次调用留痕（谁 · 调什么 · 入参指纹 · 结果 · 耗时）」。
//! 适配器的调用路已写留痕（`跨语言适配/适配器实现/src/留痕口.rs`），本件把取用口
//! 接到对外面上。
//!
//! # 形状
//!
//! ```json
//! { "成功": true,
//!   "数据": { "已启用": true, "条数": 2, "已丢弃": 0,
//!             "留痕": [ { "实例": …, "调用类": "能力", "能力号": 0, "资源号": 0,
//!                         "操作号": 0, "入参指纹": …, "结果码": 0,
//!                         "耗时微秒": 12, "追踪号": 0 } ],
//!             "查询结论": "全部成功" },
//!             "查询结论": "全部成功" },
//!   "耗时微秒": 3 }
//! ```
//!
//! # 三条如实口径
//!
//! 1. **开不开由装配侧决定**：生产装配（`服务::绑定并托管`）按契约常量 `留痕容量` 开留痕
//!    （= 10000）⇒ 正常起服务时 `已启用` 报 `true`；装配方不调
//!    `服务::启用留痕`（或 `适配器::装载` 后没开）则报 `false`、`留痕` 为空表。
//!    这不是「取不到」，是「没开」—— 两者必须分得开（旁路字段 `已启用`）。
//! 2. **取最近全部**：不给条数参数就不设人为上限 —— 上限由留痕缓冲自身的容量决定
//!    （`取最近(u32::MAX)` 会被缓冲夹到有效条数）。**不发明一个「最近 N 条」的数**。
//! 3. **「这些记录里有失败吗」有区分位**：旁路字段 `查询结论` 三值闭合 —— `记录不存在`
//!    （一条都没有，含「没开」那一档，靠 `已启用` 分得开）· `已有失败`（至少一条
//!    `结果码` 非零）· `全部成功`（每一条都零）。没有它，读的人得把整张留痕表逐条读
//!    `结果码` 再各自判，「有失败吗」这一问就各判各的（口径会漂）。
//!
//! 形状与共用件口径全在 `工具响应.rs` 的文件头，本件不另立一套。

use super::工具响应::造成功应答;
use super::线上逻辑值::真假值转线上值;
use crate::协议值::协议值;
use std::time::Instant;
use v1_adapter::{适配器, 留痕, 调用类};

/// `GET /接口/留痕` → 最近留痕（时间序：旧在前、新在后）。
pub fn 取留痕(适配器: &适配器) -> 协议值 {
    let 区间起点 = Instant::now();
    let 留痕清单 = 适配器.取留痕(u32::MAX);
    let 留痕表: Vec<协议值> = 留痕清单.iter().map(留痕转协议值).collect();
    造成功应答(
        协议值::对象值(vec![
            ("已启用".to_owned(), 真假值转线上值(适配器.留痕已启用())),
            ("条数".to_owned(), 协议值::无符号值(留痕清单.len() as u64)),
            (
                "已丢弃".to_owned(),
                协议值::无符号值(适配器.留痕已丢弃()),
            ),
            ("留痕".to_owned(), 协议值::数组值(留痕表)),
            // 旁路字段（尾部追加，只增不改）—— 口径见文件头第 3 条。
            (
                "查询结论".to_owned(),
                协议值::文本值(取查询结论(&留痕清单).to_owned()),
            ),
        ]),
        &区间起点,
    )
}

/// 一条留痕 → JSON 对象。**键是「对外形状」**：逐字照抄本件文件头那段 JSON（它是
/// 对外接口面形状的一部分，属冻结公开面）—— 与内部字段名**不必同名**：
/// 例 `"实例"` 取自内部字段 `实例号`（2026-10-06 命名债务清零：字段 `实例`→`实例号`，
/// 而对外键 `"实例"` 不动，改它会破已公布的响应形状）。
///
/// `调用类` 是判别位（`能力` / `资源`），读的人**先看它再取号**：能力调用看 `能力号`、
/// 资源访问看 `资源号` + `操作号`；另一个号位必然是 `0`（`留痕::是否自洽`）。
fn 留痕转协议值(留痕条目: &留痕) -> 协议值 {
    协议值::对象值(vec![
        ("实例".to_owned(), 协议值::无符号值(留痕条目.实例号)),
        ("调用类".to_owned(), 协议值::文本值(调用类文本(留痕条目.调用类))),
        (
            "能力号".to_owned(),
            协议值::无符号值(u64::from(留痕条目.能力号.取号值())),
        ),
        (
            "资源号".to_owned(),
            协议值::无符号值(u64::from(留痕条目.资源号.取号值())),
        ),
        (
            "操作号".to_owned(),
            协议值::无符号值(u64::from(留痕条目.操作号.取号值())),
        ),
        ("入参指纹".to_owned(), 协议值::无符号值(留痕条目.入参指纹)),
        (
            "结果码".to_owned(),
            协议值::整数项(i64::from(留痕条目.结果码)),
        ),
        ("耗时微秒".to_owned(), 协议值::无符号值(留痕条目.耗时微秒)),
        ("追踪号".to_owned(), 协议值::无符号值(留痕条目.追踪号)),
    ])
}

/// 这一次查询**拿到了什么** —— 三值闭合：`记录不存在` / `已有失败` / `全部成功`。
///
/// 为什么单开一个区分位：`已启用` 只答「开没开」、`条数` 只答「几条」，而读的人要问的
/// 第三问是「**这些记录里有失败吗**」—— 没有区分位时只能把整张留痕表逐条读 `结果码`
/// 再各自判（口径会漂）。三值**互斥且穷尽**（按「`条数` 是否为 0」与「记录里有无非零
/// `结果码`」两问切），不留第四档：
///
/// - `记录不存在`：一条记录都没有（含「装配侧没开留痕」那一档 —— 那两者靠 `已启用` 分得开）；
/// - `已有失败`：有记录，且**至少一条**的 `结果码` 非零；
/// - `全部成功`：有记录，且**每一条**的 `结果码` 都是零。
fn 取查询结论(留痕清单: &[留痕]) -> &'static str {
    if 留痕清单.is_empty() {
        return "记录不存在";
    }
    if 留痕清单.iter().any(|留痕条目| 留痕条目.结果码 != 0) {
        "已有失败"
    } else {
        "全部成功"
    }
}

/// 调用类的文本名（JSON 里给人看，不用裸数字）。
fn 调用类文本(调用类值: 调用类) -> String {
    match 调用类值 {
        调用类::能力 => "能力".to_owned(),
        调用类::资源 => "资源".to_owned(),
    }
}
