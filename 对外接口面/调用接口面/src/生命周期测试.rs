/// `POST /接口/生命周期`（`动作=装载`）→ 重扫扩展根。**声明根没注入**时 fail-closed 指路
/// （顶层仍 200：这是「重扫不了」的如实报出，不是协议层失败）。
#[test]
fn 生命周期装载_声明根未注入时指路() {
    let 服务 = 起服务(); // 起服务() 不注入 声明根
    let 应答 = 发请求(&服务, &交请求("/接口/生命周期", "{\"动作\":\"装载\"}"));
    assert_eq!(应答.状态, 200, "重扫不了是数据里的说明，协议层仍 200");
    let 数据 = 成功数据(&应答);
    assert_eq!(文本(&数据, "动作"), "装载");
    assert!(
        文本(&数据, "说明").contains("声明根未注入"),
        "必须指路（装配侧调 服务::声明根）：\n{}",
        应答.体
    );
}

/// `动作=装载` 且声明根指向一个**空**扫描目录 ⇒ 扫到 0 个：**未命中不是失败**（照卸载口径），
/// 顶层 `成功: true` 且 `装上` 为空。
#[test]
fn 生命周期装载_空扫描目录是未命中不是失败() {
    let 临时根 = std::env::temp_dir().join(format!("v1_热载入空_{}", std::process::id()));
    let 扫描目录 = 临时根.join("扫描点");
    std::fs::create_dir_all(&扫描目录).expect("建扫描目录");
    let 声明根 = 临时根.join("扩展根声明.json");
    std::fs::write(
        &声明根,
        format!(
            "{{\"种类\":[{{\"种类\":\"支持库\",\"目录\":\"{}\"}}]}}",
            扫描目录.display()
        ),
    )
    .expect("写声明根");
    let 服务 = 起服务().声明根(&声明根);
    let 应答 = 发请求(&服务, &交请求("/接口/生命周期", "{\"动作\":\"装载\"}"));
    assert_eq!(应答.状态, 200);
    let 数据 = 成功数据(&应答);
    assert_eq!(文本(&数据, "动作"), "装载");
    assert_eq!(无符号(&数据, "扫到"), 0, "空目录 ⇒ 扫到 0 个");
    assert!(数组(&数据, "装上").is_empty(), "没有新候选可装");
    let _ = std::fs::remove_dir_all(&临时根);
}

/// 未登记的错误码不许抛出：本族失败走 `数据` 如实报结局，**不自造码**。
/// （这条把「不编码」钉成可跑判据：若有人给未命中编一个 9xxx，本用例的六项断言会当场红。）
#[test]
fn 生命周期卸载_不编业务错误码() {
    let 服务 = 起服务();
    let 应答 = 发请求(
        &服务,
        &交请求(
            "/接口/生命周期",
            "{\"动作\":\"卸载\",\"标识串\":\"ffffffffffffffffffffffffffffffff\"}",
        ),
    );
    assert!(
        应答.找成员("错误").is_none(),
        "未命中不是业务失败，不许编一个错误对象：\n{}",
        应答.体
    );
}
