/// `动作=装载` 且声明根指向一个**空**扫描目录 ⇒ 扫到 0 个：**未命中不是失败**（照卸载口径），
/// 顶层 `成功: true` 且 `装上` 为空。
#[test]
fn 生命周期装载_空扫描目录是未命中不是失败() {
    let 临时仓根 = std::env::temp_dir().join(format!("v1_热载入空_{}", std::process::id()));
    let 扫描目录 = 临时仓根.join("扫描点");
    std::fs::create_dir_all(&扫描目录).expect("建扫描目录");
    let 声明根 = 临时仓根.join("扩展根声明.json");
    std::fs::write(
        &声明根,
        format!(
            "{{\"种类\":[{{\"种类\":\"支持库\",\"目录\":\"{}\"}}]}}",
            扫描目录.display()
        ),
    )
    .expect("写声明根");
    // 重扫要两份注入：声明根（扫哪些目录）与后缀表（判候选）—— 与装配侧同一条约定。
    // 缓存根也显式给一份仓外落点：本用例只看「扫到 0 个」，不让解包路参与。
    let 服务 = 起服务()
        .声明根(&声明根)
        .后缀表("{\"三类扩展\":[{\"制品后缀\":\".支持库制品\"}]}")
        .缓存根目录(临时仓根.join("缓存"));
    let 造应答 = 发请求(&服务, &交POST请求("/接口/生命周期", "{\"动作\":\"装载\"}"));
    assert_eq!(造应答.状态, 200);
    let 应答数据 = 取成功数据(&造应答);
    assert_eq!(源文本(&应答数据, "动作"), "装载");
    assert_eq!(无符号值(&应答数据, "扫到"), 0, "空目录 ⇒ 扫到 0 个");
    assert!(取成员数组(&应答数据, "装上").is_empty(), "没有新候选可装");
    let _ = std::fs::remove_dir_all(&临时仓根);
}

