//! 生命周期族与留痕端点 —— 触发卸载的路由与取留痕的口的可跑读数。
//!
//! 三条端点（`GET/POST /接口/生命周期` · `GET /接口/留痕`）走完整生产路径：
//! `TcpListener::accept` → 路由 → 转调**适配器** → 手写 HTTP 造应答。
//!
//! # 口径
//!
//! - `GET /接口/生命周期` 是**就绪/健康读数**：走生命周期通知那本账（端点表），
//!   不是另存一份健康表。
//! - `POST /接口/生命周期` 的 `{"动作":"卸载"}` 发 `2001 卸载`；没注册过的标识 ⇒
//!   `未命中`（宪法第 6 条：不是错误），如实报在 `数据.派发结果`。
//! - `GET /接口/留痕` 装配侧**已开**（容量 = 契约常量 `留痕容量` = 10000）⇒ `已启用: true`。

use crate::常量;
use crate::测试夹具::{发请求, 取请求, 交POST请求, 取逻辑值, 源文本, 无符号值, 取成员数组, 起服务, 仓根};
use std::path::PathBuf;

/// 取一个 `成功: true` 的 `数据` 对象；不是成功就挂（带原文）。
fn 取成功数据(造应答: &crate::测试夹具::收到应答) -> crate::协议值::协议值 {
    assert!(造应答.取逻辑值("成功"), "必须成功：\n{}", 造应答.报文体);
    造应答.取成员("数据")
}

/// `GET /接口/生命周期` → 就绪读数：已装载声明数 · 通知端点数 · 已注册标识串。
#[test]
fn 生命周期读数_给出装载数与端点数() {
    let 服务 = 起服务();
    let 造应答 = 发请求(&服务, &取请求("/接口/生命周期"));
    assert_eq!(造应答.状态, 200);
    let 应答数据 = 取成功数据(&造应答);

    assert!(
        无符号值(&应答数据, "已装载声明数") >= 1,
        "至少底座自身那份声明：\n{}",
        造应答.报文体
    );
    assert_eq!(
        无符号值(&应答数据, "通知端点数"),
        u64::from(服务.适配器().通知端点数()),
        "读数必须与适配器那本账同源"
    );
    assert_eq!(
        取成员数组(&应答数据, "已注册标识串").len(),
        usize::try_from(服务.适配器().通知端点数()).expect("端点数不大"),
        "标识串条数必须与端点数一致（同一把锁下的同一份账）"
    );
}

/// `POST /接口/生命周期`（卸载一个没注册过的标识）→ `未命中`，**不是失败**。
#[test]
fn 生命周期卸载_未注册标识是未命中不是失败() {
    let 服务 = 起服务();
    let 请求体 = "{\"动作\":\"卸载\",\"标识串\":\"ffffffffffffffffffffffffffffffff\"}";
    let 造应答 = 发请求(&服务, &交POST请求("/接口/生命周期", 请求体));
    assert_eq!(造应答.状态, 200, "结局在数据里，协议层仍是 200");
    let 应答数据 = 取成功数据(&造应答);
    assert_eq!(
        源文本(&应答数据, "派发结果"),
        "未命中",
        "没注册过的标识 = 未命中（宪法第 6 条）"
    );
    assert_eq!(源文本(&应答数据, "标识串"), "ffffffffffffffffffffffffffffffff");
    assert!(应答数据.取成员("通知端点数").is_some(), "卸载后要报端点剩几个");
    // C1：逻辑卸载与物理回收**分别出读数**；未命中 ⇒ 两个都是 0（不假装杀过域）。
    assert_eq!(无符号值(&应答数据, "逻辑卸载"), 0, "未命中 ⇒ 没逻辑卸载");
    assert_eq!(无符号值(&应答数据, "物理回收"), 0, "未命中 ⇒ 不杀域");
}

