//! 生命周期族与留痕端点 —— 台账 #80（触发卸载的路由）与 #99（取留痕的口）的可跑读数。
//!
//! 三条端点（`GET/POST /接口/生命周期` · `GET /接口/留痕`）走完整生产路径：
//! `TcpListener::accept` → 路由 → 转调**适配器** → 手写 HTTP 应答。
//!
//! # 口径
//!
//! - `GET /接口/生命周期` 是**就绪/健康读数**：走生命周期通知那本账（端点表），
//!   不是另存一份健康表。
//! - `POST /接口/生命周期` 的 `{"动作":"卸载"}` 发 `2001 卸载`；没注册过的标识 ⇒
//!   `未命中`（宪法第 6 条：不是错误），如实报在 `数据.派发结果`。
//! - `GET /接口/留痕` 装配侧**已开**（容量 = 契约常量 `留痕容量` = 10000，台账 #26 已裁）⇒ `已启用: true`。

use crate::测试夹具::{发, 取请求, 交请求, 布尔, 文本, 无符号, 数组, 起服务};

/// 取一个 `成功: true` 的 `数据` 对象；不是成功就挂（带原文）。
fn 成功数据(应答: &crate::测试夹具::收到) -> crate::协议值::协议值 {
    assert!(应答.取布尔("成功"), "必须成功：\n{}", 应答.体);
    应答.取("数据")
}

/// `GET /接口/生命周期` → 就绪读数：已装载声明数 · 通知端点数 · 已注册标识串。
#[test]
fn 生命周期读数_给出装载数与端点数() {
    let 服务 = 起服务();
    let 应答 = 发(&服务, &取请求("/接口/生命周期"));
    assert_eq!(应答.状态, 200);
    let 数据 = 成功数据(&应答);

    assert!(
        无符号(&数据, "已装载声明数") >= 1,
        "至少底座自己那份声明：\n{}",
        应答.体
    );
    assert_eq!(
        无符号(&数据, "通知端点数"),
        u64::from(服务.适配器().通知端点数()),
        "读数必须与适配器那本账同源"
    );
    assert_eq!(
        数组(&数据, "已注册标识串").len(),
        usize::try_from(服务.适配器().通知端点数()).expect("端点数不大"),
        "标识串条数必须与端点数一致（同一把锁下的同一份账）"
    );
}

/// `POST /接口/生命周期`（卸载一个没注册过的标识）→ `未命中`，**不是失败**。
#[test]
fn 生命周期卸载_未注册标识是未命中不是失败() {
    let 服务 = 起服务();
    let 体 = "{\"动作\":\"卸载\",\"标识串\":\"ffffffffffffffffffffffffffffffff\"}";
    let 应答 = 发(&服务, &交请求("/接口/生命周期", 体));
    assert_eq!(应答.状态, 200, "结局在数据里，协议层仍是 200");
    let 数据 = 成功数据(&应答);
    assert_eq!(
        文本(&数据, "派发结果"),
        "未命中",
        "没注册过的标识 = 未命中（宪法第 6 条）"
    );
    assert_eq!(文本(&数据, "标识串"), "ffffffffffffffffffffffffffffffff");
    assert!(数据.取("通知端点数").is_some(), "卸载后要报端点剩几个");
}

/// `POST /接口/生命周期` 的 `动作` 是闭合枚举：不认的值 ⇒ **400**（协议层）。
#[test]
fn 生命周期卸载_动作不合法是400() {
    let 服务 = 起服务();
    let 应答 = 发(&服务, &交请求("/接口/生命周期", "{\"动作\":\"装载\",\"标识串\":\"x\"}"));
    assert_eq!(应答.状态, 400, "动作不在闭合枚举里 ⇒ 请求形状不合法");
    assert!(
        应答.取文本("协议错误").contains("卸载"),
        "400 必须说清只认哪个动作：\n{}",
        应答.体
    );
}

/// `GET /接口/留痕` → 装配侧**已开**（容量取自契约常量 `留痕容量`，台账 #26 已裁 = 10000）：
/// `已启用: true`、`已丢弃: 0`。刚起的服务还没发生过**能力调用** ⇒ `条数: 0` · `留痕: []`。
#[test]
fn 留痕_装配侧已开且如实报启用() {
    let 服务 = 起服务();
    let 应答 = 发(&服务, &取请求("/接口/留痕"));
    assert_eq!(应答.状态, 200);
    let 数据 = 成功数据(&应答);
    assert!(
        布尔(&数据, "已启用"),
        "装配侧按契约常量 `留痕容量` 开留痕（README §三「每次调用留痕」）"
    );
    assert_eq!(无符号(&数据, "条数"), 0, "本服务还没发生过能力调用");
    assert_eq!(无符号(&数据, "已丢弃"), 0);
    assert!(数组(&数据, "留痕").is_empty());
}

/// `POST /接口/留痕` 方法不对 ⇒ 405（路径在，方法不对）。
#[test]
fn 留痕_方法不对是405() {
    let 服务 = 起服务();
    let 应答 = 发(&服务, &交请求("/接口/留痕", "{}"));
    assert_eq!(应答.状态, 405);
}

/// 未登记的错误码不许抛出：本族失败走 `数据` 如实报结局，**不自造码**。
/// （这条把「不编码」钉成可跑判据：若有人给未命中编一个 9xxx，本用例的六项断言会当场红。）
#[test]
fn 生命周期卸载_不编业务错误码() {
    let 服务 = 起服务();
    let 应答 = 发(
        &服务,
        &交请求(
            "/接口/生命周期",
            "{\"动作\":\"卸载\",\"标识串\":\"ffffffffffffffffffffffffffffffff\"}",
        ),
    );
    assert!(
        应答.找("错误").is_none(),
        "未命中不是业务失败，不许编一个错误对象：\n{}",
        应答.体
    );
}
