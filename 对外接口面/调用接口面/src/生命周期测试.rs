/// 后缀表读法：文本与解出的表**同一份来源**（唯一权威 `扩展装载/后缀表.json`）——
/// 测试不写死任何后缀字面（判据 ③：全仓不许有第二处后缀表）。
fn 真后缀表() -> (String, crate::扫扩展根::后缀表) {
    let 后缀表文本 = std::fs::read_to_string(仓根().join(常量::后缀表路径)).expect("读后缀表");
    let 后缀表 = crate::扫扩展根::读后缀表(&后缀表文本).expect("解后缀表");
    (后缀表文本, 后缀表)
}

/// 取一个**真模块候选目录**：按 `扩展装载/扩展根声明.json` 扫出来，**不点名任何扩展**
/// （README 硬边界 1：底座不认识任何扩展 —— 名字、路径都不许出现在底座里）。
fn 真模块候选目录(后缀表: &crate::扫扩展根::后缀表) -> PathBuf {
    let 声明件 = 仓根().join(常量::扩展根声明);
    let 源文本 = std::fs::read_to_string(&声明件).expect("读扩展根声明");
    let 扫描读数 = crate::扫扩展根::读声明根(&源文本).expect("解扩展根声明");
    for 落点 in &扫描读数.目录s {
        for 子目录 in crate::扫扩展根::列子目录(&仓根().join(落点)) {
            if crate::模块制品::是模块候选(&子目录, 后缀表) {
                return 子目录;
            }
        }
    }
    panic!("按扩展根声明扫不到任何模块候选（真样本没了？）");
}

/// `动作=装载` 扫到一个**模块候选**（真样本：按声明扫出来的那个模块目录）⇒ 结局仍落 `剔除`
/// （模块不归底座 `dlopen`，走子进程 + IPC），但**原因里必须带上依赖判读的结论**（债务 374 真接入）。
///
/// 样本从仓根**拷**到临时扫描点（目录名只是落点）；后缀表读**唯一权威** `扩展装载/后缀表.json`。
#[test]
fn 生命周期装载_模块候选报依赖判读() {
    let (后缀表文本, 后缀表) = 真后缀表();
    let 源模块 = 真模块候选目录(&后缀表);
    let 临时仓根 = std::env::temp_dir().join(format!("v1_热载入模块_{}", std::process::id()));
    let 扫描目录 = 临时仓根.join("扫描点");
    let 模块目录 = 扫描目录.join("某模块");
    std::fs::create_dir_all(&模块目录).expect("建扫描点");
    for 目录项 in std::fs::read_dir(&源模块).expect("读源模块目录") {
        let 目录项 = 目录项.expect("目录项");
        if 目录项.path().is_file() {
            std::fs::copy(目录项.path(), 模块目录.join(目录项.file_name())).expect("拷样本");
        }
    }
    let 声明根 = 临时仓根.join("扩展根声明.json");
    // 扩展落点 = **种类目录**（它的直接子目录才是候选）—— 与 `扩展根声明.json` 同一条口径。
    std::fs::write(
        &声明根,
        format!(
            "{{\"种类\":[{{\"种类\":\"模块\",\"扩展落点\":\"{}\"}}]}}",
            模块目录.parent().expect("模块目录必有上级（种类目录）").display()
        ),
    )
    .expect("写声明根");
    let 服务 = 起服务()
        .声明根(&声明根)
        .后缀表(后缀表文本)
        .缓存根目录(临时仓根.join("缓存"));
    let 造应答 = 发请求(&服务, &交POST请求("/接口/生命周期", "{\"动作\":\"装载\"}"));
    assert_eq!(造应答.状态, 200);
    let 应答数据 = 取成功数据(&造应答);
    assert_eq!(无符号值(&应答数据, "扫到"), 1, "模块候选也算扫到（它进了 剔除）");
    let 剔除表 = 取成员数组(&应答数据, "剔除");
    assert_eq!(剔除表.len(), 1, "模块候选该落 剔除（底座不 dlopen 模块）：{剔除表:?}");
    let 剔除原因 = 源文本(&剔除表[0], "原因");
    assert!(剔除原因.contains("模块候选"), "原因该点明这是模块候选：{剔除原因}");
    assert!(剔除原因.contains("依赖清单判过"), "真样本（依赖清单空表）该判过：{剔除原因}");
    let _ = std::fs::remove_dir_all(&临时仓根);
}

