//!
//! 为什么要单列：`接口面形状.md` §三 冻结的两句话全在这两条映射上 ——
//! 「文本 ⇒ JSON 字符串；字节集 ⇒ base64 字符串，**靠 `类型标签` 区分，不靠形状猜**」
//! 与「每个返回值项自带 `类型标签`，不需要二次解析」。判据要能单独数。

use crate::协议值::协议值;

