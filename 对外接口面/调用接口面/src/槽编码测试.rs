/// 文本与字节集的入参编码：**靠 `类型标签` 区分，不靠形状猜**（§三 冻结）。
#[test]
fn 槽编码_文本与字节集的入参编码() {
    let 文本槽 = 协议值::对象值(vec![
        ("类型标签".to_owned(), 协议值::整数项(4)),
        ("值".to_owned(), 协议值::文本值("反解容器".to_owned())),
    ]);
    let 来源 = crate::槽编码::由协议值(&文本槽, 0).expect("文本槽形状合法");
    assert_eq!(来源.取槽().类型标签, 4);

    let 字节 = vec![0u8, 255, 1, 2, 254];
    let 字节槽 = 协议值::对象值(vec![
        ("类型标签".to_owned(), 协议值::整数项(5)),
        (
            "值".to_owned(),
            协议值::文本值(crate::转码::base64编码(&字节)),
        ),
    ]);
    let 来源 = crate::槽编码::由协议值(&字节槽, 0).expect("字节集槽形状合法");
    assert_eq!(来源.取槽().类型标签, 5);
    assert_eq!(来源.取槽().槽字节长度, 字节.len() as u64, "字节集必须带长度");

    // 形状不合法一律拒，不猜。
    for 坏件表 in [
        // 类型标签未登记
        (99, 协议值::整数项(1)),
        // 文本标签给了数字
        (4, 协议值::整数项(1)),
        // 字节集标签给了非 base64
        (5, 协议值::文本值("!!!不是 base64!!!".to_owned())),
        // 逻辑标签给了 2
        (3, 协议值::整数项(2)),
        // 空标签给了非 0
        (0, 协议值::整数项(7)),
    ] {
        let 数据槽 = 协议值::对象值(vec![
            ("类型标签".to_owned(), 协议值::整数项(坏件表.0)),
            ("值".to_owned(), 坏件表.1),
        ]);
        assert!(
            crate::槽编码::由协议值(&数据槽, 0).is_err(),
            "类型标签 {} 的这个形状必须被判不合法",
            坏件表.0
        );
    }
}

/// 返回值的编码：文本/字节集跨得过来；**指针型返回值跨不过 HTTP 边界** ——
/// 那种槽给地址 + `引用` / `长度` 两个旁路字段，让「这里有一个指针」看得见。
#[test]
fn 槽编码_返回值编码与指针型旁路字段() {
    use v1_adapter::数据槽;

    // 文本：指针 + 长度 → JSON 字符串。
    let 文本值 = String::from("反解容器");
    let 数据槽 = 数据槽::指针(4.into(), 文本值.as_ptr() as u64, 文本值.len() as u64, false);
    let 输出缓冲 = crate::槽编码::到协议值(&数据槽);
    assert_eq!(输出缓冲.取成员("类型标签").and_then(协议值::取无符号), Some(4));
    assert_eq!(输出缓冲.取成员("值").and_then(协议值::取文本), Some("反解容器"));

    // 字节集：指针 + 长度 → base64 字符串。
    let 字节 = vec![1u8, 2, 3];
    let 数据槽 = 数据槽::指针(5.into(), 字节.as_ptr() as u64, 字节.len() as u64, false);
    let 输出缓冲 = crate::槽编码::到协议值(&数据槽);
    let 期望 = crate::转码::base64编码(&字节);
    assert_eq!(输出缓冲.取成员("值").and_then(协议值::取文本), Some(期望.as_str()));

    // 指针型（非文本/字节集）：**跨不过去**，给地址 + 两个旁路字段。
    // 用地址 0 走这条分支：空地址不许解引用。
    let 数据槽 = 数据槽::指针(0.into(), 0, 64, false);
    let 输出缓冲 = crate::槽编码::到协议值(&数据槽);
    assert_eq!(输出缓冲.取成员("引用"), Some(&协议值::真值));
    assert_eq!(输出缓冲.取成员("长度").and_then(协议值::取无符号), Some(0));

    // 内联槽：整数按 i64 读回，双精度按位读回。
    assert_eq!(
        crate::槽编码::到协议值(&数据槽::内联槽(1.into(), 42, 0))
            .取成员("值")
            .and_then(协议值::取有符号),
        Some(42)
    );
    assert_eq!(
        crate::槽编码::到协议值(&数据槽::内联槽(2.into(), 1.5f64.to_bits(), 0))
            .取成员("值")
            .and_then(协议值::取数值),
        Some(1.5)
    );
    // 空槽的形状就是冻结件里的空位写法。
    let 空槽出 = crate::槽编码::到协议值(&数据槽::空槽());
    assert_eq!(空槽出.取成员("类型标签").and_then(协议值::取无符号), Some(0));
    assert_eq!(空槽出.取成员("值").and_then(协议值::取有符号), Some(0));
}

/// 复合类型（100–103）入参：JSON → 自描述 TLV 载荷，**靠标签区分、不靠形状猜**。
#[test]
fn 槽编码_结果结构入参编成载荷() {
    let 结果项 = 协议值::对象值(vec![
        ("类型标签".to_owned(), 协议值::整数项(103)),
        (
            "值".to_owned(),
            协议值::对象值(vec![
                ("名称".to_owned(), 协议值::对象值(vec![("类型标签".to_owned(), 协议值::整数项(4)), ("值".to_owned(), 协议值::文本值("反解容器".to_owned()))])),
                ("数量".to_owned(), 协议值::对象值(vec![("类型标签".to_owned(), 协议值::整数项(1)), ("值".to_owned(), 协议值::整数项(7))])),
            ]),
        ),
    ]);
    let 来源 = crate::槽编码::由协议值(&结果项, 0).expect("结果结构形状合法");
    let 产出槽 = 来源.取槽();
    assert_eq!(产出槽.类型标签, 103, "必须是 103 —— 退化成字节集会让标签变成 5");
    assert!(产出槽.槽字节长度 > 0, "载荷必须带长度");
}

/// 入 → 载荷 → 出 必须**逐字段回到原样**（映射互为逆）。
#[test]
fn 槽编码_载荷解回协议值() {
    let 结果项 = 协议值::对象值(vec![
        ("类型标签".to_owned(), 协议值::整数项(103)),
        (
            "值".to_owned(),
            协议值::对象值(vec![
                ("名称".to_owned(), 协议值::对象值(vec![("类型标签".to_owned(), 协议值::整数项(4)), ("值".to_owned(), 协议值::文本值("反解容器".to_owned()))])),
                ("数量".to_owned(), 协议值::对象值(vec![("类型标签".to_owned(), 协议值::整数项(1)), ("值".to_owned(), 协议值::整数项(7))])),
                ("命中".to_owned(), 协议值::对象值(vec![("类型标签".to_owned(), 协议值::整数项(3)), ("值".to_owned(), 协议值::整数项(1))])),
            ]),
        ),
    ]);
    let 来源 = crate::槽编码::由协议值(&结果项, 0).expect("形状合法");
    let 回读值 = crate::槽编码::到协议值(&来源.取槽());
    assert_eq!(回读值, 结果项, "入 → 载荷 → 出 必须逐字段回到原样");
}

/// 反向样本：形状校验在 `复合值载荷` 那一份口径里，**这里不许另判一遍**。
#[test]
fn 槽编码_列表元素名必空即拒() {
    // 101 字典要求名称非空 ⇒ 空键必拒。
    let 字典项 = 协议值::对象值(vec![
        ("类型标签".to_owned(), 协议值::整数项(101)),
        (
            "值".to_owned(),
            协议值::对象值(vec![(
                String::new(),
                协议值::对象值(vec![("类型标签".to_owned(), 协议值::整数项(1)), ("值".to_owned(), 协议值::整数项(1))]),
            )]),
        ),
    ]);
    assert!(crate::槽编码::由协议值(&字典项, 0).is_err(), "字典的空名称必须拒");

    // 100 列表收数组 ⇒ 传对象必拒。
    let 列表传对象 = 协议值::对象值(vec![
        ("类型标签".to_owned(), 协议值::整数项(100)),
        ("值".to_owned(), 协议值::对象值(vec![])),
    ]);
    assert!(crate::槽编码::由协议值(&列表传对象, 0).is_err(), "列表的值必须是数组");

    // 未登记的标签照旧拒（不许因为「多了复合类型」就把兜底口放宽）。
    let 未登记项 = 协议值::对象值(vec![
        ("类型标签".to_owned(), 协议值::整数项(104)),
        ("值".to_owned(), 协议值::整数项(0)),
    ]);
    assert!(crate::槽编码::由协议值(&未登记项, 0).is_err(), "未登记标签必须拒");
}

/// 嵌套：`103` 里嵌 `100` —— 递归编解码要逐层对得上。
#[test]
fn 槽编码_嵌套结果结构往返() {
    let 内层列表 = 协议值::对象值(vec![
        ("类型标签".to_owned(), 协议值::整数项(100)),
        (
            "值".to_owned(),
            协议值::数组值(vec![
                协议值::对象值(vec![("类型标签".to_owned(), 协议值::整数项(1)), ("值".to_owned(), 协议值::整数项(11))]),
                协议值::对象值(vec![("类型标签".to_owned(), 协议值::整数项(1)), ("值".to_owned(), 协议值::整数项(22))]),
            ]),
        ),
    ]);
    let 外层项 = 协议值::对象值(vec![
        ("类型标签".to_owned(), 协议值::整数项(103)),
        (
            "值".to_owned(),
            协议值::对象值(vec![("明细".to_owned(), 内层列表)]),
        ),
    ]);
    let 来源 = crate::槽编码::由协议值(&外层项, 0).expect("嵌套形状合法");
    let 回读值 = crate::槽编码::到协议值(&来源.取槽());
    assert_eq!(回读值, 外层项, "嵌套结果结构必须逐层回到原样");
}


