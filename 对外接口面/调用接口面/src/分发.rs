//! 四个端点的分发 —— **一处分发，四条路，每条都是转调适配器**。
//!
//! 另有 `接口面形状.md` §七 的**旁路端点**（工具族：案例 · 扩展 · 导出 · 程序文本 ·
//! 菜单命令）**外加**生命周期族（就绪读数 · 卸载）与留痕：
//! 工具族**不转调适配器**，转调的是构建 / 验证工具链（见 `工具链.rs` 文件头）；
//! 生命周期族与留痕转调适配器的通知腿与留痕缓冲。HTTP 状态码的口径与四个端点**完全一样**
//! —— 业务失败一律 200 + `成功: false` + 真错误码（段位 9），只有「请求体形状不合法」才是 400。
//!
//! # 为什么 HTTP 状态码只有 400 / 404 / 405
//!
//! `接口面形状.md` §三：**失败不抛 HTTP 5xx**。HTTP 状态码在本面只表达一件事——
//! **请求本身合不合法**：
//!
//! | 码 | 什么时候 | 是谁的判定 |
//! |---|---|---|
//! | `200` | 请求合法（**业务失败也是 200**） | 业务判定在调度层，随 `成功: false` 回来 |
//! | `400` | 请求体不是合法 JSON · `值` 项形状不合法 · 编号不是十进制数 | **协议层** |
//! | `404` | 路径不在端点表里 · **静态托管根下没有这个件**（§五） | **协议层** |
//! | `405` | 路径在表里，方法不对 | **协议层** |
//!
//! 为什么业务失败不进状态码：失败是**可编程处理的数据**。塞进状态码就等于让调用方去解析
//! 协议层，而协议层不该承载业务 —— 调用方也就没法区分「网关坏了」与「这条能力现在不可用」。
//!
//! **静态托管（§五）也走 404 这一格**：请求 `/没有这个件` 与请求 `/没有这个端点` 是同一件事
//! —— 这个路径没有东西可交。两处都不编业务错误对象（那会伪造一个不存在的业务失败）。

use crate::常量::内容类型_JSON;
use crate::协议值::协议值;
use crate::路由::{拒绝, 端点};
use crate::请求;
use crate::响应;
use crate::工具响应;
use crate::网关::契约身份;
use crate::{留痕响应, 生命周期响应};
use std::path::Path;
use v1_adapter::适配器;

/// 一次应答：HTTP 状态码 + 内容类型 + 体（已序列化）。
///
/// **体是字节**（不是 `String`）：§五 的静态托管要原样交出前端自身的件
/// （`index.html` · `样式.css` · `*.js`），它们**不是 JSON**，而 §三 的四个端点一律 JSON。
/// 内容类型随体一起走，写响应那一处不再假定 JSON。
#[derive(Debug, Clone)]
pub struct 应答 {
    pub 状态: u16,
    pub 内容类型: &'static str,
    pub 体: Vec<u8>,
}

impl 应答 {
    /// 请求合法 ⇒ 200（**业务失败也走这里**）。
    pub fn 正常(待处理值: &协议值) -> Self {
        Self {
            状态: 200,
            内容类型: 内容类型_JSON,
            体: crate::协议写出::写协议值(待处理值).into_bytes(),
        }
    }

    /// 请求本身不合法 ⇒ 4xx，体里给一句可读说明（**没有业务错误对象**，
    /// 编一个 `码` 出来就是伪造业务数据）。
    pub fn 协议(状态: u16, 说明: &str) -> Self {
        Self {
            状态,
            内容类型: 内容类型_JSON,
            体: crate::协议写出::写协议值(&crate::错误形状::协议错误(说明)).into_bytes(),
        }
    }

    /// 静态件（`接口面形状.md` §五）：**原样交出**，内容类型随扩展名（`静态件.rs`）。
    pub fn 静态(静态件: crate::静态件::静态件) -> Self {
        Self {
            状态: 200,
            内容类型: 静态件.内容类型,
            体: 静态件.字节,
        }
    }
}

/// 一次请求的落点。**纯分发**：不取号、不校参数、不问配额，全在适配器与调度层。
///
/// `静态根` 是 §五 的托管目录（装配侧注入，见 `网关.rs` 的 `服务::托管静态根`）——
/// 只在这一个落点上用得到，故由调用方递进来，不在本模块存一份。
///
/// `工具根` 是 §七 工具族的**部署事实**（案例库 · 扩展根声明 · 外部 CLI 的所在；
/// 见 `网关.rs` 的 `服务::工具根`），同样由调用方递进来。
pub fn 处理(
    适配器: &适配器,
    契约身份: &契约身份,
    实际端口: u16,
    静态根: &Path,
    工具根: &Path,
    端点: 端点,
    请求体: Option<&协议值>,
) -> 应答 {
    match 端点 {
        端点::自描述根 => 应答::正常(&响应::自描述根(
            &契约身份.版本,
            契约身份.声明格式号,
            适配器,
            实际端口,
        )),
        端点::能力契约 { 编号 } => 应答::正常(&响应::能力契约(适配器, 编号)),
        端点::调用 => match 请求体 {
            None => 应答::协议(400, "POST /接口/调用 必须有请求体"),
            Some(体) => match 请求::解析调用(体) {
                Ok(请求) => 应答::正常(&响应::调用(适配器, &请求)),
                Err(错) => 应答::协议(400, &错.说明文()),
            },
        },
        端点::声明 => match 请求体 {
            // 只判协议层：体得是一个 JSON 对象（§四 冻结的请求形状就是对象）。
            // 再往下（类别 · 编号 · 正文 逐项校验）是**声明编写面**的活 ——
            // 在调用接口面里写一遍就是同一件事的第二套实现。
            None => 应答::协议(400, "POST /接口/声明 必须有请求体"),
            Some(协议值::对象(_)) => 应答::正常(&响应::声明未实现()),
            Some(_) => 应答::协议(400, "请求体必须是对象：{\"类别\":…,\"编号\":…,\"正文\":…}"),
        },
        // §五 的静态托管：托管根下没有这个件就是 404（**不列表、不重写**，见 `静态件.rs`）。
        端点::静态件 { 路径 } => match crate::静态件::取件(静态根, &路径) {
            Some(件) => 应答::静态(件),
            None => 应答::协议(
                404,
                &format!(
                    "静态托管根下没有这个件：{路径}。本面只托管前端自身的件（`接口面形状.md` §五），\
                     根下没有的路径一律 404；端点表见 GET /接口。"
                ),
            ),
        },
        // ── §七 工具族（新增旁路）────────────────────────────────────────────
        // 四个 POST 端点都**先判请求体形状**（⇒ 400），再交给工具响应组装 ——
        // 与 §三 的 `/接口/调用` 同一条分工（`请求.rs` 文件头）：业务失败回**真错误码**，
        // 只有「请求体形状不合法」才是 400。
        端点::案例清单 => 应答::正常(&工具响应::列案例(适配器, 工具根)),
        端点::扩展清单 => 应答::正常(&工具响应::列扩展(适配器, 工具根)),
        端点::案例跑 => 要体(请求体, "POST /接口/案例/跑", |体| {
            请求::解析案例标识(体).map(|标识| 工具响应::跑案例(适配器, 工具根, &标识))
        }),
        端点::导出 => 要体(请求体, "POST /接口/导出", |体| {
            请求::解析导出(体).map(|请求| 工具响应::导出(适配器, 工具根, &请求))
        }),
        端点::程序文本 => 要体(请求体, "POST /接口/程序文本", |体| {
            请求::解析程序文本(体).map(|请求| 工具响应::程序文本(适配器, 工具根, &请求))
        }),
        端点::菜单命令 => 要体(请求体, "POST /接口/菜单命令", |体| {
            请求::解析菜单命令(体).map(|编号| 工具响应::菜单命令(适配器, 工具根, &编号))
        }),
        // ── 生命周期族与留痕 ────────────────────────────────
        // 就绪/健康读数走生命周期正路（通知端点表），卸载发 `2001 卸载`。
        端点::生命周期读数 => 应答::正常(&生命周期响应::读数(适配器)),
        端点::生命周期卸载 => 要体(请求体, "POST /接口/生命周期", |体| {
            请求::解析卸载(体).map(|标识串| 生命周期响应::卸载(适配器, &标识串))
        }),
        端点::留痕 => 应答::正常(&留痕响应::取留痕(适配器)),
    }
}

/// 收体端点的一段固定流程：**体在不在 → 形状合不合法 → 交给业务**。
///
/// 四个旁路 POST 端点逐字重复这五行的形状与 §三 的 `/接口/调用` 完全一样；
/// 抽成一处是为了让「400 只有一种来源」这件事只有一处实现。
fn 要体(
    请求体: Option<&协议值>,
    端点名: &str,
   业务: impl FnOnce(&协议值) -> Result<协议值, String>,
) -> 应答 {
    match 请求体 {
        None => 应答::协议(400, &format!("{端点名} 必须有请求体")),
        Some(体) => match 业务(体) {
            Ok(值) => 应答::正常(&值),
            Err(说明) => 应答::协议(400, &说明),
        },
    }
}

/// 拒绝 → HTTP 状态码（**只表达请求合不合法**，见文件头）。
pub fn 拒绝状态码(拒绝: &拒绝) -> u16 {
    match 拒绝 {
        拒绝::路径不存在 => 404,
        拒绝::路径解码失败 | 拒绝::编号不是十进制数 => 400,
        拒绝::方法不许 { .. } => 405,
    }
}
