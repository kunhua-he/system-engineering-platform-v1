/// 第三问「执行保障是什么」：全网关同一口径。
///
/// 逐条对齐现有实现，不编一个抽象承诺：
/// - 软超时**不是强终止**：单项超时只记账报码（`契约声明/错误码表/0004.json` 的说明），
///   不杀执行方（强杀会破坏所有权单向）；
/// - 失败一律 HTTP 200 + `成功: false` + **真错误码**（段位 9 或 0），只有请求本体不合法才是 4xx；
/// - 每次调用留痕（`GET /接口/运维/留痕`）—— 应答里的 `追踪标识` 与留痕的 `追踪号` 是**同一个号**；
/// - 结果未知时不自动重放（`重试判据` 三键机器可判）。
pub const 四问_执行保障: &str = "软超时只报码不强杀 · 业务失败一律 HTTP 200 + 真错误码 · 每次调用留痕且应答带同一追踪标识 · 结果未知不自动重放（看 重试判据）";

/// 第四问「失败后下一步是什么」：全网关同一口径。
///
/// 三步依次判，每步都有机器字段，不靠猜：
/// 1. HTTP 4xx ⇒ 请求本身不合法（改请求体 / 路径，**不要重试**）；
/// 2. HTTP 200 且 `成功: false` ⇒ 看 `错误.码` 是哪一条，再看 `重试判据`：
///    `未进入扩展` 按原错误语义决定是否重试；`已进入扩展 + 结果确定` 按扩展回的错误处置；
///    `结果确定 = false`（结果未知）**不自动重放**，先查询这次调用的后果；
/// 3. `错误.已登记 = false` ⇒ 码未登记，是平台/扩展的一致性问题，报给维护方而不是重试。
