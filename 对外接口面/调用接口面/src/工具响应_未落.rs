/// `POST /接口/程序文本` → **一律 `9006 程序文本路径未定`**（读与写都一样）。
///
/// 为什么不是「实现掉它」：`项目文档/设计文档/程序文本格式.md` 只定了**格式**（§二：UTF-8 ·
/// 行式 · 4 空格缩进 · 名字与号分离）与**扩展名**（§三：`.程序文本`），
/// **没有定「编辑器里那份文本」存在哪个路径**。§三 那句话是「扩展名」不是「落点」。
///
/// **不猜路径**（9006 的说明）：猜出来的路径会让「读写成功」变成假绿 —— 写进一个没人读的位置，
/// 或读到一个不是那份文本的文件，两者都会报成功。故这里如实回执，说清缺的是哪一条裁决。
pub fn 程序文本(适配器: &适配器, 动作: &str) -> 协议值 {
    let 起 = Instant::now();
    失败(
        适配器,
        工具码::程序文本路径未定,
        Some(协议值::对象(vec![
            键文("动作", 动作),
            键文(
                "缺什么裁决",
                "「编辑器里那份文本」的落点：程序文本格式.md 只定了格式（§二）与扩展名（§三 .程序文本），\
                 没有定它存在哪个路径",
            ),
            键文(
                "为什么不能自愈",
                "猜一个路径会让「读写成功」变成假绿：写进一个没人读的位置、或读到一个不是那份文本的文件，\
                 两者都会报成功。要裁的是「程序文本落在哪」——是本仓的一个目录，还是每次由调用方自带路径",
            ),
            键文(
                "既有事实",
                "程序文本格式.md §三 定扩展名 .程序文本；测试验证/案例/<案例名>/输入.程序文本 是案例自带的输入\
                 （案例库的载体，不是编辑器的那份）",
            ),
        ])),
        &起,
    )
}

