//! 资源响应 —— `GET /接口/资源读数` 的对外形状。
//!
//! # 它答的是哪一问
//!
//! 发布验收（`八条必证.py::必证三_清理`）原先只能靠「调用成功 + owner/FD 快照」**推定**
//! 「没有泄漏」—— 推定不是证据。本端点把两件事变成**读数**：
//!
//! ```json
//! {"成功":true,"值":{"分配":{"存活分配计数":N,"存活字节数":M},
//!                   "资源":{"声明数":0,"已绑入口数":0,"状态":"未绑资源声明根（默认拒绝）"}}}
//! ```
//!
//! # 两个面各自的来源（**都不是本件另记的账**）
//!
//! - `分配`：`crate::分配读数` —— 本进程**真实的分配器调用**计数（`GlobalAlloc` 包一层），
//!   在**生产档**挂上（测试档那一处归 `边界测试.rs`，见该件文件头）。
//! - `资源`：**资源网关口**的读数。本部署若没配资源声明根，就是**默认拒绝**那一档：
//!   声明数 0、已绑入口 0 —— 如实报 0，不编数、不假装已接。
//!
//! # 为什么是旁路端点
//!
//! `接口面形状.md` §二 的四个端点是冻结项，本端点不进去；它按 §七 工具族 / 生命周期族 / 留痕
//! 同一条路**新增旁路**（`契约声明/冻结登记.json` 已登记），只进 `常量.rs::旁路端点表`。

use super::工具响应::造成功应答;
use crate::协议值::协议值;
use std::time::Instant;
use crate::分配读数::{读存活分配计数, 读存活字节数};
use v1_adapter::适配器;
use v1_resource_gateway::资源网关口;

/// `GET /接口/资源读数` → 分配读数 + 资源面读数。
pub fn 读数(关口: &资源网关口, 适配器: &适配器) -> 协议值 {
    let 区间起点 = Instant::now();
    let 分配 = 协议值::对象值(vec![
        (
            "存活分配计数".to_owned(),
            协议值::无符号值(读存活分配计数() as u64),
        ),
        (
            "存活字节数".to_owned(),
            协议值::无符号值(读存活字节数() as u64),
        ),
    ]);
    // 资源面读数：**从资源网关口现读真数**（声明数 / 已绑入口数），不编数、不假装已接。
    // 「已绑入口数」= 声明里绑上了黑盒体的份数 —— 按关口读侧摘要逐条数「已绑定入口 = 真」。
    let 声明数 = 关口.已声明资源数();
    let 已绑入口数 = 关口
        .已声明资源()
        .iter()
        .filter(|资源摘要行| 资源摘要行.已绑定入口)
        .count();
    let 资源 = 协议值::对象值(vec![
        ("声明数".to_owned(), 到号值(声明数)),
        ("已绑入口数".to_owned(), 到号值(已绑入口数)),
        ("状态".to_owned(), 协议值::文本值(取资源面状态(声明数, 已绑入口数))),
        // 已装载声明数：资源面与能力面同一次装载的读数（一个数两个面）。
        ("已装载声明数".to_owned(), 到号值(适配器.已装载声明数())),
    ]);
    造成功应答(
        协议值::对象值(vec![
            ("分配".to_owned(), 分配),
            ("资源".to_owned(), 资源),
        ]),
        &区间起点,
    )
}

/// 非负计数 → 协议无符号值。
fn 到号值(条数取值: usize) -> 协议值 {
    协议值::无符号值(条数取值 as u64)
}

/// 资源面状态文本：三档，互斥且穷尽（没配声明根 / 声明有了但一个入口都没绑 / 已就绪）。
///
/// 不把「已就绪」与「声明有、入口未绑」混作一档：后者调了会拿「入口未绑定」，
/// 是部署未做完（`资源网关口.md` §五 第 5 层），两件事必须当场分得清。
fn 取资源面状态(声明数: usize, 已绑入口数: usize) -> String {
    if 声明数 == 0 {
        return "未绑资源声明根（默认拒绝：任何资源调用都在「资源未声明」那一层被拒）".to_owned();
    }
    if 已绑入口数 == 0 {
        return format!("已声明 {声明数} 条、一个入口都没绑（调了会拿「入口未绑定」）");
    }
    format!("就绪：已声明 {声明数} 条 · 已绑入口 {已绑入口数} 条")
}
