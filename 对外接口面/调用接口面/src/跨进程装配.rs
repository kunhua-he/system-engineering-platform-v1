//! 跨进程装配 —— **由部署配置注入执行域**（冻结件 §四「生产启用」）。
//!
//! # 为什么配置住在部署侧、不住底座
//!
//! 「哪个扩展走跨进程、它的工作进程可执行在哪」是**部署事实**，不是契约事实 —— 与
//! `--声明根` / `--静态根` / `--工具根` 同一条约定（装配侧说了算，网关不替它猜）。
//! 故本件**一个扩展名都不写死**：所有标识串 / 版本 / 路径都从**配置文件**来，代码里零字面
//! （判据 ⑯ 扫的就是这个）。
//!
//! # 四条硬口径
//!
//! 1. **默认仍进程内**：没给 `--跨进程配置`，或某条目的工作进程路径为空 ⇒ 该扩展
//!    **走进程内**，绝不替它猜一个工作进程路径。
//! 2. **绑定已校验的扩展身份 + 制品版本 + 实际制品**：登记前逐条校 —— 标识串要在已装载
//!    声明里找得到、版本要逐段相等、制品路径要真实存在且落在那个扩展的**落点目录**里。
//!    三者任一不符 ⇒ **拒收并报因**，不登记。
//! 3. **不许普通调用请求指定启动程序**：启动程序只从本配置文件来，HTTP 调用路没有这个口
//!    （`网关.rs` 的调用分发一个字不改）。
//! 4. **装载 / 切换 / 卸载同一规则**：装载走 `适配器::追加装载` + 登记域；切换走
//!    `适配器::升级候选` + 换域；卸载走 `适配器::收回装载` + 注销域。三处共用本件，
//!    **不另造一套生命周期**。
//!
//! # 本件不持裸指针
//!
//! [`启用状态`] 里只有 `String` / `PathBuf` —— 不存 `&'static 平台信息`（它带裸指针、
//! **不是 `Send`/`Sync`**，存进 [`crate::服务`] 会让整个服务不能跨线程共享）。声明的校验
//! 一律**当场**做：声明由调用方在那一刻递进来（启动装配 / 装载 / 卸载各自有）。

