/// 校验**一条**部署条目并按需登记执行域。
///
/// 返回的 [`条目结局`] 就是「发布不发布」的判据：只有 [`条目结局::已登记`] 才发布。
/// **失败候选不替换旧版本、也不偷偷回退进程内** —— 本函数不改任何既有登记。
pub fn 校验并登记一条(
    适配器: &mut 适配器,
    配置: 进程池配置,
    明细条目: &跨进程条目,
    声明: &'static 平台信息,
    落点: &str,
) -> 条目结局 {
    // ① 没给工作进程路径 ⇒ 走进程内（**不猜**），不登记、不报错。
    if 明细条目.启动程序.is_empty() {
        return 条目结局::走进程内;
    }
    // ② 标识串要对得上（**已校验的扩展身份**）。
    if 取声明标识串(声明).as_deref() != Some(明细条目.标识串.as_str()) {
        return 条目结局::拒收("标识串与声明不符".to_owned());
    }
    // ③ 版本逐段相等（**已校验的制品版本**）。
    let 版本 = 声明.实现版本;
    if (版本.主版本, 版本.次版本号, 版本.构建) != 明细条目.版本 {
        return 条目结局::拒收(format!(
            "版本不符：声明 ({},{},{}) ≠ 配置 ({},{},{})",
            版本.主版本, 版本.次版本号, 版本.构建, 明细条目.版本.0, 明细条目.版本.1, 明细条目.版本.2
        ));
    }
    // ④ 制品真实存在、且落在该扩展的落点目录里（**实际制品**）。
    if let Err(拒收原因) = 校制品落点(&明细条目.制品路径, 落点) {
        return 条目结局::拒收(拒收原因);
    }
    // ⑤ 登记执行域（拉起进程走适配器那条腿，本件不碰进程）。
    //    登记成功才算「工作进程装载成功 + 初始化回执确认」—— 失败即拒收，**不发布**。
    if !适配器.有跨进程域() {
        适配器.开跨进程(配置);
    }
    let 域部署 = 域部署 {
        启动程序: 明细条目.启动程序.clone(),
        启动参数: 明细条目.启动参数.clone(),
    };
    match 适配器.登记跨进程域(声明, 域部署) {
        Ok(()) => 条目结局::已登记,
        Err(错误) => 条目结局::拒收(format!("登记执行域失败：{错误:?}")),
    }
}

/// 制品必须存在，且它的父目录就是那条扩展的落点目录（两侧都 canonicalize 后比）。
fn 校制品落点(制品路径: &Path, 落点: &str) -> Result<(), String> {
    let 构建制品 = 制品路径
        .canonicalize()
        .map_err(|错误| format!("制品路径取不到 {}：{错误}", 制品路径.display()))?;
    if !构建制品.is_file() {
        return Err(format!("制品不是文件：{}", 构建制品.display()));
    }
    let 落点目录 = Path::new(落点)
        .canonicalize()
        .map_err(|错误| format!("落点目录取不到 {落点}：{错误}"))?;
    if 构建制品.parent() != Some(落点目录.as_path()) {
        return Err(format!("制品不在它的落点目录里：{}", 构建制品.display()));
    }
    Ok(())
}

