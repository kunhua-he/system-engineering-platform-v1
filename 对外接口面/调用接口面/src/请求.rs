//! 请求形状 —— `POST /接口/调用` 的体怎么读成「编号 + 按行序的槽」。
//!
//! 冻结件 `接口面形状.md` §三：
//!
//! ```json
//! { "编号": 1105, "值": [ { "类型标签": 5, "值": "<base64 字节集>" } ] }
//! ```
//!
//! 三条读法（都是冻结件写死的，不是本文件的偏好）：
//!
//! 1. `值` 按契约 `参数表` 的**行序**对位；空位写 `{"类型标签":0,"值":0}`，**不许省略位次**
//!    （省略就是改行序）。
//! 2. 每个值都是**带类型标签的定长槽**。
//! 3. 文本 ⇒ JSON 字符串；字节集 ⇒ base64 字符串；**靠 `类型标签` 区分，不靠形状猜**。
//!
//! **网关不校验参数个数**：那是 `调用调度` 的判定（`参数个数不符` 是它的段位）。
//! 在这里再判一次就是第二套校验 —— 而且会和内核口径分叉。
//! `值` 缺席按**空表**读（JSON 里没有这个键就是没有项），空表照样交给调度去判。

use crate::协议值::协议值;
use crate::槽编码::{self, 槽源, 形状错误};

/// `POST /接口/调用` 的请求。
#[derive(Debug, Clone)]
pub struct 调用请求 {
    pub 编号: u32,
    /// 按契约行序排列的入参源数据。**顺序即契约**，本文件只做「不重排」。
    pub 值: Vec<槽源>,
}

/// 解析已通过 JSON 语法检查的请求体。
pub fn 解析调用(体: &协议值) -> Result<调用请求, 形状错误> {
    if !matches!(体, 协议值::对象(_)) {
        return Err(形状错误::新(
            None,
            "请求体必须是对象：{\"编号\":N,\"值\":[...]}",
        ));
    }
    let 编号 = 体
        .取("编号")
        .and_then(协议值::取无符号)
        .ok_or_else(|| 形状错误::新(None, "缺少 编号，或它不是非负整数"))?;
    let 编号 = u32::try_from(编号)
        .map_err(|_| 形状错误::新(None, "编号 超出 32 位，不是本平台的编号"))?;

    let mut 值 = Vec::new();
    if let Some(项表) = 体.取("值") {
        let 项表 = 项表
            .取数组()
            .ok_or_else(|| 形状错误::新(None, "值 必须是数组（每一项是一个带类型标签的槽）"))?;
        for (位次, 项) in 项表.iter().enumerate() {
            值.push(槽编码::由协议值(项, 位次)?);
        }
    }
    Ok(调用请求 { 编号, 值 })
}
