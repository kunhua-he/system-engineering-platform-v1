/// 正反成对：写一份 `.程序文本` 再读回来（裁决：真读 / 真写调用方自带路径）。
#[test]
fn 程序文本_写了再读回来() {
    let 根目录 = 临时根::新建("往返");
    let 服务 = 起服务带工具根(根目录.取路径());

    let 写应答 = 发请求(
        &服务,
        &交POST请求(
            "/接口/程序文本",
            "{\"动作\":\"写\",\"路径\":\"示例.程序文本\",\"正文\":\".版本 2\\n\"}",
        ),
    );
    let 数据 = 取成功数据(&写应答);
    assert_eq!(文本(&数据, "动作"), "写");
    assert_eq!(文本(&数据, "路径"), "示例.程序文本");

    let 读应答 = 发请求(
        &服务,
        &交POST请求("/接口/程序文本", "{\"动作\":\"读\",\"路径\":\"示例.程序文本\"}"),
    );
    let 数据 = 取成功数据(&读应答);
    assert_eq!(文本(&数据, "动作"), "读");
    assert_eq!(文本(&数据, "文本"), ".版本 2\n");
}
