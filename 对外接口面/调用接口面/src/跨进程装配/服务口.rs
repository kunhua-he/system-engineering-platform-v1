//! 跨进程装配 · 服务口 —— [`crate::服务`] 上那三个口的唯一实现。
//!
//! 从 `跨进程装配.rs` 拆出（单源 ≤ 400 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管**配置与校验**（读部署配置 · 逐条校验 · 登记结局），子件管**服务上的三个口**
//! （装配侧注入 · 验证面读数 · 生命周期动作取状态）。
//!
//! 子件能读父件的类型（`use super::{…}`），也直接 `impl crate::服务` —— 与
//! `跨进程体.rs` / `生命周期响应.rs` 同一处置（一个关注点一个件）。

use std::sync::{Arc, MutexGuard};

use v1_adapter::平台信息;

use crate::网关::服务;

use super::{跨进程部署, 条目结局, 启用状态};

impl 服务 {
    /// **由部署配置注入执行域**（冻结件 §四「生产启用」）。
    ///
    /// 在**共享出去之前**调（`&mut self`）：起服务时还没有并发调用，登记走写锁是安全的。
    /// 逐条校验（标识串 / 版本 / 制品路径三者一致）后登记；**登记不上的条目不发布**
    /// （既不替换旧版本，也不把它的调用悄悄改成进程内 —— 它本来就没被选上）。
    ///
    /// 返回逐条结局（装配侧打印）：已登记 · 走进程内 · 拒收（附原因）。
    /// **调用请求里没有指定启动程序的口** —— 启动程序只从这份部署配置来。
    pub fn 注入跨进程域(
        &mut self,
        部署: 跨进程部署,
        已装声明: &[(&'static 平台信息, String)],
    ) -> Vec<(String, 条目结局)> {
        // 卸载取声明要用的两个部署事实（与 `服务::后缀表` / `服务::缓存根目录` 同源）。
        let mut 状态 = Box::new(
            启用状态::创建(部署).装载依据(self.后缀表文本.clone(), self.缓存根目录.clone()),
        );
        let 结局表 = {
            let 适配器 =
                Arc::make_mut(self.适配器.get_mut().unwrap_or_else(|中毒| 中毒.into_inner()));
            let 结局表 = 状态.注入(适配器, 已装声明);
            for (标识串, 结局) in &结局表 {
                if matches!(结局, 条目结局::拒收(_)) {
                    for (声明, _) in 已装声明 {
                        if super::取声明标识串(声明).as_deref() == Some(标识串.as_str()) {
                            let _ = 适配器.击杀跨进程域(声明);
                            适配器.收回装载(声明);
                        }
                    }
                }
            }
            结局表
        };
        *self.跨进程.get_mut().unwrap_or_else(|中毒| 中毒.into_inner()) = Some(状态);
        结局表
    }

    /// 本实例开过跨进程域表没有（装配侧与验证面用）。
    pub fn 有跨进程域(&self) -> bool {
        self.适配器.read().unwrap_or_else(|中毒| 中毒.into_inner()).有跨进程域()
    }

    /// 生产启用状态（运行期装载 / 卸载按同一份配置登记 / 注销执行域）。
    ///
    /// 取 `&self` + 内部锁：调用方（`造应答`）此时已持适配器**写锁**，本锁只护登记，
    /// 不进任何调用关键路径。
    pub(crate) fn 取跨进程状态(&self) -> MutexGuard<'_, Option<Box<启用状态>>> {
        self.跨进程.lock().unwrap_or_else(|中毒| 中毒.into_inner())
    }
}
