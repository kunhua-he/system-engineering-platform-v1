//! 生命周期族端点 —— `GET /接口/生命周期`（就绪/健康读数）· `POST /接口/生命周期`（卸载）。
//!
//! # 为什么要有这一族
//!
//! 就绪/健康读数一直走 `GET /接口` 旁路，正路是生命周期通知号
//! （`2000 装载` / `2001 卸载`）。适配器的通知腿已就位（`通知口.rs`），缺的是
//! `对外接口面/调用接口面/` 里触发卸载的路由 —— 本文件补上它：
//!
//! ```text
//! GET  /接口/生命周期          →  就绪读数：已装载声明数 · 通知端点数 · 已注册标识串
//! POST /接口/生命周期  {动作:卸载, 标识串}  →  发 2001 卸载；扩展回 2015 即被拒（允许）
//! ```
//!
//! # 结局为什么不编一个错误码
//!
//! `派发结果` 的四种结局（`成功` / `请求延迟释放` / `失败` / `未命中`）**都在 `数据` 里**
//! 如实报出，顶层一律 `成功: true`：
//!
//! - `未命中` 按宪法第 6 条**不是错误**；
//! - `请求延迟释放` 是**允许被拒绝**（扩展还有在飞引用），不是失败；
//! - `失败` 是 fail-closed（扩展回了个不认识的结局），但它**不是某条能力的失败**，
//!   段位 9 里没有对应的码。**不许自造码**（`接口面形状.md` §七「不许自造码」）⇒
//!   如实放在 `数据.派发结果` 里让调用方判。要给它一个真错误码，得先在
//!   `契约声明/错误码表/` 登记一条（契约侧的活，不在本面）。
//!
//! 形状与共用件口径全在 `工具响应.rs` 的文件头，本件不另立一套（`成功` / `键文`）。

use super::工具响应::{成功, 键文};
use crate::协议值::协议值;
use std::time::Instant;
use v1_adapter::{派发结果, 适配器};

/// `GET /接口/生命周期` → 就绪/健康读数。
///
/// 读数取自**生命周期那本账**（通知端点表）与已装载声明表，不是另存一份健康表：
/// 端点表就是「哪些扩展收得到生命周期通知」的唯一事实源。
pub fn 读数(适配器: &适配器) -> 协议值 {
    let 区间起点 = Instant::now();
    let 标识串: Vec<协议值> = 适配器
        .通知端点标识串()
        .into_iter()
        .map(协议值::文本)
        .collect();
    成功(
        协议值::对象(vec![
            (
                "已装载声明数".to_owned(),
                协议值::无符号(适配器.已装载声明数() as u64),
            ),
            (
                "通知端点数".to_owned(),
                协议值::无符号(u64::from(适配器.通知端点数())),
            ),
            ("已注册标识串".to_owned(), 协议值::数组(标识串)),
        ]),
        &区间起点,
    )
}

/// `POST /接口/生命周期`（`动作 = 卸载`）→ 触发卸载并如实报结局（见文件头）。
pub fn 卸载(适配器: &适配器, 标识串: &str) -> 协议值 {
    let 区间起点 = Instant::now();
    let 结局 = 适配器.请求卸载按标识(标识串);
    成功(
        协议值::对象(vec![
            键文("标识串", 标识串),
            键文("派发结果", 结局名(结局)),
            (
                "通知端点数".to_owned(),
                协议值::无符号(u64::from(适配器.通知端点数())),
            ),
        ]),
        &区间起点,
    )
}

/// `派发结果` → 可读名（契约 `通知返回` 与 `派发结果` 的结局名逐字）。
fn 结局名(结局: 派发结果) -> &'static str {
    match 结局 {
        派发结果::成功 => "成功",
        派发结果::请求延迟释放 => "请求延迟释放",
        派发结果::失败 => "失败",
        派发结果::未命中 => "未命中",
    }
}
