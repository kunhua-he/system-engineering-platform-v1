//! 生命周期族端点 —— `GET /接口/生命周期`（就绪/健康读数）· `POST /接口/生命周期`（卸载）。
//!
//! # 为什么要有这一族
//!
//! 就绪/健康读数一直走 `GET /接口` 旁路，正路是生命周期通知号
//! （`2000 装载` / `2001 卸载`）。适配器的通知腿已就位（`通知口.rs`），缺的是
//! `对外接口面/调用接口面/` 里触发卸载的路由 —— 本文件补上它：
//!
//! ```text
//! GET  /接口/生命周期          →  就绪读数：已装载声明数 · 通知端点数 · 已注册标识串
//! POST /接口/生命周期  {动作:装载}          →  重扫扩展根，对新候选 dlopen + 追加装载（不重启）
//! POST /接口/生命周期  {动作:卸载, 标识串}  →  发 2001 卸载；扩展回 2015 即被拒（允许）
//! ```
//!
//! # 结局为什么不编一个错误码
//!
//! `派发结果` 的四种结局（`成功` / `请求延迟释放` / `失败` / `未命中`）**都在 `数据` 里**
//! 如实报出，顶层一律 `成功: true`：
//!
//! - `未命中` 按宪法第 6 条**不是错误**；
//! - `请求延迟释放` 是**允许被拒绝**（扩展还有在飞引用），不是失败；
//! - `失败` 是 fail-closed（扩展回了个不认识的结局），但它**不是某条能力的失败**，
//!   段位 9 里没有对应的码。**不许自造码**（`接口面形状.md` §七「不许自造码」）⇒
//!   如实放在 `数据.派发结果` 里让调用方判。要给它一个真错误码，得先在
//!   `契约声明/错误码表/` 登记一条（契约侧的活，不在本面）。
//!
//! 形状与共用件口径全在 `工具响应.rs` 的文件头，本件不另立一套（`造成功应答` / `造键文对`）。

use super::工具响应::{造成功应答, 造键文对};
use crate::协议值::协议值;
use crate::依赖序装载::{按依赖序装载, 试装结局};
use crate::扫扩展根;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};
use v1_adapter::{派发结果, 适配器};

/// 卸载时**等在途执行引用归零**的上限（毫秒）。**≤ 五秒硬顶**。
const 卸载等待毫秒: u64 = 2000;

/// 等到本实例在途执行引用归零（**有界**：超过卸载等待上限即返回，不无限等）。
///
/// 为什么必须等：在途调用持旧路由快照，若此刻杀执行域，在途调用会连带被杀（报 `0034`）。
/// 等待有界，超时如实返回（调用方按现状报读数）—— 不无限阻塞网关工作线程。
#[cfg(unix)]
fn 等在途归零(适配器: &适配器) {
    let 截止 = Instant::now() + Duration::from_millis(卸载等待毫秒);
    while 适配器.在途执行数() > 0 && Instant::now() < 截止 {
        std::thread::sleep(Duration::from_millis(1));
    }
}

/// `GET /接口/生命周期` → 就绪/健康读数。
///
/// 读数取自**生命周期那本账**（通知端点表）与已装载声明表，不是另存一份健康表：
/// 端点表就是「哪些扩展收得到生命周期通知」的唯一事实源。
pub fn 读数(适配器: &适配器) -> 协议值 {
    let 区间起点 = Instant::now();
    let 本扩展标识串: Vec<协议值> = 适配器
        .通知端点标识串()
        .into_iter()
        .map(协议值::文本值)
        .collect();
    造成功应答(
        协议值::对象值(vec![
            (
                "已装载声明数".to_owned(),
                协议值::无符号值(适配器.已装载声明数() as u64),
            ),
            (
                "通知端点数".to_owned(),
                协议值::无符号值(u64::from(适配器.通知端点数())),
            ),
            ("已注册标识串".to_owned(), 协议值::数组值(本扩展标识串)),
        ]),
        &区间起点,
    )
}

/// `POST /接口/生命周期`（`动作 = 卸载`）→ 触发卸载并如实报结局（见文件头）。
///
/// 取 `&mut 适配器`：卸载是**完整状态转换**（摘通知端点 + 收回路由 + 注销台账身份，见
/// `适配器::请求卸载按标识`）⇒ 调用方（网关的 `RwLock`）必须持**写锁**，与 `装载` 对称。
///
/// `启用状态` = 跨进程生产启用状态（`None` = 全部走进程内）。**卸载即注销执行域**：
/// 与装载对称、判据同源（`跨进程装配::启用状态::卸载注销`），不另造一套生命周期。
/// 声明由登记账里记的**落点目录**现取（同一个装载器 ⇒ 拿到的是同一份声明）。
#[cfg(unix)]
pub fn 卸载扩展(
    适配器: &mut 适配器,
    本扩展标识串: &str,
    启用状态: Option<&mut crate::跨进程装配::启用状态>,
) -> 协议值 {
    let 区间起点 = Instant::now();
    // ① **先 2001 协商**（不杀域）：扩展可回 `2015` 请求延迟释放。逻辑卸载（摘通知端点 +
    //    收回路由 + 注销台账身份）在**成功**时由这一步完成 —— 但**物理回收（杀域）一律后置**。
    let 首结局 = 适配器.请求卸载按标识(本扩展标识串);
    let mut 结局 = 首结局;
    // ② 被延迟释放，或本实例还有在途执行引用 ⇒ **等在途归零**再往下：在途调用持旧快照，
    //    此刻杀域会把在途调用连带杀死（报 0034），`2001/2015` 的协商也就成了空话。
    if 结局 == 派发结果::请求延迟释放 || 适配器.在途执行数() > 0 {
        等在途归零(适配器);
        // ③ 引用清零后**复核**（发 2003）—— 只有初次请求被延迟释放才需要复核。
        if 首结局 == 派发结果::请求延迟释放 {
            结局 = 适配器.延迟释放协商按标识(本扩展标识串);
        }
    }
    // ④ **成功才杀域**（一律后置）+ 摘登记账：按登记账里的落点、用同一个装载器取回声明。
    let mut 物理回收 = false;
    if 结局 == 派发结果::成功
        && let Some(状态) = 启用状态
    {
        物理回收 = 状态.卸载注销(适配器, 本扩展标识串);
    }
    造成功应答(
        协议值::对象值(vec![
            造键文对("标识串", 本扩展标识串),
            造键文对("派发结果", 结局名(结局)),
            (
                "逻辑卸载".to_owned(),
                协议值::无符号值(u64::from(结局 == 派发结果::成功)),
            ),
            (
                "物理回收".to_owned(),
                协议值::无符号值(u64::from(物理回收)),
            ),
            (
                "通知端点数".to_owned(),
                协议值::无符号值(u64::from(适配器.通知端点数())),
            ),
            (
                "已装载声明数".to_owned(),
                协议值::无符号值(适配器.已装载声明数() as u64),
            ),
        ]),
        &区间起点,
    )
}

/// `POST /接口/生命周期`（`动作 = 装载`）→ 重扫扩展根、对**新**候选 `追加装载`（台账 237）。
///
/// **不重启网关**：只对**已存在**的适配器追加（[`适配器::追加装载`] 取 `&mut`，调用方持写锁），
/// **不重建** —— 重建会清掉配额账本与调用留痕。
///
/// **拓扑保证与启动装配等价**（台账 C04）：候选按依赖序**多趟**试装，与
/// `examples/启动网关/装配.rs` 同读 `crate::依赖序装载` 那一份 —— 依赖者排在依赖者之前时，
/// 本趟缺依赖、下趟依赖者已装上即能装。缺依赖不再当成「一次定论的剔除」。
///
/// 结局一律顶层 `成功: true`：新候选一个都没有 ⇒ **未命中不是失败**（照卸载的既有口径）；
/// 单个候选取接缝 / 追加装载失败 ⇒ 落「剔除」如实报出（不静默吞因、不整体失败）。
///
/// `声明根` 与 `源文本`（后缀表文本）都是装配侧注入的部署事实（`服务::声明根` /
/// `服务::后缀表`）；没注入就 fail-closed 指路。`缓存根目录` 不给就用适配器的默认
/// （运行数据根的缓存类）—— 与两者同一条约定：不退回源码树、不退回 `/tmp`。
///
/// `启用状态` = 跨进程生产启用状态（`None` = 全部走进程内）。**装载 / 切换按同一份判据
/// 登记执行域**：只有登记成功（工作进程装载成功 + 初始化回执确认）才算发布；登记不上 ⇒
/// 该候选**不发布**（既不替换旧版本，也不回退进程内 —— 见 `跨进程装配::校验并登记一条`）。
#[cfg(unix)]
pub fn 装载(
    适配器: &mut 适配器,
    声明根: Option<&Path>,
    源文本: Option<&str>,
    缓存根目录: Option<&Path>,
    mut 启用状态: Option<&mut crate::跨进程装配::启用状态>,
) -> 协议值 {
    let 区间起点 = Instant::now();
    let Some(声明根) = 声明根 else {
        return 造成功应答(
            协议值::对象值(vec![
                造键文对("动作", "装载"),
                (
                    "说明".to_owned(),
                    协议值::文本值(
                        "声明根未注入：服务没拿到扩展根声明路径，无法重扫。装配侧请调 \
                         服务::声明根（examples/启动网关 注入 --声明根）。"
                            .to_owned(),
                    ),
                ),
            ]),
            &区间起点,
        );
    };
    let Some(源文本) = 源文本 else {
        return 造成功应答(
            协议值::对象值(vec![
                造键文对("动作", "装载"),
                (
                    "说明".to_owned(),
                    协议值::文本值(
                        "后缀表未注入：没拿到 `扩展装载/后缀表.json` 的文本，无法判候选。"
                            .to_owned(),
                    ),
                ),
            ]),
            &区间起点,
        );
    };
    let 后缀表 = match 扫扩展根::读后缀表(源文本) {
        Ok(后缀表) => 后缀表,
        Err(说明文字) => {
            return 造成功应答(
                协议值::对象值(vec![造键文对("动作", "装载"), 造键文对("说明", &说明文字)]),
                &区间起点,
            );
        }
    };
    // 解包物落点：注入的优先；没注入就用适配器的默认（运行数据根的缓存类）。
    // 解析不出根 ⇒ fail-closed 指路（不许退回源码树 / `/tmp`）。
    let 缓存根目录 = match 缓存根目录.map(PathBuf::from).or_else(v1_adapter::装载件缓存::默认缓存根目录) {
        Some(缓存根目录) => 缓存根目录,
        None => {
            return 造成功应答(
                协议值::对象值(vec![
                    造键文对("动作", "装载"),
                    (
                        "说明".to_owned(),
                        协议值::文本值(
                            "解析不出运行数据根：解包物无处可落（不退回源码树 / `/tmp`）。\
                             装配侧请调 服务::缓存根目录 注入落点。"
                                .to_owned(),
                        ),
                    ),
                ]),
                &区间起点,
            );
        }
    };
    let 文本值 = match fs::read_to_string(声明根) {
        Ok(文本值) => 文本值,
        Err(错误) => {
            return 造成功应答(
                协议值::对象值(vec![
                    造键文对("动作", "装载"),
                    造键文对("说明", &format!("读不到扩展根声明 {}：{错误}", 声明根.display())),
                ]),
                &区间起点,
            );
        }
    };
    let 扫描 = match 扫扩展根::读声明根(&文本值) {
        Ok(扫描) => 扫描,
        Err(说明文字) => {
            return 造成功应答(
                协议值::对象值(vec![造键文对("动作", "装载"), 造键文对("说明", &说明文字)]),
                &区间起点,
            );
        }
    };
    let mut 装上: Vec<协议值> = Vec::new();
    let mut 切换: Vec<协议值> = Vec::new();
    let mut 已在: Vec<协议值> = Vec::new();
    let mut 剔除: Vec<协议值> = Vec::new();
    // 取到接缝的候选：**按依赖序多趟试装**（台账 C04）—— 与启动装配
    // （`examples/启动网关/装配.rs`）同读 `crate::依赖序装载` 那一份。
    // **两路的拓扑保证必须等价**：同一份扩展根，装配期装得上、热装载也得装得上
    // （依赖者排在依赖者之前时，本趟缺依赖、下趟依赖者已装上即能装）。
    let mut 待装候选表: Vec<(&'static v1_adapter::平台信息, String)> = Vec::new();
    for 扩展根目录 in &扫描.目录s {
        if !扩展根目录.is_dir() {
            continue;
        }
        for 子目录项 in 扫扩展根::列子目录(扩展根目录) {
            let 落点 = 子目录项.display().to_string();
            match 扫扩展根::取扩展声明(&子目录项, &后缀表, &缓存根目录) {
                Err(失败原因) => 剔除.push(剔除条(&落点, &失败原因)),
                Ok(声明) => 待装候选表.push((声明, 落点)),
            }
        }
    }
    let 依赖序结果 = 按依赖序装载(
        待装候选表,
        &mut |声明, 落点| {
            // 已在表里 ⇒ 看是不是**同身份新版**：同身份同版本 = 已在（幂等跳过）；
            // 同身份新版本 = **版本切换**。
            let 旧版本 = 适配器.找同身份声明(声明).map(|旧声明| 旧声明.实现版本);
            if 旧版本 == Some(声明.实现版本) {
                return 试装结局::已在;
            }
            // **候选门**：先按部署配置登记执行域（拉起工作进程 + 初始化回执确认）。
            // 登记不上 ⇒ 候选**不发布** —— 既不替换旧版本，也不回退进程内。
            if let Some(状态) = 启用状态.as_deref_mut() {
                if let crate::跨进程装配::条目结局::拒收(原因) = 状态.装载登记(适配器, 声明, 落点) {
                    return 试装结局::硬失败(format!("跨进程候选未发布：{原因}"));
                }
            }
            match 旧版本 {
                // 同身份新版 ⇒ `适配器::升级装载` 那条路（先摘旧身份、再装新声明）。
                Some(_) => {
                    // 旧版声明：升级后它已不在路由里，但指针仍 `'static`，可算旧域标识。
                    let 旧声明 = 适配器.找同身份声明(声明);
                    match 适配器.升级装载(声明) {
                        Ok(()) => {
                            // **切换成功**：回收旧版执行域（杀进程组 + 摘域格 + 摘部署表）。
                            let 物理回收 = 旧声明
                                .map(|旧声明| 适配器.移除跨进程域(旧声明))
                                .unwrap_or(false);
                            试装结局::切换 { 物理回收 }
                        }
                        Err(错误) => {
                            // **切换失败回滚新域**：候选未发布 ⇒ 把新域登记撤掉（否则孤儿域）。
                            let 物理回收 = 适配器.移除跨进程域(声明);
                            试装结局::硬失败(format!(
                                "{错误:?}（已回滚新域：物理回收={物理回收}）"
                            ))
                        }
                    }
                }
                None => match 适配器.追加装载(声明) {
                    Ok(()) => 试装结局::装上,
                    // **缺依赖 ⇒ 延后一趟**（不是硬失败）：多趟才等得来依赖。
                    // 判据同源：装载入口的判定 ⑤ 回 `载入错误::依赖缺失`。
                    Err(v1_adapter::装载失败::载入失败(v1_adapter::载入错误::依赖缺失)) => {
                        试装结局::缺依赖
                    }
                    Err(错误) => 试装结局::硬失败(format!("{错误:?}")),
                },
            }
        },
        // 整趟零进展的残留：真缺依赖（不在扩展根里 / 名字写错）⇒ 按缺依赖如实报出。
        &format!("{:?}", v1_adapter::装载失败::载入失败(v1_adapter::载入错误::依赖缺失)),
    );
    for 落点 in 依赖序结果.装上 {
        装上.push(协议值::文本值(落点));
    }
    for (落点, 物理回收) in 依赖序结果.切换 {
        切换.push(切换条(&落点, 物理回收));
    }
    for 落点 in 依赖序结果.已在 {
        已在.push(协议值::文本值(落点));
    }
    for (落点, 失败原因) in 依赖序结果.剔除 {
        剔除.push(剔除条(&落点, &失败原因));
    }
    let 扫到 = (装上.len() + 切换.len() + 已在.len() + 剔除.len()) as u64;
    造成功应答(
        协议值::对象值(vec![
            造键文对("动作", "装载"),
            ("扫到".to_owned(), 协议值::无符号值(扫到)),
            ("装上".to_owned(), 协议值::数组值(装上)),
            ("切换".to_owned(), 协议值::数组值(切换)),
            ("已在".to_owned(), 协议值::数组值(已在)),
            ("剔除".to_owned(), 协议值::数组值(剔除)),
        ]),
        &区间起点,
    )
}

/// 一条剔除记录：`{落点, 原因}`（不静默吞因）。
fn 剔除条(落点: &str, 失败原因: &str) -> 协议值 {
    协议值::对象值(vec![
        ("落点".to_owned(), 协议值::文本值(落点.to_owned())),
        ("原因".to_owned(), 协议值::文本值(失败原因.to_owned())),
    ])
}

/// 一条切换记录：`{落点, 物理回收}` —— 逻辑卸载（换路由）与物理回收（杀旧域）分别出读数。
fn 切换条(落点: &str, 物理回收: bool) -> 协议值 {
    协议值::对象值(vec![
        ("落点".to_owned(), 协议值::文本值(落点.to_owned())),
        (
            "物理回收".to_owned(),
            if 物理回收 { 协议值::真值 } else { 协议值::假值 },
        ),
    ])
}

/// `派发结果` → 可读名（契约 `通知返回` 与 `派发结果` 的结局名逐字）。
fn 结局名(结局: 派发结果) -> &'static str {
    match 结局 {
        派发结果::成功 => "成功",
        派发结果::请求延迟释放 => "请求延迟释放",
        派发结果::失败 => "失败",
        派发结果::未命中 => "未命中",
    }
}
