//! 生命周期族端点 —— `GET /接口/生命周期`（就绪/健康读数）· `POST /接口/生命周期`（卸载）。
//!
//! # 为什么要有这一族
//!
//! 就绪/健康读数一直走 `GET /接口` 旁路，正路是生命周期通知号
//! （`2000 装载` / `2001 卸载`）。适配器的通知腿已就位（`通知口.rs`），缺的是
//! `对外接口面/调用接口面/` 里触发卸载的路由 —— 本文件补上它：
//!
//! ```text
//! GET  /接口/生命周期          →  就绪读数：已装载声明数 · 通知端点数 · 已注册标识串
//! POST /接口/生命周期  {动作:装载}          →  重扫扩展根，对新候选 dlopen + 追加装载（不重启）
//! POST /接口/生命周期  {动作:卸载, 标识串}  →  发 2001 卸载；扩展回 2015 即被拒（允许）
//! ```
//!
//! # 结局为什么不编一个错误码
//!
//! `派发结果` 的四种结局（`成功` / `请求延迟释放` / `失败` / `未命中`）**都在 `数据` 里**
//! 如实报出，顶层一律 `成功: true`：
//!
//! - `未命中` 按宪法第 6 条**不是错误**；
//! - `请求延迟释放` 是**允许被拒绝**（扩展还有在飞引用），不是失败；
//! - `失败` 是 fail-closed（扩展回了个不认识的结局），但它**不是某条能力的失败**，
//!   段位 9 里没有对应的码。**不许自造码**（`接口面形状.md` §七「不许自造码」）⇒
//!   如实放在 `数据.派发结果` 里让调用方判。要给它一个真错误码，得先在
//!   `契约声明/错误码表/` 登记一条（契约侧的活，不在本面）。
//!
//! 形状与共用件口径全在 `工具响应.rs` 的文件头，本件不另立一套（`成功` / `键文`）。

use super::工具响应::{成功, 键文};
use crate::协议值::协议值;
use crate::扫扩展根;
use std::fs;
use std::path::Path;
use std::time::Instant;
use v1_adapter::{派发结果, 适配器};

/// `GET /接口/生命周期` → 就绪/健康读数。
///
/// 读数取自**生命周期那本账**（通知端点表）与已装载声明表，不是另存一份健康表：
/// 端点表就是「哪些扩展收得到生命周期通知」的唯一事实源。
pub fn 读数(适配器: &适配器) -> 协议值 {
    let 区间起点 = Instant::now();
    let 标识串: Vec<协议值> = 适配器
        .通知端点标识串()
        .into_iter()
        .map(协议值::文本)
        .collect();
    成功(
        协议值::对象(vec![
            (
                "已装载声明数".to_owned(),
                协议值::无符号(适配器.已装载声明数() as u64),
            ),
            (
                "通知端点数".to_owned(),
                协议值::无符号(u64::from(适配器.通知端点数())),
            ),
            ("已注册标识串".to_owned(), 协议值::数组(标识串)),
        ]),
        &区间起点,
    )
}

/// `POST /接口/生命周期`（`动作 = 卸载`）→ 触发卸载并如实报结局（见文件头）。
pub fn 卸载(适配器: &适配器, 标识串: &str) -> 协议值 {
    let 区间起点 = Instant::now();
    let 结局 = 适配器.请求卸载按标识(标识串);
    成功(
        协议值::对象(vec![
            键文("标识串", 标识串),
            键文("派发结果", 结局名(结局)),
            (
                "通知端点数".to_owned(),
                协议值::无符号(u64::from(适配器.通知端点数())),
            ),
        ]),
        &区间起点,
    )
}

/// `POST /接口/生命周期`（`动作 = 装载`）→ 重扫扩展根、对**新**候选 `追加装载`（台账 237）。
///
/// **不重启网关**：只对**已存在**的适配器追加（[`适配器::追加装载`] 取 `&mut`，调用方持写锁），
/// **不重建** —— 重建会清掉配额账本与调用留痕。
///
/// 结局一律顶层 `成功: true`：新候选一个都没有 ⇒ **未命中不是失败**（照卸载的既有口径）；
/// 单个候选取接缝 / 追加装载失败 ⇒ 落「剔除」如实报出（不静默吞因、不整体失败）。
///
/// `声明根` 是装配侧注入的重扫落点（`服务::声明根`）；没注入就 fail-closed 指路。
pub fn 装载(适配器: &mut 适配器, 声明根: Option<&Path>) -> 协议值 {
    let 区间起点 = Instant::now();
    let Some(声明根) = 声明根 else {
        return 成功(
            协议值::对象(vec![
                键文("动作", "装载"),
                (
                    "说明".to_owned(),
                    协议值::文本(
                        "声明根未注入：服务没拿到扩展根声明路径，无法重扫。装配侧请调 \
                         服务::声明根（examples/启动网关 注入 --声明根）。"
                            .to_owned(),
                    ),
                ),
            ]),
            &区间起点,
        );
    };
    let 文本 = match fs::read_to_string(声明根) {
        Ok(文本) => 文本,
        Err(错误) => {
            return 成功(
                协议值::对象(vec![
                    键文("动作", "装载"),
                    键文("说明", &format!("读不到扩展根声明 {}：{错误}", 声明根.display())),
                ]),
                &区间起点,
            );
        }
    };
    let 扫描 = match 扫扩展根::读声明根(&文本) {
        Ok(扫描) => 扫描,
        Err(说明) => {
            return 成功(
                协议值::对象(vec![键文("动作", "装载"), 键文("说明", &说明)]),
                &区间起点,
            );
        }
    };
    let mut 装上: Vec<协议值> = Vec::new();
    let mut 已在: Vec<协议值> = Vec::new();
    let mut 剔除: Vec<协议值> = Vec::new();
    for 目录 in &扫描.目录s {
        if !目录.is_dir() {
            continue;
        }
        for 子目录项 in 扫扩展根::子目录(目录) {
            let 落点 = 子目录项.display().to_string();
            match 扫扩展根::取扩展声明(&子目录项) {
                Err(原因) => 剔除.push(剔除条(&落点, &原因)),
                Ok(声明) => {
                    // 已在台账里 ⇒ 跳过（幂等）：不重复载入，也不报成失败。
                    if 适配器.已装载标识(声明) {
                        已在.push(协议值::文本(落点));
                        continue;
                    }
                    match 适配器.追加装载(声明) {
                        Ok(()) => 装上.push(协议值::文本(落点)),
                        Err(错误) => 剔除.push(剔除条(&落点, &format!("{错误:?}"))),
                    }
                }
            }
        }
    }
    let 扫到 = (装上.len() + 已在.len() + 剔除.len()) as u64;
    成功(
        协议值::对象(vec![
            键文("动作", "装载"),
            ("扫到".to_owned(), 协议值::无符号(扫到)),
            ("装上".to_owned(), 协议值::数组(装上)),
            ("已在".to_owned(), 协议值::数组(已在)),
            ("剔除".to_owned(), 协议值::数组(剔除)),
        ]),
        &区间起点,
    )
}

/// 一条剔除记录：`{落点, 原因}`（不静默吞因）。
fn 剔除条(落点: &str, 原因: &str) -> 协议值 {
    协议值::对象(vec![
        ("落点".to_owned(), 协议值::文本(落点.to_owned())),
        ("原因".to_owned(), 协议值::文本(原因.to_owned())),
    ])
}

/// `派发结果` → 可读名（契约 `通知返回` 与 `派发结果` 的结局名逐字）。
fn 结局名(结局: 派发结果) -> &'static str {
    match 结局 {
        派发结果::成功 => "成功",
        派发结果::请求延迟释放 => "请求延迟释放",
        派发结果::失败 => "失败",
        派发结果::未命中 => "未命中",
    }
}
