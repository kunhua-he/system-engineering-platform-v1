/// 卸载时**等在途执行引用归零**的上限（毫秒）。**≤ 五秒硬顶**。
const 卸载等待毫秒: u64 = 2000;

/// 等到本实例在途执行引用归零（**有界**：超过卸载等待上限即返回，不无限等）。
///
/// 为什么必须等：在途调用持旧路由快照，若此刻杀执行域，在途调用会连带被杀（报 `0034`）。
/// 等待有界，超时如实返回（调用方按现状报读数）—— 不无限阻塞网关工作线程。
#[cfg(unix)]
fn 等在途归零(适配器: &适配器) {
    let 截止 = Instant::now() + Duration::from_millis(卸载等待毫秒);
    while 适配器.在途执行数() > 0 && Instant::now() < 截止 {
        std::thread::sleep(Duration::from_millis(1));
    }
}

/// `GET /接口/生命周期` → 就绪/健康读数。
///
/// 读数取自**生命周期那本账**（通知端点表）与已装载声明表，不是另存一份健康表：
/// 端点表就是「哪些扩展收得到生命周期通知」的唯一事实源。
pub fn 读数(适配器: &适配器) -> 协议值 {
    let 区间起点 = Instant::now();
    let 本扩展标识串: Vec<协议值> = 适配器
        .通知端点标识串()
        .into_iter()
        .map(协议值::文本值)
        .collect();
    // §32.2：装载成功 ≠ 目标可用。就绪读数的真承重点在**逐份声明**：装的是哪一版、
    // 占哪几段号、号段内有没有号真可寻址。数据只从适配器现读（不另存一份表）。
    let 已可寻址号: Vec<u32> = 适配器.能力清单().iter().map(|能力摘要项| 能力摘要项.编号).collect();
    let 逐份就绪: Vec<协议值> = 适配器
        .声明就绪表()
        .into_iter()
        .map(|就绪读数| 声明就绪项(&就绪读数, &已可寻址号))
        .collect();
    造成功应答(
        协议值::对象值(vec![
            (
                "已装载声明数".to_owned(),
                协议值::无符号值(适配器.已装载声明数() as u64),
            ),
            (
                "通知端点数".to_owned(),
                协议值::无符号值(u64::from(适配器.通知端点数())),
            ),
            ("已注册标识串".to_owned(), 协议值::数组值(本扩展标识串)),
            // 旁路字段（§32.2 就绪判定 + §22.4 装载成功≠目标可用）：
            // 逐份声明的身份/版本/号段，带「这份到底可不可用」的机器可判位。
            ("逐份就绪".to_owned(), 协议值::数组值(逐份就绪)),
            ("跨进程登记数".to_owned(), 协议值::无符号值(适配器.跨进程登记数() as u64)),
            ("跨进程运行数".to_owned(), 协议值::无符号值(适配器.跨进程运行数() as u64)),
            // 旁路字段（§22.4 五级区分）：本地自检 ≠ 构建 ≠ 准入 ≠ 就绪 ≠ 调用成功。
            ("判定层级".to_owned(), 判定层级(适配器)),
            // 旁路字段（方案 §27 十二类接入回执）：小事也必须交代清楚 ——
            // 逐类给「已判 · 说明 · 证据口」，不把「本面判不了」当成真或假。
            ("接入回执".to_owned(), 接入回执(适配器, &已可寻址号)),
        ]),
        &区间起点,
    )
}

/// 一份声明的就绪读数 → JSON：身份（标识串 + 版本三元组）· 能力号段 · `是否可用` 位。
///
/// `是否可用` 取**一条不会假报的判据**（照 `工具响应_扩展.rs` 已用过的那条）：本份声明的
/// 能力号段里有没有号真出现在**当场**的能力清单里。号段为空（技能 / 无命令的模块）⇒
/// 本面无从判它装没装，如实报 `无号段无从判` 第三个值，**不编 false**
/// （§32.4：能力不存在与暂时未就绪要分得开）。
fn 声明就绪项(就绪读数: &v1_adapter::声明就绪, 已可寻址号: &[u32]) -> 协议值 {
    let 号段内可寻址号数: usize = 就绪读数
        .能力号段
        .iter()
        .map(|号段项: &[u32; 2]| {
            已可寻址号
                .iter()
                .filter(|编号| **编号 >= 号段项[0] && **编号 <= 号段项[1])
                .count()
        })
        .sum();
    let (是否可用, 就绪判据) = if 就绪读数.能力号段.is_empty() {
        (false, "无号段无从判")
    } else if 号段内可寻址号数 == 0 {
        (false, "号段内无一号可寻址")
    } else {
        (true, "号段内有号可寻址")
    };
    协议值::对象值(vec![
        造键文对("标识串", &就绪读数.标识串),
        ("版本".to_owned(), 版本项(&就绪读数.实现版本)),
        (
            "能力号段".to_owned(),
            协议值::数组值(就绪读数.能力号段.iter().map(号段对).collect()),
        ),
        ("是否可用".to_owned(), crate::线上逻辑值::真假值转线上值(是否可用)),
        造键文对("就绪判据", 就绪判据),
        (
            "号段内可寻址号数".to_owned(),
            协议值::无符号值(号段内可寻址号数 as u64),
        ),
    ])
}

/// 一段能力号段 `[段起点, 段止]` → JSON 二元数组。
fn 号段对(号段项: &[u32; 2]) -> 协议值 {
    协议值::数组值(vec![
        协议值::无符号值(u64::from(号段项[0])),
        协议值::无符号值(u64::from(号段项[1])),
    ])
}

/// 版本三元组 → JSON 对象（主 · 次 · 构建）。
fn 版本项(版本: &v1_adapter::版本三元组) -> 协议值 {
    协议值::对象值(vec![
        ("主".to_owned(), 协议值::整数项(i64::from(版本.主版本))),
        ("次".to_owned(), 协议值::整数项(i64::from(版本.次版本号))),
        ("构建".to_owned(), 协议值::整数项(i64::from(版本.构建))),
    ])
}

/// 判定层级 —— 两种拟制一表两读：§22.4 五级区分（本地自检 ≠ 构建 ≠ 准入 ≠ 就绪 ≠ 调用成功）
/// 与 方案 §18.3-6 四类（扩展自检 / 平台准入 / 部署成功 / 业务执行成功 **必须分别判定**）。
/// 合成一条**七级链**，让两者各自的每一档都各自有可判位：
///
/// ```text
/// 本地自检 → 构建 → 准入 → 部署 → 就绪 → 业务执行 → 调用成功
/// ```
///
/// 为什么单开这一层：顶层 `成功: true`（与本端点的装载路）只说明**这条路走通了**，
/// 不等于目标可用；而可用本身又分多个更早的阶段。逐级各给 `已判` 与 `说明`：
/// 本案能现判的现判，不能现判的**如实标未判**并写明为什么（不假报绿灯）。
///
/// **四种「成功」必须分得开（18.3-6）**：自检通过 ≠ 准入通过 ≠ 部署成功 ≠ 业务执行成功。
/// 本面能现判的只有「本地自检」（声明已载入，六步跑过）与「就绪」（能力清单里有号可寻址）；
/// 其余各级的判据不在网关本进程内，逐级如实写**证据在哪**（供调用方去拿），
/// 不因为“本面判不了”就把它当成真或假。
fn 判定层级(适配器: &适配器) -> 协议值 {
    let 可寻址 = !适配器.能力清单().is_empty();
    协议值::数组值(vec![
        层级项(
            "本地自检",
            true,
            "声明已载入且号段无冲突：装载入口六步判定跑过（标识串 / 号段 / 宿主版本 / 依赖 / 自洽）",
        ),
        层级项(
            "构建",
            false,
            "构建制品（cargo）不在网关本进程内，本面无从现判 —— 要看请跑 `测试验证/测试案例/` 的对应案例",
        ),
        层级项(
            "准入",
            false,
            "准入判据（`测试验证/准入判据/`）是独立夹具，不在网关本进程内，本面无从现判",
        ),
        层级项(
            "部署",
            false,
            "部署成功（制品已落到扩展根、环境就绪可被扫到）看的是装配侧的产物与落点，本面只管运行期，无从现判",
        ),
        层级项(
            "就绪",
            可寻址,
            if 可寻址 {
                "当场能力清单非空 ⇒ 至少一份声明的号段内有号可寻址"
            } else {
                "能力清单为空：没有号可寻址（声明载入数不为零也还不等于可用）"
            },
        ),
        层级项(
            "业务执行",
            false,
            "业务执行成功 = 真发起过一次业务调用并拿到应答（不只看能力已载入）—— 那要看 `POST /接口/调用` 与 `GET /接口/留痕`",
        ),
        层级项(
            "调用成功",
            false,
            "本面不看有没有真调成功 —— 那要看 `POST /接口/调用` 的实际应答与 `GET /接口/留痕`",
        ),
    ])
}

