//! 资源调用请求 —— `POST /接口/资源调用` 的体怎么读成「资源号 + 操作号 + 按行序的槽」。
//!
//! 与 `POST /接口/调用`（`请求.rs`）**同一条读法**，只多两个号：
//!
//! ```json
//! { "资源号": 1, "操作号": 2, "输入槽表": [ { "类型标签": 4, "值": "…" } ] }
//! ```
//!
//! 三条读法逐条照抄 §三（冻结件写死的，不是本件的偏好）：
//!
//! 1. `输入槽表` 按资源声明的 `操作.输入类型` 表**行序**对位；空位写
//!    `{"类型标签":0,"值":0}`，**不许省略位次**（省略就是改行序）。
//! 2. 每个值都是**带类型标签的定长槽**。
//! 3. 文本 ⇒ JSON 字符串；字节集 ⇒ base64 字符串；**靠 `类型标签` 区分，不靠形状猜**。
//!
//! **本件不校参数个数**：那是资源网关口的判定（第 4 层 `输入形状不符`，专属码 25）。
//! 在这里再判一次就是第二套校验 —— 而且会和关口口径分叉。`输入槽表` 缺席按**空表**读。
//!
//! **资源号与能力号是两个号空间**（`号段图.json`「四个号空间互不相通」）⇒ 本件读的是
//! `资源号`，**不叫 `编号`**：叫 `编号` 会让读的人以为它走的是 `/接口/调用` 那条腿。

use crate::协议值::协议值;
use crate::槽编码::{self, 槽源, 请求形状错误};

/// `POST /接口/资源调用` 的请求。
pub struct 资源调用请求 {
    /// 资源号（**不是能力号** —— 两个号空间互不相通）。
    pub 资源号: u32,
    /// 操作号（该资源声明白名单里的那个号）。
    pub 操作号: u32,
    /// 按声明行序排列的入参源数据。**顺序即契约**，本件只做「不重排」。
    pub 输入槽表: Vec<槽源>,
}

/// 解析已通过 JSON 语法检查的请求体。
pub fn 解析资源调用(请求体: &协议值) -> Result<资源调用请求, 请求形状错误> {
    if !matches!(请求体, 协议值::对象值(_)) {
        return Err(请求形状错误::构造(
            None,
            "请求体必须是对象：{\"资源号\":N,\"操作号\":M,\"输入槽表\":[…]}",
        ));
    }
    let 资源号 = 取号值(请求体, "资源号")?;
    let 操作号 = 取号值(请求体, "操作号")?;
    let mut 输入槽表 = Vec::new();
    if let Some(项表) = 请求体.取成员("输入槽表") {
        let 项表 = 项表.取数组().ok_or_else(|| {
            请求形状错误::构造(None, "输入槽表 必须是数组（每一项是一个带类型标签的槽）")
        })?;
        for (位次, 槽项) in 项表.iter().enumerate() {
            输入槽表.push(槽编码::由协议值(槽项, 位次)?);
        }
    }
    Ok(资源调用请求 {
        资源号,
        操作号,
        输入槽表,
    })
}

/// 取一个必须存在的 32 位号（`资源号` / `操作号`）。
fn 取号值(请求体: &协议值, 键名: &str) -> Result<u32, 请求形状错误> {
    let 号值 = 请求体
        .取成员(键名)
        .and_then(协议值::取无符号)
        .ok_or_else(|| 请求形状错误::构造(None, format!("缺少 {键名}，或它不是非负整数")))?;
    u32::try_from(号值)
        .map_err(|_| 请求形状错误::构造(None, format!("{键名} 超出 32 位，不是本平台的号")))
}
