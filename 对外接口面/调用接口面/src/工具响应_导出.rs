/// 一次导出的落点：要么一条**真命令**，要么**这条出口没有落点**（如实说清）。
enum 落点 {
    命令 { 程序: PathBuf, 参数: Vec<String> },
    无落点 { 为什么: String },
}

/// `POST /接口/导出` → 按目标转调既有 CLI，或如实报这条出口没有落点。
///
/// 五种出口的动作各有出处（`项目文档/设计文档/导出目标.md`）：
///
/// | 目标 | 动作 | 出处 |
/// |---|---|---|
/// | `案例` | 转调 `v1-case-runner`（案例链） | 导出目标.md §三 ① |
/// | `支持库` | 转调 `构建装配/上线切换/构建制品.py` | 导出目标.md §二 现状列「已有（构建装配/上线切换/）」 |
/// | `制品` | 同上 | 导出目标.md §三 ③ 与 §四「agent 导出制品」 |
/// | `模块` · `技能` | **没有落点 ⇒ 9005** | 导出目标.md §二 现状列「出口未通」· §四 落点表「agent 导出 / 导入：缺」 |
///
/// `支持库` 与 `制品` 共用同一个装配器：**这不是两套实现**（一条命令，两个目标），
/// 差别只在 `--变体`（变体名进构建指纹）。这一处「共用」如实登记在 `接口面形状.md` §七 的缺口里。
pub fn 导出(适配器: &适配器, 工具根: &Path, 请求: &导出请求) -> 协议值 {
    let 起 = Instant::now();
    if !常量::五种出口.contains(&请求.目标.as_str()) {
        return 失败(
            适配器,
            工具码::导出目标不合法,
            Some(协议值::对象(vec![
                键文("目标", &请求.目标),
                (
                    "五种出口".to_owned(),
                    协议值::数组(常量::五种出口.iter().map(|名| 造文本值(名)).collect()),
                ),
                键文(
                    "缺什么",
                    "目标不在五种出口的闭合枚举里（不许按前缀或别名猜）",
                ),
            ])),
            &起,
        );
    }

    let 落点 = match 请求.目标.as_str() {
        "案例" => 落点::命令 {
            程序: 工具根.join(常量::案例跑者),
            参数: Vec::new(),
        },
        "支持库" | "制品" => 制品落点(工具根, &请求.目标, 请求.标识.as_deref()),
        _ => 落点::无落点 {
            为什么: format!(
                "「{}」这条出口没有落点：导出目标.md §二 现状列写「出口未通」、§四 落点表写 \
                 「agent 导出 / 导入：缺」；本面不替它编一条构建命令",
                请求.目标
            ),
        },
    };

    let (程序, 参数) = match 落点 {
        落点::无落点 { 为什么 } => {
            return 失败(
                适配器,
                工具码::导出失败,
                Some(协议值::对象(vec![
                    键文("目标", &请求.目标),
                    键文("缺什么", &为什么),
                ])),
                &起,
            );
        }
        落点::命令 { 程序, 参数 } => (程序, 参数),
    };

    let 借: Vec<&str> = 参数.iter().map(String::as_str).collect();
    match 工具链::跑命令(&程序, &借, 工具根) {
        Ok(读数) if 读数.成功() => 成功(导出回执(工具根, &请求.目标, &程序, &参数, &读数), &起),
        Ok(读数) => 失败(
            适配器,
            工具码::导出失败,
            Some(导出回执(工具根, &请求.目标, &程序, &参数, &读数)),
            &起,
        ),
        Err(说明) => 失败(
            适配器,
            工具码::导出失败,
            Some(协议值::对象(vec![
                键文("目标", &请求.目标),
                键文("程序", &相对(工具根, &程序)),
                (
                    "参数".to_owned(),
                    协议值::数组(参数.iter().map(|项| 造文本值(项)).collect()),
                ),
                键文("缺什么", &说明),
            ])),
            &起,
        ),
    }
}

/// 导出动作的读数（成功与失败共用同一份形状 —— 两处各写一份必然漂移）。
fn 导出回执(
    工具根: &Path,
    目标: &str,
    程序: &Path,
    参数: &[String],
    读数: &读数,
) -> 协议值 {
    协议值::对象(vec![
        键文("目标", 目标),
        键文("程序", &相对(工具根, 程序)),
        (
            "参数".to_owned(),
            协议值::数组(参数.iter().map(|项| 造文本值(项)).collect()),
        ),
        (
            "退出码".to_owned(),
            协议值::整数(i64::from(读数.退出码)),
        ),
        键文("标准输出", &读数.标准输出),
        键文("标准错误", &读数.标准错误),
    ])
}

/// 支持库 / 制品两条出口的落点：同一个装配器（`构建装配/上线切换/` 是它们的落点）。
///
/// 给了 `标识` 就走装配器的**只读检查**（`--检查 <标识>`，判据见 `上线切换/形状.md` §一 判据 4）；
/// 不给就是一次**真构建**（`--变体 <目标>`，变体名进构建指纹）。
fn 制品落点(工具根: &Path, 目标: &str, 标识: Option<&str>) -> 落点 {
    let 脚本 = 工具根.join(常量::制品装配器);
    if !脚本.is_file() {
        return 落点::无落点 {
            为什么: format!(
                "制品装配器不存在：{}（导出目标.md §四 落点表：agent 导出制品 → 构建装配/上线切换/构建制品.py）",
                脚本.display()
            ),
        };
    }
    let mut 参数 = vec![脚本.display().to_string()];
    match 标识 {
        Some(标识) => {
            参数.push("--检查".to_owned());
            参数.push(标识.to_owned());
        }
        None => {
            参数.push("--变体".to_owned());
            参数.push(目标.to_owned());
        }
    }
    落点::命令 {
        程序: PathBuf::from(常量::解释器),
        参数,
    }
}
