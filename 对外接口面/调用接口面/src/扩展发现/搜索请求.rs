//! 搜索请求 —— `GET /接口/搜索` 的查询串怎么读成「关键词 + 分页」。
//!
//! 查询串是 `关键词=…&起始=0&一次条数=20`（百分号编码，浏览器与 `fetch` 会自动编码非 ASCII）。
//! 三条读法：
//!
//! 1. **只认三个键**：`关键词` / `起始` / `一次条数`。多一个键就报错 ——
//!    静默忽略拼错的键，会让调用方以为「起始=100」生效了。
//! 2. `关键词` 必填且非空：空关键词指不出要搜什么（要列全部有 `GET /接口/扩展`
//!    与 `GET /接口/能力/<编号>`）。
//! 3. `一次条数` 有上限（[`条数上限`]）：**上下文预算** —— 一次不许多回；
//!    超上限报错，不静默截断（截断是无声地少给，调用方看不出来）。
//!
//! 空查询串（`GET /接口/搜索` 不带 `?`）回**怎么调**：不是「搜全部」，是把用法说清楚。

use crate::槽编码::请求形状错误;
use crate::转码::百分号解码;

/// 一次最多回多少条（上下文预算：够 Agent 一屏看，不把上下文一次灌满）。
pub const 条数上限: u32 = 100;

/// 省略 `一次条数` 时的默认值。
const 默认一次条数: u32 = 20;

/// `GET /接口/搜索` 的请求。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 搜索请求 {
    pub 关键词: String,
    pub 起始: u32,
    pub 一次条数: u32,
}

/// 查询串 → 搜索请求。
pub fn 解析搜索(查询串: &str) -> Result<搜索请求, 请求形状错误> {
    if 查询串.trim().is_empty() {
        return Err(请求形状错误::构造(
            None,
            "搜索怎么调：GET /接口/搜索?关键词=…&起始=0&一次条数=20 —— 关键词必填；起始/一次条数可省（默认 0 / 20）；一次条数 ≤ 100；关键词与值都要百分号编码",
        ));
    }
    let mut 关键词: Option<String> = None;
    let mut 起始: Option<u32> = None;
    let mut 一次条数: Option<u32> = None;
    for 一格 in 查询串.split('&').filter(|一格| !一格.is_empty()) {
        let (键原文, 值原文) = match 一格.split_once('=') {
            Some((键名, 值)) => (键名, 值),
            None => (一格, ""),
        };
        let 键名 = 解码(键原文)?;
        let 值 = 解码(值原文)?;
        match 键名.as_str() {
            "关键词" => 关键词 = Some(值),
            "起始" => 起始 = Some(取无符号(&值, "起始")?),
            "一次条数" => 一次条数 = Some(取无符号(&值, "一次条数")?),
            未知键 => {
                let 说明 = format!("查询串里没有这个键：{未知键}（只认 关键词 / 起始 / 一次条数）");
                return Err(请求形状错误::构造(None, 说明.as_str()));
            }
        }
    }
    let 关键词 = match 关键词 {
        Some(关键词) if !关键词.trim().is_empty() => 关键词,
        _ => {
            return Err(请求形状错误::构造(
                None,
                "缺 关键词=…（要搜什么）—— 空关键词指不出要搜什么",
            ))
        }
    };
    let 一次条数 = 一次条数.unwrap_or(默认一次条数);
    if 一次条数 == 0 || 一次条数 > 条数上限 {
        let 说明 = format!(
            "一次条数 必须在 1..={条数上限} 之间（上下文预算：一次不许多回）：{一次条数}"
        );
        return Err(请求形状错误::构造(None, 说明.as_str()));
    }
    Ok(搜索请求 {
        关键词,
        起始: 起始.unwrap_or(0),
        一次条数,
    })
}

/// 一格的百分号解码（键与值各解一次，不解整串）。
fn 解码(原文: &str) -> Result<String, 请求形状错误> {
    百分号解码(原文)
        .map_err(|_| 请求形状错误::构造(None, "查询串的百分号编码不是合法 UTF-8"))
}

/// 取一个非负整数（`起始` / `一次条数`）。
fn 取无符号(值: &str, 键名: &str) -> Result<u32, 请求形状错误> {
    值.parse::<u32>().map_err(|_| {
        let 说明 = format!("{键名} 必须是非负整数：{值}");
        请求形状错误::构造(None, 说明.as_str())
    })
}

#[cfg(test)]
mod 搜索请求测试 {
    use super::*;

    #[test]
    fn 只认三个键_缺关键词与超上限都报错() {
        assert_eq!(
            解析搜索("关键词=%E5%9B%9B%E8%88%8D%E4%BA%94%E5%85%A5"),
            Ok(搜索请求 {
                关键词: "四舍五入".to_owned(),
                起始: 0,
                一次条数: 20,
            })
        );
        assert_eq!(
            解析搜索("关键词=abc&起始=3&一次条数=5"),
            Ok(搜索请求 {
                关键词: "abc".to_owned(),
                起始: 3,
                一次条数: 5,
            })
        );
        assert!(解析搜索("").is_err(), "空查询串回「怎么调」");
        assert!(解析搜索("起始=1").is_err(), "缺关键词");
        assert!(解析搜索("关键词=").is_err(), "空关键词");
        assert!(解析搜索("关键词=a&一次条数=101").is_err(), "超上限");
        assert!(解析搜索("关键词=a&一次条数=0").is_err(), "零条");
        assert!(解析搜索("关键词=a&大小=3").is_err(), "不认的键");
        assert!(解析搜索("关键词=a&起始=x").is_err(), "起始不是整数");
    }
}
