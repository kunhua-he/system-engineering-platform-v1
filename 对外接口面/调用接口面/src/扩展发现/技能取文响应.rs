//! 技能取文 —— `GET /接口/运维/技能/取文/<编号>`：按技能能力号取回本体段 19 的 md 正文。
//!
//! # 补的是哪一段链路（三类制品接缝 · 技能取文）
//!
//! 技能是三类扩展之一（`扩展装载/后缀表.json`）：它**不含实现、没有码段**，本体就是一份 md，
//! 装在 `.技能制品` 的**技能本体段 19**（`契约声明/src/契约声明/容器封装/容器.rs::段类型_技能本体`）。
//! codec 那一半早已在位（`容器::取技能本体文本`，含指纹校验与反向样本），声明那一半也在位
//! （技能目录里 包声明 + 制品 + 能力声明 三件齐）；缺的是**对外那一段**：盘上有制品、有声明，
//! 而从 HTTP 面取不到文。本件就是那一段。
//!
//! # 只取文、不执行
//!
//! 本件不 `dlopen`、不调任何执行函数、不把正文当代码：正文原样交回（`文本` · `字符数`）。
//! 技能本体里「技能是说明，不是权限」那句话，在这里的形态就是：**只有读**。
//!
//! # 不认名字，只认号与后缀
//!
//! 扫法与 `列扩展` / 运行期装载**同一条**：`扩展根声明.json` 的 `种类[].扩展落点` 给目录，
//! `列子目录` 给候选，候选里有没有本种类的制品由**后缀**判 —— 后缀当场从唯一权威
//! `扩展装载/后缀表.json` 解出（本面不持有字面，判据 ③）。**命中只看能力号段**，
//! 不看扩展名（README 硬边界 1：底座不认识任何扩展）。
//!
//! # 失败一律回真错误码
//!
//! 取不到就 `成功: false` + `9015 技能取文失败`，并把**具体缺什么**写进回执 `数据.缺什么`
//! （声明链读不到 / 号不在任何技能号段里 / 目录里没有本种类的技能制品 / 制品解包或本体段取文失败）。
//! **不编空文本**：取不到与「取到空文」必须可区分（§三 第一原则：错误必须立刻可见）。

use super::{列子目录, 造失败应答, 造键文对, 造成功应答, 取相对路径, 读JSON件};
use crate::契约级常量::{self, 工具码};
use crate::协议值::协议值;
use std::path::{Path, PathBuf};
use std::time::Instant;
use v1_adapter::{适配器, 容器};

/// `GET /接口/运维/技能/取文/<编号>` → 技能本体文本，或结构化的失败回执。
pub fn 技能取文(适配器: &适配器, 工具根: &Path, 编号: u32) -> 协议值 {
    let 区间起点 = Instant::now();
    match 组装取文(工具根, 编号) {
        Ok((技能目录, 标识串, 本体文本)) => 造成功应答(
            协议值::对象值(vec![
                ("编号".to_owned(), 协议值::无符号值(u64::from(编号))),
                造键文对("技能目录", &取相对路径(工具根, &技能目录)),
                造键文对("标识串", &标识串),
                造键文对("文本", &本体文本),
                ("字符数".to_owned(), 协议值::无符号值(本体文本.chars().count() as u64)),
                ("只取文不执行".to_owned(), 协议值::真值),
            ]),
            &区间起点,
        ),
        Err(说明文字) => 造失败应答(
            适配器,
            工具码::技能取文失败,
            Some(协议值::对象值(vec![
                ("编号".to_owned(), 协议值::无符号值(u64::from(编号))),
                造键文对("缺什么", &说明文字),
                造键文对("扩展根声明", 契约级常量::扩展根声明),
                造键文对("后缀表", 契约级常量::后缀表路径),
            ])),
            &区间起点,
        ),
    }
}

/// **技能读面账** —— 三类扩展里唯一「不执行」的那一类：没有码段、不进 `dlopen`，
/// 就绪判据只有一条「段 19 的本体读得出（取文口可用）」。
///
/// 为什么放在这里而不是另开一件：扫法（种类落点 → 子目录 → 后缀判本种类制品）与
/// [`组装取文`] 是同一条，另写一份就是第二套事实源。本函数只多做了「把所有技能都列出来」。
pub fn 列技能读面(工具根: &Path) -> Vec<协议值> {
    let mut 技能账: Vec<协议值> = Vec::new();
    let Ok(声明) = 读JSON件(&工具根.join(契约级常量::扩展根声明)) else {
        return 技能账;
    };
    let Some(种类表) = 声明.取成员("种类").and_then(协议值::取数组) else {
        return 技能账;
    };
    for 种类项 in 种类表 {
        if 种类项.取成员("种类").and_then(协议值::取文本) != Some("技能") {
            continue;
        }
        let Some(扩展根目录) = 种类项.取成员("扩展落点").and_then(协议值::取文本) else {
            continue;
        };
        let 完整路径 = 工具根.join(扩展根目录);
        let Ok(目录表) = 列子目录(&完整路径) else {
            continue;
        };
        for 目录名 in 目录表 {
            let 技能目录 = 完整路径.join(&目录名);
            let Ok(包声明) = 读JSON件(&技能目录.join(契约级常量::扩展声明件)) else {
                continue;
            };
            let 标识串 = 包声明
                .取成员("标识串")
                .and_then(协议值::取文本)
                .unwrap_or_default()
                .to_owned();
            let 名称 = 包声明
                .取成员("名称")
                .and_then(协议值::取文本)
                .unwrap_or_default()
                .to_owned();
            let 号段协议值 = 协议值::数组值(
                包声明
                    .取成员("能力号段")
                    .and_then(协议值::取数组)
                    .unwrap_or_default()
                    .iter()
                    .map(|号段项| {
                        协议值::数组值(vec![
                            协议值::无符号值(
                                号段项.取成员("起").and_then(协议值::取无符号).unwrap_or(0),
                            ),
                            协议值::无符号值(
                                号段项.取成员("止").and_then(协议值::取无符号).unwrap_or(0),
                            ),
                        ])
                    })
                    .collect(),
            );
            let 取文结果 =
                取技能后缀(工具根).and_then(|后缀项| 找本种类制品(&技能目录, &后缀项));
            let (本体可读, 字符数, 缺失说明) = match 取文结果 {
                Ok(制品路径) => match std::fs::read(&制品路径) {
                    Ok(制品字节) => match 容器::取技能本体文本(&制品字节) {
                        Ok(本体文本) => (true, 本体文本.chars().count() as u64, String::new()),
                        Err(错误) => (false, 0, format!("技能制品取文失败：{错误:?}")),
                    },
                    Err(错误) => (false, 0, format!("读不到制品：{错误}")),
                },
                Err(说明) => (false, 0, 说明),
            };
            技能账.push(协议值::对象值(vec![
                造键文对("技能目录", &取相对路径(工具根, &技能目录)),
                造键文对("标识串", &标识串),
                造键文对("名称", &名称),
                ("能力号段".to_owned(), 号段协议值),
                (
                    "是否可用".to_owned(),
                    crate::线上逻辑值::真假值转线上值(本体可读),
                ),
                造键文对(
                    "就绪判据",
                    if 本体可读 {
                        "段19 本体可读（取文口可用）· 不执行"
                    } else {
                        "段19 本体读不出"
                    },
                ),
                ("字符数".to_owned(), 协议值::无符号值(字符数)),
                造键文对("缺什么", &缺失说明),
            ]));
        }
    }
    技能账
}

/// 定位 → 取文：命中目录 · 标识串 · 本体正文。
fn 组装取文(工具根: &Path, 编号: u32) -> Result<(PathBuf, String, String), String> {
    let 技能目录 = 按号找技能(工具根, 编号)?;
    let 包声明 = 读JSON件(&技能目录.join(契约级常量::扩展声明件))?;
    let 标识串 = 包声明
        .取成员("标识串")
        .and_then(协议值::取文本)
        .unwrap_or_default()
        .to_owned();
    let 制品路径 = 找本种类制品(&技能目录, &取技能后缀(工具根)?)?;
    let 制品字节 = std::fs::read(&制品路径)
        .map_err(|错误| format!("读不到制品 {}：{错误}", 取相对路径(工具根, &制品路径)))?;
    let 本体文本 = 容器::取技能本体文本(&制品字节)
        .map_err(|错误| format!("技能制品取文失败（{}）：{错误:?}", 取相对路径(工具根, &制品路径)))?;
    Ok((技能目录, 标识串, 本体文本))
}

/// 技能那一类的制品后缀 —— 从**唯一权威** `扩展装载/后缀表.json` 当场解出（不落字面）。
fn 取技能后缀(工具根: &Path) -> Result<String, String> {
    let 后缀表文本 = std::fs::read_to_string(工具根.join(契约级常量::后缀表路径))
        .map_err(|错误| format!("读不到 {}：{错误}", 契约级常量::后缀表路径))?;
    let 后缀项 = crate::扫扩展根::读后缀表(&后缀表文本)?
        .取种类后缀("技能")
        .ok_or_else(|| format!("{} 的 三类扩展[] 里没有「技能」这一项", 契约级常量::后缀表路径))?
        .to_owned();
    Ok(后缀项)
}

/// 按能力号找技能目录：扫 `扩展根声明.json` 里「技能」那一类的落点，逐目录比能力号段。
///
/// 命中**恰好一个**才算数：一个都没有 ⇒ 报「不在任何技能号段里」；两个以上 ⇒ 报「号段重叠」
/// （号段不许重叠是装载侧判定的活，这里只如实报出「本面看到的不止一个」，不替它裁）。
fn 按号找技能(工具根: &Path, 编号: u32) -> Result<PathBuf, String> {
    let 声明 = 读JSON件(&工具根.join(契约级常量::扩展根声明))?;
    let 种类表 = 声明
        .取成员("种类")
        .and_then(协议值::取数组)
        .ok_or_else(|| format!("{} 缺 种类（数组）", 契约级常量::扩展根声明))?;
    let mut 命中目录: Option<PathBuf> = None;
    let mut 扫过目录数 = 0_u64;
    for 种类项 in 种类表 {
        if 种类项.取成员("种类").and_then(协议值::取文本) != Some("技能") {
            continue;
        }
        let 扩展根目录 = 种类项
            .取成员("扩展落点")
            .and_then(协议值::取文本)
            .ok_or_else(|| "种类「技能」缺 扩展落点（文本）".to_owned())?;
        let 完整路径 = 工具根.join(扩展根目录);
        for 目录名 in
            列子目录(&完整路径).map_err(|说明文字| format!("技能落点 {扩展根目录}：{说明文字}"))?
        {
            扫过目录数 += 1;
            let 技能目录 = 完整路径.join(&目录名);
            let 包声明 = 读JSON件(&技能目录.join(契约级常量::扩展声明件))?;
            if !号段含号(&包声明, 编号) {
                continue;
            }
            if 命中目录.is_some() {
                return Err(format!("能力号 {编号} 落在多个技能目录里（技能号段不许重叠）"));
            }
            命中目录 = Some(技能目录);
        }
    }
    match 命中目录 {
        Some(技能目录) => Ok(技能目录),
        None => Err(format!(
            "能力号 {编号} 不在任何技能目录的能力号段里（扫过 {扫过目录数} 个技能目录；技能那一类的落点见 {}）",
            契约级常量::扩展根声明
        )),
    }
}

/// 包声明的 `能力号段` 含不含这个号（区间按声明原样读：`起 ≤ 号 ≤ 止`）。
fn 号段含号(包声明: &协议值, 编号: u32) -> bool {
    let 能力号值 = u64::from(编号);
    包声明
        .取成员("能力号段")
        .and_then(协议值::取数组)
        .is_some_and(|号段表| {
            号段表.iter().any(|号段项| {
                let 起始 = 号段项.取成员("起").and_then(协议值::取无符号);
                let 终止 = 号段项.取成员("止").and_then(协议值::取无符号);
                let (Some(起始), Some(终止)) = (起始, 终止) else {
                    return false;
                };
                能力号值 >= 起始 && 能力号值 <= 终止
            })
        })
}

/// 目录里**恰好一份**本种类的制品 —— 0 份 / 多份都如实报因（与 `模块制品.rs` 同口径）。
fn 找本种类制品(技能目录: &Path, 后缀项: &str) -> Result<PathBuf, String> {
    let 目录读器 = std::fs::read_dir(技能目录)
        .map_err(|错误| format!("读不到目录 {}：{错误}", 技能目录.display()))?;
    let 制品文件: Vec<PathBuf> = 目录读器
        .filter_map(|目录项| 目录项.ok())
        .map(|目录项| 目录项.path())
        .filter(|路径| {
            路径.is_file()
                && 路径
                    .file_name()
                    .and_then(|名称| 名称.to_str())
                    .is_some_and(|名称| 名称.ends_with(后缀项))
        })
        .collect();
    let 制品份数 = 制品文件.len();
    match 制品文件.into_iter().next() {
        Some(制品路径) if 制品份数 == 1 => Ok(制品路径),
        _ => Err(format!(
            "技能目录 {} 里本种类（后缀 `{后缀项}`，按 {} 解出）的制品有 {制品份数} 份（要求恰好 1 份）",
            技能目录.display(),
            契约级常量::后缀表路径
        )),
    }
}

#[cfg(test)]
mod 技能取文测试 {
    use super::*;
    use crate::测试夹具::{仓根, 取请求, 发请求, 起服务, 源文本, 无符号值};

    /// 取一个 `成功: true` 的 `数据` 对象；不是成功就挂（带原文）。
    fn 取成功数据(造应答: &crate::测试夹具::收到应答) -> 协议值 {
        assert!(造应答.取逻辑值("成功"), "必须成功：\n{}", 造应答.报文体);
        造应答.取成员("数据")
    }

    /// 真制品取文：编号 8200 取回的正文必须与**盘上那份**技能本体说明逐字相同。
    ///
    /// 比对物从盘上真源读，不在本件里再写一份期望文本（写死一份就是同一件事的第二份）。
    #[test]
    fn 技能取文_真制品取回说明正文逐字相同() {
        let 服务 = 起服务();
        let 造应答 = 发请求(&服务, &取请求("/接口/运维/技能/取文/8200"));
        assert_eq!(造应答.状态, 200, "协议层仍是 200：\n{}", 造应答.报文体);
        let 应答数据 = 取成功数据(&造应答);
        assert_eq!(无符号值(&应答数据, "编号"), 8200);
        assert_eq!(源文本(&应答数据, "技能目录"), "扩展根目录/技能封装库/取文技能");
        let 真源文本 = std::fs::read_to_string(仓根().join("扩展根目录/技能封装库/取文技能/说明.md"))
            .expect("盘上必须有那份说明");
        assert_eq!(源文本(&应答数据, "文本"), 真源文本, "取回的正文必须与盘上的说明逐字相同");
        assert_eq!(
            无符号值(&应答数据, "字符数"),
            真源文本.chars().count() as u64,
            "字符数按字符算，不按字节"
        );
    }

    /// 反向样本：号不在任何技能号段里 ⇒ `9015` + `缺什么` 点名那个号，**且不许给 `文本` 键**。
    #[test]
    fn 技能取文_未命中号回真错误码而不是空文本() {
        let 服务 = 起服务();
        let 造应答 = 发请求(&服务, &取请求("/接口/运维/技能/取文/8999"));
        assert_eq!(造应答.状态, 200, "业务失败也是 200：\n{}", 造应答.报文体);
        assert!(!造应答.取逻辑值("成功"), "取不到就不许报成功：\n{}", 造应答.报文体);
        let 错误 = 造应答.取成员("错误");
        assert_eq!(无符号值(&错误, "码"), u64::from(crate::契约级常量::工具码::技能取文失败));
        let 应答数据 = 造应答.取成员("数据");
        let 缺什么 = 源文本(&应答数据, "缺什么");
        assert!(缺什么.contains("8999"), "缺什么 要点名那个号，实际：{缺什么}");
        assert!(应答数据.取成员("文本").is_none(), "失败回执里不许出现 文本 键（不编空文）");
    }
}
