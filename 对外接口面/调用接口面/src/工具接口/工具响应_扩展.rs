//! §七 列扩展：`GET /接口/运维/检索`（**不带查询键**）—— 支持库 · 模块 · 技能三类清单。
//!
//! 返回组装只走共用件（`super::造成功应答` / `super::造失败应答` / `造键文对` / `取相对路径` / `读JSON件` / `列子目录`）
//! —— 形状与这一族码的口径全在 `工具响应.rs` 的文件头，本件不另立一套。

use super::{列子目录, 造失败应答, 造键文对, 造成功应答, 取相对路径, 读JSON件};
use crate::线上逻辑值::真假值转线上值;
use crate::契约级常量::{self, 工具码};
use crate::协议值::协议值;
use std::path::Path;
use std::time::Instant;
use v1_adapter::适配器;

// ════════════════════════════════════════════════════════════════════════════
// 三 列扩展：`GET /接口/运维/检索`（不带查询键）
// ════════════════════════════════════════════════════════════════════════════

/// `GET /接口/运维/检索`（不带查询键）→ 支持库 / 模块 / 技能三类清单。
///
/// **失败时一条都不返回**（`9007` 的说明：残缺清单比空清单更危险 —— 调用方会以为就这些）。
/// 故本函数只有两个出口：全量 `数据`，或**没有 `数据.种类`** 的结构化失败回执。
///
/// 判定只做**结构**（面只做结构校验，不做业务判断 —— §四 硬规则 2）：
/// 扩展根声明读得到、三类目录都在、每个扩展有 `包声明.json` 且它解得出 `名称` 与 `能力号段`。
/// **不判号段归属**（那是装载入口判定第 4 步的活，在这里再判一次就是第二套实现）。
pub fn 列扩展(适配器: &适配器, 工具根: &Path) -> 协议值 {
    let 区间起点 = Instant::now();
    match 组装列扩展(适配器, 工具根) {
        Ok(应答数据) => 造成功应答(应答数据, &区间起点),
        Err(说明文字) => 造失败应答(
            适配器,
            工具码::列扩展失败,
            Some(协议值::对象值(vec![
                造键文对("扩展根声明", 契约级常量::扩展根声明),
                造键文对("缺什么", &说明文字),
                造键文对(
                    "为什么失败时不返回部分清单",
                    "残缺清单比空清单更危险：调用方会以为「就这些」，于是把漏掉的那几个当成不存在",
                ),
            ])),
            &区间起点,
        ),
    }
}

fn 组装列扩展(适配器: &适配器, 工具根: &Path) -> Result<协议值, String> {
    let 声明 = 读JSON件(&工具根.join(契约级常量::扩展根声明))?;
    let 路径基准 = 声明
        .取成员("路径基准")
        .and_then(协议值::取文本)
        .ok_or_else(|| format!("{} 缺 路径基准（文本）", 契约级常量::扩展根声明))?;
    if 路径基准 != "工作目录" {
        return Err(format!(
            "路径基准 = {路径基准}，本面只认「工作目录」（{} 的既有口径）",
            契约级常量::扩展根声明
        ));
    }
    let 种类表 = 声明
        .取成员("种类")
        .and_then(协议值::取数组)
        .ok_or_else(|| format!("{} 缺 种类（数组）", 契约级常量::扩展根声明))?;

    // 种类[].扩展落点 相对 路径基准（= 工作目录）解析 —— `examples/启动网关.rs` 同口径且跑通，
    // 它从不读 `扩展根`。`扩展根` 键已从 `扩展根声明.json` **删掉**了
    //（该键在载入路径上无可数读方，是 种类[].扩展落点 首段的冗余副本）⇒ 本面**不再要求、
    // 不再读取、不再 join 它**：`目录` 已经是相对工作目录的完整路径。
    let mut 种类出 = Vec::new();
    for 种类项 in 种类表 {
        let 名称 = 种类项
            .取成员("种类")
            .and_then(协议值::取文本)
            .ok_or_else(|| format!("{} 的种类[] 里有条目缺 种类（文本）", 契约级常量::扩展根声明))?;
        let 扩展根目录 = 种类项
            .取成员("扩展落点")
            .and_then(协议值::取文本)
            .ok_or_else(|| format!("种类「{名称}」缺 扩展落点（文本）"))?;
        let 完整路径 = 工具根.join(扩展根目录);
        let 子目录 = 列子目录(&完整路径).map_err(|说明文字| format!("种类「{名称}」的目录 {扩展根目录}：{说明文字}"))?;

        let mut 扩展出 = Vec::new();
        for 扩展目录 in 子目录 {
            let 声明件 = 完整路径.join(&扩展目录).join(契约级常量::扩展声明件);
            let 包声明 = 读JSON件(&声明件)
                .map_err(|说明文字| format!("扩展「{扩展目录}」{说明文字}（声明缺失）"))?;
            let 名称 = 包声明
                .取成员("名称")
                .and_then(协议值::取文本)
                .ok_or_else(|| format!("扩展「{扩展目录}」的 包声明.json 缺 名称（声明不自洽）"))?;
            let 号段 = 包声明
                .取成员("能力号段")
                .and_then(协议值::取数组)
                .ok_or_else(|| format!("扩展「{扩展目录}」的 包声明.json 缺 能力号段（声明不自洽）"))?;
            let 本扩展标识串 = 包声明
                .取成员("标识串")
                .and_then(协议值::取文本)
                .unwrap_or("");
            // ── 就绪判定（§32.2：发现结果只能展示与当前查询语义相符的状态；
            //    「制品存在」「声明合法」「已就绪」必须可区分）──────────────────────
            // 本端点读的是**盘上的扩展目录**（候选面），不是适配器的已装载台账 ⇒
            // 「声明在盘上合法」**不等于**「已就绪可调」。两者必须分开报，否则 Agent 会把
            // 部署未装载误读成「这项能力不存在/不好用」（§32.4 明令：能力不存在与暂时未就绪
            // 分别可判）。判据取自**适配器当场的能力清单**（与调侧同一个入口，不另存一份表）。
            //
            // **只据能力号判，不据标识串**：适配器公开面能按**文本**查「已装载了谁」的口只有
            // 通知账（`通知端点标识串`），而它只含申报过 `通知函数` 的扩展 ⇒ 拿它判就绪对
            // 技能 / 纯取文模块会**假报未就绪**。故这里只用一条不会假报的判据：本扩展声明的
            // 能力号段里有没有号真出现在清单里。**号段为空**的扩展（技能 / 无命令的模块）
            // 本面无从判它装没装 ⇒ 如实报第三个值 `无号段无从判`，**不编 false**。
            let 已装载号: Vec<u32> = 适配器.能力清单().iter().map(|能力摘要| 能力摘要.编号).collect();
            let 已就绪号: Vec<协议值> = 号段
                .iter()
                .filter_map(|段项| {
                    let 起始 = 段项.取成员("起").and_then(协议值::取无符号)?;
                    let 终止 = 段项.取成员("止").and_then(协议值::取无符号)?;
                    Some((起始, 终止))
                })
                .flat_map(|(起始, 终止)| {
                    已装载号
                        .iter()
                        .filter(move |号值| u64::from(**号值) >= 起始 && u64::from(**号值) <= 终止)
                        .map(|号值| 协议值::无符号值(u64::from(*号值)))
                })
                .collect();
            let (是否就绪, 就绪判据) = if 号段.is_empty() {
                (false, "无号段无从判")
            } else if 已就绪号.is_empty() {
                (false, "号段内无一号可寻址")
            } else {
                (true, "号段内有号可寻址")
            };
            扩展出.push(协议值::对象值(vec![
                造键文对("扩展目录", &扩展目录),
                造键文对("名称", 名称),
                造键文对("标识串", 本扩展标识串),
                ("能力号段".to_owned(), 协议值::数组值(号段.to_vec())),
                // **声明在盘上合法**（本端点的既有语义，逐字不动）：读到、解得出名称与号段。
                造键文对("声明落点", &取相对路径(工具根, &声明件)),
                // **旁路字段**（§32.2）：把「声明合法」与「已就绪」分开，都是机器可判。
                ("是否就绪".to_owned(), 真假值转线上值(是否就绪)),
                ("已就绪能力号".to_owned(), 协议值::数组值(已就绪号)),
                造键文对("就绪判据", 就绪判据),
            ]));
        }
        种类出.push(协议值::对象值(vec![
            造键文对("种类", 名称),
            // 响应键与声明侧同名（`扩展落点`）：2026-10-27 已走冻结例外登记
            // （原「待裁冻结例外」第 ⑦ 条，收口形态见 `冻结登记.json` 已落地段）——
            // 一名两形会让「同一物在哪」不可判定，实测仓内零消费者，改键无功能风险。
            造键文对("扩展落点", 扩展根目录),
            ("扩展".to_owned(), 协议值::数组值(扩展出)),
        ]));
    }

    Ok(协议值::对象值(vec![
        // 不再返回 `扩展根`：那个键已从 `扩展根声明.json` 删除（无可数读方）。
        // 报一个空串或从 `扩展落点` 首段反推都是**编事实**；路径基准由 `种类[].扩展落点` 自带。
        造键文对("扩展根声明", 契约级常量::扩展根声明),
        ("种类".to_owned(), 协议值::数组值(种类出)),
    ]))
}
