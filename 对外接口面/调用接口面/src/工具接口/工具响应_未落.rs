/// `POST /接口/菜单命令` → **一律 `9001 端点未实现`**，回执里带**命令名与编号**。
///
/// 判据：「菜单表里已登记但后端未落的命令，一律回 9001，
/// **不要静默失败、不要假装成功**」。菜单表里 181 项，`菜单栏.js` 自身的读数就是
/// 「169 项点了写未接线 + 死在哪一步」——**后端确实一条都没落**。
///
/// 命令名从 `菜单表.js` 现读（**唯一登记处**），不在本文件里抄一份表。
/// 读不到菜单表时 `在菜单表里` 给 `null`（判不了就是判不了，**不编一个 `false`**），
/// 而 `9001` 照样成立：没有任何菜单命令有后端落点这件事与读不读得到表无关。
pub fn 菜单命令(适配器: &适配器, 工具根: &Path, 编号: &str) -> 协议值 {
    let 区间起点 = Instant::now();
    let (在菜单表里, 名称, 读表失败) = match 读菜单表(工具根) {
        Ok(项表) => match 项表.iter().find(|(号值, _)| 号值 == 编号) {
            Some((_, 名称)) => (Some(true), 名称.clone(), None),
            None => (Some(false), String::new(), None),
        },
        Err(说明文字) => (None, String::new(), Some(说明文字)),
    };

    let 命令 = 协议值::对象值(vec![
        造键文对("编号", 编号),
        造键文对("名称", &名称),
        (
            "在菜单表里".to_owned(),
            match 在菜单表里 {
                Some(是否在表) => {
                    if 是否在表 {
                        协议值::真值
                    } else {
                        协议值::假值
                    }
                }
                None => 协议值::空值项,
            },
        ),
    ]);
    let mut 对象成员 = vec![
        造键文对("目标", 契约级常量::菜单表),
        ("命令".to_owned(), 命令),
        造键文对(
            "为什么未落",
            "菜单命令没有后端落点：接口面只有 §二 四个端点 + 旁路端点（工具族六个 + \
             生命周期族 · 留痕），没有「按命令 id 分派」这一条路（菜单栏.js 自身的读数：169 项未接线）。\
             前端接上的具体能力是哪些、它们载没载入，都不在接口面的可知范围内 ——\
             接口面只认端点和菜单表，不认任何扩展的名字或编号。",
        ),
    ];
    match (在菜单表里, 读表失败) {
        (Some(false), _) => 对象成员.push(造键文对(
            "缺什么",
            "该编号不在菜单表里（不是已登记的命令）—— 已登记的命令同样一律未落，故回的仍是同一个码",
        )),
        (None, Some(说明文字)) => 对象成员.push(造键文对(
            "缺什么",
            &format!("读不到菜单表，故「在菜单表里」判不了：{说明文字}"),
        )),
        _ => {}
    }

    造失败应答(
        适配器,
        工具码::端点未实现,
        Some(协议值::对象值(对象成员)),
        &区间起点,
    )
}

/// 读菜单表：**行式取 `编号: "…"` 与同行 `文字: "…"`**。
///
/// 为什么按行取而不是按语法解析：`菜单表.js` 是**数据**（每条命令一行，见它的文件头），
/// 而本仓硬规矩是零第三方依赖 ⇒ 没有 JS 解析器。行式取的两个字段是那份数据里
/// **唯一**被用到的两项（`编号` 是身份、`文字` 是名字）。
fn 读菜单表(工具根: &Path) -> Result<Vec<(String, String)>, String> {
    let 路径 = 工具根.join(契约级常量::菜单表);
    let 文本值 =
        std::fs::read_to_string(&路径).map_err(|错误| format!("读不到 {}：{错误}", 路径.display()))?;
    let mut 输出缓冲 = Vec::new();
    for 源码行 in 文本值.lines() {
        let Some(编号) = 取引号值(源码行, "编号: \"") else {
            continue;
        };
        let 名称 = 取引号值(源码行, "文字: \"").unwrap_or_default();
        输出缓冲.push((编号, 名称));
    }
    Ok(输出缓冲)
}

/// 取 `标记` 之后第一对引号里的内容。
fn 取引号值(源码行: &str, 标记: &str) -> Option<String> {
    let 区间起点 = 源码行.find(标记)? + 标记.len();
    let 剩余文本 = 源码行.get(区间起点..)?;
    let 区间终点 = 剩余文本.find('"')?;
    Some(剩余文本[..区间终点].to_owned())
}
