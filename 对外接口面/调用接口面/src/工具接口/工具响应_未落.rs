/// 程序文本的扩展名（唯一来源：`项目文档/设计文档/程序文本格式.md` §三）。
const 后缀_程序文本: &str = ".程序文本";

/// `POST /接口/程序文本` → **真读 / 真写调用方自带的那份路径**。
///
/// 落点已裁（`项目文档/决策记录/2026-09-28_华哥的尺子与七条裁决.md` §二 206 行）：
/// 「项目/程序文本那一层」= **调用方自带路径** —— 每次由调用方给，底座**不新增目录约定、
/// 无隐式兜底**。相对路径按注入的 `工具根` 解（与 §七 其余端点同一条部署事实）；绝对路径原样用。
///
/// **逐种失败各报一个明确码**（裁决 §三 第一原则：错误必须立刻可见，不许一个通用码糊过去）：
///
/// | 失败 | 码 |
/// |---|---|
/// | 路径空（缺键 / 空串） | `9008 程序文本路径为空` |
/// | 路径不以 `.程序文本` 结尾 | `9011 程序文本后缀不符` |
/// | 路径越出允许根（工具根） | `9013 程序文本越界` |
/// | 写动作未显式升档（默认最紧 = 只读） | `9014 程序文本只读` |
/// | 读 · 件不在 | `9009 程序文本不存在` |
/// | 读 · 件在但读失败 | `9010 程序文本读不到` |
/// | 写 · 写失败（父目录不在 / 权限 / IO） | `9012 程序文本写不到` |
///
/// 为什么后缀先行：后缀是**请求自身的属性**（不看盘就能判），先判它把「把别的件当程序文本
/// 读写」这一整类挡在最前。为什么**不替调用方建父目录**：那是隐式兜底，会让「写成功」变成
/// 假绿（裁决：无隐式兜底）。
///
/// # 安全前提（口径：`项目文档/决策记录/2026-09-28_安全边界.md` §一）
///
/// 本端点原先**真读 / 真写调用方自带的任意路径**，没有任何上界 ⇒ 请求体给一个绝对路径就能
/// 读到 / 写到盘上任何一处。`安全边界.md` §一 把「经边界的输入」定为**不可信**，故补两条
/// 上界（实现在 `工具根守卫.rs`，本件只调用）：
///
/// 1. **路径上界**：规范化后的路径必须落在注入的 `工具根` 之内（相对路径也按它解）。
/// 2. **动作上界**：请求体不给 `权限` 时按**最紧**那一档（`只读`）走；要写必须显式给 `读写`。
///
/// 两条都是**业务失败回真错误码**（不是 400）：越界 ⇒ `9013`，本档不许写 ⇒ `9014`。
/// 判定顺序放在后缀之后、看盘之前 —— 越界与权限都是**请求自身的属性**（不看盘就能判），
/// 先判它们把「本来就不该碰的路径」挡在看盘之前。
pub fn 程序文本(适配器: &适配器, 工具根: &Path, 请求: &程序文本请求) -> 协议值 {
    let 区间起点 = Instant::now();
    let 给定 = 请求.路径.trim();

    // ① 路径空 ⇒ 9008（业务失败，不是 400：裁决要「路径空」有一个明确码）。
    if 给定.is_empty() {
        return 造失败应答(
            适配器,
            工具码::程序文本路径为空,
            Some(协议值::对象值(vec![
                造键文对("动作", &请求.动作),
                造键文对("路径", &请求.路径),
                造键文对(
                    "缺什么",
                    "路径 —— 裁决定落点 = 调用方自带路径（底座不新增目录约定、无隐式兜底），\
                     故路径必须由调用方给；空路径指不出读 / 写哪一份文本",
                ),
            ])),
            &区间起点,
        );
    }

    // ② 后缀不符 ⇒ 9011（先于看盘：后缀是请求自身的属性）。
    if !给定.ends_with(后缀_程序文本) {
        return 造失败应答(
            适配器,
            工具码::程序文本后缀不符,
            Some(协议值::对象值(vec![
                造键文对("动作", &请求.动作),
                造键文对("路径", 给定),
                造键文对("要求后缀", 后缀_程序文本),
                造键文对(
                    "为什么",
                    "程序文本格式.md §三 定死扩展名 .程序文本；本端点只认这一种后缀，\
                     防止把不是程序文本的件当程序文本读写 —— 那会让「读写成功」变成假绿",
                ),
            ])),
            &区间起点,
        );
    }

    // 绝对路径 join 覆盖工具根（`Path::join` 语义）；相对路径按工具根解。
    // ★ 但先过安全前提：路径必须落在允许根内、写动作必须有档。
    let 路径 = match 判路径在根内(工具根, 给定) {
        Ok(定下来的) => 定下来的,
        Err(守卫失败) => {
            return 造失败应答(
                适配器,
                工具码::程序文本越界,
                Some(协议值::对象值(vec![
                    造键文对("动作", &请求.动作),
                    造键文对("路径", 给定),
                    造键文对(权限键, 请求.权限.取名称()),
                    造键文对("为什么", &守卫失败),
                    造键文对(
                        "缺什么",
                        "一条落在允许根（工具根）之内的路径 —— 本端点的安全前提是「只碰工具根里的件」，\
                         给绝对路径也必须以工具根开头",
                    ),
                ])),
                &区间起点,
            );
        }
    };

    if 请求.动作 == "写" {
        // 写动作先过权限：默认最紧那一档（只读）不许写，要写须显式传参给 `读写`。
        // fail-closed：不升档就是不许写，不是一个「默认允许」。
        if !请求.权限.允许写() {
            return 造失败应答(
                适配器,
                工具码::程序文本只读,
                Some(协议值::对象值(vec![
                    造键文对("动作", "写"),
                    造键文对("路径", &取相对路径(工具根, &路径)),
                    造键文对(权限键, 请求.权限.取名称()),
                    造键文对(
                        "为什么",
                        &format!(
                            "本档权限（{}）不许写：请求体没给 {权限键} 键时按最紧那一档走\
                             （安全边界 §一：经边界的输入不可信 ⇒ 缺键落到最紧）；\
                             要写请显式给 {权限键}:\"读写\"",
                            请求.权限.取名称()
                        ),
                    ),
                ])),
                &区间起点,
            );
        }
        let 正文 = 请求.正文.as_deref().unwrap_or("");
        return match std::fs::write(&路径, 正文) {
            Ok(()) => 造成功应答(
                协议值::对象值(vec![
                    造键文对("动作", "写"),
                    造键文对("路径", &取相对路径(工具根, &路径)),
                    ("字节数".to_owned(), 协议值::无符号值(正文.len() as u64)),
                ]),
                &区间起点,
            ),
            Err(错误) => 造失败应答(
                适配器,
                工具码::程序文本写不到,
                Some(协议值::对象值(vec![
                    造键文对("动作", "写"),
                    造键文对("路径", &取相对路径(工具根, &路径)),
                    造键文对(
                        "为什么",
                        &format!("写到该路径失败：{错误}（父目录不在 / 权限 / IO；底座不替调用方建目录）"),
                    ),
                ])),
                &区间起点,
            ),
        };
    }

    // 读：把「件不在」与「件在但读失败」分开报（修法不同：补路径 / 看权限）。
    match std::fs::read_to_string(&路径) {
        Ok(文本值) => 造成功应答(
            协议值::对象值(vec![
                造键文对("动作", "读"),
                造键文对("路径", &取相对路径(工具根, &路径)),
                造键文对("文本", &文本值),
                ("字符数".to_owned(), 协议值::无符号值(文本值.chars().count() as u64)),
            ]),
            &区间起点,
        ),
        Err(错误) if 错误.kind() == std::io::ErrorKind::NotFound => 造失败应答(
            适配器,
            工具码::程序文本不存在,
            Some(协议值::对象值(vec![
                造键文对("动作", "读"),
                造键文对("路径", &取相对路径(工具根, &路径)),
                造键文对("缺什么", "该路径下没有这个件（读动作）"),
            ])),
            &区间起点,
        ),
        Err(错误) => 造失败应答(
            适配器,
            工具码::程序文本读不到,
            Some(协议值::对象值(vec![
                造键文对("动作", "读"),
                造键文对("路径", &取相对路径(工具根, &路径)),
                造键文对("为什么", &format!("件在，但读失败：{错误}（权限 / IO）")),
            ])),
            &区间起点,
        ),
    }
}

