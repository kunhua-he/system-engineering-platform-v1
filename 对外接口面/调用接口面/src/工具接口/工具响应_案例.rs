/// 一次读盘拿到的回执读数：可用行（原文与解析值）及跳过坏行数。
struct 回执读数 {
    可用行表: Vec<(String, 协议值)>,
    跳过坏行: usize,
}

/// 逐行容错读取回执，坏行跳过且计数。清单读共享审计日志，跑案例读本次独立目录。
fn 读回执(案例根: &Path) -> 回执读数 {
    let 路径 = 案例根.join(契约级常量::案例回执件);
    let Ok(文本值) = std::fs::read_to_string(&路径) else {
        // 件不存在 = 从没跑过。**这不是失败**（列案例照样列得出来），故给空读数。
        return 回执读数 {
            可用行表: Vec::new(),
            跳过坏行: 0,
        };
    };
    let mut 可用行表 = Vec::new();
    let mut 跳过坏行 = 0usize;
    for 源码行 in 文本值.lines() {
        match crate::协议解析::解析协议值(源码行) {
            Ok(待处理值) => 可用行表.push((源码行.to_owned(), 待处理值)),
            // 空行与截断行都拼不上：它们同样不是一条回执。
            Err(_) => 跳过坏行 += 1,
        }
    }
    回执读数 {
        可用行表, 跳过坏行
    }
}

/// 回执里某个案例名最近一条读数（取**最后**一条：回执是追加式的）。
fn 最新回执<'读数>(
    读数: &'读数 回执读数, 案例名: &str
) -> Option<&'读数 协议值> {
    读数.可用行表.iter().rev().find_map(|(_, 待处理值)| {
        (待处理值.取成员("案例名").and_then(协议值::取文本) == Some(案例名)).then_some(待处理值)
    })
}

/// `GET /接口/案例` → 案例清单（每个案例带「有没有回执」）。
///
/// **失败码 `9002 案例不存在`**：案例根读不到 ⇒ 整个案例库都不存在，
/// 于是「请求的案例标识在案例库里查不到」对**每一个**标识都成立 —— 这正是 9002 的说明。
/// （`9003` 是另一件事：「跑过但没回执」，只有跑案例端点会回它。）
pub fn 列案例(适配器: &适配器, 工具根: &Path) -> 协议值 {
    let 区间起点 = Instant::now();
    let 案例根 = 工具根.join(契约级常量::案例根);
    let 目录表 = match 列子目录(&案例根) {
        Ok(项表) => 项表,
        Err(说明文字) => {
            return 造失败应答(
                适配器,
                工具码::案例不存在,
                Some(协议值::对象值(vec![
                    造键文对("案例根", &取相对路径(工具根, &案例根)),
                    造键文对("缺什么", &说明文字),
                ])),
                &区间起点,
            );
        }
    };

    let 读数 = 读回执(&案例根);
    let mut 案例表 = Vec::new();
    for 标识 in 目录表 {
        let 声明件 = 案例根.join(&标识).join(契约级常量::案例声明件);
        // 没有 `案例.json` 的子目录**不是案例**（案例根下还有一个 `跑案例/` 是 crate 目录）——
        // 那不是「坏了」，是「不是案例」，故跳过。
        if !声明件.is_file() {
            continue;
        }
        // 有 `案例.json` 却读不了 ⇒ **如实列出来**（不静默跳过：跳过就是把它藏起来）。
        let 声明 = match 读JSON件(&声明件) {
            Ok(声明) => 声明,
            Err(说明文字) => {
                案例表.push(协议值::对象值(vec![
                    造键文对("案例标识", &标识),
                    造键文对("案例名", &标识),
                    ("有回执".to_owned(), 协议值::假值),
                    ("最新回执".to_owned(), 协议值::空值项),
                    造键文对("声明读不到", &说明文字),
                ]));
                continue;
            }
        };
        let 案例名 = 声明
            .取成员("案例名")
            .and_then(协议值::取文本)
            .unwrap_or(&标识)
            .to_owned();
        let 回执 = 最新回执(&读数, &案例名);
        let mut 对象成员 = vec![
            造键文对("案例标识", &标识),
            造键文对("案例名", &案例名),
            (
                "有回执".to_owned(),
                if 回执.is_some() {
                    协议值::真值
                } else {
                    协议值::假值
                },
            ),
        ];
        if let Some(说明文字) = 声明.取成员("说明").and_then(协议值::取文本) {
            对象成员.push(造键文对("说明", 说明文字));
        }
        match 回执 {
            Some(待处理值) => 对象成员.push(("最新回执".to_owned(), 待处理值.clone())),
            None => 对象成员.push(("最新回执".to_owned(), 协议值::空值项)),
        }
        案例表.push(协议值::对象值(对象成员));
    }

    造成功应答(
        协议值::对象值(vec![
            造键文对("案例根", &取相对路径(工具根, &案例根)),
            造键文对("回执件", 契约级常量::案例回执件),
            (
                "回执行数".to_owned(),
                协议值::整数项(读数.可用行表.len() as i64),
            ),
            ("跳过坏行".to_owned(), 协议值::整数项(读数.跳过坏行 as i64)),
            ("案例".to_owned(), 协议值::数组值(案例表)),
        ]),
        &区间起点,
    )
}

/// 目录创建以文件系统排他结果为准；同一时刻同进程也不假定时间戳唯一。
fn 创建回执目录(前缀路径: &Path) -> std::io::Result<std::path::PathBuf> {
    for 目录序号 in 0..1024 {
        let 候选目录 = 前缀路径.with_extension(目录序号.to_string());
        match std::fs::create_dir(&候选目录) {
            Ok(()) => return Ok(候选目录),
            Err(错误) if 错误.kind() == std::io::ErrorKind::AlreadyExists => continue,
            Err(错误) => return Err(错误),
        }
    }
    Err(std::io::Error::new(std::io::ErrorKind::AlreadyExists, "独立回执目录排他创建重试已耗尽"))
}

#[cfg(test)]
#[test]
fn 案例回执目录同前缀也互不覆盖() {
    let 前缀路径 = std::env::temp_dir().join(format!("案例目录排他验证-{}", std::process::id()));
    let 首次目录 = 创建回执目录(&前缀路径).unwrap();
    let 再次目录 = 创建回执目录(&前缀路径).unwrap();
    assert_ne!(首次目录, 再次目录);
    std::fs::remove_dir(首次目录).unwrap();
    std::fs::remove_dir(再次目录).unwrap();
}

/// `POST /接口/运维/案例` → 转调 `v1-case-runner`，只认**它这次新落的那一行**回执。
///
/// 三种结局，三种码：
///
/// | 观测到 | 回 | 为什么是这一个码 |
/// |---|---|---|
/// | 案例目录里没有 `案例.json` | `9002 案例不存在` | 标识查不到 |
/// | 跑者起不来 / 新行里没有本案例 | `9003 案例回执缺失` | 判据要的是「案例 + 回执」两件齐 |
/// | 新行里有本案例 | 成功 | `案例结果` 单独报「通过 / 失败」——**不把案例的失败写成动作的失败**（同 `形状.md` §二：调用结果与符合期望是两个字段） |
pub fn 跑案例(适配器: &适配器, 工具根: &Path, 案例标识: &str) -> 协议值 {
    let 区间起点 = Instant::now();
    let 案例根 = 工具根.join(契约级常量::案例根);
    let 声明件 = 案例根.join(案例标识).join(契约级常量::案例声明件);
    if !声明件.is_file() {
        return 造失败应答(
            适配器,
            工具码::案例不存在,
            Some(协议值::对象值(vec![
                造键文对("案例标识", 案例标识),
                造键文对("案例根", &取相对路径(工具根, &案例根)),
                造键文对(
                    "缺什么",
                    &format!(
                        "案例库里没有这个标识（该目录下没有 {}）",
                        契约级常量::案例声明件
                    ),
                ),
            ])),
            &区间起点,
        );
    }
    let 案例名 = 读JSON件(&声明件)
        .ok()
        .and_then(|待处理值| {
            待处理值
                .取成员("案例名")
                .and_then(协议值::取文本)
                .map(str::to_owned)
        })
        .unwrap_or_else(|| 案例标识.to_owned());

    // 每次调用只认独立落点，其他调用不能靠共享日志冒认。
    //
    // 落点走平台**唯一的运行数据根解析器**（`v1_dataroot` 的缓存类），不自行拼 `/tmp`：
    // 自行拼 = 第二个根来源（位置漂了没人拦，且 `/tmp` 里的回执会被系统清理带走）。
    // 解析不出根 ⇒ fail-closed，不退回源码树、不退回 `/tmp`（与装载件缓存同一条约定）。
    // 母目录就用缓存根本身（它一定已存在）—— 多插一层目录会让 `create_dir` 报 ENOENT，
    // 那不叫「解析不出根」，是自找的运行期失败。
    let 回执母目录 = match v1_adapter::装载件缓存::默认缓存根目录() {
        Some(缓存根) => 缓存根,
        None => return 造失败应答(
            适配器, 工具码::案例回执缺失,
            Some(协议值::对象值(vec![造键文对(
                "缺什么",
                "解析不出运行数据根：案例回执无处可落（不退回源码树 / `/tmp`）",
            )])),
            &区间起点,
        ),
    };
    let 临时目录 = 回执母目录.join(format!(
        "案例回执-{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos()
    ));
    let 临时目录 = match 创建回执目录(&临时目录) {
        Ok(临时目录) => 临时目录,
        Err(错误) => return 造失败应答(
            适配器, 工具码::案例回执缺失,
            Some(协议值::对象值(vec![造键文对("缺什么", &错误.to_string())])),
            &区间起点,
        ),
    };
    let 回执路径 = 临时目录.join(契约级常量::案例回执件);
    let 跑者 = 工具根.join(契约级常量::案例跑者);
    let 读数 = match 工具链::跑命令取读数(
        &跑者,
        &["--回执路径", &回执路径.to_string_lossy()],
        工具根,
    ) {
        Ok(读数) => 读数,
        Err(错误) => {
            let _ = std::fs::remove_dir_all(&临时目录);
            return 造失败应答(
                适配器,
                工具码::案例回执缺失,
                Some(协议值::对象值(vec![
                    造键文对("案例标识", 案例标识),
                    造键文对("案例跑者", &取相对路径(工具根, &跑者)),
                    造键文对("失败因", 错误.失败因()),
                    造键文对("缺什么", &错误.to_string()),
                ])),
                &区间起点,
            );
        }
    };

    let 跑后读数 = 读回执(&临时目录);
    let _ = std::fs::remove_dir_all(&临时目录);
    if !matches!(读数.退出码, 0 | 1) {
        return 造失败应答(
            适配器, 工具码::案例回执缺失,
            Some(协议值::对象值(vec![
                造键文对("案例标识", 案例标识),
                ("案例跑者退出码".to_owned(), 协议值::整数项(i64::from(读数.退出码))),
                造键文对("缺什么", "跑者工具异常，已有部分回执不能代表本次完整完成"),
                造键文对("案例跑者标准错误", &读数.标准错误),
            ])),
            &区间起点,
        );
    }
    let 新行 = &跑后读数.可用行表;
    let 本案例 = 新行.iter().rev().find_map(|(_, 待处理值)| {
        (待处理值.取成员("案例名").and_then(协议值::取文本) == Some(案例名.as_str()))
            .then_some(待处理值)
    });

    match 本案例 {
        Some(回执) => {
            let 案例结果 = 回执.取成员("结果").cloned().unwrap_or(协议值::空值项);
            造成功应答(
                协议值::对象值(vec![
                    造键文对("案例标识", 案例标识),
                    造键文对("案例名", &案例名),
                    ("案例结果".to_owned(), 案例结果),
                    ("回执".to_owned(), 回执.clone()),
                    (
                        "案例跑者退出码".to_owned(),
                        协议值::整数项(i64::from(读数.退出码)),
                    ),
                    // 坏行数一并报出：读端跳过几条必须看得见（静默跳过就是假绿）。
                    (
                        "跳过坏行".to_owned(),
                        协议值::整数项(跑后读数.跳过坏行 as i64),
                    ),
                ]),
                &区间起点,
            )
        }
        None => 造失败应答(
            适配器,
            工具码::案例回执缺失,
            Some(协议值::对象值(vec![
                造键文对("案例标识", 案例标识),
                造键文对("案例名", &案例名),
                造键文对("案例跑者", &取相对路径(工具根, &跑者)),
                (
                    "案例跑者退出码".to_owned(),
                    协议值::整数项(i64::from(读数.退出码)),
                ),
                造键文对("案例跑者标准输出", &读数.标准输出),
                造键文对("案例跑者标准错误", &读数.标准错误),
                造键文对(
                    "缺什么",
                    &format!(
                        "跑了但本次独立 {} 里没有本案例的回执行（新行 {} 条 · 跳过坏行 {} 条）",
                        契约级常量::案例回执件,
                        新行.len(),
                        跑后读数.跳过坏行
                    ),
                ),
            ])),
            &区间起点,
        ),
    }
}