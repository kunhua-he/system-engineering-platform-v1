/// 跑者门 —— 案例跑者往 `运行回执.jsonl` **追加**，而它的追加是**两次 `write_all`**
/// （先正文、再换行，见 `测试验证/案例/跑案例/src/回执.rs`）。两条用例并发调它，
/// 两次追加会交错、把行拼坏（坏回执行数 > 0）。故凡转调案例跑者的用例先过这道门。
static 跑者门: Mutex<()> = Mutex::new(());

fn 独占跑者() -> MutexGuard<'static, ()> {
    跑者门.lock().unwrap_or_else(|错误| 错误.into_inner())
}

/// 一件临时工具根：§七 工具族的**部署事实**（案例库 / 扩展根 / 外部 CLI 的所在）。
///
/// 为什么用临时根而不是真仓根：真仓根里的扩展根声明与目录口径不吻合，
/// 拿它造不出「列扩展成功」的正向样本。临时根让正反两条样本都由本件自身摆出。
struct 临时仓根(PathBuf);

impl 临时仓根 {
    fn 构造(名称: &str) -> Self {
        let 临时目录 = std::env::temp_dir().join(format!("v1-接口面工具族-{}-{名称}", std::process::id()));
        let _ = std::fs::remove_dir_all(&临时目录);
        std::fs::create_dir_all(&临时目录).expect("建临时工具根");
        Self(临时目录)
    }

    fn 取路径(&self) -> &Path {
        &self.0
    }

    fn 建目录(&self, 相对: &str) {
        std::fs::create_dir_all(self.0.join(相对)).expect("建目录");
    }

    fn 写文件(&self, 相对: &str, 内容: &str) {
        let 完整路径 = self.0.join(相对);
        std::fs::create_dir_all(完整路径.parent().expect("件必有父目录")).expect("建父目录");
        std::fs::write(&完整路径, 内容).expect("写件");
    }
}

impl Drop for 临时仓根 {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

/// 一条**该成功**的应答 → `数据`。成功形状与失败形状**互斥**，两处都钉住。
fn 取成功数据(造应答: &收到应答) -> 协议值 {
    assert_eq!(造应答.状态, 200, "业务结果一律 200：\n{}", 造应答.体);
    assert!(造应答.取逻辑值("成功"), "本条该成功：\n{}", 造应答.体);
    assert!(造应答.找成员("错误").is_none(), "成功不许带 错误 对象：\n{}", 造应答.体);
    assert!(造应答.找成员("耗时微秒").is_some(), "成功返回必须带 耗时微秒");
    造应答.取成员("数据")
}

/// 一条**该失败**的应答 → 断言「六项齐 + **码就是码** + 段位 9 + 200」。
///
/// **判据是码本身**：只断言「失败」对「把所有请求都判失败」毫无分辨力。
fn 断言失败码(造应答: &收到应答, 错误码: u64) {
    assert_eq!(
        造应答.状态, 200,
        "业务失败一律 200 + 成功: false，不许抛 5xx：\n{}",
        造应答.体
    );
    assert!(!造应答.取逻辑值("成功"), "失败必须报 成功: false：\n{}", 造应答.体);
    let 错误 = 造应答.取成员("错误");
    for 键名 in 错误体六项 {
        assert!(错误.取成员(键名).is_some(), "错误对象必须给「{键名}」：\n{}", 造应答.体);
    }
    assert_eq!(
        无符号值(&错误, "码"),
        错误码,
        "回的是**真错误码**（不许自造、不许把失败写成成功）：\n{}",
        造应答.体
    );
    assert_eq!(无符号值(&错误, "段位"), 9, "段位 9 = 接口面与构建验证那一层");
    assert!(造应答.找成员("耗时微秒").is_some(), "失败返回也必须带 耗时微秒");
}

