//! 接口面工具族测试 —— §七 六个旁路端点的真起服务实测。
//!
//! 与 `接口面测试.rs` 同一条口径：**真起服务、真发原始请求**（`std::net::TcpStream` 手写），
//! 每条用例都走完整生产路径（`TcpListener::accept` → 手写 HTTP → 路由 → 工具响应组装 → 造应答）。
//!
//! # 为什么单开一件（不往 `接口面测试.rs` 里加）
//!
//! `接口面测试.rs` 已 500 行（超 `项目文档/开发规范/开发规范.md` 的 400 行上限）。**超限即大文件债**，故工具族另起一件。
//!
//! # 判据对着谁
//!
//! | 用例组 | 对着的判据 |
//! |---|---|
//! | 正常路径（案例清单 · 案例跑 · 导出 · 列扩展） | §七 六个端点的返回形状 |
//! | 每条错误码的反向样本 | §七「失败一律回真错误码」· 每个码都不许自造 |
//! | 正反成对（列扩展） | `判据的可信性.md` 第五节：只有反向样本会纵容矫枉过正 |
//!
//! **每一条反向样本都断言「码本身」**，不是只断言「失败了」——后者对「把所有请求都判失败」
//! 这种矫枉过正毫无分辨力。

