//! 网关 · 注入与读数 —— [`crate::网关::服务`] 上「部署事实进 / 读数出」那一组口。
//!
//! 从 `网关.rs` 拆出（单源 ≤ 400 行 · `开发规范.md` 第六节）。拆法按**关注点**：
//! 父件管监听与请求处理（accept 循环 · 连接 · 分发），子件管**装配侧注入部署事实**与
//! **验证面读回来**。形状与理由一字未改（纯搬家）。
//!
//! 子件能读父件的私有字段（Rust 隐私：子模块看得见祖先的私有项）—— 故本件直接读写
//! `服务` 的字段，不需要父件为它开任何口子。

use std::path::{Path, PathBuf};
use std::sync::{Arc, RwLock};

use v1_adapter::适配器;
use v1_resource_gateway::资源网关口;

use super::服务;

impl 服务 {
    /// 换静态托管根（装配侧的口）。**`/` 与前端自身的件从这一刻起从新根取**。
    ///
    /// 为什么是「换」而不是构造参数：托管根与声明根不同 —— 声明根缺了根本起不来服务，
    /// 而托管根缺了只是 `/` 回 404（前端没有同源的家），服务照样能跑、接口照样能调。
    pub fn 托管静态根(mut self, 根目录: impl Into<PathBuf>) -> Self {
        self.静态根 = 根目录.into();
        self
    }

    /// 换工具根（装配侧的口）。**§七 工具族的案例库 / 扩展根 / 外部 CLI 从这一刻起从新根取。**
    ///
    /// 与 `托管静态根` 同一形状、同一理由：工具根是**部署事实**（不是契约里的数），
    /// 缺了只是那些运维端点回真错误码（9002 / 9007 / 9005），服务照样能跑。
    pub fn 工具根(mut self, 根目录: impl Into<PathBuf>) -> Self {
        self.工具根 = 根目录.into();
        self
    }

    /// 注入**扩展根声明路径**（运行期装载重扫的落点）。装配侧（`examples/启动网关`）
    /// 把 `--声明根` 那个路径注入进来。
    ///
    /// 与 `托管静态根` / `工具根` 同一条约定（部署事实 · 装配侧说了算），但**不给默认值**：
    /// 重扫一个猜出来的目录比不扫更坏 ⇒ 没注入时 `POST /接口/生命周期`（动作=装载）
    /// fail-closed 指路（`生命周期响应::装载` 报出「声明根未注入」）。
    pub fn 声明根(mut self, 根目录: impl Into<PathBuf>) -> Self {
        self.声明根 = Some(根目录.into());
        self
    }

    /// 注入**后缀表文本**（重扫时判候选用的后缀集）。与 `声明根` 同一条约定。
    pub fn 后缀表(mut self, 源文本: impl Into<String>) -> Self {
        self.后缀表文本 = Some(源文本.into());
        self
    }

    /// 换解包物缓存根（装配侧的口）。不给就用适配器默认（运行数据根的缓存类）——
    /// 与 `托管静态根` 同形：缺省走唯一落点，不退回源码树也不退回 `/tmp`。
    pub fn 缓存根目录(mut self, 根目录: impl Into<PathBuf>) -> Self {
        self.缓存根目录 = Some(根目录.into());
        self
    }

    /// 工具根（§七）。装配侧与测试读它来判「工具族接上了没有」。
    pub fn 取工具根(&self) -> &Path {
        &self.工具根
    }

    /// 启用调用留痕：容量与策略由装配侧给（生产装配在 `服务::绑定并托管`
    /// 里用契约常量 `留痕容量` + `丢最旧` 开；本口留给要换容量/策略的装配方）。
    ///
    /// 必须在**共享出去之前**调（`&mut self`）；开与不开发影响的是
    /// `GET /接口/留痕` 有没有内容，不影响任何调用结果（留痕不进关键路径）。
    pub fn 启用留痕(&mut self, 容量: u32, 策略: v1_adapter::丢弃策略) {
        Arc::make_mut(self.适配器.get_mut().unwrap_or_else(|中毒| 中毒.into_inner()))
            .启用留痕(容量, 策略);
    }

    /// **真正绑上的端口**。根端点的 `实际端口` 报的就是它（不报常量：测试与多实例下
    /// 报常量就是一个假事实）。
    pub fn 监听端口(&self) -> u16 {
        self.监听端口
    }

    /// 静态托管的根（`接口面形状.md` §五）。装配侧与测试读它来判「托管接上了没有」。
    pub fn 静态根(&self) -> &Path {
        &self.静态根
    }

    /// 唯一腿（验证面与装配用）。返回**执行引用**（`Arc` 克隆）：锁内取、锁外可长活；
    /// 调用方按 `&服务.适配器()` 取 `&适配器`（`Arc` 自动解引用）。
    pub fn 适配器(&self) -> Arc<适配器> {
        self.适配器.read().unwrap_or_else(|中毒| 中毒.into_inner()).clone()
    }

    /// **注入资源网关口**（装配侧的口）。在**共享出去之前**调（`&mut self`）——
    /// 与 `跨进程配置` / `声明根` / `后缀表` 同一条约定：资源声明根是**部署事实**，
    /// 装配侧说了算，网关不替它猜。
    ///
    /// 没注入就是**默认拒绍**那一档（空清单 = 什么都拒）——那不是「没配好」，
    /// 是本节点正确的默认值（`资源网关口.md` §二）。
    pub fn 注入资源关口(&mut self, 关口: 资源网关口) {
        self.资源关口 = RwLock::new(Arc::new(关口));
    }

    /// 取**资源关口引用**（验证面与装配用）。返回 `Arc` 克隆：锁内取、锁外可长活。
    pub fn 取资源关口(&self) -> Arc<资源网关口> {
        self.资源关口.read().unwrap_or_else(|中毒| 中毒.into_inner()).clone()
    }
}
