//! 接口面测试 · 无状态 / 多实例。
//!
//! 判据：`全局连接器与网关.md` 第六节：不让网关持有状态，才可重启、可多实例
//! （「不用全局单例实现全局唯一」）。

use crate::测试夹具::{发请求, 取请求, 交POST请求, 第一个能力号, 起服务};

