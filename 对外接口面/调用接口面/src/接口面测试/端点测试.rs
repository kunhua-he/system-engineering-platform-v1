/// `GET /接口` → 自描述根：**端点表 + 能力总清单 + 契约版本 + 端口来源**四样都得在。
///
/// 这是「第一次用不需要读文档就能调对」那条判据的落点：第一次调用拿到的就是说明书。
#[test]
fn 根端点_给出端点表与能力全量清单() {
    let 服务 = 起服务();
    let 造应答 = 发请求(&服务, &取请求("/接口"));
    assert_eq!(造应答.状态, 200);
    assert!(
        造应答.头.contains("application/json; charset=utf-8"),
        "响应头必须声明 application/json; charset=utf-8，实际：\n{}",
        造应答.头
    );
    let 根应答 = 造应答.取协议值();

    // 契约版本：**与注入的声明逐字段相等**（不是另写一个数、不是另存一份）。
    let 声明 = v1_adapter::底座声明();
    let 版本 = 根应答.取成员("契约版本").expect("根端点必须给 契约版本");
    for (键名, 期望) in [
        ("主", 声明.实现版本.主版本),
        ("次", 声明.实现版本.次),
        ("构建", 声明.实现版本.构建),
    ] {
        assert_eq!(
            无符号值(版本, 键名),
            期望 as u64,
            "契约版本.{键名} 必须来自注入的声明"
        );
    }
    assert_eq!(
        无符号值(&根应答, "声明格式号"),
        u64::from(声明.声明格式号.取号值()),
        "声明格式号必须来自注入的声明"
    );
    assert!(
        !文本(&根应答, "端口来源").is_empty(),
        "前端不写死端口 ⇒ 根端点必须带回「端口来源」那句话"
    );
    assert_eq!(
        无符号值(&根应答, "实际端口"),
        u64::from(服务.端口()),
        "报的必须是真正绑上的端口，不是常量"
    );

    // 端点表：四个，路径逐字（冻结件 §二）。
    let 路径: Vec<String> = 数组(&根应答, "端点")
        .iter()
        .map(|端点项| 文本(端点项, "路径"))
        .collect();
    assert_eq!(
        路径,
        vec!["/接口", "/接口/能力/<编号>", "/接口/调用", "/接口/声明"],
        "端点表必须是冻结件 §二 的那四个，一个不多一个不少"
    );
    assert!(
        数组(&根应答, "端点").iter().all(|端点项| 端点项.取成员("方法").is_some()),
        "每条端点都要带 方法"
    );

    // 能力：**全量**，不是首页（§三：不做分页）。
    let 能力 = 数组(&根应答, "能力");
    assert_eq!(
        能力.len(),
        服务.适配器().能力清单().len(),
        "能力清单必须是全量，不是首页"
    );
    assert!(!能力.is_empty(), "已装载的声明必须有可寻址的能力");
    for 能力项 in &能力 {
        for 键名 in ["编号", "名称", "参数个数", "返回类型"] {
            assert!(能力项.取成员(键名).is_some(), "能力摘要必须给「{键名}」");
        }
    }
}

/// `GET /接口/能力/<编号>` → 单条能力的完整契约：参数表（**行序即契约**）· 返回类型 ·
/// 可抛错误码。
#[test]
fn 能力端点_给出行序与可抛错误码() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 造应答 = 发请求(&服务, &取请求(&format!("/接口/能力/{编号}")));
    assert_eq!(造应答.状态, 200);
    assert!(造应答.取逻辑值("成功"));

    let 契约 = 造应答.取成员("契约");
    assert_eq!(无符号值(&契约, "编号"), u64::from(编号));

    let 参数表 = 数组(&契约, "参数表");
    assert_eq!(
        参数表.len(),
        服务.适配器().能力契约(编号).expect("读侧同一条路").参数表.len(),
        "参数表行数必须与适配器给的一致（行序即契约）"
    );
    assert!(!参数表.is_empty(), "底座命令 0 有一行入参");
    for 参数行 in &参数表 {
        for 键名 in ["名称", "类型标签", "状态位", "默认值"] {
            assert!(参数行.取成员(键名).is_some(), "参数行必须给「{键名}」");
        }
    }
    assert!(契约.取成员("返回类型").is_some(), "返回类型必须显式给出");

    // 可抛错误码：**这条命令自身的**那张（源 = `命令信息.可抛错误码`）。
    // 底座命令 0 的执行函数不抛错 ⇒ 空表（不是「声明没登记错误码」——声明全表另有其口，
    // 走适配器 `声明错误码表`，见 `错误形状.rs`）。
    let 码表 = 数组(&契约, "可抛错误码");
    assert!(
        码表.is_empty(),
        "底座命令 0 自身不抛错 ⇒ 可抛错误码是空表（不是声明全表）"
    );
}

/// `GET /接口/能力/<编号>` 未命中：**不是 404** —— 路径存在、请求也合法，
/// 是这个号没人认领。按 §三 的失败形状给 `成功: false` + `码 1 提供者未载入`。
#[test]
fn 能力端点_未命中的号是200加成功假加六项() {
    let 服务 = 起服务();
    let 造应答 = 发请求(&服务, &取请求("/接口/能力/999999"));
    assert_eq!(造应答.状态, 200, "未命中是业务结果，不是协议失败");
    assert!(!造应答.取逻辑值("成功"));
    let 错误 = 造应答.取成员("错误");
    for 键名 in 错误体六项 {
        assert!(错误.取成员(键名).is_some(), "错误对象必须给「{键名}」");
    }
    assert_eq!(无符号值(&错误, "码"), 1, "未命中 = 提供者未载入");
    assert_eq!(文本(&错误, "名称"), "提供者未载入");
    assert!(取逻辑值(&错误, "可自愈"), "名称与三项必须从声明现读，不是编的");
}

/// `POST /接口/调用` 调得通：`成功: true` + `值` 数组 + `耗时微秒`。
#[test]
fn 调用端点_调得通并给出结构化结果() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 参数个数 = 服务.适配器().能力契约(编号).expect("契约").参数表.len();
    let 空位 = "{\"类型标签\":0,\"值\":0}";
    let 值数组文本 = vec![空位; 参数个数].join(",");
    let 请求体 = format!("{{\"编号\":{编号},\"值\":[{值数组文本}]}}");
    let 造应答 = 发请求(&服务, &交POST请求("/接口/调用", &请求体));

    assert_eq!(造应答.状态, 200);
    assert!(造应答.取逻辑值("成功"), "调得通：\n{}", 造应答.体);
    let 返回值表 = 造应答.取数组("值");
    assert!(!返回值表.is_empty(), "成功必须带返回值数组");
    assert!(
        返回值表[0].取成员("类型标签").is_some(),
        "每一项自带 类型标签 ⇒ 不需要二次解析（§三 判据）"
    );
    assert!(造应答.找成员("耗时微秒").is_some(), "成功返回必须带 耗时微秒");
}

/// `POST /接口/调用` 参数个数不符：**业务失败**（200 + `成功: false` + 码 3），
/// **不是 400** —— 参数个数是调度的判定，不是协议层的判定。
#[test]
fn 调用端点_参数个数不符是业务失败不是400() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 请求体 = format!("{{\"编号\":{编号},\"值\":[]}}");
    let 造应答 = 发请求(&服务, &交POST请求("/接口/调用", &请求体));

    assert_eq!(造应答.状态, 200, "业务失败不许进 HTTP 状态码");
    assert!(!造应答.取逻辑值("成功"));
    let 错误 = 造应答.取成员("错误");
    assert_eq!(无符号值(&错误, "码"), 3);
    assert_eq!(文本(&错误, "名称"), "参数个数不符");
    assert_eq!(无符号值(&错误, "段位"), 0, "段位按 码 / 号段类宽度 导出");
}

/// `POST /接口/声明` → **未实现**，且必须在返回里点名这件事（§四 面校验失败形状）。
#[test]
fn 声明端点_返回未实现的结构化错误并点名这件事() {
    let 服务 = 起服务();
    let 请求体 = "{\"类别\":\"能力\",\"编号\":null,\"正文\":{\"名称\":\"反解容器\",\"返回类型\":5}}";
    let 造应答 = 发请求(&服务, &交POST请求("/接口/声明", 请求体));

    assert_eq!(造应答.状态, 200, "未实现是结构化错误，不是协议失败");
    assert!(!造应答.取逻辑值("成功"));
    let 校验 = 造应答.取数组("校验");
    let 校验项 = 校验.first().expect("校验失败必须至少给一项");
    for 键名 in ["项", "缺什么", "为什么不能自愈"] {
        assert!(校验项.取成员(键名).is_some(), "校验项必须给「{键名}」");
    }
    let 缺什么 = 文本(校验项, "缺什么");
    assert!(
        缺什么.contains("未实现"),
        "必须在返回里点名「未实现」这件事：{缺什么}"
    );
    let 为什么 = 文本(校验项, "为什么不能自愈");
    assert!(
        !为什么.contains("需要人工确认"),
        "§四 明令：不许写「需要人工确认」这种废话：{为什么}"
    );
    assert!(
        为什么.contains("声明编写面"),
        "必须说清是哪一个事实挡住了自动补全：{为什么}"
    );
}
