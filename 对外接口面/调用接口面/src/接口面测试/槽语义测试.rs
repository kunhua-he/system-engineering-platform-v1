// 分类表（`组装应答` 的 match）：错误槽里的码 → 重试判据三值
//
// 判据：§九.3 那张表（「执行前拒绝」vs「超时 / 断连 / 崩溃 ⇒ 结果未知」）。
// 为什么单列这组：分类表只有 34（`必证五` 真网关）与 else 档（上面那条 1135）有验收，
// 中间两档（4/27 与 1/2/3/5/25）没有单测 —— 分类表一旦被改错，上面两条用例抓不到。
// ════════════════════════════════════════════════════════════════════════════

/// 造一个错误槽：与三处写方逐字同形（类型标签 = 错误 · 值 = 4 位码）。
fn 造错误槽(错误码值: u32) -> v1_adapter::数据槽 {
    v1_adapter::数据槽::内联槽(crate::常量::类型标签::错误.into(), u64::from(错误码值), 0)
}

/// 取 `重试判据` 里的一个逻辑项。
fn 取判据逻辑(判据: &crate::协议值::协议值, 键名: &str) -> bool {
    match 判据.取成员(键名) {
        Some(crate::协议值::协议值::真值) => true,
        Some(crate::协议值::协议值::假值) => false,
        其余值 => panic!("重试判据里的「{键名}」应当是逻辑型，实际 {其余值:?}"),
    }
}

/// **载体失败码 4 / 27 / 34 ⇒ 结果未知**（§九.3 第三行：执行已发起、结果拿不到，不自动重放）。
#[test]
fn 分类表_载体失败码结果未知() {
    let 服务 = 起服务();
    for 错误码值 in [4u32, 27, 34] {
        let 待处理值 = crate::响应::组装应答(
            &服务.适配器(),
            1101,
            v1_adapter::转发结果::成功(造错误槽(错误码值)),
            5,
            &契约身份(),
        );
        assert!(!取逻辑值(&待处理值, "成功"), "码 {错误码值} 是失败");
        let 判据 = 待处理值.取成员("重试判据").expect("失败必须带 重试判据");
        assert_eq!(源文本(判据, "执行阶段"), "已进入扩展", "码 {错误码值}：执行后判");
        assert!(取判据逻辑(判据, "可能已执行"), "码 {错误码值}：执行已发起");
        assert!(!取判据逻辑(判据, "结果确定"), "码 {错误码值}：结果未知，不许当可安全重放");
    }
}

/// **执行前拒绝码 1 / 2 / 3 / 5 / 25 ⇒ 未进入扩展**（§九.3 第一行）。
#[test]
fn 分类表_执行前拒绝码未进入扩展() {
    let 服务 = 起服务();
    for 错误码值 in [1u32, 2, 3, 5, 25] {
        let 待处理值 = crate::响应::组装应答(
            &服务.适配器(),
            1101,
            v1_adapter::转发结果::成功(造错误槽(错误码值)),
            5,
            &契约身份(),
        );
        assert!(!取逻辑值(&待处理值, "成功"), "码 {错误码值} 是失败");
        let 判据 = 待处理值.取成员("重试判据").expect("失败必须带 重试判据");
        assert_eq!(源文本(判据, "执行阶段"), "未进入扩展", "码 {错误码值}：调度在 执行 之前返回");
        assert!(!取判据逻辑(判据, "可能已执行"), "码 {错误码值}：没进扩展");
        assert!(取判据逻辑(判据, "结果确定"), "码 {错误码值}：结果确定（就是没执行）");
    }
}
