//! 接口面测试 · 槽语义 —— 转发成功但返回槽是错误槽时，顶层必须 `成功: false`。
//!
//! 判据：`接口面形状.md` §三「成功没成功 —— `成功` 布尔，不靠猜」。
//! 执行函数把业务失败**写在返回槽里**（类型标签 4294967295 · 值 = 4 位码），而适配器的
//! `转发结果::成功` 只担保协议层成立 ⇒ 顶层 `成功` 必须读槽。
//!
//! **这两条互为反向样本**（`判据的可信性.md` 第五节）：只补「错误槽 ⇒ false」会纵容
//! 「把所有返回都判失败」这种矫枉过正；只补「正常槽 ⇒ true」则正是改前的缺陷本身。

use crate::测试夹具::{
    发, 交请求, 布尔, 六项, 无符号, 数组, 第一个能力号, 起服务,
};

/// 判据：返回槽是**错误槽** ⇒ 顶层 `成功: false` + 六项错误对象 + `耗时微秒`。
///
/// 实测来源（真网关 · `启动网关` + 现编的 `编译器支持库.dylib`）：调 1101 送
/// `类型标签 5`（字节集）⇒ 执行函数把 `参数槽不符`（码 1135）写进返回槽，**改前**顶层报的
/// 是 `成功: true`（`值:[{类型标签:4294967295,值:1135}]`）—— 与 §三 直接相抵。
/// 本用例是那条实测在测试层的钉法（真网关读数见回执）。
#[test]
fn 错误槽_顶层报成功假并填六项() {
    let 服务 = 起服务();
    // 错误槽的形状与三处写方逐字同形（占位项 · 边界面 · 编译器支持库的写错误码）。
    let 错误槽 = v1_adapter::数据槽::内联(crate::常量::类型标签::错误.into(), 1135, 0);
    let 值 = crate::响应::组装(服务.适配器(), 1101, v1_adapter::转发结果::成功(错误槽), 7);

    assert!(
        !布尔(&值, "成功"),
        "转发成功但返回槽是错误槽 ⇒ 顶层必须 成功: false（§三：不靠猜）"
    );
    let 错误 = 值.取("错误").expect("失败必须带 错误 对象");
    for 键 in 六项 {
        assert!(错误.取(键).is_some(), "错误对象必须给「{键}」");
    }
    assert_eq!(无符号(错误, "码"), 1135, "码取自返回槽的 值");
    assert_eq!(无符号(错误, "段位"), 1, "段位按 码 / 号段类宽度 导出");
    assert_eq!(无符号(&值, "耗时微秒"), 7, "失败返回也必须带 耗时微秒");
    assert!(
        值.取("值").is_none(),
        "失败返回**不许**再带 值 数组（那是成功形状的一半）：\n{值:?}"
    );
}

/// 判据：**正常成功槽 ⇒ 顶层 `成功: true`**（防矫枉过正把真成功也判成失败）。
///
/// 样本取**真调用**的返回槽：底座命令 0 的执行函数写的就是这种非错误槽（见
/// `运行内核/装载入口/src/底座静态声明.rs` 的 `底座取平台信息`）。
#[test]
fn 正常成功槽_顶层仍报成功真() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 参数个数 = 服务.适配器().能力契约(编号).expect("契约").参数表.len();
    let 空位 = "{\"类型标签\":0,\"值\":0}";
    let 体 = format!(
        "{{\"编号\":{编号},\"值\":[{}]}}",
        vec![空位; 参数个数].join(",")
    );
    let 应答 = 发(&服务, &交请求("/接口/调用", &体));
    // 内联槽（不碰指针）：本用例只判「非错误槽 ⇒ 成功」这条槽语义。
    let 真槽 = v1_adapter::数据槽::内联(crate::常量::类型标签::整数.into(), 42, 0);

    // 真调用（真链路）与同一形状的槽喂进组装，两条都必须报成功。
    assert!(
        应答.取布尔("成功"),
        "正常成功槽不许被判成失败：\n{}",
        应答.体
    );
    let 值 = crate::响应::组装(服务.适配器(), 编号, v1_adapter::转发结果::成功(真槽), 3);
    assert!(布尔(&值, "成功"), "非错误槽 ⇒ 顶层 成功: true");
    assert_eq!(数组(&值, "值").len(), 1, "成功必须带返回值数组");
    assert!(
        值.取("错误").is_none(),
        "成功返回**不许**带 错误 对象：\n{值:?}"
    );
}
