//! 接口面测试 · 可判字段 —— 三个旁路字段（`追踪标识` / `截断` / `四问`）的机器可判证据。
//!
//! # 缺的是什么（调用应答可判字段三件的判据段）
//!
//! 实现侧三个字段已落（`响应.rs` 的 `追踪标识` + `截断` · `契约响应.rs` 的 `四问`），
//! 但**没有一条判据盯着它们**：删掉字段、写错值、把四问只答一问，`GET /接口` 与
//! `POST /接口/调用` 的既有用例照样绿（它们只核端点表路径与 `成功` / `值` / `耗时微秒`）。
//! 本件把三个字段钉死 —— 「机器可判」这句话的落点就是这里。
//!
//! # 三条口径（不许假设）
//!
//! 1. **追踪标识不是编的**：它与 `GET /接口/留痕` 里**这一次调用**那条的 `追踪号` 必须同号，
//!    且同一实例内逐次递增 1（`适配器定义.rs::调用能力带追踪` 在进调用时取一次，两处共用）。
//! 2. **截断恒假**：本面无静默截断（值原样交回）⇒ `截断` 必须是假，不是省掉键。
//! 3. **四问逐问落字段**：`GET /接口` 的每个 `端点` / `旁路端点` 条目都带 `四问` 对象，
//!    四键**逐字**齐（缺一问 = 没答全），后两问全网关**同一口径**（取具名常量，不在各端点各写一份）。

use crate::协议值::协议值;
use crate::测试夹具::{
    发请求, 取请求, 交POST请求, 取逻辑值, 错误体六项, 无符号值, 源文本, 取成员数组, 第一个能力号,
    起服务, 契约身份,
};

/// 一个空位槽的 JSON 文本（`接口面形状.md` §三：空位也必须写出来，不许省略位次）。
const 空槽文本: &str = "{\"类型标签\":0,\"值\":0}";

/// 造一条 `POST /接口/调用` 的请求体：编号 + 按契约行序的槽文本表。
fn 造调用体(编号: u32, 槽表文本: &[&str]) -> String {
    format!("{{\"编号\":{编号},\"值\":[{}]}}", 槽表文本.join(","))
}

/// 按契约行数造全部空位槽的请求体（底座首条命令只吃空位）。
fn 造空位调用体(服务: &crate::网关::服务) -> String {
    let 编号 = 第一个能力号(服务);
    let 参数个数 = 服务.适配器().能力契约(编号).expect("契约").参数表.len();
    let 槽表: Vec<&str> = vec![空槽文本; 参数个数];
    造调用体(编号, &槽表)
}

/// 取 `GET /接口/留痕` 的 `数据.留痕` 数组（不是成功就挂，带原文）。
fn 取留痕表(服务: &crate::网关::服务) -> Vec<协议值> {
    let 留痕应答 = 发请求(服务, &取请求("/接口/留痕"));
    assert_eq!(留痕应答.状态, 200, "取留痕是只读端点：\n{}", 留痕应答.报文体);
    assert!(留痕应答.取逻辑值("成功"), "取留痕必须成功：\n{}", 留痕应答.报文体);
    取成员数组(&留痕应答.取成员("数据"), "留痕")
}

// ═══════════════════════════════════════════════════════
// 一 四问（§9.1：工具描述回答四问）
// ═══════════════════════════════════════════════════════

/// `GET /接口` 的**每个**端点条目（§二 四个 + §七 旁路十四个）都带 `四问` 对象，四键逐字齐、答文非空。
#[test]
fn 根端点_每个端点都答四问四键() {
    let 服务 = 起服务();
    let 根应答 = 发请求(&服务, &取请求("/接口")).取协议值();
    for 栏名 in ["端点", "旁路端点"] {
        let 端点表项 = 取成员数组(&根应答, 栏名);
        assert!(!端点表项.is_empty(), "「{栏名}」不许是空表");
        for 端点条目 in &端点表项 {
            let 路径 = 源文本(端点条目, "路径");
            let 四问对象 = 端点条目
                .取成员("四问")
                .cloned()
                .unwrap_or_else(|| panic!("端点「{路径}」没答四问：\n{端点条目:?}"));
            let 协议值::对象值(四问成员) = 四问对象 else {
                panic!("端点「{路径}」的四问必须是对象");
            };
            let 问名表: Vec<&str> = 四问成员.iter().map(|(键名, _)| 键名.as_str()).collect();
            assert_eq!(
                问名表,
                crate::常量::四问键名.to_vec(),
                "端点「{路径}」的四问键集必须逐字等于 §9.1 那四问（缺一问 = 没答全）"
            );
            for (问名, 答文) in 四问成员 {
                let 答文本 = 答文
                    .取文本()
                    .unwrap_or_else(|| panic!("端点「{路径}」的「{问名}」必须是文本，实际 {答文:?}"));
                assert!(!答文本.is_empty(), "端点「{路径}」的「{问名}」答了空话 = 没答");
            }
        }
    }
}

/// 后两问（执行保障 / 失败后下一步）**全网关同一口径**：每个端点逐字等于具名常量。
///
/// 为什么单开一条：只核「四键齐」会纵容「十八个端点各写一份散文」——同一份保证两处来源、
/// 必然漂。这一条把「只此一份」钉住（常量在 `常量.rs`，端点表里不许另写）。
#[test]
fn 根端点_执行保障与失败后下一步全端点同一口径() {
    let 服务 = 起服务();
    let 根应答 = 发请求(&服务, &取请求("/接口")).取协议值();
    let 问名 = crate::常量::四问键名;
    for 栏名 in ["端点", "旁路端点"] {
        for 端点条目 in &取成员数组(&根应答, 栏名) {
            let 路径 = 源文本(端点条目, "路径");
            let 四问对象 = 端点条目.取成员("四问").cloned().expect("上一条用例已证四问在");
            assert_eq!(
                源文本(&四问对象, 问名[2]),
                crate::常量::四问_执行保障,
                "端点「{路径}」的「执行保障」与全网关口径不一致（同一事实两处来源）"
            );
            assert_eq!(
                源文本(&四问对象, 问名[3]),
                crate::常量::四问_失败后下一步,
                "端点「{路径}」的「失败后下一步」与全网关口径不一致"
            );
        }
    }
}

// ═══════════════════════════════════════════════════════
// 二 追踪标识（§9.2：结构化结果保留追踪标识）
// ═══════════════════════════════════════════════════════

/// 成功应答的 `追踪标识` **就是**留痕里这次的 `追踪号`，且同一实例内逐次递增 1。
///
/// 判据的承重点：两处号必须**同一个**（不是应答一个号、留痕一个号）—— 那正是「同一事实
/// 两处来源」的形态。递增用来证它不是常量。
#[test]
fn 调用应答_成功支追踪标识与留痕追踪号同号且递增() {
    let 服务 = 起服务();
    let 请求体 = 造空位调用体(&服务);
    let 首应答 = 发请求(&服务, &交POST请求("/接口/调用", &请求体));
    assert!(首应答.取逻辑值("成功"), "底座首条命令调得通：\n{}", 首应答.报文体);
    let 首号 = 无符号值(&首应答.取协议值(), "追踪标识");
    let 次应答 = 发请求(&服务, &交POST请求("/接口/调用", &请求体));
    assert!(次应答.取逻辑值("成功"), "\n{}", 次应答.报文体);
    let 次号 = 无符号值(&次应答.取协议值(), "追踪标识");
    assert_eq!(次号, 首号 + 1, "同一实例内追踪号逐次递增 1（不落进程级全局）");

    let 留痕表 = 取留痕表(&服务);
    assert_eq!(留痕表.len(), 2, "两次调用 ⇒ 恰好两条留痕");
    assert_eq!(
        无符号值(&留痕表[0], "追踪号"),
        首号,
        "应答的追踪标识必须就是留痕里的 追踪号（同一个号，不是两套）"
    );
    assert_eq!(无符号值(&留痕表[1], "追踪号"), 次号);
}

/// **失败调用也带追踪标识与截断标识**（§9.2 说的是「结构化结果」，不分成功失败）。
#[test]
fn 调用应答_失败支也带追踪标识与截断标识() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    // 参数个数不符 ⇒ 执行前拒绝（码 3），业务失败但进过留痕。
    let 造应答 = 发请求(
        &服务,
        &交POST请求("/接口/调用", &format!("{{\"编号\":{编号},\"值\":[]}}")),
    );
    assert_eq!(造应答.状态, 200, "业务失败不进 HTTP 状态码");
    assert!(!造应答.取逻辑值("成功"));
    let 应答值 = 造应答.取协议值();
    let 错误 = 应答值.取成员("错误").expect("失败必须带 错误");
    for 键名 in 错误体六项 {
        assert!(错误.取成员(键名).is_some(), "错误对象必须给「{键名}」");
    }
    assert_eq!(无符号值(错误, "码"), 3);
    let 追踪号 = 无符号值(&应答值, "追踪标识");
    assert!(!取逻辑值(&应答值, "截断"), "失败支无值可截 ⇒ 截断 必须是假");

    let 留痕表 = 取留痕表(&服务);
    assert_eq!(留痕表.len(), 1, "失败调用也要留痕（跨边界可追溯不分成败）");
    assert_eq!(
        无符号值(&留痕表[0], "追踪号"),
        追踪号,
        "失败应答的追踪标识也要与留痕同号"
    );
}

// ═══════════════════════════════════════════════════════
// 三 截断标识 · 零值 / 空列表（§9.2：不因省字符改变返回语义）
// ═══════════════════════════════════════════════════════

/// 成功调用的 `截断` 恒假，且 `成功` / `值` / `耗时微秒` / `追踪标识` / `截断` 一律出现。
#[test]
fn 调用应答_截断标识恒假且值不省略() {
    let 服务 = 起服务();
    let 造应答 = 发请求(&服务, &交POST请求("/接口/调用", &造空位调用体(&服务)));
    let 应答值 = 造应答.取协议值();
    assert!(取逻辑值(&应答值, "成功"), "\n{}", 造应答.报文体);
    assert!(
        !取逻辑值(&应答值, "截断"),
        "本面无静默截断 ⇒ 截断 必须是假（与搜索响应的分页 截断 同一键名同一含义）"
    );
    for 键名 in ["成功", "值", "耗时微秒", "追踪标识", "截断"] {
        assert!(应答值.取成员(键名).is_some(), "成功应答必须给「{键名}」：\n{应答值:?}");
    }
    let 值表 = 取成员数组(&应答值, "值");
    assert_eq!(值表.len(), 1, "底座首条命令回一个槽 ⇒ 值 数组恰一项，不多不少");
    for 槽项 in &值表 {
        for 键名 in ["类型标签", "值"] {
            assert!(槽项.取成员(键名).is_some(), "槽必须显式给「{键名}」（零也要写出来）");
        }
    }
}

/// **零值槽跨接口面不许被省成「没有值」**（§9.2 的 `0` 有契约含义）。
#[test]
fn 零值槽_组装应答里显式写出零而不是省略() {
    let 服务 = 起服务();
    let 零值槽 = v1_adapter::数据槽::内联槽(crate::常量::类型标签::整数标签.into(), 0, 0);
    let 待处理值 = crate::响应::组装应答(
        &服务.适配器(),
        0,
        v1_adapter::转发结果::成功(零值槽),
        1,
        &契约身份(),
        0,
    );
    let 值表 = 取成员数组(&待处理值, "值");
    assert_eq!(值表.len(), 1, "零值也是一个值 ⇒ 值 数组恰一项");
    assert_eq!(无符号值(&值表[0], "值"), 0, "零要显式写出来，不是省略");
}
