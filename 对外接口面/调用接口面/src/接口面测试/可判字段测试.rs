/// **可用位对着当场能力清单判**，且无号段的声明**不编假**（§32.4：能力不存在与暂时未就绪分得开）。
#[test]
fn 生命周期读数_可用位对着当场能力清单且无号段不编假() {
    let 服务 = 起服务();
    let 就绪数据 = 取就绪数据(&服务);
    let 逐份 = 取成员数组(&就绪数据, "逐份就绪");
    let 清单条数 = 服务.适配器().能力清单().len();
    let 可寻址合计: usize = 逐份
        .iter()
        .map(|一份| 无符号值(一份, "号段内可寻址号数") as usize)
        .sum();
    assert_eq!(
        可寻址合计, 清单条数,
        "逐份号段内可寻址号数之和必须等于当场能力清单条数"
    );
    for 一份 in &逐份 {
        let 号段空 = 取成员数组(一份, "能力号段").is_empty();
        let 判据文本 = 源文本(一份, "就绪判据");
        if 号段空 {
            assert_eq!(判据文本, "无号段无从判", "无号段 = 本面无从判，不许编假");
            assert!(
                !取逻辑值(一份, "是否可用"),
                "无从判时 是否可用 必须是假，不是真"
            );
        } else {
            assert_ne!(判据文本, "无号段无从判", "有号段却说无从判 = 丢判据");
        }
    }
}

/// 判定层级：§22.4 五级（本地自检 ≠ 构建 ≠ 准入 ≠ 就绪 ≠ 调用成功）与
/// 方案 §18.3-6 四类（自检 / 准入 / 部署 / 业务执行 **必须分别判定**）合一条链 ——
/// 每一档都各自有 `已判` 与 `说明`，不许把两种"成功"混为一档。
#[test]
fn 生命周期读数_判定层级齐且每级有说明() {
    let 服务 = 起服务();
    let 就绪数据 = 取就绪数据(&服务);
    let 层级表 = 取成员数组(&就绪数据, "判定层级");
    let 层级名: Vec<String> = 层级表.iter().map(|一级| 源文本(一级, "层级")).collect();
    assert_eq!(
        层级名,
        vec!["本地自检", "构建", "准入", "部署", "就绪", "业务执行", "调用成功"],
        "七级必须齐且按序（本地自检 ≠ 构建 ≠ 准入 ≠ 部署 ≠ 就绪 ≠ 业务执行 ≠ 调用成功）"
    );
    // 18.3-6：四种"成功"各自单列一档 —— 缺任一档就是"自检/准入/部署/业务执行"四项被并成一档。
    for 必在各档 in ["本地自检", "准入", "部署", "业务执行"] {
        assert!(
            层级名.contains(&必在各档.to_owned()),
            "十八点三之六要四类分别判定，缺「{必在各档}」档"
        );
    }
    for 一级 in &层级表 {
        let 说明 = 源文本(一级, "说明");
        assert!(!说明.is_empty(), "每一级都要说清判了什么 / 为何未判：\n{一级:?}");
        assert!(
            一级.取成员("已判").is_some(),
            "每一级都要给可机器判的 已判 位"
        );
    }
    // 本案能现判的是本地自检（声明已载入、六步跑过）⇒ 它必须报已判。
    let 本地自检 = 层级表
        .iter()
        .find(|一级| 源文本(一级, "层级") == "本地自检")
        .expect("上一条已证");
    assert!(取逻辑值(本地自检, "已判"), "本地自检是本案能现判的一级");
}

