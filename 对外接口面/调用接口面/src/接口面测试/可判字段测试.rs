/// 十二类**逐类**出现，每类四键逐字齐（`类目` · `已判` · `说明` · `证据口`）且说明非空。
///
/// 缺一类、漏一键、少一个 `已判` 位，读的人就得猜「这一类到底判没判」—— 本用例把它钉死。
#[test]
fn 生命周期_接入回执十二类逐类四键齐() {
    const 十二类: [&str; 12] = [
        "身份", "兼容", "能力", "依赖", "构建", "副作用", "运行", "就绪", "观测", "资源", "升级", "验证",
    ];
    let 服务 = 起服务();
    let 应答 = 发请求(&服务, &取请求("/接口/运维/生命周期"));
    assert_eq!(应答.状态, 200, "生命周期是只读端点：\n{}", 应答.报文体);
    let 应答数据 = 应答.取成员("数据");
    let 回执表 = 取成员数组(&应答数据, "接入回执");
    assert_eq!(回执表.len(), 12, "接入回执必须是十二类逐类：\n{回执表:?}");
    for (序号, 类目名) in 十二类.iter().enumerate() {
        let 回执条目 = &回执表[序号];
        assert_eq!(源文本(回执条目, "类目"), *类目名, "第 {序号} 类的类目名不符");
        let 说明文字 = 源文本(回执条目, "说明");
        assert!(!说明文字.is_empty(), "「{类目名}」的说明不许空（判不了也要交代为什么）");
        let 证据口 = 源文本(回执条目, "证据口");
        assert!(!证据口.is_empty(), "「{类目名}」的证据口不许空（判不了也要指路）");
        let 读到已判: bool = 取逻辑值(回执条目, "已判");
        let _ = 读到已判;
    }
}

/// 承重：十二类里「身份」与「就绪」两类**能现判**（装好底座自身声明后为真），
/// 「构建」与「验证」两类本面判不了 ⇒ 必须如实为假（不假报绿灯）。
///
/// 把任一类写成恒真 / 恒假，本用例当场红。
#[test]
fn 生命周期_接入回执现判与未判分得开() {
    let 服务 = 起服务();
    let 应答 = 发请求(&服务, &取请求("/接口/运维/生命周期"));
    assert_eq!(应答.状态, 200);
    let 回执表 = 取成员数组(&应答.取成员("数据"), "接入回执");
    let 取已判 = |类目名: &str| -> bool {
        let 回执条目 = 回执表
            .iter()
            .find(|回执条目| 源文本(回执条目, "类目") == 类目名)
            .unwrap_or_else(|| panic!("缺类目「{类目名}」"));
        取逻辑值(回执条目, "已判")
    };
    assert!(取已判("身份"), "装了声明就有身份可判");
    assert!(取已判("就绪"), "入口起服务后能力清单非空 ⇒ 就绪可判");
    assert!(!取已判("构建"), "构建（cargo）不在本进程内 ⇒ 必须如实为假");
    assert!(!取已判("验证"), "发布验收是独立夹具 ⇒ 本面必须如实为假");
}

