/// 命名形态：按**参数名**给值 ⇒ 本面按契约 `参数表` 的 `名称` 映射成行序，与位置形态同结果。
///
/// 判据的承重点：同一份入参用命名给与用位置给，**返回的 `值` 必须逐字相同** —— 那就证明
/// 映射真的落在契约行序上，而不是另造一套。
#[test]
fn 命名参数按名映射行序() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 契约 = 服务.适配器().能力契约(编号).expect("契约");
    // 按契约参数表逐行给命名体（行序由名字映射回去，不靠请求体里的键序）。
    let 键值对: Vec<String> = 契约
        .参数表
        .iter()
        .map(|参数行| format!("\"{}\":{空槽文本}", 参数行.名称))
        .collect();
    let 命名体 = format!("{{{}}}", 键值对.join(","));
    let 命名应答 = 发请求(
        &服务,
        &交POST请求(
            "/接口/调用",
            &format!("{{\"编号\":{编号},\"命名值\":{命名体}}}"),
        ),
    );
    assert_eq!(命名应答.状态, 200, "命名形态是合法请求：\n{}", 命名应答.报文体);
    assert!(
        命名应答.取逻辑值("成功"),
        "命名形态必须与位置形态同结果：\n{}",
        命名应答.报文体
    );

    let 位置应答 = 发请求(
        &服务,
        &交POST请求("/接口/调用", &造空位调用体(&服务)),
    );
    assert!(位置应答.取逻辑值("成功"), "\n{}", 位置应答.报文体);
    assert_eq!(
        命名应答.取成员("值"),
        位置应答.取成员("值"),
        "命名形态与位置形态同入参 ⇒ 返回值必须逐字相同（映射落点就是契约行序）"
    );
}

/// 未知参数 / 缺参数 / 两形态并列 ⇒ 400，且错误里**点名具体参数**（不是「第几位」）。
#[test]
fn 命名参数未知名缺参与两形态并列() {
    let 服务 = 起服务();
    let 编号 = 第一个能力号(&服务);
    let 契约 = 服务.适配器().能力契约(编号).expect("契约");
    let 首行名 = 契约.参数表[0].名称.clone();

    // ① 未知参数：名字不在契约参数表里 ⇒ 400 且报出未知的名与可用名表。
    let 未知名应答 = 发请求(
        &服务,
        &交POST请求(
            "/接口/调用",
            &format!("{{\"编号\":{编号},\"命名值\":{{\"根本没有这个参数\":{空槽文本}}}}}"),
        ),
    );
    assert_eq!(未知名应答.状态, 400, "未知参数是请求体形状不合法");
    let 说明文字 = 源文本(&未知名应答.取协议值(), "协议错误");
    assert!(
        说明文字.contains("根本没有这个参数"),
        "错误必须点名那个未知参数：{说明文字}"
    );
    assert!(
        说明文字.contains(&首行名),
        "错误必须给出可用名表（其中有「{首行名}」）：{说明文字}"
    );

    // ② 缺参数：一个都不给 ⇒ 首行没有声明非空默认值 ⇒ 400 且点名缺的那个。
    let 缺参应答 = 发请求(
        &服务,
        &交POST请求(
            "/接口/调用",
            &format!("{{\"编号\":{编号},\"命名值\":{{}}}}"),
        ),
    );
    assert_eq!(缺参应答.状态, 400, "缺参数不许静默补空槽");
    let 缺说明 = 源文本(&缺参应答.取协议值(), "协议错误");
    assert!(
        缺说明.contains(&首行名),
        "缺参数错误必须点名缺的那个参数（{首行名}）：{缺说明}"
    );

    // ③ 两种给法并列 ⇒ 400（同一件事两个语义源）。
    let 并列应答 = 发请求(
        &服务,
        &交POST请求(
            "/接口/调用",
            &format!(
                "{{\"编号\":{编号},\"值\":[{空槽文本}],\"命名值\":{{\"{首行名}\":{空槽文本}}}}}"
            ),
        ),
    );
    assert_eq!(并列应答.状态, 400, "值与命名值只能给一种");
}

