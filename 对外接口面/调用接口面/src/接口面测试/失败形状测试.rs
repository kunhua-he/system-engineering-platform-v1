/// `POST` 一个坏 JSON ⇒ **HTTP 400**（协议层失败，不是业务失败）。
#[test]
fn 协议失败_坏协议体是400不是业务失败() {
    let 服务 = 起服务();
    let 造应答 = 发请求(&服务, &交POST请求("/接口/调用", "{这不是 JSON"));
    assert_eq!(造应答.状态, 400, "请求体形状不合法 ⇒ 协议层");
    assert!(!造应答.取逻辑值("成功"));
    assert!(!造应答.取文本("协议错误").is_empty(), "400 必须说清哪里不合法");
    assert!(
        造应答.找成员("错误").is_none(),
        "协议层失败**不许**编一个业务错误码：那是伪造业务数据"
    );
}

