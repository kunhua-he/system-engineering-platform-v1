//! 接口面测试 · 失败形状 —— 业务失败 200 / 协议失败 4xx。
//!
//! 判据：`接口面形状.md` §三：失败不抛 HTTP 5xx；状态码只表达请求合不合法。

use crate::测试夹具::{
    发请求, 取请求, 交POST请求, 取逻辑值, 错误体六项, 文本, 无符号值, 起服务,
};

