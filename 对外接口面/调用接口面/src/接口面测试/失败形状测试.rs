// ════════════════════════════════════════════════════════════════════════════
// 三 跨源副作用请求防护（审计发现2）
// ════════════════════════════════════════════════════════════════════════════

/// 一条带指定头的原始 POST —— 头区**整段由调用方给**（含 `Host` / `Origin` / `Content-Type`）。
///
/// 为何不沿用 `交POST请求`：它硬写本机 `Host` 与 `application/json`，摆不出外源形状。
fn 外站请求(路径: &str, 头区: &str, 请求体: &str) -> String {
    format!("POST {路径} HTTP/1.1\r\n{头区}\r\nContent-Length: {}\r\n\r\n{请求体}", 请求体.len())
}

/// **反向样本（审计发现2 的实证形状）**：`Host` 与 `Origin` 都是外站 + `Content-Type: text/plain`
/// 的写请求 ⇒ **必拒 400**，且**不创建文件**。
///
/// 修前实测：该形状返回 200、`成功: true`，并真往调用方给的路径落了一份件。
#[test]
fn 跨源写请求_外站来源一律拒且不落件() {
    use crate::测试夹具::起服务带工具根;
    // 工具根指到一个**新建的空目录**：写请求若真被执行，件就落在那里 —— 比断言「返回 400」
    // 更硬的一层：那个路径下确实没有东西。
    let 根目录 = std::env::temp_dir().join(format!("v1-跨源防护-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&根目录);
    std::fs::create_dir_all(&根目录).expect("建临时工具根");
    let 服务 = 起服务带工具根(&根目录);

    let 标记件 = 根目录.join("跨源.程序文本");
    let 写作 = "{\"动作\":\"写\",\"路径\":\"跨源.程序文本\",\"正文\":\"跨源请求被实际执行\"}".to_string();
    let 造应答 = 发请求(
        &服务,
        &外站请求(
            "/接口/运维/程序文本",
            "Host: attacker.example\r\nOrigin: https://attacker.example\r\n\
             Sec-Fetch-Site: cross-site\r\nContent-Type: text/plain",
            &写作,
        ),
    );
    assert_eq!(
        造应答.状态, 400,
        "外站 Host + 外站 Origin 的写请求必拒（协议层 400）：\n{}",
        造应答.报文体
    );
    assert!(!造应答.取逻辑值("成功"));
    assert!(
        !标记件.exists(),
        "跨源请求**不许**产生副作用：{} 不该存在",
        标记件.display()
    );
    let _ = std::fs::remove_dir_all(&根目录);
}

/// 正反成对：**无 `Origin`** 的 `application/json` 请求（命令行 / 脚本的形状）**照旧 200**。
///
/// 这一条是防矫枉过正的：只加校验、不改产品约定 —— 「第一次用不需要读文档就能调对」
/// （`接口面形状.md` §一）仍成立。
#[test]
fn 无来源的JSON请求_照旧放行() {
    let 服务 = 起服务();
    let 造应答 = 发请求(
        &服务,
        &外站请求("/接口/调用", "Host: 127.0.0.1\r\nContent-Type: application/json", "{\"编号\":999999,\"值\":[]}"),
    );
    assert_eq!(造应答.状态, 200, "无 Origin 的本机请求照旧：\n{}", 造应答.报文体);
    assert!(!造应答.取逻辑值("成功"), "这个号不存在 ⇒ 业务失败（但**是** 200）");
}

/// 收体端点 `Content-Type` 不是 `application/json` ⇒ 400；`; charset=…` 后缀**容忍**。
#[test]
fn 收体端点_内容类型不符是400后缀容忍() {
    let 服务 = 起服务();
    let 请求体 = "{\"编号\":999999,\"值\":[]}";
    // 错的内容类型 ⇒ 400（协议层，不是业务失败）。
    let 造应答 = 发请求(
        &服务,
        &外站请求("/接口/调用", "Host: 127.0.0.1\r\nContent-Type: text/plain", 请求体),
    );
    assert_eq!(造应答.状态, 400, "副作用 JSON 端点不许拿 text/plain 包 JSON 体");
    assert!(造应答.找成员("错误").is_none(), "协议层失败不编业务错误对象");
    // `; charset=…` 后缀容忍（浏览器与 fetch 默认会带）⇒ 照旧 200。
    let 造应答 = 发请求(
        &服务,
        &外站请求(
            "/接口/调用",
            "Host: 127.0.0.1\r\nContent-Type: application/json; charset=utf-8",
            请求体,
        ),
    );
    assert_eq!(造应答.状态, 200, "charset 后缀必须容忍：\n{}", 造应答.报文体);
    // `GET` 不带体 ⇒ 不判内容类型（拿它判就是给不存在的标的值提要求）。
    assert_eq!(发请求(&服务, &取请求("/接口")).状态, 200);
}

/// **协议层拒绝（400 / 404 / 405）不带身份，也不带重试判据** —— 这是设计意图，不是漏项。
///
/// 判据：`接口面形状.md` §三「协议层失败不编业务错误对象」；§32.4 的 `契约身份` 与 §九.2 的
/// `重试判据` 都是**业务失败**的旁路字段 —— 协议层根本没走到「哪条能力」这一步，
/// 编一个身份 / 判据出来就是伪造业务数据。
///
/// ★ **Agent 撞到协议错误时该怎么办**：协议错误说的是「你这次请求本身不合法」—— 它与
/// 「契约过期」不是一回事。Agent 不得把它当业务失败去重试同一条请求，而应**重新取契约**
/// （`GET /接口` / `GET /接口/能力/<编号>`）核对请求形状，再决定是否重发。
#[test]
fn 协议层拒绝_不带身份与重试判据() {
    let 服务 = 起服务();
    // 400：坏 JSON · 404：路径不存在 · 405：方法不对 —— 三种协议层拒绝各取一条。
    let 样本表 = [
        (发请求(&服务, &交POST请求("/接口/调用", "{不是 JSON")), 400u16),
        (发请求(&服务, &取请求("/没有这个端点")), 404),
        (发请求(&服务, &取请求("/接口/调用")), 405),
    ];
    for (造应答, 状态) in 样本表 {
        assert_eq!(造应答.状态, 状态, "协议层状态码：\n{}", 造应答.报文体);
        assert!(!造应答.取逻辑值("成功"), "协议层失败 成功: false");
        assert!(
            造应答.找成员("契约身份").is_none(),
            "协议层拒绝**不许**带 契约身份（那是业务失败的旁路字段）：\n{}",
            造应答.报文体
        );
        assert!(
            造应答.找成员("重试判据").is_none(),
            "协议层拒绝**不许**带 重试判据（没走到能力调用）：\n{}",
            造应答.报文体
        );
        assert!(
            造应答.找成员("错误").is_none(),
            "协议层拒绝**不许**编业务错误对象（那是伪造业务数据）"
        );
    }
}
