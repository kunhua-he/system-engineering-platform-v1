/// 调一个**不存在的号** ⇒ HTTP 200 + `成功: false` + 错误对象含六项。
#[test]
fn 失败形状_不存在的号是200加成功假加六项() {
    let 服务 = 起服务();
    let 造应答 = 发请求(&服务, &交POST请求("/接口/调用", "{\"编号\":999999,\"值\":[]}"));

    assert_eq!(造应答.状态, 200, "业务失败一律 200，不许抛 5xx");
    assert!(!造应答.取逻辑值("成功"));
    let 错误 = 造应答.取成员("错误");
    for 键名 in 错误体六项 {
        assert!(错误.取成员(键名).is_some(), "六项里的「{键名}」必须有");
    }
    assert_eq!(无符号值(&错误, "码"), 1);
    assert_eq!(文本(&错误, "名称"), "提供者未载入");
    assert!(取逻辑值(&错误, "可重试"));
    assert!(取逻辑值(&错误, "可自愈"));
    assert!(!取逻辑值(&错误, "需人工"));
    assert!(取逻辑值(&错误, "已登记"), "这个码在声明的错误码表里");
    assert!(造应答.找成员("耗时微秒").is_some(), "失败返回也必须带 耗时微秒");
}

/// `POST` 一个坏 JSON ⇒ **HTTP 400**（协议层失败，不是业务失败）。
#[test]
fn 协议失败_坏协议体是400不是业务失败() {
    let 服务 = 起服务();
    let 造应答 = 发请求(&服务, &交POST请求("/接口/调用", "{这不是 JSON"));
    assert_eq!(造应答.状态, 400, "请求体形状不合法 ⇒ 协议层");
    assert!(!造应答.取逻辑值("成功"));
    assert!(!造应答.取文本("协议错误").is_empty(), "400 必须说清哪里不合法");
    assert!(
        造应答.找成员("错误").is_none(),
        "协议层失败**不许**编一个业务错误码：那是伪造业务数据"
    );
}

/// 路径不在端点表里 ⇒ 404；路径在表里而方法不对 ⇒ 405。
///
/// **注意 `/` 不在这一格**：它是 §五 的静态托管（见下面那组用例）。
#[test]
fn 协议失败_路径不存在404与方法不对405() {
    let 服务 = 起服务();
    assert_eq!(发请求(&服务, &取请求("/没有这个端点")).状态, 404);

    let 造应答 = 发请求(&服务, &取请求("/接口/调用"));
    assert_eq!(造应答.状态, 405);
    assert!(
        造应答.取文本("协议错误").contains("POST"),
        "405 必须说清该用哪个方法：\n{}",
        造应答.体
    );
}

/// 编号不是十进制数 ⇒ 400（请求本身不合法）。
#[test]
fn 协议失败_编号不是十进制数是400() {
    let 服务 = 起服务();
    assert_eq!(发请求(&服务, &取请求("/接口/能力/abc")).状态, 400);
    assert_eq!(发请求(&服务, &取请求("/接口/能力/")).状态, 400);
}
