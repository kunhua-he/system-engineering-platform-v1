/// 调一个**不存在的号** ⇒ HTTP 200 + `成功: false` + 错误对象含六项。
#[test]
fn 失败形状_不存在的号是200加成功假加六项() {
    let 服务 = 起服务();
    let 造应答 = 发请求(&服务, &交POST请求("/接口/调用", "{\"编号\":999999,\"值\":[]}"));

    assert_eq!(造应答.状态, 200, "业务失败一律 200，不许抛 5xx");
    assert!(!造应答.取逻辑值("成功"));
    let 错误 = 造应答.取成员("错误");
    for 键名 in 错误体六项 {
        assert!(错误.取成员(键名).is_some(), "六项里的「{键名}」必须有");
    }
    assert_eq!(无符号值(&错误, "码"), 1);
    assert_eq!(源文本(&错误, "名称"), "提供者未载入");
    assert!(取逻辑值(&错误, "可重试"));
    assert!(取逻辑值(&错误, "可自愈"));
    assert!(!取逻辑值(&错误, "需人工"));
    assert!(取逻辑值(&错误, "已登记"), "这个码在声明的错误码表里");
    assert!(造应答.找成员("耗时微秒").is_some(), "失败返回也必须带 耗时微秒");
}

