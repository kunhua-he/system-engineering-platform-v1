//! 接口面测试 · 失败形状 —— 业务失败 200 / 协议失败 4xx。
//!
//! 判据：`接口面形状.md` §三：失败不抛 HTTP 5xx；状态码只表达请求合不合法。

use crate::测试夹具::{
    发请求, 取请求, 交POST请求, 取逻辑值, 错误体六项, 源文本, 无符号值, 起服务,
};

// ════════════════════════════════════════════════════════════════════════════
// 一之二 重试判据（§九.2/§九.3）：执行阶段 · 可能已执行 · 结果确定
// ════════════════════════════════════════════════════════════════════════════

/// 取失败应答里的 `重试判据`（没有就挂）。
///
/// 为什么用 `找成员` 而不是 `取成员`：`取成员` 在缺键时**当场 panic**，这里要的是
/// 「缺键就给一句说清的话」——`找成员` 给 `None`，`.expect(…)` 才带得出「失败返回必须带
/// 重试判据（§九.2）」这句定位提示。
fn 取重试判据(造应答: &crate::测试夹具::收到应答) -> crate::协议值::协议值 {
    造应答
        .找成员("重试判据")
        .expect("失败返回必须带 重试判据（§九.2）")
}

/// **执行前拒绝 ⇒ 未进入扩展**：调一个不存在的号，调度在 `执行(...)` 之前就返回
/// （`调度核心.rs` 的占位项分支）⇒ 确定没进扩展、副作用没可能、结果确定。
///
/// 这是 §九.3 第一行「执行前拒绝，明确没有进入扩展」的机器可判落点。
#[test]
fn 重试判据_执行前拒绝是未进入扩展() {
    let 服务 = 起服务();
    let 造应答 = 发请求(&服务, &交POST请求("/接口/调用", "{\"编号\":999999,\"值\":[]}"));
    let 判据 = 取重试判据(&造应答);
    assert_eq!(源文本(&判据, "执行阶段"), "未进入扩展", "占位项在 执行 之前返回：\n{}", 造应答.报文体);
    assert!(!取逻辑值(&判据, "可能已执行"), "没进扩展 ⇒ 副作用不可能已发生");
    assert!(取逻辑值(&判据, "结果确定"), "没进扩展 ⇒ 结果是确定的（就是没执行）");
}

/// **参数个数不符 ⇒ 未进入扩展**（第二个执行前拒绝样本，防「只对不存在的号特判」）。
#[test]
fn 重试判据_参数个数不符也是未进入扩展() {
    let 服务 = 起服务();
    let 编号 = crate::测试夹具::第一个能力号(&服务);
    let 造应答 = 发请求(&服务, &交POST请求("/接口/调用", &format!("{{\"编号\":{编号},\"值\":[]}}")));
    let 判据 = 取重试判据(&造应答);
    assert_eq!(源文本(&判据, "执行阶段"), "未进入扩展", "个数校验在 执行 之前：\n{}", 造应答.报文体);
    assert!(!取逻辑值(&判据, "可能已执行"));
}

/// **超时 ⇒ 已进入扩展且结果未知**（§九.3 第三行：返回结果未知，不自动重放）。
///
/// 超时**不走真调用**（要真等一个超时，测试会慢且不稳）：直接喂 `调度错误::超时` 进
/// `重试判据::由调度错误` —— 分档表只有这一处实现，测它就是测调用路用的同一段代码。
/// 依据：`调度核心.rs` 里超时是**执行之后**才判的（`耗时毫秒 > 超时预算毫秒`），
/// 且**不清返回槽**（执行方可能已交出所有权）⇒ 执行确已发生。
#[test]
fn 重试判据_超时是结果未知() {
    let 判据 = crate::错误形状::重试判据::由调度错误(v1_adapter::调度错误::超时 { 毫秒数: 1000 });
    let 判据值 = 判据.到协议值();
    assert_eq!(源文本(&判据值, "执行阶段"), "已进入扩展", "超时是执行后才判的");
    assert!(取逻辑值(&判据值, "可能已执行"), "执行已发起 ⇒ 副作用可能已落");
    assert!(
        !取逻辑值(&判据值, "结果确定"),
        "超时 = 结果未知（§九.3：不自动重放）"
    );
}

/// 其余四个调度错误（已废止 / 输入形状不符 / 配额用尽 / 提供者未载入）**全在执行前**：
/// 逐个钉住，防「只把超时分对、其余一律当结果未知」。
#[test]
fn 重试判据_其余四个调度错误都在执行前() {
    for 错误 in [
        v1_adapter::调度错误::提供者未载入 { 能力号: v1_adapter::能力号::构造(999999) },
        v1_adapter::调度错误::命令已废止 { 能力号: v1_adapter::能力号::构造(999999) },
        v1_adapter::调度错误::参数个数不符 { 声明: 1, 实际: 0 },
        v1_adapter::调度错误::输入形状不符 { 位次: 0, 声明类型: 0, 实际类型: 1 },
        v1_adapter::调度错误::配额用尽,
    ] {
        let 判据值 = crate::错误形状::重试判据::由调度错误(错误).到协议值();
        assert_eq!(
            源文本(&判据值, "执行阶段"),
            "未进入扩展",
            "{错误:?} 在 `执行(...)` 之前返回 ⇒ 必须报未进入扩展"
        );
        assert!(!取逻辑值(&判据值, "可能已执行"), "{错误:?} 没进扩展");
        assert!(取逻辑值(&判据值, "结果确定"), "{错误:?} 结果确定");
    }
}

/// **扩展执行崩溃 ⇒ 已进入扩展且结果确定**（扩展的执行函数 panic 被调度层接住，见码 35）。
///
/// 与「超时」分开：超时是我们没等到它答（结果未知），崩溃是它答不了但**结局已定**；
/// 与「提供者未载入」分开：那是没进扩展。所以它必须落「已回错误码」那一档。
#[test]
fn 扩展执行崩溃是已回错误码() {
    let 判据值 =
        crate::错误形状::重试判据::由调度错误(v1_adapter::调度错误::扩展执行崩溃).到协议值();
    assert_eq!(源文本(&判据值, "执行阶段"), "已进入扩展", "崩溃发生在执行发起之后");
    assert!(取逻辑值(&判据值, "可能已执行"), "已经进去了 ⇒ 副作用可能已落");
    assert!(取逻辑值(&判据值, "结果确定"), "崩溃是终局，不是结果未知");
}

