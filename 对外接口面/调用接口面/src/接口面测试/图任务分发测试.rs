//! 图任务分发测试 —— `POST /接口/调用` 里体带 `任务操作` 的那一支**真转调适配器**。
//!
//! 直接调 `处理请求`（不启服务、不占端口）：本面要验的是「请求 → 适配器 → 回执」这条线，
//! 不是 HTTP 解析（那一层另有测试）。
//!
//! | 判据 | 落点 |
//! |---|---|
//! | 提交回真实任务标识（不是本面发号） | `提交回真实任务标识` |
//! | 同请求标识两次提交 ⇒ 同一任务标识 | `提交幂等` |
//! | 查询未知任务 ⇒ 成功 false + 点名原因 | `查询未知任务回业务失败` |
//! | 取消未知任务 ⇒ 成功 false | `取消未知任务回业务失败` |
//! | 释放终态任务 ⇒ 再查询查不到 | `释放后查不到` |
//! | 从未有「未就位」回执 | `没有未就位回执` |

use std::path::Path;

use v1_adapter::{底座声明, 适配器};
use v1_resource_gateway::资源网关口;

use crate::分发::{处理请求, 请求环境};
use crate::协议值::协议值;
use crate::端点::调用;
use crate::网关::契约身份;

fn 体(文本: &str) -> 协议值 {
    crate::协议解析::解析协议值(文本).expect("测试样本必须是合法 JSON")
}

struct 门 {
    适配器: 适配器,
    关口: 资源网关口,
    身份: 契约身份,
}

impl 门 {
    fn 新() -> Self {
        let 声明 = 底座声明();
        Self {
            适配器: 适配器::装载声明根(&[声明]).expect("底座声明必须载得进来"),
            关口: 资源网关口::空实例(),
            身份: 契约身份 {
                版本: 声明.实现版本,
                声明格式号: u32::from(声明.声明格式号),
            },
        }
    }

    fn 发(&self, 体: &协议值) -> 协议值 {
        let 应答 = 处理请求(
            请求环境 {
                适配器: &self.适配器,
                资源关口: &self.关口,
                契约身份: &self.身份,
                实际端口: 0,
                静态根: Path::new("."),
                工具根: Path::new("."),
            },
            调用,
            Some(体),
        );
        assert_eq!(应答.状态, 200, "业务失败也是 200（不是 400/500）");
        crate::协议解析::解析协议值(&String::from_utf8_lossy(&应答.报文体))
            .expect("回执必须是合法 JSON")
    }
}

fn 提交体(请求标识: &str) -> 协议值 {
    体(&format!(
        r#"{{"任务操作":"提交","请求标识":"{请求标识}","节点表":[
            {{"节点标识":"唯一节点","编号":0,"命名值":{{"目标字宽":{{"类型标签":0,"值":0}}}}}}
        ]}}"#
    ))
}

fn 取值(回: &协议值, 键: &str) -> 协议值 {
    回.取成员("值")
        .and_then(|值| 值.取成员(键).cloned())
        .unwrap_or_else(|| panic!("回执的值里没有「{键}」：{回:?}"))
}

fn 成功(回: &协议值) -> bool {
    matches!(回.取成员("成功"), Some(协议值::真值))
}

fn 说明(回: &协议值) -> String {
    取值(回, "错误")
        .取成员("说明")
        .and_then(协议值::取文本)
        .map(str::to_owned)
        .unwrap_or_default()
}

#[test]
fn 提交回真实任务标识() {
    let 门 = 门::新();
    let 回 = 门.发(&提交体("请求一"));
    assert!(成功(&回), "提交必须受理：{回:?}");
    let 任务标识 = 取值(&回, "任务标识")
        .取无符号()
        .expect("任务标识必须是非负整数");
    assert!(任务标识 >= 1, "任务标识由适配器发号（从 1 起）");
    // 阶段照实说：受理不是完成。
    let 阶段 = 取值(&回, "任务阶段")
        .取文本()
        .map(str::to_owned)
        .unwrap_or_default();
    assert!(
        ["排队中", "执行中", "成功"].contains(&阶段.as_str()),
        "阶段必须是协议里的名字，实际：{阶段}"
    );
    // 查询走的是同一张任务表：查得到，且任务标识逐字相同。
    let 查 = 门.发(&体(&format!(
        r#"{{"任务操作":"查询","任务标识":{任务标识}}}"#
    )));
    assert_eq!(取值(&查, "任务标识").取无符号(), Some(任务标识));
    assert!(成功(&查), "已受理的任务必须查得到：{查:?}");
}

#[test]
fn 提交幂等() {
    let 门 = 门::新();
    let 首 = 门.发(&提交体("请求幂等"));
    let 次 = 门.发(&提交体("请求幂等"));
    assert_eq!(
        取值(&首, "任务标识").取无符号(),
        取值(&次, "任务标识").取无符号(),
        "同请求标识 + 同图 ⇒ 回原任务标识"
    );
}

#[test]
fn 查询未知任务回业务失败() {
    let 门 = 门::新();
    let 回 = 门.发(&体(r#"{"任务操作":"查询","任务标识":987654}"#));
    assert!(!成功(&回), "查无此任务必须成功 false：{回:?}");
    assert!(
        说明(&回).contains("任务不存在"),
        "说明必须点名「任务不存在」：{}",
        说明(&回)
    );
}

#[test]
fn 取消未知任务回业务失败() {
    let 门 = 门::新();
    let 回 = 门.发(&体(r#"{"任务操作":"取消","任务标识":987655}"#));
    assert!(!成功(&回), "取消查无此任务必须成功 false：{回:?}");
    assert!(说明(&回).contains("任务不存在"), "{}", 说明(&回));
}

#[test]
fn 释放后查不到() {
    let 门 = 门::新();
    let 回 = 门.发(&提交体("请求释放"));
    let 任务标识 = 取值(&回, "任务标识").取无符号().expect("必须有任务标识");
    // 终态才好释放：轮询到任务阶段不是排队中 / 执行中。
    let 终态 = ["成功", "失败", "已取消"];
    let mut 当前 = String::new();
    for _ in 0..200 {
        let 查 = 门.发(&体(&format!(
            r#"{{"任务操作":"查询","任务标识":{任务标识}}}"#
        )));
        当前 = 取值(&查, "任务阶段")
            .取文本()
            .map(str::to_owned)
            .unwrap_or_default();
        if 终态.contains(&当前.as_str()) {
            break;
        }
        std::thread::sleep(std::time::Duration::from_millis(5));
    }
    assert!(
        终态.contains(&当前.as_str()),
        "任务必须跑到终态，实际：{当前}"
    );
    let 释 = 门.发(&体(&format!(
        r#"{{"任务操作":"释放","任务标识":{任务标识}}}"#
    )));
    assert!(成功(&释), "终态任务必须可释放：{释:?}");
    let 查 = 门.发(&体(&format!(
        r#"{{"任务操作":"查询","任务标识":{任务标识}}}"#
    )));
    assert!(!成功(&查), "释放后查询必须成功 false（查不到）：{查:?}");
    assert!(说明(&查).contains("任务不存在"), "{}", 说明(&查));
}

#[test]
fn 没有未就位回执() {
    let 门 = 门::新();
    let 回 = 门.发(&体(r#"{"任务操作":"查询","任务标识":1}"#));
    let 文 = 说明(&回);
    assert!(
        !文.contains("未就位"),
        "「装配层未就位」那条回执必须整条删掉，不许留兼容分支：{文}"
    );
    assert!(!文.contains("装配层"), "不该再提装配层：{文}");
}
