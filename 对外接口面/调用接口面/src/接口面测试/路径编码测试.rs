//! 接口面测试 · 路径编码 —— 百分号编码路径必须认得出来。
//!
//! 判据：`fetch("/接口")` 会把非 ASCII 路径百分号编码；不解码 ⇒ 前端零逻辑却调不通。

use crate::测试夹具::{发请求, 取请求, 第一个能力号, 起服务};

/// **前端按 URL 规范发的就是这种路径**：`fetch("/接口")` 会把非 ASCII 路径百分号编码。
/// 不解码 ⇒ 前端零逻辑却调不通，那是本面的缺陷。
#[test]
fn 百分号编码的路径_认得出来() {
    let 服务 = 起服务();
    let 应答 = 发请求(&服务, &取请求("/%E6%8E%A5%E5%8F%A3"));
    assert_eq!(应答.状态, 200, "浏览器/fetch 把 /接口 编码成这个形状");
    assert!(应答.找成员("端点").is_some());

    let 编号 = 第一个能力号(&服务);
    let 应答 = 发请求(&服务, &取请求(&format!("/%E6%8E%A5%E5%8F%A3/%E8%83%BD%E5%8A%9B/{编号}")));
    assert_eq!(应答.状态, 200);
    assert!(应答.取逻辑值("成功"));
}
