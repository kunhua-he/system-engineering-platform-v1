//! 图任务请求形状的单测（`图任务请求.rs` 的子件）—— 纯逻辑，不碰网络 / 数据库 / 适配器。
//!
//! 覆盖：单能力体不误判 · 菱形图通过 · 空表 / 重复标识 / 自依赖 / 未知依赖 / 有环被拒 ·
//! 字面值与引用同给被拒 · 引用非传递前驱被拒 · 操作名闭合枚举 · 控制的必填项与节点标识口径。

use super::*;

fn 体(文本: &str) -> 协议值 {
    crate::协议解析::解析协议值(文本).expect("测试样本必须是合法 JSON")
}

fn 节点(标识: &str, 依赖: &str) -> String {
    format!(r#"{{"节点标识":"{标识}","编号":1105,"依赖节点":[{依赖}]}}"#)
}

#[test]
fn 单能力体不算图任务() {
    assert!(!是图任务(&体(r#"{"编号":1105,"值":[]}"#)));
    assert!(是图任务(&体(r#"{"任务操作":"提交"}"#)));
}

#[test]
fn 菱形图通过校验() {
    // A → B, A → C, B+C → D：菱形，传递前驱齐全。
    let 样本 = format!(
        r#"{{"任务操作":"提交","请求标识":"r1","节点表":[{},{},{},{}]}}"#,
        节点("示例节点1", ""),
        节点("示例节点2", r#""示例节点1""#),
        节点("示例节点3", r#""示例节点1""#),
        节点("示例节点4", r#""示例节点2","示例节点3""#),
    );
    let 请求 = 解析图任务(&体(&样本)).expect("菱形图必须通过");
    match 请求 {
        图任务请求::提交 { 节点表, .. } => {
            assert_eq!(节点表.len(), 4);
            assert_eq!(节点表[3].依赖节点.len(), 2);
        }
        _ => panic!("应是提交"),
    }
}

