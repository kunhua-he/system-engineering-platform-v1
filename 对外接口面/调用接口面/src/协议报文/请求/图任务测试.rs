#[test]
fn 查询可带节点标识_取消不吃节点标识() {
    let 查询 = 解析图任务(&体(
        r#"{"任务操作":"查询","任务标识":9,"节点标识":"示例节点1"}"#,
    ))
    .expect("查询带节点标识应通过");
    match 查询 {
        图任务请求::控制 {
            操作,
            任务标识,
            节点标识,
        } => {
            assert_eq!(操作.名(), "查询");
            assert_eq!(任务标识, 9);
            assert_eq!(节点标识.as_deref(), Some("示例节点1"));
        }
        _ => panic!("应是控制"),
    }
    let 错误 = 解析图任务(&体(
        r#"{"任务操作":"取消","任务标识":9,"节点标识":"示例节点1"}"#,
    ))
    .expect_err("取消吃节点标识必须拒");
    assert!(错误.可读说明().contains("节点标识"), "{}", 错误.可读说明());
}

