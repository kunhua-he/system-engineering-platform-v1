//! 名字（键名 · 操作名）只有一份：经 `v1_adapter` 从 `契约声明/调用任务协议.json` 的派生件取，本文件只 `use`。

use crate::协议值::协议值;
use crate::槽编码::{self, 槽源, 请求形状错误};

// ════════════════════════════════════════════════════════════════════════════
// 三 图任务（DAG）请求形状 —— 体里出现 `任务操作` 才是图任务
// ════════════════════════════════════════════════════════════════════════════
//
// **单能力路径零变化**：`任务操作` 这个键不在单能力体的形状里（§三 只有 `编号` / `值` /
// `命名值`），所以「有没有这个键」就是两套请求的分界，不需要另一个端点、也不改既有解析。
//
// 分工与本文件其余部分一致：**这里只判「请求体形状合不合法」⇒ 400**，不判业务。
// 图任务的**结构性校验**（空表 · 空/重复节点标识 · 重复/未知依赖 · 自依赖 · 有环 ·
// 非法输入引用）之所以落在 400，是因为它们说的都是「这张图本身不成立」——
// 与「能力现在不可用」不同类：后者是业务失败（200 + `成功: false`），前者重试永远是同一个结果。
//
// **错误一律定位到具体节点标识与字段名**（E02 口径）：每条说明都点名「哪个节点 · 哪个字段 ·
// 为什么」，不写「第几项不合法」这种还得回头对位次的说法。

// ── 名字的来处：**只有一份** ────────────────────────────────────────────────
//
// 图任务的字段名 · 任务操作名 · 阶段名都是协议的一部分（源件 `契约声明/调用任务协议.json`），
// 由生成器派生成常量与枚举（`契约声明/src/调用任务数据.rs`）。判据 5 不许本 crate 直接
// `use` `契约声明/` ⇒ 由适配器**再导出同一份**（`v1_adapter` 的再导出口）。本模块只 `use`，
// **不自备字符串表**：早先手抄的 18 个键名、4 个操作名、6 个任务阶段名、9 个节点阶段名
// 已整条删除（2026-11-06），改名字只改那份 JSON 并重跑生成器。
use v1_adapter::{
    控制字段名, 提交字段名, 节点字段名, 调用任务操作, 输入引用字段名
};

/// 四种操作的线上名，用 ` · ` 连起来（只是排版；名字本身取 [`调用任务操作::名`]）。
fn 操作名表() -> String {
    调用任务操作::全部
        .iter()
        .map(|操作| 操作.名())
        .collect::<Vec<&str>>()
        .join(" · ")
}

/// 名 → 操作（**逐字**命中；不许前缀 / 近似）。查的是契约派生枚举的全集。
fn 操作由名(名: &str) -> Option<调用任务操作> {
    调用任务操作::全部
        .iter()
        .copied()
        .find(|操作| 操作.名() == 名)
}

/// 一个节点的**输入引用**：这个参数的值不写在请求里，而是从**上游节点**的输出里取。
///
/// 为什么要引用：图任务的意义就是「后一个节点吃前一个节点的输出」；把上游输出整段搬进
/// 后一个节点的 `命名值` 就等于让调用方手工搬运中间结果 —— 那是把编排退回手工。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 输入引用 {
    /// 本节点里被填的那个参数名（必须是本节点 `命名值` 里的名字？**不**：引用与字面值互斥，
    /// 所以它恰恰是 `命名值` 里**没有**的那个名字）。
    pub 目标参数: String,
    /// 从哪个上游节点取（必须是本节点的**传递前驱**：直接或间接依赖到的节点）。
    pub 来源节点: String,
    /// 上游节点的哪个返回参数（`None` = 上游只回一个槽时取它的第 0 位）。
    pub 来源参数: Option<String>,
}

/// 图任务的一个节点。
#[derive(Debug, Clone)]
pub struct 图任务节点 {
    pub 节点标识: String,
    /// 这个节点调哪个能力（能力号；有没有人认领是调度层的事，本层不判）。
    #[allow(dead_code)] // 由装配层按号去调（本面只做形状与分发，不取号）
    pub 编号: u32,
    /// 这个节点的字面入参（命名形态；`输入引用` 里的目标参数**不许**在这里再出现一次）。
    pub 命名值: Vec<(String, 槽源)>,
    /// 依赖节点（前置）。空 = 根节点。
    pub 依赖节点: Vec<String>,
    pub 输入引用: Vec<输入引用>,
}

/// `POST /接口/调用` 里的图任务请求（两支）。
#[allow(dead_code)] // `请求标识` / 同步窗口 / 截止时刻 由装配层消费（本面只收下并回执）
#[derive(Debug, Clone)]
pub enum 图任务请求 {
    /// 提交一张图。
    提交 {
        请求标识: String,
        节点表: Vec<图任务节点>,
        /// 同步窗口：等了这么久还没完成就**照样回执**（给任务标识 + 当前阶段），
        /// 不把「没等到」变成错误 —— 任务还在跑，那是正常结果之一。
        同步等待毫秒: Option<u64>,
        截止时刻: Option<String>,
    },
    /// 查询 / 取消 / 释放，都按任务标识定位；查询可再按节点标识收窄。
    控制 {
        操作: 调用任务操作,
        任务标识: u64,
        节点标识: Option<String>,
    },
}

/// 请求体是不是图任务 —— **只看顶层有没有 `任务操作`** 这一个键。
///
/// 这是两套请求的唯一分界：单能力体形状里没有这个键（§三 只有 `编号` / `值` / `命名值`），
/// 所以单能力路径**一字不改**，也不用第二个端点。
pub fn 是图任务(请求体: &协议值) -> bool {
    请求体.是否含键(提交字段名::任务操作)
}

/// 解析图任务请求（体里已经有 `任务操作`，由 [`是图任务`] 判过）。
pub fn 解析图任务(请求体: &协议值) -> Result<图任务请求, 请求形状错误> {
    if !matches!(请求体, 协议值::对象值(_)) {
        return Err(请求形状错误::构造(None, "图任务的请求体必须是对象"));
    }
    let 操作名 = 取非空文本(请求体, 提交字段名::任务操作)?;
    let 操作 = 操作由名(&操作名).ok_or_else(|| {
        请求形状错误::构造(
            None,
            format!(
                "{} 只认 {} 四个值（闭合枚举，不许按前缀猜），实际：{操作名}",
                提交字段名::任务操作,
                操作名表()
            ),
        )
    })?;
    if matches!(操作, 调用任务操作::提交) {
        解析提交(请求体)
    } else {
        解析控制(请求体, 操作)
    }
}

/// `任务操作 = 提交`：请求标识 + 节点表（+ 可选同步窗口 / 截止时刻）。
fn 解析提交(请求体: &协议值) -> Result<图任务请求, 请求形状错误> {
    let 请求标识 = 取非空文本(请求体, 提交字段名::请求标识)?;
    let 节点项表 = 请求体
        .取成员(提交字段名::节点表)
        .and_then(协议值::取数组)
        .ok_or_else(|| {
            请求形状错误::构造(None, format!("缺少 {}，或它不是数组", 提交字段名::节点表))
        })?;
    if 节点项表.is_empty() {
        return Err(请求形状错误::构造(
            None,
            format!(
                "{} 是空表：图任务至少一个节点（空图没有可调度的事情，不是「什么都不做」）",
                提交字段名::节点表
            ),
        ));
    }
    let mut 节点表 = Vec::with_capacity(节点项表.len());
    for (位次, 节点项) in 节点项表.iter().enumerate() {
        节点表.push(解析节点(节点项).map_err(|说明| 请求形状错误::构造(Some(位次), 说明))?);
    }
    校验图结构(&节点表)?;
    for 节点 in &节点表 {
        校验输入引用(节点, &节点表)?;
    }
    let 同步等待毫秒 = 可选无符号(请求体, 提交字段名::同步等待毫秒)?;
    let 截止时刻 = 可选文本(请求体, 提交字段名::截止时刻)?;
    Ok(图任务请求::提交 {
        请求标识,
        节点表,
        同步等待毫秒,
        截止时刻,
    })
}

/// 一个节点项 → [`图任务节点`]。
///
/// 键的取舍（说明一次，别处不再解释）：
/// - `节点标识` / `编号` **必须给**：没有标识就没法被依赖、没法被引用、没法定位错误；
///   没有编号就不知道该调谁。
/// - `命名值` / `依赖节点` / `输入引用` **可省**（省 = 空）：这三项都是「本来就可以没有」的
///   —— 无参节点、根节点、不引用上游的节点都是正常图，给它们编一个必须写空表的规矩只是噪音。
fn 解析节点(节点项: &协议值) -> Result<图任务节点, String> {
    if !matches!(节点项, 协议值::对象值(_)) {
        return Err("节点必须是对象：{\"节点标识\":…,\"编号\":…}".to_owned());
    }
    let 节点标识 = 节点项
        .取成员(节点字段名::节点标识)
        .and_then(协议值::取文本)
        .ok_or_else(|| format!("缺少 {}，或它不是文本", 节点字段名::节点标识))?;
    if 节点标识.trim().is_empty() {
        return Err(format!(
            "{} 是空串：空标识既指不出依赖它的节点，也指不出错误落在哪",
            节点字段名::节点标识
        ));
    }
    let 节点标识 = 节点标识.to_owned();
    let 编号值 = 节点项
        .取成员(节点字段名::编号)
        .and_then(协议值::取无符号)
        .ok_or_else(|| {
            format!(
                "节点「{节点标识}」的 {}：缺少，或它不是非负整数",
                节点字段名::编号
            )
        })?;
    let 编号 = u32::try_from(编号值).map_err(|_| {
        format!(
            "节点「{节点标识}」的 {}：超出 32 位，不是本平台的能力号",
            节点字段名::编号
        )
    })?;
    let mut 命名值 = Vec::new();
    if let Some(命名项) = 节点项.取成员(节点字段名::命名值) {
        let 协议值::对象值(成员表) = 命名项 else {
            return Err(format!(
                "节点「{节点标识}」的 {}：必须是对象 {{\"参数名\":{{\"类型标签\":N,\"值\":V}}}}",
                节点字段名::命名值
            ));
        };
        for (位次, (名称, 槽项)) in 成员表.iter().enumerate() {
            命名值.push((
                名称.clone(),
                槽编码::由协议值(槽项, 位次).map_err(|错误| {
                    format!(
                        "节点「{节点标识}」的 {}「{名称}」：{}",
                        节点字段名::命名值,
                        错误.可读说明()
                    )
                })?,
            ));
        }
    }
    let mut 依赖节点 = Vec::new();
    if let Some(依赖项) = 节点项.取成员(节点字段名::依赖节点) {
        let 依赖表 = 依赖项.取数组().ok_or_else(|| {
            format!(
                "节点「{节点标识}」的 {}：必须是文本数组",
                节点字段名::依赖节点
            )
        })?;
        for 依赖 in 依赖表 {
            let 依赖名 = 依赖.取文本().ok_or_else(|| {
                format!(
                    "节点「{节点标识}」的 {}：每一项都必须是文本（节点标识）",
                    节点字段名::依赖节点
                )
            })?;
            依赖节点.push(依赖名.to_owned());
        }
    }
    let mut 输入引用表 = Vec::new();
    if let Some(引用项) = 节点项.取成员(节点字段名::输入引用) {
        let 引用表 = 引用项
            .取数组()
            .ok_or_else(|| format!("节点「{节点标识}」的 {}：必须是数组", 节点字段名::输入引用))?;
        for 引用 in 引用表 {
            输入引用表.push(解析单项引用(&节点标识, 引用)?);
        }
    }
    Ok(图任务节点 {
        节点标识,
        编号,
        命名值,
        依赖节点,
        输入引用: 输入引用表,
    })
}

/// 一项 `输入引用` → [`输入引用`]（只判形状；「是不是传递前驱」见图结构校验之后的那一步）。
fn 解析单项引用(节点标识: &str, 引用项: &协议值) -> Result<输入引用, String> {
    if !matches!(引用项, 协议值::对象值(_)) {
        return Err(format!(
            "节点「{节点标识}」的 {}：每一项都必须是对象 {{\"目标参数\":…,\"来源节点\":…}}",
            节点字段名::输入引用
        ));
    }
    let 目标参数 = 必填文本(节点标识, 引用项, 输入引用字段名::目标参数)?;
    let 来源节点 = 必填文本(节点标识, 引用项, 输入引用字段名::来源节点)?;
    let 来源参数 = match 引用项.取成员(输入引用字段名::来源参数) {
        None => None,
        Some(待处理值) => Some(
            待处理值
                .取文本()
                .ok_or_else(|| {
                    format!(
                        "节点「{节点标识}」的 {}：{} 必须是文本（上游节点的参数名）",
                        节点字段名::输入引用,
                        输入引用字段名::来源参数
                    )
                })?
                .to_owned(),
        ),
    };
    Ok(输入引用 {
        目标参数,
        来源节点,
        来源参数,
    })
}

/// 图结构性校验：空/重复标识 · 自依赖 · 重复依赖 · 未知依赖 · 有环。
///
/// 一次算全（不是逐条撞上才报）：调用方要一次看清这张图有几处不成立，
/// 否则修一处、再撞下一处，纯浪费来回。
///
/// **不复用内核的 `调用任务图`**：判据 5 不许跳层依赖 `运行内核/`。这里的判据比内核那份**少**
/// 一层：内核判的是「调度器能不能安全跑」，本层判的是「请求体能不能被接受」——
/// 两边都判不是第二套实现，是一层协议、一层调度，各判各的（口径相同的项在同名说明里对齐）。
fn 校验图结构(节点表: &[图任务节点]) -> Result<(), 请求形状错误> {
    use std::collections::{BTreeMap, BTreeSet};
    let 报 = |节点: &str, 字段: &str, 什么: String| {
        请求形状错误::构造(
            None,
            if 节点.is_empty() {
                format!("{字段}：{什么}")
            } else {
                format!("节点「{节点}」的 {字段}：{什么}")
            },
        )
    };
    let mut 下标 = BTreeMap::new();
    for (节点序号, 节点) in 节点表.iter().enumerate() {
        if 下标.insert(节点.节点标识.clone(), 节点序号).is_some() {
            return Err(报(
                &节点.节点标识,
                节点字段名::节点标识,
                "重复：同一个标识指出两个节点，依赖与引用都会指错".to_owned(),
            ));
        }
    }
    let mut 后继 = vec![Vec::new(); 节点表.len()];
    let mut 入度 = vec![0usize; 节点表.len()];
    for (节点序号, 节点) in 节点表.iter().enumerate() {
        let mut 已见 = BTreeSet::new();
        for 依赖 in &节点.依赖节点 {
            if 依赖 == &节点.节点标识 {
                return Err(报(
                    &节点.节点标识,
                    节点字段名::依赖节点,
                    "自依赖：节点不能依赖自身（永远等不到）".to_owned(),
                ));
            }
            if !已见.insert(依赖) {
                return Err(报(
                    &节点.节点标识,
                    节点字段名::依赖节点,
                    format!("重复：同一个前置「{依赖}」写了两遍"),
                ));
            }
            let Some(&前置) = 下标.get(依赖) else {
                return Err(报(
                    &节点.节点标识,
                    节点字段名::依赖节点,
                    format!("未知：{} 里没有这个节点", 提交字段名::节点表),
                ));
            };
            后继[前置].push(节点序号);
            入度[节点序号] += 1;
        }
    }
    // Kahn：排不出全序就是有环。环里报一个具体节点，别只说「有环」。
    let mut 队列: std::collections::VecDeque<usize> = 入度
        .iter()
        .enumerate()
        .filter(|(_, 度)| **度 == 0)
        .map(|(序, _)| 序)
        .collect();
    let mut 排出 = 0usize;
    while let Some(节点序号) = 队列.pop_front() {
        排出 += 1;
        for &后置 in &后继[节点序号] {
            入度[后置] -= 1;
            if 入度[后置] == 0 {
                队列.push_back(后置);
            }
        }
    }
    if 排出 != 节点表.len() {
        let 环上节点 = 入度
            .iter()
            .enumerate()
            .find(|(_, 度)| **度 > 0)
            .map(|(序, _)| 节点表[序].节点标识.clone())
            .unwrap_or_default();
        return Err(报(
            &环上节点,
            节点字段名::依赖节点,
            "有环：沿依赖绕一圈回不到起点，没有可开始的节点".to_owned(),
        ));
    }
    Ok(())
}

/// 输入引用校验：目标参数不与字面值冲突 · 目标参数不重复 · 来源节点必须是**传递前驱**。
///
/// 为什么必须传递前驱（不只是直接依赖）：引用的值来自上游节点的运行结果，而
/// 「上游」在图里的含义就是可达前置。允许引用兄弟节点或本节点 ⇒ 读数时那个节点的结果
/// 可能还没算出来 —— 那是把「等不到值」写进协议，而不是拒绝它。
fn 校验输入引用(
    节点: &图任务节点, 节点表: &[图任务节点]
) -> Result<(), 请求形状错误> {
    use std::collections::BTreeSet;
    if 节点.输入引用.is_empty() {
        return Ok(());
    }
    // 传递前驱（沿 依赖节点 往上走，含直接依赖）。
    let by_id: std::collections::BTreeMap<&str, &图任务节点> =
        节点表.iter().map(|项| (项.节点标识.as_str(), 项)).collect();
    let mut 前驱 = BTreeSet::new();
    let mut 待走: Vec<&str> = 节点.依赖节点.iter().map(String::as_str).collect();
    while let Some(当前) = 待走.pop() {
        if !前驱.insert(当前.to_owned()) {
            continue;
        }
        if let Some(上游) = by_id.get(当前) {
            待走.extend(上游.依赖节点.iter().map(String::as_str));
        }
    }
    let mut 已用目标 = BTreeSet::new();
    for 引用 in &节点.输入引用 {
        if 引用.目标参数.trim().is_empty() {
            return Err(请求形状错误::构造(
                None,
                format!(
                    "节点「{}」的 {}：{} 是空串 —— 空名字填不进任何参数",
                    节点.节点标识,
                    节点字段名::输入引用,
                    输入引用字段名::目标参数
                ),
            ));
        }
        if !已用目标.insert(引用.目标参数.as_str()) {
            return Err(请求形状错误::构造(
                None,
                format!(
                    "节点「{}」的 {}：{}「{}」被引用了两次 —— 一个参数只能有一个来源",
                    节点.节点标识,
                    节点字段名::输入引用,
                    输入引用字段名::目标参数,
                    引用.目标参数
                ),
            ));
        }
        if 节点.命名值.iter().any(|(名, _)| *名 == 引用.目标参数) {
            return Err(请求形状错误::构造(
                None,
                format!(
                    "节点「{}」的 {}「{}」：{} 里同时给了字面值与引用 —— 两种给法给同一件事，\
                     就是第二个语义源（运行期到底听谁的没有答案）",
                    节点.节点标识,
                    输入引用字段名::目标参数,
                    引用.目标参数,
                    节点字段名::命名值
                ),
            ));
        }
        if !前驱.contains(&引用.来源节点) {
            let 原因 = if 引用.来源节点 == 节点.节点标识 {
                "是本节点".to_owned()
            } else {
                "不是本节点的传递前驱（沿 依赖节点 走不到它）".to_owned()
            };
            return Err(请求形状错误::构造(
                None,
                format!(
                    "节点「{}」的 {}：{}「{}」{原因} —— 引用只许指向上游，\
                     否则读数时它的结果可能还没算出来",
                    节点.节点标识,
                    节点字段名::输入引用,
                    输入引用字段名::来源节点,
                    引用.来源节点
                ),
            ));
        }
    }
    Ok(())
}

/// `任务操作 = 查询 | 取消 | 释放`：任务标识必给，节点标识只有查询用得上。
fn 解析控制(
    请求体: &协议值,
    操作: 调用任务操作,
) -> Result<图任务请求, 请求形状错误> {
    let 任务标识 = 请求体
        .取成员(控制字段名::任务标识)
        .and_then(协议值::取无符号)
        .ok_or_else(|| {
            请求形状错误::构造(
                None,
                format!(
                    "{} = {} 必须给 {}（非负整数，提交时回执里给的那个），缺少或不是非负整数",
                    提交字段名::任务操作,
                    操作.名(),
                    控制字段名::任务标识
                ),
            )
        })?;
    // 节点标识只有查询收窄用得上；取消 / 释放给了也不算错（按整任务办），但**不静默当没给**：
    // 那会让「我只想取消一个节点」变成「整任务被取消」，是危险方向的静默修正。
    let 节点标识 = match 请求体.取成员(控制字段名::节点标识) {
        None => None,
        Some(待处理值) => {
            let 值 = 待处理值.取文本().ok_or_else(|| {
                请求形状错误::构造(
                    None,
                    format!("{} 必须是文本（节点标识）", 控制字段名::节点标识),
                )
            })?;
            if 值.trim().is_empty() {
                return Err(请求形状错误::构造(
                    None,
                    format!("{} 是空串 —— 空标识指不出哪个节点", 控制字段名::节点标识),
                ));
            }
            if !matches!(操作, 调用任务操作::查询) {
                return Err(请求形状错误::构造(
                    None,
                    format!(
                        "{} = {} 不吃 {}：取消 / 释放按整个任务办，按节点只给查询用\
                         （否则「取消一个节点」会被读成「取消整任务」）",
                        提交字段名::任务操作,
                        操作.名(),
                        控制字段名::节点标识
                    ),
                ));
            }
            Some(值.to_owned())
        }
    };
    Ok(图任务请求::控制 {
        操作,
        任务标识,
        节点标识,
    })
}

/// 必填文本键（错误说明点名节点与字段）。
fn 必填文本(节点标识: &str, 节点项: &协议值, 键名: &str) -> Result<String, String> {
    let 值 = 节点项
        .取成员(键名)
        .and_then(协议值::取文本)
        .ok_or_else(|| format!("节点「{节点标识}」缺少 {键名}，或它不是文本"))?;
    if 值.trim().is_empty() {
        return Err(format!("节点「{节点标识}」的 {键名} 是空串"));
    }
    Ok(值.to_owned())
}

/// 顶层必填文本键（非空）。
fn 取非空文本(请求体: &协议值, 键名: &str) -> Result<String, 请求形状错误> {
    let 值 = 请求体
        .取成员(键名)
        .and_then(协议值::取文本)
        .ok_or_else(|| 请求形状错误::构造(None, format!("缺少 {键名}，或它不是文本")))?;
    if 值.trim().is_empty() {
        return Err(请求形状错误::构造(
            None,
            format!("{键名} 是空串 —— 空标识指不出是哪一个请求"),
        ));
    }
    Ok(值.to_owned())
}

/// 顶层可选非负整数键（给了就必须是）。
fn 可选无符号(请求体: &协议值, 键名: &str) -> Result<Option<u64>, 请求形状错误> {
    match 请求体.取成员(键名) {
        None => Ok(None),
        Some(待处理值) => 待处理值
            .取无符号()
            .map(Some)
            .ok_or_else(|| 请求形状错误::构造(None, format!("{键名} 必须是非负整数"))),
    }
}

/// 顶层可选文本键（给了就必须是）。
fn 可选文本(请求体: &协议值, 键名: &str) -> Result<Option<String>, 请求形状错误> {
    match 请求体.取成员(键名) {
        None => Ok(None),
        Some(待处理值) => 待处理值
            .取文本()
            .map(|字| Some(字.to_owned()))
            .ok_or_else(|| 请求形状错误::构造(None, format!("{键名} 必须是文本"))),
    }
}

