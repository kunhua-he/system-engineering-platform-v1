//! 线上逻辑值 —— Rust 的 `bool` 转成线上（JSON）逻辑值，**本 crate 只此一份**。
//!
//! 留痕端点（`留痕响应.rs` 的 `已启用`）与失败形状（`错误形状.rs` 的四项业务判断）都要把
//! `bool` 装进应答对象。两件原先各带一份**逐字节相同**的私有实现 —— 同一个动作两处落点，
//! 改一处必漏另一处 ⇒ 收进本件一份，两处引用它。
//!
//! **跨层只对齐名口径，不并实现**：`跨语言适配/适配器实现/src/扩展装载/接口描述.rs` 在别的 crate，
//! 值模型也是那边自带的 `JSON值` ⇒ 那份实现留在原处，只把动作名改成同一个 ——
//! 同一个动作叫同一个名，实现各归各层。

use crate::协议值::协议值;

/// 真假值 → 线上逻辑值（`协议值::真` / `协议值::假`）。
pub fn 真假值转线上值(真假值: bool) -> 协议值 {
    if 真假值 {
        协议值::真值
    } else {
        协议值::假值
    }
}
