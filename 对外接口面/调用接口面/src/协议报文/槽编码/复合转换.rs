/// `值`（数组或对象）→ 元素表。列表收**数组**（名称一律空串）；字典 / JSON值 / 结果结构收**对象**。
///
/// 映射口径（方案子件 §五之三②）：列表 = 数组、每项是既有「值项」形状；其余 = 对象、键即元素名。
/// **形状校验不在这里重写** —— 名称必空 / 必非空 / 不重名由 `编码复合值载荷` 统一判。
pub(super) fn 协议值到元素表(标签: u32, 待解值: &协议值, 位次: usize) -> Result<Vec<复合元素>, 请求形状错误> {
    if 标签 == 类型标签::列表型 {
        let 项表 = 待解值
            .取数组()
            .ok_or_else(|| 请求形状错误::构造(Some(位次), "类型标签 100（列表）的值必须是数组"))?;
        let mut 元素表 = Vec::with_capacity(项表.len());
        for 元素项 in 项表 {
            元素表.push(复合元素 {
                名称: String::new(),
                值: 值项到复合值(元素项, 位次)?,
            });
        }
        return Ok(元素表);
    }
    let 成员项表 = match 待解值 {
        协议值::对象值(成员项表) => 成员项表,
        _ => {
            return Err(请求形状错误::构造(
                Some(位次),
                format!("类型标签 {标签} 的值必须是对象（键 = 元素名、值 = 值项）"),
            ))
        }
    };
    let mut 元素表 = Vec::with_capacity(成员项表.len());
    for (元素名, 元素项) in 成员项表 {
        元素表.push(复合元素 {
            名称: 元素名.clone(),
            值: 值项到复合值(元素项, 位次)?,
        });
    }
    Ok(元素表)
}

/// 一个「值项」（`{类型标签, 值}`）→ 复合值。复合值可递归嵌套，故本函数自递归。
fn 值项到复合值(值项: &协议值, 位次: usize) -> Result<复合值, 请求形状错误> {
    let 出错位置 = Some(位次);
    let 标签 = 值项
        .取成员("类型标签")
        .and_then(协议值::取无符号)
        .and_then(|号值| u32::try_from(号值).ok())
        .ok_or_else(|| {
            请求形状错误::构造(出错位置, "每一项必须是 {\"类型标签\":N,\"值\":V}，且 类型标签 是非负整数")
        })?;
    let 项内值 = 值项.取成员("值").ok_or_else(|| {
        请求形状错误::构造(出错位置, "缺少 值：空位也必须写 {\"类型标签\":0,\"值\":0}")
    })?;
    match 标签 {
        类型标签::无值 => Ok(复合值::无值),
        类型标签::整数标签 => 项内值
            .取有符号()
            .map(复合值::整数值)
            .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 1（整数）的值必须是 64 位整数")),
        类型标签::双精度 => 项内值
            .取数值()
            .map(复合值::双精度)
            .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 2（双精度）的值必须是数值")),
        类型标签::逻辑型 => match 项内值.取无符号() {
            Some(1) => Ok(复合值::逻辑型(true)),
            Some(0) => Ok(复合值::逻辑型(false)),
            _ => Err(请求形状错误::构造(出错位置, "类型标签 3（逻辑型）的值只能是 0 或 1")),
        },
        类型标签::文本值 => 项内值
            .取文本()
            .map(|文本值| 复合值::文本载荷(文本值.to_owned()))
            .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 4（文本）的值必须是 JSON 字符串")),
        类型标签::字节集 => match 项内值.取文本() {
            Some(文本值) => base64解码(文本值).map(复合值::字节集).map_err(|错误| {
                请求形状错误::构造(出错位置, format!("字节集不是合法 base64：{}", 错误.说明文字))
            }),
            None => Err(请求形状错误::构造(出错位置, "类型标签 5（字节集）的值必须是 base64 字符串")),
        },
        类型标签::句柄 => 项内值
            .取无符号()
            .map(复合值::句柄)
            .ok_or_else(|| 请求形状错误::构造(出错位置, "类型标签 6（句柄）的值必须是非负整数")),
        类型标签::列表型 | 类型标签::字典 | 类型标签::JSON值 | 类型标签::结果结构 => Ok(复合值::复合 {
            标签,
            元素表: 协议值到元素表(标签, 项内值, 位次)?,
        }),
        _ => Err(请求形状错误::构造(
            出错位置,
            format!("类型标签 {标签} 未登记：它的 JSON 形状未定义，面不能猜着编码"),
        )),
    }
}

/// 元素表 → JSON。列表出**数组**、其余出**对象**（与 `协议值到元素表` 互为逆）。
pub(super) fn 元素表到协议值(标签: u32, 元素表: &[复合元素]) -> 协议值 {
    if 标签 == 类型标签::列表型 {
        return 协议值::数组值(元素表.iter().map(|元素项| 复合值到值项(&元素项.值)).collect());
    }
    协议值::对象值(
        元素表
            .iter()
            .map(|元素项| (元素项.名称.clone(), 复合值到值项(&元素项.值)))
            .collect(),
    )
}

/// 复合值 → 「值项」（`{类型标签, 值}`）。与 `值项到复合值` 互为逆。
fn 复合值到值项(待处理值: &复合值) -> 协议值 {
    let 内层值 = match 待处理值 {
        复合值::无值 => 协议值::整数项(0),
        复合值::整数值(整数值) => 协议值::整数项(*整数值),
        复合值::双精度(双精度值) => 协议值::小数(*双精度值),
        复合值::逻辑型(真值) => 协议值::整数项(i64::from(*真值)),
        复合值::文本载荷(文本值) => 协议值::文本值(文本值.clone()),
        复合值::字节集(字节) => 协议值::文本值(base64编码(字节)),
        复合值::句柄(句柄值) => 造数值(*句柄值),
        复合值::复合 { 标签, 元素表 } => 元素表到协议值(*标签, 元素表),
    };
    造槽项(待处理值.取标签(), 内层值)
}

