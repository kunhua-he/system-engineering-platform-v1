// 二 旁路端点的请求形状（`接口面形状.md` §七 的工具族）
// ════════════════════════════════════════════════════════════════════════════
//
// 分工与 §一 同：**本文件只判「请求体形状合不合法」**（⇒ HTTP 400），
// **不判业务**。所以：
//
// - `导出.目标` 在这里**只判「是不是一个非空文本」**，不在枚举里 —— 那要报 **9004**
//   （真错误码），是业务失败，判在 `工具响应.rs`。在这里判成 400 就等于把业务塞进协议层
//   （`分发.rs` 文件头那条分工）。
// - 同理 `菜单命令.编号` 是不是**已登记**的命令，判在 `工具响应.rs`（回 9001）。

/// 取一个必须存在的文本字段（缺席 / 不是文本 ⇒ 400 的说明文）。
fn 要文本(请求体: &协议值, 键名: &str, 形状: &str) -> Result<String, String> {
    if !matches!(请求体, 协议值::对象值(_)) {
        return Err(format!("请求体必须是对象：{形状}"));
    }
    请求体.取成员(键名)
        .and_then(协议值::取文本)
        .map(str::to_owned)
        .ok_or_else(|| format!("缺少 {键名}，或它不是文本：{形状}"))
}

/// `POST /接口/案例/跑` 的体 → 案例标识。
pub fn 解析案例标识(请求体: &协议值) -> Result<String, String> {
    let 标识 = 要文本(请求体, "案例标识", "{\"案例标识\":\"…\"}")?;
    if 标识.trim().is_empty() {
        return Err("案例标识 是空串 —— 空标识指不出哪个案例".to_owned());
    }
    // 路径安全：标识只能是**一个目录名**（案例库的形状是 `测试验证/案例/<案例名>/`）。
    // 放行 `/` 或 `..` 就等于让请求体决定读到仓里哪一处 —— 那是把「读哪」交给调用方。
    if 标识.contains('/') || 标识.contains('\\') || 标识 == "." || 标识 == ".." {
        return Err(format!("案例标识 必须是一个目录名，不许含路径分隔符：{标识}"));
    }
    Ok(标识)
}

/// `POST /接口/导出` 的体 → 导出请求。
#[derive(Debug, Clone)]
pub struct 导出请求 {
    /// 五种出口之一。**在这里不判合法性**（非法 ⇒ 9004，见文件头）。
    pub 导出目标: String,
    /// 可选的已产出制品标识。给了就走装配器的只读检查（`--检查`），不给就是一次真构建。
    pub 标识: Option<String>,
}

/// `POST /接口/导出` 的体 → `导出请求`。
pub fn 解析导出(请求体: &协议值) -> Result<导出请求, String> {
    let 导出目标 = 要文本(
        请求体,
        "目标",
        "{\"目标\":\"案例|支持库|模块|技能|制品\",\"标识\":…}",
    )?;
    let 标识 = match 请求体.取成员("标识") {
        None => None,
        Some(待处理值) => Some(
            待处理值.取文本()
                .map(str::to_owned)
                .ok_or_else(|| "标识 必须是文本（制品标识，形如 <提交12位>-<指纹16位>）".to_owned())?,
        ),
    };
    Ok(导出请求 { 导出目标, 标识 })
}

/// `POST /接口/程序文本` 的体 → 动作 + 路径 + 正文。
#[derive(Debug, Clone)]
pub struct 程序文本请求 {
    /// `读` / `写`（闭合枚举，已校验）。
    pub 动作: String,
    /// 调用方自带的路径。裁决（`项目文档/决策记录/2026-09-28_华哥的尺子与七条裁决.md`
    /// §二 206 行）定「项目/程序文本那一层」的落点 = **调用方自带路径**（底座不新增目录约定、
    /// 无隐式兜底）。缺键 / 空串都原样收下（**业务失败** ⇒ `9008`，见本函数头），不在这里判。
    pub 路径: String,
    /// 写动作要写的文本；读动作 `None`（写动作必须给，缺 ⇒ 400）。
    pub 正文: Option<String>,
    /// **权限等级**（安全前提）：缺键 ⇒ 最紧那一档（`只读`）。
    /// 取值域是闭合枚举（`工具根守卫::权限等级`）—— 默认在解析处给
    /// （「缺键 ⇒ 最紧」是一条口径，不是结构体的默认值）。
    pub 权限: crate::工具根守卫::权限等级,
}

/// `POST /接口/程序文本` 的体 → `程序文本请求`。
///
/// 形状：`{"动作":"读|写","路径":"…","正文":"…","权限":"只读|读写"}`
/// （`正文` 只在 `写` 时要；`权限` 可省，省了就是最紧那一档）。
///
/// **路径空在这里不判**：空路径是**业务失败**（回 `9008 程序文本路径为空`），不是请求体形状
/// 不合法 —— 裁决要「路径空」有一个**明确码**，故缺 `路径` / 空 `路径` 一律原样收下，
/// 交 `工具响应_未落.rs::程序文本` 报 9008。本函数只判协议层：体是对象 · `动作` 是闭合枚举 ·
/// 给了的键形状对（`路径` / `正文` 给了就必须是文本）。
pub fn 解析程序文本(请求体: &协议值) -> Result<程序文本请求, String> {
    let 动作 = 要文本(请求体, "动作", "{\"动作\":\"读|写\",\"路径\":\"…\",\"正文\":\"…\"}")?;
    if 动作 != "读" && 动作 != "写" {
        return Err(format!(
            "动作 只认 读 / 写 两个值（闭合枚举，不许按前缀猜），实际：{动作}"
        ));
    }
    // 路径：缺键按空串读（业务失败 ⇒ 9008，见本函数头）；给了就必须是文本。
    let 路径 = match 请求体.取成员("路径") {
        None => String::new(),
        Some(待处理值) => 待处理值
            .取文本()
            .map(str::to_owned)
            .ok_or_else(|| "路径 必须是文本（调用方自带的路径；缺键 / 空串按 9008 报，不是 400）".to_owned())?,
    };
    // 正文：写动作必须给（不给就是形状不合法 ⇒ 400；清空一份程序文本请显式给空串）。
    let 正文 = match 请求体.取成员("正文") {
        None => {
            if 动作 == "写" {
                return Err(
                    "写 动作必须给 正文（要写入的文本；清空一份程序文本请显式给空串）".to_owned()
                );
            }
            None
        }
        Some(待处理值) => Some(
            待处理值.取文本()
                .map(str::to_owned)
                .ok_or_else(|| "正文 必须是文本".to_owned())?,
        ),
    };
    let 权限 = 解析权限等级(请求体)?;
    Ok(程序文本请求 { 动作, 路径, 正文, 权限 })
}

/// 从请求体取 `权限` 键 ⇒ 权限等级。**缺键 = 最紧那一档**（不是错误）。
///
/// 缺键走默认而不是 400：`安全边界.md` §一 把经边界的输入定为不可信，
/// 而「没写权限」是这条不可信输入最常见的一种 —— 缺键落到最紧那一档是 fail-closed，
/// 把它判成 400 反而把「没提要求」变成「请求不合法」。
///
/// 给了别的词 ⇒ 400（闭合枚举，不许按前缀猜）：那与 `9014` 不是一回事 ——
/// `9014` 是「本档不许写」（业务失败，要看动作），而「权限键写了个别的词」是请求体形状不合法。
fn 解析权限等级(请求体: &协议值) -> Result<crate::工具根守卫::权限等级, String> {
    use crate::工具根守卫::权限等级;
    let Some(待处理值) = 请求体.取成员(权限键) else {
        return Ok(权限等级::默认);
    };
    let 权限名 = 待处理值
        .取文本()
        .ok_or_else(|| format!("{权限键} 必须是文本（只读 | 读写）"))?;
    match 权限名 {
        "只读" => Ok(权限等级::只读),
        "读写" => Ok(权限等级::读写),
        其它值 => Err(format!(
            "{权限键} 只认 只读 / 读写 两个值（闭合枚举，不许按前缀猜），实际：{其它值}"
        )),
    }
}

/// `POST /接口/菜单命令` 的体 → 命令编号（`菜单表.js` 里的十六进制字面量，如 `0xe100`）。
pub fn 解析菜单命令(请求体: &协议值) -> Result<String, String> {
    let 编号 = 要文本(请求体, "编号", "{\"编号\":\"0xe100\"}")?;
    if 编号.trim().is_empty() {
        return Err("编号 是空串 —— 空编号指不出哪条命令".to_owned());
    }
    Ok(编号)
}

/// `POST /接口/生命周期` 的体 → 卸载标识串（走 `2001 卸载` 正路）。
///
/// `动作` 是**闭合枚举**（本端点只实现「卸载」）：按前缀或别名猜动作等于把请求体的
/// 拼写错误静默当成别的动作 —— 那是协议层失败，回 400。
pub fn 解析卸载(请求体: &协议值) -> Result<String, String> {
    let 动作 = 要文本(请求体, "动作", "{\"动作\":\"卸载\",\"标识串\":\"…\"}")?;
    if 动作 != "卸载" {
        return Err(format!(
            "动作 只认 装载 / 卸载（闭合枚举，不许按前缀猜），实际：{动作}"
        ));
    }
    let 本扩展标识串 = 要文本(请求体, "标识串", "{\"动作\":\"卸载\",\"标识串\":\"…\"}")?;
    if 本扩展标识串.trim().is_empty() {
        return Err("标识串 是空串 —— 空标识指不出哪个扩展".to_owned());
    }
    Ok(本扩展标识串)
}

/// `POST /接口/生命周期` 的体是不是「**装载**」动作（网关据它决定走写锁那一支）。
///
/// 只看顶层 `动作` 是不是文本「装载」——**不在这里报 400**：动作合不合法由
/// `解析卸载`（卸载支）与 `生命周期响应::装载`（装载支）各自判（闭合枚举，不许按前缀猜）。
pub fn 是装载动作(请求体: &协议值) -> bool {
    请求体.取成员("动作").and_then(协议值::取文本) == Some("装载")
}
