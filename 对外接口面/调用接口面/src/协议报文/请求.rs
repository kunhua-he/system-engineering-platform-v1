//! 请求形状 —— `POST /接口/调用` 的体怎么读成「编号 + 按行序的槽」。
//!
//! 冻结件 `接口面形状.md` §三：
//!
//! ```json
//! { "编号": 1105, "值": [ { "类型标签": 5, "值": "<base64 字节集>" } ] }
//! ```
//!
//! 三条读法（都是冻结件写死的，不是本文件的偏好）：
//!
//! 1. `值` 按契约 `参数表` 的**行序**对位；空位写 `{"类型标签":0,"值":0}`，**不许省略位次**
//!    （省略就是改行序）。
//! 2. 每个值都是**带类型标签的定长槽**。
//! 3. 文本 ⇒ JSON 字符串；字节集 ⇒ base64 字符串；**靠 `类型标签` 区分，不靠形状猜**。
//! 4. **命名形态**（`方案 §9.1` E02）：`命名值` 给
//!    `{"参数名":{"类型标签":N,"值":V}}`，本面按契约 `参数表` 的 `名称` **严格**映射成行序
//!    （未知名 / 缺参数且该行没有声明默认值 ⇒ 400 且点名参数；见 `按契约映射`）。
//!    `值` 与 `命名值` **只能给一种** —— 两种给法给同一件事就是第二个语义源。
//!
//! **网关不校验参数个数**：那是 `调用调度` 的判定（`参数个数不符` 是它的段位）。
//! 命名形态是例外的一半：**按名映射**必须有契约才做得了，所以缺参 / 未知名在那一步就报
//! 400（那是「请求体形状不合法」，不是「参数个数不符」—— 位置形态照旧交给调度去判）。
//! 在这里再判一次就是第二套校验 —— 而且会和内核口径分叉。
//! `值` 缺席按**空表**读（JSON 里没有这个键就是没有项），空表照样交给调度去判。

use crate::契约级常量::权限键;
use crate::协议值::协议值;
use crate::槽编码::{self, 槽源, 请求形状错误};
use v1_adapter::适配器;

/// `POST /接口/调用` 的请求。
#[derive(Debug, Clone)]
pub struct 调用请求 {
    pub 编号: u32,
    /// 按契约行序排列的入参源数据。**顺序即契约**，本文件只做「不重排」。
    pub 值: Vec<槽源>,
    /// 命名形态的入参（`方案 §9.1` E02）：**给了这个键就是命名形态**（`Some`），
    /// 没给才是位置形态（`None`）。参数名 → 槽源，顺序即请求体里的键序。
    ///
    /// 为什么不用「空向量 = 没给」：那会把 `命名值:{}`（一个零参数能力的合法体，
    /// 或给全无默认值参数的请求）静默当成位置形态 —— 正是 E02 禁的「静默修正」。
    /// 与 `值` 互斥（两种给法给同一件事 = 第二个语义源）。
    pub 命名值: Option<Vec<(String, 槽源)>>,
}

/// 解析已通过 JSON 语法检查的请求体。
pub fn 解析调用(请求体: &协议值) -> Result<调用请求, 请求形状错误> {
    if !matches!(请求体, 协议值::对象值(_)) {
        return Err(请求形状错误::构造(
            None,
            "请求体必须是对象：{\"编号\":N,\"值\":[...]}",
        ));
    }
    let 编号 = 请求体
        .取成员("编号")
        .and_then(协议值::取无符号)
        .ok_or_else(|| 请求形状错误::构造(None, "缺少 编号，或它不是非负整数"))?;
    let 编号 = u32::try_from(编号)
        .map_err(|_| 请求形状错误::构造(None, "编号 超出 32 位，不是本平台的编号"))?;

    let 值项 = 请求体.取成员("值");
    let 命名项 = 请求体.取成员("命名值");
    if 值项.is_some() && 命名项.is_some() {
        return Err(请求形状错误::构造(
            None,
            "值 与 命名值 只能给一种：值 是位置形态（按契约行序逐位对），命名值 是命名形态\
             （按参数名映射行序）；两种同时给 = 同一件事两个语义源",
        ));
    }

    let mut 槽源表 = Vec::new();
    if let Some(项表) = 值项 {
        let 项表 = 项表
            .取数组()
            .ok_or_else(|| 请求形状错误::构造(None, "值 必须是数组（每一项是一个带类型标签的槽）"))?;
        for (位次, 槽项) in 项表.iter().enumerate() {
            槽源表.push(槽编码::由协议值(槽项, 位次)?);
        }
    }

    let mut 命名体: Option<Vec<(String, 槽源)>> = None;
    if let Some(命名项) = 命名项 {
        let 协议值::对象值(成员表) = 命名项 else {
            return Err(请求形状错误::构造(
                None,
                "命名值 必须是对象：{\"参数名\":{\"类型标签\":N,\"值\":V}}",
            ));
        };
        let mut 命名槽表 = Vec::with_capacity(成员表.len());
        for (位次, (名称, 槽项)) in 成员表.iter().enumerate() {
            // 出错定位到**参数名**（E02：输入错误定位到具体参数），不是数组位次。
            let 入参槽 = 槽编码::由协议值(槽项, 位次).map_err(|错误| {
                请求形状错误::构造(None, format!("命名值 的「{名称}」：{}", 错误.说明文字))
            })?;
            命名槽表.push((名称.clone(), 入参槽));
        }
        命名体 = Some(命名槽表);
    }

    Ok(调用请求 {
        编号,
        值: 槽源表,
        命名值: 命名体,
    })
}

/// 命名参数 → 行序槽表（`方案 §9.1` E02：命名参数**严格**映射行序）。
///
/// 只在给了 `命名值` 时动手；**位置形态（`值`）原样交回**（不重排、不补位 —— 参数个数的
/// 判定归调度层，见文件头）。三条严格口径：
///
/// 1. **名逐字比**：给的名字必须在契约 `参数表` 的某一行的 `名称` 上**逐字**命中
///    （不许按前缀 / 近似猜）；不命中 ⇒ 400，并报出未知的这个名与可用名表。
/// 2. **缺参数不静默补**：某一行没给值 —— 只有该行**声明了** `默认值`（非空槽）才填默认值
///    （那是声明登记的语义，不是本面造的值）；没声明默认值 ⇒ 400，并报出缺的那个名。
/// 3. **定位到具体参数**：每一条错误都点名参数名，不只说「第几位」。
///
/// 号没人认领 ⇒ 本函数**不判**（不在这里编业务错误）：交回，让调度按调度层的判定顺序报
/// `提供者未载入`（读侧与调侧同一个段位，不第二套）。
pub fn 按契约映射(适配器: &适配器, 请求: &mut 调用请求) -> Result<(), 请求形状错误> {
    let Some(命名槽表) = 请求.命名值.take() else {
        return Ok(());
    };
    let Some(契约) = 适配器.能力契约(请求.编号) else {
        return Ok(());
    };
    // 先核未知名：报错要能把「我给的哪个名不对」与「有哪些名可用」同时摆出来。
    for (传入名, _) in &命名槽表 {
        if !契约.参数表.iter().any(|参数行| *传入名 == 参数行.名称) {
            return Err(请求形状错误::构造(
                None,
                format!(
                    "未知参数「{传入名}」：本能力的参数表里没有这个名字（名字逐字比，不许按前缀或近似猜）。可用的名字：{}",
                    可用名表(&契约)
                ),
            ));
        }
    }
    let mut 行序槽表 = Vec::with_capacity(契约.参数表.len());
    for 参数行 in &契约.参数表 {
        match 命名槽表.iter().find(|(名称, _)| *名称 == 参数行.名称) {
            Some((_, 入参槽)) => 行序槽表.push(入参槽.clone()),
            None => {
                if 参数行.默认值.是否空() {
                    return Err(请求形状错误::构造(
                        None,
                        format!(
                            "缺参数「{}」：本能力这一行没有声明默认值，命名形态不许静默补空槽。可用的名字：{}",
                            参数行.名称,
                            可用名表(&契约)
                        ),
                    ));
                }
                行序槽表.push(槽源::声明默认 { 槽: 参数行.默认值 });
            }
        }
    }
    请求.值 = 行序槽表;
    Ok(())
}

/// 参数表里可用的名字（错误信息用；顺序即契约行序）。
fn 可用名表(契约: &v1_adapter::能力契约) -> String {
    契约
        .参数表
        .iter()
        .map(|参数行| 参数行.名称.clone())
        .collect::<Vec<String>>()
        .join(" · ")
}

