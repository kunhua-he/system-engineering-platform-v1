//! JSON 写出 —— 手写，零第三方依赖。
//!
//! **缩进版（两空格）**，与 `项目文档/设计文档/接口面形状.md` 里的示例同形：
//! 根端点的返回是给人也是给 agent 读的「说明书」，压成一行就丢掉了这层用途。
//!
//! # 两条确定性
//!
//! 1. **键序 = 插入序**（对象是 `Vec`，不是哈希表）⇒ 同一份数据两次序列化逐字节相同。
//! 2. **非有限浮点写 `null`**：`NaN` / `±Infinity` 不是合法 JSON，写出去就是给出一个
//!    调用方解析不了的东西。宁可写 `null`（= 无值），也不产出非法 JSON。

use crate::协议值::协议值;
// 转义表与缩进**不在这里再写一份**：那是正确性资产（少转一个控制字符就产出非法 JSON），
// 只许有一份 —— 下沉在 `跨语言适配/适配器实现/src/协议传值/小写出.rs`（本层只依赖适配器，不新增依赖边）。
use v1_adapter::小写出::{写JSON文本, 写缩进};

/// 序列化为缩进版 JSON 文本（**不含**结尾换行）。
pub fn 写协议值(待处理值: &协议值) -> String {
    let mut 输出缓冲 = String::new();
    写一个值(&mut 输出缓冲, 待处理值, 0);
    输出缓冲
}

fn 写一个值(输出缓冲: &mut String, 待处理值: &协议值, 层级: usize) {
    match 待处理值 {
        协议值::空值项 => 输出缓冲.push_str("null"),
        协议值::真值 => 输出缓冲.push_str("true"),
        协议值::假值 => 输出缓冲.push_str("false"),
        协议值::整数项(数值载荷) => 输出缓冲.push_str(&数值载荷.to_string()),
        协议值::无符号值(数值载荷) => 输出缓冲.push_str(&数值载荷.to_string()),
        协议值::小数(数值载荷) => {
            if 数值载荷.is_finite() {
                输出缓冲.push_str(&数值载荷.to_string());
            } else {
                // 非有限值不是合法 JSON（见文件头）。
                输出缓冲.push_str("null");
            }
        }
        协议值::文本值(文本载荷) => 写JSON文本(输出缓冲, 文本载荷),
        协议值::数组值(数组项表) => {
            if 数组项表.is_empty() {
                输出缓冲.push_str("[]");
                return;
            }
            输出缓冲.push('[');
            for (序号, 数组项) in 数组项表.iter().enumerate() {
                if 序号 > 0 {
                    输出缓冲.push(',');
                }
                写缩进(输出缓冲, 层级 + 1);
                写一个值(输出缓冲, 数组项, 层级 + 1);
            }
            写缩进(输出缓冲, 层级);
            输出缓冲.push(']');
        }
        协议值::对象值(对象成员) => {
            if 对象成员.is_empty() {
                输出缓冲.push_str("{}");
                return;
            }
            输出缓冲.push('{');
            for (位序, (成员键, 成员值)) in 对象成员.iter().enumerate() {
                if 位序 > 0 {
                    输出缓冲.push(',');
                }
                写缩进(输出缓冲, 层级 + 1);
                写JSON文本(输出缓冲, 成员键);
                输出缓冲.push_str(": ");
                写一个值(输出缓冲, 成员值, 层级 + 1);
            }
            写缩进(输出缓冲, 层级);
            输出缓冲.push('}');
        }
    }
}

/// 写一个 JSON 字符串。非 ASCII 原样走 UTF-8（响应头声明 `charset=utf-8`），
/// 不转成 `\uXXXX`——转了体积大三倍且更难读。
#[cfg(test)]
mod 写出测试 {
    use super::*;

    #[test]
    fn 转义_引号反斜杠控制字符都转() {
        assert_eq!(写协议值(&协议值::文本值("a\"b\\c\nd\u{1}".to_owned())), r#""a\"b\\c\nd\u0001""#);
        // 非 ASCII 原样走 UTF-8。
        assert_eq!(写协议值(&协议值::文本值("接口".to_owned())), "\"接口\"");
    }

    #[test]
    fn 空容器与嵌套_形状对() {
        assert_eq!(写协议值(&协议值::数组值(Vec::new())), "[]");
        assert_eq!(写协议值(&协议值::对象值(Vec::new())), "{}");
        let 待处理值 = 协议值::对象值(vec![
            ("首项".to_owned(), 协议值::整数项(1)),
            ("次项".to_owned(), 协议值::数组值(vec![协议值::真值])),
        ]);
        assert_eq!(写协议值(&待处理值), "{\n  \"首项\": 1,\n  \"次项\": [\n    true\n  ]\n}");
    }

    #[test]
    fn 非有限浮点写空值_不产出非法协议体() {
        assert_eq!(写协议值(&协议值::小数(f64::NAN)), "null");
        assert_eq!(写协议值(&协议值::小数(f64::INFINITY)), "null");
    }
}
