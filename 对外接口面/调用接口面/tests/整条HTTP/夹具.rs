// ════════════════════════════════════════════════════════════════════════
// 计数全局分配器：证 HTTP 路径对带所有权交出的返回槽**真回收**（审计发现 1）
//
// `#[global_allocator]` 是 crate 级：整个本测试二进制（含链接进来的库）都走它。
// 与 `跨语言适配/适配器实现/src/边界测试.rs` 同一手法：执行函数记下它交出的堆块地址，
// 分配器在 dealloc 时比中该地址就 +1 —— 证「指定返回地址真的发生 free」，不是只证「槽形状对」。
// 反向样本：把 `响应.rs::调用` 的回收那行删掉 ⇒ 命中读数恒 0。
// ════════════════════════════════════════════════════════════════════════

use core::alloc::{GlobalAlloc, Layout};

/// 交出字节集的执行函数记下的堆块地址（0 = 还没交过）。
pub(super) static 交出地址: AtomicUsize = AtomicUsize::new(0);
/// 被盯地址上的 `dealloc` 命中数。
pub(super) static 命中次数: AtomicUsize = AtomicUsize::new(0);

struct 盯住分配器;

unsafe impl GlobalAlloc for 盯住分配器 {
    unsafe fn alloc(&self, 内存布局: Layout) -> *mut u8 {
        unsafe { std::alloc::System.alloc(内存布局) }
    }
    unsafe fn dealloc(&self, 指针: *mut u8, 内存布局: Layout) {
        let 盯住地址 = 交出地址.load(Ordering::SeqCst);
        if 盯住地址 != 0 && 指针 as usize == 盯住地址 {
            命中次数.fetch_add(1, Ordering::SeqCst);
        }
        unsafe { std::alloc::System.dealloc(指针, 内存布局) }
    }
}

#[global_allocator]
static 分配器: 盯住分配器 = 盯住分配器;

