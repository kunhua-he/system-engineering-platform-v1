/// 合成能力的执行函数：把特征值放进返回槽（类型标签 1 = 整数）。
pub(super) unsafe extern "C" fn 合成执行(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    let _ = (参数个数, 参数表);
    if !返回槽.is_null() {
        // SAFETY: 空指针已挡；非空由调用契约保证可写。
        unsafe { *返回槽 = 数据槽::内联槽(类型标签::构造(1), 特征值, 0) };
    }
}

/// 交出字节集的执行函数：用 `Box::into_raw` 分配并置「所有权交出」
/// （与外部支持库的 `写字节集` 逐字同一动作），同时把地址记进静态供分配器盯住。
pub(super) unsafe extern "C" fn 合成执行_交出字节集(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    let _ = (参数个数, 参数表);
    if 返回槽.is_null() {
        return;
    }
    let 堆地址 = Box::into_raw(vec![0x5Au8; 字节集字节数].into_boxed_slice()) as *mut u8;
    交出地址.store(堆地址 as usize, Ordering::SeqCst);
    // SAFETY: 返回槽 由调用契约保证可写；堆地址 刚由 Box 交出、有效至归还。
    unsafe {
        *返回槽 = 数据槽::指针(
            类型标签::构造(5),
            堆地址 as u64,
            字节集字节数 as u64,
            true,
        );
    }
}

