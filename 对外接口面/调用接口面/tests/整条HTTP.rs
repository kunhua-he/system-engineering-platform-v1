    /// **发现3 反向样本（HTTP 路）**：卸载是完整状态转换 —— 卸载成功后同一能力不再可调。
    ///
    /// 只看通知端点数空不空是旧判据的射程；本用例看的是**路由真收回了**：
    /// 卸载前 `POST /接口/调用` 调 `合成编号` ⇒ `成功: true`；
    /// `POST /接口/生命周期 {动作:卸载}` ⇒ `派发结果: 成功` 且 `已装载声明数` 减一；
    /// 卸载后再调同一号 ⇒ **不再是 `成功: true`**（返回槽里是错误码 1「提供者未载入」）。
    ///
    /// 重载路（同一身份可重装）在 Rust 面真跑：本仓的 `v1-adapter` 里
    /// `卸载_完整状态转换_能力失效且可重装`（HTTP 面重载要盘上制品，非本用例射程）。
    #[test]
    fn 整条HTTP_卸载后同一能力不再可调() {
        let 静态根 = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../前端呈现/网页应用");
        let 服务 = 服务::绑定并托管(&[底座声明(), 夹具声明::合成生命周期声明()], 0, 静态根)
            .expect("底座 + 合成生命周期声明必须载得进来");

        // 卸载前：调合成能力 ⇒ 成功（返回槽带回特征值）。
        let 调用请求体 = format!("{{\"编号\":{合成编号},\"值\":[]}}");
        let (状态, 卸载前调用结果) = 发请求(
            &服务,
            &format!(
                "POST /接口/调用 HTTP/1.1\r\nHost: 127.0.0.1\r\nContent-Type: application/json\r\nContent-Length: {}\r\n\r\n{调用请求体}",
                调用请求体.len()
            ),
        );
        assert_eq!(状态, 200);
        assert!(
            卸载前调用结果.contains("\"成功\": true"),
            "卸载前该调得通：\n{卸载前调用结果}"
        );
        let 卸载前声明数 = 服务.适配器().已装载声明数();

        // 卸载：完整状态转换。
        let 卸载请求体 = "{\"动作\":\"卸载\",\"标识串\":\"0011223344556677889900aabbccddee\"}";
        let (状态, 卸载结果) = 发请求(
            &服务,
            &format!(
                "POST /接口/生命周期 HTTP/1.1\r\nHost: 127.0.0.1\r\nContent-Type: application/json\r\nContent-Length: {}\r\n\r\n{卸载请求体}",
                卸载请求体.len()
            ),
        );
        assert_eq!(状态, 200, "协议层仍 200（结局在数据里）：\n{卸载结果}");
        assert!(卸载结果.contains("\"派发结果\": \"成功\""), "卸载必须成功：\n{卸载结果}");
        assert!(
            卸载结果.contains(&format!("\"已装载声明数\": {}", 卸载前声明数 - 1)),
            "卸载后已装载声明数必须减一（该份路由真摘了）：\n{卸载结果}"
        );

        // 卸载后：同一号**不再成功**（返回槽是错误码 1「提供者未载入」）。
        let (状态, 卸载后调用结果) = 发请求(
            &服务,
            &format!(
                "POST /接口/调用 HTTP/1.1\r\nHost: 127.0.0.1\r\nContent-Type: application/json\r\nContent-Length: {}\r\n\r\n{调用请求体}",
                调用请求体.len()
            ),
        );
        assert_eq!(状态, 200);
        assert!(
            !卸载后调用结果.contains("\"成功\": true"),
            "卸载后该号必须不再可调（不再成功）：\n{卸载后调用结果}"
        );
        assert!(
            卸载后调用结果.contains(&format!("\"码\": {}", 声明数据::错误码_0001.取号值())),
            "卸载后该号必须报「提供者未载入」（码 1）：\n{卸载后调用结果}"
        );
    }

    /// C1/C2 反向样本（HTTP 路）：卸载**先 2001 协商**；扩展回 `延迟释放`（拒绝本次）⇒
    /// 清零后**再发 2003 复核**；只有复核回成功才摘逻辑。**逻辑卸载与物理回收分别出读数**：
    /// 无跨进程启用状态 ⇒ 物理回收 = 0（不杀域）。
    #[test]
    fn 整条HTTP_卸载先协商被拒后复核才摘逻辑() {
        let 静态根 = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../前端呈现/网页应用");
        let 服务 = 服务::绑定并托管(&[底座声明(), 夹具声明::先拒后放声明()], 0, 静态根)
            .expect("底座 + 先拒后放声明必须载得进来");
        先拒后放计数.store(0, Ordering::SeqCst);
        let 卸载请求体 = "{\"动作\":\"卸载\",\"标识串\":\"ffeeddccbbaa99887766554433221100\"}";
        let (状态, 应答体) = 发请求(
            &服务,
            &format!(
                "POST /接口/生命周期 HTTP/1.1\r\nHost: 127.0.0.1\r\nContent-Type: application/json\r\nContent-Length: {}\r\n\r\n{卸载请求体}",
                卸载请求体.len()
            ),
        );
        assert_eq!(状态, 200, "结局在数据里：\n{应答体}");
        assert!(
            应答体.contains("\"派发结果\": \"成功\""),
            "2003 复核回成功 ⇒ 派发结果成功：\n{应答体}"
        );
        assert!(应答体.contains("\"逻辑卸载\": 1"), "复核成功才摘逻辑：\n{应答体}");
        assert!(应答体.contains("\"物理回收\": 0"), "无跨进程启用状态 ⇒ 不杀域：\n{应答体}");
        assert_eq!(
            先拒后放计数.load(Ordering::SeqCst),
            2,
            "恰好 2001（被拒）+ 2003（放行）两次通知"
        );
    }
