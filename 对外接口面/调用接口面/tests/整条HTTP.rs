    /// 判据：**HTTP 响应组装后，带所有权交出的返回槽真回收**（审计发现 1 的 HTTP 侧身份证）。
    ///
    /// 反向样本：把 `响应.rs::调用` 里那行 `归还槽值(&mut 返回槽)` 删掉 ⇒ 命中读数恒 0
    /// （本用例当场挂）—— 那就是报告里「HTTP 响应组装也没有归还所有权」的原状。
    #[test]
    fn 整条HTTP_交出字节集_响应后真回收() {
        let 服务 = 起服务();
        // 清零：确保命中计数从 0 起（上一个用例可能驻过地址）。
        交出地址.store(0, Ordering::SeqCst);
        命中次数.store(0, Ordering::SeqCst);
        let 请求体 = format!("{{\"编号\":{交出字节集编号},\"值\":[]}}");
        let 请求 = format!(
            "POST /接口/调用 HTTP/1.1\r\nHost: 127.0.0.1\r\nContent-Type: application/json; charset=utf-8\r\nContent-Length: {}\r\n\r\n{请求体}",
            请求体.len()
        );
        let (状态, 造应答) = 发请求(&服务, &请求);
        assert_eq!(状态, 200, "业务结果不许进 HTTP 状态码：\n{造应答}");
        assert!(造应答.contains("\"成功\": true"), "调用必须成功：\n{造应答}");
        // HTTP 应答里字节集走 base64；断言类型标签 5 证「真调到了交出字节集那条能力」。
        assert!(
            造应答.contains("\"类型标签\": 5"),
            "返回槽必须是字节集（证明真调到了交出字节集那条能力）：\n{造应答}"
        );
        // ★ 身份证：执行函数交出的那个堆块地址，真的发生过 free。
        // 先读命中读数、再关掉盯住（免并发的别的用例把同一地址释放了混进来）。
        // 断言 >= 1 而非 == 1：该地址 free 后可能被后续分配复用（如写回应体）再 free ⇒ 计数可能 > 1。
        // 要证的是「该地址确实发生了回收」，不是「全局只释放了一次」；旧行为下这个数恒为 0。
        let 命中读数 = 命中次数.load(Ordering::SeqCst);
        交出地址.store(0, Ordering::SeqCst);
        assert!(
            命中读数 >= 1,
            "HTTP 响应组装后必须回收带所有权交出的返回槽（旧行为下恒为 0），实测 {命中读数}"
        );
    }

