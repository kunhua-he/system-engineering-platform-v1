//! 整条 HTTP —— 起真服务 → 发原始请求 → 收应答，**走完整条生产路径**。
//!
//! # 与网关单元测试的分工
//!
//! 网关自身的用例（`src/接口面测试/`）只能拿**底座自身那一份声明**起服务，因为声明根
//! 要的构造类型原先只能从 `v1-loader` 的 dev-dependency 边够到（**那条边已拆**：拿底座声明
//! 一律走 `v1_adapter`）。本件用
//! `v1_adapter` 公开面**再导出**的那组类型，现造一份**合成扩展声明**（`跨语言适配/
//! 适配器实现/` 是唯一腿），于是「整条 HTTP」能带一条**测试自身控得住的能力**跑通 ——
//! 这是测试层原先走不了的那一半。
//!
//! # 走的是哪条路
//!
//! `TcpStream::connect` → `TcpListener::accept` → 手写 HTTP 解析 → 路由 →
//! 适配器 `调用能力` → 调度 → 合成执行函数 → 手写 HTTP 造应答。**没有一段是直接调内部函数。**
//!
//! # 为什么不开线程
//!
//! `TcpStream::connect` 只要监听已 `bind`+`listen` 就成功（内核 accept 队列接住），
//! 故顺序是：连上 → 写请求 → `服务::处理一个连接()` → 读应答，全在一个线程里。

