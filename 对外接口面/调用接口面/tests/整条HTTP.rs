//! 整条 HTTP —— 起真服务 → 发原始请求 → 收应答，**走完整条生产路径**。
//!
//! # 与网关单元测试的分工
//!
//! 网关自身的用例（`src/接口面测试/`）只能拿**底座自身那一份声明**起服务，因为声明根
//! 要的构造类型原先只能从 `v1-loader` 的 dev-dependency 边够到（**那条边已拆**：拿底座声明
//! 一律走 `v1_adapter`）。本件用
//! `v1_adapter` 公开面**再导出**的那组类型，现造一份**合成扩展声明**（`跨语言适配/
//! 适配器实现/` 是唯一腿），于是「整条 HTTP」能带一条**测试自身控得住的能力**跑通 ——
//! 这是测试层原先走不了的那一半。
//!
//! # 走的是哪条路
//!
//! `TcpStream::connect` → `TcpListener::accept` → 手写 HTTP 解析 → 路由 →
//! 适配器 `调用能力` → 调度 → 合成执行函数 → 手写 HTTP 应答。**没有一段是直接调内部函数。**
//!
//! # 为什么不开线程
//!
//! `TcpStream::connect` 只要监听已 `bind`+`listen` 就成功（内核 accept 队列接住），
//! 故顺序是：连上 → 写请求 → `服务::处理一个连接()` → 读应答，全在一个线程里。

#[cfg(test)]
mod 整条HTTP {
    use std::io::{Read, Write};
    use std::net::TcpStream;

    use v1_adapter::{
        号段, 命令信息, 底座声明, 执行函数, 数据槽, 声明数据, 声明格式号, 平台信息, 版本三元组, 版本要求,
        类型标签, 能力号, 表段, 错误码, 错误码信息,
    };
    use v1_gateway::服务;

    /// 合成能力的编号（落在它自身申报的能力号段 `[1000, 1999]` 内）。
    const 合成编号: u32 = 1000;

    /// 合成能力写进返回槽的**特征值**：HTTP 应答里只有它能带出这个数。
    const 特征值: u64 = 20817;

    /// 合成能力的执行函数：把特征值放进返回槽（类型标签 1 = 整数）。
    unsafe extern "C" fn 合成执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
        let _ = (参数个数, 参数表);
        if !返回槽.is_null() {
            // SAFETY: 空指针已挡；非空由调用契约保证可写。
            unsafe { *返回槽 = 数据槽::内联(类型标签::新(1), 特征值, 0) };
        }
    }

    /// 合成能力自身登记的可抛错误码（码 1001，段位 1 = 能力号段 1xxx 的首位）。
    const 合成可抛码: u32 = 1001;

    /// 一份**六步全过**的合成扩展声明：占能力号段 `[1000, 1999]`，一条零参能力，
    /// 它**自身**登记一个可抛错误码（用来验「可抛错误码按命令给」这条也走得通 HTTP）。
    ///
    /// 字段与 `跨语言适配/适配器实现/src/测试夹具.rs` 同形 —— 那份已由适配器自身的测试
    /// 钉住「载得进来」，本件不另发明一份形状。
    fn 合成声明() -> &'static 平台信息 {
        static 标识串: &[u8] = b"a1b2c3d4e5f60718293a4b5c6d7e8f90\0";
        static 段表: [号段; 1] = [号段::新(1000, 1999)];
        static 段位表: [u32; 1] = [1];

        let 可抛码: &'static [错误码] = Box::leak(Box::new([错误码::新(合成可抛码)]));
        let 错误码表: &'static [错误码信息] = Box::leak(Box::new([错误码信息 {
            码: 合成可抛码,
            段位: 1,
            名称: c"合成码".as_ptr().cast::<u8>(),
            说明: c"整条 HTTP 测试用。".as_ptr().cast::<u8>(),
            可重试: 1,
            可自愈: 0,
            需人工: 0,
            保留: 0,
        }]));
        let 命令表: &'static [命令信息] = Box::leak(Box::new([命令信息 {
            名称: c"合成能力".as_ptr().cast::<u8>(),
            说明: c"整条 HTTP 测试用，不参与平台语义。".as_ptr().cast::<u8>(),
            类别: 0,
            状态位: 0,
            返回类型: 类型标签::新(1),
            用户级别: 0,
            参数个数: 0,
            参数表: core::ptr::null(),
            编号: 能力号::新(合成编号),
            可抛错误码: 表段::新(可抛码.as_ptr(), 1),
        }]));
        let 函数表: &'static [执行函数] = Box::leak(Box::new([合成执行 as 执行函数]));
        Box::leak(Box::new(平台信息 {
            声明格式号,
            目标字宽: 声明数据::底座目标字宽,
            保留: 0,
            标识串: 标识串.as_ptr(),
            实现版本: 版本三元组::新(1, 0, 0),
            要求宿主版本: 版本要求::新(1, 0),
            要求内核版本: 版本要求::新(1, 0),
            名称: c"合成扩展".as_ptr().cast::<u8>(),
            说明: c"整条 HTTP 测试用，不参与平台语义。".as_ptr().cast::<u8>(),
            状态位: 0,
            类型表: 表段::空(),
            命令表: 表段::新(命令表.as_ptr(), 1),
            函数表: 函数表.as_ptr(),
            常量表: 表段::空(),
            通知函数: None,
            依赖清单: 表段::空(),
            能力号段: 表段::新(段表.as_ptr(), 1),
            通知号段: 表段::空(),
            错误段位表: 表段::新(段位表.as_ptr(), 1),
            错误码表: 表段::新(错误码表.as_ptr(), 1),
            // 两张空表都是「本声明没有」，不是漏写：夹具不声明类别表、不要求任何权限。
            命令类别表: 表段::空(),
            要求权限: 表段::空(),
        }))
    }

    /// 起一个服务：声明根 = [底座, 合成扩展]，端口让 OS 分配。
    ///
    /// 静态托管根显式注入（测试的 cwd 是 crate 目录，默认根是「相对进程工作目录」的仓根口径）。
    fn 起服务() -> 服务 {
        let 静态根 = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../前端呈现/网页应用");
        服务::绑定并托管(&[底座声明(), 合成声明()], 0, 静态根).expect("底座 + 合成声明必须载得进来")
    }

    /// 发一条原始请求并收回应答（状态码 + 原始文本）。
    fn 发请求(服务: &服务, 请求: &str) -> (u16, String) {
        let mut 流 = TcpStream::connect(("127.0.0.1", 服务.端口())).expect("必须连得上（监听已 bind）");
        流.write_all(请求.as_bytes()).expect("写请求");
        流.flush().expect("刷请求");
        服务.处理一个连接().expect("服务必须处理一次");
        let mut 缓冲 = Vec::new();
        流.read_to_end(&mut 缓冲).expect("读应答");
        let 文 = String::from_utf8(缓冲).expect("应答必须是 UTF-8");
        let (头, 体) = 文.split_once("\r\n\r\n").expect("应答必须有头体分界");
        let 状态 = 头
            .lines()
            .next()
            .and_then(|行| 行.split(' ').nth(1))
            .and_then(|码| 码.parse::<u16>().ok())
            .expect("应答首行必须是「HTTP/1.1 码 短语」");
        (状态, 体.to_owned())
    }

    /// `GET /接口` → 自描述根里必须有**合成扩展**那条能力（起服务时声明根带上了它）。
    #[test]
    fn 整条HTTP_自描述根带出合成扩展的能力() {
        let 服务 = 起服务();
        let (状态, 体) = 发请求(&服务, "GET /接口 HTTP/1.1\r\nHost: 127.0.0.1\r\n\r\n");
        assert_eq!(状态, 200);
        assert!(
            体.contains(&format!("\"编号\": {合成编号}")),
            "自描述根的能力清单必须带上合成扩展那条（声明根里确实有它）：\n{体}"
        );
        assert!(
            体.contains("\"名称\": \"合成能力\""),
            "清单里的名称必须从合成声明现读：\n{体}"
        );
    }

    /// `POST /接口/调用` 调合成能力：**整条 HTTP 走通**，返回槽带回合成执行函数的特征值。
    #[test]
    fn 整条HTTP_合成能力经调用端点返回特征值() {
        let 服务 = 起服务();
        let 体 = format!("{{\"编号\":{合成编号},\"值\":[]}}");
        let 请求 = format!(
            "POST /接口/调用 HTTP/1.1\r\nHost: 127.0.0.1\r\nContent-Type: application/json; charset=utf-8\r\nContent-Length: {}\r\n\r\n{体}",
            体.len()
        );
        let (状态, 应答) = 发请求(&服务, &请求);
        assert_eq!(状态, 200, "业务结果不许进 HTTP 状态码：\n{应答}");
        assert!(应答.contains("\"成功\": true"), "调用必须成功：\n{应答}");
        assert!(
            应答.contains(&format!("\"值\": {特征值}")),
            "返回槽必须带回合成执行函数写的特征值 {特征值}（证明真调到了它）：\n{应答}"
        );
    }

    /// `GET /接口/能力/<编号>` → 合成能力的完整契约从**合成声明**现读。
    #[test]
    fn 整条HTTP_合成能力的契约端点() {
        let 服务 = 起服务();
        let 请求 = format!("GET /接口/能力/{合成编号} HTTP/1.1\r\nHost: 127.0.0.1\r\n\r\n");
        let (状态, 体) = 发请求(&服务, &请求);
        assert_eq!(状态, 200);
        assert!(体.contains("\"成功\": true"), "能力端点应答：\n{体}");
        assert!(
            体.contains(&format!("\"编号\": {合成编号}")),
            "契约里的编号必须是合成声明的编号：\n{体}"
        );
        assert!(
            体.contains("\"返回类型\": 1"),
            "返回类型必须从合成声明现读（1 = 整数）：\n{体}"
        );
    }

    /// `可抛错误码` 是**这条命令自身**登记的那张（不是声明全表），六项 + 旁路项 `已登记` 齐。
    #[test]
    fn 整条HTTP_可抛错误码按命令给出且六项齐() {
        let 服务 = 起服务();
        let 请求 = format!("GET /接口/能力/{合成编号} HTTP/1.1\r\nHost: 127.0.0.1\r\n\r\n");
        let (状态, 体) = 发请求(&服务, &请求);
        assert_eq!(状态, 200);
        for 片段 in [
            format!("\"码\": {合成可抛码}"),
            "\"段位\": 1".to_owned(),
            "\"名称\": \"合成码\"".to_owned(),
            "\"可重试\": true".to_owned(),
            "\"可自愈\": false".to_owned(),
            "\"需人工\": false".to_owned(),
            "\"已登记\": true".to_owned(),
        ] {
            assert!(体.contains(&片段), "可抛错误码必须给 {片段}：\n{体}");
        }
    }
}
