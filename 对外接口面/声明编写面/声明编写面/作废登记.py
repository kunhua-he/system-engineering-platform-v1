# -*- coding: utf-8 -*-
"""作废登记 —— 面内的第五个类别：往 `契约声明/作废号表.json` 的 `作废` 数组**追加一行**。

形状唯一来源：`契约声明/格式说明.md` §七（五键行：`编号` · `原名称` · `作废于` · `原因` · `号空间`）。
本模块**不新造形状**，也不复制一份五键定义 —— 它只做两件形状层的事：
    ① 把请求的 `正文` 对齐成五键（缺的可推导的当场补：`作废于` 缺省 = 今天）；
    ② 按 `号空间` 判「这一行指向的号确实在**那个空间**里活跃」。

**一次作废 = 一次追加，不是一次覆盖**（与四个编号目录的「一个号一个文件」不同）：
它是 `号只增不复用` 的行为本身 —— 表只增长，永不回头改写已有的行。
落点是一份 JSON 对象（数组在对象里），故追加 = 重写整份件；「只增长」由 `只增判定` 守，
任何旧行被改/被删即拒收（同 `落盘.只增判定` 的口径，但更严：只认「前缀不动 + 尾部多一行」）。
"""

import json
import time
from pathlib import Path

# 五键行的形状：唯一来源 `格式说明.md` §七。缺键即拒收（不静默补一个猜的值）。
五键 = ("编号", "原名称", "作废于", "原因", "号空间")

# 号空间值域：**五个**（`格式说明.md` §七）。作废只封**同空间**的号 ——
# 数字相同不算同号（能力号 16 与错误码 16 是两回事）。
号空间值域 = ("能力", "类型", "通知", "错误码", "资源")


def 读作废号表(声明根):
    """→ (表对象, 现有条目表, 错说明)。读不动 ⇒ fail-closed（不覆写一份读不懂的档案）。"""
    路径 = Path(声明根) / "作废号表.json"
    if not 路径.is_file():
        return None, None, "%s 不在（作废登记的唯一落点）" % 路径.name
    try:
        配置表 = json.loads(路径.read_bytes().decode("utf-8"))
    except (OSError, UnicodeDecodeError, ValueError) as 错误:
        return None, None, "%s 读不动（%s）⇒ 面不覆写一份自身读不懂的已公布档案" % (路径.name, 错误)
    if not isinstance(配置表, dict):
        return None, None, "%s 顶层不是对象（§七 的形状）" % 路径.name
    作废条目 = 配置表.get("作废")
    if not isinstance(作废条目, list):
        return None, None, "%s 的 作废 不是数组（§七 的形状）" % 路径.name
    return 配置表, 作废条目, ""


def 编五键行(正文, 编号):
    """把请求的 `正文` 对齐成五键行。缺键按 §七 的可推导项补（`作废于` 缺省 = 今天）。"""
    五键行 = dict(正文)
    五键行["编号"] = 编号
    if not 五键行.get("作废于"):
        五键行["作废于"] = time.strftime("%Y-%m-%d")
    缺失键表 = [键名 for 键名 in 五键 if 键名 not in 五键行]
    return 五键行, 缺失键表


def 只增判定(旧条目, 新条目):
    """作废表只许**追加**：旧行必须逐字全在（按位置），新行只能多出来。

    比 `落盘.只增判定` 严：这里旧值是一份**历史档案**，故只认「前缀不动 + 尾部多一行」
    （那正是对一个数组「只追加」能有的唯一合法形态）。乱序插一行也算改历史 ⇒ 拒收。
    """
    if len(新条目) < len(旧条目):
        return False, "新表比旧表短（删了 %d 行）" % (len(旧条目) - len(新条目))
    for 序号, 旧行 in enumerate(旧条目):
        if 新条目[序号] != 旧行:
            return False, "第 %d 行被改（作废表是历史档案，只许在尾部追加）" % (序号 + 1,)
    if len(新条目) == len(旧条目):
        return False, "没有新行（一次作废 = 追加一行）"
    return True, ""
