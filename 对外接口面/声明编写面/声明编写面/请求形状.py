# -*- coding: utf-8 -*-
"""请求形状 —— `{类别, 编号?, 正文, 确认?}` → 类别 · 目录 · 编号字段 · 正文。

面**只判请求形状**（等价 HTTP 400：请求本身合不合法）。内容契约一律交判据器，
面里不许出现第二套校验（`开发规范.md` A2 · `接口面形状.md` §四 两条硬规则）。

`请求类别表` 是**唯一的映射表**：类别 → （落点目录, 编号字段名）。
前四个（`编号目录类别表`）与判据器的四个编号目录逐字对应，不许再加别名；
第五个「作废」不是编号目录（落点是一份表、一次登记 = 追加一行），见 `作废类别`。
"""

# 「一个号一个文件」的**四个编号目录**类别：类别 → （落点目录, 编号字段名）。
# 取值与判据器的四个编号目录逐字对应；加一个编号目录 = 加一个号空间，属裁决。
编号目录类别表 = {
    "能力": ("能力声明", "编号"),
    "类型": ("类型声明", "类型标签"),
    "错误码": ("错误码表", "码"),
    "通知号": ("通知号段", "通知号"),
}

# 第五个类别「作废」：它**不是**编号目录 —— 落点是**一份表**
# （`契约声明/作废号表.json` 的 `作废` 数组，形状见 `格式说明.md` §七 的五键行），
# 一次登记 = 往那数组**追加一行**。故目录位留空串，写路由由 `编排._登记作废` 接管。
# 收它进面的理由：README §九 定「`契约声明/` 的写入只有一条路 = 声明编写面」，
# 而作废号表住在 `契约声明/` ⇒ 不给它面内的路，那条纪律对它就有一个绕不过去的例外。
作废类别 = "作废"

# 面向请求的**唯一**类别表（四个编号目录 ＋ 作废）。
请求类别表 = {**编号目录类别表, 作废类别: ("", "编号")}


def _是整数(待处理值) -> bool:
    """逻辑型不算整数（Python 里 True 是 int 的子类，这里必须排掉）。"""
    return isinstance(待处理值, int) and not isinstance(待处理值, bool)


def 解析请求(请求):
    """→ (类别, 目录, 编号字段, 编号, 正文, 确认, 形状错列表)。

    形状错非空时后面几项可能为 None；调用方按「有错就不落盘」处理。
    """
    错误表 = []
    if not isinstance(请求, dict):
        return None, None, None, None, None, False, ["请求不是 JSON 对象（形状：{类别,编号,正文,确认}）"]
    类别 = 请求.get("类别")
    if 类别 not in 请求类别表:
        错误表.append(
            "类别 必须是 %s 之一（收到 %r）；它是落哪个目录 · 编号字段叫什么 的唯一依据"
            % (" · ".join(请求类别表), 类别)
        )
        return 类别, None, None, None, None, False, 错误表
    目录, 字段 = 请求类别表[类别]

    编号 = 请求.get("编号")
    if 编号 is not None and not _是整数(编号):
        错误表.append("编号 必须是整数或 null（收到 %r）；null 表示由面自动分配" % (编号,))
    if 类别 == 作废类别 and 编号 is None:
        错误表.append(
            "作废 的 编号 不许留空：作废登记指向一个**已存在**的号（号只增不复用），"
            "面不为它找空洞、不猜起始值 ⇒ 请显式给 编号"
        )

    正文 = 请求.get("正文")
    if not isinstance(正文, dict):
        错误表.append(
            "正文 必须是 JSON 对象，形状 = 契约声明/格式说明.md 里那一类 JSON，逐字一致"
            "（面不改名 · 不重排 · 不加壳）"
        )

    确认 = 请求.get("确认") is True
    if 错误表:
        return 类别, 目录, 字段, None, None, 确认, 错误表
    return 类别, 目录, 字段, 编号, 正文, 确认, []


def 合成正文(正文, 字段, 编号):
    """→ (正文, 矛盾说明)。面负责「文件名 = 编号」这条不变量。

    正文缺该字段 ⇒ 填上，且按 §三–§六 的样例放在**首位**（每类 JSON 的样例都是编号字段开头）。
    正文已填且与请求编号不同 ⇒ **不静默改写**，返回矛盾。
    正文已填且一致 ⇒ 一个键都不动（不改名 · 不重排 · 不加壳）。
    """
    现有 = 正文.get(字段)
    if 现有 is not None:
        if 现有 != 编号:
            return None, (
                "正文.%s 是 %r，与请求编号 %r 不一致。文件名与字段都是号、都已被外部引用，"
                "面静默改写哪一个都是替调用方改契约 ⇒ 请把两者改成一致再提交"
                % (字段, 现有, 编号)
            )
        return dict(正文), None
    输出正文 = {字段: 编号}
    for 键名, 待处理值 in 正文.items():
        输出正文[键名] = 待处理值
    return 输出正文, None
