# -*- coding: utf-8 -*-
"""编排 —— 面的一次写入（或一次算号）从头到尾。

流程（`形状.md` §一 · §六）：
    请求形状 → 定号（显式 / 该层号段空洞）→ 只增不改判定（改才要确认）
    → 写前跑判据器（基线）→ 落盘 → 写后跑判据器 → 挑本次写入引起的红
    → 有 ⇒ 回滚 + 成功:false；无 ⇒ 成功:true + 三元读数
校验**只**来自转调判据器（`转调判据.py`），面里没有第二套。
"""

import json
import time
from pathlib import Path

from . import 号段分配, 落盘, 转调判据
from .请求形状 import 合成正文, 解析请求, 类别表

声明根默认 = "契约声明"


def _条(项, 缺什么, 不能自愈, 位置="", 分类="") -> dict:
    return {"项": 项, "缺什么": 缺什么, "为什么不能自愈": 不能自愈, "位置": 位置, "分类": 分类}


def _解析声明根(仓根, 声明根):
    """只认仓内相对路径（同 生成声明.py 的 --声明根 口径）。"""
    候选 = Path(声明根)
    if 候选.is_absolute():
        return None, "声明根 只认**仓内相对路径**（绝对路径会让产物带机器相关前缀）⇒ 收到 %r" % 声明根
    绝对 = (仓根 / 候选).resolve()
    try:
        绝对.relative_to(仓根.resolve())
    except ValueError:
        return None, "声明根 %r 解析到仓外（%s）⇒ fail-closed" % (声明根, 绝对)
    if not 绝对.is_dir():
        return None, "声明根 %r 不是一个目录" % 声明根
    return 绝对, ""


def 处理分配(仓根, 声明根, 类别):
    """只算号、不落盘。→ (响应, 退出码)。"""
    绝对声明根, 错 = _解析声明根(仓根, 声明根)
    if 错:
        return {"成功": False, "校验": [_条("声明根", 错, "声明根是面的入参，面不替调用方改它")]}, 1
    if 类别 not in 类别表:
        return {"成功": False, "校验": [_条("类别", "类别 必须是 %s 之一（收到 %r）" % (" · ".join(类别表), 类别),
                                     "类别决定落哪个目录与编号字段，面不许猜")]}, 1
    目录, 字段 = 类别表[类别]
    段表, 来源 = 号段分配.该层号段(绝对声明根, 类别)
    if 段表 is None:
        return {"成功": False, "校验": [_条("编号自动分配（该层号段）", 来源,
                                     "该层号段是「本声明占哪几段」（格式说明 §二 ★）；"
                                     "号段未裁/读不到时面不猜一个起始值（猜出来的就是第二个事实源）"
                                     "⇒ 只能由声明方先定号段，或调用方显式给 编号")]}, 1
    已用 = 号段分配.已用号(绝对声明根, 目录, 字段)
    作废 = 号段分配.作废号(绝对声明根, 类别)
    号 = 号段分配.分配(段表, 已用, 作废)
    if 号 is None:
        return {"成功": False, "校验": [_条("编号自动分配（该层号段）",
                                     "该层号段 %s 内已无空洞（已用 %d 个 · 作废 %d 个）" % (段表, len(已用), len(作废)),
                                     "号只增不复用（§七）：不能回收已用号、不能复用作废号、不能借别层的号 ⇒ "
                                     "扩号段属全平台布局裁决（号段图.json）⇒ 只能人来裁")]}, 1
    return {
        "成功": True,
        "类别": 类别,
        "编号": 号,
        "落盘": str((绝对声明根 / 目录 / 号段分配.文件名(号)).relative_to(仓根)),
        "该层号段": 段表,
        "号段来源": 来源,
        "层": 号段分配.层标签(绝对声明根, 类别, 号),
        "已用": sorted(已用),
        "作废": sorted(作废),
    }, 0


def 处理写入(仓根, 声明根, 面根, 请求):
    """→ (响应, 退出码)。"""
    类别, 目录, 字段, 编号, 正文, 确认, 形状错 = 解析请求(请求)
    if 形状错:
        return {"成功": False, "校验": [_条("请求形状", 错, "请求形状不合法（等价 HTTP 400）："
                                     "面只判请求本身合不合法，不判内容契约") for 错 in 形状错]}, 1

    绝对声明根, 错 = _解析声明根(仓根, 声明根)
    if 错:
        return {"成功": False, "校验": [_条("声明根", 错, "声明根是面的入参，面不替调用方改它")]}, 1

    分配说明 = {"自动": 编号 is None}
    if 编号 is None:
        段表, 来源 = 号段分配.该层号段(绝对声明根, 类别)
        if 段表 is None:
            return {"成功": False, "校验": [_条("编号自动分配（该层号段）", 来源,
                                         "该层号段是「本声明占哪几段」（格式说明 §二 ★）；"
                                         "号段未裁/读不到时面不猜一个起始值 ⇒ 请显式给 编号")]}, 1
        已用 = 号段分配.已用号(绝对声明根, 目录, 字段)
        编号 = 号段分配.分配(段表, 已用, 号段分配.作废号(绝对声明根, 类别))
        if 编号 is None:
            return {"成功": False, "校验": [_条("编号自动分配（该层号段）",
                                         "该层号段 %s 内已无空洞" % (段表,),
                                         "号只增不复用（§七）⇒ 扩号段属全平台布局裁决 ⇒ 只能人来裁")]}, 1
        分配说明.update({"该层号段": 段表, "号段来源": 来源, "层": 号段分配.层标签(绝对声明根, 类别, 编号)})

    正文, 矛盾 = 合成正文(正文, 字段, 编号)
    if 矛盾:
        return {"成功": False, "校验": [_条("正文的编号字段与请求编号一致", 矛盾,
                                     "两个都是号、都已被外部引用；面不许静默改写其中一个 ⇒ "
                                     "只能由调用方把两者改成一致")]}, 1

    目标 = 绝对声明根 / 目录 / 号段分配.文件名(编号)
    相对 = str(目标.relative_to(仓根))
    旧字节 = 落盘.读现有(目标)
    旧数据 = None
    if 旧字节 is not None:
        try:
            旧数据 = json.loads(旧字节.decode("utf-8"))
        except (UnicodeDecodeError, ValueError) as 解析错:
            return {"成功": False, "校验": [_条("只增不改：号已存在", "落盘件 %s 读不动：%s" % (相对, 解析错),
                                         "面不许覆盖一份自身读不懂的已公布声明 ⇒ 只能由人来裁")]}, 1
        if not 确认:
            return {"成功": False, "校验": [_条(
                "只增不改：号已存在",
                "%s 已存在（编号 %d 已公布），本次请求没带 确认:true" % (相对, 编号),
                "已公布的号含义永不改写（开发规范 A5 · 格式说明 §七）；面不许静默覆盖 ⇒ "
                "要改就带 确认:true 显式确认，且改动前后都会留痕")],
                "旧正文": 旧数据}, 1
        只增, 差异 = 落盘.只增判定(旧数据, 正文)
        if not 只增:
            return {"成功": False, "校验": [_条(
                "只增不改：只许新增旁路字段",
                "%s 的已公布字段被改动/删除：%s" % (相对, " · ".join(差异)),
                "改旧字段的含义 = 改契约（A5 · A6 参数行序是冻结项）；旁路演进只许**新增**字段 ⇒ "
                "改旧字段只能走冻结登记与裁决 ⇒ 只能人来裁")],
                "差异": 差异, "旧正文": 旧数据}, 1

    判据器, 故障 = 转调判据.加载(仓根)
    if 故障:
        return {"成功": False, "面故障": 转调判据.面故障(故障),
                "校验": [转调判据.面故障(故障)], "落盘": False}, 1

    写前, _ = 转调判据.跑(判据器, 仓根)
    字节 = 落盘.序列化(正文)
    try:
        if 旧字节 is None:
            落盘.新建(目标, 字节)
        else:
            落盘.覆盖(目标, 字节)
    except FileExistsError:
        return {"成功": False, "校验": [_条("文件名 = 编号（一个号一个文件）",
                                     "%s 在本次写入的瞬间被另一个写入者创建了" % 相对,
                                     "编号冲突在文件系统层面就撞车（§一）⇒ 重新取号即可，"
                                     "面不替谁覆盖谁")]}, 1
    except OSError as 写错:
        return {"成功": False, "校验": [_条("落盘", "写 %s 失败：%s" % (相对, 写错),
                                     "落盘是面的唯一产出；写不动（权限/只读）面自愈不了 ⇒ 只能人来裁")]}, 1

    写后, 读数 = 转调判据.跑(判据器, 仓根)
    条表 = 转调判据.逐条(写后)
    基线指纹 = 转调判据.指纹集(写前)
    阻断, 待重跑, 面外 = 转调判据.归类(条表, 相对, 基线指纹)
    既有红 = [条 for 条 in 面外 if (条["项"], 条["位置"], 条["缺什么"]) in 基线指纹]
    新增红 = [条 for 条 in 面外 if (条["项"], 条["位置"], 条["缺什么"]) not in 基线指纹]

    响应 = {
        "编号": 编号,
        "落盘": 相对,
        "指纹": 落盘.指纹(字节),
        "分配": 分配说明,
        "判据器": 读数,
        "生成物待重跑": 待重跑,
        "面外既有红": 既有红,
        "面外新增红": 新增红,
    }
    if 阻断:
        try:
            落盘.回滚(目标, 旧字节)
            响应["回滚"] = True
        except OSError as 回滚错:
            响应["回滚"] = False
            响应["回滚失败"] = str(回滚错)
            响应["校验"] = 阻断
            响应["成功"] = False
            return 响应, 1
        响应["成功"] = False
        响应["校验"] = 阻断
        return 响应, 1

    响应["成功"] = True
    if 待重跑:
        响应["后续"] = ("判据 ⑩ 报「生成物不新鲜」：契约声明/src/声明数据.rs 是**生成物**，"
                    "源改了它就不再新鲜（退出码 1）。修法 = 重跑 构建装配/形态装配/生成声明.py"
                    "（属装配节点，面不碰生成物）")
    if 旧字节 is not None:
        响应["留痕"] = 落盘.留痕(面根, {
            "时刻": time.strftime("%Y-%m-%dT%H:%M:%S"),
            "类别": 类别, "编号": 编号, "落盘": 相对, "判定": "只增", "结果": "已落盘",
            "改前指纹": 落盘.指纹(旧字节), "改后指纹": 响应["指纹"],
            "改前正文": 旧数据, "改后正文": 正文,
        })
    return 响应, 0
