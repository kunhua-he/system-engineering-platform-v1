# -*- coding: utf-8 -*-
"""编排 —— 面的一次写入（或一次算号）从头到尾。

流程（`形状.md` §一 · §六）：
    请求形状 → 定号（显式 / 该层号段空洞）→ 只增不改判定（改才要确认）
    → 写前跑判据器（基线）→ 落盘 → 写后跑判据器 → 挑本次写入引起的红
    → 有 ⇒ 回滚 + 成功:false；无 ⇒ 成功:true + 三元读数
校验**只**来自转调判据器（`转调判据.py`），面里没有第二套。
"""

import json
import time
from pathlib import Path

from . import 号段分配, 落盘, 作废登记, 转调判据
from .请求形状 import 合成正文, 解析请求, 请求类别表, 作废类别

声明根默认 = "契约声明"


def _造一条记录(一项, 缺什么, 不能自愈, 位置="", 分类="") -> dict:
    return {"项": 一项, "缺什么": 缺什么, "为什么不能自愈": 不能自愈, "位置": 位置, "分类": 分类}


def _解析声明根(仓根, 声明根):
    """只认仓内相对路径（同 生成声明.py 的 --声明根 口径）。"""
    候选 = Path(声明根)
    if 候选.is_absolute():
        return None, "声明根 只认**仓内相对路径**（绝对路径会让产物带机器相关前缀）⇒ 收到 %r" % 声明根
    绝对 = (仓根 / 候选).resolve()
    try:
        绝对.relative_to(仓根.resolve())
    except ValueError:
        return None, "声明根 %r 解析到仓外（%s）⇒ fail-closed" % (声明根, 绝对)
    if not 绝对.is_dir():
        return None, "声明根 %r 不是一个目录" % 声明根
    return 绝对, ""


def 处理分配(仓根, 声明根, 类别):
    """只算号、不落盘。→ (响应, 退出码)。"""
    绝对声明根, 错误 = _解析声明根(仓根, 声明根)
    if 错误:
        return {"成功": False, "校验": [_造一条记录("声明根", 错误, "声明根是面的入参，面不替调用方改它")]}, 1
    if 类别 not in 请求类别表:
        return {"成功": False, "校验": [_造一条记录("类别", "类别 必须是 %s 之一（收到 %r）" % (" · ".join(请求类别表), 类别),
                                     "类别决定落哪个目录与编号字段，面不许猜")]}, 1
    if 类别 == 作废类别:
        return {"成功": False, "校验": [_造一条记录(
            "编号自动分配（作废）",
            "作废 指向一个**已存在**的号（号只增不复用），而自动分配取的是「该层号段里还没被占的号」"
            "—— 两者取向相反（作废登记的是「已被占、且不再用」的号）⇒ 面不为作废找空洞",
            "作废是「这个号不再使用」，不是一个新号，所以它没有可分配的起点 ⇒ 请显式给 编号")]}, 1
    目录, 字段 = 请求类别表[类别]
    段表, 来源 = 号段分配.该层号段(绝对声明根, 类别)
    if 段表 is None:
        return {"成功": False, "校验": [_造一条记录("编号自动分配（该层号段）", 来源,
                                     "该层号段是「本声明占哪几段」（格式说明 §二 ★）；"
                                     "号段未裁/读不到时面不猜一个起始值（猜出来的就是第二个事实源）"
                                     "⇒ 只能由声明方先定号段，或调用方显式给 编号")]}, 1
    已用 = 号段分配.已用号(绝对声明根, 目录, 字段)
    作废 = 号段分配.作废号(绝对声明根, 类别)
    号值 = 号段分配.取空闲号(段表, 已用, 作废)
    if 号值 is None:
        return {"成功": False, "校验": [_造一条记录("编号自动分配（该层号段）",
                                     "该层号段 %s 内已无空洞（已用 %d 个 · 作废 %d 个）" % (段表, len(已用), len(作废)),
                                     "号只增不复用（§七）：不能回收已用号、不能复用作废号、不能借别层的号 ⇒ "
                                     "扩号段属全平台布局裁决（号段图.json）⇒ 只能人来裁")]}, 1
    return {
        "成功": True,
        "类别": 类别,
        "编号": 号值,
        "落盘": str((绝对声明根 / 目录 / 号段分配.按编号取文件名(号值)).relative_to(仓根)),
        "该层号段": 段表,
        "号段来源": 来源,
        "层": 号段分配.层标签(绝对声明根, 类别, 号值),
        "已用": sorted(已用),
        "作废": sorted(作废),
    }, 0


def 处理写入(仓根, 声明根, 面根, 请求):
    """→ (响应, 退出码)。"""
    类别, 目录, 字段, 编号, 正文, 确认, 期望形状错 = 解析请求(请求)
    if 期望形状错:
        return {"成功": False, "校验": [_造一条记录("请求形状", 错误, "请求形状不合法（等价 HTTP 400）："
                                     "面只判请求本身合不合法，不判内容契约") for 错误 in 期望形状错]}, 1

    绝对声明根, 错误 = _解析声明根(仓根, 声明根)
    if 错误:
        return {"成功": False, "校验": [_造一条记录("声明根", 错误, "声明根是面的入参，面不替调用方改它")]}, 1

    if 类别 == 作废类别:
        return _登记作废(仓根, 绝对声明根, 面根, 编号, 正文)

    分配说明 = {"自动": 编号 is None}
    if 编号 is None:
        段表, 来源 = 号段分配.该层号段(绝对声明根, 类别)
        if 段表 is None:
            return {"成功": False, "校验": [_造一条记录("编号自动分配（该层号段）", 来源,
                                         "该层号段是「本声明占哪几段」（格式说明 §二 ★）；"
                                         "号段未裁/读不到时面不猜一个起始值 ⇒ 请显式给 编号")]}, 1
        已用 = 号段分配.已用号(绝对声明根, 目录, 字段)
        编号 = 号段分配.取空闲号(段表, 已用, 号段分配.作废号(绝对声明根, 类别))
        if 编号 is None:
            return {"成功": False, "校验": [_造一条记录("编号自动分配（该层号段）",
                                         "该层号段 %s 内已无空洞" % (段表,),
                                         "号只增不复用（§七）⇒ 扩号段属全平台布局裁决 ⇒ 只能人来裁")]}, 1
        分配说明.update({"该层号段": 段表, "号段来源": 来源, "层": 号段分配.层标签(绝对声明根, 类别, 编号)})

    正文, 矛盾 = 合成正文(正文, 字段, 编号)
    if 矛盾:
        return {"成功": False, "校验": [_造一条记录("正文的编号字段与请求编号一致", 矛盾,
                                     "两个都是号、都已被外部引用；面不许静默改写其中一个 ⇒ "
                                     "只能由调用方把两者改成一致")]}, 1

    目标 = 绝对声明根 / 目录 / 号段分配.按编号取文件名(编号)
    相对 = str(目标.relative_to(仓根))
    旧字节 = 落盘.读现有字节(目标)
    旧数据 = None
    if 旧字节 is not None:
        try:
            旧数据 = json.loads(旧字节.decode("utf-8"))
        except (UnicodeDecodeError, ValueError) as 解析错:
            return {"成功": False, "校验": [_造一条记录("只增不改：号已存在", "落盘件 %s 读不动：%s" % (相对, 解析错),
                                         "面不许覆盖一份自身读不懂的已公布声明 ⇒ 只能由人来裁")]}, 1
        if not 确认:
            return {"成功": False, "校验": [_造一条记录(
                "只增不改：号已存在",
                "%s 已存在（编号 %d 已公布），本次请求没带 确认:true" % (相对, 编号),
                "已公布的号含义永不改写（开发规范 A5 · 格式说明 §七）；面不许静默覆盖 ⇒ "
                "要改就带 确认:true 显式确认，且改动前后都会留痕")],
                "旧正文": 旧数据}, 1
        只增, 差异 = 落盘.只增判定(旧数据, 正文)
        if not 只增:
            return {"成功": False, "校验": [_造一条记录(
                "只增不改：只许新增旁路字段",
                "%s 的已公布字段被改动/删除：%s" % (相对, " · ".join(差异)),
                "改旧字段的含义 = 改契约（A5 · A6 参数行序是冻结项）；旁路演进只许**新增**字段 ⇒ "
                "改旧字段只能走冻结登记与裁决 ⇒ 只能人来裁")],
                "差异": 差异, "旧正文": 旧数据}, 1

    判据器, 故障 = 转调判据.加载判据器(仓根)
    if 故障:
        return {"成功": False, "面故障": 转调判据.造面故障条(故障),
                "校验": [转调判据.造面故障条(故障)], "落盘": False}, 1

    写前, _ = 转调判据.跑判据(判据器, 仓根)
    字节 = 落盘.序列化数据(正文)
    try:
        if 旧字节 is None:
            落盘.新建(目标, 字节)
        else:
            落盘.覆盖写入(目标, 字节)
    except FileExistsError:
        return {"成功": False, "校验": [_造一条记录("文件名 = 编号（一个号一个文件）",
                                     "%s 在本次写入的瞬间被另一个写入者创建了" % 相对,
                                     "编号冲突在文件系统层面就撞车（§一）⇒ 重新取号即可，"
                                     "面不替谁覆盖谁")]}, 1
    except OSError as 写错:
        return {"成功": False, "校验": [_造一条记录("落盘", "写 %s 失败：%s" % (相对, 写错),
                                     "落盘是面的唯一产出；写不动（权限/只读）面自愈不了 ⇒ 只能人来裁")]}, 1

    写后, 读数 = 转调判据.跑判据(判据器, 仓根)
    条表 = 转调判据.列失败条(写后)
    基线指纹 = 转调判据.指纹集(写前)
    阻断, 待重跑, 面外 = 转调判据.归类失败条(条表, 相对, 基线指纹)
    既有红 = [一条 for 一条 in 面外 if (一条["项"], 一条["位置"], 一条["缺什么"]) in 基线指纹]
    新增红 = [一条 for 一条 in 面外 if (一条["项"], 一条["位置"], 一条["缺什么"]) not in 基线指纹]

    响应 = {
        "编号": 编号,
        "落盘": 相对,
        "指纹": 落盘.取字节指纹(字节),
        "分配": 分配说明,
        "判据器": 读数,
        "生成物待重跑": 待重跑,
        "面外既有红": 既有红,
        "面外新增红": 新增红,
    }
    if 阻断:
        try:
            落盘.回滚写入(目标, 旧字节)
            响应["回滚"] = True
        except OSError as 回滚错:
            响应["回滚"] = False
            响应["回滚失败"] = str(回滚错)
            响应["校验"] = 阻断
            响应["成功"] = False
            return 响应, 1
        响应["成功"] = False
        响应["校验"] = 阻断
        return 响应, 1

    响应["成功"] = True
    if 待重跑:
        响应["后续"] = ("判据 ⑩ 报「生成物不新鲜」：契约声明/src/声明数据.rs 是**生成物**，"
                    "源改了它就不再新鲜（退出码 1）。修法 = 重跑 构建装配/形态装配/生成声明.py"
                    "（属装配节点，面不碰生成物）")
    if 旧字节 is not None:
        响应["留痕"] = 落盘.写留痕行(面根, {
            "时刻": time.strftime("%Y-%m-%dT%H:%M:%S"),
            "类别": 类别, "编号": 编号, "落盘": 相对, "判定": "只增", "结果": "已落盘",
            "改前指纹": 落盘.取字节指纹(旧字节), "改后指纹": 响应["指纹"],
            "改前正文": 旧数据, "改后正文": 正文,
        })
    return 响应, 0


def _登记作废(仓根, 绝对声明根, 面根, 编号, 正文):
    """第五个类别「作废」：一次**退休动作**（追加作废行 ＋ 移除已退休声明），原子完成。

    为什么两半必须一起：判据 3 明写「活跃声明 + 同号作废行 = 红」——只追加不移除会当场把树弄红，
    那不是「作废」，是「自相矛盾」（`接口面形状.md` §四「面只有写入，没有删除」）。
    两半必须在**一次请求**里完成 ⇒ 面必须同时拥有它们（否则 README §九「唯一写入口」对退休不成立）。
    ▲ 这不是「独立删除能力」：没有 `DELETE` 端点，移除只发生在一次已登记的作废里。

    与 `处理写入` 同一姿势：写前跑判据器（基线）→ 落盘 → 写后跑 → 有阻断就回滚。
    """
    表相对 = str((绝对声明根 / "作废号表.json").relative_to(仓根))
    数据, 旧条目, 错误 = 作废登记.读作废号表(绝对声明根)
    if 错误:
        return {"成功": False, "校验": [_造一条记录("作废登记", 错误,
                                     "作废号表是宪法第 7 条的唯一登记处；面不重建、不覆写它 ⇒ "
                                     "只能由声明方补")]}, 1

    作废行, 缺什么 = 作废登记.编五键行(正文, 编号)
    if 缺什么:
        return {"成功": False, "校验": [_造一条记录(
            "作废行的五键", "缺 %s（格式说明.md §七 的五键：编号 · 原名称 · 作废于 · 原因 · 号空间）"
            % " · ".join(缺什么),
            "作废行是历史档案：原名称 · 作废于 · 原因 只能来自当时的记录，事后补不出来 "
            "（作废于 缺省由面补为今天，其余不猜）⇒ 只能由声明方补")]}, 1
    if 作废行["号空间"] not in 作废登记.号空间值域:
        return {"成功": False, "校验": [_造一条记录(
            "号空间在值域内",
            "%r 不在值域 %s 里（格式说明.md §七）" % (作废行["号空间"], " · ".join(作废登记.号空间值域)),
            "号空间 是「这个号在哪个空间里作废」的唯一依据；认不出它就退化成全局排除 "
            "（实测：错误码 16 去封能力号 16 的假冲突，31 条红）⇒ 只能由声明方按 §七 的值域补")]}, 1

    for 序号, 旧行 in enumerate(旧条目):
        if (isinstance(旧行, dict) and 旧行.get("号空间") == 作废行["号空间"]
                and 旧行.get("编号") == 作废行["编号"]):
            return {"成功": False, "校验": [_造一条记录(
                "作废行不重复", "第 %d 行已是号空间 %s 的编号 %d（原名称「%s」）"
                % (序号 + 1, 作废行["号空间"], 作废行["编号"], 旧行.get("原名称")),
                "作废登记是指向一个号的**一次**历史事件；同空间同号再作废一次只会让生成器 "
                "fail-closed（同一空间里作废编号重复）⇒ 要改历史（撤销作废）只能人来裁")]}, 1

    # 该号在**那个空间**里的活跃声明（资源空间对不到目录 ⇒ 目录为 None，无声明可移除）。
    # 号空间 → 类别 → 目录，两步都走**已有的表**，不新写一份「号空间 → 目录」。
    空间类别 = 号段分配.号空间到类别.get(作废行["号空间"])
    目录 = 请求类别表[空间类别][0] if 空间类别 else None
    声明路径 = (绝对声明根 / 目录 / ("%04d.json" % 作废行["编号"])) if 目录 else None
    旧声明字节 = 落盘.读现有字节(声明路径) if 声明路径 else None

    判据器, 故障 = 转调判据.加载判据器(仓根)
    if 故障:
        return {"成功": False, "面故障": 转调判据.造面故障条(故障),
                "校验": [转调判据.造面故障条(故障)], "落盘": False}, 1
    写前, _ = 转调判据.跑判据(判据器, 仓根)

    旧表字节 = 落盘.读现有字节(绝对声明根 / "作废号表.json")
    数据["作废"] = 旧条目 + [作废行]
    新表字节 = 落盘.序列化数据(数据)
    try:
        落盘.覆盖写入(绝对声明根 / "作废号表.json", 新表字节)
        if 声明路径 is not None and 旧声明字节 is not None:
            声明路径.unlink()
    except OSError as 写错:
        return {"成功": False, "校验": [_造一条记录("落盘", "退休动作写不动：%s" % 写错,
                                     "落盘是面的唯一产出；写不动（权限/只读）面自愈不了 ⇒ 只能人来裁")]}, 1

    写后, 读数 = 转调判据.跑判据(判据器, 仓根)
    条表 = 转调判据.列失败条(写后)
    基线指纹 = 转调判据.指纹集(写前)
    声明相对 = str(声明路径.relative_to(仓根)) if 声明路径 is not None else ""
    # 本次动作动了**两件**（作废表 · 被退休的声明）⇒ 两件都要算进「本次引起的红」。
    # 同一根红不能被两条路径重复计入（去重按判据器给的指纹三键）。
    阻断, 待重跑, 面外 = [], [], []
    for 路径 in filter(None, (表相对, 声明相对)):
        本次阻断, 本次待重跑, 本次面外 = 转调判据.归类失败条(条表, 路径, 基线指纹)
        阻断 += [一条 for 一条 in 本次阻断 if 一条 not in 阻断]
        待重跑 += [一条 for 一条 in 本次待重跑 if 一条 not in 待重跑]
        面外 += [一条 for 一条 in 本次面外 if 一条 not in 面外]
    面外 = [一条 for 一条 in 面外 if 一条 not in 阻断 and 一条 not in 待重跑]
    既有红 = [一条 for 一条 in 面外 if (一条["项"], 一条["位置"], 一条["缺什么"]) in 基线指纹]
    新增红 = [一条 for 一条 in 面外 if (一条["项"], 一条["位置"], 一条["缺什么"]) not in 基线指纹]

    响应 = {
        "编号": 编号,
        "号空间": 作废行["号空间"],
        "落盘": 表相对,
        "指纹": 落盘.取字节指纹(新表字节),
        "退休声明": 声明相对 or None,
        "判据器": 读数,
        "生成物待重跑": 待重跑,
        "面外既有红": 既有红,
        "面外新增红": 新增红,
    }
    if 阻断:
        错表 = False
        try:
            落盘.回滚写入(绝对声明根 / "作废号表.json", 旧表字节)
            if 声明路径 is not None and 旧声明字节 is not None:
                落盘.回滚写入(声明路径, 旧声明字节)
        except OSError as 回滚错:
            错表 = True
            响应["回滚"] = False
            响应["回滚失败"] = str(回滚错)
        响应["回滚"] = not 错表
        响应["成功"] = False
        响应["校验"] = 阻断
        return 响应, 1

    响应["成功"] = True
    if 待重跑:
        响应["后续"] = ("判据 ⑩ 报「生成物不新鲜」：契约声明/src/声明数据.rs 是**生成物**，"
                    "源改了它就不再新鲜（退出码 1）。修法 = 重跑 构建装配/形态装配/生成声明.py"
                    "（属装配节点，面不碰生成物）")
    响应["留痕"] = 落盘.写留痕行(面根, {
        "时刻": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "类别": 作废类别, "编号": 编号, "落盘": 表相对, "判定": "追加", "结果": "已落盘",
        "改前指纹": 落盘.取字节指纹(旧表字节), "改后指纹": 响应["指纹"],
        "改前正文": {"作废": 旧条目}, "改后正文": {"作废": 旧条目 + [作废行]},
        "退休声明": 响应["退休声明"],
    })
    return 响应, 0
