# -*- coding: utf-8 -*-
"""校验 —— **转调既有判据器**，面里没有第二套校验。

判据器 = `构建装配/一键验证/一键验证.py`（`格式说明.md` §九 十项 + 四项新裁定的唯一实现）。
它正被另一条腿改到跑不动时：**如实报「暂时转调不了 + 缺什么」**，绝不抄一份判据进面里兜底。

判据器**惰性加载**（只在真跑校验时 import）：面自身的可用性不该被别的节点的半成品拖死。
"""

import importlib.util
import re

判据器相对路径 = "构建装配/一键验证/一键验证.py"

_模块名 = "一键验证判据器_转调"

# 判据 ⑩（生成物与 JSON 一致）的检查名前缀。它与别的判据不同：写**任何**一份声明都会让它变红
# ——`契约声明/src/声明数据.rs` 是生成物，源改了它就不再新鲜。修法是重跑生成器（开发规范 四），
# 不是回滚，所以它不能当阻断理由。但生成器对**本次声明** fail-closed（源不合契约形状）时，
# 那份声明确实写坏了，必须阻断。两者的区分用生成器自身的退出码（`生成声明.py` 主函数的契约）：
#     0 = 与落盘件逐字节一致 · 1 = 生成物不新鲜 · 2 = 生成失败（fail-closed，产物未动）
生成物检查前缀 = "⑩"


def 加载(仓根):
    """→ (判据器模块, 故障说明)。故障 = 文件不在 / 加载失败 / 入口形状变了。"""
    路径 = 仓根 / 判据器相对路径
    if not 路径.is_file():
        return None, "%s 不在（判据器是校验的唯一实现，它不在就无从转调）" % 判据器相对路径
    try:
        模块规格 = importlib.util.spec_from_file_location(_模块名, str(路径))
        if 模块规格 is None or 模块规格.loader is None:
            return None, "%s 不是可加载的 Python 源（取不到 loader）" % 判据器相对路径
        判据模块 = importlib.util.module_from_spec(模块规格)
        模块规格.loader.exec_module(判据模块)
    except BaseException as 错误:  # SyntaxError 也算：半成品期间读进来就是编译不过
        return None, "判据器 %s 加载失败（它可能正被改动）：%s: %s" % (
            判据器相对路径,
            type(错误).__name__,
            错误,
        )
    if not hasattr(判据模块, "验证"):
        return None, "判据器 %s 里没有 验证(仓根) 入口（入口形状变了，面不敢猜怎么调）" % 判据器相对路径
    return 判据模块, ""


def 跑判据(判据器, 仓根):
    """→ (判据器原始结果, 三元读数)。读数口径照判据器自身的 打印()：按检查项计。"""
    结果 = 判据器.验证(仓根)
    通过 = [一项 for 一项 in 结果.get("通过", []) if isinstance(一项, str)]
    失败 = [一项 for 一项 in 结果.get("失败", []) if isinstance(一项, str)]
    未判 = sorted(
        {一项 for 一项 in 结果.get("未判", []) if isinstance(一项, str)}
        | {一项["检查"] for 一项 in 结果.get("未判", []) if isinstance(一项, dict)}
    )
    读数 = {
        "通过": len(通过),
        "失败": len(失败),
        "未判": len(未判),
        "疑似瞬时": len(结果.get("疑似瞬时", [])),
        "耗时毫秒": 结果.get("耗时毫秒"),
    }
    return 结果, 读数


def 逐条(结果):
    """判据器的失败逐条 → [{项, 缺什么, 为什么不能自愈, 位置, 分类}]。

    `项` = 判据器的检查名（`接口面形状.md` §四 的 `校验[].项` 就是它）。
    """
    条目表 = []
    for 一条 in 结果.get("失败", []):
        if not isinstance(一条, dict):
            continue
        条目表.append(
            {
                "项": 一条.get("检查", ""),
                "缺什么": 一条.get("缺什么", ""),
                "为什么不能自愈": 一条.get("不能自愈", ""),
                "位置": 一条.get("位置", ""),
                "分类": 一条.get("分类", ""),
            }
        )
    return 条目表


def 指纹集(结果):
    """失败条的指纹集（检查 · 位置 · 缺什么），用来取写前/写后的差。"""
    return {
        (一条.get("检查"), 一条.get("位置"), 一条.get("缺什么"))
        for 一条 in 结果.get("失败", [])
        if isinstance(一条, dict)
    }


def _退出码(文本):
    """从判据 ⑩ 的说明里取生成器 --检查 的退出码（判据器自身把它写在了 `缺什么` 里）。"""
    匹配结果 = re.search(r"退出码\s*(\d+)", str(文本))
    return int(匹配结果.group(1)) if 匹配结果 else None


def 归类(条表, 相对路径, 基线指纹):
    """→ (阻断, 生成物待重跑, 面外)。

    - **阻断**：本次写入把声明写坏了（含生成器对本次声明 fail-closed，退出码 2）⇒ 回滚。
    - **生成物待重跑**：判据 ⑩ 报「生成物不新鲜」（退出码 1）⇒ 写任何声明都会这样，
      修法是重跑生成器，不是回滚，故**不阻断**，只报给调用方。
    - **面外**：基线里就有、或与本次写入无关的红 ⇒ 面不替别的节点改它们的红。
    """
    阻断, 待重跑, 面外 = [], [], []
    for 一条 in 条表:
        文本 = "%s%s" % (一条.get("位置", ""), 一条.get("缺什么", ""))
        是本文件 = 相对路径 in 文本
        新出现 = (一条.get("项"), 一条.get("位置"), 一条.get("缺什么")) not in 基线指纹
        if str(一条.get("项", "")).startswith(生成物检查前缀):
            错误码 = _退出码(一条.get("缺什么"))
            if 错误码 == 1:
                待重跑.append(一条)
            elif 错误码 == 2 and (是本文件 or 新出现):
                阻断.append(一条)
            else:
                面外.append(一条)
        elif 是本文件:
            阻断.append(一条)
        else:
            面外.append(一条)
    return 阻断, 待重跑, 面外


def 面故障(缺什么: str) -> dict:
    """转调不了时回给调用方的形状：照实说缺什么，不假装校验过了。"""
    return {
        "项": "转调判据器（构建装配/一键验证/一键验证.py）",
        "缺什么": 缺什么,
        "为什么不能自愈": (
            "面里没有第二套校验（开发规范 A2 · 接口面形状 §四：面是唯一写入口，"
            "不是第二个判据器）。判据器是校验的唯一实现，它跑不动时面只能照实报"
            "「暂时转调不了 + 缺什么」——在面里抄一份判据就是同一件事两套实现，"
            "两套判定必然漂移。修法是让判据器那一侧恢复可加载（它正被另一条腿改动）"
        ),
    }
