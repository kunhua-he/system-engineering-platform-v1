use crate::命令声明面::{函数表项数, 命令表内位, 造命令表};
use crate::编号与码面::{能力号, 错误码};
use v1_contract::{执行函数, 数据槽, 类型标签};

unsafe fn 处理调用(编号: u32, 参数个数: u32, 参数表: *const 数据槽) -> Result<数据槽, u32> {
    let 声明表 = 造命令表();
    let 命令项 = &声明表[命令表内位(编号)];
    if 参数个数 != 命令项.参数个数 { return Err(错误码::参数不合法); }
    if 参数个数 > 0 && 参数表.is_null() { return Err(错误码::参数不合法); }
    let 槽表 = if 参数个数 == 0 {
        &[][..]
    } else {
        unsafe { std::slice::from_raw_parts(参数表, 参数个数 as usize) }
    };
    for (参数位序, 槽项) in 槽表.iter().enumerate() {
        let 声明参数 = unsafe { &*命令项.参数表.add(参数位序) };
        if 槽项.类型标签 != 声明参数.类型标签 { return Err(错误码::参数不合法); }
        if matches!(声明参数.类型标签.取号值(), 4 | 5 | 100 | 101 | 102 | 103) {
            if !槽项.是否引用() || (槽项.槽值 == 0 && 槽项.槽字节长度 != 0) { return Err(错误码::参数不合法); }
            if 槽项.槽字节长度 > 786432 { return Err(错误码::资源受限); }
        } else if 槽项.是否引用() && 槽项.槽字节长度 != 0 {
            return Err(错误码::参数不合法);
        }
    }
    unsafe { crate::业务实现::执行(编号, 槽表) }
}

unsafe fn 写调用(编号: u32, 返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() { return; }
    unsafe {
        *返回槽 = 处理调用(编号, 参数个数, 参数表)
            .unwrap_or_else(|失败码| 数据槽::内联槽(类型标签::构造(u32::MAX), 失败码 as u64, 4));
    }
}

pub unsafe extern "C-unwind" fn 连接模型入口(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) { unsafe { 写调用(能力号::连接模型, 返回槽, 参数个数, 参数表); } }
pub unsafe extern "C-unwind" fn 提交生成任务入口(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) { unsafe { 写调用(能力号::提交生成任务, 返回槽, 参数个数, 参数表); } }
pub unsafe extern "C-unwind" fn 读取生成任务入口(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) { unsafe { 写调用(能力号::读取生成任务, 返回槽, 参数个数, 参数表); } }
pub unsafe extern "C-unwind" fn 取消生成任务入口(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) { unsafe { 写调用(能力号::取消生成任务, 返回槽, 参数个数, 参数表); } }
pub unsafe extern "C-unwind" fn 释放生成任务入口(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) { unsafe { 写调用(能力号::释放生成任务, 返回槽, 参数个数, 参数表); } }
pub unsafe extern "C-unwind" fn 释放句柄入口(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) { unsafe { 写调用(能力号::释放句柄, 返回槽, 参数个数, 参数表); } }
pub unsafe extern "C-unwind" fn 资源快照入口(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) { unsafe { 写调用(能力号::资源快照, 返回槽, 参数个数, 参数表); } }

pub const fn 造函数表() -> [执行函数; 函数表项数] {
    let mut 本表 = [连接模型入口 as 执行函数; 函数表项数];
    本表[命令表内位(能力号::连接模型)] = 连接模型入口;
    本表[命令表内位(能力号::提交生成任务)] = 提交生成任务入口;
    本表[命令表内位(能力号::读取生成任务)] = 读取生成任务入口;
    本表[命令表内位(能力号::取消生成任务)] = 取消生成任务入口;
    本表[命令表内位(能力号::释放生成任务)] = 释放生成任务入口;
    本表[命令表内位(能力号::释放句柄)] = 释放句柄入口;
    本表[命令表内位(能力号::资源快照)] = 资源快照入口;
    本表
}
pub(crate) const 执行函数表: [执行函数; 函数表项数] = 造函数表();
