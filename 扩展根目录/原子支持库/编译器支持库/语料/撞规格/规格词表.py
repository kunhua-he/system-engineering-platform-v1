def _字段序(line, col):
    """col 之前有几个「顶层半角逗号」（字面量内的不算）→ 就是字段序。"""
    字段数 = 0
    扫描位 = 0
    while 扫描位 < col and 扫描位 < len(line):
        字符 = line[扫描位]
        if 字符 in "“”\"":
            close = "”" if 字符 in "“”" else '"'
            扫描位 += 1
            while 扫描位 < len(line) and line[扫描位] != close:
                扫描位 += 1
            扫描位 += 1
            continue
        if 字符 == ",":
            字段数 += 1
        扫描位 += 1
    return 字段数
