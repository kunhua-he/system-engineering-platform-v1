def 行首关键字(line):
    行文 = line.lstrip()
    if 行文.startswith("."):
        匹配 = re.match(r"\.([0-9A-Za-z_\u4e00-\u9fff]+)", 行文)
        if 匹配:
            return 匹配.group(1)
    return None


def 是备注字段(line, fi):
    """该位置是不是「声明行的非结构自由文本字段」。"""
    kw = 行首关键字(line)
    if kw is None or kw in 语句关键字:
        return False
    return fi >= 结构字段数.get(kw, 99)

# 半角 ASCII 里「规格没提」但可能出现的符号
