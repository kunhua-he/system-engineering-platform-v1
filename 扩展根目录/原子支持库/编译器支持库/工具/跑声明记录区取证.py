#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""跑声明记录区取证 —— 把「声明记录区反解」的取证**落成可复跑的一步**（台账 #195 / #153）。

**为什么要有这一件**：1103 的输出形状「先取证、后立形状」是裁决
（`项目文档/决策记录/2026-09-27_1103输出形状与注册表来源.md` 裁决一）。取证已经做过一轮
（解析器 `开发工具/取证/声明记录区反解.py`，读数 `项目文档/设计文档/声明记录区实测.md`），
但**从本扩展目录里没有一条能复跑它的路**——本脚本就是那条路：跑取证、**断言承重读数**、带退出码。

    python3 扩展根目录/原子支持库/编译器支持库/工具/跑声明记录区取证.py

**承重读数（本脚本逐条断言；任一条不符即退出码 1，不静默）**：
  · `--自测`（反向样本）：19 个坏样本 + 1 个合法边界样本 ⇒ 结论「通过」、假绿 0
  · `--全部`（全语料）：程序段 1456 · 解析失败 0 · 头 4 字节恒 0 = 1456/1456
  · 五种可证记录形态各 > 0（串记录 / 语句字节码 / DLL命令记录 / 数据类型码 / 令牌）

**语料依赖**：`--自测` 用的正向样本是**随本扩展进仓**的
`语料/样本/第一个程序.e`（2163 B，只读样本）⇒ 自测**不依赖仓外路径**；
`--全部` 要 `/tmp/易语言源码`（857 MB 量级，仓外只读语料）—— 不在就报「未判」，**不算通过**。

**这不是第二套实现**：解析器只有一处（`开发工具/取证/声明记录区反解.py`，别的腿的取证件），
本脚本只做「跑它 + 断言读数」，不重写一行解析逻辑。

**还缺什么证据、怎么取**：见 `说明/声明记录区取证.md`。
"""

import os
import subprocess
import sys

# 本脚本 = <扩展根>/工具/跑声明记录区取证.py；仓库根 = 上溯四层。
工具目录 = os.path.dirname(os.path.abspath(__file__))
扩展根 = os.path.dirname(工具目录)
仓库根 = os.path.dirname(os.path.dirname(os.path.dirname(扩展根)))

取证器 = os.path.join(仓库根, "开发工具", "取证", "声明记录区反解.py")
样本 = os.path.join(扩展根, "语料", "样本", "第一个程序.e")
语料根 = "/tmp/易语言源码"


def 跑(参数):
    """跑取证器，返回 (退出码, stdout)。"""
    进程 = subprocess.run(
        [sys.executable, 取证器] + 参数,
        cwd=仓库根,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    return 进程.returncode, 进程.stdout


def 断言(条件, 描述, 失败集):
    if 条件:
        print("  ✓ %s" % 描述)
    else:
        print("  ✗ %s" % 描述)
        失败集.append(描述)


def 自测(失败集):
    if not os.path.isfile(取证器):
        print("  ✗ 取证器不在：%s" % 取证器)
        失败集.append("取证器缺失")
        return
    if not os.path.isfile(样本):
        print("  ✗ 自测样本不在：%s" % 样本)
        失败集.append("样本缺失")
        return
    码, 出 = 跑(["--自测", "--样本", 样本])
    for 行 in 出.rstrip().splitlines():
        print("    | " + 行)
    断言(码 == 0, "自测退出码 = 0（实得 %d）" % 码, 失败集)
    断言("自测结论：通过" in 出, "自测结论 = 通过", 失败集)
    断言("假绿 0" in 出, "假绿 = 0（坏样本没有一条产出记录区）", 失败集)


def 全语料(失败集):
    if not os.path.isdir(语料根):
        print("  · 未判：仓外语料 %s 不在 ⇒ --全部 没跑（**不是通过**）" % 语料根)
        return
    码, 出 = 跑(["--全部", "--目录", 语料根])
    for 行 in 出.rstrip().splitlines():
        print("    | " + 行)
    断言(码 == 0, "全语料退出码 = 0（实得 %d）" % 码, 失败集)
    断言("解析失败 0" in 出, "解析失败 = 0", 失败集)
    断言("头 4 字节恒 0：1456 / 1456" in 出, "头 4 字节恒 0 = 1456/1456（自证锚点）", 失败集)
    for 形态 in ("串记录", "语句字节码", "DLL命令记录", "数据类型码"):
        行 = next((行 for 行 in 出.splitlines() if 行.startswith("可证记录 %-12s" % 形态)), "")
        数 = 行.split()[-2] if 行 else ""
        断言(数.isdigit() and int(数) > 0, "可证记录「%s」> 0（实得 %s）" % (形态, 数 or "无"), 失败集)


def main():
    print("声明记录区取证 · 复跑（取证器 %s）" % os.path.relpath(取证器, 仓库根))
    失败集 = []
    print("一 自测（反向样本，样本随本扩展进仓）")
    自测(失败集)
    print("二 全语料（仓外只读语料）")
    全语料(失败集)
    if 失败集:
        print("结论：失败 %d 条 —— %s" % (len(失败集), "；".join(失败集)))
        return 1
    print("结论：通过（承重读数逐条对上；**分区边界 / 令牌语义 / 操作码表仍是不判**，见说明）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
