# -*- coding: utf-8 -*-
"""跑声明记录区取证 · 主流程 —— 按 `--分片` 分派；默认档跑自测 + 全语料并汇总失败集。"""
import os

from .常量 import 仓库根, 取证器, 语料根
from .检查 import 全语料, 自测
from .跑取证 import 跑取证


def 入口函数(参数):
    分片 = None
    if "--分片" in 参数:
        下标 = 参数.index("--分片")
        分片 = 参数[下标 + 1] if 下标 + 1 < len(参数) else None
        if not 分片:
            print("用法：--分片 i/n（例：--分片 0/120）")
            return 2
    if 分片:
        # 只算一片：全量的计算就靠跑齐这些片（本脚本不自行循环 —— 一条命令 5 秒内）
        码, 出 = 跑取证(["--分片", 分片, "--目录", 语料根])
        for 输出行 in 出.rstrip().splitlines():
            print("    | " + 输出行)
        print("结论：第 %s 片跑完，退出码 %d（全量读数由 --全部 归并）" % (分片, 码))
        return 码
    print("声明记录区取证 · 复跑（取证器 %s）" % os.path.relpath(取证器, 仓库根))
    失败集 = []
    print("一 自测（反向样本，样本随本扩展进仓）")
    自测(失败集)
    print("二 全语料（仓外只读语料；计算由分片命令完成，本步只归并）")
    全语料(失败集)
    if 失败集:
        print("结论：失败 %d 条 —— %s" % (len(失败集), "；".join(失败集)))
        return 1
    print("结论：通过（承重读数逐条对上；**分区边界 / 令牌语义 / 操作码表仍是不判**，见说明）")
    return 0
