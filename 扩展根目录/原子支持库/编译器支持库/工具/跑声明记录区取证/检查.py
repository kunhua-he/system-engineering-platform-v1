# -*- coding: utf-8 -*-
"""跑声明记录区取证 · 检查 —— 自测（反向样本）与跑全语料（归并逐件缓存）两条承重读数。"""
import os
import re

from .常量 import 取证器路径, 样本路径, 源码根
from .跑取证 import 跑取证, 断言


def 跑自测(失败集):
    if not os.path.isfile(取证器路径):
        print("  ✗ 取证器路径不在：%s" % 取证器路径)
        失败集.append("取证器缺失")
        return
    if not os.path.isfile(样本路径):
        print("  ✗ 自测样本路径不在：%s" % 样本路径)
        失败集.append("样本缺失")
        return
    退出码, 输出文本 = 跑取证(["--自测", "--样本", 样本路径])
    for 输出行 in 输出文本.rstrip().splitlines():
        print("    | " + 输出行)
    断言(退出码 == 0, "自测退出码 = 0（实得 %d）" % 退出码, 失败集)
    断言("自测结论：通过" in 输出文本, "自测结论 = 通过", 失败集)
    断言("假绿 0" in 输出文本, "假绿 = 0（坏样本没有一条产出记录区）", 失败集)


def 跑全语料(失败集):
    if not os.path.isdir(源码根):
        print("  · 未判：仓外语料 %s 不在 ⇒ --全部 没跑（**不是通过**）" % 源码根)
        return
    退出码, 输出文本 = 跑取证(["--全部", "--目录", 源码根])
    for 输出行 in 输出文本.rstrip().splitlines():
        print("    | " + 输出行)
    if "逐件缓存不齐" in 输出文本:
        # 缓存没跑齐 ⇒ **未判**（不是失败：全量的计算本来就不在命令路里，见文件头）
        print("  · 未判：逐件缓存不齐 ⇒ 全量读数还没算出来（**不是通过**）。")
        print("    按上面印出的三步补缓存（先跑一片量系数 → 问片数跑齐 → --全部 归并），再复跑本脚本。")
        return
    断言(退出码 == 0, "全语料退出码 = 0（实得 %d）" % 退出码, 失败集)
    断言("解析失败 0" in 输出文本, "解析失败 = 0", 失败集)
    头部匹配 = re.search(r"头 4 字节恒 0：(\d+) / (\d+)", 输出文本)
    断言(
        bool(头部匹配) and 头部匹配.group(1) == 头部匹配.group(2) and int(头部匹配.group(2)) > 0,
        "头 4 字节恒 0 = 全数（自洽，不写死件数；实得 %s）" % (头部匹配.group(0) if 头部匹配 else "无"),
        失败集,
    )
    for 记录形态 in ("串记录", "语句字节码", "DLL命令记录", "数据类型码"):
        输出行 = next((输出行 for 输出行 in 输出文本.splitlines() if 输出行.startswith("可证记录 %-12s" % 记录形态)), "")
        条目个数 = 输出行.split()[-2] if 输出行 else ""
        断言(条目个数.isdigit() and int(条目个数) > 0, "可证记录「%s」> 0（实得 %s）" % (记录形态, 条目个数 or "无"), 失败集)
