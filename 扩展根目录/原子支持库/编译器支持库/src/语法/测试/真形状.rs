//! 真形状测试 —— 手搭记号流跑 `说明/真文本覆盖.md` 里的真实形态，把树逐节点贴出来。
//!
//! 三个交付要求的形状：`.子程序` 声明 · `.如果/.否则/.如果结束` 两级嵌套 ·
//! 带 `.局部变量` 的子程序。另加一份把余下种类（判断块 / 置入代码 / 下标 / 一元 /
//! 常量引用 / 空实参）都走一遍，最后钉住「33 种节点种类全部建到」。
//!
//! **读数的形状是「先序子树区间」定出来的**：`子区间` 从第一个直接子起、到最后一个直接子的
//! 整棵子树之后，所以**每一层里的每条语句都能带自己的子树**（旧读法把区间里每个下标都当
//! 直接子，逼出「只有末子能带子树」——那是读法之误，见 `语法/草稿.rs` 头部）。
//!
//! 单文件 ≤ 400 行，故 真形状3/4 与 GBK·归属 那几条拆在 `真形状其余.rs`。

use super::夹具::*;
use crate::语言面::{节点种类, 记号流};
use crate::语法::建树;

/// 打一份树读数（跑 `--nocapture` 看；报告里的读数就是它）。
pub(super) fn 贴(名: &str, 树: &crate::语言面::语法树) {
    println!("── {名} ── 节点数={} 根={}", 树.节点表.len(), 树.根);
    for 行 in 树读数(树) {
        println!("{行}");
    }
}

/// 建树 + 显式再跑一遍不变量判定体（`新建` 已经判死，这里留一份显式证据）。
pub(super) fn 建过(流: &记号流) -> crate::语言面::语法树 {
    let 树 = 建树(流).expect("合法记号流必须建得出树");
    树.校验().expect("建出来的树必须过全部不变量");
    树
}

// ── 真形状 1：`.子程序` 声明（e8test3.txt 那份 146 字节真文本的形态）──────────

#[test]
fn 真形状1_子程序声明() {
    let 流 = 夹具一();
    let 树 = 建过(&流);
    贴("真形状1 `.子程序` 声明", &树);

    断言读数(
        &树,
        "\
0 程序 [0,127) 子(1,21)
1 源单元 [0,127) 子(2,21)
2 数值字面量 [8,9) 子(3,3)
3 换行 [9,11) 子(4,4)
4 换行 [11,13) 子(5,5)
5 程序集 [13,38) 子(6,9)
6 标识符引用 [24,34) 子(7,7)
7 换行 [34,36) 子(8,8)
8 换行 [36,38) 子(9,9)
9 子程序 [38,127) 子(10,21)
10 标识符引用 [49,74) 子(11,11)
11 换行 [74,76) 子(12,12)
12 换行 [76,78) 子(13,13)
13 调用语句 [78,127) 子(14,21)
14 命令调用 [78,125) 子(15,20)
15 标识符引用 [78,87) 子(16,16)
16 文本字面量 [89,117) 子(17,17)
17 数值字面量 [119,120) 子(18,18)
18 空实参 [120,120) 子(19,19)
19 空实参 [122,122) 子(20,20)
20 换行 [125,127) 子(21,21)",
    );

    // 根区间 == 全文，切片就是原文
    assert_eq!(树.原文切片(0), Some(夹具一原文.as_bytes()));
    // `信息框 (“本程序来自程序3”, 0, , )` 尾部两个空位是**零宽**节点
    let 空: Vec<&crate::语言面::节点> = 树
        .节点表
        .iter()
        .filter(|n| n.种类 == 节点种类::空实参)
        .collect();
    assert_eq!(空.len(), 2);
    for n in 空 {
        assert_eq!(n.起(), n.止(), "空实参必须零宽");
    }
    // 单行节点认领自己的行尾：`调用语句 [78,127)` 的末子是那枚 `换行 [125,127)`
    assert_eq!(树.节点表[13].种类, 节点种类::调用语句);
    assert_eq!(树.节点表[13].原文区间, (78, 流.全文长()));
    assert_eq!(树.直接子(13).last(), Some(20));
    assert_eq!(树.节点表[20].原文区间, (125, 127));
}

