// ── 33 种节点种类：全部建到 ─────────────────────────────────────────────────

#[test]
fn 种类覆盖_33种节点种类全部建到() {
    let mut 见: Vec<节点种类> = Vec::new();
    for 流 in 全部夹具() {
        let 树 = 建过(&流);
        for n in &树.节点表 {
            if !见.contains(&n.种类) {
                见.push(n.种类);
            }
        }
    }
    let 全部: Vec<节点种类> = (0u16..=63).filter_map(节点种类::自号).collect();
    assert_eq!(全部.len(), 33, "节点种类共 33 种");
    let 未建: Vec<&str> = 全部
        .iter()
        .filter(|k| !见.contains(k))
        .map(|k| 种类名(*k))
        .collect();
    assert!(未建.is_empty(), "这些种类没建到：{:?}", 未建);
    println!("33 种节点种类全部建到（五份夹具的并集）");
}

// ── 编码：GBK 原文里关键字认不出来 ⇒ 落到兜底，但树仍合法 ────────────────────

/// **实测事实（本腿撞到的）**：`语言面形状.md` 说「形状与编码无关」，
/// 但 **1102 的行首关键字识别不可能与编码无关** —— 关键字是**文本**，
/// 而 11 种记号种类里**没有「这是哪个关键字」的信息**（`记号定义.rs` 待办 1：
/// 「具体是哪个关键字由 1102 按区间文本 + `统一注册表` 判定」）。
///
/// 本腿按 `程序文本格式.md` §二 定的 **UTF-8** 比对；语料（GBK）里
/// `.子程序` 是 `2E D7 D3 B3 CC D0 F2`，比对不上 ⇒ 整行落成普通语句行的兜底。
/// **树仍然合法**（不变量一条不违反），只是语义退化。
#[test]
fn GBK原文_关键字认不出_落到兜底但仍建出合法树() {
    // `.子程序 启动\r\n` 的 GBK 字节
    let 原文: &[u8] = b".\xD7\xD3\xB3\xCC\xD0\xF2 \xC6\xF4\xB6\xAF\r\n";
    let 流 = 造记号流字节(
        原文,
        &[
            (记号种类::关键字, b".\xD7\xD3\xB3\xCC\xD0\xF2"),
            (记号种类::空白, b" "),
            (记号种类::标识符, b"\xC6\xF4\xB6\xAF"),
            (记号种类::换行, b"\r\n"),
        ],
    );
    let 树 = 建树(&流).expect("GBK 原文也必须建得出合法树");
    树.校验().expect("必须过全部不变量");
    贴("GBK 原文（认不出关键字）", &树);

    断言读数(
        &树,
        "\
0 程序 [0,14) 子(1,2)
1 源单元 [0,14) 子(2,3)
2 调用语句 [0,12) 子(3,4)
3 标识符引用 [0,12) 子(4,4)",
    );
    // 认不出关键字 ⇒ 没有 子程序 节点（不凭空造）
    assert!(!树.节点表.iter().any(|n| n.种类 == 节点种类::子程序));
    // 但那一行的内容字节仍被一个兜底叶认领（种类 = 标识符引用，区间 = 整行内容）
    assert_eq!(树.节点表[3].原文区间, (0, 12));
}

// ── 归属：缩进空白与行尾叶挂外层，表达式层不承接空白/换行 ────────────────────

#[test]
fn 归属_缩进空白与行尾叶挂外层节点() {
    let 流 = 夹具三();
    let 树 = 建过(&流);
    let 子程序 = 树.节点表[9];
    assert_eq!(子程序.种类, 节点种类::子程序);
    let 子: Vec<&crate::语言面::节点> = (子程序.子区间.0..子程序.子区间.1)
        .map(|i| &树.节点表[i as usize])
        .collect();
    // 缩进空白与行尾注释都挂在子程序这一层（它们是「最内层包含它的节点」的子）
    assert!(子.iter().any(|n| n.种类 == 节点种类::空白), "缩进空白挂子程序");
    assert!(子.iter().any(|n| n.种类 == 节点种类::注释), "行尾注释挂子程序");
    // 表达式层节点不得承接 空白 / 换行（`语言面形状.md` §3.5）
    for n in &树.节点表 {
        if matches!(
            n.种类,
            节点种类::二元运算
                | 节点种类::命令调用
                | 节点种类::成员访问
                | 节点种类::标识符引用
                | 节点种类::文本字面量
                | 节点种类::数值字面量
        ) {
            for 子 in n.子区间.0..n.子区间.1 {
                let c = &树.节点表[子 as usize];
                assert!(
                    !matches!(c.种类, 节点种类::空白 | 节点种类::换行),
                    "表达式层不承接空白/换行（判据 §3.5）"
                );
            }
        }
    }
}
