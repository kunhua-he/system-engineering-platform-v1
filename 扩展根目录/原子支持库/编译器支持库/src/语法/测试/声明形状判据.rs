//! 声明形状判据 —— ① 单行声明的头字段铺成子节点 · ② 程序集不包住子程序。
//!
//! 两条判据各有**正向**（真夹具的树逐条过）与**反向样本**（手搭的坏树当场红），
//! 且都走**三元读数**：通过 / 失败 / 未判 —— **空集是「未判」不是「通过」**。
//! 依据：裁决 `项目文档/决策记录/2026-09-27_语言主线三缺口裁决.md` §二 的「防回潮判据」。
//!
//! 判据不住在构造口（`语法树::新建`）里：它们不是 T1–T5 那类不变量，
//! 而是 1102 的**铺法口径**（合法树也可以违反）—— 故必须由测试维持。
//! 反向样本是手搭的**合法但铺错**的树：T1–T5 全过，只有这两条口径被违反。

use super::夹具::*;
use super::真形状::{建过, 贴快照};
use crate::测试夹具::取片段字节区间;
use crate::语言面::{节点, 节点种类, 语法树};

// ── 三元读数 ────────────────────────────────────────────────────────────────

/// 判据的三元读数。**空集是「未判」不是「通过」。**
#[derive(Debug, PartialEq, Eq)]
enum 读数 {
    通过,
    失败(String),
    未判,
}

/// 八类**单行声明**节点（`语句.rs::单行声明种类` 的节点侧名单）。
fn 是单行声明(种类: 节点种类) -> bool {
    use 节点种类::*;
    matches!(
        种类,
        支持库声明
            | 程序集变量声明
            | 全局变量声明
            | 局部变量声明
            | 参数声明
            | 数据成员声明
            | DLL命令声明
            | 常量声明
    )
}

/// 尾叶：空白 / 注释 / 换行（单行声明节点的区间认领自身的行尾）。
fn 是尾叶(种类: 节点种类) -> bool {
    matches!(种类, 节点种类::空白 | 节点种类::注释 | 节点种类::换行)
}

// ── 判据 ①：单行声明的头字段铺成子节点 ──────────────────────────────────────

/// **判据 ①**：每个单行声明节点都必须有**头字段子节点**（子区间不只剩尾叶）。
///
/// 铺法口径（`说明/语言面形状.md` §3.1）：声明头字段一律是子节点 ——
/// 子 0 = 名字，子 ≥1 = 类型候选。违反它就是「同一件事两套取值」的旧腿回潮。
fn 判据一_单行声明头字段铺子节点(语法树: &语法树) -> 读数 {
    let 声明s: Vec<u32> = 语法树
        .节点表
        .iter()
        .enumerate()
        .filter(|(_, 该节点)| 是单行声明(该节点.种类))
        .map(|(节点下标, _)| 节点下标 as u32)
        .collect();
    if 声明s.is_empty() {
        return 读数::未判; // 空集不是通过
    }
    for 下标 in 声明s {
        let 头字段: Vec<u32> = 语法树
            .直接子(下标)
            .filter(|&节点下标| !是尾叶(语法树.节点表[节点下标 as usize].种类))
            .collect();
        if 头字段.is_empty() {
            let 该节点 = &语法树.节点表[下标 as usize];
            return 读数::失败(format!(
                "{} 号 {} [{},{}) 一个头字段子节点都没有（子区间只剩尾叶）",
                下标,
                种类名(该节点.种类),
                该节点.取原文起点(),
                该节点.取原文终点()
            ));
        }
    }
    读数::通过
}

/// 正向：五份真夹具的树，每颗单行声明节点都有头字段子节点。
#[test]
fn 判据一_真夹具_每个单行声明都有头字段子节点() {
    let mut 已判 = 0;
    for 输出流 in 全部夹具() {
        let 语法树 = 建过(&输出流);
        match 判据一_单行声明头字段铺子节点(&语法树) {
            读数::通过 => 已判 += 1,
            读数::失败(因) => panic!("真夹具的树违反了判据 ①：{因}"),
            读数::未判 => {} // 这份夹具里没有单行声明 —— 不计入
        }
    }
    assert!(已判 >= 2, "夹具_局部变量声明（局部变量/参数）与夹具_其余声明种类（八类）都该判过，实得 {已判}");
}

/// 反向样本：**头字段不铺子节点**的树当场红。
///
/// 手搭一棵**合法但铺错**的树（T1–T5 全过）：那颗 `.局部变量声明` 只有一枚 `换行` 子
/// —— 正是「`建单行` 去掉 `声明字段` 调用」时的形状（本次改动前的旧树）。
#[test]
fn 判据一_反向样本_头字段不铺当场红() {
    let 输出流 = 夹具_局部变量声明();
    let 局部变量区间 = 取片段字节区间(夹具_局部变量声明原文, ".局部变量 监听服务器, Fiddler\r\n");
    let 语法树 = 语法树::新建(
        输出流,
        vec![
            节点::新建(节点种类::程序, (0, 夹具_局部变量声明原文.len() as u32), (1, 3)),
            节点::新建(节点种类::局部变量声明, 局部变量区间, (2, 3)),
            节点::叶节点(节点种类::换行, (局部变量区间.1 - 2, 局部变量区间.1)),
        ],
        0,
    )
    .expect("合法但铺错的树（T1–T5 全过）必须构造得出来");
    match 判据一_单行声明头字段铺子节点(&语法树) {
        读数::失败(_) => {}
        其他 => panic!("去掉头字段子节点必须当场红，实得 {其他:?}"),
    }
    // 同一棵坏树上判据 ② 是「未判」（树里没有 `.程序集` 节点）—— 空集不是通过。
    assert_eq!(判据二_程序集与子程序是兄弟(&语法树), 读数::未判);
}

// ── 判据 ②：程序集不包住子程序 ──────────────────────────────────────────────

/// **判据 ②**：没有 `.程序集` 节点的原文区间把任何 `.子程序` 节点包在里面。
///
/// 口径（`说明/语言面形状.md` §3.1）：`.程序集` 与 `.子程序` 是**兄弟**，
/// 归属靠「它之前最近的那条 `.程序集` 兄弟节点」判，不靠父子包含。
fn 判据二_程序集与子程序是兄弟(语法树: &语法树) -> 读数 {
    let 按种类找 = |种类: 节点种类| -> Vec<u32> {
        语法树.节点表
            .iter()
            .enumerate()
            .filter(|(_, 该节点)| 该节点.种类 == 种类)
            .map(|(节点下标, _)| 节点下标 as u32)
            .collect()
    };
    let 程序集s = 按种类找(节点种类::程序集);
    let 子程序s = 按种类找(节点种类::子程序);
    if 程序集s.is_empty() || 子程序s.is_empty() {
        return 读数::未判; // 空集不是通过
    }
    for &集 in &程序集s {
        let 程序集节点 = &语法树.节点表[集 as usize];
        for &程 in &子程序s {
            let 子程序节点 = &语法树.节点表[程 as usize];
            if 程序集节点.是否包住子区间(子程序节点.取原文起点(), 子程序节点.取原文终点()) {
                return 读数::失败(format!(
                    "{} 号 程序集 [{},{}) 包住了 {} 号 子程序 [{},{})",
                    集,
                    程序集节点.取原文起点(),
                    程序集节点.取原文终点(),
                    程,
                    子程序节点.取原文起点(),
                    子程序节点.取原文终点()
                ));
            }
        }
    }
    读数::通过
}

