//! 不变量测试 —— 语法树层 5 条（T1–T5）**每条都有正向与反向样本**。
//!
//! 依据 `项目文档/设计文档/判据的可信性.md`：**反向样本是判据的身份证**。
//! 5 条不变量本身在唯一构造口 `语法树::新建` 里判死（`语法树定义.rs`），
//! 所以这里两件事：
//!
//! 1. **正向**：本腿建出来的树逐条满足 —— 这是「建树真的产出合法树」的正面证据；
//! 2. **反向**：造一份违反该条的节点表，断言**报出正确的那一条码**（1118–1133）。
//!
//! **走子节点一律经 `语法树::直接子`**（唯一迭代口，跳子树）—— 测试也不许自身
//! 按 `子起..子止` 逐下标走：那会把子节点的后代当成兄弟
//! （`项目文档/决策记录/2026-09-27_三条裁决_按稳定性判.md` 裁决 一）。

use super::夹具::*;
use crate::语言面::{节点, 节点种类, 形状错误, 语法树};
use crate::语法::建树;

pub(super) fn 长() -> u32 {
    夹具一().全文长()
}

/// 造一份非法节点表，返回（形状错误 · 错误码）。非法值**必须构造不出来**。
pub(super) fn 报码(表: Vec<节点>, 根: u32) -> (形状错误, u32) {
    let 错 = 语法树::新建(夹具一(), 表, 根).expect_err("非法节点表必须构造不出来");
    (错, crate::形状错误码(&错))
}

// ── T1：根节点的原文区间 == [0, 全文长) ──────────────────────────────────────

#[test]
fn 不变量T1_根区间必须等于全文_正反样本() {
    // 正向：五份夹具建出来的树，根都是 [0, 全文长)
    for 流 in 全部夹具() {
        let 树 = 建树(&流).expect("合法记号流必须建得出树");
        let 根 = 树.根节点().expect("根节点存在");
        assert_eq!(根.种类, 节点种类::程序, "根的种类必须是 程序");
        assert_eq!((根.起(), 根.止()), (0, 流.全文长()));
        assert_eq!(树.原文切片(0), Some(流.原文.as_slice()));
    }

    // 反向一：根短一字节 ⇒ 1120 根区间不等于全文
    let (错, 码) = 报码(vec![节点::叶(节点种类::程序, (0, 长() - 1))], 0);
    assert_eq!(错, 形状错误::根区间不等于全文 { 起: 0, 止: 长() - 1, 全文长: 长() });
    assert_eq!(码, crate::错误码::根区间不等于全文);

    // 反向二：根长一字节 ⇒ 先撞 1122 节点区间越界（区间自身先合法，才谈得上等于全文）
    let (错, 码) = 报码(vec![节点::叶(节点种类::程序, (0, 长() + 1))], 0);
    assert_eq!(错, 形状错误::节点区间越界 { 下标: 0, 止: 长() + 1, 全文长: 长() });
    assert_eq!(码, crate::错误码::节点区间越界);

    // 反向三：空节点表 ⇒ 1118（T1 的「根得存在」那一半）
    let (错, 码) = 报码(vec![], 0);
    assert_eq!(错, 形状错误::节点表为空);
    assert_eq!(码, crate::错误码::节点表为空);

    // 反向四：根下标越界 ⇒ 1119
    let (错, 码) = 报码(vec![节点::叶(节点种类::程序, (0, 长()))], 1);
    assert_eq!(错, 形状错误::根下标越界 { 根: 1, 节点数: 1 });
    assert_eq!(码, crate::错误码::根下标越界);
}

// ── T2：父节点的原文区间包住每个直接子节点（含端点相等）────────────────────

#[test]
fn 不变量T2_父必须包住子_正反样本() {
    // 正向：逐节点逐直接子断言，且**零宽节点**也被包住（含端点相等）
    let mut 零宽见过 = 0;
    for 流 in 全部夹具() {
        let 树 = 建树(&流).expect("合法记号流必须建得出树");
        for (节点下标, 本节点) in 树.节点表.iter().enumerate() {
            for 子 in 树.直接子(节点下标 as u32) {
                let 子节点 = &树.节点表[子 as usize];
                assert!(
                    本节点.包住(子节点.起(), 子节点.止()),
                    "{} 没包住它的子 {}",
                    种类名(本节点.种类),
                    种类名(子节点.种类)
                );
                if 子节点.起() == 子节点.止() {
                    零宽见过 += 1;
                }
            }
        }
    }
    assert!(零宽见过 > 0, "夹具里必须出现零宽节点（空实参），否则这条正向样本是空的");

    // 反向：子程序 [10,20) 包不住注释 [25,30) ⇒ 1126 父未包住子
    let 表 = vec![
        节点::新(节点种类::程序, (0, 长()), (1, 2)),
        节点::新(节点种类::子程序, (10, 20), (2, 3)),
        节点::叶(节点种类::注释, (25, 30)),
    ];
    let (错, 码) = 报码(表, 0);
    assert_eq!(错, 形状错误::父未包住子 { 父: 1, 子: 2 });
    assert_eq!(码, crate::错误码::父未包住子);
}

// ── T3：直接子节点按序两两不重叠（后.起 >= 前.止）────────────────────────────

#[test]
fn 不变量T3_兄弟不得重叠_正反样本() {
    // 正向：逐节点逐对**相邻直接子**断言（走法经 `直接子`：中间夹着的是前一个兄弟的后代）
    let mut 兄弟对 = 0u32;
    for 流 in 全部夹具() {
        let 树 = 建树(&流).expect("合法记号流必须建得出树");
        for (节点下标, _n) in 树.节点表.iter().enumerate() {
            let mut 前一止: Option<u32> = None;
            for 子 in 树.直接子(节点下标 as u32) {
                let 子节点 = &树.节点表[子 as usize];
                if let Some(前止) = 前一止 {
                    assert!(子节点.起() >= 前止, "兄弟 {} 与前一个重叠", 子);
                    兄弟对 += 1;
                }
                前一止 = Some(子节点.止());
            }
        }
    }
    assert!(兄弟对 > 0, "夹具里必须有带多个子节点的节点，否则这条正向样本是空的");

    // 反向：注释 [10,20) 与换行 [15,25) 重叠 ⇒ 1127 兄弟重叠
    let 表 = vec![
        节点::新(节点种类::程序, (0, 长()), (1, 3)),
        节点::叶(节点种类::注释, (10, 20)),
        节点::叶(节点种类::换行, (15, 25)),
    ];
    let (错, 码) = 报码(表, 0);
    assert_eq!(错, 形状错误::兄弟重叠 { 父: 0, 前: 1, 后: 2 });
    assert_eq!(码, crate::错误码::兄弟重叠);
}

// ── T4：节点表构成一棵树（唯一父 · 无孤儿 · 无环 · 根无父 · 全覆盖）──────────

#[test]
fn 不变量T4_必须是一棵树_正反样本() {
    // 正向：除根外每个下标恰好一个父，且从根可达全部节点
    for 流 in 全部夹具() {
        let 树 = 建树(&流).expect("合法记号流必须建得出树");
        let 节点数 = 树.节点表.len();
        let mut 父数 = vec![0u32; 节点数];
        for (节点下标, _n) in 树.节点表.iter().enumerate() {
            for 子 in 树.直接子(节点下标 as u32) {
                父数[子 as usize] += 1;
            }
        }
        assert_eq!(父数[0], 0, "根不能有父");
        for (节点下标, 父数项) in 父数.iter().enumerate().skip(1) {
            assert_eq!(*父数项, 1, "节点 {} 的父数不是 1", 节点下标);
        }
        // 从根可达：子树止(根) == 节点数（先序表里根子树铺满整表）
        assert_eq!(树.子树止(0), Some(节点数 as u32));
    }

    // 反向一：同一节点有两个父 ⇒ 1128
    let 表 = vec![
        节点::新(节点种类::程序, (0, 长()), (1, 3)),
        节点::新(节点种类::子程序, (0, 长()), (3, 4)),
        节点::新(节点种类::源单元, (0, 长()), (3, 4)),
        节点::叶(节点种类::注释, (0, 1)),
    ];
    let (错, 码) = 报码(表, 0);
    assert_eq!(错, 形状错误::同一节点有两个父 { 节点: 3, 首父: 1, 次父: 2 });
    assert_eq!(码, crate::错误码::同一节点有两个父);

    // 反向二：根被当作子节点 ⇒ 1129
    let 表 = vec![
        节点::新(节点种类::程序, (0, 长()), (1, 2)),
        节点::叶(节点种类::程序, (0, 长())),
    ];
    let (错, 码) = 报码(表, 1);
    assert_eq!(错, 形状错误::根被当作子节点 { 节点: 1, 父: 0 });
    assert_eq!(码, crate::错误码::根被当作子节点);

    // 反向三：孤儿 ⇒ 1130
    let 表 = vec![
        节点::新(节点种类::程序, (0, 长()), (1, 2)),
        节点::叶(节点种类::注释, (0, 1)),
        节点::叶(节点种类::换行, (1, 2)),
    ];
    let (错, 码) = 报码(表, 0);
    assert_eq!(错, 形状错误::节点是孤儿 { 节点: 2 });
    assert_eq!(码, crate::错误码::节点是孤儿);

    // 反向四：1 与 2 互相当父 ⇒ 从根不可达 ⇒ 1132
    let 表 = vec![
        节点::叶(节点种类::程序, (0, 长())),
        节点::新(节点种类::子程序, (0, 长()), (2, 3)),
        节点::新(节点种类::源单元, (0, 长()), (1, 2)),
    ];
    let (错, 码) = 报码(表, 0);
    assert_eq!(错, 形状错误::节点从根不可达 { 节点: 1 });
    assert_eq!(码, crate::错误码::节点从根不可达);
}

// ── T5：节点表按深度优先先序排列（相邻兄弟 子树止(前) == 后）────────────────

#[test]
fn 不变量T5_必须先序连续_正反样本() {
    // 正向：逐节点逐对相邻直接子断言。
    // `直接子` 的走法**本身**就是 T5（下一跳 = 前一个兄弟的子树止），所以这里再判两件
    // 它保证不了的事：每一跳不许越过 `子区间.止`，且末子的子树止必须**正好**落在它上面。
    let mut 相邻对 = 0u32;
    for 流 in 全部夹具() {
        let 树 = 建树(&流).expect("合法记号流必须建得出树");
        for (节点下标, 本节点) in 树.节点表.iter().enumerate() {
            let (起, 止) = 本节点.子区间;
            if 起 >= 止 {
                continue;
            }
            let mut 前: Option<u32> = None;
            for 子 in 树.直接子(节点下标 as u32) {
                if let Some(前下标) = 前 {
                    // 相邻兄弟：前一个的子树止 == 后一个（逐跳紧接，中间不许夹兄弟）
                    assert_eq!(
                        树.子树止(前下标),
                        Some(子),
                        "兄弟 {} 后面不是紧接着 {}",
                        前下标,
                        子
                    );
                    相邻对 += 1;
                }
                let 到 = 树.子树止(子).expect("先序表里子树止必须有值");
                assert!(到 <= 止, "子 {} 的子树止 {} 越过了父声明的 {}", 子, 到, 止);
                前 = Some(子);
            }
            let 末子 = 前.expect("子区间非空就必然有直接子");
            assert_eq!(
                树.子树止(末子),
                Some(止),
                "末子 {} 的子树止没落在子区间止 {} 上（先序表有空档）",
                末子,
                止
            );
        }
    }
    assert!(相邻对 > 0, "夹具里必须有带 2 个以上子节点的节点，否则这条正向样本是空的");

    // 反向一：末子的子树**伸出**了父声明的区间（跳子树后仍抓得到）。
    // 逐下标走法看不出这条（它只会在 [子起,子止) 里数下标），跳子树才会落到 5 > 3。
    let 表 = vec![
        节点::新(节点种类::程序, (0, 长()), (1, 3)),
        节点::新(节点种类::子程序, (0, 50), (2, 5)),
        节点::叶(节点种类::注释, (10, 20)),
        节点::叶(节点种类::换行, (20, 30)),
        节点::叶(节点种类::空白, (30, 40)),
    ];
    let (错, 码) = 报码(表, 0);
    assert_eq!(错, 形状错误::非先序连续 { 父: 0, 子: 1, 子树止: 5 });
    assert_eq!(码, crate::错误码::非先序连续);

    // 反向二：伸出的是**孙辈**（不是直接子本身）—— 跳子树要一路走到底才看得出来。
    // T4 全过（每个下标恰好一个父：程序 的直接子只有 1；2..5 是 1 的直接子），
    // 但 1 的整棵子树止于 6，越过了 程序 声明的 4 ⇒ 非先序连续。
    let 表 = vec![
        节点::新(节点种类::程序, (0, 长()), (1, 4)),
        节点::新(节点种类::子程序, (0, 50), (2, 6)),
        节点::叶(节点种类::注释, (0, 10)),
        节点::叶(节点种类::换行, (10, 20)),
        节点::叶(节点种类::空白, (20, 30)),
        节点::叶(节点种类::注释, (30, 40)),
    ];
    let (错, 码) = 报码(表, 0);
    assert_eq!(错, 形状错误::非先序连续 { 父: 0, 子: 1, 子树止: 6 });
    assert_eq!(码, crate::错误码::非先序连续);
}
