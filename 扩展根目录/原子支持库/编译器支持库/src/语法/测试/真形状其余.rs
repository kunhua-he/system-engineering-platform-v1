// ── 编码：GBK 原文里关键字认不出来 ⇒ 落到兜底，但树仍合法 ────────────────────

/// **实测事实（本腿撞到的）**：`语言面形状.md` 说「形状与编码无关」，
/// 但 **1102 的行首关键字识别不可能与编码无关** —— 关键字是**文本**，
/// 而 11 种记号种类里**没有「这是哪个关键字」的信息**（`记号定义.rs` 待办 1：
/// 「具体是哪个关键字由 1102 按区间文本 + `统一注册表` 判定」）。
///
/// 本腿按 `程序文本格式.md` §二 定的 **UTF-8** 比对；语料（GBK）里
/// `.子程序` 是 `2E D7 D3 B3 CC D0 F2`，比对不上 ⇒ 整行落成普通语句行的兜底。
/// **树仍然合法**（不变量一条不违反），只是语义退化。
#[test]
fn GBK原文_关键字认不出_落到兜底但仍建出合法树() {
    // `.子程序 启动\r\n` 的 GBK 字节
    let 原文: &[u8] = b".\xD7\xD3\xB3\xCC\xD0\xF2 \xC6\xF4\xB6\xAF\r\n";
    let 流 = 造记号流字节(
        原文,
        &[
            (记号种类::关键字, b".\xD7\xD3\xB3\xCC\xD0\xF2"),
            (记号种类::空白, b" "),
            (记号种类::标识符, b"\xC6\xF4\xB6\xAF"),
            (记号种类::换行, b"\r\n"),
        ],
    );
    let 树 = 建树(&流).expect("GBK 原文也必须建得出合法树");
    树.校验().expect("必须过全部不变量");
    贴快照("GBK 原文（认不出关键字）", &树);

    断言读数(
        &树,
        "\
0 程序 [0,14) 子(1,5)
1 源单元 [0,14) 子(2,5)
2 调用语句 [0,14) 子(3,5)
3 标识符引用 [0,12) 子(4,4)
4 换行 [12,14) 子(5,5)",
    );
    // 认不出关键字 ⇒ 没有 子程序 节点（不凭空造）
    assert!(!树.节点表.iter().any(|本节点| 本节点.种类 == 节点种类::子程序));
    // 但那一行的内容字节仍被一个兜底叶认领（种类 = 标识符引用，区间 = 整行内容）
    assert_eq!(树.节点表[3].原文区间, (0, 12));
}

// ── 归属：缩进挂外层节点 · 行尾叶挂本行节点 ──────────────────────────────────

#[test]
fn 归属_缩进挂外层节点_行尾叶挂本行节点() {
    let 流 = 夹具二();
    let 树 = 建过(&流);
    let 外层块 = 树.节点表[16];
    let 内层块 = 树.节点表[24];
    assert_eq!(外层块.种类, 节点种类::块语句);
    assert_eq!(内层块.种类, 节点种类::块语句);

    // 缩进空白（内层 `.如果` 行首的 4 空格 [143,147)）挂在**外层**块这一层：
    // 内层块节点的区间从关键字起（不含缩进），故「最内层包含它的节点」是外层块（§3.5）。
    let 内层行 = 区间(夹具二原文, "    .如果 (fd.websocket");
    let 缩进 = (内层行.0, 内层行.0 + 4);
    assert_eq!(缩进, (143, 147));
    assert!(
        树.直接子(16).any(|子| 子 == 23),
        "缩进空白 [143,147) 挂外层块（23 号）"
    );
    assert!(!树.直接子(24).any(|子| 子 == 23), "缩进不属于内层块");
    assert_eq!(树.节点表[23].原文区间, (143, 147));

    // 行尾叶挂**本行节点**（语句认领自身的行尾）：`调试输出 (…)` 那行的 `换行` 是它的末子
    assert_eq!(树.节点表[34].种类, 节点种类::调用语句);
    assert_eq!(树.直接子(34).last(), Some(44), "语句的末子是它自身的行尾换行");
    assert_eq!(树.节点表[44].原文区间, (271, 273));

    // 表达式层节点不得承接 空白 / 换行（`语言面形状.md` §3.5）
    for (节点下标, 本节点) in 树.节点表.iter().enumerate() {
        if matches!(
            本节点.种类,
            节点种类::二元运算
                | 节点种类::命令调用
                | 节点种类::成员访问
                | 节点种类::标识符引用
                | 节点种类::文本字面量
                | 节点种类::数值字面量
        ) {
            for 子 in 树.直接子(节点下标 as u32) {
                let 子节点 = &树.节点表[子 as usize];
                assert!(
                    !matches!(子节点.种类, 节点种类::空白 | 节点种类::换行),
                    "表达式层不承接空白/换行（判据 §3.5）"
                );
            }
        }
    }
}

// ── 反向样本（本次读法修正的身份证）：一个体里**三条都带子树** ────────────────

/// **一个体里三条都带子树的语句，必须三条都建出正确的树。**
///
/// 这是旧读法的反面：那时 `校验` 把先序子树区间里**每个下标**都当直接子，逼出「右脊」
/// —— 一个体里只有**最后**那条语句能带子树，前面几条落成叶（种类与区间仍准确，子树丢掉）。
/// 现在读法改成跳子树（`语法树::直接子`），三条都带得动。
///
/// 断言逐条落到**每条语句自身的子树**上：成员访问 / 命令调用 / 二元运算 一个都不许少。
#[test]
fn 反向_一个体里三条都带子树的语句都要建出子树() {
    let 流 = 夹具六();
    let 树 = 建过(&流);
    贴快照("一个体里三条都带子树", &树);

    let 子程序 = 树
        .节点表
        .iter()
        .position(|本节点| 本节点.种类 == 节点种类::子程序)
        .expect("夹具六里有 .子程序") as u32;
    // 体里的三条语句（种类 + 序号），各自的直接子都 >= 2（也就是都带着自身的表达式子树）
    let 语句: Vec<(u32, 节点种类)> = 树
        .直接子(子程序)
        .filter(|&子| {
            matches!(
                树.节点表[子 as usize].种类,
                节点种类::赋值语句 | 节点种类::调用语句 | 节点种类::返回语句
            )
        })
        .map(|子| (子, 树.节点表[子 as usize].种类))
        .collect();
    assert_eq!(语句.len(), 3, "夹具六的体里必须正好三条语句");
    for &(下标, 种类) in &语句 {
        let 子: Vec<u32> = 树.直接子(下标).collect();
        assert!(
            子.len() >= 2,
            "{} 号 {} 必须带着自身的子树（直接子 {:?}）",
            下标,
            种类名(种类),
            子
        );
    }
    // 三条都带子树 ⇒ 整棵树的节点数远多于语句数（旧读法下前面两条被压成叶，只有十几个）
    assert!(
        树.节点表.len() > 20,
        "三条带子树的语句建出来的树不该被压成十几个节点，实得 {}",
        树.节点表.len()
    );
    // 三棵子树各自非空、且**紧接**（先序连续：前一条的子树止 == 后一条的下标）
    let 切: Vec<(u32, u32)> = 语句
        .iter()
        .map(|&(下标, _)| (下标, 树.子树止(下标).expect("先序表里子树止必须有值")))
        .collect();
    for (条位次, &(起, 止)) in 切.iter().enumerate() {
        assert!(止 > 起 + 1, "第 {} 条语句的子树必须非空", 条位次);
    }
    for 相邻条 in 切.windows(2) {
        assert_eq!(相邻条[0].1, 相邻条[1].0, "相邻语句的子树必须紧接（T5）");
    }
}
