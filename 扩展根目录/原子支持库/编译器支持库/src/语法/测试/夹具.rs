//! 测试夹具 —— 本模块自有的字节版手搭记号流 · 树读数；通用夹具（造记号流 · 区间）在 `crate::测试夹具`。
//!
//! 五份夹具都照 `说明/真文本覆盖.md` 的实测原样缩成几行（原文形态、缩进、CRLF、
//! 全角运算符、空实参、行尾注释都照抄），**唯一改动是文本字面量与备注里的全角标点**
//! —— 那些属于 `真文本覆盖.md` 缺口 2「备注位自由文本没有记号种类」的范围，
//! 手搭记号流时不假装 1101 认得出来。

use crate::语言面::{节点种类, 记号, 记号流, 记号种类, 语法树};

/// 字节级夹具（GBK 原文用；本腿的 UTF-8 关键字表认不出 GBK）。
pub(super) fn 造记号流字节(原文: &[u8], 项表: &[(记号种类, &[u8])]) -> 记号流 {
    let mut 记号表 = Vec::new();
    let mut 游标 = 0usize;
    for (种类, 片段) in 项表 {
        let 区间起点 = 游标;
        let 区间终点 = 区间起点 + 片段.len();
        assert_eq!(&原文[区间起点..区间终点], *片段, "夹具片段与原文对不上");
        记号表.push(记号::新建(*种类, 区间起点 as u32, 区间终点 as u32));
        游标 = 区间终点;
    }
    assert_eq!(游标, 原文.len(), "夹具片段没铺满全文");
    let 长度 = 原文.len() as u32;
    记号表.push(记号::新建(记号种类::文件结束, 长度, 长度));
    记号流::新建(原文.to_vec(), 记号表).expect("夹具造的记号流必须合法")
}

