/// 树读数：逐节点一行 `下标 种类 [起,止) 子(起,止)`。报告里的读数就是它。
pub(super) fn 树读数(语法树: &语法树) -> Vec<String> {
    语法树.节点表
        .iter()
        .enumerate()
        .map(|(位次, 节点)| {
            format!(
                "{} {} [{},{}) 子({},{})",
                位次,
                种类名(节点.种类),
                节点.取原文起点(),
                节点.取原文终点(),
                节点.子区间.0,
                节点.子区间.1
            )
        })
        .collect()
}

/// 把报告里的读数**钉成判据**：树的逐节点读数必须逐行相同。
pub(super) fn 断言读数(语法树: &语法树, 期望: &str) {
    let 实得 = 树读数(语法树).join("\n");
    assert_eq!(实得, 期望.trim_end(), "树的逐节点读数与期望不一致");
}

