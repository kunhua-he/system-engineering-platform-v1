#[test]
fn 坏输入_逐类报出正确的码_1118到1133() {
    let 项表 = 坏输入表();
    assert_eq!(项表.len(), 15, "语法树层够得着的坏输入一类不许漏");
    for 一条坏输入 in 项表 {
        let 错误 = 语法树::新建(夹具_子程序声明(), 一条坏输入.表, 一条坏输入.根)
            .err()
            .unwrap_or_else(|| panic!("{}：非法语法树应当构造不出来", 一条坏输入.名字));
        assert_eq!(错误, 一条坏输入.期望, "{}：报的变体不对", 一条坏输入.名字);
        assert_eq!(crate::形状错误码(&错误), 一条坏输入.码, "{}：报的码不对", 一条坏输入.名字);
    }
}

/// **实测事实**：`形状错误::节点被重复到达`（码 1131）在 `校验` 的检查顺序下**够不着**。
///
/// 走到可达遍历之前，「除根外每个下标恰好被一个 `子区间` 包含」已经判过 ⇒
/// 每个节点最多被入栈一次 ⇒ 不可能「重复到达」。所以 1118–1133 共 16 条码里，
/// **有坏输入样本的只有 15 条**（1131 除外）。这条测试把这个缺口钉住，
/// 免得后人以为「没样本 = 没测到」。
#[test]
fn 坏输入_1131够不着_原因是被1128挡在前面() {
    // 造一个「想重复到达」的节点表：让 1 与 2 都引用 3（这就是唯一能通向重复到达的形状）
    let 长度 = 取长度();
    let 项表 = vec![
        节点::新建(节点种类::程序, (0, 长度), (1, 3)),
        节点::新建(节点种类::子程序, (0, 长度), (3, 4)),
        节点::新建(节点种类::源单元, (0, 长度), (3, 4)),
        节点::叶节点(节点种类::注释记号, (0, 1)),
    ];
    let 错误 = 语法树::新建(夹具_子程序声明(), 项表, 0).expect_err("必须报错");
    assert_eq!(错误, 形状错误::同一节点有两个父 { 节点: 3, 首父: 1, 次父: 2 });
    assert_ne!(crate::形状错误码(&错误), crate::错误码::节点被重复到达);
    // 15 条样本覆盖 1118–1133 里除 1131 之外的全部
    let 码集: Vec<u32> = 坏输入表().iter().map(|条目| 条目.码).collect();
    for 错误码 in 1118..=1133u32 {
        if 错误码 == crate::错误码::节点被重复到达 {
            assert!(!码集.contains(&错误码), "1131 不该有样本");
        } else {
            assert!(码集.contains(&错误码), "{} 没有样本", 错误码);
        }
    }
}

/// **空记号流**：1102 根本收不到 —— 它在记号层就被 `记号流::新建` 拒掉（1108）。
#[test]
fn 坏输入_空记号流在记号层就被拒_1108() {
    let 错误 = 记号流::新建(Vec::new(), Vec::new()).expect_err("空记号表必须构造不出来");
    assert_eq!(错误, 形状错误::记号表为空);
    assert_eq!(crate::形状错误码(&错误), crate::错误码::记号表为空);
    // 而「空文件」（一枚零宽 文件结束）是合法的：1102 要能建出零宽根。
    let 输出流 = 记号流::新建(Vec::new(), vec![crate::语言面::记号::新建(
        crate::语言面::记号种类::文件结束,
        0,
        0,
    )])
    .expect("空文件的记号流必须合法");
    let 语法树 = 建树(&输出流).expect("空文件必须建得出树");
    assert_eq!(语法树.节点表.len(), 2, "程序 + 源单元");
    let 根目录 = 语法树.根节点().unwrap();
    assert_eq!((根目录.取原文起点(), 根目录.取原文终点()), (0, 0));
}
