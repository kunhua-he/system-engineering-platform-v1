//! 坏输入 —— 逐类断言报出**正确的那一条码**（1118–1133），以及两条边界事实。
//!
//! 与 `不变量.rs` 是一对：那边按 T1–T5 逐条给正反样本，这边按**码**逐条点全。

use super::不变量::{报码, 长};
