//! 语句与块 —— 单行节点（声明 / 赋值 / 调用 / 返回 / 置入代码）与块节点。
//!
//! 这一件是 [`super::建树`] 的续篇：`建树器` 的固有实现拆在两个文件里，
//! 只按「体」与「单行 / 块」分工，**不是两套实现**。

use super::表达式::兜底种类;
use super::建树::{建树器, 顶层赋值号};
use super::行::{行, 行类};
use crate::语言面::节点种类;

impl 建树器<'_> {
    // ── 单行节点 ────────────────────────────────────────────────────────────

    pub(super) fn 建单行(&mut self, h: &行) -> u32 {
        // 区间到**行字节止**：行尾空白 / 注释 / 换行由本节点认领 ——
        // 它们是「包含它的最内层语句级或声明级节点」的子（`语言面形状.md` §3.5）。
        // 旧读法（把先序子树区间逐下标当直接子）下这做不到：行尾叶排在行内容之后，
        // 会让内容成为非末子而被压成叶；现在读法改成跳子树（`语法树::直接子`），
        // 非末子照样能带子树，故行尾叶回到本行节点之下。
        let (起, 止) = (h.内容起, h.字节止);
        let mut 子: Vec<u32> = Vec::new();
        let 种类 = match h.类 {
            行类::支持库 => 节点种类::支持库声明,
            行类::程序集变量 => 节点种类::程序集变量声明,
            行类::全局变量 => 节点种类::全局变量声明,
            行类::局部变量 => 节点种类::局部变量声明,
            行类::参数 => 节点种类::参数声明,
            行类::成员 => 节点种类::数据成员声明,
            行类::Dll命令 => 节点种类::DLL命令声明,
            行类::常量 => 节点种类::常量声明,
            行类::返回 => {
                let 起2 = h.内容记号起 + 1;
                子 = self.表达式(起2, h.内容记号止).into_iter().collect();
                节点种类::返回语句
            }
            行类::置入代码 => {
                子 = self.括号实参(h);
                节点种类::置入代码语句
            }
            // 没配对上的块关键字：当单行块语句（条件照收），不 panic。
            行类::块首 | 行类::块中 | 行类::块尾 => {
                子 = self.括号实参(h);
                节点种类::块语句
            }
            行类::语句 => {
                let 流 = self.流;
                let 等号 = 顶层赋值号(&流.记号表, &流.原文, h.内容记号起, h.内容记号止);
                match 等号 {
                    Some(i) => {
                        if let Some(n) = self.表达式(h.内容记号起, i) {
                            子.push(n);
                        }
                        if let Some(n) = self.表达式(i + 1, h.内容记号止) {
                            子.push(n);
                        }
                        节点种类::赋值语句
                    }
                    None => {
                        if let Some(n) = self.表达式(h.内容记号起, h.内容记号止) {
                            子.push(n);
                        }
                        节点种类::调用语句
                    }
                }
            }
            _ => {
                子 = self.声明字段(h);
                兜底种类
            }
        };
        // 行尾叶挂在本行节点之下（区间已含到行字节止）。
        子.extend(self.尾叶(h));
        self.草稿.节点(种类, (起, 止), 子)
    }

    // ── 块 ──────────────────────────────────────────────────────────────────

    /// 找配对块尾行与一级分支行（`.否则` / `.判断` / `.默认`）。
    pub(super) fn 扫块(&self, 行表: &[行], 头: usize, 止: usize) -> (Option<usize>, Vec<usize>) {
        let mut 深 = 1i32;
        let mut 分支行 = Vec::new();
        let mut i = 头 + 1;
        while i < 止 {
            match 行表[i].类 {
                行类::块首 => 深 += 1,
                行类::块尾 => {
                    深 -= 1;
                    if 深 == 0 {
                        return (Some(i), 分支行);
                    }
                }
                行类::块中 if 深 == 1 => {
                    分支行.push(i);
                }
                _ => {}
            }
            i += 1;
        }
        (None, 分支行)
    }

    /// 块末：配对块尾行的下标；没配对就取 `止`（**不报错** —— 缩进/配对不是不变量）。
    pub(super) fn 块末(&self, 行表: &[行], 头: usize, 止: usize) -> usize {
        match self.扫块(行表, 头, 止).0 {
            Some(k) => k + 1,
            None => 止,
        }
    }

    pub(super) fn 建块(&mut self, 行表: &[行], 头: usize, 止行: usize) -> u32 {
        let (块尾行, 分支行) = self.扫块(行表, 头, 止行);
        let h = 行表[头];
        let 起 = h.关键字.map(|x| x.0).unwrap_or(h.内容起);
        let 体末 = 块尾行.unwrap_or(止行);
        let 止 = match 块尾行 {
            Some(k) => 行表[k].字节止,
            None => 行表.get(止行).map(|x| x.字节起).unwrap_or(self.全文长()),
        };
        let 判断 = self.行关键字文(&h) == ".判断开始".as_bytes();
        let mut 子 = self.括号实参(&h);
        子.extend(self.尾叶(&h));

        let mut 段起 = 头 + 1;
        for (k, &分支) in 分支行.iter().enumerate() {
            let 下一 = 分支行.get(k + 1).copied().unwrap_or(体末);
            self.深度 += 1;
            子.extend(self.建体(行表, 段起, 分支));
            self.深度 -= 1;
            let bh = 行表[分支];
            if let Some(n) = self.缩进叶(&bh) {
                子.push(n);
            }
            let 分支止 = 行表.get(下一).map(|x| x.字节起).unwrap_or(self.全文长());
            let 分支起 = bh.关键字.map(|x| x.0).unwrap_or(bh.内容起);
            let mut 分支子 = self.括号实参(&bh);
            分支子.extend(self.尾叶(&bh));
            self.深度 += 1;
            分支子.extend(self.建体(行表, 分支 + 1, 下一));
            self.深度 -= 1;
            let 分支种 = if 判断 { 节点种类::判断分支 } else { 节点种类::块语句 };
            子.push(self.草稿.节点(分支种, (分支起, 分支止), 分支子));
            段起 = 下一;
        }
        if 分支行.is_empty() {
            self.深度 += 1;
            子.extend(self.建体(行表, 头 + 1, 体末));
            self.深度 -= 1;
        }
        if let Some(k) = 块尾行 {
            let kh = 行表[k];
            if let Some(n) = self.缩进叶(&kh) {
                子.push(n);
            }
            子.extend(self.尾叶(&kh));
        }
        let 种 = if 判断 { 节点种类::判断块 } else { 节点种类::块语句 };
        self.草稿.节点(种, (起, 止), 子)
    }
}
