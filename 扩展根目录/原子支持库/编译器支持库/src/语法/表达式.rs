//! 表达式 —— 记号区间 → 表达式草稿（1102 的表达式层，号 41–50）。
//!
//! # 文法（按 `程序文本格式.md` §二 的实测读数写成，不含任何没实测到的东西）
//!
//! ```text
//! 表达式 := 解一元表达式 ( 运算符 解一元表达式 )*        // 全角；左结合；**不分优先级**
//! 解一元表达式   := '&' 解一元表达式 | 解后置表达式              // 实测只有取地址 `&`（半角）
//! 解后置表达式   := 主 ( '.' 成员 | '[' 表达式 ']' | '(' 实参表 ')' )*
//! 主     := 文本字面量 | 数值字面量 | 常量引用 | 标识符 | '(' 表达式 ')'
//! 实参表 := ( 表达式 | 空位 ) ( ',' ( 表达式 | 空位 ) )*
//! ```
//!
//! # 三条设计选择（都有理由，不是随手）
//!
//! 1. **运算符集合不写表**：`记号种类::运算符` 已经是 1101 的判定结果 —— 只要种类是
//!    `运算符` 就当二元运算符用。于是「完整运算符集合未定」（待办 4）不落在 1102 身上，
//!    实测的 `－`(U+FF0D) `＞`(U+FF1E) 也不用单独补表。
//! 2. **不分优先级**：语料里 `_启动窗口.宽度 － 图片按钮EX1.宽度 － 20` 是左结合；
//!    优先级（`＋` 与 `×` 谁先）**语料 0 例**（`语言面形状.md` 待办 4）。故一律左结合。
//! 3. **只有 `主` 会失败**，且失败时**一个草稿都没压进草稿表**。于是「失败要回滚」
//!    这套机制完全不需要（草稿是自由的树，扁平化时才落成节点表，孤儿节点无从产生）。
//!    链式扩展（`.`/`[`/`(`）任何一步接不上就**停在原地**，剩下的字节由父节点自身认领
//!    （`语言面形状.md` §4.3：不要求子节点铺满父区间）。
//!
//! **兜底**：33 种节点种类里**没有「未知 / 原始文本」这一类**（形状冻结，只增不复用，
//! 本腿不许动）。遇到解不出的记号串，本实现包一个 `标识符引用` 叶 ——
//! 这是**兜底选择**，不是实测结论，已逐条写进返回说明。

use super::草稿树::草稿表;
use crate::语言面::{记号, 记号种类};

#[path = "表达式/实参.rs"]
mod 实参;

/// 递归深度上限。超出即停止下潜（**不 panic、不爆栈**）。
const 深度上限: u32 = 32;

/// 兜底叶的种类：解不出的记号串包成一个叶子。
pub(crate) const 兜底种类: 节点种类 = 节点种类::标识符引用;

use crate::语言面::节点种类;

pub(crate) struct 表达式分析器<'a> {
    pub(super) 原文: &'a [u8],
    pub(super) 记号表: &'a [记号],
    pub(super) 草稿树: &'a mut 草稿表,
    /// 当前记号下标。
    pub(super) 游标: usize,
    /// 本次解析的上界（不含）。
    pub(super) 区间终点: usize,
    pub(super) 深度: u32,
}

impl<'a> 表达式分析器<'a> {
    pub(crate) fn 构造(
        原文: &'a [u8],
        记号表: &'a [记号],
        草稿树: &'a mut 草稿表,
    ) -> Self {
        Self { 原文, 记号表, 草稿树, 游标: 0, 区间终点: 记号表.len(), 深度: 0 }
    }

    pub(super) fn 取记号原文(&self, 该记号: 记号) -> &'a [u8] {
        self.原文.get(该记号.区间起点 as usize..该记号.区间终点 as usize).unwrap_or(&[])
    }

    pub(super) fn 当前记号(&self) -> Option<记号> {
        if self.游标 < self.区间终点 {
            self.记号表.get(self.游标).copied()
        } else {
            None
        }
    }

    pub(super) fn 是界符(&self, 源文本: &[u8]) -> bool {
        match self.当前记号() {
            Some(该记号) => 该记号.记号类别 == 记号种类::界符 && self.取记号原文(该记号) == 源文本,
            None => false,
        }
    }

    pub(super) fn 跳过空白(&mut self) {
        while self.游标 < self.区间终点 && self.记号表[self.游标].记号类别 == 记号种类::空白记号 {
            self.游标 += 1;
        }
    }

    /// 从 `游标`（停在开界符上）找配对的闭界符下标。认不出返回 `None`。
    pub(super) fn 找配对界符(&self, 开符: &[u8], 闭符: &[u8]) -> Option<usize> {
        let mut 括号深度 = 0i32;
        let mut 记号下标 = self.游标;
        while 记号下标 < self.区间终点 {
            let 该记号 = self.记号表[记号下标];
            if 该记号.记号类别 == 记号种类::界符 {
                let 源文本 = self.取记号原文(该记号);
                if 源文本 == 开符 {
                    括号深度 += 1;
                } else if 源文本 == 闭符 {
                    括号深度 -= 1;
                    if 括号深度 == 0 {
                        return Some(记号下标);
                    }
                }
            }
            记号下标 += 1;
        }
        None
    }

    /// 把 `[游标, 区间终点)` 里还没消费的记号包成一个兜底叶（有内容才包）。
    pub(super) fn 兜底到(&mut self, 区间终点: usize) -> Option<u32> {
        if self.游标 >= 区间终点 {
            return None;
        }
        let 区间起点 = self.记号表[self.游标].区间起点;
        let 末记号止 = self.记号表[区间终点 - 1].区间终点;
        self.游标 = 区间终点;
        Some(self.草稿树.追加叶节点(兜底种类, 区间起点, 末记号止))
    }

    /// 唯一的区间入口：在 `[区间起点, 区间终点)` 上解一个表达式，解不出或有余下记号就补兜底叶。
    /// 成功返回草稿下标；`None` = 一个记号都没解出（此时草稿表**一个都没多**）。
    ///
    /// 行层（`super::建树`）与表达式层自身（括号 / 下标 / 实参）都调它 ——
    /// 此前表达式层另有一个函数体逐字相同的 `子区间`，那是第二套实现，已删（只留本名）。
    pub(crate) fn 解析区间(&mut self, 区间起点: usize, 区间终点: usize) -> Option<u32> {
        let 保存游标 = self.游标;
        let 保存止 = self.区间终点;
        self.游标 = 区间起点;
        self.区间终点 = 区间终点;
        let 匹配结果 = match self.解二元表达式() {
            Some(节点下标) => {
                self.兜底到(区间终点);
                Some(节点下标)
            }
            None => self.兜底到(区间终点),
        };
        self.区间终点 = 保存止;
        self.游标 = 保存游标;
        匹配结果
    }

    pub(super) fn 解二元表达式(&mut self) -> Option<u32> {
        if self.深度 >= 深度上限 {
            return None;
        }
        self.深度 += 1;
        let 匹配结果 = self.解二元链();
        self.深度 -= 1;
        匹配结果
    }

    /// 左结合链：`a ＋ b ＋ c` ⇒ `二元运算(二元运算(a,b), c)`。
    ///
    /// 草稿是自由的树，左结合**不会**撞上节点表的布局约束（那条约束只在扁平化时生效，
    /// 由 `草稿::扁平化草稿` 统一处理）—— 这正是要草稿这一层的原因。
    fn 解二元链(&mut self) -> Option<u32> {
        let mut 左操作数 = self.解一元表达式()?;
        loop {
            let 保存 = self.游标;
            self.跳过空白();
            let 是运算符 = matches!(self.当前记号(), Some(该记号) if 该记号.记号类别 == 记号种类::运算符);
            if !是运算符 {
                self.游标 = 保存;
                return Some(左操作数);
            }
            self.游标 += 1;
            match self.解一元表达式() {
                Some(右操作数) => {
                    let 取片段字节区间 = (self.草稿树.取原文起点(左操作数), self.草稿树.取原文终点(右操作数));
                    左操作数 = self.草稿树.节点(节点种类::二元运算, 取片段字节区间, vec![左操作数, 右操作数]);
                }
                None => return Some(左操作数),
            }
        }
    }

    fn 解一元表达式(&mut self) -> Option<u32> {
        self.跳过空白();
        if self.是界符(b"&") {
            let 该记号 = self.当前记号()?;
            self.游标 += 1;
            let 操作数 = self.解一元表达式();
            let 区间终点 = 操作数.map(|节点下标| self.草稿树.取原文终点(节点下标)).unwrap_or(该记号.区间终点);
            let 子节点表 = match 操作数 {
                Some(节点下标) => vec![节点下标],
                None => Vec::new(),
            };
            return Some(self.草稿树.节点(节点种类::一元运算, (该记号.区间起点, 区间终点), 子节点表));
        }
        self.解后置表达式()
    }

    fn 解后置表达式(&mut self) -> Option<u32> {
        let mut 基节点 = self.分析主式()?;
        loop {
            let 保存 = self.游标;
            self.跳过空白();
            if self.是界符(b".") {
                self.游标 += 1;
                self.跳过空白();
                match self.当前记号() {
                    Some(成员记号) if 成员记号.记号类别 == 记号种类::标识符 => {
                        self.游标 += 1;
                        let 成员节点 = self.草稿树.追加叶节点(节点种类::标识符引用, 成员记号.区间起点, 成员记号.区间终点);
                        let 取片段字节区间 = (self.草稿树.取原文起点(基节点), 成员记号.区间终点);
                        基节点 = self.草稿树.节点(节点种类::成员访问, 取片段字节区间, vec![基节点, 成员节点]);
                    }
                    _ => {
                        self.游标 = 保存;
                        return Some(基节点);
                    }
                }
            } else if self.是界符(b"[") {
                let Some(闭符) = self.找配对界符(b"[", b"]") else {
                    self.游标 = 保存;
                    return Some(基节点);
                };
                let 开符 = self.游标;
                let 节点位序 = self.解析区间(开符 + 1, 闭符);
                self.游标 = 闭符 + 1;
                let Some(节点位序) = 节点位序 else {
                    self.游标 = 保存;
                    return Some(基节点);
                };
                let 取片段字节区间 = (self.草稿树.取原文起点(基节点), self.记号表[闭符].区间终点);
                基节点 = self.草稿树.节点(节点种类::下标访问, 取片段字节区间, vec![基节点, 节点位序]);
            } else if self.是界符(b"(") {
                let Some(闭符) = self.找配对界符(b"(", b")") else {
                    self.游标 = 保存;
                    return Some(基节点);
                };
                let 开符 = self.游标;
                let 实参 = self.解实参表(开符, 闭符);
                self.游标 = 闭符 + 1;
                let 区间终点 = self.记号表[闭符].区间终点;
                match self.草稿树.节点类别(基节点) {
                    节点种类::标识符引用 => {
                        // `名 (实参表)` ⇒ 命令调用：子 = [名, 实参…]
                        let mut 子节点表 = Vec::with_capacity(实参.len() + 1);
                        子节点表.push(基节点);
                        子节点表.extend(实参);
                        基节点 = self.草稿树.节点(节点种类::命令调用, (self.草稿树.取原文起点(基节点), 区间终点), 子节点表);
                    }
                    节点种类::成员访问 => {
                        // 成员调用：实参追加为成员访问的子（`成员访问` 自身覆盖调用形状）。
                        let mut 子节点表: Vec<u32> = self.草稿树.取子节点(基节点).to_vec();
                        子节点表.extend(实参);
                        let 区间起点 = self.草稿树.取原文起点(基节点);
                        基节点 = self.草稿树.节点(节点种类::成员访问, (区间起点, 区间终点), 子节点表);
                    }
                    _ => {
                        // `f ()()` 之类：实参挂在基节点之下，基的种类不动。
                        let mut 子节点表: Vec<u32> = self.草稿树.取子节点(基节点).to_vec();
                        子节点表.extend(实参);
                        let 区间起点 = self.草稿树.取原文起点(基节点);
                        基节点 = self.草稿树.节点(self.草稿树.节点类别(基节点), (区间起点, 区间终点), 子节点表);
                    }
                }
            } else {
                self.游标 = 保存;
                return Some(基节点);
            }
        }
    }

    fn 分析主式(&mut self) -> Option<u32> {
        self.跳过空白();
        let 该记号 = self.当前记号()?;
        match 该记号.记号类别 {
            记号种类::文本字面量 => {
                self.游标 += 1;
                Some(self.草稿树.追加叶节点(节点种类::文本字面量, 该记号.区间起点, 该记号.区间终点))
            }
            记号种类::数值字面量 => {
                self.游标 += 1;
                Some(self.草稿树.追加叶节点(节点种类::数值字面量, 该记号.区间起点, 该记号.区间终点))
            }
            记号种类::常量引用 => {
                self.游标 += 1;
                Some(self.草稿树.追加叶节点(节点种类::常量引用, 该记号.区间起点, 该记号.区间终点))
            }
            记号种类::标识符 | 记号种类::备注文本 => {
                // 备注文本落 `标识符引用` 叶：33 种节点种类里没有「备注」这一类（形状冻结、
                // 只增不复用），故沿用本文件的兜底选择（见文件头「兜底」）。
                self.游标 += 1;
                Some(self.草稿树.追加叶节点(节点种类::标识符引用, 该记号.区间起点, 该记号.区间终点))
            }
            记号种类::界符 if self.取记号原文(该记号) == b"(" => {
                let 闭符 = self.找配对界符(b"(", b")")?;
                let 开符 = self.游标;
                let 内层 = self.解析区间(开符 + 1, 闭符);
                self.游标 = 闭符 + 1;
                内层
            }
            记号种类::界符 if self.取记号原文(该记号) == b"{" => {
                let 闭符 = self.找配对界符(b"{", b"}")?;
                let 开符 = self.游标;
                let 节点 = self.解结果结构字面量(开符, 闭符)?;
                self.游标 = 闭符 + 1;
                Some(节点)
            }
            _ => None,
        }
    }

    /// `{名称: 表达式, …}` → `结果结构字面量` 节点。子节点按「名称叶 · 值表达式」成对排。
    ///
    /// 形状不合一律 `None`（**不猜**）。`{` `}` `:` `,` 都是**界符**记号 —— 词法不用动。
    /// 本节点**不查命令表**：它不是平台能力调用，是构造一个值 ⇒ 不给平台加契约层号。
    fn 解结果结构字面量(&mut self, 开符: usize, 闭符: usize) -> Option<u32> {
        let mut 子节点表: Vec<u32> = Vec::new();
        let mut 游标 = 开符 + 1;
        loop {
            while 游标 < 闭符 && self.记号表[游标].记号类别 == 记号种类::空白记号 {
                游标 += 1;
            }
            if 游标 >= 闭符 {
                break;
            }
            let 名记号 = self.记号表[游标];
            if 名记号.记号类别 != 记号种类::标识符 && 名记号.记号类别 != 记号种类::文本字面量 {
                return None;
            }
            子节点表.push(self.草稿树.追加叶节点(
                节点种类::标识符引用, 名记号.区间起点, 名记号.区间终点));
            游标 += 1;
            while 游标 < 闭符 && self.记号表[游标].记号类别 == 记号种类::空白记号 {
                游标 += 1;
            }
            if 游标 >= 闭符 {
                return None;
            }
            let 冒号 = self.记号表[游标];
            if 冒号.记号类别 != 记号种类::界符 || self.取记号原文(冒号) != b":" {
                return None;
            }
            游标 += 1;
            let 保存游标 = self.游标;
            let 保存止 = self.区间终点;
            self.游标 = 游标;
            self.区间终点 = 闭符;
            let 值节点 = self.解二元表达式();
            let 后游标 = self.游标;
            self.游标 = 保存游标;
            self.区间终点 = 保存止;
            子节点表.push(值节点?);
            游标 = 后游标;
            while 游标 < 闭符 && self.记号表[游标].记号类别 == 记号种类::空白记号 {
                游标 += 1;
            }
            if 游标 >= 闭符 {
                break;
            }
            let 分隔 = self.记号表[游标];
            if 分隔.记号类别 != 记号种类::界符 || self.取记号原文(分隔) != b"," {
                return None;
            }
            游标 += 1;
        }
        if 子节点表.is_empty() {
            return None;
        }
        let 节点起 = self.记号表[开符].区间起点;
        let 节点止 = self.记号表[闭符].区间终点;
        Some(self.草稿树.节点(节点种类::结果结构字面量, (节点起, 节点止), 子节点表))
    }
}

