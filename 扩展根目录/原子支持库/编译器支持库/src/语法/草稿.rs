//! 草稿 —— 建树时的临时树 + 扁平化成**先序节点表**。
//!
//! # 为什么要草稿这一层
//!
//! 冻结形状的 `子区间` 是**先序子树区间**（[`crate::语言面::语法树::直接子`] 的说明）：
//! 区间从第一个直接子节点起，到最后一个直接子节点的**整棵子树**之后止。
//! 于是「直接子节点怎么走」由 `子树止` 逐跳给出，而**每个子节点都可以带自己的子树**
//! —— 这正是本层要负责落出来的：先自由搭一棵草稿树（父子任意嵌套），再在扁平化时
//! 按深度优先先序铺表，每个节点都能保住它的后代。
//!
//! **曾经不是这样**：旧读法把 `[子起, 子止)` 里**每个**下标都当直接子，逼出「右脊」
//! （除末子外其余子只能是叶），一个体里只有最后一条语句能带子树，前面几条的子树被丢掉。
//! 那是读法之误，不是形状之限 —— 见 `项目文档/决策记录/2026-09-27_三条裁决_按稳定性判.md`
//! 裁决 一 与 `项目文档/未完成事项.md` 第 123 条（修法②）。
//!
//! **布局规则只有一处**：[`语法树::先序子区间`]（写侧），与 [`语法树::直接子`]（读侧）
//! 是同一条规则的两面。本文件不另立一条。

use crate::语言面::{节点, 节点种类, 语法树};

/// 草稿里的一个节点：种类 · 原文区间 · 子节点草稿下标。
pub(crate) struct 草稿 {
    pub 种类: 节点种类,
    pub 区间: (u32, u32),
    pub 子: Vec<u32>,
}

/// 草稿表（建树期间的临时容器）。
#[derive(Default)]
pub(crate) struct 草稿表 {
    表: Vec<草稿>,
}

impl 草稿表 {
    pub(crate) fn 叶(&mut self, 种类: 节点种类, 起: u32, 止: u32) -> u32 {
        self.表.push(草稿 { 种类, 区间: (起, 止), 子: Vec::new() });
        (self.表.len() - 1) as u32
    }

    pub(crate) fn 节点(&mut self, 种类: 节点种类, 区间: (u32, u32), 子: Vec<u32>) -> u32 {
        self.表.push(草稿 { 种类, 区间, 子 });
        (self.表.len() - 1) as u32
    }

    pub(crate) fn 种类(&self, 下标: u32) -> 节点种类 {
        self.表[下标 as usize].种类
    }

    pub(crate) fn 起(&self, 下标: u32) -> u32 {
        self.表[下标 as usize].区间.0
    }

    pub(crate) fn 止(&self, 下标: u32) -> u32 {
        self.表[下标 as usize].区间.1
    }

    pub(crate) fn 子(&self, 下标: u32) -> &[u32] {
        &self.表[下标 as usize].子
    }

    /// 扁平化成先序节点表：**每个子节点都带着它的整棵子树**（见文件头）。
    ///
    /// 迭代实现，**不递归** —— 输入多长脊就多长，递归会爆栈。
    /// 展开顺序：本节点 → 各子节点（按序，各自的整棵子树紧接着排在后面）。
    /// `子区间` 一律由 [`语法树::先序子区间`] 落，不在这里另写一条布局规则。
    pub(crate) fn 扁平化(&self, 根: u32) -> Vec<节点> {
        let 大小 = self.子树大小表(根);
        let mut 出: Vec<节点> = Vec::with_capacity(大小[根 as usize] as usize);
        let mut 栈: Vec<u32> = vec![根];
        while let Some(i) = 栈.pop() {
            let 位置 = 出.len() as u32;
            let 草 = &self.表[i as usize];
            出.push(节点::叶(草.种类, 草.区间));
            出[位置 as usize].子区间 = 语法树::先序子区间(位置, 大小[i as usize] - 1);
            // 逆序入栈 ⇒ 出栈即先序。
            栈.extend(草.子.iter().rev().copied());
        }
        出
    }

    /// 每个草稿节点的**子树节点数**（含自身）。迭代后序，不递归（深脊会爆栈）。
    ///
    /// 只算从 `根` 可达的那些 —— 表达式层解析失败时留下的草稿节点会成为垃圾
    /// （`表达式.rs` 明说「失败时一个草稿都没压进草稿表」，但链式扩展换掉基节点时
    /// 旧基会变垃圾），它们不参与扁平化，大小留 0 即可。
    fn 子树大小表(&self, 根: u32) -> Vec<u32> {
        let mut 大小 = vec![0u32; self.表.len()];
        let mut 栈: Vec<(u32, usize)> = vec![(根, 0)];
        while let Some((i, k)) = 栈.pop() {
            let 子 = &self.表[i as usize].子;
            match 子.get(k) {
                Some(&c) => {
                    栈.push((i, k + 1));
                    栈.push((c, 0));
                }
                None => {
                    大小[i as usize] = 1 + 子.iter().map(|&c| 大小[c as usize]).sum::<u32>();
                }
            }
        }
        大小
    }
}
