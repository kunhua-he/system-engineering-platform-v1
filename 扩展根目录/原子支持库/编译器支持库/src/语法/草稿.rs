//! 草稿 —— 建树时的临时树 + 扁平化成**先序节点表**。
//!
//! # 为什么要草稿这一层（这不是多余的抽象）
//!
//! 冻结形状的 `子区间` 是**直接子节点在节点表里的下标区间**，而且 `语法树::校验` 把
//! `[子起, 子止)` 里**每一个**下标都当成直接子节点。两条不变量合起来：
//!
//! - **T3**：直接子节点必须**按字节序**两两不重叠；
//! - **T4**：`[子起, 子止)` 里每个下标**恰好被一个**父引用；
//! - **T5**：相邻兄弟 `c_j`、`c_{j+1}` 满足 `子树止(c_j) == c_{j+1}`。
//!
//! 于是「子节点下标连续」+「前一个兄弟的子树止 == 后一个兄弟的下标」⇒
//! **除最后一个子节点外，其余子节点只能是叶**。实测（本腿在 HEAD 上跑过探针）：
//! 一个「中间那个子节点带子树」的节点表被 `校验` 拒掉，报
//! `非先序连续 { 父: 2, 子: 4, 子树止: 9 }`。
//!
//! **结论：冻结形状能表达的树是「右脊」—— 每个节点的子节点里只有最后一个可以往下长。**
//! 这不是本腿的发明，是 T3+T4+T5 的合取。所以先自由地搭一棵草稿树（父子任意嵌套），
//! 再在扁平化时按这条规矩落成节点表：**非末子只落一个叶**。
//!
//! **代价（如实记）**：一个体里有两条以上带子树的语句时，只有最后一条能带子树，
//! 前面几条只能落成叶（种类与原文区间仍然准确，子树丢掉）。

use crate::语言面::{节点, 节点种类};

/// 草稿里的一个节点：种类 · 原文区间 · 子节点草稿下标。
pub(crate) struct 草稿 {
    pub 种类: 节点种类,
    pub 区间: (u32, u32),
    pub 子: Vec<u32>,
}

/// 草稿表（建树期间的临时容器）。
#[derive(Default)]
pub(crate) struct 草稿表 {
    表: Vec<草稿>,
}

impl 草稿表 {
    pub(crate) fn 叶(&mut self, 种类: 节点种类, 起: u32, 止: u32) -> u32 {
        self.表.push(草稿 { 种类, 区间: (起, 止), 子: Vec::new() });
        (self.表.len() - 1) as u32
    }

    pub(crate) fn 节点(&mut self, 种类: 节点种类, 区间: (u32, u32), 子: Vec<u32>) -> u32 {
        self.表.push(草稿 { 种类, 区间, 子 });
        (self.表.len() - 1) as u32
    }

    pub(crate) fn 种类(&self, 下标: u32) -> 节点种类 {
        self.表[下标 as usize].种类
    }

    pub(crate) fn 区间(&self, 下标: u32) -> (u32, u32) {
        self.表[下标 as usize].区间
    }

    pub(crate) fn 起(&self, 下标: u32) -> u32 {
        self.表[下标 as usize].区间.0
    }

    pub(crate) fn 止(&self, 下标: u32) -> u32 {
        self.表[下标 as usize].区间.1
    }

    pub(crate) fn 子(&self, 下标: u32) -> &[u32] {
        &self.表[下标 as usize].子
    }

    pub(crate) fn 长(&self) -> usize {
        self.表.len()
    }

    /// 扁平化成先序节点表（见本文件头部：非末子只落一个叶）。
    ///
    /// 迭代实现，**不递归** —— 脊可以很长（输入多长脊就多长），递归会爆栈。
    /// 展开顺序：本节点 → 各子节点（非末子落叶、末子继续展开）。
    pub(crate) fn 扁平化(&self, 根: u32) -> Vec<节点> {
        let mut 出: Vec<节点> = Vec::new();
        let mut 当前 = Some(根);
        while let Some(i) = 当前 {
            let 位置 = 出.len() as u32;
            let 草 = &self.表[i as usize];
            出.push(节点::叶(草.种类, 草.区间));
            let n = 草.子.len() as u32;
            出[位置 as usize].子区间 = (位置 + 1, 位置 + 1 + n);
            for k in 0..n {
                let c = 草.子[k as usize];
                if k + 1 == n {
                    // 末子：留到下一轮展开（它的整棵子树紧接着排在后面）。
                    当前 = Some(c);
                } else {
                    // 非末子：只落一个叶（T5 逼出来的，见文件头）。
                    let cc = &self.表[c as usize];
                    let p = 出.len() as u32;
                    出.push(节点::叶(cc.种类, cc.区间));
                    出[p as usize].子区间 = (p + 1, p + 1);
                }
            }
            if n == 0 {
                当前 = None;
            }
        }
        出
    }
}
