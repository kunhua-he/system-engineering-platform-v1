//! 实参表 —— 调用实参 / 空实参 / 括号里那一段（[`super`] 的续篇）。
//!
//! `表达式分析器` 的固有实现拆在两件里（本件只放实参表），**不是两套实现**。
//! 拆的原因只有一个：单文件 ≤ 400 行。

use super::表达式分析器;
use crate::语言面::{记号种类, 节点种类};

impl 表达式分析器<'_> {
    /// 实参表：`开` 是 `(` 的下标，`闭` 是配对的 `)` 的下标。
    ///
    /// **空位的锚**（照已冻的读数 `形状测试/语法树.rs::语法树_样例子树止与子区间`）：
    /// 空位是**零宽**节点，锚在**它前面那个逗号的起**；第一个实参就是空位时锚在 `(` 的止；
    /// `…, )` 的尾空位锚在它前面那个逗号。`(首参, , 次参)` ⇒ 空位 `[11,11)`（首参止 == 11）。
    ///
    /// 解不出的实参：把余下记号包成一个兜底叶，**不再往下切**（不 panic、不死循环）。
    pub(super) fn 解实参表(&mut self, 开符: usize, 闭符: usize) -> Vec<u32> {
        let 左止 = self.记号表[开符].止;
        let mut 实参: Vec<u32> = Vec::new();
        let mut 游标 = 开符 + 1;
        let mut 前分隔: Option<u32> = None;
        let mut 期待 = true;
        loop {
            // 跳过空白与花括号（`置入代码 ({ 139, 69, … })` 的 `{` / `}`）。
            while 游标 < 闭符 {
                let 本记号 = self.记号表[游标];
                let 是花括号 =
                    本记号.种类 == 记号种类::界符 && (self.取记号原文(本记号) == b"{" || self.取记号原文(本记号) == b"}");
                if 本记号.种类 == 记号种类::空白 || 是花括号 {
                    游标 += 1;
                } else {
                    break;
                }
            }
            if 游标 >= 闭符 {
                if 期待
                    && let Some(空位锚点) = 前分隔
                {
                    实参.push(self.草稿.追加叶节点(节点种类::空实参, 空位锚点, 空位锚点));
                }
                break;
            }
            let 本记号 = self.记号表[游标];
            if 本记号.种类 == 记号种类::界符 && self.取记号原文(本记号) == b"," {
                if 期待 {
                    let 空位锚点 = 前分隔.unwrap_or(左止);
                    实参.push(self.草稿.追加叶节点(节点种类::空实参, 空位锚点, 空位锚点));
                }
                前分隔 = Some(本记号.区间起点);
                游标 += 1;
                期待 = true;
                continue;
            }
            let 保存游标 = self.游标;
            let 保存止 = self.止;
            self.游标 = 游标;
            self.止 = 闭符;
            let 结果 = self.解二元表达式();
            游标 = self.游标;
            self.游标 = 保存游标;
            self.止 = 保存止;
            match 结果 {
                // **解出一个实参就不许兜底**：剩下的逗号与实参留给下一轮，
                // 否则 `(首参, 次参, 末参)` 会变成一个实参 + 一片兜底（实测撞到过）。
                Some(实参节点) => {
                    实参.push(实参节点);
                    期待 = false;
                }
                None => {
                    // 一个记号都没解出：余下包成一个兜底叶，收手（不 panic、不死循环）
                    if let Some(叶节点) = self.兜底到(闭符) {
                        实参.push(叶节点);
                    }
                    break;
                }
            }
        }
        实参
    }

    /// 公开口：解析一整个实参表（`开符` 给 `(` 的下标）。返回实参草稿下标表。
    pub(crate) fn 解析实参表(&mut self, 开符: usize, 区间终点: usize) -> Vec<u32> {
        let 保存游标 = self.游标;
        let 保存止 = self.止;
        self.游标 = 开符;
        self.止 = 区间终点;
        let 结果 = match self.找配对界符(b"(", b")") {
            Some(闭符) => self.解实参表(开符, 闭符),
            None => Vec::new(),
        };
        self.游标 = 保存游标;
        self.止 = 保存止;
        结果
    }

    /// 公开口：在 `[区间起点, 区间终点)` 里找第一个 `(` 并解析它里面的实参表（块头条件 / 置入代码用）。
    pub(crate) fn 解析括号实参(&mut self, 区间起点: usize, 区间终点: usize) -> Vec<u32> {
        let mut 记号位次 = 区间起点;
        while 记号位次 < 区间终点 {
            let 本记号 = self.记号表[记号位次];
            if 本记号.种类 == 记号种类::界符 && self.取记号原文(本记号) == b"(" {
                return self.解析实参表(记号位次, 区间终点);
            }
            记号位次 += 1;
        }
        Vec::new()
    }
}
