//! 建树 —— 1102 语法分析：记号流 → 语法树。
//!
//! # 入口
//!
//! [`建树`] 吃一份 [`记号流`]（1101 的产物，形状已冻结），交一棵 [`语法树`]。
//! 形状全用 `语言面` 既有类型，**不另造**。
//!
//! # 四步
//!
//! 1. **切行**（[`super::行`]）：记号表 → 行表。行是本语言的一等边界
//!    （`程序文本格式.md` §二：缩进 = 块嵌套深度、注释到行尾）。
//! 2. **行 → 草稿节点**（本文件）：声明行按顶层逗号切字段、语句行按顶层 `＝` 分左右、
//!    块按配对关键字收拢、体按「段首行」收边界。
//! 3. **表达式层**（[`super::表达式`]）：括号 / 成员 / 下标 / 调用 / 二元 / 空实参。
//! 4. **扁平化**（[`super::草稿`]）：草稿树 → 先序节点表，再过唯一构造口
//!    [`语法树::新建`]（T1–T5 在那里判死）。
//!
//! # 归属判据（注释 / 空白 / 换行挂给谁）
//!
//! 照 `语言面形状.md` §3.5：挂在**包含它的最内层语句级或声明级节点**之下。本实现由此推出：
//!
//! - **缩进空白**（行首连续空白）挂在**外层**节点 —— 因为单行节点的区间从它的**内容**起，
//!   不含缩进（与已冻的读数 `形状测试/语法树.rs` 里 `空白 [32,36)` 与 `返回语句 [36,58)`
//!   是兄弟一致）；
//! - **行尾空白 / 注释 / 换行**挂在该行的语句/声明节点之下（它们落在该节点区间内）；
//! - **行内空白不建节点**（`语言面形状.md` §4.3：不要求子节点铺满父区间；这样表达式内部
//!   空白与行内空白同构，节点表不至于被空白淹掉）。
//!
//! 前两条曾经做不到：旧读法（把先序子树区间逐下标当直接子）逼出「右脊」，行尾叶若挂在本行
//! 节点下，行内容就成了非末子、必被压成叶，表达式结构整棵丢掉。所以那时行尾叶被挪到外层、
//! 体的收尾叶干脆不建。**那是绕开，不是判据** —— 读法修好（`语法树::直接子` 跳子树）之后
//! 已撤掉：行尾叶回到本行节点之下（`语句.rs::建单行`），`去尾叶` 一并删除。
//!
//! # 兜底（不许 panic）
//!
//! 解不出的记号串包成 `标识符引用` 叶（33 种里没有「未知」这一类，形状冻结不许增）。
//! **`备注文本` 记号也走这条**（词法层已立第 12 种，语法层没有对应节点种类）——
//! 它在 [`super::表达式`] 的 `主()` 里与 `标识符` 同臂，故真文本的树形状与立类前一致。
//! 块嵌套超过 [`块深上限`] 时不再下潜，内层块按单行处理。**任何输入都不 panic。**

use super::草稿::草稿表;
use super::表达式::分析器;
use super::行::{源码行, 行类, 切行};
use crate::语言面::{节点种类, 记号, 记号流, 记号种类, 形状错误, 语法树};

/// 块嵌套深度上限：超出即不再下潜（防爆栈；**不报错、不 panic**）。
const 块深上限: u32 = 64;

/// 顶层赋值号（全角 `＝` U+FF3D）。
const 赋值号: &[u8] = "＝".as_bytes();

/// **1102 语法分析**：把记号流建成语法树。
///
/// 只吃形状、不判断编码：原文是 GBK 还是 UTF-8 不影响本函数的合法性，
/// 但**行首关键字的识别依赖 UTF-8 文本比对**（见 `super::行`）——
/// GBK 原文里关键字认不出来，会落到「普通语句行」的兜底路径（实测事实，见返回说明）。
pub fn 建树(输出流: &记号流) -> Result<语法树, 形状错误> {
    let 行表 = 切行(输出流);
    let mut 建 = 建树器 { 流: 输出流, 草稿: 草稿表::default(), 深度: 0 };
    let 根 = 建.建程序(&行表);
    let 节点表 = 建.草稿.扁平化(根);
    语法树::新建(输出流.clone(), 节点表, 0)
}

/// 建树期间的容器。固有实现拆在 `建树.rs`（顶层与体）与 `语句.rs`（单行与块）两件里，
/// 故字段与跨件调用的方法一律 `pub(super)`。
pub(super) struct 建树器<'a> {
    pub(super) 流: &'a 记号流,
    pub(super) 草稿: 草稿表,
    pub(super) 深度: u32,
}

// ── 小工具（全是纯函数，不碰 self）────────────────────────────────────────────

pub(super) fn 取记号原文(原文: &[u8], 该记号: 记号) -> &[u8] {
    原文.get(该记号.起 as usize..该记号.止 as usize).unwrap_or(&[])
}

/// 去掉 `[起, 止)` 两端的 `空白` 记号；没有内容记号就返回 `None`。
pub(super) fn 去空白(项表: &[记号], 区间起点: usize, 区间终点: usize) -> Option<(usize, usize)> {
    let mut 前界 = 区间起点;
    let mut 后界 = 区间终点;
    while 前界 < 后界 && 项表[前界].种类 == 记号种类::空白 {
        前界 += 1;
    }
    while 后界 > 前界 && 项表[后界 - 1].种类 == 记号种类::空白 {
        后界 -= 1;
    }
    if 前界 < 后界 { Some((前界, 后界)) } else { None }
}

/// 按**顶层**（括号深度 0）半角逗号切段。
pub(super) fn 切字段(项表: &[记号], 原文: &[u8], 区间起点: usize, 区间终点: usize) -> Vec<(usize, usize)> {
    let mut 出 = Vec::new();
    let mut 段起 = 区间起点;
    let mut 深 = 0i32;
    for (偏移, 该记号) in 项表[区间起点..区间终点].iter().enumerate() {
        if 该记号.种类 != 记号种类::界符 {
            continue;
        }
        match 取记号原文(原文, *该记号) {
            b"(" | b"[" | b"{" => 深 += 1,
            b")" | b"]" | b"}" => 深 -= 1,
            b"," if 深 <= 0 => {
                出.push((段起, 区间起点 + 偏移));
                段起 = 区间起点 + 偏移 + 1;
            }
            _ => {}
        }
    }
    出.push((段起, 区间终点));
    出
}

/// 顶层赋值号（`＝`）的记号下标。
pub(super) fn 顶层赋值号(项表: &[记号], 原文: &[u8], 区间起点: usize, 区间终点: usize) -> Option<usize> {
    let mut 深 = 0i32;
    for (偏移, 该记号) in 项表[区间起点..区间终点].iter().enumerate() {
        if 该记号.种类 != 记号种类::界符 && 该记号.种类 != 记号种类::运算符 {
            continue;
        }
        let 记号文 = 取记号原文(原文, *该记号);
        match 记号文 {
            b"(" | b"[" | b"{" => 深 += 1,
            b")" | b"]" | b"}" => 深 -= 1,
            _ => {
                if 深 <= 0 && 该记号.种类 == 记号种类::运算符 && 记号文 == 赋值号 {
                    return Some(区间起点 + 偏移);
                }
            }
        }
    }
    None
}

/// 行里第一个非 `空白` 记号的**记号下标**（缩进到哪里为止）。
pub(super) fn 首非空白(项表: &[记号], 此行: &源码行) -> usize {
    let mut 记号下标 = 此行.记号起;
    while 记号下标 < 此行.记号止 && 项表[记号下标].种类 == 记号种类::空白 {
        记号下标 += 1;
    }
    记号下标
}

// ── 建树器 ────────────────────────────────────────────────────────────────────

impl<'a> 建树器<'a> {
    pub(super) fn 全文长(&self) -> u32 {
        self.流.全文长()
    }

    pub(super) fn 行关键字文(&self, 此行: &源码行) -> &[u8] {
        match 此行.关键字 {
            Some((起, 止)) => self.流.原文.get(起 as usize..止 as usize).unwrap_or(&[]),
            None => &[],
        }
    }

    /// 解一个表达式（`[区间起点, 区间终点)` 是记号下标区间，两端空白自动去掉）。
    pub(super) fn 表达式(&mut self, 区间起点: usize, 区间终点: usize) -> Option<u32> {
        let 流 = self.流;
        let (起, 止) = 去空白(&流.记号表, 区间起点, 区间终点)?;
        let mut 器 = 分析器::新建(&流.原文, &流.记号表, &mut self.草稿);
        器.解析区间(起, 止)
    }

    /// 缩进空白叶：`[字节起, 缩进止)`。无缩进返回 `None`。
    pub(super) fn 缩进叶(&mut self, 此行: &源码行) -> Option<u32> {
        if 此行.缩进止 > 此行.字节起 {
            Some(self.草稿.追加叶节点(节点种类::空白, 此行.字节起, 此行.缩进止))
        } else {
            None
        }
    }

    /// 行尾叶：内容之后的 `空白`（连续合并成一个）/ `注释` / `换行`。
    ///
    /// 从 `max(内容记号止, 首个非空白记号)` 起扫 —— 于是**不会**把已作缩进叶的
    /// 那一段空白再认领一次（空行就是这样：缩进止 == 内容记号起）。
    pub(super) fn 尾叶(&mut self, 此行: &源码行) -> Vec<u32> {
        let 流 = self.流;
        let 表 = &流.记号表;
        let mut 出 = Vec::new();
        let mut 记号下标 = 此行.内容记号止.max(首非空白(表, 此行));
        let mut 空白起: Option<u32> = None;
        let mut 空白止 = 0u32;
        while 记号下标 < 此行.记号止 {
            let 该记号 = 表[记号下标];
            match 该记号.种类 {
                记号种类::空白 => {
                    if 空白起.is_none() {
                        空白起 = Some(该记号.起);
                    }
                    空白止 = 该记号.止;
                }
                _ => {
                    if let Some(起) = 空白起.take() {
                        出.push(self.草稿.追加叶节点(节点种类::空白, 起, 空白止));
                    }
                    match 该记号.种类 {
                        记号种类::注释 => 出.push(self.草稿.追加叶节点(节点种类::注释, 该记号.起, 该记号.止)),
                        记号种类::换行 => 出.push(self.草稿.追加叶节点(节点种类::换行, 该记号.起, 该记号.止)),
                        _ => {}
                    }
                }
            }
            记号下标 += 1;
        }
        if let Some(起) = 空白起 {
            出.push(self.草稿.追加叶节点(节点种类::空白, 起, 此行.字节止));
        }
        出
    }

    /// 声明头行的字段：顶层逗号切段，每段解一个表达式。
    pub(super) fn 声明字段(&mut self, 此行: &源码行) -> Vec<u32> {
        let 流 = self.流;
        let 起 = if 此行.关键字.is_some() { 此行.内容记号起 + 1 } else { 此行.内容记号起 };
        let mut 出 = Vec::new();
        if 起 > 此行.内容记号止 {
            return 出;
        }
        for (字段起, 字段止) in 切字段(&流.记号表, &流.原文, 起, 此行.内容记号止) {
            if let Some(节点下标) = self.表达式(字段起, 字段止) {
                出.push(节点下标);
            }
        }
        出
    }

    /// 行里第一个 `(` 的实参表（块头条件 / `置入代码` 的 `({ … })`）。
    pub(super) fn 括号实参(&mut self, 此行: &源码行) -> Vec<u32> {
        let 流 = self.流;
        let 起 = if 此行.关键字.is_some() { 此行.内容记号起 + 1 } else { 此行.内容记号起 };
        if 起 >= 此行.内容记号止 {
            return Vec::new();
        }
        let mut 器 = 分析器::新建(&流.原文, &流.记号表, &mut self.草稿);
        器.解析括号实参(起, 此行.内容记号止)
    }
}

impl 建树器<'_> {
    // ── 顶层：程序 → 源单元 ──────────────────────────────────────────────────

    pub(super) fn 建程序(&mut self, 行表: &[源码行]) -> u32 {
        let 全文长 = self.全文长();
        let 段首: Vec<usize> = 行表
            .iter()
            .enumerate()
            .filter(|(_, 此行)| 此行.类 == 行类::版本)
            .map(|(行下标, _)| 行下标)
            .collect();
        let mut 子: Vec<u32> = Vec::new();
        if 段首.is_empty() {
            // 没有 `.版本` 行：整份文本算一个源单元（区间 == 全文，T2 含端点相等，合法）。
            let 体 = self.建体(行表, 0, 行表.len());
            子.push(self.草稿.节点(节点种类::源单元, (0, 全文长), 体));
        } else {
            // 首个 `.版本` 之前的零散行 → 程序的直属子。
            子.extend(self.建体(行表, 0, 段首[0]));
            for 段号 in 0..段首.len() {
                let 头 = 段首[段号];
                let 体止行 = 段首.get(段号 + 1).copied().unwrap_or(行表.len());
                let 止 = 行表.get(体止行).map(|此行| 此行.字节起).unwrap_or(全文长);
                let 此行 = 行表[头];
                let 起 = 此行.关键字.map(|关键字对| 关键字对.0).unwrap_or(此行.内容起);
                if let Some(节点下标) = self.缩进叶(&此行) {
                    子.push(节点下标);
                }
                let mut 体 = self.声明字段(&此行);
                体.extend(self.尾叶(&此行));
                体.extend(self.建体(行表, 头 + 1, 体止行));
                子.push(self.草稿.节点(节点种类::源单元, (起, 止), 体));
            }
        }
        self.草稿.节点(节点种类::程序, (0, 全文长), 子)
    }

    // ── 体：一串行 → 一串节点 ────────────────────────────────────────────────

    pub(super) fn 建体(&mut self, 行表: &[源码行], 区间起点: usize, 区间终点: usize) -> Vec<u32> {
        let mut 出: Vec<u32> = Vec::new();
        let mut 行下标 = 区间起点;
        while 行下标 < 区间终点 {
            let 此行 = 行表[行下标];
            if let Some(节点下标) = self.缩进叶(&此行) {
                出.push(节点下标);
            }
            match 此行.类 {
                行类::子程序 => {
                    let 段末行 = self.段末(行表, 行下标, 区间终点, 段末判据::段首);
                    出.push(self.建头带体(行表, 行下标, 段末行, 节点种类::子程序, true));
                    行下标 = 段末行;
                }
                行类::程序集 => {
                    let 段末行 = self.段末(行表, 行下标, 区间终点, 段末判据::程序集变量);
                    出.push(self.建头带体(行表, 行下标, 段末行, 节点种类::程序集, true));
                    行下标 = 段末行;
                }
                行类::数据类型 => {
                    let 段末行 = self.段末(行表, 行下标, 区间终点, 段末判据::成员);
                    出.push(self.建头带体(行表, 行下标, 段末行, 节点种类::数据类型声明, true));
                    行下标 = 段末行;
                }
                行类::块首 if self.深度 < 块深上限 => {
                    let 段末行 = self.块末(行表, 行下标, 区间终点);
                    出.push(self.建块(行表, 行下标, 段末行));
                    行下标 = 段末行;
                }
                行类::空行 => {
                    出.extend(self.尾叶(&此行));
                    行下标 += 1;
                }
                _ => {
                    // 行尾空白 / 注释 / 换行由本行节点自身认领（`语句.rs::建单行` 的区间到行字节止）
                    // —— 「最内层包含它的节点」正是本行节点（`语言面形状.md` §3.5）。
                    出.push(self.建单行(&此行));
                    行下标 += 1;
                }
            }
        }
        出
    }

    /// 段末：从 `头部+1` 起，第一条满足判据的行（或 `区间终点`）。
    pub(super) fn 段末(&self, 行表: &[源码行], 头部: usize, 区间终点: usize, 判据: 段末判据) -> usize {
        let mut 行下标 = 头部 + 1;
        while 行下标 < 区间终点 {
            let 该行类 = 行表[行下标].类;
            let 到 = match 判据 {
                段末判据::段首 => 该行类.是否段首(),
                段末判据::程序集变量 => 该行类 != 行类::程序集变量 && 该行类 != 行类::空行,
                段末判据::成员 => 该行类 != 行类::成员 && 该行类 != 行类::空行,
            };
            if 到 {
                return 行下标;
            }
            行下标 += 1;
        }
        区间终点
    }

    /// 头行 + 体：子程序 / 程序集 / 数据类型 共用（三者形状同构：头字段 → 头尾叶 → 体）。
    pub(super) fn 建头带体(
        &mut self,
        行表: &[源码行],
        头: usize,
        末: usize,
        种类: 节点种类,
        有体: bool,
    ) -> u32 {
        let 此行 = 行表[头];
        let 起 = 此行.关键字.map(|关键字对| 关键字对.0).unwrap_or(此行.内容起);
        let 止 = 行表.get(末).map(|行项| 行项.字节起).unwrap_or(self.全文长());
        let mut 子 = self.声明字段(&此行);
        子.extend(self.尾叶(&此行));
        if 有体 {
            self.深度 += 1;
            子.extend(self.建体(行表, 头 + 1, 末));
            self.深度 -= 1;
        }
        self.草稿.节点(种类, (起, 止), 子)
    }
}

/// 段末判据。
#[derive(Clone, Copy)]
pub(super) enum 段末判据 {
    /// 下一条段首行（子程序的体）。
    段首,
    /// 下一条非 `.程序集变量` 行（程序集的体）。
    程序集变量,
    /// 下一条非 `.成员` 行（数据类型的体）。
    成员,
}
