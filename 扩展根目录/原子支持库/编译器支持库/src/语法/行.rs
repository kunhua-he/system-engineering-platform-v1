//! 行 —— 切行 · 行类 · 行首关键字分类 · 段首判定。
//!
//! **为什么先切行**：本语言是行式的（`程序文本格式.md` §二：缩进 = 块嵌套深度，注释到行尾），
//! 语句/声明的边界在行首。先把记号表切成行，1102 的主体才只剩「行 → 节点」一件事。
//!
//! **行首关键字怎么认出来**：`记号种类::关键字` 只说「这是关键字」，**不说「是哪一个」**
//! （`记号定义.rs` 的待办 1：完整关键字集合未定，形状层故意不写死在枚举里）。
//! 所以本文件按**区间文本**比对一张关键字表。表按 UTF-8 写死 —— 与
//! `程序文本格式.md` §二「编码 = UTF-8」一致；GBK 原文（语料形态）认不出来，
//! 会落到 `行类::语句` 的兜底路径（实测事实，见返回说明）。

use crate::语言面::{记号流, 记号种类};

/// 一行的分类。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 行类 {
    /// `.版本 2` —— 源单元的段首。
    版本,
    支持库,
    /// `.程序集 名` —— 头部，后面跟若干 `.程序集变量`。
    程序集,
    程序集变量,
    全局变量,
    常量,
    Dll命令,
    /// `.数据类型 名` —— 头部，后面跟若干 `.成员`。
    数据类型,
    成员,
    /// `.子程序 …` —— 头部，后面跟 `.参数` / `.局部变量` / 语句 / 块。
    子程序,
    参数,
    局部变量,
    /// 块的开头：`.如果真` `.如果` `.计次循环首` `.判断开始` …
    块首,
    /// 块的分支：`.否则` `.判断` `.默认`。
    块中,
    /// 块的结尾：`.如果真结束` `.如果结束` `.计次循环尾` `.判断结束` …
    块尾,
    返回,
    置入代码,
    /// 普通语句行（赋值 / 裸调用）。
    语句,
    /// 只有空白与注释的行。
    空行,
}

impl 行类 {
    /// 是否**段首行**：一出现就终结上一段（子程序体 / 数据类型体）。
    ///
    /// `.参数` `.局部变量` `.成员` **不算**段首 —— 它们属于上一段的体。
    pub(crate) fn 是否段首(&self) -> bool {
        use 行类::*;
        matches!(
            self,
            版本 | 支持库 | 程序集 | 程序集变量 | 全局变量 | 常量 | Dll命令 | 数据类型 | 子程序
        )
    }
}

/// 行首关键字表：**文本 → 行类**。
///
/// 表 = `说明/真文本覆盖.md` §二 实测的 **23 种带点 + 2 种不带点**，
/// 另加 8 种**语料 0 例**的循环关键字（`.循环判断首` 等，按 `语言面形状.md` 待办 2 的名单
/// 收进：收进来只是「配对得上」，**不构成实测证据**）。
///
/// 用 `&str` 而不是 `b"…"`：Rust 的字节串字面量不许非 ASCII（实测撞到 E0748）。
const 关键字表: &[(&str, 行类)] = &[
    (".版本", 行类::版本),
    (".支持库", 行类::支持库),
    (".程序集", 行类::程序集),
    (".程序集变量", 行类::程序集变量),
    (".全局变量", 行类::全局变量),
    (".常量", 行类::常量),
    (".DLL命令", 行类::Dll命令),
    (".数据类型", 行类::数据类型),
    (".成员", 行类::成员),
    (".子程序", 行类::子程序),
    (".参数", 行类::参数),
    (".局部变量", 行类::局部变量),
    (".如果真", 行类::块首),
    (".如果", 行类::块首),
    (".计次循环首", 行类::块首),
    (".判断开始", 行类::块首),
    (".循环判断首", 行类::块首),
    (".变量循环首", 行类::块首),
    (".判断循环首", 行类::块首),
    (".否则", 行类::块中),
    (".判断", 行类::块中),
    (".默认", 行类::块中),
    (".如果真结束", 行类::块尾),
    (".如果结束", 行类::块尾),
    (".计次循环尾", 行类::块尾),
    (".判断结束", 行类::块尾),
    (".循环判断尾", 行类::块尾),
    (".变量循环尾", 行类::块尾),
    (".判断循环尾", 行类::块尾),
    ("返回", 行类::返回),
    ("置入代码", 行类::置入代码),
];

/// 按行首关键字**文本**定行类。
pub(crate) fn 行类自关键字(文: &[u8]) -> Option<行类> {
    关键字表
        .iter()
        .find(|(名, _)| 名.as_bytes() == 文)
        .map(|(_, 类)| *类)
}

/// 一行的读数。区间一律是**字节**区间。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 行 {
    /// 本行在记号表里的下标区间 `[记号起, 记号止)`（含缩进空白与行尾换行）。
    pub 记号起: usize,
    pub 记号止: usize,
    /// 本行的原文字节区间 `[字节起, 字节止)`；`字节止` 含行尾换行。
    pub 字节起: u32,
    pub 字节止: u32,
    /// 缩进空白止 = 首个非 `空白` 记号的起。缩进区间 = `[字节起, 缩进止)`。
    pub 缩进止: u32,
    /// 内容起 = 首个内容记号（跳过空白 / 注释 / 换行 / 文件结束）的起；
    /// 空行（只有空白与注释）时 `内容起 == 字节止`。
    pub 内容起: u32,
    /// 内容在记号表里的下标区间 `[内容记号起, 内容记号止)`。
    pub 内容记号起: usize,
    pub 内容记号止: usize,
    pub 类: 行类,
    /// 行首关键字的字节区间（**含点**）；无关键字时 `None`。
    pub 关键字: Option<(u32, u32)>,
}

fn 切一片(流: &记号流, 记号起: usize, 记号止: usize) -> 行 {
    let 表 = &流.记号表;
    let 字节起 = 表[记号起].起;
    let 字节止 = 表[记号止 - 1].止;

    // 缩进止：首个非 `空白` 记号。
    let mut 缩进止 = 字节止;
    let mut 首 = 记号止;
    for (片内位次, 本记号) in 表[记号起..记号止].iter().enumerate() {
        if 本记号.种类 != 记号种类::空白 {
            缩进止 = 本记号.起;
            首 = 记号起 + 片内位次;
            break;
        }
    }

    // 内容记号区间：跳过 `空白` / `注释` / `换行` / `文件结束`。
    let 是否内容 = |记号种: 记号种类| {
        !matches!(
            记号种,
            记号种类::空白 | 记号种类::注释 | 记号种类::换行 | 记号种类::文件结束
        )
    };
    let mut 内容记号起 = 记号止;
    let mut 内容记号止 = 记号起;
    for (片内位次, 本记号) in 表[记号起..记号止].iter().enumerate() {
        if 是否内容(本记号.种类) {
            if 内容记号起 == 记号止 {
                内容记号起 = 记号起 + 片内位次;
            }
            内容记号止 = 记号起 + 片内位次 + 1;
        }
    }
    let 内容起 = if 内容记号起 == 记号止 {
        字节止
    } else {
        表[内容记号起].起
    };

    // 行首关键字：首个非空白记号是 `关键字` 才算。
    let mut 类 = 行类::空行;
    let mut 关键字 = None;
    if 首 < 记号止 && 表[首].种类 == 记号种类::关键字 {
        let 文 = &流.原文[表[首].起 as usize..表[首].止 as usize];
        类 = 行类自关键字(文).unwrap_or(行类::语句);
        关键字 = Some((表[首].起, 表[首].止));
    } else if 内容记号起 != 记号止 {
        // 有内容但行首不是关键字 ⇒ 普通语句行（赋值 / 裸调用）。
        类 = 行类::语句;
    }

    行 {
        记号起,
        记号止,
        字节起,
        字节止,
        缩进止,
        内容起,
        内容记号起,
        内容记号止,
        类,
        关键字,
    }
}

/// 切行：一行 = 到一枚 `换行` 为止（含它）；末尾零宽的 `文件结束` 并入最后一行。
///
/// 空文件（记号表只有一枚零宽 `文件结束`）得到**一行零宽的空行**，
/// 于是「空文件也有一棵树」与「末记号止 == 全文长」两条判据同时成立。
pub(crate) fn 切行(流: &记号流) -> Vec<行> {
    let 表 = &流.记号表;
    let mut 出: Vec<行> = Vec::new();
    let mut 起 = 0usize;
    let mut 记号位次 = 0usize;
    while 记号位次 < 表.len() {
        match 表[记号位次].种类 {
            记号种类::换行 => {
                出.push(切一片(流, 起, 记号位次 + 1));
                起 = 记号位次 + 1;
            }
            记号种类::文件结束 => {
                if 起 < 记号位次 {
                    出.push(切一片(流, 起, 记号位次 + 1));
                } else if let Some(末) = 出.last_mut() {
                    // 零宽的文件结束并入上一行：字节区间不变（两者都止于全文长）。
                    末.记号止 = 记号位次 + 1;
                } else {
                    出.push(切一片(流, 记号位次, 记号位次 + 1));
                }
                起 = 记号位次 + 1;
            }
            _ => {}
        }
        记号位次 += 1;
    }
    if 起 < 表.len() {
        出.push(切一片(流, 起, 表.len()));
    }
    出
}
