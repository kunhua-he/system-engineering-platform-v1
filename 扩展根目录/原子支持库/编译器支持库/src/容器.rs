//! 容器 —— 产物形状。**冻结项**：段头与段类型号改动必须走 `契约声明/冻结登记.json`。
//!
//! 1:1 复刻的验收判据是**往返一致**：反解 → 生成，产物必须与原文逐字节相同。
//! 所以本模块的两个方向必须由同一份格式知识驱动，不许各写一套。
//!
//! # 实测口径
//!
//! 取证语料：`/tmp/易语言源码` 下全部 1444 个容器文件（大小写不敏感地取 `.e`/`.ec`），
//! 共切出 15555 条段记录。下表偏移均**相对段头起点**（段头起点 = 上一条段数据之后）：
//!
//! | 偏移 | 宽度 | 取值 | 语料实测 |
//! |---|---|---|---|
//! | 0x00 | u16 | 0x7319（字节序 `19 73`） | 15555/15555 命中 |
//! | 0x02 | u16 | 0x1511（字节序 `11 15`） | 15555/15555 命中 |
//! | 0x04 | u32 | 段校验值 | 算法未证实，本模块**原样搬运**，不重算 |
//! | 0x08 | u16 + u8 + u8 | `19 73` `00` 段类型号 | 15555/15555 命中 |
//! | 0x0C | 27 | 名称区（异或混淆） | 见下 |
//! | 0x27 | u16 + u8 | `19 73` `00` | 非类型 7 全部命中 |
//! | 0x2A | u8 | 段头尾标志 | 类型 255 取 0x03，其余取 0x00 |
//! | 0x2B | u8 | 恒 0x00 | 15555/15555 命中 |
//!
//! ## 名称区
//!
//! 非类型 7：`明文 = 段名 GBK 字节 + NUL + 补零至 27`，`密文 = 明文 ⊕ 密钥`，
//! 密钥 `73 00 <段类型> 19` 四字节循环，相位锚在段头起点。
//! 名称区起点 0x0C 是 4 的倍数，故第 i 字节用的密钥相位就是 `(0x0C + i) % 4`。
//! 15 个类型解出的段名与 `e.exe` 偏移 0x261724 起的段名表逐字相同
//! （含 `编辑信息段2` · `辅助信息段1` · `辅助信息段2` · `易模块记录段2` · `程序加固段`）。
//!
//! ## 段边界
//!
//! **容器内没有段长字段**：44 字节段头内 9 个字段位无一承载段数据长度，段数据前部也没有；
//! 对 2974 条段记录在段头全偏移与段数据前 64 字节全偏移上搜 `u32`/`u16` 等于段数据长度的
//! 字段，除字节巧合外零命中。故段数据长度只能由**下一处段头起点减本处段头起点再减 44**
//! 推出，末段数据直抵文件尾。本模块用与 `解析段头` 同一套判据向后扫描定位下一段头。
//!
//! # 与取证件（旧仓 `工程缓存/易语言架构/架构调研/｜-易程序容器格式.md`）冲突、以实测为准的三处
//!
//! 1. **取证件把 0x2A 这一个字节算了两次**。取证件 §二 称「偏移 0x27 段头结束标记 = `19 73 00 00`」
//!    且「偏移 0x2A 段头尾标志 = u8」。`0x27 + 4 = 0x2B`，与 0x2A 的尾标志重叠，两者不可能同时成立。
//!    实测：0x27..0x2A 是 `19 73 00` **加**尾标志字节（0x2A），0x2B 是补零。
//! 2. **类型 7 也是「段头结束标记」的例外，取证件只列了类型 255**。取证件称该标记 1437 条命中、
//!    例外仅类型 255 的 7 条；实测类型 7 的 0x27..0x2B 五字节**全零**（`00 00 00 00 00`），
//!    与取证件自身写的「类型 7 段头偏移 0x0C 至 0x2B 共 32 字节全零」相矛盾。以实测为准：
//!    类型 7 的 0x0C..0x2C 共 32 字节恒全零（1456/1456 条），不写名称区、不写结束标记。
//! 3. **类型 7 的名称区全零不是「空段名的异或结果」**。空段名异或密钥会得到密钥本身
//!    （`73 00 07 19` 循环），而实测原始字节是 27 个 `00`。所以「名称区全零」是类型 7 的
//!    独立盘面特征，反解与生成都必须对它特判，不能靠通用的「空串 + 异或」推出来。
//!
//! # 一处无法闭合的冻结接口
//!
//! `反解错误::段数据越界` 在本格式上**不可达**：段数据长度由扫描推出，恒被文件尾截断，
//! 不存在「长度超出文件尾」的输入。该变体保留以维持冻结接口，本模块不构造它。
//! 反过来，合法输入上 `反解` 成功 **必然**保证 `生成` 逐字节复现（段头判据已含结束标记与尾标志，
//! 任何不能被逐字节写回的段头都会被 `段头标记不符` 挡在反解阶段）。

