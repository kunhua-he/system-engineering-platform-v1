/// 段类型号。**只增不复用**：删掉的类型号作废不回收。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum 段类型 {
    用户信息 = 1,
    系统信息 = 2,
    程序 = 3,
    程序资源 = 4,
    可丢失程序 = 5,
    编辑信息 = 6,
    无名七 = 7,
    初始模块 = 8,
    编辑信息二 = 9,
    辅助信息一 = 10,
    辅助信息二 = 11,
    易模块记录 = 12,
    易包信息一 = 13,
    编辑过滤器信息 = 14,
    易模块记录二 = 15,
    程序加固 = 255,
}

impl 段类型 {
    pub fn 自号(号: u8) -> Option<Self> {
        use 段类型::*;
        Some(match 号 {
            1 => 用户信息, 2 => 系统信息, 3 => 程序, 4 => 程序资源, 5 => 可丢失程序,
            6 => 编辑信息, 7 => 无名七, 8 => 初始模块, 9 => 编辑信息二, 10 => 辅助信息一,
            11 => 辅助信息二, 12 => 易模块记录, 13 => 易包信息一, 14 => 编辑过滤器信息,
            15 => 易模块记录二, 255 => 程序加固,
            _ => return None,
        })
    }
    pub fn 号(&self) -> u8 { *self as u8 }
}

/// 段头（44 字节，逐字段对齐原文）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 段头 {
    pub 校验和: u32,
    pub 段类型: u8,
    /// 27 字节名称区。**原文里是异或混淆的**，反解要还原、生成要重新混淆。
    pub 名称区: [u8; 27],
    /// 名称区的**明文**（由名称区解出；生成时按段类型重新混淆）。
    pub 段名: Vec<u8>,
}

/// 一个段：段头 + 数据。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 段 {
    pub 头: 段头,
    pub 数据: Vec<u8>,
}

/// 容器：魔数 + 段序列，连续到文件尾。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 容器 {
    pub 段表: Vec<段>,
}

