//! 语法 —— **1102 语法分析**：把记号流建成语法树。零实现，只做 `mod` + `pub use`。
//!
//! # 公开面
//!
//! ```text
//! 建树(&记号流) -> Result<语法树, 形状错误>
//! ```
//!
//! 就这一个入口。1101（词法）的产物是 [`语言面::记号流`]，1102 的产物是
//! [`语言面::语法树`] —— 两头的类型都是 `语言面` 既有形状，本模块**不另造类型**。
//!
//! # 分件
//!
//! | 件 | 管什么 |
//! |---|---|
//! | `源码行表` | 记号表 → 行表；行类；行首关键字分类（UTF-8 文本比对） |
//! | `表达式` | 表达式层（号 41–50）：括号 / 成员 / 下标 / 调用 / 解二元表达式 / 空实参 |
//! | `建树` | 顶层（程序 / 源单元）、体、段边界、头带体；入口 `建树` |
//! | `语句` | 单行节点（声明 / 赋值 / 调用 / 返回 / 置入代码）与块节点 |
//! | `草稿树` | 临时树 → 先序节点表（`扁平化草稿`） |
//!
//! # 三条要读的判据（都写在分件头部，这里只给结论）
//!
//! 1. **`子区间` 是先序子树区间**：`[子起, 子止)` 里夹着的是那些直接子节点的**后代**，
//!    所以「怎么走直接子节点」只有一处 —— `语法树::直接子`（按 `子树止` 跳）。
//!    于是**每个子节点都能带自身的整棵子树**，一个体里的多条语句互不挤占。
//!    所以草稿树先自由搭，扁平化时按先序铺表（`草稿.rs` 头部）。
//!    （旧读法把区间里每个下标都当直接子 ⇒ 只有末子能带子树；那是读法之误，已修 ——
//!    见 `项目文档/决策记录/2026-09-27_三条裁决_按稳定性判.md` 裁决 一。）
//! 2. **行首关键字按 UTF-8 比对**（`程序文本格式.md` §二 定的编码）。
//!    GBK 原文里关键字认不出来 ⇒ 落到「普通语句行」的兜底路径，**树仍合法**。
//! 3. **任何输入都不 panic**：解不出的记号串包成 `标识符引用` 叶（33 种里没有「未知」类）。

