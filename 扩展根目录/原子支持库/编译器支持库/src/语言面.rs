//! 语言面 —— 记号与语法树。**形状已冻结**（本次冻结；改动须走 `契约声明/冻结登记.json`）。
//!
//! 冻结它之前不派活：记号与语法树是所有下游模块共用的脊梁，改了全体返工
//! （见 `项目文档/设计文档/内核落点.md` 第六节「接口先冻结，再派活」）。
//! 逐条判据与待办见 `说明/语言面形状.md`。
//!
//! # 本模块只有形状，没有算法
//!
//! 这里只有四样东西：**类型定义 · 不变量 · 构造函数 · 不变量校验**。
//! **没有任何词法分析、语法分析、语义分析或生成算法** —— 那些分别是
//! 1101 / 1102 / 1103 / 1104 的实现，各派一路活。
//!
//! 唯一一处「动手」是 [`记号流::还原`]：它是「区间首尾相接且覆盖全文」这条不变量的
//! **见证函数**，只做逐区间拼接，不含任何词法判断（不分类、不合并、不跳字节）。
//! 把它放在这里，是为了让「逐字节还原」这条硬判据**当场可断言**，
//! 而不是等 1101 写完才知道形状够不够。
//!
//! # 为什么区间是「字节」而不是「字符」，为什么原文是 `Vec<u8>` 而不是 `String`
//!
//! 语料实测（`/tmp/易语言源码/`，只读）：容器内嵌的源文本是 **GBK 字节**。
//! 例：`samples/e8/ManyFiles/e8test3.txt` 146 字节，首行 `.版本 2` 的 `.版本`
//! 是 `2E B0 E6 B1 BE`；`lib/eTools/backup/抖音解析2/抖音解析2_2023-09-14 08.17.20.e`
//! 偏移 `0x26DC5` 起有 7880 字节源文本。
//! **GBK 字节序列不保证是合法 UTF-8，装不进 Rust 的 `String`。**
//! 所以 `记号流::原文` 的类型是 `Vec<u8>`，所有区间都是**字节区间**。
//! 形状与编码无关：换成 UTF-8 语料，本模块一字不改。
//!
//! # 区间宽度
//!
//! 区间用 `u32`，即**单份源文本上限 4 GiB 字节**。语料实测最大源文本 186 581 字节
//! （`samples/易向导/API助手/API助手.e` 内嵌），余量充足。若将来出现超过 4 GiB 的
//! 源文本，区间必须整体加宽 —— 这是一次**破坏性改形状**，须走冻结登记。

