//! 名号表 —— 三张入参表（命令表 / 常量表 / 类型表）的**边界编码**与查询。
//!
//! # 为什么这里要定一个编码
//!
//! `能力声明/1103.json` 的参数表第 1–3 行是**字节集**（类型标签 5），说明写着
//! 「载荷＝本库的名号表边界编码（形状未冻）」。跨边界只有定长数据槽 ⇒ 三张表过边界
//! 必须先编成字节集，**不许无形状就接**（`说明/使用说明.md` 的同一条规矩）。
//!
//! 本件定的就是那条边界编码，与 `结构编码` / `原生路编码` **同一条规矩**：
//! 只搬字段、不含业务知识；三张表结构同构，故**只有这一处**编解码，不按表各写一套。
//!
//! # 载荷形状（小端）
//!
//! ```text
//! 名号表：u32 项数 · 每项 ( u32 名长 + 名字节 · u16 号 )
//! ```
//!
//! 名字是**原始字节**（不做编码假设：GBK 与 UTF-8 都装得下），比对照**原字节**
//! （`说明/语言面形状.md` §六待办 6）。空字节集 = **空表**（0 项，不是非法）——
//! 调用方没有这一类表时传空槽即可；空表下任何引用都落到 `名字未声明`（fail-closed）。
//!
//! # 与 `声明记录区实测.md` 的关系（如实划界）
//!
//! 三张表的号**不是** `.e` 声明记录区里那些 4 字节令牌的号 —— 令牌的字段语义是**不判项**
//! （该文 §七 第 1 条），本件一个字节都不替它编。这里定的只是**本库过边界用的**编码。

use crate::顺序读器::顺序读器;

/// 一张「名字 → 号」的表。项数 ≤ `u32`，号 ≤ `u16`（见 `形状.rs` 的号宽口径）。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 名号表 {
    名号项: Vec<(Vec<u8>, u16)>,
}

impl 名号表 {
    pub fn 空实例() -> Self {
        Self { 名号项: Vec::new() }
    }

    /// 直接给项（库内与测试构造用；顺序即盘面顺序，**不排序、不去重**）。
    pub fn 从项(项表: Vec<(Vec<u8>, u16)>) -> Self {
        Self { 名号项: 项表 }
    }

    pub fn 表项数(&self) -> usize {
        self.名号项.len()
    }

    pub fn 取项表(&self) -> &[(Vec<u8>, u16)] {
        &self.名号项
    }

    /// 按名字（**原始字节**）找号。同名取**先出现的那一项**。
    pub fn 按名取号(&self, 名称: &[u8]) -> Option<u16> {
        self.名号项
            .iter()
            .find(|(表名, _)| 表名.as_slice() == 名称)
            .map(|(_, 号值)| *号值)
    }

    /// 逐项编成字节集（本件是唯一的编码处）。
    pub fn 编码(&self) -> Vec<u8> {
        let mut 输出缓冲 = Vec::new();
        输出缓冲.extend_from_slice(&(self.名号项.len() as u32).to_le_bytes());
        for (名称, 号值) in &self.名号项 {
            输出缓冲.extend_from_slice(&(名称.len() as u32).to_le_bytes());
            输出缓冲.extend_from_slice(名称);
            输出缓冲.extend_from_slice(&号值.to_le_bytes());
        }
        输出缓冲
    }

    /// 字节集 → 表。`None` = 编码非法（截断 / 尾部有多余字节 / 项数或名长越界）。
    ///
    /// **空字节集 = 空表**（见文件头）；非空字节集必须**正好**解完，不许「尽力而为」。
    pub fn 解码(字节: &[u8]) -> Option<Self> {
        if 字节.is_empty() {
            return Some(Self::空实例());
        }
        let mut 读游标 = 顺序读器 { 字节, 游标位: 0 };
        let 表项数 = 读游标.读四字节()? as usize;
        // 每项至少 4 字节名长 + 2 字节号 = 6 字节 ⇒ 项数不可能超过 字节.len()/6。
        // 先卡这一条，免得下面 `Vec::with_capacity` 被一个伪造的大项数撑爆内存。
        if 表项数 > 字节.len() / 6 {
            return None;
        }
        let mut 项表 = Vec::with_capacity(表项数);
        for _ in 0..表项数 {
            let 名长 = 读游标.读四字节()? as usize;
            let 名称 = 读游标.取字节(名长)?.to_vec();
            let 号值 = 读游标.读双字节()?;
            项表.push((名称, 号值));
        }
        // 尾部有多余字节 ⇒ 非法（不许静默忽略）。
        if 读游标.游标位 != 字节.len() {
            return None;
        }
        Some(Self { 名号项: 项表 })
    }
}
