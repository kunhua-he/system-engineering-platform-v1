//! 建表 —— **1103 语义分析的本体**：语法树 → 带号结构（名 → 号表 + 引用表）。
//!
//! # 它做什么（三步）
//!
//! 1. **建作用域**：走树时按节点开层 —— `程序集`(4) 开程序集层 · `子程序`(8) 开局部层 ·
//!    `数据类型声明`(10) 开数据成员层；全局层恒在。
//! 2. **定号**：给声明定出**程序内全局 16 位序号**（取证：号是程序内全局序号），
//!    并把 `名字 → 号` 记进 1103 **自带**的那张表（取证：名与号在盘面不邻接）。
//! 3. **解析引用**：按裁定（`程序文本格式.md` §二）把引用解成号 ——
//!    变量 / 子程序按 **局部 > 程序集 > 全局** 取最近的；常量查程序常量再查常量表；
//!    命令名查命令表；类型名查程序类型再查类型表。解不出即 `1136 名字未声明`。
//!
//! # 声明的名字与类型从哪来（**一条实测事实，必须读**）
//! 1102 的树里，**所有**声明节点（`src/语法/建树.rs::建头带体` 与 `src/语法/语句.rs::建单行`）
//! 的头字段**都是子节点**（`声明字段` 铺的表达式）⇒ **子 0 = 名字、子 ≥1 里的标识符 = 类型候选**。
//!
//! | 形态 | 哪些 | 头字段在树里长什么样 |
//! |---|---|---|
//! | **头带体** | `程序集`(4) · `子程序`(8) · `数据类型声明`(10) | 子 0 = 名字、子 ≥1 里的标识符 = 类型候选（之后是头尾叶与体） |
//! | **单行** | `支持库声明`(3) · `程序集变量声明`(5) · `全局变量声明`(6) · `局部变量声明`(7) · `参数声明`(9) · `数据成员声明`(11) · `DLL命令声明`(12) · `常量声明`(13) | 同上（之后是头尾叶）；**只有一条取值路径** |
//!
//! ⇒ 本件对声明一律**读子节点**，不再有「节点原文区间内扫记号」那条路
//! （裁决 `项目文档/决策记录/2026-09-27_语言主线三缺口裁决.md` §二①：同一件事不许两套取值）。
//! 空字段会被 `表达式` 丢掉 ⇒ 子节点序号 ≠ 字段序号，位置判不准（见下「不判清单」）。
//! # 程序集与子程序在树里**是兄弟**（**第二条实测事实**）
//!
//! `建树.rs::建体` 对 `程序集` 用的段末判据是「下一条非 `.程序集变量` 行」⇒
//! **`子程序` 是 `程序集` 的兄弟，不是子节点**。这是**显式口径**，不是缺口：
//! 易语言文本里 `.程序集` 行与 `.子程序` 行**缩进相同、各占一行**，文本里不存在一层包含关系，
//! 改成父子就是发明一层文本里没有的结构（裁决 §二②）。
//!
//! **子程序归属程序集，靠「它之前最近的那条 `.程序集` 兄弟节点」判，不靠父子包含。**
//! 同一份口径写在 `说明/语言面形状.md` §3.1；**不许**把它「修」成父子。
//!
//! 本件的读法：**程序集层一直挂到本 `源单元` / `程序` 体结束才弹**（不是 `程序集` 节点一结束就弹）
//! —— 这样同一声明表里的 `子程序` 才看得到 `程序集变量`，裁定「局部 > 程序集 > 全局」才有意义。
//! 跨 `源单元` 的关联不做（程序集头在一个源单元、子程序在另一个源单元时看不到，如实登记）。
//!
//! # 不判清单（**如实登记，不发明**）
//!
//! | 不判的东西 | 为什么 |
//! |---|---|
//! | **资源**（`号类::资源`） | 语言面 33 种节点里没有「资源声明」；三张入参表里也没有资源表 ⇒ 无从定号 |
//! | **成员名**（`成员访问` 第 2 个及之后的标识符子） | 没有成员表可查；解不出也不该报「名字未声明」 |
//! | **声明头里除名字与类型之外的字段**（公开位 / 参考位 / 备注 / 数组维度…） | 修饰位与自由文本，不是可解析的名字 |
//!
//! **类型名解析是「尽力而为」**（找到就记，找不到**不报错**）：空字段会被 `表达式` 丢掉
//! ⇒ 子节点序号 ≠ 字段序号，位置判不准；且程序自身声明的 `数据类型` 会遮蔽注册表里的同名类型。
//! 找不到时报错会误伤修饰位与程序内类型 ⇒ **不判**（与「空集是未判不是通过」同源）。
//!
//! **程序集身份不单独定号**：裁定表五个类里没有「程序集」；`子程序` 的作用域记的是
//! 「它在程序集层里」，但具体是哪一个程序集没有号（形状里没有承载它的类）。

use super::注册表;
use super::形状::{号来源, 号类, 引用项, 作用域, 带号结构, 语义错误, 号项, 是声明类};
use crate::语言面::{节点种类, 语法树};

/// 走树时每个节点的角色 —— 只有叶子（`标识符引用` / `常量引用`）读它。
#[derive(Clone, Copy, PartialEq, Eq)]
enum 角色 {
    /// 值位置：要解析成号。
    值位置,
    /// 不判：声明名 / 类型候选（父节点已处理）/ 成员名 / 修饰位。
    不判,
}

/// 一层作用域。
struct 作用域层 {
    作用域: 作用域,
    名表: Vec<(Vec<u8>, 号类, u16)>,
}

/// 工作项。
enum 工作项 {
    跑一遍 { 下标: u32, 角色: 角色 },
    /// 把层栈弹回到某个深度（子树走完了）。
    出到 { 深: usize },
}

/// **1103 语义分析**：吃一棵语法树与三张注册表，交一份带号结构。
///
/// 失败即**第一条**解不出的名字（结构化 `1136`），不 panic、不返回字符串。
pub fn 分析(
    语法树: &语法树,
    命令表: &注册表,
    常量表: &注册表,
    类型表: &注册表,
) -> Result<带号结构, 语义错误> {
    let mut 语义分析器 = 分析器 {
        树: 语法树,
        层: vec![作用域层 { 作用域: 作用域::全局, 名表: Vec::new() }],
        层栈: vec![0],
        号表: Vec::new(),
        引用表: Vec::new(),
        下一个号: 1,
        命令表,
        常量表,
        类型表,
    };
    语义分析器.跑一遍()?;
    Ok(带号结构 { 号表: 语义分析器.号表, 引用表: 语义分析器.引用表 })
}

struct 分析器<'a> {
    树: &'a 语法树,
    层: Vec<作用域层>,
    层栈: Vec<usize>,
    号表: Vec<号项>,
    引用表: Vec<引用项>,
    下一个号: u32,
    命令表: &'a 注册表,
    常量表: &'a 注册表,
    类型表: &'a 注册表,
}

impl 分析器<'_> {
    fn 种类(&self, 下标: u32) -> 节点种类 {
        self.树.节点表[下标 as usize].种类
    }

    fn 取子节点(&self, 下标: u32) -> Vec<u32> {
        self.树.直接子(下标).collect()
    }

    fn 字节(&self, 下标: u32) -> &[u8] {
        self.树.原文切片(下标).unwrap_or(&[])
    }

    // ── 定号与建表 ────────────────────────────────────────────────────────────

    /// 给一个声明定号，并记进 1103 自带的「名 → 号」表。
    fn 登记(&mut self, 类别: 号类, 名称: Vec<u8>, 目标: 作用域) -> Result<u16, 语义错误> {
        if self.下一个号 > u16::MAX as u32 {
            return Err(语义错误::号溢出 { 序: self.下一个号 });
        }
        let 号值 = self.下一个号 as u16;
        self.下一个号 += 1;
        self.号表.push(号项 { 类: 类别, 作用域: 目标, 号: 号值, 名: 名称.clone() });
        let 层号 = self.目标层(目标);
        self.层[层号].名表.push((名称, 类别, 号值));
        Ok(号值)
    }

    /// 目标层：从栈顶（最内）往下找第一个同类型的层；没有就全局层（下标 0）。
    fn 目标层(&self, 目标: 作用域) -> usize {
        self.层栈
            .iter()
            .rev()
            .copied()
            .find(|&层下标| self.层[层下标].作用域 == 目标)
            .unwrap_or(0)
    }

    /// 变量 / 子程序：按 **局部 > 程序集 > 全局** 取最近的（层栈由内向外扫）。
    fn 解析变量或子程序(&self, 名称: &[u8]) -> Option<(号类, 作用域, u16)> {
        for &层号 in self.层栈.iter().rev() {
            let 层级 = &self.层[层号];
            if !层级.作用域.参与名字解析() {
                continue;
            }
            for (表名, 类别, 号值) in &层级.名表 {
                if 表名.as_slice() == 名称 && matches!(类别, 号类::变量 | 号类::子程序) {
                    return Some((*类别, 层级.作用域, *号值));
                }
            }
        }
        None
    }

    /// 常量：先程序内常量（全局层），再常量表。
    fn 解析常量(&self, 名称: &[u8]) -> Option<(号来源, 作用域, u16)> {
        for (表名, 类别, 号值) in &self.层[0].名表 {
            if 表名.as_slice() == 名称 && *类别 == 号类::常量 {
                return Some((号来源::程序, 作用域::全局, *号值));
            }
        }
        self.常量表.按名取号(名称).map(|号值| (号来源::常量表, 作用域::平台, 号值))
    }

    /// 类型：先程序内类型（全局层），再类型表。找不到给 `None`（**不报错**，见文件头）。
    fn 解析类型名(&self, 名称: &[u8]) -> Option<(号来源, 作用域, u16)> {
        for (表名, 类别, 号值) in &self.层[0].名表 {
            if 表名.as_slice() == 名称 && *类别 == 号类::类型 {
                return Some((号来源::程序, 作用域::全局, *号值));
            }
        }
        self.类型表.按名取号(名称).map(|号值| (号来源::类型表, 作用域::平台, 号值))
    }

    // ── 解析引用 ──────────────────────────────────────────────────────────────

    fn 解析标识符(&mut self, 节点: u32) -> Result<(), 语义错误> {
        let 名称 = self.字节(节点).to_vec();
        if let Some((类, 作用域, 号)) = self.解析变量或子程序(&名称) {
            self.引用表.push(引用项 { 节点, 类, 来源: 号来源::程序, 号, 作用域 });
        } else if let Some(号值) = self.命令表.按名取号(&名称) {
            self.引用表
                .push(引用项 { 节点, 类: 号类::能力, 来源: 号来源::命令表, 号: 号值, 作用域: 作用域::平台 });
        } else {
            return Err(语义错误::名字未声明 { 名: 名称, 节点 });
        }
        Ok(())
    }

    fn 解析常量引用(&mut self, 节点: u32) -> Result<(), 语义错误> {
        let 原文 = self.字节(节点).to_vec();
        // `#名字` ⇒ 查表用去掉 `#` 的名字（注册表存的是名字，不带引导符）。
        let 名称 = match 原文.first() {
            Some(b'#') => 原文[1..].to_vec(),
            _ => 原文.clone(),
        };
        if let Some((来源, 作用域, 号)) = self.解析常量(&名称) {
            self.引用表.push(引用项 { 节点, 类: 号类::常量, 来源, 号, 作用域 });
            Ok(())
        } else {
            Err(语义错误::名字未声明 { 名: 原文, 节点 })
        }
    }

    /// 声明头里的类型候选：**尽力而为**，找到记一条，找不到不报错（见文件头）。
    /// `节点` = 该类型名自身的节点（声明头字段一律是子节点，故候选有独立节点）。
    fn 记类型候选(&mut self, 节点: u32, 名称: &[u8]) {
        if 名称.is_empty() {
            return;
        }
        if let Some((来源, 作用域, 号)) = self.解析类型名(名称) {
            self.引用表.push(引用项 { 节点, 类: 号类::类型, 来源, 号, 作用域 });
        }
    }

    // ── 走树 ──────────────────────────────────────────────────────────────────

    fn 跑一遍(&mut self) -> Result<(), 语义错误> {
        let mut 工作栈: Vec<工作项> = vec![工作项::跑一遍 { 下标: 0, 角色: 角色::不判 }];
        while let Some(一项) = 工作栈.pop() {
            let (下标, 角色) = match 一项 {
                工作项::出到 { 深 } => {
                    self.层栈.truncate(深);
                    continue;
                }
                工作项::跑一遍 { 下标, 角色 } => (下标, 角色),
            };
            let 节点种 = self.种类(下标);
            self.处理(下标, 节点种, 角色)?;

            // 开层。登记在开层之前做（声明名与头里的类型属外层作用域）。
            //
            // **程序集归属靠行序，不靠父子**（文件头第二条事实 + `说明/语言面形状.md` §3.1）：
            // 树里 `子程序` 是 `程序集` 的**兄弟**，所以「哪个子程序属于哪个程序集」由
            // **它之前最近的那条 `.程序集` 兄弟节点**唯一确定。本件据此让 `程序集` 层
            // 一直挂到本 `源单元` / `程序` 体结束才弹（不在这里安排弹出），
            // 于是它之后、下一条 `.程序集` 之前的所有 `子程序` 都落进这一层。
            // **不许**把 `程序集` 与 `子程序` 改成父子 —— 文本里两行平级，父子是发明结构。
            let 入栈前深 = self.层栈.len();
            let mut 安排出到 = false;
            match 节点种 {
                节点种类::程序集 => self.开层(作用域::程序集),
                节点种类::子程序 => {
                    self.开层(作用域::局部);
                    安排出到 = true;
                }
                节点种类::数据类型声明 => {
                    self.开层(作用域::数据成员);
                    安排出到 = true;
                }
                节点种类::源单元 | 节点种类::程序 => 安排出到 = true,
                _ => {}
            }
            if 安排出到 {
                工作栈.push(工作项::出到 { 深: 入栈前深 });
            }

            let 子节点表 = self.取子节点(下标);
            // 逆序入栈 ⇒ 出栈即先序。
            for (序号, &子下标) in 子节点表.iter().enumerate().rev() {
                let 子种 = self.种类(子下标);
                let 子角色 = 子角色(节点种, 序号, 子种);
                工作栈.push(工作项::跑一遍 { 下标: 子下标, 角色: 子角色 });
            }
        }
        Ok(())
    }

    fn 开层(&mut self, 层作用域: 作用域) {
        self.层.push(作用域层 { 作用域: 层作用域, 名表: Vec::new() });
        self.层栈.push(self.层.len() - 1);
    }

    fn 处理(&mut self, 下标: u32, 节点种: 节点种类, 角色: 角色) -> Result<(), 语义错误> {
        // 叶子：按角色解析（不判的直接跳过）。
        if 节点种 == 节点种类::标识符引用 {
            return if 角色 == 角色::值位置 { self.解析标识符(下标) } else { Ok(()) };
        }
        if 节点种 == 节点种类::常量引用 {
            return if 角色 == 角色::值位置 { self.解析常量引用(下标) } else { Ok(()) };
        }
        if !是声明类(节点种) {
            return Ok(());
        }
        // `支持库声明` 的名字属「资源」类，而资源当前不可达（文件头不判清单）⇒ 整条跳过，
        // 连类型候选都不记（`eAPI` 不是类型名）。
        if 节点种 == 节点种类::支持库声明 {
            return Ok(());
        }
        // 声明头字段一律是子节点（头带体与单行**同一条路**，文件头第一条事实）⇒
        // 子 0 = 名字、子 ≥1 里的标识符 = 类型候选。不再有「扫节点区间内记号」那条路。
        let 子节点表 = self.取子节点(下标);
        if let Some(&名子) = 子节点表.first()
            && self.种类(名子) == 节点种类::标识符引用
            && let Some((类, 目标)) = 声明角色(节点种)
        {
            let 名称 = self.字节(名子).to_vec();
            if !名称.is_empty() {
                self.登记(类, 名称, 目标)?;
            }
        }
        for &子下标 in 子节点表.iter().skip(1) {
            if self.种类(子下标) != 节点种类::标识符引用 {
                continue;
            }
            let 名称 = self.字节(子下标).to_vec();
            self.记类型候选(子下标, &名称);
        }
        Ok(())
    }
}

/// 一个声明节点定出什么类、落在哪个作用域。`None` = 这个声明类不参与定号。
fn 声明角色(节点种: 节点种类) -> Option<(号类, 作用域)> {
    use 节点种类::*;
    Some(match 节点种 {
        程序集变量声明 => (号类::变量, 作用域::程序集),
        全局变量声明 => (号类::变量, 作用域::全局),
        局部变量声明 => (号类::变量, 作用域::局部),
        参数声明 => (号类::变量, 作用域::局部),
        数据成员声明 => (号类::变量, 作用域::数据成员),
        子程序 => (号类::子程序, 作用域::程序集),
        常量声明 => (号类::常量, 作用域::全局),
        数据类型声明 => (号类::类型, 作用域::全局),
        // `支持库声明` 是「资源」的候选，但资源类当前不可达 ⇒ 不定号。
        // `程序集` 的名字也不定号（裁定表五个类里没有程序集）。
        _ => return None,
    })
}

/// 一个节点的第 `序号` 个直接子是什么角色。
fn 子角色(父角色: 节点种类, 序号: usize, 子种: 节点种类) -> 角色 {
    use 节点种类::*;
    if matches!(父角色, 程序集 | 子程序 | 数据类型声明) {
        // 头带体：头字段与尾叶是表达式 / 空白类（不判），体是语句 / 声明类（照走）。
        return if 是表达式种(子种) || matches!(子种, 空白 | 注释 | 换行) {
            角色::不判
        } else {
            角色::值位置
        };
    }
    if 是声明类(父角色) {
        // 单行声明：子都是头字段（名字 / 类型候选）与尾叶 ⇒ 不判。
        return 角色::不判;
    }
    if 父角色 == 成员访问 {
        // `obj.成员`：子 0 是基（值位置），其余标识符子是成员名（不判），实参是值位置。
        return if 序号 == 0 {
            角色::值位置
        } else if 子种 == 标识符引用 {
            角色::不判
        } else {
            角色::值位置
        };
    }
    角色::值位置
}

fn 是表达式种(节点种: 节点种类) -> bool {
    matches!(节点种.取号值(), 41..=50)
}
