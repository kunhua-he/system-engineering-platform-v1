/// **不判**：`成员访问` 的成员名不是可解析的名字 —— 不报错、不记引用。
#[test]
fn 分析_成员名不判且不报错() {
    let 文本 = ".版本 2\n.全局变量 窗口, 整数型\n.子程序 主, 整数型\n    返回 (窗口.宽度)\n";
    let 带号结构 = 分析只类型(文本, &[("整数型", 51)]).expect("成员名解不出也必须成功（不判）");
    // 基 `窗口` 解出来了（一条变量引用）；成员 `宽度` 没有引用项。
    assert!(带号结构.引用表.iter().any(|项| 项.类 == 号类::变量), "基该被解析");
    let 宽度 = 建语法树(文本).节点表.iter().enumerate().find(|(_, 节点)| 节点.种类 == crate::语言面::节点种类::成员访问).map(|(位次, _)| 位次 as u32);
    assert!(宽度.is_some(), "该有成员访问节点");
    assert!(带号结构.按节点找(宽度.expect("有")).is_none(), "成员名不该出现在引用表里");
}

/// **不判**：`资源` 类当前不可达（语言面没有资源声明节点、入参也没有资源表）——
