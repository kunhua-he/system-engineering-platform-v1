//! 语义层测试 —— 1103 语义分析（注册表边界编码 · 定号 · 遮蔽 · 引用解析 · 错误码）。
//!
//! 输入一律走**真链路**：`词法::切记号` → `语法::建树` → `语义::分析`（不手搭树）——
//! 这样测的是能力本身，而不是测试自身铺的形状。

use super::注册表;
use super::形状::{号来源, 号类, 作用域, 语义错误};
use super::{分析, 带号结构};
use crate::语言面::语法树;

fn 建语法树(文本: &str) -> 语法树 {
    let 输出流 = crate::词法::切记号(文本).expect("切分（本件只喂引号配对的合法文本）");
    crate::语法::建树(&输出流).expect("建树")
}

fn 造注册表(一项: &[(&str, u16)]) -> 注册表 {
    注册表::从项(一项.iter().map(|(名, 号)| (名.as_bytes().to_vec(), *号)).collect())
}

/// 只给类型表的常见调用（命令表 / 常量表留空）。
fn 分析只类型(文本: &str, 类型: &[(&str, u16)]) -> Result<带号结构, 语义错误> {
    分析(&建语法树(文本), &注册表::空实例(), &注册表::空实例(), &造注册表(类型))
}

// ── 注册表边界编码 ────────────────────────────────────────────────────────────

#[test]
fn 注册表_编码解码往返且非法一律检出() {
    // 空字节集 = 空表（不是非法）。
    assert_eq!(注册表::解码(&[]), Some(注册表::空实例()));

    let 原文 = 造注册表(&[("信息框", 42), ("取版本", 7)]);
    let 字节 = 原文.编码();
    let 解码结果 = 注册表::解码(&字节).expect("自造的编码必须解得出来");
    assert_eq!(解码结果, 原文, "编码 → 解码必须逐项相同");
    assert_eq!(解码结果.按名取号("信息框".as_bytes()), Some(42));
    assert_eq!(解码结果.按名取号("不存在".as_bytes()), None);

    // 截断（少一个字节）⇒ 非法。
    assert_eq!(注册表::解码(&字节[..字节.len() - 1]), None, "截断必须检出");
    // 尾部多一个字节 ⇒ 非法（不许「尽力而为」）。
    let mut 多尾字节 = 字节.clone();
    多尾字节.push(0);
    assert_eq!(注册表::解码(&多尾字节), None, "尾部多余字节必须检出");
    // 伪造一个巨大的项数 ⇒ 非法（且不许拿它去 with_capacity 撑内存）。
    assert_eq!(注册表::解码(&[0xFF, 0xFF, 0xFF, 0xFF, 0, 0]), None, "项数越界必须检出");
    // 名长越过尾部 ⇒ 非法。
    let mut 坏件表 = Vec::new();
    坏件表.extend_from_slice(&1u32.to_le_bytes());
    坏件表.extend_from_slice(&99u32.to_le_bytes());
    坏件表.extend_from_slice(b"x");
    坏件表.extend_from_slice(&0u16.to_le_bytes());
    assert_eq!(注册表::解码(&坏件表), None, "名长越界必须检出");
}

// ── 定号与名 → 号表 ───────────────────────────────────────────────────────────

/// 号是**程序内全局 16 位序号**：按声明出现的先序递增，从 1 起。
#[test]
fn 分析_号是程序内全局序号且先序递增() {
    let 文本 = ".版本 2\n.程序集 程序集1\n    .程序集变量 计数, 整数型\n.子程序 加一, 整数型\n    .参数 首参, 整数型\n    .局部变量 计数, 整数型\n    返回 (计数)\n";
    let 带号结构 = 分析只类型(文本, &[("整数型", 51)]).expect("该解析成功");

    let 名与号: Vec<(&[u8], 号类, 作用域, u16)> = 带号结构
        .号表
        .iter()
        .map(|项| (项.名.as_slice(), 项.类, 项.作用域, 项.号))
        .collect();
    assert_eq!(
        名与号,
        vec![
            ("计数".as_bytes(), 号类::变量, 作用域::程序集, 1),
            ("加一".as_bytes(), 号类::子程序, 作用域::程序集, 2),
            ("首参".as_bytes(), 号类::变量, 作用域::局部, 3),
            ("计数".as_bytes(), 号类::变量, 作用域::局部, 4),
        ],
        "号表该按先序递增、类与作用域逐条对上"
    );
    // 号从 1 起、连续（程序内全局序号）。
    let 号s: Vec<u16> = 带号结构.号表.iter().map(|项| 项.号).collect();
    assert_eq!(号s, vec![1, 2, 3, 4]);
}

/// 裁定：**局部 > 程序集 > 全局**（取最近的，且报出取了哪一个）。
/// 同名的 `计数` 既在程序集层又在局部层 ⇒ 引用必须取**局部**那个。
#[test]
fn 分析_遮蔽取最近的并报出取了哪一层() {
    let 文本 = ".版本 2\n.程序集 程序集1\n    .程序集变量 计数, 整数型\n.子程序 加一, 整数型\n    .局部变量 计数, 整数型\n    返回 (计数)\n";
    let 带号结构 = 分析只类型(文本, &[("整数型", 51)]).expect("该解析成功");

    let 局部计数 = 带号结构.按名找("计数".as_bytes()).expect("名表里有 计数");
    assert_eq!(局部计数.作用域, 作用域::程序集, "按名找取的是先登记的那一项（程序集层）");

    // 引用那一项必须落在**局部**层。
    let 引用条目 = 带号结构.引用表.iter().find(|项| 项.类 == 号类::变量 && 项.来源 == 号来源::程序).expect("返回里的 计数 该解析出一条引用");
    assert_eq!(引用条目.作用域, 作用域::局部, "遮蔽顺序 局部 > 程序集：必须取局部那个");
    assert_eq!(引用条目.号, 3, "局部那个的号（程序集 计数=1 · 加一=2 · 局部 计数=3）");
}

/// 未声明的名字 ⇒ `1136 名字未声明`（第一条），不是崩溃、不是静默。
#[test]
fn 分析_未声明名字报名字未声明() {
    let 文本 = ".版本 2\n.子程序 主, 整数型\n    返回 (不存在)\n";
    let 语法树 = 建语法树(文本);
    let 错误 = 分析只类型(文本, &[("整数型", 51)]).expect_err("解不出的名字必须报错");
    match 错误 {
        语义错误::名字未声明 { 名, 节点 } => {
            assert_eq!(名, "不存在".as_bytes().to_vec(), "报出的该是那个名字的原字节");
            assert!((节点 as usize) < 语法树.节点表.len(), "节点下标该指向树里的一个节点");
            assert_eq!(语法树.节点表[节点 as usize].种类, crate::语言面::节点种类::标识符引用);
        }
        其他 => panic!("该报名字未声明，实得 {其他:?}"),
    }
}

/// 常量引用：先查**程序内常量**，再查常量表。
#[test]
fn 分析_常量引用查程序常量与常量表() {
    // 程序内常量（`.常量 版本号`）遮蔽同名注册表项。
    let 文本 = ".版本 2\n.常量 版本号, \"1\"\n.子程序 取版本, 整数型\n    返回 (#版本号)\n";
    let 带号结构 = 分析(&建语法树(文本), &注册表::空实例(), &造注册表(&[("版本号", 9)]), &造注册表(&[("整数型", 51)]))
        .expect("该解析成功");
    let 引用条目 = 带号结构.引用表.iter().find(|项| 项.类 == 号类::常量).expect("该有一条常量引用");
    assert_eq!(引用条目.来源, 号来源::程序, "程序内常量优先于常量表");
    assert_eq!(引用条目.号, 1);

    // 只有注册表里有 ⇒ 取常量表。
    let 文2 = ".版本 2\n.子程序 取版本, 整数型\n    返回 (#FALSE)\n";
    let 构2 = 分析(&建语法树(文2), &注册表::空实例(), &造注册表(&[("FALSE", 7)]), &造注册表(&[("整数型", 51)]))
        .expect("该解析成功");
    let 引2 = 构2.引用表.iter().find(|项| 项.类 == 号类::常量).expect("该有一条常量引用");
    assert_eq!((引2.来源, 引2.号, 引2.作用域), (号来源::常量表, 7, 作用域::平台));
}

