//! 带号结构 —— **1103 语义分析的产物形状**（号类 · 作用域 · 号来源 · 号项 · 引用项 · 带号结构 · 语义错误）。
//!
//! # 这个形状的取证地基（哪一半是实测、哪一半是本库自定）
//!
//! **实测已证**（`项目文档/设计文档/声明记录区实测.md` §四 · §九）：
//!
//! 1. 盘面**既存名也存号**，且**名与号不邻接**（`EcUpData.ec` 里 `hModule` 与它的参数令牌
//!    相距 4 MB 量级）⇒ **1103 必须自带一层「名 → 号」表**，不能指望盘面给现成绑定；
//! 2. 号是**程序内的 16 位序号**（跨 DLL 命令连续递增、文件内唯一 668/684），
//!    **不是**名字哈希、**不是**段内偏移。
//!
//! **裁定已定**（`项目文档/设计文档/程序文本格式.md` §二「名字与号的分离」）：
//! 变量 → `(作用域, 序号)`（遮蔽顺序 **局部 > 程序集 > 全局**，取最近的且诊断里要报出取了哪一个）·
//! 常量 → 常量号（程序内唯一）· 资源 → 资源号（程序内唯一）· 能力（命令）→ 能力号
//! （平台侧号段，与程序侧无关）· 子程序 → `(程序集, 序)`（程序集内唯一）。
//!
//! **取证没到的部分（不判，本形状不假装表达）**：声明记录区的**五类分区边界** ·
//! 令牌 `<u16 号><u8 参中字节><u8 令牌类别>` 的**字段语义** · 语句**字节码操作码表**。
//! 这三处是 `说明/声明记录区取证.md` §二 单列的不判项，本形状**一个字节都不替它们编**：
//! 带号结构**不表示** `.e` 记录区的分区与字节码，它只表示「名字 → 号」的解析结果。
//!
//! # 为什么号一律 `u16`
//!
//! 实测口径是「程序内全局 **16 位**序号」（上引 §4.3）。故本形状的号一律 `u16`：
//! 三张注册表里号的取值上界由此成为一条**可判死的边界**（超界即 `语义错误::号溢出`），
//! 而不是悄悄截断。`u16` 上限 65535 相对语料量级（命令 688 / 常量 335 / 类型 51）余量充足。

use crate::语言面::节点种类;

/// 号类 —— 1103 给结构里的名字定出的号属于哪一类。
///
/// 五个类逐字取自 `程序文本格式.md` §二 的解析表与 `能力声明/1103.json` 的说明
/// （「给变量 · 常量 · 资源 · 能力 · 子程序都定出号」）。
///
/// **`资源` 当前不可达**（如实登记，不发明映射）：本扩展的语言面 33 种节点里
/// **没有**一种「资源声明」，三张入参表里也**没有**资源表 ⇒ 1103 无从给资源定号。
/// 这个类保留在枚举里是为了让形状与裁定表逐条对应；等资源声明的节点种类或资源表
/// 到位后再接上，**在此之前它一条记录都不产**（有测试钉住这条读数）。
///
/// **`类型` 是本形状新增的第六类**（裁定表里没有它）：1103 的入参里有**类型表**
/// （`能力声明/1103.json` 的参数表「类型表」一行），类型名必须查得到，故类型也要有号与类。
/// 这是「入参有类型表」这条契约事实的直接推论，不是发明。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum 号类 {
    变量 = 1,
    常量 = 2,
    资源 = 3,
    能力 = 4,
    子程序 = 5,
    类型 = 6,
}

impl 号类 {
    pub fn 自号(号值: u8) -> Option<Self> {
        use 号类::*;
        Some(match 号值 {
            1 => 变量,
            2 => 常量,
            3 => 资源,
            4 => 能力,
            5 => 子程序,
            6 => 类型,
            _ => return None,
        })
    }

    pub fn 取号值(&self) -> u8 {
        *self as u8
    }
}

/// 作用域 —— 名字住在哪一层。**优先级从 `局部` 往 `平台` 递减**（裁定：局部 > 程序集 > 全局）。
///
/// `平台` 不是程序里的层，是**平台侧号段**（命令表 / 常量表 / 类型表的号与程序侧无关）——
/// 把它写进同一个枚举，是为了让「引用项取自哪一层」只有一个说法。
///
/// `数据成员` 是 `数据类型声明` 体里那一层（`.成员`）；成员访问的成员名**不判**
/// （没有成员表可查，见 `建表.rs` 的「不判」清单），故这一层只服务「成员声明定号」。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum 作用域 {
    平台 = 0,
    全局 = 1,
    程序集 = 2,
    局部 = 3,
    数据成员 = 4,
}

impl 作用域 {
    /// 本层是否参与「变量 / 子程序」的名字解析（按 局部 → 程序集 → 全局 的优先级）。
    pub fn 参与名字解析(&self) -> bool {
        matches!(self, 作用域::局部 | 作用域::程序集 | 作用域::全局)
    }

    /// 优先级：越大越近（遮蔽时取大的）。非解析层返回 `None`。
    pub fn 优先级(&self) -> Option<u8> {
        match self {
            // 裁定：局部 > 程序集 > 全局（取最近的）。
            作用域::局部 => Some(3),
            作用域::程序集 => Some(2),
            作用域::全局 => Some(1),
            _ => None,
        }
    }
}

/// 号来源 —— 一个引用项的号是从哪张表取到的。
///
/// `程序` = 1103 自建的「名 → 号」表（本形状的第 1 条取证地基）；
/// 其余三个 = 调用方传入的三张注册表（`能力声明/1103.json` 参数表第 1–3 行）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum 号来源 {
    程序 = 1,
    命令表 = 2,
    常量表 = 3,
    类型表 = 4,
}

impl 号来源 {
    pub fn 取号值(&self) -> u8 {
        *self as u8
    }
}

/// 号表的一项：**名字 → 号**。这是 1103 **自带**的那一层表（取证地基第 1 条）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 号项 {
    pub 类: 号类,
    pub 作用域: 作用域,
    pub 号: u16,
    /// 名字的**原始字节**。按原字节比，**不按解码后的字符串比**
    /// （`说明/语言面形状.md` §六待办 6：注册表名称的编码未定，比字节最安全）。
    pub 名: Vec<u8>,
}

/// 引用表的一项：某个**引用节点**解析出的号 —— 「诊断里必须报出取了哪一个」的落点。
///
/// `节点` 是引用在语法树 `节点表` 里的下标（`标识符引用` / `常量引用` 叶）。
/// `作用域` 对平台侧来源恒为 `作用域::平台`。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 引用项 {
    pub 节点: u32,
    pub 类: 号类,
    pub 来源: 号来源,
    pub 号: u16,
    pub 作用域: 作用域,
}

/// 带号结构 —— **1103 的产物**：名 → 号表 + 引用表。
///
/// 它**不表示** `.e` 声明记录区的分区边界与字节码（那三处是不判项，见本件文件头）。
/// 字节排布（过边界用）是 `src/lib.rs::语义编码`，与 `结构编码` / `原生路编码` 同一条规矩：
/// **只搬字段、不含业务知识**。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 带号结构 {
    pub 号表: Vec<号项>,
    pub 引用表: Vec<引用项>,
}

impl 带号结构 {
    /// 按名字找号表项（**按原始字节比**）。同名取**先登记的那一项**。
    pub fn 按名找(&self, 名称: &[u8]) -> Option<&号项> {
        self.号表.iter().find(|一项| 一项.名 == 名称)
    }

    /// 某个引用节点解析出的那一项。
    pub fn 按节点找(&self, 节点: u32) -> Option<&引用项> {
        self.引用表.iter().find(|一项| 一项.节点 == 节点)
    }
}

/// 语义错误。**结构化段位，不是字符串、不是 panic**（口径同 `语言面::形状错误`）。
///
/// 当前只有一个变体：`能力声明/1103.json` 的 `可抛错误码` 里唯一的语义层码是 **1136**。
/// 裁定四明说「遮蔽歧义不单立码」—— 遮蔽是**确定性选择**、不是失败。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 语义错误 {
    /// 名字未声明：程序文本引用了作用域里查不到的名字（局部 > 程序集 > 全局 都查不到，
    /// 三张注册表里也没有）。→ 错误码 **1136**。
    名字未声明 { 名: Vec<u8>, 节点: u32 },
    /// 号装不下：1103 自建的序号或注册表里的号超过 `u16` 上界。→ 错误码 **1134**
    /// （本库的边界编码装不下；见 `错误码表/1134.json`）。
    号溢出 { 序: u32 },
}

/// 本变体的 `节点种类` 是否为**声明类**（体里可以再出声明与语句）。
pub(crate) fn 是声明类(种类: 节点种类) -> bool {
    matches!(
        种类,
        节点种类::支持库声明
            | 节点种类::程序集
            | 节点种类::程序集变量声明
            | 节点种类::全局变量声明
            | 节点种类::局部变量声明
            | 节点种类::子程序
            | 节点种类::参数声明
            | 节点种类::数据类型声明
            | 节点种类::数据成员声明
            | 节点种类::DLL命令声明
            | 节点种类::常量声明
    )
}

