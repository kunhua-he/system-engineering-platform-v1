use crate::容器;

// ── 六字段的形状（接口说明 · 接口参数项 · 接口错误项）**搬到契约层** ─────────────────────
// 理由与 `接口段编码` 同：读侧在底座（模块没有本机机器码，底座只能从接口说明段读出「怎么调」），
// 而底座与扩展共用的层只有 `v1-contract`。**本件转调，不另立一份形状** —— 两份形状就是两份定义，
// 将来字段动一个就两处不同步。字段表与字段序的权威仍在 `接口面形状.md` §三（本件不复述）。
pub use v1_contract::接口说明段::{接口参数项, 接口说明, 接口错误项};

// 三段段名（`接口说明` / `能力码` / `指纹`）与名称区异或规则**只此一处**：容器格式的唯一实现
// 在 `v1_contract::容器`（见 `契约声明/src/契约声明/容器封装/容器.rs`）—— 本件不再各存一份段名。

/// 包件错误 —— **库内**构造失败（不是跨边界的码，故不登记进 `错误码表/`）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 包件错误 {
    /// 段头写不出来（段名为空 / 段名超过名称区容量）。源出 [`容器::生成错误`]。
    生成失败(容器::生成错误),
    /// 往返不一致：生成后再反解，回来的段表与本意不符。
    ///
    /// **为什么这条真会中**：冻结容器**没有段长字段**，段数据直抵下一处段头；
    /// 若某段数据里碰巧出现段头特征（`19 73` · `11 15` · 合法段类型号 · 合规尾标志），
    /// 反解会在那里切一刀。故装包**必须**当场自检，不许把这种包交给调用方。
    往返不一致,
}
