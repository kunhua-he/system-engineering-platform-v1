/// **SHA-256 已知向量**（FIPS 180-4 附录 B 与 NIST 常用向量）。
///
/// 为什么必须拿外部向量：自写哈希最大的坑是「编解码自洽但整体错」（自己编的、自己解、永远绿）。
/// 两条向量都是公开值，不依赖本仓任何东西。
#[test]
fn 指纹_sha256两条已知向量() {
    assert_eq!(
        转十六进制(&指纹::算指纹(b"")),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
        "空串向量"
    );
    assert_eq!(
        转十六进制(&指纹::算指纹(b"abc")),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
        "abc 向量"
    );
    // 长于一个块（64 字节）的输入：验证分块拼接与长度填充。
    assert_eq!(
        转十六进制(&指纹::算指纹(
            b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
        )),
        "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1",
        "两块向量"
    );
}

/// 接口说明 → 字节 → 接口说明：**逐字段不变**。
#[test]
fn 接口段编码_编解码往返逐字段不变() {
    let 原 = 样例说明();
    let 字节 = 接口段编码::编码(&原);
    let 回 = 接口段编码::解码(&字节).expect("自己编的必须解得开");
    assert_eq!(回, 原);
}

/// **反向样本**：尾部多一字节 ⇒ 解码必须拒（不许「尽力而为」）。
#[test]
fn 接口段编码_尾部多余字节拒() {
    let 字节 = 接口段编码::编码(&样例说明());
    let mut 多 = 字节.clone();
    多.push(0);
    assert!(接口段编码::解码(&多).is_none(), "尾部多字节必须拒");
    assert!(接口段编码::解码(&[]).is_none(), "空字节连编号都读不出，必须拒");
    assert!(接口段编码::解码(&字节[..字节.len() - 1]).is_none(), "截断必须拒");
}

