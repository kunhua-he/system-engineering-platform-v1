/// 三段段类型号 = u8 空洞 `16`/`17`/`18`（已落 `容器/形状.rs::段类型`）。
#[test]
fn 装包_三段段类型号是16到18() {
    assert_eq!(装包::段类型号_接口说明(), 16);
    assert_eq!(装包::段类型号_能力码(), 17);
    assert_eq!(装包::段类型号_指纹(), 18);
}

/// **一步到底的装包**：三段装进冻结容器 ⇒ 生成 → 反解逐段同形；拆包回两段字节；校验过。
#[test]
fn 装包_三段装进冻结容器且往返一致() {
    let 说明 = 样例说明();
    let 码 = b"\0asm\x01\0\0\0".to_vec();
    let 包 = 装包::装包(&说明, &码).expect("装包该成功");

    // 魔数开头，且三段各就各位。
    assert_eq!(&包[..8], 容器::魔数);
    let 含 = 容器::反解(&包).expect("自己装的反解得开");
    assert_eq!(含.段表.len(), 3, "就三段");
    assert_eq!(含.段表[0].头.段类型, 16);
    assert_eq!(含.段表[1].头.段类型, 17);
    assert_eq!(含.段表[2].头.段类型, 18);
    assert_eq!(含.段表[1].数据, 码, "能力码段原样搬运");
    // 段头 44 字节是冻结形状，一个字节不动。
    assert_eq!(包.len(), 8 + 3 * 容器::段头长度 + 含.段表.iter().map(|段| 段.数据.len()).sum::<usize>());

    // 拆包：接口说明字节能解回原六字段；能力码原样。
    let (接口字节, 回码) = 装包::拆包(&包).expect("拆包该成功");
    assert_eq!(回码, 码);
    assert_eq!(接口段编码::解码(&接口字节).expect("接口段该解得开"), 说明);

    // 指纹：两段都没被换过。
    assert_eq!(装包::校验(&包), Some(true));
}

/// **反向样本**：改过包里的能力码字节 ⇒ 校验当场报「被换过」；截掉一段 ⇒ 拆包拒。
#[test]
fn 装包_改过包任一段指纹报不一致() {
    let 包 = 装包::装包(&样例说明(), b"\0asm\x01\0\0\0").expect("装包该成功");
    let 含 = 容器::反解(&包).expect("反解");
    // 定位能力码段的最后一个字节（三段里第二段），改它一位。
    let 首段尾 = 8 + 容器::段头长度 + 含.段表[0].数据.len();
    let 码尾 = 首段尾 + 容器::段头长度 + 含.段表[1].数据.len();
    let mut 改 = 包.clone();
    改[码尾 - 1] ^= 0xFF;
    // 反解仍成立（结构没坏），但指纹对不上 ⇒ 抓到「边被换过」。
    assert_eq!(装包::校验(&改), Some(false), "改过能力码段必须报到");

    // 反向：把第三段（指纹段）整个去掉 ⇒ 拆包拒。
    let 截 = 改[..首段尾].to_vec();
    assert!(装包::拆包(&截).is_none(), "少一段必须拒");
    assert!(装包::校验(&截).is_none(), "少一段必须拒");
}

/// **反向样本**：空段名 ⇒ 生成错误，包装成 [`包件错误::生成`]（不 panic）。
#[test]
fn 装包_段名写不出时报生成不崩溃() {
    // 直接拿容器层验这条传播路径（段名为空是容器生成错误）。
    let 含 = 容器::容器 {
        段表: vec![容器::容器段 {
            头: 容器::段头 { 校验和: 0, 段类型: 16, 名称区: [0; 27], 段名: Vec::new() },
            数据: vec![1],
        }],
    };
    assert_eq!(
        容器::生成(&含),
        Err(容器::生成错误::段名为空 { 第几段: 0 }),
        "空段名必须报错"
    );
    // 而包件那一层把同一个错误原样搬出（同一个事实不两处编）。
    assert_eq!(包件错误::生成(容器::生成错误::段名为空 { 第几段: 0 }), 包件错误::生成(容器::生成错误::段名为空 { 第几段: 0 }));
}

/// 指纹段本身的编解码往返；条数不符 / 尾部多余 ⇒ 拒。
#[test]
fn 指纹_段指纹编解码往返() {
    let 字节 = 指纹::编码(&[(16, b"aaa"), (17, b"bbb")]);
    let 项 = 指纹::解码(&字节).expect("解得开");
    assert_eq!(项.len(), 2);
    assert_eq!(项[0].段类型号, 16);
    assert_eq!(项[0].哈希, 指纹::算指纹(b"aaa"));
    assert!(指纹::解码(&[]).is_none());
    let mut 多 = 字节.clone();
    多.push(0);
    assert!(指纹::解码(&多).is_none(), "尾部多余字节必须拒");
}
