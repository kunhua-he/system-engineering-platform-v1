//! 上级：`扩展根目录/原子支持库/编译器支持库/` ／ 裁定：`项目文档/设计文档/能力包件.md`
//! 相关：`项目文档/决策记录/2026-09-27_1106产物与入参裁决.md`（产物 = `.能力包件`）·
//! `项目文档/决策记录/2026-09-27_语言主线三缺口裁决.md` §四（六字段 = 接口面返回体）·
