//!
//! # 本件只立形状，不含算法
//!
//! 装包（三段拼进冻结容器）在 [`装包`](super::装包)；六字段怎么排字节在
//! [`接口段编码`](super::接口段编码)；段指纹在 [`指纹`](super::指纹)。
//!
//! # 六字段的字段表**不在本件**（不许复述）
//!
//! 接口说明段 = `GET /接口/能力/<编号>` 返回体，**逐条同名同序**，字段表只在
//! `接口面形状.md` 一处（裁决 §四：复述就是第二个来源）。本件的结构体只是那六个字段的
//! **库内形态**；可执行的权威是 `对外接口面/调用接口面/src/响应.rs::能力契约`（编号 ·
//! 名称 · 说明 · 参数表 · 返回类型 · 可抛错误码）与 `错误形状.rs::到协议值`（错误对象七项）。
//!
//! # 不预立错误码
//!
//! `能力声明/1106.json` 的 `可抛错误码` 是**空表**（契约把它钉成总函数）。按
//! `决策记录/2026-09-27_段位9错误码表.md` §五「没有调用方的码就是一份没有任何效果的声明」
//! ⇒ 本件**不替 1106 开码**。[`包件错误`] 是本库**库内**的构造失败，不是跨边界的码
//! （与 `容器::生成错误` / `反解错误` 同层）。

use crate::容器;
use v1_contract::数据槽;

/// 接口说明段的一条参数项 —— 与 `响应.rs::能力契约` 的 `参数表` 一项同序。
///
/// 字段序（可执行权威 `响应.rs`）：`名称` · `类型标签` · `状态位` · `默认值`。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 接口参数项 {
    pub 名称: String,
    pub 类型标签: u32,
    pub 状态位: u16,
    /// 定长数据槽（24 字节，冻结项 `冻结项[2] 数据槽形状`）。
    pub 默认值: 数据槽,
}

/// 接口说明段的一条可抛错误码 —— 与 `错误形状.rs::到协议值` 的错误对象逐条同序。
///
/// 字段序：`码` · `段位` · `名称` · `可重试` · `可自愈` · `需人工` · `已登记`。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 接口错误项 {
    pub 码: u32,
    pub 段位: u32,
    pub 名称: String,
    pub 可重试: bool,
    pub 可自愈: bool,
    pub 需人工: bool,
    /// 旁路字段（`接口面形状.md` §三：错误对象六项 + 旁路 `已登记`）。
    pub 已登记: bool,
}

/// 接口说明 —— 能力包件**第一段**（段类型号 `16`）的内容：只讲怎么调。
///
/// 六字段**逐条同名同序**取自接口面返回体（本件不复述字段表）。agent 只看这一段，
/// 包里没有源码（`能力包件.md` §三）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 接口说明 {
    pub 编号: u32,
    pub 名称: String,
    pub 说明: String,
    /// 行序即契约（与 `能力声明/<编号>.json` 的参数表逐行对应）。
    pub 参数表: Vec<接口参数项>,
    pub 返回类型: u32,
    pub 可抛错误码: Vec<接口错误项>,
}

/// 三段段名（写入 44 字节段头的名称区，按段类型异或混淆，见 `容器/名称区.rs`）。
///
/// 取中文名与段类型号一一对应；名称区容量 27 字节，三个名字都远在其内。
pub const 段名_接口说明: &[u8] = "接口说明".as_bytes();
pub const 段名_能力码: &[u8] = "能力码".as_bytes();
pub const 段名_指纹: &[u8] = "指纹".as_bytes();

/// 包件错误 —— **库内**构造失败（不是跨边界的码，故不登记进 `错误码表/`）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 包件错误 {
    /// 段头写不出来（段名为空 / 段名超过名称区容量）。源出 [`容器::生成错误`]。
    生成(容器::生成错误),
    /// 往返不一致：生成后再反解，回来的段表与本意不符。
    ///
    /// **为什么这条真会中**：冻结容器**没有段长字段**，段数据直抵下一处段头；
    /// 若某段数据里碰巧出现段头特征（`19 73` · `11 15` · 合法段类型号 · 合规尾标志），
    /// 反解会在那里切一刀。故装包**必须**当场自检，不许把这种包交给调用方。
    往返不一致,
}
