//! 装包 —— 三段（接口说明 · 能力码 · 指纹）装进**已冻结的容器主结构**，出能力包件字节。
//!
//! 依据：`项目文档/决策记录/2026-09-27_1106产物与入参裁决.md`（产物 = `.能力包件`；
//! **它本质是个封装包**，不是又一层语义分析）· `能力包件.md` §一（三段）
//! 与 `决策记录/2026-09-27_语言主线三缺口裁决.md` §三（段类型号取 u8 空洞 `16–18`）。
//!
//! # 容器格式只此一份实现（本件**转调**，不重写）
//!
//! 容器的唯一实现在 `v1_contract::容器`（契约层 —— 底座装载与装配侧打包共用同一份，
//! 见 `契约声明/src/契约声明/容器.rs`）。本件只做两件**本扩展自有**的事：
//! ① 把六字段 [`接口说明`] 编成接口说明段字节（`接口段编码`，六字段编码是本扩展的施工面）；
//! ② 转调契约层装包 / 拆包 / 校验。**一条格式知识也不重写**（不另造外壳、不各写一套）。
//!
//! # 它不做哪些事（**这一条决定了体量上限**）
//!
//! 本件是**装包**，不是编译器后端：
//!
//! - **不生成机器码** —— 能力码段的字节由**调用方**传入（支持库 = 本机机器码 ·
//!   模块 = `wasm32` 那一侧的构建产物）。本件**不发明**一份码，也**不假装**有码。
//! - **不解析名字、不定号** —— 那是 1103 的本体（`语义/建表.rs`），本件只接它的产物。
//! - **不猜六字段** —— 接口说明的六字段由**调用方**交（来源是模块声明那一层，形状未裁）。

use v1_contract::容器;

use crate::能力包件::形状::{包件错误, 接口说明};
use crate::能力包件::{接口段编码, 指纹};

/// 三段的段类型号（数值唯一事实源 = `v1_contract::容器` 的常量；此处只转调，免得两处各写一个数）。
pub fn 段类型号_接口说明() -> u8 {
    容器::段类型_接口说明
}
pub fn 段类型号_能力码() -> u8 {
    容器::段类型_能力码
}
pub fn 段类型号_指纹() -> u8 {
    容器::段类型_指纹
}

/// 装包：接口说明 + 能力码字节 → 能力包件字节。
///
/// 指纹段由契约层算（它登的就是前两段的 sha256）。本件把六字段先编成段字节，
/// 再转调 [`容器::装包`]；最后**当场自检往返**（冻结容器无段长字段，段数据里碰巧出现
/// 段头特征就会被多切一刀 —— 不许把这种包交给调用方）。
///
/// **输入入参是「已备好的两份数据」**：接口说明（六字段，来源由调用方决定）与
/// 能力码字节（支持库 = 本机机器码 · 模块 = WASM，来源在构建侧）。本件不替它们做任何生成。
///
/// 失败一档：[`包件错误::往返不一致`]（契约层装包无失败档：三段段名是常量，写段头恒成功）。
pub fn 装包(说明: &接口说明, 能力码: &[u8]) -> Result<Vec<u8>, 包件错误> {
    let 接口字节 = 接口段编码::编码(说明);
    let 包件字节 = 容器::装包(&接口字节, 能力码);
    match 容器::解包(&包件字节) {
        Ok(解出包件) if 解出包件.接口说明段 == 接口字节 && 解出包件.能力码段 == 能力码 => Ok(包件字节),
        _ => Err(包件错误::往返不一致),
    }
}

/// 拆包：能力包件字节 → （接口说明字节，能力码字节）。
///
/// 只认三段且段类型各就各位（由 [`容器::解包`] 保证），且指纹段是**本形状**（两条指纹）。
/// **不校哈希**（那是校验方的事；本件只解形状）。
///
/// 返回的是**段的原始字节**而不是解好的结构：接口说明的六字段什么时候解，由调用方定
/// （它才知道要不要看那一段）。
pub fn 拆包(字节: &[u8]) -> Option<(Vec<u8>, Vec<u8>)> {
    let 解出包件 = 容器::解包(字节).ok()?;
    if 指纹::解码(&解出包件.指纹段)?.len() != 2 {
        return None;
    }
    Some((解出包件.接口说明段, 解出包件.能力码段))
}

/// 校验一份包：前两段的 sha256 是否与指纹段登的一致（转调 [`容器::校验`]）。
///
/// `None` = 不是本形状的包；`Some(真)` = 两段都没被换过；`Some(假)` = 被换过。
/// 这是 `能力包件.md` §四 说的那个用途（「任何一边被换过都判得出来」）的落点。
pub fn 校验(字节: &[u8]) -> Option<bool> {
    容器::校验(字节)
}
