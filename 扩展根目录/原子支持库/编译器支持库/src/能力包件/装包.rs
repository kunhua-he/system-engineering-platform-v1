//! 装包 —— 三段（接口说明 · 能力码 · 指纹）装进**已冻结的容器主结构**，出 `.能力包件` 字节。
//!
//! 依据：`项目文档/决策记录/2026-09-27_1106产物与入参裁决.md`（产物 = `.能力包件`；
//! **它本质是个封装包**，不是又一层语义分析）· `能力包件.md` §一（三段）
//! 与 `决策记录/2026-09-27_语言主线三缺口裁决.md` §三（段类型号取 u8 空洞 `16–18`）。
//!
//! # 它不做哪些事（**这一条决定了体量上限**）
//!
//! 本件是**装包**，不是编译器后端：
//!
//! - **不生成机器码** —— 能力码段的字节由**调用方**传入（它来自 `wasm32` 那一侧的构建产物，
//!   不是本库算出来的）。本件**不发明**一份码，也**不假装**有码。
//! - **不解析名字、不定号** —— 那是 1103 的本体（`语义/建表.rs`），本件只接它的产物。
//! - **不猜六字段** —— 接口说明的六字段由**调用方**交（来源是模块声明那一层，形状未裁）。
//!
//! ⇒ 本件只干一件事：把**已给的三份数据**按能力包件的形状装成一份字节，并当场验往返。
//!
//! # 为什么不另造外壳
//!
//! `能力包件.md` §一 末段：骨架（44 字节段头 + 段类型号 + 名称区密钥）**沿用已冻结的容器主结构**，
//! **不另造一套外壳**。故本件只调 [`容器::生成`]，一条格式知识也不重写。

use crate::容器;
use crate::能力包件::形状::{
    包件错误, 段名_接口说明, 段名_能力码, 段名_指纹, 接口说明,
};
use crate::能力包件::{接口段编码, 指纹};

/// 三段的段类型号（与 `容器/形状.rs::段类型` 的枚举值同源；此处只作装包时的书写便利）。
///
/// 数值**不在这里定义** —— 唯一事实源是 `容器::段类型` 枚举；本函数取它的 `取号值()`，
/// 免得两处各写一个数。
pub fn 段类型号_接口说明() -> u8 {
    容器::段类型::接口说明.取号值()
}
pub fn 段类型号_能力码() -> u8 {
    容器::段类型::能力码.取号值()
}
pub fn 段类型号_指纹() -> u8 {
    容器::段类型::指纹.取号值()
}

/// 装包：接口说明 + 能力码字节 → `.能力包件` 字节。
///
/// 指纹段由本函数自己算（它登的就是前两段的 sha256）。
///
/// **输入入参是「已备好的两份数据」**：接口说明（六字段，来源由调用方决定）与
/// 能力码字节（WASM 产物，来源在构建侧）。本件不替它们做任何生成。
///
/// 失败两档：段头写不出 ⇒ [`包件错误::生成`]；往返不一致 ⇒ [`包件错误::往返不一致`]。
pub fn 装包(说明: &接口说明, 能力码: &[u8]) -> Result<Vec<u8>, 包件错误> {
    let 接口字节 = 接口段编码::编码(说明);
    let 指纹字节 = 指纹::编码(&[
        (段类型号_接口说明(), &接口字节),
        (段类型号_能力码(), 能力码),
    ]);
    let 含 = 容器::容器 {
        段表: vec![
            造段(段类型号_接口说明(), 段名_接口说明, 接口字节),
            造段(段类型号_能力码(), 段名_能力码, 能力码.to_vec()),
            造段(段类型号_指纹(), 段名_指纹, 指纹字节),
        ],
    };
    let 包 = 容器::生成(&含).map_err(包件错误::生成)?;
    // 当场自检：冻结容器无段长字段，段数据里碰巧出现段头特征就会被多切一刀。
    // 不许把这种包交给调用方（否则错会漂到很久以后的读侧）。
    let 回 = 容器::反解(&包).map_err(|_| 包件错误::往返不一致)?;
    if 回.段表.len() != 3 {
        return Err(包件错误::往返不一致);
    }
    for (回段, 原段) in 回.段表.iter().zip(含.段表.iter()) {
        if 回段.头.段类型 != 原段.头.段类型 || 回段.数据 != 原段.数据 {
            return Err(包件错误::往返不一致);
        }
    }
    Ok(包)
}

/// 拆包：`.能力包件` 字节 → （接口说明字节，能力码字节）。
///
/// 只认三段且段类型各就各位：多一段、少一段、段类型不符、指纹段解不开 ⇒ `None`。
/// **不校哈希**（那是校验方的事，它手上有原段数据；本件只解形状）。
///
/// 返回的是**段的原始字节**而不是解好的结构：接口说明的六字段什么时候解，由调用方定
/// （它才知道要不要看那一段）。
pub fn 拆包(字节: &[u8]) -> Option<(Vec<u8>, Vec<u8>)> {
    let 含 = 容器::反解(字节).ok()?;
    if 含.段表.len() != 3 {
        return None;
    }
    let 找 = |号: u8| 含.段表.iter().find(|段| 段.头.段类型 == 号).map(|段| 段.数据.clone());
    let (接口, 码, 指) = (
        找(段类型号_接口说明())?,
        找(段类型号_能力码())?,
        找(段类型号_指纹())?,
    );
    let 项 = 指纹::解码(&指)?;
    if 项.len() != 2 {
        return None;
    }
    Some((接口, 码))
}

/// 校验一份包：两段的 sha256 是否与指纹段登的一致。
///
/// `None` = 不是本形状的包；`Some(真)` = 两段都没被换过；`Some(假)` = 被换过。
/// 这是 `能力包件.md` §四 说的那个用途（「任何一边被换过都判得出来」）的落点。
pub fn 校验(字节: &[u8]) -> Option<bool> {
    let 含 = 容器::反解(字节).ok()?;
    if 含.段表.len() != 3 {
        return None;
    }
    let 接口 = 含.段表.iter().find(|段| 段.头.段类型 == 段类型号_接口说明())?;
    let 码 = 含.段表.iter().find(|段| 段.头.段类型 == 段类型号_能力码())?;
    let 指 = 含.段表.iter().find(|段| 段.头.段类型 == 段类型号_指纹())?;
    let 项 = 指纹::解码(&指.数据)?;
    let 期望 = [
        (段类型号_接口说明(), 指纹::算指纹(&接口.数据)),
        (段类型号_能力码(), 指纹::算指纹(&码.数据)),
    ];
    if 项.len() != 期望.len() {
        return None;
    }
    Some(
        项.iter()
            .zip(期望.iter())
            .all(|(实, (号, 哈))| 实.段类型号 == *号 && 实.哈希 == *哈),
    )
}

fn 造段(号: u8, 名: &[u8], 数据: Vec<u8>) -> 容器::容器段 {
    容器::容器段 {
        头: 容器::段头 {
            // 校验和（盘面 u32）算法**未证实**，容器侧一律原样搬运、不重算
            // （`容器/形状.rs` 模块注释）。新造的段无源可搬 ⇒ 写 0。
            校验和: 0,
            段类型: 号,
            名称区: [0; 27],
            段名: 名.to_vec(),
        },
        数据,
    }
}
