//! 接口说明段编码 —— 把 [`接口说明`](super::形状::接口说明) 六字段排成一串字节。
//!
//! 这就是 `说明/使用说明.md` 「1106 接口说明段编码（施工方案）」与
//! `能力包件.md` §六 待办 1 说的那个**「装法」**：字段形状已冻（= 接口面返回体，
//! 逐条同名同序），本件只规定它们**在段里怎么排字节**。
//!
//! # 规矩（逐条照施工方案）
//!
//! 与 `容器结构边界编码` / `原生路边界编码` / `语义编码` **同一条规矩**：
//! 只搬字段、不含业务知识；编解码只有这一处，不另起第二套。小端。
//!
//! | 字段的 JSON 类型 | 段里的字节排布 |
//! |---|---|
//! | 整数 | 按该字段宽度**小端**搬（`u32` / `u16` / `u8` 各按其宽度） |
//! | 文本 | `u32 字节长` + UTF-8 字节 |
//! | 表 | `u32 项数` + 逐项按本表递归（**参数表的行序 = 契约行序，不许重排**） |
//! | 槽（参数项的 `默认值`） | 定长数据槽 **24 字节原样** |
//! | 逻辑型 | `u8`：`0` / `1` |
//!
//! # 本编码未冻
//!
//! `决策记录/2026-09-27_语言主线三缺口裁决.md` §四 把它归**施工面**
//! （「形状部分当场闭，剩下的只是编码」）⇒ 本件**不自行登记** `冻结登记.json`。
//! 若收口方要把本编码冻成盘面形状，照 `原生路边界编码` 的先例补一条旁路即可。

use super::形状::{接口说明, 接口参数项, 接口错误项};
use crate::顺序读器::顺序读器;

/// 六字段的**字段序**（照接口面返回体，`接口面形状.md` §三）。
///
/// 列在这里是为了让「字段表只有一源」这条可核对：本件只实现这个序，不自定一个。
/// 反向解码（[`解码`]）也读同一个常量 ⇒ 两个方向不会各写一套。
pub const 接口字段序: [&str; 6] = ["编号", "名称", "说明", "参数表", "返回类型", "可抛错误码"];

/// 数据槽宽度（字节）。**冻结项 `冻结项[2] 数据槽形状`**：
/// `u32 类型标签 · u16 标志 · u16 保留 · u64 长度 · u64 值` = 4+2+2+8+8 = 24。
pub const 数据槽宽度: usize = 24;

/// 接口说明 → 段数据字节。
pub fn 编码(说明: &接口说明) -> Vec<u8> {
    let mut 输出缓冲 = Vec::new();
    输出缓冲.extend_from_slice(&说明.编号.to_le_bytes());
    写段文本(&mut 输出缓冲, &说明.名称);
    写段文本(&mut 输出缓冲, &说明.说明);
    输出缓冲.extend_from_slice(&(说明.参数表.len() as u32).to_le_bytes());
    for 参数 in &说明.参数表 {
        写参数项(&mut 输出缓冲, 参数);
    }
    输出缓冲.extend_from_slice(&说明.返回类型.to_le_bytes());
    输出缓冲.extend_from_slice(&(说明.可抛错误码.len() as u32).to_le_bytes());
    for 错误 in &说明.可抛错误码 {
        写错误项(&mut 输出缓冲, 错误);
    }
    输出缓冲
}

/// 段数据字节 → 接口说明。`None` = 编码非法（截断 / 尾部多余字节 / 不是合法 UTF-8）。
///
/// **不许尽力而为**：非空字节集必须**正好**解完，剩余一字节即 `None`（同
/// [`注册表::解码`](crate::语义::注册表::解码) 的口径）。
pub fn 解码(字节: &[u8]) -> Option<接口说明> {
    let mut 读器 = 顺序读器 { 字节, 位: 0 };
    let 编号 = 读器.读四字节()?;
    let 名称 = 读器.文本()?;
    let 说明文本 = 读器.文本()?;
    let 参数个数 = 读器.读四字节()? as usize;
    // 每项至少 4 字节名长 + 4 类型标签 + 2 状态位 + 24 槽 = 34 字节。
    if 参数个数 > 读器.取剩余长度() / 34 {
        return None;
    }
    let mut 参数表 = Vec::with_capacity(参数个数);
    for _ in 0..参数个数 {
        参数表.push(读参数项(&mut 读器)?);
    }
    let 返回类型 = 读器.读四字节()?;
    let 错误个数 = 读器.读四字节()? as usize;
    // 每项至少 4 码 + 4 段位 + 4 名长 + 4 逻辑型 = 16 字节。
    if 错误个数 > 读器.取剩余长度() / 16 {
        return None;
    }
    let mut 可抛错误码 = Vec::with_capacity(错误个数);
    for _ in 0..错误个数 {
        可抛错误码.push(读错误项(&mut 读器)?);
    }
    if 读器.位 != 字节.len() {
        return None;
    }
    Some(接口说明 { 编号, 名称, 说明: 说明文本, 参数表, 返回类型, 可抛错误码 })
}

fn 写段文本(输出缓冲: &mut Vec<u8>, 文本: &str) {
    输出缓冲.extend_from_slice(&(文本.len() as u32).to_le_bytes());
    输出缓冲.extend_from_slice(文本.as_bytes());
}

fn 写参数项(输出缓冲: &mut Vec<u8>, 参数: &接口参数项) {
    写段文本(输出缓冲, &参数.名称);
    输出缓冲.extend_from_slice(&参数.类型标签.to_le_bytes());
    输出缓冲.extend_from_slice(&参数.状态位.to_le_bytes());
    写槽(输出缓冲, &参数.默认值);
}

fn 写错误项(输出缓冲: &mut Vec<u8>, 错误: &接口错误项) {
    输出缓冲.extend_from_slice(&错误.码.to_le_bytes());
    输出缓冲.extend_from_slice(&错误.段位.to_le_bytes());
    写段文本(输出缓冲, &错误.名称);
    输出缓冲.push(bool::from(错误.可重试) as u8);
    输出缓冲.push(bool::from(错误.可自愈) as u8);
    输出缓冲.push(bool::from(错误.需人工) as u8);
    输出缓冲.push(bool::from(错误.已登记) as u8);
}

/// 定长槽**原样** 24 字节（小端）。
///
/// 不拆成五个字段写：槽形状是**冻结项**，拆写等于在本件里复刻一份槽布局，
/// 将来槽加宽就会两处不同步。直接按冻结的那五个字段拼一遍是最少知识。
fn 写槽(输出缓冲: &mut Vec<u8>, 数据槽: &v1_contract::数据槽) {
    输出缓冲.extend_from_slice(&数据槽.类型标签.取号值().to_le_bytes());
    输出缓冲.extend_from_slice(&数据槽.标志.to_le_bytes());
    输出缓冲.extend_from_slice(&数据槽.保留.to_le_bytes());
    输出缓冲.extend_from_slice(&数据槽.长度.to_le_bytes());
    输出缓冲.extend_from_slice(&数据槽.值.to_le_bytes());
}

fn 读参数项(读器: &mut 顺序读器) -> Option<接口参数项> {
    let 名称 = 读器.文本()?;
    let 类型标签 = 读器.读四字节()?;
    let 状态位 = 读器.读双字节()?;
    let 默认值 = 读器.读数据槽()?;
    Some(接口参数项 { 名称, 类型标签, 状态位, 默认值 })
}

fn 读错误项(读器: &mut 顺序读器) -> Option<接口错误项> {
    Some(接口错误项 {
        码: 读器.读四字节()?,
        段位: 读器.读四字节()?,
        名称: 读器.文本()?,
        可重试: 读器.逻辑型值()?,
        可自愈: 读器.逻辑型值()?,
        需人工: 读器.逻辑型值()?,
        已登记: 读器.逻辑型值()?,
    })
}
