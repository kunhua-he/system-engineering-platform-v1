//! 接口段编码 —— **转调**：实现已搬到契约层 `v1_contract::接口说明段`。
//!
//! # 为什么搬走（不是搬家玩，是读侧在底座）
//!
//! 原先本件是六字段编解码的**唯一实现**，只住扩展侧。但模块（`.模块制品`）没有本机机器码，
//! 底座载入器只能从制品的**接口说明段**读出「怎么调」（`扩展装载/后缀表.json` 的 `载入`）
//! ⇒ **读侧在底座**。而底座与扩展共用的层只有 `v1-contract`（`README.md` §六：底座不许跳层 ·
//! 扩展只读契约）⇒ 编解码必须住在那里，否则底座要么抄一份（第二套实现），要么看不到。
//!
//! 与 `容器.rs` 的「能力包件三段编解码只此一份」同一条理由 —— 只是那一份一直在契约层，
//! 这一份原先在扩展侧。
//!
//! # 本件为何留着（不是空壳）
//!
//! `1106` 的入参说明、命令表与若干注释都按 `src/能力包件/接口段编码.rs` 这个**路径**指路
//! （`命令声明面/参数表.rs` · `执行函数面/执行入口.rs` · `能力声明/1106.json`）。
//! 留一个转调件比让那些指路全部悬空好；且 `crate::能力包件::接口段编码::编码` 这个路径
//! 逐字不变 ⇒ 装包 · 执行入口 · 测试三处的调用点一处不用改。
//!
//! 字节排布、字段序与“不许尽力而为”的口径全在契约层那件里（**不复述** —— 复述就是第二个来源）。

