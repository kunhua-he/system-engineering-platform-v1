//! 判据落点 —— ③g / ③h 的**编译期断言**（扫描器只读这里的 const）。
//!
//! 为什么搬到编译期：表长与「参数表项数 ↔ 参数个数」只有**编译器**数得准。扫描器
//! （`测试验证/契约一致性/扫实现.py` 的 ③g / ③h）数的是声明文本 —— 换个命名或挪个
//! 位置就漏，是假绿的头号来源。改法：本文件用 `const _: () = assert!(…);` 把关系钉死，
//! 扫描器只读下面几个 const。口径见 `项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md`
//! §二 裁决 1（命令编号显式化 ⇒ 表长不再由号段跨度决定）· 裁决 5（编号必须落在申报号段内）。
//!
//! ③g 的另一个落点是 `包声明.rs` 的 `const 命令表项数: usize = 7;`（两处合起来才是「两表等长」）。
//!
//! 从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现）；三条断言与两个
//! 落点常量**一字不改**。
//!
//! ★ **这个洞拦不住什么（2026-09-28 补 · `项目文档/决策记录/2026-09-27_残留三项裁决.md`
//! §三 落法①）**：③h 是一般式的**逐条展开** —— `命令信息.参数表` 是裸指针无长度、
//! const 求值不许比指针，所以只能逐条列名。末条 `参数个数已核条数 == 表.len()` 只拦
//! 「加了命令没加断言」；**「同时改 `参数个数已核条数` 又不加断言」本文件拦不住**
//! （末条照样成立）。这条缺口由「处数判据」关小：`测试验证/契约一致性/扫实现/判据落点.py::比落点`
//! 读 `测试验证/契约一致性/处数基线.json`，把本单元的「已核条数 的值」与「逐条断言的行数」
//! 钉成固定值 —— **实测 ≠ 登记即红**。于是「两处同改」必须**故意**（改源码 + 改基线）才过，
//! 「顺手改一处」当场红。**边界**：它**不消除**「故意同时改两处」—— 那是人在骗门禁，
//! 不是门禁的洞。

use crate::能力号;
use crate::声明数据::包声明::{命令表项数, 表内位};

use super::参数表::{参数表_1103, 参数表_1106, 参数表_程序文本, 参数表_容器字节, 参数表_容器结构};
use super::命令表::{造命令表, 函数表};

/// ③g 落点：函数表的项数。**必须与 `命令表项数` 同值**（两表一一对应、等长）。
///
/// 为什么单独写一个数而不是直接复用 `命令表项数`：③g 判的是「两表等长」，两个数各写
/// 一处，扫描器读这两个 const 一比就能看出「只改了一边」；值对不对由下面三条断言钉死。
pub const 函数表项数: usize = 7;

// ③g 编译期断言：两张表的**真实长度**与各自的项数声明同值，且两表等长。
// 为什么用 `造命令表()`：命令表是 `static`，const 上下文不许读 static ⇒ 就地让编译器重算一次表长。
const _: () = assert!(造命令表().len() == 命令表项数, "③g：命令表项数 与 命令表 实际长度不符");
const _: () = assert!(函数表.len() == 函数表项数, "③g：函数表项数 与 函数表 实际长度不符");
const _: () = assert!(命令表项数 == 函数表项数, "③g：命令表与函数表必须等长");

/// ③h 落点：**已核条数** = 编译器逐条核过「参数表项数 == 参数个数」的命令条数。
///
/// 扫描器读它并与 `命令表项数` 比：少了就是有人加了命令却没加断言（不许静默少判）。
/// 值本身由下面同一段里的断言钉在表长上。
pub const 参数个数已核条数: usize = 7;

// ③h 编译期断言：逐条核「该条的 参数个数 == 它引用的参数表项数」。
// 为什么逐条列名（而不是循环遍历命令表）：`命令信息.参数表` 是**裸指针**，
// 编译期取不到被指数组的长度，也没有「指针 → 表」的编译期映射（const 求值不许比较指针）。
const _: () = {
    let 项表 = 造命令表();
    assert!(项表[表内位(能力号::词法分析)].参数个数 as usize == 参数表_程序文本.len(), "③h：1101 的 参数个数 与 参数表_程序文本 项数不符");
    assert!(项表[表内位(能力号::语法分析)].参数个数 as usize == 参数表_程序文本.len(), "③h：1102 的 参数个数 与 参数表_程序文本 项数不符");
    assert!(项表[表内位(能力号::语义分析)].参数个数 as usize == 参数表_1103.len(), "③h：1103 的 参数个数 与 参数表_1103 项数不符");
    assert!(项表[表内位(能力号::生成容器)].参数个数 as usize == 参数表_容器结构.len(), "③h：1104 的 参数个数 与 参数表_容器结构 项数不符");
    assert!(项表[表内位(能力号::反解容器)].参数个数 as usize == 参数表_容器字节.len(), "③h：1105 的 参数个数 与 参数表_容器字节 项数不符");
    assert!(项表[表内位(能力号::编译)].参数个数 as usize == 参数表_1106.len(), "③h：1106 的 参数个数 与 参数表_1106 项数不符");
    assert!(项表[表内位(能力号::诊断)].参数个数 as usize == 参数表_程序文本.len(), "③h：1107 的 参数个数 与 参数表_程序文本 项数不符");
    // 断言条数与表长必须相等：加一条命令就必须加一条断言，漏了这里当场编译不过。
    assert!(参数个数已核条数 == 项表.len(), "③h：已核条数 与 命令表项数 不符 —— 加了命令没加断言");
};
