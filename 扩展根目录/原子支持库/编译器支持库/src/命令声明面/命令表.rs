/// 带 `Sync` 的命令表外壳：`命令信息` 里有裸指针 ⇒ 不是 `Sync`，而 `static` 要求 `Sync`。
/// 表编译期冻结、只读，对外只给 `*const` 指针，故共享只读安全。
///
/// 为什么做成 `static` 而不是 `const`：表要的是**唯一实例** —— `const` 数组在
/// **每个使用点各拷一份**，而 `扩展声明().命令表.项表` 必须指向同一份表。
#[repr(transparent)]
pub(crate) struct 静态命令表(pub(crate) [命令信息; 命令表项数]);

// SAFETY: 表一旦构造即终生不变；不提供 &mut 通道，对外只交出 *const 指针。
unsafe impl Sync for 静态命令表 {}

/// 命令表（下标 = 编号 − 表首号）。
pub(crate) static 命令表存储: 静态命令表 = 静态命令表(造命令表());

/// 保留项执行函数：**当前无一条命令走它**（七条全已真实现），它是**兵底** ——
/// `造函数表` 的初值，也是「命令表加了位而函数表漏覆写」时的诚实状态：
/// 它写的是结构化错误码（提供者未载入），**不是假成功**。
///
/// 正常路径下调度侧会先看到 `命令状态::错误` 并直接返回 `提供者未载入`，
/// 本函数不会被调到；它是"直接按函数表调"时的兜底，语义与调度侧一致。
pub(crate) unsafe extern "C" fn 保留项执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    let _ = (参数个数, 参数表);
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 返回槽 由调用方保证可写。
    unsafe { 写错误槽(返回槽, 错误码_1.取号值()) };
}

/// 造函数表。七条命令**全部**指向真实现（含 1106 编译）。
///
/// 为什么仍用 `保留项执行` 作初值：它是「没覆写」的兵底 —— `命令表项数` 若有天加一位而
/// `造函数表` 漏覆写，那位会得到「提供者未载入」的结构化失败（**不是崩溃、不是假成功**），
/// 由测试 `契约形状_保留项_写结构化失败` 的名单断言当场报出。**当前七位无一走它。**
///
/// **表长与命令表同值**（`命令表项数`）：函数表的下标就是命令表的下标，一一对应。
pub const fn 造函数表() -> [执行函数; 命令表项数] {
    let mut 本表 = [保留项执行 as 执行函数; 命令表项数];
    本表[命令表内位(能力号::词法分析)] = 词法分析执行;
    本表[命令表内位(能力号::语法分析)] = 语法分析执行;
    本表[命令表内位(能力号::语义分析)] = 语义分析执行;
    本表[命令表内位(能力号::生成容器)] = 生成容器执行;
    本表[命令表内位(能力号::反解容器)] = 反解容器执行;
    本表[命令表内位(能力号::编译执行)] = 编译执行;
    本表[命令表内位(能力号::诊断)] = 诊断执行;
    本表
}

/// 函数表：与命令表**等长**，一一对应（同一下标 = 同一条命令）。**不许留空指针。**
pub(crate) const 执行函数表: [执行函数; 命令表项数] = 造函数表();
