//! 容器结构的边界编码。
//!
//! 跨边界只有定长数据槽，所以 `容器.rs` 的 `容器` 结构要过边界必须先编成字节集。
//! 本件**只做字段搬运**，不含任何 `.e` 格式知识（段头偏移 · 名称区异或全在 `容器.rs`）——
//! 它不是「第二套反解/生成」，是那个结构的一份编码。段内容那一层是 `记录流.rs`，不是这里。
//!
//! 编码（一律小端）：
//!   u32 段数
//!   每段：u32 校验和 · u8 段类型 · 27 字节名称区 · u32 段名长 + 段名字节 · u64 数据长 + 数据字节
//!   （旁路区，尾部追加：u32 未知段号数 + 逐个 u8 未知段号 · u32 嵌套段数 + 逐个 u64 偏移
//!     · u32 异常数 + 逐项(u8 种类 + 载荷)）
//!
//! ★ 旁路三表（`未知段号表` · `嵌套段表` · `自检异常表`）都是**只读报告**，
//! **旧读者读前缀仍成立**（尾部追加）。三表一律带过来：结构等价判据要求逐字段相等。
//!
//! 名称区与段名都带上：名称区是反解侧对盘面的快照，段名是它的明文，两个都带才与
//! `容器.rs` 的结构逐字段等价（`生成` 只读段名重算名称区，但等价性判据要全字段）。
//!
//! 从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现）；函数体一字不改。

use crate::容器::{容器段, 段头, 自检异常, 容器};
use crate::顺序读器::顺序读器;

/// 结构 → 字节集。
pub fn 编码容器(容器: &容器) -> Vec<u8> {
    let mut 输出缓冲 = Vec::new();
    输出缓冲.extend_from_slice(&(容器.段表.len() as u32).to_le_bytes());
    for 容器段 in &容器.段表 {
        输出缓冲.extend_from_slice(&容器段.段头字段.校验和.to_le_bytes());
        输出缓冲.push(容器段.段头字段.段类型);
        输出缓冲.extend_from_slice(&容器段.段头字段.名称区);
        输出缓冲.extend_from_slice(&(容器段.段头字段.段名.len() as u32).to_le_bytes());
        输出缓冲.extend_from_slice(&容器段.段头字段.段名);
        输出缓冲.extend_from_slice(&(容器段.数据字节.len() as u64).to_le_bytes());
        输出缓冲.extend_from_slice(&容器段.数据字节);
    }
    // 旁路区（尾部追加）：未知段号表 · 嵌套段表。
    输出缓冲.extend_from_slice(&(容器.未知段号表.len() as u32).to_le_bytes());
    输出缓冲.extend_from_slice(&容器.未知段号表);
    输出缓冲.extend_from_slice(&(容器.嵌套段表.len() as u32).to_le_bytes());
    for 偏移量 in &容器.嵌套段表 {
        输出缓冲.extend_from_slice(&偏移量.to_le_bytes());
    }
    输出缓冲.extend_from_slice(&(容器.自检异常表.len() as u32).to_le_bytes());
    for 异常项 in &容器.自检异常表 {
        match 异常项 {
            自检异常::段头校验不符 { 第几段, 期望, 实取 } => {
                输出缓冲.push(0);
                输出缓冲.extend_from_slice(&第几段.to_le_bytes());
                输出缓冲.extend_from_slice(&期望.to_le_bytes());
                输出缓冲.extend_from_slice(&实取.to_le_bytes());
            }
            自检异常::段序号不连号 { 第几段, 序号 } => {
                输出缓冲.push(1);
                输出缓冲.extend_from_slice(&第几段.to_le_bytes());
                输出缓冲.extend_from_slice(&序号.to_le_bytes());
            }
            自检异常::体长与实长不符 { 第几段, 头内, 实有 } => {
                输出缓冲.push(2);
                输出缓冲.extend_from_slice(&第几段.to_le_bytes());
                输出缓冲.extend_from_slice(&头内.to_le_bytes());
                输出缓冲.extend_from_slice(&实有.to_le_bytes());
            }
            自检异常::文件大小恒等式不成立 { 应有, 实有 } => {
                输出缓冲.push(3);
                输出缓冲.extend_from_slice(&应有.to_le_bytes());
                输出缓冲.extend_from_slice(&实有.to_le_bytes());
            }
        }
    }
    输出缓冲
}

/// 字节集 → 结构。`None` = 编码非法（长度字段与实到字节数不符，或尾部有多余字节）。
pub fn 解码容器(字节: &[u8]) -> Option<容器> {
    let mut 读游标 = 顺序读器 { 字节, 游标位: 0 };
    let 段数 = 读游标.读四字节()?;
    let mut 段表 = Vec::new();
    for _ in 0..段数 {
        let 校验和 = 读游标.读四字节()?;
        let 段类型 = 读游标.读单字节()?;
        let mut 名称区 = [0u8; 27];
        名称区.copy_from_slice(读游标.取字节(27)?);
        let 名长 = 读游标.读四字节()? as usize;
        let 段名 = 读游标.取字节(名长)?.to_vec();
        let 数长 = 读游标.读八字节()? as usize;
        let 数据字节 = 读游标.取字节(数长)?.to_vec();
        段表.push(容器段 {
            段头字段: 段头 { 校验和, 段类型, 名称区, 段名 },
            数据字节,
        });
    }
    // 旁路区（尾部追加）：旧读者读到段表尾就结束了；本件按新形状读全。
    let 未知个数 = 读游标.读四字节()? as usize;
    let 未知段号表 = 读游标.取字节(未知个数)?.to_vec();
    let 嵌套个数 = 读游标.读四字节()? as usize;
    let mut 嵌套段表 = Vec::with_capacity(嵌套个数);
    for _ in 0..嵌套个数 {
        嵌套段表.push(读游标.读八字节()?);
    }
    let 异常个数 = 读游标.读四字节()? as usize;
    let mut 自检异常表 = Vec::with_capacity(异常个数);
    for _ in 0..异常个数 {
        let 异常种类 = 读游标.读单字节()?;
        自检异常表.push(match 异常种类 {
            0 => 自检异常::段头校验不符 {
                第几段: 读游标.读四字节()?,
                期望: 读游标.读四字节()?,
                实取: 读游标.读四字节()?,
            },
            1 => 自检异常::段序号不连号 {
                第几段: 读游标.读四字节()?,
                序号: 读游标.读四字节()?,
            },
            2 => 自检异常::体长与实长不符 {
                第几段: 读游标.读四字节()?,
                头内: 读游标.读八字节()?,
                实有: 读游标.读八字节()?,
            },
            3 => 自检异常::文件大小恒等式不成立 {
                应有: 读游标.读八字节()?,
                实有: 读游标.读八字节()?,
            },
            _ => return None,
        });
    }
    // 尾部有多余字节 ⇒ 非法（不许"尽力而为"地忽略）。
    if 读游标.游标位 != 字节.len() {
        return None;
    }
    Some(容器 { 段表, 未知段号表, 嵌套段表, 自检异常表 })
}
