//! 带号结构（1103 产物）的边界编码。
//!
//! 与 `结构编码` / `原生路编码` **同一条规矩**：跨边界只有定长数据槽，结构要过边界必须先编成
//! 字节集；本件**只做字段搬运**，不含任何语义知识（定号与解析全在 `语义/建表.rs`）。
//! 为什么必须有它：`能力声明/1103.json` 的返回类型是 5（字节集），而产物是 `带号结构`
//! —— 那份结构过不了边界，除非先编成字节。编解码只有这一处，不另起第二套。
//!
//! 编码（一律小端）：
//!   号表：u32 项数 · 每项 (u8 类 · u8 作用域 · u16 号 · u32 名长 + 名)
//!   引用表：u32 项数 · 每项 (u32 节点下标 · u8 类 · u8 号来源 · u16 号 · u8 作用域)
//!
//! ⚠ 如实划界（不许被读成 `.e` 记录区形状）：本编码**只表示「名字 → 号」的解析结果**，
//! **不表示** `.e` 声明记录区的五类分区边界、令牌 `<u16 号><u8 参中字节><u8 令牌类别>` 的字段语义、
//! 语句字节码操作码表 —— 那三处是 `说明/声明记录区取证.md` §二 单列的不判项。
//!
//! 从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现）；函数体一字不改。

use crate::语义::带号结构;

/// 带号结构 → 字节集。
pub fn 编码带号结构(构: &带号结构) -> Vec<u8> {
    let mut 出 = Vec::new();
    出.extend_from_slice(&(构.号表.len() as u32).to_le_bytes());
    for 项 in &构.号表 {
        出.push(项.类.号());
        出.push(项.作用域 as u8);
        出.extend_from_slice(&项.号.to_le_bytes());
        出.extend_from_slice(&(项.名.len() as u32).to_le_bytes());
        出.extend_from_slice(&项.名);
    }
    出.extend_from_slice(&(构.引用表.len() as u32).to_le_bytes());
    for 项 in &构.引用表 {
        出.extend_from_slice(&项.节点.to_le_bytes());
        出.push(项.类.号());
        出.push(项.来源.号());
        出.extend_from_slice(&项.号.to_le_bytes());
        出.push(项.作用域 as u8);
    }
    出
}
