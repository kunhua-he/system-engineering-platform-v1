//! 词法 —— **能力 1101 词法分析的实现**：把我们的程序文本切成记号流。
//!
//! 上级：`扩展根目录/原子支持库/编译器支持库/` ／ 形状：`src/语言面/`（**已冻结，本腿一字不改**）
//! 相关：`项目文档/设计文档/程序文本格式.md`（被实现的规格）· `说明/真文本覆盖.md`（53 份真文本的实测读数）·
//! `说明/语言面形状.md`（形状与不变量 J1–J6）
//!
//! # 本件只做三件事
//!
//! 1. 声明两个子模块（[`字符集`] 回答「哪个字符归哪一类」· [`切分`] 做切分）；
//! 2. 再导出公开面 [`切记号`]；
//! 3. **零实现**。
//!
//! # 公开面
//!
//! ```text
//! 词法::切记号(原文: &str) -> Result<记号流, 形状错误>
//! ```
//!
//! 产出的类型**一字不改地用 `语言面` 里既有的三个**（`use crate::语言面::{记号, 记号流, 记号种类}`），
//! 不另造一套 —— 记号流是下游 1102/1103/1107 共用的脊梁，另造一套就是「同一件事两套实现」。
//!
//! # 为什么签名里有 `Result` 却从不失败
//!
//! `Result` 来自唯一构造口 `记号流::新建`（它判死 J1–J6，失败给 10 条记号层码 1108–1117）。
//! 但**切分器是总函数**：任何 `&str` 都有确定切法（规格 §二 的 11 类之外的一切字符并进
//! `标识符`，见 `切分.rs` 文件头「兜底」），所以经 [`切记号`] 走到那 10 条码的路**不存在**。
//! 那 10 条码是构造口的防御面，不是本函数的失败面；1101 声明的可抛错误码恰好就是这 10 条
//! （`能力声明/1101.json`）——**没有任何一条能吃「词法层输入非法」**，这是一处已登记的缺口
//! （见 `说明/语言面形状.md` 第六节待办 5 的同族问题）。
//!
//! # 两条工具链强制（与 `语言面.rs` 同源，实测过）
//!
//! 1. rustc 拒绝自动加载非 ASCII 文件名的模块（E0754），故每条 `mod` 都显式给 `#[path]`；
//! 2. 模块名不能与它再导出的同名项撞（E0255），故模块名带后缀，`pub use` 出来的才是公开面。

