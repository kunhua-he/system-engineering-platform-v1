/// 1107 诊断：合法程序文本 / 空文本 → 「覆盖到的阶段（1101 · 1102）全过」的标记字节集。
///
/// **`None` 的字节集口径：1 字节标签 0** —— 不是空字节集（空 = 没跑，下一条用例）。
/// 「全过」**不是**「编译成功」（1103/1106 都已落地，但 1107 的入参拿不到它们要的三张注册表
/// ⇒ 覆盖不到；`诊断/入口.rs` 文件头的诚实口径）。
#[test]
fn 契约形状_诊断_覆盖阶段全过_一字节标记() {
    for 原文 in [真程序文本, ""] {
        // 与直接调 整理诊断 同结论（引号配对、< 4 GiB ⇒ 切分与建树都不报错 ⇒ None）。
        assert_eq!(诊断::整理诊断(原文), None, "{原文:?}：覆盖到的阶段该全过");

        let 参数 = 文本槽(原文);
        let mut 返回槽 = 数据槽::空槽();
        // SAFETY: 按契约形状调用：返回槽可写、参数个数 1、参数表指向一个文本槽。
        unsafe { 诊断执行(&mut 返回槽, 1, &参数) };

        assert_eq!(返回槽.类型标签, 类型标签_0005, "返回槽该是字节集");
        // SAFETY: 返回槽由 诊断执行 刚写出。
        let 字节 = unsafe { 取返回字节(&返回槽) };
        assert_eq!(字节, [0u8], "{原文:?}：None 的字节集 = 1 字节标签 0");
        assert!(!字节.is_empty(), "{原文:?}：全过不许用空字节集表示（空 = 没跑）");
        assert_eq!(解诊断(&字节), 诊断解::全过, "{原文:?}：解出来该是「全过」");
        // SAFETY: 槽来自本测试刚调用的执行函数。
        unsafe { 释放返回字节(&返回槽) };
    }
}

/// 1107 诊断：入参槽不合契约 ⇒ **空字节集 = 「没跑」**。
///
/// 可抛错误码是**空表**（契约就是空表）⇒ 不许写错误槽；空字节集与「全过」的
/// 1 字节标签 0 可区分（上一条用例钉住），同一个空字节集不许表示两种意思。
#[test]
fn 契约形状_诊断_槽形不合_空字节集表示没跑() {
    let 坏槽表: [(&str, 数据槽); 3] = [
        ("字节集槽（类型标签 5）", 字节集槽(真程序文本.as_bytes())),
        ("空槽（类型标签 0）", 数据槽::空槽()),
        ("文本标签的内联槽（非引用）", 数据槽::内联(类型标签_0004.into(), 0, 0)),
    ];
    for (名称, 坏槽) in &坏槽表 {
        let mut 返回槽 = 数据槽::空槽();
        // SAFETY: 按契约形状调用（槽本身形状不对，正是要测的）。
        unsafe { 诊断执行(&mut 返回槽, 1, 坏槽) };
        assert_eq!(
            返回槽.类型标签, 类型标签_0005,
            "{名称}：返回槽该仍是字节集 —— 可抛错误码空表，不许写错误槽"
        );
        // SAFETY: 返回槽由 诊断执行 刚写出。
        let 字节 = unsafe { 取返回字节(&返回槽) };
        assert!(字节.is_empty(), "{名称}：没跑 = 空字节集");
        // SAFETY: 槽来自本测试刚调用的执行函数。
        unsafe { 释放返回字节(&返回槽) };
    }

    // 参数个数不足（0 个槽）同样没跑，不许拿默认值硬跑。
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 参数个数 0，参数表给一个有效槽 —— 位次越界正是要测的。
    unsafe { 诊断执行(&mut 返回槽, 0, &文本槽(真程序文本)) };
    // SAFETY: 返回槽刚写出。
    let 字节 = unsafe { 取返回字节(&返回槽) };
    assert!(字节.is_empty(), "参数个数 0：没跑 = 空字节集");
    // SAFETY: 槽来自本测试刚调用的执行函数。
    unsafe { 释放返回字节(&返回槽) };
}

/// 1107 诊断：**诊断路径**（一条结构化诊断）的编码 —— 阶段 · 码 · 位置（能定位）· 读数。
///
/// 为什么靠注入：`建树` 是**总函数**、`切记号` 只在引号不配对时报 1137 ⇒ 经 `整理诊断`
/// 走到 `Some` 的路只有这一条（`诊断/入口.rs` 文件头 · `诊断/测试/入口.rs` 同一口径）——
/// 其余码的失败路径只能靠注入一级的结论来验。本用例照这个口径在编码腿上打两级样本：
/// 词法级（自带字节区间 ⇒ **能定位**）与语法级（只带下标 ⇒ 位置给 `None`，不编一个位置）。
#[test]
fn 契约形状_诊断_诊断路径编码_阶段码位置读数() {
    use crate::语言面::形状错误 as 形状;

    let 诊断样例 = [
        // 词法级：记号有缝隙（码 1112）—— 无归属的是 [前止, 后起)，能定位。
        (
            形状::记号有缝隙 { 第几个: 0, 前止: 5, 后起: 7 },
            能力号::词法分析,
            错误码::记号有缝隙,
            Some((5u32, 7u32)),
        ),
        // 语法级：父未包住子（码 1126）—— 只带节点下标，给不出字节位置。
        (
            形状::父未包住子 { 父: 0, 子: 1 },
            能力号::语法分析,
            错误码::父未包住子,
            None,
        ),
    ];
    for (错误, 阶段, 错误码, 位置) in &诊断样例 {
        let 读数 = 诊断::读数(错误);
        let 字节 = 原生路编码::编码诊断结果(Some(错误));

        // 解出来逐字段对上（阶段 · 码 · 位置 · 读数）。
        assert_eq!(
            解诊断(&字节),
            诊断解::一条诊断(*阶段, *错误码, *位置, 读数.clone()),
            "{错误码}：编码→解 必须回到同一条诊断"
        );

        // 布局钉死：1 字节标签 + 阶段/码/位标志 3×u32 +（有位置再 2×u32）+ u32 读数长 + 读数。
        assert_eq!(字节[0], 1, "{错误码}：一条诊断的标签该是 1");
        let 位置长 = if 位置.is_some() { 8 } else { 0 };
        let 期望长 = 1 + 4 + 4 + 4 + 位置长 + 4 + 读数.len();
        assert_eq!(字节.len(), 期望长, "{错误码}：诊断编码的布局漂了");
    }
}
