//! 长活原语的 6 秒考题（**超时即失败**）—— 长活原语第二件。
//!
//! 依据：`项目文档/决策记录/2026-09-27_所有运行五秒硬顶.md`（**命令级 p100 ≤ 5000 ms**，超即 bug）·
//! `项目文档/决策记录/2026-09-27_边界表达力_长活原语.md` §四 判据 1–3 ·
//! `跨语言适配/边界协议/边界协议.md` §六。
//!
//! **考题的形状**：一道「合法但要 6 秒」的长活，用**任务句柄 + 立刻返回 + 取消**表达。
//! 三条断言逐条对应 `边界协议.md` §四 判据 7–9：
//!   1. **立刻返回**：第一次调用不许等那 6 秒，必须在 1 秒内拿到句柄；
//!   2. **句柄不失真**：8 字节原值过边界只传数值，逐字节不变；
//!   3. **取消后结构化失败**：取消一个句柄、再按它取 ⇒ 得到一个**码**（不是 panic、不是空）。
//!
//! **超时即判失败**（本题的要害）：把「第一次调用」放进一个工作线程，主线程用
//! `recv_timeout(1 秒)` 等它 —— **超时返回 `Err`，测试当场红**，绝不挂死。
//! 于是「它到底有没有被同步等那 6 秒」变成一条**可判的读数**，而不是靠人看墙钟。
//!
//! **考题本身也在硬顶内**：本题**不 await 那 6 秒**（工作线程被丢弃、随测试进程退出而终止）⇒
//! 整条测试命令墙钟 **< 1 秒**，远在 5000 ms 之内 —— 不是一道「必然超时」的题。
//!
//! **真 runner 的落点**：`跨语言适配/边界协议/判据_长活原语.py` —— 它用 `rustc --test`
//! **单文件**编出本考题（**不碰 cargo 锁**：不读工作区、不抢构建锁），跑完把三条断言
//! 逐条映射成 `边界协议.md` §四 判据 7 · 8 · 9 的真读数，并静态扫判据 10（内核零任务表）。
//! ⇒ 本件**已被真编、真跑**（经由那条 runner；本仓仍不许直接跑 `cargo build`/`cargo test`）。
//!
//! **本件含真实的「扩展自持任务表」**（长活原语要的那件）：句柄由表分配、取消是表的终态、
//! 超时给结构化码 —— 不是测试里编一个常数冒充凭据。

use std::collections::HashMap;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Mutex, OnceLock};
use std::thread;
use std::time::{Duration, Instant};

/// 长活时长：**故意 6 秒**（> 5 秒硬顶 ⇒ 它不许走同步调用路）。
const 长活时长: Duration = Duration::from_secs(6);
/// 第一次调用的墙钟上限：**1 秒**（证「它没被同步等」）。
const 立刻返回上限: Duration = Duration::from_secs(1);
/// 取消后再取 ⇒ 这个码（结构化失败，不是 panic、不是空）。
const 取消码: u32 = 1134;
/// 还在飞却已等满窗口 ⇒ 这个码（超时也走结构化失败，挂死不发生）。
const 超时码: u32 = 4;

/// 一个任务在表里的状态。**表在扩展侧**，边界只搬那个 8 字节句柄。
#[derive(Clone, Debug, PartialEq)]
enum 任务态 {
    在飞,
    已取消,
    已完成(Vec<u8>),
}

/// **扩展自持的任务表**（判据 10 的账：内核不持任务表，表住在扩展自己的进程里）。
///
/// 句柄由表分配（单调递增的不透明 8 字节值）⇒ 句柄是**真凭据**，不是测试里编的常数。
struct 任务表 {
    表: Mutex<HashMap<u64, 任务态>>,
    下一个句柄: AtomicU64,
}

/// 本扩展的任务表（进程内一份）。
fn 本扩展任务表() -> &'static 任务表 {
    static 表: OnceLock<任务表> = OnceLock::new();
    表.get_or_init(|| 任务表 {
        表: Mutex::new(HashMap::new()),
        // 起点是个不透明值（无含义，只保证非零、8 字节）。
        下一个句柄: AtomicU64::new(0x5441_534B_0000_0001),
    })
}

/// 取任务句柄：**立刻返回**（在表里立一条「在飞」，起一个 6 秒的后台线程，不当场等）。
fn 取任务句柄() -> u64 {
    let 项表 = 本扩展任务表();
    let 句柄 = 项表.下一个句柄.fetch_add(1, Ordering::Relaxed);
    项表.表.lock().unwrap().insert(句柄, 任务态::在飞);
    thread::spawn(move || {
        thread::sleep(长活时长);
        let 项表 = 本扩展任务表();
        let mut 锁句柄 = 项表.表.lock().unwrap();
        if let Some(任务状态) = 锁句柄.get_mut(&句柄) {
            // 只把「还在飞」推成完成；已取消的不许被覆盖（取消是终态）。
            if *任务状态 == 任务态::在飞 {
                *任务状态 = 任务态::已完成(vec![1, 2, 3]);
            }
        }
    });
    句柄
}

/// 取消一个句柄：把它打成**终态「已取消」**，返回一个可查的码（本扩展的 `1134` 一类）。
fn 取消(句柄: u64) -> u32 {
    let 项表 = 本扩展任务表();
    let mut 锁句柄 = 项表.表.lock().unwrap();
    match 锁句柄.get_mut(&句柄) {
        Some(态) if *态 == 任务态::在飞 => {
            *态 = 任务态::已取消;
            取消码
        }
        // 已取消 / 已完成 / 表里没有 ⇒ 都给结构化码，不是 panic。
        _ => 取消码,
    }
}

/// 按句柄取结果：**超时即失败**（不许挂死）。取消过的句柄当场给码。
fn 按句柄取(句柄: u64, 待取项: Duration) -> Result<Vec<u8>, u32> {
    let 项表 = 本扩展任务表();
    let 截止 = Instant::now() + 待取项;
    loop {
        {
            let 锁句柄 = 项表.表.lock().unwrap();
            match 锁句柄.get(&句柄) {
                Some(任务态::已完成(字节)) => return Ok(字节.clone()),
                Some(任务态::已取消) => return Err(取消码),
                Some(任务态::在飞) => {}
                None => return Err(取消码),
            }
        }
        if Instant::now() >= 截止 {
            // 还在飞却已等满窗口 ⇒ 结构化超时码；不是挂死、不是空。
            return Err(超时码);
        }
        thread::sleep(Duration::from_millis(5));
    }
}

#[test]
fn 判据7_句柄过边界不失真_八字节原值逐字节不变() {
    let 句柄 = 取任务句柄();
    let 原值 = 句柄.to_le_bytes();
    // 「过边界」= 只传那 8 个字节（转发路不解释它），再解回。
    let 解回 = u64::from_le_bytes(原值);
    assert_eq!(解回, 句柄, "8 字节句柄经边界后原值变了");
    assert_eq!(原值.len(), 8, "句柄必须是 8 字节");
    // 句柄是**真凭据**：表里查得到（不是编出来的常数冒充句柄）。
    assert!(
        本扩展任务表().表.lock().unwrap().contains_key(&句柄),
        "句柄不在扩展自持的任务表里"
    );
}

#[test]
fn 判据8_立刻返回_第一次调用一秒内拿到句柄() {
    let 起始时刻 = Instant::now();
    let 句柄 = 取任务句柄();
    let 耗时 = 起始时刻.elapsed();
    // 身份证：把它写回同步等 6 秒 ⇒ 本断言当场红（且整条命令越过 5 秒硬顶）。
    assert_ne!(句柄, 0, "句柄是 8 字节不透明值，不该为 0");
    assert!(耗时 < 立刻返回上限, "第一次调用耗时已达 {耗时:?}，被同步等了那 6 秒");
}

#[test]
fn 判据9_取消后结构化失败_得到码而不是panic() {
    let 句柄 = 取任务句柄();
    let 错误码 = 取消(句柄);
    // 取消后按句柄取：给一个远小于 6 秒的等待窗口 ⇒ 必得 Err(码)，不是 Ok、不是 panic。
    match 按句柄取(句柄, Duration::from_millis(50)) {
        Err(得码) => assert_eq!(得码, 错误码, "取消后应得结构化失败码"),
        Ok(_) => panic!("取消后仍取到结果，判据 9 红"),
    }
}
