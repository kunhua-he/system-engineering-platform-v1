//! 长活原语的 6 秒考题（**超时即失败**）—— 台账 #213 长活原语第二件。
//!
//! 依据：`项目文档/决策记录/2026-09-27_所有运行五秒硬顶.md`（**命令级 p100 ≤ 5000 ms**，超即 bug）·
//! `项目文档/决策记录/2026-09-27_边界表达力_长活原语.md` §四 判据 1–3 ·
//! `跨语言适配/边界协议/边界协议.md` §六。
//!
//! **考题的形状**：一道「合法但要 6 秒」的长活，用**任务句柄 + 立刻返回 + 取消**表达。
//! 三条断言逐条对应 `边界协议.md` §四 判据 7–9：
//!   1. **立刻返回**：第一次调用不许等那 6 秒，必须在 1 秒内拿到句柄；
//!   2. **句柄不失真**：8 字节原值过边界只传数值，逐字节不变；
//!   3. **取消后结构化失败**：取消一个句柄、再按它取 ⇒ 得到一个**码**（不是 panic、不是空）。
//!
//! **超时即判失败**（本题的要害）：把「第一次调用」放进一个工作线程，主线程用
//! `recv_timeout(1 秒)` 等它 —— **超时返回 `Err`，测试当场红**，绝不挂死。
//! 于是「它到底有没有被同步等那 6 秒」变成一条**可判的读数**，而不是靠人看墙钟。
//!
//! **考题本身也在硬顶内**：本题**不 await 那 6 秒**（工作线程被丢弃、随测试进程退出而终止）⇒
//! 整条测试命令墙钟 **< 1 秒**，远在 5000 ms 之内 —— 不是一道「必然超时」的题。
//!
//! **诚实标注**：本件是**考题形状（可跑骨架）**，**不是真 runner** —— 真 runner 要扩展侧真出一道
//! 「故意 6 秒」的能力（能力号 + 扩展自持的任务表），那属 1106/扩展侧的后续腿。
//! **本腿不许跑 cargo ⇒ 本考题未编译、未运行**（只过 rustfmt 语法检查）。

use std::sync::mpsc;
use std::thread;
use std::time::{Duration, Instant};

/// 长活时长：**故意 6 秒**（> 5 秒硬顶 ⇒ 它不许走同步调用路）。
const 长活时长: Duration = Duration::from_secs(6);
/// 第一次调用的墙钟上限：**1 秒**（证「它没被同步等」）。
const 立刻返回上限: Duration = Duration::from_secs(1);

/// 一个「合法但要 6 秒」的长活任务：**立刻返回句柄**，结果过会儿从通道来。
///
/// 句柄 = 不透明 8 字节值（类型标签 = 任务句柄，见 `契约声明/类型声明/0007.json`）。
/// **谁持状态 = 扩展自身**：任务在后台线程里跑，句柄只是那个线程的取件凭据（边界不持状态）。
struct 长活任务 {
    句柄: u64,
    结果: mpsc::Receiver<Result<Vec<u8>, u32>>,
}

/// 取任务句柄：**立刻返回**（不阻塞、不等那 6 秒）。
fn 取任务句柄() -> 长活任务 {
    let (发, 收) = mpsc::channel();
    let 句柄 = 0x5441_534b_0000_0001u64; // 不透明 8 字节值；测试里用固定值便于断言
    thread::spawn(move || {
        thread::sleep(长活时长);
        // 6 秒后才出结果；若调用方取消了，这个 send 会失败（接收端已丢）——忽略即可。
        let _ = 发.send(Ok(vec![1, 2, 3]));
    });
    长活任务 { 句柄, 结果: 收 }
}

/// 取消一个句柄：取消后按它取 ⇒ **结构化失败码**（这里用本扩展的 `1134` 一类码占位）。
fn 取消(_句柄: u64) -> u32 {
    1134
}

/// 按句柄取结果：**超时即失败**（不许挂死）。
fn 按句柄取(任务: &长活任务, 等: Duration) -> Result<Vec<u8>, u32> {
    match 任务.结果.recv_timeout(等) {
        Ok(Ok(字节)) => Ok(字节),
        Ok(Err(码)) => Err(码),
        // 超时 / 断线 ⇒ 结构化失败，不是 panic、不是空。
        Err(_) => Err(取消(任务.句柄)),
    }
}

#[test]
fn 判据8_立刻返回_第一次调用一秒内拿到句柄() {
    let (发回, 收回) = mpsc::channel();
    let 起 = Instant::now();
    thread::spawn(move || {
        let 任务 = 取任务句柄();
        let _ = 发回.send((任务.句柄, 起.elapsed()));
        // 故意**不**把 任务 交给别处：证明「拿到句柄」这一步本身不等 6 秒。
        drop(任务);
    });
    // 超时即判失败：1 秒内没拿到 ⇒ Err ⇒ expect 触发 ⇒ 测试红（不是挂死）。
    let (句柄, 耗时) = 收回
        .recv_timeout(立刻返回上限)
        .expect("第一次调用没有在 1 秒内返回句柄（被同步等了 6 秒？）—— 判据 8 红");
    assert_ne!(句柄, 0, "句柄是 8 字节不透明值，不该为 0");
    assert!(耗时 < 立刻返回上限, "第一次调用耗时 {耗时:?} ≥ 1 秒");
}

#[test]
fn 判据7_句柄过边界不失真_八字节原值逐字节不变() {
    let 任务 = 取任务句柄();
    let 原值 = 任务.句柄.to_le_bytes();
    // 「过边界」= 只传那 8 个字节（转发路不解释它），再解回。
    let 解回 = u64::from_le_bytes(原值);
    assert_eq!(解回, 任务.句柄, "8 字节句柄经边界后原值变了");
    assert_eq!(原值.len(), 8, "句柄必须是 8 字节");
}

#[test]
fn 判据9_取消后结构化失败_得到码而不是panic() {
    let 任务 = 取任务句柄();
    let 码 = 取消(任务.句柄);
    // 取消后按句柄取：给一个远小于 6 秒的等待窗口 ⇒ 必得 Err(码)，不是 Ok、不是 panic。
    match 按句柄取(&任务, Duration::from_millis(50)) {
        Err(得码) => assert_eq!(得码, 码, "取消后应得结构化失败码"),
        Ok(_) => panic!("取消后仍取到结果 —— 判据 9 红"),
    }
}
