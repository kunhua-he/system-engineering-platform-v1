/// 反解容器：手工造数据槽入参 → 调执行函数 → 从返回槽取结果，
/// 断言与**直接调** `容器::反解` 得到同一个结论（逐字段相同）。
#[test]
fn 契约形状_反解容器_与直接反解同结论() {
    let 容 = 样例容器();
    let 原文 = 容器::生成(&容).expect("生成样例容器");

    let 参 = 字节集槽(&原文);
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 按契约形状调用：返回槽可写、参数个数 1、参数表指向一个字节集槽。
    unsafe { 反解容器执行(&mut 返回槽, 1, &参) };

    assert_eq!(返回槽.类型标签, 类型标签_0005, "成功时返回槽该是字节集");
    // SAFETY: 返回槽由 反解容器执行 刚写出。
    let 结构字节 = unsafe { 取返回字节(&返回槽) };

    // 直接调 容器::反解 的结论。
    let 直 = 容器::反解(&原文).expect("直接反解应成功");
    // 从执行函数的返回槽解出来的结论。
    let 经槽 = 结构编码::解码容器(&结构字节).expect("返回槽里的结构编码该能解出来");

    assert_eq!(经槽, 直, "经执行函数与直接反解必须得到同一个结构");
    assert_eq!(经槽.段表.len(), 1);
    assert_eq!(经槽.段表[0].头.段名, 直.段表[0].头.段名);
    assert_eq!(经槽.段表[0].数据, 直.段表[0].数据);
    // 往返判据：生成(反解(x)) == x 逐字节相同。
    assert_eq!(容器::生成(&经槽).expect("再生成"), 原文);

    // SAFETY: 槽来自本测试刚调用的执行函数。
    unsafe { 释放返回字节(&返回槽) };
}

/// 反解容器：坏输入必须写**同一个结构化错误码**（不是 panic、不是空结果）。
#[test]
fn 契约形状_反解容器_坏输入写同一个错误码() {
    // 魔数不符。
    let 坏 = b"NOTMAGIC";
    let 参 = 字节集槽(坏);
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 按契约形状调用。
    unsafe { 反解容器执行(&mut 返回槽, 1, &参) };
    assert_eq!(返回槽.类型标签, 类型标签_4294967295, "失败该写错误槽");
    assert_eq!(返回槽.值, 错误码::魔数不符 as u64);
    assert_eq!(
        容器::反解(坏),
        Err(容器::反解错误::魔数不符),
        "与直接反解同一个结论"
    );

    // 段头截断（魔数对、不足 44 字节）。
    let 截 = b"CNWTEPRG\x19\x73\x11\x15";
    let 参 = 字节集槽(截);
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 同上。
    unsafe { 反解容器执行(&mut 返回槽, 1, &参) };
    assert_eq!(返回槽.类型标签, 类型标签_4294967295);
    assert_eq!(返回槽.值, 错误码::段头截断 as u64);
    assert_eq!(
        容器::反解(截),
        Err(容器::反解错误::段头截断 { 位置: 8 }),
        "与直接反解同一个结论"
    );

    // 槽类型不对（不是字节集）⇒ 参数槽不符，**不许尽力而为**。
    let 坏槽 = 数据槽::内联(类型标签_0004, 0, 0);
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 按契约形状调用（槽本身形状不对，正是要测的）。
    unsafe { 反解容器执行(&mut 返回槽, 1, &坏槽) };
    assert_eq!(返回槽.值, 错误码::参数槽不符 as u64);
}

/// 生成容器：结构编码经数据槽进去、`.e` 字节从返回槽出来，与直接 `容器::生成` 同结论。
#[test]
fn 契约形状_生成容器_与直接生成同结论() {
    let 容 = 样例容器();
    let 结构 = 结构编码::编码容器(&容);
    let 参 = 字节集槽(&结构);
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 按契约形状调用。
    unsafe { 生成容器执行(&mut 返回槽, 1, &参) };

    // SAFETY: 返回槽刚由 生成容器执行 写出。
    let 产物 = unsafe { 取返回字节(&返回槽) };
    assert_eq!(
        产物,
        容器::生成(&容).expect("直接生成"),
        "与直接生成同一个结论"
    );
    assert_eq!(
        产物,
        容器::生成(&容器::反解(&产物).expect("反解")).expect("再生成")
    );

    // SAFETY: 槽来自本测试刚调用的执行函数。
    unsafe { 释放返回字节(&返回槽) };
}
