//! 测试 · 解码 —— 边界编码的**解**（只在测试里）。
//!
//! 生产侧只有编码方 —— 1101/1102 的出参是字节集，当前没有任何已声明的能力吃它。留着它是为了让
//! 「编码没丢字段」当场可断言，不是第二套实现：与 `原生路编码` 是同一条格式的读与写两面。
//! 从 `src/lib.rs` 的 `#[cfg(test)] mod 测试` 搬来，函数体一字不改。

use crate::语言面::{节点, 节点种类, 记号, 记号流, 记号种类, 语法树};

/// 顺序读器（越界即 panic：测试里越界就是编码坏了）。
struct 顺序读器<'a> {
    字节: &'a [u8],
    位: usize,
}

impl<'a> 顺序读器<'a> {
    fn 读单字节(&mut self) -> u8 {
        let 待处理值 = self.字节[self.位];
        self.位 += 1;
        待处理值
    }
    fn 读双字节(&mut self) -> u16 {
        let 片段: [u8; 2] = self.字节[self.位..self.位 + 2].try_into().unwrap();
        self.位 += 2;
        u16::from_le_bytes(片段)
    }
    fn 读四字节(&mut self) -> u32 {
        let 片段: [u8; 4] = self.字节[self.位..self.位 + 4].try_into().unwrap();
        self.位 += 4;
        u32::from_le_bytes(片段)
    }
    fn 取字节(&mut self, 长度: usize) -> &'a [u8] {
        let 片段 = &self.字节[self.位..self.位 + 长度];
        self.位 += 长度;
        片段
    }
}

/// 从当前位置读一份记号流编码。
fn 读器解记号流(读器: &mut 顺序读器<'_>) -> 记号流 {
    let 原文长 = 读器.读四字节() as usize;
    let 原文 = 读器.取字节(原文长).to_vec();
    let 记号数 = 读器.读四字节();
    let mut 记号表 = Vec::with_capacity(记号数 as usize);
    for _ in 0..记号数 {
        let 号值 = 读器.读单字节();
        let 区间起点 = 读器.读四字节();
        let 区间终点 = 读器.读四字节();
        记号表.push(记号::新建(
            记号种类::自号(号值).expect("种类号该认得出来"),
            区间起点,
            区间终点,
        ));
    }
    记号流::新建(原文, 记号表).expect("解出来的记号流该过构造口")
}

/// 记号流边界编码 → `记号流`。
pub(crate) fn 解记号流(字节: &[u8]) -> 记号流 {
    let mut 读器 = 顺序读器 { 字节, 位: 0 };
    let 输出流 = 读器解记号流(&mut 读器);
    assert_eq!(读器.位, 字节.len(), "记号流编码尾部不该有多余字节");
    输出流
}

/// 语法树边界编码 → `语法树`。
pub(crate) fn 解语法树(字节: &[u8]) -> 语法树 {
    let mut 读器 = 顺序读器 { 字节, 位: 0 };
    let 输出流 = 读器解记号流(&mut 读器);
    let 节点数 = 读器.读四字节();
    let mut 节点表 = Vec::with_capacity(节点数 as usize);
    for _ in 0..节点数 {
        let 号值 = 读器.读双字节();
        let 区间起点 = 读器.读四字节();
        let 区间终点 = 读器.读四字节();
        let 子起 = 读器.读四字节();
        let 子止 = 读器.读四字节();
        节点表.push(节点::新建(
            节点种类::自号(号值).expect("节点种类号该认得出来"),
            (区间起点, 区间终点),
            (子起, 子止),
        ));
    }
    let 根节点 = 读器.读四字节();
    assert_eq!(读器.位, 字节.len(), "语法树编码尾部不该有多余字节");
    语法树::新建(输出流, 节点表, 根节点).expect("解出来的语法树该过构造口")
}

/// 诊断结果解出的形状（[`解诊断`] 用）：「全过」或「一条（阶段 · 码 · 位置 · 读数）」。
#[derive(Debug, PartialEq)]
pub(crate) enum 诊断解 {
    全过,
    一条诊断(u32, u32, Option<(u32, u32)>, String),
}

/// 诊断结果边界编码 → 解。只在测试里：与 `原生路编码::编码诊断结果` 是同一条格式的
/// 读与写两面（同 `解记号流` / `解语法树` 的口径：编码没丢字段当场可断言，不是第二套实现）。
pub(crate) fn 解诊断(字节: &[u8]) -> 诊断解 {
    let mut 读器 = 顺序读器 { 字节, 位: 0 };
    match 读器.读单字节() {
        0 => {
            assert_eq!(读器.位, 字节.len(), "全过标记该是 1 字节，尾部不该有多余字节");
            诊断解::全过
        }
        1 => {
            let 阶段 = 读器.读四字节();
            let 错误码 = 读器.读四字节();
            let 位置 = match 读器.读四字节() {
                1 => Some((读器.读四字节(), 读器.读四字节())),
                0 => None,
                其余 => panic!("位置标志只认 0 / 1，实得 {其余}"),
            };
            let 读数长 = 读器.读四字节() as usize;
            let 读数 = std::str::from_utf8(读器.取字节(读数长))
                .expect("读数该是合法 UTF-8")
                .to_owned();
            assert_eq!(读器.位, 字节.len(), "诊断编码尾部不该有多余字节");
            诊断解::一条诊断(阶段, 错误码, 位置, 读数)
        }
        其余 => panic!("结果标签只认 0 / 1，实得 {其余}"),
    }
}
