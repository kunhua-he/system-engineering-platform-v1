/// 边界编码的**布局**钉死：改字段顺序或宽度当场红（口径见 `原生路编码` 文件头）。
#[test]
fn 边界编码_布局逐字段钉住() {
    let 流 = 词法::切记号(真程序文本).expect("切分");
    let 字节 = 原生路编码::编码记号流(&流);
    let 原文长 = u32::from_le_bytes(字节[0..4].try_into().unwrap()) as usize;
    assert_eq!(原文长, 真程序文本.len(), "头 4 字节 = u32 原文长（小端）");
    assert_eq!(&字节[4..4 + 原文长], 真程序文本.as_bytes(), "紧接全文原文");
    let 记号数位 = 4 + 原文长;
    let 记号数 = u32::from_le_bytes(字节[记号数位..记号数位 + 4].try_into().unwrap());
    assert_eq!(记号数 as usize, 流.记号表.len(), "再 4 字节 = u32 记号数");
    assert_eq!(
        字节.len(),
        4 + 原文长 + 4 + 流.记号表.len() * 9,
        "每枚记号 9 字节：u8 种类号 + u32 起 + u32 止"
    );

    let 树 = 语法::建树(&流).expect("建树");
    let 树字节 = 原生路编码::编码语法树(&树);
    assert_eq!(
        树字节.len(),
        字节.len() + 4 + 树.节点表.len() * 18 + 4,
        "语法树 = 记号流编码 + u32 节点数 + 每节点 18 字节 + u32 根"
    );
    assert_eq!(解语法树(&树字节), 树, "编码→解 必须回到同一棵树");
}

/// 保留项（**只剩 1106 编译** —— 真没实现，保留项就是诚实状态）：状态位是「错误项且不带已废止」，
/// 按函数表直接调也得到**结构化错误码**（码 1 提供者未载入），不是崩溃、不是假成功。
///
/// 名单**从命令表现读**（不写死）：状态位带错误位的就是保留项 —— 这样 1103 落地后
/// 这里自动只剩 1106，不会留下「写死的过期名单」。
#[test]
fn 契约形状_保留项_写结构化失败() {
    let 声明 = 扩展声明();
    assert_eq!(声明.命令表.项数, 命令表项数 as u32);

    let 保留项: Vec<u32> = (0..命令表项数)
        .filter_map(|位| {
            // SAFETY: 位 < 命令表项数，项表非空。
            let 命令 = unsafe { &*声明.命令表.项表.add(位) };
            (命令.状态位 & 命令状态::错误 != 0).then_some(命令.编号.取())
        })
        .collect();
    assert_eq!(保留项, vec![能力号::编译], "当前保留项该只有 1106 编译");

    for 号 in 保留项 {
        // SAFETY: 命令表项数 > 0 且项表非空，下标在范围内。
        let 命令 = unsafe { &*声明.命令表.项表.add(表内位(号)) };
        assert_eq!(命令.状态位 & 命令状态::已废止, 0, "保留项**不带** 已废止");

        // 直接按函数表调：必须得到结构化错误码（提供者未载入 = 码 1）。
        // SAFETY: 函数表与命令表等长，下标在范围内。
        let 执行 = unsafe { *声明.函数表.add(表内位(号)) };
        let 参 = 文本槽(真程序文本);
        let mut 返回槽 = 数据槽::空槽();
        // SAFETY: 按契约形状调用。
        unsafe { 执行(&mut 返回槽, 1, &参) };
        assert_eq!(返回槽.类型标签, 类型标签_4294967295, "{号} 该写错误槽");
        assert_eq!(返回槽.值, 错误码_1 as u64, "{号} 该报「提供者未载入」");
        assert!(!返回槽.是否引用(), "错误槽不是引用，不该被当成结果读");
    }
}

