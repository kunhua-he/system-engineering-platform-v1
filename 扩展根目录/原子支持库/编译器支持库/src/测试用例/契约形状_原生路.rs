/// **反向样本**：1101 / 1102 的入参槽类型不符 ⇒ `参数槽不符`（1135），**不许静默成功**。
///
/// 三种坏槽各来一遍：字节集槽（5）· 空槽（0）· 文本标签但非引用槽（内联）。
#[test]
fn 契约形状_原生路两能力_参数槽不符一律报错() {
    let 坏槽表: [(&str, 数据槽); 3] = [
        ("字节集槽（类型标签 5）", 字节集槽(真程序文本.as_bytes())),
        ("空槽（类型标签 0）", 数据槽::空槽()),
        ("文本标签的内联槽（非引用）", 数据槽::内联(类型标签_0004.into(), 0, 0)),
    ];
    for (名称, 坏槽) in &坏槽表 {
        for (能力名, 执行) in [
            ("1101 词法分析", crate::执行函数面::执行入口::词法分析执行 as 执行函数),
            ("1102 语法分析", crate::执行函数面::执行入口::语法分析执行 as 执行函数),
        ] {
            let mut 返回槽 = 数据槽::空槽();
            // SAFETY: 按契约形状调用（槽本身形状不对，正是要测的）。
            unsafe { 执行(&mut 返回槽, 1, 坏槽) };
            assert_eq!(
                返回槽.类型标签, 类型标签_4294967295,
                "{能力名} 收到{名称}时该写错误槽，不许静默成功"
            );
            assert_eq!(
                返回槽.值,
                错误码::参数槽不符 as u64,
                "{能力名} 收到{名称}时该报「参数槽不符」"
            );
        }
    }

    // 参数个数不足（0 个槽）同样报错，不许拿默认值硬跑。
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 参数个数 0，参数表给一个有效槽 —— 位次越界正是要测的。
    unsafe { crate::执行函数面::执行入口::词法分析执行(&mut 返回槽, 0, &文本槽(真程序文本)) };
    assert_eq!(返回槽.值, 错误码::参数槽不符 as u64);
}

