/// 边界编码的**布局**钉死：改字段顺序或宽度当场红（口径见 `原生路编码` 文件头）。
#[test]
fn 边界编码_布局逐字段钉住() {
    let 输出流 = 词法::切记号(真程序文本).expect("切分");
    let 字节 = 原生路编码::编码记号流(&输出流);
    let 原文长 = u32::from_le_bytes(字节[0..4].try_into().unwrap()) as usize;
    assert_eq!(原文长, 真程序文本.len(), "头 4 字节 = u32 原文长（小端）");
    assert_eq!(&字节[4..4 + 原文长], 真程序文本.as_bytes(), "紧接全文原文");
    let 记号数位 = 4 + 原文长;
    let 记号数 = u32::from_le_bytes(字节[记号数位..记号数位 + 4].try_into().unwrap());
    assert_eq!(记号数 as usize, 输出流.记号表.len(), "再 4 字节 = u32 记号数");
    assert_eq!(
        字节.len(),
        4 + 原文长 + 4 + 输出流.记号表.len() * 9,
        "每枚记号 9 字节：u8 种类号 + u32 起 + u32 止"
    );

    let 语法树 = 语法::建树(&输出流).expect("建树");
    let 树字节 = 原生路编码::编码语法树(&语法树);
    assert_eq!(
        树字节.len(),
        字节.len() + 4 + 语法树.节点表.len() * 18 + 4,
        "语法树 = 记号流编码 + u32 节点数 + 每节点 18 字节 + u32 根"
    );
    assert_eq!(解语法树(&树字节), 语法树, "编码→解 必须回到同一棵树");
}

/// 保留项：**当前为空** —— 1101–1107 七条全是真实现（1106 编译于 2026-09-28 落地）。
///
/// **保留项这个概念留着**（它不是过渡物）：它是「号已申报、实现未到」的**诚实状态** ——
/// `命令状态::错误` 且**不带** `已废止` ⇒ 调用它得到 `提供者未载入` 的结构化失败，
/// 不是崩溃、不是假成功。本测试就是这条约定的执行者：**只要名单里还有人，就必须逐个证明
/// 它返回结构化失败**；**名单空了也只报空**，不会留下「写死的过期名单」。
///
/// 名单**从命令表现读**（不写死）：状态位带错误位的就是保留项 —— 这样每解决一条
/// 就自动少一个，新加一条未实现的号也自动被本测试盯上。
#[test]
fn 契约形状_保留项_写结构化失败() {
    let 声明 = 扩展声明();
    assert_eq!(声明.命令表.项数, 命令表项数 as u32);

    let 保留项: Vec<u32> = (0..命令表项数)
        .filter_map(|位置| {
            // SAFETY: 位 < 命令表项数，项表非空。
            let 命令 = unsafe { &*声明.命令表.项表.add(位置) };
            (命令.状态位 & 命令状态::错误 != 0).then_some(命令.编号.取号值())
        })
        .collect();
    assert!(保留项.is_empty(), "保留项该为空 —— 1101–1107 七条全是真实现，实得 {保留项:?}");

    for 号值 in 保留项 {
        // SAFETY: 命令表项数 > 0 且项表非空，下标在范围内。
        let 命令 = unsafe { &*声明.命令表.项表.add(表内位(号值)) };
        assert_eq!(命令.状态位 & 命令状态::已废止, 0, "保留项**不带** 已废止");

        // 直接按函数表调：必须得到结构化错误码（提供者未载入 = 码 1）。
        // SAFETY: 函数表与命令表等长，下标在范围内。
        let 执行 = unsafe { *声明.函数表.add(表内位(号值)) };
        let 参数 = 文本槽(真程序文本);
        let mut 返回槽 = 数据槽::空槽();
        // SAFETY: 按契约形状调用。
        unsafe { 执行(&mut 返回槽, 1, &参数) };
        assert_eq!(返回槽.类型标签, 类型标签_4294967295, "{号值} 该写错误槽");
        assert_eq!(返回槽.值, u64::from(错误码_1.取号值()), "{号值} 该报「提供者未载入」");
        assert!(!返回槽.是否引用(), "错误槽不是引用，不该被当成结果读");
    }
}

/// 造一份注册表字节集（载荷 = 本库的注册表边界编码）—— 与 `契约形状_语义` 的助手同口径。
fn 注册表字节(一项: &[(&str, u16)]) -> Vec<u8> {
    语义::注册表::从项(一项.iter().map(|(名称, 号值)| (名称.as_bytes().to_vec(), *号值)).collect()).编码()
}

/// 造一份 1106 的**接口说明段**（已编码段数据）：照 `能力声明/1106.json` 的六字段。
fn 接口说明段() -> Vec<u8> {
    接口段编码::编码(&接口说明 {
        编号: 能力号::编译,
        名称: "编译".to_owned(),
        说明: "一步到底：程序文本 → 结构 → 产物（.能力包件）。".to_owned(),
        参数表: vec![接口参数项 {
            名称: "程序文本".to_owned(),
            类型标签: 4,
            状态位: 0,
            默认值: 数据槽::空槽(),
        }],
        返回类型: 5,
        可抛错误码: Vec::new(),
    })
}

/// **1106 编译已落地**（不是保留项）：程序文本 + 三张注册表 + 能力码字节 + 接口说明段
/// ⇒ `.能力包件` 三段齐备，且拆包/校验往返一致。
///
/// 这条用例就是「1106 从保留项变真实现」的机器可读证据：它不再回码 1，
/// 而是交出以容器魔数开头、三段（16/17/18）各就各位的一份字节。
#[test]
fn 契约形状_编译_六入参出能力包件三段齐备() {
    let 文本 = ".版本 2\n.子程序 主, 整数型\n    返回 (0)\n";
    let 命令表 = 注册表字节(&[("信息框", 42)]);
    let 常量表 = 注册表字节(&[("FALSE", 7)]);
    let 类型表 = 注册表字节(&[("整数型", 51)]);
    let 能力码 = b"\0asm\x01\0\0\0".to_vec();
    let 号段 = 接口说明段();
    let 参数 = [
        文本槽(文本),
        字节集槽(&命令表),
        字节集槽(&常量表),
        字节集槽(&类型表),
        字节集槽(&能力码),
        字节集槽(&号段),
    ];
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 按契约形状调用：6 个槽按参数表行序填好。
    unsafe { crate::执行函数面::执行入口::编译执行(&mut 返回槽, 6, 参数.as_ptr()) };
    assert_eq!(返回槽.类型标签, 类型标签_0005, "成功时返回槽该是字节集，不是错误槽");
    // SAFETY: 返回槽由 编译执行 刚写出。
    let 包件字节 = unsafe { 取返回字节(&返回槽) };

    assert_eq!(&包件字节[..8], crate::容器::魔数, "产物该是 .能力包件（容器魔数开头）");
    let (接口, 回码) = 拆包(&包件字节).expect("拆包该成功");
    assert_eq!(回码, 能力码, "能力码段原样搬运（本能力不生成码）");
    assert_eq!(
        接口段编码::解码(&接口).expect("接口段该解得开"),
        接口段编码::解码(&号段).expect("原段该解得开"),
        "接口说明段原样封进包"
    );
    assert_eq!(校验(&包件字节), Some(true), "两段都没被换过");

    // SAFETY: 槽来自本测试刚调用的执行函数。
    unsafe { 释放返回字节(&返回槽) };
}

