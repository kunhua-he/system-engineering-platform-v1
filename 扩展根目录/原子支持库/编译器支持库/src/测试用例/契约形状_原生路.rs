/// 1101 词法分析：程序文本（文本槽）→ 记号流边界编码，与**直接调** `词法::切记号` 同结论。
#[test]
fn 契约形状_词法分析_与直接切记号同结论() {
    let 参 = 文本槽(真程序文本);
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 按契约形状调用：返回槽可写、参数个数 1、参数表指向一个文本槽。
    unsafe { crate::执行函数面::执行入口::词法分析执行(&mut 返回槽, 1, &参) };

    assert_eq!(返回槽.类型标签, 类型标签_0005, "成功时返回槽该是字节集");
    // SAFETY: 返回槽由 词法分析执行 刚写出。
    let 字节 = unsafe { 取返回字节(&返回槽) };

    let 直 = 词法::切记号(真程序文本).expect("直接切分应成功");
    let 经槽 = 解记号流(&字节);
    assert_eq!(经槽, 直, "经执行函数与直接切分必须得到同一个记号流");
    // 判据（`说明/语言面形状.md` §四 J1–J6）：区间首尾相接且覆盖全文。
    assert_eq!(经槽.还原(), 真程序文本.as_bytes(), "记号流必须逐字节还原原文");
    assert!(经槽.记号表.len() > 1, "真程序文本该切出多枚记号");

    // SAFETY: 槽来自本测试刚调用的执行函数。
    unsafe { 释放返回字节(&返回槽) };
}

