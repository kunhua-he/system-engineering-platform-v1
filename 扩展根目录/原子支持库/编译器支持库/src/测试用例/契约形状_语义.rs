/// 1103 的**可抛错误码**：实现侧数组与 `能力声明/1103.json` 逐字同源（漏一处就是两处源）。
#[test]
fn 声明自洽_可抛错误码1103与JSON一致() {
    let json = 读JSON件("能力声明/1103.json");
    let 期望码表: Vec<u32> = json
        .取成员("可抛错误码")
        .and_then(|待处理值| 待处理值.取数组())
        .expect("可抛错误码")
        .iter()
        .map(|待处理值| 待处理值.取数值().expect("码是数") as u32)
        .collect();
    assert_eq!(期望码表, 可抛错误码_1103.to_vec(), "1103 的可抛错误码声明与实现必须同源");
}
