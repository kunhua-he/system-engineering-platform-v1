/// 造一份注册表字节集（载荷 = 本库的注册表边界编码）。
///
/// **返回 Vec 而不是槽**：`字节集槽` 是「引用」槽，指向的字节必须比槽活得久；
/// 若在函数里返回槽，它指的那份 `Vec` 当场析构 ⇒ 悬垂（实测撞到 `ptr::copy_nonoverlapping`
/// 的 UB 检查）。故本助手只交字节，槽由调用方就地造。
fn 注册表字节(一项: &[(&str, u16)]) -> Vec<u8> {
    语义::注册表::从项(一项.iter().map(|(名称, 号值)| (名称.as_bytes().to_vec(), *号值)).collect())
        .编码()
}

/// 1103 语义分析：程序文本 + 三张注册表（**4 个入参槽**）→ 带号结构边界编码，
/// 与**直接调** `语义::分析` 同结论。
#[test]
fn 契约形状_语义分析_文本加三表入参_与直接分析同结论() {
    let 文本 = ".版本 2\n.全局变量 窗口, 整数型\n.子程序 主, 逻辑型\n    返回 (#FALSE)\n";
    let 命令表 = 注册表字节(&[("信息框", 42)]);
    let 常量表 = 注册表字节(&[("FALSE", 7)]);
    let 类型表 = 注册表字节(&[("整数型", 51), ("逻辑型", 12)]);
    let 参数 = [文本槽(文本), 字节集槽(&命令表), 字节集槽(&常量表), 字节集槽(&类型表)];
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 按契约形状调用：4 个槽按参数表行序填好。
    unsafe { 语义分析执行(&mut 返回槽, 4, 参数.as_ptr()) };
    assert_eq!(返回槽.类型标签, 类型标签_0005, "成功时返回槽该是字节集");
    // SAFETY: 返回槽由 语义分析执行 刚写出。
    let 字节 = unsafe { 取返回字节(&返回槽) };

    let 输出流 = 词法::切记号(文本).expect("切分");
    let 语法树 = 语法::建树(&输出流).expect("建树");
    let 命令注册表 = 语义::注册表::从项(vec![("信息框".as_bytes().to_vec(), 42)]);
    let 常量注册表 = 语义::注册表::从项(vec![("FALSE".as_bytes().to_vec(), 7)]);
    let 类型注册表 = 语义::注册表::从项(vec![
        ("整数型".as_bytes().to_vec(), 51),
        ("逻辑型".as_bytes().to_vec(), 12),
    ]);
    let 直接带号结构 = 语义::分析(&语法树, &命令注册表, &常量注册表, &类型注册表).expect("直接分析该成功");
    assert_eq!(字节, 语义编码::编码带号结构(&直接带号结构), "经执行函数与直接分析必须同一个产物");
    // 产物非空：真定出了号与引用（不是空壳）。
    assert!(!直接带号结构.号表.is_empty(), "该定出变量与子程序的号");
    assert!(!直接带号结构.引用表.is_empty(), "该解析出引用");

    // SAFETY: 槽来自本测试刚调用的执行函数。
    unsafe { 释放返回字节(&返回槽) };
}

/// **反向样本**：1103 的入参槽不合契约 ⇒ `参数槽不符`（1135），**不许静默成功**。
#[test]
fn 契约形状_语义分析_参数槽不符报参数槽不符() {
    let 文本 = ".版本 2\n";
    let 空表 = 注册表字节(&[]);
    let 坏0 = [字节集槽(&空表), 字节集槽(&空表), 字节集槽(&空表), 字节集槽(&空表)];
    let 坏1 = [文本槽(文本), 文本槽("x"), 字节集槽(&空表), 字节集槽(&空表)];
    let 坏2 = [文本槽(文本), 数据槽::空槽(), 字节集槽(&空表), 字节集槽(&空表)];
    let 坏槽表: [(&str, [数据槽; 4]); 3] = [
        ("第 0 槽不是文本（给了字节集）", 坏0),
        ("第 1 槽不是字节集（给了文本）", 坏1),
        ("第 1 槽是空槽（类型标签 0）", 坏2),
    ];
    for (名称, 参数) in &坏槽表 {
        let mut 返回槽 = 数据槽::空槽();
        // SAFETY: 按契约形状调用（槽本身形状不对，正是要测的）。
        unsafe { 语义分析执行(&mut 返回槽, 4, 参数.as_ptr()) };
        assert_eq!(返回槽.类型标签, 类型标签_4294967295, "{名称}：该写错误槽");
        assert_eq!(返回槽.值, 错误码::参数槽不符 as u64, "{名称}：该报「参数槽不符」");
    }

    // 参数个数不足（只给 3 个槽）⇒ 第 3 位越界，同样报错。
    let 三槽 = [文本槽(文本), 字节集槽(&空表), 字节集槽(&空表)];
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 参数个数 3，参数表 3 个有效槽 —— 第 3 位越界正是要测的。
    unsafe { 语义分析执行(&mut 返回槽, 3, 三槽.as_ptr()) };
    assert_eq!(返回槽.值, 错误码::参数槽不符 as u64);
}

