//! 测试 · 声明自洽（声明与实现不漂的证据）+ 导出符号形状。
//!
//! 从 `src/lib.rs` 的 `#[cfg(test)] mod 测试` 搬来；断言与样本一字不改。

use v1_contract::{命令状态, 号段};

use crate::命令声明面::命令表::{命令表存储, 执行函数表};
use crate::声明数据::包声明::{命令表项数, 命令表内位};
use crate::静态声明::{取平台信息, 扩展声明};
use crate::形状错误码;

use super::夹具::{读JSON件, 读串, 读段位表切片};

/// 命令表与函数表等长；每个 `能力声明/<编号>.json` 的参数表行数 == 该命令的参数个数；
/// 每个 `可抛错误码` 都在 `错误码表/` 里登记过。
#[test]
fn 声明自洽_表等长与参数行数与错误码登记() {
    // ① 命令表.len() == 函数表.len()。
    assert_eq!(命令表存储.0.len(), 执行函数表.len(), "执行函数表与命令表必须等长");
    assert_eq!(扩展声明().命令表.表项数 as usize, 命令表存储.0.len());
    assert!(!扩展声明().函数表.is_null());

    // ② 逐条能力声明：参数表行数 · 类型标签逐行 · 返回类型 · 状态位 · 名称 · 说明。
    let mut 见到的 = Vec::new();
    for 编号 in 1101..=1107u32 {
        let json = 读JSON件(&format!("能力声明/{编号}.json"));
        assert_eq!(
            json.取成员("编号").and_then(|待处理值| 待处理值.取数值()).map(|整数值| 整数值 as u32),
            Some(编号)
        );
        见到的.push(编号);

        // SAFETY: 命令表内位 已断言编号落在本表范围内，项表非空。
        let 命令 = unsafe { &*命令表存储.0.as_ptr().add(命令表内位(编号)) };
        let json名 = json.取成员("名称").and_then(|待处理值| 待处理值.取字符串()).expect("名称");
        // SAFETY: 命令名是静态只读 NUL 结尾串。
        assert_eq!(
            unsafe { 读串(命令.名称) },
            Some(json名.as_bytes()),
            "编号 {编号} 的名称漂了"
        );

        let json说明 = json.取成员("说明").and_then(|待处理值| 待处理值.取字符串()).expect("说明");
        // SAFETY: 同上。
        assert_eq!(
            unsafe { 读串(命令.说明) },
            Some(json说明.as_bytes()),
            "编号 {编号} 的说明漂了"
        );

        assert_eq!(
            json.取成员("返回类型").and_then(|待处理值| 待处理值.取数值()).map(|整数值| 整数值 as u32),
            Some(命令.返回类型.取号值()),
            "编号 {编号} 的返回类型漂了"
        );
        assert_eq!(
            json.取成员("状态位").and_then(|待处理值| 待处理值.取数值()).map(|整数值| 整数值 as u16),
            Some(命令.状态位),
            "编号 {编号} 的状态位漂了"
        );

        let 参数表 = json.取成员("参数表").and_then(|待处理值| 待处理值.取数组()).expect("参数表");
        assert_eq!(
            参数表.len() as u32,
            命令.参数个数,
            "编号 {编号} 的参数表行数 != 命令的参数个数"
        );
        for (序号, 入参) in 参数表.iter().enumerate() {
            // SAFETY: 序 < 参数个数，参数表非空。
            let 参数槽 = unsafe { &*命令.参数表.add(序号) };
            assert_eq!(
                入参.取成员("类型标签").and_then(|待处理值| 待处理值.取数值()).map(|整数值| 整数值 as u32),
                Some(参数槽.类型标签.取号值()),
                "编号 {编号} 第 {序号} 行的类型标签漂了（行序即契约）"
            );
            let 参名 = 入参.取成员("名称").and_then(|待处理值| 待处理值.取字符串()).expect("参数名");
            // SAFETY: 参数名是静态只读 NUL 结尾串。
            assert_eq!(unsafe { 读串(参数槽.名称) }, Some(参名.as_bytes()));
        }

        // ③ 每个可抛错误码都在 错误码表/ 里登记过，且段位 == 码 // 1000。
        let 码s = json
            .取成员("可抛错误码")
            .and_then(|待处理值| 待处理值.取数组())
            .expect("可抛错误码");
        for 错误码 in 码s {
            let 错误码 = 错误码.取数值().expect("码是数") as u32;
            let 错误码档 = 读JSON件(&format!("错误码表/{错误码}.json"));
            assert_eq!(
                错误码档.取成员("码").and_then(|待处理值| 待处理值.取数值()).map(|整数值| 整数值 as u32),
                Some(错误码)
            );
            assert_eq!(
                错误码档.取成员("段位").and_then(|待处理值| 待处理值.取数值()).map(|整数值| 整数值 as u32),
                Some(错误码 / 1000),
                "码 {错误码} 的冗余登记项「段位」必须 == 码 // 1000"
            );
        }
    }
    assert_eq!(见到的, (1101..=1107).collect::<Vec<_>>());

    // ④ 错误段位表：非空、不重复；错误码表 37 条、按码升序、段位由码导出、段位都登记过。
    let 声明 = 扩展声明();
    let 段位表 = 读段位表切片(声明);
    assert!(!段位表.is_empty(), "错误段位表不许为空");
    let mut 去重 = 段位表.to_vec();
    去重.sort_unstable();
    去重.dedup();
    assert_eq!(去重.len(), 段位表.len(), "错误段位表不许有重复段位");

    // SAFETY: 错误码表项数 > 0 且项表非空。
    let 登记 =
        unsafe { core::slice::from_raw_parts(声明.错误码表.项表, 声明.错误码表.表项数 as usize) };
    assert_eq!(登记.len(), 37, "错误码表该是 37 条");
    for (序号, 登记项) in 登记.iter().enumerate() {
        assert_eq!(登记项.段位, 登记项.码值 / 1000, "码 {} 的段位漂了", 登记项.码值);
        assert_eq!(登记项.码值, 1101 + 序号 as u32, "错误码表按码升序且无缺号");
        assert!(段位表.contains(&登记项.段位), "段位 {} 没登记", 登记项.段位);

        // 名称与说明逐字与 JSON 对齐（声明与实现不漂）。
        let 错误码档 = 读JSON件(&format!("错误码表/{}.json", 登记项.码值));
        let json名 = 错误码档.取成员("名称").and_then(|待处理值| 待处理值.取字符串()).expect("名称");
        // SAFETY: 错误码名是静态只读 NUL 结尾串。
        assert_eq!(
            unsafe { 读串(登记项.名称) },
            Some(json名.as_bytes()),
            "码 {} 的名称漂了",
            登记项.码值
        );
        let json说明 = 错误码档.取成员("说明").and_then(|待处理值| 待处理值.取字符串()).expect("说明");
        // SAFETY: 同上。
        assert_eq!(
            unsafe { 读串(登记项.说明) },
            Some(json说明.as_bytes()),
            "码 {} 的说明漂了",
            登记项.码值
        );
        for (键名, 实际值) in [("可重试", 登记项.可重试), ("可自愈", 登记项.可自愈), ("需人工", 登记项.需人工)] {
            let 期望 = if 错误码档.取成员(键名).and_then(|待处理值| 待处理值.真假()).expect(键名) {
                1u8
            } else {
                0u8
            };
            assert_eq!(实际值, 期望, "码 {} 的「{键名}」漂了", 登记项.码值);
        }
    }

    // ⑤ 装载判定第 ⑥ 步的等价自检：每个「错误状态」命令的段位都要在段位表里
    //    （不然底座侧第 ⑥ 步会判「声明不自洽」）。
    // ⑥ 参数与返回的类型标签都要在「底座类型表 ∪ 本声明类型表」里。
    //    本声明不新增类型 ⇒ 上界 = 底座类型数（8）。
    let 上界值 = 8;
    for (号值, 命令) in 命令表存储.0.iter().enumerate() {
        if 命令.状态位 & 命令状态::错误 != 0 {
            assert!(
                段位表.contains(&(号值 as u32 / 1000)),
                "错误状态的命令 {号值} 的段位没在错误段位表里"
            );
        }
        assert!(命令.返回类型 < 上界值 || 命令.返回类型 == 0);
        for 序号 in 0..命令.参数个数 {
            // SAFETY: 序 < 参数个数 且参数表非空。
            let 入参 = unsafe { &*命令.参数表.add(序号 as usize) };
            assert!(入参.类型标签 < 上界值, "命令 {号值} 第 {序号} 行的类型标签超上界");
        }
    }

    // ⑦ 本扩展一个类型都没新增、一个常量都没有、一个通知函数都没有。
    assert_eq!(声明.类型表.表项数, 0, "本扩展不新增类型");
    assert_eq!(声明.常量表.表项数, 0, "本扩展没有常量");
    assert!(声明.通知函数.is_none(), "本扩展没有通知函数");
    assert_eq!(声明.依赖清单.表项数, 0, "本扩展不依赖别的扩展");
    assert_eq!(声明.通知号段.表项数, 0, "本扩展没有通知号段");
}

/// 形状错误 → 错误码：映射函数对 27 个变体是**穷尽**的（增删改名即编译不过），
/// 且这 27 条码都真在错误码表里登记过。
#[test]
fn 声明自洽_形状错误码与登记一致() {
    use crate::语言面::形状错误 as 形状;

    let 样例 = [
        形状::记号表为空,
        形状::记号有缝隙 { 序号: 0, 前止: 1, 后起: 2 },
        形状::节点表为空,
        形状::父未包住子 { 父节点: 0, 子节点: 1 },
        形状::非先序连续 { 父节点: 0, 子节点: 1, 子树止: 2 },
        形状::词法层输入非法,
    ];
    let 声明 = 扩展声明();
    // SAFETY: 错误码表项数 > 0 且项表非空。
    let 登记 =
        unsafe { core::slice::from_raw_parts(声明.错误码表.项表, 声明.错误码表.表项数 as usize) };
    for 错误 in &样例 {
        let 错误码 = 形状错误码(错误);
        assert!(
            (1108..=1133).contains(&错误码) || 错误码 == crate::错误码::词法层输入非法,
            "形状错误的码该落在 1108..1133（或 1137），实得 {错误码}"
        );
        assert!(登记.iter().any(|登记项| 登记项.码值 == 错误码), "码 {错误码} 没登记");
    }
    // 记号层 10 条 + 词法输入层 1 条 + 语法树层 16 条 = 27 条，逐条都在登记表里。
    for 错误码 in (1108..=1133u32).chain(core::iter::once(crate::错误码::词法层输入非法)) {
        assert!(登记.iter().any(|登记项| 登记项.码值 == 错误码), "码 {错误码} 没登记");
    }
}

/// 导出符号返回本扩展的静态声明，且形状完整。
#[test]
fn 导出符号_返回扩展静态声明且形状完整() {
    let 指针 = 取平台信息();
    assert!(!指针.is_null());
    // SAFETY: 指针指向本扩展的静态声明，终生有效。
    let 声明 = unsafe { &*指针 };

    assert_eq!(声明.声明格式号, v1_contract::声明格式号);
    assert_eq!(声明.目标字宽, 64);
    assert!(core::ptr::eq(声明, 扩展声明()));

    // 标识串：32 位十六进制 + NUL，且**不是底座那串**。
    // SAFETY: 标识串是静态只读的 32 位十六进制 + NUL 串。
    let 字节串 = unsafe { core::slice::from_raw_parts(声明.标识串, 33) };
    assert_eq!(字节串[32], 0);
    assert!(字节串[..32].iter().all(|字节| 字节.is_ascii_hexdigit()));
    assert_ne!(
        &字节串[..32],
        v1_contract::声明数据::底座标识串内容,
        "不许冒用底座身份"
    );

    assert_eq!(命令表存储.0.len(), 命令表项数);
    // 缩表后：表只装**声明过的命令**（`命令表项数` 条），**不再铺满申报号段** ——
    // 号段仍申报 [1100,1199]，但表不覆盖它的每一个号。
    // 口径：`项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 1 + 裁决 5
    //（编号必须落在申报号段内 —— 这条关系由声明校验那侧的门守，不由「表跨度」守）。
    assert_eq!(
        命令表存储.0.len(),
        命令表项数,
        "表跨度 = 本扩展声明过的命令条数，不是申报号段的跨度"
    );
    assert_eq!(执行函数表.len(), 命令表存储.0.len());
    assert_eq!(声明.命令表.表项数 as usize, 命令表存储.0.len());

    // 申报的能力号段只有一段，且落在支持库段（1xxx）。
    // SAFETY: 能力号段项数 1 > 0 且项表非空，指向静态只读数组。
    let 段s = unsafe {
        core::slice::from_raw_parts(声明.能力号段.项表, 声明.能力号段.表项数 as usize)
    };
    assert_eq!(段s, [号段::构造(1100, 1199)].as_slice());
    assert_eq!(段s[0].段起点.取号值() / 1000, 1);
    assert_eq!(段s[0].段止.取号值() / 1000, 1, "号段不许跨号段类");
}
