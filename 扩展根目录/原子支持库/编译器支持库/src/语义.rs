//! `说明/使用说明.md`（带号结构边界编码）
//!
//! # 本件只做三件事
//!
//! 1. 声明子模块（[`形状`] 是产物形状 · [`名号表`] 是三张入参表的边界编码 · [`建表`] 是本体）；
//! 2. 再导出公开面 [`语义分析`] 与形状；
//! 3. **零实现**。
//!
//! # 公开面
//!
//! ```text
//! 语义::语义分析(&语法树, &名号表, &名号表, &名号表) -> Result<带号结构, 语义错误>
//! ```
//!
//! 三张名号表是 `能力声明/1103.json` 参数表第 1–3 行（命令表 · 常量表 · 类型表）。
//! **行序即契约**：本入口的形参顺序与参数表逐行对应（命令表在前、类型表在后）。
//!
//! # 能力本体与库内入口的分工（不是两条腿）
//!
//! 命令 1103 的**入参是程序文本**（参数表第 0 行，类型标签 4），故执行函数
//! （`src/lib.rs::语义分析执行`）先把文本串过 `词法::切记号` 与 `语法::建树`，再调本入口。
//! 这与 1102 的执行函数把「切记号 → 建树」两步串起来是同一条口径：**契约的入参是文本**，
//! 而库内的语义本体吃的是语法树。
//!
//! # 两条工具链强制（与 `语言面.rs` / `词法.rs` 同源，实测过）
//!
//! 1. rustc 拒绝自动加载非 ASCII 文件名的模块（E0754），故每条 `mod` 都显式给 `#[path]`；
//! 2. 模块名不能与它再导出的同名项撞（E0255），故本体件叫 [`建表`] 而公开项叫 [`语义分析`]。

