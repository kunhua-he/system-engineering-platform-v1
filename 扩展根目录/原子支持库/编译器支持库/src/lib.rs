//! 编译器支持库 —— 后端能力，**可被底座按契约载入的扩展**。
//!
//! **前端是纯 UI，不在本扩展里**（见 `说明/设计说明.md` 第一节判据）。
//!
//! # 两条路（原生路 + 互操作路）
//!
//! - **原生路**：我们的程序文本 ⇄ 结构。`语言面.rs` 是这条路的前端（记号流 · 语法树），
//!   能力 1101 / 1102 / 1103 在这条路上（**保留项，实现未到**）。
//! - **互操作路**：`.e` 容器 ⇄ 结构。`容器.rs` 是这条路的容器层，`记录流.rs` 是段内容层，
//!   能力 1105 反解容器 / 1104 生成容器 在这条路上（**已实现**）。
//!
//! 两条路都以「结构」为中心，所以本扩展的入参出参都是**字节集槽**（类型标签 5）。
//!
//! # 声明的两个来源（这一条必须读）
//!
//! 扩展的声明有**两个来源**，且它们必须逐字一致（有测试守着）：
//!
//! 1. **JSON**（`包声明.json` · `能力声明/*.json` · `错误码表/*.json`）—— 契约层，唯一事实源。
//! 2. **本文件的 Rust 常量** —— 底座读的是这个（`GetPlatformInfo` 交出的 `平台信息`）。
//!
//! 正常情形下第 2 份应当是**生成物**（`构建装配/形态装配/生成声明.py` 读 JSON 生成 Rust）。
//! 但该生成器现在**只认底座**（路径写死在 `契约声明/`，且只认 `--检查` 一个参数，
//! 不认「传声明根」），而它正被另一条腿改，本腿不许动它。故本文件第 2 份是**手写的**。
//!
//! // 违规待消：手写 static 平台信息；待生成器支持扩展声明后改成生成物（见 返回说明）
//!
//! # 命令编号（显式字段）—— 本扩展为什么仍是 1200 项命令表
//!
//! **`命令信息.编号` 现在是显式字段**（`契约声明/src/lib.rs`；源 = `能力声明/<编号>.json`）。
//! 注册表 `按号取命令` 按**编号**二分查找，建表要求命令表按编号**严格递增**。
//! 早先没有这个字段，编号只能由表内下标承担，故本扩展申报 `[1100,1199]` 时，
//! 要能按 `1104` / `1105` 调到，命令表就必须有 1200 项（下标 0..1199）。
//!
//! **本轮只给这 1200 项带上显式编号（= 各自下标），不缩表**（缩表是另一条腿的收口）。
//! 未实现的位一律放**占位项**（`命令状态::错误`，**不带** `已废止` ⇒ 调用它得到
//! `提供者未载入` 的结构化失败，不是假成功）。
//!
//! 代价仍在：编号 0..1099 落在**内核自有段 0xxx** 里，本扩展的表在物理上"占"了它们
//! （声明层面没有——`能力号段` 只申报了 `[1100,1199]`）。有显式编号后，本表本可缩成
//! 7 项（编号 1101..1107）；本轮不缩，故这仍是待收口项。

