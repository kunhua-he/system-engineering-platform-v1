    ///
    /// # Safety
    /// 指针必须指向静态只读的 NUL 结尾串。
    unsafe fn 读串(指针: *const u8) -> &'static [u8] {
        let mut 长 = 0usize;
        // SAFETY: 由调用方保证 NUL 结尾。
        while unsafe { *指针.add(长) } != 0 {
            长 += 1;
        }
        // SAFETY: 前 长 字节可读且是静态数据。
        unsafe { core::slice::from_raw_parts(指针, 长) }
    }

