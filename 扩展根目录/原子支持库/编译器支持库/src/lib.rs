/// 带 `Sync` 的命令表外壳：`命令信息` 里有裸指针 ⇒ 不是 `Sync`，而 `static` 要求 `Sync`。
/// 表编译期冻结、只读，对外只给 `*const` 指针，故共享只读安全。
///
/// 为什么做成 `static` 而不是 `const`：表要的是**唯一实例** —— `const` 数组在
/// **每个使用点各拷一份**，而 `扩展声明().命令表.项表` 必须指向同一份表。
#[repr(transparent)]
struct 静态命令表([命令信息; 命令表项数]);

// SAFETY: 表一旦构造即终生不变；不提供 &mut 通道，对外只交出 *const 指针。
unsafe impl Sync for 静态命令表 {}

