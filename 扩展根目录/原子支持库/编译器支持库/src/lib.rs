// 一之二 原生路结构的边界编码
//
// 与 §一 的 `结构编码` **同一条规矩**：跨边界只有定长数据槽，结构要过边界必须先编成字节集；
// 本模块**只做字段搬运**，不含任何词法/语法知识（切分在 `词法.rs`、建树在 `语法.rs`）。
//
// 为什么必须有它：1101 的返回类型是 5（字节集）而产物是 `记号流`，1102 的产物是 `语法树`
// —— 两份结构都过不了边界，除非先编成字节。编解码只有这一处，不另起第二套。
// 口径来源：`能力声明/1101.json` / `1102.json` 的「返回类型」= 5（行序即契约）。
//
// 编码（一律小端）：
//   记号流：u32 原文长 · 原文 · u32 记号数 · 每枚 (u8 种类号 · u32 起 · u32 止)
//   语法树：记号流编码 · u32 节点数 · 每节点 (u16 种类号 · u32 起 · u32 止 · u32 子起 · u32 子止) · u32 根
//
// ⚠ 未裁（如实登记）：这个编码格式**契约层没规定**（`能力声明/*.json` 的说明只说返回
// 「记号流」/「语法树」，没说字节怎么排）。这里是照 `结构编码` 的先例落的一份实现，
// 等契约层给形状后以契约为准 —— 详见返回说明。
// ════════════════════════════════════════════════════════════════════════════

mod 原生路编码 {
    use super::语言面::{记号流, 语法树, 形状错误};

    /// 记号流 → 字节集：全文原文 + 记号表（区间是字节区间，见 `语言面.rs` 文件头）。
    pub fn 编码记号流(流: &记号流) -> Vec<u8> {
        let mut 出 = Vec::new();
        出.extend_from_slice(&(流.原文.len() as u32).to_le_bytes());
        出.extend_from_slice(&流.原文);
        出.extend_from_slice(&(流.记号表.len() as u32).to_le_bytes());
        for 枚 in &流.记号表 {
            出.push(枚.种类.号());
            出.extend_from_slice(&枚.起.to_le_bytes());
            出.extend_from_slice(&枚.止.to_le_bytes());
        }
        出
    }

    /// 语法树 → 字节集：它自带的记号流 + 先序节点表 + 根下标。
    pub fn 编码语法树(树: &语法树) -> Vec<u8> {
        let mut 出 = 编码记号流(&树.记号流);
        出.extend_from_slice(&(树.节点表.len() as u32).to_le_bytes());
        for 节 in &树.节点表 {
            出.extend_from_slice(&节.种类.号().to_le_bytes());
            出.extend_from_slice(&节.原文区间.0.to_le_bytes());
            出.extend_from_slice(&节.原文区间.1.to_le_bytes());
            出.extend_from_slice(&节.子区间.0.to_le_bytes());
            出.extend_from_slice(&节.子区间.1.to_le_bytes());
        }
        出.extend_from_slice(&树.根.to_le_bytes());
        出
    }

    /// 诊断结果 → 字节集：**能力 1107 的返回**（返回类型 5，源 `能力声明/1107.json`）。
    ///
    /// 入参是 [`整理诊断`](super::诊断::整理诊断) 的产物 `Option<形状错误>`，编码只用三个
    /// **既有整理口**（`诊断::阶段号` · `诊断::字节位置` · `诊断::读数`）与唯一那份码映射
    /// [`形状错误码`] —— 本函数只做搬运，**不另写第二份**阶段归属 / 位置取法 / 文案。
    ///
    /// 布局（一律小端）：
    /// ```text
    ///   u8 结果标签
    ///     0 = 覆盖到的阶段（1101 词法 · 1102 语法）全过 —— 总长恒 1 字节；
    ///     1 = 一条结构化诊断 —— 后接：
    ///         u32 阶段号 · u32 码 · u32 位置标志（0 = 给不出 · 1 = 有）
    ///         [u32 起 · u32 止]              ← 仅位置标志 = 1
    ///         u32 读数字节数 · 读数 UTF-8 字节
    /// ```
    ///
    /// ⚠ 「覆盖到的阶段全过」**不是**「编译成功」——1103/1106 未落地，这条口径照
    /// `诊断/入口.rs` 文件头原样保留。**空字节集不是本函数的产物**：它留给执行函数
    /// 表示「没跑」（入参槽不合契约），与「全过」的 1 字节标签 0 可区分 —— 测试钉住。
    pub fn 编码诊断结果(果: Option<&形状错误>) -> Vec<u8> {
        let Some(错) = 果 else {
            // None = 覆盖到的阶段全过：1 字节标签 0（**非**空字节集，见上）。
            return vec![0];
        };
        let mut 出 = vec![1];
        出.extend_from_slice(&super::诊断::阶段号(错).to_le_bytes());
        出.extend_from_slice(&super::形状错误码(错).to_le_bytes());
        match super::诊断::字节位置(错) {
            Some((起, 止)) => {
                出.extend_from_slice(&1u32.to_le_bytes());
                出.extend_from_slice(&起.to_le_bytes());
                出.extend_from_slice(&止.to_le_bytes());
            }
            None => 出.extend_from_slice(&0u32.to_le_bytes()),
        }
        let 读数 = super::诊断::读数(错);
        出.extend_from_slice(&(读数.len() as u32).to_le_bytes());
        出.extend_from_slice(读数.as_bytes());
        出
    }
}

