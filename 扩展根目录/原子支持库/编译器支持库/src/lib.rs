//! 编译器支持库 —— 后端能力，**可被底座按契约载入的扩展**。
//!
//! **前端是纯 UI，不在本扩展里**（见 `说明/设计说明.md` 第一节判据）。
//!
//! # 两条路（原生路 + 互操作路）
//!
//! - **原生路**：我们的程序文本 ⇄ 结构。`词法.rs`（1101 词法分析）与 `语法.rs`（1102 语法分析）
//!   是这条路的两个入口，`语言面.rs` 是它们共用的形状（记号流 · 语法树），能力 1103 待做。
//! - **互操作路**：`.e` 容器 ⇄ 结构。`容器.rs` 是这条路的容器层，`记录流.rs` 是段内容层，
//!   能力 1105 反解容器 / 1104 生成容器 在这条路上（**已实现**）。
//!
//! 两条路都以「结构」为中心，所以本扩展的入参出参都是**字节集槽**（类型标签 5）。
//!
//! # 声明的两个来源（这一条必须读）
//!
//! 扩展的声明有**两个来源**，且它们必须逐字一致（有测试守着）：
//!
//! 1. **JSON**（`包声明.json` · `能力声明/*.json` · `错误码表/*.json`）—— 契约层，唯一事实源。
//! 2. **本文件的 Rust 常量** —— 底座读的是这个（`GetPlatformInfo` 交出的 `平台信息`）。
//!
//! 正常情形下第 2 份应当是**生成物**（`构建装配/形态装配/生成声明.py` 读 JSON 生成 Rust）。
//! 但该生成器现在**只认底座**（路径写死在 `契约声明/`，且只认 `--检查` 一个参数，
//! 不认「传声明根」），而它正被另一条腿改，本腿不许动它。故本文件第 2 份是**手写的**。
//!
//! // 违规待消：手写 static 平台信息；待生成器支持扩展声明后改成生成物（见 返回说明）
//!
//! # 命令编号（显式字段）—— 本扩展为什么只装 7 项命令表
//!
//! **`命令信息.编号` 是显式字段**（`契约声明/src/lib.rs`；源 = `能力声明/<编号>.json`）。
//! 注册表 `按号取命令` 按**编号**二分查找，建表要求命令表按编号**严格递增**。
//!
//! 早先没有这个字段，编号只能由表内下标承担 ⇒ 本扩展申报 `[1100,1199]` 时，要能按
//! `1104` / `1105` 调到，命令表就必须有 1200 项（下标 0..1199）。那使扩展的占位项落进
//! **内核自有段 `0xxx`**：能力清单 1201 条里「编号 0」出现两次（底座 `取平台信息` 与
//! 扩展占位项 `保留位`）。**那套约定已删**（`契约声明/冻结登记.json` 待办旁路已收口）。
//!
//! **现在只装本扩展声明过的 7 条（编号 1101..1107）**，表内下标不再承担编号
//! （下标 = 编号 − [`表首号`]）。7 个编号全落在申报号段 `[1100,1199]` 内 ——
//! 口径：`项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 1 + 裁决 5
//! 「**命令编号必须落在本声明申报的能力号段内**，越界即 `声明不自洽`」。
//!
//! 未实现的号仍是**保留项**（`命令状态::错误`，**不带** `已废止` ⇒ 调用它得到
//! `提供者未载入` 的结构化失败，不是假成功）；「哪几个是保留项」如实写在各自的
//! `能力声明/<编号>.json` 里（有测试守着，不许漂）。缩表后本扩展**没有占位项**。

