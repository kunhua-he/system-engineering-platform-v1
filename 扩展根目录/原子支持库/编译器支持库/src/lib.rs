/// 从参数表第 `位` 个槽取字节集。`None` = 槽形状不可用（类型标签不是字节集 / 引用地址为空）。
///
/// # Safety
///
/// 调用方保证 `参数表` 指向 `参数个数` 个按契约填好的可读槽。
unsafe fn 取字节集(参数个数: u32, 参数表: *const 数据槽, 位: u32) -> Option<Vec<u8>> {
    if 位 >= 参数个数 || 参数表.is_null() {
        return None;
    }
    // SAFETY: 由调用方保证 参数表 至少 参数个数 个槽可读，且 位 < 参数个数。
    let 槽 = unsafe { &*参数表.add(位 as usize) };
    if 槽.类型标签 != 类型标签_0005 {
        return None;
    }
    if 槽.是否空() {
        return Some(Vec::new());
    }
    if !槽.是否引用() {
        return None;
    }
    let 地址 = 槽.值 as *const u8;
    if 地址.is_null() {
        return None;
    }
    // SAFETY: 契约保证「引用」槽的 值..值+长度 可读。
    Some(unsafe { core::slice::from_raw_parts(地址, 槽.长度 as usize) }.to_vec())
}

/// 把字节集写进返回槽：**所有权交出**（接收方负责释放）。类型标签 = 字节集。
///
/// # Safety
///
/// 调用方保证 `返回槽` 可写。
unsafe fn 写字节集(返回槽: *mut 数据槽, 字节: Vec<u8>) {
    let 长度 = 字节.len() as u64;
    let 地址 = Box::into_raw(字节.into_boxed_slice()) as *const u8;
    // SAFETY: 由调用方保证 返回槽 可写。
    unsafe { *返回槽 = 数据槽::指针(类型标签_0005, 地址 as u64, 长度, true) };
}

/// 把结构化错误码写进返回槽：类型标签 = 错误（`u32::MAX`），值 = 码。
/// **不是字符串、不是 panic。**
///
/// # Safety
///
/// 调用方保证 `返回槽` 可写。
unsafe fn 写错误码(返回槽: *mut 数据槽, 码: u32) {
    // SAFETY: 由调用方保证 返回槽 可写。
    unsafe { *返回槽 = 数据槽::内联(类型标签_4294967295, 码 as u64, 0) };
}

/// 从参数表第 `位` 个槽取文本。`None` = 槽形状不可用。
///
/// 三处判死（都算 `参数槽不符`）：类型标签不是文本（4）；是引用槽但地址为空；
/// 引用字节不是合法 UTF-8（契约「文本 = UTF-8」，见 `接口面形状.md` §三）。
///
/// **类型标签先判**（与 `取字节集` 同一条规矩）：类型标签 0 的空槽是「这一位没填」，
/// 不是「空文本」—— 空文本要写成类型标签 4 的槽（带 `空` 标志，或长度 0）。
///
/// # Safety
///
/// 调用方保证 `参数表` 指向 `参数个数` 个按契约填好的可读槽。
unsafe fn 取文本(参数个数: u32, 参数表: *const 数据槽, 位: u32) -> Option<String> {
    if 位 >= 参数个数 || 参数表.is_null() {
        return None;
    }
    // SAFETY: 由调用方保证 参数表 至少 参数个数 个槽可读，且 位 < 参数个数。
    let 槽 = unsafe { &*参数表.add(位 as usize) };
    if 槽.类型标签 != 类型标签_0004 {
        return None;
    }
    // 空文本：空文件也必须切出一枚零宽的文件结束（`语言面.rs` J1）。
    if 槽.是否空() {
        return Some(String::new());
    }
    if !槽.是否引用() {
        return None;
    }
    let 地址 = 槽.值 as *const u8;
    if 地址.is_null() {
        return None;
    }
    // SAFETY: 契约保证「引用」槽的 值..值+长度 可读。
    let 字节 = unsafe { core::slice::from_raw_parts(地址, 槽.长度 as usize) };
    core::str::from_utf8(字节).ok().map(str::to_owned)
}

/// 1101 词法分析：程序文本（**文本槽**，类型标签 4）→ 记号流边界编码（字节集）。
///
/// 入参出参的类型标签逐字取自 `能力声明/1101.json`（参数表行序即契约 · 返回类型 5）。
unsafe extern "C" fn 词法分析执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用（返回槽可写、参数表可读）。
    let Some(原文) = (unsafe { 取文本(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误码(返回槽, 错误码::参数槽不符) };
        return;
    };
    // SAFETY: 返回槽 可写。
    let 码 = match 词法::切记号(&原文) {
        Ok(流) => {
            // SAFETY: 返回槽 可写（上面已判非空）。
            unsafe { 写字节集(返回槽, 原生路编码::编码记号流(&流)) };
            return;
        }
        Err(错) => 形状错误码(&错),
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误码(返回槽, 码) };
}

/// 1102 语法分析：程序文本（**文本槽**，类型标签 4）→ 语法树边界编码（字节集）。
///
/// 入参出参的类型标签逐字取自 `能力声明/1102.json`：参数表是**程序文本**（不是记号流，
/// 与 `说明/设计说明.md` §二 写的「记号流 → 语法树」不同 —— 那是设计稿，声明是契约）。
/// 故本函数把两步串起来：`切记号` → `建树`。两个入口都是既有实现，这里只做接线。
unsafe extern "C" fn 语法分析执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用。
    let Some(原文) = (unsafe { 取文本(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误码(返回槽, 错误码::参数槽不符) };
        return;
    };
    // SAFETY: 返回槽 可写。
    let 码 = match 词法::切记号(&原文).and_then(|流| 语法::建树(&流)) {
        Ok(树) => {
            // SAFETY: 返回槽 可写。
            unsafe { 写字节集(返回槽, 原生路编码::编码语法树(&树)) };
            return;
        }
        Err(错) => 形状错误码(&错),
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误码(返回槽, 码) };
}

/// 1107 诊断：程序文本（**文本槽**，类型标签 4）→ 诊断结果字节集。
///
/// 调 [`整理诊断`](诊断::整理诊断) 真跑 `1101 词法 → 1102 语法` 链、取**第一个失败**，
/// 经 [`编码诊断结果`](原生路编码::编码诊断结果) 写回返回槽（返回类型 5）。
/// **`None` = 覆盖到的阶段（1101 · 1102）全过，不是「编译成功」** —— 这条诚实口径照
/// `诊断/入口.rs` 文件头原样保留（1103/1106 未落地）。
///
/// 可抛错误码是**空表**（契约就是空表）：它的产物就是失败本身，所以它自己不许失败 ——
/// 本函数**不写错误码**：文本槽正常（含空文本）必写非空字节集（全过 = 1 字节标签 0，
/// 有失败 = 标签 1 + 诊断）；入参槽不合契约（不是文本槽 / 位次越界）⇒ 写**空字节集** =
/// 「没跑」，与「全过」的 1 字节标记可区分（两条测试钉住这条口径）。
unsafe extern "C" fn 诊断执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用（返回槽可写、参数表可读）。
    let 果 = match unsafe { 取文本(参数个数, 参数表, 0) } {
        Some(原文) => 诊断::整理诊断(&原文),
        // 槽形状不合契约：可抛错误码是空表 ⇒ 不许写错误码，写空字节集 = 没跑。
        None => {
            // SAFETY: 返回槽 可写（上面已判非空）。
            unsafe { 写字节集(返回槽, Vec::new()) };
            return;
        }
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写字节集(返回槽, 原生路编码::编码诊断结果(果.as_ref())) };
}

/// 1105 反解容器：`.e` 容器字节 → 容器结构边界编码。
unsafe extern "C" fn 反解容器执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用（返回槽可写、参数表可读）。
    let Some(输入) = (unsafe { 取字节集(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误码(返回槽, 错误码::参数槽不符) };
        return;
    };
    let 码 = match 容器::反解(&输入) {
        Ok(容) => {
            // SAFETY: 返回槽 可写（上面已判非空）。
            unsafe { 写字节集(返回槽, 结构编码::编码容器(&容)) };
            return;
        }
        Err(容器::反解错误::魔数不符) => 错误码::魔数不符,
        Err(容器::反解错误::段头截断 { .. }) => 错误码::段头截断,
        Err(容器::反解错误::段数据越界 { .. }) => 错误码::段数据越界,
        Err(容器::反解错误::段头标记不符 { .. }) => 错误码::段头标记不符,
        Err(容器::反解错误::段类型未知 { .. }) => 错误码::段类型未知,
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误码(返回槽, 码) };
}

/// 1104 生成容器：容器结构边界编码 → `.e` 容器字节。
unsafe extern "C" fn 生成容器执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用。
    let Some(输入) = (unsafe { 取字节集(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误码(返回槽, 错误码::参数槽不符) };
        return;
    };
    let Some(容) = 结构编码::解码容器(&输入) else {
        // SAFETY: 返回槽 可写。
        unsafe { 写错误码(返回槽, 错误码::结构编码非法) };
        return;
    };
    let 码 = match 容器::生成(&容) {
        Ok(字节) => {
            // SAFETY: 返回槽 可写。
            unsafe { 写字节集(返回槽, 字节) };
            return;
        }
        Err(容器::生成错误::段名为空 { .. }) => 错误码::段名为空,
        Err(容器::生成错误::段名过长 { .. }) => 错误码::段名过长,
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误码(返回槽, 码) };
}

