pub(super) fn 取有效子(源树: &语法树, 节点: u32) -> Vec<u32> {
    源树.直接子(节点).filter(|&子节点| !matches!(
        源树.节点表[子节点 as usize].节点类别,
        节点种类::空白记号 | 节点种类::注释记号 | 节点种类::换行记号
    )).collect()
}

pub(super) fn 取节点记号(源树: &语法树, 节点: u32) -> Vec<&[u8]> {
    let 节点形状 = 源树.节点表[节点 as usize];
    源树.记号流.记号表.iter().filter(|记号| {
        记号.区间起点 >= 节点形状.取原文起点()
            && 记号.区间终点 <= 节点形状.取原文终点()
            && !matches!(记号.记号类别, 记号种类::空白记号 | 记号种类::换行记号
                | 记号种类::注释记号 | 记号种类::文件结束)
    }).map(|记号| &源树.全文()[记号.区间起点 as usize..记号.区间终点 as usize]).collect()
}

fn 校验锁定依赖(请求: &本机生成请求<'_>) -> Result<(), 本机生成错误> {
    let mut 已见名称 = std::collections::BTreeSet::new();
    let mut 已见号值 = std::collections::BTreeSet::new();
    for 依赖签名 in 请求.锁定依赖 {
        if 依赖签名.名称.is_empty() || !已见名称.insert(&依赖签名.名称)
            || !已见号值.insert(依赖签名.能力号)
            || 请求.命令表.按名取号(&依赖签名.名称) != Some(依赖签名.能力号)
            || 依赖签名.返回类型 != 1
            || 依赖签名.入参类型表.iter().any(|&类型号| 类型号 != 1)
        {
            return Err(本机生成错误::依赖不匹配);
        }
    }
    Ok(())
}

/// 校验程序形状 → `(返回节点, 参数名表)`。
///
/// 当前子集：`.版本 2` + 一个子程序；子程序 = 名称 · 返回类型 · `参数声明`* · 返回语句。
/// 参数一律 `整数型`（子集只做整数）。
fn 校验程序形状(源树: &语法树, 请求: &本机生成请求<'_>) -> Result<(u32, Vec<Vec<u8>>), 本机生成错误> {
    let 拒绝形状 = || 本机生成错误::当前子集不支持 { 节点: 源树.根下标 };
    let 源单元表 = 取有效子(源树, 源树.根下标);
    let [源单元] = 源单元表.as_slice() else { return Err(拒绝形状()); };
    if 源树.节点表[*源单元 as usize].节点类别 != 节点种类::源单元 {
        return Err(拒绝形状());
    }
    let 源单元子 = 取有效子(源树, *源单元);
    let [版本字段, 入口节点] = 源单元子.as_slice() else { return Err(拒绝形状()); };
    if 源树.原文切片(*版本字段) != Some(b"2".as_slice())
        || 源树.节点表[*入口节点 as usize].节点类别 != 节点种类::子程序
    {
        return Err(拒绝形状());
    }
    // 声明字段表：名称 · 返回类型 · 参数声明* · 返回语句（返回语句必在末位）。
    let 声明字段表 = 取有效子(源树, *入口节点);
    if 声明字段表.len() < 3 {
        return Err(拒绝形状());
    }
    let (入口名称, 返回类型) = (声明字段表[0], 声明字段表[1]);
    let 返回节点 = 声明字段表[声明字段表.len() - 1];
    let 参数节点表 = &声明字段表[2..声明字段表.len() - 1];
    if 源树.节点表[入口名称 as usize].节点类别 != 节点种类::标识符引用
        || 源树.节点表[返回类型 as usize].节点类别 != 节点种类::标识符引用
        || 请求.类型表.按名取号(源树.原文切片(返回类型).unwrap_or(&[])) != Some(1)
        || 源树.节点表[返回节点 as usize].节点类别 != 节点种类::返回语句
    {
        return Err(拒绝形状());
    }
    let mut 参数名表 = Vec::with_capacity(参数节点表.len());
    for &参数节点 in 参数节点表 {
        if 源树.节点表[参数节点 as usize].节点类别 != 节点种类::参数声明 {
            return Err(拒绝形状());
        }
        let 参数子 = 取有效子(源树, 参数节点);
        let (Some(&名称节点), Some(&类型节点)) = (参数子.first(), 参数子.get(1)) else {
            return Err(拒绝形状());
        };
        if 源树.节点表[名称节点 as usize].节点类别 != 节点种类::标识符引用
            || 请求.类型表.按名取号(源树.原文切片(类型节点).unwrap_or(&[])) != Some(1)
        {
            return Err(拒绝形状());
        }
        let 名称 = 源树.原文切片(名称节点).ok_or_else(拒绝形状)?.to_vec();
        if 参数名表.contains(&名称) {
            return Err(拒绝形状());
        }
        参数名表.push(名称);
    }
    let 有效行表: Vec<_> = 源树.全文().split(|&字节| 字节 == b'\n').filter_map(|行文| {
        let 行文 = std::str::from_utf8(行文).ok()?.trim();
        let 正文 = 行文.split('\'').next()?.trim();
        (!正文.is_empty()).then_some(正文)
    }).collect();
    if 有效行表.len() != 3 + 参数名表.len()
        || 有效行表[0].split_whitespace().collect::<Vec<_>>() != [".版本", "2"]
    {
        return Err(拒绝形状());
    }
    let 入口记号 = 取节点记号(源树, *入口节点);
    if 入口记号.get(..4) != Some([
        ".子程序".as_bytes(), 源树.原文切片(入口名称).unwrap_or(&[]),
        b",", 源树.原文切片(返回类型).unwrap_or(&[]),
    ].as_slice()) || !入口记号.contains(&"返回".as_bytes()) {
        return Err(拒绝形状());
    }
    Ok((返回节点, 参数名表))
}

pub fn 生成本机源码(请求: &本机生成请求<'_>) -> Result<本机源码产物, 本机生成错误> {
    if 请求.工具链身份.trim().is_empty() || 请求.平台身份.trim().is_empty()
        || std::str::from_utf8(请求.程序文本).is_err() || 请求.程序文本.len() > 64 * 1024
    {
        return Err(本机生成错误::来源缺失);
    }
    校验锁定依赖(请求)?;
    let 原文文本 = std::str::from_utf8(请求.程序文本).map_err(|_| 本机生成错误::来源缺失)?;
    let 记号流 = 词法::切记号(原文文本).map_err(本机生成错误::语言形状)?;
    let 源树 = 语法::建树(&记号流).map_err(本机生成错误::语言形状)?;
    let 语义产物 = 语义::语义分析(&源树, 请求.命令表, 请求.常量表, 请求.类型表)
        .map_err(本机生成错误::语言语义)?;
    let (返回节点, 参数名表) = 校验程序形状(&源树, 请求)?;
    let 表达式子表 = 取有效子(&源树, 返回节点);
    let [表达式节点] = 表达式子表.as_slice() else {
        return Err(本机生成错误::表达式不完整 { 节点: 返回节点 });
    };
    let 返回记号 = 取节点记号(&源树, 返回节点);
    let Some(表达式记号) = 返回记号.strip_prefix(&["返回".as_bytes()]) else {
        return Err(本机生成错误::表达式不完整 { 节点: 返回节点 });
    };
    let 返回表达式 = 生成表达式(&源树, &语义产物, 请求.锁定依赖, &参数名表, *表达式节点, 表达式记号, 0)?;
    let 参数绑定: String = (0..参数名表.len())
        .map(|位置| format!("            let 参数{位置} = 取入参整数(入参槽, {位置})?;\n"))
        .collect();
    let 执行源码 = format!(
        "use v1_contract::数据槽;\n\
         #[derive(Debug, PartialEq, Eq)]\n\
         pub enum 内部执行错误 {{ 算术失败, 宿主失败(u32), 入参不符, 返回类型不符 }}\n\
         pub fn 模块执行(宿主调用: &mut dyn FnMut(u32, &[数据槽], &mut 数据槽) -> Result<(), u32>, 入参槽: &[数据槽]) -> Result<i64, 内部执行错误> {{\n\
             let _ = &宿主调用;\n\
             if 入参槽.len() != {参数个数} {{ return Err(内部执行错误::入参不符); }}\n\
         {参数绑定}    Ok({返回表达式})\n\
         }}\n\
         fn 取入参整数(入参槽: &[数据槽], 位置: usize) -> Result<i64, 内部执行错误> {{\n\
             let 槽 = &入参槽[位置];\n\
             if 槽.类型标签 != 1 || 槽.槽标志位 != 0 || 槽.保留 != 0 || 槽.槽字节长度 != 8 {{ return Err(内部执行错误::入参不符); }}\n\
             Ok(槽.槽值 as i64)\n\
         }}\n\
         fn 取宿主整数(宿主调用: &mut dyn FnMut(u32, &[数据槽], &mut 数据槽) -> Result<(), u32>, 能力号: u32, 调用实参: &[i64]) -> Result<i64, 内部执行错误> {{\n\
             let 入参槽表: Vec<_> = 调用实参.iter().map(|&整数值| 数据槽::内联槽(1u32.into(), 整数值 as u64, 8)).collect();\n\
             let mut 返回槽 = 数据槽::空槽();\n\
             宿主调用(能力号, &入参槽表, &mut 返回槽).map_err(内部执行错误::宿主失败)?;\n\
             if 返回槽.类型标签 != 1 || 返回槽.槽标志位 != 0 || 返回槽.保留 != 0 || 返回槽.槽字节长度 != 8 {{ return Err(内部执行错误::返回类型不符); }}\n\
             Ok(返回槽.槽值 as i64)\n\
         }}\n",
        参数个数 = 参数名表.len(),
        参数绑定 = 参数绑定,
    );
    Ok(本机源码产物 {
        原文证据: 请求.程序文本.to_vec(), 命令表证据: 请求.命令表.编码(),
        常量表证据: 请求.常量表.编码(), 类型表证据: 请求.类型表.编码(),
        锁定依赖: 请求.锁定依赖.to_vec(), 工具链身份: 请求.工具链身份.to_owned(),
        平台身份: 请求.平台身份.to_owned(), 执行源码,
    })
}
