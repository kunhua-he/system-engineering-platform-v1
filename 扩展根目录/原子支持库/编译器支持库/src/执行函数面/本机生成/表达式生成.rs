fn 取顶层位置(记号切片: &[&[u8]], 分隔: &[&[u8]]) -> Result<Vec<usize>, ()> {
    let mut 括号深度 = 0usize;
    let mut 分隔位置 = Vec::new();
    for (记号位置, 记号文) in 记号切片.iter().enumerate() {
        match *记号文 {
            b"(" => 括号深度 += 1,
            b")" => 括号深度 = 括号深度.checked_sub(1).ok_or(())?,
            _ if 括号深度 == 0 && 分隔.contains(记号文) => 分隔位置.push(记号位置),
            _ => {}
        }
    }
    if 括号深度 != 0 { return Err(()); }
    Ok(分隔位置)
}

fn 去外括号<'切片>(mut 记号切片: &'切片 [&[u8]]) -> Result<&'切片 [&'切片 [u8]], ()> {
    取顶层位置(记号切片, &[])?;
    while 记号切片.first() == Some(&b"(".as_slice()) {
        let mut 括号深度 = 0usize;
        let mut 配对位置 = None;
        for (记号位置, 记号文) in 记号切片.iter().enumerate() {
            match *记号文 {
                b"(" => 括号深度 += 1,
                b")" => {
                    括号深度 -= 1;
                    if 括号深度 == 0 { 配对位置 = Some(记号位置); break; }
                }
                _ => {}
            }
        }
        if 配对位置 != Some(记号切片.len() - 1) { break; }
        记号切片 = &记号切片[1..记号切片.len() - 1];
    }
    Ok(记号切片)
}

/// 生成一条表达式的**不变环境**：一次程序生成内固定不变的五件 —— 源树 · 语义产物 ·
/// 锁定依赖 · 参数名表 · 参数类型号表。
///
/// 单独一捆（而不是全摊成形参）：`生成表达式` 递归调自身，摊开是九个形参 ⇒
/// 严格 Clippy 的 `clippy::too_many_arguments` 会红；捆起来只剩「环境 + 本次节点」。
/// 全是引用 ⇒ 本结构 `Copy`，递归时按值传，不额外借用、不延长任何借用。
#[derive(Clone, Copy)]
pub(super) struct 生成上下文<'a> {
    pub(super) 源树: &'a 语法树,
    pub(super) 语义产物: &'a 带号结构,
    pub(super) 锁定依赖: &'a [本机依赖],
    pub(super) 参数名表: &'a [Vec<u8>],
    pub(super) 参数类型号表: &'a [u32],
}

pub(super) fn 生成表达式(
    上下文: 生成上下文<'_>, 节点: u32, 记号切片: &[&[u8]], 生成深度: usize, 期望类型号: u32,
) -> Result<String, 本机生成错误> {
    let 生成上下文 { 源树, 语义产物, 锁定依赖, 参数名表, 参数类型号表 } = 上下文;
    let 拒绝记号 = || 本机生成错误::表达式不完整 { 节点 };
    if 生成深度 >= 32 { return Err(拒绝记号()); }
    let 记号切片 = 去外括号(记号切片).map_err(|_| 拒绝记号())?;
    let 子节点表 = 取有效子(源树, 节点);
    match 源树.节点表[节点 as usize].节点类别 {
        节点种类::数值字面量 => {
            if 期望类型号 != 整数型标签 { return Err(本机生成错误::类型不符 { 节点 }); }
            if !子节点表.is_empty() || 记号切片.len() != 1
                || Some(记号切片[0]) != 源树.原文切片(节点)
            { return Err(拒绝记号()); }
            let 整数值 = std::str::from_utf8(记号切片[0]).ok().and_then(|原文文本| 原文文本.parse::<i64>().ok())
                .ok_or(本机生成错误::整数超界 { 节点 })?;
            Ok(format!("数据槽::内联槽({整数型标签}u32.into(), ({整数值}i64) as u64, 8)"))
        }
        节点种类::文本字面量 => {
            if 期望类型号 != 文本型标签 { return Err(本机生成错误::类型不符 { 节点 }); }
            if !子节点表.is_empty() || 记号切片.len() != 1
                || Some(记号切片[0]) != 源树.原文切片(节点)
            { return Err(拒绝记号()); }
            let 文本值 = 剥文本字面量(记号切片[0]).ok_or(本机生成错误::文本字面量非法 { 节点 })?;
            let 转义文本 = 转义文本字面量(&文本值);
            Ok(format!("{{ const 文本: &str = \"{转义文本}\"; 数据槽::指针({文本型标签}u32.into(), 文本.as_ptr() as u64, 文本.len() as u64, false) }}"))
        }
        节点种类::二元运算 => {
            if 期望类型号 != 整数型标签 { return Err(本机生成错误::类型不符 { 节点 }); }
            let [左节点, 右节点] = 子节点表.as_slice() else { return Err(拒绝记号()); };
            let 分隔位置 = 取顶层位置(记号切片, &["＋".as_bytes(), "－".as_bytes(), "×".as_bytes(), "÷".as_bytes()])
                .map_err(|_| 拒绝记号())?;
            let 运算位置 = *分隔位置.last().ok_or_else(拒绝记号)?;
            let 运算函数 = match 记号切片[运算位置] {
                原文文本 if 原文文本 == "＋".as_bytes() => "checked_add",
                原文文本 if 原文文本 == "－".as_bytes() => "checked_sub",
                原文文本 if 原文文本 == "×".as_bytes() => "checked_mul",
                原文文本 if 原文文本 == "÷".as_bytes() => "checked_div",
                _ => return Err(拒绝记号()),
            };
            let 左操作式 = 生成表达式(上下文, *左节点, &记号切片[..运算位置], 生成深度 + 1, 整数型标签)?;
            let 右操作式 = 生成表达式(上下文, *右节点, &记号切片[运算位置 + 1..], 生成深度 + 1, 整数型标签)?;
            Ok(format!("({{ let 左槽 = {左操作式}; let 右槽 = {右操作式}; let 左整数 = 取槽整数(&左槽)?; let 右整数 = 取槽整数(&右槽)?; 数据槽::内联槽({整数型标签}u32.into(), 左整数.{运算函数}(右整数).ok_or(内部执行错误::算术失败)? as u64, 8) }})"))
        }
        节点种类::标识符引用 => {
            let 引用项 = 语义产物.按节点找(节点).ok_or(本机生成错误::依赖不匹配)?;
            if 引用项.号类别 != 号类::变量项 || 引用项.作用域 != 作用域::局部作用域 {
                return Err(本机生成错误::依赖不匹配);
            }
            let 名称 = 源树.原文切片(节点).ok_or_else(拒绝记号)?;
            let 所在位置 = 参数名表.iter().position(|参数名| 参数名.as_slice() == 名称)
                .ok_or_else(拒绝记号)?;
            if 参数类型号表.get(所在位置).copied() != Some(期望类型号) {
                return Err(本机生成错误::类型不符 { 节点 });
            }
            Ok(format!("入参槽[{所在位置}].clone()"))
        }
        节点种类::命令调用 => {
            let Some((&名称节点, 实参节点表)) = 子节点表.split_first() else { return Err(拒绝记号()); };
            if 记号切片.len() < 3 || Some(记号切片[0]) != 源树.原文切片(名称节点)
                || 记号切片[1] != b"(" || 记号切片.last() != Some(&b")".as_slice())
            { return Err(拒绝记号()); }
            let 引用项 = 语义产物.按节点找(名称节点).ok_or(本机生成错误::依赖不匹配)?;
            if 引用项.号类别 != 号类::能力 || 引用项.来源 != 号来源::命令表 {
                return Err(本机生成错误::依赖不匹配);
            }
            let 依赖签名 = 锁定依赖.iter().find(|依赖签名|
                依赖签名.能力号 == 引用项.编号 && 依赖签名.名称 == 记号切片[0]
            ).ok_or(本机生成错误::依赖不匹配)?;
            let 实参记号 = &记号切片[2..记号切片.len() - 1];
            let 分隔位置 = 取顶层位置(实参记号, &[b","]).map_err(|_| 拒绝记号())?;
            let mut 实参切片表 = Vec::new();
            let mut 起始位置 = 0;
            for 分隔下标 in 分隔位置 {
                实参切片表.push(&实参记号[起始位置..分隔下标]);
                起始位置 = 分隔下标 + 1;
            }
            if !实参记号.is_empty() { 实参切片表.push(&实参记号[起始位置..]); }
            if 实参切片表.len() != 实参节点表.len() || 实参节点表.len() != 依赖签名.入参类型表.len() {
                return Err(本机生成错误::依赖不匹配);
            }
            if 依赖签名.返回类型 != 期望类型号 { return Err(本机生成错误::类型不符 { 节点 }); }
            let mut 调用实参 = Vec::new();
            for (实参序号, (&实参节点, 实参切片)) in 实参节点表.iter().zip(实参切片表).enumerate() {
                let 实参期望型 = 依赖签名.入参类型表[实参序号];
                调用实参.push(生成表达式(上下文, 实参节点, 实参切片, 生成深度 + 1, 实参期望型)?);
            }
            let 实参赋值: Vec<_> = 调用实参.iter().enumerate().map(|(实参位置, 实参源码)|
                format!("let 调用实参{实参位置} = {实参源码};")
            ).collect();
            let 实参名称: Vec<_> = (0..调用实参.len()).map(|实参位置| format!("调用实参{实参位置}")).collect();
            Ok(format!("({{ {} 取宿主槽(宿主调用, {}u32, &[{}], {}u32)? }})",
                实参赋值.join(" "), 依赖签名.能力号, 实参名称.join(", "), 依赖签名.返回类型))
        }
        _ => Err(本机生成错误::当前子集不支持 { 节点 }),
    }
}

/// 剥文本字面量 —— 去掉定界符，返回内容文本。
///
/// 定界符规则**不在这里判**：走 `词法::引号收尾`（唯一实现）。本函数只做两件事：
/// 读首字符定收尾、按收尾剥尾。定界符不配对 / 不是合法 UTF-8 ⇒ `None`。
fn 剥文本字面量(记号原文: &[u8]) -> Option<String> {
    let 记号文本 = std::str::from_utf8(记号原文).ok()?;
    let 引导字符 = 记号文本.chars().next()?;
    let 收尾字符 = 词法::引号收尾(引导字符)?;
    let 内容文本 = 记号文本.strip_prefix(引导字符)?.strip_suffix(收尾字符)?;
    Some(内容文本.to_owned())
}

/// 转义成能嵌进 Rust 字符串字面量的形态（`\` `"` 与控制字符）。
///
/// 中文等可打印字符**逐字保留**（生成源文件写 UTF-8）；只转义会截断字面量的那几个。
fn 转义文本字面量(文本值: &str) -> String {
    let mut 转义文本 = String::with_capacity(文本值.len());
    for 单字符 in 文本值.chars() {
        match 单字符 {
            '\\' => 转义文本.push_str("\\\\"),
            '"' => 转义文本.push_str("\\\""),
            '\n' => 转义文本.push_str("\\n"),
            '\r' => 转义文本.push_str("\\r"),
            '\t' => 转义文本.push_str("\\t"),
            _ => 转义文本.push(单字符),
        }
    }
    转义文本
}
