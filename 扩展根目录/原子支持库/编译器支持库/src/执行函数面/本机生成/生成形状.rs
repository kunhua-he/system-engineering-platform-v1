use crate::{语言面::形状错误, 语义::{名号表, 语义错误}};

/// 整数型标签 —— 与 `契约声明/类型声明/0001.json` 同号。
///
/// **只此一份**：子集闸、表达式生成、生成的包装体三处都读它，不各自写死字面。
pub(super) const 整数型标签: u32 = 1;
/// 文本型标签 —— 与 `契约声明/类型声明/0004.json` 同号。
pub(super) const 文本型标签: u32 = 4;

/// 本子集**支持的类型号集合** —— 子集闸三处（锁定依赖 / 入口返回 / 每个参数）都读它。
///
/// 加型只改这一处：写死 1 的旧写法会让「加文本型」变成六处散改，漏一处就自我拒收。
pub(super) const 支持类型号表: [u32; 2] = [整数型标签, 文本型标签];

/// 该类型号是否在本子集支持范围内。
pub(super) fn 是否支持类型号(类型号: u32) -> bool {
    支持类型号表.contains(&类型号)
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 本机依赖 {
    pub 名称: Vec<u8>,
    pub 能力号: u16,
    pub 入参类型表: Vec<u32>,
    pub 返回类型: u32,
}

pub struct 本机生成请求<'请求> {
    pub 程序文本: &'请求 [u8],
    pub 命令表: &'请求 名号表,
    pub 常量表: &'请求 名号表,
    pub 类型表: &'请求 名号表,
    pub 锁定依赖: &'请求 [本机依赖],
    pub 工具链身份: &'请求 str,
    pub 平台身份: &'请求 str,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 本机源码产物 {
    pub 原文证据: Vec<u8>,
    pub 命令表证据: Vec<u8>,
    pub 常量表证据: Vec<u8>,
    pub 类型表证据: Vec<u8>,
    pub 锁定依赖: Vec<本机依赖>,
    pub 工具链身份: String,
    pub 平台身份: String,
    pub 执行源码: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 本机生成错误 {
    来源缺失,
    语言形状(形状错误),
    语言语义(语义错误),
    当前子集不支持 { 节点: u32 },
    表达式不完整 { 节点: u32 },
    整数超界 { 节点: u32 },
    依赖不匹配,
    /// 文本字面量剥不出内容（定界符不配对 / 不是合法 UTF-8）。
    文本字面量非法 { 节点: u32 },
    /// 节点自身的类型与**期望类型号**不符（如期望文本型却给了数值字面量）。
    类型不符 { 节点: u32 },
}
