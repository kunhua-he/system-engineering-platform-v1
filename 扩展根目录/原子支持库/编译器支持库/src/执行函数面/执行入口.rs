/// 1101 词法分析：程序文本（**文本槽**，类型标签 4）→ 记号流边界编码（字节集）。
///
/// 入参出参的类型标签逐字取自 `能力声明/1101.json`（参数表行序即契约 · 返回类型 5）。
pub(crate) unsafe extern "C" fn 词法分析执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用（返回槽可写、参数表可读）。
    let Some(原文) = (unsafe { 取文本(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误槽(返回槽, 错误码::参数槽不符) };
        return;
    };
    // SAFETY: 返回槽 可写。
    let 错误码 = match 词法::切记号(&原文) {
        Ok(输出流) => {
            // SAFETY: 返回槽 可写（上面已判非空）。
            unsafe { 写字节集(返回槽, 原生路编码::编码记号流(&输出流)) };
            return;
        }
        Err(错误) => 形状错误码(&错误),
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误槽(返回槽, 错误码) };
}

/// 1102 语法分析：程序文本（**文本槽**，类型标签 4）→ 语法树边界编码（字节集）。
///
/// 入参出参的类型标签逐字取自 `能力声明/1102.json`：参数表是**程序文本**（不是记号流，
/// 与 `说明/设计说明.md` §二 写的「记号流 → 语法树」不同 —— 那是设计稿，声明是契约）。
/// 故本函数把两步串起来：`切记号` → `建树`。两个入口都是既有实现，这里只做接线。
pub(crate) unsafe extern "C" fn 语法分析执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用。
    let Some(原文) = (unsafe { 取文本(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误槽(返回槽, 错误码::参数槽不符) };
        return;
    };
    // SAFETY: 返回槽 可写。
    let 错误码 = match 词法::切记号(&原文).and_then(|输出流| 语法::建树(&输出流)) {
        Ok(语法树) => {
            // SAFETY: 返回槽 可写。
            unsafe { 写字节集(返回槽, 原生路编码::编码语法树(&语法树)) };
            return;
        }
        Err(错误) => 形状错误码(&错误),
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误槽(返回槽, 错误码) };
}

/// 1103 语义分析：程序文本（**文本槽**）+ 三张注册表（**字节集槽**）→ 带号结构边界编码。
///
/// 入参出参逐字取自 `能力声明/1103.json`：参数表 4 行 = 程序文本（类型标签 4）·
/// 命令表 · 常量表 · 类型表（类型标签 5）。**行序即契约**。
///
/// 本函数把契约的「文本入参」串成库内链路：`切记号` → `建树` → [`语义::分析`]
/// （与 `语法分析执行` 串两步是同一条口径：契约入参是文本，库内语义本体吃语法树）。
///
/// 三张表**只能由调用方传入**：本扩展只依赖 `v1-contract`（没有注册表查询口），
/// `统一注册表` 是 `运行内核/` 的内部节点（扩展不许依赖）—— 见 `1103.json` 的三行参数说明。
///
/// 失败三档：入参槽不合契约 → `1135`；三张表的载荷解不出来 / 号装不下 → `1134`；
/// 解不出的名字 → `1136`（第一条）。都是结构化码，不 panic、不返回字符串。
pub(crate) unsafe extern "C" fn 语义分析执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用（返回槽可写、参数表可读）。
    let Some(原文) = (unsafe { 取文本(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误槽(返回槽, 错误码::参数槽不符) };
        return;
    };
    let (Some(命令表字节), Some(常量表字节), Some(类型表字节)) = (
        // SAFETY: 同上。
        unsafe { 取字节集(参数个数, 参数表, 1) },
        unsafe { 取字节集(参数个数, 参数表, 2) },
        unsafe { 取字节集(参数个数, 参数表, 3) },
    ) else {
        // SAFETY: 同上。
        unsafe { 写错误槽(返回槽, 错误码::参数槽不符) };
        return;
    };
    let (Some(命令表), Some(常量表), Some(类型表)) = (
        语义::名号表::解码(&命令表字节),
        语义::名号表::解码(&常量表字节),
        语义::名号表::解码(&类型表字节),
    ) else {
        // SAFETY: 返回槽 可写。
        unsafe { 写错误槽(返回槽, 错误码::结构编码非法) };
        return;
    };
    // SAFETY: 返回槽 可写。
    let 错误码 = match 词法::切记号(&原文).and_then(|输出流| 语法::建树(&输出流)) {
        Ok(语法树) => match 语义::语义分析(&语法树, &命令表, &常量表, &类型表) {
            Ok(带号结构) => {
                // SAFETY: 返回槽 可写。
                unsafe { 写字节集(返回槽, 语义编码::编码带号结构(&带号结构)) };
                return;
            }
            Err(错误) => 语义错误码(&错误),
        },
        Err(错误) => 形状错误码(&错误),
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误槽(返回槽, 错误码) };
}

/// 1106 编译：程序文本 + 三张注册表 + 能力码字节 + 接口说明段（**六个入参槽**）→ `.能力包件` 字节。
///
/// 入参逐字取自 `能力声明/1106.json`（行序即契约）：`程序文本`（4）· `命令表`/`常量表`/`类型表`（5）·
/// `能力码字节`（5）· `接口说明段`（5）。
///
/// # 它到底干了什么（免得把体量读大）
///
/// 定性是 `项目文档/决策记录/2026-09-27_1106产物与入参裁决.md` §二 定的：**它本质是个封装包**，
/// 不是又一层语义分析。本函数三步：
///
/// 1. **真跑上游链** `1101 → 1102 → 1103`（与 `语义分析执行` 同一条口径、同一批实现）——
///    编译得先把程序文本校一遍，失败即报上游那张码（结构化）；
/// 2. **解调用方交来的接口说明段**（`src/能力包件/接口段编码.rs::解码`）—— 解不开即拒，
///    不把形状不对的段封进包；
/// 3. **装包**（`src/能力包件/装包.rs::装包`）：接口说明 + 能力码 + 指纹三段进冻结容器，
///    装包自行当场验往返（冻结容器无段长字段，段数据里凭空出现段头特征会被多切一刀）。
///
/// **不生成码、不猜六字段**（裁决 §四 那两处「不得发明」的缺口）：能力码来自构建侧 `wasm32` 产物，
/// 六字段来源属未裁的「模块声明形状」⇒ 两者都由调用方传。本函数**不假装有码**。
///
/// **1103 的产物（带号结构）不进包**：裁决 §一 已把 `带号结构` 从 1106 的产物候选里移除。
/// 跑 1103 是为了「编译真的过一遍语义」，不是为了包它。
///
/// 失败四档（都已登记，不预立码）：入参槽不合契约 → `1135`；三张表或接口说明段的载荷解不出 → `1134`；
/// 上游链失败 → 那张上游码（`1108–1133` / `1136` / `1137`）；装包失败 → `1134`。
/// **如实登记一处缺口**（与 1102 / 1103 同一处，不在本腿所有权内）：上游链能报出的 `1137`
/// （引号不配对）与 `1108–1133`（记号流 / 语法树形状）不在 `1106.json` 的 `可抛错误码` 里 ——
/// 1103 也是这个形状（`能力声明/1103.json` 只列 `1134`/`1135`/`1136`），补法见 `命令表.rs` 的同一段注。
pub(crate) unsafe extern "C" fn 编译执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用（返回槽可写、参数表可读）。
    let Some(原文) = (unsafe { 取文本(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误槽(返回槽, 错误码::参数槽不符) };
        return;
    };
    let (Some(命令表字节), Some(常量表字节), Some(类型表字节), Some(能力码), Some(接口段字节)) = (
        // SAFETY: 同上。
        unsafe { 取字节集(参数个数, 参数表, 1) },
        unsafe { 取字节集(参数个数, 参数表, 2) },
        unsafe { 取字节集(参数个数, 参数表, 3) },
        unsafe { 取字节集(参数个数, 参数表, 4) },
        unsafe { 取字节集(参数个数, 参数表, 5) },
    ) else {
        // SAFETY: 同上。
        unsafe { 写错误槽(返回槽, 错误码::参数槽不符) };
        return;
    };
    let (Some(命令表), Some(常量表), Some(类型表)) = (
        语义::名号表::解码(&命令表字节),
        语义::名号表::解码(&常量表字节),
        语义::名号表::解码(&类型表字节),
    ) else {
        // SAFETY: 返回槽 可写。
        unsafe { 写错误槽(返回槽, 错误码::结构编码非法) };
        return;
    };
    // 接口说明段：调用方交的是**已编码段数据**（六字段跨不过定长数据槽）。
    // 先解再装：解不开就不封包（形状不对的段不许漂进产物），且编码只有 `接口段编码` 一处。
    let Some(说明) = 接口段编码::解码(&接口段字节) else {
        // SAFETY: 返回槽 可写。
        unsafe { 写错误槽(返回槽, 错误码::结构编码非法) };
        return;
    };
    // 上游链：与 `语义分析执行` 逐字同路（1101 → 1102 → 1103）。带号结构不进包（见上）。
    let 错误码 = match 词法::切记号(&原文).and_then(|输出流| 语法::建树(&输出流)) {
        Ok(语法树) => match 语义::语义分析(&语法树, &命令表, &常量表, &类型表) {
            Ok(_构) => match 装包件(&说明, &能力码) {
                Ok(包件字节) => {
                    // SAFETY: 返回槽 可写。
                    unsafe { 写字节集(返回槽, 包件字节) };
                    return;
                }
                // 装包失败：段头写不出（段名是常量、非空且远短于 27 字节 ⇒ 实际不可达）
                // 或往返不一致。两者都归本库的边界编码码（不另开码 —— 段位 9 裁决 §五）。
                Err(包件错误::生成(_)) | Err(包件错误::往返不一致) => 错误码::结构编码非法,
            },
            Err(错误) => 语义错误码(&错误),
        },
        Err(错误) => 形状错误码(&错误),
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误槽(返回槽, 错误码) };
}

/// 1107 诊断：程序文本（**文本槽**，类型标签 4）→ 诊断结果字节集。
///
/// 调 [`整理诊断`](诊断::整理诊断) 真跑 `1101 词法 → 1102 语法` 链、取**第一个失败**，
/// 经 [`编码诊断结果`](原生路编码::编码诊断结果) 写回返回槽（返回类型 5）。
/// **`None` = 覆盖到的阶段（1101 · 1102）全过，不是「编译成功」** —— 这条诚实口径照
/// `诊断/入口.rs` 文件头原样保留。**1103 已落地但 1107 覆盖不到它**：1107 的契约参数表
/// 只有「程序文本」一行，而 1103 要三张注册表（`能力声明/1107.json` vs `1103.json`）——
/// 这是契约层的事实，不是实现漏做（补法见返回说明）。
///
/// 可抛错误码是**空表**（契约就是空表）：它的产物就是失败本身，所以它自身不许失败 ——
/// 本函数**不写错误码**：文本槽正常（含空文本）必写非空字节集（全过 = 1 字节标签 0，
/// 有失败 = 标签 1 + 诊断）；入参槽不合契约（不是文本槽 / 位次越界）⇒ 写**空字节集** =
/// 「没跑」，与「全过」的 1 字节标记可区分（两条测试钉住这条口径）。
pub(crate) unsafe extern "C" fn 诊断执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用（返回槽可写、参数表可读）。
    let 结果 = match unsafe { 取文本(参数个数, 参数表, 0) } {
        Some(原文) => 诊断::整理诊断(&原文),
        // 槽形状不合契约：可抛错误码是空表 ⇒ 不许写错误码，写空字节集 = 没跑。
        None => {
            // SAFETY: 返回槽 可写（上面已判非空）。
            unsafe { 写字节集(返回槽, Vec::new()) };
            return;
        }
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写字节集(返回槽, 原生路编码::编码诊断结果(结果.as_ref())) };
}

/// 1105 反解容器：`.e` 容器字节 → 容器结构边界编码。
pub(crate) unsafe extern "C" fn 反解容器执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用（返回槽可写、参数表可读）。
    let Some(输入) = (unsafe { 取字节集(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误槽(返回槽, 错误码::参数槽不符) };
        return;
    };
    let 错误码 = match 容器::反解(&输入) {
        Ok(容器) => {
            // SAFETY: 返回槽 可写（上面已判非空）。
            unsafe { 写字节集(返回槽, 结构编码::编码容器(&容器)) };
            return;
        }
        Err(容器::反解错误::魔数不符) => 错误码::魔数不符,
        Err(容器::反解错误::段头截断 { .. }) => 错误码::段头截断,
        Err(容器::反解错误::段数据越界 { .. }) => 错误码::段数据越界,
        Err(容器::反解错误::段头标记不符 { .. }) => 错误码::段头标记不符,
        Err(容器::反解错误::段类型未知 { .. }) => 错误码::段类型未知,
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误槽(返回槽, 错误码) };
}

/// 1104 生成容器：容器结构边界编码 → `.e` 容器字节。
pub(crate) unsafe extern "C" fn 生成容器执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 调用方按契约形状调用。
    let Some(输入) = (unsafe { 取字节集(参数个数, 参数表, 0) }) else {
        // SAFETY: 同上。
        unsafe { 写错误槽(返回槽, 错误码::参数槽不符) };
        return;
    };
    let Some(容器) = 结构编码::解码容器(&输入) else {
        // SAFETY: 返回槽 可写。
        unsafe { 写错误槽(返回槽, 错误码::结构编码非法) };
        return;
    };
    let 错误码 = match 容器::生成(&容器) {
        Ok(字节) => {
            // SAFETY: 返回槽 可写。
            unsafe { 写字节集(返回槽, 字节) };
            return;
        }
        Err(容器::生成错误::段名为空 { .. }) => 错误码::段名为空,
        Err(容器::生成错误::段名过长 { .. }) => 错误码::段名过长,
    };
    // SAFETY: 返回槽 可写。
    unsafe { 写错误槽(返回槽, 错误码) };
}
