//! 失败写结构化错误码）。
//!
//! 从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现）；六个函数的
//! 签名、接线、失败档与 SAFETY 注释**一字不改**，只把 `super::…` 的取址改成 `crate::…`。

