//! 执行入口 —— 七个 `unsafe extern "C"` 执行函数（入参从 数据槽 取，结果写回 返回槽，
//! 失败写结构化错误码）。
//!
//! **1106 编译已落地**（2026-09-28）：它是一个**封装包** —— 内部真跑
//! `1101 → 1102 → 1103` 把程序文本校一遍，再把调用方交来的**能力码字节**与**接口说明段**
//! 装成 `.能力包件`。为什么这两样由调用方传入：`项目文档/决策记录/2026-09-27_1106产物与入参裁决.md`
//! §四 把它们列为两处「**不得发明**」的缺口，该节自身写的解法就是「入参由调用方给」/
//! 「来源留给调用方」（本仓无代码生成器，六字段来源属未裁的「模块声明形状」）。
//!
//! 从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现）；六个函数的
//! 签名、接线、失败档与 SAFETY 注释**一字不改**，只把 `super::…` 的取址改成 `crate::…`。

