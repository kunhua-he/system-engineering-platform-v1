//! 记录流 —— **段数据内部**的「按表分区记录流」形状（第一轮）。
//!
//! 上游是 `容器.rs`（段框架，1444/1444 逐字节往返通过）。容器层之所以能全绿，是因为它
//! **把段数据一律原样搬运、完全不解析**——那证明的是**段框架正确**，不是段内容被读懂。
//! 本模块吃的就是段内容。
//!
//! # 判据（与容器层同一条，不许放宽）
//!
//! 对语料里容器文件的**程序段**（段类型 3）：`反解段数据(段数据)` → `生成段数据(记录流)`，
//! 产物必须与**原始段数据**逐字节相同。
//!
//! # 语料实测口径
//!
//! 语料：`/tmp/易语言源码` 下全部 1444 个容器文件（大小写不敏感取 `.e`/`.ec`），
//! 其中 **1456** 条程序段（段类型 3）。下表偏移均**相对段数据起点**，全部 1456/1456 命中。
//!
//! ## 段数据头（56 字节）
//!
//! | 偏移 | 宽度 | 取值 | 实测 |
//! |---|---|---|---|
//! | 0x00 | u32 | 段序号（1 基） | 3 / 4 / 5，与容器段序号一致 |
//! | 0x04 | u32 | 保留 | 恒 0 |
//! | 0x08 | u32 | 段数据校验值 | 算法未证实，**原样搬运**，绝不重算 |
//! | 0x0C | u32 | 体长 = 段数据长 − 56 | 1456/1456 |
//! | 0x10 | 40 | 补零 | 恒全零 |
//!
//! ## 段体（体长字节）
//!
//! ```text
//! 0x38  u32   段体甲       实测高 16 位 ∈ {1,2,3,7,10}，低 16 位可变
//! 0x3C  u32   段体魔数     恒 0x030BEF3F（1456/1456 唯一值）
//! 0x40  u32   数组甲字节长 = 4N
//!       N × u32  数组甲
//!       u32   数组乙字节长 = 2N
//!       N × u16  数组乙
//!       u32   数组丙字节长 = 2N
//!       N × u16  数组丙
//!       u16   支持库数 = N（1456/1456 与三个数组元素数一致）
//!       N × 支持库引用记录
//!       其余载荷（本模块**原样搬运**，见下）
//! ```
//!
//! 三个数组的**字节长度前缀**是独立盘面字段（不是从别处推出来的），实测恒等于
//! `4N` / `2N` / `2N`；`u16 支持库数` 又与三者相等——四处独立编码互证，故 N 可信。
//!
//! ## 支持库引用记录
//!
//! `u32 串长` + `串长` 字节，**无 NUL 终止**（下一条记录紧跟其后；这一条与早期把
//! 末字节读成 NUL 的口径不同，见 `说明/记录流形状.md` 第七节）。串按 `0x0D` 切成 5 段：
//!
//! | 序 | 字段 | 实测样例（`lib/krnln/samples/第一个程序.e` 段数据偏移 0x5A，串长 57） |
//! |---|---|---|
//! | 0 | 库文件名 | `KRNLN` |
//! | 1 | GUID | `d09f2340818511d396f6aaf844c7e325` |
//! | 2 | 版本甲 | `4` |
//! | 3 | 版本乙 | `2` |
//! | 4 | 中文名 | `系统核心支持库`（GBK 14 字节） |
//!
//! 全语料共切出 **5290** 条支持库引用记录，其中 **5228** 条恰为 5 段、**62** 条为 6 段
//! （`.npk` 类库，尾部多一段 `0,{GUID...}` 形态的成员表）。本模块按「按 0x0D 切、再按
//! 0x0D 拼回」处理，**对段数不做假设**，故 6 段的也逐字节一致。
//!
//! # 明确**没**吃透的部分（如实登记，不假装全懂）
//!
//! 支持库表之后的**声明记录区**（程序集 / 子程序 / DLL 命令 / 常量 / 语句字节码）
//! 本模块**原样搬运**。这不是实现选择，是当前证据下的诚实状态：见
//! `说明/记录流形状.md` 第五节列出的实测证据（5 个长度前缀块之后出现 4 字节「令牌」，
//! 令牌形如 `<u16 值> 00 01 <u8 类型>`，类型实测有 0x00/0x03/0x04/0x09/0x15/0x16/0x19/
//! 0x25/0x39/0x49/0x52；类型 0x39/0x25/0x16 后随大值，0x19/0x49/0x52/0x04/0x15 后随小值）。
//! 声明记录区的字节占段数据的 **99.78%**，这是本轮**未吃透的大头**，已登记待办。
//!
//! # 一处与容器层同源的口径
//!
//! `体长` 字段是**反解侧对盘面的快照**，`生成` 由内容重算后写回、不读该字段——与容器层
//! 「`生成` 由 `段名` 重算名称区、不读 `名称区` 快照」同一条规矩，避免两个方向各写一套知识。

