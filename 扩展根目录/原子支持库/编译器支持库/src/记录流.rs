//! 记录流 —— **段数据内部**的「按表分区记录流」形状（第一轮）。
//!
//! 上游是 `容器.rs`（段框架，1444/1444 逐字节往返通过）。容器层之所以能全绿，是因为它
//! **把段数据一律原样搬运、完全不解析**——那证明的是**段框架正确**，不是段内容被读懂。
//! 本模块吃的就是段内容。
//!
//! # 判据（与容器层同一条，不许放宽）
//!
//! 对语料里容器文件的**程序段**（段类型 3）：`反解段数据(段数据)` → `生成段数据(记录流)`，
//! 产物必须与**原始段数据**逐字节相同。
//!
//! # 语料实测口径
//!
//! 语料：`/tmp/易语言源码` 下全部 1444 个容器文件（大小写不敏感取 `.e`/`.ec`），
//! 其中 **1456** 条程序段（段类型 3）。下表偏移均**相对段数据起点**，全部 1456/1456 命中。
//!
//! ## 段数据头（56 字节）
//!
//! | 偏移 | 宽度 | 取值 | 实测 |
//! |---|---|---|---|
//! | 0x00 | u32 | 段序号（1 基） | 3 / 4 / 5，与容器段序号一致 |
//! | 0x04 | u32 | 保留 | 恒 0 |
//! | 0x08 | u32 | 段数据校验值 | 算法未证实，**原样搬运**，绝不重算 |
//! | 0x0C | u32 | 体长 = 段数据长 − 56 | 1456/1456 |
//! | 0x10 | 40 | 补零 | 恒全零 |
//!
//! ## 段体（体长字节）
//!
//! ```text
//! 0x38  u32   段体甲       实测高 16 位 ∈ {1,2,3,7,10}，低 16 位可变
//! 0x3C  u32   段体魔数     恒 0x030BEF3F（1456/1456 唯一值）
//! 0x40  u32   数组甲字节长 = 4N
//!       N × u32  数组甲
//!       u32   数组乙字节长 = 2N
//!       N × u16  数组乙
//!       u32   数组丙字节长 = 2N
//!       N × u16  数组丙
//!       u16   支持库数 = N（1456/1456 与三个数组元素数一致）
//!       N × 支持库引用记录
//!       其余载荷（本模块**原样搬运**，见下）
//! ```
//!
//! 三个数组的**字节长度前缀**是独立盘面字段（不是从别处推出来的），实测恒等于
//! `4N` / `2N` / `2N`；`u16 支持库数` 又与三者相等——四处独立编码互证，故 N 可信。
//!
//! ## 支持库引用记录
//!
//! `u32 串长` + `串长` 字节，**无 NUL 终止**（下一条记录紧跟其后；这一条与早期把
//! 末字节读成 NUL 的口径不同，见 `说明/记录流形状.md` 第七节）。串按 `0x0D` 切成 5 段：
//!
//! | 序 | 字段 | 实测样例（`lib/krnln/samples/第一个程序.e` 段数据偏移 0x5A，串长 57） |
//! |---|---|---|
//! | 0 | 库文件名 | `KRNLN` |
//! | 1 | GUID | `d09f2340818511d396f6aaf844c7e325` |
//! | 2 | 版本甲 | `4` |
//! | 3 | 版本乙 | `2` |
//! | 4 | 中文名 | `系统核心支持库`（GBK 14 字节） |
//!
//! 全语料共切出 **5290** 条支持库引用记录，其中 **5228** 条恰为 5 段、**62** 条为 6 段
//! （`.npk` 类库，尾部多一段 `0,{GUID...}` 形态的成员表）。本模块按「按 0x0D 切、再按
//! 0x0D 拼回」处理，**对段数不做假设**，故 6 段的也逐字节一致。
//!
//! # 明确**没**吃透的部分（如实登记，不假装全懂）
//!
//! 支持库表之后的**声明记录区**（程序集 / 子程序 / DLL 命令 / 常量 / 语句字节码）
//! 本模块**原样搬运**。这不是实现选择，是当前证据下的诚实状态：见
//! `说明/记录流形状.md` 第五节列出的实测证据（5 个长度前缀块之后出现 4 字节「令牌」，
//! 令牌形如 `<u16 值> 00 01 <u8 类型>`，类型实测有 0x00/0x03/0x04/0x09/0x15/0x16/0x19/
//! 0x25/0x39/0x49/0x52；类型 0x39/0x25/0x16 后随大值，0x19/0x49/0x52/0x04/0x15 后随小值）。
//! 声明记录区的字节占段数据的 **99.78%**，这是本轮**未吃透的大头**，已登记待办。
//!
//! # 一处与容器层同源的口径
//!
//! `体长` 字段是**反解侧对盘面的快照**，`生成` 由内容重算后写回、不读该字段——与容器层
//! 「`生成` 由 `段名` 重算名称区、不读 `名称区` 快照」同一条规矩，避免两个方向各写一套知识。

/// 段数据头长度（字节）。
pub const 段数据头长度: usize = 56;

/// 段体魔数（段数据偏移 0x3C 起的 u32）。实测 1456/1456 唯一值。
pub const 段体魔数: u32 = 0x030B_EF3F;

/// 支持库引用串的字段分隔符（`0x0D`，即 CR）。
pub const 引用分隔符: u8 = 0x0D;

/// 支持库引用串的字段名，**顺序即盘面顺序**。
pub const 引用字段名: [&str; 5] = ["库文件名", "GUID", "版本甲", "版本乙", "中文名"];

/// 段数据头内各字段的相对偏移。
pub mod 头偏移 {
    /// u32 段序号（1 基）。
    pub const 段序号: usize = 0x00;
    /// u32 保留，恒 0。
    pub const 保留: usize = 0x04;
    /// u32 段数据校验值。算法未证实，原样搬运。
    pub const 校验值: usize = 0x08;
    /// u32 体长 = 段数据长 − 56。
    pub const 体长: usize = 0x0C;
    /// 40 字节补零，恒全零。
    pub const 补零: usize = 0x10;
    /// 补零区长度。
    pub const 补零长度: usize = 40;
    /// u32 段体甲。
    pub const 体甲: usize = 0x38;
    /// u32 段体魔数 `0x030BEF3F`。
    pub const 体魔数: usize = 0x3C;
}

/// 段数据头（56 字节，逐字段对齐原文）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 段数据头 {
    /// u32 段序号（1 基）。实测取值 3 / 4 / 5。
    pub 段序号: u32,
    /// u32 保留。实测恒 0。
    pub 保留: u32,
    /// u32 段数据校验值。**算法未证实**：反解原样读、生成原样写，绝不重算。
    pub 校验值: u32,
    /// u32 体长 = 段数据长 − 56。**反解侧快照**：生成由内容重算，不读本字段。
    pub 体长: u32,
    /// 40 字节补零。实测恒全零，反解与生成都按「必须全零」处理。
    pub 补零: [u8; 40],
}

/// 段体头（段体前 8 字节）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 段体头 {
    /// u32 段体甲（段数据偏移 0x38）。实测高 16 位 ∈ {1,2,3,7,10}，低 16 位可变。
    pub 甲: u32,
}

/// 一条支持库引用记录。盘面是「u32 串长 + 串长字节」，本结构把它切成字段表。
///
/// `字段` 是**按 `0x0D` 切**的结果；生成时**按 `0x0D` 拼回**，故段数任意都逐字节一致。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 支持库引用 {
    /// 按 `0x0D` 切出的字段。至少 1 段（空串切成 `[""]`）。
    pub 字段: Vec<Vec<u8>>,
}

impl 支持库引用 {
    /// 由字段表建一条引用记录。字段表为空时补一个空段（与空串同构）。
    pub fn 由字段(字段: Vec<Vec<u8>>) -> Self {
        if 字段.is_empty() {
            Self { 字段: vec![Vec::new()] }
        } else {
            Self { 字段 }
        }
    }

    /// 字段数。5 段时与 [`引用字段名`] 一一对应。
    pub fn 字段数(&self) -> usize {
        self.字段.len()
    }

    /// 取第 `序号` 段。
    pub fn 取(&self, 序号: usize) -> Option<&[u8]> {
        self.字段.get(序号).map(Vec::as_slice)
    }

    /// 盘面串长（不含长度字段本身）：各段字节和 + 段间分隔符数。
    pub fn 串长(&self) -> usize {
        self.字段.iter().map(Vec::len).sum::<usize>() + self.字段.len().saturating_sub(1)
    }

    /// 按 `0x0D` 拼回盘面原文。与 [`支持库引用::字段`] 互为逆运算。
    pub fn 原文(&self) -> Vec<u8> {
        let mut 出 = Vec::with_capacity(self.串长());
        for (序, 段) in self.字段.iter().enumerate() {
            if 序 > 0 {
                出.push(引用分隔符);
            }
            出.extend_from_slice(段);
        }
        出
    }

    /// 5 段时取 `库文件名`。
    pub fn 库文件名(&self) -> Option<&[u8]> {
        self.五段()?.first().map(Vec::as_slice)
    }
    /// 5 段时取 `GUID`。
    pub fn GUID(&self) -> Option<&[u8]> {
        self.五段()?.get(1).map(Vec::as_slice)
    }
    /// 5 段时取 `版本甲`。
    pub fn 版本甲(&self) -> Option<&[u8]> {
        self.五段()?.get(2).map(Vec::as_slice)
    }
    /// 5 段时取 `版本乙`。
    pub fn 版本乙(&self) -> Option<&[u8]> {
        self.五段()?.get(3).map(Vec::as_slice)
    }
    /// 5 段时取 `中文名`。6 段（`.npk` 类库）时返回 `None`，不做猜测。
    pub fn 中文名(&self) -> Option<&[u8]> {
        self.五段()?.get(4).map(Vec::as_slice)
    }

    fn 五段(&self) -> Option<&Vec<Vec<u8>>> {
        if self.字段.len() == 引用字段名.len() { Some(&self.字段) } else { None }
    }
}

/// 支持库表：三个带字节长度前缀的索引数组 + 支持库数 + 引用记录表。
///
/// 三个数组的元素数**必须相等**，且等于 `支持库数`；四处在盘面上是独立编码，互为校验。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 支持库表 {
    /// 数组甲：N × u32，盘面字节长度前缀 = `4N`。
    pub 数组甲: Vec<u32>,
    /// 数组乙：N × u16，盘面字节长度前缀 = `2N`。
    pub 数组乙: Vec<u16>,
    /// 数组丙：N × u16，盘面字节长度前缀 = `2N`。
    pub 数组丙: Vec<u16>,
    /// 支持库引用记录，条数 = N。
    pub 引用表: Vec<支持库引用>,
}

/// 记录流：段数据头 + 段体头 + 支持库表 + 其余载荷。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 记录流 {
    /// 段数据头（56 字节）。
    pub 头: 段数据头,
    /// 段体头。
    pub 体头: 段体头,
    /// 支持库表。
    pub 支持库: 支持库表,
    /// **声明记录区**：程序集 / 子程序 / DLL 命令 / 常量 / 语句字节码。
    ///
    /// 本模块**原样搬运**（实测占段数据 99.78%）。见模块注释「明确没吃透的部分」。
    pub 其余载荷: Vec<u8>,
}

impl 记录流 {
    /// 记录条数：段数据头 1 + 段体头 1 + 支持库表 1 + 支持库引用 N + 其余载荷 0/1。
    pub fn 记录条数(&self) -> u64 {
        3 + self.支持库.引用表.len() as u64 + u64::from(!self.其余载荷.is_empty())
    }

    /// 已结构化的字节数（= 段数据长 − 其余载荷长）。
    pub fn 结构化字节(&self) -> u64 {
        段数据头长度 as u64 + 体长实算(self) - self.其余载荷.len() as u64
    }

    /// 按当前内容重算 `体长`（生成前自检用；`生成` 本来就会重算，故不是必需步骤）。
    pub fn 重算体长(&mut self) {
        self.头.体长 = u32::try_from(体长实算(self)).unwrap_or(u32::MAX);
    }
}

/// 体长实算：段数据头之后应有的字节数。**只由内容决定**，与 `头.体长` 字段无关。
pub fn 体长实算(流: &记录流) -> u64 {
    let n = 流.支持库.数组甲.len() as u64;
    let 引用: u64 = 流.支持库.引用表.iter().map(|引用| 4 + 引用.串长() as u64).sum();
    8 + (4 + 4 * n) + (4 + 2 * n) + (4 + 2 * n) + 2 + 引用 + 流.其余载荷.len() as u64
}

/// 反解错误。结构化段位，不是字符串。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 反解错误 {
    /// 段数据不足 56 字节。
    段数据头截断 { 需要: u64, 实有: u64 },
    /// 段数据头的保留字段非零（实测 1456/1456 为 0）。
    段数据头保留非零 { 位置: u64, 实取: u32 },
    /// 段数据头的补零区出现非零字节（实测 1456/1456 全零）。
    段数据头补零非零 { 位置: u64 },
    /// 头内体长与「段数据长 − 56」不符。
    体长不符 { 头内: u64, 实有: u64 },
    /// 段体不足 8 字节。
    段体截断 { 位置: u64, 需要: u64, 剩余: u64 },
    /// 段体魔数不是 `0x030BEF3F`。
    段体魔数不符 { 位置: u64, 实取: u32 },
    /// 数组字节长度前缀不是元素宽的整数倍。
    数组长度前缀非整元素 { 第几: u8, 前缀: u64, 元素宽: u8 },
    /// 数组体或长度前缀本身越过段数据尾。
    数组越界 { 第几: u8, 前缀: u64, 剩余: u64 },
    /// 三个数组元素数与 `u16 支持库数` 不一致。
    支持库数不符 { 数组元素数: u64, 声明数: u64 },
    /// 支持库引用串越过段数据尾。
    支持库引用越界 { 第几条: u32, 串长: u64, 剩余: u64 },
}

/// 生成错误。结构化段位，不是字符串。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 生成错误 {
    /// 三个数组元素数与引用表条数不一致。
    支持库数组长度不一致 { 甲: u64, 乙: u64, 丙: u64, 引用表: u64 },
    /// 某条引用记录的字段表为空（无法与空串区分）。
    支持库引用字段为空 { 第几条: u32 },
    /// `头.补零` 非全零——盘面不允许，拒绝生成。
    补零非零 { 第几字节: u32 },
}

/// 反解：段数据字节 → 记录流。
///
/// 成功即保证 `生成段数据(反解段数据(字节)) == 字节`：所有非字节精确可写回的输入
/// （保留非零 / 补零非零 / 体长不符 / 魔数不符 / 长度前缀不整 / 越界）都在反解阶段被拒。
pub fn 反解段数据(字节: &[u8]) -> Result<记录流, 反解错误> {
    if 字节.len() < 段数据头长度 {
        return Err(反解错误::段数据头截断 {
            需要: 段数据头长度 as u64,
            实有: 字节.len() as u64,
        });
    }
    let 头 = 解析段数据头(字节)?;

    let 实有体长 = (字节.len() - 段数据头长度) as u64;
    if 头.体长 as u64 != 实有体长 {
        return Err(反解错误::体长不符 { 头内: 头.体长 as u64, 实有: 实有体长 });
    }

    let 体 = &字节[段数据头长度..];
    let (体头, 位置) = 解析段体头(体)?;
    let (支持库, 位置) = 解析支持库(体, 位置)?;

    Ok(记录流 {
        头,
        体头,
        支持库,
        其余载荷: 体[位置..].to_vec(),
    })
}

/// 生成：记录流 → 段数据字节。**必须与 `反解段数据` 构成往返一致**。
pub fn 生成段数据(流: &记录流) -> Result<Vec<u8>, 生成错误> {
    let 甲 = 流.支持库.数组甲.len() as u64;
    let 乙 = 流.支持库.数组乙.len() as u64;
    let 丙 = 流.支持库.数组丙.len() as u64;
    let 引用 = 流.支持库.引用表.len() as u64;
    if 甲 != 乙 || 甲 != 丙 || 甲 != 引用 {
        return Err(生成错误::支持库数组长度不一致 { 甲, 乙, 丙, 引用表: 引用 });
    }
    for (序号, 一条) in 流.支持库.引用表.iter().enumerate() {
        if 一条.字段.is_empty() {
            return Err(生成错误::支持库引用字段为空 { 第几条: 序号 as u32 });
        }
    }
    if let Some(位) = 流.头.补零.iter().position(|&字节| 字节 != 0) {
        return Err(生成错误::补零非零 { 第几字节: 位 as u32 });
    }

    let 体长 = 体长实算(流);
    let mut 出 = Vec::with_capacity(段数据头长度 + 体长 as usize);

    出.extend_from_slice(&流.头.段序号.to_le_bytes());
    出.extend_from_slice(&流.头.保留.to_le_bytes());
    出.extend_from_slice(&流.头.校验值.to_le_bytes());
    // 体长由内容重算后写回，不读 `头.体长`（见模块注释「一处与容器层同源的口径」）。
    出.extend_from_slice(&(体长 as u32).to_le_bytes());
    出.extend_from_slice(&流.头.补零);

    出.extend_from_slice(&流.体头.甲.to_le_bytes());
    出.extend_from_slice(&段体魔数.to_le_bytes());

    出.extend_from_slice(&((4 * 甲) as u32).to_le_bytes());
    for 值 in &流.支持库.数组甲 {
        出.extend_from_slice(&值.to_le_bytes());
    }
    出.extend_from_slice(&((2 * 甲) as u32).to_le_bytes());
    for 值 in &流.支持库.数组乙 {
        出.extend_from_slice(&值.to_le_bytes());
    }
    出.extend_from_slice(&((2 * 甲) as u32).to_le_bytes());
    for 值 in &流.支持库.数组丙 {
        出.extend_from_slice(&值.to_le_bytes());
    }
    出.extend_from_slice(&(甲 as u16).to_le_bytes());

    for 一条 in &流.支持库.引用表 {
        出.extend_from_slice(&(一条.串长() as u32).to_le_bytes());
        出.extend_from_slice(&一条.原文());
    }

    出.extend_from_slice(&流.其余载荷);
    Ok(出)
}

/// 解析 56 字节段数据头。保留必须为 0、补零区必须全零，否则 fail-closed。
fn 解析段数据头(字节: &[u8]) -> Result<段数据头, 反解错误> {
    let 保留 = 读u32(字节, 头偏移::保留);
    if 保留 != 0 {
        return Err(反解错误::段数据头保留非零 {
            位置: 头偏移::保留 as u64,
            实取: 保留,
        });
    }
    let 补零尾 = 头偏移::补零 + 头偏移::补零长度;
    if let Some(位) = 字节[头偏移::补零..补零尾].iter().position(|&字节| 字节 != 0) {
        return Err(反解错误::段数据头补零非零 {
            位置: (头偏移::补零 + 位) as u64,
        });
    }
    let mut 补零 = [0u8; 头偏移::补零长度];
    补零.copy_from_slice(&字节[头偏移::补零..补零尾]);

    Ok(段数据头 {
        段序号: 读u32(字节, 头偏移::段序号),
        保留,
        校验值: 读u32(字节, 头偏移::校验值),
        体长: 读u32(字节, 头偏移::体长),
        补零,
    })
}

/// 解析段体头（体前 8 字节）。返回（段体头，下一字段在体内的偏移）。
fn 解析段体头(体: &[u8]) -> Result<(段体头, usize), 反解错误> {
    const 体头长度: usize = 8;
    if 体.len() < 体头长度 {
        return Err(反解错误::段体截断 {
            位置: 0,
            需要: 体头长度 as u64,
            剩余: 体.len() as u64,
        });
    }
    let 魔数 = 读u32(体, 4);
    if 魔数 != 段体魔数 {
        return Err(反解错误::段体魔数不符 {
            位置: 4,
            实取: 魔数,
        });
    }
    Ok((段体头 { 甲: 读u32(体, 0) }, 体头长度))
}

/// 解析支持库表（三个索引数组 + 支持库数 + N 条引用记录）。
fn 解析支持库(体: &[u8], 起点: usize) -> Result<(支持库表, usize), 反解错误> {
    let mut 位置 = 起点;
    let 数组甲 = 读数组u32(体, &mut 位置, 1)?;
    let 数组乙 = 读数组u16(体, &mut 位置, 2)?;
    let 数组丙 = 读数组u16(体, &mut 位置, 3)?;

    if 位置 + 2 > 体.len() {
        return Err(反解错误::数组越界 {
            第几: 4,
            前缀: 2,
            剩余: (体.len() - 位置) as u64,
        });
    }
    let 声明数 = u64::from(读u16(体, 位置));
    位置 += 2;

    let 元素数 = 数组甲.len() as u64;
    if 声明数 != 元素数 || 数组乙.len() as u64 != 元素数 || 数组丙.len() as u64 != 元素数 {
        return Err(反解错误::支持库数不符 { 数组元素数: 元素数, 声明数 });
    }

    let mut 引用表 = Vec::with_capacity(声明数 as usize);
    for 序号 in 0..声明数 {
        let 剩余 = (体.len() - 位置) as u64;
        if 剩余 < 4 {
            return Err(反解错误::支持库引用越界 {
                第几条: 序号 as u32,
                串长: 0,
                剩余,
            });
        }
        let 串长 = u64::from(读u32(体, 位置));
        位置 += 4;
        let 剩余 = (体.len() - 位置) as u64;
        if 串长 > 剩余 {
            return Err(反解错误::支持库引用越界 {
                第几条: 序号 as u32,
                串长,
                剩余,
            });
        }
        let 尾 = 位置 + 串长 as usize;
        引用表.push(支持库引用 {
            字段: 切串(&体[位置..尾]),
        });
        位置 = 尾;
    }

    Ok((支持库表 { 数组甲, 数组乙, 数组丙, 引用表 }, 位置))
}

/// 读一个「u32 字节长度前缀 + 该长度字节」的 u32 数组。
fn 读数组u32(体: &[u8], 位置: &mut usize, 第几: u8) -> Result<Vec<u32>, 反解错误> {
    let 前缀 = 读长度前缀(体, 位置, 第几, 4)?;
    let 元素数 = (前缀 / 4) as usize;
    let mut 出 = Vec::with_capacity(元素数);
    for 序 in 0..元素数 {
        出.push(读u32(体, *位置 + 序 * 4));
    }
    *位置 += 前缀 as usize;
    Ok(出)
}

/// 读一个「u32 字节长度前缀 + 该长度字节」的 u16 数组。
fn 读数组u16(体: &[u8], 位置: &mut usize, 第几: u8) -> Result<Vec<u16>, 反解错误> {
    let 前缀 = 读长度前缀(体, 位置, 第几, 2)?;
    let 元素数 = (前缀 / 2) as usize;
    let mut 出 = Vec::with_capacity(元素数);
    for 序 in 0..元素数 {
        出.push(读u16(体, *位置 + 序 * 2));
    }
    *位置 += 前缀 as usize;
    Ok(出)
}

/// 读一个数组的 u32 字节长度前缀，并校验「整元素 + 不越界」。
fn 读长度前缀(体: &[u8], 位置: &mut usize, 第几: u8, 元素宽: u8) -> Result<u64, 反解错误> {
    if *位置 + 4 > 体.len() {
        return Err(反解错误::数组越界 {
            第几,
            前缀: 4,
            剩余: (体.len() - *位置) as u64,
        });
    }
    let 前缀 = u64::from(读u32(体, *位置));
    *位置 += 4;
    if 前缀 % u64::from(元素宽) != 0 {
        return Err(反解错误::数组长度前缀非整元素 { 第几, 前缀, 元素宽 });
    }
    let 剩余 = (体.len() - *位置) as u64;
    if 前缀 > 剩余 {
        return Err(反解错误::数组越界 { 第几, 前缀, 剩余 });
    }
    Ok(前缀)
}

/// 按 `0x0D` 切串。与 `拼串`（`支持库引用::原文`）互为逆运算：任意字节串都逐字节还原。
fn 切串(串: &[u8]) -> Vec<Vec<u8>> {
    let mut 出: Vec<Vec<u8>> = Vec::new();
    let mut 起 = 0usize;
    for (位, &字节) in 串.iter().enumerate() {
        if 字节 == 引用分隔符 {
            出.push(串[起..位].to_vec());
            起 = 位 + 1;
        }
    }
    出.push(串[起..].to_vec());
    出
}

/// 小端读 u32。调用方必须先保证 `位置 + 4 <= 字节.len()`。
fn 读u32(字节: &[u8], 位置: usize) -> u32 {
    debug_assert!(位置 + 4 <= 字节.len());
    u32::from_le_bytes([
        字节[位置],
        字节[位置 + 1],
        字节[位置 + 2],
        字节[位置 + 3],
    ])
}

/// 小端读 u16。调用方必须先保证 `位置 + 2 <= 字节.len()`。
fn 读u16(字节: &[u8], 位置: usize) -> u16 {
    debug_assert!(位置 + 2 <= 字节.len());
    u16::from_le_bytes([字节[位置], 字节[位置 + 1]])
}

