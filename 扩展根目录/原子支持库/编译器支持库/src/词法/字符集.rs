//! 词法 · 字符集 —— 「哪个字符归哪一类」的**唯一定义处**。
//!
//! 本件只回答「是不是」，不做切分（切分在 [`super::切分`]）。每条集合都注明**出处**：
//! 「规格点名」＝ `项目文档/设计文档/程序文本格式.md` §二；「语料实测」＝ `说明/真文本覆盖.md`；
//! 「本腿裁定」＝ 规格与语料都没给、由本实现定死并登记待办的一条。
//!
//! 规格 §二 点名的 11 种记号里，**有 4 种不是「字符集」**（`关键字` 靠行首位置判、
//! `注释` 靠引导符至行尾、`文本字面量` 靠配对定界符、`文件结束` 靠全文末尾），
//! 它们不在这里；本件只管 7 种按字符判的：空白 · 换行 · 注释引导 · 引号 · 界符 · 运算符 · 标识符字符。

/// 空白：**半角空格与制表符**。
///
/// 出处：规格 §二「缩进 **4 个半角空格**」；语料实测缩进 4/8/12 空格、`\t` 计数 **0**。
/// **其他 Unicode 空白（U+3000 全角空格等）语料 0 例** ⇒ 不点名，落 [`是否兜底`]（登记待办）。
pub const fn 是否空白(字符: char) -> bool {
    matches!(字符, ' ' | '\t')
}

/// 换行：`\r` 与 `\n`。
///
/// 出处：规格 §二「写出恒 `\n`（LF）；读入**同时认** `\r\n` 与 `\n`」；语料实测
/// **CRLF 10945 · LF 0 · 裸 CR 0**。
/// 本件只判「是不是换行字符」，宽度（`\r\n` 两字节 / 单字符一字节）由切分器按行尾实测决定。
pub const fn 是否换行(字符: char) -> bool {
    matches!(字符, '\r' | '\n')
}

/// 注释引导：半角单引号 `'`（U+0027）。出处：规格 §二「注释 `'` 至行尾，**不含行尾换行**」；
/// 语料实测 57 条（其中 1 条注释内部还有第二个 `'` —— 首 `'` 赢）。
pub const fn 是否注释引导(字符: char) -> bool {
    字符 == '\''
}

/// 引号：若是定界符，返回**它的收尾字符**；否则 `None`。
///
/// 两种定界符并存且可嵌套（规格 §二 + 语料实测 `.常量 名, "“值”"`），所以**一个种类**
/// （`记号种类::文本字面量`），定界符从区间首字节读 —— 这里就是那个「读」的定义。
///
/// - 全角 `“`（U+201C）→ 收尾 `”`（U+201D）
/// - 全角 `”`（U+201D）→ 收尾 `”`（落单的收尾当引导用，与判定腿 `语料/撞规格.py` 同口径）
/// - 半角 `"`（U+0022）→ 收尾 `"`
///
/// **无转义机制**（语料实测 `“\\计算机名”` 里的 `\\` 是逐字的）；**跨行 0 例**（无证据）。
pub const fn 引号收尾(字符: char) -> Option<char> {
    match 字符 {
        '"' => Some('"'),
        '“' | '”' => Some('”'),
        _ => None,
    }
}

/// 界符：**半角** 9 个。出处：规格 §二「界符半角 `( ) [ ] , . & { }`」；
/// 语料实测 9 种 / 27000 次，**没有第 10 种**。
///
/// `.` 一号两用：行首引导关键字（进 `关键字`，点含在区间内），行内是成员访问（进 `界符`）。
/// **这一层区分由切分器按位置判**（`切分.rs`），不在这里 —— 这里只回答「`.` 是界符字符」。
pub const fn 是否界符(字符: char) -> bool {
    matches!(字符, '(' | ')' | '[' | ']' | ',' | '.' | '&' | '{' | '}')
}

/// 运算符：**全角**（半角 `-` `*` `/` 等仍是兜底）。出处分两段，**证据等级不同，不许混写**：
///
/// - **语料代码位实测 5 个**：`＝`（U+FF1D）`＋`（U+FF0B）`÷`（U+00F7）为规格 §二 点名；
///   `－`（U+FF0D）×3 · `＞`（U+FF1E）×1 见 `说明/真文本覆盖.md` 缺口 4；
/// - **参照实现文档列出、语料代码位未见 9 个**：`×` `％` `＼` `＜` `＞` `≤` `≥` `≠` `≈`
///   （`help/esdn.chm → zlsc/lang.htm` 的运算符表，14 条；见 `真文本覆盖.md` §九.5）。
///
/// **文档级那 9 个已接入本函数**（裁决 `2026-09-28_华哥的尺子与七条裁决.md` §二「文档级 9 个运算符接不接进词法」）：
/// 不接则用它们的程序文本落「兜底 → 备注文本」，是**认不出又不报错**的误类。
/// 逻辑 `且` `或` 不在这里 —— 它们是汉字（[`是否标识符字符`] 为真），单列 [`是否逻辑运算符`]。
pub const fn 是否运算符(字符: char) -> bool {
    matches!(字符,
        '＝' | '＋' | '÷' | '－' | '＞' | '×' | '％' | '＼' | '＜' | '≤' | '≥' | '≠' | '≈')
}

/// 逻辑运算符：`且` `或`（U+4E14 · U+6216）。出处：`help/esdn.chm → zlsc/lang.htm` 的运算符表
/// （逻辑 `且`/`或`），**证据等级 = 文档，语料代码位 0 例**。
///
/// **为什么不并进 [`是否运算符`]**：这两个字符**同时是汉字**（[`是否标识符字符`] 为真），并进去
/// 就出现「一个字符两个归属」，那会让切分器的分支顺序变成隐式语义（本件末的编译期断言正是要禁它）。
/// 所以它们是**独立成词**才算运算符 —— 判据在 [`super::切分::独立逻辑运算符`]，**不靠分支顺序**。
///
/// **为什么不干脆不认**：语料里 `或` 165 次 · `且` 2 次，其中**代码位有命令名 `位或`**
/// （`位或 (#DT_TOP, #DT_LEFT)`）—— 无条件把 `或` 当运算符会把 `位或` 切成
/// `标识符(位) + 运算符(或)`，那是**把已有命令名切坏**，比不认更坏。
pub const fn 是否逻辑运算符(字符: char) -> bool {
    matches!(字符, '且' | '或')
}

/// 常量引用引导：`#`（U+0023）。出处：规格 §二「常量引用 `#名字`」；语料实测 21 种 / 120 次
/// （`#FALSE` `#DEFAULT_CHARSET` `#DT_TOP` `#60` —— 名字**允许纯数字**，缺口 5）。
///
/// 所以 `#` 是**规格点名的引导符**，不算兜底（判定腿 `语料/撞规格.py` 的未归类表里也没有它）。
/// `#` 后没有名字时（语料 **0 例**）落 `标识符`，登记待办 —— 无证据，不许发明第三种行为。
pub const fn 是否常量引用引导(字符: char) -> bool {
    字符 == '#'
}

/// 标识符字符：**汉字 + `[0-9A-Za-z_]` + `%`**。
///
/// 出处：规格 §二 **未给标识符字符集**（缺口 6）；`说明/真文本覆盖.md` §二 实测 853 种字符
/// ＝ 汉字 790 · 数字 10 · 大写 26 · 小写 26 · 下划线 1，**另有 `%` 2 次**（变量名 `%s`：
/// `.局部变量 %s, 文本型` / `%s ＝ json.取通用属性 (“%s”)`）。
/// 故 `%` 按实测点名进来 —— 它是**有实测出处的**，不是兜底。
///
/// 汉字区间取 `U+4E00..=U+9FFF`（与判定腿 `语料/撞规格.py` 同区间）；
/// 扩展 A 区（`U+3400..`）与全角字母（`Ａ-Ｚ`）**语料 0 例** ⇒ 落兜底（登记待办）。
pub const fn 是否标识符字符(字符: char) -> bool {
    matches!(字符,
        '\u{4e00}'..='\u{9fff}' | '0'..='9' | 'A'..='Z' | 'a'..='z' | '_' | '%')
}

/// 兜底字符：**规格 §二 的 11 种里没有任何一类点名能吃的字符**。
///
/// 定义就是「上面 8 条的补集」——这样定义是为了**可判**：改上面任何一条，这里自动跟着改，
/// 不会出现「点名了却仍被兜底」或「没点名却没被兜底」的漂移。
///
/// **为什么必须有兜底**：J2–J5 要求**每个字节都有归属**（`说明/语言面形状.md` §四 4.1），
/// 而 `说明/真文本覆盖.md` 缺口 2 实测：声明行末字段是**不加引号的自由文本**
/// （`wFormatTag，记录着此声音的格式代号` · `-1:准备就绪;1:周期事件;-2:定时器被关闭` ·
/// `如："c:\windows\system32\user32.dll"返回…`），可含全角标点、半角标点、反斜杠、`=` `*` `/` `+`。
/// 形状原先只有 11 种、**没有 `备注文本`**，所以必须有一条兜底规则。**裁决已改口径**
/// （`2026-09-28_华哥的尺子与七条裁决.md` §二「备注位怎么记号化」）：立第 12 种 `备注文本`，兜底**不再**
/// 并进 `标识符`（那是「认不出又不报错」的误类）—— 兜底字符与**含兜底字符的连续段**
/// 一律成 `备注文本`（`切分.rs` 文件头「兜底」）。
///
/// **兜底吃掉的字节如实计数**（`切分测试.rs` 的未归类读数）—— 归类不等于有语义。
pub const fn 是否兜底(字符: char) -> bool {
    !(是否空白(字符)
        || 是否换行(字符)
        || 是否注释引导(字符)
        || 是否常量引用引导(字符)
        || 引号收尾(字符).is_some()
        || 是否界符(字符)
        || 是否运算符(字符)
        || 是否逻辑运算符(字符)
        || 是否标识符字符(字符))
}

// ─────────────────────────────────────────────────────────────────────────────
// 编译期断言：能在编译期算的，一律编译期判死。
// 依据：`项目文档/决策记录/2026-09-26_验证面的边界.md` §3.2。
// ─────────────────────────────────────────────────────────────────────────────

const _: () = {
    // ① 按字符判的集合两两不相交（否则同一个字符有两个归属，切分器的分支顺序
    //    就成了隐式语义 —— 改顺序即改行为，那种漂移编译期就该死）。
    //    **唯一一处有意重叠**是 `且` / `或`（见末两条断言）：它不由分支顺序消解。
    assert!(是否标识符字符('%') && !是否空白('%')); // 实测：`%s` 是变量名（缺口 6）
    assert!(是否界符('.') && !是否标识符字符('.')); // `.` 必须断开，否则 `计数.文本` 连成一枚标识符
    assert!(是否运算符('＝') && !是否界符('＝') && !是否标识符字符('＝'));
    assert!(是否运算符('－') && 是否运算符('＞')); // 缺口 4 实测的两个代码位运算符
    // 文档级 9 个运算符（`esdn/zlsc/lang.htm`）：全接入 ⇒ 一个都不再落兜底（裁决 §二「文档级 9 个运算符接不接进词法」）。
    assert!(是否运算符('×') && 是否运算符('％') && 是否运算符('＼'));
    assert!(是否运算符('＜') && 是否运算符('≤') && 是否运算符('≥'));
    assert!(是否运算符('≠') && 是否运算符('≈'));
    assert!(!是否兜底('×') && !是否兜底('％') && !是否兜底('＼') && !是否兜底('＜'));
    assert!(!是否兜底('≤') && !是否兜底('≥') && !是否兜底('≠') && !是否兜底('≈'));
    // 半角 `%` 是标识符字符（实测 `%s`）、全角 `％` 是运算符（文档级）—— 两个不是一个字符。
    assert!(是否标识符字符('%') && !是否运算符('%'));
    assert!(是否运算符('％') && !是否标识符字符('％'));
    assert!(是否兜底('-') && !是否运算符('-')); // 半角 `-` 规格未点名 ⇒ 兜底（实测 6 次全在备注位）
    assert!(是否兜底('，') && !是否兜底(',')); // 全角 `，`(U+FF0C) 与半角 `,` 不是一个字符
    assert!(是否兜底('。') && 是否兜底('（') && 是否兜底('）')); // 备注位实测最多的三个
    assert!(是否常量引用引导('#') && !是否兜底('#')); // `#` 是规格点名的引导符，不是兜底
    assert!(!是否兜底('"') && !是否兜底('“') && !是否兜底('”')); // 三种定界符都点名了
    // 且 / 或：**有意同时落在两个集合里** —— 它们是汉字（标识符字符），又是文档级逻辑运算符。
    // 重叠**不由分支顺序消解**（那正是上一条断言要禁的隐式语义），而由「独立成词」判据消解
    // （`切分.rs::独立逻辑运算符`：两侧只要有一侧是标识符字符就不算运算符）
    // ⇒ `位或`（语料代码位的命令名）与 `或者` 仍是一枚标识符。
    assert!(是否逻辑运算符('且') && 是否标识符字符('且'));
    assert!(是否逻辑运算符('或') && 是否标识符字符('或'));
    assert!(!是否兜底('且') && !是否兜底('或')); // 汉字本就不在兜底里（点名与否都不影响这条）
};
