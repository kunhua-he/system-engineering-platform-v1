//! 词法 · 切分测试 · 反向 —— 坏输入各有确定结论 · 不 panic · 记号边界不切字符 · 失败面。
//!
//! 依据 `项目文档/设计文档/判据的可信性.md` §五：反向样本证明判据不空转。
//! 本件的反向样本分两类：
//!
//! 1. **输入层**（本件）：空原文 · 只写注释 · 不配对引号 · 坏 UTF-8 边界 —— 逐条断言结论；
//! 2. **不变量层**：J1–J6 的反向样本在 `语言面/形状测试/记号层.rs`（构造口层面，本腿不改）。
//!
//! **本实现的失败面只有一条**：引号不配对 ⇒ `1137`（`切分.rs` 文件头「裁定 2」）。
//! 其余坏输入（空原文 · 只写注释 · 坏 UTF-8 边界不可达 · 兜底字符）都不报错 ——
//! 1108–1117 那 10 条是 `记号流` 的结构性码（构造口防御面），经本函数不可达；
//! 见 [`切分_反向_失败面是记号层十条码加一条切分码`]。

use super::夹具::{切分合法输入, 断言好流};
use crate::词法::切分::切记号;
use crate::语言面::记号种类;

/// **空原文 · 只写注释** —— 这两类**不是**坏输入：形状明写它们合法
/// （`说明/语言面形状.md` §二（二）：空文件也有一枚零宽 `文件结束`；
/// §四 4.1 的 J2 行点了 `记号流_只有注释的文件_区间首尾相接且覆盖全文`）。
/// 所以它们的「正确的码」是**没有码**：`Ok`，且记号表逐枚对得上。
#[test]
fn 切分_反向_空原文与只写注释_合法且逐枚对上() {
    use 记号种类::*;
    assert_eq!(切分合法输入(""), vec![(文件结束, String::new())]);
    assert_eq!(
        切分合法输入("\r\n"),
        vec![(换行, "\r\n".into()), (文件结束, String::new())]
    );
    assert_eq!(
        切分合法输入("\n"),
        vec![(换行, "\n".into()), (文件结束, String::new())]
    );
    assert_eq!(
        切分合法输入("'"),
        vec![(注释, "'".into()), (文件结束, String::new())]
    );
    assert_eq!(
        切分合法输入("' 一\r\n' 二\r\n"),
        vec![
            (注释, "' 一".into()),
            (换行, "\r\n".into()),
            (注释, "' 二".into()),
            (换行, "\r\n".into()),
            (文件结束, String::new()),
        ]
    );
}

/// **不配对引号** —— 无转义机制（实测）、跨行 0 例（无证据）、语料未闭合 0 例 ⇒ 无实测依据。
/// 本实现裁定 **fail-closed**：引号在行内找配对，找不到就报 `1137`（`切分.rs` 文件头「裁定 2」）。
/// **不静默吞**（原判「以行尾为界」已撤）—— 与 `记号流::新建` 对 >4 GiB 的 fail-closed 同一条口径。
#[test]
fn 切分_反向_未闭合引号_失效即拒报1137() {
    use crate::语言面::形状错误;
    let 不配对 = [
        "信息框 (“未闭合)\r\n", // 全角开引号无收尾
        "\"未闭合\r\n计数\r\n", // 半角开引号无收尾（不跨行）
        "”\r\n",               // 落单收尾（按判定腿同口径当引导用 ⇒ 无配对）
        "“",                   // 整份只有一枚开引号
        "\"",                  // 整份只有一枚半角引号
        "”””",                 // 三枚收尾：前两枚配对，第三枚落单
    ];
    for 原文 in 不配对 {
        let 错误 = 切记号(原文).expect_err(&format!("{原文:?}：引号不配对该报失败"));
        assert_eq!(错误, 形状错误::词法层输入非法, "{原文:?}：报的变体不对");
        assert_eq!(crate::形状错误码(&错误), 1137, "{原文:?}：报的码不对");
    }
    // 配对的仍然切得动（判据不误报）：全角、半角、嵌套三种都点一遍。
    for 原文 in ["信息框 (“闭合”)\r\n", "信息框 (\"闭合\")\r\n", ".常量 名, \"“值”\"\r\n"] {
        assert!(切记号(原文).is_ok(), "{原文:?}：配对的引号不该报错");
    }
}

/// **坏 UTF-8 边界** —— 入口是 `&str`，非法 UTF-8 装不进来（类型层消灭，
/// `项目文档/决策记录/2026-09-26_验证面的边界.md` §三）。能判的是它的替身：
/// **记号边界必须落在字符边界上**（任何一枚记号都不许切开一个字符）。
#[test]
fn 切分_反向_记号边界全落在字符边界上() {
    let 样例表 = [
        "“全角字面量” ＋ 汉字\r\n",
        ".成员 格式标签, 短整数型, , , wFormatTag，记录着此声音的格式代号\r\n",
        "😀兜底表情 ＋ “😀”\r\n",
        "－ ＞ ＝ ＋ ÷\r\n",
    ];
    for 原文 in 样例表 {
        let 输出流 = 切记号(原文).expect("切分");
        for (序号, 记号) in 输出流.记号表.iter().enumerate() {
            assert!(
                原文.is_char_boundary(记号.区间起点 as usize) && 原文.is_char_boundary(记号.止 as usize),
                "{原文:?} 第 {序号} 枚记号的区间切开了字符：{}..{}",
                记号.区间起点,
                记号.止
            );
        }
        assert_eq!(输出流.还原原文(), 原文.as_bytes());
    }
}

/// **坏输入不 panic** —— 一组敌对输入（引号都已配对），每一份都必须切得动、六条全过、
/// 逐字节还原。引号不配对那一类由 [`切分_反向_未闭合引号_失效即拒报1137`] 单独钉住。
#[test]
fn 切分_反向_坏输入不崩溃() {
    let 敌对 = [
        "'",                                                                      // 只有注释引导
        "'注释无换行",                   // 注释到文件尾、无行尾
        "#",                             // `#` 后面没有名字（裁定 4）
        "# % ，",                        // 常量引用后面跟兜底
        ".",                             // 行首点后面没有名字
        "..计数",                        // 双点
        "计数-1",                        // 兜底 `-` 落 备注文本（裁决 §二「备注位怎么记号化」）
        "0x1F",                          // 十六进制（裁定 3：认，`0x` + 至少一位十六进制数字）
        "0x",                            // `0x` 后无十六进制数字 ⇒ 退回 `0` + 标识符（裁定 3）
        "1e5",                           // 科学计数（裁定 3：不认）
        "，。：；、*／【】—\\=！？‘＂", // 兜底字符（备注位实测的那批；`×` 已点名成运算符，故移出）
        "位或 (1)",                      // `或` 两侧有标识符字符 ⇒ 不作运算符，`位或` 仍是一枚标识符
        "😀",                            // 4 字节字符
        "' 注释里有 \" 引号",            // 注释吞掉后面的引号
        "“字面量里有 ' 注释引导”",       // 字面量吞掉注释引导
        ".参数 事件消息值, 整数型, , -1:准备就绪;1:周期事件;-2:定时器被关闭\r\n", // 实测原样一行
        ".DLL命令 删除路径根目录_, 整数型, \"shlwapi.dll\", \"PathSkipRootA\", , 如：\"c:\\windows\\system32\\user32.dll\"返回\"windows\\system32\\user32.dll\"\r\n", // 实测原样一行
    ];
    for 原文 in 敌对 {
        断言好流(原文);
    }
}

/// **1101 的失败面** —— 分两族，本测试把两族都钉住：
///
/// 1. **记号层 10 条（1108–1117）**：`记号流::新建` 的**结构性**码，是构造口的防御面，
///    **经 [`切记号`] 不可达**（切分器顺序走完全文 ⇒ 六条不变量天然成立）；
/// 2. **切分码 `1137`（词法层输入非法）**：本函数**唯一**报得出的失败 —— 引号不配对
///    （上一枚测试逐条断言）。`1135`（参数槽不符）由执行函数写，不经本函数。
///
/// **本测试不假装 1108–1117 可达**：它断言那 10 条码的号与顺序，并断言本函数对
/// 空原文 / 只写注释 / 兜底字符都不报错。
#[test]
fn 切分_反向_失败面是记号层十条码加一条切分码() {
    use crate::语言面::形状错误 as 形状;
    let 记号层错形表 = [
        形状::记号表为空,
        形状::记号起点不为零 { 区间起点: 1 },
        形状::记号区间越界 {
            序号: 0,
            止: 1,
            全文长: 0,
        },
        形状::记号区间倒置 {
            序号: 0,
            区间起点: 1,
            止: 0,
        },
        形状::记号有缝隙 {
            序号: 1,
            前止: 0,
            后起: 1,
        },
        形状::记号有重叠 {
            序号: 1,
            前止: 1,
            后起: 0,
        },
        形状::文件结束不在末位 { 序号: 0 },
        形状::末记号非文件结束 {
            序号: 0,
            种类: 记号种类::关键字,
        },
        形状::文件结束非零宽 { 区间起点: 0, 止: 1 },
        形状::记号流未覆盖全文 {
            覆盖到: 0,
            全文长: 1,
        },
    ];
    // 记号层 10 条 → 1108..=1117，一条不差。
    for (序号, 错误) in 记号层错形表.iter().enumerate() {
        assert_eq!(
            crate::形状错误码(错误),
            1108 + 序号 as u32,
            "第 {序号} 条的码不对"
        );
    }
    // 本函数对这几类坏输入**都不报错**（它们不是「切不出记号」，只是切得难看）。
    for 原文 in ["", "' 只写注释\r\n", "计数", "😀 ，。"] {
        assert!(切记号(原文).is_ok(), "{原文:?} 该成功");
    }
    // 本函数报得出的失败**只有** 1137（引号不配对）。
    assert_eq!(
        crate::形状错误码(&切记号("\"").expect_err("引号不配对该报失败")),
        1137
    );
}
