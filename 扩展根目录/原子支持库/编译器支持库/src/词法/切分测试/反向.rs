//! 词法 · 切分测试 · 反向 —— 坏输入各有确定结论 · 不 panic · 记号边界不切字符 · 失败面。
//!
//! 依据 `项目文档/设计文档/判据的可信性.md` §五：反向样本证明判据不空转。
//! 本件的反向样本分两类：
//!
//! 1. **输入层**（本件）：空原文 · 只写注释 · 不配对引号 · 坏 UTF-8 边界 —— 逐条断言结论；
//! 2. **不变量层**：J1–J6 的反向样本在 `语言面/形状测试/记号层.rs`（构造口层面，本腿不改）。
//!
//! **本实现的失败面是空的**（总函数）：四类坏输入都不报错。这不是「忘了报错」，是
//! 1101 声明的可抛错误码（1108–1117）**全是 `记号流` 的结构性码**，没有任何一条能吃
//! 「词法层输入非法」——见 [`切分_反向_失败面恰是记号层十条码_且本函数不报错`]。

use super::夹具::{切对, 断言好流};
use crate::词法::切分::切记号;
use crate::语言面::记号种类;

/// **空原文 · 只写注释** —— 这两类**不是**坏输入：形状明写它们合法
/// （`说明/语言面形状.md` §二（二）：空文件也有一枚零宽 `文件结束`；
/// §四 4.1 的 J2 行点了 `记号流_只有注释的文件_区间首尾相接且覆盖全文`）。
/// 所以它们的「正确的码」是**没有码**：`Ok`，且记号表逐枚对得上。
#[test]
fn 切分_反向_空原文与只写注释_合法且逐枚对上() {
    use 记号种类::*;
    assert_eq!(切对(""), vec![(文件结束, String::new())]);
    assert_eq!(
        切对("\r\n"),
        vec![(换行, "\r\n".into()), (文件结束, String::new())]
    );
    assert_eq!(
        切对("\n"),
        vec![(换行, "\n".into()), (文件结束, String::new())]
    );
    assert_eq!(
        切对("'"),
        vec![(注释, "'".into()), (文件结束, String::new())]
    );
    assert_eq!(
        切对("' 一\r\n' 二\r\n"),
        vec![
            (注释, "' 一".into()),
            (换行, "\r\n".into()),
            (注释, "' 二".into()),
            (换行, "\r\n".into()),
            (文件结束, String::new()),
        ]
    );
}

/// **不配对引号** —— 无转义机制（实测）、跨行 0 例（无证据），故本实现裁定
/// **未闭合引号吃到行尾**（`切分.rs` 文件头裁定 2）：不丢字节、不跨行、不报错。
/// 报不出码的理由见 [`切分_反向_失败面恰是记号层十条码_且本函数不报错`]。
#[test]
fn 切分_反向_未闭合引号_以行尾为界() {
    use 记号种类::*;
    assert_eq!(
        切对("信息框 (“未闭合)\r\n"),
        vec![
            (标识符, "信息框".into()),
            (空白, " ".into()),
            (界符, "(".into()),
            (文本字面量, "“未闭合)".into()), // 找 `”` 找不到 ⇒ 以行尾为界
            (换行, "\r\n".into()),
            (文件结束, String::new()),
        ]
    );
    // 下一行不受影响（不跨行）。
    assert_eq!(
        切对("\"未闭合\r\n计数\r\n"),
        vec![
            (文本字面量, "\"未闭合".into()),
            (换行, "\r\n".into()),
            (标识符, "计数".into()),
            (换行, "\r\n".into()),
            (文件结束, String::new()),
        ]
    );
    // 收尾字符落单：按判定腿同口径当引导用（`撞规格.py` 的 `close` 表）。
    assert_eq!(
        切对("”\r\n"),
        vec![
            (文本字面量, "”".into()),
            (换行, "\r\n".into()),
            (文件结束, String::new()),
        ]
    );
}

/// **坏 UTF-8 边界** —— 入口是 `&str`，非法 UTF-8 装不进来（类型层消灭，
/// `项目文档/决策记录/2026-09-26_验证面的边界.md` §三）。能判的是它的替身：
/// **记号边界必须落在字符边界上**（任何一枚记号都不许切开一个字符）。
#[test]
fn 切分_反向_记号边界全落在字符边界上() {
    let 例 = [
        "“全角字面量” ＋ 汉字\r\n",
        ".成员 格式标签, 短整数型, , , wFormatTag，记录着此声音的格式代号\r\n",
        "😀兜底表情 ＋ “😀”\r\n",
        "－ ＞ ＝ ＋ ÷\r\n",
        "“未闭合的全角引号\r\n",
    ];
    for 原文 in 例 {
        let 流 = 切记号(原文).expect("总函数");
        for (序, t) in 流.记号表.iter().enumerate() {
            assert!(
                原文.is_char_boundary(t.起 as usize) && 原文.is_char_boundary(t.止 as usize),
                "{原文:?} 第 {序} 枚记号的区间切开了字符：{}..{}",
                t.起,
                t.止
            );
        }
        assert_eq!(流.还原(), 原文.as_bytes());
    }
}

/// **总函数：不 panic** —— 一组敌对输入，每一份都必须切得动、六条全过、逐字节还原。
#[test]
fn 切分_反向_坏输入不panic_总函数() {
    let 敌对 = [
        "'",                                                                      // 只有注释引导
        "'注释无换行",                   // 注释到文件尾、无行尾
        "\"",                            // 只有半角引号
        "“",                             // 只有全角引号
        "”””",                           // 落单收尾
        "#",                             // `#` 后面没有名字（裁定 4）
        "# % ，",                        // 常量引用后面跟兜底
        ".",                             // 行首点后面没有名字
        "..计数",                        // 双点
        "计数-1",                        // 兜底 `-` 续前
        "0x1F",                          // 十六进制（裁定 3：不认）
        "1e5",                           // 科学计数（裁定 3：不认）
        "，。：；、*／【】—\\=×！？‘＂", // 全部兜底字符（备注位实测的那批）
        "😀",                            // 4 字节字符
        "' 注释里有 \" 引号",            // 注释吞掉后面的引号
        "“字面量里有 ' 注释引导”",       // 字面量吞掉注释引导
        ".参数 事件消息值, 整数型, , -1:准备就绪;1:周期事件;-2:定时器被关闭\r\n", // 实测原样一行
        ".DLL命令 删除路径根目录_, 整数型, \"shlwapi.dll\", \"PathSkipRootA\", , 如：\"c:\\windows\\system32\\user32.dll\"返回\"windows\\system32\\user32.dll\"\r\n", // 实测原样一行
    ];
    for 原文 in 敌对 {
        断言好流(原文);
    }
}

/// **1101 的失败面** —— 声明的可抛错误码是记号层 10 条（1108–1117），全是 `记号流` 的
/// **结构性**码；**没有任何一条能吃「词法层输入非法」**。本测试把这个事实钉住：
/// 四类坏输入全不报错（上一枚测试逐条断言），本函数只可能经构造口报那 10 条。
///
/// 这是一处**已登记的缺口**（不是本实现的选择）：词法层没有自己的错误码。
#[test]
fn 切分_反向_失败面恰是记号层十条码_且本函数不报错() {
    use crate::语言面::形状错误 as 形状;
    let 十条 = [
        形状::记号表为空,
        形状::记号起点不为零 { 起: 1 },
        形状::记号区间越界 {
            第几个: 0,
            止: 1,
            全文长: 0,
        },
        形状::记号区间倒置 {
            第几个: 0,
            起: 1,
            止: 0,
        },
        形状::记号有缝隙 {
            第几个: 1,
            前止: 0,
            后起: 1,
        },
        形状::记号有重叠 {
            第几个: 1,
            前止: 1,
            后起: 0,
        },
        形状::文件结束不在末位 { 第几个: 0 },
        形状::末记号非文件结束 {
            第几个: 0,
            种类: 记号种类::关键字,
        },
        形状::文件结束非零宽 { 起: 0, 止: 1 },
        形状::记号流未覆盖全文 {
            覆盖到: 0,
            全文长: 1,
        },
    ];
    // 记号层 10 条 → 1108..=1117，一条不差（这就是 1101 声明的可抛错误码全集）。
    for (序, 错) in 十条.iter().enumerate() {
        assert_eq!(
            crate::形状错误码(错),
            1108 + 序 as u32,
            "第 {序} 条的码不对"
        );
    }
    // 本函数对这四类坏输入**都不报错**（报不出码 = 没有码可用，见函数注释）。
    for 原文 in ["", "' 只写注释\r\n", "信息框 (“不配对)\r\n", "计数"] {
        assert!(切记号(原文).is_ok(), "{原文:?} 该成功");
    }
}
