//! 词法 · 切分测试 · 正向 · 手写小样例 —— 12 种记号逐种出现的**已知答案**表。
//!
//! 依据 `项目文档/设计文档/判据的可信性.md` §三 5：判据必须拿一份**已知答案**的输入自检。

use super::super::夹具::{切分合法输入, 期望};
use crate::语言面::记号种类;

/// **自检**：12 种记号**逐种**在下面各出现至少一次，且逐枚断言种类与区间文本。
///
/// 每一例都是「已知答案的输入」——不是拿实现去比实现，是拿手写的期望去比。
#[test]
fn 切分_手写小样例_逐枚记号对上() {
    use 记号种类::*;
    let 样例表: &[(&str, &[(记号种类, &str)])] = &[
        // 空原文：形状明写合法，只有一枚零宽 `文件结束`（`说明/语言面形状.md` §二（二））。
        ("", &[]),
        // 关键字（带点）· 空白 · 数值 · 换行：CRLF 与 LF 都认（规格 §二）。
        (
            ".版本 2\r\n",
            &[
                (关键字, ".版本"),
                (空白记号, " "),
                (数值字面量, "2"),
                (换行记号, "\r\n"),
            ],
        ),
        (
            ".版本 2\n",
            &[
                (关键字, ".版本"),
                (空白记号, " "),
                (数值字面量, "2"),
                (换行记号, "\n"),
            ],
        ),
        // 缩进是「位于行首的空白」，不是独立种类。
        (
            "    .参数 计数, 整数型\r\n",
            &[
                (空白记号, "    "),
                (关键字, ".参数"),
                (空白记号, " "),
                (标识符, "计数"),
                (界符, ","),
                (空白记号, " "),
                (标识符, "整数型"),
                (换行记号, "\r\n"),
            ],
        ),
        // 不带点关键字 `返回` · 注释不含行尾换行（换行恒由 `换行` 认领）。
        (
            "返回 (0)  ' 行尾\r\n",
            &[
                (关键字, "返回"),
                (空白记号, " "),
                (界符, "("),
                (数值字面量, "0"),
                (界符, ")"),
                (空白记号, "  "),
                (注释记号, "' 行尾"),
                (换行记号, "\r\n"),
            ],
        ),
        ("' 整行注释\r\n", &[(注释记号, "' 整行注释"), (换行记号, "\r\n")]),
        // 行内 `.` 是成员访问界符；`真` 不在行首 ⇒ 标识符。
        (
            "监听服务器.置SSL抓包 (真)\r\n",
            &[
                (标识符, "监听服务器"),
                (界符, "."),
                (标识符, "置SSL抓包"),
                (空白记号, " "),
                (界符, "("),
                (标识符, "真"),
                (界符, ")"),
                (换行记号, "\r\n"),
            ],
        ),
        // 空实参：逗号之间的零宽位次在记号层不许被吃掉（两个逗号 = 一个空位）。
        (
            "信息框 (“你好”, 0, , )\r\n",
            &[
                (标识符, "信息框"),
                (空白记号, " "),
                (界符, "("),
                (文本字面量, "“你好”"),
                (界符, ","),
                (空白记号, " "),
                (数值字面量, "0"),
                (界符, ","),
                (空白记号, " "),
                (界符, ","),
                (空白记号, " "),
                (界符, ")"),
                (换行记号, "\r\n"),
            ],
        ),
        // 常量引用（名字允许纯数字，缺口 5）· 运算符全角 · 数值。
        (
            "#FALSE ＝ #60 ＋ 1 ÷ 2\r\n",
            &[
                (常量引用, "#FALSE"),
                (空白记号, " "),
                (运算符, "＝"),
                (空白记号, " "),
                (常量引用, "#60"),
                (空白记号, " "),
                (运算符, "＋"),
                (空白记号, " "),
                (数值字面量, "1"),
                (空白记号, " "),
                (运算符, "÷"),
                (空白记号, " "),
                (数值字面量, "2"),
                (换行记号, "\r\n"),
            ],
        ),
        // 半角里套全角（语料实测的唯一嵌套形态）：一个种类，定界符从区间首字节读。
        (
            ".常量 名, \"“值”\"\r\n",
            &[
                (关键字, ".常量"),
                (空白记号, " "),
                (标识符, "名"),
                (界符, ","),
                (空白记号, " "),
                (文本字面量, "\"“值”\""),
                (换行记号, "\r\n"),
            ],
        ),
        // `置入代码` 是实测的两个不带点关键字之一；`{` `}` 是实测的界符。
        (
            "置入代码 ({ 139, 69 })\r\n",
            &[
                (关键字, "置入代码"),
                (空白记号, " "),
                (界符, "("),
                (界符, "{"),
                (空白记号, " "),
                (数值字面量, "139"),
                (界符, ","),
                (空白记号, " "),
                (数值字面量, "69"),
                (空白记号, " "),
                (界符, "}"),
                (界符, ")"),
                (换行记号, "\r\n"),
            ],
        ),
        // 数值：负号只在操作数位起数值（`-1` 是一枚数值）；`计数-1` 里半角 `-` 是兜底字符，
        // 含兜底字符的连续段**整段**是一枚 `备注文本`（裁决 §二「备注位怎么记号化」）——
        // 不再是一枚 `标识符`。
        ("-1\r\n", &[(数值字面量, "-1"), (换行记号, "\r\n")]),
        ("3.51\r\n", &[(数值字面量, "3.51"), (换行记号, "\r\n")]),
        (
            "计数-1\r\n",
            &[(备注文本, "计数-1"), (换行记号, "\r\n")],
        ),
        // 十六进制字面量（裁决 §二「十六进制字面量」）：`0x`/`0X` + 至少一位十六进制数字
        // = **一枚**数值。不认则 `0x1F` 会切成 `数值字面量(0) + 标识符(x1F)` —— 认不出又不报错。
        ("0x1F\r\n", &[(数值字面量, "0x1F"), (换行记号, "\r\n")]),
        ("0X2a\r\n", &[(数值字面量, "0X2a"), (换行记号, "\r\n")]),
        // `0x` 后无十六进制数字 ⇒ **不是字面量**：退回「`0` + 标识符」（裁定 3）。
        (
            "0x\r\n",
            &[(数值字面量, "0"), (标识符, "x"), (换行记号, "\r\n")],
        ),
        // 文档级 9 个运算符（`esdn/zlsc/lang.htm`）已接入（裁决 §二「文档级 9 个运算符接不接进词法」）：
        // 全角、不再落兜底。
        (
            "1 × 2 ％ 3 ＼ 4 ＜ 5 ≤ 6 ≥ 7 ≠ 8 ≈ 9\r\n",
            &[
                (数值字面量, "1"),
                (空白记号, " "),
                (运算符, "×"),
                (空白记号, " "),
                (数值字面量, "2"),
                (空白记号, " "),
                (运算符, "％"),
                (空白记号, " "),
                (数值字面量, "3"),
                (空白记号, " "),
                (运算符, "＼"),
                (空白记号, " "),
                (数值字面量, "4"),
                (空白记号, " "),
                (运算符, "＜"),
                (空白记号, " "),
                (数值字面量, "5"),
                (空白记号, " "),
                (运算符, "≤"),
                (空白记号, " "),
                (数值字面量, "6"),
                (空白记号, " "),
                (运算符, "≥"),
                (空白记号, " "),
                (数值字面量, "7"),
                (空白记号, " "),
                (运算符, "≠"),
                (空白记号, " "),
                (数值字面量, "8"),
                (空白记号, " "),
                (运算符, "≈"),
                (空白记号, " "),
                (数值字面量, "9"),
                (换行记号, "\r\n"),
            ],
        ),
        // 逻辑 `且` `或`（同一条裁决）：**只在独立成词时**是运算符 —— 两侧只要有标识符字符
        // 就仍属名字（`位或` 是语料代码位实测的命令名，切坏它比不认更坏）。
        (
            "真值 且 假值\r\n",
            &[
                (标识符, "真值"),
                (空白记号, " "),
                (运算符, "且"),
                (空白记号, " "),
                (标识符, "假值"),
                (换行记号, "\r\n"),
            ],
        ),
        (
            "位或 (1)\r\n",
            &[
                (标识符, "位或"),
                (空白记号, " "),
                (界符, "("),
                (数值字面量, "1"),
                (界符, ")"),
                (换行记号, "\r\n"),
            ],
        ),
        // 备注文本（第 12 种，裁决 §二「备注位怎么记号化」）：含兜底字符的连续段**整段**是
        // 一枚 `备注文本`，不再冒充名字。`wFormatTag，记录着此声音的格式代号` 是实测原样的末字段。
        (
            "wFormatTag，记录着此声音的格式代号\r\n",
            &[
                (备注文本, "wFormatTag，记录着此声音的格式代号"),
                (换行记号, "\r\n"),
            ],
        ),
        // `%` 是实测的标识符字符（缺口 6：变量名 `%s`）。
        (
            ".局部变量 %s, 文本型\r\n",
            &[
                (关键字, ".局部变量"),
                (空白记号, " "),
                (标识符, "%s"),
                (界符, ","),
                (空白记号, " "),
                (标识符, "文本型"),
                (换行记号, "\r\n"),
            ],
        ),
        // 缺口 4 实测的两个代码位运算符：`－`（U+FF0D）与 `＞`（U+FF1E）。
        (
            "_启动窗口.高度 － 标签EX2.高度\r\n",
            &[
                (标识符, "_启动窗口"),
                (界符, "."),
                (标识符, "高度"),
                (空白记号, " "),
                (运算符, "－"),
                (空白记号, " "),
                (标识符, "标签EX2"),
                (界符, "."),
                (标识符, "高度"),
                (换行记号, "\r\n"),
            ],
        ),
    ];

    // 12 种记号**逐种**都在这组样例里出现过（漏一种就是自检没覆盖面）。
    let 见过: std::collections::BTreeSet<u8> = 样例表
        .iter()
        .flat_map(|(_, 片段)| 片段.iter().map(|(记号类别, _)| 记号类别.取号值()))
        .chain(std::iter::once(记号种类::文件结束.取号值()))
        .collect();
    assert_eq!(
        见过.len(),
        12,
        "自检样例该覆盖 12 种记号，实得 {} 种",
        见过.len()
    );

    for (原文, 片段) in 样例表 {
        assert_eq!(切分合法输入(原文), 期望(片段), "原文 {原文:?}");
    }
}
