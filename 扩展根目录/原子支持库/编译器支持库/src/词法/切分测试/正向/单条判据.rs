/// 注释**不含行尾换行** ⇒ 整行注释与行尾注释同构（`说明/语言面形状.md` §二（一））。
#[test]
fn 切分_注释不吞行尾换行() {
    use 记号种类::*;
    for 原文 in [
        "' 整行注释\r\n",
        "计数  ' 行尾注释\r\n",
        "' 整行注释\n",
        "计数  ' 行尾注释",
    ] {
        let 输出流 = 切记号(原文).expect("切分");
        for 记号 in &输出流.记号表 {
            if 记号.记号类别 == 注释记号 {
                let 片段 = &输出流.原文[记号.区间起点 as usize..记号.区间终点 as usize];
                assert!(
                    !片段.contains(&b'\r') && !片段.contains(&b'\n'),
                    "{原文:?} 的注释记号吞了行尾换行"
                );
            }
        }
    }
    // 行尾注释后面必须紧跟一枚 `换行`（若原文有行尾）。
    let 输出流 = 切记号("计数  ' 行尾注释\r\n").expect("切分");
    let 注释位置 = 输出流
        .记号表
        .iter()
        .position(|记号| 记号.记号类别 == 注释记号)
        .expect("有注释");
    assert_eq!(输出流.记号表[注释位置 + 1].记号类别, 换行记号);
}

/// 注释**到行尾不含换行**（裁决 `2026-09-28_华哥的尺子与七条裁决.md` §二「注释吞不吞行尾 CRLF」）：
/// CRLF 的 `\r` 属行尾，**随注释之后由 `换行` 记号一并认领** —— 注释记号里既没有 `\r`
/// 也没有 `\n`，CRLF 行尾是一枚 2 字节的 `换行`。字节层两种词法产同样字节（不可判）
/// ⇒ 这条设计选择只能靠**样本**钉住。
#[test]
fn 切分_注释到行尾不含任何行尾字节_CRLF归换行记号() {
    use 记号种类::*;
    assert_eq!(
        切分合法输入("' 注释\r\n"),
        期望(&[(注释记号, "' 注释"), (换行记号, "\r\n")]),
        "CRLF：注释不含 `\\r`，行尾是一枚 2 字节 `换行`"
    );
    assert_eq!(
        切分合法输入("' 注释\n"),
        期望(&[(注释记号, "' 注释"), (换行记号, "\n")]),
        "LF：注释不含 `\\n`，行尾是一枚 1 字节 `换行`"
    );
    // 逐枚查：任何注释记号的区间里都不许出现 `\r` 或 `\n`（含行尾注释与无行尾的末行）。
    for 原文 in ["' 注释\r\n", "计数  ' 行尾注释\r\n", "' 注释"] {
        let 输出流 = 切记号(原文).expect("切分");
        for 记号 in &输出流.记号表 {
            if 记号.记号类别 == 注释记号 {
                let 片段 = &输出流.原文[记号.区间起点 as usize..记号.区间终点 as usize];
                assert!(
                    !片段.contains(&b'\r') && !片段.contains(&b'\n'),
                    "{原文:?} 的注释吞了行尾字节"
                );
            }
        }
    }
}

/// `.` 一号两用：**行首**引导关键字（点含在区间内），**行内**是成员访问界符。
#[test]
fn 切分_点一号两用() {
    use 记号种类::*;
    let 输出流 = 切记号(".参数 计数.文本\r\n").expect("切分");
    assert_eq!(输出流.记号表[0].记号类别, 关键字);
    assert_eq!(输出流.记号原文切片(0), Some(&b".\xe5\x8f\x82\xe6\x95\xb0"[..])); // “.参数”，点含在内
    let 界符个数 = 输出流.记号表.iter().filter(|记号| 记号.记号类别 == 界符).count();
    assert_eq!(界符个数, 1, "行内的那一个 `.` 该是界符");
}

/// 空实参的**位次**在记号层就分得开：`(被加数, , 加数)` 与 `(被加数, 加数)` 的逗号枚数不同。
/// （零宽 `空实参` 是语法树层的事；记号层的责任是**不把空位吃掉**。）
#[test]
fn 切分_空实参位次在记号层可数() {
    use 记号种类::*;
    let 数逗号 = |原文: &str| {
        let 输出流 = 切记号(原文).expect("切分");
        (0..输出流.记号表.len())
            .filter(|记号位次| 输出流.记号表[*记号位次].记号类别 == 界符)
            .filter_map(|记号位次| 输出流.记号原文切片(记号位次))
            .filter(|片段| *片段 == b",")
            .count()
    };
    assert_eq!(
        数逗号("求和 (被加数, , 加数)\r\n"),
        2,
        "一个空位 ⇒ 两个逗号"
    );
    assert_eq!(数逗号("求和 (被加数, 加数)\r\n"), 1);
    // 实测原样一行（一条调用里 13 个空位）：判据是「记号层不许吃掉任何一枚逗号」。
    let 实测行 = "D3D_HookCall (pDevice, , , , , , , , , , , , , , )\r\n";
    assert_eq!(数逗号(实测行), 实测行.matches(',').count());
    assert_eq!(数逗号(实测行), 14, "1 个实参 + 13 个空位 ⇒ 14 枚逗号");
}

/// 未分类字符（兜底）**只可能落在具名容器里**：`备注文本` · `注释` · `文本字面量` · `数值字面量`。
/// 这条同时证明「兜底真的有了归属」（不是被丢弃、也不是另造了别的东西）；
/// `标识符` **不在列** —— 含兜底字符的连续段一律是 `备注文本`（裁决 §二「备注位怎么记号化」）。
///
/// `数值字面量` 为什么在列：半角 `-` 规格未点名（兜底），而 `计数, -1` 里的它按判定腿
/// `语料/撞规格.py` 同一条件成为负号 —— 于是它落在一枚 `数值字面量` 里。**只有它一个字符**
/// 有这情形，且只在备注位出现（实测 `-` 96 次全在声明/备注位）。
#[test]
fn 切分_兜底字符只落在具名容器里() {
    let 原文样例 = [
        ".成员 格式标签, 短整数型, , , wFormatTag，记录着此声音的格式代号\r\n",
        ".参数 事件消息值, 整数型, , -1:准备就绪;1:周期事件;-2:定时器被关闭\r\n",
        "' 注释里也有兜底 ，。：；\r\n",
        "信息框 (“字面量里也有兜底 ，。”)\r\n",
        "#FALSE ＋ ，\r\n",
    ];
    for 原文 in 原文样例 {
        let 输出流 = 切记号(原文).expect("切分");
        for (字节位置, 单字符) in 原文.char_indices() {
            if !是否兜底(单字符) {
                continue;
            }
            let 字节位置 = 字节位置 as u32;
            let 落处 = 输出流.记号表.iter().find(|记号| 记号.区间起点 <= 字节位置 && 字节位置 < 记号.区间终点);
            let 落处 = 落处.unwrap_or_else(|| panic!("{原文:?} 位置 {字节位置} 无归属"));
            assert!(
                matches!(
                    落处.记号类别,
                    记号种类::备注文本
                        | 记号种类::注释记号
                        | 记号种类::文本字面量
                        | 记号种类::数值字面量
                ),
                "{原文:?} 位置 {字节位置} 的 {单字符:?} 落在 {:?} 里",
                落处.记号类别
            );
        }
    }
}

