//! 词法 · 切分测试 · 夹具 —— 四件共用的四样东西：切分合法输入 · 期望 · 判切分六条不变量 · 断言好流。
//!
//! 夹具只有一处实现（同一件事不许两套），四件都从这里取。
//! 语料读取（同一批 53 份真文本）已收进 `crate::测试夹具`。

use crate::词法::切分::切记号;
use crate::语言面::{记号流, 记号种类};

/// 切一份原文，返回**逐枚** `(种类, 区间切片文本)`。用来与手写的期望逐枚对上。
///
/// 只喂**合法**输入（引号配对）：引号不配对会报 1137，那是
/// `切分测试/反向.rs::切分_反向_未闭合引号_失效即拒报1137` 的活。
pub fn 切分合法输入(原文: &str) -> Vec<(记号种类, String)> {
    let 输出流 = 切记号(原文).expect("切分合法输入只喂合法输入（引号配对）");
    (0..输出流.记号表.len())
        .map(|位次| {
            let 片段 = 输出流.切片(位次).expect("区间必在界内（J6）");
            (输出流.记号表[位次].种类, String::from_utf8_lossy(片段).into_owned())
        })
        .collect()
}

/// 期望的写法：逐枚列 `(种类, 区间文本)`，**末尾那枚零宽 `文件结束` 不必写**（本函数自动补）。
///
/// 每一份合法记号流都以它收尾（J1），逐例手写它是噪声 —— 但**它仍然被断言**（补出来的那枚
/// 也要与实现产出的对上），所以不是放宽判据。
pub fn 期望(片段: &[(记号种类, &str)]) -> Vec<(记号种类, String)> {
    let mut 输出缓冲: Vec<(记号种类, String)> =
        片段.iter().map(|(种类, 文本)| (*种类, (*文本).to_string())).collect();
    输出缓冲.push((记号种类::文件结束, String::new()));
    输出缓冲
}

/// 逐条判 J1–J6。返回六元组（下标 0..5 = J1..J6），**逐条独立判**，不靠构造口代劳。
pub fn 判切分六条不变量(输出流: &记号流) -> [bool; 6] {
    let 长度 = 输出流.全文长();
    let 项表 = &输出流.记号表;
    if 项表.is_empty() {
        return [false; 6];
    }
    let 尾部 = 项表.len() - 1;
    [
        // J1：末位有且仅有一枚零宽 `文件结束`，锚在 [全文长, 全文长)
        项表[尾部].种类 == 记号种类::文件结束
            && 项表[尾部].起 == 长度
            && 项表[尾部].止 == 长度
            && 项表[..尾部].iter().all(|记号| 记号.种类 != 记号种类::文件结束),
        // J2：首记号的起 == 0
        项表[0].起 == 0,
        // J3：无缝隙
        项表.windows(2).all(|相邻两枚| 相邻两枚[0].止 == 相邻两枚[1].起),
        // J4：无重叠
        项表.windows(2).all(|相邻两枚| 相邻两枚[0].止 <= 相邻两枚[1].起),
        // J5：末记号的止 == 全文长
        项表[尾部].止 == 长度,
        // J6：每枚 起 <= 止 <= 全文长
        项表.iter().all(|记号| 记号.起 <= 记号.止 && 记号.止 <= 长度),
    ]
}

/// 断言一份原文切出来的流是好流：六条全过 + 逐字节还原。
pub fn 断言好流(原文: &str) {
    let 输出流 = 切记号(原文).unwrap_or_else(|错误| panic!("{原文:?} 该切得动，实得 {错误:?}"));
    assert_eq!(判切分六条不变量(&输出流), [true; 6], "{原文:?} 有不变量没过");
    assert_eq!(输出流.还原原文(), 原文.as_bytes(), "{原文:?} 还原不等于原文");
}
