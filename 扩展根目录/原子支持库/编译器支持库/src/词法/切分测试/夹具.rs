//! 词法 · 切分测试 · 夹具 —— 四件共用的四样东西：切对 · 期望 · 判六条 · 语料读取。
//!
//! 夹具只有一处实现（同一件事不许两套），四件都从这里取。

use crate::词法::切分::切记号;
use crate::语言面::{记号流, 记号种类};
use std::path::{Path, PathBuf};

/// 切一份原文，返回**逐枚** `(种类, 区间切片文本)`。用来与手写的期望逐枚对上。
///
/// 只喂**合法**输入（引号配对）：引号不配对会报 1137，那是
/// `切分测试/反向.rs::切分_反向_未闭合引号_失效即拒报1137` 的活。
pub fn 切对(原文: &str) -> Vec<(记号种类, String)> {
    let 流 = 切记号(原文).expect("切对只喂合法输入（引号配对）");
    (0..流.记号表.len())
        .map(|位次| {
            let 片 = 流.切片(位次).expect("区间必在界内（J6）");
            (流.记号表[位次].种类, String::from_utf8_lossy(片).into_owned())
        })
        .collect()
}

/// 期望的写法：逐枚列 `(种类, 区间文本)`，**末尾那枚零宽 `文件结束` 不必写**（本函数自动补）。
///
/// 每一份合法记号流都以它收尾（J1），逐例手写它是噪声 —— 但**它仍然被断言**（补出来的那枚
/// 也要与实现产出的对上），所以不是放宽判据。
pub fn 期望(片段: &[(记号种类, &str)]) -> Vec<(记号种类, String)> {
    let mut 出: Vec<(记号种类, String)> =
        片段.iter().map(|(种, 文)| (*种, (*文).to_string())).collect();
    出.push((记号种类::文件结束, String::new()));
    出
}

/// 逐条判 J1–J6。返回六元组（下标 0..5 = J1..J6），**逐条独立判**，不靠构造口代劳。
pub fn 判六条(输出流: &记号流) -> [bool; 6] {
    let 长 = 输出流.全文长();
    let 表 = &输出流.记号表;
    if 表.is_empty() {
        return [false; 6];
    }
    let 末 = 表.len() - 1;
    [
        // J1：末位有且仅有一枚零宽 `文件结束`，锚在 [全文长, 全文长)
        表[末].种类 == 记号种类::文件结束
            && 表[末].起 == 长
            && 表[末].止 == 长
            && 表[..末].iter().all(|记号| 记号.种类 != 记号种类::文件结束),
        // J2：首记号的起 == 0
        表[0].起 == 0,
        // J3：无缝隙
        表.windows(2).all(|两| 两[0].止 == 两[1].起),
        // J4：无重叠
        表.windows(2).all(|两| 两[0].止 <= 两[1].起),
        // J5：末记号的止 == 全文长
        表[末].止 == 长,
        // J6：每枚 起 <= 止 <= 全文长
        表.iter().all(|记号| 记号.起 <= 记号.止 && 记号.止 <= 长),
    ]
}

/// 断言一份原文切出来的流是好流：六条全过 + 逐字节还原。
pub fn 断言好流(原文: &str) {
    let 流 = 切记号(原文).unwrap_or_else(|错| panic!("{原文:?} 该切得动，实得 {错:?}"));
    assert_eq!(判六条(&流), [true; 6], "{原文:?} 有不变量没过");
    assert_eq!(流.还原(), 原文.as_bytes(), "{原文:?} 还原不等于原文");
}

/// 53 份真文本样本（`语料/真文本/*.txt`，UTF-8），按文件名排序。
pub fn 语料文件() -> Vec<PathBuf> {
    let 目录 = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("语料")
        .join("真文本");
    let mut 路s: Vec<PathBuf> = std::fs::read_dir(&目录)
        .unwrap_or_else(|错| panic!("读不到 {}：{错}", 目录.display()))
        .filter_map(|项| 项.ok().map(|项| 项.path()))
        .filter(|路| 路.to_str().is_some_and(|名| 名.ends_with(".txt")))
        .collect();
    路s.sort();
    路s
}

/// 读一份语料（UTF-8）。
pub fn 读语料(路径: &Path) -> String {
    std::fs::read_to_string(路径).unwrap_or_else(|错| panic!("{}：{错}", 路径.display()))
}
