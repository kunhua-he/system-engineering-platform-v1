//! 词法 · 切分测试 · 语料 —— 53 份真文本的读数（本腿的验收基准）。
//!
//! 依据 `说明/真文本覆盖.md` §一：53 份唯一文本 / 481571 GBK 字节（落盘为 UTF-8）。
//! 三件各给一个读数：**成功份数 + 六条不变量** · **逐字节还原** · **兜底归类字节**
//! （兜底字符现归 `备注文本`，第 12 种记号 —— 裁决 `2026-09-28_华哥的尺子与七条裁决.md` §二「备注位怎么记号化」）。
//!
//! **两条腿各算各的**：判定腿 `语料/撞规格.py` 拿规格去撞真文本、算通过率；
//! 本件是**实现**，把真文本真切成记号流、数它自身切不过去的字节。本件不引用判定腿的读数，
//! 只在与它对得上的地方（总字符数）做一次交叉校验。

use super::夹具::{判六条, 语料文件, 读语料};
use crate::词法::切分::切记号;
use crate::词法::字符集::是否兜底;
use crate::语言面::记号种类;
use std::collections::BTreeMap;

/// **53 份真文本全部切得动，且六条不变量逐条过**。
#[test]
fn 语料_53份_全部成功且六条不变量逐条过() {
    let 文件s = 语料文件();
    assert_eq!(
        文件s.len(),
        53,
        "语料该是 53 份（`说明/真文本覆盖.md` §一）"
    );
    let mut 通过计数 = [0usize; 6];
    let mut 记号总数 = 0usize;
    for 路径 in &文件s {
        let 原文 = 读语料(路径);
        let 输出流 = 切记号(&原文).unwrap_or_else(|错| panic!("{}：切不动，{错:?}", 路径.display()));
        let 六条结果 = 判六条(&输出流);
        for (序, 通) in 六条结果.iter().enumerate() {
            assert!(通, "{}：J{} 没过", 路径.display(), 序 + 1);
            通过计数[序] += usize::from(*通);
        }
        记号总数 += 输出流.记号表.len();
    }
    assert_eq!(通过计数, [53; 6], "六条不变量各该在 53 份上全过");
    assert!(
        记号总数 > 100_000,
        "记号总数 {记号总数} 太小，样本像是没读到"
    );
}

/// **逐字节还原**（J2–J5 的见证函数 `记号流::还原`）：53 份的拼接结果与原文逐字节相同。
#[test]
fn 语料_53份_逐字节还原原文() {
    let mut 总字节 = 0usize;
    for 路径 in &语料文件() {
        let 原文 = 读语料(路径);
        let 输出流 = 切记号(&原文).unwrap_or_else(|错| panic!("{}：{错:?}", 路径.display()));
        assert_eq!(
            输出流.还原(),
            原文.as_bytes(),
            "{}：还原不等于原文",
            路径.display()
        );
        总字节 += 原文.len();
    }
    println!("【还原】53 份 · {总字节} 字节逐字节相同");
}

/// **读数：兜底归类字节**（规格 §二 的 11 类里没有任何一类点名能吃的字符）。
///
/// 与判定腿 `语料/撞规格.py` 的口径差别见各条断言注释。
#[test]
fn 语料_53份_兜底归类字节读数() {
    // 每字符一档：`[注释, 文本字面量, 数值字面量, 备注文本]` 四桶计数 + 首见位置 + 首见行。
    let mut 兜底: BTreeMap<char, ([usize; 4], String, String)> = BTreeMap::new();
    let mut 总字节 = 0usize;
    let mut 总字符 = 0usize;
    let mut 兜底字节 = 0usize;
    let mut 归类桶 = [0usize; 4];
    let mut 备注字节 = 0usize;
    let mut 记号种数: BTreeMap<u8, usize> = BTreeMap::new();
    for 路径 in &语料文件() {
        let 原文 = 读语料(路径);
        总字节 += 原文.len();
        let 输出流 = 切记号(&原文).expect("切分");
        for 记号 in &输出流.记号表 {
            *记号种数.entry(记号.种类.取号值()).or_default() += 1;
        }
        for (位, 字符) in 原文.char_indices() {
            总字符 += 1;
            if !是否兜底(字符) {
                continue;
            }
            兜底字节 += 字符.len_utf8();
            let 行号 = 原文[..位].matches('\n').count() + 1;
            let 本行 = 原文[位..]
                .lines()
                .next()
                .unwrap_or("")
                .trim_end()
                .to_string();
            let 位置 = 位 as u32;
            let 落处 = 输出流
                .记号表
                .iter()
                .find(|记号| 记号.起 <= 位置 && 位置 < 记号.止)
                .expect("有归属");
            let 落处档位 = match 落处.种类 {
                记号种类::注释 => 0,
                记号种类::文本字面量 => 1,
                记号种类::数值字面量 => 2,
                记号种类::备注文本 => 3,
                // 兜底字符**不可能**落进 `标识符`：含兜底字符的连续段一律是 `备注文本`（裁决 §二「备注位怎么记号化」）。
                其他 => panic!("兜底字符落进了 {其他:?} —— 立 `备注文本` 的裁定被破坏"),
            };
            归类桶[落处档位] += 1;
            if 落处档位 == 3 {
                备注字节 += 字符.len_utf8();
            }
            let 一项 = 兜底.entry(字符).or_insert_with(|| {
                (
                    [0; 4],
                    format!("{}:{行号}", 路径.file_name().unwrap().to_string_lossy()),
                    本行,
                )
            });
            一项.0[落处档位] += 1;
        }
    }
    let 兜底字符: usize = 归类桶.iter().sum();
    println!("【语料】53 份 · UTF-8 字节 {总字节} · 字符 {总字符}");
    println!(
        "【记号】共 {} 枚 · 逐种：{:?}",
        记号种数.values().sum::<usize>(),
        记号种数
            .iter()
            .map(|(号, 次)| (format!("{:?}", 记号种类::自号(*号).unwrap()), *次))
            .collect::<Vec<_>>()
    );
    println!(
        "【兜底归类】{兜底字符} 字符 / {兜底字节} 字节 = {:.6}% 字符占比 · 具名类通过率 {:.6}%",
        100.0 * 兜底字符 as f64 / 总字符 as f64,
        100.0 * (总字符 - 兜底字符) as f64 / 总字符 as f64
    );
    println!(
        "    落处分桶：注释 {} · 文本字面量 {} · 数值字面量 {} · 备注文本 {}",
        归类桶[0], 归类桶[1], 归类桶[2], 归类桶[3]
    );
    println!(
        "【备注位】落 `备注文本`（＝规格没点名、又不在注释/字面量里）{} 字符 / {备注字节} 字节 = {:.6}% 字符占比",
        归类桶[3],
        100.0 * 归类桶[3] as f64 / 总字符 as f64
    );
    println!("【兜底字符逐条】字符 · U+码 · 注释/字面量/数值/标识符 四桶 · 首见位置 · 首见行");
    for (字符, (档s, 位置, 行)) in &兜底 {
        println!(
            "    {字符:?} U+{:04X}  {}/{}/{}/{}  {位置:<46} | {}",
            *字符 as u32,
            档s[0],
            档s[1],
            档s[2],
            档s[3],
            行.trim_end()
        );
    }

    // ① 总字符与判定腿的读数**必须一致**（字符数与编码无关 ⇒ 这是两条腿的交叉校验）。
    // ★ 2026-09-28 重钉：真文本早先被清过字（少 38 字节），而这里钉的是旧数 ⇒ 本测试一直红
    // （闸 0 看不见扩展仓的测试）。现按实测重钉 —— 判定腿 `语料/撞规格.py` 与实现腿**两边都是** 356761。
    assert_eq!(总字符, 356_761, "总字符该与 语料/撞规格.py 的读数一致");
    // ② 兜底字符**一个不丢地落在具名容器里**（不许有字节被丢）。
    assert_eq!(归类桶.iter().sum::<usize>(), 兜底字符);
    // ③ 判定腿 `口径次` 的 6 个代码位字符（`－`×3 `＞`×1 `%`×2）本实现**全部点名**：
    //    前两个进 `运算符`、第三个进 `标识符` ⇒ 它们不该出现在兜底表里。
    for 已点名 in ['－', '＞', '%'] {
        assert!(
            !兜底.contains_key(&已点名),
            "{已点名:?} 已被点名，不该是兜底"
        );
    }
    // ④ 兜底表里没有 `#`（它是规格点名的引导符）、没有空白/换行/界符/运算符 ——
    //    含**文档级 9 个运算符**与逻辑 `且` `或`（裁决 §二「文档级 9 个运算符接不接进词法」已接入 ⇒ 一律不再落兜底）。
    for 点名 in [
        '#', ' ', '\r', '\n', '(', ')', '[', ']', ',', '.', '&', '{', '}', '＝', '＋', '÷', '－',
        '＞', '×', '％', '＼', '＜', '≤', '≥', '≠', '≈', '且', '或',
    ] {
        assert!(!兜底.contains_key(&点名), "{点名:?} 是点名字符，不该是兜底");
    }
}
