/// **自检**：11 种记号**逐种**在下面各出现至少一次，且逐枚断言种类与区间文本。
///
/// 每一例都是「已知答案的输入」——不是拿实现去比实现，是拿手写的期望去比。
#[test]
fn 切分_手写小样例_逐枚记号对上() {
    use 记号种类::*;
    let 例: &[(&str, &[(记号种类, &str)])] = &[
        // 空原文：形状明写合法，只有一枚零宽 `文件结束`（`说明/语言面形状.md` §二（二））。
        ("", &[]),
        // 关键字（带点）· 空白 · 数值 · 换行：CRLF 与 LF 都认（规格 §二）。
        (
            ".版本 2\r\n",
            &[
                (关键字, ".版本"),
                (空白, " "),
                (数值字面量, "2"),
                (换行, "\r\n"),
            ],
        ),
        (
            ".版本 2\n",
            &[
                (关键字, ".版本"),
                (空白, " "),
                (数值字面量, "2"),
                (换行, "\n"),
            ],
        ),
        // 缩进是「位于行首的空白」，不是独立种类。
        (
            "    .参数 计数, 整数型\r\n",
            &[
                (空白, "    "),
                (关键字, ".参数"),
                (空白, " "),
                (标识符, "计数"),
                (界符, ","),
                (空白, " "),
                (标识符, "整数型"),
                (换行, "\r\n"),
            ],
        ),
        // 不带点关键字 `返回` · 注释不含行尾换行（换行恒由 `换行` 认领）。
        (
            "返回 (0)  ' 行尾\r\n",
            &[
                (关键字, "返回"),
                (空白, " "),
                (界符, "("),
                (数值字面量, "0"),
                (界符, ")"),
                (空白, "  "),
                (注释, "' 行尾"),
                (换行, "\r\n"),
            ],
        ),
        ("' 整行注释\r\n", &[(注释, "' 整行注释"), (换行, "\r\n")]),
        // 行内 `.` 是成员访问界符；`真` 不在行首 ⇒ 标识符。
        (
            "监听服务器.置SSL抓包 (真)\r\n",
            &[
                (标识符, "监听服务器"),
                (界符, "."),
                (标识符, "置SSL抓包"),
                (空白, " "),
                (界符, "("),
                (标识符, "真"),
                (界符, ")"),
                (换行, "\r\n"),
            ],
        ),
        // 空实参：逗号之间的零宽位次在记号层不许被吃掉（两个逗号 = 一个空位）。
        (
            "信息框 (“你好”, 0, , )\r\n",
            &[
                (标识符, "信息框"),
                (空白, " "),
                (界符, "("),
                (文本字面量, "“你好”"),
                (界符, ","),
                (空白, " "),
                (数值字面量, "0"),
                (界符, ","),
                (空白, " "),
                (界符, ","),
                (空白, " "),
                (界符, ")"),
                (换行, "\r\n"),
            ],
        ),
        // 常量引用（名字允许纯数字，缺口 5）· 运算符全角 · 数值。
        (
            "#FALSE ＝ #60 ＋ 1 ÷ 2\r\n",
            &[
                (常量引用, "#FALSE"),
                (空白, " "),
                (运算符, "＝"),
                (空白, " "),
                (常量引用, "#60"),
                (空白, " "),
                (运算符, "＋"),
                (空白, " "),
                (数值字面量, "1"),
                (空白, " "),
                (运算符, "÷"),
                (空白, " "),
                (数值字面量, "2"),
                (换行, "\r\n"),
            ],
        ),
        // 半角里套全角（语料实测的唯一嵌套形态）：一个种类，定界符从区间首字节读。
        (
            ".常量 名, \"“值”\"\r\n",
            &[
                (关键字, ".常量"),
                (空白, " "),
                (标识符, "名"),
                (界符, ","),
                (空白, " "),
                (文本字面量, "\"“值”\""),
                (换行, "\r\n"),
            ],
        ),
        // `置入代码` 是实测的两个不带点关键字之一；`{` `}` 是实测的界符。
        (
            "置入代码 ({ 139, 69 })\r\n",
            &[
                (关键字, "置入代码"),
                (空白, " "),
                (界符, "("),
                (界符, "{"),
                (空白, " "),
                (数值字面量, "139"),
                (界符, ","),
                (空白, " "),
                (数值字面量, "69"),
                (空白, " "),
                (界符, "}"),
                (界符, ")"),
                (换行, "\r\n"),
            ],
        ),
        // 数值：负号只在操作数位起数值；`计数-1` 里半角 `-` 是兜底字符，续前一枚标识符。
        ("-1\r\n", &[(数值字面量, "-1"), (换行, "\r\n")]),
        ("3.51\r\n", &[(数值字面量, "3.51"), (换行, "\r\n")]),
        ("计数-1\r\n", &[(标识符, "计数-1"), (换行, "\r\n")]),
        // `%` 是实测的标识符字符（缺口 6：变量名 `%s`）。
        (
            ".局部变量 %s, 文本型\r\n",
            &[
                (关键字, ".局部变量"),
                (空白, " "),
                (标识符, "%s"),
                (界符, ","),
                (空白, " "),
                (标识符, "文本型"),
                (换行, "\r\n"),
            ],
        ),
        // 缺口 4 实测的两个代码位运算符：`－`（U+FF0D）与 `＞`（U+FF1E）。
        (
            "_启动窗口.高度 － 标签EX2.高度\r\n",
            &[
                (标识符, "_启动窗口"),
                (界符, "."),
                (标识符, "高度"),
                (空白, " "),
                (运算符, "－"),
                (空白, " "),
                (标识符, "标签EX2"),
                (界符, "."),
                (标识符, "高度"),
                (换行, "\r\n"),
            ],
        ),
    ];

    // 11 种记号**逐种**都在这组样例里出现过（漏一种就是自检没覆盖面）。
    let 见过: std::collections::BTreeSet<u8> = 例
        .iter()
        .flat_map(|(_, 片)| 片.iter().map(|(种, _)| 种.号()))
        .chain(std::iter::once(记号种类::文件结束.号()))
        .collect();
    assert_eq!(
        见过.len(),
        11,
        "自检样例该覆盖 11 种记号，实得 {} 种",
        见过.len()
    );

    for (原文, 片) in 例 {
        assert_eq!(切对(原文), 期望(片), "原文 {原文:?}");
    }
}

/// 注释**不含行尾换行** ⇒ 整行注释与行尾注释同构（`说明/语言面形状.md` §二（一））。
#[test]
fn 切分_注释不吞行尾换行() {
    use 记号种类::*;
    for 原文 in [
        "' 整行注释\r\n",
        "计数  ' 行尾注释\r\n",
        "' 整行注释\n",
        "计数  ' 行尾注释",
    ] {
        let 流 = 切记号(原文).expect("切分");
        for 记号 in &流.记号表 {
            if 记号.种类 == 注释 {
                let 片 = &流.原文[记号.起 as usize..记号.止 as usize];
                assert!(
                    !片.contains(&b'\r') && !片.contains(&b'\n'),
                    "{原文:?} 的注释记号吞了行尾换行"
                );
            }
        }
    }
    // 行尾注释后面必须紧跟一枚 `换行`（若原文有行尾）。
    let 流 = 切记号("计数  ' 行尾注释\r\n").expect("切分");
    let 注 = 流
        .记号表
        .iter()
        .position(|记号| 记号.种类 == 注释)
        .expect("有注释");
    assert_eq!(流.记号表[注 + 1].种类, 换行);
}

/// `.` 一号两用：**行首**引导关键字（点含在区间内），**行内**是成员访问界符。
#[test]
fn 切分_点一号两用() {
    use 记号种类::*;
    let 流 = 切记号(".参数 计数.文本\r\n").expect("切分");
    assert_eq!(流.记号表[0].种类, 关键字);
    assert_eq!(流.切片(0), Some(&b".\xe5\x8f\x82\xe6\x95\xb0"[..])); // “.参数”，点含在内
    let 界 = 流.记号表.iter().filter(|记号| 记号.种类 == 界符).count();
    assert_eq!(界, 1, "行内的那一个 `.` 该是界符");
}

/// 空实参的**位次**在记号层就分得开：`(被加数, , 加数)` 与 `(被加数, 加数)` 的逗号枚数不同。
/// （零宽 `空实参` 是语法树层的事；记号层的责任是**不把空位吃掉**。）
#[test]
fn 切分_空实参位次在记号层可数() {
    use 记号种类::*;
    let 数逗号 = |原文: &str| {
        let 流 = 切记号(原文).expect("切分");
        (0..流.记号表.len())
            .filter(|记号位次| 流.记号表[*记号位次].种类 == 界符)
            .filter_map(|记号位次| 流.切片(记号位次))
            .filter(|片| *片 == b",")
            .count()
    };
    assert_eq!(
        数逗号("求和 (被加数, , 加数)\r\n"),
        2,
        "一个空位 ⇒ 两个逗号"
    );
    assert_eq!(数逗号("求和 (被加数, 加数)\r\n"), 1);
    // 实测原样一行（一条调用里 13 个空位）：判据是「记号层不许吃掉任何一枚逗号」。
    let 实测行 = "D3D_HookCall (pDevice, , , , , , , , , , , , , , )\r\n";
    assert_eq!(数逗号(实测行), 实测行.matches(',').count());
    assert_eq!(数逗号(实测行), 14, "1 个实参 + 13 个空位 ⇒ 14 枚逗号");
}

/// 未分类字符（兜底）**只可能落在具名容器里**：`标识符` · `注释` · `文本字面量` · `数值字面量`。
/// 这条同时证明「兜底真的并进了具名类」（不是被丢弃、也不是另造了种类）。
///
/// `数值字面量` 为什么在列：半角 `-` 规格未点名（兜底），而 `计数, -1` 里的它按判定腿
/// `语料/撞规格.py` 同一条件成为负号 —— 于是它落在一枚 `数值字面量` 里。**只有它一个字符**
/// 有这情形，且只在备注位出现（实测 `-` 96 次全在声明/备注位）。
#[test]
fn 切分_兜底字符只落在具名容器里() {
    let 例 = [
        ".成员 格式标签, 短整数型, , , wFormatTag，记录着此声音的格式代号\r\n",
        ".参数 事件消息值, 整数型, , -1:准备就绪;1:周期事件;-2:定时器被关闭\r\n",
        "' 注释里也有兜底 ，。：；\r\n",
        "信息框 (“字面量里也有兜底 ，。”)\r\n",
        "#FALSE ＋ ，\r\n",
    ];
    for 原文 in 例 {
        let 流 = 切记号(原文).expect("切分");
        for (位, 字符) in 原文.char_indices() {
            if !是否兜底(字符) {
                continue;
            }
            let 位 = 位 as u32;
            let 落处 = 流.记号表.iter().find(|记号| 记号.起 <= 位 && 位 < 记号.止);
            let 落处 = 落处.unwrap_or_else(|| panic!("{原文:?} 位置 {位} 无归属"));
            assert!(
                matches!(
                    落处.种类,
                    记号种类::标识符
                        | 记号种类::注释
                        | 记号种类::文本字面量
                        | 记号种类::数值字面量
                ),
                "{原文:?} 位置 {位} 的 {字符:?} 落在 {:?} 里",
                落处.种类
            );
        }
    }
}

