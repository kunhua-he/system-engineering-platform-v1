/// 行首**不带点**的语句关键字。出处：规格 §二「少数不带点（`返回` `置入代码`）」；
/// 语料实测 **2 种 / 117 次**（`返回` 115 · `置入代码` 2），**没有第三种**。
///
/// 判据是「本行首个非空白处、且整枚标识符**逐字等于**这两个之一」——
/// 所以 `返回码` 是标识符，`返回` 才是关键字（`置入代码 ({ … })` 实测存在）。
const 不带点关键字: [&str; 2] = ["返回", "置入代码"];

/// **能力 1101 的公开面**：把我们的程序文本切成记号流。
///
/// 输入：UTF-8 程序文本（规格 §二；`原文` 是 `&str` ⇒ 入口天然保证 UTF-8）。
/// 输出：`记号流`（原文 + 记号表），区间首尾相接且覆盖全文，末枚为零宽 `文件结束`。
///
/// **失败面只有一条**：引号不配对 ⇒ `形状错误::词法层输入非法`（码 **1137**，见文件头「裁定 2」）。
/// 其余输入（含空原文、只有注释、坏 UTF-8 边界不可达、兜底字符）都是**总函数**：
/// 任何别的 `&str` 都切得动、不 panic、不丢字节。不做名字解析（那是 1102/1103 的活）。
pub fn 切记号(原文: &str) -> Result<记号流, 形状错误> {
    let 字节 = 原文.as_bytes();
    let 全文长 = 字节.len();
    let mut 项表: Vec<记号> = Vec::new();
    let mut 位置 = 0usize;
    while 位置 < 全文长 {
        let (内容止, 终止长) = 找行尾(字节, 位置);
        切一行(原文, 位置, 内容止, &mut 项表)?;
        if 终止长 > 0 {
            项表.push(记号::新建(记号种类::换行, 取偏移(内容止), 取偏移(内容止 + 终止长)));
        }
        位置 = 内容止 + 终止长;
    }
    // J1：**无条件**补一枚零宽 `文件结束`（空原文也有一枚）。
    项表.push(记号::新建(记号种类::文件结束, 取偏移(全文长), 取偏移(全文长)));
    记号流::新建(字节.to_vec(), 项表)
}

/// 本行内容 `[起, 止)` 与行尾终止符的宽度（0 / 1 / 2）。行尾终止符**不含在内容里**。
///
/// 认三种：`\r\n`（2 字节，语料实测 10945 次）· `\n`（1 字节，语料 0 次）· 落单 `\r`（1 字节，
/// 语料 0 次 —— 见文件头裁定 1）。
fn 找行尾(字节: &[u8], 区间起点: usize) -> (usize, usize) {
    let mut 字节下标 = 区间起点;
    while 字节下标 < 字节.len() {
        match 字节[字节下标] {
            b'\n' => return (字节下标, 1),
            b'\r' => {
                return (
                    字节下标,
                    if 字节.get(字节下标 + 1) == Some(&b'\n') {
                        2
                    } else {
                        1
                    },
                );
            }
            _ => 字节下标 += 1,
        }
    }
    (字节.len(), 0)
}

/// 切一行：`[行起, 内容止)` 是行内容（不含行尾终止符），产出的记号按序追加。
///
/// 每条分支都**至少消费一个字符**（最后一支用 `i += 1` 兜底），所以循环必然终止、
/// 且不可能漏字节 —— J3/J4/J5 就是这条性质。
///
/// **唯一的失败**：引号不配对 ⇒ `形状错误::词法层输入非法`（1137，文件头「裁定 2」）。
fn 切一行(原文: &str, 行起: usize, 内容止: usize, 项表: &mut Vec<记号>) -> Result<(), 形状错误> {
    let 字符表: Vec<(usize, char)> = 原文[行起..内容止]
        .char_indices()
        .map(|(偏, 字符)| (行起 + 偏, 字符))
        .collect();
    let 字数 = 字符表.len();
    let mut 字符下标 = 0usize;

    // ① 行首缩进（「行首的空白」不是独立种类，它是 `空白`）。
    while 字符下标 < 字数 && 是否空白(字符表[字符下标].1) {
        字符下标 += 1;
    }
    if 字符下标 > 0 {
        项表.push(记号::新建(记号种类::空白, 取偏移(字符表[0].0), 止于(&字符表, 字符下标 - 1)));
    }
    let 行首 = 字符下标; // 本行首个非空白字符在 `字` 中的下标

    // ② 顺序消费到行尾。
    while 字符下标 < 字数 {
        let 字符 = 字符表[字符下标].1;
        if 是否空白(字符) {
            let 区间起点 = 字符下标;
            while 字符下标 < 字数 && 是否空白(字符表[字符下标].1) {
                字符下标 += 1;
            }
            项表.push(记号::新建(记号种类::空白, 取偏移(字符表[区间起点].0), 止于(&字符表, 字符下标 - 1)));
        } else if 是否注释引导(字符) {
            // 注释至行尾，**不含行尾换行** —— 换行恒由 `换行` 记号认领，
            // 于是整行注释与行尾注释同构（`说明/语言面形状.md` §二（一））。
            项表.push(记号::新建(记号种类::注释, 取偏移(字符表[字符下标].0), 取偏移(内容止)));
            字符下标 = 字数;
        } else if let Some(收) = 引号收尾(字符) {
            // 文本字面量：行内找配对的收尾字符（全角找 `”`、半角找 `"`，故可嵌套）。
            let mut 收尾下标 = 字符下标 + 1;
            while 收尾下标 < 字数 && 字符表[收尾下标].1 != 收 {
                收尾下标 += 1;
            }
            if 收尾下标 >= 字数 {
                // 引号不配对 ⇒ 切分本身做不了 ⇒ fail-closed 报 1137（文件头「裁定 2」）。
                return Err(形状错误::词法层输入非法);
            }
            项表.push(记号::新建(记号种类::文本字面量, 取偏移(字符表[字符下标].0), 止于(&字符表, 收尾下标)));
            字符下标 = 收尾下标 + 1;
        } else if 字符 == '#' && 后是标识符字符(&字符表, 字符下标) {
            let 区间起点 = 字符下标;
            字符下标 += 1;
            while 字符下标 < 字数 && 是否标识符字符(字符表[字符下标].1) {
                字符下标 += 1;
            }
            项表.push(记号::新建(
                记号种类::常量引用,
                取偏移(字符表[区间起点].0),
                止于(&字符表, 字符下标 - 1),
            ));
        } else if let Some(止下标) = 数值止(&字符表, 字符下标) {
            项表.push(记号::新建(
                记号种类::数值字面量,
                取偏移(字符表[字符下标].0),
                止于(&字符表, 止下标 - 1),
            ));
            字符下标 = 止下标;
        } else if 字符 == '.' && 字符下标 == 行首 && 后是标识符字符(&字符表, 字符下标) {
            // `.` 一号两用之一：**行首**引导关键字，**点含在区间内**（源里它不可分割）。
            let 区间起点 = 字符下标;
            字符下标 += 1;
            while 字符下标 < 字数 && 是否标识符字符(字符表[字符下标].1) {
                字符下标 += 1;
            }
            项表.push(记号::新建(
                记号种类::关键字,
                取偏移(字符表[区间起点].0),
                止于(&字符表, 字符下标 - 1),
            ));
        } else if 是否运算符(字符) || 独立逻辑运算符(&字符表, 字符下标) {
            项表.push(记号::新建(记号种类::运算符, 取偏移(字符表[字符下标].0), 止于(&字符表, 字符下标)));
            字符下标 += 1;
        } else if 是否界符(字符) {
            // `.` 一号两用之另一：行内是成员访问。
            项表.push(记号::新建(记号种类::界符, 取偏移(字符表[字符下标].0), 止于(&字符表, 字符下标)));
            字符下标 += 1;
        } else {
            // 标识符 / 备注文本 / 行首不带点关键字。
            // 走到这里说明它不是上面任何一类，必是**标识符字符或兜底字符** ⇒ 至少吃一个。
            let 区间起点 = 字符下标;
            let mut 含兜底 = 是否兜底(字符表[区间起点].1);
            字符下标 += 1;
            while 字符下标 < 字数 && (是否标识符字符(字符表[字符下标].1) || 是否兜底(字符表[字符下标].1)) {
                if 是否兜底(字符表[字符下标].1) {
                    含兜底 = true;
                }
                字符下标 += 1;
            }
            let 区间终点 = 止于(&字符表, 字符下标 - 1);
            let 候选词 = &原文[字符表[区间起点].0..区间终点 as usize];
            // 种类三选一：含兜底字节 ⇒ `备注文本`（**不许冒充名字**，裁决 §二「备注位怎么记号化」）；
            // 否则是纯标识符字符段 —— 行首且逐字等于不带点关键字 ⇒ `关键字`，其余 ⇒ `标识符`。
            let 种类 = if 含兜底 {
                记号种类::备注文本
            } else if 区间起点 == 行首 && 不带点关键字.contains(&候选词) {
                记号种类::关键字
            } else {
                记号种类::标识符
            };
            项表.push(记号::新建(种类, 取偏移(字符表[区间起点].0), 区间终点));
        }
    }
    Ok(())
}

/// 数值字面量的**终止下标**（`字符表` 的下标，不含）；`None` = 这里不是数值的起点。
///
/// 形态：`-?（[0-9]+(\.[0-9]+)? | 0[xX][0-9A-Fa-f]+）`。负号只在「不紧跟在标识符字符之后」
/// 时起数值 —— 否则它是兜底字符，归 `备注文本`（`计数-1` 是**一枚** `备注文本`，`, -1` 才是数值）。
fn 数值止(字符表: &[(usize, char)], 字符下标: usize) -> Option<usize> {
    let 字数 = 字符表.len();
    let 字符 = 字符表[字符下标].1;
    let mut 数字下标 = 字符下标;
    if 字符 == '-' {
        if 字符下标 > 0 && 是否标识符字符(字符表[字符下标 - 1].1) {
            return None;
        }
        if !后是数字(字符表, 字符下标) {
            return None;
        }
        数字下标 = 字符下标 + 1;
    } else if !字符.is_ascii_digit() {
        return None;
    }
    // 十六进制：`0x` / `0X` 后**至少一位**十六进制数字 ⇒ 整个前缀段是一枚数值字面量（裁定 3）。
    // 不认这条，`0x1F` 会切成 `数值字面量(0) + 标识符(x1F)` —— 认不出又不报错的误类（裁决 §二「十六进制字面量」）。
    // `0x` 后没有十六进制数字时**不是**字面量：退回「`0` + 标识符」，如实登记（无证据、不发明行为）。
    if 字符表[数字下标].1 == '0' {
        if let (Some(前缀), Some(首位)) = (字符表.get(数字下标 + 1), 字符表.get(数字下标 + 2)) {
            if (前缀.1 == 'x' || 前缀.1 == 'X') && 首位.1.is_ascii_hexdigit() {
                let mut 十六下标 = 数字下标 + 2;
                while 十六下标 < 字数 && 字符表[十六下标].1.is_ascii_hexdigit() {
                    十六下标 += 1;
                }
                return Some(十六下标);
            }
        }
    }
    while 数字下标 < 字数 && 字符表[数字下标].1.is_ascii_digit() {
        数字下标 += 1;
    }
    // 小数：只在「点后紧跟数字」时吃（裁定 3）。`计数.文本` 不受影响：点后不是数字。
    if 数字下标 + 1 < 字数 && 字符表[数字下标].1 == '.' && 字符表[数字下标 + 1].1.is_ascii_digit() {
        数字下标 += 1;
        while 数字下标 < 字数 && 字符表[数字下标].1.is_ascii_digit() {
            数字下标 += 1;
        }
    }
    Some(数字下标)
}

/// 第 `i` 个字符是不是**独立成词**的逻辑运算符（`且` `或`）。
///
/// `且` `或` 是汉字（[`是否标识符字符`] 为真）又同时是文档级逻辑运算符，两个集合**有意重叠**
/// （`字符集.rs` 末的编译期断言）。重叠不靠分支顺序消解：**两侧都不是标识符字符时**才算
/// 运算符，于是 `位或`（语料代码位实测的命令名）与 `或者` 仍是一枚标识符，不被切坏。
fn 独立逻辑运算符(字符表: &[(usize, char)], 字符下标: usize) -> bool {
    if !是否逻辑运算符(字符表[字符下标].1) {
        return false;
    }
    let 左是名 = 字符下标 > 0 && 是否标识符字符(字符表[字符下标 - 1].1);
    let 右是名 = 字符表.get(字符下标 + 1).is_some_and(|(_, 字符)| 是否标识符字符(*字符));
    !左是名 && !右是名
}

/// 第 `i` 个字符的下一个字符是不是标识符字符。
fn 后是标识符字符(字符表: &[(usize, char)], 字符下标: usize) -> bool {
    字符表.get(字符下标 + 1).is_some_and(|(_, 字符)| 是否标识符字符(*字符))
}

/// 第 `i` 个字符的下一个字符是不是半角数字。
fn 后是数字(字符表: &[(usize, char)], 字符下标: usize) -> bool {
    字符表.get(字符下标 + 1).is_some_and(|(_, 字符)| 字符.is_ascii_digit())
}

/// 第 `k` 个字符的**终止字节偏移**（不含）。
fn 止于(字符表: &[(usize, char)], 字符下标: usize) -> u32 {
    取偏移(字符表[字符下标].0 + 字符表[字符下标].1.len_utf8())
}

/// `usize` → 区间用的 `u32`。上限 4 GiB 是形状自身的口径（`说明/语言面形状.md` §一）。
fn 取偏移(位置: usize) -> u32 {
    位置 as u32
}
