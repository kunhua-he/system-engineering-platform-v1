//! 词法 · 切分 —— **程序文本 → 记号流**（能力 1101 的实现本体）。
//!
//! 形状一字不改：产出 `crate::语言面::{记号, 记号流, 记号种类}`。
//!
//! # 六条不变量（J1–J6）怎么保证
//!
//! 切分器**顺序走完全文**：每消费一段字节就产出一枚记号，区间恰是 `[消费起, 消费止)`。于是
//!
//! | # | 不变量 | 靠什么成立 |
//! |---|---|---|
//! | J1 | 末位有且仅有一枚零宽 `文件结束`，锚在 `[全文长, 全文长)` | 收尾**无条件**补一枚（`文件结束` 只在这里产出） |
//! | J2 | 首记号的 `起` == 0 | 从 `位 = 0` 起消费，第一枚记号的起就是 0（空原文时是零宽那枚） |
//! | J3 | 无缝隙（`前.止 == 后.起`） | 每枚记号的起 = 上一枚的止（`位` 单调前进，没有第二处产出记号的入口） |
//! | J4 | 无重叠（`前.止 <= 后.起`） | 同上：起恒等于前止，不可能小于 |
//! | J5 | 末记号止 == 全文长 | 循环条件是 `位 < 全文长`，退出时 `位 == 全文长`，收尾那枚锚在此处 |
//! | J6 | 每枚 `起 <= 止 <= 全文长` | 区间只由「实际消费的字节数」算出（不查表、不补白、不跳字节） |
//!
//! 最后交给唯一构造口 [`记号流::新建`] —— 它把这 6 条判死。那 10 条码（1108–1117）是构造口的
//! 防御面，**经本函数不可达**（不是「没想到」，是「做不到」：见下「兜底」）。**本函数自身的
//! 失败面只有一条**：引号不配对 ⇒ `1137`（见下「裁定 2」）。
//!
//! # 兜底：本实现最重要的一条裁定
//!
//! 规格 §二 的 11 种里**没有一类能吃「不加引号的自由文本」**（`说明/真文本覆盖.md` 缺口 2：
//! 声明行末字段的备注可含全角标点、半角标点、反斜杠、`=` `*` `/` `+`），而 J2–J5 要求
//! **每个字节都有归属**。形状里只有 11 种、没有第 12 种 `备注文本`（不许增删），
//! 所以本实现把「规格没点名的字符」（[`super::字符集::是否兜底`]）**并进 `标识符`**：
//! 它们既能**起**一枚 `标识符`，也能**续**一枚 `标识符`。
//!
//! 出处：`说明/真文本覆盖.md` 缺口 6 —— 规格**未给**标识符字符集，而实测变量名里出现 `%`；
//! 该文给的建议是「标识符 = 汉字 + `[0-9A-Za-z_]`，实测还出现 `%`」。本实现取更强的一条：
//! **标识符 = 具名标识符字符 ∪ 兜底字符**，并把兜底吃掉的字节**如实计数**（`切分测试.rs` 的
//! 未归类读数）。**归类不等于有语义** —— 1102 拿到区间后自会按所在层级判它是不是备注。
//!
//! 这条裁定的代价说清楚：`.成员 格式标签, 短整数型, , , wFormatTag，记录着此声音的格式代号`
//! 的末字段会成一枚 `标识符`（区间含全角 `，`），而不是一枚「备注」。这是**形状的选择**，
//! 不是实现的口味：11 种里没有备注类，剩下的唯一去处就是名字类。
//!
//! # 规格与语料都没定、由本件裁定的四条（登记待办）
//!
//! 1. **落单的 `\r` 算换行**（1 字节宽）。规格只认 `\r\n` 与 `\n`；语料裸 CR 0 例 ⇒ **无证据**。
//!    选「算换行」的理由是**不这么选会静默毁掉整份文件**：`'` 注释吃到行尾，若裸 CR 不断行，
//!    CR-only 文本从第一条注释起全被吞掉，且还原仍逐字节相同（假绿）。
//! 2. **引号不配对 ⇒ fail-closed 报 `1137`**（原判「以行尾为界」已撤）。规格与语料都没给
//!    「未闭合引号怎么办」：语料未闭合 **0 例**（`说明/真文本覆盖.md` §二）⇒ 无实测依据。
//!    无转义机制（实测）、跨行 0 例（无证据）。原判把它兜成「以行尾为界」是**猜**；现在
//!    改成**明确失败**：`1137`（词法层输入非法）已在 `错误码表/1137.json` 登记、已进
//!    1101 的 `可抛错误码`，只是切分侧原先没接上。
//!    **不静默吞** —— 与 `记号流::新建` 对 >4 GiB 的 fail-closed 同一条口径。
//! 3. **数值只认十进制整数 + 可选小数**。小数出处是备注位 4 例（`3.51` `4.0`），
//!    **代码位 0 例**；十六进制与科学计数 0 例 ⇒ 不认（登记待办）。
//! 4. **`#` 后面没有名字时落兜底**（成一枚 `标识符`）。语料 `#` 全部带名字（21 种 / 120 次），
//!    落单形态 0 例 ⇒ 无证据。

use super::字符集::*;
use crate::语言面::{形状错误, 记号, 记号流, 记号种类};

/// 行首**不带点**的语句关键字。出处：规格 §二「少数不带点（`返回` `置入代码`）」；
/// 语料实测 **2 种 / 117 次**（`返回` 115 · `置入代码` 2），**没有第三种**。
///
/// 判据是「本行首个非空白处、且整枚标识符**逐字等于**这两个之一」——
/// 所以 `返回码` 是标识符，`返回` 才是关键字（`置入代码 ({ … })` 实测存在）。
const 不带点关键字: [&str; 2] = ["返回", "置入代码"];

/// **能力 1101 的公开面**：把我们的程序文本切成记号流。
///
/// 输入：UTF-8 程序文本（规格 §二；`原文` 是 `&str` ⇒ 入口天然保证 UTF-8）。
/// 输出：`记号流`（原文 + 记号表），区间首尾相接且覆盖全文，末枚为零宽 `文件结束`。
///
/// **失败面只有一条**：引号不配对 ⇒ `形状错误::词法层输入非法`（码 **1137**，见文件头「裁定 2」）。
/// 其余输入（含空原文、只有注释、坏 UTF-8 边界不可达、兜底字符）都是**总函数**：
/// 任何别的 `&str` 都切得动、不 panic、不丢字节。不做名字解析（那是 1102/1103 的活）。
pub fn 切记号(原文: &str) -> Result<记号流, 形状错误> {
    let 字节 = 原文.as_bytes();
    let 全文长 = 字节.len();
    let mut 表: Vec<记号> = Vec::new();
    let mut 位 = 0usize;
    while 位 < 全文长 {
        let (内容止, 终止长) = 找行尾(字节, 位);
        切一行(原文, 位, 内容止, &mut 表)?;
        if 终止长 > 0 {
            表.push(记号::新(记号种类::换行, 偏(内容止), 偏(内容止 + 终止长)));
        }
        位 = 内容止 + 终止长;
    }
    // J1：**无条件**补一枚零宽 `文件结束`（空原文也有一枚）。
    表.push(记号::新(记号种类::文件结束, 偏(全文长), 偏(全文长)));
    记号流::新建(字节.to_vec(), 表)
}

/// 本行内容 `[起, 止)` 与行尾终止符的宽度（0 / 1 / 2）。行尾终止符**不含在内容里**。
///
/// 认三种：`\r\n`（2 字节，语料实测 10945 次）· `\n`（1 字节，语料 0 次）· 落单 `\r`（1 字节，
/// 语料 0 次 —— 见文件头裁定 1）。
fn 找行尾(字节: &[u8], 起: usize) -> (usize, usize) {
    let mut 字节下标 = 起;
    while 字节下标 < 字节.len() {
        match 字节[字节下标] {
            b'\n' => return (字节下标, 1),
            b'\r' => {
                return (
                    字节下标,
                    if 字节.get(字节下标 + 1) == Some(&b'\n') {
                        2
                    } else {
                        1
                    },
                );
            }
            _ => 字节下标 += 1,
        }
    }
    (字节.len(), 0)
}

/// 切一行：`[行起, 内容止)` 是行内容（不含行尾终止符），产出的记号按序追加。
///
/// 每条分支都**至少消费一个字符**（最后一支用 `i += 1` 兜底），所以循环必然终止、
/// 且不可能漏字节 —— J3/J4/J5 就是这条性质。
///
/// **唯一的失败**：引号不配对 ⇒ `形状错误::词法层输入非法`（1137，文件头「裁定 2」）。
fn 切一行(原文: &str, 行起: usize, 内容止: usize, 表: &mut Vec<记号>) -> Result<(), 形状错误> {
    let 字: Vec<(usize, char)> = 原文[行起..内容止]
        .char_indices()
        .map(|(偏, 字符)| (行起 + 偏, 字符))
        .collect();
    let 字数 = 字.len();
    let mut 字符下标 = 0usize;

    // ① 行首缩进（「行首的空白」不是独立种类，它是 `空白`）。
    while 字符下标 < 字数 && 是否空白(字[字符下标].1) {
        字符下标 += 1;
    }
    if 字符下标 > 0 {
        表.push(记号::新(记号种类::空白, 偏(字[0].0), 止于(&字, 字符下标 - 1)));
    }
    let 行首 = 字符下标; // 本行首个非空白字符在 `字` 中的下标

    // ② 顺序消费到行尾。
    while 字符下标 < 字数 {
        let 字符 = 字[字符下标].1;
        if 是否空白(字符) {
            let 起 = 字符下标;
            while 字符下标 < 字数 && 是否空白(字[字符下标].1) {
                字符下标 += 1;
            }
            表.push(记号::新(记号种类::空白, 偏(字[起].0), 止于(&字, 字符下标 - 1)));
        } else if 是否注释引导(字符) {
            // 注释至行尾，**不含行尾换行** —— 换行恒由 `换行` 记号认领，
            // 于是整行注释与行尾注释同构（`说明/语言面形状.md` §二（一））。
            表.push(记号::新(记号种类::注释, 偏(字[字符下标].0), 偏(内容止)));
            字符下标 = 字数;
        } else if let Some(收) = 引号收尾(字符) {
            // 文本字面量：行内找配对的收尾字符（全角找 `”`、半角找 `"`，故可嵌套）。
            let mut 收尾下标 = 字符下标 + 1;
            while 收尾下标 < 字数 && 字[收尾下标].1 != 收 {
                收尾下标 += 1;
            }
            if 收尾下标 >= 字数 {
                // 引号不配对 ⇒ 切分本身做不了 ⇒ fail-closed 报 1137（文件头「裁定 2」）。
                return Err(形状错误::词法层输入非法);
            }
            表.push(记号::新(记号种类::文本字面量, 偏(字[字符下标].0), 止于(&字, 收尾下标)));
            字符下标 = 收尾下标 + 1;
        } else if 字符 == '#' && 后是标识符字符(&字, 字符下标) {
            let 起 = 字符下标;
            字符下标 += 1;
            while 字符下标 < 字数 && 是否标识符字符(字[字符下标].1) {
                字符下标 += 1;
            }
            表.push(记号::新(
                记号种类::常量引用,
                偏(字[起].0),
                止于(&字, 字符下标 - 1),
            ));
        } else if let Some(止下标) = 数值止(&字, 字符下标) {
            表.push(记号::新(
                记号种类::数值字面量,
                偏(字[字符下标].0),
                止于(&字, 止下标 - 1),
            ));
            字符下标 = 止下标;
        } else if 字符 == '.' && 字符下标 == 行首 && 后是标识符字符(&字, 字符下标) {
            // `.` 一号两用之一：**行首**引导关键字，**点含在区间内**（源里它不可分割）。
            let 起 = 字符下标;
            字符下标 += 1;
            while 字符下标 < 字数 && 是否标识符字符(字[字符下标].1) {
                字符下标 += 1;
            }
            表.push(记号::新(
                记号种类::关键字,
                偏(字[起].0),
                止于(&字, 字符下标 - 1),
            ));
        } else if 是否运算符(字符) {
            表.push(记号::新(记号种类::运算符, 偏(字[字符下标].0), 止于(&字, 字符下标)));
            字符下标 += 1;
        } else if 是否界符(字符) {
            // `.` 一号两用之另一：行内是成员访问。
            表.push(记号::新(记号种类::界符, 偏(字[字符下标].0), 止于(&字, 字符下标)));
            字符下标 += 1;
        } else {
            // 标识符 / 兜底 / 行首不带点关键字。**兜底也走这里**（文件头「兜底」）。
            let 起 = 字符下标;
            字符下标 += 1; // 至少吃一个：走到这里说明它不是上面任何一类，必是标识符字符或兜底字符
            while 字符下标 < 字数 && (是否标识符字符(字[字符下标].1) || 是否兜底(字[字符下标].1)) {
                字符下标 += 1;
            }
            let 止 = 止于(&字, 字符下标 - 1);
            let 词 = &原文[字[起].0..止 as usize];
            let 种类 = if 起 == 行首 && 不带点关键字.contains(&词) {
                记号种类::关键字
            } else {
                记号种类::标识符
            };
            表.push(记号::新(种类, 偏(字[起].0), 止));
        }
    }
    Ok(())
}

/// 数值字面量的**终止下标**（`字` 的下标，不含）；`None` = 这里不是数值的起点。
///
/// 形态：`-?[0-9]+(\.[0-9]+)?`。负号只在「不紧跟在标识符字符之后」时起数值 ——
/// 否则它是兜底字符，续前一枚标识符（`计数-1` 是一枚标识符，`, -1` 才是数值）。
fn 数值止(字: &[(usize, char)], 字符下标: usize) -> Option<usize> {
    let 字数 = 字.len();
    let 字符 = 字[字符下标].1;
    let mut 数字下标 = 字符下标;
    if 字符 == '-' {
        if 字符下标 > 0 && 是否标识符字符(字[字符下标 - 1].1) {
            return None;
        }
        if !后是数字(字, 字符下标) {
            return None;
        }
        数字下标 = 字符下标 + 1;
    } else if !字符.is_ascii_digit() {
        return None;
    }
    while 数字下标 < 字数 && 字[数字下标].1.is_ascii_digit() {
        数字下标 += 1;
    }
    // 小数：只在「点后紧跟数字」时吃（裁定 3）。`计数.文本` 不受影响：点后不是数字。
    if 数字下标 + 1 < 字数 && 字[数字下标].1 == '.' && 字[数字下标 + 1].1.is_ascii_digit() {
        数字下标 += 1;
        while 数字下标 < 字数 && 字[数字下标].1.is_ascii_digit() {
            数字下标 += 1;
        }
    }
    Some(数字下标)
}

/// 第 `i` 个字符的下一个字符是不是标识符字符。
fn 后是标识符字符(字: &[(usize, char)], 字符下标: usize) -> bool {
    字.get(字符下标 + 1).is_some_and(|(_, 字符)| 是否标识符字符(*字符))
}

/// 第 `i` 个字符的下一个字符是不是半角数字。
fn 后是数字(字: &[(usize, char)], 字符下标: usize) -> bool {
    字.get(字符下标 + 1).is_some_and(|(_, 字符)| 字符.is_ascii_digit())
}

/// 第 `k` 个字符的**终止字节偏移**（不含）。
fn 止于(字: &[(usize, char)], 字符下标: usize) -> u32 {
    偏(字[字符下标].0 + 字[字符下标].1.len_utf8())
}

/// `usize` → 区间用的 `u32`。上限 4 GiB 是形状自身的口径（`说明/语言面形状.md` §一）。
fn 偏(位: usize) -> u32 {
    位 as u32
}
