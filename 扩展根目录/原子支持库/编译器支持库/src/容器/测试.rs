/// 错误路径：不用 panic 表达格式错误。
#[test]
fn 反解错误路径() {
    assert_eq!(反解容器(&[]), Err(反解错误::魔数不符));
    assert_eq!(反解容器(b"NOTMAGIC"), Err(反解错误::魔数不符));
    // 魔数对但不足 44 字节 → 段头截断
    assert_eq!(
        反解容器(b"CNWTEPRG\x19\x73\x11\x15"),
        Err(反解错误::段头截断 { 字节位置: 8 })
    );

    // 段头标记不符：把 0x02 处的 0x1511 改掉
    let mut 坏件表 = Vec::new();
    坏件表.extend_from_slice(&文件头魔数);
    坏件表.extend_from_slice(&[0u8; 段头长度]);
    坏件表[8 + 0x02] = 0xFF;
    assert_eq!(反解容器(&坏件表), Err(反解错误::段头标记不符 { 字节位置: 8 }));

    // 段类型未知：合法段头但类型号写 99
    let 合法段 = 容器段 {
        段头字段: 段头 {
            校验和: 0,
            段类型: 段类型::用户信息.取号值(),
            名称区: [0; 27],
            段名: GBK用户信息段.to_vec(),
        },
        数据字节: vec![],
    };
    let mut 未知类型 = 生成容器字节(&容器 { 段表: vec![合法段] }).expect("生成应成功");
    未知类型[8 + 0x0B] = 99;
    assert_eq!(
        反解容器(&未知类型),
        Err(反解错误::段类型未知 { 字节位置: 8, 段号: 99 })
    );
}

