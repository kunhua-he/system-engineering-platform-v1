/// **唯一硬判据**：对语料里的容器文件，`生成(反解(原文))` 必须与原文逐字节相同。
///
/// 未设语料路径 ⇒ **显式未判**，不许算通过（审计附①）。
#[test]
fn 语料往返逐字节一致() {
    // 未设语料路径 ⇒ 显式未判且 **不许算通过**（原先「路径不存在就 return」报的是通过）。
    let Some(根目录) = 取语料根目录() else {
        println!("未设语料路径（{语料路径变量名}）⇒ 本测试未判，不许算通过");
        panic!("未判：未设语料路径（{语料路径变量名}）⇒ 本测试未判，不许算通过");
    };

    let mut 文件表 = Vec::new();
    收集语料(&根目录, &mut 文件表);
    文件表.sort();

    // 目录在、但一份 `.e`/`.ec` 都没收到 ⇒ **显式未判**，不许算通过（审计附①：空语料也是假绿）。
    assert!(
        !文件表.is_empty(),
        "语料目录 {根目录:?} 里一份 .e/.ec 都没收集到 ⇒ 本测试未判，不许算通过"
    );

    let mut 通过数: u64 = 0;
    let mut 段总数: u64 = 0;
    let mut 失败: Vec<String> = Vec::new();

    for 路径 in &文件表 {
        let 原文 = match std::fs::read(路径) {
            Ok(字节) => 字节,
            Err(错误) => {
                失败.push(format!("{} 读入失败：{错误}", 路径.display()));
                continue;
            }
        };
        match 反解容器(&原文) {
            Err(错误) => 失败.push(format!("{} 反解失败：{错误:?}", 路径.display())),
            Ok(容器) => match 生成容器字节(&容器) {
                Err(错误) => 失败.push(format!("{} 生成失败：{错误:?}", 路径.display())),
                Ok(产物) => {
                    段总数 += 容器.段表.len() as u64;
                    if 产物 == 原文 {
                        通过数 += 1;
                    } else {
                        let 字节偏移 = 首个不一致(&原文, &产物);
                        失败.push(format!(
                            "{} 往返不一致：首个不一致字节偏移 {字节偏移}，原文 {} 字节，产物 {} 字节",
                            路径.display(),
                            原文.len(),
                            产物.len()
                        ));
                    }
                }
            },
        }
    }

    println!(
        "语料往返实测：通过 {通过数} / 失败 {} / 共 {} 个文件；切出段记录 {段总数} 条",
        失败.len(),
        文件表.len()
    );
    for (序号, 失败样例) in 失败.iter().take(10).enumerate() {
        println!("  失败样例 {}：{失败样例}", 序号 + 1);
    }

    assert!(
        失败.is_empty(),
        "语料往返不一致：通过 {通过数}，失败 {}（共 {}）",
        失败.len(),
        文件表.len()
    );
}

/// 段头 44 字节逐字段布局：按实测口径造一条类型 2 段，核对每个字段位。
#[test]
fn 段头逐字段布局() {
    let 号段 = 容器段 {
        段头字段: 段头 {
            校验和: 0x0A06CD88,
            段类型: 段类型::系统信息.取号值(),
            名称区: [0; 27],
            段名: GBK系统信息段.to_vec(),
        },
        数据字节: vec![1, 0, 0, 0],
    };
    let 产物 = 生成容器字节(&容器 { 段表: vec![号段], ..Default::default() }).expect("生成应成功");

    assert_eq!(&产物[0..8], &文件头魔数);
    let 头部 = &产物[8..8 + 段头长度];
    assert_eq!(&头部[0x00..0x02], &[0x19, 0x73], "段头魔术 0x7319");
    assert_eq!(&头部[0x02..0x04], &[0x11, 0x15], "段头标记 0x1511");
    assert_eq!(&头部[0x04..0x08], &[0x88, 0xCD, 0x06, 0x0A], "校验值原样小端写回");
    assert_eq!(&头部[0x08..0x0C], &[0x19, 0x73, 0x00, 0x02], "类型标记 + 类型号");
    // 名称区：明文 系统信息段 + NUL + 补零，异或密钥 73 00 02 19
    assert_eq!(&头部[0x0C..0x0E], &[0xCF ^ 0x73, 0xB5], "系 的密文");
    assert_eq!(头部[0x0C + 10], 0x02, "NUL 终止位（异或后为 0x02）");
    assert_eq!(&头部[0x27..0x2C], &[0x19, 0x73, 0x00, 0x00, 0x00], "结束标记 + 尾标志 + 补零");
    assert_eq!(&产物[8 + 段头长度..], &[1, 0, 0, 0], "段数据紧随段头");
}

/// 名称区混淆：取证件样例「系统信息段」，密钥 73 00 02 19，相位锚段头起点。
#[test]
fn 名称区异或还原段名() {
    assert_eq!(名称区密钥(2), [0x73, 0x00, 0x02, 0x19]);
    assert_eq!(名称区密钥(255), [0x73, 0x00, 0xFF, 0x19]);

    let 名称 = GBK系统信息段;
    let 密文字节 = 编名称区(名称, 2, 0).expect("生成名称区");
    assert_eq!(解名称区(&密文字节, 2), 名称);
    // 首四字节密文即取证件所载 BC B5 CF AA 的同族结果（此处类型 2 与取证件一致）。
    assert_eq!(密文字节[0], 0xCF ^ 0x73);
    assert_eq!(密文字节[1], 0xB5);
    assert_eq!(密文字节[2], 0xCD ^ 0x02);
    assert_eq!(密文字节[3], 0xB3 ^ 0x19);
}

/// 类型 7（无名七）不写段名：名称区全零，且 0x27..0x2C 五字节全零。
