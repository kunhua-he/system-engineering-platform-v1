/// 错误路径：不用 panic 表达格式错误。
#[test]
fn 反解错误路径() {
    assert_eq!(反解容器(&[]), Err(反解错误::魔数不符));
    assert_eq!(反解容器(b"NOTMAGIC"), Err(反解错误::魔数不符));
    // 魔数对但不足 44 字节 → 段头截断
    assert_eq!(
        反解容器(b"CNWTEPRG\x19\x73\x11\x15"),
        Err(反解错误::段头截断 { 字节位置: 8 })
    );

    // 段头标记不符：把 0x02 处的 0x1511 改掉
    let mut 坏件表 = Vec::new();
    坏件表.extend_from_slice(&文件头魔数);
    坏件表.extend_from_slice(&[0u8; 段头长度]);
    坏件表[8 + 0x02] = 0xFF;
    assert_eq!(反解容器(&坏件表), Err(反解错误::段头标记不符 { 字节位置: 8 }));

    // 段类型未知：合法段头但类型号写 99
    let 合法段 = 容器段 {
        段头字段: 段头 {
            校验和: 0,
            段类型: 段类型::用户信息.取号值(),
            名称区: [0; 27],
            段名: GBK用户信息段.to_vec(),
        },
        数据字节: vec![],
    };
    let mut 未知类型 = 生成容器字节(&容器 { 段表: vec![合法段.clone()], ..Default::default() }).expect("生成应成功");
    未知类型[8 + 0x0B] = 99;
    // A21：互操作路对未知段类型号**放行**（跳过并保留），由 `容器::未知段号表` 报出（不静默丢）。
    let 反解未知 = 反解容器(&未知类型).expect("未知段类型号必须放行（格式向前演进）");
    assert_eq!(反解未知.段表.len(), 1);
    assert_eq!(反解未知.未知段号表, vec![99], "未知段号必须报出");
    assert_eq!(生成容器字节(&反解未知).expect("再生成"), 未知类型, "未知段仍必须逐字节往返");

    // 越界仍 fail-closed：号 `0` 仍拒（不是「一切未知都放行」）。
    let mut 越界号 = 生成容器字节(&容器 { 段表: vec![合法段.clone()], ..Default::default() }).expect("生成应成功");
    越界号[8 + 0x0B] = 0;
    assert_eq!(
        反解容器(&越界号),
        Err(反解错误::段类型未知 { 字节位置: 8, 段号: 0 })
    );
}

/// **缺段容忍**（A25）：段集合随版本变化，读方不得要求必备段。
///
/// 样本构造按易语言侧实测的两种段序：
/// 旧版本段集（无 15 段）· 新版本段集（含 15 段）。两份都必须逐字节往返
/// ⇒ 谁给反解加「必备段」校验，这条当场红。
#[test]
fn 旧版本段集与新版本段集都可逐字节往返() {
    let 旧版本号表 = [2u8, 1, 4, 3, 8, 12, 11, 5, 9, 10, 7];
    let 新版本号表 = [2u8, 1, 4, 3, 13, 8, 12, 15, 11, 5, 9, 10, 7];
    for 号表 in [&旧版本号表[..], &新版本号表[..]] {
        let 段表: Vec<容器段> = 号表
            .iter()
            .map(|&号值| 容器段 {
                段头字段: 段头 {
                    校验和: 0,
                    段类型: 号值,
                    名称区: [0; 27],
                    // 类型 7（号表里有它）必须空段名＋全零名称区，其余用任意非空段名。
                    段名: if 号值 == 段类型::无名七.取号值() { Vec::new() } else { vec![0x41] },
                },
                数据字节: vec![号值; 3],
            })
            .collect();
        let 原文 = 生成容器字节(&容器 { 段表, ..Default::default() }).expect("生成应成功");
        let 反解 = 反解容器(&原文).expect("缺段产物必须反解得开（不得要求必备段）");
        assert_eq!(反解.段表.len(), 号表.len(), "段数不塔");
        assert_eq!(生成容器字节(&反解).expect("再生成"), 原文, "缺段产物必须逐字节往返");
    }
}

/// **A23 嵌套识别（保守档）**：段数据里混一个尾标志为 `0x02` 的完整段 ⇒ 只报不改。
///
/// 段边界不变、往返逐字节；`嵌套段表` 报出嵌套段头偏移。无嵌套的容器则 `嵌套段表` 为空
///（证明判据在干活，不是恒报）。
#[test]
fn 嵌套段只报不改() {
    let 内层段 = 容器段 {
        段头字段: 段头 {
            校验和: 0,
            段类型: 段类型::用户信息.取号值(),
            名称区: [0; 27],
            段名: vec![0x41],
        },
        数据字节: vec![7, 7, 7],
    };
    let 内层字节 = 生成容器字节(&容器 { 段表: vec![内层段.clone()], ..Default::default() }).expect("生成内层");
    // 内层段头在 `内层字节[8..]`；把尾标志（段头偏移 0x2A）从 `0x00` 改成 `0x02`。
    let mut 内层头 = 内层字节[8..8 + 段头长度].to_vec();
    内层头[0x2A] = 0x02;
    let 外层段 = 容器段 {
        段头字段: 段头 {
            校验和: 0,
            段类型: 段类型::系统信息.取号值(),
            名称区: [0; 27],
            段名: vec![0x42],
        },
        数据字节: [内层头.as_slice(), &[7, 7, 7]].concat(),
    };
    let 外层字节 = 生成容器字节(&容器 { 段表: vec![外层段], ..Default::default() }).expect("生成外层");
    let 反解 = 反解容器(&外层字节).expect("嵌套段必须仍能反解（保守档不改边界）");
    assert_eq!(反解.段表.len(), 1, "段边界不变（内层段不单独切出）");
    assert!(!反解.嵌套段表.is_empty(), "嵌套段必须被报出");
    assert_eq!(生成容器字节(&反解).expect("再生成"), 外层字节, "嵌套样本仍必须逐字节往返");

    let 平常件 = 生成容器字节(&容器 { 段表: vec![内层段], ..Default::default() }).expect("生成");
    let 平常反解 = 反解容器(&平常件).expect("反解");
    assert!(平常反解.嵌套段表.is_empty(), "无嵌套时不得报告");
}

/// **A24 漏切自证（只报不改）**：互证各配一个反向样本，且默认档不 fail-closed。
#[test]
fn 自检异常只报不改() {
    let 干净段 = 容器段 {
        段头字段: 段头 {
            校验和: 0,
            段类型: 段类型::系统信息.取号值(),
            名称区: [0; 27],
            段名: vec![0x41],
        },
        数据字节: vec![1, 2, 3, 4],
    };
    let 干净件 = 生成容器字节(&容器 { 段表: vec![干净段], ..Default::default() }).expect("生成");
    let 干净反解 = 反解容器(&干净件).expect("反解");
    assert!(干净反解.自检异常表.is_empty(), "干净件不得报异常");

    // 反向样本一：段表长度与字节不符 ⇒ 文件大小恒等式不成立。
    // ★ 这一支**不能**经 `反解容器` 造：末段直抵文件尾 ⇒ 恒等式在扫描器下恒成立，
    //   只对「段表由别处构造」的调用（如结构编码解码）才可能不成立，故直接调自检函数验它。
    let 截短字节 = &干净件[..干净件.len() - 3];
    let 异常表 = super::自检::自检段链(截短字节, &干净反解.段表);
    assert!(
        异常表.iter().any(|异常| matches!(异常, 自检异常::文件大小恒等式不成立 { .. })),
        "段表与字节长度不符必须报到「文件大小恒等式不成立」"
    );

    // 反向样本二：把段头校验槽改一个字节 ⇒ 报到「段头校验不符」。
    let mut 坏校验 = 干净件.clone();
    坏校验[8 + 0x04] ^= 0xFF;
    let 坏校验反解 = 反解容器(&坏校验).expect("只报不改：校验不符仍须反解成功");
    assert!(
        坏校验反解.自检异常表.iter().any(|异常| matches!(异常, 自检异常::段头校验不符 { .. })),
        "改校验槽必须报到「段头校验不符」"
    );
}

