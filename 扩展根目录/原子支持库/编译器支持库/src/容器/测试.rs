/// 语料根目录。不存在时往返测试跳过（不失败）。
const 语料根目录: &str = "/tmp/易语言源码";

// 容器里的段名是 **GBK** 字节（不是 UTF-8），而字节串字面量放不下非 ASCII 字符，
// 故这里直接写出实测得到的 GBK 字节。
const GBK系统信息段: &[u8] = &[0xCF, 0xB5, 0xCD, 0xB3, 0xD0, 0xC5, 0xCF, 0xA2, 0xB6, 0xCE];
const GBK用户信息段: &[u8] = &[0xD3, 0xC3, 0xBB, 0xA7, 0xD0, 0xC5, 0xCF, 0xA2, 0xB6, 0xCE];
const GBK程序加固段: &[u8] = &[0xB3, 0xCC, 0xD0, 0xF2, 0xBC, 0xD3, 0xB9, 0xCC, 0xB6, 0xCE];

fn 首个不一致(原文: &[u8], 产物: &[u8]) -> u64 {
    let 上限 = 原文.len().min(产物.len());
    for 位 in 0..上限 {
        if 原文[位] != 产物[位] {
            return 位 as u64;
        }
    }
    上限 as u64
}

/// 大小写不敏感地认 `.e` / `.ec`。
fn 是语料文件(路径: &Path) -> bool {
    match 路径.extension().and_then(|扩展| 扩展.to_str()) {
        Some(扩展) => {
            let 小写 = 扩展.to_ascii_lowercase();
            小写 == "e" || 小写 == "ec"
        }
        None => false,
    }
}

/// 递归收集语料。用 `file_type()` 不追符号链接，避免环。
fn 收集语料(根目录: &Path, 输出缓冲: &mut Vec<PathBuf>) {
    let Ok(项集) = std::fs::read_dir(根目录) else {
        return;
    };
    for 项 in 项集.flatten() {
        let Ok(类型) = 项.file_type() else { continue };
        let 路 = 项.path();
        if 类型.is_dir() {
            收集语料(&路, 输出缓冲);
        } else if 类型.is_file() && 是语料文件(&路) {
            输出缓冲.push(路);
        }
    }
}

/// **唯一硬判据**：对语料里的容器文件，`生成(反解(原文))` 必须与原文逐字节相同。
///
/// 语料不存在时跳过（`return`），不算失败。
#[test]
fn 语料往返逐字节一致() {
    let 根 = Path::new(语料根目录);
    if !根.exists() {
        println!("语料目录不存在，跳过往返测试：{语料根目录}");
        return;
    }

    let mut 文件表 = Vec::new();
    收集语料(根, &mut 文件表);
    文件表.sort();

    let mut 通过数: u64 = 0;
    let mut 段总数: u64 = 0;
    let mut 失败: Vec<String> = Vec::new();

    for 路 in &文件表 {
        let 原文 = match std::fs::read(路) {
            Ok(字节) => 字节,
            Err(错) => {
                失败.push(format!("{} 读入失败：{错}", 路.display()));
                continue;
            }
        };
        match 反解(&原文) {
            Err(错) => 失败.push(format!("{} 反解失败：{错:?}", 路.display())),
            Ok(容) => match 生成(&容) {
                Err(错) => 失败.push(format!("{} 生成失败：{错:?}", 路.display())),
                Ok(产物) => {
                    段总数 += 容.段表.len() as u64;
                    if 产物 == 原文 {
                        通过数 += 1;
                    } else {
                        let 偏移 = 首个不一致(&原文, &产物);
                        失败.push(format!(
                            "{} 往返不一致：首个不一致字节偏移 {偏移}，原文 {} 字节，产物 {} 字节",
                            路.display(),
                            原文.len(),
                            产物.len()
                        ));
                    }
                }
            },
        }
    }

    println!(
        "语料往返实测：通过 {通过数} / 失败 {} / 共 {} 个文件；切出段记录 {段总数} 条",
        失败.len(),
        文件表.len()
    );
    for (序, 条) in 失败.iter().take(10).enumerate() {
        println!("  失败样例 {}：{条}", 序 + 1);
    }

    assert!(
        失败.is_empty(),
        "语料往返不一致：通过 {通过数}，失败 {}（共 {}）",
        失败.len(),
        文件表.len()
    );
}

/// 段头 44 字节逐字段布局：按实测口径造一条类型 2 段，核对每个字段位。
#[test]
fn 段头逐字段布局() {
    let 段 = 容器段 {
        头: 段头 {
            校验和: 0x0A06CD88,
            段类型: 段类型::系统信息.取号值(),
            名称区: [0; 27],
            段名: GBK系统信息段.to_vec(),
        },
        数据: vec![1, 0, 0, 0],
    };
    let 产物 = 生成(&容器 { 段表: vec![段] }).expect("生成应成功");

    assert_eq!(&产物[0..8], &魔数);
    let 头 = &产物[8..8 + 段头长度];
    assert_eq!(&头[0x00..0x02], &[0x19, 0x73], "段头魔术 0x7319");
    assert_eq!(&头[0x02..0x04], &[0x11, 0x15], "段头标记 0x1511");
    assert_eq!(&头[0x04..0x08], &[0x88, 0xCD, 0x06, 0x0A], "校验值原样小端写回");
    assert_eq!(&头[0x08..0x0C], &[0x19, 0x73, 0x00, 0x02], "类型标记 + 类型号");
    // 名称区：明文 系统信息段 + NUL + 补零，异或密钥 73 00 02 19
    assert_eq!(&头[0x0C..0x0E], &[0xCF ^ 0x73, 0xB5], "系 的密文");
    assert_eq!(头[0x0C + 10], 0x02, "NUL 终止位（异或后为 0x02）");
    assert_eq!(&头[0x27..0x2C], &[0x19, 0x73, 0x00, 0x00, 0x00], "结束标记 + 尾标志 + 补零");
    assert_eq!(&产物[8 + 段头长度..], &[1, 0, 0, 0], "段数据紧随段头");
}

/// 名称区混淆：取证件样例「系统信息段」，密钥 73 00 02 19，相位锚段头起点。
#[test]
fn 名称区异或还原段名() {
    assert_eq!(名称区密钥(2), [0x73, 0x00, 0x02, 0x19]);
    assert_eq!(名称区密钥(255), [0x73, 0x00, 0xFF, 0x19]);

    let 名 = GBK系统信息段;
    let 密文 = 编名称区(名, 2, 0).expect("生成名称区");
    assert_eq!(解名称区(&密文, 2), 名);
    // 首四字节密文即取证件所载 BC B5 CF AA 的同族结果（此处类型 2 与取证件一致）。
    assert_eq!(密文[0], 0xCF ^ 0x73);
    assert_eq!(密文[1], 0xB5);
    assert_eq!(密文[2], 0xCD ^ 0x02);
    assert_eq!(密文[3], 0xB3 ^ 0x19);
}

/// 类型 7（无名七）不写段名：名称区全零，且 0x27..0x2C 五字节全零。
#[test]
fn 类型七不写段名且尾五字节全零() {
    let 段 = 容器段 {
        头: 段头 {
            校验和: 0,
            段类型: 段类型::无名七.取号值(),
            名称区: [0; 27],
            段名: Vec::new(),
        },
        数据: vec![],
    };
    let 产物 = 生成(&容器 { 段表: vec![段] }).expect("生成应成功");
    let 头 = &产物[8..8 + 段头长度];
    assert!(头[0x0C..0x2C].iter().all(|&字节| 字节 == 0), "类型 7 的 0x0C..0x2C 应全零");

    // 反解回来：名称区全零 → 段名为空，且整体往返一致。
    let 回 = 反解(&产物).expect("反解应成功");
    assert_eq!(回.段表.len(), 1);
    assert!(回.段表[0].头.段名.is_empty(), "类型 7 段名应为空");
    assert_eq!(生成(&回).expect("再生成"), 产物);
}

