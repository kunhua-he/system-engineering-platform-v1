/// 错误路径：不用 panic 表达格式错误。
#[test]
fn 反解错误路径() {
    assert_eq!(反解(&[]), Err(反解错误::魔数不符));
    assert_eq!(反解(b"NOTMAGIC"), Err(反解错误::魔数不符));
    // 魔数对但不足 44 字节 → 段头截断
    assert_eq!(
        反解(b"CNWTEPRG\x19\x73\x11\x15"),
        Err(反解错误::段头截断 { 位置: 8 })
    );

    // 段头标记不符：把 0x02 处的 0x1511 改掉
    let mut 坏 = Vec::new();
    坏.extend_from_slice(&魔数);
    坏.extend_from_slice(&[0u8; 段头长度]);
    坏[8 + 0x02] = 0xFF;
    assert_eq!(反解(&坏), Err(反解错误::段头标记不符 { 位置: 8 }));

    // 段类型未知：合法段头但类型号写 99
    let 合法段 = 容器段 {
        头: 段头 {
            校验和: 0,
            段类型: 段类型::用户信息.取号值(),
            名称区: [0; 27],
            段名: GBK用户信息段.to_vec(),
        },
        数据: vec![],
    };
    let mut 未知类型 = 生成(&容器 { 段表: vec![合法段] }).expect("生成应成功");
    未知类型[8 + 0x0B] = 99;
    assert_eq!(
        反解(&未知类型),
        Err(反解错误::段类型未知 { 位置: 8, 号: 99 })
    );
}

