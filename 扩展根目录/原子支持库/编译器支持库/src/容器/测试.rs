// 容器里的段名是 **GBK** 字节（不是 UTF-8），而字节串字面量放不下非 ASCII 字符，
// 故这里直接写出实测得到的 GBK 字节。
const GBK系统信息段: &[u8] = &[0xCF, 0xB5, 0xCD, 0xB3, 0xD0, 0xC5, 0xCF, 0xA2, 0xB6, 0xCE];
