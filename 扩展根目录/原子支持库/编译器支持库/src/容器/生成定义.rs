//! 生成 —— 结构 → 容器字节。
//!
//! 源出 `容器.rs` 第 221–234 行（`生成`）与第 326–351 行（`写段头`），**逐字搬家**。
//!
//! **必须与反解件构成往返一致**（模块注释：往返一致是 1:1 复刻的唯一硬判据）。
//! 段名 → 名称区那一步（`编名称区`）与它的逆运算 `解名称区` 同住 `名称区.rs`。

use super::名称区::{名称区容量, 编名称区};
use super::形状::{
    段头, 段头偏移, 段头长度, 段类型, 容器, 生成错误, 魔数, 魔术乙字节, 魔术甲字节,
};

/// 生成：结构 → 容器字节。**必须与 `反解` 构成往返一致**。
pub fn 生成(容器: &容器) -> Result<Vec<u8>, 生成错误> {
    let 预估 = 魔数.len()
        + 容器.段表.len().saturating_mul(段头长度)
        + 容器.段表.iter().map(|段| 段.数据.len()).sum::<usize>();
    let mut 出 = Vec::with_capacity(预估);
    出.extend_from_slice(&魔数);
    for (序号, 段) in 容器.段表.iter().enumerate() {
        let 第几段 = u32::try_from(序号).unwrap_or(u32::MAX);
        出.extend_from_slice(&写段头(&段.头, 第几段)?);
        出.extend_from_slice(&段.数据);
    }
    Ok(出)
}

/// 写段头 44 字节。
fn 写段头(头: &段头, 第几段: u32) -> Result<[u8; 段头长度], 生成错误> {
    let 号 = 头.段类型;
    let mut 出 = [0u8; 段头长度];

    出[段头偏移::魔术甲..段头偏移::魔术甲 + 2].copy_from_slice(&魔术甲字节);
    出[段头偏移::魔术乙..段头偏移::魔术乙 + 2].copy_from_slice(&魔术乙字节);
    出[段头偏移::校验和..段头偏移::校验和 + 4].copy_from_slice(&头.校验和.to_le_bytes());
    出[段头偏移::类型标记..段头偏移::类型标记 + 2].copy_from_slice(&魔术甲字节);
    出[段头偏移::类型标记 + 2] = 0x00;
    出[段头偏移::类型标记 + 3] = 号;

    let 名称区 = 编名称区(&头.段名, 号, 第几段)?;
    出[段头偏移::名称区..段头偏移::名称区 + 名称区容量].copy_from_slice(&名称区);

    if 号 == 段类型::无名七.号() {
        // 类型 7：0x27..0x2C 五字节全零（实测 1456/1456），不写结束标记与尾标志。
    } else {
        出[段头偏移::结束标记..段头偏移::结束标记 + 2].copy_from_slice(&魔术甲字节);
        出[段头偏移::结束标记 + 2] = 0x00;
        出[段头偏移::尾标志] = if 号 == 段类型::程序加固.号() { 0x03 } else { 0x00 };
        出[段头偏移::补零] = 0x00;
    }

    Ok(出)
}
