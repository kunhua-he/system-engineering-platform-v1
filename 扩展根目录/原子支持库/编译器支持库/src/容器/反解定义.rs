//! 反解 —— 容器字节 → 结构。
//!
//! 源出 `容器.rs` 第 186–219 行（`反解`）与第 241–324 行（`是段头起点` ·
//! `段头尾部合规` · `找下一段头` · `解析段头`），**逐字搬家**。
//!
//! 这四个私有函数留在这里而不是拆到别处：`是段头起点` 与 `解析段头` **共用同一套判据**
//! （模块注释的硬要求：「扫描与解析共用同一套判据，避免两套知识」）。
//!
//! 成功即保证 `生成(反解(字节)) == 字节`：段头判据已含结束标记与尾标志，
//! 任何无法被逐字节写回的段头都会在反解阶段被拒。

use super::名称区::{名称区容量, 解名称区};
use super::形状::{
    反解错误, 容器, 容器段, 段头, 段头偏移, 段头长度, 段类型, 文件头魔数, 魔术次字节, 魔术首字节,
};
use super::自检::自检段链;

/// 反解：容器字节 → 结构。
///
/// 成功即保证 `生成(反解(字节)) == 字节`：段头判据已含结束标记与尾标志，
/// 任何无法被逐字节写回的段头都会在反解阶段被拒。
pub fn 反解容器(字节: &[u8]) -> Result<容器, 反解错误> {
    if 字节.len() < 文件头魔数.len() || 字节[..文件头魔数.len()] != 文件头魔数 {
        return Err(反解错误::魔数不符);
    }

    let mut 段表 = Vec::new();
    let mut 未知段号表 = Vec::new();
    let mut 读游标 = 文件头魔数.len();

    // 空容器（仅魔数）合法：不进入循环，段表为空。
    while 读游标 < 字节.len() {
        if 字节.len() - 读游标 < 段头长度 {
            return Err(反解错误::段头截断 { 字节位置: 读游标 as u64 });
        }
        let 头部 = 解析段头(字节, 读游标)?;
        let 数据起点 = 读游标 + 段头长度;
        // 段边界只能靠扫描：本格式无段长字段（见模块注释）。
        let 下一段头 = 找下一段头(字节, 数据起点);
        let 数据尾 = 下一段头.unwrap_or(字节.len());
        // 未知段类型号**不静默丢**：号以 u8 原值保留在段表里，并列进未知段号表（见 A21）。
        if !段类型::是已登记号(头部.段类型) && !未知段号表.contains(&头部.段类型) {
            未知段号表.push(头部.段类型);
        }
        段表.push(容器段 {
            段头字段: 头部,
            数据字节: 字节[数据起点..数据尾].to_vec(),
        });
        match 下一段头 {
            Some(下一段位置) => 读游标 = 下一段位置,
            None => break,
        }
    }

    // 段边界只靠扫描（见模块注释）；扫描自证四条（**只报不改**，默认不 fail-closed）：
    //   ① 段头 `+0x04` 校验槽与复算不符；② 段数据头 `+0x00` 段序号不连号；
    //   ③ 段数据头 `+0x0C` 体长与实长不符；④ 文件大小恒等式不成立。
    // 默认只把不合之处记进 `容器::自检异常表`（不 fail-closed：参照实现自身在精易 V12.1.1.ec
    // 上就漏切一处，fail-closed 会把 1444/1444 往返测试打红）；严格档由调用方按需取用。
    let 自检异常表 = 自检段链(字节, &段表);
    let 嵌套段表 = 扫嵌套段(&段表);
    Ok(容器 { 段表, 未知段号表, 嵌套段表, 自检异常表 })
}

/// 在各段数据里搜「被吞的嵌套段头尾」（`19 73 00 02 00`）⇒ 嵌套段头的字节偏移表。
///
/// **只报不改**：段边界不变、往返不受影响（易语言侧取证「段里可套段」，保守档）。
fn 扫嵌套段(段表: &[容器段]) -> Vec<u64> {
    let mut 位置表 = Vec::new();
    let mut 段起点 = 文件头魔数.len();
    for 号段 in 段表 {
        let 数据起点 = 段起点 + 段头长度;
        let 段数据字节 = &号段.数据字节;
        let mut 读游标 = 0usize;
        while 读游标 + 5 <= 段数据字节.len() {
            if 尾部是嵌套段尾(&段数据字节[读游标..读游标 + 5]) {
                // 尾标志在段头偏移 `0x2A`、结束标记在 `0x27` ⇒ 嵌套段头起点 = 命中位置 − 0x27。
                // 命中位置不足 `0x27` 时取 0（不可能是一个完整嵌套段头，如实报在段数据起点）。
                let 嵌套段头 = 数据起点 as u64 + 读游标.saturating_sub(段头偏移::结束标记) as u64;
                位置表.push(嵌套段头);
            }
            读游标 += 1;
        }
        段起点 = 数据起点 + 段数据字节.len();
    }
    位置表
}

/// 段头结构是否成立（含结束标记与尾标志）。扫描与解析共用同一套判据，避免两套知识。
fn 是段头起点(字节: &[u8], 读游标: usize) -> bool {
    if 读游标 + 段头长度 > 字节.len() {
        return false;
    }
    let 头部 = &字节[读游标..读游标 + 段头长度];
    if 头部[段头偏移::魔术首..段头偏移::魔术首 + 2] != 魔术首字节 {
        return false;
    }
    if 头部[段头偏移::魔术次..段头偏移::魔术次 + 2] != 魔术次字节 {
        return false;
    }
    if 头部[段头偏移::类型标记..段头偏移::类型标记 + 2] != 魔术首字节 {
        return false;
    }
    if 头部[段头偏移::类型标记 + 2] != 0x00 {
        return false;
    }
    let 号值 = 头部[段头偏移::类型标记 + 3];
    // 未知类型号**也**是合法段头起点（跳过语义）：判否会让未知段被并进前一段、边界改判。
    // 只拒号 `0`（越界），未知号照旧按尾部五字节合规定边界。
    if 号值 == 0 {
        return false;
    }
    段头尾部合规(号值, &头部[段头偏移::结束标记..段头偏移::补零 + 1])
}

/// 段头 0x27..0x2C 五字节是否合规。**类型 7 全零**（实测 1456/1456），其余写结束标记 + 尾标志。
///
/// 尾标志取值（易语言侧实测）：普通段 `0x00` · 类型 255 加固段 `0x03` ·
/// **被吞的嵌套段 `0x02`**。参照实现判「是不是段头」时对类型 255 只认 `0x03`，故尾标志为 `0x02`
/// 的嵌套段被判否、未切出、并入前一段（精易模块 V12.1.1.ec 段 4 就是这么虚胖的）。
/// 本函数**照旧只认已实测的尾标志**（认宽会让段边界改判、破 1444/1444 往返）；
/// 嵌套段由 `容器::嵌套段表` 另行报出，不改本函数的判定。
fn 段头尾部合规(号值: u8, 尾部: &[u8]) -> bool {
    debug_assert_eq!(尾部.len(), 5);
    if 号值 == 段类型::无名七.取号值() {
        尾部 == [0x00, 0x00, 0x00, 0x00, 0x00]
    } else if 号值 == 段类型::程序加固.取号值() {
        尾部 == [0x19, 0x73, 0x00, 0x03, 0x00]
    } else {
        尾部 == [0x19, 0x73, 0x00, 0x00, 0x00]
    }
}

/// 尾部五字节是不是**被吞的嵌套段**的段头尾（`19 73 00 02 00`）。
///
/// 用于「识别 + 报告」：`反解容器` 段表切齐之后，在各段数据里搜 `19 73 00 02 00`，
/// 命中即说明该段数据里混着一整个段（参照实现的漏切），记进 `容器::嵌套段表`。
/// **不改段边界、不改往返**——只是把「读不懂这件事」变成「读得懂但如实报出」。
pub(super) fn 尾部是嵌套段尾(尾部: &[u8]) -> bool {
    debug_assert_eq!(尾部.len(), 5);
    尾部 == [0x19, 0x73, 0x00, 0x02, 0x00]
}

/// 从 `起点` 起向后找下一处段头起点。
fn 找下一段头(字节: &[u8], 起点: usize) -> Option<usize> {
    if 字节.len() < 段头长度 {
        return None;
    }
    let 尾部 = 字节.len() - 段头长度;
    (起点..=尾部).find(|&读游标| 是段头起点(字节, 读游标))
}

/// 解析 `位置` 处的段头。判据与 `是段头起点` 完全一致，只是额外给出结构化错误段位。
fn 解析段头(字节: &[u8], 读游标: usize) -> Result<段头, 反解错误> {
    if 读游标 + 段头长度 > 字节.len() {
        return Err(反解错误::段头截断 { 字节位置: 读游标 as u64 });
    }
    let 头部 = &字节[读游标..读游标 + 段头长度];
    let 标记对不上 = 头部[段头偏移::魔术首..段头偏移::魔术首 + 2] != 魔术首字节
        || 头部[段头偏移::魔术次..段头偏移::魔术次 + 2] != 魔术次字节
        || 头部[段头偏移::类型标记..段头偏移::类型标记 + 2] != 魔术首字节
        || 头部[段头偏移::类型标记 + 2] != 0x00;
    if 标记对不上 {
        return Err(反解错误::段头标记不符 { 字节位置: 读游标 as u64 });
    }

    let 号值 = 头部[段头偏移::类型标记 + 3];
    // 未知段类型号**不 fail-closed**：参照实现的读段分派对未匹配类型是「跳过并继续」
    // （报错串 `发现不可识别的%s，其数据已被跳过!`，VA 0x6618B8）—— 这是格式可向前演进的机制。
    // 未知号照旧往后扫描段边界，整段原样搬进 `容器段`，由 `容器::未知段号表` 显式报出（不静默丢）。
    // 越界仍 fail-closed：号 `0` 与段头尾部五字节不成立的两处仍然拒。
    if 号值 == 0 {
        return Err(反解错误::段类型未知 { 字节位置: 读游标 as u64, 段号: 号值 });
    }
    if !段头尾部合规(号值, &头部[段头偏移::结束标记..段头偏移::补零 + 1]) {
        return Err(反解错误::段头标记不符 { 字节位置: 读游标 as u64 });
    }

    let 校验和 = u32::from_le_bytes([
        头部[段头偏移::校验和],
        头部[段头偏移::校验和 + 1],
        头部[段头偏移::校验和 + 2],
        头部[段头偏移::校验和 + 3],
    ]);
    let mut 名称区 = [0u8; 名称区容量];
    名称区.copy_from_slice(&头部[段头偏移::名称区..段头偏移::名称区 + 名称区容量]);

    Ok(段头 {
        校验和,
        段类型: 号值,
        段名: 解名称区(&名称区, 号值),
        名称区,
    })
}
