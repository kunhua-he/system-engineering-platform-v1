//! 反解 —— 容器字节 → 结构。
//!
//! 源出 `容器.rs` 第 186–219 行（`反解`）与第 241–324 行（`是段头起点` ·
//! `段头尾部合规` · `找下一段头` · `解析段头`），**逐字搬家**。
//!
//! 这四个私有函数留在这里而不是拆到别处：`是段头起点` 与 `解析段头` **共用同一套判据**
//! （模块注释的硬要求：「扫描与解析共用同一套判据，避免两套知识」）。
//!
//! 成功即保证 `生成(反解(字节)) == 字节`：段头判据已含结束标记与尾标志，
//! 任何无法被逐字节写回的段头都会在反解阶段被拒。

use super::名称区::{名称区容量, 解名称区};
use super::形状::{
    反解错误, 容器, 容器段, 段头, 段头偏移, 段头长度, 段类型, 魔数, 魔术次字节, 魔术首字节,
};

/// 反解：容器字节 → 结构。
///
/// 成功即保证 `生成(反解(字节)) == 字节`：段头判据已含结束标记与尾标志，
/// 任何无法被逐字节写回的段头都会在反解阶段被拒。
pub fn 反解(字节: &[u8]) -> Result<容器, 反解错误> {
    if 字节.len() < 魔数.len() || 字节[..魔数.len()] != 魔数 {
        return Err(反解错误::魔数不符);
    }

    let mut 段表 = Vec::new();
    let mut 位置 = 魔数.len();

    // 空容器（仅魔数）合法：不进入循环，段表为空。
    while 位置 < 字节.len() {
        if 字节.len() - 位置 < 段头长度 {
            return Err(反解错误::段头截断 { 位置: 位置 as u64 });
        }
        let 头 = 解析段头(字节, 位置)?;
        let 数据起点 = 位置 + 段头长度;
        // 段边界只能靠扫描：本格式无段长字段（见模块注释）。
        let 下一段头 = 找下一段头(字节, 数据起点);
        let 数据尾 = 下一段头.unwrap_or(字节.len());
        段表.push(容器段 {
            头,
            数据: 字节[数据起点..数据尾].to_vec(),
        });
        match 下一段头 {
            Some(下) => 位置 = 下,
            None => break,
        }
    }

    Ok(容器 { 段表 })
}

/// 段头结构是否成立（含结束标记与尾标志）。扫描与解析共用同一套判据，避免两套知识。
fn 是段头起点(字节: &[u8], 位置: usize) -> bool {
    if 位置 + 段头长度 > 字节.len() {
        return false;
    }
    let 头 = &字节[位置..位置 + 段头长度];
    if 头[段头偏移::魔术首..段头偏移::魔术首 + 2] != 魔术首字节 {
        return false;
    }
    if 头[段头偏移::魔术次..段头偏移::魔术次 + 2] != 魔术次字节 {
        return false;
    }
    if 头[段头偏移::类型标记..段头偏移::类型标记 + 2] != 魔术首字节 {
        return false;
    }
    if 头[段头偏移::类型标记 + 2] != 0x00 {
        return false;
    }
    let 号 = 头[段头偏移::类型标记 + 3];
    if 段类型::自号(号).is_none() {
        return false;
    }
    段头尾部合规(号, &头[段头偏移::结束标记..段头偏移::补零 + 1])
}

/// 段头 0x27..0x2C 五字节是否合规。**类型 7 全零**（实测 1456/1456），其余写结束标记 + 尾标志。
fn 段头尾部合规(号: u8, 尾: &[u8]) -> bool {
    debug_assert_eq!(尾.len(), 5);
    if 号 == 段类型::无名七.取号值() {
        尾 == [0x00, 0x00, 0x00, 0x00, 0x00]
    } else if 号 == 段类型::程序加固.取号值() {
        尾 == [0x19, 0x73, 0x00, 0x03, 0x00]
    } else {
        尾 == [0x19, 0x73, 0x00, 0x00, 0x00]
    }
}

/// 从 `起点` 起向后找下一处段头起点。
fn 找下一段头(字节: &[u8], 起点: usize) -> Option<usize> {
    if 字节.len() < 段头长度 {
        return None;
    }
    let 末 = 字节.len() - 段头长度;
    (起点..=末).find(|&位置| 是段头起点(字节, 位置))
}

/// 解析 `位置` 处的段头。判据与 `是段头起点` 完全一致，只是额外给出结构化错误段位。
fn 解析段头(字节: &[u8], 位置: usize) -> Result<段头, 反解错误> {
    if 位置 + 段头长度 > 字节.len() {
        return Err(反解错误::段头截断 { 位置: 位置 as u64 });
    }
    let 头 = &字节[位置..位置 + 段头长度];
    let 标记对不上 = 头[段头偏移::魔术首..段头偏移::魔术首 + 2] != 魔术首字节
        || 头[段头偏移::魔术次..段头偏移::魔术次 + 2] != 魔术次字节
        || 头[段头偏移::类型标记..段头偏移::类型标记 + 2] != 魔术首字节
        || 头[段头偏移::类型标记 + 2] != 0x00;
    if 标记对不上 {
        return Err(反解错误::段头标记不符 { 位置: 位置 as u64 });
    }

    let 号 = 头[段头偏移::类型标记 + 3];
    if 段类型::自号(号).is_none() {
        return Err(反解错误::段类型未知 { 位置: 位置 as u64, 号 });
    }
    if !段头尾部合规(号, &头[段头偏移::结束标记..段头偏移::补零 + 1]) {
        return Err(反解错误::段头标记不符 { 位置: 位置 as u64 });
    }

    let 校验和 = u32::from_le_bytes([
        头[段头偏移::校验和],
        头[段头偏移::校验和 + 1],
        头[段头偏移::校验和 + 2],
        头[段头偏移::校验和 + 3],
    ]);
    let mut 名称区 = [0u8; 名称区容量];
    名称区.copy_from_slice(&头[段头偏移::名称区..段头偏移::名称区 + 名称区容量]);

    Ok(段头 {
        校验和,
        段类型: 号,
        段名: 解名称区(&名称区, 号),
        名称区,
    })
}
