//! 自检 —— 段链切齐之后的**漏切自证**与**校验槽复算**（**只报不改**）。
//!
//! 段边界只靠扫描（本格式无段长字段，见 `容器.rs` 模块注释）⇒ 扫描本身**无法自证**有没有漏切。
//! 本件拿盘面上**独立可读**的读数与扫描结果互证（易语言侧取证「加固项：漏切自证」）：
//!   ① 段头 `+0x04` 校验槽与 `算段头校验` 复算值不符；
//!   ② 段数据头 `+0x00` 的 u32 段序号（1 基）从 1 起连号 —— 缺号即漏切；
//!   ③ 段数据头 `+0x0C` 的 u32 体长 == 「段数据长 − 56」；
//!   ④ `8 + Σ(44 + 段数据长) == 文件大小`（恒等式）。
//! ★ ②③ 只对**程序段（类型 3）**成立 —— 段数据头只有那一种段的开头有实测形状（56 字节），
//!   其余段型的开头不是段数据头，拿②③去套会全是假报。
//! ★ ① 在 31 条已知漏切样本上不符（与段数据头同一批），故**只报不拒**。
//! ★ ④ 在本扫描器下是**恒等式**（末段直抵文件尾 ⇒ 恒成立），留着它是为了「段表由别处构造」
//!   这一类调用（那时它能报出长度不符）。
//!
//! **默认只报不改**（易语言侧取证「加固项：漏切自证」）：参照实现自身在精易 V12.1.1.ec 上就漏切一处，
//! fail-closed 会把 1444/1444 往返测试打红 —— 那是把「报告」做成「拒收」。

use std::vec::Vec;

use super::校验槽::算段头校验;
use super::形状::{容器段, 段类型, 自检异常};

/// 段数据头 `+0x00` 的段序号偏移。
const 段序号偏移: usize = 0x00;
/// 段数据头 `+0x0C` 的体长偏移。
const 体长偏移: usize = 0x0C;
/// 段数据头长度（56 字节）—— 与记录流层 `段数据头长度` 同值，此处只做长度门。
const 段数据头实测长度: usize = 56;

/// 复核段链 ⇒ 异常表（**只报不改**，顺序即发现顺序）。
///
/// `字节` 是整份容器字节，`段表` 是 `反解容器` 扫描出的结果。
pub(super) fn 自检段链(字节: &[u8], 段表: &[容器段]) -> Vec<自检异常> {
    let mut 异常表 = Vec::new();
    let 程序号 = 段类型::程序.取号值();
    for (位次, 号段) in 段表.iter().enumerate() {
        let 第几段 = 位次 as u32;
        let 数据字节 = &号段.数据字节;
        // ① 段头校验槽复算（任何段型都算）。
        if let Some(段头起点) = 段起点(字节, 段表, 位次) {
            let 期望校验 = 算段头校验(&字节[段头起点..段头起点 + 44], 数据字节);
            if 期望校验 != 号段.段头字段.校验和 {
                异常表.push(自检异常::段头校验不符 {
                    第几段,
                    期望: 期望校验,
                    实取: 号段.段头字段.校验和,
                });
            }
        }
        // ②③ 只对程序段（类型 3）成立。
        if 号段.段头字段.段类型 != 程序号 || 数据字节.len() < 段数据头实测长度 {
            continue;
        }
        let 序号 = u32::from_le_bytes(读四字节(数据字节, 段序号偏移));
        if 序号 != 第几段 + 1 {
            异常表.push(自检异常::段序号不连号 { 第几段, 序号 });
        }
        let 头内体长 = u64::from(u32::from_le_bytes(读四字节(数据字节, 体长偏移)));
        let 实有体长 = (数据字节.len() - 段数据头实测长度) as u64;
        if 头内体长 != 实有体长 {
            异常表.push(自检异常::体长与实长不符 { 第几段, 头内: 头内体长, 实有: 实有体长 });
        }
    }
    // ④ 文件大小恒等式：8 + Σ(44 + 段数据长) == 文件大小。
    let 应有 = crate::容器::文件头魔数.len() as u64
        + 段表
            .iter()
            .map(|号段| (crate::容器::段头长度 + 号段.数据字节.len()) as u64)
            .sum::<u64>();
    if 应有 != 字节.len() as u64 {
        异常表.push(自检异常::文件大小恒等式不成立 { 应有, 实有: 字节.len() as u64 });
    }
    异常表
}

/// 第 `位次` 段的段头起点（= 前各段 44 + 数据长 累加）。
fn 段起点(字节: &[u8], 段表: &[容器段], 位次: usize) -> Option<usize> {
    let 起点 = crate::容器::文件头魔数.len()
        + 段表[..位次]
            .iter()
            .map(|号段| crate::容器::段头长度 + 号段.数据字节.len())
            .sum::<usize>();
    if 起点 + crate::容器::段头长度 <= 字节.len() {
        Some(起点)
    } else {
        None
    }
}

fn 读四字节(字节: &[u8], 读游标: usize) -> [u8; 4] {
    [字节[读游标], 字节[读游标 + 1], 字节[读游标 + 2], 字节[读游标 + 3]]
}
