//! 校验槽 —— 段头 `+0x04` 的字级 XOR 折叠（`折`）与段头校验复算。
//!
//! **算法**（易语言侧实测 21,641/21,641 · 取证「加固项：段头与段数据头校验槽的算法落地」）：
//! `折(X) = 小端切 4 字节逐位异或，末不足 4 字节右侧补 0`。
//! 段头 `+0x04` 覆盖范围（本腿 2026-10-07 在 2159 份 `.e`/`.ec` · 21,876 段上逐段自量）：
//! `折( 8 字节全零 ‖ 段头[0x08..] ‖ 段数据[0x00..0x08] ‖ 4 字节全零 ‖ 段数据[0x0C..] )`
//! —— 即「段头 ‖ 段数据」两处校验槽（`+0x04..0x08` 与段数据 `+0x08..0x0C`）清零后整体折叠。
//! 实测 **21845/21876 = 99.8583%**，31 条不符 = 与段数据头同一批已知漏切样本（类型 4 ×18 · 7 ×13）。
//!
//! ★ 本件是**两个方向共用的唯一一份**：反解复算与生成回填都调它，不许各写一套。
//! ★ 本件只算不判 —— 判在哪一档（fail-closed / 只报）由调用方定（本腿取「只报」，见 `自检.rs`）。

use std::vec::Vec;

/// 字级 XOR 折叠：小端切 4 字节全异或，末不足 4 字节右侧补 0。
pub fn 折(字节: &[u8]) -> u32 {
    let mut 累加值 = 0u32;
    let mut 读游标 = 0usize;
    while 读游标 < 字节.len() {
        let 末位 = (读游标 + 4).min(字节.len());
        let mut 四字节 = [0u8; 4];
        四字节[..末位 - 读游标].copy_from_slice(&字节[读游标..末位]);
        累加值 ^= u32::from_le_bytes(四字节);
        读游标 += 4;
    }
    累加值
}

/// 段头 `+0x04` 校验槽：`段头 ‖ 段数据` 两处校验槽清零后整体折叠。
///
/// 覆盖 = `8 字节全零 ‖ 段头[0x08..] ‖ 段数据[0x00..0x08] ‖ 4 字节全零 ‖ 段数据[0x0C..]`。
pub fn 算段头校验(段头字节: &[u8], 段数据字节: &[u8]) -> u32 {
    let mut 缓冲 = Vec::with_capacity(8 + 段头字节.len() + 段数据字节.len());
    缓冲.extend_from_slice(&[0u8; 8]);
    if 段头字节.len() > 8 {
        缓冲.extend_from_slice(&段头字节[8..]);
    }
    let 数据首段 = 段数据字节.len().min(8);
    缓冲.extend_from_slice(&段数据字节[..数据首段]);
    缓冲.extend_from_slice(&[0u8; 4]);
    if 段数据字节.len() > 12 {
        缓冲.extend_from_slice(&段数据字节[12..]);
    }
    折(&缓冲)
}
