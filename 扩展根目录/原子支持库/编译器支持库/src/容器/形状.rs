/// 文件头魔数（8 字节）。
pub const 文件头魔数: [u8; 8] = *b"CNWTEPRG";

/// 段头长度（字节）。
pub const 段头长度: usize = 44;

/// 段头里的两个固定标记。
pub const 段头标记首: u16 = 0x7319;
pub const 段头标记次: u16 = 0x1511;

/// 段类型号。**只增不复用**：删掉的类型号作废不回收。
///
/// **盘面宽度是 `u8`（1 字节）**：`u32 校验和 + u8 段类型 + 27 字节名称区 + u32 段名长
/// + u64 数据长 = 已冻结的 44`。所以「新增段类型号」只能取 u8 里**没人用的那些** ——
/// 参照实现占 `1–15` 与 `255`，我们自身的号从 `16` 起（`16–254` 是空洞）。
/// 号取哪几个登记在 `契约声明/冻结登记.json` 的 `段类型号登记` 键里，
/// 由 `一键验证.py` 第 9 项判「是 0–255 · 不撞已占用 · 本枚举真能表示」。
///
/// 能力包件（`项目文档/设计文档/能力包件.md`）用前三个：`16` 接口说明 · `17` 能力码 · `18` 指纹；
/// 技能制品（`8xxx`）的本体段取 `19`（`扩展装载/后缀表.json` 三段：16 · 19 · 18）。
/// 依据：`项目文档/决策记录/2026-09-27_语言主线三缺口裁决.md` §三。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum 段类型 {
    用户信息 = 1,
    系统信息 = 2,
    程序 = 3,
    程序资源 = 4,
    可丢失程序 = 5,
    /// 编辑信息段。**参照实现写侧不产生本号**（写段例程的 15 处 `push <类型标签>` 独缺类型 6；
    /// 易语言侧取证）—— 读侧认识（读段分派覆盖 1..17），写侧不产出。
    /// 语料实测类型 6 有 37 段 ⇒ **生成侧接受**（拒就破往返），「写侧不产出」只约束 V1 自造段。
    编辑信息 = 6,
    /// 无名七。同上：读侧认识（读段分派认识 7），写侧不产生。语料实测 1456 段，**生成侧接受**。
    无名七 = 7,
    初始模块 = 8,
    编辑信息二 = 9,
    辅助信息一 = 10,
    辅助信息二 = 11,
    易模块记录 = 12,
    易包信息一 = 13,
    编辑过滤器信息 = 14,
    易模块记录二 = 15,
    程序加固 = 255,
    /// 能力包件 · 接口说明段（**我们自身新增的号**，不属参照实现）。
    接口说明 = 16,
    /// 能力包件 · 能力码段。
    能力码 = 17,
    /// 能力包件 · 指纹段。
    指纹 = 18,
    /// 技能制品 · 技能本体段（md 正文）—— 技能（`8xxx`）的制品用它装本体。
    技能本体 = 19,
}

impl 段类型 {
    pub fn 自号(号值: u8) -> Option<Self> {
        use 段类型::*;
        Some(match 号值 {
            1 => 用户信息, 2 => 系统信息, 3 => 程序, 4 => 程序资源, 5 => 可丢失程序,
            6 => 编辑信息, 7 => 无名七, 8 => 初始模块, 9 => 编辑信息二, 10 => 辅助信息一,
            11 => 辅助信息二, 12 => 易模块记录, 13 => 易包信息一, 14 => 编辑过滤器信息,
            15 => 易模块记录二, 255 => 程序加固,
            16 => 接口说明, 17 => 能力码, 18 => 指纹, 19 => 技能本体,
            // 未登记号 `自号` 仍给 `None`（枚举装不下未知值）—— 但反解侧**不再据此 fail-closed**，
            // 改由 `容器::未知段号表` 把号原值报出（未知号在 `容器段.段头字段.段类型` 里以 u8 保留）。
            _ => return None,
        })
    }
    /// 号值是不是**已登记**的段类型（`自号` 有值）。未知号走「跳过并保留」那一支。
    pub fn 是已登记号(号值: u8) -> bool {
        Self::自号(号值).is_some()
    }
    pub fn 取号值(&self) -> u8 { *self as u8 }
}

/// 段头内各字段的**相对偏移**。逐字段对齐原文，实测复核（见模块注释表格）。
pub mod 段头偏移 {
    /// u16 段头魔术 `0x7319`（字节序 `19 73`）。
    pub const 魔术首: usize = 0x00;
    /// u16 段头标记 `0x1511`（字节序 `11 15`）。
    pub const 魔术次: usize = 0x02;
    /// u32 段校验值 = `折(8 字节全零 ‖ 段头[0x08..] ‖ 段数据[0x00..0x08] ‖ 4 字节全零 ‖ 段数据[0x0C..])`，
    /// `折` = 小端切 4 字节全异或、末不足 4 字节右侧补 0（算法落点 `容器/校验槽.rs::折`）。
    /// 本腿 2026-10-07 实测 21845/21876 = 99.8583%（31 条不符 = 已知漏切样本）。
    pub const 校验和: usize = 0x04;
    /// u16 `0x7319` + u8 `0x00` + u8 段类型号。
    pub const 类型标记: usize = 0x08;
    /// 27 字节名称区（异或混淆）。
    pub const 名称区: usize = 0x0C;
    /// u16 `0x7319` + u8 `0x00`。类型 7 的 0x0C..0x2C 共 32 字节全零，故该处也是 0。
    pub const 结束标记: usize = 0x27;
    /// u8 段头尾标志：类型 255 加固段取 `0x03` · 普通段取 `0x00` ·
    /// **被吞的嵌套段取 `0x02`**（易语言侧取证：尾标志三种取值）。
    pub const 尾标志: usize = 0x2A;
    /// u8 恒 `0x00`。
    pub const 补零: usize = 0x2B;
}

/// 段头标记首的字节序（`0x7319` 小端）。拆分后反解件 / 生成件要用，故放宽到 `pub(super)`。
pub(super) const 魔术首字节: [u8; 2] = 段头标记首.to_le_bytes();
/// 段头标记次的字节序（`0x1511` 小端）。同上，放宽到 `pub(super)`。
pub(super) const 魔术次字节: [u8; 2] = 段头标记次.to_le_bytes();

/// 段头（44 字节，逐字段对齐原文）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 段头 {
    pub 校验和: u32,
    pub 段类型: u8,
    /// 27 字节名称区。**原文里是异或混淆的**，反解要还原、生成要重新混淆。
    ///
    /// 本字段是反解侧对盘面原始 27 字节的快照（`逐字段对齐原文` 的落地）；
    /// `生成` 由 `段名` 重算名称区，不读本字段。两者在合法输入上必然一致。
    pub 名称区: [u8; 27],
    /// 名称区的**明文**（由名称区解出；生成时按段类型重新混淆）。
    ///
    /// 类型 7（`无名七`）盘面从不写段名，此处为空 `Vec`。
    pub 段名: Vec<u8>,
}

/// 一个段：段头 + 数据。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 容器段 {
    pub 段头字段: 段头,
    pub 数据字节: Vec<u8>,
}

/// 容器：魔数 + 段序列，连续到文件尾。
///
/// **冻结区 = `段表`**；后面三个字段是**旁路区**（一律追加在尾部，旧读者仍能读前缀）：
/// `未知段号表`（A21 未知段类型可跳过）· `嵌套段表`（A23 段里可套段识别）·
/// `自检异常表`（A24 漏切自证）。三个都是**只读报告**，生成侧不读、不影响往返。
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct 容器 {
    pub 段表: Vec<容器段>,
    /// 反解时遇到的**未登记段类型号**表（原值保留，不静默丢；见 `反解定义.rs::反解容器`）。
    pub 未知段号表: Vec<u8>,
    /// 段数据里搜到嵌套段头（尾标志 `0x02`）的**字节偏移**表（只报不改，段边界不变）。
    pub 嵌套段表: Vec<u64>,
    /// 段链自检异常表（**只报不改**，默认不 fail-closed；见 `自检.rs::自检段链`）。
    pub 自检异常表: Vec<自检异常>,
}

/// 段链自检异常项（**只报不改**）。结构化段位，不是字符串。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 自检异常 {
    /// 段头 `+0x04` 校验槽与复算值不符。
    段头校验不符 { 第几段: u32, 期望: u32, 实取: u32 },
    /// 段数据头 `+0x00` 的段序号不是「位次 + 1」（缺号即漏切）。
    段序号不连号 { 第几段: u32, 序号: u32 },
    /// 段数据头 `+0x0C` 的体长与「段数据长 − 56」不符。
    体长与实长不符 { 第几段: u32, 头内: u64, 实有: u64 },
    /// `8 + Σ(44 + 段数据长) == 文件大小` 不成立。
    文件大小恒等式不成立 { 应有: u64, 实有: u64 },
}

/// 反解错误。结构化段位，不是字符串。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 反解错误 {
    魔数不符,
    /// 段头不足 44 字节。
    段头截断 { 字节位置: u64 },
    /// 段数据长度超出文件尾。
    ///
    /// 本格式无段长字段、段数据恒被文件尾截断，故该变体在合法输入上不可达；
    /// 保留以维持冻结接口。详见模块注释「一处无法闭合的冻结接口」。
    段数据越界 { 字节位置: u64, 需要: u64 },
    /// 段头里的两个标记不对。
    段头标记不符 { 字节位置: u64 },
    /// 段类型号不在登记范围内。
    段类型未知 { 字节位置: u64, 段号: u8 },
}

/// 生成错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 生成错误 {
    /// 段名为空。
    段名为空 { 第几段: u32 },
    /// 段名超过名称区容量。
    段名过长 { 第几段: u32, 块长度: u64 },
}
