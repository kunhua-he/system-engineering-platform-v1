//! 容器产物形状 —— 魔数 · 段头长度 · 段头标记 · 段类型 · 段头偏移 · 段头 · 段 · 容器
//! · 反解错误 · 生成错误。
//!
//! 这是**形状冻结件**：源出 `容器.rs` 第 57–126 行与第 131–184 行，**逐字搬家**，
//! 段头与段类型号改动必须走 `契约声明/冻结登记.json`。
//!
//! 两个错误枚举留在这里而不是单开一件：模块注释把它们当**冻结接口**的一部分
//! （`反解错误::段数据越界` 正是为「保留以维持冻结接口」而存在的）。

/// 文件头魔数（8 字节）。
pub const 魔数: [u8; 8] = *b"CNWTEPRG";

/// 段头长度（字节）。
pub const 段头长度: usize = 44;

/// 段头里的两个固定标记。
pub const 段头标记甲: u16 = 0x7319;
pub const 段头标记乙: u16 = 0x1511;

/// 段类型号。**只增不复用**：删掉的类型号作废不回收。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum 段类型 {
    用户信息 = 1,
    系统信息 = 2,
    程序 = 3,
    程序资源 = 4,
    可丢失程序 = 5,
    编辑信息 = 6,
    无名七 = 7,
    初始模块 = 8,
    编辑信息二 = 9,
    辅助信息一 = 10,
    辅助信息二 = 11,
    易模块记录 = 12,
    易包信息一 = 13,
    编辑过滤器信息 = 14,
    易模块记录二 = 15,
    程序加固 = 255,
}

impl 段类型 {
    pub fn 自号(号: u8) -> Option<Self> {
        use 段类型::*;
        Some(match 号 {
            1 => 用户信息, 2 => 系统信息, 3 => 程序, 4 => 程序资源, 5 => 可丢失程序,
            6 => 编辑信息, 7 => 无名七, 8 => 初始模块, 9 => 编辑信息二, 10 => 辅助信息一,
            11 => 辅助信息二, 12 => 易模块记录, 13 => 易包信息一, 14 => 编辑过滤器信息,
            15 => 易模块记录二, 255 => 程序加固,
            _ => return None,
        })
    }
    pub fn 号(&self) -> u8 { *self as u8 }
}

/// 段头内各字段的**相对偏移**。逐字段对齐原文，实测复核（见模块注释表格）。
pub mod 段头偏移 {
    /// u16 段头魔术 `0x7319`（字节序 `19 73`）。
    pub const 魔术甲: usize = 0x00;
    /// u16 段头标记 `0x1511`（字节序 `11 15`）。
    pub const 魔术乙: usize = 0x02;
    /// u32 段校验值。算法未证实（非 CRC32 七变体 / 非 Adler32 / 非字节和），原样搬运。
    pub const 校验和: usize = 0x04;
    /// u16 `0x7319` + u8 `0x00` + u8 段类型号。
    pub const 类型标记: usize = 0x08;
    /// 27 字节名称区（异或混淆）。
    pub const 名称区: usize = 0x0C;
    /// u16 `0x7319` + u8 `0x00`。类型 7 的 0x0C..0x2C 共 32 字节全零，故该处也是 0。
    pub const 结束标记: usize = 0x27;
    /// u8 段头尾标志：类型 255 取 `0x03`，其余（含类型 7）取 `0x00`。
    pub const 尾标志: usize = 0x2A;
    /// u8 恒 `0x00`。
    pub const 补零: usize = 0x2B;
}

/// 段头魔术甲的字节序（`0x7319` 小端）。拆分后反解件 / 生成件要用，故放宽到 `pub(super)`。
pub(super) const 魔术甲字节: [u8; 2] = 段头标记甲.to_le_bytes();
/// 段头标记乙的字节序（`0x1511` 小端）。同上，放宽到 `pub(super)`。
pub(super) const 魔术乙字节: [u8; 2] = 段头标记乙.to_le_bytes();

/// 段头（44 字节，逐字段对齐原文）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 段头 {
    pub 校验和: u32,
    pub 段类型: u8,
    /// 27 字节名称区。**原文里是异或混淆的**，反解要还原、生成要重新混淆。
    ///
    /// 本字段是反解侧对盘面原始 27 字节的快照（`逐字段对齐原文` 的落地）；
    /// `生成` 由 `段名` 重算名称区，不读本字段。两者在合法输入上必然一致。
    pub 名称区: [u8; 27],
    /// 名称区的**明文**（由名称区解出；生成时按段类型重新混淆）。
    ///
    /// 类型 7（`无名七`）盘面从不写段名，此处为空 `Vec`。
    pub 段名: Vec<u8>,
}

/// 一个段：段头 + 数据。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 段 {
    pub 头: 段头,
    pub 数据: Vec<u8>,
}

/// 容器：魔数 + 段序列，连续到文件尾。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 容器 {
    pub 段表: Vec<段>,
}

/// 反解错误。结构化段位，不是字符串。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 反解错误 {
    魔数不符,
    /// 段头不足 44 字节。
    段头截断 { 位置: u64 },
    /// 段数据长度超出文件尾。
    ///
    /// 本格式无段长字段、段数据恒被文件尾截断，故该变体在合法输入上不可达；
    /// 保留以维持冻结接口。详见模块注释「一处无法闭合的冻结接口」。
    段数据越界 { 位置: u64, 需要: u64 },
    /// 段头里的两个标记不对。
    段头标记不符 { 位置: u64 },
    /// 段类型号不在登记范围内。
    段类型未知 { 位置: u64, 号: u8 },
}

/// 生成错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 生成错误 {
    /// 段名为空。
    段名为空 { 第几段: u32 },
    /// 段名超过名称区容量。
    段名过长 { 第几段: u32, 长度: u64 },
}
