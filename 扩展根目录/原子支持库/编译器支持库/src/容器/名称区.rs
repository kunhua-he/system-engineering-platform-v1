//! 名称区 —— 密钥 · 容量 · 解名称区 · 编名称区。
//!
//! 源出 `容器.rs` 第 128–129 行、第 236–239 行、第 353–403 行，**逐字搬家**。
//!
//! 解与编是**一对互逆运算**，放同一件里：改名称区规则时只需读这一个文件
//! （模块注释的硬要求：「两个方向必须由同一份格式知识驱动，不许各写一套」）。
//!
//! 三处可见性由「私有」放宽到 `pub(super)`（名称区容量 · 解名称区 · 编名称区）——
//! 拆分后它们要被同层的反解件 / 生成件 / 测试件调用。**公开面未变**（都不是 `pub`）。

use super::形状::{段头偏移, 段类型, 生成错误};

/// 名称区容量（字节）。段名最长 27 字节（填满时无 NUL 终止位）。
pub(super) const 名称区容量: usize = 27;

/// 名称区异或密钥：`73 00 <段类型> 19`，相位锚在**段头起点**。
pub fn 名称区密钥(段类型: u8) -> [u8; 4] {
    [0x73, 0x00, 段类型, 0x19]
}

/// 解名称区 → 段名明文。
///
/// 规则：名称区 27 字节**全零** ⟺ 该段不写段名（类型 7 的盘面特征），得空段名；
/// 否则与密钥异或，取首个 NUL 之前的部分为段名——前提是该 NUL 之后全是补零。
/// 若 NUL 之后仍有非零字节（语料未出现），则整个 27 字节都是段名（无 NUL 终止），
/// 与 `编名称区` 的「填满名称区」分支互为逆运算。
pub(super) fn 解名称区(名称区: &[u8; 名称区容量], 类型号: u8) -> Vec<u8> {
    if 名称区.iter().all(|&字节| 字节 == 0) {
        return Vec::new();
    }
    let 密钥 = 名称区密钥(类型号);
    let mut 明文 = [0u8; 名称区容量];
    for 位次 in 0..名称区容量 {
        明文[位次] = 名称区[位次] ^ 密钥[(段头偏移::名称区 + 位次) % 4];
    }
    match 明文.iter().position(|&字节| 字节 == 0) {
        Some(零尾位) if 明文[零尾位..].iter().all(|&字节| 字节 == 0) => 明文[..零尾位].to_vec(),
        _ => 明文.to_vec(),
    }
}

/// 段名明文 → 名称区 27 字节。
///
/// 规则：段名写入 27 字节名称区，**不足处先补一个 NUL 再补零**（即 `段名 + NUL + 补零`）；
/// 段名恰好占满 27 字节时不补 NUL。类型 7 恒写全零名称区（盘面从不写段名）。
pub(super) fn 编名称区(段名: &[u8], 类型号: u8, 第几段: u32) -> Result<[u8; 名称区容量], 生成错误> {
    if 类型号 == 段类型::无名七.取号值() {
        return Ok([0u8; 名称区容量]);
    }
    if 段名.is_empty() {
        return Err(生成错误::段名为空 { 第几段 });
    }
    if 段名.len() > 名称区容量 {
        return Err(生成错误::段名过长 {
            第几段,
            块长度: 段名.len() as u64,
        });
    }

    let mut 明文 = [0u8; 名称区容量];
    明文[..段名.len()].copy_from_slice(段名);
    // 段名.len() < 27 时该位已是 0（NUL 终止），其后也是 0（补零）；
    // 段名.len() == 27 时无 NUL 位，整区被段名填满。

    let 密钥 = 名称区密钥(类型号);
    let mut 密文字节 = [0u8; 名称区容量];
    for 位次 in 0..名称区容量 {
        密文字节[位次] = 明文[位次] ^ 密钥[(段头偏移::名称区 + 位次) % 4];
    }
    Ok(密文字节)
}
