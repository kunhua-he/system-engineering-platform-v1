/// 记号种类。**只增不复用**：删掉的号作废不回收（同 `容器::段类型` 的规矩）。
///
/// 号码留空档，便于新增种类而不重排既有序号。
///
/// 每一种都有语料实测出处，逐条见 `说明/语言面形状.md` 第二节。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum 记号种类 {
    /// 行首（仅前导空白之后）由 `.` 引导的指令词：`.版本` `.子程序` `.参数` `.如果真`
    /// ……，以及不带点的语句关键字 `返回` `置入代码`。
    ///
    /// **实测**：`.\xB0\xE6\xB1\xBE 2`（`.版本 2`）、`.\xD7\xD3\xB3\xCC\xD0\xF2`
    /// （`.子程序`）、`\xB7\xB5\xBB\xD8`（`返回`）。点**含在本记号区间内**。
    ///
    /// **待办**：完整关键字集合未定 —— 只有**指令词表**能定（内核库那份尚未定位），
    /// 而参照编译器是黑盒。现在只把「是不是关键字」这一层冻住，**具体是哪个关键字
    /// 由 1102 按区间文本判**，不写死在枚举里。
    ///
    /// **更正（2026-09-27）**：原文写「由 1102 按区间文本 + `统一注册表` 判定」
    /// 是**指错了件** —— `统一注册表`（`运行内核/统一注册表/src/`）只有命令表 · 类型表 ·
    /// 常量表 · 函数表 + 占位项，**没有「关键字 / 指令词」这一概念**（实测 `grep 关键字` 零命中）。
    /// 真正的唯一物是**指令词表**，见 `说明/语言面形状.md` §六 待办 1。
    关键字 = 1,
    /// 标识符。实测中文标识符与 ASCII 标识符并存，下划线可出现在首、中、尾：
    /// `_启动子程序` `_按钮1_被单击` `EndScene_hook` `取消文档打印_` `_Text_`。
    标识符 = 2,
    /// 文本字面量。**实测两种定界符并存**：全角 `“…”`（表达式里的字符串，
    /// `\xA1\xB0 … \xA1\xB1`）与半角 `"…"`（声明字段，如 `.DLL命令 …, "user32.dll"`、
    /// `.局部变量 …, "0"`）；且**可嵌套**：`.常量 名, "“值”"`。
    ///
    /// 定界符种类可从区间首字节读出，故不另设字段。
    /// **待办**：半角引号在语言里的确切角色（字段定界还是字面量定界）未证实。
    文本字面量 = 3,
    /// 数值字面量。实测十进制整数与负号：`0` `36` `1000` `-1` `255`。
    /// **待办**：小数（如 `1.5`）与十六进制在语料内未实测到。
    数值字面量 = 4,
    /// `#` 引导的常量引用。实测 `#FALSE` `#DEFAULT_CHARSET` `#DT_TOP` `#DLL_PROCESS_DETACH`。
    常量引用 = 5,
    /// 运算符。**实测全角**：`＝`（`\xA3\xBD`）`＋`（`\xA3\xAB`）`÷`（`\xA1\xC2`）。
    /// **待办**：半角运算符是否并存未证实；完整运算符集合未定。
    运算符 = 6,
    /// 界符。**实测半角**：`(` `)` `[` `]` `,` `.` `&` `{` `}`。
    ///
    /// 注意 `.` 一号两用：行首引导关键字（进 `关键字` 记号），行内是成员访问运算符
    /// （进 `界符`）。**这一层区分是 1101 的判定，不是本形状的字段。**
    界符 = 7,
    /// 空白：行内空格、行首缩进。**实测缩进是 4 个半角空格**（`    .参数 …`、
    /// `    调试输出 (…)`），**未实测到制表符**（全文 `\t` 计数为 0）。
    空白 = 8,
    /// 换行。**实测 `\r\n`**（CRLF）。单独 `\n` 在语料内未实测到。
    换行 = 9,
    /// 注释：`'`（半角单引号 `0x27`）至本行行尾。实测既有**整行注释**
    /// （`' mov eax,[ebp+8]`）也有**行尾注释**（`… )  ' 测试ACall …`）。
    /// **注释记号不含行尾的 `\r\n`** —— 换行归 `换行` 记号，这样行尾注释与整行注释同构。
    注释 = 10,
    /// 文件结束：**零宽**，锚在全文末尾 `[全文长, 全文长)`。
    /// 有了它，空文件也有一个记号，且「末记号止 == 全文长」这条覆盖判据对空文件也成立。
    文件结束 = 11,
    /// 备注文本：**规格 §二 的 11 类里没有任何一类点名能吃的字节**（`词法/字符集.rs::是否兜底`），
    /// 以及**含这类字节的连续段** —— 声明行末的不加引号自由文本（备注位）就是它。
    ///
    /// **实测**：`wFormatTag，记录着此声音的格式代号` · `-1:准备就绪;1:周期事件;-2:定时器被关闭`
    /// · `如："c:\windows\system32\user32.dll"返回…`（`说明/真文本覆盖.md` 缺口 2）。
    ///
    /// **裁决**（`项目文档/决策记录/2026-09-28_华哥的尺子与七条裁决.md` §二「备注位怎么记号化」）：原先这类字节
    /// **兜底并进 `标识符`** —— 那是「认不出又不报错」的误类（静默误判是头号大敌）。立本类后，
    /// 兜底与含兜底的连续段一律成 `备注文本`，**不再冒充名字**。
    ///
    /// **本类不是「备注位」本身**：它只表达「这些字节不属于任何点名的类」；是不是备注位由 1102
    /// 按所在层级判（词法层没有「声明行的第几个字段」这种知识）。
    备注文本 = 12,
}

impl 记号种类 {
    /// 自号：未知号返回 `None`（**不 panic** —— 反解路径上不许 panic）。
    pub fn 自号(号值: u8) -> Option<Self> {
        use 记号种类::*;
        Some(match 号值 {
            1 => 关键字,
            2 => 标识符,
            3 => 文本字面量,
            4 => 数值字面量,
            5 => 常量引用,
            6 => 运算符,
            7 => 界符,
            8 => 空白,
            9 => 换行,
            10 => 注释,
            11 => 文件结束,
            12 => 备注文本,
            _ => return None,
        })
    }

    pub fn 取号值(&self) -> u8 {
        *self as u8
    }

    /// 本种类是否「有可见内容」。零宽种类只有 `文件结束`，用于不变量判定。
    pub fn 是否零宽(&self) -> bool {
        matches!(self, 记号种类::文件结束)
    }
}

/// 一个记号。**形状冻结**：只有种类与字节区间，不带文本 —— 文本由区间从
/// `super::记号流::原文` 里切出（见 [`super::记号流::切片`]），**同一事实不存两份**。
///
/// 字段**不是公开面**（`pub(crate)`）：单个记号自身没有可判的不变量（区间是否越界、
/// 是否倒置、与左右邻居是否相接，全是**记号表**的性质），所以那些不变量不在 [`记号::新建`]
/// 里判，而在唯一构造口 [`super::记号流::新建`] 里一次判死。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 记号 {
    pub(crate) 种类: 记号种类,
    /// 覆盖的原文字节区间 `[起, 止)`。
    pub(crate) 起: u32,
    pub(crate) 止: u32,
}

impl 记号 {
    pub fn 新建(种类: 记号种类, 区间起点: u32, 区间终点: u32) -> Self {
        Self { 种类, 起: 区间起点, 止: 区间终点 }
    }

    /// 区间宽度（字节）。
    pub fn 取区间宽度(&self) -> u32 {
        self.止.saturating_sub(self.起)
    }
}

