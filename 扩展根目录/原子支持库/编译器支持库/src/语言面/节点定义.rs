/// 语法树节点种类。**只增不复用**；号码分组留空档。
///
/// 用「节点表 + 子节点区间」而不是 `Box` 递归树：便于序列化、便于逐字节往返、
/// 便于并发只读遍历（节点表是连续内存，子区间就是切片下标）。
///
/// 每一种都有语料实测出处，逐条见 `说明/语言面形状.md` 第三节。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u16)]
pub enum 节点种类 {
    // ── 1..19 顶层与声明 ────────────────────────────────────────────────────
    /// 整份源文件。**根节点**，原文区间恒等于全文。
    程序 = 1,
    /// 源单元：以 `.版本 2` 起的一段。
    ///
    /// **实测同一份文本里 `.版本 2` 出现多次**（`抖音解析2` 那段 7880 字节里 13 次），
    /// 每张声明表（数据类型 / DLL命令 / 全局变量 / 常量 …）各起一段。
    /// 所以「程序 = 一个源单元」是错的，必须允许多个。
    源单元 = 2,
    /// `.支持库 名`。实测 `.支持库 eAPI`、`.支持库 spec`。
    支持库声明 = 3,
    /// `.程序集 名`。实测 `.程序集 程序集1`、`.程序集 程序集`。
    程序集 = 4,
    /// `.程序集变量 名, 类型, , "维度"`。实测 `.程序集变量 Text, ID3DXFont, , "4"`。
    程序集变量声明 = 5,
    /// `.全局变量 名, 类型`。实测 `.全局变量 DeBugText, 文本型`。
    全局变量声明 = 6,
    /// `.局部变量 名, 类型, , "维度"`。实测 `.局部变量 n, 整数型`、
    /// `.局部变量 进程信息, 进程信息, , "0"`。
    局部变量声明 = 7,
    /// `.子程序 名, 返回类型, 公开位, 备注`。
    /// 实测 `.子程序 _启动子程序, 整数型, , By 轻飘飘的风`（备注）、
    /// `.子程序 ZJZDXHook, , 公开`（返回类型空 + 公开位）。
    子程序 = 8,
    /// `.参数 名, 类型, 参考位, 说明`。
    /// 实测 `.参数 lpModuleName, 文本型`、`.参数 _Text_, 文本型, 参考`。
    参数声明 = 9,
    /// `.数据类型 名` + 若干 `.成员`。实测 `.数据类型 D3DTLVERTEX`。
    数据类型声明 = 10,
    /// `.成员 名, 类型`。实测 `.成员 X, 小数型`（缩进 4 空格）。
    数据成员声明 = 11,
    /// `.DLL命令 名, 返回类型, "库", "命令名", , 备注`。
    /// 实测 `.DLL命令 SetRect, 逻辑型, "user32.dll", "SetRect"`。
    DLL命令声明 = 12,
    /// `.常量 名, "值", 公开位, 备注`。实测 `.常量 OUT_DEFAULT_PRECIS, "0"`、
    /// `.常量 网页事件_onactivate, "“onactivate”", 公开, 当对象设置为活动元素时触发。`
    常量声明 = 13,

    // ── 21..39 语句 ────────────────────────────────────────────────────────
    /// 赋值语句：`左 ＝ 右`。实测 `DeBugText ＝ “Viewport.X -> ” ＋ 到文本 (Viewport.X)`。
    赋值语句 = 21,
    /// 调用语句：`命令 (实参表)`，占一整行、返回值被丢弃。
    /// 实测 `信息框 (“本程序来自程序3”, 0, , )`。
    ///
    /// **与 [`节点种类::命令调用`] 是父子关系，不是两套实现**：本种类的子节点里含一个
    /// `命令调用`。两者在字节上完全一样（都是 `名 ( … )`），只能靠**所在层级**区分
    /// —— 所以语句层必须有这个节点，否则 1102 分不出「一整行裸调用」与「表达式的一处片段」。
    调用语句 = 22,
    /// 返回语句：`返回 (表达式)`。实测 `返回 (0)`、`返回 (真)`。
    返回语句 = 23,
    /// 置入代码语句：`置入代码 ({ 字节, 字节, … })`。
    /// 实测 `置入代码 ({ 139, 69, 8, 139, 0, 137, 236, 93, 194, 4, 0 })`。
    置入代码语句 = 24,
    /// 单条件块语句：`.如果真 (条件) … .如果真结束`、`.计次循环首 (…) … .计次循环尾`。
    /// 实测两者都有；`子区间` 首元素是条件表达式，其余是体内语句。
    ///
    /// **待办**：`.如果 / .否则` 二分支块、`.循环判断首 / .循环判断尾`、
    /// `.变量循环首` 等在本轮语料内未实测到，暂并入本种类，待补种类号。
    块语句 = 25,
    /// 多分支块：`.判断开始 … .判断结束`。
    /// 实测 `.判断开始 (ul_reason_for_call ＝ #DLL_PROCESS_DETACH)`。
    判断块 = 26,
    /// 判断块的一个分支：`.判断 (条件)` 或 `.默认`。
    /// 实测 `.判断 (…)` 与 `.默认` 都出现。
    判断分支 = 27,

    // ── 41..59 表达式 ──────────────────────────────────────────────────────
    /// 文本字面量。实测 `“祖国，您好！”`、`“微软雅黑”`。
    文本字面量 = 41,
    /// 数值字面量。实测 `0` `36` `1000` `-1` `255`。
    数值字面量 = 42,
    /// 常量引用：`#名`。实测 `#FALSE` `#DT_TOP`。
    常量引用 = 43,
    /// 标识符引用（变量 / 参数 / 命令名）。实测 `Viewport` `lpModuleName` `信息框`。
    标识符引用 = 44,
    /// 命令调用：`名 (实参表)`。实测 `取系统进程列表 ()`、`位或 (#DT_TOP, #DT_LEFT)`。
    命令调用 = 45,
    /// 成员访问：`对象.成员`。实测 `Viewport.Width`、`IDirect3DDevice9Func.EndScene`。
    /// **同时覆盖成员调用**（`EndScene_hook.Install (…)`）—— 调用形状由子节点给出。
    成员访问 = 46,
    /// 下标访问：`数组 [下标]`。实测 `Text [1]`、`进程信息 [n]`。
    下标访问 = 47,
    /// 一元运算。实测取地址 `&EndScene_hook`（半角 `&`）。
    /// **待办**：一元负号、逻辑非等未实测到。
    一元运算 = 48,
    /// 二元运算。实测 `＋`（`\xA3\xAB`）、`÷`（`\xA1\xC2`）、`＝`（`\xA3\xBD`）。
    二元运算 = 49,
    /// **空实参**：实参表里的空位。实测极多 ——
    /// `D3D_HookCall (IDirect3DDevice9Func.EndScene, pDevice, , , , , , , , , , , , , , )`
    /// 一列十几个空位。
    ///
    /// 它是**零宽节点**：区间形如 `[k, k)`，锚在该空位所在的逗号处。
    /// 零宽节点在不变量下是合法的（父仍包住它，兄弟仍不重叠），
    /// 见测试 `语法树_零宽节点_空实参可以表达`。
    空实参 = 50,

    // ── 61..79 注释与空白的归属 ────────────────────────────────────────────
    /// 注释的归属节点（整行注释或行尾注释）。
    注释 = 61,
    /// 空白的归属节点（缩进与行内空白）。
    空白 = 62,
    /// 换行的归属节点。
    换行 = 63,
}

impl 节点种类 {
    pub fn 自号(号: u16) -> Option<Self> {
        use 节点种类::*;
        Some(match 号 {
            1 => 程序,
            2 => 源单元,
            3 => 支持库声明,
            4 => 程序集,
            5 => 程序集变量声明,
            6 => 全局变量声明,
            7 => 局部变量声明,
            8 => 子程序,
            9 => 参数声明,
            10 => 数据类型声明,
            11 => 数据成员声明,
            12 => DLL命令声明,
            13 => 常量声明,
            21 => 赋值语句,
            22 => 调用语句,
            23 => 返回语句,
            24 => 置入代码语句,
            25 => 块语句,
            26 => 判断块,
            27 => 判断分支,
            41 => 文本字面量,
            42 => 数值字面量,
            43 => 常量引用,
            44 => 标识符引用,
            45 => 命令调用,
            46 => 成员访问,
            47 => 下标访问,
            48 => 一元运算,
            49 => 二元运算,
            50 => 空实参,
            61 => 注释,
            62 => 空白,
            63 => 换行,
            _ => return None,
        })
    }

    pub fn 号(&self) -> u16 {
        *self as u16
    }

    /// 是否**语句级或声明级**节点。
    ///
    /// 这是「注释与空白挂给谁」的判据：注释 / 空白 / 换行节点**只挂**在语句级或
    /// 声明级节点之下（挂在包含它的最内层那一个）；若没有这样的节点，则挂根节点。
    /// 挂到表达式层会让同一段空白有两个合理归属，破坏唯一性。
    pub fn 是否语句级或声明级(&self) -> bool {
        matches!(self.号(), 1..=19 | 21..=39 | 61..=63)
    }
}

/// 一个语法树节点。**形状冻结**。
///
/// - `原文区间` 是**字节**区间 `[起, 止)`，指向 `super::记号流::原文`。
/// - `子区间` 是**直接子节点在 `super::语法树::节点表` 里的下标**区间 `[起, 止)`。
///   空子节点写 `(k, k)`。**注意它不是字节区间，是下标区间。**
///
/// 字段**不是公开面**（`pub(crate)`）：单个节点自身没有可判的不变量（区间是否越界、
/// 子区间是否越界、父包不包住它、兄弟重不重叠，全是**节点表 + 根**的性质），
/// 所以那些不变量不在 [`节点::新`] / [`节点::叶`] 里判，而在唯一构造口
/// [`super::语法树::新建`] 里一次判死。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 节点 {
    pub(crate) 种类: 节点种类,
    /// 覆盖的原文字节区间 `[起, 止)`。
    pub(crate) 原文区间: (u32, u32),
    /// 直接子节点的下标区间 `[起, 止)`；空写 `(k, k)`。
    pub(crate) 子区间: (u32, u32),
}

impl 节点 {
    pub fn 新(种类: 节点种类, 原文区间: (u32, u32), 子区间: (u32, u32)) -> Self {
        Self { 种类, 原文区间, 子区间 }
    }

    /// 无子节点的叶子。
    pub fn 叶(种类: 节点种类, 原文区间: (u32, u32)) -> Self {
        Self { 种类, 原文区间, 子区间: (0, 0) }
    }

    pub fn 起(&self) -> u32 {
        self.原文区间.0
    }

    pub fn 止(&self) -> u32 {
        self.原文区间.1
    }

    /// 本节点的原文区间是否包住另一区间（**含端点相等**）。
    pub fn 包住(&self, 子起: u32, 子止: u32) -> bool {
        self.起() <= 子起 && 子止 <= self.止()
    }
}

