//! 记号流定义 —— 记号流 · 原文 · 切片 · 还原 · 校验。
//!
//! 源出 `语言面.rs` 第 148–251 行，**逐字搬家**。
//!
//! `校验` 里那六条记号层不变量与它们的反向样本（`形状测试/记号层.rs`）是**一对**：
//! 拆的时候刻意没把它们分到两个不相干的文件里（见返回说明第 4 条）。

use super::{记号, 记号种类, 形状错误};

/// 记号流：**原文 + 记号表**。
///
/// 原文随记号流一起走，是为了让「区间首尾相接且覆盖全文」这条不变量
/// **在记号流内部就可判定**，也让 1101 的产物自足（不依赖调用方还留着那份文本）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 记号流 {
    /// 全文原始字节（语料实测为 GBK；形状与编码无关）。
    pub 原文: Vec<u8>,
    /// 记号表。**必须首尾相接且覆盖全文**（见 [`记号流::校验`]）。
    pub 记号表: Vec<记号>,
}

impl 记号流 {
    /// 裸构造：**不校验**。要一份保证合法的记号流，用 [`记号流::校验`]。
    pub fn 新建(原文: Vec<u8>, 记号表: Vec<记号>) -> Self {
        Self { 原文, 记号表 }
    }

    pub fn 全文长(&self) -> u32 {
        self.原文.len() as u32
    }

    /// 按区间切出该记号的原文切片。区间越界返回 `None`（不 panic）。
    pub fn 切片(&self, 第几个: usize) -> Option<&[u8]> {
        let t = self.记号表.get(第几个)?;
        self.原文.get(t.起 as usize..t.止 as usize)
    }

    /// **不变量见证**：把所有记号的区间按序拼起来。
    ///
    /// 这不是生成算法 —— 它不做任何词法判断（不分类、不合并、不跳字节、不补字节），
    /// 只是「区间 → 字节」的机械映射。若 [`记号流::校验`] 通过，本函数必然返回
    /// 与 [`记号流::原文`] **逐字节相同**的字节（见测试 `记号流_真实语料小样例_…`）。
    pub fn 还原(&self) -> Vec<u8> {
        let mut 出 = Vec::with_capacity(self.原文.len());
        for t in &self.记号表 {
            if let Some(片) = self.原文.get(t.起 as usize..t.止 as usize) {
                出.extend_from_slice(片);
            }
        }
        出
    }

    /// 校验全部记号层不变量。返回**第一条**违反，结构化，不 panic、不返回字符串。
    pub fn 校验(&self) -> Result<(), 形状错误> {
        use 形状错误::*;
        let 全文长 = self.全文长();

        if self.记号表.is_empty() {
            return Err(记号表为空);
        }

        for i in 0..self.记号表.len() {
            let t = self.记号表[i];
            let 第几个 = i as u32;
            if t.起 > t.止 {
                return Err(记号区间倒置 { 第几个, 起: t.起, 止: t.止 });
            }
            if t.止 > 全文长 {
                return Err(记号区间越界 { 第几个, 止: t.止, 全文长 });
            }
            if i > 0 {
                let 前止 = self.记号表[i - 1].止;
                if t.起 > 前止 {
                    return Err(记号有缝隙 { 第几个, 前止, 后起: t.起 });
                }
                if t.起 < 前止 {
                    return Err(记号有重叠 { 第几个, 前止, 后起: t.起 });
                }
            }
        }

        if self.记号表[0].起 != 0 {
            return Err(记号起点不为零 { 起: self.记号表[0].起 });
        }

        // 文件结束：只允许一个，且必须在末位、必须零宽、必须锚在全文末尾。
        let 末 = self.记号表.len() - 1;
        for (i, t) in self.记号表.iter().enumerate() {
            if t.种类 == 记号种类::文件结束 && i != 末 {
                return Err(文件结束不在末位 { 第几个: i as u32 });
            }
        }
        let 末记号 = &self.记号表[末];
        if 末记号.种类 != 记号种类::文件结束 {
            return Err(末记号非文件结束 { 第几个: 末 as u32, 种类: 末记号.种类 });
        }
        if 末记号.起 != 末记号.止 {
            return Err(文件结束非零宽 { 起: 末记号.起, 止: 末记号.止 });
        }
        if 末记号.止 != 全文长 {
            return Err(记号流未覆盖全文 { 覆盖到: 末记号.止, 全文长 });
        }

        Ok(())
    }

    /// 合法的记号流：校验通过才交出。
    pub fn 校验过(原文: Vec<u8>, 记号表: Vec<记号>) -> Result<Self, 形状错误> {
        let 流 = Self::新建(原文, 记号表);
        流.校验()?;
        Ok(流)
    }
}
