//!
//! 源出 `语言面.rs` 第 148–251 行，**逐字搬家**。
//!
//! **记号层 6 条不变量（J1–J6）在唯一构造口 [`记号流::新建`] 里判死**：字段是 `pub(crate)`，
//! 本模块之外只有 [`记号流::新建`] 一个入口 ⇒ **非法值构造不出来**，不再靠反向样本测试维持
//! （依据 `项目文档/决策记录/2026-09-26_验证面的边界.md` §三）。
//! 判定体（[`记号流::校验`]）与它的「每类坏输入报出正确码」样本（`形状测试/记号层.rs`）
//! 是**一对**：拆的时候刻意没把它们分到两个不相干的文件里（见返回说明第 4 条）。

use super::{记号, 记号种类, 形状错误};

/// 记号流：**原文 + 记号表**。
///
/// 原文随记号流一起走，是为了让「区间首尾相接且覆盖全文」这条不变量
/// **在记号流内部就可判定**，也让 1101 的产物自足（不依赖调用方还留着那份文本）。
///
/// 两个字段都**不是公开面**（`pub(crate)`）：本类型只能经 [`记号流::新建`] 得到，
/// 而那一个入口先校验再交出 ——「首尾相接且覆盖全文」不是调用方要记得做的事，是类型的事。
///
/// **信任边界定在本 crate（`pub(crate)`），不是本模块 —— 这是已知且有意的事实。**
/// 本 crate 内仍可用结构体字面量绕开 [`记号流::新建`] 造出不校验的值；要做到「本 crate 内
/// 也构造不出来」得把字段改纯私有、再加 11 个只读访问器，**本仓不这么做**。口径与理由：
/// 老仓《设计哲学》第 2.1 条「支持库＝**最小原子能力**」把边界画在**库**这一层，而 V1 的
/// 扩展就是**一个 crate**（`扩展根目录/原子支持库/编译器支持库`）⇒ 库内即信任域；
/// `项目文档/设计哲学.md` §二「**冻结边界、内部自由**：内部实现可以随时改」同一条。
/// 跨 crate 的调用方（底座 / 别的扩展）**只有** [`记号流::新建`] 一个入口。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 记号流 {
    /// 全文原始字节（语料实测为 GBK）。**形状不是与编码无关的** ——
    /// `记号种类::关键字` 不带「是哪一个」，关键字身份只能按区间文本比对 ⇒ 编码一变结果就变
    /// （见 `src/语法/测试/真形状其余.rs::GBK原文_关键字认不出_落到兜底但仍建出合法树`）。
    pub(crate) 原文: Vec<u8>,
    /// 记号表。**必须首尾相接且覆盖全文**（见 [`记号流::新建`]）。
    pub(crate) 记号表: Vec<记号>,
}

impl 记号流 {
    /// **唯一构造口**：校验通过才交出。非法值构造不出来。
    ///
    /// 记号层 6 条不变量全在这里判死（判定体是 [`记号流::校验`]，返回**第一条**违反）：
    ///
    /// | # | 不变量（一句话） | 报的码 |
    /// |---|---|---|
    /// | **J1** | 记号表非空，且末位**有且仅有一枚零宽 `文件结束`**，锚在 `[全文长, 全文长)` | 1108 / 1114 / 1115 / 1116 |
    /// | **J2** | 首记号的 `起` == 0 | 1109 |
    /// | **J3** | 相邻两记号满足 `前.止 == 后.起`（**无缝隙**） | 1112 |
    /// | **J4** | 相邻两记号满足 `前.止 <= 后.起`（**无重叠**） | 1113 |
    /// | **J5** | 末记号的 `止` == 全文长（**覆盖全文**） | 1117 |
    /// | **J6** | 每枚记号的 `起 <= 止 <= 全文长` | 1110 / 1111 |
    ///
    /// **外加一条形状承诺的边界**：单份源文本上限 4 GiB（区间宽 `u32`）。超限在这里
    /// **fail-closed** 报 1137，**不许静默截断** —— `全文长()` 是 `原文.len() as u32`，
    /// 若不判，超限原文会悄悄截短、记号区间与它一起失真（`说明/语言面形状.md` §一）。
    /// 「>4 GiB 不在形状承诺内」是明写的口径；这里只是把「不承诺」落成**明确失败**。
    ///
    /// 每条「为什么必须有」与「违反会导致什么后果」逐字见 `说明/语言面形状.md` §四 4.1
    /// 与 [`形状错误`] 各变体的注释 —— 那些说明一字未动。
    pub fn 新建(原文: Vec<u8>, 记号表: Vec<记号>) -> Result<Self, 形状错误> {
        // 形状承诺的边界：单份源文本 ≤ 4 GiB。超限 fail-closed（不截断）。
        if 原文.len() > u32::MAX as usize {
            return Err(形状错误::词法层输入非法);
        }
        let 输出流 = Self { 原文, 记号表 };
        输出流.校验()?;
        Ok(输出流)
    }

    pub fn 全文长(&self) -> u32 {
        self.原文.len() as u32
    }

    /// 按区间切出该记号的原文切片。区间越界返回 `None`（不 panic）。
    pub fn 切片(&self, 第几个: usize) -> Option<&[u8]> {
        let 本记号 = self.记号表.get(第几个)?;
        self.原文.get(本记号.起 as usize..本记号.止 as usize)
    }

    /// **不变量见证**：把所有记号的区间按序拼起来。
    ///
    /// 这不是生成算法 —— 它不做任何词法判断（不分类、不合并、不跳字节、不补字节），
    /// 只是「区间 → 字节」的机械映射。若 [`记号流::校验`] 通过，本函数必然返回
    /// 与 `记号流::原文` **逐字节相同**的字节（见测试 `记号流_真实语料小样例_…`）。
    pub fn 还原(&self) -> Vec<u8> {
        let mut 输出缓冲 = Vec::with_capacity(self.原文.len());
        for 本记号 in &self.记号表 {
            if let Some(片段) = self.原文.get(本记号.起 as usize..本记号.止 as usize) {
                输出缓冲.extend_from_slice(片段);
            }
        }
        输出缓冲
    }

    /// 校验全部记号层不变量。返回**第一条**违反，结构化，不 panic、不返回字符串。
    ///
    /// 这是 [`记号流::新建`] 的判定体。拿到一份 `&记号流` 的调用方不必再调它
    /// （那份值必然已经过这里），留着它是为了让判定体与它的说明同在一处、可单独读。
    pub fn 校验(&self) -> Result<(), 形状错误> {
        use 形状错误::*;
        let 全文长 = self.全文长();

        if self.记号表.is_empty() {
            return Err(记号表为空);
        }

        for 记号位次 in 0..self.记号表.len() {
            let 本记号 = self.记号表[记号位次];
            let 第几个 = 记号位次 as u32;
            if 本记号.起 > 本记号.止 {
                return Err(记号区间倒置 { 第几个, 起: 本记号.起, 止: 本记号.止 });
            }
            if 本记号.止 > 全文长 {
                return Err(记号区间越界 { 第几个, 止: 本记号.止, 全文长 });
            }
            if 记号位次 > 0 {
                let 前止 = self.记号表[记号位次 - 1].止;
                if 本记号.起 > 前止 {
                    return Err(记号有缝隙 { 第几个, 前止, 后起: 本记号.起 });
                }
                if 本记号.起 < 前止 {
                    return Err(记号有重叠 { 第几个, 前止, 后起: 本记号.起 });
                }
            }
        }

        if self.记号表[0].起 != 0 {
            return Err(记号起点不为零 { 起: self.记号表[0].起 });
        }

        // 文件结束：只允许一个，且必须在末位、必须零宽、必须锚在全文末尾。
        let 尾部 = self.记号表.len() - 1;
        for (记号位次, 本记号) in self.记号表.iter().enumerate() {
            if 本记号.种类 == 记号种类::文件结束 && 记号位次 != 尾部 {
                return Err(文件结束不在末位 { 第几个: 记号位次 as u32 });
            }
        }
        let 末记号 = &self.记号表[尾部];
        if 末记号.种类 != 记号种类::文件结束 {
            return Err(末记号非文件结束 { 第几个: 尾部 as u32, 种类: 末记号.种类 });
        }
        if 末记号.起 != 末记号.止 {
            return Err(文件结束非零宽 { 起: 末记号.起, 止: 末记号.止 });
        }
        if 末记号.止 != 全文长 {
            return Err(记号流未覆盖全文 { 覆盖到: 末记号.止, 全文长 });
        }

        Ok(())
    }
}

