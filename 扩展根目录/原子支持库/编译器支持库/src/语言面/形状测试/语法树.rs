//! 语法树层 —— 唯一构造口对每类坏输入报出正确码 · 样例的子树止与子区间。
//!
//! 语法树层 5 条不变量（T1–T5）**已在唯一构造口 `语法树::新建` 里判死**，不再靠测试维持
//! （依据 `项目文档/决策记录/2026-09-26_验证面的边界.md` §三：①类错用类型消灭，不用测试维持）。
//! 所以这里只剩两件事：
//!
//! 1. **构造器对每类坏输入报出正确码** —— 「哪一类坏输入配哪一个码」是判据，类型表达不了；
//! 2. **函数实现行为**（`子树止` · `子区间` · `原文切片`）—— 构造期不变量保证不了它们写对。
//!
//! 原来 8 条测试的去向：6 条反向样本 + 「根区间必须等于全文」并入第 1 件事（每类一行）；
//! 「手工构造的节点表通过全部不变量」由构造期判死而删除，其中 `子树止`/`子区间`/`原文切片`
//! 的实现行为保留为第 2 件事；「零宽节点」的合法性由 T2/T3 判死（含端点相等），
//! 它的切片行为也留在第 2 件事里。逐条对应见 `说明/语言面形状.md` §四 4.2。
//!
//! **一处实测事实**：`形状错误::节点被重复到达`（码 1131）在 `校验` 的检查顺序下**够不着** ——
//! 走到可达遍历之前，「除根外每个下标恰好被一个 `子区间` 包含」已经判过，
//! 每个节点最多被入栈一次，所以「重复到达」不可能发生。它没有坏输入样本，故本表 15 行
//! （语法树层 16 个变体减去它）。

