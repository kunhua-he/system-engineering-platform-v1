/// 真实语料小样例：**手工构造**的节点表（不是解析出来的），通过全部不变量。
///
/// 先序布局：
/// ```text
/// 0 程序        [0, 全文)   子 (1,2)
/// 1 源单元      [0, 全文)   子 (2,3)
/// 2 子程序      [13, 全文)  子 (3,5)
/// 3 空白        [32,36)     子 (4,4)   ← 4 空格缩进
/// 4 返回语句    [36, 全文)  子 (5,8)
/// 5 数值字面量  [44,45)     子 (6,6)   ← “0”
/// 6 注释        [48,56)     子 (7,7)   ← 行尾注释
/// 7 换行        [56,58)     子 (8,8)
/// ```
/// 注意：`返回语句` 的区间里有 `返回 (` 与 `)  ` 若干字节**不属于任何子节点** ——
/// 这是允许的：字节归属由**记号层**保证（记号首尾相接覆盖全文），
/// 语法树只保证「根 == 全文 + 父包住子 + 兄弟不重叠」。
fn 样例语法树() -> 语法树 {
    let 记号流 = 样例记号流();
    let 全文长 = 记号流.全文长();
    let 子程序起 = 区间(样例原文, ".子程序").0;
    let 缩进 = 区间(样例原文, "    返回");
    let 返回 = 区间(样例原文, "返回 (0)");
    let 零 = 区间(样例原文, "0)");
    let 注释 = 区间(样例原文, "' 注释");
    let 末换行 = (注释.1, 全文长);

    let 节点表 = vec![
        节点::新(节点种类::程序, (0, 全文长), (1, 2)),
        节点::新(节点种类::源单元, (0, 全文长), (2, 3)),
        节点::新(节点种类::子程序, (子程序起, 全文长), (3, 5)),
        节点::叶(节点种类::空白, (缩进.0, 缩进.0 + 4)),
        节点::新(节点种类::返回语句, (返回.0, 全文长), (5, 8)),
        节点::叶(节点种类::数值字面量, (零.0, 零.0 + 1)),
        节点::叶(节点种类::注释, 注释),
        节点::叶(节点种类::换行, 末换行),
    ];
    语法树::新建(记号流, 节点表, 0)
}

#[test]
fn 语法树_真实语料小样例_手工构造的节点表通过全部不变量() {
    let 树 = 样例语法树();
    树.校验().expect("手工构造的样例语法树应当合法");

    // 根区间 == 全文
    let 根 = 树.根节点().unwrap();
    assert_eq!(根.原文区间, (0, 树.全文长()));
    assert_eq!(根.种类, 节点种类::程序);
    assert_eq!(树.原文切片(0), Some(样例原文.as_bytes()));

    // 子树连续：根子树铺满整张节点表
    assert_eq!(树.子树止(0), Some(树.节点表.len() as u32));
    // 子程序子树 = [2, 8)
    assert_eq!(树.子树止(2), Some(8));
    // 返回语句子树 = [4, 8)
    assert_eq!(树.子树止(4), Some(8));
    // 叶子
    assert_eq!(树.子树止(3), Some(4));
    assert_eq!(树.子树止(7), Some(8));

    // 子区间语义：直接子节点
    assert_eq!(树.子区间(4), Some((5, 8)));
    assert_eq!(树.原文切片(6), Some("' 注释".as_bytes()));
}

/// 不变量 T1：**根节点的原文区间必须等于全文**。
#[test]
fn 语法树_根区间必须等于全文() {
    let 流 = 样例记号流();
    let 长 = 流.全文长();
    let 好 = 语法树::新建(流.clone(), vec![节点::叶(节点种类::程序, (0, 长))], 0);
    好.校验().expect("根区间等于全文应当合法");

    let 短了 = 语法树::新建(流.clone(), vec![节点::叶(节点种类::程序, (0, 长 - 1))], 0);
    assert!(matches!(
        短了.校验(),
        Err(形状错误::根区间不等于全文 { 起: 0, .. })
    ));

    let 起晚了 = 语法树::新建(流.clone(), vec![节点::叶(节点种类::程序, (1, 长))], 0);
    assert!(matches!(
        起晚了.校验(),
        Err(形状错误::根区间不等于全文 { 起: 1, .. })
    ));
}

