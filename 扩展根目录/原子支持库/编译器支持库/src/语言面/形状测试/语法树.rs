/// **构造器对每类坏输入报出正确码**（每类一条，断言码正确）。
#[test]
fn 语法树_构造器对每类坏输入报出正确码() {
    let 项表 = 坏输入表();
    assert_eq!(项表.len(), 15, "语法树层 15 类够得着的坏输入，一类不许漏");
    for 一条坏输入 in 项表 {
        let 实得 = 语法树::新建(样例记号流(), 一条坏输入.节点表, 一条坏输入.根)
            .err()
            .unwrap_or_else(|| panic!("{}：非法语法树应当构造不出来", 一条坏输入.名字));
        assert_eq!(实得, 一条坏输入.期望, "{}：报的变体不对", 一条坏输入.名字);
        assert_eq!(crate::形状错误码(&实得), 一条坏输入.期望码, "{}：报的码不对", 一条坏输入.名字);
    }
}

/// **函数实现行为**：`子树止` · `子区间` · `原文切片` · `根节点`（含零宽节点的切片）。
///
/// 这些不是不变量（不变量已在构造期判死）：T5 保证「先序连续」成立，
/// 但保证不了 `子树止` 真按「最后一个子节点一路到底」算、`原文切片` 真按区间切。
#[test]
fn 语法树_样例子树止与子区间() {
    let 语法树 = 样例语法树();

    // 根区间 == 全文，根节点是 程序
    let 根目录 = 语法树.根节点().unwrap();
    assert_eq!(根目录.原文区间, (0, 语法树.全文长()));
    assert_eq!(根目录.种类, 节点种类::程序);
    assert_eq!(语法树.原文切片(0), Some(样例原文.as_bytes()));

    // 子树连续：根子树铺满整张节点表
    assert_eq!(语法树.子树止(0), Some(语法树.节点表.len() as u32));
    // 子程序子树 = [2, 8)
    assert_eq!(语法树.子树止(2), Some(8));
    // 返回语句子树 = [4, 8)
    assert_eq!(语法树.子树止(4), Some(8));
    // 叶子
    assert_eq!(语法树.子树止(3), Some(4));
    assert_eq!(语法树.子树止(7), Some(8));

    // 子区间是**先序子树区间**：4 号（返回语句）的直接子 5/6/7 都是叶，故区间就是 (5,8)。
    assert_eq!(语法树.取子节点区间(4), Some((5, 8)));
    assert_eq!(语法树.原文切片(6), Some("' 注释".as_bytes()));

    // 直接子：唯一走法（跳子树，`子树止` 逐跳）。
    // 2 号（子程序）的直接子是 3（缩进空白）与 4（返回语句，**带整棵子树 [4,8)**）——
    // 4 之后不是 5 而是 8（4 的子树止）；这正是「逐下标 +1」会走错的地方。
    assert_eq!(语法树.直接子(2).collect::<Vec<_>>(), vec![3, 4]);
    assert_eq!(语法树.直接子(4).collect::<Vec<_>>(), vec![5, 6, 7]);
    assert_eq!(语法树.直接子(3).collect::<Vec<_>>(), Vec::<u32>::new(), "叶没有直接子");
    // 非直接子（2 的后代 4/5/6/7）不出现在 2 的直接子里 —— 区间里夹的是后代，不是兄弟。
    assert!(!语法树.直接子(2).any(|子项| 子项 > 4));

    // 零宽节点（`空实参`）可以表达「空实参」：语料里 `…, , , , )` 那种空位。
    // 它的**合法性**由构造期 T2/T3 判死（空区间被任何区间包含；`后.起 >= 前.止` 对零宽成立），
    // 这里只断言它的切片是空字节、兄弟仍不重叠。
    let 原文 = "调用 (首参, , 次参)";
    let 输出流 = 造记号流(
        原文,
        &[
            (记号种类::标识符, "调用"),
            (记号种类::空白, " "),
            (记号种类::界符, "("),
            (记号种类::标识符, "首参"),
            (记号种类::界符, ","),
            (记号种类::空白, " "),
            (记号种类::界符, ","),
            (记号种类::空白, " "),
            (记号种类::标识符, "次参"),
            (记号种类::界符, ")"),
        ],
    );
    let 长度 = 输出流.全文长();
    let 首参 = 取片段字节区间(原文, "首参");
    let 空位 = 首参.1; // 落在「首参」之后的那个逗号处，零宽
    let 次参 = 取片段字节区间(原文, "次参");
    // 0 调用语句 子 (1,4)；1 标识符 首参；2 空实参（零宽）；3 标识符 次参
    let 语法树 = 语法树::新建(
        输出流,
        vec![
            节点::新建(节点种类::调用语句, (0, 长度), (1, 4)),
            节点::叶节点(节点种类::标识符引用, 首参),
            节点::叶节点(节点种类::空实参, (空位, 空位)),
            节点::叶节点(节点种类::标识符引用, 次参),
        ],
        0,
    )
    .expect("零宽的空实参节点应当合法");
    let 空实参节点 = &语法树.节点表[2];
    assert_eq!(空实参节点.原文区间.0, 空实参节点.原文区间.1, "空实参必须是零宽节点");
    assert_eq!(语法树.原文切片(2), Some(&b""[..]));
    // 零宽节点夹在两个兄弟之间，兄弟仍不重叠（后.起 >= 前.止）
    assert!(语法树.节点表[1].取原文终点() <= 语法树.节点表[2].取原文起点());
    assert!(语法树.节点表[2].取原文终点() <= 语法树.节点表[3].取原文起点());
}
