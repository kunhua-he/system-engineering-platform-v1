/// 真实语料小样例：**手工构造**的节点表（不是解析出来的），通过全部不变量。
///
/// 先序布局（`子区间` 是**先序子树区间**：从第一个直接子起、到最后一个直接子的整棵子树之后）：
/// ```text
/// 0 程序        [0, 全文)   子 (1,8)   ← 唯一子是 1，它的子树到 8
/// 1 源单元      [0, 全文)   子 (2,8)   ← 唯一子是 2，它的子树到 8
/// 2 子程序      [13, 全文)  子 (3,8)   ← 直接子是 3 与 4；4 的子树到 8
/// 3 空白        [32,36)     子 (4,4)   ← 4 空格缩进（叶）
/// 4 返回语句    [36, 全文)  子 (5,8)   ← 三个直接子 5/6/7 都是叶
/// 5 数值字面量  [44,45)     子 (6,6)   ← “0”
/// 6 注释        [48,56)     子 (7,7)   ← 行尾注释
/// 7 换行        [56,58)     子 (8,8)
/// ```
/// 注意：`返回语句` 的区间里有 `返回 (` 与 `)  ` 若干字节**不属于任何子节点** ——
/// 这是允许的：字节归属由**记号层**保证（记号首尾相接覆盖全文），
/// 语法树只保证「根 == 全文 + 父包住子 + 兄弟不重叠」。
fn 样例语法树() -> 语法树 {
    let 记号流 = 样例记号流();
    let 全文长 = 记号流.全文长();
    let 子程序起 = 取片段字节区间(样例原文, ".子程序").0;
    let 缩进 = 取片段字节区间(样例原文, "    返回");
    let 返回 = 取片段字节区间(样例原文, "返回 (0)");
    let 数值区间 = 取片段字节区间(样例原文, "0)");
    let 注释 = 取片段字节区间(样例原文, "' 注释");
    let 末换行 = (注释.1, 全文长);

    let 节点表 = vec![
        节点::新建(节点种类::程序, (0, 全文长), (1, 8)),
        节点::新建(节点种类::源单元, (0, 全文长), (2, 8)),
        节点::新建(节点种类::子程序, (子程序起, 全文长), (3, 8)),
        节点::叶节点(节点种类::空白, (缩进.0, 缩进.0 + 4)),
        节点::新建(节点种类::返回语句, (返回.0, 全文长), (5, 8)),
        节点::叶节点(节点种类::数值字面量, (数值区间.0, 数值区间.0 + 1)),
        节点::叶节点(节点种类::注释, 注释),
        节点::叶节点(节点种类::换行, 末换行),
    ];
    语法树::新建(记号流, 节点表, 0).expect("手工构造的样例语法树必须合法")
}

/// 一行坏输入：名字 · 节点表 · 根 · 期望报出的形状错误 · 期望的码。
///
/// 码取 `crate::错误码` 的登记常量（`lib.rs`），不在这里另抄一份数字。
struct 坏输入样本 {
    名字: &'static str,
    节点表: Vec<节点>,
    根: u32,
    期望: 形状错误,
    期望码: u32,
}

