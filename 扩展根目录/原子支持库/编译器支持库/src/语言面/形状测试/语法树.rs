/// **零宽节点**可以表达「空实参」（语料里 `…, , , , )` 那种空位）。
#[test]
fn 语法树_零宽节点_空实参可以表达() {
    // 原文：`调用 (甲, , 乙)`
    let 原文 = "调用 (甲, , 乙)";
    let 流 = 造记号流(
        原文,
        &[
            (记号种类::标识符, "调用"),
            (记号种类::空白, " "),
            (记号种类::界符, "("),
            (记号种类::标识符, "甲"),
            (记号种类::界符, ","),
            (记号种类::空白, " "),
            (记号种类::界符, ","),
            (记号种类::空白, " "),
            (记号种类::标识符, "乙"),
            (记号种类::界符, ")"),
        ],
    );
    流.校验().expect("记号流应当合法");

    let 长 = 流.全文长();
    let 甲 = 区间(原文, "甲");
    let 空位 = 甲.1; // 落在「甲」之后的那个逗号处，零宽
    let 乙 = 区间(原文, "乙");

    // 0 调用语句 子 (1,4)；1 标识符 甲；2 空实参（零宽）；3 标识符 乙
    let 树 = 语法树::新建(
        流,
        vec![
            节点::新(节点种类::调用语句, (0, 长), (1, 4)),
            节点::叶(节点种类::标识符引用, 甲),
            节点::叶(节点种类::空实参, (空位, 空位)),
            节点::叶(节点种类::标识符引用, 乙),
        ],
        0,
    );
    树.校验().expect("零宽的空实参节点应当合法");
    let 空 = &树.节点表[2];
    assert_eq!(空.原文区间.0, 空.原文区间.1, "空实参必须是零宽节点");
    assert_eq!(树.原文切片(2), Some(&b""[..]));
    // 零宽节点夹在两个兄弟之间，兄弟仍不重叠（后.起 >= 前.止）
    assert!(树.节点表[1].止() <= 树.节点表[2].起());
    assert!(树.节点表[2].止() <= 树.节点表[3].起());
}
