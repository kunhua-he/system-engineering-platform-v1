//! 形状测试夹具 —— 样例原文 · 样例记号流（通用的 `造记号流` · `区间` 在 `crate::测试夹具`）。
//!
//! 源出 `语言面.rs` 测试模块的夹具段（第 733–793 行），**逐字搬家**，只去掉一层 4 空格缩进。
//! 这些是**夹具构造**（用 `find` 定位已知片段），不是词法分析器 —— 它们不判断片段该是什么种类。
//!
//! 两个夹具由 `私有` 放宽到 `pub(super)`：拆分后同层的三个测试件要共用它们。
//! 测试子树整个挂在 `#[cfg(test)]` 下，故这不改变任何公开面。

use crate::语言面::{记号流, 记号种类};
use crate::测试夹具::造记号流;

/// 真实语料小样例（照 `samples/e8/ManyFiles/e8test3.txt` 的形态缩到一行语句）。
///
/// 原文（测试里用 UTF-8 写，形状是字节区间）。**形状不是与编码无关的**：
/// 关键字身份只能按区间文本比对，编码一变结果就变
/// （见 `src/语法/测试/真形状其余.rs::GBK原文_关键字认不出_落到兜底但仍建出合法树`）。
/// ```text
/// .版本 2
/// .子程序 启动
///     返回 (0)  ' 注释
/// ```
pub(super) const 样例原文: &str = ".版本 2\r\n.子程序 启动\r\n    返回 (0)  ' 注释\r\n";

pub(super) fn 样例记号流() -> 记号流 {
    造记号流(
        样例原文,
        &[
            (记号种类::关键字, ".版本"),
            (记号种类::空白, " "),
            (记号种类::数值字面量, "2"),
            (记号种类::换行, "\r\n"),
            (记号种类::关键字, ".子程序"),
            (记号种类::空白, " "),
            (记号种类::标识符, "启动"),
            (记号种类::换行, "\r\n"),
            (记号种类::空白, "    "),
            (记号种类::关键字, "返回"),
            (记号种类::空白, " "),
            (记号种类::界符, "("),
            (记号种类::数值字面量, "0"),
            (记号种类::界符, ")"),
            (记号种类::空白, "  "),
            (记号种类::注释, "' 注释"),
            (记号种类::换行, "\r\n"),
        ],
    )
}
