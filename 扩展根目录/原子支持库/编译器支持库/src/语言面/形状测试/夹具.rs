//! 形状测试夹具 —— 造记号流 · 区间 · 样例原文 · 样例记号流。
//!
//! 源出 `语言面.rs` 测试模块的夹具段（第 733–793 行），**逐字搬家**，只去掉一层 4 空格缩进。
//! 这些是**夹具构造**（用 `find` 定位已知片段），不是词法分析器 —— 它们不判断片段该是什么种类。
//!
//! 四个夹具由 `私有` 放宽到 `pub(super)`：拆分后同层的三个测试件要共用它们。
//! 测试子树整个挂在 `#[cfg(test)]` 下，故这不改变任何公开面。

use crate::语言面::{记号, 记号流, 记号种类};

/// 夹具：在 `原文` 里按顺序找出一串片段，拼成首尾相接的记号表，末尾补 `文件结束`。
///
/// 这是**夹具构造**（用 `find` 定位已知片段），不是词法分析器 ——
/// 它不判断片段该是什么种类，种类由调用方给定。
///
/// 出口走唯一构造口 `记号流::新建`：夹具自己铺不满全文就当场自爆
/// （夹具给的是**合法**输入，铺不满是夹具的错，不是形状的错）。
pub(super) fn 造记号流(原文: &str, 表: &[(记号种类, &str)]) -> 记号流 {
    let 字节 = 原文.as_bytes().to_vec();
    let mut 记号表 = Vec::new();
    let mut 游标 = 0usize;
    for (种类, 片段) in 表 {
        let 相对 = 原文[游标..].find(片段).expect("夹具片段在原文里找不到");
        let 起 = 游标 + 相对;
        let 止 = 起 + 片段.len();
        记号表.push(记号::新(*种类, 起 as u32, 止 as u32));
        游标 = 止;
    }
    assert_eq!(游标, 字节.len(), "夹具片段没铺满全文");
    let 长 = 字节.len() as u32;
    记号表.push(记号::新(记号种类::文件结束, 长, 长));
    记号流::新建(字节, 记号表).expect("夹具造的记号流必须合法")
}

/// 夹具：取 `原文` 里某片段的字节区间。
pub(super) fn 区间(原文: &str, 片段: &str) -> (u32, u32) {
    let 起 = 原文.find(片段).expect("夹具片段在原文里找不到");
    (起 as u32, (起 + 片段.len()) as u32)
}

/// 真实语料小样例（照 `samples/e8/ManyFiles/e8test3.txt` 的形态缩到一行语句）。
///
/// 原文（测试里用 UTF-8 写，形状是字节区间，与编码无关）：
/// ```text
/// .版本 2
/// .子程序 启动
///     返回 (0)  ' 注释
/// ```
pub(super) const 样例原文: &str = ".版本 2\r\n.子程序 启动\r\n    返回 (0)  ' 注释\r\n";

pub(super) fn 样例记号流() -> 记号流 {
    造记号流(
        样例原文,
        &[
            (记号种类::关键字, ".版本"),
            (记号种类::空白, " "),
            (记号种类::数值字面量, "2"),
            (记号种类::换行, "\r\n"),
            (记号种类::关键字, ".子程序"),
            (记号种类::空白, " "),
            (记号种类::标识符, "启动"),
            (记号种类::换行, "\r\n"),
            (记号种类::空白, "    "),
            (记号种类::关键字, "返回"),
            (记号种类::空白, " "),
            (记号种类::界符, "("),
            (记号种类::数值字面量, "0"),
            (记号种类::界符, ")"),
            (记号种类::空白, "  "),
            (记号种类::注释, "' 注释"),
            (记号种类::换行, "\r\n"),
        ],
    )
}
