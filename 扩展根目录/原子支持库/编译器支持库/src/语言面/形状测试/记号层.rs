/// 边界一：**空文件**。只有一枚零宽 `文件结束`，照样满足覆盖全文。
#[test]
fn 记号流_空文件_只有一枚零宽文件结束() {
    let 流 = 记号流::校验过(Vec::new(), vec![记号::新(记号种类::文件结束, 0, 0)])
        .expect("空文件应当是合法记号流");
    assert_eq!(流.记号表.len(), 1);
    assert_eq!(流.记号表[0].起, 0);
    assert_eq!(流.记号表[0].止, 0);
    assert_eq!(流.还原(), Vec::<u8>::new());
    assert!(流.校验().is_ok());
}

/// 边界二：**只有注释的文件**。区间照样首尾相接覆盖全文。
#[test]
fn 记号流_只有注释的文件_区间首尾相接且覆盖全文() {
    let 原文 = "' 整行注释\r\n";
    let 流 = 造记号流(
        原文,
        &[(记号种类::注释, "' 整行注释"), (记号种类::换行, "\r\n")],
    );
    流.校验().expect("只有注释的文件应当合法");
    assert_eq!(流.还原(), 原文.as_bytes());
    // 首尾相接：逐对相邻记号断言 前.止 == 后.起。
    for 对 in 流.记号表.windows(2) {
        assert_eq!(对[0].止, 对[1].起, "相邻记号必须首尾相接");
    }
    assert_eq!(流.记号表[0].起, 0);
    assert_eq!(流.记号表.last().unwrap().止, 流.全文长());
}

/// 真实语料小样例：区间首尾相接、覆盖全文、**拼接回来逐字节等于原文**。
#[test]
fn 记号流_真实语料小样例_区间首尾相接且逐字节还原原文() {
    let 流 = 样例记号流();
    流.校验().expect("样例记号流应当合法");
    // 首尾相接（无空隙、无重叠）
    for (i, 对) in 流.记号表.windows(2).enumerate() {
        assert_eq!(对[0].止, 对[1].起, "第 {i} 与第 {} 枚之间有缝隙或重叠", i + 1);
    }
    // 覆盖全文
    assert_eq!(流.记号表[0].起, 0);
    assert_eq!(流.记号表.last().unwrap().止, 流.全文长());
    // 逐字节还原
    assert_eq!(流.还原(), 样例原文.as_bytes());
    // 每个记号都能从区间切出自己的原文
    assert_eq!(流.切片(0), Some(&b".\xe7\x89\x88\xe6\x9c\xac"[..])); // “.版本”
    assert_eq!(流.切片(12), Some(&b"0"[..]));
}

/// 反向样本：**有缝隙**（漏掉了一枚空白）必须被检出。
#[test]
fn 记号流_反向_有缝隙被检出() {
    let 原文 = ".版本 2\r\n";
    let 全 = 造记号流(
        原文,
        &[
            (记号种类::关键字, ".版本"),
            (记号种类::空白, " "),
            (记号种类::数值字面量, "2"),
            (记号种类::换行, "\r\n"),
        ],
    );
    全.校验().expect("铺满全文的记号流应当合法");
    // 抽掉「空白」那一枚 ⇒ 出现缝隙
    let mut 记号表 = 全.记号表.clone();
    记号表.remove(1);
    let 坏 = 记号流::新建(原文.as_bytes().to_vec(), 记号表);
    match 坏.校验() {
        Err(形状错误::记号有缝隙 { 前止: 7, 后起: 8, .. }) => {}
        其他 => panic!("应当检出缝隙，实际：{其他:?}"),
    }
    // 见证：缝隙处的字节在还原时确实丢了
    assert_ne!(坏.还原(), 原文.as_bytes());
    assert_eq!(坏.还原(), ".版本2\r\n".as_bytes());
}

/// 反向样本：**有重叠**（同一字节两个归属）必须被检出。
#[test]
fn 记号流_反向_有重叠被检出() {
    let 原文 = ".版本 2\r\n";
    let 坏 = 记号流::新建(
        原文.as_bytes().to_vec(),
        vec![
            记号::新(记号种类::关键字, 0, 9),
            记号::新(记号种类::空白, 8, 10), // 8 与 9 重叠了一字节
            记号::新(记号种类::换行, 10, 12),
            记号::新(记号种类::文件结束, 12, 12),
        ],
    );
    assert!(matches!(坏.校验(), Err(形状错误::记号有重叠 { .. })));
}

/// 反向样本：**未覆盖到文件尾**必须被检出。
#[test]
fn 记号流_反向_未覆盖到文件尾被检出() {
    let 原文 = ".版本 2\r\n";
    let 坏 = 记号流::新建(
        原文.as_bytes().to_vec(),
        vec![
            记号::新(记号种类::关键字, 0, 9),
            // 剩下 3 字节没人认领，末尾也不放文件结束
        ],
    );
    assert!(matches!(坏.校验(), Err(形状错误::末记号非文件结束 { .. })));

    let 坏二 = 记号流::新建(
        原文.as_bytes().to_vec(),
        vec![
            记号::新(记号种类::关键字, 0, 9),
            记号::新(记号种类::文件结束, 9, 9), // 锚早了
        ],
    );
    assert!(matches!(
        坏二.校验(),
        Err(形状错误::记号流未覆盖全文 { 覆盖到: 9, 全文长: 11 })
    ));
}

/// 反向样本：`文件结束` 不在末位、或非零宽，必须被检出。
#[test]
fn 记号流_反向_文件结束位置或宽度不对被检出() {
    let 原文 = "abc";
    let 不在末位 = 记号流::新建(
        原文.as_bytes().to_vec(),
        vec![
            记号::新(记号种类::文件结束, 0, 0),
            记号::新(记号种类::标识符, 0, 3),
            记号::新(记号种类::文件结束, 3, 3),
        ],
    );
    assert!(matches!(
        不在末位.校验(),
        Err(形状错误::文件结束不在末位 { 第几个: 0 })
    ));

    let 非零宽 = 记号流::新建(
        原文.as_bytes().to_vec(),
        vec![
            记号::新(记号种类::标识符, 0, 2),
            记号::新(记号种类::文件结束, 2, 3),
        ],
    );
    assert!(matches!(
        非零宽.校验(),
        Err(形状错误::文件结束非零宽 { 起: 2, 止: 3 })
    ));
}
