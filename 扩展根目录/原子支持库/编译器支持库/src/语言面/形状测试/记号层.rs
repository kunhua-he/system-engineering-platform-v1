//! 记号层 —— 唯一构造口对每类坏输入报出正确码 · 样例的逐字节还原与切片。
//!
//! 记号层 6 条不变量（J1–J6）**已在唯一构造口 `记号流::新建` 里判死**，不再靠测试维持
//! （依据 `项目文档/决策记录/2026-09-26_验证面的边界.md` §三：①类错用类型消灭，不用测试维持）。
//! 所以这里只剩两件事：
//!
//! 1. **构造器对每类坏输入报出正确码** —— 「哪一类坏输入配哪一个码」是判据，类型表达不了；
//! 2. **函数实现行为**（`还原` 逐字节拼接 · `切片`）—— 构造期不变量保证不了那两条函数写对。
//!
//! 原来 7 条测试的去向：4 条反向样本并入第 1 件事（每类一行）；
//! 「首尾相接 / 覆盖全文 / 空文件合法」类断言由构造期判死而删除；
//! 「逐字节还原」保留为第 2 件事。逐条对应见 `说明/语言面形状.md` §四 4.1。

use super::夹具::*;
use crate::语言面::*;

/// 一行坏输入：名字 · 原文 · 记号表 · 期望报出的形状错误 · 期望的码。
///
/// 码取 `crate::错误码` 的登记常量（`lib.rs`），不在这里另抄一份数字。
struct 坏输入 {
    名字: &'static str,
    原文: &'static str,
    记号表: Vec<记号>,
    期望: 形状错误,
    期望码: u32,
}

/// 记号层 10 类坏输入，一类一行（J1–J6 各有对应，码 1108–1117 全覆盖）。
fn 坏输入表() -> Vec<坏输入> {
    use crate::错误码;
    let 样例 = 样例记号流();
    let 原文 = ".版本 2\r\n"; // 11 字节
    vec![
        坏输入 {
            名字: "记号表为空（连 文件结束 都没有）",
            原文: "",
            记号表: vec![],
            期望: 形状错误::记号表为空,
            期望码: 错误码::记号表为空,
        },
        坏输入 {
            名字: "记号起点不为零（全文开头有字节无归属）",
            原文,
            记号表: vec![
                记号::新(记号种类::标识符, 1, 9),
                记号::新(记号种类::换行, 9, 11),
                记号::新(记号种类::文件结束, 11, 11),
            ],
            期望: 形状错误::记号起点不为零 { 起: 1 },
            期望码: 错误码::记号起点不为零,
        },
        坏输入 {
            名字: "记号区间越界（止越过全文长）",
            原文: "abc",
            记号表: vec![
                记号::新(记号种类::标识符, 0, 4),
                记号::新(记号种类::文件结束, 4, 4),
            ],
            期望: 形状错误::记号区间越界 { 第几个: 0, 止: 4, 全文长: 3 },
            期望码: 错误码::记号区间越界,
        },
        坏输入 {
            名字: "记号区间倒置（起 > 止）",
            原文: "abc",
            记号表: vec![
                记号::新(记号种类::标识符, 3, 1),
                记号::新(记号种类::文件结束, 3, 3),
            ],
            期望: 形状错误::记号区间倒置 { 第几个: 0, 起: 3, 止: 1 },
            期望码: 错误码::记号区间倒置,
        },
        坏输入 {
            名字: "记号有缝隙（抽掉一枚空白，中间那几字节无归属）",
            原文: 样例原文,
            记号表: {
                // 从真实语料小样例里抽掉「空白」那一枚 ⇒ 出现缝隙。
                let mut 表 = 样例.记号表.clone();
                表.remove(1);
                表
            },
            期望: 形状错误::记号有缝隙 { 第几个: 1, 前止: 7, 后起: 8 },
            期望码: 错误码::记号有缝隙,
        },
        坏输入 {
            名字: "记号有重叠（同一字节两个归属）",
            原文,
            记号表: vec![
                记号::新(记号种类::关键字, 0, 9),
                记号::新(记号种类::空白, 8, 10), // 8 与 9 重叠了一字节
                记号::新(记号种类::换行, 10, 11),
                记号::新(记号种类::文件结束, 11, 11),
            ],
            期望: 形状错误::记号有重叠 { 第几个: 1, 前止: 9, 后起: 8 },
            期望码: 错误码::记号有重叠,
        },
        坏输入 {
            名字: "文件结束不在末位",
            原文: "abc",
            记号表: vec![
                记号::新(记号种类::文件结束, 0, 0),
                记号::新(记号种类::标识符, 0, 3),
                记号::新(记号种类::文件结束, 3, 3),
            ],
            期望: 形状错误::文件结束不在末位 { 第几个: 0 },
            期望码: 错误码::文件结束不在末位,
        },
        坏输入 {
            名字: "末记号非文件结束",
            原文,
            记号表: vec![记号::新(记号种类::关键字, 0, 9)],
            期望: 形状错误::末记号非文件结束 { 第几个: 0, 种类: 记号种类::关键字 },
            期望码: 错误码::末记号非文件结束,
        },
        坏输入 {
            名字: "文件结束非零宽",
            原文: "abc",
            记号表: vec![
                记号::新(记号种类::标识符, 0, 2),
                记号::新(记号种类::文件结束, 2, 3),
            ],
            期望: 形状错误::文件结束非零宽 { 起: 2, 止: 3 },
            期望码: 错误码::文件结束非零宽,
        },
        坏输入 {
            名字: "记号流未覆盖全文（末记号锚早了）",
            原文,
            记号表: vec![
                记号::新(记号种类::关键字, 0, 9),
                记号::新(记号种类::文件结束, 9, 9),
            ],
            期望: 形状错误::记号流未覆盖全文 { 覆盖到: 9, 全文长: 11 },
            期望码: 错误码::记号流未覆盖全文,
        },
    ]
}

/// **构造器对每类坏输入报出正确码**（每类一条，断言码正确）。
#[test]
fn 记号流_构造器对每类坏输入报出正确码() {
    let 表 = 坏输入表();
    assert_eq!(表.len(), 10, "记号层 10 类坏输入，一类不许漏");
    for 行 in 表 {
        let 实得 = 记号流::新建(行.原文.as_bytes().to_vec(), 行.记号表)
            .err()
            .unwrap_or_else(|| panic!("{}：非法记号流应当构造不出来", 行.名字));
        assert_eq!(实得, 行.期望, "{}：报的变体不对", 行.名字);
        assert_eq!(crate::形状错误码(&实得), 行.期望码, "{}：报的码不对", 行.名字);
    }
}

/// **函数实现行为**：`还原` 逐字节拼回原文 · `切片` 按区间切出字节（含空文件边界）。
///
/// 这两条不是不变量（不变量已在构造期判死），是那两条函数的实现对不对 ——
/// 构造器保证「区间首尾相接且覆盖全文」，但保证不了 `还原` 真按序拼接、`切片` 真按区间切。
/// 依据 `说明/语言面形状.md` §四 4.1：J2–J5 合起来就是「所有记号的区间首尾相接且覆盖全文」，
/// 也就是 `还原()` 必然返回与原文逐字节相同的字节 —— 这条判据的见证就是本测试。
#[test]
fn 记号流_样例逐字节还原与切片() {
    let 流 = 样例记号流();
    assert_eq!(流.还原(), 样例原文.as_bytes());
    // 每个记号都能从区间切出自身的原文
    assert_eq!(流.切片(0), Some(&b".\xe7\x89\x88\xe6\x9c\xac"[..])); // “.版本”
    assert_eq!(流.切片(12), Some(&b"0"[..]));
    // 边界一：空文件。只有一枚零宽 `文件结束`，构造器接受它，还原是空字节。
    let 空 = 记号流::新建(Vec::new(), vec![记号::新(记号种类::文件结束, 0, 0)])
        .expect("空文件应当是合法记号流");
    assert_eq!(空.还原(), Vec::<u8>::new());
}
