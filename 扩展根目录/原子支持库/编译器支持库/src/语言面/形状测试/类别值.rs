//! 类别值测试 —— 记号种类 / 节点种类 的号与自号往返 · 注释空白的归属判据。
//!
//! 源出 `语言面.rs` 测试模块末尾两条（第 1183–1215 行），**逐字搬家**，
//! 只去掉一层 4 空格缩进。断言一条未改。

use crate::语言面::*;

/// 种类号：只增不复用，未知号返回 `None` 而不是 panic。
#[test]
fn 种类号_自号与号往返且未知号不崩溃() {
    for 号值 in 1u8..=11 {
        let 类别值 = 记号种类::自号(号值).expect("1..=12 都是已登记记号种类");
        assert_eq!(类别值.取号值(), 号值);
    }
    assert_eq!(记号种类::自号(13), None);
    assert_eq!(记号种类::自号(0), None);
    assert_eq!(记号种类::自号(255), None);

    for 号值 in [1u16, 2, 13, 21, 27, 41, 50, 61, 63] {
        let 类别值 = 节点种类::自号(号值).expect("已登记节点种类");
        assert_eq!(类别值.取号值(), 号值);
    }
    assert_eq!(节点种类::自号(14), None);
    assert_eq!(节点种类::自号(64), None);
    assert_eq!(节点种类::自号(9999), None);
}

/// 「注释与空白挂给谁」的判据：只有语句级 / 声明级 / 归属级节点能承接。
#[test]
fn 归属判据_只有语句级与声明级节点承接注释与空白() {
    assert!(节点种类::子程序.是否语句级或声明级());
    assert!(节点种类::返回语句.是否语句级或声明级());
    assert!(节点种类::判断块.是否语句级或声明级());
    assert!(节点种类::程序.是否语句级或声明级());
    // 表达式层不承接：同一段空白会有多个合理归属
    assert!(!节点种类::二元运算.是否语句级或声明级());
    assert!(!节点种类::数值字面量.是否语句级或声明级());
    assert!(!节点种类::命令调用.是否语句级或声明级());
    assert!(!节点种类::空实参.是否语句级或声明级());
}
