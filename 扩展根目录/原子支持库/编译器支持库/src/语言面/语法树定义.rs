use super::{记号流, 节点, 形状错误};

/// 语法树：**记号流 + 节点表 + 根下标**。
///
/// 节点表按**深度优先先序**排列（见 [`语法树::新建`] 的「先序连续」一条）：
/// 于是任一节点的整棵子树占据节点表的一段连续区间；`子区间` 是**它的直接子节点的先序子树区间**
/// —— 区间里夹着的是那些子节点的**后代**，所以「下一个直接子节点」由 [`语法树::直接子`]
/// （按 [`语法树::子树止`] 跳）给出，**不是 `下标 + 1`**。
///
/// 三个字段都**不是公开面**（`pub(crate)`）：本类型只能经 [`语法树::新建`] 得到，
/// 而那一个入口先校验再交出 ——「根等于全文 · 父包住子 · 兄弟不重叠 · 是一棵树 · 先序连续」
/// 不是调用方要记得做的事，是类型的事。
///
/// **信任边界定在本 crate（`pub(crate)`），不是本模块 —— 这是已知且有意的事实。**
/// 本 crate 内仍可用结构体字面量绕开 [`语法树::新建`] 造出不校验的值；要做到「本 crate 内
/// 也构造不出来」得把字段改纯私有、再加只读访问器，**本仓不这么做**。口径与理由：
/// 老仓《设计哲学》第 2.1 条「支持库＝**最小原子能力**」把边界画在**库**这一层，而 V1 的
/// 扩展就是**一个 crate** ⇒ 库内即信任域；`项目文档/设计哲学.md` §二「**冻结边界、内部自由**：
/// 内部实现可以随时改」同一条。跨 crate 的调用方（底座 / 别的扩展）**只有**
/// [`语法树::新建`] 一个入口。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 语法树 {
    /// 记号流（含全文原文）。1102 的产物自带 1101 的产物，自足。
    pub(crate) 记号流: 记号流,
    pub(crate) 节点表: Vec<节点>,
    /// 根节点在 `节点表` 里的下标。通常为 0，但**不写死为 0**。
    pub(crate) 根: u32,
}

impl 语法树 {
    /// **唯一构造口**：校验通过才交出。非法值构造不出来。
    ///
    /// 语法树层 5 条不变量全在这里判死（判定体是 [`语法树::校验`]，返回**第一条**违反）：
    ///
    /// | # | 不变量（一句话） | 报的码 |
    /// |---|---|---|
    /// | **T1** | 根节点的原文区间 == `[0, 全文长)` | 1118 / 1119 / 1120 |
    /// | **T2** | 对每个节点 `n` 与其每个**直接子** `c`（由 [`语法树::直接子`] 走），`n.原文区间` 包住 `c.原文区间`（**含端点相等**） | 1126 |
    /// | **T3** | 对每个节点，其直接子节点**按序**两两不重叠（`后.起 >= 前.止`） | 1127 |
    /// | **T4** | 节点表构成**一棵树**：除根外每个下标**恰好被一个**直接子引用，且**从根可达全部节点** | 1121–1125 / 1128–1132 |
    /// | **T5** | 节点表按**深度优先先序**排列：相邻兄弟 `c_j`、`c_{j+1}` 满足 `子树止(c_j) == c_{j+1}`（逐跳即 [`语法树::直接子`] 的走法），末子的子树止**正好**落在 `子区间.止` | 1133 |
    ///
    /// 每条「为什么必须有」与「违反会导致什么后果」逐字见 `说明/语言面形状.md` §四 4.2
    /// 与 [`形状错误`] 各变体的注释 —— 那些说明一字未动。
    ///
    /// **空子区间归一**：位置 `位置` 上的叶，
    /// 其 `子区间` 一律落 `(位置 + 1, 位置 + 1)`（[`语法树::先序子区间`]，与
    /// `语法/草稿::扁平化` 同一条口径）。故入参里 `起 == 止` 的空区间在这里被归一成
    /// `先序子区间(位置, 0)` —— [`节点::叶`] 只知「无子」、不知位置，落的是占位 `(0, 0)`。
    /// **只归一 `起 == 止`**：`起 > 止`（倒置）仍交给 `校验` 报 1123，不被抹掉。
    pub fn 新建(记号流: 记号流, mut 节点表: Vec<节点>, 根: u32) -> Result<Self, 形状错误> {
        for (位置, 节点) in 节点表.iter_mut().enumerate() {
            if 节点.子区间.0 == 节点.子区间.1 {
                节点.子区间 = Self::先序子区间(位置 as u32, 0);
            }
        }
        let 树 = Self { 记号流, 节点表, 根 };
        树.校验()?;
        Ok(树)
    }

    pub fn 全文(&self) -> &[u8] {
        &self.记号流.原文
    }

    pub fn 全文长(&self) -> u32 {
        self.记号流.全文长()
    }

    /// 根节点。空节点表返回 `None`。
    pub fn 根节点(&self) -> Option<&节点> {
        self.节点表.get(self.根 as usize)
    }

    /// 某节点的直接子节点下标区间。
    pub fn 子区间(&self, 下标: u32) -> Option<(u32, u32)> {
        Some(self.节点表.get(下标 as usize)?.子区间)
    }

    /// 某节点的原文切片。区间越界返回 `None`。
    pub fn 原文切片(&self, 下标: u32) -> Option<&[u8]> {
        let n = self.节点表.get(下标 as usize)?;
        self.记号流.原文.get(n.起() as usize..n.止() as usize)
    }

    /// 子树终止下标（不含）：本节点**整棵子树之后**那个下标（叶是 `下标 + 1`）。
    ///
    /// 走法：从 `子区间.止 - 1`（先序连续的表里那个位置必是叶）出发，一路走「最后一个子节点」
    /// 到底，再 +1。用循环而非递归，避免深树爆栈；步数上限为节点数，超出即返回 `None`（防环）。
    /// 这正是 [`语法树::直接子`] 跳过一个兄弟的那一步。
    pub fn 子树止(&self, 起于: u32) -> Option<u32> {
        let 上限 = self.节点表.len() as u32;
        let mut 当前 = 起于;
        let mut 步 = 0u32;
        loop {
            步 += 1;
            if 步 > 上限 {
                return None;
            }
            let n = self.节点表.get(当前 as usize)?;
            let (起, 止) = n.子区间;
            if 起 >= 止 {
                return Some(当前 + 1);
            }
            当前 = 止 - 1;
        }
    }

    /// 某节点的**直接子节点**下标迭代口 —— **唯一**「怎么走直接子节点」的落点。
    ///
    /// `子区间` 是先序**子树**区间（夹在区间里的是子节点的后代，不是兄弟），
    /// 所以走法是**跳子树**（[`语法树::子树止`]），不是逐下标 `+ 1`。
    /// `校验` 的 T2–T5 与建树侧都调它；谁也不许再自己按 `子起..子止` 走
    /// （`项目文档/决策记录/2026-09-27_三条裁决_按稳定性判.md` 裁决 一）。
    pub fn 直接子(&self, 下标: u32) -> 直接子<'_> {
        let (起, 止) = self.子区间(下标).unwrap_or((0, 0));
        直接子 { 树: self, 下一个: 起, 止 }
    }

    /// 先序表的**布局规则**（写侧）：位置 `位置` 上、子树共 `后代数` 个后代的节点，其 `子区间`。
    ///
    /// 与 [`语法树::直接子`]（读侧）是同一条规则的写与读两面，落在一处免得两处各理解一次
    /// （`项目文档/决策记录/2026-09-27_三条裁决_按稳定性判.md` 裁决 一）。
    /// 只给 `语法/草稿::扁平化` 用，**不进公开面**。
    pub(crate) fn 先序子区间(位置: u32, 后代数: u32) -> (u32, u32) {
        (位置 + 1, 位置 + 1 + 后代数)
    }

    /// 校验全部语法树不变量。返回**第一条**违反。
    ///
    /// 这是 [`语法树::新建`] 的判定体。拿到一份 `&语法树` 的调用方不必再调它
    /// （那份值必然已经过这里），留着它是为了让判定体与它的说明同在一处、可单独读。
    ///
    /// 四处「走子节点」全经 [`语法树::直接子`]（跳子树），不在这里另写一遍逐下标走法。
    pub fn 校验(&self) -> Result<(), 形状错误> {
        use 形状错误::*;
        let 全文长 = self.全文长();
        let 节点数 = self.节点表.len() as u32;

        if self.节点表.is_empty() {
            return Err(节点表为空);
        }
        if self.根 >= 节点数 {
            return Err(根下标越界 { 根: self.根, 节点数 });
        }

        // ── 每个节点的两个区间自身合法 ──
        for (i, n) in self.节点表.iter().enumerate() {
            let 下标 = i as u32;
            if n.起() > n.止() {
                return Err(节点区间倒置 { 下标, 起: n.起(), 止: n.止() });
            }
            if n.止() > 全文长 {
                return Err(节点区间越界 { 下标, 止: n.止(), 全文长 });
            }
            let (子起, 子止) = n.子区间;
            if 子起 > 子止 {
                return Err(子区间倒置 { 下标, 起: 子起, 止: 子止 });
            }
            if 子止 > 节点数 {
                return Err(子区间越界 { 下标, 止: 子止, 节点数 });
            }
            if 子起 <= 下标 && 下标 < 子止 {
                return Err(节点是自身子节点 { 下标 });
            }
        }

        // ── 不变量 T1：根节点的原文区间 == 全文 ──
        let 根 = &self.节点表[self.根 as usize];
        if 根.起() != 0 || 根.止() != 全文长 {
            return Err(根区间不等于全文 { 起: 根.起(), 止: 根.止(), 全文长 });
        }

        // ── 不变量 T4：父引用唯一（根无父、无孤儿、无重复父）──
        let mut 父表: Vec<Option<u32>> = vec![None; self.节点表.len()];
        for 父 in 0..节点数 {
            for 子 in self.直接子(父) {
                if 子 == self.根 {
                    return Err(根被当作子节点 { 节点: 子, 父 });
                }
                if let Some(已有) = 父表[子 as usize] {
                    return Err(同一节点有两个父 { 节点: 子, 甲父: 已有, 乙父: 父 });
                }
                父表[子 as usize] = Some(父);
            }
        }
        for (i, 父) in 父表.iter().enumerate() {
            let 下标 = i as u32;
            if 下标 != self.根 && 父.is_none() {
                return Err(节点是孤儿 { 节点: 下标 });
            }
        }

        // ── 不变量 T4 续：从根可达全部节点（唯一父 + 全覆盖 ⇒ 是树，无环）──
        {
            let mut 到过 = vec![false; self.节点表.len()];
            let mut 栈 = vec![self.根];
            let mut 计数 = 0u32;
            while let Some(当前) = 栈.pop() {
                if 到过[当前 as usize] {
                    return Err(节点被重复到达 { 节点: 当前 });
                }
                到过[当前 as usize] = true;
                计数 += 1;
                栈.extend(self.直接子(当前));
            }
            if 计数 != 节点数 {
                for (i, 到) in 到过.iter().enumerate() {
                    if !到 {
                        return Err(节点从根不可达 { 节点: i as u32 });
                    }
                }
            }
        }

        // ── 不变量 T2：父节点原文区间包住每个子节点 ──
        // ── 不变量 T3：兄弟原文区间按序两两不重叠 ──
        for 父 in 0..节点数 {
            let n = &self.节点表[父 as usize];
            let mut 前一: Option<(u32, u32)> = None; // (下标, 止)
            for 子 in self.直接子(父) {
                let c = &self.节点表[子 as usize];
                if !n.包住(c.起(), c.止()) {
                    return Err(父未包住子 { 父, 子 });
                }
                if let Some((前下标, 前止)) = 前一
                    && c.起() < 前止
                {
                    return Err(兄弟重叠 { 父, 前: 前下标, 后: 子 });
                }
                前一 = Some((子, c.止()));
            }
        }

        // ── 布局不变量 T5：先序连续 ──
        // 相邻兄弟 c_j、c_{j+1} 必须满足 子树止(c_j) == c_{j+1} —— 这正是 `直接子` 的走法。
        // 于是这里只剩两件要判的事：每一步不许**越过** `子区间.止`（越过 ⇒ 该子节点的子树
        // 伸出了父声明的区间），且末子必须**正好**落在 `子区间.止`（不许留空档）。
        // 有了它，同一棵树只有一种节点表写法，且子树可 O(1) 切出。
        for 父 in 0..节点数 {
            let (子起, 子止) = self.节点表[父 as usize].子区间;
            if 子起 >= 子止 {
                continue;
            }
            let mut 末子 = 子起;
            let mut 到 = 子起;
            for 子 in self.直接子(父) {
                末子 = 子;
                到 = self.子树止(子).unwrap_or(u32::MAX);
                if 到 > 子止 {
                    return Err(非先序连续 { 父, 子, 子树止: 到 });
                }
            }
            if 到 != 子止 {
                return Err(非先序连续 { 父, 子: 末子, 子树止: 到 });
            }
        }

        Ok(())
    }
}

/// [`语法树::直接子`] 的迭代器 —— **唯一**「怎么走直接子节点」的落点。
///
/// `子区间` 是先序**子树**区间：区间里夹着的是子节点的后代。故下一个兄弟 = 当前子节点的
/// 整棵子树之后（[`语法树::子树止`]），**不是** `当前 + 1`。
/// 依据：`项目文档/决策记录/2026-09-27_三条裁决_按稳定性判.md` 裁决 一。
#[derive(Debug, Clone, Copy)]
pub struct 直接子<'a> {
    树: &'a 语法树,
    下一个: u32,
    止: u32,
}

impl<'a> Iterator for 直接子<'a> {
    type Item = u32;

    fn next(&mut self) -> Option<u32> {
        if self.下一个 >= self.止 {
            return None;
        }
        let 当前 = self.下一个;
        self.下一个 = match self.树.子树止(当前) {
            Some(到) if 到 > 当前 => 到,
            // 表不先序连续（或成环）：本节点到此为止，剩下的由 `校验` 报码。
            _ => self.止,
        };
        Some(当前)
    }
}

