//! 形状错误定义 —— 形状错误（结构化段位，不是字符串、不是 panic）。
//!
//! 源出 `语言面.rs` 第 667–723 行（第三节），**逐字搬家**。
//! 记号层的错误变体与语法树层的错误变体同住这一件：它们是**一个**错误类型，
//! 拆开会让 `形状错误` 这个名字出现在两个地方。

use super::记号种类;

/// 形状错误。**结构化段位**，不是字符串、不是 panic
/// （口径见 `说明/设计说明.md` 第五节第 2 条）。
///
/// **待办**：这些变体还没有对应的 4 位错误码。落码要写进
/// `契约声明/错误码表/`，那是契约声明层的文件，不在本腿可改范围，故登记为待办
/// （见 `说明/语言面形状.md` 第六节）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 形状错误 {
    // ── 记号层 ──
    /// 记号表为空 —— 连 `文件结束` 都没有。空文件也必须有一个零宽 `文件结束`。
    记号表为空,
    /// 首个记号不起于 0 —— 全文开头有字节无归属。
    记号起点不为零 { 起: u32 },
    /// 记号区间越出全文。
    记号区间越界 { 第几个: u32, 止: u32, 全文长: u32 },
    /// 记号区间倒置（起 > 止）。
    记号区间倒置 { 第几个: u32, 起: u32, 止: u32 },
    /// 前一个记号的止 < 后一个记号的起 —— **有缝隙**，中间那几字节无归属。
    记号有缝隙 { 第几个: u32, 前止: u32, 后起: u32 },
    /// 前一个记号的止 > 后一个记号的起 —— **有重叠**，同一字节有两个归属。
    记号有重叠 { 第几个: u32, 前止: u32, 后起: u32 },
    /// `文件结束` 出现在非末位。
    文件结束不在末位 { 第几个: u32 },
    /// 末记号不是 `文件结束`。
    末记号非文件结束 { 第几个: u32, 种类: 记号种类 },
    /// `文件结束` 不是零宽。
    文件结束非零宽 { 起: u32, 止: u32 },
    /// 末记号没到全文末尾 —— **未覆盖全文**。
    记号流未覆盖全文 { 覆盖到: u32, 全文长: u32 },

    // ── 语法树层 ──
    节点表为空,
    根下标越界 { 根: u32, 节点数: u32 },
    /// **不变量 T1 违反**：根节点原文区间不等于全文。
    根区间不等于全文 { 起: u32, 止: u32, 全文长: u32 },
    节点区间倒置 { 下标: u32, 起: u32, 止: u32 },
    节点区间越界 { 下标: u32, 止: u32, 全文长: u32 },
    子区间倒置 { 下标: u32, 起: u32, 止: u32 },
    子区间越界 { 下标: u32, 止: u32, 节点数: u32 },
    节点是自身子节点 { 下标: u32 },
    /// **不变量 T2 违反**：父节点原文区间没包住子节点。
    父未包住子 { 父: u32, 子: u32 },
    /// **不变量 T3 违反**：兄弟原文区间重叠。
    兄弟重叠 { 父: u32, 前: u32, 后: u32 },
    /// **不变量 T4 违反**：同一节点被两个父节点引用 —— 不是树。
    同一节点有两个父 { 节点: u32, 甲父: u32, 乙父: u32 },
    /// **不变量 T4 违反**：根被当作子节点。
    根被当作子节点 { 节点: u32, 父: u32 },
    /// **不变量 T4 违反**：该节点没有任何父引用 —— 不是树。
    节点是孤儿 { 节点: u32 },
    /// **不变量 T4 违反**：从根出发两次到达同一节点 —— 有环。
    节点被重复到达 { 节点: u32 },
    /// **不变量 T4 违反**：从根出发到不了该节点 —— 有环。
    节点从根不可达 { 节点: u32 },
    /// **布局不变量 T5 违反**：节点表不是深度优先先序。
    非先序连续 { 父: u32, 子: u32, 子树止: u32 },
}

