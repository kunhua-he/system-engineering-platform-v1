//! 声明数据 —— 本扩展自己的身份 · 版本 · 号段，与命令表的两个「表长」常量。
//!
//! ⚠ 违规待消：手写 static 平台信息；待生成器支持扩展声明后改成生成物（见返回说明）。
//! 本件从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现）；常量名与取值
//! 一字不改，只把「crate 根私有」改成 `pub`（外层模块是 crate 私有 ⇒ 对外仍是零泄漏）。

use crate::能力号;
use v1_contract::{号段, 版本三元组};

/// 标识串（32 位十六进制 + NUL）。**本扩展自己的身份**，不是底座那串。
/// 源：`包声明.json.标识串`。
pub const 标识串: &[u8] = b"b6ac1f87165619c4b72571bba5c4010b\0";

/// 名称。源：`包声明.json.名称`。
pub const 名称: &[u8] = "编译器支持库\0".as_bytes();

/// 说明。源：`包声明.json.说明`。
pub const 说明: &[u8] =
    "编译器后端能力：原生路（我们的程序文本 → 记号流 → 语法树 → 语义）与互操作路（.e 容器 ⇄ 结构）。前端是纯 UI，不在本扩展里。声明放在扩展自己的目录里，底座载入时读它。\0"
        .as_bytes();

/// 声明格式号：**格式的身份证，不是版本号**。平台级常量 —— 本扩展**不自己定义**，
/// 直接引用生成物（唯一来源：`契约声明/常量表.json` 的「声明格式号」条目）。
///
/// 早先这里是 `const 声明格式号: u32 = v1_contract::声明格式号;` —— 值虽引自生成物，
/// 但**造了一个同名常量**，实现侧扫描器 ③j 判「同名再绑定」为不可判。改成 `use` 之后
/// 本文件里不再有这个常量的定义处。
pub(crate) use v1_contract::声明格式号;

/// 目标字宽。源：`契约声明/常量表.json` 的「目标字宽」条目（生成物里的名字是 `底座目标字宽`）。
///
/// 早先这里是 `const 目标字宽: u16 = 64;` —— **硬编码字面量，第二来源**，
/// 实现侧扫描器 ③j 当场报红（2026-09-26）。改成 `use` 别名，值只有一个来源。
pub(crate) use v1_contract::声明数据::底座目标字宽 as 目标字宽;

/// 实现版本（本扩展自己的版本）。源：`包声明.json.实现版本`。
pub const 实现版本: 版本三元组 = 版本三元组::新(0, 1, 0, 0);

/// 要求的宿主版本。源：`包声明.json.要求宿主版本`。底座提供 1.0.0.0 ⇒ 满足。
pub const 要求宿主版本: 版本三元组 = 版本三元组::新(1, 0, 0, 0);

/// 要求的内核版本。源：`包声明.json.要求内核版本`。底座提供 1.0.0.0 ⇒ 满足。
pub const 要求内核版本: 版本三元组 = 版本三元组::新(1, 0, 0, 0);

/// 本扩展**自己占用**的能力号段（源：`包声明.json.能力号段`）。
///
/// **申报窄号段**：只报 `[1100, 1199]`，不报支持库整段 `[1000, 6999]`——
/// 「号段即层级」只管「这段归我」，不代表我要占满。**命令表不再等于号段跨度**：
/// 表只装**声明过**的号（1101..1107），号段里没声明的号不占表位。
pub const 能力号段: [号段; 1] = [号段::新(1100, 1199)];

/// 本扩展登记的错误段位（源：`包声明.json.错误段位表`）。
///
/// 段位 1 = 支持库 · 编译器域（本扩展真抛的码全在这一段）。
/// **段位 0 是缩表前的残留**：早先「编号 = 表内下标」把占位项压进下标 0..999（内核自有段），
/// 而装载判定第 ⑥ 步要求「错误状态命令的段位已登记」，故当时不得不登记它。
/// 缩表后本扩展**没有一条命令落在段位 0**，这一位成了多余登记；删它要同步改
/// `包声明.json`（不属本腿所有权的文件）⇒ 保留，并在此如实标注。
pub const 错误段位表: [u32; 2] = [0, 1];

/// 命令表**第一项**的编号 = 本扩展申报并声明的第一个号。
///
/// 表按编号**严格递增**（`统一注册表::建表` 的前提）⇒ `表内下标 = 编号 − 表首号`。
pub const 表首号: u32 = 能力号::词法分析;

/// 命令表项数：**只装本扩展声明过的 7 条**（1101..1107），不再铺满申报号段。
///
/// 编号已是显式字段 ⇒ 表内下标不再承担编号，表也不必覆盖号段的每一个号
/// （口径由 裁决 1「命令编号显式化」推出；裁决 5 管的是「编号必须落在申报号段内」）。
/// 写成整数字面量是给实现侧扫描器的（`测试验证/契约一致性/扫实现.py` 的 ③g 要静态取值）；
/// 与号段的一致性由测试 `缩表_命令表逐位编号等于表首号加下标` 当场守住，不会静默漂。
pub const 命令表项数: usize = 7;

/// 命令编号 → 表内下标。**编号必须在本扩展的命令表内**（不在即当场 panic / 编译不过）。
pub const fn 表内位(编号: u32) -> usize {
    assert!(
        编号 >= 表首号 && ((编号 - 表首号) as usize) < 命令表项数,
        "编号不在本扩展的命令表内"
    );
    (编号 - 表首号) as usize
}
