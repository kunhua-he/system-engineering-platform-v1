pub const 命令表首号: u32 = 能力号::词法分析;

/// 命令表项数：**只装本扩展声明过的 7 条**（1101..1107），不再铺满申报号段。
///
/// 编号已是显式字段 ⇒ 表内下标不再承担编号，表也不必覆盖号段的每一个号
/// （口径由 裁决 1「命令编号显式化」推出；裁决 5 管的是「编号必须落在申报号段内」）。
/// 写成整数字面量是给实现侧扫描器的（`测试验证/契约一致性/扫实现.py` 的 ③g 要静态取值）；
/// 与号段的一致性由测试 `缩表_命令表逐位编号等于表首号加下标` 当场守住，不会静默漂。
pub const 命令表项数: usize = 7;

/// 命令编号 → 表内下标。**编号必须在本扩展的命令表内**（不在即当场 panic / 编译不过）。
pub const fn 命令表内位(编号: u32) -> usize {
    assert!(
        编号 >= 命令表首号 && ((编号 - 命令表首号) as usize) < 命令表项数,
        "编号不在本扩展的命令表内"
    );
    (编号 - 命令表首号) as usize
}
