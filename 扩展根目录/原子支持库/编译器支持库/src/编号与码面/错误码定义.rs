//! 错误码 —— 11xx（段位 1 = 支持库 · 编译器域）的**号**与**登记表**。
//!
//! 从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现）；`pub mod 错误码` 的
//! 模块名与全部常量、以及 37 条登记项与构造器**一字不改**。**号与登记表同处一件**：实现侧
//! 扫描器（`测试验证/契约一致性/扫实现.py` 的 ③f）在**同一份文件**里解析 `码项(错误码::X, …,
//! 段位: 错误码 / 1000)` 的码与段位 —— 分处两件会让它两者都解不出（实测：③f 逐条报「错误码信息 表里没有它」）⇒ 两样必须同件。

