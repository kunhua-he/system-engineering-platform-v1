//! 码映射 —— 把两个错误枚举的变体**穷尽**映射到本扩展的错误码。
//!
//! 从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现）；两个函数的
//! **签名、匹配臂、文档一字不改**，只把 `super::…` 的取址改成 `crate::…`。
//!
//! 两个函数都是**穷尽匹配**：变体一旦增删或改名，这里就编译不过（编号与变体的对应不许静默漂）。

use crate::错误码;
use crate::语言面;
use crate::语义;

/// `语言面.rs` 的形状错误 → 本扩展的错误码。**穷尽匹配**：那 26 个变体一旦增删或改名，
/// 这里就编译不过（编号与变体的对应不许静默漂）。26 条码全在 `错误码表/` 登记过。
pub fn 形状错误码(错: &语言面::形状错误) -> u32 {
    use crate::语言面::形状错误 as 形状;
    match 错 {
        形状::记号表为空 => 错误码::记号表为空,
        形状::记号起点不为零 { .. } => 错误码::记号起点不为零,
        形状::记号区间越界 { .. } => 错误码::记号区间越界,
        形状::记号区间倒置 { .. } => 错误码::记号区间倒置,
        形状::记号有缝隙 { .. } => 错误码::记号有缝隙,
        形状::记号有重叠 { .. } => 错误码::记号有重叠,
        形状::文件结束不在末位 { .. } => 错误码::文件结束不在末位,
        形状::末记号非文件结束 { .. } => 错误码::末记号非文件结束,
        形状::文件结束非零宽 { .. } => 错误码::文件结束非零宽,
        形状::记号流未覆盖全文 { .. } => 错误码::记号流未覆盖全文,
        形状::节点表为空 => 错误码::节点表为空,
        形状::根下标越界 { .. } => 错误码::根下标越界,
        形状::根区间不等于全文 { .. } => 错误码::根区间不等于全文,
        形状::节点区间倒置 { .. } => 错误码::节点区间倒置,
        形状::节点区间越界 { .. } => 错误码::节点区间越界,
        形状::子区间倒置 { .. } => 错误码::子区间倒置,
        形状::子区间越界 { .. } => 错误码::子区间越界,
        形状::节点是自身子节点 { .. } => 错误码::节点是自身子节点,
        形状::父未包住子 { .. } => 错误码::父未包住子,
        形状::兄弟重叠 { .. } => 错误码::兄弟重叠,
        形状::同一节点有两个父 { .. } => 错误码::同一节点有两个父,
        形状::根被当作子节点 { .. } => 错误码::根被当作子节点,
        形状::节点是孤儿 { .. } => 错误码::节点是孤儿,
        形状::节点被重复到达 { .. } => 错误码::节点被重复到达,
        形状::节点从根不可达 { .. } => 错误码::节点从根不可达,
        形状::非先序连续 { .. } => 错误码::非先序连续,
    }
}

/// `语义::语义错误` → 本扩展的错误码。**穷尽匹配**：变体一旦增删或改名，这里就编译不过
/// （编号与变体的对应不许静默漂）。两个变体都在 `错误码表/` 登记过。
pub(crate) fn 语义错误码(错: &语义::语义错误) -> u32 {
    use crate::语义::语义错误 as 语义错;
    match 错 {
        语义错::名字未声明 { .. } => 错误码::名字未声明,
        // 号装不下 16 位：属「本库的边界编码装不下」，与容器结构编码非法同码
        // （`错误码表/1134.json` 的说明已覆盖这一层）。
        语义错::号溢出 { .. } => 错误码::结构编码非法,
    }
}
