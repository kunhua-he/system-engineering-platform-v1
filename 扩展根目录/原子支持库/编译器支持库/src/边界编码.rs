//! 边界编码 —— 三份「结构 → 字节集」的边界编码（过边界只有定长数据槽，结构必须先编成字节）。
//!
//! **本件是路由**：声明子模块 · 零实现。
//!
//! | 件 | 管什么 |
//! |---|---|
//! | [`结构编码`](边界编码/结构编码.rs) | 容器结构（`容器.rs` 的 `容器`）的字段搬运 |
//! | [`原生路编码`](边界编码/原生路编码.rs) | 记号流 / 语法树 / 诊断结果的字段搬运 |
//! | [`语义编码`](边界编码/语义编码.rs) | 带号结构（1103 产物）的字段搬运 |
//!
//! 三份都**只做字段搬运**，不含任何词法/语法/语义/`.e` 格式知识 —— 那些知识各在自身那件里
//! （切分在 `词法.rs`、建树在 `语法.rs`、定号在 `语义/建表.rs`、段头在 `容器.rs`）。
//! 编解码各只有这一处，不另起第二套。

#[path = "边界编码/结构编码.rs"]
pub(crate) mod 结构编码;
#[path = "边界编码/原生路编码.rs"]
pub(crate) mod 原生路编码;
#[path = "边界编码/语义编码.rs"]
pub(crate) mod 语义编码;
