//! 静态声明与唯一导出符号 —— 本扩展的 `平台信息` 实例与 `GetPlatformInfo` 接缝。
//!
//! ⚠ 违规待消：手写 static 平台信息；待生成器支持扩展声明后改成生成物（见返回说明）。
//! 从 `src/lib.rs` 搬来（那是路由：声明子模块 · 再导出公开面 · 零实现）。
//!
//! **导出符号名不再手写**：`#[unsafe(export_name = "GetPlatformInfo")]` 改由
//! 生成器按声明字段 `包声明.json.导出目标` 出（生成物 `src/接缝.rs`，本件 `include!` 进来）。
//! 根因见 `项目文档/设计文档/导出目标.md` §五：手写导出属性 ⇒ 底座与扩展各写一个同名 ⇒
//! 同二进制里只解析得到一个 ⇒ 底座身份自检恒假。

use v1_contract::{平台信息, 表段};

use crate::命令声明面::命令表::{命令表存储, 函数表};
use crate::声明数据::包声明::{
    声明格式号, 目标字宽, 名称, 命令表项数, 实现版本, 要求内核版本, 要求宿主版本, 能力号段,
    标识串, 说明, 错误段位表,
};
use crate::编号与码面::错误码定义::错误码表;

/// 带 `Sync` 的声明外壳。跨边界结构里有裸指针 ⇒ 类型本身不是 `Sync`，而 `static` 要求 `Sync`。
/// 内容全是静态只读数据，对外只给 `*const` 指针，任何一方都不得写。
#[repr(transparent)]
struct 静态声明(平台信息);

// SAFETY: 静态声明一旦构造即终生不变；不提供任何 &mut 通道，导出符号只交出 *const 指针，
// 故多线程共享只读是安全的。
unsafe impl Sync for 静态声明 {}

impl 静态声明 {
    const fn 取平台信息(&self) -> &平台信息 {
        &self.0
    }
}

/// 本扩展自身的静态 `平台信息`。**唯一实例**：导出符号返回它的地址。
///
/// 各字段的源：
/// - 声明数据字段（声明格式号 · 目标字宽 · 标识串 · 实现版本 · 要求宿主/内核版本 · 名称 ·
///   说明 · 能力号段 · 通知号段 · 错误段位表）—— 源是本扩展目录下的 JSON，
///   但因生成器尚不支持扩展声明，此处**手写**（违规待消，见文件头）；
/// - 结构性字段（类型表 · 命令表 · 函数表 · 常量表 · 通知函数 · 依赖清单）—— JSON 侧无源，
///   由本文件给出。
static 扩展存储: 静态声明 = 静态声明(平台信息 {
    声明格式号,
    目标字宽,
    保留: 0,
    标识串: 标识串.as_ptr(),
    实现版本,
    要求宿主版本,
    要求内核版本,
    名称: 名称.as_ptr(),
    说明: 说明.as_ptr(),
    状态位: 0,
    // 本扩展**不新增类型**：只用底座已有的（文本 4 · 字节集 5 · 错误 4294967295）。
    类型表: 表段::空(),
    命令表: 表段::新(命令表存储.0.as_ptr(), 命令表项数 as u32),
    函数表: 函数表.as_ptr(),
    // 本扩展**没有常量**。
    常量表: 表段::空(),
    // 本扩展**没有通知函数**：通知号段为空（生命周期段 2000–2999 被底座占用，
    // 扩展申报不了，见 返回说明）。
    通知函数: None,
    // 本扩展**不依赖别的扩展**（只读底座公布的契约）。
    依赖清单: 表段::空(),
    能力号段: 表段::新(能力号段.as_ptr(), 1),
    通知号段: 表段::空(),
    错误段位表: 表段::新(错误段位表.as_ptr(), 错误段位表.len() as u32),
    错误码表: 表段::新(错误码表.as_ptr(), 错误码表.len() as u32),
    // 本扩展**没有类别表**（它的 `能力声明.类别` 全是 `0` = 未分类，合法）——
    // 空表 = 「本声明没有类别表」，不是漏写。
    命令类别表: 表段::空(),
    // 本扩展**不要求任何权限**（编译器只读程序文本、写自身的运行数据根）。
    要求权限: 表段::空(),
});

/// 接缝地址 —— 生成物 `src/接缝.rs`（`crate::接缝`）的导出函数调它取本扩展的静态声明指针。
///
/// **本文件不再手写 `#[unsafe(export_name = …)]`** —— 符号名由声明字段
/// `包声明.json.导出目标` 给出，生成器据此出接缝（见文件头）。生成物只依赖这一个
/// 固定钩子（crate 根 re-export 成 `crate::取接缝地址`），不碰本模块的私有数据名。
///
/// 重出接缝：`python3 构建装配/形态装配/生成声明.py --接缝 --声明根 <本扩展目录>`。
///
/// 返回的指针指向静态数据，终生有效，调用方不得释放、不得修改。
pub(crate) fn 取接缝地址() -> *const 平台信息 {
    扩展存储.取平台信息() as *const 平台信息
}

/// 未导出但同源的只读取用口（验证面与测试用，不新增导出符号）。
#[doc(hidden)]
pub fn 扩展声明() -> &'static 平台信息 {
    扩展存储.取平台信息()
}
