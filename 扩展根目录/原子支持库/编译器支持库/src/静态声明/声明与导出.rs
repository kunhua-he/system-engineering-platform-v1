/// 接缝地址 —— 生成物 `src/接缝.rs`（`crate::接缝`）的导出函数调它取本扩展的静态声明指针。
///
/// **本文件不再手写 `#[unsafe(export_name = …)]`** —— 符号名由声明字段
/// `包声明.json.导出目标` 给出，生成器据此出接缝（见文件头）。生成物只依赖这一个
/// 固定钩子（crate 根 re-export 成 `crate::取接缝地址`），不碰本模块的私有数据名。
///
/// 重出接缝：`python3 构建装配/形态装配/生成声明.py --接缝 --声明根 <本扩展目录>`。
///
/// 返回的指针指向静态数据，终生有效，调用方不得释放、不得修改。
pub(crate) fn 取接缝地址() -> *const 平台信息 {
    扩展存储.取平台信息() as *const 平台信息
}

/// 未导出但同源的只读取用口（验证面与测试用，不新增导出符号）。
#[doc(hidden)]
pub fn 扩展声明() -> &'static 平台信息 {
    扩展存储.取平台信息()
}
