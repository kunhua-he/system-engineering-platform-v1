use super::*;
use super::测试夹具::*;
use crate::容器;
use crate::测试夹具::{首个不一致, 收集语料};
use std::path::Path;

/// **唯一硬判据**：对语料里容器文件的每条程序段，`生成(反解(段数据))` 必须与段数据逐字节相同。
#[test]
fn 语料往返_程序段数据逐字节一致() {
    let 根目录 = Path::new(语料根目录);
    if !根目录.exists() {
        println!("语料目录不存在，跳过往返测试：{语料根目录}");
        return;
    }

    let mut 文件表 = Vec::new();
    收集语料(根目录, &mut 文件表);
    文件表.sort();

    let mut 通过: u64 = 0;
    let mut 段数: u64 = 0;
    let mut 记录数: u64 = 0;
    let mut 结构化字节: u64 = 0;
    let mut 搬运字节: u64 = 0;
    let mut 引用条数: u64 = 0;
    let mut 五段引用: u64 = 0;
    let mut 失败: Vec<String> = Vec::new();

    for 路径 in &文件表 {
        let 原文 = match std::fs::read(路径) {
            Ok(字节) => 字节,
            Err(错误) => {
                失败.push(format!("{} 读入失败：{错误}", 路径.display()));
                continue;
            }
        };
        let 容器 = match 容器::反解容器(&原文) {
            Ok(容器) => 容器,
            Err(错误) => {
                失败.push(format!("{} 容器反解失败：{错误:?}", 路径.display()));
                continue;
            }
        };
        for (序号, 号段) in 容器.段表.iter().enumerate() {
            if 号段.段头字段.段类型 != 容器::段类型::程序.取号值() {
                continue;
            }
            段数 += 1;
            let 输出流 = match 反解段数据(&号段.数据字节) {
                Ok(输出流) => 输出流,
                Err(错误) => {
                    失败.push(format!("{} 第 {序号} 段 段数据反解失败：{错误:?}", 路径.display()));
                    continue;
                }
            };
            记录数 += 输出流.记录条数();
            结构化字节 += 输出流.结构化字节();
            搬运字节 += 输出流.其余载荷.len() as u64;
            引用条数 += 输出流.支持库.引用表.len() as u64;
            五段引用 += 输出流
                .支持库
                .引用表
                .iter()
                .filter(|引用记录| 引用记录.字段数() == 引用字段名.len())
                .count() as u64;

            match 生成段数据(&输出流) {
                Err(错误) => {
                    失败.push(format!("{} 第 {序号} 段 段数据生成失败：{错误:?}", 路径.display()));
                }
                Ok(产物) => {
                    if 产物 == 号段.数据字节 {
                        通过 += 1;
                    } else {
                        let 字节偏移 = 首个不一致(&号段.数据字节, &产物);
                        失败.push(format!(
                            "{} 第 {序号} 段 往返不一致：首个不一致字节偏移 {字节偏移}，原文 {} 字节，产物 {} 字节",
                            路径.display(),
                            号段.数据字节.len(),
                            产物.len()
                        ));
                    }
                }
            }
        }
    }

    let 占比 = if 结构化字节 + 搬运字节 == 0 {
        0.0
    } else {
        100.0 * 结构化字节 as f64 / (结构化字节 + 搬运字节) as f64
    };
    println!(
        "记录流语料往返实测：通过 {通过} / 失败 {} / 共 {} 个文件；切出段记录 {段数} 条 · 记录 {记录数} 条",
        失败.len(),
        文件表.len()
    );
    println!(
        "  支持库引用记录 {引用条数} 条（其中 5 段 {五段引用} 条）；已结构化字节 {结构化字节} / 原样搬运字节 {搬运字节}（结构化占比 {占比:.2}%）"
    );
    for (序号, 失败样例) in 失败.iter().take(10).enumerate() {
        println!("  失败样例 {}：{失败样例}", 序号 + 1);
    }

    assert!(
        失败.is_empty(),
        "记录流语料往返不一致：通过 {通过}，失败 {}（共 {} 个文件）",
        失败.len(),
        文件表.len()
    );
    assert!(段数 > 0, "语料里一条程序段都没切到，判据没被真正执行");
}
