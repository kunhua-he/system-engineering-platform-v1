//! 错误 —— 反解错误与生成错误（结构化段位，不是字符串）。

/// 反解错误。结构化段位，不是字符串。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 反解错误 {
    /// 段数据不足 56 字节。
    段数据头截断 { 需要: u64, 实有: u64 },
    /// 段数据头的保留字段非零（实测 1456/1456 为 0）。
    段数据头保留非零 { 字节位置: u64, 实取: u32 },
    /// 段数据头的补零区出现非零字节（实测 1456/1456 全零）。
    段数据头补零非零 { 字节位置: u64 },
    /// 头内体长与「段数据长 − 56」不符。
    体长不符 { 头内: u64, 实有: u64 },
    /// 段体不足 8 字节。
    段体截断 { 字节位置: u64, 需要: u64, 剩余字节: u64 },
    /// 段体魔数不是 `0x030BEF3F`。
    段体魔数不符 { 字节位置: u64, 实取: u32 },
    /// 数组字节长度前缀不是元素宽的整数倍。
    数组长度前缀非整元素 { 第几: u8, 长度前缀: u64, 元素宽: u8 },
    /// 数组体或长度前缀本身越过段数据尾。
    数组越界 { 第几: u8, 长度前缀: u64, 剩余字节: u64 },
    /// 三个数组元素数与 `u16 支持库数` 不一致。
    支持库数不符 { 数组元素数: u64, 声明数: u64 },
    /// 支持库引用串越过段数据尾。
    支持库引用越界 { 第几条: u32, 串长: u64, 剩余字节: u64 },
}

/// 生成错误。结构化段位，不是字符串。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 生成错误 {
    /// 三个数组元素数与引用表条数不一致。
    支持库数组长度不一致 { 首数组长: u64, 次数组长: u64, 末数组长: u64, 引用表: u64 },
    /// 某条引用记录的字段表为空（无法与空串区分）。
    支持库引用字段为空 { 第几条: u32 },
    /// `头.补零` 非全零——盘面不允许，拒绝生成。
    补零非零 { 第几字节: u32 },
}
