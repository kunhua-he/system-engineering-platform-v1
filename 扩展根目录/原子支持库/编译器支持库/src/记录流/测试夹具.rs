use super::*;

/// 语料根目录的解析口 —— **主人**在 crate 的 `测试夹具`（`src/测试夹具.rs`），本件只转出口
/// （`记录流` 下的测试件按 `super::测试夹具::取语料根目录` 取）。
///
/// 口径由「写死一个 `/tmp/易语言源码` 常量」改成「环境变量显式注入」（审计附①）——
/// 未设即 `None`，调用方按「未判」报，**不许静默当通过**。
pub(crate) use crate::测试夹具::{取语料根目录, 语料路径变量名};

// 段数据里的库中文名是 **GBK** 字节（不是 UTF-8），字节串字面量放不下非 ASCII 字符，
// 故这里直接写出实测得到的 GBK 字节（与容器层测试同一串）。
pub(crate) const GBK系统核心支持库: &[u8] =
    &[0xCF, 0xB5, 0xCD, 0xB3, 0xBA, 0xCB, 0xD0, 0xC4, 0xD6, 0xA7, 0xB3, 0xD6, 0xBF, 0xE2];

/// 造一条合法记录流：1 条支持库引用（5 段）+ 4 字节其余载荷。
pub(crate) fn 样例流() -> 记录流 {
    记录流 {
        段头字段: 段数据头 {
            段序号: 4,
            保留: 0,
            校验值: 0x0A06_CD88,
            体长: 0,
            补零: [0; 40],
        },
        体头: 段体头 { 首字段: 0x0001_0064 },
        支持库: 支持库表 {
            首数组: vec![193],
            次数组: vec![5],
            末数组: vec![0],
            引用表: vec![支持库引用::由字段(vec![
                b"KRNLN".to_vec(),
                b"d09f2340818511d396f6aaf844c7e325".to_vec(),
                b"4".to_vec(),
                b"2".to_vec(),
                GBK系统核心支持库.to_vec(),
            ])],
        },
        其余载荷: vec![0x01, 0x00, 0x01, 0x52],
    }
}

pub(crate) fn 样例字节() -> Vec<u8> {
    let mut 输出流 = 样例流();
    输出流.重算体长();
    生成段数据(&输出流).expect("样例应能生成")
}
