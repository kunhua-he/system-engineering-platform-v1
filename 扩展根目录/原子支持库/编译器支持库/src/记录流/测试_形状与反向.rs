/// 段数据头逐字段布局：按实测口径造一条，核对每个字段位与体长口径。
#[test]
fn 段数据头逐字段布局() {
    let 产物 = 样例字节();
    assert_eq!(读四字节(&产物, 0x00), 4, "段序号");
    assert_eq!(读四字节(&产物, 0x04), 0, "保留恒 0");
    assert_eq!(读四字节(&产物, 0x08), 0x0A06_CD88, "校验值原样小端写回");
    assert_eq!(
        读四字节(&产物, 0x0C) as usize,
        产物.len() - 段数据头长度,
        "体长 = 段数据长 − 56"
    );
    assert!(产物[0x10..0x38].iter().all(|&字节| 字节 == 0), "补零区恒全零");
}

