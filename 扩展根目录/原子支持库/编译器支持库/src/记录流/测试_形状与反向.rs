/// 支持库表：三数组字节长度前缀 = 4N/2N/2N，且与 u16 支持库数四处一致。
#[test]
fn 支持库表三数组与支持库数四处一致() {
    let 产物 = 样例字节();
    assert_eq!(读四字节(&产物, 0x40), 4, "首数组字节长度 = 4N");
    assert_eq!(读四字节(&产物, 0x48), 2, "次数组字节长度 = 2N");
    assert_eq!(读四字节(&产物, 0x4E), 2, "末数组字节长度 = 2N");
    assert_eq!(读双字节(&产物, 0x54), 1, "u16 支持库数 = N");

    let 输出流 = 反解段数据(&产物).expect("反解应成功");
    assert_eq!(输出流.支持库.首数组, vec![193]);
    assert_eq!(输出流.支持库.次数组, vec![5]);
    assert_eq!(输出流.支持库.末数组, vec![0]);
    assert_eq!(输出流.支持库.引用表.len(), 1);
    assert_eq!(输出流.其余载荷, vec![0x01, 0x00, 0x01, 0x52]);
}

/// 支持库引用串：按 0x0D 切五段，五段拼回与原文逐字节相同（含 GBK 中文名）。
#[test]
fn 支持库引用_按分隔符切段再拼回原文() {
    let 字节串: Vec<u8> = [
        b"KRNLN".to_vec(),
        b"d09f2340818511d396f6aaf844c7e325".to_vec(),
        b"4".to_vec(),
        b"2".to_vec(),
        GBK系统核心支持库.to_vec(),
    ]
    .join(&引用分隔符);

    let 一条 = 支持库引用 { 字段: 切引用字段(&字节串) };
    assert_eq!(一条.字段数(), 5);
    assert_eq!(一条.库文件名(), Some(b"KRNLN".as_slice()));
    assert_eq!(一条.取GUID(), Some(b"d09f2340818511d396f6aaf844c7e325".as_slice()));
    assert_eq!(一条.首版本(), Some(b"4".as_slice()));
    assert_eq!(一条.次版本(), Some(b"2".as_slice()));
    assert_eq!(一条.中文名(), Some(GBK系统核心支持库));
    assert_eq!(一条.串长(), 字节串.len());
    assert_eq!(一条.原文(), 字节串, "切段再拼回必须逐字节相同");

    // 边界：空串切成 1 段、尾分隔符切成 2 段，都能拼回原文。
    assert_eq!(切引用字段(b"").len(), 1);
    assert_eq!(支持库引用 { 字段: 切引用字段(b"") }.原文(), b"");
    assert_eq!(切引用字段(b"a\r").len(), 2);
    assert_eq!(支持库引用 { 字段: 切引用字段(b"a\r") }.原文(), b"a\r");
    // 6 段（.npk 类库）不做猜测：命名取值为 None，但拼回仍逐字节相同。
    let 六段 = b"wmp9.npk\r{GUID}##0\r1\r0\rWindows\r0,{A}".to_vec();
    let 一条六段 = 支持库引用 { 字段: 切引用字段(&六段) };
    assert_eq!(一条六段.字段数(), 6);
    assert_eq!(一条六段.中文名(), None);
    assert_eq!(一条六段.原文(), 六段);
}

