fn 反向_数组越界被检出() {
    let 合格样本 = 样例字节();
    let mut 坏件表 = 合格样本.clone();
    // 0x00FFFFFC 是 4 的整数倍（避开「非整元素」那一支），但远大于剩余字节。
    坏件表[0x40..0x44].copy_from_slice(&0x00FF_FFFCu32.to_le_bytes());
    assert_eq!(
        反解段数据(&坏件表),
        Err(反解错误::数组越界 {
            第几: 1,
            前缀: 0x00FF_FFFC,
            剩余: (合格样本.len() - 段数据头长度 - 8 - 4) as u64,
        })
    );
}

