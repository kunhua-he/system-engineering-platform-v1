/// 体长口径：`体长实算` 只看内容，与 `头.体长` 字段无关；`重算体长` 把它对齐。
#[test]
fn 体长实算只由内容决定() {
    let mut 输出流 = 样例流();
    输出流.头.体长 = 0xDEAD_BEEF;
    let 实算 = 体长实算(&输出流);
    let 产物 = 生成段数据(&输出流).expect("生成应成功");
    assert_eq!(产物.len() as u64, 段数据头长度 as u64 + 实算);
    assert_eq!(读四字节(&产物, 0x0C) as u64, 实算, "生成重算体长，不读字段");
    输出流.重算体长();
    assert_eq!(u64::from(输出流.头.体长), 实算);
}

