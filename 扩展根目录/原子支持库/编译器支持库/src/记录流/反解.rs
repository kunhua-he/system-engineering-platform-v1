//! 反解 —— 段数据字节 → 记录流（含读数组 / 切引用字段等零件）。

use super::形状::{
    段体头, 段体魔数, 段数据头, 段数据头长度, 支持库引用, 支持库表, 引用分隔符, 记录流,
};
use super::形状::头偏移;
use super::错误::反解错误;

/// 反解：段数据字节 → 记录流。
///
/// 成功即保证 `生成段数据(反解段数据(字节)) == 字节`：所有非字节精确可写回的输入
/// （保留非零 / 补零非零 / 体长不符 / 魔数不符 / 长度前缀不整 / 越界）都在反解阶段被拒。
pub fn 反解段数据(字节: &[u8]) -> Result<记录流, 反解错误> {
    if 字节.len() < 段数据头长度 {
        return Err(反解错误::段数据头截断 {
            需要: 段数据头长度 as u64,
            实有: 字节.len() as u64,
        });
    }
    let 头部 = 解析段数据头(字节)?;

    let 实有体长 = (字节.len() - 段数据头长度) as u64;
    if 头部.体长 as u64 != 实有体长 {
        return Err(反解错误::体长不符 { 头内: 头部.体长 as u64, 实有: 实有体长 });
    }
    let 段体 = &字节[段数据头长度..];
    let (体头, 读游标) = 解析段体头(段体)?;
    let (支持库, 读游标) = 解析支持库表(段体, 读游标)?;

    // 校验槽与「体的字级 XOR 折叠」互证（与 `体长不符` 同一档 fail-closed）。
    // **放在结构解析之后**：结构错误（保留非零 / 魔数不符 / 数组越界…）必须照样报出，
    // 不被校验槽抢报（那些反向样本断言的是结构错误段位）。
    // 本腿实测：程序段（类型 3）2181/2181 = 100%；本函数只被类型 3 段调用。
    let 期望校验 = crate::容器::校验槽::折校验(&字节[段数据头长度..]);
    if 期望校验 != 头部.校验值 {
        return Err(反解错误::段数据校验不符 { 期望: 期望校验, 实取: 头部.校验值 });
    }

    Ok(记录流 {
        段头字段: 头部,
        体头,
        支持库,
        其余载荷: 段体[读游标..].to_vec(),
    })
}

/// 解析 56 字节段数据头。保留必须为 0、补零区必须全零，否则 fail-closed。
fn 解析段数据头(字节: &[u8]) -> Result<段数据头, 反解错误> {
    let 保留 = 读四字节(字节, 头偏移::保留);
    if 保留 != 0 {
        return Err(反解错误::段数据头保留非零 {
            字节位置: 头偏移::保留 as u64,
            实取: 保留,
        });
    }
    let 补零尾 = 头偏移::补零 + 头偏移::补零长度;
    if let Some(读游标) = 字节[头偏移::补零..补零尾].iter().position(|&字节| 字节 != 0) {
        return Err(反解错误::段数据头补零非零 {
            字节位置: (头偏移::补零 + 读游标) as u64,
        });
    }
    let mut 补零 = [0u8; 头偏移::补零长度];
    补零.copy_from_slice(&字节[头偏移::补零..补零尾]);

    Ok(段数据头 {
        段序号: 读四字节(字节, 头偏移::段序号),
        保留,
        校验值: 读四字节(字节, 头偏移::校验值),
        体长: 读四字节(字节, 头偏移::体长),
        补零,
    })
}

/// 解析段体头（段体前 8 字节）。返回（段体头，下一字段在段体内的偏移）。
fn 解析段体头(段体: &[u8]) -> Result<(段体头, usize), 反解错误> {
    const 体头长度: usize = 8;
    if 段体.len() < 体头长度 {
        return Err(反解错误::段体截断 {
            字节位置: 0,
            需要: 体头长度 as u64,
            剩余字节: 段体.len() as u64,
        });
    }
    let 实取魔数 = 读四字节(段体, 4);
    if 实取魔数 != 段体魔数 {
        return Err(反解错误::段体魔数不符 {
            字节位置: 4,
            实取: 实取魔数,
        });
    }
    Ok((段体头 { 首字段: 读四字节(段体, 0) }, 体头长度))
}

/// 解析支持库表（三个索引数组 + 支持库数 + N 条引用记录）。
fn 解析支持库表(段体: &[u8], 起点: usize) -> Result<(支持库表, usize), 反解错误> {
    let mut 读游标 = 起点;
    let 首数组 = 读四字节数组(段体, &mut 读游标, 1)?;
    let 次数组 = 读双字节数组(段体, &mut 读游标, 2)?;
    let 末数组 = 读双字节数组(段体, &mut 读游标, 3)?;

    if 读游标 + 2 > 段体.len() {
        return Err(反解错误::数组越界 {
            第几: 4,
            长度前缀: 2,
            剩余字节: (段体.len() - 读游标) as u64,
        });
    }
    let 声明数 = u64::from(读双字节(段体, 读游标));
    读游标 += 2;

    let 元素数 = 首数组.len() as u64;
    if 声明数 != 元素数 || 次数组.len() as u64 != 元素数 || 末数组.len() as u64 != 元素数 {
        return Err(反解错误::支持库数不符 { 数组元素数: 元素数, 声明数 });
    }

    let mut 引用表 = Vec::with_capacity(声明数 as usize);
    for 序号 in 0..声明数 {
        let 剩余字节 = (段体.len() - 读游标) as u64;
        if 剩余字节 < 4 {
            return Err(反解错误::支持库引用越界 {
                第几条: 序号 as u32,
                串长: 0,
                剩余字节,
            });
        }
        let 串长 = u64::from(读四字节(段体, 读游标));
        读游标 += 4;
        let 剩余字节 = (段体.len() - 读游标) as u64;
        if 串长 > 剩余字节 {
            return Err(反解错误::支持库引用越界 {
                第几条: 序号 as u32,
                串长,
                剩余字节,
            });
        }
        let 尾部 = 读游标 + 串长 as usize;
        引用表.push(支持库引用 {
            字段: 切引用字段(&段体[读游标..尾部]),
        });
        读游标 = 尾部;
    }

    Ok((支持库表 { 首数组, 次数组, 末数组, 引用表 }, 读游标))
}

/// 读一个「u32 字节长度前缀 + 该长度字节」的 u32 数组。
fn 读四字节数组(段体: &[u8], 读游标: &mut usize, 第几: u8) -> Result<Vec<u32>, 反解错误> {
    let 长度前缀 = 读长度前缀(段体, 读游标, 第几, 4)?;
    let 元素数 = (长度前缀 / 4) as usize;
    let mut 输出缓冲 = Vec::with_capacity(元素数);
    for 序号 in 0..元素数 {
        输出缓冲.push(读四字节(段体, *读游标 + 序号 * 4));
    }
    *读游标 += 长度前缀 as usize;
    Ok(输出缓冲)
}

/// 读一个「u32 字节长度前缀 + 该长度字节」的 u16 数组。
fn 读双字节数组(段体: &[u8], 读游标: &mut usize, 第几: u8) -> Result<Vec<u16>, 反解错误> {
    let 长度前缀 = 读长度前缀(段体, 读游标, 第几, 2)?;
    let 元素数 = (长度前缀 / 2) as usize;
    let mut 输出缓冲 = Vec::with_capacity(元素数);
    for 序号 in 0..元素数 {
        输出缓冲.push(读双字节(段体, *读游标 + 序号 * 2));
    }
    *读游标 += 长度前缀 as usize;
    Ok(输出缓冲)
}

/// 读一个数组的 u32 字节长度前缀，并校验「整元素 + 不越界」。
fn 读长度前缀(段体: &[u8], 读游标: &mut usize, 第几: u8, 元素宽: u8) -> Result<u64, 反解错误> {
    if *读游标 + 4 > 段体.len() {
        return Err(反解错误::数组越界 {
            第几,
            长度前缀: 4,
            剩余字节: (段体.len() - *读游标) as u64,
        });
    }
    let 长度前缀 = u64::from(读四字节(段体, *读游标));
    *读游标 += 4;
    if 长度前缀 % u64::from(元素宽) != 0 {
        return Err(反解错误::数组长度前缀非整元素 { 第几, 长度前缀, 元素宽 });
    }
    let 剩余字节 = (段体.len() - *读游标) as u64;
    if 长度前缀 > 剩余字节 {
        return Err(反解错误::数组越界 { 第几, 长度前缀, 剩余字节 });
    }
    Ok(长度前缀)
}

/// 按 `0x0D` 切引用字段。与 `拼串`（`支持库引用::原文`）互为逆运算：任意字节串都逐字节还原。
pub(crate) fn 切引用字段(字节串: &[u8]) -> Vec<Vec<u8>> {
    let mut 输出缓冲: Vec<Vec<u8>> = Vec::new();
    let mut 区间起点 = 0usize;
    for (读游标, &字节) in 字节串.iter().enumerate() {
        if 字节 == 引用分隔符 {
            输出缓冲.push(字节串[区间起点..读游标].to_vec());
            区间起点 = 读游标 + 1;
        }
    }
    输出缓冲.push(字节串[区间起点..].to_vec());
    输出缓冲
}

/// 小端读 u32。调用方必须先保证 `位置 + 4 <= 字节.len()`。
pub(crate) fn 读四字节(字节: &[u8], 读游标: usize) -> u32 {
    debug_assert!(读游标 + 4 <= 字节.len());
    u32::from_le_bytes([
        字节[读游标],
        字节[读游标 + 1],
        字节[读游标 + 2],
        字节[读游标 + 3],
    ])
}

/// 小端读 u16。调用方必须先保证 `位置 + 2 <= 字节.len()`。
pub(crate) fn 读双字节(字节: &[u8], 读游标: usize) -> u16 {
    debug_assert!(读游标 + 2 <= 字节.len());
    u16::from_le_bytes([字节[读游标], 字节[读游标 + 1]])
}
