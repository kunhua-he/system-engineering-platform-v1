//! 诊断 · 入口 —— **能力 1107 的本体**：程序文本 → 第一个失败的结构化诊断。
//!
//! 契约（`能力声明/1107.json`，逐字照它）：参数表只有一行 `程序文本`（类型标签 4 = 文本）；
//! 返回类型 5 = 字节集；**可抛错误码为空表** —— 空表不是漏写，是本能力的语义：
//! 它的产物就是失败本身，所以它自己**不许失败**（任何 `&str` 都给得出一个诊断）。
//!
//! # 覆盖哪些阶段（这一条必须读，否则会把 `None` 读成「编译成功」）
//!
//! 覆盖：**1101 词法分析 · 1102 语法分析** —— 本入口真跑的那两步。
//! **不覆盖**：1103 语义分析 —— 它**已落地**（`src/语义/`），但它的契约要三张注册表入参，
//! 而 1107 的契约参数表只有「程序文本」一行（`能力声明/1107.json` vs `1103.json`）⇒
//! **本入口拿不到表，覆盖不到它**；1106 编译 —— 未落地。
//! 所以 `None` 只读作「**覆盖到的阶段全过**」，**不是**「编译成功」。
//! 为什么不把「1103 没被本入口覆盖」也报成一条诊断：那要知道各阶段的载入状态与契约参数表，
//! 而载入状态住在 `src/lib.rs` 的命令表与内核的 `统一注册表` 里；`说明/设计说明.md` §五 第 3 条
//! 明令「查类型/命令/常量一律经 `统一注册表`，不许在本扩展里另存一份表」⇒ 本件不许自建一张
//! 「哪个阶段覆盖得到」的表。缺口与补法见返回说明。
//!
//! # 为什么「各阶段的失败」在这里是**至多一条**
//!
//! 链是顺序的：语法树要记号流、语义要语法树、编译要语义的产物。前一阶段失败就没有后一阶段
//! 的输入 ⇒ 第一个失败之后无可再跑。所以 `Option` 不缺信息（`项目文档/决策记录/`
//! `2026-09-26_前端是网页版编译器.md` §一 的「死在第几步 · 哪个码」就是这个读法）。
//!
//! # 为什么经本入口报得出的失败只有一条
//!
//! `建树` 是**总函数**：解不出的记号串包成 `标识符引用` 叶（`语法.rs` 判据 3）。
//! `切记号` 只在**引号不配对**时失败（报 1137，`词法/切分.rs` 文件头「裁定 2」）⇒
//! 经 [`整理诊断`] 走到 `Some(错)` 的路**只有这一条**；其余已登记码是链上构造口的防御面，
//! 不是本函数的失败面（与 `词法.rs` 对那 10 条记号层码的说法是同一件事）。
//! 链的取失败逻辑因此还要靠**注入**一级的结论来打反向样本（见 [`逐级`]）。

use crate::语言面::形状错误;

/// **能力 1107 诊断**：把程序文本送进已落地的编译阶段，交出**第一个失败**的结构化诊断。
///
/// 输入按 `项目文档/设计文档/程序文本格式.md` §二 是 **UTF-8 程序文本**（`&str` ⇒ 入口天然
/// 保证 UTF-8）。**总函数**：不 panic、不 `unwrap`、任何输入都给得出结论。
///
/// `None` = 覆盖到的阶段（1101 · 1102）全过 —— **不是**「编译成功」，见本件文件头。
pub fn 整理诊断(程序文本: &str) -> Option<形状错误> {
    逐级(crate::词法::切记号(程序文本), |流| {
        crate::语法::建树(&流).map(|_树| ())
    })
}

/// 顺序链的**取失败**：一级失败即当场交出（**不跑下一级** —— 下一级本来也要它的产物），
/// 一级过了才跑下一级。
///
/// 为什么抽成一个函数而不是写在 [`整理诊断`] 里：真实的两级里，`建树` 是总函数、
/// `切记号` 只在引号不配对时失败（文件头），所以链的**其余失败路径**经入口报不出 ——
/// 链的取失败逻辑只能靠注入一级的结论来验，不然这段逻辑一句断言都没有。
/// 与 `词法.rs` 把「10 条码」说成构造口的防御面是同一个处理：**说不出怎么到达它，就说清它不可达**。
pub(super) fn 逐级<中间值>(
    一级: Result<中间值, 形状错误>,
    二级: impl FnOnce(中间值) -> Result<(), 形状错误>,
) -> Option<形状错误> {
    match 一级 {
        Err(错) => Some(错),
        Ok(中) => 二级(中).err(),
    }
}

/// 本入口真跑过的阶段号（源：`crate::能力号`）。**只此一处**给出覆盖面 ——
/// 报告与文档都引它，避免「覆盖了哪几步」有两个说法。
pub(super) const 覆盖的阶段: [u32; 2] = [crate::能力号::词法分析, crate::能力号::语法分析];
