//! 诊断 · 整理 —— 把一份 [`形状错误`] 整理成给人看（也给 agent 看）的三样东西。
//!
//! | 口 | 交出什么 | 源（唯一事实源，本件不另存一份） |
//! |---|---|---|
//! | [`阶段号`] | 失败落在哪一层（用阶段号给） | `crate::形状错误码` 的**码区间** + `crate::错误码` 的边界常量 |
//! | [`字节位置`] | 失败的位置 `[起, 止)`（给不出就是 `None`） | `形状错误` 各变体**自带的区间字段** |
//! | [`读数`] | 一行读数（给人看） | 上面两个 + `crate::形状错误码` |
//!
//! # 为什么没有「码」这一口
//!
//! 码的映射**已经有一处**：`src/lib.rs::形状错误码`（27 个变体穷尽匹配）。在这里再写一遍
//! 就是「同一件事两套实现」（`项目文档/设计文档/代码形态分工.md` 第五节硬判据 1）。
//! 同理，**码 → 名称/说明**的文案查表也不在这里：唯一那份错误码表是 `src/lib.rs::错误码表`
//! （源 `错误码表/*.json`），在这里再写一份文案就是「同一事实两份」（`契约声明/常量表.json` 的判据）。
//!
//! # 为什么「位置」会给不出（这是一处实测缺口，不是省事）
//!
//! `说明/语言面形状.md` §5.1 说 1107 的位置「用 `起/止` 直接给（字节偏移，天然可指）」。
//! 那条**对记号层成立**（10 个变体里 7 个自带字节区间）；对**语法树层多数变体不成立**：
//! 它们只带**节点下标**（`下标` / `父` / `子` / `节点`），而把下标变成字节位置需要那份
//! 节点表 —— 语法树层的失败发生在 `语法树::新建` 里、**树被拒**，此刻没有节点表。
//! 所以本件对那 17 个变体里报不出字节位置的，一律给 `None`，**不编一个位置**。

use crate::语言面::形状错误;

/// 失败落在编译链路的**哪一层**，用**阶段号**给（源：`crate::能力号`）。
///
/// 判据：`说明/使用说明.md`「错误怎么读」——`1108–1117` 是 1101 词法分析的诊断面、
/// `1118–1133` 是 1102 语法分析的诊断面。所以本口由**码**导出，不另写一张「变体 → 阶段」表
/// （那就是第二份阶段归属）。边界取 `crate::错误码` 的两个常量，不写数字字面量。
///
/// **`1137` 是例外，必须显式点它**：它的号（1137）落在 `1118–1133` 之外，但它属**词法输入层**
/// （`形状错误::词法层输入非法`），按号区间判会错判成 1102。故这里显式并上它。
pub fn 阶段号(错: &形状错误) -> u32 {
    let 码 = crate::形状错误码(错);
    if 码 <= crate::错误码::记号流未覆盖全文 || 码 == crate::错误码::词法层输入非法 {
        crate::能力号::词法分析
    } else {
        crate::能力号::语法分析
    }
}

/// 失败**自带的原文字节区间** `[起, 止)`；`None` = 该变体只带下标（或干脆无区间），给不出。
///
/// 逐变体取的是它**自己的字段**，不是推断出来的位置；为什么有的变体给不出见本件文件头。
/// 取法逐条写在下面每一支上（`止/起` 倒置的一律按原样给出，让高亮侧看得见「倒置」这件事）。
pub fn 字节位置(错: &形状错误) -> Option<(u32, u32)> {
    use 形状错误::*;
    match 错 {
        // ── 记号层：7 个变体自带字节区间 ──
        // 「首个记号不起于 0」⇒ 没有归属的是全文开头那一段 `[0, 起)`。
        记号起点不为零 { 起 } => Some((0, *起)),
        // 「记号区间越出全文」⇒ 越出的是 `[全文长, 止)`。
        记号区间越界 { 止, 全文长, .. } => Some((*全文长, *止)),
        // 倒置区间按原样给出（起 > 止），不替它调正。
        记号区间倒置 { 起, 止, .. } => Some((*止, *起)),
        // 缝隙 = 无归属的那几字节 `[前止, 后起)`。
        记号有缝隙 { 前止, 后起, .. } => Some((*前止, *后起)),
        // 重叠 = 两个归属的那几字节 `[后起, 前止)`。
        记号有重叠 { 前止, 后起, .. } => Some((*后起, *前止)),
        文件结束非零宽 { 起, 止 } => Some((*起, *止)),
        // 「未覆盖全文」⇒ 没覆盖到的是 `[覆盖到, 全文长)`。
        记号流未覆盖全文 { 覆盖到, 全文长 } => Some((*覆盖到, *全文长)),

        // ── 语法树层：3 个变体自带字节区间 ──
        根区间不等于全文 { 起, 止, .. } => Some((*起, *止)),
        节点区间倒置 { 起, 止, .. } => Some((*止, *起)),
        节点区间越界 { 止, 全文长, .. } => Some((*全文长, *止)),

        // ── 其余 17 个变体：只有节点下标 / 记号下标（或干脆无区间），给不出字节位置 ──
        // 记号层 3 个（`记号表为空` 连表都没有；后两个只有记号下标）。
        记号表为空
        | 文件结束不在末位 { .. }
        | 末记号非文件结束 { .. }
        // 词法输入层 1 个：无载荷（`说明/语言面形状.md` §六 待办 5 的同族）。
        | 词法层输入非法
        // 语法树层 13 个（都是下标类：`下标` / `父` / `子` / `节点` / `根`）。
        | 节点表为空
        | 根下标越界 { .. }
        | 子区间倒置 { .. }
        | 子区间越界 { .. }
        | 节点是自身子节点 { .. }
        | 父未包住子 { .. }
        | 兄弟重叠 { .. }
        | 同一节点有两个父 { .. }
        | 根被当作子节点 { .. }
        | 节点是孤儿 { .. }
        | 节点被重复到达 { .. }
        | 节点从根不可达 { .. }
        | 非先序连续 { .. } => None,
    }
}

/// 一行**读数**（给人看的那一行）：`阶段 1101 · 码 1112 · 位置 [5,7)`。
///
/// 体例沿用既有读数（`src/语法/测试/夹具.rs::树读数` 的「一行一件事、数都在」的写法）；
/// 读数不是线上格式，是给人看的摘要 —— 线上格式（字节集布局）不在本件，见 `诊断.rs` 文件头。
/// **不含文案**：码 → 名称/说明 由唯一那份错误码表的消费者按码查（本件文件头已说清）。
pub fn 读数(错: &形状错误) -> String {
    let 位 = match 字节位置(错) {
        Some((起, 止)) => format!("位置 [{起},{止})"),
        None => "位置 无".to_string(),
    };
    format!("阶段 {} · 码 {} · {位}", 阶段号(错), crate::形状错误码(错))
}
