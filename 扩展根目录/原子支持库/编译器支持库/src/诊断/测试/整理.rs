/// **逐条反向样本**：27 条码各自的码 · 阶段 · 位置都对上（判据不空转）。
#[test]
fn 反向_27条码逐条报出正确的码与阶段与位置() {
    let 项表 = 样本表();
    assert_eq!(项表.len(), 27, "27 个变体该有 27 条样本（`形状错误` 的定义件）");
    for 样例项 in &项表 {
        assert_eq!(
            crate::形状错误码(&样例项.错),
            样例项.码,
            "{}：码对不上（`src/lib.rs::形状错误码` 是码的唯一来源）",
            样例项.名
        );
        assert_eq!(阶段号(&样例项.错), 样例项.阶段, "{}：阶段号对不上", 样例项.名);
        assert_eq!(字节位置(&样例项.错), 样例项.位置, "{}：位置对不上", 样例项.名);
        assert_eq!(
            读数(&样例项.错),
            期望读数(样例项.阶段, 样例项.码, 样例项.位置),
            "{}：读数体例对不上",
            样例项.名
        );
    }
}

/// **码集合恰好是 1108–1133 加 1137**：不多一条、不少一条、不重一条。
#[test]
fn 反向_样本覆盖的码恰好是1108到1133加1137() {
    let mut 码s: Vec<u32> = 样本表().iter().map(|样例项| crate::形状错误码(&样例项.错)).collect();
    码s.sort_unstable();
    let mut 期望: Vec<u32> = (1108..=1133).collect();
    期望.push(错误码::词法层输入非法);
    assert_eq!(码s, 期望, "诊断面该恰好覆盖 1108–1133 加 1137（27 条，逐条不重）");
}

/// **位置给得出 10 条、给不出 17 条** —— 这是一处实测缺口，把它钉成读数（不许含糊过去）。
///
/// 判据：`说明/语言面形状.md` §5.1 说位置「用 `起/止` 直接给」，那条对**记号层**成立
/// （10 条里 7 条自带字节区间）；对**语法树层**多数变体不成立 —— 它们只带节点下标，
/// 而失败发生在 `语法树::新建` 里、树被拒，此刻没有节点表可把下标换成字节位置。
/// `词法层输入非法`（1137）无载荷，同样给不出。
///
/// **测试名不写条数**：读数会随形状变化（原 `...10条给不出16条` 这个名字在接上 1137 后就说了谎，
/// 口径见 `项目文档/决策记录/2026-09-27_判据口径十一条.md` §十四：取值一改，名字就开始说谎）。
#[test]
fn 反向_位置给得出与给不出的条数() {
    let 项表 = 样本表();
    let 有位置数 = 项表.iter().filter(|样例项| 样例项.位置.is_some()).count();
    let 无位置数 = 项表.iter().filter(|样例项| 样例项.位置.is_none()).count();
    assert_eq!((有位置数, 无位置数), (10, 17), "位置的给得出/给不出条数漂了（见本件与 `整理.rs` 文件头）");
}

/// **每条码都真在 `错误码表/` 里登记过**：硬要求是「报**已登记**的错误码」，所以逐条读盘核。
#[test]
fn 反向_27条码都已在错误码表登记() {
    let 根目录 = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("错误码表");
    for 错误码 in (1108..=1133u32).chain(core::iter::once(错误码::词法层输入非法)) {
        let 路径 = 根目录.join(format!("{错误码}.json"));
        let 文本 = std::fs::read_to_string(&路径)
            .unwrap_or_else(|错误| panic!("码 {错误码} 没登记（{}：{错误}）", 路径.display()));
        assert!(
            文本.contains(&format!("\"码\": {错误码},")),
            "{} 里的「码」不是 {错误码}",
            路径.display()
        );
        assert!(文本.contains("\"段位\": 1,"), "码 {错误码} 的段位该是 1（支持库域）");
    }
}
