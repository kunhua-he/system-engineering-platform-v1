//! 诊断 · 测试 · 整理 —— **26 条已登记码，逐条一条反向样本**。
//!
//! 硬要求是「每条错误码至少一条能真报错的样本」。1107 自己声明的可抛错误码是**空表**
//! （`能力声明/1107.json`），所以这句话在本能力上落成：**它能诊断的 26 条码，每条都有
//! 一条真样本**（构造那个变体 → 断言报出的码 · 落的阶段 · 给的位置）。
//!
//! 为什么样本能构造：`形状错误` 是**冻结的公开枚举**（`src/语言面/形状错误定义.rs`），
//! 变体与字段全公开 —— 于是「报错」这件事不必等上游真的坏掉才能验。
//! **这不是绕过判据**：链上那两条腿是总函数（`入口.rs` 文件头），真跑报不出失败，
//! 所以整理层只能这样验；「已登记」那一半另由读 `错误码表/*.json` 断言（见末条测试）。

use super::夹具::期望读数;
