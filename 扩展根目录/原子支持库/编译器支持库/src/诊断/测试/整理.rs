/// 一条反向样本：一个变体 · 它该报的码 · 它该落的阶段 · 它该给的字节位置。
struct 反向样本 {
    名: &'static str,
    错: 形状错误,
    码: u32,
    阶段: u32,
    位置: Option<(u32, u32)>,
}

