/// **逐条反向样本**：26 条码各自的码 · 阶段 · 位置都对上（判据不空转）。
#[test]
fn 反向_26条码逐条报出正确的码与阶段与位置() {
    let 表 = 样本表();
    assert_eq!(表.len(), 26, "26 个变体该有 26 条样本（`形状错误` 的定义件）");
    for 条 in &表 {
        assert_eq!(
            crate::形状错误码(&条.错),
            条.码,
            "{}：码对不上（`src/lib.rs::形状错误码` 是码的唯一来源）",
            条.名
        );
        assert_eq!(阶段号(&条.错), 条.阶段, "{}：阶段号对不上", 条.名);
        assert_eq!(字节位置(&条.错), 条.位置, "{}：位置对不上", 条.名);
        assert_eq!(
            读数(&条.错),
            期望读数(条.阶段, 条.码, 条.位置),
            "{}：读数体例对不上",
            条.名
        );
    }
}

/// **码集合恰好是 1108–1133**：不多一条、不少一条、不重一条。
#[test]
fn 反向_样本覆盖的码恰好是1108到1133() {
    let mut 码s: Vec<u32> = 样本表().iter().map(|条| crate::形状错误码(&条.错)).collect();
    码s.sort_unstable();
    let 期望: Vec<u32> = (1108..=1133).collect();
    assert_eq!(码s, 期望, "诊断面该恰好覆盖 1108–1133（26 条，逐条不重）");
}

/// **位置给得出 10 条、给不出 16 条** —— 这是一处实测缺口，把它钉成读数（不许含糊过去）。
///
/// 判据：`说明/语言面形状.md` §5.1 说位置「用 `起/止` 直接给」，那条对**记号层**成立
/// （10 条里 7 条自带字节区间）；对**语法树层**多数变体不成立 —— 它们只带节点下标，
/// 而失败发生在 `语法树::新建` 里、树被拒，此刻没有节点表可把下标换成字节位置。
#[test]
fn 反向_位置给得出10条给不出16条() {
    let 表 = 样本表();
    let 有 = 表.iter().filter(|条| 条.位置.is_some()).count();
    let 无 = 表.iter().filter(|条| 条.位置.is_none()).count();
    assert_eq!((有, 无), (10, 16), "位置的给得出/给不出条数漂了（见本件与 `整理.rs` 文件头）");
}

/// **每条码都真在 `错误码表/` 里登记过**：硬要求是「报**已登记**的错误码」，所以逐条读盘核。
#[test]
fn 反向_26条码都已在错误码表登记() {
    let 根 = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("错误码表");
    for 码 in 1108..=1133u32 {
        let 路 = 根.join(format!("{码}.json"));
        let 文 = std::fs::read_to_string(&路)
            .unwrap_or_else(|错| panic!("码 {码} 没登记（{}：{错}）", 路.display()));
        assert!(
            文.contains(&format!("\"码\": {码},")),
            "{} 里的「码」不是 {码}",
            路.display()
        );
        assert!(文.contains("\"段位\": 1,"), "码 {码} 的段位该是 1（支持库域）");
    }
}
