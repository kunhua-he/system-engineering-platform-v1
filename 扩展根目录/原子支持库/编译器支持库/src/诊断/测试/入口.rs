//! 诊断 · 测试 · 入口 —— 入口的正向样本 · 链的失败路径（注入）· 覆盖面读数。
//!
//! 硬要求里那条「反向样本」在 [`super::整理`] 里逐码打全；本件补的是**入口这一层**：
//! 它是不是总函数（任何 `&str` 都给得出诊断）、链的取失败逻辑对不对、覆盖面到底覆盖了哪几步。
//!
//! 本件**不假装**入口能报出失败：链上那两条腿都是总函数（`入口.rs` 文件头），所以
//! 真跑出来的永远是 `None` —— 这不是没测，是**实测事实**，把它写成断言才不会再被人误读。

use super::夹具::{读语料, 语料文件};
use crate::语言面::形状错误;
use crate::诊断::{入口, 整理诊断};

/// 一份真程序文本（`语料/真文本/硬文本-samples_e8_ManyFiles_e8test3-0.txt` 的那一段形态，
/// 照 `说明/真文本覆盖.md` 原样：`.版本 2` 起段 · 声明表 · 一句裸调用 · CRLF）。
const 真文本: &str = ".版本 2\r\n\r\n.常量 网页事件_onactivate, “onactivate”, 公开\r\n\r\n.程序集 程序集1\r\n\r\n.子程序 _启动子程序, 整数型, , 本子程序在程序启动后最先执行\r\n\r\n    信息框 (“祖国，您好！”, 0, , )\r\n\r\n    返回 (0)\r\n";

/// **正向样本**：空文本与一份真程序文本都给得出诊断（总函数），且都无失败。
#[test]
fn 入口_任何文本都给得出诊断() {
    for 原文 in ["", " ", "\r\n", 真文本] {
        assert_eq!(
            整理诊断(原文),
            None,
            "{原文:?}：覆盖到的阶段（1101 · 1102）该全过"
        );
    }
}

/// **总函数**：一批刁钻输入都不 panic、都给出结论（`说明/设计说明.md` §五 第 2 条：
/// 失败是结构化错误码，不是字符串、不是 panic）。
#[test]
fn 入口_总函数_刁钻输入不panic() {
    // 每一份都点一个词法/语法的实测边界（`词法/切分.rs` 文件头四条裁定 · `语法/建树.rs` 兜底）。
    let 刁钻 = [
        "' 只有注释没有换行",
        "' 注释吃到文件尾\r",
        "“未闭合的全角引号",
        "\"未闭合的半角引号",
        "置入代码 ({ 139, 69, 8 })",
        "如果真 (甲 ＝ 乙)\r\n\t计次循环首 (1)\r\n",
        ".参数 甲, 文本型, 参考, , ",
        "计数-1 ＝ 3.51",
        "　　.版本 2",       // 全角空格缩进（兜底字符）
        "\u{0}\u{1}\u{7f}", // 控制字符
        "　",
        "\r\r\r",
        "&EndScene_hook ＝ 假",
        ".成员 格式标签, 短整数型, , , wFormatTag，记录着此声音的格式代号",
    ];
    for 原文 in 刁钻 {
        let 果 = 整理诊断(原文);
        // 结论要么是「覆盖到的阶段全过」，要么是一条已登记的结构化错误 —— 两种都不是 panic。
        if let Some(错) = &果 {
            let 码 = crate::形状错误码(错);
            assert!((1108..=1133).contains(&码), "{原文:?}：报出的码 {码} 没在 1108–1133 里");
        }
    }
}

/// **语料读数**：53 份真文本逐份送进入口 —— 全过，且记下字节数（不是「没测」的读数）。
#[test]
fn 入口_语料53份_逐份给无失败() {
    let 文件s = 语料文件();
    assert_eq!(文件s.len(), 53, "语料该是 53 份（`说明/真文本覆盖.md` §一）");
    let mut 总字节 = 0usize;
    for 路 in &文件s {
        let 原文 = 读语料(路);
        assert_eq!(
            整理诊断(&原文),
            None,
            "{}：覆盖到的阶段该全过（该腿是总函数，见 `入口.rs` 文件头）",
            路.display()
        );
        总字节 += 原文.len();
    }
    assert!(总字节 > 400_000, "语料总字节 {总字节} 太小，样本像是没读到");
    println!("【入口】53 份 · {总字节} 字节 · 覆盖到的阶段全过 · 失败 0 条");
}

/// **链的失败路径（注入）**：一级失败即**当场停下**，二级一次都不许跑。
///
/// 为什么靠注入：真实的两级都是总函数，经入口报不出失败 —— 不注入，这段逻辑一句断言都没有。
#[test]
fn 链_一级失败即当场停下_不跑二级() {
    let 一级错 = 形状错误::记号表为空;
    let 果 = 入口::逐级::<()>(Err(一级错), |_中| panic!("一级失败时不许跑二级"));
    assert_eq!(果, Some(一级错), "一级的失败该原样交出");
}

/// **链的失败路径（注入）**：一级过了才跑二级；二级失败交出二级的错。
#[test]
fn 链_一级过了才跑二级_二级失败交出二级的错() {
    let 二级错 = 形状错误::根区间不等于全文 { 起: 0, 止: 1, 全文长: 2 };
    let 果 = 入口::逐级(Ok(()), |_中| Err(二级错));
    assert_eq!(果, Some(二级错), "二级的失败该原样交出");

    // 两级都过 ⇒ 无失败（这才是 `None` 的含义）。
    assert_eq!(入口::逐级(Ok(()), |_中| Ok(())), None);
}

/// **覆盖面**：只覆盖本扩展里已落地的两条腿 —— 1103 语义 / 1106 编译**不在**覆盖里。
///
/// 这条是防「假绿」的：`None` 只读作「覆盖到的阶段全过」。1103 / 1106 未落地
/// （`项目文档/未完成事项.md` 第 2 条），把它们当成「过」就是假绿。
#[test]
fn 覆盖_只覆盖已落地的两条腿() {
    assert_eq!(入口::覆盖的阶段, [1101, 1102], "覆盖的阶段漂了");
    for 没覆盖 in [1103u32, 1106] {
        assert!(
            !入口::覆盖的阶段.contains(&没覆盖),
            "阶段 {没覆盖} 没落地，不许出现在覆盖里"
        );
    }
}
