//! 编号与码面 —— 能力号 · 错误码 · 两个「错误变体 → 码」的映射口。
//!
//! **本件是路由**：声明子模块 · 再导出公开面 · 零实现（与 `src/词法.rs` 同形）。
//!
//! | 件 | 管什么 |
//! |---|---|
//! | [`能力号定义`](编号与码面/能力号定义.rs) | `pub mod 能力号`：1101–1199 的号 |
//! | [`错误码定义`](编号与码面/错误码定义.rs) | `pub mod 错误码`：11xx 的码 + 37 条错误码登记表（**同件**：实现侧扫描器 ③f 要求同文件解析） |
//! | [`码映射`](编号与码面/码映射.rs) | `形状错误码` / `语义错误码`：变体 → 码的穷尽匹配 |
//!
//! **公开面逐字不变**：`crate::能力号` · `crate::错误码` · `crate::形状错误码` 全都照旧
//! （`诊断/整理.rs` · `诊断/测试/整理.rs` · `词法/切分测试/反向.rs` 等处的调用地址一处不改）。
//!
//! 两条工具链强制（与 `语言面.rs` 同源，实测过）：rustc 拒绝自动加载非 ASCII 文件名的模块
//! （E0754），故每条 `mod` 都显式给 `#[path]`；**模块名不能与它再导出的同名项撞**
//! （E0255）—— 故 `能力号` / `错误码` 两个模块块住在带 `定义` 后缀的件里。

#[path = "编号与码面/能力号定义.rs"]
pub(crate) mod 能力号定义;
#[path = "编号与码面/错误码定义.rs"]
pub(crate) mod 错误码定义;
#[path = "编号与码面/码映射.rs"]
pub(crate) mod 码映射;

pub use 能力号定义::能力号;
pub use 错误码定义::错误码;
pub use 码映射::形状错误码;
pub(crate) use 码映射::语义错误码;
