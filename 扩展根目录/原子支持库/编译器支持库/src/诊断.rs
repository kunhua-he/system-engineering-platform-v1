//! 诊断 —— **能力 1107 诊断**的实现：把编译各阶段的失败整理成给人看（也给 agent 看）的诊断。
//!
//! 上级：`扩展根目录/原子支持库/编译器支持库/` ／ 形状：`src/语言面/`（**已冻结，本腿一字不改**）
//! 相关：`能力声明/1107.json`（参数表行序即契约）· `说明/语言面形状.md` §五（1107 吃什么吐什么）·
//! `说明/使用说明.md`「错误怎么读」（码段 ↔ 阶段的对应）· `项目文档/设计文档/能力包件.md`（1106 的产物）
//!
//! # 本件只做三件事
//!
//! 1. 声明三个子模块（[`入口`] 是能力本体 · [`整理`] 是三个整理口）；
//! 2. 再导出公开面 [`整理诊断`] · [`阶段号`] · [`字节位置`] · [`读数`]；
//! 3. **零实现**。
//!
//! # 公开面（逐条照 `能力声明/1107.json`：一个参数 · 返回类型 5 = 字节集 · 可抛错误码空）
//!
//! ```text
//! 诊断::整理诊断(程序文本: &str) -> Option<形状错误>   // 能力本体
//! 诊断::阶段号(&形状错误) -> u32                      // 整理：失败落在哪一层（用阶段号给）
//! 诊断::字节位置(&形状错误) -> Option<(u32, u32)>      // 整理：失败的位置
//! 诊断::读数(&形状错误) -> String                      // 整理：给人看的那一行
//! ```
//!
//! # 为什么产物是 `语言面::形状错误`，而不是新造一个「诊断」类型
//!
//! 1107 的**产物形状没有冻结件可依**：`说明/语言面形状.md` §五 只说「错误码 → 中文说明 + 位置」，
//! 没说字节布局；`能力包件.md` §六 待办 1 那句「同一份数据的两个出口不许各定一套」同样管这里。
//! 按「接口先冻结，再派活」（`项目文档/设计文档/内核落点.md` 第六节），**不许自己造一个形状**。
//! 而 `形状错误` 恰好装得下那三样：它是**结构化**的（不是字符串）、每个变体自带区间字段、
//! 且 `crate::形状错误码` 已把 26 个变体穷尽映射到 26 条已登记码（1108–1133）。
//! 所以本腿**一字不造类型**：产物是冻结类型，码走既有映射，文案按码查唯一那份错误码表。
//!
//! # 两条工具链强制（与 `语言面.rs` / `词法.rs` 同源，实测过）
//!
//! 1. rustc 拒绝自动加载非 ASCII 文件名的模块（E0754），故每条 `mod` 都显式给 `#[path]`；
//! 2. 模块名不能与它再导出的同名项撞（E0255），故入口不叫 `诊断` 而叫 [`整理诊断`]
//!    （`说明/使用说明.md`「调哪个号」那张表里那一行就叫「整理诊断」）。

// 1107 **已接线**（`src/lib.rs`：`#[path = "诊断.rs"] pub mod 诊断;` + 命令表/函数表位 1107
// ⇒ `诊断执行`）：`整理诊断` 由执行函数调用，三个整理口由它的编码腿
// （`lib.rs::原生路编码::编码诊断结果`）调用 —— 形状与实现是接口，不是死代码。
//
// 豁免因此**收窄**成 dead_code 一条，只服务 [`覆盖的阶段`](入口::覆盖的阶段)
// （`入口.rs` 的覆盖面声明）：它是 `pub(super)`、只活在测试里（`诊断/测试/入口.rs`
// 拿它钉覆盖面），生产区无人用 ⇒ 判 dead。原来那半个 `unused_imports` 随接线不再需要，撤掉。
#![allow(dead_code)]

#[path = "诊断/入口.rs"]
mod 入口;
#[path = "诊断/整理.rs"]
mod 整理;

pub use 入口::整理诊断;
pub use 整理::{字节位置, 阶段号, 读数};

