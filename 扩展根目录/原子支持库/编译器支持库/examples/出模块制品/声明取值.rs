//! 声明字段取值：文本 / 整数 / 默认值槽（缺项即拒，不静默补默认）。

use v1_contract::{数据槽, 类型标签};

use super::声明读取::声明值;

pub(super) fn 取文本<'值>(声明: &'值 声明值, 键名: &str) -> Result<&'值 str, String> {
    声明
        .取键(键名)
        .and_then(声明值::取文本)
        .ok_or_else(|| format!("声明缺文本字段 {键名}"))
}

pub(super) fn 取整数(声明: &声明值, 键名: &str) -> Result<i64, String> {
    声明
        .取键(键名)
        .and_then(声明值::取数值)
        .ok_or_else(|| format!("声明缺整数字段 {键名}"))
}

/// 参数声明的 `默认值` → 槽（**照声明给的类型标签**，不一律当整数）。
///
/// `类型标签 0` = 没填 ⇒ 空槽；其余 = 同标签的内联零值槽（默认值只表达「没填/占位」，
/// 真值由调用方传）。
pub(super) fn 取默认值槽(参数项: &声明值) -> 数据槽 {
    let 默认标签 = 参数项
        .取键("默认值")
        .and_then(|默认值项| 默认值项.取键("类型标签"))
        .and_then(声明值::取数值)
        .unwrap_or(0);
    match u32::try_from(默认标签) {
        Ok(标签号) if 标签号 != 0 => 数据槽::内联槽(类型标签::构造(标签号), 0, 0),
        _ => 数据槽::空槽(),
    }
}
