//! 能力声明 → 接口说明六字段（逐字段取自声明，不字面写死）；
//! 可抛错误码逐项取本包 `错误码表/<码>.json`，未登记即报「读不到」。

use std::path::Path;

use v1_compiler::能力包件::{接口参数项, 接口错误项, 接口说明};

use super::声明读取::{声明值, 读声明件};
use super::声明取值::{取整数, 取文本, 取默认值槽};

/// 能力声明 JSON → 接口说明六字段（**逐字段取自声明**，不字面写死）。
pub(super) fn 取接口说明(模块目录: &Path, 能力声明: &声明值) -> Result<接口说明, String> {
    let 参数表 = 能力声明
        .取键("参数表")
        .and_then(声明值::取表)
        .ok_or_else(|| "能力声明缺 参数表".to_owned())?
        .iter()
        .map(|参数项| {
            Ok(接口参数项 {
                名称: 取文本(参数项, "名称")?.to_owned(),
                类型标签: 取整数(参数项, "类型标签")? as u32,
                状态位: 参数项.取键("状态位").and_then(声明值::取数值).unwrap_or(0) as u16,
                默认值: 取默认值槽(参数项),
            })
        })
        .collect::<Result<Vec<_>, String>>()?;
    Ok(接口说明 {
        编号: 取整数(能力声明, "编号")? as u32,
        名称: 取文本(能力声明, "名称")?.to_owned(),
        说明: 能力声明.取键("说明").and_then(声明值::取文本).unwrap_or_default().to_owned(),
        参数表,
        返回类型: 取整数(能力声明, "返回类型")? as u32,
        可抛错误码: 能力声明
            .取键("可抛错误码")
            .and_then(声明值::取整数表)
            .unwrap_or_default()
            .into_iter()
            .map(|码值| 取错误项(模块目录, 码值))
            .collect::<Result<Vec<_>, String>>()?,
    })
}

/// 一个可抛错误码 → 接口错误项（名称/段位/三标志都取自本包的 `错误码表/<码>.json`）。
///
/// 声明里引用了未登记的错误码，装包环节就该拒（`扩展装载/开发标准/必备件.json` 的
/// 「未登记的错误码不许抛出」）—— 本件直接报「读不到」，不静默补一个空名。
pub(super) fn 取错误项(模块目录: &Path, 码值: i64) -> Result<接口错误项, String> {
    let 声明件路径 = 模块目录.join(format!("错误码表/{码值}.json"));
    let 错误码声明 = 读声明件(&声明件路径)?;
    Ok(接口错误项 {
        码值: 码值 as u32,
        段位: 错误码声明.取键("段位").and_then(声明值::取数值).unwrap_or(0) as u32,
        名称: 取文本(&错误码声明, "名称")?.to_owned(),
        可重试: 取逻辑(&错误码声明, "可重试"),
        可自愈: 取逻辑(&错误码声明, "可自愈"),
        需人工: 取逻辑(&错误码声明, "需人工"),
        已登记: true,
    })
}

/// 声明里的逻辑字段（缺项 = 假）。
pub(super) fn 取逻辑(声明: &声明值, 键名: &str) -> bool {
    matches!(声明.取键(键名), Some(声明值::逻辑值(true)))
}
