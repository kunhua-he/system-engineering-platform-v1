//! 出模块制品 —— 用**真的 1106 链**给一个模块编出 `.模块制品`。
//!
//! 怎么跑（在 `扩展根目录/原子支持库/编译器支持库` 下；本 crate 是**独立工作区**，
//! 从仓根跑 `-p v1-compiler` 会报「not found in workspace」）：
//!
//! ```sh
//! V1_MODULE_SCRATCH_DIR="$HOME/Library/Application Support/系统工程平台V1/临时件/模块编译" \
//!   cargo run --locked --example 出模块制品 -- <模块目录绝对路径>
//! ```
//!
//! 模块目录**必须显式给绝对路径**（不再有默认样本 —— 默认值会让「只认一个样本」重新长回来）。
//!
//! `V1_MODULE_SCRATCH_DIR` **未设即明确失败** —— 编执行体要一个暂存目录，而本件是扩展、
//! 取不到 `运行内核/运行数据根` 的解析口，也不许自造临时路径（判据 ㉕）。
//!
//! # 它走的链就是 1106 走的那一条
//!
//! `1106` 的**边界入口**是 `pub(crate) extern "C" fn 编译执行`（给跨边界调用用的），
//! 构建侧拿不到它。故本例按它的**三步**用公开面走同一条链：
//!
//! 1. 真跑上游链 `词法::切记号 → 语法::建树 → 语义::语义分析`（与 1106 逐字同路）；
//! 2. 解出六字段（见下面「模块声明 → 接口说明段」）；
//! 3. `能力包件::装包` —— **就是 1106 内部调的那一个函数**，不是另写一份装包。
//!
//! # 模块声明 → 接口说明段：**逐字段读真声明**
//!
//! 映射（`2026-09-27_1106产物与入参裁决.md` §四 缺口 2）：接口说明段六字段 =
//! 该模块 `能力声明/<编号>.json` 的六字段，逐条同名同序（依据 `契约声明/格式说明.md` §三
//! 与 `接口面形状.md` §三）。本版把它落成代码：能力声明由 `声明读取` 读，六字段、参数表、
//! 可抛错误码全部取自声明，**不再字面写死**；装完包当场拆开做往返断言。
//!
//! 一制品容纳同场景多能力；接口说明组与编号函数逐项对应，合编一次。
//!
//! # 执行体段（段 20）：真编出来的本机机器码
//!
//! 本仓**没有「程序文本 → WebAssembly」的代码生成器**（`能力声明/1106.json` 与
//! `2026-09-27_1106产物与入参裁决.md` §四 都记着这条）⇒ 段 17 的 wasm 含义对本样本不适用。
//!
//! 按 `项目文档/决策记录/2026-10-12_模块执行体承载与编译裁决.md`，本样本走**段 20**：
//! 程序文本 → `本机生成`（Rust 源码）→ **构建侧编译**（`rustc` → `cdylib`）→ 装段 20。
//! 段 20 载荷 = `[平台身份长度 u16 大端][平台身份][执行体机器码]`（形状见
//! `执行函数面/本机生成/编译本机源码.rs` 文件头）。
//!
//! ⇒ 段 20 里是**真机器码**（`dlopen` 取 `v1_模块执行`），不是空段、不是源码、不是 wasm。

