//! 出模块制品 —— 用**真的 1106 链**给一个模块编出 `.模块制品`。
//!
//! 怎么跑（在仓根）：
//!
//! ```sh
//! cargo run --quiet --locked -p v1-compiler --example 出模块制品 -- 扩展根目录/组合模块库/求和模块
//! ```
//!
//! 不传参数就用本样本模块（`扩展根目录/组合模块库/求和模块`）。
//!
//! # 它走的链就是 1106 走的那一条
//!
//! `1106` 的**边界入口**是 `pub(crate) extern "C" fn 编译执行`（给跨边界调用用的），
//! 构建侧拿不到它。故本例按它的**三步**用公开面走同一条链：
//!
//! 1. 真跑上游链 `词法::切记号 → 语法::建树 → 语义::语义分析`（与 1106 逐字同路）；
//! 2. 解出六字段（见下面「模块声明 → 接口说明段」）；
//! 3. `能力包件::装包` —— **就是 1106 内部调的那一个函数**，不是另写一份装包。
//!
//! # 模块声明 → 接口说明段（**映射未裁，本例取的是最自然的那一条**）
//!
//! 库里搜过「模块声明」：**没有裁决规定这个映射**（`2026-09-27_1106产物与入参裁决.md` §四
//! 把它列作缺口 2「六字段来源属未裁的模块声明形状」）。本例取的映射是：
//! **接口说明段六字段 = 该模块 `能力声明/<编号>.json` 的六字段，逐条同名同序** ——
//! 依据 `契约声明/格式说明.md` §三（能力声明字段表）与 `接口面形状.md` §三
//! （接口说明段 = `GET /接口/能力/<编号>` 返回体 = 能力声明）。
//!
//! ★ 六字段在本例里是**字面写死的**，不是从 JSON 读的 —— 理由两条：① 上面的映射还没有
//! 代码落点，它是本例的**判断**；② 扩展侧要读 JSON 就得再带一个 JSON 解析器（本仓零第三方
//! 依赖，而扩展侧现有的 JSON 件是**测试件**）。⇒ 把映射定下来、给代码落点，是另一条活。
//! 本例用**往返断言**兜住它：装完包当场拆开，六字段逐字段比一次。
//!
//! # 能力码段为空（如实登记，不是偷工）
//!
//! 本仓**没有「程序文本 → WebAssembly」的代码生成器**（`能力声明/1106.json` 与
//! `2026-09-27_1106产物与入参裁决.md` §四 都记着这条）⇒ 1106 的能力码段由调用方传入，
//! 本例传**空字节集**。传一份别的来源的机器码进去就是「编事实」。

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use v1_compiler::能力包件::{self, 接口参数项, 接口说明};
use v1_compiler::{语法, 语义, 词法};
use v1_contract::{数据槽, 类型标签};

/// 默认模块目录（仓根相对）—— 本仓唯一的模块样本。
const 默认模块目录: &str = "扩展根目录/组合模块库/求和模块";

fn main() -> ExitCode {
    let 命令行参数: Vec<String> = std::env::args().skip(1).collect();
    let 模块目录 = PathBuf::from(命令行参数.first().map(String::as_str).unwrap_or(默认模块目录));
    match 出制品(&模块目录) {
        Ok(说明) => {
            println!("出模块制品：{} · 能力 {}「{}」", 模块目录.display(), 说明.编号, 说明.名称);
            ExitCode::SUCCESS
        }
        Err(失败原因) => {
            eprintln!("出模块制品失败：{失败原因}");
            ExitCode::FAILURE
        }
    }
}

/// 一个模块目录 → 写出 `.模块制品`，返回它自述的那条接口说明。
fn 出制品(模块目录: &Path) -> Result<接口说明, String> {
    let 模块名 = 模块目录
        .file_name()
        .and_then(|名称| 名称.to_str())
        .ok_or_else(|| format!("从 {} 取不出模块名", 模块目录.display()))?
        .to_owned();
    let 源件 = 模块目录.join(format!("{模块名}.程序文本"));
    let 源文本 = fs::read_to_string(&源件).map_err(|错误| format!("读不到 {}：{错误}", 源件.display()))?;

    // 第一步：真跑上游链（与 1106 同路）。三张表传空（空字节集 = 空表，不是非法）。
    let 空表 = Vec::new();
    let 命令表 = 语义::名号表::解码(&空表).ok_or_else(|| "空命令表解不开".to_owned())?;
    let 常量表 = 语义::名号表::解码(&空表).ok_or_else(|| "空常量表解不开".to_owned())?;
    let 类型表 = 语义::名号表::解码(&空表).ok_or_else(|| "空类型表解不开".to_owned())?;
    let 记号流 = 词法::切记号(&源文本).map_err(|错误| format!("词法不过：{错误:?}"))?;
    let 语法树 = 语法::建树(&记号流).map_err(|错误| format!("语法不过：{错误:?}"))?;
    语义::语义分析(&语法树, &命令表, &常量表, &类型表)
        .map_err(|错误| format!("语义不过：{错误:?}"))?;

    // 第二步：六字段（映射见文件头；字面写死）。
    let 说明 = 接口说明 {
        编号: 7950,
        名称: "求和".to_owned(),
        说明: "把两个整数相加，返回它们的和。**样本能力**：它的存在是为了让「模块」这一类扩展有一条完整的装载面样本（声明 → 制品 → 解析 → 登记），不是一条真实业务能力。".to_owned(),
        参数表: vec![
            接口参数项 { 名称: "被加数".to_owned(), 类型标签: 1, 状态位: 0, 默认值: 内联整数槽() },
            接口参数项 { 名称: "加数".to_owned(), 类型标签: 1, 状态位: 0, 默认值: 内联整数槽() },
        ],
        返回类型: 1,
        可抛错误码: Vec::new(),
    };

    // 第三步：装包 —— 1106 内部调的就是这一个函数。能力码段空（理由见文件头）。
    let 包件字节 = 能力包件::装包(&说明, &[]).map_err(|错误| format!("装包失败：{错误:?}"))?;
    let (接口字节, 能力码) = 能力包件::拆包(&包件字节).ok_or_else(|| "装出来的包拆不开".to_owned())?;
    let 回读 = v1_compiler::能力包件::接口段编码::解码(&接口字节)
        .ok_or_else(|| "装出来的接口说明段解不开".to_owned())?;
    if 回读 != 说明 || !能力码.is_empty() {
        return Err("往返不一致：装出来的包与交进去的六字段对不上".to_owned());
    }

    let 制品件 = 模块目录.join(format!("{模块名}.模块制品"));
    fs::write(&制品件, &包件字节).map_err(|错误| format!("写不到 {}：{错误}", 制品件.display()))?;
    println!("  本体 {} → 制品 {}（{} 字节）", 源件.display(), 制品件.display(), 包件字节.len());
    Ok(说明)
}

/// 一个全零的内联整数槽（类型标签 `1` = 整数；默认值全零 = 「没填」）。
fn 内联整数槽() -> 数据槽 {
    数据槽::内联槽(类型标签::构造(1), 0, 0)
}
