//! 出模块制品 —— 用**真的 1106 链**给一个模块编出 `.模块制品`。
//!
//! 怎么跑（在 `扩展根目录/原子支持库/编译器支持库` 下；本 crate 是**独立工作区**，
//! 从仓根跑 `-p v1-compiler` 会报「not found in workspace」）：
//!
//! ```sh
//! V1_MODULE_SCRATCH_DIR="$HOME/Library/Application Support/系统工程平台V1/临时件/模块编译" \
//!   cargo run --locked --example 出模块制品 -- <模块目录绝对路径>
//! ```
//!
//! 模块目录不传就用本样本模块（`扩展根目录/组合模块库/求和模块`，**须给绝对路径**）。
//!
//! `V1_MODULE_SCRATCH_DIR` **未设即明确失败** —— 编执行体要一个暂存目录，而本件是扩展、
//! 取不到 `运行内核/运行数据根` 的解析口，也不许自造临时路径（判据 ㉕）。
//!
//! # 它走的链就是 1106 走的那一条
//!
//! `1106` 的**边界入口**是 `pub(crate) extern "C" fn 编译执行`（给跨边界调用用的），
//! 构建侧拿不到它。故本例按它的**三步**用公开面走同一条链：
//!
//! 1. 真跑上游链 `词法::切记号 → 语法::建树 → 语义::语义分析`（与 1106 逐字同路）；
//! 2. 解出六字段（见下面「模块声明 → 接口说明段」）；
//! 3. `能力包件::装包` —— **就是 1106 内部调的那一个函数**，不是另写一份装包。
//!
//! # 模块声明 → 接口说明段（**映射未裁，本例取的是最自然的那一条**）
//!
//! 库里搜过「模块声明」：**没有裁决规定这个映射**（`2026-09-27_1106产物与入参裁决.md` §四
//! 把它列作缺口 2「六字段来源属未裁的模块声明形状」）。本例取的映射是：
//! **接口说明段六字段 = 该模块 `能力声明/<编号>.json` 的六字段，逐条同名同序** ——
//! 依据 `契约声明/格式说明.md` §三（能力声明字段表）与 `接口面形状.md` §三
//! （接口说明段 = `GET /接口/能力/<编号>` 返回体 = 能力声明）。
//!
//! ★ 六字段在本例里是**字面写死的**，不是从 JSON 读的 —— 理由两条：① 上面的映射还没有
//! 代码落点，它是本例的**判断**；② 扩展侧要读 JSON 就得再带一个 JSON 解析器（本仓零第三方
//! 依赖，而扩展侧现有的 JSON 件是**测试件**）。⇒ 把映射定下来、给代码落点，是另一条活。
//! 本例用**往返断言**兜住它：装完包当场拆开，六字段逐字段比一次。
//!
//! # 执行体段（段 20）：真编出来的本机机器码
//!
//! 本仓**没有「程序文本 → WebAssembly」的代码生成器**（`能力声明/1106.json` 与
//! `2026-09-27_1106产物与入参裁决.md` §四 都记着这条）⇒ 段 17 的 wasm 含义对本样本不适用。
//!
//! 按 `项目文档/决策记录/2026-10-12_模块执行体承载与编译裁决.md`，本样本走**段 20**：
//! 程序文本 → `本机生成`（Rust 源码）→ **构建侧编译**（`rustc` → `cdylib`）→ 装段 20。
//! 段 20 载荷 = `[平台身份长度 u16 大端][平台身份][执行体机器码]`（形状见
//! `执行函数面/本机生成/编译本机源码.rs` 文件头）。
//!
//! ⇒ 段 20 里是**真机器码**（`dlopen` 取 `v1_模块执行`），不是空段、不是源码、不是 wasm。

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use v1_compiler::能力包件::{接口参数项, 接口说明};
use v1_compiler::执行函数面::本机生成;
use v1_compiler::{语法, 语义, 词法};
use v1_contract::{数据槽, 类型标签};

/// 默认模块目录（仓根相对）—— 本仓唯一的模块样本。
const 默认模块目录: &str = "扩展根目录/组合模块库/求和模块";

fn main() -> ExitCode {
    let 命令行参数: Vec<String> = std::env::args().skip(1).collect();
    let 模块目录 = PathBuf::from(命令行参数.first().map(String::as_str).unwrap_or(默认模块目录));
    match 出制品(&模块目录) {
        Ok(说明) => {
            println!("出模块制品：{} · 能力 {}「{}」", 模块目录.display(), 说明.编号, 说明.名称);
            ExitCode::SUCCESS
        }
        Err(失败原因) => {
            eprintln!("出模块制品失败：{失败原因}");
            ExitCode::FAILURE
        }
    }
}

/// 一个模块目录 → 写出 `.模块制品`，返回它自述的那条接口说明。
fn 出制品(模块目录: &Path) -> Result<接口说明, String> {
    let 模块名 = 模块目录
        .file_name()
        .and_then(|名称| 名称.to_str())
        .ok_or_else(|| format!("从 {} 取不出模块名", 模块目录.display()))?
        .to_owned();
    let 源件 = 模块目录.join(format!("{模块名}.程序文本"));
    let 源文本 = fs::read_to_string(&源件).map_err(|错误| format!("读不到 {}：{错误}", 源件.display()))?;

    // 第一步：真跑上游链（与 1106 同路）。三张表传空（空字节集 = 空表，不是非法）。
    let 空表 = Vec::new();
    let 命令表 = 语义::名号表::解码(&空表).ok_or_else(|| "空命令表解不开".to_owned())?;
    let 常量表 = 语义::名号表::解码(&空表).ok_or_else(|| "空常量表解不开".to_owned())?;
    let 类型表 = 语义::名号表::解码(&空表).ok_or_else(|| "空类型表解不开".to_owned())?;
    let 记号流 = 词法::切记号(&源文本).map_err(|错误| format!("词法不过：{错误:?}"))?;
    let 语法树 = 语法::建树(&记号流).map_err(|错误| format!("语法不过：{错误:?}"))?;
    语义::语义分析(&语法树, &命令表, &常量表, &类型表)
        .map_err(|错误| format!("语义不过：{错误:?}"))?;

    // 第二步：六字段（映射见文件头；字面写死）。
    let 说明 = 接口说明 {
        编号: 7950,
        名称: "求和".to_owned(),
        说明: "把两个整数相加，返回它们的和。**样本能力**：它的存在是为了让「模块」这一类扩展有一条完整的装载面样本（声明 → 制品 → 解析 → 登记），不是一条真实业务能力。".to_owned(),
        参数表: vec![
            接口参数项 { 名称: "被加数".to_owned(), 类型标签: 1, 状态位: 0, 默认值: 内联整数槽() },
            接口参数项 { 名称: "加数".to_owned(), 类型标签: 1, 状态位: 0, 默认值: 内联整数槽() },
        ],
        返回类型: 1,
        可抛错误码: Vec::new(),
    };

    // 第三步：真执行体 —— 本机生成（程序文本 → Rust 源码）→ 编译（源码 → 机器码）。
    // 依据：项目文档/决策记录/2026-10-12_模块执行体承载与编译裁决.md（执行体放段 20 · 构建侧编译）。
    let 执行体 = 出执行体(&源文本)?;

    // 第四步：装包 —— 接口说明段 16 + 本机执行体段 20 + 指纹段 18，走统一 codec。
    let 接口字节 = v1_contract::接口说明段::编码(&说明);
    let 包件字节 = v1_contract::容器::装包三段(&接口字节, &执行体, v1_contract::容器::段类型_本机执行体);
    let 三段 = v1_contract::容器::解包类型化(&包件字节).map_err(|错误| format!("装出来的包拆不开：{错误:?}"))?;
    let 回读 = v1_contract::接口说明段::解码(&三段.接口说明段)
        .ok_or_else(|| "装出来的接口说明段解不开".to_owned())?;
    if 回读 != 说明 || 三段.本体段 != 执行体 || 三段.本体段类别 != v1_contract::容器::本体段类别::本机执行体 {
        return Err("往返不一致：装出来的包与交进去的执行体/六字段对不上".to_owned());
    }

    let 制品件 = 模块目录.join(format!("{模块名}.模块制品"));
    fs::write(&制品件, &包件字节).map_err(|错误| format!("写不到 {}：{错误}", 制品件.display()))?;
    println!("  本体 {} → 制品 {}（{} 字节）", 源件.display(), 制品件.display(), 包件字节.len());
    Ok(说明)
}

/// 一个全零的内联整数槽（类型标签 `1` = 整数；默认值全零 = 「没填」）。
fn 内联整数槽() -> 数据槽 {
    数据槽::内联槽(类型标签::构造(1), 0, 0)
}

/// 程序文本 → 段 20 载荷（`平台身份` + 本机机器码）。
///
/// 依据 `项目文档/决策记录/2026-10-12_模块执行体承载与编译裁决.md`：
/// 执行体放段 20 · **构建侧编译**（运行侧不现编）· 制品带平台身份。
fn 出执行体(源文本: &str) -> Result<Vec<u8>, String> {
    let (工具链身份, 平台身份, 工具链命令) = 取工具链();
    let (契约产物, 依赖目录) = 找契约产物()?;
    let 类型表 = 语义::名号表::从项(vec![
        ("整数型".as_bytes().to_vec(), 1),
        ("文本型".as_bytes().to_vec(), 4),
    ]);
    let 产物 = 本机生成::生成本机源码(&本机生成::本机生成请求 {
        程序文本: 源文本.as_bytes(),
        命令表: &语义::名号表::空实例(),
        常量表: &语义::名号表::空实例(),
        类型表: &类型表,
        锁定依赖: &[],
        工具链身份: &工具链身份,
        平台身份: &平台身份,
    })
    .map_err(|错误| format!("本机生成不过：{错误:?}"))?;
    let 输出目录 = 取暂存目录()?;
    fs::create_dir_all(&输出目录).map_err(|错误| format!("建暂存目录失败：{错误}"))?;
    let 输出路径 = 输出目录.join("模块执行体.dylib");
    本机生成::编译本机源码(&产物, 7950, &工具链命令, &契约产物, &依赖目录, &输出路径)?;
    let 执行体 = fs::read(&输出路径).map_err(|错误| format!("读不出执行体：{错误}"))?;
    if 执行体.is_empty() {
        return Err("编出来的执行体是空的".to_owned());
    }
    Ok(本机生成::打包执行体载荷(&平台身份, &执行体))
}

/// 编执行体用的暂存目录：**只从环境变量来，没有默认值**。
///
/// 同 `src/测试夹具.rs::取语料根目录` 的理由：本 crate 是**扩展**，按纪律只依赖底座公布的契约
/// ⇒ 取不到 `运行内核/运行数据根` 的解析口；而直接读 `V1_RUN_DATA_ROOT` 再自拼路径，
/// 又是判据 ㉕ 当场报红的形状（自拼运行数据路径）。⇒ 暂存目录由**调用方**显式给，
/// 未设即**明确失败**（不静默回落到某个写死的路径 —— 那是「无执行假绿」的老病）。
///
/// **变量名用 ASCII**：同 `测试夹具.rs` 的 `V1_CORPUS_ROOT` —— 环境变量名要能在 shell 里
/// 直接赋值；zsh/bash 都不吃中文变量名（`V1_模块编译暂存目录=x cmd` 会被当成命令执行）。
const 暂存目录变量名: &str = "V1_MODULE_SCRATCH_DIR";

fn 取暂存目录() -> Result<PathBuf, String> {
    let 取值 = std::env::var(暂存目录变量名).unwrap_or_default();
    if 取值.trim().is_empty() {
        return Err(format!(
            "未设 {暂存目录变量名}（编执行体要一个暂存目录，本件不自造路径）\
             —— 例：{暂存目录变量名}=\"$HOME/Library/Application Support/系统工程平台V1/临时件/模块编译\""
        ));
    }
    Ok(PathBuf::from(取值))
}

/// 本机工具链：`RUSTC` 环境变量（缺省 `rustc`）→ `(工具链身份, 平台身份, 命令路径)`。
fn 取工具链() -> (String, String, PathBuf) {
    let 工具链命令 = PathBuf::from(std::env::var_os("RUSTC").unwrap_or_else(|| "rustc".into()));
    let 输出 = std::process::Command::new(&工具链命令).arg("-vV").output();
    let Ok(输出) = 输出 else { return (String::new(), String::new(), 工具链命令) };
    let 工具链身份 = String::from_utf8_lossy(&输出.stdout).to_string();
    let 平台身份 = 工具链身份
        .lines()
        .find_map(|记录行| 记录行.strip_prefix("host: "))
        .unwrap_or_default()
        .to_owned();
    (工具链身份, 平台身份, 工具链命令)
}

/// 编执行体要两样东西：契约产物（`libv1_contract-*.rlib`）与它所在的依赖目录。
///
/// 例子二进制住在 `target/<档>/examples/`，契约产物在 `target/<档>/deps/` ⇒ 上一层再进 `deps`。
fn 找契约产物() -> Result<(PathBuf, PathBuf), String> {
    let 自身 = std::env::current_exe().map_err(|错误| format!("取不到自身路径：{错误}"))?;
    let 同级 = 自身.parent().ok_or_else(|| "取不到自身所在目录".to_owned())?;
    let 依赖目录 = if 同级.file_name().is_some_and(|名称| 名称 == "examples") {
        同级.parent().unwrap_or(同级).join("deps")
    } else {
        同级.to_owned()
    };
    let 契约产物表: Vec<PathBuf> = fs::read_dir(&依赖目录)
        .map_err(|错误| format!("读不到依赖目录 {}：{错误}", 依赖目录.display()))?
        .filter_map(|目录项| 目录项.ok().map(|项| 项.path()))
        .filter(|路径| {
            路径
                .file_name()
                .is_some_and(|名称| 名称.to_string_lossy().starts_with("libv1_contract-"))
                && 路径.extension().is_some_and(|后缀| 后缀 == "rlib")
        })
        .collect();
    match 契约产物表.as_slice() {
        [唯一] => Ok((唯一.clone(), 依赖目录)),
        [] => Err(format!("依赖目录 {} 里没有 libv1_contract-*.rlib", 依赖目录.display())),
        _ => Err(format!("依赖目录 {} 里有 {} 份契约产物，分不清用哪份", 依赖目录.display(), 契约产物表.len())),
    }
}
