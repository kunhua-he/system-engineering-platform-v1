fn main() -> ExitCode {
    let 命令行参数: Vec<String> = std::env::args().skip(1).collect();
    let Some(首个参数) = 命令行参数.first() else {
        eprintln!("用法：出模块制品 <模块目录绝对路径>");
        return ExitCode::FAILURE;
    };
    match 出制品(Path::new(首个参数)) {
        Ok(说明表) => {
            println!("出模块制品：{} · {}个能力", 首个参数, 说明表.len());
            ExitCode::SUCCESS
        }
        Err(失败原因) => {
            eprintln!("出模块制品失败：{失败原因}");
            ExitCode::FAILURE
        }
    }
}

/// 一个模块目录 → 写出 `.模块制品`，返回它自述的那条接口说明。
fn 出制品(模块目录: &Path) -> Result<Vec<接口说明>, String> {
    let 目录名 = 模块目录.file_name().and_then(|名称| 名称.to_str()).ok_or("模块目录名非法")?.to_owned();
    let 包声明 = 读声明件(&模块目录.join("包声明.json"))?;
    let 仓根 = 找仓根(模块目录)?;
    let 能力声明表 = 列声明目录(&模块目录.join("能力声明"))?;
    if 能力声明表.is_empty() { return Err("模块没有能力声明".to_owned()); }
    let 依赖要求表 = 取依赖要求表(&包声明)?;
    let 依赖目录表 = 定位依赖包(&仓根, &依赖要求表)?;
    let 类型表 = 收集类型表(&仓根, &依赖目录表)?;
    let 命令表 = 收集命令表(&依赖目录表)?;
    let (工具链身份, 平台身份, 工具链命令) = 取工具链();
    let mut 说明表 = Vec::new();
    let mut 产物组 = Vec::new();
    for 能力声明 in &能力声明表 {
        let 编号 = u32::try_from(取整数(能力声明, "编号")?).map_err(|_| "模块能力号越界")?;
        let 源件 = if let Some(源码映射) = 包声明.取键("源码映射") {
            let 源码名 = 取文本(源码映射, &编号.to_string())?;
            let 源件 = 模块目录.join(源码名).canonicalize().map_err(|错误| format!("模块源码不可解析：{错误}"))?;
            if !源件.starts_with(模块目录.canonicalize().map_err(|错误| format!("模块根不可解析：{错误}"))?) { return Err("模块源码越出包目录".to_owned()); }
            源件
        } else { 模块目录.join(format!("{目录名}.程序文本")) };
        let 源文本 = fs::read_to_string(&源件).map_err(|错误| format!("读不到 {}：{错误}", 源件.display()))?;
        let 锁定依赖 = 收集锁定依赖(&命令表, &源文本, &依赖目录表)?;
        let 记号流 = 词法::切记号(&源文本).map_err(|错误| format!("能力{编号}词法不过：{错误:?}"))?;
        let 语法树 = 语法::建树(&记号流).map_err(|错误| format!("能力{编号}语法不过：{错误:?}"))?;
        语义::语义分析(&语法树, &命令表, &语义::名号表::空实例(), &类型表).map_err(|错误| format!("能力{编号}语义不过：{错误:?}"))?;
        let 产物 = 本机生成::生成本机源码(&本机生成::本机生成请求 {
            程序文本: 源文本.as_bytes(), 命令表: &命令表, 常量表: &语义::名号表::空实例(), 类型表: &类型表,
            锁定依赖: &锁定依赖, 工具链身份: &工具链身份, 平台身份: &平台身份,
        }).map_err(|错误| format!("能力{编号}本机生成不过：{错误:?}"))?;
        说明表.push(取接口说明(模块目录, 能力声明)?);
        产物组.push((编号, 产物));
    }
    说明表.sort_by_key(|说明| 说明.编号);
    let 执行体 = 出执行体(&产物组, &工具链命令, &平台身份)?;
    let 接口字节 = v1_contract::接口说明段::编码接口组(&说明表).ok_or("模块接口说明组为空、重复或长度越界")?;
    let 包件字节 = v1_contract::容器::装包三段(&接口字节, &执行体, v1_contract::容器::段类型_本机执行体);
    let 三段 = v1_contract::容器::解包类型化(&包件字节).map_err(|错误| format!("装出的模块包不可读：{错误:?}"))?;
    let 回读 = v1_contract::接口说明段::解码接口组(&三段.接口说明段).ok_or("模块接口组解不开")?;
    if 回读 != 说明表 || 三段.本体段 != 执行体 || 三段.本体段类别 != v1_contract::容器::本体段类别::本机执行体 { return Err("模块接口组与执行体往返不一致".to_owned()); }
    let 制品件 = 模块目录.join(format!("{目录名}.模块制品"));
    fs::write(&制品件, &包件字节).map_err(|错误| format!("写不到 {}：{错误}", 制品件.display()))?;
    println!("  {}个能力合编一件：{}（{}字节）", 说明表.len(), 制品件.display(), 包件字节.len());
    Ok(说明表)
}

/// 能力声明 JSON → 接口说明六字段（**逐字段取自声明**，不字面写死）。
fn 取接口说明(模块目录: &Path, 能力声明: &声明值) -> Result<接口说明, String> {
    let 参数表 = 能力声明
        .取键("参数表")
        .and_then(声明值::取表)
        .ok_or_else(|| "能力声明缺 参数表".to_owned())?
        .iter()
        .map(|参数项| {
            Ok(接口参数项 {
                名称: 取文本(参数项, "名称")?.to_owned(),
                类型标签: 取整数(参数项, "类型标签")? as u32,
                状态位: 参数项.取键("状态位").and_then(声明值::取数值).unwrap_or(0) as u16,
                默认值: 取默认值槽(参数项),
            })
        })
        .collect::<Result<Vec<_>, String>>()?;
    Ok(接口说明 {
        编号: 取整数(能力声明, "编号")? as u32,
        名称: 取文本(能力声明, "名称")?.to_owned(),
        说明: 能力声明.取键("说明").and_then(声明值::取文本).unwrap_or_default().to_owned(),
        参数表,
        返回类型: 取整数(能力声明, "返回类型")? as u32,
        可抛错误码: 能力声明
            .取键("可抛错误码")
            .and_then(声明值::取整数表)
            .unwrap_or_default()
            .into_iter()
            .map(|码值| 取错误项(模块目录, 码值))
            .collect::<Result<Vec<_>, String>>()?,
    })
}

/// 一个可抛错误码 → 接口错误项（名称/段位/三标志都取自本包的 `错误码表/<码>.json`）。
///
/// 声明里引用了未登记的错误码，装包环节就该拒（`扩展装载/开发标准/必备件.json` 的
/// 「未登记的错误码不许抛出」）—— 本件直接报「读不到」，不静默补一个空名。
fn 取错误项(模块目录: &Path, 码值: i64) -> Result<接口错误项, String> {
    let 声明件路径 = 模块目录.join(format!("错误码表/{码值}.json"));
    let 错误码声明 = 读声明件(&声明件路径)?;
    Ok(接口错误项 {
        码值: 码值 as u32,
        段位: 错误码声明.取键("段位").and_then(声明值::取数值).unwrap_or(0) as u32,
        名称: 取文本(&错误码声明, "名称")?.to_owned(),
        可重试: 取逻辑(&错误码声明, "可重试"),
        可自愈: 取逻辑(&错误码声明, "可自愈"),
        需人工: 取逻辑(&错误码声明, "需人工"),
        已登记: true,
    })
}

/// 声明里的逻辑字段（缺项 = 假）。
fn 取逻辑(声明: &声明值, 键名: &str) -> bool {
    matches!(声明.取键(键名), Some(声明值::逻辑值(true)))
}

/// 一条依赖要求：标识串 + 版本门槛（主 · 次）。
///
/// 构建侧与装载侧用**同一份合同**：`版本三元组::满足`（主不同比主、主相同比次，构建号不参与）。
struct 依赖要求 {
    标识串: String,
    版本门槛: 版本要求,
}

/// 依赖清单 / 依赖版本要求：两张表按下标一一对应，项数不等即拒；
/// 每项按正式形状 `{主, 次}` 解析（未知键 / 缺键 / 越 i32 一律拒，不猜 semver）。
fn 取依赖要求表(包声明: &声明值) -> Result<Vec<依赖要求>, String> {
    let 依赖清单 = 包声明.取键("依赖清单").and_then(声明值::取文本表).unwrap_or_default();
    let 版本要求表 = 包声明.取键("依赖版本要求").and_then(声明值::取表).unwrap_or_default();
    if 依赖清单.len() != 版本要求表.len() {
        return Err(format!(
            "依赖清单与依赖版本要求项数不等（{} vs {}）—— 两张表按下标一一对应",
            依赖清单.len(),
            版本要求表.len()
        ));
    }
    let 自身标识串 = 取文本(包声明, "标识串")?;
    let mut 要求表: Vec<依赖要求> = Vec::with_capacity(依赖清单.len());
    for (序号, (标识串, 要求项)) in 依赖清单.iter().zip(版本要求表).enumerate() {
        if !是合法依赖标识(标识串) {
            return Err(format!("依赖清单第 {} 项不是 32 位十六进制标识串：{标识串}", 序号 + 1));
        }
        if 标识串.as_str() == 自身标识串 {
            return Err(format!("依赖清单含自身标识串 {标识串}"));
        }
        if 要求表.iter().any(|已有项| 已有项.标识串 == *标识串) {
            return Err(format!("依赖清单重复项 {标识串}（清单不自洽）"));
        }
        要求表.push(依赖要求 {
            标识串: 标识串.clone(),
            版本门槛: 取版本要求(要求项, 序号)?,
        });
    }
    Ok(要求表)
}

/// `{主, 次}` → `版本要求`（正式形状只有两键，无修订段；未知键即拒）。
fn 取版本要求(要求项: &声明值, 序号: usize) -> Result<版本要求, String> {
    let 出处 = format!("依赖版本要求第 {} 项", 序号 + 1);
    let 声明值::对象项(成员表) = 要求项 else {
        return Err(format!("{出处} 不是对象"));
    };
    for (键名, _) in 成员表 {
        if 键名.as_str() != "主" && 键名.as_str() != "次" {
            return Err(format!("{出处} 有未知键 {键名}（正式形状只有 主 / 次）"));
        }
    }
    let 主段 = i32::try_from(取整数字段(要求项, "主", &出处)?).map_err(|_| format!("{出处} 的 主 超出 i32"))?;
    let 次段 = i32::try_from(取整数字段(要求项, "次", &出处)?).map_err(|_| format!("{出处} 的 次 超出 i32"))?;
    Ok(版本要求::构造(主段, 次段))
}

/// 被选依赖包的 `实现版本` → `版本三元组`（正式形状 `{主, 次, 构建}`）。
fn 取实现版本(包声明: &声明值, 标识串: &str) -> Result<版本三元组, String> {
    let 出处 = format!("依赖包 {标识串} 的 实现版本");
    let Some(版本项) = 包声明.取键("实现版本") else {
        return Err(format!("{出处} 缺失"));
    };
    let 声明值::对象项(成员表) = 版本项 else {
        return Err(format!("{出处} 不是对象"));
    };
    for (键名, _) in 成员表 {
        if 键名.as_str() != "主" && 键名.as_str() != "次" && 键名.as_str() != "构建" {
            return Err(format!("{出处} 有未知键 {键名}（正式形状只有 主 / 次 / 构建）"));
        }
    }
    let 主段 = i32::try_from(取整数字段(版本项, "主", &出处)?).map_err(|_| format!("{出处} 的 主 超出 i32"))?;
    let 次段 = i32::try_from(取整数字段(版本项, "次", &出处)?).map_err(|_| format!("{出处} 的 次 超出 i32"))?;
    let 构建段 = i32::try_from(取整数字段(版本项, "构建", &出处)?).map_err(|_| format!("{出处} 的 构建 超出 i32"))?;
    Ok(版本三元组::构造(主段, 次段, 构建段))
}

/// 一个整数键（缺键 / 非整数即拒）。
fn 取整数字段(声明对象: &声明值, 键名: &str, 出处: &str) -> Result<i64, String> {
    声明对象
        .取键(键名)
        .and_then(声明值::取数值)
        .ok_or_else(|| format!("{出处} 缺整数键 {键名}"))
}

/// 32 位十六进制标识串（与装载侧 `是合法标识串` 同一条形状；构建侧只读，不引运行内核）。
fn 是合法依赖标识(标识串: &str) -> bool {
    标识串.len() == 32 && 标识串.bytes().all(|字节| 字节.is_ascii_hexdigit())
}

/// 标识串 → 包目录（扫 `扩展根目录/` 下全部 `包声明.json`，按标识串精确命中），
/// 并**当场按装载依赖校验的同一合同**核被选包的 `实现版本` 是否满足版本门槛。
///
/// fail-closed：命中 0 份 = 缺依赖；命中多份 = 分不清用哪份；被选包缺 `标识串` / `实现版本`
/// 或版本不满足（含「要求未来版本」）= 拒。不让要求未来不兼容版本也生成。
fn 定位依赖包(仓根: &Path, 要求表: &[依赖要求]) -> Result<Vec<PathBuf>, String> {
    let mut 目录表 = Vec::with_capacity(要求表.len());
    for 要求项 in 要求表 {
        let 命中表: Vec<PathBuf> = 扫包目录(&仓根.join("扩展根目录"))
            .into_iter()
            .filter(|包目录| {
                读声明件(&包目录.join("包声明.json"))
                    .ok()
                    .and_then(|声明| 声明.取键("标识串").and_then(声明值::取文本).map(str::to_owned))
                    .is_some_and(|自身标识| 自身标识 == 要求项.标识串)
            })
            .collect();
        let [包目录] = 命中表.as_slice() else {
            return Err(match 命中表.len() {
                0 => format!("依赖 {} 在 扩展根目录/ 下找不到同标识串的包", 要求项.标识串),
                _ => format!(
                    "依赖 {} 在 扩展根目录/ 下命中 {} 份包，分不清用哪份",
                    要求项.标识串,
                    命中表.len()
                ),
            });
        };
        let 包声明 = 读声明件(&包目录.join("包声明.json"))?;
        let 实际版本 = 取实现版本(&包声明, &要求项.标识串)?;
        if !实际版本.满足(&要求项.版本门槛) {
            return Err(format!(
                "依赖 {} 的版本不满足要求：要求 {}.{}，被选包实现版本 {}.{}.{}",
                要求项.标识串,
                要求项.版本门槛.主版本,
                要求项.版本门槛.次版本号,
                实际版本.主版本,
                实际版本.次版本号,
                实际版本.构建
            ));
        }
        目录表.push(包目录.clone());
    }
    Ok(目录表)
}

/// 递归扫出含 `包声明.json` 的目录（有界：只看 `扩展根目录/` 这棵树）。
fn 扫包目录(扫描根: &Path) -> Vec<PathBuf> {
    let mut 结果表 = Vec::new();
    let mut 待扫 = vec![扫描根.to_path_buf()];
    while let Some(当前目录) = 待扫.pop() {
        if 当前目录.join("包声明.json").is_file() {
            结果表.push(当前目录.clone());
        }
        let Ok(目录项) = fs::read_dir(&当前目录) else { continue };
        for 目录条目 in 目录项.flatten() {
            let 条目路径 = 目录条目.path();
            if 条目路径.is_dir()
                && 条目路径.file_name().is_some_and(|目录名| 目录名 != "target" && 目录名 != ".git")
            {
                待扫.push(条目路径);
            }
        }
    }
    结果表
}

/// 类型表：仓根契约类型声明 ＋ 各依赖包的类型声明（名 → 号）。
///
/// **两种写法同号**：声明里的 `名称`（如 `整数`）与易语言式 `名称`＋`型`（如 `整数型`）——
/// 模块程序文本按后者写（既有样本就这么写），构建侧不能因为差一个「型」字就拒。
/// 标签超出 `u16` 的声明（`4294967295` 这类占位号）不进表：名号表的号是 `u16`。
fn 收集类型表(仓根: &Path, 依赖目录表: &[PathBuf]) -> Result<语义::名号表, String> {
    let mut 声明目录表 = vec![仓根.join("契约声明/类型声明")];
    for 依赖目录 in 依赖目录表 {
        let 声明目录 = 依赖目录.join("类型声明");
        if 声明目录.try_exists().map_err(|错误| format!("类型声明目录无法检查：{错误}"))? {
            声明目录表.push(声明目录);
        }
    }
    let mut 类型表项: BTreeMap<Vec<u8>, u16> = BTreeMap::new();
    for 声明目录 in 声明目录表 {
        for 声明件 in 列声明目录(&声明目录)? {
            let Ok(类型号) = 取整数(&声明件, "类型标签") else { continue };
            let Ok(u16标签) = u16::try_from(类型号) else { continue };
            let Some(名称) = 声明件.取键("名称").and_then(声明值::取文本) else { continue };
            类型表项.insert(名称.as_bytes().to_vec(), u16标签);
            类型表项.insert(format!("{名称}型").into_bytes(), u16标签);
        }
    }
    if 类型表项.is_empty() {
        return Err("类型表是空的：契约与依赖的类型声明都没读到".to_owned());
    }
    Ok(语义::名号表::从项(类型表项.into_iter().collect()))
}

/// 命令表：依赖包全部能力声明（名称 → 编号）。
fn 收集命令表(依赖目录表: &[PathBuf]) -> Result<语义::名号表, String> {
    let mut 类型表项: BTreeMap<Vec<u8>, u16> = BTreeMap::new();
    for 依赖目录 in 依赖目录表 {
        for 能力声明 in 列声明目录(&依赖目录.join("能力声明"))? {
            let (Ok(编号), Some(名称)) = (
                取整数(&能力声明, "编号"),
                能力声明.取键("名称").and_then(声明值::取文本),
            ) else {
                return Err(format!("依赖 {} 的能力声明缺 编号/名称", 依赖目录.display()));
            };
            let u16编号 = u16::try_from(编号).map_err(|_| format!("能力号 {编号} 超出 u16"))?;
            类型表项.insert(名称.as_bytes().to_vec(), u16编号);
        }
    }
    Ok(语义::名号表::从项(类型表项.into_iter().collect()))
}

/// 锁定依赖：命令表里**在本模块程序文本中出现过**的能力，签名逐项取自该能力的声明。
///
/// 为什么先按出现过滤：锁定依赖是「本模块真实调用了谁」的签名集合。把依赖包的全部能力
/// 都锁进来，会让本子集不支持的类型（如双精度入参）把整次生成拖红 —— 那不是模块的问题。
/// 少锁则当场红（表达式生成按名查不到签名即拒），故这是**宁可红不静默**的过滤。
fn 收集锁定依赖(
    命令表: &语义::名号表,
    源文本: &str,
    依赖目录表: &[PathBuf],
) -> Result<Vec<本机依赖>, String> {
    let mut 锁定表 = Vec::new();
    for 依赖目录 in 依赖目录表 {
        for 能力声明 in 列声明目录(&依赖目录.join("能力声明"))? {
            let Some(名称) = 能力声明.取键("名称").and_then(声明值::取文本) else { continue };
            if !源文本.contains(名称) {
                continue;
            }
            let 编号 = 命令表
                .按名取号(名称.as_bytes())
                .ok_or_else(|| format!("命令表里没有 {名称}"))?;
            let 入参类型表 = 能力声明
                .取键("参数表")
                .and_then(声明值::取表)
                .unwrap_or_default()
                .iter()
                .map(|参数项| 取整数(参数项, "类型标签").map(|标签| 标签 as u32))
                .collect::<Result<Vec<_>, String>>()?;
            锁定表.push(本机依赖 {
                名称: 名称.as_bytes().to_vec(),
                能力号: 编号,
                入参类型表,
                返回类型: 取整数(&能力声明, "返回类型")? as u32,
            });
        }
    }
    Ok(锁定表)
}

/// 列一个声明目录里的全部 `*.json`（按文件名升序，读不动即拒）。
fn 列声明目录(声明目录: &Path) -> Result<Vec<声明值>, String> {
    let 目录项 = fs::read_dir(声明目录).map_err(|错误| format!("读不到 {}：{错误}", 声明目录.display()))?;
    let mut 路径表: Vec<PathBuf> = 目录项
        .flatten()
        .map(|目录条目| 目录条目.path())
        .filter(|条目路径| 条目路径.extension().is_some_and(|扩展名| 扩展名 == "json"))
        .collect();
    路径表.sort();
    路径表.iter().map(|路径| 读声明件(路径)).collect()
}

/// 从给定目录往上找仓根（含 `契约声明/` 的那一级）。
fn 找仓根(起点: &Path) -> Result<PathBuf, String> {
    let 绝对起点 = fs::canonicalize(起点)
        .map_err(|错误| format!("取不到 {} 的真实路径：{错误}", 起点.display()))?;
    for 候选目录 in 绝对起点.ancestors() {
        if 候选目录.join("契约声明").is_dir() {
            return Ok(候选目录.to_path_buf());
        }
    }
    Err(format!("从 {} 往上找不到含 契约声明/ 的仓根", 起点.display()))
}

fn 取文本<'值>(声明: &'值 声明值, 键名: &str) -> Result<&'值 str, String> {
    声明
        .取键(键名)
        .and_then(声明值::取文本)
        .ok_or_else(|| format!("声明缺文本字段 {键名}"))
}

fn 取整数(声明: &声明值, 键名: &str) -> Result<i64, String> {
    声明
        .取键(键名)
        .and_then(声明值::取数值)
        .ok_or_else(|| format!("声明缺整数字段 {键名}"))
}

/// 参数声明的 `默认值` → 槽（**照声明给的类型标签**，不一律当整数）。
///
/// `类型标签 0` = 没填 ⇒ 空槽；其余 = 同标签的内联零值槽（默认值只表达「没填/占位」，
/// 真值由调用方传）。
fn 取默认值槽(参数项: &声明值) -> 数据槽 {
    let 默认标签 = 参数项
        .取键("默认值")
        .and_then(|默认值项| 默认值项.取键("类型标签"))
        .and_then(声明值::取数值)
        .unwrap_or(0);
    match u32::try_from(默认标签) {
        Ok(标签号) if 标签号 != 0 => 数据槽::内联槽(类型标签::构造(标签号), 0, 0),
        _ => 数据槽::空槽(),
    }
}

/// 程序文本 → 段 20 载荷（`平台身份` + 本机机器码）。
///
/// 依据 `项目文档/决策记录/2026-10-12_模块执行体承载与编译裁决.md`：
/// 执行体放段 20 · **构建侧编译**（运行侧不现编）· 制品带平台身份。
fn 出执行体(产物组: &[(u32, 本机生成::本机源码产物)], 工具链命令: &Path, 平台身份: &str) -> Result<Vec<u8>, String> {
    let (契约产物, 依赖目录) = 找契约产物()?;
    let 输出目录 = 取暂存目录()?;
    fs::create_dir_all(&输出目录).map_err(|错误| format!("建暂存目录失败：{错误}"))?;
    let 输出路径 = 输出目录.join("模块执行体.dylib");
    本机生成::编译模块源码组(产物组, 工具链命令, &契约产物, &依赖目录, &输出路径)?;
    let 执行体 = fs::read(&输出路径).map_err(|错误| format!("读不出执行体：{错误}"))?;
    if 执行体.is_empty() { return Err("编出来的执行体是空的".to_owned()); }
    Ok(v1_contract::容器::打包执行体载荷(平台身份, &执行体))
}

/// 编执行体用的暂存目录：**只从环境变量来，没有默认值**。
///
/// 同 `src/测试夹具.rs::取语料根目录` 的理由：本 crate 是**扩展**，按纪律只依赖底座公布的契约
/// ⇒ 取不到 `运行内核/运行数据根` 的解析口；而直接读 `V1_RUN_DATA_ROOT` 再自拼路径，
/// 又是判据 ㉕ 当场报红的形状（自拼运行数据路径）。⇒ 暂存目录由**调用方**显式给，
/// 未设即**明确失败**（不静默回落到某个写死的路径 —— 那是「无执行假绿」的老病）。
///
/// **变量名用 ASCII**：同 `测试夹具.rs` 的 `V1_CORPUS_ROOT` —— 环境变量名要能在 shell 里
/// 直接赋值；zsh/bash 都不吃中文变量名（`V1_模块编译暂存目录=x cmd` 会被当成命令执行）。
const 暂存目录变量名: &str = "V1_MODULE_SCRATCH_DIR";

fn 取暂存目录() -> Result<PathBuf, String> {
    let 取值 = std::env::var(暂存目录变量名).unwrap_or_default();
    if 取值.trim().is_empty() {
        return Err(format!(
            "未设 {暂存目录变量名}（编执行体要一个暂存目录，本件不自造路径）\
             —— 例：{暂存目录变量名}=\"$HOME/Library/Application Support/系统工程平台V1/临时件/模块编译\""
        ));
    }
    Ok(PathBuf::from(取值))
}

/// 本机工具链：`RUSTC` 环境变量（缺省 `rustc`）→ `(工具链身份, 平台身份, 命令路径)`。
fn 取工具链() -> (String, String, PathBuf) {
    let 工具链命令 = PathBuf::from(std::env::var_os("RUSTC").unwrap_or_else(|| "rustc".into()));
    let 输出 = std::process::Command::new(&工具链命令).arg("-vV").output();
    let Ok(输出) = 输出 else { return (String::new(), String::new(), 工具链命令) };
    let 工具链身份 = String::from_utf8_lossy(&输出.stdout).to_string();
    let 平台身份 = 工具链身份
        .lines()
        .find_map(|记录行| 记录行.strip_prefix("host: "))
        .unwrap_or_default()
        .to_owned();
    (工具链身份, 平台身份, 工具链命令)
}

