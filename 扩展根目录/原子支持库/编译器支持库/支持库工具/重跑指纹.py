#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""重跑指纹 —— 刷新 `指纹.json`（本扩展的声明文件 + 实现文件的 sha256 快照）。

**为什么要有这一件**：`指纹.json` 原先的「生成命令」只写了一句散文
（「python（只读遍历本目录…）」）—— **不是一条可跑的命令**，所以它一漂就没人能刷新，
指纹形同虚设。本脚本就是那条可跑的命令；重跑即刷新。

    python3 扩展根目录/原子支持库/编译器支持库/支持库工具/重跑指纹.py           # 刷新 指纹.json
    python3 扩展根目录/原子支持库/编译器支持库/支持库工具/重跑指纹.py --检查    # 只比对，不改盘（漂了即退出码 1）

**范围（与旧件逐字一致，本脚本不扩不缩）**：
  声明文件：`包声明.json` · `能力声明/*.json` · `错误码表/*.json` · `类型声明/*.json`
  实现文件：`Cargo.toml` · `src/**/*.rs`
  不含：`用法说明/`（散文）· `语料/`（取证语料）· `工具/`（本脚本自身）· `实现/` 与 `能力契约/`（空目录）
        · `编译器支持库.dylib`（构建产物，落源码树是待处置项）· `Cargo.lock`

**判据**：`--检查` 把当前盘面重算一遍，与 `指纹.json` 的 `指纹` 表逐键比；
  多键 / 少键 / 值不同 ⇒ 报出并退出码 1（**fail-closed**：不静默）。`生成时刻` / `生成命令` 不参与比对。

────────────────────────────────────────────────────────────────────────────
本文件是**路由**（`开发规范.md` §六）：声明子模块 · 再导出公开面 · **零实现**。
实现按关注点在同名字文件夹 `重跑指纹/`（一个关注点一个文件）。
**公开面逐字不变**：`main` 等模块级名字由包 `__init__.py::__all__` 全导一遍 ⇒
`from 重跑指纹 import <名>` 逐字不变（纯搬家，`生成命令` 与 `指纹.json` 取值不变）。
"""

import sys
import time
from pathlib import Path

起始时刻 = time.monotonic()  # 壳起表点：必须在 import 业务包**之前**（见 构建装配/门禁/命令壳.py）

sys.path.insert(0, str(Path(__file__).resolve().parents[4]))  # 仓根：取共享门禁
try:
    from 构建装配.门禁 import 自门禁  # noqa: E402
except ModuleNotFoundError as 错误:
    # `测试验证/准入判据/准入判据/样本.py::⑭` 会把本扩展复制成**单扩展临时树**再跑本件 ——
    # 那棵树里没有 `构建装配/`（共享门禁不可得）。此时退化成**不带壳**（临时树的墙钟不由本件
    # 负责），行为与加壳前逐字一致 ⇒ ⑭ 的正向样本不因加壳而红。只吞「共享门禁包本身不在」，
    # 别的导入错照旧抛出（fail-closed：不静默）。
    if 错误.name != "构建装配":
        raise

    def 自门禁(起始时刻, 退出码, 尾巴余量毫秒, 修法, 输出流=None):  # noqa: N802
        return 退出码

sys.path.insert(0, str(Path(__file__).resolve().parent))  # 同名字包所在的 <工具>/

from 重跑指纹 import *  # noqa: E402,F401,F403 —— 再导出公开面（`重跑指纹/__init__.py::__all__`）
from 重跑指纹 import 入口函数  # noqa: E402

if __name__ == "__main__":
    sys.exit(自门禁(起始时刻, 入口函数(), 尾巴余量毫秒=200,
                   修法="本件重算全部声明与实现文件；把重活移出命令路（裁决 §三.3）"))
