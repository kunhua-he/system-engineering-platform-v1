pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::规范化日期)] = 命令项(
        能力号::规范化日期,
        "规范化日期\0".as_bytes(),
        "规范化日期\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        1,
        参数表_规范化日期.as_ptr(),
        表段::构造(可抛错误码_文本.as_ptr(), 3),
    );
    本表[命令表内位(能力号::格式化日期)] = 命令项(
        能力号::格式化日期,
        "格式化日期\0".as_bytes(),
        "格式化日期\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        2,
        参数表_格式化日期.as_ptr(),
        表段::构造(可抛错误码_文本.as_ptr(), 3),
    );
    本表[命令表内位(能力号::按格式解析)] = 命令项(
        能力号::按格式解析,
        "按格式解析\0".as_bytes(),
        "按格式解析\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        2,
        参数表_按格式解析.as_ptr(),
        表段::构造(可抛错误码_文本.as_ptr(), 3),
    );
    本表[命令表内位(能力号::取当前时间)] = 命令项(
        能力号::取当前时间,
        "取当前时间\0".as_bytes(),
        "取当前时间\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        1,
        参数表_取当前时间.as_ptr(),
        表段::构造(可抛错误码_文本.as_ptr(), 3),
    );
    本表[命令表内位(能力号::计算间隔)] = 命令项(
        能力号::计算间隔,
        "计算间隔\0".as_bytes(),
        "计算间隔\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        3,
        参数表_计算间隔.as_ptr(),
        表段::构造(可抛错误码_文本.as_ptr(), 3),
    );
    本表
}
const _: () = {
    assert!(命令表项数 == 函数表项数);
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::规范化日期)].参数个数 as usize == 参数表_规范化日期.len());
    assert!(项表[命令表内位(能力号::格式化日期)].参数个数 as usize == 参数表_格式化日期.len());
    assert!(项表[命令表内位(能力号::按格式解析)].参数个数 as usize == 参数表_按格式解析.len());
    assert!(项表[命令表内位(能力号::取当前时间)].参数个数 as usize == 参数表_取当前时间.len());
    assert!(项表[命令表内位(能力号::计算间隔)].参数个数 as usize == 参数表_计算间隔.len());
    assert!(参数个数已核条数 == 项表.len());
};
