use v1_contract::{参数信息, 命令信息, 数据槽, 表段};

use crate::编号与码面::能力号;

pub const 命令表项数: usize = 1;
pub const 函数表项数: usize = 1;
pub const 参数个数已核条数: usize = 1;
pub const 命令表首号: u32 = 能力号::检测危险命令;

pub const fn 命令表内位(编号值: u32) -> usize {
    assert!(
        编号值 >= 命令表首号 && (编号值 - 命令表首号) < 命令表项数 as u32,
        "编号不在本扩展的命令表内"
    );
    (编号值 - 命令表首号) as usize
}

pub const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    返回类型: v1_contract::类型标签,
    参数个数: u32,
    参数表: *const 参数信息,
    可抛错误码: 表段<u32>,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型,
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(
            可抛错误码.项表 as *const v1_contract::错误码,
            可抛错误码.表项数,
        ),
    }
}

const 通用说明: &[u8] = "纯检测，不执行命令；未知展开明确失败\0".as_bytes();
pub const 参数表_检测危险命令: [参数信息; 1] = [参数信息 {
    名称: "命令文本\0".as_bytes().as_ptr(),
    说明: "非空UTF-8命令文本，最多65536字节\0".as_bytes().as_ptr(),
    类型标签: v1_contract::类型标签::构造(4),
    状态位: 0,
    默认值: 数据槽::空槽(),
}];
pub const 可抛错误码_检测: [u32; 3] = [2711, 2712, 2713];
pub const fn 造命令表() -> [命令信息; 命令表项数] {
    [命令项(
        能力号::检测危险命令,
        "检测危险命令\0".as_bytes(),
        通用说明,
        v1_contract::类型标签::构造(101),
        1,
        参数表_检测危险命令.as_ptr(),
        表段::构造(可抛错误码_检测.as_ptr(), 3),
    )]
}
const _: () = {
    assert!(命令表项数 == 函数表项数);
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::检测危险命令)].参数个数 as usize == 参数表_检测危险命令.len());
    assert!(参数个数已核条数 == 项表.len());
};
