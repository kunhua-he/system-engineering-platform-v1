//! 数值边界反例 —— 1329 随机数完整 i64 区间 · 1325 取整方式校验的永久回归。
//!
//! 钉的是**已复现缺陷的根因**，不是把实现里的表达式抄一遍：
//!   · 1329 旧式 `下限 + (状态 % (上限 - 下限 + 1) as u64) as i64`：完整 i64 闭区间的宽度是
//!     2^64 —— 调试档 `上限 - 下限 + 1` 溢出 panic，发布档回绕成 0 ⇒ 取余 panic；
//!   · 1325 旧式：方式文本不在这三种之内时一律 `_ => round()`，非法方式被静默当四舍五入。
//!
//! 调用面只用本 crate 的执行函数（与网关同一条实现路径），入参/出参走契约 `数据槽` 与
//! `复合值载荷`；断言看**返回槽**（结果字段 / 错误码），不看内部变量。

use v1_contract::复合值载荷::{复合元素, 复合值, 解码复合值载荷};
use v1_contract::{数据槽, 类型标签};

use crate::执行函数面::{取整执行, 随机数执行};
use crate::错误码;

/// 整数入参槽（内联，标签 1）。
fn 整数槽(值: i64) -> 数据槽 {
    数据槽::内联槽(类型标签::构造(1), 值 as u64, 8)
}

/// 双精度入参槽（内联，标签 2）。
fn 双精度槽(值: f64) -> 数据槽 {
    数据槽::内联槽(类型标签::构造(2), 值.to_bits(), 8)
}

/// 引用形状的文本槽（标签 4）—— 字节表由调用方持有，活到调用结束。
fn 造文本槽(字节表: &[u8]) -> 数据槽 {
    数据槽::指针(类型标签::构造(4), 字节表.as_ptr() as u64, 字节表.len() as u64, false)
}

/// 调一个执行函数 ⇒ `Ok(字段表)` 或 `Err(错误码)`（错误槽标签 4294967295）。
fn 调执行(
    执行入口: unsafe extern "C-unwind" fn(*mut 数据槽, u32, *const 数据槽),
    参数表: &[数据槽],
) -> Result<Vec<复合元素>, u32> {
    let mut 返回槽 = 数据槽::空槽();
    unsafe { 执行入口(&mut 返回槽, 参数表.len() as u32, 参数表.as_ptr()) };
    if 返回槽.类型标签.取号值() == 4294967295 {
        return Err(返回槽.槽值 as u32);
    }
    assert_eq!(返回槽.类型标签.取号值(), 103, "返回槽不是结果结构（103）");
    let 字节 = unsafe {
        core::slice::from_raw_parts(返回槽.槽值 as *const u8, 返回槽.槽字节长度 as usize)
    };
    let 元素表 = 解码复合值载荷(字节, 103).expect("结果结构载荷解不出来");
    // 载荷所有权随槽交出（`写结果结构` 用 `Box::into_raw`）⇒ 这里回收，不让测试漏内存。
    unsafe {
        drop(Box::from_raw(core::ptr::slice_from_raw_parts_mut(
            返回槽.槽值 as *mut u8,
            返回槽.槽字节长度 as usize,
        )))
    };
    Ok(元素表)
}

/// 取结果结构里的一个字段（按字段名，不看位次）。
fn 取字段<'a>(元素表: &'a [复合元素], 字段名: &str) -> &'a 复合值 {
    元素表
        .iter()
        .find(|元素项| 元素项.名称 == 字段名)
        .map(|元素项| &元素项.值)
        .unwrap_or_else(|| panic!("结果结构里没有字段 {字段名}"))
}

/// 取一个整数结果字段。
fn 取整数(元素表: &[复合元素], 字段名: &str) -> i64 {
    match 取字段(元素表, 字段名) {
        复合值::整数值(值) => *值,
        _ => panic!("字段 {字段名} 不是整数"),
    }
}

#[test]
fn 随机数_普通范围() {
    for _ in 0..64 {
        let 参数表 = [整数槽(5), 整数槽(9)];
        let 字段表 = 调执行(随机数执行, &参数表).expect("普通范围是合法闭区间");
        let 命中 = 取整数(&字段表, "结果");
        assert!((5..=9).contains(&命中), "命中 {命中} 越出 [5, 9]");
    }
}

#[test]
fn 随机数_完整区间() {
    // 完整 i64 闭区间：宽度 2^64 —— 旧式在这里溢出（调试档 panic / 发布档回绕 0 后取余 panic）。
    let mut 命中表 = Vec::new();
    for _ in 0..16 {
        let 参数表 = [整数槽(i64::MIN), 整数槽(i64::MAX)];
        let 字段表 = 调执行(随机数执行, &参数表).expect("完整 i64 区间必须出结果，不能报错");
        命中表.push(取整数(&字段表, "结果"));
    }
    assert!(
        命中表.iter().any(|命中| *命中 != i64::MIN),
        "完整区间的结果全等于下限 ⇒ 宽度退化（旧式回绕的表现）"
    );
}

#[test]
fn 随机数_同值上下界() {
    for 边界 in [i64::MIN, -1, 0, 7, i64::MAX] {
        let 参数表 = [整数槽(边界), 整数槽(边界)];
        let 字段表 = 调执行(随机数执行, &参数表).expect("上下界相同是合法闭区间（单点）");
        assert_eq!(取整数(&字段表, "结果"), 边界, "单点区间只能命中 {边界}");
    }
}

#[test]
