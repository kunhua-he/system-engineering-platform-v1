#[test]
fn 取整_三种合法方式() {
    let 用例表 = [
        ("向下".as_bytes(), 2.5f64, 2i64),
        ("向上".as_bytes(), 2.5, 3),
        ("四舍五入".as_bytes(), 2.5, 3),
        ("向下".as_bytes(), -2.5, -3),
        ("向上".as_bytes(), -2.5, -2),
        ("四舍五入".as_bytes(), -2.5, -3),
    ];
    for (方式字节, 用例数值, 期望) in 用例表 {
        let 参数表 = [双精度槽(用例数值), 造文本槽(方式字节)];
        let 字段表 = 调执行(取整执行, &参数表).expect("三种声明过的方式都该成功");
        assert_eq!(
            取整数(&字段表, "结果"),
            期望,
            "{:?} 取整 {用例数值} 应为 {期望}",
            core::str::from_utf8(方式字节)
        );
    }
}

#[test]
fn 取整_未知方式被拒() {
    let 未知方式表 = [
        "四舍五入 ".as_bytes(),
        "向下取整".as_bytes(),
        b"ROUND".as_slice(),
        "".as_bytes(),
    ];
    for 方式字节 in 未知方式表 {
        let 参数表 = [双精度槽(2.5), 造文本槽(方式字节)];
        match 调执行(取整执行, &参数表) {
            Err(拒绝码) => assert_eq!(拒绝码, 错误码::参数不合法, "未知方式该落参数不合法"),
            Ok(_) => panic!("未知方式 {:?} 不该被静默当四舍五入", 方式字节),
        }
    }
}

#[test]
fn 取整_非文本槽被拒() {
    // 方式槽传整数（标签 1）：旧写法把 `槽值` 当指针读，等于读野地址。
    let 参数表 = [双精度槽(2.5), 整数槽(1)];
    match 调执行(取整执行, &参数表) {
        Err(拒绝码) => assert_eq!(拒绝码, 错误码::参数不合法, "非文本槽该落参数不合法"),
        Ok(_) => panic!("非文本槽不该成功"),
    }
}

#[test]
fn 取整_内联文本槽可用() {
    // 内联槽（短文本直接躺在 `槽值` 里）：必须与引用槽同样可用，
    // 否则「拒非文本槽」的修法会把合法的短文本调用一起打掉。
    let 字节 = "向上".as_bytes();
    let mut 内联值 = [0u8; 8];
    内联值[..字节.len()].copy_from_slice(字节);
    let 方式槽 = 数据槽::内联槽(
        类型标签::构造(4),
        u64::from_le_bytes(内联值),
        字节.len() as u64,
    );
    let 参数表 = [双精度槽(2.5), 方式槽];
    let 字段表 = 调执行(取整执行, &参数表).expect("内联文本槽是合法形状");
    assert_eq!(取整数(&字段表, "结果"), 3, "内联「向上」取整 2.5 应为 3");
}
