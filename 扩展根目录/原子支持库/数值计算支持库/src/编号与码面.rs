//! 编号与码面 —— 能力号 · 错误码 · 错误码信息表。
//!
//! 能力号取自 `能力声明/<编号>.json`；错误码取自 `错误码表/<码>.json`。
//! **号与登记表同处一件**：实现侧扫描器（`测试验证/契约一致性/扫实现.py` 的 ③f）在**同一份文件**
//! 里解析 `码项(错误码::X, …)` 的码与 `错误码 / 1000` 的段位 —— 分处两件会让它两者都解不出。

use v1_contract::错误码信息;

/// 能力号 —— 本扩展申报号段 `[1324, 1335]` 里的九个号。
pub mod 能力号 {
    pub const 四舍五入: u32 = 1324;
    pub const 取整: u32 = 1325;
    pub const 绝对值: u32 = 1326;
    pub const 最大值: u32 = 1327;
    pub const 最小值: u32 = 1328;
    pub const 随机数: u32 = 1329;
    pub const 求和: u32 = 1330;
    pub const 平均值: u32 = 1331;
    pub const 分位数: u32 = 1332;
}

/// 错误码 —— 段位 1（支持库域 · 数值计算）的两条。
pub mod 错误码 {
    /// 入参不满足能力声明的参数契约。
    pub const 参数不合法: u32 = 1001;
    /// 数值计算未能得出结果（域错误或溢出）。
    pub const 计算失败: u32 = 1100;
}

/// 造一条错误码登记项。`段位` 一律 `错误码 / 1000`（冗余登记项，故意由码导出）。
pub const fn 码项(
    错误码: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    可重试: u8,
    可自愈: u8,
    需人工: u8,
) -> 错误码信息 {
    错误码信息 {
        码值: 错误码,
        段位: 错误码 / 1000,
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        可重试,
        可自愈,
        需人工,
        保留: 0,
    }
}

/// 错误码信息表（源：错误码表/*.json，共 2 条，按码升序）。
///
/// 两条都是「入参/计算」类 ⇒ 可重试 否 · 可自愈 否 · 需人工 否（调用方程序可判可改）。
pub const 错误码信息表: [错误码信息; 2] = [
    码项(
        错误码::参数不合法,
        "参数不合法\0".as_bytes(),
        "入参不满足能力声明的参数契约（个数 · 类型标签 · 取值域）。\0".as_bytes(),
        0,
        0,
        0,
    ),
    码项(
        错误码::计算失败,
        "计算失败\0".as_bytes(),
        "数值计算未能得出结果（定义域外或溢出）。\0".as_bytes(),
        0,
        0,
        0,
    ),
];

/// `平台信息.错误码表` 直接可用：项数 + 项表。
pub const fn 错误码信息表段() -> v1_contract::表段<错误码信息> {
    v1_contract::表段::构造(错误码信息表.as_ptr(), 2)
}
