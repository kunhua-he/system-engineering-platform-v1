// ③g 编译期断言：两张表的**真实长度**与各自的项数声明同值，且两表等长。
const _: () = assert!(造命令表().len() == 命令表项数, "③g：命令表项数 与 命令表 实际长度不符");
const _: () = assert!(crate::执行函数面::执行函数表.len() == 函数表项数, "③g：函数表项数 与 执行函数表 实际长度不符");
const _: () = assert!(命令表项数 == 函数表项数, "③g：命令表与执行函数表必须等长");

// ③h 编译期断言：逐条核「该条的 参数个数 == 它引用的参数表项数」。
// 为什么逐条列名（而不是循环遍历命令表）：`命令信息.参数表` 是**裸指针**，编译期取不到被指
// 数组的长度，也没有「指针 → 表」的编译期映射（const 求值不许比较指针）。
const _: () = {
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::四舍五入)].参数个数 as usize == 参数表_数值小数位.len(), "③h：1324 的 参数个数 与 参数表_数值小数位 项数不符");
    assert!(项表[命令表内位(能力号::取整)].参数个数 as usize == 参数表_数值方式.len(), "③h：1325 的 参数个数 与 参数表_数值方式 项数不符");
    assert!(项表[命令表内位(能力号::绝对值)].参数个数 as usize == 参数表_数值.len(), "③h：1326 的 参数个数 与 参数表_数值 项数不符");
    assert!(项表[命令表内位(能力号::最大值)].参数个数 as usize == 参数表_数值列表.len(), "③h：1327 的 参数个数 与 参数表_数值列表 项数不符");
    assert!(项表[命令表内位(能力号::最小值)].参数个数 as usize == 参数表_数值列表.len(), "③h：1328 的 参数个数 与 参数表_数值列表 项数不符");
    assert!(项表[命令表内位(能力号::随机数)].参数个数 as usize == 参数表_上下限.len(), "③h：1329 的 参数个数 与 参数表_上下限 项数不符");
    assert!(项表[命令表内位(能力号::求和)].参数个数 as usize == 参数表_数值列表.len(), "③h：1330 的 参数个数 与 参数表_数值列表 项数不符");
    assert!(项表[命令表内位(能力号::平均值)].参数个数 as usize == 参数表_数值列表.len(), "③h：1331 的 参数个数 与 参数表_数值列表 项数不符");
    assert!(项表[命令表内位(能力号::分位数)].参数个数 as usize == 参数表_分位数.len(), "③h：1332 的 参数个数 与 参数表_分位数 项数不符");
    // 断言条数与表长必须相等：加一条命令就必须加一条断言，漏了这里当场编译不过。
    assert!(参数个数已核条数 == 项表.len(), "③h：已核条数 与 命令表项数 不符 —— 加了命令没加断言");
};
