//! 静态声明 —— 本扩展的 `平台信息` 实例与唯一导出符号 `GetPlatformInfo`。
//!
//! 声明数据（标识串 · 名称 · 说明 · 版本 · 能力号段 · 错误段位表）逐字取自本扩展目录里的
//! `包声明.json`（本扩展**不使用** `生成声明.py`：闸 1 检查 10 对 `扩展根目录/` 不判生成物
//! 新鲜度，且该生成器对 `类型声明` 的 `元素表` 尚未放开）；错码内容表取自 `编号与码面.rs`。
//!
//! 复合类型（100 列表 · 103 结果结构）**只引用标签**，本扩展不再重声明（核心支持库为唯一归属）——
//! 故 `类型表` 是空段，不是漏写。

use v1_contract::{命令信息, 平台信息, 表段};

use crate::命令声明面::{造命令表, 命令表项数};
use crate::执行函数面::执行函数表;

// ── 声明数据（源：本扩展目录 包声明.json）──
const 底座声明格式号: v1_contract::格式号 = v1_contract::格式号::构造(1398362929);
const 底座目标字宽: u16 = 64;
const 底座标识串: &[u8] = b"87a1c519825918041cbe379271dbd2af\0";
const 底座名称: &[u8] = "数值计算支持库\0".as_bytes();
const 底座说明: &[u8] =
    "常用数值计算：四舍五入/取整/绝对值/最大/最小/随机/求和/平均（参考易语言数值计算支持库）\0"
        .as_bytes();
const 底座实现版本: v1_contract::版本三元组 = v1_contract::版本三元组::构造(0, 1, 0);
const 底座要求宿主版本: v1_contract::版本要求 = v1_contract::版本要求::构造(1, 0);
const 底座要求内核版本: v1_contract::版本要求 = v1_contract::版本要求::构造(1, 0);
const 底座能力号段: [v1_contract::号段; 1] = [v1_contract::号段::构造(1324, 1335)];
const 底座错误段位表: [u32; 1] = [1];

/// `平台信息.能力号段` 直接可用：项数 + 项表。
const fn 底座能力号段表段() -> 表段<v1_contract::号段> {
    表段::构造(底座能力号段.as_ptr(), 1)
}
/// `平台信息.错误段位表` 直接可用：项数 + 项表。
const fn 底座错误段位表段() -> 表段<u32> {
    表段::构造(底座错误段位表.as_ptr(), 1)
}

/// 带 `Sync` 的命令表外壳（`命令信息` 里有裸指针 ⇒ 不是 `Sync`，而 `static` 要求 `Sync`）。
#[repr(transparent)]
struct 静态命令表(pub(crate) [命令信息; 命令表项数]);
// SAFETY: 表一旦构造即终生不变；不提供 &mut 通道，对外只交出 *const 指针。
unsafe impl Sync for 静态命令表 {}
unsafe impl Send for 静态命令表 {}

static 命令表存储: 静态命令表 = 静态命令表(造命令表());

/// 带 `Sync` 的声明外壳（同 `静态命令表` 的理由）。
#[repr(transparent)]
struct 静态声明(平台信息);
// SAFETY: 静态声明一旦构造即终生不变；只交出 *const 指针，多线程共享只读安全。
unsafe impl Sync for 静态声明 {}
unsafe impl Send for 静态声明 {}

/// 本扩展自身的静态 `平台信息`。**唯一实例**：导出符号返回它的地址。
static 扩展存储: 静态声明 = 静态声明(平台信息 {
    声明格式号: 底座声明格式号,
    目标字宽: 底座目标字宽,
    保留: 0,
    标识串: 底座标识串.as_ptr(),
    实现版本: 底座实现版本,
    要求宿主版本: 底座要求宿主版本,
    要求内核版本: 底座要求内核版本,
    名称: 底座名称.as_ptr(),
    说明: 底座说明.as_ptr(),
    状态位: 0,
    // 复合类型（100 / 103）由核心支持库声明，本扩展只引用标签 ⇒ 空类型表不是漏写。
    类型表: 表段::空实例(),
    命令表: 表段::构造(命令表存储.0.as_ptr(), 命令表项数 as u32),
    函数表: 执行函数表.as_ptr(),
    常量表: 表段::空实例(),
    通知函数: None,
    依赖清单: 表段::空实例(),
    能力号段: 底座能力号段表段(),
    通知号段: 表段::空实例(),
    错误段位表: 底座错误段位表段(),
    错误码表: crate::编号与码面::错误码信息表段(),
    命令类别表: 表段::空实例(),
    要求权限: 表段::空实例(),
});

/// 接缝地址 —— 本 crate 唯一导出符号调它取本扩展的静态声明指针。
///
/// 返回的指针指向静态数据，终生有效；调用方不得释放、不得修改。
pub(crate) fn 取接缝指针() -> *const 平台信息 {
    &扩展存储.0 as *const 平台信息
}

/// 唯一导出符号。符号名由本扩展声明的 `导出目标` 给出（`包声明.json` = `GetPlatformInfo`）。
#[unsafe(export_name = "GetPlatformInfo")]
pub extern "C" fn 取平台信息() -> *const 平台信息 {
    取接缝指针()
}

/// 未导出但同源的只读取用口（验证面与测试用，不新增导出符号）。
#[doc(hidden)]
pub fn 扩展声明() -> &'static 平台信息 {
    &扩展存储.0
}
