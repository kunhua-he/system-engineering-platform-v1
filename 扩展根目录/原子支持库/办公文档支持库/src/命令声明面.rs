use v1_contract::{参数信息, 命令信息, 数据槽, 表段};

use crate::编号与码面::能力号;

pub const 命令表项数: usize = 2;
pub const 函数表项数: usize = 2;
pub const 参数个数已核条数: usize = 2;
pub const 命令表首号: u32 = 能力号::求值公式;

pub const fn 命令表内位(编号: u32) -> usize {
    assert!(
        编号 >= 命令表首号 && (编号 - 命令表首号) < 命令表项数 as u32,
        "编号不在本扩展的命令表内"
    );
    (编号 - 命令表首号) as usize
}

pub const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    返回类型: v1_contract::类型标签,
    参数个数: u32,
    参数表: *const 参数信息,
    可抛错误码: 表段<u32>,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型,
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(
            可抛错误码.项表 as *const v1_contract::错误码,
            可抛错误码.表项数,
        ),
    }
}

pub const 参数表_求值公式: [参数信息; 2] = [
    参数信息 {
        名称: "公式文本\0".as_bytes().as_ptr(),
        说明: "只含四则运算、括号、数字与变量名的算式\0".as_bytes().as_ptr(),
        类型标签: v1_contract::类型标签::构造(4),
        状态位: 0,
        默认值: 数据槽::空槽(),
    },
    参数信息 {
        名称: "变量文本\0".as_bytes().as_ptr(),
        说明: "JSON 对象，值只接受数值，如 {\"单价\":12.5}\0".as_bytes().as_ptr(),
        类型标签: v1_contract::类型标签::构造(4),
        状态位: 0,
        默认值: 数据槽::空槽(),
    },
];
pub const 参数表_解析标记块: [参数信息; 1] = [参数信息 {
    名称: "Markdown源文本\0".as_bytes().as_ptr(),
    说明: "待切分的 Markdown 正文\0".as_bytes().as_ptr(),
    类型标签: v1_contract::类型标签::构造(4),
    状态位: 0,
    默认值: 数据槽::空槽(),
}];
pub const 可抛错误码_办公文档: [u32; 3] = [6101, 6102, 6103];
pub const 空位种子: 命令信息 = 命令信息 {
    名称: "空位种子\0".as_bytes().as_ptr(),
    说明: "命令表的空位种子：表内每一位都该被覆写。\0"
        .as_bytes()
        .as_ptr(),
    类别号: 0,
    状态位: 0,
    返回类型: v1_contract::类型标签::构造(0),
    用户级别: 0,
    参数个数: 0,
    参数表: core::ptr::null(),
    编号: v1_contract::能力号::构造(0),
    可抛错误码: 表段::空实例(),
};

pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::求值公式)] = 命令项(
        能力号::求值公式,
        "求值公式\0".as_bytes(),
        "按四则运算与变量表求值，返回数值文本\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        2,
        参数表_求值公式.as_ptr(),
        表段::构造(可抛错误码_办公文档.as_ptr(), 3),
    );
    本表[命令表内位(能力号::解析标记块)] = 命令项(
        能力号::解析标记块,
        "解析标记块\0".as_bytes(),
        "把 Markdown 切成标题/段落/列表项/代码块/引用/分隔线，返回 JSON 文本\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        1,
        参数表_解析标记块.as_ptr(),
        表段::构造(可抛错误码_办公文档.as_ptr(), 3),
    );
    本表
}
const _: () = {
    assert!(命令表项数 == 函数表项数);
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::求值公式)].参数个数 as usize == 参数表_求值公式.len());
    assert!(项表[命令表内位(能力号::解析标记块)].参数个数 as usize == 参数表_解析标记块.len());
    assert!(参数个数已核条数 == 项表.len());
};
