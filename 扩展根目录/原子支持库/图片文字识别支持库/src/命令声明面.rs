    本表[命令表内位(能力号::识别图片文字)] = 命令项(能力号::识别图片文字,"识别图片文字\0".as_bytes(),"原生Vision图片文字识别，返回含文字及坐标的JSON文本。\0".as_bytes(),v1_contract::类型标签::构造(4),1,参数表_图片路径.as_ptr(),表段::构造(可抛错误码_图片.as_ptr(),7));
