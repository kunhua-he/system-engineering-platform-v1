#[test]
fn 测试令牌补充拒绝与非法输入() {
    assert_eq!(super::令牌判定面::计算令牌桶(10,2.0,0.0,10.0,11.0,1).unwrap(),(true,1.0,11.0));
    assert_eq!(super::令牌判定面::计算令牌桶(10,2.0,0.0,10.0,10.0,1).unwrap(),(false,0.0,10.0));
    assert_eq!(super::令牌判定面::计算令牌桶(10,2.0,9.0,10.0,100.0,1).unwrap(),(true,9.0,100.0));
    assert!(super::令牌判定面::计算令牌桶(0,2.0,0.0,10.0,11.0,1).is_err());
    assert!(super::令牌判定面::计算令牌桶(10,f64::NAN,0.0,10.0,11.0,1).is_err());
    assert!(super::令牌判定面::计算令牌桶(10,2.0,0.0,10.0,9.0,1).is_err());
    assert!(super::令牌判定面::计算令牌桶(10,2.0,11.0,10.0,11.0,1).is_err());
}
