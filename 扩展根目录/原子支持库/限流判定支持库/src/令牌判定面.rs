use v1_contract::复合值载荷::{复合元素,复合值,编码复合值载荷};
use v1_contract::{数据槽,类型标签};
pub(crate) fn 计算令牌桶(桶容量:i64,每秒补充:f64,当前令牌数:f64,上次补充时间:f64,现在:f64,取用数量:i64)->Result<(bool,f64,f64),u32>{
    if 桶容量<=0 || 取用数量<=0 || ![每秒补充,当前令牌数,上次补充时间,现在].iter().all(|参数数值| 参数数值.is_finite())
        || 每秒补充<0.0 || 当前令牌数<0.0 || 当前令牌数>桶容量 as f64 || 上次补充时间<0.0 || 现在<上次补充时间 {
        return Err(crate::声明接口面::参数不合法码);
    }
    let 补充后令牌=(当前令牌数+(现在-上次补充时间)*每秒补充).min(桶容量 as f64);
    let 放行=补充后令牌>=取用数量 as f64;
    Ok((放行,if 放行{补充后令牌-取用数量 as f64}else{补充后令牌},现在))
}
unsafe fn 执行令牌判定(参数个数:u32,参数表:*const 数据槽)->Result<数据槽,u32>{
    let 参数错误=crate::声明接口面::参数不合法码;
    if 参数个数!=6 || 参数表.is_null(){return Err(参数错误);}
    let 参数槽表=unsafe{std::slice::from_raw_parts(参数表,6)};
    for (参数位置,参数槽) in 参数槽表.iter().enumerate(){
        let 期望类型=if 参数位置==0||参数位置==5{1}else{2};
        if 参数槽.类型标签.取号值()!=期望类型 || 参数槽.是否引用(){return Err(参数错误);}
    }
    let (放行,当前令牌数,上次补充时间)=计算令牌桶(参数槽表[0].槽值 as i64,f64::from_bits(参数槽表[1].槽值),f64::from_bits(参数槽表[2].槽值),f64::from_bits(参数槽表[3].槽值),f64::from_bits(参数槽表[4].槽值),参数槽表[5].槽值 as i64)?;
    let 元素表=vec![复合元素{名称:"放行".into(),值:复合值::逻辑型(放行)},复合元素{名称:"当前令牌数".into(),值:复合值::双精度(当前令牌数)},复合元素{名称:"上次补充时间".into(),值:复合值::双精度(上次补充时间)}];
    let 返回字节=编码复合值载荷(103,&元素表).map_err(|_|参数错误)?;
    let 返回长度=返回字节.len() as u64;
    let 返回指针=Box::into_raw(返回字节.into_boxed_slice()) as *const u8;
    Ok(数据槽::指针(类型标签::构造(103),返回指针 as u64,返回长度,true))
}
pub(crate) unsafe extern "C-unwind" fn 令牌判定入口(返回槽:*mut 数据槽,参数个数:u32,参数表:*const 数据槽){
    if 返回槽.is_null(){return;}
    unsafe{*返回槽=执行令牌判定(参数个数,参数表).unwrap_or_else(|失败码|数据槽::内联槽(类型标签::构造(u32::MAX),失败码 as u64,4));}
}
