pub const 空位种子: 命令信息 = 命令信息 {
    名称: "空位种子\0".as_bytes().as_ptr(),
    说明: "命令表的空位种子：表内每一位都该被覆写。\0".as_bytes().as_ptr(),
    类别号: 0,
    状态位: 0,
    返回类型: v1_contract::类型标签::构造(0),
    用户级别: 0,
    参数个数: 0,
    参数表: core::ptr::null(),
    编号: v1_contract::能力号::构造(0),
    可抛错误码: 表段::空实例(),
};
pub const 可抛错误码_归属: [u32; 4] = [6411, 6412, 6413, 6414];

pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::判定进程归属)] = 命令项(
        能力号::判定进程归属,
        "判定进程归属\0".as_bytes(),
        "先证明归属再谈可清理：按归属登记的端口／路径指纹判命中，受保护优先、命令行缺失一律未核实（fail closed）。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        3,
        参数表_判定进程归属.as_ptr(),
        表段::构造(可抛错误码_归属.as_ptr(), 4),
    );
    本表
}

const 项表: [命令信息; 命令表项数] = 造命令表();
const _: () = {
    assert!(项表[命令表内位(能力号::判定进程归属)].参数个数 as usize == 参数表_判定进程归属.len());
    assert!(参数个数已核条数 == 项表.len());
};
