//! 编号与码面 —— 能力号 · 错误码 · 错误码信息表。
//!
//! 能力号取自 `能力声明/<编号>.json`；错误码取自 `错误码表/<码>.json`。
//! **号与登记表同处一件**：实现侧扫描器（`测试验证/契约一致性/扫实现.py` 的 ③f）在**同一份文件**
//! 里解析 `码项(错误码::X, …)` 的码与 `错误码 / 1000` 的段位 —— 分处两件会让它两者都解不出。

use v1_contract::错误码信息;

/// 能力号 —— 本扩展申报号段 `[3101, 3199]` 里的第一个号。
pub mod 能力号 {
    /// 3101 取文件摘要。
    pub const 取文件摘要: u32 = 3101;
}

/// 错误码 —— 段位 3（三方封装 · 文件与目录）的三条。
pub mod 错误码 {
    /// 路径写错 / 件已删（调用方能改）。
    pub const 文件不存在: u32 = 3001;
    /// 给的是目录 / 设备 / 套接字。
    pub const 不是普通文件: u32 = 3002;
    /// 权限不足（要人给权限）。
    pub const 读取被拒: u32 = 3003;
    /// 给的不是绝对路径（本能力只收绝对路径，不按服务进程 cwd 解析）。
    pub const 路径不是绝对路径: u32 = 3004;
}

/// 造一条错误码登记项。`段位` 一律 `错误码 / 1000`（冗余登记项，故意由码导出）。
pub const fn 码项(
    错误码: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    可重试: u8,
    可自愈: u8,
    需人工: u8,
) -> 错误码信息 {
    错误码信息 {
        码值: 错误码,
        段位: 错误码 / 1000,
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        可重试,
        可自愈,
        需人工,
        保留: 0,
    }
}

