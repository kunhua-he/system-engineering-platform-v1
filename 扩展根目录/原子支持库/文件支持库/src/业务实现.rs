//! 文件支持库业务总入口：**只做模块声明与按能力号分派**，实现按关注点住同名字文件夹
//! `src/业务实现/`（`开发规范.md` 第六节「改一处不必读全件」）。
//!
//! | 件 | 职责 | 能力号 |
//! | --- | --- | --- |
//! | `基础件.rs` | 路径校验收口 · 读错映射 · 有界读 | 各组共用 |
//! | `读取与列目录.rs` | 有界读取 · 单层列目录 | 3102 · 3103 · 3107 |
//! | `写入与删除.rs` | 新建 · 复制 · 创建目录 · 删除 | 3104 · 3105 · 3106 · 3108 · 3109 · 3110 |
//! | `祖先目录.rs` | 向上找同名标记目录 | 3116 |
//! | `路径状态与清理.rs` | 路径元信息 · 暂存残留清理 | 3117 · 3118 |
//! | `类属性扫描.rs` | 扫 py 类属性字符串常量 | 3119 |
//! | `环境文件.rs` | `KEY=VALUE` 环境文件解析 | 3114 |
//!
//! 3120–3123 受控 Git 事务在 `受控修复面`，本文件只做转接。

use crate::编号与码面::{能力号, 错误码};

#[path = "业务实现/基础件.rs"]
mod 基础件;
#[path = "业务实现/写入与删除.rs"]
mod 写入与删除;
#[path = "业务实现/祖先目录.rs"]
mod 祖先目录;
#[path = "业务实现/环境文件.rs"]
mod 环境文件;
#[path = "业务实现/读取与列目录.rs"]
mod 读取与列目录;
#[path = "业务实现/路径状态与清理.rs"]
mod 路径状态与清理;
#[path = "业务实现/类属性扫描.rs"]
mod 类属性扫描;

use 基础件::{查路径, 读有界文件};

pub fn 执行业务操作(编号: u32, 参数表: &[&[u8]]) -> Result<(u32, Vec<u8>), u32> {
    if (3120..=3123).contains(&编号) {
        let 文本表 = 参数表
            .iter()
            .map(|项| std::str::from_utf8(项).map_err(|_| 错误码::参数不合法))
            .collect::<Result<Vec<_>, _>>()?;
        let 返回字节 = crate::受控修复面::执行业务口(编号, &文本表)?;
        return Ok((4, 返回字节));
    }
    let 文件路径 = 查路径(参数表[0])?;
    if 编号 == 能力号::查找祖先目录 {
        return 祖先目录::查找祖先行(文件路径, 参数表[1]);
    }
    if 编号 == 能力号::取路径元信息 {
        return 路径状态与清理::取路径元信息行(文件路径);
    }
    if 编号 == 能力号::清理暂存残留 {
        return 路径状态与清理::清理暂存行(文件路径, 参数表[1], 参数表[2]);
    }
    if 编号 == 能力号::扫描类属性 {
        return 类属性扫描::扫描类属性行(文件路径, 参数表[1], 参数表[2]);
    }
    if 编号 == 能力号::读取环境文件 {
        let 文件字节 = 读有界文件(文件路径)?;
        let 全文 = std::str::from_utf8(&文件字节).map_err(|_| 错误码::内容不合法)?;
        return 环境文件::解析环境文本(全文);
    }
    match 编号 {
        能力号::读取文本 | 能力号::读取字节 => {
            return 读取与列目录::读取能力行(编号, 文件路径);
        }
        能力号::新建文本 | 能力号::新建字节 | 能力号::复制文件 => {
            return 写入与删除::新建或复制作业(编号, 文件路径, 参数表[1]);
        }
        能力号::创建目录 | 能力号::删除文件 | 能力号::删除空目录 => {
            写入与删除::目录与删除作业(编号, 文件路径)?;
        }
        能力号::列出目录 => {
            return 读取与列目录::列出目录行(文件路径);
        }
        _ => return Err(错误码::参数不合法),
    }
    Ok((4, 参数表[0].to_vec()))
}
