//! 执行函数面 —— 3101 取文件摘要的执行入口与它共用的槽读写口。
//!
//! 入参从 `数据槽` 取（类型标签 4 文本，指针槽，**路径字符串本身**，不是文件内容），
//! 结果写回返回槽，失败写结构化错误码（不靠返回值）。
//! 出参 `103 结果结构`：**指针槽**，载荷 = 元素表（字段名 + 值）；
//! 形状与编解码只在契约层一份（`v1_contract::复合值载荷`），本件只调用，不另写第二套。

use v1_contract::复合值载荷::{复合元素, 复合值, 编码复合值载荷};
use v1_contract::{执行函数, 数据槽, 类型标签};

use crate::命令声明面::{命令表内位, 函数表项数};
use crate::摘要面::{算摘要, 摘要错误, 摘要结果};
use crate::能力号;
use crate::错误码;

/// 写一个结构化错误码到返回槽（「错误」标签 4294967295，与底座统一注册表同口径）。
unsafe fn 写错误槽(返回槽: *mut 数据槽, 错误码值: u32) {
    if 返回槽.is_null() {
        return;
    }
    unsafe { *返回槽 = 数据槽::内联槽(类型标签::构造(4294967295), 错误码值 as u64, 4) };
}

/// 从入参槽读路径文本（指针槽 · 类型标签 4）。
///
/// `None` = 槽里没有可读的路径（空槽 / 无指针 / 不是 UTF-8）⇒ 由调用方落
/// `文件不存在`：调用方确实没给出一个能打开的件，而**不是**「读取被拒」（那是权限的事）。
unsafe fn 读路径文本(参数槽: *const 数据槽) -> Option<String> {
    if unsafe { (*参数槽).类型标签.取号值() } != 4 {
        return None;
    }
    if unsafe { (*参数槽).是否空() } || !unsafe { (*参数槽).是否引用() } || unsafe { (*参数槽).槽值 } == 0 {
        return None;
    }
    // SAFETY: 契约保证「引用」槽的 值..值+长度 可读。
    let 路径字节 = unsafe {
        core::slice::from_raw_parts((*参数槽).槽值 as *const u8, (*参数槽).槽字节长度 as usize)
    };
    core::str::from_utf8(路径字节).ok().map(str::to_owned)
}

/// 写结果结构（类型标签 103）：三字段表 → 自描述 TLV 载荷 → **指针槽**（所有权交出）。
///
/// 字段名取自 `类型声明/103.json` 的元素表（`字节数` · `行数` · `摘要文本`）。
/// 载荷编不出来（字段名空 / 重名）只可能是本扩展把表写坏了 —— 那时落 `读取被拒`：
/// 三条码里只有它 `需人工 = 是`，既**不假成功**，也不谎报成「调用方能改」的 3001 / 3002。
unsafe fn 写结果结构(返回槽: *mut 数据槽, 摘要三值: 摘要结果) {
    if 返回槽.is_null() {
        return;
    }
    let 元素表: Vec<复合元素> = vec![
        复合元素 { 名称: String::from("字节数"), 值: 复合值::整数值(摘要三值.字节数 as i64) },
        复合元素 { 名称: String::from("行数"), 值: 复合值::整数值(摘要三值.行数 as i64) },
        复合元素 { 名称: String::from("摘要文本"), 值: 复合值::文本载荷(摘要三值.摘要文本) },
    ];
    match 编码复合值载荷(103, &元素表) {
        Ok(载荷字节) => {
            let 槽字节长度 = 载荷字节.len() as u64;
            let 数据指针 = Box::into_raw(载荷字节.into_boxed_slice()) as *const u8;
            // SAFETY: 由调用方保证 返回槽 可写；载荷字节的所有权随槽交出。
            unsafe { *返回槽 = 数据槽::指针(类型标签::构造(103), 数据指针 as u64, 槽字节长度, true) };
        }
        Err(_) => unsafe { 写错误槽(返回槽, 错误码::读取被拒) },
    }
}

/// 3101 取文件摘要：路径（文本）→ 字节数 · 行数 · 摘要文本。
pub unsafe extern "C-unwind" fn 取文件摘要执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    if 参数个数 != 1 || 参数表.is_null() {
        unsafe { 写错误槽(返回槽, 错误码::文件不存在) };
        return;
    }
    let Some(路径) = (unsafe { 读路径文本(参数表) }) else {
        unsafe { 写错误槽(返回槽, 错误码::文件不存在) };
        return;
    };
    // 合同（能力声明 3101 的「路径」说明）要求绝对路径：相对路径按服务进程 cwd 解析
    // 等于把 cwd 变成第二语义源 ⇒ 明确拒，不谎报成「文件不存在」（3001）。
    if !std::path::Path::new(&路径).is_absolute() {
        unsafe { 写错误槽(返回槽, 错误码::路径不是绝对路径) };
        return;
    }
    match 算摘要(&路径) {
        Ok(摘要三值) => unsafe { 写结果结构(返回槽, 摘要三值) },
        Err(摘要错误::文件不存在) => unsafe { 写错误槽(返回槽, 错误码::文件不存在) },
        Err(摘要错误::不是普通文件) => unsafe { 写错误槽(返回槽, 错误码::不是普通文件) },
        Err(摘要错误::读取被拒) => unsafe { 写错误槽(返回槽, 错误码::读取被拒) },
    }
}

/// 保留项执行函数：`造函数表` 的初值，也是「命令表加了位而函数表漏覆写」时的诚实状态 ——
/// 它写的是结构化错误码，**不是假成功**。当前这一位已覆写，正常路径不会走到它。
pub(crate) unsafe extern "C-unwind" fn 保留项执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    let _ = (参数个数, 参数表);
    unsafe { 写错误槽(返回槽, 错误码::读取被拒) };
}

/// 造函数表：与命令表**等长**、一一对应（同一下标 = 同一条命令）。
pub const fn 造函数表() -> [执行函数; 函数表项数] {
    let mut 本表 = [保留项执行 as 执行函数; 函数表项数];
    本表[命令表内位(能力号::取文件摘要)] = 取文件摘要执行;
    本表[命令表内位(能力号::读取受控头部)] = crate::受控读取面::受控头部入口;
    crate::文件操作桥::扩展函数表(本表)
}

/// 函数表：与命令表等长，一一对应。**不许留空指针。**
pub(crate) const 执行函数表: [执行函数; 函数表项数] = 造函数表();
