//! 编译期断言 —— ③g 两表项数与真实长度 · ③h 逐条「参数个数 == 参数表项数」。
//!
//! 断言与命令表分住两件：加一条命令就必须在两处各加一条，漏了当场编译不过。

use crate::能力号;

use super::表骨架::{命令表内位, 命令表项数, 参数个数已核条数, 函数表项数};
use super::造命令表;
use super::基础参数表::{
    参数表_路径,
    参数表_读取环境文件,
    参数表_读取文本,
    参数表_读取字节,
    参数表_新建文本,
    参数表_新建字节,
    参数表_创建目录,
    参数表_列出目录,
    参数表_复制文件,
    参数表_删除文件,
    参数表_删除空目录,
};
use super::受控读写参数表::{
    参数表_原子写入字节,
    参数表_受控头部,
    参数表_受控整件,
    参数表_原子写入,
};
use super::路径与扫描参数表::{
    参数表_扫描类属性,
    参数表_取路径元信息,
    参数表_清理暂存残留,
    参数表_查找祖先目录,
};
use super::工作区参数表::{
    参数表_受控工作区,
    参数表_唯一文本替换,
    参数表_受控验证,
    参数表_受控回滚,
    参数表_受控创建提交,
};

// ③g 编译期断言：两张表的**真实长度**与各自的项数声明同值，且两表等长。
const _: () = assert!(
    造命令表().len() == 命令表项数,
    "③g：命令表项数 与 命令表 实际长度不符"
);
const _: () = assert!(
    crate::执行函数面::执行函数表.len() == 函数表项数,
    "③g：函数表项数 与 执行函数表 实际长度不符"
);
const _: () = assert!(命令表项数 == 函数表项数, "③g：命令表与执行函数表必须等长");

// ③h 编译期断言：逐条核「该条的 参数个数 == 它引用的参数表项数」。
// 为什么逐条列名（而不是循环遍历命令表）：`命令信息.参数表` 是**裸指针**，编译期取不到被指
// 数组的长度，也没有「指针 → 表」的编译期映射（const 求值不许比较指针）。
const _: () = {
    let 项表 = 造命令表();
    assert!(
        项表[命令表内位(能力号::取文件摘要)].参数个数 as usize == 参数表_路径.len(),
        "③h：3101 的 参数个数 与 参数表_路径 项数不符"
    );
    // 断言条数与表长必须相等：加一条命令就必须加一条断言，漏了这里当场编译不过。
    assert!(项表[命令表内位(能力号::读取文本)].参数个数 as usize == 参数表_读取文本.len());
    assert!(项表[命令表内位(能力号::读取字节)].参数个数 as usize == 参数表_读取字节.len());
    assert!(项表[命令表内位(能力号::新建文本)].参数个数 as usize == 参数表_新建文本.len());
    assert!(项表[命令表内位(能力号::新建字节)].参数个数 as usize == 参数表_新建字节.len());
    assert!(项表[命令表内位(能力号::创建目录)].参数个数 as usize == 参数表_创建目录.len());
    assert!(项表[命令表内位(能力号::列出目录)].参数个数 as usize == 参数表_列出目录.len());
    assert!(项表[命令表内位(能力号::复制文件)].参数个数 as usize == 参数表_复制文件.len());
    assert!(项表[命令表内位(能力号::删除文件)].参数个数 as usize == 参数表_删除文件.len());
    assert!(项表[命令表内位(能力号::删除空目录)].参数个数 as usize == 参数表_删除空目录.len());
    assert!(项表[命令表内位(能力号::读取受控头部)].参数个数 as usize == 参数表_受控头部.len());
    assert!(项表[命令表内位(能力号::读取受控全件)].参数个数 as usize == 参数表_受控整件.len());
    assert!(项表[命令表内位(能力号::受控原子写入)].参数个数 as usize == 参数表_原子写入.len());
    assert!(项表[命令表内位(能力号::读取环境文件)].参数个数 as usize == 参数表_读取环境文件.len());
    assert!(
        项表[命令表内位(能力号::受控原子写入字节)].参数个数 as usize
            == 参数表_原子写入字节.len()
    );
    assert!(项表[命令表内位(能力号::查找祖先目录)].参数个数 as usize == 参数表_查找祖先目录.len());
    assert!(项表[命令表内位(能力号::取路径元信息)].参数个数 as usize == 参数表_取路径元信息.len());
    assert!(项表[命令表内位(能力号::扫描类属性)].参数个数 as usize == 参数表_扫描类属性.len());
    assert!(项表[命令表内位(能力号::清理暂存残留)].参数个数 as usize == 参数表_清理暂存残留.len());
    assert!(项表[命令表内位(能力号::受控工作区)].参数个数 as usize == 参数表_受控工作区.len());
    assert!(项表[命令表内位(能力号::唯一文本替换)].参数个数 as usize == 参数表_唯一文本替换.len());
    assert!(项表[命令表内位(能力号::受控验证)].参数个数 as usize == 参数表_受控验证.len());
    assert!(项表[命令表内位(能力号::受控回滚)].参数个数 as usize == 参数表_受控回滚.len());
    assert!(项表[命令表内位(能力号::受控创建提交)].参数个数 as usize == 参数表_受控创建提交.len());
    assert!(
        参数个数已核条数 == 项表.len(),
        "③h：已核条数 与 命令表项数 不符 —— 加了命令没加断言"
    );
};
