//! 表骨架 —— 命令表/函数表的项数与下标换算、命令项构造、空位种子。
//!
//! 本件只装「造表用的零件」，不含任何一条命令的内容：命令内容在 `基础参数表` ·
//! `受控读写参数表` · `路径与扫描参数表` · `工作区参数表`，装配在 `命令表填充`。

use v1_contract::{参数信息, 命令信息, 表段};

use crate::能力号;

/// ③g 落点：命令表项数（只装本扩展声明过的 1 条，编号 3101）。
pub const 命令表项数: usize = 24;
/// ③g 落点：函数表项数（与命令表一一对应、等长）。
pub const 函数表项数: usize = 24;
/// ③h 落点：已核条数（逐条核过「参数表项数 == 参数个数」的命令条数）。
pub const 参数个数已核条数: usize = 24;
/// 命令表首号（本扩展申报号段 `[3101, 3199]` 的起点）。
pub const 命令表首号: u32 = 能力号::取文件摘要;

/// 命令编号 → 表内下标。编号不在本扩展的命令表内即当场 panic。
pub const fn 命令表内位(编号: u32) -> usize {
    assert!(
        编号 >= 命令表首号 && (编号 - 命令表首号) < 命令表项数 as u32,
        "编号不在本扩展的命令表内"
    );
    (编号 - 命令表首号) as usize
}

/// 造一条命令项。`编号` 是**显式命令编号**（源：`能力声明/<编号>.json`）；
/// `返回类型` / `参数个数` / `参数表` / `可抛错误码` 同样逐条取自同一份声明。
pub const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    返回类型: v1_contract::类型标签,
    参数个数: u32,
    参数表: *const 参数信息,
    可抛错误码: 表段<u32>,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型,
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(
            可抛错误码.项表 as *const v1_contract::错误码,
            可抛错误码.表项数,
        ),
    }
}

pub const 空位种子: 命令信息 = 命令信息 {
    名称: "空位种子\0".as_bytes().as_ptr(),
    说明: "命令表的空位种子：表内每一位都该被覆写。\0"
        .as_bytes()
        .as_ptr(),
    类别号: 0,
    状态位: 0,
    返回类型: v1_contract::类型标签::构造(0),
    用户级别: 0,
    参数个数: 0,
    参数表: core::ptr::null(),
    编号: v1_contract::能力号::构造(0),
    可抛错误码: 表段::空实例(),
};
