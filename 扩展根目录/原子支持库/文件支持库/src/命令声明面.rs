//!
//! 参数表行序与 `能力声明/3101.json` 的 `参数表` 逐行对应；命令编号是**显式字段**
//! （`命令信息.编号`，源 = `能力声明/3101.json`），故命令表只装本扩展声明过的那一条。
//! 函数表在 `执行函数面.rs`（与命令表等长、一一对应）。

