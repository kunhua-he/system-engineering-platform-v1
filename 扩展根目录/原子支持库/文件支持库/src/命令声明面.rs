//! 命令声明面 —— 参数表 · 命令表 · ③g/③h 的编译期断言落点。
//!
//! 参数表行序与 `能力声明/3101.json` 的 `参数表` 逐行对应；命令编号是**显式字段**
//! （`命令信息.编号`，源 = `能力声明/3101.json`），故命令表只装本扩展声明过的那一条。
//! 函数表在 `执行函数面.rs`（与命令表等长、一一对应）。

use v1_contract::声明数据::类型标签_0004;
use v1_contract::{命令信息, 参数信息, 数据槽, 表段};

use crate::能力号;
use crate::错误码;

/// ③g 落点：命令表项数（只装本扩展声明过的 1 条，编号 3101）。
pub const 命令表项数: usize = 1;
/// ③g 落点：函数表项数（与命令表一一对应、等长）。
pub const 函数表项数: usize = 1;
/// ③h 落点：已核条数（逐条核过「参数表项数 == 参数个数」的命令条数）。
pub const 参数个数已核条数: usize = 1;
/// 命令表首号（本扩展申报号段 `[3101, 3199]` 的起点）。
pub const 命令表首号: u32 = 能力号::取文件摘要;

/// 命令编号 → 表内下标。编号不在本扩展的命令表内即当场 panic。
pub const fn 命令表内位(编号: u32) -> usize {
    assert!(
        编号 >= 命令表首号 && (编号 - 命令表首号) < 命令表项数 as u32,
        "编号不在本扩展的命令表内"
    );
    (编号 - 命令表首号) as usize
}

/// 造一条命令项。`编号` 是**显式命令编号**（源：`能力声明/<编号>.json`）；
/// `返回类型` / `参数个数` / `参数表` / `可抛错误码` 同样逐条取自同一份声明。
pub const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    返回类型: v1_contract::类型标签,
    参数个数: u32,
    参数表: *const 参数信息,
    可抛错误码: 表段<u32>,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型,
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(可抛错误码.项表 as *const v1_contract::错误码, 可抛错误码.表项数),
    }
}

// ── 参数表（行序即契约）──
/// 路径（文本）—— 源：能力声明/3101.json。
pub const 参数表_路径: [参数信息; 1] = [参数信息 {
    名称: "路径\0".as_bytes().as_ptr(),
    说明: "要读取的文件的绝对路径（文本）\0".as_bytes().as_ptr(),
    类型标签: 类型标签_0004,
    状态位: 0,
    默认值: 数据槽::空槽(),
}];

// ── 可抛错误码（逐条取自 能力声明/3101.json）──
/// 文件不存在 + 不是普通文件 + 读取被拒 + 路径不是绝对路径 —— 源：能力声明/3101.json。
pub const 可抛错误码_文件码: [u32; 4] = [错误码::文件不存在, 错误码::不是普通文件, 错误码::读取被拒, 错误码::路径不是绝对路径];

/// 命令表的**空位种子**：只为 `[种子; 命令表项数]` 提供初值（`命令信息` 是 `Copy`）。
/// 造表会覆写每一位；见到它说明造表漏了一位（编号 0 不在本扩展申报号段内 ⇒ 当场露馅）。
pub const 空位种子: 命令信息 = 命令信息 {
    名称: "空位种子\0".as_bytes().as_ptr(),
    说明: "命令表的空位种子：表内每一位都该被覆写。\0".as_bytes().as_ptr(),
    类别号: 0,
    状态位: 0,
    返回类型: v1_contract::类型标签::构造(0),
    用户级别: 0,
    参数个数: 0,
    参数表: core::ptr::null(),
    编号: v1_contract::能力号::构造(0),
    可抛错误码: 表段::空实例(),
};

/// 命令表：**只装本扩展声明过的那一条**（编号 3101）。
/// 为什么写成 `本表[命令表内位(…)] = 命令项(…)` 而不是数组字面量：实现侧扫描器
/// （`测试验证/契约一致性/扫实现.py`）只认这一类调用，字面量数组会把命令全漏掉
/// ⇒ ③c/③d 对这份声明会**静默**不判（不是判过）。
pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::取文件摘要)] = 命令项(
        能力号::取文件摘要,
        "取文件摘要\0".as_bytes(),
        "读一个真实文件，返回字节数·行数·SHA-256。\0".as_bytes(),
        v1_contract::类型标签::构造(103),
        1,
        参数表_路径.as_ptr(),
        表段::构造(可抛错误码_文件码.as_ptr(), 可抛错误码_文件码.len() as u32),
    );
    本表
}

// ③g 编译期断言：两张表的**真实长度**与各自的项数声明同值，且两表等长。
const _: () = assert!(造命令表().len() == 命令表项数, "③g：命令表项数 与 命令表 实际长度不符");
const _: () = assert!(crate::执行函数面::执行函数表.len() == 函数表项数, "③g：函数表项数 与 执行函数表 实际长度不符");
const _: () = assert!(命令表项数 == 函数表项数, "③g：命令表与执行函数表必须等长");

// ③h 编译期断言：逐条核「该条的 参数个数 == 它引用的参数表项数」。
// 为什么逐条列名（而不是循环遍历命令表）：`命令信息.参数表` 是**裸指针**，编译期取不到被指
// 数组的长度，也没有「指针 → 表」的编译期映射（const 求值不许比较指针）。
const _: () = {
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::取文件摘要)].参数个数 as usize == 参数表_路径.len(), "③h：3101 的 参数个数 与 参数表_路径 项数不符");
    // 断言条数与表长必须相等：加一条命令就必须加一条断言，漏了这里当场编译不过。
    assert!(参数个数已核条数 == 项表.len(), "③h：已核条数 与 命令表项数 不符 —— 加了命令没加断言");
};
