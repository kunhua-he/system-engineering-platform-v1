/// 命令表：**只装本扩展声明过的那一条**（编号 3101）。
/// 为什么写成 `本表[命令表内位(…)] = 命令项(…)` 而不是数组字面量：实现侧扫描器
/// （`测试验证/契约一致性/扫实现.py`）只认这一类调用，字面量数组会把命令全漏掉
/// ⇒ ③c/③d 对这份声明会**静默**不判（不是判过）。
///
/// 装配按能力号分组转给 `命令表填充`（顺序与 ③h 断言逐条对应）。
pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    命令表填充::填基础命令(&mut 本表);
    命令表填充::填受控读写命令(&mut 本表);
    命令表填充::填工作区命令(&mut 本表);
    本表
}
