/// 32 位无符号数循环右移（SHA-256 的四个混量都靠它）。
const fn 右旋(值: u32, 位数: u32) -> u32 {
    值.rotate_right(位数)
}

/// SHA-256 的流式散列状态。
struct 摘要状态 {
    状态字: [u32; 8],
    缓冲: [u8; 64],
    已填: usize,
    总字节: u64,
}

impl 摘要状态 {
    /// 初态：标准初值 · 空缓冲 · 零字节。
    const fn 初态() -> Self {
        Self { 状态字: 初始散列表, 缓冲: [0u8; 64], 已填: 0, 总字节: 0 }
    }

    /// 喂入字节：先补满缓冲，满一块就压一块；剩下的留在缓冲里。
    fn 喂入字节(&mut self, 待散列字节: &[u8]) {
        self.总字节 += 待散列字节.len() as u64;
        let mut 起位 = 0;
        if self.已填 > 0 {
            let 需补 = 64 - self.已填;
            let 实补 = 需补.min(待散列字节.len());
            self.缓冲[self.已填..self.已填 + 实补].copy_from_slice(&待散列字节[..实补]);
            self.已填 += 实补;
            起位 = 实补;
            if self.已填 == 64 {
                self.压块();
                self.已填 = 0;
            }
        }
        while 待散列字节.len() - 起位 >= 64 {
            self.缓冲.copy_from_slice(&待散列字节[起位..起位 + 64]);
            self.压块();
            起位 += 64;
        }
        if 起位 < 待散列字节.len() {
            let 剩字节 = 待散列字节.len() - 起位;
            self.缓冲[..剩字节].copy_from_slice(&待散列字节[起位..]);
            self.已填 = 剩字节;
        }
    }

    /// 结算：补位（0x80 + 零填充 + 64 位大端位长）→ 输出 32 字节散列。
    fn 结算(mut self) -> [u8; 32] {
        let 位长 = self.总字节 * 8;
        self.缓冲[self.已填] = 0x80;
        self.已填 += 1;
        if self.已填 > 56 {
            for 位次 in self.已填..64 {
                self.缓冲[位次] = 0;
            }
            self.压块();
            self.已填 = 0;
        }
        for 位次 in self.已填..56 {
            self.缓冲[位次] = 0;
        }
        self.缓冲[56..64].copy_from_slice(&位长.to_be_bytes());
        self.压块();
        let mut 输出 = [0u8; 32];
        for (位次, 状态项) in self.状态字.iter().enumerate() {
            输出[位次 * 4..位次 * 4 + 4].copy_from_slice(&状态项.to_be_bytes());
        }
        输出
    }

    /// 对已满的 64 字节块做一轮压缩（FIPS 180-4 §6.2.2）。
    fn 压块(&mut self) {
        let mut 字表 = [0u32; 64];
        for (位次, 初始字) in 字表.iter_mut().enumerate().take(16) {
            *初始字 = u32::from_be_bytes([
                self.缓冲[位次 * 4],
                self.缓冲[位次 * 4 + 1],
                self.缓冲[位次 * 4 + 2],
                self.缓冲[位次 * 4 + 3],
            ]);
        }
        for 位次 in 16..64 {
            let 远位字 = 字表[位次 - 15];
            let 近位字 = 字表[位次 - 2];
            let 消息混零 = 右旋(远位字, 7) ^ 右旋(远位字, 18) ^ (远位字 >> 3);
            let 消息混一 = 右旋(近位字, 17) ^ 右旋(近位字, 19) ^ (近位字 >> 10);
            字表[位次] = 字表[位次 - 16]
                .wrapping_add(消息混零)
                .wrapping_add(字表[位次 - 7])
                .wrapping_add(消息混一);
        }
        let mut 工作字 = self.状态字;
        for 位次 in 0..64 {
            let 状态混一 = 右旋(工作字[4], 6) ^ 右旋(工作字[4], 11) ^ 右旋(工作字[4], 25);
            let 择位 = (工作字[4] & 工作字[5]) ^ ((!工作字[4]) & 工作字[6]);
            let 临时字 = 工作字[7]
                .wrapping_add(状态混一)
                .wrapping_add(择位)
                .wrapping_add(轮常量表[位次])
                .wrapping_add(字表[位次]);
            let 状态混零 = 右旋(工作字[0], 2) ^ 右旋(工作字[0], 13) ^ 右旋(工作字[0], 22);
            let 多择 = (工作字[0] & 工作字[1]) ^ (工作字[0] & 工作字[2]) ^ (工作字[1] & 工作字[2]);
            工作字[7] = 工作字[6];
            工作字[6] = 工作字[5];
            工作字[5] = 工作字[4];
            工作字[4] = 工作字[3].wrapping_add(临时字);
            工作字[3] = 工作字[2];
            工作字[2] = 工作字[1];
            工作字[1] = 工作字[0];
            工作字[0] = 临时字.wrapping_add(状态混零).wrapping_add(多择);
        }
        for (状态项, 工作项) in self.状态字.iter_mut().zip(工作字) {
            *状态项 = 状态项.wrapping_add(工作项);
        }
    }
}

/// 把打开失败的 io 错误归成两档：找不到 ⇒ 文件不存在；其余（权限等）⇒ 读取被拒。
fn 归类打开错误(错误: &std::io::Error) -> 摘要错误 {
    match 错误.kind() {
        std::io::ErrorKind::NotFound => 摘要错误::文件不存在,
        _ => 摘要错误::读取被拒,
    }
}

/// 32 字节散列 → 小写十六进制 64 字。
fn 转十六进制(散列: &[u8; 32]) -> String {
    const 十六进制字符表: [u8; 16] = *b"0123456789abcdef";
    let mut 输出文本 = String::with_capacity(64);
    for 字节 in 散列 {
        输出文本.push(十六进制字符表[(字节 >> 4) as usize] as char);
        输出文本.push(十六进制字符表[(字节 & 0x0f) as usize] as char);
    }
    输出文本
}

/// 读一个真实文件，返回 字节数 · 行数 · SHA-256 三值。
///
/// 文件句柄只在本次调用里活：任何错误分支都先返回 [`摘要错误`] 再离开作用域，
/// **不把句柄跨边界传出**（返回里没有 6 句柄 / 7 任务句柄）。
pub fn 算摘要(路径: &str) -> Result<摘要结果, 摘要错误> {
    let mut 文件句柄 = File::open(路径).map_err(|错误| 归类打开错误(&错误))?;
    let 元数据 = 文件句柄.metadata().map_err(|_| 摘要错误::读取被拒)?;
    if !元数据.is_file() {
        return Err(摘要错误::不是普通文件);
    }
    let mut 状态 = 摘要状态::初态();
    let mut 缓冲 = vec![0u8; 块字节数];
    let mut 字节数: u64 = 0;
    let mut 行数: u64 = 0;
    let mut 末字节: u8 = 0;
    loop {
        let 读到 = 文件句柄.read(&mut 缓冲).map_err(|_| 摘要错误::读取被拒)?;
        if 读到 == 0 {
            break;
        }
        状态.喂入字节(&缓冲[..读到]);
        字节数 += 读到 as u64;
        行数 += 缓冲[..读到].iter().filter(|字节| **字节 == b'\n').count() as u64;
        末字节 = 缓冲[读到 - 1];
    }
    if 字节数 > 0 && 末字节 != b'\n' {
        行数 += 1;
    }
    let 散列 = 状态.结算();
    Ok(摘要结果 { 字节数, 行数, 摘要文本: 转十六进制(&散列) })
}
