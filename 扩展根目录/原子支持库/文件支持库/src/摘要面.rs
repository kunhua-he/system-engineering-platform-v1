//! 摘要面 —— SHA-256 纯实现（零第三方依赖）+ 64 KiB 分块读 + 行数口径。
//!
//! # 口径是**内部固定的**，不给调用方开关
//!
//! · 摘要算法固定 SHA-256，输出小写十六进制 64 字（空文件也有摘要，不返回空串）；
//! · 行数 = `\n` 计数 + （件非空且末字节不是 `\n` 则 +1）；空件 0 行；
//! · 分块读，块大小 [`块字节数`]（64 KiB），不整件读进内存。
//!
//! 要别的算法是**另一个编号**，不是同一个编号的参数。
//!
//! # 三种可判结局
//!
//! 打开/读取的 io 错误一律归成 [`摘要错误`] 的三档 —— 与 `错误码表/3001..3003.json` 一一对应。
//! **不用 0 当失败哨兵**：空文件的 字节数 0 · 行数 0 是**合法值**，成功返回。

use std::fs::File;
use std::io::Read;

/// 一次读盘的块大小：64 KiB。固定，不给调用方选。
const 块字节数: usize = 64 * 1024;

/// 摘要结果 —— 三个必要值（字段名与顺序照 `类型声明/103.json` 的元素表）。
pub struct 摘要结果 {
    pub 字节数: u64,
    pub 行数: u64,
    pub 摘要文本: String,
}

/// 读取失败的三种可判结局（与 `错误码表/3001 · 3002 · 3003.json` 一一对应）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 摘要错误 {
    文件不存在,
    不是普通文件,
    读取被拒,
}

