use crate::编号与码面::能力号;
use v1_contract::{参数信息, 命令信息, 数据槽, 表段};
pub const 命令表项数: usize = 4;
pub const 函数表项数: usize = 4;
pub const 参数个数已核条数: usize = 4;
pub const 命令表首号: u32 = 能力号::打开连接;
pub const fn 命令表内位(编号: u32) -> usize {
    assert!(编号 >= 命令表首号 && 编号 < 命令表首号 + 命令表项数 as u32);
    (编号 - 命令表首号) as usize
}
pub const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    返回类型: v1_contract::类型标签,
    参数个数: u32,
    参数表: *const 参数信息,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 名称.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型,
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(
            可抛错误码_连接.as_ptr() as *const v1_contract::错误码,
            可抛错误码_连接.len() as u32,
        ),
    }
}
