pub const 空位种子: 命令信息 = 命令信息 {
    名称: c"reserved".as_ptr() as *const u8,
    说明: c"reserved".as_ptr() as *const u8,
    类别号: 0,
    状态位: 0,
    返回类型: v1_contract::类型标签::构造(0),
    用户级别: 0,
    参数个数: 0,
    参数表: core::ptr::null(),
    编号: v1_contract::能力号::构造(0),
    可抛错误码: 表段::空实例(),
};
pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::打开连接)] = 命令项(
        能力号::打开连接,
        "打开连接\0".as_bytes(),
        v1_contract::类型标签::构造(6),
        1,
        参数表_打开连接.as_ptr(),
    );
    本表[命令表内位(能力号::只读查询)] = 命令项(
        能力号::只读查询,
        "只读查询\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        2,
        参数表_只读查询.as_ptr(),
    );
    本表[命令表内位(能力号::执行事务)] = 命令项(
        能力号::执行事务,
        "执行事务\0".as_bytes(),
        v1_contract::类型标签::构造(1),
        2,
        参数表_执行事务.as_ptr(),
    );
    本表[命令表内位(能力号::释放连接)] = 命令项(
        能力号::释放连接,
        "释放连接\0".as_bytes(),
        v1_contract::类型标签::构造(1),
        1,
        参数表_释放连接.as_ptr(),
    );
    本表
}
const _: () = {
    let 项表 = 造命令表();
    assert!(命令表项数 == 函数表项数);
    assert!(crate::执行函数面::执行函数表.len() == 函数表项数);
    assert!(项表[命令表内位(能力号::打开连接)].参数个数 as usize == 参数表_打开连接.len());
    assert!(项表[命令表内位(能力号::只读查询)].参数个数 as usize == 参数表_只读查询.len());
    assert!(项表[命令表内位(能力号::执行事务)].参数个数 as usize == 参数表_执行事务.len());
    assert!(项表[命令表内位(能力号::释放连接)].参数个数 as usize == 参数表_释放连接.len());
    assert!(参数个数已核条数 == 项表.len());
};
