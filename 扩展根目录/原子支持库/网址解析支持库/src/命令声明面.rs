pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::规范化网址)] = 命令项(
        能力号::规范化网址,
        "规范化网址\0".as_bytes(),
        "规范化网址\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        1,
        参数表_规范化网址.as_ptr(),
        表段::构造(可抛错误码_文本.as_ptr(), 3),
    );
    本表[命令表内位(能力号::合并相对网址)] = 命令项(
        能力号::合并相对网址,
        "合并相对网址\0".as_bytes(),
        "合并相对网址\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        2,
        参数表_合并相对网址.as_ptr(),
        表段::构造(可抛错误码_文本.as_ptr(), 3),
    );
    本表[命令表内位(能力号::取查询参数JSON)] = 命令项(
        能力号::取查询参数JSON,
        "取查询参数JSON\0".as_bytes(),
        "取查询参数JSON\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        1,
        参数表_取查询参数JSON.as_ptr(),
        表段::构造(可抛错误码_文本.as_ptr(), 3),
    );
    本表[命令表内位(能力号::提取外部标识)] = 命令项(
        能力号::提取外部标识,
        "提取外部标识\0".as_bytes(),
        "按来源类型提取外部标识，返回JSON文本；边界判定手写，不依赖正则前瞻。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        2,
        参数表_提取外部标识.as_ptr(),
        表段::构造(可抛错误码_外部标识.as_ptr(), 3),
    );
    本表
}
const _: () = {
    assert!(命令表项数 == 函数表项数);
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::规范化网址)].参数个数 as usize == 参数表_规范化网址.len());
    assert!(项表[命令表内位(能力号::合并相对网址)].参数个数 as usize == 参数表_合并相对网址.len());
    assert!(
        项表[命令表内位(能力号::取查询参数JSON)].参数个数 as usize == 参数表_取查询参数JSON.len()
    );
    assert!(
        项表[命令表内位(能力号::提取外部标识)].参数个数 as usize == 参数表_提取外部标识.len()
    );
    assert!(参数个数已核条数 == 项表.len());
};
