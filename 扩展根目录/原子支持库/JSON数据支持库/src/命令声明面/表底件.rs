//! 表底件：命令项构造器、通用可抛错误码、命令表空位种子。

use v1_contract::{参数信息, 命令信息, 表段};

pub(super) const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    返回类型: v1_contract::类型标签,
    参数个数: u32,
    参数表: *const 参数信息,
    可抛错误码: 表段<u32>,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型,
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(
            可抛错误码.项表 as *const v1_contract::错误码,
            可抛错误码.表项数,
        ),
    }
}

pub(super) const 可抛错误码_文本: [u32; 4] = [5201, 5202, 5203, 5204];

pub(super) const 空位种子: 命令信息 = 命令信息 {
    名称: "空位种子\0".as_bytes().as_ptr(),
    说明: "命令表的空位种子：表内每一位都该被覆写。\0"
        .as_bytes()
        .as_ptr(),
    类别号: 0,
    状态位: 0,
    返回类型: v1_contract::类型标签::构造(0),
    用户级别: 0,
    参数个数: 0,
    参数表: core::ptr::null(),
    编号: v1_contract::能力号::构造(0),
    可抛错误码: 表段::空实例(),
};
