//!
//! | 件 | 职责 |
//! | --- | --- |
//! | 本文件 | 表规模常量 · 编号定位 · 子件声明 · 导出 `造命令表` |
//! | `表底件.rs` | 命令项构造器 · 通用可抛错误码 · 空位种子 |
//! | `参数表_查询与变换.rs` | 5201–5213 的参数表 |
//! | `参数表_文本与响应.rs` | 5214–5220 的参数表 |
//! | `命令表装配.rs` | const 期填表 · 参数个数自校验 |

use crate::编号与码面::能力号;

#[path = "命令声明面/表底件.rs"]
mod 表底件;
#[path = "命令声明面/参数表_查询与变换.rs"]
mod 参数表_查询与变换;
#[path = "命令声明面/参数表_文本与响应.rs"]
mod 参数表_文本与响应;
#[path = "命令声明面/命令表装配.rs"]
mod 命令表装配;

pub use 命令表装配::造命令表;

pub const 命令表项数: usize = 20;
pub const 函数表项数: usize = 20;
pub const 参数个数已核条数: usize = 20;
pub const 命令表首号: u32 = 能力号::规范化JSON;

pub const fn 命令表内位(编号: u32) -> usize {
    assert!(
        编号 >= 命令表首号 && (编号 - 命令表首号) < 命令表项数 as u32,
        "编号不在本扩展的命令表内"
    );
    (编号 - 命令表首号) as usize
}
