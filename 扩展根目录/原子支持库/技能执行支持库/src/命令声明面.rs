//! 技能执行支持库的命令表：一条能力、参数表与可抛错误码段。

use v1_contract::{参数信息, 命令信息, 数据槽};
use crate::编号与码面::能力号;

pub const 命令表项数: usize = 1;
pub const 函数表项数: usize = 1;
#[allow(dead_code)]
pub const 参数个数已核条数: usize = 1;
pub const 命令表首号: u32 = 能力号::准备技能执行;

pub const fn 命令表内位(编号: u32) -> usize {
    assert!(
        编号 >= 命令表首号 && (编号 - 命令表首号) < 命令表项数 as u32,
        "编号不在本扩展的命令表内"
    );
    (编号 - 命令表首号) as usize
}

pub const 参数表_准备技能执行: [参数信息; 1] = [参数信息 {
    名称: "执行参数\0".as_bytes().as_ptr(),
    说明: "JSON 文本：技能根目录 / 能力标识（分类.技能名）/ 参数 / 项目根目录 / 禁止导入前缀[] / 解释器（可空）/ 超时秒数（可空）。\0".as_bytes().as_ptr(),
    类型标签: v1_contract::类型标签::构造(4),
    状态位: 0,
    默认值: 数据槽::空槽(),
}];

pub const 可抛错误码段: [u32; 10] = [8301, 8302, 8303, 8304, 8305, 8306, 8307, 8308, 8309, 8310];

pub const fn 命令项(编号: u32, 名称: &'static [u8], 描述: &'static [u8], 返回类型: v1_contract::类型标签, 参数个数: u32, 参数表: *const 参数信息, 可抛错误码: v1_contract::表段<u32>) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型,
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: v1_contract::表段::构造(可抛错误码.项表 as *const v1_contract::错误码, 可抛错误码.表项数),
    }
}

pub const 空位种子: 命令信息 = 命令信息 {
    名称: "空位种子\0".as_bytes().as_ptr(),
    说明: "命令表的空位种子：表内每一位都该被覆写。\0".as_bytes().as_ptr(),
    类别号: 0,
    状态位: 0,
    返回类型: v1_contract::类型标签::构造(0),
    用户级别: 0,
    参数个数: 0,
    参数表: core::ptr::null(),
    编号: v1_contract::能力号::构造(0),
    可抛错误码: v1_contract::表段::空实例(),
};

pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::准备技能执行)] = 命令项(
        能力号::准备技能执行,
        "准备技能执行\0".as_bytes(),
        "校验技能包六件套、入口脚本范围与脚本静态安全边界（禁任意命令执行/动态加载/禁止导入前缀），把参数写成临时文件，产出可直接提交给进程执行支持库 2601 的执行计划（脚本路径/解释器/参数文件/命令/超时秒/提交参数）。本能力**只校验只出计划，不起进程**。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        1,
        参数表_准备技能执行.as_ptr(),
        v1_contract::表段::构造(可抛错误码段.as_ptr(), 10),
    );
    本表
}

const _: () = {
    assert!(命令表项数 == 函数表项数);
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::准备技能执行)].参数个数 as usize == 参数表_准备技能执行.len());
};
