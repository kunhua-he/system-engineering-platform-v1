pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::创建会话)] = 命令项(能力号::创建会话, "创建会话\0".as_bytes(), "起一个无头浏览器并开一个新标签，返回整数句柄；会话生命周期归底座，最多同时 8 个\0".as_bytes(), v1_contract::类型标签::构造(4), 1, 参数表_创建会话.as_ptr(), v1_contract::表段::构造(可抛错误码_会话.as_ptr(), 5));
    本表[命令表内位(能力号::导航)] = 命令项(能力号::导航, "导航\0".as_bytes(), "在会话里打开 http/https/file 网址，等 readyState 到 complete（最多 20 秒），返回地址/标题/加载状态\0".as_bytes(), v1_contract::类型标签::构造(4), 2, 参数表_导航.as_ptr(), v1_contract::表段::构造(可抛错误码_动作.as_ptr(), 8));
    本表[命令表内位(能力号::读页面)] = 命令项(能力号::读页面, "读页面\0".as_bytes(), "读法：文本=body.innerText / html=outerHTML / 标题地址 / 元素=按 CSS 选择器取文本·标签·属性·是否可见\0".as_bytes(), v1_contract::类型标签::构造(4), 3, 参数表_读页面.as_ptr(), v1_contract::表段::构造(可抛错误码_动作.as_ptr(), 8));
    本表[命令表内位(能力号::操作元素)] = 命令项(能力号::操作元素, "操作元素\0".as_bytes(), "动作：点击 / 填值（带 input+change 事件）/ 悬停 / 滚入视野；元素不存在报元素未找到，不做坐标模拟\0".as_bytes(), v1_contract::类型标签::构造(4), 4, 参数表_操作元素.as_ptr(), v1_contract::表段::构造(可抛错误码_动作.as_ptr(), 8));
    本表[命令表内位(能力号::截图)] = 命令项(能力号::截图, "截图\0".as_bytes(), "整页截图为 PNG 落盘，返回句柄与字节数；路径必须是绝对路径\0".as_bytes(), v1_contract::类型标签::构造(4), 2, 参数表_截图.as_ptr(), v1_contract::表段::构造(可抛错误码_动作.as_ptr(), 8));
    本表[命令表内位(能力号::关闭会话)] = 命令项(能力号::关闭会话, "关闭会话\0".as_bytes(), "杀掉该会话的浏览器进程并清临时目录；句柄随即失效\0".as_bytes(), v1_contract::类型标签::构造(4), 1, 参数表_关闭会话.as_ptr(), v1_contract::表段::构造(可抛错误码_会话.as_ptr(), 5));
    本表
}

const _: () = {
    assert!(命令表项数 == 函数表项数);
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::创建会话)].参数个数 as usize == 参数表_创建会话.len());
    assert!(项表[命令表内位(能力号::导航)].参数个数 as usize == 参数表_导航.len());
    assert!(项表[命令表内位(能力号::读页面)].参数个数 as usize == 参数表_读页面.len());
    assert!(项表[命令表内位(能力号::操作元素)].参数个数 as usize == 参数表_操作元素.len());
    assert!(项表[命令表内位(能力号::截图)].参数个数 as usize == 参数表_截图.len());
    assert!(项表[命令表内位(能力号::关闭会话)].参数个数 as usize == 参数表_关闭会话.len());
};
