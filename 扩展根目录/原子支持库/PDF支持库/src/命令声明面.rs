pub const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    参数个数: u32,
    参数表: *const 参数信息,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型: v1_contract::类型标签::构造(4),
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(可抛错误码_文档.as_ptr() as *const v1_contract::错误码, 8),
    }
}

const 空位种子: 命令信息 = 命令信息 {
    名称: [0u8].as_ptr(),
    说明: [0u8].as_ptr(),
    类别号: 0,
    状态位: 0,
    返回类型: v1_contract::类型标签::构造(4),
    用户级别: 0,
    参数个数: 0,
    参数表: std::ptr::null(),
    编号: v1_contract::能力号::构造(0),
    可抛错误码: 表段::空实例(),
};

pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::检测加密页数)] = 命令项(
        能力号::检测加密页数,
        "检测PDF加密页数\0".as_bytes(),
        "返回 PDF 总页数、是否加密与可否打开。\0".as_bytes(),
        1,
        参数表_检测加密页数.as_ptr(),
    );
    本表[命令表内位(能力号::渲染页面)] = 命令项(
        能力号::渲染页面,
        "渲染PDF页面\0".as_bytes(),
        "把指定页渲染成 PNG 落盘，返回尺寸与字节数。\0".as_bytes(),
        4,
        参数表_渲染页面.as_ptr(),
    );
    本表[命令表内位(能力号::提取内嵌图)] = 命令项(
        能力号::提取内嵌图,
        "提取PDF页内嵌图\0".as_bytes(),
        "提取指定页内嵌 JPEG 图像，返回 base64 列表；非 JPEG 流如实列为未提取。\0".as_bytes(),
        2,
        参数表_提取内嵌图.as_ptr(),
    );
    本表[命令表内位(能力号::校验文件)] = 命令项(
        能力号::校验文件,
        "校验PDF文件\0".as_bytes(),
        "校验 PDF 可解析性，返回是否合法、版本、页数与加密状态。\0".as_bytes(),
        1,
        参数表_校验文件.as_ptr(),
    );
    本表
}

const _: () = {
    assert!(命令表项数 == 函数表项数);
    assert!(参数个数已核条数 == 命令表项数);
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::检测加密页数)].参数个数 as usize == 参数表_检测加密页数.len());
    assert!(项表[命令表内位(能力号::渲染页面)].参数个数 as usize == 参数表_渲染页面.len());
    assert!(项表[命令表内位(能力号::提取内嵌图)].参数个数 as usize == 参数表_提取内嵌图.len());
    assert!(项表[命令表内位(能力号::校验文件)].参数个数 as usize == 参数表_校验文件.len());
};
