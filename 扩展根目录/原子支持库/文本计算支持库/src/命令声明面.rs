pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::多重集对账)] = 命令项(
        能力号::多重集对账,
        "多重集对账\0".as_bytes(),
        "按条目计次对账：返回缺失／多余／共有三张表与判定，重复段落按次数判，不退化成集合比对。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        3,
        参数表_多重集对账.as_ptr(),
        表段::构造(可抛错误码_对账.as_ptr(), 3),
    );
    本表[命令表内位(能力号::筛选时间窗行)] = 命令项(
        能力号::筛选时间窗行,
        "筛选时间窗行\0".as_bytes(),
        "按真实时刻筛选日志行：闭区间比较，命中行给出 行号／时刻／正文，并回报无法解析行数。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        4,
        参数表_筛选时间窗行.as_ptr(),
        表段::构造(可抛错误码_时间窗.as_ptr(), 3),
    );
    本表[命令表内位(能力号::查询人格上下文)] = 命令项(
        能力号::查询人格上下文,
        "查询人格上下文\0".as_bytes(),
        "查询指定主体、岗位、场景与两个RFC3339时点的人格上下文，响应必须是原生JSON对象。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        5,
        查询人格上下文参数表.as_ptr(),
        表段::构造(可抛错误码查询人格上下文.as_ptr(), 2),
    );
    本表[命令表内位(能力号::格式化可注入上下文)] = 命令项(
        能力号::格式化可注入上下文,
        "格式化可注入上下文\0".as_bytes(),
        "将上下文JSON对象格式化为Markdown，只注已确认事实与观察，保留证据边界与禁止推断。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        1,
        格式化可注入上下文参数表.as_ptr(),
        表段::构造(可抛错误码格式化可注入上下文.as_ptr(), 1),
    );
    本表
}

const 项表: [命令信息; 命令表项数] = 造命令表();
const _: () = {
    assert!(
        项表[命令表内位(能力号::多重集对账)].参数个数 as usize == 参数表_多重集对账.len()
    );
    assert!(
        项表[命令表内位(能力号::筛选时间窗行)].参数个数 as usize
            == 参数表_筛选时间窗行.len()
    );
    assert!(
        项表[命令表内位(能力号::查询人格上下文)].参数个数 as usize
            == 查询人格上下文参数表.len()
    );
    assert!(
        项表[命令表内位(能力号::格式化可注入上下文)].参数个数 as usize
            == 格式化可注入上下文参数表.len()
    );
    assert!(参数个数已核条数 == 项表.len());
};
