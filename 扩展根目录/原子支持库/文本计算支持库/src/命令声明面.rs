pub const 参数个数已核条数: usize = 4;
pub const fn 命令表内位(编号: u32) -> usize {
    match 编号 {
        能力号::多重集对账 => 0,
        能力号::筛选时间窗行 => 1,
        能力号::查询人格上下文 => 2,
        能力号::格式化可注入上下文 => 3,
        _ => panic!("编号不在本扩展的命令表内"),
    }
}

pub const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    返回类型: v1_contract::类型标签,
    参数个数: u32,
    参数表: *const 参数信息,
    可抛错误码: 表段<u32>,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型,
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(
            可抛错误码.项表 as *const v1_contract::错误码,
            可抛错误码.表项数,
        ),
    }
}

