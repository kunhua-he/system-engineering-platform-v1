pub const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    参数个数: u32,
    参数表: *const 参数信息,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型: v1_contract::类型标签::构造(4),
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(可抛错误码_图像.as_ptr() as *const v1_contract::错误码, 5),
    }
}

const 空位种子: 命令信息 = 命令信息 {
    名称: [0u8].as_ptr(),
    说明: [0u8].as_ptr(),
    类别号: 0,
    状态位: 0,
    返回类型: v1_contract::类型标签::构造(4),
    用户级别: 0,
    参数个数: 0,
    参数表: std::ptr::null(),
    编号: v1_contract::能力号::构造(0),
    可抛错误码: 表段::空实例(),
};

pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::分析图像文件)] = 命令项(
        能力号::分析图像文件,
        "分析图像文件\0".as_bytes(),
        "解码图像并统计格式、宽高、模式、像素数与平均颜色\0".as_bytes(),
        1,
        参数表_分析图像文件.as_ptr(),
    );
    本表[命令表内位(能力号::识别图像格式)] = 命令项(
        能力号::识别图像格式,
        "识别图像格式\0".as_bytes(),
        "按字节判定图像格式并给出宽高与颜色模式\0".as_bytes(),
        1,
        参数表_识别图像格式.as_ptr(),
    );
    本表[命令表内位(能力号::生成占位图)] = 命令项(
        能力号::生成占位图,
        "生成占位图\0".as_bytes(),
        "按宽高与占位类型生成 PNG，返回 base64 与尺寸\0".as_bytes(),
        6,
        参数表_生成占位图.as_ptr(),
    );
    本表[命令表内位(能力号::缩放图像)] = 命令项(
        能力号::缩放图像,
        "缩放图像\0".as_bytes(),
        "按目标宽高重采样（Lanczos3），返回 PNG base64\0".as_bytes(),
        3,
        参数表_缩放图像.as_ptr(),
    );
    本表[命令表内位(能力号::转置图像)] = 命令项(
        能力号::转置图像,
        "转置图像\0".as_bytes(),
        "水平翻转、垂直翻转或 90/180/270 度旋转，返回 PNG base64\0".as_bytes(),
        2,
        参数表_转置图像.as_ptr(),
    );
    本表[命令表内位(能力号::合成图像)] = 命令项(
        能力号::合成图像,
        "合成图像\0".as_bytes(),
        "把叠加图按偏移贴在底图上、按 alpha 混合，返回 PNG base64\0".as_bytes(),
        4,
        参数表_合成图像.as_ptr(),
    );
    本表[命令表内位(能力号::重编码图像)] = 命令项(
        能力号::重编码图像,
        "重编码图像\0".as_bytes(),
        "按目标格式重新编码，返回 base64 与尺寸\0".as_bytes(),
        3,
        参数表_重编码图像.as_ptr(),
    );
    本表[命令表内位(能力号::计算图像哈希组)] = 命令项(
        能力号::计算图像哈希组,
        "计算图像哈希组\0".as_bytes(),
        "返回平均哈希、差异哈希与感知哈希的十六进制串\0".as_bytes(),
        1,
        参数表_计算图像哈希组.as_ptr(),
    );
    本表[命令表内位(能力号::转置修正)] = 命令项(
        能力号::转置修正,
        "转置修正\0".as_bytes(),
        "按 EXIF 方向把图像转正后重新编码\0".as_bytes(),
        1,
        参数表_转置修正.as_ptr(),
    );
    本表[命令表内位(能力号::透明背景合成)] = 命令项(
        能力号::透明背景合成,
        "透明背景合成\0".as_bytes(),
        "把透明像素按给定背景色合成成不透明图，返回 PNG base64\0".as_bytes(),
        2,
        参数表_透明背景合成.as_ptr(),
    );
    本表[命令表内位(能力号::判定画面起伏)] = 命令项(
        能力号::判定画面起伏,
        "判定画面起伏\0".as_bytes(),
        "按红绿蓝三通道与亮度的标准差判图像有没有画面起伏，返回各通道标准差、均值与判定依据\0".as_bytes(),
        2,
        参数表_判定画面起伏.as_ptr(),
    );
    本表
}

const _: () = {
    assert!(命令表项数 == 函数表项数);
    assert!(参数个数已核条数 == 命令表项数);
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::分析图像文件)].参数个数 as usize == 参数表_分析图像文件.len());
    assert!(项表[命令表内位(能力号::识别图像格式)].参数个数 as usize == 参数表_识别图像格式.len());
    assert!(项表[命令表内位(能力号::生成占位图)].参数个数 as usize == 参数表_生成占位图.len());
    assert!(项表[命令表内位(能力号::缩放图像)].参数个数 as usize == 参数表_缩放图像.len());
    assert!(项表[命令表内位(能力号::转置图像)].参数个数 as usize == 参数表_转置图像.len());
    assert!(项表[命令表内位(能力号::合成图像)].参数个数 as usize == 参数表_合成图像.len());
    assert!(项表[命令表内位(能力号::重编码图像)].参数个数 as usize == 参数表_重编码图像.len());
    assert!(项表[命令表内位(能力号::计算图像哈希组)].参数个数 as usize == 参数表_计算图像哈希组.len());
    assert!(项表[命令表内位(能力号::转置修正)].参数个数 as usize == 参数表_转置修正.len());
    assert!(项表[命令表内位(能力号::透明背景合成)].参数个数 as usize == 参数表_透明背景合成.len());
    assert!(项表[命令表内位(能力号::判定画面起伏)].参数个数 as usize == 参数表_判定画面起伏.len());
};
