//! 6401 分析图像 · 6402 识别图像格式：像素统计、格式与色彩模式判读。

use image::{DynamicImage, GenericImageView, RgbaImage};

use super::基础件::{b64解码, 格式判定, 拼装, 键值, 键文, 解码字节};

pub(super) fn 模式名(图像: &DynamicImage) -> String {
    // 直接取 ColorType 的调试名：与动态图内部通道一一对应，免去逐个变体匹配。
    format!("{:?}", 图像.color())
}

pub(super) fn 平均颜色(图像: &RgbaImage) -> (u64, u64, u64) {
    let 总数 = u64::from(图像.width()) * u64::from(图像.height());
    if 总数 == 0 {
        return (0, 0, 0);
    }
    let mut 红分量: u64 = 0;
    let mut 绿分量: u64 = 0;
    let mut 蓝分量: u64 = 0;
    for 像素 in 图像.pixels() {
        红分量 += u64::from(像素[0]);
        绿分量 += u64::from(像素[1]);
        蓝分量 += u64::from(像素[2]);
    }
    (红分量 / 总数, 绿分量 / 总数, 蓝分量 / 总数)
}

// ---------------------------------------------------------------- 6401 分析图像

pub(crate) fn 分析图像实现(图像base64: &str) -> Result<String, u32> {
    let 字节 = b64解码(图像base64)?;
    let 图像 = 解码字节(&字节)?;
    let (列宽, 行高) = 图像.dimensions();
    let (红分量, 绿分量, 蓝分量) = 平均颜色(&图像.to_rgba8());
    Ok(拼装(&[
        键文("格式", 格式判定(&字节).as_str()),
        键值("宽度", 列宽),
        键值("高度", 行高),
        键文("模式", &模式名(&图像)),
        键值("像素数", u64::from(列宽) * u64::from(行高)),
        键值(
            "平均颜色",
            拼装(&[键值("红分量", 红分量), 键值("绿分量", 绿分量), 键值("蓝分量", 蓝分量)]),
        ),
        键值("字节数", 字节.len()),
    ]))
}

// ---------------------------------------------------------------- 6402 识别图像格式

pub(crate) fn 识别格式实现(图像base64: &str) -> Result<String, u32> {
    let 字节 = b64解码(图像base64)?;
    let 图像 = 解码字节(&字节)?;
    let (列宽, 行高) = 图像.dimensions();
    Ok(拼装(&[
        键文("格式", 格式判定(&字节).as_str()),
        键值("宽度", 列宽),
        键值("高度", 行高),
        键文("模式", &模式名(&图像)),
    ]))
}
