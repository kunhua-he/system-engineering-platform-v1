//! 6511 判定画面起伏：通道标准差 / 亮度标准差与下限比较。

use crate::编号与码面::错误码;

use super::基础件::{b64解码, 拼装, 键值, 键文, 解码字节};

// ---------------------------------------------------------------- 6511 判定画面起伏

/// 总体方差的数值稳定式：E[x²] − (E[x])²，负数（浮点误差）夹到 0。
pub(super) fn 求通道方差(累计值: f64, 累计平方: f64, 像元计数: f64) -> f64 {
    let 均值 = 累计值 / 像元计数;
    (累计平方 / 像元计数 - 均值 * 均值).max(0.0)
}

pub(crate) fn 判定画面起伏实现(图像base64: &str, 下限文本: &str) -> Result<String, u32> {
    let 下限值 = if 下限文本.trim().is_empty() {
        2.0f64
    } else {
        下限文本.trim().parse::<f64>().map_err(|_| 错误码::参数不合法)?
    };
    if !(0.0..=255.0).contains(&下限值) {
        return Err(错误码::参数不合法);
    }
    let 字节 = b64解码(图像base64)?;
    let 图像 = 解码字节(&字节)?;
    let 画布 = 图像.to_rgba8();
    let (列宽, 行高) = 画布.dimensions();
    let 像元总数 = u64::from(列宽) * u64::from(行高);
    if 像元总数 == 0 {
        return Err(错误码::解码失败);
    }
    // 逐像素两遍统计不需要，但像素上限要有：4000 万像素已够放 4K 图，再大就拒。
    if 像元总数 > 40_000_000 {
        return Err(错误码::尺寸超限);
    }
    let 像元计数 = 像元总数 as f64;
    let (mut 累计红值, mut 累计绿值, mut 累计蓝值, mut 累计亮度) = (0f64, 0f64, 0f64, 0f64);
    let (mut 累计红平方, mut 累计绿平方, mut 累计蓝平方, mut 累计亮度平方) = (0f64, 0f64, 0f64, 0f64);
    for 单像元 in 画布.pixels() {
        let 红值 = f64::from(单像元[0]);
        let 绿值 = f64::from(单像元[1]);
        let 蓝值 = f64::from(单像元[2]);
        let 亮度值 = 0.299 * 红值 + 0.587 * 绿值 + 0.114 * 蓝值;
        累计红值 += 红值;
        累计绿值 += 绿值;
        累计蓝值 += 蓝值;
        累计亮度 += 亮度值;
        累计红平方 += 红值 * 红值;
        累计绿平方 += 绿值 * 绿值;
        累计蓝平方 += 蓝值 * 蓝值;
        累计亮度平方 += 亮度值 * 亮度值;
    }
    let 红标准差 = 求通道方差(累计红值, 累计红平方, 像元计数).sqrt();
    let 绿标准差 = 求通道方差(累计绿值, 累计绿平方, 像元计数).sqrt();
    let 蓝标准差 = 求通道方差(累计蓝值, 累计蓝平方, 像元计数).sqrt();
    let 亮度标准差 = 求通道方差(累计亮度, 累计亮度平方, 像元计数).sqrt();
    let 通道最大 = 红标准差.max(绿标准差).max(蓝标准差);
    // 任一通道或亮度达标即算有起伏：纯色图三通道与亮度都接近 0；
    // 只有彩色分块的图亮度可能平但通道有起伏，只看亮度会漏。
    let 有起伏 = 通道最大 >= 下限值 || 亮度标准差 >= 下限值;
    let 判定依据 = format!(
        "通道最大标准差{:.2} 亮度标准差{:.2} 下限{:.2}",
        通道最大, 亮度标准差, 下限值
    );
    Ok(拼装(&[
        键值("有起伏", 有起伏),
        键文("判定依据", 判定依据.as_str()),
        键值("标准差下限", format!("{:.2}", 下限值)),
        键值("像素总数", 像元总数),
        键值("通道标准差", 拼装(&[
            键值("红", format!("{:.4}", 红标准差)),
            键值("绿", format!("{:.4}", 绿标准差)),
            键值("蓝", format!("{:.4}", 蓝标准差)),
            键值("亮度", format!("{:.4}", 亮度标准差)),
        ])),
        键值("通道均值", 拼装(&[
            键值("红", format!("{:.4}", 累计红值 / 像元计数)),
            键值("绿", format!("{:.4}", 累计绿值 / 像元计数)),
            键值("蓝", format!("{:.4}", 累计蓝值 / 像元计数)),
            键值("亮度", format!("{:.4}", 累计亮度 / 像元计数)),
        ])),
    ]))
}
