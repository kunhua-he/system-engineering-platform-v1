/// 逐条断言：参数个数必须等于对应参数表的项数。const 求值不许比指针，所以只能逐条列名。
pub const fn 核参数个数(项表: &[命令信息; 命令表项数]) {
    assert!(
        项表[命令表内位(能力号::渲染组件树)].参数个数 as usize == 参数表_渲染组件树.len(),
        "③h：4928 的 参数个数 与 参数表_渲染组件树 项数不符"
    );
    assert!(
        项表[命令表内位(能力号::操作组件)].参数个数 as usize == 参数表_操作组件.len(),
        "③h：4929 的 参数个数 与 参数表_操作组件 项数不符"
    );
    assert!(
        项表[命令表内位(能力号::读组件状态)].参数个数 as usize == 参数表_读组件状态.len(),
        "③h：4930 的 参数个数 与 参数表_读组件状态 项数不符"
    );
    assert!(
        项表[命令表内位(能力号::释放组件句柄)].参数个数 as usize == 参数表_释放组件句柄.len(),
        "③h：4931 的 参数个数 与 参数表_释放组件句柄 项数不符"
    );
    assert!(
        参数个数已核条数 == 项表.len(),
        "③h：已核条数 与 命令表项数 不符 —— 加了命令没加断言"
    );
}
