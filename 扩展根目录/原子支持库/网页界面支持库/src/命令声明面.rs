use v1_contract::{参数信息, 命令信息, 数据槽, 表段};

use crate::编号与码面::能力号;

pub const 命令表项数: usize = 1;
pub const 函数表项数: usize = 1;
pub const 参数个数已核条数: usize = 1;
pub const 命令表首号: u32 = 能力号::渲染组件树;

pub const fn 命令表内位(编号: u32) -> usize {
    assert!(
        编号 >= 命令表首号 && (编号 - 命令表首号) < 命令表项数 as u32,
        "编号不在本扩展的命令表内"
    );
    (编号 - 命令表首号) as usize
}

pub const fn 命令项(
    编号: u32,
    名称: &'static [u8],
    描述: &'static [u8],
    返回类型: v1_contract::类型标签,
    参数个数: u32,
    参数表: *const 参数信息,
    可抛错误码: 表段<u32>,
) -> 命令信息 {
    命令信息 {
        名称: 名称.as_ptr(),
        说明: 描述.as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型,
        用户级别: 0,
        参数个数,
        参数表,
        编号: v1_contract::能力号::构造(编号),
        可抛错误码: 表段::构造(
            可抛错误码.项表 as *const v1_contract::错误码,
            可抛错误码.表项数,
        ),
    }
}

pub const 参数表_渲染组件树: [参数信息; 1] = [参数信息 {
    名称: "树定义原文\0".as_bytes().as_ptr(),
    说明: "树定义原文\0".as_bytes().as_ptr(),
    类型标签: v1_contract::类型标签::构造(4),
    状态位: 0,
    默认值: 数据槽::空槽(),
}];
pub const 可抛错误码_界面: [u32; 3] = [4921, 4922, 4923];

pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [命令信息 {
        名称: "空位种子\0".as_bytes().as_ptr(),
        说明: "命令表的空位种子：表内每一位都该被覆写。\0".as_bytes().as_ptr(),
        类别号: 0,
        状态位: 0,
        返回类型: v1_contract::类型标签::构造(0),
        用户级别: 0,
        参数个数: 0,
        参数表: core::ptr::null(),
        编号: v1_contract::能力号::构造(0),
        可抛错误码: 表段::空实例(),
    }; 命令表项数];
    本表[命令表内位(能力号::渲染组件树)] = 命令项(
        能力号::渲染组件树,
        "渲染组件树\0".as_bytes(),
        "把一棵可递归嵌套的组件树渲染成HTML片段或整页：容器（行、列、网格、侧栏、分区、画布）任意嵌套，叶子出标题、文字、图标、表格、表单、输入框、按钮、聊天流与原生片段；悬浮层与任何节点都能声明切换显隐（可带快捷键），整页模式按需附通用脚本；表单容器与图标地址只认同源；颜色与背景按白名单校验\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        1,
        参数表_渲染组件树.as_ptr(),
        表段::构造(可抛错误码_界面.as_ptr(), 可抛错误码_界面.len() as u32),
    );
    本表
}
const _: () = {
    assert!(命令表项数 == 函数表项数);
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::渲染组件树)].参数个数 as usize == 参数表_渲染组件树.len());
    assert!(参数个数已核条数 == 项表.len());
};
