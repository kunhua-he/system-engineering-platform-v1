//! 超级列表框的边界与交互状态回归，全部调用正式组件入口。
use crate::{组件实例, 组件操作, 组件树};
use serde_json::{Value, json};

fn 建立验收表格(表格声明: Value) -> u64 {
    let (_, 页面字节) = 组件树::渲染组件树(&json!({"根":表格声明}).to_string())
        .unwrap_or_else(|码| panic!("渲染失败 码={码} 声明={表格声明}"));
    let 页面正文 = String::from_utf8(页面字节).unwrap();
    页面正文
        .split("data-hs-h=\"")
        .nth(1)
        .unwrap()
        .split('"')
        .next()
        .unwrap()
        .parse()
        .unwrap()
}
fn 执行验收操作(
    组件句柄: u64,
    操作名称: &str,
    操作参数: Value,
) -> Result<(u32, Vec<u8>), u32> {
    组件操作::操作组件(组件句柄, 操作名称, &操作参数.to_string())
}

