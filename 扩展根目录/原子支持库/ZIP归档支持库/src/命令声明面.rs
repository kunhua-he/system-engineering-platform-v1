pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::列出成员)] = 命令项(能力号::列出成员, "列出成员\0".as_bytes(), "ZIP字节归档：列出成员、读取指定成员和生成单成员归档；不写文件系统，不接受绝对成员路径或上跳路径；最多1000成员，压缩输入输出65536字节，成员实际解压65536字节；支持Stored和Deflate，拒绝损坏或不可支持的加密。\0".as_bytes(), v1_contract::类型标签::构造(100), 1, 参数表_列出成员.as_ptr(), 表段::构造(可抛错误码_文本.as_ptr(), 可抛错误码_文本.len() as u32));
    本表[命令表内位(能力号::读取成员)] = 命令项(能力号::读取成员, "读取成员\0".as_bytes(), "ZIP字节归档：列出成员、读取指定成员和生成单成员归档；不写文件系统，不接受绝对成员路径或上跳路径；最多1000成员，压缩输入输出65536字节，成员实际解压65536字节；支持Stored和Deflate，拒绝损坏或不可支持的加密。\0".as_bytes(), v1_contract::类型标签::构造(5), 2, 参数表_读取成员.as_ptr(), 表段::构造(可抛错误码_文本.as_ptr(), 可抛错误码_文本.len() as u32));
    本表[命令表内位(能力号::生成单成员)] = 命令项(能力号::生成单成员, "生成单成员\0".as_bytes(), "ZIP字节归档：列出成员、读取指定成员和生成单成员归档；不写文件系统，不接受绝对成员路径或上跳路径；最多1000成员，压缩输入输出65536字节，成员实际解压65536字节；支持Stored和Deflate，拒绝损坏或不可支持的加密。\0".as_bytes(), v1_contract::类型标签::构造(5), 2, 参数表_生成单成员.as_ptr(), 表段::构造(可抛错误码_文本.as_ptr(), 可抛错误码_文本.len() as u32));
    本表
}
const _: () = { assert!(命令表项数 == 函数表项数); let 项表 = 造命令表();
assert!(项表[命令表内位(能力号::列出成员)].参数个数 as usize == 参数表_列出成员.len());
assert!(项表[命令表内位(能力号::读取成员)].参数个数 as usize == 参数表_读取成员.len());
assert!(项表[命令表内位(能力号::生成单成员)].参数个数 as usize == 参数表_生成单成员.len());
assert!(参数个数已核条数 == 项表.len()); };
