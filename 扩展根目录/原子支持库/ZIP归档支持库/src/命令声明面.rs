pub const 参数表_生成单成员: [参数信息; 2] = [参数信息 { 名称: "成员路径\0".as_bytes().as_ptr(), 说明: "成员路径\0".as_bytes().as_ptr(), 类型标签: v1_contract::类型标签::构造(4), 状态位: 0, 默认值: 数据槽::空槽() },参数信息 { 名称: "成员内容\0".as_bytes().as_ptr(), 说明: "成员内容\0".as_bytes().as_ptr(), 类型标签: v1_contract::类型标签::构造(5), 状态位: 0, 默认值: 数据槽::空槽() }];
pub const 可抛错误码_文本: [u32; 3] = [3401, 3402, 3403];
