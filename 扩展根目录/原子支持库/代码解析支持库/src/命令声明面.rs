pub const fn 造命令表() -> [命令信息; 命令表项数] {
    let mut 本表 = [空位种子; 命令表项数];
    本表[命令表内位(能力号::解码文本)] = 命令项(
        能力号::解码文本,
        "解码文本\0".as_bytes(),
        "按显式编码把字节解成文本：BOM存在时以BOM为准并如实回报实际编码；不允许静默替换，解不了就报错。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        2,
        参数表_解码文本.as_ptr(),
        表段::构造(可抛错误码_解码.as_ptr(), 3),
    );
    本表[命令表内位(能力号::载入切块规则)] = 命令项(
        能力号::载入切块规则,
        "载入切块规则\0".as_bytes(),
        "读切块规则JSON文件并校验；同路径命中缓存且文件未变直接返回，强制重载非0时强制重读；失败不覆盖已有缓存。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        2,
        参数表_载入切块规则.as_ptr(),
        表段::构造(可抛错误码_载入.as_ptr(), 2),
    );
    本表[命令表内位(能力号::重载切块规则)] = 命令项(
        能力号::重载切块规则,
        "重载切块规则\0".as_bytes(),
        "无视缓存重读切块规则JSON文件并校验后返回。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        1,
        参数表_重载切块规则.as_ptr(),
        表段::构造(可抛错误码_载入.as_ptr(), 2),
    );
    本表[命令表内位(能力号::按规则切块)] = 命令项(
        能力号::按规则切块,
        "按规则切块\0".as_bytes(),
        "按规则JSON把源码文本切成块：切分模式 regex 按单元模式行锚定切块、python_ast 同 regex 锚定、html 按空行与标签边界分块；注释与字符串区间不切；返回 块列表（块类型／文本／行起始／行结束）与单元数，文本逐一拼接可还原原文。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        3,
        参数表_按规则切块.as_ptr(),
        表段::构造(可抛错误码_切块.as_ptr(), 2),
    );
    本表[命令表内位(能力号::解析代码字节)] = 命令项(
        能力号::解析代码字节,
        "解析代码字节\0".as_bytes(),
        "解码字节后按内置规则切块：返回 格式化／编码／块列表／资源列表（恒空表，占位给消费方）；文件格式不在支持清单报 参数不合法。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        3,
        参数表_解析代码字节.as_ptr(),
        表段::构造(可抛错误码_解析.as_ptr(), 4),
    );
    本表[命令表内位(能力号::解析代码文件)] = 命令项(
        能力号::解析代码文件,
        "解析代码文件\0".as_bytes(),
        "只读读取源码文件后按内置规则切块；文件至1MiB；返回与 解析代码字节 同构。\0".as_bytes(),
        v1_contract::类型标签::构造(4),
        3,
        参数表_解析代码文件.as_ptr(),
        表段::构造(可抛错误码_解析.as_ptr(), 4),
    );
    本表
}

const _: () = {
    let 项表 = 造命令表();
    assert!(项表[命令表内位(能力号::解码文本)].参数个数 as usize == 参数表_解码文本.len());
    assert!(项表[命令表内位(能力号::载入切块规则)].参数个数 as usize == 参数表_载入切块规则.len());
    assert!(项表[命令表内位(能力号::重载切块规则)].参数个数 as usize == 参数表_重载切块规则.len());
    assert!(项表[命令表内位(能力号::按规则切块)].参数个数 as usize == 参数表_按规则切块.len());
    assert!(项表[命令表内位(能力号::解析代码字节)].参数个数 as usize == 参数表_解析代码字节.len());
    assert!(项表[命令表内位(能力号::解析代码文件)].参数个数 as usize == 参数表_解析代码文件.len());
    assert!(参数个数已核条数 == 项表.len());
};
