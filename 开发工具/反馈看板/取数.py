def 时刻串() -> str:
    """当前时刻（本地时区 ISO8601）。"""
    return datetime.datetime.now().astimezone().strftime("%Y-%m-%dT%H:%M:%S%z")


def 截断(原文本, 宽度: int = 截断宽度) -> str:
    """单行短文本（去换行 + 截断加省略号）—— 页面列不许撑爆。"""
    净文本 = " ".join(str(原文本 or "").split())
    return 净文本 if len(净文本) <= 宽度 else 净文本[:宽度] + "…"


