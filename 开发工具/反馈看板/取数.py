def 库版本(路径: Path) -> dict:
    """库件版本读数（字节 · 修改时刻）—— 前端据它判陈旧。件不在 ⇒ 空字典。"""
    try:
        状态 = 路径.stat()
    except OSError:
        return {}
    return {"字节": 状态.st_size, "修改时刻": int(状态.st_mtime)}


def 连只读库(路径: Path) -> sqlite3.Connection:
    """只读连接（`mode=ro` URI）—— 物理上写不进，也不建表。"""
    连接 = sqlite3.connect("file:%s?mode=ro" % 路径, uri=True, isolation_level=None)
    连接.row_factory = sqlite3.Row
    return 连接


def 读台账(仓根目录: Path, 台账件=None) -> tuple:
    """台账现量（库 `未完成` 表）⇒ `(号集, 缺什么表, 错误或 None)`。库不在 / 读不动 ⇒ 错误（调用方判陈旧）。"""
    台账库路径 = Path(台账件) if 台账件 else Path(仓根目录).joinpath(*台账相对路径)
    if not 台账库路径.is_file():
        return set(), {}, "台账件不在：%s" % 台账库路径
    try:
        连接 = 连只读库(台账库路径)
        try:
            行表 = 连接.execute("select 号, 缺什么 from 未完成").fetchall()
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return set(), {}, "台账读不动：%s" % 错误
    号集, 缺什么表 = set(), {}
    for 台账行 in 行表:
        if isinstance(台账行["号"], int):
            号集.add(台账行["号"])
            缺什么表[台账行["号"]] = str(台账行["缺什么"] or "")
    return 号集, 缺什么表, None


def 读总览(连接) -> dict:
    """六表现量 + 债务数（一次读事务内取，同快照）。"""
    读数 = {}
    for 表名, 键名 in (("反馈来源", "来源"), ("反馈条目", "条目"), ("反馈判词", "判词"),
                    ("反馈证据", "证据"), ("反馈关闭", "关闭")):
        读数[键名] = 连接.execute("select count(*) from %s" % 表名).fetchone()[0]
    读数["债务"] = 连接.execute("select count(*) from 反馈判词 where 判词 = ?",
                            (判词档表[0],)).fetchone()[0]
    读数["已关闭"] = 连接.execute(
        "select count(*) from 反馈关闭 c join 反馈判词 p on p.条目号 = c.条目号 where p.判词 = ?",
        (判词档表[0],)).fetchone()[0]
    读数["未关闭"] = 读数["债务"] - 读数["已关闭"]
    return 读数


def 读筛选行(连接) -> list:
    """全部条目的**轻量**筛选面（有效判词 = 本条目判词，否则并入主条目的判词）。"""
    行表 = 连接.execute(
        "select e.条目号, e.来源号, e.并入主条目, "
        "coalesce(p.判词, p2.判词) as 判词, "
        "coalesce(p.关联种类, p2.关联种类) as 关联种类, "
        "coalesce(p.关联目标, p2.关联目标) as 关联目标, "
        "coalesce(p.关联状态, p2.关联状态) as 关联状态, "
        "(select count(*) from 反馈关闭 c where c.条目号 = e.条目号) as 关闭数 "
        "from 反馈条目 e join 反馈来源 s on s.来源号 = e.来源号 "
        "left join 反馈判词 p on p.条目号 = e.条目号 "
        "left join 反馈判词 p2 on p2.条目号 = e.并入主条目").fetchall()
    return [dict(数据行) for 数据行 in 行表]


def 读开工表(连接) -> dict:
    """`{开工号: {工作内容, 状态}}` —— 承接任务那一列的读数。"""
    return {数据行["开工号"]: {"工作内容": 数据行["工作内容"], "状态": 数据行["状态"]}
            for 数据行 in 连接.execute("select 开工号, 工作内容, 状态 from 开工")}


def 判承接(关联种类, 关联目标, 关联状态, 台账号集, 开工表) -> bool:
    """承接是否有效：关联状态现行 且 目标解析到现行台账条目 / 正式开工。未知即假（fail-closed）。"""
    if str(关联状态 or "") != 关联状态_现行:
        return False
    目标值 = str(关联目标 or "").strip()
    if not 目标值:
        return False
    if 关联种类 == 关联_台账:
        try:
            return int(目标值) in 台账号集
        except (TypeError, ValueError):
            return False
    if 关联种类 == 关联_开工:
        return 目标值 in 开工表
    return False


def 规范化(参数表: dict) -> tuple:
    """筛选 / 分页参数 ⇒ `(页码, 每页, 判词筛, 任务筛, 来源筛, 组筛)`（越界即夹回，不报错）。"""
    页码 = 参数表.get("页码")
    页码 = 页码 if isinstance(页码, int) and 页码 >= 1 else 1
    每页 = 参数表.get("每页")
    每页 = 每页 if isinstance(每页, int) and 1 <= 每页 <= 每页上限 else 默认每页
    判词筛 = str(参数表.get("判词") or 判词档表[0]).strip()
    if 判词筛 not in 判词档表 + (筛选_全部,):
        判词筛 = 判词档表[0]
    return (页码, 每页, 判词筛, str(参数表.get("任务") or "").strip(),
            str(参数表.get("来源") or "").strip(), str(参数表.get("组") or "").strip())


def 算组键(数据行: dict, 承接有效: bool) -> str:
    if 数据行.get("关闭数"):
        return 组_已关闭
    return "%s|%s" % (数据行["关联种类"], 数据行["关联目标"]) if 承接有效 else 组_缺关联


def 任务面(数据行: dict, 承接有效: bool, 缺什么表: dict, 开工表: dict) -> str:
    """任务筛选的可搜面：关联种类 + 目标 + 台账缺什么 / 开工工作内容。"""
    if not 承接有效:
        return "缺关联"
    目标值 = str(数据行["关联目标"])
    if 数据行["关联种类"] == 关联_台账:
        return "%s %s %s" % (关联_台账, 目标值, 缺什么表.get(int(目标值), "") if 目标值.isdigit() else "")
    if 数据行["关联种类"] == 关联_开工:
        return "%s %s %s" % (关联_开工, 目标值, (开工表.get(目标值) or {}).get("工作内容", ""))
    return 目标值


def 筛行(行表: list, 台账号集: set, 缺什么表: dict, 开工表: dict,
        判词筛: str, 任务筛: str, 来源筛: str, 组筛: str) -> list:
    """⇒ `[(数据行, 承接有效, 组键)]`（按判词 / 任务 / 来源 / 组四档筛；判词「全部」= 已判词的都收）。"""
    保留 = []
    for 数据行 in 行表:
        if not 数据行["判词"]:
            continue
        if 判词筛 != 筛选_全部 and 数据行["判词"] != 判词筛:
            continue
        承接有效 = 判承接(数据行["关联种类"], 数据行["关联目标"], 数据行["关联状态"], 台账号集, 开工表)
        组键值 = 算组键(数据行, 承接有效)
        if 组筛 and 组键值 != 组筛:
            continue
        if 任务筛 and 任务筛 not in 任务面(数据行, 承接有效, 缺什么表, 开工表):
            continue
        if 来源筛:
            if 来源筛.isdigit():
                if str(数据行["来源号"]) != 来源筛:
                    continue
            elif 来源筛 not in str(数据行.get("来源标识") or ""):
                continue
        保留.append((数据行, 承接有效, 组键值))
    return 保留


def 组摘要(保留: list, 缺什么表: dict, 开工表: dict) -> list:
    """按组键聚合成资料组摘要（条数降序；缺关联殿后）。"""
    组表 = {}
    for 数据行, 承接有效, 组键值 in 保留:
        资料组 = 组表.setdefault(组键值, {"组键": 组键值, "承接有效": 承接有效,
                                "已关闭": 组键值 == 组_已关闭,
                                "关联种类": 数据行["关联种类"], "关联目标": 数据行["关联目标"],
                                "关联状态": 数据行["关联状态"], "条数": 0})
        资料组["条数"] += 1
    for 资料组 in 组表.values():
        资料组["组名"] = 组名(资料组, 缺什么表, 开工表)
    return sorted(组表.values(), key=lambda 资料组: (资料组["组键"] in (组_缺关联, 组_已关闭),
                                                  -资料组["条数"], 资料组["组键"]))


def 组名(资料组: dict, 缺什么表: dict, 开工表: dict) -> str:
    if 资料组["组键"] == 组_已关闭:
        return 组_已关闭名
    if 资料组["组键"] == 组_缺关联:
        return 组_缺关联名
    目标值 = str(资料组["关联目标"])
    if 资料组["关联种类"] == 关联_台账:
        return "台账#%s %s" % (目标值, 截断(缺什么表.get(int(目标值), "") if 目标值.isdigit() else "", 80))
    if 资料组["关联种类"] == 关联_开工:
        return "%s %s" % (目标值, 截断((开工表.get(目标值) or {}).get("工作内容", ""), 80))
    return 目标值


def 核验文本(数据行: dict, 承接有效: bool, 关闭行: dict, 开工表: dict) -> str:
    """关闭 / 已合 / 已提交的**显式**读数 —— 缺证据即「未知」，不按祖先推定。"""
    if 关闭行:
        return "已关闭（提交 %s · 退出码 %s）" % (str(关闭行.get("承接提交") or "?")[:12], 关闭行.get("退出码"))
    if not 承接有效:
        return "未知：无有效承接（不按祖先推定已合 / 已提交）"
    if 数据行["关联种类"] == 关联_开工:
        状态值 = (开工表.get(str(数据行["关联目标"])) or {}).get("状态")
        if 状态值 == 状态_已释放:
            return "未知：开工已释放，未核是否已合主干"
        if 状态值 == 状态_待合并:
            return "未提交：待合主干"
        return "进行中：未提交"
    return "未关闭（关联现行台账条目）"


def 取明细(连接, 页行: list) -> list:
    """本页条目的**全字段**读数（含来源 / 判词 / 关闭），按页序返回。"""
    号表 = [数据行["条目号"] for 数据行, 有效值, 组键值 in 页行]
    if not 号表:
        return []
    占位符 = ",".join("?" * len(号表))
    明细表 = 连接.execute(
        "select e.条目号, e.现象, e.落点, e.并入主条目, e.证据, e.未测, e.登记时刻, "
        "s.来源号, s.来源标识, s.内容指纹, s.报告路径, s.读取状态, s.审完时刻, "
        "coalesce(p.判词, p2.判词) as 判词, coalesce(p.理由, p2.理由) as 理由, "
        "coalesce(p.关联种类, p2.关联种类) as 关联种类, "
        "coalesce(p.关联目标, p2.关联目标) as 关联目标, "
        "coalesce(p.关联状态, p2.关联状态) as 关联状态, "
        "c.承接提交, c.验证命令, c.退出码 "
        "from 反馈条目 e join 反馈来源 s on s.来源号 = e.来源号 "
        "left join 反馈判词 p on p.条目号 = e.条目号 "
        "left join 反馈判词 p2 on p2.条目号 = e.并入主条目 "
        "left join 反馈关闭 c on c.条目号 = e.条目号 "
        "where e.条目号 in (%s)" % 占位符, 号表).fetchall()
    按号 = {数据行["条目号"]: dict(数据行) for 数据行 in 明细表}
    return [按号[数据行["条目号"]] for 数据行, 有效值, 组键值 in 页行 if 数据行["条目号"] in 按号]


def 条目读数(明细: dict, 承接有效: bool, 组键值: str, 开工表: dict) -> dict:
    """一条明细 ⇒ 页面一行的全部列。"""
    关闭行 = {"承接提交": 明细.get("承接提交"), "退出码": 明细.get("退出码")} if 明细.get("承接提交") else None
    承接文本 = "—"
    if 承接有效 and 明细["关联种类"] == 关联_台账:
        承接文本 = "台账#%s" % 明细["关联目标"]
    elif 承接有效 and 明细["关联种类"] == 关联_开工:
        承接文本 = "%s %s" % (明细["关联目标"],
                         截断((开工表.get(str(明细["关联目标"])) or {}).get("工作内容", ""), 60))
    return {"条目号": 明细["条目号"], "来源号": 明细["来源号"], "来源标识": 明细["来源标识"],
            "报告指纹": (明细["内容指纹"] or "")[:16], "报告指纹全": 明细["内容指纹"],
            "报告路径": 明细["报告路径"], "读取状态": 明细["读取状态"],
            "审完": bool(明细["审完时刻"]), "现象": 截断(明细["现象"]), "落点": 截断(明细["落点"], 120),
            "判词": 明细["判词"], "理由": 截断(明细["理由"], 120),
            "并入主条目": 明细["并入主条目"], "承接任务": 承接文本,
            "关联种类": 明细["关联种类"], "关联目标": 明细["关联目标"], "关联状态": 明细["关联状态"],
            "承接有效": 承接有效, "组键": 组键值, "关闭提交": (明细.get("承接提交") or "未关闭"),
            "核验": 核验文本(明细, 承接有效, 关闭行, 开工表), "登记时刻": 明细["登记时刻"]}


def 取数(仓根目录: Path, 参数表: dict, 库件=None, 台账件=None) -> dict:
    """一次刷新 ⇒ 结构化载荷。**只读**；读不动 ⇒ 陈旧 + 错误，**不假装新鲜**。"""
    生成时刻 = 时刻串()
    路径 = Path(库件) if 库件 else 库路径()
    版本 = 库版本(路径)
    台账号集, 缺什么表, 台账错 = 读台账(仓根目录, 台账件)
    错误表 = [台账错] if 台账错 else []
    载荷 = {"生成时刻": 生成时刻, "库版本": 版本, "库件": str(路径),
           "陈旧": bool(错误表), "错误": 错误表 or None,
           "台账": {"现量": len(台账号集), "号表": sorted(台账号集),
                  "件": str(台账件 or Path(仓根目录).joinpath(*台账相对路径))},
           "总览": {}, "组": [], "条目": [], "口径": 口径文本,
           "分页": {"页码": 1, "每页": 默认每页, "总数": 0, "总页": 0}}
    连接 = None
    try:
        连接 = 连只读库(路径)
        连接.execute("BEGIN")
        载荷["总览"] = 读总览(连接)
        行表 = 读筛选行(连接)
        开工表 = 读开工表(连接)
        页码, 每页, 判词筛, 任务筛, 来源筛, 组筛 = 规范化(参数表)
        保留 = 筛行(行表, 台账号集, 缺什么表, 开工表, 判词筛, 任务筛, 来源筛, 组筛)
        总数 = len(保留)
        总页 = (总数 + 每页 - 1) // 每页
        起始位 = (页码 - 1) * 每页
        页行 = 保留[起始位:起始位 + 每页]
        明细表 = 取明细(连接, 页行)
        有效表 = {数据行["条目号"]: (有效值, 组键值) for 数据行, 有效值, 组键值 in 页行}
        载荷["组"] = 组摘要(保留, 缺什么表, 开工表)
        载荷["条目"] = [条目读数(明细, 有效表[明细["条目号"]][0], 有效表[明细["条目号"]][1], 开工表)
                    for 明细 in 明细表]
        载荷["分页"] = {"页码": 页码, "每页": 每页, "总数": 总数, "总页": 总页}
        载荷["筛选"] = {"判词": 判词筛, "任务": 任务筛, "来源": 来源筛, "组": 组筛}
        连接.rollback()
    except sqlite3.Error as 错误:
        载荷["陈旧"] = True
        载荷["错误"] = (载荷["错误"] or []) + ["库读不动：%s" % 错误]
    finally:
        if 连接 is not None:
            连接.close()
    return 载荷
