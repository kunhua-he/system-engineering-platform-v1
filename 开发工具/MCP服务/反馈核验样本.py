# -*- coding: utf-8 -*-
"""反馈核验样本 —— 未蒸馏判据逐条（未审完 / 未判词 / 债务无承接 / 待核有对象）+ 空报告 / 缺件 + 重启 / 迁移。

**为什么单开一件**（判据 ⑲ 单件 ≤400 行）：这一档全是「拒清语义」的逐条反证（含直接改库模拟陈旧承接），
与 `反馈样本.py` 的正路不是同一条关注点。
"""

import json
