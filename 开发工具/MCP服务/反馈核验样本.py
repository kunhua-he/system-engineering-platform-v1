from pathlib import Path

from 运行数据根.口径 import 覆盖变量名

from .反馈样本工具 import 反馈表集, 核验开工号, 空字节指纹, 读回执, 取台账号, 造夹具仓根
from . import 清树门禁


def 核验开工样本(仓根) -> list:
    """核验开工：未审完 / 未判词 / 债务无有效承接 / 待核有对象 / 空报告 / 缺件 ⇒ 逐条。"""
    from . import 开工账本
    from . import 反馈账本 as 账本
    from . import 反馈关联
    from .反馈提交 import 提交反馈, 补证
    from .反馈判词 import 批量判定
    from .反馈审完 import 登记报告审完
    # 夹具仓根：债务承接的台账那一支读的是**调用方给的仓根**下的 `未完成` 表 ——
    # 真仓台账核销到 0 行后，债务正例必被判「未知台账条目」⇒ 陈旧承接样本也就无对象可核。
    仓根 = 造夹具仓根(os.environ[覆盖变量名])
    现存号, _无此号 = 取台账号(仓根)
    样本表 = []

    def 记样本(说明, 通过):
        样本表.append((说明, bool(通过)))

    退出码, 回执文本 = 提交反馈(仓根, 核验开工号, {
        "幂等键": "核验-001", "来源标识": "agent-y/报告.md", "报告指纹": "ef" * 16,
        "条目": [{"现象": "待核类发现", "证据": "读数 Y", "未测": "落点与触发未记录"}]})
    来源号 = 读回执(回执文本).get("来源号")
    连接 = 账本.连反馈库()
    try:
        未蒸馏 = 反馈关联.未蒸馏反馈集(连接, 仓根, 核验开工号)
    finally:
        连接.close()
    记样本("未蒸馏：来源未审完（未读）+ 条目未判词 ⇒ 非空（%d 条 · 提交码 %s）"
       % (len(未蒸馏), 退出码), 退出码 == 0 and len(未蒸馏) == 2)

    来源条目号 = (读回执(回执文本).get("条目号") or [None])[0]
    批量判定(仓根, 核验开工号, {"判定表": [{"条目号": 来源条目号, "判词": "待核",
                                        "理由": "待补证据"}]})
    登记报告审完(仓根, 核验开工号, {"来源号": 来源号, "提取条数": 1, "判词条数": 1})
    连接 = 账本.连反馈库()
    try:
        未蒸馏 = 反馈关联.未蒸馏反馈集(连接, 仓根, 核验开工号)
    finally:
        连接.close()
    记样本("待核**无具体保留对象** ⇒ **不**阻断原树清理（未蒸馏 %d 条）" % len(未蒸馏),
      未蒸馏 == [])

    补证(仓根, 核验开工号, {"补证表": [{"条目号": 来源条目号, "证据": "补：现场截图路径 …"}]})
    连接 = 账本.连反馈库()
    try:
        未蒸馏 = 反馈关联.未蒸馏反馈集(连接, 仓根, 核验开工号)
    finally:
        连接.close()
    记样本("待核**带具体保留对象**（补证）⇒ 拒清：%s" % (未蒸馏[:1],), len(未蒸馏) == 1)

    退出码, 回执文本 = 提交反馈(仓根, 核验开工号, {
        "幂等键": "核验-002", "来源标识": "agent-y/空报告.md", "报告指纹": 空字节指纹,
        "读取状态": "空报告待核", "条目": []})
    空来源号 = 读回执(回执文本).get("来源号")
    记样本("空报告（空字节 sha256）可登记 ⇒ 码 %s · 来源号 %s" % (退出码, 空来源号),
      退出码 == 0 and isinstance(空来源号, int))
    退出码, _回执文本 = 提交反馈(仓根, 核验开工号, {
        "幂等键": "核验-007", "来源标识": "agent-y/假空报告.md", "报告指纹": "22" * 16,
        "读取状态": "空报告待核", "条目": []})
    记样本("空报告待核但指纹**不是空字节 sha256**（形状对 · 身份不对）⇒ 拒（码 %s）" % 退出码,
      退出码 == 2)
    退出码, _回执文本 = 登记报告审完(仓根, 核验开工号, {"来源号": 空来源号, "提取条数": 0,
                                      "判词条数": 0})
    记样本("空报告（待核）无 `待核理由` ⇒ 不能假审完（码 %s）" % 退出码, 退出码 == 2)
    退出码, 回执文本 = 登记报告审完(仓根, 核验开工号, {
        "来源号": 空来源号, "提取条数": 0, "判词条数": 0, "待核理由": "报告只有标题，无发现"})
    记样本("空报告落**显式待核**（审完 %s · 待核 %s）⇒ 码 %s"
       % (读回执(回执文本).get("审完"), 读回执(回执文本).get("待核"), 退出码),
      退出码 == 0 and 读回执(回执文本).get("审完") is False
      and 读回执(回执文本).get("待核") is True)

    退出码, 回执文本 = 提交反馈(仓根, 核验开工号, {
        "幂等键": "核验-003", "来源标识": "agent-y/已读空报告.md", "报告指纹": 空字节指纹,
        "读取状态": "已读", "条目": []})
    已读空来源号 = 读回执(回执文本).get("来源号")
    退出码, 回执文本 = 登记报告审完(仓根, 核验开工号, {"来源号": 已读空来源号, "提取条数": 0,
                                      "判词条数": 0})
    记样本("**已读空报告** ⇒ 提取 = 判词 = 0 地审完（码 %s · 审完 %s）"
       % (退出码, 读回执(回执文本).get("审完")),
      退出码 == 0 and 读回执(回执文本).get("审完") is True)

    退出码, 回执文本 = 提交反馈(仓根, 核验开工号, {
        "幂等键": "核验-004", "来源标识": "agent-y/缺件.md", "读取状态": "缺件待核", "条目": []})
    缺件来源号 = 读回执(回执文本).get("来源号")
    连接 = 账本.连反馈库()
    try:
        缺件指纹 = (账本.读来源(连接, 缺件来源号) or {}).get("内容指纹")
    finally:
        连接.close()
    记样本("缺件待核可留空 `报告指纹` ⇒ 内容指纹占位 %s（明确无内容身份）" % 缺件指纹,
      退出码 == 0 and 缺件指纹 == 账本.缺件指纹标记)
    退出码, 回执文本 = 提交反馈(仓根, 核验开工号, {
        "幂等键": "核验-005", "来源标识": "agent-y/缺件.md", "报告指纹": "78" * 16,
        "条目": [{"现象": "缺件补上后才发现", "证据": "读数 W", "未测": "落点未定位"}]})
    新来源号 = 读回执(回执文本).get("来源号")
    记样本("缺件发现输出后新 sha = **新来源**（不覆盖旧记录）：%s → %s"
       % (缺件来源号, 新来源号),
      退出码 == 0 and isinstance(新来源号, int) and 新来源号 != 缺件来源号)

    退出码, 回执文本 = 提交反馈(仓根, 核验开工号, {
        "幂等键": "核验-006", "来源标识": "agent-y/陈旧.md", "报告指纹": "56" * 16,
        "条目": [{"现象": "陈旧承接测试", "证据": "读数 Z", "未测": "落点未定位"}]})
    陈旧来源号 = 读回执(回执文本).get("来源号")
    陈旧条目号 = (读回执(回执文本).get("条目号") or [None])[0]
    批量判定(仓根, 核验开工号, {"判定表": [{"条目号": 陈旧条目号, "判词": "债务",
                              "理由": "临时承接", "关联种类": "未完成条目",
                              "关联目标": str(现存号)}]})
    登记报告审完(仓根, 核验开工号, {"来源号": 陈旧来源号, "提取条数": 1, "判词条数": 1})
    连接 = 账本.连反馈库()
    try:
        连接.execute("update 反馈判词 set 关联目标 = ? where 条目号 = ?",
                  ("v1-999999", 陈旧条目号))
        连接.commit()
        未蒸馏 = 反馈关联.未蒸馏反馈集(连接, 仓根, 核验开工号)
    finally:
        连接.close()
    记样本("债务承接**陈旧失效**（目标开工已不存在）⇒ 拒清（fail-closed）：%s"
       % ([台账行 for 台账行 in 未蒸馏 if "无有效承接" in 台账行][:1],),
      any("无有效承接" in 台账行 for 台账行 in 未蒸馏))

    # ── 机器 / 人工分流：机器记录无阻断权，人工记录照旧阻断（自动性能记录不阻断释放）──
    # ★ 2026-10-11：「超 5 秒自动反馈」机制已移除 ⇒ 本档不再借它造记录，改用**唯一反馈口**
    #   `提交反馈` 直接造一条**同形状**的机器记录（来源标识仍以 `账本.自动来源标识前缀` 起头）
    #   —— 考的口径一字没变（机器记录落库留痕但不阻断），只是不再依赖已删的机制件。
    机器开工号 = "v1-900004"
    连接 = 开工账本.连账本()
    try:
        if not 开工账本.读开工(连接, 机器开工号):
            开工账本.登记开工(连接, 机器开工号, "机器记录样本腿", "腿/" + 机器开工号, str(仓根))
    finally:
        连接.close()
    # 先自清本样本号的历史行：同一库重复调用不得跨轮累积成假读数。子表（证据 / 判词 / 关闭）
    # 按 `条目号` 关联、**没有** `来源号` 栏 ⇒ 先按条目号清子表，再清条目 / 批次 / 来源。
    连接 = 账本.连反馈库()
    try:
        for 表名 in ("反馈证据", "反馈判词", "反馈关闭"):
            连接.execute("delete from %s where 条目号 in "
                     "(select 条目号 from 反馈条目 where 开工号 = ?)" % 表名, (机器开工号,))
        连接.execute("delete from 反馈条目 where 开工号 = ?", (机器开工号,))
        连接.execute("delete from 反馈批次 where 开工号 = ?", (机器开工号,))
        连接.execute("delete from 反馈来源 where 开工号 = ?", (机器开工号,))
        连接.commit()
    finally:
        连接.close()
    机器标识 = "%s%s" % (账本.自动来源标识前缀, "释放验证")
    退出码, 回执文本 = 提交反馈(仓根, 机器开工号, {
        "幂等键": "机器-性能-001", "来源标识": 机器标识, "报告指纹": "3c" * 16,
        "条目": [{"现象": "释放验证耗时越过效率阈值（机器记录样本）",
                 "落点": "开发工具/MCP服务/仓操作.py::跑验证",
                 "触发": "释放路径跑完整验证（闸 0）真实墙钟越过效率阈值的那一刻",
                 "预期": "效率目标以内（五秒效率目标，未完成）",
                 "实际": "实测越过阈值（未被强杀，等到真实终态）",
                 "证据": "阶段 释放验证 · 开工 %s" % 机器开工号,
                 "耗时毫秒": 5077}]})
    连接 = 账本.连反馈库()
    try:
        机器明细 = 反馈关联.未蒸馏明细(连接, 仓根, 机器开工号)
        机器留痕行 = 反馈关联.自动记录行(连接, 仓根, 机器开工号)
    finally:
        连接.close()
    记样本("机器记录（来源标识 %s）⇒ **落库留痕但不阻断**：登记 %s · 阻断 %d 条 · 自动留痕 %d 条"
       % (机器标识, 退出码 == 0, len(机器明细), len(机器留痕行)),
      退出码 == 0 and 机器明细 == [] and len(机器留痕行) == 2)
    原检查清树安全, 原非终态作业 = 清树门禁.检查清树安全, 清树门禁.非终态作业
    清树门禁.检查清树安全 = lambda 仓根, 开工号, 工作树: (0, "样本：已合主干且净树")
    清树门禁.非终态作业 = lambda 开工号, 工作树: []
    try:
        连接 = 开工账本.连账本()
        try:
            机器清树成立, 机器判据表 = 清树门禁.核清树条件(
                连接, 仓根, 机器开工号,
                {"状态": 开工账本.状态_已释放, "工作树": str(仓根)})
        finally:
            连接.close()
    finally:
        清树门禁.检查清树安全, 清树门禁.非终态作业 = 原检查清树安全, 原非终态作业
    记样本("核清树条件·**只有机器记录** ⇒ 成立（放行）且回执报出自动条数：%s"
       % ([台账行 for 台账行 in 机器判据表 if "另有" in 台账行][:1],),
      机器清树成立 and any("另有" in 台账行 and "自动性能记录" in 台账行 for 台账行 in 机器判据表))
    提交反馈(仓根, 机器开工号, {"幂等键": "机器-人工-1", "来源标识": "agent-z/人报告.md",
                        "报告指纹": "9a" * 16,
                        "条目": [{"现象": "人工混入", "证据": "读数", "未测": "落点未定位"}]})
    连接 = 账本.连反馈库()
    try:
        混合明细 = 反馈关联.未蒸馏明细(连接, 仓根, 机器开工号)
        混合自动 = 反馈关联.自动记录行(连接, 仓根, 机器开工号)
    finally:
        连接.close()
    记样本("机器 + 人工混存 ⇒ **人工照旧阻断**（阻断 %d 条）· 自动仍不阻断（%d 条）"
       % (len(混合明细), len(混合自动)),
      len(混合明细) == 2 and len(混合自动) == 2)
    return 样本表


def 重启与迁移样本(仓根, 临时根) -> list:
    """重启可回读 + 旧库迁移 ⇒ 样本表。"""
    from . import 开工账本, 反馈账本 as 账本
    样本表 = []

    def 记样本(说明, 通过):
        样本表.append((说明, bool(通过)))

    连接 = 账本.连反馈库()
    连接.close()
    连接 = 账本.连反馈库()
    try:
        条目行 = 账本.读条目(连接, 1)
        判词行 = 账本.读判词(连接, 1)
        关闭行 = 账本.读关闭(连接, 1)
    finally:
        连接.close()
    记样本("重启（关连接再开）可回读：条目 1 现象 %s · 判词 %s · 关闭 %s"
       % (账本.截断((条目行 or {}).get("现象")), (判词行 or {}).get("判词"), bool(关闭行)),
      条目行 is not None and 判词行 is not None and 关闭行 is not None)

    旧根 = Path(临时根) / "旧库"
    (旧根 / "数据库").mkdir(parents=True, exist_ok=True)
    旧件 = 旧根 / "数据库" / 开工账本.库文件名
    旧连接 = sqlite3.connect(str(旧件))
    try:
        旧连接.execute(开工账本.建表语句[0])
        旧连接.execute("insert into 开工 values ('v1-888888', '旧库腿', '腿/v1-888888', "
                  "'/tmp/旧', '进行中', '2026-01-01T00:00:00+0800', null, null, '原腿')")
        旧连接.commit()
    finally:
        旧连接.close()
    os.environ[覆盖变量名] = str(旧根)
    try:
        新连接 = 账本.连反馈库()
        try:
            表集 = {数据行[0] for 数据行 in 新连接.execute(
                "select name from sqlite_master where type = 'table'")}
            旧行 = 新连接.execute("select 工作内容 from 开工 where 开工号 = 'v1-888888'").fetchone()
        finally:
            新连接.close()
    finally:
        os.environ[覆盖变量名] = str(临时根)
    记样本("原库迁移：旧库（只有 `开工` 表）连反馈库 ⇒ 六表齐 %s · 旧行保留 %s"
       % (反馈表集 <= 表集, 旧行 and 旧行[0]),
      反馈表集 <= 表集 and 旧行 is not None and 旧行[0] == "旧库腿")
    return 样本表
