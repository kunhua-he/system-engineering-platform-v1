# -*- coding: utf-8 -*-
"""长样本 —— MCP 服务的长样本套件入口（`MCP服务.py --长样本` 的实现）。

**为什么单开一件**（判据 ⑲ 单源文件 ≤400 行）：合主干回归（8 例 · 真 bare 仓 + 源库重放三态，约 23 秒）
与释放行为样本（16 态，约 8 秒）是**长**回归，塞不进 `--自检` 的 5 秒硬顶（判据 ㊽）⇒ 挂到
`--长样本`（环境步，预算宽松），由 `构建装配/一键验证/一键验证/自检_长样本.py` 把它拉进
`一键验证.py --自测`（放行口径，与 pre-commit 同路）。**这两套回归不得孤儿** —— 它们覆盖
合主干编排（含源库重放三态）与释放的正反态，没真实调用者就永不跑。

**只跑套件、不复制实现**：合主干跑 `合主干样本.跑样本`，释放跑 `释放样本.释放样本`。

读数：各套件退出码 · `失败表`（不过的套件名）。任一不过 ⇒ 返回 1。
"""


def 长样本(仓根) -> int:
    """跑长样本套件（合主干回归 + 释放行为）⇒ 退出码；`失败表` 非空即 1。"""
    from . import 合主干样本, 释放样本
    失败表 = []
    释放表 = []
    合主干码 = 1
    释放码 = 1
    try:
        合主干码 = 合主干样本.跑样本()
    except BaseException as 错误:
        print("合主干回归异常：%r" % (错误,))
    try:
        释放表 = 释放样本.释放样本()
        释放码 = 0 if 释放表 and all(通过 for _, 通过 in 释放表) else 1
    except BaseException as 错误:
        print("释放行为异常：%r" % (错误,))
    if 合主干码 != 0:
        失败表.append("合主干")
    if 释放码 != 0:
        失败表.append("释放")
    print("长样本：合主干回归退出码 %d · 释放行为 %d 态退出码 %d" % (合主干码, len(释放表), 释放码))
    if 失败表:
        print("★ 长样本失败：%s" % " · ".join(失败表))
        return 1
    print("长样本全过")
    return 0
