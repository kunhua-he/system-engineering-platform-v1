# -*- coding: utf-8 -*-
"""长样本 —— MCP 服务的**全套长样本套件入口**（`MCP服务.py --长样本全套` 的实现）。

**为什么单开一件**（判据 ⑲ 单源文件 ≤400 行）：合主干回归（8 例 · 真 bare 仓 + 源库重放三态，约 23 秒）
与释放行为样本（34 态，约 8 秒）与反馈专项（约 25 秒）是**长**回归，塞不进 `--自检` 的 5 秒硬顶（判据 ㊽）⇒ 挂到
`--长样本全套`（环境步，预算宽松），由 `构建装配/一键验证/一键验证/自检_长样本.py` 把它拉进
`一键验证.py --自测`（放行口径，与 pre-commit 同路）。**这两套回归不得孤儿** —— 它们覆盖
合主干编排（含源库重放三态）· 释放的正反态 · 反馈专项与清树接缝，没真实调用者就永不跑。

**两个 CLI 入口各归其位**（不偷换已发布入口语义）：`MCP服务.py --长样本`（已发布）= 重事务认领链
7 场景，走 `认领样本.入口`；`MCP服务.py --长样本全套`（本件）= 全套长回归，走本件 `入口`。本件此前
**只有函数、没有 CLI** ⇒ 真实现被 `自检_长样本.py` 直接 import 绕过 CLI（「长样本无 CLI 入口」的漂移），
已补 `入口` 并让消费者走真入口。

**只跑套件、不复制实现**：合主干跑 `合主干样本.跑样本`，释放跑 `释放样本.释放样本`，反馈跑 `反馈长样本.反馈长样本`。

读数：各套件退出码 · `失败表`（不过的套件名）。任一不过 ⇒ 返回 1。
"""


def 长样本(仓根) -> int:
    """跑长样本套件（合主干回归 + 释放行为 + 反馈专项与真实清树接缝 + 耗时反馈 / 验证超阈 /
    释放作业编排）⇒ 退出码；`失败表` 非空即 1。"""
    from . import 合主干样本, 释放样本, 反馈长样本, 耗时反馈样本, 验证超阈样本, 释放作业样本
    失败表 = []
    释放表 = []
    反馈行表 = []
    耗时反馈表 = []
    验证超阈表 = []
    释放作业表 = []
    合主干码 = 1
    释放码 = 1
    反馈码 = 1
    耗时反馈码 = 1
    验证超阈码 = 1
    释放作业码 = 1
    try:
        合主干码 = 合主干样本.跑样本()
    except BaseException as 错误:
        print("合主干回归异常：%r" % (错误,))
    try:
        释放表 = 释放样本.释放样本()
        释放码 = 0 if 释放表 and all(通过 for _, 通过 in 释放表) else 1
    except BaseException as 错误:
        print("释放行为异常：%r" % (错误,))
    try:
        反馈码, 反馈行表 = 反馈长样本.反馈长样本(仓根)
        for 一行读数 in 反馈行表:
            print(一行读数)
    except BaseException as 错误:
        print("反馈专项异常：%r" % (错误,))
    try:
        耗时反馈表 = 耗时反馈样本.样本列表(仓根)
        耗时反馈码 = 0 if 耗时反馈表 and all(通过 for _, 通过 in 耗时反馈表) else 1
        for 样本项 in 耗时反馈表:
            print("  %s %s" % ("✓" if 样本项[1] else "✗", 样本项[0]))
    except BaseException as 错误:
        print("耗时反馈样本异常：%r" % (错误,))
    try:
        验证超阈表 = 验证超阈样本.样本列表(仓根)
        验证超阈码 = 0 if 验证超阈表 and all(通过 for _, 通过 in 验证超阈表) else 1
        for 样本项 in 验证超阈表:
            print("  %s %s" % ("✓" if 样本项[1] else "✗", 样本项[0]))
    except BaseException as 错误:
        print("验证超阈样本异常：%r" % (错误,))
    try:
        释放作业表 = 释放作业样本.样本列表(仓根)
        释放作业码 = 0 if 释放作业表 and all(通过 for _, 通过 in 释放作业表) else 1
        for 样本项 in 释放作业表:
            print("  %s %s" % ("✓" if 样本项[1] else "✗", 样本项[0]))
    except BaseException as 错误:
        print("释放作业样本异常：%r" % (错误,))
    if 合主干码 != 0:
        失败表.append("合主干")
    if 释放码 != 0:
        失败表.append("释放")
    if 反馈码 != 0:
        失败表.append("反馈专项与清树接缝")
    if 耗时反馈码 != 0:
        失败表.append("耗时反馈")
    if 验证超阈码 != 0:
        失败表.append("验证超阈")
    if 释放作业码 != 0:
        失败表.append("释放作业")
    print("长样本：合主干回归退出码 %d · 释放行为 %d 态退出码 %d · 反馈专项 %d 行退出码 %d · "
          "耗时反馈 %d 态退出码 %d · 验证超阈 %d 态退出码 %d · 释放作业 %d 态退出码 %d"
          % (合主干码, len(释放表), 释放码, len(反馈行表), 反馈码,
             len(耗时反馈表), 耗时反馈码, len(验证超阈表), 验证超阈码,
             len(释放作业表), 释放作业码))
    if 失败表:
        print("★ 长样本失败：%s" % " · ".join(失败表))
        return 1
    print("长样本全过")
    return 0


def 入口(命令行参数, 仓根, 工具表=None) -> int:
    """`MCP服务.py --长样本全套` 的实现：跑全套长样本套件（合主干 + 释放 + 反馈专项）⇒ 退出码。"""
    print("MCP 长样本全套 —— 合主干回归 + 释放行为 + 反馈专项（短自检 `--自检` 不跑它；"
          "本口挂在提交长路 `一键验证.py --自测`）")
    return 长样本(仓根)
