def 反查表(工具名: str) -> dict:
    """该工具 `{操作名: 操作号}`（由 `编号表` 现算，不另立第二份手写表）。"""
    return {操作名: 操作号 for 操作号, 操作名 in 编号表.get(工具名, {}).items()}


