def 发现号(工具名: str, 操作名: str):
    """某操作名在本工具的固定号（别名 ⇒ 回落**本名**的号；都没有 ⇒ `None`）。"""
    if 操作名 in 反查表(工具名):
        return 反查表(工具名)[操作名]
    return 反查表(工具名).get(别名表.get(工具名, {}).get(操作名, ""))


def 号串(工具名: str) -> str:
    """该工具号的紧凑串 `0=查询 1=登记 …`（发现回执与未知操作提示共用）。"""
    return " ".join("%d=%s" % (操作号, 操作名)
                    for 操作号, 操作名 in sorted(编号表.get(工具名, {}).items()))


def _查号(工具名: str, 操作号: int) -> tuple:
    """按号取操作名 ⇒ `(操作名 或 None, 错误 或 None)`。"""
    操作名 = 编号表.get(工具名, {}).get(操作号)
    if 操作名 is None:
        if 编号表.get(工具名):
            return None, "未知操作号：%r —— 本工具 %s 没有这个号；可用号：%s" % (操作号, 工具名, 号串(工具名))
        return None, "未知操作号：%r —— 工具 %s 没有固定编号，请给操作名" % (操作号, 工具名)
    return 操作名, None


def 归一操作(工具名: str, 原文) -> tuple:
    """顶层 `操作` 原文 ⇒ `(操作名 或 "" 或 原样字符串, 错误 或 None)`。

    · `None` / 空串 / 全空白 ⇒ `("", None)`（只读发现调用）。
    · 整数（**拒逻辑值**）⇒ 查号；查不到 ⇒ 错误。
    · 字符串：纯数字串 ⇒ 查号；像数字但不合法（如 `"7.0"` / `"7a"`）⇒ 错误；
      其余（操作名 / 别名）**原样透传** ⇒ 由网关按该工具真实操作表判在不在。
    · 浮点 / 其它类型 ⇒ 错误。
    """
    if 原文 is None:
        return "", None
    if isinstance(原文, bool):
        return None, "`操作` 不接受逻辑值（true/false）—— 要给号就给整数（如 0），或给操作名。"
    if isinstance(原文, int):
        return _查号(工具名, 原文)
    if isinstance(原文, float):
        return None, "`操作` 不接受浮点（%r）—— 要给号就给整数（如 0），或给操作名。" % (原文,)
    if isinstance(原文, str):
        原文 = 原文.strip()
        if not 原文:
            return "", None
        if 整数串形.match(原文):
            return _查号(工具名, int(原文))
        if 原文[0].isdigit() or (原文[0] in "+-" and len(原文) > 1 and 原文[1].isdigit()):
            return None, "`操作` 数字串不合法：%r —— 要给号就给纯整数（如 \"0\"），或给操作名。" % (原文,)
        return 原文, None
    return None, "`操作` 类型不对（%s）—— 给整数号或操作名字符串。" % type(原文).__name__
