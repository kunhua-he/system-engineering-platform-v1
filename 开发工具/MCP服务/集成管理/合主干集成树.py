def 集成树根() -> Path:
    """集成树落点根（`<运行数据根>/临时件/集成树`）—— **唯一一处**拼它。

    为什么落运行数据根（2026-10-13 修 · 债务 530）：原先 `tempfile.mkdtemp(prefix="v1集成-")`
    落在**系统临时根**、失败现场按设计保留 ⇒ 每失败一次多一棵、散在 `/private/var/folders/…`，
    既不归属也不可枚举（实测累积 91 棵 · 4.6 MB，而 `git worktree list` 只剩 1 条 ⇒ 全是孤儿）。
    落运行数据根 ⇒ 一开工一名（可枚举 · 可回收），且**不在源码树内**（判据 ⑳ · 走唯一解析器）。
    """
    from 运行数据根 import 解析当前环境, 子目录路径
    落点根 = Path(子目录路径(解析当前环境(), 集成树根子目录[0])) / 集成树根子目录[1]
    落点根.mkdir(parents=True, exist_ok=True)
    return 落点根


def 死树(候选目录) -> bool:
    """该目录是**死集成树**吗（它自称的工作树元目录已不在）⇒ 真假。

    集成树是 `git worktree add` 出来的 ⇒ 目录里 `.git` 是**文件**、内容 `gitdir: <主仓>/.git/worktrees/<名>`：
    那个目标还在 ⇒ **活树**（真现场，交 `--查看现场` / `--恢复现场` / `--清理现场`）；目标不在 / 压根
    没有工作树链接 ⇒ **死树**（夹具仓删净后的空壳、建到一半断掉的残留）⇒ 可回收。

    ★ **不按「谁登记」判**（2026-10-13 修 · 债务 530）：样本夹具仓与真仓各有各的活树，按「本仓 git 有没
    登记它」判会把**别的仓**的活树当孤儿删掉。按目录自身的链接判则与仓无关，只认死壳。
    """
    链接件 = 候选目录 / ".git"
    if not 链接件.exists():
        return True
    if not 链接件.is_file():
        return False                      # `.git` 是目录 ⇒ 真仓本体，绝不碰
    try:
        链接首行 = 链接件.read_text(encoding="utf-8", errors="replace").strip()
    except OSError:
        return True
    if not 链接首行.startswith("gitdir:"):
        return True
    链接目标 = Path(链接首行.split(":", 1)[1].strip())
    if not 链接目标.is_absolute():
        链接目标 = (候选目录 / 链接目标).resolve()
    return not 链接目标.exists()


def 回收孤儿() -> tuple:
    """清掉 `集成树根()` 下的**死集成树**（夹具仓删净 / 建到一半断掉留下的空壳）⇒ (退出码, 行表)。

    为什么要有它（2026-10-13 修 · 债务 530）：失败现场按设计保留 ⇒ 攒下的空壳没人收（实测 91 棵 ·
    4.6 MB）。落点已从系统临时根改到运行数据根（一开工一名 · 可枚举）⇒ 收口就在同一处做。
    **只清死树**（判据见 `死树`）—— 活树是真现场，绝不代清。
    """
    落点根 = 集成树根()
    行表, 清掉表, 保留数 = [], [], 0
    for 候选目录 in sorted(落点根.glob(集成树前缀 + "*")):
        if not 候选目录.is_dir():
            continue
        if not 死树(候选目录):
            保留数 += 1
            continue
        shutil.rmtree(候选目录, ignore_errors=True)
        if 候选目录.exists():
            行表.append("  清不掉（留待人工）：%s" % 候选目录.name)
            continue
        清掉表.append(候选目录.name)
    退出码 = 1 if any("清不掉" in 数据行 for 数据行 in 行表) else 0
    return 退出码, ["回收孤儿集成树：清 %d 个 · 保留活现场 %d 个 · %s"
                 % (len(清掉表), 保留数, " · ".join(清掉表) or "无")] + 行表


def 无非源库脏件(树根) -> tuple:
    """现场除源库外无未提交/未跟踪成果 ⇒ (退出码, 说明)。

    源库是**二进制派生件**（`建库` 可重抽）⇒ 不算成果。旧口径「任何脏件都算成果」会把
    「零提交腿留下的重抽源库」当成果 ⇒ 拒清 ⇒ 现场永远清不掉（债务 529）。
    `-z` 是**唯一路径安全形式**（空格 / 引号 / 换行都不失真）；`-c core.quotePath=false` 只是
    非 `-z` 输出的兼容兜底，不再承担读路径的职责。解析只经 `门禁.git路径解析`。
    """
    退出码, 输出文本, 日志路径 = _跑(
        ["git", "status", "--porcelain", "-z", "-uall"], 树根, 超时秒数=5, 只取标准输出=True)
    if 退出码 != 0:
        return 1, "读不出现场状态 · 日志 %s" % 日志路径
    余留表 = [路径 for _, 路径 in 解析状态零分隔(输出文本) if 路径 != 库相对路径]
    if 余留表:
        return 1, "现场仍有非源库未提交/未跟踪成果 ⇒ 拒清理：%s" % " · ".join(余留表[:10])
    return 0, "现场除源库外无未提交/未跟踪成果"


def 建集成树(仓根, 开工号) -> tuple:
    """从主干建隔离集成工作树 ⇒ (退出码, 路径 或 说明)。落点 = `集成树根()`（一开工一名）。"""
    已有树 = 找集成树(仓根, 开工号)
    if 已有树:
        return 1, "已有集成现场 %s ⇒ 用 --查看现场 / --恢复现场 / --清理现场，不再建树" % 已有树
    路径 = 集成树根() / (集成树前缀 + 开工号)
    if 路径.exists():
        # 同名残留但 git 无登记（上次建到一半就断了）⇒ 先收掉再建，不然 `worktree add` 会拒。
        shutil.rmtree(路径, ignore_errors=True)
    集成分支名 = "集成/" + 开工号
    退出码, 输出文本, _ = _跑(["git", "worktree", "add", "-b", 集成分支名, str(路径), "主干"], 工作目录=仓根, 超时秒数=None)
    if 退出码 != 0:
        shutil.rmtree(路径, ignore_errors=True)
        return 退出码, "建集成树失败：%s" % 输出文本.strip()[-500:]
    return 0, str(路径)


def 合腿(集成树, 腿分支) -> tuple:
    """在集成树里合腿 ⇒ (退出码, 说明, 冲突文件表)。--no-ff 保证造合并提交（不走 ff）。"""
    退出码, 输出文本, 日志路径 = _跑(["git", "merge", "--no-commit", "--no-ff", 腿分支], 工作目录=集成树, 超时秒数=None)
    # 合腿冲突表是整条合并工序的分叉点（接管 / 重叠 / 清场全按它走）⇒ 必须按 `-z` 原字节读。
    _, 命令输出, _ = _跑(["git", "diff", "--name-only", "--diff-filter=U", "-z"],
                       工作目录=集成树, 只取标准输出=True)
    冲突表 = 解析零分隔(命令输出)
    if 冲突表:
        return 0, "合腿有冲突 · 原始退出码 %d · 是否超时 %s · 日志 %s\n%s" % (退出码, 退出码 == -1, 日志路径, 输出文本[:1500]), 冲突表
    if 退出码 != 0:
        return 退出码, "合腿失败 · 退出码 %d · 是否超时 %s · 日志 %s\n%s" % (退出码, 退出码 == -1, 日志路径, 输出文本[:1500]), []
    return 0, "合腿干净（无冲突）", []


def 提交合并(集成树, 腿分支, 开工号) -> tuple:
    """提交集成树的合并 ⇒ (退出码, 说明)，正常执行 Git 提交钩子。"""
    提交信息 = "合并 %s 进主干（隔离集成校验通过）\n\n开工号 %s\n" % (腿分支, 开工号)
    退出码, 输出文本, _ = _跑(["git", "commit", "-F", "-"],
                 工作目录=集成树, 超时秒数=None, 输入文本=提交信息)
    if 退出码 != 0:
        return 退出码, ("提交合并失败（退出码 %d；钩子拒也会落这里 —— 钩子那边打的读数在下面）:\n%s"
                    % (退出码, 输出文本.strip()[-1200:]))
    return 0, "合并提交已造（门禁随提交跑过一遍）"


def 提交恢复现场(集成路径, 腿分支, 开工号, 行表) -> tuple:
    """`--恢复现场` 的提交支 ⇒ (退出码, 说明)。树脏 ⇒ 重放结果一并提交（门禁随提交跑）；树干净 ⇒ 显式跑一遍。

    为什么树脏要再提交：重放会再写一遍源库（`创建时间` 默认 `datetime('now')` ⇒ 字节非确定）⇒
    不再提交的话 ④ 的「index == 提交树」核验必拒（2026-10-08 收口方实测）。让恢复可安全重跑。
    """
    退出码, 脏输出, _ = _跑(["git", "status", "--porcelain", "-uall"], 集成路径, 超时秒数=5)
    if 退出码 != 0:
        return 1, "恢复现场读不出集成树状态：%s" % 脏输出.strip()[-300:]
    if 脏输出.strip():
        退出码, 说明 = 提交合并(集成路径, 腿分支, 开工号)
        if 退出码 == 0:
            行表.append("   重放后集成树又变脏（源库时间默认值非确定）⇒ 把重放结果一并提交（门禁随提交跑）")
        return 退出码, 说明
    退出码, 门禁行表, 尾部 = 门禁.跑集成门禁(集成路径)
    行表.extend(门禁行表)
    if 退出码 != 0:
        return 退出码, 尾部[:1500]
    退出码, _, _ = _跑(["git", "merge-base", "--is-ancestor", 腿分支, "HEAD"], 集成路径, 超时秒数=5)
    return 退出码, "恢复现场已有提交（无新改动，不造空提交）；腿分支祖先核验退出码 %d" % 退出码


def 推进主干(仓根, 集成提交, 集成树) -> tuple:
    """优先 ff-only；附 tree 相等核验与三方一致复核 ⇒ (退出码, 说明)。"""
    _, 旧提交, _ = _跑(["git", "rev-parse", "主干"], 工作目录=仓根)
    旧提交 = 旧提交.strip()
    _, 提交树, _ = _跑(["git", "rev-parse", "%s^{tree}" % 集成提交], 工作目录=仓根)
    _, 索引树, _ = _跑(["git", "write-tree"], 工作目录=集成树)
    if 提交树.strip() != 索引树.strip():
        return 1, "集成树 index 与提交树不等（%s ≠ %s）⇒ 拒绝推进" % (索引树.strip(), 提交树.strip())
    _, 头提交, _ = _跑(["git", "rev-parse", "HEAD"], 工作目录=集成树)
    if 头提交.strip() != 集成提交:
        return 1, "集成树 HEAD %s ≠ 集成提交 %s ⇒ 拒绝推进" % (头提交.strip(), 集成提交)
    _, 脏输出, _ = _跑(["git", "status", "--porcelain", "-uall"], 工作目录=集成树)
    if 脏输出.strip():
        return 1, "集成树有未提交改动 ⇒ 拒绝推进：%s" % 脏输出.strip()[-300:]
    退出码, _, _ = _跑(["git", "merge-base", "--is-ancestor", 旧提交, 集成提交], 工作目录=仓根)
    if 退出码 != 0:
        return 1, "主干 %s 不是集成提交 %s 的祖先 ⇒ 非 ff，拒绝" % (旧提交, 集成提交)
    临时树 = tempfile.mkdtemp(prefix="v1主干-")
    shutil.rmtree(临时树, ignore_errors=True)
    退出码, 输出文本, _ = _跑(["git", "worktree", "add", 临时树, "主干"], 工作目录=仓根, 超时秒数=None)
    if 退出码 == 0:
        退出码2, 命令输出, _ = _跑(["git", "merge", "--ff-only", 集成提交], 工作目录=临时树, 超时秒数=None)
        _跑(["git", "worktree", "remove", "--force", 临时树], 工作目录=仓根, 超时秒数=None)
        shutil.rmtree(临时树, ignore_errors=True)
        if 退出码2 != 0:
            return 退出码2, "ff-only 推进失败：%s" % 命令输出.strip()[-400:]
        说明 = "ff-only（临时工作树 + merge --ff-only）"
    else:
        shutil.rmtree(临时树, ignore_errors=True)
        退出码3, 引用输出, _ = _跑(["git", "update-ref", "refs/heads/主干", 集成提交, 旧提交], 工作目录=仓根)
        if 退出码3 != 0:
            return 退出码3, "update-ref 推进失败：%s" % 引用输出.strip()[-400:]
        说明 = "update-ref（已附 tree 相等核验 + 三方一致复核 + 祖先核验）"
    _, 新提交, _ = _跑(["git", "rev-parse", "主干"], 工作目录=仓根)
    if 新提交.strip() != 集成提交:
        return 1, "推进后主干 %s ≠ 集成提交 %s ⇒ 异常" % (新提交.strip(), 集成提交)
    return 0, "主干 %s → %s（%s）" % (旧提交[:8], 集成提交[:8], 说明)


def 核主索引(主目录, 引用):
    命令头 = ["git", "--git-dir", str(Path(主目录) / ".git"), "--work-tree", str(主目录)]
    退出码, 索引, 日志路径 = _跑(命令头 + ["write-tree"], 主目录, 超时秒数=5)
    退出码2, 提交树, _ = _跑(命令头 + ["rev-parse", 引用 + "^{tree}"], 主目录, 超时秒数=5)
    if 退出码 != 0 or 退出码2 != 0 or 索引.strip() != 提交树.strip():
        差异退出码, 差异输出, _ = _跑(命令头 + ["diff-tree", "-r", "--name-only", 提交树.strip(), 索引.strip()],
                                主目录, 超时秒数=5)
        差异段 = ("\n差异件：%s" % " · ".join(差异输出.split()[:20])
                if 差异退出码 == 0 and 差异输出.strip() else "")
        return 1, "index 与旧提交不同，保留 %s · 日志 %s%s" % (主目录, 日志路径, 差异段)
    return 0, "index == 旧提交树"


