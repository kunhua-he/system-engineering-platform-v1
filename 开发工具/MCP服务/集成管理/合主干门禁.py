# -*- coding: utf-8 -*-
"""合主干门禁 —— 集成树的提交门禁，**同一份内容只跑一遍**（口径 = pre-commit 钩子）。

**为什么要单列**（2026-10-09 实测，不是推测）：`合主干编排` 原先在 ③ 用 `git hook run pre-commit`
**显式**跑一遍完整门禁，紧接着 `git commit` 又触发同一个钩子 —— 实测 `git merge --no-commit`
之后的 `git commit` 跑的是 `pre-commit`（不是 `pre-merge-commit`）⇒ **同一份内容把门禁跑两遍**。
本机实测单遍 ≈ 110 s（`--自测` ≈ 105 s · `闸0` ≈ 4 s · 全案例冷编 ≈ 2 s）⇒ 合并墙钟翻倍
（报告里的 218624 ms ≈ 2 × 109 s；报告把它记成「一次性冷构建」是**误归因** —— 真冷编译实测
1.6 s）。本件把门禁收成**一遍**：提交那一下的钩子是唯一一次；只有「无需提交」的那一支
（恢复现场且树干净）才显式跑。

**判据一条不减**：同一份内容 · 同一份钩子体 · 同一个退出码语义 —— 减掉的只是**重复执行**。
**缺钩子 = 拒**（fail-closed）：没有钩子的提交 = 无门禁合主干 ⇒ 绝不放过。
"""

import os
import sys
from pathlib import Path

from .合主干有界跑 import 跑有界命令
from ..验证管理.门禁预算 import 硬顶秒

闸门说明 = "闸0 + 判据自测 + 预构建前置 + 全案例"
# ★ 案例装载的是 **gitignored 的构建产物**（`扩展根目录/原子支持库/*/*.支持库制品`）⇒ 案例之前
#   必须先过预构建前置（戳与当前源相符 + 制品在位）。两个方向都错过：源改了不重编 ⇒ 假绿；
#   新树里制品不在 ⇒ 案例「工具错误（不写回执）」。判定与构建只在
#   `构建制品.py --确保预构建` 一个节点（与 pre-commit 钩子同一份口径，不写第二套）。
案例命令 = (". ./构建环境/进入.sh >/dev/null 2>&1 || exit 1; "
        "\"{}\" 构建装配/上线切换/构建制品.py --确保预构建 || exit 1; "
        "cargo run --quiet --locked -p v1-case-runner").format(sys.executable)


def 找钩子路径(工作树):
    """该树的 `pre-commit` 钩子路径 —— 问 git（`--git-path`），不拼目录名。"""
    _, 输出文本, _ = 跑有界命令(["git", "rev-parse", "--git-path", "hooks/pre-commit"], 工作目录=工作树)
    路径 = Path(输出文本.strip())
    if not 路径.is_absolute():
        路径 = Path(工作树) / 路径
    return 路径


def 核提交门禁(集成树) -> tuple:
    """③ 的唯一前置 ⇒ (退出码, 行表, 尾部输出)。

    钩子在 ⇒ 真门禁由**提交那一下**跑（唯一一次，不再重复跑）；钩子不在 / 不可执行 ⇒ **这里显式补跑一遍**
    （同一份口径）—— 否则那个提交根本没有门禁拦，就是「无门禁合主干」。两条路都只跑**一遍**。
    """
    路径 = 找钩子路径(集成树)
    if 路径.is_file() and os.access(路径, os.X_OK):
        return 0, ["③ 提交门禁钩子已在位 %s ⇒ 门禁由**提交那一下**跑一遍（%s，与 pre-commit 同口径）"
                 % (路径, 闸门说明)], ""
    退出码, 门禁行表, 尾部 = 跑集成门禁(集成树)
    return 退出码, ["③ 提交门禁钩子不在或不可执行（%s）⇒ 这里显式补跑一遍，否则那个提交没有门禁拦" % 路径] + 门禁行表, 尾部


def 跑集成门禁(集成树) -> tuple:
    """**显式**跑一遍门禁 ⇒ (退出码, 行表, 尾部输出)。只给「不造提交」的那一支用（恢复现场且树干净）。"""
    路径 = 找钩子路径(集成树)
    if 路径.is_file() and os.access(路径, os.X_OK):
        退出码, 输出文本, 日志路径 = 跑有界命令(["git", "hook", "run", "pre-commit"], 工作目录=集成树,
                          超时秒数=None, 保留日志=True)
        return 退出码, ["③ 提交门禁（git hook run pre-commit · 与 pre-commit 同口径：%s）退出码 %d · 日志 %s"
                  % (闸门说明, 退出码, 日志路径)], 输出文本
    步骤表 = (
        ("闸0", [sys.executable, "构建装配/一键验证/闸0.py"], 硬顶秒()),
        ("判据自测", [sys.executable, "构建装配/一键验证/一键验证.py", "--自测"], None),
        ("全案例", ["sh", "-c", 案例命令], None),
    )
    行表 = ["③ 提交门禁钩子不在 ⇒ 直接跑三条（%s）" % 闸门说明]
    读数表 = []
    for 步骤名, 命令表, 超时秒数 in 步骤表:
        退出码, 输出文本, 日志路径 = 跑有界命令(命令表, 工作目录=集成树, 超时秒数=超时秒数, 保留日志=True)
        if 退出码 != 0:
            return 退出码, 行表 + ["%s 不过（退出码 %d）· 日志 %s" % (步骤名, 退出码, 日志路径)], 输出文本
        读数表.append("%s 绿 · 日志 %s" % (步骤名, 日志路径))
    return 0, 行表 + ["；".join(读数表)], ""
