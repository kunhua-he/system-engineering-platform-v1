# -*- coding: utf-8 -*-
"""合主干现场清理 —— 失败集成现场的**恢复前置判定**与**清理收口**（源库冲突不算代码冲突）。

为什么单列：`合主干编排.py` 已近 400 行硬顶；本件只装三条判定与一处清树收口，
`_重放源库` 的重放语义与合腿后挂钩一个字不动（另一条腿在改那两段）。

两条缺口（收口方实测 v1-100533）：
  · `--恢复现场` 原先在源库三方重放**之前**做 `git diff --diff-filter=U` —— 失败现场的冲突
    只落在二进制源库（UU）时被当场拒；源库本该交正式重放处置（`_重放源库` 会取主干版 + `git add`）。
  · `--清理现场` 原先只认「干净且已入主干」—— 旧主干基现场（主干已推进过它）既恢复不动、又清不掉。
"""

from pathlib import Path

from 构建装配.门禁.git路径解析 import 解析零分隔

from .合主干有界跑 import 跑有界命令
from . import 合主干集成树 as 集成

库相对路径 = "开发工具/信息核心/信息核心.db"


def _跑(命令表, 工作目录, 只取标准输出=False):
    return 跑有界命令(命令表, 工作目录=工作目录, 超时秒数=5, 保留日志=True,
                  只取标准输出=只取标准输出)


def 未解决代码冲突(集成路径) -> tuple:
    """集成树里未合并的**非源库**件（源库由正式重放处置）⇒ (退出码, 件表 或 说明)。

    `-z` 是唯一路径安全的读法（空格 / 引号 / 换行都不失真），解析只经 `门禁.git路径解析`；
    **与 `集成接管.未合并件` 同一答案**（同一现场两种读法 = 迟早漂）。
    """
    退出码, 输出文本, 日志路径 = _跑(
        ["git", "diff", "--name-only", "--diff-filter=U", "-z"], 集成路径, 只取标准输出=True)
    if 退出码 != 0:
        return 1, "读不出未合并件 · 日志 %s\n%s" % (日志路径, 输出文本[:400])
    件表 = [路径 for 路径 in 解析零分隔(输出文本) if 路径 != 库相对路径]
    return 0, 件表


def 无非源库未提交成果(集成路径) -> tuple:
    """现场除源库外无未提交/未跟踪成果 ⇒ (退出码, 说明)。

    ★ 唯一实现已下沉到 `合主干集成树.无非源库脏件`（2026-10-13 修 · 债务 529）：本件与集成树
    各有一份同一判定（两份已漂）⇒ 本件改为转出口，不再维护第二份口径。
    """
    return 集成.无非源库脏件(集成路径)


def 判旧主干基(仓根, 开工号) -> tuple:
    """现场基于的旧主干已被推进（主干不再是现场基点）⇒ (退出码, 说明)。"""
    退出码, 基点, 日志路径 = _跑(["git", "merge-base", "集成/" + 开工号, "主干"], 仓根)
    if 退出码 != 0:
        return 1, "算不出现场基点（集成/%s）：%s · 日志 %s" % (开工号, 基点.strip()[:200], 日志路径)
    退出码, 当前主干, 日志路径 = _跑(["git", "rev-parse", "主干"], 仓根)
    if 退出码 != 0:
        return 1, "读不出主干：%s · 日志 %s" % (当前主干.strip()[:200], 日志路径)
    if 基点.strip() == 当前主干.strip():
        return 1, "现场基点正是当前主干（主干未推进过现场）⇒ 不当旧主干基清理，先试 --恢复现场"
    return 0, "现场基点 %s 已是旧主干（当前主干 %s）" % (基点.strip()[:10], 当前主干.strip()[:10])


def 清现场(仓根, 集成路径, 开工号) -> tuple:
    """`--清理现场` 收口：已入主干（既有判定）/ 旧主干基失败现场（本件新增）⇒ 清；其余拒。

    只认本服务登记的集成树（`找集成树` + 路径核对）。先走既有「干净且已入主干」判定
    （唯一实现住 `合主干集成树.清集成树`，不抄第二份）；它拒后再判「旧主干基」：
    主干已推进过现场基点（恢复不动）且除源库外无未提交成果 ⇒ 强清。

    ★ 旧主干基那一支**不再自带清树实现**（2026-10-13 修 · 债务 529）：原先它在
    `合主干集成树.py` 与本件各有一份（两份收口口径已漂），现统一调 `集成.清集成树`
    （`允许未入主干=真` —— 旧主干基现场的支线本就不在主干里，那一步由 `判旧主干基` 把门）。
    """
    仓根 = Path(str(仓根)).resolve()
    已有树 = 集成.找集成树(仓根, 开工号)
    if 已有树 is None:
        return 1, "没有已知现场，不清未知目录：%s" % 开工号
    if 已有树 != Path(str(集成路径)).resolve():
        return 1, "集成目标不符，拒绝清理：%s" % 集成路径
    既有码, 既有说明 = 集成.清集成树(仓根, 已有树, 开工号)
    if 既有码 == 0:
        return 0, 既有说明
    余留码, 余留说明 = 无非源库未提交成果(已有树)
    if 余留码 != 0:
        return 1, "现场不可清：%s（既有判定：%s）" % (余留说明, 既有说明)
    判基码, 判基说明 = 判旧主干基(仓根, 开工号)
    if 判基码 != 0:
        return 1, "现场不可清：%s（既有判定：%s）" % (判基说明, 既有说明)
    # ★ 回执里保留「旧主干基失败现场（…）」这个**因由**（2026-10-13 修）：原先它由本件的
    #   `_清树支` 拼出；收口统一到 `集成.清集成树` 之后没了它 ⇒ 样本与人都看不出「凭哪一条清的」。
    清码, 清说明 = 集成.清集成树(仓根, 已有树, 开工号, 允许未入主干=True)
    return 清码, "旧主干基失败现场（%s）：%s" % (判基说明, 清说明)
