# -*- coding: utf-8 -*-
"""开工 —— `v1_task` 的实现：登记 / 补充 / 查询 / 释放 / 单纯释放（生成物/源件记账各转发一件）。

**一条开工 = 一条支线 + 一个工作树 + 一棵独立的索引。**

为什么必须连工作树一起建：一个工作区没法同时 checkout 两条分支；两条开工改同一个文件时，
各改各的副本 ⇒ 根本不会互相覆盖，冲突推迟到合并（谁先推谁赢）。工作树的建/清**走本仓现成的
`开发工具/并行工作树.sh`** —— 它还负责那棵树自带的构建缓存与 venv（没有它，那棵树跑不了门禁）。

**仓内动作（git 子进程 · 工作树 · 指纹）在 `仓操作.py`** —— 本件只留各功能的编排：一件只讲
一件事，也是把本件压在 400 行硬数（判据 ⑲）以内的拆法。**读文件用哪棵树**：登记返回工作树的
**绝对路径**，agent 拿它去读（内置 `Read`/`Grep` 只能按路径走）。
"""

import sys
from pathlib import Path

from . import 开工账本 as 账本  # noqa: E402
from .仓操作 import (禁终端提示环境, 分支名, 支线在吗, 清工作树,  # noqa: E402
                  建工作树, 建工作树索引, 找工作树, 变更路径表, 读盘指纹, 跑命令)
from .修改 import 对账          # noqa: E402  —— 绕过检测与 v1_edit 第 ③ 道闸共用一份实现


# ── 六个功能 ────────────────────────────────────────────────────────────────────────────

def 查僵尸(连接, 仓根) -> list:
    """**僵尸开工**：状态还没翻「已释放」、却**工作树与支线都不在**的那些开工 ⇒ `[开工号…]`。

    它们的活早已并主干、树与支线也清了，只是账本状态没翻 ⇒ 会**污染冲突检测**
    （新腿登记时被报「这些件别的开工也认领了」，而那些开工根本不存在）。`功能 = 4` 能逐条销。
    """
    僵尸表 = []
    for 一条 in 账本.全部开工(连接):
        if 一条["状态"] == 账本.状态_已释放:
            continue
        if not Path(一条["工作树"]).is_dir() and not 支线在吗(仓根, 一条["开工号"]):
            僵尸表.append(一条["开工号"])
    return 僵尸表


def 登记(仓根, 工作内容: str, 文件认领, 确认重叠: bool = False) -> tuple:
    if not 工作内容.strip():
        return 2, "功能 = 1 登记要 `工作内容`（它同时是支线的提交信息）"
    连接 = 账本.连账本()
    try:
        开工号 = 账本.新开工号(连接)
        路径表 = 文件认领 if isinstance(文件认领, list) else ([文件认领] if 文件认领 else [])
        # ⑥ 重叠认领**先查再建树**（查冲突只要路径、不用读盘）—— 别的未释放开工也认领了同一个件时，
        #   各写各的工作树 ⇒ 运行期不撞、**合并期撞**（实测 205/210 撞 建库.py · 201/204 撞 引用基线.json）。
        #   故升级为**需显式确认**：不确认就拒，且**不建工作树**（不留残留）。僵尸开工先剔掉（见 `查僵尸`）。
        僵尸表 = 查僵尸(连接, 仓根)
        冲突表 = 账本.查跨开工冲突(连接, 开工号, 路径表, 僵尸表)
        if 冲突表 and not 确认重叠:
            return 2, ("**没登记**：这些件**别的开工也认领了**（各写各的工作树 ⇒ 运行期不撞，"
                     "**合并期会撞**）—— 要接着干就**显式确认**：重新 功能 = 1 并传 `确认重叠` = 真"
                     "（合并期得人工做语义合并）：\n%s"
                     % "\n".join("    %s：%s" % (路径, " · ".join(号表))
                                for 路径, 号表 in sorted(冲突表.items())))
        退出码, 输出文本 = 建工作树(仓根, 开工号)
        if 退出码 != 0:
            return 1, "建工作树失败（退出码 %d）⇒ 没登记：\n%s" % (退出码, 输出文本.strip()[-500:])
        工作树 = 找工作树(仓根, 开工号)
        if 工作树 is None:
            return 1, ("工作树建好了、但 git 没列出支线 %s ⇒ 查清再重来（别记账）"
                      % 分支名(开工号))
        退出码, 输出文本 = 建工作树索引(工作树)
        if 退出码 != 0:
            return 1, ("索引没建成（退出码 %d）⇒ 没登记。工作树在 %s，查清后可重来：\n%s"
                      % (退出码, 工作树, 输出文本.strip()[-500:]))
        指纹表, 读不出表 = 读盘指纹(工作树, 路径表)
        # ① 认领不存在的路径 ⇒ **拒收**（不入认领表）。原先只打一句警告、却仍把它收进认领表 ⇒
        #   `释放` 按开工记录 `git add` 撞 `fatal: pathspec … did not match any files` ⇒ 整条腿
        #   释放卡死（实测 207：20 件改动、0 提交）。新建的件不必先认领（`v1_edit` 功能=0 直接建）。
        if 读不出表:
            清工作树(仓根, 开工号)
            return 2, ("**没登记**：`文件认领` 里这些件**盘上不存在** ⇒ 拒收（不入认领表）：\n  %s\n"
                     "（新件请先建再认领，或用 功能 = 2 建完补一次。刚建的工作树已清掉、没留残留。）"
                     % " · ".join(读不出表))
        # ④ 口径（裁 2026-09-27）：**给了认领件、却一件都没读上盘** ⇒ 路径写错，fail-closed
        #    （新建的件不必先认领，故不存在「合法的全读不出」）。清掉刚建的工作树、**不登记** ——
        #    登记要么整条成功、要么什么都不留（留一棵没账的工作树正是 ② 要清的那类孤儿）。
        if 路径表 and not 指纹表:
            清工作树(仓根, 开工号)
            return 2, ("**没登记**：`文件认领` 给了 %d 件，却**一件都没读上盘** ⇒ 路径写错了。\n  %s\n"
                     "（新建的件不必先认领：`v1_edit` 功能=0 能直接建，建完指纹自动补进认领表。"
                     "刚建的工作树已清掉、没留残留 ⇒ 核对路径后重新 功能=1 登记。）"
                     % (len(路径表), " · ".join(读不出表)))
        账本.登记开工(连接, 开工号, 工作内容.strip(), 分支名(开工号), str(工作树))
        账本.认领文件(连接, 开工号, 指纹表)
        输出行表 = ["开工号 %s（支线 %s）" % (开工号, 分支名(开工号)),
                  "工作树（读文件用这个绝对路径）：%s" % 工作树,
                  "认领 %d 件" % len(指纹表)]
        if not 指纹表:
            输出行表.append("（认领集为空 —— 纯调研的活合法；要写文件就用 功能 = 2 补认领）")
        # ⑥ 重叠认领：已在上方**显式确认**过 ⇒ 这里把重叠件单独列一节（显眼处）。
        if 冲突表:
            输出行表.append("★ 重叠认领（**已显式确认**）：这些件**别的开工也认领了** —— "
                        "各写各的工作树（运行期不撞），**合并期要人工做语义合并**：\n%s"
                        % "\n".join("    %s：%s" % (路径, " · ".join(号表))
                                   for 路径, 号表 in sorted(冲突表.items())))
        # ② 重复登记检测（**只报不拦**，口径同 `查跨开工冲突`）—— 实测 2026-09-27 一条活登两次。
        for 别的号, 原因 in 账本.查重复登记(连接, 开工号, 工作内容, 指纹表, 僵尸表):
            输出行表.append("★ 与 **%s** 疑似重复登记：%s —— 只报不拦，先查清（功能=0 可查历史）"
                        % (别的号, 原因))
        前置行 = 账本.前置提示行()
        if 前置行:
            输出行表.append(前置行)
        输出行表.append("★ 工具行为异常 ⇒ 让收口方**重启 ZCode**（MCP 服务是长驻进程，改了不重启不生效）")
        return 0, "\n".join(输出行表)
    finally:
        连接.close()


def 补充认领(仓根, 开工号: str, 文件认领, 确认重叠: bool = False) -> tuple:
    连接 = 账本.连账本()
    try:
        一条 = 账本.读开工(连接, 开工号)
        if not 一条:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记" % 开工号
        if 一条["状态"] == 账本.状态_已释放:
            return 1, "这条开工已释放 ⇒ 不能再补认领。要接着干就新开一条（功能 = 1）"
        路径表 = 文件认领 if isinstance(文件认领, list) else ([文件认领] if 文件认领 else [])
        if not 路径表:
            return 2, "功能 = 2 补充要 `文件认领`（要给哪几个件）"
        指纹表, 读不出表 = 读盘指纹(Path(一条["工作树"]), 路径表)
        # ① 认领不存在的路径 ⇒ **拒收**（不入认领表）：新件请先建再认领，或用 功能 = 2 建完补一次。
        if 读不出表:
            return 2, ("**没补上**：这些件**盘上不存在** ⇒ 拒收（不入认领表）：\n  %s\n"
                     "（新件请先建再认领，或用 功能 = 2 建完补一次）" % " · ".join(读不出表))
        # ⑥ 重叠认领需**显式确认**（口径与 功能 = 1 同一条）：僵尸开工先剔掉（见 `查僵尸`）。
        僵尸表 = 查僵尸(连接, 仓根)
        冲突表 = 账本.查跨开工冲突(连接, 开工号, 指纹表, 僵尸表)
        if 冲突表 and not 确认重叠:
            return 2, ("**没补上**：这些件**别的开工也认领了**（各写各的工作树 ⇒ 运行期不撞，"
                     "**合并期会撞**）—— 要接着干就**显式确认**：重新 功能 = 2 并传 `确认重叠` = 真：\n%s"
                     % "\n".join("    %s：%s" % (路径, " · ".join(号表))
                                for 路径, 号表 in sorted(冲突表.items())))
        账本.认领文件(连接, 开工号, 指纹表)
        输出行表 = ["%s 现在认领 %d 件" % (开工号, len(账本.读认领(连接, 开工号)))]
        if 冲突表:
            输出行表.append("★ 重叠认领（**已显式确认**）：这些件**别的开工也认领了** —— "
                        "合并期要人工做语义合并：\n%s"
                        % "\n".join("    %s：%s" % (路径, " · ".join(号表))
                                   for 路径, 号表 in sorted(冲突表.items())))
        return 0, "\n".join(输出行表)
    finally:
        连接.close()


def 查询开工(仓根, 开工号: str, 关键词: str, 上限: int = 20) -> tuple:
    连接 = 账本.连账本()
    try:
        if 关键词.strip():
            命中表 = 账本.搜开工(连接, 关键词.strip(), 上限)
            if not 命中表:
                return 0, "没有命中「%s」的开工（搜的面：工作内容 · 认领路径 · 改动路径）" % 关键词
            return 0, "命中 %d 条：\n%s" % (len(命中表), "\n".join(
                "  %s  %s  %s  %s" % (一条["开工号"], 一条["开工时间"][:16],
                                   一条["状态"], 一条["工作内容"][:48]) for 一条 in 命中表))
        if 开工号.strip():
            一条 = 账本.读开工(连接, 开工号.strip())
            if not 一条:
                return 1, "没有这条开工：%s" % 开工号
            认领表 = 账本.读认领(连接, 开工号.strip())
            改动表 = 账本.读改动(连接, 开工号.strip())
            return 0, "\n".join([
                "开工号 %s · %s" % (一条["开工号"], 一条["状态"]),
                "工作内容：%s" % 一条["工作内容"],
                "支线 %s · 工作树 %s" % (一条["分支名"], 一条["工作树"]),
                "开工 %s%s" % (一条["开工时间"],
                             " · 释放 %s" % 一条["释放时间"] if 一条["释放时间"] else ""),
                "认领 %d 件：%s" % (len(认领表), " · ".join(sorted(认领表)) or "（空）"),
                "改动 %d 次：%s" % (len(改动表), " · ".join(
                    "%s(%s)" % (一条改动["路径"], 一条改动["功能"]) for 一条改动 in 改动表) or "（无）"),
            ])
        最近表 = 账本.列开工(连接, 上限)
        if not 最近表:
            return 0, "账本里还没有开工记录 ⇒ 先 功能 = 1 登记"
        输出行表 = ["最近 %d 条：\n%s" % (len(最近表), "\n".join(
            "  %s  %s  %s  %s" % (一条["开工号"], 一条["开工时间"][:16],
                               一条["状态"], 一条["工作内容"][:48]) for 一条 in 最近表))]
        # ④ 僵尸开工诊断：状态没翻「已释放」、却树与支线都不在（工作早已并主干）⇒ 它们**污染冲突检测**。
        僵尸表 = 查僵尸(连接, 仓根)
        if 僵尸表:
            输出行表.append("★ 僵尸开工 %d 条（状态未释放、却**工作树与支线都不在** —— 工作早已并主干）"
                        "⇒ 用 功能 = 4 逐条销（幂等，不跑验证不提交）：\n    %s"
                        % (len(僵尸表), " · ".join(僵尸表)))
        else:
            输出行表.append("（无僵尸开工：未释放的开工都有工作树或支线）")
        return 0, "\n".join(输出行表)
    finally:
        连接.close()


def 释放(仓根, 开工号: str, 强制: bool, 跳过验证: bool = False) -> tuple:
    """收工：跑验证 → 提交支线 → 推远端 ⇒ 状态「已提交待合并」（合并是**手动**的，合完跑 功能 = 4）。

    `跳过验证`（功能 = 7）只跳**门禁那一步**，提交与推送照走 —— 给「认领表干净、但验证跑不动
    （门禁自身坏了 / 环境缺件）」的腿留一条活路：跳验证**不等于**跳提交，活不会留在工作区没提交
    （实测 207 就是这么丢的：20 件改动、0 提交）。绕过检测与越界检测**不跳**（那是账本的完整性）。
    """
    连接 = 账本.连账本()
    try:
        一条 = 账本.读开工(连接, 开工号)
        if not 一条:
            return 1, "没有这条开工：%s" % 开工号
        if 一条["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能重复释放" % 一条["状态"]
        if 强制:
            账本.置状态(连接, 开工号, 账本.状态_已释放)
            return 0, ("%s **强制释放**：没跑验证、没提交、没推。工作树留着没动 —— 里面的活要人来处置。"
                     % 开工号)
        工作树 = Path(一条["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再释放（别把状态改了、活却找不回）" % 工作树

        # ① 绕过检测：**认领集里盘上指纹变了 = 有人绕过 v1_edit 直接写盘**。
        # 为什么必须在提交之前查：那种件**不在改动表里** ⇒ 不会被提交；而门禁是在**工作树上**跑的、
        # 读的是盘上的新内容 ⇒ 门禁绿、提交里却没有那份改动 —— 一次「绿着交付、内容缺失」的释放。
        # （对账与 v1_edit 第 ③ 道闸共用一份实现：`修改.对账`。）
        路径表0 = sorted({一条改动["路径"] for 一条改动 in 账本.读改动(连接, 开工号)})
        对得上表, 变过表 = 对账(工作树, 账本.读认领(连接, 开工号))
        if 变过表:
            return 1, ("**有人绕过 v1_edit 直接改了盘**（账本记的指纹与现在盘上的对不上）⇒ 无法释放：\n"
                     "  %s\n"
                     "绕过 v1_edit 就意味着那段改动**没经过四道闸**（没查路径认领、没查旧内容唯一定位），"
                     "而门禁读的正是盘上的新内容 ⇒ 它会跟着「绿」一起进去（绿得没意义）。"
                     "处置：把盘上那段改动**撤掉**，改用 v1_edit 重来。" % " · ".join(sorted(变过表)))
        # 盘上还有**改动表之外**的改动（未认领的件、未跟踪的新件）⇒ 同样是绕过。
        退出码, 变更表 = 变更路径表(工作树)
        if 退出码 != 0:
            return 1, "查不清盘上动了什么，不敢提交：\n%s" % 变更表
        越界表 = [路径 for 路径 in 变更表 if 路径 not in 路径表0]
        if 越界表:
            return 1, ("盘上这些件动了，但不在改动表里（没走过 v1_edit）⇒ 无法释放：\n  %s\n"
                     "处置：撤掉改动走 v1_edit；**生成物**（生成器产出）请用 功能=5 记账；"
                     "门禁/构建的副产物请确认后手工处置。"
                     % " · ".join(sorted(set(越界表))))

        # ② 跑门禁。红了就**不提交、不推、不释放**。`跳过验证`（功能 = 7）⇒ 整段跳过、并如实标注。
        if not 跳过验证:
            退出码, 输出文本 = 跑命令([sys.executable, "构建装配/一键验证/闸0.py"], cwd=工作树)
            if 退出码 != 0:
                有效行表 = [源码行 for 源码行 in 输出文本.splitlines() if 源码行.strip() and "─" not in 源码行]
                return 1, ("门禁没过（退出码 %d）⇒ **无法释放**（不提交、不推）。逐条读数：\n%s"
                         % (退出码, "\n".join(有效行表[-25:])))

        # ③ 提交支线 —— **精确路径**（改动表里记的那些），禁通配。
        路径表 = 路径表0
        if not 路径表:
            return 1, "这条开工一次也没改过文件 ⇒ 没什么可提交的（纯调研的活请用 功能 = 3 + `强制`）"
        # ★ 「提交成功、推送失败」之后**重跑释放**要能走通：那时工作树已经干净，
        #   `git commit` 会以「nothing to commit」失败 —— 那不是错，是**已经提交过了**。
        #   所以先问一句「还有没有东西可提交」：没有就跳过提交、直接去推。
        #   （原先直接判 `码 != 0` 就返回 ⇒ 重试卡死在这里，而且报成「门禁钩子可能拒了」——**归因是错的**。）
        退出码, 输出文本 = 跑命令(["git", "status", "--porcelain", "--"] + 路径表, cwd=工作树)
        if 退出码 != 0:
            return 1, "git status 失败：\n%s" % 输出文本.strip()[-400:]
        有得提交 = bool(输出文本.strip())
        提交说明 = ""
        if 有得提交:
            退出码, 输出文本 = 跑命令(["git", "add", "--"] + 路径表, cwd=工作树)
            if 退出码 != 0:
                return 1, "git add 失败：\n%s" % 输出文本.strip()[-400:]
            # 提交信息走 **stdin**（`git commit -F -`）—— 不落临时件：`/tmp` + 拼路径是
            # 判据 ㉕ 的形④（「临时根拼路径」），而本仓的临时件落点该是 `运行数据根/临时件/`。
            # 走 stdin 连那个落点都不用碰。
            提交信息 = "%s\n\n开工号 %s\n改动：%s\n" % (一条["工作内容"], 开工号, " · ".join(路径表))
            退出码, 输出文本 = 跑命令(["git", "commit", "-F", "-"], cwd=工作树, 超时秒数=None,
                      输入文本=提交信息, 环境=禁终端提示环境)
            if 退出码 != 0:
                return 1, ("git commit 失败（多半是**门禁钩子拒了** —— 它每次提交都跑一遍案例）：\n%s"
                         % 输出文本.strip()[-600:])
        else:
            提交说明 = "（这一步没有新改动要提交 —— 上一趟已经提交过了，直接推）\n"
        if 跳过验证:
            提交说明 += ("★ **这次跳过了验证**（功能 = 7）—— 提交里那份改动**没经过门禁**，"
                      "合并前请补跑一次全量 `闸0.py`。\n")

        # ④ 推远端（腿分支目前都没有上游 ⇒ 第一次要 -u 建上游）。
        退出码, 输出文本 = 跑命令(["git", "push", "-u", "origin", 一条["分支名"]], cwd=工作树, 超时秒数=None,
                  环境=禁终端提示环境)
        if 退出码 != 0:
            return 1, ("**推送失败**（退出码 %d）⇒ 不释放，状态留「进行中」。\n"
                     "先分清是环境问题还是代码问题（认证 / 网络 / 远端拒绝属环境，"
                     "检查 SSH key 与远端权限）：\n%s" % (退出码, 输出文本.strip()[-600:]))

        账本.置状态(连接, 开工号, 账本.状态_待合并)
        return 0, ("%s 已提交并推到 origin/%s，状态「已提交待合并」。\n%s"
                 "下一步：**手动**合并到主干，合完跑 功能 = 4 收尾（清工作树与支线）。"
                 % (开工号, 一条["分支名"], 提交说明))
    finally:
        连接.close()


def 单纯释放(仓根, 开工号: str) -> tuple:
    """手动合并到主干之后收尾：清工作树与支线 + 状态「已释放」。不跑验证、不提交、不推。

    **幂等**（2026-10-01 修）：树与支线都早已不在时，不再报错 —— 打一行「无物可清」、返回成功。
    原先那种情况会让 `git worktree remove` / `git branch -D` 各报一个 fatal ⇒ 调用方把
    「早已清干净」误判成失败。
    **僵尸开工也走这一档直接销**（④）：状态「进行中」却树与支线都没了 ⇒ 它永远进不了 功能 = 3
    （那个要求工作树在）⇒ 不放松这一条它就销不掉、继续污染冲突检测。
    """
    连接 = 账本.连账本()
    try:
        一条 = 账本.读开工(连接, 开工号)
        if not 一条:
            return 1, "没有这条开工：%s" % 开工号
        工作树在 = Path(一条["工作树"]).is_dir()
        支线在 = 支线在吗(仓根, 开工号)
        if 一条["状态"] == 账本.状态_进行中 and (工作树在 or 支线在):
            return 1, ("这条开工还是「进行中」⇒ 先用 功能 = 3 释放（跑验证 + 提交 + 推），"
                     "合并完再回来跑 功能 = 4")
        退出码, 输出文本 = 清工作树(仓根, 开工号)
        账本.置状态(连接, 开工号, 账本.状态_已释放)
        if 退出码 != 0:
            return 1, "%s 清树失败（状态已翻「已释放」）：%s" % (开工号, 输出文本.strip()[-300:])
        return 0, "%s 状态「已释放」；清树：%s" % (开工号, 输出文本.strip() or "（无物可清）")
    finally:
        连接.close()


def 派发(参数表: dict, 仓根) -> tuple:
    """`v1_task` 的入口：按 `功能` 分派。"""
    功能 = 参数表.get("功能")
    名表 = "0=查询 · 1=登记 · 2=补充 · 3=释放 · 4=单纯释放 · 5=生成物记账 · 6=源件记账 · 7=释放（跳过验证）"
    if 功能 is None:
        return 2, "缺 `功能`：" + 名表
    try:
        功能号 = int(功能)
    except (TypeError, ValueError):
        return 2, "`功能` 要是整数：" + 名表
    开工号 = str(参数表.get("开工ID") or "").strip()
    确认重叠 = bool(参数表.get("确认重叠"))
    if 功能号 == 0:
        return 查询开工(仓根, 开工号, str(参数表.get("关键词") or ""))
    if 功能号 == 1:
        return 登记(仓根, str(参数表.get("工作内容") or ""), 参数表.get("文件认领"), 确认重叠)
    if 功能号 == 2:
        if not 开工号:
            return 2, "功能 = 2 补充要 `开工ID`"
        return 补充认领(仓根, 开工号, 参数表.get("文件认领"), 确认重叠)
    if 功能号 == 3:
        if not 开工号:
            return 2, "功能 = 3 释放要 `开工ID`"
        return 释放(仓根, 开工号, bool(参数表.get("强制")))
    if 功能号 == 4:
        if not 开工号:
            return 2, "功能 = 4 单纯释放要 `开工ID`"
        return 单纯释放(仓根, 开工号)
    if 功能号 == 5:
        if not 开工号:
            return 2, "功能 = 5 生成物记账要 `开工ID`"
        from .生成物记账 import 记账      # 迟到导入：它反过来要用本件的 `跑命令`（避免环）
        return 记账(仓根, 开工号, str(参数表.get("生成器") or ""), 参数表.get("生成器参数"))
    if 功能号 == 6:
        if not 开工号:
            return 2, "功能 = 6 源件记账要 `开工ID`"
        from .源件记账 import 记账        # 迟到导入：同上（避免环）
        return 记账(仓根, 开工号, str(参数表.get("源件") or ""), str(参数表.get("源件说明") or ""))
    if 功能号 == 7:
        if not 开工号:
            return 2, "功能 = 7 释放（跳过验证）要 `开工ID`"
        return 释放(仓根, 开工号, False, 跳过验证=True)
    return 2, "`功能` 只认 0/1/2/3/4/5/6/7，收到 %r" % (功能,)
