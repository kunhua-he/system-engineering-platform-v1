def 登记(仓根, 工作内容: str, 文件认领) -> tuple:
    if not 工作内容.strip():
        return 2, "功能 = 1 登记要 `工作内容`（它同时是支线的提交信息）"
    连 = 账本.连账本()
    try:
        开工号 = 账本.新开工号(连)
        码, 出 = 建工作树(仓根, 开工号)
        if 码 != 0:
            return 1, "建工作树失败（退出码 %d）⇒ 没登记：\n%s" % (码, 出.strip()[-500:])
        工作树 = 找工作树(仓根, 开工号)
        if 工作树 is None:
            return 1, ("工作树建好了、但 git 没列出支线 %s ⇒ 查清再重来（别记账）"
                      % 分支名(开工号))
        码, 出 = 建那棵树的索引(工作树)
        if 码 != 0:
            return 1, ("索引没建成（退出码 %d）⇒ 没登记。工作树在 %s，查清后可重来：\n%s"
                      % (码, 工作树, 出.strip()[-500:]))
        路径表 = 文件认领 if isinstance(文件认领, list) else ([文件认领] if 文件认领 else [])
        指纹表, 读不出表 = 读盘指纹(工作树, 路径表)
        账本.登记开工(连, 开工号, 工作内容.strip(), 分支名(开工号), str(工作树))
        账本.认领文件(连, 开工号, 指纹表)
        输出行表 = ["开工号 %s（支线 %s）" % (开工号, 分支名(开工号)),
                  "工作树（读文件用这个绝对路径）：%s" % 工作树,
                  "认领 %d 件" % len(指纹表)]
        if 读不出表:
            输出行表.append("★ 这几件没认领上（读不到，路径写错了？）：%s"
                        % " · ".join(读不出表))
        if not 指纹表 and not 读不出表:
            输出行表.append("（认领集为空 —— 纯调研的活合法；要写文件就用 功能 = 2 补认领）")
        # 跨开工冲突：别的**未释放**开工也认领了同一个件。**只报不拦**（见 `查跨开工冲突`）。
        冲突表 = 账本.查跨开工冲突(连, 开工号, 指纹表)
        if 冲突表:
            输出行表.append("★ 这些件**别的开工也认领了**（各写各的工作树 ⇒ 运行期不撞，"
                        "**合并期会撞**）—— 只报不拦，但心里要有数：\n%s"
                        % "\n".join("    %s：%s" % (路径, " · ".join(开工号表))
                                   for 路径, 开工号表 in sorted(冲突表.items())))
        return 0, "\n".join(输出行表)
    finally:
        连.close()


def 补充(仓根, 开工号: str, 文件认领) -> tuple:
    连 = 账本.连账本()
    try:
        一条 = 账本.读开工(连, 开工号)
        if not 一条:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记" % 开工号
        if 一条["状态"] == 账本.状态_已释放:
            return 1, "这条开工已释放 ⇒ 不能再补认领。要接着干就新开一条（功能 = 1）"
        路径表 = 文件认领 if isinstance(文件认领, list) else ([文件认领] if 文件认领 else [])
        if not 路径表:
            return 2, "功能 = 2 补充要 `文件认领`（要给哪几个件）"
        指纹表, 读不出表 = 读盘指纹(Path(一条["工作树"]), 路径表)
        账本.认领文件(连, 开工号, 指纹表)
        输出行表 = ["%s 现在认领 %d 件" % (开工号, len(账本.读认领(连, 开工号)))]
        if 读不出表:
            输出行表.append("★ 没认领上（读不到）：%s" % " · ".join(读不出表))
        return 0, "\n".join(输出行表)
    finally:
        连.close()


def 查询(开工号: str, 关键词: str, 上限: int = 20) -> tuple:
    连 = 账本.连账本()
    try:
        if 关键词.strip():
            命中表 = 账本.搜开工(连, 关键词.strip(), 上限)
            if not 命中表:
                return 0, "没有命中「%s」的开工（搜的面：工作内容 · 认领路径 · 改动路径）" % 关键词
            return 0, "命中 %d 条：\n%s" % (len(命中表), "\n".join(
                "  %s  %s  %s  %s" % (一条["开工号"], 一条["开工时间"][:16],
                                   一条["状态"], 一条["工作内容"][:48]) for 一条 in 命中表))
        if 开工号.strip():
            一条 = 账本.读开工(连, 开工号.strip())
            if not 一条:
                return 1, "没有这条开工：%s" % 开工号
            认领表 = 账本.读认领(连, 开工号.strip())
            改动表 = 账本.读改动(连, 开工号.strip())
            return 0, "\n".join([
                "开工号 %s · %s" % (一条["开工号"], 一条["状态"]),
                "工作内容：%s" % 一条["工作内容"],
                "支线 %s · 工作树 %s" % (一条["分支名"], 一条["工作树"]),
                "开工 %s%s" % (一条["开工时间"],
                             " · 释放 %s" % 一条["释放时间"] if 一条["释放时间"] else ""),
                "认领 %d 件：%s" % (len(认领表), " · ".join(sorted(认领表)) or "（空）"),
                "改动 %d 次：%s" % (len(改动表), " · ".join(
                    "%s(%s)" % (一条改动["路径"], 一条改动["功能"]) for 一条改动 in 改动表) or "（无）"),
            ])
        最近表 = 账本.列开工(连, 上限)
        if not 最近表:
            return 0, "账本里还没有开工记录 ⇒ 先 功能 = 1 登记"
        return 0, "最近 %d 条：\n%s" % (len(最近表), "\n".join(
            "  %s  %s  %s  %s" % (一条["开工号"], 一条["开工时间"][:16],
                               一条["状态"], 一条["工作内容"][:48]) for 一条 in 最近表))
    finally:
        连.close()


def 释放(仓根, 开工号: str, 强制: bool) -> tuple:
    """收工：跑验证 → 提交支线 → 推远端 ⇒ 状态「已提交待合并」（合并是**手动**的，合完跑 功能 = 4）。"""
    连 = 账本.连账本()
    try:
        一条 = 账本.读开工(连, 开工号)
        if not 一条:
            return 1, "没有这条开工：%s" % 开工号
        if 一条["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能重复释放" % 一条["状态"]
        if 强制:
            账本.置状态(连, 开工号, 账本.状态_已释放)
            return 0, ("%s **强制释放**：没跑验证、没提交、没推。工作树留着没动 —— 里面的活要人来处置。"
                     % 开工号)
        工作树 = Path(一条["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再释放（别把状态改了、活却找不回）" % 工作树

        # ① 绕过检测：**认领集里盘上指纹变了 = 有人绕过 v1_edit 直接写盘**。
        # 为什么必须在提交之前查：那种件**不在改动表里** ⇒ 不会被提交；而门禁是在**工作树上**跑的、
        # 读的是盘上的新内容 ⇒ 门禁绿、提交里却没有那份改动 —— 一次「绿着交付、内容缺失」的释放。
        # （对账与 v1_edit 第 ③ 道闸共用一份实现：`修改.对账`。）
        路径表0 = sorted({一条改动["路径"] for 一条改动 in 账本.读改动(连, 开工号)})
        对得上表, 变过表 = 对账(工作树, 账本.读认领(连, 开工号))
        if 变过表:
            return 1, ("**有人绕过 v1_edit 直接改了盘**（账本记的指纹与现在盘上的对不上）⇒ 无法释放：\n"
                     "  %s\n"
                     "绕过 v1_edit 就意味着那段改动**没经过四道闸**（没查路径认领、没查旧内容唯一定位），"
                     "而门禁读的正是盘上的新内容 ⇒ 它会跟着「绿」一起进去（绿得没意义）。"
                     "处置：把盘上那段改动**撤掉**，改用 v1_edit 重来。" % " · ".join(sorted(变过表)))
        # 盘上还有**改动表之外**的改动（未认领的件、未跟踪的新件）⇒ 同样是绕过。
        码, 出 = 跑(["git", "status", "--porcelain"], cwd=工作树)
        if 码 != 0:
            return 1, "git status 失败（查不清盘上动了什么，不敢提交）：\n%s" % 出.strip()[-400:]
        越界表 = []
        for 行 in 出.splitlines():
            if not 行.strip():
                continue
            路径 = 行[3:].strip().strip('"')
            if " -> " in 路径:
                路径 = 路径.split(" -> ")[-1].strip().strip('"')
            if 路径 and 路径 not in 路径表0:
                越界表.append(路径)
        if 越界表:
            return 1, ("盘上这些件动了，但不在改动表里（没走过 v1_edit）⇒ 无法释放：\n  %s\n"
                     "处置：撤掉改动走 v1_edit，或确认这些是门禁/构建的副产物后手工处置。"
                     % " · ".join(sorted(set(越界表))))

        # ② 跑门禁。红了就**不提交、不推、不释放**。
        码, 出 = 跑([sys.executable, "构建装配/一键验证/闸0.py"], cwd=工作树)
        if 码 != 0:
            有效行表 = [行 for 行 in 出.splitlines() if 行.strip() and "─" not in 行]
            return 1, ("门禁没过（退出码 %d）⇒ **无法释放**（不提交、不推）。逐条读数：\n%s"
                     % (码, "\n".join(有效行表[-25:])))

        # ③ 提交支线 —— **精确路径**（改动表里记的那些），禁通配。
        路径表 = 路径表0
        if not 路径表:
            return 1, "这条开工一次也没改过文件 ⇒ 没什么可提交的（纯调研的活请用 功能 = 3 + `强制`）"
        # ★ 「提交成功、推送失败」之后**重跑释放**要能走通：那时工作树已经干净，
        #   `git commit` 会以「nothing to commit」失败 —— 那不是错，是**已经提交过了**。
        #   所以先问一句「还有没有东西可提交」：没有就跳过提交、直接去推。
        #   （原先直接判 `码 != 0` 就返回 ⇒ 重试卡死在这里，而且报成「门禁钩子可能拒了」——**归因是错的**。）
        码, 出 = 跑(["git", "status", "--porcelain", "--"] + 路径表, cwd=工作树)
        if 码 != 0:
            return 1, "git status 失败：\n%s" % 出.strip()[-400:]
        有得提交 = bool(出.strip())
        提交说明 = ""
        if 有得提交:
            码, 出 = 跑(["git", "add", "--"] + 路径表, cwd=工作树)
            if 码 != 0:
                return 1, "git add 失败：\n%s" % 出.strip()[-400:]
            # 提交信息走 **stdin**（`git commit -F -`）—— 不落临时件：`/tmp` + 拼路径是
            # 判据 ㉕ 的形④（「临时根拼路径」），而本仓的临时件落点该是 `运行数据根/临时件/`。
            # 走 stdin 连那个落点都不用碰。
            提交信息 = "%s\n\n开工号 %s\n改动：%s\n" % (一条["工作内容"], 开工号, " · ".join(路径表))
            码, 出 = 跑(["git", "commit", "-F", "-"], cwd=工作树, 超时秒数=None,
                      输入文本=提交信息, 环境=git环境)
            if 码 != 0:
                return 1, ("git commit 失败（多半是**门禁钩子拒了** —— 它每次提交都跑一遍案例）：\n%s"
                         % 出.strip()[-600:])
        else:
            提交说明 = "（这一步没有新改动要提交 —— 上一趟已经提交过了，直接推）\n"

        # ④ 推远端（腿分支目前都没有上游 ⇒ 第一次要 -u 建上游）。
        码, 出 = 跑(["git", "push", "-u", "origin", 一条["分支名"]], cwd=工作树, 超时秒数=None,
                  环境=git环境)
        if 码 != 0:
            return 1, ("**推送失败**（退出码 %d）⇒ 不释放，状态留「进行中」。\n"
                     "先分清是环境问题还是代码问题（认证 / 网络 / 远端拒绝属环境，"
                     "检查 SSH key 与远端权限）：\n%s" % (码, 出.strip()[-600:]))

        账本.置状态(连, 开工号, 账本.状态_待合并)
        return 0, ("%s 已提交并推到 origin/%s，状态「已提交待合并」。\n%s"
                 "下一步：**手动**合并到主干，合完跑 功能 = 4 收尾（清工作树与支线）。"
                 % (开工号, 一条["分支名"], 提交说明))
    finally:
        连.close()


def 单纯释放(仓根, 开工号: str) -> tuple:
    """手动合并到主干之后收尾：清工作树与支线 + 状态「已释放」。不跑验证、不提交、不推。"""
    连 = 账本.连账本()
    try:
        一条 = 账本.读开工(连, 开工号)
        if not 一条:
            return 1, "没有这条开工：%s" % 开工号
        if 一条["状态"] == 账本.状态_进行中:
            return 1, ("这条开工还是「进行中」⇒ 先用 功能 = 3 释放（跑验证 + 提交 + 推），"
                     "合并完再回来跑 功能 = 4")
        码, 出 = 清工作树(仓根, 开工号)
        账本.置状态(连, 开工号, 账本.状态_已释放)
        return (0 if 码 == 0 else 1), "%s 状态「已释放」；清树：%s" % (
            开工号, 出.strip()[-300:] or "（无输出）")
    finally:
        连.close()


def 派(参数表: dict, 仓根) -> tuple:
    """`v1_task` 的入口：按 `功能` 分派。"""
    功能 = 参数表.get("功能")
    if 功能 is None:
        return 2, "缺 `功能`：0=查询 · 1=登记 · 2=补充 · 3=释放 · 4=单纯释放"
    try:
        功能号 = int(功能)
    except (TypeError, ValueError):
        return 2, "`功能` 要是整数：0=查询 · 1=登记 · 2=补充 · 3=释放 · 4=单纯释放"
    开工号 = str(参数表.get("开工ID") or "").strip()
    if 功能号 == 0:
        return 查询(开工号, str(参数表.get("关键词") or ""))
    if 功能号 == 1:
        return 登记(仓根, str(参数表.get("工作内容") or ""), 参数表.get("文件认领"))
    if 功能号 == 2:
        if not 开工号:
            return 2, "功能 = 2 补充要 `开工ID`"
        return 补充(仓根, 开工号, 参数表.get("文件认领"))
    if 功能号 == 3:
        if not 开工号:
            return 2, "功能 = 3 释放要 `开工ID`"
        return 释放(仓根, 开工号, bool(参数表.get("强制")))
    if 功能号 == 4:
        if not 开工号:
            return 2, "功能 = 4 单纯释放要 `开工ID`"
        return 单纯释放(仓根, 开工号)
    return 2, "`功能` 只认 0/1/2/3/4，收到 %r" % (功能,)
