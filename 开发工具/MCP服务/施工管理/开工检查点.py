# -*- coding: utf-8 -*-
"""开工检查点 —— **显式检查点**的读写（项目记忆的「我写到哪、下一步干什么」那一半）。

表 `开工检查点` 由 `开工账本.py` 的 `建表语句` 建在**同一本** `<运行数据根>/数据库/开工账本.db`；
本件只放那四个函数（判据 ⑲ 单源文件 ≤400 行 ⇒ 从 `开工账本.py` 挪出来）。**只增不改**：
恢复摘要是「读最新一条」，覆盖会把「我原来打算做什么」洗掉。字段只认 `开工账本.检查点字段`。

依据：华哥多次明确的需求 —— 给开工内置项目记忆，崩溃后一次取回上下文；任务安全收口后整套真删。
"""

from .. import 开工账本 as 账本


def 记检查点(连接, 开工号: str, 检查点: dict) -> int:
    """落一条**显式检查点** ⇒ 新行编号。字段只认 `账本.检查点字段`，缺的留空串（不臆测）。"""
    值表 = {栏名: str(检查点.get(栏名) or "").strip() for 栏名 in 账本.检查点字段}
    游标 = 连接.execute(
        "insert into 开工检查点 (开工号, 目标, 当前步骤, 决策原因, 下一动作, 未测, 阻断, 时刻) "
        "values (?, ?, ?, ?, ?, ?, ?, ?)",
        (开工号, 值表["目标"], 值表["当前步骤"], 值表["决策原因"], 值表["下一动作"],
         值表["未测"], 值表["阻断"], 账本.时刻串()))
    连接.commit()
    return int(游标.lastrowid)


def 读检查点(连接, 开工号: str, 记录条数: int = 20) -> list:
    """本开工的检查点，**最新在前**（倒序）。"""
    return [dict(数据行) for 数据行 in 连接.execute(
        "select * from 开工检查点 where 开工号 = ? order by 编号 desc limit ?", (开工号, 记录条数))]


def 最新检查点(连接, 开工号: str):
    """最新一条检查点 ⇒ dict 或 `None`（没有就是没有，不编）。"""
    行表 = 读检查点(连接, 开工号, 1)
    return 行表[0] if 行表 else None


def 清检查点(连接, 开工号: str) -> int:
    """**真删**本开工的全部检查点 ⇒ 删掉的行数。只由安全收口在条件逐条成立后调用（fail-closed 在调用方）。"""
    行数 = 连接.execute("delete from 开工检查点 where 开工号 = ?", (开工号,)).rowcount
    连接.commit()
    return 行数
