# -*- coding: utf-8 -*-
"""承接证据 —— 腿的**工作树与支线都不在**时，收尾前唯一的「活已落主干」证据口。

**为什么要有本件**：`单纯释放` 的物理删除门禁复用 `检查清树安全`，而它判「支线已进入主树历史」
只有两条：支线在 ⇒ 核祖先；**支线不在 ⇒ 直接返回「支线已不存在」并放行**。腿的树与支线都消失后
（手工清过 / 换机 / 旧工具留下的尾巴）这条就是**无条件放行** —— 真实未完成的腿也会被当成
「已承接」翻成已释放，事实就此丢失（实测 28 条历史开工里混着 PostgreSQL 生命周期、D5 上下文原子、
超级列表框原范围三条真未完成）。

**本件只补这一处**（不新增第二个收尾口）：树与支线都不在时，`单纯释放` 必须给 `承接`，
两种形状各自可核：

  · `承接` = **承接提交**（≥7 位十六进制）：真实对象 · 是主干祖先 · 本开工**全部**认领/改动
    路径在该提交树里都在位（零路径 ⇒ 拒，改用承接开工号）；
  · `承接` = **承接开工号**（`v1-` 加六位数字，续作树场景）：该腿存在 · 已释放 · 有改动路径 ·
    其改动路径在当前主干里都在位。

**诚实边界**：腿自身的提交随支线一起没了，**逐行等价不可证**。所以判据与回执只声称
「承接提交是主干祖先、该腿的落点路径在该提交树里在位」，不声称「内容一字不差」。
"""
import re
from pathlib import Path

from .. import 开工账本 as 账本
from .仓操作 import 主工作树, 跑只读git, 跑命令, 支线在吗

提交形状 = re.compile(r"^[0-9a-fA-F]{7,40}$")
开工号形状 = re.compile(r"^v1-\d{6}$")


def 是消失腿(仓根, 开工记录) -> bool:
    """工作树不在盘上、且支线也不在 ⇒ **消失腿**（本件唯一适用范围）。"""
    return (not Path(开工记录["工作树"]).is_dir()
            and not 支线在吗(仓根, 开工记录["开工号"]))


def 取证据路径(连接, 开工号: str) -> list:
    """本开工的落点路径 = 认领 ∪ 改动（去重、排序；两条账本事实的任何一条都算落点）。"""
    路径集 = set(账本.读认领(连接, 开工号))
    路径集 |= {一条改动["路径"] for 一条改动 in 账本.读改动(连接, 开工号)}
    return sorted(路径集)


def _主干提交(仓根):
    """主工作树的当前提交 ⇒ `(退出码, 提交 或 说明)`。读不出就拒（不猜目标树）。"""
    退出码, 主树路径 = 主工作树(仓根)
    if 退出码 != 0:
        return 1, "无法确定主工作树 ⇒ 拒"
    退出码, 提交 = 跑只读git(仓根, ["rev-parse", "HEAD"], 树根=主树路径)
    if 退出码 != 0:
        return 1, "无法读取主工作树提交 ⇒ 拒"
    return 0, 提交.strip()


def _在位路径(仓根, 树引用: str, 路径表: list) -> tuple:
    """`树引用:路径` 逐条核在位 ⇒ `(在位表, 缺失表)`。"""
    在位表, 缺失表 = [], []
    for 路径 in 路径表:
        退出码, _ = 跑命令(["git", "cat-file", "-e", "%s:%s" % (树引用, 路径)], cwd=仓根)
        (在位表 if 退出码 == 0 else 缺失表).append(路径)
    return 在位表, 缺失表


def 核提交承接(仓根, 路径表: list, 承接: str) -> tuple:
    """按**承接提交**核 ⇒ `(是否成立, 判据行表, 证据摘要)`。"""
    行表 = []

    def 记判据(通过, 说明):
        行表.append("%s %s" % ("✓" if 通过 else "✗", 说明))
        return 通过

    成立 = True
    退出码, _ = 跑命令(["git", "cat-file", "-e", 承接 + "^{commit}"], cwd=仓根)
    成立 &= 记判据(退出码 == 0, "承接提交 `%s` 是仓里真实提交对象" % 承接)
    if 退出码 != 0:
        return False, 行表, ""
    主干码, 主干提交 = _主干提交(仓根)
    if 主干码 != 0:
        成立 &= 记判据(False, 主干提交)
        return False, 行表, ""
    退出码, _ = 跑命令(["git", "merge-base", "--is-ancestor", 承接, 主干提交], cwd=仓根)
    成立 &= 记判据(退出码 == 0, "承接提交在主干历史里（主干当前 %s）" % 主干提交[:12])
    if not 路径表:
        成立 &= 记判据(False, "本开工零认领零改动 ⇒ 承接提交无从对账（续作树请给 `承接` = 承接开工号）")
        return False, 行表, ""
    在位表, 缺失表 = _在位路径(仓根, 承接, 路径表)
    成立 &= 记判据(not 缺失表,
                "落点路径在承接提交树里全部在位（%d/%d）" % (len(在位表), len(路径表))
                + ("；缺失：%s" % " · ".join(缺失表) if 缺失表 else ""))
    return 成立, 行表, "承接提交 %s · 落点 %d 条全部在位" % (承接, len(在位表))


def 核开工承接(仓根, 连接, 承接: str) -> tuple:
    """按**承接开工号**核（续作树场景）⇒ `(是否成立, 判据行表, 证据摘要)`。"""
    行表 = []

    def 记判据(通过, 说明):
        行表.append("%s %s" % ("✓" if 通过 else "✗", 说明))
        return 通过

    成立 = True
    承接记录 = 账本.读开工(连接, 承接)
    成立 &= 记判据(bool(承接记录), "承接开工号 `%s` 在账本里" % 承接)
    if not 承接记录:
        return False, 行表, ""
    成立 &= 记判据(承接记录["状态"] == 账本.状态_已释放,
                "承接开工号已收口（状态「%s」）" % 承接记录["状态"])
    承接路径表 = 取证据路径(连接, 承接)
    成立 &= 记判据(bool(承接路径表), "承接开工号有落点路径（%d 条）" % len(承接路径表))
    if not 承接路径表:
        return 成立, 行表, ""
    主干码, 主干提交 = _主干提交(仓根)
    if 主干码 != 0:
        成立 &= 记判据(False, 主干提交)
        return False, 行表, ""
    在位表, 缺失表 = _在位路径(仓根, 主干提交, 承接路径表)
    成立 &= 记判据(not 缺失表,
                "承接开工号的落点路径在当前主干里全部在位（%d/%d）"
                % (len(在位表), len(承接路径表))
                + ("；缺失：%s" % " · ".join(缺失表) if 缺失表 else ""))
    return 成立, 行表, "承接开工号 %s（已释放）· 落点 %d 条在主干在位" % (承接, len(在位表))


def 核承接(仓根, 连接, 开工号: str, 承接: str) -> tuple:
    """`承接` 的正式判定口 ⇒ `(是否成立, 判据行表, 证据摘要)`；形状不认识 ⇒ 不成立并点名。"""
    承接 = (承接 or "").strip()
    if not 承接:
        return False, ["✗ 树与支线都不在 ⇒ **必须给 `承接`**：承接提交（≥7 位十六进制）"
                       "或承接开工号（`v1-` 加六位数字）"], ""
    if 开工号形状.fullmatch(承接):
        if 承接 == 开工号:
            return False, ["✗ `承接` 指回本开工 ⇒ 本开工不能给自身作证据"], ""
        return 核开工承接(仓根, 连接, 承接)
    if 提交形状.fullmatch(承接):
        return 核提交承接(仓根, 取证据路径(连接, 开工号), 承接)
    return False, ["✗ `承接` 形状不认识：%r（要么是 ≥7 位十六进制的承接提交，"
                   "要么是 `v1-` 加六位数字的承接开工号）" % (承接,)], ""
