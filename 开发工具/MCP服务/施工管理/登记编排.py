# -*- coding: utf-8 -*-
"""登记编排 —— `v1_task 登记` 的主体与失败回滚（`开工.py` 只留薄壳）。

为什么单开一件：`开工.py` 顶到 400 行硬数（判据 ⑲）⇒ 照先例把登记主体挪出来，`开工.py` 只留
「登记开工」薄壳（占号 → 主体 → 失败回滚）。**基线并入即登记消费边**：以 `基线=腿/<号>` 登记 ⇒
并入成功后 `记归属(新号, 基线腿号, 原腿)` 把「基线消费者」关系落进现成 `开工.父开工号` 列
（不另存状态表）—— `清树门禁` 据此拦未释放消费者。
"""
from pathlib import Path

from .. import 开工账本 as 账本
from .仓操作 import 分支名, 支线在吗, 建工作树, 建工作树索引, 找工作树, 读盘指纹
from .认领隔离 import 事务认领, 预留开工
from .基线并入 import 并入基线, 基线腿号


def 查僵尸(连接, 仓根):
    """**僵尸开工**：状态还没翻「已释放」、却**工作树与支线都不在**的那些开工 ⇒ `[开工号…]`。

    它们的活早已并主干、树与支线也清了，只是账本状态没翻 ⇒ 会**污染冲突检测**。`功能 = 4` 能销。
    """
    僵尸表 = []
    for 开工记录 in 账本.全部开工(连接):
        if 开工记录["状态"] == 账本.状态_已释放:
            continue
        if not Path(开工记录["工作树"]).is_dir() and not 支线在吗(仓根, 开工记录["开工号"]):
            僵尸表.append(开工记录["开工号"])
    return 僵尸表


def 登记主体(仓根, 连接, 工作内容, 文件认领, 确认重叠, 基线):
    """登记主流程 ⇒ `(退出码, 输出文本, 占号)`。`占号` 非空 ⇒ 调用方负责回滚（`清树门禁.回滚登记`）。

    先落账本行（占住开工号 + 工作树路径）再建树（2026-10-05 修 · 审计 F11.1）：原先先建树后记账 ⇒
    并发腿撞同一工作树路径被拒。`预留开工` 只占号写账本，路径查询与建树都不持 SQLite 写锁。
    """
    路径表 = 文件认领 if isinstance(文件认领, list) else ([文件认领] if 文件认领 else [])
    僵尸表 = 查僵尸(连接, 仓根)
    开工号, 工作树 = 预留开工(连接, 仓根, 工作内容.strip())
    if 开工号 is None:
        return 1, "问不到工作树路径或并发占号未成功 ⇒ 没登记", ""
    占号 = 开工号
    退出码, 输出文本 = 建工作树(仓根, 开工号)
    if 退出码 != 0:
        return 1, ("建工作树失败（退出码 %d）⇒ 没登记（账本行将回滚）：\n%s"
                  % (退出码, 输出文本.strip()[-500:])), 占号
    工作树 = 找工作树(仓根, 开工号)
    if 工作树 is None:
        return 1, ("工作树建好了、但 git 没列出支线 %s ⇒ 没登记（账本行将回滚、工作树清掉）"
                  % 分支名(开工号)), 占号
    并入文本 = ""
    if 基线:
        并入码, 并入文本 = 并入基线(工作树, 基线)
        if 并入码:
            return 并入码, "基线并入失败 ⇒ 没登记（账本行将回滚、工作树清掉）：\n%s" % 并入文本, 占号
        基线腿 = 基线腿号(基线)
        if 基线腿:
            账本.记归属(连接, 开工号, 基线腿, 账本.种类_原腿)
    # ★ 索引步**有界重试**（2026-10-12 实测）：索引器被上了 5 秒硬顶（判据 ㊲），本机并发负载
    #   高时一次构建会被顶过 5 秒 ⇒ 原先一次不过就整轮登记失败，而同一命令负载低时 1.97 秒就过
    #   ⇒ 是负载型假红。故重试一次：两次都超时才算真失败（仍如实报，不静默）。
    退出码, 输出文本 = 1, ""
    for 重试位次 in range(2):
        退出码, 输出文本 = 建工作树索引(工作树)
        if 退出码 == 0:
            break
    if 退出码 != 0:
        return 1, ("索引没建成（退出码 %d）⇒ 没登记（账本行将回滚、工作树清掉）。\n"
                  "修法：在**那条工作树**里跑 `python3 开发工具/代码地图.py 建` —— 它调的是外部"
                  "索引器 `codegraph`（5 秒硬顶 = 判据 ㊲，负载高会超 ⇒ 本步已自动重试一次）。\n%s"
                  % (退出码, 输出文本.strip()[-500:])), 占号
    指纹表, 读不出表 = 读盘指纹(工作树, 路径表)
    if 读不出表:
        return 2, ("**没登记**：`文件认领` 里这些件**盘上不存在**、或**不是仓内相对路径**"
                 "（不许绝对路径 / 不许 `..`）⇒ 拒收（不入认领表）：\n  %s\n"
                 "（新件请先建再认领，或用 功能 = 2 建完补一次。刚建的工作树将清掉、没留残留。）"
                 % " · ".join(读不出表)), 占号
    if 路径表 and not 指纹表:
        return 2, ("**没登记**：`文件认领` 给了 %d 件，却**一件都没读上盘** ⇒ 路径写错了。\n  %s\n"
                 "（新建的件不必先认领：`v1_edit` 功能=0 能直接建，建完指纹自动补进认领表。"
                 "刚建的工作树将清掉、没留残留 ⇒ 核对路径后重新 功能=1 登记。）"
                 % (len(路径表), " · ".join(读不出表))), 占号
    退出码, 提示文本 = 事务认领(连接, 仓根, 开工号, 指纹表, 确认重叠)
    if 退出码:
        return 退出码, 提示文本, 占号
    输出行表 = ["开工号 %s（支线 %s）" % (开工号, 分支名(开工号)),
              "工作树（读文件用这个绝对路径）：%s" % 工作树,
              "认领 %d 件" % len(指纹表)]
    if not 指纹表:
        输出行表.append("（认领集为空 —— 纯调研的活合法；要写文件就用 功能 = 2 补认领）")
    if 提示文本:
        输出行表.append(提示文本)
    占位表 = 账本.查跨开工占位(连接, 开工号, 指纹表, 僵尸表)
    if 占位表:
        输出行表.append("★ 重叠认领：\n%s" % 账本.拼冲突回执(占位表, 已确认=True))
    for 别的号, 失败原因 in 账本.查重复登记(连接, 开工号, 工作内容, 指纹表, 僵尸表):
        输出行表.append("★ 与 **%s** 疑似重复登记：%s —— 只报不拦，先查清（功能=0 可查历史）"
                    % (别的号, 失败原因))
    if 并入文本:
        输出行表.append("基线并入：" + 并入文本)
    前置行 = 账本.前置提示行()
    if 前置行:
        输出行表.append(前置行)
    输出行表.append("★ 工具行为异常 ⇒ 重启 **Hermes Agent**（客户端会缓存工具清单，重启才刷新）；"
                    "MCP 是常驻网关（43140）且带自愈重载，改 `MCP服务/**` **不必**重启它")
    return 0, "\n".join(输出行表), ""
