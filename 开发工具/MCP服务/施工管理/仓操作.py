def 查工作树归属(仓根, 开工号: str, 工作树) -> tuple:
    """工作树当前检出的 HEAD 是否 == 本腿支线的 tip ⇒ `(是否一致, 说明)`。

    为什么单列：`检查清树安全` 判的是**支线引用**已合主树，不核**工作树检出的是不是那个 tip**
    （分离 HEAD / 误检出别的提交时它照样过）⇒ 归属要单独证，空改腿才敢拿它的净树当「成果已合」。
    """
    if not Path(工作树).is_dir():
        return False, "工作树不在：%s" % 工作树
    退出码, 支线头 = 跑命令(["git", "rev-parse", "refs/heads/" + 分支名(开工号)], cwd=仓根)
    if 退出码 != 0:
        return False, "读不到支线 %s（%s）" % (分支名(开工号), 支线头.strip()[-120:])
    退出码, 树头 = 跑命令(["git", "rev-parse", "HEAD"], cwd=工作树)
    if 退出码 != 0:
        return False, "读不到工作树 HEAD"
    支线头, 树头 = 支线头.strip(), 树头.strip()
    return 支线头 == 树头, ("工作树 HEAD %s %s 支线 tip %s"
                          % (树头[:12], "==" if 支线头 == 树头 else "≠", 支线头[:12]))


def 检查清树安全(仓根, 开工号: str, 工作树) -> tuple:
    """清理前证明没有未提交改动，且支线已进入主工作树当前历史。"""
    if Path(工作树).is_dir():
        退出码, 输出文本 = 跑命令(["git", "status", "--porcelain", "-uall"], cwd=工作树)
        if 退出码 != 0 or 输出文本.strip():
            return 1, "工作树有未提交改动或状态读不出 ⇒ 拒绝清理，保留树与支线：\n%s" % 输出文本[-400:]
    退出码, 输出文本 = 跑命令(["git", "worktree", "list", "--porcelain"], cwd=仓根)
    if 退出码 != 0 or not 输出文本.startswith("worktree "):
        return 1, "无法确定主工作树 ⇒ 拒绝清理"
    主树路径 = Path(输出文本.splitlines()[0][len("worktree "):])
    if 主树路径.resolve() == Path(工作树).resolve():
        return 1, "目标是主工作树 ⇒ 拒绝清理"
    退出码, 主树提交 = 跑只读git(仓根, ["rev-parse", "HEAD"], 树根=主树路径)
    if 退出码 != 0:
        return 1, "无法读取主工作树提交 ⇒ 拒绝清理"
    退出码, 输出文本 = 跑只读git(仓根, ["show-ref", "--verify", "--quiet",
                                  "refs/heads/" + 分支名(开工号)])
    if 退出码 == 1:
        return 0, "支线已不存在"
    if 退出码 != 0:
        return 1, "无法读取支线引用 ⇒ 拒绝清理"
    退出码, 输出文本 = 跑命令(["git", "merge-base", "--is-ancestor", 分支名(开工号),
                              主树提交.strip()], cwd=仓根)
    if 退出码 != 0:
        # ★ 2026-10-10（债务 324）：支线非主树祖先时**先核「内容是否已被主干取代」**。
        #   取代腿（主干把函数整件搬走 / 同一函数两代写法）在旧口径下**两条路都堵**：
        #   合并撞结构性冲突、清树被「必须是祖先」永拒 ⇒ 只能由收口方手工 `git branch -D`。
        #   可核判据：支线树与主树**逐字节相同** ⇒ 无独有成果 ⇒ 明写「已被主干取代、建议走退场口」。
        #   内容不同 ⇒ 照旧硬拒（不猜、不自动删；要退场须走 `取代腿退场` 并显式给 `取代提交`）。
        退出码, 输出文本 = 跑命令(["git", "diff", "--quiet", 主树提交.strip(), 分支名(开工号)],
                                 cwd=仓根)
        if 退出码 == 0:
            return 3, ("支线树与主树**逐字节相同**（`git diff --quiet` 退 0）⇒ 内容已被主干取代、"
                      "无独有成果 ⇒ 走正式退场口（`v1_task` 操作 `取代腿退场`，须显式给 `取代提交`）；"
                      "旧口径下这条腿两条路都堵（合并撞结构性冲突 · 清树被「必须是祖先」永拒）")
        return 1, "支线尚未合并到主工作树或无法确认 ⇒ 拒绝清理，保留提交与支线"
    return 0, "支线已合并到主工作树"


def 取代腿退场(仓根, 开工号: str, 取代提交: str) -> tuple:
    """取代腿的**正式退场口**（债务 324）：支线不是主树祖先、但内容已被主干提交取代时，走这里删。

    「取代」= 主干后批提交已把这条腿的改动做掉了（或换成了两代写法），支线因此**永不合入**；
    旧口径下两条路都堵（合并撞结构性冲突、清树被「必须是祖先」永拒）⇒ 只能手工 `git branch -D`。

    逐条核（**一条不成立就拒**、保留树与支线并定位）：
      ① 支线存在，且**不是**主树祖先（是祖先 ⇒ 走正常 `单纯释放`，不走本口）；
      ② `取代提交` 是仓里**真实存在**的提交对象，且是**主干祖先**；
      ③ 它在支线分叉点**之后**（即真在分叉之后承接）；
      ④ 支线的改动路径集 ⊂ 取代提交的改动路径集（路径级覆盖，可核）；
      ⑤ 工作树净（`status --porcelain -uall` 空）。
    满足 ⇒ 复用 `清工作树` 删树 + 删支线；回执逐条报核过的项（留痕）。
    """
    支线 = 分支名(开工号)
    if not 支线在吗(仓根, 开工号):
        return 2, "支线 `%s` 不存在 ⇒ 无物可退场（树与支线都不在时不必走本口）" % 支线
    退出码, 输出文本 = 跑命令(["git", "worktree", "list", "--porcelain"], cwd=仓根)
    if 退出码 != 0 or not 输出文本.startswith("worktree "):
        return 2, "无法确定主工作树 ⇒ 拒绝退场"
    主树路径 = Path(输出文本.splitlines()[0][len("worktree "):])
    退出码, 主树提交 = 跑命令(["git", "rev-parse", "HEAD"], cwd=主树路径)
    if 退出码 != 0:
        return 2, "无法读取主工作树提交 ⇒ 拒绝退场"
    主树提交 = 主树提交.strip()
    退出码, _ = 跑命令(["git", "merge-base", "--is-ancestor", 支线, 主树提交], cwd=仓根)
    if 退出码 == 0:
        return 2, "支线已是主树祖先 ⇒ 走正常 `单纯释放`（本口只收**取代腿**）"
    退出码, _ = 跑命令(["git", "cat-file", "-e", 取代提交 + "^{commit}"], cwd=仓根)
    if 退出码 != 0:
        return 2, "`取代提交` %r 不是仓里真实存在的提交对象 ⇒ 拒绝退场（不许凭声明删）" % 取代提交
    退出码, _ = 跑命令(["git", "merge-base", "--is-ancestor", 取代提交, 主树提交], cwd=仓根)
    if 退出码 != 0:
        return 2, "`取代提交` %s 不是主干祖先 ⇒ 拒绝退场（它没进主干，谈不上取代）" % 取代提交[:12]
    退出码, 分叉点 = 跑命令(["git", "merge-base", 主树提交, 支线], cwd=仓根)
    if 退出码 != 0:
        return 2, "算不出支线分叉点 ⇒ 拒绝退场"
    分叉点 = 分叉点.strip()
    退出码, _ = 跑命令(["git", "merge-base", "--is-ancestor", 分叉点, 取代提交], cwd=仓根)
    if 退出码 != 0:
        return 2, ("`取代提交` %s 在支线分叉点（%s）之前 ⇒ 它取代不了这条腿，拒绝退场"
                  % (取代提交[:12], 分叉点[:12]))
    if 取代提交.strip() == 分叉点:
        return 2, ("`取代提交` 就是支线分叉点本身（%s）⇒ 它没在分叉之后承接任何东西，拒绝退场"
                  % 分叉点[:12])
    退出码, 支线路径 = 跑命令(["git", "diff", "--name-only", 分叉点, 支线], cwd=仓根)
    if 退出码 != 0:
        return 2, "读不出支线改动路径 ⇒ 拒绝退场"
    退出码, 取代路径 = 跑命令(["git", "show", "--name-only", "--format=", 取代提交], cwd=仓根)
    if 退出码 != 0:
        return 2, "读不出取代提交的改动路径 ⇒ 拒绝退场"
    支线集 = {行文本.strip() for 行文本 in 支线路径.splitlines() if 行文本.strip()}
    取代集 = {行文本.strip() for 行文本 in 取代路径.splitlines() if 行文本.strip()}
    未覆盖 = sorted(支线集 - 取代集)
    if 未覆盖:
        return 2, ("取代提交 %s 没覆盖这些路径 ⇒ 拒绝退场（可能有独有成果）：%s"
                  % (取代提交[:12], " · ".join(未覆盖[:8])))
    工作树 = 找工作树(仓根, 开工号)
    if 工作树 is not None and Path(工作树).is_dir():
        退出码, 状态文本 = 跑命令(["git", "status", "--porcelain", "-uall"], cwd=工作树)
        if 退出码 != 0 or 状态文本.strip():
            return 2, "工作树有未提交改动或状态读不出 ⇒ 拒绝退场，保留树与支线：\n%s" % 状态文本[-400:]
    退出码, 说明 = 清工作树(仓根, 开工号)
    行表 = ["取代腿退场（逐条核过）：",
           "  ① 支线 %s 非主树祖先 ✓" % 支线,
           "  ② 取代提交 %s 是主干祖先 ✓" % 取代提交[:12],
           "  ③ 它在分叉点 %s 之后 ✓" % 分叉点[:12],
           "  ④ 支线改动 %d 条路径全被取代提交覆盖 ✓" % len(支线集),
           "  ⑤ 工作树净 ✓",
           "  清树：%s" % 说明]
    return 退出码, "\n".join(行表)


def 清工作树(仓根, 开工号: str) -> tuple:
    """移工作树 + 删支线 ⇒ `(退出码, 一句话说明)`。**幂等**：树与支线都不在 ⇒ 什么都不做、返回成功。

    `git worktree remove` 只移树、**保留支线**（便于查它的提交）⇒ 这里补删。
    ★ 回执由本件**就地拼**（2026-10-01 修）：原先直接转发那条命令的输出，于是回执里同时出现
    「分支 `腿/<名>` 保留，便于查它的提交」（脚本的话）与 git 的 `Deleted branch 腿/<名>`
    （**这里真删了**）⇒ **自相矛盾**，收口方会以为还能靠支线查提交。删支线是刻意的（提交已在
    origin/腿/<名> 与主干历史里），故文案要如实写「已删」。
    ★ 树与支线都早已不在时，那两条命令会报
    `fatal: '…' is not a working tree` / `error: branch '…' not found` ⇒ 调用方把
    「早已清干净」误判成失败。故**先问存在性再动手**（存在性走 `找工作树` / `支线在吗`）。
    """
    工作树路径 = 找工作树(仓根, 开工号)
    支线在 = 支线在吗(仓根, 开工号)
    if 工作树路径 is None and not 支线在:
        return 0, "无物可清（工作树与支线都不在）"
    码一 = 码二 = 0
    说明表 = []
    if 工作树路径 is not None:
        # ★ 债务 565：原先转发 `开发工具/并行工作树.sh 移除`（仓内脚本）⇒ 合成仓测试面要逐层
        #   造 rust-toolchain.toml / 同级工作树布局，真夹具永远走不到。改为**直接走 git**：
        #   脏树由 git 拒（`worktree remove` 对未提交改动报错）⇒ 安全口径一字未减，
        #   而不再依赖仓内脚本与它那套布局。
        # 环境步同建树口径（`超时秒数=None`）：移除带构建缓存的大树可能 >5s，默认 5 秒会把
        # 它误报成「工作树没移除掉（退出码 -1）」（2026-10-05 修 · 与建树 `:89` 对齐）。
        码一, 出一 = 跑命令(["git", "worktree", "remove", str(工作树路径)], cwd=仓根, 超时秒数=None)
        if 码一 == 0:
            说明表.append("工作树已移除")
        else:
            说明表.append("工作树**没**移除掉（退出码 %d）：%s" % (码一, 出一.strip()[-300:]))
    if 支线在 and 码一 == 0:
        码二, 出二 = 跑命令(["git", "branch", "-D", 分支名(开工号)], cwd=仓根)
        if 码二 == 0:
            说明表.append("分支 `%s` 已删" % 分支名(开工号))
        else:
            说明表.append("分支 `%s` **没**删掉（退出码 %d）：%s"
                      % (分支名(开工号), 码二, 出二.strip()[-300:]))
    return (码一 or 码二), " · ".join(说明表)


def 读盘指纹(工作树: Path, 相对路径表: list) -> tuple:
    """认领那一刻 MCP **当场读盘**算指纹 ⇒ `({路径: 指纹}, 读不出的路径表)`。

    agent 只给路径、不传指纹。读不出的件（路径写错 / 不存在）**不静默跳过** —— 报出来，
    由调用方**拒收**（2026-10-01：认领不存在的路径必须拒，不许收进认领表 —— 收进去会让
    `释放` 的 `git add` 撞 `fatal: pathspec … did not match any files`，整条腿卡死）。
    """
    指纹表, 读不出表 = {}, []
    for 相对路径 in 相对路径表:
        相对路径项 = str(相对路径).strip()
        if not 相对路径项:
            continue
        # 只认仓内相对路径（口径与 `修改._读一条改动` 同一份）：绝对路径 / `..` **fail-closed 拒收**
        # —— 原先只 `strip()` ⇒ 绝对路径被静默收进认领表，后续 `对账` 会拿 `工作树 / "/etc/hosts"`
        # = `/etc/hosts` 去比指纹（认领表可被塞进树外/仓外路径）。
        if 相对路径项.startswith("/") or ".." in Path(相对路径项).parts:
            读不出表.append(相对路径项)
            continue
        from .路径守卫 import 核树内路径
        try:
            件路径 = 核树内路径(工作树, 相对路径项)
        except ValueError:
            读不出表.append(相对路径项)
            continue
        if not 件路径.is_file():
            读不出表.append(相对路径项)
            continue
        指纹表[相对路径项] = 文件指纹(str(件路径))
    return 指纹表, 读不出表


def 变更路径表(工作树) -> tuple:
    """`git status --porcelain` ⇒ `(退出码, 变过的路径表 或 说明)`。**一处解析**：`释放` 的
    越界检测与 `生成物记账` 的产出识别共用它 —— 不各写一份「什么算脏」。
    """
    退出码, 输出文本 = 跑命令(["git", "status", "--porcelain", "-uall"], cwd=工作树)
    if 退出码 != 0:
        return 退出码, "git status 失败（查不清盘上动了什么）：\n%s" % 输出文本.strip()[-400:]
    路径表 = []
    for 源码行 in 输出文本.splitlines():
        if not 源码行.strip():
            continue
        路径 = 源码行[3:].strip().strip('"')
        if " -> " in 路径:
            路径 = 路径.split(" -> ")[-1].strip().strip('"')
        if 路径:
            路径表.append(路径)
    return 0, 路径表
