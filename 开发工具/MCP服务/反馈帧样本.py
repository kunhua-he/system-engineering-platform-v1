def 帧调用(帧号, 操作名, 参数表=None, 开工号=None) -> dict:
    """拼一条 `tools/call` 帧（`开工ID` 是**顶层**三字段之一，不塞进 `参数`）。"""
    帧实参 = {"操作": 操作名}
    if 开工号:
        帧实参["开工ID"] = 开工号
    if 参数表:
        帧实参["参数"] = 参数表
    return {"jsonrpc": "2.0", "id": 帧号, "method": "tools/call",
            "params": {"name": 帧工具名, "arguments": 帧实参}}


def 送帧(仓根, 运行根, 命令表: list) -> tuple:
    """真 stdio 子进程送一批帧 ⇒ `(进程退出码, 响应读数表)`；起不来 / 超时 ⇒ `(-1, [])`。

    `env` **显式**给 `V1_RUN_DATA_ROOT`（独立根）—— 不靠外层 shell 赋值，故断的是本进程真环境。
    """
    输入文本 = "".join(json.dumps(帧项, ensure_ascii=False) + "\n" for 帧项 in 命令表)
    try:
        回执 = subprocess.run([sys.executable, "-B", "开发工具/MCP服务.py"], cwd=str(仓根),
                          input=输入文本, capture_output=True, text=True,
                          env=干净环境({覆盖变量名: str(运行根)}), timeout=帧超时秒)
    except (OSError, subprocess.SubprocessError):
        return -1, []
    响应表 = []
    for 源码行 in 回执.stdout.splitlines():
        if not 源码行.startswith("{"):
            continue
        try:
            响应项 = json.loads(源码行)
        except ValueError:
            continue
        if isinstance(响应项, dict) and 响应项.get("id") is not None:
            响应表.append(响应项)
    return 回执.returncode, 响应表


def 取信封(响应表: list, 帧号) -> dict:
    """某帧响应 ⇒ 内层信封（缺帧 / 形状不对 ⇒ 空字典，断言自然不通过）。"""
    for 响应项 in 响应表:
        if 响应项.get("id") != 帧号:
            continue
        内容表 = ((响应项.get("result") or {}).get("content") or [])
        if not 内容表:
            return {}
        return 读回执(内容表[0].get("text"))
    return {}


def 取码(响应表: list, 帧号) -> int:
    """某帧响应的**业务退出码**（信封顶层 `退出码`）；缺帧给 -99（不写成 0）。"""
    return 取信封(响应表, 帧号).get("退出码", -99)


def 取结果(响应表: list, 帧号) -> dict:
    """某帧响应的**结构化结果**（信封 `结果` 是对象才给；否则空字典）。"""
    结构读数 = 取信封(响应表, 帧号).get("结果")
    return 结构读数 if isinstance(结构读数, dict) else {}


def 取说明(响应表: list, 帧号) -> str:
    """某帧响应的 `说明`（退出码非 0 时它是拒因全文）。"""
    return str(取信封(响应表, 帧号).get("说明") or "")


def 取错误种类(响应表: list, 帧号) -> str:
    """某帧响应的 `错误.种类`（参数面拒的分类）；没有给空串。"""
    return str((取信封(响应表, 帧号).get("错误") or {}).get("种类") or "")


def 送HTTP帧(仓根, 命令表: list) -> tuple:
    """真 HTTP 环回（进程内、真传输处理器）送一批 `tools/call` 帧 ⇒ `(状态码表, 信封表)`。

    进程内环回 ⇒ 运行数据根就是**本进程**的 env（`跑帧样本` 已显式指到临时根），与 stdio 子进程
    走的是**同一份** `工具表` 与 `参数规范.网关派发` ⇒ 两条通道的网关参数面覆盖等价。
    """
    from .工具 import 工具表 as 登记工具表
    from . import http传输样本
    服务对象, 监听端口 = http传输样本._起环回(仓根, 登记工具表)
    状态码表 = []
    信封表 = []
    try:
        http传输样本._调用(监听端口, "POST", http传输样本._报文(
            {"jsonrpc": "2.0", "id": 0, "method": "initialize",
             "params": {"protocolVersion": "2025-06-18", "capabilities": {},
                        "clientInfo": {"name": "反馈帧样本", "version": "0"}}}),
            http传输样本.标准头)
        for 帧项 in 命令表:
            应答 = http传输样本._调用(监听端口, "POST", http传输样本._报文(帧项),
                              http传输样本.标准头)
            状态码表.append(应答[0])
            信封表.append(读回执(json.loads(应答[3])["result"]["content"][0]["text"]))
    finally:
        服务对象.shutdown()
        服务对象.server_close()
    return 状态码表, 信封表


