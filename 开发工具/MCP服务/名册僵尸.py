# -*- coding: utf-8 -*-
r"""名册僵尸 —— `v1_repo 环境体检` 的「名册僵尸行」读数：库 `命名登记` 里出现次数 = 0 的名字。

**为何单独一件**：`仓状态.py` 已 380 行（判据 ⑲ 单件 ≤400）⇒ 增量读数另开子模块
（同层互依不算违规，见 `AGENTS.md` §五）。

**口径**：`命名登记.出现次数` 由 `开发工具/信息核心/落库.py` 维护（全树重扫 ⇒ 在现量代码里
出现几次；本次没扫到的名字**归零**）。本口**只读**：出现次数 = 0 ⇒「现量代码里已无此名」
⇒ 陈旧行（僵尸）。**只报告不自动删** —— 删行走 `信息核心.py 登记 --删`，且要人确认
（`命名登记` 是受版本表，跨腿删有重放风险）。

**未判不是通过**：整表全 0 ⇒ `出现次数` 没维护过（`落库` 未跑）⇒ 如实说「未判」，
不把满表陈旧行当僵尸报（判据的可信性.md 第二节：空集 / 未维护是未判，不是通过）。
"""
import sqlite3


def 读僵尸行(库件, 记录条数: int) -> list:
    """⇒ 僵尸行报告（有界 `记录条数`）；库不在 / 读不动 ⇒ 如实说，不假装空。

    `库件` = 规则库绝对路径（调用方按 `仓根` 拼，本口不另持路径字面量）。
    """
    if not 库件.is_file():
        return ["名册僵尸行：库不在（%s）⇒ 未判" % 库件]
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
        try:
            读数 = 连接.execute(
                "select count(*), coalesce(sum(出现次数 = 0), 0) from 命名登记").fetchone()
            名表 = [名字 for (名字,) in 连接.execute(
                "select 名字 from 命名登记 where 出现次数 = 0 order by 名字 limit ?",
                (记录条数,))]
        finally:
            连接.close()
    except sqlite3.Error as 错误:
        return ["名册僵尸行：`命名登记` 读不动（%s）⇒ 未判" % 错误]
    if 读数[0] and 读数[1] == 读数[0]:
        return ["名册僵尸行：%d 行全 0 ⇒ 未判（`出现次数` 未维护，先跑 "
                "`python3 开发工具/信息核心/信息核心.py 落库`）" % 读数[0]]
    行表 = ["名册僵尸行（`命名登记.出现次数`=0 ⇒ 现量代码里已无此名，由 `落库` 维护）："
           "登记 %d 行 · 疑似僵尸 %d 行" % (读数[0], 读数[1])]
    for 名字 in 名表:
        行表.append("  僵尸  %s" % 名字)
    if 读数[1] > 记录条数:
        行表.append("  …（还有 %d 行未列出）" % (读数[1] - 记录条数))
    return 行表
