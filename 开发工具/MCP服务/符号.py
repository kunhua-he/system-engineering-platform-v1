# -*- coding: utf-8 -*-
"""符号 —— `v1_symbol` 的实现：查代码地图（**带开工号就查那条工作树的索引**）。

**合同**（W3 **唯一**）：`{开工ID?, 操作, 参数:{…}}` —— **不认旧扁平入参**（`关键词` /
`限定名` / `关系` 不直接在顶层给；要搜就给 `操作` = `搜符号` ＋ `参数.关键词`）。操作表住
`操作_符号.py`（W3 加载器 glob 合并），**必需 / 可选**两列由 `参数规范` 用来拒未知键，本件只管执行：

  · `搜符号`   —— 搜符号（关键词 / `路径` 前缀 / `类型`，**定义优先**排序；截断如实报总数）
  · `查出现位` —— 精确查一个符号的全部出现位（定义 + 引用）
  · `查关系`   —— 调用者 / 被调用 / 影响面（走索引器自带 CLI）
  · `列符号`   —— 列某路径前缀下的全部定义（代理不必再用 `git ls-tree` 拼）
  · `死代码`   —— 零消费者**候选**（**≠ 死代码证明**，须用 `限定名` 查出现位复核）

**未知键一次拒**（不静默忽略）：顶层只认 `开工ID` / `操作` / `参数`；`参数` 里只认操作表声明的
`必需` / `可选`。工具面（`参数规范.网关派发`）与本件**两层同口径** —— 直接调 `派发` 也不放行未知键。

**索引必须按树查**：一开工一工作树，那条树的索引是它自带的（`.codegraph/` 未跟踪 ⇒
`git worktree add` 不带过来，登记时在那棵树里单独建过）。不给 `开工ID` ⇒ 查**主仓**
（`落点.仓根`；主仓无源码时如实报「当前树无源码」，不返回空）。

**不给指纹**：指纹归账本管，agent 全程不碰（见 `修改.py`）。返回一个没人用的字段只会误导。

**关系走索引器自带的 CLI**（`callers` / `callees` / `impact`）：关系是索引器自带的语义，
它的库表结构是实现细节 —— 吃 CLI 输出，索引器升级了本件不用跟着改。

**陈旧提示只此一份**：由 `查索引状态` 判，**在派发层统一附在回执头**（各条路共享），不各写一份 ——
陈旧**附警告照答**，拒答只限缺失 / 损坏。
"""

