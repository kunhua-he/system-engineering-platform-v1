# -*- coding: utf-8 -*-
"""符号 —— `v1_symbol` 的实现：查代码地图（**带开工号就查那条工作树的索引**）。

**参数在就是选它**（不给数字型的选择码 —— 一个执行窗口不需要快捷键）：

  · `关键词`            —— 搜符号：名字 / 限定名 / 声明 / 路径的子串
  · `限定名`            —— 精确查一个符号的**全部出现位**（定义 + 引用）
  · `限定名` + `关系`   —— 查这个符号的关系：`调用者` / `被调用` / `影响面`
  · 一个都不给 ⇒ 报「你要查什么」（**不静默返回空** —— 空集是未判，不是「没有」）

**索引必须按树查**：一开工一工作树，那条树的索引是它自带的（`.codegraph/` 未跟踪 ⇒
`git worktree add` 不带过来，登记时在那棵树里单独建过）。不带 `开工ID` 就查主工作树的索引。

**不给指纹**：指纹归账本管，agent 全程不碰（见 `修改.py`）。返回一个没人用的字段只会误导。

**关系走索引器自带的 CLI**（`callers` / `callees` / `impact`）：关系是索引器自带的语义，
它的库表结构是实现细节 —— 吃 CLI 输出，索引器升级了本件不用跟着改。
"""

import io
from contextlib import redirect_stdout
from pathlib import Path

from 代码地图 import 查符号, 出现位置, 库目录名, 库文件名, 库路径
from 代码地图.索引库 import 报缺索引器, 找索引器命令

from . import 开工账本 as 账本

关系词表 = ("调用者", "被调用", "影响面")
关系命令 = {"调用者": "callers", "被调用": "callees", "影响面": "impact"}
超时查询秒 = 5
源码上限行 = 40


def _查询根(开工号: str, 仓根) -> tuple:
    """`开工号` ⇒ `(查询根, 索引库路径, 树名, 错误)`。不给开工号就落主工作树。"""
    if not 开工号:
        return Path(仓根), 库路径(), "主工作树", ""
    连接 = 账本.连账本()
    try:
        开工记录 = 账本.读开工(连接, 开工号)
    finally:
        连接.close()
    if not 开工记录:
        return Path(仓根), 库路径(), "", "没有这条开工：%s ⇒ 先 `v1_task` 功能 = 1 登记" % 开工号
    工作树 = str(开工记录["工作树"] or "").strip()
    if not 工作树:
        return Path(仓根), 库路径(), "", ("那条开工（%s）的 `工作树` 是空的 ⇒ 账本坏了，"
                                     "不拿当前目录顶替；找收口方核账本" % 开工号)
    根目录 = Path(工作树)
    if not 根目录.is_dir():
        return 根目录, 根目录 / 库目录名 / 库文件名, "", "那条开工的工作树不在了：%s" % 根目录
    return 根目录, 根目录 / 库目录名 / 库文件名, "%s（支线 %s）" % (开工号, 开工记录["分支名"]), ""


def _源码块(根目录: Path, 路径: str, 起始行: int, 末行: int, 上限行: int = 源码上限行) -> str:
    """截这个符号的源码块（**带行号**，给人看）。读不动就如实说，不假装空。"""
    件路径 = 根目录 / 路径
    try:
        行表 = 件路径.read_text(encoding="utf-8").split("\n")
    except OSError:
        行表 = []
    if not 行表 or not (1 <= 起始行 <= len(行表)):
        return "    （读不到源码：%s）" % 路径
    尾部 = min(末行 or 起始行, 起始行 + 上限行 - 1, len(行表))
    return "\n".join("    %d| %s" % (号值, 行表[号值 - 1]) for 号值 in range(起始行, 尾部 + 1))


def 搜定义(查询根: Path, 索引库, 关键词: str, 条数: int, 要源码: bool) -> str:
    结果 = 查符号(关键词, 结果上限=条数, 库路径=索引库, 根目录=查询根)
    if not 结果["总数"]:
        return ("没有命中「%s」的符号（搜的面：名字 · 限定名 · 声明 · 路径）。"
              "换个词，或给一段路径试试" % 关键词)
    输出行表 = ["命中 %d 个符号（扫过 %d 条）：" % (结果["总数"], 结果["扫过"])]
    for 命中记录 in 结果["命中"]:
        输出行表.append("  %s:%d–%d  %s  %s  [出现 %d 处]"
                    % (命中记录["路径"], 命中记录["行"], 命中记录["末行"] or 命中记录["行"],
                       命中记录["种类"] or "—", 命中记录["限定名"], 命中记录["出现数"]))
        if 要源码:
            输出行表.append(_源码块(查询根, 命中记录["路径"], 命中记录["行"], 命中记录["末行"] or 命中记录["行"]))
    if 结果["总数"] > len(结果["命中"]):
        输出行表.append("  …（还有 %d 个，加关键词收窄，或调 `条数`）"
                    % (结果["总数"] - len(结果["命中"])))
    return "\n".join(输出行表)


def 查出现位(查询根: Path, 索引库, 限定名: str, 条数: int, 要源码: bool) -> str:
    结果 = 出现位置(限定名, 结果上限=条数, 库路径=索引库)
    if not 结果["总数"]:
        return ("索引里没有 `%s`（先确认索引是新的；或换用限定名 —— 先用 `关键词` 查一下）"
              % 限定名)
    输出行表 = ["`%s` 出现 %d 处（口径：%s）：" % (限定名, 结果["总数"], 结果["口径"])]
    for 文件路径, 行号, 列号 in 结果["位置"]:
        输出行表.append("  %s:%d:%d" % (文件路径, 行号, 列号))
        if 要源码:
            输出行表.append(_源码块(查询根, 文件路径, 行号, 行号, 上限行=6))
    if 结果["总数"] > len(结果["位置"]):
        输出行表.append("  …（还有 %d 处，调 `条数`）" % (结果["总数"] - len(结果["位置"])))
    return "\n".join(输出行表)


def 派发(参数表: dict, 仓根) -> tuple:
    """`v1_symbol` 的入口。"""
    from .仓操作 import 跑命令

    开工号 = str(参数表.get("开工ID") or "").strip()
    关键词 = str(参数表.get("关键词") or "").strip()
    限定名 = str(参数表.get("限定名") or "").strip()
    关系 = str(参数表.get("关系") or "").strip()
    try:
        条数 = int(参数表.get("条数") or 20)
    except (TypeError, ValueError):
        return 2, "`条数` 要是整数"
    要源码 = bool(参数表.get("带源码"))

    if 关键词 and 限定名:
        return 2, "`关键词` 与 `限定名` 一次只给一个（参数在就是选它）"
    if not 关键词 and not 限定名:
        return 2, ("你要查什么？给 `关键词`（搜符号）· `限定名`（查出现位）· "
                 "`限定名` + `关系`（查调用者/被调用/影响面）")
    if 关系 and not 限定名:
        return 2, "`关系` 要配 `限定名`（关系是「这个符号」和谁有关系）"
    if 关系 and 关系 not in 关系词表:
        return 2, "`关系` 只认 %s，收到 %r" % (" / ".join(关系词表), 关系)

    查询根, 索引库, 树名, 错误 = _查询根(开工号, 仓根)
    if 错误:
        return 1, 错误
    在哪儿 = "在「%s」查的" % 树名
    # ★ 索引不在 ⇒ 定义面会静默空（`查符号` 得 0 条、`出现位置` 口径「没有索引」）——
    #   必须如实报「索引不在」，**不是「没有这个符号」**（假绿会让 agent 据此删改）。
    if not Path(索引库).is_file():
        return 1, ("%s\n索引不在：%s\n★ **这不是「没有这个符号」** —— 索引不在时定义面会静默空，"
                   "据此删改会出错。先建索引：`python3 开发工具/代码地图.py 建`" % (在哪儿, 索引库))

    if 关系:
        # 命令名只此一份（`索引库.找索引器命令()`）；不在 ⇒ 走那一份装法指引（`索引库.报缺索引器`），
        # 别拿空串去跑命令（`跑命令([""])` 只回一句 PermissionError，不是指引）。
        命令 = 找索引器命令()
        if not 命令:
            文本缓冲 = io.StringIO()
            with redirect_stdout(文本缓冲):
                报缺索引器()
            return 1, "%s\n%s" % (在哪儿, 文本缓冲.getvalue().strip())
        退出码, 输出文本 = 跑命令([命令, 关系命令[关系], 限定名], cwd=查询根, 超时秒数=超时查询秒)
        if 退出码 != 0:
            return 退出码, "%s\n查 `%s` 的%s失败：\n%s" % (在哪儿, 限定名, 关系, 输出文本.strip()[-400:])
        全文 = 输出文本.strip()
        正文 = 全文[:4000]
        if len(全文) > 4000:
            正文 += ("\n  …（已截断 %d 行：全文 %d 字，这里只留前 4000 字；要看全用 `限定名` "
                   "查出现位，或收窄符号）" % (全文.count("\n") - 正文.count("\n"), len(全文)))
        # ★ 空集是**未判**，不是「没有」。索引器的调用边有系统性假阴性，实测：
        #   `读认领` / `连账本` 明明被多处调用，`callers` 却说 No callers found；
        #   而 `文件指纹` / `出现位置`（**裸名字**调用）能正常列出 13 / 4 个。
        #   差别在调用写法：`模块.函数(...)` 这种**带限定名**的调用它解析不出来。
        #   所以这里必须把「没查到」和「确实没有」分开 —— 否则 agent 会照着空集去删东西。
        if ("No callers found" in 正文 or "No callees found" in 正文
                or "No affected symbols found" in 正文):
            正文 += ("\n★ 上面这句是**索引器的说法，不等于真没有**：实测它对 `模块.函数(...)` 这类"
                   "**带限定名**的调用解析不出来（裸名字调用才认得）。复核办法：用 `限定名` 查**出现位**，"
                   "看调用点里有没有这个写法。")
        return 0, "%s\n`%s` 的%s：\n%s" % (在哪儿, 限定名, 关系, 正文)
    if 限定名:
        return 0, "%s\n%s" % (在哪儿, 查出现位(查询根, 索引库, 限定名, 条数, 要源码))
    return 0, "%s\n%s" % (在哪儿, 搜定义(查询根, 索引库, 关键词, 条数, 要源码))
