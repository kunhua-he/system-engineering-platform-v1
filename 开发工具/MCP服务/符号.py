# -*- coding: utf-8 -*-
"""符号 —— `v1_symbol` 的实现：查代码地图（**带开工号就查那条工作树的索引**）。

**参数在就是选它**（不给数字型的选择码 —— 一个执行窗口不需要快捷键）：

  · `关键词`            —— 搜符号：名字 / 限定名 / 声明 / 路径的子串
  · `限定名`            —— 精确查一个符号的**全部出现位**（定义 + 引用）
  · `限定名` + `关系`   —— 查这个符号的关系：`调用者` / `被调用` / `影响面`
  · 一个都不给 ⇒ 报「你要查什么」（**不静默返回空** —— 空集是未判，不是「没有」）

**索引必须按树查**：一开工一工作树，那条树的索引是它自带的（`.codegraph/` 未跟踪 ⇒
`git worktree add` 不带过来，登记时在那棵树里单独建过）。不带 `开工ID` 就查主工作树的索引。

**不给指纹**：指纹归账本管，agent 全程不碰（见 `修改.py`）。返回一个没人用的字段只会误导。

**关系走索引器自带的 CLI**（`callers` / `callees` / `impact`）：关系是索引器自带的语义，
它的库表结构是实现细节 —— 吃 CLI 输出，索引器升级了本件不用跟着改。
"""

from pathlib import Path

from 代码地图 import 查, 出现位置, 库路径
from 代码地图.索引库 import 找命令

from . import 开工账本 as 账本

关系词表 = ("调用者", "被调用", "影响面")
关系命令 = {"调用者": "callers", "被调用": "callees", "影响面": "impact"}
超时查询秒 = 5
源码上限行 = 40


def _查询根(开工号: str, 仓根) -> tuple:
    """`开工号` ⇒ `(查询根, 索引库路径, 树名, 错误)`。不给开工号就落主工作树。"""
    if not 开工号:
        return Path(仓根), 库路径(), "主工作树", ""
    连 = 账本.连账本()
    try:
        一条 = 账本.读开工(连, 开工号)
    finally:
        连.close()
    if not 一条:
        return Path(仓根), 库路径(), "", "没有这条开工：%s ⇒ 先 `v1_task` 功能 = 1 登记" % 开工号
    根 = Path(一条["工作树"])
    if not 根.is_dir():
        return 根, 根 / ".codegraph" / "codegraph.db", "", "那条开工的工作树不在了：%s" % 根
    return 根, 根 / ".codegraph" / "codegraph.db", "%s（支线 %s）" % (开工号, 一条["分支名"]), ""


def _带源码(根: Path, 路径: str, 起始行: int, 末行: int, 上限行: int = 源码上限行) -> str:
    """截这个符号的源码块（**带行号**，给人看）。读不动就如实说，不假装空。"""
    件路径 = 根 / 路径
    try:
        行表 = 件路径.read_text(encoding="utf-8").split("\n")
    except OSError:
        行表 = []
    if not 行表 or not (1 <= 起始行 <= len(行表)):
        return "    （读不到源码：%s）" % 路径
    末 = min(末行 or 起始行, 起始行 + 上限行 - 1, len(行表))
    return "\n".join("    %d| %s" % (号, 行表[号 - 1]) for 号 in range(起始行, 末 + 1))


def 搜定义(查询根: Path, 索引库, 关键词: str, 条数: int, 要源码: bool) -> str:
    结果 = 查(关键词, 上限=条数, 库路径=索引库, 根=查询根)
    if not 结果["总数"]:
        return ("没有命中「%s」的符号（搜的面：名字 · 限定名 · 声明 · 路径）。"
              "换个词，或给一段路径试试" % 关键词)
    输出行表 = ["命中 %d 个符号（扫过 %d 条）：" % (结果["总数"], 结果["扫过"])]
    for 一条 in 结果["命中"]:
        输出行表.append("  %s:%d–%d  %s  %s  [出现 %d 处]"
                    % (一条["路径"], 一条["行"], 一条["末行"] or 一条["行"],
                       一条["种类"] or "—", 一条["限定名"], 一条["出现数"]))
        if 要源码:
            输出行表.append(_带源码(查询根, 一条["路径"], 一条["行"], 一条["末行"] or 一条["行"]))
    if 结果["总数"] > len(结果["命中"]):
        输出行表.append("  …（还有 %d 个，加关键词收窄，或调 `条数`）"
                    % (结果["总数"] - len(结果["命中"])))
    return "\n".join(输出行表)


def 查出现位(查询根: Path, 索引库, 限定名: str, 条数: int, 要源码: bool) -> str:
    结果 = 出现位置(限定名, 上限=条数, 库路径=索引库)
    if not 结果["总数"]:
        return ("索引里没有 `%s`（先确认索引是新的；或换用限定名 —— 先用 `关键词` 查一下）"
              % 限定名)
    输出行表 = ["`%s` 出现 %d 处（口径：%s）：" % (限定名, 结果["总数"], 结果["口径"])]
    for 文件路径, 行号, 列号 in 结果["位置"]:
        输出行表.append("  %s:%d:%d" % (文件路径, 行号, 列号))
        if 要源码:
            输出行表.append(_带源码(查询根, 文件路径, 行号, 行号, 上限行=6))
    if 结果["总数"] > len(结果["位置"]):
        输出行表.append("  …（还有 %d 处，调 `条数`）" % (结果["总数"] - len(结果["位置"])))
    return "\n".join(输出行表)


def 派(参数表: dict, 仓根) -> tuple:
    """`v1_symbol` 的入口。"""
    from .开工 import 跑

    开工号 = str(参数表.get("开工ID") or "").strip()
    关键词 = str(参数表.get("关键词") or "").strip()
    限定名 = str(参数表.get("限定名") or "").strip()
    关系 = str(参数表.get("关系") or "").strip()
    try:
        条数 = int(参数表.get("条数") or 20)
    except (TypeError, ValueError):
        return 2, "`条数` 要是整数"
    要源码 = bool(参数表.get("带源码"))

    if 关键词 and 限定名:
        return 2, "`关键词` 与 `限定名` 一次只给一个（参数在就是选它）"
    if not 关键词 and not 限定名:
        return 2, ("你要查什么？给 `关键词`（搜符号）· `限定名`（查出现位）· "
                 "`限定名` + `关系`（查调用者/被调用/影响面）")
    if 关系 and not 限定名:
        return 2, "`关系` 要配 `限定名`（关系是「这个符号」和谁有关系）"
    if 关系 and 关系 not in 关系词表:
        return 2, "`关系` 只认 %s，收到 %r" % (" / ".join(关系词表), 关系)

    查询根, 索引库, 树名, 错误 = _查询根(开工号, 仓根)
    if 错误:
        return 1, 错误
    在哪儿 = "在「%s」查的" % 树名

    if 关系:
        # 命令名只此一份（`索引库.找命令()` —— 找不到会给可执行的安装指引，不是一句 traceback）
        码, 出 = 跑([找命令(), 关系命令[关系], 限定名], cwd=查询根, 超时秒数=超时查询秒)
        if 码 != 0:
            return 码, "%s\n查 `%s` 的%s失败：\n%s" % (在哪儿, 限定名, 关系, 出.strip()[-400:])
        return 0, "%s\n`%s` 的%s：\n%s" % (在哪儿, 限定名, 关系, 出.strip()[:4000])
    if 限定名:
        return 0, "%s\n%s" % (在哪儿, 查出现位(查询根, 索引库, 限定名, 条数, 要源码))
    return 0, "%s\n%s" % (在哪儿, 搜定义(查询根, 索引库, 关键词, 条数, 要源码))
