# -*- coding: utf-8 -*-
"""作业列表 —— `v1_job` 的 `list` 实现：**有界**枚举最近后台作业（非终态在前）。

**为什么单开一件**（判据 ⑲ 单源文件 ≤400 行）：`作业.py` 已接近上限，把这**只读**的一档
（列作业 + 开工号还原）搬出来，`作业.py` 只管启动 / 查询 / 取消。

**只读**：本件只读账本（`作业账本.列作业`），不建库、不迁移、不起进程。
"""
from pathlib import Path

from .shell import 开工号形状
from ..作业账本 import 连账本, 列作业


def 取开工号(工作树文本: str) -> str:
    """工作树路径尾段若是开工号形状 ⇒ 它；否则空串（那本作业跑在服务仓根）。"""
    尾段 = Path(工作树文本).name
    return 尾段 if 开工号形状.fullmatch(尾段) else ""


def 列作业行(开工号, 参数表: dict, 仓根) -> tuple:
    """`list` ⇒ `(退出码, 输出文本)`。作业账本是全局的（`开工号` 不参与）；有界（条数 1..100）。"""
    上限 = 参数表.get("条数", 20)
    if type(上限) is not int or not 1 <= 上限 <= 100:
        return 2, "条数须整数 1..100（默认 20）"
    连接 = 连账本()
    try:
        行表 = 列作业(连接, 上限)
    finally:
        连接.close()
    输出行表 = ["作业账本：%d 条（上限 %d；非终态在前）" % (len(行表), 上限)]
    if not 行表:
        输出行表.append("（本机账本里还没有作业）")
    for 作业行 in 行表:
        输出行表.append("  %s · 具名=%s · 开工=%s · 状态=%s · 起=%s · 止=%s" % (
            作业行["任务ID"], 作业行["具名"] or "（无）",
            取开工号(作业行["工作树"]) or "服务仓根", 作业行["状态"], 作业行["开始时间"],
            作业行["完成时间"] or "（未完成）"))
    return 0, "\n".join(输出行表)
