# -*- coding: utf-8 -*-
"""耗时反馈 —— 长活（释放验证一类）跨过效率阈值时，**自动正式提交一次**性能反馈。

契约定案（2026-10-08 华哥当场授权）：「5 秒到超时不是解决了吗？可以让他长一些。自适应，不强制。
但是超过 5 秒就自动的提交一个反馈而已。」⇒ 长活不再被 5 秒强杀、不再据此判业务失败；跨过
效率阈值就自动提交**一次**性能反馈（幂等键保证只报一次；重复 / 并发调用只重放）。

**复用既有唯一入口**：真正落盘走 `反馈提交.提交反馈`（与 `v1_task` 反馈口同一条合法流）——
本件不自建第二本账、不绕反馈口、不直接写 SQL。

**失败不吞、不阻塞业务**：反馈口写失败（退出码非 0 / 抛异常）⇒ 本件绝不上抛（业务继续），
但把「未登记」状态与真实原因**如实返回**给调用方 ⇒ 由调用方打进回执 ⇒ 可发现，不静默。

**幂等键**（「只报一次」的口径）：`阶段名 · 开工号 · 作业任务ID（无则 `无作业`）` 三段拼成；
同一阶段同一作业重复 / 并发调用 ⇒ 同一键 ⇒ `反馈批次` 主键撞车 ⇒ 重放（零新行）。
不同阶段 / 不同作业各不相同（各自一条）。

**重观测不重复写**：长活重跑 / 重试 / 并发可能各报一个**略不同**的已耗时 ⇒ 同键异文（若按常规
会被反馈口「同键异文拒」）⇒ 本件先把「同键已存在 / 同键相撞」一律当**已登记（未重写）**报，
只有真正的写入失败才报「未登记」。这既不重复登记，也不把重复观测误报成失败。
"""

import json


def _幂等键已存在(幂等键: str) -> bool:
    """反馈库 `反馈批次` 里是否已有这个幂等键（**只读**，不建表不迁移）。读不动 ⇒ 假（当未存在）。"""
    try:
        from . import 反馈账本
        连接 = 反馈账本.连反馈库()
        try:
            for 建表行 in 反馈账本.建表语句:
                连接.execute(建表行)
            命中行 = 连接.execute("select 1 from 反馈批次 where 幂等键 = ?", (幂等键,)).fetchone()
            return 命中行 is not None
        finally:
            连接.close()
    except Exception:
        return False

阈值毫秒 = 5000                      # 效率阈值（华哥「超过 5 秒就自动提交一个反馈」的那条线）
阶段_释放验证 = "释放验证"            # 释放路径的验证阶段名（唯一一份，别处引用它）
反馈来源标识 = "自动性能反馈"          # 反馈来源标识前缀（唯一一份）


def 构建幂等键(阶段名: str, 开工号: str, 作业任务ID: str = "") -> str:
    """耗时反馈的**幂等键**：同一阶段同一作业 ⇒ 同一键（只报一次）；跨阶段 / 跨作业各不相同。"""
    return "耗时-%s-%s-%s" % (阶段名, 开工号 or "未开工", 作业任务ID or "无作业")


def 记耗时反馈(仓根, 开工号, 阶段名, 已耗时毫秒, 作业任务ID="", 落点="", 补充说明="") -> tuple:
    """跨过效率阈值就提交一次性能反馈 ⇒ `(是否已登记, 回执行)`。**不抛**、**不阻塞业务**。

    `已耗时毫秒` ≤ `阈值毫秒` ⇒ `(False, "")`（一个字节都不写）。超阈 ⇒ 经唯一反馈口提交：
    已登记 / 已重放 ⇒ `(True, 回执行)`；写失败 ⇒ `(False, 未登记+真因)`（业务继续，调用方须打进回执）。
    """
    if not 开工号 or not isinstance(已耗时毫秒, int) or 已耗时毫秒 <= 阈值毫秒:
        return False, ""
    from . import 反馈账本
    幂等键 = 构建幂等键(阶段名, 开工号, 作业任务ID)
    if _幂等键已存在(幂等键):
        # 重观测（重跑 / 重试 / 并发里后到者）：同键已登记 ⇒ **不重写、不报失败**。
        return True, ("★ %s 耗时反馈已登记（幂等键 %s · 重观测未重写）：本次实测 %d ms > 阈值 %d ms"
                  % (阶段名, 幂等键, 已耗时毫秒, 阈值毫秒))
    现象 = "%s耗时 %d ms 越过效率阈值 %d ms" % (阶段名, 已耗时毫秒, 阈值毫秒)
    反馈条目 = [{
        "现象": 现象,
        "落点": 落点 or "开发工具/MCP服务/仓操作.py::跑验证带跨阈",
        "触发": "释放路径跑完整验证（闸 0）真实墙钟**跨过阈值的那一刻**（不等它跑完）",
        "预期": "效率目标 ≤ %d ms（五秒效率目标，未完成）" % 阈值毫秒,
        "实际": "实测 %d ms（未被强杀，等到真实终态）%s" % (已耗时毫秒, ("；" + 补充说明) if 补充说明 else ""),
        "证据": "阶段 %s · 开工 %s · 作业 %s · 实测 %d ms" % (阶段名, 开工号, 作业任务ID or "无", 已耗时毫秒),
        "耗时毫秒": int(已耗时毫秒),
    }]
    载荷 = {"阶段名": 阶段名, "开工号": 开工号, "作业任务ID": 作业任务ID, "已耗时毫秒": 已耗时毫秒}
    参数表 = {"幂等键": 幂等键, "来源标识": "%s/%s" % (反馈来源标识, 阶段名),
            "报告指纹": 反馈账本.算指纹(载荷), "条目": 反馈条目}
    try:
        from .反馈提交 import 提交反馈
        退出码, 回执文本 = 提交反馈(仓根, 开工号, 参数表)
    except Exception as 异常:
        return False, ("★ %s 耗时反馈**未登记**（提交异常 %r）⇒ 业务继续，请人工登记此性能问题"
                  % (阶段名, 异常))
    if 退出码 != 0:
        if _幂等键已存在(幂等键):
            # 并发撞车：本进程提交时对方已抢先落同一键 ⇒ 本进程的载荷被拒（同键异文）
            # ⇒ **当已登记**（对方已报过，不重复、不报失败）。
            return True, ("★ %s 耗时反馈已登记（幂等键 %s · 并发下由另一方先落）：本次实测 %d ms"
                      % (阶段名, 幂等键, 已耗时毫秒))
        return False, ("★ %s 耗时反馈**未登记**（反馈口退出码 %d）⇒ 业务继续：%s"
                  % (阶段名, 退出码, str(回执文本).strip()[:200]))
    try:
        读数 = json.loads(回执文本)
    except (TypeError, ValueError):
        读数 = {}
    return True, ("★ %s 耗时反馈已登记（幂等键 %s · 来源号 %s · 重放 %s）：实测 %d ms > 阈值 %d ms"
              % (阶段名, 幂等键, 读数.get("来源号"), 读数.get("重放"), 已耗时毫秒, 阈值毫秒))
