# -*- coding: utf-8 -*-
"""合主干腿树门禁 —— 合并 ① 校验跑腿树闸 0，并复用 pre-commit 钩子同一份「超顶自动复跑一次」口径。

为什么要有它（2026-10-08 收口方实测）：`合并主干.py` 的 ①（腿树闸0，子进程 5 秒硬顶）在负载下
间歇红 —— 两条闸**都绿**、仅外层墙钟 `4958 ms > 4800 ms` 也判退出码 1 ⇒ 合并 ① 间歇失败。
`测试验证/案例/装门禁.sh::run_gate0` 早有口径：**超顶 ⇒ 复跑一次**，仍超才红。本件把那份口径
落到 Python 侧（钩子是纯 shell，抽不出来，故同口径镜像一份，出处写在件头）。

**区分负载红与判据红**（收口方要求）：从 `闸0.py` 的读数里逐闸抽「退出码 + 失败 N 项」——
  · 判据红（某闸 失败 N 项，N>0）⇒ 立即拒，不复跑；
  · 负载红（只有 超顶 / 超时 标记，各闸 失败 0 项）⇒ 复跑一次，仍红才拒；
  · **超时且一条读数都没抽到** ⇒ 不当负载红（fail-closed 拒），回执明说「无读数」。
读数逐闸回传（`闸 1 · 声明侧` / `闸 2 · 实现侧`），谁红了、是不是真判据红一眼可辨。

**子进程带 `-u`**（2026-10-08 加 · 诊断修复）：闸0 的读数是**逐闸**打印的，而父层管道 + 块缓冲下
超时被杀时那几行还在缓冲区里 ⇒ 父进程收到空输出 ⇒ 误判成判据红。`-u` 让闸0 逐行 flush，
中途读数活到父进程。**只改诊断保真**：5 s / 4800 ms / `是负载红` / 复跑次数一个字没改。
"""

import re
import sys

from .合主干有界跑 import 跑有界命令

闸0入口 = "构建装配/一键验证/闸0.py"
闸名行 = re.compile(r"^\s{2}(\S.*?) ｜ (\S+)\s*$")
退出码行 = re.compile(r"^\s+退出码 (\S+) ｜ (.*)$")
失败数行 = re.compile(r"失败 (\d+) 项")
超顶标记 = ("超顶", "超时")


def _闸读数(输出文本) -> list:
    """从 `闸0.py` 读数里抽 `(闸名, 退出码文本, 失败数或 None)` 表。"""
    读数表 = []
    当前名 = None
    for 数据行 in 输出文本.splitlines():
        名匹配 = 闸名行.match(数据行)
        if 名匹配:
            当前名 = 名匹配.group(1)
            continue
        码匹配 = 退出码行.match(数据行)
        if 码匹配 and 当前名:
            失败匹配 = 失败数行.search(码匹配.group(2))
            读数表.append((当前名, 码匹配.group(1), int(失败匹配.group(1)) if 失败匹配 else None))
            当前名 = None
    return 读数表


def 是负载红(退出码, 输出文本) -> bool:
    """只有「超顶 / 超时」标记、且没有闸报真判据红 ⇒ 负载红（可复跑）。"""
    if 退出码 == 0:
        return False
    if not any(标记 in 输出文本 for 标记 in 超顶标记):
        return False
    读数表 = _闸读数(输出文本)
    if not 读数表:
        return False
    for 闸名, 码文本, 失败项数 in 读数表:
        if 码文本 not in ("0", "超时") and 失败项数 != 0:
            return False
    return True


def 闸读数说明(输出文本) -> str:
    """逐闸回传退出码 ⇒ 一行文本（谁红了 / 是不是真判据红）。"""
    读数表 = _闸读数(输出文本)
    if not 读数表:
        return "（闸读数行抽不出）"
    return " · ".join("%s 退出码 %s%s" % (闸名, 码文本, "" if 失败项数 is None else "（失败 %d 项）" % 失败项数)
                    for 闸名, 码文本, 失败项数 in 读数表)


def 跑腿树门禁(腿树) -> tuple:
    """跑腿树闸 0（**只有负载红才复跑一次**）⇒ (最终退出码, 行表)。"""
    尝试 = 0
    行表 = []
    while True:
        尝试 += 1
        # ★ `-u`（2026-10-08 加 · 诊断修复）：闸0 的读数**逐闸**打印，而父层管道 + 块缓冲下
        #   超时被杀时那几行还在缓冲区里 ⇒ 父进程收不到任何读数 ⇒ `是负载红` 抽不出读数表，
        #   只能落「判据红」⇒ 误拒。`-u` 让闸0 逐行 flush ⇒ 中途读数活到父进程。只改**诊断
        #   保真**，不改 5 s / 4800 / 是负载红 / 复跑次数。
        退出码, 输出文本, 日志路径 = 跑有界命令([sys.executable, "-u", 闸0入口], 工作目录=腿树,
                            超时秒数=5, 保留日志=True)
        行表.append("① 腿树闸0 第 %d 跑：退出码 %d · 日志 %s · %s"
                  % (尝试, 退出码, 日志路径, 闸读数说明(输出文本)))
        if 退出码 == 0:
            return 0, 行表
        if 尝试 == 1 and 是负载红(退出码, 输出文本):
            行表.append("   判定：负载红（非判据红）⇒ 复用 pre-commit 口径复跑一次")
            continue
        无读数 = not _闸读数(输出文本)
        行表.append("   判定：%s ⇒ 拒（不自动放宽硬顶）"
                  % ("复跑后仍红" if 尝试 > 1
                     else ("超时且无读数（fail-closed，不当负载红）" if 无读数 else "判据红")))
        return 退出码, 行表 + [输出文本[:1500]]
