def _门禁复跑样本() -> list:
    """A：负载红一次 ⇒ 复跑判绿；真判据红 ⇒ 一次就拒（不白跑第二趟）。"""
    负载调用表 = []

    def 负载假跑(命令表, 工作目录, 超时秒数=None, 输入文本=None, 子进程环境=None, 保留日志=False):
        负载调用表.append(1)
        if len(负载调用表) == 1:
            return 1, 负载红闸0输出, "样本：假日志-负载红"
        return 0, 绿闸0输出, "样本：假日志-绿"

    判据调用表 = []

    def 判据假跑(命令表, 工作目录, 超时秒数=None, 输入文本=None, 子进程环境=None, 保留日志=False):
        判据调用表.append(1)
        return 1, 判据红闸0输出, "样本：假日志-判据红"

    with mock.patch.object(腿树门禁, "跑有界命令", side_effect=负载假跑):
        负载码, 负载行表 = 腿树门禁.跑腿树门禁("样本：假腿树")
    with mock.patch.object(腿树门禁, "跑有界命令", side_effect=判据假跑):
        判据码, 判据行表 = 腿树门禁.跑腿树门禁("样本：假腿树")
    return [
        ("A ① 门禁负载红 ⇒ 复跑一次判绿：退出码 %d（期望 0）· 真跑了 %d 趟（期望 2）· 说「负载红」%s"
         % (负载码, len(负载调用表), "是" if any("负载红" in 说明行 for 说明行 in 负载行表) else "否"),
         负载码 == 0 and len(负载调用表) == 2 and any("负载红" in 说明行 for 说明行 in 负载行表)),
        ("A ① 门禁真判据红 ⇒ 仍拒且只跑一趟：退出码 %d（期望非 0）· 跑了 %d 趟（期望 1）· 说「判据红」%s"
         % (判据码, len(判据调用表), "是" if any("判据红" in 说明行 for 说明行 in 判据行表) else "否"),
         判据码 != 0 and len(判据调用表) == 1 and any("判据红" in 说明行 for 说明行 in 判据行表)),
    ]


def _暂存非冲突样本(临时根) -> list:
    """B：接管开工改了**非冲突件** ⇒ 暂存须一并 git add（否则 ④ 因未提交改动拒）。"""
    临时根.mkdir(parents=True, exist_ok=True)
    开工号 = "v1-999005"
    接管号 = "v1-999905"
    主目录 = _搭基座(临时根)
    (主目录 / "补充.txt").write_text("补充基线\n", encoding="utf-8")
    _跑git(主目录, "add", "补充.txt")
    _跑git(主目录, "commit", "-m", "补基线")
    腿树 = _建腿树(主目录, 开工号)
    (腿树 / "样本.txt").write_text("腿改\n", encoding="utf-8")
    _跑git(腿树, "add", "样本.txt")
    _跑git(腿树, "commit", "-m", "腿成果")
    (主目录 / "样本.txt").write_text("主改\n", encoding="utf-8")
    _跑git(主目录, "add", "样本.txt")
    _跑git(主目录, "commit", "-m", "主改")
    集成树 = _造现场(主目录, 开工号)
    账本件 = 临时根 / "账本.db"
    _建空账本(账本件)
    连接 = _开账(账本件)
    连接.execute("insert into 开工 (开工号, 工作内容, 分支名, 工作树, 状态, 开工时间) values (?,?,?,?,?,?)",
             (接管号, "样本接管", "集成/" + 开工号, str(集成树), 开工账本.状态_进行中, "2026-10-08"))
    for 路径 in ("样本.txt", "补充.txt"):
        连接.execute("insert into 改动 (开工号, 路径, 功能, 时间) values (?,?,?,?)",
                 (接管号, 路径, "修改", "2026-10-08"))
    连接.commit()
    连接.close()
    (集成树 / "样本.txt").write_text("主改+腿改\n", encoding="utf-8")
    (集成树 / "补充.txt").write_text("非冲突件已改\n", encoding="utf-8")
    旧连 = 开工账本.连账本
    开工账本.连账本 = lambda: _开账(账本件)
    try:
        退出码, 行表 = 集成接管.暂存接管成果(主目录, 集成树)
        暂存表 = _跑git(集成树, "diff", "--cached", "--name-only").split()
    finally:
        开工账本.连账本 = 旧连
    return [("B 暂存接管成果 收非冲突件：退出码 %d（期望 0）· 暂存区 = %s（期望含 样本.txt 与 补充.txt）"
             % (退出码, 暂存表),
             退出码 == 0 and "样本.txt" in 暂存表 and "补充.txt" in 暂存表)]


def _恢复重跑样本(临时根) -> list:
    """C：已提交过的失败现场再跑 `--恢复现场` ⇒ 仍收敛（源库时间默认值非确定 ⇒ 须再提交）。"""
    临时根.mkdir(parents=True, exist_ok=True)
    开工号 = "v1-999006"
    主目录 = _搭基座(临时根)
    腿树 = _建腿树(主目录, 开工号)
    (腿树 / "新增.txt").write_text("腿成果\n", encoding="utf-8")
    _改库(腿树, "update 命名登记 set 语义='腿语义' where 名字='样本名'")
    _跑git(腿树, "add", ".")
    _跑git(腿树, "commit", "-m", "腿成果")
    _改库(主目录, "update 规则 set 内容='主干值' where 编号=1")
    _跑git(主目录, "add", ".")
    _跑git(主目录, "commit", "-m", "主改源库")
    集成树 = _造现场(主目录, 开工号)
    with mock.patch.object(编排, "_读开工记录", return_value=_开工记录(腿树, 开工号)):
        编排._重放源库(主目录, 集成树, "腿/" + 开工号)
    # 重放的 `创建时间` 由库默认 `datetime('now')` 填 ⇒ 秒级非确定。这里把已提交那一版**钉成过去值**，
    # 下次重放写 `now` 必产生不同字节（等价于「同一现场重放结果不可复现」，不靠 sleep 拖时间）。
    _改库(集成树, "update 命名登记 set 创建时间='2000-01-01 00:00:00' where 名字='样本名'")
    _跑git(集成树, "add", 库相对路径)
    _跑git(集成树, "commit", "-m", "样本：模拟已提交现场")
    旧提交 = _跑git(集成树, "rev-parse", "HEAD")
    with mock.patch.object(编排, "_读开工记录", return_value=_开工记录(腿树, 开工号)):
        编排._重放源库(主目录, 集成树, "腿/" + 开工号)
    重放树 = _跑git(集成树, "write-tree")
    提交树 = _跑git(集成树, "rev-parse", 旧提交 + "^{tree}")
    非确定 = 重放树 != 提交树
    with mock.patch.object(编排, "_读开工记录", return_value=_开工记录(腿树, 开工号)), \
         mock.patch.object(集成接管, "解除接管", return_value=(0, "样本：解除接管跳过")):
        退出码, 报告 = 编排.派发(开工号, False, 主目录, 操作="恢复现场")
    树在 = 集成.找集成树(主目录, 开工号)
    语义 = _读库值(主目录 / 库相对路径, "select 语义 from 命名登记 where 名字='样本名'")
    return [
        ("C 源库重放非确定（时间默认值）：重放树 %s ≠ 提交树 %s ⇒ %s"
         % (重放树[:12], 提交树[:12], "是" if 非确定 else "否"),
         非确定),
        ("C 已提交失败现场 --恢复现场 重跑：退出码 %d（期望 0）· 集成树已清 %s · 源库收敛（命名登记=%s）"
         % (退出码, "是" if not 树在 else "否", 语义),
         退出码 == 0 and not 树在 and 语义 == "腿语义"),
    ]


def 续缺口样本(仓根=None, 工具表=None) -> list:
    """三条续缺口正反样本 ⇒ 样本表（临时仓与临时账本跑完删净）。"""
    样本表 = _门禁复跑样本()
    with tempfile.TemporaryDirectory(prefix="v1续缺口样本-") as 临时目录:
        临时根 = Path(临时目录)
        样本表 += _暂存非冲突样本(临时根 / "暂存")
        样本表 += _恢复重跑样本(临时根 / "恢复")
    return 样本表
