"""顶层开工号 —— 把误写进 `参数` 里的 `开工ID` 自动上提到顶层（并给一条说明）。

**为什么**（多路代理实测）：`开工ID` 是顶层三字段之一，但 agent 常顺手把它塞进 `参数` —— 首调
即撞「未知参数键」，每次一轮往返。这里做**兼容上提**：`参数.开工ID` 有值且顶层空 ⇒ 用它；
顶层已有 ⇒ 顶层优先；不论哪种，都从 `参数` 里摘掉并给一行说明（不静默丢）。

**只此一处**：`参数规范.网关派发` 在处理前一调用；本件不碰任何业务。
"""


def 上提(参数表: dict, 开工号: str) -> tuple:
    """`⇒ (新参数表, 新开工号, 提示行或空串)`。`参数.开工ID` 非空才动，否则原样返回。"""
    if not isinstance(参数表, dict) or "开工ID" not in 参数表:
        return 参数表, 开工号, ""
    参数表 = dict(参数表)
    嵌套值 = 参数表.pop("开工ID")
    嵌套号 = 嵌套值.strip() if isinstance(嵌套值, str) else ""
    if not 嵌套号:
        return 参数表, 开工号, "★ `参数` 里的 `开工ID` 为空 / 非字符串 ⇒ 已忽略；`开工ID` 是开头三字段，别放 `参数` 内。\n"
    if 开工号:
        return 参数表, 开工号, ("★ `参数` 里的 `开工ID`（%s）与顶层 `开工ID`（%s）并存 ⇒ 用顶层；"
                       "`开工ID` 开头三字段不在 `参数` 内。\n" % (嵌套号, 开工号))
    return 参数表, 嵌套号, "★ `参数` 里的 `开工ID`（%s）已自动上提到顶层（旧写法兼容）。\n" % 嵌套号
