# -*- coding: utf-8 -*-
"""信封状态 —— 统一信封**状态面**的两件事（都不复制任何工具实现）：

  · `错误种类` —— 业务码 ⇒ 信封 `错误.种类` 的**唯一**映射（0 空串 / 参数面 / 待取作业 / 业务失败）。
  · `指向文案` 与 `_预留槽` —— 预留槽的构造与它的**指向文案**（`说明` 与「未实现」拒共用同一句）。

**为何单开一件**（判据 ⑲ 单源文件 ≤400 行）：`参数规范.py` 已顶硬数，本组是纯函数（不 import
本包其它业务模块，只取 `服务常量` 的码值），按先例单开、`参数规范` 只加一行导入。
"""

from .服务常量 import 待取作业码


def 错误种类(退出码: int) -> str:
    """业务码 ⇒ 信封 `错误.种类`（0 ⇒ 空串；参数面 / 待取作业 / 业务失败）—— 唯一一处映射。"""
    if 退出码 == 0:
        return ""
    if 退出码 == 2:
        return "参数错误"
    if 退出码 == 待取作业码:
        return "待取作业"
    return "业务失败"


def 指向文案(指向: str) -> str:
    """预留槽的**指向文案**（空指向 ⇒ 空串）—— 说明与「未实现」拒共用同一份，不各写一句。"""
    return "" if not 指向 else "；本能力已由 %s 提供 ⇒ 请调那里" % 指向


def _预留槽(说明: str, 指向: str = "") -> dict:
    """一个未实现的预留操作（`处理` 空 ⇒ 网关结构化拒「未实现」）。

    `指向` = **已实现**本能力的工具与操作（如 `` `v1_repo` 操作 `仓状态` ``）—— 只在文案里点名，
    **不复制实现**；`发现` 只读 `说明`，`指向` 只供「未实现」拒复用同一句。
    """
    return {"说明": "预留（未实现）—— " + 说明 + 指向文案(指向), "需开工ID": False, "必需": [],
            "可选": [], "最短例": {}, "处理": None, "指向": 指向}
