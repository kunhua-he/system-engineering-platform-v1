def 载入操作表() -> dict:
    """glob 同目录 `操作_*.py` 合并各自 `操作表` ⇒ `{工具名: {操作名: 条}}`（无硬编码文件清单）。

    合并规则：glob 到的操作表**覆盖**内置回退；同工具同操作两处都给实现时按件名排序后者胜；
    **有 `处理` 的条不被预留槽（无 `处理`）覆盖** ⇒ 各 owner 新增的实现能挂上预留槽。
    缺件 / 坏件跳过（不报错）。
    """
    global _总表缓存
    if _总表缓存 is not None:
        return _总表缓存
    总表 = {}
    for 件路径 in sorted((服务根 / "工具声明").glob("操作_*.py")):
        try:
            样本模块 = importlib.import_module("." + ".".join(件路径.relative_to(服务根).with_suffix("").parts), __package__.rsplit(".", 1)[0])
        except Exception:
            continue
        工具名 = str(getattr(样本模块, "工具名", "") or "")
        if not 工具名:
            continue
        操作分表 = 总表.setdefault(工具名, {})
        for 操作名, 操作条 in dict(getattr(样本模块, "操作表", {}) or {}).items():
            旧条 = 操作分表.get(操作名)
            if 旧条 and 旧条.get("处理") and not 操作条.get("处理"):
                continue
            操作分表[操作名] = 操作条
    for 工具名, 回退分表 in _回退表().items():
        分表 = 总表.setdefault(工具名, {})
        for 操作名, 操作条 in 回退分表.items():
            分表.setdefault(操作名, 操作条)
    for 工具名, 分表 in 总表.items():
        问题表 = 校验最短例(分表)
        if 问题表:
            raise RuntimeError("操作元数据校验不过（%s · 最短例只做 schema 校验、不执行）：%s"
                               % (工具名, "；".join(问题表)))
    _总表缓存 = 总表
    return 总表


def 声明工具() -> dict:
    """glob `操作_*.py`：凡**自声明新工具**（给了 `工具说明` 或 `派发`）⇒
    `{工具名: {工具说明, 模式, 派发}}`。既有六工具的操作表文件只给 `工具名` + `操作表`（不在此列）。
    缺件 / 坏件跳过（不报错）—— 新工具由各自 owner 加一件 `操作_*.py` 即注册。
    """
    声明表 = {}
    for 件路径 in sorted((服务根 / "工具声明").glob("操作_*.py")):
        try:
            样本模块 = importlib.import_module("." + ".".join(件路径.relative_to(服务根).with_suffix("").parts), __package__.rsplit(".", 1)[0])
        except Exception:
            continue
        工具名 = str(getattr(样本模块, "工具名", "") or "")
        if not 工具名 or 工具名 in 声明表:
            continue
        if not (getattr(样本模块, "工具说明", "") or getattr(样本模块, "派发", None)):
            continue
        声明表[工具名] = {"工具说明": str(getattr(样本模块, "工具说明", "") or 工具名),
                     "模式": getattr(样本模块, "模式", None), "派发": getattr(样本模块, "派发", None)}
    return 声明表


