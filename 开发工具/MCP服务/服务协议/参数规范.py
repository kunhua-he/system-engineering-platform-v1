# 取树快照：只由调用方显式开启的有限作用域内复用；默认关闭 ⇒ 生产每条现读（不盲长驻缓存）。
# 用 ContextVar 而**不是模块全局**：HTTP 自检在同一进程里起真实 HTTP 服务，处理线程与自检线程
# 必须互不污染（模块全局会让处理线程读到自检线程缓存的旧 HEAD）。
树快照 = contextvars.ContextVar("取树快照", default=None)


def 开树快照():
    """开启取树快照并返回旧值（供 `关树快照` 还原）—— 同一稳定仓连发多条信封的场景（如自检）。"""
    return 树快照.set({})


def 关树快照(旧值):
    """还原 `开树快照` 前的状态（作用域结束必须还原，别把快照留成长驻缓存）。"""
    树快照.reset(旧值)


def 取树(开工号: str, 仓根路径) -> dict:
    """Git现读树身份；仅在显式树快照作用域内复用，不碰账本。"""
    快照键 = (开工号 or "", str(仓根路径 or ""))
    当前快照 = 树快照.get()
    if 当前快照 is not None and 快照键 in 当前快照:
        return 当前快照[快照键]
    错误分类, 目标路径 = "服务仓根", str(仓根路径 or "")
    if 开工号:
        错误分类 = "未定"
        try:
            from ..施工管理.仓操作 import 找工作树
            工作树 = 找工作树(仓根路径, 开工号)
        except Exception:
            工作树 = None
        if 工作树 is not None:
            错误分类, 目标路径 = "工作树", str(工作树)
    from ..施工管理.仓操作 import 跑命令
    退出码, 输出文本 = 跑命令(["git", "rev-parse", "HEAD", "--abbrev-ref", "HEAD"],
                       cwd=目标路径, 超时秒数=取树超时秒)
    行表 = [源码行.strip() for 源码行 in 输出文本.splitlines() if 源码行.strip()]
    if 退出码 == 0 and len(行表) == 2:
        分支, HEAD = ("" if 行表[1] == "HEAD" else 行表[1]), 行表[0]
    else:
        分支 = 取git值(目标路径, ["branch", "--show-current"])
        HEAD = 取git值(目标路径, ["rev-parse", "HEAD"])
    读数 = {"种类": 错误分类, "路径": 目标路径, "开工ID": 开工号 or None,
            "分支": 分支, "HEAD": HEAD}
    if 当前快照 is not None:
        当前快照[快照键] = 读数
    return 读数


def 有界(原文: str) -> tuple:
    """`说明` 留内存有界 ⇒ `(留存文本, 截断?, 日志路径)`。超出落系统临时件（懒建）。"""
    原文 = 原文 if isinstance(原文, str) else str(原文)
    if len(原文) <= 说明上限:
        return 原文, False, None
    句柄, 日志路径 = tempfile.mkstemp(prefix="v1信封_", suffix=".log")
    with os.fdopen(句柄, "w", encoding="utf-8", errors="replace") as 日志件:
        日志件.write(原文)
    return 原文[:说明上限], True, 日志路径


def 结构化(输出文本):
    """底层回执已是结构化对象 ⇒ 原样当 `结果`；是 JSON 对象文本 ⇒ 解析；否则 `None`。"""
    if isinstance(输出文本, dict):
        return 输出文本
    try:
        读数 = json.loads(输出文本)
    except (TypeError, ValueError):
        return None
    return 读数 if isinstance(读数, dict) else None


def 归一处理输出(处理回值) -> tuple:
    """处理器输出合同（**唯一一处收敛**）：`(退出码, 输出)` 两元组 / 单值 dict / 单值输出。

    `输出` 的**允许类型只有四种**（明确列举 —— 别扩成「什么都转字符串当成功」）：
      · `str` —— 文本工具，`说明` 就是它；
      · `dict` —— 结构化结果，进信封 `结果`；带 `说明` 键时网关用它当信封 `说明`；
      · `list` —— 包成 `{"列表": [...]}` 再进 `结果`（信封 `结果` 恒为 dict，调用方按 dict 取）；
      · `None` —— 视同空文本（退出码照旧：不悄悄改成成功，也不改成失败）。
    其余类型（`int` / `float` / `set` / 任意对象）**不算成功**：退出码 3 + 点名类型 ⇒ 调用方看得见「合同不合」，
    不会拿到一个 `str(对象)` 的假回执（那会把非法类型静默当成功）。
    为什么要归一：处理器有的回 `(0, dict)`（`切片清单` / `清点反馈源`）、有的回 `(码, 文本)`，
    旧网关把 dict 当文本拼 `说明` ⇒ `str + dict` 抛 TypeError（-32603，调用方拿不到任何读数）。
    """
    if isinstance(处理回值, (tuple, list)):
        if len(处理回值) != 2:
            return 3, "处理器输出要是 `(退出码, 输出)` 两元组（收到 %d 项）" % len(处理回值)
        退出码, 输出 = 处理回值
    elif isinstance(处理回值, dict):
        退出码, 输出 = 处理回值.get("退出码", 0), 处理回值
    else:
        退出码, 输出 = 0, 处理回值
    if isinstance(退出码, bool) or not isinstance(退出码, int):
        return 3, "处理器输出的退出码要是整数（收到 %r）" % (退出码,)
    if 输出 is None:
        return 退出码, ""
    if isinstance(输出, str):
        return 退出码, 输出
    if isinstance(输出, dict):
        return 退出码, 输出
    if isinstance(输出, list):
        return 退出码, {"列表": 输出}
    return 3, "处理器输出类型不在合同内（%s）⇒ 业务失败，未当成功转文本" % type(输出).__name__


def 序列化读数(结果值) -> tuple:
    """结构化结果试序列化 ⇒ `(字节数, 错误文本)`。

    为什么单独抽出来：`json.dumps` 原先写在业务 `try` 之外 —— 处理器回了一个**嵌套不可序列化**的 dict
    （`set` / `Decimal` / 自定义对象）时，网关会抛 `TypeError` 变成协议层 **-32603**，调用方拿不到读数、
    也不知道副作用已经发生。现在这一步在网关内收敛成业务失败（退出码 3 + 明确提示）。
    """
    try:
        return len(json.dumps(结果值, ensure_ascii=False).encode()), None
    except (TypeError, ValueError) as 失败因由:
        return 0, ("结构化结果不可 JSON 序列化（%r）⇒ 业务失败；★ 副作用可能已发生"
                   "（处理器已跑完，写盘/改库不回滚）" % (失败因由,))


def 信封(工具名: str, 操作标识: str, 退出码: int, 说明: str, 结果值=None, 错误=None,
        开工号: str = "", 仓根路径=None) -> str:
    """统一一行 JSON 信封（`isError` 由协议层按「非 0 且非待取作业码」折，不进本信封）。"""
    from .协议 import 服务版本
    from .服务指纹 import 算服务指纹
    留存文本, 截断, 日志 = 有界(说明)
    return json.dumps({
        # `成功` 仍只认 0（-3 是「还没成功」，不是成功）；「不是失败」这层语义由协议的 `isError` 表达。
        "成功": 退出码 == 0,
        "退出码": 退出码,
        "工具": 工具名,
        "操作": 操作标识 or None,
        "树": 取树(开工号, 仓根路径),
        "服务": {"版本": 服务版本, "指纹": 算服务指纹()},
        "说明": 留存文本,
        "结果": 结果值,
        "错误": 错误,
        "截断": 截断,
        "日志": 日志,
    }, ensure_ascii=False)


def 拒调用(工具名: str, 操作标识: str, 错误分类: str, 说明: str, 仓根路径,
      缺参=None, 最短例=None) -> tuple:
    """结构化拒 ⇒ `(2, 信封)`（参数面一律退出码 2；`错误.种类` 分清是哪一类）。"""
    return 2, 信封(工具名, 操作标识, 2, 说明,
                  错误={"种类": 错误分类, "缺参": list(缺参 or []), "最短例": 最短例},
                  仓根路径=仓根路径)


def 发现(工具名: str, 规范: dict, 仓根路径) -> tuple:
    """只读发现调用（操作留空）⇒ `(0, 信封)`，`结果` 是**该工具的操作目录**。"""
    操作目录 = {操作名: {"号": 操作编号.发现号(工具名, 操作名), "说明": 操作条.get("说明", ""),
                  "需开工ID": bool(操作条.get("需开工ID")),
                  "必需": list(操作条.get("必需", [])), "可选": list(操作条.get("可选", [])),
                  "最短例": 操作条.get("最短例")}
          for 操作名, 操作条 in sorted(规范.items())}
    return 0, 信封(工具名, "", 0, "%s 操作目录：%d 个操作（每档的号在结果里）" % (工具名, len(操作目录)),
                  结果值={"工具": 工具名, "操作目录": 操作目录}, 仓根路径=仓根路径)


def 网关派发(工具名: str, 实参, 仓根路径) -> tuple:
    """六工具**统一入口** ⇒ `(退出码, 一行 JSON 信封)`。"""
    规范 = 载入操作表().get(工具名, {})
    if not isinstance(实参, dict):
        return 拒调用(工具名, "", "参数错误", "`arguments` 要是对象", 仓根路径)
    未知顶层 = sorted(set(实参) - set(顶层键))
    if 未知顶层:
        return 拒调用(工具名, "", "参数错误",
                 "未知顶层键：%s；本工具只认 %s" % ("、".join(未知顶层), "、".join(顶层键)), 仓根路径,
                 最短例=顶层形状例)
    开工号 = 实参.get("开工ID")
    if 开工号 is not None and not isinstance(开工号, str):
        return 拒调用(工具名, "", "参数错误", "`开工ID` 要是字符串", 仓根路径)
    开工号 = (开工号 or "").strip()
    操作标识, 操作错误 = 操作编号.归一操作(工具名, 实参.get("操作"))
    if 操作错误:
        return 拒调用(工具名, "", "参数错误", 操作错误, 仓根路径, 最短例=顶层形状例)
    参数表 = 实参.get("参数")
    if 参数表 is None:
        参数表 = {}
    if not isinstance(参数表, dict):
        return 拒调用(工具名, 操作标识, "参数错误", "`参数` 要是对象", 仓根路径)
    if not 操作标识:
        # 带了 `参数` 却没给 `操作`：单操作工具（如 v1_shell）⇒ 默认取那唯一一档（债务 221/230）；
        # 多操作工具 ⇒ 降级为发现调用（债务 220/2756）。空调用（无 参数）仍走发现目录。
        if 参数表 and len(规范) == 1:
            操作标识, 操作错误 = next(iter(规范)), 操作错误
        else:
            return 发现(工具名, 规范, 仓根路径)
    if 操作标识 not in 规范:
        号行 = 操作编号.号串(工具名)
        # 2026-10-13（债务 568）：顶层「新建」不是真错、是层级不同 —— 点明它是条目级操作
        新建提示 = "；★ `新建` 是**条目级**操作 ⇒ 顶层要写 `操作=改`，条目里再写 `操作=新建`" if 操作标识 == "新建" else ""
        return 拒调用(工具名, 操作标识, "未知操作",
                 "没有这个操作：%s；可用：%s%s%s" % (操作标识, "、".join(sorted(规范)) or "（无）",
                                            "（号：%s）" % 号行 if 号行 else "", 新建提示), 仓根路径)
    操作条 = 规范[操作标识]
    参数表, 开工号, 上提行 = 顶层开工号.上提(参数表, 开工号)
    未知键 = sorted(set(参数表) - set(操作条.get("必需", [])) - set(操作条.get("可选", [])))
    if 未知键:
        旧字段提示 = "；★「功能」是本会话旧字段 ⇒ 现改成顶层 `操作` 名（功能=3 ≡ 操作=释放）" if "功能" in 未知键 else ""
        # 2026-10-13（债务 568）：光回「未知参数键：X」调用方仍不知道该传什么（实测为此试错两次）
        # ⇒ 一并把本操作的真参数名表（必需 + 可选）列出来，照 未知操作 那支的「可用：…」写法。
        真参数 = "、".join(sorted(set(操作条.get("必需", [])) | set(操作条.get("可选", [])))) or "（无）"
        return 拒调用(工具名, 操作标识, "参数错误",
                 "未知参数键：%s%s；本操作（%s）真参数名：%s" % ("、".join(未知键), 旧字段提示, 操作标识, 真参数),
                 仓根路径, 最短例=操作条.get("最短例"))
    缺参 = [参数名 for 参数名 in 操作条.get("必需", []) if 参数名 != "开工ID" and not 有值(参数表.get(参数名))]
    if 操作条.get("需开工ID") and not 开工号:
        缺参 = ["开工ID"] + 缺参
    if 缺参:
        return 拒调用(工具名, 操作标识, "缺参", "缺必需参数：%s" % "、".join(缺参), 仓根路径,
                 缺参=缺参, 最短例=操作条.get("最短例"))
    开始时刻 = time.perf_counter()
    try:
        if 操作条.get("处理"):
            退出码, 输出文本 = 归一处理输出(操作条["处理"](开工号, 参数表, 仓根路径))
        elif 操作条.get("脚本"):
            脚本路径 = 定脚本(操作条.get("脚本"))
            if not 脚本路径:
                return 拒调用(工具名, 操作标识, "未实现",
                         "操作 `%s` 的脚本落点不合法或不在固定脚本目录：%r" % (操作标识, 操作条.get("脚本")), 仓根路径)
            退出码, 输出文本 = 归一处理输出(跑脚本(脚本路径, 开工号, 操作标识, 参数表, 仓根路径))
        else:
            指向 = str(操作条.get("指向") or "")
            return 拒调用(工具名, 操作标识, "未实现",
                     "操作 `%s` 是预留槽（未实现）%s" % (操作标识, 指向文案(指向)), 仓根路径)
    except Exception as 兜错因由:
        退出码, 输出文本 = 3, "工具处理抛异常（网关兜错，不崩）：%r" % (兜错因由,)
    from ..施工管理.工具流水 import 记流水                 # 网关统一采集工具流水（白名单元数据，记不上不阻断）
    记流水(工具名, 操作标识, 开工号, 退出码, 输出文本,
        耗时毫秒=int((time.perf_counter() - 开始时刻) * 1000))
    错误 = None
    if 退出码 != 0:
        错误 = {"种类": 错误种类(退出码), "缺参": [], "最短例": None}
    结果值 = 结构化(输出文本)
    说明键文本 = None
    if isinstance(结果值, dict) and isinstance(结果值.get("说明"), str):
        说明键文本 = 结果值["说明"]                 # 处理器自带的「人读文本」⇒ 兼作信封 `说明`（`结果` 里保留一份，不裁承重字段）
    字节数, 序列化错 = 序列化读数(结果值) if 结果值 is not None else (0, None)
    if 序列化错:
        退出码, 结果值 = 3, None
        错误 = {"种类": 错误种类(3), "缺参": [], "最短例": None}
        说明文本 = 序列化错
    elif 说明键文本 is not None:
        说明文本 = 说明键文本
    elif 结果值 is None:
        说明文本 = 输出文本 if isinstance(输出文本, str) else str(输出文本)   # 文本工具：结果就在 `说明`
    else:
        说明文本 = "结构化结果见 `结果`（%d 字节）" % 字节数
        if 退出码 != 0:
            # 结构化失败：`说明` 只留短原因（错误.说明 / 原因 / 种类），不重复整段结构化正文。
            失败原因 = 结果值.get("错误") if isinstance(结果值, dict) else None
            if isinstance(失败原因, dict):
                失败原因 = 失败原因.get("说明") or 失败原因.get("原因") or 失败原因.get("种类")
            elif not isinstance(失败原因, str):
                失败原因 = 结果值.get("说明") or 结果值.get("原因")
            if 失败原因:
                说明文本 = "失败：%s\n%s" % (str(失败原因).strip(), 说明文本)
    回执文本 = 信封(工具名, 操作标识, 退出码, (上提行 or "") + 说明文本, 结果值=结果值,
                 错误=错误, 开工号=开工号, 仓根路径=仓根路径)
    if 退出码 != 0:
        from .诊断记录 import 记诊断
        记诊断(工具名, 操作标识, 开工号, "网关非零", 退出码=退出码)
    return 退出码, 回执文本
