def 有值(值) -> bool:
    """具名参是否算「给了」：`None` / 空串 / 空表 ⇒ 假。"""
    if 值 is None:
        return False
    if isinstance(值, str):
        return bool(值.strip())
    if isinstance(值, (list, dict, tuple)):
        return bool(值)
    return True


