def 校验最短例(规范: dict) -> list:
    """统一元数据校验：每个**可执行**操作的 `最短例` 必须自身就是合法三字段调用。

    只做 schema 校验（顶层三字段 / 操作名 / 参数键 / 必需键 / 开工ID），**不执行**示例 ——
    示例里可能有写操作（`提交反馈` / `批量判定`），执行它就是副作用。
    预留槽（无 `处理` / `脚本`）没有真示例，`最短例` = {} 不算违规。
    """
    问题表 = []
    for 操作名, 操作条 in sorted(规范.items()):
        if not 操作条.get("处理") and not 操作条.get("脚本"):
            continue
        示例条 = 操作条.get("最短例")
        if not isinstance(示例条, dict) or not 示例条:
            问题表.append("%s：最短例要是非空对象（收到 %r）" % (操作名, 示例条))
            continue
        顶层多余键 = sorted(set(示例条) - set(顶层键))
        if 顶层多余键:
            问题表.append("%s：最短例顶层多了 %s ⇒ 操作参数要放 `参数` 里" % (操作名, "、".join(顶层多余键)))
        if 示例条.get("操作") != 操作名:
            问题表.append("%s：最短例的 `操作` 是 %r" % (操作名, 示例条.get("操作")))
        参数 = 示例条.get("参数", {})
        if not isinstance(参数, dict):
            问题表.append("%s：最短例 `参数` 要是对象" % 操作名)
            continue
        允许 = set(操作条.get("必需", [])) | set(操作条.get("可选", []))
        未知 = sorted(set(参数) - 允许)
        if 未知:
            问题表.append("%s：最短例 `参数` 里有本操作不认的键 %s" % (操作名, "、".join(未知)))
        缺键表 = [参数名 for 参数名 in 操作条.get("必需", []) if 参数名 != "开工ID" and 参数名 not in 参数]
        if 操作条.get("需开工ID") and not 示例条.get("开工ID"):
            缺键表.append("开工ID")
        if 缺键表:
            问题表.append("%s：最短例缺必需键 %s" % (操作名, "、".join(缺键表)))
    return 问题表


