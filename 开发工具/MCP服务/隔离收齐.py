# -*- coding: utf-8 -*-
r"""隔离收齐 —— `--自检` 的隔离池 **声明 / 提交 / 已收 三面按组名核对**，漏一组即红（fail-closed）。

**为什么要它**（2026-10-08 实撞）：`自检主体` 原先**手写**一条拼接表达式把 12 个隔离组的结果拼进
样本表 —— 新增一组时若只改了 `隔离样本组` 与 `重样本表`、漏改那条表达式，该组会**照跑、结果被
静默丢弃**，`--自检` 仍全绿（实测：4 条新样本跑完却仍报 463）。**只比长度不够** —— 换个组名、
数量相同照样漏；比长度也看不出「收了未声明的组」。

**三面 + 一批**（任一不过 ⇒ 非空说明 ⇒ 调用方落一条**失败样本**，整体非零）：
  · 声明面 = `隔离组声明`（唯一有序声明 `(组名, 该组完整样本数)`；提交与收集都从它派生）；
  · 提交面 = `样本作业表`（`跑自检` 照声明建的池作业）；
  · 已收面 = `收集样本` 照 `收集位次` 收到的组名表（按序，含重复即算错）；
  · 父进程样本批 = `输出缓冲`，位次表里必须一条不漏、不重、不越界。
每组**预期条数**由 `跑隔离样本` 核（`len(样本表) != 隔离样本组[组名]` ⇒ 整组判失败），本件不重复它。

★ 故障注入全走**替身**（假作业 / 改过的位次表）：**不动原树、不删样本** —— 删样本换绿在本件不成立。
"""

# 唯一有序声明：样本表里**池组与父进程样本批的交错位次** —— 收集只照它走，不再手写拼接表达式。
#   `("池", 组名)` 取该组结果；`("缓冲", 序号)` 取父进程样本批；`("插入", 组名)` 取结果后插到
#   `恢复样本位置`（`已记账恢复样本` 的既有落点 ⇒ 行为逐字不变）。
收集位次 = (
    ("插入", "已记账恢复样本"),
    ("池", "改名样本"), ("缓冲", 0), ("池", "上下文样本"), ("缓冲", 1), ("缓冲", 2),
    ("缓冲", 3), ("缓冲", 4), ("池", "库快照样本"), ("缓冲", 5), ("缓冲", 6),
    ("池", "跨树样本"), ("缓冲", 7), ("缓冲", 8), ("缓冲", 9), ("池", "重叠样本"),
    ("缓冲", 10), ("池", "账本差集样本"), ("池", "基线并入样本"), ("池", "易用样本一"),
    ("池", "易用样本二"), ("池", "只读缓存样本"), ("池", "记账隔离样本"), ("缓冲", 11),
)


def 收集样本(样本作业表, 输出缓冲, 位次表, 插入位置, 取值口) -> tuple:
    """按**唯一有序声明**收集 ⇒ `(样本表, 已收组表)`。

    取结果抛异常 / 池里没有该组 ⇒ 落一条**失败样本**（绝不静默吞掉整组）。
    取值口（`作业 → 结果表`）由调用方给：真池传 `Future.result`，样本传替身取值。
    """
    样本表 = []
    已收组表 = []
    for 位次 in 位次表:
        位次类别, 位次目标 = 位次
        if 位次类别 == "缓冲":
            样本表 += 输出缓冲[位次目标]
            continue
        已收组表.append(位次目标)
        try:
            结果表 = list(取值口(样本作业表[位次目标]))
        except Exception as 错误:
            结果表 = [("隔离池组 %s 取结果失败：%r" % (位次目标, 错误), False)]
        if 位次类别 == "插入":
            样本表[插入位置:插入位置] = 结果表
        else:
            样本表 += 结果表
    return 样本表, 已收组表


def 核收齐(声明组表, 样本作业表, 已收组表, 位次表, 缓冲数) -> str:
    """三面按**组名**核对 + 父进程样本批零漏 ⇒ 空串=收齐；否则一条非空说明（调用方落失败样本）。"""
    声明集 = {声明条目[0] for 声明条目 in 声明组表}
    提交集 = set(样本作业表)
    已收集 = set(已收组表)
    问题 = []
    重复 = sorted({组名 for 组名 in 已收集 if 已收组表.count(组名) > 1})
    if 重复:
        问题.append("已收面重复收集：%s" % "、".join(重复))
    for 标题, 差集 in (("声明了却没收", sorted(声明集 - 已收集)),
                   ("收了未声明的组", sorted(已收集 - 声明集)),
                   ("声明了却没提交作业", sorted(声明集 - 提交集)),
                   ("提交了未声明的作业", sorted(提交集 - 声明集))):
        if 差集:
            问题.append("%s：%s" % (标题, "、".join(差集)))
    已用缓冲 = sorted(位次[1] for 位次 in 位次表 if 位次[0] == "缓冲")
    if 已用缓冲 != list(range(缓冲数)):
        问题.append("父进程样本批（%d 条）位次不齐：%s" % (缓冲数, 已用缓冲))
    if not 问题:
        return ""
    return ("★ 隔离组收齐核对不过（声明 %d · 提交 %d · 已收 %d）：%s"
            % (len(声明集), len(提交集), len(已收集), "；".join(问题)))


class 替身作业:
    """替身作业：`取值()` 回该组**预期条数**的通过样本（样本用；不 spawn、不写盘）。"""

    def __init__(self, 组名, 样本条数):
        self.组名 = 组名
        self.样本条数 = 样本条数

    def 取值(self) -> list:
        return [("%s样本%02d" % (self.组名, 序号), True) for 序号 in range(self.样本条数)]


class 替身坏作业:
    """替身作业：`取值()` 抛异常（验「取结果失败 ⇒ 落失败样本、不静默」）。"""

    def 取值(self) -> list:
        raise RuntimeError("样本：替身作业取结果失败")


def 样本列表(仓根, 工具表) -> list:
    """⇒ 样本表：三面齐 + 七路故障注入（全走替身，不动原树、不删样本）。"""
    from .自检样本 import 隔离组声明

    取值口 = lambda 作业: 作业.取值()
    声明名表 = [声明条目[0] for 声明条目 in 隔离组声明]
    作业表 = {声明条目[0]: 替身作业(声明条目[0], 声明条目[1]) for 声明条目 in 隔离组声明}
    缓冲批 = []
    for 序号 in range(12):
        缓冲批.append([("父进程样本批%02d" % 序号, True)])
    满样本, 满已收 = 收集样本(作业表, 缓冲批, 收集位次, 0, 取值口)
    满说明 = 核收齐(隔离组声明, 作业表, 满已收, 收集位次, len(缓冲批))
    满条数 = sum(声明条目[1] for 声明条目 in 隔离组声明) + len(缓冲批)
    样本表 = [
        ("收齐·三面齐（真声明 + 替身作业 + 真位次表）：说明空 %s · 聚合条数 %d（期望 %d）· 已收组 %d（期望 %d）"
         % ("是" if 满说明 == "" else "否（%s）" % 满说明, len(满样本), 满条数,
            len(满已收), len(声明名表)),
         满说明 == "" and len(满样本) == 满条数 and len(满已收) == len(声明名表)),
    ]
    坏作业表 = dict(作业表)
    坏作业表[声明名表[0]] = 替身坏作业()
    坏样本, 坏已收 = 收集样本(坏作业表, 缓冲批, 收集位次, 0, 取值口)
    坏条 = [说明 for 说明, 通过 in 坏样本 if not 通过]
    样本表.append(("收齐·取结果抛异常 ⇒ 落**失败样本**（不静默丢整组）· 该组仍在已收面 %s · 聚合条数 %d（期望 %d）"
             % ("是" if 声明名表[0] in 坏已收 else "否", len(坏样本),
                满条数 - 隔离组声明[0][1] + 1),
             bool(坏条) and 声明名表[0] in 坏已收
             and len(坏样本) == 满条数 - 隔离组声明[0][1] + 1))
    漏缓冲位次 = tuple(位次 for 位次 in 收集位次 if 位次 != ("缓冲", 11))
    换位次 = tuple(("池", "易用样本一") if 位次 == ("池", "易用样本二") else 位次
              for 位次 in 收集位次)
    换位次样本, 换位次已收 = 收集样本(作业表, 缓冲批, 换位次, 0, 取值口)
    换位次说明 = 核收齐(隔离组声明, 作业表, 换位次已收, 换位次, len(缓冲批))
    故障表 = (
        ("已收面漏收一组", 隔离组声明, 作业表,
         [组名 for 组名 in 满已收 if 组名 != 声明名表[-1]], 收集位次, len(缓冲批), 声明名表[-1]),
        ("已收面改组名（数量同形）", 隔离组声明, 作业表,
         [组名 if 组名 != 声明名表[0] else "改名的组" for 组名 in 满已收], 收集位次,
         len(缓冲批), "改名的组"),
        ("提交面缺映射", 隔离组声明,
         {组名: 作业表[组名] for 组名 in 声明名表 if 组名 != 声明名表[0]}, 满已收, 收集位次,
         len(缓冲批), 声明名表[0]),
        ("已收面重复收集", 隔离组声明, 作业表, 满已收 + [声明名表[0]], 收集位次,
         len(缓冲批), 声明名表[0]),
        ("已收面多出未声明的组", 隔离组声明, 作业表, 满已收 + ["多出来的组"], 收集位次,
         len(缓冲批), "多出来的组"),
        ("位次表漏收一条父进程样本批", 隔离组声明, 作业表, 满已收, 漏缓冲位次,
         len(缓冲批), "位次不齐"),
        ("位次表换组名（组名与数量都同形）", 隔离组声明, 作业表, 换位次已收, 换位次,
         len(缓冲批), "易用样本二"),
    )
    for 说明, 声明表, 提交表, 已收表, 位次表, 缓冲数, 应点名 in 故障表:
        说明文本 = 核收齐(声明表, 提交表, 已收表, 位次表, 缓冲数)
        样本表.append(("收齐·故障注入「%s」⇒ 说明非空且点名「%s」（%s）"
                 % (说明, 应点名, 说明文本 or "★ 空 ⇒ 漏！"),
                 说明文本 != "" and 应点名 in 说明文本))
    return 样本表
