# -*- coding: utf-8 -*-
"""源件记账 —— `v1_task` 功能 = 6：把**由仓内命令改的源件**记进账本。

**为什么要有它**（实测）：规则库 `开发工具/信息核心/信息核心.db` 是**源**（受版本控制），
改它走 `信息核心.py` 的 `登记` / `记规则` / `冻结基线` —— 那些命令**不是生成器**，也不保证每次
都落盘（幂等命令不写盘）。于是 `v1_task` 功能 = 5（生成物记账）看不见它：跑前/跑后指纹没变
⇒ 报「0 件」⇒ 库仍不在改动表 ⇒ 功能 = 3 释放的越界检测把它挡下。

**它补的那条路**：记一个「由仓内命令改的源件」—— 件路径 ＋ 为什么 ＋ 写后指纹。**档名与生成物
分开**（`源件档名` vs `生成物记账.改动档名`）：生成物由生成器写、源件由仓内命令写，两类来源不同。

**它不放松闸**：仍要求件在盘上**真变过**（`git status` 里脏）—— 没变的件不许记（记了就是谎）；
且**只收 `v1_edit` 读不动的件**（二进制 / 非 utf-8，如规则库 `.db`；审计 B-1）—— `v1_edit` 能读的件
必须走四道闸，不许从本口洗白；同 (路径, 写后指纹) 已记过 ⇒ 不重复记（审计 B-4，幂等）；
写回指纹 + 记改动**复用账本里已有的两步**（与 `v1_edit` / 生成物记账同一套），不新造写入口。

**写前取「认领时记的指纹」**（那是上次已知良好态），写完**必须把认领表里该件的指纹更新成写后值**
（`写回指纹`，否则绕过检测恒把正当的库改动报成「绕过 MCP」）；若写前 == 写后（先改后认领、
或根本没改）⇒ **如实报一行警示**，不许静默印成「改过」（实测腿 v1-100235：回执印「写前 X → 写后 X」
两值相同，账本因此失去「这个件真被改过」的证据）。
"""

from pathlib import Path

from .仓操作 import 变更路径表    # 先导仓操作：它把 开发工具/ 挂上 sys.path
from 代码地图 import 文件指纹     # noqa: E402
from . import 开工账本 as 账本    # noqa: E402

源件档名 = 账本.源件档名          # 唯一一份在 `开工账本`（`源件路径集` 也引它）


def 记账(仓根, 开工号: str, 源件: str, 说明: str) -> tuple:
    """把**由仓内命令改的源件**记进账本 ⇒ `(退出码, 说明)`。

    `源件` = 仓内相对路径（如 `开发工具/信息核心/信息核心.db`）；`说明` = 为什么改它
    （落 `改动.说明` 栏）。盘上没变过的件**不记**（fail-closed：不许把没发生的事记成发生）。
    """
    连接 = 账本.连账本()
    try:
        一条开工 = 账本.读开工(连接, 开工号)
        if not 一条开工:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记" % 开工号
        if 一条开工["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能再记账" % 一条开工["状态"]
        工作树 = Path(一条开工["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再记账" % 工作树
        相对 = str(源件 or "").strip()
        if not 相对:
            return 2, ("功能 = 6 要 `源件`（由仓内命令改过的件的仓内相对路径，"
                     "如 `开发工具/信息核心/信息核心.db`）")
        if 相对.startswith("/") or ".." in Path(相对).parts:
            return 2, "`源件` 只认仓内相对路径（不许绝对路径 / 不许 `..`）：%r" % 相对
        件路径 = 工作树 / 相对
        if not 件路径.is_file():
            return 1, "源件不在工作树里：%s" % 相对
        退出码, 变更表 = 变更路径表(工作树)
        if 退出码 != 0:
            return 1, "查不清盘上动了什么（git status 失败）⇒ 没记账"
        if 相对 not in 变更表:
            return 1, ("盘上 `%s` **没变过**（不在 git status 的脏件里）⇒ 没记账："
                     "源件记账只记**真改过**的件 —— 先跑仓内命令改它，再来记。" % 相对)
        # ── fail-closed：只收 `v1_edit` **读不动**的件（2026-10-05 审计 B-1）──
        # 本口原先唯一的拦阻是「git 脏」⇒ 一条腿可以先认领 X、用 sed 绕过四道闸改 X、再 功能 = 6
        # 把 X 记成「源件」—— 记过之后 X 进 `源件路径集`，`修改.对账_除源件` 把它从「变过」里剔
        # 出去 ⇒ 绕过检测对它关闭，未经四道闸的改动被合法提交。故加两条判据：`v1_edit` 能读的件
        # 必须走 `v1_edit`（四道闸），不许从本口洗白；本口只收**读不动**的二进制源（规则库 `.db`）。
        try:
            件路径.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            pass
        else:
            return 1, ("`%s` **读得成文本**（utf-8）⇒ 它归 `v1_edit` 管（四道闸），不许从 功能 = 6 "
                     "记账：本口只收 `v1_edit` **读不动**的件（二进制 / 非 utf-8，如规则库 `.db`）。"
                     "要改它就走 `v1_edit`：先 `v1_task` 功能 = 2 补认领，再 功能 = 1 改。" % 相对)
        改过表 = {一条改动["路径"] for 一条改动 in 账本.读改动(连接, 开工号)
                if 一条改动["功能"] != 源件档名}
        if 相对 in 改过表:
            return 1, ("`%s` 已经带 `v1_edit` 的改动行（`v1_edit` 写过它）⇒ 不许再当「源件」记："
                     "同一件不能既走四道闸、又走本口洗白。" % 相对)
        写后指纹 = 文件指纹(str(件路径))
        认领表 = 账本.读认领(连接, 开工号)
        写前指纹 = 认领表.get(相对) or ""
        账本.写回指纹(连接, 开工号, 相对, 写后指纹)
        # 幂等（2026-10-05 审计 B-4）：同 (路径, 写后指纹) 已有一条 ⇒ 不重复记（重跑不再追加垃圾行）。
        if (相对, 写后指纹) in {(一条改动["路径"], 一条改动["写后指纹"])
                             for 一条改动 in 账本.读改动(连接, 开工号)}:
            输出行表 = ["%s：源件 `%s` 已在账本（同路径 + 同写后指纹）⇒ **不重复记**（幂等）"
                     % (开工号, 相对)]
        else:
            账本.记改动(连接, 开工号, 相对, 源件档名, 写前指纹, 写后指纹, str(说明 or "").strip())
            输出行表 = ["%s：源件 `%s` 记进账本（功能「%s」）" % (开工号, 相对, 源件档名),
                     "  写前 %s → 写后 %s" % (写前指纹 or "（未认领）", 写后指纹),
                     "  为什么：%s" % (说明 or "（未写 —— 下次带上 `源件说明`）")]
        if 写前指纹 == 写后指纹:
            输出行表.append("★ **写前 == 写后**（%s）：这个件在**认领之前**就被改过（或根本没改）"
                        " ⇒ 账本这条改动**不构成「本腿改过它」的证据**（盘上它确实脏，git status 认过）。"
                        " 要留证据，就在**认领之后**再跑一次仓内命令改它，再重跑 功能 = 6。"
                        % (写后指纹 or "（空）"))
        return 0, "\n".join(输出行表)
    finally:
        连接.close()
