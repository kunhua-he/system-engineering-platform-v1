"""主干写盘兜底 —— `v1_shell` **不带开工ID** 时的写盘拦截：跑前快照 · 跑后比对 · 脏了就还原。

**为什么要有它**（实测 · 未完成台账同题条）：`v1_shell` 不带 `开工ID` 时 cwd = 服务仓根（主干工作区），
而本工具**不在四道闸之内**（它是执行器、不是适配层）⇒ 一条 `python3 -c "…改库…"` 就能把改动
直接写进主干工作区，**绕过写盘闸、也不被开工ID 重定向**（实证：记条款被写进主干，须
`git checkout` 还原后才在腿树重做）。

**口径**（不产生第二条腿）：写盘正路仍只有 `v1_edit` 与仓内正式口；本件只做**兜底** ——
不带 `开工ID` 时把「**已跟踪件**被改 / 删」**还原**、把「**新增未跟踪件**」**如实报出**（不擅自删）。
带 `开工ID` ⇒ 写盘发生在腿树里、是正常路径 ⇒ **本件不介入**。

**为什么判据放在结果上、不放在语法上**：命令原样交给 `/bin/sh`，靠正则认「哪条是写盘」必漏
（重定向 · `sed -i` · `python -c` 写库 · `tee` · `dd` …）。判据改看 **git 看得见的结果**：
跑前跑后各取一次已跟踪件状态，多出来的脏就是本次命令写的。

**读不出 git 状态 ⇒ fail-closed**：给不出快照就说「无法判定」，不假装干净（假绿比不判更坏）。
"""

from .仓操作 import 跑命令

# 取快照 / 还原的超时（只读 git 与单件 checkout，都很快；超时 ⇒ 调用方 fail-closed）
快照超时秒 = 4
还原超时秒 = 4


def 取主干快照(仓根) -> tuple:
    """主干工作区状态 ⇒ `(已跟踪件表, 未跟踪件表)`；读不出 ⇒ `(None, None)`（fail-closed）。

    `已跟踪件表` = `{相对路径: 两字码}`，只收 `git status --porcelain` 里的**非 `??`** 行
    （`??` 是未跟踪新件 —— 没被改坏、只是多出来的，另报不删）。`未跟踪件表` 就是那些 `??` 路径。
    **一次 git 调用取两样**（少一次子进程）。
    """
    退出码, 输出 = 跑命令(["git", "status", "--porcelain", "-uall"], 仓根, 超时秒数=快照超时秒)
    if 退出码 != 0:
        return None, None
    已跟踪表, 未跟踪表 = {}, []
    for 行文本 in 输出.splitlines():
        if len(行文本) <= 3:
            continue
        路径 = 行文本[3:].strip().strip('"')
        if 行文本.startswith("??"):
            未跟踪表.append(路径)
        else:
            已跟踪表[路径] = 行文本[:2]
    return 已跟踪表, sorted(未跟踪表)


def 兜底(仓根, 前快照, 后快照, 未跟踪表: list) -> list:
    """跑完比对 ⇒ **告警行表**（空 = 本次没写主干）。

    已跟踪件被改 / 删 ⇒ 逐件 `git checkout --` **还原**（写盘正路是 `v1_edit`，不该由这里写主干）；
    新增未跟踪件 ⇒ **如实报出、不擅自删**（可能是调用方有意留的产物）。
    """
    if 前快照 is None or 后快照 is None:
        return ["★ 主干写盘兜底：读不出 git 状态 ⇒ **无法判定**本次命令有没有写主干"
                "（fail-closed，请自行核对）"]
    新增脏 = sorted(路径 for 路径, 状态码 in 后快照.items() if 前快照.get(路径) != 状态码)
    行表 = []
    if 新增脏:
        还原表, 失败表 = [], []
        for 路径 in 新增脏:
            退出码, _ = 跑命令(["git", "checkout", "--", 路径], 仓根, 超时秒数=还原超时秒)
            (还原表 if 退出码 == 0 else 失败表).append(路径)
        行表.append("★ **主干写盘已被拦下并还原**（%d 件）：%s" % (len(还原表), "、".join(还原表)))
        行表.append("  不带 `开工ID` 时本工具 cwd = 主干工作区 ⇒ 写盘会绕过写盘闸与开工ID 重定向。")
        行表.append("  改文件请走 `v1_edit`；要在腿树里写，请带上 `开工ID`。")
        if 失败表:
            行表.append("  ⚠ 还原失败（请手工核对）：%s" % "、".join(失败表))
    if 未跟踪表:
        行表.append("★ 主干工作区现有未跟踪件 %d 个（**未擅自删**）：%s"
                  % (len(未跟踪表), "、".join(未跟踪表[:10])))
    return 行表
