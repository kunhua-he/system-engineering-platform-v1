# -*- coding: utf-8 -*-
"""清理条目样本 —— 「清理已解决任务」的**条目模式（跨开工定向）正反**样本。

**为什么单开一件**（判据 ⑲ 单件 ≤400 行）：任务模式样本已近硬数；条目模式是**另一个入口**
（审计所属与承接任务分列：条目住 A 腿、维修在 B 腿），单列一件，读得完也守得住。

一片一测（每条可证伪）：跨开工定向只删**标定条目**（同来源别的条目与别的开工的反馈**一字不动**）·
`审计所属` 与条目实际开工号不符 ⇒ 拒（防跨开工误判）· `承接任务` 不是真开工 / 未合主干 ⇒ 拒 ·
`承接提交` 只存在某支线（**非主干祖先**）⇒ 拒（不得当完成）· 关闭开工号与承接任务不符 ⇒ 拒 ·
预览默认拒绝不写盘 · 真删**不动**任何开工 / 认领 / 改动行。

**夹具复用**（`清理样本.样本列表` 的基座）：腿在 `条目样本列表` 里建**一次**（同一条腿反复用会撞
`git worktree add`）；各场只换**独立运行数据根**，互不串账。
"""

from ...反馈治理 import 反馈账本
from ...现场清理 import 任务清理
from .清理样本工具 import (样本环境, 加关闭行, 加判词行, 加来源行, 加条目行, 造报告件,
                    建样本账, 建样本腿, 数样本行, 连样本账, 跑样本命令, 支线提交)

审计开工号 = "v1-900201"
承接开工号 = "v1-900202"
未合承接号 = "v1-900203"
支线承接号 = "v1-900204"


def 连条目账(数据根):
    return 连样本账(数据根)


def _造跨开工条目(数据根, 主目录, 腿表):
    """造「审计所属 = A 腿 / 承接任务 = B 腿」的一条已解决条目（跨开工定向）⇒ 取数。"""
    建样本账(数据根, 审计开工号, 腿表[审计开工号])
    建样本账(数据根, 承接开工号, 腿表[承接开工号])
    报告件 = 造报告件(数据根, "条目报告.md")
    连接 = 连条目账(数据根)
    来源号 = 加来源行(连接, 审计开工号, "样本/条目", 报告件)
    已解决条目 = 加条目行(连接, 来源号, 审计开工号, "已解决：债务（承接在别腿）")
    加判词行(连接, 已解决条目, 反馈账本.判词_债务, 反馈账本.关联_开工, 承接开工号)
    未解决条目 = 加条目行(连接, 来源号, 审计开工号, "未解决：待核（同来源另一条）")
    加判词行(连接, 未解决条目, 反馈账本.判词_待核)
    加关闭行(连接, 已解决条目, 跑样本命令(主目录, "rev-parse", "主干"),
          关闭开工号=承接开工号)
    连接.commit()
    连接.close()
    return 已解决条目, 未解决条目, 来源号


def _场一(数据根, 主目录, 腿表):
    """① 跨开工定向真删：只删标定条目；同来源别的条目别的开工一字不动；不动开工 / 认领 / 改动行。"""
    样本表 = []
    已解决条目, 未解决条目, 来源号 = _造跨开工条目(数据根, 主目录, 腿表)
    选择项 = {"条目号": 已解决条目, "审计所属": 审计开工号, "承接任务": 承接开工号}
    with 样本环境(数据根):
        预览码, _预览文 = 任务清理.跑清理(主目录, "", {"条目选择": [选择项]})
        条目数未动 = 数样本行(数据根, "select count(*) from 反馈条目 where 来源号=?", (来源号,))
        确认码, _确认文 = 任务清理.跑清理(主目录, "", {"确认": True, "条目选择": [选择项]})
    条目数 = 数样本行(数据根, "select count(*) from 反馈条目 where 来源号=?", (来源号,))
    来源数 = 数样本行(数据根, "select count(*) from 反馈来源 where 来源号=?", (来源号,))
    认领数 = 数样本行(数据根, "select count(*) from 认领")
    留存号 = 数样本行(数据根, "select count(*) from 反馈条目 where 条目号=?", (未解决条目,))
    样本表.append(("① 条目模式预览默认拒绝：退出码 %d（期望 2）· 库行未动（条目 %d，期望 2）"
             % (预览码, 条目数未动), 预览码 == 2 and 条目数未动 == 2))
    样本表.append(("① 跨开工定向真删标定条目：退出码 %d（期望 0）· 同来源留 %d（期望 1：未解决那条）· "
             "来源行保留 %d（期望 1，混合来源）"
             % (确认码, 条目数, 来源数), 确认码 == 0 and 条目数 == 1 and 来源数 == 1))
    样本表.append(("① 条目模式**不动**开工 / 认领 / 改动行：认领 %d（期望 2，两腿各一）" % 认领数,
             认领数 == 2))
    样本表.append(("① 未解决条目一字未动（%d，期望 1）" % 留存号, 留存号 == 1))
    return 样本表


def _场二(数据根, 主目录, 腿表):
    """② 归属反例：审计所属不符 / 承接任务非真开工 / 未合主干 / 承接提交非主干祖先 ⇒ 拒。"""
    样本表 = []
    已解决条目, _, _ = _造跨开工条目(数据根, 主目录, 腿表)
    错属项 = {"条目号": 已解决条目, "审计所属": "v1-900999", "承接任务": 承接开工号}
    with 样本环境(数据根):
        错属码, 错属文 = 任务清理.跑清理(主目录, "", {"确认": True, "条目选择": [错属项]})
    样本表.append(("② 审计所属与条目实际开工号不符 ⇒ 拒：退出码 %d（期望 1）· 说「防跨开工」%s"
             % (错属码, "是" if "防跨开工" in 错属文 else "否"),
             错属码 == 1 and "防跨开工" in 错属文))
    建样本账(数据根, 未合承接号, 腿表[未合承接号])
    未合项 = {"条目号": 已解决条目, "审计所属": 审计开工号, "承接任务": 未合承接号}
    with 样本环境(数据根):
        未合码, 未合文 = 任务清理.跑清理(主目录, "", {"确认": True, "条目选择": [未合项]})
    样本表.append(("② 承接任务未合主干 ⇒ 拒：退出码 %d（期望 1）· 说「未合主干」%s"
             % (未合码, "是" if "未合主干" in 未合文 else "否"),
             未合码 == 1 and "未合主干" in 未合文))
    假开工项 = {"条目号": 已解决条目, "审计所属": 审计开工号, "承接任务": "v1-999999"}
    with 样本环境(数据根):
        假开工码, 假开工文 = 任务清理.跑清理(主目录, "", {"确认": True, "条目选择": [假开工项]})
    样本表.append(("② 承接任务不是真开工 ⇒ 拒：退出码 %d（期望 1）· 说「不是真开工」%s"
             % (假开工码, "是" if "不是真开工" in 假开工文 else "否"),
             假开工码 == 1 and "不是真开工" in 假开工文))
    非主干码, 非主干文 = _试非主干承接(数据根, 主目录, 腿表, 已解决条目)
    样本表.append(("② 承接提交只存在某支线（非主干祖先）⇒ 拒：退出码 %d（期望 1）· "
             "说「主干祖先」%s" % (非主干码, "是" if "主干祖先" in 非主干文 else "否"),
             非主干码 == 1 and "主干祖先" in 非主干文))
    return 样本表


def _试非主干承接(数据根, 主目录, 腿表, 已解决条目):
    """把承接提交改成**只存在某支线**的提交（非主干祖先）⇒ 试条目模式（期望拒）。"""
    建样本账(数据根, 支线承接号, 腿表[支线承接号])
    支线号 = 支线提交(主目录, 支线承接号)
    连接 = 连条目账(数据根)
    连接.execute("update 反馈关闭 set 承接提交 = ?, 关闭开工号 = ? where 条目号 = ?",
             (支线号, 支线承接号, 已解决条目))
    连接.commit()
    连接.close()
    选择条目 = {"条目号": 已解决条目, "审计所属": 审计开工号, "承接任务": 支线承接号}
    with 样本环境(数据根):
        return 任务清理.跑清理(主目录, "", {"确认": True, "条目选择": [选择条目]})


def _场三(数据根, 主目录, 腿表):
    """③ 真实形状（审计与关闭同腿、承接在另腿）⇒ **放行**；承接任务与条目毫无关联 ⇒ 拒。

    实测 4163/4379/4382 就是「审计所属 = 642 · 关闭开工号 = 642 · 承接提交落 643」⇒ 承接任务
    与关闭开工号**本就不同腿**。只把「与条目毫无关联的开工号」当张冠李戴拒。
    """
    已解决条目, _, _ = _造跨开工条目(数据根, 主目录, 腿表)
    连接 = 连条目账(数据根)
    连接.execute("update 反馈关闭 set 关闭开工号 = ? where 条目号 = ?", (审计开工号, 已解决条目))
    连接.commit()
    连接.close()
    选择条目 = {"条目号": 已解决条目, "审计所属": 审计开工号, "承接任务": 承接开工号}
    with 样本环境(数据根):
        放行码, _放行文 = 任务清理.跑清理(主目录, "", {"确认": True, "条目选择": [选择条目]})
    错接根 = 数据根 / "错接数据根"
    错接条目, _, _ = _造跨开工条目(错接根, 主目录, 腿表)
    with 样本环境(错接根):
        错接码, 错接文 = 任务清理.跑清理(主目录, "", {"确认": True, "条目选择": [
            {"条目号": 错接条目, "审计所属": 审计开工号, "承接任务": "v1-900299"}]})
    return [("③ 真实形状（审计/关闭同腿 · 承接在另腿）⇒ 放行：退出码 %d（期望 0）" % 放行码,
             放行码 == 0),
            ("③ 承接任务与条目毫无关联 ⇒ 拒（防张冠李戴）：退出码 %d（期望 1）· 说「真关联」%s"
             % (错接码, "是" if "真关联" in 错接文 else "否"),
             错接码 == 1 and "真关联" in 错接文)]


def 条目样本列表(临时根, 主目录) -> list:
    """条目模式正反样本 ⇒ 样本表（腿建一次复用；各场独立运行数据根，跑完即删）。"""
    # 各腿**只建一次**（`git worktree add` 对同名支线会失败）—— 各场只换独立运行数据根。
    腿表 = {审计开工号: 建样本腿(主目录, 审计开工号, 并入主干=True),
           承接开工号: 建样本腿(主目录, 承接开工号, 并入主干=True),
           未合承接号: 建样本腿(主目录, 未合承接号, 并入主干=False),
           支线承接号: 建样本腿(主目录, 支线承接号, 并入主干=False)}
    样本表 = []
    样本表 += _场一(临时根 / "条目一数据根", 主目录, 腿表)
    样本表 += _场二(临时根 / "条目二数据根", 主目录, 腿表)
    样本表 += _场三(临时根 / "条目三数据根", 主目录, 腿表)
    return 样本表
