def _场五(数据根, 主目录, 合并树):
    """⑤ 归属作业：按 开工ID / 工作树身份 / 关闭记录任务ID（真归属）；未归属的不动；日志随删。"""
    样本表 = []
    开工号 = "v1-900105"
    建样本账(数据根, 开工号, 合并树)
    连接 = 连样本账(数据根)
    来源号 = 加来源行(连接, 开工号, "样本/五", 造报告件(数据根, "五报告.md"))
    加审完(连接, [来源号])
    条目号 = 加条目行(连接, 来源号, 开工号, "已解决：债务（按关闭记录的任务ID关联）")
    加判词行(连接, 条目号, 反馈账本.判词_债务, 反馈账本.关联_开工, 开工号)
    关联作业号 = "4" * 32
    加关闭行(连接, 条目号, 跑样本命令(主目录, "rev-parse", "主干"),
          日志指针="作业 %s 的产物" % 关联作业号)
    连接.commit()
    连接.close()
    日志目录 = 数据根 / "日志"
    日志目录.mkdir(parents=True, exist_ok=True)
    本任务作业号, 同树作业号, 他处作业号 = "1" * 32, "2" * 32, "3" * 32
    本任务作业日志 = 日志目录 / (本任务作业号 + ".log")
    同树作业日志 = 日志目录 / (同树作业号 + ".工作.log")
    关联作业日志 = 日志目录 / (关联作业号 + ".log")
    他处作业日志 = 日志目录 / (他处作业号 + ".log")
    for 日志件 in (本任务作业日志, 同树作业日志, 关联作业日志, 他处作业日志):
        日志件.write_text("作业日志\n", encoding="utf-8")
    作业连接 = 连作业库(数据根)
    for 任务号, 工作树, 归属开工号 in ((本任务作业号, str(合并树), 开工号),
                                (同树作业号, str(合并树), ""),
                                (他处作业号, str(主目录), ""),
                                (关联作业号, str(主目录), "")):
        作业连接.execute("insert into 作业 (任务ID, 状态, 命令, 工作树, 开工ID, 开始时间) "
                   "values (?, ?, ?, ?, ?, ?)",
                   (任务号, "已完成", "样本命令", 工作树, 归属开工号, "时刻"))
    作业连接.commit()
    作业连接.close()
    with 样本环境(数据根):
        退出码, _报告 = 任务清理.跑清理(主目录, 开工号, {"确认": True})
    作业连接 = 连作业库(数据根)
    余留号表 = sorted(数据行[0] for 数据行 in 作业连接.execute("select 任务ID from 作业"))
    作业连接.close()
    样本表.append(("⑤ 归属作业（开工ID / 同树 / 关闭记录任务ID）：退出码 %d（期望 0）· "
             "余留 %d 条（期望 1：未归属的那一条）"
             % (退出码, len(余留号表)), 退出码 == 0 and 余留号表 == [他处作业号]))
    样本表.append(("⑤ 归属作业日志随删：本任务 %s · 同树 %s · 关联 %s · 他处保留 %s"
             % ("在" if 本任务作业日志.is_file() else "已删",
                "在" if 同树作业日志.is_file() else "已删",
                "在" if 关联作业日志.is_file() else "已删",
                "是" if 他处作业日志.is_file() else "否"),
             not 本任务作业日志.is_file() and not 同树作业日志.is_file()
             and not 关联作业日志.is_file() and 他处作业日志.is_file()))
    with 样本环境(数据根):
        点名码, 点名文 = 任务清理.跑清理(主目录, 开工号, {"确认": True, "作业名单": ["x" * 32]})
    样本表.append(("⑤ 撤销的 `作业名单` ⇒ 拒（任意点名不可信）：退出码 %d（期望 2）· 说「已撤」%s"
             % (点名码, "是" if "已撤" in 点名文 else "否"),
             点名码 == 2 and "已撤" in 点名文))
    return 样本表


def _场六(数据根, 主目录, 合并树):
    """⑥ 临时快照消费（655 helper）：全清来源的快照无剩余引用 ⇒ 删；共享 / 混合来源 ⇒ 留。"""
    样本表 = []
    开工号 = "v1-900106"
    建样本账(数据根, 开工号, 合并树)
    独有快照 = 造快照件(数据根, "独有正文\n")
    共享快照 = 造快照件(数据根, "共享正文\n")
    混合快照 = 造快照件(数据根, "混合正文\n")
    连接 = 连样本账(数据根)
    独有来源 = 加来源行(连接, 开工号, "样本/独有快照", None, 快照路径=独有快照)
    独有条目 = 加条目行(连接, 独有来源, 开工号, "已解决：非问题（独有快照）")
    加判词行(连接, 独有条目, 反馈账本.判词_非问题)
    共享来源 = 加来源行(连接, 开工号, "样本/共享快照", None, 快照路径=共享快照)
    共享条目 = 加条目行(连接, 共享来源, 开工号, "已解决：非问题（共享快照）")
    加判词行(连接, 共享条目, 反馈账本.判词_非问题)
    加来源行(连接, "v1-900199", "别的任务/同快照", None, 快照路径=共享快照)
    混合来源 = 加来源行(连接, 开工号, "样本/混合快照", None, 快照路径=混合快照)
    已解决条目 = 加条目行(连接, 混合来源, 开工号, "已解决：非问题（混合快照）")
    加判词行(连接, 已解决条目, 反馈账本.判词_非问题)
    待核条目 = 加条目行(连接, 混合来源, 开工号, "未解决：待核（混合快照）")
    加判词行(连接, 待核条目, 反馈账本.判词_待核)
    加审完(连接, [独有来源, 共享来源, 混合来源])
    连接.commit()
    连接.close()
    with 样本环境(数据根):
        退出码, _报告 = 任务清理.跑清理(主目录, 开工号, {"确认": True})
    样本表.append(("⑥ 临时快照：独有 %s（期望 已删）· 共享 %s（期望 在）· 混合 %s（期望 在）"
             % ("在" if Path(独有快照).is_file() else "已删",
                "在" if Path(共享快照).is_file() else "已删",
                "在" if Path(混合快照).is_file() else "已删"),
             退出码 == 0 and not Path(独有快照).is_file()
             and Path(共享快照).is_file() and Path(混合快照).is_file()))
    return 样本表


