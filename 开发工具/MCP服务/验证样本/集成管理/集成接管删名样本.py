"""集成接管删名样本 —— 源库三方重放里「腿侧删名」动作的**绿红对照**样本（迷你命名库，不进仓）。

为什么单开一件：`集成接管样本.py` 已 293 行，加进去会顶 400 行硬顶（判据 ⑲）⇒ 增量落新件。

它守的是 `集成接管.核验重放` 的那个**真缺陷**（2026-10-08 阻 656 合并的根）：
`合并三方库` 把「基/主干有行 · 腿无行」记成 `腿值 = None`（腿侧**删除**）；而旧核验
`行元组 is None or 语义不等 ⇒ 缺` 把「实际也 None」（删成了）当成缺行 ⇒ **误拒**。
正样本：腿侧删 + 新增均落库 ⇒ 核验必绿。反样本：删未执行 / 新增未落库 ⇒ 核验必红。
"""
import sqlite3
import tempfile
from pathlib import Path

from ... import 合主干源库重放 as 重放
from ...集成管理 import 集成接管

# 迷你 `信息核心.py`：只认 `登记`（含 `--删`）—— 删名重放夹具用（真改库 ⇒ 核验读得到）。
删除名信息核心源码 = (
    "import sqlite3, sys\n"
    "from pathlib import Path\n"
    "参表 = sys.argv[1:]\n"
    "子命令 = 参表[0] if 参表 else ''\n"
    "键值 = {}\n"
    "键 = None\n"
    "for 项 in 参表[1:]:\n"
    "    if 项.startswith('--'):\n"
    "        键 = 项[2:]\n"
    "        键值[键] = ''\n"
    "    elif 键:\n"
    "        键值[键] = 项\n"
    "if 子命令 != '登记':\n"
    "    raise SystemExit(3)\n"
    "连接 = sqlite3.connect(str(Path('开发工具/信息核心/信息核心.db')))\n"
    "if '删' in 键值:\n"
    "    连接.execute('delete from 命名登记 where 名字=?', (键值.get('名字', ''),))\n"
    "else:\n"
    "    连接.execute('insert or replace into 命名登记 (名字, 语义, 模式, 来源, 状态) values (?,?,?,?,?)',\n"
    "               (键值.get('名字', ''), 键值.get('语义', ''), 键值.get('模式', '对象+说明'),\n"
    "                键值.get('来源', '新定义'), 键值.get('状态', '合格')))\n"
    "连接.commit()\n"
    "连接.close()\n"
    "print('登记 ok')\n"
)

库相对路径 = "开发工具/信息核心/信息核心.db"


def _建迷你命名库(库件, 命名行表):
    """建一个只含命名登记表的迷你规则库（含 出现次数/创建时间 派生列，与真库同形）。"""
    连接 = sqlite3.connect(str(库件))
    连接.execute("create table 命名登记(名字 text primary key, 语义 text, 模式 text, 来源 text, 状态 text, 出现次数 integer, 创建时间 text)")
    for 名字, 语义 in 命名行表:
        连接.execute("insert into 命名登记 values (?,?,?,?,?,0,'')",
                  (名字, 语义, "对象+说明", "新定义", "合格"))
    连接.commit()
    连接.close()


def _建删名夹具(工作根) -> dict:
    """迷你三方（基/腿/主干）命名库 + 集成树（带迷你 信息核心.py）⇒ 夹具表。

    腿侧 = 删一名（删除命名） + 新增一名（新增命名）（对齐 656 实测那三条动作：1 删 + 2 增）。
    """
    基库 = 工作根 / "基" / 库相对路径
    腿库 = 工作根 / "腿" / 库相对路径
    主干库 = 工作根 / "主干" / 库相对路径
    集成路径 = 工作根 / "集成"
    行表集 = (
        (基库, (("保留命名", "保留语义"), ("删除命名", "删除语义"))),
        (腿库, (("保留命名", "保留语义"), ("新增命名", "新增语义"))),
        (主干库, (("保留命名", "保留语义"), ("删除命名", "删除语义"))),
    )
    for 库件, 命名行表 in 行表集:
        库件.parent.mkdir(parents=True, exist_ok=True)
        _建迷你命名库(库件, 命名行表)
    信息核心件 = 集成路径 / "开发工具/信息核心/信息核心.py"
    信息核心件.parent.mkdir(parents=True, exist_ok=True)
    信息核心件.write_text(删除名信息核心源码, encoding="utf-8")
    return {"基库": 基库, "腿库": 腿库, "主干库": 主干库, "集成路径": 集成路径}


def _读现存名(集成路径) -> set:
    """集成树规则库里现存的命名集合 ⇒ 集合。"""
    集成库件 = 集成路径 / 库相对路径
    连接 = sqlite3.connect("file:%s?mode=ro" % 集成库件, uri=True)
    try:
        return {数据行[0] for 数据行 in 连接.execute("select 名字 from 命名登记")}
    finally:
        连接.close()


def 验删名重放() -> list:
    """真三方删名重放：腿侧删一名 + 新增一名 ⇒ 动作表含「删」「增」两类。

    重放后 `核验重放` 必须**绿**（原缺陷：删动作腿值 None 被 `行元组 is None` 误判「缺」而错拒）；
    再各造一个**未落库**反样本（删未执行 / 新增未落库）⇒ `核验重放` 必须**红**。
    """
    删样本表 = []
    with tempfile.TemporaryDirectory(prefix="v1删名重放-") as 临时目录:
        夹具 = _建删名夹具(Path(临时目录))
        集成路径 = 夹具["集成路径"]
        删动作表, 删冲突表, 删跳过表 = 重放.合并三方库(夹具["基库"], 夹具["腿库"], 夹具["主干库"], 集成路径)
        删名动作集 = [动作 for 动作 in 删动作表 if 动作["腿值"] is None]
        新增动作集 = [动作 for 动作 in 删动作表 if 动作["腿值"] is not None]
        删样本表.append(("删名重放 夹具（真三方）：动作 %d 条（删 %d · 增 %d）· 冲突 %d · 跳过 %d"
                 % (len(删动作表), len(删名动作集), len(新增动作集), len(删冲突表), len(删跳过表)),
                len(删名动作集) == 1 and len(新增动作集) == 1 and not 删冲突表))
        删重放码, _ = 重放.重放动作表(集成路径, 删动作表, 夹具["主干库"])
        现存命名集 = _读现存名(集成路径)
        删样本表.append(("删名重放 重放动作表：退出码 %d（期望 0）· 现存名 %s（期望只剩「保留命名」「新增命名」）"
                 % (删重放码, "·".join(sorted(现存命名集))),
                删重放码 == 0 and 现存命名集 == {"保留命名", "新增命名"}))
        删核码, 删核行表 = 集成接管.核验重放(集成路径, 删动作表)
        全行 = "\n".join(删核行表)
        删样本表.append(("核验重放 正向（腿侧删 + 新增均落库）：退出码 %d（期望 0）· 说「逐条落库」%s"
                 % (删核码, "是" if "逐条落库" in 全行 else "否"),
                删核码 == 0 and "逐条落库" in 全行))
        # 反样本一：腿侧删除**未执行**（删除命名 仍在）⇒ 必须红。
        with sqlite3.connect(str(集成路径 / 库相对路径)) as 连接:
            连接.execute("insert or replace into 命名登记 values ('删除命名','删除语义','对象+说明','新定义','合格',0,'')")
        反核码, 反核行表 = 集成接管.核验重放(集成路径, 删动作表)
        全行 = "\n".join(反核行表)
        删样本表.append(("核验重放 反向（腿侧删除未执行：删除命名 仍在）：退出码 %d（期望 1）· 说「删除未落库」%s"
                 % (反核码, "是" if "删除未落库" in 全行 else "否"),
                反核码 == 1 and "删除未落库" in 全行))
        # 反样本二：腿侧新增**未落库**（新增命名 被删）⇒ 必须红。
        with sqlite3.connect(str(集成路径 / 库相对路径)) as 连接:
            连接.execute("delete from 命名登记 where 名字='删除命名'")
            连接.execute("delete from 命名登记 where 名字='新增命名'")
        反核码, 反核行表 = 集成接管.核验重放(集成路径, 删动作表)
        全行 = "\n".join(反核行表)
        删样本表.append(("核验重放 反向（腿侧新增未落库：新增命名 缺失）：退出码 %d（期望 1）· 说「显式拒」%s"
                 % (反核码, "是" if "显式拒" in 全行 else "否"),
                反核码 == 1 and "显式拒" in 全行))
    return 删样本表
