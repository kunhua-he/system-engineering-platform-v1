def _写台账(树根, 台账行表):
    """把台账行写进库 `未完成` 表（库即存本：2026-10-13 起没有源件 JSON 了）。"""
    台账库件 = 树根 / 编排.库相对路径
    台账连接 = sqlite3.connect(str(台账库件))
    try:
        台账连接.execute("create table if not exists 未完成 "
                   "(号 integer primary key, 缺什么 text, 落点 text, 验证命令 text)")
        台账连接.execute("delete from 未完成")
        台账连接.executemany("insert or replace into 未完成(号, 缺什么, 落点, 验证命令) values (?,?,?,?)",
                      [tuple(数据行) for 数据行 in 台账行表])
        台账连接.commit()
    finally:
        台账连接.close()


def _读未完成行表(库件):
    """读库 `未完成` 四栏 ⇒ 行表（按 `号` 排序）。"""
    连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
    try:
        return sorted(tuple(数据行) for 数据行 in
                      连接.execute("select 号, 缺什么, 落点, 验证命令 from 未完成"))
    finally:
        连接.close()


