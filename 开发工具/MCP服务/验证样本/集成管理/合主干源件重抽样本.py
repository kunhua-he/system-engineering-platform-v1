def _跑源件重抽态(序号: int) -> dict:
    """进程池的工作体：一个态 ⇒ 带 `回显` / `异常` 的结果。

    **模块级函数**（池子按「模块名 + 函数名」反序列化，闭包 / lambda 不行）；回显在子进程里
    攒着带回父进程，由父进程**按原序**打印 ⇒ 打印顺序与串行版逐字相同。
    """
    import contextlib
    import io

    回显 = io.StringIO()
    try:
        with contextlib.redirect_stdout(回显):
            _验源件重抽态(源件重抽态表[序号])
        return {"序号": 序号, "回显": 回显.getvalue(), "异常": None}
    except BaseException as 错误:
        return {"序号": 序号, "回显": 回显.getvalue(), "异常": "%r" % (错误,)}


def 验源件重抽():
    """跑源件重抽七态（**并行**）；不过即断言炸 ⇒ 退出码 0（临时仓跑完删净）。"""
    结果表 = 并行执行(_跑源件重抽态, list(range(len(源件重抽态表))), 源件重抽档位)
    for 态果 in 结果表:
        if 态果["回显"]:
            print(态果["回显"], end="")
        if 态果["异常"] is not None:
            raise AssertionError("源件重抽「%s」不过：%s" % (源件重抽态表[态果["序号"]], 态果["异常"]))
    return 0
