r"""库快照样本 —— `v1_db` 快照差集的正反样本（临时 git 仓 + 临时 sqlite 库，跑完即删）。

**为何要它**（`v1_db` 此前零反向样本）：把快照差集的关键口径变成可复跑读数：

  · **中文多行正文按主键取整行** —— 取一行正文含换行的表，改它的正文 ⇒ 该行算 1 处变更
    （若把库 dump 成文本再拆行，多行正文会被拆成多条 ⇒ **变更计数虚高**）；
  · **0 差异**（同一 ref 对同一 ref）⇒ 全量 0/0/0 · 截断 否；
  · **展示 vs 全量**：`条数=1` 而差异 2 ⇒ 展示 +1 · **截断 是**，而全量统计不变；
  · **`目标=摘要`** ⇒ 只出每表 count，不出 `+ - ~` 行；
  · **`条数=0` 非法** ⇒ 退出码 2（参数错）；
  · **坏 ref** ⇒ 退出码非 0；
  · **缺失源库**（该 ref 下没有源库件）⇒ 退出码非 0；
  · **仓外路径冒充 ref**（`/etc/passwd`）与 **首字符 `-` 的选项注入形 ref** ⇒ 均拒（非 0）——
    这两条是旧 527 包 `_核引用` 形状守卫的承接口径：568 由 `_取提交` 的 rev-parse 验存在承担；
  · **源库只读**：跑前后源库 sha256 不变；
  · **唯一临时目录**：重入两次各开各的目录，绝不交叉覆盖；工具两次调用报的落点不同；
  · **含空格路径清理正确**：清理命令由 `shlex.quote` 引用，目录真被删；越界一律不删。

★ 自建临时仓 + 真运行数据根临时件，跑完即删 ⇒ **真仓一个字节都不改**。
"""
from pathlib import Path


def _写样本库(件路径, 行表) -> None:
    """写一棵最小 sqlite 源库（一张带主键、正文可含换行的表）。"""
    import sqlite3
    连接 = sqlite3.connect(str(件路径))
    try:
        连接.execute("create table if not exists 条款(序号 integer primary key, 正文 text)")
        连接.execute("delete from 条款")
        连接.executemany("insert into 条款 values(?, ?)", 行表)
        连接.commit()
    finally:
        连接.close()


def _建样本仓(临时根: Path) -> Path:
    """自建临时 git 仓（两次提交，第二版改一行的多行正文、再添两行）⇒ 仓根；样本只碰它。

    ★ 每条 git 都带 `env=干净环境()`：本样本会被 `--自检` 在**提交前钩子里**跑到，而 git 给钩子
    导出了 `GIT_DIR` / `GIT_INDEX_FILE` 一类定位变量 —— 不剔掉，临时仓的 `git add` / `git commit`
    会**落到外层工作树的暂存索引**（实测：外层索引被改写、整棵树显示成「暂存删除」、提交被拒）。
    """
    import subprocess
    from ...集成管理.合主干有界跑 import 干净环境
    环境表 = 干净环境()
    仓根 = 临时根 / "样本仓"
    库目录 = 仓根 / "开发工具" / "信息核心"
    库目录.mkdir(parents=True)
    库件 = 库目录 / "信息核心.db"
    身份 = ["-c", "user.name=样本", "-c", "user.email=样本@例"]
    多行正文 = "第一行\n第二行\n第三行"
    _写样本库(库件, [(1, "第一行\n第二行"), (2, "单行")])
    subprocess.run(["git", "init", "-q"], cwd=仓根, check=True, env=环境表)
    subprocess.run(["git"] + 身份 + ["add", "."], cwd=仓根, check=True, env=环境表)
    subprocess.run(["git"] + 身份 + ["commit", "-q", "-m", "首版"], cwd=仓根, check=True, env=环境表)
    _写样本库(库件, [(1, 多行正文), (2, "单行改"), (3, "新增条目"), (4, "另一条目")])
    subprocess.run(["git"] + 身份 + ["commit", "-q", "-a", "-m", "次版"], cwd=仓根, check=True, env=环境表)
    return 仓根


def _建无库仓(临时根: Path) -> Path:
    """自建临时 git 仓，**不放源库件**（验「该 ref 下没有源库」⇒ 退出码非 0）。"""
    import subprocess
    from ...集成管理.合主干有界跑 import 干净环境
    环境表 = 干净环境()
    仓根 = 临时根 / "无库仓"
    仓根.mkdir(parents=True)
    (仓根 / "占位.txt").write_text("占位\n", encoding="utf-8")
    身份 = ["-c", "user.name=样本", "-c", "user.email=样本@例"]
    subprocess.run(["git", "init", "-q"], cwd=仓根, check=True, env=环境表)
    subprocess.run(["git"] + 身份 + ["add", "."], cwd=仓根, check=True, env=环境表)
    subprocess.run(["git"] + 身份 + ["commit", "-q", "-m", "无库"], cwd=仓根, check=True, env=环境表)
    return 仓根


def _落点行(回执文本: str) -> str:
    """从回执（JSON 信封或纯文本）里取「快照落点」那一段（取不到 ⇒ 空串）。"""
    命中表 = [文本行 for 文本行 in 回执文本.replace("\\n", "\n").split("\n")
             if 文本行.startswith("快照落点")]
    return 命中表[0] if 命中表 else ""


def 库快照样本(仓根, 工具表) -> list:
    """⇒ 样本表（`(说明, 通过?)`）；自建临时仓 + 真运行数据根临时件，跑完即删，**真仓一个字节都不改**。"""
    import hashlib
    import shlex
    import shutil
    import tempfile

    from ...只读查询.库快照 import _取临时根, _开快照目录, _清快照目录

    def 跑快照(参数表):
        退出码, 输出文本 = 工具表["v1_db"][0]({"操作": "快照差集", "参数": 参数表}, 样本仓)
        return 退出码, 输出文本

    样本表 = []
    临时根 = Path(tempfile.mkdtemp(prefix="v1库快照样本-"))
    try:
        样本仓 = _建样本仓(临时根)
        源库 = 样本仓 / "开发工具" / "信息核心" / "信息核心.db"
        源库前 = hashlib.sha256(源库.read_bytes()).hexdigest()
        退出码, 输出文本 = 跑快照({"基准": "HEAD~1", "对照": "HEAD"})
        样本表.append(("中文多行正文按主键取整行（改一行多行正文算 1 处变更，不拆行）：退出码 %d · "
                 "全量 新增 2 · 删除 0 · 变更 2 · 截断 否（%s）"
                 % (退出码, "是" if "全量 新增 2 · 删除 0 · 变更 2 · 展示 +2/-0/~2 · 截断 否" in 输出文本 else "否"),
                 退出码 == 0 and "全量 新增 2 · 删除 0 · 变更 2 · 展示 +2/-0/~2 · 截断 否" in 输出文本))
        子码, 子文 = 跑快照({"基准": "HEAD~1"})
        样本表.append(("两侧来源：基准给来源提交 · 对照（盘上）如实标可变件（非提交）：退出码 %d" % 子码,
                 子码 == 0 and "来源提交 " in 子文
                 and "盘上工作树可变件（非提交，无 commit）" in 子文))
        退出码, 输出文本 = 跑快照({"基准": "HEAD~1", "对照": "HEAD", "条数": 1})
        样本表.append(("展示 vs 全量：条数=1 而差异 2 ⇒ 展示 +1 · 截断 是 · 全量仍 2（%s）"
                 % ("是" if "全量 新增 2 · 删除 0 · 变更 2 · 展示 +1/-0/~1 · 截断 是" in 输出文本 else "否"),
                 退出码 == 0 and "全量 新增 2 · 删除 0 · 变更 2 · 展示 +1/-0/~1 · 截断 是" in 输出文本))
        退出码, 输出文本 = 跑快照({"基准": "HEAD~1", "对照": "HEAD", "目标": "摘要"})
        样本表.append(("目标=摘要：只出每表 count，不出 `+ - ~` 行（%s）"
                 % ("是" if "全量 新增 2" in 输出文本 and "    + " not in 输出文本 else "否"),
                 退出码 == 0 and "全量 新增 2" in 输出文本 and "    + " not in 输出文本))
        退出码, 输出文本 = 跑快照({"基准": "HEAD", "对照": "HEAD"})
        样本表.append(("0 差异（同一 ref 对同一 ref）：退出码 %d · 全量 0/0/0 · 截断 否（%s）"
                 % (退出码, "是" if "全量 新增 0 · 删除 0 · 变更 0 · 展示 +0/-0/~0 · 截断 否" in 输出文本 else "否"),
                 退出码 == 0 and "全量 新增 0 · 删除 0 · 变更 0 · 展示 +0/-0/~0 · 截断 否" in 输出文本))
        退出码, 输出文本 = 跑快照({"基准": "HEAD~1", "对照": "HEAD", "条数": 0})
        样本表.append(("条数=0 非法 ⇒ 退出码 %d（期望 2 · 参数拒绝）" % 退出码, 退出码 == 2))
        退出码, 输出文本 = 跑快照({"基准": "没有这个ref"})
        样本表.append(("不存在的 ref ⇒ 退出码 %d（非 0）" % 退出码, 退出码 != 0))
        退出码, 输出文本 = 跑快照({"基准": "HEAD~1", "对照": "HEAD", "目标": "瞎目标"})
        样本表.append(("`目标` 非法 ⇒ 退出码 %d（期望 2）" % 退出码, 退出码 == 2))
        样本表.append(("源库只读（读前后 sha256 不变）：%s"
                 % ("是" if hashlib.sha256(源库.read_bytes()).hexdigest() == 源库前 else "否"),
                 hashlib.sha256(源库.read_bytes()).hexdigest() == 源库前))

        真临时根 = _取临时根()
        目录前 = _开快照目录(真临时根)
        目录后 = _开快照目录(真临时根)
        样本表.append(("唯一临时目录（重入不覆盖）：两次开的目录不同且在（%s ≠ %s）"
                 % (目录前.name, 目录后.name),
                 目录前 != 目录后 and 目录前.is_dir() and 目录后.is_dir()))
        _清快照目录(目录前, 真临时根)
        _清快照目录(目录后, 真临时根)
        前码, 前文 = 跑快照({"基准": "HEAD~1", "对照": "HEAD"})
        后码, 后文 = 跑快照({"基准": "HEAD~1", "对照": "HEAD"})
        落点前, 落点后 = _落点行(前文), _落点行(后文)
        样本表.append(("工具两次调用各报各的唯一落点（不复用固定名）：%s ≠ %s"
                 % (落点前 or "（缺）", 落点后 or "（缺）"),
                 前码 == 0 and 后码 == 0 and bool(落点前) and bool(落点后) and 落点前 != 落点后))
        空格目录 = Path(tempfile.mkdtemp(prefix="v1 空格 样本-", dir=str(真临时根)))
        清命令 = _清快照目录(空格目录, 真临时根)
        引用对 = bool(清命令) and shlex.quote(str(空格目录.resolve())) in 清命令
        样本表.append(("含空格路径清理正确：命令引用对 %s · 目录已删 %s（命令 %s）"
                 % ("是" if 引用对 else "否", "是" if not 空格目录.exists() else "否", 清命令 or "（空）"),
                 引用对 and not 空格目录.exists()))
        界外目录 = Path(tempfile.mkdtemp(prefix="v1越界样本-"))
        越界命令 = _清快照目录(界外目录, 真临时根)
        样本表.append(("越界拒删：临时件根之外的目录 ⇒ 空命令 %s · 目录仍在 %s"
                 % ("是" if not 越界命令 else "否", "是" if 界外目录.is_dir() else "否"),
                 越界命令 == "" and 界外目录.is_dir()))
        shutil.rmtree(界外目录, ignore_errors=True)
        无库仓 = _建无库仓(临时根)
        退出码, 输出文本 = 工具表["v1_db"][0](
            {"操作": "快照差集", "参数": {"基准": "HEAD", "对照": "盘上"}}, 无库仓)
        样本表.append(("缺失源库（该 ref 下没有 信息核心.db）⇒ 退出码 %d（非 0）" % 退出码,
                 退出码 != 0))
        # ★ 527 承接（2026-10-08）：527 独有 `_核引用` 形状守卫（拒首字符 `-` 的选项注入面、
        #   拒仓外路径冒充 ref）在 568 由 `_取提交` 的 rev-parse 承担 —— 补正反读它仍拒。
        退出码, 输出文本 = 跑快照({"基准": "/etc/passwd"})
        样本表.append(("非本库路径冒充 ref（/etc/passwd）⇒ 退出码 %d（非 0）" % 退出码,
                 退出码 != 0))
        退出码, 输出文本 = 跑快照({"基准": "--all"})
        样本表.append(("选项注入形 ref（首字符 `-`）⇒ 退出码 %d（非 0）" % 退出码,
                 退出码 != 0))
    finally:
        shutil.rmtree(临时根, ignore_errors=True)
    return 样本表
