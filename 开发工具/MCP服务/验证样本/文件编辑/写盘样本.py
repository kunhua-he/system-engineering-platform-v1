def 样本列表(仓根, 工具表) -> list:
    """写盘生命周期的正反样本 ⇒ 样本表（全在临时根里跑，跑完即删）。"""
    from 代码地图 import 文件指纹

    from ...文件编辑 import 批量改名, 修改, 写盘恢复, 写盘账本, 预检凭据
    from ... import 开工账本 as 账本

    临时根 = Path(tempfile.mkdtemp(prefix="v1写盘样本-"))
    工作树 = 临时根 / "工作树"
    (工作树 / "开发工具/信息核心").mkdir(parents=True)
    库件 = 工作树 / "开发工具/信息核心/信息核心.db"
    连接 = sqlite3.connect(str(库件))
    连接.execute("create table 命名登记(名字 text, 状态 text)")
    连接.execute("create table 命名例外(名字 text)")
    连接.executemany("insert into 命名登记 values (?,?)",
                [(标识符, "合格") for 标识符 in
                 ("配置文件", "旧样例名", "新样例名", "短引件", "样本件")])
    连接.commit()
    连接.close()
    账本库 = 账本.子目录路径(临时根 / "运行根", 账本.子目录类别) / 账本.库文件名
    账本库.parent.mkdir(parents=True)
    连接 = sqlite3.connect(str(账本库))
    for 建表行 in 账本.建表语句:
        连接.execute(建表行)
    连接.execute("insert into 开工 (开工号, 工作内容, 分支名, 工作树, 状态, 开工时间, 释放时间) "
               "values (?,?,?,?,?,?,?)",
               ("v1-样本", "样本", "样本", str(工作树), 账本.状态_进行中, "样本", None))
    连接.commit()
    连接.close()

    def 开账():
        """每个调用开**一条新连接**（`派发` 用完会 close ⇒ 不能给同一条）。"""
        新连接 = sqlite3.connect(str(账本库))
        新连接.row_factory = sqlite3.Row
        return 新连接

    def 立件(相对路径: str, 内容值: str) -> Path:
        """在工作树里立一个件 + 认领它（指纹现读）⇒ 件路径。"""
        件路径 = 工作树 / 相对路径
        件路径.parent.mkdir(parents=True, exist_ok=True)
        件路径.write_text(内容值, encoding="utf-8")
        连接 = 开账()
        连接.execute("insert or replace into 认领 values (?,?,?)",
                  ("v1-样本", 相对路径, 文件指纹(str(件路径))))
        连接.commit()
        连接.close()
        return 件路径

    def 认领刷新(相对路径: str) -> None:
        连接 = 开账()
        连接.execute("update 认领 set 指纹=? where 开工号=? and 路径=?",
                  (文件指纹(str(工作树 / 相对路径)), "v1-样本", 相对路径))
        连接.commit()
        连接.close()

    def 跑写盘(改动表: list, **额外) -> tuple:
        实参 = {"开工ID": "v1-样本", "改动表": 改动表}
        实参.update(额外)
        return 修改.派发(实参, 仓根)

    真连, 真索引, 真改名索引 = 账本.连账本, 修改.同步索引, 批量改名.同步索引
    账本.连账本 = 开账
    修改.同步索引 = lambda _根: (0, "样本空索引")
    批量改名.同步索引 = lambda _根: (0, "样本空索引")
    样本表 = []
    try:
        from .写盘边界样本 import 验写盘边界
        样本表 += 验写盘边界(立件, 跑写盘, 工作树, 开账)
        样本表 += _整批原子性与全替(立件, 跑写盘)
        样本表 += _定义面与字面禁项(立件, 跑写盘, 库件)
        样本表 += _命名闸批内全列(立件, 跑写盘)
        样本表 += _键形兼容()
        样本表 += _命名面跳行假阳(仓根)
        样本表 += _短引用与行数预警(立件, 认领刷新, 跑写盘, 临时根)
        样本表 += _整批重跑幂等(立件, 跑写盘)
        样本表 += _删除形幂等(立件, 跑写盘)
        样本表 += _旧内容不在盘不静默跳(立件, 跑写盘)
        样本表 += _越界归因三条真因(立件, 开账, 工作树, 写盘恢复, 写盘账本)
        样本表 += _批量改名并入同套(立件, 开账, 工作树, 批量改名, 写盘恢复, 写盘账本)
    finally:
        账本.连账本, 修改.同步索引, 批量改名.同步索引 = 真连, 真索引, 真改名索引
        import shutil
        shutil.rmtree(临时根, ignore_errors=True)
    return 样本表


def _整批原子性与全替(立件, 跑写盘) -> list:
    """整批原子性 + 全替。"""
    首件 = 立件("样本区/首件.py", "配置文件 = 1\n")
    次件 = 立件("样本区/次件.py", "配置文件 = 1\n")
    退出码, 说明 = 跑写盘([
        {"路径": "样本区/首件.py", "功能": 1, "旧内容": "配置文件 = 1", "新内容": "配置文件 = 2"},
        {"路径": "样本区/次件.py", "功能": 1, "旧内容": "没这一段", "新内容": "配置文件 = 3"}])
    首未动 = 首件.read_text(encoding="utf-8") == "配置文件 = 1\n"
    次未动 = 次件.read_text(encoding="utf-8") == "配置文件 = 1\n"
    输出表 = [("整批原子性：一批里有一条定位不过 ⇒ 退出码 3 · 回执说「整批预检」· 首条也没落盘",
             退出码 == 3 and "整批预检" in 说明 and 首未动 and 次未动)]
    形件 = 立件("样本区/同形件.py", "旧名 = 1\n旧名 = 2\n")
    退出码, 说明 = 跑写盘([{"路径": "样本区/同形件.py", "功能": 1,
                      "旧内容": "旧名", "新内容": "新名"}])
    不给全替拒 = 退出码 == 3 and 形件.read_text(encoding="utf-8") == "旧名 = 1\n旧名 = 2\n"
    退出码, 说明 = 跑写盘([{"路径": "样本区/同形件.py", "功能": 1, "旧内容": "旧名",
                      "新内容": "新名", "全替": True}])
    给全替过 = 退出码 == 0 and 形件.read_text(encoding="utf-8") == "新名 = 1\n新名 = 2\n"
    输出表.append(("全替：同一片段多次出现时不给 `全替` ⇒ 拒（盘未动）；给 `全替` = 真 ⇒ 全部换掉",
              不给全替拒 and 给全替过))
    形件 = 立件("样本区/整件删除.py", "第一行\n第二行\n")
    错误全文拒 = 跑写盘([{"路径": "样本区/整件删除.py", "功能": 2,
                      "旧内容": "不是盘上全文"}])
    错误全文未删 = (错误全文拒[0] != 0
                and 形件.read_text(encoding="utf-8") == "第一行\n第二行\n"
                and "逐字等于盘上全文" in 错误全文拒[1])
    退出码, 说明 = 跑写盘([{"路径": "样本区/整件删除.py", "功能": 2,
                      "旧内容": "第一行\n第二行\n"}])
    正确全文删除 = 退出码 == 0 and not 形件.exists()
    输出表.append(("整件删除：错误全文拒绝且原件不动；逐字全文才允许删除",
              错误全文未删 and 正确全文删除))
    return 输出表


