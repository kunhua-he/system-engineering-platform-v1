def _命名面跳行假阳(仓根) -> list:
    """命名面跳行假阳回归（`return "", ""` + 下一行元组解包）。"""
    import sys as _sys
    工具根 = Path(__file__).resolve().parents[4]
    if str(工具根 / "构建装配" / "一键验证") not in _sys.path:
        _sys.path.insert(0, str(工具根 / "构建装配" / "一键验证"))
    from 一键验证.源码解析 import 命名扫描 as 命名面

    假件 = "def 读对(件):\n    return \"\", \"\"\n    x, y = 1, 2\n"
