# -*- coding: utf-8 -*-
"""写盘样本 —— 写盘生命周期那一批面的**永久正反样本**（判据 ㊽ 经 `自检样本.跑自检` 跑它）。

**为何单开一件**（判据 ⑲ 单源文件 ≤400 行）：`预检样本.py` 已顶硬数；照先例
（`裸仓回执样本.py`）把新面单开。

**夹具**：临时工作树 + 临时规则库 + 临时账本；`开工账本.连账本` 与两个 `同步索引` 换替身
（同 `预检样本` 的法子）。**一个字节都不写仓**：全在临时根里跑，跑完即删。

一片一测（每条都是**可证伪**的读数，不是「跑过就算」）：
  · 整批原子性 —— 一批里有一条定位不过 ⇒ 整批拒、**首条也没落盘**（0 写盘）。
  · 全替 —— 同一片段多处出现：不给 `全替` ⇒ 拒；给 `全替` = 真 ⇒ 全部换掉。
  · 定义面闸 —— 新写模块级函数名未登记 ⇒ 5 且回执带**可粘贴登记载荷**；登记过 ⇒ 放行。
  · 命名闸批内全列 —— 两件各有未登记名 ⇒ **一轮全列** + 两份载荷；空 `新内容` 当场拒。
  · 键形兼容 —— 新形 `操作` / 旧形 `功能` 都收；两不像 ⇒ 报迁移提示。
  · 命名面跳行假阳 —— `return "", ""` 紧跟下一行元组解包 ⇒ 不再抓出 `return`（回归）。
  · 写前字面禁项 —— 新内容带十干字 ⇒ 3 且指名、盘未动；干净内容 ⇒ 放行。
  · 短引用 —— `只检查` 过的表可 `沿用上次`；失效 / 对不上 ⇒ 明确拒。
  · 行数预警 —— `改` 档也报行数（超顶 + 距上限只剩几行两档）。
  · 整批重跑幂等 —— 插入形那批再跑一次 ⇒ 全判「已存在跳过」、不重复插入。
  · 删除形幂等 —— `新内容` ⊂ `旧内容`：旧内容在必须真删、重跑跳过、同件两条都落（612/616 回归）。
  · 替换形不静默跳 —— 旧内容不在盘（手抄差异 / 写错）⇒ 如实拒，不得判「已存在跳过」假成功。
  · 批量改名并入同套 —— 崩溃窗口 ⇒ 意图仍在；新连接恢复收敛；重跑幂等；外部漂移拒；
    单件失败不回滚（先改的件留在盘上）。
"""

import sqlite3
import tempfile
from pathlib import Path


# 十干字用转义写（判据 ㊵ 逐字节扫全树 —— 源码里一个字面十干字都不许有）。
