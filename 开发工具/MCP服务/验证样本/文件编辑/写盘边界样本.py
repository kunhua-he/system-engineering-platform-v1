"""同源快照、链接路径与全替插入形的永久反证。"""
from unittest.mock import patch


def 验写盘边界(立件, 跑写盘, 工作树, 开账):
    from ...文件编辑 import 修改
    from ...施工管理.仓操作 import 读盘指纹
    输出表 = []
    件路径 = 立件("样本区/快照样本.py", "配置文件 = 1\n")
    def 注入外改(最终态表):
        件路径.write_text("配置文件 = 9\n", encoding="utf-8")
        return []
    with patch.object(修改, "查最终态语法", 注入外改):
        退出码, 说明 = 跑写盘([{"路径":"样本区/快照样本.py", "功能":1,
                              "旧内容":"配置文件 = 1", "新内容":"配置文件 = 2"}])
    连接 = 开账()
    try:
        改动数 = 连接.execute("select count(*) from 改动 where 路径=?", ("样本区/快照样本.py",)).fetchone()[0]
    finally:
        连接.close()
    输出表.append(("推演后外改拒写且不洗账", 退出码 != 0 and 件路径.read_text() == "配置文件 = 9\n" and 改动数 == 0))
    立件("样本区/全替样本.py", "# 旧片 旧片新片\n")
    退出码, 说明 = 跑写盘([{"路径":"样本区/全替样本.py", "功能":1,
                          "旧内容":"旧片", "新内容":"旧片新片", "全替":True}])
    输出表.append(("全替插入形必须应用剩余旧串", 退出码 == 0 and (工作树/"样本区/全替样本.py").read_text() == "# 旧片新片 旧片新片新片\n"))
    (工作树/"链接样本").symlink_to(工作树/"样本区", target_is_directory=True)
    退出码, 说明 = 跑写盘([{"路径":"链接样本/链接新建.py", "功能":0, "新内容":"配置文件 = 1\n"}])
    指纹表, 拒收表 = 读盘指纹(工作树, ["链接样本/快照样本.py"])
    输出表.append(("目录链接在新建与认领两侧均拒绝", 退出码 != 0 and not (工作树/"样本区/链接新建.py").exists() and not 指纹表 and bool(拒收表)))
    输出表 += 验换行与崩溃(立件, 跑写盘, 工作树, 开账)
    return 输出表

def 验换行与崩溃(立件, 跑写盘, 工作树, 开账):
    """真子进程在原子替换前后退出；新连接据意图恢复，临时件只清所属目标。"""
    import os
    import time
    from ...文件编辑 import 写盘执行, 写盘恢复, 写盘账本
    输出表 = []
    原全文 = "配置文件 = 1\r\n# 中文\r\n"
    候选全文 = "配置文件 = 2\r\n# 中文\r\n"
    件路径 = 立件("样本区/换行样本.py", 原全文)
    退出码, 说明 = 跑写盘([{"路径":"样本区/换行样本.py", "功能":1,
                          "旧内容":原全文, "新内容":候选全文}])
    输出表.append(("CRLF多行锚点与输出字节保真", 退出码 == 0 and 件路径.read_bytes() == 候选全文.encode()))
    退出码, 说明 = 跑写盘([{"路径":"样本区/换行样本.py", "功能":1,
                          "旧内容":"配置文件 = 2\n# 中文\n", "新内容":"配置文件 = 3\n"}])
    输出表.append(("LF锚点不可冒认CRLF全文", 退出码 != 0 and 件路径.read_bytes() == 候选全文.encode()))
    for 路径, 原全文, 候选全文 in (("无尾样本.py", "# 中文", "# 修改"), ("空件样本.py", "", "")):
        件路径 = 工作树 / 路径
        件路径.write_bytes(原全文.encode())
        错误 = 写盘执行.写文件(件路径, 候选全文, 工作树=工作树)
        输出表.append((路径 + "原样写入", not 错误 and 件路径.read_bytes() == 候选全文.encode()))
    件路径 = 工作树 / "清理目标.py"
    件路径.write_text("# 保留\n")
    临时件 = 工作树 / "清理目标.py.abcdefgh.v1edit-tmp"
    新件 = 工作树 / "清理目标.py.12345678.v1edit-tmp"
    非本件 = 工作树 / "其他目标.py.abcdefgh.v1edit-tmp"
    错名件 = 工作树 / "清理目标.py.abc.v1edit-tmp"
    链接件 = 工作树 / "清理目标.py.linkname.v1edit-tmp"
    链接件.symlink_to(件路径)
    for 目标路径 in (临时件, 新件, 非本件, 错名件):
        目标路径.write_bytes(b"keep")
    for 目标路径 in (临时件, 非本件, 错名件):
        os.utime(目标路径, (time.time() - 90000, time.time() - 90000))
    清理表 = 写盘执行.清理陈旧写盘临时件(工作树, ["清理目标.py"])
    输出表.append(("清理限定目标与唯一名且保新件和链接", 清理表 == [临时件.name] and 新件.exists()
                  and 非本件.exists() and 错名件.exists() and 链接件.is_symlink() and 件路径.read_text() == "# 保留\n"))
    for 目标路径 in (新件, 非本件, 错名件, 链接件):
        目标路径.unlink()
    for 退出点 in ("替换前", "替换后"):
        相对路径 = "样本区/崩溃" + 退出点 + ".py"
        件路径 = 立件(相对路径, "配置文件 = 1\n")
        写前指纹 = 写盘执行.内容指纹("配置文件 = 1\n")
        写后指纹 = 写盘执行.内容指纹("配置文件 = 2\n")
        连接 = 开账()
        写盘账本.记写盘意图(连接, "v1-样本", 相对路径, "修改", 写前指纹, 写后指纹)
        连接.close()
        子进程号 = os.fork()
        if 子进程号 == 0:
            原替换 = 写盘执行.os.replace
            def 崩溃替换(来源, 目标):
                if 退出点 == "替换后":
                    原替换(来源, 目标)
                os._exit(73)
            写盘执行.os.replace = 崩溃替换
            写盘执行.写文件(件路径, "配置文件 = 2\n", 写前指纹, 工作树)
            os._exit(74)
        _, 等待状态 = os.waitpid(子进程号, 0)
        连接 = 开账()
        try:
            恢复结果 = 写盘恢复.恢复一次(连接, 工作树, "v1-样本")
            未决表 = 写盘账本.列写盘意图(连接, "v1-样本")
            改动数 = 连接.execute("select count(*) from 改动 where 路径=?", (相对路径,)).fetchone()[0]
        finally:
            连接.close()
        期望字节 = ("配置文件 = 1\n" if 退出点 == "替换前" else "配置文件 = 2\n").encode()
        输出表.append((退出点 + "真实退出后盘账恢复", os.waitstatus_to_exitcode(等待状态) == 73
                      and 恢复结果[0] == 0 and not 未决表 and 件路径.read_bytes() == 期望字节
                      and 改动数 == (0 if 退出点 == "替换前" else 1)))
        for 临时件 in 件路径.parent.glob(件路径.name + ".*.v1edit-tmp"):
            os.utime(临时件, (time.time() - 90000, time.time() - 90000))
        写盘执行.清理陈旧写盘临时件(工作树, [相对路径])
        输出表.append((退出点 + "残留暂存可收敛", not list(件路径.parent.glob(件路径.name + ".*.v1edit-tmp"))))
    return 输出表

