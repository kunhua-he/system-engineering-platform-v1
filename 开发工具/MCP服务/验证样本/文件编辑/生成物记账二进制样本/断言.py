def 判声明档(夹具根: Path) -> list:
    """声明能不能读回 · 认不认生成器名 · 模板算不算规则（纯函数）。"""
    样本仓根 = 夹具.造隔离仓(夹具根 / "声明", 夹具.声明表(夹具.样本生成器名))
    声明 = 读生成物声明(样本仓根, 夹具.样本生成器名)
    return [
        ("① 声明能读回（合法二进制有档可走）", 声明.get("生成器") == 夹具.样本生成器名, str(声明)),
        ("② 生成器名不符 ⇒ 声明作废", 读生成物声明(样本仓根, "别的.py") == {}, ""),
        ("③ 模板是规则：新增模块不必改声明",
         声明命中(声明, "扩展根目录/组合模块库/新模块/新模块.模块制品"), ""),
        ("④ 模板不是后缀白名单：同名绑不上 ⇒ 未声明",
         not 声明命中(声明, "扩展根目录/组合模块库/子/卯.模块制品"), ""),
        ("⑤ 段数不符 ⇒ 未声明",
         not 声明命中(声明, "扩展根目录/组合模块库/子/子/子.模块制品"), ""),
    ]


def 判核验档(夹具根: Path) -> list:
    """判二进制产物的六问：逐件核验（不跑生成器、不碰账本）。"""
    样本仓根 = 夹具.造隔离仓(夹具根 / "核验", 夹具.声明表(夹具.样本生成器名))
    声明 = 读生成物声明(样本仓根, 夹具.样本生成器名)
    样本件 = 夹具.样本制品相对
    认领表 = {样本件: "夹具指纹"}
    结果表 = [("⑥ 合法二进制核过（在边界 + 已认领 + 真容器）",
            判二进制产物(样本仓根, 声明, [样本件], 认领表) == [],
            str(判二进制产物(样本仓根, 声明, [样本件], 认领表)))]
    越界件 = "扩展根目录/原子支持库/丑/丑.模块制品"
    夹具.写二进制(样本仓根 / 越界件, b"\x00\x01\x02")
    越界声明 = 夹具.声明表(夹具.样本生成器名, 模板表=[], 输出表=[越界件])
    拒表 = 判二进制产物(样本仓根, 越界声明, [越界件], {越界件: "夹具指纹"})
    结果表.append(("⑦ 越根 ⇒ 拒（拒由点名越界）", any("越出" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    无声明件 = "扩展根目录/组合模块库/子/卯.模块制品"
    夹具.写二进制(样本仓根 / 无声明件, b"\x00\x02")
    拒表 = 判二进制产物(样本仓根, 声明, [无声明件], {无声明件: "夹具指纹"})
    结果表.append(("⑧ 未声明 ⇒ 拒", any("不在生成器声明" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    拒表 = 判二进制产物(样本仓根, 声明, [样本件], {越界件: "夹具指纹"})
    结果表.append(("⑨ 越认领 ⇒ 拒", any("认领" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    文本后缀件 = 夹具.样本文本相对
    后缀声明 = 夹具.声明表(夹具.样本生成器名, 模板表=[], 输出表=[文本后缀件])
    拒表 = 判二进制产物(样本仓根, 后缀声明, [文本后缀件], {文本后缀件: "夹具指纹"})
    结果表.append(("⑩ 源码后缀伪装 ⇒ 拒", any("源码" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    伪二进制件 = "扩展根目录/组合模块库/伪/伪.模块制品"
    (样本仓根 / 伪二进制件).parent.mkdir(parents=True, exist_ok=True)
    (样本仓根 / 伪二进制件).write_text("这是文本不是容器\n", encoding="utf-8")
    拒表 = 判二进制产物(样本仓根, 声明, [伪二进制件], {伪二进制件: "夹具指纹"})
    结果表.append(("⑪ utf-8 文本冒二进制 ⇒ 拒", any("utf-8" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    空件 = "扩展根目录/组合模块库/空/空.模块制品"
    夹具.写二进制(样本仓根 / 空件, b"")
    拒表 = 判二进制产物(样本仓根, 声明, [空件], {空件: "夹具指纹"})
    结果表.append(("⑫ 空件 ⇒ 拒", any("空件" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    硬链接件 = "扩展根目录/组合模块库/硬/硬.模块制品"
    (样本仓根 / 硬链接件).parent.mkdir(parents=True, exist_ok=True)
    (样本仓根 / 硬链接件).hardlink_to(样本仓根 / 样本件)
    拒表 = 判二进制产物(样本仓根, 声明, [硬链接件], {硬链接件: "夹具指纹"})
    结果表.append(("⑬ 硬链伪装 ⇒ 拒", any("硬链接" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    符号链接件 = "扩展根目录/组合模块库/链/链.模块制品"
    (样本仓根 / 符号链接件).parent.mkdir(parents=True, exist_ok=True)
    (样本仓根 / 符号链接件).symlink_to(样本仓根 / 样本件)
    拒表 = 判二进制产物(样本仓根, 声明, [符号链接件], {符号链接件: "夹具指纹"})
    结果表.append(("⑭ 符号链接 ⇒ 拒", any("符号链接" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    拒表 = 判二进制产物(样本仓根, 声明, [样本件], {})
    结果表.append(("㉓ 空认领表 ⇒ 拒（零认领的腿不许借生成器洗白）",
                any("认领" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    链接根 = 夹具根 / "核验-仓外链接"
    样本仓根 = 夹具.造隔离仓(链接根, 夹具.声明表(夹具.样本生成器名))
    夹具.造目录链接(样本仓根, 链接根 / "仓外")
    拒表 = 判二进制产物(样本仓根, 读生成物声明(样本仓根, 夹具.样本生成器名),
                    [样本件], {样本件: "夹具指纹"})
    结果表.append(("㉔ 目录链接穿出仓外 ⇒ 拒（归一后越出工作树）",
                any("越出工作树" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    链接根 = 夹具根 / "核验-边界链接"
    样本仓根 = 夹具.造隔离仓(链接根, 夹具.声明表(夹具.样本生成器名))
    链接件 = "扩展根目录/组合模块库/链内/丑/丑.模块制品"
    (样本仓根 / "扩展根目录/原子支持库/丑").mkdir(parents=True)
    夹具.写二进制(样本仓根 / "扩展根目录/原子支持库/丑/丑.模块制品", b"\x00\x01")
    (样本仓根 / "扩展根目录/组合模块库/链内").symlink_to(
        样本仓根 / "扩展根目录/原子支持库", target_is_directory=True)
    拒表 = 判二进制产物(样本仓根, 夹具.声明表(夹具.样本生成器名, 模板表=[], 输出表=[链接件]),
                    [链接件], {链接件: "夹具指纹"})
    结果表.append(("㉕ 目录链接指向仓内边界外 ⇒ 拒（归一后越出声明边界）",
                any("越出声明边界" in 拒由 for _, 拒由 in 拒表), str(拒表)))
    return 结果表


def 判记账档(夹具根: Path) -> list:
    """真跑 `记生成物账`：隔离账本 + 真 git 仓 + 真生成器（端到端，不是纯函数）。"""
    结果表 = []
    夹具根 = 夹具根 / "记账-合法"
    样本仓根 = 夹具.造隔离仓(夹具根, 夹具.声明表(夹具.样本生成器名))
    夹具.造隔离账本(夹具根, 样本仓根)
    记账退出码, 记账说明 = 记生成物账(样本仓根, 夹具.样本开工号, 夹具.样本生成器名, [])
    改动表 = 夹具.读账本改动(夹具根)
    真指纹 = hashlib.sha256((样本仓根 / 夹具.样本制品相对).read_bytes()).hexdigest()[:16]
    结果表.append(("⑮ 端到端：合法二进制真变化 ⇒ 记入账本（写后指纹 = 盘上真指纹）",
                记账退出码 == 0 and len(改动表) == 1
                and 改动表[0]["路径"] == 夹具.样本制品相对
                and 改动表[0]["写后指纹"] == 真指纹,
                "退出码 %d · 记账 %d 件 · %s"
                % (记账退出码, len(改动表), (记账说明 or "").splitlines()[0:1])))
    变更码, 脏路径集 = 变更路径表(样本仓根)
    改动路径集 = {改动行["路径"] for 改动行 in 改动表}
    结果表.append(("⑯ 释放可识别：脏件都在改动表里（越界检测不会拒）",
                变更码 == 0 and bool(脏路径集) and set(脏路径集) <= 改动路径集,
                "脏 %s · 改动 %s" % (sorted(脏路径集 or []), sorted(改动路径集))))
    基准数 = len(改动表)
    记账退出码, 记账说明 = 记生成物账(样本仓根, 夹具.样本开工号, 夹具.样本生成器名, [])
    记录数 = len(夹具.读账本改动(夹具根))
    结果表.append(("⑰ 生成器没写出变化 ⇒ 记 0 件（账本零新增）",
                记账退出码 == 0 and 记录数 == 基准数,
                "退出码 %d · 改动 %d → %d" % (记账退出码, 基准数, 记录数)))
    夹具根 = 夹具根 / ".." / "记账-未声明"
    未声明件 = "扩展根目录/组合模块库/子/卯.模块制品"
    样本仓根 = 夹具.造隔离仓(夹具根, 夹具.声明表(夹具.样本生成器名), 未声明件)
    夹具.造隔离账本(夹具根, 样本仓根,
                {未声明件: "夹具指纹", 夹具.样本文本相对: "夹具指纹"})
    记账退出码, 记账说明 = 记生成物账(样本仓根, 夹具.样本开工号, 夹具.样本生成器名, [])
    记录数 = len(夹具.读账本改动(夹具根))
    结果表.append(("⑱ 未声明 ⇒ 拒且账本零写", 记账退出码 != 0 and 记录数 == 0,
                "退出码 %d · 改动 %d 件" % (记账退出码, 记录数)))
    夹具根 = 夹具根 / ".." / "记账-越认领"
    样本仓根 = 夹具.造隔离仓(夹具根, 夹具.声明表(夹具.样本生成器名))
    夹具.造隔离账本(夹具根, 样本仓根, {夹具.样本文本相对: "夹具指纹"})
    记账退出码, 记账说明 = 记生成物账(样本仓根, 夹具.样本开工号, 夹具.样本生成器名, [])
    记录数 = len(夹具.读账本改动(夹具根))
    结果表.append(("⑲ 越认领 ⇒ 拒且账本零写", 记账退出码 != 0 and 记录数 == 0,
                "退出码 %d · 改动 %d 件" % (记账退出码, 记录数)))
    夹具根 = 夹具根 / ".." / "记账-越根"
    越界件 = "扩展根目录/原子支持库/丑/丑.模块制品"
    样本仓根 = 夹具.造隔离仓(夹具根, 夹具.声明表(夹具.样本生成器名, 模板表=[], 输出表=[越界件]),
                        越界件)
    夹具.造隔离账本(夹具根, 样本仓根, {越界件: "夹具指纹"})
    记账退出码, 记账说明 = 记生成物账(样本仓根, 夹具.样本开工号, 夹具.样本生成器名, [])
    记录数 = len(夹具.读账本改动(夹具根))
    结果表.append(("⑳ 越根 ⇒ 拒且账本零写", 记账退出码 != 0 and 记录数 == 0,
                "退出码 %d · 改动 %d 件" % (记账退出码, 记录数)))
    夹具根 = 夹具根 / ".." / "记账-失败"
    样本仓根 = 夹具.造隔离仓(夹具根, 夹具.声明表(夹具.样本生成器名), 夹具.样本制品相对, 3)
    夹具.造隔离账本(夹具根, 样本仓根)
    记账退出码, 记账说明 = 记生成物账(样本仓根, 夹具.样本开工号, 夹具.样本生成器名, [])
    记录数 = len(夹具.读账本改动(夹具根))
    结果表.append(("㉑ 生成器退出码非 0 ⇒ 一件不记（账本零写）", 记账退出码 != 0 and 记录数 == 0,
                "退出码 %d · 改动 %d 件" % (记账退出码, 记录数)))
    夹具根 = 夹具根 / ".." / "记账-文本"
    样本仓根 = 夹具.造隔离仓(夹具根, 夹具.声明表(夹具.样本生成器名))
    夹具.造隔离账本(夹具根, 样本仓根)
    记账退出码, 记账说明 = 记生成物账(样本仓根, 夹具.样本开工号, 夹具.样本文本生成器名, [])
    改动表 = 夹具.读账本改动(夹具根)
    结果表.append(("㉒ 文本产物走原路（头标自述照旧记入）",
                记账退出码 == 0 and len(改动表) == 1
                and 改动表[0]["路径"] == 夹具.样本文本相对,
                "退出码 %d · 记账 %d 件" % (记账退出码, len(改动表))))
    夹具根 = 夹具根 / ".." / "记账-零认领"
    样本仓根 = 夹具.造隔离仓(夹具根, 夹具.声明表(夹具.样本生成器名))
    夹具.造隔离账本(夹具根, 样本仓根, {})
    记账退出码, 记账说明 = 记生成物账(样本仓根, 夹具.样本开工号, 夹具.样本生成器名, [])
    记录数 = len(夹具.读账本改动(夹具根))
    结果表.append(("㉖ 零认领 ⇒ 拒且账本零写（端到端）", 记账退出码 != 0 and 记录数 == 0,
                "退出码 %d · 改动 %d 件" % (记账退出码, 记录数)))
    夹具根 = 夹具根 / ".." / "记账-目录链接"
    样本仓根 = 夹具.造隔离仓(夹具根, 夹具.声明表(夹具.样本生成器名))
    夹具.造目录链接(样本仓根, 夹具根 / "仓外")
    夹具.造隔离账本(夹具根, 样本仓根)
    记账退出码, 记账说明 = 记生成物账(样本仓根, 夹具.样本开工号, 夹具.样本生成器名, [])
    记录数 = len(夹具.读账本改动(夹具根))
    仓外真写 = (夹具根 / "仓外" / Path(夹具.样本制品相对).name).read_bytes() == 夹具.新字节
    结果表.append(("㉗ 目录链接穿出仓外 ⇒ 拒且账本零写（仓外副作用真发生、记账拒绝）",
                记账退出码 != 0 and 记录数 == 0 and 仓外真写,
                "退出码 %d · 改动 %d 件 · 仓外真写=%s" % (记账退出码, 记录数, 仓外真写)))
    return 结果表
