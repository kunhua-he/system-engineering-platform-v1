"""生成器真实删除的正反样本：干净产物、认领、自述归属及非产物写面。"""
import os
import json
from . import 夹具
from MCP服务.文件编辑.生成物记账 import 记生成物账


def 判回收档(夹具根):
    断言表 = []
    旧环境 = os.environ.get(夹具.运行数据根环境变量)
    样本表 = [('干净自有产物真实删除', 1, 1, 1), ('未认领产物拒记账', 0, 1, 0),
           ('他人生成器产物拒记账', 1, 0, 0), ('普通源码删除拒记账', 1, 2, 0)]
    try:
        for 样本名, 需认领, 自述档, 期望通过 in 样本表:
            本根 = 夹具根 / 样本名
            本根.mkdir(parents=True)
            仓根 = 夹具.造隔离仓(本根, 夹具.声明表(夹具.样本生成器名))
            源件 = 仓根 / 夹具.样本文本相对
            头标 = ('# 生成物\n禁手改\n生成器：%s\n' % (夹具.样本文本生成器名 if 自述档 == 1 else '其它生成器.py')) if 自述档 != 2 else '源码正文\n'
            源件.write_text(头标)
            (仓根 / 夹具.样本文本生成器名).write_text('from pathlib import Path\nPath(%r).unlink()\n' % 夹具.样本文本相对)
            提交码, 提交输出 = 夹具.跑git(仓根, ['add', '-A'])
            assert 提交码 == 0, 提交输出
            提交码, 提交输出 = 夹具.跑git(仓根, ['commit', '-qm', '回收前干净基线'])
            assert 提交码 == 0, 提交输出
            开工号 = 夹具.造隔离账本(本根, 仓根, {夹具.样本文本相对: '夹具基线'} if 需认领 else {})
            退出码, 回执 = 记生成物账(仓根, 开工号, 夹具.样本文本生成器名, [])
            改动表 = 夹具.读账本改动(本根)
            已过 = ((退出码 == 0) == bool(期望通过) and not 源件.exists()
                  and len(改动表) == 期望通过 and (not 期望通过 or 改动表[0]['路径'] == 夹具.样本文本相对))
            断言表.append((样本名, 已过, 回执))
    finally:
        if 旧环境 is None:
            os.environ.pop(夹具.运行数据根环境变量, None)
        else:
            os.environ[夹具.运行数据根环境变量] = 旧环境
    断言表.extend(判二进制回收档(夹具根))
    return 断言表


