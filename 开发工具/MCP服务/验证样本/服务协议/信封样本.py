# -*- coding: utf-8 -*-
"""信封样本 —— 统一信封**状态面**的正反样本：`v1_gate` 全量转后台作业的四种态 + 预留槽指向。

一片一测（前四态全走替身，后三条是便宜只读调用；不动仓、不起重进程）：
  · 同步完成 —— 同步窗口内到终态且闸绿 ⇒ 退出码 0。
  · 后台未完成后成功 —— 窗口内未到终态 ⇒ 退出码 = `服务常量.待取作业码`、`错误.种类` = 待取作业、
    回执带任务ID（**不是** `-1`「业务失败」—— 那会把「还要去取」误判成闸红）。
  · 后台实际失败 —— 窗口内到终态且闸红 ⇒ 退出码 1、`错误.种类` = 业务失败。
  · 直跑真实超时 —— 直跑超硬顶 ⇒ 退出码 `-1`、`错误.种类` = 业务失败（与「待取作业」分开）。
  · 合法操作 / 保留号表 —— 预留槽调用 ⇒ 未实现且说明指向已实现工具；号表条目仍在、未被删。
"""


def 样本列表(仓根, 工具表) -> list:
    """信封状态面正反样本 ⇒ 样本表 `[(说明, 通过)]`。"""
    import json
    import subprocess
    from unittest import mock

    from ...验证管理 import 门禁
    from ...服务协议 import 参数规范, 操作编号
    from ... import 作业
    from ...服务协议.服务常量 import 待取作业码

    样本表 = []

    def 代跑全量(状态, 退出码, 任务ID):
        """替身跑一次「全量转后台作业」⇒ `(退出码, 说明文本)`（不起真作业、不读真日志）。"""
        with mock.patch.object(门禁, "有界等作业", return_value={"状态": 状态, "退出码": 退出码}), \
             mock.patch.object(作业, "起具名作业", return_value=(0, "任务ID：%s" % 任务ID)), \
             mock.patch.object(作业, "读日志片段", return_value=(1, "样本：无日志")):
            return 门禁.全量转作业(仓根, "", 仓根, "样本树", None, set())

    # ── ① 同步完成：窗口内到终态且闸绿 ⇒ 0 ──
    退出码, 输出文本 = 代跑全量("已完成", 0, "1" * 32)
    样本表.append(("信封·同步完成：窗口内到终态且闸绿 ⇒ 退出码 %d（期望 0）· 错误.种类 %r（期望 空）"
             % (退出码, 参数规范.错误种类(退出码)),
             退出码 == 0 and 参数规范.错误种类(退出码) == ""))

    # ── ② 后台未完成后成功：未到终态 ⇒ 待取作业码（不是 -1）且带任务ID ──
    退出码, 输出文本 = 代跑全量("运行中", None, "2" * 32)
    样本表.append(("信封·后台未完成后成功：未到终态 ⇒ 退出码 %d（期望 待取作业码 %d）· 错误.种类 %r"
             "（期望 待取作业）· 回执带任务ID %s · 不是 -1 %s"
             % (退出码, 待取作业码, 参数规范.错误种类(退出码),
                "是" if "2" * 32 in 输出文本 else "否", "是" if 退出码 != -1 else "否"),
             退出码 == 待取作业码 and 退出码 != -1 and 参数规范.错误种类(退出码) == "待取作业"
             and "2" * 32 in 输出文本))

    # ── ③ 后台实际失败：到终态且闸红 ⇒ 1 ──
    退出码, 输出文本 = 代跑全量("失败", 1, "3" * 32)
    样本表.append(("信封·后台实际失败：到终态且闸红 ⇒ 退出码 %d（期望 1）· 错误.种类 %r（期望 业务失败）"
             % (退出码, 参数规范.错误种类(退出码)),
             退出码 == 1 and 参数规范.错误种类(退出码) == "业务失败"))

    # ── ④ 直跑真实超时：超硬顶 ⇒ -1（与待取作业码分开）──
    with mock.patch.object(门禁.subprocess, "run",
                           side_effect=subprocess.TimeoutExpired("样本：闸0", 10)):
        退出码, 输出文本 = 门禁.派发({"直跑": True}, 仓根)
    样本表.append(("信封·直跑真实超时：超硬顶 ⇒ 退出码 %d（期望 -1）· 错误.种类 %r（期望 业务失败）"
             "· 与待取作业码不同 %s"
             % (退出码, 参数规范.错误种类(退出码), "是" if 退出码 != 待取作业码 else "否"),
             退出码 == -1 and 参数规范.错误种类(退出码) == "业务失败" and 退出码 != 待取作业码))

    # ── ④b 待取作业**过网关**：信封 `错误.种类` = 待取作业、`成功` = 假（不是「业务失败」）──
    with mock.patch.object(门禁, "全量转作业",
                           return_value=(待取作业码, "任务ID：%s" % ("4" * 32))):
        退出码, 输出文本 = 工具表["v1_gate"][0]({"操作": "全量"}, 仓根)
    读数 = json.loads(输出文本)
    样本表.append(("信封·待取作业过网关：退出码 %d（期望 待取作业码）· 错误.种类 %r（期望 待取作业）"
             "· 成功 %s（期望 假）· 回执带任务ID %s"
             % (退出码, (读数.get("错误") or {}).get("种类"), 读数.get("成功"),
                "是" if "4" * 32 in (读数.get("说明") or "") else "否"),
             退出码 == 待取作业码 and (读数.get("错误") or {}).get("种类") == "待取作业"
             and 读数.get("成功") is False and "4" * 32 in (读数.get("说明") or "")))

    # ── ④c 失败回执带详情（2026-10-10 真实发作 · 腿 v1-100759）：失败正文要给**网关写的详情全文**
    #   （写前字面禁项逐条 / 缺参名单），不许只回一句「失败：业务失败」——那等于「不知道为什么失败」。
    from ...服务协议 import 协议
    替身表 = {"样本工具": (lambda 实参, 仓根: (3, json.dumps(
        {"退出码": 3, "工具": "样本工具", "操作": "改",
         "说明": "整批预检不过：① 写前字面禁项在「样本区/禁项件.py」；② 缺参 旧内容",
         "错误": {"种类": "业务失败", "缺参": ["旧内容"]}}, ensure_ascii=False)), "样本", "", {})}
    结果值, 错误 = 协议.派发("tools/call", {"name": "样本工具", "arguments": {"操作": "改"}}, 仓根, 替身表)
    正文 = 结果值["content"][0]["text"]
    样本表.append(("信封·失败回执带详情：退出码 3 ⇒ 正文 %r（须含具体详情，不得只回「失败：业务失败」）" % 正文,
             错误 is None and 结果值["isError"] and 正文.startswith("失败：")
             and "整批预检不过" in 正文 and "缺参" in 正文 and 正文 != "失败：业务失败"))
    # ── ⑤ 合法操作 / 保留号表：预留槽 ⇒ 未实现且指向已实现工具；号表不删不重造 ──
    退出码, 输出文本 = 工具表["v1_context"][0]({"操作": "仓状态"}, 仓根)
    读数 = json.loads(输出文本)
    样本表.append(("信封·预留槽指向·v1_context：操作=仓状态 ⇒ 退出码 %d（期望 2 · 未实现）"
             "· 说明指向 v1_repo %s"
             % (退出码, "是" if "v1_repo" in (读数.get("说明") or "") else "否"),
             退出码 == 2 and (读数.get("错误") or {}).get("种类") == "未实现"
             and "v1_repo" in (读数.get("说明") or "")))
    退出码, 输出文本 = 工具表["v1_symbol"][0]({"操作": "列文件符号"}, 仓根)
    读数 = json.loads(输出文本)
    样本表.append(("信封·预留槽指向·v1_symbol：操作=列文件符号 ⇒ 退出码 %d（期望 2 · 未实现）"
             "· 说明指向 列符号 %s"
             % (退出码, "是" if "列符号" in (读数.get("说明") or "") else "否"),
             退出码 == 2 and "列符号" in (读数.get("说明") or "")))
    名表 = [操作编号.编号表["v1_context"][操作号] for 操作号 in (11, 12, 13, 14, 15)]
    规范表 = 参数规范.载入操作表().get("v1_context", {})
    样本表.append(("信封·保留号表：v1_context 号表 11..15 名字仍在且都在操作表里：%s"
             % "、".join(名表),
             len(名表) == 5 and all(操作名 in 规范表 for 操作名 in 名表)))

    # ── ⑥ 处理器输出合同（台账 10106301 / 10106303 同族根因）：允许类型只有 str/dict/list/None，
    #   其余类型与坏形状一律业务失败（退出码 3），**不许** `str(对象)` 当成功；不可序列化也归业务失败。
    合同表 = (
        ("dict ⇒ 结果真 dict", (0, {"整体状态": "全成功"}), 0, dict),
        ("str ⇒ 文本工具", (0, "文本回执"), 0, str),
        ("list ⇒ 包成 列表 键", (0, [1, 2]), 0, dict),
        ("None ⇒ 空文本", (0, None), 0, str),
        ("非法退出码 ⇒ 3", ("x", "y"), 3, str),
        ("非法元组（三项）⇒ 3", (0, "a", "b"), 3, str),
        ("非法类型（int）⇒ 3 且不转文本当成功", (0, 7), 3, str),
    )
    for 名称, 回值, 期望码, 期望类型 in 合同表:
        退出码, 输出文本 = 参数规范.归一处理输出(回值)
        样本表.append(("信封·输出合同·%s ⇒ 退出码 %d（期望 %d）· 类型 %s（期望 %s）"
                 % (名称, 退出码, 期望码, type(输出文本).__name__, 期望类型.__name__),
                 退出码 == 期望码 and isinstance(输出文本, 期望类型)))
    字节数, 序列化错 = 参数规范.序列化读数({"键": {1, 2}})
    样本表.append(("信封·非 JSON dict ⇒ 业务失败且点名副作用可能已发生（字节 %d）" % 字节数,
             字节数 == 0 and 序列化错 is not None and "副作用可能已发生" in 序列化错))
    return 样本表
