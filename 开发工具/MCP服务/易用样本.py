# -*- coding: utf-8 -*-
"""易用样本 —— MCP 易用性小包的正反样本（载荷 / 行号映射 / 标准具名 / 自愈提示 / 参数层位 / 推名 / 发现面）。

**为什么单开一件**（判据 ⑲ 单源文件 ≤400 行）：`自检样本.py` 已接近上限，把这组**纯函数 /
只读**样本搬出来，`自检样本.py` 只留一行调用。全部样本**不动仓、不起进程、不写盘**（推名样本
在**临时夹具**里建名册，跑完即删）。
"""
import sqlite3
import tempfile
from pathlib import Path


def 样本列表(仓根, 工具表) -> list:
    """⇒ 样本表（`[(说明, 通过), …]`）。"""
    from . import 服务指纹
    from .作业 import 具名作业表
    from .命名闸 import 登记载荷 as 命名载荷, 映射文件行
    from .操作_批量登记 import 抽可登记, 登记载荷 as 预检载荷, 推名操作, 推名项表
    from .顶层开工号 import 上提
    样本表 = []

    # ① v1_name 预检载荷（干跑回执末尾给可粘贴 `批量登记` 载荷）
    回执 = ("批量登记（干跑，未写库）：收到 2 行 · 登记 2 · 已存在跳过 0 · 需改名 0 · 批内重复 0\n"
          "【可登记】2 个\n  读配置\n  写日志\n")
    名表 = 抽可登记(回执)
    载荷 = 预检载荷("v1-100000", 名表)
    样本表.append(("预检载荷·正向：抽 %d 个可登记 · 载荷含开工号与两名" % len(名表),
             名表 == [["读配置"], ["写日志"]] and "v1-100000" in 载荷
             and "批量登记" in 载荷 and "读配置" in 载荷 and "写日志" in 载荷))
    样本表.append(("预检载荷·反向：无可登记 ⇒ 空名单且空载荷",
             抽可登记("【需改名】1 个\n  「坏名」  —— 落禁止形状\n") == []
             and 预检载荷("v1-1", []) == ""))

    # ② v1_edit 命名拒载荷
    命名条目 = [("样例.py", 3, "未登记配置"), ("样例.py", 5, "未登记日志")]
    命名文本 = 命名载荷("v1-100000", 命名条目)
    样本表.append(("命名拒载荷·正向：含两名字与开工号",
             "v1-100000" in 命名文本 and "未登记配置" in 命名文本
             and "未登记日志" in 命名文本 and "批量登记" in 命名文本))
    样本表.append(("命名拒载荷·反向：空条目 ⇒ 空串", 命名载荷("v1-1", []) == ""))

    # ③ 命名回执行号：片段行 ⇒ 文件行
    with tempfile.TemporaryDirectory(prefix="v1易用样本-") as 临时根:
        工作树 = Path(临时根)
        (工作树 / "样例.py").write_text("读配置 = 1\n" * 19 + "旧锚点 = 2\n", encoding="utf-8")
        文件行 = 映射文件行(工作树, "样例.py", False, "旧锚点 = 2", 1)
        整件行 = 映射文件行(工作树, "样例.py", True, "", 1)
        缺锚行 = 映射文件行(工作树, "样例.py", False, "不存在的锚点", 7)
        样本表.append(("命名行号映射·正向：片段第 1 行 ⇒ 文件第 %d 行（期望 20）" % 文件行, 文件行 == 20))
        样本表.append(("命名行号映射·整件（功能=0）：片段行即文件行（%d）" % 整件行, 整件行 == 1))
        样本表.append(("命名行号映射·反向：锚点定位不了 ⇒ 原样返回片段行（%d）" % 缺锚行, 缺锚行 == 7))

    # ④ 标准具名（自测 / 案例）
    样本表.append(("标准具名·自测在册", 具名作业表.get("自测", "").endswith("一键验证.py --自测")))
    样本表.append(("标准具名·案例在册", 具名作业表.get("案例", "").endswith("-p v1-case-runner")))

    # ⑤ 自愈提示去重（同一盘上指纹只提示一次）
    原已提示, 真指纹 = 服务指纹._已提示指纹, 服务指纹.算服务指纹
    try:
        服务指纹._已提示指纹 = None
        服务指纹.算服务指纹 = lambda: "盘上样本指纹"
        首提示 = 服务指纹.过期提示一次()
        再提示 = 服务指纹.过期提示一次()
        服务指纹.算服务指纹 = lambda: "盘上样本指纹二"
        变后提示 = 服务指纹.过期提示一次()
        服务指纹.算服务指纹 = lambda: 服务指纹.启动指纹
        一致提示 = 服务指纹.过期提示一次()
        样本表.append(("自愈提示去重：首非空 %s · 同指纹闭口 %s · 变后非空 %s · 一致空 %s"
                 % (bool(首提示), not 再提示, bool(变后提示), not 一致提示),
                 bool(首提示) and not 再提示 and bool(变后提示) and not 一致提示))
    finally:
        服务指纹.算服务指纹, 服务指纹._已提示指纹 = 真指纹, 原已提示

    # ⑥ 参数层位：参数内 `开工ID` 自动上提
    新参数, 新号, 提示 = 上提({"开工ID": "v1-100001", "改动表": []}, "")
    样本表.append(("参数层位·上提：参数内开工号上提 + 给说明",
             新号 == "v1-100001" and "开工ID" not in 新参数 and bool(提示)))
    新参数, 新号, 提示 = 上提({"开工ID": "v1-100001"}, "v1-100002")
    样本表.append(("参数层位·并存：顶层优先 + 给说明",
             新号 == "v1-100002" and "开工ID" not in 新参数 and bool(提示)))
    新参数, 新号, 提示 = 上提({"改动表": []}, "v1-100002")
    样本表.append(("参数层位·无嵌套：原样且无提示", 新号 == "v1-100002" and 提示 == ""))

    # ⑦ 发现面：description 列全可用操作
    样本表.append(("发现面·描述列全可用操作（v1_job 含 list）",
             工具表.get("v1_job") is not None and "可用操作：" in 工具表["v1_job"][2]
             and "list" in 工具表["v1_job"][2]))

    # ⑧ 推名：比对面 = 合格名册（待改名不算已登记）
    with tempfile.TemporaryDirectory(prefix="v1推名样本-") as 临时根:
        工作树 = Path(临时根)
        (工作树 / "开发工具/信息核心").mkdir(parents=True)
        连接 = sqlite3.connect(str(工作树 / "开发工具/信息核心/信息核心.db"))
        连接.execute("create table 命名登记(名字 text, 语义 text, 模式 text, 来源 text, 状态 text)")
        连接.execute("create table 命名例外(名字 text, 说明 text)")
        连接.execute("insert into 命名登记 values('读配置','样本','动作+对象','新定义','合格')")
        连接.execute("insert into 命名登记 values('待改样例','样本','动作+对象','新定义','待改名')")
        连接.commit()
        连接.close()
        源码 = "def 样例函数(读配置):\n    局部值 = 读配置\n    待改样例 = 局部值\n    新样例名 = 待改样例\n"
        样本表.append(("推名·项表：源码 + 路径 ⇒ 整件项",
                 推名项表({"路径": "样例.py", "源码": 源码}) == [("样例.py", 0, "", 源码)]))
        退出码, 输出文本 = 推名操作("", {"路径": "样例.py", "源码": 源码}, 工作树)
        样本表.append(("推名·正向：合格名不报 · 待改名与新名都报 · 附载荷",
                 退出码 == 0 and "读配置" not in 输出文本 and "待改样例" in 输出文本
                 and "新样例名" in 输出文本 and "批量登记" in 输出文本))
        样本表.append(("推名·反向：参数不全 ⇒ 退出码 2", 推名操作("", {"源码": 源码}, 工作树)[0] == 2))
    return 样本表
