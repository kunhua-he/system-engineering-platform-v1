    闸输出 = ("闸 0：两条闸串起来跑\n"
            "  闸 1 · 声明侧 ｜ 通过 37 项 · 失败 0 项 · 未判 0 项\n"
            "  闸 2 · 实现侧 ｜ 通过 12 项 · 失败 0 项 · 未判 0 项\n")
