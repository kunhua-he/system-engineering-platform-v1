def _写响应报文(输出, 报文号, 查询读数=None, 错误=None):
    """写一条响应。`错误` 非空 ⇒ JSON-RPC 错误对象（协议级失败，不是工具失败）。"""
    响应报文 = {"jsonrpc": "2.0", "id": 报文号}
    if 错误 is not None:
        响应报文["error"] = 错误
    else:
        响应报文["result"] = 查询读数
    输出.write(json.dumps(响应报文, ensure_ascii=False) + "\n")
    输出.flush()


def 派发(协议方法, 命令行参数, 仓根, 工具表):
    """把一个请求派到 MCP 的四个方法上 ⇒ `(结果, 错误)`。

    业务派发**逐字共用**同一份工具表 / 同一份统一信封，不因入口不同而绕授权。
    """
    if 协议方法 == "initialize":
        # MCP 口径：回**服务端支持**的版本 —— 不原样回显客户端请求的版本（原样回显 = 声称支持所有版本）。
        return {
            "protocolVersion": 协议版本,
            "capabilities": {"tools": {}},
            "serverInfo": {"name": 服务名, "title": 服务显示名, "version": 服务版本},
            "instructions": 服务提示词,
        }, None
    if 协议方法 == "ping":
        return {}, None
    if 协议方法 == "tools/list":
        # 工具表每条 = `(实现, 标题, 说明, 模式)` —— 标题是**中文显示名**，说明是给模型的原文。
        return {"tools": [
            {"name": 名称, "title": 标题, "description": 说明, "inputSchema": 模式}
            for 名称, (_实现, 标题, 说明, 模式) in 工具表.items()
        ]}, None
    if 协议方法 == "tools/call":
        名称 = 命令行参数.get("name")
        if 名称 not in 工具表:
            return None, {"code": -32602, "message": "没有这个工具：%r" % (名称,)}
        实参 = 命令行参数.get("arguments")
        if 实参 is None:
            实参 = {}
        if not isinstance(实参, dict):
            return None, {"code": -32602,
                          "message": "arguments 必须是对象，收到：%s" % type(实参).__name__}
        实现 = 工具表[名称][0]
        操作名 = str(实参.get("操作") or "")
        开工号 = str(实参.get("开工ID") or "")
        try:
            退出码, 输出文本 = 实现(实参, 仓根)
        except Exception as 异常:
            from .诊断记录 import 记诊断, 取定位
            记诊断(名称, 操作名, 开工号, type(异常).__name__, 定位=取定位(异常))
            raise
        # ★ 对外只砍**实测无人读**的两个壳字段：`树`（绝对路径 + 40 位提交号）与 `服务`（版本 + 指纹）
        #   —— 全仓 `get("树")` / `["树"]` / `get("服务")` / `["服务"]` 实测皆 **0 处引用**，
        #   但它们**每次调用都原样重带**，是回执里体积最大、信息量为零的部分。
        # ★ 其余字段**一律保留**：`退出码` 是**承重件**（`反馈帧样本.py::取码` 靠信封顶层 `退出码`
        #   读业务码，缺了就退化成 -99 ⇒ 腿里 26 条探针全红），`工具` / `操作` 被诊断样本与流水读，
        #   `截断` 被死腿检测读。**删壳不许删到承重件**——先实测证明无人读，再动手。
        # ★ content 与 structuredContent 用**同一份**对外形状 ⇒ 上游（Hermes `mcp_tool_handlers.
        #   _render_call_tool_result`）按「文本块与 structuredContent 逐字相同即去重」只给模型一份
        #   （据 kimi-code#3234）；不去重的客户端收两份也只是同一份小对象，不再是两整段大 JSON。
        内层读数 = 结构化(输出文本)
        对外读数 = None
        if 内层读数 is not None:
            对外读数 = dict(内层读数)
            对外读数.pop("树", None)
            对外读数.pop("服务", None)
        # ★ 2026-10-10（华哥 2026-10-09 定口径，见 `项目文档/决策记录/2026-10-09_回执与绑定裁决口径.md`
        #   §一「回执：只给结果本身」）：`content` 走「易语言式返回值」——
        #   对模型那面**只给那个值本身**，没有成功/失败包装（参照 `句柄 = 连接(地址, 账号, 密码…)`）。
        #   成功 ⇒ `结果` 就是值（无 `结果` 时给 `说明` 那一句）；失败 ⇒ 给失败原因一句。
        # ★ 分层：`structuredContent` **仍给完整信封**（含 `退出码`）—— 内部探针链（`反馈帧样本.py::取码`
        #   靠它读业务码，缺即退化成 -99，腿里 26 条探针全红）先读这一份；等探针链全部迁到新形状
        #   再撤信封。**不得一步砍到底**（已真实发作一次）。
        待取 = 退出码 == 待取作业码
        if 退出码 == 0 or 待取:
            if 对外读数 is not None and 对外读数.get("结果") is not None:
                内容文本 = json.dumps(对外读数["结果"], ensure_ascii=False)
            elif 对外读数 is not None:
                内容文本 = str(对外读数.get("说明") or "")
            else:
                内容文本 = 输出文本
        else:
            # ★ 失败原因优先取 `说明`（它才是网关写的详情全文：缺参 / 禁项 / 拒因逐条都在里面），
            #   `错误` 只是个分类信封（种类 / 缺参 / 最短例）。实测教训（2026-10-10）：先取
            #   `错误.种类` ⇒ 只回一句「业务失败」，把真正的详情（写前字面禁项逐条、缺参名单）
            #   全丢了 —— 调用方看到失败却不知道为什么失败。
            失败原因 = None
            if 对外读数 is not None:
                失败原因 = 对外读数.get("说明")
                if not 失败原因:
                    错误读数 = 对外读数.get("错误")
                    if isinstance(错误读数, dict):
                        失败原因 = 错误读数.get("说明") or 错误读数.get("原因") or 错误读数.get("种类")
                    elif isinstance(错误读数, str):
                        失败原因 = 错误读数
            if not 失败原因:
                失败原因 = 输出文本
            内容文本 = "失败：%s" % str(失败原因).strip()
        # ★ 2026-10-10（债务 320）：`待取作业码`（-3，长活已转后台、同步窗口内未到终态）**不是失败**
        #   —— 它要调用方去 `v1_job` 取。原先 `!= 0` 把它折成 isError，运行中被读成失败。
        结果值 = {"content": [{"type": "text", "text": 内容文本}],
                "isError": 退出码 not in (0, 待取作业码)}
        if 对外读数 is not None:
            # 探针面：完整信封（`退出码` 是承重字段，探针链迁完前不可撤）。
            结果值["structuredContent"] = 对外读数
        return 结果值, None
    return None, {"code": -32601, "message": "方法不存在：%r" % (协议方法,)}

def _重启参数():
    """自愈重启的 argv：**原样重放本进程的启动参数**（含 `-B` / `-u` 等解释器标志）。

    为什么不用 `[sys.executable] + sys.argv`：那样会**丢掉启动时的解释器标志** —— 实测：客户端
    以 `python3 -B -u` 拉起服务，`-B` 一丢，`dont_write_bytecode` 翻假 ⇒ 自愈后每次 import
    都在仓里写 `__pycache__`（污染仓）。`sys.orig_argv`（Python ≥3.10）保真原样。它不可用时
    才退回旧口径（保命：宁可少几个标志，也不让服务起不来）。
    """
    参数表 = list(getattr(sys, "orig_argv", None) or [])
    if not 参数表:
        参数表 = [sys.executable] + sys.argv
    return 参数表
