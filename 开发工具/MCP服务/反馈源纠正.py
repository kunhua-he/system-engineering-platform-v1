# -*- coding: utf-8 -*-
"""反馈源纠正 —— 来源报告**路径**的正式纠正口（只改定位，不改内容身份与来源身份）。

**为什么要有它**（2026-10-08 审计实证）：`补证` 只能给条目追加证据，**没有正式更新口** ——
来源 `报告路径` 一旦写错（会话目录 / 用户名 / 目录名笔误），只能靠补证在正文里「口头纠正」，
原字段仍错。本件是**唯一**的路径纠正口，最小闭环：

  输入一条 = `来源号` + `预期旧路径` + `既有完整指纹` + `候选新路径`；
  **只改同一来源身份的定位**（`报告路径`）—— `内容指纹`（报告内容 sha）与 `来源标识`（代理号）
  **一字不改**；条目的全部事实（现象 / 证据 / 判词 / 关闭）**一字不改**。

四道闸（任一条不过 ⇒ **整批零写**，一条 SQL 都不落）：
  ① **权限**：来源必须属**本开工**（顶层 `开工ID`）⇒ 跨开工越界拒。
  ② **漂移**：库内 `报告路径` 必须**逐字等于** `预期旧路径` ⇒ 别人已改过就拒（不盲覆盖）。
  ③ **真实性**：`既有完整指纹` 必须是**完整 sha256**（64 位十六进制，**缩写不算**）且**等于**
     库内 `内容指纹`；`候选新路径` 必须可读、是**普通件**、其 sha256 **等于** `内容指纹`
     （⇒ 候选确是同内容的真件，不是另一份报告）。
  ④ **有界**：`候选新路径`（解析符号链接后）必须落在**允许根**内（客户端代理源根 / 项目根 /
     官方工作树）⇒ 越界 / 符号链接外逃拒。

`内容指纹` = `缺件指纹标记`（缺件来源无内容身份）⇒ 拒（无可比对的真实内容）。
"""

import hashlib
from pathlib import Path

from . import 反馈账本 as 账本
from .反馈判词 import 找重号
from .反馈提交 import 取文本

# 完整 sha256 的十六进制长度 —— **完整**才算（八位缩写一类是形状对、身份不对，一律拒）。
完整指纹长 = 64


def 读文件指纹(路径) -> str:
    """件内容的 sha256（读不动 ⇒ 空串，调用方按「不是同一份报告」拒）。"""
    try:
        文件字节 = Path(路径).read_bytes()
    except OSError:
        return ""
    return hashlib.sha256(文件字节).hexdigest()


def 允许根表(仓根) -> list:
    """候选新路径的**允许根**（解析符号链接后须落在其中）：客户端代理源根 · 项目根 · 官方工作树。"""
    from . import 反馈源清点
    根表 = []
    for 根文本 in (反馈源清点.客户端根(), 反馈源清点.项目根(仓根), 反馈源清点.工作树根(仓根)):
        try:
            根表.append(str(Path(根文本).resolve()))
        except OSError:
            continue
    return sorted(set(根表))


def 路径有界(候选路径, 根表) -> tuple:
    """`候选路径` 解析符号链接后是否落在 `根表` 内、且是可读普通件 ⇒ `(实路径, 错误)`。"""
    try:
        实路径 = Path(候选路径).resolve()
    except (OSError, RuntimeError):
        return None, "候选新路径读不动 / 符号链接环 ⇒ 拒"
    if not 实路径.is_file():
        return None, "候选新路径不存在 / 不是普通件（目录 / 特殊件）⇒ 拒"
    实文本 = str(实路径)
    for 根文本 in 根表:
        if 实文本 == 根文本 or 实文本.startswith(根文本 + "/"):
            return 实路径, ""
    return None, "候选新路径越界（解析后 %s 不在允许根 %s 内）⇒ 拒" % (实文本, " · ".join(根表))


def 规范一条(连接, 开工号, 纠正项, 序次, 根表) -> tuple:
    """一条纠正 ⇒ `(规范 dict, 错误表)`（**只判不写**；四道闸全在这里）。"""
    if not isinstance(纠正项, dict):
        return {}, ["纠正 %d：要是对象" % 序次]
    错误表 = []
    来源号 = 纠正项.get("来源号")
    预期旧路径 = 取文本(纠正项.get("预期旧路径"))
    既有完整指纹 = 取文本(纠正项.get("既有完整指纹")).lower()
    候选新路径 = 取文本(纠正项.get("候选新路径"))
    if type(来源号) is not int:
        错误表.append("纠正 %d：`来源号` 要是整数" % 序次)
    if not 预期旧路径:
        错误表.append("纠正 %d：缺 `预期旧路径`（漂移闸的锚）" % 序次)
    if len(既有完整指纹) != 完整指纹长 or not 账本.指纹形状.fullmatch(既有完整指纹):
        错误表.append("纠正 %d：`既有完整指纹` 要是**完整 sha256**（%d 位十六进制；"
                 "缩写 / 形状像 sha 的串一律拒）" % (序次, 完整指纹长))
    if not 候选新路径:
        错误表.append("纠正 %d：缺 `候选新路径`" % 序次)
    来源行 = 账本.读来源(连接, 来源号) if type(来源号) is int else None
    if type(来源号) is int and not 来源行:
        错误表.append("纠正 %d：来源 %d 不存在" % (序次, 来源号))
    elif 来源行 is not None and 来源行["开工号"] != 开工号:
        错误表.append("纠正 %d：来源 %d 属开工 %s ⇒ **跨开工越界**（只认本号）"
                 % (序次, 来源号, 来源行["开工号"]))
    内容指纹 = (来源行 or {}).get("内容指纹") or ""
    实路径 = None
    if 来源行 is not None and 来源行["开工号"] == 开工号:
        if len(内容指纹) != 完整指纹长 or not 账本.指纹形状.fullmatch(内容指纹):
            错误表.append("纠正 %d：来源 %d 无完整内容身份（内容指纹 %r）⇒ 无可比对的真件"
                     % (序次, 来源号, 内容指纹))
        elif 既有完整指纹 != 内容指纹.lower():
            错误表.append("纠正 %d：`既有完整指纹` ≠ 库内 `内容指纹` ⇒ 不是同一份报告" % 序次)
        elif (来源行["报告路径"] or "") != 预期旧路径:
            错误表.append("纠正 %d：库内报告路径已漂移（现 %r ≠ 预期 %r）⇒ 拒，先核现状"
                     % (序次, 来源行["报告路径"], 预期旧路径))
    if 候选新路径:
        实路径, 有界错 = 路径有界(候选新路径, 根表)
        if 有界错:
            错误表.append("纠正 %d：%s" % (序次, 有界错))
        elif 内容指纹 and 读文件指纹(实路径) != 内容指纹.lower():
            错误表.append("纠正 %d：候选件 sha256 ≠ 库内 `内容指纹` ⇒ 候选不是同一份报告" % 序次)
    return {"来源号": 来源号, "预期旧路径": 预期旧路径, "候选新路径": 候选新路径,
            "实路径": 实路径}, 错误表


def 纠正来源路径(仓根, 开工号, 参数表) -> tuple:
    """一批来源路径纠正 ⇒ `(退出码, 短回执 JSON)`。**整批事务**：一条不合规整批零写。"""
    if not 账本.是开工号(开工号):
        return 2, "纠正来源路径要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    纠正表 = 参数表.get("纠正表")
    if not isinstance(纠正表, list) or not 纠正表:
        return 2, "`纠正表` 要是非空数组"
    连接 = 账本.连反馈库()
    try:
        if not 账本.开工在吗(连接, 开工号):
            return 1, "没有这条开工：%s ⇒ 先登记" % 开工号
        根表 = 允许根表(仓根)
        错误表 = []
        规范表 = []
        for 序次, 纠正项 in enumerate(纠正表, 1):
            规范, 条目错 = 规范一条(连接, 开工号, 纠正项, 序次, 根表)
            错误表 += 条目错
            规范表.append(规范)
        重号 = 找重号([规范["来源号"] for 规范 in 规范表 if type(规范.get("来源号")) is int])
        if 重号:
            错误表.append("批内重复纠正同一来源：%s" % " · ".join(str(号值) for 号值 in 重号))
        if 错误表:
            return 2, "**整批零写**（纠正来源路径校验未过）：\n  " + "\n  ".join(错误表)
        明细表 = []
        for 规范 in 规范表:
            连接.execute("update 反馈来源 set 报告路径 = ? where 来源号 = ?",
                      (规范["候选新路径"], 规范["来源号"]))
            明细表.append({"来源号": 规范["来源号"], "旧路径": 规范["预期旧路径"],
                       "新路径": 规范["候选新路径"]})
        连接.commit()
        return 0, 账本.拼回执({"纠正条数": len(明细表), "纠正": 明细表})
    except Exception:
        连接.rollback()
        raise
    finally:
        连接.close()
