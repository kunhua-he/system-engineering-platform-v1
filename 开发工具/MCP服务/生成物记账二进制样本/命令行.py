# -*- coding: utf-8 -*-
"""命令行 —— 用法行 · 帮助文本 · 入口函数(参数)（退出码 0 全绿 / 1 有红）。"""

from pathlib import Path

from . import 断言, 夹具
from 运行数据根 import 确保子目录, 解析当前环境

用法文本 = "用法：python 开发工具/MCP服务/生成物记账二进制样本.py [夹具根]"


def 帮助文本() -> list:
    return [
        用法文本,
        "",
        "夹具根缺省 = 运行数据根的 `临时件` 子目录；样本只在它自身的子目录里造夹具，跑完删掉它。",
        "档位：① 声明档（纯函数）· ② 核验档（纯函数）· ③ 记账档（真跑 记生成物账 + 隔离账本）。",
        "隔离：记账档把 `%s` 指到夹具目录 ⇒ 真账本一个字节都不碰。" % 夹具.运行数据根环境变量,
    ]


def 入口函数(命令行参数) -> int:
    if any(参数词 in ("-h", "--帮助") for 参数词 in 命令行参数):
        for 源码行 in 帮助文本():
            print(源码行)
        return 0
    夹具根 = (Path(命令行参数[0]).resolve() if 命令行参数
            else 确保子目录(解析当前环境(), "临时件"))
    夹具根 = 夹具根 / "生成物记账二进制样本-夹具"
    夹具.清理夹具(夹具根)
    夹具根.mkdir(parents=True, exist_ok=True)
    try:
        断言表 = 断言.判声明档(夹具根) + 断言.判核验档(夹具根) + 断言.判记账档(夹具根)
    finally:
        夹具.清理夹具(夹具根)
    for 断言名, 通过, 读数 in 断言表:
        print("%s %s %s" % ("✓" if 通过 else "✗", 断言名, 读数))
    失败数 = sum(1 for _, 通过, _ in 断言表 if not 通过)
    print("样本：%d 条，失败 %d 条" % (len(断言表), 失败数))
    return 0 if 失败数 == 0 else 1
