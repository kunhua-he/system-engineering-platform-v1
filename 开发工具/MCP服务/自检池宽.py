# -*- coding: utf-8 -*-
r"""自检池宽 —— `--自检` 的**隔离组池**该起几个工人（按机器在跑的自检分份额）。

**为什么存在**（债务 517 / 313 · 2026-10-13 实测）：隔离池原先**固定**起
`len(隔离样本组)`（15）个工人，而每个工人还要 fork python（+ git）⇒ 实测：

    1 路并发 ⇒ 每条 `--自检`  3.61 s（15 个工人用不满核）
    2 路并发 ⇒ 每条 `--自检`  6.07 s（2/2 超 5 秒硬顶）
    4 路并发 ⇒ 每条 `--自检` 13.94 s（4/4 超顶）

⇒ 判据 ㊽ 给 `--自检` 5 秒硬顶（`判据_MCP自检.py::自检超时秒`）⇒ 并发腿一多，㊽ **必红**。
那不是「抖动」，是**确定性**的：固定宽度两头不讨好（单跑浪费、并发踏平）。

**口径与 `构建装配/一键验证/一键验证/常量_池宽.py::判据池宽()` 同一条**（那边早为判据池
做了这件事，理由逐字相同）——按**机器当前在跑的自检进程数**分份额，使「同时跑的几条自检的
工人总数 ≈ 核数」。唯一不同：本处数的标记是 `自检入口词`（隔离池的服务对象），不是闸入口词。

**三条不许违反**：
  · 起 `ps` 失败 / 读不到 ⇒ 按**单跑**口径给满额（宁可多给，不静默少给）；
  · 宽度**永不小于 1**（少给会把自检判成「跑不完」）；
  · 只读机器状态，不写任何东西。
"""
from __future__ import annotations

import os
import subprocess

# 数进程用的**唯一标记**：自检入口的命令行里必有它（`MCP服务.py --自检`）。
自检入口词 = "--自检"


def 在跑自检进程数() -> int:
    """机器上正在跑的自检进程数（含本进程 —— 本进程命令行也带 `自检入口词`）。

    `ps` 起不来 / 读不到 ⇒ 返回 1（按单跑口径，见件头第一条）。
    """
    try:
        读数 = subprocess.run(["ps", "-A", "-o", "command="],
                            capture_output=True, text=True, timeout=5)
    except Exception:
        return 1
    命中数 = sum(1 for 文本行 in (读数.stdout or "").splitlines() if 自检入口词 in 文本行)
    return max(1, 命中数)


def 隔离池宽(组数: int) -> int:
    """本次该起几个隔离组工人 ⇒ 使「同时跑的几条自检的工人总数 ≈ 核数」。

    · `满额组数` = min(组数, 核数)（每组只跑一次 ⇒ 组数本身就是上限）；
    · 份额 = 满额 ÷ 在跑自检进程数（至少 1）。
    """
    满额组数 = max(1, min(int(组数), os.cpu_count() or 1))
    return max(1, 满额组数 // 在跑自检进程数())


def 自检池宽身份证() -> list:
    """本口径的身份证（挂 `--自检` 的样本表）：纯函数四问，**不真起池**。"""
    from unittest.mock import patch

    宽度表 = []
    for 进程数 in (1, 2, 4, 64):
        with patch(__name__ + ".在跑自检进程数", return_value=进程数):
            宽度表.append(隔离池宽(15))
    with patch(__name__ + ".在跑自检进程数", return_value=1):
        少组宽度 = 隔离池宽(3)
    return [
        ("自检池宽：单跑给满额（%d，期望 ≥ 2）" % 宽度表[0], 宽度表[0] >= 2),
        ("自检池宽：并发越多份额越小（%d > %d > %d）" % (宽度表[0], 宽度表[1], 宽度表[2]),
         宽度表[0] > 宽度表[1] > 宽度表[2] >= 1),
        ("自检池宽：极端并发也不给 0（%d，期望 ≥ 1）" % 宽度表[3], 宽度表[3] >= 1),
        ("自检池宽：组数少时不超组数（%d ≤ 3）" % 少组宽度, 少组宽度 <= 3),
    ]
