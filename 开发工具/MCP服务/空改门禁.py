# -*- coding: utf-8 -*-
"""空改门禁 —— 空改腿（盘上无改动）该跑哪棵树的门禁：唯一一份判据与分档。

**为什么要有它**（2026-10-08 实测根因）：旧腿树是**当年的快照**，缺 `构建装配/门禁/复跑.py`
（2026-10-08 才加）⇒ 空改释放复用共享 pre-commit 时 `ROOT = 腿树` ⇒
`ImportError: cannot import name '跑并复跑超顶'` ⇒ 30 条**成果早已在主干**的空改腿永拒。
只对**证明得了**「成果已在主干」的空改腿改走**当前主干**门禁 —— 既避旧树缺件，又顺带证明主干过闸。
判据面**不新写一份**，复用 `清树门禁.核清树条件(要求已释放=False)`（净树+已合主干 · 无在途作业 ·
无未释放消费者 · 台账未点名 · 无未蒸馏反馈，唯一一份），本件只补一条它没有的「工作树归属一致」。
"""

from .仓操作 import 检查清树安全, 跑空改门禁, 跑主干空改门禁, 查工作树归属
from .清树门禁 import 核清树条件


def 判主干空改腿(连接, 仓根, 开工号: str, 开工记录) -> tuple:
    """空改腿是否可拿**当前主干门禁**验（真腿）⇒ `(可否走主干, 已合净, 归属对, 判据行表)`。

    `已合净` 单列出来供调用方分档：已合净却**安全不全成立** ⇒ 差在**保全项**（反馈 / 台账 /
    消费者 / 作业），那就该**拒**（保全），而不是退回腿树门禁。
    """
    已合净 = 检查清树安全(仓根, 开工号, 开工记录["工作树"])[0] == 0
    归属对, 归属说明 = 查工作树归属(仓根, 开工号, 开工记录["工作树"])
    安全全成立, 判据行 = 核清树条件(连接, 仓根, 开工号, 开工记录, 要求已释放=False)
    判据行 = list(判据行) + ["%s 工作树归属一致（HEAD == 本腿 tip）—— %s"
                          % ("✓" if 归属对 else "✗", 归属说明)]
    return (安全全成立 and 归属对), 已合净, 归属对, 判据行


def 择空改门禁(走主干, 已合净, 归属对, 空改判据, 仓根, 工作树) -> tuple:
    """空改腿的门禁分三档 ⇒ `(退出码, 输出文本, 门禁名, 拒文)`（拒文非空 ⇒ 调用方直接拒）。

    ① 空改已合净（归属一致 · 无保全项）⇒ 走**当前主干**门禁（避旧树缺件，兼证主干过闸）；
    ② 已合净**但有保全项**（反馈 / 台账 / 消费者 / 非终态作业）⇒ **拒**（保全，不退回旧树）；
    ③ 未合 / 脏 ⇒ 退回本腿门禁（**未合 / dirty 释放规则一字未改**，仍旧 fail-closed）。
    """
    if 走主干:
        退出码, 输出文本 = 跑主干空改门禁(仓根)
        门禁名 = "当前主干门禁"
    elif 已合净 and 归属对:
        return 0, "", "", ("空改已合腿但**有保全项**（未蒸馏反馈 / 台账点名 / 未释放消费者 / 非终态作业）"
                         "⇒ 不释放，状态留「进行中」。逐条读数：\n%s" % "\n".join(空改判据))
    else:
        退出码, 输出文本 = 跑空改门禁(工作树)
        门禁名 = "本腿门禁"
    return 退出码, 输出文本, 门禁名, ""
