# -*- coding: utf-8 -*-
r"""诊断记录 —— MCP **失败诊断日志**的唯一落痕口（只落白名单元数据 · 单行 · 永不抛）。

**为什么要有它**（上游响应提前结束实测）：MCP 服务是长驻进程，一次内部异常、一次业务非 0
只体现为**一条回执** —— 进程不崩、也不留痕 ⇒ 事后只能靠猜。本件把**失败那一刻的白名单元数据**
落一行，供有界追溯。

**落点**：`<运行数据根>/日志/MCP诊断.log`。日志根**复用** `作业账本.日志路径`（唯一解析口是
`运行数据根/口径.py`）—— **不建第二信封**、不自拼路径。

**只记白名单元数据**（`允许字段`）：时刻 · 工具 · 操作 · 明确开工ID · 错误类型 · 退出码 · 有限定位。
**绝不记**：请求正文 / `arguments` 全文 / 环境变量 / 协议头 / 任何机密。值的来源只有两个 ——
**本仓自带的表**（工具名 · 操作名，来自 `工具.py` / `操作_*.py`）与**有界净化**过的短串（开工ID）。
内部异常只取**类型名**与**帧位置**（`件:行:函数`），**绝不取异常消息**（消息可能带机密）。

**三条硬口径**：
  · **永不抛** —— 本件自身任何失败（路径解析不出 / 目录不可写 / 写盘失败）一律吞掉并回假，
    **不改调用方的退出码 / 信封 / 异常处理**。
  · **单行有界** —— 一条一行 JSON（`单行上限` 封顶），一次 `os.write`（`O_APPEND`）落盘 ⇒
    并发不同请求的行**不交叉**。
  · **一处一记** —— 同一失败只由**一个**调用点落痕：网关**执行后**非 0 在 `参数规范.网关派发`
    的**尾**（`信封` 之后）记；内部异常在 `协议.派发` 的 `tools/call` 处记并**原样 re-raise**
    （外层照旧折 `-32603`）。先建信封、后落痕 ⇒ 两条路互斥，不双记。
"""

import json
import os
from pathlib import Path

诊断日志名 = "MCP诊断"
单行上限 = 1200
值上限 = 120
定位上限 = 200
允许字段 = ("时刻", "工具", "操作", "开工ID", "错误类型", "退出码", "定位")


def 诊断路径():
    """`<运行数据根>/日志/MCP诊断.log` —— 路径只经 `作业账本.日志路径`（本件不自拼路径）。"""
    from .作业账本 import 日志路径
    return 日志路径(诊断日志名)


def 净化字段(值) -> str:
    """白名单元数据值 ⇒ 单行短串：控制字符（含换行）抹成空格、限长（**绝不原样带正文**）。"""
    if 值 is None:
        return ""
    return "".join(" " if 单字符 < " " or 单字符 == chr(127) else 单字符
                  for 单字符 in str(值)[:值上限])


def 取定位(异常) -> str:
    """内部异常 ⇒ 有限定位 `件:行:函数`（**只取帧位置，绝不取异常消息** —— 消息可能带机密）。"""
    import traceback
    try:
        帧表 = traceback.extract_tb(异常.__traceback__)
    except Exception:
        return ""
    if not 帧表:
        return ""
    末帧 = 帧表[-1]
    return ("%s:%d:%s" % (Path(末帧.filename).name, 末帧.lineno, 末帧.name))[:定位上限]


def 记诊断(工具名, 操作名, 开工号, 错误类型, 退出码=None, 定位="") -> bool:
    """落一条诊断 ⇒ 逻辑型（真 = 落了；**假 = 本件没落成，调用方照旧**）。

    **永不抛**：包住全部动作，任何失败都吞掉并回假。字段**逐键白名单**构造（不做 `**实参`
    一类展开）⇒ 请求正文 / 环境 / 协议头无从进入。
    """
    try:
        from .作业账本 import 时刻串
        全体字段 = {
            "时刻": 时刻串(),
            "工具": 净化字段(工具名),
            "操作": 净化字段(操作名),
            "开工ID": 净化字段(开工号),
            "错误类型": 净化字段(错误类型),
            "退出码": None if 退出码 is None else int(退出码),
            "定位": 净化字段(定位),
        }
        记录行 = {键名: 全体字段[键名] for 键名 in 允许字段}
        行件 = json.dumps(记录行, ensure_ascii=False)[:单行上限]
        句柄 = os.open(str(诊断路径()), os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
        try:
            os.write(句柄, (行件 + chr(10)).encode("utf-8"))
        finally:
            os.close(句柄)
        return True
    except Exception:
        return False
