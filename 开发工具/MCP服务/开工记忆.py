# -*- coding: utf-8 -*-
"""开工记忆 —— `v1_task` 的项目记忆操作：显式检查点 / 崩溃后一次取回 / 安全收口清理。

**一句话**：给开工内置一份**项目记忆** —— 崩溃后 `取检查点` 一次拿回本号上下文；任务安全收口后
`安全清收口` 把临时检查点与工具流水**真删**（不另建永久历史库）。

**恢复摘要只合成、不臆测**：摘要**只**由「开工行规则字段 + agent 显式写的检查点行（`开工账本.检查点字段`）」
合成；没写的项**不虚构**（如实写「未记录」）。工具流水只当**时间线旁证**报出，**不进摘要** ——
绝不从流水反推模型思维。

**安全收口 fail-closed**：只在「验证已合主干 + 收口成功」后清；`未合 / 失败 / 已取消 / 崩溃失联 /
未知漂移 / 尚未完成的非终态 job` 一律**保**。复用 `仓操作.检查清树安全`（支线已合主干）与
`作业账本.非终态集`。**永不删**：Git 历史 · 正式规则库 `信息核心.db` · `未完成.json` 台账 ·
安全必要业务证据 —— 本件只删 `开工检查点` 与 `工具流水` 两张表里**本开工**的行，**不碰**
`开工` / `认领` / `改动` 账本行。删除**默认拒绝**，条件逐条成立且显式 `确认` 才动手。
"""

import re
import sqlite3
from pathlib import Path

from . import 开工账本 as 账本
from . import 开工检查点
from . import 工具流水
from . import 作业账本
from .仓操作 import 检查清树安全

开工号形状 = re.compile(r"v1-[0-9]{6}")
# 只有这六项是**检查点字段**（与 `开工账本.检查点字段` 同一份，不另写第二份）。
检查点字段 = 账本.检查点字段


# ── 记检查点 ──────────────────────────────────────────────────────────────────────────────

def 记检查点(仓根, 开工号: str, 参数表: dict) -> tuple:
    """落一条显式检查点 ⇒ `(退出码, 文本)`。字段只认 `检查点字段`；一个都不给 ⇒ 拒。"""
    if not 开工号形状.fullmatch(开工号 or ""):
        return 2, "记检查点要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    检查点 = {栏名: 参数表.get(栏名) for 栏名 in 检查点字段}
    if not any(str(检查点.get(栏名) or "").strip() for 栏名 in 检查点字段):
        return 2, ("记检查点至少要给一个字段（%s）；一个都不给 ⇒ 拒（不落空检查点）"
                 % " · ".join(检查点字段))
    连接 = 账本.连账本()
    try:
        if not 账本.读开工(连接, 开工号):
            return 1, "没有这条开工：%s ⇒ 先 登记" % 开工号
        编号 = 开工检查点.记检查点(连接, 开工号, 检查点)
        已写 = [栏名 for 栏名 in 检查点字段 if str(检查点.get(栏名) or "").strip()]
        return 0, "\n".join([
            "%s 检查点已落：编号 %d" % (开工号, 编号),
            "字段：%s" % " · ".join(已写),
            "下一步：崩溃 / 换会话后用 `取检查点` 一次取回本号上下文。",
        ])
    finally:
        连接.close()


# ── 取检查点（崩溃后一次取回上下文）────────────────────────────────────────────────────────

def 合成恢复摘要(最新检查点) -> list:
    """把**最新一条显式检查点**的规则字段合成恢复摘要行表。没检查点 ⇒ 明说「无可合成摘要」。

    **不虚构**：字段为空就写「（未记录）」；整条没有就写「无显式检查点 ⇒ 无可合成的恢复摘要」。
    """
    if not 最新检查点:
        return ["★ 无显式检查点 ⇒ 无可合成的恢复摘要（**不虚构**）。",
                "  下一步：补一条 `记检查点`（目标 · 当前步骤 · 下一动作 · 未测 · 阻断）。"]
    行表 = ["时刻：%s（编号 %s）" % (最新检查点.get("时刻"), 最新检查点.get("编号"))]
    for 栏名 in 检查点字段:
        值文本 = str(最新检查点.get(栏名) or "").strip()
        行表.append("%s：%s" % (栏名, 值文本 if 值文本 else "（未记录）"))
    return 行表


def 组装上下文行(连接, 开工号: str, 开工记录: dict) -> list:
    """开工行字段 + 认领 + 改动 ⇒ 上下文行表（只摆账本里**有**的事实）。"""
    认领表 = 账本.读认领(连接, 开工号)
    改动表 = 账本.读改动(连接, 开工号)
    归属行 = []
    if 开工记录.get("开工种类"):
        归属行.append("开工种类：%s" % 开工记录["开工种类"])
    if 开工记录.get("父开工号"):
        归属行.append("父开工号（被合 / 被接管的原腿）：%s" % 开工记录["父开工号"])
    return [
        "开工号 %s · 状态 %s" % (开工记录["开工号"], 开工记录["状态"]),
        "工作内容：%s" % 开工记录["工作内容"],
        "支线 %s · 工作树 %s" % (开工记录["分支名"], 开工记录["工作树"]),
        "开工 %s%s" % (开工记录["开工时间"],
                    " · 释放 %s" % 开工记录["释放时间"] if 开工记录["释放时间"] else ""),
    ] + 归属行 + [
        "认领 %d 件：%s" % (len(认领表), " · ".join(sorted(认领表)) or "（空）"),
        "改动 %d 次：%s" % (len(改动表), " · ".join(
            "%s(%s)" % (一条改动["路径"], 一条改动["功能"]) for 一条改动 in 改动表) or "（无）"),
    ]


def 排流水行(流水表: list) -> list:
    """工具流水（旁证时间线）⇒ 行表。**不进恢复摘要**。"""
    if not 流水表:
        return ["（无工具流水）"]
    return ["%s · %s %s · exit %s%s" % (
        一条流水["时刻"][:19], 一条流水["工具名"], 一条流水["操作"] or "（发现）",
        一条流水["退出码"],
        " · 作业 %s" % 一条流水["作业任务ID"] if 一条流水["作业任务ID"] else "")
        for 一条流水 in 流水表]


def 取检查点(仓根, 开工号: str, 参数表: dict) -> tuple:
    """一次取回本号完整上下文 ⇒ `(退出码, 文本)`。"""
    if not 开工号形状.fullmatch(开工号 or ""):
        return 2, "取检查点要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    记录条数 = 参数表.get("条数", 20)
    if type(记录条数) is not int or not 1 <= 记录条数 <= 200:
        return 2, "`条数` 要是 1..200 的整数（收到 %r）" % (记录条数,)
    连接 = 账本.连账本()
    try:
        开工记录 = 账本.读开工(连接, 开工号)
        if not 开工记录:
            return 1, "没有这条开工：%s" % 开工号
        工具流水.补流水表(连接)
        行表 = ["═ 开工上下文 ═"] + 组装上下文行(连接, 开工号, 开工记录)
        行表 += ["", "═ 恢复摘要（只由开工行字段 + 显式检查点行合成 · 未记录项不虚构）═"]
        行表 += 合成恢复摘要(开工检查点.最新检查点(连接, 开工号))
        行表 += ["", "═ 事实时间线（工具流水旁证 · 不参与摘要合成）═"]
        行表 += 排流水行(工具流水.读流水(连接, 开工号, min(记录条数, 40)))
        非终态行 = 非终态作业(开工号, 开工记录["工作树"])
        行表 += ["", "═ 非终态后台作业（未收敛 ⇒ 不许收口清理）═"]
        行表 += 非终态行 if 非终态行 is not None else ["（作业账本读不出 ⇒ fail-closed：当作有未收敛作业）"]
        return 0, "\n".join(行表)
    finally:
        连接.close()


# ── 安全判定（记忆边界 / 安全清收口 共用）──────────────────────────────────────────────────

def 读未完成行(仓根, 开工号: str) -> list:
    """`未完成.json` 里提到本开工号的原文行 ⇒ 行表（台账是证据，不许被清流程绕过）。"""
    台账件 = Path(仓根) / "开发工具" / "信息核心" / "未完成.json"
    if not 台账件.is_file():
        return []
    try:
        正文 = 台账件.read_text(encoding="utf-8")
    except OSError:
        return []
    return [源码行.strip() for 源码行 in 正文.splitlines() if 开工号 in 源码行]


def 子开工行(开工号: str) -> list:
    """父开工号 == 本开工号 的**别的**开工 ⇒ 行表（每条一行；含它当前状态）。"""
    连接 = 账本.连账本()
    try:
        return ["%s（%s）" % (记录行["开工号"], 记录行["状态"]) for 记录行 in 账本.全部开工(连接)
                if 记录行.get("父开工号") == 开工号]
    finally:
        连接.close()


def 非终态作业(开工号: str, 工作树: str):
    """与本开工相关、**尚未收敛**的后台作业 ⇒ 行表；作业账本读不出 ⇒ `None`（fail-closed）。

    关联口径：`作业` 表**有** `开工ID` 列就按它匹配；没有就退回按 `工作树` 匹配（安全兜底）。
    """
    路径 = 作业账本.作业账本路径()
    if not Path(路径).is_file():
        return []
    连接 = sqlite3.connect("file:%s?mode=ro" % 路径, uri=True)
    try:
        连接.row_factory = sqlite3.Row
        try:
            列名集 = {文本行[1] for 文本行 in 连接.execute("pragma table_info(作业)")}
            行表 = 连接.execute("select * from 作业").fetchall()
        except sqlite3.Error:
            return None
    finally:
        连接.close()
    命中 = []
    for 数据行 in 行表:
        记录行 = dict(数据行)
        if 记录行.get("状态") not in 作业账本.非终态集:
            continue
        if "开工ID" in 列名集:
            属本开工 = bool(记录行.get("开工ID")) and 记录行.get("开工ID") == 开工号
        else:
            属本开工 = Path(str(记录行.get("工作树") or "")).resolve() == Path(str(工作树)).resolve()
        if 属本开工:
            命中.append("%s · %s · 退出码 %s · 命令 %s" % (
                记录行.get("任务ID"), 记录行.get("状态"), 记录行.get("退出码"), 记录行.get("命令")))
    return 命中


def 核安全条件(仓根, 开工号: str, 开工记录: dict) -> tuple:
    """安全收口**逐条**判据 ⇒ `(是否全成立, 判据行表)`。一条不成立 ⇒ 不可清（fail-closed）。"""
    行表 = []
    条件均成立 = True

    def 记判据(通过: bool, 说明: str) -> None:
        nonlocal 条件均成立
        if not 通过:
            条件均成立 = False
        行表.append("%s %s" % ("✓" if 通过 else "✗", 说明))

    记判据(开工记录["状态"] == 账本.状态_已释放,
        "收口成功（状态「已释放」）—— 现「%s」" % 开工记录["状态"])
    退出码, 清树说明 = 检查清树安全(仓根, 开工号, 开工记录["工作树"])
    记判据(退出码 == 0, "验证已合主干 —— %s（退出码 %d）" % (清树说明, 退出码))
    作业行 = 非终态作业(开工号, 开工记录["工作树"])
    if 作业行 is None:
        记判据(False, "非终态作业读不出（作业账本异常）⇒ fail-closed，当作有未收敛作业")
    else:
        记判据(not 作业行, "无尚未收敛的后台作业" + ("（有 %d 条）" % len(作业行) if 作业行 else ""))
    for 行文本 in 作业行 or []:
        行表.append("    · " + 行文本)
    子开工表 = 子开工行(开工号)
    未释放子表 = [行文本 for 行文本 in 子开工表 if 账本.状态_已释放 not in 行文本]
    记判据(not 未释放子表, "无凡属本开工的**未释放**接管 / 子开工（继承者）"
        + ("；未释放：%s" % " · ".join(未释放子表) if 未释放子表 else ""))
    for 行文本 in 子开工表:
        行表.append("    · 子开工 " + 行文本)
    未完成行 = 读未完成行(仓根, 开工号)
    记判据(not 未完成行, "`未完成.json` 台账未点名本开工（有证据 ⇒ 不许清）")
    for 行文本 in 未完成行[:5]:
        行表.append("    · 台账：" + 行文本)
    return 条件均成立, 行表


# ── 记忆边界（只读枚举，先看边界再接线）────────────────────────────────────────────────────

def 记忆边界(仓根, 开工号: str, 参数表: dict) -> tuple:
    """只读枚举本开工的消费者 / 接管关系 / 未完成作业 / 合主干状态 ⇒ `(退出码, 文本)`。"""
    if not 开工号形状.fullmatch(开工号 or ""):
        return 2, "记忆边界要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    连接 = 账本.连账本()
    try:
        开工记录 = 账本.读开工(连接, 开工号)
    finally:
        连接.close()
    if not 开工记录:
        return 1, "没有这条开工：%s" % 开工号
    条件均成立, 判据行 = 核安全条件(仓根, 开工号, 开工记录)
    行表 = ["═ 记忆边界（只读）· %s ═" % 开工号,
           "状态 %s · 开工种类 %s · 父开工号 %s" % (
               开工记录["状态"], 开工记录.get("开工种类") or "（未记）",
               开工记录.get("父开工号") or "（无）")]
    行表 += 判据行
    行表.append("─ 结论 ─ " + ("安全条件**逐条成立** ⇒ 可 `安全清收口`（仍需显式 `确认`）"
                          if 条件均成立 else "安全条件**不成立** ⇒ 收口清理**拒**（保留检查点与流水）"))
    return 0, "\n".join(行表)


# ── 安全清收口（删默认拒绝；条件逐条成立 + 显式确认 才真删）──────────────────────────────────

def 安全清收口(仓根, 开工号: str, 参数表: dict) -> tuple:
    """**真删**本开工的临时检查点与工具流水 ⇒ `(退出码, 文本)`。fail-closed。

    删除**默认拒绝**：没传 `确认` = 真 ⇒ 只回边界报告（不删）；安全条件有一条不成立 ⇒ 拒（不删）。
    只删 `开工检查点` / `工具流水` 两张表里本开工的行；**不碰** `开工`/`认领`/`改动`、Git 历史、
    规则库 `信息核心.db`、`未完成.json`、安全必要业务证据；**不另建永久历史库**。
    """
    if not 开工号形状.fullmatch(开工号 or ""):
        return 2, "安全清收口要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    确认 = 参数表.get("确认", False)
    if not isinstance(确认, bool):
        return 2, "`确认` 要是逻辑型（默认假 = 默认拒绝）"
    连接 = 账本.连账本()
    try:
        开工记录 = 账本.读开工(连接, 开工号)
        if not 开工记录:
            return 1, "没有这条开工：%s" % 开工号
        条件均成立, 判据行 = 核安全条件(仓根, 开工号, 开工记录)
        if not 条件均成立:
            return 1, "\n".join(["**收口清理拒**（安全条件不成立，一个字节没删）："] + 判据行)
        if not 确认:
            return 2, "\n".join(
                ["**收口清理默认拒绝**（条件已成立，但没传 `确认` = 真 ⇒ 不删）："] + 判据行
                + ["★ 要真删检查点与工具流水，重提并传 `确认` = 真。"])
        工具流水.补流水表(连接)
        检查点行数 = 开工检查点.清检查点(连接, 开工号)
        流水行数 = 工具流水.清流水(连接, 开工号)
        return 0, "\n".join([
            "%s 安全收口：**已真删**临时记忆（不另建历史库）" % 开工号,
            "删掉检查点 %d 条 · 工具流水 %d 条" % (检查点行数, 流水行数),
            "保留：`开工`/`认领`/`改动` 账本行 · Git 历史 · 规则库 · `未完成.json` · 业务证据",
        ])
    finally:
        连接.close()
