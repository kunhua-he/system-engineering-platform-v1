# -*- coding: utf-8 -*-
"""反馈作废 —— 作废「空登记位」的**唯一**正式口（债务 334）。

**空登记位** = 子代理只建了登记位、从未交报告：`读取状态` = 缺件待核 · `报告路径` 与 `快照路径`
**都空** · `提取条数` = `判词条数` = 0 · 一条条目都没有。它永远「审不完」⇒ 原腿收口被**永久阻断**
（实测 11 个来源使一条开工永拒释放，当时只能手工改库）。

**两种缺件语义在这里可判别**（用现成列，不新增列、不加第二套标记）：
  · **从未有过原件** = `报告路径` 与 `快照路径` 都空 ⇒ 空登记位，**可作废**；
  · **原件丢了** = `报告路径` 有值（登记时给过）却读不到 ⇒ **待核保留、不许作废**（删了就断溯源链）。
与「不许假审完」不冲突：**作废 ≠ 审完** —— 帧十五/十六照旧拒「缺件假审完」。

fail-closed：默认只回**预览**（一个字节不删），`确认` = 真 才真删；删除走 `清理执行.删来源行`
（**不另写一份删除 SQL**）；回执逐条报作废了什么（留痕、可审计）。
"""

from . import 反馈账本 as 账本
from . import 清理执行


def 是空登记位(来源行) -> bool:
    """空登记位判据：缺件待核 · 路径与快照都空 · 提取与判词都 0（即「从未有过原件」那一档）。"""
    return (来源行["读取状态"] == 账本.读取_缺件
            and not str(来源行["报告路径"] or "").strip()
            and not str(来源行["快照路径"] or "").strip()
            and int(来源行["提取条数"] or 0) == 0
            and int(来源行["判词条数"] or 0) == 0)


def 作废空登记位(仓根, 开工号: str, 参数表: dict) -> tuple:
    """作废空登记位 ⇒ `(退出码, 回执)`；`来源号表` 缺省 = 本开工全部空登记位。"""
    来源号表 = 参数表.get("来源号表")
    确认 = 参数表.get("确认") is True
    if 来源号表 is not None and not isinstance(来源号表, list):
        return 2, "`来源号表` 要是数组（省 = 本开工全部空登记位）；收到 %s" % type(来源号表).__name__
    连接 = 账本.连反馈库()
    try:
        点名 = 来源号表 is not None
        候补 = []
        if not 点名:
            候补 = 账本.列来源(连接, 开工号)
        else:
            for 序号, 来源号 in enumerate(来源号表, 1):
                if type(来源号) is not int:
                    return 2, "作废 %d：`来源号` 要是整数" % 序号
                来源行 = 账本.读来源(连接, 来源号)
                if not 来源行:
                    return 2, "作废 %d：来源 %d 不存在" % (序号, 来源号)
                候补.append(来源行)
        拒表 = []
        可删 = []
        跳过 = []
        for 来源行 in 候补:
            来源号 = 来源行["来源号"]
            理由 = ""
            if 来源行["开工号"] != 开工号:
                理由 = "属开工 %s ⇒ **跨开工越界**（作废按来源开工顶层ID）" % 来源行["开工号"]
            elif 来源行["审完时刻"]:
                理由 = "已审完 ⇒ 不是空登记位"
            elif not 是空登记位(来源行):
                理由 = ("不是空登记位（读取状态 %s · 报告路径 %s · 提取 %d · 判词 %d）⇒ "
                       "**原件丢了**（登记时给过路径）与**有过内容**都属待核保留"
                       % (来源行["读取状态"], 来源行["报告路径"] or "空",
                          来源行["提取条数"] or 0, 来源行["判词条数"] or 0))
            else:
                条目数 = 连接.execute("select count(*) from 反馈条目 where 来源号 = ?",
                                 (来源号,)).fetchone()[0]
                if 条目数:
                    理由 = "下还有 %d 条条目 ⇒ 不是空登记位" % 条目数
            if not 理由:
                可删.append(来源号)
            elif 点名:
                拒表.append("来源 %d %s" % (来源号, 理由))
            else:
                跳过.append(来源号)
        if 拒表:
            return 2, "**整批零写**（一条不合规就整批拒）：\n  " + "\n  ".join(拒表)
        if not 可删:
            return 0, ("本开工来源里没有可作废的空登记位（0 条符合「从未有过原件」那一档）· "
                     "跳过 %d 条" % len(跳过))
        点名说明 = "点名 %d 条" % len(来源号表) if 点名 else "全量扫描（本开工 %d 条来源）" % len(候补)
        if not 确认:
            行表 = ["**作废预览（默认拒绝，一个字节没删）** · 开工 %s · %s" % (开工号, 点名说明),
                   "  可作废空登记位 %d 个：%s" % (len(可删), " · ".join(str(来源号) for 来源号 in 可删[:20])),
                   "  跳过（不属「从未有过原件」那一档、未动）%d 个" % len(跳过),
                   "  ★ 作废 = 删掉「从未有过原件」的登记位（它永远审不完、永久阻断收口）；"
                   "**原件丢了**的来源不在此列（待核保留、不许作废）。带 `确认` = 真 才真删。"]
            return 0, "\n".join(行表)
        with 连接:
            删掉 = 清理执行.删来源行(连接, 可删)
        return 0, ("作废空登记位：真删 %d 条来源行（%s）· 跳过 %d 条 · 留痕：本回执即审计记录"
                  "（走 MCP、不手工改库）"
                  % (删掉, " · ".join(str(来源号) for 来源号 in 可删[:20]), len(跳过)))
    finally:
        连接.close()
