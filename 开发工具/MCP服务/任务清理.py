# -*- coding: utf-8 -*-
"""任务清理 —— `v1_task`「清理已解决任务」（号 21，追加不复用）的**编排与回执面**。

**一句话**：把**已解决**任务的证据按 fail-closed 逐条判定后**一次性真删**；**未解决事实一律承接
保留**（不脚本关键词切分、不伪造指纹 / 历史、不按目录粗删）。三种入口（同一套判定）：

  · **任务模式** —— 给顶层 `开工ID`：清这条**过了正式收口保护**（已释放 · 已合主干 · 净树 · 无在途
    作业 · 无未释放消费者 · 台账未点名 · 无未蒸馏反馈）的开工的整份生命周期（反馈 + 开工/认领/
    改动历史 + 归属作业行与日志 + 精确报告件 + **开工行本体** + 工作树与支线）；
  · **条目模式** —— 给 `条目选择`（`[{条目号, 审计所属, 承接任务}, …]`）：**跨开工定向**清**精确
    条目**。条目住 642、维修在 643 这类「审计与承接分列」由此可达；**绝不粗删**别的未解决反馈；
  · **续清** —— 本开工若有 `清理待续` 残留（上次 unlink 失败 / 崩溃），**先续清再算新计划**。

**为什么拆三件**（判据 ⑲ 单件 ≤400 行）：本件只留编排与回执；判定口径住 `清理选择.py`；落盘执行
（路径硬化 · 待续清意图 · 库行删除）住 `清理执行.py`。

**顺序与原子性**：先续清（幂等）→ 只读算计划 → **默认拒绝**（回预览）→ `确认`=真 时**一条事务**
删库行 **并落待续清意图**（`清理待续` 表，与库行同事务 ⇒ 崩溃后能续清）→ 提交**之后**才逐个 `unlink`，
删一件清一件待续行。**残留 ⇒ 不回 0**（不得宣称完整清）；下次调用先续清，清完即删行、不留永久流水。
不另建历史库、不复制原件、不备份整史。

**留下的最小东西**：**什么都不留** —— 开工行**本体删除**（2026-10-08 用户纠偏：墓碑是「以关闭
替代删」）。代价：开工号不再由本行保「已用过」（`新开工号` 取现存最大 + 1）。条目模式**不动**
任何开工行（只删标定条目）。

**永不删**：Git 历史 · 源码 · 规则库 `信息核心.db` · `未完成.json` · 别的开工的行 · 别的开工的未解
决反馈 · 整个 `.zcode` 代理库 / 全局日志；不跳钩子、不手写 SQL、不碰权限 / core.bare / 配置。
"""

from . import 仓操作
from . import 开工账本 as 账本
from . import 反馈账本
from . import 清理执行, 清理选择

辅助表名 = 清理执行.辅助表名
预览上限 = 60


def _连库():
    """连账本并**在事务之外**先建 `清理待续` 表 —— 建表若混进删除事务会中途提交，固化半删态。"""
    连接 = 账本.连账本()
    清理执行.补待续表(连接)
    连接.commit()
    return 连接


# ── 续清（幂等，先于计划）──────────────────────────────────────────────────────

def 续清一次(连接, 开工号: str) -> tuple:
    """把本开工 `清理待续` 的剩余文件再删一遍 ⇒ `(已删路径表, 残留说明表)`；清完即删待续行。"""
    待续表 = 清理执行.读待续(连接, 开工号)
    if not 待续表:
        return [], []
    已删路径表, 残留表 = 清理执行.删文件(待续表)
    if 已删路径表:
        清理执行.清待续(连接, 开工号, 已删路径表)
        连接.commit()
    return 已删路径表, 残留表


# ── 计划 ──────────────────────────────────────────────────────────────────

def 算任务计划(连接, 仓根, 开工号, 开工记录) -> dict:
    """任务模式只读计划 ⇒ 计划 dict（可删 / 保留 / 阻断逐项列清）。**不写盘**。"""
    计划 = {"模式": "任务", "可删条目": [], "删来源": [], "全清来源": [], "混合来源": [],
          "报告待续": [], "快照候选": [], "保留报告": [], "作业行": [], "作业日志待续": [],
          "任务行数": {}, "保留条目数": 0, "可清开工行": True, "阻断": []}
    表错 = 清理选择.反馈表集核(连接)
    if 表错:
        计划["阻断"] += 表错
        return 计划
    来源表 = 反馈账本.列来源(连接, 开工号)
    可删, 删来源, 全清, 混合, 保留集 = 清理选择.切分来源(连接, 仓根, 来源表, set())
    计划["可删条目"] = 可删
    计划["删来源"] = 删来源
    计划["全清来源"] = 全清
    计划["混合来源"] = 混合
    计划["保留条目数"] = len(保留集)
    计划["可清开工行"] = not 保留集
    计划["阻断"] += 引用断裂阻断(连接, 可删)
    报告待续, 保留报告 = 清理选择.判报告件(全清, 清理选择.保留身份集(连接, set(删来源)))
    计划["报告待续"] = 报告待续
    计划["保留报告"] = 保留报告
    计划["快照候选"] = 清理执行.候选快照路径(连接, 删来源)
    作业行表, 日志待续, 作业阻断 = 清理选择.作业面(连接, 开工号, 开工记录["工作树"])
    计划["作业行"] = 作业行表
    计划["作业日志待续"] = 日志待续
    计划["阻断"] += 作业阻断
    for 表名 in 辅助表名:
        计划["任务行数"][表名] = 清理执行.数表行(连接, 表名, 开工号)
    return 计划


def 算条目计划(连接, 仓根, 条目号表) -> dict:
    """条目模式只读计划（**跨开工**）⇒ 计划 dict。**不动**任何开工 / 认领 / 改动行。"""
    计划 = {"模式": "条目", "可删条目": [], "删来源": [], "全清来源": [], "混合来源": [],
          "报告待续": [], "快照候选": [], "保留报告": [], "作业行": [], "作业日志待续": [],
          "任务行数": {}, "保留条目数": 0, "可清开工行": False, "阻断": []}
    表错 = 清理选择.反馈表集核(连接)
    if 表错:
        计划["阻断"] += 表错
        return 计划
    选定集 = set(条目号表)
    占位符 = ",".join("?" * len(条目号表))
    来源号表 = sorted({数据行[0] for 数据行 in 连接.execute(
        "select 来源号 from 反馈条目 where 条目号 in (%s)" % 占位符, 条目号表)})
    来源表 = [反馈账本.读来源(连接, 来源号) for 来源号 in 来源号表]
    可删, 删来源, 全清, 混合, 保留集 = 清理选择.切分来源(连接, 仓根, 来源表, 选定集)
    计划["可删条目"] = 可删
    计划["删来源"] = 删来源
    计划["全清来源"] = 全清
    计划["混合来源"] = 混合
    计划["保留条目数"] = len(保留集)
    计划["阻断"] += 引用断裂阻断(连接, 可删)
    报告待续, 保留报告 = 清理选择.判报告件(全清, 清理选择.保留身份集(连接, set(删来源)))
    计划["报告待续"] = 报告待续
    计划["保留报告"] = 保留报告
    计划["快照候选"] = 清理执行.候选快照路径(连接, 删来源)
    return 计划


def 引用断裂阻断(连接, 可删条目表) -> list:
    """保留条目**并入**的主条目将被删 ⇒ 引用会断 ⇒ 阻断（须人工切分，不自动跟随）。"""
    可删集 = set(可删条目表)
    if not 可删集:
        return []
    阻断 = []
    try:
        行表 = 连接.execute("select 条目号, 并入主条目 from 反馈条目 where 并入主条目 is not null")
    except Exception:
        return 阻断
    for 数据行 in 行表:
        if 数据行["条目号"] not in 可删集 and 数据行["并入主条目"] in 可删集:
            阻断.append("保留条目 %d 并入的主条目 %d 将被删 ⇒ 引用断裂，阻断（须人工切分）"
                    % (数据行["条目号"], 数据行["并入主条目"]))
    return 阻断


# ── 回执 ──────────────────────────────────────────────────────────────────

def 排预览(标题, 计划) -> str:
    """默认拒绝时的**可读精确预览**（目标逐条列出，一个字节没删）。"""
    行表 = ["**清理预览（默认拒绝，一个字节没删）** · %s · 模式 %s" % (标题, 计划["模式"]),
           "待删：反馈条目 %d · 反馈来源 %d · 报告件 %d · 作业行 %d · 作业日志 %d · 快照候选 %d"
           % (len(计划["可删条目"]), len(计划["删来源"]), len(计划["报告待续"]),
              len(计划["作业行"]), len(计划["作业日志待续"]), len(计划["快照候选"]))]
    非零任务行 = [("%s %d" % (表名, 表行数)) for 表名, 表行数 in 计划["任务行数"].items() if 表行数]
    if 计划["模式"] == "任务":
        行表.append("任务账本行：" + (" · ".join(非零任务行) if 非零任务行 else "（无）"))
        行表.append("开工行：" + ("**本体删除**（不留墓碑）" if 计划["可清开工行"]
                            else "**保留**（尚有 %d 条未解决条目承接）" % 计划["保留条目数"]))
        行表.append("工作树与支线：先过正式收口保护（已合主干 / 净树 / 无在途作业 / 无未释放消费者 / "
                  "台账未点名 / 无未蒸馏反馈）⇒ 过则清，不过则整批拒")
        行表.append("反向 `认领重叠` 孤儿行（引用方已清 / 已释放 ⇒ 无主，随本开工一并真删）：%d 条"
                  % len(计划["反向孤儿行"]))
    else:
        行表.append("条目模式：**不动**开工 / 认领 / 改动行（只删标定条目及其变空来源）")
    if 计划["可删条目"]:
        行表.append("待删条目（前 %d）：%s" % (min(len(计划["可删条目"]), 预览上限),
                                   " · ".join(str(号值) for 号值 in 计划["可删条目"][:预览上限])))
    if 计划["混合来源"]:
        行表.append("混合来源（只删已解决条目、留未解决事实）：")
        for 混合来源 in 计划["混合来源"]:
            留号 = " · ".join(str(号值) for 号值 in 混合来源["留条目"][:12])
            行表.append("    · 来源 %d：删 %d 条 · 留 %d 条（%s）"
                    % (混合来源["来源号"], 混合来源["删条数"],
                       len(混合来源["留条目"]), 留号))
    if 计划["报告待续"] or 计划["作业日志待续"]:
        行表.append("将删报告件 / 作业日志：")
        行表 += ["    · " + 待续项["路径"] for 待续项 in
              (计划["报告待续"] + 计划["作业日志待续"])[:预览上限]]
    if 计划["保留报告"]:
        行表.append("保留报告件（共享 / 越界 / 链接面 / 不存在）：")
        行表 += ["    · %s —— %s" % (路径, 因由) for 路径, 因由 in 计划["保留报告"][:预览上限]]
    行表.append("★ 要真删，重提并传 `确认` = 真。")
    return "\n".join(行表)


def 排回执(标题, 计划, 删除计数, 已删文件, 残留, 清树说明="") -> str:
    """成功回执：**只留最短删除计数**；有残留则明说「未完整清、已落待续」。"""
    非零删除计数 = [("%s %d" % (表名, 表行数)) for 表名, 表行数 in 删除计数.items() if 表行数]
    行表 = ["%s 生命周期清理：**已真删**（不另建历史库 / 不留整史备份）" % 标题,
           "库行：" + (" · ".join(非零删除计数) if 非零删除计数 else "（无）"),
           "文件已删 %d · 保留未解决事实 %d 条 · 保留报告件 %d 个"
           % (已删文件, 计划["保留条目数"], len(计划["保留报告"]))]
    if 清树说明:
        行表.append("工作树与支线：" + 清树说明)
    if 残留:
        行表.append("★ **未完整清**（库行已全清；下列文件删不掉，已落 `清理待续` 待下次续清）：")
        行表 += ["    · " + 残留项 for 残留项 in 残留]
    return "\n".join(行表)


# ── 编排 ──────────────────────────────────────────────────────────────────

def _确认项(参数表) -> tuple:
    if "作业名单" in 参数表:
        return None, ("`作业名单` 已撤（任意点名能删别的任务行 ⇒ 不可信）；归属由作业 `开工ID` / "
                 "工作树身份 / 关闭记录里的任务ID 三条真归属判定")
    确认 = 参数表.get("确认", False)
    if not isinstance(确认, bool):
        return None, "`确认` 要是逻辑型（默认假 = 默认拒绝，只回预览）"
    return 确认, ""


def _条目选择(参数表) -> tuple:
    选择表 = 参数表.get("条目选择")
    if 选择表 is None:
        return None, ""
    if not isinstance(选择表, list) or not 选择表:
        return None, "`条目选择` 要是非空数组（每项 {条目号, 审计所属, 承接任务}）"
    return 选择表, ""


def 跑清理(仓根, 开工号: str, 参数表: dict) -> tuple:
    """统一入口 ⇒ `(退出码, 文本)`。

    退出码：`0` = 已真删（或幂等无待清）；`1` = 拒（门禁 / 计划阻断 / 事务失败 / **有残留未完整清**）；
    `2` = 参数错或默认拒绝（只回预览）。生产调用由主策划在独立验收通过后进行。
    """
    确认, 确认错 = _确认项(参数表)
    if 确认错:
        return 2, 确认错
    选择表, 选择错 = _条目选择(参数表)
    if 选择错:
        return 2, 选择错
    if 选择表:
        return _跑条目模式(仓根, 选择表, 确认)
    return _跑任务模式(仓根, 开工号, 确认)


def _跑任务模式(仓根, 开工号: str, 确认) -> tuple:
    if not 反馈账本.是开工号(开工号):
        return 2, "清理已解决任务要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    连接 = _连库()
    try:
        已删路径表, 残留表 = 续清一次(连接, 开工号)
        开工记录 = 账本.读开工(连接, 开工号)
        if not 开工记录:
            # 开工行**已清**（本口不留墓碑）⇒ 续清仍要跑完（`清理待续` 按开工号键，活得比开工行久）。
            if 清理执行.读待续(连接, 开工号):
                return 1, _残留文本(开工号, 残留表)
            if 已删路径表:
                return 0, "%s 无此开工（开工行已清）；续清 %d 件待续文件" % (开工号, len(已删路径表))
            return 1, "没有这条开工：%s（本口**不留墓碑** ⇒ 已清理的开工查不到）" % 开工号
        if 清理执行.读待续(连接, 开工号):
            return 1, _残留文本(开工号, 残留表)
        阻断, 判据行, 孤儿引用 = 清理选择.核任务门禁(连接, 仓根, 开工号, 开工记录)
        if 阻断:
            return 1, "\n".join(["**清理拒**（任务级门禁不成立，一个字节没删）："] + 判据行)
        计划 = 算任务计划(连接, 仓根, 开工号, 开工记录)
        计划["反向孤儿行"] = 孤儿引用
        if 计划["阻断"]:
            return 1, "\n".join(["**清理拒**（计划阻断，一个字节没删）："] + 计划["阻断"])
        if not 确认:
            return 2, 排预览(开工号, 计划)
        # 工作树与支线：**先过正式收口保护再删**（同一份 `清树门禁.核清树条件`，门禁里已逐条核过）；
        # 清树失败 ⇒ 拒，库行一个字节没删（删了行却留孤儿树，查都没法查）。
        树码, 树文 = 仓操作.清工作树(仓根, 开工号)
        if 树码 != 0:
            return 1, "**清理拒**（工作树 / 支线没清掉，库行一个字节没删）：%s" % 树文.strip()[-300:]
        待续项表 = 计划["报告待续"] + 计划["作业日志待续"]
        try:
            连接.execute("begin immediate")
            删除计数 = 清理执行.删任务库行(连接, 计划, 开工号)
            删除计数["认领重叠孤儿"] = 清理执行.删认领重叠行(连接, 计划["反向孤儿行"])
            # 快照复核在**事务内、库行删之后**：此刻读到的「剩余 source 引用」才是删后的真实引用。
            待续项表 = 待续项表 + 清理执行.复核快照待续(连接, 计划["快照候选"])
            清理执行.记待续(连接, 开工号, 待续项表, 账本.时刻串())
            连接.commit()
        except Exception as 错误:
            连接.rollback()
            return 1, "**清理失败**（整批回滚，库行一个字节没删）：%r" % (错误,)
        已删路径表, 残留表 = _清待续文件(连接, 开工号, 待续项表)
        作业数, 作业残留 = 清理执行.删作业行([作业行["任务ID"] for 作业行 in 计划["作业行"]])
        残留表 += 作业残留
        if 残留表:
            return 1, 排回执(开工号, 计划, 删除计数, len(已删路径表), 残留表, 树文)
        return 0, 排回执(开工号, 计划, 删除计数, len(已删路径表), [], 树文)
    finally:
        连接.close()


def _跑条目模式(仓根, 选择表, 确认) -> tuple:
    连接 = _连库()
    try:
        错误表, 条目号表 = [], []
        for 序次, 选择项 in enumerate(选择表, 1):
            条目号, 条目错 = 清理选择.核实一条(连接, 仓根, 选择项, 序次)
            错误表 += 条目错
            if 条目号 is not None:
                条目号表.append(条目号)
        if len(set(条目号表)) != len(条目号表):
            错误表.append("批内重复选择同一条目")
        if 错误表:
            return 1, "\n".join(["**清理拒**（条目选择校验未过，一个字节没删）："] + 错误表)
        计划 = 算条目计划(连接, 仓根, 条目号表)
        if 计划["阻断"]:
            return 1, "\n".join(["**清理拒**（计划阻断，一个字节没删）："] + 计划["阻断"])
        标题 = "条目选择 %d 条（跨开工定向）" % len(条目号表)
        if not 确认:
            return 2, 排预览(标题, 计划)
        待续项表 = 计划["报告待续"]
        续清键 = "条目模式:" + ",".join(str(号值) for 号值 in sorted(条目号表))
        try:
            连接.execute("begin immediate")
            删除计数 = 清理执行.删条目库行(连接, 计划)
            待续项表 = 待续项表 + 清理执行.复核快照待续(连接, 计划["快照候选"])
            清理执行.记待续(连接, 续清键, 待续项表, 账本.时刻串())
            连接.commit()
        except Exception as 错误:
            连接.rollback()
            return 1, "**清理失败**（整批回滚，库行一个字节没删）：%r" % (错误,)
        已删路径表, 残留表 = _清待续文件(连接, 续清键, 待续项表)
        if 残留表:
            return 1, 排回执(标题, 计划, 删除计数, len(已删路径表), 残留表)
        return 0, 排回执(标题, 计划, 删除计数, len(已删路径表), [])
    finally:
        连接.close()


def _清待续文件(连接, 续清键: str, 待续项表) -> tuple:
    """删已落待续的文件 ⇒ `(已删路径表, 残留表)`；删掉的清待续行（清完即删，不留永久流水）。"""
    已删路径表, 残留表 = 清理执行.删文件(待续项表)
    if 已删路径表:
        清理执行.清待续(连接, 续清键, 已删路径表)
        连接.commit()
    return 已删路径表, 残留表


def _残留文本(开工号, 残留表) -> str:
    return "\n".join(["**未完整清**（%s 仍有待续文件残留，已保留在 `清理待续`）：" % 开工号]
                  + ["    · " + 残留项 for 残留项 in 残留表])
