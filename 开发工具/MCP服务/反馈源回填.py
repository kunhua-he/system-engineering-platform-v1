# -*- coding: utf-8 -*-
"""反馈源回填 —— 把清点源条目**经反馈口幂等登记**为来源（复用反馈六操作，不加新工具）。

**只做三件事**：① 由源条目构造 `提交反馈` 载荷（纯函数，可单测）；② 惰性调用反馈口
（`反馈提交.提交反馈`，整批事务）；③ 逐条回执（成功 / 待核，待核带反馈口原文）。

**source 键**：`来源标识 = 代理号` + `报告指纹 = 内容 sha` ⇒ resume 新报告是新版本行。
**零条目未读**：初版不自动提取问题 ⇒ 条目为空、读取状态按输出有无记 `未读` / 待核；
`已读` 只由主策划明确审读后置，回填**不**自置、不判词、不审完、不猜原文条目。
"""

import json
from pathlib import Path

读取_未读 = "未读"
幂等前缀 = "源回填-"


def 构造载荷(源条目: dict) -> dict:
    """一条源条目 ⇒ `提交反馈` 载荷（纯函数；`条目` 为空 —— v1 不自动提取问题）。"""
    标识 = str(源条目.get("来源标识") or "").strip()
    指纹 = 源条目.get("报告指纹")
    return {
        "幂等键": 幂等前缀 + 标识 + "-" + (str(指纹)[:16] if 指纹 else "无指纹"),
        "来源标识": 标识,
        "报告指纹": 指纹,
        "报告路径": 源条目.get("报告路径"),
        "读取状态": 源条目.get("读取状态") or 读取_未读,
        "条目": [],
    }


def 读快照(快照目录) -> list:
    """读快照的 `总表.json` ⇒ 源条目表（读不动 ⇒ 空表）。"""
    try:
        return json.loads((Path(快照目录) / "总表.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []


def 登记来源(仓根, 开工号: str, 源条目表: list) -> tuple:
    """逐条经反馈口登记来源 ⇒ `(退出码, 回执 JSON)`；反馈口不在本树 ⇒ 退出码 3（待合主干）。"""
    try:
        from .反馈提交 import 提交反馈
    except ImportError:
        return 3, json.dumps({"说明": "反馈口未在本树（反馈腿未合主干）⇒ 回填待接入；清点已落快照",
                         "条数": len(源条目表)}, ensure_ascii=False)
    成功 = 0
    待核 = []
    for 源条目 in 源条目表:
        载荷 = 构造载荷(源条目)
        退出码, 回执 = 提交反馈(仓根, 开工号, 载荷)
        if 退出码 == 0:
            成功 += 1
        else:
            待核.append({"来源标识": 载荷["来源标识"], "读取状态": 载荷["读取状态"],
                     "回执": 回执[:200]})
    return (0 if not 待核 else 2), json.dumps(
        {"登记成功": 成功, "待核": len(待核), "待核明细": 待核[:5]}, ensure_ascii=False)
