def 号被占(库件, 候选号) -> bool:
    """候选号在**真实**账本里是否已存在（`开工` 或 `反馈来源` 任一命中即占）—— 只读。"""
    if not Path(库件).is_file():
        return False
    连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
    try:
        表集 = {数据行[0] for 数据行 in 连接.execute(
            "select name from sqlite_master where type = 'table'")}
        if "开工" in 表集 and 连接.execute(
                "select count(*) from 开工 where 开工号 = ?", (候选号,)).fetchone()[0]:
            return True
        if "反馈来源" in 表集 and 连接.execute(
                "select count(*) from 反馈来源 where 开工号 = ?", (候选号,)).fetchone()[0]:
            return True
        return False
    finally:
        连接.close()


def 取唯一开工号(生产根) -> str:
    """挑一个真实账本**不占**的合法开工号（`v1-` 加六位数字）⇒ 号；撞满上限 ⇒ 抛 `无可用开工号`。

    只读预检（`开工` / `反馈来源` 双表），**不删任何历史行**；号格式遵既有形状，不用 UUID。
    """
    库件 = 生产库件(生产根)
    for 尝试序 in range(预检重试上限):
        候选号 = "v1-9%05d" % random.randrange(号段起点, 号段终点)
        if not 号被占(库件, 候选号):
            return 候选号
    raise 无可用开工号("只读预检 %d 次都撞上真实账本已有号 ⇒ 显式拒" % 预检重试上限)


def 圈定临时根(目录前缀) -> tuple:
    """把运行数据根**显式圈定**到新临时根 ⇒ `(临时根, 旧值)`；调用方负责 `还原根`。"""
    临时根 = Path(tempfile.mkdtemp(prefix=目录前缀))
    旧值 = os.environ.get(覆盖变量名)
    os.environ[覆盖变量名] = str(临时根)
    return 临时根, 旧值


def 还原根(旧值) -> None:
    """还原 `圈定临时根` 之前的覆盖值（原来没设 ⇒ 摘掉）。"""
    if 旧值 is None:
        os.environ.pop(覆盖变量名, None)
    else:
        os.environ[覆盖变量名] = 旧值


def 生产零写样本(生产根, 临时根, 夹具号) -> list:
    """**圈定前**解析出的真实根上只读探针：**夹具号**零行；并断言探针根 ≠ 临时根（防退化自查）。

    探针查的就是夹具**真正会写**的那个号（同号贯穿）⇒ 隔离一破必红，不存在「查另一个号」的假 0。
    """
    if Path(生产根).resolve() == Path(临时根).resolve():
        return [("生产零写探针：探针根 == 临时根（%s）⇒ 退化成临时自查，**不作数**" % 生产根, False)]
    库件 = 生产库件(生产根)
    if not 库件.is_file():
        return [("生产零写探针：真实根 %s 下无账本件（无对象可写）⇒ 零写（夹具号 %s）"
                 % (生产根, 夹具号), True)]
    连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
    try:
        表集 = {数据行[0] for 数据行 in 连接.execute(
            "select name from sqlite_master where type = 'table'")}
        反馈行数 = 连接.execute("select count(*) from 反馈来源 where 开工号 = ?",
                          (夹具号,)).fetchone()[0] if "反馈来源" in 表集 else 0
        开工行数 = 连接.execute("select count(*) from 开工 where 开工号 = ?",
                          (夹具号,)).fetchone()[0] if "开工" in 表集 else 0
    finally:
        连接.close()
    return [("生产零写探针：真实根 %s（≠ 临时根 %s）里夹具号 %s 反馈来源 %d 行 · 开工 %d 行"
             % (生产根, 临时根, 夹具号, 反馈行数, 开工行数), 反馈行数 == 0 and 开工行数 == 0)]


