# 候选号段（`v1-9xxxxx` 高位段）：与真实腿号（`v1-100xxx` 段）、固定样本号（`v1-900001..900005`）错开。
号段起点 = 50000
号段终点 = 100000
预检重试上限 = 8


class 无可用开工号(Exception):
    """只读预检连续撞上真实账本已有号 —— 显式拒（不静默复用历史号）。"""


def 生产库件(生产根):
    """真实根下的账本件路径（只拼路径，不建目录、不打开）。"""
