# -*- coding: utf-8 -*-
"""反馈判词 —— 主策划**批量判定**：债务 / 非问题 / 待核 + 关联唯一承接 + 显式语义合并。

三条硬纪律：
  · **整批事务**：一批里任一条不合规 ⇒ 整批零写，逐条列错；
  · **债务不许悬空**：判为债务必须关联**唯一现行 `未完成.json` 条目**或**正式开工**，未知即拒；
  · **语义合并只由主策划显式给**（`并入条目号`），**不按标题自动合并** —— 从条目行与来源全留，
    计次累加，主条目的判词经 `反馈账本.有效判词` 对从条目可回读。

**跨开工越界拒**：判定只认**本开工**（顶层 `开工ID` = 来源开工号）的条目 —— 主策划从
`查反馈` 取到原开工号后，按来源开工顶层ID**逐批**判定；本件不伪造身份、不做鉴权。
"""

from . import 反馈账本 as 账本
from . import 反馈关联
from .反馈提交 import 取文本


def 规范判定(连接, 仓根, 开工号: str, 判定项, 序次: int) -> tuple:
    """一条判定 ⇒ `(规范 dict, 错误表)`（**只判不写**）。"""
    if not isinstance(判定项, dict):
        return {}, ["判定 %d：要是对象" % 序次]
    错误表 = []
    条目号 = 判定项.get("条目号")
    条目行 = None
    if type(条目号) is not int:
        错误表.append("判定 %d：`条目号` 要是整数" % 序次)
    else:
        条目行 = 账本.读条目(连接, 条目号)
        if not 条目行:
            错误表.append("判定 %d：条目 %d 不存在" % (序次, 条目号))
        elif 条目行["开工号"] != 开工号:
            错误表.append("判定 %d：条目 %d 属开工 %s ⇒ **跨开工越界**"
                     "（判定按来源开工顶层ID逐批）" % (序次, 条目号, 条目行["开工号"]))
    判词 = 取文本(判定项.get("判词"))
    理由 = 取文本(判定项.get("理由"))
    if 判词 not in 账本.判词档表:
        错误表.append("判定 %d：`判词` 只认 %s" % (序次, " · ".join(账本.判词档表)))
    if not 理由:
        错误表.append("判定 %d：缺 `理由`" % 序次)
    关联种类 = 取文本(判定项.get("关联种类")) or None
    关联目标 = 取文本(判定项.get("关联目标")) or None
    if 关联种类 and 关联种类 not in 账本.关联档表:
        错误表.append("判定 %d：`关联种类` 只认 %s" % (序次, " · ".join(账本.关联档表)))
    elif 判词 == 账本.判词_债务 and (not 关联种类 or not 关联目标):
        错误表.append("判定 %d：债务必须关联**唯一现行台账条目**或**正式开工**"
                 "（缺 `关联种类` / `关联目标`）" % 序次)
    elif 关联种类 and 关联目标 and not 反馈关联.承接有效(连接, 仓根, 关联种类, 关联目标):
        错误表.append("判定 %d：关联**未知或已不存在**（%s %s）⇒ 拒"
                 % (序次, 关联种类, 关联目标))
    并入条目号 = 判定项.get("并入条目号")
    并入值 = None
    if 并入条目号 is not None:
        if type(并入条目号) is not int:
            错误表.append("判定 %d：`并入条目号` 要是整数" % 序次)
        elif 并入条目号 == 条目号:
            错误表.append("判定 %d：`并入条目号` 不能等于 `条目号`" % 序次)
        elif 条目行 is not None:
            从行 = 账本.读条目(连接, 并入条目号)
            if not 从行:
                错误表.append("判定 %d：并入目标 %d 不存在" % (序次, 并入条目号))
            elif 从行["开工号"] != 开工号:
                错误表.append("判定 %d：并入目标 %d 属开工 %s ⇒ 跨开工越界"
                         % (序次, 并入条目号, 从行["开工号"]))
            elif 从行["并入主条目"]:
                错误表.append("判定 %d：并入目标 %d 已并入条目 %d"
                         % (序次, 并入条目号, 从行["并入主条目"]))
            else:
                已被并数 = 连接.execute("select count(*) from 反馈条目 where 并入主条目 = ?",
                                 (并入条目号,)).fetchone()[0]
                if 已被并数:
                    错误表.append("判定 %d：并入目标 %d 本身已是主条目（有 %d 条并入它）"
                             % (序次, 并入条目号, 已被并数))
                else:
                    并入值 = 并入条目号
    return {"条目号": 条目号, "判词": 判词, "理由": 理由, "关联种类": 关联种类,
            "关联目标": 关联目标, "并入条目号": 并入值}, 错误表


def 找重号(号表: list) -> list:
    """批内出现多次的值 ⇒ 去重升序表（报「批内重复」用）。"""
    return sorted({号值 for 号值 in 号表 if 号表.count(号值) > 1},
                key=lambda 号值: str(号值))


def 批量判定(仓根, 开工号: str, 参数表: dict) -> tuple:
    """一批判词 ⇒ `(退出码, 短回执 JSON)`。**整批事务**：一条不合规整批零写。"""
    if not 账本.是开工号(开工号):
        return 2, "批量判定要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    判定表 = 参数表.get("判定表")
    if not isinstance(判定表, list) or not 判定表:
        return 2, "`判定表` 要是非空数组"
    连接 = 账本.连反馈库()
    try:
        if not 账本.开工在吗(连接, 开工号):
            return 1, "没有这条开工：%s ⇒ 先登记" % 开工号
        错误表 = []
        规范表 = []
        for 序次, 判定项 in enumerate(判定表, 1):
            规范, 条目错 = 规范判定(连接, 仓根, 开工号, 判定项, 序次)
            错误表 += 条目错
            规范表.append(规范)
        重主号 = 找重号([规范["条目号"] for 规范 in 规范表
                    if type(规范.get("条目号")) is int])
        if 重主号:
            错误表.append("批内重复判定同一条目：%s"
                     % " · ".join(str(号值) for 号值 in 重主号))
        重从号 = 找重号([规范["并入条目号"] for 规范 in 规范表 if 规范.get("并入条目号")])
        if 重从号:
            错误表.append("同一从条目被并多次：%s"
                     % " · ".join(str(号值) for 号值 in 重从号))
        if 错误表:
            return 2, "**整批零写**（批量判定校验未过）：\n  " + "\n  ".join(错误表)
        合并数 = 0
        主条目号表 = []
        for 规范 in 规范表:
            连接.execute(
                "insert into 反馈判词 (条目号, 判词, 理由, 关联种类, 关联目标, 关联状态, "
                "判定开工号, 判定时刻) values (?, ?, ?, ?, ?, ?, ?, ?) "
                "on conflict(条目号) do update set 判词 = excluded.判词, 理由 = excluded.理由, "
                "关联种类 = excluded.关联种类, 关联目标 = excluded.关联目标, "
                "关联状态 = excluded.关联状态, 判定开工号 = excluded.判定开工号, "
                "判定时刻 = excluded.判定时刻",
                (规范["条目号"], 规范["判词"], 规范["理由"], 规范["关联种类"], 规范["关联目标"],
                 账本.关联状态_现行, 开工号, 账本.时刻串()))
            主条目号表.append(规范["条目号"])
            if 规范["并入条目号"]:
                # **从条目不再自带判词**（删掉它自身的那一条）⇒ 判词唯一落在主条目上，
                # 从条目的 `有效判词` 走主条目回读；从条目行与来源**全留**（保留全部来源与计次）。
                连接.execute("update 反馈条目 set 并入主条目 = ? where 条目号 = ?",
                          (规范["条目号"], 规范["并入条目号"]))
                连接.execute("delete from 反馈判词 where 条目号 = ?", (规范["并入条目号"],))
                合并数 += 1
        连接.commit()
        未关闭债务数 = 连接.execute(
            "select count(*) from 反馈判词 join 反馈条目 on 反馈判词.条目号 = 反馈条目.条目号 "
            "where 反馈条目.开工号 = ? and 反馈判词.判词 = ? "
            "and not exists(select 1 from 反馈关闭 where 反馈关闭.条目号 = 反馈判词.条目号)",
            (开工号, 账本.判词_债务)).fetchone()[0]
        return 0, 账本.拼回执({"判定条数": len(主条目号表), "合并条数": 合并数,
                         "主条目号": 主条目号表, "未关闭债务数": 未关闭债务数})
    except Exception:
        连接.rollback()
        raise
    finally:
        连接.close()
