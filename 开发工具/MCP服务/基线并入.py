# -*- coding: utf-8 -*-
r"""基线并入 —— `v1_task 登记` 的可选 `基线`：把一条未合腿（或任意 ref）**并进新工作树**，
省掉手工 `git merge` 与二进制（`信息核心.db`）冲突处置。

**为什么要有它**（清理腿 v1-100560 实测）：一条腿要接着另一条腿的成果干，得手工 merge 再处置
`信息核心.db` 的二进制冲突（`--ours` + `落库`）—— 纯机械往返，且 `--ours` 的取向一错就悄悄丢登记。
本件把这件事收成登记的一步：

  · `基线` 能解析 ⇒ `git merge` 进新工作树（干净并入 ⇒ 直接完成）；
  · 冲突**全是二进制**（`*.db`）⇒ **不盲取一侧**：规则库（`开发工具/信息核心/信息核心.db`）
    走 `合主干源库重放` 的**按主键三方重放**（腿 == 基 ⇒ 无事；腿 == 主干 ⇒ 留主干；主干 == 基
    ⇒ 重放腿值；两侧各改且不同 ⇒ 判冲突、拒并入并留双方值交人裁）—— 保住命名 / 规则 / 条款 /
    号段两侧的正式增量；其余 `*.db` 取本支线侧；
  · 冲突含**源码件** ⇒ `git merge --abort` **清晰拒**（不留半合并现场，交人工判断）。

★ `落库` **不替代**三方重放：它只重抽**名字**（`命名登记` / `命名出现`），重不出 `规则` /
  `条款` / 号段这些**库是唯一存本**的正式内容 ⇒ 旧口径「`--ours` + `落库`」会静默丢被并入腿的正式增量。

**只动新工作树**（它就是这条腿的树）；不碰主干、不碰别的腿。
"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))     # 开发工具/

from .仓操作 import 跑命令                          # noqa: E402
from .仓状态 import git环境                          # noqa: E402
from .合主干有界跑 import 干净环境                    # noqa: E402  —— 二进制导出的子进程环境（剔继承 Git 定位）
from .合主干源库重放 import 合并三方库, 重放动作表     # noqa: E402  —— 规则库按主键三方重放（唯一一份）

# `表定义.库相对路径`（规则库唯一权威）—— 加它的目录到 sys.path 才能 import（同 `合主干源库重放.py` 法）。
_信息核心目录 = Path(__file__).resolve().parents[1] / "信息核心"
if str(_信息核心目录) not in sys.path:
    sys.path.insert(0, str(_信息核心目录))
import 表定义  # noqa: E402  —— 库相对路径 / 源表 的唯一权威

# 只收显式 ref 形状（不拿调用方的任意串拼命令）。
基线形状 = re.compile(r"^(腿/v1-[0-9]{6}|origin/腿/v1-[0-9]{6}|主干|origin/主干|[0-9a-f]{40})$")
# 可从源码 / 仓内命令重生的二进制：冲突时可取本支线侧，再由 `落库` 补回。
可重生后缀 = (".db",)
# 规则库相对路径（唯一权威 = `表定义.库相对路径`；本件不自持第二份）。
规则库相对路径 = 表定义.库相对路径
# git **短命令**的超时（rev-parse / diff / checkout / add / merge --abort —— 同步路；不扩）。
并入超时秒 = 5
# 二进制阶段 blob 导出的超时（同上）。
导出超时秒 = 5


def 可重生二进制(路径: str) -> bool:
    """`*.db` = 可从源码 / 仓内命令重生的二进制（登记住库、派生表可重抽）。"""
    return str(路径).endswith(可重生后缀)


def _跑git(工作树, 参数表: list) -> tuple:
    """在新工作树里跑一条 git 子命令 ⇒ `(退出码, 输出文本)`（剔继承的 Git 定位变量）。

    ★ 走 `只读缓存.跑只读命令`（实测 2026-10-08）：合并期同一棵树 + 同一组 ref 的只读问句
    被问很多次（每次 fork 一个 git ≈ 20 ms）⇒ 缓存按**仓内容指纹**失效（见 `只读缓存.py`：
    ref / 索引正文一变即未命中，失败不缓存，不跨树串）。非只读子命令一律现跑。
    """
    def 现跑(仓根, 参数表, 树根=None, 超时=并入超时秒):
        return 跑命令(["git", "-c", "core.quotePath=false"] + list(参数表),
                    cwd=str(树根 or 仓根), 超时秒数=超时, 子进程环境=git环境(树根 or 仓根))
    from .只读缓存 import 跑只读命令
    return 跑只读命令(现跑, 工作树, 参数表)


def _跑长事务git(工作树, 参数表: list) -> tuple:
    """跑一条**会触发提交钩子**的 git（`merge` / `commit`）⇒ `(退出码, 输出文本, 日志路径)`。

    ★ **不套 5 秒、也不套 10 秒总顶**（2026-10-08 · 实测）：`git commit` 会跑完整 pre-commit
    （闸 0 + 判据自测 + 全部案例 —— 几十秒到分钟级）⇒ 任何「预算级」上限都会把它掐成失败再
    `merge --abort`（红的不是判据而是预算）。走**既有正式长事务路线** `合主干有界跑.跑有界命令`
    （`超时秒数=None`：一趟就是它自身的长度 + 保留完整日志 + 终态退出码）—— **不新增第二个 runner、
    不绕钩子、不 `--no-verify`**。短命令仍走 `_跑git` 的同步窗（不扩）。
    """
    from .合主干有界跑 import 跑有界命令
    退出码, 输出文本, 日志路径 = 跑有界命令(
        ["git", "-c", "core.quotePath=false"] + list(参数表), 工作目录=str(工作树),
        超时秒数=None, 保留日志=True, 子进程环境=git环境(工作树))
    return 退出码, 输出文本, 日志路径


def _临时库(前缀: str) -> str:
    """建一个空临时件占位（导出阶段 blob 用）⇒ 路径。"""
    句柄, 路径 = tempfile.mkstemp(prefix=前缀, suffix=".db")
    os.close(句柄)
    return 路径


def _导出阶段(工作树, 阶段: int, 相对路径: str, 目标路径) -> int:
    """把冲突索引的阶段 blob（1=合并基 / 2=本支线 / 3=基线腿）导到 `目标路径` ⇒ 退出码。

    二进制不能经 `跑命令` 的文本回执（会毁字节）⇒ 直接 stdout 落文件句柄。阶段不在
    （如单侧新增）⇒ 建空件（三方各按缺行处理）。
    """
    with open(目标路径, "wb") as 句柄:
        回执 = subprocess.run(
            ["git", "-c", "core.quotePath=false", "cat-file", "blob", ":%d:%s" % (阶段, 相对路径)],
            cwd=str(工作树), stdout=句柄, stderr=subprocess.PIPE, env=干净环境(), timeout=导出超时秒)
    if 回执.returncode == 0:
        return 0
    Path(目标路径).write_bytes(b"")
    return 0


def _报冲突行(冲突表: list) -> list:
    """把三方冲突逐条报出（表 · 主键 · 腿值 · 主干值）⇒ 行表。"""
    行表 = ["★ 规则库三方重放判**冲突**（两侧都改同一主键且不同）⇒ 拒并入、留双方值交人裁："]
    for 冲突 in 冲突表[:20]:
        行表.append("  · %s 主键 %r\n      腿值   = %r\n      主干值 = %r"
                 % (冲突["表"], 冲突["键"], 冲突["腿值"], 冲突["主干值"]))
    if len(冲突表) > 20:
        行表.append("  …（共 %d 条）" % len(冲突表))
    return 行表


def _三方重放规则库(工作树, 相对路径: str) -> tuple:
    """规则库冲突 ⇒ 按主键三方重放（复用 `合主干源库重放`）⇒ `(退出码, 行表)`。

    索引阶段：① 合并基 · ② 本支线（= 新工作树分支）· ③ 基线腿；腿值重放进新工作树。
    冲突 ⇒ 非 0（调用方 `merge --abort`，不留半合并现场）。
    """
    基库 = _临时库("v1基线基库_")
    腿库 = _临时库("v1基线腿库_")
    主干库 = _临时库("v1基线主干库_")
    try:
        for 阶段, 目标 in ((1, 基库), (2, 主干库), (3, 腿库)):
            _导出阶段(工作树, 阶段, 相对路径, 目标)
        动作表, 冲突表, 跳过表 = 合并三方库(基库, 腿库, 主干库, 工作树)
        行表 = ["规则库按主键三方重放：动作 %d 条 · 冲突 %d 条 · 跳过 %d 条"
              % (len(动作表), len(冲突表), len(跳过表))]
        if 冲突表:
            return 1, 行表 + _报冲突行(冲突表)
        退出码, 重放行表 = 重放动作表(工作树, 动作表, 主干库)
        for 重放行 in 重放行表:
            行表.append("  " + 重放行)
        if 退出码 != 0:
            return 退出码, 行表
        if 跳过表:
            行表.append("  （跳过 %d 条：源件权威，建库 重抽）" % len(跳过表))
        return 0, 行表
    finally:
        for 临时 in (基库, 腿库, 主干库):
            try:
                Path(临时).unlink()
            except OSError:
                pass


def 并入基线(工作树, 基线: str) -> tuple:
    """把 `基线` 并进 `工作树` ⇒ `(退出码, 输出文本)`；`(0, "")` = 没给基线（不需并入）。"""
    基线 = str(基线 or "").strip()
    if not 基线:
        return 0, ""
    if not 基线形状.fullmatch(基线):
        return 2, ("`基线` 形状不认：只收 `腿/v1-加六位数字` / `origin/腿/…` / `主干` / `origin/主干` / "
                 "40 位提交号（收到 %r）" % 基线)
    退出码, 输出文本 = _跑git(工作树, ["rev-parse", "--verify", "--quiet", 基线 + "^{commit}"])
    if 退出码 != 0 or not 输出文本.strip():
        return 2, "`基线` 不存在（本仓解析不出 `%s`）⇒ 拒绝并入（不留半合并现场）" % 基线
    # `merge --no-edit` 可能**自动造提交** ⇒ 会跑完整 pre-commit ⇒ 走长事务路线（不套预算总顶）。
    退出码, 输出文本, 日志路径 = _跑长事务git(工作树, ["merge", "--no-edit", 基线])
    if 退出码 == 0:
        return 0, "基线 %s 已并入新工作树（干净并入）" % 基线
    退出码, 冲突文本 = _跑git(工作树, ["diff", "--name-only", "--diff-filter=U"])
    冲突表 = [源码行.strip() for 源码行 in 冲突文本.splitlines() if 源码行.strip()]
    if not 冲突表:
        _跑git(工作树, ["merge", "--abort"])
        return 2, "基线 %s 并入失败（非冲突）：%s" % (基线, 输出文本.strip()[-300:])
    源码冲突 = [路径 for 路径 in 冲突表 if not 可重生二进制(路径)]
    if 源码冲突:
        _跑git(工作树, ["merge", "--abort"])
        return 2, ("基线 %s **不可自动并入**：源码件冲突（%s）—— 已 `git merge --abort`，"
                 "不留半合并现场。\n  请人工比较后再定（或走 `v1_task 接管集成`）。"
                 % (基线, " · ".join(源码冲突)))
    # 全二进制冲突 ⇒ **不盲取一侧**：规则库三方重放（保两侧正式增量），其余 .db 取本支线侧。
    行表 = []
    if 规则库相对路径 in 冲突表:
        退出码, 重放行表 = _三方重放规则库(工作树, 规则库相对路径)
        行表 += 重放行表
        if 退出码 != 0:
            _跑git(工作树, ["merge", "--abort"])
            return 退出码, "基线 %s **不可自动并入**：\n%s" % (基线, "\n".join(行表))
    其余二进制 = [路径 for 路径 in 冲突表 if 路径 != 规则库相对路径]
    if 其余二进制:
        退出码, 输出文本 = _跑git(工作树, ["checkout", "--ours", "--"] + 其余二进制)
        if 退出码 != 0:
            _跑git(工作树, ["merge", "--abort"])
            return 2, "取本支线侧的二进制失败：%s" % 输出文本.strip()[-300:]
        行表.append("非规则库二进制取本支线侧：%s" % " · ".join(其余二进制))
    _跑git(工作树, ["add", "--"] + 冲突表)
    退出码, 输出文本, 日志路径 = _跑长事务git(工作树, ["commit", "--no-edit"])
    if 退出码 != 0:
        _跑git(工作树, ["merge", "--abort"])
        return 2, "完成合并提交失败：%s\n（完整日志：%s）" % (输出文本.strip()[-300:], 日志路径)
    行表.append("基线 %s 已并入新工作树（规则库按主键三方重放 · 其余二进制取本支线侧）" % 基线)
    行表.append("★ 库变了 ⇒ 记 `v1_task 源件记账`（源件 = %s）" % 规则库相对路径)
    return 0, "\n".join(行表)
