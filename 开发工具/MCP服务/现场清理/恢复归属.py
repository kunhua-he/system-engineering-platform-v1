"""恢复归属 —— 清理报告里**四类东西的恢复责任**（按落点机器判定，不靠文案）。

**四类**（判定口径只有一份，住 `判恢复归属`；报告只取它的输出，不另抄一份）：
  · **可重建缓存** —— 丢了由本机命令重建即得，代价只有时间；
  · **正式制品** —— 必须留存，丢了要从源码与工具链重出并重核指纹；
  · **规则源** —— 源件，丢了等于丢规则，重建无从谈起；
  · **业务状态** —— 不可重建，真删即真丢。

**判定口径**（按**落点**判，不按文件名猜）：
  ① 落在运行数据根的 `缓存` 子目录之下，或后缀是字节码 ⇒ 可重建缓存；
  ② 落在 `构建装配/制品产物` 之下，或后缀是可装载库 ⇒ 正式制品；
  ③ 落在 `开发工具/信息核心` 之下（规则库与台账的家）⇒ 规则源；
  ④ 其余 ⇒ 业务状态；
  ⑤ 读不出 / 空 / 非绝对路径 ⇒ **业务状态**（fail-closed：不明即按最不可重建的一类算，
     宁可多报责任，不许把不可重建的东西说成可丢）。

**责任三问**（每类必答，缺一项即不算写全）：谁负责恢复 · 怎么恢复 · 丢了会怎样。

**为什么单开一件**：四类口径与责任文案是**唯一事实面**，`任务清理.py` 只做编排与回执；
件头引用的落点一律写 `路径::符号名`，不写行号（判据 ⑮）。
"""

