# 落点口径（全是**相对仓根或运行数据根**的片段，不写绝对路径）。
制品产物段 = ("构建装配", "制品产物")
规则源段 = ("开发工具", "信息核心")
可装载库后缀 = (".dylib", ".so", ".dll", ".a")
可重建后缀 = (".pyc", ".pyo")


def 缓存子目录路径():
    """运行数据根的 `缓存` 子目录（解析不出 ⇒ `None`，由调用方按 fail-closed 处置）。"""
    try:
        from 运行数据根 import 子目录路径, 解析当前环境
        return 子目录路径(解析当前环境(), "缓存")
    except Exception:
        return None


def 路径段表(路径) -> tuple:
    """路径 ⇒ 段元组（读不出 / 空 ⇒ 空元组）。只 `normpath`，**不 `resolve`**（同清理执行的口径）。"""
    原文 = str(路径 or "").strip()
    if not 原文:
        return ()
    try:
        return Path(os.path.normpath(原文)).parts
    except (TypeError, ValueError):
        return ()


def 判恢复归属(路径) -> str:
    """一条待删落点 ⇒ 四类之一。**读不出即回「业务状态」**（fail-closed，见件头 ⑤）。"""
    原文 = str(路径 or "").strip()
    路径段 = 路径段表(路径)
    if not 路径段 or not os.path.isabs(原文):
        return "业务状态"
    后缀名 = os.path.splitext(路径段[-1])[1].lower()
    缓存根 = 缓存子目录路径()
    if 缓存根 is not None:
        缓存路径段 = 路径段表(缓存根)
        if 缓存路径段 and 路径段[:len(缓存路径段)] == 缓存路径段:
            return "可重建缓存"
    if 后缀名 in 可重建后缀:
        return "可重建缓存"
    相邻路径段 = tuple(zip(路径段, 路径段[1:]))
    if 后缀名 in 可装载库后缀 or 制品产物段 in 相邻路径段:
        return "正式制品"
    if 规则源段 in 相邻路径段:
        return "规则源"
    return "业务状态"


def 归属清单(待续项表) -> list:
    """待删落点表 ⇒ 逐件归属 `[{类, 路径, 种类}]`（按四类序，同类内按路径序）。"""
    行表 = []
    for 待续项 in 待续项表 or []:
        if not isinstance(待续项, dict):
            continue
        路径 = str(待续项.get("路径") or "")
        行表.append({"类": 判恢复归属(路径), "路径": 路径,
                   "种类": str(待续项.get("种类") or "")})
    return sorted(行表, key=lambda 归属条目: (四类归属.index(归属条目["类"]), 归属条目["路径"]))


def 缺项清单() -> list:
    """责任表里没写全的类与项 ⇒ 行表（空 = 四类三问都写全）。机器可判，不靠人看文案。"""
    缺项 = []
    for 类名 in 四类归属:
        责任三项 = 责任表.get(类名)
        if not isinstance(责任三项, dict):
            缺项.append("%s：整类责任缺失" % 类名)
            continue
        for 问项名 in ("谁负责恢复", "怎么恢复", "丢了会怎样"):
            if not str(责任三项.get(问项名) or "").strip():
                缺项.append("%s：缺「%s」" % (类名, 问项名))
    return 缺项


def 责任行表(归属行) -> list:
    """归属清单 ⇒ 报告行（**责任三问每类必列**，逐件也点名所属类）。空表 ⇒ 一段「无待删」行。"""
    行表 = ["★ 恢复责任（四类 · 机器判定 `恢复归属.py::判恢复归属`）："]
    for 类名 in 四类归属:
        责任三项 = 责任表.get(类名) or {}
        命中数 = sum(1 for 归属条目 in 归属行 if 归属条目.get("类") == 类名)
        行表.append("    · %s %d 件 —— 谁负责恢复：%s；怎么恢复：%s；丢了会怎样：%s"
                 % (类名, 命中数, 责任三项.get("谁负责恢复") or "（缺）",
                    责任三项.get("怎么恢复") or "（缺）", 责任三项.get("丢了会怎样") or "（缺）"))
    if not 归属行:
        行表.append("    本次无待删落点（四类计数全 0）。")
        return 行表
    行表.append("    待删逐件归属：")
    for 归属条目 in 归属行:
        行表.append("      · %s  %s（%s）" % (归属条目.get("类"), 归属条目.get("路径"),
                                     归属条目.get("种类") or "未标种类"))
    return 行表


