# -*- coding: utf-8 -*-
"""反馈读数样本 —— `查反馈` 未蒸馏**分页 / 分类计数** 与 `列反馈来源` 的正反样本。

**为什么单开一件**（判据 ⑲ 单件 ≤400 行）：`反馈样本.py` 已 330+ 行；本组是**另一条关注点**
（读数面：分页边界 · 分类计数与全量一致 · 截断不误导 · 空集 · 按档枚举来源），故单开，
由 `反馈样本.跑样本` 末尾加一行调用（⇒ 随 `反馈长样本` 进提交放行路）。

**隔离**：夹具号 `读数开工号` / `空集开工号` 独立于另三件样本号；运行数据根由外层
`反馈样本.跑全套` 覆盖到临时根 ⇒ 不碰真开工账本；`仓根` 只读。
本件**不带 `__main__` 块**（带了就被判据 ⑲ 当入口件）。
"""

from .反馈样本工具 import 反馈开工号, 读回执, 造开工

读数开工号 = "v1-900006"
空集开工号 = "v1-900007"


def 样本列表(仓根, 临时根) -> list:
    """未蒸馏分页 / 分类计数 / 列反馈来源 的正反样本 ⇒ 样本表 `[(说明, 通过)]`。"""
    from . import 反馈关联
    from . import 反馈账本 as 账本
    from .反馈判词 import 批量判定
    from .反馈审完 import 登记报告审完
    from .反馈提交 import 补证, 提交反馈
    from .反馈来源查询 import 列反馈来源
    from .反馈查询 import 查反馈

    造开工(临时根, (读数开工号, 空集开工号))
    样本表 = []

    def 记样本(说明, 通过):
        样本表.append((说明, bool(通过)))

    def 提交一条(序号, 标识, 指纹, 读取状态, 条目表):
        """提交一份来源 ⇒ `(退出码, 来源号, 条目号表)`（幂等键按序号固定）。"""
        退出码, 回执文本 = 提交反馈(仓根, 读数开工号, {
            "幂等键": "读数-%d" % 序号, "来源标识": 标识, "报告指纹": 指纹,
            "读取状态": 读取状态, "条目": 条目表})
        读数 = 读回执(回执文本)
        return 退出码, 读数.get("来源号"), 读数.get("条目号") or []

    def 查未蒸馏(参数表):
        """带 `读数开工号` 查一次 ⇒ `(退出码, 读数)`。"""
        退出码, 回执文本 = 查反馈(仓根, "", dict(参数表, 开工号=读数开工号))
        return 退出码, 读回执(回执文本)

    三现象 = [{"现象": "读数样本发现 %d" % 序号, "证据": "读数 %d" % 序号,
             "未测": "落点与触发未记录"} for 序号 in (1, 2, 3)]
    未审完码, _, _ = 提交一条(1, "读数/未审完.md", "a1" * 32, "未读", 三现象)
    已审完码, 已审完号, 已审完条目 = 提交一条(
        2, "读数/已审完.md", "b2" * 32, "已读",
        [{"现象": "读数样本已审完", "证据": "读数", "未测": "落点与触发未记录"}])
    待核码, 待核号, 待核条目 = 提交一条(
        3, "读数/待核.md", "c3" * 32, "已读",
        [{"现象": "读数样本待核", "证据": "读数", "未测": "落点与触发未记录"}])
    缺件码, 缺件号, _ = 提交一条(4, "读数/缺件.md", "", "缺件待核", [])
    空报告码, _, _ = 提交一条(5, "读数/空报告.md", 账本.空字节报告指纹, "空报告待核", [])
    记样本("读数夹具：五档来源提交（未读 %s · 已读 %s/%s · 缺件 %s · 空报告 %s）"
       % (未审完码, 已审完码, 待核码, 缺件码, 空报告码),
      未审完码 == 已审完码 == 待核码 == 缺件码 == 空报告码 == 0)
    提交码表 = (未审完码, 已审完码, 待核码, 缺件码, 空报告码)
    if any(提交码 != 0 for 提交码 in 提交码表) or not (已审完条目 and 待核条目):
        return 样本表 + [("读数夹具未建成（提交码 %s · 条目号 %s/%s）⇒ 后续读数样本未判（不是通过）"
                    % (提交码表, 已审完条目, 待核条目), False)]
    批量判定(仓根, 读数开工号, {"判定表": [
        {"条目号": 已审完条目[0], "判词": "非问题", "理由": "读数样本非问题"},
        {"条目号": 待核条目[0], "判词": "待核", "理由": "读数样本待核"}]})
    补证(仓根, 读数开工号, {"补证表": [{"条目号": 待核条目[0], "证据": "补证：读数样本"}]})
    登记报告审完(仓根, 读数开工号, {"审完表": [
        {"来源号": 已审完号, "提取条数": 1, "判词条数": 1},
        {"来源号": 待核号, "提取条数": 1, "判词条数": 1}]})

    连接 = 账本.连反馈库()
    try:
        明细表 = 反馈关联.未蒸馏明细(连接, 仓根, 读数开工号)
        行表 = 反馈关联.未蒸馏反馈集(连接, 仓根, 读数开工号)
        分类计数 = 反馈关联.未蒸馏分类计数(明细表)
    finally:
        连接.close()
    记样本("未蒸馏明细：共 %d 条（未审完来源 %d · 未判词条目 %d · 债务无承接 %d · 待核须保留 %d）"
       % (len(明细表), 分类计数["未审完来源"], 分类计数["未判词条目"],
          分类计数["债务无有效承接"], 分类计数["待核须保留"]),
      len(明细表) == 7 and 分类计数 == {"未审完来源": 3, "未判词条目": 3,
                                "债务无有效承接": 0, "待核须保留": 1})
    记样本("未蒸馏反馈集（旧字符串口）逐行取 `正文` ⇒ 与明细同长同序（%d / %d）"
       % (len(行表), len(明细表)),
      len(行表) == len(明细表) and 行表 == [明细行["正文"] for 明细行 in 明细表])

    退出码, 默认读数 = 查未蒸馏({})
    记样本("查反馈 未蒸馏默认页：条数 %s · 页码 %s · 每页 %s · 本页 %s · 下页 %s · 截断 %s"
       % (默认读数.get("未蒸馏条数"), 默认读数.get("未蒸馏页码"), 默认读数.get("未蒸馏每页"),
          默认读数.get("未蒸馏本页条数"), 默认读数.get("未蒸馏下页"), 默认读数.get("未蒸馏截断")),
      退出码 == 0 and 默认读数.get("未蒸馏条数") == 7 and 默认读数.get("未蒸馏页码") == 1
      and 默认读数.get("未蒸馏每页") == 20 and 默认读数.get("未蒸馏本页条数") == 7
      and 默认读数.get("未蒸馏下页") is None and 默认读数.get("未蒸馏截断") is False)
    记样本("查反馈 未蒸馏分类计数（默认页）与全量一致：%s" % (默认读数.get("未蒸馏分类计数"),),
      默认读数.get("未蒸馏分类计数") == {"未审完来源": 3, "未判词条目": 3,
                                "债务无有效承接": 0, "待核须保留": 1})
    默认行 = 默认读数.get("未蒸馏") or []
    记样本("查反馈 `未蒸馏` 仍是本页字符串行表（旧形状保留 · %d 行 · 首行起头 %r）"
       % (len(默认行), 默认行[0][:6] if 默认行 else ""),
      isinstance(默认读数.get("未蒸馏"), list) and len(默认行) == 7
      and 默认行[0].startswith("未审完来源"))

    退出码, 页一 = 查未蒸馏({"未蒸馏每页": 2})
    记样本("查反馈 `未蒸馏每页` = 2 ⇒ 本页 2 条 · 下页 2 · 截断真（旧口硬截 20 条且无此字段）",
      退出码 == 0 and 页一.get("未蒸馏条数") == 7 and 页一.get("未蒸馏本页条数") == 2
      and 页一.get("未蒸馏下页") == 2 and 页一.get("未蒸馏截断") is True
      and len(页一.get("未蒸馏") or []) == 2)
    退出码, 页二 = 查未蒸馏({"未蒸馏每页": 2, "未蒸馏页码": 2})
    记样本("查反馈 未蒸馏第 2 页（每页 2）⇒ 本页 2 条 · 下页 3 · 与第 1 页不重",
      退出码 == 0 and 页二.get("未蒸馏本页条数") == 2 and 页二.get("未蒸馏下页") == 3
      and 页二.get("未蒸馏") != 页一.get("未蒸馏"))
    退出码, 页四 = 查未蒸馏({"未蒸馏每页": 2, "未蒸馏页码": 4})
    记样本("查反馈 未蒸馏末页（第 4 页 / 每页 2）⇒ 本页 1 条 · 下页空 · 截断真（本页非全量）",
      退出码 == 0 and 页四.get("未蒸馏本页条数") == 1
      and 页四.get("未蒸馏下页") is None and 页四.get("未蒸馏截断") is True)
    合并行表 = []
    for 页码 in (1, 2, 3, 4):
        _, 页读数 = 查未蒸馏({"未蒸馏每页": 2, "未蒸馏页码": 页码})
        合并行表 += 页读数.get("未蒸馏") or []
    记样本("查反馈 未蒸馏四页拼起来 == 全量（%d / %d，逐行同序）" % (len(合并行表), len(行表)),
      合并行表 == 行表)
    退出码, _回执文本 = 查反馈(仓根, "", {"开工号": 读数开工号, "未蒸馏页码": 0})
    记样本("查反馈 `未蒸馏页码` = 0 ⇒ 拒（码 %s）" % 退出码, 退出码 == 2)
    退出码, _回执文本 = 查反馈(仓根, "", {"开工号": 读数开工号, "未蒸馏每页": 201})
    记样本("查反馈 `未蒸馏每页` = 201 ⇒ 拒（码 %s）" % 退出码, 退出码 == 2)

    空码, 回执文本 = 查反馈(仓根, "", {"开工号": 空集开工号})
    空读数 = 读回执(回执文本)
    记样本("查反馈 空集（无来源的开工）⇒ 未蒸馏条数 0 · 未蒸馏 [] · 分类计数四档全 0 · 下页空",
      空码 == 0 and 空读数.get("未蒸馏条数") == 0 and 空读数.get("未蒸馏") == []
      and 空读数.get("未蒸馏下页") is None and 空读数.get("未蒸馏截断") is False
      and len(空读数.get("未蒸馏分类计数") or {}) == 4
      and set((空读数.get("未蒸馏分类计数") or {}).values()) == {0})

    退出码, 回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号})
    列读数 = 读回执(回执文本)
    记样本("列反馈来源 全量：总数 %s · 本页 %s · 读取计数 %s · 审完计数 %s"
       % (列读数.get("总数"), 列读数.get("本页条数"),
          列读数.get("读取状态计数"), 列读数.get("审完状态计数")),
      退出码 == 0 and 列读数.get("总数") == 5 and 列读数.get("本页条数") == 5
      and 列读数.get("读取状态计数") == {"未读": 1, "已读": 2, "空报告待核": 1, "缺件待核": 1}
      and 列读数.get("审完状态计数") == {"未审完": 3, "已审完": 2, "显式待核": 0})
    退出码, 回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号, "读取状态": "已读"})
    列读数 = 读回执(回执文本)
    记样本("列反馈来源 按 `读取状态` = 已读 筛 ⇒ 总数 2（分布计数仍按全开工口径）",
      退出码 == 0 and 列读数.get("总数") == 2
      and (列读数.get("读取状态计数") or {}).get("已读") == 2)
    退出码, 回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号, "审完状态": "已审完"})
    列读数 = 读回执(回执文本)
    记样本("列反馈来源 按 `审完状态` = 已审完 筛 ⇒ 总数 2", 退出码 == 0 and 列读数.get("总数") == 2)
    退出码, 回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号, "审完状态": "未审完"})
    列读数 = 读回执(回执文本)
    记样本("列反馈来源 按 `审完状态` = 未审完 筛 ⇒ 总数 3（含显式待核那档）",
      退出码 == 0 and 列读数.get("总数") == 3)
    退出码, 回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号, "每页": 2})
    列页一 = 读回执(回执文本)
    退出码, 回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号, "每页": 2, "页码": 3})
    列页三 = 读回执(回执文本)
    记样本("列反馈来源 分页：每页 2 ⇒ 第 1 页 2 条 / 下页 2；第 3 页 1 条 / 下页空",
      列页一.get("本页条数") == 2 and 列页一.get("下页") == 2
      and 列页三.get("本页条数") == 1 and 列页三.get("下页") is None)

    登记报告审完(仓根, 读数开工号, {"来源号": 缺件号, "提取条数": 0, "判词条数": 0,
                          "待核理由": "原件缺失：读数样本"})
    退出码, 回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号, "审完状态": "显式待核"})
    显式读数 = 读回执(回执文本)
    显式来源 = (显式读数.get("来源") or [{}])[0]
    记样本("列反馈来源 按 `审完状态` = 显式待核 筛 ⇒ 总数 1（`待核理由` 非空且未审完 · %r）"
       % (显式来源.get("审完状态"),),
      退出码 == 0 and 显式读数.get("总数") == 1
      and 显式来源.get("审完状态") == "显式待核" and bool(显式来源.get("待核理由")))
    退出码, 回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号})
    列读数 = 读回执(回执文本)
    记样本("显式待核后 审完状态计数：未审完 3（含显式待核 1）· 已审完 2 · 显式待核 1",
      列读数.get("审完状态计数") == {"未审完": 3, "已审完": 2, "显式待核": 1})
    审完计数 = 列读数.get("审完状态计数") or {}
    记样本("列反馈来源 计数与筛选同口径：未审完 %s + 已审完 %s == 总数 %s（显式待核 %s 是子集不参与）"
       % (审完计数.get("未审完"), 审完计数.get("已审完"), 列读数.get("总数"),
          审完计数.get("显式待核")),
      审完计数.get("未审完") + 审完计数.get("已审完") == 列读数.get("总数"))

    退出码, _回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号, "读取状态": "随便"})
    记样本("列反馈来源 `读取状态` 非法 ⇒ 拒（码 %s）" % 退出码, 退出码 == 2)
    退出码, _回执文本 = 列反馈来源(仓根, "", {"开工号": 读数开工号, "审完状态": "随便"})
    记样本("列反馈来源 `审完状态` 非法 ⇒ 拒（码 %s）" % 退出码, 退出码 == 2)
    退出码, _回执文本 = 列反馈来源(仓根, "", {"开工号": "v1-1"})
    记样本("列反馈来源 `开工号` 形状不对 ⇒ 拒（码 %s）" % 退出码, 退出码 == 2)
    退出码, _回执文本 = 列反馈来源(仓根, "", {})
    记样本("列反馈来源 缺 `开工号`（无顶层开工ID）⇒ 拒（码 %s）" % 退出码, 退出码 == 2)
    退出码, 回执文本 = 列反馈来源(仓根, 空集开工号, {})
    空列读数 = 读回执(回执文本)
    记样本("列反馈来源 顶层 `开工ID` 兜底：空集开工 ⇒ 总数 0 · 来源 [] · 两分布全 0",
      退出码 == 0 and 空列读数.get("总数") == 0 and 空列读数.get("来源") == []
      and len(空列读数.get("读取状态计数") or {}) == 4
      and len(空列读数.get("审完状态计数") or {}) == 3
      and set((空列读数.get("读取状态计数") or {}).values()) == {0}
      and set((空列读数.get("审完状态计数") or {}).values()) == {0})
    return 样本表


def 补证来源样本(仓根) -> list:
    """`查反馈` 的**补证读数**与**来源元数据**正反样本（有界 · 可继续读取 · 默认计数不变）⇒ 样本表。

    从 `反馈样本.py` 分出（该件行数已顶判据 ⑲ 的 400 上限）；本组同属**读数面** ⇒ 落本件。
    """
    from .反馈提交 import 补证
    from .反馈查询 import 查反馈, 补证默认条数, 补证条数上限
    样本表 = []

    def 记样本(说明, 通过):
        样本表.append((说明, bool(通过)))

    退出码, _回执文本 = 补证(仓根, 反馈开工号, {"补证表": [
        {"条目号": 2, "证据": "多补证 %02d" % 序次, "来源": "复现日志 %02d" % 序次}
        for 序次 in range(1, 13)]})
    记样本("补证 12 条（条目 2 · 带 `来源` 与补证时刻）⇒ 码 %s" % 退出码, 退出码 == 0)

    退出码, 查文本 = 查反馈(仓根, "", {"开工号": 反馈开工号})
    短条 = (读回执(查文本).get("条目") or [{}])[0]
    记样本("未展开 ⇒ 保持短（不回 `证据` / 不回 `补证`）：首条键 %s"
       % "·".join(sorted(短条)), 退出码 == 0 and "证据" not in 短条 and "补证" not in 短条)

    退出码, 查文本 = 查反馈(仓根, "", {"开工号": 反馈开工号, "条目号": 2, "展开": True})
    全条 = (读回执(查文本).get("条目") or [{}])[0]
