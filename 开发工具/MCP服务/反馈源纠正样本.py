def 圈定临时根(目录前缀) -> tuple:
    """把运行数据根显式圈定到新临时根 ⇒ `(临时根, 旧值)`（调用方负责还原）。"""
    临时根 = Path(tempfile.mkdtemp(prefix=目录前缀))
    旧值 = os.environ.get(覆盖变量名)
    os.environ[覆盖变量名] = str(临时根)
    return 临时根, 旧值


def 还原根(旧值) -> None:
    """还原 `圈定临时根` 之前的覆盖值（原来没设 ⇒ 摘掉）。"""
    if 旧值 is None:
        os.environ.pop(覆盖变量名, None)
    else:
        os.environ[覆盖变量名] = 旧值


def 写真件(代理目录, 正文) -> str:
    """在代理目录写 `output.txt` ⇒ 该件内容的 sha256（真件内容身份）。"""
    代理目录.mkdir(parents=True, exist_ok=True)
    输出件 = 代理目录 / "output.txt"
    输出件.write_text(正文, encoding="utf-8")
    return hashlib.sha256(正文.encode("utf-8")).hexdigest()


def 提交一条(假仓, 开工号, 幂等后缀, 代理号, 报告指纹, 报告路径, 条目表=None) -> dict:
    """经真口 `提交反馈` 落一条来源 ⇒ 回执读数。

    `读取状态` 取 **缺件待核**（不是 `已读`）：夹具给的 `报告路径` 是**故意写错**的路径
    （会话目录 / 目录名 / 用户名笔误），盘上**不存在** —— 提交口对 `已读` 的非空路径要求
    **可读且内容 sha 相符**；写错的路径只能如实报「缺件待核」（内容身份仍由 `报告指纹`
    记着，正是纠正口要修的那种状态）。
    """
    退出码, 回执 = 反馈提交.提交反馈(假仓, 开工号, {
        "幂等键": "纠正样本-%s-%s" % (开工号, 幂等后缀),
        "来源标识": 代理号, "报告指纹": 报告指纹, "报告路径": 报告路径,
        "读取状态": "缺件待核", "条目": 条目表 or []})
    读数 = json.loads(回执) if 回执.strip().startswith("{") else {}
    return {"退出码": 退出码, "读数": 读数}


def 读来源(来源号) -> dict:
    """只读取一条来源行（独立连接，用完即关）。"""
    连接 = 账本.连反馈库()
    try:
        return 账本.读来源(连接, 来源号) or {}
    finally:
        连接.close()


def 读条目(条目号) -> dict:
    """只读取一条条目行（独立连接，用完即关）。"""
    连接 = 账本.连反馈库()
    try:
        return 账本.读条目(连接, 条目号) or {}
    finally:
        连接.close()


