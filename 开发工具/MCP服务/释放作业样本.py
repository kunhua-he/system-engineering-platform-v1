# -*- coding: utf-8 -*-
"""释放作业样本 —— 功能 3 的**后台作业路**编排：前台有界回 running · 查询幂等 · 终态失败拒提交。

一片一测（真工作目录 + 独立样本账本 + **独立运行数据根**；真作业账本一个字节都不动）：
  · 前台有界回运行中 —— 后台作业睡 6 秒 ⇒ 前台窗口（压到 1.5 秒）内回 `待取作业码` +
    **运行中任务ID**（不是失败、不阻塞）。
  · 查询幂等不重启验证 —— 同一开工连调两次 ⇒ **同一个任务ID**，账本里只有**一条**释放作业行。
  · 终态失败拒提交 —— 作业退出码非 0 ⇒ 前台回 1 + 日志尾，**开工状态留「进行中」**。
  · 终态成功 —— 作业退出码 0 ⇒ 前台回 0。

`仓根` = 真仓（作业工作进程要 import 仓内 `作业.py`）；只把 `作业._取工作树` 与
`作业.读后台预算` 按档替身，`V1_RUN_DATA_ROOT` 指向临时根。本件不带 `__main__` 块。
"""

import os
import re
import sqlite3
import tempfile
import time
from pathlib import Path
from unittest import mock

# 运行数据根的唯一解析器与覆盖变量名只从包里取（判据 ㉕：不许自身拼、不许再写一份变量名）。
from 开发工具.运行数据根 import 解析当前环境, 子目录路径, 覆盖变量名

from . import 作业, 作业账本, 开工账本, 释放作业
from .服务常量 import 待取作业码

开工号 = "v1-900431"
同步秒 = 1.5
睡秒 = 5
任务号形状 = re.compile(r"任务ID：([0-9a-f]{32})")


def 样本列表(仓根, 工具表=None) -> list:
    """⇒ `[(说明, 通过)]`（`工具表` 不用；签名与其它样本组同形）。"""
    样本表 = []
    for 名称 in ("前台有界回运行中", "查询幂等不重启验证", "终态失败拒提交", "终态成功"):
        with tempfile.TemporaryDirectory(prefix="v1释放作业-") as 临时目录:
            样本表.append(跑一档(Path(临时目录), 名称, 仓根))
    return 样本表


def 列样本释放作业(作业库路径):
    """临时作业账本里的释放作业行 ⇒ `[dict]`（按开始时间）。"""
    连接 = sqlite3.connect(str(作业库路径))
    连接.row_factory = sqlite3.Row
    try:
        return [dict(数据行) for 数据行 in 连接.execute(
            "select * from 作业 where 具名 = ? and 开工ID = ? order by 开始时间",
            (释放作业.释放具名, 开工号))]
    finally:
        连接.close()


def 跑一档(临时根, 名称, 仓根):
    工作树 = 临时根 / "工作树"
    工作树.mkdir()
    账本路径 = 临时根 / "账本.db"

    def 连样本账本():
        连接 = sqlite3.connect(账本路径)
        连接.row_factory = sqlite3.Row
        return 连接

    连接 = 连样本账本()
    for 建表行 in 开工账本.建表语句:
        连接.execute(建表行)
    开工账本.登记开工(连接, 开工号, "释放作业样本", "腿/" + 开工号, str(工作树))
    连接.close()

    def 假命令(仓根值, 工作树值, 开工号值, 跳过验证, 推送):
        if 名称 == "终态失败拒提交":
            return "python3 -c \"import sys; sys.exit(7)\"", "样本：终态失败"
        if 名称 == "终态成功":
            # 落一条与本次请求（推送=False）**不同**的推送态标记 ⇒ 能分辨「真读了作业日志」
            # 还是「回落成参数」（日志在落终态前已关件刷新 ⇒ 读得到是确定的，不是竞态）。
            return "python3 -c \"print('推送态：本次已推远端（推送=真）')\"", "样本：终态成功"
        return "python3 -c \"import time; time.sleep(%s)\"" % 睡秒, "样本：长活"

    退出码二 = None
    输出文本二 = ""
    with mock.patch.dict(os.environ, {覆盖变量名: str(临时根 / "运行数据")}):
        with mock.patch.object(开工账本, "连账本", 连样本账本), \
                mock.patch.object(作业, "_取工作树", lambda 仓根值, 开工号值: 工作树), \
                mock.patch.object(作业, "读后台预算", lambda 仓根值: (1800, 7200, False)), \
                mock.patch.object(释放作业, "释放命令", 假命令), \
                mock.patch.object(释放作业, "释放同步秒", 同步秒):
            起点 = time.monotonic()
            退出码, 输出文本 = 释放作业.派发释放(仓根, 开工号, False, False, False)
            前台毫秒 = int((time.monotonic() - 起点) * 1000)
            if 名称 == "查询幂等不重启验证":
                退出码二, 输出文本二 = 释放作业.派发释放(仓根, 开工号, False, False, False)
            连接二 = 连样本账本()
            状态 = 开工账本.读开工(连接二, 开工号)["状态"]
            连接二.close()
            作业行表 = 列样本释放作业(
                子目录路径(解析当前环境(), 作业账本.子目录类别) / 作业账本.库文件名)
            for 记录行 in 作业行表:
                作业.取消作业(记录行["任务ID"])
    配对 = 任务号形状.search(输出文本)
    任务ID = 配对.group(1) if 配对 else "（没读到）"
    if 名称 == "前台有界回运行中":
        说明 = ("前台有界回运行中：退出码 %d（待取作业码 %d）· 前台 %d ms（窗口 %g 秒）· "
              "任务ID %s · 状态 %s · 回执含运行中 %s"
              % (退出码, 待取作业码, 前台毫秒, 同步秒, 任务ID, 状态,
                 "是" if "运行中" in 输出文本 else "否"))
        return (说明, 退出码 == 待取作业码 and 配对 is not None
                and 前台毫秒 < int(同步秒 * 1000) + 3000
                and "运行中" in 输出文本 and 状态 == 开工账本.状态_进行中)
    if 名称 == "查询幂等不重启验证":
        配对二 = 任务号形状.search(输出文本二)
        同一 = bool(配对 and 配对二 and 配对.group(1) == 配对二.group(1))
        说明 = ("查询幂等不重启验证：首次 %d · 再调 %d · 同一任务ID %s · 释放作业行 %d 条（期望 1）"
              % (退出码, 退出码二, "是" if 同一 else "否", len(作业行表)))
        return (说明, 退出码 == 待取作业码 and 退出码二 == 待取作业码 and 同一
                and len(作业行表) == 1)
    if 名称 == "终态失败拒提交":
        说明 = ("终态失败拒提交：退出码 %d（期望 1）· 状态 %s（期望 进行中）· 回执含真实终态且失败 %s"
              % (退出码, 状态, "是" if "真实终态且失败" in 输出文本 else "否"))
        return (说明, 退出码 == 1 and 状态 == 开工账本.状态_进行中
                and "真实终态且失败" in 输出文本)
    说明 = ("终态成功：退出码 %d（期望 0）· 回执含真实终态且成功 %s · 逐字报作业日志里的推送态 %s"
          % (退出码, "是" if "真实终态且成功" in 输出文本 else "否",
             "是" if "本次已推远端（推送=真）" in 输出文本 else "否"))
    return (说明, 退出码 == 0 and "真实终态且成功" in 输出文本
            and "本次已推远端（推送=真）" in 输出文本)
