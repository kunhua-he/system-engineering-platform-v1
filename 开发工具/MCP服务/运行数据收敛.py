# -*- coding: utf-8 -*-
"""运行数据收敛 —— 三处「只增不减」的落点各自带界（作业日志 · 临时件 · 案例运行回执）。

# 它解决什么

运行数据根里有三处按次追加、按份落盘的落点，此前都没有保留期或份数上限 ⇒ 攒到几百上千件
才有人手工清。界写成常量，收敛写成一个函数：

| 落点 | 界 | 收在哪 |
|---|---|---|
| `<运行数据根>/日志/` | 留最近 `日志保留天数` 天，且总份数 ≤ `日志份数上限`（超的按 mtime 最旧优先删） | 本件 [`收敛日志`] |
| `<运行数据根>/临时件/` | 删 mtime 早于 `临时件保留天数` 天的子目录 / 件（白名单一律不动） | 本件 [`收敛临时件`] |
| `测试验证/测试案例/运行回执.jsonl` | 留最近 `回执运行上限` 次运行 | **不归本件**：`测试验证/测试案例/跑案例/src/回执.rs::收敛回执` —— 读它的是 Rust 侧，跨界共写会有两个写者 |

# 何时收（惰性，不开定时线程）

[`惰性收敛`] 是唯一触发口，调用方只有两处：**作业结束**（`作业.py::接管作业`）与**服务启动**
（`MCP服务_http.py` 起传输之前）。不常驻线程的理由：常驻进程里多一条自转线程就多一处看不见的
状态与退出时序，而收敛晚几十秒没有代价 —— 「有界」这件事由常量保证，不由触发频率保证。

# 落点只经唯一解析器

路径一律从 `运行数据根` 包取（判据 ㉕：不许自身拼路径）。本件只接「根在哪」这一个事实，
不判平台、不读环境变量。
"""

import re
import shutil
import time
from pathlib import Path

from 运行数据根 import 子目录路径, 解析当前环境

# 作业日志：留最近多少天、最多多少份。
日志保留天数 = 7
日志份数上限 = 300
# 临时件：删多少天以前的。
临时件保留天数 = 7
每天秒数 = 86400
# 惰性触发的节流：同一个常驻进程里至多每 5 秒收一次（作业工作进程是一次性的，恒会收）。
# ★ 取 5 秒而不是几十秒：这条只是「别在同一个进程里连着重扫目录」，与判据 ㊲（超时设置 ≤5 秒）
#   同一口径 —— 一个节流不该比硬顶还长；真正的界由 `日志份数上限` / `临时件保留天数` 保证。
收敛最小间隔秒 = 5

# 作业日志名的形状：`<32 位十六进制任务ID>` + 可选档名后缀 + `.log`。
# ★ 只认这一族：`日志/` 里还住着 `MCP诊断.log` / `MCP服务_http.日志.txt` 这类单件（只有一份、
#   按次追加），它们不随作业份数增长 ⇒ 拿份数上限去删，删掉的正是正在用的那一份。
作业日志名模式 = re.compile(r"^[0-9a-f]{32}(?:\.工作|\.错误)?\.log$")

# ★ 白名单：这两条是活路径，年龄再大也不清。
#   · `易语言源码` —— 默认语料根（`挖真文本/常量.py::源码根` 指它；删了语料类案例与判据集体找不到料）；
#   · `上线切换` —— 活运行态（`上线切换/常量.py::运行根` 指它；删了上线切换的现场就没了）。
临时件白名单 = ("易语言源码", "上线切换")

# 上一次收敛的时刻（只在常驻进程里起节流作用；0.0 = 本进程还没收过）。
上次收敛时刻表 = [0.0]


def 取子目录路径(类别值):
    """`<运行数据根>/<类别值>` —— 只经唯一解析器（判据 ㉕）。"""
    return 子目录路径(解析当前环境(), 类别值)


def _删一项(路径项, 读数表):
    """删一个件或一棵子树；删不动就如实记进读数表（不抛：一次删不动不该拦住后面的项）。"""
    try:
        if 路径项.is_dir() and not 路径项.is_symlink():
            shutil.rmtree(路径项)
        else:
            路径项.unlink()
    except OSError as 删不动:
        读数表["删不动"].append("%s（%r）" % (路径项.name, 删不动))
        return False
    读数表["删除项"].append(路径项.name)
    return True


def 收敛日志(日志根=None, 保留天数=None, 份数上限=None, 当前时刻=None):
    """作业日志收敛：**先按保留期、再按份数** ⇒ 读数表。两条界都成立才算收敛完。

    · 保留期：mtime 早于 `当前时刻 - 保留天数` 的作业日志一律删；
    · 份数：删完保留期后仍多于 `份数上限` ⇒ 按 mtime **最旧优先**删到上限为止。
    · 非作业日志（名字不匹配 `作业日志名模式`）一个都不动 —— 见该常量的理由。

    两界同一次调用里算完，是因为「只按年龄」在密集跑批的日子里仍会堆到上千份（实测一次收口
    就几十条后台作业），而「只按份数」会把七天内该留的读数删掉。
    """
    保留天数 = 日志保留天数 if 保留天数 is None else 保留天数
    份数上限 = 日志份数上限 if 份数上限 is None else 份数上限
    根路径 = Path(日志根) if 日志根 is not None else 取子目录路径("日志")
    读数表 = {"落点": str(根路径), "保留天数": 保留天数, "份数上限": 份数上限,
             "删除份数": 0, "剩余份数": 0, "删除项": [], "删不动": []}
    if not 根路径.is_dir():
        读数表["说明"] = "日志目录不在（还没跑过作业）⇒ 无可收敛"
        return 读数表
    现在秒数 = time.time() if 当前时刻 is None else float(当前时刻)
    过期界限 = 现在秒数 - 保留天数 * 每天秒数
    件表 = []
    for 件项 in 根路径.iterdir():
        if not 件项.is_file() or not 作业日志名模式.match(件项.name):
            continue
        try:
            件表.append((件项.stat().st_mtime, 件项))
        except OSError as 读不到:
            读数表["删不动"].append("%s（%r）" % (件项.name, 读不到))
    件表.sort(key=lambda 件对: 件对[0])
    保留表 = []
    for 修改秒数, 件项 in 件表:
        if 修改秒数 < 过期界限:
            if _删一项(件项, 读数表):
                读数表["删除份数"] += 1
        else:
            保留表.append((修改秒数, 件项))
    超出的份数 = len(保留表) - 份数上限
    for 修改秒数, 件项 in 保留表[:max(超出的份数, 0)]:
        if _删一项(件项, 读数表):
            读数表["删除份数"] += 1
    读数表["剩余份数"] = len(保留表) - max(超出的份数, 0)
    return 读数表


def 收敛临时件(临时件根=None, 保留天数=None, 白名单=None, 当前时刻=None):
    """临时件收敛：删 mtime 早于 `当前时刻 - 保留天数` 的子目录与件 ⇒ 读数表。

    · 白名单（`临时件白名单`）里按**名字**命中的顶层项一律不动，也不递归进去清它的子项 ——
      它们是别的件按默认路径正在用的活目录，不是旧产物；
    · 目录整棵删（`rmtree`），符号链接只删链接自身（不跟进去删目标）。
    """
    保留天数 = 临时件保留天数 if 保留天数 is None else 保留天数
    白名单 = 临时件白名单 if 白名单 is None else tuple(白名单)
    根路径 = Path(临时件根) if 临时件根 is not None else 取子目录路径("临时件")
    读数表 = {"落点": str(根路径), "保留天数": 保留天数, "删除项数": 0, "保留项数": 0,
             "白名单保留": [], "删除项": [], "删不动": []}
    if not 根路径.is_dir():
        读数表["说明"] = "临时件目录不在 ⇒ 无可收敛"
        return 读数表
    现在秒数 = time.time() if 当前时刻 is None else float(当前时刻)
    过期界限 = 现在秒数 - 保留天数 * 每天秒数
    for 件项 in sorted(根路径.iterdir(), key=lambda 项值: 项值.name):
        if 件项.name in 白名单:
            读数表["白名单保留"].append(件项.name)
            continue
        try:
            修改秒数 = 件项.stat().st_mtime
        except OSError as 读不到:
            读数表["删不动"].append("%s（%r）" % (件项.name, 读不到))
            continue
        if 修改秒数 >= 过期界限:
            读数表["保留项数"] += 1
            continue
        if _删一项(件项, 读数表):
            读数表["删除项数"] += 1
    return 读数表


def 惰性收敛(最小间隔秒=None, 当前时刻=None):
    """作业结束 / 服务启动时惰性收一次 ⇒ 两张读数表。**绝不抛**：收敛不是主业务的成败条件。

    `最小间隔秒` 只对常驻进程起作用（同一进程里两次调用间隔不足 ⇒ 跳过并如实说跳过了）；
    作业工作进程每次都是新进程，故每个作业结束都会真收一次。
    """
    最小间隔秒 = 收敛最小间隔秒 if 最小间隔秒 is None else 最小间隔秒
    现在秒数 = time.time() if 当前时刻 is None else float(当前时刻)
    if 现在秒数 - 上次收敛时刻表[0] < 最小间隔秒:
        return {"跳过": "距上次收敛不足 %s 秒" % 最小间隔秒}
    上次收敛时刻表[0] = 现在秒数
    try:
        return {"日志": 收敛日志(当前时刻=现在秒数), "临时件": 收敛临时件(当前时刻=现在秒数)}
    except Exception as 出错:
        return {"错误": repr(出错)}
