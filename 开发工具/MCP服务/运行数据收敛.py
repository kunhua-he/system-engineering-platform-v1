# -*- coding: utf-8 -*-
"""运行数据收敛 —— 三处「只增不减」的落点各自带界（作业日志 · 临时件 · 案例运行回执）。

# 它解决什么

运行数据根里有三处按次追加、按份落盘的落点，此前都没有保留期或份数上限 ⇒ 攒到几百上千件
才有人手工清。界写成常量，收敛写成一个函数：

| 落点 | 界 | 收在哪 |
|---|---|---|
| `<运行数据根>/日志/` | 留最近 `日志保留天数` 天，且总份数 ≤ `日志份数上限`（超的按 mtime 最旧优先删） | 本件 [`收敛日志`] |
| `<运行数据根>/临时件/` | 只清**认得出形状的按次产物**（`临时件可删前缀`）里 mtime 早于 `临时件保留天数` 天的项；认不出名字的一律保留（白名单活路径也不动） | 本件 [`收敛临时件`] |
| `<运行数据根>/日志/MCP诊断.log` · `MCP服务_http.日志.txt` | **单件**：到 `单件日志字节上限`（5 MB）就「抄一份 `.1` + 把活动件截成 0」（**不换 inode**），只留一份 | 本件 [`收敛单件日志`] |
| `测试验证/测试案例/运行回执.jsonl` | 留最近 `回执运行上限` 次运行 | **不归本件**：`测试验证/测试案例/跑案例/src/回执.rs::收敛回执` —— 读它的是 Rust 侧，跨界共写会有两个写者 |

# 何时收（惰性，不开定时线程）

[`惰性收敛`] 是唯一触发口，调用方只有两处：**作业结束**（`作业.py::接管作业`）与**服务启动**
（`MCP服务_http.py` 起传输之前）。不常驻线程的理由：常驻进程里多一条自转线程就多一处看不见的
状态与退出时序，而收敛晚几十秒没有代价 —— 「有界」这件事由常量保证，不由触发频率保证。

# 落点只经唯一解析器

路径一律从 `运行数据根` 包取（判据 ㉕：不许自身拼路径）。本件只接「根在哪」这一个事实，
不判平台、不读环境变量。
"""

import os
import re
import shutil
import time
from pathlib import Path

from 运行数据根 import 子目录路径, 解析当前环境

# 作业日志：留最近多少天、最多多少份。
日志保留天数 = 7
日志份数上限 = 300
# 临时件：删多少天以前的。
临时件保留天数 = 7
每天秒数 = 86400
# 惰性触发的节流：同一个常驻进程里至多每 5 秒收一次（作业工作进程是一次性的，恒会收）。
# ★ 取 5 秒而不是几十秒：这条只是「别在同一个进程里连着重扫目录」，与判据 ㊲（超时设置 ≤5 秒）
#   同一口径 —— 一个节流不该比硬顶还长；真正的界由 `日志份数上限` / `临时件保留天数` 保证。
收敛最小间隔秒 = 5

# 作业日志名的形状：`<32 位十六进制任务ID>` + 可选档名后缀 + `.log`。
# ★ 只认这一族：`日志/` 里还住着 `MCP诊断.log` / `MCP服务_http.日志.txt` 这类单件（只有一份、
#   按次追加），它们不随作业份数增长 ⇒ 拿份数上限去删，删掉的正是正在用的那一份。
作业日志名模式 = re.compile(r"^[0-9a-f]{32}(?:\.工作|\.错误)?\.log$")

# 单件日志的 size 轮转：这两份**只有一份、按次追加**，份数上限与保留期都管不到它们 ——
# 实测 `MCP服务_http.日志.txt` 已长到 2.7 MB 且没有任何界（上一轮漏纳的就是这一处）。
单件轮转表 = ("MCP诊断.log", "MCP服务_http.日志.txt")
单件日志字节上限 = 5 * 1024 * 1024

# ★ 「按次产物」的可删族：**只清认识形状的**，认不出名字的一律保留。
#   实测 `临时件/` 里住着人写的证据（`反馈源正文` 内容寻址快照 · `收敛回执` · `债务落点-*.json` ·
#   审计稿），还有活作业用的目录（`集成树`）—— 拿 mtime 一锅端，删掉的是反馈源与回执证据。
#   这两族由工具体按 `mkdtemp` 生成、用完即弃（`库快照.py::快照目录`、
#   `反馈源清点.py::快照根`），名字形态固定 ⇒ 才敢按年龄清。
临时件可删前缀 = ("v1_db快照-", "反馈源清点-")

# ★ 白名单：这两条是活路径，年龄再大也不清。
#   · `易语言源码` —— 默认语料根（`挖真文本/常量.py::源码根` 指它；删了语料类案例与判据集体找不到料）；
#   · `上线切换` —— 活运行态（`上线切换/常量.py::运行根` 指它；删了上线切换的现场就没了）。
临时件白名单 = ("易语言源码", "上线切换")

# 上一次收敛的时刻（只在常驻进程里起节流作用；0.0 = 本进程还没收过）。
上次收敛时刻表 = [0.0]


def 取子目录路径(类别值):
    """`<运行数据根>/<类别值>` —— 只经唯一解析器（判据 ㉕）。"""
    return 子目录路径(解析当前环境(), 类别值)


def _删一项(路径项, 读数表):
    """删一个件或一棵子树；删不动就如实记进读数表（不抛：一次删不动不该拦住后面的项）。"""
    try:
        if 路径项.is_dir() and not 路径项.is_symlink():
            shutil.rmtree(路径项)
        else:
            路径项.unlink()
    except OSError as 删不动:
        读数表["删不动"].append("%s（%r）" % (路径项.name, 删不动))
        return False
    读数表["删除项"].append(路径项.name)
    return True


def 收敛日志(日志根=None, 保留天数=None, 份数上限=None, 当前时刻=None):
    """作业日志收敛：**先按保留期、再按份数** ⇒ 读数表。两条界都成立才算收敛完。

    · 保留期：mtime 早于 `当前时刻 - 保留天数` 的作业日志一律删；
    · 份数：删完保留期后仍多于 `份数上限` ⇒ 按 mtime **最旧优先**删到上限为止。
    · 非作业日志（名字不匹配 `作业日志名模式`）一个都不动 —— 见该常量的理由。

    两界同一次调用里算完，是因为「只按年龄」在密集跑批的日子里仍会堆到上千份（实测一次收口
    就几十条后台作业），而「只按份数」会把七天内该留的读数删掉。
    """
    保留天数 = 日志保留天数 if 保留天数 is None else 保留天数
    份数上限 = 日志份数上限 if 份数上限 is None else 份数上限
    根路径 = Path(日志根) if 日志根 is not None else 取子目录路径("日志")
    读数表 = {"落点": str(根路径), "保留天数": 保留天数, "份数上限": 份数上限,
             "删除份数": 0, "剩余份数": 0, "删除项": [], "删不动": []}
    if not 根路径.is_dir():
        读数表["说明"] = "日志目录不在（还没跑过作业）⇒ 无可收敛"
        return 读数表
    现在秒数 = time.time() if 当前时刻 is None else float(当前时刻)
    过期界限 = 现在秒数 - 保留天数 * 每天秒数
    件表 = []
    for 件项 in 根路径.iterdir():
        if not 件项.is_file() or not 作业日志名模式.match(件项.name):
            continue
        try:
            件表.append((件项.stat().st_mtime, 件项))
        except OSError as 读不到:
            读数表["删不动"].append("%s（%r）" % (件项.name, 读不到))
    件表.sort(key=lambda 件对: 件对[0])
    保留表 = []
    for 修改秒数, 件项 in 件表:
        if 修改秒数 < 过期界限:
            if _删一项(件项, 读数表):
                读数表["删除份数"] += 1
        else:
            保留表.append((修改秒数, 件项))
    超出的份数 = len(保留表) - 份数上限
    for 修改秒数, 件项 in 保留表[:max(超出的份数, 0)]:
        if _删一项(件项, 读数表):
            读数表["删除份数"] += 1
    读数表["剩余份数"] = len(保留表) - max(超出的份数, 0)
    return 读数表


def 最新修改秒数(路径项):
    """该项**自身与整棵子树里最晚的 mtime**（目录本身只反映「增删条目」）。

    ★ 为什么不能用 `路径项.stat().st_mtime` 一项定生死：目录里再改写件不会更新目录 mtime ⇒
    一个「7 天前建的、今天还在往里写」的目录看起来是旧的。按子树最晚 mtime 判，才与「多久没动过」
    这个语义对得上（判据只取读数，不猜内容）。
    """
    最新 = 路径项.stat().st_mtime
    if 路径项.is_symlink() or not 路径项.is_dir():
        return 最新
    for 子项 in 路径项.rglob("*"):
        try:
            if 子项.is_symlink():
                continue
            最新 = max(最新, 子项.stat().st_mtime)
        except OSError:
            continue
    return 最新


def 收敛临时件(临时件根=None, 保留天数=None, 白名单=None, 当前时刻=None):
    """临时件收敛：只清 `临时件可删前缀` 那几族里「整棵子树最晚 mtime」早于保留期的项 ⇒ 读数表。

    · **认不出的名字一律不动**（`未匹配保留` 列出）：`临时件/` 里住着反馈源快照、回执、审计稿与
      活作业目录，凭 mtime 一锅端会删掉活作业与反馈源证据 —— 那是不可恢复的损失，宁可少清；
    · 白名单（`临时件白名单`）里按**名字**命中的顶层项一律不动，也不递归进去清它的子项；
    · 年龄按子树最晚 mtime 判（[`最新修改秒数`]）：里面今天还在写的目录不算旧；
    · 目录整棵删（`rmtree`），符号链接只删链接自身（不跟进去删目标）。
    """
    保留天数 = 临时件保留天数 if 保留天数 is None else 保留天数
    白名单 = 临时件白名单 if 白名单 is None else tuple(白名单)
    根路径 = Path(临时件根) if 临时件根 is not None else 取子目录路径("临时件")
    读数表 = {"落点": str(根路径), "保留天数": 保留天数, "删除项数": 0, "保留项数": 0,
             "白名单保留": [], "未匹配保留": [], "删除项": [], "删不动": []}
    if not 根路径.is_dir():
        读数表["说明"] = "临时件目录不在 ⇒ 无可收敛"
        return 读数表
    现在秒数 = time.time() if 当前时刻 is None else float(当前时刻)
    过期界限 = 现在秒数 - 保留天数 * 每天秒数
    for 件项 in sorted(根路径.iterdir(), key=lambda 项值: 项值.name):
        if 件项.name in 白名单:
            读数表["白名单保留"].append(件项.name)
            continue
        if not 件项.name.startswith(临时件可删前缀):
            # 认不出形状 ⇒ 可能是活作业 / 反馈源证据 / 人写的审计稿 ⇒ 一个都不删，只登记。
            读数表["未匹配保留"].append(件项.name)
            continue
        try:
            修改秒数 = 最新修改秒数(件项)
        except OSError as 读不到:
            读数表["删不动"].append("%s（%r）" % (件项.name, 读不到))
            continue
        if 修改秒数 >= 过期界限:
            读数表["保留项数"] += 1
            continue
        if _删一项(件项, 读数表):
            读数表["删除项数"] += 1
    return 读数表


def 收敛单件日志(日志根=None, 字节上限=None):
    """单件日志按**大小**轮转：到界 ⇒ 「抄一份 `.1` + 把活动件截成 0」⇒ 读数表。

    · 为什么单独一条：这两份是「一份、按次追加」的活日志（`单件轮转表`），`收敛日志` 的
      保留期与份数上限都不认它们 —— 拿份数去删，删掉的正是正在用的那一份；
    · **为什么不是改名（`os.replace`）**：这两份的真写者不是「打开-写-关」：
      ① `MCP服务_http.日志.txt` 是常驻服务子进程**继承下来的 stdout**（`服务管理.py::启动服务`
      把父进程开的句柄递给子进程），句柄活整个进程生命周期；② `MCP诊断.log` 每条一次
      `os.open(O_APPEND)` 后立刻关。对 ① 做 `rename`，持有者的文件描述仍指旧 inode ⇒ 它**继续
      往 `.1` 里写**，活动件永远是 0 字节、`.1` 无限长大 —— 界等于没设，还骗过「`.1` 存在」这种
      浅断言。**抄 + 截**不换 inode：写者（继承的 stdout 与逐次 `open`）都继续写同一个活动路径。
    · 代价（明写）：抄与截之间（毫秒级）写进活动件的那几行会在 `.1` 与活动件里都没有 —— 日志
      允许丢这几行，回执与台账不允许（它们走各自的锁）；抄是「先写 `.1` 再截」，读数由此可复算。
    """
    字节上限 = 单件日志字节上限 if 字节上限 is None else 字节上限
    根路径 = Path(日志根) if 日志根 is not None else 取子目录路径("日志")
    读数表 = {"落点": str(根路径), "字节上限": 字节上限,
             "轮转项": [], "未到界": [], "删不动": []}
    if not 根路径.is_dir():
        读数表["说明"] = "日志目录不在 ⇒ 无可轮转"
        return 读数表
    for 名字 in 单件轮转表:
        件项 = 根路径 / 名字
        try:
            字节数 = 件项.stat().st_size
        except OSError:
            # 不在 = 从没写过（或刚被轮转走）⇒ 不是问题，也不建空件。
            读数表["未到界"].append(名字)
            continue
        if 字节数 < 字节上限:
            读数表["未到界"].append(名字)
            continue
        try:
            备份件 = 根路径 / (名字 + ".1")
            备份件.write_bytes(件项.read_bytes())
            os.truncate(件项, 0)
        except OSError as 换不动:
            读数表["删不动"].append("%s（%r）" % (名字, 换不动))
            continue
        读数表["轮转项"].append("%s → %s.1（抄 %d 字节 · 活动件截回 0，不换 inode）"
                             % (名字, 名字, 字节数))
    return 读数表


def 惰性收敛(最小间隔秒=None, 当前时刻=None):
    """作业结束 / 服务启动时惰性收一次 ⇒ 三张读数表。**绝不抛**：收敛不是主业务的成败条件。

    `最小间隔秒` 只对常驻进程起作用（同一进程里两次调用间隔不足 ⇒ 跳过并如实说跳过了）；
    作业工作进程每次都是新进程，故每个作业结束都会真收一次。
    """
    最小间隔秒 = 收敛最小间隔秒 if 最小间隔秒 is None else 最小间隔秒
    现在秒数 = time.time() if 当前时刻 is None else float(当前时刻)
    if 现在秒数 - 上次收敛时刻表[0] < 最小间隔秒:
        return {"跳过": "距上次收敛不足 %s 秒" % 最小间隔秒}
    上次收敛时刻表[0] = 现在秒数
    try:
        return {
            "日志": 收敛日志(当前时刻=现在秒数),
            "临时件": 收敛临时件(当前时刻=现在秒数),
            "单件日志": 收敛单件日志(),
        }
    except Exception as 出错:
        return {"错误": repr(出错)}
