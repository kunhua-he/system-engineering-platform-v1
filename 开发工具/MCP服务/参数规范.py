def 载入操作表() -> dict:
    """glob 同目录 `操作_*.py` 合并各自 `操作表` ⇒ `{工具名: {操作名: 条}}`（无硬编码文件清单）。

    合并规则：glob 到的操作表**覆盖**内置回退；同工具同操作两处都给实现时按件名排序后者胜；
    **有 `处理` 的条不被预留槽（无 `处理`）覆盖** ⇒ 各 owner 新增的实现能挂上预留槽。
    缺件 / 坏件跳过（不报错）。
    """
    global _总表缓存
    if _总表缓存 is not None:
        return _总表缓存
    总表 = {}
    for 件路径 in sorted(服务根.glob("操作_*.py")):
        try:
            模块 = importlib.import_module("." + 件路径.stem, __package__)
        except Exception:
            continue
        工具名 = str(getattr(模块, "工具名", "") or "")
        if not 工具名:
            continue
        操作分表 = 总表.setdefault(工具名, {})
        for 操作名, 操作条 in dict(getattr(模块, "操作表", {}) or {}).items():
            旧条 = 操作分表.get(操作名)
            if 旧条 and 旧条.get("处理") and not 操作条.get("处理"):
                continue
            操作分表[操作名] = 操作条
    for 工具名, 回退分表 in _回退表().items():
        分表 = 总表.setdefault(工具名, {})
        for 操作名, 操作条 in 回退分表.items():
            分表.setdefault(操作名, 操作条)
    _总表缓存 = 总表
    return 总表


def 声明工具() -> dict:
    """glob `操作_*.py`：凡**自声明新工具**（给了 `工具说明` 或 `派发`）⇒
    `{工具名: {工具说明, 模式, 派发}}`。既有六工具的操作表文件只给 `工具名` + `操作表`（不在此列）。
    缺件 / 坏件跳过（不报错）—— 新工具由各自 owner 加一件 `操作_*.py` 即注册。
    """
    声明表 = {}
    for 件路径 in sorted(服务根.glob("操作_*.py")):
        try:
            模块 = importlib.import_module("." + 件路径.stem, __package__)
        except Exception:
            continue
        工具名 = str(getattr(模块, "工具名", "") or "")
        if not 工具名 or 工具名 in 声明表:
            continue
        if not (getattr(模块, "工具说明", "") or getattr(模块, "派发", None)):
            continue
        声明表[工具名] = {"工具说明": str(getattr(模块, "工具说明", "") or 工具名),
                     "模式": getattr(模块, "模式", None), "派发": getattr(模块, "派发", None)}
    return 声明表


def 定脚本(脚本相对: str) -> str:
    """操作声明的脚本落点 ⇒ 绝对路径；越出**固定脚本目录** / 不存在 ⇒ 空串（拒，不接受任意路径）。"""
    if not 脚本相对 or str(脚本相对).startswith("/") or ".." in Path(str(脚本相对)).parts:
        return ""
    绝对路径 = (脚本根 / str(脚本相对)).resolve()
    根路径 = 脚本根.resolve()
    if 根路径 != 绝对路径 and 根路径 not in 绝对路径.parents:
        return ""
    return str(绝对路径) if 绝对路径.is_file() else ""


def 跑脚本(脚本路径: str, 开工号: str, 操作: str, 参数表: dict, 仓根路径) -> tuple:
    """执行一个操作脚本 ⇒ `(退出码, 输出文本)`：**5 秒硬顶 · 输出有界 · 完整日志指针**（复用 shell 执行器）。

    脚本从环境拿输入：`V1_操作` · `V1_开工ID` · `V1_参数`（JSON）；工作目录 = 目标树（开工号定工作树）。
    **源码写盘仍只走 `v1_edit`**：脚本写脏的源码件在释放的越界检测处被拒 —— 本口不授权绕记账。
    """
    import shlex
    from .shell import 派发 as 终端派
    命令 = "V1_操作=%s V1_开工ID=%s V1_参数=%s sh %s" % (
        shlex.quote(操作), shlex.quote(开工号),
        shlex.quote(json.dumps(参数表, ensure_ascii=False)), shlex.quote(脚本路径))
    实参 = {"命令": 命令, "超时": 脚本超时秒}
    if 开工号:
        实参["开工ID"] = 开工号
    return 终端派(实参, 仓根路径)


def 有值(值) -> bool:
    """具名参是否算「给了」：`None` / 空串 / 空表 ⇒ 假。"""
    if 值 is None:
        return False
    if isinstance(值, str):
        return bool(值.strip())
    if isinstance(值, (list, dict, tuple)):
        return bool(值)
    return True


def 取git值(目标路径, 参数表: list) -> str:
    """在 `目标路径` 里跑一条 git 子命令 ⇒ 去空白 stdout；跑不动 ⇒ 空串（不编话）。"""
    from .仓操作 import 跑命令
    退出码, 输出文本 = 跑命令(["git"] + 参数表, cwd=目标路径, 超时秒数=取树超时秒)
    return 输出文本.strip() if 退出码 == 0 else ""


# 取树快照：只由调用方显式开启的有限作用域内复用；默认关闭 ⇒ 生产每条现读（不盲长驻缓存）。
# 用 ContextVar 而**不是模块全局**：HTTP 自检在同一进程里起真实 HTTP 服务，处理线程与自检线程
# 必须互不污染（模块全局会让处理线程读到自检线程缓存的旧 HEAD）。
树快照 = contextvars.ContextVar("取树快照", default=None)


def 开树快照():
    """开启取树快照并返回旧值（供 `关树快照` 还原）—— 同一稳定仓连发多条信封的场景（如自检）。"""
    return 树快照.set({})


def 关树快照(旧值):
    """还原 `开树快照` 前的状态（作用域结束必须还原，别把快照留成长驻缓存）。"""
    树快照.reset(旧值)


def 取树(开工号: str, 仓根路径) -> dict:
    """信封里的 `树`：`{种类, 路径, 开工ID, 分支, HEAD}`。

    给了 `开工ID` ⇒ 问 git 精确定位那条开工的工作树（`找工作树`，**不碰账本、不建库**）；
    问不到 ⇒ 种类「未定」。留空 ⇒ 种类「服务仓根」。分支 / HEAD 由 git 现读（读不到给空串）。
    开了 `树快照`（有限作用域）⇒ 同键复用；不开 ⇒ 每条现读。分支与 HEAD 合并成一条 git 调用。
    """
    快照键 = (开工号 or "", str(仓根路径 or ""))
    当前快照 = 树快照.get()
    if 当前快照 is not None and 快照键 in 当前快照:
        return 当前快照[快照键]
    种类, 目标路径 = "服务仓根", str(仓根路径 or "")
    if 开工号:
        种类 = "未定"
        try:
            from .仓操作 import 找工作树
            工作树 = 找工作树(仓根路径, 开工号)
        except Exception:
            工作树 = None
        if 工作树 is not None:
            种类, 目标路径 = "工作树", str(工作树)
    from .仓操作 import 跑命令
    退出码, 输出文本 = 跑命令(["git", "rev-parse", "HEAD", "--abbrev-ref", "HEAD"],
                       cwd=目标路径, 超时秒数=取树超时秒)
    行表 = [源码行.strip() for 源码行 in 输出文本.splitlines() if 源码行.strip()]
    if 退出码 == 0 and len(行表) == 2:
        分支, HEAD = ("" if 行表[1] == "HEAD" else 行表[1]), 行表[0]
    else:
        分支 = 取git值(目标路径, ["branch", "--show-current"])
        HEAD = 取git值(目标路径, ["rev-parse", "HEAD"])
    读数 = {"种类": 种类, "路径": 目标路径, "开工ID": 开工号 or None,
            "分支": 分支, "HEAD": HEAD}
    if 当前快照 is not None:
        当前快照[快照键] = 读数
    return 读数


def 有界(原文: str) -> tuple:
    """`说明` 留内存有界 ⇒ `(留存文本, 截断?, 日志路径)`。超出落系统临时件（懒建）。"""
    原文 = 原文 if isinstance(原文, str) else str(原文)
    if len(原文) <= 说明上限:
        return 原文, False, None
    句柄, 日志路径 = tempfile.mkstemp(prefix="v1信封_", suffix=".log")
    with os.fdopen(句柄, "w", encoding="utf-8", errors="replace") as 日志件:
        日志件.write(原文)
    return 原文[:说明上限], True, 日志路径


def 结构化(输出文本: str):
    """底层回执若是 JSON 对象 ⇒ 解析出来当 `结果`；否则 `None`（文本工具的结果就在 `说明` 里）。"""
    try:
        读数 = json.loads(输出文本)
    except (TypeError, ValueError):
        return None
    return 读数 if isinstance(读数, dict) else None


def 信封(工具名: str, 操作: str, 退出码: int, 说明: str, 结果值=None, 错误=None,
        开工号: str = "", 仓根路径=None) -> str:
    """统一一行 JSON 信封（`isError` 由协议层按 `退出码 != 0` 折，不进本信封）。"""
    from .协议 import 服务版本
    from .服务指纹 import 算服务指纹
    留存文本, 截断, 日志 = 有界(说明)
    return json.dumps({
        "成功": 退出码 == 0,
        "退出码": 退出码,
        "工具": 工具名,
        "操作": 操作 or None,
        "树": 取树(开工号, 仓根路径),
        "服务": {"版本": 服务版本, "指纹": 算服务指纹()},
        "说明": 留存文本,
        "结果": 结果值,
        "错误": 错误,
        "截断": 截断,
        "日志": 日志,
    }, ensure_ascii=False)


def 拒调用(工具名: str, 操作: str, 种类: str, 说明: str, 仓根路径,
      缺参=None, 最短例=None) -> tuple:
    """结构化拒 ⇒ `(2, 信封)`（参数面一律退出码 2；`错误.种类` 分清是哪一类）。"""
    return 2, 信封(工具名, 操作, 2, 说明,
                  错误={"种类": 种类, "缺参": list(缺参 or []), "最短例": 最短例},
                  仓根路径=仓根路径)


def 发现(工具名: str, 规范: dict, 仓根路径) -> tuple:
    """只读发现调用（操作留空）⇒ `(0, 信封)`，`结果` 是**该工具的操作目录**。"""
    目录 = {操作名: {"说明": 操作条.get("说明", ""), "需开工ID": bool(操作条.get("需开工ID")),
                  "必需": list(操作条.get("必需", [])), "可选": list(操作条.get("可选", [])),
                  "最短例": 操作条.get("最短例")}
          for 操作名, 操作条 in sorted(规范.items())}
    return 0, 信封(工具名, "", 0, "%s 操作目录：%d 个操作" % (工具名, len(目录)),
                  结果值={"工具": 工具名, "操作目录": 目录}, 仓根路径=仓根路径)


def 网关派发(工具名: str, 实参, 仓根路径) -> tuple:
    """六工具**统一入口** ⇒ `(退出码, 一行 JSON 信封)`。"""
    规范 = 载入操作表().get(工具名, {})
    if not isinstance(实参, dict):
        return 拒调用(工具名, "", "参数错误", "`arguments` 要是对象", 仓根路径)
    未知顶层 = sorted(set(实参) - set(顶层键))
    if 未知顶层:
        return 拒调用(工具名, "", "参数错误",
                 "未知顶层键：%s；本工具只认 %s" % ("、".join(未知顶层), "、".join(顶层键)), 仓根路径)
    开工号 = 实参.get("开工ID")
    if 开工号 is not None and not isinstance(开工号, str):
        return 拒调用(工具名, "", "参数错误", "`开工ID` 要是字符串", 仓根路径)
    开工号 = (开工号 or "").strip()
    操作 = 实参.get("操作")
    if 操作 is not None and not isinstance(操作, str):
        return 拒调用(工具名, "", "参数错误", "`操作` 要是字符串", 仓根路径)
    操作 = (操作 or "").strip()
    参数表 = 实参.get("参数")
    if 参数表 is None:
        参数表 = {}
    if not isinstance(参数表, dict):
        return 拒调用(工具名, 操作, "参数错误", "`参数` 要是对象", 仓根路径)
    if not 操作:
        if 参数表:
            return 拒调用(工具名, "", "参数错误",
                     "带了 `参数` 却没给 `操作` ⇒ 拒（本工具不猜你要干什么）", 仓根路径)
        return 发现(工具名, 规范, 仓根路径)
    if 操作 not in 规范:
        return 拒调用(工具名, 操作, "未知操作",
                 "没有这个操作：%s；可用：%s" % (操作, "、".join(sorted(规范)) or "（无）"), 仓根路径)
    操作条 = 规范[操作]
    未知键 = sorted(set(参数表) - set(操作条.get("必需", [])) - set(操作条.get("可选", [])))
    if 未知键:
        return 拒调用(工具名, 操作, "参数错误", "未知参数键：%s" % "、".join(未知键), 仓根路径,
                 最短例=操作条.get("最短例"))
    缺参 = [参数名 for 参数名 in 操作条.get("必需", []) if 参数名 != "开工ID" and not 有值(参数表.get(参数名))]
    if 操作条.get("需开工ID") and not 开工号:
        缺参 = ["开工ID"] + 缺参
    if 缺参:
        return 拒调用(工具名, 操作, "缺参", "缺必需参数：%s" % "、".join(缺参), 仓根路径,
                 缺参=缺参, 最短例=操作条.get("最短例"))
    if 操作条.get("处理"):
        退出码, 输出文本 = 操作条["处理"](开工号, 参数表, 仓根路径)
    elif 操作条.get("脚本"):
        脚本路径 = 定脚本(操作条.get("脚本"))
        if not 脚本路径:
            return 拒调用(工具名, 操作, "未实现",
                     "操作 `%s` 的脚本落点不合法或不在固定脚本目录：%r" % (操作, 操作条.get("脚本")), 仓根路径)
        退出码, 输出文本 = 跑脚本(脚本路径, 开工号, 操作, 参数表, 仓根路径)
    else:
        return 拒调用(工具名, 操作, "未实现", "操作 `%s` 是预留槽（未实现）" % 操作, 仓根路径)
    错误 = None
    if 退出码 != 0:
        错误 = {"种类": "参数错误" if 退出码 == 2 else "业务失败", "缺参": [], "最短例": None}
    return 退出码, 信封(工具名, 操作, 退出码, 输出文本,
                      结果值=结构化(输出文本),
                      错误=错误, 开工号=开工号, 仓根路径=仓根路径)
