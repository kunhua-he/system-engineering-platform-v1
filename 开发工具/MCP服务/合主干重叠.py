# -*- coding: utf-8 -*-
"""合主干重叠 —— 合并侧重叠工序：读认领重叠登记 · 判合并形态 · 双方裁决报告 · 核双方裁决齐。

与 `认领隔离.py`（**认领侧**闸：把「两条腿认领同一件」写进账本 `认领重叠` 表）成对 ——
本件是**合并侧**那一半。`合主干编排._派发` 合腿后调本件，把「撞文件」从**一律交人裁**收成
**固定工序**：

  · 读本腿在 `认领重叠` 里的登记（**表不存在 / 为空 ⇒ 优雅空集** ⇒ 本工序休眠，不误伤）；
  · 逐件判合并形态：git 已自动三方合并（**不同片段**）⇒ **核双方裁决齐**后继续；
    **同片段 / 嵌套冲突** ⇒ 出**双方裁决报告**（逐件给两侧值 + 行区间，**不静默取一侧**）
    并要 `接管集成`；
  · **核双方裁决齐**：本腿与对方侧各自的独有改动都落进结果，缺一侧 ⇒ 显式拒 —— 防
    「保留双方裁决」被做成一侧覆盖另一侧。比对**按去缩进后的内容**：整块缩进位移不是内容改动
    （逐字含缩进比会把「把一段主体搬进新函数」这类重排误判成丢一侧 —— 假红）。

**未知冲突**（不在重叠登记里）不归本件 —— 编排保持原拒绝语义（见 `合主干编排._派发`）。

`对方侧 = 主干`（**不是**对方腿分支）：三方合并的「我方」就是**合腿前的主干**（对方腿若已先合，
它的改动就在主干里）—— 只有主干那一侧的东西才可能进结果；拿对方腿分支当参照会在对方腿**尚未
合主干**时假红。
"""

import difflib
import sqlite3
from pathlib import Path


def 去注释(源码行: str) -> str:
    """去整行/行尾注释后归一（引号内的 `#` / `//` 不动）—— 注释不是内容。"""
    引号符 = ""
    游标 = 0
    while 游标 < len(源码行):
        位上字 = 源码行[游标]
        if 引号符:
            if 位上字 == "\\":
                游标 += 2
                continue
            if 位上字 == 引号符:
                引号符 = ""
        elif 位上字 in "\"'":
            引号符 = 位上字
        elif 源码行.startswith("//", 游标) or 位上字 == "#":
            return 源码行[:游标].strip()
        游标 += 1
    return 源码行.strip()

from .合主干有界跑 import 干净环境

重叠表名 = "认领重叠"
主干引用 = "主干"
冲突起始标记 = "<<<<<<<"
冲突分隔标记 = "======="
冲突结束标记 = ">>>>>>>"


def _跑(命令表, 工作目录):
    """一条 git 命令 ⇒ `(退出码, 合并输出)`。

    环境走 `合主干有界跑.干净环境`（**已剔 Git 定位变量**）⇒ 样本 / 真腿里都不污染真仓
    （`仓操作.跑命令` 的那一处净化由另一条腿在做；本件**不依赖它修好**）。
    """
    import subprocess

    回执 = subprocess.run(命令表, cwd=str(工作目录), capture_output=True, text=True,
                       env=干净环境(), timeout=5)
    return 回执.returncode, (回执.stdout or "") + (回执.stderr or "")


def 读重叠登记(开工号, 连接=None) -> list:
    """本腿在账本 `认领重叠` 里的登记行 ⇒ dict 表。

    **表不存在 / 为空 ⇒ 空表**（认领侧那条腿未合主干时本工序自动休眠 —— 不报错、不误伤）。
    """
    自有连接 = 连接 is None
    if 自有连接:
        from . import 开工账本

        连接 = 开工账本.连账本()
    try:
        try:
            登记行表 = 连接.execute(
                "select 开工号, 路径, 工作树, 基线提交, 对方开工号, 对方工作树, 对方基线提交 "
                "from %s where 开工号 = ? order by 路径, 对方开工号" % 重叠表名, (开工号,)).fetchall()
        except sqlite3.OperationalError:
            return []
        return [dict(重叠行) for 重叠行 in 登记行表]
    finally:
        if 自有连接:
            连接.close()


def 重叠路径集(开工号, 连接=None) -> set:
    """本腿认领重叠的**件路径集**（编排拿它把**未知冲突**留给原拒绝语义）。"""
    return {重叠行["路径"] for 重叠行 in 读重叠登记(开工号, 连接)}


def 未合并集(集成树) -> set:
    """集成树里**未合并**（索引带冲突暂存段）的件路径集。"""
    退出码, 输出文本 = _跑(["git", "diff", "--name-only", "--diff-filter=U"], 集成树)
    if 退出码 != 0:
        return set()
    return {源码行.strip() for 源码行 in 输出文本.splitlines() if 源码行.strip()}


def 取文本(集成树, 引用, 路径) -> str:
    """`git show 引用:路径` ⇒ 文本；读不出（件不在该引用）⇒ 空串。"""
    退出码, 输出文本 = _跑(["git", "show", "%s:%s" % (引用, 路径)], 集成树)
    return 输出文本 if 退出码 == 0 else ""


def 逐行增量(基行表, 侧行表) -> tuple:
    """相对基，侧（某引用）的独有改动 ⇒ `(新增行表, 删除行表)`。

    `autojunk=False` —— 重复行不许被当噪声丢掉（本工序专防「多行同形的改动被吃」）。
    **按去缩进、去注释后的内容比**：整块缩进位移不是「内容改动」；两侧对**同一行的行尾注释**
    措辞不同时「独有行逐字在场」不可能满足（实测 v1-100680 两处假红全在注释）；**内容真被丢照样算缺**。
    """
    基行表 = [去注释(源码行) for 源码行 in 基行表]
    侧行表 = [去注释(源码行) for 源码行 in 侧行表]
    匹配器 = difflib.SequenceMatcher(None, 基行表, 侧行表, autojunk=False)
    新增表, 删除表 = [], []
    for 标签, 基起, 基止, 侧起, 侧止 in 匹配器.get_opcodes():
        if 标签 in ("insert", "replace"):
            新增表.extend(侧行表[侧起:侧止])
        if 标签 in ("delete", "replace"):
            删除表.extend(基行表[基起:基止])
    return 新增表, 删除表


def 缺行(结果行集, 待查行表) -> list:
    """待查行里**有内容**却不在结果里的 ⇒ 列表（空行/纯注释不判；**按去缩进、去注释后的内容比**）。"""
    return [源码行 for 源码行 in 待查行表
            if 去注释(源码行) and 去注释(源码行) not in 结果行集]


def 核双方裁决齐(集成树, 腿分支, 路径, 基提交) -> tuple:
    """核结果里**本腿与对方侧各自独有改动都在** ⇒ `(退出码, 行表)`。缺一侧 ⇒ 退出码 1。"""
    件路径 = Path(集成树) / 路径
    if not 件路径.is_file():
        return 0, ["   重叠核 %s：结果里没有这个件（删除类改动不误伤）" % 路径]
    try:
        结果文本 = 件路径.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return 0, ["   重叠核 %s：非文本件（二进制 / 读不动）⇒ 不作文本核" % 路径]
    基行表 = 取文本(集成树, 基提交, 路径).splitlines()
    本腿新增, _ = 逐行增量(基行表, 取文本(集成树, 腿分支, 路径).splitlines())
    对方新增, _ = 逐行增量(基行表, 取文本(集成树, 主干引用, 路径).splitlines())
    结果行集 = {去注释(源码行) for 源码行 in 结果文本.splitlines()}
    缺本腿 = 缺行(结果行集, 本腿新增)
    缺对方 = 缺行(结果行集, 对方新增)
    if 缺本腿 or 缺对方:
        行表 = ["   ★ 重叠核 %s：**一侧独有改动被丢** ⇒ 显式拒（防「保留双方裁决」做成一侧覆盖）：" % 路径]
        if 缺本腿:
            行表.append("     缺**本腿**独有改动 %d 行：%s" % (len(缺本腿), " / ".join(缺本腿[:6])))
        if 缺对方:
            行表.append("     缺**对方侧**独有改动 %d 行：%s" % (len(缺对方), " / ".join(缺对方[:6])))
        return 1, 行表
    return 0, ["   重叠核 %s：双方独有改动都在（本腿 %d 行 · 对方侧 %d 行）"
             % (路径, len(本腿新增), len(对方新增))]


def 解析冲突块(全文) -> list:
    """从带冲突标记的文本里摊出各块 ⇒ `[(起始行, 结束行, 我方行表, 对方行表)]`。"""
    源码行表 = 全文.splitlines()
    块表, 游标位 = [], 0
    while 游标位 < len(源码行表):
        if 源码行表[游标位].startswith(冲突起始标记):
            起始行号 = 游标位
            我方行表 = []
            游标位 += 1
            while 游标位 < len(源码行表) and not 源码行表[游标位].startswith(冲突分隔标记):
                我方行表.append(源码行表[游标位])
                游标位 += 1
            对方行表 = []
            游标位 += 1
            while 游标位 < len(源码行表) and not 源码行表[游标位].startswith(冲突结束标记):
                对方行表.append(源码行表[游标位])
                游标位 += 1
            块表.append((起始行号 + 1, 游标位 + 1, 我方行表, 对方行表))
        游标位 += 1
    return 块表


def _压成一行(行表) -> str:
    正文文本 = " / ".join(源码行.strip() for 源码行 in 行表 if 源码行.strip())
    return 正文文本[:200] or "（空）"


def 双方裁决报告(集成树, 路径表) -> list:
    """逐件把冲突标记里的**两侧值 + 行区间**摊开 ⇒ 行表（**不取一侧**）。"""
    行表 = []
    for 路径 in sorted(路径表):
        件路径 = Path(集成树) / 路径
        try:
            全文 = 件路径.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            行表.append("     %s：非文本件（二进制冲突）⇒ 交人裁" % 路径)
            continue
        块表 = 解析冲突块(全文)
        if not 块表:
            行表.append("     %s：未见冲突标记 ⇒ 按已解决走核双方裁决齐" % 路径)
            continue
        行表.append("     %s（冲突块 %d 个）：" % (路径, len(块表)))
        for 序号, (起始行, 结束行, 主侧行表, 腿侧行表) in enumerate(块表, 1):
            行表.append("       块 %d · 行 %d–%d" % (序号, 起始行, 结束行))
            行表.append("         主干/对方侧：%s" % _压成一行(主侧行表))
            行表.append("         本腿：%s" % _压成一行(腿侧行表))
    return 行表


def 审重叠(开工号, 集成树, 腿分支, 冲突表=(), 连接=None) -> tuple:
    """合腿后的重叠工序 ⇒ `(退出码, 行表, 已知重叠路径集)`。

    退出码 0 = 可继续（**无重叠登记** / 重叠件**双方裁决齐**）；非 0 = 拒（出报告或核不过）。
    **已知重叠路径集** = 本腿认领重叠的件 —— 编排拿它把**未知冲突**留给原拒绝语义。
    """
    重叠集 = 重叠路径集(开工号, 连接)
    if not 重叠集:
        return 0, ["   重叠工序：本腿无 `认领重叠` 登记 ⇒ 本工序休眠（按原拒绝语义）"], set()
    集成树 = Path(集成树)
    基码, 基输出 = _跑(["git", "merge-base", 主干引用, 腿分支], 集成树)
    if 基码 != 0:
        return 1, ["   重叠工序：合并基读不出（`git merge-base %s %s` 退出码 %d）⇒ 拒：%s"
                % (主干引用, 腿分支, 基码, 基输出.strip()[:200])], 重叠集
    基提交 = 基输出.strip()
    同片段 = sorted(重叠集 & (set(冲突表) | 未合并集(集成树)))
    行表 = ["   重叠工序：本腿认领重叠 %d 件（%s）" % (len(重叠集), " · ".join(sorted(重叠集)))]
    if 同片段:
        行表.append("   ★ 已知重叠**同片段 / 嵌套冲突** ⇒ 双方裁决报告（**不静默取一侧**）：")
        行表.extend(双方裁决报告(集成树, 同片段))
        行表.append("   入口：`v1_task 操作=接管集成 开工ID=%s` 正式接管集成树后用 `v1_edit` 解冲突"
                  "（**保留双方**），再 `合并主干.py %s --恢复现场` —— 收口时本工序核双方裁决齐。"
                  % (开工号, 开工号))
        return 1, 行表, 重叠集
    核码 = 0
    for 路径 in sorted(重叠集):
        核件码, 核行表 = 核双方裁决齐(集成树, 腿分支, 路径, 基提交)
        行表.extend(核行表)
        核码 = 核码 or 核件码
    return 核码, 行表, 重叠集
