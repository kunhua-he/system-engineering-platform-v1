# -*- coding: utf-8 -*-
"""禁改面 —— **唯一一份**「这个件不许手改」判据：`v1_edit`（功能 0/1/2）与 `批量改名`（功能 9）同调。

**为什么要有它**（2026-10-05 审计 B-3 实测）：`v1_edit` 原先四道闸里**没有这一面** ⇒ 一条腿只要
认领了生成物（`契约声明/src/声明数据.rs`）或冻结公开面（`契约声明/src/契约声明/平台形状.rs`），
就能用 `v1_edit 功能 = 1` 手改；`功能 = 0` 还能往 `只读参考/`、`制品产物/` 建件。而 `AGENTS.md §二`
明写「不许手改生成物」「不许碰 `只读参考/`」。功能 = 9 早就有这一面（原 `批量改名.禁改原因`），
`v1_edit` 没有 ⇒ **不对称**。故把那一面**提成本件**，两处**同一份**调用（不写第二套）。

**四条面**：
  · **生成物** —— 件头自称产物、不许手改（判据 ⑩ 的产物头标口径：改源 + 重跑生成器）；
  · **冻结公开面** —— 件在 `契约声明/` 且件头自称「逐字不变」（跨边界 ABI，`命名口径-10`）；
  · **只读参考** —— 路径里有 `只读参考` 段（只读：不许写、不许 import、不许读）；
  · **制品产物** —— 路径里有 `制品产物` 段（被 git 忽略的生成物快照：要改就改源再重出）。

前两条**只扫件头**（文件开头的注释块 + 模块文档串，到第一个代码行为止）且要求件头**自称** ——
讲**别件**的冻结（`登记.py` 引 `错误码形状.rs` 的「逐字不变」）与在**代码里发射**标记
（`渲染.py` 把标记写进一个字符串字面量）都不算（否则整批 fail-closed 误拦）。后两条只看路径。
"""

import sys
from pathlib import Path

工具根 = Path(__file__).resolve().parents[2]
for 子目录 in (str(工具根 / "开发工具"), str(工具根 / "开发工具" / "信息核心"),
             str(工具根 / "构建装配" / "一键验证")):
    if 子目录 not in sys.path:
        sys.path.insert(0, 子目录)

from 一键验证.判据_台账号 import 是制品产物  # noqa: E402  —— 制品产物段判定**只此一份**，不抄第二份


def 禁改原因(路径: str, 全文: str) -> str:
    """**禁改面**（路径面 + 件头面）⇒ 原因（空 = 可改）。`v1_edit` 与 `批量改名` **同调这一份**。

    路径面先判（不必读件）：`只读参考` 段 / `制品产物` 段。
    件头面：只扫**件头**（文件开头的注释块 + 模块文档串，到第一个代码行为止），且要求件头
    **自称** —— 讲**别件**的冻结（`登记.py` 引 `错误码形状.rs` 的「逐字不变」）与在**代码里
    发射**标记（`渲染.py` 的 `渲染器("// 生成物，禁手改…")`）都不算。
      · 生成物 —— 件头同时出现「生成物」「禁手改」（真产物第 1 行就是这句）；
      · 冻结公开面 —— 件在 `契约声明/`（跨边界 ABI，`命名口径-10`）且件头出现「逐字不变」。
    """
    if "只读参考" in str(路径).split("/"):
        return "只读参考（`只读参考/` 只读 —— 不许写、不许 import、不许读）"
    if 是制品产物(路径):
        return "制品产物（被 git 忽略的生成物快照）—— 要改就改源再重出，别手改快照"
    头部, 引号符, 状态 = [], "", False
    for 一行 in 全文.splitlines()[:60]:
        一行 = 一行.strip()
        if 状态:
            头部.append(一行)
            if 引号符 in 一行:
                状态 = False
            continue
        if not 一行:
            头部.append(一行)
            continue
        if 一行.startswith(("//", "#", "/*", "*")):
            头部.append(一行)
            continue
        if 一行[:3] in ('"""', "'''") or 一行[:4] in ('r"""', "r'''", 'u"""', "u'''",
                                                   'b"""', "b'''", 'f"""', "f'''"):
            引号符 = '"""' if '"""' in 一行 else "'''"
            头部.append(一行)
            if 一行.count(引号符) < 2:
                状态 = True
            continue
        break  # 第一个代码行 ⇒ 件头到此为止
    头部 = "\n".join(头部)
    if "生成物" in 头部 and "禁手改" in 头部:
        return "生成物（件头自称「生成物，禁手改」）—— 改源 + 重跑生成器，别手改产物"
    # ★ 2026-10-06（命名债务收口 · 开工 v1-100334）：**撤掉「冻结公开面」这道面**。
    #   依据：华哥裁决「能修就修、不能修就重构、不怕麻烦、只要干净」+ 设计哲学 §总纲（砍代码优先）。
    #   冻结形状的**真正守卫是判据 ⑨**（`冻结登记.json` 的 `形状指纹` 逐条比对）——
    #   改名后必须重算指纹并同步 `冻结登记.json`，对不上即红。禁改面**再拦一道**会让
    #   「真改 + 同步指纹」这条正路走不通（`功能=9` 与 `v1_edit` 都拒）⇒ 与裁决冲突。
    #   生成物 / 只读参考 / 制品产物 三面**保留**（那三条与冻结形状无关）。
    return ""
