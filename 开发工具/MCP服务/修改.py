def _已过条目行(项表: list, 失败序号集: set) -> str:
    """一次「整批拒」里**没被点到**的那些条目 ⇒ 一行「已过预检（但同样没写盘）」。

    **为何要有它**（2026-10-08 · 560 清理腿实测）：整批拒是**全批 0 写盘**（原子性）⇒ 回执只报
    出错那几条时，调用方不知道哪几条其实已经过了，常把整批原样重发（白跑）。把「已过条目」
    列出来，重发时就能**只改要修的那几条、其余原样带上**。全批都不过 / 全批都过 ⇒ 不报（没信息量）。

    ★ 2026-10-13（债务 564）措辞纠偏：原回执写「这次不必重发」**与同一句里的「整批 0 写盘」
    自相矛盾** —— 一条都没写进盘，已过预检的条目**同样要重发**（只是内容不必再改）。
    实测按字面理解会只重发被点名那条，其余静默丢失（真丢过一条）⇒ 措辞改为「已过预检、
    重发时原样带上」。
    """
    过表 = [str(序号) for 序号, 改动行 in enumerate(项表, 1) if 序号 not in 失败序号集]
    if not 过表 or len(过表) == len(项表):
        return ""
    return ("★ 已过预检（**但整批 0 写盘 ⇒ 它们同样要重发**，只是内容不必再改）的条目：第 %s 条"
            "（重发 = 要修的那几条改好 + 这几条原样带上，一条都不能少）。"
            % " · ".join(过表))


def 修改一次(参数表: dict, 仓根) -> tuple:
    """`v1_edit` 的入口。"""
    if not isinstance(参数表.get("只检查", False), bool):
        return 2, "`只检查` 要传 真/假 ⇒ 收到 %r；不查就整个去掉这个键" % (参数表.get("只检查"),)
    if 参数表.get("只检查", False):
        from .批量预检 import 派发 as 修改派
        return 修改派(参数表, 仓根)
    开工号 = str(参数表.get("开工ID") or "").strip()
    if not 开工号:
        return 2, "缺 `开工ID` ⇒ 先跑 v1_task 操作=登记 拿开工号，再把它传进来"
    沿用 = 参数表.get("沿用上次")
    if 沿用 is not None and not isinstance(沿用, str):
        return 2, "`沿用上次` 要传字符串（`只检查` 回执里给的那个）⇒ 收到 %r" % (沿用,)
    改动表 = 参数表.get("改动表")
    if 沿用 and 沿用.strip():
        # 短引用（2026-10-08 · 540 腿实测）：取 `只检查` 查过的那份表 ⇒ 大表不必重传。
        # 失效 / 对不上 ⇒ **明确拒**（不静默重查、不静默用旧表）。
        存表 = 取凭据(开工号, 沿用.strip())
        if not 存表:
            return 3, ("`沿用上次` = `%s` 本会话没查过（或属别条开工）⇒ 先跑一次 `只检查` 拿新引用"
                    % 沿用.strip())
        if 改动表 and 改动表指纹(改动表) != 沿用.strip():
            # 只在**真给了非空改动表**且与短引用对不上时拒（空表 / 没给 = 沿用），免得把
            # 调用方一句「沿用」误判成「篡改」。
            return 3, ("`沿用上次` = `%s` 与本次给的 `改动表` 不是同一份 ⇒ 二者只给一个："
                    "要沿用就只给 `沿用上次`，要改就整份重给" % 沿用.strip())
        改动表 = 存表
    if not isinstance(改动表, list) or not 改动表:
        return 2, "缺 `改动表` ⇒ 补上它（一次一条改动，多条就放多项；`只检查` 过了也可改传 `沿用上次`）"

