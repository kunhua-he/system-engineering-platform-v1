from .禁改面 import 禁改原因

功能_新建 = 0
功能_修改 = 1
功能_删除 = 2
功能名表 = {功能_新建: "新建", 功能_修改: "修改", 功能_删除: "删除"}

写盘后缀 = ".v1edit-tmp"          # 不含 `_临时_`：源码树里禁那个前缀（判据 ⑰）


# ── 共用：对账（「盘上指纹 == 账本指纹」）────────────────────────────────────────────────

def 对账(工作树: Path, 认领表: dict) -> tuple:
    """`({路径: 指纹}, {路径: (账本指纹, 盘上指纹)})` —— 对得上的 / 变过的。

    **一处实现，两处用**：`修改` 拿它当第 ③ 道闸（变过 ⇒ 拒写）；`门禁` 拿它当绕过检测
    （变过 ⇒ 报「这个件被绕过 MCP 改过」）。
    """
    对得上表, 变过表 = {}, {}
    for 相对路径, 账本指纹 in 认领表.items():
        件路径 = 工作树 / 相对路径
        盘上指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
        对得上表[相对路径] = 盘上指纹
        if 盘上指纹 != 账本指纹:
            变过表[相对路径] = (账本指纹, 盘上指纹)
    return 对得上表, 变过表


def 对账_除源件(工作树: Path, 认领表: dict, 源件表) -> tuple:
    """`对账` 之后把**经 `功能 = 6`（源件记账）记过的源件**从「变过」里剔出去 ⇒
    `(对得上表, 变过表, 放行表)`。

    为什么放行：那些件是**二进制源**（规则库 `.db` 一类），`v1_edit` 改不了它 —— 只能由仓内命令
    改 + `功能 = 6` 记账（AGENTS.md §二 明写这条路）。对它们做「盘上 == 账本」的绕过检测是**误报**
    （实测腿 v1-100235：释放前 `v1_gate` 把正当的库改动报成「绕过 MCP 改过」）。
    放行的只限 `源件表`（`开工账本.源件路径集`）里那些；**没记过的照旧报**。
    """
    对得上表, 变过表 = 对账(工作树, 认领表)
    放行表 = {路径: 键值对 for 路径, 键值对 in 变过表.items() if 路径 in 源件表}
    变过表 = {路径: 键值对 for 路径, 键值对 in 变过表.items() if 路径 not in 源件表}
    return 对得上表, 变过表, 放行表


# ── 一条改动的字段校验 ──────────────────────────────────────────────────────────────────

def _读一条改动(一条) -> tuple:
    """把一条改动的字段读出来 ⇒ `(路径, 功能号, 旧内容, 新内容, 错误)`。"""
    if not isinstance(一条, dict):
        return "", None, "", "", "改动表里每一条要是对象（`{路径, 功能, 旧内容, 新内容}`）"
    路径 = str(一条.get("路径") or "").strip()
    if not 路径:
        return "", None, "", "", "缺 `路径`"
    if 路径.startswith("/") or ".." in Path(路径).parts:
        return 路径, None, "", "", "`路径` 只许仓内相对路径（不许绝对路径 / 不许 `..`）"
    try:
        功能号 = int(一条.get("功能"))
    except (TypeError, ValueError):
        return 路径, None, "", "", "缺 `功能`：0=新建 · 1=修改 · 2=删除"
    if 功能号 not in 功能名表:
        return 路径, None, "", "", "`功能` 只认 0/1/2，收到 %r" % (一条.get("功能"),)
    旧内容 = 一条.get("旧内容")
    新内容 = 一条.get("新内容")
    旧内容 = "" if 旧内容 is None else str(旧内容).replace("\r\n", "\n")
    新内容 = "" if 新内容 is None else str(新内容).replace("\r\n", "\n")
    return 路径, 功能号, 旧内容, 新内容, ""


def _查改动字段(功能号: int, 旧内容: str, 新内容: str) -> str:
    """按功能查字段合法性 ⇒ 错误说明（空 = 合法）。"""
    if 功能号 == 功能_新建:
        if 旧内容:
            return "功能 = 0 新建：**不传 `旧内容`**（新建没有「原文」可对）"
        if not 新内容:
            return "功能 = 0 新建：要 `新内容`（不然建出来是个空件，没意义）"
    if 功能号 == 功能_修改:
        if not 旧内容:
            return ("功能 = 1 修改：要 `旧内容`（**按内容定位，不按行号**）。"
                  "要插行就把锚点行同时写进旧内容和新内容里")
        if 旧内容 == 新内容:
            return "功能 = 1 修改：`旧内容` 与 `新内容` 一模一样 ⇒ 空转，不写"
    if 功能号 == 功能_删除:
        if not 旧内容:
            return "功能 = 2 删除：要 `旧内容`（删错件是不可逆的，得先证明你要删的就是它）"
    return ""


def _定位旧内容(全文: str, 旧内容: str) -> tuple:
    """`旧内容` 在全文里的**全部出现位置** ⇒ `[位置…]`（空表 = 找不到）。"""
    位表, 区间起点 = [], 0
    while True:
        位置 = 全文.find(旧内容, 区间起点)
        if 位置 < 0:
            return 位表
        位表.append(位置)
        区间起点 = 位置 + 1


def _写文件(件路径: Path, 全文: str) -> str:
    """**临时件 + rename**（同目录、同文件系统 ⇒ 原子的）⇒ 错误说明（空 = 成功）。

    为什么不 `write_text`：它是「截断 + 写」，中途崩了会留一个**半截文件** ——
    那是把「拒」变成了「毁」。
    """
    临时路径 = 件路径.with_name(件路径.name + 写盘后缀)
    try:
        临时路径.write_text(全文, encoding="utf-8", newline="\n")
        os.replace(临时路径, 件路径)
    except OSError as 写不动的原因:
        临时路径.unlink(missing_ok=True)
        return "写盘失败：%r" % (写不动的原因,)
    return ""


# ── 闸 ⑤：命名登记（写盘即拒）────────────────────────────────────────────────

# 依据：华哥 2026-09-28「出现即须定义，未定义即红」· 2026-09-29「用规则管 · 直接提示错误」。
# 面 = **形参 + 局部绑定**（索引看不见的那两层；定义面由判据 ㊷ 在闸 0 兜）。
# 扫描器与判据 ㉒/㊷ **同一份**（不另写一套）；名册与基线住**被改的那棵树**的规则库，
# 所以腿当场 `登记` 出来的名立刻可见。
# ★ 2026-09-30 收口：「名是否已定义」的判定**只此一份**（`命名穷举.判未登记`）。本件原先
#   自拼 `唯一名 | 例外 | 基线键` —— 那是**第二套实现**，且把基线**按名**放行 ⇒ 比判据的
#   `(面, 名)` 宽（同一名在别的面当债、这里当形参用，会「闸放行、判据报红」）。现已删除。


def _未登记绑定名(工作树: Path, 项表: list) -> tuple:
    """新内容里**新引入的绑定名**里、名册 / 例外 / 存量基线都不收的那些 ⇒ `(名表, 错误或 None)`。

    ★ 判定**只此一份**：`命名穷举.判未登记(..., 存量基线, 含存量基线=True)` —— 与判据 ㊷
      同一份实现，差异只是那个开关（写盘闸要放行存量债，判据要它报出来再分档）。
    ★ **fail-closed**：名册 / 基线读不动 ⇒ 交错误回去，调用方**拒写**（一个字节都不写）。
    """
    import sys as _sys

    工具根 = Path(__file__).resolve().parents[2]
    for 子目录 in (str(工具根 / "开发工具"), str(工具根 / "开发工具" / "信息核心"),
                 str(工具根 / "构建装配" / "一键验证")):
        if 子目录 not in _sys.path:
            _sys.path.insert(0, 子目录)
    import 命名穷举 as 穷举
    import 命名基线 as 基线件

    try:
        唯一名, 例外 = 穷举.读名册(工作树)
    except 穷举.名册读不动 as 错误:
        return [], str(错误)
    基线表, 错误 = 基线件.读穷举基线(工作树)
    if 错误:
        return [], 错误
    存量基线 = set(基线表)              # `{(面, 名)}` —— 面也要对上（与判据 ㊷ 同口径）
    后缀表 = tuple(穷举.查名.命名后缀)
    出现表 = {穷举.面_形参: [], 穷举.面_局部: []}
    for 路径, 功能号, 旧内容, 新内容 in 项表:
        if 功能号 == 功能_删除 or not 新内容 or not 路径.endswith(后缀表):
            continue
        件后缀 = "." + 路径.rsplit(".", 1)[-1]
        出现表[穷举.面_形参] += [(形参名, 路径, 行号) for 行号, _函数名, 形参名 in
                            穷举.形参面.扫文本(路径, 新内容, 只单字=False)]
        出现表[穷举.面_局部] += [(绑定名, 路径, 行号) for 行号, 绑定名 in
                            穷举.命名扫描.扫局部绑定(件后缀, 新内容, 只单字=False)]
    未登记 = 穷举.判未登记(出现表, 唯一名, 例外, 存量基线, 含存量基线=True)
    return sorted({出现名 for 面表 in 未登记.values() for 出现名 in 面表}), None


# ── 主流程 ──────────────────────────────────────────────────────────────────────────────

def 派发(参数表: dict, 仓根) -> tuple:
    """`v1_edit` 的入口。"""
    开工号 = str(参数表.get("开工ID") or "").strip()
    if not 开工号:
        return 2, "缺 `开工ID`（`v1_task` 功能 = 1 登记时返回的那个）"
    改动表 = 参数表.get("改动表")
    if not isinstance(改动表, list) or not 改动表:
        return 2, "缺 `改动表`（一次一条改动，要改多个就放多条）"

    连接 = 账本.连账本()
    try:
        一条开工 = 账本.读开工(连接, 开工号)
        if not 一条开工:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记（`v1_task`）" % 开工号
        if 一条开工["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能再改。要接着干就新开一条" % 一条开工["状态"]
        工作树 = Path(一条开工["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再改（别改了状态、活却找不回）" % 工作树

        # ── 读全表 ──
        项表 = []
        for 一条 in 改动表:
            路径, 功能号, 旧内容, 新内容, 错误 = _读一条改动(一条)
            if 错误:
                return 2, "改动表第 %d 条：%s" % (len(项表) + 1, 错误)
            错误 = _查改动字段(功能号, 旧内容, 新内容)
            if 错误:
                return 2, "改动表第 %d 条：%s" % (len(项表) + 1, 错误)
            项表.append((路径, 功能号, 旧内容, 新内容))

        # ── 闸 ② 认领集（全批先验）──
        认领表 = 账本.读认领(连接, 开工号)
        # ★ 功能 = 0 新建的件**盘上还不存在** ⇒ 认领那一刻读不到盘、进不了认领集
        #   （`读盘指纹` 只收读得到的件）⇒ 「没认领」这一条对新建要放宽：
        #   不在认领集里**且**盘上确实不存在 ⇒ 放行。写完之后指纹会补进认领表（`写回指纹` 是 upsert）。
        #   存在却不认领的仍然拒 —— 那才是真的越界。（实测：不放宽 ⇒ 新建永远被挡死。）
        新建待建集 = {路径 for 路径, 功能号, _, _ in 项表
                    if 功能号 == 功能_新建 and not (工作树 / 路径).exists()}
        越界表 = sorted({路径 for 路径, _, _, _ in 项表
                      if 路径 not in 认领表 and 路径 not in 新建待建集})
        if 越界表:
            return 3, ("**拒**（第 ② 道闸 · 认领）：这些路径不在开工 %s 的认领集里 ⇒ "
                     "先 `v1_task` 功能 = 2 补认领：\n  %s" % (开工号, "\n  ".join(越界表)))

        # ── 闸 ③ 指纹（全批先验；这一条同时是「绕过检测」）──
        # 新建的件**认领表里没有它那一行**（认领时盘上还不存在）⇒ 只对认领表里有的件对账；
        # 其余的由第 ② 道闸的「新建待建集」兜着（它保证了盘上确实不存在）。
        盘上表, 变过表 = 对账(工作树, {路径: 认领表[路径] for 路径 in {路径 for 路径, _, _, _ in 项表}
                                 if 路径 in 认领表})
        # 新建的件本来就不存在 —— 盘上指纹为空是**预期**，不算「变过」。
        新建集 = {路径 for 路径, 功能号, _, _ in 项表 if 功能号 == 功能_新建}
        变过表 = {路径: 键值对 for 路径, 键值对 in 变过表.items() if 路径 not in 新建集}
        if 变过表:
            return 3, "**拒**（第 ③ 道闸 · 指纹）：这些件被**绕过 MCP** 改过（盘上指纹 ≠ 账本指纹）⇒\n%s\n%s" % (
                "\n".join("  %s：账本 %s → 盘上 %s" % (路径, 键值对[0] or "（无）", 键值对[1] or "（件没了）")
                        for 路径, 键值对 in sorted(变过表.items())),
                "一个字节都没写。用 `v1_task` 功能 = 2 重报这些件的指纹（它会**重读盘**），再发起修改。")
        for 路径, 功能号, _, _ in 项表:
            if 功能号 == 功能_新建 and (工作树 / 路径).exists():
                return 3, "**拒**（第 ② 道闸 · 新建）：`%s` 已经存在 ⇒ 要改它就用 功能 = 1" % 路径
            if 功能号 != 功能_新建 and not (工作树 / 路径).is_file():
                return 3, "**拒**（第 ③ 道闸 · 指纹）：`%s` 在盘上不存在 ⇒ 要新建就用 功能 = 0" % 路径

        # ── 闸 ⑥ 禁改面（全批先验）：生成物 / 冻结公开面 / 只读参考 / 制品产物 一律拒写 ──
        # 与 `批量改名` **同一份**实现（`禁改面.py`）—— 功能 = 9 早有这一面，`v1_edit` 原先没有
        # （审计 B-3）⇒ 认领了生成物就能手改。路径面先判；件头面要读全文，读不动（二进制 /
        # 非 utf-8）⇒ 结构化拒（fail-closed），不抛未捕获异常（审计「存疑 4」）。
        禁改表 = {}
        for 路径, 功能号, _, 新内容 in 项表:
            try:
                全文 = 新内容 if 功能号 == 功能_新建 else (工作树 / 路径).read_text(
                    encoding="utf-8", newline="\n")
                原因 = 禁改原因(路径, 全文)
            except UnicodeDecodeError:
                原因 = ("不是 utf-8 文本（二进制件）⇒ `v1_edit` 只改文本件；"
                      "二进制源件走 `v1_task` 功能 = 6 源件记账")
                原因 = 禁改原因(路径, "") or 原因
            if 原因:
                禁改表[路径] = 原因
        if 禁改表:
            return 3, ("**拒**（第 ⑥ 道闸 · 禁改面）：这些件不许手改：\n%s"
                     % "\n".join("  %s：%s" % (路径, 原因) for 路径, 原因 in sorted(禁改表.items())))

        # ── 闸 ⑤ 命名登记（全批先验）：新内容里**新引入的绑定名**必须在规则库里 ──
        未登记名表, 错误 = _未登记绑定名(工作树, 项表)
        if 错误:
            return 5, ("**拒**（第 ⑤ 道闸 · 命名登记）：读不动规则库 ⇒ **fail-closed**：%s\n"
                     "修法：在**这棵工作树**里跑 `python3 开发工具/信息核心/信息核心.py 建库`"
                     % 错误)
        if 未登记名表:
            return 5, ("**拒**（第 ⑤ 道闸 · 命名登记）：这些名没登记（也不在存量基线里）⇒ "
                     "先登记再用：\n  %s\n"
                     "登记（在**这棵工作树**里跑）：`python3 开发工具/信息核心/信息核心.py "
                     "登记 <名> …` —— 名册与基线都住规则库（`开发工具/信息核心/信息核心.db`）。\n"
                     "口径：华哥 2026-09-28「出现即须定义，未定义即红」—— 名要在库 `命名定义` 表里，"
                     "或属库 `命名例外`（语言强加）。面 = 形参 + 局部绑定（定义面由判据 ㊷ 在闸 0 兜）。"
                     % "\n  ".join(未登记名表))

        # ── 逐条：④ 定位 → 写盘 → 更新账本（索引在整批之后刷一次，见下）──
        完成表, 失败说明 = [], ""
        for 序号, (路径, 功能号, 旧内容, 新内容) in enumerate(项表, 1):
            件路径 = 工作树 / 路径
            写前指纹 = 盘上表.get(路径) or (文件指纹(str(件路径)) if 件路径.is_file() else "")
            if 功能号 == 功能_新建:
                if not 件路径.parent.is_dir():
                    失败说明 = ("第 %d 条 `%s`：父目录 `%s` 不存在 ⇒ 拒。本仓规矩是"
                            "「磁盘上多出来的目录必须回来登记进 README §五 目录树」——"
                            "先建目录并登记，再来建件" % (序号, 路径, 件路径.parent.name))
                    break
                全文 = 新内容 if 新内容.endswith("\n") else 新内容 + "\n"
                错误 = _写文件(件路径, 全文)
            else:
                try:
                    全文 = 件路径.read_text(encoding="utf-8", newline="\n")
                except UnicodeDecodeError:
                    失败说明 = ("第 %d 条 `%s`：不是 utf-8 文本（二进制件）⇒ 拒（`v1_edit` 只改"
                            "文本件；二进制源件走 `v1_task` 功能 = 6 源件记账）" % (序号, 路径))
                    break
                位表 = _定位旧内容(全文, 旧内容)
                if not 位表:
                    失败说明 = ("第 %d 条 `%s`：**找不到** `旧内容` ⇒ 拒（文件已变，"
                            "请重新读一次这个件再发起修改）" % (序号, 路径))
                    break
                if len(位表) > 1:
                    行号表 = [全文[:位置].count("\n") + 1 for 位置 in 位表]
                    失败说明 = ("第 %d 条 `%s`：`旧内容` 在文件里出现 **%d 次**（行 %s）⇒ 拒。"
                            "多给几行上下文，让它唯一" % (序号, 路径, len(位表),
                                              " · ".join(str(行序号) for 行序号 in 行号表[:8])))
                    break
                位置 = 位表[0]
                if 功能号 == 功能_删除:
                    件路径.unlink()
                    错误 = ""
                else:
                    错误 = _写文件(件路径, 全文[:位置] + 新内容 + 全文[位置 + len(旧内容):])
            if 错误:
                失败说明 = "第 %d 条 `%s`：%s" % (序号, 路径, 错误)
                break
            写后指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
            账本.写回指纹(连接, 开工号, 路径, 写后指纹)
            账本.记改动(连接, 开工号, 路径, 功能名表[功能号], 写前指纹, 写后指纹)
            完成表.append("%s（%s）" % (路径, 功能名表[功能号]))

        # ── 刷索引（**整批一次**）──
        # 为什么不必每条都刷：定位靠**内容**不靠行号 ⇒ 下一条不依赖索引的新旧；
        # 一次 sync 实测 389 ms，N 条改动的批不必付 N 次。（本注释原先写「每条写完都刷」——
        # 那是设计初稿的说法，代码一直是循环外刷一次；注释已改回实话。）
        退出码, 说明 = 同步索引(工作树)
        输出行表 = ["%s：改了 %d/%d 条 —— %s" % (开工号, len(完成表), len(项表),
                                            " · ".join(完成表) or "（无）"),
                  "索引：%s" % 说明]
        if 失败说明:
            输出行表.append("**%s**" % 失败说明)
            if 完成表:
                输出行表.append("（前面 %d 条已经写进盘了 —— 本工具是逐条写的，不是整批回滚）"
                            % len(完成表))
            return 4, "\n".join(输出行表)
        return 0, "\n".join(输出行表)
    finally:
        连接.close()
