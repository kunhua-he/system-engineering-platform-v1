# ── 共用：对账（「盘上指纹 == 账本指纹」）────────────────────────────────────────────────

def 对账(工作树: Path, 认领表: dict) -> tuple:
    """`({路径: 指纹}, {路径: (账本指纹, 盘上指纹)})` —— 对得上的 / 变过的。

    **一处实现，两处用**：`修改` 拿它当第 ③ 道闸（变过 ⇒ 拒写）；`门禁` 拿它当绕过检测
    （变过 ⇒ 报「这个件被绕过 MCP 改过」）。
    """
    对得上表, 变过表 = {}, {}
    for 相对路径, 账本指纹 in 认领表.items():
        件路径 = 工作树 / 相对路径
        盘上指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
        对得上表[相对路径] = 盘上指纹
        if 盘上指纹 != 账本指纹:
            变过表[相对路径] = (账本指纹, 盘上指纹)
    return 对得上表, 变过表


def 对账_除源件(工作树: Path, 认领表: dict, 源件表) -> tuple:
    """`对账` 之后把**经 `功能 = 6`（源件记账）记过的源件**从「变过」里剔出去 ⇒
    `(对得上表, 变过表, 放行表)`。

    为什么放行：那些件是**二进制源**（规则库 `.db` 一类），`v1_edit` 改不了它 —— 只能由仓内命令
    改 + `功能 = 6` 记账（AGENTS.md §二 明写这条路）。对它们做「盘上 == 账本」的绕过检测是**误报**
    （实测腿 v1-100235：释放前 `v1_gate` 把正当的库改动报成「绕过 MCP 改过」）。
    放行的只限 `源件表`（`开工账本.源件路径集`）里那些；**没记过的照旧报**。
    """
    对得上表, 变过表 = 对账(工作树, 认领表)
    放行表 = {路径: 键值对 for 路径, 键值对 in 变过表.items() if 路径 in 源件表}
    变过表 = {路径: 键值对 for 路径, 键值对 in 变过表.items() if 路径 not in 源件表}
    return 对得上表, 变过表, 放行表


# ── 一条改动的字段校验 ──────────────────────────────────────────────────────────────────

def _读一条改动(改动项) -> tuple:
    """把一条改动的字段读出来 ⇒ `(路径, 功能号, 旧内容, 新内容, 全替, 错误)`。

    `全替`（2026-10-08 加）= 真 时 `旧内容` 换掉**全部**出现处（replace_all）；缺省假 ⇒ 仍旧口径
    （必须**唯一**）。它只对 功能 = 1 修改 有意义（新建 / 删除没有「多处出现」这回事）。
    """
    if not isinstance(改动项, dict):
        return "", None, "", "", None, "改动表里每一条要是对象（`{路径, 功能, 旧内容, 新内容}`）"
    路径 = str(改动项.get("路径") or "").strip()
    if not 路径:
        return "", None, "", "", None, "缺 `路径`"
    if 路径.startswith("/") or ".." in Path(路径).parts:
        return 路径, None, "", "", None, "`路径` 只许仓内相对路径（不许绝对路径 / 不许 `..`）"
    try:
        功能号 = int(改动项.get("功能"))
    except (TypeError, ValueError):
        return 路径, None, "", "", None, "缺 `功能`：0=新建 · 1=修改 · 2=删除"
    if 功能号 not in 功能名表:
        return 路径, None, "", "", None, "`功能` 只认 0/1/2，收到 %r" % (改动项.get("功能"),)
    旧内容 = 改动项.get("旧内容")
    新内容 = 改动项.get("新内容")
    旧内容 = "" if 旧内容 is None else str(旧内容).replace("\r\n", "\n")
    新内容 = "" if 新内容 is None else str(新内容).replace("\r\n", "\n")
    全替 = 改动项.get("全替")
    if 全替 is not None and not isinstance(全替, bool):
        return 路径, None, "", "", None, "`全替` 要是逻辑型值（真 = 换掉全部出现处）"
    return 路径, 功能号, 旧内容, 新内容, bool(全替), ""


def _查改动字段(功能号: int, 旧内容: str, 新内容: str, 全替: bool = False) -> str:
    """按功能查字段合法性 ⇒ 错误说明（空 = 合法）。"""
    if 全替 and 功能号 != 功能_修改:
        return "`全替` 只对 功能=1 有意义 ⇒ 去掉 `全替`，或把 功能 改成 1"
    if 功能号 == 功能_新建:
        if 旧内容:
            return "功能=0 新建不传 `旧内容` ⇒ 去掉它（新建没有原文可对）"
        if not 新内容:
            return "功能=0 新建要 `新内容` ⇒ 补上它（不然建出来是空件）"
    if 功能号 == 功能_修改:
        if not 旧内容:
            return "功能=1 修改要 `旧内容` ⇒ 补上它（按内容定位；要插行就把锚点行同时写进 旧内容 和 新内容）"
        if 旧内容 == 新内容:
            return "`旧内容` 与 `新内容` 一模一样 ⇒ 空转；要删掉这段就只给 `旧内容`、别传 `新内容`"
