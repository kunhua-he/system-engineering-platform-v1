# -*- coding: utf-8 -*-
"""修改 —— `v1_edit` 的实现：四道闸 + **按内容定位** + 原子写盘。

**为什么不按行号改**（2026-09-27 实测）：`v1_symbol` 的行号来自**索引库**（快照），
而它返回的指纹是**现读盘**算的 ⇒ 同一条记录里两个数**不同源**。在 `开发工具/代码地图/落点.py`
顶上插一行、不刷索引：行号仍是 25、指纹却变了，而盘上真位置是 26。指纹闸比的是「账本 vs 盘」，
**比不出「索引 vs 盘」** ⇒ 会出现「指纹绿灯 + 行号错一格」= **静默改到隔壁那一行**。
`旧内容` 把这一整类换成「当场拒」。

**四道闸**（流程图 ② ③ ④ + 写盘）：
  ① 开工号存在且「进行中」
  ② 每个路径都在那条开工的认领集里
  ③ 账本里记的指纹 == 那条工作树里盘上的指纹（**这一条同时就是「绕过检测」**：
     对不上 ⇒ 有人绕过 MCP 改过它 —— `sed -i` · `cargo fmt` · 生成器 · 人手）
  ④ 旧内容能在文件里**唯一**定位到

**① ② ③ 全批先验**（任何一道不过 ⇒ **一个字节都不写**）；**④ 只能逐条**（前面写盘会改变文件）。
逐条走完「定位 → 写盘 → 刷索引 → 更新账本指纹」再走下一条 —— 因为定位靠内容不靠行号，**顺序无关**。
④ 在中途失败时**如实报**「第 N 条没改，前 N−1 条已改」。
"""

import os
from pathlib import Path

from 代码地图 import 同步, 文件指纹

from . import 开工账本 as 账本

功能_新建 = 0
功能_修改 = 1
功能_删除 = 2
功能名 = {功能_新建: "新建", 功能_修改: "修改", 功能_删除: "删除"}

写盘后缀 = ".v1edit-tmp"          # 不含 `_临时_`：源码树里禁那个前缀（判据 ⑰）


# ── 共用：对账（「盘上指纹 == 账本指纹」）────────────────────────────────────────────────

def 对账(工作树: Path, 认领表: dict) -> tuple:
    """`({路径: 指纹}, {路径: (账本指纹, 盘上指纹)})` —— 对得上的 / 变过的。

    **一处实现，两处用**：`修改` 拿它当第 ③ 道闸（变过 ⇒ 拒写）；`门禁` 拿它当绕过检测
    （变过 ⇒ 报「这个件被绕过 MCP 改过」）。
    """
    对得上表, 变过表 = {}, {}
    for 相对路径, 账本指纹 in 认领表.items():
        件路径 = 工作树 / 相对路径
        盘上指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
        对得上表[相对路径] = 盘上指纹
        if 盘上指纹 != 账本指纹:
            变过表[相对路径] = (账本指纹, 盘上指纹)
    return 对得上表, 变过表


# ── 一条改动的字段校验 ──────────────────────────────────────────────────────────────────

def _读一条(一条) -> tuple:
    """把一条改动的字段读出来 ⇒ `(路径, 功能号, 旧内容, 新内容, 错误)`。"""
    if not isinstance(一条, dict):
        return "", None, "", "", "改动表里每一条要是对象（`{路径, 功能, 旧内容, 新内容}`）"
    路径 = str(一条.get("路径") or "").strip()
    if not 路径:
        return "", None, "", "", "缺 `路径`"
    if 路径.startswith("/") or ".." in Path(路径).parts:
        return 路径, None, "", "", "`路径` 只许仓内相对路径（不许绝对路径 / 不许 `..`）"
    try:
        功能号 = int(一条.get("功能"))
    except (TypeError, ValueError):
        return 路径, None, "", "", "缺 `功能`：0=新建 · 1=修改 · 2=删除"
    if 功能号 not in 功能名:
        return 路径, None, "", "", "`功能` 只认 0/1/2，收到 %r" % (一条.get("功能"),)
    旧内容 = 一条.get("旧内容")
    新内容 = 一条.get("新内容")
    旧内容 = "" if 旧内容 is None else str(旧内容).replace("\r\n", "\n")
    新内容 = "" if 新内容 is None else str(新内容).replace("\r\n", "\n")
    return 路径, 功能号, 旧内容, 新内容, ""


def _查字段(功能号: int, 旧内容: str, 新内容: str) -> str:
    """按功能查字段合法性 ⇒ 错误说明（空 = 合法）。"""
    if 功能号 == 功能_新建:
        if 旧内容:
            return "功能 = 0 新建：**不传 `旧内容`**（新建没有「原文」可对）"
        if not 新内容:
            return "功能 = 0 新建：要 `新内容`（不然建出来是个空件，没意义）"
    if 功能号 == 功能_修改:
        if not 旧内容:
            return ("功能 = 1 修改：要 `旧内容`（**按内容定位，不按行号**）。"
                  "要插行就把锚点行同时写进旧内容和新内容里")
        if 旧内容 == 新内容:
            return "功能 = 1 修改：`旧内容` 与 `新内容` 一模一样 ⇒ 空转，不写"
    if 功能号 == 功能_删除:
        if not 旧内容:
            return "功能 = 2 删除：要 `旧内容`（删错件是不可逆的，得先证明你要删的就是它）"
    return ""


def _定位(全文: str, 旧内容: str) -> tuple:
    """`旧内容` 在全文里的**全部出现位置** ⇒ `[位置…]`（空表 = 找不到）。"""
    位表, 起 = [], 0
    while True:
        位 = 全文.find(旧内容, 起)
        if 位 < 0:
            return 位表
        位表.append(位)
        起 = 位 + 1


def _写盘(件路径: Path, 全文: str) -> str:
    """**临时件 + rename**（同目录、同文件系统 ⇒ 原子的）⇒ 错误说明（空 = 成功）。

    为什么不 `write_text`：它是「截断 + 写」，中途崩了会留一个**半截文件** ——
    那是把「拒」变成了「毁」。
    """
    临时路径 = 件路径.with_name(件路径.name + 写盘后缀)
    try:
        临时路径.write_text(全文, encoding="utf-8", newline="\n")
        os.replace(临时路径, 件路径)
    except OSError as 写不动的原因:
        临时路径.unlink(missing_ok=True)
        return "写盘失败：%r" % (写不动的原因,)
    return ""


# ── 主流程 ──────────────────────────────────────────────────────────────────────────────

def 派发(参数表: dict, 仓根) -> tuple:
    """`v1_edit` 的入口。"""
    开工号 = str(参数表.get("开工ID") or "").strip()
    if not 开工号:
        return 2, "缺 `开工ID`（`v1_task` 功能 = 1 登记时返回的那个）"
    改动表 = 参数表.get("改动表")
    if not isinstance(改动表, list) or not 改动表:
        return 2, "缺 `改动表`（一次一条改动，要改多个就放多条）"

    连 = 账本.连账本()
    try:
        一条开工 = 账本.读开工(连, 开工号)
        if not 一条开工:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记（`v1_task`）" % 开工号
        if 一条开工["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能再改。要接着干就新开一条" % 一条开工["状态"]
        工作树 = Path(一条开工["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再改（别改了状态、活却找不回）" % 工作树

        # ── 读全表 ──
        表 = []
        for 一条 in 改动表:
            路径, 功能号, 旧内容, 新内容, 错 = _读一条(一条)
            if 错:
                return 2, "改动表第 %d 条：%s" % (len(表) + 1, 错)
            错 = _查字段(功能号, 旧内容, 新内容)
            if 错:
                return 2, "改动表第 %d 条：%s" % (len(表) + 1, 错)
            表.append((路径, 功能号, 旧内容, 新内容))

        # ── 闸 ② 认领集（全批先验）──
        认领表 = 账本.读认领(连, 开工号)
        # ★ 功能 = 0 新建的件**盘上还不存在** ⇒ 认领那一刻读不到盘、进不了认领集
        #   （`读盘指纹` 只收读得到的件）⇒ 「没认领」这一条对新建要放宽：
        #   不在认领集里**且**盘上确实不存在 ⇒ 放行。写完之后指纹会补进认领表（`写回指纹` 是 upsert）。
        #   存在却不认领的仍然拒 —— 那才是真的越界。（实测：不放宽 ⇒ 新建永远被挡死。）
        新建待建集 = {路径 for 路径, 功能号, _, _ in 表
                    if 功能号 == 功能_新建 and not (工作树 / 路径).exists()}
        越界表 = sorted({路径 for 路径, _, _, _ in 表
                      if 路径 not in 认领表 and 路径 not in 新建待建集})
        if 越界表:
            return 3, ("**拒**（第 ② 道闸 · 认领）：这些路径不在开工 %s 的认领集里 ⇒ "
                     "先 `v1_task` 功能 = 2 补认领：\n  %s" % (开工号, "\n  ".join(越界表)))

        # ── 闸 ③ 指纹（全批先验；这一条同时是「绕过检测」）──
        # 新建的件**认领表里没有它那一行**（认领时盘上还不存在）⇒ 只对认领表里有的件对账；
        # 其余的由第 ② 道闸的「新建待建集」兜着（它保证了盘上确实不存在）。
        盘上表, 变过表 = 对账(工作树, {路径: 认领表[路径] for 路径 in {路径 for 路径, _, _, _ in 表}
                                 if 路径 in 认领表})
        # 新建的件本来就不存在 —— 盘上指纹为空是**预期**，不算「变过」。
        新建集 = {路径 for 路径, 功能号, _, _ in 表 if 功能号 == 功能_新建}
        变过表 = {路径: 对 for 路径, 对 in 变过表.items() if 路径 not in 新建集}
        if 变过表:
            return 3, "**拒**（第 ③ 道闸 · 指纹）：这些件被**绕过 MCP** 改过（盘上指纹 ≠ 账本指纹）⇒\n%s\n%s" % (
                "\n".join("  %s：账本 %s → 盘上 %s" % (路径, 对[0] or "（无）", 对[1] or "（件没了）")
                        for 路径, 对 in sorted(变过表.items())),
                "一个字节都没写。用 `v1_task` 功能 = 2 重报这些件的指纹（它会**重读盘**），再发起修改。")
        for 路径, 功能号, _, _ in 表:
            if 功能号 == 功能_新建 and (工作树 / 路径).exists():
                return 3, "**拒**（第 ② 道闸 · 新建）：`%s` 已经存在 ⇒ 要改它就用 功能 = 1" % 路径
            if 功能号 != 功能_新建 and not (工作树 / 路径).is_file():
                return 3, "**拒**（第 ③ 道闸 · 指纹）：`%s` 在盘上不存在 ⇒ 要新建就用 功能 = 0" % 路径

        # ── 逐条：④ 定位 → 写盘 → 更新账本（索引在整批之后刷一次，见下）──
        完成表, 失败说明 = [], ""
        for 序号, (路径, 功能号, 旧内容, 新内容) in enumerate(表, 1):
            件路径 = 工作树 / 路径
            写前指纹 = 盘上表.get(路径) or (文件指纹(str(件路径)) if 件路径.is_file() else "")
            if 功能号 == 功能_新建:
                if not 件路径.parent.is_dir():
                    失败说明 = ("第 %d 条 `%s`：父目录 `%s` 不存在 ⇒ 拒。本仓规矩是"
                            "「磁盘上多出来的目录必须回来登记进 README §五 目录树」——"
                            "先建目录并登记，再来建件" % (序号, 路径, 件路径.parent.name))
                    break
                全文 = 新内容 if 新内容.endswith("\n") else 新内容 + "\n"
                错误 = _写盘(件路径, 全文)
            else:
                全文 = 件路径.read_text(encoding="utf-8", newline="\n")
                位表 = _定位(全文, 旧内容)
                if not 位表:
                    失败说明 = ("第 %d 条 `%s`：**找不到** `旧内容` ⇒ 拒（文件已变，"
                            "请重新读一次这个件再发起修改）" % (序号, 路径))
                    break
                if len(位表) > 1:
                    行号表 = [全文[:位].count("\n") + 1 for 位 in 位表]
                    失败说明 = ("第 %d 条 `%s`：`旧内容` 在文件里出现 **%d 次**（行 %s）⇒ 拒。"
                            "多给几行上下文，让它唯一" % (序号, 路径, len(位表),
                                              " · ".join(str(号) for 号 in 行号表[:8])))
                    break
                位置 = 位表[0]
                if 功能号 == 功能_删除:
                    件路径.unlink()
                    错误 = ""
                else:
                    错误 = _写盘(件路径, 全文[:位置] + 新内容 + 全文[位置 + len(旧内容):])
            if 错误:
                失败说明 = "第 %d 条 `%s`：%s" % (序号, 路径, 错误)
                break
            写后指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
            账本.写回指纹(连, 开工号, 路径, 写后指纹)
            账本.记改动(连, 开工号, 路径, 功能名[功能号], 写前指纹, 写后指纹)
            完成表.append("%s（%s）" % (路径, 功能名[功能号]))

        # ── 刷索引（**整批一次**）──
        # 为什么不必每条都刷：定位靠**内容**不靠行号 ⇒ 下一条不依赖索引的新旧；
        # 一次 sync 实测 389 ms，N 条改动的批不必付 N 次。（本注释原先写「每条写完都刷」——
        # 那是设计初稿的说法，代码一直是循环外刷一次；注释已改回实话。）
        码, 说明 = 同步(工作树)
        输出行表 = ["%s：改了 %d/%d 条 —— %s" % (开工号, len(完成表), len(表),
                                            " · ".join(完成表) or "（无）"),
                  "索引：%s" % 说明]
        if 失败说明:
            输出行表.append("**%s**" % 失败说明)
            if 完成表:
                输出行表.append("（前面 %d 条已经写进盘了 —— 本工具是逐条写的，不是整批回滚）"
                            % len(完成表))
            return 4, "\n".join(输出行表)
        return 0, "\n".join(输出行表)
    finally:
        连.close()
