任务号形状 = re.compile(r"[0-9a-f]{32}")


def 提交主干祖先(仓根, 提交: str) -> tuple:
    """提交是否是**主干祖先** ⇒ `(是否, 说明)`。三道：存在且是提交对象 · 是 `主干` 祖先。

    第三道是关键 —— 只存在某支线的提交**不得**当完成（清理会把它当已关闭而误删）。
    """
    提交值 = str(提交 or "").strip()
    if not 提交值:
        return False, "空提交"
    退出码, _ = 跑命令(["git", "rev-parse", "--verify", "--quiet", 提交值 + "^{commit}"],
                   cwd=仓根, 超时秒数=2)
    if 退出码 != 0:
        return False, "不是仓里真实存在的提交对象"
    退出码, 输出文本 = 跑命令(["git", "merge-base", "--is-ancestor", 提交值, "主干"],
                        cwd=仓根, 超时秒数=2)
    if 退出码 == 0:
        return True, "主干祖先"
    if 退出码 == 1:
        return False, "不是主干祖先（可能只存在某支线）"
    return False, "主干祖先核不出（%s）" % (输出文本.strip()[:120] or "退出码 %d" % 退出码)


def 是已解决条目(连接, 仓根, 条目号) -> bool:
    """条目是否**已解决**（口径见文件头，唯一一份）。"""
    判词行 = 反馈账本.有效判词(连接, 条目号)
    if not 判词行:
        return False
    if 判词行["判词"] == 反馈账本.判词_非问题:
        return True
    if 判词行["判词"] != 反馈账本.判词_债务:
        return False
    关闭行 = 反馈账本.读关闭(连接, 判词行["条目号"])
    if not 关闭行 or 关闭行["退出码"] != 0:
        return False
    return 提交主干祖先(仓根, 关闭行["承接提交"])[0]


def 承接任务合格(仓根, 承接任务: str) -> tuple:
    """承接任务是否已合主干 ⇒ `(是否, 说明)`：真开工 · 已释放 · 支线已并入主干（`检查清树安全`）。"""
    承接任务 = str(承接任务 or "").strip()
    if not 承接任务:
        return False, "缺承接任务"
    连接 = 账本.连账本()
    try:
        开工记录 = 账本.读开工(连接, 承接任务)
    finally:
        连接.close()
    if not 开工记录:
        return False, "承接任务不是真开工：%s" % 承接任务
    if 开工记录["状态"] != 账本.状态_已释放:
        return False, "承接任务未释放（状态 %s）" % 开工记录["状态"]
    退出码, 说明 = 检查清树安全(仓根, 承接任务, 开工记录["工作树"])
    if 退出码 != 0:
        return False, "承接任务未合主干：%s" % 说明
    return True, "承接任务已合主干"


def 核实一条(连接, 仓根, 选择项, 序次) -> tuple:
    """一条**条目模式**选择项 ⇒ `(条目号 或 None, 错误表)`。逐项核，不猜。"""
    错误表 = []
    if not isinstance(选择项, dict):
        return None, ["选择 %d：要是对象" % 序次]
    条目号 = 选择项.get("条目号")
    if type(条目号) is not int:
        return None, ["选择 %d：`条目号` 要是整数" % 序次]
    条目行 = 反馈账本.读条目(连接, 条目号)
    if not 条目行:
        return None, ["选择 %d：条目 %d 不存在" % (序次, 条目号)]
    审计所属 = str(选择项.get("审计所属") or "").strip()
    承接任务 = str(选择项.get("承接任务") or "").strip()
    if 条目行["开工号"] != 审计所属:
        错误表.append("条目 %d 的审计所属是 %s，不是给出的 %s ⇒ 拒（防跨开工误删）"
                 % (条目号, 条目行["开工号"], 审计所属 or "（空）"))
    if not 账本.读开工(连接, 审计所属):
        错误表.append("审计所属 %s 不是真开工" % (审计所属 or "（空）"))
    承接是否, 承接说明 = 承接任务合格(仓根, 承接任务)
    if not 承接是否:
        错误表.append("承接任务 %s 不合格：%s" % (承接任务 or "（空）", 承接说明))
    if not 是已解决条目(连接, 仓根, 条目号):
        错误表.append("条目 %d 未达「已解决」（须判词非问题，或债务且承接提交是主干祖先）" % 条目号)
    else:
        真关联集 = 真关联开工集(连接, 条目号)
        if 承接任务 and 承接任务 not in 真关联集:
            错误表.append("条目 %d 的承接任务 %s 不是它**真关联**的开工（真关联：%s）"
                      "⇒ 拒（防张冠李戴）"
                      % (条目号, 承接任务, " · ".join(sorted(真关联集)) or "（无）"))
    return 条目号, 错误表


def 真关联开工集(连接, 条目号) -> set:
    """条目**真关联**的开工号集：判词的开工关联目标 + 关闭记录的关闭开工号。

    **为什么不能只等关闭开工号 == 承接任务**：真实形状就是「审计所属 = A 腿（条目住它）·
    关闭开工号 = A 腿（同一腿关的）· 承接任务 = B 腿（维修在 B 腿）」（实测 4163/4379/4382：
    审计与关闭都是 642，承接提交 148b867e 落在 643）。承接任务只要**在这个真关联集里**即算有据；
    与条目毫无关联的任意开工号仍被拒。
    """
    关联集 = set()
    try:
        判词行 = 反馈账本.有效判词(连接, 条目号)
    except sqlite3.Error:
        return 关联集
    if 判词行 and str(判词行["关联种类"] or "") == 反馈账本.关联_开工:
        if str(判词行["关联目标"] or "").strip():
            关联集.add(str(判词行["关联目标"]).strip())
    关闭行 = 反馈账本.读关闭(连接, 条目号) if 判词行 else None
    if 关闭行 and str(关闭行["关闭开工号"] or "").strip():
        关联集.add(str(关闭行["关闭开工号"]).strip())
    return 关联集


def 核任务门禁(连接, 仓根, 开工号, 开工记录) -> tuple:
    """任务模式 fail-closed 门禁 ⇒ `(阻断表, 判据行表, 孤儿行表)`。

    清树前安全条件**复用** `清树门禁.核清树条件`（已合主干 · 净树 · 无在途作业 · 无未释放消费者 ·
    台账未点名 · 无未蒸馏反馈 —— 与 `单纯释放` / `安全清收口` 同一份判据，不写第二套）；另加
    「无**在途**别的开工的 `认领重叠` 反向引用本开工」（那会让清后留孤儿）；已清 / 已释放开工留下的
    反向行是**孤儿**（无主）⇒ 不算阻断，随本开工一并真删。
    """
    条件均成立, 行表 = 清树门禁.核清树条件(连接, 仓根, 开工号, 开工记录, 要求已释放=True)
    阻断引用, 孤儿引用 = 反向认领重叠(连接, 开工号)
    行表.append("%s 无**在途**别的开工的 `认领重叠` 反向引用本开工（否则清后成孤儿）"
            % ("✓" if not 阻断引用 else "✗"))
    for 数据行 in 阻断引用[:5]:
        行表.append("    · 在途反向引用：%s · %s（对方开工 %s）"
                  % (数据行["开工号"], 数据行["路径"], 数据行["对方开工号"]))
    if 孤儿引用:
        行表.append("○ 已清 / 已释放开工留下的反向行 %d 条（**孤儿** ⇒ 不算阻断，随本开工一并真删、回执留痕）"
                  % len(孤儿引用))
        for 数据行 in 孤儿引用[:5]:
            行表.append("    · 孤儿行：%s · %s" % (数据行["开工号"], 数据行["路径"]))
    if 阻断引用:
        条件均成立 = False
    阻断 = [行文本 for 行文本 in 行表 if 行文本.startswith("✗")]
    return 阻断, 行表, 孤儿引用


def 反向认领重叠(连接, 开工号) -> tuple:
    """别的开工的 `认领重叠` 行把本开工当 `对方开工号` ⇒ `(阻断行表, 孤儿行表)`（每项 = dict）。

    **阻断** = 引用方**仍在途**（开工行还在账本且状态不是「已释放」）⇒ 清本开工会让它的行变孤儿 ⇒ 硬拒。
    **孤儿** = 引用方**已不在账本**（已被清）或**已释放**（生命周期已结束）⇒ 该行**无主**（唯一读者
    已不存在）⇒ 随本开工一并真删、回执留痕，不再永拒（2026-10-10 · 工作台第 2 批新缺口：清 `v1-100753`
    时被已清的 `754` / `755` 的 22 行拦住，只能手工改库）。
    """
    try:
        数据表 = [dict(数据行) for 数据行 in 连接.execute(
            "select 开工号, 路径, 对方开工号 from 认领重叠 where 对方开工号 = ? order by 开工号",
            (开工号,))]
    except sqlite3.Error:
        return [], []
    阻断表, 孤儿表 = [], []
    for 数据行 in 数据表:
        引用记录 = 账本.读开工(连接, 数据行["开工号"])
        if 引用记录 and 引用记录.get("状态") != 账本.状态_已释放:
            阻断表.append(数据行)
        else:
            孤儿表.append(数据行)
    return 阻断表, 孤儿表


def 反馈表集核(连接) -> list:
    """反馈六表「全无 / 齐全 / 残缺」三态 ⇒ 错误表（残缺 ⇒ fail-closed）。"""
    表集 = 反馈关联.反馈表集(连接)
    if 表集 and 表集 != set(反馈账本.反馈表名表):
        return ["反馈表残缺（现存 %s / 应有 %s）⇒ fail-closed"
              % (" · ".join(sorted(表集)), " · ".join(反馈账本.反馈表名表))]
    return []


def 切分来源(连接, 仓根, 来源表, 可选条目集) -> tuple:
    """按来源切分 ⇒ `(可删条目表, 删来源表, 全清来源表, 混合来源表, 保留条目集)`。

    `可选条目集` 为空 ⇒ **任务模式**：来源内每条都按 `是已解决条目` 判，全解决才全清。
    `可选条目集` 非空 ⇒ **条目模式**：只认**选中的**已解决条目；来源内其余条目一律保留。
    """
    可删条目, 删来源, 全清来源, 混合来源, 保留条目集 = [], [], [], [], set()
    for 来源行 in 来源表:
        条目号表 = [数据行[0] for 数据行 in 连接.execute(
            "select 条目号 from 反馈条目 where 来源号 = ? order by 条目号", (来源行["来源号"],))]
        已解决集 = {号值 for 号值 in 条目号表 if 是已解决条目(连接, 仓根, 号值)}
        可删集 = (已解决集 if not 可选条目集 else (已解决集 & 可选条目集))
        删条目 = [号值 for 号值 in 条目号表 if 号值 in 可删集]
        留条目 = [号值 for 号值 in 条目号表 if 号值 not in 可删集]
        可删条目 += 删条目
        保留条目集.update(留条目)
        if 留条目:
            混合来源.append({"来源号": 来源行["来源号"], "报告路径": 来源行["报告路径"],
                        "删条数": len(删条目), "留条目": 留条目})
        else:
            全清来源.append({"来源号": 来源行["来源号"], "报告路径": 来源行["报告路径"]})
            删来源.append(来源行["来源号"])
    return 可删条目, 删来源, 全清来源, 混合来源, 保留条目集


def 保留身份集(连接, 删来源集) -> set:
    """**保留来源**引用的报告件身份串集（`realpath` 规范化 ⇒ 同文件不同拼法算同一件）。"""
    身份集 = set()
    try:
        行表 = 连接.execute("select 来源号, 报告路径 from 反馈来源 "
                      "where 报告路径 is not null and 报告路径 <> ''")
    except sqlite3.Error:
        return 身份集
    for 数据行 in 行表:
        if 数据行["来源号"] not in 删来源集:
            身份集.add(清理执行.规范同身份(数据行["报告路径"]))
    return 身份集


def 判报告件(全清来源表, 保留身份集) -> tuple:
    """全清来源的报告件 ⇒ `(可删待续项, 保留报告说明表)`。四道：共享身份 · 界内 · 链接面 · 存在。"""
    可删, 保留, 已见身份 = [], [], {}
    for 来源行 in 全清来源表:
        路径 = 来源行["报告路径"]
        if not 路径:
            continue
        身份 = 清理执行.规范同身份(路径)
        if 身份 in 保留身份集:
            保留.append((路径, "被别的保留来源引用（共享，按实名身份核）"))
            continue
        if 身份 in 已见身份:
            保留.append((路径, "同批内与 %s 同身份（已在待删）" % 已见身份[身份]))
            continue
        逻辑路径, 路径说明 = 清理执行.规范报告路径(路径)
        if 逻辑路径 is None:
            保留.append((路径, "路径不合法：%s" % 路径说明))
            continue
        if not 清理执行.在界内(逻辑路径):
            保留.append((路径, "越界（不在允许的报告件落点）"))
            continue
        链接说明 = 清理执行.链接面异常(逻辑路径)
        if 链接说明:
            保留.append((路径, "链接面：%s" % 链接说明))
            continue
        if not Path(逻辑路径).is_file():
            保留.append((路径, "盘上不存在"))
            continue
        内容哈希 = 清理执行.文件内容哈希(逻辑路径)
        if not 内容哈希:
            保留.append((路径, "读不动内容（不落待续，免 TOCTOU 误删）"))
            continue
        已见身份[身份] = 路径
        可删.append({"路径": str(逻辑路径), "种类": 清理执行.种类_报告件, "期望内容哈希": 内容哈希})
    return 可删, 保留


def 关联任务ID集(连接, 开工号) -> set:
    """本开工**由真实验证关联**的后台作业任务ID集 —— 从本开工条目的 `反馈关闭` 文本里抽 32 位 hex。

    **不接受任意点名**（点名能删别的任务的行 ⇒ 不可信）。无开工ID 的合后验收作业，只在它的任务ID
    出现在本开工某条已关闭记录的 `验证命令` / `日志指针` 里时才归本开工（真实关联，非任意断言）。
    """
    任务集 = set()
    try:
        行表 = 连接.execute(
            "select 反馈关闭.验证命令, 反馈关闭.日志指针 from 反馈关闭 "
            "join 反馈条目 on 反馈关闭.条目号 = 反馈条目.条目号 where 反馈条目.开工号 = ?",
            (开工号,)).fetchall()
    except sqlite3.Error:
        return 任务集
    for 数据行 in 行表:
        for 文本值 in (数据行[0], 数据行[1]):
            for 命中 in 任务号形状.findall(str(文本值 or "")):
                任务集.add(命中)
    return 任务集


def 归属作业行(开工号, 工作树, 关联集) -> tuple:
    """本开工**归属**的后台作业行 ⇒ `(行表, 说明或 None)`。三条**真归属**口径（无任意点名）。

    ① `作业.开工ID == 开工号`；② `作业.工作树` 与开工工作树**同一身份串**；③ `作业.任务ID` 在
    `关联任务ID集`（来自真实关闭记录的验证文本）。读不出 ⇒ fail-closed。
    """
    库路径 = 作业账本.作业账本路径()
    if not Path(库路径).is_file():
        return [], None
    连接 = sqlite3.connect("file:%s?mode=ro" % 库路径, uri=True)
    try:
        连接.row_factory = sqlite3.Row
        try:
            全表 = [dict(数据行) for 数据行 in 连接.execute("select * from 作业")]
        except sqlite3.Error:
            return [], "作业账本读不出 ⇒ fail-closed"
    finally:
        连接.close()
    基准身份 = (清理执行.规范同身份(工作树) if str(工作树 or "").strip() else "")
    命中表 = []
    for 记录行 in 全表:
        属本开工 = bool(开工号) and str(记录行.get("开工ID") or "") == 开工号
        同树 = (bool(基准身份) and bool(str(记录行.get("工作树") or "").strip())
              and 清理执行.规范同身份(记录行["工作树"]) == 基准身份)
        验证关联 = str(记录行.get("任务ID") or "") in 关联集
        if 属本开工 or 同树 or 验证关联:
            命中表.append(记录行)
    return 命中表, None


def 作业面(连接, 开工号, 工作树) -> tuple:
    """归属作业面 ⇒ `(作业行表, 作业日志待续项, 阻断表)`（非终态 / 读不出 ⇒ 阻断）。"""
    关联集 = 关联任务ID集(连接, 开工号)
    作业行表, 作业说明 = 归属作业行(开工号, 工作树, 关联集)
    if 作业说明:
        return [], [], [作业说明]
    未收敛 = [记录行 for 记录行 in 作业行表 if 记录行.get("状态") in 作业账本.非终态集]
    if 未收敛:
        return [], [], ["有尚未收敛的后台作业 %d 条 ⇒ 拒" % len(未收敛)]
    日志待续 = []
    for 记录行 in 作业行表:
        任务ID = str(记录行.get("任务ID") or "")
        for 日志后缀 in (作业账本.日志后缀, 作业账本.工作日志后缀, 作业账本.错误日志后缀):
            日志件 = 作业账本.日志路径(任务ID, 日志后缀)
            if 日志件.is_file():
                内容哈希 = 清理执行.文件内容哈希(日志件)
                if 内容哈希:
                    日志待续.append({"路径": str(日志件), "种类": 清理执行.种类_作业日志,
                               "期望内容哈希": 内容哈希})
    return 作业行表, 日志待续, []
