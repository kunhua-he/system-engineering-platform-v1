# -*- coding: utf-8 -*-
"""清理选择 —— 「清理已解决任务」的**判定与计划面**：任务级门禁 · 条目级归属核 · 来源切分 · 报告件共享核。

**为什么单开一件**（判据 ⑲ 单件 ≤400 行）：判定口径（什么算已解决 / 什么算可清）是本能力的**唯一
事实面**，`任务清理.py` 只做编排与回执。

**两种模式**（同一条判定口径，只换入口）：
  · **任务模式**（给顶层 `开工ID`）：清这条已解决开工的整份生命周期（反馈 + 账本行 + 文件）。
  · **条目模式**（给 `条目选择` 数组）：**跨开工定向**清**精确条目** —— 每条要给 `审计所属`（该条目
    住哪条开工）与 `承接任务`（修它的那条开工）。绝不按开工号粗删别的未解决反馈。

**条目级「已解决」（唯一一份）**：判词「非问题」，或判词「债务」且有 `反馈关闭` + 承接提交是**主干
祖先**（`git merge-base --is-ancestor … 主干`，**不复用**只看「归属某支线」的宽校验 —— 只存在某支线
的提交不得当完成）。承接任务校验同理：真开工 · 已释放 · 支线已并入主干。

**报告件共享核**：共享判定按**同一物理文件的身份串**（`清理执行.规范同身份`，`realpath` 规范化）——
同一文件的不同拼法（符号链接 / `..` / 冗余分隔）也算同一件 ⇒ 只要还有保留来源引用它，就**不删**。
"""

