def _命名面跳行假阳(仓根) -> list:
    """命名面跳行假阳回归（`return "", ""` + 下一行元组解包）。"""
    import sys as _sys
    工具根 = Path(__file__).resolve().parents[2]
    if str(工具根 / "构建装配" / "一键验证") not in _sys.path:
        _sys.path.insert(0, str(工具根 / "构建装配" / "一键验证"))
    from 一键验证 import 命名扫描 as 命名面

    假件 = "def 读对(件):\n    return \"\", \"\"\n    x, y = 1, 2\n"
    假件抓到 = {标识符 for _行号, 标识符 in 命名面.扫局部绑定(".py", 假件, 只单字=False)}
    真件路径 = Path(仓根) / "构建装配/形态装配/生成声明/推导比对.py"
    真件命中 = set()
    if 真件路径.is_file():
        真件命中 = {标识符 for _行号, 标识符 in 命名面.扫局部绑定(
            ".py", 真件路径.read_text(encoding="utf-8"), 只单字=False)
            if 标识符 in ("return", "def", "if", "for", "else")}
    return [("命名面跳行假阳回归：`return \"\", \"\"` 后紧跟元组解包 ⇒ 只抽 x/y，不抓关键字",
             假件抓到 == {"x", "y"} and not 真件命中)]


def _短引用与行数预警(立件, 认领刷新, 跑写盘, 临时根) -> list:
    """短引用 + 行数预警。"""
    import os

    from 运行数据根.口径 import 覆盖变量名

    短引件 = 立件("样本区/短引件.py", "配置文件 = 1\n")
    改动表 = [{"路径": "样本区/短引件.py", "功能": 1,
            "旧内容": "配置文件 = 1\n", "新内容": "配置文件 = 2\n"}]
    # `只检查` 走 `批量预检` —— 它按**环境变量**定位账本（不走替身连接）⇒ 得把运行根指到夹具。
    os.environ[覆盖变量名] = str(临时根 / "运行根")
    try:
        退出码, 说明 = 跑写盘(改动表, 只检查=True)
    finally:
        os.environ.pop(覆盖变量名, None)
    短引用 = ""
    for 文本行 in 说明.splitlines():
        if "短引用" in 文本行:
            短引用 = 文本行.rsplit("：", 1)[-1].strip()
    退出码, 说明 = 跑写盘([], 沿用上次=短引用)
    沿用过 = 退出码 == 0 and 短引件.read_text(encoding="utf-8") == "配置文件 = 2\n"
    退出码, 说明 = 跑写盘([], 沿用上次="0000000000000000")
    失效拒 = 退出码 == 3 and "没查过" in 说明
    退出码, 说明 = 跑写盘([{"路径": "样本区/短引件.py", "功能": 1,
                       "旧内容": "配置文件 = 2", "新内容": "配置文件 = 9"}], 沿用上次=短引用)
    对不上拒 = 退出码 == 3 and 短引件.read_text(encoding="utf-8") == "配置文件 = 2\n"
    输出表 = [("短引用：`只检查` 过的表可 `沿用上次` 免重传；失效 / 与所给改动表对不上 ⇒ 明确拒",
             沿用过 and 失效拒 and 对不上拒)]
    行数件 = 立件("样本区/行数件.py", "配置文件 = 1\n")
    超顶 = "配置文件 = 1\n" + "# 填充\n" * 402
    退出码, 说明 = 跑写盘([{"路径": "样本区/行数件.py", "功能": 1,
                       "旧内容": "配置文件 = 1\n", "新内容": 超顶}])
    超顶报 = 退出码 == 0 and "行数预警" in 说明 and "400" in 说明
    认领刷新("样本区/行数件.py")
    # 临顶不能是超顶的**子串**（否则会被幂等口径判「已存在跳过」）⇒ 末尾换成另一行。
    临顶 = "配置文件 = 1\n" + "# 填充\n" * 397 + "配置文件 = 9\n"
    退出码, 说明 = 跑写盘([{"路径": "样本区/行数件.py", "功能": 1,
                       "旧内容": 超顶, "新内容": 临顶}])
    临顶报 = 退出码 == 0 and "行数预警" in 说明 and "只剩" in 说明
    输出表.append(("行数预警：`改` 档也报行数（超顶报一行；距上限 ≤5 行报一行）",
              超顶报 and 临顶报))
    return 输出表


def _整批重跑幂等(立件, 跑写盘) -> list:
    """插入形那批再跑一次 ⇒ 全判已存在跳过，不重复插入。"""
    增行件 = 立件("样本区/增行件.py", "import sys\nx = 1\n")
    重跑改动表 = [
        {"路径": "样本区/增行件.py", "功能": 1,
         "旧内容": "import sys", "新内容": "import os\nimport sys"},
        {"路径": "样本区/增行件.py", "功能": 1,
         "旧内容": "import os\nimport sys", "新内容": "import os\nimport sys\nimport re"}]
    退出码, 说明 = 跑写盘(重跑改动表)
    首跑 = (退出码 == 0
          and 增行件.read_text(encoding="utf-8") == "import os\nimport sys\nimport re\nx = 1\n")
    退出码, 说明 = 跑写盘(重跑改动表)
    重跑读数 = (退出码 == 0 and "已存在跳过 2 条" in 说明
             and 增行件.read_text(encoding="utf-8").count("import os") == 1)
    return [("整批重跑幂等：插入形那批再跑一次 ⇒ 全判「已存在跳过」、import 只有一份",
             首跑 and 重跑读数)]


def _删除形幂等(立件, 跑写盘) -> list:
    """删除形（`新内容` ⊂ `旧内容`）幂等回归：旧内容在 ⇒ 必须真删；重跑 ⇒ 跳过；同件两条都落。"""
    删行件 = 立件("样本区/删行件.py", "lineA\nlineB\nlineC\n")
    退出码, 说明 = 跑写盘([{"路径": "样本区/删行件.py", "功能": 1,
                       "旧内容": "lineA\nlineB", "新内容": "lineA"}])
    首跑 = 退出码 == 0 and 删行件.read_text(encoding="utf-8") == "lineA\nlineC\n"
    退出码, 说明 = 跑写盘([{"路径": "样本区/删行件.py", "功能": 1,
                       "旧内容": "lineA\nlineB", "新内容": "lineA"}])
    重跑 = (退出码 == 0 and "已存在跳过 1 条" in 说明
          and 删行件.read_text(encoding="utf-8") == "lineA\nlineC\n")
    同件删行件 = 立件("样本区/同件删行.py", "lineA\nlineB\nlineC\n")
    退出码, 说明 = 跑写盘([
        {"路径": "样本区/同件删行.py", "功能": 1, "旧内容": "lineA\nlineB", "新内容": "lineA"},
        {"路径": "样本区/同件删行.py", "功能": 1, "旧内容": "lineC", "新内容": "lineD"}])
    同件两条 = (退出码 == 0 and "改了 2/2 条" in 说明
             and 同件删行件.read_text(encoding="utf-8") == "lineA\nlineD\n")
    return [("删除形幂等：`新内容` ⊂ `旧内容` 且旧内容在 ⇒ 必须真删（不静默跳过）；重跑 ⇒ 已存在跳过；"
             "同件两条串行 ⇒ 两条都落（改了 2/2）",
             首跑 and 重跑 and 同件两条)]


def _批量改名并入同套(立件, 开账, 工作树, 批量改名, 写盘恢复, 写盘账本) -> list:
    """功能 9 并入同一套写盘生命周期（意图 / 恢复 / 幂等 / 漂移拒 / 不回滚）。"""
    改名参数 = {"开工ID": "v1-样本", "路径范围": ["样本区"],
             "改名对": [{"旧名": "旧样例名", "新名": "新样例名"}]}
    输出表 = []
    首件 = 立件("样本区/改名首件.py", "旧样例名 = 1\nprint(旧样例名)\n")
    次件 = 立件("样本区/改名次件.py", "旧样例名 = 2\nprint(旧样例名)\n")
    退出码, 说明 = 批量改名.派发(改名参数, 工作树.parent)
    正向 = (退出码 == 0 and "改了 2/2 件" in 说明
          and "旧样例名" not in 首件.read_text(encoding="utf-8"))
    退出码, 说明 = 批量改名.派发(改名参数, 工作树.parent)
    幂等 = 退出码 == 2 and "0 处" in 说明 and 次件.read_text(encoding="utf-8").count("新样例名") == 2
    输出表.append(("功能 9 正向：两件都改名、回执「改了 2/2 件」；重跑幂等（0 处、盘上不动）",
              正向 and 幂等))
    首件 = 立件("样本区/崩件首.py", "旧样例名 = 1\n")
    次件 = 立件("样本区/崩件次.py", "旧样例名 = 2\n")
    真记一件 = 批量改名.记一件写盘

    def 假记一件(连接, 开工号, 路径, 功能名, 写前指纹, 写后指纹):
        raise sqlite3.Error("disk I/O error")

    批量改名.记一件写盘 = 假记一件
    try:
        退出码, 说明 = 批量改名.派发(改名参数, 工作树.parent)
    finally:
        批量改名.记一件写盘 = 真记一件
    崩溃读数 = 退出码 == 4 and "记账" in 说明 and "盘已写" in 说明
    未决表 = 写盘账本.列写盘意图(开账(), "v1-样本")
    退出码恢复, 说明恢复, _已收敛表, _拒收表 = 写盘恢复.恢复一次(开账(), 工作树, "v1-样本")
    恢复读数 = 退出码恢复 == 0 and "已收敛" in 说明恢复
    退出码, 说明 = 批量改名.派发(改名参数, 工作树.parent)
    恢复后重跑 = 退出码 == 0 or "0 处" in 说明
    输出表.append(("功能 9 崩溃窗口：记账失败 ⇒ 4 且意图仍留在账本；新连接恢复收敛；重跑幂等",
              崩溃读数 and len(未决表) == 1 and 恢复读数 and 恢复后重跑))
    首件 = 立件("样本区/漂移件.py", "旧样例名 = 1\n")
    写盘账本.补意图表(开账())
    写盘账本.记写盘意图(开账(), "v1-样本", "样本区/漂移件.py", "批量改名",
                  "盘上写前指纹占位", "期望写后指纹占位")
    首件.write_text("别人改的 = 9\n", encoding="utf-8")
    退出码漂, 说明漂, _收敛, 拒收表 = 写盘恢复.恢复一次(开账(), 工作树, "v1-样本")
    输出表.append(("功能 9 外部漂移：盘上既非写前也非期望写后 ⇒ 恢复拒收（3）、不洗账",
              退出码漂 == 3 and "外部漂移" in 说明漂 and len(拒收表) == 1
              and 首件.read_text(encoding="utf-8") == "别人改的 = 9\n"))
    首件 = 立件("样本区/半成首.py", "旧样例名 = 1\n")
    次件 = 立件("样本区/半成次.py", "旧样例名 = 2\n")
    真写文件 = 批量改名.写文件

    def 假写文件(件路径, 全文):
        # 待改表按路径排序 ⇒ 「半成次.py」（次 U+6B21）在「半成首.py」（首 U+9996）**之前**
        # ⇒ 让排在**后面**那一件失败，才能证「前面那件已写进盘、不回滚」。
        if 件路径.name == "半成首.py":
            return "写盘失败：OSError(28, 'No space left')"
        return 真写文件(件路径, 全文)

    批量改名.写文件 = 假写文件
    try:
        退出码, 说明 = 批量改名.派发(改名参数, 工作树.parent)
    finally:
        批量改名.写文件 = 真写文件
    输出表.append(("功能 9 单件失败不回滚：报落盘阶段、先改的件留在盘上、失败件未动",
              退出码 == 4 and "落盘" in 说明 and "前面 1 件已经写进盘" in 说明
              and "旧样例名" not in 次件.read_text(encoding="utf-8")
              and 首件.read_text(encoding="utf-8") == "旧样例名 = 1\n"))
    return 输出表
