# -*- coding: utf-8 -*-
"""反馈审完 —— 来源报告的**审完登记**与条目的**验证关闭**。

**审完**：一份报告要宣称「已逐份蒸馏」，必须给出**覆盖的提取条数与判词条数**，且与库中实际相符；
未知来源 / 空报告 / 缺件**不能假审完** —— 只能落**显式待核**（并因此继续阻断原腿收口清理）；
已读空报告可审完，但只许「提取 = 判词 = 0」。
**显式待核优先**：任一条来源只要给了**非空 `待核理由`**（含 `已读`）⇒ 落显式待核、**保理由、不盖审完**
—— 原件缺失 / 指纹不符等「已读但内容待核」由此可表达，不再被静默丢弃。
**批量档**：可选 `审完表`（数组）一次审完多来源，**保留旧单来源调用**（`来源号` + 覆盖数）；
整批**先校验覆盖 / 归属再事务写** —— 任一条不合规整批零写。
**验证关闭**：关闭须给**验证证据 + 验证命令 + 退出码 + 承接提交**（可选 `输出指纹` / `日志指针`）；
`承接提交` 必须是仓里**真实存在且归属某支线**的提交对象（git 校验）；`退出码` 必须为 0
（非 0 命令不得当验收证据；缺字段不许拿假默认 0 顶替）；`验证证据` 不得与条目原证据逐字相同
（**只防原文重放**，不以此声称证明独立验证）。关闭后撤待办关联，回执带验证者开工 / 命令 / 退出码 /
承接提交 / 输出指纹 / 日志指针供主策划审核。
"""

from . import 反馈账本 as 账本
from .反馈判词 import 找重号
from .反馈提交 import 取文本


def 提交校验(仓根, 承接提交: str) -> tuple:
    """承接提交是不是仓里**真实存在且归属某支线**的提交对象 ⇒ `(是否, 说明)`。

    两道：① `git rev-parse --verify <sha>^{commit}`（存在且是提交对象）；
    ② `git branch --all --contains <sha>` 非空（**归属**本仓某支线，悬空提交不算）。
    跑不动 / 读不出 ⇒ 假（fail-closed，不编话）。
    """
    from .仓操作 import 跑命令
    退出码, 输出文本 = 跑命令(["git", "rev-parse", "--verify", "--quiet", 承接提交 + "^{commit}"],
                       cwd=仓根, 超时秒数=2)
    if 退出码 != 0 or not 输出文本.strip():
        return False, "不是仓里真实存在的提交对象"
    归属码, 归属文本 = 跑命令(["git", "branch", "--all", "--contains", 承接提交],
                       cwd=仓根, 超时秒数=2)
    if 归属码 != 0 or not 归属文本.strip():
        return False, "存在但**不归属任何支线**（悬空提交）"
    return True, ""


def 规范审完(连接, 开工号: str, 来源号, 提取条数, 判词条数, 待核理由, 序次: int) -> tuple:
    """一条审完 ⇒ `(规范 dict, 错误表)`（**只判不写**）。覆盖数 / 归属不符 ⇒ 错误表非空。"""
    错误表 = []
    if type(来源号) is not int:
        错误表.append("审完 %d：`来源号` 要是整数" % 序次)
        return {}, 错误表
    if type(提取条数) is not int or 提取条数 < 0:
        错误表.append("审完 %d：`提取条数` 要是非负整数" % 序次)
    if type(判词条数) is not int or 判词条数 < 0:
        错误表.append("审完 %d：`判词条数` 要是非负整数" % 序次)
    if 错误表:
        return {}, 错误表
    来源行 = 账本.读来源(连接, 来源号)
    if not 来源行:
        错误表.append("审完 %d：来源 %d 不存在 ⇒ 不能假审完" % (序次, 来源号))
        return {}, 错误表
    if 来源行["开工号"] != 开工号:
        错误表.append("审完 %d：来源 %d 属开工 %s ⇒ **跨开工越界**（审完按来源开工顶层ID）"
                  % (序次, 来源号, 来源行["开工号"]))
        return {}, 错误表
    实际条数 = 连接.execute("select count(*) from 反馈条目 where 来源号 = ?",
                       (来源号,)).fetchone()[0]
    if 提取条数 != 实际条数:
        错误表.append("审完 %d：`提取条数` %d 与实际 %d 不符 ⇒ 覆盖数不实，不能审完"
                  % (序次, 提取条数, 实际条数))
        return {}, 错误表
    条目号集 = {数据行[0] for 数据行 in 连接.execute(
        "select 条目号 from 反馈条目 where 来源号 = ?", (来源号,))}
    已判词集 = 账本.已判词集(连接, 开工号) & 条目号集
    读取状态 = 来源行["读取状态"]
    # **显式待核优先**：给了非空 `待核理由`（含 `已读`）⇒ 落显式待核、保理由、不盖审完。
    # 这是「已读但原件缺失 / 指纹不符」等内容的表达口，不再被静默丢弃。
    if 待核理由:
        规范 = {"来源号": 来源号, "审完": False, "待核": True, "读取状态": 读取状态,
               "待核理由": 待核理由, "提取条数": 提取条数, "判词条数": 0,
               "写": ("update 反馈来源 set 待核理由 = ?, 判词条数 = 0, 审完时刻 = null, "
                   "审完说明 = ? where 来源号 = ?",
                   (待核理由, "显式待核：%s" % 待核理由, 来源号))}
        return 规范, 错误表
    # ★ 原件不可回读（空报告待核 / 缺件待核）但**发现事实完整**（提取 > 0 且逐条已判词）⇒
    #   允许审完并**保留 `待核理由` 作证据留痕**：发现已完整蒸馏，原件状态是证据项、不是阻断项。
    #   没有这条 ⇒ 这类来源只能落永久显式待核 ⇒ 原腿收口清树被**永久阻断**（实证：来源 866 使
    #   v1-100686 永拒释放，同类共 7 个来源）。真空报告（提取 0）与事实未承接的仍照旧拒。
    if (读取状态 not in (账本.读取_未读, 账本.读取_已读) and 提取条数 > 0
            and len(已判词集) >= 提取条数):
        规范 = {"来源号": 来源号, "审完": True, "待核": False, "读取状态": 读取状态,
               "待核理由": 待核理由, "提取条数": 提取条数, "判词条数": 提取条数,
               "写": ("update 反馈来源 set 提取条数 = ?, 判词条数 = ?, 审完时刻 = ?, "
                   "审完说明 = ?, 待核理由 = ? where 来源号 = ?",
                   (提取条数, 提取条数, 账本.时刻串(),
                    "原件不可回读（%s）· 发现事实已完整蒸馏（提取 %d 条 · 判词 %d 条）"
                    % (读取状态, 提取条数, 提取条数), 待核理由, 来源号))}
        return 规范, 错误表
    if 读取状态 not in (账本.读取_未读, 账本.读取_已读):
        # 空报告 / 缺件**只能落显式待核** ⇒ 须给 `待核理由`，卷完不写。
        错误表.append("审完 %d：来源 %d 是空报告 / 缺件（读取状态 %s）⇒ 须给明确 `待核理由` "
                 "落显式待核，不能假审完" % (序次, 来源号, 读取状态))
        return {}, 错误表
    if 提取条数 == 0:
        # **已读空报告**：合法，但只许「提取 = 判词 = 0」地审完 —— 不伪造条数。
        if 判词条数 != 0:
            错误表.append("审完 %d：空报告（提取 0 条）的 `判词条数` 必须是 0，收到 %d"
                     % (序次, 判词条数))
            return {}, 错误表
        规范 = {"来源号": 来源号, "审完": True, "待核": False, "读取状态": 读取状态,
               "待核理由": None, "提取条数": 0, "判词条数": 0,
               "写": ("update 反馈来源 set 提取条数 = 0, 判词条数 = 0, 审完时刻 = ?, "
                   "审完说明 = ?, 待核理由 = null where 来源号 = ?",
                   (账本.时刻串(), "空报告（提取 0 条 · 判词 0 条）", 来源号))}
        return 规范, 错误表
    if 判词条数 != len(已判词集):
        错误表.append("审完 %d：`判词条数` %d 与实际已判词 %d 不符 ⇒ 覆盖数不实"
                 % (序次, 判词条数, len(已判词集)))
        return {}, 错误表
    if len(已判词集) < 提取条数:
        错误表.append("审完 %d：该来源还有 %d 条未判词 ⇒ 不能假审完（先批量判定）"
                 % (序次, 提取条数 - len(已判词集)))
        return {}, 错误表
    规范 = {"来源号": 来源号, "审完": True, "待核": False, "读取状态": 读取状态,
           "待核理由": None, "提取条数": 提取条数, "判词条数": 判词条数,
           "写": ("update 反馈来源 set 提取条数 = ?, 判词条数 = ?, 审完时刻 = ?, 审完说明 = ?, "
               "待核理由 = null where 来源号 = ?",
               (提取条数, 判词条数, 账本.时刻串(),
                "覆盖提取 %d 条 · 判词 %d 条" % (提取条数, 判词条数), 来源号))}
    return 规范, 错误表


def _回执条(规范: dict) -> dict:
    """规范 ⇒ 回执里那一条（去掉内部 `写` 键）。"""
    return {字段名: 值 for 字段名, 值 in 规范.items() if 字段名 != "写"}


def _取审完项(参数表: dict) -> list:
    """入参归一：给了 `审完表`（数组）就用它；否则回退**旧单来源形**（`来源号` + 覆盖数）。"""
    审完表 = 参数表.get("审完表")
    if 审完表 is not None:
        return 审完表 if isinstance(审完表, list) else None
    待核理由 = 取文本(参数表.get("待核理由"))
    return [{"来源号": 参数表.get("来源号"), "提取条数": 参数表.get("提取条数"),
             "判词条数": 参数表.get("判词条数"), "待核理由": 待核理由}]


def 登记报告审完(仓根, 开工号: str, 参数表: dict) -> tuple:
    """登记一份 / 一批来源报告审完（覆盖数必须属实）⇒ `(退出码, 短回执 JSON)`。

    **保留旧单来源调用**（`来源号` + `提取条数` + `判词条数`，可选 `待核理由`）；
    也可给 `审完表`（数组，每条 = `来源号` / `提取条数` / `判词条数` / 可选 `待核理由`）批量。
    整批**先校验覆盖 / 归属再事务写** —— 任一条不合规整批零写。
    """
    if not 账本.是开工号(开工号):
        return 2, "登记报告审完要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    审完项表 = _取审完项(参数表)
    if 审完项表 is None:
        return 2, "**零写**：`审完表` 要是数组"
    if not 审完项表:
        return 2, "**零写**：`审完表` 要是非空数组"
    连接 = 账本.连反馈库()
    try:
        错误表 = []
        规范表 = []
        for 序次, 审完项 in enumerate(审完项表, 1):
            if not isinstance(审完项, dict):
                错误表.append("审完 %d：要是对象" % 序次)
                规范表.append({})
                continue
            规范, 条目错 = 规范审完(连接, 开工号, 审完项.get("来源号"),
                            审完项.get("提取条数"), 审完项.get("判词条数"),
                            取文本(审完项.get("待核理由")), 序次)
            错误表 += 条目错
            规范表.append(规范)
        重号 = 找重号([规范["来源号"] for 规范 in 规范表
                  if type(规范.get("来源号")) is int])
        if 重号:
            错误表.append("批内重复审完同一来源：%s" % " · ".join(str(号值) for 号值 in 重号))
        if 错误表:
            return 2, "**整批零写**（审完登记校验未过）：\n  " + "\n  ".join(错误表)
        for 规范 in 规范表:
            写语句 = 规范["写"][0]
            写参数 = 规范["写"][1]
            连接.execute(写语句, 写参数)
        连接.commit()
        明细表 = [_回执条(规范) for 规范 in 规范表]
        if len(明细表) == 1:
            return 0, 账本.拼回执(明细表[0])
        return 0, 账本.拼回执({"审完条数": len(明细表), "审完": 明细表})
    except Exception:
        连接.rollback()
        raise
    finally:
        连接.close()


def 规范关闭(连接, 仓根, 开工号: str, 关闭项, 序次: int) -> tuple:
    """一条关闭 ⇒ `(规范 dict, 错误表)`（**只判不写**）。"""
    if not isinstance(关闭项, dict):
        return {}, ["关闭 %d：要是对象" % 序次]
    错误表 = []
    条目号 = 关闭项.get("条目号")
    条目行 = None
    if type(条目号) is not int:
        错误表.append("关闭 %d：`条目号` 要是整数" % 序次)
    else:
        条目行 = 账本.读条目(连接, 条目号)
        if not 条目行:
            错误表.append("关闭 %d：条目 %d 不存在" % (序次, 条目号))
        elif 条目行["开工号"] != 开工号:
            错误表.append("关闭 %d：条目 %d 属开工 %s ⇒ 跨开工越界"
                     % (序次, 条目号, 条目行["开工号"]))
        elif 条目行["并入主条目"]:
            错误表.append("关闭 %d：条目 %d 已并入主条目 %d ⇒ 关主条目"
                     % (序次, 条目号, 条目行["并入主条目"]))
    验证证据 = 取文本(关闭项.get("验证证据"))
    验证命令 = 取文本(关闭项.get("验证命令"))
    承接提交 = 取文本(关闭项.get("承接提交"))
    输出指纹 = 取文本(关闭项.get("输出指纹")) or None
    日志指针 = 取文本(关闭项.get("日志指针")) or None
    退出码 = 关闭项.get("退出码")
    if not 验证证据:
        错误表.append("关闭 %d：缺 `验证证据`" % 序次)
    if not 验证命令:
        错误表.append("关闭 %d：缺 `验证命令`" % 序次)
    if type(退出码) is not int:
        错误表.append("关闭 %d：`退出码` 要是整数（**必填**，不许拿默认 0 顶替）" % 序次)
    elif 退出码 != 0:
        错误表.append("关闭 %d：`退出码` 是 %d ⇒ 非 0 命令不得当验收证据" % (序次, 退出码))
    if not 承接提交:
        错误表.append("关闭 %d：缺 `承接提交`" % 序次)
    if 条目行 is not None:
        有效判词 = 账本.有效判词(连接, 条目号)
        if not 有效判词:
            错误表.append("关闭 %d：条目 %d 还没判词 ⇒ 先批量判定" % (序次, 条目号))
        elif 有效判词["判词"] == 账本.判词_非问题:
            错误表.append("关闭 %d：条目 %d 判词是「非问题」⇒ 无须关闭" % (序次, 条目号))
        elif 有效判词["判词"] == 账本.判词_待核:
            错误表.append("关闭 %d：条目 %d 判词是「待核」⇒ 须先判定再关闭" % (序次, 条目号))
        if 验证证据 and 验证证据 == 取文本(条目行["证据"]):
            错误表.append("关闭 %d：`验证证据` 与条目原 `证据` 逐字相同 ⇒ 拒（防原文重放；"
                     "本判据**不**声称证明独立验证）" % 序次)
    if 承接提交:
        在吗, 提交说明 = 提交校验(仓根, 承接提交)
        if not 在吗:
            错误表.append("关闭 %d：`承接提交` %s %s ⇒ 拒" % (序次, 承接提交, 提交说明))
    return {"条目号": 条目号, "验证证据": 验证证据, "验证命令": 验证命令, "退出码": 退出码,
            "承接提交": 承接提交, "输出指纹": 输出指纹, "日志指针": 日志指针}, 错误表


def 验证关闭(仓根, 开工号: str, 参数表: dict) -> tuple:
    """一批验证关闭 ⇒ `(退出码, 短回执 JSON)`。**整批事务**：一条不合规整批零写。"""
    if not 账本.是开工号(开工号):
        return 2, "验证关闭要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    关闭表 = 参数表.get("关闭表")
    if not isinstance(关闭表, list) or not 关闭表:
        return 2, "`关闭表` 要是非空数组"
    连接 = 账本.连反馈库()
    try:
        if not 账本.开工在吗(连接, 开工号):
            return 1, "没有这条开工：%s ⇒ 先登记" % 开工号
        错误表 = []
        规范表 = []
        for 序次, 关闭项 in enumerate(关闭表, 1):
            规范, 条目错 = 规范关闭(连接, 仓根, 开工号, 关闭项, 序次)
            错误表 += 条目错
            规范表.append(规范)
        重号 = 找重号([规范["条目号"] for 规范 in 规范表
                  if type(规范.get("条目号")) is int])
        if 重号:
            错误表.append("批内重复关闭同一条目：%s"
                     % " · ".join(str(号值) for 号值 in 重号))
        if 错误表:
            return 2, "**整批零写**（验证关闭校验未过）：\n  " + "\n  ".join(错误表)
        明细表 = []
        for 规范 in 规范表:
            连接.execute(
                "insert into 反馈关闭 (条目号, 验证证据, 验证命令, 退出码, 承接提交, "
                "输出指纹, 日志指针, 关闭开工号, 关闭时刻) values (?, ?, ?, ?, ?, ?, ?, ?, ?) "
                "on conflict(条目号) do update set 验证证据 = excluded.验证证据, "
                "验证命令 = excluded.验证命令, 退出码 = excluded.退出码, "
                "承接提交 = excluded.承接提交, 输出指纹 = excluded.输出指纹, "
                "日志指针 = excluded.日志指针, 关闭开工号 = excluded.关闭开工号, "
                "关闭时刻 = excluded.关闭时刻",
                (规范["条目号"], 规范["验证证据"], 规范["验证命令"], 规范["退出码"],
                 规范["承接提交"], 规范["输出指纹"], 规范["日志指针"], 开工号, 账本.时刻串()))
            连接.execute("update 反馈判词 set 关联状态 = ? where 条目号 = ?",
                      (账本.关联状态_已撤, 规范["条目号"]))
            明细表.append({"条目号": 规范["条目号"], "验证者开工号": 开工号,
                       "验证命令": 规范["验证命令"], "退出码": 规范["退出码"],
                       "承接提交": 规范["承接提交"], "输出指纹": 规范["输出指纹"],
                       "日志指针": 规范["日志指针"]})
        连接.commit()
        return 0, 账本.拼回执({"关闭条数": len(明细表), "关闭": 明细表})
    except Exception:
        连接.rollback()
        raise
    finally:
        连接.close()
