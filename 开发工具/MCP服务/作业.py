def 收僵尸() -> None:
    """机会式收尸：start 起过的工作进程跑完要 wait 掉，否则一直是僵尸（占 PID 号）。"""
    for 进程 in list(待收表):
        if 进程.poll() is not None:
            待收表.remove(进程)


def 接管作业(任务ID, 命令文本, 目标树文本, 仓根文本, 日志文本, 错误日志文本):
    """工作进程主体（**独立于 MCP 服务** ⇒ 服务 exec 重载不影响它）。跑一次、不重放。"""
    目标树 = Path(目标树文本)
    仓根 = Path(仓根文本)
    标准输出夹 = _开日志夹(Path(日志文本), "标准输出")
    标准错误夹 = _开日志夹(Path(错误日志文本), "标准错误")
    预算三件 = 读后台预算(仓根)
    超时上限 = None if 预算三件 is None else 预算三件[0]
    try:
        子进程 = subprocess.Popen(命令文本, shell=True, cwd=str(目标树), stdout=subprocess.PIPE,
                             stderr=subprocess.PIPE, encoding="utf-8", errors="replace",
                             env=_执行环境(目标树), start_new_session=True)
    except OSError as 起不来:
        _关日志夹(标准输出夹)
        _关日志夹(标准错误夹)
        落终态(任务ID, -2, 0, "起不了：%r" % (起不来,))
        return 0
    # 报回「运行中 + 命令组号 / 代次」⇒ start 的握手与 cancel 的定点都靠这一行。
    # 允许从 `取消中` 起也照写：取消者若已抢先，命令组号仍要落下来（否则它无从定点）。
    改行(任务ID, (状态_启动中, 状态_运行中, 状态_取消中),
        {"状态": 状态_运行中, "命令组号": 子进程.pid, "命令代次": 进程读数(子进程.pid)[1]})
    收集表 = {}
    线程表 = [
        threading.Thread(target=lambda: 收集表.update({"出": _收流(子进程.stdout, 标准输出夹)})),
        threading.Thread(target=lambda: 收集表.update({"错": _收流(子进程.stderr, 标准错误夹)})),
    ]
    for 线程 in 线程表:
        线程.start()
    说明 = ""
    超时了 = False
    if 超时上限 is None:
        超时了 = True
        说明 = "后台预算规则读不到（fail-closed）⇒ 杀整组，不静默挂住"
        杀组(子进程.pid)
    else:
        try:
            子进程.wait(timeout=超时上限)
        except subprocess.TimeoutExpired:
            超时了 = True
            说明 = "超时（预算 %d 秒）⇒ 已杀整组" % 超时上限
            杀组(子进程.pid)
    for 线程 in 线程表:
        线程.join(timeout=收尾秒)
    输出留存 = 收集表.get("出", ("", False))
    错误留存 = 收集表.get("错", ("", False))
    _补齐小输出(标准输出夹, 输出留存[0])
    _补齐小输出(标准错误夹, 错误留存[0])
    截断 = 1 if (输出留存[1] or 错误留存[1]) else 0
    if 标准输出夹["截顶"] or 标准错误夹["截顶"]:
        说明 = (说明 + "；" if 说明 else "") + "日志已到 %d MiB 上限（再多的输出没留）" % (
            日志上限 // (1024 * 1024))
    _关日志夹(标准输出夹)
    _关日志夹(标准错误夹)
    落终态(任务ID, (-1 if 超时了 else 子进程.returncode), 截断, 说明)
    return 0


def 起作业(命令文本: str, 开工号: str, 握手秒: int, 仓根) -> tuple:
    """`v1_job` 的 `start` ⇒ `(退出码, 输出文本)`。只启动、不等待（握手 ≤ `握手秒` 秒）。"""
    预算三件 = 读后台预算(仓根)
    if 预算三件 is None:
        return 2, ("后台预算读不到 / 非法 ⇒ 不启动（fail-closed）：规则库缺 类=`%s` 名=`%s` 或 "
                   "名=`%s` 的**正整数**行（不回落成无限或默认巨值）；先跑 "
                   "`python3 开发工具/信息核心/信息核心.py 记规则 --类 %s --名 <名> --内容 <正整数>`"
                   % (预算规则类, 预算规则名, 预算硬顶名, 预算规则类))
    有效预算, 硬顶, 是否压回 = 预算三件
    目标树 = Path(仓根).resolve()
    if 开工号:
        工作树路径 = _取工作树(仓根, 开工号)
        if 工作树路径 is None or not 工作树路径.is_dir():
            return 2, "参数拒绝：开工 %s 的工作树不在（问 git 问不到）⇒ 不启动" % 开工号
        目标树 = 工作树路径.resolve()
    任务ID = uuid.uuid4().hex
    开始时间 = 时刻串()
    日志 = 日志路径(任务ID)
    错误日志 = 日志路径(任务ID, 错误日志后缀)
    工作日志 = 日志路径(任务ID, 工作日志后缀)
    # 先落「启动中」行再起进程 —— 反过来的话工作进程会先写「运行中」，而那时行还不存在（改 0 行）。
    落新行(任务ID, 命令文本, str(目标树), 开始时间)
    环境表 = dict(os.environ)
    环境表.update(禁终端提示环境)
    try:
        工作记录 = open(工作日志, "w", encoding="utf-8", errors="replace")
        try:
            工作进程 = subprocess.Popen(
                [sys.executable, "-c", 工作段, 任务ID, 命令文本, str(目标树), str(仓根),
                 str(日志), str(错误日志)],
                cwd=str(仓根), env=环境表, stdin=subprocess.DEVNULL,
                stdout=工作记录, stderr=工作记录, start_new_session=True)
        finally:
            工作记录.close()
    except OSError as 起不来:
        改行(任务ID, 可抢态集, {"状态": 状态_失败, "完成时间": 时刻串(),
                          "说明": "工作进程起不来：%r" % (起不来,)})
        return 1, "起不了工作进程：%r" % (起不来,)
    待收表.append(工作进程)
    改行(任务ID, 可抢态集, {"组号": 工作进程.pid, "组代次": 进程读数(工作进程.pid)[1]})
    作业行 = 等握手(任务ID, 工作进程, 握手秒)
    状态值 = 作业行["状态"] if 作业行 else 状态_启动中
    说明行 = ""
    if 状态值 == 状态_启动中 and 工作进程.poll() is not None:
        改行(任务ID, 可抢态集, {"状态": 状态_失败, "完成时间": 时刻串(),
                          "说明": "工作进程在报回命令组号前就退出（退出码 %s）⇒ 启动失败"
                                  % 工作进程.returncode})
        状态值 = 状态_失败
    elif 状态值 == 状态_启动中:
        说明行 = "★ 启动握手 %d 秒内没等到命令组号 ⇒ 仍报 `启动中`（用 status 继续轮询）" % 握手秒
    输出行 = ["任务ID：%s" % 任务ID, "状态：%s" % 状态值, "工作树：%s" % 目标树,
             "开始时间：%s" % 开始时间, "日志：%s" % 日志,
             "后台预算：%d 秒（硬顶 %d 秒）" % (有效预算, 硬顶)]
    if 是否压回:
        输出行.append("★ 规则里的最长运行超过硬顶 ⇒ **压回硬顶 %d 秒**（如实报，不放宽）" % 硬顶)
    if 说明行:
        输出行.append(说明行)
    return (1 if 状态值 == 状态_失败 else 0), "\n".join(输出行)


def 等握手(任务ID: str, 工作进程, 握手秒: int):
    """等「工作进程报回命令组号」⇒ 作业行。**有界**（`握手秒` ≤5）：超时就如实报 `启动中`。"""
    截止时刻 = time.monotonic() + 握手秒
    while True:
        作业行 = 读行(任务ID)
        if 作业行 is None or 作业行["状态"] != 状态_启动中:
            return 作业行
        if 工作进程.poll() is not None:
            return 读行(任务ID)      # 工作进程已退出却没报「运行中」⇒ 启动失败
        if time.monotonic() >= 截止时刻:
            return 作业行
        time.sleep(轮询间隔秒)


def 收敛失联(任务ID: str, 作业行):
    """非终态作业：工作进程不在（组探活 + 代次核对）⇒ 收敛为 `崩溃失联`，并清理残留命令组。"""
    if 作业行["状态"] not in 非终态集:
        return 作业行
    if 组在吗(作业行["组号"], 作业行["组代次"]):
        return 作业行
    清理表 = []
    if 作业行["命令组号"] and 组在吗(作业行["命令组号"], 作业行["命令代次"]):
        杀组(作业行["命令组号"])
        清理表.append("已杀残留命令组 %d" % 作业行["命令组号"])
    else:
        清理表.append("无残留命令组")
    收敛值 = 状态_已取消 if 作业行["状态"] == 状态_取消中 else 状态_崩溃失联
    改行(任务ID, 非终态集, {"状态": 收敛值, "完成时间": 时刻串(),
                        "说明": "工作进程失联（组已不在或代次不符）⇒ 收敛为 %s；%s"
                                % (收敛值, "；".join(清理表))})
    return 读行(任务ID)


def 查状态(任务ID: str) -> tuple:
    """`status` ⇒ `(退出码, 输出文本)`。只读；唯一写入是把失联作业收敛成终态（落盘，非静默）。"""
    作业行 = 读行(任务ID)
    if 作业行 is None:
        return 2, "参数拒绝：未知任务ID `%s`（本机作业账本里没有这一条）" % 任务ID
    作业行 = 收敛失联(任务ID, 作业行)
    输出行 = ["任务ID：%s" % 任务ID, "状态：%s" % 作业行["状态"],
             "退出码：%s" % (作业行["退出码"] if 作业行["退出码"] is not None else "（未定）"),
             "开始时间：%s" % 作业行["开始时间"],
             "完成时间：%s" % (作业行["完成时间"] or "（未完成）"),
             "工作树：%s" % 作业行["工作树"],
             "截断：%s" % ("是" if 作业行["截断"] else "否"),
             "日志：%s" % 日志路径(任务ID),
             "错误日志：%s" % 日志路径(任务ID, 错误日志后缀)]
    if 作业行["说明"]:
        输出行.append("说明：%s" % 作业行["说明"])
    if 作业行["状态"] in 非终态集:
        输出行.append("★ 非终态 ⇒ 用 status 继续轮询；别当成成功，也别当成还在跑。")
    return 0, "\n".join(输出行)


def 读日志片段(任务ID: str, 起点字节: int, 是错误流: bool) -> tuple:
    """`log` ⇒ `(退出码, 输出文本)`。**有界读取**：从 `起点字节` 起最多 `日志片段上限` 字节。"""
    作业行 = 读行(任务ID)
    if 作业行 is None:
        return 2, "参数拒绝：未知任务ID `%s`" % 任务ID
    日志件 = 日志路径(任务ID, 错误日志后缀 if 是错误流 else 日志后缀)
    if not 日志件.is_file():
        return 1, "日志件不在：%s（作业可能还没产出，或已被清理）" % 日志件
    字节总数 = 日志件.stat().st_size
    if 起点字节 > 字节总数:
        起点字节 = 字节总数
    with open(日志件, "rb") as 句柄:
        句柄.seek(起点字节)
        原始字节 = 句柄.read(日志片段上限)
    片段文本 = 原始字节.decode("utf-8", errors="replace")
    下次偏移 = 起点字节 + len(原始字节)
    还有更多 = 下次偏移 < 字节总数
    输出行 = ["任务ID：%s" % 任务ID, "流：%s" % ("标准错误" if 是错误流 else "标准输出"),
             "完整日志：%s" % 日志件, "总字节：%d" % 字节总数, "本次起点：%d" % 起点字节,
             "本次读到字节：%d" % len(原始字节),
             "还有更多：%s" % ("是（下次起点 %d）" % 下次偏移 if 还有更多 else "否"),
             "", 片段文本.rstrip()]
    return 0, "\n".join(输出行)


def 取消作业(任务ID: str) -> tuple:
    """`cancel` ⇒ `(退出码, 输出文本)`。**只杀本作业的组**；终态幂等、不伤别的任务。"""
    作业行 = 读行(任务ID)
    if 作业行 is None:
        return 2, "参数拒绝：未知任务ID `%s`" % 任务ID
    if 作业行["状态"] in 终态集:
        return 0, "已幂等：作业已终态（状态=%s）⇒ 不动手。\n任务ID：%s" % (作业行["状态"], 任务ID)
    # 先占「取消中」：与工作进程的终态写入**条件竞争**，谁先抢到谁说了算（无条件写会互相覆盖）。
    抢到 = 改行(任务ID, 可抢态集, {"状态": 状态_取消中,
                              "说明": "已受理取消请求（%s）" % 时刻串()})
    if not 抢到:
        作业行 = 读行(任务ID)
        return 0, "已幂等：并发下作业已到终态（状态=%s）⇒ 不动手。" % 作业行["状态"]
    命令组号, 命令代次 = 作业行["命令组号"], 作业行["命令代次"]
    if not 命令组号 and 作业行["状态"] == 状态_启动中:
        命令组号, 命令代次 = 等命令组(任务ID)
    动手表 = []
    if 命令组号 and 组在吗(命令组号, 命令代次):
        杀组(命令组号)
        动手表.append("已杀命令组 %d（TERM→KILL）" % 命令组号)
    elif 命令组号:
        动手表.append("命令组 %d 已不在（或代次不符）⇒ 不杀" % 命令组号)
    if 组在吗(作业行["组号"], 作业行["组代次"]):
        杀组(作业行["组号"])
        动手表.append("已杀工作进程组 %d" % 作业行["组号"])
    else:
        动手表.append("工作进程组已不在（或代次不符）⇒ 不杀")
    # 收口：工作进程若已死没写终态 ⇒ 由这里补上（幂等）。
    改行(任务ID, (状态_取消中,), {"状态": 状态_已取消, "完成时间": 时刻串(),
                           "说明": "已取消：%s" % "；".join(动手表)})
    作业行 = 读行(任务ID)
    return 0, "\n".join(["任务ID：%s" % 任务ID, "状态：%s" % 作业行["状态"],
                     "取消动作：%s" % "；".join(动手表)])


def _取任务ID(参数表: dict):
    """校验 `任务ID` 形状（32 位十六进制）⇒ 值或 `None`。"""
    参数值 = 参数表.get("任务ID")
    if not isinstance(参数值, str) or not 任务号形状.fullmatch(参数值.strip()):
        return None
    return 参数值.strip()


def 合主线命令(作业参数, 仓根):
    """复用唯一主仓定位；固定合并入口，不接受调用方路径或代码。"""
    if set(作业参数) - {"目标开工ID", "推送"}:
        return 2, "合主线作业参数只认目标开工ID、推送"
    开工号 = 作业参数.get("目标开工ID")
    if not isinstance(开工号, str) or not 开工号形状.fullmatch(开工号):
        return 2, "合主线需作业参数.目标开工ID（v1-加六位数字）"
    推送 = 作业参数.get("推送", False)
    if type(推送) is not bool:
        return 2, "推送须逻辑型，默认假"
    try:
        from .合主干集成树 import 定位主仓
    except ImportError:
        return 2, "合主线依赖唯一主仓定位与合并互斥修复，接口未就绪 ⇒ 不启动"
    退出码, 主仓路径 = 定位主仓(仓根)
    if 退出码:
        return 退出码, str(主仓路径)
    入口路径 = Path(主仓路径) / "开发工具/MCP服务/合并主干.py"
    if not 入口路径.is_file():
        return 2, "主仓合并入口不在 ⇒ 不启动合主线"
    命令表 = [sys.executable, str(入口路径), 开工号]
    if 推送:
        命令表.append("--推送")
    return 0, shlex.join(命令表)


def 起具名作业(具名: str, 开工号: str, 握手秒: int, 仓根, 作业参数=None) -> tuple:
    """固定具名作业；合主线参数转发唯一合并入口。"""
    if not isinstance(具名, str) or 具名 not in 具名作业表:
        return 2, "未知具名作业；只认 %s" % "、".join(sorted(具名作业表))
    if 作业参数 is None:
        作业参数 = {}
    if not isinstance(作业参数, dict):
        return 2, "作业参数须对象"
    命令文本 = 具名作业表[具名]
    if 具名 == "合主线":
        退出码, 命令文本 = 合主线命令(作业参数, 仓根)
        if 退出码:
            return 退出码, 命令文本
    elif 作业参数:
        return 2, "此具名作业不接受作业参数"
    return 起作业(命令文本, 开工号, 握手秒, 仓根)


def 启动作业(开工号, 参数表, 仓根):
    """W3 start 具名参数值校验；键解析由参数规范完成。"""
    收僵尸()
