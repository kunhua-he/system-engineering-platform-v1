def 收僵尸() -> None:
    """机会式收尸：start 起过的工作进程跑完要 wait 掉，否则一直是僵尸（占 PID 号）。"""
    for 进程 in list(待收表):
        if 进程.poll() is not None:
            待收表.remove(进程)


def 接管作业(任务ID, 命令文本, 目标树文本, 仓根文本, 日志文本, 错误日志文本):
    """工作进程主体（**独立于 MCP 服务** ⇒ 服务 exec 重载不影响它）。跑一次、不重放。"""
    目标树 = Path(目标树文本)
    仓根 = Path(仓根文本)
    标准输出夹 = _开日志夹(Path(日志文本), "标准输出")
    标准错误夹 = _开日志夹(Path(错误日志文本), "标准错误")
    预算三件 = 读后台预算(仓根)
    超时上限 = None if 预算三件 is None else 预算三件[0]
    try:
        # ★ 2026-10-10（债务 326）：**这一层才是真正跑命令的子进程** —— 任务ID 必须注在这里，
        #   否则长活（释放作业）核清树时认不出本作业，把本作业那一行算成「未收敛的后台作业」而永拒释放。
        作业环境 = _执行环境(目标树)
        作业环境["V1_任务ID"] = 任务ID
        作业环境["V1_PY"] = 解释器路径()
        子进程 = subprocess.Popen(命令文本, shell=True, cwd=str(目标树), stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, encoding="utf-8", errors="replace",
                              env=作业环境, start_new_session=True)
    except OSError as 起不来:
        _关日志夹(标准输出夹)
        _关日志夹(标准错误夹)
        落终态(任务ID, -2, 0, "起不了：%r" % (起不来,))
        return 0
    # 报回「运行中 + 命令组号 / 代次」⇒ start 的握手与 cancel 的定点都靠这一行。
    # 允许从 `取消中` 起也照写：取消者若已抢先，命令组号仍要落下来（否则它无从定点）。
    改行(任务ID, (状态_启动中, 状态_运行中, 状态_取消中),
        {"状态": 状态_运行中, "命令组号": 子进程.pid, "命令代次": 进程读数(子进程.pid)[1]})
    收集表 = {}
    线程表 = [
        threading.Thread(target=lambda: 收集表.update({"出": _收流(子进程.stdout, 标准输出夹)})),
        threading.Thread(target=lambda: 收集表.update({"错": _收流(子进程.stderr, 标准错误夹)})),
    ]
    for 线程 in 线程表:
        线程.start()
    说明 = ""
    超时了 = False
    if 超时上限 is None:
        超时了 = True
        说明 = "后台预算规则读不到（fail-closed）⇒ 杀整组，不静默挂住"
        杀组(子进程.pid)
    else:
        try:
            子进程.wait(timeout=超时上限)
        except subprocess.TimeoutExpired:
            超时了 = True
            说明 = "超时（预算 %d 秒）⇒ 已杀整组" % 超时上限
            杀组(子进程.pid)
    for 线程 in 线程表:
        线程.join(timeout=收尾秒)
    输出留存 = 收集表.get("出", ("", False))
    错误留存 = 收集表.get("错", ("", False))
    _补齐小输出(标准输出夹, 输出留存[0])
    _补齐小输出(标准错误夹, 错误留存[0])
    截断 = 1 if (输出留存[1] or 错误留存[1]) else 0
    if 标准输出夹["截顶"] or 标准错误夹["截顶"]:
        说明 = (说明 + "；" if 说明 else "") + "日志已到 %d MiB 上限（再多的输出没留）" % (
            日志上限 // (1024 * 1024))
    _关日志夹(标准输出夹)
    _关日志夹(标准错误夹)
    落终态(任务ID, (-1 if 超时了 else 子进程.returncode), 截断, 说明)
    return 0


def 取树提交(目标树路径) -> tuple:
    """取一棵树「被验证的」那一对 `(树码, 提交码)`（台账 K-3453）——与 `v1_gate` 的读数对得上。

    树码 = 该树根的**绝对规范路径**（`git rev-parse --show-toplevel`）；提交码 = 该树 HEAD
    （`git rev-parse HEAD`）。取不到给空串（**不猜、不回落**：答不出就答不出）。
    """
    路径文本 = str(Path(目标树路径).resolve())
    读数, 树输出 = 跑命令(["git", "rev-parse", "--show-toplevel"], cwd=路径文本)
    树码 = 树输出.strip() if 读数 == 0 else ""
    读数, 提交输出 = 跑命令(["git", "rev-parse", "HEAD"], cwd=路径文本)
    提交码 = 提交输出.strip() if 读数 == 0 else ""
    return 树码, 提交码


