"""后台作业执行器 —— `v1_job` 的实现：本地 shell 长活的**异步路**（提交 + 轮询 + 取消）。

**为什么有它**：判据 ㊲ 与库 `规则` 的 `安全边界-4`（不许挂死）· `安全边界-5`（请求路不许跑
长活）把同步路钉在 5 秒 —— 跨仓大目录 `find`/`grep`、`gh`/`git ls-remote`、`信息核心.py 建库`、
`闸0`、`--自测`、`cargo run -p v1-case-runner` 这类**必然超 5 秒**的活，走同步路只能被硬顶杀掉。
条款 `2026-09-27_所有运行五秒硬顶.md` §5 明写「边界必须能表达长活」，§1 又禁止「用异步返回
假装达标」。本件就是那个原语：**提交立刻返回 + 轮询 + 取消**，命令**真的做完**（终态落盘）。

**具名作业**：上列长活各有具名（`闸0` · `自测` · `案例` · `建库` · `放行`）⇒ 调用方报名字即可，
不必另行拼命令（`v1_gate` 的放行档就调 `放行`）。

**不自动重放**：`start` 每次都建**新**作业；`push`/`merge` 这类副作用命令**绝不**自动重试。

**自愈重载**：状态全在盘上（`作业账本.py`）。工作进程**独立于 MCP 服务** ⇒ 服务 exec 重载不
影响在跑的作业；工作进程真没了（崩溃 / 被杀）时，`status` 按「组探活 + 代次核对」把它收敛成
`崩溃失联`，并清理残留命令组（保清理证据），**绝不静默当成功或当还在跑**。
"""

