r"""符号样本 —— `v1_symbol` 的**正反样本**（W3 合同拒未知 · 新查询能力 · 坏 / 过期 / 缺件索引不假绿 · 惰性导出）。

`自检样本.跑自检` 调本件并把结果计入样本表（判据 ㊽ 只看退出码 ⇒ 样本弱 = 闸 0 弱）。
**只读**：真仓一个字节都不改；要索引的地方一律用临时夹具库，不依赖调用方那棵树刷没刷索引。
"""
import json
