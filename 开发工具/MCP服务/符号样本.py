必备操作 = ("搜符号", "查出现位", "查关系", "列符号", "死代码")
新公开名表 = ("查索引状态", "查询定义", "零消费者符号", "可读说明")
旧公开名表 = ("查符号", "文件指纹", "出现位置", "状态行")


def _读信封(输出文本: str):
    """回执是统一 JSON 信封 ⇒ 解析；不是 ⇒ `None`。"""
    try:
        return json.loads(输出文本)
    except (TypeError, ValueError):
        return None


def _建夹具(树根: Path, 夹具库况: str) -> Path:
    """一棵最小树 + 一张索引库（`夹具库况` ∈ 缺失 / 损坏 / 过期 / 新鲜）⇒ 索引库路径。

    索引库**只建 查索引状态 要的三张表**（`nodes` / `edges` / `files`）—— 本件的样本只调
    「状态判定」这一档，不调定义面 ⇒ 表里不必有真节点。
    """
    (树根 / "开发工具").mkdir(parents=True, exist_ok=True)
    (树根 / "开发工具" / "示例件.py").write_text("占位 = 1\n", encoding="utf-8")
    库件 = 树根 / ".codegraph" / "codegraph.db"
    库件.parent.mkdir(exist_ok=True)
    if 夹具库况 == "缺失":
        return 库件
    if 夹具库况 == "损坏":
        库件.write_bytes("这不是一张 sqlite 库".encode("utf-8"))
        return 库件
    # 索引器按**它收的后缀集**收件（实测收 `.mjs`），命名面却只看 `命名后缀` ⇒ 这一档专门钉住
    # 「索引里有、盘上也有、但不是命名件」不许被判成「多余 / 陈旧」。
    非命名件 = 夹具库况 == "非命名件"
    if 非命名件:
        (树根 / "开发工具" / "示例件.mjs").write_text("// 非命名后缀的索引件\n", encoding="utf-8")
    # ★ 前端标记档：`.html` 在盘上、**索引器不收它**（codegraph 不索引 html）⇒ 不许被判
    #   「缺索引 / 陈旧」（命名面只对可解析代码，`.html` 不算命名件）。
    if 夹具库况 == "含前端标记":
        (树根 / "开发工具" / "示例页.html").write_text("<p>占位</p>\n", encoding="utf-8")
    # ★ 缺源件档：一个 `.py` 在盘上、**不在索引里** ⇒ 必须判「陈旧 · 索引缺少源件」
    #   （钉住：真缺失不许被「前端标记不算」掩掉）。
    if 夹具库况 == "缺源件":
        (树根 / "开发工具" / "新增件.py").write_text("新增 = 1\n", encoding="utf-8")
    # 「缺件」：盘上真实新增一个命名件，却**不写进索引 `files`** ⇒ 覆盖.缺失 非空 ⇒ 陈旧
    #   （正是收口方实测的主干现场：合主干落新件、索引留旧账）。
    if 夹具库况 == "缺件":
        (树根 / "开发工具" / "另件.py").write_text("另占位 = 1\n", encoding="utf-8")
    连接 = sqlite3.connect(库件)
    try:
        连接.execute("create table nodes(id text, kind text, name text)")
        连接.execute("create table edges(id text, kind text, source text, target text)")
        连接.execute("create table files(path text, modified_at real)")
        源件时刻 = (树根 / "开发工具" / "示例件.py").stat().st_mtime * 1000
        索引时刻 = 源件时刻 + 1000 if 夹具库况 in ("新鲜", "非命名件", "含前端标记", "缺源件") else 0.0
        连接.execute("insert into files values(?, ?)", ("开发工具/示例件.py", 索引时刻))
        if 非命名件:
            连接.execute("insert into files values(?, ?)", ("开发工具/示例件.mjs", 索引时刻))
        连接.commit()
    finally:
        连接.close()
    return 库件


def _惰性读数(仓根) -> tuple:
    """**新子进程**里 `import 代码地图` ⇒ `(导入后已加载的子模块, 未取时是否已具名, 旧名可调, 新名可调)`。

    ★ 必须走子进程：本进程早已把 代码地图.索引库 拉进来了，就地测等于假绿。
    """
    脚本 = ("import sys\n"
        "sys.path.insert(0, %r)\n"
        "import 代码地图\n"
        "先 = sorted(名 for 名 in sys.modules if 名.startswith('代码地图'))\n"
        "未取 = '查符号' not in vars(代码地图)\n"
        "旧 = all(callable(getattr(代码地图, 名)) for 名 in %r)\n"
        "新 = all(callable(getattr(代码地图, 名)) for 名 in %r)\n"
        "print('\\t'.join([','.join(先), str(未取), str(旧), str(新)]))\n"
        % (str(Path(仓根) / "开发工具"), 旧公开名表, 新公开名表))
    进程 = subprocess.run([sys.executable, "-c", 脚本], cwd=str(仓根),
                       capture_output=True, text=True, timeout=5)
    读数段 = (进程.stdout.strip().splitlines() or [""])[-1].split("\t")
    if len(读数段) != 4:
        return (), False, False, False
    return (tuple(读数段[0].split(",")), 读数段[1] == "True",
            读数段[2] == "True", 读数段[3] == "True")


