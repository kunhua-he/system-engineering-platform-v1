def 取主键列(库路径, 表名) -> list:
    """一张表的主键列名（按 pragma 顺序）⇒ 列表。"""
    连接 = sqlite3.connect("file:%s?mode=ro" % 库路径, uri=True)
    try:
        return [数据行[1] for 数据行 in 连接.execute("pragma table_info('%s')" % 表名) if 数据行[5]]
    finally:
        连接.close()


def 读源表(库路径, 表名) -> tuple:
    """⇒ (列名表, {主键元组: 整行元组})。库不在 / 表不在 ⇒ ([], {})。"""
    if not Path(库路径).is_file():
        return [], {}
    连接 = sqlite3.connect("file:%s?mode=ro" % 库路径, uri=True)
    try:
        列名表 = [数据行[1] for 数据行 in 连接.execute("pragma table_info('%s')" % 表名)]
        if not 列名表:
            return [], {}
        主键表 = [数据行[1] for 数据行 in 连接.execute("pragma table_info('%s')" % 表名) if 数据行[5]]
        if not 主键表:
            主键表 = [列名表[0]]
        主键位 = [列名表.index(列名) for 列名 in 主键表]
        行表 = {}
        for 行元组 in 连接.execute("select * from '%s'" % 表名):
            行表[tuple(行元组[列位] for 列位 in 主键位)] = tuple(行元组)
        return 列名表, 行表
    finally:
        连接.close()


def 取语义值(行元组, 列名表) -> tuple:
    """整行里去掉派生/自动列 ⇒ 用于比对的语义元组。行不在 ⇒ None。"""
    if 行元组 is None:
        return None
    return tuple(值 for 列名, 值 in zip(列名表, 行元组) if 列名 not in 忽略列)


def _列值(列名表, 行元组, 列名):
    if 行元组 is None or 列名 not in 列名表:
        return None
    return 行元组[列名表.index(列名)]


def 定列面(表名, 基列名表, 腿列名表, 主干列名表) -> tuple:
    """⇒ (列名表, 冲突项)。三库**列集合与顺序**必须一致 —— 否则逐列比对会静默错位 / 丢列。

    基库缺该表（合并基早于开表）⇒ 按**空基**处理：列面取腿 / 主干那一份（两者都有则须一致）。
    三库都没有该表 ⇒ (None, None)（真没这张表，跳过不是漏行）。
    不一致 ⇒ (None, 冲突项)：塞进冲突表 ⇒ 现有两个展示器（`_报冲突` · `_报冲突行`）照读
    `表` / `键` / `基值` / `腿值` / `主干值`，把三份列名元组原样报给人裁。
    """
    列名表 = 基列名表 or 腿列名表 or 主干列名表
    if not 列名表:
        return None, None
    不一致 = [别名 for 别名, 列面 in (("基", 基列名表), ("腿", 腿列名表), ("主干", 主干列名表))
             if 列面 and tuple(列面) != tuple(列名表)]
    if 不一致:
        return None, {"表": 表名, "键": ("列面",),
                      "基值": tuple(基列名表), "腿值": tuple(腿列名表), "主干值": tuple(主干列名表),
                      "说明": "列集合 / 顺序不一致（%s 与首份不同）⇒ 无法逐列无损重放" % "·".join(不一致)}
    return 列名表, None


def 备集成表(库件, 表名集) -> list:
    """集成树库缺表（基缺表 / 腿新增表）⇒ 按 `表定义.建表语句`（正式语句，唯一一份）建齐 ⇒ 缺过的表名。

    不补 DDL 就只能靠各表**自身**的写命令撞「no such table」⇒ 腿行整表静默漏掉（本批确认缺口）。
    只在**真缺表**时执行；三库都有的正常路径一个字节不动（`create ... if not exists` 全幂等）。
    """
    连接 = sqlite3.connect(str(库件))
    try:
        现有 = {数据行[0] for 数据行 in 连接.execute(
            "select name from sqlite_master where type='table'")}
        缺表 = sorted(set(表名集) - 现有)
        if not 缺表:
            return []
        for 语句 in 表定义.建表语句:
            连接.execute(语句)
        连接.commit()
        return 缺表
    finally:
        连接.close()


def 合并三方库(基库, 腿库, 主干库, 集成树) -> tuple:
    """⇒ (动作表, 冲突表, 跳过表)。

    动作 = 只有腿改（需重放）；冲突 = 两腿各改且不同（交人裁）；跳过 = 源件权威 / 重冻型（建库 重抽 / 冻结基线 重冻）。
    """
    动作表, 冲突表, 跳过表 = [], [], []
    for 表名 in 表定义.源表:
        基列名表, 基表 = 读源表(基库, 表名)
        腿列名表, 腿表 = 读源表(腿库, 表名)
        主干列名表, 主干表 = 读源表(主干库, 表名)
        列名表, 列面冲突 = 定列面(表名, 基列名表, 腿列名表, 主干列名表)
        if 列面冲突 is not None:
            冲突表.append(列面冲突)
            continue
        if not 列名表:
            continue
        for 主键值 in sorted(set(基表) | set(腿表) | set(主干表), key=repr):
            基值 = 基表.get(主键值)
            腿值 = 腿表.get(主键值)
            主干值 = 主干表.get(主键值)
            腿语 = 取语义值(腿值, 列名表)
            主语 = 取语义值(主干值, 列名表)
            基语 = 取语义值(基值, 列名表)
            # **正常三方**：腿未改 ⇒ 留主干；两侧同值 ⇒ 无事；只剩「腿改且与主干不同」要继续判 ——
            # 主干也没改 ⇒ 重放腿值；主干也改了 ⇒ 双方各改且不同 ⇒ **冲突**（交人裁）。
            if 腿语 == 基语 or 腿语 == 主语:
                continue
            if 表名 in 重冻表名:
                跳过表.append((表名, 主键值, 重冻权威说明))
                continue
            if 表名 == 条款表名 and 腿值 is not None and (Path(集成树) / str(腿值[0])).is_file():
                跳过表.append((表名, 主键值, 源件权威说明))
                continue
            if 表名 == "命名登记" and 主键值 == ("None",) and 腿值 is not None:
                跳过表.append((表名, 主键值, "施工误登记占位名，不进入主干"))
                continue
            if 主语 == 基语:
                # 只有腿改（含腿删：`腿值 = None`）；主干未动 ⇒ 重放腿值，无需人裁。
                动作表.append({"表": 表名, "键": 主键值, "列名表": 列名表, "腿值": 腿值})
            else:
                冲突表.append({"表": 表名, "键": 主键值, "列名表": 列名表,
                            "基值": 基值, "腿值": 腿值, "主干值": 主干值})
    return 动作表, 冲突表, 跳过表


def _跑一条(集成树, 参数表) -> tuple:
    """⇒ (退出码, 输出文本)。有界日志件的路径不回 —— 重放只看成不成。"""
    退出码, 输出文本, _ = 跑有界命令([sys.executable, 信息核心入口] + 参数表, 工作目录=集成树, 超时秒数=None)
    return 退出码, 输出文本


def _重放条款(集成树, 列名表, 腿值, 主键值) -> tuple:
    文档路径 = str(主键值[0])
    序号 = str(主键值[1])
    if 腿值 is None:
        return _跑一条(集成树, ["记条款", "--删", "--文档路径", 文档路径, "--序号", 序号, "--确认"])
    正文 = _列值(列名表, 腿值, "正文") or ""
    临时相对 = "重放正文-%s-%s.txt" % (文档路径.replace("/", "_"), 序号)
    临时件 = Path(集成树) / 临时相对
    临时件.write_text(正文, encoding="utf-8")
    try:
        参数表 = ["记条款", "--文档路径", 文档路径, "--序号", 序号,
                "--标题", str(_列值(列名表, 腿值, "标题") or ""), "--正文文件", 临时相对, "--覆盖"]
        # 仅执行三方比对已准许的非冲突动作；已有键需显式覆盖，直接记条款仍默认拒绝。
        权威档 = _列值(列名表, 腿值, "权威档")
        if 权威档:
            参数表 += ["--权威档", str(权威档)]
        if not 正文.strip():
            参数表 += ["--允许空正文"]
        return _跑一条(集成树, 参数表)
    finally:
        try:
            临时件.unlink()
        except OSError:
            pass


def _重放一条(集成树, 动作) -> tuple:
    表名 = 动作["表"]
    列名表 = 动作["列名表"]
    腿值 = 动作["腿值"]
    主键值 = 动作["键"]
    if 表名 == "命名登记":
        if 腿值 is None:
            return _跑一条(集成树, ["登记", "--删", "--名字", str(主键值[0])])
        return _跑一条(集成树, ["登记", "--名字", str(_列值(列名表, 腿值, "名字")),
                            "--语义", str(_列值(列名表, 腿值, "语义") or ""),
                            "--模式", str(_列值(列名表, 腿值, "模式") or ""),
                            "--来源", str(_列值(列名表, 腿值, "来源") or ""),
                            "--状态", str(_列值(列名表, 腿值, "状态") or "合格")])
    if 表名 == "命名泛名":
        参数表 = ["登记", "--泛名", "--名字", str(主键值[0])]
        if 腿值 is None:
            参数表 += ["--删"]
        else:
            参数表 += ["--说明", str(_列值(列名表, 腿值, "说明"))]
        return _跑一条(集成树, 参数表)
    if 表名 == "命名字典":
        if 腿值 is None:
            return 1, "命名字典 删行无具名命令 ⇒ fail-closed 拒并"
        return _跑一条(集成树, ["登记", "--名字", str(_列值(列名表, 腿值, "名字")),
                            "--分组", str(_列值(列名表, 腿值, "分组") or ""),
                            "--说明", str(_列值(列名表, 腿值, "说明") or "")])
    if 表名 == "命名例外":
        if 腿值 is None:
            return 1, "命名例外 删行无具名命令 ⇒ fail-closed 拒并"
        return _跑一条(集成树, ["登记", "--例外", "--名字", str(_列值(列名表, 腿值, "名字")),
                            "--理由", str(_列值(列名表, 腿值, "说明") or "")])
    if 表名 == "规则":
        if 腿值 is None:
            return _跑一条(集成树, ["记规则", "--删", "--编号", str(主键值[0])])
        return _跑一条(集成树, ["记规则", "--类", str(_列值(列名表, 腿值, "类") or ""),
                            "--名", str(_列值(列名表, 腿值, "名") or ""),
                            "--内容", str(_列值(列名表, 腿值, "内容") or ""),
                            "--依据", str(_列值(列名表, 腿值, "依据") or ""),
                            "--编号", str(_列值(列名表, 腿值, "编号") or "")])
    if 表名 == 条款表名:
        return _重放条款(集成树, 列名表, 腿值, 主键值)
    if 表名 == "未完成":
        if 腿值 is None:
            return _跑一条(集成树, ["记未完成", "--删", "--号", str(主键值[0])])
        参数表 = ["记未完成", "--号", str(主键值[0]),
                "--缺什么", str(_列值(列名表, 腿值, "缺什么") or "")]
        落点 = _列值(列名表, 腿值, "落点")
        验证命令 = _列值(列名表, 腿值, "验证命令")
        # **四栏显式传值**：`记未完成` 按「键在不在字段表」判保真值 —— 传了空串 = 把这栏清成空串，
        # 不传 = 更新保留原值、新增留 NULL。旧写法 `if 落点:` 会丢掉显式空串。
        if 落点 is not None:
            参数表 += ["--落点", str(落点)]
        if 验证命令 is not None:
            参数表 += ["--验证命令", str(验证命令)]
        return _跑一条(集成树, 参数表)
    return 1, "表 %s 无仓内具名命令 ⇒ fail-closed 拒并" % 表名


def _重放一件(入参) -> tuple:
    """进程池的工作体：一条动作 ⇒ `(退出码, 输出文本)`。

    **模块级函数** —— 池子按「模块名 + 函数名」反序列化它，闭包 / lambda 不行
    （同仓先例：`开发工具/取证/声明记录区反解/分片.py::_跑片`）。
    """
    集成树, 动作 = 入参
    return _重放一条(集成树, 动作)


def _串行重放(集成树, 动作表) -> list:
    """退路与基线：逐条串行重放 ⇒ 结果表（与动作表同序）。"""
    return [_重放一条(集成树, 动作) for 动作 in 动作表]


def 并行重放(集成树, 动作表, 档位=None) -> list:
    """把动作表摊给 **fork 进程池**逐条重放 ⇒ 结果表（**与动作表逐位同序**）。

    **为什么可以并行**：三方比对（`合并三方库`）对每张表按主键只出一条动作，故动作之间
    **主键互不相同**、彼此独立；每条动作 = 一条 `信息核心.py` 子进程（实测 0.10–0.11 s/条，
    其中大半是**进程启动**，不是算力）⇒ 天然可分片，摊到多核直接砍掉串行段。

    **为什么是 fork 不是线程**：动作体是「起子进程 + 等它跑完」，线程池只会把等待摊开、
    仍受 GIL 与串行启动调度；fork 是仓内先例（`取证/声明记录区反解/分片.py`）且子进程
    继承父进程已装载的模块（本仓 `信息核心/` 等目录没有 `__init__.py`，`spawn` 会 ImportError）。

    **退路只在池子起不来时走**（`fork` 不在 / 池子建不出）⇒ 退回串行，口径一字不变、不静默
    降级（真退回时命令变慢，会被墙钟读数照实报出）。**池子已起、工人中途抛**不退回 —— 那会把
    已执行的动作重跑一遍（`记规则 --删` 之类不幂等），直接让异常冒到调用方 fail-closed。
    """
    if not 动作表:
        return []
    档位数 = max(1, min(int(档位) if 档位 else 并行档位, len(动作表)))
    if 档位数 <= 1 or "fork" not in multiprocessing.get_all_start_methods():
        return _串行重放(集成树, 动作表)
    入参表 = [(str(集成树), 动作) for 动作 in 动作表]
    try:
        进程上下文 = multiprocessing.get_context("fork")
    except ValueError:
        return _串行重放(集成树, 动作表)
    try:
        进程池 = 进程上下文.Pool(processes=档位数)
    except (OSError, ValueError, NotImplementedError):
        return _串行重放(集成树, 动作表)
    with 进程池:
        return list(进程池.map(_重放一件, 入参表, chunksize=1))


def 重放动作表(集成树, 动作表, 主干库) -> tuple:
    """把非冲突动作重放进集成树的库 ⇒ (退出码, 行表)。先确保集成树库 = 主干版本。

    逐条重放的并发档位与退路见 `并行重放`；**行表顺序与逐条串行逐字相同**（结果表同序 + 按
    原序编号）⇒ 调用方与样本读到的回执一字不漂。
    """
    if not 动作表:
        return 0, []
    库件 = Path(集成树) / 表定义.库相对路径
    shutil.copyfile(主干库, 库件)
    行表 = ["集成树库先置为主干版本（消除 git 对二进制的自动取值），再按主键重放腿值"]
    缺表 = 备集成表(库件, {动作["表"] for 动作 in 动作表})
    if 缺表:
        行表.append("集成树库缺表 %s ⇒ 按 表定义.建表语句 正式建齐（基缺表 / 腿新增表，腿行一条不丢）"
                    % "·".join(缺表))
    for 序号, (动作, (退出码, 说明)) in enumerate(zip(动作表, 并行重放(集成树, 动作表)), 1):
        if 退出码 != 0:
            return 退出码, 行表 + ["重放失败（%s 主键 %r）：%s" % (动作["表"], 动作["键"], 说明[:1500])]
        首行 = 说明.strip().splitlines()[0] if 说明.strip() else ""
        行表.append("%d. %s：%s" % (序号, 动作["表"], 首行))
    return 0, 行表


def 建源库重抽(集成路径) -> tuple:
    """重放后**真跑仓内建源库**（重抽源件权威：活 md 的 `条款` 片）＋ `核源库` ＋ `冻结基线` ＋ 暂存 ⇒ (退出码, 行表)。

    为何必须（2026-10-08 收口方实测）：三方重放对源件权威表只「跳过」、从不重抽 ⇒ 库停在
    主干版，而活 md 已由 git 文本合过 ⇒ 合主干绿、库条款仍旧。
    （`未完成` 那一半 2026-10-13 起改「库即存本」⇒ 它已走逐键重放，不在此列。）
    这里把它补成真动作：① `建源库` 重抽；② `核源库` 逐条核活 md 抽取；
    ③ `冻结基线` 把十张基线（`重冻表名`，逐键重放跳过）按集成树现状**整表重冻**（只许减 ·
    fail-closed：腿真新增禁形名 / 新债即在此拒）；④ 库必须**全部暂存**（否则提交里的库是旧的
    —— 正是「绿而台账仍旧」那条）⇒ 未暂存即拒。任一步失败 ⇒ 退出码非 0，调用方 fail-closed
    （不推进主干、不假报）。
    """
    行表 = []
    退出码, 输出文本 = _跑一条(集成路径, ["建源库"])
    if 退出码 != 0:
        return 1, 行表 + ["   ★ 仓内建源库失败（退出码 %d）⇒ 拒（不推进主干）：%s"
                        % (退出码, 输出文本.strip()[:1500])]
    行表.append("   仓内建源库：源件权威（活 md）已重抽进集成树规则库")
    退出码, 输出文本 = _跑一条(集成路径, ["核源库"])
    for 说明行 in (输出文本.strip().splitlines() or ["核源库：无读数"]):
        行表.append("   " + 说明行)
    if 退出码 != 0:
        return 1, 行表 + ["   ★ 源库核验不过（退出码 %d）⇒ 拒（不推进主干）" % 退出码]
    库件 = Path(集成路径) / 表定义.库相对路径
    冻结前指纹 = 表定义.内容指纹(库件)
    冻结前字节 = 库件.read_bytes() if 库件.is_file() else None
    退出码, 输出文本 = _跑一条(集成路径, ["冻结基线"])
    for 说明行 in (输出文本.strip().splitlines() or ["冻结基线：无读数"]):
        行表.append("   " + 说明行)
    if 退出码 != 0:
        return 1, 行表 + ["   ★ 基线重冻不过（退出码 %d）⇒ 拒（不推进主干）：腿真新增禁形名 / "
                        "新债即在此拒（`冻结基线` 只许减 · fail-closed）" % 退出码]
    # `冻结基线` 的整表重写（delete + insert）会**白改 sqlite 事务计数**：内容一字未变时也换字节
    # ⇒ 恢复现场重放会因这点字节差多造一个提交（幂等破）。照 `建源库` 先例（内容指纹不变即还原字节）。
    if 冻结前字节 is not None and 表定义.内容指纹(库件) == 冻结前指纹:
        库件.write_bytes(冻结前字节)
    退出码, 输出文本, _ = 跑有界命令(["git", "add", 表定义.库相对路径], 工作目录=集成路径)
    if 退出码 != 0:
        return 1, 行表 + ["   ★ 源库 git add 失败：%s" % 输出文本.strip()[-300:]]
    退出码, 输出文本, _ = 跑有界命令(["git", "diff", "--name-only", "--", 表定义.库相对路径],
                                工作目录=集成路径, 超时秒数=5)
    if 退出码 != 0:
        return 1, 行表 + ["   ★ 源库暂存态读不出：%s" % 输出文本.strip()[-300:]]
    if 输出文本.strip():
        return 1, 行表 + ["   ★ 建源库后源库仍有未暂存改动 ⇒ 拒（提交里的库会是旧的）：%s"
                        % 输出文本.strip()[-300:]]
    行表.append("   源库已暂存（git add）：提交带的是重抽后的库")
    return 0, 行表
