"""清树门禁 —— 物理删除（清工作树 / 删支线）前的**唯一**安全判定口。

一句话：删旧树前逐条核「已合主干 · 净树 · 无在途作业 · 无未释放继承者与基线消费者 ·
台账未点名 · 无未蒸馏反馈」，一条不成立就**拒删并精确定位**（fail-closed）。

**唯一一份**：`开工.单纯释放`（功能 4）与 `开工记忆.核安全条件`（记忆边界 / 安全清收口）都从
这里取条件 —— 不各写一份「什么算能删」。已合主干 + 净树（含未跟踪）复用 `仓操作.检查清树安全`；
在途作业复用 `作业账本.非终态集`；继承者 / 基线消费者复用账本事实（`开工.父开工号`）；
未蒸馏反馈复用反馈保护口 `反馈关联.未蒸馏反馈集`（迟到导入：反馈包未合入 ⇒ 明确未启用、不阻断；
在场后任何错误一律 fail-closed）。**不另存状态表** —— 判据全由现成账本事实 + 现成检查合成。

`回滚登记` 同样先证「无成果 · 无消费者」再清本次创建的资源；有其一 ⇒ 保留并定位（fail-closed）。
"""
import os
import sqlite3
import sys
from pathlib import Path

from . import 开工账本 as 账本
from . import 作业账本
from .仓操作 import 检查清树安全, 变更路径表, 找工作树, 支线在吗, 清工作树


def 非终态作业(开工号, 工作树):
    """与本开工相关、**尚未收敛**的后台作业 ⇒ 行表；作业账本读不出 ⇒ `None`（fail-closed）。

    关联口径：`作业` 表**有** `开工ID` 列就按它匹配；没有就退回按 `工作树` 匹配（安全兜底）。
    """
    路径 = 作业账本.作业账本路径()
    if not Path(路径).is_file():
        return []
    连接 = sqlite3.connect("file:%s?mode=ro" % 路径, uri=True)
    try:
        连接.row_factory = sqlite3.Row
        try:
            列名集 = {文本行[1] for 文本行 in 连接.execute("pragma table_info(作业)")}
            行表 = 连接.execute("select * from 作业").fetchall()
        except sqlite3.Error:
            return None
    finally:
        连接.close()
    命中 = []
    for 数据行 in 行表:
        记录行 = dict(数据行)
        if 记录行.get("状态") not in 作业账本.非终态集:
            continue
        # ★ 2026-10-10（债务 326）：**正在跑这次核清树的那条作业**不算「未收敛」——
        #   它就是本进程（`作业.py` 起作业时注入了 `V1_任务ID`）。排除后，释放作业才可能自证清树。
        if 记录行.get("任务ID") and 记录行.get("任务ID") == os.environ.get("V1_任务ID"):
            continue
        if "开工ID" in 列名集:
            属本开工 = bool(记录行.get("开工ID")) and 记录行.get("开工ID") == 开工号
        else:
            属本开工 = Path(str(记录行.get("工作树") or "")).resolve() == Path(str(工作树)).resolve()
        if 属本开工:
            命中.append("%s · %s · 退出码 %s · 命令 %s" % (
                记录行.get("任务ID"), 记录行.get("状态"), 记录行.get("退出码"), 记录行.get("命令")))
    return 命中


def 读未完成行(仓根, 开工号):
    """库 `未完成` 表里提到本开工号的原文行 ⇒ 行表（台账是证据，不许被清流程绕过）。

    ★ 2026-10-14 修（债务 599）：原先读**已删件** `开发工具/信息核心/未完成.json` —— 件不在盘上
    ⇒ 恒判「未点名」⇒ **带未了结台账证据的腿可被清掉**（fail-open）。台账自 2026-10-13 起
    「库即存本」⇒ 改读库 `未完成` 表。库不在 ⇒ 空表（新克隆未建库）；库在场但读不动 ⇒
    异常上抛（fail-closed，不许把「读不动」当成「未点名」）。
    """
    # 点号全路径取 `表定义`：`开发工具/信息核心` 也在 sys.path 上（别的件插的）⇒ 直接
    # `import 信息核心.表定义` 会被同目录下的 `信息核心.py` 遮蔽（命名空间包让位于常规模块）。
    模块根 = str(Path(__file__).resolve().parents[2])
    if 模块根 not in sys.path:
        sys.path.insert(0, 模块根)
    from 开发工具.信息核心.表定义 import 库路径 as 规则库路径
    库件 = 规则库路径(仓根)
    if not 库件.is_file():
        return []
    连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
    try:
        行表 = 连接.execute(
            "select 号, coalesce(缺什么, '') || ' ' || coalesce(落点, '') || ' '"
            " || coalesce(验证命令, '') from 未完成").fetchall()
    finally:
        连接.close()
    命中 = []
    for 数据行 in 行表:
        if 开工号 in "%s %s" % (数据行[0], 数据行[1]):
            命中.append("[%s] %s" % (数据行[0], 数据行[1].strip()))
    return 命中


def 消费者行(开工号):
    """以本开工号为 `父开工号` 的**别的**开工 ⇒ 行表（继承者 / 基线消费者，按种类标注）。

    `父开工号` = 被合 / 被接管的原腿：接管腿（`记归属` 于 `集成接管`）· 以本腿为 `基线` 并入的
    消费腿（`记归属` 于 `登记编排.登记主体`）。**只读**；清树前判「有没有未释放消费者」的唯一取数口。
    """
    连接 = 账本.连账本()
    try:
        return [dict(数据行) for 数据行 in 连接.execute(
            "select 开工号, 状态, 开工种类 from 开工 where 父开工号 = ? order by 开工号", (开工号,))]
    finally:
        连接.close()


def 基线消费者行(开工号):
    """`父开工号` == 本开工号、且**非接管 / 非集成**（把本腿当 `基线` 并入的消费腿）⇒ 行表。"""
    return [记录行 for 记录行 in 消费者行(开工号)
            if 记录行.get("开工种类") not in (账本.种类_接管, 账本.种类_集成)]


def 消费者标注(记录行):
    """一条消费者记录 ⇒ 可读标注（继承者 / 基线消费者 + 状态）。"""
    种类值 = 记录行.get("开工种类") or 账本.种类_原腿
    标注词 = "继承者（%s）" % 种类值 if 种类值 in (账本.种类_接管, 账本.种类_集成) else "基线消费者"
    return "%s %s（%s）" % (记录行["开工号"], 标注词, 记录行["状态"])


反馈件名 = "反馈关联.py"


def 反馈保护启用():
    """反馈保护口是否在场（`反馈关联.py` 与本件同目录）⇒ 真假。

    在场 ⇒ 合入后一切错误 fail-closed；不在 ⇒ 明确「未启用」（本包单独树测试，不阻断）。
    """
    return Path(__file__).with_name(反馈件名).is_file()


def 未蒸馏反馈行(连接, 仓根, 开工号):
    """反馈保护口（`反馈关联.未蒸馏反馈集`）⇒ 需保留的未蒸馏反馈行表。

    **唯一合同**：`反馈关联.py::未蒸馏反馈集(连接, 仓根, 开工号) -> list[str]`（不从反馈账本导出）。
    `连接` 同一本开工账本；`仓根` 必须显式实际目标树（解析现行 `未完成` 表不可猜）；非空 ⇒ 拒。
    仅当反馈模块**尚不存在**（`反馈保护启用` = 假）时明确「未启用」返回空表（本包单独树测试）；
    模块在场后**任何错误一律 fail-closed** —— 不许泛 catch `ImportError` 吞掉已存在模块的内部导入错误。
    """
    if not 反馈保护启用():
        return []
    try:
        from .反馈关联 import 未蒸馏反馈集
        反馈读数 = 未蒸馏反馈集(连接, 仓根, 开工号)
        return ["%s" % 一条反馈 for 一条反馈 in (反馈读数 or [])]
    except Exception as 错误:
        return ["（反馈保护口读不出 ⇒ fail-closed 当作有未蒸馏反馈：%r）" % (错误,)]


def 自动记录行(连接, 仓根, 开工号):
    """机器产生、**不阻断释放**的未蒸馏记录 ⇒ 行表（供回执显式报出，避免「看起来干净」）。

    **唯一合同**：`反馈关联.py::自动记录行(连接, 仓根, 开工号) -> list[str]`。与阻断口同源分流，
    区别只在：机器记录**无阻断权**（不参与 `条件均成立`），故本口**读不出就给空表**（信息项，
    不像阻断口那样 fail-closed —— 安全由同一份阻断口单独兜住）。
    """
    if not 反馈保护启用():
        return []
    try:
        from .反馈关联 import 自动记录行 as 取自动记录行
        自动行 = 取自动记录行(连接, 仓根, 开工号) or []
        return ["%s" % 一条反馈 for 一条反馈 in 自动行]
    except Exception:
        return []


def 核清树条件(连接, 仓根, 开工号, 开工记录, 要求已释放=True):
    """物理删除**逐条**判据 ⇒ `(是否全成立, 判据行表)`。一条不成立 ⇒ 不可删（fail-closed）。"""
    行表 = []
    条件均成立 = True

    def 记判据(通过, 说明):
        nonlocal 条件均成立
        if not 通过:
            条件均成立 = False
        行表.append("%s %s" % ("✓" if 通过 else "✗", 说明))

    if 要求已释放:
        记判据(开工记录["状态"] == 账本.状态_已释放,
            "收口成功（状态「已释放」）—— 现「%s」" % 开工记录["状态"])
    退出码, 清树说明 = 检查清树安全(仓根, 开工号, 开工记录["工作树"])
    记判据(退出码 == 0, "验证已合主干且净树（含未跟踪）—— %s（退出码 %d）" % (清树说明, 退出码))
    作业行 = 非终态作业(开工号, 开工记录["工作树"])
    if 作业行 is None:
        记判据(False, "非终态作业读不出（作业账本异常）⇒ fail-closed，当作有未收敛作业")
    else:
        记判据(not 作业行, "无尚未收敛的后台作业" + ("（有 %d 条）" % len(作业行) if 作业行 else ""))
    for 行文本 in 作业行 or []:
        行表.append("    · " + 行文本)
    消费者表 = 消费者行(开工号)
    未释放表 = [记录行 for 记录行 in 消费者表 if 记录行["状态"] != 账本.状态_已释放]
    记判据(not 未释放表, "无凡属本开工的**未释放**继承者 / 基线消费者"
        + ("；未释放：%s" % " · ".join(消费者标注(记录行) for 记录行 in 未释放表) if 未释放表 else ""))
    for 记录行 in 消费者表:
        行表.append("    · " + 消费者标注(记录行))
    未完成行 = 读未完成行(仓根, 开工号)
    记判据(not 未完成行, "库 `未完成` 表未点名本开工（有证据 ⇒ 不许清）")
    for 行文本 in 未完成行[:5]:
        行表.append("    · 台账：" + 行文本)
    反馈行 = 未蒸馏反馈行(连接, 仓根, 开工号)
    记判据(not 反馈行, "无未蒸馏反馈（反馈保护口）" + ("；有 %d 条" % len(反馈行) if 反馈行 else ""))
    for 行文本 in 反馈行[:5]:
        行表.append("    · 反馈：" + 行文本)
    自动行 = 自动记录行(连接, 仓根, 开工号)
    if 自动行:
        行表.append("○ 另有 %d 条自动性能记录（不阻断释放）—— 留痕可查（`查反馈` / `列反馈来源`）"
                 % len(自动行))
    return 条件均成立, 行表


def 回滚登记(仓根, 连接, 开工号):
    """登记失败时回滚**本次创建**的资源 ⇒ 说明行（可接在失败回执后）；幂等。

    只清本次创建的（开工行 / 认领行 / 工作树 / 支线），且**先证无成果 · 无消费者**：
      · 工作树有未提交 / 未跟踪改动 ⇒ **保留**（不许丢未证明的成果）；
      · 有别的开工以本号为父（继承者 / 基线消费者）⇒ **保留**（不许断消费者）。
    开工行已不在 ⇒ 空串（重复回滚一个字节都不再动）。
    """
    开工记录 = 账本.读开工(连接, 开工号)
    if not 开工记录:
        # ★ 行已不在 ≠ 没残留（2026-10-12 实测）：登记失败时**开工行可能已被删**，回滚再进来
        #   只看到「行不在」⇒ 原先直接返回，于是**工作树/支线留着**；下次登记撞上残留分支，
        #   报出的还是误导性的「读不动规则库」，要人工查 git branch
        #   才发现。故行不在时**仍要收尾**：先问 git 有没有残留，有就清、没有才返回空串。
        工作树残留 = 找工作树(仓根, 开工号) is not None
        支线残留 = 支线在吗(仓根, 开工号)
        if not 工作树残留 and not 支线残留:
            return ""
        收尾码, 收尾说明 = 清工作树(仓根, 开工号)
        return "（回滚补收尾：开工行已不在，但仍有残留 ⇒ %s）" % 收尾说明
    消费者表 = 消费者行(开工号)
    if 消费者表:
        return ("★ 登记失败但**回滚保留**：%s 已有 %d 条继承者 / 基线消费者（%s）—— "
                "工作树与账本行都留着，查清再处置。"
                % (开工号, len(消费者表), " · ".join(消费者标注(记录行) for 记录行 in 消费者表)))
    工作树 = 开工记录["工作树"]
    if Path(工作树).is_dir():
        退出码, 变更表 = 变更路径表(工作树)
        if 退出码 != 0:
            return ("★ 登记失败但**回滚保留**：%s 工作树状态读不出 ⇒ fail-closed，保留树与账本行。"
                    % 开工号)
        if 变更表:
            return ("★ 登记失败但**回滚保留**：%s 工作树有未提交 / 未跟踪成果（%s）—— 保留树与账本行。"
                    % (开工号, " · ".join(sorted(set(变更表))[:8])))
    清工作树(仓根, 开工号)
    连接.execute("delete from 认领 where 开工号 = ?", (开工号,))
    连接.execute("delete from 开工 where 开工号 = ?", (开工号,))
    连接.commit()
    return "（回滚：已清本次创建的开工行 / 认领行 / 工作树 / 支线）"
