    """统一处理签名，开工ID解析的目标树决定源库落点。"""
    def 操作处理(开工号, 参数表, 仓根):
        from .仓操作 import 找工作树
        if 开工号:
            工作树 = 找工作树(仓根, 开工号)
            if 工作树 is None or not 工作树.is_dir():
                return 1, "开工 %s 的工作树不在" % 开工号
            仓根 = 工作树
        if 干跑 is None:
            return 落库操作(仓根, 参数表)
        return 跑批操作(仓根, 参数表, 干跑, 开工号)
    return 操作处理

