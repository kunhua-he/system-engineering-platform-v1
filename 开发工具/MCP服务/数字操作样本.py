# -*- coding: utf-8 -*-
"""数字操作样本 —— 顶层 `操作` 数字选择与编辑条目数值选择的正反样本（判据 ㊽ 经 `自检样本` 跑）。

**为何单开一件**（判据 ⑲ 单源文件 ≤400 行）：`自检样本.py` 已顶硬数；本组是**纯函数 + 两条便宜
只读调用**（不动仓、不起重进程），按先例单开、`自检样本.自检主体` 只加一行调用。

一片一测（每条都可证伪）：
  · 编号表自洽 —— 号→名唯一；名（除尚未并入的反馈包模块）都在该工具真实操作表里。
  · 别名等价（归一层）—— 每个号、数字串、操作名都归一到同一个操作名。
  · 0 有效 + 留空发现 —— `操作=0` 是该工具第 0 号操作（不是发现）；留空才回操作目录。
  · 拒绝 —— 逻辑值 / 浮点 / 未知号 / 非法数字串一律拒，且**不执行**。
  · 网关层等价 —— `v1_shell` 的 0 与 `执行`、`v1_task` 的 0 与 `查询` 回同一退出码与操作名。
  · 改动表数值选择 —— 0/1/2 与 新建/修改/删除 等价；`操作` 与 `功能` 并存且**矛盾 ⇒ 整批零写拒**；
    逻辑值 / 浮点 / 未知号 / 非法数字串拒（不做 int 宽转换）。
"""


def 样本列表(仓根, 工具表) -> list:
    """数字选择面的正反样本 ⇒ 样本表 `[(说明, 通过)]`（纯函数为主，只两条便宜只读调用）。"""
    import json

    from . import 参数规范, 操作_编辑, 操作编号

    规范表 = 参数规范.载入操作表()
    样本表 = []

    # ── ① 编号表自洽：号→名唯一；名都在真实操作表里（除显式声明的待并入名）──
    for 工具名, 分表 in 操作编号.编号表.items():
        名表 = list(分表.values())
        未覆盖 = sorted(set(名表) - set(规范表.get(工具名, {})) - 操作编号.待并入名)
        样本表.append(("%s 编号表自洽：号→名唯一且名都在操作表里（未覆盖 %s）" % (工具名, 未覆盖 or "无"),
                  len(set(名表)) == len(名表) and bool(名表) and not 未覆盖))

    # ── ② 别名等价（归一层）：号 / 数字串 / 操作名 → 同一操作名 ──
    for 工具名, 分表 in 操作编号.编号表.items():
        for 操作号, 操作名 in 分表.items():
            样本表.append(("%s 别名等价：%d ≡ %s（整数 / 数字串 / 名同一结果）" % (工具名, 操作号, 操作名),
                     操作编号.归一操作(工具名, 操作号) == (操作名, None)
                     and 操作编号.归一操作(工具名, str(操作号)) == (操作名, None)
                     and 操作编号.归一操作(工具名, 操作名) == (操作名, None)))

    # ── ③ 0 有效 + 留空发现 ──
    样本表.append(("0 有效：v1_task 操作=0 归一到「查询」（不是发现）",
             操作编号.归一操作("v1_task", 0) == ("查询", None)))
    样本表.append(("留空发现：None / 空串 / 全空白都归一到发现（空名）",
             操作编号.归一操作("v1_task", None) == ("", None)
             and 操作编号.归一操作("v1_task", "") == ("", None)
             and 操作编号.归一操作("v1_task", "   ") == ("", None)))

    # ── ④ 拒绝：逻辑值 / 浮点 / 未知号 / 非法数字串 ──
    for 标签, 原值 in (("逻辑值", True), ("浮点", 1.0), ("未知号", 999), ("未知数字串", "999"),
                  ("非法数字串", "1.0"), ("带字数字串", "1a")):
        归一结果, 错误 = 操作编号.归一操作("v1_task", 原值)
        样本表.append(("拒绝·%s：%r 被拒且不归一" % (标签, 原值), 归一结果 is None and bool(错误)))

    # ── ⑤ 网关层等价（两条便宜只读调用）──
    出口 = 工具表["v1_shell"][0]
    数字退出码, 数字回执 = 出口({"操作": 0, "参数": {"命令": "echo v1_数字别名"}}, 仓根)
    名称退出码, 名称回执 = 出口({"操作": "执行", "参数": {"命令": "echo v1_数字别名"}}, 仓根)
    样本表.append(("网关等价·v1_shell：0 与 执行 同退出码（%d/%d）同操作名（%s/%s）"
             % (数字退出码, 名称退出码, json.loads(数字回执).get("操作"), json.loads(名称回执).get("操作")),
             数字退出码 == 名称退出码 == 0
             and json.loads(数字回执).get("操作") == json.loads(名称回执).get("操作") == "执行"
             and "v1_数字别名" in 数字回执 and "v1_数字别名" in 名称回执))
    出口 = 工具表["v1_task"][0]
    数字退出码, 数字回执 = 出口({"操作": 0}, 仓根)
    名称退出码, 名称回执 = 出口({"操作": "查询"}, 仓根)
    样本表.append(("网关等价·v1_task：0 与 查询 同退出码（%d/%d）同操作名（%s/%s）"
             % (数字退出码, 名称退出码, json.loads(数字回执).get("操作"), json.loads(名称回执).get("操作")),
             数字退出码 == 名称退出码 == 0
             and json.loads(数字回执).get("操作") == json.loads(名称回执).get("操作") == "查询"))

    # ── ⑥ 改动表数值选择：0/1/2 ≡ 新建/修改/删除；矛盾零写拒；拒逻辑值 / 浮点 / 未知号 / 非法数字串 ──
    换改动 = 操作_编辑.换改动
    形表 = {"路径": "样例.py", "旧内容": "旧", "新内容": "新"}
    新建换算, _ = 换改动({"改动表": [dict(形表, 操作=0)]})
    名称换算, _ = 换改动({"改动表": [dict(形表, 操作="新建")]})
    功能换算, _ = 换改动({"改动表": [dict(形表, 功能=0)]})
    样本表.append(("改动表数值选择：操作=0 ≡ 操作=新建 ≡ 功能=0（同换算）",
             新建换算 == 名称换算 == 功能换算 and bool(新建换算)
             and 新建换算[0].get("功能") == 0))
    修改换算, _ = 换改动({"改动表": [dict(形表, 操作=1)]})
    样本表.append(("改动表数值选择：操作=1 → 修改（功能 1）", 修改换算[0].get("功能") == 1))
    删除换算, _ = 换改动({"改动表": [dict(形表, 操作="2")]})
    样本表.append(("改动表数值选择：数字串 操作=\"2\" → 删除（功能 2）", 删除换算[0].get("功能") == 2))
    矛盾换算, 矛盾错误 = 换改动({"改动表": [dict(形表, 操作="修改", 功能=2)]})
    样本表.append(("改动表矛盾选择：操作=修改 与 功能=2 并存且矛盾 ⇒ 整批零写拒",
             矛盾换算 == [] and bool(矛盾错误) and "矛盾" in 矛盾错误))
    一致换算, 一致错误 = 换改动({"改动表": [dict(形表, 操作="修改", 功能=1)]})
    样本表.append(("改动表并存且一致：操作=修改 与 功能=1 ⇒ 放行（功能 1）",
             一致错误 is None and 一致换算[0].get("功能") == 1))
    for 标签, 坏值 in (("逻辑值", True), ("浮点", 1.0), ("非法数字串", "1.0"), ("未知号", 9)):
        功能拒后, 功能拒错 = 换改动({"改动表": [dict(形表, 功能=坏值)]})
        样本表.append(("改动表·功能拒%s：%r 被拒且空表" % (标签, 坏值), 功能拒后 == [] and bool(功能拒错)))
        操作拒后, 操作拒错 = 换改动({"改动表": [dict(形表, 操作=坏值)]})
        样本表.append(("改动表·操作拒%s：%r 被拒且空表" % (标签, 坏值), 操作拒后 == [] and bool(操作拒错)))
    return 样本表
