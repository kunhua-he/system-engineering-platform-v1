# -*- coding: utf-8 -*-
"""冲突样本 —— 跨开工重叠的**状态化回执**与**隔离硬闸**的正反样本（临时夹具，跑完即删）。

`自检样本.跑自检` 调它（判据 ㊽ 跑自检，退出码非 0 ⇒ 闸 0 当场红）。**仓一个字节都不改**：
账本连口、支线问口与 git 树身份都走替身（git 层由 `认领样本.py` 的临时真仓覆盖）。

三档口径（与 `开工账本.拼冲突回执` 同一份文案）：
  ① 独立副本重叠（只撞进行中）⇒ 放行（退出码 0），回执**逐件带准确状态**，**不带**清树话术。
  ② 独立副本重叠（撞待合 + 已释放）⇒ 放行，回执含「未核是否已合主干」「核已合且净树后由收口方
     功能 = 4 收口（工具不自动清）」—— 条件式安全清理，**不自行清**；占位工作树原样保留。
  ③ **隔离硬闸**（占位开工与本开工**同一棵树**）⇒ 拒（退出码 2）· 回执带「硬闸」·
     `确认重叠` = 真**也不放行**；别的开工的认领**指纹没被洗**。
"""
import shutil
import sqlite3
import tempfile
from pathlib import Path


def 冲突回执样本(仓根, 工具表) -> list:
    """跑三档正反样本 ⇒ 样本表。"""
    from . import 开工, 开工账本, 认领隔离

    临时根 = Path(tempfile.mkdtemp(prefix="v1冲突回执自检-"))
    try:
        工作树 = 临时根 / "工作树"
        (工作树 / "临时区").mkdir(parents=True)
        争用件进行中 = 工作树 / "临时区" / "争用件进行中.py"
        争用件进行中.write_text("共用件首 = 1\n", encoding="utf-8")
        争用件待合 = 工作树 / "临时区" / "争用件待合.py"
        争用件待合.write_text("共用件次 = 1\n", encoding="utf-8")
        争用件同树 = 工作树 / "临时区" / "争用件同树.py"
        争用件同树.write_text("共用件末 = 1\n", encoding="utf-8")
        占位树 = {}
        for 占位号 in ("v1-占位进行中", "v1-占位待合", "v1-占位已释放"):
            占位树[占位号] = 临时根 / 占位号
            占位树[占位号].mkdir()
        占位树["v1-占位同树"] = 工作树          # ③ 硬闸：占位开工与本开工**同一棵树**
        账本路径 = 临时根 / "账本.db"
        连接 = sqlite3.connect(str(账本路径))
        连接.row_factory = sqlite3.Row
        for 建表行 in 开工账本.建表语句:
            连接.execute(建表行)
        开工账本.登记开工(连接, "v1-自检主", "冲突回执样本", "腿/v1-自检主", str(工作树))
        开工账本.登记开工(连接, "v1-占位进行中", "占位进行中", "腿/v1-占位进行中",
                    str(占位树["v1-占位进行中"]))
        开工账本.登记开工(连接, "v1-占位待合", "占位待合", "腿/v1-占位待合",
                    str(占位树["v1-占位待合"]))
        开工账本.登记开工(连接, "v1-占位已释放", "占位已释放", "腿/v1-占位已释放",
                    str(占位树["v1-占位已释放"]))
        开工账本.登记开工(连接, "v1-占位同树", "占位同树", "腿/v1-占位同树",
                    str(占位树["v1-占位同树"]))
        开工账本.置状态(连接, "v1-占位待合", 开工账本.状态_待合并)
        开工账本.置状态(连接, "v1-占位已释放", 开工账本.状态_已释放)
        连接.executemany("insert into 认领 (开工号, 路径, 指纹) values (?,?,?)",
                  [("v1-占位进行中", "临时区/争用件进行中.py", "占位指纹"),
                   ("v1-占位待合", "临时区/争用件待合.py", "占位指纹"),
                   ("v1-占位已释放", "临时区/争用件待合.py", "占位指纹"),
                   ("v1-占位同树", "临时区/争用件同树.py", "占位指纹")])
        连接.commit()
        连接.close()

        def 开账():
            新连接 = sqlite3.connect(str(账本路径))
            新连接.row_factory = sqlite3.Row
            return 新连接

        def 树身份(忽略仓根, 树, 忽略分支):
            # 与真 `核验树身份` 同一口径：树根**先 resolve**（`/var` 与 `/private/var` 是同一条）。
            return Path(树).resolve(), "样本提交"

        真连, 真支线, 真核验 = 开工账本.连账本, 开工.支线在吗, 认领隔离.核验树身份
        开工账本.连账本 = 开账
        开工.支线在吗 = lambda 忽略仓根, 忽略开工号: False
        认领隔离.核验树身份 = 树身份        # git 层替身：本样本只判**回执与硬闸**，真树身份由 `认领样本.py` 覆盖
        出口 = 工具表["v1_task"][0]
        样本表 = []
        try:
            退出码, 回执 = 出口(
                {"开工ID": "v1-自检主", "操作": "补充",
                 "参数": {"文件认领": ["临时区/争用件进行中.py"]}}, 仓根)
            样本表.append(("v1_task 补充 独立副本重叠（只撞进行中）：退出码 %d（期望 0）· 含「进行中」%s · "
                    "清树话术%s · 已显式确认%s"
                    % (退出码, "是" if "进行中" in 回执 else "否",
                       "**带了**" if ("清理" in 回执 or "功能 = 4" in 回执) else "不带",
                       "齐" if "已显式确认" in 回执 else "**缺**"),
                     退出码 == 0 and "进行中" in 回执 and "清理" not in 回执 and "功能 = 4" not in 回执
                     and "已显式确认" in 回执 and "Traceback" not in 回执))
            退出码, 回执 = 出口(
                {"开工ID": "v1-自检主", "操作": "补充",
                 "参数": {"文件认领": ["临时区/争用件待合.py"]}}, 仓根)
            状态齐 = all(命中词 in 回执 for 命中词 in
                     ("已提交待合并", "已释放", "未核是否已合主干", "核已合且净树后"))
            保树 = all(占位树[占位号].is_dir() for 占位号 in 占位树)
            样本表.append(("v1_task 补充 独立副本重叠（撞待合 + 已释放）：退出码 %d（期望 0）· 状态%s准 · "
                    "条件清理%s · 称清理漏%s · 占位树%s保留"
                    % (退出码, "" if 状态齐 else "**不**",
                       "在" if "核已合且净树后" in 回执 else "**缺**",
                       "**是**" if "清理漏" in 回执 else "否", "" if 保树 else "**没**"),
                     退出码 == 0 and 状态齐 and "清理漏" not in 回执 and 保树
                     and "Traceback" not in 回执))
            退出码, 回执 = 出口(
                {"开工ID": "v1-自检主", "操作": "补充",
                 "参数": {"文件认领": ["临时区/争用件同树.py"], "确认重叠": True}}, 仓根)
            连接 = 开账()
            指纹未洗 = 连接.execute("select 指纹 from 认领 where 开工号 = ? and 路径 = ?",
                              ("v1-占位同树", "临时区/争用件同树.py")).fetchone()[0] == "占位指纹"
            连接.close()
            样本表.append(("v1_task 补充 隔离硬闸（占位开工与本开工同树 · 确认重叠=真）：退出码 %d（期望 2）· "
                    "说「硬闸」%s · 别的开工认领指纹%s被洗"
                    % (退出码, "是" if "硬闸" in 回执 else "否", "" if 指纹未洗 else "**"),
                     退出码 == 2 and 指纹未洗 and "硬闸" in 回执 and "Traceback" not in 回执))
        finally:
            开工账本.连账本, 开工.支线在吗, 认领隔离.核验树身份 = 真连, 真支线, 真核验
        return 样本表
    finally:
        shutil.rmtree(临时根, ignore_errors=True)
