# -*- coding: utf-8 -*-
"""集成接管 —— 把「合并冲突保留的集成树」正式绑成一条可编辑开工（唯一受控冲突解决入口）。

合并编排遇代码冲突时保留隔离集成树（分支 `集成/<原开工号>`，落系统临时目录）。`v1_edit` 只认
账本里那条开工的**正式工作树** ⇒ 那条树原先谁也改不了，只能绕写（实测 2026-10-07：收口腿
只能脚本直改 `自检样本.py` 解冲突 —— 那是**第二写盘**，违反「唯一 v1_edit」）。

本件给的唯一口：**复用** `v1_task` 的开工登记 + 认领 + 指纹与 `v1_edit` 的原编辑路径 ——
把集成树登记成一条正式开工（工作树 = 集成树、认领 = 未合并冲突件），此后 `v1_edit` 照常过
四道闸、逐条记账。**不新增写盘口**：本件一个源码字节都不写（只读盘算指纹 + 登记账本）。
授权来自**集成现场核验 + 账本绑定**，不是「传一个临时目录路径」。
"""

import re
from pathlib import Path

from . import 开工账本 as 账本
from . import 合主干集成树 as 集成
from .仓操作 import 读盘指纹
from .合主干有界跑 import 跑有界命令
from .合主干源库重放 import 取语义值, 读源表

库相对路径 = "开发工具/信息核心/信息核心.db"
开工号形状 = re.compile(r"v1-[0-9]{6}")


def _跑(命令表, 工作目录):
    return 跑有界命令(命令表, 工作目录=工作目录, 超时秒数=5)


def 找接管开工(连接, 集成路径) -> str:
    """账本里**工作树 == 集成路径**、状态「进行中」的开工号 ⇒ 号或空串（**一处查口**）。"""
    目标 = Path(str(集成路径)).resolve()
    for 开工记录 in 账本.全部开工(连接):
        if 开工记录["状态"] == 账本.状态_进行中 and Path(开工记录["工作树"]).resolve() == 目标:
            return 开工记录["开工号"]
    return ""


def 核现场(仓根, 原开工号) -> tuple:
    """核验集成现场真是本项目、原开工号那条腿的现场 ⇒ (退出码, 集成路径 或 说明)。

    只认 `git worktree list` 里登记、分支 == `集成/<原开工号>`、公共主仓 == 仓根的那棵 ——
    **不接受任何传参路径当授权**（未知绝对目录 / 非本项目集成树一律拒）。
    """
    集成路径 = 集成.找集成树(仓根, 原开工号)
    if 集成路径 is None:
        return 1, ("没有已知集成现场：%s（先跑 `合并主干.py %s` 造现场；"
                 "本口只认本项目 git 登记的集成树，不接任意路径）" % (原开工号, 原开工号))
    退出码, 定位 = 集成.定位主仓(集成路径)
    if 退出码 != 0 or Path(str(定位)).resolve() != Path(仓根).resolve():
        return 1, "集成现场不属于本项目主仓：%s（%s）" % (集成路径, 定位)
    return 0, 集成路径


def 未合并件(集成路径) -> tuple:
    """集成树里未合并的**文本**冲突件（剔源库 —— 源库由编排的正式重放处置）⇒ (退出码, 件表 或 说明)。"""
    退出码, 输出文本, 日志路径 = _跑(["git", "diff", "--name-only", "--diff-filter=U"], 集成路径)
    if 退出码 != 0:
        return 1, "读不出未合并件（退出码 %d）· 日志 %s\n%s" % (退出码, 日志路径, 输出文本[:400])
    件表 = [数据行.strip() for 数据行 in 输出文本.splitlines()
          if 数据行.strip() and 数据行.strip() != 库相对路径]
    return 0, 件表


def 派发(仓根, 原开工号) -> tuple:
    """`v1_task 操作=接管集成` 的实现 ⇒ (退出码, 文本)。"""
    仓根 = Path(str(仓根)).resolve()
    原开工号 = (原开工号 or "").strip()
    if not 开工号形状.fullmatch(原开工号):
        return 2, "入参：顶层 `开工ID` 要是**原腿**的开工号（`v1-` 加六位数字）；收到 %r" % 原开工号
    退出码, 集成路径 = 核现场(仓根, 原开工号)
    if 退出码 != 0:
        return 退出码, 集成路径
    集成路径 = Path(集成路径)
    连接 = 账本.连账本()
    try:
        if not 账本.读开工(连接, 原开工号):
            return 1, "账本里没有这条开工：%s" % 原开工号
        已有号 = 找接管开工(连接, 集成路径)
        if 已有号:
            return 1, ("集成现场已被 **%s** 正式接管 ⇒ 不重复绑定（幂等拒，一个字节没写）。\n"
                     "改冲突件：`v1_edit` 带 `开工ID`=%s；收口：`合并主干.py %s --恢复现场`。"
                     % (已有号, 已有号, 原开工号))
        退出码, 件表 = 未合并件(集成路径)
        if 退出码 != 0:
            return 1, 件表
        if not 件表:
            return 2, ("现场没有待解的文本冲突件（源库冲突由编排的正式重放处置）⇒ 无需接管：%s"
                     % 集成路径)
        指纹表, 读不出表 = 读盘指纹(集成路径, 件表)
        if 读不出表:
            return 1, ("这些冲突件读不上盘（盘上不存在 / 路径非法）⇒ 拒接管（不塞进认领表）：\n  %s"
                     % " · ".join(读不出表))
        新开工号 = 账本.新开工号(连接)
        工作内容 = "接管集成现场 %s 解冲突（认领 %d 件）" % (原开工号, len(指纹表))
        账本.登记开工(连接, 新开工号, 工作内容, "集成/" + 原开工号, str(集成路径))
        账本.认领文件(连接, 新开工号, 指纹表)
        # 归属显式落库：执行开工号（集成树）↔ 目标开工号（被接管的原腿）分列可查 ——
        # 不再靠「工作树 == 集成路径」反查（那是唯一一份的隐式反查，别处想查只能抄一遍）。
        账本.记归属(连接, 新开工号, 原开工号, 账本.种类_接管)
        return 0, "\n".join([
            "接管成功：集成现场 %s" % 集成路径,
            "接管开工号 %s（分支 集成/%s · 状态 进行中）" % (新开工号, 原开工号),
            "认领 %d 件：%s" % (len(指纹表), " · ".join(sorted(指纹表))),
            "下一步：`v1_edit` 带 `开工ID`=%s 解冲突（过四道闸、逐条记账）；"
            "解完跑 `合并主干.py %s --恢复现场` 收口。" % (新开工号, 原开工号),
        ])
    finally:
        连接.close()


def 暂存接管成果(仓根, 集成路径) -> tuple:
    """集成现场被正式接管 ⇒ 核它的改动覆盖全部文本冲突件并 `git add` 暂存 ⇒ (退出码, 行表)。

    未被接管 ⇒ **拒**（不许把没走 `v1_edit` 的未合并件当已解决）；缺覆盖 ⇒ 拒（不暂存半截）。
    """
    集成路径 = Path(str(集成路径)).resolve()
    退出码, 件表 = 未合并件(集成路径)
    if 退出码 != 0:
        return 1, [件表]
    if not 件表:
        return 0, ["   暂存：现场无未合并文本冲突件（源库冲突由正式重放处置）"]
    连接 = 账本.连账本()
    try:
        接管号 = 找接管开工(连接, 集成路径)
        if not 接管号:
            return 1, ["   ★ 现场**未被正式接管** ⇒ 拒把未合并冲突件当已解决：%s" % 集成路径,
                    "   入口：`v1_task 操作=接管集成 开工ID=<原腿>` 正式接管，再用 `v1_edit` 解冲突。"]
        改动路径集 = {一条改动["路径"] for 一条改动 in 账本.读改动(连接, 接管号)}
        未覆盖表 = [路径 for 路径 in 件表 if 路径 not in 改动路径集]
        if 未覆盖表:
            return 1, ["   ★ 接管开工 %s 的改动未覆盖这些冲突件 ⇒ 拒暂存（不许把没走 v1_edit 的当已解决）：" % 接管号,
                    "     " + " · ".join(未覆盖表)]
        # 接管开工用 `v1_edit` 改过的件**不止冲突件**（也可改非冲突件）⇒ 一并暂存；
        # 只暂存冲突件时 ④ 会因「集成树有未提交改动」拒（2026-10-08 收口方实测 547 的 开工.py）。
        非冲突表 = sorted(路径 for 路径 in 改动路径集 if 路径 not in 件表)
        待暂存表 = list(件表) + 非冲突表
        for 路径 in 待暂存表:
            退出码, 输出文本, 日志路径 = _跑(["git", "add", "--", 路径], 集成路径)
            if 退出码 != 0:
                return 1, ["   `git add %s` 失败（退出码 %d）· 日志 %s\n%s" % (路径, 退出码, 日志路径, 输出文本[:400])]
        return 0, ["   暂存：已按接管开工 %s 的改动 `git add` %d 件（冲突件 %d + 非冲突件 %d）：%s"
                % (接管号, len(待暂存表), len(件表), len(非冲突表), " · ".join(待暂存表))]
    finally:
        连接.close()


def 核验重放(集成路径, 动作表) -> tuple:
    """源库重放后**核验**：集成树库必须逐条含腿侧动作 ⇒ (退出码, 行表)。缺 ⇒ **显式拒**（不静默跳过）。"""
    if not 动作表:
        return 0, ["   重放核验：无腿侧动作待核"]
    库件 = Path(str(集成路径)) / 库相对路径
    缺失表 = []
    for 动作 in 动作表:
        列名表, 行表 = 读源表(str(库件), 动作["表"])
        if not 列名表:
            缺失表.append("%s（表读不出）" % 动作["表"])
            continue
        行元组 = 行表.get(动作["键"])
        if 行元组 is None or 取语义值(行元组, 列名表) != 取语义值(动作["腿值"], 动作["列名表"]):
            缺失表.append("%s 主键 %r" % (动作["表"], 动作["键"]))
    if 缺失表:
        return 1, ["   ★ 源库重放**核验不过**：集成树库缺 %d 条腿侧动作 ⇒ **显式拒**（不静默跳过丢动作）："
                 % len(缺失表)] + ["     " + 缺失项 for 缺失项 in 缺失表[:20]]
    return 0, ["   重放核验：%d 条腿侧动作逐条落库（读库比对）" % len(动作表)]


def 解除接管(集成路径) -> tuple:
    """集成现场已收口 ⇒ 把绑定它的接管开工翻「已释放」（清僵尸）⇒ (退出码, 说明)。"""
    连接 = 账本.连账本()
    try:
        接管号 = 找接管开工(连接, str(集成路径))
        if not 接管号:
            return 0, "（现场未被正式接管，无需解除）"
        账本.置状态(连接, 接管号, 账本.状态_已释放)
        return 0, "接管开工 %s 随现场收口翻「已释放」" % 接管号
    finally:
        连接.close()
