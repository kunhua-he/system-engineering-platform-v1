# -*- coding: utf-8 -*-
"""预检凭据 —— `v1_edit 只检查` 与 `改` 之间的**短引用**（住进程内存，不落盘不落库）。

**为何要有它**（2026-10-08 · 540 腿实测）：`只检查` 通过后 `改` 要带**同一份** `改动表` ⇒ 大表
重传一遍（纯机械往返）。本件把「只检查查过的那份表」按**内容指纹**存进进程内存，回执里给出
短引用（那个指纹）；`改` 带 `沿用上次` = 短引用即可，不必重传。

**为何不落账本 / 不落库**：`只检查` 的契约是**零写**（`预检样本` 逐帧哈希整棵树，含账本库文件）
⇒ 凭据只能住内存。代价：MCP 进程重启 ⇒ 凭据没了 ⇒ `改` 报「短引用失效」**明确拒**
（**不静默重查、不静默用旧表**）—— 那正是要的：失效就重发一次 `只检查`。

**凭据绑死在内容上**：键 = 改动表规范化 JSON 的 sha256 前 16 位 ⇒ 调用方若**同时**给了
`沿用上次` 与一份对不上的 `改动表`，本件**明确拒**（不拿旧表顶替、不拿新表盖掉短引用）。
"""

import hashlib
import json

容量上限 = 32          # 只留最近这么多条 —— 长驻进程不许无限长
凭据表: dict = {}       # {(开工号, 指纹): 改动表}


def 改动表指纹(改动表: list) -> str:
    """`改动表` ⇒ 短引用指纹（规范化 JSON 的 sha256 前 16 位，与 `代码地图.文件指纹` 同形）。

    `sort_keys` + 紧凑分隔 ⇒ 同内容的字段顺序 / 空白差异不会算出两个指纹。
    """
    规范文本 = json.dumps(改动表, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(规范文本.encode("utf-8")).hexdigest()[:16]


def 记凭据(开工号: str, 改动表: list) -> str:
    """落一份凭据（同键覆盖）⇒ 短引用；超容就丢最旧的那条。"""
    指纹 = 改动表指纹(改动表)
    凭据表[(开工号, 指纹)] = 改动表
    while len(凭据表) > 容量上限:
        凭据表.pop(next(iter(凭据表)))
    return 指纹


def 取凭据(开工号: str, 短引用: str) -> list:
    """按短引用取那份改动表 ⇒ 列表；没有 ⇒ `[]`（调用方据此**明确拒**，不当空表用）。"""
    return 凭据表.get((开工号, 短引用)) or []
