# -*- coding: utf-8 -*-
"""反馈查询 —— **分页短回执** + 未蒸馏状态读数（主策划批处理与收口清理的入口）。

**默认短回执**：现象按 `账本.截断宽度` 截断，**不回整篇正文**；要全文传 `展开` = 真。
**未蒸馏读数**：给了开工号（顶层或参数）就在回执里附 `未蒸馏条数` · **分页**（`未蒸馏页码` /
`未蒸馏每页` / `未蒸馏本页条数` / `未蒸馏下页` / `未蒸馏截断`）· **分类计数**（`未蒸馏分类计数`：
未审完来源 / 未判词条目 / 债务无有效承接 / 待核须保留）—— 实现体是 `反馈关联.未蒸馏明细`，
**唯一判据口**，本件不另写第二套；`未蒸馏` 仍是**本页**的字符串行表（旧形状保留）。
"""

from . import 反馈账本 as 账本
from . import 反馈关联
from .反馈提交 import 取文本

# `状态` 筛选档（封闭）：判词面两档 + 债务关闭面两档。
状态档表 = ("未判词", "已判词", "未关闭", "已关闭")
默认每页 = 20
每页上限 = 200
# `展开` 时每条条目回多少补证：**有界**（默认 5 · 上限 50）；`补证起始` 可继续读取（补证只增不改）。
补证默认条数 = 5
补证条数上限 = 50


def 规范化分页(参数表: dict) -> tuple:
    """`(页码, 每页, 错误表)`。"""
    页码 = 参数表.get("页码", 1)
    每页 = 参数表.get("每页", 默认每页)
    错误表 = []
    if type(页码) is not int or 页码 < 1:
        错误表.append("`页码` 要是 ≥1 的整数")
    if type(每页) is not int or not 1 <= 每页 <= 每页上限:
        错误表.append("`每页` 要是 1..%d 的整数" % 每页上限)
    return 页码, 每页, 错误表


def 规范化未蒸馏分页(参数表: dict, 条目每页: int) -> tuple:
    """未蒸馏读数的 `(页码, 每页, 错误表)` —— 默认跟条目那页走（旧行为 = 首页 20 条不变）。"""
    页码 = 参数表.get("未蒸馏页码", 1)
    每页 = 参数表.get("未蒸馏每页", 条目每页)
    错误表 = []
    if type(页码) is not int or 页码 < 1:
        错误表.append("`未蒸馏页码` 要是 ≥1 的整数")
    if type(每页) is not int or not 1 <= 每页 <= 每页上限:
        错误表.append("`未蒸馏每页` 要是 1..%d 的整数" % 每页上限)
    return 页码, 每页, 错误表


def 规范补证分页(参数表: dict) -> tuple:
    """`(补证起始, 补证条数, 错误表)` —— `展开` 时每条条目取多少补证（**有界**，只判不写）。"""
    补证起始 = 参数表.get("补证起始", 1)
    补证条数 = 参数表.get("补证条数", 补证默认条数)
    错误表 = []
    if type(补证起始) is not int or 补证起始 < 1:
        错误表.append("`补证起始` 要是 ≥1 的整数")
    if type(补证条数) is not int or not 1 <= 补证条数 <= 补证条数上限:
        错误表.append("`补证条数` 要是 1..%d 的整数" % 补证条数上限)
    return 补证起始, 补证条数, 错误表


# `来源号` 筛选命中的来源元数据列（**实际列**，与 `反馈来源` 表同集合 —— 不虚构派生字段）。
来源列名表 = ("来源号", "开工号", "来源标识", "内容指纹", "报告路径", "读取状态",
          "提取条数", "判词条数", "待核理由", "审完时刻", "审完说明", "登记时刻")


def 来源读数(来源行) -> dict:
    """`反馈来源` 行 ⇒ 元数据字典（缺失 ⇒ `None`，由调用方标 `来源缺失`）。"""
    if not 来源行:
        return None
    return {列名: 来源行.get(列名) for 列名 in 来源列名表}


def 条目补证(连接, 条目号: int, 补证起始: int, 补证条数: int) -> dict:
    """条目**补证读数**：有界取一页 + 总数 + 截断标记（**不回无限数组**）。

    补证（`反馈证据`）只增不改 ⇒ 可能很多：这里只回 `补证条数` 条，另给 `补证总数` 与
    `补证截断`；截断时给 `补证下页起始`（拿它再查一次即可继续读，无需新参数）。
    """
    总数 = 账本.计证据(连接, 条目号)
    行表 = 账本.列证据(连接, 条目号, 补证起始, 补证条数)
    补证表 = [{"编号": 数据行["编号"], "证据": 数据行["证据"], "来源": 数据行["来源"],
            "补证开工号": 数据行["补证开工号"], "补证时刻": 数据行["补证时刻"]}
           for 数据行 in 行表]
    下页 = 补证起始 + len(补证表)
    截断 = 下页 - 1 < 总数
    return {"补证": 补证表, "补证总数": 总数, "补证起始": 补证起始,
            "补证截断": 截断, "补证下页起始": 下页 if 截断 else None}


def 条目读数(连接, 条目行: dict, 展开: bool, 补证起始: int = 1,
        补证条数: int = 补证默认条数) -> dict:
    """一条条目 ⇒ 回执字典（默认短：现象截断；`展开` 才带全字段 + **有界补证**）。"""
    有效判词 = 账本.有效判词(连接, 条目行["条目号"]) or {}
    读数 = {"条目号": 条目行["条目号"], "开工号": 条目行["开工号"], "来源号": 条目行["来源号"],
          "现象": 条目行["现象"] if 展开 else 账本.截断(条目行["现象"]),
          "计次": 账本.计次(连接, 条目行["条目号"]),
          "并入主条目": 条目行["并入主条目"],
          "判词": 有效判词.get("判词"), "关联种类": 有效判词.get("关联种类"),
          "关联目标": 有效判词.get("关联目标"), "关联状态": 有效判词.get("关联状态"),
          "已关闭": bool(账本.读关闭(连接, 条目行["条目号"]))}
    if 展开:
        读数.update({"落点": 条目行["落点"], "触发": 条目行["触发"], "预期": 条目行["预期"],
                  "实际": 条目行["实际"], "证据": 条目行["证据"], "未测": 条目行["未测"],
                  "耗时毫秒": 条目行["耗时毫秒"], "调用次数": 条目行["调用次数"],
                  "判词理由": 有效判词.get("理由"), "登记时刻": 条目行["登记时刻"]})
        读数.update(条目补证(连接, 条目行["条目号"], 补证起始, 补证条数))
    return 读数


def 拼筛选(参数表: dict, 开工号: str) -> tuple:
    """⇒ `(条件表, 值表, 错误表, 生效开工号)`（只判不写）。"""
    错误表 = []
    开工筛选 = 取文本(参数表.get("开工号")) or 开工号
    if 开工筛选 and not 账本.是开工号(开工筛选):
        错误表.append("`开工号` 形状不对（`v1-` 加六位数字）")
    条目号 = 参数表.get("条目号")
    来源号 = 参数表.get("来源号")
    if 条目号 is not None and type(条目号) is not int:
        错误表.append("`条目号` 要是整数")
    if 来源号 is not None and type(来源号) is not int:
        错误表.append("`来源号` 要是整数")
    判词筛选 = 取文本(参数表.get("判词")) or None
    if 判词筛选 and 判词筛选 not in 账本.判词档表:
        错误表.append("`判词` 只认 %s" % " · ".join(账本.判词档表))
    状态筛选 = 取文本(参数表.get("状态")) or None
    if 状态筛选 and 状态筛选 not in 状态档表:
        错误表.append("`状态` 只认 %s" % " · ".join(状态档表))
    条件表 = []
    值表 = []
    if 开工筛选:
        条件表.append("开工号 = ?")
        值表.append(开工筛选)
    if 条目号 is not None:
        条件表.append("条目号 = ?")
        值表.append(条目号)
    if 来源号 is not None:
        条件表.append("来源号 = ?")
        值表.append(来源号)
    判词存在 = ("exists(select 1 from 反馈判词 p where "
            "(p.条目号 = 反馈条目.条目号 or p.条目号 = 反馈条目.并入主条目) and p.判词 = ?)")
    if 判词筛选:
        条件表.append(判词存在)
        值表.append(判词筛选)
    if 状态筛选 == "未判词":
        条件表.append("not exists(select 1 from 反馈判词 p where "
                 "p.条目号 = 反馈条目.条目号 or p.条目号 = 反馈条目.并入主条目)")
    elif 状态筛选 == "已判词":
        条件表.append("exists(select 1 from 反馈判词 p where "
                 "p.条目号 = 反馈条目.条目号 or p.条目号 = 反馈条目.并入主条目)")
    elif 状态筛选 == "未关闭":
        条件表.append(判词存在
                 + " and not exists(select 1 from 反馈关闭 c where c.条目号 = 反馈条目.条目号)")
        值表.append(账本.判词_债务)
    elif 状态筛选 == "已关闭":
        条件表.append("exists(select 1 from 反馈关闭 c where c.条目号 = 反馈条目.条目号)")
    return 条件表, 值表, 错误表, 开工筛选


def 查反馈(仓根, 开工号: str, 参数表: dict) -> tuple:
    """分页查反馈 ⇒ `(退出码, 短回执 JSON)`。**默认不回整篇正文**；给 `来源号` 附来源元数据。"""
    页码, 每页, 错误表 = 规范化分页(参数表)
    补证起始, 补证条数, 补证错 = 规范补证分页(参数表)
    错误表 += 补证错
    展开 = 参数表.get("展开", False)
    if not isinstance(展开, bool):
        错误表.append("`展开` 要是逻辑型")
    条件表, 值表, 筛选错, 开工筛选 = 拼筛选(参数表, 开工号)
    错误表 += 筛选错
    未蒸馏页码, 未蒸馏每页, 未蒸馏分页错 = 规范化未蒸馏分页(参数表, 每页)
    错误表 += 未蒸馏分页错
    if 错误表:
        return 2, "**零读**（查反馈参数未过）：\n  " + "\n  ".join(错误表)
    连接 = 账本.连反馈库()
    try:
        条件文本 = (" where " + " and ".join(条件表)) if 条件表 else ""
        总数 = 连接.execute("select count(*) from 反馈条目" + 条件文本, 值表).fetchone()[0]
        行表 = 连接.execute("select * from 反馈条目" + 条件文本 + " order by 条目号 limit ? offset ?",
                        值表 + [每页, (页码 - 1) * 每页]).fetchall()
        条目列表 = [条目读数(连接, dict(数据行), 展开, 补证起始, 补证条数)
                for 数据行 in 行表]
        读数 = {"总数": 总数, "页码": 页码, "每页": 每页, "本页条数": len(条目列表),
              "下页": 页码 + 1 if 页码 * 每页 < 总数 else None, "条目": 条目列表}
        if 参数表.get("来源号") is not None:
            来源行 = 账本.读来源(连接, 参数表["来源号"])
            读数["来源"] = 来源读数(来源行)
            if 来源行 is None:
                读数["来源缺失"] = True
        if 开工筛选:
            未蒸馏明细表 = 反馈关联.未蒸馏明细(连接, 仓根, 开工筛选)
            未蒸馏条数 = len(未蒸馏明细表)
            起行 = (未蒸馏页码 - 1) * 未蒸馏每页
            本页明细 = 未蒸馏明细表[起行:起行 + 未蒸馏每页]
            读数["未蒸馏条数"] = 未蒸馏条数
            读数["未蒸馏"] = [明细行["正文"] for 明细行 in 本页明细]
            读数["未蒸馏页码"] = 未蒸馏页码
            读数["未蒸馏每页"] = 未蒸馏每页
            读数["未蒸馏本页条数"] = len(本页明细)
            读数["未蒸馏下页"] = (未蒸馏页码 + 1
                            if 未蒸馏页码 * 未蒸馏每页 < 未蒸馏条数 else None)
            读数["未蒸馏截断"] = 未蒸馏条数 > len(本页明细)
            读数["未蒸馏分类计数"] = 反馈关联.未蒸馏分类计数(未蒸馏明细表)
            自动行 = 反馈关联.自动记录行(连接, 仓根, 开工筛选)
            读数["自动记录条数"] = len(自动行)
            读数["自动记录行"] = 自动行[:未蒸馏每页]
        return 0, 账本.拼回执(读数)
    finally:
        连接.close()
