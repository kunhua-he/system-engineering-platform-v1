# -*- coding: utf-8 -*-
r"""反馈销账 —— 把「验证关闭」这个销账口带进**每条腿的常规流程**（债务 518）。

**为什么存在**（2026-10-13 实测）：反馈库 4735 条目里判为「债务」的 **2345 条从未关闭**
（`反馈关闭` 全表只有 6 行）；登记口（`提交反馈`）已进每条腿的固定动作，而销账口
（`v1_task` 操作 `验证关闭`）**不在任何常规流程**里 ⇒ 债务只进不出。
本件把销账口**点名进释放回执**（口径同债务 536 的修法：回执点名 + 给完整可粘贴命令）：
每条腿释放成功时，列出「本开工名下的未关闭债务」与「本腿改动落点关联的未关闭债务」，
并把可粘贴的关闭载荷骨架一起交出来 —— 收口方每次读释放回执就会看到它。

**只读**：本件一个字节都不写库（销账的唯一写口是 `v1_task` 操作 `验证关闭`）。
"""
from __future__ import annotations

from . import 反馈账本 as 账本


def 未关闭债务表(连接, 开工号: str) -> list:
    """本开工名下**判词=债务且无关闭行**的条目 ⇒ `[{条目号, 落点, 现象}]`（按条目号升序）。"""
    未关闭查询 = (
        "select 反馈条目.条目号, 反馈条目.落点, 反馈条目.现象 from 反馈条目 "
        "join 反馈判词 on 反馈判词.条目号 = 反馈条目.条目号 "
        "where 反馈条目.开工号 = ? and 反馈判词.判词 = ? "
        "and not exists(select 1 from 反馈关闭 where 反馈关闭.条目号 = 反馈条目.条目号) "
        "order by 反馈条目.条目号")
    return [dict(数据行) for 数据行 in 连接.execute(未关闭查询, (开工号, 账本.判词_债务))]


def 改动路径表(连接, 开工号: str) -> set:
    """本开工 `改动` 表里的路径集 —— 落点关联的**匹配面**（空 ⇒ 无关联，不是错误）。"""
    return {数据行[0] for 数据行 in
            连接.execute("select distinct 路径 from 改动 where 开工号 = ?", (开工号,))}


def 落点关联表(未关闭表: list, 路径表: set) -> list:
    """未关闭债务里 `落点` **文本含本腿任一改动路径**的 ⇒ 子集。

    ★ **启发式**（如实标注）：`反馈条目.落点` 是**自由文本**（实测有「开工账本.db 反馈来源(106/107)」
      这类写法），不是路径字段 ⇒ 这条只做「点名」，不当判决；判词与关闭仍由人给证据。
    """
    return [债务条目 for 债务条目 in 未关闭表
            if any(路径 and 路径 in (债务条目.get("落点") or "") for 路径 in 路径表)]


def 销账行(开工号: str) -> list:
    """本腿释放回执要追加的**销账点名行** ⇒ 行表。库读不动 ⇒ 如实报一行，**不吞**。"""
    try:
        连接 = 账本.连反馈库()
    except Exception as 错误:
        return ["★ 反馈销账：读不动反馈库（%r）⇒ 本开工名下的未关闭债务数**未知**" % 错误]
    try:
        未关闭表 = 未关闭债务表(连接, 开工号)
        关联表 = 落点关联表(未关闭表, 改动路径表(连接, 开工号))
    finally:
        连接.close()
    行表 = ["★ 反馈销账（债务 518）：本开工名下未关闭债务 %d 条 · 本腿改动落点关联 %d 条"
          % (len(未关闭表), len(关联表))]
    if not 关联表:
        行表.append("  （本腿改动落点没有关联的未关闭债务 —— 有 ⇒ 按下面骨架逐条关闭）")
        return 行表
    关闭骨架 = " · ".join(
        '{"条目号": %d, "验证证据": "…", "验证命令": "…", "退出码": 0, "承接提交": "…"}'
        % 债务条目["条目号"] for 债务条目 in 关联表[:5])
    行表.append("  落点关联条目号：%s"
              % " · ".join(str(债务条目["条目号"]) for 债务条目 in 关联表[:10]))
    行表.append("  关闭（**先备真验证证据**再逐条填）：`v1_task` 操作 `验证关闭` · 参数 "
              "`关闭表` = [%s]" % 关闭骨架)
    if len(关联表) > 5:
        行表.append("  （骨架只列前 5 条，共 %d 条）" % len(关联表))
    return 行表
