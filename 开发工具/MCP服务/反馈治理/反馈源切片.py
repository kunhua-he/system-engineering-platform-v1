# -*- coding: utf-8 -*-
"""反馈源切片 —— 历史报告来源按**报告指纹升序取模**切成 N 份清单（逐份蒸馏的前置）。

**为什么**：历史报告几百份，一个人 / 一条腿啃不完 ⇒ 按指纹升序取模切片：同一份报告永远落在
同一片（指纹不变 ⇒ 切片不变）⇒ 可重跑、可对账、可分工。

**不靠枚举冒充完成**：每片清单逐份带 `内容指纹` 与 `审完时刻`，拿清单回读即可核「哪几份还没审完」。

**已裁定的口径**（未完成台账的『618 清点/回填死代码 + 蒸馏前置缺口』条）：共用一个专用蒸馏开工号、
按报告指纹升序取模切片、重复组成员各提交同一份条目以保来源与计次、幂等键用 `蒸馏-` 前缀。

**零写**：只读 `反馈来源` 表 + 落清单文件；不改任何来源行、不动任何原件。
"""

import json
import secrets
from pathlib import Path

from 运行数据根 import 子目录路径, 解析当前环境

from . import 反馈账本

切片默认 = 8
切片前缀 = "反馈切片-"

# 清单列（定位 + 追踪两用）：拿一份清单回读就能核「这份报告审完了没」
取列 = ("来源号", "开工号", "来源标识", "内容指纹", "报告路径", "读取状态",
      "提取条数", "判词条数", "审完时刻")


def 取来源行表(连接, 来源号表=None) -> list:
    """读 `反馈来源` ⇒ 行表（按 `来源号表` 收窄；不给 = 全表，含全部历史报告）。"""
    if 来源号表:
        占位符 = ",".join("?" * len(来源号表))
        return 连接.execute(
            "select %s from 反馈来源 where 来源号 in (%s)" % (",".join(取列), 占位符),
            list(来源号表)).fetchall()
    return 连接.execute("select %s from 反馈来源" % ",".join(取列)).fetchall()


def 分片(行表: list, 切片数: int) -> list:
    """按 `内容指纹` 升序取模分片 ⇒ 切片表（每片 = 行表）；指纹为空的行归第 0 片（不丢）。"""
    有序 = sorted(行表, key=lambda 来源行: (来源行[3] or "", 来源行[0]))
    切片表 = [[] for _ in range(切片数)]
    for 序号, 来源行 in enumerate(有序):
        切片表[序号 % 切片数].append(来源行)
    return 切片表


def 是审完(来源行) -> bool:
    """审完 = `审完时刻` 非空（唯一判据口；`读取状态` 会撒谎，不能拿它推断）。"""
    return bool(来源行[8])


def 切片清单(仓根, 切片数: int = 切片默认, 来源号表=None, 切片根=None) -> dict:
    """切 + 落盘 ⇒ 读数（批号 / 目录 / 每片条数 / 每片指纹 / 未审完计数）。"""
    if int(切片数) < 1:
        raise ValueError("切片数 必须 ≥ 1（收到 %r）—— 给 0 或负数会把全部来源吞成 0 片。" % (切片数,))
    连接 = 反馈账本.连反馈库()
    try:
        行表 = 取来源行表(连接, 来源号表)
    finally:
        连接.close()
    if 切片根 is None:
        切片根 = 子目录路径(解析当前环境(), "临时件")
    批号 = 切片前缀 + secrets.token_hex(4)
    切片目录 = Path(切片根) / 批号
    切片目录.mkdir(parents=True, exist_ok=True)
    片读数 = []
    for 序号, 切片组 in enumerate(分片(行表, 切片数), start=1):
        片文件 = 切片目录 / ("切片-%02d.json" % 序号)
        片文件.write_text(json.dumps([dict(zip(取列, 来源行)) for 来源行 in 切片组],
                                 ensure_ascii=False, indent=1), encoding="utf-8")
        片读数.append({"切片": 序号, "件": str(片文件), "条数": len(切片组),
                    "未审完": sum(1 for 来源行 in 切片组 if not 是审完(来源行)),
                    "指纹": [来源行[3] for 来源行 in 切片组]})
    return {"批号": 批号, "目录": str(切片目录), "切片数": len(片读数), "来源总数": len(行表),
            "未审完总数": sum(1 for 来源行 in 行表 if not 是审完(来源行)), "每片": 片读数}
