# -*- coding: utf-8 -*-
"""反馈来源查询 —— 按 `读取状态` / `审完状态` 枚举本开工**来源**（只读 · 分页 · 带分布计数）。

**为什么单开一件**（判据 ⑲ 单件 ≤400 行）：`反馈查询.py` 管**条目**分页与未蒸馏读数；来源面的
枚举是另一条关注点，另有一套档表（读取四档 · 审完三档）—— 混进 `反馈查询.py` 会把两套
分页与两套筛选缠在一件里，改一处要读整件。

**审完状态三档**（由库内两列**现算**，不新增存储）：
  · `未审完` = `审完时刻 is null`（**含**显式待核那一档）；
  · `已审完` = `审完时刻 is not null`；
  · `显式待核` = `审完时刻 is null` 且 `待核理由 is not null`（是 `未审完` 的**子集**，可单独筛）。

**分布计数**（`读取状态计数` / `审完状态计数`）口径 = **本开工全部来源**，**不受筛选影响**，
且与筛选**同一份谓词** ⇒ 计数就是该档筛选的预期总数。`未审完` 计数**含** `显式待核`（子集）⇒
`未审完 + 已审完 == 总数`；调用方先看分布、再按档筛：一次把未蒸馏全景看全
（旧口 `查反馈` 的 `未蒸馏` 只回前 20 条，正是本口要补的缺口）。

**只读**：本件只 `select`，零写、零删、零改台账。
"""

from . import 反馈账本 as 账本
from .反馈查询 import 规范化分页
from .反馈提交 import 取文本

审完_未审完 = "未审完"
审完_已审完 = "已审完"
审完_显式待核 = "显式待核"
审完状态档表 = (审完_未审完, 审完_已审完, 审完_显式待核)
# 审完三档的**筛选谓词**（唯一一份）：筛选与分布计数都引它 ⇒ 计数即该档筛选的预期总数。
审完谓词表 = {
    审完_未审完: "审完时刻 is null",
    审完_已审完: "审完时刻 is not null",
    审完_显式待核: "审完时刻 is null and 待核理由 is not null",
}


def 拼来源条件(参数表: dict, 开工号: str) -> tuple:
    """⇒ `(条件表, 值表, 错误表, 开工筛选)`（**只判不写**）。"""
    错误表 = []
    开工筛选 = 取文本(参数表.get("开工号")) or 开工号
    if not 开工筛选:
        错误表.append("要 `开工号`（参数里给，或顶层给 `开工ID`）")
    elif not 账本.是开工号(开工筛选):
        错误表.append("`开工号` 形状不对（`v1-` 加六位数字）")
    读取筛选 = 取文本(参数表.get("读取状态")) or None
    if 读取筛选 and 读取筛选 not in 账本.读取状态档表:
        错误表.append("`读取状态` 只认 %s" % " · ".join(账本.读取状态档表))
    审完筛选 = 取文本(参数表.get("审完状态")) or None
    if 审完筛选 and 审完筛选 not in 审完状态档表:
        错误表.append("`审完状态` 只认 %s" % " · ".join(审完状态档表))
    条件表 = []
    值表 = []
    if 开工筛选 and 账本.是开工号(开工筛选):
        条件表.append("开工号 = ?")
        值表.append(开工筛选)
    if 读取筛选:
        条件表.append("读取状态 = ?")
        值表.append(读取筛选)
    if 审完筛选 in 审完谓词表:
        条件表.append(审完谓词表[审完筛选])
    return 条件表, 值表, 错误表, 开工筛选


def 审完状态(来源行: dict) -> str:
    """一条来源行 ⇒ `审完状态` 档名（**由库内两列现算**，不新增存储列）。"""
    if 来源行.get("审完时刻"):
        return 审完_已审完
    if 取文本(来源行.get("待核理由")):
        return 审完_显式待核
    return 审完_未审完


def 来源读数(来源行: dict) -> dict:
    """一条来源 ⇒ 回执字典（**短**：`待核理由` 截断，不回正文）。"""
    return {"来源号": 来源行["来源号"], "来源标识": 来源行["来源标识"],
            "读取状态": 来源行["读取状态"], "审完状态": 审完状态(来源行),
            "提取条数": 来源行["提取条数"], "判词条数": 来源行["判词条数"],
            "待核理由": 账本.截断(来源行["待核理由"]) if 来源行.get("待核理由") else None,
            "审完时刻": 来源行["审完时刻"], "登记时刻": 来源行["登记时刻"]}


def 分布计数(连接, 开工号: str) -> tuple:
    """本开工**全部来源**的读取 / 审完分布（**不受筛选影响**）⇒ `(读取计数, 审完计数)`。

    **口径与筛选同一份谓词**（`审完谓词表` / `读取状态档表`）⇒ 计数就是该档筛选的预期总数。
    `未审完` 计数**含** `显式待核`（后者是前者的子集）⇒ `未审完 + 已审完 == 总数`；
    `显式待核` 是**额外**的一栏（不参与该等式）。
    """
    读取计数 = {档名: 连接.execute(
        "select count(*) from 反馈来源 where 开工号 = ? and 读取状态 = ?",
        (开工号, 档名)).fetchone()[0] for 档名 in 账本.读取状态档表}
    审完计数 = {档名: 连接.execute(
        "select count(*) from 反馈来源 where 开工号 = ? and " + 谓词,
        (开工号,)).fetchone()[0] for 档名, 谓词 in 审完谓词表.items()}
    return 读取计数, 审完计数


def 列反馈来源(仓根, 开工号: str, 参数表: dict) -> tuple:
    """按 `读取状态` / `审完状态` 枚举本开工来源 ⇒ `(退出码, 短回执 JSON)`。**只读**。"""
    页码, 每页, 错误表 = 规范化分页(参数表)
    条件表, 值表, 筛选错, 开工筛选 = 拼来源条件(参数表, 开工号)
    错误表 += 筛选错
    if 错误表:
        return 2, "**零读**（列反馈来源参数未过）：\n  " + "\n  ".join(错误表)
    连接 = 账本.连反馈库()
    try:
        条件文本 = (" where " + " and ".join(条件表)) if 条件表 else ""
        总数 = 连接.execute("select count(*) from 反馈来源" + 条件文本, 值表).fetchone()[0]
        行表 = 连接.execute(
            "select * from 反馈来源" + 条件文本 + " order by 来源号 limit ? offset ?",
            值表 + [每页, (页码 - 1) * 每页]).fetchall()
        来源列表 = [来源读数(dict(数据行)) for 数据行 in 行表]
        读取计数, 审完计数 = 分布计数(连接, 开工筛选)
        return 0, 账本.拼回执(
            {"开工号": 开工筛选, "总数": 总数, "页码": 页码, "每页": 每页,
             "本页条数": len(来源列表),
             "下页": 页码 + 1 if 页码 * 每页 < 总数 else None,
             "读取状态计数": 读取计数, "审完状态计数": 审完计数, "来源": 来源列表})
    finally:
        连接.close()
