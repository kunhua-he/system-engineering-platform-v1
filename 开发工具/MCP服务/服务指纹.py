def 指纹件表() -> list:
    """指纹面（服务源码 ＋ 运行期依赖）⇒ 文件路径表。**同一份推导**给 `算服务指纹` 与缓存键。"""
    件表 = sorted(服务根.glob("*.py"))
    if 入口件.is_file():
        件表.append(入口件)
    件表.append(工具根 / "MCP服务_http.py")
    for 目录路径 in 依赖:
        if 目录路径.is_dir():
            件表 += sorted(目录路径.glob("*.py"))
        else:
            件表.append(目录路径)
    return 件表


def 指纹键快照(件表: list) -> tuple:
    """指纹比对键 = 逐件的 `(路径, 字节数, 修改时刻纳秒)`。

    **为什么这个键能顶替「重算一遍内容哈希」**：本函数唯一用途是判「**盘上源码变没变**」——
    改一个字节必然同时改「字节数」或「修改时刻」之一（写盘一定刷新 mtime）。而**路径**在键里
    ⇒ 增删件也算变。键一命中就直接回上次的合并摘要，不再重读那 186 件、1.87 MB。
    ★ 键**不含内容**，所以它只用来**命中缓存**，取到的摘要仍是当初按内容算出来的那一个
    （摘要本身从内容来 —— 不是拿 stat 冒充内容指纹）。
    """
    return tuple(
        (str(路径), 路径.stat().st_size, 路径.stat().st_mtime_ns) if 路径.is_file() else (str(路径), -1, -1)
        for 路径 in 件表
    )


def 算服务指纹() -> str:
    """服务源码的合并指纹 ⇒ 16 位十六进制（按件名排序后逐件摘要 —— 顺序无关）。

    ★ **按 stat 键缓存**（2026-10-08 实测）：本函数在**每次派发**都要调（`参数规范.信封` 里
      `算服务指纹()`，`协议.派发` 又调 `过期提示一次`）—— 真仓实测**每次 67.9 ms**（186 件 ·
      1.87 MB 逐个 `read_bytes` + sha256），`--自检` 一条命令里调 **84 次 ⇒ 1.72 s**
      （占 `--自检` 老墙钟的四成以上）。而它要回答的只是「盘上源码变没变」⇒ 键取
      `指纹键快照`（逐件 stat，实测 0.54 ms）：键没变 ⇒ 直接回上次摘要，**不重读一个字节**。
      语义逐字不变：内容变了 ⇒ 键必然变（字节数 / mtime / 件集 任一）。反向样本：
      `易用样本.py` 仍按老口径把 `算服务指纹` 换掉来证「过期提示」的两态，本缓存不影响它。
    """
    global 指纹缓存键, 指纹缓存值
    件表 = 指纹件表()
    键名 = 指纹键快照(件表)
    if 键名 == 指纹缓存键 and 指纹缓存值 is not None:
        return 指纹缓存值
    摘要值 = hashlib.sha256()
    for 源码件 in 件表:
        try:
            内容值 = 源码件.read_bytes()
        except OSError:
            内容值 = b""
        摘要值.update(源码件.name.encode("utf-8"))
        摘要值.update(内容值)
    指纹缓存键, 指纹缓存值 = 键名, 摘要值.hexdigest()[:16]
    return 指纹缓存值


# `算服务指纹` 的按键缓存（本轮 stat 键 ⇒ 上次摘要）。**只在本进程内**：跨进程各自算一次，
# 首算仍走完整内容哈希（不省那一次），省的是同一进程里后续每一次。
指纹缓存键 = None
指纹缓存值 = None


启动指纹 = 算服务指纹()


def 过期提示行(传输="stdio") -> str:
    """启动时的指纹 ≠ 现在盘上的 ⇒ 提示行；一致 ⇒ 空串（不编话）。

    `传输` 只分流**措辞**：`stdio` 面服务随即自愈重启（`协议.py::跑主循环` 每轮拿它的**非空**
    当自愈重启的闸）；HTTP 面等待连接排空再预检，失败由服务对象记录。
    """
    if 算服务指纹() == 启动指纹:
        return ""
    if 传输 == "http":
        return "★ HTTP 当前加载码已过期：等待连接排空后预检重载；预检或 exec 失败会保留旧服务"
    return "★ 服务代码已过期：本帧仍是旧码，服务随即自愈重启（改了 `MCP服务/**` 不必重启 ZCode）"


# 本会话已提示过的「盘上指纹」—— 同一个不再重复提示（改了件才再提示一次）。
_已提示指纹 = None


def 过期提示一次() -> str:
    """同会话内缓存：同一「盘上指纹」只提示一次（改了件才再提示一次）；一致 ⇒ 空串。

    **为什么**（多路代理实测）：`协议.py::派发` 原先每帧都拼 `过期提示行()` —— stdio 面靠自愈
    exec 立即消跳，但 HTTP 面无自动 exec ⇒ 该提示每帧刷屏。这里只做**去重**（同一盘上指纹只
    提醒一次）；`过期提示行()` 的**纯判定**语义不变（主循环的自愈闸照用它）。
    """
    global _已提示指纹
    当前指纹 = 算服务指纹()
    if 当前指纹 == 启动指纹 or 当前指纹 == _已提示指纹:
        return ""
    _已提示指纹 = 当前指纹
    return 过期提示行()
