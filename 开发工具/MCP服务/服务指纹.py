"""服务指纹 —— MCP 服务**自身源码**的指纹：启动记一次，每次调用比对，不一致就报该重启。

**为什么要有它**（实测 2026-10-01）：MCP 是 ZCode 启动时拉起的**长驻进程** —— 改 `MCP服务/**`
不重启就跑旧码。腿 204 加了 `功能=6 源件记账`，而跑着的服务里根本没有它，只能直接 import 自证。
故服务启动时记下自身文件指纹，每次调用比对 ⇒ 不一致就报过期。

**过期怎么办**（2026-10-05）：`协议.py::跑主循环` 每轮「读下一帧之前」拿本判定当闸 —— 过期就
`os.execv` 重放自身（**自愈重启**：同一对 stdio 管道，客户端察觉不到）⇒ 改了件不必再重启 ZCode。
本函数仍是那唯一的判定实现；`协议.py::派发` 里那处只作「本帧用的是旧码」的兜底提示。
HTTP 面在唯一 accept 循环的空闲安全点预检重载，监听描述符由新进程核验继承；失败保留旧服务。

**面 = 服务源码 ＋ 运行期依赖**：`MCP服务/*.py` ＋ 入口 `MCP服务.py` ＋ `依赖` 表里那些被 import
的件（`代码地图/**` · 信息核心的 `表定义` · 一键验证的 `命名扫描`/`判据_台账号`
及其直接依赖）—— 改了它们、跑着的服务同样是旧码，同样该报过期。**一处算法**（`算服务指纹`），
启动记录与每次比对都用它。
"""

