def 算服务指纹() -> str:
    """服务源码的合并指纹 ⇒ 16 位十六进制（按件名排序后逐件摘要 —— 顺序无关）。"""
    摘要值 = hashlib.sha256()
    件表 = sorted(服务根.glob("*.py"))
    if 入口件.is_file():
        件表.append(入口件)
    for 目录路径 in 依赖:
        if 目录路径.is_dir():
            件表 += sorted(目录路径.glob("*.py"))
        else:
            件表.append(目录路径)
    for 源码件 in 件表:
        try:
            内容值 = 源码件.read_bytes()
        except OSError:
            内容值 = b""
        摘要值.update(源码件.name.encode("utf-8"))
        摘要值.update(内容值)
    return 摘要值.hexdigest()[:16]


启动指纹 = 算服务指纹()


def 过期提示行() -> str:
    """启动时的指纹 ≠ 现在盘上的 ⇒ 提示行；一致 ⇒ 空串（不编话）。

    `协议.py::跑主循环` 每轮拿它的**非空**当自愈重启的闸；`协议.py::派发` 拿它当兜底提示。
    """
    if 算服务指纹() == 启动指纹:
        return ""
    return "★ 服务代码已过期：本帧仍是旧码，服务随即自愈重启（改了 `MCP服务/**` 不必重启 ZCode）"
