# -*- coding: utf-8 -*-
"""服务指纹 —— MCP 服务**自身源码**的指纹：启动记一次，每次调用比对，不一致就报该重启。

**为什么要有它**（实测 2026-10-01）：MCP 是 ZCode 启动时拉起的**长驻进程** —— 改 `MCP服务/**`
不重启就跑旧码。腿 204 加了 `功能=6 源件记账`，而跑着的服务里根本没有它，只能直接 import 自证。
故服务启动时记下自身文件指纹，每次调用比对 ⇒ 不一致就在回执头打一行「服务代码已过期」。

**面 = 服务源码 ＋ 运行期依赖**：`MCP服务/*.py` ＋ 入口 `MCP服务.py` ＋ `依赖` 表里那些被 import
的件（`代码地图/**` · 信息核心的 `命名穷举`/`命名基线`/`表定义` · 一键验证的 `命名扫描`/`判据_台账号`
及其直接依赖）—— 改了它们、跑着的服务同样是旧码，同样该报过期。**一处算法**（`算服务指纹`），
启动记录与每次比对都用它。
"""

import hashlib
from pathlib import Path

服务根 = Path(__file__).resolve().parent
工具根 = 服务根.parent
仓根 = 工具根.parent
入口件 = 工具根 / "MCP服务.py"

# 运行期依赖面：服务 import 的、却不在 `服务根` 下的件 —— 改它们同样让跑着的服务过期。
# 逐条对得上 import 行：`代码地图/**`（`修改.py` · `符号.py` · `仓操作.py` · `批量改名.py` 都 import 它）·
# `信息核心/{命名穷举,命名基线,表定义}.py`（`修改.py` 的 `_未登记绑定名` 迟到 import 前两者，前两者又 import 表定义）·
# `一键验证/一键验证/{命名扫描,判据_台账号}.py` 及其直接依赖（`批量改名.py` 顶部 import）。
依赖 = (
    工具根 / "代码地图",
    工具根 / "信息核心" / "命名穷举.py",
    工具根 / "信息核心" / "命名基线.py",
    工具根 / "信息核心" / "表定义.py",
    仓根 / "构建装配" / "一键验证" / "一键验证" / "命名扫描.py",
    仓根 / "构建装配" / "一键验证" / "一键验证" / "判据_台账号.py",
    仓根 / "构建装配" / "一键验证" / "一键验证" / "剥字面量.py",
    仓根 / "构建装配" / "一键验证" / "一键验证" / "局部绑定形状.py",
    仓根 / "构建装配" / "一键验证" / "一键验证" / "小工具.py",
    仓根 / "构建装配" / "一键验证" / "一键验证" / "常量.py",
    仓根 / "构建装配" / "一键验证" / "一键验证" / "判据基线.py",
    仓根 / "构建装配" / "一键验证" / "一键验证" / "条款文本.py",
)


def 算服务指纹() -> str:
    """服务源码的合并指纹 ⇒ 16 位十六进制（按件名排序后逐件摘要 —— 顺序无关）。"""
    摘要 = hashlib.sha256()
    件表 = sorted(服务根.glob("*.py"))
    if 入口件.is_file():
        件表.append(入口件)
    for 目录 in 依赖:
        if 目录.is_dir():
            件表 += sorted(目录.glob("*.py"))
        else:
            件表.append(目录)
    for 源码件 in 件表:
        try:
            内容 = 源码件.read_bytes()
        except OSError:
            内容 = b""
        摘要.update(源码件.name.encode("utf-8"))
        摘要.update(内容)
    return 摘要.hexdigest()[:16]


启动指纹 = 算服务指纹()


def 过期提示行() -> str:
    """启动时的指纹 ≠ 现在盘上的 ⇒ 提示行；一致 ⇒ 空串（不编话）。"""
    if 算服务指纹() == 启动指纹:
        return ""
    return "★ 服务代码已过期，请重启 ZCode（MCP 是长驻进程，改了不重启跑的是旧码）"
