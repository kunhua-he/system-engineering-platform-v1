"""操作_编辑 —— `v1_edit` 的操作表（改 / 只检查 / 恢复）。

`改动表` 每条 = `{路径, 操作, 旧内容, 新内容}`，`操作` ∈ 新建 / 修改 / 删除（**不再用数值功能号**）；
本件把操作名映射回底层 `修改.派发` 认的数值。加载器 `参数规范.py` 自动 glob 本件。

`恢复` = 据账本里的**写盘意图**把「盘已写、账未记」收敛（不洗指纹、不造历史）——
它无改动表，直转 `写盘恢复.恢复开工`。给「改了盘、记账中途失败」的腿收尾，不另开第二入口。
"""

工具名 = "v1_edit"

改动操作号 = {"新建": 0, "修改": 1, "删除": 2}


def 换改动(参数表: dict) -> tuple:
    """新形 `改动表`（操作名）⇒ 底层 `改动表`（数值功能号）⇒ `(表, 错误或 None)`。

    `全替`（2026-10-08 加）逐条透传 —— 真 = 该条的 `旧内容` 换掉**全部**出现处（replace_all）。
    """
    改动表 = 参数表.get("改动表")
    if not isinstance(改动表, list) or not 改动表:
        return [], "缺 `改动表`（一次一条改动，要改多个就放多条；`只检查` 过了也可给 `沿用上次`）"
    换后 = []
    for 序号, 一条改动 in enumerate(改动表, 1):
        if not isinstance(一条改动, dict):
            return [], "改动表第 %d 条要是对象" % 序号
        操作名 = str(一条改动.get("操作") or "").strip()
        if 操作名 not in 改动操作号:
            # 旧键兼容（2026-10-08 · 566 腿实测「描述 vs 实现」漂移）：工具描述/最短例写的是新形
            # `操作`（新建 / 修改 / 删除），而树内 `修改._读一条改动` 读的是换算后的数值键 ⇒ 只按
            # 任一边写的调用方都可能被拒。故本口**两种都收**；两不像则给**迁移提示**（说清两形）。
            反查表 = {号码值: 操作键 for 操作键, 号码值 in 改动操作号.items()}
            try:
                号码 = int(一条改动.get("功能"))
            except (TypeError, ValueError):
                号码 = None
            if 号码 not in 反查表:
                return [], ("改动表第 %d 条：键不对 ⇒ 两种都认 —— 新形 `{路径, 操作, 旧内容, 新内容}`"
                        "（`操作` ∈ %s）或旧形 `{路径, 功能, 旧内容, 新内容}`（`功能` ∈ 0/1/2）。"
                        % (序号, " / ".join(改动操作号)))
            操作名 = 反查表[号码]
        换后.append({"路径": 一条改动.get("路径"), "功能": 改动操作号[操作名],
                 "旧内容": 一条改动.get("旧内容"), "新内容": 一条改动.get("新内容"),
                 "全替": 一条改动.get("全替")})
    return 换后, None


def 建处理(只检查: bool):
    """两种编辑操作（写盘 / 只读预检）共用一个处理工厂。"""

    def 处理(开工号: str, 参数表: dict, 仓根):
        from .修改 import 派发
        沿用 = str(参数表.get("沿用上次") or "").strip()
        原始表 = 参数表.get("改动表")
        if 只检查:
            换后, 错误 = 换改动(参数表)
            if 错误:
                return 2, 错误
            return 派发({"开工ID": 开工号, "改动表": 换后, "只检查": True}, 仓根)
        if 沿用 and not 原始表:
            # 短引用：`只检查` 查过的那份表住进程内存 ⇒ 大表不必重传（2026-10-08 · 540 腿）。
            return 派发({"开工ID": 开工号, "沿用上次": 沿用}, 仓根)
        换后, 错误 = 换改动(参数表)
        if 错误:
            return 2, 错误
        实参 = {"开工ID": 开工号, "改动表": 换后}
        if 沿用:
            实参["沿用上次"] = 沿用
        return 派发(实参, 仓根)

    return 处理


def 恢复处理(开工号: str, 参数表: dict, 仓根):
    """`恢复` 的处理：据写盘意图收敛盘账（无改动表）。"""
    from .写盘恢复 import 恢复开工
    return 恢复开工(仓根, 开工号)


