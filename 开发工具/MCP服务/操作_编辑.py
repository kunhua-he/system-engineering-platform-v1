# -*- coding: utf-8 -*-
"""操作_编辑 —— `v1_edit` 的操作表（改 / 只检查 / 恢复）。

`改动表` 每条 = `{路径, 操作, 旧内容, 新内容}`，`操作` ∈ 新建 / 修改 / 删除（**不再用数值功能号**）；
本件把操作名映射回底层 `修改.派发` 认的数值。加载器 `参数规范.py` 自动 glob 本件。

`恢复` = 据账本里的**写盘意图**把「盘已写、账未记」收敛（不洗指纹、不造历史）——
它无改动表，直转 `写盘恢复.恢复开工`。给「改了盘、记账中途失败」的腿收尾，不另开第二入口。
"""

import re

工具名 = "v1_edit"

改动操作号 = {"新建": 0, "修改": 1, "删除": 2}
改动号反查 = {操作号: 操作名 for 操作名, 操作号 in 改动操作号.items()}
整数串形 = re.compile(r"^[+-]?[0-9]+$")


def _解改动操作(一条改动: dict) -> tuple:
    """把一条改动的操作选择解成规范操作名 ⇒ `(操作名, 错误或 None)`。

    两种键都收（新形 `操作` / 旧形 `功能`），二者**并存且一致**也收：
      · `操作` = 操作名（新建 / 修改 / 删除）或号（0 / 1 / 2，或纯数字串）。
      · `功能` = 号，**只收整数 0/1/2** —— 拒逻辑值 / 浮点 / 字符串（**不做 int 宽转换**）。
    **并存且矛盾 ⇒ 拒**（不再「新形优先」静默吞冲突）。
    """
    给了操作 = "操作" in 一条改动
    给了功能 = "功能" in 一条改动
    操作侧名 = None
    if 给了操作:
        取值 = 一条改动.get("操作")
        if isinstance(取值, bool):
            return None, "`操作` 不接受逻辑值（true/false）—— 给 0/1/2 或 新建/修改/删除"
        if isinstance(取值, int):
            操作侧名 = 改动号反查.get(取值)
            if 操作侧名 is None:
                return None, "`操作` 号 %r 未知（0=新建 · 1=修改 · 2=删除）" % (取值,)
        elif isinstance(取值, float):
            return None, "`操作` 不接受浮点（%r）—— 给 0/1/2 或 新建/修改/删除" % (取值,)
        elif isinstance(取值, str):
            取值 = 取值.strip()
            if 取值 in 改动操作号:
                操作侧名 = 取值
            elif 整数串形.match(取值):
                操作侧名 = 改动号反查.get(int(取值))
                if 操作侧名 is None:
                    return None, "`操作` 号 %r 未知（0=新建 · 1=修改 · 2=删除）" % (取值,)
            else:
                return None, "`操作` 不合法：%r（0/1/2 或 新建/修改/删除）" % (取值,)
        else:
            return None, "`操作` 类型不对（%s）—— 给 0/1/2 或 新建/修改/删除" % type(取值).__name__
    功能侧名 = None
    if 给了功能:
        取值 = 一条改动.get("功能")
        if isinstance(取值, bool) or not isinstance(取值, int):
            return None, "`功能` 只接受整数 0/1/2（拒逻辑值 / 浮点 / 字符串），收到 %r" % (取值,)
        功能侧名 = 改动号反查.get(取值)
        if 功能侧名 is None:
            return None, "`功能` 只认 0/1/2，收到 %r" % (取值,)
    if 操作侧名 is not None and 功能侧名 is not None and 操作侧名 != 功能侧名:
        return None, ("`操作`=%s 与 `功能`=%s **矛盾** ⇒ 整批零写拒（二者只给一个，或给一致的）"
                  % (操作侧名, 功能侧名))
    操作名 = 操作侧名 if 操作侧名 is not None else 功能侧名
    if 操作名 is None:
        return None, ("缺操作 —— 给 `操作`（0/1/2 或 新建/修改/删除）或旧形 `功能`（0/1/2）。"
                  "两种键都认；同时给且一致也可以。")
    return 操作名, None


def 换改动(参数表: dict) -> tuple:
    """新形 `改动表`（操作名 / 号）⇒ 底层 `改动表`（数值功能号）⇒ `(表, 错误或 None)`。

    `全替`（2026-10-08 加）逐条透传 —— 真 = 该条的 `旧内容` 换掉**全部**出现处（replace_all）。
    操作选择接受 名（新建 / 修改 / 删除）或 号（0 / 1 / 2，整数或纯数字串）；`操作` 与 `功能`
    并存且矛盾 ⇒ 整批零写拒。
    """
    改动表 = 参数表.get("改动表")
    if not isinstance(改动表, list) or not 改动表:
        return [], "缺 `改动表`（一次一条改动，要改多个就放多条；`只检查` 过了也可给 `沿用上次`）"
    换后 = []
    for 序号, 一条改动 in enumerate(改动表, 1):
        if not isinstance(一条改动, dict):
            return [], "改动表第 %d 条要是对象" % 序号
        操作名, 错误 = _解改动操作(一条改动)
        if 错误:
            return [], "改动表第 %d 条：%s" % (序号, 错误)
        换后.append({"路径": 一条改动.get("路径"), "功能": 改动操作号[操作名],
                 "旧内容": 一条改动.get("旧内容"), "新内容": 一条改动.get("新内容"),
                 "全替": 一条改动.get("全替")})
    return 换后, None


def 建处理(只检查: bool):
    """两种编辑操作（写盘 / 只读预检）共用一个处理工厂。"""

    def 处理(开工号: str, 参数表: dict, 仓根):
        from .修改 import 派发
        沿用 = str(参数表.get("沿用上次") or "").strip()
        原始表 = 参数表.get("改动表")
        if 只检查:
            换后, 错误 = 换改动(参数表)
            if 错误:
                return 2, 错误
            return 派发({"开工ID": 开工号, "改动表": 换后, "只检查": True}, 仓根)
        if 沿用 and not 原始表:
            # 短引用：`只检查` 查过的那份表住进程内存 ⇒ 大表不必重传（2026-10-08 · 540 腿）。
            return 派发({"开工ID": 开工号, "沿用上次": 沿用}, 仓根)
        换后, 错误 = 换改动(参数表)
        if 错误:
            return 2, 错误
        实参 = {"开工ID": 开工号, "改动表": 换后}
        if 沿用:
            实参["沿用上次"] = 沿用
        return 派发(实参, 仓根)

    return 处理


