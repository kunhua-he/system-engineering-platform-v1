# -*- coding: utf-8 -*-
"""参数键集 —— 「某操作声明的具名键」的**唯一边界**（声明 → 校验的推导只此一份）。

**为何单立**（债务 2882 收口）：网关 `参数规范.py::网关派发` 早已按 `操作表` 声明派生键集，
但 `shell.py` / `符号查询.py` / `操作_搜索.py` 三层直调口仍手写第二份 —— 改声明不会同步到校验
（415 / 605 是同一病根）。本件把这个推导抽成一个叶子节点：谁要「本操作认哪些键」都调它。

**声明表 = 参数**（函数体内取，调用时才求值）。传表而不是传模块，因为各工具的操作表分住
各自的 `操作_*.py`；收表也就避开了环形导入（`符号查询.py` ↔ `操作_符号.py` 那类）。
"""
from __future__ import annotations


# W3 合同的**顶层三字段**（`开工ID` / `操作` / `参数`）—— 唯一来源就在本件；
# `参数规范.py` 与各直调口（如 `符号查询.py`）都从这里取，不再各持一份字面量。
顶层键 = ("开工ID", "操作", "参数")


def 声明键集(操作表: dict, 操作名: str, 并入开工: bool = False) -> tuple:
    """某操作**声明**的具名键（`必需` + `可选`；`并入开工` ⇒ 再收 `开工ID`）。

    唯一来源是**该操作所在的操作表**条目 —— 校验不许再手写第二份键集：415 即手写键集与
    声明漂开（声明早收 `速览`、校验仍拒），改声明的人不会想到还有一处手写表要同步。
    调用点写 `声明键集(操作表, "操作名", …)`：`操作表` 是**调用模块的全局**，函数体内取
    ⇒ 调用时才求值，既不撞定义顺序，也不撞环形导入（`件头` / `账本差集` 的声明住别的件）。
    """
    操作条 = 操作表[操作名]
    键表 = tuple(操作条.get("必需", ())) + tuple(操作条.get("可选", ()))
    return 键表 + (("开工ID",) if 并入开工 else ())


__all__ = ["声明键集", "顶层键"]
