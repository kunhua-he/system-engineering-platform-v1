跳过目录 = (".git", "__pycache__", ".codegraph", "只读参考", "node_modules")


def 读命名件(工作树) -> dict:
    """走树读**代码件** ⇒ `{仓内相对路径: 文本}`（跳过只读参考 / 版本库 / 缓存 / 索引库）。

    ★ 2026-10-06：原先走 `命名穷举.读命名件` —— 该模块已随旧命名口径体系退场（那处 import
    会让本模块**整个 ImportError**）。本件自持这一份走树读件：**不复用** `落库.候选文件` 是
    因为它内部的 `是仓内` 只认**它自身所在的那棵树**的仓根，对**别的**工作树会整枝判成仓外。
    """
    文件内容表 = {}
    for 路径 in Path(工作树).rglob("*"):
        if not 路径.is_file() or 路径.suffix not in 命名可解析后缀:
            continue
        if any(路径段 in 跳过目录 for 路径段 in 路径.parts):
            continue
        try:
            文件内容表[路径.relative_to(工作树).as_posix()] = 路径.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
    return 文件内容表


# ── `.名` 成员访问（**只在本件声明了该键时才认**）─────────────────────────────────────
# 依据：实测 2026-10-06 —— 共用扫描器把紧跟 `.` 的一律当「别人家的成员」排除 ⇒ 改对象字面量的键时，
# `对象.名` 的读取**没跟着改** ⇒ 悬空引用（`开着的.盒` / `步卡.卡` / `.能` / `流水条.时` 实测撞过）。
# **安全边界**：只有当 `名` 在**本件**被声明成键/字段（`名:` · `self.名 =` · `{ 名 }` 简写）时，
# 才把 `.名` 当作者起的名字。这条同时挡住 `from .验证小工具 import`（模块名）· `.start()`（标准库方法）·
# `document.body`（DOM）这类**别人家的成员** —— 实测挡住 `小工具`58 · `start`19 · `end`14 · `key`4 处。
# （`小工具` 三名已改名：`验证小工具` · `生成小工具` · `扫实现小工具`；此处留着旧读数是实测记录。）
_点读名 = re.compile(r"(?<!\.)\.\s*([A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*)")
# `...名`（JS 展开 / 剩余）里的 `名` **不是**成员访问 —— 但共用扫描器把 `...` 的第三个点当成了 `.`，
# 于是 `...枝` 被整枝漏掉（实测：`支持库树.js` 的 `[...枝.get(...)]` 改一半留一半 ⇒ 悬空引用）。这里补回来。
_展开名 = re.compile(r"\.\.\.\s*([A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*)")


def 本件声明的键(净文本: str, 名集) -> set:
    """`名集` 里**在本件被声明成键/字段**的那些 ⇒ 本件里的 `.名` 点读才算作者的名字。"""
    声明键集 = set()
    for 候选名 in 名集:
        名正则 = re.escape(候选名)
        if (re.search(r"(?<![\w.\"'])" + 名正则 + r"\s*:", 净文本)
                or re.search(r"self\.\s*" + 名正则 + r"\s*=", 净文本)
                or re.search(r"[\{,}]\s*" + 名正则 + r"\s*[,}]", 净文本)):
            声明键集.add(候选名)
    return 声明键集


# ── 冻结字段/载荷名白名单（方案 A：读 `契约声明/冻结登记.json`）──────────────────────
# 依据：实测 2026-10-06（腿 v1-100335）—— 冻结字段（`数据槽.值` 一类）在**调用点不声明** ⇒
# 「本件声明的键」那一道看不见跨件 `.名`，只能逐条 `v1_edit`。白名单来源 = `冻结登记.json`
# 各 `冻结项` 落点 `路径::符号名` 的**声明文本**里的字段/载荷名（`名:`）—— 权威源（判据 ⑨），
# **不另立标记**（方案 B 要人工维护 ⇒ 弃）。**安全边界**：只放行白名单里的名，标准库方法
# （`.get()` / `.append()` / `.start()`）不在其中 ⇒ 不误改。**降级**：JSON 缺失 / 读不到 /
# 解析失败 ⇒ **空集**（退回旧行为），绝不崩。
_字段名 = re.compile(r"(?<!:)([A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*)\s*:")


def 读冻结字段名(工作树) -> set:
    """⇒ `冻结登记.json` 各形状里登记的**字段名 / 枚举载荷名**集合（只认 `pub struct`/`pub enum`
    声明，不取 `fn` 体里的局部；落点非 `路径::符号名`、件读不到、JSON 坏 ⇒ 跳过 / 空集）。
    """
    import json
    try:
        文件条目 = Path(工作树) / "契约声明" / "冻结登记.json"
        if not 文件条目.is_file():
            return set()
        登记 = json.loads(文件条目.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return set()
    _子目录 = str(工具根 / "构建装配" / "一键验证")
    if _子目录 not in sys.path:
        sys.path.insert(0, _子目录)
    try:
        from 一键验证.源码解析.冻结形状 import 抽符号声明文本
    except ImportError:
        return set()
    名集 = set()
    for 冻结项 in (登记.get("冻结项") or []):
        落点 = str(冻结项.get("落点") or "")
        if "::" not in 落点:
            continue
        相对路径, 符号名 = 落点.split("::", 1)
        try:
            源文本 = (Path(工作树) / 相对路径).read_text(encoding="utf-8")
        except OSError:
            continue
        声明 = 抽符号声明文本(源文本, 符号名)
        if 声明 and re.match(r"\s*pub\s+(?:unsafe\s+)?(?:struct|enum)\b", 声明):
            名集 |= set(_字段名.findall(声明))
    return 名集


def 抽可换(净文本: str, 名集, 冻结名集=()) -> list:
    """⇒ `[(名, 位置)]`：常规标识符 **＋** 本件声明的键的 `.名` 点读 **＋** 冻结字段名的跨件 `.名` 点读。

    `.名` 那部分是本件对共用扫描器（`命名扫描.抽标识符带位置`）的**局部加宽** —— 不动共用件，
    免得波及判据 ㉒ / 代码地图 / 债名落点（它们要的仍是「排除成员访问」的口径）。
    **冻结字段名**（`数据槽.值` / `号段.起` 一类）在调用点不声明 ⇒ 「本件声明的键」那一道看不见
    它们；它们由 `读冻结字段名` 的白名单放行。
    """
    名位表 = 命名扫描.抽标识符带位置(净文本)
    键集 = 本件声明的键(净文本, 名集) | (set(名集) & set(冻结名集))
    已占位 = {字节位置 for _, 字节位置 in 名位表}
    for 命中项 in _点读名.finditer(净文本):
        if 命中项.group(1) in 键集 and 命中项.start(1) not in 已占位:
            名位表.append((命中项.group(1), 命中项.start(1)))
    for 命中项 in _展开名.finditer(净文本):
        if 命中项.group(1) in 名集 and 命中项.start(1) not in 已占位:
            名位表.append((命中项.group(1), 命中项.start(1)))
    名位表.sort(key=lambda 名位对: 名位对[1])
    return 名位表


def 扫出现(工作树, 名表, 冻结名集=()) -> dict:
    """走树扫**标识符整词** ⇒ `{路径: {旧名: 处数}}`（面 = `读命名件`）。

    **面与 `验证.py::扫债名落点` 同一份**（同一剥器 + 同一抽法 + 同一制品排除）：只在
    `命名扫描.剥后缀` 后的**标识符位置**上数 ⇒ 注释 / 字符串 / 正则里的整词不算，
    非 `self.` 的 `.名` 成员访问也不算。`路径串区间` 作冗余第二道（字符串已在净文本里抹空）。
    """
    命中表 = {}
    for 路径, 源文本 in 读命名件(工作树).items():
        if 是制品产物(路径):
            continue
        净文本 = 命名扫描.剥后缀("." + 路径.rsplit(".", 1)[-1], 源文本)
        区间表 = 路径串区间(源文本)
        次数表 = {}
        for 旧名字, 字节位置 in 抽可换(净文本, 名表, 冻结名集):
            if 旧名字 in 名表 and not _在区间里(字节位置, 区间表):
                次数表[旧名字] = 次数表.get(旧名字, 0) + 1
        if 次数表:
            命中表[路径] = 次数表
    return 命中表


def 换整词(全文, 名对表, 源码后缀, 冻结名集=()) -> tuple:
    """按**标识符整词**替换 ⇒ `(新全文, {旧名: 换了几处})`。子串不换（`参数表` 不动）。

    **只在剥掉注释与字符串之后的标识符位置上换**（面与 `扫出现` 同一份，见其说明）：
    注释 / 字符串 / 正则里的整词一个字都不动。`路径串区间` 作冗余第二道。
    """
    净文本 = 命名扫描.剥后缀(源码后缀, 全文)
    区间表 = 路径串区间(全文)
    缓冲, 换数表, 末位 = [], {}, 0
    for 旧名, 字节位置 in 抽可换(净文本, set(名对表), 冻结名集):
        if 旧名 in 名对表 and not _在区间里(字节位置, 区间表):
            缓冲.append(全文[末位:字节位置])
            缓冲.append(名对表[旧名])
            换数表[旧名] = 换数表.get(旧名, 0) + 1
            末位 = 字节位置 + len(旧名)
    缓冲.append(全文[末位:])
    return "".join(缓冲), 换数表
