def 内容指纹(内容值: str) -> str:
    """一段文本按 utf-8 码的内容指纹（sha256 前 16 位）—— 与 `文件指纹` 同形，但吃内存文本。

    `写文件` 以 `newline="\n"` + utf-8 写盘 ⇒ 落盘字节就是 `文本.encode("utf-8")` ⇒
    两者得同一个值。写盘**之前**就能算出期望写后指纹，才能拿它当恢复的唯一凭据。
    """
    return hashlib.sha256(内容值.encode("utf-8")).hexdigest()[:16]


def 写文件(件路径: Path, 全文: str, 预期指纹=None, 工作树=None) -> str:
    """**临时件 + rename**（同目录、同文件系统 ⇒ 原子的）⇒ 错误说明（空 = 成功）。

    为什么不 `write_text`：它是「截断 + 写」，中途崩了会留一个**半截文件** ——
    那是把「拒」变成了「毁」。

    ★ **保留既有件的模式位**（2026-10-08 实测）：`rename` 换的是**新 inode**，新 inode 的模式
    是「按 umask 新建」的那个（仓内 umask 022 ⇒ 644），**原件带不带执行位都不带过去** ——
    实测 0755 的件经本函数落盘后变 644。仓里有 5 个带执行位的 `.sh`（`git ls-files -s` 记
    `100755`，`合主干集成树.py` 合主干时也读这个位），原先的 `write_text`（原地截断）不丢模式位
    ⇒ 那是本件引入的**回归**。故写临时件后先把原模式位 `chmod` 回去、再 `replace`。
    新件（原件不存在）照旧吃 umask —— 与 `write_text` 建新件同一口径。模式位读 / 设不动
    ⇒ 同 `OSError` 一并走失败分支：临时件删掉，**原文件一个字节不动**。
    """
    import tempfile
    if 预期指纹 is None:
        预期指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
    临时路径 = None
    原父目录 = 件路径.parent.resolve()
    try:
        if 工作树 is not None:
            核树内路径(工作树, 件路径.relative_to(工作树).as_posix())
        elif 件路径.is_symlink() or 件路径.parent.is_symlink():
            return "路径含链接：未写盘"
        文件描述符, 临时文件名 = tempfile.mkstemp(prefix=件路径.name + ".", suffix=写盘后缀, dir=件路径.parent)
        os.close(文件描述符)
        临时路径 = Path(临时文件名)
        原模式 = 件路径.stat().st_mode & 0o7777 if 件路径.exists() else None
        临时路径.write_text(全文, encoding="utf-8", newline="\n")
        if 原模式 is not None:
            os.chmod(临时路径, 原模式)
        当前指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
        if 件路径.is_symlink() or 件路径.parent.resolve() != 原父目录 or 当前指纹 != 预期指纹:
            临时路径.unlink(missing_ok=True)
            return "替换前指纹漂移：未替换原件"
        os.replace(临时路径, 件路径)
    except (OSError, ValueError) as 写不动的原因:
        if 临时路径 is not None:
            临时路径.unlink(missing_ok=True)
        return "写盘失败：%r" % (写不动的原因,)
    return ""


def 删除文件(件路径: Path) -> str:
    """删除件 ⇒ 错误说明（空 = 成功）。

    ★ 原先直接 `件路径.unlink()` 裸抛：删不动（权限 / 目录不可写）时异常冒到协议层，
    变成 `-32603 内部错误`，而**前面已写成功的件已经落盘、账也记了** —— 回执拿不到，
    调用方无从判断。本函数把它收成可读的返回（与 `写文件` 同形），失败原样进回执。
    """
    try:
        件路径.unlink()
    except OSError as 删不动的原因:
        return "删除失败：%r" % (删不动的原因,)
    return ""


def 定位旧内容(全文: str, 旧内容: str) -> list:
    """`旧内容` 在全文里的**全部出现位置** ⇒ `[位置…]`（空表 = 找不到）。"""
    位表, 区间起点 = [], 0
    while True:
        字节位置 = 全文.find(旧内容, 区间起点)
        if 字节位置 < 0:
            return 位表
        位表.append(字节位置)
        区间起点 = 字节位置 + 1


def 改动已落(全文: str, 旧内容: str, 新内容: str) -> bool:
    """这一条改动**是否已经落在** `全文` 里 ⇒ 真 = 幂等重放，跳过。

    ★ 判据**不能只看**「`新内容` 在不在全文里」：当 `新内容` 是 `旧内容` 的**子串**（删除形 ——
    旧内容是「锚点行 + 要删的行」、新内容只留锚点行）时，落盘**之前** `新内容` 就已经在全文里 ⇒
    只看它会把「还没应用」误判成「已应用」而**静默跳过**（612 / 616 腿实测：删除没落盘、
    同件两条还把回执记成 2/2）。正确口径按新旧**包含关系**分形：
      · 插入形（`旧内容` 是 `新内容` 的一部分）：落过之后 `旧内容` 仍在（就在新内容里）⇒
        只能看 `新内容` 在不在（554 腿的重复 import 就是这个形）。
      · 其余（替换 / 删除）：落过之后 `旧内容` 必消失 ⇒ 要 `旧内容` 不在全文、且 `新内容` 在，
        才算已落；`新内容` 为空（纯删除）⇒ 不看它，交定位去删（在就删、不在就如实报）。
    """
    if not 新内容:
        return False
    if 新内容 not in 全文:
        return False
    if 旧内容 in 新内容:
        # 插入形（旧内容是新的子串）：落过之后旧内容仍在（就在新内容里）⇒ 看新内容在不在即可。
        return True
    if 新内容 in 旧内容:
        # 删除形（新内容是旧的子串）：落过之后旧内容必消失。★ 这一形**能**靠「旧内容不在」判已落
        # —— 因为「新内容在」是它的前提（旧内容在则新内容必在）⇒ 旧内容不在就只能是已落，
        #   不会是「旧内容写错」。
        return 旧内容 not in 全文
    # 替换形（新旧互不包含）：旧内容不在全文时**分不清**是「已落」还是「旧内容写错」
    # ⇒ 一律交定位去判（找不到就如实拒，不静默跳过）。
    # ★ 2026-10-10 修（腿 v1-100759 真实发作）：原先末行是 `旧内容 in 新内容 or 旧内容 not in 全文`
    #   ⇒ 后半个条件把替换形的「旧内容写错」也当成「已落」⇒ `模拟整批` 连定位都不做就跳过
    #   ⇒ 回执报「已存在跳过」**假成功**，调用方以为改完了，其实一个字节没动。
    return False


def 模拟整批(工作树: Path, 项表: list, 写前快照=None) -> tuple:
    """整批在内存里推到**每件最终态** ⇒ `(最终态表, 定位失败表)`。

    改动项 = `(路径, 功能号, 旧内容, 新内容)`，可带第 5 位 `全替`（真 = 换掉**全部**出现处）。
    最终态表 = `{相对路径: 最终全文 或 None}`（None = 这件最终被删）。
    定位失败表 = `[(序号, 路径, 原因)]` —— **非空 ⇒ 调用方整批拒、0 写盘**（整批原子性）。

    按项表顺序推（不按行号）：同件「先改一半、后条补另一段」的中间态是**正常**的 ⇒ 每条的定位
    都对**前一条落定之后**的文本做，与真写盘同一顺序、同一结果。`全替` 真时走 `str.replace`
    （**单遍**左到右，不重扫插入文本）；假时要求**唯一**（多次出现即失败，旧口径不变）。
    """
    最终态表, 定位失败表 = {}, []
    for 序号, 改动项 in enumerate(项表, 1):
        路径, 功能号, 旧内容, 新内容 = 改动项[0], 改动项[1], 改动项[2], 改动项[3]
        全替 = bool(改动项[4]) if len(改动项) > 4 else False
        if 路径 not in 最终态表:
            件路径 = 工作树 / 路径
            try:
                件路径 = 核树内路径(工作树, 路径)
                原始字节 = 件路径.read_bytes() if 件路径.is_file() else None
                最终态表[路径] = 原始字节.decode("utf-8") if 原始字节 is not None else None
                if 写前快照 is not None:
                    写前快照[路径] = hashlib.sha256(原始字节).hexdigest()[:16] if 原始字节 is not None else ""
            except (UnicodeDecodeError, OSError, ValueError) as 读不动:
                最终态表[路径] = None
                定位失败表.append((序号, 路径, "读件失败：%r" % (读不动,)))
                continue
        全文 = 最终态表[路径]
        目标全文 = 新内容 if 新内容.endswith("\n") else 新内容 + "\n"
        if 功能号 == 功能_新建:
            if 全文 is None:
                最终态表[路径] = 目标全文
                continue
            if 全文 == 目标全文:
                continue          # 已存在且内容一致 ⇒ 幂等跳过（最终态不动 ⇒ 落盘阶段也不写）
            定位失败表.append((序号, 路径, "盘上已存在且内容不同 ⇒ 要改它就用 功能 = 1"))
            continue
        if 功能号 == 功能_删除:
            if 全文 is None:
                continue          # 件已经不在了 ⇒ 删除已生效（幂等跳过）
            if 旧内容 != 全文:
                定位失败表.append((序号, 路径,
                              "功能=2 整件删除要求 `旧内容` 逐字等于盘上全文 ⇒ 拒绝删除"))
                continue
            最终态表[路径] = None
            continue
        if 全文 is None:
            定位失败表.append((序号, 路径, "盘上不存在 ⇒ 要新建就用 功能 = 0"))
            continue
        if 全替:
            if 旧内容 in 全文:
                最终态表[路径] = 全文.replace(旧内容, 新内容)
                continue
            if 新内容 and 旧内容 not in 新内容 and 改动已落(全文, 旧内容, 新内容):
                continue
            定位失败表.append((序号, 路径, "找不到旧内容，不能确认全替已应用"))
            continue
        if 改动已落(全文, 旧内容, 新内容):
            # 本条的改动**已经落过** ⇒ 判为「已存在跳过」（不报错、不动最终态）⇒ 整批可安全重跑。
            # 判据见 `改动已落`：只看「新内容在不在」会把「新内容 ⊂ 旧内容」的删除形误判成已落。
            continue
        位表 = 定位旧内容(全文, 旧内容)
        if not 位表:
            定位失败表.append((序号, 路径, "**找不到** `旧内容` ⇒ 拒（件已变，重读一次再发起）"))
            continue
        if len(位表) > 1:
            行号表 = [全文[:字节位置].count("\n") + 1 for 字节位置 in 位表]
            定位失败表.append((序号, 路径,
                        "`旧内容` 出现 **%d 次**（行 %s）⇒ 拒。多给几行上下文让它唯一，"
                        "或显式 `全替` = 真" % (len(位表),
                                          " · ".join(str(行号) for 行号 in 行号表[:8]))))
            continue
        最终态表[路径] = 全文[:位表[0]] + 新内容 + 全文[位表[0] + len(旧内容):]
    return 最终态表, 定位失败表


def 扫字面禁项(路径: str, 内容值: str) -> list:
    """新内容里的 ㊵ 零字面十干 / ㊹ 零字面禁译名 命中 ⇒ `[(类别, 行号, 说明)]`（写即拒）。

    **为何进写前预检**（2026-10-08 · 546 腿实测）：这两条判据原先只在闸 0 跑 ⇒ 新内容里写进
    一个十干字，四道闸全放行，直到跑完**整个**闸 0 才被打红 —— 白跑一整轮全量。这两条是
    **廉价逐字节**扫描 ⇒ 提到写前，当场拒并指名（行号 + 码位）。

    **一处实现，两处用**：`修改.派发`（真写）与 `批量预检.扫一遍`（只读）都调本件 ——
    与判据 ㊵/㊹ **共用同一份扫描器**（`判据_十干.扫十干` / `判据_禁译名.扫禁译名`），
    本件不另写一套正则。面口径同判据：先过 `判据_十干.路径被排除`。
    """
    import sys as _sys
    from pathlib import Path as _路径
    工具根 = _路径(__file__).resolve().parents[3]
    for 子目录 in (str(工具根 / "构建装配" / "一键验证"), str(工具根 / "开发工具")):
        if 子目录 not in _sys.path:
            _sys.path.insert(0, 子目录)
    if not _禁项扫描器:
        from 一键验证.检查规则.规范文本 import 判据_十干 as _十干, 判据_禁译名 as _禁译
        _禁项扫描器.extend((_十干, _禁译))
    判据_十干, 判据_禁译名 = _禁项扫描器[0], _禁项扫描器[1]
    if 判据_十干.路径被排除(路径):
        return []
    条目表 = [("十干", 行号, "码位 U+%04X" % 码位)
           for 路径名, 行号, 码位 in 判据_十干.扫十干({路径: 内容值})]
    条目表 += [("禁译名", 行号, "") for 路径名, 行号 in 判据_禁译名.扫禁译名({路径: 内容值})]
    return 条目表


def _记意图(连接, 开工号: str, 路径: str, 功能名: str, 写前指纹: str, 期望写后: str) -> str:
    """落盘前记一行意图 ⇒ 错误说明（空 = 成功）。落不动意图 ⇒ **不写盘**（fail-closed）。"""
    try:
        记写盘意图(连接, 开工号, 路径, 功能名, 写前指纹, 期望写后)
    except sqlite3.Error as 意图错:
        return "%s" % (意图错,)
    return ""


def _平意图(连接, 开工号: str, 路径: str) -> str:
    """落盘**失败**后就地销意图（件没动，意图无害）⇒ 残留提示（空 = 已销 / 销不动）。"""
    try:
        销写盘意图(连接, 开工号, 路径)
    except sqlite3.Error:
        return "（写盘意图未销掉，可跑 `v1_edit` 操作 `恢复` 收敛）"
    return ""


def 行数预警(工作树: Path, 最终态表: dict) -> list:
    """最终态的行数预警 ⇒ 行表（**只预警，不改行为** · 2026-10-08 加）。

    原先行数能力只在 `只检查` 档（`批量预检.检查候选文本`），`改` 档没有 ⇒ 549 腿白跑一轮闸 0
    （⑲ 参数规范.py 403 行超顶）+ 一轮改。这里把**同一份**读数（`查文件行数.核心`，与判据 ⑲ 同源）
    接进写前：超顶报一行；**距上限 ≤5 行**也报一行（顶到 800 行的件，下一笔增量本该落**新件**）。
    """
    import sys as _sys
    工具根 = Path(__file__).resolve().parents[3]
    if str(工具根 / "开发工具") not in _sys.path:
        _sys.path.insert(0, str(工具根 / "开发工具"))
    from 查文件行数 import 核心
    预警行表 = []
    for 路径 in sorted(最终态表):
        全文 = 最终态表[路径]
        if 全文 is None or not 核心.是源码(路径):
            continue
        行数 = len(全文.splitlines())
        上限 = 核心.行数上限
        if 行数 > 上限:
            预警行表.append("  `%s`：最终态 %d 行 > %d ⇒ 闸 0 会红；把增量落**新件**，别顶这一件"
                      % (路径, 行数, 上限))
        elif 行数 >= 上限 - 5:
            预警行表.append("  `%s`：最终态 %d 行，距 %d 上限只剩 %d 行 ⇒ 下一笔增量该落新件"
                      % (路径, 行数, 上限, 上限 - 行数))
    return 预警行表


def 执行写盘(连接, 工作树: Path, 开工号: str, 项表: list, 最终态表: dict, 写前快照: dict) -> tuple:
    """按**已推演好的最终态**逐件落盘 ⇒ `(完成表, 失败说明, 失败阶段, 跳过数)`。

    定位已在 `模拟整批` 里整批干跑过（整批原子性）⇒ 本函数**不再定位**，只落盘：
    每件只写一次（同件多条改动共用同一份最终态），但**每条改动各计一行**完成读数
    （回执的「改了 N/M 条」与传入条数对齐）。落盘仍**逐件**（FS 没有整批事务）：
    第 k 件落盘失败 ⇒ 前 k−1 件已在盘上、账已记，回执如实报「本批已写几件、失败在第几件」。

    返回的 `失败阶段` ∈ 空串（全成）/「落意图」/「落盘」/「记账」—— 回执靠它说清
    「盘到哪一步了」，不洒一个笼统的失败。
    """
    完成表, 失败说明, 失败阶段, 跳过数 = [], "", "", 0
    已落集, 跳过件 = set(), set()
    for 序号, 改动行 in enumerate(项表, 1):
        路径, 功能号 = 改动行[0], 改动行[1]
        功能名 = 功能名表[功能号]
        if 路径 in 已落集:
            if 路径 in 跳过件:
                跳过数 += 1        # 按**条**计（同件多条都算跳过），与回执的「%d 条」对齐
            完成表.append("%s（%s%s）" % (路径, 功能名,
                                  " · 已存在跳过" if 路径 in 跳过件 else ""))
            continue
        try:
            件路径 = 核树内路径(工作树, 路径)
        except ValueError as 错误:
            return 完成表, str(错误), "路径校验", 跳过数
        写前指纹 = 写前快照[路径]
        if (文件指纹(str(件路径)) if 件路径.is_file() else "") != 写前指纹:
            return 完成表, "推演后指纹漂移：未写盘、未记意图", "落盘", 跳过数
        终态 = 最终态表.get(路径)
        try:
            现有 = (件路径.read_text(encoding="utf-8", newline="\n")
                  if 件路径.is_file() else None)
        except (UnicodeDecodeError, OSError):
            现有 = None
        if (终态 is None and not 件路径.is_file()) or (终态 is not None and 现有 == 终态):
            # 盘上已经是推演出来的最终态 ⇒ 本件**没有要落的改动**（本批前一条已落 / 整批重跑）
            # —— 幂等跳过：不落意图、不写盘、不记账（免得重跑把已应用的条目再应用一遍）。
            跳过数 += 1
            跳过件.add(路径)
            已落集.add(路径)
            完成表.append("%s（%s · 已存在跳过）" % (路径, 功能名))
            continue
        期望写后 = "" if 终态 is None else 内容指纹(终态)
        意图错 = _记意图(连接, 开工号, 路径, 功能名, 写前指纹, 期望写后)
        if 意图错:
            失败说明 = ("第 %d 条 `%s`：落写盘意图失败 ⇒ **没写盘**（fail-closed）：%s"
                    % (序号, 路径, 意图错.strip()))
            失败阶段 = "落意图"
            break
        当前指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
        if 当前指纹 != 写前指纹:
            错误 = "落盘前指纹漂移"
        elif 终态 is None:
            错误 = 删除文件(件路径)
        else:
            错误 = 写文件(件路径, 终态, 写前指纹, 工作树)
        if 错误:
            残留 = _平意图(连接, 开工号, 路径)
            失败说明 = "第 %d 条 `%s`：%s（盘上未改）%s" % (序号, 路径, 错误, 残留)
            失败阶段 = "落盘"
            break
        写后指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
        try:
            记一件写盘(连接, 开工号, 路径, 功能名, 写前指纹, 写后指纹)
        except sqlite3.Error as 收尾错:
            失败说明 = ("第 %d 条 `%s`：**盘已写（写后 %s），但记账没提上去**（%s）⇒ "
                    "盘账不一致，写盘意图仍在账本 —— 后面没动，先跑 `v1_edit` 操作 `恢复` 收敛"
                    % (序号, 路径, 写后指纹 or "（件没了）", 收尾错))
            失败阶段 = "记账"
            break
        已落集.add(路径)
        完成表.append("%s（%s）" % (路径, 功能名))
    return 完成表, 失败说明, 失败阶段, 跳过数


class 写盘占用(Exception):
    """已有写入者时立即拒绝。"""


from contextlib import contextmanager


@contextmanager
def 开工写盘锁(开工号):
    """同一账本、同一开工共享非阻塞进程锁。"""
    import fcntl
    from ..开工账本 import 连账本
    if not isinstance(开工号, str) or not 开工号.startswith("v1-") or "/" in 开工号 or ".." in 开工号 or "\\" in 开工号:
        raise 写盘占用("开工号形状错误")
    锁连接 = 连账本()
    try:
        树记录 = 锁连接.execute("select 工作树 from 开工 where 开工号 = ?", (开工号,)).fetchone()
    finally:
        锁连接.close()
    if not 树记录 or not Path(树记录[0]).is_dir():
        raise 写盘占用("没有这条开工工作树")
    锁描述符 = os.open(Path(树记录[0]), os.O_RDONLY)
    try:
        try:
            fcntl.flock(锁描述符, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise 写盘占用("开工写盘锁已占用，未写盘")
        try:
            yield
        finally:
            fcntl.flock(锁描述符, fcntl.LOCK_UN)
    finally:
        os.close(锁描述符)
