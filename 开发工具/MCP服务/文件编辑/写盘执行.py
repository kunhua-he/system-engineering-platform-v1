def 缺的祖先目录(工作树: Path, 新建路径表: list) -> list:
    """功能 = 0 的件，其父目录链上**盘上还不存在**的那些 ⇒ 从浅到深排序（＝建序）。

    只收**工作树内**的相对目录；已存在的一个也不收（目录已在盘上 ⇒ 空表，幂等）。
    """
    缺集 = set()
    for 相对路径 in 新建路径表:
        祖先目录 = (工作树 / 相对路径).parent
        while 祖先目录 != 工作树 and not 祖先目录.exists():
            缺集.add(祖先目录.relative_to(工作树).as_posix())
            祖先目录 = 祖先目录.parent
    return sorted(缺集, key=lambda 相对目录: (相对目录.count("/"), 相对目录))


def 清理新建目录(工作树: Path, 缺目录表: list) -> list:
    """失败收尾：只删除本批新建且仍为空的目录，返回真实删除路径。"""
    清理结果 = []
    for 清理项 in sorted(缺目录表, key=lambda 清理项: (清理项.count("/"), 清理项), reverse=True):
        目录路径 = 工作树 / 清理项
        try:
            目录路径.rmdir()
        except OSError:
            continue
        清理结果.append(清理项 + "/")
    return 清理结果


def 清理陈旧写盘临时件(工作树: Path, 路径表: list, 陈旧期限: int = 86400) -> list:
    """只清理本次目标同目录、匹配唯一暂存名的过期件；期限单位为秒，是文件年龄而非执行超时；调用方持开工锁。"""
    import re
    现在 = time.time()
    清理表 = []
    for 相对路径 in sorted(set(路径表)):
        件路径 = 核树内路径(工作树, 相对路径)
        if not 件路径.parent.is_dir():
            continue
        名称模式 = re.compile(re.escape(件路径.name) + r"\.[a-z0-9_]{8}" + re.escape(写盘后缀))
        for 临时件 in 件路径.parent.iterdir():
            if not 名称模式.fullmatch(临时件.name) or 临时件.is_symlink():
                continue
            核树内路径(工作树, 临时件.relative_to(工作树).as_posix())
            try:
                if not 临时件.is_file() or 现在 - 临时件.stat().st_mtime < 陈旧期限:
                    continue
                临时件.unlink()
                清理表.append(临时件.relative_to(工作树).as_posix())
            except FileNotFoundError:
                continue
    return 清理表

