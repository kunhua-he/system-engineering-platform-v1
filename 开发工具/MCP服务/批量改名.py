# ── 路径串（批量改名**不换**里面的整词）──────────────────────────────────────────────────
# 依据：实测腿 v1-100233 —— `#[path = "测试/坏输入.rs"]` 里的 `坏输入` 被当整词换掉 ⇒ 模块指到
# 不存在的件 ⇒ 编译崩（只能整体回退）。★ 2026-10-04 面收窄后，字符串整体已不在匹配面里 ⇒
# 本闸成了**冗余第二道**（裁决 `账本口径-3` 仍引着它、判据自测也可能引 ⇒ 不删）。
def 路径串区间(全文: str) -> list:
    """**路径串**在全文里的 `(起, 止)` 区间表（区间 = 引号**之内**，不含引号）。

    两类算路径串：① `#[path = "…"]` / `#[path="…"]` 的属性值（不论内容像不像路径）；
    ② 形如路径的字符串字面量（含 `/`，或结尾 `.rs`/`.py`/`.js`/`.ts`/`.vue`）。
    """
    区间表 = []
    for 匹配项 in re.finditer(r'"([^"\n]*)"', 全文):
        if (re.search(r'#[ \t]*\[[ \t]*path[ \t]*=[ \t]*$', 全文[:匹配项.start()])
                or "/" in 匹配项.group(1) or re.search(r"\.(?:rs|py|js|ts|vue)$", 匹配项.group(1))):
            区间表.append(匹配项.span(1))
    return 区间表


def _在区间里(位置: int, 区间表: list) -> bool:
    """`位置` 落在任一区间里（左闭右开）⇒ 真。"""
    return any(区间[0] <= 位置 < 区间[1] for 区间 in 区间表)


def 读名对(参数) -> tuple:
    """`改名对` 参数 ⇒ `({旧名: 新名}, 错误)`。空 / 形状不对 / 同名给两个目标 ⇒ 拒。"""
    if not isinstance(参数, list) or not 参数:
        return {}, "缺 `改名对`（形如 `[{\"旧名\": \"旧例\", \"新名\": \"新例\"}]`，可多对）"
    名对表 = {}
    for 序号, 一对 in enumerate(参数, 1):
        if not isinstance(一对, dict):
            return {}, "改名对第 %d 条要是对象 `{旧名, 新名}`" % 序号
        旧名 = str(一对.get("旧名") or "").strip()
        新名 = str(一对.get("新名") or "").strip()
        if not 旧名 or not 新名:
            return {}, "改名对第 %d 条缺 `旧名` 或 `新名`" % 序号
        if 旧名 == 新名:
            return {}, "改名对第 %d 条：旧名与新名一样 ⇒ 空转，不写" % 序号
        if 旧名 in 名对表 and 名对表[旧名] != 新名:
            return {}, "同一个旧名 `%s` 给了两个新名 ⇒ 拒（一次一个目标）" % 旧名
        名对表[旧名] = 新名
    return 名对表, ""


def 读范围(参数, 工作树) -> tuple:
    """`路径范围` 参数 ⇒ `(顶层区集合, 错误)`。空 / 不是工作树里的顶层目录 ⇒ 拒。"""
    if not isinstance(参数, list) or not 参数:
        return set(), "缺 `路径范围`（顶层区名，如 `[\"对外接口面\", \"前端呈现\"]`）"
    范围表 = {str(区名).strip() for 区名 in 参数 if str(区名 or "").strip()}
    if not 范围表:
        return set(), "`路径范围` 是空的（要至少一个顶层区）"
    不在 = sorted(区名 for 区名 in 范围表 if not (工作树 / 区名).is_dir())
    if 不在:
        return set(), "这些顶层区在工作树里不是目录：%s" % " · ".join(不在)
    return 范围表, ""


# 走树读件的面：代码件后缀 · 整枝跳过的目录（与 `命名校验` 同一套口径）。
代码后缀 = (".rs", ".py", ".js", ".ts", ".vue")
跳过目录 = (".git", "__pycache__", ".codegraph", "只读参考", "node_modules")


def 读命名件(工作树) -> dict:
    """走树读**代码件** ⇒ `{仓内相对路径: 文本}`（跳过只读参考 / 版本库 / 缓存 / 索引库）。

    ★ 2026-10-06：原先走 `命名穷举.读命名件` —— 该模块已随旧命名口径体系退场（那处 import
    会让本模块**整个 ImportError**）。本件自持这一份走树读件：不复用 `命名校验.候选文件` 是
    因为它内部的 `是仓内` 只认**它自身所在的那棵树**的仓根，对**别的**工作树会整枝判成仓外。
    """
    出 = {}
    for 路径 in Path(工作树).rglob("*"):
        if not 路径.is_file() or 路径.suffix not in 代码后缀:
            continue
        if any(段 in 跳过目录 for 段 in 路径.parts):
            continue
        try:
            出[路径.relative_to(工作树).as_posix()] = 路径.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
    return 出


# ── `.名` 成员访问（**只在本件声明了该键时才认**）─────────────────────────────────────
# 依据：实测 2026-10-06 —— 共用扫描器把紧跟 `.` 的一律当「别人家的成员」排除 ⇒ 改对象字面量的键时，
# `对象.名` 的读取**没跟着改** ⇒ 悬空引用（`开着的.盒` / `步卡.卡` / `.能` / `流水条.时` 实测撞过）。
# **安全边界**：只有当 `名` 在**本件**被声明成键/字段（`名:` · `self.名 =` · `{ 名 }` 简写）时，
# 才把 `.名` 当作者起的名字。这条同时挡住 `from .小工具 import`（模块名）· `.start()`（标准库方法）·
# `document.body`（DOM）这类**别人家的成员** —— 实测挡住 `小工具`58 · `start`19 · `end`14 · `key`4 处。
_点读名 = re.compile(r"(?<!\.)\.\s*([A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*)")
# `...名`（JS 展开 / 剩余）里的 `名` **不是**成员访问 —— 但共用扫描器把 `...` 的第三个点当成了 `.`，
# 于是 `...枝` 被整枝漏掉（实测：`支持库树.js` 的 `[...枝.get(...)]` 改一半留一半 ⇒ 悬空引用）。这里补回来。
_展开名 = re.compile(r"\.\.\.\s*([A-Za-z_\u4e00-\u9fff][0-9A-Za-z_\u4e00-\u9fff]*)")


def 本件声明的键(净文本: str, 名集) -> set:
    """`名集` 里**在本件被声明成键/字段**的那些 ⇒ 本件里的 `.名` 点读才算作者的名字。"""
    声明键集 = set()
    for 候选名 in 名集:
        名正则 = re.escape(候选名)
        if (re.search(r"(?<![\w.\"'])" + 名正则 + r"\s*:", 净文本)
                or re.search(r"self\.\s*" + 名正则 + r"\s*=", 净文本)
                or re.search(r"[\{,}]\s*" + 名正则 + r"\s*[,}]", 净文本)):
            声明键集.add(候选名)
    return 声明键集


def 抽可换(净文本: str, 名集) -> list:
    """⇒ `[(名, 位置)]`：常规标识符 **＋** 本件声明的键的 `.名` 点读（**位置去重**）。

    `.名` 那部分是本件对共用扫描器（`命名扫描.抽标识符带位置`）的**局部加宽** —— 不动共用件，
    免得波及判据 ㉒ / 代码地图 / 债名落点（它们要的仍是「排除成员访问」的口径）。
    """
    名位表 = 命名扫描.抽标识符带位置(净文本)
    键集 = 本件声明的键(净文本, 名集)
    已占位 = {位置 for _, 位置 in 名位表}
    for 命中项 in _点读名.finditer(净文本):
        if 命中项.group(1) in 键集 and 命中项.start(1) not in 已占位:
            名位表.append((命中项.group(1), 命中项.start(1)))
    for 命中项 in _展开名.finditer(净文本):
        if 命中项.group(1) in 名集 and 命中项.start(1) not in 已占位:
            名位表.append((命中项.group(1), 命中项.start(1)))
    名位表.sort(key=lambda 名位对: 名位对[1])
    return 名位表


def 扫出现(工作树, 名表) -> dict:
    """走树扫**标识符整词** ⇒ `{路径: {旧名: 处数}}`（面 = `读命名件`）。

    **面与 `验证.py::扫债名落点` 同一份**（同一剥器 + 同一抽法 + 同一制品排除）：只在
    `命名扫描.剥后缀` 后的**标识符位置**上数 ⇒ 注释 / 字符串 / 正则里的整词不算，
    非 `self.` 的 `.名` 成员访问也不算。`路径串区间` 作冗余第二道（字符串已在净文本里抹空）。
    """
    命中表 = {}
    for 路径, 文本 in 读命名件(工作树).items():
        if 是制品产物(路径):
            continue
        净文本 = 命名扫描.剥后缀("." + 路径.rsplit(".", 1)[-1], 文本)
        区间表 = 路径串区间(文本)
        次数表 = {}
        for 名目, 位置 in 抽可换(净文本, 名表):
            if 名目 in 名表 and not _在区间里(位置, 区间表):
                次数表[名目] = 次数表.get(名目, 0) + 1
        if 次数表:
            命中表[路径] = 次数表
    return 命中表


def 换整词(全文, 名对表, 后缀) -> tuple:
    """按**标识符整词**替换 ⇒ `(新全文, {旧名: 换了几处})`。子串不换（`参数表` 不动）。

    **只在剥掉注释与字符串之后的标识符位置上换**（面与 `扫出现` 同一份，见其说明）：
    注释 / 字符串 / 正则里的整词一个字都不动。`路径串区间` 作冗余第二道。
    """
    净文本 = 命名扫描.剥后缀(后缀, 全文)
    区间表 = 路径串区间(全文)
    缓冲, 换数表, 末位 = [], {}, 0
    for 旧名, 位置 in 抽可换(净文本, set(名对表)):
        if 旧名 in 名对表 and not _在区间里(位置, 区间表):
            缓冲.append(全文[末位:位置])
            缓冲.append(名对表[旧名])
            换数表[旧名] = 换数表.get(旧名, 0) + 1
            末位 = 位置 + len(旧名)
    缓冲.append(全文[末位:])
    return "".join(缓冲), 换数表


def 派发(参数表: dict, 仓根) -> tuple:
    """`v1_task` 功能 = 9 的入口。"""
    开工号 = str(参数表.get("开工ID") or "").strip()
    if not 开工号:
        return 2, "缺 `开工ID`（`v1_task` 功能 = 1 登记时返回的那个）"
    连接 = 账本.连账本()
    try:
        开工记录 = 账本.读开工(连接, 开工号)
        if not 开工记录:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记" % 开工号
        if 开工记录["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能再改" % 开工记录["状态"]
        工作树 = Path(开工记录["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再改" % 工作树

        名对表, 错误 = 读名对(参数表.get("改名对"))
        if 错误:
            return 2, 错误
        范围表, 错误 = 读范围(参数表.get("路径范围"), 工作树)
        if 错误:
            return 2, 错误

        # 闸 ④ 新名登记（fail-closed）：名册读不动 ⇒ 拒，绝不当空名册放行。
        try:
            已登记, 例外 = 读名册(工作树)
        except 命名校验.库读不动 as 读不动:
            return 5, ("**拒**（新名登记闸）：读不动规则库 ⇒ fail-closed：%s\n"
                     "修法：在这棵工作树里跑 `python3 开发工具/信息核心/信息核心.py 建库`" % 读不动)
        未登记 = sorted({新名 for 新名 in 名对表.values()
                     if 新名 not in 已登记 and 新名 not in 例外})
        if 未登记:
            return 5, ("**拒**（新名登记闸）：这些新名不在库 `命名登记`（**状态=合格**）"
                     "（也不在 `命名例外`）⇒ 先登记：\n  %s\n（在这棵工作树里跑："
                     "`python3 开发工具/信息核心/信息核心.py 登记 <名> …`）" % "\n  ".join(未登记))

        命中表 = 扫出现(工作树, set(名对表))
        if not 命中表:
            return 2, "这些旧名在命名面里 0 处：%s" % " · ".join(名对表)
        待改表, 越区表 = {}, {}
        for 路径, 次数表 in 命中表.items():
            (待改表 if 路径.split("/", 1)[0] in 范围表 else 越区表)[路径] = 次数表
        if 越区表 and not bool(参数表.get("越区确认")):
            return 3, ("**拒**（越区闸）：旧名在给定范围 %s **之外**也出现 ⇒ 要么把那些顶层区加进"
                     " `路径范围`，要么显式 `越区确认` = 真（只改范围内、范围外留着）：\n%s"
                     % (" · ".join(sorted(范围表)), "\n".join(
                         "  %s：%s" % (路径, " · ".join("%s×%d" % (名目, 处数) for 名目, 处数 in sorted(次数表.items())))
                         for 路径, 次数表 in sorted(越区表.items()))))
        if not 待改表:
            return 2, "给定范围 %s 里 0 处（旧名只在范围外出现）" % " · ".join(sorted(范围表))

        # 闸 ② 认领集：待改件必须全已认领（未认领 ⇒ 报出来让 agent 功能=2 补）。
        认领表 = 账本.读认领(连接, 开工号)
        未认领 = sorted(路径 for 路径 in 待改表 if 路径 not in 认领表)
        if 未认领:
            return 3, ("**拒**（认领闸）：这些件要改、但不在开工 %s 的认领集里 ⇒ 先 `v1_task` "
                     "功能 = 2 补认领，再重跑本口：\n  %s" % (开工号, "\n  ".join(未认领)))

        # 闸 ③ 指纹对账（同时是绕过检测）：复用 `修改.对账`，不另写一套。
        对得上表, 变过表 = 对账(工作树, {路径: 认领表[路径] for 路径 in 待改表})
        if 变过表:
            return 3, ("**拒**（指纹闸）：这些件被绕过 MCP 改过（盘上指纹 ≠ 账本指纹）：\n%s\n"
                     "一个字节都没写。用 `v1_task` 功能 = 2 重报这些件的指纹（它会重读盘）再发起。"
                     % "\n".join("  %s：账本 %s → 盘上 %s" % (路径, 键值对[0] or "（无）", 键值对[1] or "（件没了）")
                              for 路径, 键值对 in sorted(变过表.items())))

        # 禁改面：生成物 / 冻结公开面 —— 拒，并说明正路。
        禁改表 = {}
        for 路径 in 待改表:
            原因 = 禁改原因(路径, (工作树 / 路径).read_text(encoding="utf-8", newline="\n"))
            if 原因:
                禁改表[路径] = 原因
        if 禁改表:
            return 3, ("**拒**（禁改面）：这些件不许手改：\n%s"
                     % "\n".join("  %s：%s" % (路径, 原因) for 路径, 原因 in sorted(禁改表.items())))

        完成表, 失败说明 = [], ""
        for 路径, 次数表 in sorted(待改表.items()):
            件路径 = 工作树 / 路径
            写前指纹 = 对得上表.get(路径) or 文件指纹(str(件路径))
            全文 = 件路径.read_text(encoding="utf-8", newline="\n")
            新全文, 换数表 = 换整词(全文, 名对表, "." + 路径.rsplit(".", 1)[-1])
            if 新全文 == 全文:
                完成表.append("%s（0 处）" % 路径)
                continue
            错误 = _写文件(件路径, 新全文)
            if 错误:
                失败说明 = "%s：%s" % (路径, 错误)
                break
            写后指纹 = 文件指纹(str(件路径))
            账本.写回指纹(连接, 开工号, 路径, 写后指纹)
            账本.记改动(连接, 开工号, 路径, 档名, 写前指纹, 写后指纹)
            完成表.append("%s（%s）" % (路径, " · ".join("%s×%d" % (名目, 处数) for 名目, 处数 in sorted(换数表.items()))))

        退出码, 说明 = 同步索引(工作树)
        输出行表 = ["%s：改了 %d/%d 件 —— %s" % (开工号, len(完成表), len(待改表),
                                            " · ".join(完成表) or "（无）"),
                 "索引：%s" % 说明]
        if 退出码 != 0:
            输出行表.append("**索引没刷上（退出码 %d）** ⇒ 索引没跟上，下次 `v1_symbol` 会读到旧行号；"
                        "修法：`python3 开发工具/代码地图.py 建`" % 退出码)
        if 越区表:
            输出行表.append("★ 范围外**没改**（已显式确认）：%s" % " · ".join(
                "%s（%s）" % (路径, " · ".join("%s×%d" % (名目, 处数) for 名目, 处数 in sorted(次数表.items())))
                for 路径, 次数表 in sorted(越区表.items())))
        if 失败说明:
            输出行表.append("**%s**" % 失败说明)
            if 完成表:
                输出行表.append("（前面 %d 件已经写进盘了 —— 本口逐件写，不是整批回滚）" % len(完成表))
            return 4, "\n".join(输出行表)
        if 退出码 != 0:
            return 1, "\n".join(输出行表)
        return 0, "\n".join(输出行表)
    finally:
        连接.close()
