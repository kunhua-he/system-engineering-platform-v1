def 读名对(命令行参数) -> tuple:
    """`改名对` 参数 ⇒ `({旧名: 新名}, 错误)`。空 / 形状不对 / 同名给两个目标 ⇒ 拒。"""
    if not isinstance(命令行参数, list) or not 命令行参数:
        return {}, "缺 `改名对`（形如 `[{\"旧名\": \"旧例\", \"新名\": \"新例\"}]`，可多对）"
    名对表 = {}
    for 序号, 一对 in enumerate(命令行参数, 1):
        if not isinstance(一对, dict):
            return {}, "改名对第 %d 条要是对象 `{旧名, 新名}`" % 序号
        旧名 = str(一对.get("旧名") or "").strip()
        新名 = str(一对.get("新名") or "").strip()
        if not 旧名 or not 新名:
            return {}, "改名对第 %d 条缺 `旧名` 或 `新名`" % 序号
        if 旧名 == 新名:
            return {}, "改名对第 %d 条：旧名与新名一样 ⇒ 空转，不写" % 序号
        if 旧名 in 名对表 and 名对表[旧名] != 新名:
            return {}, "同一个旧名 `%s` 给了两个新名 ⇒ 拒（一次一个目标）" % 旧名
        名对表[旧名] = 新名
    return 名对表, ""


def 读范围(命令行参数, 工作树) -> tuple:
    """`路径范围` 参数 ⇒ `(顶层区集合, 错误)`。空 / 不是工作树里的顶层目录 ⇒ 拒。"""
    if not isinstance(命令行参数, list) or not 命令行参数:
        return set(), "缺 `路径范围`（顶层区名，如 `[\"对外接口面\", \"前端呈现\"]`）"
    范围表 = {str(区名).strip() for 区名 in 命令行参数 if str(区名 or "").strip()}
    if not 范围表:
        return set(), "`路径范围` 是空的（要至少一个顶层区）"
    不在 = sorted(区名 for 区名 in 范围表 if not (工作树 / 区名).is_dir())
    if 不在:
        return set(), "这些顶层区在工作树里不是目录：%s" % " · ".join(不在)
    return 范围表, ""


def 读文件范围(命令行参数, 工作树) -> tuple:
    """`文件范围` 参数 ⇒ `(仓内相对路径集合, 错误)`。留空 ⇒ `(None, "")`（= 不按件收窄）。"""
    if 命令行参数 is None or (isinstance(命令行参数, list) and not 命令行参数):
        return None, ""
    if not isinstance(命令行参数, list):
        return None, "`文件范围` 要是路径表（仓内相对路径），收到 %s" % type(命令行参数).__name__
    件范围 = {str(路径).strip() for 路径 in 命令行参数 if str(路径 or "").strip()}
    不在 = sorted(路径 for 路径 in 件范围 if not (工作树 / 路径).is_file())
    if 不在:
        return None, "这些件在工作树里不是文件：%s" % " · ".join(不在)
    return 件范围, ""


def 派发(参数表: dict, 仓根) -> tuple:
    """`v1_task` 功能 = 9 的入口。"""
    开工号 = str(参数表.get("开工ID") or "").strip()
    if not 开工号:
        return 2, "缺 `开工ID`（`v1_task` 功能 = 1 登记时返回的那个）"
    连接 = 账本.连账本()
    try:
        开工记录 = 账本.读开工(连接, 开工号)
        if not 开工记录:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记" % 开工号
        if 开工记录["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能再改" % 开工记录["状态"]
        工作树 = Path(开工记录["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再改" % 工作树

        名对表, 错误 = 读名对(参数表.get("改名对"))
        if 错误:
            return 2, 错误
        范围表, 错误 = 读范围(参数表.get("路径范围"), 工作树)
        if 错误:
            return 2, 错误
        件范围, 错误 = 读文件范围(参数表.get("文件范围"), 工作树)
        if 错误:
            return 2, 错误

        # 闸 ④ 新名登记（fail-closed）：名册读不动 ⇒ 拒，绝不当空名册放行。
        try:
            已登记, 例外 = 读名册(工作树)
        except 表定义.库读不动 as 读不动:
            return 5, ("**拒**（新名登记闸）：读不动规则库 ⇒ fail-closed：%s\n"
                     "修法：在这棵工作树里跑 `python3 开发工具/信息核心/信息核心.py 建库`" % 读不动)
        未登记 = sorted({新名 for 新名 in 名对表.values()
                     if 新名 not in 已登记 and 新名 not in 例外})
        if 未登记:
            return 5, ("**拒**（新名登记闸）：这些新名不在库 `命名登记`（**状态=合格**）"
                     "（也不在 `命名例外`）⇒ 先登记：\n  %s\n（在这棵工作树里跑："
                     "`python3 开发工具/信息核心/信息核心.py 登记 --名字 <名> --语义 <语义> "
                     "--模式 对象+说明 --来源 新定义`（该子命令只吃具名参））" % "\n  ".join(未登记))

        冻结名集 = 读冻结字段名(工作树)  # 方案 A：白名单放行跨件 `.名`（读不到 = 空集，退回旧行为）
        命中表 = 扫出现(工作树, set(名对表), 冻结名集)
        if not 命中表:
            return 2, "这些旧名在命名面里 0 处：%s" % " · ".join(名对表)
        待改表, 越区表 = {}, {}
        for 路径, 次数表 in 命中表.items():
            (待改表 if 路径.split("/", 1)[0] in 范围表 else 越区表)[路径] = 次数表
        件外表 = {}
        if 件范围 is not None:
            for 路径 in [路径 for 路径 in 待改表 if 路径 not in 件范围]:
                件外表[路径] = 待改表.pop(路径)
        if 越区表 and not bool(参数表.get("越区确认")):
            return 3, ("**拒**（越区闸）：旧名在给定范围 %s **之外**也出现 ⇒ 要么把那些顶层区加进"
                     " `路径范围`，要么显式 `越区确认` = 真（只改范围内、范围外留着）：\n%s"
                     % (" · ".join(sorted(范围表)), "\n".join(
                         "  %s：%s" % (路径, " · ".join("%s×%d" % (旧名字, 处数) for 旧名字, 处数 in sorted(次数表.items())))
                         for 路径, 次数表 in sorted(越区表.items()))))
        if not 待改表:
            return 2, "给定范围 %s 里 0 处（旧名只在范围外出现）" % " · ".join(sorted(范围表))

        # 闸 ② 认领集：待改件必须全已认领（未认领 ⇒ 报出来让 agent 功能=2 补）。
        认领表 = 账本.读认领(连接, 开工号)
        未认领 = sorted(路径 for 路径 in 待改表 if 路径 not in 认领表)
        if 未认领:
            return 3, ("**拒**（认领闸）：这些件要改、但不在开工 %s 的认领集里 ⇒ 先 `v1_task` "
                     "功能 = 2 补认领，再重跑本口：\n  %s" % (开工号, "\n  ".join(未认领)))

        # 闸 ③ 指纹对账（同时是绕过检测）：复用 `修改.对账`，不另写一套。
        对得上表, 变过表 = 对账(工作树, {路径: 认领表[路径] for 路径 in 待改表})
        if 变过表:
            return 3, ("**拒**（指纹闸）：这些件被绕过 MCP 改过（盘上指纹 ≠ 账本指纹）：\n%s\n"
                     "一个字节都没写。用 `v1_task` 功能 = 2 重报这些件的指纹（它会重读盘）再发起。"
                     % "\n".join("  %s：账本 %s → 盘上 %s" % (路径, 键值对[0] or "（无）", 键值对[1] or "（件没了）")
                              for 路径, 键值对 in sorted(变过表.items())))

        # 禁改面：生成物 / 冻结公开面 —— 拒，并说明正路。
        禁改表 = {}
        for 路径 in 待改表:
            失败原因 = 禁改原因(路径, (工作树 / 路径).read_text(encoding="utf-8", newline="\n"))
            if 失败原因:
                禁改表[路径] = 失败原因
        if 禁改表:
            return 3, ("**拒**（禁改面）：这些件不许手改：\n%s"
                     % "\n".join("  %s：%s" % (路径, 失败原因) for 路径, 失败原因 in sorted(禁改表.items())))

        # 闸 ⑤ 撞名预检（整批 fail-closed）：新名若**已在同一件里**出现 ⇒ 改完一名两用。
        #   依据：实测 2026-10-06 —— `读盘.py` 里 `r1 → 首遍读数`，而该件本就有 `首遍读数`。
        #   只看**命名面**（剥注释与字符串）⇒ 注释/串里的同形字不算。
        撞名表 = {}
        for 路径 in 待改表:
            净文本 = 命名扫描.剥后缀("." + 路径.rsplit(".", 1)[-1],
                               (工作树 / 路径).read_text(encoding="utf-8", errors="ignore"))
            本件名 = set(命名扫描.抽标识符(净文本))
            命中 = sorted({名对表[旧名] for 旧名 in 待改表[路径] if 名对表[旧名] in 本件名})
            if 命中:
                撞名表[路径] = 命中
        if 撞名表:
            return 3, ("**拒**（撞名预检）：这些件里**新名已经存在** ⇒ 改完会一名两用：\n%s\n"
                     "一个字节都没写。要么换个新名，要么先把件里既有的那个名改掉（拆成两次调用）。"
                     % "\n".join("  %s：%s" % (路径, " · ".join(命中))
                               for 路径, 命中 in sorted(撞名表.items())))

        完成表, 失败说明 = [], ""
        for 路径, 次数表 in sorted(待改表.items()):
            件路径 = 工作树 / 路径
            写前指纹 = 对得上表.get(路径) or 文件指纹(str(件路径))
            全文 = 件路径.read_text(encoding="utf-8", newline="\n")
            新全文, 换数表 = 换整词(全文, 名对表, "." + 路径.rsplit(".", 1)[-1], 冻结名集)
            if 新全文 == 全文:
                完成表.append("%s（0 处）" % 路径)
                continue
            错误 = _写文件(件路径, 新全文)
            if 错误:
                失败说明 = "%s：%s" % (路径, 错误)
                break
            写后指纹 = 文件指纹(str(件路径))
            账本.写回指纹(连接, 开工号, 路径, 写后指纹)
            账本.记改动(连接, 开工号, 路径, 档名, 写前指纹, 写后指纹)
            完成表.append("%s（%s）" % (路径, " · ".join("%s×%d" % (旧名字, 处数) for 旧名字, 处数 in sorted(换数表.items()))))

        退出码, 说明 = 同步索引(工作树)
        输出行表 = ["%s：改了 %d/%d 件 —— %s" % (开工号, len(完成表), len(待改表),
                                            " · ".join(完成表) or "（无）"),
                 "索引：%s" % 说明]
        if 退出码 != 0:
            输出行表.append("**索引没刷上（退出码 %d）** ⇒ 索引没跟上，下次 `v1_symbol` 会读到旧行号；"
                        "修法：`python3 开发工具/代码地图.py 建`" % 退出码)
        if 件外表:
            输出行表.append("★ `文件范围` 外**没改**（有意留着的那一半语义群）：%s" % " · ".join(
                "%s（%s）" % (路径, " · ".join("%s×%d" % (项名, 处数) for 项名, 处数 in sorted(次数表.items())))
                for 路径, 次数表 in sorted(件外表.items())))
        if 越区表:
            输出行表.append("★ 范围外**没改**（已显式确认）：%s" % " · ".join(
                "%s（%s）" % (路径, " · ".join("%s×%d" % (旧名字, 处数) for 旧名字, 处数 in sorted(次数表.items())))
                for 路径, 次数表 in sorted(越区表.items())))
        if 失败说明:
            输出行表.append("**%s**" % 失败说明)
            if 完成表:
                输出行表.append("（前面 %d 件已经写进盘了 —— 本口逐件写，不是整批回滚）" % len(完成表))
            return 4, "\n".join(输出行表)
        if 退出码 != 0:
            return 1, "\n".join(输出行表)
        return 0, "\n".join(输出行表)
    finally:
        连接.close()
