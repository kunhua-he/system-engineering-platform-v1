# -*- coding: utf-8 -*-
r"""批量改名 —— `v1_task` 功能 = 9：一次把**同一个名**改到给定范围里的**全部出现处**。

**为什么要有它**（未完成 271 号实测）：改名债还剩 75 个跨区名 / 4495 处，而 `v1_edit` 一次只改
一处、且要求 `旧内容` 在文件里**唯一** ⇒ 一个名在一个文件里出现 391 次就要 391 次调用。这个
量级用 `v1_edit` 清不掉。本口是「同一改动一次落多处」的**正当形态**：它**不绕四道闸** ——
① 开工在进行中 ② 待改件全在认领集 ③ 逐件账本指纹 == 盘上指纹（同 `修改.对账`，这一条同时是
绕过检测）④ 新名已在库 `命名登记`（**状态=合格**）或 `命名例外` 登记（fail-closed）
⑤ **撞名预检**：新名不得已存在于**待改的同一件**里（否则改完一名两用）—— 整批拒、一个字节不写；
并逐件把写前/写后指纹记进账本 `改动` 表
（复用 `账本.记改动`）。裁决见库 `规则` 表 `账本口径-3`。

**命名面在 `改名面.py`**（判据 ⑲ 拆件，2026-10-06）：本件是**口**（参数校验 + 五道闸 + 逐件写盘），
「怎么认标识符、怎么换」那一半在 `改名面.py` —— 两者**同一份口径**（同一剥器 + 同一抽法 +
同一制品排除），注释 / 字符串 / 正则里的整词一个字都不换。

**面**：走树读件 = `改名面.读命名件`（跳过只读参考 / 版本库 / 缓存 / 索引库）。
**不改产物**（件头自称产物禁改 ⇒ 拒，改源 + 重跑生成器）· **不碰冻结公开面**（`契约声明/`
的件头自称冻结 ⇒ 拒）。两条都**只扫件头**且要求**件头自称** —— 讲别件 / 在代码里发射标记
都不算（否则整批 fail-closed 误拦）。禁改面判据住共用件 `禁改面.py`（`v1_edit` 同调这一份，2026-10-05）。
**面只到代码件**（`.rs`/`.py`/`.js`/`.ts`/`.vue`）—— `.json`/`.md` 散文里的同形字不在面内（如实登记）。
"""

