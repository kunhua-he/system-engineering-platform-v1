"""查询渲染 —— `v1_task` 查询的**纯文本拼装**（诊断 · 单号明细 · 列表）。

`开工.py` 顶 400 行硬数（判据 ⑲）⇒ 照先例「入口转出口」把**渲染**挪出来：`开工.查询开工` 只留
取数与分档，拼字全在本件。本件**不读账本、不写盘、不翻状态** —— 入参全是调用方已取好的数据。

噪声口径（2026-10-08 定）：单号查询**只给本号**（不附全局诊断）；全局 / 关键词查询保留诊断，
但「工作树仍在」默认**折成计数**（`展开` = 真 才逐号列）。条数上限**单定义**在本件。
"""

# 条数上限：**单定义**（`开工.查询开工` 与自检样本都读这里，别处不许再写 20）
结果上限默认 = 20
结果上限最大 = 500


def 规范化上限(原值) -> tuple:
    """`(上限, 错误说明)` —— 没给 ⇒ 默认；给了要**正整数且不超上限**，否则错误说明非空（退出码 2）。"""
    if 原值 is None or (isinstance(原值, str) and not 原值.strip()):
        return 结果上限默认, ""
    if isinstance(原值, bool):
        return 0, "`上限` 要是 1..%d 的整数，收到逻辑值 %r" % (结果上限最大, 原值)
    try:
        条数值 = int(原值)
    except (TypeError, ValueError):
        return 0, "`上限` 要是 1..%d 的整数，收到 %r" % (结果上限最大, 原值)
    if 条数值 < 1 or 条数值 > 结果上限最大:
        return 0, "`上限` 要在 1..%d 之间，收到 %r" % (结果上限最大, 原值)
    return 条数值, ""


def 拼诊断(僵尸表, 树在表, 展开: bool = False) -> str:
    """全局诊断：僵尸开工逐号列（量小）+ 「工作树仍在」默认折成计数、`展开` 才逐号列。

    噪声实证（2026-10-08）：关键词连查三次各拿同一大段 100+ 棵在树号 ⇒ 默认折成计数。
    """
    行表 = []
    if 僵尸表:
        行表.append("★ 僵尸开工 %d 条（状态未释放、却工作树与支线都不在）⇒ 功能 = 4 销：\n    %s"
                 % (len(僵尸表), " · ".join(僵尸表)))
    else:
        行表.append("（无僵尸开工）")
    if 树在表:
        分组 = {}
        for 数据行 in 树在表:
            分组.setdefault(数据行["状态"], []).append(数据行["开工号"])
        汇总 = " · ".join("%s %d 条" % (状态, len(号表)) for 状态, 号表 in sorted(分组.items()))
        表头行 = ("★ 工作树仍在的开工 %d 条（%s）—— 「保留待合」：树在 = 支线未清，"
                "**不代表清理漏**；是否已合主干须实证；核已合且净树后由收口方 功能 = 4 收口"
                "（工具不自动清）" % (len(树在表), 汇总))
        if 展开:
            行表.append(表头行 + "：\n    " + " · ".join(数据行["开工号"] for 数据行 in 树在表))
        else:
            行表.append(表头行 + "。\n    （默认折叠：要看逐号列表，查询传 `展开` = 真）")
    return "\n".join(行表)


def 拼列表(记录表) -> str:
    """最近 / 命中列表：一行一条（开工号 · 时间 · 状态 · 工作内容前 48 字）。"""
    return "\n".join("  %s  %s  %s  %s" % (
        数据行["开工号"], 数据行["开工时间"][:16], 数据行["状态"], 数据行["工作内容"][:48])
        for 数据行 in 记录表)


def 拼单号明细(开工记录, 认领表, 改动表, 分支: str = "", 树头: str = "") -> str:
    """单号查询：**只给本号**完整状态（不附全局诊断）。分支 / 树头 由调用方现读传入。"""
    行表 = [
        "开工号 %s · %s" % (开工记录["开工号"], 开工记录["状态"]),
        "工作内容：%s" % 开工记录["工作内容"],
        "支线 %s · 工作树 %s" % (开工记录["分支名"], 开工记录["工作树"]),
        ("分支 HEAD：%s %s" % (分支 or "（无分支）", 树头 or "（无提交）")
         if (分支 or 树头) else "分支 HEAD：（读不到：工作树不在，或不是 Git 树）"),
        "开工 %s%s" % (开工记录["开工时间"],
                   " · 释放 %s" % 开工记录["释放时间"] if 开工记录["释放时间"] else ""),
        "认领 %d 件：%s" % (len(认领表), " · ".join(sorted(认领表)) or "（空）"),
        "改动 %d 次：%s" % (len(改动表), " · ".join(
            "%s(%s)" % (一条改动["路径"], 一条改动["功能"]) for 一条改动 in 改动表) or "（无）"),
    ]
    return "\n".join(行表)
