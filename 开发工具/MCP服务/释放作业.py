释放具名 = "释放"              # `作业.具名` 里的这一档（找在途 / 判幂等只认它）
释放同步秒 = 4.0              # 前台有界窗口（≤5 秒：同步路硬顶；不靠「加长同步等待」凑预算）
启动握手秒 = 3                # 起作业的握手（`作业.启动握手上限秒` = 5 以内）
释放入口文件 = "开发工具/MCP服务/释放入口.py"
在途扫描条数 = 200             # 找在途作业时的有界取数（非终态在前，够覆盖）
日志尾行数 = 25               # 回执里附的作业日志尾行数（有界）
推送态前缀 = "推送态："          # `释放主体` 落的**推送态标记行**前缀（前台回执据此逐字转述）


def 取释放入口(仓根, 工作树):
    """释放入口脚本 ⇒ `(路径 或 None, 说明)`。**优先仓根**（正式合并后全腿共用的那一份），
    退**工作树**（正式合并前的自举窗口）—— 报出实际用了哪份（不静默）。
    """
    正式 = Path(仓根) / 释放入口文件
    if 正式.is_file():
        return 正式, "释放入口：仓根那份（%s）" % 正式
    自举 = Path(工作树) / 释放入口文件
    if 自举.is_file():
        return 自举, "释放入口：**工作树**那份（%s）—— 仓根尚无该件（正式合并前的自举窗口）" % 自举
    return None, "释放入口不在：仓根 %s · 工作树 %s" % (正式, 自举)


def 释放命令(仓根, 工作树, 开工号, 跳过验证, 推送):
    """拼释放作业的命令行 ⇒ `(命令文本 或 None, 说明)`。绝对入口 + 开工号 + 仓根 + 旗标。"""
    入口路径, 说明 = 取释放入口(仓根, 工作树)
    if 入口路径 is None:
        return None, 说明
    命令表 = [sys.executable, str(入口路径), 开工号, str(仓根)]
    if 跳过验证:
        命令表.append("--跳过验证")
    if 推送:
        命令表.append("--推送")
    return shlex.join(命令表), 说明


def 找本开工释放作业(开工号):
    """本开工**在途**（非终态）的释放作业行 ⇒ dict 或 `None`。**查询幂等**的取数口。"""
    连接 = 作业账本.连账本()
    try:
        行表 = 作业账本.列作业(连接, 在途扫描条数)
    finally:
        连接.close()
    for 记录行 in 行表:
        if (记录行.get("开工ID") == 开工号 and 记录行.get("具名") == 释放具名
                and 记录行.get("状态") in 作业账本.非终态集):
            return 记录行
    return None


def 起释放作业(仓根, 工作树, 开工号, 跳过验证, 推送):
    """起一条释放后台作业（复用 `作业.起作业`，不新增工具）⇒ `(退出码, 输出文本)`。"""
    from .作业 import 起作业
    命令文本, 说明 = 释放命令(仓根, 工作树, 开工号, 跳过验证, 推送)
    if 命令文本 is None:
        return 1, 说明
    退出码, 输出文本 = 起作业(命令文本, 开工号, 启动握手秒, 仓根, 释放具名, 开工号)
    return 退出码, 说明 + "\n" + 输出文本


def 等释放作业(任务ID, 等秒):
    """有界等释放作业到终态（复用 `门禁.有界等作业` 同一份轮询）⇒ 作业行 或 `None`。"""
    from .门禁 import 有界等作业
    return 有界等作业(任务ID, 等秒)


def 读日志尾行(任务ID):
    """作业日志尾（有界，复用 `作业.读日志片段`）⇒ 行表；读不到给一行说明。"""
    from .作业 import 读日志片段
    日志码, 日志文 = 读日志片段(任务ID, 0, False)
    if 日志码 != 0:
        return ["（作业日志读不到：%s）" % str(日志文).strip()[:200]]
    有效行表 = [源码行 for 源码行 in 日志文.splitlines() if 源码行.strip() and "─" not in 源码行]
    return ["—— 释放作业标准输出尾 ——"] + 有效行表[-日志尾行数:]


def 读推送态(任务ID):
    """从作业日志里取**推送态标记行**的值（`释放主体` 落的）⇒ 文本 或 `None`（没落 / 读不到）。

    **为什么读日志、不看本次调用给的 `推送`**：查询幂等档复用**在途**作业时，作业的推送态由
    **更早那次调用**决定，与本次调用给的 `推送` 未必同值 —— 只有作业自身落的标记才是真值。
    """
    from .作业 import 读日志片段
    日志码, 日志文 = 读日志片段(任务ID, 0, False)
    if 日志码 != 0:
        return None
    for 标记行 in 日志文.splitlines():
        if 标记行.startswith(推送态前缀):
            return 标记行.strip()[len(推送态前缀):]
    return None


def 拼释放回执(开工号, 任务ID, 作业行, 来源说明, 推送):
    """前台回执：终态 ⇒ 看退出码（0 = 真成功；非 0 = 真失败，**拒提交**）；未终态 ⇒
    `待取作业码` + **运行中任务ID**（**不是失败**）。**逐字报推送态**（旧缺陷：回执不报这一项，
    调用方看不见本次到底推没推远端 —— 2026-10-08 三次误推远端都这么发生）。"""
    终结 = 作业行 is not None and 作业行["状态"] in 作业账本.终态集
    行表 = ["%s 释放（后台作业路）：%s" % (开工号, 来源说明),
           "任务ID：%s · 状态：%s · 开工ID：%s"
           % (任务ID, 作业行["状态"] if 作业行 else "（未落行）",
              作业行["开工ID"] if 作业行 else "（未记录）")]
    if not 终结:
        行表.append("★ 推送态：待定（作业未到终态）—— 到终态后本行逐字报"
                 "「本次已推远端（推送=真）/ 本次未推远端（推送=假）」")
    elif 作业行["退出码"] != 0:
        行表.append("★ 推送态：本次未推远端（释放未到推送步）")
    else:
        行表.append("★ 推送态：%s" % (读推送态(任务ID)
                  or ("本次已推远端（推送=真）" if 推送 else "本次未推远端（推送=假）")))
    if not 终结:
        行表 += [
            "★ 这是**运行中**（前台有界窗口 %g 秒内没跑完），**不是失败** —— 长活不许被 5 秒强杀，"
            "也不据此判业务失败。" % 释放同步秒,
            "★ 取终态：`v1_job` 操作 `status` / `log`（参数 `任务ID`）；或**再调一次本操作**"
            "（**查询幂等**：已有在途释放作业就不再起第二条验证）。",
            "★ 跨过效率阈值已自动提交一次性能反馈（幂等）；后台一直跑到真实终态才提交 / 翻状态。",
        ]
        return 待取作业码, "\n".join(行表)
    退出码 = 作业行["退出码"]
    if 退出码 == 0:
        行表.append("★ 后台已到**真实终态且成功**（验证 + pre-commit 钩子真跑过）：提交与状态翻转都已完成。")
        return 0, "\n".join(行表)
    行表.append("★ 后台已到**真实终态且失败**（退出码 %s）⇒ **拒提交**：状态留「进行中」，认领未清。" % 退出码)
    return 1, "\n".join(行表 + 读日志尾行(任务ID))


def 派发释放(仓根, 开工号, 强制=False, 跳过验证=False, 推送=False):
    """`v1_task` 功能 3 的入口：便宜前置 → **查询幂等** → 起后台作业 → 前台有界等。

    前置只做**便宜**的（状态 · 工作树在 · 强制）—— 贵的（钩子 · 对账 · 漂移 · 越界）在**后台**做：
    它们大多在一两秒内出结论，前台窗口照样看得见；看不见就是「运行中」，不是失败。

    **`推送` 默认假**（2026-10-08 改）：用户口径是「子代理只提交本地，主会话合并到主线后才推远端」
    —— 旧默认真与它相反，实测三次误推远端（`origin/腿/v1-100648` / `v1-100642` / `v1-100675`）。
    要推就**显式**传 `推送=true`（主会话合并推送用）。
    """
    if not isinstance(推送, bool):
        return 2, "`推送` 要是逻辑型；**默认假**（只本地提交），显式真才推远端"
    连接 = 账本.连账本()
    try:
        开工记录 = 账本.读开工(连接, 开工号)
        if not 开工记录:
            return 1, "没有这条开工：%s" % 开工号
        if 开工记录["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能重复释放" % 开工记录["状态"]
        if 强制:
            账本.置状态(连接, 开工号, 账本.状态_已释放)
            return 0, ("%s **强制释放**：没跑验证、没提交、没推。工作树留着没动 —— 里面的活要人来处置。"
                     % 开工号)
        工作树 = Path(开工记录["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再释放（别把状态改了、活却找不回）" % 工作树
    finally:
        连接.close()

    # ── 查询幂等：已有在途释放作业 ⇒ 只观察，不再起第二条（重复调用是**查询**，不是第二次验证）──
    在途 = 找本开工释放作业(开工号)
    if 在途 is not None:
        作业行 = 等释放作业(在途["任务ID"], 释放同步秒)
        return 拼释放回执(开工号, 在途["任务ID"], 作业行,
                    "复用本开工**在途**释放作业（查询幂等，不重启验证）", 推送)

    # ── 起后台作业：前置 + 验证 + 提交 + 推 + 翻状态整条都在后台（状态在真终态前不翻）──
    开始 = time.monotonic()
    启动码, 启动文 = 起释放作业(仓根, 工作树, 开工号, 跳过验证, 推送)
    配对 = re.search(r"任务ID：([0-9a-f]{32})", 启动文)
    if not 配对:
        # 真起不来（预算读不到 / 入口不在 / 工作进程起不了）⇒ 回执就是它，不假装跑过。
        # ★ **不拿 `启动码` 短路**：作业跑得太快（在 `起作业` 的握手里就已到终态）时 `起作业`
        #   也会回 1 —— 那不是「起不来」，必须照常去读终态；否则「真终态失败」会被误报成
        #   「启动失败」（实测在长样本全套里撞到过）。
        return (启动码 or 1), 启动文
    任务ID = 配对.group(1)
    窗口余量 = max(0.0, 释放同步秒 - (time.monotonic() - 开始))
    作业行 = 等释放作业(任务ID, 窗口余量)
    if 作业行 is None:
        return 1, "起作业后读不到作业行（账本未落）⇒ 用 `v1_job` status 核：%s" % 任务ID
    return 拼释放回执(开工号, 任务ID, 作业行,
                 启动文.splitlines()[0] if 启动文 else "释放作业（新起）", 推送)


def 释放主体(仓根, 开工号, 跳过验证=False, 推送=False):
    """**唯一一份**真释放实现（跑在后台作业进程里，也供样本直调）⇒ `(退出码, 输出文本)`。

    顺序固定：前置（状态 · 工作树 · 钩子 · 对账 · 漂移 · 越界）→ 验证 →
    提交（pre-commit 钩子真跑）→ 推（**仅 `推送=true`**）→ **翻状态**。**真验证 + 钩子完成之前
    不翻状态、不清认领**；任一步不过 ⇒ 立刻返回，状态留「进行中」。
    """
    连接 = 账本.连账本()
    try:
        开工记录 = 账本.读开工(连接, 开工号)
        if not 开工记录:
            return 1, "没有这条开工：%s" % 开工号
        if 开工记录["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能重复释放" % 开工记录["状态"]
        工作树 = Path(开工记录["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再释放（别把状态改了、活却找不回）" % 工作树
        退出码, 输出文本 = 检查提交门禁(工作树)
        if 退出码 != 0:
            return 1, 输出文本

        改动路径表 = sorted({一条改动["路径"] for 一条改动 in 账本.读改动(连接, 开工号)})
        源件表 = 账本.源件路径集(连接, 开工号)
        对得上表, 变过表, 放行表 = 对账_除源件(工作树, 账本.读认领(连接, 开工号), 源件表)
        退出码, 说明 = 释放前漂移检查(连接, 工作树, 开工号, 变过表)
        if 退出码:
            return 1, 说明
        退出码, 变更表 = 变更路径表(工作树)
        if 退出码 != 0:
            return 1, "查不清盘上动了什么，不敢提交：\n%s" % 变更表
        越界表 = [路径 for 路径 in 变更表 if 路径 not in 改动路径表]
        if 越界表:
            越界说明 = ("盘上这些件动了，但不在改动表里（没走过 v1_edit）⇒ 无法释放：\n  %s\n"
                     "处置：撤掉改动走 v1_edit；**生成物**（生成器产出）请用 功能=5 记账；"
                     "门禁/构建的副产物请确认后手工处置。" % " · ".join(sorted(set(越界表))))
            自错行 = 越界归因(连接, 工作树, 开工号, 越界表)
            if 自错行:
                越界说明 += "\n" + 自错行
            return 1, 越界说明

        # 空改已合腿走主干门禁（2026-10-08 修 · 旧树缺 `复跑.py` 致 ImportError 永拒）：
        # 盘上无改动（空改）才可能有「成果已在主干」一说；有改动就走原路（校验树 = 本树）。
        走主干 = 已合净 = 归属对 = False
        空改判据 = []
        if not 变更表:
            走主干, 已合净, 归属对, 空改判据 = 空改门禁.判主干空改腿(
                连接, 仓根, 开工号, 账本.读开工(连接, 开工号))
        验证树 = 仓根 if 走主干 else 工作树


        if not 跳过验证:
            退出码, 输出文本, 复跑过 = 跑验证(验证树 or 工作树)
            if 退出码 != 0:
                有效行表 = [源码行 for 源码行 in 输出文本.splitlines()
                        if 源码行.strip() and "─" not in 源码行]
                失败行 = ("门禁没过（退出码 %d）⇒ **无法释放**（不提交、不推）。逐条读数：\n%s"
                        % (退出码, "\n".join(有效行表[-日志尾行数:])))
                if 复跑过:
                    失败行 += ("\n（已自动复跑一次仍红：若是**负载红**（闸 0 撞效率硬顶、非判据坏）"
                            "⇒ 等负载降重跑；或走 **功能 = 7**（跳工具层闸 0，提交门禁照跑）。"
                            "若是判据真红 ⇒ 改代码，不靠重跑变绿。）")
                return 1, 失败行

        # 改动历史用于越界检测；暂存只取盘上存在或 Git 已跟踪的路径。
        路径表 = 改动路径表
        if 路径表:
            退出码, 输出文本 = 跑命令(["git", "ls-files", "-z", "--"] + 路径表, cwd=工作树)
            if 退出码 != 0:
                return 1, "git ls-files 失败，无法确认提交路径：\n%s" % 输出文本.strip()[-400:]
            路径表 = [路径 for 路径 in 路径表
                    if (工作树 / 路径).is_file() or 路径 in 输出文本.split("\0")]
        # 空改不造提交；仍执行同一 pre-commit 门禁，防止少跑自测或案例。
        退出码, 输出文本 = 跑命令(["git", "status", "--porcelain", "--"] + 路径表, cwd=工作树)
        if 退出码 != 0:
            return 1, "git status 失败：\n%s" % 输出文本.strip()[-400:]
        有得提交 = bool(输出文本.strip())
        提交说明 = "本地提交成功。\n"
        if 有得提交:
            退出码, 输出文本 = 跑命令(["git", "add", "--"] + 路径表, cwd=工作树)
            if 退出码 != 0:
                return 1, "git add 失败：\n%s" % 输出文本.strip()[-400:]
            # 提交信息走 stdin（`git commit -F -`）—— 不落临时件（判据 ㉕ 禁「临时根拼路径」）。
            提交信息 = "%s\n\n开工号 %s\n改动：%s\n" % (开工记录["工作内容"], 开工号, " · ".join(路径表))
            退出码, 输出文本 = 跑命令(["git", "commit", "-F", "-"], cwd=工作树, 超时秒数=None,
                      输入文本=提交信息, 子进程环境=禁终端提示环境)
            if 退出码 != 0:
                return 1, ("git commit 失败（多半是**门禁钩子拒了** —— 它每次提交都跑一遍案例）：\n%s"
                         % 输出文本.strip()[-600:])
        else:
            # 空改腿分三档（2026-10-08 修 · 旧树缺 `复跑.py` 致 ImportError 永拒）：判据与分档住
            # `空改门禁.py`（唯一一份），本件只执行它给的门禁。
            退出码, 输出文本, 门禁名, 拒文 = 空改门禁.择空改门禁(走主干, 已合净, 归属对, 空改判据,
                                                    仓根, 工作树)
            if 拒文:
                return 1, 拒文
            if 退出码 != 0:
                return 1, ("空改提交门禁失败（%s）⇒ 不释放，状态留「进行中」：\n%s"
                         % (门禁名, 输出文本.strip()[-600:]))
            提交说明 = "没有新改动要提交；%s 完整提交门禁已通过，未创建空提交。\n" % 门禁名
        if 跳过验证:
            提交说明 += "★ 功能 = 7 跳过工具层闸0；提交门禁仍执行，合并前请复核全量验证。\n"
        退出码, 变更表 = 变更路径表(工作树)
        if 退出码 != 0 or 变更表:
            return 1, "验证/提交后工作树仍有改动或读不出 ⇒ 不推、不释放：%s" % 变更表
        if not 推送:
            账本.置状态(连接, 开工号, 账本.状态_已释放)
            return 0, ("%s本次未推远端（推送=假）\n"
                      "%s 本地正常释放，状态「已释放」。\n%s"
                      "明确跳过远端推送（推送=false）；工作树与支线保留，手动合并后用功能 = 4 安全清理。"
                      % (推送态前缀, 开工号, 提交说明 or "本地提交成功。\n"))

        # ④ 推远端（腿分支目前都没有上游 ⇒ 第一次要 -u 建上游）。
        退出码, 输出文本 = 跑命令(["git", "push", "-u", "origin", 开工记录["分支名"]], cwd=工作树,
                  超时秒数=None, 子进程环境=禁终端提示环境)
        if 退出码 != 0:
            return 1, ("**推送失败**（退出码 %d）⇒ 不释放，状态留「进行中」。\n"
                     "先分清是环境问题还是代码问题（认证 / 网络 / 远端拒绝属环境，"
                     "检查 SSH key 与远端权限）：\n%s" % (退出码, 输出文本.strip()[-600:]))

        账本.置状态(连接, 开工号, 账本.状态_待合并)
        return 0, ("%s本次已推远端（推送=真）\n"
                 "%s 已提交并推到 origin/%s，状态「已提交待合并」。\n%s"
                 "下一步：**手动**合并到主干，合完跑 功能 = 4 收尾（清工作树与支线）。"
                 % (推送态前缀, 开工号, 开工记录["分支名"], 提交说明))
    finally:
        连接.close()
