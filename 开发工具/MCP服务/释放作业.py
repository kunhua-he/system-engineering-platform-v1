"""释放作业 —— `v1_task` 功能 3 的**后台作业路**：前台有界回 running 任务ID，后台跑到真终态。

**为什么要有它**：
释放验证是**长活**，不许被 5 秒强杀、不许据此
判业务失败。四条口径住本件：

  · **前台有界**（`释放同步秒`，≤5 秒窗口）：起（或复用）后台作业，窗口内到终态就一次看完；
    没到就回 `待取作业码` + **运行中任务ID** —— 不阻塞、不假装成功、不假装失败。
  · **后台跑到真终态**：前置 → 验证 → 提交（pre-commit 钩子真跑）→ 推 → 翻状态；
    **真验证 + 钩子完成之前，状态不许翻「已提交待合并 / 已释放」、认领不许清**。
  · **查询幂等，不重启验证**：同一条开工已有**在途**释放作业 ⇒ 本档只观察它、**不再起第二条**
    —— 重复调用是**查询**，不是第二次验证。
  · **真终态失败可取且拒提交**：作业退出码非 0 ⇒ 回执带日志尾，状态留「进行中」；终态与日志由
    `v1_job` 的 `status` / `log` 随时可取。

**不新增工具**：执行与观测**复用既有** `作业.py` / `作业账本.py`（与 `门禁.全量转作业` 同一先例：
长活 = 起 `v1_job` 作业 + 有界等）。

**谁跑哪一段**：前台（MCP 服务）用 `派发释放`；后台（作业子进程）用 `释放入口.py` → `释放主体`。
`释放主体` 是**唯一一份**真释放实现（前置 + 验证 + 提交 + 推 + 翻状态），样本直调它。
"""

