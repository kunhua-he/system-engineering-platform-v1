# -*- coding: utf-8 -*-
"""门禁 —— `v1_gate` 的实现：**验证器**（全量 / 只跑指定判据）。

**为什么分两档，以及为什么只作反馈不作放行**（裁决与实测见
`项目文档/决策记录/2026-09-27_开工账本与四道闸.md`）：

  · **局部绿 ≠ 全仓绿** —— 判据之间有耦合（改一个常量可能让三条判据一起变红），
    所以「只跑我碰到的那几条」**永远不能当放行凭据**。放行凭据只有一个：**全量**。
  · **局部存在的理由是「反馈要快」**，不是「少验一点」：红了 → 改 → 只跑那一条复验（快）→
    全绿了再跑全量。没有这一档，agent 会因为全量慢而干脆不验。
  · **不按「件」切**：判据的 `扫描面` 是按**顶层目录**声明的 ⇒ 拿一个件去筛，37 条里还能命中
    10–17 条，而重型那几条几乎每条件的面里都有 —— 实测墙钟 1124 ms vs 全量 1164 ms，**省 3%**，
    白搭。按**判据**切才是真杠杆：只跑 ㊲ 是 1097 ms（它一条就吃掉全量的 73%）、
    只跑 ㉒ 是 689 ms、空集地板 247 ms。

**★ 全量档跑的是 `闸0.py`，不是 `一键验证.py`**：`闸0.py` 把**两条闸**串起来跑 ——
闸 1 声明侧（`一键验证.py`，37 条判据）+ 闸 2 实现侧（`扫实现.py`）。**只跑闸 1 会漏掉实现侧**，
而漏掉的那一半正是 `闸0.py` 存在的理由（它文件头记着实测：闸 1 不 import 闸 2 ⇒ 主干上坏了
一整段而没有任何门禁抓到）。`判据` 那一档只能落在闸 1 上（实现侧没有「只跑某几条」的对应物），
所以它**只是反馈档**。

**读数第一行必须写明「在哪棵树跑的」**：不带 `开工ID` 就落在主工作树，而主工作树的绿
**不代表**你那条开工的绿 —— 这一行就是防这个误读的。
"""

import subprocess
import sys
from pathlib import Path

from . import 开工账本 as 账本
from .修改 import 对账

超时秒 = 5


def 派发(参数表: dict, 仓根) -> tuple:
    """`v1_gate` 的入口。"""
    开工号 = str(参数表.get("开工ID") or "").strip()
    判据词表 = 参数表.get("判据")
    if isinstance(判据词表, str):
        判据词表 = [判据词表]
    词表 = [str(词).strip() for 词 in (判据词表 or []) if str(词).strip()]

    查询根, 树名, 认领表 = Path(仓根).resolve(), "主工作树", None
    if 开工号:
        连 = 账本.连账本()
        try:
            一条 = 账本.读开工(连, 开工号)
            if not 一条:
                return 1, "没有这条开工：%s ⇒ 先 `v1_task` 功能 = 1 登记" % 开工号
            查询根 = Path(一条["工作树"])
            树名 = "%s（支线 %s）" % (开工号, 一条["分支名"])
            认领表 = 账本.读认领(连, 开工号)
        finally:
            连.close()
        if not 查询根.is_dir():
            return 1, "那条开工的工作树不在了：%s ⇒ 查清再验" % 查询根

    # ★ **全量 = 闸 0**（两条闸一起跑：闸 1 声明侧 + 闸 2 实现侧），不是只跑闸 1 那一条。
    #   只跑 `一键验证.py` 会把**实现侧**（`扫实现.py`）整段漏掉 —— 而那正是 `闸0.py` 存在的
    #   理由（它文件头记着实测：闸 1 不 import 闸 2 ⇒ 主干上坏了一整段、**没有任何门禁抓到**，
    #   直到收口方手跑才发现）。本件原先正好踩回了这个坑。
    #   带 `判据` 时走 `一键验证.py --只跑`：那是**反馈档**（局部绿不算放行），
    #   而「只跑某几条」对实现侧没有对应物。
    命令表 = ([sys.executable, "构建装配/一键验证/闸0.py"] if not 词表
            else [sys.executable, "构建装配/一键验证/一键验证.py", "--只跑", ",".join(词表)])
    try:
        回执 = subprocess.run(命令表, cwd=str(查询根), capture_output=True, text=True,
                            timeout=超时秒)
        退出码 = 回执.returncode
        命令输出 = (回执.stdout or "") + (回执.stderr or "")
    except subprocess.TimeoutExpired:
        return -1, ("超时（%d 秒）—— 五秒硬顶无例外。全量跑不动就说明总 CPU 又涨了"
                  "（台账记着这条），别改成放宽超时" % 超时秒)
    except OSError as 起不来的原因:
        return -2, "起不了验证器：%r" % (起不来的原因,)

    有效行表 = [行 for 行 in 命令输出.splitlines() if 行.strip() and "─" not in 行]
    输出行表 = ["在「%s」跑的：%s" % (树名, 查询根),
              "范围：%s" % ("只跑判据 %s" % " · ".join(词表) if 词表
                         else "**全量 = 闸 0**（声明侧 + 实现侧两条闸；这才是放行凭据）"),
              "退出码 %d" % 退出码,
              "\n".join(有效行表[-28:])]
    if 词表:
        输出行表.append("★ 这是**局部**读数 —— 它绿**不代表**全仓绿。放行前必须跑一次全量（不传 `判据`）。")

    # 绕过检测：这条开工认领集里，盘上指纹 ≠ 账本指纹 ⇒ 有人绕过 MCP 改了它。
    if 认领表 is not None:
        _, 变过表 = 对账(查询根, 认领表)
        if 变过表:
            输出行表.append("★ **绕过检测**：这些件被绕过 MCP 改过（盘上指纹 ≠ 账本指纹）：\n%s"
                        % "\n".join("    %s：账本 %s → 盘上 %s"
                                   % (路径, 对[0] or "（无）", 对[1] or "（件没了）")
                                   for 路径, 对 in sorted(变过表.items())))
    return 退出码, "\n".join(输出行表)
