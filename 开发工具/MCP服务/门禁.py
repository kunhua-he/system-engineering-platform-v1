# -*- coding: utf-8 -*-
"""门禁 —— `v1_gate` 的实现：**验证器**（全量 / 只跑指定判据）。

**为什么分两档，以及为什么只作反馈不作放行**（裁决与实测见
`项目文档/决策记录/2026-09-27_开工账本与四道闸.md`）：

  · **局部绿 ≠ 全仓绿** —— 判据之间有耦合（改一个常量可能让三条判据一起变红），
    所以「只跑我碰到的那几条」**永远不能当放行凭据**。本档内放行凭据只有一个：**全量**
    （但全量本身仍**不是**提交闸 —— 见下「全量绿 ≠ 提交放行」）。
  · **局部存在的理由是「反馈要快」**，不是「少验一点」：红了 → 改 → 只跑那一条复验（快）→
    全绿了再跑全量。没有这一档，agent 会因为全量慢而干脆不验。
  · **不按「件」切**：判据的 `扫描面` 是按**顶层目录**声明的 ⇒ 拿一个件去筛，37 条里还能命中
    10–17 条，而重型那几条几乎每条件的面里都有 —— 实测墙钟 1124 ms vs 全量 1164 ms，**省 3%**，
    白搭。按**判据**切才是真杠杆：只跑 ㊲ 是 1097 ms（它一条就吃掉全量的 73%）、
    只跑 ㉒ 是 689 ms、空集地板 247 ms。

**★ 全量档跑的是 `闸0.py`，不是 `一键验证.py`**：`闸0.py` 把**两条闸**串起来跑 ——
闸 1 声明侧（`一键验证.py`，37 条判据）+ 闸 2 实现侧（`扫实现.py`）。**只跑闸 1 会漏掉实现侧**，
而漏掉的那一半正是 `闸0.py` 存在的理由（它文件头记着实测：闸 1 不 import 闸 2 ⇒ 主干上坏了
一整段而没有任何门禁抓到）。`判据` 那一档只能落在闸 1 上（实现侧没有「只跑某几条」的对应物），
所以它**只是反馈档**。

**★ 全量绿 ≠ 提交放行（两套口径，别混）**：本档全量只跑 `闸0.py`（闸 1 声明侧 + 闸 2 实现侧）；
而真实提交闸（`测试验证/案例/装门禁.sh` 的 pre-commit）**额外跑** ①b
`python3 构建装配/一键验证/一键验证.py --自测` 与 ③ `cargo run --quiet --locked -p v1-case-runner`
全部案例。⇒ **提交放行 = 闸 0 + 判据自测 + 案例**。全量绿只是提交前的**必要一环**，腿若据此判
「可交付」，仍可能在 `功能=3 释放` 的 git commit 处被 pre-commit 拒（`开工.py` 只报「多半是门禁钩子拒了」）。

**★ 绕过检测这一档只报不拦**（裁决 2026-10-05）：本档把「认领件盘上指纹 ≠ 账本指纹」append 进回执，
**但退出码仍取 `闸0.py`** —— 即全量档可以带着「★ 绕过检测」那行返回 0。**硬闸在 `功能=3 释放`**
（`开工.py` 的认领对账会拒）。本轮只把行为写清楚，不改行为。

**读数第一行必须写明「在哪棵树跑的」**：不带 `开工ID` 就落在主工作树，而主工作树的绿
**不代表**你那条开工的绿 —— 这一行就是防这个误读的。
"""

import subprocess
import sys
from pathlib import Path

from . import 开工账本 as 账本
from .修改 import 对账_除源件

超时秒 = 5


def 派发(参数表: dict, 仓根) -> tuple:
    """`v1_gate` 的入口。"""
    开工号 = str(参数表.get("开工ID") or "").strip()
    判据词表 = 参数表.get("判据")
    if isinstance(判据词表, str):
        判据词表 = [判据词表]
    elif 判据词表 is None:
        判据词表 = []
    elif not isinstance(判据词表, (list, tuple)):
        return 2, ("`判据` 要一段字符串或一张表 —— 合法面 = `判据表.检查表` 的可运行判据"
                 "（编号或名子串）；选择器住 `构建装配/一键验证/一键验证/判据选择.py`（同源）")
    词表 = list(判据词表)
    # ★ **不在这里丢词**（原写法 `if str(判据词).strip()` 会把空词 / 非串静默丢掉 ⇒ 退回全量，
    #   正是「只跑」变假象的那条病）。原样透传给 `一键验证.py --只跑`，由**同一个选择器**
    #   （`判据选择.解析选择`，`主流程.解析只跑` 复用它）判：空词 / 非串 / 重复 / 未知 /
    #   已知未知混给 ⇒ 清晰非 0（带近似候选），绝不静默退回全量。
    if 词表 and not all(isinstance(判据词, str) for 判据词 in 词表):
        return 2, "`判据` 里每一项都要是字符串（选择器拒非串项；本档不静默改类型）"

    查询根, 树名, 认领表, 源件表 = Path(仓根).resolve(), "主工作树", None, set()
    if 开工号:
        连接 = 账本.连账本()
        try:
            开工记录 = 账本.读开工(连接, 开工号)
            if not 开工记录:
                return 1, "没有这条开工：%s ⇒ 先 `v1_task` 功能 = 1 登记" % 开工号
            查询根 = Path(开工记录["工作树"])
            树名 = "%s（支线 %s）" % (开工号, 开工记录["分支名"])
            认领表 = 账本.读认领(连接, 开工号)
            源件表 = 账本.源件路径集(连接, 开工号)
        finally:
            连接.close()
        if not 查询根.is_dir():
            return 1, "那条开工的工作树不在了：%s ⇒ 查清再验" % 查询根

    # ★ **全量 = 闸 0**（两条闸一起跑：闸 1 声明侧 + 闸 2 实现侧），不是只跑闸 1 那一条。
    #   只跑 `一键验证.py` 会把**实现侧**（`扫实现.py`）整段漏掉 —— 而那正是 `闸0.py` 存在的
    #   理由（它文件头记着实测：闸 1 不 import 闸 2 ⇒ 主干上坏了一整段、**没有任何门禁抓到**，
    #   直到收口方手跑才发现）。本件原先正好踩回了这个坑。
    #   带 `判据` 时走 `一键验证.py --只跑`：那是**反馈档**（局部绿不算放行），
    #   而「只跑某几条」对实现侧没有对应物。
    命令表 = ([sys.executable, "构建装配/一键验证/闸0.py"] if not 词表
            else [sys.executable, "构建装配/一键验证/一键验证.py", "--只跑", ",".join(词表)])
    try:
        回执 = subprocess.run(命令表, cwd=str(查询根), capture_output=True, text=True,
                            timeout=超时秒)
        退出码 = 回执.returncode
        命令输出 = (回执.stdout or "") + (回执.stderr or "")
    except subprocess.TimeoutExpired:
        return -1, ("超时（%d 秒）—— 五秒硬顶无例外。全量跑不动就说明总 CPU 又涨了"
                  "（台账记着这条），别改成放宽超时" % 超时秒)
    except OSError as 起不来的原因:
        return -2, "起不了验证器：%r" % (起不来的原因,)

    有效行表 = [源码行 for 源码行 in 命令输出.splitlines() if 源码行.strip() and "─" not in 源码行]
    输出行表 = ["在「%s」跑的：%s" % (树名, 查询根),
              "范围：%s" % ("只跑判据 %s" % " · ".join(词表) if 词表
                         else "**全量 = 闸 0**（声明侧 + 实现侧两条闸；提交放行 = 闸 0 + 判据自测 + 案例）"),
              "退出码 %d" % 退出码,
              "\n".join(有效行表[-28:])]
    if 词表:
        输出行表.append("★ 这是**局部**读数 —— 它绿**不代表**全仓绿。放行前必须跑一次全量（不传 `判据`）。")

    # 绕过检测：这条开工认领集里，盘上指纹 ≠ 账本指纹 ⇒ 有人绕过 MCP 改了它。
    if 认领表 is not None:
        对得上表, 变过表, 放行表 = 对账_除源件(查询根, 认领表, 源件表)
        if 放行表:
            输出行表.append("（经 功能 = 6 记过的源件，指纹漂移已放行：%s）"
                        % " · ".join(sorted(放行表)))
        if 变过表:
            输出行表.append("★ **绕过检测**：这些件被绕过 MCP 改过（盘上指纹 ≠ 账本指纹）：\n%s"
                        % "\n".join("    %s：账本 %s → 盘上 %s"
                                   % (路径, 键值对[0] or "（无）", 键值对[1] or "（件没了）")
                                   for 路径, 键值对 in sorted(变过表.items())))
    return 退出码, "\n".join(输出行表)
