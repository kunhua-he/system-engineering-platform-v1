def 置状态(连接, 开工号: str, 状态: str) -> None:
    """翻状态（顺带落 `释放时间`）。**状态未变就一个字节都不动** —— 幂等重跑不许刷新时间线
    （实测：对已释放的开工再跑 功能 = 4 会把 `释放时间` 刷成当下 ⇒ 账本时间线失真）。

    用 `case when` 把「状态没变 ⇒ 保留原 `释放时间`」压进一条 SQL：SQLite 的 SET 右值按**改前**
    的旧行求值 ⇒ `case when 状态 = <新状态>` 判的正是「旧状态 == 新状态」。
    """
    连接.execute("update 开工 set 状态 = ?, 释放时间 = case when 状态 = ? then 释放时间 else ? end "
              "where 开工号 = ?",
              (状态, 状态, 时刻串() if 状态 != 状态_进行中 else None, 开工号))
    连接.commit()


