def 认领文件(连接, 开工号: str, 路径指纹表: dict) -> None:
    """登记/补充认领。**指纹由调用方读盘算好**（agent 从不传指纹）。"""
    for 路径, 指纹 in 路径指纹表.items():
        连接.execute("insert into 认领 (开工号, 路径, 指纹) values (?, ?, ?) "
                  "on conflict(开工号, 路径) do update set 指纹 = excluded.指纹",
                  (开工号, 路径, 指纹))
    连接.commit()


def 读认领(连接, 开工号: str) -> dict:
    return {数据行["路径"]: 数据行["指纹"] for 数据行 in 连接.execute(
        "select 路径, 指纹 from 认领 where 开工号 = ?", (开工号,))}


def 撤认领(连接, 开工号: str, 路径表) -> tuple:
    """按**精确路径**撤掉这条开工的认领，并销掉这些路径在本开工 `改动` 表的旧行
    ⇒ `(撤掉的路径表, 本来就没认领的路径表, 销掉的改动行数)`。

    为什么要有它（2026-10-01 实测腿 v1-100215）：认领的件**在盘上没了**（被删 / 被并进来的
    另一条腿替换成别的件）而账本里还留着旧指纹 ⇒ `释放` 的对账拿它比盘上（件没了 = 空串）
    ⇒ 恒报「变过」⇒ 释放被拒；而 `补充认领`（功能 = 2）只认**盘上存在**的件 ⇒ 那条陈旧认领
    **谁也清不掉**。本函数只动**本开工的**认领行与改动行，不碰别的开工的。
    """
    认领表 = 读认领(连接, 开工号)
    撤掉表 = [路径 for 路径 in dict.fromkeys(路径表) if 路径 in 认领表]
    for 路径 in 撤掉表:
        连接.execute("delete from 认领 where 开工号 = ? and 路径 = ?", (开工号, 路径))
    # ★ 连同这些路径在本开工 `改动` 表的旧行一并销掉（2026-10-05 修 · 审计 A 存疑5）：
    #   否则同一开工「先建后删」的件会在改动表留陈旧行，`释放` 的 `git add` 拿它当路径 ⇒
    #   `fatal: pathspec … did not match any files` 卡死整条腿。只动**本开工的**行。
    行数 = 0
    if 撤掉表:
        行数 = 连接.execute("delete from 改动 where 开工号 = ? and 路径 in (%s)"
                        % ",".join("?" * len(撤掉表)), [开工号] + 撤掉表).rowcount
    连接.commit()
    return 撤掉表, [路径 for 路径 in dict.fromkeys(路径表) if 路径 not in 认领表], 行数


