def 查跨开工占位(连接, 开工号: str, 路径表, 排除开工表=frozenset()) -> dict:
    """`{路径: [{"开工号": …, "状态": …}, …]}` —— 别的开工还**占着**同一个件（含它当前状态）。

    「占着」看**工作树在不在**（树在才可能有改写者）：实测 2026-10-01 收口腿 v1-100228
    开工时被 9 条腿拦、理由是它们「已释放」—— 实际那些腿的状态还挂在「已提交待合并」
    （功能 = 3 跑完、树早清了，收口方先开收口腿、后跑 功能 = 4 翻状态，这个先后差每批
    都会复现）⇒ 树不在就没有改写者，运行期根本无冲突，不算占用。树还在的照旧算 ——
    含「已释放」但树没清成的（功能 = 3 `强制` 释放就留着活树）。

    **只报不拦**（拦截由调用方 `登记` / `补充认领` 做：它们要 `确认重叠` 才放行）：
    有时确实要两条开工改同一个件的不同节。但工具不许一句不说 —— 两条开工各写各的工作树
    （**运行期不撞**），撞的是**合并期**；等合并时才发现最贵。

    **一次 SQL 取号 + 状态**（不额外跑 git、不逐件二次查询）；`排除开工表` 仍透传（僵尸开工，
    见 `开工.查僵尸`）。
    """
    占表 = {}
    for 路径 in 路径表:
        行表 = 连接.execute(
            "select 认领.开工号, 开工.状态, 开工.工作树 from 认领 join 开工 on 认领.开工号 = 开工.开工号 "
            "where 认领.路径 = ? and 认领.开工号 <> ?",
            (路径, 开工号)).fetchall()
        明细 = [{"开工号": 数据行["开工号"], "状态": 数据行["状态"]} for 数据行 in 行表
              if 数据行["开工号"] not in 排除开工表 and Path(数据行["工作树"]).is_dir()]
        if 明细:
            占表[路径] = sorted(明细, key=lambda 占位项: 占位项["开工号"])
    return 占表


def 查跨开工冲突(连接, 开工号: str, 路径表, 排除开工表=frozenset()) -> dict:
    """`{路径: [也认领了它的别的开工号…]}` —— **旧契约**（只给号）；明细走 `查跨开工占位`（同一份实现）。"""
    return {路径: [占位项["开工号"] for 占位项 in 明细]
            for 路径, 明细 in 查跨开工占位(连接, 开工号, 路径表, 排除开工表).items()}


def 拼冲突回执(冲突表: dict, 已确认: bool = False) -> str:
    """把 `查跨开工占位` 的结果拼成**稳定可读回执**：逐件列占位开工的**当前状态**与含义。

    `已确认` = 假 ⇒ 附「默认安全拒」一行（不确认就拒，退出码 2）；真 ⇒ 附「已显式确认」口径。
    两路都带授权提示：独立工作树已有授权可以确认重叠，不必逐次请示。
    """
    行表 = ["各写各的工作树 ⇒ **运行期不撞**；撞的是**合并期**（要人工做语义合并）。"]
    for 路径, 明细 in sorted(冲突表.items()):
        行表.append("    %s：" % 路径)
        for 占位项 in 明细:
            行表.append("        %s（%s）" % (占位项["开工号"],
                                    开工状态含义.get(占位项["状态"], 占位项["状态"])))
    if 已确认:
        行表.append("★ 重叠认领（**已显式确认**）—— 合并期要人工做语义合并。")
    else:
        行表.append("★ 独立工作树**已有授权可以确认重叠** —— 要接着干就重提并传 `确认重叠` = 真，"
                  "不必逐次请示收口方。")
        行表.append("★ **默认安全拒**：不确认就拒（退出码 2）；工具**不**自动忽略占用 / 不抢写 / "
                  "不删树 / 不改状态。")
    return "\n".join(行表)


def 查同内容未释放(连接, 工作内容: str, 排除开工号: str) -> list:
    """**未释放**的开工里，工作内容与本次逐字相同（去首尾空白后）的那些 ⇒ `[(开工号, 工作内容)]`。

    **只报不拦**（口径与 `查跨开工冲突` 同一条）：有时确实要重开一条。但工具不许一句不说 ——
    实测 2026-09-27：同一条活登了两次（`v1-100002` 与 `v1-100007`，工作内容一模一样），
    留下一棵没人认领的孤儿工作树。
    """
    内容值 = 工作内容.strip()
    if not 内容值:
        return []
    return [(数据行["开工号"], 数据行["工作内容"]) for 数据行 in 连接.execute(
        "select 开工号, 工作内容 from 开工 "
        "where 工作内容 = ? and 开工号 <> ? and 状态 <> ? order by 开工号",
        (内容值, 排除开工号, 状态_已释放))]


def 查重复登记(连接, 开工号: str, 工作内容: str, 路径表, 排除开工表=frozenset()) -> list:
    """疑似重复登记的别的**未释放**开工 ⇒ `[(别的开工号, 原因)]`。**只报不拦**。

    两个面：① 工作内容逐字相同；② 认领路径**高度重叠**（重合 ≥ 2 件且占本次认领的一半以上）。
    路径那一面**复用** `查跨开工冲突`（同一份实现）—— 不写平行的第二套判断。
    `排除开工表` 透传给它（剔僵尸，见 `开工.查僵尸`）。
    """
    输出缓冲 = [(别的号, "工作内容逐字相同（它还没释放）")
         for 别的号, _ in 查同内容未释放(连接, 工作内容, 开工号)]
    重合表: dict = {}
    for 路径, 号表 in 查跨开工冲突(连接, 开工号, 路径表, 排除开工表).items():
        for 别的号 in 号表:
            重合表.setdefault(别的号, []).append(路径)
    for 别的号, 件表 in sorted(重合表.items()):
        if len(件表) >= 2 and len(件表) * 2 >= len(路径表):
            输出缓冲.append((别的号, "认领路径高度重叠（重合 %d / 本次 %d 件）" % (len(件表), len(路径表))))
    return 输出缓冲


def 前置提示行() -> str:
    """收口方那份《派腿前置》存在 ⇒ 指路那一行；不存在 / 解析不出 ⇒ 空串（不编话）。

    落点走 `运行数据根` 包取（`子目录路径`）—— **不许自身拼路径**（判据 ㉕）。
    """
    try:
        路径 = 子目录路径(解析当前环境(), "临时件") / 前置文件名
    except 无位置:
        return ""
    if not 路径.is_file():
        return ""
    return ("开工前先读收口方的《派腿前置》：%s\n"
            "  （工具优先级 MCP 优先 · 硬纪律 · 提速红线 · 权威源地图 —— 腿不知道它存在 = 等于没写）" % 路径)


def 写回指纹(连接, 开工号: str, 路径: str, 指纹: str) -> None:
    """写盘之后把**新指纹**内置回认领那一栏（agent 全程不碰指纹）。

    **是 upsert 不是 update**：新建出来的件在认领那一刻盘上还不存在 ⇒ 认领表里没有它那一行
    （`读盘指纹` 只收读得到的件）⇒ 写完必须能**补进去**，否则这个件下一次改动会被第 ③ 道闸
    判成「变过」而永远改不动（实测这条：不改 upsert，新建完就再也改不了它）。
    """
    连接.execute("insert into 认领 (开工号, 路径, 指纹) values (?, ?, ?) "
              "on conflict(开工号, 路径) do update set 指纹 = excluded.指纹",
              (开工号, 路径, 指纹))
    连接.commit()


# ── 改动 ────────────────────────────────────────────────────────────────────────────────

def 记改动(连接, 开工号: str, 路径: str, 功能: str, 写前指纹: str, 写后指纹: str,
         说明: str = "") -> None:
    """记一条改动。`说明` 只有**源件记账**（功能 = 6）填 —— 「为什么改这个源件」。"""
    连接.execute("insert into 改动 (开工号, 路径, 功能, 写前指纹, 写后指纹, 时间, 说明) "
              "values (?, ?, ?, ?, ?, ?, ?)",
              (开工号, 路径, 功能, 写前指纹, 写后指纹, 时刻串(), 说明))
    连接.commit()


def 读改动(连接, 开工号: str) -> list:
    return [dict(数据行) for 数据行 in 连接.execute(
        "select * from 改动 where 开工号 = ? order by 编号", (开工号,))]


def 源件路径集(连接, 开工号: str) -> set:
    """本开工里**经 `功能 = 6`（源件记账）记过**的件路径集合。

    这些件是**二进制源**（如规则库 `开发工具/信息核心/信息核心.db`）：`v1_edit` 改不了它，只能由
    仓内命令（`信息核心.py 登记/建库/冻结基线`）改 ⇒ 盘上指纹与账本漂移是**正当**的 ⇒ 绕过检测
    对它们放行（见 `修改.对账_除源件`）。**没记过的件照旧报**。
    """
    return {数据行["路径"] for 数据行 in 连接.execute(
        "select distinct 路径 from 改动 where 开工号 = ? and 功能 = ?", (开工号, 源件档名))}


def 全部开工(连接) -> list:
    return [dict(数据行) for 数据行 in 连接.execute("select * from 开工 order by 开工号")]


# ── 开工归属（执行开工号 ↔ 目标开工号）────────────────────────────────────────────────────

def 记归属(连接, 开工号: str, 父开工号: str, 开工种类: str) -> None:
    """把一条开工的**归属**写下来：它属哪个**目标开工号**（被合 / 被接管的原腿）+ 它是哪一**开工种类**。

    `父开工号` 为空串 ⇒ 写 NULL（原腿无父）。幂等（重复写同一对值，改前改后同形）。
    """
    连接.execute("update 开工 set 父开工号 = ?, 开工种类 = ? where 开工号 = ?",
              (父开工号 or None, 开工种类 or 种类_原腿, 开工号))
    连接.commit()


