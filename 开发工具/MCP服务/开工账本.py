def 新开工号(连接: sqlite3.Connection) -> str:
    """下一个开工号：`v1-` + 6 位递增号（**只增不复用**）。

    复用号会让旧记录与支线撞名 ⇒ 那是最难查的一类错，所以取「已出现过的最大号 + 1」，
    不取「当前行数 + 1」。
    """
    源码行 = 连接.execute("select 开工号 from 开工 order by 开工号 desc limit 1").fetchone()
    号值 = int(源码行["开工号"][3:]) + 1 if 源码行 else 100001
    return "v1-%06d" % 号值


