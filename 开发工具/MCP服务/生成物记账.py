# -*- coding: utf-8 -*-
"""生成物记账 —— `v1_task` 功能 = 5：**跑生成器**，把它写过的件记进账本。

**为什么要有它**（2026-09-27 实测）：生成物由**生成器**写出、本来就不走 `v1_edit` ⇒ `释放` 的
「绕过检测」把它们当越界（`git status` 里有、`改动` 表里没有）⇒ 恒被拒；收口方只能手工把生成物
补进账本 `改动` 表 —— 那是**绕过账本**，不是记账。

**唯一来源是生成器自身**（不写第二套清单）：产出集 = **跑前 / 跑后指纹变了的件**，由「生成器
确实写了盘」这个事实得出，不是听调用方报一张表。所以「由生成器产出」是**实测**出来的。

**它不放松闸**：`释放` 的越界检测一字未改 —— 没跑过生成器、或生成器没写过的件照拒；跑出来的件
还要**自称是本生成器的产物**（头标，见 `读生成器`）才认。本件只补「生成器写出来的那些」的记账：
`写回指纹`（认领 upsert）＋ `记改动`，**复用账本里已有的两步**（与 `v1_edit` 写盘之后那两步
同一套），不新造写入口。
"""

import sys
from pathlib import Path

from .开工 import 变更路径表, 跑命令, 超时秒      # 先导开工：它把 开发工具/ 挂上 sys.path
from 代码地图 import 文件指纹                 # noqa: E402
from . import 开工账本 as 账本                # noqa: E402

功能名 = "生成物（重跑生成器产出）"          # 账本 `改动` 表里那一档的名字（沿用既有那条）


def 脏件指纹(工作树: Path):
    """`git status --porcelain` 里的每个件 ⇒ `{路径: 盘上指纹}`（件没了 = 空串）。

    「什么算脏」**复用** `开工.变更路径表`（与 `释放` 的越界检测同一份解析），本件只多读一次指纹。
    `git status` 跑不动 ⇒ **`None`**（不许当成「盘上没变化」—— 那是把判不了当通过）。
    """
    退出码, 变更表 = 变更路径表(工作树)
    if 退出码 != 0:
        return None
    return {路径: (文件指纹(str(工作树 / 路径)) if (工作树 / 路径).is_file() else "")
            for 路径 in 变更表}


def 读生成器(件路径: Path) -> str:
    """件头里**自称的生成器路径**（注释形 `// 生成器：<路径>` · 或 JSON 值里的同文）；
    不自称生成物 ⇒ 空串。

    认的是**产物自身的声明**（README §九「生成物被手改即为违规」· 判据 ⑩ 的产物头标四件事）——
    那是「这是生成物、禁手改」的**唯一标记**。本件只**读**它，不另立第二套口径/清单。
    """
    try:
        # 头标窗口：**整个头部注释块**都可能很长 —— `契约声明/src/声明数据.rs` 的
        # `// 生成器：` 在逐文件源指纹清单**之后**。原先只读 40 行 ⇒ 那份
        # 产物永远「不自称生成器」⇒ 功能 = 5 恒拒（实测 2026-09-27，本件与判据 ⑩
        # 的差别在：⑩ 只问「四件事有没有」（`"生成器" in 头` 就够），本件要**取出路径**
        # 与真生成器比对 ⇒ 必须真看到那一行）。取 400 行足够覆盖头标 + 开头的 `use`。
        头部 = "\n".join(件路径.read_text(encoding="utf-8", errors="replace").splitlines()[:400])
    except OSError:
        return ""
    if "生成物" not in 头部 or not ("禁手改" in 头部 or "禁手不改" in 头部):
        return ""
    for 源码行 in 头部.splitlines():
        if "生成器：" in 源码行:
            # 剥掉 JSON 的收尾标点：JSON 值恒带 `"`（有时还有 `,`），
            # 不剥则取出的路径永远多两个字符 ⇒ 与真生成器路径对不上 ⇒ 记账恒被拒。
            return 源码行.split("生成器：", 1)[1].strip().strip('",').strip()
    return ""


def 记账(仓根, 开工号: str, 生成器: str, 参数) -> tuple:
    """跑生成器 → 把**它写过的件**记进账本 ⇒ `(退出码, 说明)`。"""
    连接 = 账本.连账本()
    try:
        一条开工 = 账本.读开工(连接, 开工号)
        if not 一条开工:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记" % 开工号
        if 一条开工["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能再记账" % 一条开工["状态"]
        工作树 = Path(一条开工["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再记账" % 工作树
        相对 = str(生成器 or "").strip()
        if not 相对:
            return 2, "功能 = 5 要 `生成器`（生成器入口的仓内相对路径，如 `构建装配/形态装配/生成声明.py`）"
        if 相对.startswith("/") or ".." in Path(相对).parts or not 相对.endswith(".py"):
            return 2, "`生成器` 只认仓内相对 `.py` 路径（不许绝对路径 / 不许 `..`）：%r" % 相对
        if not (工作树 / 相对).is_file():
            return 1, "生成器不在工作树里：%s" % 相对
        参数 = ([str(一项) for 一项 in 参数] if isinstance(参数, (list, tuple))
            else ([] if not 参数 else [str(参数)]))

        跑前 = 脏件指纹(工作树)
        if 跑前 is None:
            return 1, "查不清盘上动了什么（git status 失败）⇒ 没跑生成器、没记账"
        退出码, 输出文本 = 跑命令([sys.executable, 相对] + 参数, cwd=工作树, 超时秒数=超时秒)
        if 退出码 != 0:
            return 1, ("生成器没跑通（退出码 %d）⇒ **一件都不记**（账本一个字没动）：\n%s"
                     % (退出码, 输出文本.strip()[-500:]))
        跑后 = 脏件指纹(工作树)
        if 跑后 is None:
            return 1, "生成器跑完了，但查不清盘上动了什么（git status 失败）⇒ 一件都不记"
        写过表 = [(路径, 跑前.get(路径) or "", 指纹)
                for 路径, 指纹 in sorted(跑后.items()) if 跑前.get(路径) != 指纹]
        # 唯一来源 = **产物自身的头标**（README §九 · 判据 ⑩ 的产物头标四件事）：它自称由哪个
        # 生成器产出。不认这一条的件**一件都不记**（fail-closed）—— 闸不放宽到「跑什么都记」。
        非产物表 = [路径 for 路径, _, _ in 写过表 if 读生成器(工作树 / 路径) != 相对]
        if 非产物表:
            return 1, ("生成器这次写过的件里，有**没自称是本生成器产物**的 ⇒ **一件都不记**：\n  %s\n"
                     "（头标要同时有「生成物」「禁手改」（或写成「禁手不改」）与 `生成器：%s` 一处 —— 判据 ⑩ 的口径；"
                     "注释形与 JSON 值都认）"
                     % (" · ".join(非产物表), 相对))
        认领表 = 账本.读认领(连接, 开工号)
        改过表 = {一条改动["路径"] for 一条改动 in 账本.读改动(连接, 开工号)}
        for 路径, 写前, 写后 in 写过表:
            账本.写回指纹(连接, 开工号, 路径, 写后)
            账本.记改动(连接, 开工号, 路径, 功能名, 认领表.get(路径) or 写前, 写后)
        输出行表 = ["%s：生成器 %s 跑通，记账 %d 件（功能「%s」）"
                 % (开工号, 相对, len(写过表), 功能名)]
        if 写过表:
            输出行表 += ["  %s（写后 %s）" % (路径, 写后 or "件没了")
                      for 路径, _, 写后 in 写过表]
        else:
            输出行表.append("  （生成器没写出任何变化 —— 产出已是最新，无需记账）")
        越界表 = sorted(路径 for 路径 in 跑后
                     if 路径 not in 改过表 and 路径 not in {节点件 for 节点件, _, _ in 写过表})
        if 越界表:
            输出行表.append("★ 另有这些件脏、且不在改动表（**不是这次生成器写的**）⇒ 释放仍会拒：%s"
                        % " · ".join(越界表))
        return 0, "\n".join(输出行表)
    finally:
        连接.close()
