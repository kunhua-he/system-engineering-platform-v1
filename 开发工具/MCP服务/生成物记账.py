"""生成物记账 —— `v1_task` 功能 = 5：**跑生成器**，把它写过的件记进账本。

**为什么要有它**（2026-09-27 实测）：生成物由**生成器**写出、本来就不走 `v1_edit` ⇒ `释放` 的
「绕过检测」把它们当越界（`git status` 里有、`改动` 表里没有）⇒ 恒被拒；收口方只能手工把生成物
补进账本 `改动` 表 —— 那是**绕过账本**，不是记账。

**唯一来源是生成器自身**（不写第二套清单）：产出集 = **跑前 ∪ 跑后里指纹变了的件**（含
「跑前脏、跑后干净」那一种 —— 生成器把件写回**与 HEAD 逐字节一致**时 `git status` 不再列它，
只遍历「跑后」就会漏掉它 ⇒ 认领表里更早那次的指纹永远洗不掉 · 债务 532），由「生成器
确实写了盘」这个事实得出，不是听调用方报一张表。所以「由生成器产出」是**实测**出来的。

**它不放松闸**：`释放` 的越界检测一字未改 —— 没跑过生成器、或生成器没写过的件照拒；跑出来的件
还要**自称是本生成器的产物**（头标，见 `读生成器声明`）才认。本件只补「生成器写出来的那些」的记账：
`写回指纹`（认领 upsert）＋ `记改动`，**复用账本里已有的两步**（与 `v1_edit` 写盘之后那两步
同一套），不新造写入口。
"""

import json
import re
import sys
from pathlib import Path

from .仓操作 import 变更路径表, 跑命令, 超时秒    # 先导仓操作：它把 开发工具/ 挂上 sys.path
from 代码地图 import 文件指纹                 # noqa: E402
from . import 开工账本 as 账本                # noqa: E402

改动档名 = "生成物（重跑生成器产出）"          # 账本 `改动` 表里那一档的名字（沿用既有那条）

# 外部生成器标记表（债务 581）：仓内生成器走「仓内相对路径 + 中文头标」那一套；**仓外**工具
# （cargo 一类）既进不了仓内相对路径，产物头也只有它自带的英文注释、不自称「生成物」⇒ 两条
# 都进不来、记账恒 0 件。这张表是「允许的仓外生成器名 → 它产物头的逐字标记对」的**唯一落点**：
# 不在表里的名字照拒（fail-closed 一字不松），标记对逐字取自该工具真实产物头。
外部生成器标记表 = {
    "cargo": ("@generated by Cargo", "not intended for manual editing"),
}

# ★ 声明式二进制产物：二进制容器（如 `.模块制品`）**带不了文本自述** —— 头字节是容器魔数 + 段表，
#   写不进 `生成物` / `禁手改` / `生成器：` 三件事 ⇒ 老机制对它们恒判「不自称」、恒拒，
#   生成物就只能靠手工包装进树（那是绕记账）。这一档的**唯一来源仍是生成器自身**：
#   生成器源文件里一行机器可读声明（本标记之后一个单行 JSON），列出它写出的二进制件**相对路径**。
#   本档只**读**声明并按它核验：不新立第二套账本、不按后缀放行（`.模块制品` 之类不在任何白名单里）、
#   不为任何具体制品加特例（判据只看声明与盘面事实）。
生成物声明标记 = "# 生成物声明："

# ★ 声明给**规则**，不给实例清单（2026-10-17 修）：生成器「扫目录、按目录名出同名件」这类规则，
#   用实例表（`二进制输出` 逐件列相对路径）只能列清**当时已经存在**的那几件 ⇒ 新增一个模块就得改
#   声明，声明本身就会漂成第二份清单（那正是本档一开始要避开的东西）。`二进制输出模板` 一条
#   就把规则说清：`<名>` 是占位符，同名的两处必须绑**同一个**路径段（`<模块>/<模块>.模块制品`
#   = 目录名与件名同名）。判据仍是**声明 + 盘面事实**，不按后缀开白名单：`…/子/卯.模块制品`
#   段数对得上、占位绑定对不上 ⇒ 照样判「未声明」。
模板占位形 = re.compile(r"<([0-9A-Za-z_\u4e00-\u9fff]+)>")

# 源码后缀集：声明成「二进制产物」却落这些后缀 ⇒ 是源码伪装（本档只收真二进制容器）。
源码后缀集 = frozenset({".py", ".rs", ".json", ".md", ".toml", ".c", ".h", ".cpp", ".hpp",
                     ".txt", ".yaml", ".yml", ".sh", ".js", ".ts", ".html", ".css"})


def 读生成物声明(工作树: Path, 生成器路径: str) -> dict:
    """读生成器源文件里的 `# 生成物声明：<单行 JSON>` ⇒ 声明 dict；不成立 ⇒ 空 dict（fail-closed）。

    三件事必须齐：`生成器` 逐字等于本次生成器路径（别人的声明不认）、`边界` 是非空字符串表、
    `二进制输出` 是字符串表。任一不成立 ⇒ 空 dict ⇒ 下游把二进制件全判「未声明」并整批零写。
    """
    生成器件路径 = 工作树 / 生成器路径
    try:
        源文本 = 生成器件路径.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {}
    for 源码行 in 源文本.splitlines():
        if 生成物声明标记 not in 源码行:
            continue
        try:
            声明 = json.loads(源码行.split(生成物声明标记, 1)[1].strip())
        except ValueError:
            return {}
        if not isinstance(声明, dict) or 声明.get("生成器") != 生成器路径:
            return {}
        边界 = 声明.get("边界")
        输出 = 声明.get("二进制输出") or []
        模板表 = 声明.get("二进制输出模板") or []
        if not (isinstance(边界, list) and 边界 and all(isinstance(声明项, str) and 声明项 for 声明项 in 边界)):
            return {}
        if not (isinstance(输出, list) and all(isinstance(声明项, str) and 声明项 for 声明项 in 输出)):
            return {}
        if not (isinstance(模板表, list) and all(是合法模板(模板项) for 模板项 in 模板表)):
            return {}
        if not 输出 and not 模板表:
            return {}
        return 声明
    return {}


def 拆段(相对路径: str) -> list:
    """仓内相对路径 ⇒ 非空路径段表（`/` 分家，空段丢掉）。"""
    return [路径段 for 路径段 in str(相对路径).split("/") if 路径段]


def 是合法模板(模板项) -> bool:
    """模板成立吗：仓内相对路径 · 无 `..` · 至少一个 `<占位>`（无占位的模板 = 实例，走实例表）。"""
    if not isinstance(模板项, str) or not 模板项 or 模板项.startswith("/"):
        return False
    路径段表 = 拆段(模板项)
    if not 路径段表 or ".." in 路径段表:
        return False
    return 模板占位形.search(模板项) is not None


def 段匹配(模板段: str, 路径段: str, 绑定表: dict) -> bool:
    """一段模板对一段路径：字面部分逐字相等、`<名>` 部分占一个非空片段；同名占位必须绑同一个值。"""
    模式片段 = []
    光标 = 0
    for 占位匹配 in 模板占位形.finditer(模板段):
        模式片段.append(re.escape(模板段[光标:占位匹配.start()]))
        模式片段.append("(.+?)")
        光标 = 占位匹配.end()
    模式片段.append(re.escape(模板段[光标:]))
    整体匹配 = re.fullmatch("".join(模式片段), 路径段)
    if 整体匹配 is None:
        return False
    名表 = [占位匹配.group(1) for 占位匹配 in 模板占位形.finditer(模板段)]
    for 占位名, 绑定值 in zip(名表, 整体匹配.groups()):
        if 绑定值 in (".", ".."):
            return False
        已绑值 = 绑定表.get(占位名)
        if 已绑值 is not None and 已绑值 != 绑定值:
            return False
        绑定表[占位名] = 绑定值
    return True


def 模板命中(模板项: str, 路径: str) -> bool:
    """`路径` 是否命中 `模板项`：段数相等、逐段匹配（见 `段匹配`）。"""
    模板段表 = 拆段(模板项)
    路径段表 = 拆段(路径)
    if len(模板段表) != len(路径段表):
        return False
    绑定表 = {}
    return all(段匹配(模板段, 路径段, 绑定表) for 模板段, 路径段 in zip(模板段表, 路径段表))


def 声明命中(声明: dict, 路径: str) -> bool:
    """`路径` 在不在生成器声明里（实例表命中，或命中任一模板）。"""
    if 路径 in set(声明.get("二进制输出") or ()):
        return True
    return any(模板命中(模板项, 路径) for 模板项 in (声明.get("二进制输出模板") or ()))


def 判二进制产物(工作树: Path, 声明: dict, 候选表: list, 认领表: dict) -> list:
    """逐件核声明式二进制产物 ⇒ `[(路径, 拒由)]`（空表 = 全部成立）。

    六问，任一不过就拒（调用方整批零写）：
      ① 声明里有没有这件（实例表命中 或 命中模板；未声明 = 想拿「是二进制」当通行证）；
      ② 在 `边界` 根之内（越根 = 写到认领面外）；
      ③ 在本腿认领表里（越认领 = 没认领的件借生成器洗白）；
      ④ 普通文件、非符号链接、非硬链接（伪装 / 共用 inode）；
      ⑤ 后缀不在 `源码后缀集`（源码伪装）；
      ⑥ 字节含 NUL 且读不成 utf-8、非空（文本 / 库伪装 —— 真容器是二进制）。
    """
    边界表 = [边界.rstrip("/") + "/" for 边界 in (声明.get("边界") or ())]
    拒表 = []
    for 路径 in 候选表:
        if not 声明命中(声明, 路径):
            拒表.append((路径, "不在生成器声明的 `二进制输出` / `二进制输出模板` 里"))
            continue
        if Path(路径).is_absolute() or ".." in Path(路径).parts:
            拒表.append((路径, "不是仓内相对路径"))
            continue
        if not any(路径.startswith(边界) for 边界 in 边界表):
            拒表.append((路径, "越出声明边界 %s" % "、".join(声明.get("边界") or ())))
            continue
        if 认领表 and 路径 not in 认领表:
            拒表.append((路径, "不在本腿认领表里"))
            continue
        生成器件路径 = 工作树 / 路径
        if 生成器件路径.is_symlink() or not 生成器件路径.is_file():
            拒表.append((路径, "不是普通文件（符号链接 / 缺件）"))
            continue
        if 生成器件路径.stat().st_nlink > 1:
            拒表.append((路径, "硬链接（共用 inode，属伪装）"))
            continue
        if 生成器件路径.suffix.lower() in 源码后缀集:
            拒表.append((路径, "后缀 %s 属源码，不能声明成二进制产物" % 生成器件路径.suffix))
            continue
        字节 = 生成器件路径.read_bytes()
        if not 字节:
            拒表.append((路径, "空件（不构成产物）"))
            continue
        if b"\x00" not in 字节:
            try:
                字节.decode("utf-8")
            except UnicodeDecodeError:
                pass
            else:
                拒表.append((路径, "读得成 utf-8 文本（源码伪装）"))
    return 拒表


def 脏件指纹(工作树: Path):
    """`git status --porcelain` 里的每个件 ⇒ `{路径: 盘上指纹}`（件没了 = 空串）。

    「什么算脏」**复用** `开工.变更路径表`（与 `释放` 的越界检测同一份解析），本件只多读一次指纹。
    `git status` 跑不动 ⇒ **`None`**（不许当成「盘上没变化」—— 那是把判不了当通过）。
    """
    退出码, 变更表 = 变更路径表(工作树)
    if 退出码 != 0:
        return None
    return {路径: (文件指纹(str(工作树 / 路径)) if (工作树 / 路径).is_file() else "")
            for 路径 in 变更表}


def _取声明(源文本: str, 生成器路径: str) -> str:
    """从一段文本里取出「生成器：<路径>」 ⇒ 路径（三件事不齐或路径不是本生成器 ⇒ 空串）。"""
    if "生成物" not in 源文本 or not ("禁手改" in 源文本 or "禁手不改" in 源文本):
        return ""
    for 源码行 in 源文本.splitlines():
        if "生成器：" in 源码行:
            # 剥掉 JSON 的收尾标点：JSON 值恒带 `"`（有时还有 `,`），
            # 不剥则取出的路径永远多两个字符 ⇒ 与真生成器路径对不上 ⇒ 记账恒被拒。
            自称 = 源码行.split("生成器：", 1)[1].strip().strip('",').strip()
            if 自称 == 生成器路径:
                return 自称
    return ""


def 读生成器声明(件路径: Path, 生成器路径: str) -> str:
    """件**自称的生成器路径**（注释形 `// 生成器：<路径>` · JSON 值里的同文 · 或二进制件里某张表的同一行）；
    不自称 ⇒ 空串。

    认的是**产物自身的声明**（README §九「生成物被手改即为违规」· 判据 ⑩ 的产物头标四件事）——
    那是「这是生成物、禁手改」的**唯一标记**。本件只**读**它，不另立第二套口径/清单。

    **两段窗口**（实测 2026-09-29 补）：
      · 头 400 行 —— 文本产物（`.rs`/`.json`）的头标就住在那里（原先只读 40 行 ⇒
        `契约声明/src/声明数据.rs` 的 `生成器：` 在逐文件指纹清单之后 ⇒ 恒判「不自称」）；
      · **退到全文** —— 二进制产物（规则库 `信息核心.db`）**带不了头标**：它是 sqlite，第 0 字节
        必须是 `SQLite format 3\0`；而声明是一行数据（表 `元`），落在文件里的某处（实测 137 KB 处，
        而头 400 行只到 15 KB）⇒ 只看头就恒拒，连开工都释放不了。
    为何敢放宽：判据 ⑩ 判的是**文本生成物的头标**（窗口 = 头部）；本件要的是「这个件自称由哪个
    生成器产出」这个**事实**，与它落在文件哪个位置无关（两个窗口本来就不同，见本件开头那句）。
    """
    try:
        全文 = 件路径.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    自称 = (_取声明("\n".join(全文.splitlines()[:400]), 生成器路径)
            or _取声明(全文, 生成器路径))
    if 自称:
        return 自称
    # ★ 债务 581：仓外工具（cargo 一类）不写中文头标，只留它自带的英文注释 ⇒ 逐字认它产物头的
    #   标记对（表见 `外部生成器标记表`）。窗口同「头 400 行」那一档（外部工具的产物头恒在头部）。
    外部标记对 = 外部生成器标记表.get(Path(生成器路径).name)
    if 外部标记对 and all(标记 in "\n".join(全文.splitlines()[:400]) for 标记 in 外部标记对):
        return 生成器路径
    return ""


def 记生成物账(仓根, 开工号: str, 生成器: str, 命令行参数) -> tuple:
    """跑生成器 → 把**它写过的件**记进账本 ⇒ `(退出码, 说明)`。"""
    连接 = 账本.连账本()
    try:
        一条开工 = 账本.读开工(连接, 开工号)
        if not 一条开工:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记" % 开工号
        if 一条开工["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能再记账" % 一条开工["状态"]
        工作树 = Path(一条开工["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再记账" % 工作树
        相对 = str(生成器 or "").strip()
        if not 相对:
            return 2, ("功能 = 5 要 `生成器`（仓内相对路径，如 `构建装配/形态装配/生成声明.py`；"
                     "或 `外部生成器标记表` 里的仓外工具名，如 `cargo`）")
        # ★ 债务 581：仓外工具（只认表里那几个）走 PATH 上的真命令；其余照旧只认**仓内相对路径**
        #   （`.py` 走解释器、别的后缀直接执行 —— 原先写死 `.py` ⇒ 仓内可执行生成器也传不进来）。
        if 相对 in 外部生成器标记表:
            命令 = [相对]
        else:
            if 相对.startswith("/") or ".." in Path(相对).parts:
                return 2, "`生成器` 只认仓内相对路径（不许绝对路径 / 不许 `..`）：%r" % 相对
            if not (工作树 / 相对).is_file():
                return 1, "生成器不在工作树里：%s" % 相对
            # 仓内非 `.py` 可执行必须给**绝对路径**：子进程起不带斜杠的名字会走 PATH 查（实测 -2 起不了）。
            命令 = ([sys.executable, 相对] if 相对.endswith(".py")
                 else [str(工作树 / 相对)])
        命令行参数 = ([str(参数项) for 参数项 in 命令行参数] if isinstance(命令行参数, (list, tuple))
            else ([] if not 命令行参数 else [str(命令行参数)]))

        跑前 = 脏件指纹(工作树)
        if 跑前 is None:
            return 1, "查不清盘上动了什么（git status 失败）⇒ 没跑生成器、没记账"
        退出码, 输出文本 = 跑命令(命令 + 命令行参数, cwd=工作树, 超时秒数=超时秒)
        if 退出码 != 0:
            return 1, ("生成器没跑通（退出码 %d）⇒ **一件都不记**（账本一个字没动）：\n%s"
                     % (退出码, 输出文本.strip()[-500:]))
        跑后 = 脏件指纹(工作树)
        if 跑后 is None:
            return 1, "生成器跑完了，但查不清盘上动了什么（git status 失败）⇒ 一件都不记"
        候选路径表 = sorted(set(跑前) | set(跑后))
        # ★ 候选集取**跑前 ∪ 跑后**（2026-10-13 修 · 债务 532）：原先只遍历「跑后」，于是
        #   「跑前脏、跑后干净」的件进不了候选 —— 生成器把件写回与 HEAD 逐字节一致时
        #   （回退、或重跑产出旧版）git status 不再列它 ⇒ 认领表里更早那次的指纹永远洗不掉
        #   （`补充认领` 按设计拒洗漂移件），释放恒拒「有人绕过 v1_edit 直接改了盘」，
        #   而盘上其实与 HEAD 一模一样、根本没有绕过。
        写过表 = []
        for 路径 in 候选路径表:
            写前 = 跑前.get(路径) or ""
            写后 = 跑后.get(路径)
            if 写后 is None:
                # 跑前脏、跑后干净 ⇒ 盘上现内容就是 HEAD 内容（件不在盘上 = 空串）。
                写后 = 文件指纹(str(工作树 / 路径)) if (工作树 / 路径).is_file() else ""
            if 写前 == 写后:
                continue
            写过表.append((路径, 写前, 写后))
        # 唯一来源 = **产物自身的头标**（README §九 · 判据 ⑩ 的产物头标四件事）：它自称由哪个
        # 生成器产出。不认这一条的件**一件都不记**（fail-closed）—— 闸不放宽到「跑什么都记」。
        认领表 = 账本.读认领(连接, 开工号)
        # 产物分两档：文本产物走「头标自述」（老机制，一字未改）；二进制容器带不了头标 ⇒
        # 走「生成器源里的声明」（`读生成物声明`）。两档都拿不到的件照旧拒、整批零写。
        声明 = 读生成物声明(工作树, 相对)
        文本产物表 = [路径 for 路径, _, _ in 写过表 if 读生成器声明(工作树 / 路径, 相对) == 相对]
        二进制产物表 = [路径 for 路径, _, _ in 写过表
                   if 路径 not in 文本产物表 and 声明命中(声明, 路径)]
        非产物表 = [路径 for 路径, _, _ in 写过表
                if 路径 not in 文本产物表 and not 声明命中(声明, 路径)]
        if 非产物表:
            return 1, ("生成器这次写过的件里，有**没自称是本生成器产物**、也不在生成器 `二进制输出` / `二进制输出模板` 声明里的 ⇒ **一件都不记**：\n  %s\n"
                     "（文本产物：头标要同时有「生成物」「禁手改」（或写成「禁手不改」）与 `生成器：%s` 一处 —— 判据 ⑩ 的口径；"
                     "注释形与 JSON 值都认。二进制容器带不了头标 ⇒ 由生成器源里 `%s<单行 JSON>` 显式列出相对路径或模板）"
                     % (" · ".join(非产物表), 相对, 生成物声明标记))
        拒表 = 判二进制产物(工作树, 声明, 二进制产物表, 认领表)
        if 拒表:
            return 1, ("声明式二进制产物**核不过** ⇒ **一件都不记**：\n  %s"
                     % "\n  ".join("%s（%s）" % (路径, 拒由) for 路径, 拒由 in 拒表))
        改过表 = {一条改动["路径"] for 一条改动 in 账本.读改动(连接, 开工号)}
        for 路径, 写前, 写后 in 写过表:
            账本.写回指纹(连接, 开工号, 路径, 写后)
            账本.记改动(连接, 开工号, 路径, 改动档名, 认领表.get(路径) or 写前, 写后)
        输出行表 = ["%s：生成器 %s 跑通，记账 %d 件（功能「%s」）"
                 % (开工号, 相对, len(写过表), 改动档名)]
        if 写过表:
            输出行表 += ["  %s（写后 %s）" % (路径, 写后 or "件没了")
                      for 路径, _, 写后 in 写过表]
        else:
            输出行表.append("  （生成器没写出任何变化 —— 产出已是最新，无需记账）")
        越界表 = sorted(路径 for 路径 in 跑后
                     if 路径 not in 改过表 and 路径 not in {节点件 for 节点件, _, _ in 写过表})
        if 越界表:
            输出行表.append("★ 另有这些件脏、且不在改动表（**不是这次生成器写的**）⇒ 释放仍会拒：%s"
                        % " · ".join(越界表))
        return 0, "\n".join(输出行表)
    finally:
        连接.close()
