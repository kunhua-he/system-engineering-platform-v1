# -*- coding: utf-8 -*-
"""生成物记账 —— `v1_task` 功能 = 5：**跑生成器**，把它写过的件记进账本。

**为什么要有它**（2026-09-27 实测）：生成物由**生成器**写出、本来就不走 `v1_edit` ⇒ `释放` 的
「绕过检测」把它们当越界（`git status` 里有、`改动` 表里没有）⇒ 恒被拒；收口方只能手工把生成物
补进账本 `改动` 表 —— 那是**绕过账本**，不是记账。

**唯一来源是生成器自身**（不写第二套清单）：产出集 = **跑前 ∪ 跑后里指纹变了的件**（含
「跑前脏、跑后干净」那一种 —— 生成器把件写回**与 HEAD 逐字节一致**时 `git status` 不再列它，
只遍历「跑后」就会漏掉它 ⇒ 认领表里更早那次的指纹永远洗不掉 · 债务 532），由「生成器
确实写了盘」这个事实得出，不是听调用方报一张表。所以「由生成器产出」是**实测**出来的。

**它不放松闸**：`释放` 的越界检测一字未改 —— 没跑过生成器、或生成器没写过的件照拒；跑出来的件
还要**自称是本生成器的产物**（头标，见 `读生成器声明`）才认。本件只补「生成器写出来的那些」的记账：
`写回指纹`（认领 upsert）＋ `记改动`，**复用账本里已有的两步**（与 `v1_edit` 写盘之后那两步
同一套），不新造写入口。
"""

import sys
from pathlib import Path

from .仓操作 import 变更路径表, 跑命令, 超时秒    # 先导仓操作：它把 开发工具/ 挂上 sys.path
from 代码地图 import 文件指纹                 # noqa: E402
from . import 开工账本 as 账本                # noqa: E402

改动档名 = "生成物（重跑生成器产出）"          # 账本 `改动` 表里那一档的名字（沿用既有那条）

# 外部生成器标记表（债务 581）：仓内生成器走「仓内相对路径 + 中文头标」那一套；**仓外**工具
# （cargo 一类）既进不了仓内相对路径，产物头也只有它自带的英文注释、不自称「生成物」⇒ 两条
# 都进不来、记账恒 0 件。这张表是「允许的仓外生成器名 → 它产物头的逐字标记对」的**唯一落点**：
# 不在表里的名字照拒（fail-closed 一字不松），标记对逐字取自该工具真实产物头。
外部生成器标记表 = {
    "cargo": ("@generated by Cargo", "not intended for manual editing"),
}


def 脏件指纹(工作树: Path):
    """`git status --porcelain` 里的每个件 ⇒ `{路径: 盘上指纹}`（件没了 = 空串）。

    「什么算脏」**复用** `开工.变更路径表`（与 `释放` 的越界检测同一份解析），本件只多读一次指纹。
    `git status` 跑不动 ⇒ **`None`**（不许当成「盘上没变化」—— 那是把判不了当通过）。
    """
    退出码, 变更表 = 变更路径表(工作树)
    if 退出码 != 0:
        return None
    return {路径: (文件指纹(str(工作树 / 路径)) if (工作树 / 路径).is_file() else "")
            for 路径 in 变更表}


def _取声明(源文本: str, 生成器路径: str) -> str:
    """从一段文本里取出「生成器：<路径>」 ⇒ 路径（三件事不齐或路径不是本生成器 ⇒ 空串）。"""
    if "生成物" not in 源文本 or not ("禁手改" in 源文本 or "禁手不改" in 源文本):
        return ""
    for 源码行 in 源文本.splitlines():
        if "生成器：" in 源码行:
            # 剥掉 JSON 的收尾标点：JSON 值恒带 `"`（有时还有 `,`），
            # 不剥则取出的路径永远多两个字符 ⇒ 与真生成器路径对不上 ⇒ 记账恒被拒。
            自称 = 源码行.split("生成器：", 1)[1].strip().strip('",').strip()
            if 自称 == 生成器路径:
                return 自称
    return ""


def 读生成器声明(件路径: Path, 生成器路径: str) -> str:
    """件**自称的生成器路径**（注释形 `// 生成器：<路径>` · JSON 值里的同文 · 或二进制件里某张表的同一行）；
    不自称 ⇒ 空串。

    认的是**产物自身的声明**（README §九「生成物被手改即为违规」· 判据 ⑩ 的产物头标四件事）——
    那是「这是生成物、禁手改」的**唯一标记**。本件只**读**它，不另立第二套口径/清单。

    **两段窗口**（实测 2026-09-29 补）：
      · 头 400 行 —— 文本产物（`.rs`/`.json`）的头标就住在那里（原先只读 40 行 ⇒
        `契约声明/src/声明数据.rs` 的 `生成器：` 在逐文件指纹清单之后 ⇒ 恒判「不自称」）；
      · **退到全文** —— 二进制产物（规则库 `信息核心.db`）**带不了头标**：它是 sqlite，第 0 字节
        必须是 `SQLite format 3\0`；而声明是一行数据（表 `元`），落在文件里的某处（实测 137 KB 处，
        而头 400 行只到 15 KB）⇒ 只看头就恒拒，连开工都释放不了。
    为何敢放宽：判据 ⑩ 判的是**文本生成物的头标**（窗口 = 头部）；本件要的是「这个件自称由哪个
    生成器产出」这个**事实**，与它落在文件哪个位置无关（两个窗口本来就不同，见本件开头那句）。
    """
    try:
        全文 = 件路径.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    自称 = (_取声明("\n".join(全文.splitlines()[:400]), 生成器路径)
            or _取声明(全文, 生成器路径))
    if 自称:
        return 自称
    # ★ 债务 581：仓外工具（cargo 一类）不写中文头标，只留它自带的英文注释 ⇒ 逐字认它产物头的
    #   标记对（表见 `外部生成器标记表`）。窗口同「头 400 行」那一档（外部工具的产物头恒在头部）。
    外部标记对 = 外部生成器标记表.get(Path(生成器路径).name)
    if 外部标记对 and all(标记 in "\n".join(全文.splitlines()[:400]) for 标记 in 外部标记对):
        return 生成器路径
    return ""


def 记生成物账(仓根, 开工号: str, 生成器: str, 命令行参数) -> tuple:
    """跑生成器 → 把**它写过的件**记进账本 ⇒ `(退出码, 说明)`。"""
    连接 = 账本.连账本()
    try:
        一条开工 = 账本.读开工(连接, 开工号)
        if not 一条开工:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记" % 开工号
        if 一条开工["状态"] != 账本.状态_进行中:
            return 1, "这条开工的状态是「%s」⇒ 不能再记账" % 一条开工["状态"]
        工作树 = Path(一条开工["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再记账" % 工作树
        相对 = str(生成器 or "").strip()
        if not 相对:
            return 2, ("功能 = 5 要 `生成器`（仓内相对路径，如 `构建装配/形态装配/生成声明.py`；"
                     "或 `外部生成器标记表` 里的仓外工具名，如 `cargo`）")
        # ★ 债务 581：仓外工具（只认表里那几个）走 PATH 上的真命令；其余照旧只认**仓内相对路径**
        #   （`.py` 走解释器、别的后缀直接执行 —— 原先写死 `.py` ⇒ 仓内可执行生成器也传不进来）。
        if 相对 in 外部生成器标记表:
            命令 = [相对]
        else:
            if 相对.startswith("/") or ".." in Path(相对).parts:
                return 2, "`生成器` 只认仓内相对路径（不许绝对路径 / 不许 `..`）：%r" % 相对
            if not (工作树 / 相对).is_file():
                return 1, "生成器不在工作树里：%s" % 相对
            # 仓内非 `.py` 可执行必须给**绝对路径**：子进程起不带斜杠的名字会走 PATH 查（实测 -2 起不了）。
            命令 = ([sys.executable, 相对] if 相对.endswith(".py")
                 else [str(工作树 / 相对)])
        命令行参数 = ([str(参数项) for 参数项 in 命令行参数] if isinstance(命令行参数, (list, tuple))
            else ([] if not 命令行参数 else [str(命令行参数)]))

        跑前 = 脏件指纹(工作树)
        if 跑前 is None:
            return 1, "查不清盘上动了什么（git status 失败）⇒ 没跑生成器、没记账"
        退出码, 输出文本 = 跑命令(命令 + 命令行参数, cwd=工作树, 超时秒数=超时秒)
        if 退出码 != 0:
            return 1, ("生成器没跑通（退出码 %d）⇒ **一件都不记**（账本一个字没动）：\n%s"
                     % (退出码, 输出文本.strip()[-500:]))
        跑后 = 脏件指纹(工作树)
        if 跑后 is None:
            return 1, "生成器跑完了，但查不清盘上动了什么（git status 失败）⇒ 一件都不记"
        候选路径表 = sorted(set(跑前) | set(跑后))
        # ★ 候选集取**跑前 ∪ 跑后**（2026-10-13 修 · 债务 532）：原先只遍历「跑后」，于是
        #   「跑前脏、跑后干净」的件进不了候选 —— 生成器把件写回与 HEAD 逐字节一致时
        #   （回退、或重跑产出旧版）git status 不再列它 ⇒ 认领表里更早那次的指纹永远洗不掉
        #   （`补充认领` 按设计拒洗漂移件），释放恒拒「有人绕过 v1_edit 直接改了盘」，
        #   而盘上其实与 HEAD 一模一样、根本没有绕过。
        写过表 = []
        for 路径 in 候选路径表:
            写前 = 跑前.get(路径) or ""
            写后 = 跑后.get(路径)
            if 写后 is None:
                # 跑前脏、跑后干净 ⇒ 盘上现内容就是 HEAD 内容（件不在盘上 = 空串）。
                写后 = 文件指纹(str(工作树 / 路径)) if (工作树 / 路径).is_file() else ""
            if 写前 == 写后:
                continue
            写过表.append((路径, 写前, 写后))
        # 唯一来源 = **产物自身的头标**（README §九 · 判据 ⑩ 的产物头标四件事）：它自称由哪个
        # 生成器产出。不认这一条的件**一件都不记**（fail-closed）—— 闸不放宽到「跑什么都记」。
        非产物表 = [路径 for 路径, _, _ in 写过表 if 读生成器声明(工作树 / 路径, 相对) != 相对]
        if 非产物表:
            return 1, ("生成器这次写过的件里，有**没自称是本生成器产物**的 ⇒ **一件都不记**：\n  %s\n"
                     "（头标要同时有「生成物」「禁手改」（或写成「禁手不改」）与 `生成器：%s` 一处 —— 判据 ⑩ 的口径；"
                     "注释形与 JSON 值都认）"
                     % (" · ".join(非产物表), 相对))
        认领表 = 账本.读认领(连接, 开工号)
        改过表 = {一条改动["路径"] for 一条改动 in 账本.读改动(连接, 开工号)}
        for 路径, 写前, 写后 in 写过表:
            账本.写回指纹(连接, 开工号, 路径, 写后)
            账本.记改动(连接, 开工号, 路径, 改动档名, 认领表.get(路径) or 写前, 写后)
        输出行表 = ["%s：生成器 %s 跑通，记账 %d 件（功能「%s」）"
                 % (开工号, 相对, len(写过表), 改动档名)]
        if 写过表:
            输出行表 += ["  %s（写后 %s）" % (路径, 写后 or "件没了")
                      for 路径, _, 写后 in 写过表]
        else:
            输出行表.append("  （生成器没写出任何变化 —— 产出已是最新，无需记账）")
        越界表 = sorted(路径 for 路径 in 跑后
                     if 路径 not in 改过表 and 路径 not in {节点件 for 节点件, _, _ in 写过表})
        if 越界表:
            输出行表.append("★ 另有这些件脏、且不在改动表（**不是这次生成器写的**）⇒ 释放仍会拒：%s"
                        % " · ".join(越界表))
        return 0, "\n".join(输出行表)
    finally:
        连接.close()
