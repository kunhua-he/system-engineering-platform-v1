"""命名闸 —— `v1_edit` 第 ⑤ 道闸（命名登记）的名册读口与条目排版。

**为什么单开一件**（判据 ⑲ 单源文件 ≤400 行）：`修改.py` 给第 ⑤ 道闸补「带位置的未登记条目」
之后越限；一个关注点一个文件 —— 名册读口（`读名册`）与条目排版（`排命名条目`）与 `修改.py`
的闸序无关，搬到这里，`修改.py` 再导入（`批量改名.py` 从 `修改` 取的 `读名册` 照旧可用）。

依据：华哥 2026-09-28「出现即须定义，未定义即红」· 2026-09-29「用规则管 · 直接提示错误」。
"""

from pathlib import Path


def 读名册(工作树: Path) -> tuple:
    """⇒ `(已登记合格名, 例外名)` —— 读**这棵工作树**的规则库；读不动 ⇒ 抛 `表定义.库读不动`。

    只认 `命名登记` 里 `状态='合格'` 的行（`待改名` 的行是**待改的债**，不能拿来当新名）；
    外部强加的名住 `命名例外`，一并放行。**fail-closed**：库不在 / 读不动一律抛，绝不当空名册用。
    """
    import sqlite3
    import sys as _sys

    工具根 = Path(__file__).resolve().parents[2]
    for 子目录 in (str(工具根 / "开发工具"), str(工具根 / "开发工具" / "信息核心")):
        if 子目录 not in _sys.path:
            _sys.path.insert(0, 子目录)
    import 表定义

    库件 = 表定义.库路径(工作树)
    if not Path(库件).is_file():
        raise 表定义.库读不动("规则库不在：%s" % 库件)
    连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
    try:
        已登记 = {文本行[0] for 文本行 in 连接.execute("select 名字 from 命名登记 where 状态='合格'")}
        例外 = {文本行[0] for 文本行 in 连接.execute("select 名字 from 命名例外")}
    except sqlite3.Error as 错误:
        raise 表定义.库读不动("规则库读不动：%s" % 错误) from 错误
    finally:
        连接.close()
    return 已登记, 例外


def 排命名条目(条目表: list) -> str:
    """把 `(相对路径, 行号, 名)` 条目排成按件分组的多行文本 ⇒ 每行「  件:行 · 名」。

    **一处实现，两处用**：`修改.py` 的拒写消息（`派发`）与只读预检（`批量预检.扫一遍`）共用。
    为什么必须带位置（2026-10-07 审计实证：有腿撞了四轮）：只列裸名，腿不知道是哪条改动引入的，
    只能反复试、反复登记。裸名子串**保留**（既有样本断言「未登记配置」一类仍绿）。
    """
    return "\n".join("  %s:%d · %s" % (路径, 行号, 绑定名)
                     for 路径, 行号, 绑定名 in sorted(set(条目表)))


def 未登记绑定名(工作树: Path, 项表: list) -> tuple:
    """新内容里**新引入的**绑定名里、名册 / 例外都不收的那些 ⇒ `(条目表, 错误或 None)`。

    条目 = `(相对路径, 行号, 名)` —— **带位置**（调用方经 `排命名条目` 打「件:行 · 名」）。
    面 = **形参 + 局部绑定 + 定义面**（2026-10-08 加：与判据 55 的定义面口径对齐 ⇒ 新写一个
    模块级函数名不再静默过闸，直到跑完闸 0 才被判据 55 打红）。扫描器与判据面**同一份**
    （`代码地图.形参面` + `一键验证.命名扫描` + 本件 `定义面条目`），不另写一套。
    **新引入** = 新内容里的绑定名 − 旧内容里已有的绑定名（**按名相减**，故同名换行不算新引入）。
    ★ **批内全部件一次扫完**（不 fail-fast）：一轮列全批的未登记名，配 `排登记载荷` 一次登完。
    ★ **fail-closed**：名册读不动 ⇒ 交错误回去，调用方**拒写**（一个字节都不写）。
    """
    import sys as _sys

    工具根 = Path(__file__).resolve().parents[2]
    for 子目录 in (str(工具根 / "开发工具"), str(工具根 / "开发工具" / "信息核心"),
                 str(工具根 / "构建装配" / "一键验证")):
        if 子目录 not in _sys.path:
            _sys.path.insert(0, 子目录)
    import 表定义
    from 代码地图 import 形参面, 查名
    import 一键验证.命名扫描 as 命名扫描
    from .写盘执行 import 功能_删除

    def 绑定条目(路径: str, 内容值: str) -> list:
        """一份内容里的形参 + 局部绑定 + **定义面** ⇒ `[(行号, 名)]`（面与判据面同一份）。"""
        件后缀 = "." + 路径.rsplit(".", 1)[-1]
        return ([(行号, 形参名) for 行号, _函, 形参名 in 形参面.扫文本(路径, 内容值, 只单字=False)]
                + 命名扫描.扫局部绑定(件后缀, 内容值, 只单字=False)
                + 定义面条目(路径, 内容值))

    try:
        已登记, 例外 = 读名册(工作树)
    except 表定义.库读不动 as 错误:
        return [], str(错误)
    未登记条目 = []
    for 路径, 功能号, 旧内容, 新内容, _全替 in 项表:
        if 功能号 == 功能_删除 or not 新内容 or not 路径.endswith(查名.命名后缀):
            continue
        旧名集 = {绑定名 for _行号, 绑定名 in 绑定条目(路径, 旧内容)} if 旧内容 else set()
        for 行号, 绑定名 in 绑定条目(路径, 新内容):
            if 绑定名 in 旧名集 or 绑定名 in 已登记 or 绑定名 in 例外:
                continue
            未登记条目.append((路径, 行号, 绑定名))
    return sorted(set(未登记条目)), None


def 定义面条目(路径: str, 内容值: str) -> list:
    """一份内容里的**定义面**名 ⇒ `[(行号, 名)]`（与判据 55 的面同口径）。

    **为何单列**（2026-10-08 · 闸⑤ 与判据 55 对齐）：`v1_edit` 第 ⑤ 道闸原先只扫**形参 + 局部绑定**
    ⇒ 新写一个**模块级函数名**会静默过闸，直到跑完整个闸 0 才被判据 55 打红（写完才知道要补落库）。
    本面把**定义面**也收进闸⑤（面 ⊆ 判据 55 的面 ⇒ 闸⑤ 拦下的，判据 55 本来也会红 —— 不再事后）。

    口径主人：面的判定走 `落库.判面`（定义面的口径只此一份）· 标识符走
    `命名扫描.抽标识符带位置` · 过滤走 `落库.过滤名`（语言关键字 + 内建噪声）—— 本件不自写启发式。
    """
    import sys as _sys
    from pathlib import Path as _路径
    工具根 = _路径(__file__).resolve().parents[2]
    for 子目录 in (str(工具根 / "开发工具"), str(工具根 / "开发工具" / "信息核心"),
                 str(工具根 / "构建装配" / "一键验证")):
        if 子目录 not in _sys.path:
            _sys.path.insert(0, 子目录)
    import 落库, 一键验证.命名扫描 as 命名扫描
    条目表 = []
    净文本 = 命名扫描.剥后缀("." + 路径.rsplit(".", 1)[-1], 内容值)
    for 行号, 行文本 in enumerate(净文本.splitlines(), 1):
        for 标识符, _起始 in 命名扫描.抽标识符带位置(行文本):
            if 标识符 in 落库.过滤名:
                continue
            if 落库.判面(行文本, 标识符) == "定义面":
                条目表.append((行号, 标识符))
    return 条目表


def 排登记载荷(条目表: list) -> str:
    """未登记条目 ⇒ **可直接粘贴**的 `信息核心.py 登记` 载荷（逐名一行）。

    为何要它（2026-10-08）：闸⑤ 的拒写消息原先只说「先登记」⇒ 调用方得照格式另拼一遍（实测
    反复试错）。把载荷排出来，复制即用；配 `v1_name 批量登记` 一次登记完。
    """
    载荷行表 = []
    for _路径名, _行号, 名字 in sorted(set(条目表)):
        载荷行表.append("python3 开发工具/信息核心/信息核心.py 登记 --名字 %s --语义 %s "
                   "--模式 对象+说明 --来源 新定义" % (名字, 名字))
    return "\n".join(载荷行表)
