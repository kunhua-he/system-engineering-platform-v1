# -*- coding: utf-8 -*-
"""命名闸 —— `v1_edit` 第 ⑤ 道闸（命名登记）的名册读口与条目排版。

**为什么单开一件**（判据 ⑲ 单源文件 ≤400 行）：`修改.py` 给第 ⑤ 道闸补「带位置的未登记条目」
之后越限；一个关注点一个文件 —— 名册读口（`读名册`）与条目排版（`排命名条目`）与 `修改.py`
的闸序无关，搬到这里，`修改.py` 再导入（`批量改名.py` 从 `修改` 取的 `读名册` 照旧可用）。

依据：华哥 2026-09-28「出现即须定义，未定义即红」· 2026-09-29「用规则管 · 直接提示错误」。
"""

import json
from pathlib import Path


def 读名册(工作树: Path) -> tuple:
    """⇒ `(已登记合格名, 例外名)` —— 读**这棵工作树**的规则库；读不动 ⇒ 抛 `表定义.库读不动`。

    只认 `命名登记` 里 `状态='合格'` 的行（`待改名` 的行是**待改的债**，不能拿来当新名）；
    外部强加的名住 `命名例外`，一并放行。**fail-closed**：库不在 / 读不动一律抛，绝不当空名册用。
    """
    import sqlite3
    import sys as _sys

    工具根 = Path(__file__).resolve().parents[2]
    for 子目录 in (str(工具根 / "开发工具"), str(工具根 / "开发工具" / "信息核心")):
        if 子目录 not in _sys.path:
            _sys.path.insert(0, 子目录)
    import 表定义

    库件 = 表定义.库路径(工作树)
    if not Path(库件).is_file():
        raise 表定义.库读不动("规则库不在：%s" % 库件)
    连接 = sqlite3.connect("file:%s?mode=ro" % 库件, uri=True)
    try:
        已登记 = {文本行[0] for 文本行 in 连接.execute("select 名字 from 命名登记 where 状态='合格'")}
        例外 = {文本行[0] for 文本行 in 连接.execute("select 名字 from 命名例外")}
    except sqlite3.Error as 错误:
        raise 表定义.库读不动("规则库读不动：%s" % 错误) from 错误
    finally:
        连接.close()
    return 已登记, 例外


def 排命名条目(条目表: list) -> str:
    """把 `(相对路径, 行号, 名)` 条目排成按件分组的多行文本 ⇒ 每行「  件:行 · 名」。

    **一处实现，两处用**：`修改.py` 的拒写消息（`派发`）与只读预检（`批量预检.扫一遍`）共用。
    为什么必须带位置（2026-10-07 审计实证：有腿撞了四轮）：只列裸名，腿不知道是哪条改动引入的，
    只能反复试、反复登记。裸名子串**保留**（既有样本断言「未登记配置」一类仍绿）。
    """
    return "\n".join("  %s:%d · %s" % (路径, 行号, 绑定名)
                     for 路径, 行号, 绑定名 in sorted(set(条目表)))


def 登记载荷(开工号: str, 条目表: list) -> str:
    """把 `(相对路径, 行号, 名)` 条目里的名字拼成一条**可粘贴的 `v1_name` 批量登记载荷**。

    **一处实现**：`修改.py` 的命名登记拒写回执用它 —— 只列裸名会让腿反复逐名登记、反复往返
    （审计实证：有腿撞了四轮）。空条目 ⇒ 空串（不拼空载荷）。
    """
    名表 = sorted({绑定名 for 路径, 行号, 绑定名 in 条目表})
    if not 名表:
        return ""
    载荷 = {"操作": "批量登记", "参数": {"名单": [[名字] for 名字 in 名表]}}
    if 开工号:
        载荷["开工ID"] = 开工号
    return ("一条可粘贴的 `v1_name` 载荷（把上面这些名一次登记完，幂等）：\n"
            + json.dumps(载荷, ensure_ascii=False))


def 映射文件行(工作树: Path, 路径: str, 是整件: bool, 旧内容: str, 片段行: int) -> int:
    """把「`新内容` 片段行号」映射回「文件行号」；映射不了 ⇒ 原样返回 `片段行`。

    **为什么**（多路代理实测）：命名闸原先直接报**片段行**，而该名实际在文件别处 ⇒ agent 去那一行
    找一个不存在的名、反复试错。片段是**替换** `旧内容` 的那一段 ⇒ 片段首行即文件里 `旧内容`
    所在行 ⇒ 文件行 = 基准 + 片段行。**新建**（`是整件`）时整件就是片段 ⇒ 基准 0。
    `旧内容` 在文件里找不到 / 出现多次 ⇒ 不敢猜，原样返回片段行。
    """
    if 是整件:
        return 片段行
    件路径 = 工作树 / 路径
    if not 件路径.is_file():
        return 片段行
    try:
        全文 = 件路径.read_text(encoding="utf-8", newline="\n")
    except (UnicodeDecodeError, OSError):
        return 片段行
    if not 旧内容 or 全文.count(旧内容) != 1:
        return 片段行
    return 全文[:全文.find(旧内容)].count("\n") + 片段行
