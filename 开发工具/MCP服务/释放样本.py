    件路径.write_text("print('夹具门禁通过')\n", encoding="utf-8")
    执行命令(["git", "add", "--", "样本.txt", "构建装配/一键验证/闸0.py"])
    执行命令(["git", "commit", "-m", "夹具基线"])
