"""合主干集成树 —— 从主干建隔离集成工作树、合腿、提交合并、推进主干、同步主工作区。

集成树落在**系统临时目录**（仓外）⇒ 全仓扫描看不见它（同并行工作树落仓外的理由），
且**不在仓内自建以「系统工程平台V1」开头的目录名**（那会踩判据 ㉕）。
"""

import hashlib
import os
import stat
import shutil
import sys
import tempfile
from pathlib import Path

from .合主干有界跑 import 跑有界命令
from . import 合主干门禁 as 门禁


def _跑(命令表, 工作目录, 超时秒数=None, 输入文本=None):
    return 跑有界命令(命令表, 工作目录=工作目录, 超时秒数=超时秒数, 输入文本=输入文本, 保留日志=True)


def 定位主仓(候选目录):
    """从脚本所在树的公共 Git 元目录定位本项目主仓，拒绝元目录自身。"""
    候选目录 = Path(候选目录).resolve()
    退出码, 输出文本, 日志路径 = _跑(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"], 候选目录, 超时秒数=5)
    if 退出码 != 0:
        return 退出码, "主仓定位失败：%s · 日志 %s" % (输出文本, 日志路径)
    元目录 = Path(输出文本.strip()).resolve()
    主目录 = 元目录.parent
    if 元目录.name != ".git" or 候选目录 == 元目录 or not 元目录.is_dir():
        return 1, "公共元目录不是本项目主目录/.git：%s" % 元目录
    try:
        if "系统工程平台 V1" not in (主目录 / "README.md").read_text(encoding="utf-8") or not (主目录 / "AGENTS.md").is_file():
            return 1, "主仓标识不符：%s" % 主目录
    except OSError as 错误:
        return 1, "主仓标识读不出：%s" % 错误
    退出码, 输出文本, 日志路径 = _跑(["git", "rev-parse", "--verify", "refs/heads/主干"], 主目录, 超时秒数=5)
    if 退出码 != 0:
        return 退出码, "主干引用读不出：%s · 日志 %s" % (输出文本, 日志路径)
    return 0, 主目录


def 找集成树(仓根, 开工号):
    退出码, 输出文本, _ = _跑(["git", "worktree", "list", "--porcelain"], 仓根, 超时秒数=5)
    if 退出码 != 0:
        return None
    当前路径 = None
    for 数据行 in 输出文本.splitlines():
        if 数据行.startswith("worktree "):
            当前路径 = Path(数据行[9:]).resolve()
        elif 数据行 == "branch refs/heads/集成/" + 开工号:
            return 当前路径
    return None


def 核工作文件(主目录, 引用):
    """逐件核真实字节与模式，不信任 index 的跳过检查标记。"""
    命令头 = ["git", "--git-dir", str(Path(主目录) / ".git"), "--work-tree", str(主目录)]
    退出码, 输出文本, 日志路径 = _跑(命令头 + ["ls-tree", "-rz", 引用], 主目录, 超时秒数=5)
    if 退出码 != 0:
        return 退出码, "读提交文件失败：%s · 日志 %s" % (输出文本, 日志路径)
    # ls-tree 返回可能超过回执上限，完整内容从日志的标准输出段读取。
    全文 = Path(日志路径).read_text(encoding="utf-8")
    输出文本 = 全文.split("=== 标准输出 ===\n", 1)[1].split("=== 标准错误 ===\n", 1)[0]
    差异表 = []
    文件数 = 0
    for 数据行 in 输出文本.split("\0"):
        if not 数据行.strip():
            continue
        元信息, 路径 = 数据行.split("\t", 1)
        模式, 类型, 指纹 = 元信息.split()
        件路径 = Path(主目录) / 路径
        文件数 += 1
        try:
            if 类型 != "blob":
                差异表.append(路径 + "（不支持的提交类型）")
                continue
            文件字节 = os.readlink(件路径).encode() if 模式 == "120000" else 件路径.read_bytes()
            实际指纹 = hashlib.sha1(b"blob " + str(len(文件字节)).encode() + b"\0" + 文件字节).hexdigest()
            实际模式 = "120000" if 件路径.is_symlink() else ("100755" if 件路径.stat().st_mode & stat.S_IXUSR else "100644")
            if 实际指纹 != 指纹 or 实际模式 != 模式:
                差异表.append(路径)
        except OSError:
            差异表.append(路径)
    if 差异表:
        return 1, "实际工作文件与 %s 不等：%s（共%d件，现场 %s）" % (引用, " · ".join(差异表[:20]), len(差异表), 主目录)
    return 0, "实际工作文件 %d 件字节及模式 == %s（目标 %s）" % (文件数, 引用, 主目录)


def 建集成树(仓根, 开工号) -> tuple:
    """从主干建隔离集成工作树 ⇒ (退出码, 路径 或 说明)。"""
    已有树 = 找集成树(仓根, 开工号)
    if 已有树:
        return 1, "已有集成现场 %s ⇒ 用 --查看现场 / --恢复现场 / --清理现场，不再建树" % 已有树
    路径 = tempfile.mkdtemp(prefix="v1集成-")
    分支 = "集成/" + 开工号
    退出码, 输出文本, _ = _跑(["git", "worktree", "add", "-b", 分支, 路径, "主干"], 工作目录=仓根, 超时秒数=None)
    if 退出码 != 0:
        shutil.rmtree(路径, ignore_errors=True)
        return 退出码, "建集成树失败：%s" % 输出文本.strip()[-500:]
    return 0, 路径


def 合腿(集成树, 腿分支) -> tuple:
    """在集成树里合腿 ⇒ (退出码, 说明, 冲突文件表)。--no-ff 保证造合并提交（不走 ff）。"""
    退出码, 输出文本, 日志路径 = _跑(["git", "merge", "--no-commit", "--no-ff", 腿分支], 工作目录=集成树, 超时秒数=None)
    _, 输出2, _ = _跑(["git", "diff", "--name-only", "--diff-filter=U"], 工作目录=集成树)
    冲突表 = [数据行.strip() for 数据行 in 输出2.splitlines() if 数据行.strip()]
    if 冲突表:
        return 0, "合腿有冲突 · 原始退出码 %d · 是否超时 %s · 日志 %s\n%s" % (退出码, 退出码 == -1, 日志路径, 输出文本[:1500]), 冲突表
    if 退出码 != 0:
        return 退出码, "合腿失败 · 退出码 %d · 是否超时 %s · 日志 %s\n%s" % (退出码, 退出码 == -1, 日志路径, 输出文本[:1500]), []
    return 0, "合腿干净（无冲突）", []


def 提交合并(集成树, 腿分支, 开工号) -> tuple:
    """提交集成树的合并 ⇒ (退出码, 说明)，正常执行 Git 提交钩子。"""
    提交信息 = "合并 %s 进主干（隔离集成校验通过）\n\n开工号 %s\n" % (腿分支, 开工号)
    退出码, 输出文本, _ = _跑(["git", "commit", "-F", "-"],
                 工作目录=集成树, 超时秒数=None, 输入文本=提交信息)
    if 退出码 != 0:
        return 退出码, ("提交合并失败（退出码 %d；钩子拒也会落这里 —— 钩子那边打的读数在下面）:\n%s"
                    % (退出码, 输出文本.strip()[-1200:]))
    return 0, "合并提交已造（门禁随提交跑过一遍）"


def 提交恢复现场(集成路径, 腿分支, 开工号, 行表) -> tuple:
    """`--恢复现场` 的提交支 ⇒ (退出码, 说明)。树脏 ⇒ 重放结果一并提交（门禁随提交跑）；树干净 ⇒ 显式跑一遍。

    为什么树脏要再提交：重放会再写一遍源库（`创建时间` 默认 `datetime('now')` ⇒ 字节非确定）⇒
    不再提交的话 ④ 的「index == 提交树」核验必拒（2026-10-08 收口方实测）。让恢复可安全重跑。
    """
    退出码, 脏输出, _ = _跑(["git", "status", "--porcelain", "-uall"], 集成路径, 超时秒数=5)
    if 退出码 != 0:
        return 1, "恢复现场读不出集成树状态：%s" % 脏输出.strip()[-300:]
    if 脏输出.strip():
        退出码, 说明 = 提交合并(集成路径, 腿分支, 开工号)
        if 退出码 == 0:
            行表.append("   重放后集成树又变脏（源库时间默认值非确定）⇒ 把重放结果一并提交（门禁随提交跑）")
        return 退出码, 说明
    退出码, 门禁行表, 尾部 = 门禁.跑集成门禁(集成路径)
    行表.extend(门禁行表)
    if 退出码 != 0:
        return 退出码, 尾部[:1500]
    退出码, _, _ = _跑(["git", "merge-base", "--is-ancestor", 腿分支, "HEAD"], 集成路径, 超时秒数=5)
    return 退出码, "恢复现场已有提交（无新改动，不造空提交）；腿分支祖先核验退出码 %d" % 退出码


def 推进主干(仓根, 集成提交, 集成树) -> tuple:
    """优先 ff-only；附 tree 相等核验与三方一致复核 ⇒ (退出码, 说明)。"""
    _, 旧提交, _ = _跑(["git", "rev-parse", "主干"], 工作目录=仓根)
    旧提交 = 旧提交.strip()
    _, 提交树, _ = _跑(["git", "rev-parse", "%s^{tree}" % 集成提交], 工作目录=仓根)
    _, 索引树, _ = _跑(["git", "write-tree"], 工作目录=集成树)
    if 提交树.strip() != 索引树.strip():
        return 1, "集成树 index 与提交树不等（%s ≠ %s）⇒ 拒绝推进" % (索引树.strip(), 提交树.strip())
    _, 头提交, _ = _跑(["git", "rev-parse", "HEAD"], 工作目录=集成树)
    if 头提交.strip() != 集成提交:
        return 1, "集成树 HEAD %s ≠ 集成提交 %s ⇒ 拒绝推进" % (头提交.strip(), 集成提交)
    _, 脏输出, _ = _跑(["git", "status", "--porcelain", "-uall"], 工作目录=集成树)
    if 脏输出.strip():
        return 1, "集成树有未提交改动 ⇒ 拒绝推进：%s" % 脏输出.strip()[-300:]
    退出码, _, _ = _跑(["git", "merge-base", "--is-ancestor", 旧提交, 集成提交], 工作目录=仓根)
    if 退出码 != 0:
        return 1, "主干 %s 不是集成提交 %s 的祖先 ⇒ 非 ff，拒绝" % (旧提交, 集成提交)
    临时树 = tempfile.mkdtemp(prefix="v1主干-")
    shutil.rmtree(临时树, ignore_errors=True)
    退出码, 输出文本, _ = _跑(["git", "worktree", "add", 临时树, "主干"], 工作目录=仓根, 超时秒数=None)
    if 退出码 == 0:
        退出码2, 输出2, _ = _跑(["git", "merge", "--ff-only", 集成提交], 工作目录=临时树, 超时秒数=None)
        _跑(["git", "worktree", "remove", "--force", 临时树], 工作目录=仓根, 超时秒数=None)
        shutil.rmtree(临时树, ignore_errors=True)
        if 退出码2 != 0:
            return 退出码2, "ff-only 推进失败：%s" % 输出2.strip()[-400:]
        说明 = "ff-only（临时工作树 + merge --ff-only）"
    else:
        shutil.rmtree(临时树, ignore_errors=True)
        退出码3, 输出3, _ = _跑(["git", "update-ref", "refs/heads/主干", 集成提交, 旧提交], 工作目录=仓根)
        if 退出码3 != 0:
            return 退出码3, "update-ref 推进失败：%s" % 输出3.strip()[-400:]
        说明 = "update-ref（已附 tree 相等核验 + 三方一致复核 + 祖先核验）"
    _, 新提交, _ = _跑(["git", "rev-parse", "主干"], 工作目录=仓根)
    if 新提交.strip() != 集成提交:
        return 1, "推进后主干 %s ≠ 集成提交 %s ⇒ 异常" % (新提交.strip(), 集成提交)
    return 0, "主干 %s → %s（%s）" % (旧提交[:8], 集成提交[:8], 说明)


def 核主索引(主目录, 引用):
    命令头 = ["git", "--git-dir", str(Path(主目录) / ".git"), "--work-tree", str(主目录)]
    退出码, 索引, 日志路径 = _跑(命令头 + ["write-tree"], 主目录, 超时秒数=5)
    退出码2, 提交树, _ = _跑(命令头 + ["rev-parse", 引用 + "^{tree}"], 主目录, 超时秒数=5)
    if 退出码 != 0 or 退出码2 != 0 or 索引.strip() != 提交树.strip():
        return 1, "index 与旧提交不同，保留 %s · 日志 %s" % (主目录, 日志路径)
    return 0, "index == 旧提交树"


def 重建代码地图索引(工作树) -> tuple:
    """在那棵树里重建代码地图索引 ⇒ (退出码, 说明)。**复用 `仓操作.建工作树索引`**（一处实现，不抄命令）。"""
    from .仓操作 import 建工作树索引
    return 建工作树索引(Path(工作树))


def 对齐本机生成物(主目录) -> tuple:
    """主干已推进后对齐**主树本机生成物**（代码地图索引 + 派生缓存）⇒ (退出码, 说明)。幂等、可同提交重试。

    **唯一可跳过（返回 0）**：该树不带 `开发工具/代码地图.py`（不是本项目源码树 ⇒ 没有要对齐的生成物）。
    **索引器 `codegraph` 不在 ⇒ 不是跳过，是「未完成」（返回非 0）**：索引建不了、派生缓存也建不了，
    必须如实报「未完成」并保现场，由 `--对齐索引` 同提交重试（装回索引器即可转绿）——不得回 0
    短路派生库的 fail-closed。索引重建复用 `仓操作.建工作树索引`（其内部 `索引器超时秒` 5 秒不动）；
    派生缓存重建走 `信息核心.py 建派生库`（**只写派生库**，绝不重写受版本的规则库）。
    """
    主目录 = Path(主目录)
    if not (主目录 / "开发工具/代码地图.py").is_file():
        return 0, "跳过（该树不带 开发工具/代码地图.py ⇒ 不是本项目源码树）"
    from . import 仓操作  # noqa: F401 —— 它 import 时把 `开发工具/` 挂上 sys.path
    from 代码地图.索引库 import 找索引器命令
    if not 找索引器命令():
        return 1, ("主树代码地图索引未完成（索引器 codegraph 不在 ⇒ 索引建不了、派生缓存也建不了）；"
                 "装回索引器后同提交重试 `合并主干.py <开工号> --对齐索引`")
    退出码, 说明 = 重建代码地图索引(主目录)
    if 退出码 != 0:
        return 1, "主树代码地图索引重建失败（退出码 %d）：%s" % (退出码, 说明.strip()[-300:])
    行表 = ["主树代码地图索引已重建"]
    if (主目录 / "开发工具/信息核心/建库").is_dir():
        from .合主干源库重放 import 信息核心入口
        退出码, 说明, _ = 跑有界命令([sys.executable, 信息核心入口, "建派生库"],
                                 工作目录=主目录, 超时秒数=None)
        if 退出码 != 0:
            return 1, "；".join(行表 + ["主树派生缓存重建失败（退出码 %d）：%s"
                                    % (退出码, 说明.strip()[-300:])])
        行表.append("主树派生缓存已重建")
    return 0, "；".join(行表)


def 同步主工作区(主目录, 同步前提交=None):
    """仅从已核旧提交更新已跟踪件，未知差异与未跟踪碰撞拒绝。

    三道保护依次是：`核工作文件`（**内容级**逐件 sha1 + 模式）· `核主索引`（**树级**）·
    `update-index --really-refresh`（**stat 级**，把 index 的 uptodate 标记对齐盘面）——
    最后一道专补 `read-tree -u -m` 的 stat 级判定与前两道内容级之间的口径差（见 314）。

    收尾再对齐**主树本机生成物**（代码地图索引 + 派生缓存，见 `对齐本机生成物`）：失败给 **2**
    （调用方据此如实报「主干已推进 · 对齐未完成」，不假称整体合并零写）。
    """
    主目录 = Path(主目录).resolve()
    退出码, 定位 = 定位主仓(主目录)
    if 退出码 != 0 or 定位 != 主目录:
        return 1, "同步目标不是公共主仓：%s（%s）" % (主目录, 定位)
    命令头 = ["git", "--git-dir", str(主目录 / ".git"), "--work-tree", str(主目录)]
    同步前提交 = 同步前提交 or "主干"
    退出码, 说明 = 核工作文件(主目录, 同步前提交)
    if 退出码 != 0:
        return 退出码, "同步保护拒绝：" + 说明
    退出码, 说明 = 核主索引(主目录, 同步前提交)
    if 退出码 != 0:
        return 退出码, "同步保护拒绝：" + 说明
    # ★ 补齐「**stat 级** vs **内容级**」的口径差（2026-10-09 实测 v1-100641 真实合并发作）：
    #   `read-tree -u -m` 用 **stat 级** uptodate 判定，而上面两道保护是**内容级**
    #   （`核工作文件` 逐件 sha1 · `核主索引` 树相等）⇒ 被外部重写过、**字节相同但 mtime 变**
    #   的件能过保护却在落刀那步被拒（退出码 128 · `error: Entry '…' not uptodate. Cannot merge.`）。
    #   真实发作：2026-10-09 04:14 合并 v1-100641，④ 已把主干推到新提交、⑤ 在此被拒 ⇒ 半推进态。
    #   落刀前先做一次 stat 级刷新把口径对齐；**非 0 即 fail-closed**（真未提交改动仍被拒 ——
    #   内容级两道保护先行挡住，此处是兜底，不洗白任何真差异）。
    退出码, 输出文本, 日志路径 = _跑(命令头 + ["update-index", "--really-refresh"], 主目录, 超时秒数=5)
    if 退出码 != 0:
        return 1, ("同步保护拒绝：index 刷新不过（真未提交改动 / 半态索引）· 退出码 %d · 日志 %s\n%s"
                 % (退出码, 日志路径, 输出文本.strip()[-400:]))
    退出码, 输出文本, 日志路径 = _跑(命令头 + ["read-tree", "-u", "-m", 同步前提交, "主干"], 主目录, 超时秒数=5)
    if 退出码 != 0:
        return 退出码, "同步目标 %s · 退出码 %d · 是否超时 %s · 日志 %s\n%s" % (主目录, 退出码, 退出码 == -1, 日志路径, 输出文本[:1500])
    退出码, 说明 = 核工作文件(主目录, "主干")
    退出码2, 索引, _ = _跑(命令头 + ["write-tree"], 主目录, 超时秒数=5)
    退出码3, 提交树, _ = _跑(命令头 + ["rev-parse", "主干^{tree}"], 主目录, 超时秒数=5)
    if 退出码 != 0 or 退出码2 != 0 or 退出码3 != 0 or 索引.strip() != 提交树.strip():
        return 1, "同步核验失败：%s；index %s · 提交树 %s" % (说明, 索引.strip(), 提交树.strip())
    行表 = ["%s；index == 提交树 %s；未跟踪件保留" % (说明, 提交树.strip())]
    退出码, 说明 = 对齐本机生成物(主目录)
    if 退出码 != 0:
        return 2, "；".join(行表 + ["★ 主干已推进 · 对齐未完成：%s；同提交重试："
                                "`合并主干.py <开工号> --对齐索引`，再 `--清理现场`" % 说明])
    行表.append(说明)
    return 0, "；".join(行表)


def 清集成树(仓根, 集成树, 开工号):
    """只清可证明干净且已入主干的已知集成树。"""
    已有树 = 找集成树(仓根, 开工号)
    if 已有树 is None:
        return 1, "查不到已知集成树，拒绝清理"
    if 已有树 != Path(集成树).resolve():
        return 1, "集成目标不符，拒绝清理"
    退出码, 输出文本, 日志路径 = _跑(["git", "status", "--porcelain", "-uall"], 已有树, 超时秒数=5)
    if 退出码 != 0 or 输出文本.strip():
        return 1, "现场有未提交/未跟踪成果，拒绝清理：%s · 日志 %s" % (已有树, 日志路径)
    退出码, _, 日志路径 = _跑(["git", "merge-base", "--is-ancestor", "集成/" + 开工号, "主干"], 仓根, 超时秒数=5)
    if 退出码 != 0:
        return 1, "集成提交尚未进入主干，拒绝清理：%s · 日志 %s" % (已有树, 日志路径)
    退出码, 输出文本, 日志路径 = _跑(["git", "worktree", "remove", str(已有树)], 仓根)
    if 退出码 != 0:
        return 退出码, "清理失败：%s · 日志 %s" % (输出文本, 日志路径)
    退出码, 输出文本, 日志路径 = _跑(["git", "branch", "-d", "集成/" + 开工号], 仓根)
    return 退出码, "集成树清理退出码 %d · 日志 %s\n%s" % (退出码, 日志路径, 输出文本)
