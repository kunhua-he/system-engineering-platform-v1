# -*- coding: utf-8 -*-
"""写盘恢复 —— `v1_edit` 操作 `恢复`：据**写盘意图**把盘账收敛到一致态。

**它修的是什么**（2026-10-08 隔离复现）：原实现两次提交（写回指纹 / 记改动）之间没有归属，
一次崩溃就能留下「盘已写、认领指纹已新、改动行没有」，而释放的越界检测拿它当「没走过 v1_edit」
拒整条腿。本模块不上新架构：它只**读既有意图**（落盘前写的）与**盘上当前指纹**，二者都对得上
才补记 —— **不洗指纹、不凭空造改动、不拿「重跑原修改」当恢复**（原修改的内容已经变，重跑必卡）。

**三态**（每一条意图只看盘上指纹）：
  · `盘上 == 写前指纹` ⇒ **没写成**：件没动（临时件加更换是原子的）⇒ 销意图，不记账。
  · `盘上 == 期望写后指纹` ⇒ **写成了、账没记**：走 `记一件写盘`（与正常写盘同一事务）补上认领
    指纹 + 改动行（带说明「据写盘意图恢复」），并销意图。
  · 其余 ⇒ **外部漂移**：盘上既不是写前也不是期望写后 —— 那是人 / 别的工具动的，**拒**（不碰它、
    不清意图、不改账），逐件报出。

★ **同一个意图第二次跑**：若该件在改动表里已有「写后指纹 == 盘上」的行 ⇒ 只销意图，不重复记
（幂等，重跑不灌垃圾行）。
"""

from pathlib import Path

from 代码地图 import 文件指纹

from . import 开工账本 as 账本
from .写盘账本 import 列写盘意图, 销写盘意图, 补意图表, 记一件写盘


def 分漂移(工作树: Path, 认领表: dict, 意图表: list) -> tuple:
    """把每条意图按盘上指纹归成 `(自错表, 未写成表, 外部表)`。

    自错表 = `(意图行, 盘上指纹)`，盘上已到期望写后；未写成表 = 盘上仍是写前；
    外部表 = `(意图行, 盘上指纹)`，盘上指纹既非写前也非期望写后（**不猜、不碰**）。
    """
    自错表, 未写成表, 外部表 = [], [], []
    for 意图行 in 意图表:
        路径 = 意图行["路径"]
        件路径 = 工作树 / 路径
        盘上指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
        写前指纹 = 意图行["写前指纹"] or ""
        期望写后指纹 = 意图行["期望写后指纹"] or ""
        if 盘上指纹 == 写前指纹:
            未写成表.append((意图行, 盘上指纹))
        elif 盘上指纹 == 期望写后指纹:
            自错表.append((意图行, 盘上指纹))
        else:
            外部表.append((意图行, 盘上指纹))
    return 自错表, 未写成表, 外部表


def 分类漂移(工作树: Path, 变过表: dict, 意图表: list) -> tuple:
    """把**对账报「变过」的件**按未决意图拆成 `(自错表, 外部表)` ⇒ `{路径: (账本指纹, 盘上指纹)}`。

    **谁调它**：`释放`（`开工.py`）与绕过检测（`门禁.py`）—— 它们原先一句「有人绕过 v1_edit
    直接改了盘」把**工具自错**（盘已写、记账中途失败，盘上指纹恰是意图里的期望写后）与
    **外部漂移**（人 / 别的工具改的）混成一类报；自错件被当成用户绕写拒整条腿，且 `功能=2`
    洗不了那个不可导出变动的指纹。本函数只认「盘上 == 意图期望写后」 ⇒ 自错（可 `恢复`）；
    盘上指纹既非写前也非期望写后 ⇒ 外部（照旧当绕过）。**不猜、不洗账**。
    """
    意图指纹表 = {意图行["路径"]: 意图行 for 意图行 in 意图表}
    自错表, 外部表 = {}, {}
    for 路径, 键值对 in 变过表.items():
        意图行 = 意图指纹表.get(路径)
        件路径 = 工作树 / 路径
        盘上指纹 = 文件指纹(str(件路径)) if 件路径.is_file() else ""
        if 意图行 and 盘上指纹 == (意图行["期望写后指纹"] or ""):
            自错表[路径] = 键值对
        else:
            外部表[路径] = 键值对
    return 自错表, 外部表


def 恢复一次(连接, 工作树: Path, 开工号: str) -> tuple:
    """按意图逐件收敛 ⇒ `(退出码, 说明, 已收敛行表, 拒收表)`。

    自错件：走 `记一件写盘`（认领 + 改动 + 销意图同一事务），说明栏写明「据写盘意图恢复」；
    未写成件：只销意图；外部漂移：逐件报出、**一个字节都不碰**，退出码 3。
    """
    意图表 = 列写盘意图(连接, 开工号)
    if any(意图行["功能"].startswith("恢复已记账写后:") for 意图行 in 意图表):
        return 3, "存在已记账恢复意图，须同改动编号/候选全文调用恢复已记账写后", [], []
    if not 意图表:
        return 0, "没有未决的写盘意图 —— 盘账已是一致态（不必恢复）", [], []
    认领表 = 账本.读认领(连接, 开工号)
    自错表, 未写成表, 外部表 = 分漂移(工作树, 认领表, 意图表)
    已收敛行表, 拒收表, 记账错 = [], [], ""
    已有改动 = {(一条改动["路径"], 一条改动["写后指纹"])
             for 一条改动 in 账本.读改动(连接, 开工号)}
    for 意图行, 盘上指纹 in 未写成表:
        try:
            销写盘意图(连接, 开工号, 意图行["路径"])
        except Exception as 失败原因:  # noqa: BLE001 —— 销不动如实报，不吞
            拒收表.append((意图行["路径"], "销意图失败：%s" % (失败原因,)))
            continue
        已收敛行表.append((意图行["路径"], "没写成（盘上仍是写前 %s）⇒ 销意图，不记账"
                       % (意图行["写前指纹"] or "（空）")))
    for 意图行, 盘上指纹 in 自错表:
        路径 = 意图行["路径"]
        if (路径, 盘上指纹) in 已有改动:
            try:
                销写盘意图(连接, 开工号, 路径)
            except Exception as 失败原因:  # noqa: BLE001
                拒收表.append((路径, "销意图失败：%s" % (失败原因,)))
                continue
            已收敛行表.append((路径, "改动表已有同写后行 ⇒ 只销意图（幂等）"))
            continue
        写前 = 认领表.get(路径) or 意图行["写前指纹"] or ""
        try:
            记一件写盘(连接, 开工号, 路径, 意图行["功能"], 写前, 盘上指纹,
                   "据写盘意图恢复（落盘后记账未提上去）")
        except Exception as 失败原因:  # noqa: BLE001
            记账错 = "%s" % (失败原因,)
            break
        已收敛行表.append((路径, "盘已写（写后 %s）⇒ 补记认领指纹与改动行（同一事务）"
                       % (盘上指纹 or "（件没了）",)))
    for 意图行, 盘上指纹 in 外部表:
        拒收表.append((意图行["路径"], "盘上 %s 既不是写前 %s、也不是期望写后 %s ⇒ **外部漂移**，不恢复"
                    % (盘上指纹 or "（件没了）", 意图行["写前指纹"] or "（空）",
                       意图行["期望写后指纹"] or "（空）")))
    退出码, 说明 = 退出码_汇总(已收敛行表, 拒收表, 记账错)
    return 退出码, 说明, 已收敛行表, 拒收表


def 退出码_汇总(已收敛行表: list, 拒收表: list, 记账错: str) -> tuple:
    """拼回执并定退出码：0 全收敛 / 3 有外部漂移（拒收）/ 1 收敛中途记账失败。"""
    行表 = []
    if 已收敛行表:
        行表.append("已收敛 %d 件（盘账已对齐）：" % len(已收敛行表))
        行表 += ["    %s：%s" % (路径, 读数) for 路径, 读数 in 已收敛行表]
    if 拒收表:
        行表.append("**拒收 %d 件（外部漂移：人 / 别的工具动的，不洗账）**：" % len(拒收表))
        行表 += ["    %s：%s" % (路径, 读数) for 路径, 读数 in 拒收表]
    if 记账错:
        行表.append("**收敛中途记账失败**：%s ⇒ 已收敛的已入库，剩余的仍留意图，修好后重跑"
                  % 记账错)
        return 1, "\n".join(行表)
    if 拒收表:
        return 3, "\n".join(行表)
    return 0, "\n".join(行表)


def 释放前漂移检查(连接, 工作树: Path, 开工号: str, 变过表: dict) -> tuple:
    """释放前把「变过表」按意图归因 ⇒ `(退出码, 说明)`（0 = 放行）。

    外部漂移 ⇒ 照旧当「绕过 v1_edit」（拒）；工具自错（盘上 == 意图期望写后）⇒ 指路
    `v1_edit` 操作 `恢复` —— 它不洗指纹，只把盘已写而账未记的那笔补上；仍有未决意图
    （盘上 == 写前，写盘没发生）也拒 —— 释放前先把写盘生命周期收干净。
    """
    意图表 = 列写盘意图(连接, 开工号)
    自错表, 外部表 = 分类漂移(工作树, 变过表, 意图表)
    if 外部表:
        return 1, ("**有人绕过 v1_edit 直接改了盘**（账本记的指纹与现在盘上的对不上）⇒ 无法释放：\n"
                 "  %s\n"
                 "绕过 v1_edit 就意味着那段改动**没经过四道闸**（没查路径认领、没查旧内容唯一定位），"
                 "而门禁读的正是盘上的新内容 ⇒ 它会跟着「绿」一起进去（绿得没意义）。"
                 "处置：把盘上那段改动**撤掉**，改用 v1_edit 重来。"
                 % " · ".join(sorted(外部表)))
    if 自错表:
        return 1, ("**本工具自错**（不是用户绕写）：这些件盘已写、但记账中途失败"
                 "（盘上指纹 == 写盘意图的期望写后）：\n  %s\n"
                 "处置：跑 `v1_edit` 操作 `恢复` —— 只据写盘意图收敛（补认领指纹与改动行），"
                 "**不洗指纹、不造历史**；收完再释放。" % " · ".join(sorted(自错表)))
    if 意图表:
        return 1, ("还有 **%d 条未决写盘意图**（写盘未发生或未收尾）⇒ 释放前先跑 "
                 "`v1_edit` 操作 `恢复` 收干净：%s"
                 % (len(意图表), " · ".join(意图行["路径"] for 意图行 in 意图表)))
    return 0, ""


def 越界归因(连接, 工作树: Path, 开工号: str, 越界表: list) -> str:
    """把释放的**越界件**（盘上脏、但不在改动表）按意图归因 ⇒ 说明文本（空 = 无自错）。

    盘上 == 某条意图的期望写后 ⇒ **工具自错**（新建件账未记时它既不在认领表、也不在改动表）；
    其余照旧当绕过 / 未记账的脏件。返回的文本只在有自错件时非空。
    """
    意图表 = 列写盘意图(连接, 开工号)
    自错表, 外部表 = 分类漂移(工作树, {路径: ("", "") for 路径 in 越界表}, 意图表)
    自错件 = sorted(路径 for 路径 in 自错表 if 路径 in set(越界表))
    if not 自错件:
        return ""
    return ("★ 其中这些是**本工具自错**（盘已写、记账未提上去）⇒ 跑 `v1_edit` 操作 `恢复`：%s"
            % " · ".join(自错件))


def 恢复开工(仓根, 开工号: str) -> tuple:
    """`v1_edit` 操作 `恢复` 的入口 ⇒ `(退出码, 说明)`。只对本开工、只按意图，不动别的开工。"""
    连接 = 账本.连账本()
    try:
        补意图表(连接)
        一条开工 = 账本.读开工(连接, 开工号)
        if not 一条开工:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记（`v1_task`）" % 开工号
        工作树 = Path(一条开工["工作树"])
        if not 工作树.is_dir():
            return 1, "工作树不在了：%s ⇒ 查清再恢复（别改了账、活却找不回）" % 工作树
        退出码, 说明 = 恢复一次(连接, 工作树, 开工号)[:2]
        return 退出码, "%s 写盘恢复（只据写盘意图，不洗指纹、不造历史）：\n%s" % (开工号, 说明)
    finally:
        连接.close()


def 核恢复路径(仓根, 开工号, 工作树, 路径):
    """公共仓真实登记树和无链接的规范相对路径。"""
    from .仓操作 import 找工作树, 跑命令
    if not isinstance(路径, str) or not 路径 or Path(路径).is_absolute() or str(Path(路径)) != 路径 or ".." in Path(路径).parts:
        raise ValueError("路径须为规范仓内相对路径")
    if 工作树.is_symlink() or not 工作树.is_dir():
        raise ValueError("工作树不存在或为链接")
    登记树 = 找工作树(仓根, 开工号)
    if 登记树 is None or 登记树.resolve() != 工作树.resolve():
        raise ValueError("工作树与公共仓真实登记不同")
    当前路径 = 工作树
    for 路径段 in Path(路径).parts:
        当前路径 = 当前路径 / 路径段
        if 当前路径.is_symlink():
            raise ValueError("路径含链接")
    if not 当前路径.is_file() or not 当前路径.resolve().is_relative_to(工作树.resolve()):
        raise ValueError("目标不是树内普通文件")
    公共值 = []
    for 树路径 in (仓根, 工作树):
        退出码, 输出文本 = 跑命令(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"], cwd=树路径)
        if 退出码:
            raise ValueError("公共仓定位失败")
        公共值.append(Path(输出文本.strip()).resolve())
    if 公共值[0] != 公共值[1]:
        raise ValueError("目标属于外仓")
    return 当前路径


def 核已记账记录(连接, 开工号, 改动编号, 路径):
    """只认可最新成功修改行及仍等于原写后的认领。"""
    开工行 = 账本.读开工(连接, 开工号)
    if not 开工行 or 开工行["状态"] != 账本.状态_进行中:
        raise ValueError("目标开工不是进行中")
    记录 = 连接.execute("select * from 改动 where 编号 = ? and 开工号 = ? and 路径 = ?", (改动编号, 开工号, 路径)).fetchone()
    if not 记录 or 记录["功能"] != "修改" or not 记录["写前指纹"] or not 记录["写后指纹"] or 记录["写前指纹"] == 记录["写后指纹"]:
        raise ValueError("没有确切成功修改记录")
    if 连接.execute("select 1 from 改动 where 开工号 = ? and 路径 = ? and 编号 > ?", (开工号, 路径, 改动编号)).fetchone():
        raise ValueError("原记录之后存在合法改动")
    if 账本.读认领(连接, 开工号).get(路径) != 记录["写后指纹"]:
        raise ValueError("未认领或认领指纹不是原写后")
    return 开工行, dict(记录)


def 恢复已记账写后(仓根, 开工号, 参数表):
    """精确恢复既有成功记录，原历史和认领保持不变。"""
    import hashlib
    import sqlite3
    from .写盘执行 import 开工写盘锁, 写盘占用, 写文件
    改动编号, 路径, 候选全文 = 参数表.get("改动编号"), 参数表.get("路径"), 参数表.get("候选全文")
    if type(改动编号) is not int or 改动编号 <= 0 or not isinstance(候选全文, str):
        return 2, "改动编号须为正整数，候选全文须为准确完整文本"
    try:
        with 开工写盘锁(开工号):
            连接 = 账本.连账本()
            try:
                开工行, 记录 = 核已记账记录(连接, 开工号, 改动编号, 路径)
                工作树 = Path(开工行["工作树"])
                件路径 = 核恢复路径(仓根, 开工号, 工作树, 路径)
                候选指纹 = hashlib.sha256(候选全文.encode("utf-8")).hexdigest()
                if 候选指纹[:16] != 记录["写后指纹"]:
                    raise ValueError("候选全文指纹不是原记录写后")
                盘上字节 = 件路径.read_bytes()
                盘上指纹 = hashlib.sha256(盘上字节).hexdigest()[:16]
                if 盘上指纹 not in (记录["写前指纹"], 记录["写后指纹"]):
                    raise ValueError("盘上不是原写前或原写后，拒绝第三版本")
                from .禁改面 import 禁改原因
                from .命名闸 import 未登记绑定名
                from .语法闸 import 查最终态语法
                for 全文 in (盘上字节.decode("utf-8"), 候选全文):
                    原因 = 禁改原因(路径, 全文)
                    if 原因:
                        raise ValueError(原因)
                if 查最终态语法({路径: 候选全文}):
                    raise ValueError("候选语法不合法")
                未登记, 错误 = 未登记绑定名(工作树, [(路径, 1, "", 候选全文, False)])
                if 未登记 or 错误:
                    return 5, "命名闸拒：%s" % (错误 or 未登记)
                意图表 = [意图行 for 意图行 in 列写盘意图(连接, 开工号) if 意图行["路径"] == 路径]
                恢复功能 = "恢复已记账写后:%d" % 改动编号
                if 意图表 and (意图表[0]["功能"] != 恢复功能 or 意图表[0]["写前指纹"] != 记录["写前指纹"] or 意图表[0]["期望写后指纹"] != 记录["写后指纹"]):
                    raise ValueError("目标存在其他未决意图")
                if 盘上指纹 == 记录["写后指纹"] and not 意图表:
                    return 0, "幂等零写：原记录%d %s 写后%s，候选SHA256=%s" % (改动编号, 路径, 盘上指纹, 候选指纹)
                from .写盘账本 import 记写盘意图, 记已记账恢复
                补意图表(连接)
                if 盘上指纹 == 记录["写前指纹"]:
                    记写盘意图(连接, 开工号, 路径, 恢复功能, 记录["写前指纹"], 记录["写后指纹"])
                    核已记账记录(连接, 开工号, 改动编号, 路径)
                    核恢复路径(仓根, 开工号, 工作树, 路径)
                    错误 = 写文件(件路径, 候选全文, 盘上指纹)
                    if 错误:
                        return 4, "%s；原记录未改，恢复意图保留，可用同参重试" % 错误
                if 文件指纹(str(件路径)) != 记录["写后指纹"]:
                    return 4, "替换后漂移：保留恢复意图与现场"
                核已记账记录(连接, 开工号, 改动编号, 路径)
                记已记账恢复(连接, 开工号, 路径, 记录, 候选指纹)
                return 0, "恢复已记账写后：原记录%d %s 写前%s → 写后%s；原历史/认领未改；候选SHA256=%s；恢复动作已记账" % (改动编号, 路径, 记录["写前指纹"], 记录["写后指纹"], 候选指纹)
            finally:
                连接.close()
    except (ValueError, OSError, UnicodeError, sqlite3.Error, 写盘占用) as 错误:
        return 3, "恢复拒或未收尾（保留现场）：%s" % 错误
