    from .反馈提交 import 提交反馈
    from .反馈判词 import 批量判定
    from .反馈审完 import 登记报告审完
    样本表 = []

    def 记样本(说明, 通过):
        样本表.append((说明, bool(通过)))

    def 造已读来源(幂等键, 标识, 指纹):
        退出码, 回执文本 = 提交反馈(仓根, 反馈开工号, {
            "幂等键": 幂等键, "来源标识": 标识, "报告指纹": 指纹,
            "读取状态": "已读", "条目": [{"现象": "批量样本发现", "证据": "读数 B",
                                  "未测": "落点与触发未记录"}]})
        来源号 = 读回执(回执文本).get("来源号")
        条目号 = (读回执(回执文本).get("条目号") or [None])[0]
        批量判定(仓根, 反馈开工号, {"判定表": [{"条目号": 条目号, "判词": "非问题",
                                          "理由": "批量样本"}]})
        return 来源号

