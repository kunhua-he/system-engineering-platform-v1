# -*- coding: utf-8 -*-
"""门禁 —— `v1_gate` 的实现：**验证器**（全量 / 只跑指定判据）。

**为什么分两档，以及为什么只作反馈不作放行**（裁决与实测见
`项目文档/决策记录/2026-09-27_开工账本与四道闸.md`）：

  · **局部绿 ≠ 全仓绿** —— 判据之间有耦合（改一个常量可能让三条判据一起变红），
    所以「只跑我碰到的那几条」**永远不能当放行凭据**。本档内放行凭据只有一个：**全量**
    （但全量本身仍**不是**提交闸 —— 见下「全量绿 ≠ 提交放行」）。
  · **局部存在的理由是「反馈要快」**，不是「少验一点」：红了 → 改 → 只跑那一条复验（快）→
    全绿了再跑全量。没有这一档，agent 会因为全量慢而干脆不验。
  · **不按「件」切**：判据的 `扫描面` 是按**顶层目录**声明的 ⇒ 拿一个件去筛，37 条里还能命中
    10–17 条，而重型那几条几乎每条件的面里都有 —— 实测墙钟 1124 ms vs 全量 1164 ms，**省 3%**，
    白搭。按**判据**切才是真杠杆：只跑 ㊲ 是 1097 ms（它一条就吃掉全量的 73%）、
    只跑 ㉒ 是 689 ms、空集地板 247 ms。

**★ 全量档跑的是 `闸0.py`，不是 `一键验证.py`**：`闸0.py` 把**两条闸**串起来跑 ——
闸 1 声明侧（`一键验证.py`，37 条判据）+ 闸 2 实现侧（`扫实现.py`）。**只跑闸 1 会漏掉实现侧**，
而漏掉的那一半正是 `闸0.py` 存在的理由（它文件头记着实测：闸 1 不 import 闸 2 ⇒ 主干上坏了
一整段而没有任何门禁抓到）。`判据` 那一档只能落在闸 1 上（实现侧没有「只跑某几条」的对应物），
所以它**只是反馈档**。

**★ 全量档转后台作业（2026-10-08 · 易用腿二）**：`闸 0` 合计实测可超同步路那 5 秒硬顶（闸 1 自身就
近 5 秒）⇒ 直接同步跑会被掐成「超时 `-1`」，腿只能回落 Bash。本档改成：**全量 = 起 `v1_job` 具名
`闸0` 作业**，同步只等 `全量同步秒` —— 等到终态就一次看完（不必轮询），没等到就回「任务ID + 已得读数」
（用 `v1_job` 的 `status` / `log` 取完）。**不放宽硬顶、不回落 Bash**。带 `判据` 的反馈档仍同步跑。
★ **未到终态 ≠ 闸失败**：窗口内没跑完时退出码 = `服务常量.待取作业码`（`-3`）、信封 `错误.种类` =
`待取作业` —— 与 `-1`（超时未完成验证）、`1`（业务失败）**分开**，调用方据此判「还要去取」而非「红」。

**★ 全量绿 ≠ 提交放行（两套口径，别混）**：本档全量只跑 `闸0.py`（闸 1 声明侧 + 闸 2 实现侧）；
而真实提交闸（`测试验证/测试案例/装门禁.sh` 的 pre-commit）**额外跑** ①b
`python3 构建装配/一键验证/一键验证.py --自测` 与 ③ `cargo run --quiet --locked -p v1-case-runner`
全部案例。⇒ **提交放行 = 闸 0 + 判据自测 + 案例**。全量绿只是提交前的**必要一环**，腿若据此判
「可交付」，仍可能在 `功能=3 释放` 的 git commit 处被 pre-commit 拒（`开工.py` 只报「多半是门禁钩子拒了」）。

**★ 绕过检测这一档只报不拦**（裁决 2026-10-05）：本档把「认领件盘上指纹 ≠ 账本指纹」append 进回执，
**但退出码仍取 `闸0.py`** —— 即全量档可以带着「★ 绕过检测」那行返回 0。**硬闸在 `功能=3 释放`**
（`开工.py` 的认领对账会拒）。本轮只把行为写清楚，不改行为。

**★ 漂移要分两类报**（2026-10-08）：同一条「盘上指纹 ≠ 账本指纹」既可能是人 / 别的工具绕写，
也可能是**本工具自错**（盘已写、记账中途失败，盘上指纹恰是写盘意图里的期望写后）—— 后者不该
被当「用户绕写」。本档复用 `写盘恢复.分类漂移` 只按**未决写盘意图**拆：自错件指路 `v1_edit` 操作
`恢复`，其余照旧当绕过。**只报不拦**这条不变。

**读数第一行必须写明「在哪棵树跑的」**：不带 `开工ID` 就落在主工作树，而主工作树的绿
**不代表**你那条开工的绿 —— 这一行就是防这个误读的。
"""

import re
import subprocess
import sys
import time
from pathlib import Path

from .. import 开工账本 as 账本
from ..文件编辑.修改 import 对账_除源件
from .门禁预算 import 硬顶秒
from ..服务协议.服务常量 import 待取作业码

# 验证子进程（闸 0 / 一键验证）的上限：**从唯一主人派生**（2026-10-08 硬顶临时放宽到 10 s ⇒ 10）。
# ★ `全量同步秒` **不动**（4.0）—— 全量仍转后台作业，不靠「加长同步等待」凑预算。
超时秒 = 硬顶秒()
全量同步秒 = 4.0      # 全量转作业后，同步窗口内最多等这么久（同步路不改）
作业轮询秒 = 0.15


def 绕行回执行(查询根, 开工号, 认领表, 源件表) -> list:
    """认领件盘上指纹 ≠ 账本指纹 ⇒ 漂移（本工具自错 / 外部绕过）—— **只报不拦**（裁决 2026-10-05）。

    同一份读口（`对账_除源件` + `分类漂移`），供「全量转作业」与「只跑判据」两条路共用。
    """
    行表 = []
    if 认领表 is None:
        return 行表
    对得上表, 变过表, 放行表 = 对账_除源件(查询根, 认领表, 源件表)
    if 放行表:
        行表.append("（经 功能 = 6 记过的源件，指纹漂移已放行：%s）" % " · ".join(sorted(放行表)))
    if not 变过表:
        return 行表
    from ..文件编辑.写盘恢复 import 分类漂移
    from ..文件编辑.写盘账本 import 列写盘意图
    连接_意图 = 账本.连账本()
    try:
        意图表 = 列写盘意图(连接_意图, 开工号)
    finally:
        连接_意图.close()
    自错表, 外部表 = 分类漂移(查询根, 变过表, 意图表)
    if 自错表:
        行表.append("★ **本工具自错**（不是用户绕写）：这些件盘已写、记账中途失败"
                  "（盘上指纹 == 写盘意图的期望写后）⇒ 跑 `v1_edit` 操作 `恢复`：\n%s"
                  % "\n".join("    %s：账本 %s → 盘上 %s"
                            % (路径, 键值对[0] or "（无）", 键值对[1] or "（件没了）")
                            for 路径, 键值对 in sorted(自错表.items())))
    if 外部表:
        行表.append("★ **绕过检测**：这些件被绕过 MCP 改过（盘上指纹 ≠ 账本指纹）：\n%s"
                  % "\n".join("    %s：账本 %s → 盘上 %s"
                            % (路径, 键值对[0] or "（无）", 键值对[1] or "（件没了）")
                            for 路径, 键值对 in sorted(外部表.items())))
    return 行表


def 有界等作业(任务ID: str, 等秒: float):
    """等后台作业到终态或 `等秒` 上限 ⇒ 作业行（读不到 ⇒ None）。"""
    from ..作业 import 读行, 收敛失联, 终态集
    截止时刻 = time.monotonic() + 等秒
    while True:
        作业行 = 读行(任务ID)
        if 作业行 is None:
            return None
        作业行 = 收敛失联(任务ID, 作业行)
        if 作业行["状态"] in 终态集 or time.monotonic() >= 截止时刻:
            return 作业行
        time.sleep(min(作业轮询秒, max(0.0, 截止时刻 - time.monotonic())))


def 读数计数行(行表: list) -> list:
    """从闸输出里挑出「通过 N 项 · 失败 N 项 · 未判 N 项」那几行 ⇒ 计数行表（供直接读数）。

    ★ 2026-10-08（易用腿二 · 308 腿实测）：要判「闸 2 未判归 0」原先得手动解析闸 2 输出 ⇒
    本档直接把它挑出来。
    """
    计数行表 = []
    for 源码行 in 行表:
        if "项" in 源码行 and ("通过" in 源码行 or "失败" in 源码行 or "未判" in 源码行):
            计数行表.append("    " + 源码行.strip())
    return 计数行表[:8]


def 取提交哈希(查询根) -> str:
    """该树 HEAD 的短提交哈希（读数引用用）；取不到 ⇒ 空串。"""
    try:
        回执 = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=str(查询根),
                           capture_output=True, text=True, timeout=3)
        return (回执.stdout or "").strip()
    except Exception:
        return ""


def 判据落点行(词表: list) -> list:
    """选中的判据 ⇒ 「判据名 —— 件:行」行表（失败时直接定位判据实现）。取不到 ⇒ 空表。"""
    try:
        import sys as _sys
        from pathlib import Path as _路径
        工具根 = _路径(__file__).resolve().parents[3]
        for 子目录 in (str(工具根 / "构建装配" / "一键验证"), str(工具根 / "开发工具"),
                    str(工具根 / "开发工具" / "信息核心")):
            if 子目录 not in _sys.path:
                _sys.path.insert(0, 子目录)
        from 一键验证.判据编排 import 判据选择
        选中集, 问题 = 判据选择.解析选择(词表)
        if 问题:
            return []
        return ["    %s —— %s" % (判据名, 判据选择.判据落点(判据名)) for 判据名 in sorted(选中集)]
    except Exception:
        return []


def 全量转作业(仓根, 开工号, 查询根, 树名, 认领表, 源件表) -> tuple:
    """**全量 = 闸 0** ⇒ 转后台作业（闸 0 合计可超 5 秒硬顶，同步路塞不下）。

    同步只等 `全量同步秒`：等到终态就一次看完（不必轮询）；没等到就回「任务ID + 已得读数」，
    用 `v1_job` 的 `status` / `log` 取完。**不放宽硬顶、不回落 Bash**。
    """
    from ..作业 import 起具名作业, 读日志片段, 终态集
    开始 = time.monotonic()
    启动码, 启动文 = 起具名作业("闸0", 开工号, 3, 仓根)
    if 启动码:
        return 启动码, 启动文
    配对 = re.search(r"任务ID：([0-9a-f]{32})", 启动文)
    if not 配对:
        return 1, "起作业回执里没读到任务ID ⇒ 不假装跑过：\n%s" % 启动文
    任务ID = 配对.group(1)
    窗口余量 = max(0.0, 全量同步秒 - (time.monotonic() - 开始))
    作业行 = 有界等作业(任务ID, 窗口余量)
    if 作业行 is None:
        return 1, "起作业后读不到作业行（账本未落）⇒ 用 `v1_job` status 核：%s" % 任务ID
    终结 = 作业行["状态"] in 终态集
    行表 = ["在「%s」跑的（后台作业，转 `v1_job` 具名 `闸0`）：%s" % (树名, 查询根),
           "提交：%s" % (取提交哈希(查询根) or "（取不到）"),
           "范围：**全量 = 闸 0**（声明侧 + 实现侧两条闸；提交放行 = 闸 0 + 判据自测 + 案例）",
           "任务ID：%s · 状态：%s · 退出码：%s"
           % (任务ID, 作业行["状态"], 作业行["退出码"] if 终结 else "（未定）")]
    if not 终结:
        行表.append("★ 同步窗口（%s 秒）内没跑完 ⇒ 这里只是**已得读数**；取完用 `v1_job`："
                 "`{\"操作\":\"status\",\"参数\":{\"任务ID\":\"%s\"}}` ／ `{\"操作\":\"log\",…}`"
                 % (全量同步秒, 任务ID))
    日志码, 日志文 = 读日志片段(任务ID, 0, False)
    if 日志码 == 0:
        有效行表 = [源码行 for 源码行 in 日志文.splitlines()
                 if 源码行.strip() and "─" not in 源码行]
        行表.append("—— 已得读数（作业标准输出尾）——")
        行表 += 有效行表[:6] + (["…（中略 %d 行；完整日志见报告）" % (len(有效行表) - 28)] if len(有效行表) > 28 else []) + 有效行表[-22:]
        计数表 = 读数计数行(有效行表)
        if 计数表:
            行表.append("—— 读数计数（闸1/闸2 通过·失败·未判）——")
            行表 += 计数表
    else:
        行表.append("（作业日志还没产出：%s）" % 日志文.strip()[:200])
    行表 += 绕行回执行(查询根, 开工号, 认领表, 源件表)
    if 终结:
        退出码 = 作业行["退出码"] if 作业行["退出码"] is not None else 1
    else:
        退出码 = 待取作业码
    return 退出码, "\n".join(行表)


def 派发(参数表: dict, 仓根) -> tuple:
    """`v1_gate` 的入口。"""
    开工号 = str(参数表.get("开工ID") or "").strip()
    判据词表 = 参数表.get("判据")
    if isinstance(判据词表, str):
        判据词表 = [判据词表]
    elif 判据词表 is None:
        判据词表 = []
    elif not isinstance(判据词表, (list, tuple)):
        return 2, ("`判据` 要一段字符串或一张表 —— 合法面 = `判据表.检查表` 的可运行判据"
                 "（编号或名子串）；选择器住 `构建装配/一键验证/一键验证/判据编排/判据选择.py`（同源）")
    词表 = list(判据词表)
    # ★ **不在这里丢词**（原写法 `if str(判据词).strip()` 会把空词 / 非串静默丢掉 ⇒ 退回全量，
    #   正是「只跑」变假象的那条病）。原样透传给 `一键验证.py --只跑`，由**同一个选择器**
    #   （`判据选择.解析选择`，`主流程.解析只跑` 复用它）判：空词 / 非串 / 重复 / 未知 /
    #   已知未知混给 ⇒ 清晰非 0（带近似候选），绝不静默退回全量。
    if 词表 and not all(isinstance(判据词, str) for 判据词 in 词表):
        return 2, "`判据` 里每一项都要是字符串（选择器拒非串项；本档不静默改类型）"

    查询根, 树名, 认领表, 源件表 = Path(仓根).resolve(), "主工作树", None, set()
    if 开工号:
        连接 = 账本.连账本()
        try:
            开工记录 = 账本.读开工(连接, 开工号)
            if not 开工记录:
                return 1, "没有这条开工：%s ⇒ 先 `v1_task` 功能 = 1 登记" % 开工号
            查询根 = Path(开工记录["工作树"])
            树名 = "%s（支线 %s）" % (开工号, 开工记录["分支名"])
            认领表 = 账本.读认领(连接, 开工号)
            源件表 = 账本.源件路径集(连接, 开工号)
        finally:
            连接.close()
        if not 查询根.is_dir():
            return 1, "那条开工的工作树不在了：%s ⇒ 查清再验" % 查询根

    # ★ **全量 = 闸 0**（两条闸一起跑：闸 1 声明侧 + 闸 2 实现侧），不是只跑闸 1 那一条。
    #   只跑 `一键验证.py` 会把**实现侧**（`扫实现.py`）整段漏掉 —— 而那正是 `闸0.py` 存在的
    #   理由（它文件头记着实测：闸 1 不 import 闸 2 ⇒ 主干上坏了一整段、**没有任何门禁抓到**，
    #   直到收口方手跑才发现）。本件原先正好踩回了这个坑。
    #   带 `判据` 时走 `一键验证.py --只跑`：那是**反馈档**（局部绿不算放行），
    #   而「只跑某几条」对实现侧没有对应物。
    直跑 = bool(参数表.get("直跑"))
    if not 词表 and not 直跑:
        return 全量转作业(仓根, 开工号, 查询根, 树名, 认领表, 源件表)
    命令表 = ([sys.executable, "构建装配/一键验证/闸0.py"] if not 词表 else
             [sys.executable, "构建装配/一键验证/一键验证.py", "--只跑", ",".join(词表)])
    try:
        回执 = subprocess.run(命令表, cwd=str(查询根), capture_output=True, text=True,
                            timeout=超时秒)
        退出码 = 回执.returncode
        命令输出 = (回执.stdout or "") + (回执.stderr or "")
    except subprocess.TimeoutExpired:
        if 词表:
            return -1, "局部判据超过 %d 秒硬顶，未完成验证" % 超时秒
        try:
            回执 = subprocess.run(命令表, cwd=str(查询根), capture_output=True, text=True, timeout=超时秒)
        except subprocess.TimeoutExpired:
            return -1, "全量及正式复跑均超过 %d 秒硬顶，未完成验证" % 超时秒
        退出码 = 回执.returncode
        命令输出 = (回执.stdout or "") + (回执.stderr or "")
    except OSError as 起不来的原因:
        return -2, "起不了验证器：%r" % (起不来的原因,)

    有效行表 = [源码行 for 源码行 in 命令输出.splitlines() if 源码行.strip() and "─" not in 源码行]
    输出行表 = ["在「%s」跑的：%s" % (树名, 查询根),
              "提交：%s" % (取提交哈希(查询根) or "（取不到）"),
              "范围：%s" % ("只跑判据 %s" % " · ".join(词表) if 词表 else "全量 = 闸 0（正式直跑）"),
              "退出码 %d" % 退出码,
              "\n".join(有效行表[:6] + (["…（中略 %d 行；完整日志见报告）" % (len(有效行表) - 28)] if len(有效行表) > 28 else []) + 有效行表[-22:]),
              "★ 这是**局部**读数 —— 它绿**不代表**全仓绿。放行前必须跑一次全量（不传 `判据`）。"]
    计数表 = 读数计数行(有效行表)
    if 计数表:
        输出行表.append("—— 读数计数 ——")
        输出行表 += 计数表
    落点行表 = 判据落点行(词表)
    if 落点行表:
        输出行表.append("—— 判据落点（件:行）——")
        输出行表 += 落点行表
    输出行表 += 绕行回执行(查询根, 开工号, 认领表, 源件表)
    return 退出码, "\n".join(输出行表)
