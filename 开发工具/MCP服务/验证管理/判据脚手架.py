# -*- coding: utf-8 -*-
"""判据脚手架 —— 一条命令生成「新判据」的五处骨架（省掉每加一条判据必撞的那几轮返工）。

**为什么要有它**（多路代理实测）：加一条判据要同时动五处 —— 判据件 · 判据表 · 检查名 ·
判据元数据 · 注入反向样本 + 自测用例；漏一处闸 0 就红（判据 ⑭ 元判据：两源对齐 / 每条判据
必须有反向样本与正向样本），实测撞了三轮才补齐。本件按**现盘锚点**把五处一次拼好，
出一份**可直接粘贴的 `v1_edit` 改动表**，并附一条 `v1_name` 批量登记载荷。

**不许假绿**：判据件骨架**故意报红**（「骨架未填判定 ⇒ 未实现（不是通过）」）—— 真判定填好
之前，生成出来的判据让闸 0 必红；这是刻意的（空判据放行 = 假绿，本项目最忌）。
"""
from __future__ import annotations

import json
import re
from pathlib import Path

验证目录 = "构建装配/一键验证/一键验证"
判据表件 = 验证目录 + "/判据表.py"
检查名件 = 验证目录 + "/常量_检查名.py"
元数据件 = 验证目录 + "/判据元数据.py"
用例件 = 验证目录 + "/自测用例.py"

# 五处的锚点（按**现盘**正则取最后一条 ⇒ 新条目接在它后面）—— 锚点没命中就**如实报**，
# 不硬塞（硬塞等于写错位置）。
锚点表 = {
    "判据表导入": (判据表件, r"^from \.判据_\S+ import .+$"),
    "判据表条目": (判据表件, r"^    \(检查名\[\d+\], 检查\d+_\S+\),$"),
    "元数据接线": (元数据件, r"^判据元数据\.update\(.+\)$"),
    "用例导入": (用例件, r"^from \.注入_\S+ import .+$"),
}


def 取末行(全文: str, 模式: str) -> str:
    """全文里**最后一条**匹配 `模式` 的行 ⇒ 原文（没有 ⇒ 空串）。"""
    命中表 = re.findall(模式, 全文, flags=re.MULTILINE)
    return 命中表[-1] if 命中表 else ""


def 拼判据件(判据名: str, 序号: int, 简述: str) -> str:
    """判据件骨架：故意报红（判定未填 ⇒ 未实现）。"""
    行表 = [
        "# -*- coding: utf-8 -*-",
        '\"\"\"判据 %d：%s（骨架 · 判定待填）。' % (序号, 简述),
        "",
        "★ 本件由 `v1_gate 操作=判据脚手架` 生成 —— **判定未填之前恒报红**（不静默通过 = 不假绿）。",
        '\"\"\"',
        "from __future__ import annotations",
        "",
        "from .验证小工具 import 违规",
        "from .常量 import 检查名",
        "",
        '相对路径 = "TODO 判据声明的落点件"',
        "",
        "",
        "def 样本_%s面(上层读数: dict) -> int:" % 判据名,
        '    \"\"\"对象数：0 ⇒ 未判（空集不算通过）。骨架默认 0，填判定时一并改成真读数。\"\"\"',
        "    return 0",
        "",
        "",
        "def 检查%d_%s(上层读数: dict) -> list:" % (序号, 判据名),
        '    \"\"\"骨架：判定未填 ⇒ 恒报一条违规。填好真判定后把这一条删掉。\"\"\"',
        "    return [违规(检查名[%d], 相对路径," % (序号 - 1),
        '               "判据骨架未填判定 ⇒ 未实现（不是通过）",',
        '               "%s：填 `检查%d_%s` 的真判定与 `样本_%s面` 的对象数；'
        '本骨架故意报红，防「空判据 = 假绿」")]' % (简述, 序号, 判据名, 判据名),
        "",
    ]
    return "\n".join(行表)


def 拼元数据件(判据名: str, 序号: int, 简述: str) -> str:
    """判据元数据件骨架（身份证：反向样本 · 正向样本 · 扫描面 · 对象数）。"""
    行表 = [
        "# -*- coding: utf-8 -*-",
        '\"\"\"判据 %d（%s）的身份证元数据（从 `判据元数据.py` 拆出，控单件行数）。\"\"\"' % (序号, 简述),
        "from __future__ import annotations",
        "",
        "from .判据_%s import 样本_%s面 as _样本_%s面" % (判据名, 判据名, 判据名),
        "from .常量 import 取全仓区面, 检查名",
        "",
        "",
        "%s判据元数据 = {" % 判据名,
        "    检查名[%d]: {" % (序号 - 1),
        '        "扫描面": 取全仓区面(),',
        '        "对象数": _样本_%s面,' % 判据名,
        '        "反向样本": "%s：注入一处该抓的违规 ⇒ 当场红（见 注入_%s.py）",' % (简述, 判据名),
        '        "正向样本": "干净合成仓",',
        "    },",
        "}",
        "",
    ]
    return "\n".join(行表)


def 拼注入件(判据名: str, 序号: int, 简述: str) -> str:
    """反向样本注入件骨架：往干净合成仓注入一处该抓的违规。"""
    行表 = [
        "# -*- coding: utf-8 -*-",
        '\"\"\"判据 %d 的反向样本：往干净合成仓注入一处该抓的违规。\"\"\"' % 序号,
        "from __future__ import annotations",
        "",
        "from pathlib import Path",
        "",
        "",
        "def 注入_%s(临根: Path) -> str:" % 判据名,
        '    \"\"\"%s：注入一处该抓的违规 ⇒ 返回被改件的相对路径。骨架：先想清「打哪一条断言」。\"\"\"' % 简述,
        '    raise NotImplementedError("判据 %d 的反向样本未填 ⇒ 自测当场报红（不假绿）")' % 序号,
        "",
    ]
    return "\n".join(行表)


def 拼接线(目标树: Path, 判据名: str, 序号: int, 简述: str) -> tuple:
    """四处接线 ⇒ `(改动项表, 未命中锚点表)`。"""
    改动项表, 未命中表 = [], []
    # ① 检查名：接在 `检查名` 元组收尾的 `)` 之前。
    检查名文本 = (目标树 / 检查名件).read_text(encoding="utf-8")
    收尾锚 = "\n)\n\n# 「检查名」里"
    if 收尾锚 in 检查名文本:
        新条目 = ("\n    # ── %d：%s ──\n"
                "    \"%d %s：%s\",\n)" % (序号, 简述, 序号, 简述, 简述))
        改动项表.append({"路径": 检查名件, "功能": 1, "旧内容": 收尾锚, "新内容": 新条目 + 收尾锚})
    else:
        未命中表.append("检查名件（锚点「检查名元组收尾」没命中）")
    # ②③ 判据表：导入行后追加导入、末条目后追加条目。
    for 键名, 新行 in (("判据表导入", "from .判据_%s import 检查%d_%s" % (判据名, 序号, 判据名)),
                    ("判据表条目", "    (检查名[%d], 检查%d_%s)," % (序号 - 1, 序号, 判据名))):
        路径, 模式 = 锚点表[键名]
        锚行 = 取末行((目标树 / 路径).read_text(encoding="utf-8"), 模式)
        if 锚行:
            改动项表.append({"路径": 路径, "功能": 1, "旧内容": 锚行, "新内容": 锚行 + "\n" + 新行})
        else:
            未命中表.append("%s（锚点「%s」没命中）" % (键名, 模式))
    # ④ 元数据接线：末条 update 后追加。
    路径, 模式 = 锚点表["元数据接线"]
    锚行 = 取末行((目标树 / 路径).read_text(encoding="utf-8"), 模式)
    if 锚行:
        新行 = "判据元数据.update(%s判据元数据)" % 判据名
        改动项表.append({"路径": 路径, "功能": 1, "旧内容": 锚行, "新内容": 锚行 + "\n" + 新行})
    else:
        未命中表.append("元数据接线（锚点没命中）")
    # ⑤ 自测用例：导入行后追加导入、末条目后追加用例。
    路径, 模式 = 锚点表["用例导入"]
    锚行 = 取末行((目标树 / 路径).read_text(encoding="utf-8"), 模式)
    if 锚行:
        新行 = "from .注入_%s import 注入_%s" % (判据名, 判据名)
        改动项表.append({"路径": 路径, "功能": 1, "旧内容": 锚行, "新内容": 锚行 + "\n" + 新行})
    else:
        未命中表.append("用例导入（锚点没命中）")
    用例文本 = (目标树 / 用例件).read_text(encoding="utf-8")
    用例锚 = ")\n\n样本清单 = 建样本清单()"
    if 用例锚 in 用例文本:
        新行 = ('    ("%s", 检查名[%d],\n     注入_%s, "TODO 被注入件的相对路径"),\n'
              % (简述, 序号 - 1, 判据名))
        改动项表.append({"路径": 用例件, "功能": 1, "旧内容": 用例锚, "新内容": 新行 + 用例锚})
    else:
        未命中表.append("用例条目（锚点「自测用例元组收尾」没命中）")
    return 改动项表, 未命中表


def 名册载荷(判据名: str, 序号: int) -> str:
    """骨架引入的新标识符 ⇒ 一条可粘贴的 `v1_name` 批量登记载荷。"""
    名表 = [["检查%d_%s" % (序号, 判据名)], ["样本_%s面" % 判据名],
          ["%s判据元数据" % 判据名], ["注入_%s" % 判据名],
          ["判据名"], ["简述"], ["目标树"], ["改动项表"], ["未命中表"], ["收尾锚"],
          ["新条目"], ["键名"], ["新行"], ["锚行"], ["路径"], ["模式"],
          ["用例文本"], ["用例锚"], ["验证目录"], ["判据表件"], ["检查名件"],
          ["元数据件"], ["用例件"], ["锚点表"], ["取末行"], ["命中表"],
          ["拼判据件"], ["拼元数据件"], ["拼注入件"], ["拼接线"], ["名册载荷"], ["生成骨架"]]
    return json.dumps({"操作": "批量登记", "参数": {"名单": 名表}}, ensure_ascii=False)


def 生成骨架(目标树: Path, 参数表: dict) -> tuple:
    """⇒ `(退出码, 文本)`：五处骨架 + 一条可粘贴的 `v1_edit` 改动表 + 名册载荷。"""
    判据名 = str(参数表.get("判据名") or "").strip()
    序号原文 = str(参数表.get("序号") or "").strip()
    简述 = str(参数表.get("简述") or "").strip()
    if not 判据名 or not 判据名.isidentifier():
        return 2, "要给 `判据名`（合法标识符，如 `台账形状`）"
    if not 序号原文.isdigit():
        return 2, "要给 `序号`（整数，接在现有判据号之后）"
    if not 简述:
        return 2, "要给 `简述`（一句话，写进检查名与判据件头）"
    序号 = int(序号原文)
    改动表 = [
        {"路径": "%s/判据_%s.py" % (验证目录, 判据名), "功能": 0,
         "新内容": 拼判据件(判据名, 序号, 简述)},
        {"路径": "%s/判据元数据_%s.py" % (验证目录, 判据名), "功能": 0,
         "新内容": 拼元数据件(判据名, 序号, 简述)},
        {"路径": "%s/注入_%s.py" % (验证目录, 判据名), "功能": 0,
         "新内容": 拼注入件(判据名, 序号, 简述)},
    ]
    接线表, 未命中表 = 拼接线(目标树, 判据名, 序号, 简述)
    改动表.extend(接线表)
    输出行表 = ["判据 %d（%s）骨架：%d 处改动（3 处新建 + %d 处接线）"
             % (序号, 简述, len(改动表), len(接线表))]
    if 未命中表:
        输出行表.append("★ 未生成（锚点没命中 ⇒ 手工补）：%s" % " · ".join(未命中表))
    输出行表.append("")
    输出行表.append("一条可粘贴的 `v1_edit` 改动表（把 `改动表` 整段换上）：")
    输出行表.append(json.dumps({"操作": "改", "参数": {"改动表": 改动表}}, ensure_ascii=False))
    输出行表.append("")
    输出行表.append("先把这些新名登记（幂等）：")
    输出行表.append(名册载荷(判据名, 序号))
    输出行表.append("")
    输出行表.append("★ 判据件骨架**故意报红**（判定未填 ⇒ 未实现）：真判定与反向样本填好之前，"
                "闸 0 必红 —— 这是刻意的，别当故障。")
    return 0, "\n".join(输出行表)
