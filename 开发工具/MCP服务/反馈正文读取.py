# -*- coding: utf-8 -*-
"""反馈正文读取 —— `v1_task`「读来源正文」的实现：只读取回某来源报告**正文**。

**为什么单开一件**（判据 ⑲ 单件 ≤400 行）：本口是**读取面**，与 `反馈源快照` 的**存储面**
分开；存储不反向依赖读取面。

**可达性**：B1 实证 —— 原先没有 MCP 口能回读正文（代理由此无法回读）。本口即那个可达口。
**有界不静默截断**：默认整件；件超 `正文字节上限` ⇒ `源正文状态=超限待核`（**不截原文**）；
分页只回一页，另给 `源正文截断` / `源正文下页起始`（拿它续读）。
**同一描述符读 + 回传字节 sha 校验**（在 `反馈源快照.源正文读数` 内）⇒ 无「先核后开」TOCTOU。
**与 646 各司其职**：646 回来源元数据 / 补证分页，本口回正文，不另造第二反馈查询面。
"""

import hashlib
import os

from . import 反馈账本 as 账本
from . import 反馈源快照

源正文_无来源 = "无来源"
源正文_超限 = "超限待核"


def 源正文读数(连接, 来源号: int, 起始偏移: int = 0, 本页字节数: int = 0) -> tuple:
    """来源号 ⇒ `(退出码, 读数字典)` —— **MCP 只读可达口**的底：有界（可分段）回来源报告**正文**。

    · 先取 `快照路径`（内容寻址不可变副本），无则回退 `报告路径`；
    · **同一描述符读取 + 回传字节 sha 校验**（无「先核后开」TOCTOU）；
    · 与 `内容指纹` 不符 / 读不动 / 父链不安全 ⇒ `状态=快照缺失待核`（不静默回错正文）；
    · 件超 `正文字节上限` ⇒ `状态=超限待核`（**不截原文**）；
    · 有界分页：`起始偏移` / `本页字节数`，回 `源正文总字节` / `源正文截断` / `源正文下页起始`。
    """
    来源行 = 连接.execute("select 快照路径, 报告路径, 内容指纹 from 反馈来源 where 来源号 = ?",
                     (来源号,)).fetchone()
    if not 来源行:
        return 2, {"源正文状态": 源正文_无来源, "说明": "来源 %d 不存在" % 来源号}
    期望内容指纹 = 来源行["内容指纹"]
    快照件路径 = 来源行["快照路径"]
    命中路径 = 快照件路径 or 来源行["报告路径"]
    if not 命中路径:
        return 0, {"源正文状态": 反馈源快照.快照状态_无, "源正文指纹": None,
                "源正文总字节": 0, "源正文截断": False, "源正文下页起始": None,
                "说明": "该来源显式无快照（无报告路径）⇒ 无正文可回"}
    退出码, 件描述符号, 件总字节 = 反馈源快照.开只读件(命中路径)
    if 退出码 != 0:
        return 0, {"源正文状态": 反馈源快照.快照状态_缺失, "源正文指纹": None,
                "源正文总字节": 0, "源正文截断": False, "源正文下页起始": None,
                "说明": "快照 / 原路径读不动、父链含 symlink 或末段是链 ⇒ 待核（不静默回错正文）"}
    try:
        if 件总字节 > 反馈源快照.正文字节上限:
            return 0, {"源正文状态": 源正文_超限, "源正文指纹": 期望内容指纹,
                    "源正文总字节": 件总字节, "源正文截断": False, "源正文下页起始": None,
                    "说明": "件 %d 字节 > 上限 %d ⇒ 拒回（不截原文）"
                            % (件总字节, 反馈源快照.正文字节上限)}
        if 起始偏移 < 0 or 起始偏移 > 件总字节:
            return 2, {"说明": "`起始` 越界（件 %d 字节）" % 件总字节}
        页字节 = 本页字节数 if 本页字节数 > 0 else 件总字节 - 起始偏移
        if 页字节 > 反馈源快照.正文字节上限:
            return 2, {"说明": "`页字节` 超上限 %d" % 反馈源快照.正文字节上限}
        os.lseek(件描述符号, 0, os.SEEK_SET)
        摘要器 = hashlib.sha256()
        读块表 = []
        剩余字节 = 件总字节
        while 剩余字节 > 0:
            读块字节 = os.read(件描述符号, min(反馈源快照.分块字节, 剩余字节))
            if not 读块字节:
                break
            摘要器.update(读块字节)
            读块表.append(读块字节)
            剩余字节 -= len(读块字节)
        全字节 = b"".join(读块表)
    finally:
        os.close(件描述符号)
    if 摘要器.hexdigest() != 期望内容指纹:
        return 0, {"源正文状态": 反馈源快照.快照状态_缺失, "源正文指纹": 摘要器.hexdigest(),
                "源正文总字节": 件总字节, "源正文截断": False, "源正文下页起始": None,
                "说明": "件内容 sha 与 `内容指纹` 不符 ⇒ 待核（不静默回错正文）"}
    页字节值 = 全字节[起始偏移:起始偏移 + 页字节]
    下页起始 = 起始偏移 + len(页字节值)
    截断 = 下页起始 < 件总字节
    return 0, {"源正文状态": 反馈源快照.快照状态_有 if 快照件路径 else 反馈源快照.快照状态_原路径,
            "源正文指纹": 摘要器.hexdigest(), "源正文总字节": 件总字节,
            "源正文起始": 起始偏移, "源正文本页字节": len(页字节值),
            "源正文截断": 截断, "源正文下页起始": 下页起始 if 截断 else None,
            "源正文": 页字节值.decode("utf-8", "replace"),
            "快照路径": 快照件路径}


def 读来源正文(仓根, 开工号: str, 参数表: dict) -> tuple:
    """参数 `来源号`（必）· `起始` / `页字节`（可选）⇒ `(退出码, 短回执 JSON)`。只读，零写盘。"""
    来源号 = 参数表.get("来源号")
    起始 = 参数表.get("起始", 0)
    页字节 = 参数表.get("页字节", 0)
    错误表 = []
    if type(来源号) is not int:
        错误表.append("`来源号` 要是整数")
    if type(起始) is not int or 起始 < 0:
        错误表.append("`起始` 要是 ≥0 的整数")
    if type(页字节) is not int or 页字节 < 0:
        错误表.append("`页字节` 要是 ≥0 的整数（0 = 读到尾）")
    if 错误表:
        return 2, "**零读**（读来源正文参数未过）：\n  " + "\n  ".join(错误表)
    连接 = 账本.连反馈库()
    try:
        码, 读数 = 源正文读数(连接, 来源号, 起始, 页字节)
    finally:
        连接.close()
    if 码 != 0:
        return 码, str(读数.get("说明") or "")
    return 0, 账本.拼回执(读数)
