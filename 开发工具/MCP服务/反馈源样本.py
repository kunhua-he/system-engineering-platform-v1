def 样本入口() -> int:
    """跑全部样本 ⇒ 退出码（0 全过）。"""
    样本 = 样本列表()
    for 说明, 通过 in 样本:
        print("%s %s" % ("OK" if 通过 else "FAIL", 说明))
    失败数 = sum(1 for _, 通过 in 样本 if not 通过)
    print("样本 %d 条，失败 %d 条" % (len(样本), 失败数))
    return 1 if 失败数 else 0


