# -*- coding: utf-8 -*-
"""反馈提交 —— 代理**只填发现**：批量提交（客户端幂等键 + 整批事务）与补证。

**代理自报不是验收**：本件只落「现象 / 落点 / 触发 / 预期与实际 / 证据或明确未测」；
判词（债务 / 非问题 / 待核）与关闭在别件（`反馈判词.py` · `反馈审完.py`）。
**提交与补证只认本号**（顶层 `开工ID`）—— 跨开工由主策划按来源开工顶层ID逐批处理，本件不伪造身份。

**整批事务**：一批里任一条不合规 ⇒ **整批零写**（一条 SQL 都不落），逐条列错。
**同键异文拒**：同一客户端幂等键重提另一份载荷 ⇒ 拒且零写；同键同文 ⇒ **重放**（零新行）。
"""

import hashlib
import json
import sqlite3

from . import 反馈账本 as 账本
from . import 反馈源快照

条目文本栏表 = ("现象", "落点", "触发", "预期", "实际", "证据", "未测")
# 「省略要付代价」的四栏：省略就得给**明确未测理由**（收口方 2026-10-08 口径）。
细项栏表 = ("落点", "触发", "预期", "实际")
条目计数栏表 = ("耗时毫秒", "调用次数")


def 取文本(原值) -> str:
    """值 ⇒ 去首尾空白的字符串（`None` ⇒ 空串）。"""
    return "" if 原值 is None else str(原值).strip()


def 规范条目(条目项, 序次: int) -> tuple:
    """一条条目 ⇒ `(规范 dict, 错误表)`（**只判不写**）。"""
    if not isinstance(条目项, dict):
        return {}, ["条目 %d：要是对象" % 序次]
    错误表 = []
    规范 = {栏名: 取文本(条目项.get(栏名)) for 栏名 in 条目文本栏表}
    if not 规范["现象"]:
        错误表.append("条目 %d：缺 `现象`" % 序次)
    缺项 = [栏名 for 栏名 in 细项栏表 if not 规范[栏名]]
    if 缺项 and not 规范["未测"]:
        错误表.append("条目 %d：`%s` 未填 ⇒ 须给明确 `未测` 理由"
                 % (序次, " · ".join(缺项)))
    if not 规范["证据"] and not 规范["未测"]:
        错误表.append("条目 %d：`证据` 与 `未测` 至少给一个" % 序次)
    for 栏名 in 条目计数栏表:
        计数原值 = 条目项.get(栏名)
        if 计数原值 is None or 计数原值 == "":
            规范[栏名] = None
        elif type(计数原值) is not int or 计数原值 < 0:
            错误表.append("条目 %d：`%s` 要是非负整数" % (序次, 栏名))
            规范[栏名] = None
        else:
            规范[栏名] = 计数原值
    return 规范, 错误表


def 提交反馈(仓根, 开工号: str, 参数表: dict) -> tuple:
    """批量提交一批反馈 ⇒ `(退出码, 短回执 JSON)`。"""
    if not 账本.是开工号(开工号):
        return 2, "提交反馈要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    幂等键 = 取文本(参数表.get("幂等键"))
    来源标识 = 取文本(参数表.get("来源标识"))
    报告指纹 = 取文本(参数表.get("报告指纹"))
    报告路径 = 取文本(参数表.get("报告路径")) or None
    读取状态 = 取文本(参数表.get("读取状态")) or 账本.读取_未读
    条目表 = 参数表.get("条目")
    错误表 = []
    if not 幂等键:
        错误表.append("缺 `幂等键`（客户端批次幂等键）")
    if not 来源标识:
        错误表.append("缺 `来源标识`（代理 / 报告标识）")
    if 读取状态 == 账本.读取_缺件 and not 报告指纹:
        # 缺件：无内容身份 ⇒ 用标记串占位（发现输出后新 sha = **新来源**，不覆盖旧记录）。
        报告指纹 = 账本.缺件指纹标记
    elif 读取状态 == 账本.读取_空报告 and 报告指纹 != 账本.空字节报告指纹:
        # 空报告的指纹**不是形状问题、是身份问题**：必须逐字等于空字节 sha256，别的一律拒。
        错误表.append("`读取状态` = 空报告待核 ⇒ `报告指纹` 必须逐字等于空字节 sha256（%s）；收到 %r"
                 % (账本.空字节报告指纹, 报告指纹))
    elif not 账本.是报告指纹(报告指纹):
        错误表.append("`报告指纹` 要是十六进制内容 sha（8..128 位；空报告用空字节 sha256；"
                 "缺件待核可留空）")
    if 读取状态 not in 账本.读取状态档表:
        错误表.append("`读取状态` 只认 %s" % " · ".join(账本.读取状态档表))
    if not isinstance(条目表, list):
        错误表.append("`条目` 要是数组")
        条目表 = []
    规范表 = []
    for 序次, 条目项 in enumerate(条目表, 1):
        规范, 条目错 = 规范条目(条目项, 序次)
        错误表 += 条目错
        规范表.append(规范)
    if 错误表:
        return 2, "**整批零写**（提交反馈校验未过）：\n  " + "\n  ".join(错误表)
    # ── 正文快照（可选）：有路径且可读 ⇒ 核真实完整 hash 后存内容寻址副本 ──
    待存正文 = None
    if 报告路径 and 读取状态 in (账本.读取_未读, 账本.读取_已读, 账本.读取_空报告):
        正文字节 = 反馈源快照.读整件(报告路径, 反馈源快照.读正文上限(仓根))
        if 正文字节 is None:
            return 2, ("**整批零写**：`报告路径` 读不动 / 非普通件 / 超 `正文字节上限`（%d 字节）"
                    "⇒ 拒（不截原文）" % 反馈源快照.读正文上限(仓根))
        实算指纹 = hashlib.sha256(正文字节).hexdigest()
        if 实算指纹 != 报告指纹:
            return 2, ("**整批零写**：`报告路径` 内容 sha（%s）与 `报告指纹`（%s）不符 ⇒ "
                    "路径指向可变件或指纹过期（先重新清点）" % (实算指纹[:12], 报告指纹[:12]))
        待存正文 = 正文字节
    载荷 = {"来源标识": 来源标识, "报告指纹": 报告指纹, "报告路径": 报告路径,
          "读取状态": 读取状态, "条目": 规范表}
    载荷指纹 = 账本.算指纹(载荷)
    with 反馈源快照.锁快照(仓根):
        return _提交一批(仓根, 开工号, 幂等键, 来源标识, 报告指纹, 报告路径, 读取状态,
                     规范表, 载荷指纹, 待存正文)


def _提交一批(仓根, 开工号, 幂等键, 来源标识, 报告指纹, 报告路径, 读取状态,
          规范表, 载荷指纹, 待存正文) -> tuple:
    """锁内一批提交：文件先写、DB 后提交；失败回滚（**只删本次新建且复核无引用**的快照件）。"""
    快照件路径 = None
    新建快照 = False
    if 待存正文 is not None:
        try:
            快照件路径, 新建快照 = 反馈源快照.存正文(仓根, 待存正文)
        except 反馈源快照.快照写不动 as 错误:
            return 2, "**整批零写**：快照写不动（%s）" % 错误
    已提交 = False
    连接 = 账本.连反馈库()
    try:
        if not 账本.开工在吗(连接, 开工号):
            return 1, "没有这条开工：%s ⇒ 先登记" % 开工号
        已有批次 = 连接.execute("select * from 反馈批次 where 幂等键 = ?", (幂等键,)).fetchone()
        if 已有批次:
            if 已有批次["载荷指纹"] != 载荷指纹:
                return 2, ("**同键异文拒**（整批零写）：幂等键 `%s` 已用于另一份载荷"
                        "（原 %s ≠ 今 %s）—— 换一个幂等键重提" % (幂等键,
                        已有批次["载荷指纹"][:12], 载荷指纹[:12]))
            原结果 = json.loads(已有批次["结果摘要"])
            return 0, 账本.拼回执({"重放": True, "幂等键": 幂等键, **原结果})
        来源行 = 连接.execute(
            "select 来源号 from 反馈来源 where 开工号 = ? and 来源标识 = ? and 内容指纹 = ?",
            (开工号, 来源标识, 报告指纹)).fetchone()
        新建来源 = 来源行 is None
        if 新建来源:
            # **并发同来源**：两个进程同提一份报告 ⇒ 都查不到来源、都想建 ⇒ 用 `do nothing` 让
            # 后到者安静落地，再重读拿号（否则唯一约束会误伤成「同键异文」）。
            写入行数 = 连接.execute(
                "insert into 反馈来源 (开工号, 来源标识, 内容指纹, 报告路径, 快照路径, "
                "读取状态, 登记时刻) "
                "values (?, ?, ?, ?, ?, ?, ?) on conflict(开工号, 来源标识, 内容指纹) do nothing",
                (开工号, 来源标识, 报告指纹, 报告路径, 快照件路径, 读取状态,
                 账本.时刻串())).rowcount
            新建来源 = 写入行数 == 1
            来源号 = 连接.execute(
                "select 来源号 from 反馈来源 where 开工号 = ? and 来源标识 = ? and 内容指纹 = ?",
                (开工号, 来源标识, 报告指纹)).fetchone()["来源号"]
        else:
            来源号 = 来源行["来源号"]
            连接.execute("update 反馈来源 set 报告路径 = coalesce(?, 报告路径), "
                      "快照路径 = coalesce(?, 快照路径), 读取状态 = ? where 来源号 = ?",
                      (报告路径, 快照件路径, 读取状态, 来源号))
        已有指纹集 = {数据行[0] for 数据行 in 连接.execute(
            "select 条目指纹 from 反馈条目 where 来源号 = ?", (来源号,))}
        新增号表 = []
        跳过数 = 0
        for 规范 in 规范表:
            条目指纹 = 账本.算指纹(规范)
            if 条目指纹 in 已有指纹集:
                跳过数 += 1
                continue
            已有指纹集.add(条目指纹)
            新增号表.append(连接.execute(
                "insert into 反馈条目 (来源号, 开工号, 现象, 落点, 触发, 预期, 实际, 证据, 未测, "
                "耗时毫秒, 调用次数, 条目指纹, 登记时刻) "
                "values (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (来源号, 开工号, 规范["现象"], 规范["落点"], 规范["触发"], 规范["预期"], 规范["实际"],
                 规范["证据"], 规范["未测"], 规范["耗时毫秒"], 规范["调用次数"], 条目指纹,
                 账本.时刻串())).lastrowid)
        提取条数 = 连接.execute("select count(*) from 反馈条目 where 来源号 = ?",
                          (来源号,)).fetchone()[0]
        连接.execute("update 反馈来源 set 提取条数 = ? where 来源号 = ?", (提取条数, 来源号))
        提交结果 = {"来源号": 来源号, "新建来源": 新建来源, "新增条目": len(新增号表),
                "跳过重复": 跳过数, "条目号": 新增号表, "该来源现提取条数": 提取条数}
        连接.execute("insert into 反馈批次 (幂等键, 开工号, 载荷指纹, 结果摘要, 提交时刻) "
                  "values (?, ?, ?, ?, ?)",
                  (幂等键, 开工号, 载荷指纹,
                   json.dumps(提交结果, ensure_ascii=False), 账本.时刻串()))
        连接.commit()
        已提交 = True
        return 0, 账本.拼回执({"重放": False, "幂等键": 幂等键, **提交结果})
    except sqlite3.IntegrityError:
        # **并发同键**：两个进程同提一个幂等键 ⇒ 后到者在 `反馈批次` 主键上撞车。
        # 整批回滚（本进程写的行全撤，先到者的已提交行留着）后重读：同文 ⇒ 重放，异文 ⇒ 拒。
        连接.rollback()
        已提批次 = 连接.execute("select * from 反馈批次 where 幂等键 = ?", (幂等键,)).fetchone()
        if 已提批次 and 已提批次["载荷指纹"] == 载荷指纹:
            原结果 = json.loads(已提批次["结果摘要"])
            return 0, 账本.拼回执({"重放": True, "幂等键": 幂等键, **原结果})
        return 2, ("**同键异文拒**（整批零写 · 并发撞车）：幂等键 `%s` 已被另一份载荷占用"
                "—— 换一个幂等键重提" % 幂等键)
    except Exception:
        连接.rollback()
        raise
    finally:
        连接.close()
        if 新建快照 and not 已提交:
            # 回滚：**只删本次新建**且**复核无别的来源行引用**的快照件（防毁后到者同 sha 件）
            复查连接 = 账本.连反馈库()
            try:
                if not 反馈源快照.快照被引用(复查连接, 快照件路径):
                    反馈源快照.删件(快照件路径)
            finally:
                复查连接.close()


def 补证(仓根, 开工号: str, 参数表: dict) -> tuple:
    """给已有条目补一条证据（只增不改；**只认本号**）⇒ `(退出码, 短回执 JSON)`。"""
    if not 账本.是开工号(开工号):
        return 2, "补证要顶层 `开工ID`（`v1-` 加六位数字）；收到 %r" % (开工号,)
    补证表 = 参数表.get("补证表")
    if not isinstance(补证表, list) or not 补证表:
        return 2, "`补证表` 要是非空数组"
    错误表 = []
    规范表 = []
    for 序次, 补证项 in enumerate(补证表, 1):
        if not isinstance(补证项, dict):
            错误表.append("补证 %d：要是对象" % 序次)
            continue
        条目号 = 补证项.get("条目号")
        证据 = 取文本(补证项.get("证据"))
        if type(条目号) is not int:
            错误表.append("补证 %d：`条目号` 要是整数" % 序次)
            continue
        if not 证据:
            错误表.append("补证 %d：缺 `证据`" % 序次)
            continue
        规范表.append({"条目号": 条目号, "证据": 证据,
                   "来源": 取文本(补证项.get("来源")) or None})
    if 错误表:
        return 2, "**整批零写**（补证校验未过）：\n  " + "\n  ".join(错误表)
    连接 = 账本.连反馈库()
    try:
        if not 账本.开工在吗(连接, 开工号):
            return 1, "没有这条开工：%s ⇒ 先登记" % 开工号
        越界错 = []
        for 规范 in 规范表:
            条目行 = 账本.读条目(连接, 规范["条目号"])
            if not 条目行:
                越界错.append("补证条目 %d：不存在" % 规范["条目号"])
            elif 条目行["开工号"] != 开工号:
                越界错.append("补证条目 %d：属开工 %s ⇒ **跨开工越界**（补证只认本号）"
                         % (规范["条目号"], 条目行["开工号"]))
        if 越界错:
            return 2, "**整批零写**（补证越界）：\n  " + "\n  ".join(越界错)
        for 规范 in 规范表:
            连接.execute("insert into 反馈证据 (条目号, 证据, 来源, 补证开工号, 补证时刻) "
                      "values (?, ?, ?, ?, ?)",
                      (规范["条目号"], 规范["证据"], 规范["来源"], 开工号, 账本.时刻串()))
        连接.commit()
        return 0, 账本.拼回执({"补证条数": len(规范表),
                         "条目号": [规范["条目号"] for 规范 in 规范表]})
    except Exception:
        连接.rollback()
        raise
    finally:
        连接.close()
