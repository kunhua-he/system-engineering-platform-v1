# -*- coding: utf-8 -*-
"""跨树 —— `v1_tree` 的实现：按开工ID 或 ref 只读读文件 / 列文件 / 存在性 / 差集。

**为什么要有它**（多路代理实测）：① 按开工ID 或 commit/树 读一个件，现在要手拼
`git worktree list` + `git show <ref>:<路径>` 好几次往返；② 列一树文件要 `git ls-tree`
（中文路径还会被 quote 成 `\344\270\255` 的假阴性）；③ 查一个件/符号在不在旧树里要反复
`ls` / `git cat-file`；④ **多路代理的成果只在工作树未提交** ⇒ `git diff 主干..腿` 恒为空，
反复返工。本件把这四件事各收成一个**有界只读回执**。

★ **回执必带该树 HEAD · 分支 · 相对主干位次** —— 拿旧树读到的代码当现状是最贵的坑。
**只读零写**：只跑查询类 git 子命令；不改任何件、不写索引/台账。
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))     # 开发工具/

from .仓操作 import 找工作树                                       # noqa: E402
from .仓状态 import (参数错, 取开工号, 取记录条数, 拒未知, 收尾, 主干引用,  # noqa: E402
                 相对主干位次, 跑git, 骨架)

上限行 = 200
上限字节 = 400000

def _定位(仓根, 开工号, 引用) -> tuple:
    """⇒ `(定位, 错误)`；`定位` = {树根, 引用, 树名, 树头, 分支, 位次}。
    开工号 优先（读**工作树**，含未提交）；引用 其次（读 git 对象）；都不给 ⇒ 主干。"""
    引用 = str(引用 or "").strip()
    if 开工号:
        工作树 = 找工作树(仓根, 开工号)
        if 工作树 is None or not 工作树.is_dir():
            return None, "开工 %s 的工作树不在（问 git 问不到）⇒ 不编路径" % 开工号
        退出码, 提交 = 跑git(仓根, ["rev-parse", "--short", "HEAD"], 树根=工作树)
        退出码, 分支 = 跑git(仓根, ["branch", "--show-current"], 树根=工作树)
        return {"树根": 工作树, "引用": "", "树名": "开工 %s 的工作树 %s" % (开工号, 工作树),
                "树头": 提交.strip() or "读不出", "分支": 分支.strip() or "（游离）",
                "位次": 相对主干位次(仓根, "HEAD", 树根=工作树)}, ""
    if not 引用:
        引用 = 主干引用(仓根)
        if not 引用:
            return None, "主干引用读不出 ⇒ 不编引用"
    退出码, 提交 = 跑git(仓根, ["rev-parse", "--short", "%s^{commit}" % 引用])
    if 退出码 != 0:
        return None, "引用读不出：%s（%s）" % (引用, 提交.strip()[-120:])
    return {"树根": Path(仓根), "引用": 引用, "树名": "引用 %s" % 引用,
            "树头": 提交.strip(), "分支": "（引用）", "位次": 相对主干位次(仓根, 引用)}, ""

def _头行(定位) -> list:
    return ["【%s】HEAD %s · 分支 %s · 相对主干 %s"
           % (定位["树名"], 定位["树头"], 定位["分支"], 定位["位次"])]

def _件文(仓根, 定位, 路径) -> tuple:
    """读那个树下的一个件 ⇒ `(全文 或 None, 错误)`。引用走 git 对象，工作树走盘上件。"""
    if 定位["引用"]:
        退出码, 输出文本 = 跑git(仓根, ["show", "%s:%s" % (定位["引用"], 路径)])
        if 退出码 != 0:
            return None, "该引用下没有这个件（或读不出）：%s" % 输出文本.strip()[-200:]
        return 输出文本[:上限字节], ""
    件路径 = 定位["树根"] / 路径
    if not 件路径.is_file():
        return None, "该树下没有这个件：%s" % 件路径
    return 件路径.read_text(encoding="utf-8", errors="replace")[:上限字节], ""

def _路径(源码行, 偏) -> str:
    """从 `git status --porcelain`（偏=3）或 `git diff --name-status`（偏=1）的一行里取路径。"""
    段表 = 源码行.split(None, 1)
    if len(段表) < 2:
        return ""
    路径 = 段表[1].strip().strip('"')
    return 路径.split(" -> ")[-1].strip().strip('"') if " -> " in 路径 else 路径

def _按区(行表, 名表) -> None:
    区表 = {}
    for 路径 in 名表:
        区名 = 路径.split("/")[0] if "/" in 路径 else 路径
        区表[区名] = 区表.get(区名, 0) + 1
    for 区名 in sorted(区表):
        行表.append("    %s  %d 件" % (区名, 区表[区名]))

def 读文件(仓根, 参数表) -> tuple:
    拒未知(参数表, ("路径", "开工ID", "引用"))
    路径 = str(参数表.get("路径") or "").strip()
    if not 路径:
        raise 参数错("缺 `路径`（要读哪个件）")
    if 路径.startswith("/") or ".." in Path(路径).parts:
        raise 参数错("`路径` 只认仓内相对路径（收到 %r）" % 路径)
    定位, 错误 = _定位(仓根, 取开工号(参数表), 参数表.get("引用"))
    if 错误:
        return 1, 错误
    行表 = _头行(定位)
    全文, 错误 = _件文(仓根, 定位, 路径)
    if 错误:
        return 1, "\n".join(行表 + ["★ " + 错误])
    行表.append("件：%s · 行数 %d" % (路径, 全文.count("\n") + 1))
    行表.append("")
    行表 += 全文.split("\n")[:上限行]
    if 全文.count("\n") + 1 > 上限行:
        行表.append("…（只列前 %d 行，共 %d 行）" % (上限行, 全文.count("\n") + 1))
    return 0, 收尾(行表)

def 列文件(仓根, 参数表) -> tuple:
    拒未知(参数表, ("路径前缀", "开工ID", "引用", "条数"))
    记录条数 = 取记录条数(参数表)
    路径前缀 = str(参数表.get("路径前缀") or "").strip()
    定位, 错误 = _定位(仓根, 取开工号(参数表), 参数表.get("引用"))
    if 错误:
        return 1, 错误
    范围 = ["--", 路径前缀] if 路径前缀 else []
    命令 = (["ls-tree", "-r", "--name-only", 定位["引用"]] if 定位["引用"]
          else ["ls-files", "--cached", "--others", "--exclude-standard"])
    退出码, 输出文本 = 跑git(仓根, 命令 + 范围, 树根=定位["树根"])
    if 退出码 != 0:
        return 1, "\n".join(_头行(定位) + ["列文件失败：%s" % 输出文本.strip()[-200:]])
    名表 = [源码行 for 源码行 in 输出文本.splitlines() if 源码行.strip()]
    行表 = _头行(定位)
    行表.append("件数 %d（%s · 强制 core.quotePath=false 防中文路径假阴性）"
             % (len(名表), "引用树" if 定位["引用"] else "工作树（含未跟踪）"))
    for 源码行 in 名表[:记录条数]:
        行表.append("  %s" % 源码行)
    if len(名表) > 记录条数:
        行表.append("  …（还有 %d 件，收窄 `路径前缀` 再取）" % (len(名表) - 记录条数))
    return 0, 收尾(行表)

def 存在性(仓根, 参数表) -> tuple:
    拒未知(参数表, ("路径", "符号", "开工ID", "引用"))
    路径 = str(参数表.get("路径") or "").strip()
    if not 路径:
        raise 参数错("缺 `路径`（要查哪个件）")
    符号 = str(参数表.get("符号") or "").strip()
    定位, 错误 = _定位(仓根, 取开工号(参数表), 参数表.get("引用"))
    if 错误:
        return 1, 错误
    行表 = _头行(定位)
    if 定位["引用"]:
        退出码, 输出文本 = 跑git(仓根, ["cat-file", "-e", "%s:%s" % (定位["引用"], 路径)])
        标记值 = 退出码 == 0
    else:
        标记值 = (定位["树根"] / 路径).exists()
    行表.append("件 %s：%s" % (路径, "在" if 标记值 else "不在"))
    if not 符号:
        return 0, 收尾(行表)
    if not 标记值:
        return 0, 收尾(行表 + ["（件不在 ⇒ 符号无从查）"])
    全文, 错误 = _件文(仓根, 定位, 路径)
    if 错误:
        return 0, 收尾(行表 + ["（件在但读不出 ⇒ 符号未判：%s）" % 错误])
    命中 = re.search(r"(?<![\w])%s(?![\w])" % re.escape(符号), 全文)
    行表.append("符号 %s：%s" % (符号, "在（整词命中）" if 命中 else "不在（未整词命中）"))
    return 0, 收尾(行表)

def 差集(仓根, 参数表) -> tuple:
    """某开工树 相对主干 的**未提交 / 已提交**差集摘要（按区 / 按件）。

    为什么单列它：多路代理的成果只在工作树未提交 ⇒ `git diff 主干..腿` 恒为空（实测多轮返工）。
    本操作把「已提交（主干...HEAD 三点）」与「未提交（工作树 vs HEAD）」分开报，**未提交那栏才是现场**。
    """
    拒未知(参数表, ("开工ID", "范围", "条数"))
    记录条数 = 取记录条数(参数表)
    开工号 = 取开工号(参数表)
    if not 开工号:
        raise 参数错("缺 `开工ID`（差集是「某开工树 相对主干」的）")
    工作树 = 找工作树(仓根, 开工号)
    if 工作树 is None or not 工作树.is_dir():
        return 1, "开工 %s 的工作树不在（问 git 问不到）" % 开工号
    范围 = str(参数表.get("范围") or "").strip()
    行表 = ["【开工 %s 的工作树】%s" % (开工号, 工作树),
           "相对主干：%s" % 相对主干位次(仓根, "HEAD", 树根=工作树)]
    退出码, 输出文本 = 跑git(仓根, ["diff", "--name-status", "主干...HEAD"], 树根=工作树)
    差异 = [源码行 for 源码行 in 输出文本.splitlines() if 源码行.strip()] if 退出码 == 0 else []
    路径表 = [_路径(源码行, 1) for 源码行 in 差异]
    退出码, 输出文本 = 跑git(仓根, ["status", "--porcelain=v1", "-uall"], 树根=工作树)
    变更表 = [源码行 for 源码行 in 输出文本.splitlines() if 源码行.strip()] if 退出码 == 0 else []
    名表 = [_路径(源码行, 3) for 源码行 in 变更表]
    if 范围:
        路径表 = [路径 for 路径 in 路径表 if 路径.startswith(范围)]
        名表 = [路径 for 路径 in 名表 if 路径.startswith(范围)]
    行表.append("已提交（主干...HEAD 三点，merge-base 起）：%d 件" % len(路径表))
    _按区(行表, 路径表)
    for 路径 in 路径表[:记录条数]:
        行表.append("    %s" % 路径)
    行表.append("未提交（工作树 vs HEAD —— 现场那栏）：%d 件" % len(名表))
    _按区(行表, 名表)
    for 源码行 in 变更表[:记录条数]:
        行表.append("    %s" % 源码行)
    if len(变更表) > 记录条数:
        行表.append("    …（还有 %d 件）" % (len(变更表) - 记录条数))
    return 0, 收尾(行表)

