# -*- coding: utf-8 -*-
"""开工记忆样本 —— 项目记忆（检查点 / 一次取回 / 安全收口清理）的正反样本。

`自检样本.自检主体` 调它（判据 ㊽ 跑自检，退出码非 0 ⇒ 闸 0 当场红）。**仓一个字节都不改**：
账本连口、清树安全、非终态作业、消费者行、台账读口、未蒸馏反馈都走替身；夹具是临时目录，跑完即删。
★ 自检全程在**临时记账域**里（`工具流水.临时记账库`）⇒ 本样本把记账目的地**一并指到本夹具账本**：
否则「安全收口真删流水」「只检查 / 被拒不落流水」两条断言会静默变空（域内流水不再落夹具）。

七档口径（安全收口与 `开工.单纯释放` 物理删除门禁共用 `清树门禁.核清树条件`）：
① 检查点写入后可一次取回（摘要含已写字段，未记录项写「（未记录）」）。
② 无显式检查点 ⇒ 摘要不虚构（明说无可合成）。
③ 未合腿 / 有非终态作业 / 未收口 ⇒ 清理拒（保留检查点与流水）。
④ 有未释放继承者 / 基线消费者 ⇒ 清理拒（`父开工号` = 本号的别的开工）。
⑤ 有未蒸馏反馈（反馈保护口非空）⇒ 清理拒。
⑥ 安全条件成立但无 `确认` ⇒ 默认拒（一个字节不删）。
⑦ 安全收口 ⇒ 真删检查点与流水，且 `开工` 账本行仍在（不留历史库、不删账本行）。
另：`只检查` / 被拒 `v1_edit` 不落流水（写操作的关键证据走真实事务，不由流水代保证）。
"""

import shutil
import sqlite3
import sys
import tempfile
import types
from pathlib import Path


def 开工记忆样本(仓根, 工具表) -> list:
    """跑项目记忆正反样本 ⇒ 样本表。"""
    from . import 工具流水, 开工账本, 开工记忆, 清树门禁

    临时根 = Path(tempfile.mkdtemp(prefix="v1开工记忆自检-"))
    try:
        账本路径 = 临时根 / "账本.db"
        连接 = sqlite3.connect(str(账本路径))
        连接.row_factory = sqlite3.Row
        for 建表行 in 开工账本.建表语句:
            连接.execute(建表行)
        沙箱号, 收口号 = "v1-900001", "v1-900002"
        沙箱树, 收口树 = 临时根 / "沙箱树", 临时根 / "收口树"
        沙箱树.mkdir()
        收口树.mkdir()
        开工账本.登记开工(连接, 沙箱号, "记忆样本活腿", "腿/" + 沙箱号, str(沙箱树))
        开工账本.登记开工(连接, 收口号, "记忆样本收口", "腿/" + 收口号, str(收口树))
        开工账本.置状态(连接, 收口号, 开工账本.状态_已释放)
        连接.commit()
        连接.close()

        def 开账():
            新连接 = sqlite3.connect(str(账本路径))
            新连接.row_factory = sqlite3.Row
            return 新连接

        真连, 真清树, 真作业 = 开工账本.连账本, 清树门禁.检查清树安全, 清树门禁.非终态作业
        真消费者, 真台账, 真反馈 = 清树门禁.消费者行, 清树门禁.读未完成行, 清树门禁.未蒸馏反馈行
        真目的地 = 工具流水.记账目的地.set(账本路径)
        开工账本.连账本 = 开账
        清树门禁.检查清树安全 = lambda 仓根, 开工号, 工作树: (0, "支线已合并到主工作树")
        清树门禁.非终态作业 = lambda 开工号, 工作树: []
        清树门禁.消费者行 = lambda 开工号: []
        清树门禁.读未完成行 = lambda 仓根, 开工号: []
        清树门禁.未蒸馏反馈行 = lambda 连接, 仓根, 开工号: []
        出口 = 工具表["v1_task"][0]
        样本表 = []
        try:
            # ① 检查点写入后可一次取回
            退出码, 回执 = 出口({"开工ID": 沙箱号, "操作": "记检查点",
                          "参数": {"目标": "内置记忆", "当前步骤": "落检查点", "下一动作": "取回"}}, 仓根)
            检查点已落 = 退出码 == 0 and "编号" in 回执
            退出码, 取回 = 出口({"开工ID": 沙箱号, "操作": "取检查点"}, 仓根)
            样本表.append(("检查点写入后可一次取回：落%s · 取回退出码 %d · 摘要含「下一动作：取回」%s"
                    % ("是" if 检查点已落 else "否", 退出码, "是" if "下一动作：取回" in 取回 else "否"),
                    检查点已落 and 退出码 == 0 and "下一动作：取回" in 取回
                    and "未测：（未记录）" in 取回))
            # ② 无显式检查点 ⇒ 不虚构
            退出码, 空取回 = 出口({"开工ID": 收口号, "操作": "取检查点"}, 仓根)
            样本表.append(("无显式检查点 ⇒ 摘要不虚构",
                    退出码 == 0 and "无显式检查点" in 空取回 and "不虚构" in 空取回))
            # ③ 空检查点拒
            退出码, 空检查拒 = 出口({"开工ID": 沙箱号, "操作": "记检查点", "参数": {}}, 仓根)
            样本表.append(("空检查点拒（退出码 %d，期望 2）" % 退出码, 退出码 == 2))
            # ④ 未合腿 / 非终态作业 / 未释放消费者 / 未蒸馏反馈 / 未收口 ⇒ 清理拒
            清树门禁.检查清树安全 = lambda 仓根, 开工号, 工作树: (1, "支线尚未合并")
            退出码, 拒未合 = 出口({"开工ID": 收口号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            样本表.append(("未合腿 ⇒ 清理拒（退出码 %d）" % 退出码, 退出码 != 0 and "拒" in 拒未合))
            清树门禁.检查清树安全 = lambda 仓根, 开工号, 工作树: (0, "支线已合并到主工作树")
            清树门禁.非终态作业 = lambda 开工号, 工作树: ["任务X · 运行中"]
            退出码, 拒作业 = 出口({"开工ID": 收口号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            样本表.append(("非终态 job ⇒ 清理拒（退出码 %d）" % 退出码, 退出码 != 0 and "拒" in 拒作业))
            清树门禁.非终态作业 = lambda 开工号, 工作树: []
            清树门禁.消费者行 = lambda 开工号: [{"开工号": "v1-900009", "状态": 开工账本.状态_进行中,
                                        "开工种类": 开工账本.种类_原腿}]
            退出码, 拒消费者 = 出口({"开工ID": 收口号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            样本表.append(("未释放基线消费者 ⇒ 清理拒（退出码 %d · 定位含 v1-900009）" % 退出码,
                    退出码 != 0 and "拒" in 拒消费者 and "v1-900009" in 拒消费者
                    and "基线消费者" in 拒消费者))
            清树门禁.消费者行 = lambda 开工号: []
            清树门禁.未蒸馏反馈行 = lambda 连接, 仓根, 开工号: ["反馈X：未判词"]
            退出码, 拒反馈 = 出口({"开工ID": 收口号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            样本表.append(("未蒸馏反馈 ⇒ 清理拒（退出码 %d · 定位含未蒸馏反馈）" % 退出码,
                    退出码 != 0 and "拒" in 拒反馈 and "未蒸馏反馈" in 拒反馈))
            清树门禁.未蒸馏反馈行 = lambda 连接, 仓根, 开工号: []
            退出码, 拒未收口 = 出口({"开工ID": 沙箱号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            样本表.append(("未收口（进行中）⇒ 清理拒（退出码 %d）" % 退出码,
                    退出码 != 0 and "拒" in 拒未收口))
            连接 = 开账()
            留检查点 = 连接.execute("select count(*) from 开工检查点 where 开工号 = ?", (沙箱号,)).fetchone()[0]
            连接.close()
            样本表.append(("清理拒后保留检查点（%d ≥ 1）" % 留检查点, 留检查点 >= 1))
            # ⑤ 条件成立但无确认 ⇒ 默认拒
            退出码, 默认拒 = 出口({"开工ID": 收口号, "操作": "安全清收口"}, 仓根)
            样本表.append(("安全条件成立但默认拒（退出码 %d，期望 2）" % 退出码,
                    退出码 == 2 and "默认拒绝" in 默认拒))
            # ⑥ 安全收口 ⇒ 真删且账本行仍在
            退出码, 收口回执 = 出口({"开工ID": 收口号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            连接 = 开账()
            账本行数 = 连接.execute("select count(*) from 开工 where 开工号 = ?", (收口号,)).fetchone()[0]
            流水留数 = 连接.execute("select count(*) from 工具流水 where 开工号 = ?", (收口号,)).fetchone()[0]
            连接.close()
            样本表.append(("安全收口 ⇒ 真删检查点与流水 · 账本行仍在（不留历史库）",
                    退出码 == 0 and "已真删" in 收口回执 and 账本行数 == 1 and 流水留数 == 0))
            # ⑦ 只检查 / 被拒 v1_edit 不落流水
            连接 = 开账()
            流水前数 = 连接.execute("select count(*) from 工具流水").fetchone()[0]
            连接.close()
            出口({"开工ID": 沙箱号, "操作": "只检查", "参数": {"改动表": [
                {"路径": "新件.py", "操作": "新建", "新内容": "配置文件 = 1\n"}]}}, 仓根)
            连接 = 开账()
            流水后数 = 连接.execute("select count(*) from 工具流水").fetchone()[0]
            连接.close()
            样本表.append(("只检查 / 被拒 v1_edit 不落流水（写证据走真实事务）", 流水后数 == 流水前数))
            # ⑧ 反馈保护口：未合入 ⇒ 未启用（空、不阻断）；在场且出错 ⇒ fail-closed（非空）；非空 ⇒ 原样返回
            真启用 = 清树门禁.反馈保护启用
            清树门禁.反馈保护启用 = lambda: False
            样本表.append(("反馈保护口未合入 ⇒ 未启用返回空（不阻断）",
                    真反馈(开账(), 仓根, 收口号) == []))
            from . import 反馈关联
            旧模块 = sys.modules.get("MCP服务.反馈关联")
            样本表.append(("替身前置：真 `反馈关联` 已加载（旧模块非空 %s）" % (旧模块 is not None),
                    旧模块 is not None))
            假模块 = types.ModuleType("MCP服务.反馈关联")

            def 坏口(连接, 仓根, 开工号):
                raise RuntimeError("口坏")

            # ★ 替身模块用完**必须还原真模块对象**（不是 `del`）：真 `反馈关联` 已被 import 过时，
            #   `del sys.modules[...]` 会把那份**真模块对象**从缓存里抹掉（身份丢失）—— 同进程
            #   后续接缝调用拿到的就不是同一份实现了。`旧模块` 存原值 + try/finally 还原。
            try:
                假模块.未蒸馏反馈集 = 坏口
                sys.modules["MCP服务.反馈关联"] = 假模块
                清树门禁.反馈保护启用 = lambda: True
                失败行 = 真反馈(开账(), 仓根, 收口号)
                样本表.append(("反馈保护口在场但出错 ⇒ fail-closed（非空且明说）",
                        失败行 and "fail-closed" in 失败行[0]))
                假模块.未蒸馏反馈集 = lambda 连接, 仓根, 开工号: ["反馈Y：未判词"]
                样本表.append(("反馈保护口在场且非空 ⇒ 原样返回",
                        真反馈(开账(), 仓根, 收口号) == ["反馈Y：未判词"]))
            finally:
                if 旧模块 is None:
                    sys.modules.pop("MCP服务.反馈关联", None)
                else:
                    sys.modules["MCP服务.反馈关联"] = 旧模块
            清树门禁.反馈保护启用 = 真启用
            还原模块 = sys.modules.get("MCP服务.反馈关联")
            样本表.append(("替身用完 ⇒ 真模块**身份与功能**都还原（身份同旧 %s · 口可调 %s）"
                    % (还原模块 is 旧模块,
                       callable(getattr(还原模块, "未蒸馏反馈集", None))),
                    还原模块 is 旧模块
                    and callable(getattr(还原模块, "未蒸馏反馈集", None))))
        finally:
            开工账本.连账本, 清树门禁.检查清树安全, 清树门禁.非终态作业 = 真连, 真清树, 真作业
            清树门禁.消费者行, 清树门禁.读未完成行, 清树门禁.未蒸馏反馈行 = 真消费者, 真台账, 真反馈
            工具流水.记账目的地.reset(真目的地)
        return 样本表
    finally:
        shutil.rmtree(临时根, ignore_errors=True)
