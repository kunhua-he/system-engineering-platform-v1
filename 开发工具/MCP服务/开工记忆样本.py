# -*- coding: utf-8 -*-
"""开工记忆样本 —— 项目记忆（检查点 / 一次取回 / 安全收口清理）的正反样本。

`自检样本.自检主体` 调它（判据 ㊽ 跑自检，退出码非 0 ⇒ 闸 0 当场红）。**仓一个字节都不改**：
账本连口、清树安全、非终态作业、子开工、台账读口都走替身；夹具是临时目录，跑完即删。

五档口径：
① 检查点写入后可一次取回（摘要含已写字段，未记录项写「（未记录）」）。
② 无显式检查点 ⇒ 摘要不虚构（明说无可合成）。
③ 未合腿 / 有非终态作业 / 未收口 ⇒ 清理拒（保留检查点与流水）。
④ 安全条件成立但无 `确认` ⇒ 默认拒（一个字节不删）。
⑤ 安全收口 ⇒ 真删检查点与流水，且 `开工` 账本行仍在（不留历史库、不删账本行）。
另：`只检查` / 被拒 `v1_edit` 不落流水（写操作的关键证据走真实事务，不由流水代保证）。
"""

import shutil
import sqlite3
import tempfile
from pathlib import Path


def 开工记忆样本(仓根, 工具表) -> list:
    """跑项目记忆正反样本 ⇒ 样本表。"""
    from . import 开工账本, 开工记忆

    临时根 = Path(tempfile.mkdtemp(prefix="v1开工记忆自检-"))
    try:
        账本路径 = 临时根 / "账本.db"
        连接 = sqlite3.connect(str(账本路径))
        连接.row_factory = sqlite3.Row
        for 建表行 in 开工账本.建表语句:
            连接.execute(建表行)
        沙箱号, 收口号 = "v1-900001", "v1-900002"
        沙箱树, 收口树 = 临时根 / "沙箱树", 临时根 / "收口树"
        沙箱树.mkdir()
        收口树.mkdir()
        开工账本.登记开工(连接, 沙箱号, "记忆样本活腿", "腿/" + 沙箱号, str(沙箱树))
        开工账本.登记开工(连接, 收口号, "记忆样本收口", "腿/" + 收口号, str(收口树))
        开工账本.置状态(连接, 收口号, 开工账本.状态_已释放)
        连接.commit()
        连接.close()

        def 开账():
            新连接 = sqlite3.connect(str(账本路径))
            新连接.row_factory = sqlite3.Row
            return 新连接

        真连, 真清树, 真作业 = 开工账本.连账本, 开工记忆.检查清树安全, 开工记忆.非终态作业
        真子开工, 真台账 = 开工记忆.子开工行, 开工记忆.读未完成行
        开工账本.连账本 = 开账
        开工记忆.检查清树安全 = lambda 仓根, 开工号, 工作树: (0, "支线已合并到主工作树")
        开工记忆.非终态作业 = lambda 开工号, 工作树: []
        开工记忆.子开工行 = lambda 开工号: []
        开工记忆.读未完成行 = lambda 仓根, 开工号: []
        出口 = 工具表["v1_task"][0]
        样本表 = []
        try:
            # ① 检查点写入后可一次取回
            退出码, 回执 = 出口({"开工ID": 沙箱号, "操作": "记检查点",
                          "参数": {"目标": "内置记忆", "当前步骤": "落检查点", "下一动作": "取回"}}, 仓根)
            检查点已落 = 退出码 == 0 and "编号" in 回执
            退出码, 取回 = 出口({"开工ID": 沙箱号, "操作": "取检查点"}, 仓根)
            样本表.append(("检查点写入后可一次取回：落%s · 取回退出码 %d · 摘要含「下一动作：取回」%s"
                    % ("是" if 检查点已落 else "否", 退出码, "是" if "下一动作：取回" in 取回 else "否"),
                    检查点已落 and 退出码 == 0 and "下一动作：取回" in 取回
                    and "未测：（未记录）" in 取回))
            # ② 无显式检查点 ⇒ 不虚构
            退出码, 空取回 = 出口({"开工ID": 收口号, "操作": "取检查点"}, 仓根)
            样本表.append(("无显式检查点 ⇒ 摘要不虚构",
                    退出码 == 0 and "无显式检查点" in 空取回 and "不虚构" in 空取回))
            # ③ 空检查点拒
            退出码, 空检查拒 = 出口({"开工ID": 沙箱号, "操作": "记检查点", "参数": {}}, 仓根)
            样本表.append(("空检查点拒（退出码 %d，期望 2）" % 退出码, 退出码 == 2))
            # ④ 未合腿 / 非终态作业 / 未收口 ⇒ 清理拒
            开工记忆.检查清树安全 = lambda 仓根, 开工号, 工作树: (1, "支线尚未合并")
            退出码, 拒未合 = 出口({"开工ID": 收口号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            样本表.append(("未合腿 ⇒ 清理拒（退出码 %d）" % 退出码, 退出码 != 0 and "拒" in 拒未合))
            开工记忆.检查清树安全 = lambda 仓根, 开工号, 工作树: (0, "支线已合并到主工作树")
            开工记忆.非终态作业 = lambda 开工号, 工作树: ["任务X · 运行中"]
            退出码, 拒作业 = 出口({"开工ID": 收口号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            样本表.append(("非终态 job ⇒ 清理拒（退出码 %d）" % 退出码, 退出码 != 0 and "拒" in 拒作业))
            开工记忆.非终态作业 = lambda 开工号, 工作树: []
            退出码, 拒未收口 = 出口({"开工ID": 沙箱号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            样本表.append(("未收口（进行中）⇒ 清理拒（退出码 %d）" % 退出码,
                    退出码 != 0 and "拒" in 拒未收口))
            连接 = 开账()
            留检查点 = 连接.execute("select count(*) from 开工检查点 where 开工号 = ?", (沙箱号,)).fetchone()[0]
            连接.close()
            样本表.append(("清理拒后保留检查点（%d ≥ 1）" % 留检查点, 留检查点 >= 1))
            # ⑤ 条件成立但无确认 ⇒ 默认拒
            退出码, 默认拒 = 出口({"开工ID": 收口号, "操作": "安全清收口"}, 仓根)
            样本表.append(("安全条件成立但默认拒（退出码 %d，期望 2）" % 退出码,
                    退出码 == 2 and "默认拒绝" in 默认拒))
            # ⑥ 安全收口 ⇒ 真删且账本行仍在
            退出码, 收口回执 = 出口({"开工ID": 收口号, "操作": "安全清收口", "参数": {"确认": True}}, 仓根)
            连接 = 开账()
            账本行数 = 连接.execute("select count(*) from 开工 where 开工号 = ?", (收口号,)).fetchone()[0]
            流水留数 = 连接.execute("select count(*) from 工具流水 where 开工号 = ?", (收口号,)).fetchone()[0]
            连接.close()
            样本表.append(("安全收口 ⇒ 真删检查点与流水 · 账本行仍在（不留历史库）",
                    退出码 == 0 and "已真删" in 收口回执 and 账本行数 == 1 and 流水留数 == 0))
            # ⑦ 只检查 / 被拒 v1_edit 不落流水
            连接 = 开账()
            流水前数 = 连接.execute("select count(*) from 工具流水").fetchone()[0]
            连接.close()
            出口({"开工ID": 沙箱号, "操作": "只检查", "参数": {"改动表": [
                {"路径": "新件.py", "操作": "新建", "新内容": "配置文件 = 1\n"}]}}, 仓根)
            连接 = 开账()
            流水后数 = 连接.execute("select count(*) from 工具流水").fetchone()[0]
            连接.close()
            样本表.append(("只检查 / 被拒 v1_edit 不落流水（写证据走真实事务）", 流水后数 == 流水前数))
        finally:
            开工账本.连账本, 开工记忆.检查清树安全, 开工记忆.非终态作业 = 真连, 真清树, 真作业
            开工记忆.子开工行, 开工记忆.读未完成行 = 真子开工, 真台账
        return 样本表
    finally:
        shutil.rmtree(临时根, ignore_errors=True)
