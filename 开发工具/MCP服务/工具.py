# -*- coding: utf-8 -*-
"""MCP 工具面 —— 六个工具：开工 · 符号 · 修改器 · 门禁 · 上下文 · 终端。

**为什么要有 MCP，而不是「仓里放几个脚本」**（华哥原话）：
「封装工具是没用的，agent 天然的弱点。只有 mcp 这种强制协议才不会漂移」—— 本仓自身就是这条的实证：
一腿一工作树与认领机制「已在药柜、从未吃过」，直到有人强制用它们才生效。
故本件把四条命令**变成工具表里的工具**（协议强制出现，不靠记性）。

**它是适配层，不是能力**（老仓 `代码地图/说明/设计说明.md` §2）：四个工具都只**转发**仓内已有的
入口（`开工.py` · `符号.py` · `修改.py` · `门禁.py`），本件**零业务逻辑**。
底座不调它、判据面不依赖它 —— 退掉它（删配置）其余一切照跑。

**工具名一律 ASCII** —— **客户端强加，不是口味**。ZCode 把工具名归一化成
`mcp__<服务名>__<工具名>`，非 ASCII 字符被截掉：实测三个中文名（`v1_门禁` / `v1_符号` / `v1_替换`）
全部截成同一个 `v1_`，模型侧只活下来一个 ⇒ 另两个等于不存在。同「腿名必须 ASCII」一类。
**中文显示名放 `title`**（协议字段，客户端会用）。
★ **截断只针对 `mcp__服务名__工具名` 的归一化** —— **参数名不受影响**：参数名走 `arguments` 的 JSON
键，客户端不做 `mcp__…__` 归一化。四工具的 `inputSchema` 参数名**全中文**（`功能` / `开工ID` / …），实测可用。

**退出码语义（四工具统一 · 协议层只把 `退出码 != 0` 折成 `isError`）**：
`0` 成功 · `1` 业务/环境失败（没有这条开工 · 状态不对 · 工作树不在 · 建树/建索引失败）·
`2` 参数错**或业务前置不满足**（见下「2 的两义」）· `3` 闸拒（四道闸 / 越区闸 / 认领闸）·
`4` 逐条中途失败（部分改动已落盘）· `5` 命名登记拒（新名未登记 · 名册读不动）·
`-1` 超时（五秒硬顶）· `-2` 起不来（验证器/子进程拉不起）。

★ **2 的两义（读回执正文判是哪一类）**：`v1_edit` 的 2 = 参数/字段错（该改参数）；
`v1_task`/`v1_symbol`/`v1_gate` 的 2 还兼「业务前置不满足」（该改仓态）—— 如 功能=1 的
`文件认领` 盘上不存在 · 功能=9 的 `旧名` 在命名面 0 处。协议层不区分，**读回执正文判是哪一类**。
"""

