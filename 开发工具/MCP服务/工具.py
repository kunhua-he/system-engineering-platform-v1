"""MCP 工具实现 —— 三个：**门禁** · **符号** · **替换**。

**为什么要有 MCP，而不是「仓里放几个脚本」**（华哥 2026-09-27 原话）：
「封装工具是没用的，agent 天然的弱点。只有 mcp 这种强制协议才不会漂移。如果不用强制协议，
本质上就算放了一大堆工具给你都没用。很少会用上的」—— 本仓自身就是这条的实证：
一腿一工作树与认领机制「**已在药柜、从未吃过**」，直到有人强制用它们才生效。
故本件把三条命令**变成工具表里的工具**（协议强制出现，不靠记性）。

**它是适配层，不是能力**（老仓 `支持库/后端/代码解析支持库/代码地图/说明/设计说明.md` §2）：
三个工具都只**转发**仓内已有的入口，零业务逻辑、零第二套实现（老仓 1.3「结果唯一即收口」）。
底座不调它、判据面不依赖它 —— 退掉它（删插件）其余一切照跑。

**写操作必须过认领机制**：`替换` 的 `应用` 模式先查 `开发工具/认领机制/账本.json` ——
有活跃租约时必须指名腿，且目标路径必须全在该腿的路径集里，否则**拒**（fail-closed）。
这条是 MCP 与「自由批量替换」的分界：改动作不是风险，**绕过所有权**才是。
"""

import json
import subprocess
import sys

超时秒 = 5


def 跑(命令表, 仓根, 超时秒数=超时秒):
    """跑一条命令 ⇒ `(退出码, 合并输出)`。超时给退出码 `-1`（不许当成通过）。"""
    try:
        命令回执 = subprocess.run(命令表, cwd=str(仓根), capture_output=True, text=True,
                                timeout=超时秒数)
    except subprocess.TimeoutExpired:
        return -1, "超时（%d 秒）—— 五秒硬顶无例外，先查是哪一段慢" % 超时秒数
    except OSError as 起不来的原因:
        return -2, "起不了：%r" % (起不来的原因,)
    return 命令回执.returncode, (命令回执.stdout or "") + (命令回执.stderr or "")


# ── 工具一：门禁（一键编译 + 全量门禁）───────────────────────────────────────────────────

def 门禁(参数表, 仓根):
    """跑 `构建装配/一键验证/闸0.py`（闸 1 声明侧 + 闸 2 实现侧并排读数）⇒ 退出码 + 读数。"""
    命令表 = [sys.executable, str(仓根 / "构建装配" / "一键验证" / "闸0.py")]
    if 参数表.get("自测"):
        命令表 = [sys.executable, str(仓根 / "构建装配" / "一键验证" / "一键验证.py"), "--自测"]
    退出码, 命令输出 = 跑(命令表, 仓根)
    有效行表 = [输出行 for 输出行 in 命令输出.splitlines() if 输出行.strip() and "─" not in 输出行]
    return 退出码, "退出码 %d\n%s" % (退出码, "\n".join(有效行表[-30:]))


# ── 工具二：符号（代码地图查/引用）────────────────────────────────────────────────────────

def _取代码地图(仓根):
    """取代码地图包（`开发工具/` 进 sys.path 后 import）。"""
    if str(仓根 / "开发工具") not in sys.path:
        sys.path.insert(0, str(仓根 / "开发工具"))
    from 代码地图 import 查, 引用, 出现位置, 索引状态
    return {"查": 查, "引用": 引用, "出现位置": 出现位置, "索引状态": 索引状态}


def _要索引(仓根):
    """索引在不在 ⇒ `(代码地图模块, 错误说明)`。不在 ⇒ 报「先建」而不是报空。"""
    代码地图 = _取代码地图(仓根)
    当前状态 = 代码地图["索引状态"]()
    if not 当前状态["有"]:
        return None, ("还没有索引 ⇒ 先跑 `python3 开发工具/代码地图.py 建`（落点 %s）"
                     % 当前状态["路径"])
    return 代码地图, None


def 符号(参数表, 仓根):
    """按关键词查符号，或按**限定名精确**查它出现在哪几处（定义 + 引用）。"""
    代码地图, 错误说明 = _要索引(仓根)
    if 错误说明:
        return 1, 错误说明

    限定名 = str(参数表.get("限定名") or "")
    if 限定名:
        出现结果 = 代码地图["出现位置"](限定名)
        输出行表 = ["`%s` 出现 %d 处（口径：%s）：" % (限定名, 出现结果["总数"], 出现结果["口径"])]
        for 文件路径, 行号, 列号 in 出现结果["位置"]:
            输出行表.append("  %s:%d:%d" % (文件路径, 行号, 列号))
        return 0, "\n".join(输出行表)

    关键词 = str(参数表.get("关键词") or "")
    if not 关键词:
        return 2, "缺 `关键词`（查符号）或 `限定名`（查出现位置）"
    查询结果 = 代码地图["查"](关键词, 上限=int(参数表.get("上限") or 40))
    输出行表 = ["命中 %d 个定义（扫过 %d 条）" % (查询结果["总数"], 查询结果["扫过"])]
    for 定义记录 in 查询结果["命中"]:
        输出行表.append("  %-46s %-10s %s:%d:%d  [出现 %d 处]" % (
            定义记录["限定名"], 定义记录["种类"] or "—", 定义记录["路径"],
            定义记录["行"], 定义记录["列"], 定义记录["出现数"]))
    return 0, "\n".join(输出行表)


# ── 工具三：替换（**符号级**批量替换）─────────────────────────────────────────────────────

def _读租约表(仓根):
    """读认领账本 ⇒ 租约列表；读不出 ⇒ `None`（**判不了**，不是「没有租约」）。"""
    账本路径 = 仓根 / "开发工具" / "认领机制" / "账本.json"
    try:
        账本数据 = json.loads(账本路径.read_text(encoding="utf-8"))
    except Exception:
        return None
    租约表 = 账本数据.get("租约")
    return 租约表 if isinstance(租约表, list) else None


def _放行(仓根, 待改路径表, 腿标识):
    """写操作的所有权闸 ⇒ `(允许?, 说明)`。**有活跃租约就必须指名腿**（fail-closed）。"""
    租约表 = _读租约表(仓根)
    if 租约表 is None:
        return False, "读不出认领账本 ⇒ 判不了（不许当成「没有租约」）"
    活跃租约表 = [一条租约 for 一条租约 in 租约表 if 一条租约.get("到期时间")]
    if not 活跃租约表:
        return True, "账本里 0 条活跃租约 ⇒ 放行（无人认领 = 无争用）"
    if not 腿标识:
        return False, "有 %d 条活跃租约 ⇒ 必须给 `腿`（否则不知道这次改动算谁的）" % len(活跃租约表)
    我的租约表 = [一条租约 for 一条租约 in 活跃租约表 if 一条租约.get("腿标识") == 腿标识]
    if not 我的租约表:
        return False, "账本里没有腿 `%s` 的活跃租约" % 腿标识
    认领路径集 = set(我的租约表[0].get("路径集") or [])
    越界路径表 = sorted(待改路径 for 待改路径 in 待改路径表 if 待改路径 not in 认领路径集)
    if 越界路径表:
        return False, "这些路径不在腿 `%s` 的认领集里 ⇒ 拒：%s" % (腿标识, " · ".join(越界路径表))
    return True, "腿 `%s` 的认领集覆盖全部 %d 个目标件" % (腿标识, len(待改路径表))


def _按列换(整行文本, 起始列, 旧名字, 新名字):
    """按 **UTF-16 列**换掉行内一段（SCIP 的 `position_encoding` 是 utf-16）。
    切出来的文本不等于 `旧名字` ⇒ 返回 `None`（**fail-closed**：位置漂了就不猜）。"""
    整行单位 = 整行文本.encode("utf-16-le")
    起始字节位 = 起始列 * 2
    旧名单位 = 旧名字.encode("utf-16-le")
    实际切出段 = 整行单位[起始字节位:起始字节位 + len(旧名单位)]
    if 实际切出段 != 旧名单位:
        return None
    return (整行单位[:起始字节位] + 新名字.encode("utf-16-le")
            + 整行单位[起始字节位 + len(旧名单位):]).decode("utf-16-le")


def 替换(参数表, 仓根):
    """把某个符号的**全部出现位置**（定义 + 引用，由索引给出）换成新名。默认 dry-run。

    与文本替换的分界：本工具只动**索引认得的那几处**，不动字符串 / 注释 / 同名别的符号。
    """
    限定名 = str(参数表.get("限定名") or "")
    新名字 = str(参数表.get("新名") or "")
    要写盘 = bool(参数表.get("应用"))
    if not 限定名 or not 新名字:
        return 2, "缺 `限定名` 或 `新名`"
    旧名字 = 限定名.rsplit("::", 1)[-1]
    代码地图, 错误说明 = _要索引(仓根)
    if 错误说明:
        return 1, 错误说明
    出现结果 = 代码地图["出现位置"](限定名)          # 上限 0 = 不限量（截断会漏改）
    if not 出现结果["位置"]:
        return 1, "索引里没有 `%s`（先建索引；或换用限定名 —— 用 `符号` 工具查）" % 限定名
    全部位置表 = sorted(set(出现结果["位置"]))
    按文件位置表 = {}
    for 文件路径, 行号, 列号 in 全部位置表:
        按文件位置表.setdefault(文件路径, []).append((行号, 列号))

    输出行表 = ["`%s` → `%s`：%d 处，落在 %d 个件（口径：%s）" % (
        旧名字, 新名字, len(全部位置表), len(按文件位置表), 出现结果["口径"])]
    for 文件路径 in sorted(按文件位置表):
        输出行表.append("  %s × %d" % (文件路径, len(按文件位置表[文件路径])))

    if not 要写盘:
        return 0, "\n".join(输出行表 + ["", "**dry-run**（没改任何文件）。要真改：`应用: true`"
                                       "（有活跃租约时还要给 `腿`）。"])

    放行结果, 放行说明 = _放行(仓根, sorted(按文件位置表), 参数表.get("腿"))
    if not 放行结果:
        return 3, "\n".join(输出行表 + ["", "**拒**（所有权闸）：%s" % 放行说明])

    # 先在内存里把**所有**件都换出来，再统一写 —— 一处位置对不上就整批不写。
    # 拒绝原因表**不能跨件累积**：它一旦非空，后面的件会被 `continue` 一起跳过，
    # 而排在前面、已经写盘的件就回不来了 ⇒ 那就成了「半改」，
    # 与「拒绝整批（不猜、不留半改）」的口径相反，还会谎报「未写入任何文件」。
    待写表, 拒绝原因表 = [], []
    for 文件路径 in sorted(按文件位置表):
        目标文件 = 仓根 / 文件路径
        整文件行表 = 目标文件.read_text(encoding="utf-8").split("\n")
        # 同一行多处 ⇒ 从右往左换（否则前列会挪位）。
        for 行号, 列号 in sorted(按文件位置表[文件路径], reverse=True):
            换后行 = _按列换(整文件行表[行号 - 1], 列号, 旧名字, 新名字)
            if 换后行 is None:
                拒绝原因表.append("%s:%d:%d（切出的文本不是 `%s` ⇒ 位置漂了）"
                              % (文件路径, 行号, 列号, 旧名字))
                continue
            整文件行表[行号 - 1] = 换后行
        待写表.append((目标文件, "\n".join(整文件行表)))
    if 拒绝原因表:
        return 4, "\n".join(输出行表 + ["", "**拒绝整批**（fail-closed，未写入任何文件）："]
                           + 拒绝原因表)
    for 目标文件, 换后全文 in 待写表:
        目标文件.write_text(换后全文, encoding="utf-8")
    return 0, "\n".join(输出行表 + ["", "**已改 %d 个件**。%s" % (len(待写表), 放行说明),
                                  "接着跑 `门禁` 工具验（索引已过期，要重跑 `代码地图.py 建`）。"])


