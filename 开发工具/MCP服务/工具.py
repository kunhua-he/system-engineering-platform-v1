def 并入声明工具() -> None:
    """把 `操作_*.py` 里**自声明的新工具**并入对外工具面（新工具不必在本件手写）。

    新工具模块导出：`工具名`(ASCII) · `工具说明` · `操作表` · 可选 `模式`(inputSchema) ·
    可选 `派发`(`callable(实参, 仓根) -> (退出码, 输出文本)`；缺省走统一网关)。
    缺该模块 ⇒ 什么都不做（不报错）。新工具与既有六工具对外形态完全同形。
    """
    for 工具名, 声明 in 参数规范.声明工具().items():
        if 工具名 in 工具表:
            continue
        派发 = 声明.get("派发")
        实现 = 派发 if callable(派发) else functools.partial(参数规范.网关派发, 工具名)
        工具表[工具名] = (实现, 声明.get("工具说明", 工具名), 声明.get("工具说明", ""),
                     声明.get("模式") or 统一模式)


def _补操作清单() -> None:
    """把各工具**可用操作名**追进 `description` —— 让发现面首屏就列全（省一次试错）。

    实测：agent 误传 `操作="发现"` 才从「可用：…」里拿到清单。操作名从**唯一事实源**
    `参数规范.载入操作表()` 现取（不写死），只在描述尾部追加一段。
    """
    操作总表 = 参数规范.载入操作表()
    for 名称, (实现, 标题, 说明, 模式) in list(工具表.items()):
        操作名表 = sorted(操作总表.get(名称, {}))
        if not 操作名表 or "可用操作：" in 说明:
            continue
        工具表[名称] = (实现, 标题, 说明 + " 可用操作：" + " / ".join(操作名表) + "。", 模式)


并入声明工具()
_补操作清单()
