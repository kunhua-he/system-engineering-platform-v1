# -*- coding: utf-8 -*-
"""反馈关联 —— 判词**承接校验**与**未蒸馏判据**（唯一口）。

**为什么单开一件**：判词要关联「唯一现行台账条目」或「正式开工」，这要读库 `未完成` 表
与开工账本 —— 把它与纯存储分开 ⇒ `反馈账本.py` 不反向依赖业务口径，也不与它成环。

**未蒸馏判据的唯一口** = `未蒸馏反馈集`：收口清理与单纯释放都引它，别处不许自建第二套。
**机器产生记录无阻断权**（2026-10-09 用户裁定：「超过 5 秒就汇报进债务就行……这个是纯后台记录，
不需要 agent 的介入」）—— 来源标识以 `账本.自动来源标识前缀` 起头的记录走 `自动记录行`，照旧落库、
照旧可查，但**不进**阻断集；区分按**产生者身份**，不按耗时 / 阈值这类会漂的条件。
口径（收口方 2026-10-08 纠正）：**已审完 + 已判词 + 有效承接** ⇒ 视为**已蒸馏**，
原腿可清、反馈与处置证据永久保留；只有下面三条任一成立才拒：
  ① 报告未审完（含空报告 / 缺件显式待核）；
  ② 有未判词条目（已并入主条目且主条目有判词者不算）；
  ③ **债务无有效承接**（关联空、或解析不到现行台账条目 / 正式开工）；
  ④ 待核且**有具体保留对象**（带补证证据，或关联目标非空）—— 待核本身**不**一律阻断。

★ 三档的语义与退出条件、待核何时阻断 —— **单一落点** = 库 `条款` `项目文档/审核与裁决流程.md`
  （两个终裁 + 一个中间态）。本件只落「未蒸馏四类」的实现，口径改看那份条款，不在此复述。

**表形态三态**（2026-10-08 裁决）：六表**全不存在** = 支持的**旧库形态** ⇒ 返空（允许清树）；
六表**齐全** ⇒ 才读实际反馈；**任意非空真子集**（含「来源缺但别的表有行」/ 部分迁移 / 查询读不动）
⇒ 显式 `反馈表残缺` ⇒ fail-closed。**不**按单表真假放行；也**不**对外宣称「全无表 = 历史从未用过」
（六表被整批删掉同样落那一态，仅凭 schema 追不出来）。
"""

import json
from pathlib import Path

from . import 反馈账本 as 账本

台账相对路径 = ("开发工具", "信息核心", "信息核心.db")

# 未蒸馏**类别**（封闭档表 · 四类）：`未蒸馏明细` 逐行标它、`未蒸馏分类计数` 按它计数 ——
# 类别名**就是**行首（`正文` 以类别名起头），别处不许另拼字面量。
类别_未审完来源 = "未审完来源"
类别_未判词条目 = "未判词条目"
类别_债务无承接 = "债务无有效承接"
类别_待核须保留 = "待核须保留"
未蒸馏类别档表 = (类别_未审完来源, 类别_未判词条目, 类别_债务无承接, 类别_待核须保留)


class 反馈表残缺(Exception):
    """反馈表形态**非全有也非全无**（任意非空真子集 / 部分迁移 / 查询读不动）—— fail-closed。"""


def 反馈表集(连接) -> set:
    """库里**现存的**反馈表名集（只读 `sqlite_master`）—— 判「齐全 / 全无 / 真子集」用。

    只回答「哪几张在」，**不**替调用方下「有没有反馈」的结论（三态判定在 `未蒸馏反馈集`）。
    """
    return {数据行[0] for 数据行 in 连接.execute(
        "select name from sqlite_master where type = 'table'")} & set(账本.反馈表名表)


def 读台账号集(仓根) -> set:
    """库 `未完成` 表的**现行条目号**集；库不在 / 读不动 ⇒ 空集（调用方 fail-closed 当无效）。"""
    import sqlite3
    台账库路径 = Path(仓根).joinpath(*台账相对路径)
    if not 台账库路径.is_file():
        return set()
    try:
        连接 = sqlite3.connect("file:%s?mode=ro" % 台账库路径, uri=True)
        try:
            号集 = {数据行[0] for 数据行 in 连接.execute("select 号 from 未完成")}
        finally:
            连接.close()
    except sqlite3.Error:
        return set()
    return 号集


def 承接有效(连接, 仓根, 关联种类, 关联目标) -> bool:
    """判词的关联是否**有效承接**：唯一现行台账条目 / 真实开工。**未知即假**（fail-closed）。"""
    种类值 = str(关联种类 or "").strip()
    目标值 = str(关联目标 or "").strip()
    if not 种类值 or not 目标值:
        return False
    if 种类值 == 账本.关联_台账:
        try:
            号值 = int(目标值)
        except (TypeError, ValueError):
            return False
        return 号值 in 读台账号集(仓根)
    if 种类值 == 账本.关联_开工:
        return 账本.开工在吗(连接, 目标值)
    return False


def 台账对账(连接, 仓根, 号集=None) -> list:
    """**全量**债务判词的关联对账 ⇒ 悬空行表（空 = 全对得上）。

    **为什么要有它**（债务 577）：`承接有效` 只在**写**判词那一刻核一次（`批量判定` 拒悬空）；
    而台账条目是**会事后删**的 —— 债务修完即删行 ⇒ 早先写的债务判词当场悬空、**无人报红**。
    本口把「全库的债务判词 × 现行台账号集」一次核完。

    `号集` 缺省 = 读本树 `未完成` 表现行号；显式给 = 按那一份号集核（自检样本用它模拟
    「台账条目事后被删」）。口径与 `未蒸馏分流` 的 `类别_债务无承接` 同源：只看
    `判词 = 债务` 且 `关联种类 = 未完成条目` 的行，不按 `关联状态` 筛（已撤的债务判词
    照旧要有承接 —— 与释放的未蒸馏判据一致）。
    """
    if 号集 is None:
        号集 = 读台账号集(仓根)
    悬空表 = []
    for 数据行 in 连接.execute(
            "select 反馈判词.条目号, 反馈判词.关联目标 from 反馈判词 "
            "where 反馈判词.判词 = ? and 反馈判词.关联种类 = ? order by 反馈判词.条目号",
            (账本.判词_债务, 账本.关联_台账)):
        目标值 = str(数据行[1] or "").strip()
        try:
            号值 = int(目标值)
        except (TypeError, ValueError):
            号值 = None
        if 号值 is None or 号值 not in 号集:
            悬空表.append("债务 %d 关联台账条目 %s ⇒ 现行台账里没有这一条（悬空）"
                       % (数据行[0], 目标值 or "（空）"))
    return 悬空表


def 未蒸馏分流(连接, 仓根, 开工号: str) -> tuple:
    """本开工的未蒸馏反馈按**产生者身份**分流 ⇒ `(阻断明细表, 自动明细表)`。

    **机器产生**（`账本.是自动来源`：来源标识以 `自动来源标识前缀` 起头）的记录**无阻断权**
    ——「用户强制要求：性能记录是纯后台记录，不需要 agent 介入」（2026-10-09 裁定）⇒ 进
    `自动明细表`（照旧落库、照旧可查，**不静默丢弃**）；**人工产生**的进 `阻断明细表`，四条口径
    （未审完来源 / 未判词条目 / 债务无有效承接 / 待核须保留）一条不放松。`仓根` 必须显式传入。
    **唯一实现体**：`未蒸馏明细` / `未蒸馏反馈集` / `自动记录行` 都只由它分流，不另写第二套 SQL。
    """
    自动明细表 = []
    阻断明细表 = []
    表集 = 反馈表集(连接)
    if not 表集:
        # 六表**全不存在** = 支持的**旧库形态**（反馈包合入前的老账本）⇒ 返空、允许清树。
        # ★ 这不是「证明历史从未用过反馈」：六表被整批删掉同样落这一态，仅凭 schema 追不出来。
        return 阻断明细表, 自动明细表
    if 表集 != set(账本.反馈表名表):
        # **任意非空真子集**（含「`反馈来源` 缺、别的表有行」/ 部分迁移 / 查询读不动）⇒ 显式拒，
        # 绝不按单表真假放行；异常照样冒泡 ⇒ `清树门禁.未蒸馏反馈行` 的 fail-closed 兜住。
        raise 反馈表残缺("反馈表残缺（现存 %s / 应有 %s）⇒ fail-closed，不按单表真假放行"
                   % (" · ".join(sorted(表集)), " · ".join(账本.反馈表名表)))
    for 数据行 in 连接.execute(
            "select 来源号, 来源标识, 读取状态, 提取条数 from 反馈来源 "
            "where 开工号 = ? and 审完时刻 is null order by 来源号", (开工号,)):
        明细行 = {"类别": 类别_未审完来源, "来源号": 数据行["来源号"], "条目号": None,
                "正文": "未审完来源 %d（%s · 读取状态 %s · 提取 %d 条）"
                      % (数据行["来源号"], 数据行["来源标识"], 数据行["读取状态"],
                         数据行["提取条数"])}
        if 账本.是自动来源(数据行["来源标识"]):
            自动明细表.append(明细行)
        else:
            阻断明细表.append(明细行)
    for 数据行 in 连接.execute(
            "select 反馈条目.条目号, 反馈条目.现象, 反馈来源.来源标识 from 反馈条目 "
            "join 反馈来源 on 反馈条目.来源号 = 反馈来源.来源号 "
            "where 反馈条目.开工号 = ? "
            "and not exists(select 1 from 反馈判词 where 反馈判词.条目号 = 反馈条目.条目号) "
            "and not exists(select 1 from 反馈判词 where 反馈判词.条目号 = 反馈条目.并入主条目) "
            "order by 反馈条目.条目号", (开工号,)):
        明细行 = {"类别": 类别_未判词条目, "来源号": None, "条目号": 数据行["条目号"],
                "正文": "未判词条目 %d：%s" % (数据行["条目号"], 账本.截断(数据行["现象"]))}
        if 账本.是自动来源(数据行["来源标识"]):
            自动明细表.append(明细行)
        else:
            阻断明细表.append(明细行)
    for 数据行 in 连接.execute(
            "select 反馈判词.条目号, 反馈判词.关联种类, 反馈判词.关联目标, 反馈来源.来源标识 "
            "from 反馈判词 join 反馈条目 on 反馈判词.条目号 = 反馈条目.条目号 "
            "join 反馈来源 on 反馈条目.来源号 = 反馈来源.来源号 "
            "where 反馈条目.开工号 = ? and 反馈判词.判词 = ? order by 反馈判词.条目号",
            (开工号, 账本.判词_债务)):
        if 承接有效(连接, 仓根, 数据行["关联种类"], 数据行["关联目标"]):
            continue
        明细行 = {"类别": 类别_债务无承接, "来源号": None, "条目号": 数据行["条目号"],
                "正文": "债务无有效承接 %d（关联 %s %s）"
                      % (数据行["条目号"], 数据行["关联种类"] or "（未记）",
                         数据行["关联目标"] or "（未记）")}
        if 账本.是自动来源(数据行["来源标识"]):
            自动明细表.append(明细行)
        else:
            阻断明细表.append(明细行)
    for 数据行 in 连接.execute(
            "select 反馈判词.条目号, 反馈判词.理由, 反馈判词.关联目标, 反馈来源.来源标识, "
            "(select count(*) from 反馈证据 where 反馈证据.条目号 = 反馈判词.条目号) as 补证数 "
            "from 反馈判词 join 反馈条目 on 反馈判词.条目号 = 反馈条目.条目号 "
            "join 反馈来源 on 反馈条目.来源号 = 反馈来源.来源号 "
            "where 反馈条目.开工号 = ? and 反馈判词.判词 = ? order by 反馈判词.条目号",
            (开工号, 账本.判词_待核)):
        if not (数据行["补证数"] or str(数据行["关联目标"] or "").strip()):
            continue
        明细行 = {"类别": 类别_待核须保留, "来源号": None, "条目号": 数据行["条目号"],
                "正文": "待核须保留 %d（补证 %d 条 · 关联 %s）"
                      % (数据行["条目号"], 数据行["补证数"],
                         数据行["关联目标"] or "（无）")}
        if 账本.是自动来源(数据行["来源标识"]):
            自动明细表.append(明细行)
        else:
            阻断明细表.append(明细行)
    return 阻断明细表, 自动明细表


def 未蒸馏明细(连接, 仓根, 开工号: str) -> list:
    """本开工**未蒸馏且会阻断**的反馈 ⇒ **结构化明细行表**（`类别` / `正文` / `来源号` / `条目号`）。

    `仓根` **必须显式传入**（要读该树的库 `未完成` 表）—— 不许猜主干 / 旧树。
    **唯一判据口的实现体**：`未蒸馏反馈集` 只由它取 `正文`；机器产生记录被 `未蒸馏分流` 剔到
    `自动明细表`（不阻断，走 `自动记录行` 查）⇒ 本函数只回**阻断**那一侧。
    """
    return 未蒸馏分流(连接, 仓根, 开工号)[0]


def 未蒸馏反馈集(连接, 仓根, 开工号: str) -> list:
    """本开工未蒸馏的反馈 ⇒ **行表（字符串）**（**非空 ⇒ 收口清理拒**）。**唯一判据口**。

    口径四条见模块头；机器产生记录**无阻断权**（见 `未蒸馏分流`）。实现体只有 `未蒸馏分流`
    一处 —— 本函数只取它阻断那一侧的 `正文`。
    """
    return [明细行["正文"] for 明细行 in 未蒸馏明细(连接, 仓根, 开工号)]


def 自动记录行(连接, 仓根, 开工号: str) -> list:
    """本开工**机器产生、不阻断释放**的未蒸馏记录 ⇒ **行表（字符串）**（照旧落库、照旧可查）。

    与 `未蒸馏反馈集` 同源分流（`未蒸馏分流` 的自动那一侧）—— 释放回执据此显式报出
    「另有 N 条自动性能记录（不阻断释放）」，避免「看起来干净」的假象。
    """
    return [明细行["正文"] for 明细行 in 未蒸馏分流(连接, 仓根, 开工号)[1]]


def 未蒸馏分类计数(明细表: list) -> dict:
    """明细行表 ⇒ **逐类别计数**（四档全在，无该类记 0）—— 一眼看全量而不被截断误导。"""
    计数表 = {档名: 0 for 档名 in 未蒸馏类别档表}
    for 明细行 in 明细表:
        类别值 = 明细行.get("类别")
        if 类别值 in 计数表:
            计数表[类别值] += 1
    return 计数表
