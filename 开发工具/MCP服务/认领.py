# -*- coding: utf-8 -*-
"""认领 —— `v1_task` 功能 = 8「撤销认领」：把本开工对某些件的认领从账本撤掉。

**为什么单独一件**：`开工.py` 已顶 400 行硬数（判据 ⑲）⇒ 照「一个关注点一个文件」把这一块
整块挪出来，`开工.py` 只留 import + 转出口。**实现只有这一份**：别处不许再写一遍撤认领。

**它给谁用**（2026-10-01 实测腿 v1-100215）：`释放` 的对账比「账本指纹 vs 盘上指纹」。件没了、
账本里还留着旧指纹 ⇒ 对账恒报「变过」⇒ 释放被拒；而 `补充认领`（功能 = 2）只认**盘上存在**
的件 ⇒ 那条陈旧认领谁也清不掉，只能先把件从父提交复原、再用 `v1_edit 功能=2` 正式删一次
—— 很脏。本档给的是那条正路（收口腿把别的腿并进来时，被并进来的那条删掉的件就长这样）。
"""

from pathlib import Path

from . import 开工账本 as 账本
from .仓操作 import 变更路径表
from .修改 import 功能名表, 功能_删除


def 撤销认领(仓根, 开工号: str, 文件认领) -> tuple:
    """撤掉认领，销掉本开工对它们的旧改动行，并为「盘上已删」的件如实补一条删除改动。

    三件事，都是「这件不再是我的」的后果：① 撤掉认领行；② 把本开工在 `改动` 表里这些路径的旧行
    一并销掉（`开工账本.撤认领` 一并做）—— 否则同一开工「先建后删」的件会在 `改动` 表留陈旧行，
    `释放` 的 `git add` 拿它当路径 ⇒ `fatal: pathspec` 卡死整条腿；③ 件**盘上已不在、且 git 认为
    它被删了** ⇒ 如实补记一条「删除」改动 —— 否则 `释放` 的越界检测会把这个脏件当越界、照样拒
    （件是**已经**没了的，不记下来就等于把一次真删除藏起来）。②先销、③后记，顺序不能反，否则
    新记的删除行又被销掉。③**不是**第二次实现 `v1_edit` 的删除：那条要求件在盘上、`旧内容` 能
    唯一定位，而这里件已经没了、无从定位 ⇒ 只复用账本已有的 `记改动` 一步。
    """
    连接 = 账本.连账本()
    try:
        开工条目 = 账本.读开工(连接, 开工号)
        if not 开工条目:
            return 1, "没有这条开工：%s ⇒ 先 功能 = 1 登记" % 开工号
        if 开工条目["状态"] == 账本.状态_已释放:
            return 1, "这条开工已释放 ⇒ 认领已无意义，不必撤"
        路径表 = 文件认领 if isinstance(文件认领, list) else ([文件认领] if 文件认领 else [])
        路径表 = list(dict.fromkeys(str(路径).strip() for 路径 in 路径表 if str(路径 or "").strip()))
        if not 路径表:
            return 2, "功能 = 8 撤销认领要 `文件认领`（要撤哪几个件）"
        工作树 = Path(开工条目["工作树"])
        原指纹表 = 账本.读认领(连接, 开工号)
        # `撤认领` 一并销掉这些路径在本开工 `改动` 表的旧行、返回销掉行数（2026-10-05 修 ·
        # 审计 A 存疑5）：否则同一开工「先建后删」的件在改动表留陈旧行，`释放` 的 `git add`
        # 拿它当路径 ⇒ `fatal: pathspec` 卡死整条腿。顺序：先销旧行、再对盘上真删的件补记删除
        # （否则新记的删除行又被销掉）。
        撤掉表, 没认领表, 行数 = 账本.撤认领(连接, 开工号, 路径表)
        退出码, 变更表 = 变更路径表(工作树)
        if 退出码 != 0:
            return 1, ("认领已撤掉 %d 件、改动表旧行已销 %d 条，但查不清盘上动了什么"
                     "（git status 失败）⇒ 删除没记：\n%s" % (len(撤掉表), 行数, 变更表))
        删除表 = [路径 for 路径 in 撤掉表 if not (工作树 / 路径).is_file() and 路径 in 变更表]
        for 路径 in 删除表:
            账本.记改动(连接, 开工号, 路径, 功能名表[功能_删除], 原指纹表.get(路径) or "", "")
        输出行表 = ["%s 撤销 %d 件：%s" % (开工号, len(撤掉表), " · ".join(撤掉表) or "（无）"),
                 "剩余认领 %d 件" % len(账本.读认领(连接, 开工号))]
        if 行数:
            输出行表.append("其中销掉 `改动` 表旧行 %d 条（`释放` 的 `git add` 不再拿它们当路径 ⇒ "
                        "不会撞 `pathspec` 卡死）" % 行数)
        if 删除表:
            输出行表.append("其中 %d 件盘上已不在、且 git 认为被删 ⇒ 已如实记一条「删除」改动"
                        "（`释放` 才能把这次删除提交出去）：%s" % (len(删除表), " · ".join(删除表)))
        if [路径 for 路径 in 撤掉表 if (工作树 / 路径).is_file() and 路径 in 变更表]:
            输出行表.append("★ 这些件盘上还在、也还有未提交的改动，但已不再认领、`改动` 表旧行已销 ⇒ "
                        "`释放` 会把它们当**越界**拒（撤掉认领 = 这件不再是本开工的）：%s"
                        % " · ".join(路径 for 路径 in 撤掉表
                                  if (工作树 / 路径).is_file() and 路径 in 变更表))
        if 没认领表:
            输出行表.append("（这些本来就没认领，未动：%s）" % " · ".join(没认领表))
        return 0, "\n".join(输出行表)
    finally:
        连接.close()
