def 装表(连接, 表名: str, 现抽, 根目录: Path, *命令行参数) -> int:
    """装一张表，返回行数。

    **有源件的源表 ⇒ 每次重抽**（源件是权威）；**无源件的源表 ⇒ 有行就不动**（库是唯一存本）。
    **分片源件的源表**（`表定义.分片源件表`）⇒ 只重抽**源件在场**的那几片，其余行保住（见 `装分片源件`）。

    ★ 为什么不能用「抽出来是空的才保」：源件删掉后，抽取器往往还能抽出**部分**非空结果
    （实测：md 删后 `条款` 从 576 节被洗成 20 节 —— 只剩 README 与 AGENTS 的节；`规则` 从 108 条
    被洗成 28 条 —— 14 个来源只剩 4 个还在）。**部分非空比全空更危险**：它静默丢数据。
    ⇒ 无源件的源表只填空表；派生表不受此保护（它们的源永远在）。
    """
    if 表名 in 表定义.分片源件表:
        return 装分片源件(连接, 表名, 表定义.分片源件表[表名], 现抽, 根目录)
    已有行数 = 连接.execute(f"select count(*) from {表名}").fetchone()[0]
    有源件 = 表名 in 表定义.源件表 and all(
        (根目录 / 一件).is_file() for 一件 in 表定义.源件表[表名])
    if 表名 in 表定义.源表 and 已有行数 and not 有源件:
        return 已有行数
    数据行 = 现抽(根目录, *命令行参数)
    旧值表 = 记旧值(连接, 表名)
    连接.execute(f"delete from {表名}")
    if 数据行:
        连接.executemany(
            f"insert or replace into {表名} values({','.join('?' * len(数据行[0]))})", 数据行)
        回填旧值(连接, 表名, 旧值表)
        # ★ 2026-09-28 实测撞过：`命名定义` 的主键是**第 1 栏**（语义），源件里第 1 栏重了
        # 两行 ⇒ `insert or replace` 静默合并，报 2577 行而库里只有 2573 行。
        # 静默丢数据是头号大敌 ⇒ 落库行数对不上就**炸**，先修源件。
        落库行数 = 连接.execute(f"select count(*) from {表名}").fetchone()[0]
        if 落库行数 != len(数据行):
            raise ValueError(
                f"{表名}：源件抽出 {len(数据行)} 行、落库只剩 {落库行数} 行 ⇒ "
                f"{len(数据行) - 落库行数} 行被**主键（第 1 栏）**合并掉了。"
                f"源件里有第 1 栏重复的行 —— 这是静默丢数据，先修源件再跑。")
    return len(数据行)


def 清孤儿表(连接, 许表集: set) -> list:
    """删掉库里**不在许表集**里的表（`sqlite_%` 内部表除外）⇒ 被删的表名表。

    为何要它（2026-10-07 · E1 派生表移出版本库）：`建表语句` / `派生建表语句` 只有
    `create table if not exists` ⇒ 一张表从建表语句里删掉后**旧表仍留在库里**（实测：
    `命名出现` 从源表搬进派生表后，规则库里那张 8.7 万行的旧表不会被重抽，库仍 11.4 MB）。
    清孤儿表让「库里的表集 == 代码里的表集」自动成立，此后任何表被移走 / 改名都在下次
    `建库` 自动清干净（不再靠一次性脚本）。**只删表**，不碰行与别的对象。
    """
    现表 = {表行[0] for 表行 in 连接.execute(
        "select name from sqlite_master where type='table' and name not like 'sqlite_%'")}
    孤儿 = sorted(现表 - set(许表集))
    for 表名 in 孤儿:
        连接.execute(f'drop table "{表名}"')
    return 孤儿


def 补台账类别列(连接) -> bool:
    """老库的 `未完成` 表补上「类别」列 ⇒ 这次有没有补。

    为何要它（6125 · 审计 G1）：`建表语句` 只有 `create table if not exists` —— 对**已经存在**的表
    一列都不加。这张表在 2026-10-27 之前就建好了，光改建表语句，老库永远没有这一栏，升级与债务就还是
    一笔糊涂账。迁移做成**幂等**：先 `pragma table_info`，缺列才 `alter table`，已有列不重复动。
    """
    列名集 = {列信息[1] for 列信息 in 连接.execute("pragma table_info(未完成)")}
    if "类别" in 列名集:
        return False
    连接.execute("alter table 未完成 add column 类别 text not null default '债务'")
    return True


def 建源库(指定根: Path = None, 打读数: bool = False) -> dict:
    """建**规则库**（源表，受版本控制）⇒ 计数表。只重抽源表，不碰派生缓存。

    为何单列（2026-10-08 · 合主干源库重放）：合主干三方重放**跳过**源件权威表（`未完成` · 活 md 的
    `条款` 片），必须真跑重抽把活 md 的正文落进受版本的规则库（台账已改库即存本，不再在源件表里）；而派生缓存的源
    `.codegraph/` 不在新集成工作树里（gitignore）⇒ 合主干只能也只需建源库。
    ★ 清孤儿表：表从建表语句里移走后旧表不再残留；清过才 `VACUUM`（`drop table` 不缩文件）。
    """
    根目录 = 指定根 or 仓根
    规则库 = 表定义.库路径(根目录)
    # 受控的规则库不许无谓变脏：sqlite 文件头带事务计数 ⇒ 内容没变时字节也变（见 表定义.内容指纹）。
    建库前指纹 = 表定义.内容指纹(规则库)
    建库前字节 = 规则库.read_bytes() if 规则库.is_file() else None
    规则连接 = sqlite3.connect(规则库)
    for 语句 in 表定义.建表语句:
        规则连接.execute(语句)
    补台账类别列(规则连接)          # 老库补栏（幂等）；新库建表时已带这一栏，这里直接跳过
    规则连接.execute("insert or replace into 元 values(?,?)", ("生成物声明", 表定义.生成物声明))
    规则连接.execute("delete from 元 where 键 <> '生成物声明'")  # `元` 只留它；旧键是孤儿，见 表定义.py
    规则孤儿 = 清孤儿表(规则连接, set(表定义.源表) | {"元"})
    计数表 = {
        "条款": 装表(规则连接, "条款", 装条款, 根目录),
        "规则": 装表(规则连接, "规则", 装规则, 根目录),
    }
    规则连接.commit()
    if 规则孤儿:
        规则连接.execute("VACUUM")  # drop table 不缩文件 ⇒ 清过孤儿才 VACUUM（无孤儿不 VACUUM，免得白改字节）
    规则连接.close()
    if 建库前字节 is not None and 表定义.内容指纹(规则库) == 建库前指纹:
        临时件 = 规则库.with_name(规则库.name + ".还原")
        临时件.write_bytes(建库前字节)
        临时件.replace(规则库)
    if 打读数:
        print(f"规则库：{规则库}")
        if 规则孤儿:
            print(f"  清孤儿表：{' · '.join(规则孤儿)}")
        for 表名, 行数 in 计数表.items():
            print(f"  {表名}：{行数}")
    return 计数表


def 建派生库(指定根: Path = None, 打读数: bool = False) -> dict:
    """建**派生缓存**（派生表，每次重抽，不进版本库）⇒ 计数表。

    源是活源（代码地图索引 · `契约声明/` · `文档账本.json`）—— `.codegraph/` 不在场时抽取器
    fail-closed 抛（见 `代码图._拒重抽`），故本函数只在有索引的树里跑得动。
    """
    根目录 = 指定根 or 仓根
    派生库 = 表定义.派生库路径(根目录)
    派生连接 = sqlite3.connect(派生库)
    for 语句 in 表定义.派生建表语句:
        派生连接.execute(语句)
    派生孤儿 = 清孤儿表(派生连接, set(表定义.派生表))
    计数表 = {
        "文档": 装表(派生连接, "文档", 装文档, 根目录),
        "代码名": 装表(派生连接, "代码名", 装代码名, 根目录),
        "节点": 装表(派生连接, "节点", 装节点, 根目录),
        "连接": 装表(派生连接, "连接", 装连接, 根目录),
        "能力": 装表(派生连接, "能力", 装能力, 根目录),
        "能力参数": 装表(派生连接, "能力参数", 装能力参数, 根目录),
        "类型": 装表(派生连接, "类型", 装类型, 根目录),
        "错误码": 装表(派生连接, "错误码", 装错误码, 根目录),
        "文档索引": 装表(派生连接, "文档索引", 装文档索引, 根目录),
    }
    派生连接.commit()
    if 派生孤儿:
        派生连接.execute("VACUUM")
    派生连接.close()
    if 打读数:
        print(f"派生库：{派生库}")
        if 派生孤儿:
            print(f"  清孤儿表：{' · '.join(派生孤儿)}")
        for 表名, 行数 in 计数表.items():
            print(f"  {表名}：{行数}")
    return 计数表


def 建库(指定根: Path = None, 打读数: bool = False) -> dict:
    """建**两个**库：**规则库**（源表，受版本控制）＋ **派生缓存**（派生表，每次重抽）。

    为何分家见 `表定义.py` 件头（缓存与规则同住一个文件会把库拖脏，且它是索引的第二份副本）。
    两库各自清孤儿表（见 `建源库` / `建派生库`）。
    """
    计数表 = 建源库(指定根, 打读数)
    计数表.update(建派生库(指定根, 打读数))
    return 计数表


def 入口函数(命令行参数: list) -> int:
    """`信息核心.py 建库 …` 调它 —— 本包**不带** CLI（入口只有一个壳，见 信息核心.py）。"""
    建库(打读数="--读数" in 命令行参数)
    return 0
