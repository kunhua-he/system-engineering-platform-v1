# -*- coding: utf-8 -*-
"""建库 · 文档索引 —— `条款` → `文档索引`：把库里的文档正文投影成 (文档路径 · 序号 · 标题) 索引。

为何要它（2026-10-08）：库 `条款` 表装着约 130 份文档的正文（一行一节），却**没有索引** ——
查一份文档有哪些节、每节叫什么，只能靠把 `文档路径` 与序号背下来。本抽取器每跑一次 `建库`，
把那张表的 (文档路径 · 序号 · 标题) **投影**成派生表 `文档索引`（住派生库，不进版本库）。

来源与口径：**读规则库 `条款` 表**，不重跑 md —— `条款` 是全部 md 正文的**唯一存本**
（活 MD 取源、已删正文取条款，见 `表定义.分片源件表` 与 `建库.条款`）。故本抽取器与
`装条款` 解耦：它只投影那张表，`建库` 顺序保证 `条款` 先落好再抽本表。

★ **读不动就炸，绝不回空**（同 `代码图._拒重抽`）：回空会把派生表 `文档索引` 静默清空 ——
空源重抽是这个仓的头号大敌。
"""
import sqlite3
from pathlib import Path

from .路径 import 仓根  # noqa: F401,E402 —— 先挂 sys.path（须在下面那条 import 之前）
import 表定义  # noqa: E402


def 装文档索引(根目录: Path) -> list:
    """⇒ `文档索引` 的行表（每行 = `(文档路径, 序号, 标题)`）。

    **源 = 规则库 `条款` 表**（`建库` 里 `条款` 先落好再抽本表）：给不上就**炸**，不返回空。
    """
    规则库件 = 表定义.库路径(根目录)
    if not 规则库件.is_file():
        raise ValueError(
            f"规则库不在（{规则库件}）⇒ 拒重抽 `文档索引`（源为空就重抽会把派生表静默清空）")
    连接 = sqlite3.connect("file:%s?mode=ro" % 规则库件, uri=True)
    try:
        行表 = 连接.execute(
            "select 文档路径, 序号, 标题 from 条款 order by 文档路径, 序号").fetchall()
    finally:
        连接.close()
    if not 行表:
        raise ValueError("规则库 `条款` 表为空 ⇒ 拒重抽 `文档索引`（空源重抽 = 静默清空派生表）")
    return [(条款行[0], 条款行[1], 条款行[2]) for 条款行 in 行表]
