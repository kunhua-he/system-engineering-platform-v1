"""建库 · 源件 —— 读**分片源件**（`表定义.分片源件表`：每片的源件就是该片 `文档路径` 指的那份 md）。

★ 2026-10-13：整表的源件读取（`读源件` / `读一件` / `装未完成`）**已删** —— `未完成` 改
「库即存本」后 `表定义.源件表` 空了，没有整表源件可读（死码已删）。
"""
from pathlib import Path

import 表定义

from .保留时间 import 记旧值, 回填旧值
from .通用 import 读JSON件
from .文档 import 装文档


def 装分片源件(连接, 表名: str, 分片列: str, 现抽, 根目录: Path) -> int:
    """分片源件表：只重抽**源件在场**的那几片，其余行**保住**（见 `表定义.分片源件表`）。

    `条款` 走这条：每片的源件 = 该片 `文档路径` 指的那份 md。md 在场 ⇒ 重抽它那几节；
    md 已删（全树只剩 `README.md` / `AGENTS.md`）⇒ 旧节一字不动（库是它们的唯一存本）。
    ★ **临时文档是例外**：`项目文档/哲学.md` §四 定「临时文档用完即删」，`开发规范.md`
    的「策划与异步执行」一节同定「整批完成后也删除」⇒ 源件不在场的**临时文档**那几片
    **跟着删**（见 `清用完即删档`）；正式已删设计正文照旧保住。
    返回**整表**行数（读数口径与 `装表` 一致）。
    """
    文档行 = 装文档(根目录)
    在场路径表 = [文本行[0] for 文本行 in 文档行]
    数据行 = 现抽(根目录, 文档行)
    if 在场路径表:
        占位符 = ",".join("?" * len(在场路径表))
        旧值表 = 记旧值(连接, 表名)
        连接.execute(f"delete from {表名} where {分片列} in ({占位符})", 在场路径表)
        if 数据行:
            连接.executemany(
                f"insert or replace into {表名} values({','.join('?' * len(数据行[0]))})", 数据行)
            回填旧值(连接, 表名, 旧值表)
            落库行数 = 连接.execute(
                f"select count(*) from {表名} where {分片列} in ({占位符})", 在场路径表).fetchone()[0]
            if 落库行数 != len(数据行):
                raise ValueError(
                    f"{表名}：分片源件抽出 {len(数据行)} 行、落库只剩 {落库行数} 行 ⇒ "
                    f"有行被**主键**合并掉了（先修源件再跑）。")
    清用完即删档(连接, 表名, 分片列, 在场路径表)
    return 连接.execute(f"select count(*) from {表名}").fetchone()[0]


# 「用完即删」的档（`项目文档/哲学.md` §四 · `开发规范.md` 的「策划与异步执行」一节）：源件不在场 ⇒ 库里那几片**跟着删**。
# 只此一档 —— 正式设计正文（决策记录 / 设计文档 / 落点与规范 …）md 已删仍**保住**（库是唯一存本）。
用完即删档位 = ("临时文档",)


def 清用完即删档(连接, 表名: str, 分片列: str, 在场路径表: list) -> list:
    """删掉库里**源件已不在场**的「用完即删」档那几片 ⇒ 被删的路径表。

    表没有 `权威档` 列（非 `条款`）⇒ 不适用，返回空（本步只对「一行一节、带档位」的条款表有意义）。
    """
    列名集 = {列信息[1] for 列信息 in 连接.execute(f"pragma table_info({表名})")}
    if "权威档" not in 列名集 or not 用完即删档位:
        return []
    占位符 = ",".join("?" * len(用完即删档位))
    待查路径表 = [列信息[0] for 列信息 in 连接.execute(
        f"select distinct {分片列} from {表名} where 权威档 in ({占位符})", 用完即删档位)]
    待删路径表 = [路径 for 路径 in 待查路径表 if 路径 not in set(在场路径表)]
    if 待删路径表:
        连接.executemany(f"delete from {表名} where {分片列} = ?", [(路径,) for 路径 in 待删路径表])
    return 待删路径表
