# -*- coding: utf-8 -*-
"""保留时间 —— 重抽前先记住「创建时间」这类**首次落库时刻**列，重抽后按主键回填旧值。

**为什么**：`装表` / `装分片源件` 都是「先 `delete from` 再 `insert or replace`」⇒ 表里旧行
已不在，`创建时间 TEXT DEFAULT (datetime('now','localtime'))` 必取**当前时刻** ⇒ 同一份源件
在不同时刻建库得到**不同字节**。实测代价：`合主干集成树.提交恢复现场` 靠「重放后树变脏就再提交
一次」收口 ⇒ 源库每次重放都脏 ⇒ **必然造第二个同内容提交**（未完成台账的『合并工具两处缺陷』条 ①）。

**口径**：`创建时间` 是「这个名字**第一次**登记的时刻」，不是「这次重抽的时刻」⇒ 上次也在的行
沿用旧值；这次才出现的行取默认（它确实首次出现）。

**为什么抽成一件**：`装表` 与 `装分片源件` 两处同形（同类出现两次即抽节点）—— 写两遍迟早漂。
"""

import sqlite3

# 带默认值、且语义是「首次落库时刻」的列（`表定义.py` 里 `DEFAULT (datetime('now','localtime'))` 那几列）
保留列名 = "创建时间"


def _主键列(连接, 表名: str) -> str:
    """表的主键列名 ⇒ 列名（**只有单列主键**才有意义；复合主键 / 无主键 ⇒ 空串）。"""
    主键列名表 = [文本行[1] for 文本行 in 连接.execute("pragma table_info(%s)" % 表名) if 文本行[5]]
    return 主键列名表[0] if len(主键列名表) == 1 else ""


def 记旧值(连接, 表名: str) -> dict:
    """重抽**前**读 ⇒ `{主键值: 创建时间}`；表 / 列 / 单列主键任一不满足 ⇒ 空表（不干预）。"""
    try:
        列名集 = {文本行[1] for 文本行 in 连接.execute("pragma table_info(%s)" % 表名)}
    except sqlite3.Error:
        return {}
    if 保留列名 not in 列名集:
        return {}
    主键列 = _主键列(连接, 表名)
    if not 主键列:
        return {}
    return {数据行[0]: 数据行[1] for 数据行 in 连接.execute(
        "select %s, %s from %s" % (主键列, 保留列名, 表名))}


def 回填旧值(连接, 表名: str, 旧值表: dict) -> int:
    """重抽**后**按主键回填 ⇒ 回填条数（只碰上次也在的行；新行保持默认值）。"""
    if not 旧值表:
        return 0
    主键列 = _主键列(连接, 表名)
    if not 主键列:
        return 0
    回填 = 0
    for 主键值, 旧时间 in 旧值表.items():
        游标 = 连接.execute("update %s set %s = ? where %s = ?" % (表名, 保留列名, 主键列),
                        (旧时间, 主键值))
        回填 += 游标.rowcount or 0
    return 回填
