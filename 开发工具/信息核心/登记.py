# -*- coding: utf-8 -*-
"""登记 —— 往规则库的 `命名定义` 表登记新名 / 改自由文本两栏（**改命名规则的唯一写路径**）。

用法：
    python3 开发工具/信息核心/信息核心.py 登记 <名> [<名>…] [--语义 <一句话>]
    python3 开发工具/信息核心/信息核心.py 登记 --语义 <语义> [--唯一名 <文本>] [--现状 <文本>]
    python3 开发工具/信息核心/信息核心.py 登记 --例外 <名>
    python3 开发工具/信息核心/信息核心.py 登记 --删 --语义 <语义>

**为何要它**：名册住规则库（华哥 2026-09-29「全规则都在 db 里面。外部不留」）⇒ 登记不能再靠
改一份 json（库里是唯一存本，不再有源件）。写库走**源件记账**那条路（`v1_task` 功能 = 6）
—— `v1_edit` 是文本替换，二进制件它改不了。

**语义**：默认「名即语义」（与旧名册的 txt 一行一名同口径）；一个名指多件事的，
用 `--语义` 写清楚，或改由「一个语义一行」的方式登记。

**第三种形态（`--例外`）—— 写 `命名例外` 表**：语言 / 协议 / 工具强加的名（不是取名）住那张一列的表，此前**没有任何写口**（只能手写 SQL —— 那是已关掉的坏路）。本口补上它：`--例外 <名>` 往 `命名例外` 里 `insert or replace` 一行（键 = 名，重名不报错）。首个用例：契约强加的冻结公开面字段名 `码`（`契约声明/src/契约声明/错误码形状.rs` 件头「逐字不变」）—— 它不许改名（改了就破 ABI），也不该占 `命名定义` 的定义豁免出口。

**第四种形态（`--删`）—— 删 `命名定义` 一行**：`命名定义` 的写口此前只有「新建」「改两栏」
「写例外」三种，**没有删行口**。去重批次要删几十行**重复登记**（同一 `唯一名` 挂多行同义
`语义`，只留一行），没有删行口就只能手写 SQL（绕过账本，是已关掉的坏路）。本口补上它：
`--删 --语义 <语义>` 删主键那一行。fail-closed（语义不在名册 ⇒ 拒，不静默删 0 行）·
幂等（删主键行，不叠加副作用）· 打印删了几行。

**第二种形态（`--唯一名` / `--现状`）—— 改自由文本两栏**：`命名定义` 的 `唯一名` /
`现状` 两栏是自由文本，原先只做 `(语义, 唯一名, 现状)` 的 `insert or replace`（三栏一起写死），
两栏改不动。现给 `登记` 加这两栏的**显式写口**：`--语义` 定位既有行（它是主键），
`--唯一名` / `--现状` 各只改一栏（不给的那栏保持原值）。**本口只改既有行，不新建** ——
新建走 `登记 <名>`。首个用例：枚举值名裁为 `真`/`假`（库 `规则` 表 `命名口径-8`）——
    python3 开发工具/信息核心/信息核心.py 登记 --语义 "null / true / false" \\
        --唯一名 "`空值` · `真` · `假`" --现状 "`空` · `逻辑真` · `逻辑假`"
"""
from __future__ import annotations

import sqlite3
import sys
from pathlib import Path

仓根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

import 表定义  # noqa: E402
import 记规则  # noqa: E402  （复用它的参数解析 —— 不许写第二套）


def 解析(参数表: list) -> tuple:
    """⇒ `(名表, 语义, 唯一名, 现状, 例外, 是否删行)`。

    位置参数（首个 `--` 之前）= 名表；`--语义` / `--唯一名` / `--现状` / `--例外` 各吃一个值
    （值可带空格）。字段解析复用 `记规则.解析参数`（**不许写第二套**）；缺席的旗标给 `None`
    （`None` = 不走那一条路，与「显式给空串」区分开）。`是否删行` = 是否给了 `--删`（它**不吃值**，
    只看旗标在不在 —— `记规则.解析参数` 把「没给」与「给了空值」都记成空串，分不开）。
    """
    名表 = []
    for 一片 in 参数表:
        if 一片.startswith("--"):
            break
        名表.append(一片)
    字段表 = 记规则.解析参数(参数表)
    return (名表, 字段表.get("语义", ""), 字段表.get("唯一名"),
            字段表.get("现状"), 字段表.get("例外"), "删" in 字段表)


def 写例外(例外名: str) -> int:
    """把 `例外名` 写进库 `命名例外`（语言 / 协议 / 工具强加，不在命名管辖内）⇒ 退出码。

    一列的表、键 = 名：`insert or replace` ⇒ 重名不报错（幂等）。空名 ⇒ 拒。
    """
    if not 例外名:
        print("`--例外` 要一个名（空名不写）", file=sys.stderr)
        return 2
    连接 = sqlite3.connect(表定义.库路径(仓根))
    try:
        连接.execute("insert or replace into 命名例外 values(?)", (例外名,))
        连接.commit()
    finally:
        连接.close()
    print("登记例外：%s（语言 / 协议 / 工具强加，不在命名管辖内）" % 例外名)
    print("★ 库变了 ⇒ 收口前记得 `v1_task` 功能=6 记账"
          "（`源件` = `开发工具/信息核心/信息核心.db`），否则释放的越界检测会拒")
    return 0


def 唯一名形状拒因(唯一名: str) -> str:
    """`唯一名` 过形状闸 ⇒ 空串 = 放行，非空 = 拒因（调用方拼提示用）。

    `唯一名` 栏该是**名**（一个名，或 `名` · `名` 的名单）；整句描述、带注解的长文
    该进 `语义` 栏。实测 2026-10-01 腿 v1-100217 / v1-100221 把长描述串写进了 `唯一名`
    栏（`语义` 反倒拿了短名）⇒ 立此闸。三条拒因全有全量库读数撑着（6566 行正当名
    全量回放零误拒）：
    ① 含全角括号 ⇒ 拒 —— 正当名 0 例含它，错位行恰恰带；
    ② ` · ` 分隔符之外还有空白 ⇒ 拒 —— 22 个含空白的正当行全是名单形；
    ③ 全长超过 64 ⇒ 拒 —— 正当名最长 47（语言强加的苹果选择器）、名单形最长 33，
       64 = 上一档整界，只拦成句级描述、不误拒任何存量。
    """
    if "（" in 唯一名 or "）" in 唯一名:
        return "含全角括号"
    for 名单段 in 唯一名.split(" · "):
        if any(字符.isspace() for 字符 in 名单段):
            return "含 ` · ` 之外的空白"
    if len(唯一名) > 64:
        return "长 %d 超过 64" % len(唯一名)
    return ""


def 删行(语义: str) -> int:
    """从 `命名定义` 删掉 `语义` 那一行（主键定位）⇒ 退出码。

    **为何要它**：`命名定义` 的写口原先只有「新建」「改两栏」「写例外」三种，**没有删行口** ——
    而去重批次要删几十行**重复登记**（同一 `唯一名` 挂多行同义 `语义`，只留一行），没有删行口
    就只能手写 SQL（绕过账本，是已关掉的坏路）。本口补上它：`--删 --语义 <语义>` 删主键那一行。
    **fail-closed**：`语义` 不在名册 ⇒ 拒（退出码 1）—— 静默删 0 行会把「语义打错」伪装成
    「已删」，一批里打错一条就漏删一组。**幂等**：删的是主键行，重放同一批命令不叠加副作用
    （第二次因该行已不在名册而报拒，正是 fail-closed 在报「已删净」）。**打印删了几行**。
    """
    语义 = (语义 or "").strip()
    if not 语义:
        print("`--删` 要 `--语义 <语义>`（它是 `命名定义` 的主键）", file=sys.stderr)
        return 2
    连接 = sqlite3.connect(表定义.库路径(仓根))
    try:
        游标 = 连接.execute("delete from 命名定义 where 语义 = ?", (语义,))
        删掉行数 = 游标.rowcount
        if 删掉行数 == 0:
            连接.rollback()
            print("拒：`%s` 不在名册 —— 没有可删的行（fail-closed：不静默删 0 行）" % 语义,
                  file=sys.stderr)
            return 1
        连接.commit()
    finally:
        连接.close()
    print("删行：%s ⇒ 删了 %d 行" % (语义, 删掉行数))
    print("★ 库变了 ⇒ 收口前记得 `v1_task` 功能=6 记账"
          "（`源件` = `开发工具/信息核心/信息核心.db`），否则释放的越界检测会拒")
    return 0


def 登记(名表: list, 语义: str = "", 唯一名=None, 现状=None, 例外=None, 是否删行=False) -> int:
    """登记新名 / 改 `命名定义` 两栏 / 写 `命名例外` / 删 `命名定义` 一行（四种形态互斥，见件头）⇒ 退出码。

    一次给多个名时**不许再给 `--语义`**（`语义` 是主键，多名共用一个主键会互相覆盖、静默丢
    数据）⇒ 拒；名表里有重名同样拒（同一主键）。
    `--语义` 定位既有行（它是 `命名定义` 的主键），语义不在名册 ⇒ 拒（**只改既有行，不新建**）；
    只改给的栏，另一栏保持原值；两栏都没给 ⇒ 拒。
    `唯一名` 落库前过 `唯一名形状拒因` 形状闸（含全角括号 / 名单外空白 / 全长超 64
    ⇒ 拒，退出码 2）—— 两种写口（`<名>` 位置参与 `--唯一名`）都过。
    """
    if 是否删行:
        return 删行((语义 or "").strip())
    if 例外 is not None:
        return 写例外((例外 or "").strip())
    if 唯一名 is not None or 现状 is not None:
        语义 = (语义 or "").strip()
        if not 语义:
            print("改两栏要 `--语义 <语义>`（它是 `命名定义` 的主键）", file=sys.stderr)
            return 2
        if 唯一名 is not None:
            拒因 = 唯一名形状拒因(唯一名)
            if 拒因:
                print("拒：`唯一名` %s —— `唯一名` 该是名、`语义` 才是描述" % 拒因,
                      file=sys.stderr)
                return 2
        连接 = sqlite3.connect(表定义.库路径(仓根))
        try:
            旧行 = 连接.execute(
                "select 唯一名, 现状 from 命名定义 where 语义 = ?", (语义,)).fetchone()
            if 旧行 is None:
                print("拒：`%s` 不在名册 —— 本口只改既有行；新建走 `登记 <名>`" % 语义,
                      file=sys.stderr)
                return 1
            唯一名 = 旧行[0] if 唯一名 is None else 唯一名
            现状 = 旧行[1] if 现状 is None else 现状
            连接.execute("update 命名定义 set 唯一名 = ?, 现状 = ? where 语义 = ?",
                       (唯一名, 现状, 语义))
            连接.commit()
        finally:
            连接.close()
        print("改两栏：%s ⇒ 唯一名 = %s · 现状 = %s" % (语义, 唯一名, 现状))
        print("★ 库变了 ⇒ 收口前记得 `v1_task` 功能=6 记账"
              "（`源件` = `开发工具/信息核心/信息核心.db`），否则释放的越界检测会拒")
        return 0
    if not 名表:
        print("用法：信息核心.py 登记 <名> [<名>…] [--语义 <一句话>]", file=sys.stderr)
        return 2
    if (语义 or "").strip() and len(名表) > 1:
        print("拒：一次给多个名时不许再给 `--语义` —— `语义` 是 `命名定义` 的主键，"
              "多个名共用同一个主键会互相覆盖、静默只留最后一行。"
              "要一次登记多名请逐名给（名即语义）；要写 `--语义` 请一次只登记一个名。",
              file=sys.stderr)
        return 2
    if len(set(名表)) != len(名表):
        print("拒：名表里有重名 —— 同一个名占同一个主键，`insert or replace` 会静默合并。"
              "请去掉重复的名再登记。", file=sys.stderr)
        return 2
    for 登记名 in 名表:
        拒因 = 唯一名形状拒因(登记名)
        if 拒因:
            print("拒：%r %s —— `唯一名` 该是名、`语义` 才是描述" % (登记名, 拒因),
                  file=sys.stderr)
            return 2
    连接 = sqlite3.connect(表定义.库路径(仓根))
    try:
        for 登记名 in 名表:
            连接.execute("insert or replace into 命名定义 values(?,?,?)",
                       (语义 or 登记名, 登记名, "（名即语义）"))
        连接.commit()
    finally:
        连接.close()
    print("登记 %d 个名：%s" % (len(名表), " · ".join(名表)))
    print("★ 库变了 ⇒ 收口前记得 `v1_task` 功能=6 记账"
          "（`源件` = `开发工具/信息核心/信息核心.db`），否则释放的越界检测会拒")
    return 0
