"""项目上下文聚合：预算投影与版本绑定分页，无持久化状态。

操作表 是 v1_context 的查询契约：操作名 → (必需字段, 可选字段, 最短例)；
MCP 层 `操作_上下文.py` 直接再导出它，供加载器合并进工具模式。
"""
import base64
import hashlib
import json
from pathlib import Path
from .上下文来源 import (上下文失败, 安全文档路径, 安全路径前缀, 取版本件表, 取来源版本,
                        读上下文条目, 文档账本件, 读指纹, 临时档名)

模块版本 = "v1_context/2"
# 数值参的合法范围与缺省（下限, 上限, 缺省）—— **单源表**：输入检查 · 操作说明 · 回执都从它派生。
数值约束 = {"条数": (1, 50, 20), "字节预算": (1024, 16384, 8192)}
数值参 = tuple(数值约束)
# 顶层 `开工ID` 与 `操作` / `参数` 同级（不在 `参数` 内）—— 操作说明复用的单源文本。
开工说明 = "顶层 `开工ID` 与 `操作` / `参数` 同级（不在 `参数` 内）"
# 非法 / 过期游标一律照这句办：不给伪游标值，重取第一页。
游标提示 = "；请去掉 `游标` 重取第一页（本工具不回给伪游标值）"


def 数值范围文本(名称):
    """一个数值参的合法区间文本（如 `1..50`）。"""
    return "%d..%d" % (数值约束[名称][0], 数值约束[名称][1])


def 数值缺省(名称):
    """一个数值参的缺省值。"""
    return 数值约束[名称][2]


def 约束说明(名称):
    """一个数值参的合法范围与缺省的单源说明文本。"""
    return "`" + 名称 + "` 合法范围 " + 数值范围文本(名称) + "，缺省 " + str(数值缺省(名称))


def 数值参说明(名称表):
    """一组数值参名的合法范围与缺省的单源说明文本（空表 ⇒ 空串）。"""
    return "；".join(约束说明(名称) for 名称 in 名称表)


操作表 = {
    "摘要": ((), ("主题", "包含", "条数", "字节预算", "游标", "权威档", "开工ID"), {"操作": "摘要"}),
    "条款检索": (("检索",), ("包含", "条数", "字节预算", "游标", "权威档"), {"操作": "条款检索", "检索": "元素表"}),
    "文档序号": (("文档路径",), ("条数", "字节预算", "权威档"), {"操作": "文档序号", "文档路径": "项目文档/开发规范/开发规范.md"}),
    "文档索引": (("文档路径",), ("条数", "字节预算"), {"操作": "文档索引", "文档路径": "项目文档/开发规范"}),
    "取整件": (("文档路径",), ("序号段", "条数", "字节预算", "游标"), {"操作": "取整件", "文档路径": "项目文档/开发规范/开发规范.md"}),
    "冻结落点": ((), ("路径", "条数", "字节预算"), {"操作": "冻结落点"}),
    "名字全文": (("名字",), ("条数", "字节预算", "游标"), {"操作": "名字全文", "名字": "上下文读取"}),
}
来源类别表 = ("规则", "条款", "未完成", "开工", "索引", "名字")


def 编码输出(输出对象):
    return json.dumps(输出对象, ensure_ascii=False, separators=(",", ":"), sort_keys=True)


def 检查输入(查询参数):
    允许字段 = {"开工ID", "主题", "文档路径序号表", "包含", "条数", "字节预算", "游标",
                "操作", "检索", "文档路径", "序号段", "权威档", "名字", "路径", "参数"}
    if not isinstance(查询参数, dict):
        raise 上下文失败("参数错误", "输入须为对象")
    查询参数 = dict(查询参数)
    if "参数" in 查询参数:
        嵌套 = 查询参数.pop("参数")
        if not isinstance(嵌套, dict):
            raise 上下文失败("参数错误", "参数须为对象")
        查询参数.update(嵌套)
    if set(查询参数) - 允许字段:
        raise 上下文失败("参数错误", "不支持的输入字段")
    for 名称, 上限 in (("开工ID", 256), ("主题", 256), ("游标", 1024), ("操作", 32),
                     ("检索", 256), ("文档路径", 256), ("权威档", 64), ("名字", 256), ("路径", 256)):
        查询参数.setdefault(名称, "")
        if 名称 == "主题" and type(查询参数[名称]) is int:
            查询参数[名称] = str(查询参数[名称])      # 主题惯用台账号 / 开工号（纯数字）⇒ 整数也收
        if not isinstance(查询参数[名称], str) or len(查询参数[名称]) > 上限:
            raise 上下文失败("参数错误", 名称 + "须为有界字符串")
    for 名称 in 数值参:
        下限值, 上限值, 默认值 = 数值约束[名称]
        查询参数.setdefault(名称, 默认值)
        if type(查询参数[名称]) is not int or not 下限值 <= 查询参数[名称] <= 上限值:
            raise 上下文失败("参数错误", "超出范围：" + 约束说明(名称))
    包含给定 = "包含" in 查询参数
    查询参数.setdefault("包含", ["条款", "规则", "未完成"])
    包含表 = 查询参数["包含"]
    if not isinstance(包含表, list) or not 包含表 or len(包含表) > 6 or any(type(名称) is not str or 名称 not in 来源类别表 for 名称 in 包含表):
        raise 上下文失败("参数错误", "包含须为明确来源类别列表")
    查询参数["包含"] = sorted(set(包含表))
    查询参数.setdefault("文档路径序号表", [])
    精确表 = 查询参数["文档路径序号表"]
    if not isinstance(精确表, list) or len(精确表) > 50:
        raise 上下文失败("参数错误", "精确定位最多50条")
    for 条款定位 in 精确表:
        if not isinstance(条款定位, dict) or set(条款定位) != {"文档路径", "序号"} or not isinstance(条款定位["文档路径"], str) or len(条款定位["文档路径"]) > 256 or type(条款定位["序号"]) is not int or 条款定位["序号"] < 0:
            raise 上下文失败("参数错误", "条款定位格式错误")
        安全文档路径(Path.cwd(), 条款定位["文档路径"])
    查询参数.setdefault("序号段", None)
    段值 = 查询参数["序号段"]
    if 段值 is not None:
        if not isinstance(段值, list) or len(段值) != 2 or any(type(段项) is not int or 段项 < 0 for 段项 in 段值) or 段值[0] > 段值[1]:
            raise 上下文失败("参数错误", "序号段须为两个非负整数，起不大于止")
    if 查询参数["文档路径"]:
        安全路径前缀(查询参数["文档路径"])
    操作值 = 查询参数["操作"]
    if 操作值 and 操作值 not in 操作表:
        raise 上下文失败("参数错误", "未知操作：" + 操作值)
    if not 操作值:
        if 查询参数["检索"]:
            操作值 = "条款检索"
        elif 查询参数["文档路径"] and 段值 is not None:
            操作值 = "取整件"
        elif 查询参数["文档路径"]:
            操作值 = "文档序号"
        elif 查询参数["名字"] and "名字" not in 查询参数["包含"]:
            操作值 = "名字全文"
        else:
            操作值 = "摘要"
    if 操作值 == "条款检索" and not 查询参数["检索"]:
        raise 上下文失败("参数错误", "操作=条款检索 须给 检索")
    if 操作值 in ("文档序号", "取整件", "文档索引") and not 查询参数["文档路径"]:
        raise 上下文失败("参数错误", 操作值 + " 须给 文档路径")
    if 操作值 == "名字全文" and not 查询参数["名字"]:
        raise 上下文失败("参数错误", "操作=名字全文 须给 名字")
    if 段值 is not None and 操作值 != "取整件":
        raise 上下文失败("参数错误", "序号段仅操作=取整件使用")
    if 精确表 and 操作值 != "摘要":
        raise 上下文失败("参数错误", "文档路径序号表仅操作=摘要使用")
    if not 包含给定:
        if 操作值 == "条款检索":
            查询参数["包含"] = ["条款", "规则"]
        elif 操作值 in ("文档序号", "取整件", "文档索引"):
            查询参数["包含"] = ["条款"]
        elif 操作值 == "名字全文":
            查询参数["包含"] = ["名字"]
        elif 操作值 == "冻结落点":
            查询参数["包含"] = ["条款"]
    查询参数["操作"] = 操作值
    if 精确表 and "条款" not in 查询参数["包含"]:
        raise 上下文失败("参数错误", "精确定位须包含条款")
    return 查询参数


def 打包游标(查询指纹, 来源指纹, 页位置):
    return base64.urlsafe_b64encode(编码输出({"查询": 查询指纹, "版本": 来源指纹, "位置": 页位置}).encode()).decode()


def 解读游标(游标值, 查询指纹, 来源指纹):
    if not 游标值:
        return 0
    try:
        游标对象 = json.loads(base64.b64decode(游标值, altchars=b"-_", validate=True))
    except (ValueError, UnicodeError) as 失败原因:
        raise 上下文失败("参数错误", "游标无法解码" + 游标提示) from 失败原因
    if not isinstance(游标对象, dict) or set(游标对象) != {"查询", "版本", "位置"} or type(游标对象["位置"]) is not int or not 0 <= 游标对象["位置"] <= 100000:
        raise 上下文失败("参数错误", "游标格式错误" + 游标提示)
    if 游标对象["查询"] != 查询指纹 or 游标对象["版本"] != 来源指纹:
        raise 上下文失败("游标过期", "树、查询或来源版本已变" + 游标提示)
    return 游标对象["位置"]


def 读取上下文(树根, 查询参数, 分支值, 分支HEAD, 账本路径=None, 服务代码版本=None):
    查询参数 = 检查输入(查询参数)
    树根 = Path(树根).resolve()
    指纹值 = 读指纹(树根 / 文档账本件)
    版本件表, 账本内容 = 取版本件表(树根, 查询参数["包含"], 账本路径, 查询参数["操作"])
    来源版本 = 取来源版本(版本件表)
    if 来源版本[str(树根 / 文档账本件)] != 指纹值:
        raise 上下文失败("不一致", "读取文档账本期间来源发生变化")
    来源指纹 = hashlib.sha256(编码输出({"来源": 来源版本, "HEAD": 分支HEAD}).encode()).hexdigest()
    查询键 = {名称: 字段值 for 名称, 字段值 in 查询参数.items() if 名称 != "游标"}
    查询指纹 = hashlib.sha256(编码输出({"树": str(树根), "查询": 查询键, "模块": 模块版本, "服务代码": 服务代码版本}).encode()).hexdigest()
    页位置 = 解读游标(查询参数["游标"], 查询指纹, 来源指纹)
    输出对象 = {"版本": 模块版本, "树绝对路径": str(树根), "分支": 分支值, "HEAD": 分支HEAD,
                "提交": 分支HEAD, "来源版本": 来源指纹, "新鲜度": "源表当前读取",
                "服务代码": 服务代码版本 or {"模块版本": 模块版本, "新鲜度": "未知"},
                "条目": [], "截断": False, "游标": None}
    输出预算 = 查询参数["字节预算"]
    返回条目, 投影数量 = [], 0
    完整条目表 = list(读上下文条目(树根, 查询参数, 账本内容, 账本路径, 分支HEAD))
    if 查询参数["权威档"]:
        完整条目表 = [完整条目 for 完整条目 in 完整条目表 if 完整条目.get("权威档") == 查询参数["权威档"]]
    临时命中数 = sum(1 for 完整条目 in 完整条目表 if 完整条目.get("权威档") == 临时档名)
    if 临时命中数:
        输出对象["提示"] = "命中 %d 条临时档（权威档=临时文档）；建议改用精确路径或操作=取整件" % 临时命中数
    if 查询参数["操作"] == "摘要" and not 查询参数["主题"] and not 查询参数["文档路径序号表"]:
        完整条目表.sort(key=lambda 完整条目: (完整条目["类型"] != "未完成", 完整条目["类型"] != "条款",
                                            完整条目.get("权威档") == 临时档名,
                                            完整条目.get("内容", {}).get("定位", {}).get("序号", 0)))
        for 完整条目 in 完整条目表:
            if 完整条目["类型"] == "未完成":
                完整条目["内容"] = {"号": 完整条目["内容"]["号"], "状态": "未完成；完整四栏按主题读取"}
    if 页位置 > len(完整条目表):
        raise 上下文失败("参数错误", "游标位置超出结果")
    for 序号值 in range(页位置, len(完整条目表)):
        完整条目 = 完整条目表[序号值]
        if len(返回条目) == 查询参数["条数"]:
            输出对象.update({"截断": True, "游标": 打包游标(查询指纹, 来源指纹, 序号值)})
            break
        输出对象.update({"条目": 返回条目 + [完整条目], "截断": True, "游标": 打包游标(查询指纹, 来源指纹, 序号值 + 1)})
        if len(编码输出(输出对象).encode()) + 32 > 输出预算:
            if 返回条目:
                输出对象.update({"条目": 返回条目, "截断": True, "游标": 打包游标(查询指纹, 来源指纹, 序号值)})
                break
            投影条目 = {名称: 字段值 for 名称, 字段值 in 完整条目.items() if 名称 != "内容"}
            投影条目["内容"] = {"状态": "预算投影，仅返回完整来源指针", "完整内容字节": len(编码输出(完整条目["内容"]).encode())}
            输出对象["条目"] = [投影条目]
            if len(编码输出(输出对象).encode()) + 32 > 输出预算:
                raise 上下文失败("预算不足", "元数据与来源指针无法放入预算；请提高字节预算")
            完整条目, 投影数量 = 投影条目, 投影数量 + 1
        返回条目.append(完整条目)
        输出对象.update({"条目": 返回条目, "截断": False, "游标": None})
    if 取来源版本(版本件表) != 来源版本:
        raise 上下文失败("不一致", "跨源读取期间来源发生变化")
    if 投影数量:
        输出对象["投影"] = 投影数量
    输出文本 = 编码输出(输出对象)
    if len(输出文本.encode()) > 输出预算:
        raise 上下文失败("预算不足", "输出元数据无法放入预算")
    return 输出文本
