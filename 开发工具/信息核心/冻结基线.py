"""冻结基线 —— 把**十张存量清单**重冻成现状（判据 ㉒/㊷ 的命名面 · 判据 ⑲/㉕/㊴/㊵/㊳/⑯/㊹/㊺ 的判据面）。

用法：
    python3 开发工具/信息核心/信息核心.py 冻结基线

**只许减**：重冻只允许「删掉已经归零的登记」—— 任何**新增键**（旧基线里没有的）或**涨了**
（实测处数 > 登记处数）一律拒写，并把差额逐条列出来。理由：基线是「存量不许再长」的闸，
不是白名单；让它自动重冻就等于把闸拆了（判据 ⑲ 先立的那句话：「不许靠重冻洗白」）。
新增债的正确走法：① 改代码，或 ② 把名登记进库（`信息核心.py 登记 --名字 <名> --语义 <语义>
--模式 对象+说明 --来源 新定义`，该子命令只吃具名参）。

**★ 面扩首冻**（2026-09-30 · 形状债面扩）：把某档的**扫描面**从一处扩到多处（如 ㉒ 的档 E/F
从「索引定义面」扩到「形参面 + 局部面」）⇒ 实测必然冒出「新键」—— 那是**扩面后现形的存量**
（债一直在，只是原先看不见），**不是**新写的债。故 `首冻档` 里的档**在旧基线里一条登记都没有**
（本次是它的首冻）时，新键放行（承认存量，不是「不算债」）。**已有面仍只许减** —— 首冻落地后
该档就有行了，本口子自动闭合：此后该档任何新键都是真「新增即红」。

**★ 面扩首冻（债名面 · 2026-10-05 · ㊺ 的 `→` 分支修活）**：判据 ㊺ 的 `→` 分支（禁形取自
**本行** `唯一名` 栏 · `命名口径-10` ③ 的归属豁免）此前恒不命中 ⇒ **债名行**（`现状` 含 `→`）
派生的禁形从未进过 `命名禁形基线`。修活后它们**第一次**现形 ⇒ 实测冒出 62 个「新键」——那是
扩面后现形的**存量**（债一直在，只是原先看不见），**不是**新写的债。故 `债名禁形集`（债名行
派生的禁形名集 · 由 `判据_禁形.读禁形行` 给出）在**旧基线里一条登记都没有**（本次是它的首冻）
时，本集内的新键放行；**已有面仍只许减** —— 落地后旧基线里就有本集的键了，本口子自动闭合：
此后同类新键即真「新增即红」。★ 残余（如实登记）：本集若日后被**改齐到一条不剩**，旧基线里
本集的登记就没了，口子会重开 ⇒ 那时把 `只许减` 的 `债名禁形集` 入参去掉即闭合（由维护方做）。

**为何要有这条命令**：两张基线都住规则库（二进制），手改没有正当路径；而没有它，
每修好一处债就得现写一段一次性脚本 —— 那正是「靠重冻洗白」最容易被做出来的地方。

**八张基线共一个命令**（不拆八条腿）：它们的判据不同，但**写时机与守卫完全一样**
（都在「债修完了」那一刻 · 都只许减）⇒ 拆开只会多五处「只减守卫」的副本。

**★ 名册（`命名定义`）只增不减是「有意」**：判据 ㊷ 只判「**出现的**名有没有登记」，
不管「**登记的**名有没有出现」—— 名可复用、也可暂离代码，登记是「这个名有定义」的**声明**，不是
「这个名此刻在代码里」的**快照**。故本命令只修剪两张**基线**表（`命名基线` · `命名穷举基线`），
**不剪名册**：删净一个名后名册留条目不是债，修掉它也不是本命令的活。
"""
