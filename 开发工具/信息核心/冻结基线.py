def 只许减(旧基线: dict, 新基线: dict, 比处数: bool, 首冻前缀: str = "") -> list:
    """实测对基线 ⇒ **新增 / 涨了**的差额说明（空 = 只有减，可以写）。

    `比处数` 跟着**各自判据**走：有的基线判「处数」，多一处就更糟 ⇒ 比；有的按「条」记、
    不按处数记 ⇒ 不比。守卫若比判据更严，就会出现「判据放行、冻结拒写」的两套口径。

    `首冻前缀` = **面扩首冻**的前缀（见件头「★ 面扩首冻（条款面）」）：旧基线里一条该前缀的
    登记都没有（本次是它的首冻）时，前缀内的新键放行；落地后自动闭合（旧基线里已有该前缀的
    键 ⇒ 此后同类新键即真「新增」）。**不按前缀无条件放行** —— 那等于永久口子（重冻洗白）。
    """
    差额 = []
    for 键名, 处数 in sorted(新基线.items()):
        登记 = 旧基线.get(键名)
        if 登记 is None:
            # 面扩首冻前缀**自闭合**：旧基线里一条该前缀的登记都没有（本次是它的首冻）才放行。
            if (首冻前缀 and str(键名[0]).startswith(首冻前缀)
                    and not any(str(旧键[0]).startswith(首冻前缀) for 旧键 in 旧基线)):
                continue
            差额.append(f"新增：{键名}（{处数} 处）")
        elif 比处数 and 处数 > 登记:
            差额.append(f"涨了：{键名}（{登记} → {处数} 处）")
    return 差额


def 取判据实测(树根) -> tuple:
    """七张判据基线（⑲/㉕/㊴/㊵/㊳/⑯/㊹）的**实测**读数 ⇒
    `({"行数", "运行数据", "引用", "引用未判", "十干", "台账号", "底座扩展名",
    "禁译名", "硬写能力号"}, 错误)`（引用有两面）。

    七张都走**各自判据的那一份扫描器**（⑲ 走 `查文件行数.核心.扫一遍` · ㉕ 走
    `判据_运行数据.扫自拼` · ㊴ 走 `判据_引用.扫引用面` · ㊵ 走 `判据_十干.数命中` ·
    ㊳ 走 `判据_台账号.扫台账号` · ⑯ 走 `判据_底座与树.扫底座扩展名注释面` ·
    ㊹ 走 `判据_禁译名.扫禁译名面` + `数命中`），
    本件不另写一套 —— 否则「冻结的读数」与「判据的读数」会漂成两个数。七张共用一份
    `上层读数`（`读文件.建上下文`）。
    """
    from 一键验证 import (读文件, 判据_墙钟与行数, 判据_运行数据, 判据_引用, 判据_十干,
                        判据_台账号, 判据_底座与树, 判据_禁译名, 判据_能力号)

    上层读数 = 读文件.建上下文(树根)
    核心 = 判据_墙钟与行数._行数工具(上层读数)
    超行数, 入口超行数, 入口有实现 = 核心.扫一遍(树根)
    行数实测 = {}
    for 行数, 路径 in 超行数:
        行数实测[("超行数", 路径)] = 行数
    for 行数, 路径 in 入口超行数:
        行数实测[("入口超行数", 路径)] = 行数
    for 路径, 实现 in 入口有实现:
        行数实测[("入口有实现", 路径)] = len(实现)
    运行数据实测 = 判据_运行数据.扫自拼(判据_运行数据.运行数据面(上层读数))
    悬空表, _判过, 未判表 = 判据_引用.扫引用面(上层读数)
    引用实测 = {(本件路径, 件名, 节号) for 本件路径, _行号, 件名, 节号, _原文 in 悬空表}
    引用未判实测 = {冻结条目[2] for 冻结条目 in 未判表}
    十干实测 = 判据_十干.数命中(判据_十干.扫十干面(上层读数))
    台账号实测 = {}
    for 路径, 号值, 形式, 原文 in 判据_台账号.扫台账号(判据_台账号.台账号面(上层读数)):
        键名 = (路径, 形式.split("（", 1)[0])
        台账号实测[键名] = 台账号实测.get(键名, 0) + 1
    底座扩展名实测 = 判据_底座与树.扫底座扩展名注释面(判据_底座与树.底座扩展面(上层读数))
    return {"行数": 行数实测, "运行数据": 运行数据实测, "引用": 引用实测,
            "引用未判": 引用未判实测, "十干": 十干实测,
            "台账号": 台账号实测, "底座扩展名": 底座扩展名实测,
            "禁译名": 判据_禁译名.数命中(判据_禁译名.扫禁译名面(上层读数)),
            "硬写能力号": 判据_能力号.文本键(判据_能力号.扫硬写能力号(上层读数))}, ""


def 两半并发(树根) -> tuple:
    """判据面的**实测**读数 ⇒ `(判据实测, 错误)`。

    命名面（原 `取实测`）随命名口径体系一并删除 ⇒ 本件只剩判据面这一半（函数名沿用旧称）。
    判据面是一次**全树只读扫描**；本条命令的墙钟受 5 秒硬顶管（裁决 §一「所有运行五秒硬顶」）。
    **按仓内先例**（`验证.py::用判据进程池` · `开发工具/取证/声明记录区反解/分片.py::扫并发`）
    用 `fork` 进程池跑 —— 扫描是 CPU 密集的纯 Python 代码，GIL 之下线程池拿不到并行。
    没有 `fork` 的平台**退回串行**（读数一样，只是慢 —— 那时本命令如实超顶，不假装）。
    """
    import multiprocessing

    try:
        with multiprocessing.get_context("fork").Pool(processes=1) as 进程池:
            判据实测 = 进程池.apply_async(取判据实测, (树根,)).get()
    except Exception:
        判据实测 = 取判据实测(树根)
    return 判据实测[0], 判据实测[1]


def 冻结(树根) -> int:
    """重冻各张基线（只许减）⇒ 退出码。"""
    旧行数, 错误 = 判据基线.读行数基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    旧运行数据, 错误 = 判据基线.读运行数据基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    旧引用, 旧引用未判, 错误 = 判据基线.读引用基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    旧十干, 错误 = 判据基线.读十干基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    旧台账号, 错误 = 判据基线.读台账号基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    旧底座扩展名, 错误 = 判据基线.读底座扩展名基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    旧禁译名, 错误 = 判据基线.读禁译名基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    旧硬写能力号, 错误 = 判据基线.读硬写能力号基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    判据实测, 错误 = 两半并发(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    差额 = (只许减(旧行数, 判据实测["行数"], True)
            + 只许减(旧运行数据, 判据实测["运行数据"], True)
            + 只许减({键名: 1 for 键名 in 旧引用}, {键名: 1 for 键名 in 判据实测["引用"]}, False)
            # 下面几面**不再**包 `if 旧X else []`：那层包裹在旧基线为空时直接短路放行，
            # 守卫等于零（审计实测：`只许减({}, {"x":1}, True)` 本会拒、被短路放过）。
            # 首冻（旧基线为空 ⇒ 实测全是「新键」）该由维护方**显式**裁决，不许由短路静默放行。
            + 只许减({件名: 1 for 件名 in 旧引用未判},
                    {件名: 1 for 件名 in 判据实测["引用未判"]}, False)
            + 只许减(旧十干, 判据实测["十干"], True)
            + 只许减(旧台账号, 判据实测["台账号"], True, 首冻前缀=面扩首冻前缀)
            + 只许减(旧底座扩展名, 判据实测["底座扩展名"], True)
            + 只许减(旧禁译名, 判据实测["禁译名"], True)
            + 只许减(旧硬写能力号, 判据实测["硬写能力号"], True))
    if 差额:
        print("**拒**（不许靠重冻洗白）：重冻只许**减**，而实测有新增或涨了 ⇒ 先改代码，"
              "或把名登记进库（`信息核心.py 登记 --名字 <名> --语义 <语义> --模式 对象+说明 "
              "--来源 新定义`，只吃具名参）：", file=sys.stderr)
        for 记录条 in 差额[:40]:
            print(f"  {记录条}", file=sys.stderr)
        return 1
    判据基线.写行数基线(树根, 判据实测["行数"])
    判据基线.写运行数据基线(树根, 判据实测["运行数据"])
    判据基线.写引用基线(树根, 判据实测["引用"], 判据实测["引用未判"])
    判据基线.写十干基线(树根, 判据实测["十干"])
    判据基线.写台账号基线(树根, 判据实测["台账号"])
    判据基线.写底座扩展名基线(树根, 判据实测["底座扩展名"])
    判据基线.写禁译名基线(树根, 判据实测["禁译名"])
    判据基线.写硬写能力号基线(树根, 判据实测["硬写能力号"])
    print(f"重冻完成（只许减）：行数基线 {len(旧行数)} → {len(判据实测['行数'])} 条 · "
          f"运行数据基线 {len(旧运行数据)} → {len(判据实测['运行数据'])} 条 · "
          f"引用基线 {len(旧引用)} → {len(判据实测['引用'])} 条 · "
          f"引用未判基线 {len(旧引用未判)} → {len(判据实测['引用未判'])} 条 · "
          f"十干基线 {len(旧十干)} → {len(判据实测['十干'])} 条 · "
          f"台账号基线 {len(旧台账号)} → {len(判据实测['台账号'])} 条 · "
          f"底座扩展名基线 {len(旧底座扩展名)} → {len(判据实测['底座扩展名'])} 条 · "
          f"禁译名基线 {len(旧禁译名)} → {len(判据实测['禁译名'])} 条 · "
          f"硬写能力号基线 {len(旧硬写能力号)} → {len(判据实测['硬写能力号'])} 条")
    return 0
