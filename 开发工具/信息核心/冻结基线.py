import sys
from pathlib import Path

仓根 = Path(__file__).resolve().parents[2]
for _目录 in (str(仓根), str(仓根 / "开发工具"), str(仓根 / "开发工具" / "信息核心"),
             str(仓根 / "构建装配" / "一键验证")):
    if _目录 not in sys.path:
        sys.path.insert(0, _目录)

import 命名基线  # noqa: E402
import 命名穷举  # noqa: E402
from 一键验证 import 判据_命名  # noqa: E402

# ★ 面扩首冻（2026-09-30 · 形状债面扩）：判据 ㉒ 的档 E/F（下划线单字 · 数量代称）原只吃**索引
#   定义面** ⇒ 这两个形状当**形参 / 局部**用时判据看不见（它们是**存量**，不是没债）。本次把这两档
#   的面扩到**形参面 + 局部面**（`判据_命名.数命中` 复用既有扫描器，`只单字=False`）⇒ 实测必然
#   冒出「新键」—— 那是**扩面后现形的存量**，不是新写的债。
#   ⇒ 首冻放行（只此一次）：**该档在旧基线里一条登记都没有**（本次是它的首冻）时，新键允许入基线
#   （承认存量，不是「不算债」）。**已有面仍只许减** —— 首冻落地后该档就有行了，本口子自动闭合，
#   此后该档任何新键都是真「新增即红」。
#   ★ 残余（如实登记）：若某首冻档扩面后实测**仍为零行**，本口子就还开着 ⇒ 那时把该档从 `首冻档`
#     里删掉即闭合（由维护方做）。
首冻档 = (判据_命名.档_下划线单字, 判据_命名.档_数量代称)


def 取实测(树根) -> tuple:
    """两张基线的**实测**读数 ⇒ `({"穷举": {(面,名): 处数}, "六档": {(档,路径,名字): 处数}}, 错误)`。

    两张都走**各自判据的那一份扫描器**（㊷ 走 `命名穷举` · ㉒ 走 `判据_命名.数命中` 与两件面），
    本件不另写一套 —— 否则「冻结的读数」与「判据的读数」会漂成两个数。
    """
    件表 = 命名穷举.读命名件(树根)
    上层读数 = {"仓根": 树根,
              "文件": {路径: {"文本": 文本} for 路径, 文本 in 件表.items()}}
    穷举读数 = 命名穷举.读数(树根, 件表)["未登记"]
    穷举表 = {(面名, 出现名): 记录["处数"]
              for 面名, 面表 in 穷举读数.items()
              for 出现名, 记录 in 面表.items()}
    形参命中, 形参件数 = 判据_命名.数形参单字(上层读数)
    局部命中, 局部件数 = 判据_命名.数局部单字(上层读数)
    # 空集是「扫描器坏了」不是「真没有」—— 那样冻结会把整张基线判成陈旧、一键抹平。
    if not 形参件数 or not 局部件数:
        return {}, ("形参面 %d 件 / 局部面 %d 件 —— 至少一件没扫到函数头或局部绑定，"
                  "扫描器坏了。此时冻结会把整张基线判成陈旧 ⇒ 拒。" % (形参件数, 局部件数))
    六档表 = dict(判据_命名.数命中(上层读数))
    六档表[判据_命名.档_形参单字] = 形参命中
    六档表[判据_命名.档_局部单字] = 局部命中
    return {"穷举": 穷举表,
            "六档": {(档名, *键名): 处数
                   for 档名, 档表 in 六档表.items()
                   for 键名, 处数 in 档表.items()}}, ""


def 只许减(旧基线: dict, 新基线: dict, 比处数: bool, 首冻档: tuple = ()) -> list:
    """实测对基线 ⇒ **新增 / 涨了**的差额说明（空 = 只有减，可以写）。

    `比处数` 跟着**各自判据**走：㉒ 判「违规形状」，多一处就更糟 ⇒ 比；㊷ 判「名有没有定义」，
    债按名记、不按处数记（名可复用）⇒ 不比。守卫若比判据更严，就会出现「判据放行、冻结拒写」
    的两套口径。

    `首冻档` = 本次**面扩首冻**的档（见件头「★ 面扩首冻」）。这些档**在旧基线里一条登记都没有**
    （本次是它的首冻）时，新键放行 —— 那是扩面后现形的**存量**；**已有面仍只许减**（首冻落地后
    该档就有行了，口子自动闭合）。键名的第一格是档名（㉒）或面名（㊷）⇒ 只有 ㉒ 会命中。
    """
    差额 = []
    旧档集 = {键名[0] for 键名 in 旧基线}
    for 键名, 处数 in sorted(新基线.items()):
        登记 = 旧基线.get(键名)
        if 登记 is None:
            if 键名[0] in 首冻档 and 键名[0] not in 旧档集:
                continue
            差额.append(f"新增：{键名}（{处数} 处）")
        elif 比处数 and 处数 > 登记:
            差额.append(f"涨了：{键名}（{登记} → {处数} 处）")
    return 差额


def 冻结(树根) -> int:
    """重冻两张基线（只许减）⇒ 退出码。"""
    旧穷举基线, 错误 = 命名基线.读穷举基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    旧六档基线, 错误 = 命名基线.读命名基线(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    实测, 错误 = 取实测(树根)
    if 错误:
        print(f"拒：{错误}", file=sys.stderr)
        return 1
    差额 = (只许减(旧穷举基线, 实测["穷举"], False)
            + 只许减(旧六档基线, 实测["六档"], True, 首冻档))
    if 差额:
        print("**拒**（不许靠重冻洗白）：重冻只许**减**，而实测有新增或涨了 ⇒ 先改代码，"
              "或把名登记进库（`信息核心.py 登记 <名>`）：", file=sys.stderr)
        for 一条 in 差额[:40]:
            print(f"  {一条}", file=sys.stderr)
        return 1
    命名基线.写穷举基线(树根, 实测["穷举"])
    命名基线.写命名基线(树根, 实测["六档"])
    print(f"重冻完成（只许减）：穷举基线 {len(旧穷举基线)} → {len(实测['穷举'])} 条"
          f"（删陈旧 {len(旧穷举基线) - len(实测['穷举'])}）· 六档基线 {len(旧六档基线)} → "
          f"{len(实测['六档'])} 条（删陈旧 {len(旧六档基线) - len(实测['六档'])}）")
    return 0
