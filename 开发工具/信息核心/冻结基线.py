"""冻结基线 —— 把两张**存量清单**重冻成现状（判据 ㉒ 的六档 · 判据 ㊷ 的三面债清单）。

用法：
    python3 开发工具/信息核心/信息核心.py 冻结基线

**只许减**：重冻只允许「删掉已经归零的登记」—— 任何**新增键**（旧基线里没有的）或**涨了**
（实测处数 > 登记处数）一律拒写，并把差额逐条列出来。理由：基线是「存量不许再长」的闸，
不是白名单；让它自动重冻就等于把闸拆了（判据 ⑲ 先立的那句话：「不许靠重冻洗白」）。
新增债的正确走法：① 改代码，或 ② 把名登记进库（`信息核心.py 登记 <名>`）。

**★ 面扩首冻**（2026-09-30 · 形状债面扩）：把某档的**扫描面**从一处扩到多处（如 ㉒ 的档 E/F
从「索引定义面」扩到「形参面 + 局部面」）⇒ 实测必然冒出「新键」—— 那是**扩面后现形的存量**
（债一直在，只是原先看不见），**不是**新写的债。故 `首冻档` 里的档**在旧基线里一条登记都没有**
（本次是它的首冻）时，新键放行（承认存量，不是「不算债」）。**已有面仍只许减** —— 首冻落地后
该档就有行了，本口子自动闭合：此后该档任何新键都是真「新增即红」。

**为何要有这条命令**：两张基线都住规则库（二进制），手改没有正当路径；而没有它，
每修好一处债就得现写一段一次性脚本 —— 那正是「靠重冻洗白」最容易被做出来的地方。

**两张基线共一个命令**（不拆两条腿）：它们的判据不同，但**写时机与守卫完全一样**
（都在「债修完了」那一刻 · 都只许减）⇒ 拆开只会多一处「只减守卫」的副本。
"""
