# ── 规则一之二：「有没有主人」与「泛不泛」──────────────────────
# 华哥 2026-09-28：「同一个语义的，只需要保留一个。只要精准的。不需要泛指的变量……
# 例如说返回 vs 返回语句。理论上来说，只需要返回语句……不要做泛命名。一定是精准命名」
# ★ 判「泛」的关键不是名短不短，而是**有没有主人**：
#   `号类::类型` 短，但主人（`号类` 枚举）已把语义钉死 ⇒ 精准；
#   `渲染` 短且**无主**（顶层函数）⇒ 泛指，必须写成「渲染<什么>」。
测试件关键词 = ("测试", "test", "案例", "自检", "夹具")


def 有主(限定名: str) -> bool:
    """限定名末段之前还有东西 ⇒ 这名字住在一个类型/模块里，语义由主人定。"""
    for 分隔符 in ("::", "."):
        if 分隔符 in (限定名 or ""):
            return bool(限定名.rsplit(分隔符, 1)[0])
    return False


def 是测试件(文件: str) -> bool:
    return any(关键词 in (文件 or "") for 关键词 in 测试件关键词)


def 按名归件(连接) -> dict:
    """名 → `{件集, 出现位, 种类}`。判「跨件」与「测试/生产」都靠它。"""
    名到记录 = {}
    for 名称, 种类, 限定名, 文件, 行号 in 连接.execute(
        "select 名,种类,限定名,文件,行 from 代码名 where 种类 not in ('import','file')"
    ):
        记录 = 名到记录.setdefault(名称, {"件": set(), "位": [], "种类": 种类})
        记录["件"].add(文件)
        记录["位"].append((种类, 限定名 or "", 文件, 行号))
    return 名到记录


def _无主生产名(名到记录: dict) -> dict:
    """剥掉两档「不是泛指」的：**有主**的（枚举变体/方法）与**只在测试/案例件里**的。"""
    无主名 = {}
    for 名称, 记录 in 名到记录.items():
        if any(有主(限定名) for _种, 限定名, _件, _行 in 记录["位"]):
            continue
        if all(是测试件(件名) for 件名 in 记录["件"]):
            continue
        无主名[名称] = 记录
    return 无主名


def 细化名表(名称: str, 名表: dict) -> list:
    """同类无主名里，**以 `名称` 为正前缀**且不是「加编号」的那些。

    ★ 三个实测过的坑（第一版启发式全踩了）：
    ① 用**子串**匹配 ⇒ `表` 被 `读作废号表` 算成「被细化 56 个」—— 那是**后缀**，不是一个语义两个名。
    ② `错误码_1` ⊂ `错误码_10` ⇒ 那是**编号**（后名紧跟数字），不是细化。
    ③ 例外名（`_`）也在按名归件的表里，但它是语言强加，不管。
    ④ 后名去掉前导下划线后紧跟数字（`命令名` → `命令名_1101`）⇒ 那是**编号实例**，不是细化。
    ⑤ 名本身不算本身的细化（`解析` → `解析`）。
    """
    return sorted((候选名 for 候选名 in 名表
                   if 候选名 != 名称 and 候选名.startswith(名称)
                   and not re.match(r"_?\d", 候选名[len(名称):])),
                  key=lambda 候选名: -名表[候选名])


def 泛名候选(名到记录: dict, 例外: set) -> list:
    """**无主 · 生产**且（被 ≥2 个同类名细化，或**单字**名）⇒ 泛指，该加限定词。

    只卡单字、不卡两字：中文两字词本来就是完整词（`仓根` · `装表` 是精准的），
    华哥要的是**精准**不是**长**（「名字可以长一点问题不大」）。
    返回 `(种类, 名, 件数, 细化数, 细化例)`，被细化多的在前 —— 这就是「梳理」的批次清单。
    """
    按种类 = {}
    for 名称, 记录 in _无主生产名(名到记录).items():
        if 名称 in 例外:
            continue
        按种类.setdefault(记录["种类"], {})[名称] = len(记录["件"])
    候选表 = []
    for 种类, 名表 in 按种类.items():
        for 名称, 件数 in 名表.items():
            细化 = 细化名表(名称, 名表)
            if len(细化) >= 2:
                候选表.append((种类, 名称, 件数, len(细化), " · ".join(细化[:6])))
            elif len(名称) == 1:
                候选表.append((种类, 名称, 件数, 0, "（单字名 —— 中文里几乎必然是泛指）"))
    候选表.sort(key=lambda 一项: (-一项[3], -一项[2], 一项[1]))
    return 候选表


def 同义候选(名到记录: dict, 例外: set, 上限: int = 120) -> list:
    """同 种类 · 都无主 · 一个名是另一个名的**正前缀**（差 ≤3 字）⇒ 很可能一个语义两个名。"""
    按种类 = {}
    for 名称, 记录 in _无主生产名(名到记录).items():
        if 名称 in 例外:
            continue
        按种类.setdefault(记录["种类"], {}).setdefault(名称, len(记录["件"]))
    候选组 = []
    for 种类, 名表 in 按种类.items():
        for 名称 in sorted(名表, key=len):
            for 后名 in 细化名表(名称, 名表):
                if len(名称) >= 2 and len(后名) - len(名称) <= 3:
                    候选组.append((种类, 名称, 后名))
                    if len(候选组) >= 上限:
                        return 候选组
    return 候选组


# ── 规则一之三：归族（类型）───────────────────────────────
# 华哥 2026-09-28：「有定义的，名字相近的，你最好全部整理好类型。」
# 族 = **类型**：同一个族的名共用一个定义、**跨包可复用**。
# 归属用 `search`（不是 `match`）：规则里写 `类型$` 这种尾匹配也要认。
def 归族(名到记录: dict, 族表: tuple, 例外: set) -> dict:
    """每个名归**第一个**命中的族（`命名族` 表的次序 = 从专到泛）。

    返回 `{"各族": [(族名, 定义, 名数, 例), …], "未归": [名, …]}`。
    """
    判据表 = [(族名, re.compile(判据式), 定义) for 族名, 判据式, 定义 in 族表]
    各族名表 = {族名: [] for 族名, _判据式, _定义 in 判据表}
    # 两档不走正则：**例外**按成员判定，**测试用例名**按「只在测试/案例件里出现」判定。
    各族名表["语言强加例外"] = []
    各族名表["测试用例名"] = []
    未归族 = []
    for 名称, 记录 in 名到记录.items():
        if 名称 in 例外:
            各族名表["语言强加例外"].append(名称)
            continue
        if all(是测试件(件名) for 件名 in 记录["件"]):
            各族名表["测试用例名"].append(名称)
            continue
        for 族名, 判据正则, _定义 in 判据表:
            if 判据正则.search(名称):
                各族名表[族名].append(名称)
                break
        else:
            未归族.append(名称)
    各族名表["专名"] = 未归族
    定义表 = {族名: 定义 for 族名, _判据式, 定义 in 判据表}
    定义表["语言强加例外"] = "语言 / 协议 / 工具强加的名（不在命名管辖内）"
    定义表["测试用例名"] = "测试 / 案例的名字 —— 一整句，说清被测面与断言"
    定义表["专名"] = "只此一处的名 —— 没有族，**它本身就是它的类型**（专名）"
    族表 = [(族名, 定义表[族名], len(名表), " · ".join(sorted(名表)[:6]))
            for 族名, 名表 in 各族名表.items() if 名表]
    # 三档不走正则的排到最后（例外 · 测试名 · 专名），前面按名数降序。
    非正则档 = ("语言强加例外", "测试用例名", "专名")
    族表.sort(key=lambda 一项: (一项[0] in 非正则档, -一项[2]))
    return {"各族": 族表, "未归": sorted(未归族)}


def 词性汇总(族表: list, 词性规则: tuple) -> list:
    """把族按**词性**归堆（小学语文那套：动词 / 名词 / 判断 / 量）。

    ★ 华哥 2026-09-28：「他到底是执行动作，还是怎么样的，本质上属于小学语文的类型了。」
    判一个名对不对，先问它**在句子里当什么**：动词名必带宾语（`解析协议值` 成句，
    光杆 `解析` 是语法残缺）；名词名必到具体物（`协议值` 不是 `值`）。
    返回 `[(词性, 判据, 族数, 名数), …]`，次序照 `命名词性` 表。
    """
    词性堆 = {词性: [0, 0] for 词性, _说明, _判据式 in 词性规则}
    for 族名, _定义, 名数, _例 in 族表:
        for 词性, _说明, 判据式 in 词性规则:
            if re.search(判据式, 族名):
                词性堆[词性][0] += 1
                词性堆[词性][1] += 名数
                break
    return [(词性, 说明, 词性堆[词性][0], 词性堆[词性][1])
            for 词性, 说明, _判据式 in 词性规则]


# ── 规则二：契约参数有没有越过定义 ───────────────────────────
def 查契约(连接) -> list:
    类型集 = {标签 for (标签,) in 连接.execute("select 标签 from 类型")}
    越界表 = []
    for 编号, 序号, 名称, 类型, 方向 in 连接.execute(
        "select 编号,序号,名,类型,方向 from 能力参数"
    ):
        if 类型 not in 类型集:
            越界表.append((编号, f"{方向}{序号}", 名称, f"类型标签 {类型} 不在类型表里"))
    for 编号, 能力名, 返回类型 in 连接.execute("select 编号,名称,返回类型 from 能力"):
        if 返回类型 and 返回类型 not in 类型集:
            越界表.append((编号, "返回", 能力名, f"返回类型 {返回类型} 不在类型表里"))
    错误码集 = {码值 for (码值,) in 连接.execute("select 码 from 错误码")}
    for 编号, 能力名, 可抛 in 连接.execute("select 编号,名称,可抛错误码 from 能力"):
        for 码值 in [一项 for 一项 in (可抛 or "").split(",") if 一项]:
            if int(码值) not in 错误码集:
                越界表.append((编号, "可抛错误码", 能力名, f"码 {码值} 不在错误码表里"))
    return 越界表


# ── 规则三：债名落点（命名改名债的仓内 dump）─────────────────
# 命名改名债（库 `未完成` 表 271 号）的落点表此前只在**仓外易失**的临时件里 ⇒ 本命令把它变成
# **仓内可复现**的一条读数：债名 → 逐处 `路径:行` → 顶层区，可按区 / 按名过滤。
# 口径全复用别处：债名 = 库 `命名定义` 的 `现状` 含 `→` 的行（旧名 = `唯一名` 栏）；
# 面 = `命名穷举.读命名件`（与判据 ㊷ 同一份走树）；标识符与位 = `命名扫描.抽标识符带位置`。

def 读债名(连接) -> dict:
    """库 `命名定义` 的 `现状` 含 `→` 的行 ⇒ `{旧名: 新名}`（拆行口径 = 判据 ㊺ 的 `拆禁形`）。"""
    债名表 = {}
    for 语义, 唯一名, 现状 in 连接.execute("select 语义,唯一名,现状 from 命名定义"):
        if "→" not in (现状 or ""):
            continue
        新名 = " · ".join(拆名(现状.split("→", 1)[1]))
        for 旧名 in 拆禁形(现状, 唯一名):
            债名表[旧名] = 新名
    return 债名表


def 扫债名落点(树根, 债名表: dict) -> dict:
    """命名面逐处扫债名 ⇒ `{旧名: [(路径, 行号)]}`（制品产物不进面 —— 与判据 ㊺ 同一条规则）。"""
    落点表 = {}
    for 路径, 文本 in 命名穷举.读命名件(树根).items():
        if 是制品产物(路径):
            continue
        净文本 = 命名扫描.剥后缀("." + 路径.rsplit(".", 1)[-1], 文本)
        for 标识符 in 命名扫描.抽标识符带位置(净文本):
            if 标识符[0] in 债名表:
                落点表.setdefault(标识符[0], []).append(
                    (路径, 净文本.count("\n", 0, 标识符[1]) + 1))
    return {旧名: 落点表[旧名] for 旧名 in 落点表 if 落点表[旧名]}


def 取顶层区(路径: str) -> str:
    """路径的顶层区（第一段目录名）。"""
    return 路径.split("/", 1)[0]


def 取参数值(参数表: list, 旗标: str) -> str:
    """`--区 X` / `--名 X` 的值；旗标不在（或后面没值）⇒ 空串。"""
    if 旗标 in 参数表 and 参数表.index(旗标) + 1 < len(参数表):
        return 参数表[参数表.index(旗标) + 1]
    return ""


def 打印债名落点(债名表: dict, 落点表: dict, 参数表: list) -> int:
    """`--债名落点` 的读数：逐区汇总 + 逐名（名 / 处数 / 区数）；给 `--区` / `--名` 时逐处位置。"""
    区处数 = {}
    for 处表 in 落点表.values():
        for 路径, 行号 in 处表:
            区处数[取顶层区(路径)] = 区处数.get(取顶层区(路径), 0) + 1
    print(f"【债名落点】库 `命名定义.现状` 含 `→` 的债名 {len(债名表)} 个 · "
          f"命名面里真在用 {len(落点表)} 个 · 共 {sum(len(处表) for 处表 in 落点表.values())} 处 · "
          f"{len(区处数)} 区")
    区序 = sorted(区处数, key=区处数.get, reverse=True)
    print("  逐区：" + " · ".join(f"{区名} {区处数[区名]}" for 区名 in 区序))
    只看区 = 取参数值(参数表, "--区")
    只看名 = 取参数值(参数表, "--名")
    if not 只看区 and not 只看名:
        print(f"  （逐名 {len(落点表)} 个，处数降序；要看逐处位置加 `--区 <顶层区>` 或 `--名 <债名>`）")
    名序 = sorted(落点表, key=lambda 旧名: (-len(落点表[旧名]), 旧名))
    for 旧名 in 名序:
        if 只看名 and 旧名 != 只看名:
            continue
        处表 = [(路径, 行号) for 路径, 行号 in sorted(落点表[旧名])
                if not 只看区 or 取顶层区(路径) == 只看区]
        if not 处表:
            continue
        区数 = len({取顶层区(路径) for 路径, 行号 in 落点表[旧名]})
        print(f"    {旧名} → {债名表.get(旧名, '?')}（{len(处表)} 处 · 共 {len(落点表[旧名])} 处 · {区数} 区）")
        if 只看区 or 只看名:
            for 路径, 行号 in 处表:
                print(f"      {路径}:{行号}")
    return 0


# ── 入口 ────────────────────────────────────────────────────────
def 入口函数(参数表: list) -> int:
    连接, 库文件 = 连信息核心库()
    if 连接 is None:
        print(f"库不在：{库文件}\n先跑：python3 开发工具/信息核心/信息核心.py 建库", file=sys.stderr)
        return 1
    if "--债名落点" in 参数表:
        债名表 = 读债名(连接)
        连接.close()
        return 打印债名落点(债名表, 扫债名落点(仓根, 债名表), 参数表)
    红数 = 0
    if not 参数表 or "--命名" in 参数表:
        结果 = 查命名(连接)
        未定义表 = 结果["未定义"]
        print(f"【命名】三面 {结果['总数']} 处 · 逐面出现：{结果['分档']}")
        print(f"  未登记 {len(未定义表)} 个名（其中跨件 {len(结果['跨件未定义'])} 个）· "
              f"逐面名数：{结果['未登记名数']}")
        print("  （穷举口径：出现即须登记 —— 三面 = 定义面 + 形参面 + 局部绑定面。"
              "前 25 个按件数降序）：")
        for 面名, 名称, 件数, 处数, 样例 in 未定义表[:25]:
            print(f"    ✗ 该名没登记：{名称}（{面名} · {件数} 件 · {处数} 处 · 如 {样例}）")
        泛名表 = 结果["泛名"]
        print(f"  其中**无主泛名**（该加限定词）{len(泛名表)} 个 —— 前 15：")
        for 种类, 名称, 件数, 细化数, 细化例 in 泛名表[:15]:
            print(f"    ⚠ {名称}（{种类} · {件数} 件 · 被 {细化数} 个细化）⇒ {细化例 or '（无名细化它，只是名短）'}")
        红数 += len(未定义表)
    if not 参数表 or "--契约" in 参数表:
        越界表 = 查契约(连接)
        print(f"【契约】参数/返回/错误码越界：{len(越界表)} 处")
        for 一条 in 越界表[:25]:
            print(f"    ✗ 能力 {一条[0]} 的{一条[1]}（{一条[2]}）：{一条[3]}")
        红数 += len(越界表)
    连接.close()
    print(f"\n共 {红数} 处红。" if 红数 else "\n无红。")
    return 1 if 红数 else 0
