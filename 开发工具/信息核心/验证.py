# ── 取库 ──────────────────────────────────────────────────────────
def 连信息核心库():
    库文件 = 表定义.库路径(仓根)
    if not 库文件.is_file():
        return None, 库文件
    return sqlite3.connect(库文件), 库文件


# ── 规则一：命名是否存在定义 ──────────────────────────────────
拆名分隔 = re.compile(r"[·、/,]")


def 命名规则(连接):
    """返回 `(唯一名集合, 模式表)`。模式表 = [(种类, 编译后的正则, 说明)]。"""
    唯一名 = set()
    for (单元,) in 连接.execute("select 唯一名 from 命名定义"):
        for 一项 in 拆名分隔.split(单元 or ""):
            一项 = 一项.strip().strip("`")
            if 一项:
                唯一名.add(一项)
    # 模式表读**库**（不读 `表定义`）—— 页面与判据读同一张，不各拿一份。
    模式 = [(种类, re.compile(正则式), 例文)
            for 种类, 正则式, 例文 in 连接.execute("select 种类,模式,例 from 命名模式")]
    return 唯一名, 模式


def 是定义内名(名称: str, 唯一名: set, 模式: list) -> str:
    """返回定义来源：`唯一名` / `模式:<种类>` / `例外` / `未定义`。"""
    if not 名称:
        return "未定义"
    if 名称 in 唯一名:
        return "唯一名"
    if 名称 in 表定义.命名例外:
        return "例外"
    for 种类, 正则, _说明 in 模式:
        if 正则.match(名称):
            return f"模式:{种类}"
    return "未定义"


def 查命名(连接) -> dict:
    """**穷举口径**：出现即须定义，未定义即红（华哥 2026-09-28）。

    「只要出现的，必须就 100% 的定义，没定义直接爆红」—— 私有名与局部名同样管。
    `跨件未定义`（≥2 件同名却无定义）单独列出，因为它是「同义多名」的真漂移，最该先改；
    但**红的总数 = 全部未定义**，不是只算跨件的。
    """
    唯一名, 模式 = 命名规则(连接)
    按来源计数, 按名 = {}, {}
    总数 = 0
    # `import` 是模块路径（`.` · `./剪辑历史.js`），`file` 是件名 —— 两者都不是标识符，不归命名管。
    for 名称, 种类, 语言, 限定名, 文件, 行号 in 连接.execute(
        "select 名,种类,语言,限定名,文件,行 from 代码名 where 种类 not in ('import','file')"
    ):
        总数 += 1
        来源 = 是定义内名(名称, 唯一名, 模式)
        按来源计数[来源.split(":")[0]] = 按来源计数.get(来源.split(":")[0], 0) + 1
        if 来源 == "未定义":
            按名.setdefault(名称, {"件": set(), "种类": 种类, "样例": f"{文件}:{行号}"})
            按名[名称]["件"].add(文件)
    未定义 = [(名称, len(记录["件"]), 记录["种类"], 记录["样例"])
              for 名称, 记录 in 按名.items()]
    未定义.sort(key=lambda 一项: (-一项[1], 一项[0]))
    跨件 = [一项 for 一项 in 未定义 if 一项[1] >= 2]
    名到记录 = 按名归件(连接)
    return {"总数": 总数, "分档": 按来源计数, "未定义": 未定义,
            "跨件未定义": 跨件, "单件未定义": len(未定义) - len(跨件),
            "归": 名到记录, "泛名": 泛名候选(名到记录)}


# ── 规则一之二：「有没有主人」与「泛不泛」──────────────────────
# 华哥 2026-09-28：「同一个语义的，只需要保留一个。只要精准的。不需要泛指的变量……
# 例如说返回 vs 返回语句。理论上来说，只需要返回语句……不要做泛命名。一定是精准命名」
# ★ 判「泛」的关键不是名短不短，而是**有没有主人**：
#   `号类::类型` 短，但主人（`号类` 枚举）已把语义钉死 ⇒ 精准；
#   `渲染` 短且**无主**（顶层函数）⇒ 泛指，必须写成「渲染<什么>」。
测试件关键词 = ("测试", "test", "案例", "自检", "夹具")


def 有主(限定名: str) -> bool:
    """限定名末段之前还有东西 ⇒ 这名字住在一个类型/模块里，语义由主人定。"""
    for 分隔符 in ("::", "."):
        if 分隔符 in (限定名 or ""):
            return bool(限定名.rsplit(分隔符, 1)[0])
    return False


def 是测试件(文件: str) -> bool:
    return any(关键词 in (文件 or "") for 关键词 in 测试件关键词)


def 按名归件(连接) -> dict:
    """名 → `{件集, 出现位, 种类}`。判「跨件」与「测试/生产」都靠它。"""
    名到记录 = {}
    for 名称, 种类, 限定名, 文件, 行号 in 连接.execute(
        "select 名,种类,限定名,文件,行 from 代码名 where 种类 not in ('import','file')"
    ):
        记录 = 名到记录.setdefault(名称, {"件": set(), "位": [], "种类": 种类})
        记录["件"].add(文件)
        记录["位"].append((种类, 限定名 or "", 文件, 行号))
    return 名到记录


def _无主生产名(名到记录: dict) -> dict:
    """剥掉两档「不是泛指」的：**有主**的（枚举变体/方法）与**只在测试/案例件里**的。"""
    无主名 = {}
    for 名称, 记录 in 名到记录.items():
        if any(有主(限定名) for _种, 限定名, _件, _行 in 记录["位"]):
            continue
        if all(是测试件(件名) for 件名 in 记录["件"]):
            continue
        无主名[名称] = 记录
    return 无主名


def 被细化(名称: str, 名表: dict) -> list:
    """同类无主名里，**以 `名称` 为正前缀**且不是「加编号」的那些。

    ★ 三个实测过的坑（第一版启发式全踩了）：
    ① 用**子串**匹配 ⇒ `表` 被 `读作废号表` 算成「被细化 56 个」—— 那是**后缀**，不是一个语义两个名。
    ② `错误码_1` ⊂ `错误码_10` ⇒ 那是**编号**（后名紧跟数字），不是细化。
    ③ 例外名（`_`）也在按名归件的表里，但它是语言强加，不管。
    ④ 后名去掉前导下划线后紧跟数字（`命令名` → `命令名_1101`）⇒ 那是**编号实例**，不是细化。
    ⑤ 名本身不算本身的细化（`解析` → `解析`）。
    """
    return sorted((候选名 for 候选名 in 名表
                   if 候选名 != 名称 and 候选名.startswith(名称)
                   and not re.match(r"_?\d", 候选名[len(名称):])),
                  key=lambda 候选名: -名表[候选名])


def 泛名候选(名到记录: dict) -> list:
    """**无主 · 生产**且（被 ≥2 个同类名细化，或**单字**名）⇒ 泛指，该加限定词。

    只卡单字、不卡两字：中文两字词本来就是完整词（`仓根` · `装表` 是精准的），
    华哥要的是**精准**不是**长**（「名字可以长一点问题不大」）。
    返回 `(种类, 名, 件数, 细化数, 细化例)`，被细化多的在前 —— 这就是「梳理」的批次清单。
    """
    按种类 = {}
    for 名称, 记录 in _无主生产名(名到记录).items():
        if 名称 in 表定义.命名例外:
            continue
        按种类.setdefault(记录["种类"], {})[名称] = len(记录["件"])
    候选表 = []
    for 种类, 名表 in 按种类.items():
        for 名称, 件数 in 名表.items():
            细化 = 被细化(名称, 名表)
            if len(细化) >= 2:
                候选表.append((种类, 名称, 件数, len(细化), " · ".join(细化[:6])))
            elif len(名称) == 1:
                候选表.append((种类, 名称, 件数, 0, "（单字名 —— 中文里几乎必然是泛指）"))
    候选表.sort(key=lambda 一项: (-一项[3], -一项[2], 一项[1]))
    return 候选表


def 同义候选(名到记录: dict, 上限: int = 120) -> list:
    """同 种类 · 都无主 · 一个名是另一个名的**正前缀**（差 ≤3 字）⇒ 很可能一个语义两个名。"""
    按种类 = {}
    for 名称, 记录 in _无主生产名(名到记录).items():
        if 名称 in 表定义.命名例外:
            continue
        按种类.setdefault(记录["种类"], {}).setdefault(名称, len(记录["件"]))
    候选组 = []
    for 种类, 名表 in 按种类.items():
        for 名称 in sorted(名表, key=len):
            for 后名 in 被细化(名称, 名表):
                if len(名称) >= 2 and len(后名) - len(名称) <= 3:
                    候选组.append((种类, 名称, 后名))
                    if len(候选组) >= 上限:
                        return 候选组
    return 候选组


# ── 规则二：契约参数有没有越过定义 ───────────────────────────
def 查契约(连接) -> list:
    类型集 = {标签 for (标签,) in 连接.execute("select 标签 from 类型")}
    越界表 = []
    for 编号, 序号, 名称, 类型, 方向 in 连接.execute(
        "select 编号,序号,名,类型,方向 from 能力参数"
    ):
        if 类型 not in 类型集:
            越界表.append((编号, f"{方向}{序号}", 名称, f"类型标签 {类型} 不在类型表里"))
    for 编号, 能力名, 返回类型 in 连接.execute("select 编号,名称,返回类型 from 能力"):
        if 返回类型 and 返回类型 not in 类型集:
            越界表.append((编号, "返回", 能力名, f"返回类型 {返回类型} 不在类型表里"))
    错误码集 = {码值 for (码值,) in 连接.execute("select 码 from 错误码")}
    for 编号, 能力名, 可抛 in 连接.execute("select 编号,名称,可抛错误码 from 能力"):
        for 码值 in [一项 for 一项 in (可抛 or "").split(",") if 一项]:
            if int(码值) not in 错误码集:
                越界表.append((编号, "可抛错误码", 能力名, f"码 {码值} 不在错误码表里"))
    return 越界表


# ── 入口 ──────────────────────────────────────────────────────────
def 入口函数(参数: list) -> int:
    连接, 库文件 = 连信息核心库()
    if 连接 is None:
        print(f"库不在：{库文件}\n先跑：python3 开发工具/信息核心/建库.py", file=sys.stderr)
        return 1
    红数 = 0
    if not 参数 or "--命名" in 参数:
        结果 = 查命名(连接)
        未定义表 = 结果["未定义"]
        print(f"【命名】扫描 {结果['总数']} 个代码名 · 分档：{结果['分档']}")
        print(f"  未定义 {len(未定义表)} 个唯一名（其中跨件 {len(结果['跨件未定义'])} 个）")
        print("  （穷举口径：出现即须定义 —— 扫描面 = 索引定义面，**不含形参/局部**。前 25 个按件数降序）：")
        for 名称, 件数, 种类, 样例 in 未定义表[:25]:
            print(f"    ✗ 该名不存在定义：{名称}（{件数} 件 · {种类} · 如 {样例}）")
        泛名表 = 结果["泛名"]
        print(f"  其中**无主泛名**（该加限定词）{len(泛名表)} 个 —— 前 15：")
        for 种类, 名称, 件数, 细化数, 细化例 in 泛名表[:15]:
            print(f"    ⚠ {名称}（{种类} · {件数} 件 · 被 {细化数} 个细化）⇒ {细化例 or '（无名细化它，只是名短）'}")
        红数 += len(未定义表)
    if not 参数 or "--契约" in 参数:
        越界表 = 查契约(连接)
        print(f"【契约】参数/返回/错误码越界：{len(越界表)} 处")
        for 一条 in 越界表[:25]:
            print(f"    ✗ 能力 {一条[0]} 的{一条[1]}（{一条[2]}）：{一条[3]}")
        红数 += len(越界表)
    连接.close()
    print(f"\n共 {红数} 处红。" if 红数 else "\n无红。")
    return 1 if 红数 else 0
