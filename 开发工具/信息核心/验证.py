"""信息核心 · 验证 —— 批量走**库规则**，不靠 agent 自觉。

华哥 2026-09-28：「验证器，直接批量走 db 规则去验证。例如说命名是否存在，纯靠 agent 自觉，
肯定会漂移。直接一个调用代码地图，拆解函数或者变量命名，然后一个对比脚本，库里面这个变量是否
存在定义，不存在定义的直接返回，该变量不存在。」

用法：
    python3 开发工具/信息核心/验证.py            # 全跑，打读数
    python3 开发工具/信息核心/验证.py --命名      # 只跑命名
    python3 开发工具/信息核心/验证.py --契约      # 只跑契约参数越界

退出码：0 = 无红；1 = 有红。
"""
import re
import sqlite3
import sys
import time
from pathlib import Path

起始时刻 = time.monotonic()
仓根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(仓根))
sys.path.insert(0, str(仓根 / "开发工具"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import 表定义  # noqa: E402


# ── 取库 ──────────────────────────────────────────────────────────
def 连库():
    库文件 = 表定义.库路径(仓根)
    if not 库文件.is_file():
        return None, 库文件
    return sqlite3.connect(库文件), 库文件


# ── 规则一：命名是否存在定义 ──────────────────────────────────
拆名分隔 = re.compile(r"[·、/,]")


def 命名规则(连接):
    """返回 `(唯一名集合, 模式表)`。模式表 = [(种类, 编译后的正则, 说明)]。"""
    唯一名 = set()
    for (单元,) in 连接.execute("select 唯一名 from 命名定义"):
        for 一项 in 拆名分隔.split(单元 or ""):
            一项 = 一项.strip().strip("`")
            if 一项:
                唯一名.add(一项)
    # 模式表读**库**（不读 `表定义`）—— 页面与判据读同一张，不各拿一份。
    模式 = [(种类, re.compile(正则式), 例文)
            for 种类, 正则式, 例文 in 连接.execute("select 种类,模式,例 from 命名模式")]
    return 唯一名, 模式


def 是定义内名(名称: str, 唯一名: set, 模式: list) -> str:
    """返回定义来源：`唯一名` / `模式:<种类>` / `例外` / `未定义`。"""
    if not 名称:
        return "未定义"
    if 名称 in 唯一名:
        return "唯一名"
    if 名称 in 表定义.命名例外:
        return "例外"
    for 种类, 正则, _说明 in 模式:
        if 正则.match(名称):
            return f"模式:{种类}"
    return "未定义"


def 查命名(连接) -> dict:
    """**穷举口径**：出现即须定义，未定义即红（华哥 2026-09-28）。

    「只要出现的，必须就 100% 的定义，没定义直接爆红」—— 私有名与局部名同样管。
    `跨件未定义`（≥2 件同名却无定义）单独列出，因为它是「同义多名」的真漂移，最该先改；
    但**红的总数 = 全部未定义**，不是只算跨件的。
    """
    唯一名, 模式 = 命名规则(连接)
    分档, 按名 = {}, {}
    总数 = 0
    # `import` 是模块路径（`.` · `./剪辑历史.js`），`file` 是件名 —— 两者都不是标识符，不归命名管。
    for 名称, 种类, 语言, 限定名, 文件, 行号 in 连接.execute(
        "select 名,种类,语言,限定名,文件,行 from 代码名 where 种类 not in ('import','file')"
    ):
        总数 += 1
        来源 = 是定义内名(名称, 唯一名, 模式)
        分档[来源.split(":")[0]] = 分档.get(来源.split(":")[0], 0) + 1
        if 来源 == "未定义":
            按名.setdefault(名称, {"件": set(), "种类": 种类, "样例": f"{文件}:{行号}"})
            按名[名称]["件"].add(文件)
    未定义 = [(名称, len(记录["件"]), 记录["种类"], 记录["样例"])
              for 名称, 记录 in 按名.items()]
    未定义.sort(key=lambda 一项: (-一项[1], 一项[0]))
    跨件 = [一项 for 一项 in 未定义 if 一项[1] >= 2]
    return {"总数": 总数, "分档": 分档, "未定义": 未定义,
            "跨件未定义": 跨件, "单件未定义": len(未定义) - len(跨件)}


# ── 规则二：契约参数有没有越过定义 ───────────────────────────
def 查契约(连接) -> list:
    类型集 = {标签 for (标签,) in 连接.execute("select 标签 from 类型")}
    越界表 = []
    for 编号, 序号, 名称, 类型, 方向 in 连接.execute(
        "select 编号,序号,名,类型,方向 from 能力参数"
    ):
        if 类型 not in 类型集:
            越界表.append((编号, f"{方向}{序号}", 名称, f"类型标签 {类型} 不在类型表里"))
    for 编号, 能力名, 返回类型 in 连接.execute("select 编号,名称,返回类型 from 能力"):
        if 返回类型 and 返回类型 not in 类型集:
            越界表.append((编号, "返回", 能力名, f"返回类型 {返回类型} 不在类型表里"))
    错误码集 = {码值 for (码值,) in 连接.execute("select 码 from 错误码")}
    for 编号, 能力名, 可抛 in 连接.execute("select 编号,名称,可抛错误码 from 能力"):
        for 码值 in [一项 for 一项 in (可抛 or "").split(",") if 一项]:
            if int(码值) not in 错误码集:
                越界表.append((编号, "可抛错误码", 能力名, f"码 {码值} 不在错误码表里"))
    return 越界表


# ── 入口 ──────────────────────────────────────────────────────────
def 入口函数(参数: list) -> int:
    连接, 库文件 = 连库()
    if 连接 is None:
        print(f"库不在：{库文件}\n先跑：python3 开发工具/信息核心/建库.py", file=sys.stderr)
        return 1
    红数 = 0
    if not 参数 or "--命名" in 参数:
        结果 = 查命名(连接)
        未定义表 = 结果["未定义"]
        print(f"【命名】扫描 {结果['总数']} 个代码名 · 分档：{结果['分档']}")
        print(f"  未定义 {len(未定义表)} 个唯一名（其中跨件 {len(结果['跨件未定义'])} 个）")
        print("  （穷举口径：出现即须定义；私有名与局部名同样管。前 25 个按件数降序）：")
        for 名称, 件数, 种类, 样例 in 未定义表[:25]:
            print(f"    ✗ 该名不存在定义：{名称}（{件数} 件 · {种类} · 如 {样例}）")
        红数 += len(未定义表)
    if not 参数 or "--契约" in 参数:
        越界表 = 查契约(连接)
        print(f"【契约】参数/返回/错误码越界：{len(越界表)} 处")
        for 一条 in 越界表[:25]:
            print(f"    ✗ 能力 {一条[0]} 的{一条[1]}（{一条[2]}）：{一条[3]}")
        红数 += len(越界表)
    连接.close()
    print(f"\n共 {红数} 处红。" if 红数 else "\n无红。")
    return 1 if 红数 else 0
