# -*- coding: utf-8 -*-
"""代码地图 · 查询 —— 在**索引库**上做「谁定义了它」与「它还在哪被用」。

**三种语言同一套口径**：索引器（codegraph，tree-sitter）给的是**真解析器**的标识符，
不是文本匹配 —— 所以答得出「这两处是不是同一个符号」，而不只是「哪几行有这个字」。

**渲染也归包里**（`查符号行` / `引用行` / `状态行`）：入口件零实现，只有命令分发。
"""

import hashlib
import os
from pathlib import Path

from .落点 import 仓根, 库目录名, 库文件名, 库路径
from .索引库 import 全部定义, 出现位, 有库, 库读数, 索引陈旧

定义记录键 = ("名字", "限定名", "种类", "声明", "路径", "行", "列", "末行", "出现数")


def 可读说明(根目录=None, 库路径=None) -> str:
    """索引库比源件旧 / 不在 ⇒ 一行可读提示（空 = 新鲜）。

    口径**只此一份**：复用 `索引库.索引陈旧`（判据 ㉒/㊷ 同调它）—— 本函数只做
    「查哪棵树 + 拼成一行」。`根目录` 给了就用它；否则从 `库路径`
    （`<根>/.codegraph/codegraph.db`）反推；都没有 ⇒ 主工作树 `仓根`。
    """
    from .形参面 import 遍历命名件

    if 根目录 is None:
        if (库路径 is not None and Path(库路径).name == 库文件名
                and Path(库路径).parent.name == 库目录名):
            根目录 = Path(库路径).parent.parent
        else:
            根目录 = 仓根
    根目录 = Path(根目录)
    件表 = {os.path.relpath(绝对路径, str(根目录)): "" for 绝对路径 in 遍历命名件(str(根目录))}
    索引状态, 说明 = 索引陈旧(根目录, 件表)
    if 索引状态:
        return "★ 索引陈旧：%s ⇒ 先跑 `python3 开发工具/代码地图.py 建`（行号 / 出现位可能过时）" % 说明
    return ""


def 文件指纹(相对路径: str, 根目录=None) -> str:
    """该件的**内容指纹**（sha256 前 16 位十六进制）。

    ★ **现算、不落库**：它是给写操作做 CAS 的（「我看到的还是不是那一版」），
    必须**只由文件内容决定** —— 索引器库里的 `content_hash` 是它自带的算法、且改完件要重刷才更新
    ⇒ 不能当指纹用（写完的那一刻它必然过期）。
    """
    件路径 = Path(相对路径)
    if not 件路径.is_absolute():
        件路径 = (根目录 or 仓根) / 件路径
    try:
        return hashlib.sha256(件路径.read_bytes()).hexdigest()[:16]
    except OSError:
        return ""


def 查符号(关键词: str, 结果上限: int = 40, 库路径=None, 根目录=None) -> dict:
    """按**短名 / 限定名 / 声明 / 路径**子串查定义 ⇒ `{"命中": [...], "扫过": n, "总数": n}`。

    每条命中带**起止行**（`行` / `末行`）与**文件指纹**（`指纹`，现算）——
    这两个是写操作要的：起止行直接填 `开始行` / `结束行`，指纹用于指纹闸拒了之后重新对齐。
    """
    定义表 = 全部定义(库路径)
    if not 定义表:
        读数 = 库读数(库路径)
        if 读数.get("错误"):
            return {"命中": [], "扫过": 0, "总数": 0, "错误": 读数["错误"]}
    命中表 = [定义记录 for 定义记录 in 定义表
            if (关键词 in 定义记录["名字"] or 关键词 in 定义记录["限定名"]
                or 关键词 in 定义记录["声明"] or 关键词 in 定义记录["路径"])]
    # 精确命中的排前面（改名前先看「就是这个符号」）
    命中表.sort(key=lambda 定义记录: (定义记录["限定名"] != 关键词,
                                 定义记录["路径"], 定义记录["行"]))
    命中数 = len(命中表)
    命中表 = 命中表[:结果上限]
    指纹表: dict = {}                       # 同一件只读一次
    for 定义记录 in 命中表:
        件路径 = 定义记录["路径"]
        if 件路径 not in 指纹表:
            指纹表[件路径] = 文件指纹(件路径, 根目录)
        定义记录["指纹"] = 指纹表[件路径]
    查询读数 = {"命中": 命中表, "扫过": len(定义表), "总数": 命中数}
    提示语 = 可读说明(根目录=根目录, 库路径=库路径)
    if 提示语:
        查询读数["索引陈旧"] = 提示语
    return 查询读数


def 出现位置(键名: str, 结果上限: int = 0, 库路径=None) -> dict:
    """该符号的全部出现位置 ⇒ `{"位置": [(路径, 行, 列)…], "总数": n, "口径": "…"}`（**带列**）。

    列是**字符下标**（codegraph 的口径），写操作按它定点换。口径说明见 `索引库.出现位`。
    """
    查询读数 = 出现位(键名, 结果上限, 库路径)
    提示语 = 可读说明(库路径=库路径)
    if 提示语:
        查询读数["口径"] = "%s ｜ %s" % (查询读数["口径"], 提示语)
    return 查询读数


def 查引用(键名: str, 结果上限: int = 400, 库路径=None) -> dict:
    """找该符号的全部出现（定义处也算）⇒ `{"按文件": {路径: [行…]}, "总数": n, "口径": "…"}`。"""
    出现结果 = 出现位置(键名, 结果上限=结果上限, 库路径=库路径)
    按文件行号表: dict = {}
    for 文件路径, 行号, _ in 出现结果["位置"]:
        按文件行号表.setdefault(文件路径, []).append(行号)
    return {"按文件": 按文件行号表, "总数": 出现结果["总数"],
            "截断": 出现结果["总数"] > len(出现结果["位置"]), "口径": 出现结果["口径"]}


# ── 渲染 ────────────────────────────────────────────────────────────────────────────────

def 查符号行(关键词: str) -> list:
    """`查符号` 的结果渲染成几行给人读的字（**入口零实现**：渲染也归包里）。

    带**起止行**与**文件指纹** —— 这两个是喂写操作的：起止行直接填 `开始行` / `结束行`，
    指纹用于指纹闸拒了之后重新对齐。
    """
    查询结果 = 查符号(关键词)
    if 查询结果.get("错误"):
        return ["**%s**" % 查询结果["错误"]]
    输出行表 = ["命中 %d 个定义（扫过 %d 条）" % (查询结果["总数"], 查询结果["扫过"])]
    for 定义记录 in 查询结果["命中"]:
        输出行表.append("  %-46s %-10s %s:%d–%d  [出现 %d 处]  指纹 %s" % (
            定义记录["限定名"], 定义记录["种类"] or "—", 定义记录["路径"],
            定义记录["行"], 定义记录["末行"] or 定义记录["行"],
            定义记录["出现数"], 定义记录.get("指纹", "")))
    if 查询结果["总数"] > len(查询结果["命中"]):
        输出行表.append("  …（还有 %d 个，加关键词收窄）"
                     % (查询结果["总数"] - len(查询结果["命中"])))
    if 查询结果.get("索引陈旧"):
        输出行表.append("  " + 查询结果["索引陈旧"])
    return 输出行表


def 引用行(键名: str) -> list:
    """`引用` 的结果渲染成几行给人读的字。"""
    引用结果 = 查引用(键名)
    输出行表 = ["出现 %d 处（口径：%s）" % (引用结果["总数"], 引用结果["口径"])]
    for 文件路径 in sorted(引用结果["按文件"]):
        去重行号表 = sorted(set(引用结果["按文件"][文件路径]))
        输出行表.append("  %-56s %s" % (
            文件路径, " ".join(str(行号) for 行号 in 去重行号表[:24])))
    return 输出行表


def 状态行() -> list:
    """索引库在不在、多大、几个节点 —— 几行给人读的字。"""
    if not 有库():
        return ["代码地图：还没有索引库 ⇒ 先跑 `python3 开发工具/代码地图.py 建`",
                "  落点 %s" % 库路径()]
    读数 = 库读数()
    if 读数.get("错误"):
        return ["代码地图 · 索引库：%s" % 库路径(), "  **%s**" % 读数["错误"]]
    输出行表 = [
        "代码地图 · 索引库：%s" % 库路径(),
        "  %d 节点 · %d 边 · %d 件（索引器 %s）· %d 字节" % (
            读数["节点"], 读数["边"], 读数["件"], 读数["索引器版本"] or "—",
            库路径().stat().st_size),
    ]
    提示语 = 可读说明()
    if 提示语:
        输出行表.append("  " + 提示语)
    return 输出行表
