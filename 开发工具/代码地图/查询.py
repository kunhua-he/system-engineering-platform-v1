# -*- coding: utf-8 -*-
"""代码地图 · 查询 —— 在**统一索引**上做「谁定义了它」与「它还在哪被用」。

**为什么是流式扫而不是全load**：索引实测 1.6 万定义 + 12 万出现（合计约 20 MB）。
一次 `json.loads` 全load 要 ~1 s 且吃内存；而**逐行扫 + 过滤**只要 ~0.2 s 且常驻内存近乎零
（本仓五秒硬顶：`查`/`引用` 是判顶对象）。这也是为什么索引落 **JSONL** 而不是一个大 JSON 数组。

**三种语言同一套口径**（SCIP 给的，不是自研推的）：每条记录都带 **`限定名`** ——
它由符号串唯一决定（`SCIP前端.拆符号` 是纯函数），所以 `引用 <限定名>` 是**精确**的：
答得出「这两处是不是同一个符号」，而不只是「哪几行有这个字」。跨模块同名不再混。
"""

import json

from .落点 import 出现路径, 定义路径


def _逐行(路) -> list:
    if not 路.is_file():
        return []
    with 路.open(encoding="utf-8") as 文:
        for 行 in 文:
            if 行.strip():
                yield json.loads(行)


def 查(关键词: str, 上限: int = 40) -> dict:
    """按**短名 / 限定名 / 声明 / 路径**子串查定义 ⇒ `{"命中": [...], "扫过": n, "总数": n}`。"""
    出, 扫 = [], 0
    for 条 in _逐行(定义路径()):
        扫 += 1
        if (关键词 in 条.get("名字", "") or 关键词 in 条.get("限定名", "")
                or 关键词 in 条.get("声明", "") or 关键词 in 条.get("路径", "")):
            出.append(条)
    # 精确命中的排前面（改名前先看「就是这个符号」）
    出.sort(key=lambda 条: (条.get("限定名", "") != 关键词, 条.get("路径", ""), 条.get("行", 0)))
    return {"命中": 出[:上限], "扫过": 扫, "总数": len(出)}


def 出现位置(键: str, 上限: int = 0) -> dict:
    """该符号的**全部出现位置** ⇒ `{"位置": [(路, 行, 列)…], "总数": n, "口径": "…"}`。

    `上限=0` 表示不限（`替换` 要的就是全量 —— 截断会让它漏改）。**带列**，因为列是
    UTF-16 列（SCIP 的 `position_encoding`），符号级替换要靠它。
    **口径**：先按 `限定名` **全等**找（精确，SCIP 符号级）；一条都没有才退回按 `名字` 全等
    （名字级 —— 会混进同名不同符号）。用的是哪一种，如实写在返回的 `口径` 里。
    """
    for 键名, 口径 in (("限定名", "限定名（精确）"), ("名字", "名字（同名不同符号会混进来）")):
        位置, 总数 = [], 0
        for 条 in _逐行(出现路径()):
            if 条.get(键名) != 键:
                continue
            总数 += 1
            if not 上限 or 总数 <= 上限:
                位置.append((条.get("路径", ""), 条.get("行", 0), 条.get("列", 0)))
        if 总数:
            return {"位置": 位置, "总数": 总数, "口径": 口径}
    return {"位置": [], "总数": 0, "口径": "没找到"}


def 引用(键: str, 上限: int = 400) -> dict:
    """找该符号的全部出现（定义处也算）⇒ `{"按文件": {路径: [行…]}, "总数": n, "口径": "…"}`。"""
    果 = 出现位置(键, 上限=上限)
    按件: dict = {}
    for 路, 行, _ in 果["位置"]:
        按件.setdefault(路, []).append(行)
    return {"按文件": 按件, "总数": 果["总数"], "截断": 果["总数"] > len(果["位置"]),
            "口径": 果["口径"]}


def 查行(键: str) -> list:
    """`查` 的结果渲染成几行给人读的字（**入口零实现**：渲染也归包里）。"""
    果 = 查(键)
    出 = ["命中 %d 个定义（扫过 %d 条）" % (果["总数"], 果["扫过"])]
    for 条 in 果["命中"]:
        出.append("  %-46s %-10s %s:%d:%d  [出现 %d 处]" % (
            条["限定名"], 条["种类"] or "—", 条["路径"], 条["行"], 条["列"], 条["出现数"]))
    if 果["总数"] > len(果["命中"]):
        出.append("  …（还有 %d 个，加关键词收窄）" % (果["总数"] - len(果["命中"])))
    return 出


def 引用行(键: str) -> list:
    """`引用` 的结果渲染成几行给人读的字。"""
    果 = 引用(键)
    出 = ["出现 %d 处（口径：%s）" % (果["总数"], 果["口径"])]
    for 路 in sorted(果["按文件"]):
        行表 = sorted(set(果["按文件"][路]))
        出.append("  %-56s %s" % (路, " ".join(str(行) for 行 in 行表[:24])))
    return 出


def 状态行(状: dict) -> list:
    """把 `索引状态()` 变成几行给人读的字。"""
    if not 状["有"]:
        return ["代码地图：还没有统一索引 ⇒ 先跑 `python3 开发工具/代码地图.py 建`",
                "  落点 %s" % 状["路径"]]
    腿 = " · ".join(
        "%s %s" % (键, ("%d 字节" % 条["字节"]) if 条["有"] else "**没跑**")
        for 键, 条 in (状.get("原始") or {}).items())
    return [
        "代码地图 · 索引：%s" % 状["路径"],
        "  定义 %d 字节 · 出现 %d 字节 · 合计 %d 字节" % (
            状["定义"].get("字节", 0), 状["出现"].get("字节", 0), 状["字节"]),
        "  三条腿的原始 .scip：%s" % 腿,
    ]
