def 库身份(库件) -> tuple:
    """库文件身份 `(dev, ino, size, mtime_ns)` —— 读不出 ⇒ `()`（一律不记忆）。"""
    try:
        读数 = 库件.stat()
    except OSError:
        return ()
    return (读数.st_dev, 读数.st_ino, 读数.st_size, 读数.st_mtime_ns)


def 读库健康(库件, 读不动模板) -> dict:
    """库**自身**的健康读数：必要表 / `pragma integrity_check` / `files` 表。

    ⇒ `{"损坏说明", "索引路径表"}` —— `损坏说明` 非空即损坏（**已套好 `读不动模板`**，
    文案与旧版逐字一致）；空串即健康，此时 `索引路径表` 才可用。

    ★ **只答「这个库件有没有坏」，不答新鲜度** —— 新鲜度取决于源件，归 `查索引状态`。
    """
    索引路径表: dict = {}
    try:
        动态库 = 连库(库件)
    except sqlite3.Error as 失败原因:
        return {"损坏说明": 读不动模板 % 失败原因, "索引路径表": 索引路径表}
    try:
        try:
            必要表 = {表行[0] for 表行 in 动态库.execute(
                "select name from sqlite_master where type='table' and name in ('nodes','edges','files')")}
            if 必要表 != {"nodes", "edges", "files"}:
                缺表 = "、".join(sorted({"nodes", "edges", "files"} - 必要表))
                return {"损坏说明": "%s；缺少索引表：%s" % (读不动模板 % "schema 不完整", 缺表),
                        "索引路径表": 索引路径表}
            完整性 = 动态库.execute("pragma integrity_check").fetchone()
            if not 完整性 or 完整性[0] != "ok":
                return {"损坏说明": "%s；完整性检查：%s" % (
                    读不动模板 % "sqlite 完整性失败", 完整性[0] if 完整性 else "无回执"),
                    "索引路径表": 索引路径表}
            索引路径表 = {表行[0]: 表行[1] for 表行 in 动态库.execute("select path, modified_at from files")}
        except sqlite3.Error as 失败原因:
            return {"损坏说明": 读不动模板 % 失败原因, "索引路径表": {}}
    finally:
        动态库.close()
    return {"损坏说明": "", "索引路径表": 索引路径表}


# ★ **库健康读数按库文件身份记忆**（提速）：`pragma integrity_check` 在 40 MB 库上要 152–166 ms，
#   而 `查索引状态` 是**每次**都跑的热路（工具 · CLI · `v1_context` 三处共用它这一份口径）。
#   身份（dev/ino/size/mtime_ns）未变 ⇒ 库内容未变 ⇒ 健康结论与 `files` 表读数可复用。
#   **源件新鲜度仍每次现算** —— 它取决于源件、不由库身份保护；连它一起记就是假绿。
_健康记忆: dict = {}


def 查索引状态(根目录=None, 库路径=None) -> dict:
    """索引库的存在 / 完整性 / 覆盖 / 新鲜度 ⇒ `{"状态","说明","错误","警告","覆盖"}`。

    **口径只此一份**（工具 · CLI · 上下文共用）。`状态` ∈ 缺失 / 损坏 / 陈旧 / 新鲜：
      · 缺失 / 损坏 ⇒ `错误` 非空（**拒答** —— 不许当「没有这个符号」）；
      · 陈旧 ⇒ `警告` 非空、`错误` 空（**附警告照答** —— 行号 / 出现位可能过时）；
      · 新鲜 ⇒ 两个都空。

    `根目录` 给了就用它；否则从 `库路径`（`<根>/.codegraph/codegraph.db`）反推；都没有 ⇒ 主工作树 `仓根`。

    ★ **新鲜度单位已对齐**：`files.modified_at` 是**毫秒**（codegraph 落库时写的），而
      `os.stat().st_mtime` 是**秒** ⇒ 必须 `st_mtime * 1000` 再比。旧版直接比 ⇒ 秒恒小于毫秒
      ⇒ **恒报新鲜**（实测踩过）。件表里有件、盘上 `stat` 不到 ⇒ 也算陈旧（已删件仍被索引留着）。
    """
    from .形参面 import 遍历命名件
    from .查名 import 命名后缀

    if 根目录 is not None:
        定位根 = Path(根目录)
    elif (库路径 is not None and Path(库路径).name == 库文件名
          and Path(库路径).parent.name == 库目录名):
        定位根 = Path(库路径).parent.parent
    else:
        定位根 = 仓根
    库件 = Path(库路径) if 库路径 else 定位根 / 库目录名 / 库文件名
    覆盖读数 = {"源件": 0, "索引件": 0, "缺失": [], "多余": []}
    件表 = {os.path.relpath(绝对路径, str(定位根)): "" for 绝对路径 in 遍历命名件(str(定位根))}
    源路径表 = {路径 for 路径 in 件表 if 路径.endswith(命名后缀)}
    覆盖读数["源件"] = len(源路径表)

    if not 库件.is_file():
        缺失文本 = "索引库不在：%s" % 库件
        return {"状态": "缺失", "说明": 缺失文本, "错误": 缺失文本, "警告": "", "覆盖": 覆盖读数}
    读不动模板 = "索引库读不动（%s）：%%s ⇒ 先跑 `python3 开发工具/代码地图.py 建`" % 库件
    库身份值 = 库身份(库件)
    记忆读数 = _健康记忆.get(str(库件)) if 库身份值 else None
    if 记忆读数 is None or 记忆读数["身份"] != 库身份值:
        记忆读数 = {"身份": 库身份值, **读库健康(库件, 读不动模板)}
        if 库身份值:
            _健康记忆[str(库件)] = 记忆读数
    if 记忆读数["损坏说明"]:
        损坏文本 = 记忆读数["损坏说明"]
        return {"状态": "损坏", "说明": 损坏文本, "错误": 损坏文本, "警告": "", "覆盖": 覆盖读数}
    索引路径表 = 记忆读数["索引路径表"]

    覆盖读数["索引件"] = len(索引路径表)
    覆盖读数["缺失"] = sorted(源路径表 - set(索引路径表))
    # ★ 只把「**盘上已不存在**的索引行」算多余：索引器按**它收的后缀集**收件（实测收 `.mjs`），
    #   而 `源路径表` 只含 `命名后缀` 的命名件 ⇒ 直接 `索引件 - 源路径表` 会把索引器收的
    #   非命名后缀件恒判成「多余」⇒ 本仓恒报**假陈旧**（实测：`测试验证/准入判据/使用面回归_网页.mjs`
    #   在盘上真实存在、主干也有，却被判「索引含已不存在的件」）。真多余 = 索引有行、盘上没件。
    覆盖读数["多余"] = sorted(相对路径 for 相对路径 in 索引路径表
                        if not (定位根 / 相对路径).is_file())
    陈旧件 = ""
    if 覆盖读数["缺失"]:
        陈旧件 = "索引缺少源件：%s" % "、".join(覆盖读数["缺失"][:3])
    elif 覆盖读数["多余"]:
        陈旧件 = "索引含已不存在的件：%s" % "、".join(覆盖读数["多余"][:3])
    else:
        for 相对路径 in sorted(源路径表):
            try:
                源件时刻 = (定位根 / 相对路径).stat().st_mtime * 1000
            except OSError:
                陈旧件 = "源件在盘上 stat 不到（已删？）：`%s`" % 相对路径
                break
            # +1 毫秒容差：codegraph 的 modified_at 存到 3 位小数，与 `st_mtime*1000` 有
            #   ~0.0003 毫秒的浮点噪声（实测踩到：无容差时恒定假陈旧）。真改动间隔 ≫1 毫秒。
            if 相对路径 in 索引路径表 and 源件时刻 > float(索引路径表[相对路径]) + 1:
                陈旧件 = "索引库比源件旧：`%s` 改在索引落库之后" % 相对路径
                break
    if 陈旧件:
        陈旧警告 = ("索引陈旧：%s ⇒ 先跑 `python3 开发工具/代码地图.py 建`"
                 "（行号 / 出现位可能过时）" % 陈旧件)
        return {"状态": "陈旧", "说明": 陈旧件, "错误": "", "警告": 陈旧警告, "覆盖": 覆盖读数}
    return {"状态": "新鲜", "说明": "索引新鲜", "错误": "", "警告": "", "覆盖": 覆盖读数}


def 可读说明(根目录=None, 库路径=None) -> str:
    """索引状态的一行可读提示（空 = 新鲜且覆盖齐）。口径只此一份：`查索引状态`。"""
    状态读数 = 查索引状态(根目录=根目录, 库路径=库路径)
    if 状态读数["错误"]:
        return "★ %s" % 状态读数["错误"]
    if 状态读数["警告"]:
        return "★ %s" % 状态读数["警告"]
    return ""


def 文件指纹(相对路径: str, 根目录=None) -> str:
    """该件的**内容指纹**（sha256 前 16 位十六进制）。

    ★ **现算、不落库**：它是给写操作做 CAS 的（「我看到的还是不是那一版」），
    必须**只由文件内容决定** —— 索引器库里的 `content_hash` 是它自带的算法、且改完件要重刷才更新
    ⇒ 不能当指纹用（写完的那一刻它必然过期）。
    """
    件路径 = Path(相对路径)
    if not 件路径.is_absolute():
        件路径 = (根目录 or 仓根) / 件路径
    try:
        return hashlib.sha256(件路径.read_bytes()).hexdigest()[:16]
    except OSError:
        return ""


def 查询定义(关键词: str = "", 结果上限: int = 40, 库路径=None,
             路径前缀: str = "", 类型: str = "") -> dict:
    """按**短名 / 限定名 / 声明 / 路径**子串查定义 ⇒ `{"命中","扫过","总数"}`（坏库带 `错误`）。

    **过滤 / 排序 / 计数 / 分页全在 SQLite 内**（不把全定义搬进 Python）：
      · `关键词` 空串 = 全部；`路径前缀` 只看该前缀下的件（F7 收窄）；`类型` 只看该 `kind`；
      · **排序 = 定义优先**：限定名全等 > 名字全等 > 可调用类（function / method / class …）
        > 其余，再按路径 / 行 —— 宽关键词（如「扩展」上千命中）先看到「就是它」的那条。
    """
    库件 = Path(库路径 or 默认库路径())
    if not 库件.is_file():
        return {"命中": [], "扫过": 0, "总数": 0, "错误": "索引库不在：%s" % 库件}
    try:
        动态库 = 连库(库件)
    except sqlite3.Error as 失败原因:
        return {"命中": [], "扫过": 0, "总数": 0,
                "错误": "索引库读不动（%s）：%s ⇒ 先跑 `python3 开发工具/代码地图.py 建`" % (库件, 失败原因)}
    try:
        try:
            基础条件 = "n.kind <> ? and n.kind <> ?"
            收窄条件 = ""
            查询参数 = list(非标识符种类)
            if 路径前缀:
                收窄条件 += " and n.file_path like ?"
                查询参数.append(路径前缀.replace("\\", "/") + "%")
            if 类型:
                收窄条件 += " and n.kind = ?"
                查询参数.append(类型)
            匹配条件 = 基础条件 + 收窄条件
            if 关键词:
                匹配条件 += (" and (instr(n.name, ?) > 0 or instr(n.qualified_name, ?) > 0 "
                          "or instr(coalesce(n.signature, ''), ?) > 0 or instr(n.file_path, ?) > 0)")
                查询参数 += [关键词] * 4
            扫过数量 = 动态库.execute(
                "select count(*) from nodes n where " + 基础条件, list(非标识符种类)).fetchone()[0]
            命中数量 = 动态库.execute(
                "select count(*) from nodes n where " + 匹配条件, 查询参数).fetchone()[0]
            排序子句 = ("order by (n.qualified_name <> ?) asc, (n.name <> ?) asc, "
                    "case n.kind when 'function' then 0 when 'method' then 1 when 'class' then 2 "
                    "when 'struct' then 3 when 'enum' then 4 when 'trait' then 5 else 6 end asc, "
                    "n.file_path, n.start_line")
            取数上限 = max(0, int(结果上限))
            结果行表 = 动态库.execute(
                "select %s from nodes n where %s %s limit ?" % (_节点字段, 匹配条件, 排序子句),
                查询参数 + [关键词, 关键词, 取数上限]).fetchall()
            return {"命中": [节点记录(表行) for 表行 in 结果行表],
                    "扫过": 扫过数量, "总数": 命中数量}
        except (sqlite3.Error, TypeError, ValueError) as 失败原因:
            return {"命中": [], "扫过": 0, "总数": 0,
                    "错误": "索引库读不动（%s）：%s ⇒ 先跑 `python3 开发工具/代码地图.py 建`" % (库件, 失败原因)}
    finally:
        动态库.close()


def 查符号(关键词: str, 结果上限: int = 40, 库路径=None, 根目录=None) -> dict:
    """按**短名 / 限定名 / 声明 / 路径**子串查定义（带**起止行**与**文件指纹**，喂写操作）。

    坏库 / 缺库 ⇒ 带 `错误`（调用方据此**拒答**，不当「没有这个符号」）。
    """
    查询读数 = 查询定义(关键词, 结果上限=结果上限, 库路径=库路径)
    if 查询读数.get("错误"):
        return 查询读数
    指纹表: dict = {}
    for 定义记录 in 查询读数["命中"]:
        件路径 = 定义记录["路径"]
        if 件路径 not in 指纹表:
            指纹表[件路径] = 文件指纹(件路径, 根目录)
        定义记录["指纹"] = 指纹表[件路径]
    提示语 = 可读说明(根目录=根目录, 库路径=库路径)
    if 提示语:
        查询读数["索引陈旧"] = 提示语
    return 查询读数


def 出现位置(键名: str, 结果上限: int = 0, 库路径=None, 根目录=None) -> dict:
    """该符号的全部出现位置 ⇒ `{"位置","总数","口径"}`（**带列**）。

    坏库 / 缺库 ⇒ 带 `错误`（调用方据此**拒答**）；陈旧 ⇒ 只在 `口径` 里**附警告照答**。
    列是**字符下标**（codegraph 的口径），写操作按它定点换。口径说明见 `索引库.出现位`。
    """
    查询读数 = 出现位(键名, 结果上限, 库路径)
    状态读数 = 查索引状态(根目录=根目录, 库路径=库路径)
    if 状态读数["错误"]:
        查询读数["错误"] = 状态读数["错误"]
    elif 状态读数["警告"]:
        查询读数["口径"] = "%s ｜ %s" % (查询读数["口径"], 状态读数["警告"])
    return 查询读数


def 零消费者符号(路径前缀: str = "", 结果上限: int = 50, 库路径=None) -> dict:
    """**索引里没有任何入边**的定义（`kind<>'contains'`）⇒ `{"命中","扫过","总数"}`（坏库带 `错误`）。

    ★ **0 消费者 ≠ 死代码证明**：入口 / 公开 API / 测试 / 反射 / 宏 / 索引漏解析
      都会让一个活的符号显得「没人调」。本档只给**候选**；复核必须用 `限定名` 查**出现位**
      （看文本里到底有没有调用点），改名 / 删除前还要编译兜底。
    """
    库件 = Path(库路径 or 默认库路径())
    if not 库件.is_file():
        return {"命中": [], "扫过": 0, "总数": 0, "错误": "索引库不在：%s" % 库件}
    try:
        动态库 = 连库(库件)
    except sqlite3.Error as 失败原因:
        return {"命中": [], "扫过": 0, "总数": 0,
                "错误": "索引库读不动（%s）：%s ⇒ 先跑 `python3 开发工具/代码地图.py 建`" % (库件, 失败原因)}
    try:
        try:
            基础条件 = "n.kind <> ? and n.kind <> ?"
            收窄条件 = ""
            查询参数 = list(非标识符种类)
            if 路径前缀:
                收窄条件 = " and n.file_path like ?"
                查询参数.append(路径前缀.replace("\\", "/") + "%")
            零入边 = (" and not exists (select 1 from edges e where e.target = n.id "
                    "and e.kind <> 'contains')")
            扫过数量 = 动态库.execute(
                "select count(*) from nodes n where " + 基础条件 + 收窄条件, 查询参数).fetchone()[0]
            命中数量 = 动态库.execute(
                "select count(*) from nodes n where " + 基础条件 + 收窄条件 + 零入边, 查询参数).fetchone()[0]
            取数上限 = max(0, int(结果上限))
            结果行表 = 动态库.execute(
                "select %s from nodes n where %s order by n.file_path, n.start_line limit ?"
                % (_节点字段, 基础条件 + 收窄条件 + 零入边), 查询参数 + [取数上限]).fetchall()
            return {"命中": [节点记录(表行) for 表行 in 结果行表],
                    "扫过": 扫过数量, "总数": 命中数量}
        except (sqlite3.Error, TypeError, ValueError) as 失败原因:
            return {"命中": [], "扫过": 0, "总数": 0,
                    "错误": "索引库读不动（%s）：%s ⇒ 先跑 `python3 开发工具/代码地图.py 建`" % (库件, 失败原因)}
    finally:
        动态库.close()


def 查引用(键名: str, 结果上限: int = 400, 库路径=None) -> dict:
    """找该符号的全部出现（定义处也算）⇒ `{"按文件": {路径: [行…]}, "总数": n, "口径": "…"}`。"""
    出现结果 = 出现位置(键名, 结果上限=结果上限, 库路径=库路径)
    按文件行号表: dict = {}
    for 文件路径, 行号, _ in 出现结果["位置"]:
        按文件行号表.setdefault(文件路径, []).append(行号)
    return {"按文件": 按文件行号表, "总数": 出现结果["总数"],
            "截断": 出现结果["总数"] > len(出现结果["位置"]), "口径": 出现结果["口径"]}


# ── 渲染 ────────────────────────────────────────────────────────────────────────────────

def 查符号行(关键词: str) -> list:
    """`查符号` 的结果渲染成几行给人读的字（**入口零实现**：渲染也归包里）。

    带**起止行**与**文件指纹** —— 这两个是喂写操作的：起止行直接填 `开始行` / `结束行`，
    指纹用于指纹闸拒了之后重新对齐。
    """
    查询结果 = 查符号(关键词)
    if 查询结果.get("错误"):
        return ["**%s**" % 查询结果["错误"]]
    输出行表 = ["命中 %d 个定义（扫过 %d 条）" % (查询结果["总数"], 查询结果["扫过"])]
    for 定义记录 in 查询结果["命中"]:
        输出行表.append("  %-46s %-10s %s:%d–%d  [出现 %d 处]  指纹 %s" % (
            定义记录["限定名"], 定义记录["种类"] or "—", 定义记录["路径"],
            定义记录["行"], 定义记录["末行"] or 定义记录["行"],
            定义记录["出现数"], 定义记录.get("指纹", "")))
    if 查询结果["总数"] > len(查询结果["命中"]):
        输出行表.append("  …（还有 %d 个，加关键词收窄）"
                     % (查询结果["总数"] - len(查询结果["命中"])))
    if 查询结果.get("索引陈旧"):
        输出行表.append("  " + 查询结果["索引陈旧"])
    return 输出行表


def 引用行(键名: str) -> list:
    """`引用` 的结果渲染成几行给人读的字。"""
    引用结果 = 查引用(键名)
    输出行表 = ["出现 %d 处（口径：%s）" % (引用结果["总数"], 引用结果["口径"])]
    for 文件路径 in sorted(引用结果["按文件"]):
        去重行号表 = sorted(set(引用结果["按文件"][文件路径]))
        输出行表.append("  %-56s %s" % (
            文件路径, " ".join(str(行号) for 行号 in 去重行号表[:24])))
    return 输出行表


def 状态行() -> list:
    """索引库在不在、多大、几个节点 —— 几行给人读的字。"""
    if not 有库():
        return ["代码地图：还没有索引库 ⇒ 先跑 `python3 开发工具/代码地图.py 建`",
                "  落点 %s" % 库路径()]
    读数 = 库读数()
    if 读数.get("错误"):
        return ["代码地图 · 索引库：%s" % 库路径(), "  **%s**" % 读数["错误"]]
    输出行表 = [
        "代码地图 · 索引库：%s" % 库路径(),
        "  %d 节点 · %d 边 · %d 件（索引器 %s）· %d 字节" % (
            读数["节点"], 读数["边"], 读数["件"], 读数["索引器版本"] or "—",
            库路径().stat().st_size),
    ]
    提示语 = 可读说明()
    if 提示语:
        输出行表.append("  " + 提示语)
    return 输出行表
