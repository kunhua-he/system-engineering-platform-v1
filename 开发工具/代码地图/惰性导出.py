def __getattr__(名字):
    """按属性取公开名 ⇒ 只 import 提供它的那一个子模块（PEP 562 模块级 `__getattr__`）。"""
    模块名 = _公开名到模块.get(名字)
    if 模块名 is None:
        raise AttributeError("代码地图没有公开名 %r" % 名字)
    导出值 = importlib.import_module("." + 模块名, __package__)
    if 名字 != 模块名:
        导出值 = getattr(导出值, 名字)
    sys.modules[__package__].__dict__[名字] = 导出值
    return 导出值


def __dir__():
    """⇒ 包已设属性 ∪ 惰性公开名（PEP 562 模块级 `__dir__`）。"""
    return sorted(set(_公开名到模块) | set(sys.modules[__package__].__dict__))
