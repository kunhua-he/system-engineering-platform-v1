"""代码地图 · 查名 —— 把命名规范的口径套在**索引的定义面**上。

**为什么要有它**（华哥 2026-09-27 原话）：「代码地图本来就能索引出来所有的变量。然后复用这个
脚本做检测不就完事了？」—— 对。索引给的是**真解析器**给出的标识符，没有自研剥器那两类假阴性
（都实测漏过）：① 把紧跟 `.` 的一律当「别人家的成员」排除 ⇒ 看不见 `self.d`；
② 把整个字符串抹空 ⇒ 看不见 f-string / Rust 内联格式串里的名字。

故本件把**规则**（三档口径）与**面**（标识符从哪来）分开：
  · **规则只此一份**（本件）—— 判据 ㉒ 也 import 它，不许各写一套；
  · **面各取所需** —— 本件吃索引（全语义，最准）；判据 ㉒ 吃自身的零依赖剥器
    （因为它要在**合成仓**上跑：索引是整仓产出的，夹具仓没有索引 ⇒ 那条判据会永远「未判」）。

依据：`项目文档/决策记录/2026-09-27_命名规范.md` §二/§三/§六 · `判据口径十一条.md` §十三。
"""

import re

from .落点 import 库路径

# ★ 解互锁（台账 I-115 · 2026-10-11）：`索引库` 原先在本件**顶层** import ⇒ 本件被 `落库.py`
#   顶层 import（`from 代码地图 import 查名`）时，索引库被连带拖进 ⇒ 索引库一旦损坏/缺失，
#   信息核心的 `落库` 与 `登记` 全崩（实测把 `索引库.py` 写坏后 `import 落库` 即 RuntimeError）。
#   改为**惰性 import**：本件的规则谓词（判状态 / 判模式 / 判禁止形状）零依赖索引库，
#   只有 `读索引定义` / `检名` 真读索引时才取 ⇒ 落库只走谓词，不再连带。

# 有标识符的语言后缀 —— `.css` / `.html` / `.sh` **没有标识符这回事**，扫它们就是假红。
# ★ 2026-10-08 收口（前端标记掉出命名面）：命名面**只对可解析代码** —— `.html` 是前端标记、
#   非作者标识符（实测：算进来会让命名面多出 80 新名 / 81 待改名，且 `代码地图` 查索引状态
#   误报 `.html` 缺索引，而索引器 codegraph 根本不收 html）⇒ 唯一权威仍是闸那份 `常量.py`，
#   本表取它的 `命名可解析后缀`（= `代码后缀` 去掉 `.html`），**不另写一份**。
# ★ **取法必须惰性**：本件在 `代码地图/__init__` 里被较早 import，而 `常量.py` 又在它引
#   `代码地图.落点` 之前就定义好了后缀表 —— 若在**顶层**直接
#   `from 一键验证.常量 import 命名可解析后缀`，从本件进入时会撞循环 import。做法照
#   `夹具规则库.取命名后缀` 与 `命名面.取查名` 的先例（惰性取 + 上门口的路）。
def _取命名可解析后缀() -> tuple:
    """惰性引**后缀表唯一权威**（`构建装配/一键验证/一键验证/常量.py::命名可解析后缀`）。

    带上门口那条路：本件可能被 MCP 工具（`服务指纹` 的依赖面）单独拉进来，
    那时 `构建装配/一键验证` 未必在 `sys.path` 里。
    """
    import sys as _sys
    from pathlib import Path as _Path

    子目录 = str(_Path(__file__).resolve().parents[2] / "构建装配" / "一键验证")
    if 子目录 not in _sys.path:
        _sys.path.insert(0, 子目录)
    import 一键验证.常量 as _常量

    return tuple(_常量.命名可解析后缀)


命名后缀 = _取命名可解析后缀()

