# -*- coding: utf-8 -*-
"""代码地图 · 查名 —— 把命名规范的口径套在**索引的定义面**上。

**为什么要有它**（华哥 2026-09-27 原话）：「代码地图本来就能索引出来所有的变量。然后复用这个
脚本做检测不就完事了？」—— 对。索引给的是**真解析器**给出的标识符，没有自研剥器那两类假阴性
（都实测漏过）：① 把紧跟 `.` 的一律当「别人家的成员」排除 ⇒ 看不见 `self.d`；
② 把整个字符串抹空 ⇒ 看不见 f-string / Rust 内联格式串里的名字。

故本件把**规则**（三档口径）与**面**（标识符从哪来）分开：
  · **规则只此一份**（本件）—— 判据 ㉒ 也 import 它，不许各写一套；
  · **面各取所需** —— 本件吃索引（全语义，最准）；判据 ㉒ 吃自己的零依赖剥器
    （因为它要在**合成仓**上跑：索引是整仓产出的，夹具仓没有索引 ⇒ 那条判据会永远「未判」）。

依据：`项目文档/决策记录/2026-09-27_命名规范.md` §二/§三/§六 · `判据口径十一条.md` §十三。
"""

import json
from pathlib import Path

from .落点 import 定义路径

# 有标识符的语言后缀 —— `.css` / `.html` / `.sh` **没有标识符这回事**，扫它们就是假红。
命名后缀 = (".rs", ".py", ".js", ".ts", ".vue")

# 天干十字：甲乙丙丁戊己庚辛壬癸（命名规范 §二「天干一律停用（作标识符）」）。
天干字 = "甲乙丙丁戊己庚辛壬癸"

# ★ **词内天干不算**（裁决 2026-09-27，`判据口径十一条.md` §十三）：判的是「拿天干**当序数代称**」，
# 不是「标识符里出现过某个天干字」—— `自己` 里的 `己` 是词的一部分（有词典义），不是代称。
# **白名单是封闭的、且必须由实测得出**：实测全仓含天干字的标识符只有 9 个，8 个含 `自己`，
# 第 9 个是 `含拉丁字母`（`拉丁` 是「Latin」的音译，`丁` 在词内不表序）。
# 要往这里加一条，先证明那个词**有词典义**且天干字在词内不表序 —— 别拿它当消音器。
词内天干 = ("自己", "拉丁")

# 「无义中文单字」那一档（命名规范 §三 的 `出` `加` `取` `查` `判`）——
# **不判**（白名单/黑名单是开放的，判它必假红）；只用于「如实报读数」。
无义单字 = "出加做取查判"

# 「实义单字名」：该字在本项目词表里是**有义的领域名词** ⇒ 允许（命名规范 §三 那一档）。
实义单字 = set("值码槽号根表键止起名项条位序上左前末首")


def 含天干作标识符(名: str) -> bool:
    """标识符里有没有「**当序数代称**的天干字」（词内的不算，见 `词内天干`）。"""
    余 = 名
    for 词 in 词内天干:
        余 = 余.replace(词, "")
    return any(字 in 天干字 for 字 in 余)


def 是单西文字母(名: str) -> bool:
    """单个**西文（拉丁）字母**的标识符（`f` `i` `n` … 大小写皆算；`_` 不算 —— 它不是字母）。"""
    return len(名) == 1 and 名.isascii() and 名.isalpha()


def 是命名件(路径: str) -> bool:
    """判据 ㉒ 的扫描件：后缀在 `命名后缀` 里（`.css`/`.html`/`.sh` 不收）。"""
    return 路径.endswith(命名后缀)


def 含拉丁字母(名: str) -> bool:
    """名字里有没有拉丁字母（**读数用**：命名规范 §六「拉丁名一律换成中文，除非是强加的」）。"""
    return any(字.isascii() and 字.isalpha() for 字 in 名)


def 分档(定义表: list) -> dict:
    """把索引里的定义分档 ⇒ `{"天干": [...], "拉丁单字母": [...], "无义单字": [...], "拉丁": [...]}`。

    每条 = `{"路径","名字","种类","行","出现数"}`（只收 `命名后缀` 里的件）。
    前两档是**判**的档；后两档是**读数**（命名规范 §六 明写「不做成判据」）。
    """
    档表 = {"天干": [], "拉丁单字母": [], "无义单字": [], "拉丁": []}
    for 定义条 in 定义表:
        路径 = 定义条.get("路径", "")
        if not 是命名件(路径):
            continue
        名 = 定义条.get("名字", "")
        if not 名:
            continue
        一条 = {"路径": 路径, "名字": 名, "种类": 定义条.get("种类", ""),
               "行": 定义条.get("行", 0), "出现数": 定义条.get("出现数", 0)}
        if 含天干作标识符(名):
            档表["天干"].append(一条)
        if 是单西文字母(名):
            档表["拉丁单字母"].append(一条)
        elif 含拉丁字母(名):
            档表["拉丁"].append(一条)
        elif len(名) == 1 and 名 in 无义单字:
            档表["无义单字"].append(一条)
    return 档表


def 读索引定义() -> list:
    """读 `定义.jsonl`（流式）⇒ 定义表。索引不在 ⇒ 空表（调用方据此报「先建」）。"""
    索引路径 = 定义路径()
    if not 索引路径.is_file():
        return []
    定义表 = []
    with 索引路径.open(encoding="utf-8") as 索引文件:
        for 原始行 in 索引文件:
            if 原始行.strip():
                定义表.append(json.loads(原始行))
    return 定义表


def 检名(上限: int = 25) -> dict:
    """跑一遍命名检查 ⇒ 分档读数 + 每档前若干条。

    **索引不在 ⇒ `{"有索引": False}`**（调用方报「先跑 `代码地图.py 建`」）——
    不是「没有违规」。空集是**未判**，不是通过。
    """
    索引路径 = 定义路径()
    if not 索引路径.is_file():
        return {"有索引": False, "路径": str(索引路径)}
    档表 = 分档(读索引定义())
    读数 = {档: len(条表) for 档, 条表 in 档表.items()}
    return {
        "有索引": True,
        "路径": str(索引路径),
        "读数": 读数,
        "样本": {档: 条表[:上限] for 档, 条表 in 档表.items()},
    }
