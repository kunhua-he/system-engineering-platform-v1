def 含序数代称作标识符(名称: str) -> bool:
    """标识符里有没有「**当序数代称**的序数代称字」（词内的不算，见 `词内序数代称`）。"""
    剩余名称 = 名称
    for 白名单词 in 词内序数代称:
        剩余名称 = 剩余名称.replace(白名单词, "")
    return any(字符表 in 序数代称字 for 字符表 in 剩余名称)


def 是单西文字母(名称: str) -> bool:
    """单个**西文字母**的标识符（`f` `i` `n` … 大小写皆算；`_` 不算 —— 它不是字母）。"""
    return len(名称) == 1 and 名称.isascii() and 名称.isalpha()


def 是命名件(路径: str) -> bool:
    """判据 ㉒ 的扫描件：后缀在 `命名后缀` 里（`.css`/`.html`/`.sh` 不收）。"""
    return 路径.endswith(命名后缀)


# ── 禁形判据三条（旧套那件蒸馏而来，2026-10-07）──────────────────────
# ★ 为何住本件：它们是**命名规范的口径**（「哪些形状算合格」），与 `含序数代称作标识符` /
#   `是单西文字母` 同一类 —— 本件就是那套口径的主人（件头那句「规则只此一份」）。
#   调用方：`开发工具/信息核心/落库.py`（写库前逐名重判状态），不另写第二套。
def 判模式(标识符: str, 动作词表: set) -> str:
    """以动作词开头且后面还有对象 ⇒ 「动作+对象」；否则 ⇒ 「对象+说明」（**结构判，不查词源**）。"""
    return "动作+对象" if any(标识符.startswith(关键词) and len(标识符) > len(关键词)
                         for 关键词 in 动作词表) else "对象+说明"


def 判禁止形状(标识符: str, 泛名表: set) -> str:
    """⇒ 命中的禁止形状名（空串＝没命中）。四条口径见 库 `规则` 表 `设计原则-7`「标识符表达角色」。

    「序数代称」＝含序数代称字（本件那套谓词）· 以**单个**数字结尾（`临时2`，错误码/HTTP 码那种
    多位数结尾不算）· 形如 `第N个`；「西文单字母」也走本件的谓词；
    「泛名」「单汉字名」本函数判（泛名名单住库 `命名泛名`，由调用方读入传入）。
    """
    if 标识符 in 泛名表:
        return "泛名"
    if len(标识符) == 1:
        return "单汉字名" if not 标识符.isascii() else ("西文单字母" if 标识符.isalpha() else "")
    if 含序数代称作标识符(标识符) or re.fullmatch(r"第.{1,4}个", 标识符) or re.search(r"(?<![\d号码])\d$", 标识符):
        return "序数代称"
    return ""


def 判状态(标识符: str, 泛名表: set, 动作词表: set) -> tuple:
    """⇒ `(状态, 模式, 语义)`：落禁止形状 ⇒ `待改名`，否则 `合格`。"""
    模式 = 判模式(标识符, 动作词表)
    形状 = 判禁止形状(标识符, 泛名表)
    if 形状:
        return "待改名", 模式, f"原名{标识符}，落入禁止形状「{形状}」⇒ 需人工定改法"
    return "合格", 模式, f"原名{标识符}，结构为「{模式}」，不落禁止形状"


def 含西文字母(名称: str) -> bool:
    """名字里有没有西文字母（**读数用**：命名规范 §六「西文名一律换成中文，除非是强加的」）。"""
    return any(字符表.isascii() and 字符表.isalpha() for 字符表 in 名称)


def 定义分档(定义表: list) -> dict:
    """把索引里的定义分档 ⇒ `{"序数代称": [...], "西文单字母": [...], "无义单字": [...], "西文": [...]}`。

    每条 = `{"路径","名字","种类","行","出现数"}`（只收 `命名后缀` 里的件）。
    前两档是**判**的档；后两档是**读数**（命名规范 §六 明写「不做成判据」）。
    """
    档表 = {"序数代称": [], "西文单字母": [], "无义单字": [], "西文": []}
    for 定义条 in 定义表:
        路径 = 定义条.get("路径", "")
        if not 是命名件(路径):
            continue
        名称 = 定义条.get("名字", "")
        if not 名称:
            continue
        定义条目 = {"路径": 路径, "名字": 名称, "种类": 定义条.get("种类", ""),
               "行": 定义条.get("行", 0), "出现数": 定义条.get("出现数", 0)}
        if 含序数代称作标识符(名称):
            档表["序数代称"].append(定义条目)
        if 是单西文字母(名称):
            档表["西文单字母"].append(定义条目)
        elif 含西文字母(名称):
            档表["西文"].append(定义条目)
        elif len(名称) == 1 and 名称 in 无义单字:
            档表["无义单字"].append(定义条目)
    return 档表


def 读索引定义() -> list:
    """读索引库的定义面 ⇒ 定义表。索引库不在 ⇒ 空表（调用方据此报「先建」）。

    **面由 `索引库.全部定义` 定**（已剔掉 `file` 与 `import` —— 导入名是模块绑定，
    不是作者起的标识符；本件不再过滤一遍，同一职责只留一处）。
    """
    from .索引库 import 全部定义
    return 全部定义()


def 检名(显示上限: int = 25) -> dict:
    """跑一遍命名检查 ⇒ 分档读数 + 每档前若干条。

    **索引库不在 ⇒ `{"有索引": False}`**（调用方报「先跑 `代码地图.py 建`」）——
    不是「没有违规」。空集是**未判**，不是通过。
    """
    from .索引库 import 有库
    if not 有库():
        return {"有索引": False, "路径": str(库路径())}
    档表 = 定义分档(读索引定义())
    读数 = {档位: len(条表) for 档位, 条表 in 档表.items()}
    return {
        "有索引": True,
        "路径": str(库路径()),
        "读数": 读数,
        "样本": {档位: 条表[:显示上限] for 档位, 条表 in 档表.items()},
    }
