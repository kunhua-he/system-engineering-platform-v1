# -*- coding: utf-8 -*-
"""代码地图 · 形参面 —— 补上索引面**看不见的那两层**：函数形参 · JS 箭头/回调形参。

★ **模块名为何不叫 `检形参`**：`__init__.py` 再导出的那个函数就叫 `检形参` ——
同名会把**子模块属性遮住**（`import 代码地图.检形参 as X` 拿到的会是函数，实测撞过
`AttributeError: 'function' object has no attribute ...`）。故模块用**面的名**（`形参面`），
函数用**动作的名**（`检形参`）—— 同 `查名.py` 收 `检名` 的口径。

**为什么要有它**：`codegraph` 的定义面只收**函数 / 方法 / 变量 / 类型**，**形参一个都不收**
（形参没有自身的定义行，它挂在签名里）⇒ 只照索引列落点，形参会**整层漏改**：实测漏过一整轮，
714 处无一在批内。JS 的箭头函数 / 回调 / 闭包形参更不在索引的面里。故另开一面。

**规则与面分开**（同 `查名.py` 的口径）：
  · **规则只此一份** —— 哪个名算违规归 `查名.py`（本件 import 它，不另写一套）；
  · **面**在这里 —— 两套扫描，共用一个人口 `扫文本(路径, 文本)`：
      `扫签名形参` 吃 `.rs`/`.py` 的 `fn`/`def` 签名（**多行签名也认**：跨行读到配平的 `)`）；
      `扫JS形参`   吃 `.js`/`.ts`/`.vue` 的箭头函数 / 函数表达式 / 回调 / 闭包。

★ **不许拿文本工具替代它**：`rg` 认不出「多行签名」与「回调形参」，这两类实测都漏过。

**两个调用方，同一份面**：
  · `python3 开发工具/代码地图.py 检形参`（`检形参`）—— 自行走树，**不依赖索引库**；
  · **判据 ㉒ 的第三档「形参单字」**（`构建装配/一键验证/一键验证/判据_命名.py`）—— 吃
    `上["文件"]` 的**内存文本**，故夹具仓照跑。**不许另写一套扫描器**。

★ `读文本` 的错误策略是**有意的（`errors="replace"` 且吞 `OSError` 返空串）** —— 本面**只报
读数不判**，二进制 / 权限读不动不该炸整轮扫描。与别处同名读器（`形状检查/形状.py` 不吞原样抛 ·
`生成声明/小工具.py` 抛 `生成失败` · `查文件行数/核心.py` 不吞 `OSError`）**不是同一事实，勿合并**。

依据：`项目文档/决策记录/2026-09-27_命名规范.md` §三 · §八.11 · §四.2。
"""

import os
import re

from .查名 import 命名后缀
from .落点 import 仓根, 排除目录

# 整棵跳过的目录 = **段形态主人**（`落点.排除目录`：只读参考 · 构建环境 · 版本库 · 索引库）
# ＋ 本面的增量（各腿工作树 · 编译产物 · 第三方依赖）。
跳过目录 = 排除目录 + ("工作树", "target", "node_modules")

# 行首即注释 ⇒ 整行跳过（`///` 排在 `//` 之后无妨）。
注释头 = ("//", "#", "*", "///", "/*")

# JS 面吃这几个后缀；其余（`.rs`/`.py`）走签名面。面由后缀选，只此一处。
JS后缀 = (".js", ".ts", ".vue")

# 签名面：`fn`/`def` 头。允许 `pub(…)` / `async` / `const` / `unsafe` / `extern "C"` 前缀。
_函数头 = re.compile(
    r'^(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?(?:const\s+)?(?:unsafe\s+)?'
    r'(?:extern\s+"[^"]*"\s+)?fn\s+([\w\u4e00-\u9fff]+)'
    r'|^(?:async\s+)?def\s+([\w\u4e00-\u9fff]+)'
)

# 签名里的一个形参名：段首 / 逗号之后，可选 `mut` 与借用符，名后跟 `:` / `,` / `=` / 段尾。
_形参名 = re.compile(
    r'(?:^|,)\s*(?:mut\s+)?(?:&\s*(?:mut\s+)?)?'
    r'([A-Za-z_\u4e00-\u9fff][\w\u4e00-\u9fff]*)\s*(?::|,|$|=)'
)

# JS 面：箭头函数（`(首参, 次参) =>` 与 `首参 =>` 两种写法）。
_箭头函数 = re.compile(
    r'(?:^|[^\w$])(?:\(([^()]*)\)|([A-Za-z_\u4e00-\u9fff][\w\u4e00-\u9fff]*))\s*=>'
)

# JS 面：函数表达式 / 回调（`function 名(首参, 次参)` 与匿名 `function (首参, 次参)`）。
_函数表达式 = re.compile(r'function\s*[\w\u4e00-\u9fff$]*\s*\(([^()]*)\)')

# JS 形参段里取一个名：段首 / 逗号之后，允许 `...` 剩余参数与默认值。
_JS形参名 = re.compile(r'(?:^|,)\s*\.{0,3}([A-Za-z_\u4e00-\u9fff][\w\u4e00-\u9fff]*)')


def 是形参名(名称: str, 只单字: bool = True) -> bool:
    """形参面收不收这个名 —— **两种口径共用这一个判定**（不另写一套）。

    `_`（语言通配符）与 `self`（不是作者起的）**两种口径都不收**；
    `只单字=True`（判据 ㉒ 第三档的口径）只收单字；`False`（命名穷举的全名口径）收全部形参名。
    """
    if 名称 in ("_", "self"):
        return False
    return len(名称) == 1 if 只单字 else True


def 是单字形参(名称: str) -> bool:
    """单字形参 —— `是形参名(名称, 只单字=True)` 的别名（判据 ㉒ 那一档的既有调用名）。"""
    return 是形参名(名称, 只单字=True)


def 读文本(路径: str) -> str:
    """读成文本；读不动（二进制 / 权限）⇒ 空串。本面**只报读数不判**，故不当成错误抛。

    ★ 错误策略**有意与别处不同**（`replace` + 吞 `OSError`）：与 `形状检查/形状.py` ·
      `生成声明/小工具.py` · `查文件行数/核心.py` 的同名读器**不是同一事实，勿合并**。
    """
    try:
        with open(路径, encoding="utf-8", errors="replace") as 节点件:
            return 节点件.read()
    except OSError:
        return ""


def 扫签名形参(行表: list, 只单字: bool = True) -> list:
    """`fn`/`def` 签名里的形参 ⇒ `[(行号, 函数名, 形参名)]`（收哪些见 `是形参名`）。

    ★ **多行签名也认**：从签名行的首个 `(` 起，跨行（最多 40 行）读到**配平**的 `)`。
    实测（本仓）多行签名里有 12 处单字形参 —— 只扫单行签名会整批漏掉。

    ★ **首个 `(` 从函数名之后起数**（2026-09-29 修实测假阳）：`pub(crate) fn 名(…)` /
      `pub(super) fn 名(…)` 的**可见性括号在函数名之前** —— 从行首起数会把它当签名括号，
      于是整条签名只收进一个 `crate` / `super`（实测 `crate` 37 件 126 处 · `super` 14 件 62 处，
      全是假阳）。

    ★ **泛型与嵌套括号不进缓冲**（同日实测第二类）：`fn 名<取号: Fn(usize) -> u32>(项数: …)`
      的 `Fn(usize)`、`取片段字节区间: (u32, u32)` 的元组类型 —— 那里的括号被当签名括号后，`usize` 成了
      「形参」而真形参 `项数` / `取号` 整批漏掉（**假阳与假阴同时发生**）。故：先按角深度
      跳过 `<…>`，且**只收签名括号那一层**（`深度 == 1`）里的字符。
    """
    输出缓冲 = []
    for 序号, 源码行 in enumerate(行表):
        首字节 = 源码行.strip()
        if 首字节.startswith(注释头):
            continue
        匹配 = _函数头.match(首字节)
        if not 匹配:
            continue
        函数名 = 匹配.group(1) or 匹配.group(2)
        前导 = len(源码行) - len(源码行.lstrip())
        缓冲 = ""
        深度 = 0
        角深度 = 0
        开了 = False
        for 偏移, 后续 in enumerate(行表[序号:序号 + 40]):
            if 偏移:
                号段 = 后续.strip()
                if 号段.startswith(注释头):
                    continue
            else:
                号段 = 后续[前导 + 匹配.end():]
            for 字符表 in 号段:
                if not 开了:
                    # 函数名之后可能先来一段**泛型**（`fn 名<取号: Fn(usize) -> u32>(…)`）——
                    # 那里的括号不是签名括号：从它起数，`usize` 会被当成形参、真形参整批漏掉。
                    if 字符表 == "<":
                        角深度 += 1
                        continue
                    if 字符表 == ">" and 角深度:
                        角深度 -= 1
                        continue
                    if 字符表 == "(" and 角深度 == 0:
                        深度 = 1
                        开了 = True
                    continue
                if 字符表 == "(":
                    深度 += 1
                    continue
                if 字符表 == ")":
                    深度 -= 1
                    if 深度 == 0:
                        break
                    continue
                if 深度 == 1:
                    缓冲 += 字符表
            if 开了 and 深度 == 0:
                break
            if 开了 and 深度 == 1:
                缓冲 += ","
        for 形参名 in _形参名.findall(缓冲):
            if 是形参名(形参名, 只单字):
                输出缓冲.append((序号 + 1, 函数名, 形参名))
    return 输出缓冲


def 扫JS形参(行表: list, 只单字: bool = True) -> list:
    """JS/TS 的箭头函数 / 函数表达式 / 回调 / 闭包里的形参 ⇒ `[(行号, 形参名)]`。

    这些形参是**函数内局部**的：改名字面替换即可，但**不许**把同名的外层变量一起改（按行判）。
    """
    输出缓冲 = []
    for 序号, 源码行 in enumerate(行表, 1):
        if 源码行.strip().startswith(注释头):
            continue
        for 匹配 in list(_箭头函数.finditer(源码行)) + list(_函数表达式.finditer(源码行)):
            形参段 = ""
            for 匹配组 in 匹配.groups():
                if 匹配组 is not None:
                    形参段 = 匹配组
                    break
            for 形参名 in _JS形参名.findall(形参段):
                if 是形参名(形参名, 只单字):
                    输出缓冲.append((序号, 形参名))
    return 输出缓冲


def 扫文本(路径: str, 文本: str, 只单字: bool = True) -> list:
    """按后缀选面扫**一段文本** ⇒ `[(行号, 函数名, 形参名)]`（JS 面无函数名，留空串）。

    **面只由这里选**（`.js`/`.ts`/`.vue` 走 JS 面，其余走签名面）—— CLI 走盘、判据 ㉒ 走
    内存件表，都调它，不另写一套。`只单字` 的口径见 `是形参名`。
    """
    行表 = 文本.splitlines()
    if 路径.endswith(JS后缀):
        return [(源码行, "", 形参名) for 源码行, 形参名 in 扫JS形参(行表, 只单字)]
    return 扫签名形参(行表, 只单字)


def 扫件(路径: str, 只单字: bool = True) -> list:
    """走盘的入口：读一件的文本再 `扫文本`。"""
    return 扫文本(路径, 读文本(路径), 只单字)


def 有函数头(路径: str, 文本: str) -> bool:
    """这段文本里有没有函数头（**判空集用**：面下一个函数头都没有 ⇒ 未判，不是通过）。

    走**与扫描同一套正则**（`_函数头` / `_箭头函数` / `_函数表达式`）—— 这样「扫描器坏了」与
    「真的没有形参」分得开：正则一坏，空集那一关当场报未判，而不是静默报 0（假绿）。
    """
    行表 = 文本.splitlines()
    if 路径.endswith(JS后缀):
        return any(_箭头函数.search(源码行) or _函数表达式.search(源码行) for 源码行 in 行表)
    return any(_函数头.match(源码行.strip()) and not 源码行.strip().startswith(注释头)
               for 源码行 in 行表)


def 遍历命名件(根目录: str = None):
    """走树产出扫描面里的件路径（后缀在 `命名后缀` 里，且不在 `跳过目录` 下）。"""
    起点 = str(根目录 or 仓根)
    for 目录, 子目录表, 件表 in os.walk(起点):
        子目录表[:] = [号段 for 号段 in 子目录表 if 号段 not in 跳过目录]
        for 节点件 in 件表:
            if 节点件.endswith(命名后缀):
                yield os.path.join(目录, 节点件)


def 扫描面读数(条表: list) -> dict:
    """一面的读数：处数 / 唯一名数 / 件数。"""
    return {"处": len(条表),
            "唯一名": len({明细条目["形参名"] for 明细条目 in 条表}),
            "件": len({明细条目["路径"] for 明细条目 in 条表})}


def 检形参(根目录: str = None, 显示上限: int = 25, 只单字: bool = True) -> dict:
    """走一遍全树的两套扫描 ⇒ `{"读数": {面: 读数}, "明细": {面: 前若干条}}`。

    每面读数见 `扫描面读数`；每条明细 = `{"路径","行","函数名","形参名"}`（JS 面无函数名）。
    **不依赖索引库** —— 自行走树，没建索引也能跑。
    """
    起点 = str(根目录 or 仓根)
    面表 = {"签名面": [], "JS面": []}
    for 路径 in 遍历命名件(起点):
        短路径 = os.path.relpath(路径, 起点)
        面名 = "JS面" if 路径.endswith(JS后缀) else "签名面"
        for 源码行, 函数名, 形参名 in 扫件(路径, 只单字):
            面表[面名].append(
                {"路径": 短路径, "行": 源码行, "函数名": 函数名, "形参名": 形参名})
    return {"读数": {扫描面: 扫描面读数(条表) for 扫描面, 条表 in 面表.items()},
            "明细": {扫描面: 条表[:显示上限] for 扫描面, 条表 in 面表.items()}}


def 形参行(读数: dict = None) -> list:
    """把 `检形参` 的读数与明细排成给人读的行（**CLI 只 print，不做排版** —— 入口要保持薄）。"""
    if 读数 is None:
        读数 = 检形参()
    行表 = ["代码地图 · 检形参（扫描面 = 全树两套扫描；"
            "**索引看不见形参** ⇒ 本命令不依赖索引库）："]
    for 面名 in ("签名面", "JS面"):
        一面 = 读数["读数"][面名]
        行表.append("  %-6s %d 处 / %d 个唯一名 / %d 件"
                    % (面名, 一面["处"], 一面["唯一名"], 一面["件"]))
    for 面名 in ("签名面", "JS面"):
        for 明细条目 in 读数["明细"][面名]:
            落点 = ("%s(%s)" % (明细条目["函数名"], 明细条目["形参名"]) if 明细条目["函数名"]
                    else 明细条目["形参名"])
            行表.append("    [%s] %s:%d  %s"
                        % (面名, 明细条目["路径"], 明细条目["行"], 落点))
    return 行表
