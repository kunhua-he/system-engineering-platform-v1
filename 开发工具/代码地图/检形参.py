# -*- coding: utf-8 -*-
"""代码地图 · 检形参 —— 补上索引面**看不见的那两层**：函数形参 · JS 箭头/回调形参。

**为什么要有它**：`codegraph` 的定义面只收**函数 / 方法 / 变量 / 类型**，**形参一个都不收**
（形参没有自己的定义行，它挂在签名里）⇒ 只照索引列落点，形参会**整层漏改**：实测漏过一整轮，
714 处无一在批内。JS 的箭头函数 / 回调 / 闭包形参更不在索引的面里。故另开一面。

**规则与面分开**（同 `查名.py` 的口径）：
  · **规则只此一份** —— 哪个名算违规归 `查名.py`（本件 import 它，不另写一套）；
  · **面**在这里 —— 两套扫描：
      `扫签名形参` 吃 `.rs`/`.py` 的 `fn`/`def` 签名（**多行签名也认**：跨行读到配平的 `)`）；
      `扫JS形参`   吃 `.js`/`.ts`/`.vue` 的箭头函数 / 函数表达式 / 回调 / 闭包。

★ **不许拿文本工具替代它**：`rg` 认不出「多行签名」与「回调形参」，这两类实测都漏过。

**它不依赖索引库**（自己走树）⇒ 没建索引也能跑 —— 这是它与 `检名` 的分工。

依据：`项目文档/决策记录/2026-09-27_命名规范.md` §三 · §八.11。
"""

import os
import re

from .查名 import 命名后缀
from .落点 import 仓根

# 整棵跳过的目录：版本库 / 索引库 / 各腿工作树 / 编译产物 / 第三方 / 只读参考（后者本仓不许读）。
跳过目录 = (".git", ".codegraph", "工作树", "target", "node_modules", "只读参考")

# 行首即注释 ⇒ 整行跳过（`///` 排在 `//` 之后无妨）。
注释头 = ("//", "#", "*", "///", "/*")

# 签名面：`fn`/`def` 头。允许 `pub(…)` / `async` / `const` / `unsafe` / `extern "C"` 前缀。
_函数头 = re.compile(
    r'^(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?(?:const\s+)?(?:unsafe\s+)?'
    r'(?:extern\s+"[^"]*"\s+)?fn\s+([\w\u4e00-\u9fff]+)'
    r'|^(?:async\s+)?def\s+([\w\u4e00-\u9fff]+)'
)

# 签名里的一个形参名：段首 / 逗号之后，可选 `mut` 与借用符，名后跟 `:` / `,` / `=` / 段尾。
_形参名 = re.compile(
    r'(?:^|,)\s*(?:mut\s+)?(?:&\s*(?:mut\s+)?)?'
    r'([A-Za-z_\u4e00-\u9fff][\w\u4e00-\u9fff]*)\s*(?::|,|$|=)'
)

# JS 面：箭头函数（`(甲, 乙) =>` 与 `甲 =>` 两种写法）。
_箭头 = re.compile(
    r'(?:^|[^\w$])(?:\(([^()]*)\)|([A-Za-z_\u4e00-\u9fff][\w\u4e00-\u9fff]*))\s*=>'
)

# JS 面：函数表达式 / 回调（`function 名(甲, 乙)` 与匿名 `function (甲, 乙)`）。
_函数式 = re.compile(r'function\s*[\w\u4e00-\u9fff$]*\s*\(([^()]*)\)')

# JS 形参段里取一个名：段首 / 逗号之后，允许 `...` 剩余参数与默认值。
_JS名 = re.compile(r'(?:^|,)\s*\.{0,3}([A-Za-z_\u4e00-\u9fff][\w\u4e00-\u9fff]*)')


def 是单字形参(名称: str) -> bool:
    """单字形参（`_` 不算 —— 它是语言通配符；`self` 本就不是单字，一并排除）。"""
    return len(名称) == 1 and 名称 not in ("_", "self")


def 读行表(路径: str) -> list:
    """读成行表；读不动（二进制 / 权限）⇒ 空表。本面**只报读数不判**，故不当成错误抛。"""
    try:
        with open(路径, encoding="utf-8", errors="replace") as 件:
            return 件.read().splitlines()
    except OSError:
        return []


def 扫签名形参(路径: str) -> list:
    """`fn`/`def` 签名里的单字形参 ⇒ `[(行号, 函数名, 形参名)]`。

    ★ **多行签名也认**：从签名行的首个 `(` 起，跨行（最多 40 行）读到**配平**的 `)`。
    实测（本仓）多行签名里有 12 处单字形参 —— 只扫单行签名会整批漏掉。
    """
    行表 = 读行表(路径)
    出 = []
    for 序号, 行 in enumerate(行表):
        首 = 行.strip()
        if 首.startswith(注释头):
            continue
        匹配 = _函数头.match(首)
        if not 匹配:
            continue
        函数名 = 匹配.group(1) or 匹配.group(2)
        缓冲 = ""
        深度 = 0
        开了 = False
        for 偏移, 后续 in enumerate(行表[序号:序号 + 40]):
            段 = 后续 if 偏移 == 0 else 后续.strip()
            if 偏移 and 段.startswith(注释头):
                continue
            for 字 in 段:
                if 字 == "(":
                    深度 += 1
                    开了 = True
                    continue
                if 字 == ")":
                    深度 -= 1
                    if 深度 == 0:
                        break
                    continue
                if 开了:
                    缓冲 += 字
            if 开了 and 深度 == 0:
                break
            if 开了:
                缓冲 += ","
        for 形参名 in _形参名.findall(缓冲):
            if 是单字形参(形参名):
                出.append((序号 + 1, 函数名, 形参名))
    return 出


def 扫JS形参(路径: str) -> list:
    """JS/TS 的箭头函数 / 函数表达式 / 回调 / 闭包里的单字形参 ⇒ `[(行号, 形参名)]`。

    这些形参是**函数内局部**的：改名字面替换即可，但**不许**把同名的外层变量一起改（按行判）。
    """
    出 = []
    for 序号, 行 in enumerate(读行表(路径), 1):
        if 行.strip().startswith(注释头):
            continue
        for 匹配 in list(_箭头.finditer(行)) + list(_函数式.finditer(行)):
            形参段 = ""
            for 组 in 匹配.groups():
                if 组 is not None:
                    形参段 = 组
                    break
            for 形参名 in _JS名.findall(形参段):
                if 是单字形参(形参名):
                    出.append((序号, 形参名))
    return 出


def 遍历命名件(根目录: str = None):
    """走树产出扫描面里的件路径（后缀在 `命名后缀` 里，且不在 `跳过目录` 下）。"""
    起点 = str(根目录 or 仓根)
    for 目录, 子目录表, 件表 in os.walk(起点):
        子目录表[:] = [段 for 段 in 子目录表 if 段 not in 跳过目录]
        for 件 in 件表:
            if 件.endswith(命名后缀):
                yield os.path.join(目录, 件)


def 面读数(条表: list) -> dict:
    """一面的读数：处数 / 唯一名数 / 件数。"""
    return {"处": len(条表),
            "唯一名": len({条["形参名"] for 条 in 条表}),
            "件": len({条["路径"] for 条 in 条表})}


def 检形参(根目录: str = None, 上限: int = 25) -> dict:
    """走一遍全树的两套扫描 ⇒ `{"读数": {面: 读数}, "明细": {面: 前若干条}}`。

    每面读数见 `面读数`；每条明细 = `{"路径","行","函数名","形参名"}`（JS 面无函数名）。
    **不依赖索引库** —— 自己走树，没建索引也能跑。
    """
    起点 = str(根目录 or 仓根)
    面表 = {"签名面": [], "JS面": []}
    for 路径 in 遍历命名件(起点):
        短路径 = os.path.relpath(路径, 起点)
        if 路径.endswith((".js", ".ts", ".vue")):
            for 行, 形参名 in 扫JS形参(路径):
                面表["JS面"].append(
                    {"路径": 短路径, "行": 行, "函数名": "", "形参名": 形参名})
        else:
            for 行, 函数名, 形参名 in 扫签名形参(路径):
                面表["签名面"].append(
                    {"路径": 短路径, "行": 行, "函数名": 函数名, "形参名": 形参名})
    return {"读数": {面: 面读数(条表) for 面, 条表 in 面表.items()},
            "明细": {面: 条表[:上限] for 面, 条表 in 面表.items()}}


def 形参行(读数: dict = None) -> list:
    """把 `检形参` 的读数与明细排成给人读的行（**CLI 只 print，不做排版** —— 入口要保持薄）。"""
    if 读数 is None:
        读数 = 检形参()
    行表 = ["代码地图 · 检形参（扫描面 = 全树两套扫描；"
            "**索引看不见形参** ⇒ 本命令不依赖索引库）："]
    for 面名 in ("签名面", "JS面"):
        一面 = 读数["读数"][面名]
        行表.append("  %-6s %d 处 / %d 个唯一名 / %d 件"
                    % (面名, 一面["处"], 一面["唯一名"], 一面["件"]))
    for 面名 in ("签名面", "JS面"):
        for 一条 in 读数["明细"][面名]:
            落点 = ("%s(%s)" % (一条["函数名"], 一条["形参名"]) if 一条["函数名"]
                    else 一条["形参名"])
            行表.append("    [%s] %s:%d  %s"
                        % (面名, 一条["路径"], 一条["行"], 落点))
    return 行表
