"""打印 —— 把读数打成可读报告（原 `配色对拍.py::打印`，纯搬家）。"""


def 打印(读数):
    宽度, 高度 = 读数["尺寸"]
    print(f"=== {读数['路径']} ===")
    print(f"  尺寸 {宽度}x{高度} · 采样色数 {读数['色数']}")
    print(f"  纯黑 {读数['黑']} px（{读数['黑占比']:.2f}%）· 强边 {读数['强边']} · 斜面 {读数['斜面']}")
    print("  前 8 众数色：")
    for 颜色, 个数 in 读数["众数"]:
        print(f"    rgb{颜色}  {个数 * 4} px  ({个数 * 4 * 100 // (宽度 * 高度)}%)")
    print("  黑像素最多的 14 行：")
    for 个数, 行号 in sorted(((个数, 行号) for 行号, 个数 in enumerate(读数["逐行黑"])), reverse=True)[:14]:
        print(f"    y={行号:>3}  黑 {个数:>4}  ({个数 * 100 // 宽度}%)")
    print()
