def _解变长数组(模板字节, 游标, 资源id, 字段):
    """菜单/类/标题三个变长数组共用：0x0000 空、0xFFFF+序数、或 UTF-16 串。"""
    if 游标 + 2 > len(模板字节):
        raise 解析错误("对话框 %s 的 %s 数组越界 @0x%x" % (资源id, 字段, 游标))
    变量宽 = struct.unpack_from("<H", 模板字节, 游标)[0]
    if 变量宽 == 0:
        return None, 游标 + 2, "空"
    if 变量宽 == 0xFFFF:
        if 游标 + 4 > len(模板字节):
            raise 解析错误("对话框 %s 的 %s 序数越界 @0x%x" % (资源id, 字段, 游标))
        return struct.unpack_from("<H", 模板字节, 游标 + 2)[0], 游标 + 4, "序数"
    区间起点 = 游标
    while True:
        if 游标 + 2 > len(模板字节):
            raise 解析错误("对话框 %s 的 %s 串没有 NUL 结尾（从 0x%x 起）" % (资源id, 字段, 区间起点))
        if struct.unpack_from("<H", 模板字节, 游标)[0] == 0:
            break
        游标 += 2
    return 模板字节[区间起点:游标].decode("utf-16le"), 游标 + 2, "串"


def 解对话框(模板字节, 资源id):
    if len(模板字节) < 18:
        raise 解析错误("对话框 %s 短于 DLGTEMPLATE" % 资源id)
    扩展 = struct.unpack_from("<I", 模板字节, 0)[0] == 0xFFFF0001
    if 扩展:
        if len(模板字节) < 26:
            raise 解析错误("对话框 %s 声明 DLGTEMPLATEEX 但短于 26 字节" % 资源id)
        _, 签名, 帮助id, 扩展样式, 窗口样式, 控件数, 左边距, 顶边距, cx, cy = struct.unpack_from("<HHIIIHhhhh", 模板字节, 0)
        if 签名 != 0xFFFF:
            raise 解析错误("对话框 %s 的 DLGTEMPLATEEX 签名 0x%x != 0xFFFF" % (资源id, 签名))
        游标 = 26
    else:
        窗口样式, 扩展样式, 控件数, 左边距, 顶边距, cx, cy = struct.unpack_from("<IIHhhhh", 模板字节, 0)
        帮助id = None
        游标 = 18
    菜单, 游标, _ = _解变长数组(模板字节, 游标, 资源id, "菜单")
    类别值, 游标, _ = _解变长数组(模板字节, 游标, 资源id, "类")
    标题, 游标, 标题形 = _解变长数组(模板字节, 游标, 资源id, "标题")
    字体 = None
    if 窗口样式 & 0x40:
        if 扩展:
            if 游标 + 6 > len(模板字节):
                raise 解析错误("对话框 %s 的字体块越界" % 资源id)
            号值, 粗细, 斜体, 字符集 = struct.unpack_from("<HHBB", 模板字节, 游标)
            游标 += 6
            名称, 游标, _ = _解变长数组(模板字节, 游标, 资源id, "字体名")
            字体 = {"号": 号值, "粗细": 粗细, "斜体": 斜体, "字符集": 字符集, "名": 名称}
        else:
            if 游标 + 2 > len(模板字节):
                raise 解析错误("对话框 %s 的字号越界" % 资源id)
            号值 = struct.unpack_from("<H", 模板字节, 游标)[0]
            游标 += 2
            名称, 游标, _ = _解变长数组(模板字节, 游标, 资源id, "字体名")
            字体 = {"号": 号值, "名": 名称}
    控件 = []
    for 控件序 in range(控件数):
        游标 = (游标 + 3) & ~3
        if 扩展:
            if 游标 + 24 > len(模板字节):
                raise 解析错误("对话框 %s 第 %d 个控件头越界 @0x%x" % (资源id, 控件序, 游标))
            头部 = struct.unpack_from("<IIIhhhhI", 模板字节, 游标)
            帮助号, 扩样, 控件样式, 控件左, 控件顶, 控件宽, 控件高, 控件号 = 头部
            游标 += 24
        else:
            if 游标 + 18 > len(模板字节):
                raise 解析错误("对话框 %s 第 %d 个控件头越界 @0x%x" % (资源id, 控件序, 游标))
            控件样式, 扩样, 控件左, 控件顶, 控件宽, 控件高, 控件号 = struct.unpack_from("<IIhhhhH", 模板字节, 游标)
            帮助号 = None
            游标 += 18
        控件类号, 游标, 类形 = _解变长数组(模板字节, 游标, 资源id, "控件类")
        控件标题, 游标, 题形 = _解变长数组(模板字节, 游标, 资源id, "控件标题")
        if 游标 + 2 > len(模板字节):
            raise 解析错误("对话框 %s 第 %d 个控件的附加数据长度越界" % (资源id, 控件序))
        附加 = struct.unpack_from("<H", 模板字节, 游标)[0]
        游标 += 2
        if 游标 + 附加 > len(模板字节):
            raise 解析错误("对话框 %s 第 %d 个控件的附加数据越界（%d 字节）" % (资源id, 控件序, 附加))
        游标 += 附加
        if 附加 % 2:
            游标 += 1
        控件.append({"样式": 控件样式, "扩展样式": 扩样, "帮助id": 帮助号, "x": 控件左, "y": 控件顶, "cx": 控件宽,
                     "cy": 控件高, "id": 控件号, "类": 控件类号, "类形": 类形, "标题": 控件标题, "标题形": 题形,
                     "附加": 附加, "偏移": 游标})
    if 游标 != len(模板字节):
        raise 解析错误("对话框 %s 消耗 %d != 声明 %d：模板边界不自洽" % (资源id, 游标, len(模板字节)))
    return {"扩展": 扩展, "帮助id": 帮助id, "样式": 窗口样式, "扩展样式": 扩展样式, "控件数": 控件数,
            "x": 左边距, "y": 顶边距, "cx": cx, "cy": cy, "菜单": 菜单, "类": 类别值, "标题": 标题,
            "标题形": 标题形, "字体": 字体, "控件": 控件}


def 类名(待处理值, 形状标识):
    if 形状标识 == "空":
        return "（空）"
    if 形状标识 == "序数":
        return "预定义#%d=%s" % (待处理值, 预定义控件类.get(待处理值, "未登记"))
    return str(待处理值)


def 取显示文字(待处理值, 形状标识):
    if 形状标识 == "空":
        return ""
    if 形状标识 == "序数":
        return "#%d（资源序数）" % 待处理值
    return 待处理值
