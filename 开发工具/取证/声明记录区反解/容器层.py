# -*- coding: utf-8 -*-
"""容器层 —— `.e` / `.ec` 容器的段表反解（段边界靠扫描，本格式无段长字段）。"""

from .公共 import (
    文件头魔数, 段头长度, 段头标记首字节, 段头标记次字节, 段类型白名单,
    段类型_无名七, 段类型_程序加固, 解析错误,
)

# ── 容器层 ────────────────────────────────────────────────────────────────────

def 是段头(容器字节, 字节位置):
    """段头结构是否成立。判据与 `src/容器/反解定义.rs::是段头起点` 一致。"""
    if 字节位置 + 段头长度 > len(容器字节):
        return False
    段头字节 = 容器字节[字节位置:字节位置 + 段头长度]
    if 段头字节[0:2] != 段头标记首字节 or 段头字节[2:4] != 段头标记次字节:
        return False
    if 段头字节[8:10] != 段头标记首字节 or 段头字节[10] != 0x00:
        return False
    号值 = 段头字节[11]
    if 号值 not in 段类型白名单:
        return False
    尾部 = 段头字节[0x27:0x2C]
    if 号值 == 段类型_无名七:
        return 尾部 == b"\x00\x00\x00\x00\x00"
    if 号值 == 段类型_程序加固:
        return 尾部 == b"\x19\x73\x00\x03\x00"
    return 尾部 == b"\x19\x73\x00\x00\x00"


def 找下一段头(容器字节, 起点):
    for 候选位 in range(起点, len(容器字节) - 段头长度 + 1):
        if 是段头(容器字节, 候选位):
            return 候选位
    return None


def 反解容器(容器字节):
    """容器字节 → [(段类型, 段数据起点, 段数据止, 段头起点)]。段边界靠扫描（本格式无段长字段）。"""
    if len(容器字节) < len(文件头魔数) or 容器字节[:len(文件头魔数)] != 文件头魔数:
        raise 解析错误("无 CNWTEPRG 魔数，不是易程序容器")
    字节位置, 号段 = len(文件头魔数), []
    while 字节位置 < len(容器字节):
        if len(容器字节) - 字节位置 < 段头长度:
            raise 解析错误("段头截断 @0x%x（剩 %d 字节）" % (字节位置, len(容器字节) - 字节位置))
        if not 是段头(容器字节, 字节位置):
            raise 解析错误("段头标记/类型号不符 @0x%x" % 字节位置)
        号值 = 容器字节[字节位置 + 11]
        下一 = 找下一段头(容器字节, 字节位置 + 段头长度)
        尾部 = 下一 if 下一 is not None else len(容器字节)
        号段.append((号值, 字节位置 + 段头长度, 尾部, 字节位置))
        if 下一 is None:
            break
        字节位置 = 下一
    return 号段
