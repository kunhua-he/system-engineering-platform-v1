# -*- coding: utf-8 -*-
"""段数据层 —— 段数据头 + 支持库表 + 声明记录区起点（逐条 fail-closed）。"""

import struct

from .公共 import (
    段数据头长度, 段体魔数, 头偏移_保留, 头偏移_补零, 头偏移_补零长度,
    头偏移_体长, 头偏移_体首字段, 头偏移_体魔数, 段类型_程序, 解析错误,
)
from .容器层 import 反解容器

# ── 段数据层 ──────────────────────────────────────────────────────────────────

def 解段数据(段数据字节):
    """段数据字节 → 头字段 + 支持库表 + 声明记录区起点。逐条 fail-closed。"""
    if len(段数据字节) < 段数据头长度:
        raise 解析错误("段数据头截断 { 需要: %d, 实有: %d }" % (段数据头长度, len(段数据字节)))
    段序号, 保留, 校验值, 体长 = struct.unpack_from("<IIII", 段数据字节, 0)
    if 保留 != 0:
        raise 解析错误("段数据头保留非零 { 位置: %d, 实取: %d }" % (头偏移_保留, 保留))
    if 段数据字节[头偏移_补零:头偏移_补零 + 头偏移_补零长度] != b"\x00" * 头偏移_补零长度:
        raise 解析错误("段数据头补零非零")
    if 体长 != len(段数据字节) - 段数据头长度:
        raise 解析错误("体长不符 { 头内: %d, 实有: %d }" % (体长, len(段数据字节) - 段数据头长度))
    体首字段, 实取魔数 = struct.unpack_from("<II", 段数据字节, 头偏移_体首字段)
    if 实取魔数 != 段体魔数:
        raise 解析错误("段体魔数不符 { 实取: 0x%08x }" % 实取魔数)

    游标 = 段数据头长度 + 8

    def 读长度前缀(游标, 第几, 元素宽):
        if 游标 + 4 > len(段数据字节):
            raise 解析错误("数组越界 { 第几: %d }" % 第几)
        前缀 = struct.unpack_from("<I", 段数据字节, 游标)[0]
        游标 += 4
        if 前缀 % 元素宽 != 0:
            raise 解析错误("数组长度前缀非整元素 { 第几: %d, 前缀: %d, 元素宽: %d }"
                        % (第几, 前缀, 元素宽))
        if 前缀 > len(段数据字节) - 游标:
            raise 解析错误("数组越界 { 第几: %d, 前缀: %d, 剩余: %d }" % (第几, 前缀, len(段数据字节) - 游标))
        return 前缀, 游标

    首数组长, 游标 = 读长度前缀(游标, 1, 4)
    首数组 = list(struct.unpack_from("<%dI" % (首数组长 // 4), 段数据字节, 游标)) if 首数组长 else []
    游标 += 首数组长
    次数组长, 游标 = 读长度前缀(游标, 2, 2)
    次数组 = list(struct.unpack_from("<%dH" % (次数组长 // 2), 段数据字节, 游标)) if 次数组长 else []
    游标 += 次数组长
    末数组长, 游标 = 读长度前缀(游标, 3, 2)
    末数组 = list(struct.unpack_from("<%dH" % (末数组长 // 2), 段数据字节, 游标)) if 末数组长 else []
    游标 += 末数组长
    if 游标 + 2 > len(段数据字节):
        raise 解析错误("数组越界 { 第几: 4 }")
    声明数 = struct.unpack_from("<H", 段数据字节, 游标)[0]
    游标 += 2
    if 声明数 != len(首数组) or len(次数组) != len(首数组) or len(末数组) != len(首数组):
        raise 解析错误("支持库数不符 { 数组元素数: %d, 声明数: %d }" % (len(首数组), 声明数))
    引用表 = []
    for 序号 in range(声明数):
        if 游标 + 4 > len(段数据字节):
            raise 解析错误("支持库引用越界 { 第几条: %d }" % 序号)
        串长 = struct.unpack_from("<I", 段数据字节, 游标)[0]
        游标 += 4
        if 串长 > len(段数据字节) - 游标:
            raise 解析错误("支持库引用越界 { 第几条: %d, 串长: %d, 剩余: %d }"
                        % (序号, 串长, len(段数据字节) - 游标))
        引用表.append(段数据字节[游标:游标 + 串长])
        游标 += 串长
    return {
        "段序号": 段序号, "保留": 保留, "校验值": 校验值, "体长": 体长,
        "体首字段": 体首字段, "首数组": 首数组, "次数组": 次数组, "末数组": 末数组,
        "引用表": 引用表, "声明记录区起点": 游标,
    }


def 取声明记录区(容器字节):
    """容器字节 → [(段类型, 段数据起点, 声明记录区起点(绝对), 声明记录区) ]。"""
    结果 = []
    for 号值, 区间起点, 区间终点, _声明记录区 in 反解容器(容器字节):
        if 号值 != 段类型_程序:
            continue
        段数据字节 = 容器字节[区间起点:区间终点]
        段数据读数 = 解段数据(段数据字节)
        区起 = 段数据读数["声明记录区起点"]
        结果.append((号值, 区间起点, 区间起点 + 区起, 段数据字节[区起:], 段数据读数))
    return 结果
