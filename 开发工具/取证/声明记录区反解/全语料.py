# -*- coding: utf-8 -*-
"""全语料 —— 扫整个语料目录的硬读数（**分片**与**归并**两条路，走同一条归并与同一个打印口）。

**为什么必须拆成两条路**：全量的总 CPU 时间远大于单条命令的 5 秒预算
（`项目文档/决策记录/2026-09-27_所有运行五秒硬顶.md` §一），故「一条命令跑完全量」**不可能**进顶 ——
32 进程已是最快形态，实测仍远超顶。解法是裁决 §三.2/§三.3 的两条腿：
  · `扫一片`（`--分片 i/n`）：把全量拆成 **n 条命令**，每条只算一片 ⇒ 每条的墙钟由**片的大小**决定；
  · `扫全部`（`--全部`）：**只归并**已算好的逐件缓存（缓存齐时几百毫秒）⇒ 重活不在命令路里。

逐件结果按 `(路径, 大小, mtime)` 缓存（`逐文件.py`）⇒ 语料只读、mtime 稳定时，
逐件读数是纯函数，故「谁算的」不影响「归并出什么」：分片命令算出来的与串行算出来的逐字相同
（`自测` 里有一条反向样本钉这件事）。
**缓存不齐时 `扫全部` 报出缺多少件并非 0**，不静默少算。
"""

from .报告 import 出全语料读数
from .分片 import 文件表, 归并读数, 扫分片
from .运行数据根 import 缓存目录
from .逐文件 import 取缓存

脚本路径 = "开发工具/取证/声明记录区反解.py"


def 扫一片(目录路径, 序号, 片数):
    """只算**第 i 片（共 n 片）**，打印本片读数。全量由「跑齐 n 条分片命令」完成。"""
    缓存根目录 = 缓存目录()
    运行汇总, 本片数, 命中 = 扫分片(目录路径, 序号, 片数, 缓存根目录)
    出全语料读数(运行汇总, 目录路径, 附注="第 %d/%d 片 · 本片文件 %d · 本片缓存命中 %d（命中在算之前数）"
              % (序号, 片数, 本片数, 命中))
    return 0


def 扫全部(目录路径, 进程数=None):
    """全量 = **读齐逐件缓存 → 归并 → 打印**。本命令**不再自身算**（裁决 §三.3「重活移出命令路」）。

    `进程数` 形参只为兼容旧调用面而留（归并是加法，不并行）；多进程那条路仍在
    `分片.py::扫并发` —— 它是「串行 == 分片」等价性证明的参照实现，由 `自测` 使用。
    """
    缓存根目录 = 缓存目录()
    项表 = 文件表(目录路径)
    if 缓存根目录 is None:
        print("✗ 取不到逐件缓存目录（运行数据根）⇒ 归并没有来源。")
        打印补缓存命令(目录路径)
        return 1
    if not 项表:
        print("✗ 语料目录里没有语料件（%s 下 *.e / *.ec / *.E / *.EC）⇒ 没有可归并的东西。" % 目录路径)
        return 1
    逐件, 缺件表 = [], []
    for 样本路径 in 项表:
        读数 = 取缓存(缓存根目录, 样本路径)
        (逐件 if 读数 is not None else 缺件表).append(读数 if 读数 is not None else 样本路径)
    if 缺件表:
        print("✗ 逐件缓存不齐：已算 %d / %d 件，缺 %d 件。" % (len(逐件), len(项表), len(缺件表)))
        print("  为什么本命令不算：全量的总 CPU 时间远超单条命令的 5 秒预算 ⇒ 按裁决 §三.3"
              "把重活移出命令路，本命令只归并。")
        for 样本路径 in 缺件表[:5]:
            print("    · 缺 %s" % 样本路径)
        if len(缺件表) > 5:
            print("    … 另 %d 件" % (len(缺件表) - 5))
        打印补缓存命令(目录路径)
        return 1
    运行汇总 = 归并读数(逐件)
    出全语料读数(运行汇总, 目录路径, 附注="全量 · 逐件缓存齐 %d/%d（本命令只归并，不算）" % (len(项表), len(项表)))
    return 0


def 打印补缓存命令(目录路径):
    """把「怎么把缓存补齐」印成能直接粘的命令。

    **分三步**，因为片数只能**从实测**推、而冷缓存里一件实测都没有（`建议分片数` 此时返回 0，
    直接拿它做循环会空转 —— 所以先跑一片把系数量出来）：
      ① 跑一片量系数。n 取**大**：片小只会更慢、更安全（门禁超顶会报红兜底），
         绝不会因为片小而出错。这一片的件进缓存 ⇒ 有实测毫秒了。
      ② 拿 `--建议分片数`（由刚量到的 `ms/MB` 推全量片数）跑齐 0..N-1。
      ③ `--全部` 归并出全量读数。
    """
    打印 = print
    打印("  怎么补（每条命令各自都在硬顶内；片数由实测推，不写死）：")
    打印("    ① 先跑一片，量出「每 MB 多少毫秒」（n 取大：片小只会更慢、更安全）：")
    打印("       python3 %s --分片 0/120 --目录 %s" % (脚本路径, 目录路径))
    打印("    ② 问片数并跑齐（`--建议分片数` 用刚量到的系数推全量片数）：")
    打印("       N=$(python3 %s --建议分片数 --目录 %s)" % (脚本路径, 目录路径))
    打印("       for i in $(seq 0 $((N-1))); do python3 %s --分片 $i/$N --目录 %s || break; done"
         % (脚本路径, 目录路径))
    打印("    ③ 归并出全量读数：")
    打印("       python3 %s --全部 --目录 %s" % (脚本路径, 目录路径))
