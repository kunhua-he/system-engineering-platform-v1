# -*- coding: utf-8 -*-
"""全语料 —— 扫整个语料目录的硬读数（**分片**与**全量**两条路，走同一条归并与同一个打印口）。

**为什么拆成两条路**：全量的总 CPU 时间远大于单条命令的 5 秒预算（`所有运行五秒硬顶.md` §一），
故「一条命令跑完全量」在冷缓存下**不可能**进顶。解法是裁决 §三.2/§三.3 的两条腿：
  · `扫一片`（`--分片 i/n`）：把全量拆成 n 条命令，每条只算一片 ⇒ 每条的墙钟由**片的大小**决定；
  · `扫全部`（`--全部`）：全量，多进程 + 逐件缓存 ⇒ 它是「预热缓存 / 复跑读数」的最快形态。

**预热后 `--全部` 也进顶**：逐件结果按 `(路径, 大小, mtime)` 缓存（`逐文件.py`）⇒ 语料只读、
mtime 稳定时，第二遍起 `--全部` 只做归并，不再走「取区 / 走记录」那两段重活。
**缓存冷时 `--全部` 超顶是如实读数，不是被藏起来**（命令墙钟由壳自量自门禁报出）。
"""

from .报告 import 出全语料读数
from .分片 import 文件表, 扫分片, 扫并发
from .运行数据根 import 缓存目录
from .逐文件 import 缓存覆盖数


def 扫一片(目录, i, n):
    """只算**第 i 片（共 n 片）**，打印本片读数。全量由「跑齐 n 条分片命令」完成。"""
    缓 = 缓存目录()
    汇总, 本片数, 命中 = 扫分片(目录, i, n, 缓)
    出全语料读数(汇总, 目录, 附="第 %d/%d 片 · 本片文件 %d · 本片缓存命中 %d（命中在算之前数）"
              % (i, n, 本片数, 命中))
    return 0


def 扫全部(目录, 进程数=None):
    """全量：多进程分片 + 逐件缓存。缓存冷时本命令会超顶（如实报，由壳自门禁判红）。"""
    缓 = 缓存目录()
    表 = 文件表(目录)
    命中 = 缓存覆盖数(缓, 表) if 缓 is not None else 0
    汇总, 用进程 = 扫并发(目录, 缓, 进程数)
    出全语料读数(汇总, 目录, 附="全量 · 多进程 %d · 缓存命中 %d/%d"
              % (用进程, 命中, len(表)))
    return 0
