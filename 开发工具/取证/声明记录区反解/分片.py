# -*- coding: utf-8 -*-
"""分片 —— 语料枚举 · 均衡切分 · 逐件归并 · 单进程跑一片 / 多进程跑全量。

**为什么必须多进程而不是多线程**：本扫描是**纯 Python 字节循环**（逐字节试四种记录形态），
GIL 之下线程池等于没并行 —— 这不是推测，是 `2026-09-27_所有运行五秒硬顶.md` §二
在 `一键验证` 上实测过的（线程池 ≈ 串行）。故这里用 **`fork` 进程池**（同仓内先例）。

**切分均衡按「实测耗时」而不是按「文件数」**：逐件读数里记了本件实测毫秒（`逐文件.py`），
切分优先拿它做贪心均衡（大件先落最空的一片）；缓存还没有的件退回**按字节数**估
（大小与耗时同向，实测如此）。**不写死任何耗时系数** —— 系数是从缓存里现读的。

**归并是加法**：段数/首4零/全零/未解/字节 相加，记录计数逐类相加，区长表拼接（min/中位/max
在全语料层算），坏件列表拼接。逐件读数与归并结果都与「一件一件串行算」逐字相同。
"""

import glob
import os

from .逐文件 import 带缓存, 缓存覆盖数, 取缓存

语料后缀 = ("*.e", "*.ec", "*.E", "*.EC")


def 用进程池() -> bool:
    """平台有没有 `fork`。**按仓内先例**（`构建装配/一键验证/一键验证/验证.py::用判据进程池`）：
    本类扫描是 CPU 密集的纯 Python 字节循环，GIL 之下线程池拿不到并行 ⇒ 只能进程池；
    没有 `fork` 的平台**退回串行**（退回线程是「假装并行」，本件不做）。"""
    try:
        import multiprocessing

        return "fork" in multiprocessing.get_all_start_methods()
    except Exception:
        return False


def 文件表(目录) -> list:
    """语料枚举：四种后缀、递归、去重、按路径排序（次序固定 ⇒ 切分可复现）。"""
    命中 = []
    for 后缀 in 语料后缀:
        命中 += glob.glob(os.path.join(目录, "**", 后缀), recursive=True)
    return sorted(set(命中))


def 解析分片形(文) -> tuple:
    """`"i/n"` → `(i, n)`。**形状错就抛**（不默认、不猜）—— 分片编号猜错等于少算/重算一片。"""
    if not 文 or "/" not in 文:
        raise ValueError("分片形必须是 `i/n`（例：0/8），实得 %r" % (文,))
    左, _, 右 = 文.partition("/")
    try:
        序号, 片数 = int(左), int(右)
    except ValueError:
        raise ValueError("分片形必须是整数 `i/n`（例：0/8），实得 %r" % (文,))
    if 片数 < 1:
        raise ValueError("分片总数必须 ≥ 1，实得 %d" % 片数)
    if not (0 <= 序号 < 片数):
        raise ValueError("分片序号越界：i=%d 不在 [0, %d)" % (序号, 片数))
    return 序号, 片数


def 权重表(文件表) -> dict:
    """每件的切分权重 = **字节数**（同向估计，`大小 ↔ 耗时` 实测同向）。

    ★ **不许拿缓存里的实测耗时来切分**（本件早先版本这么干过，是个静默的正确性 bug）：
    分片是**多条独立命令**，每条自己算一次切分；若权重随缓存填充而变，则先跑的第 i 片与后跑的
    第 j 片会**切在不同位置** ⇒ 有的件被算两遍、有的件一次都没算，而两边读数都不报错。
    ⇒ 权重必须是**只由盘面决定**的量（字节数就是），与缓存状态无关 ⇒ 同 `(目录, n)` 恒得同一刀。
    """
    结果 = {}
    for 件 in 文件表:
        try:
            结果[件] = max(1, os.path.getsize(件))
        except OSError:
            结果[件] = 1
    return 结果


def 切分(文件表, 片数: int) -> list:
    """贪心均衡切成 n 片（大件先落当前最空的一片）⇒ 各片权重和尽量相等。

    **确定性**：只看文件大小与路径 ⇒ 同 `(文件表, n)` 每次都得同一刀（多进程/多命令可复现）。
    n ≤ 1 时退化为「一片 = 全量」；空片照给，保持「第 i/n 片」编号稳定。
    """
    if 片数 < 1:
        片数 = 1
    if 片数 == 1:
        return [sorted(文件表)]
    片 = [[] for _ in range(片数)]
    和 = [0] * 片数
    权重 = 权重表(文件表)
    for 件 in sorted(文件表, key=lambda 件: (-权重[件], 件)):
        片号 = min(range(片数), key=lambda 序号: (和[序号], 序号))
        片[片号].append(件)
        和[片号] += 权重[件]
    return [sorted(件) for 件 in 片]


def 归并(逐件表) -> dict:
    """把逐件读数加成一份全语料读数（与串行逐件算**逐字相同**）。"""
    汇总 = {"文件": len(逐件表), "段数": 0, "区长": [], "首4零": 0, "全零": 0,
            "计": {}, "未解": 0, "字节": 0, "坏": []}
    for 读数 in 逐件表:
        汇总["段数"] += 读数.get("段数", 0)
        汇总["区长"].extend(读数.get("区长", []))
        汇总["首4零"] += 读数.get("首4零", 0)
        汇总["全零"] += 读数.get("全零", 0)
        汇总["未解"] += 读数.get("未解", 0)
        汇总["字节"] += 读数.get("字节", 0)
        for 片号, 值 in (读数.get("计") or {}).items():
            汇总["计"][片号] = 汇总["计"].get(片号, 0) + 值
        if 读数.get("坏"):
            汇总["坏"].append((读数["键"][0] if 读数.get("键") else "?", 读数["坏"]))
    汇总["区长"].sort()
    return 汇总


def 归并汇总(汇总表) -> dict:
    """把**多片的汇总**加成一份全量汇总（`--分片` 的驱动侧用它：片各自跑完，再并一次）。

    与 `归并` 分开是因为两者输入形状不同（逐件读数 / 已归并的汇总）；但**输出必须同形**
    ⇒ 「跑齐 n 片再并」与「一条命令全量」的读数逐字相同（`自测` 里钉这件事）。
    """
    结果 = {"文件": 0, "段数": 0, "区长": [], "首4零": 0, "全零": 0,
          "计": {}, "未解": 0, "字节": 0, "坏": []}
    for 汇总 in 汇总表:
        结果["文件"] += 汇总.get("文件", 0)
        结果["段数"] += 汇总.get("段数", 0)
        结果["区长"].extend(汇总.get("区长", []))
        结果["首4零"] += 汇总.get("首4零", 0)
        结果["全零"] += 汇总.get("全零", 0)
        结果["未解"] += 汇总.get("未解", 0)
        结果["字节"] += 汇总.get("字节", 0)
        for 片号, 值 in (汇总.get("计") or {}).items():
            结果["计"][片号] = 结果["计"].get(片号, 0) + 值
        结果["坏"].extend(汇总.get("坏", []))
    结果["区长"].sort()
    return 结果



def 建议分片数(目录, 缓存目录, 目标毫秒: int = 4000) -> tuple:
    """建议分片数 `n` = `ceil(总耗时估计 / 目标毫秒)`。返回 `(n, 依据说明)`；估不出来给 `(0, 为什么)`。

    **为什么需要它**：全量的计算只能由「跑齐 n 条 `--分片 i/n`」完成（见 `全语料.py::扫全部`），
    而 `n` 定小了某一片就超顶。`n` 不该由人拍 —— 它随语料增长而变，写死必漂。

    **估计怎么来**：优先用**逐件缓存里记的实测毫秒**（`逐文件.py` 的 `读数["毫秒"]`）；
    还没实测的件按**字节数 × 系数**推，系数 = 已实测件的 `中位(毫秒/字节)`（同向，实测如此）。
    一件都没实测过 ⇒ 返回 0 并说明「缓存冷」——**不编一个数**。

    ★ **本函数只出建议，不参与切分**：切分的权重永远是字节数（`权重表` 的注释说明了为什么
    —— 权重随缓存漂移会让先跑的片与后跑的片切在不同位置，静默漏算）。本函数只是把
    「要跑几条命令」这个数从实测里算出来给人看，读数与实际切分互不影响。
    """
    表 = 文件表(目录)
    if not 表:
        return 0, "语料目录里没有语料件 ⇒ 无可算"
    字节 = 权重表(表)
    实测 = {}
    for 件 in 表:
        读数 = 取缓存(缓存目录, 件)
        if isinstance(读数, dict) and isinstance(读数.get("毫秒"), int):
            实测[件] = 读数["毫秒"]
    if not 实测:
        return 0, ("缓存冷：一件都没有实测毫秒 ⇒ 估不出片数（**不编数**）。"
                   "先跑一片把系数量出来，n 要取**大**（片小只会更慢、更安全；"
                   "门禁超顶会报红兜底）：`--分片 0/120`，再问一次。")
    比 = sorted(实测[件] / max(1, 字节[件]) for 件 in 实测)
    系数 = 比[len(比) // 2]  # 中位数，抗单件离群（最大单件实测占比很小，见报告）
    总估 = sum(实测.get(件, 字节[件] * 系数) for 件 in 表)
    片数 = max(1, -(-int(总估) // max(1, 目标毫秒)))  # 上取整
    依据 = ("实测 %d / %d 件（其余按字节推，系数 %.3f ms/MB）· 总估 %d ms · "
            "目标 %d ms/片 ⇒ n = %d" % (len(实测), len(表), 系数 * 1048576.0,
                                        int(总估), 目标毫秒, 片数))
    return 片数, 依据


def _跑片(参数) -> list:
    """进程池的工作体：算一片的逐件读数。**模块级函数** —— 池子按名字反序列化它，藏在闭包里就找不到。"""
    片, 缓存目录 = 参数
    return [带缓存(缓存目录, 件) for 件 in 片]


def 扫分片(目录, 序号: int, 片数: int, 缓存目录) -> tuple:
    """跑**第 i 片（共 n 片）**：片内串行、逐件走缓存。返回 `(汇总, 本片文件数, 本片缓存命中数)`。

    **命中数在算之前数**（算完再数就恒等于本片文件数 —— 那是「刚写进去的」冒充「本来就在的」）。
    片内**不再开进程池**：分片的意义就是把重活拆到**多条命令**里，片内再并发等于把核数二次分配
    （n 片 × 每片 32 进程 ⇒ 超订）。要全量并发请走 `扫并发`。
    """
    表 = 文件表(目录)
    片 = 切分(表, 片数)
    if not (0 <= 序号 < 片数):
        raise ValueError("分片序号越界：i=%d 不在 [0, %d)" % (序号, 片数))
    本片 = 片[序号]
    命中 = 缓存覆盖数(缓存目录, 本片)
    return 归并([带缓存(缓存目录, 件) for 件 in 本片]), len(本片), 命中


def 扫并发(目录, 缓存目录, 进程数=None) -> tuple:
    """跑**全量**：按进程数均衡切分后多进程归并。返回 `(汇总, 实际进程数)`。

    这是「一条命令跑完全量」的最快形态 —— 但**最快不等于进顶**：全量的总 CPU 时间远大于
    单条命令的 5 秒预算，故它是否达标取决于语料是否已被分片命令**预热进缓存**。
    `fork` 起不来 ⇒ 退回**串行**（不是线程：见模块注释），并如实把实际进程数报成 1。
    """
    上限 = os.cpu_count() or 1
    进程数 = 上限 if 进程数 is None else max(1, min(进程数, 上限))
    表 = 文件表(目录)
    if not 表:
        return 归并([]), 进程数
    if 进程数 == 1 or not 用进程池():
        return 归并([带缓存(缓存目录, 件) for 件 in 表]), 1
    import multiprocessing

    片 = 切分(表, 进程数)
    try:
        with multiprocessing.get_context("fork").Pool(processes=进程数) as 池:
            各片 = 池.map(_跑片, [(片, 缓存目录) for 片 in 片])
    except Exception:
        return 归并([带缓存(缓存目录, 件) for 件 in 表]), 1
    逐件 = [读数 for 片读数 in 各片 for 读数 in 片读数]
    return 归并(逐件), 进程数
