def _去耗时(读数: dict) -> dict:
    """比较读数时剔掉 `毫秒`：它是**实测耗时**，两次跑必然不同，不属于「读数是否相同」的面。"""
    结果 = dict(读数)
    结果.pop("毫秒", None)
    return 结果


def _缓存与分片(样本, 失败: list) -> None:
    """② 缓存一致性 + ③ 分片不重不漏 / 归并等价（含多进程）。"""
    基准 = 单件读数(样本)
    临时缓存 = Path(tempfile.mkdtemp(prefix="声明记录区反解_自测_缓存_"))
    try:
        不命中 = 带缓存(临时缓存, 样本)
        命中 = 带缓存(临时缓存, 样本)
        if _去耗时(基准) == _去耗时(不命中) == _去耗时(命中):
            print("  ✓ 缓存一致性：不命中 / 命中 逐字同读数（缓存不是正确性来源）")
        else:
            print("  ✗ 缓存一致性：命中与不命中读数不同 —— 缓存冒充了正确性")
            失败.append("缓存一致性")
    finally:
        shutil.rmtree(临时缓存, ignore_errors=True)

    临时语料 = Path(tempfile.mkdtemp(prefix="声明记录区反解_自测_分片_"))
    try:
        表 = []
        for 序号 in range(4):
            路 = 临时语料 / "样本{}.e".format(序号)
            shutil.copy2(样本, 路)
            表.append(str(路))
        表 = sorted(表)
        片 = 切分(表, 2)
        覆盖 = sorted(件 for 一片 in 片 for 件 in 一片)
        if 覆盖 == 表 and len(覆盖) == len(set(覆盖)):
            print("  ✓ 分片不重不漏：切 2 片覆盖全部件且无重复")
        else:
            print("  ✗ 分片切分有重/有漏：%d 件 → %d 件" % (len(表), len(覆盖)))
            失败.append("分片覆盖")
        # 切分**确定性**（反向样本）：分片是多条独立命令，每条自身算一次切分 ⇒ 权重若随缓存状态
        # 而变，先跑的第 i 片与后跑的第 j 片会切在不同位置（有的件算两遍、有的没算），两边都不报错。
        临时刀 = Path(tempfile.mkdtemp(prefix="声明记录区反解_自测_切分_"))
        try:
            片一 = 切分(表, 3)
            for 件 in 表:
                带缓存(临时刀, 件)  # 把缓存填满（含实测耗时）
            片二 = 切分(表, 3)
            if 片一 == 片二:
                print("  ✓ 切分确定性：缓存从空到满，同一 (文件表, n) 得同一刀（分片可复现）")
            else:
                print("  ✗ 切分随缓存状态漂移 —— 分片会漏算/重算")
                失败.append("切分确定性")
        finally:
            shutil.rmtree(临时刀, ignore_errors=True)
        全 = 归并([单件读数(件) for 件 in 表])
        并 = 归并([带缓存(None, 件) for 件 in 表])
        扫片 = 归并汇总([扫分片(临时语料, 下标, 2, None)[0] for 下标 in range(2)])
        if 全 == 并 == 扫片:
            print("  ✓ 归并等价：串行逐件 == 缓存逐件 == 两片各扫再并（读数逐字相同）")
        else:
            print("  ✗ 归并等价：分片/缓存把读数改掉了")
            失败.append("归并等价")
        try:
            并发 = 扫并发(临时语料, None, 2)[0]
            if 并发 == 全:
                print("  ✓ 多进程等价：2 进程归并 == 串行逐件（进程池不改读数）")
            else:
                print("  ✗ 多进程等价：进程池归并出的读数与串行不同")
                失败.append("多进程等价")
        except Exception as ex:  # 进程池起不来也是「分片路不可用」，必须报出来
            print("  ✗ 多进程起不来：%s" % ex)
            失败.append("多进程起不来")
    finally:
        shutil.rmtree(临时语料, ignore_errors=True)


def 自测(样本="/tmp/易语言源码/lib/krnln/samples/第一个程序.e"):
    with open(样本, "rb") as fh:
        好 = fh.read()
    段 = 反解容器(好)
    段号, 段起, 段止, 头起 = [一片 for 一片 in 段 if 一片[0] == 段类型_程序][0]
    段数据读数 = 解段数据(好[段起:段止])
    区起 = 段数据读数["声明记录区起点"]

    例 = [
        ("空文件", b""),
        ("只有魔数 8 字节", 好[:8]),
        ("段头截断到 20 字节", 好[:8 + 20]),
        ("截断到程序段数据中间", 好[:段起 + 100]),
        ("随机字节流", bytes(range(256)) * 8),
        ("魔数改坏", b"ZZ" + 好[2:]),
    ]
    # 段头级
    坏样本字节 = bytearray(好); 坏样本字节[8:10] = b"\x00\x00"
    例.append(("段头标记首改坏", bytes(坏样本字节)))
    坏样本字节 = bytearray(好); 坏样本字节[10:12] = b"\x00\x00"
    例.append(("段头标记次改坏", bytes(坏样本字节)))
    坏样本字节 = bytearray(好); 坏样本字节[8 + 11] = 0x99
    例.append(("段类型号越界 0x99", bytes(坏样本字节)))
    坏样本字节 = bytearray(好); 坏样本字节[8 + 0x2A] = 0x03
    例.append(("段头尾标志改成 0x03（仅类型255合法）", bytes(坏样本字节)))
    # 段数据级（段数据起 = 段起）
    坏样本字节 = bytearray(好); 坏样本字节[段起 + 头偏移_保留:段起 + 头偏移_保留 + 4] = (1).to_bytes(4, "little")
    例.append(("段数据头保留改成 1", bytes(坏样本字节)))
    坏样本字节 = bytearray(好); 坏样本字节[段起 + 头偏移_补零 + 5] = 0x7F
    例.append(("段数据头补零区塞非零", bytes(坏样本字节)))
    坏样本字节 = bytearray(好); 坏样本字节[段起 + 头偏移_体长:段起 + 头偏移_体长 + 4] = (段数据读数["体长"] + 1).to_bytes(4, "little")
    例.append(("体长字段 +1", bytes(坏样本字节)))
    坏样本字节 = bytearray(好); 坏样本字节[段起 + 头偏移_体魔数:段起 + 头偏移_体魔数 + 4] = (段体魔数 ^ 1).to_bytes(4, "little")
    例.append(("段体魔数改坏", bytes(坏样本字节)))
    # 支持库表级
    首数组前缀位 = 段起 + 段数据头长度 + 8
    声明数位 = 首数组前缀位 + 4 + 4 * len(段数据读数["首数组"]) + 4 + 2 * len(段数据读数["次数组"]) + 4 + 2 * len(段数据读数["末数组"])
    坏样本字节 = bytearray(好); 坏样本字节[首数组前缀位:首数组前缀位 + 4] = (6).to_bytes(4, "little")
    例.append(("首数组长度前缀改成 6（非 4 倍数）", bytes(坏样本字节)))
    坏样本字节 = bytearray(好); 坏样本字节[首数组前缀位:首数组前缀位 + 4] = (0x00FFFFFC).to_bytes(4, "little")
    例.append(("首数组长度前缀改成 0x00FFFFFC（越界）", bytes(坏样本字节)))
    坏样本字节 = bytearray(好); 坏样本字节[声明数位:声明数位 + 2] = (0).to_bytes(2, "little")
    例.append(("支持库数 u16 改成 0（数组仍 1）", bytes(坏样本字节)))
    引用位 = 声明数位 + 2
    坏样本字节 = bytearray(好); 坏样本字节[引用位:引用位 + 4] = (0x00FFFFFF).to_bytes(4, "little")
    例.append(("第一条引用串长改成 0x00FFFFFF（越界）", bytes(坏样本字节)))
    # 声明记录区级：整区截断（把段数据尾部砍掉，体长随之不符）
    坏样本字节 = bytearray(好); del 坏样本字节[段止 - 40:段止]
    例.append(("声明记录区被砍 40 字节", bytes(坏样本字节)))
    # 声明记录区全零（空程序）—— 这是**合法**输入，必须成功
    好零 = bytearray(好)
    好零[段起 + 区起:段止] = b"\x00" * (段止 - 段起 - 区起)
    合法例 = [("声明记录区整区清 0（空程序）", bytes(好零))]

    print("自测：喂 %d 个坏样本 + %d 个合法边界样本" % (len(例), len(合法例)))
    print("判据：坏样本**不许产出声明记录区**（报错 或 零条程序段）；合法样本必须过。")
    报错数 = 未产出数 = 假绿 = 失败 = 0
    for 名, 数据 in 例:
        try:
            区表 = 取声明记录区(数据)
        except 解析错误 as ex:
            print("  ✓ %-36s 报错：%s" % (名, ex))
            报错数 += 1
            continue
        except (struct.error, IndexError, ValueError, OverflowError, TypeError) as ex:
            print("  ✗ %-36s 抛了非解析错误（%s: %s）" % (名, type(ex).__name__, ex))
            失败 += 1
            continue
        if not 区表:
            print("  ✓ %-36s 未产出（0 条程序段 ⇒ 无声明记录区）" % 名)
            未产出数 += 1
        else:
            print("  ✗ %-36s 竟产出 %d 条声明记录区 —— 假绿" % (名, len(区表)))
            假绿 += 1
            失败 += 1
    for 名, 数据 in 合法例:
        try:
            区表 = 取声明记录区(数据)
            assert 区表 and len(区表[0][3]) > 0
            print("  ✓ %-36s 通过（区 %d 字节，头 4 字节 %s）"
                  % (名, len(区表[0][3]), 区表[0][3][:4].hex(" ")))
        except Exception as ex:
            print("  ✗ %-36s 合法样本反而失败：%s" % (名, ex))
            失败 += 1
    try:
        区表 = 取声明记录区(好)
        记录, 未解 = 走记录(区表[0][3])
        print("  ✓ 正向样本 %s：程序段 %d 个，声明记录区 %d 字节，可证记录 %d 条（未解 %d 字节）"
              % (os.path.basename(样本), len(区表), len(区表[0][3]), len(记录), 未解))
    except 解析错误 as ex:
        print("  ✗ 正向样本反而失败：%s" % ex)
        失败 += 1
    if 报错数 < 8:
        print("  ✗ 真正报错的坏样本只有 %d 个（要求 ≥ 8）" % 报错数)
        失败 += 1

    追加失败 = []
    _缓存与分片(样本, 追加失败)
    失败 += len(追加失败)

    print("自测读数：坏样本 %d（报错 %d · 未产出 %d · 假绿 %d）· 失败合计 %d"
          % (len(例), 报错数, 未产出数, 假绿, 失败))
    print("自测结论：%s" % ("通过" if 失败 == 0 else "不通过"))
    return 1 if 失败 else 0
