"""自测 —— 反向样本断言（判据可信性，零假绿）。

三层：
  ① **字节层**（原有）：19 个坏样本不许产出声明记录区 + 1 个合法边界样本必须过；
  ② **缓存层**：缓存是**可选加速**，不是正确性来源 —— 命中与不命中必须逐字同读数；
  ③ **分片层**：切分必须**不重不漏**覆盖全部件，且「分片归并」与「串行逐件」必须逐字同读数
     （多进程同理）—— 否则分片会把读数改掉，那是分片最危险的失效方式（静默改数）。
"""

