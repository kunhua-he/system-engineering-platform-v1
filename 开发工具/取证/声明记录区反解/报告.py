def 十六进制(区字节, 基=0, 宽度=16, 上限=None):
    实取长 = len(区字节) if 上限 is None else min(len(区字节), 上限)
    源码行 = []
    for 位置 in range(0, 实取长, 宽度):
        字节片 = 区字节[位置:位置 + 宽度]
        try:
            可打印文本 = 字节片.decode("gbk")
        except Exception:
            可打印文本 = ""
        可打印文本 = "".join(ch if 32 <= ord(ch) < 127 or ord(ch) > 0x2000 else "." for ch in 可打印文本)
        源码行.append("%04x  %-*s  %s" % (基 + 位置, 宽度 * 3 - 1, 字节片.hex(" "), 可打印文本))
    return "\n".join(源码行)


def 出全语料读数(汇总, 目录, 附注=None):
    """全语料（或**一片**）的硬读数。分片与全量走**同一个打印口** ⇒ 两边读数可逐字对比。

    行格式与拆分前**逐字一致**（外部复跑件按 `可证记录 %-12s` 行首与 `头 4 字节恒 0：…` 断言）；
    `附` 只多打一行说明本行是「全量」还是「第几片」，不改任何读数行。
    """
    段数, 区长, 坏件表 = 汇总["段数"], 汇总["区长"], 汇总["坏"]
    字节总, 未解总 = 汇总["字节"], 汇总["未解"]
    print("=" * 78)
    print("全语料 %s：文件 %d · 程序段 %d · 解析失败 %d" % (目录, 汇总["文件"], 段数, len(坏件表)))
    if 附注:
        print("   扫描：%s" % 附注)
    for 节点件, 错误 in 坏件表[:5]:
        print("   失败样例 %s：%s" % (节点件, 错误))
    if 区长:
        print("声明记录区长度：min %d · 中位 %d · max %d"
              % (区长[0], 区长[len(区长) // 2], 区长[-1]))
    else:
        print("声明记录区长度：无（本扫描没有程序段）")
    print("头 4 字节恒 0：%d / %d" % (汇总["首4零"], 段数))
    print("整区全零（空程序）：%d / %d" % (汇总["全零"], 段数))
    for 形态 in ("串记录", "语句字节码", "DLL命令记录", "数据类型码"):
        print("可证记录 %-12s %d 条" % (形态, 汇总["计"].get(形态, 0)))
    if 字节总:
        print("可证记录覆盖字节 %d / %d（%.2f%%）；其余 %d 字节（%.2f%%）**不判**"
              % (字节总 - 未解总, 字节总, 100.0 * (字节总 - 未解总) / 字节总,
                 未解总, 100.0 * 未解总 / 字节总))
    else:
        print("可证记录覆盖字节 0 / 0；本扫描没有程序段 ⇒ 覆盖率不判")


def 出报告(路径, 转储=False):
    with open(路径, "rb") as fh:
        数据 = fh.read()
    号段 = 反解容器(数据)
    print("样本 %s（%d 字节）｜ 段记录 %d 条 ｜ 段类型序列 %s"
          % (路径, len(数据), len(号段), [段片[0] for 段片 in 号段]))
    命中 = [段片 for 段片 in 号段 if 段片[0] == 段类型_程序]
    if not 命中:
        print("  本文件没有类型 3「程序段」，声明记录区不存在")
        return 0
    for _, 段起, 段止, 头起 in 命中:
        段数据字节 = 数据[段起:段止]
        段数据读数 = 解段数据(段数据字节)
        区起 = 段数据读数["声明记录区起点"]
        区字节 = 段数据字节[区起:]
        print("-" * 78)
        print("① 段头 @0x%x ｜ 段数据 @0x%x..0x%x（%d 字节）" % (头起, 段起, 段止, len(段数据字节)))
        print("② 段数据头：段序号=%d 保留=%d 校验值=0x%08x 体长=%d（= 段数据长−56）体首字段=0x%08x"
              % (段数据读数["段序号"], 段数据读数["保留"], 段数据读数["校验值"], 段数据读数["体长"], 段数据读数["体首字段"]))
        print("   体长校验：%d == %d ⇒ %s" % (段数据读数["体长"], len(段数据字节) - 段数据头长度,
              "命中" if 段数据读数["体长"] == len(段数据字节) - 段数据头长度 else "不符"))
        print("③ 段体魔数 0x%08x ⇒ %s" % (段体魔数, "命中" if struct.unpack_from("<I", 段数据字节, 头偏移_体魔数)[0] == 段体魔数 else "不符"))
        print("④ 支持库表：首数组 %s · 次数组 %s · 末数组 %s · 支持库数 %d"
              % (段数据读数["首数组"], 段数据读数["次数组"], 段数据读数["末数组"], len(段数据读数["引用表"])))
        for 段片 in 段数据读数["引用表"]:
            print("     引用：" + repr(段片[:96]))
        print("⑤ **声明记录区**：段数据内偏移 0x%x（= %d）→ 文件偏移 0x%x；长度 %d 字节（占段数据 %.2f%%）"
              % (区起, 区起, 段起 + 区起, len(区字节), 100.0 * len(区字节) / len(段数据字节)))
        print("   边界判据：起点 = 段数据头(56) + 段体头(8) + 支持库表(三数组+u16+N 条引用)；"
              "止点 = 段数据头.体长 + 56")
        print("   头 4 字节 = %s ⇒ %s" % (区字节[:4].hex(" "), "恒 0（本脚本 1456/1456 实测）" if 区字节[:4] == b"\x00\x00\x00\x00" else "非 0（不合本脚本的边界判据）"))
        记录, 未解 = 走记录(区字节)
        种类计数 = {}
        for 段片 in 记录:
            种类计数[段片["种类"]] = 种类计数.get(段片["种类"], 0) + 1
        print("⑥ 可证记录（只证「某处是一条 X 记录」，不证分区）：")
        for 形态 in ("DLL命令记录", "语句字节码", "数据类型码", "串记录"):
            if 种类计数.get(形态):
                print("     %-12s %d 条" % (形态, 种类计数[形态]))
        print("   未解字节 %d / %d（%.2f%%）—— 分区边界与记录头字段语义**不判**"
              % (未解, len(区字节), 100.0 * 未解 / max(1, len(区字节))))
        for 段片 in 记录[:24]:
            if 段片["种类"] == "串记录":
                print("     [0x%04x] 串记录 长%3d %r" % (段片["起"], 段片["串长"], 段片["串"]))
            elif 段片["种类"] == "语句字节码":
                print("     [0x%04x] 语句字节码 长%3d %r" % (段片["起"], 段片["长度"], 段片["文本"]))
            elif 段片["种类"] == "DLL命令记录":
                print("     [0x%04x] DLL命令 %r.%r → 使用名 %r 参数%d 参中字节%s 号%s"
                      % (段片["起"], 段片["库名"], 段片["命令名"], 段片["使用名"],
                         段片["参数个数"], 段片["参中字节"], 段片["号"]))
            else:
                print("     [0x%04x] 数据类型码 0x%08x" % (段片["起"], 段片["值"]))
        if 转储:
            print("⑦ 十六进制转储（声明记录区，前 512 字节）：")
            print(十六进制(区字节, 上限=512))
    return 0
