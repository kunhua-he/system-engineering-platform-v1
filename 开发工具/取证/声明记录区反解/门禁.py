# -*- coding: utf-8 -*-
"""门禁 —— 命令级墙钟**自量自门禁**（`2026-09-27_所有运行五秒硬顶.md` §六.1 的落法）。

**为什么是「壳自量」而不是「中央判据读回执」**（裁决 §六.1 给了两条实测理由）：
  · 回执不在 ⇒ 中央判据只能报「未判」，而 `一键验证` 的退出码语义是「未判即 1」⇒ 门禁**永久变红**
    （新克隆、`git clean` 之后必然如此）；
  · 回执里记的常是**内部耗时**（例：案例回执的 `耗时微秒` 不含 `cargo` 启动那一段）⇒ 拿它冒充
    墙钟就是**假读数**。
⇒ 一条命令的**完整墙钟只有它自身的壳能量**。本脚本的壳 = 入口 `声明记录区反解.py`。

**量得到的边界（如实登记）**：壳在入口的**第一行可执行语句**起表，故它量不到
「解释器启动」与「进程退出」那两段（几十毫秒量级）。这与 `一键验证` 判据 ⑱ 同一条边界 ——
那边用 `尾巴余量毫秒` 校正（裁决 §二：内部读数按「硬顶 − 尾巴余量」判）。
本件照同一口径：阈值 = `硬顶毫秒 − 尾巴余量毫秒` ⇒ **本件的声明（完整命令 ≤ 硬顶）为真**。

**阈值与反向样本注入只有一处落点**：`构建装配/门禁/`（裁决 `判据口径十一条.md` §十四）。
本件原先自留一份 `硬顶毫秒 = 5000` 与自身的注入变量 `V1_FORENSIC_SLOW_MS` —— **已删**：
同一条事实两处落点就是漂移源。改共享那个数 ⇒ 全平台各命令的壳同变；反向样本也统一成
`V1_CMD_SLOW_MS`（变量名**必须 ASCII**：`sh`/`zsh` 不认非 ASCII 变量名，实测过 ——
同 `进入.sh` 与 `.git/hooks/pre-commit` 顶部那条理由）。`尾巴余量毫秒` **本件自留**（§十四）。

**反向样本**：`V1_CMD_SLOW_MS` 注入一段真睡 ⇒ 门禁必须报红（不空转）。见 `自测` 与报告读数。
"""

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))  # 仓根：`构建装配.门禁` 是包
from 构建装配.门禁 import 硬顶毫秒, 注入人为慢  # noqa: E402

# 尾巴余量**本命令自留**（§十四：它不共享）—— 它是「本命令量不到的那一段」，
# 别的命令的尾巴是别的一段。余量与那条尾巴自证是一件事的两半，改一个必须同改另一个。
尾巴余量毫秒 = 200
阈值毫秒 = 硬顶毫秒 - 尾巴余量毫秒


def 带门禁跑(参数, 起始) -> int:
    """跑命令本体 → 自量墙钟 → 超阈值报红并非 0。**命令本体算出来的码优先保留**。

    门禁报告走 **stderr**：它是诊断，不是命令的输出面 —— 走 stdout 会污染
    `N=$(python3 … --建议分片数)` 这类取值（取回来的是「命令墙钟…」那一行，不是数）。
    """
    from .命令行 import 主
    码 = 主(参数)
    注入 = 注入人为慢()
    墙钟毫秒 = int((time.monotonic() - 起始) * 1000)
    print("─" * 78, file=sys.stderr)
    print("命令墙钟（壳自量）%d ms · 阈值 %d ms（硬顶 %d − 尾巴余量 %d）· 人为慢注入 %d ms"
          % (墙钟毫秒, 阈值毫秒, 硬顶毫秒, 尾巴余量毫秒, 注入), file=sys.stderr)
    if 墙钟毫秒 > 阈值毫秒:
        print("✗ 超顶：完整墙钟 %d ms > %d ms —— 五秒硬顶无例外（裁决 §一）"
              % (墙钟毫秒, 阈值毫秒), file=sys.stderr)
        print("  修法（裁决 §三.2/§三.3）：`--分片 i/n` 把 n 调大（全量切成更多条命令，每条更小）；"
              "`--全部` 只归并缓存 —— 它超顶说明归并本身太重，那是另一回事，要单独查。",
              file=sys.stderr)
        return 1
    print("✓ 在硬顶内", file=sys.stderr)
    return 码
