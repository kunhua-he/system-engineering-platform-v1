# -*- coding: utf-8 -*-
"""门禁 —— 命令级墙钟**自量自门禁**（`2026-09-27_所有运行五秒硬顶.md` §六.1 的落法）。

**为什么是「壳自量」而不是「中央判据读回执」**（裁决 §六.1 给了两条实测理由）：
  · 回执不在 ⇒ 中央判据只能报「未判」，而 `一键验证` 的退出码语义是「未判即 1」⇒ 门禁**永久变红**
    （新克隆、`git clean` 之后必然如此）；
  · 回执里记的常是**内部耗时**（例：案例回执的 `耗时微秒` 不含 `cargo` 启动那一段）⇒ 拿它冒充
    墙钟就是**假读数**。
⇒ 一条命令的**完整墙钟只有它自己的壳能量**。本脚本的壳 = 入口 `声明记录区反解.py`。

**量得到的边界（如实登记）**：壳在入口的**第一行可执行语句**起表，故它量不到
「解释器启动」与「进程退出」那两段（几十毫秒量级）。这与 `一键验证` 判据 ⑱ 同一条边界 ——
那边用 `尾巴余量毫秒` 校正（裁决 §二 第四轮：内部读数按「硬顶 − 尾巴余量」判）。
本件照同一口径：阈值 = `硬顶毫秒 − 尾巴余量毫秒` ⇒ **本件的声明（完整命令 ≤ 硬顶）为真**。
余量与那条尾巴自证是一件事的两半，改一个必须同改另一个。

**反向样本**：`人为慢环境变量` 注入一段真睡 ⇒ 门禁必须报红（不空转）。见 `自测` 与报告读数。
"""

import os
import time

硬顶毫秒 = 5000
尾巴余量毫秒 = 200
阈值毫秒 = 硬顶毫秒 - 尾巴余量毫秒
# 反向样本注入的变量名**必须 ASCII**：`sh` / `zsh` 不认非 ASCII 变量名（`export 中文=…` 不生效，
# 实测过 —— 同 `进入.sh` 与 `.git/hooks/pre-commit` 顶部那条理由）。值 = 毫秒数。
人为慢环境变量 = "V1_FORENSIC_SLOW_MS"


def 注入人为慢() -> int:
    """反向样本注入：环境变量给毫秒数，就在算完之后**真睡**那么久（默认 0 = 不注入）。

    刻意用环境变量而不是命令行开关：它只服务于「门禁不空转」这条自证，不进公开用法面。
    """
    值 = os.environ.get(人为慢环境变量)
    if not 值:
        return 0
    try:
        毫秒 = float(值)
    except ValueError:
        return 0
    if 毫秒 <= 0:
        return 0
    time.sleep(毫秒 / 1000.0)
    return int(毫秒)


def 带门禁跑(参数, 起始) -> int:
    """跑命令本体 → 自量墙钟 → 超阈值报红并非 0。**命令本体算出来的码优先保留**。"""
    from .命令行 import 主
    码 = 主(参数)
    注入 = 注入人为慢()
    墙钟毫秒 = int((time.monotonic() - 起始) * 1000)
    print("─" * 78)
    print("命令墙钟（壳自量）%d ms · 阈值 %d ms（硬顶 %d − 尾巴余量 %d）· 人为慢注入 %d ms"
          % (墙钟毫秒, 阈值毫秒, 硬顶毫秒, 尾巴余量毫秒, 注入))
    if 墙钟毫秒 > 阈值毫秒:
        print("✗ 超顶：完整墙钟 %d ms > %d ms —— 五秒硬顶无例外（裁决 §一）"
              % (墙钟毫秒, 阈值毫秒))
        print("  修法（裁决 §三.2/§三.3）：`--分片 i/n` 增大 n（把全量切成更多条命令）；"
              "或先让 `--全部` 预热逐件缓存，再复跑（命中缓存时只做归并）。")
        return 1
    print("✓ 在硬顶内")
    return 码
