# -*- coding: utf-8 -*-
"""翻译器生成 —— 生成 V1 声明根（包声明 · 能力声明 · 错误码表 · 类型声明）· 落盘 · 翻译来源。

口径（对齐 `契约声明/格式说明.md` 与 `生成声明/读子表.py`）：
  · 复合类型编号按裁定：`102 = JSON值型 · 103 = 结果型（结果结构）`；
  · 结果型的**值结构**落该类型的 `元素表`（§四形状 `{名称,类型标签,说明}`），**不落 `属性表`**
    （`属性表` 的正式形状未裁，生成器对非空项 fail-closed）；
  · 参数行的 `默认值` 是**三态**（未提供 · 空值 · 显式默认），文本默认值走兼容键 `文本`
    （口径 = `构建装配/形态装配/生成声明/声明读取/读子表.py::读默认值槽`）；
  · 复合类型声明只出**本模块用到的**那几个（对核心支持库已有的复合类型只**引用标签**，
    不整份复制进本模块目录）；
  · 出 `翻译来源.json`（含 `保真损失`，为空即无损）。
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from 翻译器常量 import (
    声明格式号, 目标字宽, 导出目标默认, 号段类宽度, 复合类型表,
    错误码序号表, 错误码兜底序号起,
)
from 翻译器实现 import (
    取能力名, 取能力说明, 取参数项表, 取返回项, 取错误码短语表, 类型标签,
    净化说明文本, 修复名字, 标识串,
)

# 默认值槽**能承载**的类型标签（`读默认值槽` 只认这几个）。
默认值可承载标签 = (1, 2, 3, 4, 6)


# ── 默认值三态 ─────────────────────────────────────────────────────────
def 默认值槽(参数类型标签: int, 默认值):
    """老项目参数的「默认值」⇒ `(V1 槽, 损失说明)`；损失说明非空 ⇒ 已降级为「空值」。

    三态：`None` ⇒ 空值（`{类型标签: 0, 值: 0}`）；整数 ⇒ `值`；文本 ⇒ `文本`（兼容键）。
    """
    if 默认值 is None:
        return {"类型标签": 0, "值": 0}, ""
    if isinstance(默认值, bool):
        标签, 载荷键, 载荷值 = 3, "值", (1 if 默认值 else 0)
    elif isinstance(默认值, int):
        标签, 载荷键, 载荷值 = 参数类型标签, "值", 默认值
    elif isinstance(默认值, float) and float(默认值).is_integer():
        标签, 载荷键, 载荷值 = 参数类型标签, "值", int(默认值)
    elif isinstance(默认值, str):
        标签, 载荷键, 载荷值 = 4, "文本", 默认值
    else:
        return {"类型标签": 0, "值": 0}, "默认值形状（%s）槽承载不了" % type(默认值).__name__
    if 标签 not in 默认值可承载标签:
        return {"类型标签": 0, "值": 0}, "类型标签 %d 的显式默认值载荷未定义" % 标签
    if 标签 != 参数类型标签:
        return {"类型标签": 0, "值": 0}, "默认值类型（标签 %d）与参数类型（标签 %d）不一致" % (
            标签, 参数类型标签)
    if (标签 == 4) != (载荷键 == "文本"):
        return {"类型标签": 0, "值": 0}, "文本标签与非文本载荷不符（或反之）"
    if 标签 == 3 and 载荷值 not in (0, 1):
        return {"类型标签": 0, "值": 0}, "逻辑默认值只接受 0 或 1"
    return {"类型标签": 标签, 载荷键: 载荷值}, ""


# ── 生成声明 ───────────────────────────────────────────────────────────
def 生成包声明(模块数据: dict, 号段: dict) -> dict:
    """V1 扩展包声明（形状照 扩展根目录/原子支持库/编译器支持库/包声明.json）。"""
    段位 = int(号段.get("段位", 号段["号段起"] // 号段类宽度))
    return {
        "声明格式号": 声明格式号,
        "标识串": 标识串(模块数据["模块名"]),
        "实现版本": {"主": 0, "次": 1, "构建": 0},
        "要求宿主版本": {"主": 1, "次": 0},
        "要求内核版本": {"主": 1, "次": 0},
        "名称": 模块数据["模块名"],
        "说明": 模块数据["模块说明"],
        "目标字宽": 目标字宽,
        "能力号段": [{"起": 号段["号段起"], "止": 号段["号段止"]}],
        "通知号段": [],
        "错误段位表": [段位],
        "导出目标": 导出目标默认,
    }


def 生成参数行(参数项: dict, 修复表: dict) -> dict:
    """V1 参数信息：名称 · 说明 · 类型标签 · 状态位 · 默认值（三态；缺键 = 未提供）。"""
    参数行 = {
        "名称": 修复名字(参数项.get("名称"), 修复表),
        "说明": 净化说明文本(str(参数项.get("说明") or "")),
        "类型标签": 类型标签(参数项.get("类型")),
        "状态位": 0,
    }
    if "默认值" in 参数项:
        载荷槽, _损失 = 默认值槽(参数行["类型标签"], 参数项.get("默认值"))
        参数行["默认值"] = 载荷槽
    return 参数行


def 收集错误码(能力项表: list, 段位: int) -> dict:
    """⇒ {码表, 短语转码}。**码 = 段位 × 1000 + 序号**；已知短语走序号固定表，
    未知短语按排序从兜底序号起取。段位来自模块所在的号段（见 `分配号段`）。"""
    短语表 = sorted({短语 for 能力项 in 能力项表 for 短语 in 取错误码短语表(能力项)})
    码表 = {}
    短语转码 = {}
    兜底序 = 错误码兜底序号起
    for 短语 in 短语表:
        if 短语 in 错误码序号表:
            序号 = 错误码序号表[短语]
        else:
            序号 = 兜底序
            兜底序 += 1
        码值 = 段位 * 号段类宽度 + 序号
        短语转码[短语] = 码值
        码表[码值] = {
            "码": 码值,
            "名称": 短语,
            "说明": "老项目错误码「%s」在 V1 的登记码（段位 %d）。" % (短语, 段位),
            "段位": 段位,
            "可重试": False,
            "可自愈": False,
            "需人工": False,
        }
    return {"码表": 码表, "短语转码": 短语转码}


def 取值结构元素(能力项: dict) -> list:
    """老项目 `返回.值结构`（字段名 → 「类型，说明」）⇒ 结果型 `元素表`（§四 形状）。"""
    值结构 = 取返回项(能力项).get("值结构") or {}
    if not isinstance(值结构, dict):
        return []
    元素表 = []
    for 字段名, 描述 in 值结构.items():
        描述 = 净化说明文本(str(描述 or ""))
        元素表.append({"名称": str(字段名), "类型标签": 类型标签(描述), "说明": 描述})
    return 元素表


def 收集类型声明(能力项表: list) -> dict:
    """⇒ {标签: 类型声明}。只收**本模块用到的复合类型**（基础 0–7 由底座提供，不重声明）。

    结果型的 `值结构` 落 `元素表`（**不落 `属性表`**：后者形状未裁、生成器 fail-closed）。
    对核心支持库已有的复合类型（100–103）**只引用标签**，不整份复制。
    """
    标签表 = {}
    for 能力项 in 能力项表:
        类型名表 = [取返回项(能力项).get("类型")]
        类型名表 += [参数项.get("类型") for 参数项 in 取参数项表(能力项)]
        for 类型名 in 类型名表:
            首段名 = str(类型名 or "").split("，")[0].strip()
            if 首段名 not in 复合类型表:
                continue
            标签, 名称, 说明 = 复合类型表[首段名]
            元素表 = (标签表.get(标签) or {}).get("元素表") or []
            if 首段名 == "结果型":
                元素表 = 元素表 + 取值结构元素(能力项)
            标签表[标签] = {
                "类型标签": 标签, "名称": 名称, "说明": 说明, "状态位": 0,
                "元素表": 元素表, "属性表": [], "事件表": [], "命令号表": [],
            }
    return 标签表


def 收集保真损失(模块数据: dict, 修复表: dict) -> list:
    """逐能力逐参数核「老项目语义 → V1 槽」承载不下的处 ⇒ 损失项列表（空 = 无损）。

    每条：`模块 · 位置 · 原语义 · 降级说明`。
    """
    损失表 = []
    for 能力项 in 模块数据["能力项表"]:
        能力名 = 修复名字(取能力名(能力项), 修复表)
        for 参数项 in 取参数项表(能力项):
            if "默认值" not in 参数项:
                continue
            参数名 = 修复名字(参数项.get("名称"), 修复表)
            载荷槽, 损失 = 默认值槽(类型标签(参数项.get("类型")), 参数项.get("默认值"))
            if 损失:
                损失表.append({
                    "模块": 模块数据["模块名"],
                    "位置": "能力 %s · 参数 %s" % (能力名, 参数名),
                    "原语义": "默认值 = %s" % json.dumps(参数项.get("默认值"), ensure_ascii=False),
                    "降级说明": 损失 + " ⇒ 该参数默认值降级为「空值」",
                })
    return 损失表


def 生成能力声明(模块数据: dict, 号段: dict, 修复表: dict, 短语转码: dict) -> list:
    """⇒ 能力声明表：编号自号段起连续递增（行序 = 老项目原序，不重排）。"""
    声明表 = []
    当前号 = 号段["号段起"]
    for 能力项 in 模块数据["能力项表"]:
        能力名 = 修复名字(取能力名(能力项), 修复表)
        参数表 = [生成参数行(参数项, 修复表) for 参数项 in 取参数项表(能力项)]
        可抛码表 = sorted({短语转码[短语] for 短语 in 取错误码短语表(能力项)
                         if 短语 in 短语转码})
        声明表.append({
            "编号": 当前号,
            "名称": "%s_%s" % (模块数据["模块名"], 能力名),
            "说明": 取能力说明(能力项),
            "类别": 0,
            "状态位": 0,
            "返回类型": 类型标签(取返回项(能力项).get("类型")),
            "用户级别": 0,
            "参数表": 参数表,
            "可抛错误码": 可抛码表,
        })
        当前号 += 1
    return 声明表


def 生成声明根(模块数据: dict, 号段: dict, 修复表: dict) -> dict:
    """⇒ {包声明, 能力声明表, 错误码表, 类型声明表, 保真损失}。"""
    段位 = int(号段.get("段位", 号段["号段起"] // 号段类宽度))
    错误码 = 收集错误码(模块数据["能力项表"], 段位)
    return {
        "包声明": 生成包声明(模块数据, 号段),
        "能力声明表": 生成能力声明(模块数据, 号段, 修复表, 错误码["短语转码"]),
        "错误码表": 错误码["码表"],
        "类型声明表": 收集类型声明(模块数据["能力项表"]),
        "保真损失": 收集保真损失(模块数据, 修复表),
    }


# ── 落盘 ───────────────────────────────────────────────────────────────
def 写件(件路径: Path, 结构) -> str:
    """写一个 JSON 件（缩进 2 · 不转义中文）⇒ 返回它的 sha256。"""
    件路径.parent.mkdir(parents=True, exist_ok=True)
    正文 = json.dumps(结构, ensure_ascii=False, indent=2) + "\n"
    件路径.write_text(正文, encoding="utf-8")
    return hashlib.sha256(正文.encode("utf-8")).hexdigest()


def 写说明书(输出目录: Path, 声明根: dict) -> str:
    """出扩展自带的用法说明（必备件之一）⇒ 返回它的 sha256（正文按 md 直写，不套 JSON）。"""
    包声明 = 声明根["包声明"]
    号段项 = 包声明["能力号段"][0]
    行表 = ["# %s —— 用法说明" % 包声明["名称"], "", str(包声明["说明"]), "",
            "## 能力清单", "", "| 编号 | 名称 | 参数个数 |", "| --- | --- | --- |"]
    for 能力声明 in 声明根["能力声明表"]:
        行表.append("| %d | %s | %d |" % (能力声明["编号"], 能力声明["名称"],
                                          len(能力声明["参数表"])))
    行表 += ["", "## 号段", "",
             "能力号段 %d–%d（段位 %d 归模块扩展）。" % (号段项["起"], 号段项["止"],
                                                        包声明["错误段位表"][0]), ""]
    正文 = "\n".join(行表)
    件路径 = 输出目录 / "说明" / "使用说明.md"
    件路径.parent.mkdir(parents=True, exist_ok=True)
    件路径.write_text(正文, encoding="utf-8")
    return hashlib.sha256(正文.encode("utf-8")).hexdigest()


def 落盘(声明根: dict, 输出目录: Path) -> dict:
    """把声明根落成一棵 V1 扩展声明根 ⇒ 返回 {相对路径: sha256}。"""
    指纹表 = {}
    指纹表["包声明.json"] = 写件(输出目录 / "包声明.json", 声明根["包声明"])
    for 能力声明 in 声明根["能力声明表"]:
        相对名 = "能力声明/%d.json" % 能力声明["编号"]
        指纹表[相对名] = 写件(输出目录 / 相对名, 能力声明)
    for 码值, 错误码声明 in sorted(声明根["错误码表"].items()):
        相对名 = "错误码表/%d.json" % 码值
        指纹表[相对名] = 写件(输出目录 / 相对名, 错误码声明)
    for 标签, 类型声明 in sorted(声明根["类型声明表"].items()):
        相对名 = "类型声明/%d.json" % 标签
        指纹表[相对名] = 写件(输出目录 / 相对名, 类型声明)
    指纹表["说明/使用说明.md"] = 写说明书(输出目录, 声明根)
    写件(输出目录 / "指纹.json",
        {"说明": "本扩展各声明件的 sha256（重译即刷新）", "件": 指纹表})
    return 指纹表


def 写翻译来源(声明根: dict, 模块目录: Path, 来源目录: Path) -> dict:
    """出 `翻译来源.json`：本模块的翻译口径与**保真损失**（`保真损失` 为空即无损）。

    该件是**验收读数**，落运行数据根临时件（不进版本库）。
    """
    包声明 = 声明根["包声明"]
    号段项 = 包声明["能力号段"][0]
    来源 = {
        "模块": 包声明["名称"],
        "老项目目录": str(模块目录),
        "能力号段": {"起": 号段项["起"], "止": 号段项["止"]},
        "能力数": len(声明根["能力声明表"]),
        "类型声明": sorted("类型声明/%d.json" % 标签 for 标签 in 声明根["类型声明表"]),
        "错误码": sorted(声明根["错误码表"]),
        "保真损失": 声明根["保真损失"],
    }
    来源目录.mkdir(parents=True, exist_ok=True)
    件路径 = 来源目录 / ("%s.翻译来源.json" % 包声明["名称"])
    件路径.write_text(json.dumps(来源, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return 来源
