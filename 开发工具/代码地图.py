#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""代码地图 —— 本仓的**符号索引**（独立一套，不走 MCP）。

用法：
    python3 开发工具/代码地图.py 建             # 建/刷索引库（环境步：照实报墙钟，不判顶）
    python3 开发工具/代码地图.py 查 <关键词>     # 按短名/限定名/声明/路径子串查符号
    python3 开发工具/代码地图.py 引用 <限定名>   # 该符号的全部出现（定义处也算）
    python3 开发工具/代码地图.py 检名           # 命名规范三档口径套在索引的定义面上
    python3 开发工具/代码地图.py 检形参         # 索引看不见的形参层（签名面 + JS 面）
    python3 开发工具/代码地图.py 状态           # 索引库在不在、多大、几个节点

**它买的是什么**：`rg` 快但没有语义 —— 它分不清「定义」与「引用」，也认不出两个同名符号。
本工具用**外部开源索引器**（`codegraph`：tree-sitter 解析 + sqlite 落库）预建索引，
查的时候只读那个库：`rg` 管「哪几行有这个字」，代码地图管「谁是定义、谁在引用它」。
**零自研解析** —— 解析归 tree-sitter，本仓不再养剥器与前端。

**索引器**（一件，是**环境依赖**，不是底座能力）：`codegraph`
（`npm i -g @colbymchenry/codegraph`）。不在 ⇒ `建` 如实报装法，其余命令照跑。

**落点**：`<仓根>/.codegraph/codegraph.db`（索引器自带的库，本仓只读）。

**★ 引用面少约 7%**（换索引器的代价，实测见 `决策记录/2026-09-27_代码地图换 codegraph.md`）：
浏览够用；**符号级改名要拿编译兜底**（编译不过 = 索引漏了几处，用 `rg` 按词边界复核）。

**五秒硬顶**：`建` 是环境步（实测 1.4 s，但大仓会更久）⇒ 用 `报告环境步` 照实报；
`查`/`引用`/`状态` 只读 sqlite（实测 10–50 ms）⇒ 用 `自门禁` 判顶。
依据：`项目文档/决策记录/2026-09-27_代码地图换 codegraph.md` · `2026-09-27_构建段归环境步.md` §四。
"""
import sys
import time
from pathlib import Path

起始时刻 = time.monotonic()  # 壳起表点：必须在 import 业务包**之前**（见 构建装配/门禁/壳.py）

仓根 = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(仓根))            # 取 构建装配.门禁
sys.path.insert(0, str(仓根 / "开发工具"))  # 取 代码地图 包

from 构建装配.门禁 import 报告环境步, 自门禁  # noqa: E402

from 代码地图 import (  # noqa: E402
    建索引, 报缺索引器, 找索引器命令, 索引状态, 查符号行, 引用行, 状态行, 检名, 形参行,
)

用法文本 = ("用法：python3 开发工具/代码地图.py "
          "{建|查 <关键词>|引用 <限定名>|检名|检形参|状态}")

没有索引的提示 = "代码地图：还没有索引库 ⇒ 先跑 `python3 开发工具/代码地图.py 建`"


def 入口函数(argv=None):
    # 无参 = 没给子命令 ⇒ 落到末尾印用法并退 2（原先静默默认 `状态` = 声明与行为不符）
    命令行参数 = list(sys.argv[1:] if argv is None else argv)
    子命令 = 命令行参数[0] if 命令行参数 else ""

    if 子命令 == "建":
        if not 找索引器命令():
            return 报缺索引器()
        退出码, 墙钟毫秒, 建索引说明 = 建索引(仓根)
        print("代码地图 · 建索引：%s" % 建索引说明)
        print("  冷构建墙钟 %d ms（环境步：照实报，不判顶）" % 墙钟毫秒)
        return 退出码

    if 子命令 == "检名":
        命名读数 = 检名()
        if not 命名读数["有索引"]:
            print(没有索引的提示)
            return 1
        print("代码地图 · 检名（扫描面 = 索引的定义面，共 %d 档）：" % len(命名读数["读数"]))
        for 档名, 条数 in 命名读数["读数"].items():
            print("  %-10s %d 条" % (档名, 条数))
        for 档名 in ("序数代称", "西文单字母"):
            for 一条 in 命名读数["样本"][档名]:
                print("    [%s] %s  %s:%d（出现 %d 处）"
                      % (档名, 一条["名字"], 一条["路径"], 一条["行"], 一条["出现数"]))
        return 0

    if 子命令 == "检形参":
        print("\n".join(形参行()))
        return 0

    if 子命令 == "状态":
        print("\n".join(状态行()))
        return 0 if 索引状态()["有"] else 1

    if 子命令 in ("查", "引用"):
        if len(命令行参数) < 2:
            print(用法文本)
            return 2
        if not 索引状态()["有"]:
            print(没有索引的提示)
            return 1
        关键词 = 命令行参数[1]
        print("\n".join(查符号行(关键词) if 子命令 == "查" else 引用行(关键词)))
        return 0

    print(用法文本)
    return 2


if __name__ == "__main__":
    是建索引 = bool(sys.argv[1:]) and sys.argv[1] == "建"
    退出码 = 入口函数()
    if 是建索引:
        sys.exit(
            报告环境步(
                起始时刻, 退出码,
                "代码地图 · 建索引 —— 索引器全量重建（一次性冷构建，属环境步）",
            )
        )
    sys.exit(
        自门禁(
            起始时刻, 退出码, 尾巴余量毫秒=200,
            修法="本命令只读索引库（不加载工程、不跑索引器）。库长大它自身会超顶 —— "
                 "修法是给查询加索引/收窄面，别改成现建现查。",
        )
    )
