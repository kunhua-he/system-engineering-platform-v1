//!
//! 源出 `lib.rs`（拆件依据：`项目文档/开发规范/开发规范.md` 第六节「入口零实现」），**逐字搬家**。

    use super::*;

    /// 正常路径：分配拿到非 0 地址、按长度记账、释放后账清。
    #[test]
    fn 分配释放后账清() {
        let mut 分配器实例 = 分配器::构造();
        let 块地址 = 分配器实例.分配内存块(64).expect("分配应成功");
        assert_ne!(块地址, 0, "成功返回的地址不许是 0");
        assert_eq!(分配器实例.块长(块地址), Some(64), "长度必须按请求记账");
        assert_eq!(分配器实例.在用块数(), 1);

        unsafe { 分配器实例.释放内存(块地址).expect("释放应成功") };
        assert_eq!(分配器实例.块长(块地址), None, "释放后账上不应还有该块");
        assert_eq!(分配器实例.在用块数(), 0);
    }

    /// 多块各自记账、地址互不相同；释放一块不影响另一块。
    #[test]
    fn 多块各自记账() {
        let mut 分配器实例 = 分配器::构造();
        let 首块 = 分配器实例.分配内存块(16).expect("首块应成功");
        let 次块 = 分配器实例.分配内存块(32).expect("次块应成功");
        assert_ne!(首块, 次块, "两块地址不许相同");
        assert_eq!(分配器实例.块长(首块), Some(16));
        assert_eq!(分配器实例.块长(次块), Some(32));
        assert_eq!(分配器实例.在用块数(), 2);

        unsafe { 分配器实例.释放内存(首块).expect("释放首块应成功") };
        assert_eq!(分配器实例.块长(首块), None);
        assert_eq!(分配器实例.块长(次块), Some(32), "释放首块不许动到次块");
        assert_eq!(分配器实例.在用块数(), 1);

        unsafe { 分配器实例.释放内存(次块).expect("释放次块应成功") };
        assert_eq!(分配器实例.在用块数(), 0);
    }

    /// 交出去的内存是清零的：跨语言读到的不是垃圾。
    #[test]
    fn 分配的内存已清零() {
        let mut 分配器实例 = 分配器::构造();
        let 块地址 = 分配器实例.分配内存块(32).expect("分配应成功");
        // SAFETY: 地址由本分配器交出，32 字节可读。
        let 字节 = unsafe { *(块地址 as *const u8) };
        assert_eq!(字节, 0);
        unsafe { 分配器实例.释放内存(块地址).expect("释放应成功") };
    }

    /// 零长度必须报错，不许返回一个可用的 0 长度块。
    #[test]
    fn 零长度报错() {
        let mut 分配器实例 = 分配器::构造();
        assert_eq!(分配器实例.分配内存块(0), Err(分配错误::零长度));
        assert_eq!(分配器实例.在用块数(), 0);
    }

    /// 超上限必须报错，且错误里带出请求值与契约常量上限。
    #[test]
    fn 超上限报错() {
        let mut 分配器实例 = 分配器::构造();
        let 请求 = 单次分配上限 + 1;
        assert_eq!(分配器实例.分配内存块(请求), Err(分配错误::超上限 { 请求, 上限: 单次分配上限 }));
        assert_eq!(分配器实例.在用块数(), 0, "被拒的请求不许记账");
    }

    /// 重复释放必须报错，不许静默通过。
    #[test]
    fn 重复释放报错() {
        let mut 分配器实例 = 分配器::构造();
        let 块地址 = 分配器实例.分配内存块(8).expect("分配应成功");
        unsafe { 分配器实例.释放内存(块地址).expect("首次释放应成功") };
        assert_eq!(unsafe { 分配器实例.释放内存(块地址) }, Err(释放错误::重复释放));
    }

    /// 非本分配器给出的地址必须拒绝——拿真实栈地址来试。
    #[test]
    fn 外来地址被拒() {
        let mut 分配器实例 = 分配器::构造();
        let 在用 = 分配器实例.分配内存块(16).expect("分配应成功");

        let 栈上 = 0u8;
        let 外来地址 = (&栈上 as *const u8) as u64;
        assert_ne!(外来地址, 0);
        assert_eq!(unsafe { 分配器实例.释放内存(外来地址) }, Err(释放错误::非本分配器地址));

        // 拒绝外来地址不许影响在用块。
        assert_eq!(分配器实例.块长(在用), Some(16));
        assert_eq!(分配器实例.在用块数(), 1);
        unsafe { 分配器实例.释放内存(在用).expect("释放在用块应成功") };
    }

    /// 空指针必须报错（且与外来地址区分开）。
    #[test]
    fn 空指针报错() {
        let mut 分配器实例 = 分配器::构造();
        assert_eq!(unsafe { 分配器实例.释放内存(0) }, Err(释放错误::空指针));
    }

    /// 两个分配器实例互不污染：首器的地址在次器那里是外来地址。
    #[test]
    fn 两实例互不污染() {
        let mut 首器 = 分配器::构造();
        let mut 次器 = 分配器::构造();
        let 块地址 = 首器.分配内存块(16).expect("首器分配应成功");
        assert_eq!(次器.块长(块地址), None);
        assert_eq!(unsafe { 次器.释放内存(块地址) }, Err(释放错误::非本分配器地址));
        unsafe { 首器.释放内存(块地址).expect("首器释放应成功") };
    }
