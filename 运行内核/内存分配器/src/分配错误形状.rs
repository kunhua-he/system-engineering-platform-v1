//! 形状 —— 分配错误与释放错误。
//!
//! 源出 `lib.rs`（拆件依据：`项目文档/开发规范/开发规范.md` 第六节「入口零实现」），**逐字搬家**。

/// 分配错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 分配错误 {
    /// 申请 0 字节。
    零长度,
    /// 长度超过上限（上限是契约里的常量，不是拍脑袋的数）。
    超上限 { 请求: u64, 上限: u64 },
    /// 底层分配失败。
    内存不足,
}

/// 释放错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 释放错误 {
    /// 空指针。
    空指针,
    /// 该地址本分配器交出过，但**已经释放过了** —— 重复释放必须报错，不许静默。
    重复释放,
    /// 该地址不是本分配器给出的 —— **必须拒绝，不许宽容**。
    非本分配器地址,
}
