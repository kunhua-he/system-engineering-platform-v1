//! 内存分配器 —— 跨边界只认一个分配器；所有权单向。**路由**：声明子模块 + 再导出公开面。
//!
//! 入参归调用方，返回值所有权交出（宪法第 4 条）。谁分配谁释放，不许出现「两种语言各按各的规则释放」。
//!
//! 本 crate 是**唯一**能给出跨边界地址的地方，因此释放侧必须严：每个交出去的地址都记账
//! （地址 → 长度），释放时先查账 —— 账上没有的地址一律拒绝，绝不放行。
//!
//! 跨边界一律 `u64` 地址（`内核落点.md` §一：跨边界结构里不出现 `usize` / `isize`）；
//! `usize` 只在内部构造 `Layout` 时出现，不出现在任何对外签名或对外结构里。
//!
//! # 拆件（2026-09-27）
//!
//! 依据 `项目文档/开发规范/开发规范.md` 第六节「入口 ≤120 行且零实现」，
//! 判据 = `构建装配/一键验证/一键验证.py` 第 19 项（`项目文档/决策记录/2026-09-27_行数硬数与拆分面裁决.md`）。
//!
//! | 件 | 一类 |
//! |---|---|
//! | [`形状`] | 两个错误枚举（分配错误 / 释放错误） |
//! | [`分配`] | `分配器` 与它的两本账（活块 / 已释放） |
//! | `测试` | 释放侧的反向验证（重复释放 · 外来地址 · 空指针 · 两实例互不污染） |

