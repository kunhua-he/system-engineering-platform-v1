//! 内存分配器 —— 跨边界只认一个分配器；所有权单向。
//!
//! 入参归调用方，返回值所有权交出（宪法第 4 条）。谁分配谁释放，
//! 不许出现"两种语言各按各的规则释放"。
//!
//! 本 crate 是**唯一**能给出跨边界地址的地方，因此释放侧必须严：
//! 每个交出去的地址都记账（地址 → 长度），释放时先查账——
//! 账上没有的地址一律拒绝，绝不放行（否则就是"两种语言各按各的规则释放"）。
//!
//! 跨边界一律 `u64` 地址（`内核落点.md` §一：跨边界结构里不出现 `usize` / `isize`）；
//! `usize` 只在内部构造 `Layout` 时出现，不出现在任何对外签名或对外结构里。

#![allow(uncommon_codepoints)]
#![allow(non_snake_case)]

use std::alloc::{alloc_zeroed, dealloc, Layout};
use std::collections::{HashMap, HashSet};

/// 单次分配上限（字节）。
///
/// **依据（不是拍脑袋的数）**：设计文档《内核落点》§一 规则 2 要求
/// 「数据槽的形状与字宽无关……32 位构建下指针放进 `值` 时高 32 位为 0」，
/// 即同一套源码要能出 32 位与 64 位两种构建，跨边界地址必须在 32 位值域内可寻址。
/// 故单块字节数不得超过 32 位地址空间能表达的最大值：
pub const 单次分配上限: u64 = u32::MAX as u64;

/// 分配对齐（字节）。
///
/// 取 16：这是 64 位目标上基础类型的最强对齐（`max_align_t`，x86-64 / arm64 皆为 16），
/// 保证交出去的内存能承载任何标量或结构，跨语言绑定不需要再做对齐补偿。
const 分配对齐: u64 = 16;

/// 分配错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 分配错误 {
    /// 申请 0 字节。
    零长度,
    /// 长度超过上限（上限是契约里的常量，不是拍脑袋的数）。
    超上限 { 请求: u64, 上限: u64 },
    /// 底层分配失败。
    内存不足,
}

/// 释放错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 释放错误 {
    /// 空指针。
    空指针,
    /// 该地址本分配器交出过，但**已经释放过了** —— 重复释放必须报错，不许静默。
    重复释放,
    /// 该地址不是本分配器给出的 —— **必须拒绝，不许宽容**。
    非本分配器地址,
}

/// 单一跨边界分配器。
///
/// 状态显式持有，不落进程级全局（多实例安全）。
/// 账本两本：
/// - `活块`：地址 → 长度，当前尚未释放的块；
/// - `已释放`：曾经交出、且已被释放的地址，用来把「重复释放」与「外来地址」分开。
pub struct 分配器 {
    活块: HashMap<u64, u64>,
    已释放: HashSet<u64>,
}

impl 分配器 {
    pub fn 新建() -> Self {
        Self { 活块: HashMap::new(), 已释放: HashSet::new() }
    }

    /// 分配 `字节长度` 字节，返回地址。
    ///
    /// 失败一律走 `Result`，不 panic：`0` 字节 → [`分配错误::零长度`]；
    /// 超过 [`单次分配上限`] → [`分配错误::超上限`]；底层拿不到内存 → [`分配错误::内存不足`]。
    /// 成功返回的地址一定非 0，且已记账。
    pub fn 分配(&mut self, 字节长度: u64) -> Result<u64, 分配错误> {
        if 字节长度 == 0 {
            return Err(分配错误::零长度);
        }
        if 字节长度 > 单次分配上限 {
            return Err(分配错误::超上限 { 请求: 字节长度, 上限: 单次分配上限 });
        }
        // 走到这里：1 <= 字节长度 <= u32::MAX，对齐固定 16。
        // 若目标平台的 usize 装不下（32 位下 size + align - 1 溢出），按超上限处理。
        let 布局 = Layout::from_size_align(字节长度 as usize, 分配对齐 as usize)
            .map_err(|_| 分配错误::超上限 { 请求: 字节长度, 上限: 单次分配上限 })?;
        // SAFETY: 布局已校验且非零长度，alloc_zeroed 对合法布局是安全的。
        // 用 alloc_zeroed 而非 alloc：交出去的内存先清零，跨语言读到的不是垃圾，
        // 确定性优先（README 第二节「要求确定性」）。
        let 指针 = unsafe { alloc_zeroed(布局) };
        if 指针.is_null() {
            return Err(分配错误::内存不足);
        }
        let 地址 = 指针 as u64;
        self.活块.insert(地址, 字节长度);
        // 地址可能被底层复用：重新交出后就不再是"已释放"。
        self.已释放.remove(&地址);
        Ok(地址)
    }

    /// 释放。
    ///
    /// 先查账再动手：账上没有的地址**一律拒绝**，绝不传给 `dealloc`。
    ///
    /// # Safety
    /// `地址` 必须来自本分配器且尚未释放。本函数会校验这一点并拒绝非法地址，
    /// 但调用方仍不得把已释放的地址当有效指针使用（那是调用方的 UB，不是本函数能兜住的）。
    pub unsafe fn 释放(&mut self, 地址: u64) -> Result<(), 释放错误> {
        if 地址 == 0 {
            return Err(释放错误::空指针);
        }
        let Some(长度) = self.活块.remove(&地址) else {
            // 交出过但已释放 ⇒ 重复释放；从没交出过 ⇒ 外来地址。两者都不许静默。
            return Err(if self.已释放.contains(&地址) {
                释放错误::重复释放
            } else {
                释放错误::非本分配器地址
            });
        };
        // SAFETY: 长度与对齐来自本分配器成功的一次分配，布局必然合法。
        let 布局 = unsafe { Layout::from_size_align_unchecked(长度 as usize, 分配对齐 as usize) };
        // SAFETY: 地址由本分配器交出、尚未释放（刚从活块账上取下），且按同一布局分配。
        unsafe { dealloc(地址 as *mut u8, 布局) };
        self.已释放.insert(地址);
        Ok(())
    }

    /// 查账：该地址当前在用块的字节长度（未在用返回 `None`）。
    pub fn 块长(&self, 地址: u64) -> Option<u64> {
        self.活块.get(&地址).copied()
    }

    /// 当前在用块数（对外的计数一律 `u64`）。
    pub fn 在用块数(&self) -> u64 {
        self.活块.len() as u64
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    /// 正常路径：分配拿到非 0 地址、按长度记账、释放后账清。
    #[test]
    fn 分配释放正常() {
        let mut 器 = 分配器::新建();
        let 地址 = 器.分配(64).expect("分配应成功");
        assert_ne!(地址, 0, "成功返回的地址不许是 0");
        assert_eq!(器.块长(地址), Some(64), "长度必须按请求记账");
        assert_eq!(器.在用块数(), 1);

        unsafe { 器.释放(地址).expect("释放应成功") };
        assert_eq!(器.块长(地址), None, "释放后账上不应还有该块");
        assert_eq!(器.在用块数(), 0);
    }

    /// 多块各自记账、地址互不相同；释放一块不影响另一块。
    #[test]
    fn 多块各自记账() {
        let mut 器 = 分配器::新建();
        let 甲 = 器.分配(16).expect("甲应成功");
        let 乙 = 器.分配(32).expect("乙应成功");
        assert_ne!(甲, 乙, "两块地址不许相同");
        assert_eq!(器.块长(甲), Some(16));
        assert_eq!(器.块长(乙), Some(32));
        assert_eq!(器.在用块数(), 2);

        unsafe { 器.释放(甲).expect("释放甲应成功") };
        assert_eq!(器.块长(甲), None);
        assert_eq!(器.块长(乙), Some(32), "释放甲不许动到乙");
        assert_eq!(器.在用块数(), 1);

        unsafe { 器.释放(乙).expect("释放乙应成功") };
        assert_eq!(器.在用块数(), 0);
    }

    /// 交出去的内存是清零的：跨语言读到的不是垃圾。
    #[test]
    fn 分配的内存已清零() {
        let mut 器 = 分配器::新建();
        let 地址 = 器.分配(32).expect("分配应成功");
        // SAFETY: 地址由本分配器交出，32 字节可读。
        let 字节 = unsafe { *(地址 as *const u8) };
        assert_eq!(字节, 0);
        unsafe { 器.释放(地址).expect("释放应成功") };
    }

    /// 零长度必须报错，不许返回一个可用的 0 长度块。
    #[test]
    fn 零长度报错() {
        let mut 器 = 分配器::新建();
        assert_eq!(器.分配(0), Err(分配错误::零长度));
        assert_eq!(器.在用块数(), 0);
    }

    /// 超上限必须报错，且错误里带出请求值与契约常量上限。
    #[test]
    fn 超上限报错() {
        let mut 器 = 分配器::新建();
        let 请求 = 单次分配上限 + 1;
        assert_eq!(器.分配(请求), Err(分配错误::超上限 { 请求, 上限: 单次分配上限 }));
        assert_eq!(器.在用块数(), 0, "被拒的请求不许记账");
    }

    /// 重复释放必须报错，不许静默通过。
    #[test]
    fn 重复释放报错() {
        let mut 器 = 分配器::新建();
        let 地址 = 器.分配(8).expect("分配应成功");
        unsafe { 器.释放(地址).expect("首次释放应成功") };
        assert_eq!(unsafe { 器.释放(地址) }, Err(释放错误::重复释放));
    }

    /// 非本分配器给出的地址必须拒绝——拿真实栈地址来试。
    #[test]
    fn 外来地址被拒() {
        let mut 器 = 分配器::新建();
        let 在用 = 器.分配(16).expect("分配应成功");

        let 栈上 = 0u8;
        let 外来地址 = (&栈上 as *const u8) as u64;
        assert_ne!(外来地址, 0);
        assert_eq!(unsafe { 器.释放(外来地址) }, Err(释放错误::非本分配器地址));

        // 拒绝外来地址不许影响在用块。
        assert_eq!(器.块长(在用), Some(16));
        assert_eq!(器.在用块数(), 1);
        unsafe { 器.释放(在用).expect("释放在用块应成功") };
    }

    /// 空指针必须报错（且与外来地址区分开）。
    #[test]
    fn 空指针报错() {
        let mut 器 = 分配器::新建();
        assert_eq!(unsafe { 器.释放(0) }, Err(释放错误::空指针));
    }

    /// 两个分配器实例互不污染：甲的地址在乙那里是外来地址。
    #[test]
    fn 两实例互不污染() {
        let mut 甲 = 分配器::新建();
        let mut 乙 = 分配器::新建();
        let 地址 = 甲.分配(16).expect("甲分配应成功");
        assert_eq!(乙.块长(地址), None);
        assert_eq!(unsafe { 乙.释放(地址) }, Err(释放错误::非本分配器地址));
        unsafe { 甲.释放(地址).expect("甲释放应成功") };
    }
}
