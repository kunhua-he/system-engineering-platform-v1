//! 台账 —— `实例表` 与它的一条条记录。
//!
//! 源出 `lib.rs`（拆件依据：`项目文档/开发规范/开发规范.md` 第六节「入口零实现」），**逐字搬家**。
//!
//! # 句柄为什么能认出「不属于本表」
//!
//! 每开一个实例发一枚**令牌**：堆上的一字节，**它的地址就是句柄**。
//! 活着的堆分配地址两两不同，所以首表的句柄在次表里**查不到** —— 这就是 `句柄越界`。
//! 令牌在整张表的存续期内不释放，地址不会被后来者复用，因此不存在
//! 「旧句柄冒充新实例」的 ABA 问题。

use std::collections::HashMap;

use crate::实例句柄形状::{实例错误, 实例句柄};

/// 一条实例记录：令牌 + 是否已释放。
///
/// `_令牌` 在堆上只占一字节，**它的地址就是句柄**。把它留在记录里，是为了让这个
/// 地址在整张表存续期内不被复用 —— 记录从不删除，所以已释放的句柄不会被新实例撞上。
struct 实例记录 {
    _令牌: Box<u8>,
    已释放: bool,
}

/// 实例表：显式持有，无全局。
pub struct 实例表 {
    实例台账: HashMap<u64, 实例记录>,
}

impl 实例表 {
    pub fn 构造() -> Self {
        Self { 实例台账: HashMap::new() }
    }

    /// 开一个实例，返回句柄。
    pub fn 开启实例(&mut self) -> 实例句柄 {
        let 令牌 = Box::new(0u8);
        let 句柄值 = &*令牌 as *const u8 as u64;
        self.实例台账.insert(句柄值, 实例记录 { _令牌: 令牌, 已释放: false });
        实例句柄(句柄值)
    }

    /// 关一个实例。
    ///
    /// 本表没发过这个句柄 ⇒ `句柄越界`；已经关过 ⇒ `句柄失效`。
    pub fn 关闭实例(&mut self, 句柄: 实例句柄) -> Result<(), 实例错误> {
        match self.实例台账.get_mut(&句柄.0) {
            None => Err(实例错误::句柄越界),
            Some(实例台账) if 实例台账.已释放 => Err(实例错误::句柄失效),
            Some(实例台账) => {
                实例台账.已释放 = true;
                Ok(())
            }
        }
    }

    /// 校验句柄。**未命中返回错误，不许当成功。**
    ///
    /// 本表没发过 ⇒ `句柄越界`；已关掉 ⇒ `句柄失效`。
    pub fn 校验句柄(&self, 句柄: 实例句柄) -> Result<(), 实例错误> {
        match self.实例台账.get(&句柄.0) {
            None => Err(实例错误::句柄越界),
            Some(实例台账) if 实例台账.已释放 => Err(实例错误::句柄失效),
            Some(_) => Ok(()),
        }
    }
}
