//! 实例状态 —— 状态显式持有为句柄，**不落进程级全局**。
//!
//! 两个实例互不污染。状态是句柄：调用方持有，调用方释放。
//!
//! # 为什么这里没有全局
//!
//! 一个句柄的全部含义只由两处决定：**哪张表发的**、**表里的哪一条**。
//! 这两处都随 `实例表` 走，模块里没有 `static mut`、没有单例、没有进程级计数。
//! 所以两张 `实例表` 天然互不可见——这是宪法「多实例安全」在代码上的落点。
//!
//! # 句柄为什么能认出「不属于本表」
//!
//! 每开一个实例发一枚**令牌**：堆上的一字节，**它的地址就是句柄**。
//! 活着的堆分配地址两两不同，所以甲表的句柄在乙表里**查不到**——这就是 `句柄越界`。
//! 令牌在整张表的存续期内不释放，地址不会被后来者复用，因此不存在
//! 「旧句柄冒充新实例」的 ABA 问题。
//!
//! # 两种失败必须分得开
//!
//! - `句柄越界`：本表从没发过这个句柄（不属于本表）。
//! - `句柄失效`：本表发过，但已经关掉了（含重复关闭）。

use std::collections::HashMap;

/// 实例句柄。不透明，跨边界只传这个数。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 实例句柄(pub u64);

/// 实例错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 实例错误 {
    /// 句柄不存在或已释放。
    句柄失效,
    /// 句柄不属于本实例。
    句柄越界,
}

/// 一条实例记录：令牌 + 是否已释放。
///
/// `_令牌` 在堆上只占一字节，**它的地址就是句柄**。把它留在记录里，是为了让这个
/// 地址在整张表存续期内不被复用——记录从不删除，所以已释放的句柄不会被新实例撞上。
struct 实例记录 {
    _令牌: Box<u8>,
    已释放: bool,
}

/// 实例表：显式持有，无全局。
pub struct 实例表 {
    记录: HashMap<u64, 实例记录>,
}

impl 实例表 {
    pub fn 新建() -> Self {
        Self { 记录: HashMap::new() }
    }

    /// 开一个实例，返回句柄。
    pub fn 开启(&mut self) -> 实例句柄 {
        let 令牌 = Box::new(0u8);
        let 号 = &*令牌 as *const u8 as u64;
        self.记录.insert(号, 实例记录 { _令牌: 令牌, 已释放: false });
        实例句柄(号)
    }

    /// 关一个实例。
    ///
    /// 本表没发过这个句柄 ⇒ `句柄越界`；已经关过 ⇒ `句柄失效`。
    pub fn 关闭(&mut self, 句柄: 实例句柄) -> Result<(), 实例错误> {
        match self.记录.get_mut(&句柄.0) {
            None => Err(实例错误::句柄越界),
            Some(记录) if 记录.已释放 => Err(实例错误::句柄失效),
            Some(记录) => {
                记录.已释放 = true;
                Ok(())
            }
        }
    }

    /// 校验句柄。**未命中返回错误，不许当成功。**
    ///
    /// 本表没发过 ⇒ `句柄越界`；已关掉 ⇒ `句柄失效`。
    pub fn 校验(&self, 句柄: 实例句柄) -> Result<(), 实例错误> {
        match self.记录.get(&句柄.0) {
            None => Err(实例错误::句柄越界),
            Some(记录) if 记录.已释放 => Err(实例错误::句柄失效),
            Some(_) => Ok(()),
        }
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn 开启后校验通过() {
        let mut 表 = 实例表::新建();
        let 句柄 = 表.开启();
        assert_eq!(表.校验(句柄), Ok(()));
    }

    #[test]
    fn 关闭后校验报失效() {
        let mut 表 = 实例表::新建();
        let 句柄 = 表.开启();
        assert_eq!(表.关闭(句柄), Ok(()));
        assert_eq!(表.校验(句柄), Err(实例错误::句柄失效));
    }

    #[test]
    fn 重复关闭报失效() {
        let mut 表 = 实例表::新建();
        let 句柄 = 表.开启();
        assert_eq!(表.关闭(句柄), Ok(()));
        assert_eq!(表.关闭(句柄), Err(实例错误::句柄失效));
    }

    #[test]
    fn 陌生句柄报越界() {
        let mut 表 = 实例表::新建();
        // 没开过任何实例：任何句柄都不属于本表。
        assert_eq!(表.校验(实例句柄(0)), Err(实例错误::句柄越界));
        assert_eq!(表.关闭(实例句柄(0)), Err(实例错误::句柄越界));

        // 开过一个之后，陌生句柄仍然报越界（不是失效）。
        let 句柄 = 表.开启();
        assert_eq!(表.校验(实例句柄(句柄.0.wrapping_add(4096))), Err(实例错误::句柄越界));
    }

    /// 最关键的反向验证：两张独立实例表，各自开实例，互不污染。
    #[test]
    fn 两表互不污染() {
        let mut 甲 = 实例表::新建();
        let mut 乙 = 实例表::新建();
        let 甲句柄 = 甲.开启();
        let 乙句柄 = 乙.开启();

        // 各自认自己的。
        assert_eq!(甲.校验(甲句柄), Ok(()));
        assert_eq!(乙.校验(乙句柄), Ok(()));

        // 反向：甲表的句柄在乙表里必须报「越界」，不是失效、更不是通过。
        assert_eq!(乙.校验(甲句柄), Err(实例错误::句柄越界));
        assert_eq!(甲.校验(乙句柄), Err(实例错误::句柄越界));

        // 反向关闭也不许误伤对方。
        assert_eq!(乙.关闭(甲句柄), Err(实例错误::句柄越界));
        assert_eq!(甲.校验(甲句柄), Ok(()));

        // 在甲表里关掉甲句柄，乙表一点不受影响。
        assert_eq!(甲.关闭(甲句柄), Ok(()));
        assert_eq!(甲.校验(甲句柄), Err(实例错误::句柄失效));
        assert_eq!(乙.校验(乙句柄), Ok(()));
    }

    /// 句柄空间是 u64，不会真耗尽；这里验的是**生成器不重复**：
    /// 同一张表连开一批不撞号，关掉一半再开一批也不与旧号相撞。
    #[test]
    fn 句柄生成器不重复() {
        let 数量 = 10_000u32;
        let mut 表 = 实例表::新建();
        let mut 见过 = HashSet::new();
        let mut 首批 = Vec::new();
        for _ in 0..数量 {
            首批.push(表.开启());
        }
        for 句柄 in &首批 {
            assert!(见过.insert(句柄.0), "句柄重复：{句柄:?}");
        }
        assert_eq!(见过.len(), 数量 as usize);
        for 句柄 in &首批 {
            assert_eq!(表.校验(*句柄), Ok(()));
        }

        for 句柄 in 首批.iter().step_by(2) {
            assert_eq!(表.关闭(*句柄), Ok(()));
        }
        let mut 次批 = Vec::new();
        for _ in 0..数量 {
            次批.push(表.开启());
        }
        for 句柄 in &次批 {
            assert!(见过.insert(句柄.0), "新旧句柄撞号：{句柄:?}");
        }
        assert_eq!(见过.len(), (数量 * 2) as usize);
    }
}
