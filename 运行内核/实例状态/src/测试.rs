//! 测试 —— 两表互不污染 · 句柄生成器不重复（源出 `lib.rs`，**逐字搬家**）。

use super::*;
use std::collections::HashSet;

#[test]
fn 开启后校验通过() {
    let mut 表 = 实例表::新建();
    let 句柄 = 表.开启();
    assert_eq!(表.校验(句柄), Ok(()));
}

#[test]
fn 关闭后校验报失效() {
    let mut 表 = 实例表::新建();
    let 句柄 = 表.开启();
    assert_eq!(表.关闭(句柄), Ok(()));
    assert_eq!(表.校验(句柄), Err(实例错误::句柄失效));
}

#[test]
fn 重复关闭报失效() {
    let mut 表 = 实例表::新建();
    let 句柄 = 表.开启();
    assert_eq!(表.关闭(句柄), Ok(()));
    assert_eq!(表.关闭(句柄), Err(实例错误::句柄失效));
}

#[test]
fn 陌生句柄报越界() {
    let mut 表 = 实例表::新建();
    // 没开过任何实例：任何句柄都不属于本表。
    assert_eq!(表.校验(实例句柄(0)), Err(实例错误::句柄越界));
    assert_eq!(表.关闭(实例句柄(0)), Err(实例错误::句柄越界));

    // 开过一个之后，陌生句柄仍然报越界（不是失效）。
    let 句柄 = 表.开启();
    assert_eq!(表.校验(实例句柄(句柄.0.wrapping_add(4096))), Err(实例错误::句柄越界));
}

/// 最关键的反向验证：两张独立实例表，各自开实例，互不污染。
#[test]
fn 两表互不污染() {
    let mut 首表 = 实例表::新建();
    let mut 次表 = 实例表::新建();
    let 首句柄 = 首表.开启();
    let 次句柄 = 次表.开启();

    // 各自认自己的。
    assert_eq!(首表.校验(首句柄), Ok(()));
    assert_eq!(次表.校验(次句柄), Ok(()));

    // 反向：首表的句柄在次表里必须报「越界」，不是失效、更不是通过。
    assert_eq!(次表.校验(首句柄), Err(实例错误::句柄越界));
    assert_eq!(首表.校验(次句柄), Err(实例错误::句柄越界));

    // 反向关闭也不许误伤对方。
    assert_eq!(次表.关闭(首句柄), Err(实例错误::句柄越界));
    assert_eq!(首表.校验(首句柄), Ok(()));

    // 在首表里关掉首句柄，次表一点不受影响。
    assert_eq!(首表.关闭(首句柄), Ok(()));
    assert_eq!(首表.校验(首句柄), Err(实例错误::句柄失效));
    assert_eq!(次表.校验(次句柄), Ok(()));
}

/// 句柄空间是 u64，不会真耗尽；这里验的是**生成器不重复**：
/// 同一张表连开一批不撞号，关掉一半再开一批也不与旧号相撞。
#[test]
fn 句柄生成器不重复() {
    let 数量 = 10_000u32;
    let mut 表 = 实例表::新建();
    let mut 见过 = HashSet::new();
    let mut 首批 = Vec::new();
    for _ in 0..数量 {
        首批.push(表.开启());
    }
    for 句柄 in &首批 {
        assert!(见过.insert(句柄.0), "句柄重复：{句柄:?}");
    }
    assert_eq!(见过.len(), 数量 as usize);
    for 句柄 in &首批 {
        assert_eq!(表.校验(*句柄), Ok(()));
    }

    for 句柄 in 首批.iter().step_by(2) {
        assert_eq!(表.关闭(*句柄), Ok(()));
    }
    let mut 次批 = Vec::new();
    for _ in 0..数量 {
        次批.push(表.开启());
    }
    for 句柄 in &次批 {
        assert!(见过.insert(句柄.0), "新旧句柄撞号：{句柄:?}");
    }
    assert_eq!(见过.len(), (数量 * 2) as usize);
}
