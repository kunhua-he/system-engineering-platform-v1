//!
//! 源出 `lib.rs`（拆件依据：`项目文档/开发规范/开发规范.md` 第六节「入口零实现」），**逐字搬家**。

/// 实例句柄。不透明，跨边界只传这个数。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct 实例句柄(pub u64);

/// 实例错误。
///
/// # 两种失败必须分得开
///
/// - `句柄越界`：本表从没发过这个句柄（不属于本表）。
/// - `句柄失效`：本表发过，但已经关掉了（含重复关闭）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 实例错误 {
    /// 句柄不存在或已释放。
    句柄失效,
    /// 句柄不属于本实例。
    句柄越界,
}
