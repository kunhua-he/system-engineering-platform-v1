//! 密钥引用 —— **密钥的「引用」是部署事实**（架构收敛方案项 E08）。
//!
//! # 它解决什么
//!
//! 一条资源要连数据库、要连上游接口，就需要一个口令 / 密钥。**密钥本体不许进制品**：
//! 制品是可分发、可复制、可进版本库的东西，把本体写进去等于把凭据一起发出去。
//! 故制品里只放**引用**（一个名字），本体由**部署侧**给 —— 与
//! [`解析`](crate::解析) 对「运行数据放哪」是同一条口径：**外部事实注入，不从全局读**。
//!
//! ```text
//! 制品 / 声明          部署侧（本机环境）
//! 引用名 ──────────►  部署密钥表（引用名 → 值）
//!                            │
//!                     解析密钥引用 ──► 值（只在运行期、只在部署方手上）
//! ```
//!
//! # 三条硬规则
//!
//! | 规则 | 落点 |
//! |---|---|
//! | **本体不进制品** | 本件只有 [`密钥引用::引用名`] 与 [`密钥引用::部署密钥表`]；本 crate **零第三方依赖**，读不到任何真实密钥库 |
//! | **解析不到即结构化失败** | [`密钥解析失败`] 逐条可判（引用为空 / 无此引用），**不编一个空值**（编值 = 把「没配」藏起来） |
//! | **空即拒** | [`密钥引用::空实例`] 的引用名是空串 ⇒ 解析恒 [`密钥解析失败::引用为空`]（与「默认拒绝」同一条纪律） |
//!
//! # 本件**不做**什么（如实登记，不假装覆盖了）
//!
//! - **不读环境变量、不读文件、不连密钥库** —— 部署侧怎么把表填出来（env / 文件 / 保管库）
//!   不是本件的活；本件只吃**已经填好的** [`密钥引用::部署密钥表`]（与 [`解析`](crate::解析)
//!   只吃 [`解析环境`](crate::解析环境) 同一个路子）。
//! - **不做加解密** —— 本件只回答「这个引用名部署方给了什么值」，不碰值本身怎么保护。

