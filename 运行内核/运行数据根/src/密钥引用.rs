/// 一个密钥的**引用**（不是本体）。
///
/// 形状只有两样：制品里写的**引用名** + 部署方给的**引用表**。
/// 表里**没有**引用名对应的那一行 ⇒ 解析失败（不是「空值」）—— 「没配」与「配了空」
/// 必须分得开（`契约声明/格式说明.md` 第四节同一个坑）。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 密钥引用 {
    /// 制品里写的引用名。**空串即拒**（没有名字就无从解析）。
    pub 引用名: String,
    /// 部署侧给的引用表：`(引用名, 值)`。**值只在运行期、只在部署方手上**。
    pub 部署密钥表: Vec<(String, String)>,
}

/// 解析密钥引用失败。**结构化，不编一个空值**。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 密钥解析失败 {
    /// 引用名是空串（没有名字，部署方也无从给）。
    引用为空,
    /// 部署方的引用表里没有这个名字（「没配」，与「配了空」不是一回事）。
    无此引用,
}

impl 密钥引用 {
    /// 空实例：没有引用名、没有引用表 ⇒ 解析恒失败。
    ///
    /// 与 [`资源网关口`](crate::子目录) 一类的「默认拒绝」同一条纪律：
    /// **这不是「没配好」，这是本节点正确的默认值**。
    pub const fn 空实例() -> Self {
        Self {
            引用名: String::new(),
            部署密钥表: Vec::new(),
        }
    }

    /// **部署侧解析口**：把 [`密钥引用::引用名`] 解析成部署方给的值。
    ///
    /// - 引用名为空 ⇒ [`密钥解析失败::引用为空`]；
    /// - 表里没有这个名字 ⇒ [`密钥解析失败::无此引用`]；
    /// - 表里有 ⇒ 交出那个值（**原样**，本件不加工它）。
    pub fn 解析密钥引用(&self) -> Result<&str, 密钥解析失败> {
        if self.引用名.is_empty() {
            return Err(密钥解析失败::引用为空);
        }
        self.部署密钥表
            .iter()
            .find(|引用条目| 引用条目.0 == self.引用名)
            .map(|引用条目| 引用条目.1.as_str())
            .ok_or(密钥解析失败::无此引用)
    }

    /// 部署方已给的条数。**只报条数，不报值** —— 值不许进日志、不许进回执。
    pub fn 已登记条数(&self) -> u32 {
        u32::try_from(self.部署密钥表.len()).unwrap_or(u32::MAX)
    }
}
