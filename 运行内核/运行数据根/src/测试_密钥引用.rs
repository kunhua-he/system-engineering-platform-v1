//! 测试（整文件即测试，`lib.rs` 用 `#[cfg(test)] #[path]` 挂进来）。
//!
//! 每条分支都要有读数：空引用名 · 表里无此名 · 表里有名 · 空实例恒拒 · 条数只报数。
//! 另外一条是**判据的反向样本**：解析出的值必须**逐字**是部署方给的那个（串台即红）。

use super::*;

// ── 一 引用为空 ───────────────────────────────────────────────────────────

#[test]
fn 引用名为空时拒_不看表里有什么() {
    let 引用 = 密钥引用 {
        引用名: String::new(),
        部署密钥表: vec![("上游口令".to_owned(), "部署方给的值".to_owned())],
    };
    assert_eq!(引用.解析密钥引用(), Err(密钥解析失败::引用为空));
}

#[test]
fn 空实例恒拒() {
    assert_eq!(密钥引用::空实例().解析密钥引用(), Err(密钥解析失败::引用为空));
}

// ── 二 无此引用 ───────────────────────────────────────────────────────────

#[test]
fn 表里没有这个名字时拒_不编一个空值() {
    let 引用 = 密钥引用 {
        引用名: "上游口令".to_owned(),
        部署密钥表: vec![("别的名字".to_owned(), "部署方给的值".to_owned())],
    };
    assert_eq!(引用.解析密钥引用(), Err(密钥解析失败::无此引用));
}

#[test]
fn 空表也拒() {
    let 引用 = 密钥引用 {
        引用名: "上游口令".to_owned(),
        部署密钥表: Vec::new(),
    };
    assert_eq!(引用.解析密钥引用(), Err(密钥解析失败::无此引用));
}

// ── 三 表里有名 ⇒ 交出那个值 ─────────────────────────────────────────────

#[test]
fn 表里有这个名字时交出值() {
    let 引用 = 密钥引用 {
        引用名: "上游口令".to_owned(),
        部署密钥表: vec![("上游口令".to_owned(), "部署方给的值".to_owned())],
    };
    assert_eq!(引用.解析密钥引用(), Ok("部署方给的值"));
}

/// **反向样本**：多条同表时不许串台 —— 取到的必须是**引用名对上的那一条**。
///
/// 反向样本：把 `find` 的条件写错（如恒取第一条），本用例当场红。
#[test]
fn 多条同表_取的是引用名对上的那一条() {
    let 引用 = 密钥引用 {
        引用名: "次口令".to_owned(),
        部署密钥表: vec![
            ("首口令".to_owned(), "首值".to_owned()),
            ("次口令".to_owned(), "次值".to_owned()),
        ],
    };
    assert_eq!(引用.解析密钥引用(), Ok("次值"));
}

#[test]
fn 条数只报数_不报值() {
    let 引用 = 密钥引用 {
        引用名: "上游口令".to_owned(),
        部署密钥表: vec![
            ("首口令".to_owned(), "首值".to_owned()),
            ("次口令".to_owned(), "次值".to_owned()),
        ],
    };
    assert_eq!(引用.已登记条数(), 2);
    assert_eq!(密钥引用::空实例().已登记条数(), 0);
}
