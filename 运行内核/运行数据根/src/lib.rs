//! 运行数据根 —— **全平台运行数据的唯一落点**（第 13 个唯一物）。
//!
//! 上级：`README.md` §十（本树明确不含什么）· §十一（未定项：运行数据根的默认位置与命名）
//! 裁决：`项目文档/决策记录/2026-09-27_运行数据根.md`
//!
//! # 它解决什么
//!
//! 运行数据（数据库 · 缓存 · 日志 · 临时件）**不许落在源码树内**（`README.md` §十：
//! 上一版把运行数据堆在源码树里，是必须避免的形态）。本 crate 是**唯一**回答
//! 「运行数据放哪」的地方 —— 别的节点要落运行数据，一律调本 crate 的解析口，
//! **不许自身拼路径**（自身拼 = 第二个来源 ⇒ 位置漂了没人拦）。
//!
//! # 两条自证判据
//!
//! | 判据 | 怎么判 |
//! |---|---|
//! | **唯一解析器** | 解析口只有 [`解析`] 一处；其余口都拿「已解析的根」当入参 |
//! | **默认位置永不在源码树内** | 默认位置由**平台数据目录**推出（macOS `Library/Application Support` · Linux `$XDG_DATA_HOME` 或 `~/.local/share` · Windows `%APPDATA%`）—— 没有一条分支落在**当前目录或它的祖先** |
//!
//! # 路由（本文件零实现）
//!
//! | 件 | 是什么 |
//! |---|---|
//! | [`解析环境`] | 解析要的全部外部事实（覆盖 · 家目录 · XDG · 应用数据目录）—— **注入**，不从全局读 |
//! | [`平台`] | 目标平台（决定默认位置用哪条规则） |
//! | [`解析`] | **唯一解析器** |
//! | [`解析当前环境`] | 从真实环境解析（薄壳，只做「读 env + 判平台」两件事） |
//! | [`子目录`] | 四类运行数据的封闭枚举 |
//! | [`确保子目录`] | 建目录并交出路径 |
//!
//! 硬约束：零第三方依赖 · 标识符中文 · 定宽整数（无 `usize`/`isize` 进形状）。

