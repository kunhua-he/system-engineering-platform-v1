//! 形状 —— 一条留痕记什么 · 两个构造口 · 号位互斥判据（含承重证明）。
//!
//! 裁决与五判据对比见 `项目文档/决策记录/2026-09-27_留痕形状装两个号.md`。

/// 这次留痕记的是哪一种调用。
///
/// **为什么判别要进记录**（不许靠「哪个号非零」推断）：
/// `0` 在能力号空间里**是合法号**（底座自有段 `0xxx`，`契约声明/能力声明/0000.json` 在）
/// ⇒ 「这个号位不适用」既不能用 `0` 表达、也不能从 `0` 读出来（`契约声明/格式说明.md`
/// 第四节禁的正是「`0` 与没填不可区分」）。判别显式进记录，读取方才**不必猜**
/// —— 与「类型标签在槽内」（`README.md` §三 第 3 条）同一条口径。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum 调用类 {
    /// 调一条能力：`能力号` 有义。
    能力 = 0,
    /// 访问一条资源的某个操作：`资源号` + `操作号` 有义。
    资源 = 1,
}

/// 一条留痕。
///
/// 字段顺序 = **冻结区 + 旁路区**（`契约声明/冻结登记.json` 的旁路纪律：旁路字段一律追加在尾部）。
/// 前六个字段是原形状，逐字未动；`调用类` · `资源号` · `操作号` 是 2026-09-27 追加的旁路字段
/// （原形状只有「能力号」一个号字段，而资源访问有「资源号 + 操作号」两个
/// ⇒ 资源号曾塞进 `能力号`、操作号曾塞进 `追踪号`）
/// ⚠ **改这里的字段或顺序 = 改形状**：形状变化必须在 `契约声明/冻结登记.json` 登记，没有登记即为违规。
///
/// **构造只有两个口**：[`留痕::能力调用`] 与 [`留痕::资源访问`]。本类型带 `#[non_exhaustive]`
/// ⇒ 本 crate 之外**写不出结构体字面量**（rustc 报 E0639），两个号位的互斥关系由这两个口一次写对，
/// 调用方不必自己维护；读取不受影响（字段照旧可读）。
#[non_exhaustive]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 留痕 {
    pub 实例: u64,
    pub 能力号: u32,
    pub 入参指纹: u64,
    pub 结果码: i32,
    pub 耗时微秒: u64,
    pub 追踪号: u64,
    // ── 旁路区（2026-09-27，只增不改）──────────────────────────────
    /// 这一次留痕记的是能力调用还是资源访问。
    pub 调用类: 调用类,
    /// 资源号。`调用类::资源` 时有义；能力调用恒 `0`（`0` 不是资源号，见 [`留痕::自洽`]）。
    pub 资源号: u32,
    /// 操作号。`调用类::资源` 时有义；能力调用恒 `0`。
    pub 操作号: u32,
}

impl 留痕 {
    /// **能力调用**的一条留痕 —— 写侧唯一的两个口之一。
    ///
    /// 参数次序与字段次序一致（`实例` 在前，`追踪号` 在后）。
    /// `追踪号` 是**这一次调用**的关联号（一次调用一个，`现代架构落点.md` §六），
    /// **不是**任何号空间里的号 —— 资源访问曾经把它当操作号用，那个塞法已废。
    pub const fn 能力调用(
        实例: u64,
        能力号: u32,
        入参指纹: u64,
        结果码: i32,
        耗时微秒: u64,
        追踪号: u64,
    ) -> Self {
        Self {
            实例,
            能力号,
            入参指纹,
            结果码,
            耗时微秒,
            追踪号,
            调用类: 调用类::能力,
            资源号: 0,
            操作号: 0,
        }
    }

    /// **资源访问**的一条留痕 —— 写侧唯一的两个口之一。
    ///
    /// `资源号` + `操作号` 就是「调什么」那两个号（`字段名册与引用方式.md` §三：资源按
    /// **资源号 + 操作号**引用）；`能力号` 恒 `0`（不适用，由 [`留痕::自洽`] 判）。
    pub const fn 资源访问(
        实例: u64,
        资源号: u32,
        操作号: u32,
        入参指纹: u64,
        结果码: i32,
        耗时微秒: u64,
        追踪号: u64,
    ) -> Self {
        Self {
            实例,
            能力号: 0,
            入参指纹,
            结果码,
            耗时微秒,
            追踪号,
            调用类: 调用类::资源,
            资源号,
            操作号,
        }
    }

    /// 本条记录自洽吗 —— **判别与号位必须一致**（防回潮判据，可机器判）：
    ///
    /// - `调用类::能力` ⇒ `资源号 == 0` 且 `操作号 == 0`（`能力号` 是能力号，`0` 也是合法能力号）；
    /// - `调用类::资源` ⇒ `能力号 == 0` 且 `资源号 != 0`
    ///   （`0` 不是资源号：`契约声明/号段图.json` 的资源号段从 `1` 起）。
    ///
    /// 读侧的用法：**先看 `调用类` 再取号**；两个号位里另一个必然是 `0`。
    pub const fn 自洽(&self) -> bool {
        match self.调用类 {
            调用类::能力 => self.资源号 == 0 && self.操作号 == 0,
            调用类::资源 => self.能力号 == 0 && self.资源号 != 0,
        }
    }
}

// ════════════════════════════════════════════════════════════════════════════
// 编译期判据（③g/③h 同款：`const _: () = assert!(…)` —— `cargo check` 即判，不靠人眼）
// ════════════════════════════════════════════════════════════════════════════

/// 判据与**承重证明**（「退回一步」）：两个构造口产出的记录必自洽；把资源号塞回 `能力号`、
/// 把操作号塞进 `追踪号` 的**旧塞法**在最后一条断言里**当场判不自洽** ⇒ 判据不是空的，
/// 它抓的正是旧病；把修法退回一步，它就红。
const _: () = {
    let 能力样本: 留痕 = 留痕::能力调用(7, 1001, 0x9E37_79B9_7F4A_7C15, 0, 10, 1);
    assert!(能力样本.自洽());
    let 资源样本: 留痕 = 留痕::资源访问(7, 5003, 1, 0, 0, 0, 1);
    assert!(资源样本.自洽());
    // 退回一步：旧塞法（资源号 → `能力号`，操作号 → `追踪号`，资源号位空着）⇒ 必须红。
    let 退回一步: 留痕 = 留痕 {
        实例: 7,
        能力号: 5003,
        入参指纹: 0,
        结果码: 0,
        耗时微秒: 0,
        追踪号: 1,
        调用类: 调用类::资源,
        资源号: 0,
        操作号: 0,
    };
    assert!(!退回一步.自洽());
    // 反向样本之二：判别说「能力」，而资源号位非零（有义号位填错了）⇒ 也必须红。
    let 号位串味: 留痕 = 留痕 {
        实例: 7,
        能力号: 1001,
        入参指纹: 0,
        结果码: 0,
        耗时微秒: 0,
        追踪号: 1,
        调用类: 调用类::能力,
        资源号: 9,
        操作号: 0,
    };
    assert!(!号位串味.自洽());
};
