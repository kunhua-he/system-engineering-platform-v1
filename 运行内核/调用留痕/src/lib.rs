//! 调用留痕 —— 谁 · 调什么 · 入参指纹 · 结果 · 耗时。
//!
//! **不进关键路径**：留痕缺席时调用照样成功，留痕存在时调用不变慢。
//! 所以是本地环形缓冲 + 满了按策略丢弃并计数，不是同步落盘。
//!
//! # 路由（本文件零实现）
//!
//! | 件 | 是什么 |
//! |---|---|
//! | [`留痕`] | 一条留痕的**形状**（冻结区 + 旁路区）+ 两个构造口 + [`留痕::是否自洽`] |
//! | [`调用类`] | 这次记的是**能力调用**还是**资源访问**（判别在记录内，读侧不必猜） |
//! | [`留痕缓冲`] | 环形缓冲：`追加一条` / `取最近` / `已丢弃` / `号位不自洽数` |
//! | [`丢弃策略`] | 满了丢最旧还是丢最新 |
//! | [`槽表指纹`] | 入参槽表的 FNV-1a 指纹（留痕的「调什么」标识；全平台只此一份） |
//!
//! # 形状（已收口，2026-09-27）
//!
//! 资源访问有**资源号 + 操作号**两个号，原形状只有「能力号」一个号位（`留痕` 与它现在
//! 的字段表见 [`留痕`]）；[`留痕::能力调用`] 与 [`留痕::资源访问`] 是**写侧唯一的两个口**，
//! 判别与两个号位一次写对。裁决与五判据对比：`项目文档/决策记录/2026-09-27_留痕形状装两个号.md`。
//!
//! # 落点（`现代架构落点.md` §六 · `开发规范.md` B7）
//!
//! | 要求 | 本 crate 的做法 |
//! |---|---|
//! | 不阻塞调用 | [`留痕缓冲::追加一条`] 只做原子操作与一次字段写入，**不取锁、不等待、不分配** |
//! | 满了按策略丢弃并计数 | `丢最旧` 覆盖最旧一条、`丢最新` 丢掉新来的一条；两者都把 [`留痕缓冲::已丢弃`] 加一 |
//! | 丢痕不许静默 | 丢弃数**必须能读到**（[`留痕缓冲::已丢弃`]），这是本 crate 的核心判据 |
//! | 坏痕不许静默 | 号位不自洽的条数也要能读到（[`留痕缓冲::号位不自洽数`]），见下 |
//! | 状态显式持有 | 缓冲是普通值，随实例持有，**不落进程级全局**（`开发规范.md` B6） |
//!
//! # 并发形状（留痕侧前提）
//!
//! 留痕**不阻塞调用**，所以它对并发的要求是「**谁都能记、谁都能读、谁都不等谁**」：
//!
//! - `追加一条` 与 `取最近` 都取 `&self` ⇒ 多个写者与读者可同时进来，调用方**不需要**加锁；
//! - 写者先用一次 `fetch_add` 原子领号（**唯一的共享写点，常数时间**），再落到 `号 % 容量` 那格；
//! - 每格内容**逐字段原子**，写者写完字段后用 `就绪` 发布，读者按顺序锁（读 `就绪` → 读字段 → 复读 `就绪`）校验，
//!   因此**不需要 `unsafe`**，也不存在数据竞争；
//! - 同格的多个写者用一次 CAS 认领串行化；认领与读取都用**有界重试**，宁可丢一条也**绝不转圈等待**；
//! - `留痕缓冲` / `留痕` / `调用类` 的 `Send + Sync` 是**编译期**判据（`缓冲.rs` 末尾的
//!   `const _: fn() = …`）：给缓冲加线程亲和的字段（`Cell` / `Rc` / `RefCell`）或全局可变状态，当场红。
//!
//! **给接线方的口**（形状归本 crate，接线归 `跨语言适配/` 与 `对外接口面/`）：
//! 写侧用两个构造函数（`留痕 { … }` 字面量在本 crate 外**写不出来**：`#[non_exhaustive]`）；
//! 读侧照字段读、`取最近` 与 `号位不自洽数` 各一次调用；**本 crate 不替任何一侧造第二份记录形状**。
//!
//! 硬约束：零第三方依赖 · 标识符中文 · 形状只用定宽整数（无 `usize`/`isize`）·
//! [`留痕缓冲::追加一条`] **不 panic、不返回 `Result`** · 三条 `const _` 判据在 `cargo check` 即判。

