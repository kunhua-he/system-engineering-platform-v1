// 留痕不阻塞调用 —— 多线程记与读，不取锁、不丢、不崩
// ════════════════════════════════════════════════════════════════════════════

/// 四个线程各记 1000 条进容量 4096 的缓冲：写入总数 ≤ 容量 ⇒ 每条各占一格，
/// 认领不会相互挤 ⇒ **已丢弃必须为 0**、取回 4000 条、全部自洽。
///
/// 这一条同时是「留痕对并发的要求」的落点：缓冲逐字段原子、`追加一条`/`取最近` 都取 `&self`，
/// 调用方**不需要**外部加锁（`const _: fn() = …` 的 `Send + Sync` 断言在 `缓冲.rs`）。
#[test]
fn 并发_四线程记不丢不崩() {
    use std::sync::Arc;
    use std::sync::atomic::{AtomicU64, Ordering};

    const 线程数: u64 = 4;
    const 每线程条数: u64 = 1000;
    let 缓冲 = Arc::new(留痕缓冲::构造(4096, 丢弃策略::丢最旧));
    // 各线程用自身的追踪号段，避免撞号看不出是谁的。
    let 下一个追踪号 = Arc::new(AtomicU64::new(0));

    std::thread::scope(|作用域| {
        for _ in 0..线程数 {
            let 缓冲 = Arc::clone(&缓冲);
            let 下一个追踪号 = Arc::clone(&下一个追踪号);
            作用域.spawn(move || {
                for _ in 0..每线程条数 {
                    let 追踪号 = 下一个追踪号.fetch_add(1, Ordering::Relaxed);
                    缓冲.追加一条(留痕::能力调用(7, 能力号::构造(1001), 追踪号, 0, 0, 追踪号));
                }
            });
        }
    });

    let 取回 = 缓冲.取最近(u32::MAX);
    assert_eq!(取回.len() as u64, 线程数 * 每线程条数, "一条都不许丢");
    assert_eq!(缓冲.已丢弃条数(), 0);
    assert_eq!(缓冲.号位不自洽数(), 0);
    assert!(取回.iter().all(留痕::是否自洽));
}

/// 造一条**四字段同源**的留痕：`身份值` 同时进 `实例号` · `入参指纹` · `耗时微秒` · `追踪号`。
///
/// 为什么四字段都要与同一个值挂钩：发现4 的病是「读到的字段由**不同调用**拼接」
///（实例号属新写、入参指纹/耗时/追踪号属旧写）⇒ 任一字段跟另一个对不上就是拼接。
fn 造同源留痕(身份值: u64) -> 留痕 {
    留痕::能力调用(身份值, 能力号::构造(1001), 同源指纹(身份值), 0, 同源耗时(身份值), 身份值)
}

/// `身份值` ⇒ `入参指纹`（与 `造留痕` 同一乘子，只是这里必须可逆地由单字段反推）。
fn 同源指纹(身份值: u64) -> u64 {
    身份值.wrapping_mul(0x9E37_79B9_7F4A_7C15)
}

/// `身份值` ⇒ `耗时微秒`。
fn 同源耗时(身份值: u64) -> u64 {
    身份值.wrapping_mul(10)
}

/// 一条记录自洽吗 —— **四个字段必须都指向同一个身份值**（读侧跨字段一致，不是写侧自洽）。
///
/// 与 [`留痕::是否自洽`] 是两回事：那个管**号位**（判别/号位是否互斥），本件管**同一批发布**
/// （一条已发布的记录里字段属不属于同一次写入）。
fn 是同源(明细条目: &留痕) -> bool {
    明细条目.实例号 == 明细条目.追踪号
        && 明细条目.耗时微秒 == 同源耗时(明细条目.追踪号)
        && 明细条目.入参指纹 == 同源指纹(明细条目.追踪号)
        && 明细条目.能力号 == 能力号::构造(1001)
}

/// **发现4 反向样本**：**一写一读同时进行**（不是写完再读）· 容量 8 · 三轮。
///
/// 断言：读到的**每一条**记录四字段同源。
///
/// **为什么非得读写同时**（审计原话）：写者是「先认领 `在写` → 逐字段覆盖 → 发布 `就绪` → 放 `在写`」。
/// 只在写完之后读，`就绪` 早已发布，那条窗口（字段已覆盖、`就绪` 还是旧值）踩不到 ⇒
/// 这条测试就成了「写侧自洽」的重复，而不是「读侧跨字段一致」。
/// 容量 8 是为了让同一格被反复覆盖 —— 窗口只在这一格被改写时出现。
#[test]
fn 并发_读写同时_每条记录字段自洽() {
    use std::sync::Arc;
    use std::sync::atomic::{AtomicBool, Ordering};

    const 容量: u32 = 8;
    const 轮数: u64 = 3;
    const 每轮写入: u64 = 20_000;

    let mut 总读条数: u64 = 0;
    let mut 拼接数: u64 = 0;

    for 轮号 in 0..轮数 {
        let 缓冲 = Arc::new(留痕缓冲::构造(容量, 丢弃策略::丢最旧));
        let 写完了 = Arc::new(AtomicBool::new(false));
        let 写侧缓冲 = Arc::clone(&缓冲);
        let 写侧标志 = Arc::clone(&写完了);
        let 起点 = 轮号 * 每轮写入;

        std::thread::scope(|作用域| {
            作用域.spawn(move || {
                for 序号 in 0..每轮写入 {
                    写侧缓冲.追加一条(造同源留痕(起点 + 序号));
                }
                写侧标志.store(true, Ordering::Release);
            });

            // 读侧：写者没写完就一直读（**读写同时**）；写完后再收一回尾。
            let mut 点一遍 = |缓冲: &留痕缓冲| {
                for 明细条目 in 缓冲.取最近(容量) {
                    总读条数 += 1;
                    if !是同源(&明细条目) {
                        拼接数 += 1;
                    }
                }
            };
            while !写完了.load(Ordering::Acquire) {
                点一遍(&缓冲);
            }
            点一遍(&缓冲);
        });
    }

    assert!(总读条数 > 0, "读侧一条都没读到 ⇒ 反向样本没真跑（假绿）");
    assert_eq!(拼接数, 0, "读到由不同调用拼接的字段（实例号/入参指纹/耗时/追踪号 不同源）：{拼接数} 条");
}

