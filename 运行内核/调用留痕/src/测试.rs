#[test]
fn 多实例互不污染() {
    // 两个同类实例按**角色**命名：`被测缓冲` 超容量（丢 1 条）、`对照缓冲` 不超（丢 0 条）。
    let 被测缓冲 = 留痕缓冲::新建(2, 丢弃策略::丢最旧);
    let 对照缓冲 = 留痕缓冲::新建(2, 丢弃策略::丢最旧);
    被测缓冲.追加一条(一条(1));
    被测缓冲.追加一条(一条(2));
    被测缓冲.追加一条(一条(3));
    对照缓冲.追加一条(一条(9));
    assert_eq!(被测缓冲.已丢弃(), 1);
    assert_eq!(对照缓冲.已丢弃(), 0);
    assert_eq!(追踪号列(&被测缓冲.取最近(2)), vec![2, 3]);
    assert_eq!(追踪号列(&对照缓冲.取最近(2)), vec![9]);
}

