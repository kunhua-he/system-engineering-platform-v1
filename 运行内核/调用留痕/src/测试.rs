/// 资源访问：`资源号` 进 `资源号` 格、`操作号` 进 `操作号` 格、`能力号` 恒 `0`、
/// **`追踪号` 还是真追踪号**（旧塞法把操作号塞进 `追踪号`，这一条钉的就是它不再发生）。
#[test]
fn 资源访问_两个号各就各位_追踪号不被征用() {
    let 缓冲 = 留痕缓冲::新建(4, 丢弃策略::丢最旧);
    缓冲.追加一条(留痕::资源访问(7, 资源号::新建(5003), 操作号::新建(2), 0xABCD, 0, 42, 99));

    let 条 = 缓冲.取最近(1);
    assert_eq!(条.len(), 1);
    assert_eq!(条[0].调用类, 调用类::资源);
    assert_eq!(条[0].资源号, 5003);
    assert_eq!(条[0].操作号, 2);
    assert_eq!(条[0].能力号, 0, "资源访问时能力号位不适用");
    assert_eq!(条[0].追踪号, 99, "追踪号是这一次调用的关联号，不是操作号");
    assert_eq!(条[0].耗时微秒, 42);
    assert!(条[0].自洽());
    assert_eq!(缓冲.不自洽数(), 0);
}

/// 能力调用：`资源号` / `操作号` 两个位恒 `0`；`能力号 0` 是**合法能力号**，照常记。
#[test]
fn 能力调用_资源侧两位恒零() {
    let 缓冲 = 留痕缓冲::新建(4, 丢弃策略::丢最旧);
    缓冲.追加一条(一条(1));
    // 能力号 0（底座自有段）也是合法的，不许被当成「不适用」。
    缓冲.追加一条(留痕::能力调用(7, 能力号::新建(0), 0, 0, 1, 2));

    let 条 = 缓冲.取最近(2);
    assert_eq!(条[0].调用类, 调用类::能力);
    assert_eq!(条[0].资源号, 0);
    assert_eq!(条[0].操作号, 0);
    assert_eq!(条[1].能力号, 0, "0 是合法能力号，照样读得出来");
    assert_eq!(缓冲.不自洽数(), 0);
}

/// **两种调用走同一条缓冲**（这是「不产生第二条腿」的落点）：一条机制、两种记录，
/// 按时间序混排取出，类别与号位一一对得上。
#[test]
fn 两种调用同一条缓冲_时间序混排() {
    let 缓冲 = 留痕缓冲::新建(8, 丢弃策略::丢最旧);
    缓冲.追加一条(一条(1));
    缓冲.追加一条(留痕::资源访问(7, 资源号::新建(1), 操作号::新建(1), 0, 0, 0, 2));
    缓冲.追加一条(一条(3));

    let 条 = 缓冲.取最近(8);
    assert_eq!(追踪号列(&条), vec![1, 2, 3], "两种记录在同一条时间序里");
    assert_eq!(
        [条[0].调用类, 条[1].调用类, 条[2].调用类],
        [调用类::能力, 调用类::资源, 调用类::能力]
    );
    assert_eq!(条[1].资源号, 1);
    assert_eq!(条[1].操作号, 1);
    assert_eq!(缓冲.已丢弃(), 0);
}

/// **防回潮（承重证明的运行期那一半）**：把号塞错位的记录**照样记下来**（事件不许被抹掉），
/// 但 `不自洽数` 必须加一 ⇒ 坏痕不许静默。
#[test]
fn 号位串味_照样记下但不静默() {
    let 缓冲 = 留痕缓冲::新建(4, 丢弃策略::丢最旧);
    // 退回一步的旧塞法：资源号 → 能力号，操作号 → 追踪号，资源号位空着。
    let 旧塞法 = 留痕 {
        实例: 7,
        能力号: 能力号::新建(5003),
        入参指纹: 0,
        结果码: 0,
        耗时微秒: 0,
        追踪号: 1,
        调用类: 调用类::资源,
        资源号: 资源号::新建(0),
        操作号: 操作号::新建(0),
    };
    assert!(!旧塞法.自洽(), "旧塞法必须判不自洽");
    缓冲.追加一条(旧塞法);

    assert_eq!(缓冲.已丢弃(), 0, "坏痕也要记下，不许悄悄丢");
    assert_eq!(缓冲.不自洽数(), 1, "坏痕必须能读到");
    assert_eq!(缓冲.取最近(1).len(), 1, "事件还在（留痕的职责是记下这次调用）");

    // 反向对照：换回构造函数 ⇒ 计数不再涨。
    缓冲.追加一条(留痕::资源访问(7, 资源号::新建(5003), 操作号::新建(1), 0, 0, 0, 1));
    assert_eq!(缓冲.不自洽数(), 1, "自洽的记录不涨这个数");
}

// ════════════════════════════════════════════════════════════════════════════
// 留痕不阻塞调用 —— 多线程记与读，不取锁、不丢、不崩
// ════════════════════════════════════════════════════════════════════════════

/// 四个线程各记 1000 条进容量 4096 的缓冲：写入总数 ≤ 容量 ⇒ 每条各占一格，
/// 认领不会相互挤 ⇒ **已丢弃必须为 0**、取回 4000 条、全部自洽。
///
/// 这一条同时是「留痕对并发的要求」的落点：缓冲逐字段原子、`追加一条`/`取最近` 都取 `&self`，
/// 调用方**不需要**外部加锁（`const _: fn() = …` 的 `Send + Sync` 断言在 `缓冲.rs`）。
#[test]
fn 并发_四线程记不丢不崩() {
    use std::sync::Arc;
    use std::sync::atomic::{AtomicU64, Ordering};

    const 线程数: u64 = 4;
    const 每线程条数: u64 = 1000;
    let 缓冲 = Arc::new(留痕缓冲::新建(4096, 丢弃策略::丢最旧));
    // 各线程用自身的追踪号段，避免撞号看不出是谁的。
    let 下一个追踪号 = Arc::new(AtomicU64::new(0));

    std::thread::scope(|作用域| {
        for _ in 0..线程数 {
            let 缓冲 = Arc::clone(&缓冲);
            let 下一个追踪号 = Arc::clone(&下一个追踪号);
            作用域.spawn(move || {
                for _ in 0..每线程条数 {
                    let 追踪号 = 下一个追踪号.fetch_add(1, Ordering::Relaxed);
                    缓冲.追加一条(留痕::能力调用(7, 能力号::新建(1001), 追踪号, 0, 0, 追踪号));
                }
            });
        }
    });

    let 取回 = 缓冲.取最近(u32::MAX);
    assert_eq!(取回.len() as u64, 线程数 * 每线程条数, "一条都不许丢");
    assert_eq!(缓冲.已丢弃(), 0);
    assert_eq!(缓冲.不自洽数(), 0);
    assert!(取回.iter().all(留痕::自洽));
}
