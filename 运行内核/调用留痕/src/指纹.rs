//! 指纹 —— 入参槽表的 FNV-1a 指纹：留痕要能说清「**调什么**」而不必存下整张槽表。
//!
//! 同一张槽表必得同一个数（常数时间 · 不分配 · 零 `unsafe`）。
//! **全平台只有这一份**：`资源网关口` 与 `适配器实现` 都从这里取
//! （两个 crate 都已依赖本 crate）—— 早先各写一份，字段序 / 宽度哪天漂了，
//! 跨 crate 的指纹就静默不可比（假读数）。

use v1_contract::数据槽;

/// FNV-1a 64 位的**偏移基数**（初始值）。**只做指纹**，不做加密。
const 指纹基数: u64 = 0xcbf2_9ce4_8422_2325;
/// FNV-1a 64 位的**质数**（每次异或后相乘）。
const 指纹质数: u64 = 0x0000_0100_0000_01b3;

/// 入参指纹：对一张槽表逐字节滚过每个槽的**定长字段**（类型标签 · 标志 · 保留 · 长度 · 值）。
///
/// 字段宽度与字节序是契约：类型标签 `u32` · 标志 `u16` · 保留 `u16` · 长度 `u64` · 值 `u64`，
/// 一律小端 ⇒ **跨机器同一个数**（指纹要能比对）。
/// **不碰 `值` 指向的内存** —— 指针值本身进指纹就够了；解引用会引入越界风险，
/// 且不改变「入参不同指纹不同」这条性质。
pub fn 槽表指纹(槽表: &[数据槽]) -> u64 {
    let mut 指纹 = 指纹基数;
    for 数据槽 in 槽表 {
        let 字节 = 数据槽
            .类型标签
            .取号值()
            .to_le_bytes()
            .into_iter()
            .chain(数据槽.槽标志位.to_le_bytes())
            .chain(数据槽.保留.to_le_bytes())
            .chain(数据槽.长度.to_le_bytes())
            .chain(数据槽.槽值.to_le_bytes());
        for 一字节 in 字节 {
            指纹 ^= u64::from(一字节);
            指纹 = 指纹.wrapping_mul(指纹质数);
        }
    }
    指纹
}
