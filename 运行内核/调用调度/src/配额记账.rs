//! 配额账本：按能力号记账的滚动窗口计数器。
//!
//! 时间源用 `Instant`（单调）而不是墙钟：墙钟回拨不许把配额算错。
//!
//! **本结构体不落任何 `static`**：调用方按实例 `新建` 一个、显式传给 `调用`。
//! 两本账本天然互不可见 —— 这就是「多实例安全」在调用路径上的落点。
//! 账本以 `&self` 共享，故内部计数用 `Mutex` 保护（不是进程级共享，是**这一本**账的内部可变性）。

use std::collections::BTreeMap;
use std::sync::Mutex;
use std::time::Instant;

use v1_contract::调用账本;

/// 配额窗口（毫秒）。
///
/// **值只有一个来源**：`v1_contract::声明数据::配额窗口毫秒`
/// （源 = `契约声明/常量表.json` 的「配额窗口毫秒」条目）。这里只 `pub use` ——
/// 早先手写的 `pub const 配额窗口毫秒: u64 = 1_000;` 已删（同一事实的第二来源）。
///
/// 口径：窗口与单项超时**同阶**，于是「一个窗口」≈「一项最多该占的时间」，
/// 两个数看一眼就能对上，不需要额外换算。窗口越长，突发越容易被误判成超配额。
pub use v1_contract::声明数据::配额窗口毫秒;

/// 一个能力号在**一个窗口**内的调用上限。
///
/// 按号记账而不是全局记账：一个能力疯跑不许把别的能力饿死。
///
/// **值只有一个来源**：`v1_contract::声明数据::配额上限`
/// （源 = `契约声明/常量表.json` 的「配额上限」条目；**定数依据与实测读数逐字记在那里**）。
/// 这里只 `pub use` —— 早先手写的 `pub const 配额上限: u32 = 10_000;` 已删。
///
/// 口径不变：它是**限速阀**不是**容量阀** —— 正常调用摸不到它。
pub use v1_contract::声明数据::配额上限;

/// 一个号在一个窗口里的用量。
#[derive(Clone, Copy)]
struct 窗口用量 {
    窗口起点毫秒: u64,
    已用: u32,
}

/// 配额账本：按能力号记账的滚动窗口计数器。
///
/// 时间源用 `Instant`（单调）而不是墙钟：墙钟回拨不许把配额算错。
///
/// **本结构体不落任何 `static`**：调用方按实例 `新建` 一个、显式传给 `调用`。
/// 两本账本天然互不可见 —— 这就是「多实例安全」在调用路径上的落点。
/// 账本以 `&self` 共享，故内部计数用 `Mutex` 保护（不是进程级共享，是**这一本**账的内部可变性）。
pub struct 配额账本 {
    上限: u32,
    窗口毫秒: u64,
    起点: Instant,
    记录: Mutex<BTreeMap<u32, 窗口用量>>,
    /// 按号累计的真实耗时（毫秒）。执行后才写，只留痕、不参与放行判定。
    耗时记录: Mutex<BTreeMap<u32, u64>>,
}

impl 配额账本 {
    /// 新建一本账本。上限/窗口由调用方按实例给定（默认值取本 crate 的常量）。
    pub fn 新建(上限: u32, 窗口毫秒: u64) -> Self {
        Self {
            上限,
            窗口毫秒,
            起点: Instant::now(),
            记录: Mutex::new(BTreeMap::new()),
            耗时记录: Mutex::new(BTreeMap::new()),
        }
    }

    /// 某个能力号累计的真实耗时（毫秒）。
    pub fn 累计耗时毫秒(&self, 能力号: u32) -> u64 {
        let 记录 = self.耗时记录.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        *记录.get(&能力号).unwrap_or(&0)
    }

    /// 该号有没有被记过账。真实耗时为 0 毫秒时 `累计耗时毫秒` 也是 0，
    /// 分不出「没记账」与「记了但耗时为 0」，故另给这个口。
    pub fn 耗时记录键存在(&self, 能力号: u32) -> bool {
        let 记录 = self.耗时记录.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        记录.contains_key(&能力号)
    }

    /// 取用一次配额。超限返回 `false`，**不是 panic**。
    fn 取用(&self, 号: u32) -> bool {
        let 现在 = self.现在毫秒();
        // 锁中毒不许崩：中毒只说明别人 panic 过，账本本身照样能记账。
        let mut 记录 = self.记录.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        let 项 = 记录.entry(号).or_insert(窗口用量 { 窗口起点毫秒: 现在, 已用: 0 });
        if 现在.saturating_sub(项.窗口起点毫秒) >= self.窗口毫秒 {
            *项 = 窗口用量 { 窗口起点毫秒: 现在, 已用: 0 };
        }
        if 项.已用 >= self.上限 {
            return false;
        }
        项.已用 += 1;
        true
    }

    fn 现在毫秒(&self) -> u64 {
        u64::try_from(self.起点.elapsed().as_millis()).unwrap_or(u64::MAX)
    }
}

impl 调用账本 for 配额账本 {
    /// 执行**前**问一次：配额够就 `true`（放行），不够就 `false`（**不许进执行函数**）。
    fn 准调(&self, 能力号: v1_contract::能力号) -> bool {
        self.取用(能力号.取())
    }

    /// 执行**后**记一次。本账本的配额是**按次数**判的，不参与耗时——
    /// 但真实耗时仍然要收下（它是超时唯一口径的来源之一），所以不做 `_耗时毫秒` 丢弃。
    /// 现在只累加留痕；将来若要按耗时限速，改这里，不改契约。
    fn 记账(&self, 能力号: v1_contract::能力号, 耗时毫秒: u64) {
        let mut 记录 = self.耗时记录.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        let 项 = 记录.entry(能力号.取()).or_insert(0);
        *项 = 项.saturating_add(耗时毫秒);
    }
}

