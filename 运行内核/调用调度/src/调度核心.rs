//! 调度核心：调用路径上**唯一**的判定点，顺序固定、不许换。
//!
//! ```text
//! 按号取命令 → 判「未载入 / 保留项 / 已废止」 → 校验参数个数 → 问配额 → 执行 → 记账耗时
//! ```
//!
//! `调度调用` 与公开入口 `调用` 分开只为可测：公开签名里没有命令槽、账本、超时预算三个参数，
//! 判定逻辑本身只有这一份，不存在第二条腿。

use std::time::Instant;

use v1_contract::{能力号, 调用账本, 命令状态, 数据槽};
use v1_registry::{命令槽, 注册表};

use crate::错误与结果::{调度错误, 调用结果};

/// 单项超时（毫秒）—— **全平台唯一口径**。
///
/// 超时是调度层的事（`现代架构落点.md` 把「给每个能力单独设超时口径」列为明确不做）：
/// 能力不许自设，调用方也不许各传一套。
///
/// # 值只有一个来源
///
/// `v1_contract::声明数据::单项超时毫秒`（源 = `契约声明/常量表.json` 的「单项超时毫秒」
/// 条目；**定数依据与实测读数逐字记在那里**，含本机实测读数
/// `实测_空调用耗时量级` 的量级、与「一次全量验证秒级」判据的关系）。
/// 这里只 `pub use` —— 早先手写的 `pub const 单项超时毫秒: u64 = 1_000;` 已删：
/// 手写一份就是同一事实的第二来源（`契约声明/常量表.json` 判据 ①
/// 「同一个常量名不许在别处再定义」）。
///
/// **我没把握的地方**：若将来某项能力（如链接、跨机 IO）合法地需要更长的单项时间，
/// 要重定的是 `常量表.json` 里那**一个**数 —— 不许退化成「每个能力各设一套」。
/// 收紧是刻意为之：越紧，「坏了看得见」越灵。
pub use v1_contract::声明数据::单项超时毫秒;

/// 调用：按号取命令 → 判未载入/已废止 → 校验参数 → 记配额 → 执行 → 记账超时。
///
/// `账本` **按实例传入**：调用方持有，调用方释放。同一份注册表配两本账本，
/// 就是两个互不干扰的配额域（多实例隔离）。
///
/// # Safety
/// `返回槽` 必须指向可写的 `数据槽`；`参数` 的每个槽都必须已按契约填好。
pub unsafe fn 调用命令(
    注册表: &注册表,
    账本: &dyn 调用账本,
    命令号: 能力号,
    参数: &[数据槽],
    返回槽: *mut 数据槽,
) -> 调用结果 {
    // 未命中由注册表给占位项（宪法第 6 条），这里只负责把占位变成明确段位。
    let 命令槽 = 注册表.按号取命令(命令号);
    // SAFETY: 本函数的 `# Safety` 就是本调用的前提，原样传给调度核心。
    unsafe { 调度调用(命令号, 命令槽, 账本, 单项超时毫秒, 参数, 返回槽) }
}

/// 调度核心：已取到的命令槽 → 判未载入/已废止 → 校参数 → 记配额 → 执行 → 记账超时。
///
/// 与 `调用` 分开只为可测：公开签名里没有命令槽、账本、超时预算三个参数，判定逻辑本身
/// 只有这一份，不存在第二条腿。
///
/// # Safety
/// `返回槽` 必须指向可写的 `数据槽`；`参数` 的每个槽都必须已按契约填好。
///
/// 可见性：`pub(crate)` 而非私有——`配额账本` 的单元测试（兄弟模块）要直接跑调度核心，
/// 免得为了测账本再造一条旁路。crate 外看不到它。
pub(crate) unsafe fn 调度调用(
    命令号: 能力号,
    槽: 命令槽<'_>,
    账本: &dyn 调用账本,
    超时预算毫秒: u64,
    参数: &[数据槽],
    返回槽: *mut 数据槽,
) -> 调用结果 {
    let (声明, 执行) = match 槽 {
        命令槽::已载入 { 声明, 执行 } => (声明, 执行),
        // 占位项：提供者没载入。**明确段位，不是崩溃**；返回槽置空（未命中返回空）。
        命令槽::占位 { 能力号: 未命中命令号 } => {
            // SAFETY: 由调用方保证 `返回槽` 可写。
            unsafe { 置空返回槽(返回槽) };
            return 调用结果::失败(调度错误::提供者未载入 { 能力号: 未命中命令号 });
        }
    };

    // 状态位标了「错误项」= 这一项现在不可用。**要再分一次**：
    //   带了 `已废止` ⇒ 永久不可用（改用别的号）；没带 ⇒ 保留项，实现没来（等它回来）。
    // 两者处置相反，故不许合成一个段位。排在参数个数校验**之前**：目标侧判定先于
    // 调用方侧判定 —— 命令都没了，再报「你参数传错了」是误导。
    if 声明.状态位 & 命令状态::错误 != 0 {
        // SAFETY: 由调用方保证 `返回槽` 可写。
        unsafe { 置空返回槽(返回槽) };
        return 调用结果::失败(if 声明.状态位 & 命令状态::已废止 != 0 {
            调度错误::命令已废止 { 能力号: 命令号 }
        } else {
            调度错误::提供者未载入 { 能力号: 命令号 }
        });
    }

    // 参数个数：**行序即契约**，个数不符不许"尽力而为"。
    // 长度超出 u32 表达范围时按 u32::MAX 报，不截断成一个可能刚好相等的数。
    let 实际 = u32::try_from(参数.len()).unwrap_or(u32::MAX);
    if 实际 != 声明.参数个数 {
        // SAFETY: 由调用方保证 `返回槽` 可写。
        unsafe { 置空返回槽(返回槽) };
        return 调用结果::失败(调度错误::参数个数不符 { 声明: 声明.参数个数, 实际 });
    }

    // 配额在**执行前**问：账本说不行就不许进扩展。
    // 执行**后**才记账（真实耗时那时才有）——两个时点分开，见契约 `调用账本` 的注释。
    // 传的就是 `能力号` 本身：`.into()` 那种「先落成裸 u32 再进去」的写法会把号空间抹掉。
    if !账本.准调(命令号) {
        // SAFETY: 由调用方保证 `返回槽` 可写。
        unsafe { 置空返回槽(返回槽) };
        return 调用结果::失败(调度错误::配额用尽);
    }

    // 0 个参数给空指针：不把悬垂指针交给扩展。
    let 参数表 = if 实际 == 0 { core::ptr::null() } else { 参数.as_ptr() };

    let 起点 = Instant::now();
    // SAFETY: 参数表与返回槽由调用方按契约备好，个数已与声明核对过。
    unsafe { 执行(返回槽, 实际, 参数表) };
    let 耗时毫秒 = u64::try_from(起点.elapsed().as_millis()).unwrap_or(u64::MAX);

    // 执行已发生，此刻记账只留痕、拦不住什么——这正是它必须与 `准调` 分开的原因。
    账本.记账(命令号, 耗时毫秒);

    // 超时记账：越界即报段位。返回槽**不清空** —— 执行方可能已把所有权交出来，
    // 清空等于泄漏；调用方拿到失败就知道槽里的内容不可信。
    if 耗时毫秒 > 超时预算毫秒 {
        return 调用结果::失败(调度错误::超时 { 毫秒: 超时预算毫秒 });
    }

    调用结果::成功
}

/// 把返回槽置为空值：**未命中返回空**，不许把上一轮的内容留给调用方。
///
/// # Safety
/// `返回槽` 必须指向可写的 `数据槽`。
unsafe fn 置空返回槽(返回槽: *mut 数据槽) {
    // SAFETY: 由调用方保证 `返回槽` 可写。
    unsafe { 返回槽.write(数据槽::空槽()) };
}

