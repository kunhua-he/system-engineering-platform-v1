//! 错误与结果：调度路径上的两个公开枚举。
//!
//! **未命中不是崩溃**——它是明确段位，调用方按段位编程处置。
//!
//! 两个带号的变体装的是 `能力号`（不是裸 `u32`）：号空间互不相通，
//! 拿类型标签 / 资源号 / 错误码来顶替**编不过**。

use v1_contract::能力号;

/// 调度错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 调度错误 {
    /// 超时（口径唯一，来自本 crate 的常量）。
    超时 { 毫秒: u64 },
    /// 配额用尽。
    配额用尽,
    /// 被调用的扩展未载入 —— **这是明确的错误段位，不是崩溃**。
    提供者未载入 { 号: 能力号 },
    /// 命令已废止 —— 注册表里是**真项**，但状态位标了 `命令状态::错误`。
    ///
    /// 与 `提供者未载入` 分开报，是因为两种失败的可编程处置不同：
    /// 前者等提供者载入后重试即可，后者**永远不该再调**（编号只增不复用，但能力已作废）。
    命令已废止 { 号: 能力号 },
    /// 参数个数与声明不符。
    参数个数不符 { 声明: u32, 实际: u32 },
}

/// 调用结果。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 调用结果 {
    成功,
    失败(调度错误),
}
