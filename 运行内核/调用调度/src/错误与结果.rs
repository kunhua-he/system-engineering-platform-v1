//! 错误与结果：调度路径上的两个公开枚举。
//!
//! **未命中不是崩溃**——它是明确段位，调用方按段位编程处置。
//!
//! 两个带号的变体装的是 `能力号`（不是裸 `u32`）：号空间互不相通，
//! 拿类型标签 / 资源号 / 错误码来顶替**编不过**。

use v1_contract::能力号;

/// 调度错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 调度错误 {
    /// 超时（口径唯一，来自本 crate 的常量）。
    超时 { 毫秒数: u64 },
    /// 配额用尽。
    配额用尽,
    /// 被调用的扩展未载入 —— **这是明确的错误段位，不是崩溃**。
    提供者未载入 { 能力号: 能力号 },
    /// 命令已废止 —— 注册表里是**真项**，但状态位标了 `命令状态::错误`。
    ///
    /// 与 `提供者未载入` 分开报，是因为两种失败的可编程处置不同：
    /// 前者等提供者载入后重试即可，后者**永远不该再调**（编号只增不复用，但能力已作废）。
    命令已废止 { 能力号: 能力号 },
    /// 参数个数与声明不符。
    参数个数不符 { 声明: u32, 实际: u32 },
    /// 入参槽的**类型标签**与声明的参数表对应行不符（按契约行序逐位对）。
    ///
    /// 与 `参数个数不符` 分开报：个数对而类型错，是**值的形状**错，不是**槽的个数**错——
    /// 两者处置不同（一个改传几个槽，一个改槽里放什么）。这是「执行前按契约行序校验类型标签」
    /// 的落点（类型标签是跨边界放值的唯一锚点：位置错位或类型不符，当场可判）。
    输入形状不符 { 位次: u32, 声明类型: u32, 实际类型: u32 },
    /// 扩展的执行函数 panic，被调度层接住。
    ///
    /// 与 `超时` 分开：超时是执行方**没在预算内答**（可能还在跑），本段位是它**崩了**。
    /// 与 `提供者未载入` 分开：那是没进扩展，本段位是**已经进去**了。
    ///
    /// 报本段位说明调用方的处置与前面几种不同：这次调用**可能已经改了扩展内部状态**，
    /// 不能当「没发生过」直接重试（错误码 `0035` 的可重试位为真，但需人工确认，见那份登记）。
    扩展执行崩溃,
}

/// 调用结果。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 调用结果 {
    成功,
    失败(调度错误),
}
