//! `协作取消表` 的单元测试：**请求取消 ≠ 已终止 ≠ 已补偿**。
//!
//! 本件的要害是**反向样本**：把 `请求取消` 写成「直接打成已终止」（旧缺口里
//! 「取消自动等价于已终止」那种做法）⇒ `请求取消不自动等价于已终止` 当场红。
//! 只跑绿不算验收 —— 这条样本就是本原语的身份证。

use super::*;

/// 凭据来源：一个**真登记过**的句柄（不是编一个常数冒充凭据）。
fn 已登记句柄(取消表: &协作取消表, 句柄: u64) -> u64 {
    取消表.登记句柄(句柄);
    assert_eq!(取消表.取阶段(句柄), Some(取消阶段::未请求), "新登记的凭据从未请求起");
    句柄
}

/// **身份证（反向样本所在）**：请求取消只把阶段推到 `已请求未终止` ——
/// 它**不**自动等价于 `已终止`，更不等于 `已补偿`。
#[test]
fn 请求取消不自动等价于已终止() {
    let 取消表 = 协作取消表::构造();
    let 句柄 = 已登记句柄(&取消表, 0x5441_534B_0000_0001);

    assert_eq!(取消表.请求取消(句柄), 取消回执::已受理);
    assert_eq!(
        取消表.取阶段(句柄),
        Some(取消阶段::已请求未终止),
        "请求取消后必须停在「已请求未终止」—— 请求收到了不等于任务已停"
    );
    assert!(!取消表.是否已终止(句柄), "已请求未终止 不许被读成已终止");
    assert!(!取消表.是否已补偿(句柄), "已请求未终止 不许被读成已补偿");
}

/// 四档逐档可读：请求 → 报已终止 → 报已补偿，回读逐档对上。
#[test]
fn 取消后状态回读_四档逐档可读() {
    let 取消表 = 协作取消表::构造();
    let 句柄 = 已登记句柄(&取消表, 0x5441_534B_0000_0002);

    assert_eq!(取消表.取阶段(句柄), Some(取消阶段::未请求));
    assert_eq!(取消表.请求取消(句柄), 取消回执::已受理);
    assert_eq!(取消表.取阶段(句柄), Some(取消阶段::已请求未终止));
    assert_eq!(取消表.报阶段(句柄, 取消阶段::已终止), 取消回执::已受理);
    assert_eq!(取消表.取阶段(句柄), Some(取消阶段::已终止));
    assert!(取消表.是否已终止(句柄));
    assert!(!取消表.是否已补偿(句柄));
    assert_eq!(取消表.报阶段(句柄, 取消阶段::已补偿), 取消回执::已受理);
    assert_eq!(取消表.取阶段(句柄), Some(取消阶段::已补偿));
    assert!(取消表.是否已补偿(句柄));
}

/// 阶段倒退即拒：已补偿之后报已终止 ⇒ `阶段不符`，**且阶段一动不动**。
#[test]
fn 阶段倒退即拒_回执阶段不符且阶段不动() {
    let 取消表 = 协作取消表::构造();
    let 句柄 = 已登记句柄(&取消表, 0x5441_534B_0000_0003);
    assert_eq!(取消表.请求取消(句柄), 取消回执::已受理);
    assert_eq!(取消表.报阶段(句柄, 取消阶段::已补偿), 取消回执::已受理);

    assert_eq!(
        取消表.报阶段(句柄, 取消阶段::已终止),
        取消回执::阶段不符 { 已记: 取消阶段::已补偿, 要报: 取消阶段::已终止 },
        "倒退必须回结构化「阶段不符」"
    );
    assert_eq!(取消表.取阶段(句柄), Some(取消阶段::已补偿), "拒收后阶段一动不动");
    // 往 `未请求` 报同属倒退。
    assert_eq!(
        取消表.报阶段(句柄, 取消阶段::未请求),
        取消回执::阶段不符 { 已记: 取消阶段::已补偿, 要报: 取消阶段::未请求 }
    );
    assert_eq!(取消表.取阶段(句柄), Some(取消阶段::已补偿));
}

/// 同档重复即拒（幂等）：已请求未终止之后再请求 ⇒ `重复请求`，阶段不动。
#[test]
fn 重复请求幂等_回执重复请求() {
    let 取消表 = 协作取消表::构造();
    let 句柄 = 已登记句柄(&取消表, 0x5441_534B_0000_0004);
    assert_eq!(取消表.请求取消(句柄), 取消回执::已受理);
    assert_eq!(取消表.请求取消(句柄), 取消回执::重复请求);
    assert_eq!(取消表.取阶段(句柄), Some(取消阶段::已请求未终止), "重复请求不改阶段");
    // 已终止之后再请求同属重复（不许被打回已请求未终止）。
    assert_eq!(取消表.报阶段(句柄, 取消阶段::已终止), 取消回执::已受理);
    assert_eq!(取消表.请求取消(句柄), 取消回执::重复请求);
    assert_eq!(取消表.取阶段(句柄), Some(取消阶段::已终止));
}

/// 未登记句柄回结构化回执：**不是 panic、不是空**（与「未命中不是错误」同条）。
#[test]
fn 未登记句柄回结构化回执不是崩溃() {
    let 取消表 = 协作取消表::构造();
    assert_eq!(取消表.取阶段(0x5441_534B_0000_00FF), None);
    assert_eq!(取消表.请求取消(0x5441_534B_0000_00FF), 取消回执::未登记);
    assert_eq!(
        取消表.报阶段(0x5441_534B_0000_00FF, 取消阶段::已终止),
        取消回执::未登记
    );
    assert!(!取消表.是否已终止(0x5441_534B_0000_00FF));
    assert!(!取消表.是否已补偿(0x5441_534B_0000_00FF));
}

/// 多实例隔离：两表互不可见（表落进程级时这条必挂）。
#[test]
fn 两份表互不可见() {
    let 首表 = 协作取消表::构造();
    let 次表 = 协作取消表::构造();
    首表.登记句柄(7);
    次表.登记句柄(9);
    assert_eq!(首表.取阶段(9), None, "次表的凭据不许出现在首表里");
    assert_eq!(次表.取阶段(7), None, "首表的凭据不许出现在次表里");
    assert_eq!(首表.取阶段(7), Some(取消阶段::未请求));
}
