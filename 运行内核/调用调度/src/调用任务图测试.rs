//! 调用任务图与任务调度器的单元测试 —— 从入口 `lib.rs` 的 `mod 调用任务图测试` 原样搬出。
//!
//! 只搬不改：四条用例（菱形依赖就绪 · 坏图拒绝 · 完成事件按批号幂等 · 资源车道同键先进先出）
//! 的断言逐字照旧。`use super::*;` 仍从 crate 根取公开面，故不需要在入口里留任何实现。
//!
//! 为什么要搬：判据 ⑲ 的入口硬数是「入口 ≤160 行 · 入口零实现」—— 入口是路由，测试是实现。

use super::*;

#[test]
fn 菱形依赖就绪() {
    let 任务图 = 调用任务图::构造图(vec![
        调用任务节点::构造("起点", Vec::<String>::new()),
        调用任务节点::构造("左支", ["起点"]),
        调用任务节点::构造("右支", ["起点"]),
        调用任务节点::构造("汇合", ["左支", "右支"]),
    ])
    .expect("菱形图应可构造");
    let mut 调度器 = 调用任务调度器::构造(任务图);
    let 启动 = 调度器
        .启动节点("起点", Vec::<String>::new())
        .expect("起点应可启动")
        .expect("应产生启动决策");
    let 启动批号 = match 启动 {
        调度决策::启动 { 执行批号, .. } => 执行批号,
        _ => 0,
    };
    调度器
        .处理完成(节点完成事件 {
            节点标识: "起点".into(),
            执行批号: 启动批号,
            成功: true,
        })
        .expect("完成事件应可处理");
    assert_eq!(调度器.节点阶段("左支"), Some(调用节点阶段::就绪));
    assert_eq!(调度器.节点阶段("右支"), Some(调用节点阶段::就绪));
    assert_eq!(调度器.节点阶段("汇合"), Some(调用节点阶段::等待依赖));
}

#[test]
fn 坏图拒绝() {
    let 环形任务图 = 调用任务图::构造图(vec![
        调用任务节点::构造("起点", ["终点"]),
        调用任务节点::构造("终点", ["起点"]),
    ]);
    assert_eq!(环形任务图, Err(图校验错误::有环));
    let 重复依赖 = 调用任务图::构造图(vec![
        调用任务节点::构造("节点", Vec::<String>::new()),
        调用任务节点::构造("后继", ["节点", "节点"]),
    ]);
    assert_eq!(
        重复依赖,
        Err(图校验错误::重复依赖("后继".into(), "节点".into()))
    );
}

#[test]
fn 完成事件按批号幂等() {
    let 任务图 = 调用任务图::构造图(vec![调用任务节点::构造(
        "节点",
        Vec::<String>::new(),
    )])
    .unwrap();
    let mut 调度器 = 调用任务调度器::构造(任务图);
    let 启动 = 调度器
        .启动节点("节点", Vec::<String>::new())
        .unwrap()
        .unwrap();
    let 执行批号 = match 启动 {
        调度决策::启动 { 执行批号, .. } => 执行批号,
        _ => unreachable!(),
    };
    let 事件 = 节点完成事件 {
        节点标识: "节点".into(),
        执行批号,
        成功: true,
    };
    assert!(!调度器.处理完成(事件.clone()).unwrap().is_empty());
    assert!(调度器.处理完成(事件).unwrap().is_empty());
    assert_eq!(调度器.节点阶段("节点"), Some(调用节点阶段::成功));
}

#[test]
fn 资源车道同键先进先出() {
    let mut 资源车道实例 = 调用资源车道::构造();
    let 首份 = 资源车道实例.尝试预留("首份", ["模型服务"]);
    assert!(首份.is_some());
    assert!(资源车道实例.尝试预留("后份", ["模型服务"]).is_none());
    let 租约 = 首份.unwrap();
    assert_eq!(
        资源车道实例
            .等待节点("模型服务")
            .unwrap()
            .front()
            .map(String::as_str),
        Some("后份")
    );
    assert!(资源车道实例.释放(&租约));
    assert!(资源车道实例.尝试预留("后份", ["模型服务"]).is_some());
}
