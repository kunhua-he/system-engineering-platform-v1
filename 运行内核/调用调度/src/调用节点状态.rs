//! 节点 / 任务阶段 —— **协议派生件，不手抄**。
//!
//! 阶段名与码的唯一来源是 `契约声明/调用任务协议.json`，派生件是
//! `v1_contract::调用任务数据`（生成器 `构建装配/形态装配/生成声明.py` 产出）。
//! 本件只做两件事：
//!
//! 1. **再导出**那两个枚举（调用方按原路径 `调用节点状态::调用节点阶段` 取到同一份类型）；
//! 2. 给出**转换错误类型与转换入口** —— 合法跃迁表也在派生件里，本件不写第二份规则。
//!
//! # 为什么不在这里写 `matches!`
//!
//! 先前这一件自带一份跃迁 `matches!`，与协议描述就成了两套规则：改 JSON 不改 Rust、
//! 或改 Rust 不改 JSON，两边都各有一次「看着对」的假绿 —— 而没有任何闸能同时看见两边。
//! 现在规则只有一个实现（`v1_contract::可转换` 查表），本件只包一层错误类型。

use std::fmt;

pub use v1_contract::声明数据::{调用任务阶段, 调用节点阶段};

/// 非法跃迁：当前阶段 + 想去的阶段（两样都带上，报错才定位得到是哪个节点卡在哪一步）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 状态转换错误 {
    pub 当前阶段: 调用节点阶段,
    pub 目标: 调用节点阶段,
}

impl fmt::Display for 状态转换错误 {
    fn fmt(&self, 格式输出: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(格式输出, "节点状态不可转换")
    }
}

impl std::error::Error for 状态转换错误 {}

/// 这一跃迁合不合法（**唯一实现**：查协议派生出来的跃迁表）。
pub fn 可转换(从: 调用节点阶段, 到: 调用节点阶段) -> bool {
    v1_contract::声明数据::可转换(从, 到)
}

/// 走一次状态转换；不合法即结构化失败，不改任何状态。
///
/// 返回**目标阶段**而不是「()」：调用方拿到的就是新状态，不必再赋值一遍
/// （再赋值 = 状态有两个写入点）。
pub fn 转换(
    从: 调用节点阶段,
    到: 调用节点阶段,
) -> Result<调用节点阶段, 状态转换错误> {
    if 可转换(从, 到) {
        Ok(到)
    } else {
        Err(状态转换错误 {
            当前阶段: 从,
            目标: 到,
        })
    }
}
