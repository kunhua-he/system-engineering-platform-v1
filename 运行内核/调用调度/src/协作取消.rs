//! 协作取消 —— 取消是**协作请求**，不是「已终止」的同义词。
//!
//! 本件的落点（缺口出自架构收敛方案项 C07）：底座侧原先**没有**取消通道，也**没有**取消后状态回读 ⇒
//! 「取消」只能被当成「已终止」的同一件事。本件把两件事分开：
//!
//! ```text
//! 请求取消（协作请求） → 已请求未终止 → 已终止（执行侧报了） → 已补偿（执行侧报了）
//! ```
//!
//! **请求取消 ≠ 已终止 ≠ 已补偿**：三档是三个不同的状态，回读得到哪一个就是哪一个，
//! 不许把「请求收到了」读成「已经停了」。这条区分就是本原语的**身份证**：
//! 拿掉它，`请求取消不自动等价于已终止` 当场红。
//!
//! # 状态住在哪
//!
//! **本表记的是「这次协作取消谈到了哪一档」**，不是任务本体 —— 任务本体与它的收尾方式
//! 在扩展侧（`项目文档/决策记录/2026-09-27_边界表达力_长活原语.md` §三：取消是扩展侧的事，
//! 它自身知道怎么收尾）。内核仍然**不持长活任务状态**：本表按**实例**持有（调用方新建、调用方持有，
//! 不落任何 `static`），与 [`配额账本`](crate::配额账本) 同一条纪律
//! （宪法三条补缺陷之一「状态显式持有为句柄，不落进程级全局」）。
//!
//! # 四档只许前进
//!
//! `未请求 → 已请求未终止 → 已终止 → 已补偿`：**只许往更高档走**。
//! 倒退（已补偿之后再报已终止）⇒ `阶段不符`，**且阶段一动不动**（坏读数不许覆盖好读数）；
//! 同档重复（已请求未终止之后再请求取消）⇒ `重复请求`，也是幂等：阶段不动。
//!
//! 全是**结构化回执**，没有一处 panic：表里没有这个句柄 ⇒ `未登记`，不是崩溃、不是空。

use std::collections::BTreeMap;
use std::sync::Mutex;

/// 取消阶段：协作取消的四档。**只许前进，不许倒退**。
///
/// 三档的语义边界（本件存在的理由）：
/// - [`取消阶段::未请求`]：从没被请求过取消；
/// - [`取消阶段::已请求未终止`]：请求**收到了**，任务**还在收尾** —— 它不等于已终止；
/// - [`取消阶段::已终止`]：执行侧报了「已停」；
/// - [`取消阶段::已补偿`]：执行侧报了「已回滚 / 已补偿」。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum 取消阶段 {
    未请求,
    已请求未终止,
    已终止,
    已补偿,
}

/// 取消回执：`请求取消` / `报阶段` 的结局。**全是结构化值，不是 panic**。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 取消回执 {
    /// 请求收到了 / 阶段前进了一档。
    已受理,
    /// 同档重复请求：**幂等**，阶段不动。
    重复请求,
    /// 倒退（或往 `未请求` 报）：拒收，**阶段不动**。
    阶段不符 { 已记: 取消阶段, 要报: 取消阶段 },
    /// 表里没有这个句柄 —— 与「未命中不是错误」同一条（宪法第 6 条）。
    未登记,
}

/// 协作取消表：句柄 → 取消阶段。
///
/// **按实例持有**（调用方新建、调用方持有），不落任何 `static` —— 两份表天然互不可见，
/// 同进程开两份就是两个互不干扰的取消域（与 [`配额账本`](crate::配额账本) 同一条纪律）。
pub struct 协作取消表 {
    阶段表: Mutex<BTreeMap<u64, 取消阶段>>,
}

impl 协作取消表 {
    /// 新建一张表。空表 = 没有任何凭据。
    pub fn 构造() -> Self {
        Self { 阶段表: Mutex::new(BTreeMap::new()) }
    }

    /// 登记一个句柄：阶段从 [`取消阶段::未请求`] 起。
    ///
    /// 重复登记**幂等**且**不倒退**：已在该句柄上的阶段原样保留（重复登记不许把一条
    /// 已终止的凭据打回未请求）。
    pub fn 登记句柄(&self, 句柄: u64) {
        let mut 项表 = self.阶段表.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        项表.entry(句柄).or_insert(取消阶段::未请求);
    }

    /// **请求取消**：把 `未请求` 推成 `已请求未终止`。
    ///
    /// 这是**协作请求**那一条腿：请求成功只说明「请求收到了」，**不说明任务已停** ——
    /// 要停不停得看执行侧报的 `已终止` / `已补偿`（用 [`协作取消表::取阶段`] 回读）。
    /// 已经在 `已请求未终止` 及之后 ⇒ `重复请求`（幂等，阶段不动）。
    pub fn 请求取消(&self, 句柄: u64) -> 取消回执 {
        let mut 项表 = self.阶段表.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        let Some(已记阶段) = 项表.get_mut(&句柄) else {
            return 取消回执::未登记;
        };
        match *已记阶段 {
            取消阶段::未请求 => {
                *已记阶段 = 取消阶段::已请求未终止;
                取消回执::已受理
            }
            _ => 取消回执::重复请求,
        }
    }

    /// **报阶段**：执行侧报它收尾到哪一档（`已终止` / `已补偿`）。
    ///
    /// 只许**前进**：`要报` 必须严格高于已记阶段，否则 `阶段不符 { 已记, 要报 }` 且
    /// **阶段一动不动**（坏读数不许把好读数盖掉）。往 `未请求` 报同属倒退 —— 拒收。
    pub fn 报阶段(&self, 句柄: u64, 要报: 取消阶段) -> 取消回执 {
        let mut 项表 = self.阶段表.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        let Some(已记阶段) = 项表.get_mut(&句柄) else {
            return 取消回执::未登记;
        };
        if 要报 > *已记阶段 {
            *已记阶段 = 要报;
            return 取消回执::已受理;
        }
        取消回执::阶段不符 { 已记: *已记阶段, 要报 }
    }

    /// **取消后状态回读**：这个句柄现在在哪一档。
    ///
    /// `None` = 表里没有这条凭据（未登记不是错误）。**回读是只读的** —— 它不改阶段。
    pub fn 取阶段(&self, 句柄: u64) -> Option<取消阶段> {
        let 项表 = self.阶段表.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        项表.get(&句柄).copied()
    }

    /// 是否已终止（**只有 `已终止` / `已补偿` 才算**；`已请求未终止` 不算）。
    pub fn 是否已终止(&self, 句柄: u64) -> bool {
        matches!(self.取阶段(句柄), Some(取消阶段::已终止 | 取消阶段::已补偿))
    }

    /// 是否已补偿（只有 `已补偿` 算）。
    pub fn 是否已补偿(&self, 句柄: u64) -> bool {
        matches!(self.取阶段(句柄), Some(取消阶段::已补偿))
    }
}

