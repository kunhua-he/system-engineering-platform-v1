/// **反向样本 1**：账本拒绝时，执行函数一次都不许被调到，且必须报 `配额用尽`。
#[test]
fn 账本拒绝_不许进执行函数() {
    let 调用前读数 = 拒绝命令被调次数.load(Ordering::SeqCst);
    // 先放脏值：被拒也必须置空。
    let mut 返回槽 = 数据槽::内联(v1_contract::类型标签::新建(测试标签), 123, 0);
    // SAFETY: 返回槽 是本栈上的可写槽；0 个入参。
    let 结果 = unsafe {
        调度调用(
            能力号::新建(1005),
            已载入(&命令表_测试.0[0], 拒绝命令),
            &拒绝账本,
            单项超时毫秒,
            &[],
            &mut 返回槽,
        )
    };
    assert_eq!(结果, 调用结果::失败(调度错误::配额用尽), "账本返回 false ⇒ 报配额用尽");
    assert_eq!(拒绝命令被调次数.load(Ordering::SeqCst), 调用前读数, "账本拒绝时执行函数被调次数必须为 0");
    assert!(返回槽.是否空(), "被拒也必须置空");
}

/// **反向样本 3**：已废止命令报 `命令已废止`，**不是** `提供者未载入`。
