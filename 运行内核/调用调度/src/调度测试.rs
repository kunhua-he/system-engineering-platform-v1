#[test]
fn 参数个数不符() {
    let 账本 = 配额账本::新建(配额上限, 配额窗口毫秒);
    // 先放脏值：失败必须把它盖成空值，不许留给调用方。
    let mut 返回槽 = 数据槽::内联(v1_contract::类型标签::新建(测试标签), 123, 0);
    let 一个入参 = [数据槽::内联(v1_contract::类型标签::新建(测试标签), 1, 0)];
    // SAFETY: 返回槽 是本栈上的可写槽；入参按契约填好。
    let 结果 = unsafe {
        调度调用(
            能力号::新建(1002),
            已载入(&命令表_测试.0[1], 两参命令),
            &账本,
            单项超时毫秒,
            &一个入参,
            &mut 返回槽,
        )
    };
    assert_eq!(结果, 调用结果::失败(调度错误::参数个数不符 { 声明: 2, 实际: 1 }));
    assert!(返回槽.是否空(), "失败必须置空，不许把脏值留给调用方");
    assert_eq!(两参命令被调次数.load(Ordering::SeqCst), 0, "校验不过不许进执行函数");
}

