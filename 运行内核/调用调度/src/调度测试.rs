/// **反向样本**：入参槽的类型标签与声明参数表对应行不符 ⇒ 结构化拒，且**不进执行函数**。
///
/// 声明两参（两行都是 `测试标签`）；传两个**类型不对**的槽（标签 2）⇒ 必须报
/// `输入形状不符 { 位次: 0, 声明类型: 测试标签, 实际类型: 2 }`，执行函数一次都不许被调到。
/// 不是「参数个数不符」（个数是对的）——两种失败分开报。
#[test]
fn 参数类型不符_结构化拒绝且不进执行函数() {
    let 账本 = 配额账本::构造(配额上限, 配额窗口毫秒);
    let 调用前读数 = 两参命令被调次数.load(Ordering::SeqCst);
    // 先放脏值：类型不符必须把它盖成空值，不许留给调用方。
    let mut 返回槽 = 数据槽::内联槽(v1_contract::类型标签::构造(测试标签), 123, 0);
    let 错类型入参 = [
        数据槽::内联槽(v1_contract::类型标签::构造(2), 1, 0),
        数据槽::内联槽(v1_contract::类型标签::构造(测试标签), 2, 0),
    ];
    // SAFETY: 返回槽 是本栈上的可写槽；入参个数与声明一致（2）。
    let 调用读数 = unsafe {
        调度调用(
            能力号::构造(1002),
            已载入(&命令表_测试.0[1], 两参命令),
            &账本,
            单项超时毫秒,
            &错类型入参,
            &mut 返回槽,
        )
    };
    assert_eq!(
        调用读数,
        调用结果::失败(调度错误::输入形状不符 { 位次: 0, 声明类型: 测试标签, 实际类型: 2 })
    );
    assert_ne!(
        调用读数,
        调用结果::失败(调度错误::参数个数不符 { 声明: 2, 实际: 2 }),
        "个数对而类型错 ⇒ 不许报「参数个数不符」"
    );
    assert!(返回槽.是否空(), "类型不符必须置空（执行尚未发生，清空安全）");
    assert_eq!(
        两参命令被调次数.load(Ordering::SeqCst),
        调用前读数,
        "类型不符时执行函数被调次数必须为 0"
    );
}

