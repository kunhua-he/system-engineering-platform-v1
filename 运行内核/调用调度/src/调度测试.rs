/// 端到端：真建表 · 走公开入口 `调用` · 未命中由占位项兜住 · 已废止走真项段位。
#[test]
fn 公开入口端到端() {
    let 注册表 = match 注册表::建表(&平台_测试.0) {
        Ok(项表) => 项表,
        Err(错误) => panic!("测试声明必须建得成表，却报：{错误:?}"),
    };
    let 账本 = 配额账本::新建(配额上限, 配额窗口毫秒);

    // 号 `测试命令首号`：真命令，走完整路径。
    let mut 返回槽 = 数据槽::空槽();
    // SAFETY: 返回槽 是本栈上的可写槽；0 个入参。
    let 结果 = unsafe { 调用(&注册表, &账本, 测试命令首号, &[], &mut 返回槽) };
    assert_eq!(结果, 调用结果::成功);
    assert_eq!(返回槽, 数据槽::内联(v1_contract::类型标签::新建(测试标签), 42, 0));

    // 号 `测试命令首号 + 2`：真项但已废止 —— 必须走「命令已废止」段位，不是「提供者未载入」。
    let mut 返回槽 = 数据槽::内联(v1_contract::类型标签::新建(测试标签), 123, 0);
    // SAFETY: 同上。
    let 结果 = unsafe { 调用(&注册表, &账本, 能力号::新建(测试命令首号.取号值() + 2), &[], &mut 返回槽) };
    assert_eq!(
        结果,
        调用结果::失败(调度错误::命令已废止 {
            能力号: 能力号::新建(测试命令首号.取号值() + 2)
        })
    );
    assert!(返回槽.是否空(), "已废止返回空");

    // 号 99：未命中 —— 注册表给占位项，这里必须变成明确段位 + 空返回，**不是崩溃**。
    let mut 返回槽 = 数据槽::内联(v1_contract::类型标签::新建(测试标签), 123, 0);
    // SAFETY: 同上。
    let 结果 = unsafe { 调用(&注册表, &账本, 能力号::新建(99), &[], &mut 返回槽) };
    assert_eq!(结果, 调用结果::失败(调度错误::提供者未载入 { 能力号: 能力号::新建(99) }));
    assert!(返回槽.是否空(), "未命中返回空（宪法第 6 条）");
}

/// **实测**：空调用一次的真实耗时量级 —— 三个常量的定数依据。
///
/// 想看读数：`cargo test -p v1-dispatch 实测_空调用耗时量级 -- --nocapture`。
#[test]
fn 实测_空调用耗时量级() {
    // 上限给到 u32::MAX：本用例只量耗时，不撞配额。
    let 账本 = 配额账本::新建(u32::MAX, 配额窗口毫秒);
    let 命令 = 已载入(&命令表_测试.0[0], 零参命令);
    let mut 返回槽 = 数据槽::空槽();

    const 次数: u32 = 200_000;
    let 起点 = Instant::now();
    for _ in 0..次数 {
        // SAFETY: 返回槽 是本栈上的可写槽；0 个入参。
        let 结果 = unsafe { 调度调用(能力号::新建(1), 命令, &账本, 单项超时毫秒, &[], &mut 返回槽) };
        assert_eq!(结果, 调用结果::成功);
    }
    let 总耗时 = 起点.elapsed();
    let 每次纳秒 = 总耗时.as_nanos() / u128::from(次数);

    eprintln!("实测：{次数} 次空调用共 {总耗时:?}，单次 ≈ {每次纳秒} ns ≈ {} µs", 每次纳秒 / 1_000);

    // 判据：调度自身开销必须远小于单项超时预算，否则超时口径本身不可解释。
    // 取 1 毫秒（= 10^6 ns）作硬上限，比实测留出 3 个数量级以上的余量。
    assert!(
        每次纳秒 < 1_000_000,
        "单次空调用开销 {每次纳秒} ns 已逼近 1 ms —— 超时口径不可解释"
    );
}
