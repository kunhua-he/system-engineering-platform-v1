//! 调用调度 —— 单项超时 · 资源配额 · 单项故障不扩散。
//!
//! **单项超时口径唯一**：不许每个能力各设一套，否则超时不可解释。
//! **单项故障不扩散**：一个扩展崩了，别的扩展照跑。
//!
//! 本 crate 是调用路径上**唯一**的判定点，顺序固定、不许换：
//!
//! ```text
//! 按号取命令 → 校验参数个数 → 记配额 → 执行 → 记账超时
//! ```
//!
//! 三条不许破的：
//!
//! 1. **未命中走占位项**：没载入的号由注册表给占位项，这里把它变成「提供者未载入」
//!    这个**明确段位**，并把返回槽置空（宪法第 6 条「未命中返回空」）——**不是崩溃**。
//! 2. **超时与配额只有一份口径**：两个数都是本 crate 的常量，能力不许自设、调用方不许另传。
//! 3. **调度自身不 panic**：所有失败路径都是 `Result` / 枚举；锁中毒、长度超出表达范围
//!    都有明确处理，不靠 `unwrap` 崩。
//!
//! **超时是怎么判的**：执行函数是同步的 `extern "C"`，**进程内无法被抢占**，所以这里判的是
//! 「这一项有没有越界」——越界即报 `超时` 段位，让失败可编程判定（宪法「坏了看得见」）。
//! 真正强杀要跨进程（`现代架构落点.md` 形态 2 的进程级超时），不在本节点能力范围内。

use std::collections::BTreeMap;
use std::sync::{Mutex, OnceLock};
use std::time::Instant;

pub use v1_contract::数据槽;
pub use v1_registry::注册表;
use v1_registry::命令槽;

/// 单项超时（毫秒）—— **全平台唯一口径**。
///
/// 超时是调度层的事（`现代架构落点.md`「给每个能力单独设超时口径」列为明确不做）：
/// 能力不许自设，调用方也不许各传一套。
pub const 单项超时毫秒: u64 = 30_000;

/// 配额窗口（毫秒）。
pub const 配额窗口毫秒: u64 = 1_000;

/// 一个能力号在**一个窗口**内的调用上限。
///
/// 按号记账而不是全局记账：一个能力疯跑不许把别的能力饿死。
pub const 配额上限: u32 = 10_000;

/// 调度错误。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 调度错误 {
    /// 超时（口径唯一，来自本 crate 的常量）。
    超时 { 毫秒: u64 },
    /// 配额用尽。
    配额用尽,
    /// 被调用的扩展未载入 —— **这是明确的错误段位，不是崩溃**。
    提供者未载入 { 号: u32 },
    /// 参数个数与声明不符。
    参数个数不符 { 声明: u32, 实际: u32 },
}

/// 调用结果。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 调用结果 {
    成功,
    失败(调度错误),
}

/// 一个号在一个窗口里的用量。
#[derive(Clone, Copy)]
struct 窗口用量 {
    窗口起点毫秒: u64,
    已用: u32,
}

/// 配额账本：按能力号记账的滚动窗口计数器。
///
/// 时间源用 `Instant`（单调）而不是墙钟：墙钟回拨不许把配额算错。
pub(crate) struct 配额账本 {
    上限: u32,
    窗口毫秒: u64,
    起点: Instant,
    记录: Mutex<BTreeMap<u32, 窗口用量>>,
}

impl 配额账本 {
    pub(crate) fn 新建(上限: u32, 窗口毫秒: u64) -> Self {
        Self {
            上限,
            窗口毫秒,
            起点: Instant::now(),
            记录: Mutex::new(BTreeMap::new()),
        }
    }

    /// 取用一次配额。超限返回 `配额用尽`，**不是 panic**。
    pub(crate) fn 取用(&self, 号: u32) -> Result<(), 调度错误> {
        let 现在 = self.现在毫秒();
        // 锁中毒不许崩：中毒只说明别人 panic 过，账本本身照样能记账。
        let mut 记录 = self.记录.lock().unwrap_or_else(|中毒| 中毒.into_inner());
        let 项 = 记录.entry(号).or_insert(窗口用量 { 窗口起点毫秒: 现在, 已用: 0 });
        if 现在.saturating_sub(项.窗口起点毫秒) >= self.窗口毫秒 {
            *项 = 窗口用量 { 窗口起点毫秒: 现在, 已用: 0 };
        }
        if 项.已用 >= self.上限 {
            return Err(调度错误::配额用尽);
        }
        项.已用 += 1;
        Ok(())
    }

    fn 现在毫秒(&self) -> u64 {
        u64::try_from(self.起点.elapsed().as_millis()).unwrap_or(u64::MAX)
    }
}

/// 进程级默认账本。
///
/// `调用` 的公开签名里没有账本参数（签名冻结，见 `内核落点.md` 第五节），
/// 所以唯一口径的账本只能在本 crate 里挂一份 —— 这正是 `现代架构落点.md`
/// 给本节点写的「进程级超时与配额」。
static 进程账本: OnceLock<配额账本> = OnceLock::new();

fn 默认账本() -> &'static 配额账本 {
    进程账本.get_or_init(|| 配额账本::新建(配额上限, 配额窗口毫秒))
}

/// 调用：按号取命令 → 校验参数 → 加超时与配额 → 执行。
///
/// # Safety
/// `返回槽` 必须指向可写的 `数据槽`；`参数` 的每个槽都必须已按契约填好。
pub unsafe fn 调用(
    注册表: &注册表,
    号: u32,
    参数: &[数据槽],
    返回槽: *mut 数据槽,
) -> 调用结果 {
    // 未命中由注册表给占位项（宪法第 6 条），这里只负责把占位变成明确段位。
    let 槽 = 注册表.按号取命令(号);
    // SAFETY: 本函数的 `# Safety` 就是本调用的前提，原样传给调度核心。
    unsafe { 调度(号, 槽, 默认账本(), 单项超时毫秒, 参数, 返回槽) }
}

/// 调度核心：已取到的命令槽 → 校参数 → 记配额 → 执行 → 记账超时。
///
/// 与 `调用` 分开只为可测：公开签名里没有命令槽、账本、超时预算三个参数（签名冻结），
/// 判定逻辑本身只有这一份，不存在第二条腿。
///
/// # Safety
/// `返回槽` 必须指向可写的 `数据槽`；`参数` 的每个槽都必须已按契约填好。
unsafe fn 调度(
    号: u32,
    槽: 命令槽<'_>,
    账本: &配额账本,
    超时预算毫秒: u64,
    参数: &[数据槽],
    返回槽: *mut 数据槽,
) -> 调用结果 {
    let (声明, 执行) = match 槽 {
        命令槽::已载入 { 声明, 执行 } => (声明, 执行),
        // 占位项：提供者没载入。**明确段位，不是崩溃**；返回槽置空（未命中返回空）。
        命令槽::占位 { 号 } => {
            // SAFETY: 由调用方保证 `返回槽` 可写。
            unsafe { 置空(返回槽) };
            return 调用结果::失败(调度错误::提供者未载入 { 号 });
        }
    };

    // 参数个数：**行序即契约**，个数不符不许"尽力而为"。
    // 长度超出 u32 表达范围时按 u32::MAX 报，不截断成一个可能刚好相等的数。
    let 实际 = u32::try_from(参数.len()).unwrap_or(u32::MAX);
    if 实际 != 声明.参数个数 {
        // SAFETY: 由调用方保证 `返回槽` 可写。
        unsafe { 置空(返回槽) };
        return 调用结果::失败(调度错误::参数个数不符 { 声明: 声明.参数个数, 实际 });
    }

    // 配额在**执行前**记：超限的调用不许进扩展。
    if let Err(错误) = 账本.取用(号) {
        // SAFETY: 由调用方保证 `返回槽` 可写。
        unsafe { 置空(返回槽) };
        return 调用结果::失败(错误);
    }

    // 0 个参数给空指针：不把悬垂指针交给扩展。
    let 参数表 = if 实际 == 0 { core::ptr::null() } else { 参数.as_ptr() };

    let 起点 = Instant::now();
    // SAFETY: 参数表与返回槽由调用方按契约备好，个数已与声明核对过。
    unsafe { 执行(返回槽, 实际, 参数表) };
    let 耗时毫秒 = u64::try_from(起点.elapsed().as_millis()).unwrap_or(u64::MAX);

    // 超时记账：越界即报段位。返回槽**不清空** —— 执行方可能已把所有权交出来，
    // 清空等于泄漏；调用方拿到失败就知道槽里的内容不可信。
    if 耗时毫秒 > 超时预算毫秒 {
        return 调用结果::失败(调度错误::超时 { 毫秒: 超时预算毫秒 });
    }

    调用结果::成功
}

/// 把返回槽置为空值：**未命中返回空**，不许把上一轮的内容留给调用方。
///
/// # Safety
/// `返回槽` 必须指向可写的 `数据槽`。
unsafe fn 置空(返回槽: *mut 数据槽) {
    // SAFETY: 由调用方保证 `返回槽` 可写。
    unsafe { 返回槽.write(数据槽::空槽()) };
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering};
    use v1_contract::{参数信息, 命令信息, 执行函数};

    /// 类型标签：测试自用，只为能断言"返回槽确实被写过"。
    const 测试标签: u32 = 1;

    /// 静态声明包装。
    ///
    /// 契约类型里带裸指针（`*const u8` 等），裸指针不实现 `Sync`，而 `static` 必须 `Sync`。
    /// 表在编译期冻结且只读，别处拿到的也只会是共享引用，故安全。
    /// **真实扩展的静态声明必须做同一件事**，这里顺手把这条路走通。
    struct 静态<T>(T);
    // SAFETY: 表只读、无内部可变性，跨线程共享不产生数据竞争。
    unsafe impl Sync for 静态<命令信息> {}
    // SAFETY: 同上。
    unsafe impl Sync for 静态<[参数信息; 2]> {}

    static 零参次数: AtomicUsize = AtomicUsize::new(0);
    static 两参次数: AtomicUsize = AtomicUsize::new(0);
    static 配额次数: AtomicUsize = AtomicUsize::new(0);

    /// 零参命令：把 42 写进返回槽。
    unsafe extern "C" fn 零参命令(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
        零参次数.fetch_add(1, Ordering::SeqCst);
        let _ = (参数个数, 参数表);
        // SAFETY: 调度核心保证 `返回槽` 可写。
        unsafe { 返回槽.write(数据槽::内联(测试标签, 42, 0)) };
    }

    /// 两参命令：参数个数不符时**不该被调到**。
    unsafe extern "C" fn 两参命令(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
        两参次数.fetch_add(1, Ordering::SeqCst);
        let _ = (参数个数, 参数表);
        // SAFETY: 调度核心保证 `返回槽` 可写。
        unsafe { 返回槽.write(数据槽::内联(测试标签, 7, 0)) };
    }

    /// 配额命令：0 参，配额用尽时**不该被调到**。
    unsafe extern "C" fn 配额命令(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
        配额次数.fetch_add(1, Ordering::SeqCst);
        let _ = (参数个数, 参数表);
        // SAFETY: 调度核心保证 `返回槽` 可写。
        unsafe { 返回槽.write(数据槽::内联(测试标签, 7, 0)) };
    }

    /// 慢命令：睡过 1 毫秒，用来验超时段位。
    unsafe extern "C" fn 慢命令(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
        std::thread::sleep(std::time::Duration::from_millis(2));
        let _ = (参数个数, 参数表);
        // SAFETY: 调度核心保证 `返回槽` 可写。
        unsafe { 返回槽.write(数据槽::内联(测试标签, 9, 0)) };
    }

    /// 一条最小命令的声明：0 个参数。
    static 零参声明: 静态<命令信息> = 静态(命令信息 {
        名称: c"零参".as_ptr().cast::<u8>(),
        说明: c"测试用最小命令".as_ptr().cast::<u8>(),
        类别: 0,
        状态位: 0,
        返回类型: 测试标签,
        用户级别: 0,
        参数个数: 0,
        参数表: core::ptr::null(),
    });

    /// 两参命令的参数表（**行序即契约**，测试里只为占位）。
    static 两参参数表: 静态<[参数信息; 2]> = 静态([
        参数信息 {
            名称: c"甲".as_ptr().cast::<u8>(),
            说明: c"第一个入参".as_ptr().cast::<u8>(),
            类型标签: 测试标签,
            状态位: 0,
            默认值: 数据槽::空槽(),
        },
        参数信息 {
            名称: c"乙".as_ptr().cast::<u8>(),
            说明: c"第二个入参".as_ptr().cast::<u8>(),
            类型标签: 测试标签,
            状态位: 0,
            默认值: 数据槽::空槽(),
        },
    ]);

    static 两参声明: 静态<命令信息> = 静态(命令信息 {
        名称: c"两参".as_ptr().cast::<u8>(),
        说明: c"需要两个入参的命令".as_ptr().cast::<u8>(),
        类别: 0,
        状态位: 0,
        返回类型: 测试标签,
        用户级别: 0,
        参数个数: 2,
        参数表: 两参参数表.0.as_ptr(),
    });

    fn 已载入(声明: &'static 命令信息, 执行: 执行函数) -> 命令槽<'static> {
        命令槽::已载入 { 声明, 执行 }
    }

    #[test]
    fn 正常调用() {
        let 账本 = 配额账本::新建(配额上限, 配额窗口毫秒);
        let mut 返回槽 = 数据槽::空槽();
        // SAFETY: 返回槽 是本栈上的可写槽；0 个入参。
        let 结果 = unsafe {
            调度(1001, 已载入(&零参声明.0, 零参命令), &账本, 单项超时毫秒, &[], &mut 返回槽)
        };
        assert_eq!(结果, 调用结果::成功);
        assert_eq!(返回槽, 数据槽::内联(测试标签, 42, 0), "结果必须写进返回槽");
        assert_eq!(零参次数.load(Ordering::SeqCst), 1, "执行函数必须被调到一次");
    }

    #[test]
    fn 参数个数不符() {
        let 账本 = 配额账本::新建(配额上限, 配额窗口毫秒);
        // 先放脏值：失败必须把它盖成空值，不许留给调用方。
        let mut 返回槽 = 数据槽::内联(测试标签, 123, 0);
        let 一个入参 = [数据槽::内联(测试标签, 1, 0)];
        // SAFETY: 返回槽 是本栈上的可写槽；入参按契约填好。
        let 结果 = unsafe {
            调度(1002, 已载入(&两参声明.0, 两参命令), &账本, 单项超时毫秒, &一个入参, &mut 返回槽)
        };
        assert_eq!(结果, 调用结果::失败(调度错误::参数个数不符 { 声明: 2, 实际: 1 }));
        assert!(返回槽.是否空(), "失败必须置空，不许把脏值留给调用方");
        assert_eq!(两参次数.load(Ordering::SeqCst), 0, "校验不过不许进执行函数");
    }

    #[test]
    fn 未命中号() {
        let 账本 = 配额账本::新建(配额上限, 配额窗口毫秒);
        let mut 返回槽 = 数据槽::内联(测试标签, 123, 0);
        // SAFETY: 返回槽 是本栈上的可写槽；未命中不会碰入参。
        let 结果 = unsafe {
            调度(1777, 命令槽::占位 { 号: 1777 }, &账本, 单项超时毫秒, &[], &mut 返回槽)
        };
        assert_eq!(结果, 调用结果::失败(调度错误::提供者未载入 { 号: 1777 }));
        assert!(返回槽.是否空(), "未命中返回空（宪法第 6 条）");
    }

    #[test]
    fn 配额用尽() {
        // 窗口给到 60 秒：本用例只验配额，不验窗口滚动。
        let 账本 = 配额账本::新建(2, 60_000);
        let 命令 = 已载入(&零参声明.0, 配额命令);
        let mut 返回槽 = 数据槽::空槽();
        for _ in 0..2 {
            // SAFETY: 返回槽 是本栈上的可写槽；0 个入参。
            let 结果 = unsafe { 调度(1003, 命令, &账本, 单项超时毫秒, &[], &mut 返回槽) };
            assert_eq!(结果, 调用结果::成功);
        }
        // SAFETY: 同上。
        let 结果 = unsafe { 调度(1003, 命令, &账本, 单项超时毫秒, &[], &mut 返回槽) };
        assert_eq!(结果, 调用结果::失败(调度错误::配额用尽));
        assert_eq!(配额次数.load(Ordering::SeqCst), 2, "配额用尽不许进执行函数");
    }

    #[test]
    fn 超时记账() {
        let 账本 = 配额账本::新建(配额上限, 配额窗口毫秒);
        let mut 返回槽 = 数据槽::空槽();
        // 预算 1 毫秒，慢命令睡 2 毫秒 —— 必然越界。
        // SAFETY: 返回槽 是本栈上的可写槽；0 个入参。
        let 结果 = unsafe {
            调度(1004, 已载入(&零参声明.0, 慢命令), &账本, 1, &[], &mut 返回槽)
        };
        assert_eq!(结果, 调用结果::失败(调度错误::超时 { 毫秒: 1 }));
    }
}
