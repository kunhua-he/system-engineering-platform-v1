//! 调用调度 —— 单项超时 · 资源配额 · 单项故障不扩散。
//!
//! **单项超时口径唯一**：不许每个能力各设一套，否则超时不可解释。
//! **单项故障不扩散**：一个扩展崩了，别的扩展照跑。
//!
//! 本 crate 是调用路径上**唯一**的判定点，顺序固定、不许换：
//!
//! ```text
//! 按号取命令 → 判「未载入 / 保留项 / 已废止」 → 校验参数个数 → 问配额 → 执行 → 记账耗时
//! ```
//!
//! 四条不许破的：
//!
//! 1. **未命中走占位项**：没载入的号由注册表给占位项，这里把它变成「提供者未载入」
//!    这个**明确段位**，并把返回槽置空（宪法第 6 条「未命中返回空」）——**不是崩溃**。
//! 2. **「不可用」要分两种**：注册表给的是**真项**但状态位标了 `命令状态::错误` 时，
//!    带 `已废止` 位 ⇒ 报 `命令已废止`（永久没了，改用别的号）；不带 ⇒ 报
//!    `提供者未载入`（保留项，实现还没来，等它回来）。两者处置相反，不许合成一个段位。
//! 3. **超时口径只有一份**：超时预算是本 crate 的常量，能力不许自设、调用方不许另传。
//!    配额账本则**按实例显式传入**（`&dyn 调用账本`）——账本落进程级，多实例就不隔离
//!    （宪法三条补缺陷之一「状态显式持有为句柄，不落进程级全局」）。
//! 4. **调度自身不 panic**：所有失败路径都是 `Result` / 枚举；锁中毒、长度超出表达范围
//!    都有明确处理，不靠 `unwrap` 崩。
//!
//! **超时是怎么判的**：执行函数是同步的 `extern "C"`，**进程内无法被抢占**，所以这里判的是
//! 「这一项有没有越界」——越界即报 `超时` 段位，让失败可编程判定（宪法「坏了看得见」）。
//! 真正强杀要跨进程（`现代架构落点.md` 形态 2 的进程级超时），不在本节点能力范围内。
//!
//! # 文件分工（本文件是路由：声明子模块 · 再导出公开面 · 零实现）
//!
//! - `错误与结果.rs` —— `调度错误` · `调用结果`
//! - `配额记账.rs` —— 配额上限与窗口 · 按能力号记账的滚动窗口账本
//! - `调度核心.rs` —— 单项超时口径 · 公开入口 `调用` · 调度核心 `调度`
//!
//! 模块名一律**不等于**它导出的符号名（`mod 配额记账` 导出 `配额账本`）：同名会与
//! 再导出在类型命名空间里撞名（`E0255`），所以文件名按「关注点」起，不按符号起。

