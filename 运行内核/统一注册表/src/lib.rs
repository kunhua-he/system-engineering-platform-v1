//! 统一注册表 —— 四张表 + 占位项 + 状态位。
//!
//! **编号只增不复用**（宪法第 7 条）。删掉的能力编号作废不回收。
//! **缺项由占位项兜底**：某个扩展没载入而别人引用了它的编号时，用占位项占住位置，
//! 保证编号不塌——错位是静默的，比崩溃更坏。
//!
//! 本模块的三条硬纪律：
//! 1. **不许半载**（`扩展装载与开发标准.md` 2.3）：建表校验全过才建表；任一条不过就返回
//!    `建表错误`，注册表根本不存在——不存在「进了一半」的中间态。
//! 2. **未命中给占位，不给空**（宪法第 6 条）：取号失败不是错误、不是崩溃，是可编程的降级。
//! 3. **号即下标**：命令号 / 类型号 / 常量号就是各自表里的下标（`数据类型信息.命令号表`
//!    里放的就是命令表下标），所以取号一律按项数判界，越界即占位。

use v1_contract::{常量排布, 数据槽, 平台信息};

pub use v1_contract::{常量信息, 命令信息, 数据类型信息, 执行函数};

/// 占位项写入返回槽的类型标签：**内核保留值**。
///
/// 正常类型标签取自 `契约声明/类型声明/`（按类型表下标取用），`u32::MAX` 不在任何
/// 可取范围里——拿到它即「不是一个类型」，`定长数据槽::判定相容` 会当场报 `类型不符`。
/// 这是 `契约声明/类型声明/` 建表前的唯一落点。
pub const 类型标签_错误: u32 = u32::MAX;

/// 占位项的错误段位：内核错误段（`0xxx`）——「提供者未载入」。
///
/// 这是 `契约声明/错误码表/` 建表前的唯一落点；建表后本常量改为引用登记值，
/// 数值只增不复用。
pub const 错误码_提供者未载入: u32 = 1;

/// 占位执行函数：把「提供者未载入」写进返回槽。**不 panic，不崩**。
///
/// 公开它是因为 `命令槽::占位` 里不带函数——调用侧（`调用调度`）拿到占位项时，
/// 要自己把这条失败写进返回槽，用的是同一个函数、同一个错误段位，不许各写一套。
///
/// # Safety
/// `返回槽` 若不为空，必须是调用方给出的可写槽（调用契约保证）。
pub unsafe extern "C" fn 占位执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    let _ = (参数个数, 参数表);
    if 返回槽.is_null() {
        // 没有可写的槽就静默返回：占位项的底线是「不许崩」。
        return;
    }
    // SAFETY: 空指针已挡；非空由调用契约保证可写。
    unsafe {
        *返回槽 = 数据槽::内联(类型标签_错误, u64::from(错误码_提供者未载入), 4);
    }
}

/// 命令槽：已载入给声明与执行函数，未载入给占位。
#[derive(Clone, Copy)]
pub enum 命令槽<'a> {
    已载入 { 声明: &'a 命令信息, 执行: 执行函数 },
    /// 占位：调用它返回「提供者未载入」的错误段位，不是崩溃。
    占位 { 号: u32 },
}

/// 类型槽 / 常量槽同理：未载入一律给占位，不给空。
#[derive(Clone, Copy)]
pub enum 类型槽<'a> {
    已载入(&'a 数据类型信息),
    占位 { 号: u32 },
}

#[derive(Clone, Copy)]
pub enum 常量槽<'a> {
    已载入(&'a 常量信息),
    占位 { 号: u32 },
}

/// 注册表：把静态声明变成可寻址的表。
///
/// 四张表在 `建表` 时一次性成形，字段私有——只能经 `建表` 得到，
/// 所以「表内不变量」（函数表与命令表等长）不可能被外面破坏。
pub struct 注册表 {
    命令表: &'static [命令信息],
    /// 与 `命令表` 等长（建表时保证），一一对应，缺项不许留空指针。
    函数表: &'static [执行函数],
    类型表: &'static [数据类型信息],
    常量表: &'static [常量信息],
}

/// 建表错误。与 `装载入口` 的判定六步一一对应。
///
/// 本模块只产生「表自己站不住」的那几条：`格式号不匹配` · `项表为空` ·
/// `类型表自相矛盾` · `常量表自相矛盾` · `函数表项数不符`。
/// `标识串重复` 与 `号段冲突` 是**跨扩展**判定（`装载入口` 的 ②③：标识串唯一、号段不冲突），
/// 单份声明里判不出来，本模块不产生它们。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 建表错误 {
    格式号不匹配 { 期望: u32, 实际: u32 },
    标识串重复,
    号段冲突 { 起: u32, 止: u32 },
    类型表自相矛盾 { 命令号: u32 },
    常量表自相矛盾 { 常量号: u32 },
    /// 表段自相矛盾：项数 > 0，却给了空项表指针 —— 这张表根本不可用（不是空表）。
    项表为空 { 表名: &'static str, 项数: u32 },
    /// 函数表项数与命令表项数不等 —— 这是**致命**的，不许半载。
    函数表项数不符 { 命令数: u32, 函数数: u32 },
}

/// 表名：`建表错误::项表为空` 的定位信息。
///
/// 不给表另编一套号——**名字就是位置**，报出来即可直接对到声明里的那一个字段。
mod 表名 {
    pub const 类型表: &str = "类型表";
    pub const 命令表: &str = "命令表";
    pub const 常量表: &str = "常量表";
    pub const 类型表_命令号表: &str = "类型表.命令号表";
    pub const 类型表_事件表: &str = "类型表.事件表";
    pub const 类型表_属性表: &str = "类型表.属性表";
    pub const 类型表_元素表: &str = "类型表.元素表";
    pub const 事件表_参数表: &str = "类型表.事件表.参数表";
    pub const 命令表_参数表: &str = "命令表.参数表";
}

/// 表段 → 切片。
///
/// **项数 > 0 却给空项表 = 这张表不可用**，当场拒绝：既不能当空表放过（那是半载），
/// 也不能拿空指针去 `from_raw_parts`（那是未定义行为）。
/// 传参按「项数 + 项表」两个字段，不传整个 `表段`：`表段<T>` 只在 `T: Copy` 时才 `Copy`，
/// 从 `&平台信息` 里读不出来（也正因如此，这里一律按字段取值，不搬结构）。
fn 切片<T>(项数: u32, 项表: *const T, 表名: &'static str) -> Result<&'static [T], 建表错误> {
    if 项数 == 0 {
        return Ok(&[]);
    }
    if 项表.is_null() {
        return Err(建表错误::项表为空 { 表名, 项数 });
    }
    // SAFETY: `声明` 是 &'static，其表段指向静态数据；项数 > 0 且项表非空。
    // u32 → usize 在 32/64 位目标下无损。
    Ok(unsafe { core::slice::from_raw_parts(项表, 项数 as usize) })
}

impl 注册表 {
    /// 从契约主结构建表。**要么完整可用，要么完全不进表**（不许半载）。
    ///
    /// 建表只判「表本身站得住」：格式号 · 表段形状 · 函数表项数 · 类型表的命令号引用 ·
    /// 常量排布。**参数类型标签是否已在类型表登记**属 `装载入口` 的 ⑥（跨表语义），
    /// 本函数不判——它需要看每一条参数，不是「表自己」的事。
    pub fn 建表(声明: &'static 平台信息) -> Result<Self, 建表错误> {
        // ① 格式号：格式的身份证，不是版本号。不匹配 = 这份声明不是本代契约写的。
        if 声明.声明格式号 != v1_contract::声明格式号 {
            return Err(建表错误::格式号不匹配 {
                期望: v1_contract::声明格式号,
                实际: 声明.声明格式号,
            });
        }

        // ② 四张表：项数 > 0 就必须给得出项表。
        let 类型表 = 切片(声明.类型表.项数, 声明.类型表.项表, 表名::类型表)?;
        let 命令表 = 切片(声明.命令表.项数, 声明.命令表.项表, 表名::命令表)?;
        let 常量表 = 切片(声明.常量表.项数, 声明.常量表.项表, 表名::常量表)?;

        // ③ 函数表与命令表一一对应（**致命项**：对不上就等于没有可调的命令）。
        //    `平台信息` 里没有「函数表项数」字段——项数就是命令数，所以唯一可判的
        //    「不等」是「有命令却没有函数表」（函数数按 0 计）。
        let 函数表: &'static [执行函数] = if 命令表.is_empty() {
            &[]
        } else if 声明.函数表.is_null() {
            return Err(建表错误::函数表项数不符 {
                命令数: 命令表.len() as u32,
                函数数: 0,
            });
        } else {
            // SAFETY: 同上；函数表与命令表等长，指向静态函数指针数组。
            unsafe { core::slice::from_raw_parts(声明.函数表, 命令表.len()) }
        };

        // ④ 类型表自洽：子表形状 + 命令号引用必须真的落在命令表里。
        for 类型 in 类型表 {
            let 命令号表 = 切片(类型.命令个数, 类型.命令号表, 表名::类型表_命令号表)?;
            let 事件表 = 切片(类型.事件个数, 类型.事件表, 表名::类型表_事件表)?;
            切片(类型.属性个数, 类型.属性表, 表名::类型表_属性表)?;
            切片(类型.元素个数, 类型.元素表, 表名::类型表_元素表)?;
            for 号 in 命令号表 {
                if *号 >= 命令表.len() as u32 {
                    return Err(建表错误::类型表自相矛盾 { 命令号: *号 });
                }
            }
            for 事件 in 事件表 {
                切片(事件.参数个数, 事件.参数表, 表名::事件表_参数表)?;
            }
        }

        // ⑤ 命令表的参数表：同一把尺子。
        for 命令 in 命令表 {
            切片(命令.参数个数, 命令.参数表, 表名::命令表_参数表)?;
        }

        // ⑥ 常量表自洽：排布必须是登记值；文本排布必须真带文本；逻辑常量只认 0/1。
        for (下标, 常量) in 常量表.iter().enumerate() {
            let 排布 = 常量.排布;
            let 排布已登记 = 排布 == 常量排布::空
                || 排布 == 常量排布::数值
                || 排布 == 常量排布::逻辑
                || 排布 == 常量排布::文本;
            if !排布已登记
                || (排布 == 常量排布::文本 && 常量.文本.is_null())
                || (排布 == 常量排布::逻辑 && 常量.数值 != 0.0 && 常量.数值 != 1.0)
            {
                return Err(建表错误::常量表自相矛盾 {
                    常量号: 下标 as u32,
                });
            }
        }

        // 全过 → 建表。到这里之前没有任何一张表被交出去，所以不存在半载。
        Ok(Self {
            命令表,
            函数表,
            类型表,
            常量表,
        })
    }

    /// 按号取命令。**未命中返回占位项，不返回空**（宪法第 6 条）。
    ///
    /// 号 = 命令表下标（`数据类型信息.命令号表` 里的号就是它）。
    pub fn 按号取命令(&self, 号: u32) -> 命令槽<'_> {
        match (self.命令表.get(号 as usize), self.函数表.get(号 as usize)) {
            (Some(声明), Some(&执行)) => 命令槽::已载入 { 声明, 执行 },
            // 两张表等长（建表时保证），所以只会同时命中或同时不命中。
            _ => 命令槽::占位 { 号 },
        }
    }

    pub fn 按号取类型(&self, 号: u32) -> 类型槽<'_> {
        match self.类型表.get(号 as usize) {
            Some(声明) => 类型槽::已载入(声明),
            None => 类型槽::占位 { 号 },
        }
    }

    pub fn 按号取常量(&self, 号: u32) -> 常量槽<'_> {
        match self.常量表.get(号 as usize) {
            Some(声明) => 常量槽::已载入(声明),
            None => 常量槽::占位 { 号 },
        }
    }

    /// 占位项（`内核落点.md` §五 冻结接口）：载入失败兜底。
    ///
    /// **兜底不许盖掉真项**：该号已载入就给真项，未载入才给占位。
    pub fn 占位项(&self, 号: u32) -> 命令槽<'_> {
        self.按号取命令(号)
    }

    /// 命令表项数（用于验证面比对）。
    pub fn 命令数(&self) -> u32 {
        self.命令表.len() as u32
    }
}

