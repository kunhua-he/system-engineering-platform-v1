    #[test]
    fn 越界取号走占位_不返回空() {
        let 表 = 注册表::建表(正常声明()).expect("正常声明必须建表成功");

        // 命令 2 条 → 2 号越界；类型 / 常量各 1 条 → 1 号越界。
        match 表.按号取命令(2) {
            命令槽::占位 { 号 } => assert_eq!(号, 2),
            命令槽::已载入 { .. } => panic!("2 号越界，必须是占位"),
        }
        match 表.按号取类型(1) {
            类型槽::占位 { 号 } => assert_eq!(号, 1),
            类型槽::已载入(_) => panic!("1 号越界，必须是占位"),
        }
        match 表.按号取常量(1) {
            常量槽::占位 { 号 } => assert_eq!(号, 1),
            常量槽::已载入(_) => panic!("1 号越界，必须是占位"),
        }

        // 占位项：越界号照样给得出占位（宪法第 6 条），且不给空。
        match 表.占位项(u32::MAX) {
            命令槽::占位 { 号 } => assert_eq!(号, u32::MAX),
            命令槽::已载入 { .. } => panic!("u32::MAX 不可能已载入"),
        }
        // 兜底不许盖掉真项：已载入的号给真项。
        match 表.占位项(0) {
            命令槽::已载入 { .. } => {}
            命令槽::占位 { 号 } => panic!("0 号已载入，兜底不许盖掉真项（号={号}）"),
        }

        // 占位执行函数：把「提供者未载入」写成结构化失败，不是崩溃。
        let mut 槽 = 数据槽::空槽();
        unsafe { 占位执行(&mut 槽, 0, core::ptr::null()) };
        assert_eq!(槽.类型标签, 类型标签_错误);
        assert_eq!(槽.值, u64::from(错误码_提供者未载入));
        assert!(!槽.是否空(), "占位失败是「有值」的错误，不是空值");

        // 连返回槽都没有也不许崩。
        unsafe { 占位执行(core::ptr::null_mut(), 0, core::ptr::null()) };
    }

