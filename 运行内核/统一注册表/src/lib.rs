//! 统一注册表 —— 四张表 + 占位项 + 状态位。
//!
//! **编号只增不复用**（宪法第 7 条）。删掉的能力编号作废不回收。
//! **缺项由占位项兜底**：某个扩展没载入而别人引用了它的编号时，用占位项占住位置，
//! 保证编号不塌——错位是静默的，比崩溃更坏。

pub use v1_contract::{常量信息, 命令信息, 数据类型信息, 执行函数};

/// 命令槽：已载入给声明与执行函数，未载入给占位。
#[derive(Clone, Copy)]
pub enum 命令槽<'a> {
    已载入 { 声明: &'a 命令信息, 执行: 执行函数 },
    /// 占位：调用它返回「提供者未载入」的错误段位，不是崩溃。
    占位 { 号: u32 },
}

/// 类型槽 / 常量槽同理：未载入一律给占位，不给空。
#[derive(Clone, Copy)]
pub enum 类型槽<'a> {
    已载入(&'a 数据类型信息),
    占位 { 号: u32 },
}

#[derive(Clone, Copy)]
pub enum 常量槽<'a> {
    已载入(&'a 常量信息),
    占位 { 号: u32 },
}

/// 注册表：把静态声明变成可寻址的表。
pub struct 注册表 {
    _私有: (),
}

/// 建表错误。与 `装载入口` 的判定六步一一对应。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 建表错误 {
    格式号不匹配 { 期望: u32, 实际: u32 },
    标识串重复,
    号段冲突 { 起: u32, 止: u32 },
    类型表自相矛盾 { 命令号: u32 },
    常量表自相矛盾 { 常量号: u32 },
    /// 函数表项数与命令表项数不等 —— 这是**致命**的，不许半载。
    函数表项数不符 { 命令数: u32, 函数数: u32 },
}

