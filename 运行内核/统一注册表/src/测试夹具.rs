//! 单元测试夹具：样本声明 · 样本零件 · 静态表钉桩。
//!
//! 夹具本身**不判**任何东西——它只负责把被测的那一处以外的东西都摆对，
//! 于是每个用例只需改一处就能造出反向样本。
//!
//! 只在 `cfg(test)` 下存在，故一律 `pub(crate)`：不进公开面。

use v1_contract::{
    号段, 参数信息, 常量排布, 常量信息, 命令信息, 数据类型信息, 数据槽, 事件信息, 执行函数,
    平台信息, 版本三元组, 表段,
};

/// 测试夹具用的号段与错误段位（必须静态，不能拿临时数组的指针）。
pub(crate) const 测试能力号段: [号段; 1] = [号段::新(1000, 1999)];
/// 本夹具命令表的**首个编号**：取号段的 `起`。
///
/// 不写字面量：编号必须落在本声明申报的能力号段内，换号段就得跟着换号
/// （`项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 5）。
pub(crate) const 测试命令首号: u32 = 测试能力号段[0].起.取();
pub(crate) const 测试错误段位表: [u32; 1] = [1];

// ── 夹具零件 ────────────────────────────────────────────────────────────

/// 执行函数甲：把「参数个数」原样写进返回槽的 值。
pub(crate) unsafe extern "C" fn 执行_首(返回槽: *mut 数据槽, 参数个数: u32, _参数表: *const 数据槽) {
    if !返回槽.is_null() {
        // SAFETY: 空指针已挡；非空由调用契约保证可写。
        unsafe { *返回槽 = 数据槽::内联(v1_contract::类型标签::新(1), u64::from(参数个数), 0) };
    }
}

/// 执行函数乙：写「参数个数 + 100」——与甲不同，用来验证取到的函数是对的。
pub(crate) unsafe extern "C" fn 执行_次(返回槽: *mut 数据槽, 参数个数: u32, _参数表: *const 数据槽) {
    if !返回槽.is_null() {
        unsafe { *返回槽 = 数据槽::内联(v1_contract::类型标签::新(2), u64::from(参数个数) + 100, 0) };
    }
}

pub(crate) fn 字节(文本: &'static str) -> *const u8 {
    文本.as_ptr()
}

pub(crate) fn 造参数(名称: &'static str) -> 参数信息 {
    参数信息 {
        名称: 字节(名称),
        说明: 字节(名称),
        类型标签: 1,
        状态位: 0,
        默认值: 数据槽::空槽(),
    }
}

/// `参数` 为空则参数表给空指针（与参数个数 0 一致）。
///
/// `编号` 是**显式命令编号**（`命令信息.编号`）——夹具里要什么号就给什么号，
/// 于是「按编号查」与「编号严格递增」都能各造一处反向样本。
pub(crate) fn 造命令(
    编号: u32,
    名称: &'static str,
    参数: &'static [参数信息],
    返回类型: u32,
) -> 命令信息 {
    命令信息 {
        名称: 字节(名称),
        说明: 字节(名称),
        类别: 0,
        状态位: 0,
        返回类型: 返回类型.into(),
        用户级别: 0,
        参数个数: 参数.len() as u32,
        参数表: if 参数.is_empty() {
            core::ptr::null()
        } else {
            参数.as_ptr()
        },
        编号: 编号.into(),
        可抛错误码: v1_contract::表段::空(),
    }
}

pub(crate) fn 造事件(参数: &'static [参数信息]) -> 事件信息 {
    事件信息 {
        名称: 字节("事件甲"),
        说明: 字节("事件甲"),
        参数个数: 参数.len() as u32,
        参数表: if 参数.is_empty() {
            core::ptr::null()
        } else {
            参数.as_ptr()
        },
    }
}

/// `类型标签` 是**显式类型标签**（`数据类型信息.类型标签`）——夹具里要什么标签就给什么标签。
pub(crate) fn 造类型(
    类型标签: u32,
    命令号表: &'static [u32],
    事件表: &'static [事件信息],
) -> 数据类型信息 {
    数据类型信息 {
        名称: 字节("类型甲"),
        说明: 字节("类型甲"),
        状态位: 0,
        命令个数: 命令号表.len() as u32,
        命令号表: if 命令号表.is_empty() {
            core::ptr::null()
        } else {
            命令号表.as_ptr()
        },
        事件个数: 事件表.len() as u32,
        事件表: if 事件表.is_empty() {
            core::ptr::null()
        } else {
            事件表.as_ptr()
        },
        属性个数: 0,
        属性表: core::ptr::null(),
        元素个数: 0,
        元素表: core::ptr::null(),
        类型标签,
    }
}

pub(crate) fn 造常量(常量号: v1_contract::常量号, 排布: u16, 文本: *const u8, 数值: f64) -> 常量信息 {
    常量信息 {
        名称: 字节("常量甲"),
        说明: 字节("常量甲"),
        排布,
        类型标签: v1_contract::类型标签::新(1),
        文本,
        数值,
        常量号,
    }
}

/// 最简声明：四张表全空、函数表空指针。**要改哪一处就改哪一处**——
/// 夹具不许掩盖被测的那一处。
pub(crate) fn 造声明(改: impl FnOnce(&mut 平台信息)) -> &'static 平台信息 {
    let 声明 = Box::leak(Box::new(平台信息 {
        声明格式号: v1_contract::声明格式号,
        目标字宽: 64,
        保留: 0,
        标识串: 字节("00000000000000000000000000000000"),
        实现版本: 版本三元组::新(1, 0, 0, 0),
        要求宿主版本: 版本三元组::新(1, 0, 0, 0),
        要求内核版本: 版本三元组::新(1, 0, 0, 0),
        名称: 字节("测试扩展"),
        说明: 字节("测试扩展"),
        状态位: 0,
        类型表: 表段::空(),
        命令表: 表段::空(),
        函数表: core::ptr::null(),
        常量表: 表段::空(),
        通知函数: None,
        依赖清单: 表段::空(),
        能力号段: 表段::新(测试能力号段.as_ptr(), 1),
        通知号段: 表段::空(),
        错误段位表: 表段::新(测试错误段位表.as_ptr(), 1),
        错误码表: 表段::空(),
        命令类别表: 表段::空(),
        要求权限: 表段::空(),
    }));
    改(声明);
    声明
}

/// 正常声明：2 条命令（编号 `测试命令首号` 带 1 个参数 · `测试命令首号 + 1`）·
/// 2 个执行函数 · 1 个类型 · 1 个常量。
///
/// 编号取号段的 `起`（不写字面量）：命令编号必须落在本声明申报的能力号段内
/// （`项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 5）。
pub(crate) fn 正常声明() -> &'static 平台信息 {
    造声明(|声明| {
        let 参数: &'static [参数信息] = Box::leak(Box::new([造参数("入参")]));
        let 命令: &'static [命令信息] = Box::leak(Box::new([
            造命令(测试命令首号, "甲", 参数, 1),
            造命令(测试命令首号 + 1, "乙", &[], 0),
        ]));
        let 函数: &'static [执行函数] = Box::leak(Box::new([执行_首, 执行_次]));
        let 命令号: &'static [u32] = Box::leak(Box::new([测试命令首号]));
        let 事件: &'static [事件信息] = Box::leak(Box::new([造事件(参数)]));
        let 类型: &'static [数据类型信息] = Box::leak(Box::new([造类型(1, 命令号, 事件)]));
        let 常量: &'static [常量信息] =
            Box::leak(Box::new([造常量(v1_contract::常量号::新(0), 常量排布::数值, core::ptr::null(), 3.5)]));

        声明.类型表 = 表段::新(类型.as_ptr(), 类型.len() as u32);
        声明.命令表 = 表段::新(命令.as_ptr(), 命令.len() as u32);
        声明.函数表 = 函数.as_ptr();
        声明.常量表 = 表段::新(常量.as_ptr(), 常量.len() as u32);
    })
}
