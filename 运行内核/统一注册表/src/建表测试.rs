#[test]
fn 正常建表_四张表都可寻址() {
    let 注册表 = match 注册表::建表(正常声明()) {
        Ok(项表) => 项表,
        Err(错误) => panic!("正常声明必须建表成功，却报：{错误:?}"),
    };
    assert_eq!(注册表.命令数(), 2, "命令数 = 命令表项数");

    // `测试命令首号`：首个命令（返回类型 1、1 个参数、执行函数首）。
    match 注册表.按号取命令(测试命令首号) {
        命令槽::已载入 { 声明, 执行 } => {
            assert_eq!(声明.返回类型.取号值(), 1);
            assert_eq!(声明.参数个数, 1);
            let mut 数据槽 = 数据槽::空槽();
            // SAFETY: 执行函数按契约收三个参数；首个命令不用参数表，给空指针。
            unsafe { 执行(&mut 数据槽, 7, core::ptr::null()) };
            assert_eq!(数据槽.值, 7, "首号取到的必须是首个命令");
        }
        命令槽::占位 { 能力号: 未命中命令号 } => panic!("首号已载入，不许给占位（号={未命中命令号:?}）"),
    }

    // `测试命令首号 + 1`：次个命令。
    match 注册表.按号取命令(能力号::新建(测试命令首号.取号值() + 1)) {
        命令槽::已载入 { 声明, 执行 } => {
            assert_eq!(声明.返回类型.取号值(), 0);
            let mut 数据槽 = 数据槽::空槽();
            unsafe { 执行(&mut 数据槽, 7, core::ptr::null()) };
            assert_eq!(数据槽.值, 107, "首号 + 1 取到的必须是次个命令");
        }
        命令槽::占位 { 能力号: 未命中命令号 } => panic!("首号 + 1 已载入，不许给占位（号={未命中命令号:?}）"),
    }

    match 注册表.按号取类型(类型标签::新建(1)) {
        类型槽::已载入(声明) => assert_eq!(声明.命令个数, 1),
        类型槽::占位 { 类型标签: 未命中类型号 } => panic!("类型标签 1 已载入，不许给占位（号={未命中类型号:?}）"),
    }
    match 注册表.按号取常量(常量号::新建(0)) {
        常量槽::已载入(声明) => assert_eq!(声明.数值, 3.5),
        常量槽::占位 { 常量号: 未命中常量号 } => panic!("常量号 0 已载入，不许给占位（号={未命中常量号:?}）"),
    }
}

