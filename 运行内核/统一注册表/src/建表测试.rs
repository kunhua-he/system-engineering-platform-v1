//! `建表` 的单元测试：四张表成形 + 每一条「表自己站不住」的反向样本。

use super::*;
use crate::测试夹具::*;
use crate::占位项::{命令槽, 类型槽, 常量槽};
use v1_contract::{数据槽, 表段};

#[test]
fn 正常建表_四张表都可寻址() {
    let 表 = match 注册表::建表(正常声明()) {
        Ok(表) => 表,
        Err(错) => panic!("正常声明必须建表成功，却报：{错:?}"),
    };
    assert_eq!(表.命令数(), 2, "命令数 = 命令表项数");

    // 0 号：甲（返回类型 1、1 个参数、执行函数甲）。
    match 表.按号取命令(0) {
        命令槽::已载入 { 声明, 执行 } => {
            assert_eq!(声明.返回类型, 1);
            assert_eq!(声明.参数个数, 1);
            let mut 槽 = 数据槽::空槽();
            // SAFETY: 执行函数按契约收三个参数；甲不用参数表，给空指针。
            unsafe { 执行(&mut 槽, 7, core::ptr::null()) };
            assert_eq!(槽.值, 7, "0 号取到的必须是甲");
        }
        命令槽::占位 { 号 } => panic!("0 号已载入，不许给占位（号={号}）"),
    }

    // 1 号：乙。
    match 表.按号取命令(1) {
        命令槽::已载入 { 声明, 执行 } => {
            assert_eq!(声明.返回类型, 0);
            let mut 槽 = 数据槽::空槽();
            unsafe { 执行(&mut 槽, 7, core::ptr::null()) };
            assert_eq!(槽.值, 107, "1 号取到的必须是乙");
        }
        命令槽::占位 { 号 } => panic!("1 号已载入，不许给占位（号={号}）"),
    }

    match 表.按号取类型(0) {
        类型槽::已载入(声明) => assert_eq!(声明.命令个数, 1),
        类型槽::占位 { 号 } => panic!("0 号类型已载入，不许给占位（号={号}）"),
    }
    match 表.按号取常量(0) {
        常量槽::已载入(声明) => assert_eq!(声明.数值, 3.5),
        常量槽::占位 { 号 } => panic!("0 号常量已载入，不许给占位（号={号}）"),
    }
}

