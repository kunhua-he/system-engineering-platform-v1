//! 占位项：未命中给占位、不给空（宪法第 6 条）。
//!
//! 占位执行函数把「提供者未载入」写成**结构化失败**——不是崩溃。
//! 三个槽类型（命令 / 类型 / 常量）同理：未载入一律给占位，不给空。

use v1_contract::{
    常量信息, 能力号, 类型标签, 常量号, 数据槽, 数据类型信息, 错误码, 命令信息, 执行函数,
};

/// 占位项写入返回槽的类型标签：**内核保留值**。
///
/// 正常类型标签取自 `契约声明/类型声明/`（按类型表下标取用），`u32::MAX` 不在任何
/// 可取范围里——拿到它即「不是一个类型」，`定长数据槽::判定相容` 会当场报 `类型不符`。
/// **值取自生成物**：`契约声明/类型声明/4294967295.json` 的「类型标签」⇒
/// `v1_contract::声明数据::类型标签_4294967295`（不再硬写 `u32::MAX`，硬写即第二来源）。
///
/// 型是 `类型标签`（号空间 newtype）：生成物给的是裸 `u32` 常量，此处用 `类型标签::新`
/// **在常量期**包一层 —— 生成物一个字不用改，号空间却在类型层立住。
pub const 类型标签_错误: 类型标签 =
    类型标签::新(v1_contract::声明数据::类型标签_4294967295);

/// 占位项的错误段位：内核错误段（`0xxx`）——「提供者未载入」。
///
/// **值取自生成物**：`契约声明/错误码表/0001.json` ⇒ `v1_contract::声明数据::错误码_1`
/// （不再硬写 `1`，硬写即第二来源）。数值只增不复用。
pub const 错误码_提供者未载入: 错误码 = 错误码::新(v1_contract::声明数据::错误码_1);

/// 占位执行函数：把「提供者未载入」写进返回槽。**不 panic，不崩**。
///
/// 公开它是因为 `命令槽::占位` 里不带函数——调用侧（`调用调度`）拿到占位项时，
/// 要自己把这条失败写进返回槽，用的是同一个函数、同一个错误段位，不许各写一套。
///
/// # Safety
/// `返回槽` 若不为空，必须是调用方给出的可写槽（调用契约保证）。
pub unsafe extern "C" fn 占位执行(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽) {
    let _ = (参数个数, 参数表);
    if 返回槽.is_null() {
        // 没有可写的槽就静默返回：占位项的底线是「不许崩」。
        return;
    }
    // SAFETY: 空指针已挡；非空由调用契约保证可写。
    unsafe {
        *返回槽 = 数据槽::内联(类型标签_错误, u64::from(错误码_提供者未载入.取()), 4);
    }
}

/// 命令槽：已载入给声明与执行函数，未载入给占位。
#[derive(Clone, Copy)]
pub enum 命令槽<'a> {
    已载入 { 声明: &'a 命令信息, 执行: 执行函数 },
    /// 占位：调用它返回「提供者未载入」的错误段位，不是崩溃。
    占位 { 号: 能力号 },
}

/// 类型槽 / 常量槽同理：未载入一律给占位，不给空。
#[derive(Clone, Copy)]
pub enum 类型槽<'a> {
    已载入(&'a 数据类型信息),
    占位 { 号: 类型标签 },
}

#[derive(Clone, Copy)]
pub enum 常量槽<'a> {
    已载入(&'a 常量信息),
    占位 { 号: 常量号 },
}
