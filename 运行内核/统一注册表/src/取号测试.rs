//! `取号` 的单元测试：越界给占位（不给空）· 兜底不许盖掉真项 · 空表取号全走占位。

use super::*;
use crate::测试夹具::*;
use crate::占位项::{占位执行, 类型标签_错误, 错误码_提供者未载入};
use v1_contract::{常量号, 类型标签, 能力号, 数据槽};

#[test]
fn 越界取号走占位_不返回空() {
    let 注册表实例 = 统一注册表::建表(正常声明()).expect("正常声明必须建表成功");

    // 命令 2 条（编号 `测试命令首号` / `+1`）→ 首号 + 2 越界；类型标签 1 已载入 → 取 99 越界；
    // 常量号 0 → 1 越界。
    match 注册表实例.按号取命令(能力号::新建(测试命令首号.取号值() + 2)) {
        命令槽::占位 { 能力号: 未命中命令号 } => assert_eq!(未命中命令号, 能力号::新建(测试命令首号.取号值() + 2)),
        命令槽::已载入 { .. } => panic!("首号 + 2 越界，必须是占位"),
    }
    match 注册表实例.按号取类型(类型标签::新建(99)) {
        类型槽::占位 { 类型标签: 未命中类型号 } => assert_eq!(未命中类型号, 99),
        类型槽::已载入(_) => panic!("99 号越界，必须是占位"),
    }
    match 注册表实例.按号取常量(常量号::新建(1)) {
        常量槽::占位 { 常量号: 未命中常量号 } => assert_eq!(未命中常量号, 1),
        常量槽::已载入(_) => panic!("1 号越界，必须是占位"),
    }

    // 占位项：越界号照样给得出占位（宪法第 6 条），且不给空。
    match 注册表实例.占位项(能力号::新建(u32::MAX)) {
        命令槽::占位 { 能力号: 未命中命令号 } => assert_eq!(未命中命令号, u32::MAX),
        命令槽::已载入 { .. } => panic!("u32::MAX 不可能已载入"),
    }
    // 兜底不许盖掉真项：已载入的号给真项。
    match 注册表实例.占位项(测试命令首号) {
        命令槽::已载入 { .. } => {}
        命令槽::占位 { 能力号: 未命中命令号 } => panic!("首号已载入，兜底不许盖掉真项（号={未命中命令号:?}）"),
    }

    // 占位执行函数：把「提供者未载入」写成结构化失败，不是崩溃。
    let mut 数据槽 = 数据槽::空槽();
    unsafe { 占位执行(&mut 数据槽, 0, core::ptr::null()) };
    assert_eq!(数据槽.类型标签, 类型标签_错误);
    assert_eq!(数据槽.槽值, u64::from(错误码_提供者未载入.取号值()));
    assert!(!数据槽.是否空(), "占位失败是「有值」的错误，不是空值");

    // 连返回槽都没有也不许崩。
    unsafe { 占位执行(core::ptr::null_mut(), 0, core::ptr::null()) };
}

#[test]
fn 空表_建表成功且取号全走占位() {
    let 注册表实例 = 统一注册表::建表(造声明(|_| {})).expect("空表也是合法声明：扩展可以只有名字");
    assert_eq!(注册表实例.命令数(), 0);

    for 号值 in [0u32, 1, u32::MAX] {
        match 注册表实例.按号取命令(能力号::新建(号值)) {
            命令槽::占位 { 能力号: 回值 } => assert_eq!(回值, 号值),
            命令槽::已载入 { .. } => panic!("空表不可能有已载入项"),
        }
        match 注册表实例.按号取类型(类型标签::新建(号值)) {
            类型槽::占位 { 类型标签: 回值 } => assert_eq!(回值, 号值),
            类型槽::已载入(_) => panic!("空表不可能有已载入项"),
        }
        match 注册表实例.按号取常量(常量号::新建(号值)) {
            常量槽::占位 { 常量号: 回值 } => assert_eq!(回值, 号值),
            常量槽::已载入(_) => panic!("空表不可能有已载入项"),
        }
    }
}
