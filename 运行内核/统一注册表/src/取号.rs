//! 按号取：**号 = 表项里那个显式号**（命令 `编号` · 类型 `类型标签` · 常量 `常量号`），
//! 不是表内下标。表按号严格递增（`建表.rs` 保证），故按号二分查找；未命中即占位，不给空
//! （宪法第 6 条）。
//!
//! **为什么不再用下标**：下标会随合并/重排顺序漂移，且两份声明都从 0 起就撞号
//! （`冻结登记.json` 待办旁路 · 阻断级）。显式号只增不复用、允许有洞，按号寻址才稳。

use crate::建表::统一注册表;
use crate::占位项::{命令槽, 类型槽, 常量槽};

use v1_contract::{能力号, 类型标签};

impl 统一注册表 {
    /// 按号取命令。**号 = 命令编号**（`命令信息.编号`），不是命令表下标。
    /// **未命中返回占位项，不返回空**（宪法第 6 条）。
    ///
    /// `数据类型信息.命令号表` 里放的也是命令编号（同一把尺子）。
    ///
    /// **号空间进类型**：形参是 `能力号`，不是裸 `u32` ⇒ 拿类型标签 / 资源号 / 错误码来顶替
    /// **编不过**（`号段图.json` 的「四个号空间互不相通」由类型维持，不再只靠判据）。
    pub fn 按号取命令(&self, 命令号: 能力号) -> 命令槽<'_> {
        match self.命令表.binary_search_by_key(&命令号, |命令| 命令.编号) {
            // 函数表与命令表等长且一一对应（建表时保证）。
            Ok(位置) => 命令槽::已载入 {
                声明: &self.命令表[位置],
                执行: self.函数表[位置],
            },
            Err(_) => 命令槽::占位条目 { 能力号: 命令号 },
        }
    }

    /// 按**表内位置**取命令：第 `位置` 条（0 起）。**只给枚举用**（读侧列「有哪些能力」），
    /// **寻址一律走 `按号取命令`（按编号）** —— 枚举要的是「表里有哪些」，寻址要的是「号是谁」，
    /// 两件事，别混。越界给占位。
    ///
    /// `位置` 是**下标**（表内位置），不是号 —— 故仍是 `u32`；越界占位时把它包成 `能力号`，
    /// 因为占位槽装的是「没找到的那个命令号」。
    pub fn 按位取命令(&self, 位置: u32) -> 命令槽<'_> {
        match (self.命令表.get(位置 as usize), self.函数表.get(位置 as usize)) {
            (Some(声明), Some(&执行)) => 命令槽::已载入 { 声明, 执行 },
            _ => 命令槽::占位条目 { 能力号: 能力号::新建(位置) },
        }
    }

    /// 按号取类型。**号 = 类型标签**（`数据类型信息.类型标签`），不是类型表下标。
    ///
    /// 形参是 `类型标签` ⇒ 拿能力号 / 错误码来顶替**编不过**。
    pub fn 按号取类型(&self, 类型号: 类型标签) -> 类型槽<'_> {
        match self.类型表.binary_search_by_key(&类型号, |类型| 类型.类型标签) {
            Ok(位置) => 类型槽::已载入(&self.类型表[位置]),
            Err(_) => 类型槽::占位条目 { 类型标签: 类型号 },
        }
    }

    /// 按号取常量。**号 = 常量号**（`常量信息.常量号`），不是常量表下标。
    ///
    /// 形参名与型同名会撞（E0530）⇒ 型写全路径 `v1_contract::常量号`，形参用词表名 `常量号`。
    pub fn 按号取常量(&self, 常量号: v1_contract::常量号) -> 常量槽<'_> {
        match self.常量表.binary_search_by_key(&常量号, |常量表条目| 常量表条目.常量号) {
            Ok(位置) => 常量槽::已载入(&self.常量表[位置]),
            Err(_) => 常量槽::占位条目 { 常量号: 常量号 },
        }
    }

    /// 占位项（`内核落点.md` §五 冻结接口）：载入失败兜底。
    ///
    /// **兜底不许盖掉真项**：该号已载入就给真项，未载入才给占位。
    pub fn 占位项(&self, 命令号: 能力号) -> 命令槽<'_> {
        self.按号取命令(命令号)
    }

    /// 命令表项数（用于验证面比对）。
    pub fn 命令数(&self) -> u32 {
        self.命令表.len() as u32
    }
}

