//! 建表：四张表一次性成形 —— **要么完整可用，要么完全不进表**（不许半载）。
//!
//! 只判「表本身站得住」：格式号 · 表段形状 · 函数表项数 · **三张表按显式号严格递增** ·
//! 类型表的命令号引用 · 常量排布。
//! **参数类型标签是否已在类型表登记**属 `装载入口` 的 ⑥（跨表语义），本模块不判——
//! 它需要看每一条参数，不是「表自身」的事。

use v1_contract::{常量排布, 常量号, 常量信息, 命令信息, 能力号, 数据类型信息, 执行函数, 平台信息};

/// 注册表：把静态声明变成可寻址的表。
///
/// 四张表在 `建表` 时一次性成形，字段**只在本 crate 内可见**（`pub(crate)`：`取号.rs`
/// 是兄弟模块，按号取要读它们）——crate 外只能经 `建表` 得到，所以「表内不变量」
/// （函数表与命令表等长）不可能被外面破坏。
pub struct 统一注册表 {
    pub(crate) 命令表: &'static [命令信息],
    /// 与 `命令表` 等长（建表时保证），一一对应，缺项不许留空指针。
    pub(crate) 函数表: &'static [执行函数],
    pub(crate) 类型表: &'static [数据类型信息],
    pub(crate) 常量表: &'static [常量信息],
}

/// 建表错误。与 `装载入口` 的判定六步一一对应。
///
/// 变体名**逐字取** `契约声明/错误码表/<码>.json` 的 `名称` —— 码表是名称的唯一登记处
/// （`契约声明/格式说明.md` §五），而运行期把变体换成码只能按名对（枚举不带码）。
/// 一处已知例外：`标识串重复` 对应的码 7 叫 `标识串非法`；本模块**不产生**该变体
/// （它要跨扩展判定），故没改，缺口登记在 `项目文档/未完成事项.md` 第 97 条。
///
/// 本模块只产生「表自身站不住」的那几条：`声明格式号不匹配` · `项表为空` ·
/// `项数超上限` · `类型表自相矛盾` · `常量表自相矛盾` · `函数表项数不符`。
/// `标识串重复` 与 `号段冲突` 是**跨扩展**判定（`装载入口` 的 ②③：标识串唯一、号段不冲突），
/// 单份声明里判不出来，本模块不产生它们。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 建表错误 {
    声明格式号不匹配 { 期望: u32, 实际: u32 },
    标识串重复,
    号段冲突 { 段起点: u32, 止: u32 },
    类型表自相矛盾 { 命令号: 能力号 },
    常量表自相矛盾 { 常量号: 常量号 },
    /// 表段自相矛盾：项数 > 0，却给了空项表指针 —— 这张表根本不可用（不是空表）。
    项表为空 { 表名: &'static str, 项数: u32 },
    /// 表段自相矛盾：项数超过防呆上限 —— 拿这个数去 `from_raw_parts` 就是越界。
    项数超上限 { 表名: &'static str, 项数: u32 },
    /// 函数表项数与命令表项数不等 —— 这是**致命**的，不许半载。
    函数表项数不符 { 命令数: u32, 函数数: u32 },
    /// 命令表不按 `编号` 严格递增 —— 注册表按编号二分查找，乱序即错位（fail-closed）。
    ///
    /// **号只增不复用、允许有洞**：递增只要求 `前 < 当前`（相等即撞号，也拒）。
    命令编号不递增 { 序: u32, 前值: u32, 当前: u32 },
    /// 常量表不按 `常量号` 严格递增（同上）。
    常量号不递增 { 序: u32, 前值: u32, 当前: u32 },
    /// 类型表不按 `类型标签` 严格递增（同上）。
    类型标签不递增 { 序: u32, 前值: u32, 当前: u32 },
}

/// 表名：`建表错误::项表为空` 的定位信息。
///
/// 不给表另编一套号——**名字就是位置**，报出来即可直接对到声明里的那一个字段。
mod 表名 {
    pub const 类型表: &str = "类型表";
    pub const 命令表: &str = "命令表";
    pub const 常量表: &str = "常量表";
    pub const 类型表_命令号表: &str = "类型表.命令号表";
    pub const 类型表_事件表: &str = "类型表.事件表";
    pub const 类型表_属性表: &str = "类型表.属性表";
    pub const 类型表_元素表: &str = "类型表.元素表";
    pub const 事件表_参数表: &str = "类型表.事件表.参数表";
    pub const 命令表_参数表: &str = "命令表.参数表";
}

/// 一张表的项数上限（防呆）。
///
/// `项数` 是声明里的 `u32`，`切片` 会拿它去 `core::slice::from_raw_parts` —— 没有上限时，
/// 一份坏声明（如 `项数 = u32::MAX`）就是一条精确的越界路。底座与扩展同进程、
/// `panic = "abort"` ⇒ 一次越界带走整个网关。
///
/// 取 `10_000`：号段空间是 10 类 × 每类 1000 个号，合法编号最多 10 000 条 ——
/// 这是**防呆上限**，不是契约里的数。
const 项数上限: u32 = 10_000;

/// 表段 → 切片。
///
/// **项数 > 0 却给空项表 = 这张表不可用**，当场拒绝：既不能当空表放过（那是半载），
/// 也不能拿空指针去 `from_raw_parts`（那是未定义行为）。**项数超上限**（防呆）同样拒绝。
/// 传参按「项数 + 项表」两个字段，不传整个 `表段`：`表段<T>` 只在 `T: Copy` 时才 `Copy`，
/// 从 `&平台信息` 里读不出来（也正因如此，这里一律按字段取值，不搬结构）。
fn 项表切片<项类型>(项数: u32, 项表: *const 项类型, 表名: &'static str) -> Result<&'static [项类型], 建表错误> {
    if 项数 > 项数上限 {
        return Err(建表错误::项数超上限 { 表名, 项数 });
    }
    if 项数 == 0 {
        return Ok(&[]);
    }
    if 项表.is_null() {
        return Err(建表错误::项表为空 { 表名, 项数 });
    }
    // SAFETY: `声明` 是 &'static，其表段指向静态数据；项数 > 0 且项表非空。
    // u32 → usize 在 32/64 位目标下无损。
    Ok(unsafe { core::slice::from_raw_parts(项表, 项数 as usize) })
}

/// 判一张表按某个**显式号字段**严格递增（号只增不复用、允许有洞；相等即撞号，也拒）。
///
/// 返回第一处违反的 `(序, 前, 当前)`；全递增则 `None`。
///
/// 为什么建表就要判：注册表按显式号**二分查找**（`取号.rs`）。表没排好序，二分查找会
/// 静默找错项——而「错位是静默的，比崩溃更坏」（`README.md` 第二节）。所以这是
/// **fail-closed** 的一条，不是提醒。
fn 首处不递增<取号: Fn(usize) -> u32>(项数: usize, 取号: 取号) -> Option<(u32, u32, u32)> {
    for 序号 in 1..项数 {
        let 前一个号值 = 取号(序号 - 1);
        let 当前 = 取号(序号);
        if 当前 <= 前一个号值 {
            return Some((序号 as u32, 前一个号值, 当前));
        }
    }
    None
}

impl 统一注册表 {
    /// 从契约主结构建表。**要么完整可用，要么完全不进表**（不许半载）。
    ///
    /// 建表只判「表本身站得住」：格式号 · 表段形状 · 函数表项数 · **三张表按显式号严格递增** ·
    /// 类型表的命令号引用 · 常量排布。**参数类型标签是否已在类型表登记**属 `装载入口` 的 ⑥
    /// （跨表语义），本函数不判——它需要看每一条参数，不是「表自身」的事。
    pub fn 建表(声明: &'static 平台信息) -> Result<Self, 建表错误> {
        // ① 格式号：格式的身份证，不是版本号。不匹配 = 这份声明不是本代契约写的。
        if 声明.声明格式号 != v1_contract::声明格式号 {
            return Err(建表错误::声明格式号不匹配 {
                期望: v1_contract::声明格式号.取号值(),
                实际: 声明.声明格式号.取号值(),
            });
        }

        // ② 四张表：项数 > 0 就必须给得出项表。
        let 类型表 = 项表切片(声明.类型表.项数, 声明.类型表.项表, 表名::类型表)?;
        let 命令表 = 项表切片(声明.命令表.项数, 声明.命令表.项表, 表名::命令表)?;
        let 常量表 = 项表切片(声明.常量表.项数, 声明.常量表.项表, 表名::常量表)?;

        // ③ 函数表与命令表一一对应（**致命项**：对不上就等于没有可调的命令）。
        //    `平台信息` 里没有「函数表项数」字段——项数就是命令数，所以唯一可判的
        //    「不等」是「有命令却没有函数表」（函数数按 0 计）。
        let 函数表: &'static [执行函数] = if 命令表.is_empty() {
            &[]
        } else if 声明.函数表.is_null() {
            return Err(建表错误::函数表项数不符 {
                命令数: 命令表.len() as u32,
                函数数: 0,
            });
        } else {
            // SAFETY: 同上；函数表与命令表等长，指向静态函数指针数组。
            unsafe { core::slice::from_raw_parts(声明.函数表, 命令表.len()) }
        };

        // ③′ 三张表各按**显式号**严格递增 —— 这是「注册表按编号二分查找」的前提。
        //    号只增不复用、允许有洞；相等（撞号）与逆序都拒。fail-closed，不许半载。
        if let Some((序号, 前一个号值, 当前)) = 首处不递增(命令表.len(), |位置| 命令表[位置].编号.取号值()) {
            return Err(建表错误::命令编号不递增 { 序: 序号, 前值: 前一个号值, 当前 });
        }
        if let Some((序号, 前一个号值, 当前)) = 首处不递增(常量表.len(), |位置| 常量表[位置].常量号.取号值()) {
            return Err(建表错误::常量号不递增 { 序: 序号, 前值: 前一个号值, 当前 });
        }
        if let Some((序号, 前一个号值, 当前)) = 首处不递增(类型表.len(), |位置| 类型表[位置].类型标签.取号值()) {
            return Err(建表错误::类型标签不递增 { 序: 序号, 前值: 前一个号值, 当前 });
        }

        // ④ 类型表自洽：子表形状 + 命令号引用必须真的落在命令表里。
        //    `命令号表` 里放的是**命令编号**（显式 `命令信息.编号`），不是表内下标。
        for 类型 in 类型表 {
            let 命令号表 = 项表切片(类型.命令个数, 类型.命令号表, 表名::类型表_命令号表)?;
            let 事件表 = 项表切片(类型.事件个数, 类型.事件表, 表名::类型表_事件表)?;
            项表切片(类型.属性个数, 类型.属性表, 表名::类型表_属性表)?;
            项表切片(类型.元素个数, 类型.元素表, 表名::类型表_元素表)?;
            for 命令编号 in 命令号表 {
                if !命令表.iter().any(|命令| 命令.编号.取号值() == *命令编号) {
                    return Err(建表错误::类型表自相矛盾 { 命令号: 能力号::新建(*命令编号) });
                }
            }
            for 事件项 in 事件表 {
                项表切片(事件项.参数个数, 事件项.参数表, 表名::事件表_参数表)?;
            }
        }

        // ⑤ 命令表的参数表：同一把尺子。
        for 命令 in 命令表 {
            项表切片(命令.参数个数, 命令.参数表, 表名::命令表_参数表)?;
        }

        // ⑥ 常量表自洽：排布必须是登记值；文本排布必须真带文本；逻辑常量只认 0/1。
        for 常量 in 常量表 {
            let 排布 = 常量.排布;
            let 排布已登记 = 排布 == 常量排布::无值
                || 排布 == 常量排布::数值
                || 排布 == 常量排布::逻辑
                || 排布 == 常量排布::文本;
            if !排布已登记
                || (排布 == 常量排布::文本 && 常量.文本.is_null())
                || (排布 == 常量排布::逻辑 && 常量.数值 != 0.0 && 常量.数值 != 1.0)
            {
                return Err(建表错误::常量表自相矛盾 {
                    常量号: 常量.常量号,
                });
            }
        }

        // 全过 → 建表。到这里之前没有任何一张表被交出去，所以不存在半载。
        Ok(Self {
            命令表,
            函数表,
            类型表,
            常量表,
        })
    }
}

