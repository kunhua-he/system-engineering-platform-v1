//! 形状 —— 生命周期通知子号 · 通知端点 · 派发结果。

use v1_contract::通知函数;

/// 生命周期号段（2000–2999）里的具体子号。
///
/// 契约只冻结**号段范围**（`通知号段::生命周期起/止`），段内子号尚未登记在
/// `契约声明/` 里。所以段内子号在本节点定义一次，别处只许引用，不许各写一个数。
pub mod 生命周期通知 {
    use v1_contract::{通知号, 通知号段};

    /// 装载：扩展被载入后收到的一次通知。
    pub const 装载: 通知号 = 通知号::新建(通知号段::生命周期起);
    /// 卸载：宿主问扩展「能不能卸」。扩展回 `通知返回::延迟释放` 即**拒绝本次卸载**。
    pub const 卸载: 通知号 = 通知号::新建(通知号段::生命周期起 + 1);
    /// 退出：底座退出前给所有扩展的最后一次通知。
    pub const 退出: 通知号 = 通知号::新建(通知号段::生命周期起 + 2);
    /// 延迟释放应答：引用清零后宿主再来一次，扩展此时应回成功。
    pub const 延迟释放: 通知号 = 通知号::新建(通知号段::生命周期起 + 3);
}

/// 一个已注册的通知端点。
#[derive(Clone, Copy)]
pub struct 通知端点 {
    pub 标识串: *const u8,
    pub 函数: 通知函数,
}

/// 派发结果。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 派发结果 {
    成功,
    失败,
    /// 扩展请求延迟释放 —— 它的引用还没清零，或它挂了别的组件的钩子。
    请求延迟释放,
    /// 号段里没有这个号：**返回「未命中」，不是错误**（宪法第 6 条）。
    未命中,
}
