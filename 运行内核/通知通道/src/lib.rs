//! 通知通道 —— 双向通道的三个号段。
//!
//! - **下行 1–999**：宿主 → 扩展。本节点提供 `派发下行通知`（广播给全部已注册端点）。
//! - **上行 1000–1999**：**本版未启用**（`契约声明/号段图.json` 标注「实现落点未定」）。
//!   扩展取系统值走**能力调用** —— 宿主把「取系统值」那一族能力注册进 `运行内核/统一注册表`，
//!   扩展按**能力号**调（`运行内核/调用调度`），取值函数的**持有者 = 宿主**
//!   （注册进注册表的那份实现），**不经本节点**。本节点只承载下行派发 + 生命周期。
//! - **生命周期 2000–2999**：装载 · 卸载 · 退出 · 延迟释放。
//!
//! 生命周期段里有两条最容易被漏掉的：**卸载要能被拒绝**（引用未清零时请求延迟释放），
//! 以及**卸载必须收回**（注册表项 · 类型表项 · 常量表项 · 内存 · 资源 · 已注册的通知）。
//! 本节点负责其中**已注册的通知**这一项：卸载成功即把该标识串的端点从端点表里摘掉。
//! 其余各项分属 `统一注册表` / `内存分配器` 等节点，由内核卸载路径按同一份标识串收回。
//!
//! **未命中不是错误**（宪法第 6 条）：号不在号段里，或号段里没有接收方，都返回
//! `派发结果::未命中`，不是失败、更不是 panic。

