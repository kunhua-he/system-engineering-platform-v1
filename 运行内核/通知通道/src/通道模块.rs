//! 通道 —— 通知通道本体：派发下行通知 + 生命周期管理。

use core::cell::RefCell;

// 号空间类型**不 `use` 进来**：形参名就叫 `通知号`，import 进来会撞（E0530）。
// 类型位置写全路径 `v1_contract::通知号`。
use v1_contract::{通知号段, 通知函数, 通知返回};

use super::通知形状::{生命周期通知, 通知端点, 派发结果};

/// 标识串读取上限（字节）。标识串按契约是 32 位十六进制 + NUL；给足余量。
/// 读到上限还没有 NUL 就判「不相同」——不让一个坏指针把派发拖进死循环。
const 标识串上限: usize = 256;

/// 通知通道：派发下行通知 + 生命周期管理。
///
/// 端点表用 `RefCell` 持有：`请求卸载` 与 `注销通知端点` 都要改表，而 `请求卸载` 的签名是
/// `&self`（内核卸载路径只借出共享引用）。**任何外部函数调用都不在借用期内发生**
/// —— 先摘表、放掉借用、再调端点函数，所以端点函数回手调 `注册通知端点`/`注销通知端点` 也不会撞借用。
pub struct 通知通道 {
    端点表: RefCell<Vec<通知端点>>,
}

impl 通知通道 {
    pub fn 构造() -> Self {
        Self { 端点表: RefCell::new(Vec::new()) }
    }

    /// 注册一个通知端点。
    ///
    /// - `标识串` 为空指针 → 忽略（无法寻址，fail-closed）。
    /// - `标识串` 已注册 → **保留先注册的那个**，不登记第二个。标识串必须唯一
    ///   （`扩展装载与开发标准.md` 2.3 ②：重复身份即拒绝），否则同一个号会被派发两次。
    ///
    /// `函数` 必须是一个终生有效的 `通知函数` 指针；本节点只保存、不校验。
    ///
    /// 签名按冻结接口保持安全函数（不改签名），但确实会读 `标识串` 指向的字节。
    // 所以在此显式登记这条 clippy 例外：`标识串` 是契约保证的 NUL 结尾边界串，
    // 读取有 256 字节上限兜底；不因此把已冻结的公开签名改成 `unsafe`。
    #[allow(clippy::not_unsafe_ptr_arg_deref)]
    pub fn 注册通知端点(&mut self, 标识串: *const u8, 端点函数: 通知函数) {
        if 标识串.is_null() {
            return;
        }
        let 端点表 = self.端点表.get_mut();
        let 已存在 = 端点表.iter().any(|端点| unsafe { 标识串相同(端点.标识串, 标识串) });
        if 已存在 {
            return;
        }
        端点表.push(通知端点 { 标识串, 端点函数 });
    }

    /// 注销一个通知端点。注销后该标识串不再被派发。
    ///
    /// 未注册的标识串、空指针 → 无操作（未命中不是错误）。
    // 同 `注册通知端点`：读 NUL 结尾边界串，签名保持冻结的安全函数。
    #[allow(clippy::not_unsafe_ptr_arg_deref)]
    pub fn 注销通知端点(&mut self, 标识串: *const u8) {
        if 标识串.is_null() {
            return;
        }
        self.端点表
            .get_mut()
            .retain(|端点| !unsafe { 标识串相同(端点.标识串, 标识串) });
    }

    /// 已注册的端点数（供内核与验证面比对，不参与派发）。
    pub fn 端点数(&self) -> u32 {
        self.端点表.borrow().len() as u32
    }

    /// 派发下行通知：宿主 → 扩展。
    ///
    /// 号在 1–999 之外（不在下行段），或表里没有接收方 ⇒ `未命中`（宪法第 6 条）。
    /// 否则按注册顺序广播给全部端点，并归并回执：
    /// 任一端点回 `失败` ⇒ `失败`；否则任一端点回 `延迟释放` ⇒ `请求延迟释放`；否则 `成功`。
    ///
    /// # Safety
    /// `参数一` / `参数二` 的含义由号段决定，调用方必须按号段约定传。
    pub unsafe fn 派发下行通知(
        &self,
        通知号: v1_contract::通知号,
        参数一: usize,
        参数二: usize,
    ) -> 派发结果 {
        if !(通知号段::下行起..=通知号段::下行止).contains(&通知号.取号值()) {
            return 派发结果::未命中;
        }
        // 先拷一份快照，再放掉借用去调外部函数：端点函数里若回手调本通道，
        // 不会撞上 RefCell 的借用检查而 panic。
        let 快照: Vec<通知端点> = self.端点表.borrow().clone();
        if 快照.is_empty() {
            return 派发结果::未命中;
        }
        let mut 调用读数 = 派发结果::成功;
        for 端点 in 快照 {
            // SAFETY: 端点由 `注册通知端点` 收入，注册方保证 `函数` 是终生有效的通知函数指针。
            let 回执 = unsafe { (端点.端点函数)(通知号, 参数一, 参数二) };
            match 回执 {
                通知返回::成功 => {}
                通知返回::延迟释放 => {
                    if 调用读数 == 派发结果::成功 {
                        调用读数 = 派发结果::请求延迟释放;
                    }
                }
                _ => 调用读数 = 派发结果::失败,
            }
        }
        调用读数
    }

    /// 生命周期：卸载请求。扩展可返回「请求延迟释放」。
    ///
    /// 发的是 `2001 卸载`（`生命周期通知::卸载`）——宿主第一次问「能不能卸」。
    /// 四种结局：
    /// - 端点不存在 ⇒ `未命中`（不是错误）。
    /// - 端点回 `通知返回::延迟释放` ⇒ `请求延迟释放`：**允许被拒绝**，端点原样放回，
    ///   等引用清零后再来一次（第二次走 [`通知通道::延迟释放协商`]，发 `2003 延迟释放`）。
    /// - 端点回 `成功` ⇒ 收回：该标识串的端点从端点表里摘掉（卸载必须收回，本节点这一项）。
    /// - 其余回执（含 `失败`）⇒ fail-closed：不放行卸载，端点原样放回，返回 `失败`。
    ///
    /// # Safety 之外的约定
    /// `标识串` 必须指向 NUL 结尾的字节串（契约：标识串 = 32 位十六进制 + NUL）；
    /// 已注册端点的 `函数` 必须是有效指针。
    // 同 `注册通知端点`：读 NUL 结尾边界串，签名保持冻结的安全函数。
    #[allow(clippy::not_unsafe_ptr_arg_deref)]
    pub fn 请求卸载(&self, 标识串: *const u8) -> 派发结果 {
        self.问卸载(标识串, 生命周期通知::卸载扩展)
    }

    /// 生命周期：**延迟释放协商**（⑥）—— 引用清零后宿主**再问一次**。
    ///
    /// 发的是 `2003 延迟释放`（`生命周期通知::延迟释放`，契约 `通知号段/2003.json`：
    /// 「引用清零后，宿主再问一次能否卸载」）。结局与 [`通知通道::请求卸载`] 同一套：
    /// 回 `成功` ⇒ 收回（端点摘掉）；回 `延迟释放` ⇒ 仍拒绝、端点放回；其余 ⇒ `失败`、端点放回。
    ///
    /// 与 `请求卸载` 分两个号，是因为契约把「第一次问」(`2001`) 与「引用清零后再问」(`2003`)
    /// 定成两个通知号 —— 扩展可据此区分是初次请求还是延迟释放后的复核。
    ///
    /// # Safety 之外的约定
    /// 同 [`通知通道::请求卸载`]：`标识串` 必须指向 NUL 结尾字节串。
    #[allow(clippy::not_unsafe_ptr_arg_deref)]
    pub fn 延迟释放协商(&self, 标识串: *const u8) -> 派发结果 {
        self.问卸载(标识串, 生命周期通知::延迟释放应答)
    }

    /// 生命周期：**装载通知**（发 `2000 装载`）—— 扩展被载入后宿主通知它一次。
    ///
    /// 与 `请求卸载` 同一形状（按标识串找端点 · 归并回执），**但不收回端点**：
    /// 装载只是「告知已载入」，端点留在表里。回执归并同 [`通知通道::派发下行通知`]：
    /// 任一端点回 `失败` ⇒ `失败`；否则任一回 `延迟释放` ⇒ `请求延迟释放`；
    /// 全部成功 ⇒ `成功`；该标识串没有端点 ⇒ `未命中`（不是错误）。
    ///
    /// # Safety 之外的约定
    /// 同 [`通知通道::请求卸载`]：`标识串` 必须指向 NUL 结尾字节串。
    // 同 `注册通知端点`：读 NUL 结尾边界串，签名保持冻结的安全函数。
    #[allow(clippy::not_unsafe_ptr_arg_deref)]
    pub fn 装载(&self, 标识串: *const u8) -> 派发结果 {
        if 标识串.is_null() {
            return 派发结果::未命中;
        }
        // 先拷快照再放掉借用去调外部函数（同 `派发下行通知`）：端点函数里若回手调本通道，
        // 不会撞上 RefCell 的借用检查而 panic。
        let 快照: Vec<通知端点> = self.端点表.borrow().clone();
        let mut 命中 = false;
        let mut 调用读数 = 派发结果::成功;
        for 端点 in 快照 {
            if !unsafe { 标识串相同(端点.标识串, 标识串) } {
                continue;
            }
            命中 = true;
            // SAFETY: 端点由 `注册通知端点` 收入，注册方保证 `函数` 是终生有效的通知函数指针。
            let 回执 = unsafe { (端点.端点函数)(生命周期通知::装载, 0, 0) };
            match 回执 {
                通知返回::成功 => {}
                通知返回::延迟释放 => {
                    if 调用读数 == 派发结果::成功 {
                        调用读数 = 派发结果::请求延迟释放;
                    }
                }
                _ => 调用读数 = 派发结果::失败,
            }
        }
        if 命中 { 调用读数 } else { 派发结果::未命中 }
    }

    /// 问卸载的共用体：摘下该标识串的端点 → 按 `通知号` 问一次 → 收回或放回。
    ///
    /// 借用纪律同 `请求卸载`：先摘表、放掉借用、再调端点函数。
    fn 问卸载(&self, 标识串: *const u8, 通知号: v1_contract::通知号) -> 派发结果 {
        if 标识串.is_null() {
            return 派发结果::未命中;
        }

        // ① 把该标识串的端点全部摘下。借用只在这一小段里，不跨越外部调用。
        let mut 摘下: Vec<通知端点> = Vec::new();
        {
            let mut 项表 = self.端点表.borrow_mut();
            let 原表 = core::mem::take(&mut *项表);
            for 端点 in 原表 {
                if unsafe { 标识串相同(端点.标识串, 标识串) } {
                    摘下.push(端点);
                } else {
                    项表.push(端点);
                }
            }
        }
        if 摘下.is_empty() {
            return 派发结果::未命中;
        }

        // ② 问扩展「能不能卸」。只有明确回成功才收回，其余一律把端点放回去。
        let mut 可以卸 = true;
        let mut 见过失败 = false;
        for 端点 in &摘下 {
            // SAFETY: 端点由 `注册通知端点` 收入，注册方保证 `函数` 是终生有效的通知函数指针。
            let 回执 = unsafe { (端点.端点函数)(通知号, 0, 0) };
            match 回执 {
                通知返回::成功 => {}
                通知返回::延迟释放 => 可以卸 = false,
                _ => {
                    可以卸 = false;
                    见过失败 = true;
                }
            }
        }

        if 可以卸 {
            // 卸载必须收回：本节点收「已注册的通知」；端点已在上面的摘表中摘掉，
            // 此处不再放回即完成收回。
            return 派发结果::成功;
        }

        // 拒绝卸载：端点原样放回，通道状态与卸载前逐条一致。
        self.放回端点(摘下);
        if 见过失败 {
            派发结果::失败
        } else {
            派发结果::请求延迟释放
        }
    }

    /// 把端点放回端点表。已在表里的标识串不再放第二次——
    /// 卸载期扩展若回手调过 `注册通知端点`，也不许把「标识串唯一」这条不变量破坏掉。
    fn 放回端点(&self, 端点集: Vec<通知端点>) {
        let mut 项表 = self.端点表.borrow_mut();
        for 端点 in 端点集 {
            let 已在 = 项表.iter().any(|已有| unsafe { 标识串相同(已有.标识串, 端点.标识串) });
            if !已在 {
                项表.push(端点);
            }
        }
    }
}

/// 比较两个 NUL 结尾的标识串是否相同。任一为空指针一律视为「不相同」。
///
/// # Safety
/// 两个非空指针都必须指向 NUL 结尾的字节串（契约：标识串 = 32 位十六进制 + NUL）。
unsafe fn 标识串相同(左串: *const u8, 右串: *const u8) -> bool {
    if 左串.is_null() || 右串.is_null() {
        return false;
    }
    let mut 位移: usize = 0;
    while 位移 < 标识串上限 {
        // SAFETY: 调用方保证两个指针都指向可读的 NUL 结尾字节串。
        let 左字节 = unsafe { *左串.add(位移) };
        // SAFETY: 同上。
        let 右字节 = unsafe { *右串.add(位移) };
        if 左字节 != 右字节 {
            return false;
        }
        if 左字节 == 0 {
            return true;
        }
        位移 += 1;
    }
    false
}
