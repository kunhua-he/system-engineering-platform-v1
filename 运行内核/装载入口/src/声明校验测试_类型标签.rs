//! 类型标签合法域的正反样本（A32 · A34）—— 从 `声明校验测试.rs` 拆出。
//!
//! **为什么单立一件**：判据 ⑲ 的单源文件硬数是 400 行（非落点件写的 1000）。
//!
//! 口径：`契约声明/格式说明.md` §四 定「扩展的类型从 `100` 起」、底座类型表由
//! `契约声明/类型声明/*.json` 唯一给出。合法域 **= 本声明类型表 ∪ 底座已登记标签
//! ∪ 通用复合标签**，**不按计数算**（旧口径「声明类型数 + 底座类型数」会把合法的 `100` 判出去）。
//!
//! 第三项「通用复合标签（`100`–`103`）」是 2026-10-14 补的：这四个号归扩展，但每份扩展
//! 各自声明同一批号（`项目文档/决策记录/2026-10-12_复合类型槽载荷裁决.md` §九）
//! ⇒ 一份扩展**只引用**这四个号也合法。

use super::*;
use crate::测试夹具::*;
use crate::判定::判定可装载;
use v1_contract::{参数信息, 数据槽, 类型标签, 命令信息, 常量信息, 常量排布, 数据类型信息};

/// **正向样本（A32 · 本声明自有标签 `100` 作返回类型）**：样本夹具的类型表就是一项、标签 `100`。
///
/// 修前必红：旧口径上界 = `声明类型数(1) + 底座类型数(9) = 10`，`100 >= 10` ⇒ 恒判
/// `声明不自洽` ⇒ **凡声明了标签 `100` 的合法扩展都载不进来**。
#[test]
fn 类型标签_声明自有标签100作返回类型即放行() {
    let mut 合成样例 = 合成样本();
    // 按位拷一份原命令（原数组随即被覆盖，不会双重释放），只把 `返回类型` 改成 100。
    let 旧命令 = unsafe { core::ptr::read(合成样例.命令表.项表) };
    let 改后命令 = Box::leak(Box::new([命令信息 { 返回类型: 类型标签::构造(100), ..旧命令 }]));
    合成样例.命令表 = 表段::构造(改后命令.as_ptr(), 1);
    assert_eq!(判定可装载(钉住(合成样例), &标准台账()), Ok(()));
}

