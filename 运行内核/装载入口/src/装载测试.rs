#[test]
fn 载入_判定不过就不建表() {
    let mut 样本 = 合样本();
    样本.声明格式号 = 0;
    // 判定第一关就拦下 ⇒ 不会走到 注册表::建表。
    assert!(matches!(
        载入(钉(样本), &标准台账()),
        Err(载入错误::格式号不匹配 { .. })
    ));
}

#[test]
fn 载入_台账冲突也拦下() {
    // 证明 载入 真的把台账透传进判定：号段撞底座 ⇒ 在判定阶段就返回，不去建表。
    let mut 样本 = 合样本();
    样本.能力号段 = 钉段表(&[号段::新(0, 999)]);
    assert!(matches!(
        载入(钉(样本), &标准台账()),
        Err(载入错误::号段冲突 { 起: 0, 止: 999 })
    ));
}

#[test]
fn 载入_判定通过后交给建表() {
    // 判定全过 ⇒ 载入必须把声明交给 注册表::建表，且**不许**在判定阶段返回 Err。
    //
    // 统一注册表::建表 是本 crate 之外的节点，可能还在别人的手上（骨架期）。
    // 故用 catch_unwind 承接「建表 尚未实现」那一处；但**只容忍**那一处：
    // 若载入 自己崩了（越界 / unwrap 之类），仍然算失败。
    let 声明 = 钉(合样本());
    let 台账 = 标准台账();
    let 结果 = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| 载入(声明, &台账)));
    match 结果 {
        Ok(Ok(_)) => {}
        Ok(Err(载入错误::建表(_))) => {}
        Ok(Err(其它)) => panic!("判定已全过，载入不该在判定阶段失败：{其它:?}"),
        Err(载荷) => {
            let 文本 = 载荷
                .downcast_ref::<&str>()
                .map(|文本| (*文本).to_string())
                .or_else(|| 载荷.downcast_ref::<String>().cloned())
                .unwrap_or_default();
            assert!(
                文本.contains("not yet implemented"),
                "载入 在判定通过后崩了，且不是「建表 尚未实现」那一处：{文本}"
            );
        }
    }
}
