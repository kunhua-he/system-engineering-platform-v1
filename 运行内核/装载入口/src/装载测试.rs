#[test]
fn 台账_能力与通知两个命名空间分开记() {
    // 一份只占**通知**号段 (1000,1999) 的声明：登记后，
    // 能力账里不该有它，通知账里该有它 —— 两个命名空间不交叉。
    let 声明 = 钉住({
        let mut 合成样例 = 合成样本();
        合成样例.能力号段 = 表段::空实例();
        合成样例.通知号段 = 钉段表(&[号段::构造(1000, 1999)]);
        合成样例
    });
    let mut 台账 = 载入台账::空实例();
    台账.登记标识串(声明);
    assert!(
        !台账.号段已占用(号段空间::能力号, 1000.into(), 1999.into()),
        "能力账不该被通知号段污染"
    );
    assert!(
        台账.号段已占用(号段空间::通知号, 1000.into(), 1999.into()),
        "通知账该记下这段"
    );
}

