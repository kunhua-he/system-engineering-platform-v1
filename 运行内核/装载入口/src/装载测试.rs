#[test]
fn 载入_判定通过后交给建表() {
    // 判定全过 ⇒ 载入必须把声明交给 注册表::建表，且**不许**在判定阶段返回 Err。
    //
    // 统一注册表::建表 是本 crate 之外的节点，可能还在别人的手上（骨架期）。
    // 故用 catch_unwind 承接「建表 尚未实现」那一处；但**只容忍**那一处：
    // 若载入 自身崩了（越界 / unwrap 之类），仍然算失败。
    let 声明 = 钉住(合成样本());
    let 台账 = 标准台账();
    let 调用读数 = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| 载入声明(声明, &台账)));
    match 调用读数 {
        Ok(Ok(_)) => {}
        Ok(Err(载入错误::建表(_))) => {}
        Ok(Err(其余值)) => panic!("判定已全过，载入不该在判定阶段失败：{其余值:?}"),
        Err(载荷) => {
            let 源文本 = 载荷
                .downcast_ref::<&str>()
                .map(|源文本| (*源文本).to_string())
                .or_else(|| 载荷.downcast_ref::<String>().cloned())
                .unwrap_or_default();
            assert!(
                源文本.contains("not yet implemented"),
                "载入 在判定通过后崩了，且不是「建表 尚未实现」那一处：{源文本}"
            );
        }
    }
}
