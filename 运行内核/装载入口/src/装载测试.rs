/// 一张只含一项、指定 `类型标签` 的类型表（跨声明类型标签占用的样本用；
/// 命令个数 0 ⇒ 不引出「命令无人认领」以外的自洽问题）。
fn 类型表带标签(标签: u32) -> 表段<数据类型信息> {
    let 类型表 = Box::leak(
        vec![数据类型信息 {
            名称: 静态串("跨声明类型\0"),
            说明: 静态串("跨声明类型标签占用样本。\0"),
            状态位: 0,
            命令个数: 0,
            命令号表: core::ptr::null(),
            事件个数: 0,
            事件表: core::ptr::null(),
            属性个数: 0,
            属性表: core::ptr::null(),
            元素个数: 0,
            元素表: core::ptr::null(),
            类型标签: 类型标签::构造(标签),
        }]
        .into_boxed_slice(),
    );
    表段::构造(类型表.as_ptr(), 1)
}

