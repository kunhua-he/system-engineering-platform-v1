#[test]
fn 台账_预置底座后占0xxx即冲突() {
    // 台账预置了底座自占的 0..999；扩展再声明 0..999 ⇒ 撞底座。
    let mut 合成样例 = 合成样本();
    合成样例.能力号段 = 钉段表(&[号段::构造(0, 999)]);
    assert_eq!(
        判定可装载(钉住(合成样例), &标准台账()),
        Err(载入错误::号段冲突 { 段起点: 0, 段止: 999 })
    );
}

