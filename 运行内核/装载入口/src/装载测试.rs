#[test]
fn 台账_扩展占能力2000到2999不与底座的通知段冲突() {
    // 底座占的是**通知** 2000–2999；扩展占**能力** 2000–2999 是另一个空间，合法。
    // 这条是「不许把两个空间取并集」的回归判据：并集实现会在这里报假冲突。
    // 换号段得用 `合成样本占号段`：命令编号随之取新号段的 `起`，否则会先撞上
    // 「编号必须落在本声明申报的能力号段内」那条门（裁决 5）。
    let mut 合成样例 = 合成样本占号段(号段::构造(2000, 2999));
    合成样例.通知号段 = 表段::空实例();
    assert_eq!(判定可装载(钉住(合成样例), &标准台账()), Ok(()));
}

#[test]
fn 台账_生命周期通知段是广播段可被扩展申报() {
    // ④：扩展申报**生命周期通知号段** [2000,2999]（与底座预置的占用同段）
    // 必须载得进来 —— 它是宿主向每个已注册端点广播的号，不是独占号位。
    // 旧行为：这里会被底座预置的通知 2000–2999 判 `号段冲突`，任何扩展都申报不了。
    // **2026-10-07 收紧闭集**：广播段上界 = 已登记号的最大者（今 2015）⇒ 申报写 `[2000, 2015]`
    //（旧写法 `[2000,2999]` 现已不再豁，回落按独占号位判 ⇒ 号段冲突）。
    let mut 合成样例 = 合成样本();
    合成样例.通知号段 = 钉段表(&[号段::构造(2000, 2015)]);
    合成样例.通知函数 = Some(占位通知);
    assert_eq!(判定可装载(钉住(合成样例), &标准台账()), Ok(()));
}

