use crate::依赖校验::依赖清单合法;
use crate::声明校验::{判不与作废号冲突, 判号段表, 判声明自洽, 号段表名};
use crate::标签登记::底座已登记标签;
use crate::读数::{号段切片, 标识串字节数, 是合法标识串, 读串};
use crate::错误::载入错误;
use v1_contract::{号段空间, 已载入台账, 平台信息, 版本三元组, 通知号段};

/// 底座提供的**宿主**版本。扩展声明里的「要求宿主版本」按它判（④）。
/// 源：`契约声明/平台声明.json.提供宿主版本`。
pub const 底座宿主版本: 版本三元组 = v1_contract::声明数据::底座提供宿主版本;

/// 底座提供的**内核**版本。扩展声明里的「要求内核版本」按它判（④）。
/// 源：`契约声明/平台声明.json.提供内核版本`。
pub const 底座内核版本: 版本三元组 = v1_contract::声明数据::底座提供内核版本;

/// 判定六步：只判不载。给验证面用，也给载入前预检用。
///
/// 顺序与判据严格按 `扩展装载与开发标准.md` 2.3：
/// ①格式号 → ②标识串 → ③号段 → ④要求版本 → ⑤依赖 → ⑥自洽。
/// **任一步不过即返回 `Err`，不触碰任何状态**（不是崩溃，也不是半载）。
///
/// `台账` 是调用方显式持有的已载入台账（`&dyn 已载入台账`）：②标识串唯一、
/// ③号段不冲突、⑤依赖都在，三项都真的走它，不许绕过。
pub fn 判定可装载(声明: &平台信息, 台账: &dyn 已载入台账) -> Result<(), 载入错误> {
    // ── ① 声明格式号匹配 ──────────────────────────────────────────────
    if 声明.声明格式号 != v1_contract::声明格式号 {
        return Err(载入错误::声明格式号不匹配 {
            期望: v1_contract::声明格式号.取号值(),
            实际: 声明.声明格式号.取号值(),
        });
    }

    // ── ② 标识串非空且唯一 ───────────────────────────────────────────
    // 形状：32 位十六进制 + NUL（契约主结构注释）。空指针 / 空串 / 长度不符 / 非十六进制
    // 一律非法；另：**不得冒用底座身份**，且**不得与台账里已载入的身份重名**。
    let 标识串 = unsafe { 读串(声明.标识串, 标识串字节数 + 1) };
    let Some(标识串) = 标识串 else {
        return Err(载入错误::标识串非法);
    };
    if !是合法标识串(标识串) {
        return Err(载入错误::标识串非法);
    }
    if !是底座自有声明(声明) && 标识串 == v1_contract::声明数据::底座标识串内容 {
        // 同一身份不能有两个主人。
        return Err(载入错误::标识串非法);
    }
    if 台账.是否已载入(声明.标识串) {
        // 跨扩展唯一：台账里已经有这个身份了。
        return Err(载入错误::标识串非法);
    }

    // ── ③ 号段不冲突 ─────────────────────────────────────────────────
    // 号段由声明**直接给出**（`能力号段` / `通知号段` 两张独立表）。
    // 两张表分开判：能力号段与通知号段是两个独立命名空间（`格式说明.md` 第二节），
    // 同一份声明里这两张表之间不交叉比对。
    判号段表(声明.能力号段, 号段表名::能力号段名)?;
    判号段表(声明.通知号段, 号段表名::通知号段名)?;
    // 与作废号表冲突（号只增不复用）：作废号是能力编号，故只对能力空间判，
    // 且**逐条命令编号精确比**（不整段封）。
    判不与作废号冲突(声明)?;
    // 类型标签按**离散标签**比对（不借号段区间语义）。**底座自身的标签（0–99）由
    // `声明校验.rs::底座已登记标签`（A34）另行把关**，此处只管跨声明占用。
    //
    // ★ 故底座已登记的标签**跳过**：`载入台账::构造` 会把底座自身的类型表也收进账
    //（它预置底座占用），若不跳过，一份复用底座标签的扩展会在 ③ 先报 `号段冲突`，
    // 把 ⑥ 的 A34 闸（更具体的 `类型标签与已登记重复`）抢掉 —— 而 A34 已裁底座标签归它把关。
    // 本处只扫**非底座已登记**的标签：重复占用由 ③ 报、复用底座标签由 ⑥ 报，各归各位。
    for 类型序 in 0..声明.类型表.表项数 as usize {
        // SAFETY: ⑥ `判声明自洽` 会判「类型表项数 > 0 则项表非空」；此处先扫，
        // 用 `声明.类型表.项表.is_null()` 兜住（项数 > 0 却空指针 = 声明不自洽，交给 ⑥ 报）。
        if 声明.类型表.项表.is_null() {
            break;
        }
        let 标签 = unsafe { (*声明.类型表.项表.add(类型序)).类型标签 };
        if 底座已登记标签(标签.取号值()) {
            continue;
        }
        // ★ **通用复合标签（100–103）是共享标签**：`契约声明/号段图.json` 的 `类型号段` 把
        //   它们留在扩展段，但每个扩展**各自声明同一批号**（`元素表` 记该扩展各能力的返回字段）
        //   —— 见 `项目文档/决策记录/2026-10-12_复合类型槽载荷裁决.md` §九「平台不拥有这四个号」
        //   ⇒ 多份声明同报这四个号**不算冲突**。不跳过就会把第二个扩展拦在 ③
        //   （实测 `号段冲突 { 段起点: 100, 段止: 100 }`）。
        //   判据 = `v1_contract::复合值载荷::是通用复合标签`（唯一来源），本件不写死号，
        //   与「生命周期通知段按广播段判」同一先例。
        if v1_contract::复合值载荷::是通用复合标签(标签.取号值()) {
            continue;
        }
        if 台账.类型标签已占用(标签) {
            return Err(载入错误::号段冲突 { 段起点: 标签.取号值(), 段止: 标签.取号值() });
        }
    }
    // 与已载入台账冲突：能力号段、通知号段各按自身的**空间**比对，不交叉。
    for 号段项 in 号段切片(声明.能力号段) {
        if 台账.号段已占用(号段空间::能力号, 号段项.段起点, 号段项.段止) {
            return Err(载入错误::号段冲突 { 段起点: 号段项.段起点.取号值(), 段止: 号段项.段止.取号值() });
        }
    }
    for 号段项 in 号段切片(声明.通知号段) {
        // 生命周期段是**广播段**：装载/卸载/退出由宿主广播给每个已注册端点
        // （`载入判定.json`「热载入与热卸载」），可被多份声明共同申报，与台账不判冲突
        // ——否则底座预置的通知 2000–2999 会把每一份扩展都拦下（
        // 已裁：`项目文档/决策记录/2026-09-27_生命周期通知段按广播段判.md`）。
        if 生命周期广播段(号段项.段起点.取号值(), 号段项.段止.取号值()) {
            continue;
        }
        if 台账.号段已占用(号段空间::通知号, 号段项.段起点, 号段项.段止) {
            return Err(载入错误::号段冲突 { 段起点: 号段项.段起点.取号值(), 段止: 号段项.段止.取号值() });
        }
    }

    // ── ④ 要求宿主版本 / 要求内核版本满足 ───────────────────────────
    if !底座宿主版本.满足(&声明.要求宿主版本) {
        return Err(载入错误::要求版本不满足 {
            要求: 声明.要求宿主版本.主版本,
            实际: 底座宿主版本.主版本,
        });
    }
    if !底座内核版本.满足(&声明.要求内核版本) {
        return Err(载入错误::要求版本不满足 {
            要求: 声明.要求内核版本.主版本,
            实际: 底座内核版本.主版本,
        });
    }

    // ── ⑤ 依赖清单里的扩展都在 ──────────────────────────────────────
    // 三项一起判：清单本身合法（形状 · 不重复 · 不含自依赖）、且每个依赖都在台账里。
    if !依赖清单合法(声明, 标识串, 台账) {
        return Err(载入错误::依赖缺失);
    }

    // ── ⑥ 声明自洽 ──────────────────────────────────────────────────
    // 申报通知号段 ⇒ 通知函数必须非空（照参照实现 `LIB_INFO.m_pfnNotify` 的「不能为NULL」，
    // `sdk/cpp/elib/lib2.h` 的 `m_pfnNotify`）——申报了收不到，与 载入判定.json
    // 「申报生命周期段即表示接收」相反。不过时走**既有** `声明不自洽`（**不引新码**：
    // 段位 0 下一空号 `0034` 已被别的裁决预留，不许复用）。
    判通知申报自洽(声明)?;
    判声明自洽(声明)
}

/// ⑥ 申报通知号段 ⇒ 通知函数必须非空。
///
/// 依据：参照实现 `LIB_INFO.m_pfnNotify` 注释「**不能为NULL**」
///（`sdk/cpp/elib/lib2.h` 的 `m_pfnNotify` 注释「不能为NULL」），krnln 装载器的跳过分支里
/// 就有 `pfnNotify != 0` 这一条；`载入判定.json` 步 3 又写「申报生命周期段即表示接收」
/// ⇒ 申报了却给 None，等于声明与实现不一致（号段即归属，收不到就不该申报）。
///
/// **不引新码**（收口方裁 2026-10-07）：段位 0 下一空号 `0034` 已被别的裁决预留（不许复用），
/// 故不过时走**既有** `声明不自洽` 变体（与本节其它闸同形，零新码、不改错误码表）。
fn 判通知申报自洽(声明: &平台信息) -> Result<(), 载入错误> {
    if 声明.通知号段.表项数 > 0 && 声明.通知函数.is_none() {
        return Err(载入错误::声明不自洽 { 命令号: v1_contract::能力号::构造(0) });
    }
    Ok(())
}

/// 已登记生命周期通知号的**上界**（闭集收紧）：取生成物 `v1_contract::声明数据::通知号表`
/// 里落在生命周期段的号的最大者 —— **值只有一个来源**（源：`契约声明/通知号段/*.json`），
/// 不另抄一份常量。同日新号登记后本上界自动前移，判定不必改。
///
/// 为什么要上界：旧实现只判「整段落在 2000–2999」⇒ 段内**未登记号**（如 2016–2999）
/// 也进广播豁免，是**静默放行**。参照实现 `ITL_*` 的编号空间是**闭集**，号域窄
/// 且加上界检查，一个号**不是** ITL 号可证；
/// 本处以「已登记号的上界」给出同一条否证：段止越过上界 ⇒ 不是生命周期广播号。
pub(crate) fn 生命周期上界() -> u32 {
    v1_contract::声明数据::通知号表
        .iter()
        .copied()
        .filter(|通知号| (通知号段::生命周期起..=通知号段::生命周期止).contains(通知号))
        .max()
        .unwrap_or(通知号段::生命周期起)
}

/// 这段通知号是不是**已登记生命周期号**范围内的（闭集与上界，两者一起判）。
///
/// 广播段 = 宿主向每个已注册端点广播的号（装载/卸载/退出），**可被多份声明共同申报**
/// ——不是独占号位。下界取生成物 `v1_contract::通知号段`，上界取 `生命周期上界()`
/// （已登记号的最大者，今 = 2015）⇒ 2016–2999 这些**未登记号**不再进豁免，
/// 回落按独占号位判（撞底座预置 ⇒ 号段冲突）。
///
/// 判据与代价见本文件头「③ 的通知空间：生命周期段是**广播段**（已裁 2026-09-27）」。
fn 生命周期广播段(区间起点: u32, 区间终点: u32) -> bool {
    区间起点 >= 通知号段::生命周期起 && 区间终点 <= 生命周期上界()
}

