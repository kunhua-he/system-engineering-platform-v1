//! 判定六步：只判不载。给验证面用，也给载入前预检用。
//!
//! 顺序与判据严格按 `扩展装载与开发标准.md` 2.3：
//! ①格式号 → ②标识串 → ③号段 → ④要求版本 → ⑤依赖 → ⑥自洽。
//! **任一步不过即返回 `Err`，不触碰任何状态**（不是崩溃，也不是半载）。
//!
//! 本文件另放「底座自身的版本」（判定 ④ 的据）：**值一律取自生成物**
//! （`v1_contract::声明数据`，源 = `契约声明/*.json`）。这里只留名字，不再手写数值
//! ——手写一份就是同一事实的第二来源。
//!
//! # ③ 的通知空间：生命周期段是**广播段**（已裁 2026-09-27）
//!
//! `载入台账::新()` 预置了底座占用的通知 `2000–2999` ⇒ 任何扩展都申报不了
//! 生命周期通知号段，而同一份 `载入判定.json` 又要求扩展能收生命周期通知并回 `2015`。
//! **已裁：按广播段判**（`项目文档/决策记录/2026-09-27_生命周期通知段按广播段判.md`）：
//! 生命周期段（契约 `通知号段::生命周期起..=生命周期止`）是宿主向**每个**已注册端点
//! **广播**的号，不是谁独占的号位 ⇒ 「声明接收生命周期通知」与台账**不判冲突**。
//! 广播段之外的号（下行 1–999 · 上行 1000–1999）仍按独占号位判，fail-closed 不变。
//! 另一条路「给扩展留一段号位」单独也解决不了：扩展要收的正是 `2000/2001/2002/2003`
//! 这几个**具体号**，且要动冻结件 `契约声明/平台声明.json` 与底座 `通知函数`。

use crate::底座静态声明::是底座自有声明;
use crate::声明校验::{判不与作废号冲突, 判号段表, 判声明自洽, 号段表名, 依赖清单合法};
use crate::读数::{号段切片, 标识串字节数, 是合法标识串, 读串};
use crate::错误::载入错误;
use v1_contract::{号段空间, 已载入台账, 平台信息, 版本三元组, 通知号段};

/// 底座提供的**宿主**版本。扩展声明里的「要求宿主版本」按它判（④）。
/// 源：`契约声明/平台声明.json.提供宿主版本`。
pub const 底座宿主版本: 版本三元组 = v1_contract::声明数据::底座提供宿主版本;

/// 底座提供的**内核**版本。扩展声明里的「要求内核版本」按它判（④）。
/// 源：`契约声明/平台声明.json.提供内核版本`。
pub const 底座内核版本: 版本三元组 = v1_contract::声明数据::底座提供内核版本;

/// 判定六步：只判不载。给验证面用，也给载入前预检用。
///
/// 顺序与判据严格按 `扩展装载与开发标准.md` 2.3：
/// ①格式号 → ②标识串 → ③号段 → ④要求版本 → ⑤依赖 → ⑥自洽。
/// **任一步不过即返回 `Err`，不触碰任何状态**（不是崩溃，也不是半载）。
///
/// `台账` 是调用方显式持有的已载入台账（`&dyn 已载入台账`）：②标识串唯一、
/// ③号段不冲突、⑤依赖都在，三项都真的走它，不许绕过。
pub fn 判定可装载(声明: &平台信息, 台账: &dyn 已载入台账) -> Result<(), 载入错误> {
    // ── ① 声明格式号匹配 ──────────────────────────────────────────────
    if 声明.声明格式号 != v1_contract::声明格式号 {
        return Err(载入错误::声明格式号不匹配 {
            期望: v1_contract::声明格式号,
            实际: 声明.声明格式号,
        });
    }

    // ── ② 标识串非空且唯一 ───────────────────────────────────────────
    // 形状：32 位十六进制 + NUL（契约主结构注释）。空指针 / 空串 / 长度不符 / 非十六进制
    // 一律非法；另：**不得冒用底座身份**，且**不得与台账里已载入的身份重名**。
    let 标识串 = unsafe { 读串(声明.标识串, 标识串字节数 + 1) };
    let Some(标识串) = 标识串 else {
        return Err(载入错误::标识串非法);
    };
    if !是合法标识串(标识串) {
        return Err(载入错误::标识串非法);
    }
    if !是底座自有声明(声明) && 标识串 == v1_contract::声明数据::底座标识串内容 {
        // 同一身份不能有两个主人。
        return Err(载入错误::标识串非法);
    }
    if 台账.是否已载入(声明.标识串) {
        // 跨扩展唯一：台账里已经有这个身份了。
        return Err(载入错误::标识串非法);
    }

    // ── ③ 号段不冲突 ─────────────────────────────────────────────────
    // 号段由声明**直接给出**（`能力号段` / `通知号段` 两张独立表）。
    // 两张表分开判：能力号段与通知号段是两个独立命名空间（`格式说明.md` 第二节），
    // 同一份声明里这两张表之间不交叉比对。
    判号段表(声明.能力号段, 号段表名::能力)?;
    判号段表(声明.通知号段, 号段表名::通知)?;
    // 与作废号表冲突（号只增不复用）：作废号是能力编号，故只对能力空间判，
    // 且**逐条命令编号精确比**（不整段封）。
    判不与作废号冲突(声明)?;
    // 与已载入台账冲突：能力号段、通知号段各按自身的**空间**比对，不交叉。
    for 段 in 号段切片(声明.能力号段) {
        if 台账.号段已占用(号段空间::能力号, 段.起, 段.止) {
            return Err(载入错误::号段冲突 { 起: 段.起.取(), 止: 段.止.取() });
        }
    }
    for 段 in 号段切片(声明.通知号段) {
        // 生命周期段是**广播段**：装载/卸载/退出由宿主广播给每个已注册端点
        // （`载入判定.json`「热载入与热卸载」），可被多份声明共同申报，与台账不判冲突
        // ——否则底座预置的通知 2000–2999 会把每一份扩展都拦下（
        // 已裁：`项目文档/决策记录/2026-09-27_生命周期通知段按广播段判.md`）。
        if 生命周期广播段(段.起.取(), 段.止.取()) {
            continue;
        }
        if 台账.号段已占用(号段空间::通知号, 段.起, 段.止) {
            return Err(载入错误::号段冲突 { 起: 段.起.取(), 止: 段.止.取() });
        }
    }

    // ── ④ 要求宿主版本 / 要求内核版本满足 ───────────────────────────
    if !底座宿主版本.满足(&声明.要求宿主版本) {
        return Err(载入错误::要求版本不满足 {
            要求: 声明.要求宿主版本.主,
            实际: 底座宿主版本.主,
        });
    }
    if !底座内核版本.满足(&声明.要求内核版本) {
        return Err(载入错误::要求版本不满足 {
            要求: 声明.要求内核版本.主,
            实际: 底座内核版本.主,
        });
    }

    // ── ⑤ 依赖清单里的扩展都在 ──────────────────────────────────────
    // 三项一起判：清单本身合法（形状 · 不重复 · 不含自依赖）、且每个依赖都在台账里。
    if !依赖清单合法(声明, 标识串, 台账) {
        return Err(载入错误::依赖缺失);
    }

    // ── ⑥ 声明自洽 ──────────────────────────────────────────────────
    判声明自洽(声明)
}

/// 这段通知号是不是**生命周期广播段**里的（契约布局 `2000–2999`）。
///
/// 广播段 = 宿主向每个已注册端点广播的号（装载/卸载/退出），**可被多份声明共同申报**
/// ——不是独占号位。范围取生成物 `v1_contract::通知号段`（唯一来源），不另抄一份常量。
/// 判据与代价见本文件头「③ 的通知空间：生命周期段是**广播段**（已裁 2026-09-27）」。
///
/// 这里判「**整段落在**广播段内」，不是「与广播段相交」。两者在本处等价，且理由在结构上：
/// `判号段表`（③ 的前一步）要求每个通知号段都落在同一个**号段类**里（`段.起 / 号段类宽度`
/// == `段.止 / 号段类宽度`，宽度 1000），而广播段 `2000–2999` 恰好就是号段类 `2` 整段
/// ⇒ 一个通知号段要么整段在里面、要么整段在外面，不存在「只压到一半」的中间态。
fn 生命周期广播段(起: u32, 止: u32) -> bool {
    起 >= 通知号段::生命周期起 && 止 <= 通知号段::生命周期止
}

