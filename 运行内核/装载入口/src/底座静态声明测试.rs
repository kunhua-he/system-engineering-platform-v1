//! `底座静态声明` 的单元测试：唯一导出符号的形状 · 底座执行函数 · 底座通知函数。

use super::*;
use crate::测试夹具::串读取上限;
use crate::声明校验::读段位表;
use crate::读数::{号段切片, 标识串字节数, 是合法标识串, 读串};
use v1_contract::号段;

#[test]
fn 导出符号_返回底座静态声明且形状完整() {
    let 指针 = 取平台信息();
    assert!(!指针.is_null());
    // SAFETY: 指针指向底座自己的静态声明，终生有效。
    let 声明 = unsafe { &*指针 };

    assert_eq!(声明.声明格式号, v1_contract::声明格式号);
    assert_eq!(声明.目标字宽, 64);
    assert!(core::ptr::eq(声明, 底座声明()));

    // 形状完整：**8 个内置类型**（生成物按 `契约声明/类型声明/*.json` 全量给：
    // 空 · 整数 · 双精度 · 逻辑 · 文本 · 字节集 · 句柄 · 错误）· 1 条命令 · 1 个常量 ·
    // 函数表与命令表一一对应。
    assert_eq!(声明.类型表.项数, 8);
    assert!(!声明.类型表.项表.is_null());
    assert_eq!(声明.命令表.项数, 1);
    assert!(!声明.命令表.项表.is_null());
    assert!(!声明.函数表.is_null());
    assert_eq!(声明.常量表.项数, 1);
    assert!(!声明.常量表.项表.is_null());
    assert!(声明.通知函数.is_some());
    assert_eq!(声明.依赖清单.项数, 0);
    // 错误码表：生成物给**全部登记码**——「失败可编程处理」的落点。
    // 项数不写死：源（`契约声明/错误码表/*.json`）是活的，写死就成第二来源。
    assert_eq!(
        声明.错误码表.项数 as usize,
        v1_contract::声明数据::错误码信息表.len()
    );
    assert!(!声明.错误码表.项表.is_null());
    assert!(声明.错误码表.项数 > 0);

    // 标识串：32 位十六进制 + NUL。
    // SAFETY: 底座标识串是静态只读的 NUL 结尾串。
    let 标识串 = unsafe { 读串(声明.标识串, 标识串字节数 + 1) }.expect("标识串可读");
    assert_eq!(标识串.len(), 标识串字节数);
    assert!(是合法标识串(标识串));

    // 名称 / 说明非空。
    // SAFETY: 同上，均为静态只读 NUL 结尾串。
    assert!(
        !unsafe { 读串(声明.名称, 串读取上限) }
            .expect("名称可读")
            .is_empty()
    );
    assert!(
        !unsafe { 读串(声明.说明, 串读取上限) }
            .expect("说明可读")
            .is_empty()
    );

    // 底座自占的号段：能力 0..999（内核自有）· 通知 2000..2999（生命周期）。
    // 号段由声明**直接给出**，不再从三张表的项数反推。
    let 能力 = 号段切片(声明.能力号段);
    assert_eq!(能力, [号段::新(0, 999)].as_slice());
    let 通知 = 号段切片(声明.通知号段);
    assert_eq!(通知, [号段::新(2000, 2999)].as_slice());
    // 错误段位表：段位 0 是底座自有（码 1–999）；段位 9 是「接口面与构建验证」
    //（`号段图.json` 划的归属），码 9001–9007 见 `契约声明/错误码表/`。
    assert_eq!(读段位表(声明.错误段位表).expect("段位表可读"), [0u32, 9].as_slice());
}

#[test]
fn 底座执行函数_把平台信息放进返回槽() {
    let mut 槽 = 数据槽::空槽();
    // SAFETY: 占位执行函数按契约形状调用；参数个数 0，参数表空。
    unsafe { 底座取平台信息(&mut 槽, 0, core::ptr::null()) };
    assert!(槽.是否引用());
    assert!(!槽.交出了所有权());
    assert_eq!(槽.长度, core::mem::size_of::<平台信息>() as u64);
    assert_eq!(槽.值, 取平台信息() as u64);
}

#[test]
fn 底座通知_只接受自己声明的那一段() {
    // 底座声明只占通知号段 2000–2999（生命周期）；段内成功、段外失败。
    // SAFETY: 按契约形状调用。
    unsafe {
        assert_eq!(底座通知(2000, 0, 0), 通知返回::成功);
        assert_eq!(底座通知(2998, 0, 0), 通知返回::成功);
        assert_eq!(底座通知(2999, 0, 0), 通知返回::成功);
        assert_eq!(底座通知(3000, 0, 0), 通知返回::失败);
        assert_eq!(底座通知(1999, 0, 0), 通知返回::失败);
        assert_eq!(底座通知(0, 0, 0), 通知返回::失败);
    }
}

#[test]
fn 底座通知_声明之外的方向段也一律不收() {
    // **反向样本**：底座只声明了生命周期段（2000–2999）。
    // 下行（1–999）与上行（1000–1999）是别的方向的段，底座**不许**照收——
    // 声明之外的号也回「成功」，就是声明与实现不一致（旧实现正是三段全收）。
    // SAFETY: 按契约形状调用。
    unsafe {
        assert_eq!(底座通知(1, 0, 0), 通知返回::失败, "下行段不许照收");
        assert_eq!(底座通知(999, 0, 0), 通知返回::失败, "下行段不许照收");
        assert_eq!(底座通知(1000, 0, 0), 通知返回::失败, "上行段不许照收");
        assert_eq!(底座通知(1999, 0, 0), 通知返回::失败, "上行段不许照收");
        // 直接对照：声明的那一段仍收。
        assert_eq!(底座通知(2000, 0, 0), 通知返回::成功);
    }
}
