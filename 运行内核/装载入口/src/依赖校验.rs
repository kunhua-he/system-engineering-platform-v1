//! 依赖校验 —— 判定 ⑤ 的零件：依赖清单与依赖版本要求（两张表按下标一一对应）。
//!
//! **为什么单独一件**：这两张表判的是「**跨声明**的事实」（依赖在不在 · 那一份版本够不够），
//! 与 `声明校验` 判的「声明自身站不站得住」不是一回事；判定 ⑤ 只调这一件。

use crate::读数::{标识串字节数, 是合法标识串, 读串};
use v1_contract::{已载入台账, 平台信息};

/// 依赖清单的项数上限（防呆：超过就当声明不自洽）。
///
/// 与 `参数个数上限` 同一量级：项数是声明里的 `u32`，拿去逐个解引用依赖项 ——
/// 没有上限时一份坏声明就是一条精确的越界路（底座与扩展同进程、`panic = "abort"`）。
const 依赖清单上限: usize = 256;

/// ⑤ 依赖清单是否合法 + **每一条依赖的版本是否满足要求**。
///
/// 逐项五问：形状（NUL 结尾的 32 位十六进制标识串）· 不重复 · 不含自身 · 在台账里 ·
/// **台账里那一份的 `实现版本` 满足 `依赖版本要求` 第 i 项**。
///
/// **两张表按下标一一对应**：第 i 项要求说的是 `依赖清单` 第 i 项那份依赖。
/// 项数不等或要求表形状不可用 ⇒ 直接不过（错位是静默的，比崩溃更坏）。
///
/// 不过一律报 `载入错误::依赖缺失`（**不引新码**）：对调用方而言「依赖不在」与
/// 「依赖在但版本不够」是同一条出路 —— 换一份能用的依赖，或把那一份升上去。
/// 版本够不够比的是 `版本三元组::满足`（提供方拿要求当门槛）。
pub(crate) fn 依赖清单合法(声明: &平台信息, 自身: &[u8], 台账: &dyn 已载入台账) -> bool {
    let 表项数 = 声明.依赖清单.表项数;
    if 表项数 == 0 {
        // 空清单 = 「不依赖任何东西」；此时要求表也必须空（项数相等由建表与下面这一句一起守）。
        return 声明.依赖版本要求.表项数 == 0;
    }
    if 声明.依赖清单.项表.is_null() || 声明.依赖版本要求.项表.is_null() {
        return false;
    }
    if 表项数 as usize > 依赖清单上限 || 声明.依赖版本要求.表项数 != 表项数 {
        return false;
    }
    let mut 已见: [*const u8; 依赖清单上限] = [core::ptr::null(); 依赖清单上限];
    for 序号 in 0..表项数 as usize {
        // SAFETY: 项数 > 0 且两张表的项表都非空，序号 < 项数。
        let 依赖项 = unsafe { *声明.依赖清单.项表.add(序号) };
        let 要求项 = unsafe { *声明.依赖版本要求.项表.add(序号) };
        // SAFETY: 依赖项按契约是静态只读的 NUL 结尾标识串。
        let Some(字节串) = (unsafe { 读串(依赖项, 标识串字节数 + 1) }) else {
            return false;
        };
        if !是合法标识串(字节串) || 字节串 == 自身 {
            return false;
        }
        // 版本比对的**唯一**入口：台账答「已载入的那一份是什么版本」，`无` = 没载入。
        let Some(实际版本) = 台账.已载入版本(依赖项) else {
            return false; // 依赖不在台账里 ⇒ 依赖缺失
        };
        if !实际版本.满足(&要求项) {
            return false; // 依赖在，但那一份的版本低于要求 ⇒ 同一条出路
        }
        if 已见[..序号].contains(&依赖项) {
            return false; // 重复依赖：清单不自洽
        }
        已见[序号] = 依赖项;
    }
    true
}
