//! 依赖校验 —— 判定 ⑤ 的零件：依赖清单与依赖版本要求（两张表按下标一一对应）。
//!
//! **为什么单独一件**：这两张表判的是「**跨声明**的事实」（依赖在不在 · 那一份版本够不够），
//! 与 `声明校验` 判的「声明自身站不站得住」不是一回事；判定 ⑤ 只调这一件。
//!
//! # 判据只有一份，两个入口共用
//!
//! 依赖清单有两种**写法**、同一种**事实**：① 平台信息的裸指针表（支持库那条路，静态声明）；
//! ② `包声明.json` 的文本表（模块那条路，声明侧是 JSON）。写法不同不改判据 ——
//! 四问（形状 · 不重复 · 不含自身 · 在台账里且版本够）只写在 [`依赖项表合法`] 一处，
//! [`依赖清单合法`] 与 [`依赖清单合法文本`] 各自只做「把表摊平」这一件事。

use std::ffi::CString;

use crate::读数::{标识串字节数, 是合法标识串, 读串};
use v1_contract::{已载入台账, 平台信息, 版本要求};

/// 依赖清单的项数上限（防呆：超过就当声明不自洽）。
///
/// 与 `参数个数上限` 同一量级：项数是声明里的 `u32`，拿去逐个解引用依赖项 ——
/// 没有上限时一份坏声明就是一条精确的越界路（底座与扩展同进程、`panic = "abort"`）。
const 依赖清单上限: usize = 256;

/// ⑤ 依赖清单是否合法 + **每一条依赖的版本是否满足要求**。
///
/// 逐项五问：形状（NUL 结尾的 32 位十六进制标识串）· 不重复 · 不含自身 · 在台账里 ·
/// **台账里那一份的 `实现版本` 满足 `依赖版本要求` 第 i 项**。
///
/// **两张表按下标一一对应**：第 i 项要求说的是 `依赖清单` 第 i 项那份依赖。
/// 项数不等或要求表形状不可用 ⇒ 直接不过（错位是静默的，比崩溃更坏）。
///
/// 不过一律报 `载入错误::依赖缺失`（**不引新码**）：对调用方而言「依赖不在」与
/// 「依赖在但版本不够」是同一条出路 —— 换一份能用的依赖，或把那一份升上去。
/// 版本够不够比的是 `版本三元组::满足`（提供方拿要求当门槛）。
pub(crate) fn 依赖清单合法(声明: &平台信息, 自身: &[u8], 台账: &dyn 已载入台账) -> bool {
    let 表项数 = 声明.依赖清单.表项数;
    if 表项数 == 0 {
        // 空清单 = 「不依赖任何东西」；此时要求表也必须空（项数相等由建表与下面这一句一起守）。
        return 声明.依赖版本要求.表项数 == 0;
    }
    if 声明.依赖清单.项表.is_null() || 声明.依赖版本要求.项表.is_null() {
        return false;
    }
    if 表项数 as usize > 依赖清单上限 || 声明.依赖版本要求.表项数 != 表项数 {
        return false;
    }
    // SAFETY: 项数 > 0 且两张表的项表都非空（上面已挡），长度 = 项数。
    let 依赖项表 = unsafe { core::slice::from_raw_parts(声明.依赖清单.项表, 表项数 as usize) };
    let 版本要求表 = unsafe { core::slice::from_raw_parts(声明.依赖版本要求.项表, 表项数 as usize) };
    依赖项表合法(自身, 依赖项表, 版本要求表, 台账)
}

/// 依赖清单的**文本入口** —— `包声明.json` 那条路（模块的声明侧是 JSON 文本，不是裸指针表）。
///
/// 判据与裸指针入口**同一份**（[`依赖项表合法`]）：本函数只把文本摊成同一形状的表。
/// 台账那两问要的是 NUL 结尾的静态串读法 ⇒ 文本侧先按同一形状（32 位十六进制 + NUL）落串。
///
/// 空清单 = 「不依赖任何东西」，此时要求表也必须空（与裸指针入口同一条）。
/// 自身标识串或任一依赖项不是 32 位十六进制 ⇒ 直接不过（**不静默**）。
pub fn 依赖清单合法文本(
    自身标识串: &str,
    依赖清单: &[String],
    依赖版本要求: &[版本要求],
    台账: &dyn 已载入台账,
) -> bool {
    if !是合法标识串(自身标识串.as_bytes()) || 依赖清单.len() != 依赖版本要求.len() {
        return false;
    }
    if 依赖清单.is_empty() {
        return true;
    }
    if 依赖清单.len() > 依赖清单上限 {
        return false;
    }
    let mut 依赖串表: Vec<CString> = Vec::with_capacity(依赖清单.len());
    for 依赖项 in 依赖清单 {
        if !是合法标识串(依赖项.as_bytes()) {
            return false;
        }
        let Ok(依赖串) = CString::new(依赖项.as_str()) else {
            return false;
        };
        依赖串表.push(依赖串);
    }
    let 项表: Vec<*const u8> =
        依赖串表.iter().map(|依赖串| 依赖串.as_ptr().cast::<u8>()).collect();
    依赖项表合法(自身标识串.as_bytes(), &项表, 依赖版本要求, 台账)
}

/// 依赖清单的**四问** —— 只此一份。
///
/// 两个入口共用它（裸指针表 / 文本表），故这里不关心「表是怎么来的」，只问事实：
/// 形状 · 不重复 · 不含自身 · 在台账里且版本够。`自身` 是声明那条标识串（32 字节）。
fn 依赖项表合法(
    自身: &[u8],
    依赖项表: &[*const u8],
    版本要求表: &[版本要求],
    台账: &dyn 已载入台账,
) -> bool {
    if 依赖项表.len() != 版本要求表.len() || 依赖项表.len() > 依赖清单上限 {
        return false;
    }
    let mut 已见: [*const u8; 依赖清单上限] = [core::ptr::null(); 依赖清单上限];
    for (序号, &依赖项) in 依赖项表.iter().enumerate() {
        // SAFETY: 依赖项按契约是静态只读的 NUL 结尾标识串（文本入口落的是同一形状）。
        let Some(字节串) = (unsafe { 读串(依赖项, 标识串字节数 + 1) }) else {
            return false;
        };
        if !是合法标识串(字节串) || 字节串 == 自身 {
            return false;
        }
        // 版本比对的**唯一**入口：台账答「已载入的那一份是什么版本」，`无` = 没载入。
        let Some(实际版本) = 台账.已载入版本(依赖项) else {
            return false; // 依赖不在台账里 ⇒ 依赖缺失
        };
        if !实际版本.满足(&版本要求表[序号]) {
            return false; // 依赖在，但那一份的版本低于要求 ⇒ 同一条出路
        }
        if 已见[..序号].contains(&依赖项) {
            return false; // 重复依赖：清单不自洽
        }
        已见[序号] = 依赖项;
    }
    true
}
