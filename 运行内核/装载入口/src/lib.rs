//! 装载入口 —— 可装载性判定 + 载入 + 唯一导出符号。
//!
//! **判定顺序 fail-closed**（`扩展装载与开发标准.md` 2.3）：任一步不过就拒绝载入，
//! 不是崩溃，也不是半载。
//!
//! # 冻结契约下的两条约定（必须读）
//!
//! 契约主结构 `平台信息` 里**没有**「编号」字段；三张表（类型表 · 命令表 · 常量表）
//! 都是「项数 + 项表」的稠密表。旁路区已补齐三张号段/段位表（`能力号段` ·
//! `通知号段` · `错误段位表`）与 `数据类型信息.类型标签`。由此定下两条约定：
//!
//! 1. **编号 = 表内下标（0 起）**：命令编号 = 命令表下标；类型标签 = 类型表下标；
//!    常量编号 = 常量表下标。三者分属三个编号空间，互不重叠。
//!    「号段即层级，也即归属」（`README.md` 第七节）：编号落在哪一段，就是谁的号。
//! 2. **类型标签的有效空间 = 底座类型表 ∪ 声明自身的类型表**（`扩展装载与开发标准.md`
//!    2.2：「类型表：本扩展新增的类型，与底座类型表合并」）。即：底座类型在前、
//!    声明新增在后，有效上界 = 底座类型数 + 声明类型数。这是**只放宽、不放严**的一条。
//!
//! # 跨扩展判定：走台账，不落进程级全局
//!
//! ②的「跨扩展唯一」、③的「与已载入扩展冲突」、⑤的「依赖清单里的扩展都在」，
//! 判据都指向**已载入台账**。台账由调用方**显式传入**（`&dyn 已载入台账`），
//! 不落进程级全局（`开发规范.md` B6：状态是句柄）。本 crate 另提供一份具体实现
//! `载入台账`（`Vec` 字段，多实例安全），并在初始化时把**底座自身的占用**预置进去
//! ——不预置，第一个扩展就会撞上底座而台账误判「没人占」。
//!
//! **台账是只读入参**：`已载入台账` 的方法都收 `&self`，所以 `载入` 改不了台账。
//! 「载入成功后把这份声明记进台账」由调用方调 `载入台账::登记` 完成（装载器收口处）。
//!
//! # 号段是两个独立命名空间
//!
//! `能力号段` 与 `通知号段` 是两张独立的表（`格式说明.md` 第二节：合成一张会把通知号
//! 2000 判成「落在支持库 1000–6999 里」）。声明自检按表分别判合法性，两张表之间不交叉比对。
//! **已收口**：trait `已载入台账` 的 `号段已占用(空间, 起, 止)` 带 `号段空间`，
//! 故 `载入台账` 按空间分账**精确**判、不取并集——并集会把「扩展占能力 1000–6999」
//! 误判成与「底座占通知 0–999」冲突（**假冲突**：一个完全合法的扩展载不进来）。
//!
//! # 文件分工（本文件是路由：声明子模块 · 再导出公开面 · 零实现）
//!
//! - `错误.rs` —— `载入错误`（与判定六步一一对应）
//! - `读数.rs` —— 静态只读串 / 号段表的原始读取与形状判定（判定六步的零件）
//! - `声明校验.rs` —— 号段 · 标签 · 段位 · 自洽（判定 ③ ⑥ 的零件）
//! - `判定.rs` —— 判定六步入口 `判定可装载` + 它据以判版本的底座版本常量
//! - `装载.rs` —— `载入` + `载入台账`（`已载入台账` 的具体实现）
//! - `底座静态声明.rs` —— 底座自身的静态 `平台信息` 与唯一导出符号
//!
//! 模块名一律**不等于**它导出的符号名（`mod 装载` 导出 `载入`；`mod 底座静态声明`
//! 导出 `底座声明`）：同名会与再导出在类型命名空间里撞名（`E0255`）。

