    #[test]
    fn 导出符号_返回底座静态声明且形状完整() {
        let 指针 = 取平台信息();
        assert!(!指针.is_null());
        // SAFETY: 指针指向底座自己的静态声明，终生有效。
        let 声明 = unsafe { &*指针 };

        assert_eq!(声明.声明格式号, v1_contract::声明格式号);
        assert_eq!(声明.目标字宽, 64);
        assert!(core::ptr::eq(声明, 底座声明()));

        // 形状完整：1 个类型 · 1 条命令 · 1 个常量 · 函数表与命令表一一对应。
        assert_eq!(声明.类型表.项数, 1);
        assert!(!声明.类型表.项表.is_null());
        assert_eq!(声明.命令表.项数, 1);
        assert!(!声明.命令表.项表.is_null());
        assert!(!声明.函数表.is_null());
        assert_eq!(声明.常量表.项数, 1);
        assert!(!声明.常量表.项表.is_null());
        assert!(声明.通知函数.is_some());
        assert_eq!(声明.依赖清单.项数, 0);

        // 标识串：32 位十六进制 + NUL。
        // SAFETY: 底座标识串是静态只读的 NUL 结尾串。
        let 标识串 = unsafe { 读串(声明.标识串, 标识串字节数 + 1) }.expect("标识串可读");
        assert_eq!(标识串.len(), 标识串字节数);
        assert!(是合法标识串(标识串));

        // 名称 / 说明非空。
        // SAFETY: 同上，均为静态只读 NUL 结尾串。
        assert!(
            !unsafe { 读串(声明.名称, 串读取上限) }
                .expect("名称可读")
                .is_empty()
        );
        assert!(
            !unsafe { 读串(声明.说明, 串读取上限) }
                .expect("说明可读")
                .is_empty()
        );

        // 全部编号落在 0xxx 内核自有段。
        let (起, 止) = 占用号段(声明);
        assert_eq!((起, 止), (0, 0));
    }

