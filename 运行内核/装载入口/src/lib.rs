//! 装载入口 —— 可装载性判定 + 载入 + 唯一导出符号。
//!
//! **判定顺序 fail-closed**（`扩展装载与开发标准.md` 2.3）：任一步不过就拒绝载入，
//! 不是崩溃，也不是半载。
//!
//! # 冻结契约下的两条约定（必须读）
//!
//! 契约主结构 `平台信息` 里**没有**「号段」字段，也**没有**「编号」字段；三张表
//! （类型表 · 命令表 · 常量表）都是「项数 + 项表」的稠密表。由此定下两条约定：
//!
//! 1. **编号 = 表内下标（0 起）**：命令编号 = 命令表下标；类型标签 = 类型表下标；
//!    常量编号 = 常量表下标。三者分属三个编号空间，互不重叠。
//!    「号段即层级，也即归属」（`README.md` 第七节）：编号落在哪一段，就是谁的号。
//! 2. **类型标签的有效空间 = 底座类型表 ∪ 声明自己的类型表**（`扩展装载与开发标准.md`
//!    2.2：「类型表：本扩展新增的类型，与底座类型表合并」）。即：底座类型在前、
//!    声明新增在后，有效上界 = 底座类型数 + 声明类型数。这是**只放宽、不放严**的一条。
//!
//! # 本回合的判定边界（如实登记，不假装做到了）
//!
//! ②的「跨扩展唯一」、③的「与已载入扩展冲突」、⑤的「依赖清单里的扩展都在」，
//! 都需要一张**已载入扩展台账**。冻结签名 `判定可装载(&'static 平台信息)` 不含该入参，
//! 且 `开发规范.md` B6 明令「状态是句柄，不落进程级全局」——所以本函数只判
//! **声明自身可判的那一部分**，跨扩展那一部分留在装载器收口处（见本文件末尾注释）。

pub use v1_contract::平台信息;
pub use v1_registry::{建表错误, 注册表};

use v1_contract::{
    参数信息, 命令信息, 命令状态, 常量信息, 常量排布, 执行函数, 数据槽, 数据类型信息, 版本三元组,
    表段, 通知号段, 通知返回,
};

/// 载入错误：与判定六步一一对应。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 载入错误 {
    /// ① 声明格式号不匹配。
    格式号不匹配 { 期望: u32, 实际: u32 },
    /// ② 标识串为空或重复。
    标识串非法,
    /// ③ 号段与已载入扩展或作废号表冲突。
    号段冲突 { 起: u32, 止: u32 },
    /// ④ 要求宿主版本 / 要求内核版本不满足。
    /// **报主版本号**（最粗、最能说明「哪一代不够」）；宿主与内核两处共用本分支。
    要求版本不满足 { 要求: u16, 实际: u16 },
    /// ⑤ 依赖清单里的扩展不在。
    依赖缺失,
    /// ⑥ 声明自洽失败（参数类型不在类型表、错误段位未登记、编号重复）。
    声明不自洽 { 命令号: u32 },
    /// 建表失败（见 `建表错误`）。
    建表(建表错误),
}

