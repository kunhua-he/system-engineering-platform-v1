/// 底座提供的**宿主**版本。扩展声明里的「要求宿主版本」按它判（④）。
pub const 底座宿主版本: 版本三元组 = 版本三元组::新(1, 0, 0, 0);

/// 底座提供的**内核**版本。扩展声明里的「要求内核版本」按它判（④）。
pub const 底座内核版本: 版本三元组 = 版本三元组::新(1, 0, 0, 0);

/// 号段类宽度：0xxx 一段，每段 1000 个号。
const 号段类宽度: u32 = 1000;

/// 号段类个数（0xxx–9xxx）。
const 号段类个数: u32 = 10;

// 底座保留段：0xxx 内核自有 · 9xxx 工具类（`README.md` 第七节）。
// 本回合不作拒绝判据——契约主结构没有「号段」字段，扩展的号段无从声明，
// 若按「扩展不得占 0xxx」判，会把所有扩展一并拒掉。故只在文件头如实登记这个缺口。

/// **作废号表**（宪法第 7 条：号只增不复用）。本回合为空——尚无扩展，故无作废号。
const 作废号表: &[u32] = &[];

/// 底座已登记的错误段位（0xxx 内核自有）。见 ⑥ 的第三项判定说明。
const 已登记错误段位: &[u32] = &[0];

/// 判定六步：只判不载。给验证面用，也给载入前预检用。
///
/// 顺序与判据严格按 `扩展装载与开发标准.md` 2.3：
/// ①格式号 → ②标识串 → ③号段 → ④要求版本 → ⑤依赖 → ⑥自洽。
/// **任一步不过即返回 `Err`，不触碰任何状态**（不是崩溃，也不是半载）。
pub fn 判定可装载(声明: &'static 平台信息) -> Result<(), 载入错误> {
    // ── ① 声明格式号匹配 ──────────────────────────────────────────────
    if 声明.声明格式号 != v1_contract::声明格式号 {
        return Err(载入错误::格式号不匹配 {
            期望: v1_contract::声明格式号,
            实际: 声明.声明格式号,
        });
    }

    // ── ② 标识串非空且唯一 ───────────────────────────────────────────
    // 形状：32 位十六进制 + NUL（契约主结构注释）。空指针 / 空串 / 长度不符 / 非十六进制
    // 一律非法；另：**不得冒用底座身份**——那是唯一能在无台账时判定的「重复」。
    let 标识串 = unsafe { 读串(声明.标识串, 标识串字节数 + 1) };
    let Some(标识串) = 标识串 else {
        return Err(载入错误::标识串非法);
    };
    if !是合法标识串(标识串) {
        return Err(载入错误::标识串非法);
    }
    if !是底座自有声明(声明) && 标识串 == 底座标识串内容 {
        // 同一身份不能有两个主人。跨扩展的唯一性需要台账，见文件头「判定边界」。
        return Err(载入错误::标识串非法);
    }

    // ── ③ 号段不冲突 ─────────────────────────────────────────────────
    // 声明占用的号段 = 三张表编号的并集区间（编号 = 表内下标，见文件头约定 1）。
    let (号段起, 号段止) = 占用号段(声明);
    if 号段止 >= 号段起 {
        // 跨号段类 = 归属不明（号段即归属）；超出 9xxx = 根本没有那一段。
        let 起类 = 号段起 / 号段类宽度;
        let 止类 = 号段止 / 号段类宽度;
        if 起类 != 止类 || 止类 >= 号段类个数 {
            return Err(载入错误::号段冲突 {
                起: 号段起,
                止: 号段止,
            });
        }
        // 与作废号表冲突（号只增不复用）。本回合作废号表为空，分支留好，接口不塌。
        if 与作废号表冲突(号段起, 号段止) {
            return Err(载入错误::号段冲突 {
                起: 号段起,
                止: 号段止,
            });
        }
    }

    // ── ④ 要求宿主版本 / 要求内核版本满足 ───────────────────────────
    if !底座宿主版本.满足(&声明.要求宿主版本) {
        return Err(载入错误::要求版本不满足 {
            要求: 声明.要求宿主版本.主,
            实际: 底座宿主版本.主,
        });
    }
    if !底座内核版本.满足(&声明.要求内核版本) {
        return Err(载入错误::要求版本不满足 {
            要求: 声明.要求内核版本.主,
            实际: 底座内核版本.主,
        });
    }

    // ── ⑤ 依赖清单里的扩展都在 ──────────────────────────────────────
    // 无台账 ⇒ 判「在」做不到。可判的是：清单本身合法、且不含**永不满足**的自依赖
    // （自己依赖自己，装载期永远等不到，等价于「依赖不在」）。
    if !依赖清单合法(声明, 标识串) {
        return Err(载入错误::依赖缺失);
    }

    // ── ⑥ 声明自洽 ──────────────────────────────────────────────────
    判声明自洽(声明)
}

/// 载入：判定通过后建注册表。
///
/// **不许半载**：六步全过才交给 `注册表::建表`；建表失败即整体失败（错误转成
/// `载入错误::建表`），不留下任何半个注册表。
pub fn 载入(声明: &'static 平台信息) -> Result<注册表, 载入错误> {
    判定可装载(声明)?;
    注册表::建表(声明).map_err(载入错误::建表)
}

