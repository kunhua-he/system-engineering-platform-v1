//! 声明校验：号段 · 标签 · 段位 · 自洽（判定 ③ 与 ⑥ 的零件）。
//!
//! 判的是「声明自身站不站得住」与「与台账 / 作废号表冲不冲突」；
//! 读指针的动作一律走 `读数`，六步的先后由 `判定` 编排。

use crate::底座静态声明::{底座类型数, 是底座自有声明};
use crate::读数::{号段切片, 号段表上限, 标识串字节数, 是合法标识串, 读串};
use crate::错误::载入错误;
use v1_contract::{常量排布, 命令状态, 号段, 号值, 平台信息, 表段, 已载入台账, 能力号};

// 号段类宽度 / 号段类个数：**值只有一个来源**（`v1_contract::声明数据`，源 = `契约声明/号段图.json`
// 的 `能力号段` 推导）。这里只引名，不写数 —— 手写一份就是同一事实的第二来源。
use v1_contract::声明数据::{号段类个数, 号段类宽度};

/// 号段类宽度：0xxx 一段，每段 1000 个号（`README.md` 第七节）。
///
/// **值只有一个来源**：`v1_contract::声明数据::号段类宽度`
/// （源 = `契约声明/号段图.json.能力号段` 的段边界 gcd；推导规则逐字写在生成物第七节）。
/// 这里只 `use` 名字 —— 早先手写的 `const 号段类宽度: u32 = 1000;` 已删（第二来源）。
///
/// 两个真实用途，都与「从表项数反推号段」无关（那条旧腿已删）：
/// 1. 判声明**直接给出**的号段是否跨号段类（号段即归属，跨类 = 归属不明）；
/// 2. 把能力编号换算成**能力段位**（首位十进制数字 = `编号 / 号段类宽度`），
///    再拿去比对声明的 `错误段位表`（错误码段位与能力号段共用同一套段位口径）。
///
/// 号段类个数（0xxx–9xxx）：值同样只有一个来源，`v1_contract::声明数据::号段类个数`。
///
/// 号段表名：`载入错误::号段非法` / `号段表内重叠` 的定位信息。
pub(crate) mod 号段表名 {
    pub const 能力: &str = "能力号段";
    pub const 通知: &str = "通知号段";
}

/// **作废号表 · 能力空间**（宪法第 7 条：号只增不复用）。
///
/// 作废行按**号空间**分账：能力编号 `0xxx` 与错误码「段位 × 1000 + 序号」只是数字上撞了
/// 同一个数，不是同一个号 —— 全局封禁会把两个空间的同号混为一谈（假冲突：底座从来没有
/// 能力编号 16，却因错误码 16 作废而整段 `[0,999]` 被判冲突，底座自身就载不进来）。
/// 单一来源：`v1_contract::声明数据::作废号表_能力`（源：`契约声明/作废号表.json`）。
const 作废号表_能力: &[u32] = v1_contract::声明数据::作废号表_能力;

/// 一张错误段位表的项数上限（同上）。
const 错误段位表上限: usize = 16;

/// 依赖清单的项数上限（防呆：超过就当声明不自洽）。
const 依赖清单上限: usize = 256;

/// ③ 一张号段表自身的合法性 + 归属：
///
/// - 每段必须 `起 <= 止`（否则 `号段非法`；表段形状不可用同此）；
/// - 同一张表内两段不许相交（否则 `号段表内重叠`）；
/// - 每段不许跨号段类、不许越过 9xxx（号段即层级，跨类 = 归属不明 ⇒ `号段冲突`）。
///
/// **只判这一张表**：能力号段与通知号段是两个独立命名空间，两张表之间不交叉比对。
pub(crate) fn 判号段表(表: 表段<号段>, 名: &'static str) -> Result<(), 载入错误> {
    if 表.项数 == 0 {
        return Ok(());
    }
    if 表.项表.is_null() || 表.项数 as usize > 号段表上限 {
        return Err(载入错误::号段非法 { 表: 名, 序: 0 });
    }
    let 段s = 号段切片(表);
    for (序, 段) in 段s.iter().enumerate() {
        let 序 = 序 as u32;
        if 段.起 > 段.止 {
            return Err(载入错误::号段非法 { 表: 名, 序 });
        }
        let 类 = 段.止.取() / 号段类宽度;
        if 段.起.取() / 号段类宽度 != 类 || 类 >= 号段类个数 {
            return Err(载入错误::号段冲突 { 起: 段.起.取(), 止: 段.止.取() });
        }
        for (另序, 另段) in 段s[..序 as usize].iter().enumerate() {
            if 段.相交(另段) {
                return Err(载入错误::号段表内重叠 {
                    表: 名,
                    序,
                    另序: 另序 as u32,
                });
            }
        }
    }
    Ok(())
}

/// 号是否落在**能力空间**的作废号表里 —— **精确比**（逐号相等，不是区间相交）。
///
/// 口径（已裁）：与「按空间」同一逻辑，**精确比，不整段封**。
/// 早先判「声明的号段与作废号表**相交**」⇒ 只要能力空间真作废了一个**与任何命令都不撞**
/// 的号，而它又落在底座申报的能力号段内，底座整段就被判冲突（同空间的假红）。
fn 号已作废(作废表: &[u32], 命令号: 能力号) -> bool {
    作废表.contains(&命令号.取())
}

/// ③ 声明的**命令编号**不许碰**同空间**（能力空间）的作废号。
///
/// **逐条命令编号比**：作废号是能力编号，故拿声明的每一条 `命令信息.编号` 去比，
/// 命中即 `号段冲突` —— `起 = 止 = 该命令编号`：报的是那一个号，不是一整段。
///
/// `作废表` 是形参而非直接读常量：生产入口传生成物 `作废号表_能力`（单一来源），
/// 测试要能注入一张合成表造「空洞号不假红 / 真在用的号必红」两条反向样本 ——
/// 生成物当前那张表为空时，这两条样本只能靠注入才造得出来。
pub(crate) fn 判命令编号不与作废号冲突(
    声明: &平台信息,
    作废表: &[u32],
) -> Result<(), 载入错误> {
    let 项数 = 声明.命令表.项数;
    if 项数 == 0 || 声明.命令表.项表.is_null() {
        return Ok(());
    }
    for 序 in 0..项数 as usize {
        // SAFETY: 项数 > 0 且项表非空，序 < 项数。
        let 命令 = unsafe { &*声明.命令表.项表.add(序) };
        let 命令号 = 命令.编号;
        if 号已作废(作废表, 命令号) {
            return Err(载入错误::号段冲突 { 起: 命令号.取(), 止: 命令号.取() });
        }
    }
    Ok(())
}

/// ③ 声明的**能力空间**命令编号不许碰能力空间的作废号（作废号是能力编号，故只对能力空间判）。
///
/// 生产入口：作废表取生成物 `v1_contract::声明数据::作废号表_能力`（单一来源）。
pub(crate) fn 判不与作废号冲突(声明: &平台信息) -> Result<(), 载入错误> {
    判命令编号不与作废号冲突(声明, 作废号表_能力)
}

/// 依赖清单是否合法：逐项都是合法标识串、不重复、不含自身，**且每一项都在台账里**。
pub(crate) fn 依赖清单合法(
    声明: &平台信息,
    自身: &[u8],
    台账: &dyn 已载入台账,
) -> bool {
    let 项数 = 声明.依赖清单.项数;
    if 项数 == 0 {
        return true;
    }
    if 声明.依赖清单.项表.is_null() {
        return false;
    }
    let mut 已见: [*const u8; 依赖清单上限] = [core::ptr::null(); 依赖清单上限];
    if 项数 as usize > 依赖清单上限 {
        return false;
    }
    for 序 in 0..项数 as usize {
        // SAFETY: 项数 > 0 且项表非空，序 < 项数。
        let 项 = unsafe { *声明.依赖清单.项表.add(序) };
        // SAFETY: 依赖项按契约是静态只读的 NUL 结尾标识串。
        let Some(串) = (unsafe { 读串(项, 标识串字节数 + 1) }) else {
            return false;
        };
        if !是合法标识串(串) || 串 == 自身 {
            return false;
        }
        if !台账.是否已载入(项) {
            return false; // 依赖不在台账里 ⇒ 依赖缺失
        }
        if 已见[..序].contains(&项) {
            return false; // 重复依赖：清单不自洽
        }
        已见[序] = 项;
    }
    true
}

/// ⑥ 声明自洽：类型标签显式且不重复 · **命令编号落在本声明申报的能力号段内** ·
/// 参数类型都在类型表里 · 错误段位表合法 · 错误段位已登记 · 编号不重复。
pub(crate) fn 判声明自洽(声明: &平台信息) -> Result<(), 载入错误> {
    let 声明类型数 = 声明.类型表.项数;
    let 命令数 = 声明.命令表.项数;
    let 常量数 = 声明.常量表.项数;

    // 表指针防呆：项数 > 0 却给了空指针 ⇒ 声明不自洽（也避免下面越界读）。
    if (声明类型数 > 0 && 声明.类型表.项表.is_null())
        || (命令数 > 0 && 声明.命令表.项表.is_null())
        || (常量数 > 0 && 声明.常量表.项表.is_null())
    {
        return Err(载入错误::声明不自洽 { 命令号: 能力号::新(0) });
    }

    // 类型标签的有效上界：底座类型在前、声明新增在后（只放宽，不放严）。
    let 类型标签上界 = 声明类型数 + 底座类型数();

    // ⓪ 类型标签：不许复用底座已登记的标签，且表内不许重复。
    //    **不做「底座例外」**——底座自身的 `类型表` 就是内置标签注册表（含「空」= 0），
    //    非底座声明一律不许再登记这些标签（0 · 1–6 · 4294967295）。规则对所有声明成立。
    let 是底座 = 是底座自有声明(声明);
    for 类型序 in 0..声明类型数 {
        // SAFETY: 类型表项数 > 0 且项表非空，类型序 < 项数。
        let 类型 = unsafe { &*声明.类型表.项表.add(类型序 as usize) };
        if !是底座 && 底座已登记标签(类型.类型标签.取()) {
            return Err(载入错误::类型标签与已登记重复 {
                类型标签: 类型.类型标签,
                类型序,
            });
        }
        for 前序 in 0..类型序 {
            // SAFETY: 同上，前序 < 类型序 < 项数。
            let 前类型 = unsafe { &*声明.类型表.项表.add(前序 as usize) };
            if 前类型.类型标签 == 类型.类型标签 {
                return Err(载入错误::类型标签重复 {
                    类型标签: 类型.类型标签,
                    序: 类型序,
                    另序: 前序,
                });
            }
        }
    }

    // ① 命令编号落在本声明申报的能力号段内 + 参数类型都在类型表里 + 返回类型合法
    //    + 参数表指针不自相矛盾。
    for 命令序 in 0..命令数 {
        // SAFETY: 命令表项数 > 0 且项表非空，命令序 < 项数。
        let 命令 = unsafe { &*声明.命令表.项表.add(命令序 as usize) };
        // **命令号取自命令自身的显式 `编号`**，不是表内下标（下标会随重排漂移）。
        let 命令号 = 命令.编号;
        // 命令编号必须落在**本声明自身申报**的能力号段内，越界即 `声明不自洽`。
        // 号段即归属：申报 1000–1999 的命令拿编号 0，等于把「谁是底座、谁是扩展」交出去
        // （`项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 5）。
        if !命令编号在申报号段内(声明, 命令号) {
            return Err(载入错误::声明不自洽 { 命令号 });
        }
        if 命令.参数个数 > 0 && 命令.参数表.is_null() {
            return Err(载入错误::声明不自洽 { 命令号 });
        }
        if 命令.返回类型 != 0 && 命令.返回类型.取() >= 类型标签上界 {
            return Err(载入错误::声明不自洽 { 命令号 });
        }
        for 参数序 in 0..命令.参数个数 {
            // SAFETY: 参数个数 > 0 且参数表非空，参数序 < 参数个数。
            let 参数 = unsafe { &*命令.参数表.add(参数序 as usize) };
            if 参数.类型标签.取() >= 类型标签上界 {
                return Err(载入错误::声明不自洽 { 命令号 });
            }
        }
    }

    // ② 常量类型标签合法（排布 = 空 时不带类型，跳过）。
    for 常量序 in 0..常量数 {
        // SAFETY: 常量表项数 > 0 且项表非空，常量序 < 项数。
        let 常量 = unsafe { &*声明.常量表.项表.add(常量序 as usize) };
        if 常量.排布 != 常量排布::空 && 常量.类型标签.取() >= 类型标签上界 {
            return Err(载入错误::声明不自洽 {
                命令号: 能力号::新(常量序)
            });
        }
    }

    // ③ 编号不重复：类型表的命令号表内不许重复，且必须落在命令表里。
    //
    // ⚠ 「命令无人认领」当前**不判红**：本函数只查「类型认领的命令号是否合法且不重复」，
    //    不查「命令表里每条命令是否都被某个类型认领」。原因：`契约声明/类型声明/*.json`
    //    的 `命令号表` 8 个全是 `[]` —— JSON 侧**没有**「哪个类型带哪条命令」的源，
    //    判了就是把生成物的空当违规。实测后果：接线生成物后**底座命令 0 无任何类型认领**
    //    （手写那份曾给 `底座类型表[0].命令号表 = [0]`，接线后该手写项被删）。要判这条，
    //    得先在 JSON 侧定义并填写「类型 → 命令号」的源。
    //
    // `命令号表` 里放的是**命令编号**（`命令信息.编号`），不是命令表下标 ——
    // 故「落在命令表里」= 这个编号能在命令表里按 `编号` 找到，不是「小于命令表项数」。
    for 类型序 in 0..声明类型数 {
        // SAFETY: 类型表项数 > 0 且项表非空，类型序 < 项数。
        let 类型 = unsafe { &*声明.类型表.项表.add(类型序 as usize) };
        if 类型.命令个数 > 0 && 类型.命令号表.is_null() {
            return Err(载入错误::声明不自洽 { 命令号: 能力号::新(0) });
        }
        if 类型.事件个数 > 0 && 类型.事件表.is_null() {
            return Err(载入错误::声明不自洽 { 命令号: 能力号::新(0) });
        }
        if 类型.属性个数 > 0 && 类型.属性表.is_null() {
            return Err(载入错误::声明不自洽 { 命令号: 能力号::新(0) });
        }
        if 类型.元素个数 > 0 && 类型.元素表.is_null() {
            return Err(载入错误::声明不自洽 { 命令号: 能力号::新(0) });
        }
        for 位 in 0..类型.命令个数 {
            // SAFETY: 命令个数 > 0 且命令号表非空，位 < 命令个数。
            // 命令号表存的是**裸 `u32` 编号**（表段<u32>，与 `命令信息.编号` 同源），
            // 过闸处包成 `能力号` —— 号空间在闸的形参上立住。
            let 号 = 能力号::新(unsafe { *类型.命令号表.add(位 as usize) });
            if !命令表含编号(声明, 号) {
                return Err(载入错误::声明不自洽 { 命令号: 号 });
            }
            for 前位 in 0..位 {
                // SAFETY: 同上，前位 < 位 < 命令个数。
                if 能力号::新(unsafe { *类型.命令号表.add(前位 as usize) }) == 号 {
                    return Err(载入错误::声明不自洽 { 命令号: 号 });
                }
            }
        }
    }

    // ④ 错误段位表合法 + 错误项命令的段位已登记。
    //    错误段位表由声明**直接给出**（旁路字段），不再用底座写死的常量。
    //    段位口径用**命令编号**（`命令信息.编号 / 号段类宽度`），不是表内下标 ——
    //    早先按下标，占 1xxx 号段的扩展只要有一条错误项命令就恒判不自洽（待办旁路·阻断级）。
    let 段位表 = 读段位表(声明.错误段位表)?;
    for 命令序 in 0..命令数 {
        // SAFETY: 命令表项数 > 0 且项表非空，命令序 < 项数。
        let 命令 = unsafe { &*声明.命令表.项表.add(命令序 as usize) };
        if 命令.状态位 & 命令状态::错误 != 0 && !能力段位已登记(段位表, 命令.编号) {
            return Err(载入错误::声明不自洽 { 命令号: 命令.编号 });
        }
    }

    Ok(())
}

/// 命令编号是否落在**本声明自身申报**的能力号段内（多段取并集；一段都没申报即越界）。
///
/// 闭区间含端点：恰好等于 `起` 与恰好等于 `止` 都算在内。
/// 口径：`项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 5。
fn 命令编号在申报号段内(声明: &平台信息, 命令号: 能力号) -> bool {
    号段切片(声明.能力号段)
        .iter()
        .any(|段| 段.含(号值::新(命令号.取())))
}

/// 命令表里有没有这个编号（按显式 `编号` 找，**不按表内下标**）。
///
/// 线性扫描：命令表一般很小，且 `判声明自洽` 可在 `注册表::建表` 之前单独调用
/// （那时还不敢假设表已排序），故这里不依赖「表按编号递增」这条建表期不变量。
fn 命令表含编号(声明: &平台信息, 命令号: 能力号) -> bool {
    let 项数 = 声明.命令表.项数;
    if 项数 == 0 || 声明.命令表.项表.is_null() {
        return false;
    }
    for 序 in 0..项数 as usize {
        // SAFETY: 项数 > 0 且项表非空，序 < 项数。
        if unsafe { (*声明.命令表.项表.add(序)).编号 } == 命令号 {
            return true;
        }
    }
    false
}

/// 读声明的错误段位表：**不许为空**（没有它，「未登记的段位不许抛出」判不了），
/// 段位**不许重复**；表段形状不可用同 `错误段位表为空` 一并拦下。
pub(crate) fn 读段位表(表: 表段<u32>) -> Result<&'static [u32], 载入错误> {
    if 表.项数 == 0 || 表.项表.is_null() || 表.项数 as usize > 错误段位表上限 {
        return Err(载入错误::错误段位表为空);
    }
    // SAFETY: 契约保证错误段位表指向静态只读数组；项数 > 0 且项表非空。
    let 段s = unsafe { core::slice::from_raw_parts(表.项表, 表.项数 as usize) };
    for (序, 段位) in 段s.iter().enumerate() {
        if 段s[..序].contains(段位) {
            return Err(载入错误::错误段位重复 { 段位: *段位 });
        }
    }
    Ok(段s)
}

/// 错误项命令的**能力段位**是否已在声明的错误段位表里登记。
///
/// 段位口径（`README.md` 第七节 · `格式说明.md` 第五节）：段位 = 号的首位十进制数字，
/// 也即能力号段的首位（**号段即归属**）。`命令号` 是命令自身的显式 `编号`，故
/// 命令编号的段位 = `命令编号 / 号段类宽度`。错误码与能力号**共用同一套段位**，
/// 所以这个段位能直接拿去比对 `错误段位表`。
fn 能力段位已登记(段位表: &[u32], 命令号: 能力号) -> bool {
    段位表.contains(&(命令号.取() / 号段类宽度))
}

/// 这个标签是不是**底座已经登记**的。
///
/// 底座自身就是那张内置标签注册表：`0` 空 · `1–6` 整数/双精度/逻辑/文本/字节集/句柄 ·
/// `4294967295` 错误。非底座声明不许复用其中任何一个。
fn 底座已登记标签(标签: u32) -> bool {
    标签 <= 6 || 标签 == u32::MAX
}

