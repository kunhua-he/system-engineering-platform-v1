//! 类型标签登记面 —— 「这个标签算不算已登记」的两问（A32 · A34）。
//!
//! 从 `声明校验.rs` 拆出（判据 ⑲ 单源文件 400 行硬数）。口径：`契约声明/格式说明.md` §四
//! 定「扩展的类型从 `100` 起」（标签是**号值**，不是表内下标）⇒ 合法域 **= 本声明类型表
//! ∪ 底座已登记标签**，**不按计数算**。

use v1_contract::{平台信息, 类型标签};

/// 这个标签是不是**底座已经登记**的（源 = 生成物 `底座类型表`，唯一来源 = `契约声明/类型声明/*.json`）。
///
/// **读枚举，不写死区间**：底座类型表实测 9 项（`0` · `1–7` · `4294967295`，`0007.json`
/// 为 2026-09-27 旁路新增）。早先写死 `标签 <= 6 || 标签 == u32::MAX`：漏 `7`（`7 > 6`、
/// `7 < 上界`）⇒ 非底座声明登记 `7` 静默与底座「任务句柄」撞号。枚举读法加一个底座类型
/// 只需落一个 JSON，本函数自动跟上。
pub(crate) fn 底座已登记标签(标签: u32) -> bool {
    v1_contract::声明数据::底座类型表
        .iter()
        .any(|类型| 类型.类型标签.取号值() == 标签)
}

/// 这个标签是不是**本声明可引用**的：本声明类型表里有一项，或它已是底座已登记标签。
///
/// 底座已有的类型**不用重声明**（`扩展装载/开发标准/必备件.json`：「本扩展**新增**的数据类型
/// （底座已有的不用重声明）」）⇒ 参数/返回/常量引用的标签必须允许落在**底座已登记标签**上。
pub(crate) fn 标签已登记(声明: &平台信息, 标签: 类型标签) -> bool {
    if 底座已登记标签(标签.取号值()) {
        return true;
    }
    for 类型序 in 0..声明.类型表.表项数 as usize {
        // SAFETY: `判声明自洽` 开头已判过「类型表项数 > 0 则项表非空」；类型序 < 项数。
        if unsafe { (*声明.类型表.项表.add(类型序)).类型标签 } == 标签 {
            return true;
        }
    }
    false
}
