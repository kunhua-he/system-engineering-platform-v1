//! `判定可装载` 的单元测试：全过样本 + 六步各一个失败样本。

use super::*;
use crate::测试夹具::*;
use crate::载入台账;
use crate::底座声明;
use v1_contract::{号段, 参数信息, 命令信息, 数据槽, 数据类型信息, 类型标签, 表段};

// ── 全过样本 ────────────────────────────────────────────────────────

#[test]
fn 全过样本_六步全通过() {
    // 标准台账（底座占用已预置）下，样本声明的号段 (1000,1999) 不碰底座 ⇒ 全过。
    assert_eq!(判定可装载(钉(合样本()), &标准台账()), Ok(()));
}

#[test]
fn 全过样本_底座自身的声明也全通过() {
    // 底座自有声明必须自身就能过六步——否则底座连自身都载不进来。
    // 用**空台账**：判底座自身时，台账里还不该有底座自身，否则 ② 会把它当成重名。
    assert_eq!(判定可装载(底座声明(), &载入台账::空()), Ok(()));
}

// ── 六步各一个失败样本 ──────────────────────────────────────────────

#[test]
fn 第一步_声明格式号不匹配即拒() {
    let mut 样本 = 合样本();
    样本.声明格式号 = v1_contract::格式号::新(v1_contract::声明格式号.取() - 1);
    assert_eq!(
        判定可装载(钉(样本), &标准台账()),
        Err(载入错误::声明格式号不匹配 {
            期望: v1_contract::声明格式号.取(),
            实际: v1_contract::声明格式号.取() - 1,
        })
    );
}

#[test]
fn 第二步_标识串为空即拒() {
    let mut 空串 = 合样本();
    空串.标识串 = 串("\0");
    assert_eq!(判定可装载(钉(空串), &标准台账()), Err(载入错误::标识串非法));

    let mut 空指针 = 合样本();
    空指针.标识串 = core::ptr::null();
    assert_eq!(判定可装载(钉(空指针), &标准台账()), Err(载入错误::标识串非法));

    let mut 形状不符 = 合样本();
    形状不符.标识串 = 串("abc\0");
    assert_eq!(判定可装载(钉(形状不符), &标准台账()), Err(载入错误::标识串非法));
}

#[test]
fn 第二步_冒用底座身份即拒() {
    // 用空台账：这样拦下它的只能是「冒用底座身份」这一条，而不是「台账里已载入」。
    let mut 样本 = 合样本();
    样本.标识串 = v1_contract::声明数据::底座标识串.as_ptr();
    assert_eq!(判定可装载(钉(样本), &载入台账::空()), Err(载入错误::标识串非法));
}

#[test]
fn 第三步_号段跨段即拒() {
    // 能力号段 (0, 1500) 跨 0xxx 与 1xxx 两段 ⇒ 归属不明（号段即层级，也即归属）。
    // 号段由声明**直接给出**（不再从表项数反推）。
    let mut 样本 = 合样本();
    样本.能力号段 = 钉段表(&[号段::新(0, 1500)]);
    assert_eq!(
        判定可装载(钉(样本), &标准台账()),
        Err(载入错误::号段冲突 { 起: 0, 止: 1500 })
    );
}

#[test]
fn 第四步_要求版本不满足即拒() {
    let mut 宿主不够 = 合样本();
    宿主不够.要求宿主版本 = 版本三元组::新(2, 0, 0, 0);
    assert_eq!(
        判定可装载(钉(宿主不够), &标准台账()),
        Err(载入错误::要求版本不满足 {
            要求: 2, 实际: 1
        })
    );

    let mut 内核不够 = 合样本();
    内核不够.要求内核版本 = 版本三元组::新(1, 1, 0, 0);
    assert_eq!(
        判定可装载(钉(内核不够), &标准台账()),
        Err(载入错误::要求版本不满足 {
            要求: 1, 实际: 1
        })
    );
}

