/// **反向样本（[425] 可抛码越域）**：命令的可抛错误码写了一项**本声明错误码表里没有、
/// 底座错误码表里也没有**的码 ⇒ 必判 `可抛码未登记`（**具名报出是哪个码**，不是笼统的
/// `声明不自洽`）。
///
/// 为什么必须有这一条：错误码与类型标签同属「按扩展归属」的号空间，声明里写一个平台侧
/// 无处登记的码 ⇒ 抛出时调用方拿不到 `可重试 / 可自愈 / 需人工` 三项（`格式说明.md` §三）。
#[test]
fn 第六步_可抛码未登记即拒_具名报出哪个码() {
    // 取一个**本声明与底座都没有**的码（段位 7 在本样本的 `错误段位表 = [1]` 外，
    // 且该命令非错误项 ⇒ 不会先撞上段位闸）。
    let 孤儿码 = 错误码::构造(7001);
    let 可抛表: &'static [错误码] = Box::leak(Box::new([孤儿码]));
    let mut 合成样例 = 合成样本();
    let 旧命令 = unsafe { core::ptr::read(合成样例.命令表.项表) };
    let 改后命令 = Box::leak(Box::new([命令信息 {
        可抛错误码: 表段::构造(可抛表.as_ptr(), 1),
        ..旧命令
    }]));
    合成样例.命令表 = 表段::构造(改后命令.as_ptr(), 1);
    assert_eq!(
        判定可装载(钉住(合成样例), &标准台账()),
        Err(载入错误::可抛码未登记 { 错误码: 孤儿码 })
    );
}

