//! `判定可装载` 的单元测试：全过样本 + 六步各一个失败样本。

use super::*;
use crate::测试夹具::*;
use crate::载入台账;
use crate::底座声明;
use v1_contract::{号段, 参数信息, 命令信息, 数据槽, 数据类型信息, 类型标签, 表段, 版本要求};

// ── 全过样本 ────────────────────────────────────────────────────────

#[test]
fn 全过样本_六步全通过() {
    // 标准台账（底座占用已预置）下，样本声明的号段 (1000,1999) 不碰底座 ⇒ 全过。
    assert_eq!(判定可装载(钉住(合成样本()), &标准台账()), Ok(()));
}

#[test]
fn 全过样本_底座自身的声明也全通过() {
    // 底座自有声明必须自身就能过六步——否则底座连自身都载不进来。
    // 用**空台账**：判底座自身时，台账里还不该有底座自身，否则 ② 会把它当成重名。
    assert_eq!(判定可装载(底座声明(), &载入台账::空实例()), Ok(()));
}

// ── 六步各一个失败样本 ──────────────────────────────────────────────

#[test]
fn 第一步_声明格式号不匹配即拒() {
    let mut 合成样例 = 合成样本();
    合成样例.声明格式号 = v1_contract::格式号::构造(v1_contract::声明格式号.取号值() - 1);
    assert_eq!(
        判定可装载(钉住(合成样例), &标准台账()),
        Err(载入错误::声明格式号不匹配 {
            期望: v1_contract::声明格式号.取号值(),
            实际: v1_contract::声明格式号.取号值() - 1,
        })
    );
}

#[test]
fn 第二步_标识串为空即拒() {
    let mut 空串 = 合成样本();
    空串.标识串 = 静态串("\0");
    assert_eq!(判定可装载(钉住(空串), &标准台账()), Err(载入错误::标识串非法));

    let mut 空指针 = 合成样本();
    空指针.标识串 = core::ptr::null();
    assert_eq!(判定可装载(钉住(空指针), &标准台账()), Err(载入错误::标识串非法));

    let mut 形状不符 = 合成样本();
    形状不符.标识串 = 静态串("abc\0");
    assert_eq!(判定可装载(钉住(形状不符), &标准台账()), Err(载入错误::标识串非法));
}

#[test]
fn 第二步_冒用底座身份即拒() {
    // 用空台账：这样拦下它的只能是「冒用底座身份」这一条，而不是「台账里已载入」。
    let mut 合成样例 = 合成样本();
    合成样例.标识串 = v1_contract::声明数据::底座标识串.as_ptr();
    assert_eq!(判定可装载(钉住(合成样例), &载入台账::空实例()), Err(载入错误::标识串非法));
}

#[test]
fn 第三步_号段跨段即拒() {
    // 能力号段 (0, 1500) 跨 0xxx 与 1xxx 两段 ⇒ 归属不明（号段即层级，也即归属）。
    // 号段由声明**直接给出**（不再从表项数反推）。
    let mut 合成样例 = 合成样本();
    合成样例.能力号段 = 钉段表(&[号段::构造(0, 1500)]);
    assert_eq!(
        判定可装载(钉住(合成样例), &标准台账()),
        Err(载入错误::号段冲突 { 段起点: 0, 段止: 1500 })
    );
}

#[test]
