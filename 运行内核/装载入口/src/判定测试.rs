#[test]
fn 第六步_参数类型不在类型表里即拒() {
    // 有效上界 = 声明类型数(样本 1) + 底座类型数(生成物给 8) = 9；
    // 参数类型标签取 99，确实超出上界（接线前底座只 1 个类型、上界 2，故旧样本取 7 就够）。
    let 参数表 = Box::leak(
        vec![参数信息 {
            名称: 串("坏参数\0"),
            说明: 串("类型标签远超有效上界。\0"),
            类型标签: 类型标签::新(99),
            状态位: 0,
            默认值: 数据槽::空槽(),
        }]
        .into_boxed_slice(),
    );
    let 命令表 = Box::leak(
        vec![命令信息 {
            名称: 串("坏命令\0"),
            说明: 串("带一个坏参数。\0"),
            类别: 0,
            状态位: 0,
            返回类型: v1_contract::类型标签::新(0),
            用户级别: 0,
            参数个数: 1,
            参数表: 参数表.as_ptr(),
            编号: 样本命令编号,
            可抛错误码: 表段::空(),
        }]
        .into_boxed_slice(),
    );
    let mut 样本 = 合样本();
    样本.命令表 = 表段::新(命令表.as_ptr(), 1);
    assert_eq!(
        判定可装载(钉(样本), &标准台账()),
        Err(载入错误::声明不自洽 {
            命令号: 样本命令编号
        })
    );
}

#[test]
fn 第六步_编号重复即拒() {
    let 命令号表 = Box::leak(vec![样本命令编号.取(), 样本命令编号.取()].into_boxed_slice());
    let 类型表 = Box::leak(
        vec![数据类型信息 {
            名称: 串("坏类型\0"),
            说明: 串("命令号表里同一个号出现了两次。\0"),
            状态位: 0,
            命令个数: 2,
            命令号表: 命令号表.as_ptr(),
            事件个数: 0,
            事件表: core::ptr::null(),
            属性个数: 0,
            属性表: core::ptr::null(),
            元素个数: 0,
            元素表: core::ptr::null(),
            类型标签: 类型标签::新(100),
        }]
        .into_boxed_slice(),
    );
    let mut 样本 = 合样本();
    样本.类型表 = 表段::新(类型表.as_ptr(), 1);
    assert_eq!(
        判定可装载(钉(样本), &标准台账()),
        Err(载入错误::声明不自洽 {
            命令号: 样本命令编号
        })
    );
}
