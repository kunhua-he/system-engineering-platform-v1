/// **正向样本（共享标签 · 通用复合标签 `100` 被别份占用也不算冲突）**。
///
/// `100`–`103` 归扩展，但**每份扩展各自声明同一批号**（`元素表` 记该扩展各能力的返回字段）
/// —— 见 `项目文档/决策记录/2026-10-12_复合类型槽载荷裁决.md` §九「平台不拥有这四个号」。
/// ⇒ 后继声明再报 `100` **不能**算「号段冲突」，否则同网关双执行域装不进第二份扩展。
///
/// 修前必红：`100` 已随第一份进台账 ⇒ ③ 报 `号段冲突 { 段起点: 100, 段止: 100 }`。
#[test]
fn 第三步_通用复合标签100被别份占用即不拒() {
    let mut 台账 = 标准台账();
    // 第一份：换一个能力号段（免得后继声明撞号段），类型表里仍带 `100`。
    台账.登记标识串(钉住(合成样本占号段(号段::构造(3000, 3999))));
    // 后继声明：标识串与能力号段都与第一份不同，**只差「也报 100」这一处**。
    let 后继声明 = 合成样本带标识串(样本标识串次);
    assert_eq!(判定可装载(钉住(后继声明), &台账), Ok(()));
}
