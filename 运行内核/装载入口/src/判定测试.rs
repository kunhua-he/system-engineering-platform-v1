#[test]
fn 第六步_参数类型不在类型表里即拒() {
    // 合法域不按计数算（扩展从 `100` 起）：参数类型标签取 99 —— 它既不在样本声明
    // 的类型表（唯一一项的标签是 100）里，也不在底座类型表（0–7 · 4294967295）里
    // ⇒ 必须判「声明不自洽」。
    let 参数表 = Box::leak(
        vec![参数信息 {
            名称: 静态串("坏参数\0"),
            说明: 静态串("类型标签远超有效上界。\0"),
            类型标签: 类型标签::构造(99),
            状态位: 0,
            默认值: 数据槽::空槽(),
        }]
        .into_boxed_slice(),
    );
    let 命令表 = Box::leak(
        vec![命令信息 {
            名称: 静态串("坏命令\0"),
            说明: 静态串("带一个坏参数。\0"),
            类别号: 0,
            状态位: 0,
            返回类型: v1_contract::类型标签::构造(0),
            用户级别: 0,
            参数个数: 1,
            参数表: 参数表.as_ptr(),
            编号: 样本命令编号,
            可抛错误码: 表段::空实例(),
        }]
        .into_boxed_slice(),
    );
    let mut 合成样例 = 合成样本();
    合成样例.命令表 = 表段::构造(命令表.as_ptr(), 1);
    assert_eq!(
        判定可装载(钉住(合成样例), &标准台账()),
        Err(载入错误::声明不自洽 {
            命令号: 样本命令编号
        })
    );
}

