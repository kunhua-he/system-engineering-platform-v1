#[test]
fn 类型标签_复用底座已登记标签即拒() {
    // 标签 0（「空」）是底座登记过的 ⇒ 非底座声明不许再登记它。
    // 这条替换了原先的「未显式即拒」：那个变体判不到（「没填」与「填了 0」在运行期不可区分），
    // 而「不许复用已登记标签」对 0 与 1–6、u32::MAX 一视同仁。
    let 类型表 = Box::leak(
        vec![数据类型信息 {
            名称: 串("复用空标签的类型\0"),
            说明: 串("类型标签为 0，与底座的「空」重复。\0"),
            状态位: 0,
            命令个数: 0,
            命令号表: core::ptr::null(),
            事件个数: 0,
            事件表: core::ptr::null(),
            属性个数: 0,
            属性表: core::ptr::null(),
            元素个数: 0,
            元素表: core::ptr::null(),
            类型标签: 0,
        }]
        .into_boxed_slice(),
    );
    let mut 样本 = 合样本();
    样本.类型表 = 表段::新(类型表.as_ptr(), 1);
    assert_eq!(
        判定可装载(钉(样本), &标准台账()),
        Err(载入错误::类型标签与已登记重复 { 类型标签: 0, 类型序: 0 })
    );
}

