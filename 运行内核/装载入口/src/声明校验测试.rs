// ── 作废号门：逐条命令编号比（精确比，不整段封）────────────────────────
//
// 口径（已裁）：作废号是能力编号，只比**同空间**的号，且**精确比** ——
// 拿声明的每条命令编号去比，命中才红。早先判「声明的号段与作废号表**相交**」⇒
// 只要能力空间真作废了**底座申报的能力号段**里一个与命令不撞的号，底座整段又冲突。
//
// 生成物 `作废号表_能力` 当前为空 ⇒ 生产路径造不出这两条样本，故直接调
// `判命令编号不与作废号冲突(声明, 作废表)`（生产入口 `判不与作废号冲突` 调的就是它，
// 只是作废表取生成物）并注入一张合成表。

/// **反向样本（同空间空洞号不假红）**：作废一个**与任何命令都不撞**、但落在底座申报的
/// 能力号段内的号，不许报冲突 —— 旧「段相交」口径会因它落在号段内而假红。
#[test]
fn 作废号_同空间空洞号不假红() {
    let 声明 = 底座声明();
    let 底座命令号 = v1_contract::声明数据::能力编号_0000;
    // 前提由现算保证：注入的号必须真的落在申报号段内、且不与任何命令编号相撞。
    let 号段 = v1_contract::声明数据::底座能力号段[0];
    let 空洞号 = (号段.段起点.取号值()..=号段.段止.取号值())
        .find(|命令编号| *命令编号 != 底座命令号)
        .expect("底座申报的能力号段里必有与命令编号不同的号");
    assert_eq!(
        判命令编号不与作废号冲突(声明, &[空洞号]),
        Ok(()),
        "空洞号 {空洞号} 不与任何命令编号相撞，作废它不许把底座整段申报的号段判成冲突"
    );
}

/// **反向样本（真在用的命令编号必红）**：作废一条**真在用**的命令编号（底座命令号）⇒ 必须报冲突。
#[test]
fn 作废号_真在用的命令编号必红() {
    let 声明 = 底座声明();
    let 命令号 = v1_contract::声明数据::能力编号_0000;
    let 调用读数 = 判命令编号不与作废号冲突(声明, &[命令号]);
    assert!(
        matches!(调用读数, Err(载入错误::号段冲突 { .. })),
        "命令编号 {命令号} 真在用，作废它必须报号段冲突；实得 {调用读数:?}"
    );
}

/// **报的是那一个号，不是一整段**：命中时 `起 == 止 == 该命令编号`
/// （旧口径报的是**整段申报号段**，调用方看不出是哪条命令作废了）。
#[test]
fn 作废号_报的是那一个号不是整段() {
    let 声明 = 底座声明();
    let 命令号 = v1_contract::声明数据::能力编号_0000;
    assert_eq!(
        判命令编号不与作废号冲突(声明, &[命令号]),
        Err(载入错误::号段冲突 { 段起点: 命令号, 段止: 命令号 })
    );
}
