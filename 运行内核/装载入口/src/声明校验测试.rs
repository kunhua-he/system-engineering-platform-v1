#[test]
fn 类型标签_表内重复即拒() {
    let 造类型 = |名: &'static str| 数据类型信息 {
        名称: 串(名),
        说明: 串("重复标签。\0"),
        状态位: 0,
        命令个数: 0,
        命令号表: core::ptr::null(),
        事件个数: 0,
        事件表: core::ptr::null(),
        属性个数: 0,
        属性表: core::ptr::null(),
        元素个数: 0,
        元素表: core::ptr::null(),
        类型标签: 100,
    };
    let 类型表 = Box::leak(vec![造类型("类型甲\0"), 造类型("类型乙\0")].into_boxed_slice());
    let mut 样本 = 合样本();
    样本.类型表 = 表段::新(类型表.as_ptr(), 2);
    assert_eq!(
        判定可装载(钉(样本), &标准台账()),
        Err(载入错误::类型标签重复 {
            类型标签: 100,
            序: 1,
            另序: 0,
        })
    );
}
