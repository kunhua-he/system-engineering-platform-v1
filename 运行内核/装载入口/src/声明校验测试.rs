/// **反向样本（参数个数无上限）**：`参数个数 = u32::MAX` 的命令。
///
/// 修前：自洽判定放过它，随后 `for 参数序 in 0..命令.参数个数` 逐个解引用参数表 ⇒ 越界
/// （配 `panic = "abort"` 即整进程死）。修后：在自洽判定这一步就拿到 `声明不自洽`。
#[test]
fn 自洽_参数个数超上限即拒() {
    let mut 声明样本 = 合成样本();
    // 取声明样本那条命令（按位拷一份；原数组随即被覆盖，不会双重释放），
    // 只把 `参数个数` 改成 `u32::MAX`（其余逐字照旧），再钉回声明。
    let 旧命令 = unsafe { core::ptr::read(声明样本.命令表.项表) };
    let 坏命令 = Box::leak(Box::new([命令信息 { 参数个数: u32::MAX, ..旧命令 }]));
    声明样本.命令表 = 表段::构造(坏命令.as_ptr(), 1);
    assert_eq!(
        判定可装载(钉住(声明样本), &标准台账()),
        Err(载入错误::声明不自洽 { 命令号: 样本命令编号 }),
    );
}

// ── 作废号只比**同空间**的号（四个号空间各自独立）──────────────────────
//
// 口径：作废行按号空间分账，能力编号 `0xxx` 与错误码「段位 × 1000 + 序号」只是数字上撞了
// 同一个数，不是同一个号。全局封禁会把两个空间的同号混为一谈（假冲突）。

/// **反向样本（跨空间不作废）**：错误码空间作废的号若数字上落在底座能力号段内，
/// **不许**污染能力号段 —— 底座必须照样载得进来。
///
/// 前提由**生成物现算**（不写死某个数）：错误码空间里得真有一个号落在底座能力号段内，
/// 否则这条反证无前提、当场报红让人补。
#[test]
fn 跨空间作废_错误码空间的作废号不污染能力号段() {
    let 底座能力段 = v1_contract::声明数据::底座能力号段[0];
    let 跨空间同号: Vec<u32> = v1_contract::声明数据::作废号表_错误码
        .iter()
        .copied()
        .filter(|错误码| 底座能力段.包含(号值::构造(*错误码)))
        .collect();
    assert!(
        !跨空间同号.is_empty(),
        "错误码空间里得有一个作废号落在底座能力号段 {:?} 内，这条反证才有前提",
        底座能力段
    );
    assert_eq!(
        判定可装载(底座声明(), &载入台账::空实例()),
        Ok(()),
        "错误码空间作废了 {跨空间同号:?}，但那是另一个空间，不许判成能力号段的冲突"
    );
}

