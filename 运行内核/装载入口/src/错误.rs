//! 载入错误：与判定六步一一对应。**每一条都是结构化变体，不许只报 `false`。**

use v1_registry::建表错误;
use v1_contract::{能力号, 错误码, 类型标签};

/// 载入错误：与判定六步一一对应。**每一条都是结构化变体，不许只报 `false`。**
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 载入错误 {
    /// ① 声明格式号不匹配。名字逐字取 `契约声明/错误码表/0006.json`（码表是名称的唯一登记处，
    /// 见 `契约声明/格式说明.md` §五）；`建表错误` 的同一条也改成了这个名字 —— 同一个失败不换名。
    声明格式号不匹配 { 期望: u32, 实际: u32 },
    /// ② 标识串为空 / 形状不符 / 冒用底座身份 / 已在台账里（跨扩展重名）。
    标识串非法,
    /// ③ 号段与已载入扩展或作废号表冲突。
    号段冲突 { 段起点: u32, 段止: u32 },
    /// ③ 号段表自身不合法：某段 `起 > 止`，或表段形状不可用（项数 > 0 却给空项表）。
    号段非法 { 所属表名: &'static str, 项位次: u32 },
    /// ③ 同一张号段表内两段相交（`序` 与 `另序` 两段重叠）。
    号段表内重叠 { 所属表名: &'static str, 项位次: u32, 另序: u32 },
    /// ④ 要求宿主版本 / 要求内核版本不满足。
    /// **报主版本**（最粗、最能说明「哪一代不够」）；宿主与内核两处共用本分支。
    /// 比对的是 `版本要求`（两段 `i32`，无修订段）的主段 ⇒ 载荷是 `i32`。
    要求版本不满足 { 要求: i32, 实际: i32 },
    /// ④′ 声明的**目标字宽**与宿主实际字宽不等。
    ///
    /// 表指针宽度随目标字宽变（`平台信息` 里唯一随目标变宽的字段），宿主按本机字宽去读
    /// 另一字宽的表指针必然错位 ⇒ 判定若放行，就是「先执行后爆」。故在 ④ 之后、⑤ 之前
    /// 执行前即拒（**不 panic**，走结构化变体）。
    ///
    /// 与制品侧的 `本机平台身份`（`适配器实现/src/模块执行体装载.rs`）**不是一件事**：
    /// 此处判的是**宿主字宽**（声明写「我这份表指针按几字节排」），制品侧判的是**制品构建目标**
    /// （三元组 `架构-系统`）。声明侧的平台可判只有字宽这一项 —— 声明里没有架构 / 系统字段。
    ///
    /// 对应登记码 **36**（`契约声明/错误码表/0036.json`，名称逐字「平台字宽不匹配」）。
    平台字宽不匹配 { 声明: u16, 宿主: u16 },
    /// ⑤ 依赖清单里的扩展不在（或清单本身不合法：形状不符 · 重复 · 自依赖）。
    依赖缺失,
    /// ⑥ 声明自洽失败（命令编号越出本声明申报的能力号段、参数类型不在类型表、
    /// 错误段位未登记、编号重复）。
    声明不自洽 { 命令号: 能力号 },
    /// ⑥ 错误段位表为空（或表段形状不可用）——没有它，「未登记的段位不许抛出」判不了。
    错误段位表为空,
    /// ⑥ 错误段位表里段位重复。
    错误段位重复 { 段位: u32 },
    /// ⑥ 类型标签复用了**底座已登记**的标签。
    ///
    /// 底座自身就是那张内置标签注册表（`0`=空 · `1–6`=整数/双精度/逻辑型/文本/字节集/句柄 ·
    /// `4294967295`=错误），所以**任何非底座声明都不许再登记这些标签**——包括 `0`。
    ///
    /// **为什么不做成「底座例外」**：例外会繁殖。真正的规则是「不许复用已登记的标签」，
    /// 它对所有声明一视同仁，`0` 只是其中一个实例。原变体 `类型标签未显式` 已删——
    /// 它判不到：「标签没填」与「填了 0」在运行期不可区分（JSON 里 `类型标签` 是必填键，
    /// 缺键由验证面抓），留着就是一条永远判不准的判据。
    ///
    /// 它对应的登记码是 **32**（`契约声明/错误码表/0032.json`，名称逐字「类型标签与已登记重复」）；
    /// 旧码 **16**「类型标签未显式」已进 `契约声明/作废号表.json`（**作废不是改名**——旧语义
    /// 已不存在；依据 `项目文档/决策记录/2026-09-27_三条裁决_按稳定性判.md` 裁决 二：
    /// 加新码、旧的作废，号段分层且永不复用）。**不许把本变体改叫那个旧名**：
    /// 本变体覆盖 `0`–`6` 与 `4294967295`，旧名只描述 `== 0`，改了就是复活一条已删的判据。
    类型标签与已登记重复 { 类型标签: 类型标签, 类型序: u32 },
    /// ⑥ 声明的类型表 / 命令 / 常量引用了**合法域之外**的类型标签。
    ///
    /// 合法域 = **本声明类型表 ∪ 底座已登记标签 ∪ 通用复合标签（`100`–`103`）**。
    /// 越域即拒，且**具名报出是哪个标签**（与旧写法一律报裸 `声明不自洽` 不同）：
    /// 类型标签是**按扩展归属**的号（`契约声明/号段图.json::类型号段`），
    /// 跨扩展引用别的扩展私有的标签不受允许 —— 唯一的两类共享是底座内置标签
    /// 与通用复合标签（`2026-10-12_复合类型槽载荷裁决.md` §九：平台不拥有这四个号）。
    ///
    /// 对应登记码 **37**（`契约声明/错误码表/0037.json`，名称逐字「类型引用越域」）。
    类型引用越域 { 类型标签: 类型标签 },
    /// ⑥ 某条命令的 `可抛错误码` 里有一项在本声明错误码表与底座错误码表**都没有登记**。
    ///
    /// 错误码与类型标签同属「按扩展归属」的号空间：该码在平台侧无处登记 ⇒ 抛出时
    /// 调用方拿不到 `可重试 / 可自愈 / 需人工` 三项（`契约声明/格式说明.md` §三 的
    /// `可抛错误码` 行：「每一项都必须能在错误码表里查到，未登记的不许声明」）。
    /// **具名报出是哪个码**（不是笼统的 `声明不自洽`）。
    ///
    /// 对应登记码 **38**（`契约声明/错误码表/0038.json`，名称逐字「可抛码未登记」）。
    可抛码未登记 { 错误码: 错误码 },
    /// ⑥ 类型标签在表内重复（`序` 与 `另序` 两个类型共用同一标签）。
    类型标签重复 { 类型标签: 类型标签, 项位次: u32, 另序: u32 },
    /// 建表失败（见 `建表错误`）。
    建表(建表错误),
}
