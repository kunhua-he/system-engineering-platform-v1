//! 装载：判定通过后建注册表 + `已载入台账` 的具体实现。
//!
//! 台账是「跨扩展三项判定」的落点：**不落进程级全局**（`开发规范.md` B6：状态是句柄），
//! 由调用方显式持有；同进程里开多少份台账都互不串。

use crate::判定::判定可装载;
use crate::底座静态声明::底座声明;
use crate::读数::{标识串字节数, 读号段表, 读串};
use crate::错误::载入错误;
use v1_contract::{号段, 号段空间, 已载入台账, 平台信息, 类型标签, 版本三元组};
use v1_registry::统一注册表;

/// 载入声明：判定通过后建注册表。
///
/// **不许半载**：六步全过才交给 `注册表::建表`；建表失败即整体失败（错误转成
/// `载入错误::建表`），不留下任何半个注册表。
///
/// 签名收 `&'static 平台信息`：下游 `注册表::建表` 冻结签名要求 `'static`（注册表长期
/// 持有指向声明静态表的切片），本函数必须原样转交。`台账` 收 `&dyn`（只读）——载入成功后
/// 「把这份声明记进台账」由调用方调 `载入台账::登记标识串` 完成。
pub fn 载入声明(声明: &'static 平台信息, 台账: &dyn 已载入台账) -> Result<统一注册表, 载入错误> {
    判定可装载(声明, 台账)?;
    统一注册表::建表(声明).map_err(载入错误::建表)
}

// ════════════════════════════════════════════════════════════════════════════
// 载入台账：`已载入台账` 的具体实现
// ════════════════════════════════════════════════════════════════════════════

/// 已载入项：台账的一行 —— 一份已载入的声明「是谁」与「它自报什么版本」。
///
/// **两样一起记**：版本查询口 `已载入版本` 答的就是这里的 `实现版本`；
/// 不记版本的话，判定 ⑤ 的版本比对就没有「实际是多少」这一半（`契约声明/冻结登记.json`
/// 待办旁路原记该缺口）。
#[derive(Clone, Copy)]
pub struct 已载入项 {
    /// 标识串（不含 NUL 的 32 字节）。
    标识串: [u8; 标识串字节数],
    /// 这份声明自报的 `平台信息.实现版本` —— 判「依赖的版本够不够」的被比一方。
    实现版本: 版本三元组,
}

/// 已载入台账的具体实现：两本账 —— 已载入标识串 + 已占号段。
///
/// 号段按**命名空间分两本**（能力 / 通知），因为两者是独立命名空间
/// （`格式说明.md` 第二节）。内部一律用普通结构体字段，**不落进程级 `static`**
/// （`开发规范.md` B6：状态是句柄）——所以同进程里开多少份台账都互不串。
pub struct 载入台账 {
    /// 已载入的项（标识串 + 它自报的实现版本）。
    已载入项表: Vec<已载入项>,
    /// 已占的能力号段。
    能力号段表: Vec<号段>,
    /// 已占的通知号段。
    通知号段表: Vec<号段>,
    /// 已占的**类型标签**（第五个号空间，离散，不是号段）。
    类型标签表: Vec<类型标签>,
}

impl 载入台账 {
    /// 空台账（什么都不占）。
    ///
    /// 用途：判**底座自身的声明**时，台账里还不该有底座自身——否则 ② 会把它当成重名。
    pub fn 空实例() -> Self {
        Self {
            已载入项表: Vec::new(),
            能力号段表: Vec::new(),
            通知号段表: Vec::new(),
            类型标签表: Vec::new(),
        }
    }

    /// 标准台账：**先把底座自身的占用预置进去**。
    ///
    /// 预置的内容取自底座静态声明本身（标识串 = 底座标识串；号段 = 底座自占的
    /// `0..999` 能力段与 `2000..2999` 生命周期通知段），不另抄一份常量。
    /// **不预置的话，第一个扩展就会撞上底座，而台账会误判为「没人占」。**
    pub fn 构造() -> Self {
        let mut 台账 = Self::空实例();
        台账.登记标识串(底座声明());
        台账
    }

    /// 把一份**已载入**的声明记进台账：标识串 + **实现版本** + 能力号段 + 通知号段。
    ///
    /// **载入成功后由调用方调**：`载入声明` 收的是 `&dyn 已载入台账`（只读），改不了台账。
    ///
    /// # Safety 契约（调用方须保证）
    ///
    /// `声明` 的串与表段按契约指向静态只读数据（与 `判定可装载` 同一前提）。
    pub fn 登记标识串(&mut self, 声明: &平台信息) {
        if let Some(字节串) = unsafe { 读串(声明.标识串, 标识串字节数 + 1) }
            && let Ok(定长) = <[u8; 标识串字节数]>::try_from(字节串)
            && !self.已载入项表.iter().any(|已载| 已载.标识串 == 定长)
        {
            // 版本与标识串**同一次**记进去：判定 ⑤ 拿它比「依赖的版本够不够」。
            self.已载入项表.push(已载入项 { 标识串: 定长, 实现版本: 声明.实现版本 });
        }
        self.能力号段表.extend(读号段表(声明.能力号段));
        self.通知号段表.extend(读号段表(声明.通知号段));
        for 类型序 in 0..声明.类型表.表项数 as usize {
            // SAFETY: 与 `声明校验.rs::判声明自洽` 同一前提（类型表项数 > 0 则项表非空）。
            self.类型标签表.push(unsafe { (*声明.类型表.项表.add(类型序)).类型标签 });
        }
    }

    /// 已载入的标识串个数（验证面用）。
    pub fn 已载入数(&self) -> usize {
        self.已载入项表.len()
    }

    /// 把一份声明从台账里**注销**：身份串 + 它占的能力/通知号段 + 类型标签。
    ///
    /// 与 [`载入台账::登记标识串`] 是**同一件事的两面**（登记 / 注销），卸载时由调用方调——
    /// 不注销的话，同一身份就永远重载不进来（判定 ② 报「标识串非法」），而它的号段也永远占着。
    /// **类型标签同理**：登记时收进账、注销时不摘的话，同一份声明重新载入会在 ③ 报
    /// 「号段冲突」（本条声明的标签与自身撞）——与身份串 / 号段是同一类后果。
    ///
    /// **只注销这一份占的**：号段按段值逐条摘（`retain`），不整表清——台账可能装着多份声明，
    /// 整表清就是「卸载一个把别人也卸了」。身份串不在表里（未载过）时什么都不做（幂等）。
    ///
    /// # Safety 契约（调用方须保证）
    /// `声明` 的串与表段按契约指向静态只读数据（与 `登记标识串` 同一前提）。
    pub fn 注销标识串(&mut self, 声明: &平台信息) {
        if let Some(字节串) = unsafe { 读串(声明.标识串, 标识串字节数 + 1) }
            && let Ok(定长) = <[u8; 标识串字节数]>::try_from(字节串)
        {
            self.已载入项表.retain(|已载| 已载.标识串 != 定长);
        }
        for 号段项 in 读号段表(声明.能力号段) {
            self.能力号段表.retain(|已占| *已占 != 号段项);
        }
        for 号段项 in 读号段表(声明.通知号段) {
            self.通知号段表.retain(|已占| *已占 != 号段项);
        }
        for 类型序 in 0..声明.类型表.表项数 as usize {
            // SAFETY: 与 `登记标识串` 同一前提（类型表项数 > 0 则项表非空）。
            let 标签 = unsafe { (*声明.类型表.项表.add(类型序)).类型标签 };
            self.类型标签表.retain(|已占| *已占 != 标签);
        }
    }
}

impl 已载入台账 for 载入台账 {
    // 冻结 trait 的签名就是 `fn 是否已载入(&self, 标识串: *const u8) -> bool`（安全 fn + 裸指针）。
    // 契约规定这个指针是静态只读 NUL 结尾串；改不了 trait（不在本 crate），故在此显式放行该 lint。
    #[allow(clippy::not_unsafe_ptr_arg_deref)]
    fn 是否已载入(&self, 标识串: *const u8) -> bool {
        // SAFETY: 由契约保证 标识串 要么为空、要么指向静态只读 NUL 结尾串。
        let Some(字节串) = (unsafe { 读串(标识串, 标识串字节数 + 1) }) else {
            return false;
        };
        let Ok(定长) = <[u8; 标识串字节数]>::try_from(字节串) else {
            return false;
        };
        self.已载入项表.iter().any(|已载| 已载.标识串 == 定长)
    }

    /// **已载入的那一份是什么版本** —— `无` = 这个标识串没载入过。
    ///
    /// 与 `是否已载入` 同源（同一本账）：两问都落在这张表上，但问的不是一件事 ——
    /// 「没载入」与「载入了但版本 0.0.0」必须分得开，故这里返 `Option`。
    /// 判定 ⑤ 的版本比对只有这一个取数口。
    #[allow(clippy::not_unsafe_ptr_arg_deref)]
    fn 已载入版本(&self, 标识串: *const u8) -> Option<版本三元组> {
        // SAFETY: 由契约保证 标识串 要么为空、要么指向静态只读 NUL 结尾串。
        let 字节串 = (unsafe { 读串(标识串, 标识串字节数 + 1) })?;
        let 定长 = <[u8; 标识串字节数]>::try_from(字节串).ok()?;
        self.已载入项表
            .iter()
            .find(|已载| 已载.标识串 == 定长)
            .map(|已载| 已载.实现版本)
    }

    /// 按 `空间` **分账精确**判：能力号与通知号是两个独立命名空间，同一个 `[起, 止]`
    /// 在两个空间里可以各占一次，不算冲突。**不取并集**——并集会产生假冲突
    /// （「扩展占能力 2000–2999」会被「底座占通知 2000–2999」误拦，合法扩展载不进来）。
    fn 号段已占用(&self, 号空间: 号段空间, 区间起点: v1_contract::号值, 区间终点: v1_contract::号值) -> bool {
        let 号段账 = match 号空间 {
            号段空间::能力号 => &self.能力号段表,
            号段空间::通知号 => &self.通知号段表,
        };
        let 号段 = 号段 { 段起点: 区间起点, 段止: 区间终点 };
        号段账.iter().any(|已占号段| 已占号段.相交(&号段))
    }

    fn 类型标签已占用(&self, 标签: 类型标签) -> bool {
        self.类型标签表.contains(&标签)
    }
}

