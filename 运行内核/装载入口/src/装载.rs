//! 装载：判定通过后建注册表 + `已载入台账` 的具体实现。
//!
//! 台账是「跨扩展三项判定」的落点：**不落进程级全局**（`开发规范.md` B6：状态是句柄），
//! 由调用方显式持有；同进程里开多少份台账都互不串。

use crate::判定::判定可装载;
use crate::底座静态声明::底座声明;
use crate::读数::{标识串字节数, 读号段表, 读串};
use crate::错误::载入错误;
use v1_contract::{号段, 号段空间, 已载入台账, 平台信息};
use v1_registry::统一注册表;

/// 载入声明：判定通过后建注册表。
///
/// **不许半载**：六步全过才交给 `注册表::建表`；建表失败即整体失败（错误转成
/// `载入错误::建表`），不留下任何半个注册表。
///
/// 签名收 `&'static 平台信息`：下游 `注册表::建表` 冻结签名要求 `'static`（注册表长期
/// 持有指向声明静态表的切片），本函数必须原样转交。`台账` 收 `&dyn`（只读）——载入成功后
/// 「把这份声明记进台账」由调用方调 `载入台账::登记标识串` 完成。
pub fn 载入声明(声明: &'static 平台信息, 台账: &dyn 已载入台账) -> Result<统一注册表, 载入错误> {
    判定可装载(声明, 台账)?;
    统一注册表::建表(声明).map_err(载入错误::建表)
}

// ════════════════════════════════════════════════════════════════════════════
// 载入台账：`已载入台账` 的具体实现
// ════════════════════════════════════════════════════════════════════════════

/// 已载入台账的具体实现：两本账 —— 已载入标识串 + 已占号段。
///
/// 号段按**命名空间分两本**（能力 / 通知），因为两者是独立命名空间
/// （`格式说明.md` 第二节）。内部一律用普通结构体字段，**不落进程级 `static`**
/// （`开发规范.md` B6：状态是句柄）——所以同进程里开多少份台账都互不串。
pub struct 载入台账 {
    /// 已载入的标识串（不含 NUL 的 32 字节）。
    标识串表: Vec<[u8; 标识串字节数]>,
    /// 已占的能力号段。
    能力号段表: Vec<号段>,
    /// 已占的通知号段。
    通知号段表: Vec<号段>,
}

impl 载入台账 {
    /// 空台账（什么都不占）。
    ///
    /// 用途：判**底座自身的声明**时，台账里还不该有底座自身——否则 ② 会把它当成重名。
    pub fn 空实例() -> Self {
        Self {
            标识串表: Vec::new(),
            能力号段表: Vec::new(),
            通知号段表: Vec::new(),
        }
    }

    /// 标准台账：**先把底座自身的占用预置进去**。
    ///
    /// 预置的内容取自底座静态声明本身（标识串 = 底座标识串；号段 = 底座自占的
    /// `0..999` 能力段与 `2000..2999` 生命周期通知段），不另抄一份常量。
    /// **不预置的话，第一个扩展就会撞上底座，而台账会误判为「没人占」。**
    pub fn 新建() -> Self {
        let mut 台账 = Self::空实例();
        台账.登记标识串(底座声明());
        台账
    }

    /// 把一份**已载入**的声明记进台账：标识串 + 能力号段 + 通知号段。
    ///
    /// **载入成功后由调用方调**：`载入声明` 收的是 `&dyn 已载入台账`（只读），改不了台账。
    ///
    /// # Safety 契约（调用方须保证）
    ///
    /// `声明` 的串与表段按契约指向静态只读数据（与 `判定可装载` 同一前提）。
    pub fn 登记标识串(&mut self, 声明: &平台信息) {
        if let Some(字节串) = unsafe { 读串(声明.标识串, 标识串字节数 + 1) }
            && let Ok(定长) = <[u8; 标识串字节数]>::try_from(字节串)
            && !self.标识串表.contains(&定长)
        {
            self.标识串表.push(定长);
        }
        self.能力号段表.extend(读号段表(声明.能力号段));
        self.通知号段表.extend(读号段表(声明.通知号段));
    }

    /// 已载入的标识串个数（验证面用）。
    pub fn 已载入数(&self) -> usize {
        self.标识串表.len()
    }
}

impl 已载入台账 for 载入台账 {
    // 冻结 trait 的签名就是 `fn 是否已载入(&self, 标识串: *const u8) -> bool`（安全 fn + 裸指针）。
    // 契约规定这个指针是静态只读 NUL 结尾串；改不了 trait（不在本 crate），故在此显式放行该 lint。
    #[allow(clippy::not_unsafe_ptr_arg_deref)]
    fn 是否已载入(&self, 标识串: *const u8) -> bool {
        // SAFETY: 由契约保证 标识串 要么为空、要么指向静态只读 NUL 结尾串。
        let Some(字节串) = (unsafe { 读串(标识串, 标识串字节数 + 1) }) else {
            return false;
        };
        let Ok(定长) = <[u8; 标识串字节数]>::try_from(字节串) else {
            return false;
        };
        self.标识串表.contains(&定长)
    }

    /// 按 `空间` **分账精确**判：能力号与通知号是两个独立命名空间，同一个 `[起, 止]`
    /// 在两个空间里可以各占一次，不算冲突。**不取并集**——并集会产生假冲突
    /// （「扩展占能力 2000–2999」会被「底座占通知 2000–2999」误拦，合法扩展载不进来）。
    fn 号段已占用(&self, 空间: 号段空间, 区间起点: v1_contract::号值, 区间终点: v1_contract::号值) -> bool {
        let 号段账 = match 空间 {
            号段空间::能力号 => &self.能力号段表,
            号段空间::通知号 => &self.通知号段表,
        };
        let 号段 = 号段 { 段起点: 区间起点, 止: 区间终点 };
        号段账.iter().any(|已占号段| 已占号段.相交(&号段))
    }
}

// ════════════════════════════════════════════════════════════════════════════
// 跨扩展三项判定（台账）—— 已收口
// ════════════════════════════════════════════════════════════════════════════
//
// `扩展装载与开发标准.md` 2.3 的 ②「没有第二个同身份的扩展」、③「与已载入扩展不冲突」、
// ⑤「依赖清单里的扩展都在」，判据都指向**已载入台账**。本回合已收口：
//
// - `判定可装载(声明, 台账)` / `载入(声明, 台账)` 都收 `&dyn 已载入台账`，三项真的走它；
// - 台账由调用方显式持有（`载入台账` 用 `Vec` 字段，不落进程级 `static`，多实例安全）；
// - `载入台账::新建()` 预置底座自身的占用，避免第一个扩展被误判「没人占」。
//
// **已收口**：trait `已载入台账` 的 `号段已占用` 现在带 `号段空间`（能力号 / 通知号），
// 故 ③ 按空间分账精确判、不取并集（并集会产生假冲突，见 crate 头）。
// 不采用「给号段打命名空间标签」那条路——`号段` 是 `平台信息` 的冻结旁路字段，
// 给它加字段等于改冻结形状。

