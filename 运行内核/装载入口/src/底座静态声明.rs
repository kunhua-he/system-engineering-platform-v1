/// 命令 0 的执行函数：把底座契约主结构指针放进返回槽。
///
/// 形状 1:1 复刻：`(返回槽, 参数个数, 参数表) -> ()`，返回 void；失败靠错误段位。
unsafe extern "C" fn 底座取平台信息(
    返回槽: *mut 数据槽,
    参数个数: u32,
    参数表: *const 数据槽,
) {
    let _ = (参数个数, 参数表);
    if 返回槽.is_null() {
        return;
    }
    // SAFETY: 返回槽 由调用方保证可写；指针指向静态数据，终生有效，不交出所有权。
    unsafe {
        *返回槽 = 数据槽::指针(
            0,
            取平台信息() as u64,
            core::mem::size_of::<平台信息>() as u64,
            false,
        );
    }
}

/// 底座的执行函数表：与命令表一一对应，**不许留空指针**。
static 底座函数表: [执行函数; 1] = [底座取平台信息];

/// 底座的通知函数：**只接受自己声明的那一段**（`底座通知号段`，生命周期 2000–2999），
/// 段外一律失败。
///
/// 为什么只收一段：底座声明里 `通知号段` 只有 `2000–2999`。声明之外的号也照收，
/// 就是**声明与实现不一致**——声明说占哪段，实现就得只认哪段（号段即归属）。
/// 这里直接读生成物的 `底座通知号段`，不另抄一份区间常量（抄了就是第二来源）。
unsafe extern "C" fn 底座通知(通知号: u32, 参数一: usize, 参数二: usize) -> isize {
    let _ = (参数一, 参数二);
    if v1_contract::声明数据::底座通知号段.iter().any(|段| 段.含(通知号)) {
        通知返回::成功
    } else {
        通知返回::失败
    }
}

/// 带 `Sync` 的声明外壳。
///
/// 跨边界结构里有裸指针 ⇒ 类型本身不是 `Sync`，而 `static` 要求 `Sync`。
/// 内容全是**静态只读**数据，对外只给出 `*const` 指针，任何一方都不得写。
#[repr(transparent)]
struct 静态声明(平台信息);

// SAFETY: 底座静态声明一旦构造即终生不变；不提供任何 &mut 通道，
// 导出符号只交出 *const 指针，故多线程共享只读是安全的。
unsafe impl Sync for 静态声明 {}

impl 静态声明 {
    const fn 取(&self) -> &平台信息 {
        &self.0
    }
}

/// 底座自己的静态 `平台信息`。**唯一实例**：导出符号返回它的地址。
