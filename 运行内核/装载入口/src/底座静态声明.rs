/// ③g 落点：命令表的项数。**值只有一个来源**——`底座命令表` 的数组长就是它。
const 命令表项数: usize = 1;

/// ③g 落点：函数表的项数。**故意与 `命令表项数` 各写一处**（不互相引用）：
/// ③g 判的是「两表等长」，两个数各写一处，判据面一比对就能看出「只改了一边」；
