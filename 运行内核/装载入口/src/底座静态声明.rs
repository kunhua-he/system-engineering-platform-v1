/// ③h 落点：**已核条数** = 编译器逐条核过「参数表项数 == 参数个数」的命令条数。
const 参数个数已核条数: usize = 1;

// ★ **这个洞拦不住什么（2026-09-28 补 · `项目文档/决策记录/2026-09-27_残留三项裁决.md`
// §三 落法①）**：③h 是一般式的**逐条展开**；`参数个数已核条数` 与逐条断言**必须同批改**，
// **只改前者不加断言本文件拦不住**（末条 `已核条数 == 命令表.len()` 照样成立）。
// 缺口由「处数判据」关小：`测试验证/契约一致性/扫实现/判据落点.py::比落点` 读
// `测试验证/契约一致性/处数基线.json`，钉住本单元的「已核条数 的值」与「逐条断言的行数」
// —— 实测 ≠ 登记即红。「两处同改」须**故意**（改源码 + 改基线）才过。**边界**：不消除
// 「故意同时改两处」—— 那是人在骗门禁，不是门禁的洞。

// ③h 编译期断言：逐条核「该条的 参数个数 == 它引用的参数表项数」。
// 为什么逐条列名（而不是循环遍历命令表）：`命令信息.参数表` 是**裸指针**，
// 编译期取不到被指数组的长度（const 求值不许比较指针）。
const _: () = {
    assert!(底座命令表[0].参数个数 as usize == 底座参数表.len(), "③h：编号 0 的 参数个数 与 底座参数表 项数不符");
    // 断言条数与表长必须相等：加一条命令就必须加一条断言，漏了这里当场编译不过。
    assert!(参数个数已核条数 == 底座命令表.len(), "③h：已核条数 与 命令表项数 不符 —— 加了命令没加断言");
};

/// 底座的通知函数：**只接受自身声明的那一段**（`底座通知号段`，生命周期 2000–2999），
/// 段外一律失败。
///
/// 为什么只收一段：底座声明里 `通知号段` 只有 `2000–2999`。声明之外的号也照收，
/// 就是**声明与实现不一致**——声明说占哪段，实现就得只认哪段（号段即归属）。
/// 这里直接读生成物的 `底座通知号段`，不另抄一份区间常量（抄了就是第二来源）。
unsafe extern "C" fn 底座通知(通知号: v1_contract::通知号, 参数一: usize, 参数二: usize) -> isize {
    let _ = (参数一, 参数二);
    if v1_contract::声明数据::底座通知号段.iter().any(|段| 段.含(号值::新(通知号.取()))) {
        通知返回::成功
    } else {
        通知返回::失败
    }
}

/// 带 `Sync` 的声明外壳。
///
/// 跨边界结构里有裸指针 ⇒ 类型本身不是 `Sync`，而 `static` 要求 `Sync`。
/// 内容全是**静态只读**数据，对外只给出 `*const` 指针，任何一方都不得写。
#[repr(transparent)]
struct 静态声明(平台信息);

// SAFETY: 底座静态声明一旦构造即终生不变；不提供任何 &mut 通道，
// 导出符号只交出 *const 指针，故多线程共享只读是安全的。
unsafe impl Sync for 静态声明 {}

impl 静态声明 {
    const fn 取平台信息(&self) -> &平台信息 {
        &self.0
    }
}

