/// 这个声明是不是**底座自己的**静态声明（按地址认，不按内容认）。
pub(crate) fn 是底座自有声明(声明: &平台信息) -> bool {
    core::ptr::eq(声明 as *const 平台信息, 取平台信息())
}

/// 底座类型表里的类型个数（判定 ⑥ 的合并空间用）。
pub(crate) fn 底座类型数() -> u32 {
    底座存储.取().类型表.项数
}

