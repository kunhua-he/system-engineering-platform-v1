/// 样本的标识串（与底座身份不同）。
pub(crate) const 样本标识串: &[u8] = b"11223344556677889900aabbccddeeff\0";
/// 第二份样本的标识串（测「两份不同扩展」用）。
pub(crate) const 样本标识串次: &[u8] = b"fedcba9876543210fedcba9876543210\0";

/// 一份**六步全过**的样本声明（每步失败的样本都由它改一处得到）。
pub(crate) const 样本能力号段: [号段; 1] = [号段::构造(1000, 1999)];
/// 样本的命令编号：**取号段的 `起`**，不写字面量 —— 换号段调用（`合成样本占号段`）时
/// 编号得跟着走，否则又越界。口径见
/// `项目文档/决策记录/2026-09-27_接缝反解与1对1的边界.md` §二 裁决 5。
pub(crate) const 样本命令编号: 能力号 = 能力号::构造(样本能力号段[0].段起点.取号值());
pub(crate) const 样本错误段位表: [u32; 1] = [1];

pub(crate) fn 合成样本() -> 平台信息 {
    合成样本带标识串(样本标识串)
}

/// 同 `合成样本`，但换一个标识串（测跨扩展重名 / 依赖用）。
pub(crate) fn 合成样本带标识串(标识串: &'static [u8]) -> 平台信息 {
    造样本(标识串, 样本能力号段[0], 样本命令编号)
}

/// 同 `合成样本`，但换一个**申报号段**；命令编号随之取 `段.起`（仍落在号段内）。
pub(crate) fn 合成样本占号段(号段: 号段) -> 平台信息 {
    造样本(样本标识串, 号段, 能力号::构造(号段.段起点.取号值()))
}

/// 同 `合成样本`，但分别指定申报号段与命令编号（造「编号越界 / 边界」反向样本用）。
pub(crate) fn 合成样本占号段与编号(号段: 号段, 命令编号: 能力号) -> 平台信息 {
    造样本(样本标识串, 号段, 命令编号)
}

/// 样本声明的唯一构造口：号段与命令编号都从形参来，三者（号段 · 命令编号 ·
/// 类型认领的命令号）**只有一个来源**，改一处即三者同步。
fn 造样本(标识串: &'static [u8], 号段: 号段, 命令编号: 能力号) -> 平台信息 {
    let 命令号表 = Box::leak(vec![命令编号.取号值()].into_boxed_slice());
    let 参数表 = Box::leak(
        vec![参数信息 {
            名称: 静态串("目标字宽\0"),
            说明: 静态串("样本参数。\0"),
            类型标签: v1_contract::类型标签::构造(0),
            状态位: 0,
            默认值: 数据槽::空槽(),
        }]
        .into_boxed_slice(),
    );
    let 类型表 = Box::leak(
        vec![数据类型信息 {
            名称: 静态串("样本类型\0"),
            说明: 静态串("样本类型。\0"),
            状态位: 0,
            命令个数: 1,
            命令号表: 命令号表.as_ptr(),
            事件个数: 0,
            事件表: core::ptr::null(),
            属性个数: 0,
            属性表: core::ptr::null(),
            元素个数: 0,
            元素表: core::ptr::null(),
            类型标签: v1_contract::类型标签::构造(100),
        }]
        .into_boxed_slice(),
    );
    let 命令表 = Box::leak(
        vec![命令信息 {
            名称: 静态串("样本命令\0"),
            说明: 静态串("样本命令。\0"),
            类别号: 0,
            状态位: 0,
            返回类型: v1_contract::类型标签::构造(0),
            用户级别: 0,
            参数个数: 1,
            参数表: 参数表.as_ptr(),
            编号: 命令编号,
            可抛错误码: 表段::空实例(),
        }]
        .into_boxed_slice(),
    );
    let 常量表 = Box::leak(
        vec![常量信息 {
            名称: 静态串("样本常量\0"),
            说明: 静态串("样本常量。\0"),
            排布: 常量排布::数值项,
            类型标签: v1_contract::类型标签::构造(0),
            文本值: core::ptr::null(),
            数值项: 1.0,
            常量号: v1_contract::常量号::构造(0),
        }]
        .into_boxed_slice(),
    );
    let 函数表 = Box::leak(vec![占位执行 as 执行函数].into_boxed_slice());
    平台信息 {
        声明格式号: v1_contract::声明格式号,
        目标字宽: 64,
        保留: 0,
        标识串: 静态字节串(标识串),
        实现版本: 版本三元组::构造(1, 0, 0),
        要求宿主版本: 版本要求::构造(1, 0),
        要求内核版本: 版本要求::构造(1, 0),
        名称: 静态串("样本\0"),
        说明: 静态串("样本声明。\0"),
        状态位: 0,
        类型表: 表段::构造(类型表.as_ptr(), 1),
        命令表: 表段::构造(命令表.as_ptr(), 1),
        函数表: 函数表.as_ptr(),
        常量表: 表段::构造(常量表.as_ptr(), 1),
        通知函数: None,
        依赖清单: 表段::空实例(),
        能力号段: 钉段表(&[号段]),
        通知号段: 表段::空实例(),
        错误段位表: 表段::构造(样本错误段位表.as_ptr(), 1),
        错误码表: 表段::空实例(),
        命令类别表: 表段::空实例(),
        要求权限: 表段::空实例(),
    }
}

/// 把样本钉成 `&'static`（测试专用：泄漏一份，进程退出即回收）。
pub(crate) fn 钉住(声明: 平台信息) -> &'static 平台信息 {
    Box::leak(Box::new(声明))
}

/// 把一张号段表钉成 `'static`。
pub(crate) fn 钉段表(段s: &[号段]) -> 表段<号段> {
    let 泄漏 = Box::leak(段s.to_vec().into_boxed_slice());
    表段::构造(泄漏.as_ptr(), 泄漏.len() as u32)
}

/// 把一张错误段位表钉成 `'static`。
pub(crate) fn 钉段位表(段位s: &[u32]) -> 表段<u32> {
    let 泄漏 = Box::leak(段位s.to_vec().into_boxed_slice());
    表段::构造(泄漏.as_ptr(), 泄漏.len() as u32)
}

/// 把一张依赖清单钉成 `'static`（按字节串给，标识串就是字节）。
pub(crate) fn 钉依赖表(项s: &[&'static [u8]]) -> 表段<*const u8> {
    let 泄漏 = Box::leak(项s.iter().map(|标识串| 标识串.as_ptr()).collect::<Vec<_>>().into_boxed_slice());
    表段::构造(泄漏.as_ptr(), 泄漏.len() as u32)
}

/// 标准台账：预置了底座自身的占用（标识串 + 0..999 + 2000..2999）。
pub(crate) fn 标准台账() -> 载入台账 {
    载入台账::构造()
}
