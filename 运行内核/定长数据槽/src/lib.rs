//! 定长数据槽 —— 跨边界唯一的交换形状。
//!
//! 每种语言只需要会两件事：把值放进槽、把槽读出来。类型标签在槽内，
//! 所以语言之间不需要互相理解类型系统（见 `多语言兼容实现.md`）。
//!
//! 本 crate 只管槽本身：放入、读出、相容判定。**分配不在这里**（归 `内存分配器`）。
//!
//! 三条落点口径（`内核落点.md` 第四 · 五节）：
//!
//! 1. **文本与字节集必带长度**——参照内核不带长度，是它的缺陷，不复刻。所以
//!    `放入字节` 一律把字节长度写进 `长度`，长度为 0 也照写（空字节集不是"无值"）。
//! 2. **槽的形状与字宽无关**：`长度` 与 `值` 都是显式 `u64`。本文件里不出现
//!    `usize` / `isize` 作为形状；只在构造切片视图时把长度按目标字宽**校验后**转换
//!    （32 位构建下超宽的长度报 `长度不符`，不静默截断）。
//! 3. **失败可编程判定**：一律 `Result` + [`槽错误`]，不用 panic 表达业务失败。

pub use v1_contract::{槽标志, 数据槽};

/// 整数在槽里的字节宽度：契约把「整数」映射为 `i64`（`多语言兼容实现.md` 类型映射表），
/// 内联值域固定 64 位，所以整数恒占 8 字节。
///
/// **值只有一个来源**：`v1_contract::声明数据::整数字节宽度`
/// （源 = `契约声明/常量表.json` 的「整数字节宽度」条目）。这里只 `pub use` ——
/// 早先手写的 `pub const 整数字节宽度: u64 = 8;` 已删（同一事实的第二来源）。
pub use v1_contract::声明数据::整数字节宽度;

/// 内联值域（`数据槽.值`）的字节宽度。比它长的数据只能走引用路径。
pub const 内联值域宽度: u64 = 8;

/// 槽操作错误。**不用异常**：失败必须可编程判定。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 槽错误 {
    /// 槽里是空值，但调用方要取值。
    空值,
    /// 实际类型标签与期望不符。
    类型不符 { 期望: u32, 实际: u32 },
    /// 长度不满足（文本/字节集短于读取需要）。
    长度不符 { 期望: u64, 实际: u64 },
    /// 内联值被当成引用读，或反之。
    取值方式不符,
}

/// 期望类型标签与实际是否相容。位置错位、类型不符，**当场可判**（宪法第 3 条）。
///
/// 空槽按「空值」返回（`槽错误::空值`），**不当成类型不符**——空值是"无值"，
/// 不是"错类型的值"，两者调用方的处置不同（宪法第 6 条：未命中只许降级，不许崩）。
pub fn 判定相容(期望类型: u32, 槽: &数据槽) -> Result<(), 槽错误> {
    if 槽.是否空() {
        return Err(槽错误::空值);
    }
    if 槽.类型标签 != 期望类型 {
        return Err(槽错误::类型不符 { 期望: 期望类型, 实际: 槽.类型标签.取() });
    }
    Ok(())
}

/// 放入一个整数（内联值）。
///
/// 走内联路径：`值` 直接装整数本身，`标志` 清零（既不是引用也不是空），
/// `长度` 写 [`整数字节宽度`]——整数是定宽标量，长度写出来才能被 [`取出整数`] 当场校验。
pub fn 放入整数(槽: &mut 数据槽, 类型标签: u32, 值: i64) {
    // i64 → u64 是同宽位重解释（补码），不丢信息；取出时再原样重解释回来。
    *槽 = 数据槽::内联(类型标签.into(), 值 as u64, 整数字节宽度);
}

/// 取出一个整数。槽必须不是引用。
pub fn 取出整数(槽: &数据槽) -> Result<i64, 槽错误> {
    if 槽.是否空() {
        return Err(槽错误::空值);
    }
    if 槽.是否引用() {
        // 引用槽里放的是地址，不是值：当成内联读会读出个地址，是静默错位。
        return Err(槽错误::取值方式不符);
    }
    if 槽.长度 != 整数字节宽度 {
        return Err(槽错误::长度不符 { 期望: 整数字节宽度, 实际: 槽.长度 });
    }
    Ok(槽.值 as i64)
}

/// 放入一段字节（**必须带长度**；数据已由 `内存分配器` 分配好，此处只记地址与长度）。
///
/// `交出所有权 = true` 表示接收方负责释放。
///
/// 长度 0 也照记：**空字节集不是空槽**——`长度 = 0` 加引用标志表示"有值，且是零字节"，
/// 而 [`数据槽::空槽`] 表示"无值"。两者不可混同。
pub fn 放入字节(槽: &mut 数据槽, 类型标签: u32, 地址: u64, 字节长度: u64, 交出所有权: bool) {
    *槽 = 数据槽::指针(类型标签.into(), 地址, 字节长度, 交出所有权);
}

/// 取出字节视图。引用槽与内联槽都支持（内联时按 `值` 的低位地址解释）。
///
/// # 安全义务（调用方）
///
/// 本函数签名由冻结的对外接口给定（`内核落点.md` 第五节），所以它是安全函数，
/// 但它对**引用槽**会按槽里声明的地址与长度构造切片。调用方必须保证：
///
/// - 该地址对本进程可读，且从该地址起有 `长度` 个连续字节；
/// - 在拿到的切片存活期间，这段内存不被改写、不被释放（`&[u8]` 是共享引用）。
///
/// 长度 0 是特例：此时**不触碰地址**，直接返回空切片——零长度不构成解引用，
/// 所以地址为 0 的零长度字节集也是合法的。
///
/// 内联槽：返回 `值` 字段起始地址起的 `长度` 个字节（小端下即低位字节），
/// 长度不得超过 [`内联值域宽度`]。
pub fn 取出字节(槽: &数据槽) -> Result<&[u8], 槽错误> {
    if 槽.是否空() {
        return Err(槽错误::空值);
    }

    if 槽.是否引用() {
        if 槽.长度 == 0 {
            // 零长度：不解引用，地址是否为 0 都合法。
            return Ok(&[]);
        }
        if 槽.值 == 0 {
            // 声明了非零长度却没有地址：坏槽，报长度不符（可用字节 0 个），不 panic、不静默。
            return Err(槽错误::长度不符 { 期望: 槽.长度, 实际: 0 });
        }
        // 目标字宽可能窄于 64 位：长度超宽即报错，绝不静默截断（`内核落点.md` 宽度策略）。
        let 长度 = usize::try_from(槽.长度)
            .map_err(|_| 槽错误::长度不符 { 期望: usize::MAX as u64, 实际: 槽.长度 })?;
        // SAFETY: 由本函数的调用方保证：地址可读且有 长度 个连续字节、存活期内不被改写。
        Ok(unsafe { core::slice::from_raw_parts(槽.值 as *const u8, 长度) })
    } else {
        if 槽.长度 > 内联值域宽度 {
            // 内联值域只有 8 字节，比它长的数据只能走引用路径。
            return Err(槽错误::长度不符 { 期望: 内联值域宽度, 实际: 槽.长度 });
        }
        let 长度 = 槽.长度 as usize; // 已判 ≤ 8，任何目标字宽都装得下。
        // SAFETY: 起点取自 `&数据槽` 内的 `值` 字段（借来的、对齐的、非空的），
        // 长度 ≤ 8 不越出该字段；切片存活期受 `槽` 的借用期约束。
        Ok(unsafe { core::slice::from_raw_parts((&槽.值 as *const u64).cast::<u8>(), 长度) })
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    // 测试用类型标签。真标签取自 `契约声明/类型声明/`（尚未落盘），
    // 本 crate 只比数值是否相等，与标签取值无关。
    const 整数标签: u32 = 1001;
    const 文本标签: u32 = 1002;
    const 字节集标签: u32 = 1003;

    // ── 判定相容 ────────────────────────────────────────────────────────────

    #[test]
    fn 相容_标签相符() {
        let mut 槽 = 数据槽::空槽();
        放入整数(&mut 槽, 整数标签, 42);
        assert_eq!(判定相容(整数标签, &槽), Ok(()));
    }

    #[test]
    fn 相容_类型不符报期望与实际() {
        let mut 槽 = 数据槽::空槽();
        放入整数(&mut 槽, 文本标签, 42);
        assert_eq!(
            判定相容(整数标签, &槽),
            Err(槽错误::类型不符 { 期望: 整数标签, 实际: 文本标签 })
        );
    }

    #[test]
    fn 相容_空槽给空值不当类型不符() {
        let 槽 = 数据槽::空槽();
        // 空槽的类型标签是 0，与期望不符——但结论必须是「空值」，不是「类型不符」。
        assert_eq!(判定相容(整数标签, &槽), Err(槽错误::空值));
    }

    // ── 整数：内联路径 ──────────────────────────────────────────────────────

    #[test]
    fn 整数_内联往返() {
        let mut 槽 = 数据槽::空槽();
        放入整数(&mut 槽, 整数标签, 123_456_789);
        assert_eq!(槽.类型标签, 整数标签);
        assert!(!槽.是否引用(), "整数走内联路径，不许带引用标志");
        assert!(!槽.是否空());
        assert_eq!(槽.长度, 整数字节宽度);
        assert_eq!(取出整数(&槽), Ok(123_456_789));
    }

    #[test]
    fn 整数_负数与边界值往返() {
        for 值 in [0_i64, -1, i64::MIN, i64::MAX, -9_007_199_254_740_993] {
            let mut 槽 = 数据槽::空槽();
            放入整数(&mut 槽, 整数标签, 值);
            assert_eq!(取出整数(&槽), Ok(值), "值 {值} 往返不一致");
        }
    }

    #[test]
    fn 整数_覆盖旧槽不留旧标志() {
        let mut 槽 = 数据槽::空槽();
        let 数据 = [1_u8, 2, 3];
        放入字节(&mut 槽, 字节集标签, 数据.as_ptr() as u64, 3, true);
        assert!(槽.是否引用() && 槽.交出了所有权());
        放入整数(&mut 槽, 整数标签, 7);
        assert!(!槽.是否引用(), "放入整数必须清掉引用标志");
        assert!(!槽.交出了所有权(), "放入整数必须清掉所有权交出标志");
        assert!(!槽.是否空());
        assert_eq!(取出整数(&槽), Ok(7));
    }

    #[test]
    fn 整数_空槽报空值() {
        let 槽 = 数据槽::空槽();
        assert_eq!(取出整数(&槽), Err(槽错误::空值));
    }

    #[test]
    fn 整数_引用槽报取值方式不符() {
        let 数据 = [0_u8; 4];
        let mut 槽 = 数据槽::空槽();
        放入字节(&mut 槽, 整数标签, 数据.as_ptr() as u64, 4, false);
        // 标签对得上，但值是地址不是整数：必须报取值方式不符，不许把地址当整数读出来。
        assert_eq!(取出整数(&槽), Err(槽错误::取值方式不符));
    }

    #[test]
    fn 整数_长度不足报长度不符() {
        for 长度 in [0_u64, 4, 7] {
            let 槽 = 数据槽::内联(整数标签.into(), 42, 长度);
            assert_eq!(
                取出整数(&槽),
                Err(槽错误::长度不符 { 期望: 整数字节宽度, 实际: 长度 })
            );
        }
    }

    #[test]
    fn 整数_长度超宽同样报长度不符() {
        let 槽 = 数据槽::内联(整数标签.into(), 42, 16);
        assert_eq!(取出整数(&槽), Err(槽错误::长度不符 { 期望: 8, 实际: 16 }));
    }

    // ── 字节集：引用路径 ────────────────────────────────────────────────────

    #[test]
    fn 字节_引用往返() {
        let 数据 = [0xDE_u8, 0xAD, 0xBE, 0xEF];
        let mut 槽 = 数据槽::空槽();
        放入字节(&mut 槽, 字节集标签, 数据.as_ptr() as u64, 数据.len() as u64, false);
        assert_eq!(槽.类型标签, 字节集标签);
        assert!(槽.是否引用());
        assert!(!槽.是否空());
        assert!(!槽.交出了所有权());
        assert_eq!(槽.长度, 4);
        assert_eq!(取出字节(&槽), Ok(&数据[..]));
    }

    #[test]
    fn 字节_引用_交出所有权置位() {
        let 数据 = [7_u8; 2];
        let mut 槽 = 数据槽::空槽();
        放入字节(&mut 槽, 字节集标签, 数据.as_ptr() as u64, 2, true);
        assert!(槽.交出了所有权());
        assert!(槽.是否引用());
        assert_eq!(取出字节(&槽), Ok(&数据[..]));
    }

    #[test]
    fn 字节_引用_边界长度零是空字节集不是空槽() {
        let mut 槽 = 数据槽::空槽();
        // 地址为 0、长度为 0：合法的空字节集，不得解引用、不得报错。
        放入字节(&mut 槽, 字节集标签, 0, 0, false);
        assert!(!槽.是否空(), "长度 0 的字节集是「有值」，不是「无值」");
        assert!(槽.是否引用());
        assert_eq!(槽.长度, 0);
        assert_eq!(取出字节(&槽), Ok(&[][..]));
        // 与空槽对照：空槽才报空值。
        assert_eq!(取出字节(&数据槽::空槽()), Err(槽错误::空值));
    }

    #[test]
    fn 字节_引用_非零长度却无地址报长度不符() {
        let mut 槽 = 数据槽::空槽();
        放入字节(&mut 槽, 字节集标签, 0, 8, false);
        assert_eq!(取出字节(&槽), Err(槽错误::长度不符 { 期望: 8, 实际: 0 }));
    }

    #[test]
    fn 字节_空槽报空值() {
        assert_eq!(取出字节(&数据槽::空槽()), Err(槽错误::空值));
    }

    // ── 字节集：内联路径 ────────────────────────────────────────────────────

    #[test]
    fn 字节_内联往返按值字段字节序() {
        let mut 槽 = 数据槽::空槽();
        放入整数(&mut 槽, 字节集标签, 0x0102_0304_0506_0708);
        let 视图 = 取出字节(&槽).expect("内联槽长度 8 应当可读");
        assert_eq!(视图.len(), 8);
        let 期望 = 0x0102_0304_0506_0708_u64.to_ne_bytes();
        assert_eq!(视图, &期望[..], "内联视图就是值字段起始地址起的 8 字节");
    }

    #[test]
    fn 字节_内联_边界长度零给空切片() {
        let 槽 = 数据槽::内联(字节集标签.into(), 0xFFFF, 0);
        assert!(!槽.是否空());
        assert_eq!(取出字节(&槽), Ok(&[][..]));
    }

    #[test]
    fn 字节_内联_长度超值域报长度不符() {
        for 长度 in [9_u64, 16, 1024] {
            let 槽 = 数据槽::内联(字节集标签.into(), 0, 长度);
            assert_eq!(
                取出字节(&槽),
                Err(槽错误::长度不符 { 期望: 内联值域宽度, 实际: 长度 })
            );
        }
    }

    #[test]
    fn 字节_内联_长度不足一字节也不多读() {
        // 长度 1..8 全部只读到声明的那几个字节，不越界、不补齐。
        for 长度 in 1_u64..=8 {
            let 槽 = 数据槽::内联(字节集标签.into(), 0x0807_0605_0403_0201, 长度);
            let 视图 = 取出字节(&槽).expect("长度 1..=8 应当可读");
            assert_eq!(视图.len() as u64, 长度);
            let 期望 = 0x0807_0605_0403_0201_u64.to_ne_bytes();
            assert_eq!(视图, &期望[..长度 as usize]);
        }
    }

    // ── 两条路径的交叉判定 ──────────────────────────────────────────────────

    #[test]
    fn 交叉_整数槽与引用槽互不冒充() {
        let 数据 = [0_u8; 8];
        let mut 引用槽 = 数据槽::空槽();
        放入字节(&mut 引用槽, 整数标签, 数据.as_ptr() as u64, 8, false);
        let mut 内联槽 = 数据槽::空槽();
        放入整数(&mut 内联槽, 整数标签, 5);

        assert_eq!(取出整数(&引用槽), Err(槽错误::取值方式不符));
        assert!(取出字节(&内联槽).is_ok(), "内联槽可读字节视图");
        // 同一标签：一条路只认一种取值方式，读错方式当场可判（宪法第 3 条）。
        assert_eq!(判定相容(整数标签, &引用槽), Ok(()));
        assert_eq!(判定相容(整数标签, &内联槽), Ok(()));
    }
}
