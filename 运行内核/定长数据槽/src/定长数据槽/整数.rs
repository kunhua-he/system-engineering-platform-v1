//! 整数 —— 内联路径的放入与取出。

use crate::错误::槽错误;
use v1_contract::声明数据::整数字节宽度;
use v1_contract::{类型标签, 数据槽};

/// 放入一个整数（内联值）。
///
/// 走内联路径：`值` 直接装整数本身，`标志` 清零（既不是引用也不是空），
/// `长度` 写 [`整数字节宽度`]——整数是定宽标量，长度写出来才能被 [`取出整数`] 当场校验。
pub fn 放入整数(数据槽: &mut 数据槽, 标签: 类型标签, 待处理值: i64) {
    // i64 → u64 是同宽位重解释（补码），不丢信息；取出时再原样重解释回来。
    *数据槽 = 数据槽::内联(标签, 待处理值 as u64, 整数字节宽度);
}

/// 取出一个整数。槽必须不是引用。
pub fn 取出整数(数据槽: &数据槽) -> Result<i64, 槽错误> {
    if 数据槽.是否空() {
        return Err(槽错误::空值项);
    }
    if 数据槽.是否引用() {
        // 引用槽里放的是地址，不是值：当成内联读会读出个地址，是静默错位。
        return Err(槽错误::取值方式不符);
    }
    if 数据槽.长度 != 整数字节宽度 {
        return Err(槽错误::长度不符 { 期望: 整数字节宽度, 实际: 数据槽.长度 });
    }
    Ok(数据槽.槽值 as i64)
}
