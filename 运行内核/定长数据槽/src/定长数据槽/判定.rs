//! 相容判定 —— 位置错位、类型不符当场可判。

use crate::错误::槽错误;
use v1_contract::{类型标签, 数据槽};

/// 期望类型标签与实际是否相容。位置错位、类型不符，**当场可判**（宪法第 3 条）。
///
/// 空槽按「空值」返回（`槽错误::空值`），**不当成类型不符**——空值是"无值"，
/// 不是"错类型的值"，两者调用方的处置不同（宪法第 6 条：未命中只许降级，不许崩）。
pub fn 判定相容(期望类型: 类型标签, 槽: &数据槽) -> Result<(), 槽错误> {
    if 槽.是否空() {
        return Err(槽错误::空值);
    }
    if 槽.类型标签 != 期望类型 {
        return Err(槽错误::类型不符 { 期望: 期望类型.取(), 实际: 槽.类型标签.取() });
    }
    Ok(())
}
