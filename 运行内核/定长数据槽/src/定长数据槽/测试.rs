//! 槽的单元测试 —— 内联路径 · 引用路径 · 两条路径的交叉判定。

use super::*;
use v1_contract::类型标签;

// 测试用类型标签。真标签取自 `契约声明/类型声明/`（尚未落盘），
// 本 crate 只比数值是否相等，与标签取值无关。
// 型是 `类型标签`（号空间 newtype）—— 与裸 `u32` 互不能赋值，用 `取()` 落到数值。
const 整数标签: 类型标签 = 类型标签::新建(1001);
const 文本标签: 类型标签 = 类型标签::新建(1002);
const 字节集标签: 类型标签 = 类型标签::新建(1003);

// ── 判定相容 ────────────────────────────────────────────────────────────

#[test]
fn 相容_标签相符() {
    let mut 数据槽 = 数据槽::空槽();
    放入整数(&mut 数据槽, 整数标签, 42);
    assert_eq!(判定相容(整数标签, &数据槽), Ok(()));
}

#[test]
fn 相容_类型不符报期望与实际() {
    let mut 数据槽 = 数据槽::空槽();
    放入整数(&mut 数据槽, 文本标签, 42);
    assert_eq!(
        判定相容(整数标签, &数据槽),
        Err(槽错误::类型不符 { 期望: 整数标签.取号值(), 实际: 文本标签.取号值() })
    );
}

#[test]
fn 相容_空槽给空值不当类型不符() {
    let 数据槽 = 数据槽::空槽();
    // 空槽的类型标签是 0，与期望不符——但结论必须是「空值」，不是「类型不符」。
    assert_eq!(判定相容(整数标签, &数据槽), Err(槽错误::空值));
}

// ── 整数：内联路径 ──────────────────────────────────────────────────────

#[test]
fn 整数_内联往返() {
    let mut 数据槽 = 数据槽::空槽();
    放入整数(&mut 数据槽, 整数标签, 123_456_789);
    assert_eq!(数据槽.类型标签, 整数标签);
    assert!(!数据槽.是否引用(), "整数走内联路径，不许带引用标志");
    assert!(!数据槽.是否空());
    assert_eq!(数据槽.长度, 整数字节宽度);
    assert_eq!(取出整数(&数据槽), Ok(123_456_789));
}

#[test]
fn 整数_负数与边界值往返() {
    for 待处理值 in [0_i64, -1, i64::MIN, i64::MAX, -9_007_199_254_740_993] {
        let mut 数据槽 = 数据槽::空槽();
        放入整数(&mut 数据槽, 整数标签, 待处理值);
        assert_eq!(取出整数(&数据槽), Ok(待处理值), "值 {待处理值} 往返不一致");
    }
}

#[test]
fn 整数_覆盖旧槽不留旧标志() {
    let mut 数据槽 = 数据槽::空槽();
    let 数据 = [1_u8, 2, 3];
    放入字节(&mut 数据槽, 字节集标签, 数据.as_ptr() as u64, 3, true);
    assert!(数据槽.是否引用() && 数据槽.交出了所有权());
    放入整数(&mut 数据槽, 整数标签, 7);
    assert!(!数据槽.是否引用(), "放入整数必须清掉引用标志");
    assert!(!数据槽.交出了所有权(), "放入整数必须清掉所有权交出标志");
    assert!(!数据槽.是否空());
    assert_eq!(取出整数(&数据槽), Ok(7));
}

#[test]
fn 整数_空槽报空值() {
    let 数据槽 = 数据槽::空槽();
    assert_eq!(取出整数(&数据槽), Err(槽错误::空值));
}

#[test]
fn 整数_引用槽报取值方式不符() {
    let 数据 = [0_u8; 4];
    let mut 数据槽 = 数据槽::空槽();
    放入字节(&mut 数据槽, 整数标签, 数据.as_ptr() as u64, 4, false);
    // 标签对得上，但值是地址不是整数：必须报取值方式不符，不许把地址当整数读出来。
    assert_eq!(取出整数(&数据槽), Err(槽错误::取值方式不符));
}

#[test]
fn 整数_长度不足报长度不符() {
    for 长度 in [0_u64, 4, 7] {
        let 数据槽 = 数据槽::内联(整数标签, 42, 长度);
        assert_eq!(
            取出整数(&数据槽),
            Err(槽错误::长度不符 { 期望: 整数字节宽度, 实际: 长度 })
        );
    }
}

#[test]
fn 整数_长度超宽同样报长度不符() {
    let 数据槽 = 数据槽::内联(整数标签, 42, 16);
    assert_eq!(取出整数(&数据槽), Err(槽错误::长度不符 { 期望: 8, 实际: 16 }));
}

// ── 字节集：引用路径 ────────────────────────────────────────────────────

#[test]
fn 字节_引用往返() {
    let 数据 = [0xDE_u8, 0xAD, 0xBE, 0xEF];
    let mut 数据槽 = 数据槽::空槽();
    放入字节(&mut 数据槽, 字节集标签, 数据.as_ptr() as u64, 数据.len() as u64, false);
    assert_eq!(数据槽.类型标签, 字节集标签);
    assert!(数据槽.是否引用());
    assert!(!数据槽.是否空());
    assert!(!数据槽.交出了所有权());
    assert_eq!(数据槽.长度, 4);
    assert_eq!(取出字节(&数据槽), Ok(&数据[..]));
}

#[test]
fn 字节_引用_交出所有权置位() {
    let 数据 = [7_u8; 2];
    let mut 数据槽 = 数据槽::空槽();
    放入字节(&mut 数据槽, 字节集标签, 数据.as_ptr() as u64, 2, true);
    assert!(数据槽.交出了所有权());
    assert!(数据槽.是否引用());
    assert_eq!(取出字节(&数据槽), Ok(&数据[..]));
}

#[test]
fn 字节_引用_边界长度零是空字节集不是空槽() {
    let mut 数据槽 = 数据槽::空槽();
    // 地址为 0、长度为 0：合法的空字节集，不得解引用、不得报错。
    放入字节(&mut 数据槽, 字节集标签, 0, 0, false);
    assert!(!数据槽.是否空(), "长度 0 的字节集是「有值」，不是「无值」");
    assert!(数据槽.是否引用());
    assert_eq!(数据槽.长度, 0);
    assert_eq!(取出字节(&数据槽), Ok(&[][..]));
    // 与空槽对照：空槽才报空值。
    assert_eq!(取出字节(&数据槽::空槽()), Err(槽错误::空值));
}

#[test]
fn 字节_引用_非零长度却无地址报长度不符() {
    let mut 数据槽 = 数据槽::空槽();
    放入字节(&mut 数据槽, 字节集标签, 0, 8, false);
    assert_eq!(取出字节(&数据槽), Err(槽错误::长度不符 { 期望: 8, 实际: 0 }));
}

#[test]
fn 字节_空槽报空值() {
    assert_eq!(取出字节(&数据槽::空槽()), Err(槽错误::空值));
}

// ── 字节集：内联路径 ────────────────────────────────────────────────────

#[test]
fn 字节_内联往返按值字段字节序() {
    let mut 数据槽 = 数据槽::空槽();
    放入整数(&mut 数据槽, 字节集标签, 0x0102_0304_0506_0708);
    let 视图 = 取出字节(&数据槽).expect("内联槽长度 8 应当可读");
    assert_eq!(视图.len(), 8);
    let 期望 = 0x0102_0304_0506_0708_u64.to_ne_bytes();
    assert_eq!(视图, &期望[..], "内联视图就是值字段起始地址起的 8 字节");
}

#[test]
fn 字节_内联_边界长度零给空切片() {
    let 数据槽 = 数据槽::内联(字节集标签, 0xFFFF, 0);
    assert!(!数据槽.是否空());
    assert_eq!(取出字节(&数据槽), Ok(&[][..]));
}

#[test]
fn 字节_内联_长度超值域报长度不符() {
    for 长度 in [9_u64, 16, 1024] {
        let 数据槽 = 数据槽::内联(字节集标签, 0, 长度);
        assert_eq!(
            取出字节(&数据槽),
            Err(槽错误::长度不符 { 期望: 内联值域宽度, 实际: 长度 })
        );
    }
}

#[test]
fn 字节_内联_长度不足一字节也不多读() {
    // 长度 1..8 全部只读到声明的那几个字节，不越界、不补齐。
    for 长度 in 1_u64..=8 {
        let 数据槽 = 数据槽::内联(字节集标签, 0x0807_0605_0403_0201, 长度);
        let 视图 = 取出字节(&数据槽).expect("长度 1..=8 应当可读");
        assert_eq!(视图.len() as u64, 长度);
        let 期望 = 0x0807_0605_0403_0201_u64.to_ne_bytes();
        assert_eq!(视图, &期望[..长度 as usize]);
    }
}

// ── 两条路径的交叉判定 ──────────────────────────────────────────────────

#[test]
fn 交叉_整数槽与引用槽互不冒充() {
    let 数据 = [0_u8; 8];
    let mut 引用槽 = 数据槽::空槽();
    放入字节(&mut 引用槽, 整数标签, 数据.as_ptr() as u64, 8, false);
    let mut 内联槽 = 数据槽::空槽();
    放入整数(&mut 内联槽, 整数标签, 5);

    assert_eq!(取出整数(&引用槽), Err(槽错误::取值方式不符));
    assert!(取出字节(&内联槽).is_ok(), "内联槽可读字节视图");
    // 同一标签：一条路只认一种取值方式，读错方式当场可判（宪法第 3 条）。
    assert_eq!(判定相容(整数标签, &引用槽), Ok(()));
    assert_eq!(判定相容(整数标签, &内联槽), Ok(()));
}
