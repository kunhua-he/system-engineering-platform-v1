//! 字节集 —— 引用路径与内联路径的放入与读出。

use crate::常量::内联值域宽度;
use crate::错误::槽错误;
use v1_contract::{类型标签, 数据槽};

/// 放入一段字节（**必须带长度**；数据已由 `内存分配器` 分配好，此处只记地址与长度）。
///
/// `交出所有权 = true` 表示接收方负责释放。
///
/// 长度 0 也照记：**空字节集不是空槽**——`长度 = 0` 加引用标志表示"有值，且是零字节"，
/// 而 [`数据槽::空槽`] 表示"无值"。两者不可混同。
pub fn 放入字节(数据槽: &mut 数据槽, 标签: 类型标签, 地址: u64, 字节长度: u64, 交出所有权: bool) {
    *数据槽 = 数据槽::指针(标签, 地址, 字节长度, 交出所有权);
}

/// 取出字节视图。引用槽与内联槽都支持（内联时按 `值` 的低位地址解释）。
///
/// # 安全义务（调用方）
///
/// 本函数签名由冻结的对外接口给定（`内核落点.md` 第五节），所以它是安全函数，
/// 但它对**引用槽**会按槽里声明的地址与长度构造切片。调用方必须保证：
///
/// - 该地址对本进程可读，且从该地址起有 `长度` 个连续字节；
/// - 在拿到的切片存活期间，这段内存不被改写、不被释放（`&[u8]` 是共享引用）。
///
/// 长度 0 是特例：此时**不触碰地址**，直接返回空切片——零长度不构成解引用，
/// 所以地址为 0 的零长度字节集也是合法的。
///
/// 内联槽：返回 `值` 字段起始地址起的 `长度` 个字节（小端下即低位字节），
/// 长度不得超过 [`内联值域宽度`]。
pub fn 取出字节(数据槽: &数据槽) -> Result<&[u8], 槽错误> {
    if 数据槽.是否空() {
        return Err(槽错误::空值项);
    }

    if 数据槽.是否引用() {
        if 数据槽.长度 == 0 {
            // 零长度：不解引用，地址是否为 0 都合法。
            return Ok(&[]);
        }
        if 数据槽.值 == 0 {
            // 声明了非零长度却没有地址：坏槽，报长度不符（可用字节 0 个），不 panic、不静默。
            return Err(槽错误::长度不符 { 期望: 数据槽.长度, 实际: 0 });
        }
        // 目标字宽可能窄于 64 位：长度超宽即报错，绝不静默截断（`内核落点.md` 宽度策略）。
        let 长度 = usize::try_from(数据槽.长度)
            .map_err(|_| 槽错误::长度不符 { 期望: usize::MAX as u64, 实际: 数据槽.长度 })?;
        // SAFETY: 由本函数的调用方保证：地址可读且有 长度 个连续字节、存活期内不被改写。
        Ok(unsafe { core::slice::from_raw_parts(数据槽.值 as *const u8, 长度) })
    } else {
        if 数据槽.长度 > 内联值域宽度 {
            // 内联值域只有 8 字节，比它长的数据只能走引用路径。
            return Err(槽错误::长度不符 { 期望: 内联值域宽度, 实际: 数据槽.长度 });
        }
        let 长度 = 数据槽.长度 as usize; // 已判 ≤ 8，任何目标字宽都装得下。
        // SAFETY: 起点取自 `&数据槽` 内的 `值` 字段（借来的、对齐的、非空的），
        // 长度 ≤ 8 不越出该字段；切片存活期受 `数据槽` 的借用期约束。
        Ok(unsafe { core::slice::from_raw_parts((&数据槽.值 as *const u64).cast::<u8>(), 长度) })
    }
}
