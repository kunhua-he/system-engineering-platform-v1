//! 槽操作错误 —— 失败必须可编程判定，不用异常。

/// 槽操作错误。**不用异常**：失败必须可编程判定。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 槽错误 {
    /// 槽里是空值，但调用方要取值。
    空值,
    /// 实际类型标签与期望不符。
    类型不符 { 期望: u32, 实际: u32 },
    /// 长度不满足（文本/字节集短于读取需要）。
    长度不符 { 期望: u64, 实际: u64 },
    /// 内联值被当成引用读，或反之。
    取值方式不符,
}
