"""复用唯一量级驱动，统一跑旧库、新库与二至四库组合。"""
import concurrent.futures
import hashlib as 摘要引擎
from 测试验证.扩展量级.槽值 import 解槽值
from 测试验证.数据文本扩展.HTTP验收 import 核验数据文本
from .独立样本 import 核验独立样本
from .边界样本 import 核验边界


def 核验通用基础(请求,检查,实例表):
    核验数据文本(请求,检查,实例表)
    def 调用(网关实例,编号,参数表,预期错误=None):
        状态码,正文=请求(网关实例,'/接口/调用',dict(编号=编号,值=[dict(类型标签=4,值=参数文本) for 参数文本 in 参数表]))
        if 预期错误 is not None:
            检查(状态码<500 and 正文.get('成功') is False and 正文.get('错误',{}).get('码')==预期错误,'能力%s原码错误透传'%编号,正文)
            return None
        检查(状态码==200 and 正文.get('成功') and len(正文['值'])==1,'能力%s真实HTTP成功'%编号,正文)
        return 解槽值(正文['值'][0])
    for 网关实例 in 实例表:
        核验独立样本(调用,检查,网关实例)
        核验边界(调用,请求,检查,网关实例)
        调用(网关实例,7981,['日期\n2026-10-18T04:30:00+08:00\n','/1/0'])
        _,留痕=请求(网关实例,'/接口/留痕')
        编号集合={条目['能力号'] for 条目 in 留痕.get('数据',{}).get('留痕',[])}
        检查({7981,5301,5203,2301,4601}.issubset(编号集合),'四库内外调用均可追踪',留痕)
    def 并发核验(请求序号):
        网关实例=实例表[请求序号%len(实例表)]
        期望值=摘要引擎.sha256(b'2026-10-17T20:30:00+00:00').hexdigest()
        assert 调用(网关实例,7981,['日期\n2026-10-18T04:30:00+08:00\n','/1/0'])==期望值
        assert 调用(网关实例,7973,['<根>订单%s中文</根>'%请求序号,r'\d+'])==[str(请求序号)]
    with concurrent.futures.ThreadPoolExecutor(max_workers=12) as 线程池:list(线程池.map(并发核验,range(96)))
    检查(True,'双网关12线程96次四库及XML跨库并发')


def 执行通用基础验收(仓根,缓存根):
    from 测试验证.扩展量级.HTTP验收 import 执行量级验收
    return 执行量级验收(仓根,缓存根,扩展验证=核验通用基础)
