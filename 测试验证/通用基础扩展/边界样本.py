"""通用扩展的资源上界、错误透传与真实参数边界。"""
import base64 as 编码引擎
import hashlib as 摘要引擎
import json
from pathlib import Path


def 核验边界(调用,请求,检查,网关实例):
    错误表=[(4302,['%%%'],4302),(4302,['/w=='],4302),(4304,['YQ=='],4302),
        (4502,['0'],4502),(4502,['GG'],4502),(4502,['FF'],4502),
        (2301,['不是日期'],2302),(2302,['2026-01-01T00:00:00+00:00','%Q'],2302),(2302,['2026-01-01T00:00:00+00:00','%#z'],2302),
        (3303,['a\0b'],3302),
        (4201,['不是网址'],4202),(4202,['mailto:test@example.com','relative'],4202),
        (5302,['[[1]]'],5302),(5302,['[[]]'],5302),
        (5301,['x\n'*1001],5303),(5301,[','.join(['x']*257)],5303),
        (4701,['<根>'],4702),(4701,['<根/><另根/>'],4702),
        (4701,['<!DOCTYPE 根><根/>'],4702),(4702,['<根>&未知;</根>'],4702),
        (4701,['<根 属性="&未知;"/>'],4702),
        (4701,['<?xml version="1.0" encoding="GBK"?><根/>'],4702),
        (4701,['<根>'*65+'</根>'*65],4703),(4701,['<根>'+'<空/>'*2000+'</根>'],4703),
        (7971,['字段\n文字\n','/1/0','(?=x)'],4402),
        (7974,['<根/>','/不存在'],5202),(7979,['%%%'],4302),
        (7980,['GG'],4502),(7981,['日期\n坏日期\n','/1/0'],2302),
        (7981,['日期\n正常值\n','/99/0'],5202)]
    for 编号,参数表,错误码 in 错误表:调用(网关实例,编号,参数表,错误码)
    for 编号,输入字节上限,错误码 in [(4301,49152,4303),(4501,32768,4503)]:
        实际值=调用(网关实例,编号,['x'*输入字节上限])
        检查(len(实际值.encode())==65536,'能力%s精确输出上界'%编号)
        调用(网关实例,编号,['x'*(输入字节上限+1)],错误码)
    大文本='x'*65536
    检查(调用(网关实例,4601,[大文本])==摘要引擎.sha256(大文本.encode()).hexdigest(),'摘要精确输入上界')
    调用(网关实例,4601,[大文本+'x'],4603)
    检查(调用(网关实例,4302,[编码引擎.b64encode(b'x'*49152).decode()])=='x'*49152,'解码精确输入上界')
    编号表=list(range(2301,2304))+list(range(3301,3305))+list(range(4201,4204))+list(range(4301,4305))+[4501,4502,4601,4602,4701,4702,4703,5301,5302]+list(range(7969,7982))
    for 编号 in 编号表:
        件表=list((Path(__file__).resolve().parents[2]/'扩展根目录').glob('*/*/能力声明/%s.json'%编号))
        assert len(件表)==1,(编号,件表)
        参数条数=len(json.loads(件表[0].read_text())['参数表'])
        for 参数槽表 in ([],[dict(类型标签=1,值=7)]*参数条数,[dict(类型标签=4,值='x')]*(参数条数+1)):
            预期错误=3 if 编号<7000 and len(参数槽表)!=参数条数 else 25
            _,正文=请求(网关实例,'/接口/调用',dict(编号=编号,值=参数槽表))
            检查(not 正文.get('成功') and 正文.get('错误',{}).get('码')==预期错误,'能力%s真实参数边界'%编号,正文)
