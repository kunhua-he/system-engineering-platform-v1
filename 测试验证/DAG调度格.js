/* 拒绝格共用：必须真被拒（成功=false 或 协议错误 400），且理由文本点明是哪一类坏图；不许「拒了但语焉不详」当通过。 */
async function 拒绝格(格记录, 类名, 节点清单) {
  const 本次标识 = 新标识(类名);
  const 提交信封 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  // 图结构不成立 ⇒ 平台按 400 协议错误 回（与单能力同一条口径：请求体不合法才 400）。
  // 只要理由点明是哪一类坏图，这就是**正确的拒绝通道**，判通过；含混的 400 才算阻塞。
  if (提交信封.信封通道 === '协议错误') {
    const 说明全文 = String(提交信封.说明 || '');
    const 点到类 = 说明全文.indexOf(类名) >= 0
      || (类名 === '环' && 说明全文.indexOf('有环') >= 0)
      || (类名 === '未知依赖' && 说明全文.indexOf('未知') >= 0)
      || (类名 === '自依赖' && 说明全文.indexOf('自依赖') >= 0);
    记断言(格记录, 点到类, '坏图被拒在协议层（400）且理由点明是哪一类：' + 说明全文.slice(0, 120));
    if (!点到类) return 判阻塞(格记录, '被拒了但理由没点明坏图类别：' + 说明全文.slice(0, 120));
    return 收口(格记录);
  }
  if (提交信封.信封通道 === '非JSON' || 提交信封.信封通道 === '网络失败') {
    return 判阻塞(格记录, '提交没走到图校验（' + 提交信封.信封通道 + '）：' + String(提交信封.说明 || '').slice(0, 120));
  }
  const 被拒 = 提交信封.成功 === false;
  记断言(格记录, 被拒, '坏图被拒收（成功=false）');
  if (!被拒) {
    if (格记录.任务标识) 记断言(格记录, false, '坏图竟拿到任务标识 ' + 格记录.任务标识 + '：图校验没拦住');
    return 收口(格记录);
  }
  记断言(格记录, !格记录.任务标识, '拒收时没有回任务标识（未落任务）');
  const 理由文本 = String(提交信封.说明 || '') + ' ' + String(提交信封.错误说明 || '') + ' ' + String(提交信封.错误名 || '');
  const 点名样式 = 类名 === '未知依赖' ? /未知|不存在|未声明|找不到/ : new RegExp(类名 === '环' ? '环|循环|成环' : '自依赖|自指|依赖回指');
  if (!点名样式.test(理由文本) && 提交信封.错误类别 === 0) {
    return 判阻塞(格记录, '拒收只给到类别级「图形不合法」，没点明是' + 类名 + '：三类坏图在回执上互相分不开（实回：' + 理由文本.trim().slice(0, 80) + '）');
  }
  记断言(格记录, 点名样式.test(理由文本), '拒收理由点名了「' + 类名 + '」（实回：' + 理由文本.trim().slice(0, 80) + '）');
  return 收口(格记录);
}
/* 九 · 重复提交幂等：同一请求标识 + 同一内容，两次必须同一任务。 */
async function 格重复提交幂等(格记录) {
  const 本次标识 = 新标识('幂等');
  const 节点清单 = [
    节点('幂等根', 1108, { 程序文本: '幂等根' }),
    节点('幂等尾', 1108, { 程序文本: '幂等尾' }, ['幂等根']),
  ];
  const 左区间段 = await 提交(格记录, '提交·首次', 提交体(本次标识, 节点清单));
  const 一标 = 格记录.任务标识;
  const 右区间段 = await 提交(格记录, '提交·重放', 提交体(本次标识, 节点清单));
  const 二标 = 取任务标识(右区间段);
  记断言(格记录, 左区间段.成功 && 一标 !== '', '首次提交拿到真任务标识');
  if (!左区间段.成功 || !一标) return 提交受阻(格记录, 左区间段);
  记断言(格记录, 右区间段.成功, '重放被受理（同标识同内容不该冲突）');
  记断言(格记录, 二标 === 一标, '重放拿回同一任务标识（' + (二标 || '空') + '）');
  await 采样(格记录, ['幂等根', '幂等尾']);
  if (!有节点阶段(格记录)) return 判阻塞(格记录, '幂等对照成立，但查询未回节点阶段，二次开工无法核');
  const 区间册 = 建区间(格记录);
  const 批号集 = Object.keys(区间册).map(function (键名) { return 区间册[键名].批号; }).filter(function (能力号) { return 能力号 !== null; });
  记断言(格记录, 批号集.length === 0 || new Set(批号集).size <= 2, '节点执行批号未出现成倍增长（无二次开工）');
  记断言(格记录, 末尾任务阶段(格记录) === '成功', '任务阶段 收口到 成功');
  return 收口(格记录);
}
/* 十 · 重复或迟到完成事件不双启：宿主内部事件黑盒注入不了，只能看批号与轨迹有没有被二次拉起。 */
async function 格迟到完成(格记录) {
  const 本次标识 = 新标识('迟到');
  const 节点清单 = [
    节点('迟到根', 1108, { 程序文本: '迟到根' }),
    节点('迟到尾', 1108, { 程序文本: '迟到尾' }, ['迟到根']),
  ];
  const 左区间段 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  if (!左区间段.成功 || !格记录.任务标识) return 提交受阻(格记录, 左区间段);
  /* 完成前后各重放一次同标识提交：等价于「同一任务被重复唤醒」的外部可见面。 */
  const 右区间段 = await 提交(格记录, '提交·执行中重放', 提交体(本次标识, 节点清单));
  记断言(格记录, 取任务标识(右区间段) === 格记录.任务标识, '执行中重放仍指向同一任务（未新建第二个）');
  await 采样(格记录, ['迟到根', '迟到尾']);
  if (!有节点阶段(格记录)) return 判阻塞(格记录, '查询未回节点阶段：无法核「同一节点是否被启动两次」');
  const 区间册 = 建区间(格记录);
  const 三段 = 格记录.轨迹.filter(function (样本) { return 样本.轨迹 && 样本.轨迹.length > 0; });
  if (三段.length === 0) {
    return 判阻塞(格记录, '平台未回阶段轨迹也未回执行批号：重复/迟到完成事件是否双启在外部不可观测');
  }
  const 启动次数 = {};
  三段.forEach(function (样本) {
    样本.轨迹.forEach(function (条目) {
      if (条目.阶段 === '执行中') 启动次数[条目.节点标识] = (启动次数[条目.节点标识] || 0) + 1;
    });
  });
  const 双启 = Object.keys(启动次数).filter(function (键名) { return 启动次数[键名] > 1; });
  记断言(格记录, 双启.length === 0, '轨迹里没有节点被启动两次（实见 ' + JSON.stringify(启动次数) + '）');
  记断言(格记录, 末尾任务阶段(格记录) === '成功', '任务阶段 收口到 成功');
  return 收口(格记录);
}
/* 十一 · 独立分支失败隔离：坏支失败只带走其后代，好支照跑到成功。 */
async function 格失败隔离(格记录) {
  const 本次标识 = 新标识('隔离');
  const 节点清单 = [
    节点('隔离根', 1108, { 程序文本: '隔离根' }),
    节点('好支', 1108, { 程序文本: '好支' }, ['隔离根']),
    节点('坏支', 6110, { 公式文本: '1+', 变量文本: '{}' }, ['隔离根']),
    节点('好支尾', 1108, { 程序文本: '好支尾' }, ['好支']),
    节点('坏支尾', 1108, { 程序文本: '坏支尾' }, ['坏支']),
  ];
  const 提交信封 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  if (!提交信封.成功 || !格记录.任务标识) return 提交受阻(格记录, 提交信封);
  await 采样(格记录, ['隔离根', '好支', '坏支', '好支尾', '坏支尾']);
  if (阶段缺证据(格记录)) return 格记录;
  记断言(格记录, 见过(格记录, '坏支', '失败'), '坏支 真落到 失败');
  记断言(格记录, 见过(格记录, '坏支尾', '跳过'), '坏支尾 被记为 跳过（不跑）');
  记断言(格记录, 见过(格记录, '好支', '成功'), '好支 仍到 成功（失败未扩散）');
  记断言(格记录, 见过(格记录, '好支尾', '成功'), '好支尾 仍到 成功');
  记断言(格记录, 末尾任务阶段(格记录) !== '成功', '任务阶段没有记成 成功（实见 ' + (末尾任务阶段(格记录) || '未回阶段') + '）');
  return 收口(格记录);
}
/* 十二 · 取消执行中 / 等待中的节点：先看任务真在哪一阶段，再取消，然后看有没有停下。 */
async function 格取消(格记录) {
  const 本次标识 = 新标识('取消');
  const 节点清单 = [
    节点('取消根', 1108, { 程序文本: '取消根' }),
    节点('取消一', 1108, { 程序文本: '取消一' }, ['取消根']),
    节点('取消二', 1108, { 程序文本: '取消二' }, ['取消根']),
    节点('取消尾', 1108, { 程序文本: '取消尾' }, ['取消一', '取消二']),
  ];
  const 提交信封 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  if (!提交信封.成功 || !格记录.任务标识) return 提交受阻(格记录, 提交信封);
  const 首查 = await 采一(格记录, 格记录.任务标识, ['取消根', '取消一', '取消二', '取消尾']);
  格记录.轨迹.push(首查);
  const 取消前 = 首查.任务阶段;
  if (取消前 === '') {
    const 末查 = 格记录.流水.filter(function (条目) { return 条目.步.indexOf('查询') === 0; }).pop();
    return 判阻塞(格记录, '首次查询没回任务阶段，取消窗口无法判定（' + (末查 ? 末查.信封通道 + ' · ' + String(末查.说明 || '').slice(0, 100) : '没有查询流水') + '）');
  }
  if (终态集.indexOf(取消前) >= 0) {
    return 判阻塞(格记录, '取消窗口没赶上：查询时任务已在终态 ' + 取消前 + '，执行中/等待中取消未被验到');
  }
  const 取档 = await 控制(格记录, '取消', 控制体('取消', 格记录.任务标识));
  if (!取档.成功) return 判阻塞(格记录, '取消未被受理（' + 取档.信封通道 + '）：' + String(取档.说明 || '').slice(0, 120));
  await 采样(格记录, ['取消根', '取消一', '取消二', '取消尾']);
  记断言(格记录, 末尾任务阶段(格记录) === '已取消', '任务阶段 落到 已取消（实见 ' + (末尾任务阶段(格记录) || '未回阶段') + '）');
  const 未跑节点 = ['取消尾'].filter(function (键名) { return 见过(格记录, 键名, '已取消') || 见过(格记录, 键名, '跳过'); });
  记断言(格记录, 未跑节点.length > 0, '未开工的节点被收成 已取消/跳过');
  const 释放信封 = await 控制(格记录, '释放', 控制体('释放', 格记录.任务标识));
  记断言(格记录, 释放信封.成功 || 释放信封.信封通道 === '业务失败', '释放有明确回执（成功或业务失败，不是崩）');
  return 收口(格记录);
}
/* 十三 · 断线后续查：提交只拿标识就放手，隔一会儿按标识取回同一任务。 */
async function 格断线续查(格记录) {
  const 本次标识 = 新标识('续查');
  const 节点清单 = [
    节点('续查根', 1108, { 程序文本: '续查根' }),
    节点('续查尾', 1108, { 程序文本: '续查尾' }, ['续查根']),
  ];
  const 提交信封 = await 提交(格记录, '提交·立即交回', 提交体(本次标识, 节点清单, { 同步等待毫秒: 0 }));
  if (!提交信封.成功 || !格记录.任务标识) return 提交受阻(格记录, 提交信封);
  const 原标 = 格记录.任务标识;
  记断言(格记录, 原标 !== '', '提交立即交回了真任务标识');
  await 等一会儿(300);
  const 续查信封 = await 控制(格记录, '续查', 控制体('查询', 原标));
  if (!续查信封.成功) return 判阻塞(格记录, '断线后按标识续查未被受理（' + 续查信封.信封通道 + '）：' + String(续查信封.说明 || '').slice(0, 120));
  记断言(格记录, 取任务标识(续查信封) === '' || 取任务标识(续查信封) === 原标, '续查回的还是同一任务（不是新任务）');
  const 阶段 = 取任务阶段(续查信封);
  记断言(格记录, 阶段 !== '', '续查回了任务阶段（实见 ' + (阶段 || '空') + '）');
  if (阶段 === '') return 收口(格记录);
  await 采样(格记录, ['续查根', '续查尾']);
  if (!有节点阶段(格记录)) return 判阻塞(格记录, '续查能拿到任务阶段，但查询未回节点阶段：断线后的阶段细节不可核');
  记断言(格记录, 终态集.indexOf(末尾任务阶段(格记录)) >= 0, '续查把任务追到终态（实见 ' + (末尾任务阶段(格记录) || '未回阶段') + '）');
  return 收口(格记录);
}

