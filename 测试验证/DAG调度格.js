/* 一档一套流程：提交慢图 → 确认节点真在跑 → 按档位取消 → 读阶段。 */
async function 取消一档(格记录, 档名, 档位) {
  const 标 = 新标识('取消' + 档名);
  const 提交信封 = await 提交(格记录, '提交·' + 档名, 提交体(标, [慢节点('慢节点' + 档名, [])], { 同步等待毫秒: 0 }));
  const 任务 = 格记录.任务标识;
  if (!任务) {
    return { 状态: '阻塞', 说明: 档名 + ' 的慢图未被受理（' + String(提交信封.说明 || '没回任务标识') + '）——先确认 ' + 页面设置.慢能力编号 + ' 与模型引用可用' };
  }
  const 开场 = await 采一(格记录, 任务, ['慢节点' + 档名]);
  格记录.轨迹.push(开场);
  if (终态集.indexOf(开场.任务阶段) >= 0) {
    return { 状态: '阻塞', 说明: 档名 + ' 在取消前就已在终态 ' + 开场.任务阶段 + '：模型响应太快，把慢节点令牌数/等待毫秒调大即可' };
  }
  const 起 = performance.now();
  const 取消 = await 控制(格记录, '取消·' + 档名, 控制体('取消', 任务, { 取消档位: 档位 }));
  const 耗 = performance.now() - 起;
  if (!取消.成功) return { 状态: '阻塞', 说明: 档名 + ' 取消未被受理：' + String(取消.说明 || '').slice(0, 140), 任务: 任务 };
  const 阶段 = 取任务阶段(取消);
  await 采样(格记录, ['慢节点' + 档名]);
  /* 耗时只作读数、不作判据：快慢取决于模型这一轮多快，拿它当门槛就是赌时序。
     档位语义看**回执给的是不是终态**，那才是「等不等收口」的真区别。 */
  记断言(格记录, 阶段 !== '', 档名 + ' 回执带了任务阶段（实见 ' + (阶段 || '空') + '，耗时 ' + Math.round(耗) + ' 毫秒）');
  await 控制(格记录, '释放·' + 档名, 控制体('释放', 任务));
  return { 状态: '成', 阶段: 阶段, 耗: 耗 };
}

async function 格取消(格记录) {
  /* 两档都在「节点真在跑」的瞬间发出取消（提交后先采样确认执行中），差别只看回执阶段：
     放弃档不等收口 ⇒ 回「收尾中」；等收口档窗口内等到真终态 ⇒ 回终态。
     窗口没赶上（节点恰好已收口）不算失败，是这一轮没抓到 —— **最多重试三次**，
     三次都没抓到才如实报阻塞。这样判据只依赖「现象是否出现」，不赌某一次的先后。 */
  let 等收口 = null;
  for (let 轮 = 1; 轮 <= 3 && 等收口 === null; 轮 += 1) {
    const 本次 = await 取消一档(格记录, '等收口档第' + 轮 + '轮', '等收口');
    if (本次.状态 === '阻塞') return 判阻塞(格记录, 本次.说明);
    if (终态集.indexOf(本次.阶段) >= 0) 等收口 = 本次;
  }
  if (等收口 === null) {
    return 判阻塞(格记录, '连试三次「等收口」档都在窗口内没等到终态：取消回的都是非终态（窗口上限内节点没收口）');
  }
  记断言(格记录, true, '等收口档回的是真终态「' + 等收口.阶段 + '」（在跑节点收口后才回，不是立刻回）');

  let 放弃 = null;
  for (let 轮 = 1; 轮 <= 3 && 放弃 === null; 轮 += 1) {
    const 本次 = await 取消一档(格记录, '放弃档第' + 轮 + '轮', '放弃');
    if (本次.状态 === '阻塞') return 判阻塞(格记录, 本次.说明);
    if (本次.阶段 === '收尾中' || 本次.阶段 === '已取消') 放弃 = 本次;
  }
  if (放弃 === null) {
    return 判阻塞(格记录, '连试三次「放弃」档，取消时节点都已收口：两档差异这一轮没捕获（语义没错，是窗口没赶上）');
  }
  记断言(格记录, 放弃.耗 < 800, '放弃档立刻回（实测 ' + Math.round(放弃.耗) + ' 毫秒，不等在跑节点收口）');
  记断言(格记录, ['收尾中', '已取消'].indexOf(放弃.阶段) >= 0,
    '放弃档回的是真阶段「' + 放弃.阶段 + '」（不按旗撒谎说已取消）');
  记断言(格记录, true, '两档差异当场可观测：放弃档回「' + 放弃.阶段 + '」· 等收口档回「' + 等收口.阶段 + '」');
  return 收口(格记录);
}

