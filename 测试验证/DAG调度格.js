/* 十 · 重复或迟到完成事件不双启：宿主内部事件黑盒注入不了，只能看批号与轨迹有没有被二次拉起。 */
async function 格迟到完成(格记录) {
  const 本次标识 = 新标识('迟到');
  const 节点清单 = [
    节点('迟到根', 1108, { 程序文本: '迟到根' }),
    节点('迟到尾', 1108, { 程序文本: '迟到尾' }, ['迟到根']),
  ];
  const 左区间段 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  if (!左区间段.成功 || !格记录.任务标识) return 提交受阻(格记录, 左区间段);
  /* 完成前后各重放一次同标识提交：等价于「同一任务被重复唤醒」的外部可见面。 */
  const 右区间段 = await 提交(格记录, '提交·执行中重放', 提交体(本次标识, 节点清单));
  记断言(格记录, 取任务标识(右区间段) === 格记录.任务标识, '执行中重放仍指向同一任务（未新建第二个）');
  await 采样(格记录, ['迟到根', '迟到尾']);
  if (!有节点阶段(格记录)) return 判阻塞(格记录, '查询未回节点阶段：无法核「同一节点是否被启动两次」');
  const 区间册 = 建区间(格记录);
  /* 判「同一节点被启动两次」的可观测口径：执行批号是**逐节点开工**时发出的，一个节点真跑一次
     才吃一个号。所以「各节点批号互不相同」且「最大批号不超过节点数」两条同时成立时，
     不可能有节点多吃过号（否则总号数会超过节点数）。这比盯采样轨迹稳，也不赌时序。 */
  const 批号表 = {};
  Object.keys(区间册).forEach(function (键名) {
    if (区间册[键名].批号 !== null && 区间册[键名].批号 !== undefined) 批号表[键名] = 区间册[键名].批号;
  });
  const 批号键 = Object.keys(批号表);
  if (批号键.length === 0) {
    return 判阻塞(格记录, '平台未回执行批号，也没有阶段轨迹：重复/迟到完成事件是否双启在外部不可观测');
  }
  const 批号值 = 批号键.map(function (键名) { return 批号表[键名]; });
  记断言(格记录, new Set(批号值).size === 批号值.length, '各节点执行批号互不相同（没有两个节点共用一代）');
  记断言(格记录, Math.max.apply(null, 批号值) <= 节点清单.length,
    '最大执行批号不超过节点数（有节点多吃号就说明被启动了两次）：实见 ' + JSON.stringify(批号表));
  记断言(格记录, 末尾任务阶段(格记录) === '成功', '任务阶段 收口到 成功');
  return 收口(格记录);
}
/* 十一 · 独立分支失败隔离：坏支失败只带走其后代，好支照跑到成功。 */
async function 格失败隔离(格记录) {
  const 本次标识 = 新标识('隔离');
  const 节点清单 = [
    节点('隔离根', 1108, { 程序文本: '隔离根' }),
    节点('好支', 1108, { 程序文本: '好支' }, ['隔离根']),
    节点('坏支', 6110, { 公式文本: '1+', 变量文本: '{}' }, ['隔离根']),
    节点('好支尾', 1108, { 程序文本: '好支尾' }, ['好支']),
    节点('坏支尾', 1108, { 程序文本: '坏支尾' }, ['坏支']),
  ];
  /* 不等同步：这一格要的是**节点级组合**，不是中间态 —— 坏支 6102 立刻失败，整图二十毫秒就收口，
     带同步等待的话第一次快照已是终态，反倒看不出「谁成功谁跳过」。 */
  const 提交信封 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单, { 同步等待毫秒: 0 }));
  /* 受理判据只看「回执有没有任务标识」：带同步等待时，等到失败结局也是 `成功:false`，
     拿 成功 当受理判据会把「跑失败了」误读成「没受理」（格 10 就是要它失败）。 */
  if (!格记录.任务标识) return 提交受阻(格记录, 提交信封);
  await 采样(格记录, ['隔离根', '好支', '坏支', '好支尾', '坏支尾']);
  /* 判据不依赖「采样抓到中间态」：只要有一份快照带节点阶段，节点级组合就能判 ——
     拿「有没有中间态」当门槛，等于赌采样能不能赶上二十毫秒的图。 */
  if (!有节点阶段(格记录)) {
    return 判阻塞(格记录, '一次快照都没拿到节点阶段：失败隔离（谁成功、谁跳过）无从判');
  }
  记断言(格记录, 见过(格记录, '坏支', '失败'), '坏支 真落到 失败');
  记断言(格记录, 见过(格记录, '坏支尾', '跳过'), '坏支尾 被记为 跳过（不跑）');
  记断言(格记录, 见过(格记录, '好支', '成功'), '好支 仍到 成功（失败未扩散）');
  记断言(格记录, 见过(格记录, '好支尾', '成功'), '好支尾 仍到 成功');
  记断言(格记录, 末尾任务阶段(格记录) !== '成功', '任务阶段没有记成 成功（实见 ' + (末尾任务阶段(格记录) || '未回阶段') + '）');
  return 收口(格记录);
}
