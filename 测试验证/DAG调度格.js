/* 左区间段 · 菱形汇合：起点 → 左支 / 右支 / 旁支 → 汇合。 */
async function 格菱形汇合(格记录) {
  const 本次标识 = 新标识('菱形');
  const 节点清单 = [
    节点('起点', 1108, { 程序文本: '起点' }),
    节点('左支', 1108, { 程序文本: '左支' }, ['起点']),
    节点('右支', 1108, { 程序文本: '右支' }, ['起点']),
    节点('旁支', 1108, { 程序文本: '旁支' }, ['起点']),
    节点('汇合', 1108, { 程序文本: '汇合' }, ['左支', '右支', '旁支']),
  ];
  const 提交信封 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  /* 受理判据只看「回执有没有任务标识」：带同步等待时，等到失败结局也是 `成功:false`，
     拿 成功 当受理判据会把「跑失败了」误读成「没受理」（格 10 就是要它失败）。 */
  if (!格记录.任务标识) return 提交受阻(格记录, 提交信封);
  await 采样(格记录, ['起点', '左支', '右支', '旁支', '汇合']);
  if (阶段缺证据(格记录)) return 格记录;
  /* 先看平台回执给没给节点时刻：给了就不必依赖采样抓到中间阶段（图比采样还快也能判）。 */
  const 区间册 = 建区间(格记录);
  const 分叉节点 = ['左支', '右支', '旁支', '汇合'];
  if (!区间证据齐(区间册, 分叉节点) && 中间态缺证据(格记录, 分叉节点)) return 格记录;
  if (!区间证据齐(区间册, 分叉节点)) {
    return 判阻塞(格记录, '平台既不回节点开始/结束时刻，采样也没抓到中间阶段：并发区间不可观测，证据不足');
  }
  记断言(格记录, 见过(格记录, '汇合', '等待依赖') || 见过(格记录, '汇合', '就绪') || 区间册['汇合'].起点时刻 !== null,
    '汇合 在开工前处于 等待依赖/就绪（图比采样快时以平台时刻为准）');
  /* 「真进入过执行中」不能只认采样：图跑完只要 0.3 毫秒，任何轮询都可能一次都抓不到。
     平台给了开始与结束时刻，就是它真跑过的凭据 —— 这比"我看见了"更硬。 */
  记断言(格记录, 见过(格记录, '汇合', '执行中')
    || (区间册['汇合'].起点时刻 !== null && 区间册['汇合'].止 !== null),
    '汇合 真跑过（采样见过执行中，或平台给了两端时刻）');
  ['左支', '右支', '旁支'].forEach(function (键名) {
    记断言(格记录, 区间册[键名] && 区间册[键名].阶段.indexOf('成功') >= 0, 键名 + ' 到达 成功');
  });
  const 前驱止 = ['左支', '右支', '旁支'].map(function (键名) { return 区间册[键名] ? 区间册[键名].止 : null; });
  const 汇合起 = 区间册['汇合'] ? 区间册['汇合'].起点时刻 : null;
  const 全部有 = 前驱止.every(function (值) { return 值 !== null; }) && 汇合起 !== null;
  记断言(格记录, 全部有 && 汇合起 >= Math.max.apply(null, 前驱止), '汇合 起点不早于三个前驱各自终点（区间不重叠）');
  记断言(格记录, 末尾任务阶段(格记录) === '成功', '任务阶段 收口到 成功');
  return 收口(格记录);
}
/* 右区间段 · 嵌套分支展开：根 → 层一 →（层二左 / 层二右）→ 尾；分支里再开分支。 */
async function 格嵌套分支(格记录) {
  const 本次标识 = 新标识('嵌套');
  const 节点清单 = [
    节点('根', 1108, { 程序文本: '根' }),
    节点('层一', 1108, { 程序文本: '层一' }, ['根']),
    节点('层二左', 1108, { 程序文本: '层二左' }, ['层一']),
    节点('层二右', 1108, { 程序文本: '层二右' }, ['层一']),
    节点('尾', 1108, { 程序文本: '尾' }, ['层二左', '层二右']),
  ];
  const 提交信封 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  /* 受理判据只看「回执有没有任务标识」：带同步等待时，等到失败结局也是 `成功:false`，
     拿 成功 当受理判据会把「跑失败了」误读成「没受理」（格 10 就是要它失败）。 */
  if (!格记录.任务标识) return 提交受阻(格记录, 提交信封);
  await 采样(格记录, ['根', '层一', '层二左', '层二右', '尾']);
  if (阶段缺证据(格记录)) return 格记录;
  const 区间册 = 建区间(格记录);
  const 嵌套节点 = ['层一', '层二左', '层二右', '尾'];
  if (!区间证据齐(区间册, 嵌套节点) && 中间态缺证据(格记录, 嵌套节点)) return 格记录;
  if (!区间证据齐(区间册, 嵌套节点)) {
    return 判阻塞(格记录, '平台既不回节点开始/结束时刻，采样也没抓到中间阶段：嵌套分支起跑先后不可观测');
  }
  记断言(格记录, 区间册['层二左'] && 区间册['层二右'], '两组嵌套节点都被查询回报过阶段');
  const 层一止 = 区间册['层一'] ? 区间册['层一'].止 : null;
  const 左起 = 区间册['层二左'] ? 区间册['层二左'].起点时刻 : null;
  const 右起 = 区间册['层二右'] ? 区间册['层二右'].起点时刻 : null;
  记断言(格记录, 层一止 !== null && 左起 !== null && 右起 !== null && 左起 >= 层一止 && 右起 >= 层一止, '两支内层节点都晚于 层一 终点起跑');
  记断言(格记录, 区间重叠(区间册['层二左'], 区间册['层二右']), '层二左 与 层二右 执行区间重叠（分支确实展开）');
  const 尾起 = 区间册['尾'] ? 区间册['尾'].起点时刻 : null;
  记断言(格记录, 尾起 !== null && 左起 !== null && 右起 !== null && 尾起 >= Math.max(左起, 右起), '尾 晚于两支起跑');
  记断言(格记录, 末尾任务阶段(格记录) === '成功', '任务阶段 收口到 成功');
  return 收口(格记录);
}
/* 三 · 两张图并发提交：两张互不相干的图同时提交，各自独立推进。 */
async function 格两图并发(格记录) {
  const 标一 = 新标识('并发图一');
  const 标二 = 新标识('并发图二');
  const 图一 = [
    节点('一图根', 1108, { 程序文本: '一图根' }),
    节点('一图尾', 1108, { 程序文本: '一图尾' }, ['一图根']),
  ];
  const 图二 = [
    节点('二图根', 1108, { 程序文本: '二图根' }),
    节点('二图尾', 1108, { 程序文本: '二图尾' }, ['二图根']),
  ];
  const 起重 = performance.now();
  const 两封 = await Promise.all([
    提交(格记录, '提交·图一', 提交体(标一, 图一)),
    提交(格记录, '提交·图二', 提交体(标二, 图二)),
  ]);
  const 一封 = 格记录.流水.filter(function (条目) { return 条目.步 === '提交·图一'; });
  const 二封 = 格记录.流水.filter(function (条目) { return 条目.步 === '提交·图二'; });
  const 一标 = 一封.length > 0 ? 取任务标识({ 值: 一封[0].值 }) : '';
  const 二标 = 二封.length > 0 ? 取任务标识({ 值: 二封[0].值 }) : '';
  if (!两封[0].成功 || !两封[1].成功 || !一标 || !二标) {
    return 判阻塞(格记录, '两张图至少一张未被受理（图一：' + 两封[0].信封通道 + '；图二：' + 两封[1].信封通道 + '）');
  }
  记断言(格记录, 一标 !== 二标, '两张图拿到互不相同的任务标识');
  记断言(格记录, Math.round(performance.now() - 起重) < 页面设置.请求超时毫秒, '两次提交在同一次并发里交回（未串行等待完成）');
  /* 两图各自采样：串行采会掩掉重叠，所以两边并发采。 */
  const 一记 = { 轨迹: [], 流水: [], 任务标识: 一标 };
  const 二记 = { 轨迹: [], 流水: [], 任务标识: 二标 };
  await Promise.all([
    采样(一记, ['一图根', '一图尾']),
    采样(二记, ['二图根', '二图尾']),
  ]);
  格记录.轨迹 = 一记.轨迹.concat(二记.轨迹);
  const 区间一 = 建区间(一记);
  const 区间二 = 建区间(二记);
  const 一末 = 一记.轨迹.length > 0 ? 一记.轨迹[一记.轨迹.length - 1].任务阶段 : '';
  const 二末 = 二记.轨迹.length > 0 ? 二记.轨迹[二记.轨迹.length - 1].任务阶段 : '';
  记断言(格记录, 一末 === '成功', '图一 收口到 成功（实见 ' + (一末 || '未回阶段') + '）');
  记断言(格记录, 二末 === '成功', '图二 收口到 成功（实见 ' + (二末 || '未回阶段') + '）');
  if (区间一['一图根'] && 区间一['一图尾']) {
    记断言(格记录, 区间一['一图尾'].起点时刻 !== null && 区间一['一图根'].止 !== null
      && 区间一['一图尾'].起点时刻 >= 区间一['一图根'].止, '图一内部 尾 不早于 根 结束（自身时钟内可比）');
  }
  if (区间二['二图根'] && 区间二['二图尾']) {
    记断言(格记录, 区间二['二图尾'].起点时刻 !== null && 区间二['二图根'].止 !== null
      && 区间二['二图尾'].起点时刻 >= 区间二['二图根'].止, '图二内部 尾 不早于 根 结束（自身时钟内可比）');
  }
  /* 零时是**进程装载那一刻**（不是本任务提交）⇒ 两张图的时刻落在同一只时钟上，可直接比。
     本格证的是「跨任务可比」；「执行区间真重叠」由格 04 四节点并行给出（那格不赌调度时序）。 */
  const 一始 = 区间一['一图根'] ? 区间一['一图根'].起点时刻 : null;
  const 一止 = 区间一['一图尾'] ? 区间一['一图尾'].止 : null;
  const 二始 = 区间二['二图根'] ? 区间二['二图根'].起点时刻 : null;
  if (一始 === null || 二始 === null || 一止 === null) {
    return 判阻塞(格记录, '有图没拿到节点开始/结束时刻：平台没回时刻，跨任务可比无从判');
  }
  记断言(格记录, 一始 > 0 && 二始 > 0,
    '零时是进程装载那一刻，不是各自任务提交（图一 ' + 一始 + ' 微秒 · 图二 ' + 二始 + ' 微秒）');
  /* 两张图并发提交时**起跑先后不固定**（图二可能先起跑），所以不拿「谁先」当判据；
     跨任务可比要证的是「两张图的时刻落在同一只进程时钟上，能直接相减」：
     再加第三张图，在两张图都收完之后提交 ⇒ 它的起点必须不早于前两张的终点。
     修复前（零时是本任务提交）第三张图的起点会掉到 0 附近，这条必红。 */
  const 三标 = 新标识('并发图三');
  格记录.任务标识 = '';
  const 三封 = await 提交(格记录, '提交·图三（收完之后）', 提交体(三标, [节点('三图根', 页面设置.资源键编号, { 程序文本: '三图根' })], { 同步等待毫秒: 3000 }));
  const 三任务 = 格记录.任务标识;
  if (!三任务) return 判阻塞(格记录, '第三张图未被受理：' + String(三封.说明 || '没回任务标识').slice(0, 120));
  const 三查 = await 控制(格记录, '查询·图三', 控制体('查询', 三任务));
  const 三节 = (取节点项(三查) || []).filter(function (项) { return 项.标识 === '三图根'; })[0] || {};
  const 三始 = typeof 三节.开始 === 'number' ? 三节.开始 : null;
  if (三始 === null) return 判阻塞(格记录, '第三张图没回节点开始时刻：跨任务可比无从判');
  记断言(格记录, 三始 >= 一止,
    '跨任务可比：图三起点 ' + 三始 + ' 不早于图一终点 ' + 一止 + ' 微秒（同一只进程时钟）');
  await 控制(格记录, '释放·图三', 控制体('释放', 三任务));
  return 收口(格记录);
}
/* 四 · 车道节点独属：同编号的四个独立节点**真并行**，谁都不用排队。 */
async function 格车道独属并行(格记录) {
  const 本次标识 = 新标识('车道独属');
  const 能力号 = 页面设置.资源键编号;
  const 名单 = ['并行一', '并行二', '并行三', '并行四'];
  const 节点清单 = 名单.map(function (键名) { return 节点(键名, 能力号, { 程序文本: 键名 }); });
  const 提交信封 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  /* 受理判据只看「回执有没有任务标识」：带同步等待时，等到失败结局也是 `成功:false`，
     拿 成功 当受理判据会把「跑失败了」误读成「没受理」（格 10 就是要它失败）。 */
  if (!格记录.任务标识) return 提交受阻(格记录, 提交信封);
  await 采样(格记录, 名单);
  if (阶段缺证据(格记录)) return 格记录;
  const 区间册 = 建区间(格记录);
  /* 「真跑过」不能靠采样抓「执行中」：1108 亚毫秒跑完，轮询很可能一次都抓不到。
     平台给了开始与结束时刻，就是它真跑过的硬凭据 —— 比「我看见了」更硬。 */
  记断言(格记录, 名单.every(function (键名) {
    const 一档 = 区间册[键名];
    return 见过(格记录, 键名, '执行中') || 见过(格记录, 键名, '收尾中')
      || (一档 && 一档.起点时刻 !== null && 一档.止 !== null);
  }), '四个节点都真跑过（见过 执行中，或平台给了两端时刻）');
  /* 车道是按节点独属的（键里含节点标识）⇒ 全程不该有任何节点进过 等资源。
     反过来一旦见到 等资源，说明有两条节点共用了一条车道：那就是键推导坏了。 */
  记断言(格记录, 名单.every(function (键名) { return !见过(格记录, 键名, '等资源'); }),
    '没有任何节点进过 等资源（车道按节点独属，异节点互不相干）');
  let 真重叠对 = 0;
  for (let 前位 = 0; 前位 < 名单.length; 前位 += 1) {
    for (let 后位 = 前位 + 1; 后位 < 名单.length; 后位 += 1) {
      if (区间重叠(区间册[名单[前位]], 区间册[名单[后位]])) 真重叠对 += 1;
    }
  }
  记断言(格记录, 真重叠对 >= 1, '至少有一对节点的执行区间真重叠（并行，不是一条道串起来）');
  记断言(格记录, 末尾任务阶段(格记录) === '成功', '四个节点都收口到 成功');
  return 收口(格记录);
}
