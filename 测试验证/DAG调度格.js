/* 左区间段 · 菱形汇合：起点 → 左支 / 右支 / 旁支 → 汇合。 */
async function 格菱形汇合(格记录) {
  const 本次标识 = 新标识('菱形');
  const 节点清单 = [
    节点('起点', 1108, { 程序文本: '起点' }),
    节点('左支', 1108, { 程序文本: '左支' }, ['起点']),
    节点('右支', 1108, { 程序文本: '右支' }, ['起点']),
    节点('旁支', 1108, { 程序文本: '旁支' }, ['起点']),
    节点('汇合', 1108, { 程序文本: '汇合' }, ['左支', '右支', '旁支']),
  ];
  const 提交信封 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  if (!提交信封.成功 || !格记录.任务标识) return 提交受阻(格记录, 提交信封);
  await 采样(格记录, ['起点', '左支', '右支', '旁支', '汇合']);
  if (阶段缺证据(格记录)) return 格记录;
  if (中间态缺证据(格记录, ['左支', '右支', '旁支', '汇合'])) return 格记录;
  const 区间册 = 建区间(格记录);
  if (!区间证据齐(区间册, ['左支', '右支', '旁支', '汇合'])) {
    return 判阻塞(格记录, '平台回执不带节点开始/结束时刻（只有阶段名）：并发区间与汇合时点不可观测，证据不足');
  }
  记断言(格记录, 见过(格记录, '汇合', '等待依赖') || 见过(格记录, '汇合', '就绪'), '汇合 在开工前处于 等待依赖/就绪');
  记断言(格记录, 见过(格记录, '汇合', '执行中'), '汇合 真进入过 执行中');
  ['左支', '右支', '旁支'].forEach(function (键名) {
    记断言(格记录, 区间册[键名] && 区间册[键名].阶段.indexOf('成功') >= 0, 键名 + ' 到达 成功');
  });
  const 前驱止 = ['左支', '右支', '旁支'].map(function (键名) { return 区间册[键名] ? 区间册[键名].止 : null; });
  const 汇合起 = 区间册['汇合'] ? 区间册['汇合'].起点时刻 : null;
  const 全部有 = 前驱止.every(function (值) { return 值 !== null; }) && 汇合起 !== null;
  记断言(格记录, 全部有 && 汇合起 >= Math.max.apply(null, 前驱止), '汇合 起点不早于三个前驱各自终点（区间不重叠）');
  记断言(格记录, 末尾任务阶段(格记录) === '成功', '任务阶段 收口到 成功');
  return 收口(格记录);
}
/* 右区间段 · 嵌套分支展开：根 → 层一 →（层二左 / 层二右）→ 尾；分支里再开分支。 */
