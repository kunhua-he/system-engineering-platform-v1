#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""使用面回归 · 命令行界面 —— 失败保真 + 每次操作只发一次请求（替身发请求夹具）。

判据：`接口面形状.md` §三（业务失败一律 200 + `成功:false` + 完整错误对象）。
为什么要有它：失败保真（未知应答退出码 3 · 完整失败应答）与「同一操作只调一次」
此前**零自动化测试** —— `前端呈现/命令行界面/` 没有运行时回归，
静态检查不算运行时覆盖。

做法：**替身发请求**（`假发请求`）拦住网络，记下每次调用的参数并回一份预设应答；
被测的是真 `命令模块.命令调用`（真走 `json.loads` + 分支 + `显示`）。不启网关、不引第三方库。

    python3 测试验证/准入判据/使用面回归_命令行.py
退出码：0 = 各条断言成立；1 = 有断言不成立。
"""

import io
import json
import sys
from contextlib import redirect_stdout
from pathlib import Path

仓根 = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(仓根 / "前端呈现/命令行界面"))

from 命令行界面 import 命令 as 命令模块  # noqa: E402

请求记录 = []
当前应答 = (200, "{}")


def 假发请求(监听端口, 协议方法, 接口路径, 请求体文本, 显示请求):
    """替身：记下这次调用，回一份预设应答（**不碰网络**）。"""
    请求记录.append({"协议方法": 协议方法, "接口路径": 接口路径, "请求体文本": 请求体文本})
    return 当前应答


# 装替身：`命令调用` 经模块级名 `发请求` 取它，替换模块属性即可。
命令模块.发请求 = 假发请求


def 跑调用(应答对, 进程参数):
    """用替身发请求跑一次 `命令调用`，返回 (实际码, 捕获输出, 请求次数)。"""
    global 当前应答
    请求记录.clear()
    当前应答 = 应答对
    输出缓冲 = io.StringIO()
    with redirect_stdout(输出缓冲):
        实际码 = 命令模块.命令调用(43110, 进程参数, False)
    return 实际码, 输出缓冲.getvalue(), len(请求记录)


def 跑命令行回归():
    成功体 = json.dumps(
        {"成功": True, "值": [{"类型标签": 4, "值": "ok"}], "耗时微秒": 1}, ensure_ascii=False
    )
    失败体 = json.dumps(
        {"成功": False, "错误": {"码": 1, "段位": 0, "名称": "提供者未载入",
                            "可重试": True, "可自愈": True, "需人工": False, "已登记": True}},
        ensure_ascii=False,
    )
    未知体 = json.dumps({"值": [{"类型标签": 4, "值": "ok"}]}, ensure_ascii=False)

    成功样本 = 跑调用((200, 成功体), ["1101", "abc"])
    失败样本 = 跑调用((200, 失败体), ["999999"])
    未知样本 = 跑调用((200, 未知体), ["1101", "abc"])
    非JSON样本 = 跑调用((200, "{这不是 JSON"), ["1101", "abc"])

    用例表 = [
        ("① 成功：只发一次请求", 成功样本[2] == 1, "请求次数=%d" % 成功样本[2]),
        ("① 成功：退出码 0", 成功样本[0] == 0, "退出码=%d" % 成功样本[0]),
        ("② 失败：只发一次请求", 失败样本[2] == 1, "请求次数=%d" % 失败样本[2]),
        ("② 失败：退出码 1", 失败样本[0] == 1, "退出码=%d" % 失败样本[0]),
        ("② 失败：显示完整失败应答（保真）",
         ("完整失败应答" in 失败样本[1]) and ("提供者未载入" in 失败样本[1]),
         "含完整失败应答=%s" % ("完整失败应答" in 失败样本[1])),
        ("③ 未知应答：退出码 3", 未知样本[0] == 3, "退出码=%d" % 未知样本[0]),
        ("③ 未知应答：只发一次请求", 未知样本[2] == 1, "请求次数=%d" % 未知样本[2]),
        ("③ 未知应答：不谎报成功", "成功：是" not in 未知样本[1], "输出首行=%r" % 未知样本[1].splitlines()[:1]),
        ("④ 非 JSON：退出码 3", 非JSON样本[0] == 3, "退出码=%d" % 非JSON样本[0]),
        ("④ 非 JSON：只发一次请求", 非JSON样本[2] == 1, "请求次数=%d" % 非JSON样本[2]),
    ]

    失败表 = []
    print("使用面回归 · 命令行界面（替身发请求夹具）")
    for 条名, 条件, 实际 in 用例表:
        print("  [%s] %s" % ("符合" if 条件 else "不符", 条名))
        print("        实际：%s" % 实际)
        if not 条件:
            失败表.append(条名)
    print("")
    if 失败表:
        print("命令行回归：不符 %d 条 —— %s" % (len(失败表), " · ".join(失败表)))
        return 1
    print("命令行回归：全部符合（退出码 0）")
    return 0

