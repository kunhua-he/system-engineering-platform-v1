def 段含键(文: str, 段名: str, 键: str) -> bool:
    """粗判 TOML：段 [段名] 到下一个 [ 之间是否出现 键。"""
    行 = 文.splitlines()
    在段 = False
    for 行文 in 行:
        净 = 行文.strip()
        if 净.startswith("[") and 净.endswith("]"):
            在段 = 净 == f"[{段名}]"
            continue
        if 在段 and 净.split("=")[0].strip() == 键:
            return True
    return False


