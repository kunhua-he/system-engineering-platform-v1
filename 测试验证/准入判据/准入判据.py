#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""外部支持库准入判据 —— 把 `项目文档/决策记录/2026-09-27_外部支持库准入判据.md` 的
**16 条**里**机器可判**的做成能跑的判据；不可机器判的**如实登记**（不假装覆盖）。

上级判据：`项目文档/设计文档/判据的可信性.md`（最高判据）。本件按它落三条：
  **读数三元**（通过 / 失败 / 未判，空集不算通过）·
  **每条判据成对样本**（反向样本 + 正向样本，缺一即「未验证」）·
  **每条判据声明扫描面并报实际读数**。

────────────────────────────────────────────────────────────────────────────
怎么单独跑（在仓库根；零第三方依赖，只 `python3` 标准库；**不跑 cargo**）

    python3 测试验证/准入判据/准入判据.py            # 判一遍，打三元读数
    python3 测试验证/准入判据/准入判据.py --读数      # 加打每条判据的扫描面与对象数
    python3 测试验证/准入判据/准入判据.py --自测      # 逐条跑正向/反向样本，断言判据抓得住
    python3 测试验证/准入判据/准入判据.py --清单      # 16 条逐条：做了 / 没做 / 为什么

输出：

    准入判据：通过 <N> · 失败 <M> · 未判 <K> · 机器可判 <X>/16 · 耗时 <毫秒> ms

退出码：16 条全通过 = 0；否则 = 1（**未判也算「没验过」**，计入非零）。
自测（`--自测`）：每条机器可判判据的正/反向样本都符合预期 = 0；否则 = 1。

口径（判据的可信性 §二/§五/§六）：
  · 三元读数；空集报未判，不许算通过。
  · 每条判据声明扫描面；`--读数` 报实际对象数。
  · 反向样本 = 把修法退回一步 ⇒ 必红；正向样本 = 干净输入 ⇒ 必过。
    缺任一方 ⇒ 该判据「未验证」。
────────────────────────────────────────────────────────────────────────────

本文件是**路由**：解析参数 → 调包里的公开面 → 打印 → 退出码。判据本体在 `准入判据/`
（一个关注点一个文件）。
"""

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from 准入判据.报告 import 单条, 扫, 打印, 清单  # noqa: E402
from 准入判据.样本 import 自测  # noqa: E402
from 准入判据.世界 import 世界, 找仓根  # noqa: E402


def main(参数) -> int:
    根 = 找仓根()
    if "--自测" in 参数:
        return 自测()
    if "--清单" in 参数:
        清单()
        return 0
    世 = 世界(根)
    if "--判" in 参数:
        i = 参数.index("--判")
        if i + 1 >= len(参数):
            print("用法：--判 <编号>（如 --判 ⑧）")
            return 1
        return 单条(世, 参数[i + 1])
    起 = time.perf_counter()
    结果 = 扫(世)
    毫秒 = int((time.perf_counter() - 起) * 1000)
    打印(结果, 毫秒, 读数="--读数" in 参数)
    失败 = sum(1 for _, _, _, r in 结果 if r[0] == "失败")
    未判 = sum(1 for _, _, _, r in 结果 if r[0] == "未判")
    # 16 条口径：机器可判 10 条 + 不可机器判 6 条（恒未判）
    return 0 if (失败 == 0 and 未判 == 0 and len(结果) == 16) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
