def _复制(世: 世界) -> 世界:
    新 = object.__new__(世界)
    新.__dict__ = dict(世.__dict__)
    return 新


def _复制扩展目录(世: 世界) -> Path:
    目标 = Path(tempfile.mkdtemp(prefix="准入判据_指纹_")) / "编译器支持库"
    shutil.copytree(世.扩展目录(), 目标)
    return 目标


def 自测() -> int:
    """逐条跑正/反向样本：正向必过、反向必红。缺任一方 ⇒ 该条未验证。"""
    世 = 世界(找仓根())
    起 = time.perf_counter()
    失败 = []
    行 = []

    def 断(编号, 名, 样本, 期望, 果):
        if 果[0] != 期望:
            失败.append(f"{编号} {名}｜{样本}：期望 {期望}，实得 {果[0]}（{果[1]}）")
            return False
        return True

    # ④
    正 = _复制(世)
    断("④", "广播段", "正向样本", "通过", 判_4(正))
    反 = _复制(世)
    反.判定rs = 反.判定rs.replace("if 生命周期广播段(段.起, 段.止) {\n            continue;\n        }", "")
    断("④", "广播段", "反向样本（抽掉广播段 continue）", "失败", 判_4(反))

    # ⑤
    正 = _复制(世)
    断("⑤", "通知口", "正向样本", "通过", 判_5(正))
    反 = _复制(世)
    反.通知口 = 反.通知口.replace("pub fn 注册通知端点", "fn _没了_注册通知端点")
    断("⑤", "通知口", "反向样本（抽掉注册通知端点）", "失败", 判_5(反))

    # ⑦
    正 = _复制(世)
    断("⑦", "接缝冻结", "正向样本", "通过", 判_7(正))
    反 = _复制(世)
    反.边界协议 = 反.边界协议.replace("不复刻", "保持一致").replace("偏离", "保持一致")
    断("⑦", "接缝冻结", "反向样本（抽掉「不复刻/偏离」）", "失败", 判_7(反))

    # ⑧
    正 = _复制(世)
    断("⑧", "无死键", "正向样本", "通过", 判_8(正))
    反 = _复制(世)
    路, 声 = 反.包声明表[0]
    带死键 = dict(声)
    带死键["提供宿主版本"] = {"主": 1, "次": 0, "修订": 0, "构建": 0}
    反.包声明表 = [(路, 带死键)]
    断("⑧", "无死键", "反向样本（注入 提供宿主版本）", "失败", 判_8(反))

    # ⑨
    正 = _复制(世)
    断("⑨", "crate-type", "正向样本", "通过", 判_9(正))
    反 = _复制(世)
    路, 文 = 反.扩展Cargo表[0]
    反.扩展Cargo表 = [(路, 文.replace("[lib]\n", '[lib]\ncrate-type = ["cdylib"]\n'))]
    断("⑨", "crate-type", "反向样本（注入 crate-type）", "失败", 判_9(反))

    # ⑩：空集 → 未判；注入一条合法 → 通过；注入一条非法 → 失败（证明非空转）
    临时 = Path(tempfile.mkdtemp(prefix="准入判据_类别_")) / "0000.json"
    临时.write_text(json.dumps({"类别号": 0, "名称": "默认", "说明": "默认类别"},
                              ensure_ascii=False), encoding="utf-8")
    正 = _复制(世)
    正.命令类别 = [临时]
    断("⑩", "命令类别", "正向样本（注入 1 条合法）", "通过", 判_10(正))
    反 = _复制(世)
    临时2 = Path(tempfile.mkdtemp(prefix="准入判据_类别_")) / "0001.json"
    临时2.write_text(json.dumps({"类别号": 99, "名称": "", "说明": ""}, ensure_ascii=False),
                    encoding="utf-8")
    反.命令类别 = [临时2]
    断("⑩", "命令类别", "反向样本（类别号≠文件名 + 名/说明空）", "失败", 判_10(反))
    空 = _复制(世)
    空.命令类别 = []
    断("⑩", "命令类别", "空集样本（必报未判，不许算通过）", "未判", 判_10(空))

    # ⑪：口径已补（2026-09-27 协调方施工，`载入判定.json` 的 `判定顺序的优先级`）。
    # 正/反都**合成**：正向 = 真件（应通过）；反向 = 真件**去掉那条键**（应失败）。
    # **为什么反向不许再用「现状」**：现状一旦被修好，反向样本就当场消失（判据的身份证没了）——
    # 判据的可信性.md 第五节：反向样本必须是**固定**的一份输入，不许跟着实物漂。
    正 = _复制(世)
    断("⑪", "显式顺序", "正向样本（真件已写明先于关系）", "通过", 判_11(正))
    反 = _复制(世)
    反.载入判定文 = re.sub(
        r'\s*"判定顺序的优先级"\s*:\s*"(?:[^"\\]|\\.)*",', "", 反.载入判定文)
    断("⑪", "显式顺序", "反向样本（合成：抽掉那条优先级键）", "失败", 判_11(反))

    # ⑬
    正 = _复制(世)
    断("⑬", "报因", "正向样本", "通过", 判_13(正))
    反 = _复制(世)
    反.启动网关 = 反.启动网关.replace("剔除的.push", "let _ = 丢弃;")
    断("⑬", "报因", "反向样本（抽掉剔除台账）", "失败", 判_13(反))

    # ⑭：正向 = 临时副本刷新指纹后 --检查 退 0；反向 = 改一个哈希后 --检查 退 1
    临时根 = Path(tempfile.mkdtemp(prefix="准入判据_指纹根_"))
    (临时根 / "扩展装载").mkdir(parents=True, exist_ok=True)
    临时扩展 = 临时根 / 扩展根目录名 / "原子支持库" / "编译器支持库"
    临时扩展.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(世.扩展目录(), 临时扩展)
    # 先刷新（去掉漂移），再判
    subprocess.run([sys.executable, str(临时扩展 / "工具/重跑指纹.py")],
                   capture_output=True, text=True, timeout=120)
    正 = _复制(世)
    正.仓根 = 临时根
    正.扩展目录 = lambda: 临时扩展  # 覆盖方法
    正.指纹件 = lambda: 临时扩展 / "指纹.json"
    正.指纹脚本 = lambda: 临时扩展 / "工具/重跑指纹.py"
    断("⑭", "指纹可跑", "正向样本（临时副本刷新后 --检查）", "通过", 判_14(正))
    # 反向：改一个哈希
    指纹 = json.loads((临时扩展 / "指纹.json").read_text(encoding="utf-8"))
    首键 = next(iter(指纹["指纹"]))
    指纹["指纹"][首键] = "0" * 64
    (临时扩展 / "指纹.json").write_text(json.dumps(指纹, ensure_ascii=False, indent=2),
                                      encoding="utf-8")
    反 = _复制(世)
    反.仓根 = 临时根
    反.扩展目录 = lambda: 临时扩展
    反.指纹件 = lambda: 临时扩展 / "指纹.json"
    反.指纹脚本 = lambda: 临时扩展 / "工具/重跑指纹.py"
    断("⑭", "指纹可跑", "反向样本（改一个哈希）", "失败", 判_14(反))

    # ⑯
    正 = _复制(世)
    断("⑯", "并发", "正向样本", "通过", 判_16(正))
    反 = _复制(世)
    反.线程安全 = 反.线程安全.replace("unsafe impl Sync for 适配器 {}", "")
    断("⑯", "并发", "反向样本（抽掉 Sync 断言）", "失败", 判_16(反))

    毫秒 = int((time.perf_counter() - 起) * 1000)
    for 编号, 名, 判 in 机器判据:
        行.append(f"  {编号} {名}")
    print("准入判据自测（正向必过 · 反向必红）")
    for 文 in 行:
        print(文)
    print(f"\n样本断言：{len(失败) == 0 and '全过' or '有失败'} · 耗时 {毫秒} ms")
    for 文 in 失败:
        print(f"  ✗ {文}")
    if not 失败:
        print("  每条机器判据的 正向样本 与 反向样本 都符合预期（判据非空转）")
    return 0 if not 失败 else 1


