def 打印(结果, 耗时毫秒, 读数=False):
    通过 = sum(1 for _, _, _, r in 结果 if r[0] == "通过")
    失败 = sum(1 for _, _, _, r in 结果 if r[0] == "失败")
    未判 = sum(1 for _, _, _, r in 结果 if r[0] == "未判")
    print(f"准入判据：通过 {通过} · 失败 {失败} · 未判 {未判} · "
          f"机器可判 {len(机器判据)}/16 · 耗时 {耗时毫秒} ms")
    print("")
    for 编号, 名, 面, (判定, 证据, 对象数) in 结果:
        标 = {"通过": "✓", "失败": "✗", "未判": "○"}[判定]
        print(f"{标} {编号} {名}｜{判定}｜{证据}")
        if 读数:
            print(f"    扫描面：{面}｜对象数：{对象数}")
    print("")
    print("不可机器判的 6 条（如实登记，未判）：")
    for 编号 in ["①", "②", "③", "⑥", "⑫", "⑮"]:
        名, 判不了, 缺 = 登记[编号]
        print(f"  ○ {编号} {名}")
        print(f"      为什么判不了：{判不了}")
        print(f"      缺什么才能判：{缺}")


def 清单():
    print("16 条逐条：")
    for 编号, 名, 判 in 机器判据:
        print(f"  {编号} 做了（机器可判）  {名}")
    for 编号 in ["①", "②", "③", "⑥", "⑫", "⑮"]:
        名, 判不了, 缺 = 登记[编号]
        print(f"  {编号} 没做（不可机器判）  {名}")


def 扫(世: 世界):
    面 = {
        "④": "契约声明/src/声明数据.rs::通知号段 · 运行内核/装载入口/src/判定.rs · 扩展装载/载入约定/载入判定.json",
        "⑤": "跨语言适配/适配器实现/src/通知口.rs · 跨语言适配/适配器实现/src/lib.rs::装载声明根",
        "⑦": "跨语言适配/边界协议/边界协议.md §二 · 扩展装载/扩展根声明.json::扫描.找什么 · 对外接口面/调用接口面/examples/启动网关.rs",
        "⑧": f"{扩展根目录名}/**/包声明.json",
        "⑨": f"{扩展根目录名}/**/Cargo.toml · 构建装配/上线切换/构建制品.py · 扩展装载/开发标准/必备件.json",
        "⑩": "契约声明/命令类别/*.json",
        "⑪": "扩展装载/载入约定/载入判定.json",
        "⑬": "对外接口面/调用接口面/examples/启动网关.rs",
        "⑭": f"{扩展根目录名}/原子支持库/编译器支持库/指纹.json + 工具/重跑指纹.py",
        "⑯": "跨语言适配/适配器实现/src/线程安全.rs · 对外接口面/调用接口面/src/网关.rs · examples/启动网关.rs",
    }
    出 = []
    for 编号, 名, 判 in 机器判据:
        出.append((编号, 名, 面[编号], 判(世)))
    # 不可机器判的 6 条也进读数（恒未判）—— 16 条一条不漏，空集/判不了都不算通过
    for 编号 in ["①", "②", "③", "⑥", "⑫", "⑮"]:
        名, 判不了, 缺 = 登记[编号]
        出.append((编号, 名, "（不可机器判，登记）", ("未判", f"{判不了} 缺：{缺}", 0)))
    return 出


def 单条(世: 世界, 编号: str) -> int:
    """单条判据：通过 = 0 · 失败 = 1 · 未判 = 2（带退出码的读数，供后续接线）。"""
    for 号, 名, 判 in 机器判据:
        if 号 == 编号:
            判定, 证据, 对象数 = 判(世)
            print(f"{编号} {名}｜{判定}｜{证据}｜对象数 {对象数}")
            return {"通过": 0, "失败": 1, "未判": 2}[判定]
    if 编号 in 登记:
        名, 判不了, 缺 = 登记[编号]
        print(f"{编号} {名}｜未判（不可机器判）｜{判不了} 缺：{缺}")
        return 2
    print(f"没有判据 {编号}（16 条见 --清单）")
    return 1


def main(参数) -> int:
    根 = 找仓根()
    if "--自测" in 参数:
        return 自测()
    if "--清单" in 参数:
        清单()
        return 0
    世 = 世界(根)
    if "--判" in 参数:
        i = 参数.index("--判")
        if i + 1 >= len(参数):
            print("用法：--判 <编号>（如 --判 ⑧）")
            return 1
        return 单条(世, 参数[i + 1])
    起 = time.perf_counter()
    结果 = 扫(世)
    毫秒 = int((time.perf_counter() - 起) * 1000)
    打印(结果, 毫秒, 读数="--读数" in 参数)
    失败 = sum(1 for _, _, _, r in 结果 if r[0] == "失败")
    未判 = sum(1 for _, _, _, r in 结果 if r[0] == "未判")
    # 16 条口径：机器可判 10 条 + 不可机器判 6 条（恒未判）
    return 0 if (失败 == 0 and 未判 == 0 and len(结果) == 16) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
