    ("⑪", "号段冲突判定不靠检查顺序的巧合", 判_11),
    ("⑬", "装载失败报因（剔除并报原因）", 判_13),
    ("⑭", "扩展 指纹.json 有一条可跑的重跑命令", 判_14),
