#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""外部支持库准入判据 —— 把 `项目文档/决策记录/2026-09-27_外部支持库准入判据.md` 的
**16 条**做成能跑的判据。

上级判据：`项目文档/设计文档/判据的可信性.md`（最高判据）。本件按它落三条：
  **读数四元**（通过 / 失败 / 未判 / **有意不判**，空集不算通过）·
  **每条判据成对样本**（反向样本 + 正向样本，缺一即「未验证」）·
  **每条判据声明扫描面并报实际读数**。

★ **16 条的三种归宿**（未判收敛，以前是「机器 10 + 未判 6」）：
  · **14 条机器可判**（原 10 条 + 本腿新收的 ②③⑥⑫）：其中 ⑥⑫ 的**真跑读数**要跑 cargo /
    起网关 —— 本脚本不许跑（会抢构建锁）；裁决给的第二条路是「协调方代跑并回读数」，
    逐字登在 `外部支持库准入判据.md` §五 的回执表里 ⇒ 本脚本**读那一行**来判（可复算：
    行里写着重跑命令；行一被删/改就当场红），不是空等 cargo。
  · **2 条有意不判**（①⑮）：按设计不判（不是判不了）—— ① 在默认进程内模式下**不适用**；
    ⑮ 自锁是设计使然（外部库按准入判据未全绿前不许写）。**依据锚点机器核**：锚点一丢即红
    （详见 `准入判据/登记.py`），所以它不是免检牌。

────────────────────────────────────────────────────────────────────────────
怎么单独跑（在仓库根；零第三方依赖，只 `python3` 标准库；**不跑 cargo**）

    python3 测试验证/准入判据/准入判据.py            # 判一遍，打四元读数
    python3 测试验证/准入判据/准入判据.py --读数      # 加打每条判据的扫描面与对象数
    python3 测试验证/准入判据/准入判据.py --判 <编号> # 只跑一条（出口 0/1/2）
    python3 测试验证/准入判据/准入判据.py --自测      # 逐条跑正向/反向样本，断言判据抓得住
    python3 测试验证/准入判据/准入判据.py --清单      # 16 条逐条：做了 / 有意不判 / 为什么

输出：

    准入判据：通过 <N> · 失败 <M> · 未判 <K> · 有意不判 <X> · 机器可判 <Y>/16 · 耗时 <毫秒> ms

退出码：**失败 = 0 且 未判 = 0** = 0；否则 = 1（**未判也算「没验过」**，计入非零；
**有意不判**是第四个数 —— 不阻塞，但它那两条的**依据锚点**同样机器核过）。
自测（`--自测`）：每条机器可判判据的正/反向样本都符合预期 = 0；否则 = 1。

口径（判据的可信性 §二/§五/§六）：
  · 四元读数；空集报未判，不许算通过；「按设计不判」要单独报且**依据可证伪**。
  · 每条判据声明扫描面；`--读数` 报实际对象数。
  · 反向样本 = 把修法退回一步 ⇒ 必红；正向样本 = 干净输入 ⇒ 必过。
    缺任一方 ⇒ 该判据「未验证」。
────────────────────────────────────────────────────────────────────────────

本文件是**路由**：解析参数 → 调包里的公开面 → 打印 → 退出码。判据本体在 `准入判据/`
（一个关注点一个文件）。
"""

import sys
import time
from pathlib import Path

起始时刻 = time.monotonic()  # 壳起表点：必须在 import 业务包**之前**（见 构建装配/门禁/命令壳.py）

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # 仓根：取共享门禁
from 构建装配.门禁 import 自门禁  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))

from 准入判据.报告 import 跑单条判据, 扫一遍, 打印报告, 打印清单  # noqa: E402
from 准入判据.样本 import 跑自测  # noqa: E402
from 准入判据.世界 import 判读世界, 找仓根  # noqa: E402


def 入口函数(命令行参数) -> int:
    根目录 = 找仓根()
    if "--自测" in 命令行参数:
        return 跑自测()
    if "--清单" in 命令行参数:
        打印清单()
        return 0
    测试世界 = 判读世界(根目录)
    if "--判" in 命令行参数:
        判位 = 命令行参数.index("--判")
        if 判位 + 1 >= len(命令行参数):
            print("用法：--判 <编号>（如 --判 ⑧）")
            return 1
        return 跑单条判据(测试世界, 命令行参数[判位 + 1])
    区间起点 = time.perf_counter()
    判定汇总 = 扫一遍(测试世界)
    毫秒数 = int((time.perf_counter() - 区间起点) * 1000)
    打印报告(判定汇总, 毫秒数, 读数="--读数" in 命令行参数)
    失败 = sum(1 for _, _, _, 判据结果 in 判定汇总 if 判据结果[0] == "失败")
    未判 = sum(1 for _, _, _, 判据结果 in 判定汇总 if 判据结果[0] == "未判")
    # 16 条口径：机器可判 14 条 + 有意不判 2 条。**有意不判不阻塞**（它是第四个数），
    # 但它的依据锚点已在 `判有意不判_依据锚点齐` 里机器核过 —— 不成立时那条已变「失败」，照常阻塞。
    return 0 if (失败 == 0 and 未判 == 0 and len(判定汇总) == 16) else 1


if __name__ == "__main__":
    sys.exit(自门禁(起始时刻, 入口函数(sys.argv[1:]), 尾巴余量毫秒=200,
                   修法="准入判据按范围扫；范围调小或把重活移出命令路（裁决 §三.3）"))
