def 期望拒(调用) -> str:
    """跑一次该 fail-closed 的调用，返回它的说明；没拒就返 None。"""
    try:
        调用()
    except SystemExit as 错误:
        return str(错误)
    return None


def 造候选面(隔离根: Path) -> None:
    """在隔离根里造一份候选面（后缀表 + 三类目录 + 候选单表里各子目录）。"""
    (隔离根 / "扩展装载").mkdir(parents=True, exist_ok=True)
