def 判候选资格(隔离根: Path, 断言表: list) -> None:
    """候选资格按后缀表判：有本种类制品的算候选；支持库无制品但有 Cargo 源也算；不合格跳过并报因。"""
    # `扫扩展` 读模块级 `仓根` / `后缀表源` ⇒ 指到隔离根（真跑同一份实现，不另写一份扫法）。
    装配面.仓根 = 隔离根
    装配面.后缀表源 = 隔离根 / "扩展装载" / "后缀表.json"
    制品声明 = {"种类": [{"种类": 种名, "扩展落点": 落点} for 种名, 落点 in 种类表]}
    缓冲 = io.StringIO()
    with contextlib.redirect_stdout(缓冲):
        命中项 = 装配面.扫扩展(制品声明)
    报因 = 缓冲.getvalue()
    候选名集 = {候选件["名"] for 候选件 in 命中项}
    跳过行 = [源码行.strip() for 源码行 in 报因.splitlines() if "跳过" in 源码行]
    断言表.append(("候选资格：按后缀表命中（支持库可现编 / 有制品）", 候选名集 == 期望候选,
                  "命中 {}".format(sorted(候选名集))))
    断言表.append(("候选资格：不合格目录跳过并报因", all(跳过名 in 报因 for 跳过名 in 期望跳过) and not (期望跳过 & 候选名集),
                  "跳过行 {}".format(跳过行)))


def 判取制品(隔离根: Path, 断言表: list) -> None:
    """取制品路径：模块 / 技能只消费既有制品，不编；无制品 / 同类 >1 / 未知种类一律 fail-closed。"""
    根目录 = 隔离根 / "扩展根目录"
    制品件名 = 装配面.取制品路径({"种类": "模块", "落点": 根目录 / "组合模块库/有制品模块"}).name
    技能件 = 装配面.取制品路径({"种类": "技能", "落点": 根目录 / "技能封装库/有制品技能"}).name
    断言表.append(("取制品：模块只消费既有制品（不编）", 制品件名 == "有制品模块.模块制品", 制品件名))
    断言表.append(("取制品：技能只消费既有制品（不编）", 技能件 == "有制品技能.技能制品", 技能件))
    拒空 = 期望拒(lambda: 装配面.取制品路径({"种类": "模块", "落点": 根目录 / "组合模块库/空模块"}))
    断言表.append(("取制品：无制品的候选 fail-closed", 拒空 is not None and "恰好一个" in (拒空 or ""), 拒空 or "未拒"))
    目录路径 = 根目录 / "组合模块库/双制品模块"
    目录路径.mkdir(parents=True, exist_ok=True)
    (目录路径 / "双制品模块.模块制品").write_text("x", encoding="utf-8")
    (目录路径 / "另一个.模块制品").write_text("y", encoding="utf-8")
    拒多 = 期望拒(lambda: 装配面.扫扩展({"种类": [{"种类": "模块", "扩展落点": "扩展根目录/组合模块库"}]}))
    断言表.append(("同类制品 >1 fail-closed", 拒多 is not None and "不唯一" in (拒多 or ""), 拒多 or "未拒"))
    拒未知 = 期望拒(lambda: 装配面.扫扩展({"种类": [{"种类": "外星库", "扩展落点": "扩展根目录/原子支持库"}]}))
    断言表.append(("未知种类 fail-closed", 拒未知 is not None and "未知" in (拒未知 or ""), 拒未知 or "未拒"))


def 判预构建分派(隔离根: Path, 断言表: list) -> None:
    """`预构建` 按种类分派：支持库 → 建扩展产物（编 + 包）；模块 / 技能 → 取制品路径（只消费不编）。

    真跑 `主流程.预构建` 本体 —— 只把两条底座 cargo 子进程、扩展编 / 取、戳落点换成隔离记录器，
    分派的那段 `if 扩展["种类"] == "支持库"` 逐字真跑（不像旧实现那样对模块 / 技能也调 `建扩展产物`）。
    """
    子进程记录 = []
    编产物记录 = []
    取制品记录 = []
    纳入样本表 = [
        {"种类": "支持库", "名": "样支持库", "落点": 隔离根 / "扩展根目录/原子支持库/样支持库", "扩展落点": "扩展根目录/原子支持库"},
        {"种类": "模块", "名": "样模块", "落点": 隔离根 / "扩展根目录/组合模块库/样模块", "扩展落点": "扩展根目录/组合模块库"},
        {"种类": "技能", "名": "样技能", "落点": 隔离根 / "扩展根目录/技能封装库/样技能", "扩展落点": "扩展根目录/技能封装库"},
    ]
    函数名表 = ("仓根", "跑子进程", "建扩展产物", "取制品路径", "预构建戳", "预构建指纹")
    原函数表 = {名字: getattr(主流程面, 名字) for 名字 in 函数名表}
    try:
        主流程面.仓根 = 隔离根
        主流程面.跑子进程 = lambda 命令, **附加: 子进程记录.append(list(命令))
        主流程面.建扩展产物 = lambda 扩展: 编产物记录.append(扩展["种类"])
        主流程面.取制品路径 = lambda 扩展: 取制品记录.append(扩展["种类"])
        主流程面.预构建戳 = 隔离根 / "预构建.json"
        主流程面.预构建指纹 = lambda 纳入的扩展: "样本指纹"
        with contextlib.redirect_stdout(io.StringIO()):
            返回码 = 主流程面.预构建(纳入样本表)
    finally:
        for 名字, 原值 in 原函数表.items():
            setattr(主流程面, 名字, 原值)
    编了支持库 = 编产物记录 == ["支持库"]
    只消费制品 = sorted(取制品记录) == ["技能", "模块"]
    两条编命令 = len(子进程记录) == 2 and 子进程记录[0][:3] == ["cargo", "build", "--locked"]
    无错编 = 返回码 == 0
    断言表.append(("预构建：按种类分派（支持库编 · 模块技能只消费既有制品）", 编了支持库 and 只消费制品,
                  "编产物 {} · 取制品 {}".format(编产物记录, 取制品记录)))
    断言表.append(("预构建：两条底座编命令照跑（网关 + 装支持库制品 bin）", 两条编命令,
                  "子进程 {} 条 · 首条 {}".format(len(子进程记录), 子进程记录[0][:3] if 子进程记录 else None)))
    断言表.append(("预构建：返回码 0（分派不崩）", 无错编, "返回码 {}".format(返回码)))


def 判声明键(断言表: list) -> None:
    """制品内声明的键必须是运行期读的 `扩展落点`（写成别的键 = 运行期静默 0 扩展）。"""
    源声明 = json.loads((仓根 / "扩展装载/扩展根声明.json").read_text(encoding="utf-8"))
    各类 = 造制品声明(源声明).get("种类", [])
    有键 = bool(各类) and all("扩展落点" in 类别项 for 类别项 in 各类)
    指向 = bool(各类) and all(str(类别项.get("扩展落点", "")).startswith("扩展/") for 类别项 in 各类)
    无错键 = all("制品落点目录" not in 类别项 for 类别项 in 各类)
    断言表.append(("制品内声明键 = 扩展落点（运行期读的键）", 有键 and 指向 and 无错键,
                  "写出 {}".format([类别项.get("扩展落点") for 类别项 in 各类])))


def 判装入落点(断言表: list) -> None:
    """装入目标目录的**种类段**必须 = 制品内声明的 `扩展落点` 末段（两处不一致 ⇒ 制品找不到自身的扩展）。"""
    # 本判据只读**真仓**的声明与候选面（`判候选资格` 把 `装配面.仓根` 指到了隔离根 ⇒ 这里指回来）。
    装配面.仓根 = 仓根
    装配面.后缀表源 = 仓根 / "扩展装载" / "后缀表.json"
    源声明面 = json.loads((仓根 / "扩展装载/扩展根声明.json").read_text(encoding="utf-8"))
    制品声明 = 造制品声明(源声明面)
    声明落点集 = {类别项["种类"]: 类别项["扩展落点"] for 类别项 in 制品声明.get("种类", [])}
    扫描项表 = 装配面.扫扩展(源声明面)
    种名表 = [扫描项["种类"] for 扫描项 in 扫描项表]
    # 装入目标 = 制品落点 / "扩展" / <声明落点末段> / <扩展名> / <制品件名>（主流程.入口函数 第 2 步）
    装入落点集 = {
        扩展["种类"]: "扩展/{}".format(Path(声明落点集[扩展["种类"]]).name)
        for 扩展 in 扫描项表
    }
    一致 = bool(种名表) and all(装入落点集[种名] == 声明落点集[种名] for 种名 in 种名表)
    断言表.append(("装入落点：种类段 = 声明 `扩展落点` 末段（两处一致）", 一致,
                  "扫描 {} 种 · 声明 {}".format(sorted(set(种名表)), 声明落点集)))


def 造运行面(隔离根: Path, 网关路径: Path) -> tuple:
    """造运行面：网关 + 有效支持库制品 + 3 个无制品目录 + 制品内声明 + 后缀表 + 缓存目录。

    目录布局**不手抄**：从真实 `造制品声明` 输出的 `种类[].扩展落点` 现取 ⇒ 若声明键 / 值写错，
    制品就摆不到运行期扫的位上，运行期那几条当场红（这是「装入 ↔ 运行期」真的配对，不是两份常量互抄）。
    返回 (运行面, 装上有望)；`装上有望` = 真实支持库制品在（否则那一条只报未判，不当通过）。
    """
    运行面 = 隔离根 / "运行面"
    运行面.mkdir(parents=True, exist_ok=True)
    (运行面 / "缓存目录").mkdir(parents=True, exist_ok=True)
    shutil.copy2(网关路径, 运行面 / "网关")
    (运行面 / "网关").chmod(0o755)
    制品声明 = 造制品声明(json.loads((仓根 / "扩展装载/扩展根声明.json").read_text(encoding="utf-8")))
    落点表 = {类别项["种类"]: 类别项["扩展落点"] for 类别项 in 制品声明.get("种类", [])}
    for 落点 in 落点表.values():
        (运行面 / 落点).mkdir(parents=True, exist_ok=True)
    # 有效支持库制品摆进声明指的那一类落点（真实制品在 ⇒ 可测「装上」）。
    真制品 = 仓根 / "扩展根目录/原子支持库/编译器支持库/编译器支持库.支持库制品"
    装上有望 = 真制品.is_file()
    if 装上有望 and "支持库" in 落点表:
        有效目录 = 运行面 / 落点表["支持库"] / "有效支持库"
        有效目录.mkdir(parents=True, exist_ok=True)
        shutil.copy2(真制品, 有效目录 / "有效支持库.支持库制品")
    # 三个无制品目录（各类一个）—— 运行期应剔除并逐条报因。
    for 候选件名, 种名 in (("空支持库", "支持库"), ("空模块", "模块"), ("空技能", "技能")):
        if 种名 in 落点表:
            (运行面 / 落点表[种名] / 候选件名).mkdir(parents=True, exist_ok=True)
    (运行面 / "扩展根声明.json").write_text(json.dumps(制品声明, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    shutil.copy2(仓根 / "扩展装载/后缀表.json", 运行面 / "后缀表.json")
    return 运行面, 装上有望


def 取空闲端口() -> int:
    """取一个本机空闲端口（让内核分配后立即释放）。"""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as 套接字:
        套接字.bind(("127.0.0.1", 0))
        return int(套接字.getsockname()[1])


def 起网关(网关路径: Path, 运行面: Path, 监听端口: int) -> subprocess.Popen:
    """起一次网关进程（stdout 收进管道，由 `停网关` 读满即停）。"""
    return subprocess.Popen(
        [str(网关路径), "--声明根", str(运行面 / "扩展根声明.json"),
         "--后缀表", str(运行面 / "后缀表.json"), "--端口", str(监听端口),
         "--缓存根", str(运行面 / "缓存目录")],
        cwd=str(运行面), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
    )


def 停网关(网关进程: subprocess.Popen, 超时秒: float = 3.0) -> str:
    """读满输出即停：读到 `监听` 行（或超时）就 kill —— 不常驻。"""
    try:
        输出, _ = 网关进程.communicate(timeout=超时秒)
    except subprocess.TimeoutExpired:
        网关进程.kill()
        输出, _ = 网关进程.communicate()
    return 输出 or ""


def 判运行期配对(运行面: Path, 网关路径: Path, 装上有望: bool, 断言表: list, 阻断表: list) -> None:
    """运行期对同 fixture 的成对读数：不合格目录剔除并报因 + 服务起得来 + 支持库装上。"""
    监听端口 = 取空闲端口()
    输出 = 停网关(起网关(网关路径, 运行面, 监听端口))
    空齐 = all(候选件名 in 输出 for 候选件名 in ("空支持库", "空模块", "空技能"))
    报因数 = 输出.count("本平台制品 0 个（要求恰好 1 个）")
    起了 = "监听 127.0.0.1:{}".format(监听端口) in 输出
    断言表.append(("运行期：不合格目录剔除并报因（与装配侧成对）", 空齐 and 报因数 >= 3,
                  "三个空目录在 {} · 0 制品报因 {} 次".format(空齐, 报因数)))
    断言表.append(("运行期：服务起得来（扫描不崩）", 起了, "监听行 {}".format(起了)))
    if 装上有望:
        装上项 = [源码行.strip() for 源码行 in 输出.splitlines() if "装上 " in 源码行]
        断言表.append(("运行期：支持库装上（制品路径保真）", bool(装上项), "装上行 {}".format(装上项)))
    else:
        阻断表.append("真实支持库制品不在 ⇒ 运行期「装上」未测（未当作通过）")


def 收读数(断言表: list, 阻断表: list) -> int:
    for 说明, 通过, 读数 in 断言表:
        print("{} {}｜{}".format("✓" if 通过 else "✗", 说明, 读数))
    for 阻断项 in 阻断表:
        print("○ 未判（阻断）：{}".format(阻断项))
    失败数 = sum(1 for _, 通过, _ in 断言表 if not 通过)
    print("\n扩展分流回归：断言 {} 条（失败 {}）· 阻断 {} 条 · 隔离 tmp 已清".format(len(断言表), 失败数, len(阻断表)))
    return 0 if 失败数 == 0 and not 阻断表 else 1


def 入口函数() -> int:
    """跑完五组断言：候选资格 · 取制品 · 预构建分派 · 装入落点 · 声明键 · 运行期配对。"""
    断言表 = []
    阻断表 = []
    隔离根 = Path(tempfile.mkdtemp(prefix="v1扩展分流_")).resolve()
    try:
        造候选面(隔离根)
        判装入落点(断言表)
        判候选资格(隔离根, 断言表)
        判取制品(隔离根, 断言表)
        判预构建分派(隔离根, 断言表)
        判声明键(断言表)
        网关路径 = 仓根 / "构建环境/构建缓存/release/examples/启动网关"
        if not 网关路径.is_file():
            阻断表.append("启动网关 不在（没预构建）：{} ⇒ 运行期配对未测".format(网关路径))
        else:
            运行面, 装上有望 = 造运行面(隔离根, 网关路径)
            判运行期配对(运行面, 网关路径, 装上有望, 断言表, 阻断表)
        return 收读数(断言表, 阻断表)
    finally:
        shutil.rmtree(隔离根, ignore_errors=True)
