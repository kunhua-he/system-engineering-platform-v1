#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T06 发布验收 · 缓存中断恢复 —— 在三个时点对测试发布做真中止（读数 = 夹具自证）。

预期（写死在本件里，跑出实际读数）：
  ① 临时写入中被中止 ⇒ 坏指纹不装载半写内容，当前版本不被顶替
  ② 校验完成但未切换时被中止 ⇒ 失败不替换当前版本，旧内容逐字节不变
  ③ 切换后被中止 ⇒ 仍被引用的旧版本内容不被清理（引用归零才清理）

中止是**真信号**（`SIGKILL`），不是 try/except 拟态：被中止的子进程用本件自身重入
（`--子进程 <时点> <授权目录>`）。落盘全在**运行数据根**（判据 ⑳/㉕），不落源码树。

★ 阻断（如实报，`阻断表` 逐条列缺什么口）：平台侧发布协议唯一实现是 Rust 侧
  `跨语言适配/适配器实现/src/候选发布.rs` 与 `装载件缓存.rs`；本树无 Python 可调口、
  无预编译制品（本腿边界禁 `cargo build`）⇒ 这三条的**平台语义**读数给不出。
  本件读数属**夹具自证**：证明尺子能判三条不变量，**不证明平台这么做**。

    python3 测试验证/准入判据/故障取证样本/发布验收_缓存恢复.py
退出码：0 = 平台判过（无阻断且三条不变量逐条成立）· 1 = 读数不符 · 3 = 平台未判（本件有阻断）。
"""

import hashlib
import os
import signal
import subprocess
import sys
import time
from pathlib import Path

仓根 = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(仓根))

from 开发工具.运行数据根 import 子目录路径, 解析当前环境  # noqa: E402
from 制品读数 import 印制品读数  # noqa: E402

单轮上限秒 = 3.0
落刀窗口秒 = 0.25  # 每个阶段标记后留给父进程落刀的窗口；不落刀才是异常
中止时点表 = ("临时写入中", "校验完成未切换", "切换后")
阻断表 = (
    "平台发布协议无 Python 可调口：`候选发布.rs` 的 `升级候选` / `升级装载` 只在 Rust 侧",
    "本树无预编译制品（`cargo build` 被本腿边界禁止）⇒ 跑不起平台侧发布流程",
    "`装载件缓存.rs` 未导出「当前版本 / 在途引用数」可观测口 ⇒ ③ 的引用计数读不到",
)


def 文件指纹(文件路径):
    return hashlib.sha256(Path(文件路径).read_bytes()).hexdigest()


def 取授权目录(时点):
    """每个中止时点一个单独的目录 —— 共用会让 ③ 的清理把 ② 的证据一并删掉。"""
    临时根 = 子目录路径(解析当前环境(), "临时件")
    授权目录 = 临时根 / ("发布验收_缓存恢复_%d_%s" % (os.getpid(), 时点))
    授权目录.mkdir(parents=True, exist_ok=True)
    return 授权目录


def 标记路径(授权目录, 时点):
    return Path(授权目录) / ("阶段_%s" % 时点)


def 写阶段标记(授权目录, 时点):
    标记路径(授权目录, 时点).write_text(时点, encoding="utf-8")


def 按指纹装载(版本目录):
    """按指纹装载：声明指纹与内容对不上 ⇒ 拒装（**不返回半写内容**）。"""
    版本目录 = Path(版本目录)
    声明指纹 = (版本目录 / "版本指纹.txt").read_text(encoding="utf-8").strip()
    版本内容 = (版本目录 / "版本.bin").read_bytes()
    if hashlib.sha256(版本内容).hexdigest() != 声明指纹:
        return None
    return 版本内容


def 清理旧版本(版本目录, 在途引用数):
    """仍被引用的旧版本不清理；引用归零才清理（③ 的规则本体）。"""
    版本目录 = Path(版本目录)
    if 在途引用数 > 0:
        return "保留"
    for 目录内文件 in 版本目录.iterdir():
        目录内文件.unlink()
    版本目录.rmdir()
    return "已清理"


def 预备旧版本(授权目录):
    授权目录 = Path(授权目录)
    旧版本目录 = 授权目录 / "旧版本"
    旧版本目录.mkdir(parents=True, exist_ok=True)
    (旧版本目录 / "版本.bin").write_bytes(b"old-version-payload" * 256)
    (旧版本目录 / "版本指纹.txt").write_text(文件指纹(旧版本目录 / "版本.bin"), encoding="utf-8")
    (授权目录 / "当前版本.txt").write_text("旧版本", encoding="utf-8")
    return 旧版本目录


def 子进程流程(时点, 授权目录):
    """被中止的子进程：只做本地版本目录的写入与切换，不碰平台。"""
    授权目录 = Path(授权目录)
    新版本目录 = 授权目录 / "新版本"
    新版本目录.mkdir(parents=True, exist_ok=True)
    版本内容 = b"new-version-payload" * 256
    with (新版本目录 / "版本.bin").open("wb") as 文件句柄:
        文件句柄.write(版本内容[: len(版本内容) // 2])
        文件句柄.flush()
        写阶段标记(授权目录, "临时写入中")
        time.sleep(落刀窗口秒)  # 半写状态下等父进程落刀
        文件句柄.write(版本内容[len(版本内容) // 2:])
    (新版本目录 / "版本指纹.txt").write_text(hashlib.sha256(版本内容).hexdigest(), encoding="utf-8")
    写阶段标记(授权目录, "校验完成未切换")
    time.sleep(落刀窗口秒)  # **切换之前**等父进程落刀：这才是「校验完成但未切换」
    (授权目录 / "当前版本.txt").write_text("新版本", encoding="utf-8")
    写阶段标记(授权目录, "切换后")
    time.sleep(单轮上限秒)  # 等父进程落刀；不落刀才是异常
    return 0


def 跑中止轮(时点):
    授权目录 = 取授权目录(时点)
    旧版本目录 = 预备旧版本(授权目录)
    旧版本指纹 = 文件指纹(旧版本目录 / "版本.bin")
    子进程句柄 = subprocess.Popen(
        [sys.executable, "-c",
         "import sys; sys.path[:0] = [%r]; from 发布验收_缓存恢复 import 入口函数; "
         "sys.exit(入口函数(sys.argv[1:]))" % str(Path(__file__).resolve().parent),
         "--子进程", 时点, str(授权目录)],
        cwd=str(Path(__file__).resolve().parent),
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    截止时刻 = time.monotonic() + 单轮上限秒
    标记到位 = False
    while time.monotonic() < 截止时刻:
        if 标记路径(授权目录, 时点).exists():
            标记到位 = True
            break
        time.sleep(0.01)
    已落刀 = False
    if 标记到位:
        try:
            os.kill(子进程句柄.pid, signal.SIGKILL)
            已落刀 = True
        except ProcessLookupError:
            已落刀 = False
    子进程句柄.wait(timeout=单轮上限秒)
    当前版本件 = 授权目录 / "当前版本.txt"
    return {"授权目录": 授权目录, "旧版本目录": 旧版本目录, "旧版本指纹": 旧版本指纹,
            "标记到位": 标记到位, "已落刀": 已落刀,
            "当前版本": 当前版本件.read_text(encoding="utf-8").strip() if 当前版本件.exists() else "无",
            "新版本已成文": (授权目录 / "新版本" / "版本指纹.txt").exists()}


def 跑发布验收():
    逐时点读数 = {时点: 跑中止轮(时点) for 时点 in 中止时点表}
    临时写入 = 逐时点读数["临时写入中"]
    校验未切换 = 逐时点读数["校验完成未切换"]
    切换后 = 逐时点读数["切换后"]
    半写版本目录 = 临时写入["授权目录"] / "新版本"
    半写指纹件 = 半写版本目录 / "版本指纹.txt"
    半写装载 = 按指纹装载(半写版本目录) if 半写指纹件.exists() else None
    半写字节数 = len((半写版本目录 / "版本.bin").read_bytes())
    全量字节数 = 2 * 256 * len(b"new-version-payload")
    保留读数 = 清理旧版本(切换后["旧版本目录"], 1)
    旧版本未被清 = 文件指纹(切换后["旧版本目录"] / "版本.bin") == 切换后["旧版本指纹"]
    清理读数 = 清理旧版本(切换后["旧版本目录"], 0)
    逐条读数 = (
        {"验收条名": "① 临时写入中中止 ⇒ 不装载半写内容", "预期读数": "拒装 + 当前版本仍旧版本",
         "实际读数": "装载=%s · 半写字节=%d/%d · 当前版本=%s" % (
             半写装载, 半写字节数, 全量字节数, 临时写入["当前版本"]),
         "是否成立": (半写装载 is None and 半写字节数 < 全量字节数
                  and 临时写入["当前版本"] == "旧版本")},
        {"验收条名": "② 校验完成未切换中止 ⇒ 不替换当前版本", "预期读数": "当前版本仍旧 · 旧内容逐字节不变",
         "实际读数": "当前版本=%s · 旧内容指纹不变=%s · 新版本已成文=%s（未启用）" % (
             校验未切换["当前版本"], 文件指纹(校验未切换["旧版本目录"] / "版本.bin") == 校验未切换["旧版本指纹"],
             校验未切换["新版本已成文"]),
         "是否成立": (校验未切换["当前版本"] == "旧版本"
                  and 文件指纹(校验未切换["旧版本目录"] / "版本.bin") == 校验未切换["旧版本指纹"])},
        {"验收条名": "③ 切换后中止 ⇒ 被引用的旧版本不被清理", "预期读数": "引用>0→保留 · 引用=0→清理",
         "实际读数": "引用=1→%s · 内容逐字节不变=%s · 引用=0→%s" % (
             保留读数, 旧版本未被清, 清理读数),
         "是否成立": (保留读数 == "保留" and 旧版本未被清 and 清理读数 == "已清理")},
    )
    中止全到位 = all(读["标记到位"] and 读["已落刀"] for 读 in 逐时点读数.values())
    全成立 = 中止全到位 and all(条["是否成立"] for 条 in 逐条读数)
    print("T06 发布验收 · 缓存中断恢复（读数 = 夹具自证 · 授权目录 = %s）" % 临时写入["授权目录"].parent)
    印制品读数()
    for 条 in 逐条读数:
        print("  [%s] %s" % ("符合" if 条["是否成立"] else "不符", 条["验收条名"]))
        print("        预期：%s" % 条["预期读数"])
        print("        实际：%s" % 条["实际读数"])
    if not 中止全到位:
        print("  [不符] 中止未在预定时点真落刀 ⇒ 上述读数一律不算数")
    for 条目 in 阻断表:
        print("  [阻断 · 原因] %s" % 条目)
    # 退出语义（与 T09 `读数.py::汇总结局` 同族：阻断一律非 0）：
    #   0 = 平台判过（无阻断且读数全符）· 1 = 读数不符 · 3 = 平台未判（本件有阻断 ⇒ 平台语义给不出）
    退出码值 = 1 if not 全成立 else (3 if 阻断表 else 0)
    print("退出码：%d（0 = 平台判过 · 1 = 读数不符 · 3 = 平台未判）" % 退出码值)
    return 退出码值


def 入口函数(命令行参数):
    """命令行入口：`--子进程 <时点> <授权目录>` 走子进程，其余走 T06 验收。"""
    if len(命令行参数) >= 3 and 命令行参数[0] == "--子进程":
        return 子进程流程(命令行参数[1], 命令行参数[2])
    return 跑发布验收()
