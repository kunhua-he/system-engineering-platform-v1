class 超限异常(Exception):
    """超限时抛的结构化异常：携带错误码，**不是 panic**。"""

    def __init__(self, 资源类别, 超限错误码):
        super().__init__("%s 超限（错误码 %s）" % (资源类别, 超限错误码))
        self.资源类别 = 资源类别
        self.超限错误码 = 超限错误码


class 预算账本:
    """按类记账的预算账本：申领超限 ⇒ 抛 `超限异常`（结构化可判）。"""

    def __init__(self, 上限表):
        self.上限表 = dict(上限表)
        self.用量表 = {类别: 0 for 类别 in 上限表}
        self.拒绝表 = {类别: 0 for 类别 in 上限表}

    def 申领(self, 资源类别):
        if 资源类别 not in self.用量表:
            raise KeyError("未登记的资源类别：%s" % 资源类别)
        if self.用量表[资源类别] + 1 > self.上限表[资源类别]:
            self.拒绝表[资源类别] += 1
            raise 超限异常(资源类别, 1000 + 六类资源表.index(资源类别))
        self.用量表[资源类别] += 1
        return self.用量表[资源类别]

    def 释放(self, 资源类别):
        self.用量表[资源类别] = max(0, self.用量表[资源类别] - 1)
        return self.用量表[资源类别]

    def 造空账本(self):
        self.用量表 = {类别: 0 for 类别 in self.上限表}
        self.拒绝表 = {类别: 0 for 类别 in self.上限表}
        return self


