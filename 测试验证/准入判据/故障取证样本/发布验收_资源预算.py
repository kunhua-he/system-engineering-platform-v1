def 判超限可判(账本):
    """耗到上限再多申一份 ⇒ 逐类都得给得出错误码（非 panic）。"""
    逐类读数 = {}
    for 资源类别 in 六类资源表:
        while 账本.用量表[资源类别] < 账本.上限表[资源类别]:
            账本.申领(资源类别)
        try:
            账本.申领(资源类别)
            逐类读数[资源类别] = "未报超限（不符）"
        except 超限异常 as 异常读数:
            逐类读数[资源类别] = "错误码 %d" % 异常读数.超限错误码
    return 逐类读数


def 判清理可恢复(账本):
    """退出额度后同一类再申一份 ⇒ 应当成功。"""
    逐类读数 = {}
    for 资源类别 in 六类资源表:
        账本.释放(资源类别)
        try:
            账本.申领(资源类别)
            逐类读数[资源类别] = "恢复可用（用量 %d/%d）" % (账本.用量表[资源类别], 账本.上限表[资源类别])
        except 超限异常:
            逐类读数[资源类别] = "清理后仍拒（不符）"
        while 账本.用量表[资源类别] > 0:
            账本.释放(资源类别)
    return 逐类读数


def 判不持续累积(账本):
    """连做多轮「申领 → 用 → 释放」⇒ 用量应回落基线。"""
    累积读数表 = []
    for 轮号 in range(1, 轮次 + 1):
        for 资源类别 in 六类资源表:
            for _ in range(单轮增量):
                账本.申领(资源类别)
        for 资源类别 in 六类资源表:
            while 账本.用量表[资源类别] > 0:
                账本.释放(资源类别)
        累积读数表.append({"轮次": 轮号, "用量": dict(账本.用量表)})
    用量回落 = all(读["用量"][类别] == 0 for 读 in 累积读数表 for 类别 in 六类资源表)
    return 累积读数表, 用量回落


