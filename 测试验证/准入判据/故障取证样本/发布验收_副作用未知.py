#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T07 发布验收 · 副作用未知 —— 结果通道被断开后，同身份重试/查询必须回「结果未知」。

预期（写死在本件里，跑出实际读数）：
  · 首次执行（通道通、账本干净）⇒ 「已执行」且支持库记录件多一行
  · 再写一次可查记录后**故意断开结果通道** ⇒ 该次判定为「结果未知」，**不是「未执行」**
  · 同意图身份**重试** ⇒ 仍为「结果未知」，且支持库记录**不新增行**（平台不自行重放）
  · 同意图身份**查询** ⇒ 仍为「结果未知」，且不新增行
  · 账本里没有的陌生身份 ⇒ 才是「未执行」（对照项，防「一律报未知」的假绿）

落盘全在**运行数据根**（判据 ⑳/㉕），不落源码树。

★ 阻断（如实报）：平台上「意图身份账本 + 结果未知」的唯一实现在 Rust 侧
  `跨语言适配/适配器实现/src/候选发布.rs`（`在途引用` / `在途执行数`）与
  `扩展根目录/` 的支持库；本树无 Python 可调口、无预编译制品 ⇒ 平台语义读数给不出。
  本件读数属**夹具自证**：证明尺子能判「未知 ≠ 未执行」与「不自行重放」。

    python3 测试验证/准入判据/故障取证样本/发布验收_副作用未知.py
退出码：0 = 平台判过（无阻断且五条判读逐条相符）· 1 = 读数不符 · 3 = 平台未判（本件有阻断）。
"""

import json
import os
import sys
from pathlib import Path

仓根 = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(仓根))

from 开发工具.运行数据根 import 子目录路径, 解析当前环境  # noqa: E402
from 制品读数 import 印制品读数  # noqa: E402

阻断表 = (
    "平台「意图身份账本」只在 Rust 侧（`候选发布.rs` 的 `在途引用` / `在途执行数`）⇒ 无 Python 可调口",
    "支持库实现不在本树可执行面（`扩展根目录/` 无预编译制品）⇒ 副作用只能由本夹具拟态",
    "平台未导出「本意图是否已执行」的可观测查询 ⇒ 「结果未知」只能在本夹具的账本上判",
)
判读表 = ("首次执行", "断通道后重试", "断通道后查询", "通道恢复后查询", "陌生身份执行")


def 造支持库目录():
    临时根 = 子目录路径(解析当前环境(), "临时件")
    授权目录 = 临时根 / ("发布验收_副作用未知_%d" % os.getpid())
    授权目录.mkdir(parents=True, exist_ok=True)
    支持库记录件 = 授权目录 / "支持库记录.txt"
    支持库记录件.write_text("", encoding="utf-8")
    结果通道件 = 授权目录 / "结果通道.json"
    结果通道件.write_text(json.dumps({"已断开": False}, ensure_ascii=False), encoding="utf-8")
    意图账本件 = 授权目录 / "意图账本.json"
    意图账本件.write_text("{}", encoding="utf-8")
    return 授权目录, 支持库记录件, 结果通道件, 意图账本件


def 数记录行数(支持库记录件):
    return len([数据行 for 数据行 in Path(支持库记录件).read_text(encoding="utf-8").splitlines() if 数据行.strip()])


def 判通道可读(结果通道件):
    件路径 = Path(结果通道件)
    if not 件路径.exists():
        return False
    return not json.loads(件路径.read_text(encoding="utf-8"))["已断开"]


def 断开结果通道(结果通道件):
    件路径 = Path(结果通道件)
    件路径.write_text(json.dumps({"已断开": True}, ensure_ascii=False), encoding="utf-8")


def 读意图状态(意图账本件, 意图身份):
    账本 = json.loads(Path(意图账本件).read_text(encoding="utf-8"))
    return 账本.get(意图身份)


def 支持库写入记录(支持库记录件, 意图身份):
    """支持库的副作用本体：追加一行可查记录（幂等由账本守）。"""
    with Path(支持库记录件).open("a", encoding="utf-8") as 文件句柄:
        文件句柄.write(意图身份 + "\n")


def 按意图执行(授权目录, 支持库记录件, 结果通道件, 意图账本件, 意图身份):
    """按意图身份执行一次。**已执行过的身份绝不重放**；通道断了 ⇒ 结果未知。"""
    账本 = json.loads(Path(意图账本件).read_text(encoding="utf-8"))
    if 意图身份 in 账本:
        # 身份已入手：**不重放**；通道断着就只能报未知，不能报「未执行 / 上次结果」
        if not 判通道可读(结果通道件):
            return "结果未知"
        return "已执行"
    if not 判通道可读(结果通道件):
        # 断着通道、身份又全新 ⇒ 连「执行没执行」都无从判定 ⇒ 入账后报未知
        账本[意图身份] = "已执行"
        Path(意图账本件).write_text(json.dumps(账本, ensure_ascii=False), encoding="utf-8")
        支持库写入记录(支持库记录件, 意图身份)
        return "结果未知"
    账本[意图身份] = "已执行"
    Path(意图账本件).write_text(json.dumps(账本, ensure_ascii=False), encoding="utf-8")
    支持库写入记录(支持库记录件, 意图身份)
    return "已执行"


def 查意图结果(结果通道件, 意图账本件, 意图身份):
    """按意图身份查询上次结果：断着通道 ⇒ 结果未知（**不退化成未执行**）。"""
    if 读意图状态(意图账本件, 意图身份) is None:
        return "未执行"
    if not 判通道可读(结果通道件):
        return "结果未知"
    return "已执行"


def 跑副作用未知验收():
    授权目录, 支持库记录件, 结果通道件, 意图账本件 = 造支持库目录()
    意图身份 = "意图-%d-首笔" % os.getpid()
    陌生身份 = "意图-%d-未有" % os.getpid()
    首次判读 = 按意图执行(授权目录, 支持库记录件, 结果通道件, 意图账本件, 意图身份)
    首次行数 = 数记录行数(支持库记录件)
    # 再写一次可查记录，然后**故意断开结果通道**
    支持库写入记录(支持库记录件, 意图身份 + "-事后笔")
    断通道前行数 = 数记录行数(支持库记录件)
    断开结果通道(结果通道件)
    断通道判读 = 按意图执行(授权目录, 支持库记录件, 结果通道件, 意图账本件, 意图身份)
    断通道后行数 = 数记录行数(支持库记录件)
    查询判读 = 查意图结果(结果通道件, 意图账本件, 意图身份)
    查询后行数 = 数记录行数(支持库记录件)
    通通道判读 = 查意图结果(结果通道件, 意图账本件, 陌生身份)
    陌生身份判读 = 按意图执行(授权目录, 支持库记录件, 结果通道件, 意图账本件, 陌生身份)
    判读读数表 = (
        {"判读条目": "首次执行（通道通）⇒ 已执行且记录新增", "预期判读": "已执行 + 新增 1 行",
         "实际判读": "%s + 行数 %d" % (首次判读, 首次行数),
         "是否相符": 首次判读 == "已执行" and 首次行数 == 1},
        {"判读条目": "断通道后重试 ⇒ 结果未知（**不是未执行**）且**不重放**", "预期判读": "结果未知 + 行数不变",
         "实际判读": "%s + 行数 %d→%d" % (断通道判读, 断通道前行数, 断通道后行数),
         "是否相符": 断通道判读 == "结果未知" and 断通道后行数 == 断通道前行数},
        {"判读条目": "断通道后查询 ⇒ 结果未知且不新增行", "预期判读": "结果未知 + 行数不变",
         "实际判读": "%s + 行数 %d" % (查询判读, 查询后行数),
         "是否相符": 查询判读 == "结果未知" and 查询后行数 == 断通道后行数},
        {"判读条目": "陌生身份查询（断通道下）⇒ 未执行（对照项，防「一律报未知」）", "预期判读": "未执行",
         "实际判读": 通通道判读, "是否相符": 通通道判读 == "未执行"},
        {"判读条目": "陌生身份在断通道下执行 ⇒ 结果未知", "预期判读": "结果未知",
         "实际判读": 陌生身份判读, "是否相符": 陌生身份判读 == "结果未知"},
    )
    全相符 = all(读数条["是否相符"] for 读数条 in 判读读数表)
    print("T07 发布验收 · 副作用未知（读数 = 夹具自证 · 授权目录 = %s）" % 授权目录)
    印制品读数()
    for 读数条 in 判读读数表:
        print("  [%s] %s" % ("相符" if 读数条["是否相符"] else "不符", 读数条["判读条目"]))
        print("        预期：%s" % 读数条["预期判读"])
        print("        实际：%s" % 读数条["实际判读"])
    for 明细条目 in 阻断表:
        print("  [阻断 · 原因] %s" % 明细条目)
    # 退出语义（与 T09 `读数.py::汇总结局` 同族：阻断一律非 0）：
    #   0 = 平台判过 · 1 = 读数不符 · 3 = 平台未判（本件有阻断 ⇒ 平台语义给不出）
    退出码值 = 1 if not 全相符 else (3 if 阻断表 else 0)
    print("退出码：%d（0 = 平台判过 · 1 = 读数不符 · 3 = 平台未判）" % 退出码值)
    return 退出码值


def 入口函数(命令行参数):
    """命令行入口：跑 T07 副作用未知验收。"""
    return 跑副作用未知验收()
