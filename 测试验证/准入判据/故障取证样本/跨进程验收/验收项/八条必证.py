def 看返回值(服务端口, 参位表, 编号=夹具.靶子编号):
    """经生产入口发一次调用，返回 `(槽表 或 None, 说明文本)`。"""
    HTTP码, 应答体, 原文 = 夹具.发调用(服务端口, 编号, 参位表)
    if HTTP码 != 200:
        return None, f"HTTP {HTTP码} · {原文}"
    槽表, 说明文本 = 夹具.取返回表(应答体)
    if 槽表 is None:
        return None, f"HTTP {HTTP码} · {说明文本} · 原文 {原文[:200]}"
    return 槽表, ""


def 形状对(槽表):
    """比较全部返回槽的标签与逐字节内容。"""
    if not 槽表:
        return None
    return tuple((槽项.get("类型标签"), 夹具.解字节集(槽项)) for 槽项 in 槽表)


def 必证一_数据过线(服务端口):
    """① 非空 / 空 / 中文文本 + 含零字节字节集过线往返正确（含引用输入与返回值）。"""
    for 样本名, 源文本 in 样本文本表:
        槽表, 说明文本 = 看返回值(服务端口, [夹具.造文本位(源文本)])
        if 槽表 is None:
            记一条(f"一·文本往返·{样本名}", "拿到返回槽", 说明文本, 1)
            continue
        字节串 = 夹具.解字节集(槽表[0])
        标签 = 槽表[0].get("类型标签")
