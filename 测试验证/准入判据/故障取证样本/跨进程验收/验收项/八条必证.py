def 必证二_两条路一致(服务端口):
    """同一批样本逐槽逐字节比较进程内与跨进程，再核业务失败码。"""
    跨进程表 = [
        (样本名, 看返回值(服务端口, [夹具.造文本位(源文本)])[0]) for 样本名, 源文本 in 样本文本表
    ]
    _, 跨进程失败体, _ = 夹具.发调用(服务端口, 无主号, [夹具.造文本位("x")])

    工作目录 = 夹具.取工作目录()
    进程内端口 = 夹具.取空闲端口()
    无配置进程, 进程内端口 = 夹具.起网关(工作目录, 进程内端口, 跨进程配置=None)
    try:
        进程内表 = [
            (样本名, 看返回值(进程内端口, [夹具.造文本位(源文本)])[0])
            for 样本名, 源文本 in 样本文本表
        ]
        _, 跨进程失败体, _ = 夹具.发调用(服务端口, 夹具.靶子编号, [])
        _, 进程内失败体, _ = 夹具.发调用(进程内端口, 夹具.靶子编号, [])
        记一条("二·个数错误逐码一致", "两路均返回参数个数码3",
               f"两路 {夹具.判失败码(跨进程失败体)} / {夹具.判失败码(进程内失败体)}",
               0 if 夹具.判失败码(跨进程失败体) == 夹具.判失败码(进程内失败体) == 3 else 1)
        for 端口项 in (服务端口, 进程内端口):
            源字节 = (夹具.仓根 / "测试验证/案例/往返逐字节/输入.容器").read_bytes()
            槽表, 说明文本 = 看返回值(端口项, [夹具.造字节集位(源字节)], 编号=1105)
            if 槽表:
                槽表, 说明文本 = 看返回值(端口项, [夹具.造字节集位(夹具.解字节集(槽表[0]))], 编号=1104)
            记一条(f"一·字节输入与返回往返·{端口项}", "1105→1104恢复原容器全部字节（含零）",
                   f"原件 {len(源字节)} 字节 · 含零 {0 in 源字节} · {说明文本}",
                   0 if 槽表 and 夹具.解字节集(槽表[0]) == 源字节 and 0 in 源字节 else 1)
        _, 进程内失败体, _ = 夹具.发调用(进程内端口, 无主号, [夹具.造文本位("x")])
        _, 跨进程失败体, _ = 夹具.发调用(服务端口, 无主号, [夹具.造文本位("x")])
    finally:
        夹具.停网关(无配置进程)

    for 位次 in range(len(样本文本表)):
        样本名 = 跨进程表[位次][0]
        跨进程形 = 形状对(跨进程表[位次][1])
        进程内形 = 形状对(进程内表[位次][1])
        记一条(
            f"二·两条路一致·{样本名}",
            "全部槽标签与内容逐字节相等：跨进程 = 进程内",
            f"跨进程 {跨进程形!r} · 进程内 {进程内形!r}",
            0 if (跨进程形 is not None and 跨进程形 == 进程内形) else 1,
        )
    跨进程码 = 夹具.判失败码(跨进程失败体)
    进程内码 = 夹具.判失败码(进程内失败体)
    记一条(
        "二·业务失败档一致",
        "无主号在两条路上给同一档结构化失败码",
        f"跨进程码 {跨进程码} · 进程内码 {进程内码}",
        0 if (跨进程码 is not None and 跨进程码 == 进程内码) else 1,
    )


def 必证三_清理(服务端口, 网关进程):
    """③ 正常 / 失败 / 反复调用与进程退出后，内存与进程资源都被回收。

    逐项读：连续调 20 次仍全正常（重复调用不泄句柄 / 不串会话）；
    一次失败调用后健康调用照常；跨进程路真起了工作进程（证明确实没回落进程内）。
    """
    global 资源面读数
    # 跨分配器存活分配计数：**在动手调之前**先读一次（末尾再读一次比对）。
    读数前 = 夹具.取存活分配计数(服务端口)
    # 资源面读数：趁网关还活着取一次（`主流程` 的 finally 会把网关停掉）。
    资源面读数 = 夹具.取资源读数(服务端口)
    成功数 = 0
    for 序次 in range(20):
        槽表, _ = 看返回值(服务端口, [夹具.造文本位(f"repeat {序次}.")])
        成功数 += 1 if 槽表 else 0
    记一条(
        "三·反复调用",
        "连续 20 次调用全部正常返回",
        f"成功 {成功数} / 20",
        0 if 成功数 == 20 else 1,
    )
    _ = 夹具.发调用(服务端口, 无主号, [夹具.造文本位("x")])
    槽表, 说明文本 = 看返回值(服务端口, [夹具.造文本位("after failure.")])
    记一条(
        "三·失败后仍可用",
        "一次失败调用之后健康调用照常出值",
        "拿到返回槽" if 槽表 else 说明文本,
        0 if 槽表 else 1,
    )
    time.sleep(1.1)
    槽表, 说明文本 = 看返回值(服务端口, [夹具.造文本位("after idle")])
    记一条("三·空闲后存活", "空闲超过旧1秒预算后首次调用成功",
           说明文本 or "成功", 0 if 槽表 and 夹具.取所属进程(网关进程) else 1)
    存活 = len(夹具.取所属进程(网关进程))
    记一条(
        "三·跨进程真在场",
        "跨进程路真起了本次网关所属工作进程",
        f"存活工作进程 {存活} 个",
        0 if 存活 >= 1 else 1,
    )
    # ★ 2026-10-13：本条从「推定」升级为「读数」——`GET /接口/资源读数` 报生产进程的
    #   跨分配器存活分配计数（计数分配器挂在生产二进制，见 `examples/启动网关.rs`）。
    #   前后各读一次、**差为 0** 才算过；owner / FD 快照仍由上面那条「三·跨进程真在场」留着。
    读数后 = 夹具.取存活分配计数(服务端口)
    记一条(
        "三·内存回收",
        "跨分配器存活分配计数：调用前后各读一次，差为 0（不再由「调用成功」推定）",
        f"前 {读数前} · 后 {读数后} · 差 {读数后 - 读数前 if None not in (读数前, 读数后) else '（读不到）'}",
        0 if 读数前 is not None and 读数后 is not None and 读数前 == 读数后 else 1,
    )


