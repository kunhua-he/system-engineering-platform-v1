def 主流程():
    """跑八条必证；返回汇总退出码。"""
    工作目录 = 夹具.取工作目录(新建=True)
    print(f"工作目录 {工作目录}")
    工作进程路径 = 找工作进程()
    if not 工作进程路径.exists():
        报一条阻断("整段", f"工作进程可执行件不存在（{工作进程路径}）")
        报阻断()
        return 1

    配置件 = 夹具.造部署配置(工作目录, str(工作进程路径))
    print(f"部署配置 {配置件}")
    端口 = 夹具.取空闲端口()
    网关进程, 端口 = 夹具.起网关(工作目录, 端口, 跨进程配置=配置件)
    try:
        print("")
        print("一 数据过线（非空 / 中文 / 空文本 · 含零字节字节集）")
        必证一_数据过线(端口)
        print("")
        print("二 进程内 vs 跨进程语义一致")
        必证二_两条路一致(端口)
        print("")
        print("三 正常 / 失败 / 反复调用的资源清理")
        print("调用前资源", 夹具.取资源快照(网关进程, "调用前"))
        必证三_清理(端口, 网关进程)
        print("调用后资源", 夹具.取资源快照(网关进程, "调用后"))
        成功数 = 夹具.验并发调用(端口)
        记一条("三·同域并发不串帧", "32次每次返回自身原文字节", f"成功 {成功数}/32", 0 if 成功数 == 32 else 1)
        print("")
        print("四 超长 / 畸形载荷结构化拒 + 拒后仍健康")
        必证四_拒收后仍健康(端口)
        print("")
        print("五 工作进程被杀的结构化失败与隔离")
        必证五_杀进程(端口, 网关进程)
    finally:
        清理进程号表 = [行文本.split()[0] for 行文本 in 夹具.取所属进程(网关进程)]
        日志 = 夹具.停网关(网关进程)
        time.sleep(0.02)
        残留进程号表 = 夹具.查残留进程(清理进程号表)
        记一条("三·退出回收所属进程", "owner已核对的工作进程停止后消失",
               f"清理PID {清理进程号表} · 残留 {残留进程号表}",
               0 if 清理进程号表 and not 残留进程号表 else 1)
        print("")
        print(f"网关日志末段：{(日志 or '')[-300:]}")

    print("")
    print("六 初始化失败不发布")
    必证六_初始化失败不发布(工作目录)
    print("")
    print("七 资源零 / 多输出语义")
    必证七_资源语义()
    print("")
    print("八 接入发布验收")
    必证八_接入发布验收()

    报阻断()
    return 汇总结局()
