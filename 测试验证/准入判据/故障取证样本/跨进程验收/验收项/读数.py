"""验收项 · 读数 —— 记一条 / 报阻断 / 汇总。

口径与 W07 同族：每条必证给「预期 / 实际 / 退出码」；给不出底层语义的**如实标阻断**，
绝不用别的项通过去补它的空。
"""

记录表 = []
阻断表 = []


def 记一条(条目名, 预期, 实际, 退出码值, 说明文本=""):
    """记一条读数（与 W07 同形：预期 / 实际 / 退出码）。"""
    记录表.append((条目名, 预期, 实际, 退出码值, 说明文本))
    标记 = "✓" if 退出码值 == 0 else "✗"
    print(f"  {标记} {条目名}")
    print(f"      预期：{预期}")
    print(f"      实际：{实际}")
    if 说明文本:
        print(f"      说明：{说明文本}")


def 报一条阻断(条目名, 阻断原因):
    """如实标阻断：给不出底层语义就不给读数（不造数字）。"""
    阻断表.append((条目名, 阻断原因))
    print(f"  ⊘ {条目名}（阻断：{阻断原因}）")


def 报阻断():
    """把阻断逐条打印出来。"""
    print("")
    if 阻断表:
        print("阻断（如实报）：")
        for 条目名, 阻断原因 in 阻断表:
            print(f"  · {条目名} —— {阻断原因}")
    else:
        print("阻断：无")


def 汇总结局():
    """打印汇总并返回退出码（有失败或有阻断 ⇒ 1）。"""
    失败数 = sum(1 for 读数行 in 记录表 if 读数行[3] != 0)
    print("")
    print(f"汇总：读数 {len(记录表)} 条 · 失败 {失败数} 条 · 阻断 {len(阻断表)} 条")
    return 0 if (失败数 == 0 and not 阻断表) else 1
