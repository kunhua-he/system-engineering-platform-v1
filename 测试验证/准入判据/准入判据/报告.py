def 打印(结果, 耗时毫秒, 读数=False):
    通过 = sum(1 for _, _, _, r in 结果 if r[0] == "通过")
    失败 = sum(1 for _, _, _, r in 结果 if r[0] == "失败")
    未判 = sum(1 for _, _, _, r in 结果 if r[0] == "未判")
    print(f"准入判据：通过 {通过} · 失败 {失败} · 未判 {未判} · "
          f"机器可判 {len(机器判据)}/16 · 耗时 {耗时毫秒} ms")
    print("")
    for 编号, 名, 面, (判定, 证据, 对象数) in 结果:
        标 = {"通过": "✓", "失败": "✗", "未判": "○"}[判定]
        print(f"{标} {编号} {名}｜{判定}｜{证据}")
        if 读数:
            print(f"    扫描面：{面}｜对象数：{对象数}")
    print("")
    print("不可机器判的 6 条（如实登记，未判）：")
    for 编号 in ["①", "②", "③", "⑥", "⑫", "⑮"]:
        名, 判不了, 缺 = 登记[编号]
        print(f"  ○ {编号} {名}")
        print(f"      为什么判不了：{判不了}")
        print(f"      缺什么才能判：{缺}")


def 清单():
    print("16 条逐条：")
    for 编号, 名, 判 in 机器判据:
        print(f"  {编号} 做了（机器可判）  {名}")
    for 编号 in ["①", "②", "③", "⑥", "⑫", "⑮"]:
        名, 判不了, 缺 = 登记[编号]
        print(f"  {编号} 没做（不可机器判）  {名}")


