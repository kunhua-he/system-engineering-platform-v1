def 跑单条判据(测试世界: 判读世界, 编号: str) -> int:
    """单条判据：通过 = 0 · 失败 = 1 · 未判 = 2 · 有意不判 = 0（按设计不判，不阻塞）。"""
    for 号值, 名称, 判据函数 in 机器判据:
        if 号值 == 编号:
            判定, 证据, 对象数 = 判据函数(测试世界)
            print(f"{编号} {名称}｜{判定}｜{证据}｜对象数 {对象数}")
            return {"通过": 0, "失败": 1, "未判": 2, "有意不判": 0}[判定]
    if 编号 in 有意不判:
        有意条目 = 有意不判[编号]
        判定, 证据, 对象数 = 判有意不判_依据锚点齐(测试世界, 编号)
        print(f"{编号} {有意条目['名']}｜{判定}｜{证据}｜对象数 {对象数}")
        print(f"    依据：{有意条目['依据']}")
        print(f"    什么时候能判：{有意条目['何时能判']}")
        return {"通过": 0, "失败": 1, "未判": 2, "有意不判": 0}[判定]
    print(f"没有判据 {编号}（16 条见 --清单）")
    return 1
