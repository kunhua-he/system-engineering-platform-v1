# 有意不判的编号（固定两条；多一条少一条都会让 16 条口径失衡 ⇒ 报「失败」）
有意不判编号 = ["①", "⑮"]


def 打印报告(判定汇总, 耗时毫秒, 读数=False):
    通过 = sum(1 for _, _, _, 判据结果 in 判定汇总 if 判据结果[0] == "通过")
    失败 = sum(1 for _, _, _, 判据结果 in 判定汇总 if 判据结果[0] == "失败")
    未判 = sum(1 for _, _, _, 判据结果 in 判定汇总 if 判据结果[0] == "未判")
    有意 = sum(1 for _, _, _, 判据结果 in 判定汇总 if 判据结果[0] == "有意不判")
    print(f"准入判据：通过 {通过} · 失败 {失败} · 未判 {未判} · 有意不判 {有意} · "
          f"机器可判 {len(机器判据)}/16 · 耗时 {耗时毫秒} ms")
    print("")
    for 编号, 名称, 扫描面, (判定, 证据, 对象数) in 判定汇总:
        标记 = {"通过": "✓", "失败": "✗", "未判": "○", "有意不判": "◆"}[判定]
        print(f"{标记} {编号} {名称}｜{判定}｜{证据}")
        if 读数:
            print(f"    扫描面：{扫描面}｜对象数：{对象数}")
    print("")
    print(f"按设计不判的 {len(有意不判编号)} 条（**有意不判** = 依据锚点机器核过，不是放任）：")
    for 编号 in 有意不判编号:
        有意条目 = 有意不判[编号]
        print(f"  ◆ {编号} {有意条目['名']}")
        print(f"      为什么有意不判：{有意条目['理由']}")
        print(f"      依据：{有意条目['依据']}")
        print(f"      什么时候能判：{有意条目['何时能判']}")


def 打印清单(测试世界: 判读世界):
    """16 条逐条：机器可判 / 有意不判 / 失败。

    **有意不判的那两条也走同一判定**（`判据.判有意不判_依据锚点齐`）—— 不许在这里纯静态
    打「按设计不判」：那会让清单与实跑结论相反。清单是**读数**、不是放行凭据：
    它只报 ①⑮ 的锚点状态，**本次未运行**其余 14 条机器判据（那些只在实跑里判）。
    """
    print("16 条逐条（本清单只报 ①⑮ 的锚点状态，其余 14 条机器判据本次**未运行**）：")
    for 编号, 名称, _判据函数 in 机器判据:
        print(f"  {编号} 做了（机器可判）  {名称}")
    for 编号 in 有意不判编号:
        有意条目 = 有意不判[编号]
        判定, 证据, _对象数 = 判有意不判_依据锚点齐(测试世界, 编号)
        print(f"  {编号} {判定}  {有意条目['名']}")
        print(f"      依据锚点：{证据}")


