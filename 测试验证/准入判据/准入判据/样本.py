"""样本 —— 自测：逐条跑正/反向样本（正向必过、反向必红）。

缺任一方 ⇒ 该条未验证（判据的可信性 §五）。
"""

import json
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

from .判据 import (
    判_2, 判_3, 判_4, 判_5, 判_6, 判_7, 判_8, 判_9, 判_10, 判_11, 判_12, 判_13, 判_14, 判_16,
    判有意不判,
)
from .世界 import 世界, 找仓根, 扩展根目录名
from .清单 import 机器判据
from .登记 import 有意不判


def _复制(测试世界: 世界) -> 世界:
    新内容 = object.__new__(世界)
    新内容.__dict__ = dict(测试世界.__dict__)
    return 新内容


def _复制扩展目录(测试世界: 世界) -> Path:
    目标 = Path(tempfile.mkdtemp(prefix="准入判据_指纹_")) / "编译器支持库"
    shutil.copytree(测试世界.扩展目录(), 目标)
    return 目标


def 自测() -> int:
    """逐条跑正/反向样本：正向必过、反向必红。缺任一方 ⇒ 该条未验证。"""
    测试世界 = 世界(找仓根())
    区间起点 = time.perf_counter()
    失败 = []
    源码行 = []

    def 断言(编号, 名称, 样本, 期望, 结果):
        if 结果[0] != 期望:
            失败.append(f"{编号} {名称}｜{样本}：期望 {期望}，实得 {结果[0]}（{结果[1]}）")
            return False
        return True

    # ②：时长半读数口 + 配额码。反向 = 抽掉配额账本的读数口。
    正向样本 = _复制(测试世界)
    断言("②", "资源上限", "正向样本", "通过", 判_2(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.面 = dict(反向样本.面)
    反向样本.面["配额记账"] = ""
    断言("②", "资源上限", "反向样本（抽掉配额账本读数口）", "失败", 判_2(反向样本))

    # ③：超时执行者已裁 + 两处报码 4 + 会越界的样本。反向 = 抽掉调度的越界判定。
    正向样本 = _复制(测试世界)
    断言("③", "超时不挂死", "正向样本", "通过", 判_3(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.面 = dict(反向样本.面)
    反向样本.面["调度核心"] = ""
    断言("③", "超时不挂死", "反向样本（抽掉调度越界报码）", "失败", 判_3(反向样本))

    # ④
    正向样本 = _复制(测试世界)
    断言("④", "广播段", "正向样本", "通过", 判_4(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.判定rs = 反向样本.判定rs.replace(
        "if 生命周期广播段(段.起.取号值(), 段.止.取号值()) {\n            continue;\n        }", "")
    断言("④", "广播段", "反向样本（抽掉广播段 continue）", "失败", 判_4(反向样本))

    # ⑤
    正向样本 = _复制(测试世界)
    断言("⑤", "通知口", "正向样本", "通过", 判_5(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.通知口 = 反向样本.通知口.replace("pub fn 注册通知端点", "fn _没了_注册通知端点")
    断言("⑤", "通知口", "反向样本（抽掉注册通知端点）", "失败", 判_5(反向样本))

    # ⑥：机制件（2015 号段 · 真跑测试） + §五 代跑读数行。反向 = 抽掉代跑读数行。
    正向样本 = _复制(测试世界)
    断言("⑥", "优雅卸载", "正向样本", "通过", 判_6(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.决策记录准入 = ""
    断言("⑥", "优雅卸载", "反向样本（抽掉 §五 ⑥ 代跑读数行）", "失败", 判_6(反向样本))

    # ⑦
    正向样本 = _复制(测试世界)
    断言("⑦", "接缝冻结", "正向样本", "通过", 判_7(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.边界协议 = 反向样本.边界协议.replace("不复刻", "保持一致").replace("偏离", "保持一致")
    断言("⑦", "接缝冻结", "反向样本（抽掉「不复刻/偏离」）", "失败", 判_7(反向样本))

    # ⑧
    正向样本 = _复制(测试世界)
    断言("⑧", "无死键", "正向样本", "通过", 判_8(正向样本))
    反向样本 = _复制(测试世界)
    路, 声 = 反向样本.包声明表[0]
    带死键 = dict(声)
    带死键["提供宿主版本"] = {"主": 1, "次": 0, "构建": 0}
    反向样本.包声明表 = [(路, 带死键)]
    断言("⑧", "无死键", "反向样本（注入 提供宿主版本）", "失败", 判_8(反向样本))

    # ⑨
    正向样本 = _复制(测试世界)
    断言("⑨", "crate-type", "正向样本", "通过", 判_9(正向样本))
    反向样本 = _复制(测试世界)
    路, 文 = 反向样本.扩展Cargo表[0]
    反向样本.扩展Cargo表 = [(路, 文.replace("[lib]\n", '[lib]\ncrate-type = ["cdylib"]\n'))]
    断言("⑨", "crate-type", "反向样本（注入 crate-type）", "失败", 判_9(反向样本))

    # ⑩：空集 → 未判；注入一条合法 → 通过；注入一条非法 → 失败（证明非空转）
    临时 = Path(tempfile.mkdtemp(prefix="准入判据_类别_")) / "0000.json"
    临时.write_text(json.dumps({"类别号": 0, "名称": "默认", "说明": "默认类别"},
                              ensure_ascii=False), encoding="utf-8")
    正向样本 = _复制(测试世界)
    正向样本.命令类别 = [临时]
    断言("⑩", "命令类别", "正向样本（注入 1 条合法）", "通过", 判_10(正向样本))
    反向样本 = _复制(测试世界)
    临时2 = Path(tempfile.mkdtemp(prefix="准入判据_类别_")) / "0001.json"
    临时2.write_text(json.dumps({"类别号": 99, "名称": "", "说明": ""}, ensure_ascii=False),
                    encoding="utf-8")
    反向样本.命令类别 = [临时2]
    断言("⑩", "命令类别", "反向样本（类别号≠文件名 + 名/说明空）", "失败", 判_10(反向样本))
    空集世界 = _复制(测试世界)
    空集世界.命令类别 = []
    断言("⑩", "命令类别", "空集样本（必报未判，不许算通过）", "未判", 判_10(空集世界))

    # ⑪：口径已补（2026-09-27 协调方施工，`载入判定.json` 的 `判定顺序的优先级`）。
    # 正/反都**合成**：正向 = 真件（应通过）；反向 = 真件**去掉那条键**（应失败）。
    # **为什么反向不许再用「现状」**：现状一旦被修好，反向样本就当场消失（判据的身份证没了）——
    # 判据的可信性.md 第五节：反向样本必须是**固定**的一份输入，不许跟着实物漂。
    正向样本 = _复制(测试世界)
    断言("⑪", "显式顺序", "正向样本（真件已写明先于关系）", "通过", 判_11(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.载入判定文 = re.sub(
        r'\s*"判定顺序的优先级"\s*:\s*"(?:[^"\\]|\\.)*",', "", 反向样本.载入判定文)
    断言("⑪", "显式顺序", "反向样本（合成：抽掉那条优先级键）", "失败", 判_11(反向样本))

    # ⑫：§五 代跑读数行 + 静态形状（无硬编码）。反向 = 抽掉代跑读数行；另反向 = 注入硬编码扩展名。
    正向样本 = _复制(测试世界)
    断言("⑫", "列真清单", "正向样本", "通过", 判_12(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.决策记录准入 = ""
    断言("⑫", "列真清单", "反向样本（抽掉 §五 ⑫ 代跑读数行）", "失败", 判_12(反向样本))
    反2 = _复制(测试世界)
    反2.工具响应扩展 = 反2.工具响应扩展 + "\n// 编译器支持库\n"
    断言("⑫", "列真清单", "反向样本（注入硬编码扩展名）", "失败", 判_12(反2))

    # ⑬
    正向样本 = _复制(测试世界)
    断言("⑬", "报因", "正向样本", "通过", 判_13(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.启动网关 = 反向样本.启动网关.replace("剔除的.push", "let _ = 丢弃;")
    断言("⑬", "报因", "反向样本（抽掉剔除台账）", "失败", 判_13(反向样本))

    # ⑭：正向 = 临时副本刷新指纹后 --检查 退 0；反向 = 改一个哈希后 --检查 退 1
    临时根 = Path(tempfile.mkdtemp(prefix="准入判据_指纹根_"))
    (临时根 / "扩展装载").mkdir(parents=True, exist_ok=True)
    临时扩展 = 临时根 / 扩展根目录名 / "原子支持库" / "编译器支持库"
    临时扩展.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(测试世界.扩展目录(), 临时扩展)
    # 先刷新（去掉漂移），再判
    subprocess.run([sys.executable, str(临时扩展 / "工具/重跑指纹.py")],
                   capture_output=True, text=True, timeout=5)
    正向样本 = _复制(测试世界)
    正向样本.仓根 = 临时根
    正向样本.扩展目录 = lambda: 临时扩展  # 覆盖方法
    正向样本.指纹件 = lambda: 临时扩展 / "指纹.json"
    正向样本.指纹脚本 = lambda: 临时扩展 / "工具/重跑指纹.py"
    断言("⑭", "指纹可跑", "正向样本（临时副本刷新后 --检查）", "通过", 判_14(正向样本))
    # 反向：改一个哈希
    指纹 = json.loads((临时扩展 / "指纹.json").read_text(encoding="utf-8"))
    首键 = next(iter(指纹["指纹"]))
    指纹["指纹"][首键] = "0" * 64
    (临时扩展 / "指纹.json").write_text(json.dumps(指纹, ensure_ascii=False, indent=2),
                                      encoding="utf-8")
    反向样本 = _复制(测试世界)
    反向样本.仓根 = 临时根
    反向样本.扩展目录 = lambda: 临时扩展
    反向样本.指纹件 = lambda: 临时扩展 / "指纹.json"
    反向样本.指纹脚本 = lambda: 临时扩展 / "工具/重跑指纹.py"
    断言("⑭", "指纹可跑", "反向样本（改一个哈希）", "失败", 判_14(反向样本))

    # ⑯
    正向样本 = _复制(测试世界)
    断言("⑯", "并发", "正向样本", "通过", 判_16(正向样本))
    反向样本 = _复制(测试世界)
    反向样本.线程安全 = 反向样本.线程安全.replace("unsafe impl Sync for 适配器 {}", "")
    断言("⑯", "并发", "反向样本（抽掉 Sync 断言）", "失败", 判_16(反向样本))

    # 有意不判：**依据锚点机器核** —— 锚点在 ⇒ 有意不判；锚点丢 ⇒ **失败**（不是免检牌）。
    for 编号 in ["①", "⑮"]:
        正向样本 = _复制(测试世界)
        断言(编号, 有意不判[编号]["名"], "正向样本（依据锚点在）", "有意不判", 判有意不判(正向样本, 编号))
        反向样本 = _复制(测试世界)
        反向样本.面 = dict(反向样本.面)
        首面 = 有意不判[编号]["锚点"][0][0]
        反向样本.面[首面] = ""
        断言(编号, 有意不判[编号]["名"], f"反向样本（抽掉依据锚点所依的面 {首面}）", "失败",
           判有意不判(反向样本, 编号))

    毫秒 = int((time.perf_counter() - 区间起点) * 1000)
    for 编号, 名, 判 in 机器判据:
        源码行.append(f"  {编号} {名}")
    for 编号 in ["①", "⑮"]:
        源码行.append(f"  {编号} {有意不判[编号]['名']}（有意不判：依据锚点机器核）")
    print("准入判据自测（正向必过 · 反向必红）")
    for 文本 in 源码行:
        print(文本)
    print(f"\n样本断言：{len(失败) == 0 and '全过' or '有失败'} · 耗时 {毫秒} ms")
    for 文本 in 失败:
        print(f"  ✗ {文本}")
    if not 失败:
        print("  每条机器判据的 正向样本 与 反向样本 都符合预期（判据非空转）")
    return 0 if not 失败 else 1
