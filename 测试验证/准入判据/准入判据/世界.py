"""世界 —— 一次判读的全部输入。判据只读它，**不各自去开文件**（便于自测注入变异）。

★ `读文本` / `读JSON件` 的错误策略是**有意的（都吞 `OSError`；`读JSON件` 另吞 `ValueError`
→ `""` / `None`）** —— 本件是**一次判读的输入聚合**，某一份输入缺了要让对应判据走「未判」，
不许一个坏文件炸掉整轮。与别处同名读器（`代码地图/形参面.py` 吞 `OSError` 返空串 ·
`查文件行数/核心.py` 不吞原样抛 · `生成声明/小工具.py` 抛 `生成失败` · `形状检查/形状.py`
不吞原样抛）**不是同一事实，勿合并**。
"""

