"""世界 —— 一次判读的全部输入。判据只读它，**不各自去开文件**（便于自测注入变异）。"""

import json
from pathlib import Path

契约目录名 = "契约声明"
扩展根目录名 = "扩展根目录"


def 找仓根() -> str:
    for 起 in [Path.cwd(), Path(__file__).resolve().parent, *Path(__file__).resolve().parents]:
        if (起 / 契约目录名).is_dir() and (起 / "扩展装载").is_dir():
            return str(起)
    return str(Path.cwd())


def 读文本(路径: Path) -> str:
    try:
        return 路径.read_text(encoding="utf-8")
    except OSError:
        return ""


def 读JSON件(路径: Path):
    try:
        return json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def 读生成物面(根目录: Path) -> str:
    """拼接**生成物全集**的文本：`契约声明/src/` 下以「数据.rs」结尾的 `.rs`（路由件 + 子件）。

    生成物按表拆后不再是单个 `声明数据.rs`；判据凡要读生成物内容（判据 ④ 读 `生命周期起/止`）
    一律走这里。写死单个路径，拆一次就静默丢覆盖面（#230 记的正是这个病）。
    """
    目录 = 根目录 / "契约声明/src"
    if not 目录.is_dir():
        return ""
    return "".join(
        读文本(路) for 路 in sorted(目录.glob("*数据.rs"))
    )


def 读装配器源码(根目录: Path) -> str:
    """装配器 = 入口 `构建制品.py` + 同名字文件夹 `构建制品/`。

    判据 ⑨ 要在**装配器源码**里找「现场编 cdylib」那一条路。入口拆成路由后，
    那条路落在 `构建制品/扩展.py`；故这里把入口与包一起读进来（口径见
    `开发规范.md` §六「主文件是路由」）。
    """
    文本 = 读文本(根目录 / "构建装配/上线切换/构建制品.py")
    return 文本 + "".join(
        读文本(路) for 路 in sorted((根目录 / "构建装配/上线切换/构建制品").rglob("*.py"))
    )


def 读目录全部源文件(目录: Path) -> str:
    """一个目录下全部 `.rs`（含子目录）拼起来 —— 判据读「面」，不读某一个写死的文件。"""
    if not 目录.is_dir():
        return ""
    return "".join(读文本(路) for 路 in sorted(目录.rglob("*.rs")))


def _码文(根目录: Path, 号值: str) -> str:
    """一条错误码的 `名称` + `说明`（锚点两条都要能命中），读不到给空串。"""
    条 = 读JSON件(根目录 / f"契约声明/错误码表/{号值}.json") or {}
    if not isinstance(条, dict):
        return ""
    return f"{条.get('名称', '')} {条.get('说明', '')}"


def 读件与包(根目录: Path, 相对: str) -> str:
    """路由件 + **同名字文件夹**（`启动网关.rs` + `启动网关/`）。

    #230 记的病：判据把落点写成**单个文件路径** ⇒ 那个件一拆成路由（`mod` + 子件），
    判据就读不到搬进子件的记号，静默丢覆盖面（闸还照绿）。故一律读「件 + 它的包」。
    """
    件 = 根目录 / 相对
    return 读文本(件) + 读目录全部源文件(件.with_suffix(""))


class 世界:
    """一次判读的全部输入。判据只读它，**不各自去开文件**（便于自测注入变异）。

    每条判据的扫描面 = 本类里被它读到的那几个字段。
    """

    def __init__(self, 根目录: str):
        根目录 = Path(根目录)
        self.仓根 = 根目录
        self.边界协议 = 读文本(根目录 / "跨语言适配/边界协议/边界协议.md")
        self.扩展根声明 = 读JSON件(根目录 / "扩展装载/扩展根声明.json") or {}
        self.包声明表 = sorted(
            (声明件, 读JSON件(声明件)) for 声明件 in (根目录 / 扩展根目录名).rglob("包声明.json")
        )
        self.扩展Cargo表 = sorted(
            (声明件, 读文本(声明件)) for 声明件 in (根目录 / 扩展根目录名).rglob("Cargo.toml")
        )
        self.必备件 = 读JSON件(根目录 / "扩展装载/开发标准/必备件.json") or {}
        self.构建制品 = 读装配器源码(根目录)
        self.载入判定 = 读JSON件(根目录 / "扩展装载/载入约定/载入判定.json") or {}
        self.载入判定文 = 读文本(根目录 / "扩展装载/载入约定/载入判定.json")
        self.判定rs = 读文本(根目录 / "运行内核/装载入口/src/判定.rs")
        self.通知口 = 读文本(根目录 / "跨语言适配/适配器实现/src/通知口.rs")
        # 适配器 crate 的 `lib.rs` 是路由（子件散在 `src/` 下）⇒ 读**整个 crate 源**，
        # 不是那一个 `lib.rs`（否则 `通知.通道.注册(...)` 搬进 `核心实现/适配器定义.rs` 就丢了）。
        self.适配器lib = 读目录全部源文件(根目录 / "跨语言适配/适配器实现/src")
        self.线程安全 = 读文本(根目录 / "跨语言适配/适配器实现/src/线程安全.rs")
        self.网关 = 读文本(根目录 / "对外接口面/调用接口面/src/网关.rs")
        # 启动网关是路由件（子件在 `examples/启动网关/`）⇒ 读「件 + 包」。
        self.启动网关 = 读件与包(根目录, "对外接口面/调用接口面/examples/启动网关.rs")
        # 生成物**按表拆**后是一组件（路由件 `声明数据.rs` + 子件，都以「数据.rs」结尾）。
        # 判据要的是**生成物全集**，不是某一个写死的路径 —— 写死单路径，拆一次就静默丢覆盖面
        # （#230 记的正是这个病）。这里拼全部生成物文本（判据 ④ 读 `生命周期起/止`）。
        self.生成物面 = 读生成物面(根目录)
        self.命令类别 = sorted((根目录 / "契约声明/命令类别").glob("*.json"))
        self.工具响应扩展 = 读文本(根目录 / "对外接口面/调用接口面/src/工具响应_扩展.rs")
        # ⑥⑫ 判据要的东西：**机制件** + **代跑读数**（本脚本不许跑 cargo / 起网关，
        # 故真跑读数读**已登记**的那一行 —— `外部支持库准入判据.md` §五，不是空等）。
        self.通知号段2015 = 读JSON件(根目录 / "契约声明/通知号段/2015.json")
        self.生命周期测试 = 读文本(根目录 / "跨语言适配/适配器实现/src/生命周期协商测试.rs")
        self.决策记录准入 = 读文本(根目录 / "项目文档/决策记录/2026-09-27_外部支持库准入判据.md")
        # 「有意不判」各条的**依据锚点**要读的面。锚点是**机器可判**的：依据件一缺，
        # 那条当场由「有意不判」变「失败」—— 不许拿「有意」当免检牌。
        self.面 = {
            "裁决长活": 读文本(根目录 / "项目文档/决策记录/2026-09-27_长活真runner与准入未判裁决.md"),
            "现代架构落点": 读文本(根目录 / "项目文档/设计文档/现代架构落点.md"),
            "准入判据": self.决策记录准入,
            "配额记账": 读文本(根目录 / "运行内核/调用调度/src/配额记账.rs"),
            "留痕口": 读文本(根目录 / "跨语言适配/适配器实现/src/留痕口.rs"),
            "调度核心": 读文本(根目录 / "运行内核/调用调度/src/调度核心.rs"),
            "入口绑定": 读文本(根目录 / "跨语言适配/资源网关口/src/入口绑定.rs"),
            "调度测试": 读文本(根目录 / "运行内核/调用调度/src/调度测试.rs"),
            "关口主体": 读文本(根目录 / "跨语言适配/资源网关口/src/关口/关口主体.rs"),
            "常量表": 读文本(根目录 / "契约声明/常量表.json"),
            "工具响应扩展": self.工具响应扩展,
            "错误码4": _码文(根目录, "0004"),
            "错误码5": _码文(根目录, "0005"),
        }

    def 面文本(self, 名称: str) -> str:
        """按面名取已读入的文本（「有意不判」的依据锚点走这里，不各自开文件）。"""
        return self.面.get(名称, "")

    # 扩展目录（目前恰好 1 个；多处判据要它）
    def 扩展目录(self) -> Path:
        return self.仓根 / 扩展根目录名 / "原子支持库" / "编译器支持库"

    def 指纹件(self) -> Path:
        return self.扩展目录() / "指纹.json"

    def 指纹脚本(self) -> Path:
        命 = (读JSON件(self.指纹件()) or {}).get("生成命令", "")
        # 生成命令形如 "python3 扩展根目录/…/重跑指纹.py"（仓库根相对）
        分 = 命.split()
        参 = [参项 for 参项 in 分 if 参项.endswith(".py")]
        return self.仓根 / 参[0] if 参 else self.仓根 / "__缺__"
