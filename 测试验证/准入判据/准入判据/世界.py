def 读文本(路径: Path) -> str:
    try:
        return 路径.read_text(encoding="utf-8")
    except OSError:
        return ""


def 读JSON件(路径: Path):
    try:
        return json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def 读条款(根目录: Path, 文档路径: str) -> str:
    """取一份 md 的**全量正文** —— 该 md 已全量入库并删净（`项目文档/` 下不再有这些件）。

    唯一存本是规则库 `开发工具/信息核心/信息核心.db` 的 `条款` 表（键：文档路径 · 序号 · 标题 · 正文）。
    按 `序号` 拼「标题 + 正文」，与原件阅读顺序一致（`取代跑读数行` 依赖表行逐行在）。
    读不到（库缺 / 表缺 / 该路径无行）返空串 —— 与 `读文本` 同一条错误策略（缺输入 ⇒ 判据走未判/失败）。
    """
    库件 = 根目录 / "开发工具/信息核心/信息核心.db"
    if not 库件.is_file():
        return ""
    try:
        连接 = sqlite3.connect(str(库件))
        try:
            行表 = 连接.execute(
                "select 标题, 正文 from 条款 where 文档路径 = ? order by 序号", (文档路径,)
            ).fetchall()
        finally:
            连接.close()
    except sqlite3.Error:
        return ""
    return "\n".join(f"{标题 or ''}\n{正文 or ''}" for 标题, 正文 in 行表)


def 读生成物面(根目录: Path) -> str:
    """拼接**生成物全集**的文本：`契约声明/src/` 下以「数据.rs」结尾的 `.rs`（路由件 + 子件）。

    生成物按表拆后不再是单个 `声明数据.rs`；判据凡要读生成物内容（判据 ④ 读 `生命周期起/止`）
    一律走这里。写死单个路径，拆一次就静默丢覆盖面（#230 记的正是这个病）。
    """
    目录 = 根目录 / "契约声明/src"
    if not 目录.is_dir():
        return ""
    return "".join(
        读文本(路径) for 路径 in sorted(目录.glob("*数据.rs"))
    )


def 读装配器源码(根目录: Path) -> str:
    """装配器 = 入口 `构建制品.py` + 同名字文件夹 `构建制品/`。

    判据 ⑨ 要在**装配器源码**里找「现场编 cdylib」那一条路。入口拆成路由后，
    那条路落在 `构建制品/扩展.py`；故这里把入口与包一起读进来（口径见
    `开发规范.md` §六「主文件是路由」）。
    """
    文本 = 读文本(根目录 / "构建装配/上线切换/构建制品.py")
    return 文本 + "".join(
        读文本(路径) for 路径 in sorted((根目录 / "构建装配/上线切换/构建制品").rglob("*.py"))
    )


def 读目录全部源文件(目录: Path) -> str:
    """一个目录下全部 `.rs`（含子目录）拼起来 —— 判据读「面」，不读某一个写死的文件。"""
    if not 目录.is_dir():
        return ""
    return "".join(读文本(路径) for 路径 in sorted(目录.rglob("*.rs")))


def _码文(根目录: Path, 号值: str) -> str:
    """一条错误码的 `名称` + `说明`（锚点两条都要能命中），读不到给空串。"""
    一条 = 读JSON件(根目录 / f"契约声明/错误码表/{号值}.json") or {}
    if not isinstance(一条, dict):
        return ""
    return f"{一条.get('名称', '')} {一条.get('说明', '')}"


def 读件与包(根目录: Path, 相对: str) -> str:
    """路由件 + **同名字文件夹**（`启动网关.rs` + `启动网关/`）。

    #230 记的病：判据把落点写成**单个文件路径** ⇒ 那个件一拆成路由（`mod` + 子件），
    判据就读不到搬进子件的记号，静默丢覆盖面（闸还照绿）。故一律读「件 + 它的包」。
    """
    节点件 = 根目录 / 相对
    return 读文本(节点件) + 读目录全部源文件(节点件.with_suffix(""))


