def 段含键(源文本: str, 段名: str, 键名: str) -> bool:
    """粗判 TOML：段 [段名] 到下一个 [ 之间是否出现 键名。"""
    源码行 = 源文本.splitlines()
    在段 = False
    for 行文 in 源码行:
        净文本 = 行文.strip()
        if 净文本.startswith("[") and 净文本.endswith("]"):
            在段 = 净文本 == f"[{段名}]"
            continue
        if 在段 and 净文本.split("=")[0].strip() == 键名:
            return True
    return False


