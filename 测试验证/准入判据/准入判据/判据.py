def 判有意不判_依据锚点齐(测试世界: 判读世界, 编号: str):
    """逐条核「有意不判」的依据锚点：锚点齐 ⇒ 有意不判；缺 ⇒ **失败**。

    **为什么不是恒过**：若只写「有意不判」就不管了，那它就是一张免检牌 —— 依据件被删、
    那句话被改，读数里什么都不会变（判据的可信性 §二：「判不了」必须能取证）。
    故这里把依据锚点也做成**机器可判**：`依据件` 里逐字找 `锚点`，少一条即红。
    """
    有意条目 = 有意不判[编号]
