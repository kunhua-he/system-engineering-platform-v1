"""发布验收卡调度 —— 按卡号找到 `故障取证样本/` 下的卡模块并跑它（一个关注点一个文件）。

T09 是**跨进程执行路**那一张：它与其他三张不同，不是夹具自证 ——
它起真网关、真工作进程、真支持库制品，读数全是生产链上的实际结果。
"""

import importlib
import sys
from pathlib import Path

包目录 = Path(__file__).resolve().parents[1] / "故障取证样本"
卡号表 = (
    ("T06", "发布验收_缓存恢复"),
    ("T07", "发布验收_副作用未知"),
    ("T08", "发布验收_资源预算"),
    # T09 的模块住它本域目录（它带夹具与子模块，不宜平铺）⇒ 导入前把那一层加进路径。
    ("T09", "跨进程验收.入口函数"),
)


if str(包目录) not in sys.path:
    sys.path.insert(0, str(包目录))


def 导入卡模块(模块名):
    """按模块名导入一张卡的实施模块（卡模块是库件，不带 `__main__`）。"""
    return importlib.import_module(模块名)


def 跑卡(卡号):
    """按卡号跑一张发布验收卡，返回该卡的退出码。"""
    模块名 = dict(卡号表)[卡号]
    return 导入卡模块(模块名).入口函数([])


def 跑全部卡():
    """三张卡依次跑并汇总退出码（任一非 0 ⇒ 汇总非 0）。"""
    逐卡退出码 = []
    for 卡号, 模块名 in 卡号表:
        print("")
        逐卡退出码.append((卡号, 跑卡(卡号)))
    print("")
    print("发布验收汇总：" + " · ".join("%s=%d" % (卡号, 退出码值) for 卡号, 退出码值 in 逐卡退出码))
    return 0 if all(退出码值 == 0 for 卡号, 退出码值 in 逐卡退出码) else 1


def 入口函数(命令行参数):
    """命令行入口：给卡号只跑一张，否则三张依次跑。"""
    卡号项集 = [参数项 for 参数项 in 命令行参数 if 参数项 in dict(卡号表)]
    if 卡号项集:
        return 跑卡(卡号项集[0])
    return 跑全部卡()
