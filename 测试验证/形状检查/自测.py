# -*- coding: utf-8 -*-
"""自测 —— 反向样本：在**内存里**造坏期望 ⇒ 两条形状必须真报红。

为什么必须有：`判据的可信性.md` §五「每条判据成对样本（正向 + 反向，缺一即未验证）」。
这里造的两条坏期望都**不落盘**（`查一步` 只吃对象）⇒ 自测不动案例库一个字节。

三例：
  · 反向 A（形状②）：期望里写 `标准输出` 键 ⇒ **必红**（旁路当载体 = 假绿）；
  · 反向 B（形状③）：案例目录里备了 `输入.期望结果`，期望却降成 `非空字节集`
    ⇒ **必红**（关键值就在手边却不用）；
  · 正向对照：同一份输入写成 `逐字节等于文件` ⇒ **不许报红**（判据不误报）。
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

from .常量 import 关键值判据, 期望结果文件名, 判定_违反
from .形状 import 查一份案例


def 自测() -> int:
    """返回 0 = 三例全对 / 1 = 有不对。"""
    合格样本 = True
    print("查案例形状 · 反向样本（造坏的期望 ⇒ 必须报红）")
    with tempfile.TemporaryDirectory() as 临时:
        目录 = Path(临时) / "样本案例"
        目录.mkdir()
        # 反向 A：形状②（旁路键）
        旁路键报告 = []
        try:
            查一份案例(目录, {"步骤": [{"结果": "成功", "产物": {"判据": "非空字节集"},
                                    "标准输出": "42"}]}, 旁路键报告)
            合格样本 = False
            print("  ✗ 形状②：期望里写 `标准输出` 没被抓到（旁路当载体 = 假绿）")
        except ValueError as 错误:
            print(f"  ✓ 形状②：`标准输出` 被抓到 → {错误}")
        # 反向 B：形状③（备了关键值却把期望降成 `非空字节集`）
        (目录 / 期望结果文件名).write_bytes(b"42\n")
        降级报告 = []
        未判 = 查一份案例(目录, {"步骤": [{"结果": "成功", "产物": {"判据": "非空字节集"}}]}, 降级报告)
        命中 = any(判定值 == 判定_违反 and "关键值就在手边" in 说明 for _, 说明, 判定值 in 降级报告)
        if 命中 and 未判 == 0:
            print(f"  ✓ 形状③：备了 `{期望结果文件名}` 却降成 `非空字节集` 被抓到"
                  f" → {降级报告[0][1]}")
        else:
            合格样本 = False
            print(f"  ✗ 形状③：没抓到（判定={降级报告}）")
        # 正向对照：写成关键值断言 ⇒ 不许报红
        关键值报告 = []
        关键值步未判 = 查一份案例(目录, {"步骤": [{"结果": "成功",
                                        "产物": {"判据": 关键值判据, "文件": 期望结果文件名}}]}, 关键值报告)
        if not 关键值报告 and 关键值步未判 == 0:
            print(f"  ✓ 正向对照：写成 `{关键值判据}` ⇒ 不报红（判据不误报）")
        else:
            合格样本 = False
            print(f"  ✗ 正向对照：写成 `{关键值判据}` 却被报 ⇒ 假红（{关键值报告}）")
    print("")
    print("查案例形状自测：" + ("全部通过" if 合格样本 else "有不过的用例"),
          file=sys.stdout)
    return 0 if 合格样本 else 1
