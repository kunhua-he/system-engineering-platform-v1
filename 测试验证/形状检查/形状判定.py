# -*- coding: utf-8 -*-
"""形状 —— 三条形状的判定（读盘 · 查一步 · 查一份案例 · 扫案例 · 打读数）。

口径与判法（含「③ 纯确定性」那一半的可判口径）全在本文件的 `模块说明` 段，
逐条抄自 `测试验证/测试案例/形状.md` §十。三条形状的**键名与白名单**在 `形状键名.py`。

★ **未判是终态，不是待办**（库 `规则` 表 · 类 判据可信性）：「产物是被测实现自身定义的内部
编码（词法记号流 · 反解结构编码 · 诊断报告 · 能力包件）⇒ 期望只能停在 `非空字节集`」
—— 没有独立于实现的权威可比，而拿实现的产出当 `输入.期望结果` 是**空转的尺子**
（`判据的可信性.md` §三.1）。要断言其内容只能另立**黄金包案例**，那是另一件事。

★ `读JSON件` 的错误策略是**有意的（不吞：UTF-8 / JSON 错原样抛）** —— 形状件是期望值的权威，
读不动就得当场炸，不许静默。与别处同名读器（`生成声明/生成小工具.py` 抛 `生成失败` ·
`代码地图/形参面.py` 吞 `OSError`）**不是同一事实，勿合并**。
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from .形状键名 import (
    产物判据白名单,
    非载体键名,
    关键值判据,
    期望结果文件名,
    判定_违反,
    判定_未判,
    期望形状错,
)


def 读JSON件(路径: Path):
    return json.loads(路径.read_text(encoding="utf-8"))


def 找非载体键(待处理值, 路径: str = "") -> list:
    """在期望对象里递归找非载体键名；返回 [(位置, 键名)]。"""
    输出缓冲 = []
    if isinstance(待处理值, dict):
        for 键名, 子值 in 待处理值.items():
            小写 = str(键名).strip().lower()
            小写位 = f"{路径}/{键名}" if 路径 else str(键名)
            if 小写 in 非载体键名:
                输出缓冲.append((小写位, 键名))
            输出缓冲.extend(找非载体键(子值, 小写位))
    elif isinstance(待处理值, list):
        for 序号, 子值 in enumerate(待处理值):
            输出缓冲.extend(找非载体键(子值, f"{路径}[{序号}]"))
    return 输出缓冲


def 查一步(目录路径: Path, 步序: dict, 落点: str, 备了关键值: bool, 报告: list) -> int:
    """查一步期望的三条形状。返回**未判**条数（0 表示这一步没有未判）。"""
    # ── 形状②：非载体键 ──
    for 键路, 键名 in 找非载体键(步序):
        raise 期望形状错(
            f"{落点}：出现非载体键 `{键名}`（位置 {键路}）—— 载体必须是**返回值槽**，"
            f"标准输出与退出码是**非载体**（形状.md §10.1②）"
        )
    # ── 形状①：产物判据必须在那五个里 ──
    产物 = 步序.get("产物")
    if 产物 is None:
        报告.append((落点, "`产物` 缺失 ⇒ 这一步连载体都没声明", 判定_未判))
        return 1
    if not isinstance(产物, dict):
        raise 期望形状错(f"{落点}：`产物` 不是对象")
    判据 = 产物.get("判据")
    if 判据 not in 产物判据白名单:
        raise 期望形状错(
            f"{落点}：产物判据 `{判据}` 不在封闭枚举里"
            f"（{' / '.join(产物判据白名单)}）—— 载体只能是返回值槽（形状.md §1.2 + §10.1①）"
        )
    # ── 形状③：关键值断言 ──
    if 判据 == 关键值判据:
        目标目录 = 产物.get("文件")
        if not isinstance(目标目录, str) or not 目标目录:
            raise 期望形状错(f"{落点}：`{关键值判据}` 缺 `文件`（关键值断言要指到比对目标）")
        实路 = Path(目标目录) if Path(目标目录).is_absolute() else (目录路径 / 目标目录)
        if not 实路.is_file():
            raise 期望形状错(
                f"{落点}：`{关键值判据}` 的比对目标 `{目标目录}` 在案例目录里**不存在**（{实路}）"
                f"⇒ **断言是坏的**（尺子指到空处，比对时才会炸，且那时已在门禁里）——"
                f"形状.md §10.2：关键值 = 落到案例目录里一个文件，那个文件必须真在"
            )
        return 0
    if 判据 in ("非空字节集", "不判"):
        if 备了关键值:
            报告.append((
                落点,
                f"期望停在 `{判据}`，而案例目录里已备 `{期望结果文件名}`（关键值就在手边）"
                f"⇒ 纯确定性不许只写「非空」/「不判」（形状.md §10.1③）",
                判定_违反,
            ))
            return 0
        报告.append((
            落点,
            f"期望是 `{判据}` 且没有 `{期望结果文件名}` ⇒ 未判（终态）：库 `规则` 表 · 类"
            f" 判据可信性 —— 产物是被测实现自身定义的内部编码时，`{判据}` 就是终态，"
            f"拿实现产出当期望是空转的尺子；断言其内容只能另立黄金包案例"
            f"（如实报未判，不算通过）",
            判定_未判,
        ))
        return 1
    return 0


def 查一份案例(目录路径: Path, 期望: dict, 报告: list) -> int:
    """查一份案例 `期望.json`。返回未判条数。"""
    名称 = 目录路径.name
    步表 = 期望.get("步骤")
    if not isinstance(步表, list) or not 步表:
        raise 期望形状错(f"{名称}/期望.json：`步骤` 缺失、不是数组、或是空集（空集不算通过）")
    备了关键值 = (目录路径 / 期望结果文件名).is_file()
    未判 = 0
    for 序号, 步序 in enumerate(步表):
        if not isinstance(步序, dict):
            raise 期望形状错(f"{名称}/期望.json 步骤[{序号}]：不是对象")
        未判 += 查一步(目录路径, 步序, f"{名称}/期望.json 步骤[{序号}]", 备了关键值, 报告)
    return 未判


def 扫案例(根目录: Path) -> tuple:
    """扫案例根下每一份 `期望.json` ⇒ (报告, 工具错误或 None)。"""
    报告 = []
    未判 = 0
    有案例 = False
    for 目录路径 in sorted(目录项 for 目录项 in 根目录.iterdir() if 目录项.is_dir()):
        期望路径 = 目录路径 / "期望.json"
        if not 期望路径.is_file():
            continue  # 非案例目录（`跑案例/` 那类）
        有案例 = True
        try:
            未判 += 查一份案例(目录路径, 读JSON件(期望路径), 报告)
        except 期望形状错 as 错误:
            return [], str(错误)
    if not 有案例:
        return [], f"案例根 {根目录} 下 0 份 期望.json —— 空集不算通过（判据的可信性.md 第二节）"
    return 报告, None


def 查根(根目录: Path) -> int:
    """查一个案例根并打读数。返回退出码（0 = 无违反；`未判` 只报不阻塞）。

    ★ **退出码只认「违反」**（2026-10-01 收口口径）：`未判` 是**本件判不了**（缺关键值，而本件
    按「不猜哪个能力是纯确定性」的立场不替它编一个），**不是案例坏了** —— 按 `判据的可信性.md`
    第二节，这是「判不了 + 缺什么」那一档，如实报、不阻塞。

    为什么不再把 `未判` 算红：它清不掉。清它只有一条路 —— 给每个 `非空字节集` 步备一份
    `输入.期望结果`；而那字节只能由**被测实现自身**产出（跑一遍把它交回的东西存下来）⇒ 这把
    尺子的读数由被测对象定义，**一造出来就不可能报错**，即 `判据的可信性.md` 第三节第 1 条
    「判据是空转的」。把它当红，本件就**永远红**（谁也不再拿它当信号），与闸 2 当年把「不覆盖」
    从「未判」里单列出来的理由同一条（`扫实现/不覆盖.py` 文件头）。

    **不因此放宽**：真该红的「违反」（关键值就在手边却降级成 `非空字节集`）照旧红。
    """
    报告, 错误 = 扫案例(根目录)
    if 错误:
        print(f"工具错误：{错误}", file=sys.stderr)
        return 2
    违反 = [报告项 for 报告项 in 报告 if 报告项[2] == 判定_违反]
    未判 = [报告项 for 报告项 in 报告 if 报告项[2] == 判定_未判]
    print(f"形状检查：违反 {len(违反)} 条 · 未判 {len(未判)} 条"
          f"（未判不阻塞退出码 · 未判不算通过）· 案例根 {根目录}")
    for 落点, 说明, _ in 违反:
        print(f"- 违反 ｜ {落点} ｜ {说明}")
    for 落点, 说明, _ in 未判:
        print(f"- 未判 ｜ {落点} ｜ {说明}")
    return 0 if not 违反 else 1
