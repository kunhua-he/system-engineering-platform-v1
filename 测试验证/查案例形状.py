"""查案例形状 —— 案例期望的**判据形状**检查器（`测试验证/案例/形状.md` §十）。

上级：`测试验证/案例/形状.md` §十（三条形状：载体 = 返回值槽 · 标准输出/退出码是旁路 ·
纯确定性必须写关键值断言）· 依据裁决 `项目文档/决策记录/2026-09-27_待裁九项按老仓设计哲学裁决.md`
裁决 8。口径与判法全写在 `形状检查/形状.py` 的文件头；本件是**路由**：
声明子模块 · 再导出公开面 · **零实现**（`开发规范.md` 第六节）。

怎么跑（在仓库根）：

    python3 测试验证/查案例形状.py            # 查案例根下每份 期望.json 的三条形状
    python3 测试验证/查案例形状.py --自测      # 反向样本（内存里造坏期望 ⇒ 必须报红）
    python3 测试验证/查案例形状.py --样本      # 落盘的正向 + 反向样本（真案例）
    python3 测试验证/查案例形状.py --案例根 <目录>   # 换案例根

退出码：0 = 无违反（`未判` 只报不阻塞 —— 口径见 `形状检查/形状.py::查根`）；1 = 有违反；2 = 工具错误（案例目录坏了）。

★ 现存 5 条 `未判` 是**终态**，不是待办（库 `规则` 表 · 类 判据可信性）：那五步的产物是被测
实现自身定义的内部编码（词法记号流 · 反解结构编码 · 诊断报告 · 能力包件）⇒ 没有独立于实现的
权威可比；拿实现产出当 `输入.期望结果` 是空转的尺子（`判据的可信性.md` §三.1）。要断言其内容
只能另立黄金包案例 —— 那是另一件事，不是本判据的缺口。
"""

import sys
import time
from pathlib import Path

起始时刻 = time.monotonic()  # 壳起表点：必须在 import 业务包**之前**（见 构建装配/门禁/壳.py）

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # 仓根：取共享门禁
from 构建装配.门禁 import 自门禁  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))

from 形状检查 import 案例根, 查根, 自测, 跑样本  # noqa: E402

__all__ = ["案例根", "查根", "自测", "跑样本"]


def 入口函数(参数: list) -> int:
    """命令行入口：分发到 `形状检查` 的公开面。阈值与注入只从 `构建装配/门禁/` 取。"""
    if "--自测" in 参数:
        return 自测()
    if "--样本" in 参数:
        return 跑样本()
    根目录 = 案例根
    if "--案例根" in 参数:
        序号 = 参数.index("--案例根")
        if 序号 + 1 < len(参数):
            根目录 = Path(参数[序号 + 1]).resolve()
    return 查根(根目录)


if __name__ == "__main__":
    sys.exit(自门禁(起始时刻, 入口函数(sys.argv[1:]), 尾巴余量毫秒=200,
                   修法="本件只读案例目录里的 JSON（毫秒级）；慢了先查案例根是不是被换成大目录"))
