# -*- coding: utf-8 -*-
"""运行数据收敛的五组反证 —— **造脏 → 触发 → 核收敛**，全部在临时目录里做（不碰主仓运行根）。

# 为什么要写成脚本

手工做过一次不算证据：下一个改动把界调没了，没人会再手工造 400 份假日志。本件把四组反证做成
可重跑的样本（`跑反证.py` 是入口），每条断言都带读数 —— 红了当场能看出「哪条界没生效」。

# 五组

| 组 | 造什么脏 | 断言什么 |
|---|---|---|
| 日志 | 400 份假作业日志（mtime 分散，含 8 天前）+ 3 份非作业日志 | 8 天前的全没 · 7 天内的留 · 总数 ≤ 300 · 非作业日志一份不少 |
| 日志（份数界单独逼） | 350 份 1 小时内 + 60 份 8 天前（410 份） | 只按年龄删完仍超界 ⇒ 按 mtime 最旧优先删到恰好 300 · 删掉的确实是最旧那批 |
| 临时件 | 10 个 8 天前的按次产物 + 2 个 1 天前的 + 2 个 8 天前的证据目录（内有 1 天前改写的件）+ 2 个认不出名字的旧目录 + 两个白名单同名目录（也做成 8 天前） | 按次产物里 8 天前的全清、1 天前的全留 · **证据目录（内含新件）与认不出名字的一律不删**（并列进 `未匹配保留`）· `易语言源码` 与 `上线切换` 一动不动 |
| 守护壳 | 1 MB 小日志（不该轮转）· 6 MB 大日志（该轮转）· 轮转后再超界（`.1` 只留一份） | `sh -n` 过 · 小件不轮转 · 大件 `mv` 成 `.1` 且大小不变 · 再轮转只覆盖 `.1` |
| 单件日志 | 1 MB 的 `MCP诊断.log` + 6 MB 的 `MCP服务_http.日志.txt`；再用**两件各自的真写者**（逐次 `open` 追加 / 继承 stdout 的子进程）在轮转前后各写一段 | 小件不轮转 · 大件抄成 `.1` 且活动件被截回 0（**不换 inode**）· 轮转后写者的字节落**活动件**、`.1` 不再增长 · 再超界只覆盖 `.1` |

**回执那一组不归本件**：轮转实现在 `测试验证/测试案例/跑案例/src/回执.rs::收敛回执`，它的反证是
那条 crate 的单元测试（`cargo test -p v1-case-runner 收敛回执`）；本件只在读数里点明这一点，
不在这里用 Python 重写一遍轮转（同一件事两套实现 = 假绿来源）。
"""

