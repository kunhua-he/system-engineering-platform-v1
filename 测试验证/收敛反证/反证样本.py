# 反证持的「现在」：定死一个时刻，样本里所有 mtime 都相对它算 ⇒ 断言不随真实时钟漂。
现在秒数 = 1_800_000_000.0
八天前秒数 = 现在秒数 - 8 * 收敛件.每天秒数
一小时前秒数 = 现在秒数 - 3600
一天前秒数 = 现在秒数 - 收敛件.每天秒数


def 造假件(路径: Path, 修改秒数: float, 字节数: int = 16) -> None:
    """造一份假件并把 mtime 定到指定时刻（`os.utime` 是唯一能钉 mtime 的口）。"""
    路径.write_bytes(b"x" * 字节数)
    设时刻(路径, 修改秒数)


def 设时刻(路径: Path, 修改秒数: float) -> None:
    """把一个已存在的件/目录的 mtime 钉到指定时刻（**目录也要钉**：目录的 mtime 是它自身的
    最后改动时刻，只钉里面那份件的话，目录看起来仍是最新造的）。"""
    os.utime(路径, (修改秒数, 修改秒数))


def 作业日志名(序号: int, 档名后缀: str = ".log") -> str:
    """32 位十六进制作业号 + 后缀（与 `作业账本.日志路径` 的形状一致）。"""
    return ("%032x" % 序号) + 档名后缀


def 反证日志(工作目录: Path) -> list:
    """日志组：两条界各逼一次 ⇒ 断言表 `[(断言名, 通过, 读数)]`。"""
    断言表 = []
    # ── 情形按龄：年龄界 + 份数界同时成立（400 份：120 份 8 天前、280 份 7 天内）──
    按龄日志根 = 工作目录 / "日志-按龄"
    按龄日志根.mkdir()
    for 序号 in range(120):
        造假件(按龄日志根 / 作业日志名(序号), 八天前秒数 - 序号, 64)
    for 序号 in range(280):
        造假件(按龄日志根 / 作业日志名(1000 + 序号, ".工作.log" if 序号 % 2 else ".log"),
                现在秒数 - 序号 * 60, 64)
    # 非作业日志：名字不匹配作业日志族 ⇒ 一份都不许动（老也是它的正常状态）。
    for 名字 in ("MCP诊断.log", "MCP服务_http.日志.txt", "钩子拦截.jsonl"):
        造假件(按龄日志根 / 名字, 八天前秒数, 32)
    按龄读数 = 收敛件.收敛日志(日志根=按龄日志根, 当前时刻=现在秒数)
    按龄剩表 = sorted(按龄日志根.iterdir())
    按龄作业表 = [项值 for 项值 in 按龄剩表 if 收敛件.作业日志名模式.match(项值.name)]
    剩非作业表 = [项值 for 项值 in 按龄剩表 if not 收敛件.作业日志名模式.match(项值.name)]
    旧作业仍在 = [项值.name for 项值 in 按龄作业表
                if 项值.stat().st_mtime < 现在秒数 - 收敛件.日志保留天数 * 收敛件.每天秒数]
    断言表.append(("8 天前的作业日志一份不剩", not 旧作业仍在, "残留 %d 份 %s" % (
        len(旧作业仍在), 旧作业仍在[:3])))
    断言表.append(("7 天内的作业日志全留（280 份）", len(按龄作业表) == 280,
                "剩 %d 份（删除 %d 份）" % (len(按龄作业表), 按龄读数["删除份数"])))
    断言表.append(("总数 ≤ 300 份", len(按龄作业表) <= 收敛件.日志份数上限,
                "剩 %d 份 ≤ 上限 %d" % (len(按龄作业表), 收敛件.日志份数上限)))
    断言表.append(("非作业日志（诊断/服务/钩子）一份不少", len(剩非作业表) == 3,
                "剩 %d 份：%s" % (len(剩非作业表), [项值.name for 项值 in 剩非作业表])))

    # ── 情形按份：只按年龄删完仍超界 ⇒ 按 mtime 最旧优先截到上限，且截掉的确实是最旧那批 ──
    按份日志根 = 工作目录 / "日志-按份"
    按份日志根.mkdir()
    for 序号 in range(60):
        造假件(按份日志根 / 作业日志名(5000 + 序号), 八天前秒数 - 序号, 64)
    新件秒数表 = []
    for 序号 in range(350):
        修改秒数 = 一小时前秒数 - 序号 * 10
        新件秒数表.append(修改秒数)
        造假件(按份日志根 / 作业日志名(6000 + 序号), 修改秒数, 64)
    按份读数 = 收敛件.收敛日志(日志根=按份日志根, 当前时刻=现在秒数)
    按份剩表 = [项值 for 项值 in 按份日志根.iterdir() if 收敛件.作业日志名模式.match(项值.name)]
    剩秒数表 = sorted(项值.stat().st_mtime for 项值 in 按份剩表)
    应删数 = 350 - 收敛件.日志份数上限
    最旧该留 = sorted(新件秒数表)[应删数]
    断言表.append(("年龄界删完仍超界 ⇒ 恰好截到 300 份", len(按份剩表) == 收敛件.日志份数上限,
                "410 份 ⇒ 剩 %d 份（删除 %d 份）" % (len(按份剩表), 按份读数["删除份数"])))
    断言表.append(("截掉的是最旧那 %d 份" % 应删数,
                bool(剩秒数表) and 剩秒数表[0] == 最旧该留,
                "剩件里最旧 = %.0f · 该留的最旧 = %.0f" % (
                    (剩秒数表[0] if 剩秒数表 else 0), 最旧该留)))
    return 断言表


def 反证临时件(工作目录: Path) -> list:
    """临时件组：按次产物旧的清、新的留；**证据与认不出的名字一个都不删**；白名单一动不动。

    这一组的红样本就是「只凭 mtime 一锅端」：`临时件/` 里的反馈源快照、回执、审计稿与活作业
    目录都在这里，删了就不可恢复 ⇒ 收敛只清认得出形状的按次产物。
    """
    临时根 = 工作目录 / "临时件"
    临时根.mkdir()
    可删前缀 = 收敛件.临时件可删前缀
    旧目录表 = []
    for 序号 in range(10):
        新建目录 = 临时根 / ("%s旧%d" % (可删前缀[序号 % len(可删前缀)], 序号))
        新建目录.mkdir()
        造假件(新建目录 / "读数.txt", 八天前秒数)
        设时刻(新建目录, 八天前秒数)
        旧目录表.append(新建目录)
    新目录表 = []
    for 序号 in range(2):
        新建目录 = 临时根 / ("%s新%d" % (可删前缀[0], 序号))
        新建目录.mkdir()
        造假件(新建目录 / "读数.txt", 一天前秒数)
        设时刻(新建目录, 一天前秒数)
        新目录表.append(新建目录)
    旧文件表 = []
    for 序号 in range(2):
        旧件 = 临时根 / ("%s旧件%d.json" % (可删前缀[0], 序号))
        造假件(旧件, 八天前秒数)
        旧文件表.append(旧件)
    新文件表 = []
    for 序号 in range(2):
        新件 = 临时根 / ("%s新件%d.json" % (可删前缀[1], 序号))
        造假件(新件, 一天前秒数)
        新文件表.append(新件)
    # 证据：目录自身 mtime 很旧，但里面今天还写过 ⇒ 按子树最晚 mtime 判 ⇒ 必须留。
    证据目录 = 临时根 / "反馈源正文"
    证据目录.mkdir()
    造假件(证据目录 / "很旧的.txt", 八天前秒数)
    造假件(证据目录 / "今天写的.txt", 一天前秒数)
    设时刻(证据目录, 八天前秒数)
    # 认不出名字的旧目录：可能是别的工具生成的按次目录，也可能是活作业现场 ⇒ 一律不删。
    不明目录 = 临时根 / "探针-不明来历"
    不明目录.mkdir()
    造假件(不明目录 / "读数.txt", 八天前秒数)
    设时刻(不明目录, 八天前秒数)
    # 白名单那两条活路径：内容与 mtime 都做成「很旧」，仍必须一动不动。
    白名单件表 = []
    for 名字 in 收敛件.临时件白名单:
        新建目录 = 临时根 / 名字
        新建目录.mkdir()
        造假件(新建目录 / "活件.txt", 八天前秒数)
        设时刻(新建目录, 八天前秒数)
        白名单件表.append(新建目录)
    读数 = 收敛件.收敛临时件(临时件根=临时根, 当前时刻=现在秒数)
    旧目录仍在 = [项值.name for 项值 in 旧目录表 if 项值.is_dir()]
    新目录仍在 = [项值.name for 项值 in 新目录表 if 项值.is_dir()]
    旧件仍在 = [项值.name for 项值 in 旧文件表 if 项值.is_file()]
    新件仍在 = [项值.name for 项值 in 新文件表 if 项值.is_file()]
    证据还在 = 证据目录.is_dir() and (证据目录 / "今天写的.txt").is_file()
    不明还在 = 不明目录.is_dir() and (不明目录 / "读数.txt").is_file()
    未匹配列了 = "探针-不明来历" in 读数.get("未匹配保留", [])
    白名单都还在 = all(新建目录.is_dir() and (新建目录 / "活件.txt").is_file() for 新建目录 in 白名单件表)
    return [
        ("8 天前的按次产物（子目录）全清", not 旧目录仍在, "残留 %s" % 旧目录仍在),
        ("1 天前的按次产物（子目录）全留", len(新目录仍在) == 2, "剩 %s" % 新目录仍在),
        ("8 天前的按次产物（件）全清", not 旧件仍在, "残留 %s" % 旧件仍在),
        ("1 天前的按次产物（件）全留", len(新件仍在) == 2, "剩 %s" % 新件仍在),
        ("证据目录里有今天的件 ⇒ 不动（不许只看目录 mtime）", 证据还在,
         "证据目录在 %s · 今天写的件在 %s" % (证据目录.is_dir(), (证据目录 / "今天写的.txt").is_file())),
        ("认不出名字的旧目录不删，并列进未匹配保留", 不明还在 and 未匹配列了,
         "目录在 %s · 未匹配保留 %s" % (不明还在, 读数.get("未匹配保留"))),
        ("白名单两条活路径不动（连里面的件都在）", 白名单都还在,
         "白名单保留 %s · 删 %d 项 · 留 %d 项" % (读数["白名单保留"], 读数["删除项数"], 读数["保留项数"])),
    ]


def 反证守护壳(工作目录: Path) -> list:
    """守护壳组：真跑那份壳（只 source 定义、不进保活循环）⇒ 断言 5 MB 轮转那一条。"""
    脚本 = 仓根 / "构建装配" / "上线切换" / "网关守护.sh"
    断言表 = []
    语法 = subprocess.run(["sh", "-n", str(脚本)], capture_output=True, text=True, timeout=10)
    断言表.append(("`sh -n` 语法检查", 语法.returncode == 0,
                "退出码 %d · %s" % (语法.returncode, 语法.stderr.strip()[:200])))
    环境 = dict(os.environ, V1_守护自检="1")
    # 只 source 定义（`V1_守护自检=1` 让壳跳过 `guard` 保活循环）再单独调轮转函数。
    调用形状 = 'V1_守护自检=1; . "$0"; rotate_log "$1"'
    小日志 = 工作目录 / "小.log"
    小日志.write_bytes(b"y" * (1024 * 1024))
    小跑 = subprocess.run(["sh", "-c", 调用形状, str(脚本), str(小日志)],
                        capture_output=True, text=True, timeout=10, env=环境)
    断言表.append(("1 MB 的小日志不轮转", 小日志.is_file() and not Path(str(小日志) + ".1").exists(),
                "退出码 %d · 原件在 %s · .1 在 %s" % (
                    小跑.returncode, 小日志.is_file(), Path(str(小日志) + ".1").exists())))
    大日志 = 工作目录 / "大.log"
    大日志.write_bytes(b"z" * (6 * 1024 * 1024))
    大跑 = subprocess.run(["sh", "-c", 调用形状, str(脚本), str(大日志)],
                        capture_output=True, text=True, timeout=10, env=环境)
    旧份 = Path(str(大日志) + ".1")
    断言表.append(("6 MB 的大日志轮转成 .1（原件让位）",
                旧份.is_file() and not 大日志.exists()
                and 旧份.stat().st_size == 6 * 1024 * 1024,
                "退出码 %d · .1 在 %s · .1 字节 %d · 原件还在 %s" % (
                    大跑.returncode, 旧份.is_file(),
                   (旧份.stat().st_size if 旧份.is_file() else 0), 大日志.exists())))
    # 再超界一次：只保留一份 `.1`（覆盖，不堆成 `.2`）。
    大日志.write_bytes(b"w" * (6 * 1024 * 1024))
    再跑 = subprocess.run(["sh", "-c", 调用形状, str(脚本), str(大日志)],
                        capture_output=True, text=True, timeout=10, env=环境)
    断言表.append(("再超界只覆盖 .1（不堆成 .2）",
                旧份.is_file() and not Path(str(大日志) + ".2").exists(),
                "退出码 %d · .1 字节 %d · .2 在 %s" % (
                    再跑.returncode, (旧份.stat().st_size if 旧份.is_file() else 0),
                    Path(str(大日志) + ".2").exists())))
    return 断言表


def 反证单件日志(工作目录: Path) -> list:
    """单件日志组：轮到界才动 ⇒ 小件不动、大件「抄 `.1` + 活动件截 0」、再超界只覆盖 `.1`。

    ★ 本组最后两条是**真写者**样本（不是只看 `.1` 在不在）：
      · `MCP服务_http.日志.txt` 的真写者是**继承 stdout 的子进程**（`服务管理.py::启动服务` 把父
        进程开的句柄递给常驻服务）⇒ 这里就照这个形状起一个真子进程；
      · `MCP诊断.log` 的真写者是**每条一次 `os.open(O_APPEND)`**（`诊断记录.py::记诊断`）。
    轮转前后各写一段，断言「轮转后的字节落**活动件**、`.1` 不再增长」——`os.replace` 那一版会在
    这里红：子进程的 stdout 仍指旧 inode，字节继续进 `.1`，活动件永远 0 字节。
    """
    日志根 = 工作目录 / "日志-单件"
    日志根.mkdir()
    小件 = 日志根 / "MCP诊断.log"
    小件.write_bytes(b"x" * (1024 * 1024))
    大件 = 日志根 / "MCP服务_http.日志.txt"
    大件.write_bytes(b"y" * (6 * 1024 * 1024))
    读数 = 收敛件.收敛单件日志(日志根=日志根)
    断言表 = [
        ("1 MB 的 MCP诊断.log 不轮转",
         小件.is_file() and not Path(str(小件) + ".1").exists(),
         "原件在 %s · .1 在 %s · 未到界 %s" % (
             小件.is_file(), Path(str(小件) + ".1").exists(), 读数["未到界"])),
        ("6 MB 的 MCP服务_http.日志.txt 抄成 .1 且活动件截回 0（不换 inode）",
         Path(str(大件) + ".1").is_file() and 大件.exists() and 大件.stat().st_size == 0
         and Path(str(大件) + ".1").stat().st_size == 6 * 1024 * 1024,
         "轮转项 %s" % (读数["轮转项"],)),
    ]
    # 再超界一次：只留一份 `.1`（覆盖，不堆成 `.2`）。
    大件.write_bytes(b"z" * (6 * 1024 * 1024))
    再读数 = 收敛件.收敛单件日志(日志根=日志根)
    断言表.append(("再超界只覆盖 .1（不堆成 .2）",
                  Path(str(大件) + ".1").is_file() and not Path(str(大件) + ".2").exists(),
                  "轮转项 %s" % (再读数["轮转项"],)))
    断言表.extend(反证真写者(日志根))
    return 断言表


# 子进程样本：照 `服务管理.py::启动服务` 的形状 —— 该子进程的 stdout 就是那份日志（继承句柄），
# 写一段、等父进程发信号、再写一段。父子之间用 stdin 一行当同步信号（不睡眠凑时序）。
子进程脚本 = (
    "import sys\n"
    "sys.stdout.write('轮转前一段\\n')\n"
    "sys.stdout.flush()\n"
    "sys.stdin.readline()\n"
    "sys.stdout.write('轮转后一段\\n')\n"
    "sys.stdout.flush()\n"
)


def 反证真写者(日志根: Path) -> list:
    """两件各自的**真写者形态**：轮转之后写者继续写活动件，且活动件仍有界。"""
    断言表 = []
    前段 = "轮转前一段".encode("utf-8")
    后段 = "轮转后一段".encode("utf-8")
    # ── ① 服务日志：继承 stdout 的常驻子进程 ──
    服务件 = 日志根 / "MCP服务_http.日志.txt"
    服务件.write_bytes(b"P" * (6 * 1024 * 1024))          # 造到界（> 5 MB）
    句柄 = open(服务件, "ab")
    try:
        子进程 = subprocess.Popen([sys.executable, "-c", 子进程脚本], stdin=subprocess.PIPE,
                              stdout=句柄, stderr=subprocess.STDOUT, text=True)
    finally:
        句柄.close()          # 父进程关掉父侧副本：子进程继承的那份仍开着（真写者形态）
    # 第一段写完后轮转（子进程会在写第二段之前停住等信号）。
    for _ in range(200):
        if 前段 in 服务件.read_bytes():
            break
        time.sleep(0.01)
    轮转读数 = 收敛件.收敛单件日志(日志根=日志根)
    子进程.stdin.write("go\n")
    子进程.stdin.flush()
    服务码 = 子进程.wait(timeout=5)
    活动字节 = 服务件.read_bytes() if 服务件.is_file() else b""
    备份字节 = Path(str(服务件) + ".1").read_bytes() if Path(str(服务件) + ".1").is_file() else b""
    断言表.append((
        "继承 stdout 的写者：轮转后仍写活动件，.1 不再增长",
        服务码 == 0 and 后段 in 活动字节 and 后段 not in 备份字节
        and 前段 in 备份字节,
        "子进程退出码 %s · 活动件 %d 字节 · .1 %d 字节 · 轮转 %s" % (
            服务码, len(活动字节), len(备份字节), 轮转读数["轮转项"]),
    ))
    # ── ② 诊断日志：每条一次 os.open(O_APPEND) 的真写者 ──
    诊断件 = 日志根 / "MCP诊断.log"
    诊断件.write_bytes(b"D" * (6 * 1024 * 1024))

    def 追加一条(日志字节: bytes) -> None:
        句柄 = os.open(str(诊断件), os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
        try:
            os.write(句柄, 日志字节)
        finally:
            os.close(句柄)

    追加一条(前段 + b"\n")
    再轮转读数 = 收敛件.收敛单件日志(日志根=日志根)
    追加一条(后段 + b"\n")
    活动字节 = 诊断件.read_bytes() if 诊断件.is_file() else b""
    备份字节 = Path(str(诊断件) + ".1").read_bytes() if Path(str(诊断件) + ".1").is_file() else b""
    断言表.append((
        "逐次 open 追加的写者：轮转后写活动件，活动件有界",
        活动字节 == 后段 + b"\n" and 前段 in 备份字节
        and len(活动字节) < 收敛件.单件日志字节上限,
        "活动件 %d 字节 · .1 %d 字节 · 轮转 %s" % (
            len(活动字节), len(备份字节), 再轮转读数["轮转项"]),
    ))
    return 断言表


def 跑全部组(保留目录: bool = False) -> list:
    """五组里本件负责的四组各跑一遍 ⇒ `[(组名, 断言名, 通过, 读数)]`。临时目录收尾即删。"""
    工作目录 = Path(tempfile.mkdtemp(prefix="收敛反证-"))
    结果表 = []
    try:
        for 组名, 样本函数 in (
            ("日志", 反证日志),
            ("临时件", 反证临时件),
            ("守护壳", 反证守护壳),
            ("单件日志", 反证单件日志),
        ):
            子目录 = 工作目录 / 组名
            子目录.mkdir()
            for 断言名, 通过, 读数 in 样本函数(子目录):
                结果表.append((组名, 断言名, 通过, 读数))
    finally:
        if not 保留目录:
            shutil.rmtree(工作目录, ignore_errors=True)
    return 结果表
