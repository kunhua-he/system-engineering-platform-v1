# -*- coding: utf-8 -*-
"""运行数据收敛的四组反证 —— **造脏 → 触发 → 核收敛**，全部在临时目录里做（不碰主仓运行根）。

# 为什么要写成脚本

手工做过一次不算证据：下一个改动把界调没了，没人会再手工造 400 份假日志。本件把四组反证做成
可重跑的样本（`跑反证.py` 是入口），每条断言都带读数 —— 红了当场能看出「哪条界没生效」。

# 四组

| 组 | 造什么脏 | 断言什么 |
|---|---|---|
| 日志 | 400 份假作业日志（mtime 分散，含 8 天前）+ 3 份非作业日志 | 8 天前的全没 · 7 天内的留 · 总数 ≤ 300 · 非作业日志一份不少 |
| 日志（份数界单独逼） | 350 份 1 小时内 + 60 份 8 天前（410 份） | 只按年龄删完仍超界 ⇒ 按 mtime 最旧优先删到恰好 300 · 删掉的确实是最旧那批 |
| 临时件 | 10 个 8 天前子目录 + 2 个 1 天前子目录 + 2 个 8 天前文件 + 2 个 1 天前文件 + 两个白名单同名目录（也做成 8 天前） | 旧子目录/旧文件全清 · 新的全留 · `易语言源码` 与 `上线切换` 一动不动（连里面的件都在） |
| 守护壳 | 1 MB 小日志（不该轮转）· 6 MB 大日志（该轮转）· 轮转后再超界（`.1` 只留一份） | `sh -n` 过 · 小件不轮转 · 大件 `mv` 成 `.1` 且大小不变 · 再轮转只覆盖 `.1` |

**回执那一组不归本件**：轮转实现在 `测试验证/测试案例/跑案例/src/回执.rs::收敛回执`，它的反证是
那条 crate 的单元测试（`cargo test -p v1-case-runner 收敛回执`）；本件只在读数里点明这一点，
不在这里用 Python 重写一遍轮转（同一件事两套实现 = 假绿来源）。
"""

import importlib.util
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

仓根 = Path(__file__).resolve().parents[2]
if str(仓根 / "开发工具") not in sys.path:
    sys.path.insert(0, str(仓根 / "开发工具"))

模块路径 = 仓根 / "开发工具" / "MCP服务" / "运行数据收敛.py"
规格值 = importlib.util.spec_from_file_location("运行数据收敛反证用", 模块路径)
收敛件 = importlib.util.module_from_spec(规格值)
规格值.loader.exec_module(收敛件)

# 反证持的「现在」：定死一个时刻，样本里所有 mtime 都相对它算 ⇒ 断言不随真实时钟漂。
现在秒数 = 1_800_000_000.0
八天前秒数 = 现在秒数 - 8 * 收敛件.每天秒数
一小时前秒数 = 现在秒数 - 3600
一天前秒数 = 现在秒数 - 收敛件.每天秒数


def 造假件(路径: Path, 修改秒数: float, 字节数: int = 16) -> None:
    """造一份假件并把 mtime 定到指定时刻（`os.utime` 是唯一能钉 mtime 的口）。"""
    路径.write_bytes(b"x" * 字节数)
    设时刻(路径, 修改秒数)


def 设时刻(路径: Path, 修改秒数: float) -> None:
    """把一个已存在的件/目录的 mtime 钉到指定时刻（**目录也要钉**：目录的 mtime 是它自身的
    最后改动时刻，只钉里面那份件的话，目录看起来仍是最新造的）。"""
    os.utime(路径, (修改秒数, 修改秒数))


def 作业日志名(序号: int, 档名后缀: str = ".log") -> str:
    """32 位十六进制作业号 + 后缀（与 `作业账本.日志路径` 的形状一致）。"""
    return ("%032x" % 序号) + 档名后缀


def 反证日志(工作目录: Path) -> list:
    """日志组：两条界各逼一次 ⇒ 断言表 `[(断言名, 通过, 读数)]`。"""
    断言表 = []
    # ── 情形按龄：年龄界 + 份数界同时成立（400 份：120 份 8 天前、280 份 7 天内）──
    按龄日志根 = 工作目录 / "日志-按龄"
    按龄日志根.mkdir()
    for 序号 in range(120):
        造假件(按龄日志根 / 作业日志名(序号), 八天前秒数 - 序号, 64)
    for 序号 in range(280):
        造假件(按龄日志根 / 作业日志名(1000 + 序号, ".工作.log" if 序号 % 2 else ".log"),
                现在秒数 - 序号 * 60, 64)
    # 非作业日志：名字不匹配作业日志族 ⇒ 一份都不许动（老也是它的正常状态）。
    for 名字 in ("MCP诊断.log", "MCP服务_http.日志.txt", "钩子拦截.jsonl"):
        造假件(按龄日志根 / 名字, 八天前秒数, 32)
    按龄读数 = 收敛件.收敛日志(日志根=按龄日志根, 当前时刻=现在秒数)
    按龄剩表 = sorted(按龄日志根.iterdir())
    按龄作业表 = [项值 for 项值 in 按龄剩表 if 收敛件.作业日志名模式.match(项值.name)]
    剩非作业表 = [项值 for 项值 in 按龄剩表 if not 收敛件.作业日志名模式.match(项值.name)]
    旧作业仍在 = [项值.name for 项值 in 按龄作业表
                if 项值.stat().st_mtime < 现在秒数 - 收敛件.日志保留天数 * 收敛件.每天秒数]
    断言表.append(("8 天前的作业日志一份不剩", not 旧作业仍在, "残留 %d 份 %s" % (
        len(旧作业仍在), 旧作业仍在[:3])))
    断言表.append(("7 天内的作业日志全留（280 份）", len(按龄作业表) == 280,
                "剩 %d 份（删除 %d 份）" % (len(按龄作业表), 按龄读数["删除份数"])))
    断言表.append(("总数 ≤ 300 份", len(按龄作业表) <= 收敛件.日志份数上限,
                "剩 %d 份 ≤ 上限 %d" % (len(按龄作业表), 收敛件.日志份数上限)))
    断言表.append(("非作业日志（诊断/服务/钩子）一份不少", len(剩非作业表) == 3,
                "剩 %d 份：%s" % (len(剩非作业表), [项值.name for 项值 in 剩非作业表])))

    # ── 情形按份：只按年龄删完仍超界 ⇒ 按 mtime 最旧优先截到上限，且截掉的确实是最旧那批 ──
    按份日志根 = 工作目录 / "日志-按份"
    按份日志根.mkdir()
    for 序号 in range(60):
        造假件(按份日志根 / 作业日志名(5000 + 序号), 八天前秒数 - 序号, 64)
    新件秒数表 = []
    for 序号 in range(350):
        修改秒数 = 一小时前秒数 - 序号 * 10
        新件秒数表.append(修改秒数)
        造假件(按份日志根 / 作业日志名(6000 + 序号), 修改秒数, 64)
    按份读数 = 收敛件.收敛日志(日志根=按份日志根, 当前时刻=现在秒数)
    按份剩表 = [项值 for 项值 in 按份日志根.iterdir() if 收敛件.作业日志名模式.match(项值.name)]
    剩秒数表 = sorted(项值.stat().st_mtime for 项值 in 按份剩表)
    应删数 = 350 - 收敛件.日志份数上限
    最旧该留 = sorted(新件秒数表)[应删数]
    断言表.append(("年龄界删完仍超界 ⇒ 恰好截到 300 份", len(按份剩表) == 收敛件.日志份数上限,
                "410 份 ⇒ 剩 %d 份（删除 %d 份）" % (len(按份剩表), 按份读数["删除份数"])))
    断言表.append(("截掉的是最旧那 %d 份" % 应删数,
                bool(剩秒数表) and 剩秒数表[0] == 最旧该留,
                "剩件里最旧 = %.0f · 该留的最旧 = %.0f" % (
                    (剩秒数表[0] if 剩秒数表 else 0), 最旧该留)))
    return 断言表


def 反证临时件(工作目录: Path) -> list:
    """临时件组：旧的全清、新的全留、两个白名单活路径一动不动。"""
    临时根 = 工作目录 / "临时件"
    临时根.mkdir()
    for 序号 in range(10):
        新建目录 = 临时根 / ("发布验收_旧%d" % 序号)
        新建目录.mkdir()
        造假件(新建目录 / "读数.txt", 八天前秒数)
        设时刻(新建目录, 八天前秒数)
    for 序号 in range(2):
        新建目录 = 临时根 / ("跨进程验收-新%d" % 序号)
        新建目录.mkdir()
        造假件(新建目录 / "读数.txt", 一天前秒数)
        设时刻(新建目录, 一天前秒数)
    for 序号 in range(2):
        造假件(临时根 / ("旧件%d.md" % 序号), 八天前秒数)
    for 序号 in range(2):
        造假件(临时根 / ("新件%d.md" % 序号), 一天前秒数)
    # 白名单那两条活路径：内容与 mtime 都做成「很旧」，仍必须一动不动。
    白名单件表 = []
    for 名字 in 收敛件.临时件白名单:
        新建目录 = 临时根 / 名字
        新建目录.mkdir()
        造假件(新建目录 / "活件.txt", 八天前秒数)
        设时刻(新建目录, 八天前秒数)
        白名单件表.append(新建目录)
    读数 = 收敛件.收敛临时件(临时件根=临时根, 当前时刻=现在秒数)
    旧目录仍在 = [项值.name for 项值 in 临时根.glob("发布验收_旧*") if 项值.is_dir()]
    新目录仍在 = [项值.name for 项值 in 临时根.glob("跨进程验收-新*") if 项值.is_dir()]
    旧件仍在 = [项值.name for 项值 in 临时根.glob("旧件*.md")]
    新件仍在 = [项值.name for 项值 in 临时根.glob("新件*.md")]
    白名单都还在 = all(新建目录.is_dir() and (新建目录 / "活件.txt").is_file() for 新建目录 in 白名单件表)
    return [
        ("8 天前的子目录全清", not 旧目录仍在, "残留 %s" % 旧目录仍在),
        ("1 天前的子目录全留", len(新目录仍在) == 2, "剩 %s" % 新目录仍在),
        ("8 天前的件全清", not 旧件仍在, "残留 %s" % 旧件仍在),
        ("1 天前的件全留", len(新件仍在) == 2, "剩 %s" % 新件仍在),
        ("白名单两条活路径不动（连里面的件都在）", 白名单都还在,
         "白名单保留 %s · 删 %d 项 · 留 %d 项" % (读数["白名单保留"], 读数["删除项数"], 读数["保留项数"])),
    ]


def 反证守护壳(工作目录: Path) -> list:
    """守护壳组：真跑那份壳（只 source 定义、不进保活循环）⇒ 断言 5 MB 轮转那一条。"""
    脚本 = 仓根 / "构建装配" / "上线切换" / "网关守护.sh"
    断言表 = []
    语法 = subprocess.run(["sh", "-n", str(脚本)], capture_output=True, text=True, timeout=10)
    断言表.append(("`sh -n` 语法检查", 语法.returncode == 0,
                "退出码 %d · %s" % (语法.returncode, 语法.stderr.strip()[:200])))
    环境 = dict(os.environ, V1_守护自检="1")
    # 只 source 定义（`V1_守护自检=1` 让壳跳过 `guard` 保活循环）再单独调轮转函数。
    调用形状 = 'V1_守护自检=1; . "$0"; rotate_log "$1"'
    小日志 = 工作目录 / "小.log"
    小日志.write_bytes(b"y" * (1024 * 1024))
    小跑 = subprocess.run(["sh", "-c", 调用形状, str(脚本), str(小日志)],
                        capture_output=True, text=True, timeout=10, env=环境)
    断言表.append(("1 MB 的小日志不轮转", 小日志.is_file() and not Path(str(小日志) + ".1").exists(),
                "退出码 %d · 原件在 %s · .1 在 %s" % (
                    小跑.returncode, 小日志.is_file(), Path(str(小日志) + ".1").exists())))
    大日志 = 工作目录 / "大.log"
    大日志.write_bytes(b"z" * (6 * 1024 * 1024))
    大跑 = subprocess.run(["sh", "-c", 调用形状, str(脚本), str(大日志)],
                        capture_output=True, text=True, timeout=10, env=环境)
    旧份 = Path(str(大日志) + ".1")
    断言表.append(("6 MB 的大日志轮转成 .1（原件让位）",
                旧份.is_file() and not 大日志.exists()
                and 旧份.stat().st_size == 6 * 1024 * 1024,
                "退出码 %d · .1 在 %s · .1 字节 %d · 原件还在 %s" % (
                    大跑.returncode, 旧份.is_file(),
                   (旧份.stat().st_size if 旧份.is_file() else 0), 大日志.exists())))
    # 再超界一次：只保留一份 `.1`（覆盖，不堆成 `.2`）。
    大日志.write_bytes(b"w" * (6 * 1024 * 1024))
    再跑 = subprocess.run(["sh", "-c", 调用形状, str(脚本), str(大日志)],
                        capture_output=True, text=True, timeout=10, env=环境)
    断言表.append(("再超界只覆盖 .1（不堆成 .2）",
                旧份.is_file() and not Path(str(大日志) + ".2").exists(),
                "退出码 %d · .1 字节 %d · .2 在 %s" % (
                    再跑.returncode, (旧份.stat().st_size if 旧份.is_file() else 0),
                    Path(str(大日志) + ".2").exists())))
    return 断言表


def 跑全部组(保留目录: bool = False) -> list:
    """四组里本件负责的三组各跑一遍 ⇒ `[(组名, 断言名, 通过, 读数)]`。临时目录收尾即删。"""
    工作目录 = Path(tempfile.mkdtemp(prefix="收敛反证-"))
    结果表 = []
    try:
        for 组名, 样本函数 in (("日志", 反证日志), ("临时件", 反证临时件), ("守护壳", 反证守护壳)):
            子目录 = 工作目录 / 组名
            子目录.mkdir()
            for 断言名, 通过, 读数 in 样本函数(子目录):
                结果表.append((组名, 断言名, 通过, 读数))
    finally:
        if not 保留目录:
            shutil.rmtree(工作目录, ignore_errors=True)
    return 结果表
