def 跑自测() -> int:
    """runner 自身的成对样本：① 戳对源变化敏感 ② 坏默认值表八类 ③ 元素表错形四类 ④ 正样本成对。"""
    错误表 = []
    import tempfile

    with tempfile.TemporaryDirectory() as 临时目录:
        临时根 = Path(临时目录)
        (临时根 / "契约声明/src").mkdir(parents=True)
        源件 = 临时根 / 契约源相对路径
        源件.write_text("// 旧内容\n", encoding="utf-8")
        旧指纹 = 契约源指纹(临时根)
        源件.write_text("// 新内容\n", encoding="utf-8")
        if not 旧指纹 or 旧指纹 == 契约源指纹(临时根):
            错误表.append("契约源指纹对源变化不敏感（戳形同虚设）")
        源件.unlink()
        if 契约源指纹(临时根):
            错误表.append("契约源不在时应给空指纹（否则戳会误判新鲜）")

    if len(坏默认值表) != 8:
        错误表.append("坏默认值表不是八类（实测 %d 类）" % len(坏默认值表))
    if len({样本名 for 样本名, _ in 坏默认值表}) != len(坏默认值表):
        错误表.append("坏默认值表里有重名样本（报出来分不清是哪一类）")
    if len(元素表错形表) != 4:
        错误表.append("元素表错形表不是四类（实测 %d 类）" % len(元素表错形表))
    if len(元素表正样本) < 2:
        错误表.append("元素表正样本少于两条（重名过那条是设计取舍，必须成对在）")
    探针断言在 = "中文\\0默认" in 探针正文
    if not 探针断言在:
        错误表.append("探针正文丢了「UTF-8 含空字节」那条断言（那是文本型默认值的真读回）")

    if 错误表:
        print("✗ runner 自测红：" + "；".join(错误表))
        return 1
    print("✓ runner 自测：戳对源变化敏感 · 八类坏默认值齐 · 四类元素表错形齐 · 正样本成对 · 探针断言在")
    return 0
