def 真编译(根目录: Path) -> tuple:
    """编探针（真读回的载体）⇒ `(问题表, 探针可执行件)`。契约 rlib 由环境步备好。"""
    问题表 = []
    戳内容 = 读戳(根目录)
    契约产物 = 缓存根(根目录) / str(戳内容.get("契约产物") or 契约产物名)
    if not 戳内容 or not 契约产物.is_file():
        return ["契约产物缺失：先跑环境步 —— python3 测试验证/单元测试/参数生成考题.py --预编译契约"], None
    if 戳内容.get("源指纹") != 契约源指纹(根目录):
        return ["契约产物与源不符（契约源改过，戳是旧的）：先跑 --预编译契约 刷新"], None
    题根 = 根目录 / 考题根相对
    探针源件 = 题根 / 探针件名
    探针源件.write_text(探针正文, encoding="utf-8")
    执行件 = 题根 / 执行件名
    回执 = subprocess.run(
        ["rustc", "--edition=2024", "--crate-name", "parameter_probe", str(探针源件),
         "--extern", 契约库名 + "=" + str(契约产物), "-o", str(执行件)],
        cwd=str(根目录), capture_output=True, text=True, timeout=编译超时毫秒 / 1000,
    )
    if 回执.returncode != 0:
        问题表.append("探针编不出来（rustc 退出码 %d）：%s" % (回执.returncode, 回执.stderr.strip()[:600]))
        return 问题表, None
    return 问题表, 执行件


def 真读回(执行件: Path) -> list:
    """真跑探针 ⇒ 问题表（空 = 读回全对）。"""
    if 执行件 is None:
        return ["探针可执行件不在（真编译没过）"]
    回执 = subprocess.run([str(执行件)], capture_output=True, text=True, timeout=跑测超时毫秒 / 1000)
    if 回执.returncode != 0:
        return ["探针跑红（退出码 %d）：%s"
                % (回执.returncode, ((回执.stdout or "") + (回执.stderr or "")).strip()[:600])]
    return []


