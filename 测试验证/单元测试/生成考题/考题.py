"""考题 —— `生成声明` 链的真读数：真生成 · 真编译 · 真读回。

**为什么本 runner 存在**：这段断言原先只活在 `构建装配/形态装配/生成声明/参数生成测试.py`
（unittest 孤儿，全仓无人 import）⇒ 「写了没人跑」，是假绿的结构性来源。它不能搬进闸 1：
整条链真跑一次 ~3.3 s（生成器 1.8 s · rustc 编契约 0.9 s · 编探针并跑 0.5 s），
而闸 1 全量已在 4.4–5.4 s（效率目标 5 s）⇒ 搬进去会把闸 1 顶穿。故做成独立 runner：
与闸 1 的判据 64（零成本静态面）分工 —— 判据 64 守「同一份真产物上的逐项断言」，
本 runner 守「真编真跑那段」。

**两档照 `测试验证/准入判据/长活原语.py` 的形状**：
  · 环境步（`--预编译契约`）—— 编契约 crate 成 rlib + 写源指纹戳，不碰生成物；
  · 命令体 —— 真生成（生成器 + `--检查`）· 真编译（探针 + 契约 rlib）· 真读回（跑探针）。
产物缺失 / 与源不符 ⇒ fail-closed 指路，不静默降级。

**考题根**：拷一份真声明的**字节副本**进仓内缓存根（生成器只认仓内相对路径 ——
绝对路径会让产物带上机器相关前缀，故 fail-closed），再往里写样本参数表。
只动副本，**不碰仓里任何真声明件**。
"""

