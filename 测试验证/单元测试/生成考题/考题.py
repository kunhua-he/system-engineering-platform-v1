def 真生成(根目录: Path) -> tuple:
    """真生成 + `--检查` + 八类坏默认值反向样本 + 元素表正反向样本 ⇒ `(问题表, 题根)`。"""
    问题表 = []
    题根 = 建考题根(根目录)
    声明内容 = 写参数表(题根)
    能力源 = 题根 / "能力声明/1101.json"

    退出码, 输出文本 = 跑生成器(根目录)
    if 退出码 != 0:
        return ["真生成没过（退出码 %d）：%s" % (退出码, 输出文本[:600])], 题根
    退出码, 输出文本 = 跑生成器(根目录, 检查=True)
    if 退出码 != 0:
        问题表.append("真生成的 `--检查` 没过（退出码 %d）：%s" % (退出码, 输出文本[:600]))

    for 样本名, 坏默认值 in 坏默认值表:
        坏声明 = json.loads(json.dumps(声明内容))
        坏声明["参数表"][0]["默认值"] = 坏默认值
        能力源.write_text(json.dumps(坏声明, ensure_ascii=True), encoding="utf-8")
        退出码, _ = 跑生成器(根目录)
        if 退出码 != 2:
            问题表.append("坏默认值样本「%s」没被拒（生成器退出码 %d，该 2）" % (样本名, 退出码))
    能力源.write_text(json.dumps(声明内容, ensure_ascii=False), encoding="utf-8")

    类型文件 = 题根 / 类型文件相对
    类型内容 = json.loads(类型文件.read_text(encoding="utf-8"))
    for 样本名, 元素表 in 元素表正样本:
        类型内容["元素表"] = 元素表
        类型文件.write_text(json.dumps(类型内容, ensure_ascii=False), encoding="utf-8")
        退出码, 输出文本 = 跑生成器(根目录)
        if 退出码 != 0:
            问题表.append("元素表正样本「%s」被误拒（退出码 %d）：%s" % (样本名, 退出码, 输出文本[:400]))
    for 样本名, 元素表 in 元素表错形表:
        类型内容["元素表"] = 元素表
        类型文件.write_text(json.dumps(类型内容, ensure_ascii=True), encoding="utf-8")
        退出码, 输出文本 = 跑生成器(根目录)
        if 退出码 != 2 or "元素表" not in 输出文本:
            问题表.append("元素表错形「%s」没被拒或没定位（退出码 %d）：%s"
                          % (样本名, 退出码, 输出文本[:400]))
    类型内容["元素表"] = []
    类型文件.write_text(json.dumps(类型内容, ensure_ascii=False), encoding="utf-8")
    退出码, 输出文本 = 跑生成器(根目录)
    if 退出码 != 0:
        问题表.append("空元素表被误拒（退出码 %d，原行为是过）：%s" % (退出码, 输出文本[:400]))
    return 问题表, 题根


def 跑参数生成考题(根目录: Path) -> int:
    """命令体：真生成 → 真编译 → 真读回，逐段落打读数。"""
    段落表 = []
