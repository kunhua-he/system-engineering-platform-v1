def 建考题根(根目录: Path) -> Path:
    """把真声明拷进仓内缓存根 ⇒ 考题根（生成器只认仓内相对路径，故必须住仓内）。"""
    原件根 = 根目录 / 原声明相对
    题根 = 根目录 / 考题根相对
    if 题根.exists():
        shutil.rmtree(题根)
    题根.mkdir(parents=True)
    (题根 / "src").mkdir()
    shutil.copy(原件根 / "包声明.json", 题根 / "包声明.json")
    for 目录名 in ("类型声明", "错误码表"):
        shutil.copytree(原件根 / 目录名, 题根 / 目录名)
    (题根 / "能力声明").mkdir()
    shutil.copy(原件根 / "能力声明/1101.json", 题根 / "能力声明/1101.json")
    return 题根


def 写参数表(题根: Path) -> dict:
    """往考题根的能力声明里写**七类参数种类**（三态 + 各类型载体）⇒ 返回声明内容。"""
    能力源 = 题根 / "能力声明/1101.json"
    声明内容 = json.loads(能力源.read_text(encoding="utf-8"))
    参数种类表 = [
        (文本型标签, None),                                          # 未提供（三态之一）
        (文本型标签, {"类型标签": 空槽标签, "值": 0}),                 # 显式空槽
        (文本型标签, {"类型标签": 文本型标签, "文本": "中文\x00默认\n"}),  # 文本含空字节
        (双精度型标签, {"类型标签": 双精度型标签,
                        "值": struct.unpack("<Q", struct.pack("<d", -1.25))[0]}),
        (整数型标签, {"类型标签": 整数型标签, "值": 18446744073709551615}),
        (逻辑型标签, {"类型标签": 逻辑型标签, "值": 1}),
        (文本型标签, {"类型标签": 文本型标签, "文本": ""}),             # 显式空文本
    ]
    声明内容["参数表"] = []
    for 标签, 默认值 in 参数种类表:
        参数行 = {"名称": "样本参数", "说明": "真实生成样本", "类型标签": 标签, "状态位": 0}
        if 默认值 is not None:
            参数行["默认值"] = 默认值
        声明内容["参数表"].append(参数行)
    能力源.write_text(json.dumps(声明内容, ensure_ascii=False), encoding="utf-8")
    return 声明内容


