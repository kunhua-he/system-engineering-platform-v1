    段落表.append(("真读回", "跑探针：三态/UTF-8含空字节/静态所有权/浮点/整数/逻辑/空文本", 读回问题表))

    print("─" * 78)
    print("生成声明链真读数（参数生成考题 runner · 真生成 · 真编译 · 真读回）")
    总问题数 = 0
    for 标目, 说明, 问题表 in 段落表:
        标记 = "✓" if not 问题表 else "✗"
        print("  %s %s ｜ %s" % (标记, 标目, 说明))
        for 单条问题 in 问题表:
            print("      ✗ %s" % 单条问题)
        总问题数 += len(问题表)
    print("考题根：%s（拷来的字节副本，不碰真声明）" % 考题根相对)
    print("问题 %d 条 · %s" % (总问题数, "全链通过" if 总问题数 == 0 else "有失败"))
    return 0 if 总问题数 == 0 else 1


