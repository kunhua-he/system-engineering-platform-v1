/// 观测一次生命周期通知的派发：把 `派发结果` 翻成「结果 + 说明」。
///
/// 通知步骤走的是适配器的**通知口**（`装载通知` / `请求卸载` / `延迟释放协商`），
/// **不是**能力调用 —— 生命周期通知号（2000/2001/2003）本来就不在能力编号空间里。
/// 早先跑案例只能按能力编号调，这六处（通知通道 · 生命周期 等）根本到不了；
/// 现在案例可以点名要装载的声明（[`crate::装载声明::解析声明名`]）并发真通知。
///
/// `标识串` 是目标声明的 NUL 结尾标识串指针（由调用方从已装载声明里取）。
///
/// 取 `&mut 适配器`：`2001 卸载` / `2003 延迟释放` 是**完整状态转换**（改 `装载单元s` / `台账`）。
pub(crate) fn 观测通知(适配器: &mut 适配器, 案例步骤: &案例步骤, 标识串: *const u8) -> Result<观测, String> {
    let 通知号 = 案例步骤
        .通知号
        .ok_or_else(|| "通知步骤缺 `通知号`（能力步骤不会走到这里）".to_owned())?;
    let 结局 = match 通知号 {
        v1_contract::声明数据::通知号_2000 => 适配器.装载通知(标识串),
        v1_contract::声明数据::通知号_2001 => 适配器.请求卸载(标识串),
        v1_contract::声明数据::通知号_2003 => 适配器.延迟释放协商(标识串),
        其他值 => {
            return Err(format!("通知号 {其他值} 不认（只认 2000 装载 / 2001 卸载 / 2003 延迟释放）"));
        }
    };
    let 结局名 = 派发结果名(&结局);
    // 三种结局不算失败：未命中按宪法第 6 条**不是错误**；请求延迟释放是**允许被拒绝**；
    // 成功自然算成功。只有 `失败`（扩展回了个不认识的结局，fail-closed）算「结果=失败」。
    let (调用结局, 说明) = match 结局 {
        派发结果::失败 => (
            "失败",
            format!("发通知 {通知号}：扩展回了个不认识的结局 ⇒ 派发结果 失败（fail-closed）"),
        ),
        _ => (
            "成功",
            format!("发通知 {通知号}：派发结果 {结局名}（未命中不是错误 · 请求延迟释放是允许被拒绝）"),
        ),
    };
    Ok(观测 {
        调用结局,
        死在哪一层: None,
        死在哪一步: None,
        错误码: None,
        能力名: None,
        产物: 观测产物::派发结果(结局名.clone()),
        派发结果: Some(结局名),
        说明,
    })
}

// ════════════════════════════════════════════════════════════════════════════
// 观测一次**读留痕**：把适配器留痕缓冲里最近 N 条折成读数
// ════════════════════════════════════════════════════════════════════════════

/// 观测一次「读留痕」：读适配器留痕缓冲最近 `读留痕条数` 条，折成「条数 + 首条号 + 首条结果码」。
///
/// 留痕**不进关键路径**（`留痕口.rs` 文件头）：读它不改任何调用结果 —— 它证的是「刚才那次
/// 调用被如实记了一条」。适配器没启用留痕 ⇒ [`适配器::取留痕`] 恒空 ⇒ 首条为 `None`，
/// 判定侧当场报红（不是静默通过）。
pub(crate) fn 观测留痕(适配器: &适配器, 案例步骤: &案例步骤) -> Result<观测, String> {
    let 留痕条数 = 案例步骤
        .读留痕条数
        .ok_or_else(|| "读留痕步骤缺 `读留痕` 条数（能力/通知步骤不会走到这里）".to_owned())?;
    let 记录表 = 适配器.取留痕(留痕条数);
    let 首条 = 记录表.first();
    let 说明 = match 首条 {
        Some(留痕项) => format!(
            "读留痕 {留痕条数} 条：实到 {} 条 · 首条能力号 {} · 首条结果码 {}",
            记录表.len(),
            留痕项.能力号.取号值(),
            留痕项.结果码
        ),
        None => format!("读留痕 {留痕条数} 条：实到 0 条（适配器没启用留痕，或这段时间没有调用）"),
    };
    Ok(观测 {
        调用结局: "成功",
        死在哪一层: None,
        死在哪一步: None,
        错误码: None,
        能力名: None,
        产物: 观测产物::留痕读数 {
            留痕条数: 记录表.len(),
            首条能力号: 首条.map(|留痕项| 留痕项.能力号.取号值()),
            首条结果码: 首条.map(|留痕项| 留痕项.结果码),
        },
        派发结果: None,
        说明,
    })
}

/// `派发结果` 的变体名（逐字取 `运行内核/通知通道/src/形状.rs` 的枚举）。
fn 派发结果名(结局: &派发结果) -> String {
    match 结局 {
        派发结果::成功 => "成功",
        派发结果::失败 => "失败",
        派发结果::请求延迟释放 => "请求延迟释放",
        派发结果::未命中 => "未命中",
    }
    .to_owned()
}

