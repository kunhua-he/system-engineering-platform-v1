//! 观测：把一次调用翻成「层 + 层内位置 + 错误码 + 产物」，并把案例写的实参解成定长槽。
//!
//! **本件不实现装载，也不实现调用**：装载只有 `适配器::装载`，调用只有 `适配器::调用能力`。
//! 这里只做两件它不做的：**读返回槽**（把结果翻成可判的形状）与**解实参**（案例 → 槽）。
//!
//! 定层的两个事实源见 `错误码.rs` 的文件头。这里只补一句：
//! **失败时的返回槽也要当场读**——宪法第 6 条「未命中返回空」不是嘴上说的，
//! 读出来的才是读数。

use v1_adapter::{适配器, 转发结果, 数据槽, 调度错误};
use v1_contract::声明数据::类型标签_4294967295;

use crate::案例::{self as 案例件, 实参来源, 步骤, 案例};
use crate::错误码::{登记, 登记表, 段位到层};

// ════════════════════════════════════════════════════════════════════════════
// 观测：把一次调用的结果翻成「层 + 层内位置 + 错误码 + 产物」
// ════════════════════════════════════════════════════════════════════════════

/// 返回槽里的产物（**封闭枚举**，只认契约里有的那几种形状）。
pub(crate) enum 观测产物 {
    空槽,
    字节集(Vec<u8>),
    错误槽(u32),
    其他,
}

pub(crate) struct 观测 {
    pub(crate) 结果: &'static str,
    pub(crate) 死在哪一层: Option<String>,
    pub(crate) 死在哪一步: Option<String>,
    pub(crate) 错误码: Option<登记>,
    pub(crate) 能力名: Option<String>,
    pub(crate) 产物: 观测产物,
    pub(crate) 说明: String,
}

pub(crate) fn 观测一步(
    适配器: &适配器,
    登记表: &登记表,
    一条: &案例,
    步骤: &步骤,
    上一步返回: &Option<Vec<u8>>,
) -> Result<观测, String> {
    let 契 = 适配器.能力契约(步骤.能力编号);
    let 能力名 = 契.as_ref().map(|契| 契.名称.clone());

    // 案例文件形状自检（fail-closed）：实参个数与每行类型标签必须与契约对得上。
    // 对不上是**案例自身写坏了**（工具错误），不是被测对象的缺陷 —— 不许把假红留给平台。
    if let Some(契) = &契 {
        if 契.参数表.len() != 步骤.实参.len() {
            return Err(format!(
                "案例 `{}` 步骤 `{}`：实参个数 {} 与契约的参数表行数 {} 不符",
                一条.名,
                步骤.名,
                步骤.实参.len(),
                契.参数表.len()
            ));
        }
        for (位, (参, 行)) in 步骤.实参.iter().zip(契.参数表.iter()).enumerate() {
            if 参.类型标签 != 行.类型标签 {
                return Err(format!(
                    "案例 `{}` 步骤 `{}`：实参[{位}] 类型标签 {} 与契约行 `{}` 的类型标签 {} 不符",
                    一条.名, 步骤.名, 参.类型标签, 行.名称, 行.类型标签
                ));
            }
        }
    }

    let (参, 缓冲) = 解实参(一条, 步骤, 上一步返回)?;
    let mut 返回槽 = 数据槽::空槽();
    let 转 = 适配器.调用能力(步骤.能力编号, &参, &mut 返回槽);
    // 入参缓冲只在这次调用期间要活着；槽里的指针已不再被读。
    drop(缓冲);
    Ok(match 转 {
        // 失败时也读返回槽：宪法第 6 条「未命中返回空」**要当场看到**，
        // 不是嘴上说「调度层会置空」。读出来的才是读数。
        转发结果::失败(错) => 由调度错误(登记表, 能力名, 契.is_some(), 错, &返回槽),
        转发结果::成功(槽) => 由返回槽(登记表, 能力名, 槽),
    })
}

/// 返回槽 → 产物。**三种形状照契约认**（错误标签 / 空 / 引用），其余如实记「其他」。
fn 槽产物(数据槽: &数据槽) -> 观测产物 {
    if 数据槽.类型标签 == 类型标签_4294967295 {
        return 观测产物::错误槽(u32::try_from(数据槽.值).unwrap_or(u32::MAX));
    }
    if 数据槽.是否空() {
        return 观测产物::空槽;
    }
    if 数据槽.是否引用() && 数据槽.值 != 0 {
        // SAFETY: 引用槽按契约带指针与字节长度。
        let 片 =
            unsafe { core::slice::from_raw_parts(数据槽.值 as *const u8, usize::try_from(数据槽.长度).unwrap_or(0)) };
        return 观测产物::字节集(片.to_vec());
    }
    观测产物::其他
}

fn 由返回槽(登记表: &登记表, 能力名: Option<String>, 数据槽: 数据槽) -> 观测 {
    let 产物 = 槽产物(&数据槽);
    // 一次分流定下全部字段：**没有 `unreachable!()`**——判据里不留 panic 路。
    let (结果, 死在哪一层, 死在哪一步, 错误码, 说明) = match &产物 {
        观测产物::错误槽(码) => {
            let 登记 = 登记表.按码(*码);
            let 层 = if 登记.已登记 {
                段位到层(登记.段位).to_owned()
            } else {
                "（层判不了：这个码在任何事实源里都没登记）".to_owned()
            };
            (
                "失败",
                Some(层),
                Some("执行".to_owned()),
                Some(登记.clone()),
                format!("扩展自身在返回槽里写了错误码 {}（{}）", 登记.码, 登记.名称),
            )
        }
        观测产物::空槽 => ("成功", None, None, None, "返回槽是空槽".to_owned()),
        观测产物::字节集(字节) => (
            "成功",
            None,
            None,
            None,
            format!("返回字节集 {} 字节", 字节.len()),
        ),
        观测产物::其他 => (
            "成功",
            None,
            None,
            None,
            format!("返回内联槽：类型标签 {} 值 {}", 数据槽.类型标签.取号值(), 数据槽.值),
        ),
    };
    观测 { 结果, 死在哪一层, 死在哪一步, 错误码, 能力名, 产物, 说明 }
}

/// 由 `调度错误` 定「层 + 层内位置 + 错误码」。
///
/// `号已声明` = `适配器::能力契约(号)` 有值。两个分支处置不同：
/// - **有值** ⇒ 号在某个已装载声明的表里 ⇒ 失败是**调度**判出来的
///   （占位项 / 已废止 / 参数个数 / 配额 / 超时）；
/// - **无值** ⇒ 号不在任何已装载声明的表里 ⇒ 失败是**注册表**未命中（占位项兜底）。
fn 由调度错误(
    登记表: &登记表,
    能力名: Option<String>,
    号已声明: bool,
    错误: 调度错误,
    返回槽: &数据槽,
) -> 观测 {
    let 登记 = 登记表.由调度错误(错误);
    let 步 = if 号已声明 { "调度" } else { "注册表" };
    let 层 = if 登记.已登记 {
        段位到层(登记.段位).to_owned()
    } else {
        "（层判不了：这个码在任何事实源里都没登记）".to_owned()
    };
    观测 {
        结果: "失败",
        死在哪一层: Some(层),
        死在哪一步: Some(步.to_owned()),
        错误码: Some(登记.clone()),
        能力名,
        // 失败时的返回槽是**当场读出来的**，不是假定的：宪法第 6 条「未命中返回空」。
        产物: 槽产物(返回槽),
        说明: format!(
            "调度判出 `{错误:?}` ⇒ 码 {}（{}）· 层内位置 {步} · 号是否已声明 {号已声明}",
            登记.码, 登记.名称
        ),
    }
}

/// 把案例写的实参解成定长槽。返回「槽表 + 缓冲区」——**缓冲区必须与槽表一起活着**，
/// 否则槽里的指针当场悬垂。
fn 解实参(
    一条: &案例,
    步骤: &步骤,
    上一步返回: &Option<Vec<u8>>,
) -> Result<(Vec<数据槽>, Vec<Vec<u8>>), String> {
    let mut 缓冲: Vec<Vec<u8>> = Vec::with_capacity(步骤.实参.len());
    for (位, 参) in 步骤.实参.iter().enumerate() {
        let 字节 = match &参.来源 {
            实参来源::程序文本 => {
                let 路 = 一条.程序文本路();
                std::fs::read(&路).map_err(|错| {
                    format!(
                        "案例 `{}` 步骤 `{}` 实参[{位}]：读不到程序文本 {}：{错}",
                        一条.名,
                        步骤.名,
                        路.display()
                    )
                })?
            }
            实参来源::文件(路) => {
                let 路 = 案例件::解路(&一条.目录, 路);
                std::fs::read(&路).map_err(|错| {
                    format!(
                        "案例 `{}` 步骤 `{}` 实参[{位}]：读不到 {}：{错}",
                        一条.名,
                        步骤.名,
                        路.display()
                    )
                })?
            }
            实参来源::十六进制(字节) => 字节.clone(),
            实参来源::上一步返回 => 上一步返回.clone().ok_or_else(|| {
                format!(
                    "案例 `{}` 步骤 `{}` 实参[{位}]：要上一步的返回，但上一步没有返回字节集",
                    一条.名, 步骤.名
                )
            })?,
        };
        缓冲.push(字节);
    }
    let 槽 = 缓冲
        .iter()
        .zip(步骤.实参.iter())
        .map(|(字节, 参)| 数据槽::指针(参.类型标签.into(), 字节.as_ptr() as u64, 字节.len() as u64, false))
        .collect();
    Ok((槽, 缓冲))
}

