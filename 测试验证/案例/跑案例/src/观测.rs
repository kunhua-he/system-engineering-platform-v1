//! 观测：把一次调用翻成「层 + 层内位置 + 错误码 + 产物」，并把案例写的实参解成定长槽。
//!
//! **本件不实现装载，也不实现调用**：装载只有 `适配器::装载`，调用只有 `适配器::调用能力`。
//! 这里只做两件它不做的：**读返回槽**（把结果翻成可判的形状）与**解实参**（案例 → 槽）。
//!
//! 定层的两个事实源见 `错误码.rs` 的文件头。这里只补一句：
//! **失败时的返回槽也要当场读**——宪法第 6 条「未命中返回空」不是嘴上说的，
//! 读出来的才是读数。

use std::path::PathBuf;

use v1_adapter::{适配器, 转发结果, 数据槽, 调度错误, 派发结果};
use v1_contract::声明数据::类型标签_4294967295;

use crate::案例::{self as 案例件, 实参来源, 案例步骤, 案例};
use crate::错误码::{错误码登记, 登记表, 段位到层};

// ════════════════════════════════════════════════════════════════════════════
// 观测：把一次调用的结果翻成「层 + 层内位置 + 错误码 + 产物」
// ════════════════════════════════════════════════════════════════════════════

/// 返回槽里的产物（**封闭枚举**，只认契约里有的那几种形状）。
pub(crate) enum 观测产物 {
    空槽,
    字节集(Vec<u8>),
    错误槽(u32),
    /// 通知步骤的派发结果（能力步骤不会产出这个）。
    派发结果(String),
    /// 读留痕步骤的读数：缓冲里最近 `留痕条数` 条，加**首条**的号与结果码
    /// （空缓冲 ⇒ `首条能力号` / `首条结果码` 为 `None`）。
    留痕读数 { 留痕条数: usize, 首条能力号: Option<u32>, 首条结果码: Option<i32> },
    /// 内联整数返回（模块类能力：类型标签 1、非引用）。
    内联整数(i64),
    其他槽形态,
}

pub(crate) struct 观测 {
    pub(crate) 调用结局: &'static str,
    pub(crate) 死在哪一层: Option<String>,
    pub(crate) 死在哪一步: Option<String>,
    pub(crate) 错误码: Option<错误码登记>,
    pub(crate) 能力名: Option<String>,
    pub(crate) 产物: 观测产物,
    /// 通知步骤的派发结果名；能力步骤恒 `None`。
    pub(crate) 派发结果: Option<String>,
    pub(crate) 说明: String,
}

pub(crate) fn 观测一步(
    适配器: &适配器,
    登记表: &登记表,
    案例记录: &案例,
    案例步骤: &案例步骤,
    上一步返回: &Option<Vec<u8>>,
) -> Result<观测, String> {
    let 契约 = 适配器.能力契约(案例步骤.能力编号);
    let 能力名 = 契约.as_ref().map(|契约项| 契约项.名称.clone());

    // 案例文件形状自检（fail-closed）：实参个数与每行类型标签必须与契约对得上。
    // 对不上是**案例自身写坏了**（工具错误），不是被测对象的缺陷 —— 不许把假红留给平台。
    if let Some(契约) = &契约 {
        if 契约.参数表.len() != 案例步骤.实参.len() {
            return Err(format!(
                "案例 `{}` 步骤 `{}`：实参个数 {} 与契约的参数表行数 {} 不符",
                案例记录.名字,
                案例步骤.名字,
                案例步骤.实参.len(),
                契约.参数表.len()
            ));
        }
        for (实参序号, (实参项, 契约行)) in 案例步骤.实参.iter().zip(契约.参数表.iter()).enumerate() {
            if 实参项.类型标签 != 契约行.类型标签 {
                return Err(format!(
                    "案例 `{}` 步骤 `{}`：实参[{实参序号}] 类型标签 {} 与契约行 `{}` 的类型标签 {} 不符",
                    案例记录.名字, 案例步骤.名字, 实参项.类型标签, 契约行.名称, 契约行.类型标签
                ));
            }
        }
    }

    let (实参槽表, 缓冲, 临时件表) = 解实参(案例记录, 案例步骤, 上一步返回)?;
    let mut 返回槽 = 数据槽::空槽();
    let 转发结果值 = 适配器.调用能力(案例步骤.能力编号, &实参槽表, &mut 返回槽);
    // 入参缓冲只在这次调用期间要活着；槽里的指针已不再被读。
    drop(缓冲);
    // 临时件也只在这次调用期间要活着：步骤成败都回收（仓外造件，不脏工作区）。
    drop(临时件表);
    Ok(match 转发结果值 {
        // 失败时也读返回槽：宪法第 6 条「未命中返回空」**要当场看到**，
        // 不是嘴上说「调度层会置空」。读出来的才是读数。
        转发结果::失败(错误) => 由调度错误(登记表, 能力名, 契约.is_some(), 错误, &返回槽),
        转发结果::成功(数据槽) => 由返回槽(登记表, 能力名, 数据槽),
    })
}

/// 返回槽 → 产物。**三种形状照契约认**（错误标签 / 空 / 引用），其余如实记「其他」。
fn 槽产物(数据槽: &数据槽) -> 观测产物 {
    if 数据槽.类型标签 == 类型标签_4294967295 {
        return 观测产物::错误槽(u32::try_from(数据槽.槽值).unwrap_or(u32::MAX));
    }
    if 数据槽.是否空() {
        return 观测产物::空槽;
    }
    // 内联整数（模块类能力的整数返回）：类型标签 1、非引用 ⇒ 值就在槽里。
    if 数据槽.类型标签.取号值() == 1 && !数据槽.是否引用() {
        return 观测产物::内联整数(数据槽.槽值 as i64);
    }
    if 数据槽.是否引用() && 数据槽.槽值 != 0 {
        // SAFETY: 引用槽按契约带指针与字节长度。
        let 片段 =
            unsafe { core::slice::from_raw_parts(数据槽.槽值 as *const u8, usize::try_from(数据槽.槽字节长度).unwrap_or(0)) };
        return 观测产物::字节集(片段.to_vec());
    }
    观测产物::其他槽形态
}

fn 由返回槽(登记表: &登记表, 能力名: Option<String>, 数据槽: 数据槽) -> 观测 {
    let 产物 = 槽产物(&数据槽);
    // 一次分流定下全部字段：**没有 `unreachable!()`**——判据里不留 panic 路。
    let (调用结局, 死在哪一层, 死在哪一步, 错误码, 说明) = match &产物 {
        观测产物::错误槽(错误码) => {
            let 登记 = 登记表.按码(*错误码);
            let 层级 = if 登记.已登记 {
                段位到层(登记.段位).to_owned()
            } else {
                "（层判不了：这个码在任何事实源里都没登记）".to_owned()
            };
            (
                "失败",
                Some(层级),
                Some("执行".to_owned()),
                Some(登记.clone()),
                format!("扩展自身在返回槽里写了错误码 {}（{}）", 登记.码值, 登记.名称),
            )
        }
        观测产物::空槽 => ("成功", None, None, None, "返回槽是空槽".to_owned()),
        观测产物::字节集(字节) => (
            "成功",
            None,
            None,
            None,
            format!("返回字节集 {} 字节", 字节.len()),
        ),
        // 派发结果只由通知步骤产出，`由返回槽` 是**能力调用**的路径 ⇒ 到不了这一格。
        // 不留 `unreachable!()`（判据里不留 panic 路），如实按「其他」报。
        观测产物::派发结果(_) => (
            "成功",
            None,
            None,
            None,
            "派发结果不该出现在返回槽路径（能力调用）".to_owned(),
        ),
        // 同上：读留痕的产物只由 `观测留痕` 产出 ⇒ 到不了「能力调用返回槽」这一格。
        观测产物::留痕读数 { .. } => (
            "成功",
            None,
            None,
            None,
            "留痕读数不该出现在返回槽路径（能力调用）".to_owned(),
        ),
        观测产物::内联整数(数值) => (
            "成功",
            None,
            None,
            None,
            format!("返回内联整数 {数值}"),
        ),
        观测产物::其他槽形态 => (
            "成功",
            None,
            None,
            None,
            format!("返回内联槽：类型标签 {} 值 {}", 数据槽.类型标签.取号值(), 数据槽.槽值),
        ),
    };
    观测 { 调用结局, 死在哪一层, 死在哪一步, 错误码, 能力名, 产物, 派发结果: None, 说明 }
}

/// 由 `调度错误` 定「层 + 层内位置 + 错误码」。
///
/// `号已声明` = `适配器::能力契约(号)` 有值。两个分支处置不同：
/// - **有值** ⇒ 号在某个已装载声明的表里 ⇒ 失败是**调度**判出来的
///   （占位项 / 已废止 / 参数个数 / 配额 / 超时）；
/// - **无值** ⇒ 号不在任何已装载声明的表里 ⇒ 失败是**注册表**未命中（占位项兜底）。
fn 由调度错误(
    登记表: &登记表,
    能力名: Option<String>,
    号已声明: bool,
    错误: 调度错误,
    返回槽: &数据槽,
) -> 观测 {
    let 登记 = 登记表.由调度错误(错误);
    let 步序 = if 号已声明 { "调度" } else { "注册表" };
    let 层级 = if 登记.已登记 {
        段位到层(登记.段位).to_owned()
    } else {
        "（层判不了：这个码在任何事实源里都没登记）".to_owned()
    };
    观测 {
        调用结局: "失败",
        死在哪一层: Some(层级),
        死在哪一步: Some(步序.to_owned()),
        错误码: Some(登记.clone()),
        能力名,
        // 失败时的返回槽是**当场读出来的**，不是假定的：宪法第 6 条「未命中返回空」。
        产物: 槽产物(返回槽),
        派发结果: None,
        说明: format!(
            "调度判出 `{错误:?}` ⇒ 码 {}（{}）· 层内位置 {步序} · 号是否已声明 {号已声明}",
            登记.码值, 登记.名称
        ),
    }
}

/// 临时件的回收守卫：`Drop` 时删件 —— 步骤成功、失败、提前 `?` 返回都回收。
pub(crate) struct 临时件守卫 {
    路径: PathBuf,
}

impl Drop for 临时件守卫 {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.路径);
    }
}

/// 在**仓外**临时目录里造一个精确字节的件 ⇒ 绝对路径文本 + 回收守卫。
///
/// 落点走唯一解析器 `v1_dataroot`（运行数据根/临时件，**不在仓内**）：案例跑完工作区仍要干净；
/// 名字含进程号 + 单调序号 ⇒ 同一次运行多步不撞名。
fn 造临时件(字节: &[u8]) -> Result<(String, 临时件守卫), String> {
    static 序号: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let 本次序号 = 序号.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let 根目录 = v1_dataroot::解析当前环境()
        .map_err(|错误| format!("取运行数据根失败：{错误:?}（临时件要落仓外运行数据根）"))?;
    let 临时目录 = v1_dataroot::确保子目录(&根目录, v1_dataroot::子目录::临时件)
        .map_err(|错误| format!("建临时件目录失败：{错误}"))?;
    let 路径 = 临时目录.join(format!("v1-案例临时件-{}-{本次序号}.bin", std::process::id()));
    std::fs::write(&路径, 字节)
        .map_err(|错误| format!("造临时件 {} 失败：{错误}", 路径.display()))?;
    let 守卫 = 临时件守卫 { 路径: 路径.clone() };
    let 路径串 = 路径
        .to_str()
        .ok_or_else(|| format!("临时件路径 {} 不是合法 UTF-8", 路径.display()))?
        .to_owned();
    Ok((路径串, 守卫))
}

/// 解实参的结果：槽表 + 缓冲区 + 临时件守卫 —— **三者必须一起活着**，否则槽里的指针当场悬垂。
type 实参装配 = (Vec<数据槽>, Vec<Vec<u8>>, Vec<临时件守卫>);

/// 把案例写的实参解成定长槽。返回「槽表 + 缓冲区」——**缓冲区必须与槽表一起活着**，
/// 否则槽里的指针当场悬垂。
fn 解实参(
    案例记录: &案例,
    案例步骤: &案例步骤,
    上一步返回: &Option<Vec<u8>>,
) -> Result<实参装配, String> {
    let mut 缓冲: Vec<Vec<u8>> = Vec::with_capacity(案例步骤.实参.len());
    let mut 守卫表: Vec<临时件守卫> = Vec::new();
    for (实参序号, 实参项) in 案例步骤.实参.iter().enumerate() {
        let 字节 = match &实参项.来源 {
            实参来源::程序文本 => {
                let 路径 = 案例记录.程序文本路();
                std::fs::read(&路径).map_err(|错误| {
                    format!(
                        "案例 `{}` 步骤 `{}` 实参[{实参序号}]：读不到程序文本 {}：{错误}",
                        案例记录.名字,
                        案例步骤.名字,
                        路径.display()
                    )
                })?
            }
            实参来源::路径文本(路径) => {
                // 送的是**路径字符串本身**，不是文件内容：相对路径按案例目录解成绝对路径。
                let 实路 = 案例件::解路(&案例记录.案例目录, 路径);
                if !实路.is_absolute() {
                    return Err(format!(
                        "案例 `{}` 步骤 `{}` 实参[{实参序号}]：`路径文本` 要绝对路径（案例目录 `{}` 不是绝对路径）",
                        案例记录.名字,
                        案例步骤.名字,
                        案例记录.案例目录.display()
                    ));
                }
                let 路径串 = 实路.to_str().ok_or_else(|| {
                    format!(
                        "案例 `{}` 步骤 `{}` 实参[{实参序号}]：路径 `{}` 不是合法 UTF-8（能力只收文本路径）",
                        案例记录.名字,
                        案例步骤.名字,
                        实路.display()
                    )
                })?;
                路径串.as_bytes().to_vec()
            }
            实参来源::文件路径(路径) => {
                let 路径 = 案例件::解路(&案例记录.案例目录, 路径);
                std::fs::read(&路径).map_err(|错误| {
                    format!(
                        "案例 `{}` 步骤 `{}` 实参[{实参序号}]：读不到 {}：{错误}",
                        案例记录.名字,
                        案例步骤.名字,
                        路径.display()
                    )
                })?
            }
            实参来源::十六进制字节(字节) => 字节.clone(),
            // 整数是**内联槽**（值在槽里，不经缓冲）—— 缓冲留空，槽在下面单独造。
            实参来源::整数值(_) => Vec::new(),
            实参来源::原样文本(文本) => 文本.as_bytes().to_vec(),
            实参来源::临时件(字节) => {
                let (路径串, 守卫) = 造临时件(字节)?;
                守卫表.push(守卫);
                路径串.into_bytes()
            }
            实参来源::上一步返回 => 上一步返回.clone().ok_or_else(|| {
                format!(
                    "案例 `{}` 步骤 `{}` 实参[{实参序号}]：要上一步的返回，但上一步没有返回字节集",
                    案例记录.名字, 案例步骤.名字
                )
            })?,
        };
        缓冲.push(字节);
    }
    let 数据槽 = 缓冲
        .iter()
        .zip(案例步骤.实参.iter())
        .map(|(字节, 入参)| match &入参.来源 {
            // 整数是**内联槽**：值在槽里，宽度 8（模块 ABI 的 `取槽整数` 逐字校宽度）。
            实参来源::整数值(数值) => 数据槽::内联槽(入参.类型标签.into(), *数值 as u64, 8),
            _ => 数据槽::指针(入参.类型标签.into(), 字节.as_ptr() as u64, 字节.len() as u64, false),
        })
        .collect();
    Ok((数据槽, 缓冲, 守卫表))
}

