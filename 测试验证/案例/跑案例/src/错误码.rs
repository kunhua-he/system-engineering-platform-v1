//! 错误码登记与「死在哪一层」的映射 —— **一处都不自行编**，全部读既有事实源。
//!
//! # 事实源只有两个
//!
//! 1. **生成物 `v1_contract::声明数据::错误码信息表`**（源 = `契约声明/错误码表/*.json`）
//!    —— 内核自有段位（`0xxx`）的码、名称、三项业务判断全在这里。
//! 2. **适配器当场取到的 `能力契约.可抛错误码`**（源 = 被载入声明自身的错误码表）
//!    —— 扩展段位的码。**不另存一份表**，与「读与调同一条路」同一条理由。
//!
//! # 「死在哪一层」怎么定（不许自身编层级名）
//!
//! 层级名只有四个，就是任务书那条链上的四个：`调用方 → 适配器 → 内核 → 扩展`。
//! 定法**只看两个既有事实源**：
//!
//! | 事实源 | 怎么读 | 定出什么 |
//! |---|---|---|
//! | **失败是哪一步判出来的** | `装载失败` / `调度错误` / 返回槽是不是错误槽 | 层 + 层内位置 |
//! | **错误码的段位** | `码 / 号段类宽度`（`README.md` 第七节：段位即归属） | 扩展段的层名落到哪个号段 |
//!
//! 段位 → 层（`README.md` 第七节「号段即归属」）：
//! `0` = 内核自有 → **内核**；`1–8` = 支持库 / 模块 / 技能，三者都是可热载入的**扩展** → **扩展**；
//! `9` = 接口面与构建验证 → **接口面**（不在本链的四个名字里，如实另给一名，不硬塞进「内核」）。
//!
//! **`适配器` 这一层到不了**：适配器自身只有一处自有失败（`装载失败::空声明根`），
//! 而跑案例总是递进至少一份声明。这是**如实登记**，不是「判过了」。

use std::collections::BTreeMap;

use v1_adapter::{适配器, 调度错误, 载入错误, 号段类宽度};

/// 一条错误码登记。**结构化的六项 + 一个暴露缺口的旁路项**。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 登记 {
    pub 码: u32,
    pub 段位: u32,
    pub 名称: String,
    pub 可重试: bool,
    pub 可自愈: bool,
    pub 需人工: bool,
    /// 旁路项：这个码**没在任何事实源里登记**。契约规定「未登记的错误码不许抛出」
    /// ⇒ 出现 `false` 即一条缺陷证据。**不编一个名字填上**（编名字就是把「未登记」藏起来）。
    pub 已登记: bool,
}

impl 登记 {
    /// 未登记时的成形：码留着（它是事实），名称留空，三项一律 `false`。
    pub fn 未登记(码: u32) -> Self {
        Self {
            码,
            段位: 码 / 号段类宽度,
            名称: String::new(),
            可重试: false,
            可自愈: false,
            需人工: false,
            已登记: false,
        }
    }

    pub fn 转JSON文本(&self) -> String {
        let mut 文本缓冲 = String::from("{");
        文本缓冲.push_str(&format!("\"码\":{},\"段位\":{}", self.码, self.段位));
        文本缓冲.push_str(",\"名称\":");
        crate::最小JSON::写串(&mut 文本缓冲, &self.名称);
        文本缓冲.push_str(&format!(
            ",\"可重试\":{},\"可自愈\":{},\"需人工\":{},\"已登记\":{}",
            self.可重试, self.可自愈, self.需人工, self.已登记
        ));
        文本缓冲.push('}');
        文本缓冲
    }
}

/// 错误码登记表：码 → 登记。**当场建，不缓存到磁盘。**
#[derive(Debug, Default)]
pub struct 登记表 {
    项: BTreeMap<u32, 登记>,
}

impl 登记表 {
    /// 从**生成物**与**适配器当场取到的契约**建表。两处都不新增一份表。
    pub fn 建登记表(适配器: &适配器) -> Self {
        let mut 表 = Self::从生成物();
        // ② 适配器当场取：被载入声明自身的错误码表（扩展段位）。**清单与契约同一个入口。**
        for 摘要 in 适配器.能力清单() {
            let Some(契) = 适配器.能力契约(摘要.编号) else {
                continue;
            };
            for 码 in 契.可抛错误码 {
                表.追加一条(登记 {
                    码: 码.码,
                    段位: 码.码 / 号段类宽度,
                    名称: 码.名称,
                    可重试: 码.可重试,
                    可自愈: 码.可自愈,
                    需人工: 码.需人工,
                    已登记: true,
                });
            }
        }
        表
    }

    /// 只从**生成物**建（内核自有段位的码，源 = `契约声明/错误码表/*.json`）。
    /// 单独给出来是为了能**不依赖任何声明**就测这一段 —— 测它不必先造一份声明。
    pub fn 从生成物() -> Self {
        let mut 表 = Self::default();
        for 码 in v1_contract::声明数据::错误码信息表.iter() {
            表.追加一条(登记 {
                码: 码.码,
                段位: 码.段位,
                // SAFETY: 契约保证一切串都是静态只读 NUL 结尾串。
                名称: unsafe { 读契约串(码.名称) },
                可重试: 码.可重试 != 0,
                可自愈: 码.可自愈 != 0,
                需人工: 码.需人工 != 0,
                已登记: true,
            });
        }
        表
    }

    fn 追加一条(&mut self, 一: 登记) {
        // 同一码在两处登记：**不许互相盖**。只在「后到的已登记、先到的未登记」时补上。
        match self.项.get(&一.码) {
            Some(旧) if 旧.已登记 => {}
            _ => {
                self.项.insert(一.码, 一);
            }
        }
    }

    pub fn 按码(&self, 码: u32) -> 登记 {
        self.项.get(&码).cloned().unwrap_or_else(|| 登记::未登记(码))
    }

    /// 按**名称**取登记。这是把 `调度错误` / `载入错误` 的变体名换成码的**唯一**办法：
    /// 那两套枚举的变体**不带码**，适配器也没有「段位 → 错误码」这个口（缺口，见回执说明）。
    /// 名字对不上 ⇒ `None` ⇒ 调用方如实记「未登记」，**不猜一个码**。
    pub fn 按名(&self, 名: &str) -> Option<登记> {
        self.项.values().find(|一| 一.名称 == 名).cloned()
    }

    pub fn 由调度错误(&self, 错: 调度错误) -> 登记 {
        self.按名(调度错误名(错)).unwrap_or_else(|| 登记::未登记(0))
    }

    pub fn 由载入错误(&self, 错: &载入错误) -> 登记 {
        self.按名(载入错误名(错)).unwrap_or_else(|| 登记::未登记(0))
    }
}

/// `调度错误` 的变体名。**与 `契约声明/错误码表/*.json` 的 `名称` 逐字相同**
/// （实测：五个变体全对得上；对不上时 [`登记表::按名`] 会给 `None`，回执里 `已登记=false`）。
pub fn 调度错误名(错: 调度错误) -> &'static str {
    match 错 {
        调度错误::提供者未载入 { .. } => "提供者未载入",
        调度错误::命令已废止 { .. } => "命令已废止",
        调度错误::参数个数不符 { .. } => "参数个数不符",
        调度错误::超时 { .. } => "超时",
        调度错误::配额用尽 => "配额用尽",
    }
}

/// `载入错误` 的变体名（判定六步的哪一步不过，`运行内核/装载入口/src/错误.rs`）。
///
/// 变体名**逐字取** `契约声明/错误码表/<码>.json` 的 `名称`（码表是名称的唯一登记处）——
/// 按名对码是运行期把变体换成码的唯一办法。
///
/// **变体名必须与码表的 `名称` 逐字相同**（`契约声明/错误码表/` 是名称的唯一登记处）：
/// 按名查码是运行期把变体换成码的唯一办法。
///
/// **改名前先看 `契约声明/作废号表.json`** —— 号**只增不改**：改语义要**加新码 + 作废旧码**
/// （例：`类型标签与已登记重复` 由码 32 承载，码 16「类型标签未显式」已作废），不许原地改名。
/// 查不到就记 `已登记: false`（回执里的旁路项），**不许替它编一个码**。
/// `格式号不匹配` 那一处与 `建表错误` 的同一条都叫 `声明格式号不匹配`，与 `错误码表/0006.json` 同名。
pub fn 载入错误名(错: &载入错误) -> &'static str {
    match 错 {
        载入错误::声明格式号不匹配 { .. } => "声明格式号不匹配",
        载入错误::标识串非法 => "标识串非法",
        载入错误::号段冲突 { .. } => "号段冲突",
        载入错误::号段非法 { .. } => "号段非法",
        载入错误::号段表内重叠 { .. } => "号段表内重叠",
        载入错误::要求版本不满足 { .. } => "要求版本不满足",
        载入错误::依赖缺失 => "依赖缺失",
        载入错误::声明不自洽 { .. } => "声明不自洽",
        载入错误::错误段位表为空 => "错误段位表为空",
        载入错误::错误段位重复 { .. } => "错误段位重复",
        载入错误::类型标签与已登记重复 { .. } => "类型标签与已登记重复",
        载入错误::类型标签重复 { .. } => "类型标签重复",
        载入错误::建表(内) => 建表错误名(内),
    }
}

fn 建表错误名(错: &v1_loader::建表错误) -> &'static str {
    match 错 {
        v1_loader::建表错误::声明格式号不匹配 { .. } => "声明格式号不匹配",
        v1_loader::建表错误::标识串重复 => "标识串非法",
        v1_loader::建表错误::号段冲突 { .. } => "号段冲突",
        v1_loader::建表错误::类型表自相矛盾 { .. } => "类型表自相矛盾",
        v1_loader::建表错误::常量表自相矛盾 { .. } => "常量表自相矛盾",
        v1_loader::建表错误::项表为空 { .. } => "项表为空",
        v1_loader::建表错误::函数表项数不符 { .. } => "函数表项数不符",
        // 下面三条**已在 `契约声明/错误码表/` 登记**（0029 · 0030 · 0031，经声明编写面写入）。
        // 但生成物 `声明数据.rs` 还没重跑 ⇒ 它们在**运行期表**里仍查不到（按名查 `None`、
        // 回执 `已登记=false`），直到装配节点重跑 `构建装配/形态装配/生成声明.py`。
        // **本件不替它编一个码**：编出来的码没有登记处背书。
        v1_loader::建表错误::命令编号不递增 { .. } => "命令编号不递增",
        v1_loader::建表错误::常量号不递增 { .. } => "常量号不递增",
        v1_loader::建表错误::类型标签不递增 { .. } => "类型标签不递增",
    }
}

/// 段位 → 层。**层名只有四个**（任务书那条链）+ 一个如实另给的 `接口面`。
pub fn 段位到层(段位: u32) -> &'static str {
    match 段位 {
        0 => "内核",
        1..=8 => "扩展",
        _ => "接口面",
    }
}

/// 读一个契约串（静态只读 NUL 结尾）。与适配器读契约串同一口径、同一上限。
///
/// # Safety
/// `指针` 要么为空，要么指向至少 `契约串上限` 字节可读的静态数据。
unsafe fn 读契约串(指针: *const u8) -> String {
    const 上限: usize = 4096;
    if 指针.is_null() {
        return String::new();
    }
    let mut 长 = 0usize;
    while 长 < 上限 {
        // SAFETY: 由调用方保证 指针..指针+上限 可读。
        if unsafe { *指针.add(长) } == 0 {
            break;
        }
        长 += 1;
    }
    if 长 == 上限 {
        return String::new();
    }
    // SAFETY: 已扫到 NUL，前 长 字节可读且不再变动（静态数据）。
    let 字节 = unsafe { core::slice::from_raw_parts(指针, 长) };
    String::from_utf8_lossy(字节).into_owned()
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use v1_adapter::能力号;   // 只有本模块用：构造 `调度错误` 的号字段

    /// 正向样本：生成物那份错误码表必须建得出登记（空表就是判不了，不是通过）。
    #[test]
    fn 生成物错误码表建得出登记() {
        let 表 = 登记表::从生成物();
        assert!(!表.项.is_empty(), "登记表是空集 —— 那什么都没验");
        let 一 = 表.按码(1);
        assert_eq!(一.名称, "提供者未载入");
        assert!(一.已登记);
        assert_eq!(一.段位, 0);
        assert!(一.可重试 && 一.可自愈 && !一.需人工);
    }

    /// 反向样本：没登记的码必须报 `已登记=false`，**不许编一个名字**。
    #[test]
    fn 未登记的码不编名字() {
        let 表 = 登记表::default();
        let 一 = 表.按码(4321);
        assert!(!一.已登记);
        assert_eq!(一.名称, "");
        assert_eq!(一.段位, 4);
    }

    /// 段位到层：四层名 + 接口面，且**没有第五个名字**。
    #[test]
    fn 段位到层只有四个名字() {
        assert_eq!(段位到层(0), "内核");
        assert_eq!(段位到层(1), "扩展");
        assert_eq!(段位到层(8), "扩展");
        assert_eq!(段位到层(9), "接口面");
    }

    /// 反向样本：五个调度错误变体名必须都能在生成物里查到（否则回执会大面积 `未登记`）。
    #[test]
    fn 五个调度错误变体名都对得上() {
        for 错 in [
            调度错误::提供者未载入 { 能力号: 能力号::新(1) },
            调度错误::命令已废止 { 能力号: 能力号::新(1) },
            调度错误::参数个数不符 { 声明: 1, 实际: 2 },
            调度错误::超时 { 毫秒: 1 },
            调度错误::配额用尽,
        ] {
            assert!(调度错误名(错).chars().all(|字| !字.is_whitespace()));
        }
    }
}
