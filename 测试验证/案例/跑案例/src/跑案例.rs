//! 跑案例 —— 端到端主门禁的主流程。
//!
//! # 一条案例的活
//!
//! ```text
//! 读案例目录 → 取扩展声明（经接缝 GetPlatformInfo）→ 适配器装载
//!   → 逐步：解析实参 → 调用能力（经适配器）→ 观测（层 + 错误码 + 产物）→ 与期望比对
//!   → 追加一行回执
//! ```
//!
//! **本件不实现装载，也不实现调用**：装载只有 `适配器::装载`，调用只有 `适配器::调用能力`。
//! 这里只做三件它不做的：**案例的读写** · **期望的比对** · **回执的成形**。
//!
//! # 三类结局，三种退出码（没有「跳过」这一档）
//!
//! | 结局 | 退出码 | 写回执吗 |
//! |---|---|---|
//! | 全部案例通过 | `0` | 写（每条一行） |
//! | 有案例失败 | `1` | 写（失败那一行带层 + 错误码） |
//! | **工具错误** | `2` | **不写** |
//!
//! 工具错误 = 案例文件坏了 / 语料读不到 / 接缝被解析到别的声明上 / git 读数取不到。
//! **不写回执**的理由：回执的不变量是「失败必有结构化错误码」，而工具错误没有码；
//! 硬写一行没有码的失败，就把那个不变量破坏掉了 —— 后人再也分不清「被测对象坏了」
//! 与「判据的输入坏了」（`判据的可信性.md` 第三节第 5 条：判据的解析器坏了也是假绿来源）。

