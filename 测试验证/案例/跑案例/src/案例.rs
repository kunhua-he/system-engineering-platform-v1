//! 案例形状与读盘 —— 案例库的**唯一事实源是磁盘上的案例目录**，不是本文件里的任何表。
//!
//! # 案例目录形状（`测试验证/案例/形状.md` 是权威，这里只实现它）
//!
//! ```text
//! 测试验证/案例/<案例名>/
//!   案例.json        做什么：装载哪份声明 · 步骤链（能力编号 + 按契约行序的实参来源）
//!   输入.程序文本     真程序文本（我们的原生格式）。「程序」类案例必有；容器类案例没有
//!   期望.json        期望什么：按步骤一一对应（运行结果 或 诊断）
//! ```
//!
//! 编码一律 UTF-8，换行一律 LF。**`输入.程序文本` 不在这里转码**：它的字节原样送进能力，
//! 转码是调用方的事，案例库不该替调用方做决定。
//!
//! # 期望是**封闭枚举**，不是断言语言
//!
//! 判据只有下面 [`期望`] 与 [`产物判据`] 里那几个变体：没有变量、没有表达式、没有运算符、
//! 不能组合。加一种判据 = 加一个变体 = 改这一份实现；**加不出「写一条新断言」这回事**。

use std::path::{Path, PathBuf};

use crate::最小JSON::{self, JSON值};

/// 案例目录里放真程序文本的那一个文件名（**名字写死在一处**）。
pub const 程序文本文件名: &str = "输入.程序文本";

/// 实参的取值来源。**封闭枚举**。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 实参来源 {
    /// 案例目录里的 `输入.程序文本`。
    程序文本,
    /// 一个文件：相对路径按案例目录解，绝对路径原样用（只读语料走这条）。
    文件路径(PathBuf),
    /// 一个文件的**路径文本本身**（不是文件内容）：相对路径按案例目录解成绝对路径，
    /// 再把**路径字符串**送进能力 —— 文件类能力的入参形态。
    路径文本(PathBuf),
    /// 就地写的十六进制字节（小输入用，避免为几个字节建一个文件）。
    十六进制字节(Vec<u8>),
    /// 一个整数（**内联槽**，不经缓冲）：模块类能力的两个整数入参走这条。
    整数值(i64),
    /// 上一步的返回字节集（步骤链；`1105 → 1104` 的往返就走它）。
    上一步返回,
    /// **原样**文本：`值` 直接当 UTF-8 字节送进能力，**不**按案例目录解析（相对路径 / 任意文本）。
    原样文本(String),
    /// 按精确字节在**仓外**临时目录造件，再把它的**绝对路径文本**送进能力（字节边界用）。
    临时件(Vec<u8>),
}

/// 一个实参：类型标签 + 来源。**行序即契约**，由 `案例.json` 里 `实参` 数组的排列给出。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 实参 {
    pub 类型标签: u32,
    pub 来源: 实参来源,
}

/// 一步：调能力（`通知号` / `读留痕条数` 均 `None`）· 发生命周期通知（`通知号 = Some`）· 读留痕（`读留痕条数 = Some`）。三者互斥。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 案例步骤 {
    pub 名字: String,
    pub 能力编号: u32,
    pub 实参: Vec<实参>,
    pub 通知号: Option<u32>,
    pub 读留痕条数: Option<u32>,
}

/// 成功时看返回槽的哪一件事。**封闭枚举**。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 产物判据 {
    /// 返回槽是空槽（`槽标志::空槽标志`）。
    空槽,
    /// 返回的字节集**逐字节等于**这个文件的字节。相对路径按案例目录解。
    逐字节等于文件(PathBuf),
    /// 返回的是字节集且长度 > 0。
    非空字节集,
    /// 返回槽是**错误槽**且码等于这个值（类型标签 = 错误）。
    ///
    /// 与「空槽」是**两件不同的事**：空槽 = 调用没到扩展（未命中返回空，宪法第 6 条）；
    /// 错误槽 = **扩展抛错了**（码在槽里）。以前期望侧表达不了后者，只能写「不判」——
    /// 于是「扩展抛错」与「没到扩展」在案例里区分不开。
    错误槽(u32),
    /// 返回的 `103 结果结构` 里，给定字段**逐个等于**给定值（文件类能力的精确断言）。
    ///
    /// 为什么要有这一档：文件摘要类能力返回的是三个可被外部工具复算的值（`shasum` / `wc`），
    /// 只写「非空字节集」等于没判。解码走契约层唯一 codec
    /// （`v1_contract::复合值载荷::解码复合值载荷`），期望值由人写进 `期望.json`。
    复合字段(Vec<(String, 复合字段期望)>),
    /// 只看转发成功，不看返回槽内容（读侧一类的调用）。
    不看返回槽,
    /// 返回槽是**内联整数**且值等于这个数（模块类能力的整数返回）。
    内联整数(i64),
    /// 读留痕步骤的产物：留痕缓冲**首条**记录的 `能力号` 等于这个值（`形状检查/常量.py` 白名单已同步）。
    留痕首条能力号(u32),
}

/// 一条字段期望值。**封闭枚举**：整数或文本 —— `103 结果结构` 里这两种就够用。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 复合字段期望 {
    /// 整数字段（`字节数` · `行数` 这类；文件类取值不会为负）。
    整数(i64),
    /// 文本字段（`摘要文本` 这类）。
    文本(String),
}

/// 失败时期望的错误码。三项业务判断**必须写在案例里**——它们猜不出来（`README.md` 第七节）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 错误码期望 {
    pub 码值: u32,
    pub 名称: String,
    pub 可重试: bool,
    pub 可自愈: bool,
    pub 需人工: bool,
}

/// 一步的期望。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 期望 {
    /// 期望转发成功。`派发结果` 只对通知步骤有意义（`Some` = 比对，`None` = 不看）。
    成功 { 产物: 产物判据, 派发结果: Option<String> },
    /// 期望**结构化失败**：死在哪一层 + 哪个错误码（+ 可选的返回槽判据）。
    /// **没有「跳过」这一档。**
    失败 {
        死在哪一层: String,
        错误码: 错误码期望,
        /// 失败时返回槽该是什么样。`不判` = 不看。宪法第 6 条「未命中返回空」
        /// 就靠这里写 `空槽` 来证 —— 不写就没人证它。
        产物: 产物判据,
    },
}

/// 一个案例。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 案例 {
    pub 名字: String,
    pub 案例目录: PathBuf,
    pub 说明: String,
    /// 案例点名要装载的声明名（可选；空 = 只装被验扩展）。名字 → 声明在 `装载声明::解析声明名`。
    pub 声明: Vec<String>,
    /// 案例点名的**模块部署事实**（可选；空 = 不碰模块）。
    pub 模块部署值: Option<模块部署>,
    /// 步骤链。**至少一步**——空步骤链是空集，不许算通过。
    pub 案例步骤: Vec<案例步骤>,
    /// 与 `步骤` 等长，一一对应。
    pub 期望: Vec<期望>,
}

/// 案例点名的一个**模块部署事实**：模块不是支持库声明，装载走工作进程 + 模块域登记。
///
/// 四件都是**部署事实**（与网关的 `--跨进程配置` 同源），案例显式写出来 —— 跑案例不猜路径、不写号表。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 模块部署 {
    pub 模块制品: PathBuf,
    pub 标识串: String,
    pub 版本: (u32, u32, u32),
    pub 能力号: u32,
}

impl 案例 {
    pub fn 程序文本路(&self) -> PathBuf {
        self.案例目录.join(程序文本文件名)
    }
}

/// 案例库里不是案例的目录（**写死一处**）：跑案例的程序自身住在这里。
const 非案例目录: &[&str] = &["跑案例"];

/// 读一个案例根下的全部案例，按目录名排序（顺序确定 ⇒ 回执可比）。
///
/// **fail-closed**：除 [`非案例目录`] 外，任何一个子目录缺 `案例.json` 或 `期望.json`
/// 都是**工具错误**（不是「跳过这个案例」）——静默跳过就是假绿。
pub fn 读全部(案例根: &Path) -> Result<Vec<案例>, String> {
    let 目录迭代器 = std::fs::read_dir(案例根).map_err(|错误| format!("读不到案例根 {}：{错误}", 案例根.display()))?;
    let mut 名表: Vec<String> = Vec::new();
    for 目录项 in 目录迭代器 {
        let 目录项 = 目录项.map_err(|错误| format!("列案例根失败：{错误}"))?;
        let 路径 = 目录项.path();
        if !路径.is_dir() {
            continue;
        }
        let 名称 = 目录项.file_name().to_string_lossy().into_owned();
        if !非案例目录.contains(&名称.as_str()) {
            名表.push(名称);
        }
    }
    名表.sort();
    if 名表.is_empty() {
        return Err(format!(
            "案例根 {} 下 0 个案例目录 —— 空集不算通过（判据的可信性.md 第二节）",
            案例根.display()
        ));
    }
    let mut 累积表 = Vec::new();
    for 名称 in 名表 {
        累积表.push(读一个(&案例根.join(&名称))?);
    }
    Ok(累积表)
}

fn 读一个(案例目录: &Path) -> Result<案例, String> {
    let 案例清单 = 读JSON件(&案例目录.join("案例.json"))?;
    let 名称 = 要串(&案例清单, "案例名")?.to_owned();
    let 说明 = 要串(&案例清单, "说明")?.to_owned();
    let 声明 = 读声明(&案例清单)?;
    let 模块部署值 = 读模块(&案例清单)?;
    let 案例步骤 = 读步骤(&案例清单, 案例目录)?;
    let 期望 = 读期望(&案例目录.join("期望.json"), 案例步骤.len(), 案例目录)?;
    if 案例步骤.is_empty() {
        return Err(format!("{}：步骤是空集 —— 空集不算通过", 案例目录.display()));
    }
    Ok(案例 { 名字: 名称, 案例目录: 案例目录.to_path_buf(), 说明, 声明, 模块部署值, 案例步骤, 期望 })
}

/// 读案例点名的**模块部署事实**（可选；空 = 这个案例不碰模块）。
fn 读模块(案例清单: &JSON值) -> Result<Option<模块部署>, String> {
    let Some(模块值) = 案例清单.取成员("模块") else { return Ok(None) };
    let 模块制品 = 模块值
        .取成员("制品")
        .and_then(|成员值| 成员值.取字符串())
        .ok_or_else(|| "`模块.制品` 缺失或不是字符串".to_owned())?;
    let 标识串 = 模块值
        .取成员("标识串")
        .and_then(|成员值| 成员值.取字符串())
        .ok_or_else(|| "`模块.标识串` 缺失或不是字符串".to_owned())?;
    let 版本值 = 模块值
        .取成员("版本")
        .ok_or_else(|| "`模块.版本` 缺失".to_owned())?;
    let 取段 = |键名: &str| -> Result<u32, String> {
        版本值
            .取成员(键名)
            .and_then(|成员值| 成员值.取整数())
            .and_then(|号值| u32::try_from(号值).ok())
            .ok_or_else(|| format!("`模块.版本.{键名}` 缺失或不是 32 位整数"))
    };
    let 能力号 = 模块值
        .取成员("能力号")
        .and_then(|成员值| 成员值.取整数())
        .and_then(|号值| u32::try_from(号值).ok())
        .ok_or_else(|| "`模块.能力号` 缺失或不是 32 位整数".to_owned())?;
    Ok(Some(模块部署 {
        模块制品: PathBuf::from(模块制品),
        标识串: 标识串.to_owned(),
        版本: (取段("主版本")?, 取段("次版本号")?, 取段("构建")?),
        能力号,
    }))
}

/// 读案例点名的**声明表**（可选；空 = 只装被验扩展）。名字不认由 `装载声明` 报。
fn 读声明(案例清单: &JSON值) -> Result<Vec<String>, String> {
    let Some(项表) = 案例清单.取成员("声明") else { return Ok(Vec::new()) };
    let 项表 = 项表.取数组().ok_or_else(|| "`声明` 不是数组".to_owned())?;
    let mut 声明表 = Vec::with_capacity(项表.len());
    for 数组项 in 项表 {
        声明表.push(数组项.取字符串().ok_or_else(|| "`声明` 项不是字符串".to_owned())?.to_owned());
    }
    Ok(声明表)
}

fn 读步骤(案例清单: &JSON值, 案例目录: &Path) -> Result<Vec<案例步骤>, String> {
    let 项表 = 案例清单
        .取成员("步骤")
        .and_then(|成员值| 成员值.取数组())
        .ok_or_else(|| format!("{}：`步骤` 缺失或不是数组", 案例目录.display()))?;
    let mut 累积表 = Vec::new();
    for (序号, 步骤项) in 项表.iter().enumerate() {
        let 名称 = 步骤项
            .取成员("名")
            .and_then(|成员值| 成员值.取字符串())
            .ok_or_else(|| format!("{}：步骤[{序号}] 缺 `名`", 案例目录.display()))?
            .to_owned();
        // 通知步骤：写 `通知号` 而不是 `能力编号`（二者互斥；通知步骤没有实参）。
        // 两种步骤共用一次 `步骤 { … }` 构造（只此处一处 `名:` 字段），故先读通知号再分派。
        let 通知号 = 步骤项
            .取成员("通知号")
            .and_then(|数组项| 数组项.取整数())
            .and_then(|整数值| u32::try_from(整数值).ok());
        let 读留痕条数 = 步骤项.取成员("读留痕").and_then(|数组项| 数组项.取整数()).and_then(|整数值| u32::try_from(整数值).ok());
        let mut 能力编号 = 0;
        let mut 实参 = Vec::new();
        if 通知号.is_none() && 读留痕条数.is_none() {
            能力编号 = 步骤项
                .取成员("能力编号")
                .and_then(|成员值| 成员值.取整数())
                .and_then(|整数值| u32::try_from(整数值).ok())
                .ok_or_else(|| format!("{}：步骤[{序号}] 的 `能力编号` 缺失或不是 32 位整数", 案例目录.display()))?;
            let 实参表 = 步骤项
                .取成员("实参")
                .and_then(|成员值| 成员值.取数组())
                .ok_or_else(|| format!("{}：步骤[{序号}] 的 `实参` 缺失或不是数组", 案例目录.display()))?;
        for (实参序号, 实参项) in 实参表.iter().enumerate() {
            let 类型标签 = 实参项
                .取成员("类型标签")
                .and_then(|成员值| 成员值.取整数())
                .and_then(|整数值| u32::try_from(整数值).ok())
                .ok_or_else(|| {
                    format!("{}：步骤[{序号}].实参[{实参序号}] 的 `类型标签` 缺失或不是 32 位整数", 案例目录.display())
                })?;
            let 来源名 = 实参项
                .取成员("来源")
                .and_then(|成员值| 成员值.取字符串())
                .ok_or_else(|| format!("{}：步骤[{序号}].实参[{实参序号}] 缺 `来源`", 案例目录.display()))?;
            let 值项 = 实参项.取成员("值");
            let 来源 = match 来源名 {
                "程序文本" => 实参来源::程序文本,
                "文件" => 实参来源::文件路径(PathBuf::from(
                    值项
                        .and_then(|成员值| 成员值.取字符串())
                        .ok_or_else(|| {
                            format!("{}：步骤[{序号}].实参[{实参序号}] 来源是 `文件`，缺 `值`（路径）", 案例目录.display())
                        })?
                        .to_owned(),
                )),
                "十六进制" => {
                    let 源文本 = 值项.and_then(|成员值| 成员值.取字符串()).ok_or_else(|| {
                        format!("{}：步骤[{序号}].实参[{实参序号}] 来源是 `十六进制`，缺 `值`", 案例目录.display())
                    })?;
                    实参来源::十六进制字节(解十六进制(源文本).map_err(|错误| {
                        format!("{}：步骤[{序号}].实参[{实参序号}] 的十六进制：{错误}", 案例目录.display())
                    })?)
                }
                "上一步返回" => 实参来源::上一步返回,
                // `整数` 也是合法来源（模块类能力的整数入参走内联槽，不经缓冲）。
                "整数" => 实参来源::整数值(值项.and_then(|成员值| 成员值.取数值()).ok_or_else(|| {
                    format!("{}：步骤[{序号}].实参[{实参序号}] 来源是 `整数`，缺 `值`（整数）", 案例目录.display())
                })? as i64),
                "原样文本" => 实参来源::原样文本(
                    值项
                        .and_then(|成员值| 成员值.取字符串())
                        .ok_or_else(|| {
                            format!(
                                "{}：步骤[{序号}].实参[{实参序号}] 来源是 `原样文本`，缺 `值`（文本）",
                                案例目录.display()
                            )
                        })?
                        .to_owned(),
                ),
                "临时件" => {
                    let 源文本 = 值项.and_then(|成员值| 成员值.取字符串()).ok_or_else(|| {
                        format!(
                            "{}：步骤[{序号}].实参[{实参序号}] 来源是 `临时件`，缺 `值`（十六进制字节）",
                            案例目录.display()
                        )
                    })?;
                    实参来源::临时件(解十六进制(源文本).map_err(|错误| {
                        format!("{}：步骤[{序号}].实参[{实参序号}] 的十六进制：{错误}", 案例目录.display())
                    })?)
                }
                "路径文本" => 实参来源::路径文本(PathBuf::from(
                    值项
                        .and_then(|成员值| 成员值.取字符串())
                        .ok_or_else(|| {
                            format!(
                                "{}：步骤[{序号}].实参[{实参序号}] 来源是 `路径文本`，缺 `值`（路径）",
                                案例目录.display()
                            )
                        })?
                        .to_owned(),
                )),
                其他来源 => {
                    return Err(format!(
                        "{}：步骤[{序号}].实参[{实参序号}] 的 `来源` 不认：`{其他来源}`（只认 程序文本 / 文件 / 十六进制 / 上一步返回 / 路径文本 / 原样文本 / 临时件）",
                        案例目录.display()
                    ));
                }
            };
            实参.push(实参 { 类型标签, 来源 });
        }
        }
        累积表.push(案例步骤 { 名字: 名称, 能力编号, 实参, 通知号, 读留痕条数 });
    }
    Ok(累积表)
}

fn 读期望(路径: &Path, 步骤数: usize, 案例目录: &Path) -> Result<Vec<期望>, String> {
    let 根目录 = 读JSON件(路径)?;
    let 项表 = 根目录
        .取成员("步骤")
        .and_then(|成员值| 成员值.取数组())
        .ok_or_else(|| format!("{}：`步骤` 缺失或不是数组", 路径.display()))?;
    if 项表.len() != 步骤数 {
        return Err(format!(
            "{}：期望有 {} 条、步骤有 {步骤数} 条 —— 必须一一对应（不等就是案例自身写坏了）",
            路径.display(),
            项表.len()
        ));
    }
    let mut 累积表 = Vec::new();
    for (序号, 步骤项) in 项表.iter().enumerate() {
        let 调用结局 = 步骤项
            .取成员("结果")
            .and_then(|成员值| 成员值.取字符串())
            .ok_or_else(|| format!("{}：步骤[{序号}] 缺 `结果`", 路径.display()))?;
        let 判定 = match 调用结局 {
            "成功" => 期望::成功 {
                产物: 读产物(步骤项, 案例目录)?,
                派发结果: 步骤项
                    .取成员("派发结果")
                    .and_then(|数组项| 数组项.取字符串())
                    .map(str::to_owned),
            },
            "失败" => {
                let 层级 = 步骤项
                    .取成员("死在哪一层")
                    .and_then(|成员值| 成员值.取字符串())
                    .ok_or_else(|| format!("{}：步骤[{序号}] 结果=失败，必须有 `死在哪一层`", 路径.display()))?
                    .to_owned();
                let 码项 = 步骤项
                    .取成员("错误码")
                    .ok_or_else(|| format!("{}：步骤[{序号}] 结果=失败，必须有 `错误码`", 路径.display()))?;
                let 错误码 = 错误码期望 {
                    码值: 要整数(码项, "码", 路径)?,
                    名称: 要串(码项, "名称")?.to_owned(),
                    可重试: 要真假(码项, "可重试")?,
                    可自愈: 要真假(码项, "可自愈")?,
                    需人工: 要真假(码项, "需人工")?,
                };
                期望::失败 { 死在哪一层: 层级, 错误码, 产物: 读产物(步骤项, 案例目录)? }
            }
            其他结果 => {
                return Err(format!(
                    "{}：步骤[{序号}] 的 `结果` 不认：`{其他结果}`（只认 成功 / 失败 —— 没有「跳过」这一档）",
                    路径.display()
                ));
            }
        };
        累积表.push(判定);
    }
    Ok(累积表)
}

fn 读产物(产物值: &JSON值, 案例目录: &Path) -> Result<产物判据, String> {
    let Some(产物) = 产物值.取成员("产物") else {
        return Ok(产物判据::不看返回槽);
    };
    let 判定值 = 产物
        .取成员("判据")
        .and_then(|成员值| 成员值.取字符串())
        .ok_or_else(|| format!("{}：`产物` 缺 `判据`", 案例目录.display()))?;
    match 判定值 {
        "空槽" => Ok(产物判据::空槽),
        "非空字节集" => Ok(产物判据::非空字节集),
        "不判" => Ok(产物判据::不看返回槽),
        "内联整数" => Ok(产物判据::内联整数(
            产物
                .取成员("值")
                .and_then(|成员值| 成员值.取数值())
                .ok_or_else(|| "`内联整数` 缺 `值`（要一个整数）".to_owned())? as i64,
        )),
        "留痕首条能力号" => Ok(产物判据::留痕首条能力号(
            产物.取成员("能力号").and_then(|数组项| 数组项.取数值()).ok_or_else(|| "`留痕首条能力号` 缺 `能力号`".to_owned())? as u32,
        )),
        "错误槽" => Ok(产物判据::错误槽(
            产物
                .取成员("码")
                .and_then(|成员值| 成员值.取数值())
                .ok_or_else(|| "`错误槽` 缺 `码`（要一个整数）".to_owned())? as u32,
        )),
        "复合字段" => Ok(产物判据::复合字段(读复合字段(产物)?)),
        "逐字节等于文件" => Ok(产物判据::逐字节等于文件(PathBuf::from(
            产物
                .取成员("文件")
                .and_then(|成员值| 成员值.取字符串())
                .ok_or_else(|| "`逐字节等于文件` 缺 `文件`".to_owned())?
                .to_owned(),
        ))),
        其他判据 => Err(format!("`产物.判据` 不认：`{其他判据}`")),
    }
}

/// 读「复合字段」判据的字段表：`{"字段": {"字节数": 14, "行数": 3, "摘要文本": "…"}}`。
///
/// 只认整数与文本两种期望值（`103 结果结构` 里这两种就够用）；其余形状当场报错 ——
/// 期望写坏了是**工具错误**（退出码 2、不写回执），不是被测对象的缺陷。
fn 读复合字段(产物值: &JSON值) -> Result<Vec<(String, 复合字段期望)>, String> {
    let 字段对象 = 产物值
        .取成员("字段")
        .ok_or_else(|| "`复合字段` 缺 `字段`（要一个对象：字段名 → 期望值）".to_owned())?;
    let JSON值::对象值(项表) = 字段对象 else {
        return Err("`复合字段` 的 `字段` 不是对象".to_owned());
    };
    if 项表.is_empty() {
        return Err("`复合字段` 的 `字段` 是空集 —— 空集不算通过".to_owned());
    }
    let mut 期望表 = Vec::with_capacity(项表.len());
    for (字段名, 字段值) in 项表 {
        if let Some(整数值) = 字段值.取整数() {
            期望表.push((字段名.clone(), 复合字段期望::整数(整数值 as i64)));
            continue;
        }
        if let Some(文本值) = 字段值.取字符串() {
            期望表.push((字段名.clone(), 复合字段期望::文本(文本值.to_owned())));
            continue;
        }
        return Err(format!(
            "`复合字段` 的字段 `{字段名}` 既不是整数也不是文本 —— 期望值只认这两种（负数也不收）"
        ));
    }
    Ok(期望表)
}

/// 相对路径按案例目录解；绝对路径原样用（只读语料在仓外）。
pub fn 解路(案例目录: &Path, 路径: &Path) -> PathBuf {
    if 路径.is_absolute() {
        路径.to_path_buf()
    } else {
        案例目录.join(路径)
    }
}

pub fn 解十六进制(源文本: &str) -> Result<Vec<u8>, String> {
    let 净文本: Vec<u8> = 源文本.bytes().filter(|字符表| !matches!(字符表, b' ' | b'\n' | b'\r' | b'\t')).collect();
    if !净文本.len().is_multiple_of(2) {
        return Err(format!("十六进制位数是奇数（{}）", 净文本.len()));
    }
    let mut 累积表 = Vec::with_capacity(净文本.len() / 2);
    for 字节对 in 净文本.chunks(2) {
        let 源文本 = std::str::from_utf8(字节对).map_err(|_| "不是 ASCII".to_owned())?;
        let 字节值 = u8::from_str_radix(源文本, 16).map_err(|_| format!("`{源文本}` 不是十六进制字节"))?;
        累积表.push(字节值);
    }
    Ok(累积表)
}

fn 读JSON件(路径: &Path) -> Result<JSON值, String> {
    let 源文本 = std::fs::read_to_string(路径).map_err(|错误| format!("读不到 {}：{错误}", 路径.display()))?;
    最小JSON::解析JSON值(&源文本).map_err(|错误| format!("{} 不是合法 JSON：{错误}", 路径.display()))
}

fn 要串<'a>(容器值: &'a JSON值, 键名: &str) -> Result<&'a str, String> {
    容器值.取成员(键名).and_then(|成员值| 成员值.取字符串()).ok_or_else(|| format!("缺 `{键名}`（或不是字符串）"))
}

fn 要整数(容器值: &JSON值, 键名: &str, 路径: &Path) -> Result<u32, String> {
    容器值.取成员(键名)
        .and_then(|成员值| 成员值.取整数())
        .and_then(|整数值| u32::try_from(整数值).ok())
        .ok_or_else(|| format!("{}：`{键名}` 缺失或不是 32 位整数", 路径.display()))
}

fn 要真假(容器值: &JSON值, 键名: &str) -> Result<bool, String> {
    容器值.取成员(键名).and_then(|成员值| 成员值.真假()).ok_or_else(|| format!("缺 `{键名}`（或不是 true/false）"))
}

