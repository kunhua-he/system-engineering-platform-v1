//! 比对：`期望.json` 写的那一条 vs 观测到的读数。
//!
//! # 「不符」与「工具错」必须分开
//!
//! - `判定::不符` = **案例失败**（写回执，退出码 1）：被测对象没做到期望的事。
//! - `Err(…)` = **工具错误**（不写回执，退出码 2）：判据的输入坏了（例如比对目标读不到）。
//!
//! 混在一起，后人就分不清「对象坏了」与「尺子坏了」——`判据的可信性.md` 第三节第 5 条
//! 把「判据的解析器坏了」列为假绿来源之一。

use std::path::Path;

use crate::案例::{产物判据, 期望};
use crate::观测::{观测, 观测产物};
use crate::案例 as 案例件;

// ════════════════════════════════════════════════════════════════════════════
// 比对：期望 vs 观测
// ════════════════════════════════════════════════════════════════════════════

/// 一步的判定。**「不符」与「工具错」必须分开**：前者是案例失败（写回执，退出 1），
/// 后者是判据的输入坏了（不写回执，退出 2）。
pub(crate) enum 判定 {
    通过(String),
    不符(String),
}

pub(crate) fn 比对(期望: &期望, 观: &观测, 目录: &Path) -> Result<判定, String> {
    match 期望 {
        期望::失败 { 死在哪一层, 错误码, 产物 } => {
            if 观.结果 == "成功" {
                return Ok(判定::不符(format!("期望失败，实到成功（{}）", 观.说明)));
            }
            let 实到层 = 观.死在哪一层.clone().unwrap_or_default();
            if 实到层 != *死在哪一层 {
                return Ok(判定::不符(format!(
                    "期望死在 `{死在哪一层}`，实到 `{实到层}`（{}）",
                    观.说明
                )));
            }
            let 实到 = 观
                .错误码
                .clone()
                .ok_or_else(|| format!("期望错误码，实到没有码（{}）", 观.说明))?;
            let 差 = [
                (实到.码 == 错误码.码, format!("码 期望 {} 实到 {}", 错误码.码, 实到.码)),
                (
                    实到.名称 == 错误码.名称,
                    format!("名称 期望 `{}` 实到 `{}`", 错误码.名称, 实到.名称),
                ),
                (
                    实到.可重试 == 错误码.可重试,
                    format!("可重试 期望 {} 实到 {}", 错误码.可重试, 实到.可重试),
                ),
                (
                    实到.可自愈 == 错误码.可自愈,
                    format!("可自愈 期望 {} 实到 {}", 错误码.可自愈, 实到.可自愈),
                ),
                (
                    实到.需人工 == 错误码.需人工,
                    format!("需人工 期望 {} 实到 {}", 错误码.需人工, 实到.需人工),
                ),
            ]
            .into_iter()
            .filter(|(过, _)| !过)
            .map(|(_, 说)| 说)
            .collect::<Vec<_>>();
            if !差.is_empty() {
                return Ok(判定::不符(format!("错误码不符：{}", 差.join("；"))));
            }
            match 比对产物(产物, 观, 目录)? {
                判定::通过(_) => Ok(判定::通过(format!("{} ｜ {}", 观.说明, 观.产物说明()))),
                判定::不符(差) => Ok(判定::不符(差)),
            }
        }
        期望::成功 { 产物 } => {
            if 观.结果 != "成功" {
                return Ok(判定::不符(format!("期望成功，实到失败（{}）", 观.说明)));
            }
            比对产物(产物, 观, 目录)
        }
    }
}

/// 产物判据的比对。**失败时的返回槽也走这一条**——「未命中返回空」是宪法第 6 条，
/// 它和「成功时返回了什么」用的是同一把尺子。
pub(crate) fn 比对产物(判据: &产物判据, 观: &观测, 目录: &Path) -> Result<判定, String> {
    match 判据 {
        产物判据::不判 => Ok(判定::通过(观.产物说明())),
        产物判据::空槽 => {
            if matches!(观.产物, 观测产物::空槽) {
                Ok(判定::通过("返回槽是空槽".to_owned()))
            } else {
                Ok(判定::不符(format!("期望空槽，实到 {}", 观.产物说明())))
            }
        }
        产物判据::错误槽(期望码) => match &观.产物 {
            观测产物::错误槽(码) if 码 == 期望码 => Ok(判定::通过(format!("返回槽是错误槽 码 {码}"))),
            _ => Ok(判定::不符(format!(
                "期望错误槽 码 {期望码}，实到 {}",
                观.产物说明()
            ))),
        },
        产物判据::非空字节集 => match &观.产物 {
            观测产物::字节集(字节) if !字节.is_empty() => {
                Ok(判定::通过(format!("返回 {} 字节", 字节.len())))
            }
            _ => Ok(判定::不符(format!("期望非空字节集，实到 {}", 观.产物说明()))),
        },
        产物判据::逐字节等于文件(路) => {
            let 实路 = 案例件::解路(目录, 路);
            let 期望字节 =
                std::fs::read(&实路).map_err(|错| format!("读不到比对目标 {}：{错}", 实路.display()))?;
            match &观.产物 {
                观测产物::字节集(字节) if 字节 == &期望字节 => Ok(判定::通过(format!(
                    "逐字节等于 {}（{} 字节）",
                    实路.display(),
                    字节.len()
                ))),
                观测产物::字节集(字节) => Ok(判定::不符(首处差异(字节, &期望字节, &实路))),
                _ => Ok(判定::不符(format!("期望字节集，实到 {}", 观.产物说明()))),
            }
        }
    }
}

impl 观测 {
    fn 产物说明(&self) -> String {
        match &self.产物 {
            观测产物::空槽 => "空槽".to_owned(),
            观测产物::字节集(字节) => format!("字节集 {} 字节", 字节.len()),
            观测产物::错误槽(码) => format!("错误槽 码 {码}"),
            观测产物::其他 => "其他形状".to_owned(),
        }
    }
}

/// 逐字节比对失败时**报出第一处差异的偏移**（不给偏移，后人只能猜）。
fn 首处差异(实到: &[u8], 期望: &[u8], 路: &Path) -> String {
    let 共 = 实到.len().min(期望.len());
    match (0..共).find(|位| 实到[*位] != 期望[*位]) {
        Some(位) => format!(
            "与 {} 不逐字节相同：首处差异在偏移 {位}（实到 {:#04x}，期望 {:#04x}）；实到 {} 字节、期望 {} 字节",
            路.display(),
            实到[位],
            期望[位],
            实到.len(),
            期望.len()
        ),
        None => format!(
            "与 {} 前 {共} 字节相同但长度不同：实到 {} 字节、期望 {} 字节",
            路.display(),
            实到.len(),
            期望.len()
        ),
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use crate::案例::错误码期望;
    use crate::错误码::登记;
    use std::path::PathBuf;

    fn 造观测(结果: &'static str, 层: Option<&str>, 码: Option<登记>, 产物: 观测产物) -> 观测 {
        观测 {
            结果,
            死在哪一层: 层.map(str::to_owned),
            死在哪一步: Some("调度".to_owned()),
            错误码: 码,
            能力名: Some("首项".to_owned()),
            产物,
            说明: "读数".to_owned(),
        }
    }

    fn 登记1() -> 登记 {
        登记 {
            码: 1,
            段位: 0,
            名称: "提供者未载入".to_owned(),
            可重试: true,
            可自愈: true,
            需人工: false,
            已登记: true,
        }
    }

    fn 期失败(层: &str, 需人工: bool) -> 期望 {
        期望::失败 {
            死在哪一层: 层.to_owned(),
            错误码: 错误码期望 {
                码: 1,
                名称: "提供者未载入".to_owned(),
                可重试: true,
                可自愈: true,
                需人工,
            },
            产物: 产物判据::不判,
        }
    }

    /// 正向样本：期望失败 + 层对 + 码与三项全对 ⇒ 通过。
    #[test]
    fn 期望失败对得上就通过() {
        let 实 = 造观测("失败", Some("内核"), Some(登记1()), 观测产物::空槽);
        assert!(matches!(比对(&期失败("内核", false), &实, Path::new("/首案例")), Ok(判定::通过(_))));
    }

    /// 反向样本：层错 ⇒ 报层（先报最粗的那一层，不往下比码）。
    #[test]
    fn 层错就报层() {
        let 实 = 造观测("失败", Some("内核"), Some(登记1()), 观测产物::空槽);
        let 判定值 = 比对(&期失败("扩展", true), &实, Path::new("/首案例"));
        assert!(
            matches!(&判定值, Ok(判定::不符(错)) if 错.contains("期望死在 `扩展`")),
            "该报层不符，实到 {}",
            描述(&判定值)
        );
    }

    /// 反向样本：层对上了，三项业务判断里错一条也要逐条报出来。
    #[test]
    fn 业务判断错就报那一条() {
        let 实 = 造观测("失败", Some("内核"), Some(登记1()), 观测产物::空槽);
        let 判定值 = 比对(&期失败("内核", true), &实, Path::new("/首案例"));
        assert!(
            matches!(&判定值, Ok(判定::不符(错)) if 错.contains("需人工")),
            "该报需人工不符，实到 {}",
            描述(&判定值)
        );
    }

    /// 反向样本：期望失败实到成功，必须报红（不是「差不多算通过」）。
    #[test]
    fn 期望失败实到成功要报红() {
        let 实 = 造观测("成功", None, None, 观测产物::空槽);
        let 判定值 = 比对(&期失败("内核", false), &实, Path::new("/首案例"));
        assert!(matches!(判定值, Ok(判定::不符(_))), "该报不符，实到 {}", 描述(&判定值));
    }

    /// 正向/反向样本：逐字节比对必须报出**第一处差异的偏移**与长度差。
    #[test]
    fn 逐字节比对报偏移() {
        let 临时件路径 = 临时路("首案例");
        std::fs::write(&临时件路径, b"abcd").unwrap();
        let 期 = 期望::成功 { 产物: 产物判据::逐字节等于文件(临时件路径.clone()) };
        let 同 = 比对(&期, &造观测("成功", None, None, 观测产物::字节集(b"abcd".to_vec())), Path::new("/"));
        assert!(matches!(同, Ok(判定::通过(_))), "该通过，实到 {}", 描述(&同));
        let 异 = 比对(&期, &造观测("成功", None, None, 观测产物::字节集(b"abXd".to_vec())), Path::new("/"));
        assert!(matches!(&异, Ok(判定::不符(错)) if 错.contains("偏移 2")), "实到 {}", 描述(&异));
        let 短 = 比对(&期, &造观测("成功", None, None, 观测产物::字节集(b"ab".to_vec())), Path::new("/"));
        assert!(matches!(&短, Ok(判定::不符(错)) if 错.contains("长度不同")), "实到 {}", 描述(&短));
        let _ = std::fs::remove_file(&临时件路径);
    }

    /// 工具错误：比对目标读不到 ⇒ `Err`（不写回执），**不许**当成案例失败。
    #[test]
    fn 比对目标读不到是工具错误() {
        let 期 = 期望::成功 { 产物: 产物判据::逐字节等于文件(PathBuf::from("/绝对不存在")) };
        assert!(比对(&期, &造观测("成功", None, None, 观测产物::字节集(vec![1])), Path::new("/")).is_err());
    }

    /// 期望空槽：返回了东西就该报红（「保留项不是假成功」就靠这一条）。
    #[test]
    fn 期望空槽时返回了东西要报红() {
        let 期 = 期望::成功 { 产物: 产物判据::空槽 };
        let 实 = 造观测("成功", None, None, 观测产物::字节集(vec![1]));
        let 判定值 = 比对(&期, &实, Path::new("/"));
        assert!(matches!(判定值, Ok(判定::不符(_))), "该报不符，实到 {}", 描述(&判定值));
    }

    /// 判定的可读描述（只为报错信息，不是判定逻辑）。
    fn 描述(判定值: &Result<判定, String>) -> String {
        match 判定值 {
            Ok(判定::通过(读)) => format!("通过（{读}）"),
            Ok(判定::不符(差)) => format!("不符（{差}）"),
            Err(错) => format!("工具错误（{错}）"),
        }
    }

    fn 临时路(名: &str) -> std::path::PathBuf {
        let 路 = std::env::temp_dir().join(format!("跑案例测试-{名}-{}", std::process::id()));
        let _ = std::fs::remove_file(&路);
        路
    }
}

