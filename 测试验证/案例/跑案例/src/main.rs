//! 跑案例 —— **端到端主门禁**。用真案例跑真链路，跑不通当场自爆。
//!
//! 形状与口径的权威是 `测试验证/案例/形状.md`；本文件是**入口：只做路由，零实现**。
//!
//! ```text
//! 测试验证/案例/跑案例/         ← 本程序（crate `v1-case-runner`）
//!   案例.json                  做什么：步骤链（能力编号 + 按契约行序的实参来源）
//!   输入.程序文本               真程序文本（我们的原生格式）；「程序」类案例必有
//!   期望.json                  期望什么：按步骤一一对应（运行结果 或 诊断）
//! ```
//!
//! 文件分工：
//!
//! - `最小JSON.rs` —— 案例文件的读写件（零第三方依赖；不是平台能力）
//! - `案例.rs` —— 案例形状与读盘（**唯一事实源是磁盘上的案例目录**）
//! - `装载声明.rs` —— 经接缝 `GetPlatformInfo` 取被验扩展的声明
//! - `错误码.rs` —— 错误码登记 + 「死在哪一层」的映射（不自行编任何一层名）
//! - `回执.rs` —— 运行回执的形状 · git 读数 · 追加一行
//! - `观测.rs` —— 观测一步：读返回槽 → 「层 + 层内位置 + 错误码 + 产物」
//! - `判定.rs` —— 期望 vs 观测的比对（不符 / 工具错 分得开）
//! - `跑.rs` —— 主流程：逐案例 · 逐步骤 · 汇总 · 追加回执
//!
//! 退出码：`0` 全过 / `1` 有案例失败 / `2` 工具错误（判据的输入坏了，不写回执）。

