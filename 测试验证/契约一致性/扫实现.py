def _本表(u: dict) -> dict:
    """本单元内可解析的整数符号（能力号 · 错误码 · 本文件 const）。"""
    表 = {}
    for c in u["能力号"]:
        if c["值"] is not None:
            表[c["名"]] = c["值"]
    for c in u.get("错误码常量", []):
        if c["值"] is not None:
            表[c["名"]] = c["值"]
    表.update(u.get("本文件整数常量", {}))
    return 表


def _按编号找命令(u: dict, n) -> object:
    for c in u["命令"]:
        if c["编号"] == n:
            return c
    return None


def _参数表名(条: dict) -> object:
    原 = 条["字段"].get("参数表", {}).get("原文")
    if 原 is None:
        return None
    m = re.match(r"([^\s.]+)", 原.strip())
    if not m:
        return None
    名 = m.group(1)
    if "::" in 名 or 名 in ("core", "std", "null"):
        return None  # 路径表达式（`core::ptr::null()` 之类）不是本地参数表名
    return 名


