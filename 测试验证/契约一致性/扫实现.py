def 读盘(仓根: str, 范围: list) -> dict:
    根 = Path(仓根)
    件表 = {}
    坏 = []

    def 收(路径: Path):
        键 = 相对(根, 路径)
        try:
            if 路径.stat().st_size > 读上限字节:
                坏.append((键, f"超过读上限 {读上限字节} 字节（不截断——截断会让解析腿拿到半个文件）"))
                return
            件表[键] = 路径.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as 错:
            坏.append((键, f"读不动：{错}"))

    for r in 范围:
        基 = 根 / r
        if not 基.is_dir():
            continue
        for 根目录, 目录表, 文件表 in os.walk(基):
            目录表[:] = [d for d in 目录表 if d not in {".git", "__pycache__", "构建缓存", "target"}]
            for 名 in 文件表:
                if 名.endswith((".rs", ".json")) or 名 == "Cargo.toml":
                    收(Path(根目录) / 名)
    契约 = 根 / 契约目录名
    if 契约.is_dir():
        for 根目录, 目录表, 文件表 in os.walk(契约):
            目录表[:] = [d for d in 目录表 if d not in {"__pycache__"}]
            for 名 in 文件表:
                if 名.endswith(".json") or (名 in ("lib.rs", "声明数据.rs") and "src" in 根目录):
                    收(Path(根目录) / 名)
    return {"件表": 件表, "坏": 坏}


def 常量表名集(件表: dict) -> set:
    文 = 件表.get(常量表相对)
    if not 文:
        return set()
    try:
        数 = json.loads(文)
    except json.JSONDecodeError:
        return set()
    出 = set()
    for c in 数.get("常量") or []:
        if isinstance(c, dict) and isinstance(c.get("名"), str):
            出.add(c["名"])
    return 出


def _扫一遍(仓根: str, 范围: list, 件表=None, 坏=None) -> list:
    if 件表 is None:
        r = 读盘(仓根, 范围)
        件表, 坏 = r["件表"], r["坏"]
    坏 = 坏 or []
    掩表 = {k: 掩码(v) for k, v in 件表.items() if k.endswith(".rs") and v is not None}
    夹具 = 建夹具集(件表, 掩表)
    符号表 = 建符号表(件表, 掩表)
    实现面 = 抽实现面(件表, 范围, 符号表, 夹具, 掩表)
    声明根表 = 读声明侧(件表)
    比对结果 = 比对(实现面, 声明根表, 符号表, 常量表名集(件表))
    # 读不动的文件：不许静默——挂到第一条判据的明细上（位置与原因都具体）
    for 键, 因 in 坏:
        比对结果[判据名表[0]]["明细"].append(
            记(判据名表[0], "未判", 键,
               f"判不了：这个文件读不动（{因}）⇒ 它可能是实现面或声明面的一部分，漏读就是漏判",
               "读不动有两种：文件被别的腿写到一半（瞬时），或权限/编码问题（持久）。"
               "验证面不能替它猜内容 ⇒ 只能由该文件的作者确认")
        )
    return _组装(比对结果)


def 扫实现(仓根: str, 范围: list) -> list:
    """**冻结接口**：`扫实现(仓根: str, 范围: list[str]) -> list[dict]`。

    一条判据一条记录（含 `明细`）。内部**连跑两遍**：同一条判据两遍都红才算「源码错」，
    只红一遍的标「疑似瞬时」并不当阻断（`判据的可信性.md` §四.1）。
    """
    r1 = 读盘(仓根, 范围)
    甲 = _扫一遍(仓根, 范围, 件表=r1["件表"], 坏=r1["坏"])
    r2 = 读盘(仓根, 范围)
    if r2["件表"] == r1["件表"] and r2["坏"] == r1["坏"]:
        # 两遍读到的**字节完全一致** ⇒ 判定必然一致（解析是纯函数：同一输入 → 同一输出）。
        # 这一条短路把「连跑两遍」的成本在稳态下变成「只多读一遍文件」（≈10 ms），
        # 而**真变了**的场合仍然会走第二趟解析并逐条比判定 —— 判据的严格性没有放宽。
        return 甲
    乙 = _扫一遍(仓根, 范围, 件表=r2["件表"], 坏=r2["坏"])
    乙表 = {r["项"]: r for r in 乙}
    for r in 甲:
        o = 乙表.get(r["项"])
        if o is None or o["判定"] != r["判定"]:
            r["红类"] = "疑似瞬时" if r["判定"] == "失败" else r["红类"]
            if r["判定"] == "失败":
                r["缺什么"] = (
                    "疑似瞬时（两遍读数不一致）：" + r["缺什么"]
                    + f"｜第二遍的判定是「{o['判定'] if o else '缺'}」"
                )
                r["为什么不能自愈"] = (
                    "两遍读数不一致 ⇒ 多半是别的腿正在写文件（半成品），不是源码问题。"
                    "按 判据的可信性 §四.1：只红一次不当阻断，重跑一次仍红才算 ⇒ 只能等文件写完后重跑"
                )
    return 甲


