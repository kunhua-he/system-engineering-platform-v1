def 自测() -> int:
    """正向样本 + 逐条反向样本。返回 0=全过 / 1=有不过。

    正向样本的断言口径：**干净输入不许报红**（证明判据不误报，`判据的可信性.md` §四.3）。
    干净输入下判成「未判」的（结构性覆盖边界，例如 ③d2）不算误报——它的原因已在
    `缺什么` 里写明，且 `--读数` 会把「正向判定=未判」如实报出。
    """
    好 = True
    print("自测 · 正向样本（干净输入不许报红；结构性未判不算误报）")
    样本 = 造样本()
    结果 = _组装(比对(*_中间(样本)))
    正向 = {}
    for r in 结果:
        正向[r["项"]] = r["判定"]
        if r["判定"] == "失败":
            好 = False
            print(f"  ✗ {r['项']}：干净输入被报红（假红）")
            for d in r["明细"]:
                if d["判定"] == "失败":
                    print(f"      位置 {d['位置']}｜缺什么：{d['缺什么']}")
        else:
            print(f"  ✓ {r['项']}：{r['判定']}")
    print("")
    print("自测 · 反向样本（注入一条该抓的违规 ⇒ 必须报红且报出正确位置）")
    靶 = {短: 判据名表[序] for 短, 序 in 短名表.items()}
    反向 = {}
    for 短名, 说明, 变异 in 反向样本:
        件 = 造样本()
        变异(件)
        结果 = _组装(比对(*_中间(件)))
        命中 = [r for r in 结果 if r["项"] == 靶[短名]]
        过了 = bool(命中) and 命中[0]["判定"] == "失败"
        反向[短名] = 过了
        好 = 好 and 过了
        print(f"  {'✓' if 过了 else '✗'} {短名}：{说明}")
        if 过了:
            for d in 命中[0]["明细"]:
                if d["判定"] == "失败":
                    print(f"      抓到 → {d['位置']}｜缺什么：{d['缺什么'][:140]}")
        else:
            print(f"      没抓到（判定={命中[0]['判定'] if 命中 else '缺记录'}）")
    print("")
    print("自测 · ③d2 反向样本：结构性判不了（命令信息 无该字段）⇒ 无反向样本可造 ⇒ 标「未验证」")
    print("")
    短到长 = {短: 判据名表[序] for 短, 序 in 短名表.items()}
    实测 = {}
    for 名 in 判据名表:
        实测[名] = {
            "正向": 正向.get(名) != "失败",
            "反向": any(反向.get(短) for 短, 长 in 短到长.items() if 长 == 名),
        }
    # 声明必须与实测逐条一致：表比实测宽 ⇒ 报错（不许把没验的写成验过的）
    声明错 = [
        名 for 名 in 判据名表
        if 样本状态[名]["正向"] and not 实测[名]["正向"]
        or 样本状态[名]["反向"] and not 实测[名]["反向"]
    ]
    if 声明错:
        好 = False
        print("  ✗ 样本状态声明与实测不符（声明比实测宽）：")
        for 名 in 声明错:
            print(f"      {名}：声明 {样本状态[名]} vs 实测 {实测[名]}")
    未验 = [名 for 名 in 判据名表 if not (样本状态[名]["正向"] and 样本状态[名]["反向"])]
    for 名 in 未验:
        print(f"  · 未验证：{名}（正向={样本状态[名]['正向']} 反向={样本状态[名]['反向']}）")
    print("")
    # ── 判据器自身机制的身份证：解析器也要有样本（判据的可信性.md §三.5）──
    print("自测 · 判据器自身机制（判据的解析器也是假绿来源，所以它自己也要有身份证）")
    机制 = 自检_整份夹具跳过()
    for 名, 这轮过, 说明 in 机制:
        这轮过 = bool(这轮过)
        好 = 好 and 这轮过
        print(f"  {'✓' if 这轮过 else '✗'} {名}")
        print(f"      {说明}")
    print("")
    # 「为什么不能自愈」必须具体（空话会让定位成本推回维护者）——自测断言不出现空话
    空话 = []
    for r in 结果:
        for d in r["明细"]:
            for 词 in 空话表:
                if 词 in (d["为什么不能自愈"] or ""):
                    空话.append((r["项"], d["位置"], 词))
    if 空话:
        好 = False
        print(f"  ✗ 「为什么不能自愈」里出现空话 {len(空话)} 处（定位成本被推回维护者）：")
        for 项, 位, 词 in 空话[:5]:
            print(f"      {项} ｜ {位} ｜ 「{词}」")
    else:
        print(f"  ✓ 「为什么不能自愈」全部具体（{sum(len(r['明细']) for r in 结果)} 条明细，"
              f"无 {(' / '.join(空话表))} 之类空话）")
    print("")
    print(f"自测{'全部通过' if 好 else '有不过的用例'}：正向样本 1 份 · 反向样本 {len(反向样本)} 条 · 未验证判据 {len(未验)} 条")
    return 0 if 好 else 1


# 自测样本里的 Rust 形状**拆开拼**（`#` + `[` + 内文 + `]`）。
# 为什么必须拆：本文件是 `.py`，而判据面会用 **Rust 词法**扫 `.py` ——
# `一键验证.py` 的 ⑪/⑫ 扫全仓（`测试验证/` 不在它的排除目录里）且**保留字符串**
# （数导出符号名必须保串）⇒ 直接在源码里写一整条「导出属性 + 引号里的符号名」
# 会被它读成一个**真导出** ⇒ 给判据面造一处假红。
# **实测撞到过两次**：① 样本写成完整形状 ⇒ 读成 `扫实现.py:2405` 的 `夹具导出`；
# ② 连**本段注释**里引一条完整形状也会被读进去（读成 `扫实现.py:2395` 的 `…`）
# ⇒ 本文件里任何地方（含注释与文档串）都不许出现完整形状。
_井 = "#"


def _属(内: str) -> str:
    """把属性内文拼成 `#[内]`（拼出来才是真形状，源码里不是）。"""
    return _井 + "[" + 内 + "]"


def 自检_整份夹具跳过() -> list:
    """整份夹具跳过机制的身份证（反向样本 + 对照）——`判据的可信性.md` §三.5：
    判据的**解析器**自己也是假绿来源，所以它也要有样本。

    反向样本：一份「看起来就是生产代码」的独立 .rs（重定义常量 + 第二个导出符号），
    由**父文件**的 `#[cfg(test)] … mod …;` 挂进来 ⇒ 必须整份跳过（否则就是假红）。
    真仓里出现过的形状都测一遍：`#[path]` 指向**子目录** · mod 名与文件名**不同** ·
    `#[path]` 写在 `#[cfg(test)]` **之前** · cfg 条件里**嵌括号**。
    对照：**不挂** ⇒ 同一份文件必须进实现面（证明「跳过」不是空转）。
    """
    夹具文 = (
        "// 整份夹具：自己文件里没有 cfg 测试标记\n"
        "pub const 号段类宽度: u32 = 1000;\n"
        + _属('unsafe(export_name = "夹具导出")') + "\n"
        + 'pub extern "C" fn 夹具() {}\n'
    )
    形状 = (
        ("`#[path]` 指向子目录 · mod 名与文件名不同",
         _属("cfg(test)") + "\n" + _属('path = "子/夹具.rs"') + "\nmod 测试;\n"),
        ("`#[path]` 写在 `#[cfg(test)]` 之前",
         _属('path = "子/夹具.rs"') + "\n" + _属("cfg(test)") + "\nmod 测试;\n"),
        ('cfg 条件里嵌括号（`#[cfg(any(test, feature = "x"))]`）',
         _属('cfg(any(test, feature = "x"))') + "\n" + _属('path = "子/夹具.rs"') + "\nmod 测试;\n"),
    )
    出 = []
    键夹具 = "p/src/子/夹具.rs"
    for 名, 挂载 in 形状:
        件 = {"p/src/lib.rs": 挂载, 键夹具: 夹具文}
        夹 = 建夹具集(件, {k: 掩码(v) for k, v in 件.items()})
        出.append(
            (
                f"反向样本：整份夹具被跳过（{名}）",
                键夹具 in 夹["整份夹具"],
                f"整份夹具={sorted(夹['整份夹具'])}",
            )
        )
    # 对照：用正向样本仓（造样本）——把父文件里那一行挂载声明**删掉**，同一份夹具必须进实现面。
    # 为什么不用合成的 p/ 仓：这里要的是「真判据会不会报红」，只有跑完整比对才算数。
    靶 = {短: 判据名表[序] for 短, 序 in 短名表.items()}
    挂载行 = _属("cfg(test)") + "\n" + _属('path = "测试夹具.rs"') + "\npub(crate) mod 测试夹具;\n"
    样本 = 造样本()
    件 = dict(样本)
    件["运行内核/装载入口/src/lib.rs"] = 样本["运行内核/装载入口/src/lib.rs"].replace(挂载行, "")
    挂了 = _组装(比对(*_中间(样本)))
    没挂 = _组装(比对(*_中间(件)))
    挂了红 = [r["项"] for r in 挂了 if r["判定"] == "失败"]
    没挂红 = [r["项"] for r in 没挂 if r["判定"] == "失败"]
    出.append(
        (
            "对照：不挂载 ⇒ 同一份夹具进实现面并被抓到（证明「跳过」不是空转）",
            not 挂了红 and 靶["③i"] in 没挂红,
            f"挂载：失败 {挂了红 or '无'} · 不挂载：失败 {没挂红}",
        )
    )
    return 出


def _中间(件表: dict):
    夹具 = 建夹具集(件表)
    符号表 = 建符号表(件表)
    实现面 = 抽实现面(件表, 默认范围, 符号表, 夹具)
    声明根表 = 读声明侧(件表)
    return 实现面, 声明根表, 符号表, 常量表名集(件表)


