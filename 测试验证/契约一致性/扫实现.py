def 比对(实现面: dict, 声明根表: dict, 符号表: dict, 常量表名: set) -> dict:
    """返回 {判据名: {"明细": [...], "扫描面": str, "扫描读数": str, "已判": int}}。

    口径（为什么这样切）：③a–③d、③f 的判据对象是「**一份声明** ↔ 它的实现」，所以按
    **声明根**驱动，不是按 crate 驱动 —— 内核内部那些不对外提供能力的 crate（内存分配器 ·
    定长数据槽 · 统一注册表 …）不属于任何一份声明，把它们按 crate 报「空集」只会把真信号埋掉。
    它们仍然进 ③e（用到的类型标签）与 ③j（定义的常量）。这个切法在 `扫描读数` 里如实报出。

    `已判` = 这条判据**实际比对了多少项**。它存在的唯一理由：让「比过之后全对」与
    「没东西可比」在读数上分开（`判据的可信性.md` §二：空集不许算通过）。
    """
    出 = {名: {"明细": [], "扫描面": "", "扫描读数": "", "已判": 0} for 名 in 判据名表}
    计数 = 实现面["计数"]
    单元表 = 实现面["单元"]
    件表 = 实现面["件表"]
    夹具 = 实现面["夹具"]

    # ── 声明根 → 实现单元 ──
    根到单元 = {}
    for 根 in sorted(声明根表):
        if 根 == 底座声明根:
            根到单元[根] = [u for u in 单元表 if u["目录"] == 底座实现落点]
        else:
            根到单元[根] = [
                u for u in 单元表 if u["目录"] == 根 or u["目录"].startswith(根 + "/")
            ]
    无声明根单元 = [
        u
        for u in 单元表
        if not any(u in v for v in 根到单元.values())
    ]
    有表单元 = [
        u for u in 单元表 if u["命令表项数集"] or u["函数表项数集"]
    ]

    声明扫描面 = "；".join(
        f"{r}=能力声明 {len(声明根表.get(r, {}).get('能力声明', {}))} 份 · "
        f"错误码表 {len(声明根表.get(r, {}).get('错误码表', {}))} 份 · "
        f"类型声明 {len(声明根表.get(r, {}).get('类型声明', {}))} 份"
        for r in sorted(声明根表)
    ) or "（无声明根）"
    面 = (
        f"实现面=范围下的 *.rs 生产区（跳过 #[cfg(test)] 块与整份夹具文件）；"
        f"声明面=契约声明/**.json + 扩展声明根/**.json（{声明扫描面}）；"
        f"引用表={生成物相对} + {契约源相对}（只读解析符号，不计入实现面）"
    )
    读 = (
        f"读 {计数['文件']} 个 .rs 生产区（整份夹具跳过 {计数['夹具文件']} 个）；"
        f"另读声明面与清单件（.json / Cargo.toml）"
        f"{计数.get('件表总数', 0) - 计数['文件'] - 计数['夹具文件']} 个；"
        f"跳过 #[cfg(test)] 块 {计数['夹具块']} 处；其它 cfg 属性 {计数['其它cfg']} 处；"
        f"macro_rules! 0 处 · include! 0 处（范围内实测）；"
        f"抽到 单元 {len(单元表)} 个（其中带声明根 {len(单元表) - len(无声明根单元)} 个 · "
        f"不带声明根 {len(无声明根单元)} 个 · 带命令/函数表 {len(有表单元)} 个）· "
        f"能力号 {计数['能力号']} 项 · 命令 {计数['命令']} 条 · "
        f"参数表 {计数['参数表']} 张 · 类型表 {计数['类型表']} 项 · 错误码 {计数['错误码']} 条 · "
        f"导出 {计数['导出']} 个 · 常量 {计数['常量']} 项"
    )
