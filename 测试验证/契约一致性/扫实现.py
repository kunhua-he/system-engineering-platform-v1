"""扫实现 —— 闸 2 · 实现侧（验证流程图 ②扫实现 · ③比对 a–j）：**声明 ↔ 实现** 的一致性。

`构建装配/一键验证/一键验证.py` 查的是**声明侧**；本模块查**另一半**：实现 ↔ 声明。
两半合起来，才能同时抓住「改了实现忘了改声明」与「改了声明忘了改实现」。

完整契约（判据来源 · 扫描面 · 覆盖边界 · 冻结接口 · 红类三分）见
`扫实现/模块说明.py` 的文件头。

本文件是**路由**：声明子模块 → 再导出公开面 → **零实现**。判据本体在 `扫实现/`
（一个关注点一个文件）。

在仓库根执行（只用标准库）：

    python3 测试验证/契约一致性/扫实现.py             # 默认范围
    python3 测试验证/契约一致性/扫实现.py --自测       # 正向样本 + 逐条反向样本
    python3 测试验证/契约一致性/扫实现.py --读数       # 加打扫描面与实际读数
    python3 测试验证/契约一致性/扫实现.py --范围 运行内核,扩展根目录

读数四元：`通过 <N> 项 · 失败 <M> 项 · 未判 <K> 项 · 不覆盖 <J> 项`；退出码 0=无失败无未判 / 1=否则。
「不覆盖」是**第四个数**（按格计 = 按设计不覆盖的格数），**不阻塞退出码**；三元（通过/失败/未判）
仍是三元、按判据计、含义不动（唯一登记表 `扫实现/不覆盖.py::不覆盖登记表`）。
**一切计数（`#[cfg(test)]` 处数 · 夹具文件数 · 单元数 …）以 `--读数` 实时报出的为准**——
本文件与子模块的注释都不写死数字（仓在长，写死必漂）。
"""

import sys
import time
from pathlib import Path

起始时刻 = time.monotonic()  # 壳起表点：必须在 import 业务包**之前**（见 构建装配/门禁/壳.py）

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))  # 仓根：取共享门禁
from 构建装配.门禁 import 自门禁  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))

from 扫实现 import (  # noqa: E402
    打印比对结果,
    打印读数,
    扫实现,
    找仓根,
    跑自测,
    默认范围,
)

__all__ = ["默认范围", "找仓根", "扫实现", "跑自测", "打印比对结果", "打印读数"]


def 入口函数(参数: list) -> int:
    """命令行入口：解析参数 → 调公开面 → 打印 → 退出码。"""
    仓根 = 找仓根()
    范围 = 默认范围
    if "--范围" in 参数:
        参数位 = 参数.index("--范围")
        if 参数位 + 1 < len(参数):
            范围 = [范围项 for 范围项 in 参数[参数位 + 1].split(",") if 范围项]
    if "--自测" in 参数:
        return 跑自测()
    区间起点 = time.perf_counter()
    结果 = 扫实现(仓根, 范围)
    毫秒 = int((time.perf_counter() - 区间起点) * 1000)
    打印比对结果(结果, 耗时毫秒=毫秒)
    if "--读数" in 参数:
        print("")
        打印读数(结果)
    失败 = sum(1 for 判据读数 in 结果 if 判据读数["判定"] == "失败")
    未判 = sum(1 for 判据读数 in 结果 if 判据读数["判定"] == "未判")
    return 0 if (失败 == 0 and 未判 == 0) else 1


if __name__ == "__main__":
    # 壳自量自门禁（裁决 §六.1）：`--自测` 也在量程内（§一：范围含 `--自测`）。
    sys.exit(自门禁(起始时刻, 入口函数(sys.argv[1:]), 尾巴余量毫秒=200,
                   修法="本件按范围扫实现面；范围调小（`--范围`）或把重活移出命令路（裁决 §三.3）"))
