def 抽模块常量(掩: str, 键: str, 模块名: str) -> list:
    """`pub mod <模块名> { pub const <名>: <t> = <值>; }` → [{名, 值, 位置}]。"""
    出 = []
    for m in re.finditer(r"pub\s+mod\s+" + re.escape(模块名) + r"\s*\{", 掩):
        止 = 配对(掩, m.end() - 1)
        if 止 < 0:
            continue
        块起 = m.end()
        for c in re.finditer(
            r"pub\s+const\s+([^\s:]+)\s*:\s*[^=;]*?=\s*([^;]+);", 掩[块起:止]
        ):
            v = 解整数(c.group(2))
            出.append(
                {
                    "名": c.group(1),
                    "值": v,
                    "原文": c.group(2).strip(),
                    "位置": f"{键}:{行号(掩, 块起 + c.start())}",
                }
            )
    return 出


def 抽构造器(掩: str, 返回型: str) -> dict:
    """`const fn <名>(<形参>) -> <返回型> { <返回型> { 字段: 值, … } }`

    返回 {构造名: {"形参": [名…], "字段": {字段: ("形参"|"表达式", 文本)}}}。
    """
    出 = {}
    for m in re.finditer(r"const\s+fn\s+([^\s(<]+)\s*\(", 掩):
        形参起 = m.end() - 1
        形参止 = 配对(掩, 形参起)
        if 形参止 < 0:
            continue
        形参名 = []
        for p in 拆顶层项(掩[形参起 + 1 : 形参止]):
            名 = p.split(":", 1)[0].strip()
            if 名:
                形参名.append(名)
        尾 = 掩[形参止 + 1 : 形参止 + 200]
        m2 = re.match(r"\s*->\s*" + re.escape(返回型) + r"\s*\{", 尾)
        if not m2:
            continue
        # `-> 返回型 {` 那个 `{` 是**函数体**的开括号；真正的结构体字面量在它里面。
        # 实测两种写法都有：`-> 命令信息 { 命令信息 { … } }` 与 `-> 命令信息 { …字段… }`，
        # 所以先看函数体里有没有 `<返回型> {`，没有才把函数体本身当字段表。
        体起0 = 形参止 + 1 + m2.end() - 1
        体止0 = 配对(掩, 体起0)
        if 体止0 < 0:
            continue
        体0 = 掩[体起0 + 1 : 体止0]
        m3 = re.search(r"(?:^|[^\w])" + re.escape(返回型) + r"\s*\{", 体0)
        if m3:
            体起 = 体起0 + 1 + m3.end() - 1
            体止 = 配对(掩, 体起)
            if 体止 < 0:
                continue
            体 = 掩[体起 + 1 : 体止]
        else:
            体 = 体0
        字段 = {}
        for f in 拆顶层项(体):
            if ":" in f:
                名, 值 = f.split(":", 1)
                字段[名.strip()] = ("表达式", 值.strip())
            else:
                字段[f.strip()] = ("形参", f.strip())
        出[m.group(1)] = {"形参": 形参名, "字段": 字段}
    return 出


def 抽本文件整数常量(掩: str) -> dict:
    """本文件里能定值的整数常量（含 `能力号段[0].止 as usize + 1` 这一种）。"""
    表 = {}
    for m in re.finditer(r"(?:^|\n)[ \t]*(?:pub\s+)?const\s+([^\s:]+)\s*:", 掩):
        名 = m.group(1)
        位 = m.end()
        _, 值文, _ = _切声明(掩, 位)
        v = 解整数(值文)
        if v is not None:
            表[名] = v
            continue
        # const 命令表项数: usize = 能力号段[0].止 as usize + 1;
        m2 = re.fullmatch(r"([^\s\[]+)\s*\[\s*(\d+)\s*\]\s*\.\s*止\s+as\s+usize\s*\+\s*(\d+)", 值文 or "")
        if m2:
            段名, 序, 加 = m2.group(1), int(m2.group(2)), int(m2.group(3))
            m3 = re.search(
                r"const\s+" + re.escape(段名) + r"\s*:\s*\[[^\]]*\]\s*=\s*\[([^\]]*)\]",
                掩,
            )
            if m3:
                项 = 拆顶层项(m3.group(1))
                if 序 < len(项):
                    内 = re.search(r"\(\s*(\d+)\s*,\s*(\d+)\s*\)", 项[序])
                    if 内:
                        表[名] = int(内.group(2)) + 加
    return 表


def _切声明(掩: str, 位: int):
    """从 `位` 起切一个 const/static 声明：返回 (类型文, 值文, 止位)。"""
    深 = 0
    i = 位
    类型起 = 位
    while i < len(掩):
        c = 掩[i]
        if c in "([{":
            深 += 1
        elif c in ")]}":
            深 -= 1
        elif 深 == 0 and c == "=":
            值起 = i + 1
            值止 = 找顶层终止(掩, 值起, ";")
            if 值止 < 0:
                return 掩[类型起:i].strip(), 掩[值起:].strip(), len(掩)
            return 掩[类型起:i].strip(), 掩[值起:值止].strip(), 值止 + 1
        elif 深 == 0 and c == ";":
            return 掩[类型起:i].strip(), None, i + 1
        i += 1
    return None, None, len(掩)


def 抽数组表(掩: str, 元素型: str) -> list:
    """抽 `(const|static) <名>: [<元素型>; <N>] = [ … ];` 与
    `const fn <名>() -> [<元素型>; <N>] { … }` 的声明项数。"""
    出 = []
    for m in re.finditer(
        r"(?:const|static)\s+([^\s:]+)\s*:\s*\[\s*" + re.escape(元素型)
        + r"\s*;\s*([^\]]+)\]\s*=\s*",
        掩,
    ):
        表名 = m.group(1)
        项数文 = m.group(2).strip()
        rhs起 = m.end()
        分号 = 找顶层终止(掩, rhs起, ";")
        rhs = 掩[rhs起:分号].strip() if 分号 > 0 else 掩[rhs起:].strip()
        出.append(
            {
                "表名": 表名,
                "项数原文": 项数文,
                "值原文": rhs,
                "位置": f"{行号(掩, m.start())}",
                "内文": (掩[rhs起 + 1 : 配对(掩, rhs起)] if rhs.startswith("[") else None),
                "内文起": rhs起 + 1,
            }
        )
    for m in re.finditer(
        r"const\s+fn\s+([^\s(<]+)\s*\(\s*\)\s*->\s*\[\s*" + re.escape(元素型)
        + r"\s*;\s*([^\]]+)\]\s*\{",
        掩,
    ):
        体起 = m.end() - 1
        体止 = 配对(掩, 体起)
        if 体止 < 0:
            continue
        出.append(
            {
                "表名": m.group(1),
                "项数原文": m.group(2).strip(),
                "值原文": m.group(1) + "()",
                "位置": f"{行号(掩, m.start())}",
                "内文": 掩[体起 + 1 : 体止],
                "内文起": 体起 + 1,
                "是函数": True,
            }
        )
    return 出


def 抽参数表(掩: str, 键: str, 符号表: dict) -> dict:
    出 = {}
    for m in re.finditer(
        r"(?:const|static)\s+([^\s:]+)\s*:\s*\[\s*参数信息\s*;\s*([^\]]+)\]\s*=\s*\[",
        掩,
    ):
        起 = m.end() - 1
        止 = 配对(掩, 起)
        if 止 < 0:
            continue
        内 = 掩[起 + 1 : 止]
        项 = 拆顶层项(内)
        标签 = []
        for t in 项:
            t2 = t.split("{", 1)[1] if "{" in t else t
            mm = re.search(r"类型标签\s*:\s*([^,}]+)", t2)
            标签.append(mm.group(1).strip() if mm else None)
        项数文 = m.group(2).strip()
        出[m.group(1)] = {
            "项数": 解整数(项数文) if 解整数(项数文) is not None else len(项),
            "项数原文": 项数文,
            "类型标签原文": 标签,
            "位置": f"{键}:{行号(掩, m.start())}",
        }
    return 出


def 抽类型表(掩: str, 键: str) -> list:
    出 = []
    for m in re.finditer(
        r"(?:const|static)\s+([^\s:]+)\s*:\s*\[\s*数据类型信息\s*;\s*([^\]]+)\]\s*=\s*\[",
        掩,
    ):
        起 = m.end() - 1
        止 = 配对(掩, 起)
        if 止 < 0:
            continue
        for t in 拆顶层项(掩[起 + 1 : 止]):
            if "{" not in t:
                continue
            内 = t.split("{", 1)[1]
            mm = re.search(r"类型标签\s*:\s*([^,}]+)", 内)
            出.append(
                {
                    "表名": m.group(1),
                    "类型标签原文": mm.group(1).strip() if mm else None,
                    "位置": f"{键}:{行号(掩, m.start())}",
                }
            )
    return 出


def 抽错误码表(掩: str, 键: str, 符号表: dict, 本表: dict) -> dict:
    出 = {"表": [], "来源": None, "位置": None}
    for m in re.finditer(
        r"(?:const|static)\s+([^\s:]+)\s*:\s*\[\s*错误码信息\s*;\s*([^\]]+)\]\s*=\s*\[",
        掩,
    ):
        起 = m.end() - 1
        止 = 配对(掩, 起)
        if 止 < 0:
            continue
        构造 = 抽构造器(掩, "错误码信息")
        段位表达式 = None
        for 名, c in 构造.items():
            f = c["字段"].get("段位")
            if f and f[0] == "表达式":
                段位表达式 = f[1]
        for t in 拆顶层项(掩[起 + 1 : 止]):
            t = t.strip()
            if "{" in t:
                内 = t.split("{", 1)[1]
                码文 = re.search(r"(?:^|,)\s*码\s*:\s*([^,}]+)", 内)
                段文 = re.search(r"(?:^|,)\s*段位\s*:\s*([^,}]+)", 内)
                码 = 解符号(码文.group(1), 符号表, 本表) if 码文 else None
                段 = 解符号(段文.group(1), 符号表, 本表) if 段文 else None
            else:
                mm = re.match(r"([^\s(]+)\s*\((.*)\)\s*$", t, re.S)
                if not mm:
                    continue
                实参 = 拆顶层项(mm.group(2))
                码 = 解符号(实参[0], 符号表, 本表) if 实参 else None
                段 = None
                if 段位表达式 and 码 is not None:
                    v = 解符号(段位表达式, {**符号表, "码": 码}, 本表)
                    段 = v
            出["表"].append(
                {"码": 码, "段位": 段, "原文": " ".join(t.split())[:70], "位置": f"{键}:{行号(掩, m.start())}"}
            )
        出["来源"] = "字面量表"
        出["位置"] = f"{键}:{行号(掩, m.start())}"
        return 出
    # 非字面量：`错误码表: 表段::新(v1_contract::声明数据::错误码信息表段()…)`
    m = re.search(r"错误码表\s*:\s*([^,\n}]+)", 掩)
    if m:
        出["来源"] = "生成物"
        出["位置"] = f"{键}:{行号(掩, m.start())}"
        出["原文"] = m.group(1).strip()
    return 出


导出模式 = re.compile(r"#\[\s*(?:unsafe\s*\(\s*)?export_name\s*=")
无修饰模式 = re.compile(r"#\[\s*no_mangle\s*\]")


def 抽导出(掩: str, 原文本: str, 键: str) -> list:
    出 = []
    for m in 导出模式.finditer(掩):
        引 = 原文本.find('"', m.end(), min(len(原文本), m.end() + 200))
        if 引 < 0:
            continue
        终引 = 原文本.find('"', 引 + 1)
        if 终引 < 0:
            continue
        出.append({"符号": 原文本[引 + 1 : 终引], "位置": f"{键}:{行号(掩, m.start())}"})
    for m in 无修饰模式.finditer(掩):
        尾 = 掩[m.end() : m.end() + 300]
        f = re.search(r"fn\s+([^\s(<]+)", 尾)
        出.append(
            {"符号": (f.group(1) if f else "?"), "位置": f"{键}:{行号(掩, m.start())}"}
        )
    return 出


def 抽常量(掩: str, 键: str) -> list:
    出 = []
    for m in re.finditer(r"(?:^|\n)[ \t]*(?:pub\s+)?const\s+([^\s:]+)\s*:", 掩):
        名 = m.group(1)
        _, 值文, _ = _切声明(掩, m.end())
        出.append(
            {
                "名": 名,
                "值文": 值文,
                "值": 解整数(值文),
                "位置": f"{键}:{行号(掩, m.start() + 1)}",
            }
        )
    return 出


def 找所属单元(键: str, 件表: dict) -> str:
    """文件的 crate 根 = **最近的**含 Cargo.toml 的祖先目录（`src/` 在 crate 根下一层）。"""
    段 = 键.split("/")[:-1]
    for i in range(len(段), 0, -1):
        候选 = "/".join(段[:i])
        if f"{候选}/Cargo.toml" in 件表:
            return 候选
    return ""


def 抽实现面(件表: dict, 范围: list, 符号表: dict, 夹具: dict, 掩表: dict = None) -> dict:
    """返回 {"单元": [...], "计数": {...}}。只吃 `范围` 下的 .rs 生产区。"""
    Rs = {
        k: v
        for k, v in 件表.items()
        if k.endswith(".rs") and v is not None and 任内(k, 范围)
    }
    单元表 = {}
    for 键 in Rs:
        目录 = 找所属单元(键, 件表)
        if 目录:
            单元表.setdefault(目录, []).append(键)
    单元 = []
    计数 = {
        "文件": 0, "夹具文件": 0, "夹具块": 0, "其它cfg": 0,
        "能力号": 0, "命令": 0, "占位项": 0, "参数表": 0, "类型表": 0,
        "错误码": 0, "导出": 0, "常量": 0,
    }
    for 目录 in sorted(单元表):
        名配 = re.search(
            r"^\s*name\s*=\s*\"([^\"]+)\"",
            件表.get(f"{目录}/Cargo.toml") or "",
            re.M,
        )
        单元.append(
            {
                "目录": 目录,
                "包名": 名配.group(1) if 名配 else "",
                "文件": sorted(单元表[目录]),
                "能力号": [],
                "错误码常量": [],
                "本文件整数常量": {},
                "命令": [],
                "命令表项数集": [],
                "函数表项数集": [],
                "命令表位置": None,
                "参数表": {},
                "类型表": [],
                "类型标签引用": [],
                "错误码表": {"表": [], "来源": None, "位置": None},
                "导出": [],
                "常量": [],
            }
        )
    索引 = {u["目录"]: u for u in 单元}
    for 目录 in sorted(单元表):
        u = 索引[目录]
        for 键 in sorted(单元表[目录]):
            if 键 in 夹具["整份夹具"]:
                continue  # 整份夹具：由父文件 #[cfg(test)] mod 引入，逐文件解析看不见 cfg(test)
            计数["文件"] += 1
            原 = 件表[键]
            块 = 夹具["块"].get(键, [])
            计数["夹具块"] += len(块)
            掩 = 生产区((掩表 or {}).get(键) or 掩码(原), 块)
            # 能力号 / 错误码 模块常量
            能力号 = 抽模块常量(掩, 键, "能力号")
            错误码 = 抽模块常量(掩, 键, "错误码")
            本文件常量 = 抽本文件整数常量(掩)
            本表 = {
                **{c["名"]: c["值"] for c in 能力号 if c["值"] is not None},
                **{c["名"]: c["值"] for c in 错误码 if c["值"] is not None},
                **本文件常量,
            }
            u["能力号"].extend(能力号)
            u["错误码常量"].extend(错误码)
            u["本文件整数常量"].update(本文件常量)
            计数["能力号"] += len(能力号)
            # 参数表
            参数表 = 抽参数表(掩, 键, 符号表)
            u["参数表"].update(参数表)
            计数["参数表"] += len(参数表)
            # 类型表
            tt = 抽类型表(掩, 键)
            u["类型表"].extend(tt)
            计数["类型表"] += len(tt)
            # 命令表
            构造器 = 抽构造器(掩, "命令信息")
            for 表 in 抽数组表(掩, "命令信息"):
                if 表["表名"] in ("命令信息",):
                    continue
                if 表.get("是函数"):
                    表名 = 表["表名"]
                    内 = 表["内文"]
                    内起 = 表["内文起"]
                    for a in re.finditer(r"本表\s*\[([^\]]+)\]\s*=\s*([^\s(]+)\s*\(", 内):
                        编号 = 解符号(a.group(1), 符号表, 本表)
                        实参起 = a.end() - 1
                        实参止 = 配对(内, 实参起)
                        实参 = 拆顶层项(内[实参起 + 1 : 实参止])
                        字段 = _按构造器解字段(构造器.get(a.group(2)), 实参, 符号表, 本表)
                        u["命令"].append(
                            {
                                "编号": 编号,
                                "编号原文": a.group(1).strip(),
                                "构造": a.group(2),
                                "字段": 字段,
                                "位置": f"{键}:{行号(掩, 内起 + a.start())}",
                            }
                        )
                    计数["命令"] += 1
                    u["命令表项数集"].append((表["项数原文"], f"{键}:{表['位置']}"))
                    u["命令表位置"] = u["命令表位置"] or f"{键}:{表['位置']}"
                else:
                    内 = 表["内文"] or ""
                    内起 = 表["内文起"]
                    for 序, t in enumerate(拆顶层项(内)):
                        if "{" not in t:
                            continue
                        字段 = {}
                        内字段 = t.split("{", 1)[1]
                        if 内字段.rstrip().endswith("}"):
                            内字段 = 内字段.rstrip()[:-1]
                        for f in 拆顶层项(内字段):
                            if ":" in f:
                                名, 值 = f.split(":", 1)
                                名, 值 = 名.strip(), 值.strip()
                            else:
                                名 = 值 = f.strip()
                            字段[名] = {"原文": 值, "值": 解符号(值, 符号表, 本表)}
                        u["命令"].append(
                            {
                                "编号": 序,
                                "编号原文": f"下标 {序}",
                                "构造": "字面量",
                                "字段": 字段,
                                "位置": f"{键}:{行号(掩, 内起 + 内.find(t[:12]))}",
                            }
                        )
                    计数["命令"] += 1
                    u["命令表项数集"].append((表["项数原文"], f"{键}:{表['位置']}"))
                    u["命令表位置"] = u["命令表位置"] or f"{键}:{表['位置']}"
            # 函数表
            for 表 in 抽数组表(掩, "执行函数"):
                if 表["表名"] == "执行函数":
                    continue
                u["函数表项数集"].append((表["项数原文"], f"{键}:{表['位置']}"))
            # 错误码表
            e = 抽错误码表(掩, 键, 符号表, 本表)
            if e["表"] or (e["来源"] and u["错误码表"]["来源"] is None):
                u["错误码表"] = e
                计数["错误码"] += len(e["表"])
            # 类型标签引用（符号）
            for m in re.finditer(r"类型标签_\d+", 掩):
                u["类型标签引用"].append(
                    {"符号": m.group(0), "位置": f"{键}:{行号(掩, m.start())}"}
                )
            # 字面量 类型标签: N（参数信息 / 数据类型信息 / 命令信息 内）
            for m in re.finditer(r"类型标签\s*:\s*(\d+)", 掩):
                u["类型标签引用"].append(
                    {"符号": m.group(1), "位置": f"{键}:{行号(掩, m.start())}"}
                )
            # 导出
            ex = 抽导出(掩, 原, 键)
            u["导出"].extend(ex)
            计数["导出"] += len(ex)
            # 常量
            cs = 抽常量(掩, 键)
            u["常量"].extend(cs)
            计数["常量"] += len(cs)
    # 占位项计数：命令表里带 `占位` 的常量/字段
    计数["占位项"] = sum(
        1
        for u in 单元
        for c in u["常量"]
        if "占位" in (c["名"] or "")
    )
    计数["其它cfg"] = len(夹具["其它cfg"])
    计数["夹具文件"] = len(夹具["整份夹具"])
    计数["件表总数"] = len(件表)
    return {"单元": 单元, "计数": 计数, "件表": 件表, "夹具": 夹具}


def _按构造器解字段(构造, 实参, 符号表, 本表) -> dict:
    """把一次构造器调用的实参映射成 命令信息/错误码信息 的字段。"""
    出 = {}
    if not 构造:
        return 出
    for 字段, (来, 文本) in 构造["字段"].items():
        if 来 == "形参":
            try:
                序 = 构造["形参"].index(文本)
            except ValueError:
                序 = -1
            if 0 <= 序 < len(实参):
                出[字段] = {"原文": 实参[序], "值": 解符号(实参[序], 符号表, 本表)}
        else:
            出[字段] = {"原文": 文本, "值": 解符号(文本, 符号表, 本表)}
    return 出


def 任内(键: str, 范围: list) -> bool:
    return any(键 == p or 键.startswith(p.rstrip("/") + "/") for p in 范围)


