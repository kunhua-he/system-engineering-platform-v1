def 找仓根() -> str:
    for 起 in [Path.cwd(), Path(__file__).resolve().parent, *Path(__file__).resolve().parents]:
        if (起 / 契约目录名).is_dir():
            return str(起)
    return str(Path.cwd())


def main(参数: list) -> int:
    仓根 = 找仓根()
    范围 = 默认范围
    if "--范围" in 参数:
        i = 参数.index("--范围")
        if i + 1 < len(参数):
            范围 = [x for x in 参数[i + 1].split(",") if x]
    if "--自测" in 参数:
        return 自测()
    起 = time.perf_counter()
    结果 = 扫实现(仓根, 范围)
    毫秒 = int((time.perf_counter() - 起) * 1000)
    打印(结果, 耗时毫秒=毫秒)
    if "--读数" in 参数:
        print("")
        打印读数(结果)
    失败 = sum(1 for r in 结果 if r["判定"] == "失败")
    未判 = sum(1 for r in 结果 if r["判定"] == "未判")
    return 0 if (失败 == 0 and 未判 == 0) else 1


