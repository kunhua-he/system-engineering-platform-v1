"""判据导出常量 —— ③i 导出符号（恰好 1 个 GetPlatformInfo）· ③j 常量表同名再定义。"""
from __future__ import annotations

from .常量 import 判据名表, 底座实现落点, 扩展三类, 接缝符号, 常量表相对
from .符号解析 import 解整数
from .判据工具 import 记


def 比导出(出: dict, 单元表: list) -> None:
    """③i：底座与每个扩展**恰好 1 个** `GetPlatformInfo`（全局连接器与网关 第四节判据 2）。"""
    底座单元 = [u for u in 单元表 if u["目录"] == 底座实现落点]
    扩展单元 = [
        u
        for u in 单元表
        if u["目录"].startswith("扩展根目录/")
        and len(u["目录"].split("/")) > 1
        and u["目录"].split("/")[1] in 扩展三类
    ]
    if not 底座单元:
        出[判据名表[9]]["明细"].append(
            记(判据名表[9], "未判", 底座实现落点,
               f"判不了：底座实现落点 {底座实现落点} 下没有带 Cargo.toml 的单元"
               f"（实测单元：{[u['目录'] for u in 单元表]}）",
               "底座是唯一导出契约主结构的实现；落点找不到就判不了「恰好 1 个导出」。"
               "落点写错还是被搬走，只能由实现方确认")
        )
    for u in 底座单元 + 扩展单元:
        出[判据名表[9]]["已判"] += 1
        名 = sorted({e["符号"] for e in u["导出"]})
        if 名 != [接缝符号]:
            情形 = (
                "一个导出都没有 ⇒ 接缝还没接上（该单元还没出 C ABI 面）"
                if not 名
                else f"多出来的就是第二条接缝：{[n for n in 名 if n != 接缝符号]}"
            )
            出[判据名表[9]]["明细"].append(
                记(判据名表[9], "失败",
                   " · ".join(e["位置"] for e in u["导出"]) or f"{u['目录']}/",
                   f"{u['目录']} 导出 {len(名)} 个符号（判据要求恰好 1 个：`{接缝符号}`）："
                   f"{名 or '无'}——{情形}",
                   f"全局连接器与网关 第四节判据 2：接缝只有一个符号 `{接缝符号}`；"
                   f"要提供别的能力一律走命令表（平台信息.命令表 + 函数表），不许再导出第二个符号。"
                   f"多一个导出就是第二条接缝 ⇒ 只能由该单元补（底座不认识任何扩展）", "源码错")
            )


def 比常量(出: dict, 单元表: list, 常量表名: set) -> None:
    """③j：常量表里的同名常量不许在实现侧再定义（按名匹配，见 `模块说明.py` 注 10）。"""
    硬编码 = []
    引用生成物 = []
    for u in 单元表:
        for c in u["常量"]:
            if c["名"] not in 常量表名:
                continue
            值文 = (c["值文"] or "").strip()
            if 解整数(值文) is not None:
                硬编码.append(c)
            else:
                引用生成物.append(c)
    if not 常量表名:
        出[判据名表[10]]["明细"].append(
            记(判据名表[10], "未判", 常量表相对,
               "扫描 0 项：常量表.json 里一条常量都没读到 ⇒ 空集不算通过",
               "常量表是全平台常量的唯一定义处；读不到就没法按名比对 ⇒ 只能由声明方补")
        )
    else:
        出[判据名表[10]]["已判"] += len(常量表名)
        for c in 硬编码:
            出[判据名表[10]]["明细"].append(
                记(判据名表[10], "失败", c["位置"],
                   f"常量名「{c['名']}」在实现侧被再定义，且值是**硬编码字面量**"
                   f"（= {c['值文']}）——`{常量表相对}` 才是唯一定义处（全表 {len(常量表名)} 条）",
                   f"按名匹配：同一个常量名在别处再定义就是第二个来源，值一旦漂移就没有判据能"
                   f"抓住（按值匹配实测判不了：1000 被三个常量共用、8 命中 62 处）。"
                   f"修法是改成引用生成物（`v1_contract::声明数据::…`）——改哪个数只有声明方能定 ⇒ "
                   f"只能由实现方改成引用", "源码错")
            )
        for c in 引用生成物:
            出[判据名表[10]]["明细"].append(
                记(判据名表[10], "未判", c["位置"],
                   f"判不了：常量名「{c['名']}」在实现侧被再定义，但值是**引用**"
                   f"（= {c['值文']}）⇒ 它不是第二来源，只是同名再绑定。"
                   f"判据字面是「同名不许在别处再定义」，意图是「不许造第二来源」——"
                   f"两种读法在这处给出相反的结论",
                   "口径未定：按字面（同名即违规）它该红，按意图（值来自生成物即合规）它该绿。"
                   "选哪种读法是契约侧裁决（改判据字面或改实现命名）⇒ 只能由契约侧裁")
            )
