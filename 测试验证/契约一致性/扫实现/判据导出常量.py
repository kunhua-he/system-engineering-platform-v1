"""判据导出常量 —— ③i 导出符号（名由声明给：扩展恰好 1 个 · 底座 0 个）· ③j 常量表同名再定义。"""
from __future__ import annotations

from .常量 import 判据名表, 底座实现落点, 扩展三类, 常量表相对路径
from .符号解析 import 解整数
from .判据工具 import 记判据


def 比导出(结果: dict, 单元表: list, 目录到导出目标: dict) -> None:
    """③i：导出名**由声明给**（`导出目标`）—— 扩展恰好 1 个 · 底座 0 个。

    口径两半：① 个数（裁决 6：接缝符号只属于可装载件，底座不导出）
    ② **名字逐字来自声明**（`包声明.json` / `平台声明.json` 的 `导出目标`）——
    以前这里拿硬编码常量比，于是「声明说 A、实现导出 B」抓不到（腿实测报的缺口，2026-09-27）。
    """
    底座单元 = [登记单元 for 登记单元 in 单元表 if 登记单元["目录"] == 底座实现落点]
    扩展单元 = [
        登记单元
        for 登记单元 in 单元表
        if 登记单元["目录"].startswith("扩展根目录/")
        and len(登记单元["目录"].split("/")) > 1
        and 登记单元["目录"].split("/")[1] in 扩展三类
    ]
    if not 底座单元:
        结果[判据名表[9]]["明细"].append(
            记判据(判据名表[9], "未判", 底座实现落点,
               f"判不了：底座实现落点 {底座实现落点} 下没有带 Cargo.toml 的单元"
               f"（实测单元：{[登记单元['目录'] for 登记单元 in 单元表]}）",
               "底座是唯一导出契约主结构的实现；落点找不到就判不了「底座一个接缝符号都不许导出」。"
               "落点写错还是被搬走，只能由实现方确认")
        )
    for 登记单元 in 底座单元:
        结果[判据名表[9]]["已判"] += 1
        名称 = sorted({导出项["符号"] for 导出项 in 登记单元["导出"]})
        期望, 根目录 = 目录到导出目标.get(登记单元["目录"], (None, ""))
        if 名称:
            结果[判据名表[9]]["明细"].append(
                记判据(判据名表[9], "失败",
                   " · ".join(导出项["位置"] for 导出项 in 登记单元["导出"]) or f"{登记单元['目录']}/",
                   f"{登记单元['目录']} 导出 {len(名称)} 个符号（判据要求 0 个）：{名称}——"
                   f"底座不是可装载件（没人 dlopen 它），它取自身的声明走 Rust 路径；"
                   f"底座侧也导出同名符号 ⇒ 同二进制里两个同名定义只解析得到一个，底座身份自检恒假",
                   f"裁决 6（`决策记录/2026-09-27_接缝反解与1对1的边界.md` §二）：接缝符号只属于"
                   f"可装载件（扩展），底座不导出 ⇒ 去掉底座侧的 export_name", "源码错")
            )
        elif 期望 is not None:
            结果[判据名表[9]]["明细"].append(
                记判据(判据名表[9], "失败", f"{根目录}/平台声明.json::导出目标",
                   f"声明里 `导出目标` = {期望!r}，而底座**一个符号都没导出** ⇒ 声明与实现相反",
                   f"底座不导出接缝（裁决 6）⇒ 声明里应当明确写 `null`（不导出），"
                   f"写符号名就是「声明在骗人」⇒ 只能由契约设计方改声明", "源码错")
            )
    for 登记单元 in 扩展单元:
        结果[判据名表[9]]["已判"] += 1
        名称 = sorted({导出项["符号"] for 导出项 in 登记单元["导出"]})
        期望, 根目录 = 目录到导出目标.get(登记单元["目录"], (None, ""))
        if 期望 is None:
            结果[判据名表[9]]["明细"].append(
                记判据(判据名表[9], "失败", f"{登记单元['目录']}",
                   f"{登记单元['目录']} 的声明里没有 `导出目标`（或为 null），而它导出 {len(名称)} 个符号："
                   f"{名称 or '无'} ⇒ **导出这件事没有声明**",
                   f"设计文档/导出目标.md §五：手写导出属性是已发生的缺陷（谁都能写一遍、写重了没人拦）"
                   f"⇒ 导出目标必须进声明、由生成器出接缝。缺这个键就退回了手写时代 ⇒ "
                   f"只能由该扩展的声明方补", "源码错")
            )
            continue
        if 名称 != [期望]:
            情形 = (
                "一个导出都没有 ⇒ 接缝还没接上（该单元还没出 C ABI 面）"
                if not 名称
                else f"多出来的就是第二条接缝：{[项名 for 项名 in 名称 if 项名 != 期望]}"
                if 期望 in 名称
                else f"**声明与实现名字不符**：声明说 {期望!r}，实现导出 {名称}"
            )
            结果[判据名表[9]]["明细"].append(
                记判据(判据名表[9], "失败",
                   " · ".join(导出项["位置"] for 导出项 in 登记单元["导出"]) or f"{登记单元['目录']}/",
                   f"{登记单元['目录']} 导出 {len(名称)} 个符号（声明说恰好 1 个：`{期望}`）："
                   f"{名称 or '无'}——{情形}",
                   f"全局连接器与网关 第四节判据 2 + 设计文档/导出目标.md §五：接缝只有一个符号，"
                   f"它的名字由声明的 `导出目标` 给、由生成器渲染；要提供别的能力一律走命令表"
                   f"（平台信息.命令表 + 函数表），不许再导出第二个符号 ⇒ 只能由该单元补"
                   f"（或改声明 —— 改哪边是契约裁决）", "源码错")
            )


def 比常量(结果: dict, 单元表: list, 常量表名: set) -> None:
    """③j：常量表里的同名常量不许在实现侧再定义（按名匹配，见 `模块说明.py` 注 10）。"""
    硬编码 = []
    引用生成物 = []
    for 登记单元 in 单元表:
        for 常量条 in 登记单元["常量"]:
            if 常量条["名"] not in 常量表名:
                continue
            值文 = (常量条["值文"] or "").strip()
            if 解整数(值文) is not None:
                硬编码.append(常量条)
            else:
                引用生成物.append(常量条)
    if not 常量表名:
        结果[判据名表[10]]["明细"].append(
            记判据(判据名表[10], "未判", 常量表相对路径,
               "扫描 0 项：常量表.json 里一条常量都没读到 ⇒ 空集不算通过",
               "常量表是全平台常量的唯一定义处；读不到就没法按名比对 ⇒ 只能由声明方补")
        )
    elif not any(登记单元["常量"] for 登记单元 in 单元表):
        结果[判据名表[10]]["明细"].append(
            记判据(判据名表[10], "未判", 常量表相对路径,
               f"扫描 0 项：常量表里有 {len(常量表名)} 条常量，而实现面一个单元/一条常量都没有"
               f" ⇒ 没有可比对的项（空集不算通过）",
               "实现面为空说明这次范围里没有实现单元，或解析腿没抽到常量；两者在读数上不可区分"
               " ⇒ 只能由实现方确认范围与对象是否存在")
        )
    else:
        # `已判` 按**实现侧**计（判了什么算什么）：旧写法 `len(常量表名)` 取的是声明侧条数 ⇒
        # 实现面为空时仍报「已判 12 ⇒ 通过」（假绿）。被逐条比对的对象是
        # 实现侧的常量（名字不在常量表里的也做过一次「按名比对」）。
        结果[判据名表[10]]["已判"] += sum(len(登记单元["常量"]) for 登记单元 in 单元表)
        for 常量条 in 硬编码:
            结果[判据名表[10]]["明细"].append(
                记判据(判据名表[10], "失败", 常量条["位置"],
                   f"常量名「{常量条['名']}」在实现侧被再定义，且值是**硬编码字面量**"
                   f"（= {常量条['值文']}）——`{常量表相对路径}` 才是唯一定义处（全表 {len(常量表名)} 条）",
                   f"按名匹配：同一个常量名在别处再定义就是第二个来源，值一旦漂移就没有判据能"
                   f"抓住（按值匹配实测判不了：1000 被三个常量共用、8 命中 62 处）。"
                   f"修法是改成引用生成物（`v1_contract::声明数据::…`）——改哪个数只有声明方能定 ⇒ "
                   f"只能由实现方改成引用", "源码错")
            )
        for 常量条 in 引用生成物:
            结果[判据名表[10]]["明细"].append(
                记判据(判据名表[10], "未判", 常量条["位置"],
                   f"判不了：常量名「{常量条['名']}」在实现侧被再定义，但值是**引用**"
                   f"（= {常量条['值文']}）⇒ 它不是第二来源，只是同名再绑定。"
                   f"判据字面是「同名不许在别处再定义」，意图是「不许造第二来源」——"
                   f"两种读法在这处给出相反的结论",
                   "口径未定：按字面（同名即违规）它该红，按意图（值来自生成物即合规）它该绿。"
                   "选哪种读法是契约侧裁决（改判据字面或改实现命名）⇒ 只能由契约侧裁")
            )
