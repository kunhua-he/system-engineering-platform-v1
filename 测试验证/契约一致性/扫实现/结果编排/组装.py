# -*- coding: utf-8 -*-
"""组装 —— 一条判据一条记录：样本状态声明 + 三元判定装配。"""
from __future__ import annotations

from .口径落点 import 判据名表
from ..比对规则.判据工具 import 记判据


样本状态 = {
    判据名表[0]: {"正向": True, "反向": True},   # ③a
    判据名表[1]: {"正向": True, "反向": True},   # ③b
    判据名表[2]: {"正向": True, "反向": True},   # ③c
    判据名表[3]: {"正向": True, "反向": True},   # ③d1
    判据名表[4]: {"正向": True, "反向": True},   # ③d2（`可抛错误码` 字段已进形状 ⇒ 反向样本可造）
    判据名表[5]: {"正向": True, "反向": True},   # ③e
    判据名表[6]: {"正向": True, "反向": True},   # ③f
    判据名表[7]: {"正向": True, "反向": True},   # ③g（读编译期断言落点）
    判据名表[8]: {"正向": True, "反向": True},   # ③h（读编译期断言落点）
    判据名表[9]: {"正向": True, "反向": True},   # ③i
    判据名表[10]: {"正向": True, "反向": True},  # ③j
    判据名表[11]: {"正向": True, "反向": True},  # ③k（扩展声明自洽）
}


def _组装(比对结果: dict) -> list:
    判定汇总 = []
    for 名称 in 判据名表:
        判据读数 = 比对结果.get(名称, {"明细": [], "扫描面": "", "扫描读数": "", "已判": 0})
        明细 = list(判据读数["明细"])
        已判 = 判据读数.get("已判", 0)
        # 「按设计不覆盖」的格（`判定` == "不覆盖"）：它不是失败、也不是未判 ——
        # 三元判定**不看它**（三元仍是三元，含义不动）；它是第四个数，按格计、不阻塞退出码。
        不覆盖 = [明细条 for 明细条 in 明细 if 明细条["判定"] == "不覆盖"]
        判词 = "通过"
        if any(明细条["判定"] == "失败" for 明细条 in 明细):
            判词 = "失败"
        elif any(明细条["判定"] == "未判" for 明细条 in 明细):
            判词 = "未判"
        elif 已判 <= 0:
            # 「比过之后全对」与「没东西可比」必须分开（判据的可信性 §二）。
            # 裁决（2026-10-01）：`已判<=0` 一律报**未判** ——
            # 不许因为存在任一「不覆盖」格就把「一项都没比过」洗成通过（「不覆盖」是按格计的
            # 第四个数，不是「判过」）。
            判词 = "未判"
            明细.append(
                记判据(名称, "未判", "（无明细）",
                   "扫描 0 项：本判据在这次运行里一项都没比过 ⇒ 空集不算通过"
                   + (f"（本判据另有 {len(不覆盖)} 格按设计不覆盖，但按格不覆盖不等于判过）"
                      if 不覆盖 else ""),
                   "空集说明判据的对象不存在，或解析腿没抽到东西；两者在读数上不可区分 ⇒ "
                   "只能由实现方/声明方确认对象是否存在")
            )
        else:
            明细.append(记判据(名称, "通过", "（比过之后全对）", f"已比 {已判} 项，未发现不一致", "—"))
        样本记录 = 样本状态.get(名称, {"正向": False, "反向": False})
        已验证 = bool(样本记录["正向"] and 样本记录["反向"])
        if 判词 == "通过" and not 已验证:
            判词 = "未判"
            明细.append(
                记判据(名称, "未判", "（判据自身未验证）",
                   "未验证：这条判据缺正向样本或反向样本（判据的可信性 §五）⇒ 它的「通过」不计入通过数",
                   "补样本是验证面自身的活（自测里注入该抓的违规 + 喂一份干净输入）⇒ 只能由验证面补")
            )
        失败 = [明细条 for 明细条 in 明细 if 明细条["判定"] == "失败"]
        未判 = [明细条 for 明细条 in 明细 if 明细条["判定"] == "未判"]
        通过条 = [明细条 for 明细条 in 明细 if 明细条["判定"] == "通过"]
        代表 = 失败 or 未判 or 通过条 or 明细
        判定汇总.append(
            {
                "项": 名称,
                "位置": " ↔ ".join(明细条["位置"] for 明细条 in 代表[:6]),
                "缺什么": 代表[0]["缺什么"],
                "为什么不能自愈": 代表[0]["为什么不能自愈"],
                "判定": 判词,
                "扫描面": 判据读数["扫描面"],
                "扫描读数": 判据读数["扫描读数"],
                "红类": (失败[0]["红类"] or "源码错") if 失败 else "",
                "已验证": 已验证,
                "样本": 样本记录,
                "已判": 已判,
                "明细": 明细,
            }
        )
    return 判定汇总
