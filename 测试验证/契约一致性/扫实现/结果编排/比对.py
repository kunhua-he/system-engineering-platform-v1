# -*- coding: utf-8 -*-
"""比对声明实现 —— 一条判据一条记录：装配扫描面与读数，再分派各判据族（a–j）。"""
from __future__ import annotations

from .口径落点 import 判据名表, 契约源目录, 底座声明根, 底座实现落点, 必备件相对路径, 实现件文件名
from .扫实现小工具 import 是整数
from ..比对规则.判据工具 import 记判据
from ..比对规则.不覆盖 import 按种类不覆盖, 声明根种类
from ..比对规则.判据声明实现 import 比一声明根
from ..比对规则.判据类型标签 import 比类型标签
from ..比对规则.判据落点 import 比落点
from ..比对规则.判据导出常量 import 比常量, 比导出
from ..比对规则.判据扩展自洽 import 比扩展自洽


def 比对声明实现(实现面: dict, 声明根表: dict, 符号表: dict, 常量表名: set) -> dict:
    """返回 {判据名: {"明细": [...], "扫描面": str, "扫描读数": str, "已判": int}}。

    口径（为什么这样切）：③a–③d、③f 的判据对象是「**一份声明** ↔ 它的实现」，所以按
    **声明根**驱动，不是按 crate 驱动 —— 内核内部那些不对外提供能力的 crate（内存分配器 ·
    定长数据槽 · 统一注册表 …）不属于任何一份声明，把它们按 crate 报「空集」只会把真信号埋掉。
    它们仍然进 ③e（用到的类型标签）与 ③j（定义的常量）。这个切法在 `扫描读数` 里如实报出。

    `已判` = 这条判据**实际比对了多少项**。它存在的唯一理由：让「比过之后全对」与
    「没东西可比」在读数上分开（`判据的可信性.md` §二：空集不许算通过）。
    """
    判定汇总 = {名称: {"明细": [], "扫描面": "", "扫描读数": "", "已判": 0} for 名称 in 判据名表}
    计数表 = 实现面["计数"]
    单元表 = 实现面["单元"]
    件表 = 实现面["件表"]
    夹具 = 实现面["夹具"]

    # ── 声明根 → 实现单元 ──
    根到单元 = {}
    for 根目录 in sorted(声明根表):
        if 根目录 == 底座声明根:
            根到单元[根目录] = [登记单元 for 登记单元 in 单元表 if 登记单元["目录"] == 底座实现落点]
        else:
            根到单元[根目录] = [
                登记单元 for 登记单元 in 单元表 if 登记单元["目录"] == 根目录 or 登记单元["目录"].startswith(根目录 + "/")
            ]
    无声明根单元 = [
        登记单元
        for 登记单元 in 单元表
        if not any(登记单元 in 根下单元 for 根下单元 in 根到单元.values())
    ]
    # ③g / ③h 的判据面 = **出声明面的实现单元**（去重）：落点即契约，出声明面就得有落点。
    落点单元 = sorted({登记单元["目录"]: 登记单元 for 根下单元 in 根到单元.values() for 登记单元 in 根下单元}.values(),
                    key=lambda 登记单元: 登记单元["目录"])

    声明扫描面 = "；".join(
        f"{声明根}=能力声明 {len(声明根表.get(声明根, {}).get('能力声明', {}))} 份 · "
        f"错误码表 {len(声明根表.get(声明根, {}).get('错误码表', {}))} 份 · "
        f"类型声明 {len(声明根表.get(声明根, {}).get('类型声明', {}))} 份"
        for 声明根 in sorted(声明根表)
    ) or "（无声明根）"
    扫描面 = (
        f"实现面=范围下的 *.rs 生产区文本（跳过 #[cfg(test)] 块与整份夹具文件）；"
        f"声明面=契约声明/**.json + 扩展声明根/**.json（{声明扫描面}）；"
        f"引用表={契约源目录} 下全部 .rs（含子目录，只读解析符号，不计入实现面）"
    )
    读面说明 = (
        f"读 {计数表['文件']} 个 .rs 生产区文本（整份夹具跳过 {计数表['夹具文件']} 个）；"
        f"另读声明面与清单件（.json / .rs / Cargo.toml）"
        f"{计数表.get('件表总数', 0) - 计数表['文件'] - 计数表['夹具文件']} 个；"
        f"跳过 #[cfg(test)] 块 {计数表['夹具块']} 处；其它 cfg 属性 {计数表['其它cfg']} 处；"
        f"macro_rules! 0 处 · include! 0 处（范围内实测）；"
        f"抽到 单元 {len(单元表)} 个（其中出声明面 {len(落点单元)} 个 · "
        f"不带声明根 {len(无声明根单元)} 个）· "
        f"能力号 {计数表['能力号']} 项 · 命令 {计数表['命令']} 条 · "
        f"参数表 {计数表['参数表']} 张 · 类型表 {计数表['类型表']} 项 · 错误码 {计数表['错误码']} 条 · "
        f"可抛错误码表 {计数表['抛码表']} 张（③d2 的对照物，0 张 = 该判据只剩未判）· "
        f"导出 {计数表['导出']} 个 · 常量 {计数表['常量']} 项"
    )
    for 名称 in 判据名表:
        判定汇总[名称]["扫描面"] = 扫描面
        判定汇总[名称]["扫描读数"] = 读面说明

    全局类型 = {}
    for 声明根, 声明根读数 in 声明根表.items():
        for 键名, (声明值, _) in 声明根读数["类型声明"].items():
            标签 = 声明值.get("类型标签")
            if 是整数(标签):
                全局类型.setdefault(标签, 键名)

    # ════════════════════════════════════════════════════════════════════════
    # ③a–③d、③f：按声明根驱动
    # ════════════════════════════════════════════════════════════════════════
    for 根目录 in sorted(声明根表):
        单元集 = 根到单元.get(根目录) or []
        if not 单元集:
            按种类 = 按种类不覆盖(根目录, 件表)
            if 按种类:
                种类名, 默认目录 = 按种类
                判定汇总[判据名表[0]]["明细"].append(
                    记判据(判据名表[0], "不覆盖", f"{根目录}/",
                       f"按设计不覆盖：{根目录} 属「{种类名}」种类（默认目录 {默认目录}/），而"
                       f"`{必备件相对路径}` 里 `{实现件文件名}` 对该种类是 false ⇒ 它**按设计**没有"
                       f"Rust 实现单元。③a–③d 的对照物（能力号常量 · 命令表 · 参数表）不在 `.rs` 里，"
                       f"而在制品里 ⇒ 本判据不声称覆盖它。",
                       f"由谁覆盖：① 载入期六步判定（`扩展装载/载入约定/载入判定.json`，"
                       f"实现 = `运行内核/装载入口`）—— 声明自洽在载入时判；② 本闸 ③k（扩展声明自洽）"
                       f"已在同一次运行里判了这份声明。为什么这里判不了：制品是能力包件，其 codec 只有"
                       f"Rust 一份（`契约声明/src/契约声明/容器封装/容器.rs`），Python 侧解它 = 第二套实现 ⇒ "
                       f"只能由制品侧的载入路覆盖")
                )
                continue
            种类读数 = 声明根种类(根目录, 件表)
            附注 = ""
            if 种类读数 and 种类读数[1]:
                附注 = (
                    f" ★ **这不是盲区**：{根目录} 属「{种类读数[0]}」种类，而 `{必备件相对路径}` 里 "
                    f"`{实现件文件名}` 对该种类是 true ⇒ 该种类**按设计必须有实现单元**，"
                    f"「声明先行、实现后补」对它是**真的缺实现**。过渡期请把产物落**暂存区**"
                    f"（不在闸 1 / 闸 2 的扫描范围内），上架时声明与实现一起落；"
                    f"要更早曝光就让它同时出实现骨架（含命令表与编号），而不是让闸2 闭眼。"
                    f"依据：库 `条款` `项目文档/决策记录/2026-10-06_闸2支持库声明根覆盖面.md`。"
                )
            判定汇总[判据名表[0]]["明细"].append(
                记判据(判据名表[0], "未判", f"{根目录}/",
                   f"判不了：声明根 {根目录} 找不到对应的实现单元（实测单元："
                   f"{[登记单元['目录'] for 登记单元 in 单元表]}）⇒ 声明没有实现面可比。{附注}",
                   "声明与实现必须成对；找不到实现单元可能是缺件（还没写）或落点变了。"
                   "验证面不能替它认一个实现 ⇒ 只能由实现方把落点定下来")
            )
            continue
        比一声明根(判定汇总, 根目录, 单元集, 声明根表, 符号表, 实现面.get("全局表"))

    # ════════════════════════════════════════════════════════════════════════
    # ③e 类型标签：**全范围聚合**（实现里用到的每个标签都要在 类型声明/ 里）
    # ════════════════════════════════════════════════════════════════════════
    比类型标签(判定汇总, 单元表, 符号表, 全局类型)

    # ════════════════════════════════════════════════════════════════════════
    # ③g / ③h：读**编译期断言落点**（见 `模块说明.py` 注 12 · 注 13）
    # ════════════════════════════════════════════════════════════════════════
    比落点(判定汇总, 落点单元, 件表)

    # ════════════════════════════════════════════════════════════════════════
    # ③i 导出符号（**期望名从声明读**：`导出目标`）
    # ════════════════════════════════════════════════════════════════════════
    目录到导出目标 = {}
    for 根目录, 单元们 in 根到单元.items():
        包声明 = (声明根表.get(根目录) or {}).get("包")
        待处理值 = 包声明[0].get("导出目标") if isinstance(包声明, tuple) and isinstance(包声明[0], dict) else None
        for 登记单元 in 单元们:
            目录到导出目标[登记单元["目录"]] = (待处理值, 根目录)
    比导出(判定汇总, 单元表, 目录到导出目标)

    # ════════════════════════════════════════════════════════════════════════
    # ③j 常量表同名再定义
    # ════════════════════════════════════════════════════════════════════════
    比常量(判定汇总, 单元表, 常量表名)

    # ════════════════════════════════════════════════════════════════════════
    # ③k 扩展声明自洽：能力声明.可抛错误码 ⊆ 本扩展错误码表
    # ════════════════════════════════════════════════════════════════════════
    比扩展自洽(判定汇总, 声明根表)
    return 判定汇总
