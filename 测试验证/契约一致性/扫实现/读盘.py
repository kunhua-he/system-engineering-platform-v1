def 读盘(仓根: str, 范围: list) -> dict:
    仓根路径 = Path(仓根)
    件表 = {}
    坏件表 = []

    def 收文件(路径: Path):
        键名 = 取相对路径(仓根路径, 路径)
        try:
            if 路径.stat().st_size > 读上限字节:
                坏件表.append((键名, f"超过读上限 {读上限字节} 字节（不截断——截断会让解析腿拿到半个文件）"))
                return
            件表[键名] = 路径.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as 错误:
            坏件表.append((键名, f"读不动：{错误}"))

    for 范围项 in 范围:
        范围根 = 仓根路径 / 范围项
        if not 范围根.is_dir():
            continue
        for 根目录, 目录表, 文件表 in os.walk(范围根):
            目录表[:] = [目录 for 目录 in 目录表 if 目录 not in 跳过目录]
            for 名称 in 文件表:
                if 名称.endswith((".rs", ".json")) or 名称 == "Cargo.toml":
                    收文件(Path(根目录) / 名称)
    契约 = 仓根路径 / 契约目录名
    if 契约.is_dir():
        for 根目录, 目录表, 文件表 in os.walk(契约):
            目录表[:] = [目录 for 目录 in 目录表 if 目录 not in 跳过目录]
            for 名称 in 文件表:
                # `.rs` 全收（含 `契约声明/src/` 子目录）——符号表的落点是符号不是文件，
                # 写死文件名会让拆分后的子件静默丢出符号表。
                if 名称.endswith((".json", ".rs")):
                    收文件(Path(根目录) / 名称)
    # ③h 处数判据的基线（不在 `范围` 内，故显式收）：判据读不到它就只能报未判（fail-closed）。
    基线 = 仓根路径 / 处数基线相对路径
    if 基线.is_file():
        收文件(基线)
    return {"件表": 件表, "坏": 坏件表}


def 常量表名集(件表: dict) -> set:
    文本 = 件表.get(常量表相对路径)
    if not 文本:
        return set()
    try:
        个数 = json.loads(文本)
    except json.JSONDecodeError:
        return set()
    常量名集 = set()
    for 常量条 in 个数.get("常量") or []:
        if isinstance(常量条, dict) and isinstance(常量条.get("名"), str):
            常量名集.add(常量条["名"])
    return 常量名集


def _扫一遍(仓根: str, 范围: list, 件表=None, 坏件表=None) -> list:
    if 件表 is None:
        读回 = 读盘(仓根, 范围)
        件表, 坏件表 = 读回["件表"], 读回["坏"]
    坏件表 = 坏件表 or []
    掩表 = {件键: 去字面量(掩前) for 件键, 掩前 in 件表.items() if 件键.endswith(".rs") and 掩前 is not None}
    夹具 = 建夹具集(件表, 掩表)
    符号表 = 建符号表(件表, 掩表)
    实现面 = 抽实现面(件表, 范围, 符号表, 夹具, 掩表)
    声明根表 = 读声明侧(件表)
    比对结果 = 比对声明实现(实现面, 声明根表, 符号表, 常量表名集(件表))
    # 读不动的文件：不许静默——挂到第一条判据的明细上（位置与原因都具体）
    for 键名, 原因 in 坏件表:
        比对结果[判据名表[0]]["明细"].append(
            记判据(判据名表[0], "未判", 键名,
               f"判不了：这个文件读不动（{原因}）⇒ 它可能是实现面或声明面的一部分，漏读就是漏判",
               "读不动有两种：文件被别的腿写到一半（瞬时），或权限/编码问题（持久）。"
               "验证面不能替它猜内容 ⇒ 只能由该文件的作者确认")
        )
    结果 = _组装(比对结果)
    # 「不覆盖登记表」自洽（fail-closed）：登记表长霉 ⇒ 追加一条**失败**的登记表自洽元记录（不是未判）。
    # 传 `仓根`/`范围` ⇒ 按范围过滤：窄范围（扩展专属档）不因范围外的底座登记而假红（#56）。
    结果.extend(登记表自洽元记录(实现面["单元"], 仓根=仓根, 范围=范围))
    return 结果


def 扫实现(仓根: str, 范围: list) -> list:
    """**冻结接口**：`扫实现(仓根: str, 范围: list[str]) -> list[dict]`。

    一条判据一条记录（含 `明细`）。内部**连跑两遍**：同一条判据两遍都红才算「源码错」，
    只红一遍的标「疑似瞬时」并不当阻断（`判据的可信性.md` §四.1）。
    """
    r1 = 读盘(仓根, 范围)
    首遍读数 = _扫一遍(仓根, 范围, 件表=r1["件表"], 坏件表=r1["坏"])
    r2 = 读盘(仓根, 范围)
    if r2["件表"] == r1["件表"] and r2["坏"] == r1["坏"]:
        # 两遍读到的**字节完全一致** ⇒ 判定必然一致（解析是纯函数：同一输入 → 同一输出）。
        # 这一条短路把「连跑两遍」的成本在稳态下变成「只多读一遍文件」（≈10 ms），
        # 而**真变了**的场合仍然会走第二趟解析并逐条比判定 —— 判据的严格性没有放宽。
        return 首遍读数
    次遍读数 = _扫一遍(仓根, 范围, 件表=r2["件表"], 坏件表=r2["坏"])
    次遍索引 = {一条["项"]: 一条 for 一条 in 次遍读数}
    for 一条 in 首遍读数:
        对条 = 次遍索引.get(一条["项"])
        if 对条 is None or 对条["判定"] != 一条["判定"]:
            一条["红类"] = "疑似瞬时" if 一条["判定"] == "失败" else 一条["红类"]
            if 一条["判定"] == "失败":
                一条["缺什么"] = (
                    "疑似瞬时（两遍读数不一致）：" + 一条["缺什么"]
                    + f"｜第二遍的判定是「{对条['判定'] if 对条 else '缺'}」"
                )
                一条["为什么不能自愈"] = (
                    "两遍读数不一致 ⇒ 多半是别的腿正在写文件（半成品），不是源码问题。"
                    "按 判据的可信性 §四.1：只红一次不当阻断，重跑一次仍红才算 ⇒ 只能等文件写完后重跑"
                )
    return 首遍读数


