"""夹具判定 —— `#[cfg(test)]` 块（`块`）与不含 test 的 cfg 位（`其它cfg`）。

「整份夹具文件」（被 cfg(test) mod 挂载；内联自挂还须路径在测试面）**不在这里** ——
只有一份实现，主人 = `构建装配/一键验证/一键验证/测试件.py::建测试文件集`；本件 import 它
（闸2→闸1 合法方向）。
"""
from __future__ import annotations

import re

from .扫实现小工具 import 找配对界符
from 构建装配.一键验证.一键验证.剥字面量 import 去字面量
# `#[cfg(…)]` 属性扫描的两件**只有一份**，主人 = `构建装配/一键验证/一键验证/构造点.py`：
#   · 属性开头正则 `_夹具挂载形` · 括号配对解析 `_条件编译属性`。
# 本件原先自带三份同形实现（`条件属性开头模式` · `解析条件属性` · `_属性窗起`；后两者与主人
# 那份或逐字相同、或只差局部变量名）⇒ 2026-09-30 收口：全删、改引主人（同一职责不许两份）。
# 括号必须**找配对界符**解析（不能用 `#\[\s*cfg\s*\([^)]*\btest\b[^)]*\)\s*\]`）的理由写在主人那份里。
# 方向：闸 1 不许 import 闸 2，反向合法 —— 同 `扫实现.py` 引 `构建装配.门禁` 的方向。
from 构建装配.一键验证.一键验证.构造点 import _夹具挂载形, _条件编译属性
# 「整份夹具文件」的判定也只有一份，主人 = 闸 1 侧 `测试件.py::建测试文件集`（本件 import 它）。
from 构建装配.一键验证.一键验证.测试件 import 建测试文件集


def 找条件属性(掩码文本: str) -> list:
    """返回 [(起, 止, 属性文本, 是否含 test)]，按位置序。"""
    判定汇总 = []
    for 正则匹配 in _夹具挂载形.finditer(掩码文本):
        属性解析 = _条件编译属性(掩码文本, 正则匹配.start())
        if 属性解析 is None:
            continue
        属性文本, 区间终点 = 属性解析
        判定汇总.append((正则匹配.start(), 区间终点, 属性文本, bool(re.search(r"\btest\b", 属性文本))))
    return 判定汇总


def _项头(掩码文本: str, 落点: int) -> tuple:
    """从 `位置` 起扫到第一个 `{` 或 `;`，返回 (头文本, 终止位)。"""
    全长 = len(掩码文本)
    终止位 = 落点
    while 终止位 < 全长 and 掩码文本[终止位] not in "{;":
        终止位 += 1
    return 掩码文本[落点:终止位], 终止位


def 找夹具项(掩码文本: str) -> list:
    """返回 [(起, 止)]：`#[cfg(test)]` 引出的项区间（内联块整段 · 外部声明那一句）。

    外部夹具**文件**的判定不在这里 —— 口径「被 cfg(test) mod 挂载即算（内联自挂还须
    路径在测试面）」只有一份实现，主人 = `构建装配/一键验证/一键验证/测试件.py::建测试文件集`。
    """
    数据块 = []
    for 区间起点, 属止, _属性文本, 含test in 找条件属性(掩码文本):
        if not 含test:
            continue
        # `头部`（mod 名所在那段）本件不再用：外部夹具文件的判定已收口到 `建测试文件集`。
        头部, 终止位 = _项头(掩码文本, 属止)
        if 终止位 >= len(掩码文本):
            continue
        if 掩码文本[终止位] == ";":
            数据块.append((区间起点, 终止位 + 1))
        else:
            区间终点 = 找配对界符(掩码文本, 终止位)
            if 区间终点 < 0:
                continue
            数据块.append((区间起点, 区间终点 + 1))
    return 数据块


def 建夹具集(件表: dict, 掩表: dict = None) -> dict:
    """返回 {"块": {键: [(起,止)]}, "整份夹具": set(键), "其它cfg": [(键,位)]}。

    `整份夹具` 不在本件算 —— 「被 cfg(test) mod 挂载即算（内联自挂还须路径在测试面）」
    只有一份实现，主人 = `构建装配/一键验证/一键验证/测试件.py::建测试文件集`（本件 import 它）。
    本件只负责 `块`（`#[cfg(test)]` 引出的项区间）与 `其它cfg`（不含 test 的 cfg 位）。

    `掩表` 是 `掩码()` 的**每趟缓存**：掩码是这一趟里最贵的一步（154 个文件 ≈ 250 ms），
    而夹具判定与实现面抽取都要它 ⇒ 一趟只算一次（这是秒级的手段，不是可选优化）。
    """
    Rs件 = {括号位: 原文 for 括号位, 原文 in 件表.items() if 括号位.endswith(".rs") and 原文 is not None}
    if 掩表 is None:
        掩表 = {括号位: 去字面量(原文) for 括号位, 原文 in Rs件.items()}
    块表 = {}
    其他项 = []
    for 键名, 掩码文本 in 掩表.items():
        块表[键名] = 找夹具项(掩码文本)
        for 区间起点, _区间终点, _属性文本, 含test in 找条件属性(掩码文本):
            if not 含test:
                其他项.append((键名, 区间起点))
    整份 = 建测试文件集({键名: {"文本": 原文} for 键名, 原文 in Rs件.items()})
    return {"块": 块表, "整份夹具": 整份, "其它cfg": 其他项}


def 生产区文本(源文本: str, 区间表: list) -> str:
    if not 区间表:
        return 源文本
    判定汇总 = list(源文本)
    for 区间起点, 区间终点 in 区间表:
        for 位次 in range(区间起点, min(区间终点, len(判定汇总))):
            if 判定汇总[位次] != "\n":
                判定汇总[位次] = " "
    return "".join(判定汇总)
