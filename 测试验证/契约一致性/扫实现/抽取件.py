def 抽模块常量(掩码文本: str, 键名: str, 模块名: str) -> list:
    """`pub mod <模块名> { pub const <名>: <t> = <值>; }` → [{名, 值, 位置}]。"""
    判定汇总 = []
    for 正则匹配 in re.finditer(r"pub\s+mod\s+" + re.escape(模块名) + r"\s*\{", 掩码文本):
        区间终点 = 找配对界符(掩码文本, 正则匹配.end() - 1)
        if 区间终点 < 0:
            continue
        块起 = 正则匹配.end()
        for 常量项 in re.finditer(
            r"pub\s+const\s+([^\s:]+)\s*:\s*[^=;]*?=\s*([^;]+);", 掩码文本[块起:区间终点]
        ):
            取值 = 解整数(常量项.group(2))
            判定汇总.append(
                {
                    "名": 常量项.group(1),
                    "值": 取值,
                    "原文": 常量项.group(2).strip(),
                    "位置": f"{键名}:{行号(掩码文本, 块起 + 常量项.start())}",
                }
            )
    return 判定汇总


def 抽构造器(掩码文本: str, 返回型: str) -> dict:
    """`const fn <名>(<形参>) -> <返回型> { <返回型> { 字段: 值, … } }`

    返回 {构造名: {"形参": [名…], "字段": {字段: ("形参"|"表达式", 文本)}}}。
    """
    判定汇总 = {}
    for 正则匹配 in re.finditer(r"const\s+fn\s+([^\s(<]+)\s*\(", 掩码文本):
        形参起 = 正则匹配.end() - 1
        形参止 = 找配对界符(掩码文本, 形参起)
        if 形参止 < 0:
            continue
        形参名 = []
        for 表项 in 拆顶层项(掩码文本[形参起 + 1 : 形参止]):
            名称 = 表项.split(":", 1)[0].strip()
            if 名称:
                形参名.append(名称)
        尾部 = 掩码文本[形参止 + 1 : 形参止 + 200]
        体匹配 = re.match(r"\s*->\s*" + re.escape(返回型) + r"\s*\{", 尾部)
        if not 体匹配:
            continue
        # `-> 返回型 {` 那个 `{` 是**函数体**的开括号；真正的结构体字面量在它里面。
        # 实测两种写法都有：`-> 命令信息 { 命令信息 { … } }` 与 `-> 命令信息 { …字段… }`，
        # 所以先看函数体里有没有 `<返回型> {`，没有才把函数体本身当字段表。
        函数体起 = 形参止 + 1 + 体匹配.end() - 1
        函数体止 = 找配对界符(掩码文本, 函数体起)
        if 函数体止 < 0:
            continue
        函数体 = 掩码文本[函数体起 + 1 : 函数体止]
        声明匹配 = re.search(r"(?:^|[^\w])" + re.escape(返回型) + r"\s*\{", 函数体)
        if 声明匹配:
            体起 = 函数体起 + 1 + 声明匹配.end() - 1
            体止 = 找配对界符(掩码文本, 体起)
            if 体止 < 0:
                continue
            应答体 = 掩码文本[体起 + 1 : 体止]
        else:
            应答体 = 函数体
        字段 = {}
        for 匹配项 in 拆顶层项(应答体):
            if ":" in 匹配项:
                名称, 待处理值 = 匹配项.split(":", 1)
                字段[名称.strip()] = ("表达式", 待处理值.strip())
            else:
                字段[匹配项.strip()] = ("形参", 匹配项.strip())
        判定汇总[正则匹配.group(1)] = {"形参": 形参名, "字段": 字段}
    return 判定汇总


def 抽本文件整数常量(掩码文本: str) -> dict:
    """本文件里能定值的整数常量（含 `能力号段[0].止 as usize + 1` 这一种）。"""
    项表 = {}
    for 正则匹配 in re.finditer(r"(?:^|\n)[ \t]*(?:pub\s+)?const\s+([^\s:]+)\s*:", 掩码文本):
        名称 = 正则匹配.group(1)
        落点 = 正则匹配.end()
        _, 值文, _ = _切声明(掩码文本, 落点)
        取值 = 解整数(值文)
        if 取值 is not None:
            项表[名称] = 取值
            continue
        # const 命令表项数: usize = 能力号段[0].止 as usize + 1;
        体匹配 = re.fullmatch(r"([^\s\[]+)\s*\[\s*(\d+)\s*\]\s*\.\s*止\s+as\s+usize\s*\+\s*(\d+)", 值文 or "")
        if 体匹配:
            段名, 序号, 加数 = 体匹配.group(1), int(体匹配.group(2)), int(体匹配.group(3))
            声明匹配 = re.search(
                r"const\s+" + re.escape(段名) + r"\s*:\s*\[[^\]]*\]\s*=\s*\[([^\]]*)\]",
                掩码文本,
            )
            if 声明匹配:
                顶层项 = 拆顶层项(声明匹配.group(1))
                if 序号 < len(顶层项):
                    内层 = re.search(r"\(\s*(\d+)\s*,\s*(\d+)\s*\)", 顶层项[序号])
                    if 内层:
                        项表[名称] = int(内层.group(2)) + 加数
    return 项表


def _切声明(掩码文本: str, 落点: int):
    """从 `位置` 起切一个 const/static 声明：返回 (类型文, 值文, 止位)。"""
    括号深度 = 0
    位次 = 落点
    类型起 = 落点
    while 位次 < len(掩码文本):
        常量项 = 掩码文本[位次]
        if 常量项 in "([{":
            括号深度 += 1
        elif 常量项 in ")]}":
            括号深度 -= 1
        elif 括号深度 == 0 and 常量项 == "=":
            值起 = 位次 + 1
            值止 = 找顶层终止(掩码文本, 值起, ";")
            if 值止 < 0:
                return 掩码文本[类型起:位次].strip(), 掩码文本[值起:].strip(), len(掩码文本)
            return 掩码文本[类型起:位次].strip(), 掩码文本[值起:值止].strip(), 值止 + 1
        elif 括号深度 == 0 and 常量项 == ";":
            return 掩码文本[类型起:位次].strip(), None, 位次 + 1
        位次 += 1
    return None, None, len(掩码文本)


def 抽数组表(掩码文本: str, 元素型: str) -> list:
    """抽 `(const|static) <名>: [<元素型>; <N>] = [ … ];` 与
    `const fn <名>() -> [<元素型>; <N>] { … }` 的表体。

    **不再抽「声明项数 `<N>`」**：命令表 / 函数表的项数已由编译期断言落点承担（③g），
    留一个没人判的项数在这里就是第二个事实源（`项目文档/哲学.md` §一）。
    """
    判定汇总 = []
    for 正则匹配 in re.finditer(
        r"(?:const|static)\s+([^\s:]+)\s*:\s*\[\s*" + re.escape(元素型)
        + r"\s*;\s*([^\]]+)\]\s*=\s*",
        掩码文本,
    ):
        表名 = 正则匹配.group(1)
        rhs起 = 正则匹配.end()
        分号 = 找顶层终止(掩码文本, rhs起, ";")
        rhs = 掩码文本[rhs起:分号].strip() if 分号 > 0 else 掩码文本[rhs起:].strip()
        判定汇总.append(
            {
                "表名": 表名,
                "值原文": rhs,
                "位置": f"{行号(掩码文本, 正则匹配.start())}",
                "内文": (掩码文本[rhs起 + 1 : 找配对界符(掩码文本, rhs起)] if rhs.startswith("[") else None),
                "内文起": rhs起 + 1,
            }
        )
    for 正则匹配 in re.finditer(
        r"const\s+fn\s+([^\s(<]+)\s*\(\s*\)\s*->\s*\[\s*" + re.escape(元素型)
        + r"\s*;\s*([^\]]+)\]\s*\{",
        掩码文本,
    ):
        体起 = 正则匹配.end() - 1
        体止 = 找配对界符(掩码文本, 体起)
        if 体止 < 0:
            continue
        判定汇总.append(
            {
                "表名": 正则匹配.group(1),
                "值原文": 正则匹配.group(1) + "()",
                "位置": f"{行号(掩码文本, 正则匹配.start())}",
                "内文": 掩码文本[体起 + 1 : 体止],
                "内文起": 体起 + 1,
                "是函数": True,
            }
        )
    return 判定汇总


def 抽参数表(掩码文本: str, 键名: str, 符号表: dict) -> dict:
    """抽 `[参数信息; N]` 表 → {表名: {类型标签原文, 位置}}。

    **不再抽「项数」**：③h 已改成读编译期断言落点（表长只有编译器数得准），
    留一个没人判的项数在这里就是第二个事实源（`项目文档/哲学.md` §一）。
    """
    判定汇总 = {}
    for 正则匹配 in re.finditer(
        r"(?:const|static)\s+([^\s:]+)\s*:\s*\[\s*参数信息\s*;\s*([^\]]+)\]\s*=\s*\[",
        掩码文本,
    ):
        区间起点 = 正则匹配.end() - 1
        区间终点 = 找配对界符(掩码文本, 区间起点)
        if 区间终点 < 0:
            continue
        内层 = 掩码文本[区间起点 + 1 : 区间终点]
        顶层项 = 拆顶层项(内层)
        标签 = []
        for 条目项 in 顶层项:
            条目体 = 条目项.split("{", 1)[1] if "{" in 条目项 else 条目项
            mm = re.search(r"类型标签\s*:\s*([^,}]+)", 条目体)
            标签.append(mm.group(1).strip() if mm else None)
        判定汇总[正则匹配.group(1)] = {
            "类型标签原文": 标签,
            "位置": f"{键名}:{行号(掩码文本, 正则匹配.start())}",
        }
    return 判定汇总


def 抽类型表(掩码文本: str, 键名: str) -> list:
    判定汇总 = []
    for 正则匹配 in re.finditer(
        r"(?:const|static)\s+([^\s:]+)\s*:\s*\[\s*数据类型信息\s*;\s*([^\]]+)\]\s*=\s*\[",
        掩码文本,
    ):
        区间起点 = 正则匹配.end() - 1
        区间终点 = 找配对界符(掩码文本, 区间起点)
        if 区间终点 < 0:
            continue
        for 条目项 in 拆顶层项(掩码文本[区间起点 + 1 : 区间终点]):
            if "{" not in 条目项:
                continue
            内层 = 条目项.split("{", 1)[1]
            mm = re.search(r"类型标签\s*:\s*([^,}]+)", 内层)
            判定汇总.append(
                {
                    "表名": 正则匹配.group(1),
                    "类型标签原文": mm.group(1).strip() if mm else None,
                    "位置": f"{键名}:{行号(掩码文本, 正则匹配.start())}",
                }
            )
    return 判定汇总


def 抽错误码表(掩码文本: str, 键名: str, 符号表: dict, 本表: dict) -> dict:
    判定汇总 = {"表": [], "来源": None, "位置": None}
    for 正则匹配 in re.finditer(
        r"(?:const|static)\s+([^\s:]+)\s*:\s*\[\s*错误码信息\s*;\s*([^\]]+)\]\s*=\s*\[",
        掩码文本,
    ):
        区间起点 = 正则匹配.end() - 1
        区间终点 = 找配对界符(掩码文本, 区间起点)
        if 区间终点 < 0:
            continue
        构造 = 抽构造器(掩码文本, "错误码信息")
        段位表达式 = None
        # 段位表达式里引用的**就是构造器的首形参名**（如 `码 / 1000`）⇒ 注入符号表时要用**实盘那个名**。
        # 不许写死 `码`：写死的话，形参一改名扫描器就解不出 ⇒ 一片「未判」而判据静默失效。
        码形参名 = "码"
        for 名称, 常量项 in 构造.items():
            匹配项 = 常量项["字段"].get("段位")
            if 匹配项 and 匹配项[0] == "表达式":
                段位表达式 = 匹配项[1]
                形参名表 = 常量项.get("形参") or []
                if 形参名表:
                    码形参名 = 形参名表[0]
        for 条目项 in 拆顶层项(掩码文本[区间起点 + 1 : 区间终点]):
            条目项 = 条目项.strip()
            if "{" in 条目项:
                内层 = 条目项.split("{", 1)[1]
                码文 = re.search(r"(?:^|,)\s*码\s*:\s*([^,}]+)", 内层)
                段文 = re.search(r"(?:^|,)\s*段位\s*:\s*([^,}]+)", 内层)
                错误码 = 解符号(码文.group(1), 符号表, 本表) if 码文 else None
                号段 = 解符号(段文.group(1), 符号表, 本表) if 段文 else None
            else:
                mm = re.match(r"([^\s(]+)\s*\((.*)\)\s*$", 条目项, re.S)
                if not mm:
                    continue
                实参 = 拆顶层项(mm.group(2))
                错误码 = 解符号(实参[0], 符号表, 本表) if 实参 else None
                号段 = None
                if 段位表达式 and 错误码 is not None:
                    取值 = 解符号(段位表达式, {**符号表, 码形参名: 错误码}, 本表)
                    号段 = 取值
            判定汇总["表"].append(
                {"码": 错误码, "段位": 号段, "原文": " ".join(条目项.split())[:70], "位置": f"{键名}:{行号(掩码文本, 正则匹配.start())}"}
            )
        判定汇总["来源"] = "字面量表"
        判定汇总["位置"] = f"{键名}:{行号(掩码文本, 正则匹配.start())}"
        return 判定汇总
    # 非字面量：`错误码表: 表段::新建(v1_contract::声明数据::错误码信息表段()…)`
    正则匹配 = re.search(r"错误码表\s*:\s*([^,\n}]+)", 掩码文本)
    if 正则匹配:
        判定汇总["来源"] = "生成物"
        判定汇总["位置"] = f"{键名}:{行号(掩码文本, 正则匹配.start())}"
        判定汇总["原文"] = 正则匹配.group(1).strip()
    return 判定汇总


导出属性模式 = re.compile(r"#\[\s*(?:unsafe\s*\(\s*)?export_name\s*=")
无修饰模式 = re.compile(r"#\[\s*no_mangle\s*\]")


def 抽导出(掩码文本: str, 原文本: str, 键名: str) -> list:
    判定汇总 = []
    for 正则匹配 in 导出属性模式.finditer(掩码文本):
        引号位 = 原文本.find('"', 正则匹配.end(), min(len(原文本), 正则匹配.end() + 200))
        if 引号位 < 0:
            continue
        终引 = 原文本.find('"', 引号位 + 1)
        if 终引 < 0:
            continue
        判定汇总.append({"符号": 原文本[引号位 + 1 : 终引], "位置": f"{键名}:{行号(掩码文本, 正则匹配.start())}"})
    for 正则匹配 in 无修饰模式.finditer(掩码文本):
        尾部 = 掩码文本[正则匹配.end() : 正则匹配.end() + 300]
        匹配项 = re.search(r"fn\s+([^\s(<]+)", 尾部)
        判定汇总.append(
            {"符号": (匹配项.group(1) if 匹配项 else "?"), "位置": f"{键名}:{行号(掩码文本, 正则匹配.start())}"}
        )
    return 判定汇总


def 抽常量(掩码文本: str, 键名: str) -> list:
    判定汇总 = []
    # ★ 2026-10-01（抽取面缺口）：可见性修饰放宽到 `pub(crate)` / `pub(super)` —— 旧正则只认
    #   `pub ` / 无修饰 ⇒ 全仓 166 个 `pub(crate) const` 名抽不出（③j 常量同名再定义 · ③k
    #   与闸 1 的常量判据都建立在这个抽取面上 ⇒ 漏抽即静默少判）。
    for 正则匹配 in re.finditer(r"(?:^|\n)[ \t]*(?:pub(?:\([^)]*\))?\s+)?const\s+([^\s:]+)\s*:", 掩码文本):
        名称 = 正则匹配.group(1)
        _, 值文, _ = _切声明(掩码文本, 正则匹配.end())
        判定汇总.append(
            {
                "名": 名称,
                "值文": 值文,
                "值": 解整数(值文),
                "位置": f"{键名}:{行号(掩码文本, 正则匹配.start() + 1)}",
            }
        )
    return 判定汇总
