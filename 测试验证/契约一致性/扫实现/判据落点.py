# -*- coding: utf-8 -*-
"""判据落点 —— ③g / ③h：读编译期断言落点（命令表项数 · 函数表项数 · 参数个数已核条数）。"""
from __future__ import annotations

from .常量 import (
    判据名表,
    落点_命令表项数,
    落点_函数表项数,
    落点_参数个数已核条数,
    接缝符号,
)
from .判据工具 import 记


def 比落点(结果: dict, 落点单元: list) -> None:
    """③g / ③h：读**编译期断言落点**（不再扫表声明），明细与扫描面/读数写进 `出`。"""
    落点面 = (
        f"③g/③h 的扫描面 = **编译期断言落点**：每个出声明面的实现单元里的 "
        f"`const {落点_命令表项数}` / `const {落点_函数表项数}`（③g）与 "
        f"`const {落点_参数个数已核条数}`（③h）；关系本身由实现侧的 "
        f"`const _: () = assert!(…);` 钉死（**以该 crate 编译通过为前提**，见文件头 §四.12）"
    )
    落点读数 = (
        f"判据面 = 出声明面的实现单元 {len(落点单元)} 个"
        f"（{[单元['目录'] for 单元 in 落点单元]}）；带 ③g 落点 "
        f"{sum(1 for 单元 in 落点单元 if _落点(单元, 落点_命令表项数) and _落点(单元, 落点_函数表项数))} 个 · "
        f"带 ③h 落点 {sum(1 for 单元 in 落点单元 if _落点(单元, 落点_参数个数已核条数))} 个"
    )
    for 序 in (7, 8):
        结果[判据名表[序]]["扫描面"] = 落点面
        结果[判据名表[序]]["扫描读数"] = 落点读数

    for 单元 in 落点单元:
        # ── ③g 命令表与函数表等长：读 `命令表项数` ↔ `函数表项数` ──
        命 = _落点(单元, 落点_命令表项数)
        函 = _落点(单元, 落点_函数表项数)
        缺 = [名 for 名, 常量条 in ((落点_命令表项数, 命), (落点_函数表项数, 函)) if 常量条 is None]
        if 缺:
            结果[判据名表[7]]["明细"].append(
                记(判据名表[7], "未判", f"{单元['目录']}/",
                   f"判不了：{单元['目录']} 没有 ③g 落点 const {缺}（本单元抽到的 const："
                   f"{sorted(常量条['名'] for 常量条 in 单元['常量'])}）⇒ 「命令表与函数表等长」这一条"
                   f"只剩编译期断言，落点不在就读不出两表项数",
                   f"落点是**契约名**（同 ③i 的 `{接缝符号}`）：出声明面的单元必须把"
                   f"「两表等长」用 `const _: () = assert!(…);` 钉死并交出这两个 const。"
                   f"补法是实现方的活（要定这两个数怎么来）⇒ 只能由该单元补", "缺件或半成品")
            )
        elif 命["值"] is None or 函["值"] is None:
            结果[判据名表[7]]["明细"].append(
                记(判据名表[7], "未判", f"{命['位置']} ↔ {函['位置']}",
                   f"判不了：落点的值不是可静态求值的整数（{落点_命令表项数} = 「{命['值文']}」 · "
                   f"{落点_函数表项数} = 「{函['值文']}」）⇒ 两表项数取不出",
                   "落点必须是整数字面量才能读（关系由编译期断言钉死，本模块只读落点）⇒ "
                   "只能由实现方把落点写成字面量")
            )
        else:
            结果[判据名表[7]]["已判"] += 1
            if 命["值"] != 函["值"]:
                结果[判据名表[7]]["明细"].append(
                    记(判据名表[7], "失败", f"{命['位置']} ↔ {函['位置']}",
                       f"{落点_命令表项数} = {命['值']}（{命['位置']}），"
                       f"{落点_函数表项数} = {函['值']}（{函['位置']}）⇒ 两表不等长",
                       "函数表与命令表**等长且一一对应**（`契约声明/src/lib.rs`）；不等长会让"
                       "某个命令号在函数表里取不到执行函数（越界）。两个落点必有一个与"
                       "编译期断言不符 ⇒ 只能由实现方补", "源码错")
                )

        # ── ③h 参数表项数 == 参数个数：读 `参数个数已核条数` ↔ `命令表项数` ──
        核 = _落点(单元, 落点_参数个数已核条数)
        if 核 is None:
            结果[判据名表[8]]["明细"].append(
                记(判据名表[8], "未判", f"{单元['目录']}/",
                   f"判不了：{单元['目录']} 没有 ③h 落点 const `{落点_参数个数已核条数}`"
                   f"（本单元抽到的 const：{sorted(常量条['名'] for 常量条 in 单元['常量'])}）⇒ "
                   f"「参数表项数 == 参数个数」只剩编译期断言，落点不在就读不出已核条数",
                   "落点是**契约名**：出声明面的单元必须逐条核「参数表项数 == 参数个数」"
                   "并把已核条数交出来（少了就是静默少判）。补法是实现方的活 ⇒ 只能由该单元补",
                   "缺件或半成品")
            )
            continue
        if 核["值"] is None:
            结果[判据名表[8]]["明细"].append(
                记(判据名表[8], "未判", 核["位置"],
                   f"判不了：落点 `{落点_参数个数已核条数}` 的值不是可静态求值的整数"
                   f"（原文「{核['值文']}」）⇒ 已核条数取不出",
                   "落点必须是整数字面量才能读（关系由编译期断言钉死，本模块只读落点）⇒ "
                   "只能由实现方把落点写成字面量")
            )
            continue
        结果[判据名表[8]]["已判"] += 1
        if 命 is None or 命["值"] is None:
            结果[判据名表[8]]["明细"].append(
                记(判据名表[8], "未判", 核["位置"],
                   f"判不了：已核条数 {核['值']}（{核['位置']}）没有对照物 —— 本单元缺 "
                   f"`{落点_命令表项数}`（③g 落点），无从比「核过几条 / 共几条」",
                   "已核条数必须与命令表项数比才有意义（少了 = 静默少判）⇒ "
                   "只能由实现方补 ③g 落点")
            )
            continue
        if 核["值"] != 命["值"]:
            结果[判据名表[8]]["明细"].append(
                记(判据名表[8], "失败", f"{核['位置']} ↔ {命['位置']}",
                   f"{落点_参数个数已核条数} = {核['值']}（{核['位置']}），而 "
                   f"{落点_命令表项数} = {命['值']}（{命['位置']}）⇒ 有命令没被核过"
                   f"（少 {命['值'] - 核['值']} 条）",
                   "同表内自洽：参数个数 是调度侧校验入参的依据、参数表 是取槽的依据；"
                   "两者不等会让调度放行一个取不到槽的调用（越界读）。已核条数落后于表长 = "
                   "加了命令没加断言 ⇒ 只能由实现方补", "源码错")
            )


def _落点(单元: dict, 名: str) -> object:
    """本单元里名为 `名` 的 const（③g / ③h 的编译期断言落点）；没有返回 None。

    为什么按**名**取 const 而不扫表声明：落点是**声明过的契约名**（只在一处定义，
    改口径只改那一处），而扫声明文本会因换个命名 / 挪个位置就漏（假绿）。
    """
    for 常量条 in 单元["常量"]:
        if 常量条["名"] == 名:
            return 常量条
    return None
