# -*- coding: utf-8 -*-
"""判据落点 —— ③g / ③h：读编译期断言落点（命令表项数 · 函数表项数 · 参数个数已核条数）。"""
from __future__ import annotations

import json

from .常量 import (
    判据名表,
    处数基线相对路径,
    落点_命令表项数,
    落点_函数表项数,
    落点_参数个数已核条数,
    接缝符号,
)
from .判据工具 import _落点, 记判据


def 比落点(结果: dict, 落点单元: list, 件表: dict) -> None:
    """③g / ③h：读**编译期断言落点**（不再扫表声明），明细与扫描面/读数写进 `结果`。

    ③h 多一层**处数判据**（残留三项裁决 2026-09-27 §三 落法②）：读 `处数基线相对路径`
    把「已核条数 的值」与「逐条断言的行数」钉成固定值（实测 ≠ 登记即红）。为什么
    需要它见 `_比处数` 的文档串。
    """
    处数基线, 基线坏 = _读处数基线(件表)
    落点面 = (
        f"③g/③h 的扫描面 = **编译期断言落点**：每个出声明面的实现单元里的 "
        f"`const {落点_命令表项数}` / `const {落点_函数表项数}`（③g）与 "
        f"`const {落点_参数个数已核条数}`（③h）；关系本身由实现侧的 "
        f"`const _: () = assert!(…);` 钉死（**以该 crate 编译通过为前提**，见文件头 §四.12）。"
        f"③h 另读**处数基线** `{处数基线相对路径}`：把「已核条数 的值」与「逐条断言的行数」"
        f"钉成固定值（实测 ≠ 登记即红）"
    )
    落点读数 = (
        f"判据面 = 出声明面的实现单元 {len(落点单元)} 个"
        f"（{[单元['目录'] for 单元 in 落点单元]}）；带 ③g 落点 "
        f"{sum(1 for 单元 in 落点单元 if _落点(单元, 落点_命令表项数) and _落点(单元, 落点_函数表项数))} 个 · "
        f"带 ③h 落点 {sum(1 for 单元 in 落点单元 if _落点(单元, 落点_参数个数已核条数))} 个 · "
        f"处数基线登记 {len(处数基线)} 个"
    )
    for 序号 in (7, 8):
        结果[判据名表[序号]]["扫描面"] = 落点面
        结果[判据名表[序号]]["扫描读数"] = 落点读数
    if 基线坏:
        结果[判据名表[8]]["明细"].append(
            记判据(判据名表[8], "未判", 处数基线相对路径,
               f"判不了：③h 处数判据的基线读不出（{基线坏}）⇒ 读不出「已核条数 的值 / "
               f"逐条断言的行数」该是多少",
               "处数判据靠固定登记关小「改一处不动另一处」的洞；基线读不出就没有对照物。"
               "基线是声明方的活（谁出声明面谁登记）⇒ 只能由维护方补/修 `处数基线.json`")
        )

    for 扫描单元 in 落点单元:
        # ── ③g 命令表与函数表等长：读 `命令表项数` ↔ `函数表项数` ──
        命令表落点 = _落点(扫描单元, 落点_命令表项数)
        函数表落点 = _落点(扫描单元, 落点_函数表项数)
        缺落点 = [名称 for 名称, 常量条 in ((落点_命令表项数, 命令表落点), (落点_函数表项数, 函数表落点)) if 常量条 is None]
        if 缺落点:
            结果[判据名表[7]]["明细"].append(
                记判据(判据名表[7], "未判", f"{单元['目录']}/",
                   f"判不了：{单元['目录']} 没有 ③g 落点 const {缺落点}（本单元抽到的 const："
                   f"{sorted(常量条['名'] for 常量条 in 单元['常量'])}）⇒ 「命令表与函数表等长」这一条"
                   f"只剩编译期断言，落点不在就读不出两表项数",
                   f"落点是**契约名**（同 ③i 的 `{接缝符号}`）：出声明面的单元必须把"
                   f"「两表等长」用 `const _: () = assert!(…);` 钉死并交出这两个 const。"
                   f"补法是实现方的活（要定这两个数怎么来）⇒ 只能由该单元补", "缺件或半成品")
            )
        elif 命令表落点["值"] is None or 函数表落点["值"] is None:
            结果[判据名表[7]]["明细"].append(
                记判据(判据名表[7], "未判", f"{命令表落点['位置']} ↔ {函数表落点['位置']}",
                   f"判不了：落点的值不是可静态求值的整数（{落点_命令表项数} = 「{命令表落点['值文']}」 · "
                   f"{落点_函数表项数} = 「{函数表落点['值文']}」）⇒ 两表项数取不出",
                   "落点必须是整数字面量才能读（关系由编译期断言钉死，本模块只读落点）⇒ "
                   "只能由实现方把落点写成字面量")
            )
        else:
            结果[判据名表[7]]["已判"] += 1
            if 命令表落点["值"] != 函数表落点["值"]:
                结果[判据名表[7]]["明细"].append(
                    记判据(判据名表[7], "失败", f"{命令表落点['位置']} ↔ {函数表落点['位置']}",
                       f"{落点_命令表项数} = {命令表落点['值']}（{命令表落点['位置']}），"
                       f"{落点_函数表项数} = {函数表落点['值']}（{函数表落点['位置']}）⇒ 两表不等长",
                       "函数表与命令表**等长且一一对应**（`契约声明/src/lib.rs`）；不等长会让"
                       "某个命令号在函数表里取不到执行函数（越界）。两个落点必有一个与"
                       "编译期断言不符 ⇒ 只能由实现方补", "源码错")
                )

        # ── ③h 参数表项数 == 参数个数：读 `参数个数已核条数` ↔ `命令表项数` ──
        核过条数 = _落点(扫描单元, 落点_参数个数已核条数)
        if 核过条数 is None:
            结果[判据名表[8]]["明细"].append(
                记判据(判据名表[8], "未判", f"{单元['目录']}/",
                   f"判不了：{单元['目录']} 没有 ③h 落点 const `{落点_参数个数已核条数}`"
                   f"（本单元抽到的 const：{sorted(常量条['名'] for 常量条 in 单元['常量'])}）⇒ "
                   f"「参数表项数 == 参数个数」只剩编译期断言，落点不在就读不出已核条数",
                   "落点是**契约名**：出声明面的单元必须逐条核「参数表项数 == 参数个数」"
                   "并把已核条数交出来（少了就是静默少判）。补法是实现方的活 ⇒ 只能由该单元补",
                   "缺件或半成品")
            )
        elif 核过条数["值"] is None:
            结果[判据名表[8]]["明细"].append(
                记判据(判据名表[8], "未判", 核过条数["位置"],
                   f"判不了：落点 `{落点_参数个数已核条数}` 的值不是可静态求值的整数"
                   f"（原文「{核过条数['值文']}」）⇒ 已核条数取不出",
                   "落点必须是整数字面量才能读（关系由编译期断言钉死，本模块只读落点）⇒ "
                   "只能由实现方把落点写成字面量")
            )
        else:
            结果[判据名表[8]]["已判"] += 1
            if 命令表落点 is None or 命令表落点["值"] is None:
                结果[判据名表[8]]["明细"].append(
                    记判据(判据名表[8], "未判", 核过条数["位置"],
                       f"判不了：已核条数 {核过条数['值']}（{核过条数['位置']}）没有对照物 —— 本单元缺 "
                       f"`{落点_命令表项数}`（③g 落点），无从比「核过几条 / 共几条」",
                       "已核条数必须与命令表项数比才有意义（少了 = 静默少判）⇒ "
                       "只能由实现方补 ③g 落点")
                )
            elif 核过条数["值"] != 命令表落点["值"]:
                结果[判据名表[8]]["明细"].append(
                    记判据(判据名表[8], "失败", f"{核过条数['位置']} ↔ {命令表落点['位置']}",
                       f"{落点_参数个数已核条数} = {核过条数['值']}（{核过条数['位置']}），而 "
                       f"{落点_命令表项数} = {命令表落点['值']}（{命令表落点['位置']}）⇒ 有命令没被核过"
                       f"（少 {命令表落点['值'] - 核过条数['值']} 条）",
                       "同表内自洽：参数个数 是调度侧校验入参的依据、参数表 是取槽的依据；"
                       "两者不等会让调度放行一个取不到槽的调用（越界读）。已核条数落后于表长 = "
                       "加了命令没加断言 ⇒ 只能由实现方补", "源码错")
                )
            # ── ③h 处数判据（残留三项裁决 §三 落法②）：与固定登记比 ──
            if not 基线坏:
                _比处数(结果, 扫描单元, 核过条数, 处数基线)


def _读处数基线(件表: dict):
    """读 ③h 处数基线（`处数基线相对路径`）；返回 (基线字典, 读不出的原因)。

    基线**从被扫仓的件表取**（同 `行数基线.json` 的口径：基线是被扫仓自身的债务/登记，
    判据的实现跟着判据走）—— 于是自测的合成仓可以自带一份基线（见 `样本.造样本`）。
    """
    文本 = (件表 or {}).get(处数基线相对路径)
    if not 文本:
        return {}, f"件表里没有 `{处数基线相对路径}`（读盘要显式收它，见 `读盘.读盘`）"
    try:
        个数 = json.loads(文本)
    except json.JSONDecodeError as 错误:
        return {}, f"`{处数基线相对路径}` 解析不了（{错误}）"
    基线 = 个数.get("基线")
    if not isinstance(基线, dict):
        return {}, f"`{处数基线相对路径}` 缺 `基线` 节"
    return 基线, ""


def _比处数(结果: dict, 扫描单元: dict, 核过条数: dict, 处数基线: dict) -> None:
    """③h 处数判据：把「已核条数 的值」与「逐条断言的行数」钉在 `处数基线.json` 上。

    为什么要有这一条（残留三项裁决 2026-09-27 §三 落法②）：末条 `已核条数 == 表.len()`
    只拦「加了命令没加断言」；**「同时改 `参数个数已核条数` 又不加断言」它拦不住**
    （末条照样成立）—— 改一处而不同批改另一处，**处数就对不上**。本判据把两处都钉成
    固定值：**实测 ≠ 登记即红**（新增与陈旧都红），于是「两处同时改」必须**故意**
    （改源码 + 改基线）才过，而不是顺手。

    **为什么钉「值」而不只钉标识符出现处数**：`参数个数已核条数` 的出现处数恒为 2
    （声明 + 末条断言），改它的**值**处数不变 ⇒ 只钉出现处数拦不住那条洞。
    **边界**：它不消除「故意同时改两处」（那是人在骗门禁，不是门禁的洞）。
    """
    名称 = 判据名表[8]
    目录 = 扫描单元["目录"]
    登记 = (处数基线 or {}).get(目录)
    if 登记 is None:
        结果[名称]["明细"].append(
            记判据(名称, "未判", f"{目录}/",
               f"判不了：{目录} 在处数基线（`{处数基线相对路径}`）里没有登记 ⇒ "
               f"读不出「已核条数 的值 / 逐条断言的行数」该是多少",
               "处数判据靠固定登记关小「改一处不动另一处」的洞；没有登记就没有对照物。"
               "登记是**声明方**的活（谁出声明面谁登记）⇒ 只能由该单元补一条登记")
        )
        return
    实测行数 = 扫描单元.get("③h断言处数", 0)
    登记已核 = 登记.get("已核条数")
    登记行数 = 登记.get("逐条断言行数")
    位置 = 核过条数["位置"]
    if 登记已核 is not None and 核过条数["值"] != 登记已核:
        结果[名称]["明细"].append(
            记判据(名称, "失败", 位置,
               f"{落点_参数个数已核条数} = {核过条数['值']}，而处数基线登记 {登记已核}"
               f"（`{处数基线相对路径}`）⇒ 值被改而处数登记未同批改（处数对不上）",
               "残留三项裁决 §三 落法②：把「已核条数 的值」与「逐条断言的行数」都钉成固定值。"
               "只改 `参数个数已核条数` 而不加断言，末条 `已核条数 == 表.len()` 拦不住"
               "（两处同改时照样成立）⇒ 由本判据兜。修法：真加了命令就连同逐条断言、"
               "`命令表项数` 与**本基线**一起改（那才是「故意」）；没加命令就改回去 ⇒ "
               "只能由该单元处置", "源码错")
        )
    if 登记行数 is not None:
        if 实测行数 > 登记行数:
            结果[名称]["明细"].append(
                记判据(名称, "失败", 位置,
                   f"逐条断言 {实测行数} 处 > 处数基线登记 {登记行数} 处"
                   f"（`{处数基线相对路径}`）⇒ **新增断言未登记**",
                   "处数判据把逐条断言行数钉成固定值（照判据 ⑲/㉒ 的基线形状）：新增即红。"
                   "真加了断言就连基线一起改 ⇒ 只能由该单元处置", "源码错")
            )
        elif 实测行数 < 登记行数:
            结果[名称]["明细"].append(
                记判据(名称, "失败", 位置,
                   f"逐条断言 {实测行数} 处 < 处数基线登记 {登记行数} 处"
                   f"（`{处数基线相对路径}`）⇒ **登记陈旧**（断言被删而基线没跟着减）",
                   "处数判据的基线只许跟着源码走（照判据 ⑲/㉒ 的形状）：实测低于登记就同步减下来。"
                   "不减的话，这一处可以一路长回登记值而不报红 ⇒ 只能由该单元处置", "源码错")
            )
