# -*- coding: utf-8 -*-
"""判据类型标签 —— ③e：实现里用到的每个类型标签都要在 类型声明/ 里登记。"""
from __future__ import annotations

from .常量 import 判据名表
from .符号解析 import 解符号
from .判据工具 import 记判据, _本表


def 比类型标签(结果: dict, 单元表: list, 符号表: dict, 全局类型: dict) -> None:
    """③e：**全范围聚合**——实现里用到的每个类型标签都要在 契约声明/类型声明/ 里。"""
    标签登记 = {}
    for 单元 in 单元表:
        for 类型项 in 单元["类型表"]:
            原文 = 类型项["类型标签原文"]
            标签登记.setdefault((解符号(原文, 符号表, _本表(单元)), 原文, 类型项["位置"]), 单元["目录"])
        for 引用项 in 单元["类型标签引用"]:
            标签登记.setdefault((解符号(引用项["符号"], 符号表, _本表(单元)), 引用项["符号"], 引用项["位置"]), 单元["目录"])
    if not 标签登记:
        结果[判据名表[5]]["明细"].append(
            记判据(判据名表[5], "未判", "（全范围）",
               "扫描 0 项：范围内一个类型标签都没抽到（既没有 类型表 项，也没有 类型标签 引用）"
               "⇒ 空集不算通过",
               "空集可能是「范围内真的不带类型」（合法），也可能是解析腿漏抽；两者在读数上"
               "不可区分 ⇒ 只能由实现方确认")
        )
    for (标签值, 原文, 位置), 目录 in 标签登记.items():
        if 标签值 is None:
            结果[判据名表[5]]["明细"].append(
                记判据(判据名表[5], "未判", 位置,
                   f"判不了：类型标签原文「{原文}」既不是整数、也不在生成物/契约源的符号表里"
                   f"（符号表 {len(符号表)} 条）⇒ 取不出它的数",
                   "解不出标签就没法查它有没有登记。要么它来自宏/生成物之外的第二来源，"
                   "要么解析腿漏了——两种都只能由实现方确认并改成引用生成物")
            )
            continue
        结果[判据名表[5]]["已判"] += 1
        if 标签值 not in 全局类型:
            结果[判据名表[5]]["明细"].append(
                记判据(判据名表[5], "失败", 位置,
                   f"实现用到类型标签 {标签值}（原文「{原文}」，在 {目录}），但 契约声明/类型声明/ 里"
                   f"没有登记它（已登记：{sorted(全局类型)}）",
                   f"§四：类型标签是槽内携带的那个数，是跨语言兼容的锚点，标签一旦公布含义"
                   f"永不改写。补一个标签要占一个永不回收的号（走声明编写面）；"
                   f"改成已登记标签会改这条命令的参数/返回语义 ⇒ 只能人来裁", "源码错")
            )
