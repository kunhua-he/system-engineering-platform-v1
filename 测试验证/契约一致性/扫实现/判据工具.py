# -*- coding: utf-8 -*-
"""判据工具 —— `记判据` 与比对用的小解析（本表 · 编号 · 可抛错误码 · 落点）。"""
from __future__ import annotations

import re

from .扫实现小工具 import 拆顶层项
from .符号解析 import 解符号, 末段


def 记判据(判据: str, 判定: str, 落点: str, 缺什么: str, 不能自愈: str, 红类: str = "") -> dict:
    return {
        "位置": 落点,
        "缺什么": 缺什么,
        "为什么不能自愈": 不能自愈,
        "判定": 判定,
        "红类": 红类,
    }


def _本表(扫描单元: dict) -> dict:
    """本单元内可解析的整数符号（能力号 · 错误码 · 本文件 const）。"""
    项表 = {}
    for 条目项 in 扫描单元["能力号"]:
        if 条目项["值"] is not None:
            项表[条目项["名"]] = 条目项["值"]
    for 条目项 in 扫描单元.get("错误码常量", []):
        if 条目项["值"] is not None:
            项表[条目项["名"]] = 条目项["值"]
    项表.update(扫描单元.get("本文件整数常量", {}))
    return 项表


def _取编号(字段: dict, 兜底):
    """命令编号读法：**显式字段优先，下标只作兜底**（`契约声明/src/lib.rs` 命令信息 · 旁路区）。

    `命令信息.编号` 是显式 `u32`（旧形状没有这个字段）⇒ 有字段且解得出就用它；
    字段缺失或解不出才退回 `兜底()`（= 命令表下标 / 下标表达式）。
    为什么这么排：显式编号是唯一对照键（`字段名册与引用方式.md` §三 的旧约定已废止）。
    """
    编号字段 = 字段.get("编号")
    if 编号字段 and 编号字段.get("值") is not None:
        return 编号字段["值"], (编号字段.get("原文") or "").strip()
    return 兜底()


def _解可抛错误码(扫描单元: dict, 原文, 符号表: dict, 本表: dict, 全局抛码表: dict = None):
    """把 `命令信息.可抛错误码` 的实参解析成错误码列表；解不出返回 None（不许猜）。

    只认两种写法（`契约声明/src/lib.rs` 命令信息 · 旁路区 `可抛错误码: 表段<错误码>`）：
    `表段::空实例()` = 空集（本命令不抛错，不是漏写）；`表段::构造(<表>.as_ptr(), …)`
    = 取那张表的项逐项解符号。别的写法一律 None ⇒ 判据侧报未判并写明原文。

    表名**先查本单元、再查跨单元索引**（2026-10-15 补，实测撞到）：生成器把命令的每个字段
    出成常量后，实现侧指的 `能力可抛错误码_<词干>` 住在**另一个单元**的生成物里
    （`契约声明/src/`）⇒ 只查本单元当场报未判。这不是「解不出所以未判」，是**解析腿漏抽**
    （`判据的可信性.md` §三.5）。本单元优先（同 Rust 的作用域直觉）。
    """
    if 原文 is None:
        return None
    源文本 = 原文.strip()
    # `表段` 可带模块路径（`v1_contract::表段::构造(…)`）—— 实现侧全路径引用生成物时
    # 就是这种写法（2026-10-15 补，实测撞到：旧读法只认裸 `表段::…` ⇒ 当场报未判）。
    段前缀 = r"(?:[\w:]+\s*::\s*)?表段\s*::\s*"
    if re.fullmatch(段前缀 + r"空实例\s*\(\s*\)", 源文本):
        return []
    正则匹配 = re.match(段前缀 + r"构造\s*\(\s*([^\s.(]+)\s*\.\s*as_ptr\s*\(\s*\)", 源文本)
    if not 正则匹配:
        return None
    表名 = 末段(正则匹配.group(1))
    抛码表项 = 扫描单元.get("抛码表", {}).get(表名)
    if 抛码表项 is None and 全局抛码表:
        抛码表项 = 全局抛码表.get(表名)
    if 抛码表项 is None:
        return None
    判定汇总 = []
    for 顶层项 in 拆顶层项(抛码表项.get("内文") or ""):
        待处理值 = 解符号(顶层项, 符号表, 本表)
        if 待处理值 is None:
            return None
        判定汇总.append(待处理值)
    return 判定汇总


def _按编号找命令(扫描单元: dict, 编号) -> object:
    for 条目项 in 扫描单元["命令"]:
        if 条目项["编号"] == 编号:
            return 条目项
    return None


def _参数表名(实现条目: dict) -> object:
    """命令项 `参数表` 字段 → 表名（③c 逐位比行序的对照物名）。

    只认两种写法：**本地表名**（`底座参数表.as_ptr()`）与**全路径**（生成物里的
    `v1_contract::声明数据::能力参数表_0000.as_ptr()` —— 取末段，供跨单元索引命中）。
    其余（`core::ptr::null()` 之类）一律 None ⇒ 判据报未判（fail-closed，不许猜）。

    为什么认全路径（2026-10-15 补，实测撞到）：生成器把命令的每个字段都出成常量后
    （`构建装配/形态装配/生成声明/渲染数据表.py::渲染能力编号`），实现侧按 `命令信息` 形状
    组装时字段原文就是**全路径** ⇒ 旧读法（只认本地名、见 `::` 即 None）当场报未判。
    这不是「解不出所以未判」，是**解析腿漏抽**（`判据的可信性.md` §三.5）。
    """
    原文 = 实现条目["字段"].get("参数表", {}).get("原文")
    if 原文 is None:
        return None
    原文文本 = 原文.strip()
    正则匹配 = re.match(r"([^\s.(]+)\s*\.\s*as_ptr", 原文文本) or re.match(r"^([^\s.()]+)$", 原文文本)
    if not 正则匹配:
        return None
    return 末段(正则匹配.group(1))


def _落点(扫描单元: dict, 名称: str) -> object:
    """本单元里名为 `名称` 的 const（③g / ③h 的编译期断言落点）；没有返回 None。

    为什么按**名**取 const 而不扫表声明：落点是**声明过的契约名**（只在一处定义，
    改口径只改那一处），而扫声明文本会因换个命名 / 挪个位置就漏（假绿）。
    """
    for 条目项 in 扫描单元["常量"]:
        if 条目项["名"] == 名称:
            return 条目项
    return None
