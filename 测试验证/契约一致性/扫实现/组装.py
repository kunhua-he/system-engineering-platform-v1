# -*- coding: utf-8 -*-
"""组装 —— 一条判据一条记录：样本状态声明 + 三元判定装配。"""
from __future__ import annotations

from .常量 import 判据名表
from .判据工具 import 记


样本状态 = {
    判据名表[0]: {"正向": True, "反向": True},   # ③a
    判据名表[1]: {"正向": True, "反向": True},   # ③b
    判据名表[2]: {"正向": True, "反向": True},   # ③c
    判据名表[3]: {"正向": True, "反向": True},   # ③d1
    判据名表[4]: {"正向": True, "反向": True},   # ③d2（`可抛错误码` 字段已进形状 ⇒ 反向样本可造）
    判据名表[5]: {"正向": True, "反向": True},   # ③e
    判据名表[6]: {"正向": True, "反向": True},   # ③f
    判据名表[7]: {"正向": True, "反向": True},   # ③g（读编译期断言落点）
    判据名表[8]: {"正向": True, "反向": True},   # ③h（读编译期断言落点）
    判据名表[9]: {"正向": True, "反向": True},   # ③i
    判据名表[10]: {"正向": True, "反向": True},  # ③j
    判据名表[11]: {"正向": True, "反向": True},  # ③k（扩展声明自洽，台账 #201）
}


def _组装(比对结果: dict) -> list:
    出 = []
    for 名 in 判据名表:
        条 = 比对结果.get(名, {"明细": [], "扫描面": "", "扫描读数": "", "已判": 0})
        明细 = list(条["明细"])
        已判 = 条.get("已判", 0)
        # 「按设计不覆盖」的格（`判定` == "不覆盖"）：它不是失败、也不是未判 ——
        # 三元判定**不看它**（三元仍是三元，含义不动）；它是第四个数，按格计、不阻塞退出码。
        不覆盖 = [d for d in 明细 if d["判定"] == "不覆盖"]
        判 = "通过"
        if any(d["判定"] == "失败" for d in 明细):
            判 = "失败"
        elif any(d["判定"] == "未判" for d in 明细):
            判 = "未判"
        elif 已判 <= 0 and not 不覆盖:
            # 「比过之后全对」与「没东西可比」必须分开（判据的可信性 §二）
            判 = "未判"
            明细.append(
                记(名, "未判", "（无明细）",
                   "扫描 0 项：本判据在这次运行里一项都没比过 ⇒ 空集不算通过",
                   "空集说明判据的对象不存在，或解析腿没抽到东西；两者在读数上不可区分 ⇒ "
                   "只能由实现方/声明方确认对象是否存在")
            )
        else:
            已比 = (
                f"已比 {已判} 项，未发现不一致"
                if 已判 > 0
                else "本判据的格全部按设计不覆盖（见 `扫实现/不覆盖.py::不覆盖登记`）⇒ 没有待判项"
            )
            明细.append(记(名, "通过", "（比过之后全对）", 已比, "—"))
        样本 = 样本状态.get(名, {"正向": False, "反向": False})
        已验证 = bool(样本["正向"] and 样本["反向"])
        if 判 == "通过" and not 已验证:
            判 = "未判"
            明细.append(
                记(名, "未判", "（判据自身未验证）",
                   "未验证：这条判据缺正向样本或反向样本（判据的可信性 §五）⇒ 它的「通过」不计入通过数",
                   "补样本是验证面自己的活（自测里注入该抓的违规 + 喂一份干净输入）⇒ 只能由验证面补")
            )
        失败 = [d for d in 明细 if d["判定"] == "失败"]
        未判 = [d for d in 明细 if d["判定"] == "未判"]
        通过条 = [d for d in 明细 if d["判定"] == "通过"]
        代表 = 失败 or 未判 or 通过条 or 明细
        出.append(
            {
                "项": 名,
                "位置": " ↔ ".join(d["位置"] for d in 代表[:6]),
                "缺什么": 代表[0]["缺什么"],
                "为什么不能自愈": 代表[0]["为什么不能自愈"],
                "判定": 判,
                "扫描面": 条["扫描面"],
                "扫描读数": 条["扫描读数"],
                "红类": (失败[0]["红类"] or "源码错") if 失败 else "",
                "已验证": 已验证,
                "样本": 样本,
                "已判": 已判,
                "明细": 明细,
            }
        )
    return 出
