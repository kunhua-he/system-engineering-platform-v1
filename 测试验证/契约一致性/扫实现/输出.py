# -*- coding: utf-8 -*-
"""输出 —— 打印（三元读数 + 失败/未判逐条）与 打印读数（扫描面 · 读数 · 样本状态）。"""
from __future__ import annotations

import sys


def 打印比对结果(判定汇总: list, 耗时毫秒=None, 输出流=None) -> None:
    输出流 = 输出流 or sys.stdout
    通过 = [判据读数 for 判据读数 in 判定汇总 if 判据读数["判定"] == "通过"]
    失败 = [判据读数 for 判据读数 in 判定汇总 if 判据读数["判定"] == "失败"]
    未判 = [判据读数 for 判据读数 in 判定汇总 if 判据读数["判定"] == "未判"]
    # 「不覆盖」是**第四个数**：按格（明细）计，不阻塞退出码（`失败 == 0 and 未判 == 0`）。
    # 三元（通过/失败/未判）仍是三元、按判据计、含义不动。
    不覆盖 = [明细条 for 判据读数 in 判定汇总 for 明细条 in 判据读数["明细"] if 明细条["判定"] == "不覆盖"]
    未验 = [判据读数 for 判据读数 in 判定汇总 if not 判据读数["已验证"]]
    尾部 = f" · 耗时 {耗时毫秒} ms" if 耗时毫秒 is not None else ""
    print(
        f"通过 {len(通过)} 项 · 失败 {len(失败)} 项 · 未判 {len(未判)} 项 · "
        f"不覆盖 {len(不覆盖)} 项{尾部}",
        file=输出流,
    )
    if 未验:
        print(
            f"（其中 {len(未验)} 条判据**未验证**：缺正向或反向样本，其「通过」不计入通过数）",
            file=输出流,
        )
    if 失败:
        print("", file=输出流)
        print("失败逐条：", file=输出流)
        for 判据读数 in 失败:
            for 明细条 in 判据读数["明细"]:
                if 明细条["判定"] != "失败":
                    continue
                print(
                    f"- {判据读数['项']} ｜ {明细条['位置']} ｜ 缺什么：{明细条['缺什么']} ｜ "
                    f"为什么不能自愈：{明细条['为什么不能自愈']} ｜ 红类：{明细条['红类'] or '源码错'}",
                    file=输出流,
                )
    if 未判:
        print("", file=输出流)
        print("未判逐条（空集与判不了都不算通过）：", file=输出流)
        for 判据读数 in 未判:
            for 明细条 in 判据读数["明细"]:
                if 明细条["判定"] != "未判":
                    continue
                print(
                    f"- {判据读数['项']} ｜ {明细条['位置']} ｜ {明细条['缺什么']} ｜ 为什么不能自愈：{明细条['为什么不能自愈']}",
                    file=输出流,
                )
    if 不覆盖:
        print("", file=输出流)
        print("不覆盖逐条（按设计不覆盖：声明的范围之外，不阻塞退出码；覆盖者见登记表）：", file=输出流)
        for 判据读数 in 判定汇总:
            for 明细条 in 判据读数["明细"]:
                if 明细条["判定"] != "不覆盖":
                    continue
                print(
                    f"- {判据读数['项']} ｜ {明细条['位置']} ｜ {明细条['缺什么']} ｜ 为什么不能自愈：{明细条['为什么不能自愈']}",
                    file=输出流,
                )


def 打印读数(判定汇总: list) -> None:
    print("每条判据的扫描面 · 实际读数 · 样本状态（元判据用）：")
    for 判据读数 in 判定汇总:
        print(f"· {判据读数['项']}")
        print(f"  判定：{判据读数['判定']}{'（未验证）' if not 判据读数['已验证'] else ''} · 红类：{判据读数['红类'] or '—'} · 已判 {判据读数['已判']} 项")
        print(f"  扫描面：{判据读数['扫描面']}")
        print(f"  扫描读数：{判据读数['扫描读数']}")
        print(f"  样本：正向={判据读数['样本']['正向']} 反向={判据读数['样本']['反向']}")
