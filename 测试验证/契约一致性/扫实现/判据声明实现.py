# -*- coding: utf-8 -*-
"""判据声明实现 —— ③a ③b ③c ③d1 ③d2 ③f：按声明根驱动的 实现 ↔ 声明 比对。"""
from __future__ import annotations

from .常量 import 判据名表, 底座声明根
from .小工具 import 是整数
from .符号解析 import 解符号
from .判据工具 import (
    记,
    _本表,
    _取编号,
    _解可抛错误码,
    _按编号找命令,
    _参数表名,
)


def 比一声明根(出: dict, 根: str, 单元集: list, 声明根表: dict, 符号表: dict) -> None:
    """③a–③d2 与 ③f：对一份声明根下的每个实现单元逐条比对（明细与已判都写进 `出`）。"""
    声明能力 = {}
    for 键, (数, _) in 声明根表[根]["能力声明"].items():
        n = 数.get("编号")
        声明能力[n] = (数, 键)
    是底座 = 根 == 底座声明根
    for u in 单元集:
        实现能力 = {}
        for c in u["能力号"]:
            if c["值"] is not None:
                实现能力.setdefault(c["值"], c["位置"])
        for c in u["命令"]:
            if c["编号"] is not None:
                实现能力.setdefault(c["编号"], c["位置"])

        # ── ③a 声明有实现无 ──
        if not 声明能力:
            出[判据名表[0]]["明细"].append(
                记(判据名表[0], "未判", f"{根}/能力声明/",
                   f"扫描 0 项：{根}/能力声明/ 里一份声明都没有 ⇒ 这一半是空集（空集不算通过）。"
                   f"同一声明根下的实现侧有 {len(实现能力)} 个编号"
                   f"（{sorted(x for x in 实现能力 if x is not None)}）",
                   "空集有两种可能：这份声明还没写能力，或目录被删了；两者在磁盘上不可区分，"
                   "而「补哪些能力声明」是声明方的活 ⇒ 只能由声明方补")
            )
        else:
            for n in sorted(声明能力, key=lambda x: (x is None, x)):
                数, 键 = 声明能力[n]
                if n is None:
                    出[判据名表[0]]["明细"].append(
                        记(判据名表[0], "未判", f"{键}:编号",
                           "判不了：这份能力声明没有可用的 编号（缺字段或不是整数）⇒ 无法与实现对照",
                           "编号是唯一对照键；字段缺失或形状不对只能由声明方按 §三 补")
                    )
                    continue
                出[判据名表[0]]["已判"] += 1
                if n not in 实现能力:
                    出[判据名表[0]]["明细"].append(
                        记(判据名表[0], "失败", f"{键}:编号",
                           f"声明了能力编号 {n}（「{数.get('名称')}」），但 {u['目录']} 的实现里"
                           f"既没有 能力号 常量、也没有命令表项指向 {n}"
                           f"（实现里有：{sorted(x for x in 实现能力 if x is not None)}）",
                           f"编号是显式字段（`命令信息.编号`，见 `契约声明/src/lib.rs` 旁路区）："
                           f"要在实现里补一位，就得定它的编号、补在命令表哪一项、"
                           f"以及它是不是占位项——那是实现方的活，验证面补一位等于替它编实现 ⇒ "
                           f"只能由实现方补", "源码错")
                    )

        # ── ③b 实现有声明无 ──
        if not 声明能力:
            注 = (
                f"**注**：底座 0xxx 已进 `契约声明/能力声明/`（`0000.json`，编号 0）⇒ "
                f"这条口径已裁；本处读数说明它又被删回空目录了"
                if 是底座
                else f"**注**：{根}/能力声明/ 是空目录，而实现侧有编号——这份声明还没写能力"
            )
            出[判据名表[1]]["明细"].append(
                记(判据名表[1], "未判", f"{根}/能力声明/",
                   f"判不了：{根}/能力声明/ 为空集，而实现侧有 {len(实现能力)} 个编号"
                   f"（{sorted(x for x in 实现能力 if x is not None)}）⇒ 「实现有声明无」这一半"
                   f"对不了。{注}",
                   "口径未定：补声明（=把该段命令对外公布）与不补声明（=该段不对外）"
                   "是两种都自洽的做法；选哪种是契约侧裁决 ⇒ 只能由契约侧裁")
            )
        else:
            for n in sorted(x for x in 实现能力 if x is not None):
                出[判据名表[1]]["已判"] += 1
                if n not in 声明能力:
                    出[判据名表[1]]["明细"].append(
                        记(判据名表[1], "失败", 实现能力[n],
                           f"实现里有能力编号 {n}，但 {根}/能力声明/ 里没有它的声明",
                           f"编号已进实现（可能已被调用方按号调用）；补声明要写全参数表 · 返回类型 · "
                           f"可抛错误码，那是声明方的活；撤实现会废掉一个已落地的号 ⇒ "
                           f"只能由声明方补（或人来裁撤哪一边）", "源码错")
                    )

        # ── ③c 参数行序与个数 ──
        if not 声明能力:
            出[判据名表[2]]["明细"].append(
                记(判据名表[2], "未判", f"{根}/能力声明/",
                   f"扫描 0 项：{根}/能力声明/ 为空 ⇒ 没有可比对的 参数表",
                   "参数行序即契约（§三）；声明侧空集时这一半无从比对 ⇒ 只能由声明方补")
            )
        for n in sorted(x for x in 声明能力 if x is not None):
            数, 键 = 声明能力[n]
            参 = 数.get("参数表")
            位置 = f"{键}:参数表"
            if not isinstance(参, list):
                出[判据名表[2]]["明细"].append(
                    记(判据名表[2], "未判", 位置,
                       f"判不了：声明的 参数表 不是列表（{type(参).__name__}）⇒ 行数取不出",
                       "§三 定死 参数表 是列表（空表也写 []）；形状不对只能由声明方补")
                )
                continue
            实现条 = _按编号找命令(u, n)
            if 实现条 is None:
                continue  # ③a 已报
            个 = 实现条["字段"].get("参数个数", {}).get("值")
            if 个 is None:
                出[判据名表[2]]["明细"].append(
                    记(判据名表[2], "未判", 实现条["位置"],
                       f"判不了：命令 {n} 的 参数个数 原文是 "
                       f"「{实现条['字段'].get('参数个数', {}).get('原文')}」，静态解析取不出它的值",
                       "参数个数 是构造器实参；解不出它就没法比行数。改法只有两种：写成整数字面量，"
                       "或由契约侧给出可静态求值的写法 ⇒ 只能由实现方补")
                )
                continue
            出[判据名表[2]]["已判"] += 1
            if 个 != len(参):
                出[判据名表[2]]["明细"].append(
                    记(判据名表[2], "失败", 实现条["位置"],
                       f"能力 {n} 的 声明参数表 有 {len(参)} 行，实现的 参数个数 是 {个}",
                       f"参数表行序即契约（§三 冻结项）：行数不符意味着两侧对这条命令的入参"
                       f"个数不一致。改声明会改已公布的调用形状，改实现会让调用方少/多传一个槽 ⇒ "
                       f"只能人来裁以哪边为准（若走旁路登记则先改冻结登记）", "源码错")
                )
                continue
            # 逐位比类型标签（行序）
            for i, 行 in enumerate(参):
                if not isinstance(行, dict):
                    continue
                声 = 行.get("类型标签")
                if not 是整数(声):
                    continue
                参表名 = _参数表名(实现条)
                if 参表名 is None:
                    continue
                pt = u["参数表"].get(参表名)
                if pt is None or i >= len(pt["类型标签原文"]):
                    continue
                原文 = pt["类型标签原文"][i]
                实 = 解符号(原文, 符号表, _本表(u))
                if 实 is None:
                    出[判据名表[2]]["明细"].append(
                        记(判据名表[2], "未判", pt["位置"],
                           f"判不了：能力 {n} 第 {i} 位的实现类型标签原文是「{原文}」，"
                           f"静态解析取不出它的值",
                           "类型标签是跨边界放值的唯一锚点（§四）；解不出它就没法逐位比对 ⇒ "
                           "只能由实现方改成可静态求值的写法")
                    )
                    continue
                if 实 != 声:
                    出[判据名表[2]]["明细"].append(
                        记(判据名表[2], "失败", pt["位置"],
                           f"能力 {n} 第 {i} 位（0 起）：声明 类型标签 {声}，实现 类型标签 {实}"
                           f"（原文「{原文}」）",
                           f"参数行序即契约：同一位的标签不同，意味着两侧对「第 {i} 位放什么」"
                           f"的约定不一致，跨边界取值会按错标签解释。改声明会改已公布的参数语义，"
                           f"改实现会让已在跑的调用方取错值 ⇒ 只能人来裁", "源码错")
                    )

        # ── ③d1 返回类型 ──
        if not 声明能力:
            出[判据名表[3]]["明细"].append(
                记(判据名表[3], "未判", f"{根}/能力声明/",
                   f"扫描 0 项：{根}/能力声明/ 为空 ⇒ 没有可比对的 返回类型",
                   "§三：返回类型 决定调用方怎么解返回槽；声明侧空集时这一半无从比对 ⇒ "
                   "只能由声明方补")
            )
        for n in sorted(x for x in 声明能力 if x is not None):
            数, 键 = 声明能力[n]
            声 = 数.get("返回类型")
            实现条 = _按编号找命令(u, n)
            if 实现条 is None:
                continue
            if not 是整数(声):
                出[判据名表[3]]["明细"].append(
                    记(判据名表[3], "未判", f"{键}:返回类型",
                       f"判不了：声明的 返回类型 不是整数（{声!r}）",
                       "§三：返回类型 0 表示无返回值；字段缺失或形状不对只能由声明方补")
                )
                continue
            原 = 实现条["字段"].get("返回类型", {}).get("原文")
            实 = 实现条["字段"].get("返回类型", {}).get("值")
            if 实 is None:
                出[判据名表[3]]["明细"].append(
                    记(判据名表[3], "未判", 实现条["位置"],
                       f"判不了：命令 {n} 的 返回类型 原文是「{原}」，静态解析取不出它的值",
                       "返回类型是返回槽的解释依据；解不出它就没法比 ⇒ 只能由实现方改成可静态求值的写法")
                )
                continue
            出[判据名表[3]]["已判"] += 1
            if 实 != 声:
                出[判据名表[3]]["明细"].append(
                    记(判据名表[3], "失败", 实现条["位置"],
                       f"能力 {n}：声明 返回类型 {声}，实现 返回类型 {实}（原文「{原}」）",
                       f"返回类型决定调用方怎么解返回槽（§三）；两侧不一致会让返回槽被按错的"
                       f"类型解释。改声明会改已公布的返回语义，改实现会让已在跑的调用方取错 ⇒ "
                       f"只能人来裁", "源码错")
                )

        # ── ③d2 可抛错误码 ──
        # 读法：`命令信息.可抛错误码` 是旁路区字段 `表段<u32>`（`契约声明/src/lib.rs`）⇒
        # 声明 `可抛错误码` ↔ 该命令字段指向的码集，逐项比。空表（`表段::空()`）与
        # 声明 `[]` 都是合法值（= 本命令不抛错），**不许**当成「漏写」或「空集未判」。
        if not 声明能力:
            出[判据名表[4]]["明细"].append(
                记(判据名表[4], "未判", f"{根}/能力声明/",
                   f"扫描 0 项：{根}/能力声明/ 为空 ⇒ 没有可比对的 可抛错误码",
                   "可抛错误码 是调用方按码做处置（重试 / 自愈 / 报人工）的依据（§五）；"
                   "声明侧空集时这一半无从比对 ⇒ 只能由声明方补")
            )
        for n in sorted(x for x in 声明能力 if x is not None):
            数, 键 = 声明能力[n]
            声 = 数.get("可抛错误码")
            实现条 = _按编号找命令(u, n)
            if 实现条 is None:
                continue  # ③a 已报
            if not isinstance(声, list):
                出[判据名表[4]]["明细"].append(
                    记(判据名表[4], "未判", f"{键}:可抛错误码",
                       f"判不了：声明的 可抛错误码 不是列表（{type(声).__name__}）⇒ 码集取不出",
                       "§三 定死 可抛错误码 是列表（空表也写 []）；形状不对只能由声明方补")
                )
                continue
            f = 实现条["字段"].get("可抛错误码")
            if f is None:
                出[判据名表[4]]["明细"].append(
                    记(判据名表[4], "未判", 实现条["位置"],
                       f"判不了：命令 {n} 的构造器没有 可抛错误码 字段（`命令信息` 旧形状）⇒ "
                       f"声明里的 {sorted(声)} 在实现面上没有对照物",
                       "`命令信息.可抛错误码` 是旁路区字段（`契约声明/src/lib.rs` 命令信息 · 旁路区）；"
                       "实现侧还没跟上新形状 ⇒ 只能由实现方按新形状补")
                )
                continue
            实 = _解可抛错误码(u, f.get("原文"), 符号表, _本表(u))
            if 实 is None:
                出[判据名表[4]]["明细"].append(
                    记(判据名表[4], "未判", 实现条["位置"],
                       f"判不了：命令 {n} 的 可抛错误码 原文是「{f.get('原文')}」，"
                       f"静态解析取不出它指向的码集",
                       "本模块只认两种写法：`表段::空()` 与 "
                       "`表段::新(<本单元 [u32; N] 表>.as_ptr(), …)`（且表项要能逐个解成整数）；"
                       "其余写法要判得先能静态看到码集 ⇒ 只能由实现方改成可静态求值的写法")
                )
                continue
            出[判据名表[4]]["已判"] += 1
            if sorted(实) != sorted(声):
                出[判据名表[4]]["明细"].append(
                    记(判据名表[4], "失败", 实现条["位置"],
                       f"能力 {n}：声明 可抛错误码 {sorted(声)}（{len(声)} 条），"
                       f"实现 可抛错误码 {sorted(实)}（{len(实)} 条）（原文「{f.get('原文')}」）",
                       "可抛错误码 是调用方按码做处置（重试 / 自愈 / 报人工）的依据（§五）："
                       "实现多抛一个未声明的码，调用方没有处置分支；少一个则调用方白写分支。"
                       "改声明会改已公布的失败面，改实现会改已落地的行为 ⇒ 只能人来裁", "源码错")
                )

        # ── ③f 错误码表 ──
        e = u["错误码表"]
        if e["来源"] == "生成物":
            出[判据名表[6]]["明细"].append(
                记(判据名表[6], "未判", e["位置"] or f"{u['目录']}/",
                   f"判不了：本单元的错误码表来自生成物（原文「{e.get('原文')}」）⇒ "
                   f"实现面上没有可数的项。这半边等价于声明侧第 10 项（生成物 ↔ JSON 指纹比对），"
                   f"本判据**不重复声称覆盖**它",
                   "生成物是声明侧的唯一来源（§八）；要判它的内容，得由声明侧的生成物指纹闸来判"
                   "（`构建装配/形态装配/生成声明.py --检查`）⇒ 只能由声明侧那一项覆盖")
            )
        elif not e["表"]:
            出[判据名表[6]]["明细"].append(
                记(判据名表[6], "未判", f"{u['目录']}/",
                   "扫描 0 项：本单元生产区里没有 错误码信息 字面量表 ⇒ 空集不算通过",
                   "本单元可能真的没有错误码（合法），也可能是表写成了别的形状（解析腿漏抽）；"
                   "两者读数上不可区分 ⇒ 只能由实现方确认")
            )
        else:
            声明码 = {}
            for 键, (数, _) in (声明根表.get(根, {}).get("错误码表", {}) or {}).items():
                c = 数.get("码")
                声明码[c] = (数, 键)
            实现码 = {}
            for t in e["表"]:
                实现码.setdefault(t["码"], t)
            出[判据名表[6]]["已判"] += max(len(声明码), len(实现码))
            for c in sorted(x for x in 声明码 if x is not None):
                if c not in 实现码:
                    数, 键 = 声明码[c]
                    出[判据名表[6]]["明细"].append(
                        记(判据名表[6], "失败", f"{键}:码",
                           f"声明了错误码 {c}（「{数.get('名称')}」），但 {u['目录']} 的"
                           f" 错误码信息 表里没有它（实现里有：{sorted(x for x in 实现码 if x is not None)}）",
                           f"§五：未登记不许抛出，反过来登记了就该有实现面的落点。补一条要定"
                           f"「可重试 · 可自愈 · 需人工」三项业务语义 ⇒ 只能由实现方补", "源码错")
                    )
            for c in sorted(x for x in 实现码 if x is not None):
                if c not in 声明码:
                    出[判据名表[6]]["明细"].append(
                        记(判据名表[6], "失败", 实现码[c]["位置"],
                           f"实现里登记了错误码 {c}，但 {根}/错误码表/ 里没有它",
                           "§五：未登记的错误码不许抛出。补登记要写全四项（三项业务判断 + 段位），"
                           "那是声明方的活 ⇒ 只能由声明方补", "源码错")
                    )
            for t in e["表"]:
                c, s = t["码"], t["段位"]
                if c is None or s is None:
                    出[判据名表[6]]["明细"].append(
                        记(判据名表[6], "未判", t["位置"],
                           f"判不了：错误码项原文「{t['原文']}」的 码/段位 静态解析取不出"
                           f"（码={c} · 段位={s}）",
                           "码与段位都必须可静态求值才能交叉比对（§五：段位 == 码//1000）⇒ "
                           "只能由实现方改成可静态求值的写法")
                    )
                    continue
                if s != c // 1000:
                    出[判据名表[6]]["明细"].append(
                        记(判据名表[6], "失败", t["位置"],
                           f"码 {c} 的首位十进制数字是 {c // 1000}，实现里写的 段位 是 {s}",
                           "§五：段位 是**冗余登记项**，故意写出来让验证面交叉比对抓错。"
                           "改码要动全局唯一号，改段位要改归属 ⇒ 只能人来裁", "源码错")
                    )
