"""不覆盖 —— 「按设计不覆盖」登记表（唯一一张）· 查询 · 校验（fail-closed）· 元记录。

为什么单列一档：`未判` 是「**本该判却判不了**」（是缺口）；`不覆盖` 是
「**按设计就不在本判据的范围内**」（是声明的范围）。两者原先混在「未判」里 ⇒ 闸 2 的
退出码（`失败 == 0 and 未判 == 0`）永远红，谁也不再拿它当信号。

- **三元仍是三元**：`通过 / 失败 / 未判` 仍按判据分类，含义不动。
- **「不覆盖」是第四个数（按格计）**，不阻塞退出码。
- **一处事实一个落点**：登记表只在本文件里写一份；判据里只留一句「见不覆盖登记表」。
- **fail-closed**：登记表会长霉 —— 「判据名不在 判据名表 里」或「登记的单元在本次扫描面里
  不存在」一律记**失败**（不是未判）。不检查的话，登记表就变成「永久豁免」的后门。
"""
from __future__ import annotations

from pathlib import Path

from .常量 import 判据名表
from .判据工具 import 记

# 元判据名：登记表自洽这条检查自身的名字（它不在 `判据名表` 里 —— 它是判据面的自检，
# 只在长霉时以一条**失败**记录出现，不参与常规的通过/未判读数）。
元判据名 = "不覆盖登记表自洽（元判据）"

# ── 唯一一张「不覆盖登记表」 ──
# 每条至少写：判据名 · 单元（或范围）· 为什么本判据不覆盖 · 由谁覆盖（指到那个判据/命令）。
不覆盖登记 = (
    {
        "判据名": 判据名表[6],  # ③f 错误码表 码/段位（实现 ↔ 声明）
        "单元": "运行内核/装载入口",
        "为什么": (
            "本单元的错误码表来自生成物（原文 `v1_contract::声明数据::错误码信息表段()`）"
            "⇒ 实现面上没有可数的项；生成物是声明侧的唯一来源，本判据不重复声称覆盖它"
        ),
        "由谁覆盖": (
            "声明侧第 10 项（生成物 ↔ JSON 指纹比对）："
            "`构建装配/形态装配/生成声明.py --检查`"
        ),
    },
)


def 查不覆盖(判据名: str, 单元: str):
    """本次扫描里这一格是否按设计不覆盖；是则返回登记条，否则 None。"""
    for 登记条 in 不覆盖登记:
        if 登记条["判据名"] == 判据名 and 登记条["单元"] == 单元:
            return 登记条
    return None


def 校验登记(单元表: list, 登记=None, 仓根: str = None, 范围: list = None) -> list:
    """fail-closed：登记表长霉即红。返回失败明细（`判定` = 失败）。

    `登记` 只为自测注入而设（默认用本文件那张唯一表）——「清空表 ⇒ ③f 那半边回到未判」
    与「写一个不存在的判据名 ⇒ 报红」两条反向样本靠它造。

    **按范围过滤**（`仓根` / `范围` 给定时的唯一新增口径）：登记表是**全仓**一张，
    而扫描面是**本次范围**。一条登记的单元落在本次范围**之外**、却在仓里**确实存在**
    （目录在盘上）⇒ 本范围**不判它**（不是长霉）—— 否则「扩展专属档」这种窄范围
    会因底座单元的登记而恒红（那是假红；口径见 `项目文档/决策记录/2026-09-27_扩展侧本地自检的成对判据口径.md`）。
    **不放宽的两种**：① 单元在本次**范围内**却不在扫描面里 ⇒ 仍报红（真长霉）；
    ② 单元在范围外且仓里**不存在** ⇒ 仍报红（登记悬空）。
    未给 `仓根`/`范围`（自测直调）⇒ 退回旧口径（严格按 `单元表` 比），反向样本照旧成立。
    """
    有效判据 = set(判据名表)
    有效单元 = {登记单元["目录"] for 登记单元 in 单元表}
    # **按范围过滤**（唯一的放宽，理由见文档串）：登记表是**全仓**一张、扫描面是**本次范围**
    # ⇒ 一条登记的单元落在本次范围之外、却在仓里确实存在（目录在盘上）时，本范围**不判它**。
    # 把它并进 `有效单元` ⇒ 循环体与原先逐字相同（判定口径不动，只多这一句集合运算）。
    # 不放宽的两种仍照红：① 单元在本次范围内却没扫到 ② 单元在范围外且仓里不存在。
    有效单元 |= {
        条["单元"]
        for 条 in (不覆盖登记 if 登记 is None else 登记)
        if 单元在本次范围外但存在(条["单元"], 仓根, 范围)
    }
    出 = []
    for 登记序, 登记条 in enumerate(不覆盖登记 if 登记 is None else 登记):
        位 = f"扫实现/不覆盖.py::不覆盖登记[{登记序}]"
        if 登记条["判据名"] not in 有效判据:
            出.append(
                记(元判据名, "失败", 位,
                   f"登记的判据名「{登记条['判据名']}」不在 判据名表 里（判据名表 {len(判据名表)} 条）"
                   f"⇒ 这条豁免悬空，谁都不会被它挡住",
                   "登记表是「按设计不覆盖」的唯一落点；判据名写错 = 一条永远生效的假豁免"
                   "（要防的正是这种后门）。改法是把它改成 判据名表 里的实名 ⇒ "
                   "只能由登记表的作者改", "源码错")
            )
        if 登记条["单元"] not in 有效单元:
            出.append(
                记(元判据名, "失败", 位,
                   f"登记的单元「{登记条['单元']}」在本次扫描面里不存在（实测单元 {len(有效单元)} 个）"
                   f"⇒ 这条登记指向一个不存在的对象",
                   "登记表按「判据名 · 单元」定位一格；单元不存在说明落点变了或写错了 ⇒ "
                   "登记表会静默失效（豁免了一个不存在的格，而真格子没人管）⇒ "
                   "只能由登记表的作者按实测单元改", "源码错")
            )
    return 出


def 单元在本次范围外但存在(单元: str, 仓根, 范围) -> bool:
    """这个登记的单元是否「落在本次范围之外、却在仓里确实存在」。

    两个条件缺一不可：① 单元不在 `范围` 里（否则它就该被扫描面看见，看不见才是长霉）；
    ② 仓根给定了，且 `仓根/单元` 在盘上是个目录（否则是悬空登记，仍要报红）。
    """
    if 仓根 is None or 范围 is None:
        return False
    在范围内 = any(单元 == 前缀 or 单元.startswith(前缀.rstrip("/") + "/") for 前缀 in 范围)
    if 在范围内:
        return False
    return (Path(仓根) / 单元).is_dir()


def 元记录(单元表: list, 仓根: str = None, 范围: list = None) -> list:
    """登记表自洽的元记录：**只在长霉时出现**（干净时返回空，不参与常规读数）。

    `仓根` / `范围` 只为「按范围过滤」用（见 `校验登记`）——窄范围（扩展专属档）
    不该因底座单元的登记而报假红。
    """
    明细 = 校验登记(单元表, 仓根=仓根, 范围=范围)
    if not 明细:
        return []
    return [
        {
            "项": 元判据名,
            "位置": " · ".join(明细条["位置"] for 明细条 in 明细[:6]),
            "缺什么": 明细[0]["缺什么"],
            "为什么不能自愈": 明细[0]["为什么不能自愈"],
            "判定": "失败",
            "扫描面": "扫实现/不覆盖.py::不覆盖登记（唯一一张「按设计不覆盖」登记表）",
            "扫描读数": f"登记 {len(不覆盖登记)} 条 · 本次扫描面单元 {len(单元表)} 个",
            "红类": "源码错",
            "已验证": True,
            "样本": {"正向": True, "反向": True},
            "已判": len(不覆盖登记),
            "明细": 明细,
        }
    ]
