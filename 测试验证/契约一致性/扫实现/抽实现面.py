# -*- coding: utf-8 -*-
"""抽实现面 —— 按 crate 单元聚合逐文件抽取结果（只吃范围下的 .rs 生产区）。"""
from __future__ import annotations

import re

from .小工具 import 配对, 拆顶层项, 行号
from .掩码 import 掩码
from .夹具判定 import 生产区
from .符号解析 import 解符号
from .判据工具 import _取编号
from .抽取件 import (
    抽模块常量,
    抽构造器,
    抽本文件整数常量,
    抽数组表,
    抽参数表,
    抽类型表,
    抽错误码表,
    抽导出,
    抽常量,
)

def 找所属单元(键: str, 件表: dict) -> str:
    """文件的 crate 根 = **最近的**含 Cargo.toml 的祖先目录（`src/` 在 crate 根下一层）。"""
    段 = 键.split("/")[:-1]
    for i in range(len(段), 0, -1):
        候选 = "/".join(段[:i])
        if f"{候选}/Cargo.toml" in 件表:
            return 候选
    return ""


def 抽实现面(件表: dict, 范围: list, 符号表: dict, 夹具: dict, 掩表: dict = None) -> dict:
    """返回 {"单元": [...], "计数": {...}}。只吃 `范围` 下的 .rs 生产区。"""
    Rs = {
        k: v
        for k, v in 件表.items()
        if k.endswith(".rs") and v is not None and 任内(k, 范围)
    }
    单元表 = {}
    for 键 in Rs:
        目录 = 找所属单元(键, 件表)
        if 目录:
            单元表.setdefault(目录, []).append(键)
    单元 = []
    计数 = {
        "文件": 0, "夹具文件": 0, "夹具块": 0, "其它cfg": 0,
        "能力号": 0, "命令": 0, "占位项": 0, "参数表": 0, "类型表": 0,
        "错误码": 0, "导出": 0, "常量": 0, "抛码表": 0,
    }
    for 目录 in sorted(单元表):
        名配 = re.search(
            r"^\s*name\s*=\s*\"([^\"]+)\"",
            件表.get(f"{目录}/Cargo.toml") or "",
            re.M,
        )
        单元.append(
            {
                "目录": 目录,
                "包名": 名配.group(1) if 名配 else "",
                "文件": sorted(单元表[目录]),
                "能力号": [],
                "错误码常量": [],
                "本文件整数常量": {},
                "命令": [],
                "参数表": {},
                "类型表": [],
                "类型标签引用": [],
                # `可抛错误码` 字段指向的 `[u32; N]` 表：表名 → {内文, 位置}（③d2 的对照物）
                "抛码表": {},
                "错误码表": {"表": [], "来源": None, "位置": None},
                "导出": [],
                "常量": [],
            }
        )
    索引 = {u["目录"]: u for u in 单元}
    for 目录 in sorted(单元表):
        u = 索引[目录]
        for 键 in sorted(单元表[目录]):
            if 键 in 夹具["整份夹具"]:
                continue  # 整份夹具：由父文件 #[cfg(test)] mod 引入，逐文件解析看不见 cfg(test)
            计数["文件"] += 1
            原 = 件表[键]
            块 = 夹具["块"].get(键, [])
            计数["夹具块"] += len(块)
            掩 = 生产区((掩表 or {}).get(键) or 掩码(原), 块)
            # 能力号 / 错误码 模块常量
            能力号 = 抽模块常量(掩, 键, "能力号")
            错误码 = 抽模块常量(掩, 键, "错误码")
            本文件常量 = 抽本文件整数常量(掩)
            本表 = {
                **{c["名"]: c["值"] for c in 能力号 if c["值"] is not None},
                **{c["名"]: c["值"] for c in 错误码 if c["值"] is not None},
                **本文件常量,
            }
            u["能力号"].extend(能力号)
            u["错误码常量"].extend(错误码)
            u["本文件整数常量"].update(本文件常量)
            计数["能力号"] += len(能力号)
            # 参数表
            参数表 = 抽参数表(掩, 键, 符号表)
            u["参数表"].update(参数表)
            计数["参数表"] += len(参数表)
            # 类型表
            tt = 抽类型表(掩, 键)
            u["类型表"].extend(tt)
            计数["类型表"] += len(tt)
            # 可抛错误码表：`命令信息.可抛错误码` 指向的 `[u32; N]` 表（③d2 的对照物）
            for t in 抽数组表(掩, "u32"):
                if t.get("内文") is None:
                    continue  # 值不是数组字面量（表达式）⇒ 解不出码集，③d2 报未判
                if t["表名"] not in u["抛码表"]:
                    u["抛码表"][t["表名"]] = t
                    计数["抛码表"] += 1
            # 命令表
            构造器 = 抽构造器(掩, "命令信息")
            for 表 in 抽数组表(掩, "命令信息"):
                if 表["表名"] in ("命令信息",):
                    continue
                if 表.get("是函数"):
                    表名 = 表["表名"]
                    内 = 表["内文"]
                    内起 = 表["内文起"]
                    for a in re.finditer(r"本表\s*\[([^\]]+)\]\s*=\s*([^\s(]+)\s*\(", 内):
                        实参起 = a.end() - 1
                        实参止 = 配对(内, 实参起)
                        实参 = 拆顶层项(内[实参起 + 1 : 实参止])
                        字段 = _按构造器解字段(构造器.get(a.group(2)), 实参, 符号表, 本表)
                        编号, 编号原文 = _取编号(字段, lambda: (解符号(a.group(1), 符号表, 本表), a.group(1).strip()))
                        u["命令"].append(
                            {
                                "编号": 编号,
                                "编号原文": 编号原文,
                                "构造": a.group(2),
                                "字段": 字段,
                                "位置": f"{键}:{行号(掩, 内起 + a.start())}",
                            }
                        )
                else:
                    内 = 表["内文"] or ""
                    内起 = 表["内文起"]
                    for 序, t in enumerate(拆顶层项(内)):
                        if "{" not in t:
                            continue
                        字段 = {}
                        内字段 = t.split("{", 1)[1]
                        if 内字段.rstrip().endswith("}"):
                            内字段 = 内字段.rstrip()[:-1]
                        for f in 拆顶层项(内字段):
                            if ":" in f:
                                名, 值 = f.split(":", 1)
                                名, 值 = 名.strip(), 值.strip()
                            else:
                                名 = 值 = f.strip()
                            字段[名] = {"原文": 值, "值": 解符号(值, 符号表, 本表)}
                        编号, 编号原文 = _取编号(字段, lambda: (序, f"下标 {序}"))
                        u["命令"].append(
                            {
                                "编号": 编号,
                                "编号原文": 编号原文,
                                "构造": "字面量",
                                "字段": 字段,
                                "位置": f"{键}:{行号(掩, 内起 + 内.find(t[:12]))}",
                            }
                        )
            # 错误码表
            e = 抽错误码表(掩, 键, 符号表, 本表)
            if e["表"] or (e["来源"] and u["错误码表"]["来源"] is None):
                u["错误码表"] = e
                计数["错误码"] += len(e["表"])
            # 类型标签引用（符号）
            for m in re.finditer(r"类型标签_\d+", 掩):
                u["类型标签引用"].append(
                    {"符号": m.group(0), "位置": f"{键}:{行号(掩, m.start())}"}
                )
            # 字面量 类型标签: N（参数信息 / 数据类型信息 / 命令信息 内）
            for m in re.finditer(r"类型标签\s*:\s*(\d+)", 掩):
                u["类型标签引用"].append(
                    {"符号": m.group(1), "位置": f"{键}:{行号(掩, m.start())}"}
                )
            # 导出
            ex = 抽导出(掩, 原, 键)
            u["导出"].extend(ex)
            计数["导出"] += len(ex)
            # 常量
            cs = 抽常量(掩, 键)
            u["常量"].extend(cs)
            计数["常量"] += len(cs)
    # 占位项计数：命令表里带 `占位` 的常量/字段
    计数["占位项"] = sum(
        1
        for u in 单元
        for c in u["常量"]
        if "占位" in (c["名"] or "")
    )
    # 命令条数：抽到的**命令项**总数（不是表数）——③g 的旧读法按表数计，缩表后那个数会骗人。
    计数["命令"] = sum(len(u["命令"]) for u in 单元)
    计数["其它cfg"] = len(夹具["其它cfg"])
    计数["夹具文件"] = len(夹具["整份夹具"])
    计数["件表总数"] = len(件表)
    return {"单元": 单元, "计数": 计数, "件表": 件表, "夹具": 夹具}


def _按构造器解字段(构造, 实参, 符号表, 本表) -> dict:
    """把一次构造器调用的实参映射成 命令信息/错误码信息 的字段。"""
    出 = {}
    if not 构造:
        return 出
    for 字段, (来, 文本) in 构造["字段"].items():
        if 来 == "形参":
            try:
                序 = 构造["形参"].index(文本)
            except ValueError:
                序 = -1
            if 0 <= 序 < len(实参):
                出[字段] = {"原文": 实参[序], "值": 解符号(实参[序], 符号表, 本表)}
        else:
            出[字段] = {"原文": 文本, "值": 解符号(文本, 符号表, 本表)}
    return 出


def 任内(键: str, 范围: list) -> bool:
    return any(键 == p or 键.startswith(p.rstrip("/") + "/") for p in 范围)
