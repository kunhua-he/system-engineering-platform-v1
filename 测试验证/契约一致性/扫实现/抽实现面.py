"""抽实现面 —— 按 crate 单元聚合逐文件抽取结果（只吃范围下的 .rs 生产区）。"""
from __future__ import annotations

import re

from .小工具 import 配对, 拆顶层项, 行号
from .掩码 import 掩码
from .夹具判定 import 生产区
from .符号解析 import 解符号
from .判据工具 import _取编号
from .抽取件 import (
    抽模块常量,
    抽构造器,
    抽本文件整数常量,
    抽数组表,
    抽参数表,
    抽类型表,
    抽错误码表,
    抽导出,
    抽常量,
)

def 找所属单元(键: str, 件表: dict) -> str:
    """文件的 crate 根 = **最近的**含 Cargo.toml 的祖先目录（`src/` 在 crate 根下一层）。"""
    段 = 键.split("/")[:-1]
    for 位次 in range(len(段), 0, -1):
        候选 = "/".join(段[:位次])
        if f"{候选}/Cargo.toml" in 件表:
            return 候选
    return ""


def 抽实现面(件表: dict, 范围: list, 符号表: dict, 夹具: dict, 掩表: dict = None) -> dict:
    """返回 {"单元": [...], "计数": {...}}。只吃 `范围` 下的 .rs 生产区。"""
    Rs = {
        件键: 裸值
        for 件键, 裸值 in 件表.items()
        if 件键.endswith(".rs") and 裸值 is not None and 任内(件键, 范围)
    }
    单元表 = {}
    for 键 in Rs:
        目录 = 找所属单元(键, 件表)
        if 目录:
            单元表.setdefault(目录, []).append(键)
    单元 = []
    计数 = {
        "文件": 0, "夹具文件": 0, "夹具块": 0, "其它cfg": 0,
        "能力号": 0, "命令": 0, "占位项": 0, "参数表": 0, "类型表": 0,
        "错误码": 0, "导出": 0, "常量": 0, "抛码表": 0,
    }
    for 目录 in sorted(单元表):
        名配 = re.search(
            r"^\s*name\s*=\s*\"([^\"]+)\"",
            件表.get(f"{目录}/Cargo.toml") or "",
            re.M,
        )
        单元.append(
            {
                "目录": 目录,
                "包名": 名配.group(1) if 名配 else "",
                "文件": sorted(单元表[目录]),
                "能力号": [],
                "错误码常量": [],
                "本文件整数常量": {},
                "命令": [],
                "参数表": {},
                "类型表": [],
                "类型标签引用": [],
                # `可抛错误码` 字段指向的 `[u32; N]` 表：表名 → {内文, 位置}（③d2 的对照物）
                "抛码表": {},
                "错误码表": {"表": [], "来源": None, "位置": None},
                "导出": [],
                "常量": [],
            }
        )
    索引 = {登记单元["目录"]: 登记单元 for 登记单元 in 单元}
    # ── 单元级常量表（2026-09-27 补：符号表的落点是**单元**不是文件）──
    #
    # **实测撞到**：扩展把 `pub mod 能力号` 按「形状与算法分家」拆到 `编号与码面/能力号定义.rs`，
    # 而命令表在 `命令声明面/命令表.rs` 里写 `本表[表内位(能力号::词法分析)] = 命令项(能力号::词法分析, …)`。
    # 原先 `本表` 只装**当前文件**的常量 ⇒ 那 7 条命令的 `编号` 全解不出来（= None）⇒
    # ③a 的兜底路径认不出、③c/③d1/③d2 对扩展侧**一条都比不了**而报未判。
    # 这不是「真的解不出」，是**解析腿漏抽**（`判据的可信性.md` §三.5 那一类假绿来源：
    # 覆盖面悄悄变窄而闸还是绿的）。
    #
    # 口径：符号表按**单元**（crate）建，与 `符号解析.建符号表` 对 `契约声明/src/` 的做法同形
    #   —— 那边也是「扫该目录下**全部** `.rs`」而不是某一个写死的路径。
    # 只用于**解符号**；`计数` 与 `u["能力号"]` 仍按逐文件累计（读数口径不动）。
    # 文件局部常量**优先**（同名时以本文件为准，同 Rust 的作用域直觉）。
    单元常量 = {}
    for 单元目录 in sorted(单元表):
        for 单元件 in sorted(单元表[单元目录]):
            if 单元件 in 夹具["整份夹具"]:
                continue
            块0 = 夹具["块"].get(单元件, [])
            掩0 = 生产区((掩表 or {}).get(单元件) or 掩码(件表[单元件]), 块0)
            for 常量条 in 抽模块常量(掩0, 单元件, "能力号") + 抽模块常量(掩0, 单元件, "错误码"):
                if 常量条["值"] is not None:
                    单元常量.setdefault(单元目录, {}).setdefault(常量条["名"], 常量条["值"])
            for 名, 值 in 抽本文件整数常量(掩0).items():
                if 值 is not None:
                    单元常量.setdefault(单元目录, {}).setdefault(名, 值)
    for 目录 in sorted(单元表):
        登记单元 = 索引[目录]
        for 键 in sorted(单元表[目录]):
            if 键 in 夹具["整份夹具"]:
                continue  # 整份夹具：由父文件 #[cfg(test)] mod 引入，逐文件解析看不见 cfg(test)
            计数["文件"] += 1
            原 = 件表[键]
            块 = 夹具["块"].get(键, [])
            计数["夹具块"] += len(块)
            掩 = 生产区((掩表 or {}).get(键) or 掩码(原), 块)
            # 能力号 / 错误码 模块常量
            能力号 = 抽模块常量(掩, 键, "能力号")
            错误码 = 抽模块常量(掩, 键, "错误码")
            本文件常量 = 抽本文件整数常量(掩)
            本表 = {
                **(单元常量.get(目录) or {}),
                **{常量条["名"]: 常量条["值"] for 常量条 in 能力号 if 常量条["值"] is not None},
                **{常量条["名"]: 常量条["值"] for 常量条 in 错误码 if 常量条["值"] is not None},
                **本文件常量,
            }
            登记单元["能力号"].extend(能力号)
            登记单元["错误码常量"].extend(错误码)
            登记单元["本文件整数常量"].update(本文件常量)
            计数["能力号"] += len(能力号)
            # 参数表
            参数表 = 抽参数表(掩, 键, 符号表)
            登记单元["参数表"].update(参数表)
            计数["参数表"] += len(参数表)
            # 类型表
            tt = 抽类型表(掩, 键)
            登记单元["类型表"].extend(tt)
            计数["类型表"] += len(tt)
            # 可抛错误码表：`命令信息.可抛错误码` 指向的 `[u32; N]` 表（③d2 的对照物）
            for 条目 in 抽数组表(掩, "u32"):
                if 条目.get("内文") is None:
                    continue  # 值不是数组字面量（表达式）⇒ 解不出码集，③d2 报未判
                if 条目["表名"] not in 登记单元["抛码表"]:
                    登记单元["抛码表"][条目["表名"]] = 条目
                    计数["抛码表"] += 1
            # 命令表
            构造器 = 抽构造器(掩, "命令信息")
            for 表 in 抽数组表(掩, "命令信息"):
                if 表["表名"] in ("命令信息",):
                    continue
                if 表.get("是函数"):
                    表名 = 表["表名"]
                    内 = 表["内文"]
                    内起 = 表["内文起"]
                    for 构造匹配 in re.finditer(r"本表\s*\[([^\]]+)\]\s*=\s*([^\s(]+)\s*\(", 内):
                        实参起 = 构造匹配.end() - 1
                        实参止 = 配对(内, 实参起)
                        实参 = 拆顶层项(内[实参起 + 1 : 实参止])
                        字段 = _按构造器解字段(构造器.get(构造匹配.group(2)), 实参, 符号表, 本表)
                        编号, 编号原文 = _取编号(字段, lambda: (解符号(构造匹配.group(1), 符号表, 本表), 构造匹配.group(1).strip()))
                        登记单元["命令"].append(
                            {
                                "编号": 编号,
                                "编号原文": 编号原文,
                                "构造": 构造匹配.group(2),
                                "字段": 字段,
                                "位置": f"{键}:{行号(掩, 内起 + 构造匹配.start())}",
                            }
                        )
                else:
                    内 = 表["内文"] or ""
                    内起 = 表["内文起"]
                    for 序, 条目 in enumerate(拆顶层项(内)):
                        if "{" not in 条目:
                            continue
                        字段 = {}
                        内字段 = 条目.split("{", 1)[1]
                        if 内字段.rstrip().endswith("}"):
                            内字段 = 内字段.rstrip()[:-1]
                        for 字段项 in 拆顶层项(内字段):
                            if ":" in 字段项:
                                名, 值 = 字段项.split(":", 1)
                                名, 值 = 名.strip(), 值.strip()
                            else:
                                名 = 值 = 字段项.strip()
                            字段[名] = {"原文": 值, "值": 解符号(值, 符号表, 本表)}
                        编号, 编号原文 = _取编号(字段, lambda: (序, f"下标 {序}"))
                        登记单元["命令"].append(
                            {
                                "编号": 编号,
                                "编号原文": 编号原文,
                                "构造": "字面量",
                                "字段": 字段,
                                "位置": f"{键}:{行号(掩, 内起 + 内.find(条目[:12]))}",
                            }
                        )
            # 错误码表
            错误码表项 = 抽错误码表(掩, 键, 符号表, 本表)
            if 错误码表项["表"] or (错误码表项["来源"] and 登记单元["错误码表"]["来源"] is None):
                登记单元["错误码表"] = 错误码表项
                计数["错误码"] += len(错误码表项["表"])
            # 类型标签引用（符号）
            for 匹配 in re.finditer(r"类型标签_\d+", 掩):
                登记单元["类型标签引用"].append(
                    {"符号": 匹配.group(0), "位置": f"{键}:{行号(掩, 匹配.start())}"}
                )
            # 字面量 类型标签: N（参数信息 / 数据类型信息 / 命令信息 内）
            for 匹配 in re.finditer(r"类型标签\s*:\s*(\d+)", 掩):
                登记单元["类型标签引用"].append(
                    {"符号": 匹配.group(1), "位置": f"{键}:{行号(掩, 匹配.start())}"}
                )
            # 导出
            ex = 抽导出(掩, 原, 键)
            登记单元["导出"].extend(ex)
            计数["导出"] += len(ex)
            # 常量
            cs = 抽常量(掩, 键)
            登记单元["常量"].extend(cs)
            计数["常量"] += len(cs)
    # 占位项计数：命令表里带 `占位` 的常量/字段
    计数["占位项"] = sum(
        1
        for 登记单元 in 单元
        for 常量条 in 登记单元["常量"]
        if "占位" in (常量条["名"] or "")
    )
    # 命令条数：抽到的**命令项**总数（不是表数）——③g 的旧读法按表数计，缩表后那个数会骗人。
    计数["命令"] = sum(len(登记单元["命令"]) for 登记单元 in 单元)
    计数["其它cfg"] = len(夹具["其它cfg"])
    计数["夹具文件"] = len(夹具["整份夹具"])
    计数["件表总数"] = len(件表)
    return {"单元": 单元, "计数": 计数, "件表": 件表, "夹具": 夹具}


def _按构造器解字段(构造, 实参, 符号表, 本表) -> dict:
    """把一次构造器调用的实参映射成 命令信息/错误码信息 的字段。

    **表达式字段里的形参要代进去**（2026-09-27 补，实测撞到）：`命令项` 这类构造器的
    字段分成两半 —— 一半直接是形参（`状态位: 状态位`），另一半是**用形参拼的表达式**
    （`编号: v1_contract::能力号::新(编号)` · `返回类型: v1_contract::类型标签::新(类型标签_0005)` ·
    `可抛错误码: 表段::新(可抛错误码.项表 as …, 可抛错误码.项数)`）。原先只认「字段名 = 形参名」
    这一种，表达式里嵌的形参**一个都不代** ⇒ 扩展侧那 7 条命令的 `编号` / `返回类型` /
    `可抛错误码` 全解不出来（`值` = None）⇒ ③c/③d1/③d2 对**扩展侧**已判 0 项报未判，
    而底座侧照判 ⇒ 缺口只在扩展侧静默。这不是「解不出所以未判」，是**解析腿漏抽**
    （`判据的可信性.md` §三.5：判据的解析器坏了也是假绿来源）。

    三条代法，都 **fail-closed**（代不出仍是 None，不许猜）：

    - **整体透传**：表达式里这个形参的每一次出现都是 `形参.<字段>` 投影（表段那类按值传的
      结构体）⇒ 本字段原文就是那个实参本身（供下游按自己的语法再解）。
    - **逐名代入**：其余情形把实参原文代进同名形参，再解一次
      （`新(编号)` → `新(能力号::词法分析)`，内层由 `解构造器` 的符号内层读法接着解）。
    - **原样**：没有形参出现（字面量 / 生成物常量）⇒ 与原先同。
    """
    出 = {}
    if not 构造:
        return 出
    形参 = 构造.get("形参") or []
    for 字段, (来, 文本) in 构造["字段"].items():
        if 来 == "形参":
            序 = _序(形参, 文本)
            if 0 <= 序 < len(实参):
                出[字段] = {"原文": 实参[序], "值": 解符号(实参[序], 符号表, 本表)}
            continue
        透传序 = _整段透传序(文本, 形参)
        if 透传序 is not None and 透传序 < len(实参):
            出[字段] = {"原文": 实参[透传序], "值": 解符号(实参[透传序], 符号表, 本表)}
            continue
        换 = _代形参(文本, 形参, 实参)
        出[字段] = {"原文": 换, "值": 解符号(换, 符号表, 本表)}
    return 出


def _序(表: list, 名: str) -> int:
    try:
        return 表.index(名)
    except ValueError:
        return -1


def _整段透传序(文本: str, 形参: list):
    """这段表达式是不是「把某个形参整个透传下去」（该形参的每次出现都长成 `形参.<字段>`）。

    是则返回那个形参的序号，否则 None。**只在出现次数 ≥ 1 且全部是投影时成立** ——
    于是 `表段::新(可抛错误码.项表 …)` 认得出是透传 `可抛错误码`（该项的码集在指针后面，
    本模块静态取不到 ⇒ 原文留给下游 `_解可抛错误码` 按实参自己的语法解），
    而 `v1_contract::能力号::新(编号)`（裸形参，不是投影）不认，走逐名代入。
    """
    if not 文本:
        return None
    命中 = set()
    for 序, 名 in enumerate(形参):
        if re.search(r"(?<![\w:])" + re.escape(名) + r"(?:\.\w+)+", 文本):
            命中.add(序)
            # 这个形参的**全部**出现都必须是投影：有一处裸出现即不算透传。
            if re.search(r"(?<![\w:])" + re.escape(名) + r"(?![\w:]|\.\w+)", 文本):
                return None
    if len(命中) == 1:
        return next(iter(命中))
    return None


def _代形参(文本: str, 形参: list, 实参: list) -> str:
    """把表达式里的形参名逐一换成对应实参原文（长的先换，免得短名把长名切碎）。"""
    if not 文本:
        return 文本
    换 = 文本
    for 名 in sorted(形参, key=len, reverse=True):
        序 = _序(形参, 名)
        if 序 < 0 or 序 >= len(实参):
            continue
        换 = re.sub(r"(?<![\w:])" + re.escape(名) + r"(?![\w:])", lambda _, 值=实参[序]: 值, 换)
    return 换


def 任内(键: str, 范围: list) -> bool:
    return any(键 == 项 or 键.startswith(项.rstrip("/") + "/") for 项 in 范围)
