# -*- coding: utf-8 -*-
"""掩码 —— 把注释与字符串/字符字面量换成等长空格（保偏移、保行号）。"""
from __future__ import annotations

import re

def _前面不是标识符(文本: str, 位: int) -> bool:
    if 位 == 0:
        return True
    字 = 文本[位 - 1]
    return not (字.isalnum() or 字 == "_" or 字 == "：")


def 掩码(文本: str) -> str:
    """返回等长掩码串：注释 · 字符串 · 字符字面量都变空格（换行保留）。

    为什么必须掩：范围里的注释大量写着 `本表[能力号::…]` · `命令项(…)` ·
    `命令状态::错误` 这些**示例文本**；不掩就会把它们当成真实现抽出来（假绿）。
    """
    结果 = list(文本)
    全长 = len(文本)
    游标 = 0

    def 抹区间(起, 止):
        for 位次 in range(起, min(止, 全长)):
            if 结果[位次] != "\n":
                结果[位次] = " "

    while 游标 < 全长:
        字 = 文本[游标]
        if 字 == "/" and 游标 + 1 < 全长 and 文本[游标 + 1] == "/":
            行末 = 文本.find("\n", 游标)
            抹区间(游标, 全长 if 行末 < 0 else 行末)
            游标 = 全长 if 行末 < 0 else 行末
            continue
        if 字 == "/" and 游标 + 1 < 全长 and 文本[游标 + 1] == "*":
            深 = 1
            扫描位 = 游标 + 2
            while 扫描位 < 全长 and 深:
                if 文本[扫描位] == "/" and 扫描位 + 1 < 全长 and 文本[扫描位 + 1] == "*":
                    深 += 1
                    扫描位 += 2
                elif 文本[扫描位] == "*" and 扫描位 + 1 < 全长 and 文本[扫描位 + 1] == "/":
                    深 -= 1
                    扫描位 += 2
                else:
                    扫描位 += 1
            抹区间(游标, 扫描位)
            游标 = 扫描位
            continue
        匹配 = re.match(r'(?:b|c)?r(#*)"', 文本[游标:])
        if 匹配 and _前面不是标识符(文本, 游标):
            井 = 匹配.group(1)
            起 = 游标 + 匹配.end()
            终 = 文本.find('"' + 井, 起)
            终 = 全长 if 终 < 0 else 终 + len(井) + 1
            抹区间(游标, 终)
            游标 = 终
            continue
        匹配 = re.match(r'(?:b|c)?"', 文本[游标:])
        if 匹配 and _前面不是标识符(文本, 游标):
            扫描位 = 游标 + 匹配.end()
            while 扫描位 < 全长:
                if 文本[扫描位] == "\\":
                    扫描位 += 2
                    continue
                if 文本[扫描位] == '"':
                    扫描位 += 1
                    break
                if 文本[扫描位] == "\n":
                    break
                扫描位 += 1
            抹区间(游标, 扫描位)
            游标 = 扫描位
            continue
        if 字 == "'":
            匹配 = re.match(r"'(?:\\.|[^\\'])'", 文本[游标:])
            if 匹配:
                抹区间(游标, 游标 + 匹配.end())
                游标 += 匹配.end()
                continue
        游标 += 1
    return "".join(结果)
