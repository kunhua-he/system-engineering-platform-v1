# -*- coding: utf-8 -*-
"""判据声明实现 —— ③a ③b ③c ③d1 ③d2 ③f：按声明根驱动的 实现 ↔ 声明 比对。"""
from __future__ import annotations

from ..结果编排.常量 import 判据名表, 底座声明根
from ..结果编排.扫实现小工具 import 是整数
from ..源码解析.符号解析 import 解符号
from .不覆盖 import 查不覆盖
from .判据工具 import (
    记判据,
    _本表,
    _取编号,
    _解可抛错误码,
    _按编号找命令,
    _参数表名,
)


def 比一声明根(
    判定汇总: dict,
    根目录: str,
    单元集: list,
    声明根表: dict,
    符号表: dict,
    全局表: dict = None,
) -> None:
    """③a–③d2 与 ③f：对一份声明根下的每个实现单元逐条比对（明细与已判都写进 `出`）。

    `全局表` = **跨单元**的表索引（`抽实现面.py` 在 `契约源目录` 下扫出来的生成物表：
    参数表 · 可抛错误码）。为什么需要它（2026-10-15 补，实测撞到）：生成器把命令的每个
    字段出成常量后，实现侧（`运行内核/装载入口`）指的 `能力参数表_<词干>` /
    `能力可抛错误码_<词干>` 住在**另一个单元**的生成物里（`契约声明/src/`）⇒ 只查本单元
    当场报未判。**先查本单元、再查全局**（同 Rust 的作用域直觉）。
    """
    全局表 = 全局表 or {}
    声明能力 = {}
    for 键名, (声明值, _) in 声明根表[根目录]["能力声明"].items():
        编号 = 声明值.get("编号")
        声明能力[编号] = (声明值, 键名)
    是底座 = 根目录 == 底座声明根
    for 登记单元 in 单元集:
        实现能力 = {}
        for 能力条 in 登记单元["能力号"]:
            if 能力条["值"] is not None:
                实现能力.setdefault(能力条["值"], 能力条["位置"])
        for 能力条 in 登记单元["命令"]:
            if 能力条["编号"] is not None:
                实现能力.setdefault(能力条["编号"], 能力条["位置"])

        # ── ③a 声明有实现无 ──
        if not 声明能力:
            判定汇总[判据名表[0]]["明细"].append(
                记判据(判据名表[0], "未判", f"{根目录}/能力声明/",
                   f"扫描 0 项：{根目录}/能力声明/ 里一份声明都没有 ⇒ 这一半是空集（空集不算通过）。"
                   f"同一声明根下的实现侧有 {len(实现能力)} 个编号"
                   f"（{sorted(编号项 for 编号项 in 实现能力 if 编号项 is not None)}）",
                   "空集有两种可能：这份声明还没写能力，或目录被删了；两者在磁盘上不可区分，"
                   "而「补哪些能力声明」是声明方的活 ⇒ 只能由声明方补")
            )
        else:
            for 编号 in sorted(声明能力, key=lambda 编号项: (编号项 is None, 编号项)):
                声明值, 键名 = 声明能力[编号]
                if 编号 is None:
                    判定汇总[判据名表[0]]["明细"].append(
                        记判据(判据名表[0], "未判", f"{键名}:编号",
                           "判不了：这份能力声明没有可用的 编号（缺字段或不是整数）⇒ 无法与实现对照",
                           "编号是唯一对照键；字段缺失或形状不对只能由声明方按 §三 补")
                    )
                    continue
                判定汇总[判据名表[0]]["已判"] += 1
                if 编号 not in 实现能力:
                    判定汇总[判据名表[0]]["明细"].append(
                        记判据(判据名表[0], "失败", f"{键名}:编号",
                           f"声明了能力编号 {编号}（「{声明值.get('名称')}」），但 {登记单元['目录']} 的实现里"
                           f"既没有 能力号 常量、也没有命令表项指向 {编号}"
                           f"（实现里有：{sorted(编号项 for 编号项 in 实现能力 if 编号项 is not None)}）",
                           f"编号是显式字段（`命令信息.编号`，见 `契约声明/src/lib.rs` 旁路区）："
                           f"要在实现里补一位，就得定它的编号、补在命令表哪一项、"
                           f"以及它是不是占位项——那是实现方的活，验证面补一位等于替它编实现 ⇒ "
                           f"只能由实现方补", "源码错")
                    )

        # ── ③b 实现有声明无 ──
        if not 声明能力:
            附注 = (
                f"**注**：底座 0xxx 已进 `契约声明/能力声明/`（`0000.json`，编号 0）⇒ "
                f"这条口径已裁；本处读数说明它又被删回空目录了"
                if 是底座
                else f"**注**：{根目录}/能力声明/ 是空目录，而实现侧有编号——这份声明还没写能力"
            )
            判定汇总[判据名表[1]]["明细"].append(
                记判据(判据名表[1], "未判", f"{根目录}/能力声明/",
                   f"判不了：{根目录}/能力声明/ 为空集，而实现侧有 {len(实现能力)} 个编号"
                   f"（{sorted(编号项 for 编号项 in 实现能力 if 编号项 is not None)}）⇒ 「实现有声明无」这一半"
                   f"对不了。{附注}",
                   "口径未定：补声明（=把该段命令对外公布）与不补声明（=该段不对外）"
                   "是两种都自洽的做法；选哪种是契约侧裁决 ⇒ 只能由契约侧裁")
            )
        else:
            for 编号 in sorted(编号项 for 编号项 in 实现能力 if 编号项 is not None):
                判定汇总[判据名表[1]]["已判"] += 1
                if 编号 not in 声明能力:
                    判定汇总[判据名表[1]]["明细"].append(
                        记判据(判据名表[1], "失败", 实现能力[编号],
                           f"实现里有能力编号 {编号}，但 {根目录}/能力声明/ 里没有它的声明",
                           f"编号已进实现（可能已被调用方按号调用）；补声明要写全参数表 · 返回类型 · "
                           f"可抛错误码，那是声明方的活；撤实现会废掉一个已落地的号 ⇒ "
                           f"只能由声明方补（或人来裁撤哪一边）", "源码错")
                    )

        # ── ③c 参数行序与个数 ──
        if not 声明能力:
            判定汇总[判据名表[2]]["明细"].append(
                记判据(判据名表[2], "未判", f"{根目录}/能力声明/",
                   f"扫描 0 项：{根目录}/能力声明/ 为空 ⇒ 没有可比对的 参数表",
                   "参数行序即契约（§三）；声明侧空集时这一半无从比对 ⇒ 只能由声明方补")
            )
        for 编号 in sorted(编号项 for 编号项 in 声明能力 if 编号项 is not None):
            声明值, 键名 = 声明能力[编号]
            入参表 = 声明值.get("参数表")
            落点 = f"{键名}:参数表"
            if not isinstance(入参表, list):
                判定汇总[判据名表[2]]["明细"].append(
                    记判据(判据名表[2], "未判", 落点,
                       f"判不了：声明的 参数表 不是列表（{type(入参表).__name__}）⇒ 行数取不出",
                       "§三 定死 参数表 是列表（空表也写 []）；形状不对只能由声明方补")
                )
                continue
            实现条 = _按编号找命令(登记单元, 编号)
            if 实现条 is None:
                continue  # ③a 已报
            参数个数 = 实现条["字段"].get("参数个数", {}).get("值")
            if 参数个数 is None:
                判定汇总[判据名表[2]]["明细"].append(
                    记判据(判据名表[2], "未判", 实现条["位置"],
                       f"判不了：命令 {编号} 的 参数个数 原文是 "
                       f"「{实现条['字段'].get('参数个数', {}).get('原文')}」，静态解析取不出它的值",
                       "参数个数 是构造器实参；解不出它就没法比行数。改法只有两种：写成整数字面量，"
                       "或由契约侧给出可静态求值的写法 ⇒ 只能由实现方补")
                )
                continue
            判定汇总[判据名表[2]]["已判"] += 1
            if 参数个数 != len(入参表):
                判定汇总[判据名表[2]]["明细"].append(
                    记判据(判据名表[2], "失败", 实现条["位置"],
                       f"能力 {编号} 的 声明参数表 有 {len(入参表)} 行，实现的 参数个数 是 {参数个数}",
                       f"参数表行序即契约（§三 冻结项）：行数不符意味着两侧对这条命令的入参"
                       f"个数不一致。改声明会改已公布的调用形状，改实现会让调用方少/多传一个槽 ⇒ "
                       f"只能人来裁以哪边为准（若走旁路登记则先改冻结登记）", "源码错")
                )
                continue
            # 逐位比类型标签（行序）。
            # 取不到对照物的四条路径**一律报未判**（不许静默 continue —— 那会让「行序」静默
            # 失效而整条判据仍报通过，fail-open）。
            参表名 = _参数表名(实现条)
            pt = 登记单元["参数表"].get(参表名) if 参表名 is not None else None
            if pt is None and 参表名 is not None:
                pt = (全局表.get("参数表") or {}).get(参表名)
            if 入参表 and 参表名 is None:
                判定汇总[判据名表[2]]["明细"].append(
                    记判据(判据名表[2], "未判", 实现条["位置"],
                       f"判不了：命令 {编号} 的 参数表 字段原文是"
                       f"「{实现条['字段'].get('参数表', {}).get('原文')}」，静态解析取不出参数表名"
                       f" ⇒ 逐位行序对不了",
                       "参数表名解不出（`_参数表名` 只认 `<名>.as_ptr()` 与裸表名两种写法，"
                       "`core::ptr::null()` 一类表达式一律 None）就没法逐位比"
                       " ⇒ 只能由实现方改成可静态求值的写法")
                )
                continue
            if 入参表 and pt is None:
                判定汇总[判据名表[2]]["明细"].append(
                    记判据(判据名表[2], "未判", 实现条["位置"],
                       f"判不了：命令 {编号} 指向的参数表「{参表名}」在本单元与跨单元索引里都没有抽到"
                       f" ⇒ 逐位行序对不了",
                       "参数表没抽到，说明该表写成了别的形状（不是 `[参数信息; N] = [ … ]`）、"
                       "或解析腿漏抽；两者在读数上不可区分 ⇒ 只能由实现方确认")
                )
                continue
            for 位次, 源码行 in enumerate(入参表):
                if not isinstance(源码行, dict):
                    判定汇总[判据名表[2]]["明细"].append(
                        记判据(判据名表[2], "未判", f"{落点}[{位次}]",
                           f"判不了：声明参数表第 {位次} 位不是对象（{type(源码行).__name__}）"
                           f" ⇒ 取不出 类型标签",
                           "§三 定死 参数表 的每一项是对象（含 类型标签）；形状不对只能由声明方补")
                    )
                    continue
                声明标签 = 源码行.get("类型标签")
                if not 是整数(声明标签):
                    判定汇总[判据名表[2]]["明细"].append(
                        记判据(判据名表[2], "未判", f"{落点}[{位次}]",
                           f"判不了：声明参数表第 {位次} 位没有可用的 类型标签（{声明标签!r}）"
                           f" ⇒ 无法与实现逐位对照",
                           "§三 定死每一位都要写 类型标签（整数）；缺字段或形状不对只能由声明方补")
                    )
                    continue
                if 位次 >= len(pt["类型标签原文"]):
                    判定汇总[判据名表[2]]["明细"].append(
                        记判据(判据名表[2], "未判", pt["位置"],
                           f"判不了：能力 {编号} 第 {位次} 位的声明标签在实现参数表「{参表名}」里"
                           f"没有对照位（实现参数表只有 {len(pt['类型标签原文'])} 位）⇒ 位次越界",
                           "声明与实现的参数表行数应一致（前一半已比个数）；越界说明两侧行序/行数不一致"
                           " ⇒ 只能由实现方/声明方确认以哪边为准")
                    )
                    continue
                原文 = pt["类型标签原文"][位次]
                实现标签 = 解符号(原文, 符号表, _本表(登记单元))
                if 实现标签 is None:
                    判定汇总[判据名表[2]]["明细"].append(
                        记判据(判据名表[2], "未判", pt["位置"],
                           f"判不了：能力 {编号} 第 {位次} 位的实现类型标签原文是「{原文}」，"
                           f"静态解析取不出它的值",
                           "类型标签是跨边界放值的唯一锚点（§四）；解不出它就没法逐位比对 ⇒ "
                           "只能由实现方改成可静态求值的写法")
                    )
                    continue
                if 实现标签 != 声明标签:
                    判定汇总[判据名表[2]]["明细"].append(
                        记判据(判据名表[2], "失败", pt["位置"],
                           f"能力 {编号} 第 {位次} 位（0 起）：声明 类型标签 {声明标签}，实现 类型标签 {实现标签}"
                           f"（原文「{原文}」）",
                           f"参数行序即契约：同一位的标签不同，意味着两侧对「第 {位次} 位放什么」"
                           f"的约定不一致，跨边界取值会按错标签解释。改声明会改已公布的参数语义，"
                           f"改实现会让已在跑的调用方取错值 ⇒ 只能人来裁", "源码错")
                    )

        # ── ③d1 返回类型 ──
        if not 声明能力:
            判定汇总[判据名表[3]]["明细"].append(
                记判据(判据名表[3], "未判", f"{根目录}/能力声明/",
                   f"扫描 0 项：{根目录}/能力声明/ 为空 ⇒ 没有可比对的 返回类型",
                   "§三：返回类型 决定调用方怎么解返回槽；声明侧空集时这一半无从比对 ⇒ "
                   "只能由声明方补")
            )
        for 编号 in sorted(编号项 for 编号项 in 声明能力 if 编号项 is not None):
            声明值, 键名 = 声明能力[编号]
            声明返回类型 = 声明值.get("返回类型")
            实现条 = _按编号找命令(登记单元, 编号)
            if 实现条 is None:
                continue
            if not 是整数(声明返回类型):
                判定汇总[判据名表[3]]["明细"].append(
                    记判据(判据名表[3], "未判", f"{键名}:返回类型",
                       f"判不了：声明的 返回类型 不是整数（{声明返回类型!r}）",
                       "§三：返回类型 0 表示无返回值；字段缺失或形状不对只能由声明方补")
                )
                continue
            原文 = 实现条["字段"].get("返回类型", {}).get("原文")
            实现返回类型 = 实现条["字段"].get("返回类型", {}).get("值")
            if 实现返回类型 is None:
                判定汇总[判据名表[3]]["明细"].append(
                    记判据(判据名表[3], "未判", 实现条["位置"],
                       f"判不了：命令 {编号} 的 返回类型 原文是「{原文}」，静态解析取不出它的值",
                       "返回类型是返回槽的解释依据；解不出它就没法比 ⇒ 只能由实现方改成可静态求值的写法")
                )
                continue
            判定汇总[判据名表[3]]["已判"] += 1
            if 实现返回类型 != 声明返回类型:
                判定汇总[判据名表[3]]["明细"].append(
                    记判据(判据名表[3], "失败", 实现条["位置"],
                       f"能力 {编号}：声明 返回类型 {声明返回类型}，实现 返回类型 {实现返回类型}（原文「{原文}」）",
                       f"返回类型决定调用方怎么解返回槽（§三）；两侧不一致会让返回槽被按错的"
                       f"类型解释。改声明会改已公布的返回语义，改实现会让已在跑的调用方取错 ⇒ "
                       f"只能人来裁", "源码错")
                )

        # ── ③d2 可抛错误码 ──
        # 读法：`命令信息.可抛错误码` 是旁路区字段 `表段<u32>`（`契约声明/src/lib.rs`）⇒
        # 声明 `可抛错误码` ↔ 该命令字段指向的码集，逐项比。空表（`表段::空实例()`）与
        # 声明 `[]` 都是合法值（= 本命令不抛错），**不许**当成「漏写」或「空集未判」。
        if not 声明能力:
            判定汇总[判据名表[4]]["明细"].append(
                记判据(判据名表[4], "未判", f"{根目录}/能力声明/",
                   f"扫描 0 项：{根目录}/能力声明/ 为空 ⇒ 没有可比对的 可抛错误码",
                   "可抛错误码 是调用方按码做处置（重试 / 自愈 / 报人工）的依据（§五）；"
                   "声明侧空集时这一半无从比对 ⇒ 只能由声明方补")
            )
        for 编号 in sorted(编号项 for 编号项 in 声明能力 if 编号项 is not None):
            声明值, 键名 = 声明能力[编号]
            声明码集 = 声明值.get("可抛错误码")
            实现条 = _按编号找命令(登记单元, 编号)
            if 实现条 is None:
                continue  # ③a 已报
            if not isinstance(声明码集, list):
                判定汇总[判据名表[4]]["明细"].append(
                    记判据(判据名表[4], "未判", f"{键名}:可抛错误码",
                       f"判不了：声明的 可抛错误码 不是列表（{type(声明码集).__name__}）⇒ 码集取不出",
                       "§三 定死 可抛错误码 是列表（空表也写 []）；形状不对只能由声明方补")
                )
                continue
            字段 = 实现条["字段"].get("可抛错误码")
            if 字段 is None:
                判定汇总[判据名表[4]]["明细"].append(
                    记判据(判据名表[4], "未判", 实现条["位置"],
                       f"判不了：命令 {编号} 的构造器没有 可抛错误码 字段（`命令信息` 旧形状）⇒ "
                       f"声明里的 {sorted(声明码集)} 在实现面上没有对照物",
                       "`命令信息.可抛错误码` 是旁路区字段（`契约声明/src/lib.rs` 命令信息 · 旁路区）；"
                       "实现侧还没跟上新形状 ⇒ 只能由实现方按新形状补")
                )
                continue
            实现码集 = _解可抛错误码(
                登记单元, 字段.get("原文"), 符号表, _本表(登记单元), 全局表.get("抛码表")
            )
            if 实现码集 is None:
                判定汇总[判据名表[4]]["明细"].append(
                    记判据(判据名表[4], "未判", 实现条["位置"],
                       f"判不了：命令 {编号} 的 可抛错误码 原文是「{字段.get('原文')}」，"
                       f"静态解析取不出它指向的码集",
                       "本模块只认两种写法：`表段::空实例()` 与 "
                       "`表段::构造(<表>.as_ptr(), …)`（表名先查本单元、再查跨单元索引；"
                       "且表项要能逐个解成整数）；"
                       "其余写法要判得先能静态看到码集 ⇒ 只能由实现方改成可静态求值的写法")
                )
                continue
            判定汇总[判据名表[4]]["已判"] += 1
            if sorted(实现码集) != sorted(声明码集):
                判定汇总[判据名表[4]]["明细"].append(
                    记判据(判据名表[4], "失败", 实现条["位置"],
                       f"能力 {编号}：声明 可抛错误码 {sorted(声明码集)}（{len(声明码集)} 条），"
                       f"实现 可抛错误码 {sorted(实现码集)}（{len(实现码集)} 条）（原文「{字段.get('原文')}」）",
                       "可抛错误码 是调用方按码做处置（重试 / 自愈 / 报人工）的依据（§五）："
                       "实现多抛一个未声明的码，调用方没有处置分支；少一个则调用方白写分支。"
                       "改声明会改已公布的失败面，改实现会改已落地的行为 ⇒ 只能人来裁", "源码错")
                )

        # ── ③f 错误码表 ──
        表项 = 登记单元["错误码表"]
        if 表项["来源"] == "生成物":
            # 「按设计不覆盖」= 声明的范围（登记在唯一一张表里），不是「本该判却判不了」。
            # 判据里只留一句「见不覆盖登记表」——理由与覆盖者都是那一条事实，只落在表里。
            if 查不覆盖(判据名表[6], 登记单元["目录"]) is not None:
                判定汇总[判据名表[6]]["明细"].append(
                    记判据(判据名表[6], "不覆盖", 表项["位置"] or f"{登记单元['目录']}/",
                       "按设计不覆盖：这一格不在本判据声明的范围内，"
                       "见 `扫实现/不覆盖.py::不覆盖登记表`",
                       "不覆盖是**声明的范围**（不是本该判却判不了）；为什么 · 由谁覆盖 "
                       "都登记在 `扫实现/不覆盖.py::不覆盖登记表`")
                )
            else:
                判定汇总[判据名表[6]]["明细"].append(
                    记判据(判据名表[6], "未判", 表项["位置"] or f"{登记单元['目录']}/",
                       f"判不了：本单元的错误码表来自生成物（原文「{表项.get('原文')}」）⇒ "
                       f"实现面上没有可数的项。这半边等价于声明侧第 10 项"
                       f"（生成物 ↔ JSON 指纹比对），本判据**不重复声称覆盖**它",
                       "生成物是声明侧的唯一来源（§八）；要判它的内容，得由声明侧的生成物指纹闸"
                       "来判（`构建装配/形态装配/生成声明.py --检查`）⇒ 只能由声明侧那一项覆盖。"
                       "**若这一格确实按设计不覆盖，应登记进 `扫实现/不覆盖.py::不覆盖登记表`**"
                       "（登记表是唯一落点；不登记就只能是未判）")
                )
        elif not 表项["表"]:
            判定汇总[判据名表[6]]["明细"].append(
                记判据(判据名表[6], "未判", f"{登记单元['目录']}/",
                   "扫描 0 项：本单元生产区里没有 错误码信息 字面量表 ⇒ 空集不算通过",
                   "本单元可能真的没有错误码（合法），也可能是表写成了别的形状（解析腿漏抽）；"
                   "两者读数上不可区分 ⇒ 只能由实现方确认")
            )
        else:
            声明码 = {}
            for 键名, (声明值, _) in (声明根表.get(根目录, {}).get("错误码表", {}) or {}).items():
                能力条 = 声明值.get("码")
                声明码[能力条] = (声明值, 键名)
            实现码 = {}
            for 条目项 in 表项["表"]:
                实现码.setdefault(条目项["码"], 条目项)
            判定汇总[判据名表[6]]["已判"] += max(len(声明码), len(实现码))
            for 能力条 in sorted(编号项 for 编号项 in 声明码 if 编号项 is not None):
                if 能力条 not in 实现码:
                    声明值, 键名 = 声明码[能力条]
                    判定汇总[判据名表[6]]["明细"].append(
                        记判据(判据名表[6], "失败", f"{键名}:码",
                           f"声明了错误码 {能力条}（「{声明值.get('名称')}」），但 {登记单元['目录']} 的"
                           f" 错误码信息 表里没有它（实现里有：{sorted(编号项 for 编号项 in 实现码 if 编号项 is not None)}）",
                           f"§五：未登记不许抛出，反过来登记了就该有实现面的落点。补一条要定"
                           f"「可重试 · 可自愈 · 需人工」三项业务语义 ⇒ 只能由实现方补", "源码错")
                    )
            for 能力条 in sorted(编号项 for 编号项 in 实现码 if 编号项 is not None):
                if 能力条 not in 声明码:
                    判定汇总[判据名表[6]]["明细"].append(
                        记判据(判据名表[6], "失败", 实现码[能力条]["位置"],
                           f"实现里登记了错误码 {能力条}，但 {根目录}/错误码表/ 里没有它",
                           "§五：未登记的错误码不许抛出。补登记要写全四项（三项业务判断 + 段位），"
                           "那是声明方的活 ⇒ 只能由声明方补", "源码错")
                    )
            for 条目项 in 表项["表"]:
                能力条, 段位 = 条目项["码"], 条目项["段位"]
                if 能力条 is None or 段位 is None:
                    判定汇总[判据名表[6]]["明细"].append(
                        记判据(判据名表[6], "未判", 条目项["位置"],
                           f"判不了：错误码项原文「{条目项['原文']}」的 码/段位 静态解析取不出"
                           f"（码={能力条} · 段位={段位}）",
                           "码与段位都必须可静态求值才能交叉比对（§五：段位 == 码//1000）⇒ "
                           "只能由实现方改成可静态求值的写法")
                    )
                    continue
                if 段位 != 能力条 // 1000:
                    判定汇总[判据名表[6]]["明细"].append(
                        记判据(判据名表[6], "失败", 条目项["位置"],
                           f"码 {能力条} 的首位十进制数字是 {能力条 // 1000}，实现里写的 段位 是 {段位}",
                           "§五：段位 是**冗余登记项**，故意写出来让验证面交叉比对抓错。"
                           "改码要动全局唯一号，改段位要改归属 ⇒ 只能人来裁", "源码错")
                    )
