from ..源码解析.符号解析 import 建符号表, 解符号
from ..比对规则.判据类型标签 import 比类型标签
from ..结果编排.常量 import 判据名表
from .样本 import 造样本
from 构建装配.形态装配.生成声明.生成编排.路径形状 import 声明根
from 构建装配.形态装配.生成声明.声明渲染.渲染常量推导 import 渲染常量表, 渲染号段推导


def 自检_扩展生成同源():
    输出缓冲 = []
    样本件 = 造样本()
    根目录 = "扩展根目录/原子支持库/外部生成样本"
    样本件[根目录 + "/包声明.json"] = "{}"
    数据块 = "// 生成物，禁手改。\n// 生成器：构建装配/形态装配/生成声明.py\n"
    样本件[根目录 + "/src/附加数据.rs"] = 数据块 + (
        "pub const 类型标签_0100: v1_contract::类型标签 = v1_contract::类型标签::构造(100);\n"
    )
    符号表 = 建符号表(样本件)
    输出缓冲.append(("已声明扩展的额外生成件进入符号表", 解符号("类型标签_0100", 符号表, {}) == 100, "按真实生成定义解析为100"))
    扫描单元 = {"类型表": [{"类型标签原文": "类型标签_0100", "位置": 根目录 + "/src/附加数据.rs::类型标签_0100"}],
              "类型标签引用": [], "目录": 根目录, "能力号": {}, "常量": {}}
    判定汇总 = {判据名表[5]: {"明细": [], "已判": 0}}
    比类型标签(判定汇总, [扫描单元], 符号表, {100: ({}, "登记类型")})
    输出缓冲.append(("额外生成件类型已登记时③e通过", 判定汇总[判据名表[5]]["已判"] == 1 and not 判定汇总[判据名表[5]]["明细"], "不是跳过生成件"))
    判定汇总 = {判据名表[5]: {"明细": [], "已判": 0}}
    比类型标签(判定汇总, [扫描单元], 符号表, {})
    输出缓冲.append(("额外生成件引用未登记类型时③e报失败", any(明细条["判定"] == "失败" for 明细条 in 判定汇总[判据名表[5]]["明细"]), "不是未判或漏扫"))
    样本件[根目录 + "/src/附加数据.rs"] = 数据块 + "pub const 类型标签_0100: u32 = 9999;\n"
    符号表 = 建符号表(样本件)
    判定汇总 = {判据名表[5]: {"明细": [], "已判": 0}}
    比类型标签(判定汇总, [扫描单元], 符号表, {100: ({}, "登记类型")})
    输出缓冲.append(("额外生成件数值漂移按实际值报失败", 解符号("类型标签_0100", 符号表, {}) == 9999 and any(明细条["判定"] == "失败" for 明细条 in 判定汇总[判据名表[5]]["明细"]), "不根据名称后缀猜100"))
    样本件[根目录 + "/src/附加数据.rs"] = 数据块 + "pub const 类型标签_0100: u32 = 未知标签;\n"
    输出缓冲.append(("生成值不可解析仍fail-closed", 解符号("类型标签_0100", 建符号表(样本件), {}) is None, "不猜数值"))
    样本件[根目录 + "/src/附加数据.rs"] = "pub const 类型标签_0100: u32 = 100;\n"
    输出缓冲.append(("扩展手写件不冒充生成符号源", 解符号("类型标签_0100", 建符号表(样本件), {}) is None, "缺生成头标不能入表"))
    样本件.pop(根目录 + "/包声明.json")
    样本件[根目录 + "/src/附加数据.rs"] = 数据块 + "pub const 类型标签_0100: u32 = 100;\n"
    输出缓冲.append(("未声明根不能只凭生成头标入表", 解符号("类型标签_0100", 建符号表(样本件), {}) is None, "必须来自已发现声明根"))
    根目录 = 声明根("扩展根目录/原子支持库/外部生成样本")
    根目录.声明文件 = 根目录.包声明
    常量表 = [{"名": "接口端口", "值": 43110, "位宽": 16, "依据": "样本"}]
    样本件 = []
    渲染常量表(样本件.append, 根目录, 常量表)
    渲染号段推导(样本件.append, 根目录, {}, (), {})
    输出缓冲.append(("扩展全局常量及号段推导只引用底座", "pub use v1_contract::声明数据::接口端口;" in 样本件 and not any("pub const" in 文本行 for 文本行 in 样本件), "无复制常量定义"))
    根目录.声明文件 = 根目录.平台声明
    样本件 = []
    渲染常量表(样本件.append, 根目录, 常量表)
    输出缓冲.append(("底座仍生成唯一常量定义", "pub const 接口端口: u16 = 43110;" in 样本件, "底座路径不改成引用"))
    return 输出缓冲
