# -*- coding: utf-8 -*-
"""判据扩展自洽 —— ③k：每个扩展的 `能力声明.可抛错误码 ⊆ 本扩展的错误码表`。

为什么单列：`能力声明.可抛错误码 ⊆ 错误码表` 这条在**扩展侧**原先没有任何
可跑的检查 —— 生成器不查（接缝冻结腿⑮ 明令不许改生成器语义）· `一键验证.py` 的扫描面只
覆盖 `契约声明/`（不含 `扩展根目录/`）⇒ 扩展侧自洽**靠人眼**。⑮ 的链只证到「生成物出那个
库的码」，**没证**「那个库引用的码都登记过」。本判据把它变成 **fail-closed**：未登记的码 = 失败。

口径：**同一个扩展的** 能力声明 ↔ **同一个扩展的** 错误码表（跨扩展不算 —— 号空间按扩展归属）。
底座不在本判据内：它的错误码表来自生成物，由声明侧指纹闸覆盖（见 `不覆盖.py::不覆盖登记表`）。
"""
from __future__ import annotations

from .常量 import 判据名表, 底座声明根
from .小工具 import 是整数
from .判据工具 import 记判据


def 比扩展自洽(结果: dict, 声明根表: dict) -> None:
    """③k：逐扩展比 `可抛错误码` 与 `错误码表`；未登记的码报**失败**，形状不对报**未判**。"""
    名称 = 判据名表[11]
    结果[名称]["扫描面"] = (
        "每个**扩展**声明根（`扩展根目录/<类>/<扩展>/`）的 `能力声明/*.json` × "
        "**同一扩展**的 `错误码表/*.json`；底座不在内（其错误码表来自生成物）"
    )
    读数 = []
    已判 = 0
    for 根目录 in sorted(声明根表):
        if 根目录 == 底座声明根:
            continue
        能力 = 声明根表[根目录].get("能力声明") or {}
        if not 能力:
            continue
        登记 = set()
        for _键, (声明值, _) in (声明根表[根目录].get("错误码表") or {}).items():
            错误码 = 声明值.get("码")
            if 是整数(错误码):
                登记.add(错误码)
        条数 = 0
        for 键名, (声明值, _) in sorted(能力.items()):
            可抛 = 声明值.get("可抛错误码")
            if not isinstance(可抛, list):
                结果[名称]["明细"].append(
                    记判据(名称, "未判", f"{键名}:可抛错误码",
                       f"判不了：能力声明的 可抛错误码 不是列表（{type(可抛).__name__}）⇒ 码集取不出",
                       "§三 定死 可抛错误码 是列表（空表也写 []）；形状不对只能由声明方补")
                )
                continue
            已判 += 1
            for 错误码 in 可抛:
                if not 是整数(错误码):
                    结果[名称]["明细"].append(
                        记判据(名称, "未判", f"{键名}:可抛错误码",
                           f"判不了：可抛错误码 里有非整数项（{错误码!r}）⇒ 无法与错误码表比",
                           "码必须是整数才能与错误码表比 ⇒ 只能由声明方补")
                    )
                    continue
                条数 += 1
                if 错误码 not in 登记:
                    结果[名称]["明细"].append(
                        记判据(名称, "失败", f"{键名}:可抛错误码",
                           f"能力声明 {键名} 的 可抛错误码 里有 {错误码}，但 {根目录}/错误码表/ 里没有"
                           f"登记它（本扩展已登记 {len(登记)} 个码）",
                           "§五：未登记的错误码不许抛出。声明一个未登记的码 = 调用方拿不到处置"
                           "依据（重试/自愈/报人工）。补法只有两条：登记那个码（写全四项 + 段位，"
                           "声明方的活），或从可抛表里撤掉它（改已公布的失败面）⇒ "
                           "只能由声明方补或人来裁", "源码错")
                    )
        读数.append(
            f"{根目录}：能力声明 {len(能力)} 份 · 错误码表 {len(声明根表[根目录].get('错误码表') or {})} 份 · "
            f"可抛码 {条数} 条"
        )
    结果[名称]["扫描读数"] = ("；".join(读数) or "（无扩展声明根）") + f"；已判能力声明 {已判} 份"
    结果[名称]["已判"] += 已判
