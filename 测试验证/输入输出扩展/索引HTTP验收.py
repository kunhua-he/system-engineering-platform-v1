"""逐层发现、分页、精确契约及坏请求的真实HTTP回归。"""
import json
import urllib.parse


def 核验族类索引(请求, 检查, 实例表):
    for 网关实例 in 实例表:
        _, 索引前生命周期 = 请求(网关实例, '/接口/生命周期')
        索引前运行数 = 索引前生命周期['数据']['跨进程运行数']
        def 取节点(路径='', **参数):
            查询 = urllib.parse.urlencode(dict(路径=路径, **参数))
            状态, 回执 = 请求(网关实例, '/接口/索引?' + 查询)
            检查(状态 == 200 and 回执.get('成功'), '分层索引真实GET：' + 路径, 回执)
            return 回执['数据']
        根节点 = 取节点()
        检查(len(根节点['子项']) == 3 and all(条目项['节点'] == '种类' and '编号' not in 条目项 for 条目项 in 根节点['子项']), '索引根只给三类不泄入能力全集', 根节点)
        包路径 = '支持库/编解码支持库'
        包节点 = 取节点(包路径)
        检查({条目项['名称'] for 条目项 in 包节点['子项']} == {'二进制文本', '字符集', 'URI组件'}, '编解码按职责给直接子族', 包节点)
        二进制节点 = 取节点(包路径 + '/二进制文本')
        检查({条目项['名称'] for 条目项 in 二进制节点['子项']} == {'Base64', '十六进制'} and all('编号' not in 条目项 for 条目项 in 二进制节点['子项']), '子族允许继续细分而非提前展开后代', 二进制节点)
        路径表 = [包路径 + '/二进制文本/Base64', 包路径 + '/二进制文本/十六进制', 包路径 + '/字符集', 包路径 + '/URI组件']
        能力号表 = []
        for 族路径 in 路径表:
            叶节点 = 取节点(族路径)
            能力号表.extend(条目项['编号'] for 条目项 in 叶节点['子项'])
            检查(all(set(条目项) == {'节点', '编号', '名称', '参数个数', '返回类型'} for 条目项 in 叶节点['子项']), '叶能力只返短卡不返参数与长说明', 叶节点)
            检查(len(json.dumps(叶节点, ensure_ascii=False).encode()) < 4096, '叶索引实际响应小于4KiB', 叶节点)
        检查(len(能力号表) == len(set(能力号表)) == 10 and set(能力号表) == {4001, 4002, 4101, 4102, 4301, 4302, 4303, 4304, 4501, 4502}, '原十能力在族树完整且唯一', 能力号表)
        检查(取节点(编号=0)['编号'] == 0, '底座已知编号按正式文件格式直达')
        模块节点 = 取节点('模块/数值统计模块')
        检查([条目项['编号'] for 条目项 in 模块节点['子项']] == [7950,7951,7960], '同场景包直接给三能力短卡不插空分类层', 模块节点)
        模块契约 = 取节点('模块/数值统计模块',编号=7950)
        检查(取节点(编号=7950) == 模块契约 and len(模块契约['参数表']) == 2 and 模块契约['返回类型'] == 1, '已知模块编号直达与场景契约一致', 模块契约)
        精确契约 = 取节点(路径表[0], 编号=4301)
        检查(取节点(编号=4301) == 精确契约, '已知编号直接定位而不反复爬树', 精确契约)
        检查(精确契约['编号'] == 4301 and '参数表' in 精确契约 and '子项' not in 精确契约, '只取所选能力完整契约', 精确契约)
        分页编号 = []
        页起点 = 0
        while 页起点 is not None:
            单页 = 取节点(路径表[0], 起始=页起点, 一次条数=1)
            检查(len(单页['子项']) == 1 and 单页['总项数'] == 4, '族内单项分页保留真实总数', 单页)
            分页编号.extend(条目项['编号'] for 条目项 in 单页['子项'])
            页起点 = 单页['下页起始']
        检查(分页编号 == [4301, 4302, 4303, 4304], '翻页不漏不重且按稳定编号排序', 分页编号)
        越尾 = 取节点(路径表[0], 起始=999)
        检查(越尾['子项'] == [] and 越尾['下页起始'] is None, '越尾显式空页', 越尾)
        for 参数 in [dict(路径='支持库/../无关目录'), dict(一次条数=0), dict(一次条数=51), dict(起始=-1), dict(不存在键='值'), dict(路径='支持库', 编号=4301)]:
            状态, 回执 = 请求(网关实例, '/接口/索引?' + urllib.parse.urlencode(参数))
            检查(状态 == 400 and not 回执.get('成功'), '索引坏请求即时拒绝', 回执)
        状态, 回执 = 请求(网关实例, '/接口/索引?一次条数=1&一次条数=2')
        检查(状态 == 400, '重复索引键不得静默覆盖', 回执)
        状态, 回执 = 请求(网关实例, '/接口/索引?' + urllib.parse.urlencode(dict(路径=路径表[0], 编号=4501)))
        检查(状态 == 200 and not 回执.get('成功') and 回执['错误']['码'] == 9007, '跨族编号不能借包路径冒领', 回执)
        _, 索引后生命周期 = 请求(网关实例, '/接口/生命周期')
        检查(索引前运行数 == 索引后生命周期['数据']['跨进程运行数'] == 0, '逐层索引与精确取约不启动模块进程', 索引后生命周期)
