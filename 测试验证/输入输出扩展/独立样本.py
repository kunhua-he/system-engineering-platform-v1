"""独立标准库对照真实文件、网络、文本编码及ZIP返回。"""
import hashlib
import io
import json
from pathlib import Path
import urllib.parse
import zipfile
from .网络靶场 import 网页原文


def 核验基础样本(调用,检查,网关实例,靶场地址,文件目录):
    文件目录=Path(文件目录);文件目录.mkdir()
    原文='中文🙂\x00订单123'
    网页正文='中文🙂 订单123 店铺'
    样本=[(2401,[靶场地址+'/html'],网页原文),(2402,[靶场地址+'/json','{"中文":123}'],'{"中文":123}'),
          (2403,[靶场地址+'/bytes'],bytes([0,1,127,255])),
          (4801,[网页原文],'门店123 & 服务'),(4802,[网页原文],网页正文),
          (4803,[网页原文,'p'],['订单123']),(4804,[网页原文,'a','href'],['/shop']),
          (4803,[网页原文,'.missing'],[]),(4801,[''],''),
          (4901,['你好{{ name }} / {{ shop.city }}','{"name":"中文🙂","shop":{"city":"佛山"}}'],'你好中文🙂 / 佛山'),
          (4902,['{{ name }}{{ shop.city }}{{ name }}'],['name','shop.city']),
          (7982,[靶场地址+'/html'],'门店123 & 服务'),(7983,[靶场地址+'/html'],网页正文),
          (7984,[靶场地址+'/html'],['/shop']),(7985,[靶场地址+'/html','p'],['订单123']),
          (7986,[靶场地址+'/json','/标题'],'中文🙂'),(7987,[靶场地址+'/html','订单\\d+'],['订单123']),
          (7988,[靶场地址+'/html'],hashlib.sha256(网页原文.encode()).hexdigest()),
          (7993,['{{ name }}','{"name":"中文🙂"}'],hashlib.sha256('中文🙂'.encode()).hexdigest()),
          (7994,['{{ name }}','{"name":"中文🙂"}'],urllib.parse.quote('中文🙂',safe='-._~')),
          (7995,[靶场地址+'/html'],urllib.parse.quote('门店123 & 服务',safe='-._~'))]
    for 编号,参数表,预期 in 样本:
        实际值=调用(网关实例,编号,参数表)
        检查(实际值==预期,'基础输入输出独立对照%s'%编号,dict(实际=实际值,预期=预期))
    for 编码名,测试文本 in [('GBK','中文'),('UTF-8',原文),('UTF-16LE',原文),('UTF-16BE',原文)]:
        编码字节=调用(网关实例,4001,[测试文本,编码名]);检查(编码字节==测试文本.encode(编码名),'字符编码独立字节对照'+编码名)
        检查(调用(网关实例,4002,[编码字节,编码名])==测试文本,'字符编码往返'+编码名)
    for 编码名 in ('UTF-8','GBK'):检查(调用(网关实例,4002,[b'',编码名])=='','空字节解码'+编码名)
    ZIP字节=调用(网关实例,3403,['目录/中文.txt',原文.encode()])
    with zipfile.ZipFile(io.BytesIO(ZIP字节)) as 归档:检查(归档.read('目录/中文.txt')==原文.encode(),'V1生成ZIP由独立标准库解包')
    检查(调用(网关实例,3401,[ZIP字节])==['目录/中文.txt'],'ZIP成员原生列表')
    检查(调用(网关实例,3402,[ZIP字节,'目录/中文.txt'])==原文.encode(),'ZIP成员原生字节')
    缓冲=io.BytesIO()
    with zipfile.ZipFile(缓冲,'w',compression=zipfile.ZIP_DEFLATED) as 归档:归档.writestr('压缩.txt',原文)
    检查(调用(网关实例,3402,[缓冲.getvalue(),'压缩.txt'])==原文.encode(),'标准库Deflate归档由V1解码')
    文件路径=文件目录/'原文.txt';路径=str(文件路径)
    检查(调用(网关实例,3104,[路径,原文])==路径,'新建真实文件')
    检查(文件路径.read_text()==原文,'独立读取新建文本')
    检查(调用(网关实例,3102,[路径])==原文,'公开读取文本')
    检查(调用(网关实例,3103,[路径])==原文.encode(),'公开读取字节')
    检查(调用(网关实例,7990,[路径])==hashlib.sha256(原文.encode()).hexdigest(),'文件读取摘要组合')
    检查(调用(网关实例,7997,[路径,'订单\\d+'])==['订单123'],'文件正则组合')
    二进制路径=str(文件目录/'原字节.bin');调用(网关实例,3105,[二进制路径,b'\x00\xff']);检查(Path(二进制路径).read_bytes()==b'\x00\xff','真实二进制新建')
    复制路径=str(文件目录/'副本.txt');调用(网关实例,3108,[路径,复制路径]);检查(Path(复制路径).read_bytes()==原文.encode(),'复制文件不改变字节')
    调用(网关实例,3109,[复制路径]);检查(not Path(复制路径).exists(),'非递归删除真实文件')
    子目录=str(文件目录/'空目录');调用(网关实例,3106,[子目录]);检查(Path(子目录).is_dir(),'真实创建目录')
    检查(调用(网关实例,3107,[str(文件目录)])==sorted(目录件.name for 目录件 in 文件目录.iterdir()),'目录列表独立对照')
    调用(网关实例,3110,[子目录]);检查(not Path(子目录).exists(),'真实删除空目录')
    JSON路径=str(文件目录/'规范.json');调用(网关实例,7996,[JSON路径,'{"b":2,"a":1}']);检查(json.loads(Path(JSON路径).read_text())==dict(a=1,b=2),'JSON规范新建模块')
    检查(json.loads(调用(网关实例,7991,[JSON路径]))==dict(a=1,b=2),'文件JSON规范组合')
    CSV路径=文件目录/'行表.csv';CSV路径.write_text('姓名,备注\n门店,订单123\n')
    检查(json.loads(调用(网关实例,7998,[str(CSV路径)]))==[['姓名','备注'],['门店','订单123']],'文件CSV解析组合')
    import zlib
    检查(zlib.decompress(bytes.fromhex(调用(网关实例,7992,[str(CSV路径)]))).decode()==CSV路径.read_text(),'文件读取压缩独立还原')
    模板路径=str(文件目录/'渲染.txt');调用(网关实例,7999,[模板路径,'你好{{ name }}','{"name":"门店"}']);检查(Path(模板路径).read_text()=='你好门店','模板生成真实文件')
    下载路径=str(文件目录/'下载.txt');调用(网关实例,2404,[靶场地址+'/html',下载路径]);检查(Path(下载路径).read_text()==网页原文,'HTTP下载真实落盘')
    摘要路径=str(文件目录/'下载摘要.txt');摘要结果=调用(网关实例,7989,[靶场地址+'/html',摘要路径]);检查(摘要结果['摘要文本']==hashlib.sha256(网页原文.encode()).hexdigest(),'网络下载文件摘要跨库')
