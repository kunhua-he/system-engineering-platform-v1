def 核验边界样本(调用,检查,网关实例,靶场地址,文件目录):
    for 编号,参数表,错误码 in [
        (2401,['file:///etc/hosts'],2401),(2401,[靶场地址+'/missing'],2405),
        (2401,[靶场地址+'/redirect'],2405),(2401,[靶场地址+'/large'],2403),
        (2401,[靶场地址+'/bytes'],2402),(2402,[靶场地址+'/json','{bad'],2402),
        (4803,['<p>x</p>','['],4802),(4803,['<p>x</p>','x'*4097],4803),
        (4901,['{{ missing }}','{}'],4902),(4901,['{{ name }}','[]'],4902),
        (4901,['{{ "x" * 999999999 }}','{}'],4902),(4901,['{% for x in range(100) %}x{% endfor %}','{}'],4902),
        (4001,['🙂','GBK'],4002),(4002,[b'\xff','UTF-8'],4002),
        (4001,['中文','no-such-encoding'],4002),(3401,[b'notzip'],3402),
        (3403,['../逃出.txt',b'x'],3402),(3403,['/绝对.txt',b'x'],3402),
        (3102,['相对.txt'],3004),(3102,[str(文件目录/'不存在')],3001),
        (3102,[str(文件目录)],3002),(3104,[str(文件目录/'原文.txt'),'覆盖'],3013),
        (3109,[str(文件目录)],3002),(3110,[str(文件目录)],3014),
        (7983,[靶场地址+'/missing'],2405),(7999,[str(文件目录/'失败不落盘.txt'),'{{ missing }}','{}'],4902),
    ]:调用(网关实例,编号,参数表,错误码)
    检查(not (文件目录/'失败不落盘.txt').exists(),'跨库中间失败没有文件副作用')
    for 编号,参数 in [(2401,['中'*22000]),(4801,['中'*22000]),(4901,['中'*22000,'{}']), (4002,[b'x'*65537,'UTF-8']),(3401,[b'x'*65537]),(3105,[str(文件目录/'过大.bin'),b'x'*65537])]:
        调用(网关实例,编号,参数, {2401:2403,4801:4803,4901:4903,4002:4003,3401:3403,3105:3012}[编号])
    调用(网关实例,4901,['{{ name }}'*7000,'{"name":"中文"}'],4903)
    调用(网关实例,4901,['{{ name }}'*6000,'{"name":"中文中文"}'],4903)
    大文件=文件目录/'过大.txt';大文件.write_bytes(b'x'*65537);调用(网关实例,3102,[str(大文件)],3012)
    链接路径=文件目录/'链接.txt';链接路径.symlink_to(文件目录/'原文.txt');调用(网关实例,3109,[str(链接路径)],3002)
    检查(链接路径.is_symlink() and (文件目录/'原文.txt').exists(),'拒删除链接并保留目标')
    炸弹流=io.BytesIO()
    with zipfile.ZipFile(炸弹流,'w',compression=zipfile.ZIP_DEFLATED) as 归档:归档.writestr('大成员.txt',b'x'*65537)
    调用(网关实例,3402,[炸弹流.getvalue(),'大成员.txt'],3403)
    原文=(文件目录/'原文.txt').read_bytes()
    调用(网关实例,2404,[靶场地址+'/html',str(文件目录/'原文.txt')],2406)
    检查((文件目录/'原文.txt').read_bytes()==原文,'下载拒覆盖不污染原文件')
    检查(not (文件目录/'过大.bin').exists(),'资源界拒绝发生写入')
