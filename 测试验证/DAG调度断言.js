/* DAG调度断言.js —— 图任务黑盒验收的断言与并发调度（页面只渲染，判定全在这里）。
 *
 * 硬规矩：HTTP 200 不算通过（业务失败也是 200 + 成功=false）。每格先解平台信封
 * （成功 / 错误 / 值），再拿真任务标识去查任务，按节点阶段与任务阶段的真实跃迁、
 * 按节点时间区间是否重叠下结论；拿不到真标识、拿不到阶段轨迹的格记「阻塞」，不记通过。
 */
'use strict';
const 终态集 = ['成功', '失败', '跳过', '已取消'];
const 任务阶段集 = ['排队中', '执行中', '收尾中', '成功', '失败', '已取消'];
const 节点阶段集 = ['等待依赖', '就绪', '等资源', '执行中', '收尾中', '成功', '失败', '跳过', '已取消'];
/* 页面设置：入口、资源键测试编号与采样节拍都可从页面改，改的是数据不是代码。 */
const 页面设置 = { 入口: '接口/调用', 资源键编号: 1108, 请求超时毫秒: 8000, 采样间隔毫秒: 30, 采样预算毫秒: 6000, 采样最长次数: 200 };
function 等一会儿(等待毫秒) {
  return new Promise(function (兑现) {
    setTimeout(兑现, 等待毫秒);
  });
}
function 新标识(标识前缀) {
  const 片段 = Math.random().toString(36).slice(2, 8);
  return 标识前缀 + '-' + Date.now().toString(36) + '-' + 片段;
}

/* ── 传输与信封 ─────────────────────────────────────────────── */
async function 交请求(请求体全文) {
  const 起点时刻 = performance.now();
  const 入口地址 = new URL(页面设置.入口, location.origin).toString();
  const 应答对象 = { 入口地址: 入口地址, 请求体: 请求体全文, HTTP码: 0, 原文: '', 解析: null, 耗时毫秒: 0, 网络失败: '' };
  const 中断控 = new AbortController();
  const 计时 = setTimeout(function () { 中断控.abort(); }, 页面设置.请求超时毫秒);
  try {
    const 响应对象 = await fetch(入口地址, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(请求体全文),
      signal: 中断控.signal,
    });
    应答对象.HTTP码 = 响应对象.status;
    应答对象.原文 = await 响应对象.text();
    try { 应答对象.解析 = JSON.parse(应答对象.原文); } catch (异常) { 应答对象.解析 = null; }
  } catch (异常) {
    应答对象.网络失败 = (异常 && 异常.name === 'AbortError') ? '请求超时' : ('网络异常：' + (异常 && 异常.message ? 异常.message : 异常));
  } finally {
    clearTimeout(计时);
  }
  应答对象.耗时毫秒 = Math.round(performance.now() - 起点时刻);
  return 应答对象;
}
/* 解平台信封：四通道 —— 网络失败 / 非JSON（多半是静态托管 404） / 协议错误（4xx） / 业务失败（200 且 成功=false） / 受理成功。 */
function 解信封(应答对象) {
  const 信封解 = { 信封通道: '', 成功: false, 错误名: '', 错误码: null, 错误类别: null, 错误说明: '', 值: null, 说明: '' };
  if (应答对象.网络失败) {
    信封解.信封通道 = '网络失败';
    信封解.说明 = 应答对象.网络失败;
    return 信封解;
  }
  if (!应答对象.解析 || typeof 应答对象.解析 !== 'object') {
    信封解.信封通道 = '非JSON';
    信封解.说明 = 'HTTP ' + 应答对象.HTTP码 + ' 但回体不是 JSON：' + String(应答对象.原文 || '').slice(0, 160);
    return 信封解;
  }
  const 请求体全文 = 应答对象.解析;
  if (typeof 请求体全文.协议错误 === 'string') {
    信封解.信封通道 = '协议错误';
    信封解.说明 = 'HTTP ' + 应答对象.HTTP码 + ' 协议错误：' + 请求体全文.协议错误;
    return 信封解;
  }
  if (应答对象.HTTP码 >= 400) {
    信封解.信封通道 = '协议错误';
    信封解.说明 = 'HTTP ' + 应答对象.HTTP码 + '（无协议错误字段）：' + JSON.stringify(请求体全文).slice(0, 160);
    return 信封解;
  }
  信封解.值 = 请求体全文.值 !== undefined ? 请求体全文.值 : null;
  if (请求体全文.成功 === true) {
    信封解.信封通道 = '受理成功';
    信封解.成功 = true;
    信封解.说明 = '成功：值已回';
    return 信封解;
  }
  信封解.信封通道 = '业务失败';
  /* 两种失败形状都要认：
     ① 单能力失败 —— 错误在顶层 `错误`（带名称/码/类别）；
     ② **图任务跑到终态是失败** —— 任务已经被受理、已经跑完，错误在 `值.错误`（只有说明与节点标识）。
     第 ② 种不是「没受理」：它带着任务标识和每个节点的真实阶段，是真样本，丢掉它就会把
     「同步等待里等到了失败结局」误读成「提交被拒」。 */
  const 异常 = 请求体全文.错误 || {};
  const 值内错误 = (信封解.值 && typeof 信封解.值 === 'object' && 信封解.值.错误) ? 信封解.值.错误 : {};
  信封解.错误名 = 异常.名称 || '';
  信封解.错误码 = 异常.码 !== undefined ? 异常.码 : null;
  信封解.错误类别 = 异常.类别 !== undefined ? 异常.类别 : null;
  信封解.错误说明 = 异常.说明 || 异常.可读说明 || 值内错误.说明 || '';
  if (信封解.错误名 === '' && 信封解.错误说明 !== '') {
    信封解.说明 = '任务失败：' + 信封解.错误说明;
  } else {
    信封解.说明 = '业务失败：' + (信封解.错误名 || '未给错误名') + (信封解.错误码 === null ? '' : '（码 ' + 信封解.错误码 + '）');
  }
  return 信封解;
}
/* 值里的每一项都可能带类型标签：数组与「{类型标签,值}」两种包法都拆开。 */
function 拆标签(值) {
  let 当前层级 = 值;
  for (let 轮次 = 0; 轮次 < 4; 轮次 += 1) {
    if (Array.isArray(当前层级) && 当前层级.length === 1) { 当前层级 = 当前层级[0]; continue; }
    if (当前层级 && typeof 当前层级 === 'object' && !Array.isArray(当前层级)
      && 当前层级.类型标签 !== undefined && Object.prototype.hasOwnProperty.call(当前层级, '值')) {
      当前层级 = 当前层级.值;
      continue;
    }
    break;
  }
  return 当前层级;
}
function 取任务标识(信封解) {
  const 值 = 拆标签(信封解.值);
  if (值 && typeof 值 === 'object' && !Array.isArray(值)) {
    const 键名 = ['任务标识', '任务标识串', '标识'];
    for (let 序位 = 0; 序位 < 键名.length; 序位 += 1) {
      const 取档 = 值[键名[序位]];
      // 平台的 `任务标识` 是**非负整数**（不是字符串）：数字与字符串都收，只丢空值。
      if (typeof 取档 === 'number' && Number.isFinite(取档) && 取档 >= 0) return String(取档);
      if (typeof 取档 === 'string' && 取档.trim() !== '') return 取档.trim();
    }
  }
  return '';
}
function 取任务阶段(信封解) {
  const 值 = 拆标签(信封解.值);
  if (值 && typeof 值 === 'object' && !Array.isArray(值)) {
    const 键名 = ['任务状态', '任务阶段'];
    for (let 序位 = 0; 序位 < 键名.length; 序位 += 1) {
      const 取档 = 值[键名[序位]];
      if (typeof 取档 === 'string' && 任务阶段集.indexOf(取档) >= 0) return 取档;
    }
  }
  return '';
}
/* 节点项：键名容三种写法（节点表 / 节点 / 节点状态），形状统一成 {标识, 阶段, 开始, 结束, 批号}。 */
function 取节点项(信封解) {
  const 值 = 拆标签(信封解.值);
  const 结果集 = [];
  if (!值 || typeof 值 !== 'object') return 结果集;
  const 末级容器 = 值.节点表 || 值.节点 || 值.节点状态 || 值.节点列表;
  if (!Array.isArray(末级容器)) return 结果集;
  for (let 序位 = 0; 序位 < 末级容器.length; 序位 += 1) {
    const 原条目 = 拆标签(末级容器[序位]);
    if (!原条目 || typeof 原条目 !== 'object') continue;
    const 标识 = String(原条目.节点标识 || 原条目.标识 || '');
    if (!标识) continue;
    结果集.push({
      标识: 标识,
      阶段: String(原条目.阶段 || 原条目.节点阶段 || 原条目.状态 || ''),
      开始: 数时间(原条目.开始微秒 !== undefined ? 原条目.开始微秒 : (原条目.开始时刻 !== undefined ? 原条目.开始时刻 : 原条目.起始时刻)),
      结束: 数时间(原条目.结束微秒 !== undefined ? 原条目.结束微秒 : (原条目.结束时刻 !== undefined ? 原条目.结束时刻 : 原条目.完成时刻)),
      批号: 原条目.执行批号 !== undefined ? 原条目.执行批号 : null,
    });
  }
  return 结果集;
}
function 数时间(原条目) {
  if (typeof 原条目 === 'number' && isFinite(原条目)) return 原条目;
  if (typeof 原条目 === 'string' && 原条目.trim() !== '' && isFinite(Number(原条目))) return Number(原条目);
  return null;
}
/* 平台若给「阶段轨迹 / 轨迹 / 历史」，直接采信它；没给就退回轮询采样。 */
function 取轨迹项(信封解) {
  const 值 = 拆标签(信封解.值);
  const 结果集 = [];
  if (!值 || typeof 值 !== 'object') return 结果集;
  const 末级容器 = 值.阶段轨迹 || 值.轨迹 || 值.历史;
  if (!Array.isArray(末级容器)) return 结果集;
  for (let 序位 = 0; 序位 < 末级容器.length; 序位 += 1) {
    const 原条目 = 拆标签(末级容器[序位]);
    if (!原条目 || typeof 原条目 !== 'object') continue;
    结果集.push({
      时刻: 数时间(原条目.时刻 !== undefined ? 原条目.时刻 : 原条目.发生时刻),
      任务阶段: String(原条目.任务阶段 || 原条目.任务状态 || ''),
      节点标识: String(原条目.节点标识 || 原条目.标识 || ''),
      阶段: String(原条目.阶段 || 原条目.节点阶段 || ''),
    });
  }
  return 结果集;
}

/* ── 记录与判定骨架 ─────────────────────────────────────────── */
function 新记录(定义) {
  return {
    片键: 定义.片键,
    名称: 定义.名称,
    意图: 定义.意图,
    流水: [],
    轨迹: [],
    轨迹来源: '',
    断言: [],
    判定: '阻塞',
    理由: '',
    任务标识: '',
    耗时毫秒: 0,
  };
}
function 记一步(格记录, 步名, 应答对象, 信封解) {
  格记录.流水.push({
    步: 步名,
    请求体: 应答对象.请求体,
    HTTP码: 应答对象.HTTP码,
    信封通道: 信封解.信封通道,
    成功: 信封解.成功,
    错误名: 信封解.错误名,
    错误码: 信封解.错误码,
    说明: 信封解.说明,
    值: 信封解.值,
    耗时毫秒: 应答对象.耗时毫秒,
  });
}
function 记断言(格记录, 条件, 说明) {
  格记录.断言.push({ 说明: 说明, 通过: !!条件 });
  return !!条件;
}
function 判阻塞(格记录, 理由) {
  格记录.判定 = '阻塞';
  格记录.理由 = 理由;
  return 格记录;
}
/* 收口：断言全过才算通过；任何一条不过即失败，并指出第一条不过的原因。 */
function 收口(格记录) {
  const 未过条目 = 格记录.断言.filter(function (条目) { return !条目.通过; });
  if (未过条目.length === 0) {
    if (格记录.断言.length === 0) return 判阻塞(格记录, '没有任何断言被执行，视为未验');
    格记录.判定 = '通过';
    格记录.理由 = '全部断言成立（共 ' + 格记录.断言.length + ' 条目）';
    return 格记录;
  }
  格记录.判定 = '失败';
  格记录.理由 = '首个不成立断言：' + 未过条目[0].说明 + (未过条目.length > 1 ? '（共 ' + 未过条目.length + ' 条不成立）' : '');
  return 格记录;
}
async function 跑一格(定义) {
  const 格记录 = 新记录(定义);
  const 起点时刻 = performance.now();
  try {
    await 定义.跑(格记录);
  } catch (异常) {
    判阻塞(格记录, '执行器异常：' + (异常 && 异常.message ? 异常.message : String(异常)));
  }
  格记录.耗时毫秒 = Math.round(performance.now() - 起点时刻);
  return 格记录;
}

/* ── 提交 / 查询 / 采样 ─────────────────────────────────────── */
function 节点(标识, 编号, 命名值, 依赖节点) {
  return {
    节点标识: 标识,
    编号: 编号,
    命名值: 命名值 || {},
    依赖节点: 依赖节点 || [],
    输入引用: [],
  };
}
function 提交体(请求标识, 节点表, 附加) {
  const 请求体全文 = { 任务操作: '提交', 请求标识: 请求标识, 节点表: 节点表 };
  if (附加) Object.keys(附加).forEach(function (片键) { 请求体全文[片键] = 附加[片键]; });
  return 请求体全文;
}
function 控制体(操作, 任务标识, 附加) {
  // 平台的 `任务标识` 是**非负整数**：本地为便于展示存成字符串，发请求前必须还原成数字，
  // 否则平台会回「任务标识 不是非负整数」（协议按类型判，不做字符串宽容）。
  const 数字标识 = typeof 任务标识 === 'number' ? 任务标识 : Number(String(任务标识).trim());
  const 请求体全文 = { 任务操作: 操作, 任务标识: Number.isFinite(数字标识) ? 数字标识 : 任务标识 };
  if (附加) Object.keys(附加).forEach(function (片键) { 请求体全文[片键] = 附加[片键]; });
  return 请求体全文;
}
async function 提交(格记录, 步名, 请求体全文) {
  const 应答对象 = await 交请求(请求体全文);
  const 信封解 = 解信封(应答对象);
  记一步(格记录, 步名, 应答对象, 信封解);
  // 受理判定只看「回执有没有任务标识」：带同步等待时，等到失败结局的回执也是 `成功:false`，
  // 但任务确实被受理且跑完了 —— 拿 成功 这个真假值当受理判据就是把「跑失败了」误读成「没受理」。
  const 本次标识 = 取任务标识(信封解);
  if (本次标识) {
    格记录.任务标识 = 本次标识;
    // 回执带**节点真实阶段**（执行中 / 等待依赖 / 终态），它是一个真样本，
    // 不能因为「不是查询拿的」就丢掉：丢掉就会把「图跑得快」误判成「没有中间态」。
    const 受理节点 = 取节点项(信封解);
    if (受理节点.length > 0) {
      格记录.轨迹.push({ 时刻: Math.round(performance.now()), 任务阶段: 取任务阶段(信封解), 节点: 受理节点, 轨迹: [] });
    }
  }
  return 信封解;
}
async function 控制(格记录, 步名, 请求体全文) {
  const 应答对象 = await 交请求(请求体全文);
  const 信封解 = 解信封(应答对象);
  记一步(格记录, 步名, 应答对象, 信封解);
  return 信封解;
}
/* 查询一次：默认只回任务摘要；摘要里没有节点项时按节点逐个补查（每个节点一次，不刷屏）。 */
async function 采一(格记录, 任务标识, 节点标识表) {
  const 信封解 = await 控制(格记录, '查询', 控制体('查询', 任务标识));
  const 样本 = {
    时刻: Math.round(performance.now()),
    任务阶段: 取任务阶段(信封解),
    节点: 取节点项(信封解),
    轨迹: 取轨迹项(信封解),
  };
  if (样本.节点.length === 0 && 信封解.成功 && 节点标识表 && 节点标识表.length > 0) {
    样本.节点 = [];
    for (let 序位 = 0; 序位 < 节点标识表.length; 序位 += 1) {
      const 单次信封 = await 控制(格记录, '查询·' + 节点标识表[序位], 控制体('查询', 任务标识, { 节点标识: 节点标识表[序位] }));
      if (!单次信封.成功) continue;
      const 节点项 = 取节点项(单次信封);
      if (节点项.length > 0) 样本.节点.push(节点项[0]);
      else 样本.节点.push({ 标识: 节点标识表[序位], 阶段: 取任务阶段(单次信封), 开始: null, 结束: null, 批号: null });
      if (单次信封.值 && 单次信封.值.阶段轨迹) 样本.轨迹 = 样本.轨迹.concat(取轨迹项(单次信封));
    }
  }
  return 样本;
}
/* 采样到终态：间隔轮询，直到任务到终态或预算用完；每轮都进轨迹，供后面判跃迁与区间。 */
async function 采样(格记录, 节点标识表) {
  const 起点时刻 = performance.now();
  const 节点名 = (节点标识表 || []).slice();
  let 轮询次数 = 0;
  while (轮询次数 < 页面设置.采样最长次数 && performance.now() - 起点时刻 < 页面设置.采样预算毫秒) {
    轮询次数 += 1;
    const 样本 = await 采一(格记录, 格记录.任务标识, 节点名);
    格记录.轨迹.push(样本);
    if (样本.轨迹 && 样本.轨迹.length > 0) 格记录.轨迹来源 = '平台轨迹';
    if (样本.任务阶段 && 终态集.indexOf(样本.任务阶段) >= 0) break;
    if (!样本.任务阶段 && 样本.节点.length === 0 && 轮询次数 >= 3) break;
    await 等一会儿(页面设置.采样间隔毫秒);
  }
  return 格记录.轨迹;
}
/* 区间表：优先用平台给的开始/结束时刻；没给就用采样里「见过该阶段」的时刻拼出来。 */
function 建区间(格记录) {
  const 区间表 = {};
  function 取档(标识) {
    if (!区间表[标识]) 区间表[标识] = { 起点时刻: null, 止: null, 阶段: [], 来源: '采样', 批号: null };
    return 区间表[标识];
  }
  格记录.轨迹.forEach(function (样本) {
    样本.节点.forEach(function (节点项) {
      const 条目 = 取档(节点项.标识);
      if (条目.阶段.indexOf(节点项.阶段) < 0) 条目.阶段.push(节点项.阶段);
      if (节点项.开始 !== null) { 条目.起点时刻 = 节点项.开始; 条目.来源 = '时间戳'; }
      if (节点项.结束 !== null) { 条目.止 = 节点项.结束; 条目.来源 = '时间戳'; }
      if (!条目.批号 && 节点项.批号 !== null) 条目.批号 = 节点项.批号;
    });
  });
  /* 采样兜底：把「见过 执行中/收尾中」的首末时刻当作区间端点。 */
  const 首见 = {};
  const 末见 = {};
  格记录.轨迹.forEach(function (样本) {
    样本.节点.forEach(function (节点项) {
      if (['执行中', '收尾中'].indexOf(节点项.阶段) < 0) return;
      if (首见[节点项.标识] === undefined) 首见[节点项.标识] = 样本.时刻;
      末见[节点项.标识] = 样本.时刻;
    });
  });
  Object.keys(首见).forEach(function (标识) {
    const 条目 = 取档(标识);
    if (条目.起点时刻 === null) 条目.起点时刻 = 首见[标识];
    if (条目.止 === null) 条目.止 = 末见[标识];
  });
  return 区间表;
}
function 有节点阶段(格记录) {
  return 格记录.轨迹.some(function (样本) { return 样本.节点.length > 0; });
}
/* 跃迁证据：同一节点在两个采样里被看到不同阶段；或平台给了阶段轨迹。 */
function 有跃迁(格记录) {
  if (格记录.轨迹来源 === '平台轨迹') return true;
  const 阶段册 = {};
  let 已见跃迁 = false;
  格记录.轨迹.forEach(function (样本) {
    样本.节点.forEach(function (节点项) {
      if (!阶段册[节点项.标识]) 阶段册[节点项.标识] = {};
      if (!阶段册[节点项.标识][节点项.阶段]) { 阶段册[节点项.标识][节点项.阶段] = 1; 已见跃迁 = 已见跃迁 || Object.keys(阶段册[节点项.标识]).length > 1; }
    });
  });
  return 已见跃迁;
}
function 见过(格记录, 标识, 阶段) {
  return 格记录.轨迹.some(function (样本) {
    return 样本.节点.some(function (节点项) { return 节点项.标识 === 标识 && 节点项.阶段 === 阶段; });
  });
}
function 区间重叠(左区间段, 右区间段) {
  if (!左区间段 || !右区间段 || 左区间段.起点时刻 === null || 左区间段.止 === null || 右区间段.起点时刻 === null || 右区间段.止 === null) return false;
  return Math.min(左区间段.止, 右区间段.止) >= Math.max(左区间段.起点时刻, 右区间段.起点时刻);
}
/* 某个节点是否被采到过「非终态」阶段。没采到 ≠ 没发生 —— 图跑得比采样间隔还快时，
   结论只能是「证据不足」，记阻塞；记失败等于把仪表的分辨率当成平台的缺陷。 */
function 见过中间态(格记录, 标识) {
  return 格记录.轨迹.some(function (样本) {
    return 样本.节点.some(function (节点项) {
      return 节点项.标识 === 标识 && 节点项.阶段 !== '成功' && 节点项.阶段 !== '失败' && 节点项.阶段 !== '已取消';
    });
  });
}
/* 时间区间证据：平台回执里目前**不带**节点开始/结束时刻（只有阶段名），
   所以「并发区间重叠」「同键区间互斥」这类断言在外部拿不到证据 —— 记阻塞，不记失败。 */
function 区间证据齐(区间册, 标识表) {
  return 标识表.every(function (标识) {
    const 段 = 区间册[标识];
    return 段 && 段.起点时刻 !== null && 段.止 !== null;
  });
}
function 中间态缺证据(格记录, 标识表) {
  const 缺 = 标识表.filter(function (标识) { return !见过中间态(格记录, 标识); });
  if (缺.length === 0) return null;
  return 判阻塞(格记录, '采样没有抓到这些节点的中间阶段（' + 缺.join('、') + '）：图比采样间隔还快，证据不足，不能判通过也不能判失败');
}
function 末尾任务阶段(格记录) {
  for (let 序位 = 格记录.轨迹.length - 1; 序位 >= 0; 序位 -= 1) {
    if (格记录.轨迹[序位].任务阶段) return 格记录.轨迹[序位].任务阶段;
  }
  return '';
}
/* 提交未受理时统一出口：把信封里的真话搬进理由，格记阻塞。 */
function 提交受阻(格记录, 信封解) {
  return 判阻塞(格记录, '提交未被受理（' + 信封解.信封通道 + '）：' + 信封解.说明);
}
function 阶段缺证据(格记录) {
  const 末查 = 格记录.流水.filter(function (条目) { return 条目.步.indexOf('查询') === 0; }).pop();
  const 附言 = 末查 ? '（末次查询：' + 末查.信封通道 + ' · ' + String(末查.说明 || '').slice(0, 120) + '）' : '（本格没有发出过查询）';
  if (!有节点阶段(格记录)) return 判阻塞(格记录, '查询未回节点阶段：拿不到节点跃迁，不能判通过' + 附言);
  if (!有跃迁(格记录)) return 判阻塞(格记录, '采样只见到终态快照，没有中间阶段：无法证明阶段跃迁（图任务过快或平台不回中间态）' + 附言);
  return null;
}

