/* 十二 · 取消执行中 / 等待中的节点：先看任务真在哪一阶段，再取消，然后看有没有停下。 */
async function 格取消(格记录) {
  const 本次标识 = 新标识('取消');
  const 节点清单 = [
    节点('取消根', 1108, { 程序文本: '取消根' }),
    节点('取消一', 1108, { 程序文本: '取消一' }, ['取消根']),
    节点('取消二', 1108, { 程序文本: '取消二' }, ['取消根']),
    节点('取消尾', 1108, { 程序文本: '取消尾' }, ['取消一', '取消二']),
  ];
  const 提交信封 = await 提交(格记录, '提交', 提交体(本次标识, 节点清单));
  if (!提交信封.成功 || !格记录.任务标识) return 提交受阻(格记录, 提交信封);
  const 首查 = await 采一(格记录, 格记录.任务标识, ['取消根', '取消一', '取消二', '取消尾']);
  格记录.轨迹.push(首查);
  const 取消前 = 首查.任务阶段;
  if (取消前 === '') {
    const 末查 = 格记录.流水.filter(function (条目) { return 条目.步.indexOf('查询') === 0; }).pop();
    return 判阻塞(格记录, '首次查询没回任务阶段，取消窗口无法判定（' + (末查 ? 末查.信封通道 + ' · ' + String(末查.说明 || '').slice(0, 100) : '没有查询流水') + '）');
  }
  if (终态集.indexOf(取消前) >= 0) {
    return 判阻塞(格记录, '取消窗口没赶上：查询时任务已在终态 ' + 取消前 + '，执行中/等待中取消未被验到');
  }
  const 取档 = await 控制(格记录, '取消', 控制体('取消', 格记录.任务标识));
  if (!取档.成功) return 判阻塞(格记录, '取消未被受理（' + 取档.信封通道 + '）：' + String(取档.说明 || '').slice(0, 120));
  await 采样(格记录, ['取消根', '取消一', '取消二', '取消尾']);
  记断言(格记录, 末尾任务阶段(格记录) === '已取消', '任务阶段 落到 已取消（实见 ' + (末尾任务阶段(格记录) || '未回阶段') + '）');
  const 未跑节点 = ['取消尾'].filter(function (键名) { return 见过(格记录, 键名, '已取消') || 见过(格记录, 键名, '跳过'); });
  记断言(格记录, 未跑节点.length > 0, '未开工的节点被收成 已取消/跳过');
  const 释放信封 = await 控制(格记录, '释放', 控制体('释放', 格记录.任务标识));
  记断言(格记录, 释放信封.成功 || 释放信封.信封通道 === '业务失败', '释放有明确回执（成功或业务失败，不是崩）');
  return 收口(格记录);
}
