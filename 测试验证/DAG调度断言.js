/* 并发：十三格一场 Promise.all；格子互不共享请求标识，并发不会互相干扰。 */
async function 跑全部(进度) {
  const 起点时刻 = performance.now();
  const 结果集 = await Promise.all(格表.map(async function (定义) {
    const 格记录 = await 跑一格(定义);
    if (typeof 进度 === 'function') 进度(格记录);
    return 格记录;
  }));
  const 汇总 = { 通过: 0, 失败: 0, 阻塞: 0, 总耗时毫秒: Math.round(performance.now() - 起点时刻) };
  结果集.forEach(function (格记录) { 汇总[格记录.判定] = (汇总[格记录.判定] || 0) + 1; });
  return { 结果集: 结果集, 汇总: 汇总 };
}
/* 单格重跑：给某一格单独再跑一遍，不打断其它结果。 */
async function 跑单格(片键, 进度) {
  const 定义 = 格表.filter(function (条目) { return 条目.片键 === 片键; })[0];
  if (!定义) throw new Error('没有这一格：' + 片键);
  return 跑一格(定义);
}
/* 平台探测：先看端点在不在、能力清单里有没有图任务能力。这是页尾那张「服务状态」的证据。 */
async function 探测平台() {
  const 探测读数 = { 入口地址: new URL('接口', location.origin).toString(), HTTP码: 0, 说明: '', 能力候选: [], 端点: [] };
  try {
    const 响应对象 = await fetch(探测读数.入口地址, { method: 'GET' });
    探测读数.HTTP码 = 响应对象.status;
    const 回体文本 = await 响应对象.text();
    let 信封解 = null;
    try { 信封解 = JSON.parse(回体文本); } catch (异常) { 信封解 = null; }
    if (!信封解) {
      探测读数.说明 = 'HTTP ' + 响应对象.status + ' 但回体不是 JSON：' + 回体文本.slice(0, 120);
      return 探测读数;
    }
    探测读数.端点 = (信封解.端点 || []).map(function (条目) { return 条目.方法 + ' ' + 条目.路径; });
    const 能力 = 信封解.能力 || [];
    探测读数.能力候选 = 能力.filter(function (条目) {
      return /图任务|调用任务|调度/.test(String(条目.名称 || ''));
    }).map(function (条目) { return 条目.编号 + ' ' + 条目.名称; });
    const 任务类能力 = 能力.filter(function (条目) { return /任务/.test(String(条目.名称 || '')); });
    探测读数.说明 = 'HTTP ' + 响应对象.status + ' · 端点 ' + 探测读数.端点.length + ' 个 · 能力 ' + 能力.length + ' 条'
      + ' · 图任务能力 ' + 探测读数.能力候选.length + ' 条'
      + ' · 名字带任务的其它能力 ' + 任务类能力.length + ' 条（' + 任务类能力.slice(0, 6).map(function (条目) { return 条目.名称; }).join(' / ') + '）';
  } catch (异常) {
    探测读数.说明 = '网络异常：' + (异常 && 异常.message ? 异常.message : String(异常));
  }
  return 探测读数;
}
