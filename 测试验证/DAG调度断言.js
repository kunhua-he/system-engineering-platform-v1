function 区间重叠(左区间段, 右区间段) {
  if (!左区间段 || !右区间段 || 左区间段.起点时刻 === null || 左区间段.止 === null || 右区间段.起点时刻 === null || 右区间段.止 === null) return false;
  return Math.min(左区间段.止, 右区间段.止) >= Math.max(左区间段.起点时刻, 右区间段.起点时刻);
}
