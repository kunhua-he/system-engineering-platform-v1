//! 取被验扩展的声明（经接缝 `GetPlatformInfo`）与**按名字装载别的声明**。
//!
//! # 接缝是什么（`跨语言适配/边界协议/边界协议.md` 第二节）
//!
//! ```c
//! const 平台信息* GetPlatformInfo(void);   // 每个扩展恰好 1 个导出
//! ```
//!
//! 符号名 ASCII，因为它是**外部协议边界**，别的语言按名字绑。返回静态常量指针，终生有效，
//! 调用方不得释放、不得修改。
//!
//! # 实测撞到的一处硬矛盾（原样报，不替它圆）
//!
//! **底座也导出了一个 `GetPlatformInfo`**（`运行内核/装载入口/src/底座静态声明.rs::取平台信息`
//! 当年手写的那条 `export_name` 属性），
//! 与被验扩展的那个**同名**。同一个进程里静态链接两份，链接器只解析得到一个（实测：扩展那份赢）。
//! 后果是 `运行内核/装载入口` 自身的 `取平台信息()` 也被绑到了扩展那份上，
//! 于是底座的身份自检 `是底座自有声明(声明)` 拿扩展的地址比底座的地址 ⇒ 假 ⇒
//! **底座自身载不进来**（实测 `适配器::装载(底座声明())` = `载入(标识串非法)`，
//! 两个函数的返回地址实测逐位相同：`0x1030235b0`）。
//!
//! 所以本件：
//!
//! 1. 取被验扩展的声明时**核对**「接缝的 C 符号」与「同源的 Rust 只读取用口」指向同一份
//!    静态声明，不等就**炸**（工具错误，退出非 0）——否则跑的是另一份声明，那就是假绿；
//! 2. **声明按名字点**（[`解析声明名`]）：案例的 `声明` 字段点名要装载哪几份声明，
//!    跑案例据此组声明根（底座排在最前）。这就是「装载别的声明」那条路 —— 早先
//!    声明根里**只放被验扩展这一份**（`v1_compiler::取平台信息`），于是只声明 7 条能力
//!    （1101~1107）的编译器支持库之外的声明（底座等）一律调不到，落到注册表占位回码 1
//!    —— 跑出来的「通过」不是真覆盖。
//!
//! **底座声明不经接缝取**（[`取底座声明`]）：同一进程里接缝 `GetPlatformInfo` 被扩展那份
//! 解析走了（见上），拿接缝取底座会拿到扩展的声明 —— 那是假绿。故底座走同源只读口
//! `v1_adapter::底座声明()`。
//!
//! # 第三个导出者：只能走制品，不能静态链接（实测）
//!
//! 再加一份支持库（`文件支持库`）时，**静态链接直接链不起来**：
//! `warning: Linking globals named 'GetPlatformInfo': symbol multiply defined!` +
//! `error: failed to load bitcode of module "v1_file-….rcgu.o"`（release 实测，runner 退出 101）。
//! 这不是环境问题，是「一个进程只能有一个 `GetPlatformInfo` 定义」的直接后果。
//!
//! 所以第二份支持库走**与网关同一条装载腿**：
//! `v1_adapter::工作进程::装载支持库(制品路径, 缓存根)` = 解包制品 → `dlopen` → `dlsym` 接缝 → 取声明。
//! 前置：制品由 `python3 构建装配/上线切换/构建制品.py --预构建` 生成（装配产物 · 不入库）。

use v1_adapter::平台信息;
use v1_adapter::工作进程::装载支持库;

/// 取被验扩展的声明。
///
/// 返回的引用终生有效（契约：静态常量指针）。**调用方不得释放、不得修改。**
pub fn 取扩展声明() -> Result<&'static 平台信息, String> {
    // 接缝：`GetPlatformInfo` 那一个导出符号，按 Rust 路径调（同一份函数）。
    let 接缝 = v1_compiler::取平台信息();
    // 同源的只读取用口（扩展自身写的「验证面与测试用，不新增导出符号」那一处）。
    let 取用口 = v1_compiler::扩展声明() as *const 平台信息;
    if !core::ptr::eq(接缝, 取用口) {
        return Err(format!(
            "接缝 `GetPlatformInfo` 被解析到别的声明上了：接缝返回 {接缝:p}，\
             本扩展的静态声明是 {取用口:p}。\
             实测原因：底座（`运行内核/装载入口`）与被验扩展各导出一个同名 `GetPlatformInfo`。\
             此时**不许**拿另一份声明当被验对象 —— 那就是假绿。"
        ));
    }
    if 接缝.is_null() {
        return Err("接缝 `GetPlatformInfo` 返回了空指针".to_owned());
    }
    // SAFETY: 契约保证返回静态常量指针、终生有效；上面已核对它就是本扩展那一份。
    Ok(unsafe { &*接缝 })
}

/// 取**底座**自身的声明 —— 「装载别的声明」那条路的第一份（排在声明根最前）。
///
/// **不经接缝**：同一进程里接缝 `GetPlatformInfo` 被扩展那份解析走了（见文件头），
/// 拿接缝取底座会拿到扩展的声明。故走同源只读口 [`v1_adapter::底座声明`]。
///
/// 返回的引用终生有效（契约：静态常量指针）。**调用方不得释放、不得修改。**
pub fn 取底座声明() -> &'static 平台信息 {
    v1_adapter::底座声明()
}

/// 声明名 → 静态声明。**案例只按名字点声明**，不写地址、不写路径。
///
/// 这就是「装载别的声明」那条路的入口：案例的 `声明` 字段给出要装载的声明名，
/// 跑案例逐名解析、组声明根（[`取底座声明`] 排最前）。
///
/// **新声明要能被案例装载，就得进本表**：名字不认即工具错误（退出 2），
/// **不静默跳过** —— 静默跳过就是「案例以为跑了那份声明，实际没跑」。
pub fn 解析声明名(声明名: &str) -> Result<&'static 平台信息, String> {
    match 声明名 {
        "底座" => Ok(取底座声明()),
        "编译器支持库" => 取扩展声明(),
        // 第二个扩展：**不静态链接，走制品**。同一进程里 `GetPlatformInfo` 只能解析到一个定义
        // （本件文件头已报这个实测硬矛盾；再加第三份连 LLVM 都拒：
        //  `Linking globals named 'GetPlatformInfo': symbol multiply defined!` ⇒ 整个 runner 链不起来）。
        // 故第二个支持库走与网关同一条装载腿：解包制品 → dlopen → dlsym 接缝 → 取声明
        // （`v1_adapter::工作进程::装载支持库`，全仓唯一实现，本件不自带 dlopen）。
        // ★ 前置：制品是装配产物（不入库），由 `python3 构建装配/上线切换/构建制品.py --预构建` 生成。
        "文件支持库" => 按制品装载("文件支持库"),
        // 第二个走制品的支持库：模块组合案例的依赖（模块 7951 → 宿主回调 → 1330）。
        // 装它进主进程是为了让**错误码登记表**与**依赖台账**都认得 1001 / 1100
        // （这两个码由 1330 抛、模块只透传），不是为了让主进程去算。
        "数值计算支持库" => 按制品装载("数值计算支持库"),
        其他值 => Err(format!(
            "案例点名要装载声明 `{其他值}`，但跑案例的声明名表里没有它\
             （只认 `底座` / `编译器支持库` / `文件支持库` / `数值计算支持库`；声明名表在 `装载声明.rs::解析声明名`）"
        )),
    }
}

/// 按**扩展名**从 `扩展根目录/原子支持库/<名>/<名>.支持库制品` 装载一份支持库声明。
///
/// 走与网关同一条装载腿（[`装载支持库`]：解包制品 → dlopen → dlsym 接缝），
/// **不静态链接**（同一进程里 `GetPlatformInfo` 只能解析到一个定义）。
fn 按制品装载(扩展名: &str) -> Result<&'static 平台信息, String> {
    let 缓存根 = v1_dataroot::解析当前环境()
        .map(|根目录| 根目录.join("装载件缓存"))
        .map_err(|错误| format!("取运行数据根失败：{错误:?}（装载制品要仓外缓存目录）"))?;
    std::fs::create_dir_all(&缓存根)
        .map_err(|错误| format!("建装载缓存目录 {} 失败：{错误}", 缓存根.display()))?;
    装载支持库(
        &crate::运行定位::定位当前仓根()?.join(format!("扩展根目录/原子支持库/{扩展名}/{扩展名}.支持库制品")),
        &缓存根,
    )
    .map_err(|错误| {
        format!(
            "装载 `{扩展名}` 的制品失败：{错误:?}。\
             制品是装配产物（不入库），先跑：python3 构建装配/上线切换/构建制品.py --预构建"
        )
    })
}
