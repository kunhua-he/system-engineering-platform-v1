/// 一条步骤读数。
#[derive(Debug, Clone)]
pub struct 步骤读数 {
    pub 名字: String,
    /// 步骤种类：`能力` / `通知`。通知步骤的 `能力编号` 恒 0（通知号另记在 `名` 与说明里）。
    pub 扩展种类: String,
    pub 能力编号: u32,
    /// 适配器当场取到的能力名；`None` = 这个号没被任何已装载声明认领。
    pub 能力名: Option<String>,
    /// **这次调用**的结果：`成功` / `失败`（平台那一侧的结果，不是案例判定）。
    ///
    /// 与 [`步骤读数::符合期望`] 分开是**必须的**：「调 1101 期望它失败」这条案例里，
    /// 调用结果是 `失败`、判定结果是 `符合期望`。合成一个字段，读者会把
    /// 「案例通过」误读成「能力可用」——那正是假绿。
    pub 调用结果: String,
    /// 这一步是否符合 `期望.json` 写的那一条。
    pub 符合期望: bool,
    pub 死在哪一层: Option<String>,
    pub 死在哪一步: Option<String>,
    pub 错误码: Option<错误码登记>,
    pub 耗时微秒: u128,
    /// 一句话读数（人读；机器只读上面那些字段）。
    pub 说明: String,
}

/// 一个案例一行。
#[derive(Debug, Clone)]
pub struct 回执 {
    pub 提交哈希: String,
    pub 工作区是否干净: bool,
    pub 案例名: String,
    pub 调用结局: String,
    pub 死在哪一层: Option<String>,
    pub 死在哪一步: Option<String>,
    pub 错误码: Option<错误码登记>,
    pub 耗时微秒: u128,
    pub 跑的时间: String,
    pub 说明: String,
    pub 案例步骤: Vec<步骤读数>,
}

impl 回执 {
    /// 一行 JSON（**没有换行**，追加时补）。
    pub fn 写成一行(&self) -> String {
        let mut 文本缓冲 = String::from("{");
        文本缓冲.push_str("\"提交哈希\":");
        crate::最小JSON::写串(&mut 文本缓冲, &self.提交哈希);
        文本缓冲.push_str(&format!(",\"工作区是否干净\":{}", self.工作区是否干净));
        文本缓冲.push_str(",\"案例名\":");
        crate::最小JSON::写串(&mut 文本缓冲, &self.案例名);
        文本缓冲.push_str(",\"结果\":");
        crate::最小JSON::写串(&mut 文本缓冲, &self.调用结局);
        文本缓冲.push_str(",\"死在哪一层\":");
        写可选串(&mut 文本缓冲, self.死在哪一层.as_deref());
        文本缓冲.push_str(",\"死在哪一步\":");
        写可选串(&mut 文本缓冲, self.死在哪一步.as_deref());
        文本缓冲.push_str(",\"错误码\":");
        match &self.错误码 {
            Some(错误码) => 文本缓冲.push_str(&错误码.转JSON文本()),
            None => 文本缓冲.push_str("null"),
        }
        文本缓冲.push_str(&format!(",\"耗时微秒\":{}", self.耗时微秒));
        文本缓冲.push_str(",\"跑的时间\":");
        crate::最小JSON::写串(&mut 文本缓冲, &self.跑的时间);
        文本缓冲.push_str(",\"说明\":");
        crate::最小JSON::写串(&mut 文本缓冲, &self.说明);
        文本缓冲.push_str(",\"步骤\":[");
        for (序号, 步序) in self.案例步骤.iter().enumerate() {
            if 序号 > 0 {
                文本缓冲.push(',');
            }
            文本缓冲.push('{');
            文本缓冲.push_str("\"名\":");
            crate::最小JSON::写串(&mut 文本缓冲, &步序.名字);
            文本缓冲.push_str(",\"种类\":");
            crate::最小JSON::写串(&mut 文本缓冲, &步序.扩展种类);
            文本缓冲.push_str(&format!(",\"能力编号\":{},\"能力名\":", 步序.能力编号));
            写可选串(&mut 文本缓冲, 步序.能力名.as_deref());
            文本缓冲.push_str(",\"调用结果\":");
            crate::最小JSON::写串(&mut 文本缓冲, &步序.调用结果);
            文本缓冲.push_str(&format!(",\"符合期望\":{}", 步序.符合期望));
            文本缓冲.push_str(",\"死在哪一层\":");
            写可选串(&mut 文本缓冲, 步序.死在哪一层.as_deref());
            文本缓冲.push_str(",\"死在哪一步\":");
            写可选串(&mut 文本缓冲, 步序.死在哪一步.as_deref());
            文本缓冲.push_str(",\"错误码\":");
            match &步序.错误码 {
                Some(错误码) => 文本缓冲.push_str(&错误码.转JSON文本()),
                None => 文本缓冲.push_str("null"),
            }
            文本缓冲.push_str(&format!(",\"耗时微秒\":{},\"说明\":", 步序.耗时微秒));
            crate::最小JSON::写串(&mut 文本缓冲, &步序.说明);
            文本缓冲.push('}');
        }
        文本缓冲.push_str("]}");
        文本缓冲
    }
}

fn 写可选串(文本缓冲: &mut String, 待处理值: Option<&str>) {
    match 待处理值 {
        Some(源文本) => crate::最小JSON::写串(文本缓冲, 源文本),
        None => 文本缓冲.push_str("null"),
    }
}

/// 锁件路径：与回执同目录的 `运行回执.jsonl.锁`。
///
/// ★ 锁必须挂在**不换 inode 的那一份件**上 —— 回执的写回是 `rename`，锁若挂在回执自身，
/// 换完 inode 就锁不住后到的写者（理由见文件头第 1 条）。
fn 锁件路径(路径: &Path) -> PathBuf {
    路径.with_extension("jsonl.锁")
}

// ★ FFI 与「有界等待取锁」搬进子件（`src/回执/独占锁.rs`）：本件只留声明，
//   临界区一律经 `独占锁::取锁(&锁件路径, 等待毫秒)`，不再有 `Option` 那种「拿不到就降级」的形状。
#[cfg(unix)]
#[path = "回执/独占锁.rs"]
mod 独占锁;

/// 非 unix 没有 `flock` ⇒ **明确失败**（早先回 `None` 让调用方退回无锁追加，那正是拼坏行的来源）。
#[cfg(not(unix))]
mod 独占锁 {
    use std::path::Path;

    pub struct 锁件;

    pub fn 取锁(路径: &Path, _等待毫秒: u64) -> Result<锁件, String> {
        Err(format!(
            "本平台没有 flock（{}）⇒ 回执的并发安全无从保证，拒绝无锁写",
            路径.display()
        ))
    }
}

/// 取锁最多等多久（毫秒）。★ 有界是硬口径：持锁者崩在临界区时，等待方**自身**回失败，
/// 不许把整条跑案例的进程挂死在这里（`独占锁::取锁` 用 `LOCK_NB` 轮询实现）。
pub const 锁等待毫秒: u64 = 2000;

/// **追加一行**。追加不是覆盖：回执是历史，抹掉历史就没法判「回执是不是旧的」。
///
/// 并发安全的口径见文件头：持锁 ⇒ 读全文 ⇒ 追加 ⇒ `rename`。`rename` 之前盘上一直是旧件，
/// 之后是「旧件 + 这一条新行」—— **中间没有半行状态**。拿不到锁 ⇒ 回明确错误、**这条不写**。
pub fn 追加一行(路径: &Path, 源码行: &str) -> Result<(), String> {
    追加一行带等待(路径, 源码行, 锁等待毫秒)
}

/// [`追加一行`] 的本体：等待毫秒由调用方给（单元测试要能把「等多久」压到毫秒级验有界）。
fn 追加一行带等待(路径: &Path, 源码行: &str, 等待毫秒: u64) -> Result<(), String> {
    if let Some(父目录) = 路径.parent() {
        std::fs::create_dir_all(父目录).map_err(|错误| format!("建不了 {}：{错误}", 父目录.display()))?;
    }
    // ★ 锁凭据活到函数末 ⇒ 「读全文 → 追加 → rename」整段都在锁里（作用域结束放锁）。
    let _锁凭据 = 独占锁::取锁(&锁件路径(路径), 等待毫秒)
        .map_err(|失败原因| format!("回执没写：{失败原因}"))?;
    let mut 原文 = match std::fs::read(路径) {
        Ok(原文) => 原文,
        Err(错误) if 错误.kind() == std::io::ErrorKind::NotFound => Vec::new(),
        Err(错误) => return Err(format!("读不了 {}：{错误}", 路径.display())),
    };
    // 上一次坏写留下的残尾先封口：不然新行会黏在它后面，把一条好行也一起毁掉。
    if !原文.is_empty() && !原文.ends_with(b"\n") {
        原文.push(b'\n');
    }
    原文.extend_from_slice(源码行.as_bytes());
    原文.push(b'\n');
    let 临时路径 = 路径.with_extension("jsonl.写入中");
    std::fs::write(&临时路径, &原文)
        .map_err(|错误| format!("写不进临时件 {}：{错误}", 临时路径.display()))?;
    std::fs::rename(&临时路径, 路径).map_err(|错误| {
        let _ = std::fs::remove_file(&临时路径);
        format!("换不进 {}：{错误}", 路径.display())
    })
}

/// 回执里最多留最近多少次运行（一次运行 = 同一次跑案例写下的那一组行）。
pub const 回执运行上限: usize = 500;

/// 从一行回执里取一个**字串字段**的值（回执的形状由 [`回执::写成一行`] 固定，故按锚串取即可）。
fn 取字串字段(源码行: &str, 字段名: &str) -> Option<String> {
    let 锚文本 = format!("\"{字段名}\":\"");
    let 锚位 = 源码行.find(&锚文本)?;
    let 余文 = &源码行[锚位 + 锚文本.len()..];
    let 尾位 = 余文.find('"')?;
    Some(余文[..尾位].to_owned())
}

/// 一行的「运行键」＝ `提交哈希|跑的时间`：一次运行里每个案例各写一行，键相同。
///
/// 取不到这两个字段（能解析、但不是本件写的形状）⇒ `None` ⇒ 它**自成一组**，不与任何一次运行
/// 混在一起，免得它跟着某一组一起被删或一起被留。
fn 取运行键(源码行: &str) -> Option<String> {
    let 提交值 = 取字串字段(源码行, "提交哈希")?;
    let 时刻值 = 取字串字段(源码行, "跑的时间")?;
    Some(format!("{提交值}|{时刻值}"))
}

/// 按「运行」分组算**该裁掉多少行**（0 = 没到界）。
///
/// 分组键 = [`取运行键`]（`提交哈希|跑的时间`），按**连续相同**归组；★ 边界：同一次运行里每
/// 一个案例写一行、`跑的时间` 一次运行只算一次 ⇒ 同一秒内并发起来的两次运行、且提交相同 ⇒
/// **键相同、并成一组**。这条边界只让「留 500 组」比「留 500 次运行」更保守（留得更多、不更少），
/// 不会删掉本该留的那次运行；要精确到「次」必须给回执加一个独立运行号 —— 那是改记录格式、
/// 连带改网关读方与门禁读方，不在「收敛有界」这条债的范围里，故按现状记明边界、不凭空扩大。
fn 该删行数(可用行表: &[String]) -> usize {
    let mut 组起点表: Vec<usize> = Vec::new();
    let mut 上一组键: Option<String> = None;
    for (行号, 源码行) in 可用行表.iter().enumerate() {
        let 本组键 = 取运行键(源码行).unwrap_or_else(|| format!("无运行键{行号}"));
        if 上一组键.as_deref() != Some(本组键.as_str()) {
            组起点表.push(行号);
            上一组键 = Some(本组键);
        }
    }
    // 删掉行数 = 去掉最旧那几组之后，第一个留下的行在 `可用行表` 里的下标（也就是被裁掉的好行数）。
    组起点表
        .len()
        .checked_sub(回执运行上限)
        .map_or(0, |超出组数| 组起点表[超出组数])
}

/// 收敛的读数：两个数**分开报** —— 坏行不许静默。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 收敛读数 {
    /// 被「只留最近 N 次运行」裁掉的好行数（0 = 没到界、一条好行都没删）。
    pub 删掉行数: usize,
    /// 拼不上而跳过的行数。**空行也算**：它同样不是一条回执（存量坏行里就有一批空行）。
    pub 跳过坏行: usize,
}

impl 收敛读数 {
    /// 什么都没发生（件不在 / 没到界且没有坏行）。
    fn 无改动() -> Self {
        Self { 删掉行数: 0, 跳过坏行: 0 }
    }
}

/// 逐行容错读回执 ⇒ （可用行的原文 · 跳过坏行数）。
///
/// 「拼得上」只有一个口径：[`crate::最小JSON::解析JSON值`] 解得开 —— 与写方
/// [`回执::写成一行`] 对得上，也就与网关那一侧（`工具响应_案例.rs`）的读方同一条判据。
/// **一行坏不许毁掉整份读数**：跳过、计数、继续。
pub fn 逐行读回执(原文文本: &str) -> (Vec<String>, usize) {
    let mut 可用行表 = Vec::new();
    let mut 跳过坏行 = 0usize;
    for 源码行 in 原文文本.lines() {
        if 源码行.trim().is_empty() || crate::最小JSON::解析JSON值(源码行).is_err() {
            跳过坏行 += 1;
            continue;
        }
        可用行表.push(源码行.to_owned());
    }
    (可用行表, 跳过坏行)
}

/// 收敛回执：**只留最近 [`回执运行上限`] 次运行**，顺带把拼不上的行清掉 ⇒ 读数。
///
/// # 为什么按「运行」整组留，不按行数截
///
/// 两个读方要的都是**完整的一次运行**：门禁读 `tail -n 1`（最新那次运行的最后一行，见
/// `测试验证/测试案例/装门禁.sh`）；网关的 `POST /接口/运维/案例` 读「这次新落的那几行」。
/// 按行数截断会把某次运行切成前后两截 —— 界是收敛了，读数却是错的。
///
/// # 写回是「持锁 + 原子替换」
///
/// 同目录先写 `<件名>.收敛中` 再 `rename` 到位：半行、半份都不能留在原路径上 ——
/// 下一次 [`追加一行`] 会接在坏行后面，坏行就成了永久的噪声。整段「读 → 算 → 换」都在
/// [`独占锁::取`] 给的锁里，故不会踩掉并发追加进来的行。
///
/// # 拿不到锁：不重写，但「该裁却裁不了」明确失败
///
/// 没有锁的整件替换会把并发追加的行一起踩掉 ⇒ 一行都不重写。没到界时照旧把坏行数报出来；
/// **已到界（该裁行数 > 0）时回明确错误** —— 否则回执件会无限长大而没人知道。
pub fn 收敛回执(路径: &Path) -> Result<收敛读数, String> {
    收敛回执带等待(路径, 锁等待毫秒)
}

/// [`收敛回执`] 的本体：等待毫秒由调用方给（单元测试要能验「等多久就失败」）。
fn 收敛回执带等待(路径: &Path, 等待毫秒: u64) -> Result<收敛读数, String> {
    // 回执件不在 = 从没跑过案例 ⇒ 没有要收敛的东西（不是错误，也不建空件）。
    if !路径.is_file() {
        return Ok(收敛读数::无改动());
    }
    let 锁结果 = 独占锁::取锁(&锁件路径(路径), 等待毫秒);
    let _锁凭据 = match 锁结果 {
        Ok(凭据) => 凭据,
        Err(失败原因) => {
            // 拿不到锁 ⇒ 一个字都不重写（无锁的整件替换会把并发追加的行整条踩掉）；
            // **但「该裁却裁不了」必须明确失败** —— 静默不收敛会让回执件无限长大，那是另一种假绿。
            let 原文文本 = std::fs::read_to_string(路径)
                .map_err(|错误| format!("读不了 {}：{错误}", 路径.display()))?;
            let (可用行表, 跳过坏行) = 逐行读回执(&原文文本);
            let 待裁行数 = 该删行数(&可用行表);
            if 待裁行数 > 0 {
                return Err(format!("回执没收敛：{失败原因}（已到界，需裁 {待裁行数} 行）"));
            }
            return Ok(收敛读数 { 删掉行数: 0, 跳过坏行 });
        }
    };
    // ★ 读盘必须在持锁之后：先读后锁会把「锁住之前并发追加的行」写丢。
    let 原文文本 = std::fs::read_to_string(路径)
        .map_err(|错误| format!("读不了 {}：{错误}", 路径.display()))?;
    let (可用行表, 跳过坏行) = 逐行读回执(&原文文本);
    let 删掉行数 = 该删行数(&可用行表);
    // 没到界且没有坏行 ⇒ **一个字节都不动**（不许顺手「规范化」把旧行重排）。
    if 删掉行数 == 0 && 跳过坏行 == 0 {
        return Ok(收敛读数::无改动());
    }
    let mut 新文本 = 可用行表[删掉行数..].join("\n");
    if !新文本.is_empty() {
        新文本.push('\n');
    }
    let 临时路径 = 路径.with_extension("jsonl.收敛中");
    std::fs::write(&临时路径, 新文本.as_bytes())
        .map_err(|错误| format!("写不进收敛临时件 {}：{错误}", 临时路径.display()))?;
    std::fs::rename(&临时路径, 路径).map_err(|错误| {
        let _ = std::fs::remove_file(&临时路径);
        format!("换不进 {}：{错误}", 路径.display())
    })?;
    Ok(收敛读数 { 删掉行数, 跳过坏行 })
}

/// `git rev-parse HEAD` 的**完整**值。取不到就报错——**不许拿一个空串或短哈希顶上**。
pub fn 提交哈希(仓根: &Path) -> Result<String, String> {
    let 文本缓冲 = Command::new("git")
        .arg("-C")
        .arg(仓根)
        .args(["rev-parse", "HEAD"])
        .output()
        .map_err(|错误| format!("跑不了 git rev-parse：{错误}"))?;
    if !文本缓冲.status.success() {
        return Err(format!(
            "git rev-parse HEAD 失败：{}",
            String::from_utf8_lossy(&文本缓冲.stderr).trim()
        ));
    }
    let 哈希值 = String::from_utf8_lossy(&文本缓冲.stdout).trim().to_owned();
    if 哈希值.len() < 40 {
        return Err(format!("提交哈希不是完整值（{} 位）：`{哈希值}`", 哈希值.len()));
    }
    Ok(哈希值)
}

/// 工作区是否干净：除**回执自身**之外的改动数为 0。
pub fn 工作区干净(仓根: &Path) -> Result<bool, String> {
    let 文本缓冲 = Command::new("git")
        .arg("-C")
        .arg(仓根)
        .args(["status", "--porcelain", "--"])
        .arg(format!(":(exclude){回执相对路径}"))
        .output()
        .map_err(|错误| format!("跑不了 git status：{错误}"))?;
    if !文本缓冲.status.success() {
        return Err(format!(
            "git status 失败：{}",
            String::from_utf8_lossy(&文本缓冲.stderr).trim()
        ));
    }
    Ok(String::from_utf8_lossy(&文本缓冲.stdout).trim().is_empty())
}

/// UTC 的 `YYYY-MM-DDTHH:MM:SSZ`。自身算，不调外部程序（少一个环境依赖）。
pub fn 现在UTC() -> String {
    let 纪元秒数 = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|时长| 时长.as_secs() as i64)
        .unwrap_or(0);
    let 天数 = 纪元秒数.div_euclid(86_400);
    let 日内 = 纪元秒数.rem_euclid(86_400);
    let (年份, 月份, 日序号) = 民用日期(天数);
    format!(
        "{年份:04}-{月份:02}-{日序号:02}T{:02}:{:02}:{:02}Z",
        日内 / 3600,
        (日内 % 3600) / 60,
        日内 % 60
    )
}

/// 天数（1970-01-01 起）→ 公历日期。Howard Hinnant 的 `civil_from_days`，整数运算，无外部依赖。
fn 民用日期(天数: i64) -> (i64, u32, u32) {
    let 偏移天数 = 天数 + 719_468;
    let 纪元 = if 偏移天数 >= 0 { 偏移天数 } else { 偏移天数 - 146_096 } / 146_097;
    let 纪内 = (偏移天数 - 纪元 * 146_097) as u64;
    let 年内 = (纪内 - 纪内 / 1460 + 纪内 / 36_524 - 纪内 / 146_096) / 365;
    let 年份 = 年内 as i64 + 纪元 * 400;
    let 日年 = 纪内 - (365 * 年内 + 年内 / 4 - 年内 / 100);
    let 月内 = (5 * 日年 + 2) / 153;
    let 日序号 = (日年 - (153 * 月内 + 2) / 5 + 1) as u32;
    let 月份 = if 月内 < 10 { 月内 + 3 } else { 月内 - 9 } as u32;
    (if 月份 <= 2 { 年份 + 1 } else { 年份 }, 月份, 日序号)
}

