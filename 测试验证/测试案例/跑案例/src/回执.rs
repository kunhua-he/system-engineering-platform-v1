/// 非 unix 没有 `flock` ⇒ **明确失败**（早先回 `None` 让调用方退回无锁追加，那正是拼坏行的来源）。
#[cfg(not(unix))]
mod 独占锁 {
    use std::path::Path;

    pub struct 锁件;

    pub fn 取锁(路径: &Path, _等待毫秒: u64) -> Result<锁件, String> {
        Err(format!(
            "本平台没有 flock（{}）⇒ 回执的并发安全无从保证，拒绝无锁写",
            路径.display()
        ))
    }
}

