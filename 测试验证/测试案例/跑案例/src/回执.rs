//! 运行回执 —— **追加一行** JSON 到 `测试验证/测试案例/运行回执.jsonl`。
//!
//! # 为什么必须绑提交哈希
//!
//! 照抄 `项目文档/设计文档/判据的可信性.md` 第三节「假绿的六种来源」第 4 条
//! （「空集被算成通过」）与它的上位结论：
//!
//! > **回执必须绑提交哈希** —— 否则「回执是旧的」和「代码坏了」不可区分。
//!
//! 具体到本件：回执是**上一次跑**的读数。没有提交哈希，一份旧回执与一份新回执长得一模一样，
//! 于是「没跑过」会被当成「跑过了且通过」——那就是假绿。绑了哈希之后，门禁能直接判
//! 「这份回执说的是不是**这一个**提交」，`装门禁.sh` 就是这么判的。
//!
//! # 三个字段的口径
//!
//! - `提交哈希`：`git rev-parse HEAD` 的**完整**值（40 位十六进制，不截断）。
//! - `工作区是否干净`：`git status --porcelain` 除**回执自身**之外是否为空。
//!   排除回执自身是因为**每跑一次就追加一行 ⇒ 它自身永远是脏的**，不排除就恒为 `false`，
//!   那个字段就永远没有信息量。
//! - `跑的时间`：UTC 的 `YYYY-MM-DDTHH:MM:SSZ`（**不是本地时间**：跨机器比读数时本地时区是噪声）。
//!
//! # 并发写：持锁 + 整次原子替换
//!
//! 回执是**多进程同时追加**的（一次跑案例起一个进程，构建装配还会并发起多份）。早先的追加是
//! 「先写正文、再写换行」两次 `write_all` 且**没有任何互斥** —— 两个写者的字节交错进同一条行里，
//! 盘上因此攒出过 52 条拼不上的行（截断的 JSON + 空行）。两条措施现在一起上：
//!
//! 1. **互斥**：同目录的 `运行回执.jsonl.锁` 上 `flock(LOCK_EX|LOCK_NB)` 轮询。锁挂在**锁件**而不是
//!    回执自身 —— 回执的写回是「临时件 + `rename`」，`rename` 之后回执换了 inode，挂在旧 inode 上的
//!    锁就锁不住后到的写者。`flock` 是内核原语：进程退出即释放，不留死锁。
//! 2. **整次写入**：持锁后读全文 → 追加一条 → 写 `运行回执.jsonl.写入中` → `rename` 到位。
//!    `rename` 是原子的 ⇒ 盘上永远是「整条行在」或「整条行不在」，**没有半行状态**。
//! 3. **同一把锁**：[`收敛回执`] 与 [`追加一行`] 用**同一个**锁件（[`锁件路径`] 一处算），
//!    于是「整件重写」与「追加一行」互斥 —— 否则收敛的 `rename` 会把并发追加的行整条踩掉。
//!
//! **等待有界、失败明确**（2026-10-29 修）：取锁最多等 [`锁等待毫秒`]，超时就回
//! 「锁被占用」的明确错误，**绝不退回无锁追加**。早先的降级路（拿不到锁就单 `write` 追加）看着
//! 「至少写进去了」，实际是在另一个写者持有临界区时插进去 ⇒ 拼坏行正是它造出来的；而裸
//! `flock(LOCK_EX)`（无 `LOCK_NB`）会在持锁者崩在临界区时把整条跑案例的进程无限期挂住。
//! 现在的取舍：**回执宁可没写（调用方看到非 0 退出码），也不许两个写者同时写。**
//!
//! # 读：逐行容错，坏行不静默
//!
//! 读方不吃「一行坏 = 整份报错」：拼不上的行**跳过并计数**（[`收敛读数::跳过坏行`]），余下的
//! 可用行照旧参与收敛与读数。跳过几条必须报得出来 —— 静默跳过就是假绿。

