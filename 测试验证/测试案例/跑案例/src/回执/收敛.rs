use std::path::Path;

use super::独占锁;
use super::锁与追加::{锁件路径, 锁等待毫秒};

/// 回执里最多留最近多少次运行（一次运行 = 同一次跑案例写下的那一组行）。
pub const 回执运行上限: usize = 500;

/// 从一行回执里取一个**字串字段**的值（回执的形状由 [`回执::写成一行`] 固定，故按锚串取即可）。
pub(super) fn 取字串字段(源码行: &str, 字段名: &str) -> Option<String> {
    let 锚文本 = format!("\"{字段名}\":\"");
    let 锚位 = 源码行.find(&锚文本)?;
    let 余文 = &源码行[锚位 + 锚文本.len()..];
    let 尾位 = 余文.find('"')?;
    Some(余文[..尾位].to_owned())
}

/// 一行的「运行键」＝ `提交哈希|跑的时间`：一次运行里每个案例各写一行，键相同。
///
/// 取不到这两个字段（能解析、但不是本件写的形状）⇒ `None` ⇒ 它**自成一组**，不与任何一次运行
/// 混在一起，免得它跟着某一组一起被删或一起被留。
pub(super) fn 取运行键(源码行: &str) -> Option<String> {
    let 提交值 = 取字串字段(源码行, "提交哈希")?;
    let 时刻值 = 取字串字段(源码行, "跑的时间")?;
    Some(format!("{提交值}|{时刻值}"))
}

/// 按「运行」分组算**该裁掉多少行**（0 = 没到界）。
///
/// 分组键 = [`取运行键`]（`提交哈希|跑的时间`），按**连续相同**归组；★ 边界：同一次运行里每
/// 一个案例写一行、`跑的时间` 一次运行只算一次 ⇒ 同一秒内并发起来的两次运行、且提交相同 ⇒
/// **键相同、并成一组**。这条边界只让「留 500 组」比「留 500 次运行」更保守（留得更多、不更少），
/// 不会删掉本该留的那次运行；要精确到「次」必须给回执加一个独立运行号 —— 那是改记录格式、
/// 连带改网关读方与门禁读方，不在「收敛有界」这条债的范围里，故按现状记明边界、不凭空扩大。
pub(super) fn 该删行数(可用行表: &[String]) -> usize {
    let mut 组起点表: Vec<usize> = Vec::new();
    let mut 上一组键: Option<String> = None;
    for (行号, 源码行) in 可用行表.iter().enumerate() {
        let 本组键 = 取运行键(源码行).unwrap_or_else(|| format!("无运行键{行号}"));
        if 上一组键.as_deref() != Some(本组键.as_str()) {
            组起点表.push(行号);
            上一组键 = Some(本组键);
        }
    }
    // 删掉行数 = 去掉最旧那几组之后，第一个留下的行在 `可用行表` 里的下标（也就是被裁掉的好行数）。
    组起点表
        .len()
        .checked_sub(回执运行上限)
        .map_or(0, |超出组数| 组起点表[超出组数])
}

/// 收敛的读数：两个数**分开报** —— 坏行不许静默。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 收敛读数 {
    /// 被「只留最近 N 次运行」裁掉的好行数（0 = 没到界、一条好行都没删）。
    pub 删掉行数: usize,
    /// 拼不上而跳过的行数。**空行也算**：它同样不是一条回执（存量坏行里就有一批空行）。
    pub 跳过坏行: usize,
}

impl 收敛读数 {
    /// 什么都没发生（件不在 / 没到界且没有坏行）。
    fn 无改动() -> Self {
        Self {
            删掉行数: 0,
            跳过坏行: 0,
        }
    }
}

/// 逐行容错读回执 ⇒ （可用行的原文 · 跳过坏行数）。
///
/// 「拼得上」只有一个口径：[`crate::最小JSON::解析JSON值`] 解得开 —— 与写方
/// [`回执::写成一行`] 对得上，也就与网关那一侧（`工具响应_案例.rs`）的读方同一条判据。
/// **一行坏不许毁掉整份读数**：跳过、计数、继续。
pub fn 逐行读回执(原文文本: &str) -> (Vec<String>, usize) {
    let mut 可用行表 = Vec::new();
    let mut 跳过坏行 = 0usize;
    for 源码行 in 原文文本.lines() {
        if 源码行.trim().is_empty() || crate::最小JSON::解析JSON值(源码行).is_err() {
            跳过坏行 += 1;
            continue;
        }
        可用行表.push(源码行.to_owned());
    }
    (可用行表, 跳过坏行)
}

/// 收敛回执：**只留最近 [`回执运行上限`] 次运行**，顺带把拼不上的行清掉 ⇒ 读数。
///
/// # 为什么按「运行」整组留，不按行数截
///
/// 两个读方要的都是**完整的一次运行**：门禁读 `tail -n 1`（最新那次运行的最后一行，见
/// `测试验证/测试案例/装门禁.sh`）；网关的 `POST /接口/运维/案例` 读「这次新落的那几行」。
/// 按行数截断会把某次运行切成前后两截 —— 界是收敛了，读数却是错的。
///
/// # 写回是「持锁 + 原子替换」
///
/// 同目录先写 `<件名>.收敛中` 再 `rename` 到位：半行、半份都不能留在原路径上 ——
/// 下一次 [`追加一行`] 会接在坏行后面，坏行就成了永久的噪声。整段「读 → 算 → 换」都在
/// [`独占锁::取`] 给的锁里，故不会踩掉并发追加进来的行。
///
/// # 拿不到锁：不重写，但「该裁却裁不了」明确失败
///
/// 没有锁的整件替换会把并发追加的行一起踩掉 ⇒ 一行都不重写。没到界时照旧把坏行数报出来；
/// **已到界（该裁行数 > 0）时回明确错误** —— 否则回执件会无限长大而没人知道。
pub fn 收敛回执(路径: &Path) -> Result<收敛读数, String> {
    收敛回执带等待(路径, 锁等待毫秒)
}

/// [`收敛回执`] 的本体：等待毫秒由调用方给（单元测试要能验「等多久就失败」）。
pub(super) fn 收敛回执带等待(
    路径: &Path, 等待毫秒: u64
) -> Result<收敛读数, String> {
    // 回执件不在 = 从没跑过案例 ⇒ 没有要收敛的东西（不是错误，也不建空件）。
    if !路径.is_file() {
        return Ok(收敛读数::无改动());
    }
    let 锁结果 = 独占锁::取锁(&锁件路径(路径), 等待毫秒);
    let _锁凭据 = match 锁结果 {
        Ok(凭据) => 凭据,
        Err(失败原因) => {
            // 拿不到锁 ⇒ 一个字都不重写（无锁的整件替换会把并发追加的行整条踩掉）；
            // **但「该裁却裁不了」必须明确失败** —— 静默不收敛会让回执件无限长大，那是另一种假绿。
            let 原文文本 = std::fs::read_to_string(路径)
                .map_err(|错误| format!("读不了 {}：{错误}", 路径.display()))?;
            let (可用行表, 跳过坏行) = 逐行读回执(&原文文本);
            let 待裁行数 = 该删行数(&可用行表);
            if 待裁行数 > 0 {
                return Err(format!(
                    "回执没收敛：{失败原因}（已到界，需裁 {待裁行数} 行）"
                ));
            }
            return Ok(收敛读数 {
                删掉行数: 0,
                跳过坏行,
            });
        }
    };
    // ★ 读盘必须在持锁之后：先读后锁会把「锁住之前并发追加的行」写丢。
    let 原文文本 = std::fs::read_to_string(路径)
        .map_err(|错误| format!("读不了 {}：{错误}", 路径.display()))?;
    let (可用行表, 跳过坏行) = 逐行读回执(&原文文本);
    let 删掉行数 = 该删行数(&可用行表);
    // 没到界且没有坏行 ⇒ **一个字节都不动**（不许顺手「规范化」把旧行重排）。
    if 删掉行数 == 0 && 跳过坏行 == 0 {
        return Ok(收敛读数::无改动());
    }
    let mut 新文本 = 可用行表[删掉行数..].join("\n");
    if !新文本.is_empty() {
        新文本.push('\n');
    }
    let 临时路径 = 路径.with_extension("jsonl.收敛中");
    std::fs::write(&临时路径, 新文本.as_bytes())
        .map_err(|错误| format!("写不进收敛临时件 {}：{错误}", 临时路径.display()))?;
    std::fs::rename(&临时路径, 路径).map_err(|错误| {
        let _ = std::fs::remove_file(&临时路径);
        format!("换不进 {}：{错误}", 路径.display())
    })?;
    Ok(收敛读数 {
        删掉行数, 跳过坏行
    })
}
