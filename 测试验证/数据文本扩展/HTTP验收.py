"""数据与文本扩展真实验收；复用原量级驱动，不另开启动和装卸链。"""
import concurrent.futures
import json
from pathlib import Path
import zlib


def 核验数据文本(请求, 检查, 实例表):
    from 测试验证.扩展量级.槽值 import 解槽值 as 解值

    def 调用(网关实例,编号,参数表,预期错误=None):
        状态码,正文=请求(网关实例,'/接口/调用',dict(编号=编号,值=[dict(类型标签=4,值=参数文本) for 参数文本 in 参数表]))
        if 预期错误 is not None:
            检查(not 正文.get('成功') and 正文.get('错误',{}).get('码')==预期错误,'数据文本错误原码返回',正文)
            return None
        assert 状态码==200 and 正文.get('成功'),(编号,状态码,正文)
        assert len(正文['值'])==1,正文
        return 解值(正文['值'][0])

    for 网关实例 in 实例表:
        样本数据={'文字':'中文🙂\0 /','金额':123456789012345678901234567890,'列表':[None,False,0,''],'a/b':{'~':'测试'}}
        原文=json.dumps(样本数据,ensure_ascii=False)
        for 编号 in (5201,7961): 检查(json.loads(调用(网关实例,编号,[原文]))==样本数据,'JSON规范化与独立标准库对照')
        for 编号 in (5202,7962):
            for 路径,期望 in [('/金额','123456789012345678901234567890'),('/列表/0','null'),('/列表/1','false'),('/列表/2','0'),('/列表/3','""')]:
                检查(调用(网关实例,编号,[原文,路径])==期望,'JSON大数空值假值及零不混淆')
            检查(json.loads(调用(网关实例,编号,[原文,'']))==样本数据,'空JSON指针取根')
        检查(调用(网关实例,5203,[原文,'/a~1b/~0'])=='测试','JSON指针转义')
        检查(调用(网关实例,5203,[原文,'/文字'])==样本数据['文字'],'JSON取文本保留Unicode及NUL')
        for 样本值 in ({'$serde_json::private::Number':'123'},{'嵌套':[{'$serde_json::private::Number':'00123'}]}, {'$serde_json::private::RawValue':'文本'}):
            样本文=json.dumps(样本值,ensure_ascii=False)
            检查(json.loads(调用(网关实例,7961,[样本文]))==样本值,'引擎私有同名键仍是普通对象')
        检查(json.loads(调用(网关实例,5201,['{"重复":1,"重复":2}']))=={'重复':2},'重复键明确取最后值')
        for 编号 in (5204,7966):
            for 原值,类型名称,成员数量 in [(None,'空值',0),(False,'逻辑',0),(0,'数值',0),('','文本',0),([],'列表',0),({'键':1},'对象',1)]:
                结构摘要=调用(网关实例,编号,[json.dumps(原值,ensure_ascii=False)])
                检查(结构摘要['类型名称']==类型名称 and 结构摘要['成员数量']==成员数量 and json.loads(结构摘要['规范文本'])==原值,'固定结构摘要字段保真',结构摘要)
        for 编号 in (5201,7961):
            检查(len(调用(网关实例,编号,['"'+'x'*65534+'"']).encode())==65536,'JSON精确输入上界')
            调用(网关实例,编号,['"'+'x'*65535+'"'],5204)
            调用(网关实例,编号,['['*65+']'*65],5204)
            调用(网关实例,编号,['{'],5201)
        for 编号 in (5202,7962):
            调用(网关实例,编号,[原文,'/不存在'],5202)
            调用(网关实例,编号,[原文,'/~2'],5201)
            调用(网关实例,编号,[原文,'/'+'a'*4096],5204)
        调用(网关实例,5203,[原文,'/金额'],5203)
        for 编号 in (4401,7963):
            检查(调用(网关实例,编号,[r'\p{Han}+','abc中文🙂测试'])==['中文','测试'],'Unicode正则完整匹配')
            检查(调用(网关实例,编号,['z','abc'])==[],'正则无命中返回空列表')
            检查(调用(网关实例,编号,['',''])==[''],'正则空命中与空列表不同')
            调用(网关实例,编号,['(?=x)','x'],4402)
            调用(网关实例,编号,['a','a'*1001],4403)
            调用(网关实例,编号,['a{100000000}','a'],4403)
            调用(网关实例,编号,['a'*4097,'a'],4403)
            调用(网关实例,编号,['a','a'*65537],4403)
        for 编号 in (4402,7964):
            检查(调用(网关实例,编号,[r'\d+','a12中🙂\0','$1'])=='a$1中🙂\0','替换字面量不展开捕获')
            检查(调用(网关实例,编号,['z','abc','x'])=='abc','无命中替换原样返回')
            调用(网关实例,编号,['a','aa','x'*65536],4403)
        for 编号 in (4403,7965):
            检查(调用(网关实例,编号,[',','a,,b,'])==['a','','b',''],'正则分割保留空片段')
            检查(调用(网关实例,编号,['','ab'])==['','a','b',''],'空模式分割语义')
            调用(网关实例,编号,[',',','*1000],4403)
        文本JSON=json.dumps({'文字':'编号123，订单456'},ensure_ascii=False)
        检查(调用(网关实例,7967,[文本JSON,'/文字',r'\d+'])==['123','456'],'JSON取文本后跨库正则提取')
        调用(网关实例,7967,[文本JSON,'/文字','(?=x)'],4402)
        调用(网关实例,7967,[json.dumps({'文字':'1'*1001}),'/文字','1'],4403)
        调用(网关实例,7967,[文本JSON,'/不存在','1'],5202)
        检查(json.loads(zlib.decompress(bytes.fromhex(调用(网关实例,7968,[原文]))))==样本数据,'JSON规范化后跨库压缩对照')
        for 编号 in (5201,5202,5203,5204,4401,4402,4403,7961,7962,7963,7964,7965,7966,7967,7968):
            契约路径表=list((Path(__file__).resolve().parents[2]/'扩展根目录').glob('*/*/能力声明/%s.json'%编号))
            assert len(契约路径表)==1,契约路径表
            参数条数=len(json.loads(契约路径表[0].read_text())['参数表'])
            for 参数槽 in ([],[dict(类型标签=1,值=7)]*参数条数,[dict(类型标签=4,值='x')]*(参数条数+1)):
                预期错误=3 if 编号<7000 and len(参数槽)!=参数条数 else 25
                _,正文=请求(网关实例,'/接口/调用',dict(编号=编号,值=参数槽))
                检查(not 正文.get('成功') and 正文.get('错误',{}).get('码')==预期错误,'编号%s错型少参多参在边界拒绝'%编号,dict(预期错误=预期错误,返回=正文))
        调用(网关实例,7967,[文本JSON,'/文字',r'\d+']);调用(网关实例,7968,[原文])
        _,正文=请求(网关实例,'/接口/留痕')
        留痕编号=[条目['能力号'] for 条目 in 正文.get('数据',{}).get('留痕',[])]
        检查(all(编号 in 留痕编号 for 编号 in (7967,5203,4401,7968,5201,3201)),'两类跨库组合内外调用均留痕',正文)

    def 并发样本(请求序号):
        网关实例=实例表[请求序号%len(实例表)]
        样本数据={'文字':'订单%s中文🙂'%请求序号,'请求序号':请求序号}
        原文=json.dumps(样本数据,ensure_ascii=False)
        assert 调用(网关实例,7967,[原文,'/文字',r'\d+'])==[str(请求序号)]
        assert json.loads(zlib.decompress(bytes.fromhex(调用(网关实例,7968,[原文]))))==样本数据
    with concurrent.futures.ThreadPoolExecutor(max_workers=12) as 线程池: list(线程池.map(并发样本,range(96)))
    检查(True,'双网关12线程96次新跨库提取及压缩对照')


def 执行数据文本验收(仓根,缓存根):
    from 测试验证.扩展量级.HTTP验收 import 执行量级验收
    return 执行量级验收(仓根,缓存根,扩展验证=核验数据文本)
