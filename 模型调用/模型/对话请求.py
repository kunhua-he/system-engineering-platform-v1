# -*- coding: utf-8 -*-
"""一句一答 —— 消息形状 · 一次对话 · 超过同步窗口就拿任务句柄接着取。

长生成的预算在**任务句柄**这条腿上：一次对话等到窗口结束还没生成完，底座回句柄，
本件拿句柄去 `取生成结果` 直到它说完成（或说失败）。单次请求的等待时间不拉长。
"""
import time

from .底座地址 import 一次对话, 取生成结果, 默认超时秒
from .底座应答 import 打到底座, 模型错误


def 记消息(单条消息):
    """一条消息 → 底座要的形状（每个字段各带标签）。"""
    if isinstance(单条消息, str):
        单条消息 = {"role": "user", "content": 单条消息}
    return {"类型标签": 101,
            "值": {键名: {"类型标签": 4, "值": 字段值} for 键名, 字段值 in 单条消息.items()}}


def 跑一次(模型类型, 消息列表, 系统提示词="", 温度=0.7, 最大令牌数=2048, 超时秒=默认超时秒):
    """一次对话。模型没起底座会拉起，起了就复用，默认模型不用传路径。"""
    回执值 = 打到底座(一次对话, {
        "消息列表": {"类型标签": 100, "值": 消息列表},
        "系统提示词": 系统提示词,
        "温度": 温度,
        "最大令牌数": 最大令牌数,
        "模型类型": 模型类型,
        "模型引用": "",
        "等待毫秒": min(超时秒 * 1000, 110000),
    }, 超时=超时秒)

    if 回执值.get("已完成"):
        答复内容 = 回执值.get("内容") or ""
        return 答复内容 if isinstance(答复内容, str) else str(答复内容)

    # 超过底座等待上限没生成完：它回任务句柄，接着取
    任务 = 回执值.get("任务句柄") or 0
    if not 任务:
        raise 模型错误("没拿到内容也没拿到任务句柄：%s" % 回执值.get("说明", ""))

    截止 = time.time() + 超时秒
    while time.time() < 截止:
        取回值 = 打到底座(取生成结果, {"任务句柄": {"类型标签": 7, "值": 任务}}, 超时=超时秒)
        if 取回值.get("已完成"):
            错误信息 = 取回值.get("错误信息") or ""
            if 错误信息:
                raise 模型错误("生成失败：%s" % 错误信息)
            答复内容 = 取回值.get("内容") or ""
            return 答复内容 if isinstance(答复内容, str) else str(答复内容)
        time.sleep(0.2)
    raise 模型错误("等生成结果超过 %d 秒" % 超时秒)


def 对话(消息, 系统提示词="", 温度=0.7, 最大令牌数=2048, 超时秒=默认超时秒):
    """一句话对话。消息可以是字符串，也可以是 [{"role":"user","content":"…"}] 多轮。"""
    if isinstance(消息, str):
        消息表 = [记消息(消息)]
    else:
        消息表 = [记消息(单条) for 单条 in 消息]
    return 跑一次("LLM文本模型", 消息表, 系统提示词, 温度, 最大令牌数, 超时秒)
