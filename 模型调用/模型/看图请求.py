# -*- coding: utf-8 -*-
"""看图 —— 本地图片读成 data URL，按视觉模型那一支问一句。

图片**走内联而不是路径**：底座不读调用方的盘，路径交给它只会跨机器失效。
"""
import base64

from .对话请求 import 跑一次
from .底座地址 import 默认超时秒


def 看图(图片路径, 问题="描述这张图", 超时秒=默认超时秒):
    """让视觉模型看一张本地图片。"""
    with open(图片路径, "rb") as 文件句柄:
        图片数据 = base64.b64encode(文件句柄.read()).decode()
    消息 = {"类型标签": 101, "值": {
        "role": {"类型标签": 4, "值": "user"},
        "content": {"类型标签": 100, "值": [
            {"类型标签": 101, "值": {
                "type": {"类型标签": 4, "值": "text"},
                "text": {"类型标签": 4, "值": 问题}}},
            {"类型标签": 101, "值": {
                "type": {"类型标签": 4, "值": "image_url"},
                "image_url": {"类型标签": 101, "值": {
                    "url": {"类型标签": 4, "值": "data:image/jpeg;base64," + 图片数据}}}}},
        ]},
    }}
    return 跑一次("VLM看图模型", [消息], "", 0.2, 1024, 超时秒)
