// `命令信息.类别: u16` 若没有这张表，这个号在运行期**永远解不出名字** ——
// 参照实现把它放在 `LIB_INFO +0x5C/+0x60` 那一对（计数 + 串块）里，我方顶层原先没有这一对。
// 本表就是补上的那一对：号 → 名（`取命令类别名`），表按 类别号 升序。
//
// **表允许为空**：类别号的**值域与含义尚未裁**（`契约声明/格式说明.md` §三·五 与 §十 待裁），
// 生成器**不替它编一个值域**。空表 = 「表在（机制已通），值域待裁」，不是漏写。


/// 命令类别表（源：契约声明/命令类别/*.json）——**当前为空**。
/// 空 = 「表在（机制已通），值域待裁」：类别号的值域与含义尚未裁
///（`契约声明/格式说明.md` §三·五 与 §十 待裁）⇒ 生成器不替它编一个值域。
pub const 命令类别表: [v1_contract::命令类别信息; 0] = [];

/// `命令信息.类别` → 类别名（NUL 结尾）。**查不到返回空指针**（那是「值域未裁」或「没登记」，
/// 不是错误 —— 类别号是可选说明，不是能力编号）。表按 类别号 升序（生成期已判重号），线性查即可。
pub const fn 取命令类别名(类别号: u16) -> *const u8 {
    let mut 序 = 0usize;
    while 序 < 命令类别表.len() {
        if 命令类别表[序].类别号 == 类别号 {
            return 命令类别表[序].名称;
        }
        序 += 1;
    }
    core::ptr::null()
}

