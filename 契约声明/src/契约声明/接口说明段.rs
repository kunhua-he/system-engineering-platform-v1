//! 接口说明段 —— 能力包件第一段（段类型号 `16`）的六字段编解码。
//!
//! 上级：`契约声明/` ／ 裁定：`项目文档/决策记录/2026-09-27_1106产物与入参裁决.md` §四（六字段 =
//! `GET /接口/能力/<编号>` 返回体，逐条同名同序）· `项目文档/设计文档/能力包件.md` §六。
//!
//! # 为什么在这里（唯一一份实现）
//!
//! 六字段的编解码原先只住扩展侧（`编译器支持库/src/能力包件/接口段编码.rs`）。但**读侧在底座**：
//! 模块（`.模块制品`）没有本机机器码，底座载入器只能从制品的**接口说明段**读出「怎么调」
//! （`扩展装载/后缀表.json` 的 `载入`：底座解析制品 → 取接口说明段）。而底座与扩展共用的层
//! 只有 `v1-contract`（`README.md` §六：底座不许跳层 · 扩展只读契约）⇒ 编解码搬到这里，
//! 两侧**同一份**（与 `容器.rs` 的「能力包件三段编解码只此一份」同一条理由）。
//!
//! # 本编码未冻
//!
//! `决策记录/2026-09-27_语言主线三缺口裁决.md` §四 把它归**施工面**（形状部分当场闭，剩下的只是编码）
//! ⇒ 本件不自行登记 `冻结登记.json`。若收口方要把本编码冻成盘面形状，照 `原生路边界编码`
//! 的先例补旁路即可。
//!
//! # 字节排布（逐条照原施工方案，一个字节未改）
//!
//! | 字段的 JSON 类型 | 段里的字节排布 |
//! |---|---|
//! | 整数 | 按该字段宽度**小端**搬（`u32` / `u16` / `u8` 各按其宽度） |
//! | 文本 | `u32 字节长` + UTF-8 字节 |
//! | 表 | `u32 项数` + 逐项按本表递归（**参数表的行序 = 契约行序，不许重排**） |
//! | 槽（参数项的 `默认值`） | 定长数据槽 **24 字节原样** |
//! | 逻辑型 | `u8`：`0` / `1` |
//!
//! # 本件自带的读游标
//!
//! 契约 crate 是 `no_std`，`容器.rs` 解段头用裸下标；本件字段嵌套三层（表 → 项 → 槽），
//! 裸下标会写成一堆手算位移 ⇒ 本件自带一个**私有** `读游标`（**不导出**，不是第二套对外件）。
//! 行为约定与扩展侧 `顺序读器` 一致：**越界 / 截断 / 非法 UTF-8 一律 `None`，绝不 panic**。

use alloc::string::String;
use alloc::vec::Vec;

use crate::数据槽;

/// 六字段的**字段序**（照接口面返回体，`接口面形状.md` §三）。
///
/// 列在这里是为了让「字段表只有一源」这条可核对：本件只实现这个序，不自定一个。
/// 反向解码（[`解码`]）也读同一个常量 ⇒ 两个方向不会各写一套。
pub const 接口字段序: [&str; 6] = ["编号", "名称", "说明", "参数表", "返回类型", "可抛错误码"];

/// 数据槽宽度（字节）。**冻结项 `冻结项[2] 数据槽形状`**：
/// `u32 类型标签 · u16 标志 · u16 保留 · u64 长度 · u64 值` = 4+2+2+8+8 = 24。
pub const 数据槽宽度: usize = 24;

/// 接口说明段的一条参数项 —— 与 `响应.rs::能力契约` 的 `参数表` 一项同序。
///
/// 字段序（可执行权威 `对外接口面/调用接口面/src/响应.rs::能力契约`）：
/// `名称` · `类型标签` · `状态位` · `默认值`。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 接口参数项 {
    pub 名称: String,
    pub 类型标签: u32,
    pub 状态位: u16,
    /// 定长数据槽（24 字节，冻结项 `冻结项[2] 数据槽形状`）。
    pub 默认值: 数据槽,
}

/// 接口说明段的一条可抛错误码 —— 与 `错误形状.rs::到协议值` 的错误对象逐条同序。
///
/// 字段序：`码` · `段位` · `名称` · `可重试` · `可自愈` · `需人工` · `已登记`。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 接口错误项 {
    pub 码值: u32,
    pub 段位: u32,
    pub 名称: String,
    pub 可重试: bool,
    pub 可自愈: bool,
    pub 需人工: bool,
    /// 旁路字段（`接口面形状.md` §三：错误对象六项 + 旁路 `已登记`）。
    pub 已登记: bool,
}

/// 接口说明 —— 能力包件**第一段**（段类型号 `16`）的内容：只讲怎么调。
///
/// 六字段**逐条同名同序**取自接口面返回体（字段表只在 `接口面形状.md` §三 一处，本件不复述）。
/// agent 只看这一段，包里没有源码（`能力包件.md` §三）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 接口说明 {
    pub 编号: u32,
    pub 名称: String,
    pub 说明: String,
    /// 行序即契约（与 `能力声明/<编号>.json` 的参数表逐行对应）。
    pub 参数表: Vec<接口参数项>,
    pub 返回类型: u32,
    pub 可抛错误码: Vec<接口错误项>,
}

/// 接口说明 → 段数据字节。
pub fn 编码(说明: &接口说明) -> Vec<u8> {
    let mut 输出缓冲 = Vec::new();
    输出缓冲.extend_from_slice(&说明.编号.to_le_bytes());
    写段文本(&mut 输出缓冲, &说明.名称);
    写段文本(&mut 输出缓冲, &说明.说明);
    输出缓冲.extend_from_slice(&(说明.参数表.len() as u32).to_le_bytes());
    for 入参 in &说明.参数表 {
        写参数项(&mut 输出缓冲, 入参);
    }
    输出缓冲.extend_from_slice(&说明.返回类型.to_le_bytes());
    输出缓冲.extend_from_slice(&(说明.可抛错误码.len() as u32).to_le_bytes());
    for 错误 in &说明.可抛错误码 {
        写错误项(&mut 输出缓冲, 错误);
    }
    输出缓冲
}

/// 段数据字节 → 接口说明。`None` = 编码非法（截断 / 尾部多余字节 / 不是合法 UTF-8）。
///
/// **不许尽力而为**：非空字节集必须**正好**解完，剩余一字节即 `None`。
pub fn 解码(字节: &[u8]) -> Option<接口说明> {
    let mut 读游标 = 读游标 { 字节, 位: 0 };
    let 编号 = 读游标.读四字节()?;
    let 名称 = 读游标.读文本()?;
    let 说明文本 = 读游标.读文本()?;
    let 参数个数 = 读游标.读四字节()? as usize;
    // 每项至少 4 字节名长 + 4 类型标签 + 2 状态位 + 24 槽 = 34 字节。
    if 参数个数 > 读游标.剩余() / 34 {
        return None;
    }
    let mut 参数表 = Vec::with_capacity(参数个数);
    for _ in 0..参数个数 {
        参数表.push(读参数项(&mut 读游标)?);
    }
    let 返回类型 = 读游标.读四字节()?;
    let 错误个数 = 读游标.读四字节()? as usize;
    // 每项至少 4 码 + 4 段位 + 4 名长 + 4 逻辑型 = 16 字节。
    if 错误个数 > 读游标.剩余() / 16 {
        return None;
    }
    let mut 可抛错误码 = Vec::with_capacity(错误个数);
    for _ in 0..错误个数 {
        可抛错误码.push(读错误项(&mut 读游标)?);
    }
    if 读游标.位 != 字节.len() {
        return None;
    }
    Some(接口说明 { 编号, 名称, 说明: 说明文本, 参数表, 返回类型, 可抛错误码 })
}

fn 写段文本(输出缓冲: &mut Vec<u8>, 源文本: &str) {
    输出缓冲.extend_from_slice(&(源文本.len() as u32).to_le_bytes());
    输出缓冲.extend_from_slice(源文本.as_bytes());
}

fn 写参数项(输出缓冲: &mut Vec<u8>, 入参: &接口参数项) {
    写段文本(输出缓冲, &入参.名称);
    输出缓冲.extend_from_slice(&入参.类型标签.to_le_bytes());
    输出缓冲.extend_from_slice(&入参.状态位.to_le_bytes());
    写槽(输出缓冲, &入参.默认值);
}

fn 写错误项(输出缓冲: &mut Vec<u8>, 错误: &接口错误项) {
    输出缓冲.extend_from_slice(&错误.码值.to_le_bytes());
    输出缓冲.extend_from_slice(&错误.段位.to_le_bytes());
    写段文本(输出缓冲, &错误.名称);
    输出缓冲.push(u8::from(错误.可重试));
    输出缓冲.push(u8::from(错误.可自愈));
    输出缓冲.push(u8::from(错误.需人工));
    输出缓冲.push(u8::from(错误.已登记));
}

/// 定长槽**原样** 24 字节（小端）。
///
/// 不拆成五个字段写：槽形状是**冻结项**，拆写等于在本件里复刻一份槽布局，
/// 将来槽加宽就会两处不同步。直接按冻结的那五个字段拼一遍是最少知识。
fn 写槽(输出缓冲: &mut Vec<u8>, 数据槽: &数据槽) {
    输出缓冲.extend_from_slice(&数据槽.类型标签.取号值().to_le_bytes());
    输出缓冲.extend_from_slice(&数据槽.槽标志位.to_le_bytes());
    输出缓冲.extend_from_slice(&数据槽.保留.to_le_bytes());
    输出缓冲.extend_from_slice(&数据槽.槽字节长度.to_le_bytes());
    输出缓冲.extend_from_slice(&数据槽.槽值.to_le_bytes());
}

fn 读参数项(读游标: &mut 读游标<'_>) -> Option<接口参数项> {
    let 名称 = 读游标.读文本()?;
    let 类型标签 = 读游标.读四字节()?;
    let 状态位 = 读游标.读双字节()?;
    let 默认值 = 读游标.读槽()?;
    Some(接口参数项 { 名称, 类型标签, 状态位, 默认值 })
}

fn 读错误项(读游标: &mut 读游标<'_>) -> Option<接口错误项> {
    Some(接口错误项 {
        码值: 读游标.读四字节()?,
        段位: 读游标.读四字节()?,
        名称: 读游标.读文本()?,
        可重试: 读游标.读逻辑型()?,
        可自愈: 读游标.读逻辑型()?,
        需人工: 读游标.读逻辑型()?,
        已登记: 读游标.读逻辑型()?,
    })
}

/// 本件私有的读游标：每个取字节都查边界，越界给 `None`（不 panic）。**不导出**。
struct 读游标<'a> {
    字节: &'a [u8],
    位: usize,
}

impl<'a> 读游标<'a> {
    /// 还没读的字节数（供调用方先卡「项数不可能超过 剩余长度 / 每项最小字节数」）。
    fn 剩余(&self) -> usize {
        self.字节.len().saturating_sub(self.位)
    }

    fn 取字节(&mut self, 个数: usize) -> Option<&'a [u8]> {
        let 尾部 = self.位.checked_add(个数)?;
        if 尾部 > self.字节.len() {
            return None;
        }
        let 片段 = &self.字节[self.位..尾部];
        self.位 = 尾部;
        Some(片段)
    }

    fn 读单字节(&mut self) -> Option<u8> {
        self.取字节(1).map(|片段| 片段[0])
    }

    fn 读双字节(&mut self) -> Option<u16> {
        Some(u16::from_le_bytes(self.取字节(2)?.try_into().ok()?))
    }

    fn 读四字节(&mut self) -> Option<u32> {
        Some(u32::from_le_bytes(self.取字节(4)?.try_into().ok()?))
    }

    fn 读八字节(&mut self) -> Option<u64> {
        Some(u64::from_le_bytes(self.取字节(8)?.try_into().ok()?))
    }

    fn 读文本(&mut self) -> Option<String> {
        let 读取字节数 = self.读四字节()? as usize;
        let 片段 = self.取字节(读取字节数)?;
        Some(String::from(core::str::from_utf8(片段).ok()?))
    }

    fn 读逻辑型(&mut self) -> Option<bool> {
        Some(match self.读单字节()? {
            0 => false,
            1 => true,
            _ => return None,
        })
    }

    fn 读槽(&mut self) -> Option<数据槽> {
        let 类型标签 = self.读四字节()?;
        let 槽标志位 = self.读双字节()?;
        let 保留 = self.读双字节()?;
        let 槽字节长度 = self.读八字节()?;
        let 槽值 = self.读八字节()?;
        Some(数据槽 { 类型标签: crate::类型标签::构造(类型标签), 槽标志位, 保留, 槽字节长度, 槽值 })
    }
}
