use super::*;
use alloc::string::ToString;
use alloc::vec;

fn 造文本元素(名称: &str, 文本值: &str) -> 复合元素 {
    复合元素 {
        名称: 名称.to_string(),
        值: 复合值::文本载荷(文本值.to_string()),
    }
}

fn 空名元素(值: 复合值) -> 复合元素 {
    复合元素 { 名称: String::new(), 值 }
}

#[test]
fn 结果结构往返一致() {
    let 往返元素表 = vec![
        造文本元素("能力名", "求和"),
        复合元素 { 名称: "次数".to_string(), 值: 复合值::整数值(-3) },
        复合元素 { 名称: "成功".to_string(), 值: 复合值::逻辑型(true) },
        复合元素 { 名称: "耗时".to_string(), 值: 复合值::双精度(1.5) },
        复合元素 { 名称: "原始".to_string(), 值: 复合值::字节集(vec![0, 255, 7]) },
        复合元素 { 名称: "句柄".to_string(), 值: 复合值::句柄(7) },
        复合元素 { 名称: "占位".to_string(), 值: 复合值::无值 },
    ];
    let 编出载荷 = 编码复合值载荷(结果结构标签, &往返元素表).unwrap();
    assert_eq!(解码复合值载荷(&编出载荷, 结果结构标签).unwrap(), 往返元素表);
}

#[test]
fn 列表名称必空且嵌套字典可往返() {
    let 内层元素表 = vec![
        造文本元素("名称键", "值"),
        复合元素 { 名称: "数值键".to_string(), 值: 复合值::双精度(1.5) },
    ];
    let 外层元素表 = vec![
        空名元素(复合值::复合 { 标签: 字典标签, 元素表: 内层元素表 }),
        空名元素(复合值::句柄(7)),
    ];
    let 编出载荷 = 编码复合值载荷(列表标签, &外层元素表).unwrap();
    assert_eq!(解码复合值载荷(&编出载荷, 列表标签).unwrap(), 外层元素表);
}

#[test]
fn 形状校验四种各拒各的() {
    let 列表带名元素表 = vec![造文本元素("不该有名字", "x")];
    assert_eq!(
        编码复合值载荷(列表标签, &列表带名元素表),
        Err(复合载荷错误::名称该为空 { 元素位次: 0 })
    );
    let 字典空名元素表 = vec![空名元素(复合值::整数值(1))];
    assert_eq!(
        编码复合值载荷(字典标签, &字典空名元素表),
        Err(复合载荷错误::名称不该为空 { 元素位次: 0 })
    );
    let 重名元素表 = vec![造文本元素("字段", "a"), 造文本元素("字段", "b")];
    assert_eq!(
        编码复合值载荷(结果结构标签, &重名元素表),
        Err(复合载荷错误::名称重复 { 元素位次: 1 })
    );
    let 不限形状元素表 = vec![
        空名元素(复合值::整数值(1)),
        造文本元素("字段", "a"),
        造文本元素("字段", "b"),
    ];
    assert!(编码复合值载荷(JSON值标签, &不限形状元素表).is_ok());
}

#[test]
fn 标签未登记即拒() {
    assert_eq!(
        编码复合值载荷(99, &[]),
        Err(复合载荷错误::标签未登记 { 标签: 99 })
    );
    assert_eq!(
        解码复合值载荷(&[0, 0, 0, 0], 99),
        Err(复合载荷错误::标签未登记 { 标签: 99 })
    );
    let 未登记标签元素表 = vec![空名元素(复合值::复合 { 标签: 200, 元素表: Vec::new() })];
    assert_eq!(
        编码复合值载荷(列表标签, &未登记标签元素表),
        Err(复合载荷错误::标签未登记 { 标签: 200 })
    );
}

#[test]
fn 坏载荷各报各的() {
    assert_eq!(解码复合值载荷(&[], 列表标签), Err(复合载荷错误::载荷截断));
    assert_eq!(
        解码复合值载荷(&[0, 0, 0, 2], 列表标签),
        Err(复合载荷错误::元素个数越界 { 声明: 2, 可读: 0 })
    );
    assert_eq!(
        解码复合值载荷(&[0, 0, 0, 0, 9], 列表标签),
        Err(复合载荷错误::尾部多余字节 { 多余字节: 1 })
    );
    let mut 逻辑坏载荷 = Vec::new();
    逻辑坏载荷.extend_from_slice(&1u32.to_be_bytes());
    逻辑坏载荷.extend_from_slice(&0u32.to_be_bytes());
    逻辑坏载荷.extend_from_slice(&3u32.to_be_bytes());
    逻辑坏载荷.extend_from_slice(&2u64.to_be_bytes());
    assert_eq!(
        解码复合值载荷(&逻辑坏载荷, 列表标签),
        Err(复合载荷错误::逻辑值非零非一 { 元素位次: 0, 值: 2 })
    );
    let mut 文本坏载荷 = Vec::new();
    文本坏载荷.extend_from_slice(&1u32.to_be_bytes());
    文本坏载荷.extend_from_slice(&0u32.to_be_bytes());
    文本坏载荷.extend_from_slice(&4u32.to_be_bytes());
    文本坏载荷.extend_from_slice(&1u32.to_be_bytes());
    文本坏载荷.push(0xff);
    assert_eq!(
        解码复合值载荷(&文本坏载荷, 列表标签),
        Err(复合载荷错误::文本非文本 { 元素位次: 0 })
    );
}

