//! 复合值载荷 —— 类型标签 `100 列表` / `101 字典` / `102 JSON值` / `103 结果结构`
//! 的槽载荷**形状与编解码**。
//!
//! 依据 `项目文档/决策记录/2026-10-12_复合类型槽载荷裁决.md`。载荷形状（该件 §二）：
//!
//! ```text
//! 元素个数 u32 大端
//! 元素*：名称长度 u32 大端 + 名称 UTF-8 + 类型标签 u32 大端 + 值
//! 值（按类型标签）：
//!   0  无值    0 字节
//!   1  整数    8 字节大端
//!   2  双精度  8 字节大端（IEEE754 位型）
//!   3  逻辑型  8 字节大端（0 或 1）
//!   4  文本    长度 u32 大端 + UTF-8 字节
//!   5  字节集  长度 u32 大端 + 原始字节
//!   6  句柄    8 字节大端
//!   100–103   长度 u32 大端 + 子载荷（递归）
//! ```
//!
//! # 为什么住在契约层
//!
//! 槽载荷的形状要由**三方共认**：`对外接口面`（JSON ↔ 槽编解码）·
//! `运行内核`（槽搬运与归还）· 生成的模块执行体（写入返回值）。
//! 三方都不属于任何一个扩展 ⇒ 形状与编解码收进契约层，
//! 与段 `20` 载荷（`契约声明/契约声明/执行体载荷.rs`）同一先例。
//!
//! # 四个标签共用形状，区别只在形状校验
//!
//! `100 列表` 名称必空 · `101 字典` 名称必非空 · `102 JSON值` 不限 ·
//! `103 结果结构` 名称必非空且不重名。
//!
//! # 本件只管形状
//!
//! 「这个槽归谁释放」是**槽标志**的事（`槽标志::所有权交出`），本件不碰。

use alloc::string::String;
use alloc::vec::Vec;

/// 类型标签：列表。
pub const 列表标签: u32 = 100;
/// 类型标签：字典。
pub const 字典标签: u32 = 101;
/// 类型标签：JSON值。
pub const JSON值标签: u32 = 102;
/// 类型标签：结果结构。
pub const 结果结构标签: u32 = 103;

/// **通用复合标签** —— 上面那四个号的**唯一一份**清单（判「是不是通用复合标签」只读这里）。
///
/// 为什么要单列一份：装载侧要判「这个标签算不算已登记」，而这四个号与底座内置标签
/// （`0`–`99`）不是一回事 —— 它们**归扩展**（`契约声明/号段图.json` 的 `类型号段`
/// `100`–`4294967294`；`项目文档/决策记录/2026-10-12_复合类型槽载荷裁决.md` §九
/// 「平台不拥有这四个号」），但**每个扩展各自声明同一批号**（`元素表` 记的是该扩展
/// 各能力的返回字段）⇒ 它们不是谁独占的号位，而是**共享标签**。
///
/// 同一先例：生命周期通知段按广播段判（`项目文档/决策记录/2026-09-27_生命周期通知段按广播段判.md`）
/// —— 「同一号被多份声明共同申报」在那一处已裁过，这里照同一口径裁。
///
/// 装载侧若按「独占」判，第二个扩展一装就撞号：实测两条路都堵 ——
/// **只引用**报声明不自洽、**自行声明**报号段冲突 ⇒ 同网关双执行域立不起来。
/// 故「这四个号是共享的」这件事只在本件写一份，装载侧引用本件，不另写第二份区间。
pub const 通用复合标签: [u32; 4] = [列表标签, 字典标签, JSON值标签, 结果结构标签];

/// 这个标签是不是**通用复合标签**（共享标签：每个扩展都可自行声明，也可只引用）。
pub fn 是通用复合标签(标签: u32) -> bool {
    通用复合标签.contains(&标签)
}

/// 递归深度上界 —— 防恶意深嵌套。超了即拒（不是「以后再支持」）。
pub const 递归深度上界: usize = 32;

/// 一个复合值的元素：名称 + 值。名称的合法性由**外层标签**的形状校验判。
#[derive(Debug, Clone, PartialEq)]
pub struct 复合元素 {
    pub 名称: String,
    pub 值: 复合值,
}

/// 复合值 —— 递归定义。
#[derive(Debug, Clone, PartialEq)]
pub enum 复合值 {
    无值,
    整数值(i64),
    双精度(f64),
    逻辑型(bool),
    文本载荷(String),
    字节集(Vec<u8>),
    句柄(u64),
    复合 { 标签: u32, 元素表: Vec<复合元素> },
}

impl 复合值 {
    /// 本值的类型标签。
    pub fn 取标签(&self) -> u32 {
        match self {
            复合值::无值 => 0,
            复合值::整数值(_) => 1,
            复合值::双精度(_) => 2,
            复合值::逻辑型(_) => 3,
            复合值::文本载荷(_) => 4,
            复合值::字节集(_) => 5,
            复合值::句柄(_) => 6,
            复合值::复合 { 标签, .. } => *标签,
        }
    }
}

/// 编解码的结构化失败。**不 panic**（跨边界不许抛异常）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 复合载荷错误 {
    /// 读不够声明的字节数。
    载荷截断,
    /// 元素个数声明得比剩余字节还多（每个元素至少要 8 字节）。
    元素个数越界 { 声明: usize, 可读: usize },
    /// 读完之后还剩字节 —— 载荷比声明的长。
    尾部多余字节 { 多余字节: usize },
    /// 名称那一段不是合法 UTF-8。
    名称非文本,
    /// 文本值那一段不是合法 UTF-8。
    文本非文本 { 元素位次: usize },
    /// 列表元素的名称该为空。
    名称该为空 { 元素位次: usize },
    /// 字典 / 结果结构元素的名称不该为空。
    名称不该为空 { 元素位次: usize },
    /// 结果结构 / 字典里出现重名（`元素位次` 是**后出现**的那个）。
    名称重复 { 元素位次: usize },
    /// 标签没登记（不是本平台认的复合标签）。
    标签未登记 { 标签: u32 },
    /// 逻辑型只许 0 或 1。
    逻辑值非零非一 { 元素位次: usize, 值: u64 },
    /// 嵌套层数超过上界。
    嵌套过深,
}

/// 编码：`元素表` → 载荷字节。`标签` 决定形状校验。
pub fn 编码复合值载荷(标签: u32, 元素表: &[复合元素]) -> Result<Vec<u8>, 复合载荷错误> {
    校验标签(标签)?;
    校验形状(标签, 元素表)?;
    编元素表(元素表, 1)
}

/// 解码：载荷字节 → `元素表`。`期望标签` 既校验标签本身，也校验形状。
pub fn 解码复合值载荷(载荷: &[u8], 期望标签: u32) -> Result<Vec<复合元素>, 复合载荷错误> {
    校验标签(期望标签)?;
    let mut 读数 = 读数器 { 载荷, 读位: 0 };
    let 元素表 = 读元素表(&mut 读数, 1)?;
    if 读数.读位 != 载荷.len() {
        return Err(复合载荷错误::尾部多余字节 { 多余字节: 载荷.len() - 读数.读位 });
    }
    校验形状(期望标签, &元素表)?;
    Ok(元素表)
}

/// 标签是不是本平台认的复合标签。
fn 校验标签(标签: u32) -> Result<(), 复合载荷错误> {
    match 标签 {
        列表标签 | 字典标签 | JSON值标签 | 结果结构标签 => Ok(()),
        _ => Err(复合载荷错误::标签未登记 { 标签 }),
    }
}

/// 按标签做形状校验 —— 四个标签的**唯一区别**就在这里。
fn 校验形状(标签: u32, 元素表: &[复合元素]) -> Result<(), 复合载荷错误> {
    match 标签 {
        列表标签 => {
            for (元素位次, 元素项) in 元素表.iter().enumerate() {
                if !元素项.名称.is_empty() {
                    return Err(复合载荷错误::名称该为空 { 元素位次 });
                }
            }
        }
        字典标签 | 结果结构标签 => {
            let mut 已见名: Vec<&str> = Vec::new();
            for (元素位次, 元素项) in 元素表.iter().enumerate() {
                if 元素项.名称.is_empty() {
                    return Err(复合载荷错误::名称不该为空 { 元素位次 });
                }
                if 已见名.contains(&元素项.名称.as_str()) {
                    return Err(复合载荷错误::名称重复 { 元素位次 });
                }
                已见名.push(元素项.名称.as_str());
            }
        }
        JSON值标签 => {}
        _ => return Err(复合载荷错误::标签未登记 { 标签 }),
    }
    Ok(())
}

fn 编元素表(元素表: &[复合元素], 深度: usize) -> Result<Vec<u8>, 复合载荷错误> {
    if 深度 > 递归深度上界 {
        return Err(复合载荷错误::嵌套过深);
    }
    let mut 载荷 = Vec::new();
    载荷.extend_from_slice(&(元素表.len() as u32).to_be_bytes());
    for 元素项 in 元素表 {
        写元素(&mut 载荷, 元素项, 深度)?;
    }
    Ok(载荷)
}

fn 写元素(载荷: &mut Vec<u8>, 元素项: &复合元素, 深度: usize) -> Result<(), 复合载荷错误> {
    let 名称字节 = 元素项.名称.as_bytes();
    载荷.extend_from_slice(&(名称字节.len() as u32).to_be_bytes());
    载荷.extend_from_slice(名称字节);
    载荷.extend_from_slice(&元素项.值.取标签().to_be_bytes());
    match &元素项.值 {
        复合值::无值 => {}
        复合值::整数值(值) => 载荷.extend_from_slice(&值.to_be_bytes()),
        复合值::双精度(值) => 载荷.extend_from_slice(&值.to_bits().to_be_bytes()),
        复合值::逻辑型(值) => 载荷.extend_from_slice(&u64::from(*值).to_be_bytes()),
        复合值::句柄(值) => 载荷.extend_from_slice(&值.to_be_bytes()),
        复合值::文本载荷(值) => {
            let 字节 = 值.as_bytes();
            载荷.extend_from_slice(&(字节.len() as u32).to_be_bytes());
            载荷.extend_from_slice(字节);
        }
        复合值::字节集(值) => {
            载荷.extend_from_slice(&(值.len() as u32).to_be_bytes());
            载荷.extend_from_slice(值);
        }
        复合值::复合 { 标签, 元素表 } => {
            校验标签(*标签)?;
            校验形状(*标签, 元素表)?;
            let 子载荷 = 编元素表(元素表, 深度 + 1)?;
            载荷.extend_from_slice(&(子载荷.len() as u32).to_be_bytes());
            载荷.extend_from_slice(&子载荷);
        }
    }
    Ok(())
}

/// 只前进不后退的读数器 —— 越界一律 `载荷截断`，不 panic。
struct 读数器<'载荷> {
    载荷: &'载荷 [u8],
    读位: usize,
}

impl<'载荷> 读数器<'载荷> {
    fn 剩余字节(&self) -> usize {
        self.载荷.len() - self.读位
    }

    fn 取字节(&mut self, 字节宽: usize) -> Result<&'载荷 [u8], 复合载荷错误> {
        let 止位 = self.读位.checked_add(字节宽).ok_or(复合载荷错误::载荷截断)?;
        if 止位 > self.载荷.len() {
            return Err(复合载荷错误::载荷截断);
        }
        let 取到字节 = &self.载荷[self.读位..止位];
        self.读位 = 止位;
        Ok(取到字节)
    }

    fn 取u32(&mut self) -> Result<u32, 复合载荷错误> {
        let 字节 = self.取字节(4)?;
        Ok(u32::from_be_bytes([字节[0], 字节[1], 字节[2], 字节[3]]))
    }

    fn 取u64(&mut self) -> Result<u64, 复合载荷错误> {
        let 字节 = self.取字节(8)?;
        Ok(u64::from_be_bytes([
            字节[0], 字节[1], 字节[2], 字节[3], 字节[4], 字节[5], 字节[6], 字节[7],
        ]))
    }
}

fn 读元素表(读数: &mut 读数器<'_>, 深度: usize) -> Result<Vec<复合元素>, 复合载荷错误> {
    if 深度 > 递归深度上界 {
        return Err(复合载荷错误::嵌套过深);
    }
    let 元素个数 = 读数.取u32()? as usize;
    // 每个元素至少「名称长度 4 + 类型标签 4」= 8 字节 ⇒ 元素个数超过剩余/8 必是坏载荷。
    if 元素个数.saturating_mul(8) > 读数.剩余字节() {
        return Err(复合载荷错误::元素个数越界 { 声明: 元素个数, 可读: 读数.剩余字节() });
    }
    let mut 元素表 = Vec::with_capacity(元素个数);
    for 元素位次 in 0..元素个数 {
        元素表.push(读元素(读数, 元素位次, 深度)?);
    }
    Ok(元素表)
}

fn 读元素(
    读数: &mut 读数器<'_>,
    元素位次: usize,
    深度: usize,
) -> Result<复合元素, 复合载荷错误> {
    let 名称宽 = 读数.取u32()? as usize;
    let 名称字节 = 读数.取字节(名称宽)?;
    let 名称 = core::str::from_utf8(名称字节)
        .map_err(|_| 复合载荷错误::名称非文本)?
        .into();
    let 标签 = 读数.取u32()?;
    let 值 = 读值(读数, 标签, 元素位次, 深度)?;
    Ok(复合元素 { 名称, 值 })
}

fn 读值(
    读数: &mut 读数器<'_>,
    标签: u32,
    元素位次: usize,
    深度: usize,
) -> Result<复合值, 复合载荷错误> {
    match 标签 {
        0 => Ok(复合值::无值),
        1 => Ok(复合值::整数值(读数.取u64()? as i64)),
        2 => Ok(复合值::双精度(f64::from_bits(读数.取u64()?))),
        3 => {
            let 逻辑原值 = 读数.取u64()?;
            if 逻辑原值 > 1 {
                return Err(复合载荷错误::逻辑值非零非一 { 元素位次, 值: 逻辑原值 });
            }
            Ok(复合值::逻辑型(逻辑原值 == 1))
        }
        4 => {
            let 文本宽 = 读数.取u32()? as usize;
            let 文本字节 = 读数.取字节(文本宽)?;
            let 文本值 = core::str::from_utf8(文本字节)
                .map_err(|_| 复合载荷错误::文本非文本 { 元素位次 })?
                .into();
            Ok(复合值::文本载荷(文本值))
        }
        5 => {
            let 字节集宽 = 读数.取u32()? as usize;
            Ok(复合值::字节集(读数.取字节(字节集宽)?.to_vec()))
        }
        6 => Ok(复合值::句柄(读数.取u64()?)),
        列表标签 | 字典标签 | JSON值标签 | 结果结构标签 => {
            let 子载荷宽 = 读数.取u32()? as usize;
            let 子载荷 = 读数.取字节(子载荷宽)?;
            let mut 子读数 = 读数器 { 载荷: 子载荷, 读位: 0 };
            let 元素表 = 读元素表(&mut 子读数, 深度 + 1)?;
            if 子读数.读位 != 子载荷.len() {
                return Err(复合载荷错误::尾部多余字节 { 多余字节: 子载荷.len() - 子读数.读位 });
            }
            校验形状(标签, &元素表)?;
            Ok(复合值::复合 { 标签, 元素表 })
        }
        _ => Err(复合载荷错误::标签未登记 { 标签 }),
    }
}

