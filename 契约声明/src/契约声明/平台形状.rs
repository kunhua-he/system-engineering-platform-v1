//! 平台形状 —— 契约主结构。宿主读一次即掌握全部可装载性。
//!
//! 公开面经 `lib.rs` 再导出 ⇒ `v1_contract::平台信息` 逐字不变。

use crate::{
    版本三元组, 表段, 命令信息, 号段, 常量信息, 数据类型信息, 执行函数, 通知函数, 错误码信息,
};

/// 契约主结构。宿主读一次即掌握全部可装载性（宪法第 2 条）。
#[repr(C)]
pub struct 平台信息 {
    /// 格式的身份证，不是版本号。
    pub 声明格式号: u32,
    /// 本构建的目标字宽（32 或 64）。**唯一随目标变宽的是表指针**，宿主据此决定按几字节读。
    pub 目标字宽: u16,
    pub 保留: u16,
    /// 32 位十六进制标识串 + NUL。
    pub 标识串: *const u8,
    pub 实现版本: 版本三元组,
    /// 我需要什么宿主；不满足即拒绝载入。
    pub 要求宿主版本: 版本三元组,
    /// 我需要什么内核；不满足即拒绝载入。
    pub 要求内核版本: 版本三元组,
    pub 名称: *const u8,
    pub 说明: *const u8,
    pub 状态位: u32,
    pub 类型表: 表段<数据类型信息>,
    pub 命令表: 表段<命令信息>,
    /// 与命令表一一对应的执行函数表。缺项用占位函数，**不许留空指针**。
    pub 函数表: *const 执行函数,
    pub 常量表: 表段<常量信息>,
    pub 通知函数: Option<通知函数>,
    pub 依赖清单: 表段<*const u8>,
    // ── 旁路区（只增不改；一律追加）──
    /// 本声明**自己占用**的**能力号**段表。**没有它，扩展无法声明自己占哪段号。**
    ///
    /// 与 `契约声明/号段图.json` 的 `能力号段` **不是一回事**：那张图是**全平台布局**
    /// （每一段归谁），这个是**本声明占哪几段**。底座只占 `0xxx`，不是占满 5 段——
    /// 把布局当成占用会让底座把 1xxx–8xxx 全占死，任何扩展都载不进来。
    pub 能力号段: 表段<号段>,
    /// 本声明占用的**通知号**段表。通知号是独立命名空间，必须分开声明。
    pub 通知号段: 表段<号段>,
    /// 已登记的错误段位表（**占用声明**：本声明占哪几个段位）。
    /// **没有它，「未登记的段位不许抛出」判不了。**
    /// 错误码口径：`码 = 段位 × 1000 + 序号`（4 位十进制：段位 1 位 + 序 3 位；段位 0 = 内核自有）。
    pub 错误段位表: 表段<u32>,
    /// 错误码内容表。**没有它，「失败可编程处理」到不了运行期**——
    /// 调用方拿到 `码` 之后要能查到 `可重试 · 可自愈 · 需人工`，否则那三项只是注释。
    /// 与 `错误段位表` 的关系：段位表是占用声明（紧凑），本表是内容；验证面交叉比对
    /// 「段位表 == 本表里各码的段位集合」，两边不一致即判红。
    pub 错误码表: 表段<错误码信息>,
}
