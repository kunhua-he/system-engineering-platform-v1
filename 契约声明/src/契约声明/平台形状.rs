//! 平台形状 —— 契约主结构。宿主读一次即掌握全部可装载性。
//!
//! 公开面经 `lib.rs` 再导出 ⇒ `v1_contract::平台信息` 逐字不变。

use crate::{
    版本三元组, 表段, 命令信息, 号段, 常量信息, 数据类型信息, 执行函数, 通知函数, 错误码信息,
    命令类别信息,
};

/// 契约主结构。宿主读一次即掌握全部可装载性（宪法第 2 条）。
#[repr(C)]
pub struct 平台信息 {
    /// 格式的身份证，不是版本号。型是 `格式号`（newtype）—— 与任何号/版本互不能赋值。
    pub 声明格式号: crate::格式号,
    /// 本构建的目标字宽（32 或 64）。**唯一随目标变宽的是表指针**，宿主据此决定按几字节读。
    pub 目标字宽: u16,
    pub 保留: u16,
    /// 32 位十六进制标识串 + NUL。
    pub 标识串: *const u8,
    pub 实现版本: 版本三元组,
    /// 我需要什么宿主；不满足即拒绝载入。
    pub 要求宿主版本: 版本三元组,
    /// 我需要什么内核；不满足即拒绝载入。
    pub 要求内核版本: 版本三元组,
    pub 名称: *const u8,
    pub 说明: *const u8,
    /// 声明状态位。**位含义见 `平台状态`**（本文件下方）——
    /// 原先这是**没有位含义的字段**（宽度在、含义无），宿主收到非零状态字只能当不透明数。
    pub 状态位: u32,
    pub 类型表: 表段<数据类型信息>,
    pub 命令表: 表段<命令信息>,
    /// 与命令表一一对应的执行函数表。缺项用占位函数，**不许留空指针**。
    pub 函数表: *const 执行函数,
    pub 常量表: 表段<常量信息>,
    pub 通知函数: Option<通知函数>,
    pub 依赖清单: 表段<*const u8>,
    // ── 旁路区（只增不改；一律追加）──
    /// 本声明**自身占用**的**能力号**段表。**没有它，扩展无法声明自身占哪段号。**
    ///
    /// 与 `契约声明/号段图.json` 的 `能力号段` **不是一回事**：那张图是**全平台布局**
    /// （每一段归谁），这个是**本声明占哪几段**。底座只占 `0xxx`，不是占满 5 段——
    /// 把布局当成占用会让底座把 1xxx–8xxx 全占死，任何扩展都载不进来。
    pub 能力号段: 表段<号段>,
    /// 本声明占用的**通知号**段表。通知号是独立命名空间，必须分开声明。
    pub 通知号段: 表段<号段>,
    /// 已登记的错误段位表（**占用声明**：本声明占哪几个段位）。
    /// **没有它，「未登记的段位不许抛出」判不了。**
    /// 错误码口径：`码 = 段位 × 1000 + 序号`（4 位十进制：段位 1 位 + 序 3 位；段位 0 = 内核自有）。
    pub 错误段位表: 表段<u32>,
    /// 错误码内容表。**没有它，「失败可编程处理」到不了运行期**——
    /// 调用方拿到 `码` 之后要能查到 `可重试 · 可自愈 · 需人工`，否则那三项只是注释。
    /// 与 `错误段位表` 的关系：段位表是占用声明（紧凑），本表是内容；验证面交叉比对
    /// 「段位表 == 本表里各码的段位集合」，两边不一致即判红。
    pub 错误码表: 表段<错误码信息>,
    /// **命令类别表** —— `命令信息.类别` 那个号的「号 → 名」表（**旁路字段**，2026-09-27）。
    ///
    /// 原先 `命令类别表` / `取命令类别名` 只出在 `声明数据` 里（由 `lib.rs` `pub use`），
    /// **没进 `平台信息`** ⇒ 底座自身的类别号经 `v1_contract::取命令类别名` 可查，
    /// 而宿主手里只有**本声明的** `平台信息`（拿不到扩展的 `声明数据`）⇒ **扩展的**类别号取不到。
    /// 补进尾部旁路区后，扩展在它自身的 `命令类别/<类别号>.json` 里声明的类别表随 `平台信息`
    /// 交到宿主，宿主按 `命令信息.类别` 查名不必认识扩展内部。
    /// 空表 = 「本声明没有类别表」（合法，不是漏写）—— 与 `取命令类别名` 查不到时返回空指针同义。
    pub 命令类别表: 表段<命令类别信息>,
    /// **要求权限** —— 本声明**要求**的权限（**旁路字段**，2026-09-27）。
    ///
    /// 值是一张 NUL 结尾权限名表；权限名取自资源网关口的副作用四名：`读文件` / `写文件` /
    /// `联网` / `派生进程`（`跨语言适配/资源网关口/src/声明形状/副作用与允许.rs::副作用`），
    /// **不另立一套词汇**。**没有它，「默认拒绝」无可比对**：关口只能按资源声明的 `允许`
    /// 单边放行，无从知道扩展自称需要什么（裁决：`项目文档/决策记录/2026-09-27_补主人与核心预算.md`
    /// §一 第 4 条 —— 「没有『要求』就无可比对 ⇒ 只有单边」）。
    /// 空表 = 「本声明不要求任何权限」（合法，不是漏写）—— 与「漏写」靠「键必须存在」分开。
    pub 要求权限: 表段<*const u8>,
}

/// 声明状态位（`平台信息.状态位` 的位含义）。
///
/// **为什么有这一段**：`状态位: u32` 原先是**没有位含义的字段** —— 字段在、宽度在，
/// 而「哪一位是什么意思」全无定义 ⇒ 收到一个非零状态字的宿主只能当它是不透明数（台账 #131
/// 第 ④ 处「无理由偏离」：参照实现 `LIB_INFO.m_dwState` 有一整张位表，我方全无）。
/// 位名与位号**照抄参照实现的实测位表**（`项目文档/设计文档/接缝实测.md` §七.1 ·
/// `开发工具/取证/接缝反解/常量.py::库状态位`），不发明新的位。
///
/// **不是复刻它的结构**：位号是我们自己结构里的语义（参照实现的高位是 `__OS_*` 宏 —— 见下），
/// 拿到的位值不保证与它的某一份 `.fne` 逐位相同（它的格式号不同，本来就不互认）。
///
/// 与 `命令状态`（`契约声明/命令形状.rs`）**是两个命名空间**：这个是**声明/库**一级的状态，
/// 那个是**单条命令**一级的状态。两者的位号有重合（如 `隐含`/`错误`）但含义互不引用。
pub mod 平台状态 {
    /// 本声明**无运行代码**（只有声明与元数据，没有可执行的命令实现）。
    pub const 无运行代码: u32 = 1 << 2;
    /// 本声明**无编辑信息**（不含 IDE 侧的编辑/属性描述）。
    pub const 无编辑信息: u32 = 1 << 3;
    /// 本声明是**数据库支持库**（参照实现这一位的语义）。
    pub const 数据库支持库: u32 = 1 << 5;
    /// 状态字**实为库信息变体**（参照实现命名「实为 LIB_INFO2」）——
    /// 即这一位的存在说明承载它的记录是另一种库信息形态，不是本契约的 `平台信息`。
    pub const 载体为库信息变体: u32 = 1 << 7;
    /// 本声明是**集成环境插件**（参照实现命名「IDE 插件」）。
    pub const 集成环境插件: u32 = 1 << 8;
    /// **高位操作系统宏的掩码**。
    ///
    /// 参照实现把「支持哪几个操作系统」编在状态字的高两位（实测 `0xC0000000`，样本 `sock`
    /// 报 `__OS_WIN|__OS_LINUX`）。**哪一位是哪个操作系统，实测定不了** ——
    /// `项目文档/设计文档/接缝实测.md` §八 第 3 条把「`m_dwState` 高位的 OS 宏全集」
    /// 明列为**证据不足**（要非 Windows/Linux 的库样本，或 OS 宏完整清单）。
    /// ⇒ 这里只登记**实测到的那两位合成一张掩码**，不给逐位命名：
    /// 给某一位置名就是编，而编出来的位名会被下游当事实引用。
    pub const 系统位掩码: u32 = 0xC000_0000;
}
