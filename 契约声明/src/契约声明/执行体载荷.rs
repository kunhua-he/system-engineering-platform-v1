//! 本机执行体载荷 —— 段类型号 `20`（模块 · 本机执行体段）载荷的**形状与编解码**。
//!
//! 依据 `项目文档/决策记录/2026-10-12_模块执行体承载与编译裁决.md`：制品随执行体段带
//! **平台身份**，装载时不匹配即拒、不静默降级。载荷形状（该件 §七 记的收口方自裁）：
//!
//! ```text
//! [平台身份长度 u16 大端][平台身份 UTF-8 字节][执行体机器码字节]
//! ```
//!
//! # 为什么住在契约层
//!
//! 段 `20` 是**契约**（`契约声明/冻结登记.json` 的段类型号登记），它的载荷形状就是契约的一部分。
//! **构建侧**（构建侧的例子 `出模块制品`）写它、**装载侧**（适配器侧的 `装载件缓存`）读它 ——
//! 两侧都要用 ⇒ **只此一份**，谁都不许各写一份（两套事实源必然漂移）。
//!
//! # 本件只管形状
//!
//! 「这段机器码能不能在这台机器上跑」（平台身份比对）是**装载侧**的事；
//! 「这串字节是不是真机器码」是**构建侧**的事。本件只回答：载荷怎么装、怎么拆、拆不开时错在哪。

use alloc::string::String;
use alloc::vec::Vec;

/// 执行体入口的**符号名**（C-ABI）。构建侧按它 `#[unsafe(no_mangle)]` 导出，装载侧按它 `dlsym`。
///
/// **为什么是 ASCII**：`#[no_mangle]` 要求标识符是 ASCII（`error[E0754]`）——
/// 工具链硬约束，不是命名偏好。C-ABI 符号名是**跨语言边界的标识符**，同 `ID`/`PPT` 一类缩写。
pub const 入口符号: &str = "v1_module_exec";

/// 平台身份的长度前缀宽度（字节）—— 大端 `u16`。
pub const 身份长度宽度: usize = 2;

/// 平台身份长度上界（字节）—— 真三元组不超过 64 字节，超了必是坏载荷（不是「以后再支持」）。
pub const 身份长度上界: usize = 64;

/// 拆载荷的结构化失败。**不 panic**（跨边界不许抛异常）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 载荷错误 {
    /// 载荷短于长度前缀 —— 连「身份多长」都读不出来。
    载荷截断,
    /// 长度前缀声明的身份长度与实际字节数不符（越界，或超出上界）。
    身份长度越界 { 声明: usize, 可读: usize },
    /// 身份那一段不是合法 UTF-8。
    身份非文本,
    /// 执行体那一段是空的 —— 空段不是执行体（段 `20` 装的就是执行体本身）。
    执行体为空,
}

/// 打包：`平台身份` + `执行体字节` → 段 `20` 载荷。
///
/// **不在这里校验平台身份**（那是装载侧的事）。身份超过上界就按上界截断：这是**可判的降级**
/// —— 拆的时候长度前缀对不上，报 `身份长度越界`，不会被静默接受。
pub fn 打包执行体载荷(平台身份: &str, 执行体: &[u8]) -> Vec<u8> {
    let 身份字节 = 平台身份.as_bytes();
    let 取长 = 身份字节.len().min(身份长度上界);
    let mut 载荷 = Vec::with_capacity(身份长度宽度 + 取长 + 执行体.len());
    载荷.extend_from_slice(&(取长 as u16).to_be_bytes());
    载荷.extend_from_slice(&身份字节[..取长]);
    载荷.extend_from_slice(执行体);
    载荷
}

/// 拆包：段 `20` 载荷 → `(平台身份, 执行体字节)`。
pub fn 拆执行体载荷(载荷: &[u8]) -> Result<(String, Vec<u8>), 载荷错误> {
    let 长度字节 = 载荷.get(..身份长度宽度).ok_or(载荷错误::载荷截断)?;
    let 声明 = u16::from_be_bytes([长度字节[0], 长度字节[1]]) as usize;
    let 越界 = || 载荷错误::身份长度越界 { 声明, 可读: 载荷.len() };
    if 声明 > 身份长度上界 {
        return Err(越界());
    }
    let 身份段 = 载荷.get(身份长度宽度..身份长度宽度 + 声明).ok_or_else(越界)?;
    let 执行体 = 载荷.get(身份长度宽度 + 声明..).ok_or_else(越界)?;
    if 执行体.is_empty() {
        return Err(载荷错误::执行体为空);
    }
    let 身份 = core::str::from_utf8(身份段).map_err(|_| 载荷错误::身份非文本)?;
    Ok((String::from(身份), 执行体.to_vec()))
}

