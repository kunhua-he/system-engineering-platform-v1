//! 通知形状 —— 宿主与扩展之间的双向通道：函数类型与它的返回值约定。
//!
//! 公开面经 `lib.rs` 再导出 ⇒ `v1_contract::通知函数` / `v1_contract::通知返回` 逐字不变。

use crate::通知号;

/// 通知函数：宿主与扩展之间的双向通道。
///
/// 返回值：`0` 成功；`-1` 失败；[`通知返回::延迟释放`] 请求延迟释放（生命周期号段）。
/// **这里不写那个数** —— 它的值只有一个来源：生成物里那条「延迟释放应答」通知号常量
/// （源：`契约声明/通知号段/` 下那份声明，文件名即通知号）。早先这里硬写了字面量，是第二来源。
pub type 通知函数 = unsafe extern "C" fn(通知号: 通知号, 参数一: usize, 参数二: usize) -> isize;

/// 通知返回值。
///
/// `成功` / `失败` 是**协议约定值**，`契约声明/` 下没有它们的 JSON 源（JSON 侧没有
/// 「通知返回值的清单」这个文件），故仍在这里手写。`延迟释放` 不同：它就是
/// `通知号段/` 下那条「延迟释放应答」声明的 `通知号`，**必须由生成物给出**。
pub mod 通知返回 {
    pub const 成功: isize = 0;
    pub const 失败: isize = -1;
    /// 延迟释放：本扩展还需要被延迟释放（有引用或挂了钩子）。
    ///
    /// **值只有一个来源**：生成物里那条「延迟释放应答」通知号常量
    /// （源：`契约声明/通知号段/` 下那份声明，文件名即通知号）。
    /// 这里只是把它转成 `isize`（通知函数的返回类型），**不另写一份数**。
    pub const 延迟释放: isize = crate::声明数据::通知号_2015 as isize;
}
