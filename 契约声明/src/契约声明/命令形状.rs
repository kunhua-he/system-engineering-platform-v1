//! 命令形状 —— 参数 · 命令 · 命令状态 · 执行函数 · 命令类别。
//!
//! 公开面经 `lib.rs` 再导出 ⇒ `v1_contract::参数信息` / `v1_contract::命令信息` /
//! `v1_contract::命令状态` / `v1_contract::执行函数` / `v1_contract::命令类别信息`
//! 逐字不变。

use crate::{能力号, 数据槽, 类型标签, 表段, 错误码};

/// 参数信息。**参数行序即契约**：一旦公布，不许重排、不许插入。
#[repr(C)]
pub struct 参数信息 {
    pub 名称: *const u8,
    pub 说明: *const u8,
    /// 类型标签，必须能在 `契约声明/类型声明/` 里查到。
    ///
    /// 型是 `类型标签`（号空间 newtype），不是裸 `u32`：拿能力号 / 资源号 / 错误码来顶替**编不过**。
    pub 类型标签: 类型标签,
    pub 状态位: u16,
    pub 默认值: 数据槽,
}

/// 命令状态位。
pub mod 命令状态 {
    /// 隐含：不出现在帮助与自动补全里。
    pub const 隐含: u16 = 1 << 2;
    /// 错误项：这一项**现在**不可用。**单独一位分不出「占位」与「已废止」**——
    /// 是否**永久**不可用由 `已废止` 位分。两个都要有。
    pub const 错误: u16 = 1 << 3;
    /// 已废止：这一项**永久**不可用。编号不回收、含义永不改写。
    ///
    /// **为什么与 `错误` 分开**：参照实现只有 `错误` 一位，于是调用侧分不出
    /// 「提供者今天不在（等它回来）」与「这个号永远不会有了（改用别的号）」——
    /// 而这两种情况的处置完全相反。这是不复刻的缺陷之一（`冻结登记.json` 有登记）。
    pub const 已废止: u16 = 1 << 10;
    /// 发布版禁用。
    pub const 发布禁用: u16 = 1 << 4;
    /// 对象拷贝命令。
    pub const 对象拷贝: u16 = 1 << 7;
    /// 对象释放命令。
    pub const 对象释放: u16 = 1 << 8;
    /// 对象构造命令。
    pub const 对象构造: u16 = 1 << 9;
}

/// 命令信息。
///
/// **字段顺序＝冻结区 + 旁路区**：旁路字段一律追加在尾部（旧读者仍能读前缀）。
/// 这是「新增段类型号不动旧段」在结构层的形态（同 `数据类型信息`）。
#[repr(C)]
pub struct 命令信息 {
    // ── 冻结区 ──
    pub 名称: *const u8,
    pub 说明: *const u8,
    pub 类别号: u16,
    pub 状态位: u16,
    /// 返回类型标签；0 表示无返回值。
    pub 返回类型: 类型标签,
    pub 用户级别: u16,
    pub 参数个数: u32,
    pub 参数表: *const 参数信息,
    // ── 旁路区（只增不改；一律追加）──
    /// **命令编号（显式）**。取自 `契约声明/能力声明/<编号>.json` 的「编号」。
    ///
    /// 早先 `平台信息` 里没有「编号」字段，注册表只能约定「编号 = 命令表下标（0 起）」。
    /// **实测咬人**（`冻结登记.json` 待办旁路 · 阻断级）：①「号只增不复用」判不了
    /// （重排一次表所有号静默全变）②占 `1xxx` 号段的扩展只要有一条 `错误` 状态位的命令，
    /// 就必然被判 `声明不自洽 { 命令号: 0 }`（段位口径 = 编号 / 号段类宽度，下标 0 的段位恒为 0）
    /// ③每份声明的编号都从 0 起 ⇒ 多声明共存时重号，「号段即归属」在命令编号上根本没落地。
    ///
    /// 显式给编号后：注册表**按编号查**（不按下标），建表要求**表按编号严格递增**（违反即 fail-closed）。
    /// 号**只增不复用、允许有洞**（宪法第 7 条）。
    pub 编号: 能力号,
    /// **可抛错误码**（表段<错误码>）：本命令在执行中可能抛出的错误码，取自
    /// `契约声明/能力声明/<编号>.json` 的「可抛错误码」（`格式说明.md` §三）。
    ///
    /// **没有它，实现侧扫描器判据 ③d2 结构性判不了**（恒报「未判」）：`格式说明.md` §三
    /// 早就要求声明写 `可抛错误码`，而实现侧 `命令信息` 没有承载它的字段 ⇒ 声明里的
    /// `可抛错误码` 在实现面上没有对照物。空表用 `表段::空实例()`（= 本命令不抛错，不是漏写）。
    pub 可抛错误码: 表段<错误码>,
}

/// 执行函数：**调用形状 1:1 复刻**——三参数，返回槽与参数槽分离，返回 void。
///
/// 失败靠错误段位，不靠返回值。
///
/// # ABI 为什么是 `C-unwind`
///
/// 扩展的执行函数可能 panic。Rust 1.71 起 panic 穿过 `extern "C"` 边界**直接 abort 进程**：
/// 底座与扩展同进程，一次扩展 panic 就带走整个网关，外层 `catch_unwind` 物理上接不住
/// （实测：`extern "C"` 下 panic ⇒ 退出码 134）。`C-unwind` 是 Rust 为此专开的 ABI：
/// panic 能穿过它回到调用方，由调度核心的 `catch_unwind` 接住并转成结构化失败码。
///
/// **它管不到的那一段**：扩展制品经 `dlopen` 进来时，两边的 Rust 运行时各自独立 ——
/// 那种边界上 panic 仍然是 abort（实测：`Rust cannot catch foreign exceptions`）。
/// 跨制品隔离由**跨进程执行域**承担（`进程池` / `进程调用`，崩溃报 `0034`），
/// 本 ABI 只管同运行时那条路。
pub type 执行函数 =
    unsafe extern "C-unwind" fn(返回槽: *mut 数据槽, 参数个数: u32, 参数表: *const 数据槽);

/// 命令类别信息 —— 一个命令类别的登记项（`命令信息.类别` 那个号的名字与说明）。
///
/// 形状照 `错误码信息` 的既有样子：显式号 + 保留位 + 名称 + 说明。
/// `类别号` 是 `u16`（与 `命令信息.类别` 同宽，逐位对应）；`保留` 写出来是为了宽度显式
/// （跨边界结构不许有隐式填充）。
#[repr(C)]
pub struct 命令类别信息 {
    /// 类别号。**就是 `命令信息.类别` 那个值**，也是 `命令类别/<类别号>.json` 的文件名。
    pub 类别号: u16,
    /// 保留：显式写出宽度（`命令信息.类别` 是 `u16`，本结构对齐它）。恒 0。
    pub 保留: u16,
    /// 类别名（NUL 结尾 UTF-8）。
    pub 名称: *const u8,
    /// 说明（NUL 结尾 UTF-8）。
    pub 说明: *const u8,
}
