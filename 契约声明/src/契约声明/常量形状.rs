//! 常量形状 —— 常量的排布与登记项。
//!
//! 公开面经 `lib.rs` 再导出 ⇒ `v1_contract::常量排布` / `v1_contract::常量信息` 逐字不变。

use crate::{常量号, 类型标签};

/// 常量排布。
pub mod 常量排布 {
    pub const 无值: u16 = 0;
    pub const 数值项: u16 = 1;
    pub const 逻辑: u16 = 2;
    pub const 文本值: u16 = 3;
}

/// 常量信息。
///
/// **字段顺序＝冻结区 + 旁路区**：旁路字段一律追加在尾部（旧读者仍能读前缀）。
#[repr(C)]
pub struct 常量信息 {
    // ── 冻结区 ──
    pub 名称: *const u8,
    pub 说明: *const u8,
    pub 排布: u16,
    /// 类型标签（`类型标签` 号空间）—— 不是裸 `u32`：与能力号/资源号/错误码互不能赋值。
    pub 类型标签: 类型标签,
    pub 文本值: *const u8,
    /// 数值常量一律双精度；逻辑常量用 0/1。
    pub 数值项: f64,
    // ── 旁路区（只增不改；一律追加）──
    /// **常量号（显式）**。与 `命令信息.编号` 同一个缺陷的同一份修法：
    /// 早先常量编号只能由常量表下标承担（`字段名册与引用方式.md` §三 原话
    /// 「常量号 = 常量表下标」），重排一次表所有号静默全变。
    ///
    /// 显式给号后：注册表**按常量号查**（不按下标），建表要求**表按常量号严格递增**。
    /// 号只增不复用、允许有洞。
    pub 常量号: 常量号,
}
