//! 台账形状 —— 载入台账与调用账本。都是**显式传入**的宿主侧账，不许落进程级全局。
//!
//! 公开面经 `lib.rs` 再导出 ⇒ `v1_contract::已载入台账` / `v1_contract::调用账本` 逐字不变。

use crate::{能力号, 号段空间, 号值};

/// 已载入台账 —— 谁已经载入了。
///
/// **由装载器持有、显式传入，不许用进程级全局**（`开发规范` B6）。
/// 判定六步里的 ②标识串唯一 ③号段不冲突 ⑤依赖都在 三项全靠它。
pub trait 已载入台账 {
    /// 这个标识串是否已被载入。
    fn 是否已载入(&self, 标识串: *const u8) -> bool;
    /// 这段号是否已被别的扩展占用。**必须带 `空间`**（见 `号段空间`）。
    fn 号段已占用(&self, 号空间: 号段空间, 区间起点: 号值, 区间终点: 号值) -> bool;
}

/// 调用账本 —— 配额与超时的记账处。
///
/// **按实例持有、显式传入**：账本若落进程级，多实例就不隔离（违反三条补缺陷之一）。
///
/// **两个时点必须分开，不许合成一个方法**：执行**前**只可能问「准不准调」，
/// 执行**后**才知道真实耗时。早先写成 `记账(号, 耗时毫秒) -> bool` 是错的——
/// 执行前拿不到耗时（只能拿预算冒充），执行后已经拦不住调用（返回 `false` 也晚了）。
/// 一次调用无法同时满足这两件事，所以是两个方法。
pub trait 调用账本 {
    /// 执行**前**问一次。返回 `false` = 超配额，本次调用**不许进入执行函数**。
    fn 准调(&self, 能力号: 能力号) -> bool;
    /// 执行**后**记一次。`耗时毫秒` 是本次**真实**耗时；账本可据此限速。
    /// 返回值忽略——执行已经发生，此刻返回什么都拦不住它。
    fn 记账(&self, 能力号: 能力号, 耗时毫秒: u64);
}
