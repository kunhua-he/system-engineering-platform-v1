/// 装包：接口说明段 + 能力码段 → 能力包件字节（`.支持库制品` 等）。
///
/// 指纹段由本函数自身算（它登的就是前两段的 sha256）。
pub fn 装包(接口说明段: &[u8], 能力码段: &[u8]) -> Vec<u8> {
    装包三段(接口说明段, 能力码段, 段类型_能力码)
}

pub fn 装包技能(接口说明段: &[u8], 技能文本: &str) -> Result<Vec<u8>, 技能容器错误> {
    let 包件 = 装包三段(接口说明段, 技能文本.as_bytes(), 段类型_技能本体);
    取技能本体文本(&包件)?;
    Ok(包件)
}

/// 装包（本体段号显式）：技能制品传 `段类型_技能本体`（`19`），支持库 / 模块传 `段类型_能力码`（`17`）。
pub fn 装包三段(接口说明段: &[u8], 本体段: &[u8], 本体段号: u8) -> Vec<u8> {
    let 本体段名: &[u8] = match 本体段号 {
        段类型_技能本体 => 段名_技能本体,
        段类型_本机执行体 => 段名_本机执行体,
        _ => 段名_能力码,
    };
    let 指纹段 = 编码指纹段(&[
        (段类型_接口说明, 接口说明段),
        (本体段号, 本体段),
    ]);
    let 段表: [(u8, &[u8], &[u8]); 3] = [
        (段类型_接口说明, 段名_接口说明, 接口说明段),
        (本体段号, 本体段名, 本体段),
        (段类型_指纹, 段名_指纹, 指纹段.as_slice()),
    ];
    let mut 输出缓冲 = Vec::with_capacity(
        文件头魔数.len() + 3 * 段头长度 + 接口说明段.len() + 本体段.len() + 指纹段.len(),
    );
    输出缓冲.extend_from_slice(&文件头魔数);
    for (号值, 段名, 数据字节) in 段表 {
        输出缓冲.extend_from_slice(&写段头(号值, 段名, 数据字节));
        输出缓冲.extend_from_slice(数据字节);
    }
    输出缓冲
}

/// 字级 XOR 折叠：小端切 4 字节全异或，末不足 4 字节右侧补 0（算法与互操作路同源）。
fn 折(字节: &[u8]) -> u32 {
    let mut 累加值 = 0u32;
    let mut 读游标 = 0usize;
    while 读游标 < 字节.len() {
        let 末位 = (读游标 + 4).min(字节.len());
        let mut 四字节 = [0u8; 4];
        四字节[..末位 - 读游标].copy_from_slice(&字节[读游标..末位]);
        累加值 ^= u32::from_le_bytes(四字节);
        读游标 += 4;
    }
    累加值
}

/// 由内容复算段头 `+0x04` 校验槽：`折(8 字节全零 ‖ 段头[0x08..] ‖ 段数据前 8 ‖ 4 字节全零 ‖ 段数据[12..])`。
fn 算段头校验(段头字节: &[u8], 数据字节: &[u8]) -> u32 {
    let mut 缓冲 = Vec::with_capacity(8 + 段头字节.len() + 数据字节.len());
    缓冲.extend_from_slice(&[0u8; 8]);
    if 段头字节.len() > 8 {
        缓冲.extend_from_slice(&段头字节[8..]);
    }
    let 数据首段 = 数据字节.len().min(8);
    缓冲.extend_from_slice(&数据字节[..数据首段]);
    缓冲.extend_from_slice(&[0u8; 4]);
    if 数据字节.len() > 12 {
        缓冲.extend_from_slice(&数据字节[12..]);
    }
    折(&缓冲)
}

/// 写 44 字节段头。段名非空且 ≤ 27 字节（本件三段的段名是常量，恒成立）。
///
/// `数据字节` 用于**由内容复算校验槽**（`+0x04`）；调用方必须传入本段真实数据。
fn 写段头(号值: u8, 段名: &[u8], 数据字节: &[u8]) -> [u8; 段头长度] {
    let 标记首 = 段头标记首.to_le_bytes();
    let 标记次 = 段头标记次.to_le_bytes();
    let mut 段头字节 = [0u8; 段头长度];
    段头字节[0x00..0x02].copy_from_slice(&标记首);
    段头字节[0x02..0x04].copy_from_slice(&标记次);
    // 0x04..0x08 段校验值：由内容复算（折(段头全零8 ‖ 段头[8..] ‖ 段数据前 8 ‖ 全零4 ‖ 段数据[12..])）。
    // 新造的段也有内容可算 ⇒ 不再写 0（写 0 的段过不了本件的复算判据）；回填在本函数尾。
    段头字节[0x08..0x0A].copy_from_slice(&标记首);
    段头字节[0x0A] = 0x00;
    段头字节[0x0B] = 号值;
    段头字节[0x0C..0x0C + 名称区容量].copy_from_slice(&编名称区(段名, 号值));
    段头字节[0x27..0x29].copy_from_slice(&标记首);
    段头字节[0x29] = 0x00;
    段头字节[0x2A] = 0x00;
    段头字节[0x2B] = 0x00;
    // 整条段头已备齐、段数据已知 ⇒ 由内容复算校验槽（不写 0，也不读任何快照）。
    let 校验和 = 算段头校验(&段头字节, 数据字节);
    段头字节[0x04..0x08].copy_from_slice(&校验和.to_le_bytes());
    段头字节
}

/// 段名明文 → 名称区 27 字节（`段名 + NUL + 补零`，异或密钥 `73 00 <段类型> 19`）。
fn 编名称区(段名: &[u8], 号值: u8) -> [u8; 名称区容量] {
    let mut 明文 = [0u8; 名称区容量];
    let 元素个数 = 段名.len().min(名称区容量);
    明文[..元素个数].copy_from_slice(&段名[..元素个数]);
    let 密钥 = 名称区密钥(号值);
    let mut 密文字节 = [0u8; 名称区容量];
    for 位次 in 0..名称区容量 {
        // 名称区起点 0x0C 是 4 的倍数 ⇒ 第 位次 字节用的密钥相位就是 位次 % 4。
        密文字节[位次] = 明文[位次] ^ 密钥[位次 % 4];
    }
    密文字节
}

