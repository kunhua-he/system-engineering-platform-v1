#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 能力包件三段 {
    pub 接口说明段: Vec<u8>,
    pub 能力码段: Vec<u8>,
    pub 指纹段: Vec<u8>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 本体段类别 {
    能力码,
    技能本体,
    /// 模块制品 · 本机执行体段（段 `20`）。依据 `项目文档/决策记录/2026-10-12_模块执行体承载与编译裁决.md`。
    本机执行体,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 能力包件类型化 {
    pub 接口说明段: Vec<u8>,
    pub 本体段类别: 本体段类别,
    pub 本体段: Vec<u8>,
    pub 指纹段: Vec<u8>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 技能容器错误 {
    容器损坏(容器错误),
    本体类别不符 { 本体段号: u8 },
    指纹不符,
    正文编码不符,
}

/// 容器错误。结构化段位，不是字符串、不是 panic。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 容器错误 {
    /// 文件头魔数不符。
    魔数不符,
    /// 段头不足 44 字节。
    段头截断 { 字节位置: u64 },
    /// 段头里的标记 / 尾标志不对。
    段头标记不符 { 字节位置: u64 },
    /// 段类型号不是能力包件三段（`16`/`17`/`18`/`19`）。
    段类型未知 { 字节位置: u64, 段号: u8 },
    /// 段数不是 3。
    段数不符 { 实际: u64 },
    /// 第几段的段类型号与能力包件的段序不符。
    段类型次序不符 { 第几段: u64, 段号: u8 },
    /// 指纹段自身解不开（截断 / 条数不符 / 尾部多余）。
    指纹段损坏,
}

