// 一 写：装包
// ─────────────────────────────────────────────────────────────────────────────

/// 装包：接口说明段 + 能力码段 → 能力包件字节（`.支持库制品` 等）。
///
/// 指纹段由本函数自身算（它登的就是前两段的 sha256）。
pub fn 装包(接口说明段: &[u8], 能力码段: &[u8]) -> Vec<u8> {
    let 指纹段 = 编码指纹段(&[
        (段类型_接口说明, 接口说明段),
        (段类型_能力码, 能力码段),
    ]);
    let 段表: [(u8, &[u8], &[u8]); 3] = [
        (段类型_接口说明, 段名_接口说明, 接口说明段),
        (段类型_能力码, 段名_能力码, 能力码段),
        (段类型_指纹, 段名_指纹, 指纹段.as_slice()),
    ];
    let mut 输出缓冲 = Vec::with_capacity(
        文件头魔数.len() + 3 * 段头长度 + 接口说明段.len() + 能力码段.len() + 指纹段.len(),
    );
    输出缓冲.extend_from_slice(&文件头魔数);
    for (号值, 段名, 数据) in 段表 {
        输出缓冲.extend_from_slice(&写段头(号值, 段名));
        输出缓冲.extend_from_slice(数据);
    }
    输出缓冲
}

/// 写 44 字节段头。段名非空且 ≤ 27 字节（本件三段的段名是常量，恒成立）。
fn 写段头(号值: u8, 段名: &[u8]) -> [u8; 段头长度] {
    let 标记首 = 段头标记首.to_le_bytes();
    let 标记次 = 段头标记次.to_le_bytes();
    let mut 段头字节 = [0u8; 段头长度];
    段头字节[0x00..0x02].copy_from_slice(&标记首);
    段头字节[0x02..0x04].copy_from_slice(&标记次);
    // 0x04..0x08 段校验值：算法未证实（`.e` 容器一律原样搬运）；新造的段无源可搬 ⇒ 写 0。
    段头字节[0x08..0x0A].copy_from_slice(&标记首);
    段头字节[0x0A] = 0x00;
    段头字节[0x0B] = 号值;
    段头字节[0x0C..0x0C + 名称区容量].copy_from_slice(&编名称区(段名, 号值));
    段头字节[0x27..0x29].copy_from_slice(&标记首);
    段头字节[0x29] = 0x00;
    段头字节[0x2A] = 0x00;
    段头字节[0x2B] = 0x00;
    段头字节
}

/// 段名明文 → 名称区 27 字节（`段名 + NUL + 补零`，异或密钥 `73 00 <段类型> 19`）。
fn 编名称区(段名: &[u8], 号值: u8) -> [u8; 名称区容量] {
    let mut 明文 = [0u8; 名称区容量];
    let 个数 = 段名.len().min(名称区容量);
    明文[..个数].copy_from_slice(&段名[..个数]);
    let 密钥 = 名称区密钥(号值);
    let mut 密文 = [0u8; 名称区容量];
    for 位次 in 0..名称区容量 {
        // 名称区起点 0x0C 是 4 的倍数 ⇒ 第 位次 字节用的密钥相位就是 位次 % 4。
        密文[位次] = 明文[位次] ^ 密钥[位次 % 4];
    }
    密文
}

// ─────────────────────────────────────────────────────────────────────────────
// 二 读：解包
// ─────────────────────────────────────────────────────────────────────────────

/// 解包：能力包件字节 → 三段。
///
/// 段头校验 · 段类型号只认 `16`/`17`/`18` · 名称区密钥照旧。**只解形状，不校哈希**
/// （哈希校验是 [`校验`] 的事）。
pub fn 解包(字节: &[u8]) -> Result<能力包件三段, 容器错误> {
    if 字节.len() < 文件头魔数.len() || 字节[..文件头魔数.len()] != 文件头魔数 {
        return Err(容器错误::魔数不符);
    }
    let mut 段表: Vec<(u8, Vec<u8>)> = Vec::new();
    let mut 位置 = 文件头魔数.len();
    while 位置 < 字节.len() {
        let 号值 = 解析段头(字节, 位置)?;
        let 数据起点 = 位置 + 段头长度;
        let 下一段头 = 找下一段头(字节, 数据起点);
        let 数据尾 = 下一段头.unwrap_or(字节.len());
        段表.push((号值, 字节[数据起点..数据尾].to_vec()));
        match 下一段头 {
            Some(下一位置) => 位置 = 下一位置,
            None => break,
        }
    }

    let 段数 = 段表.len();
    if 段数 != 3 {
        return Err(容器错误::段数不符 { 实际: 段数 as u64 });
    }
    let 期望号表 = [段类型_接口说明, 段类型_能力码, 段类型_指纹];
    let mut 迭代 = 段表.into_iter();
    let mut 数据表: [Vec<u8>; 3] = [Vec::new(), Vec::new(), Vec::new()];
    for (序号, 期望号) in 期望号表.iter().enumerate() {
        let Some((号值, 数据)) = 迭代.next() else {
            return Err(容器错误::段数不符 { 实际: 段数 as u64 });
        };
        if 号值 != *期望号 {
            return Err(容器错误::段类型次序不符 { 第几段: 序号 as u64, 号: 号值 });
        }
        数据表[序号] = 数据;
    }
    let [接口说明段, 能力码段, 指纹段] = 数据表;
    Ok(能力包件三段 { 接口说明段, 能力码段, 指纹段 })
}

/// 解析 `位置` 处的段头，返回段类型号。
fn 解析段头(字节: &[u8], 位置: usize) -> Result<u8, 容器错误> {
    if 位置 + 段头长度 > 字节.len() {
        return Err(容器错误::段头截断 { 位置: 位置 as u64 });
    }
    let 段头字节 = &字节[位置..位置 + 段头长度];
    let 标记首 = 段头标记首.to_le_bytes();
    let 标记次 = 段头标记次.to_le_bytes();
    if 段头字节[0x00..0x02] != 标记首
        || 段头字节[0x02..0x04] != 标记次
        || 段头字节[0x08..0x0A] != 标记首
        || 段头字节[0x0A] != 0x00
    {
        return Err(容器错误::段头标记不符 { 位置: 位置 as u64 });
    }
    let 号值 = 段头字节[0x0B];
    if !是能力包件段类型(号值) {
        return Err(容器错误::段类型未知 { 位置: 位置 as u64, 号: 号值 });
    }
    if !段头尾部合规(&段头字节[0x27..0x2C]) {
        return Err(容器错误::段头标记不符 { 位置: 位置 as u64 });
    }
    Ok(号值)
}

/// 段类型号是不是能力包件三段之一。
fn 是能力包件段类型(号值: u8) -> bool {
    matches!(号值, 段类型_接口说明 | 段类型_能力码 | 段类型_指纹)
}

/// 段头 0x27..0x2C 五字节是否合规。能力包件三段（`16–18`）恒 `19 73 00 00 00`。
fn 段头尾部合规(尾部: &[u8]) -> bool {
    尾部 == [0x19, 0x73, 0x00, 0x00, 0x00]
}

/// 从 `起点` 起向后找下一处段头起点。
fn 找下一段头(字节: &[u8], 起点: usize) -> Option<usize> {
    if 字节.len() < 段头长度 {
        return None;
    }
    let 尾部 = 字节.len() - 段头长度;
    (起点..=尾部).find(|&位置| 解析段头(字节, 位置).is_ok())
}

// ─────────────────────────────────────────────────────────────────────────────
// 三 校验：指纹段
// ─────────────────────────────────────────────────────────────────────────────

/// 校验一份包：前两段的 sha256 是否与指纹段登的一致。
///
/// `None` = 不是本形状的包（解不开 / 指纹段损坏）；`Some(真)` = 两段都没被换过；
/// `Some(假)` = 被换过。这是 `能力包件.md` §四 那个用途（「任何一边被换过都判得出来」）的落点。
pub fn 校验(字节: &[u8]) -> Option<bool> {
    let 解出包件 = 解包(字节).ok()?;
    let 指纹表 = 解指纹段(&解出包件.指纹段)?;
    if 指纹表.len() != 2 {
        return None;
    }
    let 期望表 = [
        (段类型_接口说明, 算指纹(&解出包件.接口说明段)),
        (段类型_能力码, 算指纹(&解出包件.能力码段)),
    ];
    Some(指纹表.iter().zip(期望表.iter()).all(|(实测项, (期望号, 期望哈希))| {
        实测项.段类型号 == *期望号 && 实测项.哈希 == *期望哈希
    }))
}

/// 算一份指纹段数据：`u32 条数 · 每条 ( u8 段类型号 + 32 字节 sha256 )`。
pub fn 编码指纹段(段们: &[(u8, &[u8])]) -> Vec<u8> {
    let mut 输出缓冲 = Vec::with_capacity(4 + 段们.len() * (1 + 指纹宽度));
    输出缓冲.extend_from_slice(&(段们.len() as u32).to_le_bytes());
    for (号值, 数据) in 段们 {
        输出缓冲.push(*号值);
        输出缓冲.extend_from_slice(&算指纹(数据));
    }
    输出缓冲
}

/// 指纹段数据 → 项表。`None` = 截断 / 尾部多余字节。
///
/// **只做形状解，不重算哈希**：重算要拿原段数据，那是 [`校验`] 的事。
pub fn 解指纹段(字节: &[u8]) -> Option<Vec<段指纹>> {
    if 字节.len() < 4 {
        return None;
    }
    let 条数 = u32::from_le_bytes(字节[..4].try_into().ok()?) as usize;
    let 每项 = 1 + 指纹宽度;
    if 字节.len() - 4 != 条数 * 每项 {
        return None;
    }
    let mut 输出缓冲 = Vec::with_capacity(条数);
    for 序号 in 0..条数 {
        let 起点 = 4 + 序号 * 每项;
        let mut 哈希 = [0u8; 指纹宽度];
        哈希.copy_from_slice(&字节[起点 + 1..起点 + 每项]);
        输出缓冲.push(段指纹 { 段类型号: 字节[起点], 哈希 });
    }
    Some(输出缓冲)
}

