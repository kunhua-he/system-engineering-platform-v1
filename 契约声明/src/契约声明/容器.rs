/// 校验一份包：前两段的 sha256 是否与指纹段登的一致。
///
/// `None` = 不是本形状的包（解不开 / 指纹段损坏）；`Some(真)` = 两段都没被换过；
/// `Some(假)` = 被换过。这是 `能力包件.md` §四 那个用途（「任何一边被换过都判得出来」）的落点。
pub fn 校验段指纹(字节: &[u8]) -> Option<bool> {
    let 解出包件 = 解包类型化(字节).ok()?;
    let 指纹表 = 解指纹段(&解出包件.指纹段)?;
    if 指纹表.len() != 2 {
        return None;
    }
    let 本体段号 = match 解出包件.本体段类别 {
        本体段类别::能力码 => 段类型_能力码,
        本体段类别::技能本体 => 段类型_技能本体,
        本体段类别::本机执行体 => 段类型_本机执行体,
    };
    let 期望表 = [
        (段类型_接口说明, 算指纹(&解出包件.接口说明段)),
        (本体段号, 算指纹(&解出包件.本体段)),
    ];
    Some(指纹表.iter().zip(期望表.iter()).all(|(实测项, (期望号, 期望哈希))| {
        实测项.段类型号 == *期望号 && 实测项.哈希字节 == *期望哈希
    }))
}

/// 算一份指纹段数据：`u32 条数 · 每条 ( u8 段类型号 + 32 字节 sha256 )`。
pub fn 编码指纹段(段们: &[(u8, &[u8])]) -> Vec<u8> {
    let mut 输出缓冲 = Vec::with_capacity(4 + 段们.len() * (1 + 指纹宽度));
    输出缓冲.extend_from_slice(&(段们.len() as u32).to_le_bytes());
    for (号值, 数据字节) in 段们 {
        输出缓冲.push(*号值);
        输出缓冲.extend_from_slice(&算指纹(数据字节));
    }
    输出缓冲
}

/// 指纹段数据 → 项表。`None` = 截断 / 尾部多余字节。
///
/// **只做形状解，不重算哈希**：重算要拿原段数据，那是 [`校验段指纹`] 的事。
pub fn 解指纹段(字节: &[u8]) -> Option<Vec<段指纹>> {
    if 字节.len() < 4 {
        return None;
    }
    let 条目个数 = u32::from_le_bytes(字节[..4].try_into().ok()?) as usize;
    let 每项 = 1 + 指纹宽度;
    if 字节.len() - 4 != 条目个数 * 每项 {
        return None;
    }
    let mut 输出缓冲 = Vec::with_capacity(条目个数);
    for 序号 in 0..条目个数 {
        let 起点 = 4 + 序号 * 每项;
        let mut 哈希字节 = [0u8; 指纹宽度];
        哈希字节.copy_from_slice(&字节[起点 + 1..起点 + 每项]);
        输出缓冲.push(段指纹 { 段类型号: 字节[起点], 哈希字节 });
    }
    Some(输出缓冲)
}

