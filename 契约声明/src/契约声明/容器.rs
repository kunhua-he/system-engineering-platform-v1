//! 容器 —— 能力包件（`.支持库制品` · `.模块制品` · `.技能制品`）的容器编解码。
//!
//! 上级：`契约声明/` ／ 裁定：`项目文档/决策记录/2026-09-28_核心后缀表.md`（制品后缀一律自定义）
//! · `项目文档/设计文档/能力包件.md` §一（三段：接口说明 `16` · 能力码 `17` · 指纹 `18`）
//! · `项目文档/决策记录/2026-09-27_语言主线三缺口裁决.md` §三（段类型号取 u8 空洞 `16–18`）。
//!
//! # 为什么在这里（唯一一份实现）
//!
//! **能力包件三段的编解码只此一份实现**（接口说明 `16` · 本体 `17`/`19` · 指纹 `18`）：底座（读 `.支持库制品` 取能力码段）与扩展
//! （1106 装包）都依赖 `v1-contract`（`README.md` §六）⇒ 放这里共用；装配侧 bin 与扩展侧都**转调本件**。
//! **`.e` 互操作路的骨架另算**：`编译器支持库/src/容器/` 是同一套 44 字节段头的另一份实现，服务 `.e` 的 `1–15`/`255` —— 跨语言/跨层不许硬合。
//!
//! # 骨架逐字节同构（不许自创）
//!
//! 44 字节段头 · 段类型号在盘面是 `u8` · 名称区异或密钥 —— 照
//! `扩展根目录/原子支持库/编译器支持库/src/容器/`（`.e` 互操作路的容器层，与本件同源）。
//! **本件只认能力包件三段**（`16`/`17`/`18`/`19`）；参照实现的 `1–15`/`255` 一律 `段类型未知`。
//! 段边界只能靠扫描（无段长字段）⇒ **装包当场验往返**。

use alloc::string::String;
use alloc::vec::Vec;

/// 文件头魔数（8 字节）。与 `.e` 容器同源。
pub const 文件头魔数: [u8; 8] = *b"CNWTEPRG";

/// 段头长度（字节）。冻结形状：`u32 校验和 + u8 段类型 + 27 字节名称区 + u32 段名长 + u64 数据长 = 44`。
pub const 段头长度: usize = 44;

/// 段头里的两个固定标记（小端写出 `19 73` / `11 15`）。
const 段头标记首: u16 = 0x7319;
const 段头标记次: u16 = 0x1511;

/// 能力包件三段的段类型号（`16–19`；登记见 `契约声明/冻结登记.json` 的 `段类型号登记`）。
///
/// 三段是「接口说明 + 本体 + 指纹」，本体段号随种类定：
/// 支持库 / 模块的**本体**是能力码（`17`）；技能的**本体**是 md 正文（`技能本体` `19`）。
/// 依据：`扩展装载/后缀表.json` 的 `三段`（支持库 `16·17·18` · 模块 `16·17·18` · 技能 `16·19·18`）。
pub const 段类型_接口说明: u8 = 16;
pub const 段类型_能力码: u8 = 17;
pub const 段类型_指纹: u8 = 18;
/// 技能制品 · 技能本体段（md 正文）—— 技能没有码段，本体装这一段。
pub const 段类型_技能本体: u8 = 19;

/// 模块制品 · 本机执行体段（本机机器码 · 构建侧产出）。段 `17` 的 WASM 含义保留给旧模块只读兼容。
/// 依据：`项目文档/决策记录/2026-10-12_模块执行体承载与编译裁决.md`。
pub const 段类型_本机执行体: u8 = 20;

/// 能力包件三段的段名（写入段头 27 字节名称区）。
const 段名_接口说明: &[u8] = "接口说明".as_bytes();
const 段名_能力码: &[u8] = "能力码".as_bytes();
const 段名_指纹: &[u8] = "指纹".as_bytes();
const 段名_技能本体: &[u8] = "技能本体".as_bytes();
const 段名_本机执行体: &[u8] = "本机执行体".as_bytes();

/// 名称区容量（字节）。
const 名称区容量: usize = 27;

/// 指纹宽度（sha256）。
pub const 指纹宽度: usize = 32;

/// 名称区异或密钥：`73 00 <段类型> 19`，相位锚在**段头起点**。
pub fn 名称区密钥(段类型: u8) -> [u8; 4] {
    [0x73, 0x00, 段类型, 0x19]
}

/// 一段的指纹项：段类型号 + 该段数据的 sha256。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 段指纹 {
    pub 段类型号: u8,
    pub 哈希字节: [u8; 指纹宽度],
}

/// 解包结果：三段各自的**数据字节**。
///
/// 返回原始字节而不是解好的结构：接口说明的六字段什么时候解，由调用方定
