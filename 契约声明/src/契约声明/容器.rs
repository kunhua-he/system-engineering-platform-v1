/// 解包：能力包件字节 → 三段。
///
/// 段头校验 · 段类型号只认 `16`/`17`/`18`/`19` · 名称区密钥照旧。**只解形状，不校哈希**
/// （哈希校验是 [`校验段指纹`] 的事）。
pub fn 解包(字节: &[u8]) -> Result<能力包件三段, 容器错误> {
    let 解出包件 = 解包类型化(字节)?;
    Ok(能力包件三段 {
        接口说明段: 解出包件.接口说明段,
        能力码段: 解出包件.本体段,
        指纹段: 解出包件.指纹段,
    })
}

pub fn 解包类型化(字节: &[u8]) -> Result<能力包件类型化, 容器错误> {
    let 段表 = 容器分段::拆分容器段(字节)?;

    let 段数 = 段表.len();
    if 段数 != 3 {
        return Err(容器错误::段数不符 { 实际: 段数 as u64 });
    }
    // 三段次序固定：首段是接口说明（`16`）、末段是指纹（`18`）；中间那一段是**本体段**，
    // 号随种类定 —— 支持库 / 模块是能力码 `17`，技能是技能本体 `19`。
    let 本体段号 = 段表[1].0;
    if !matches!(本体段号, 段类型_能力码 | 段类型_技能本体 | 段类型_本机执行体) {
        return Err(容器错误::段类型次序不符 { 第几段: 1, 段号: 本体段号 });
    }
    let 期望号表 = [段类型_接口说明, 本体段号, 段类型_指纹];
    let mut 迭代 = 段表.into_iter();
    let mut 数据表: [Vec<u8>; 3] = [Vec::new(), Vec::new(), Vec::new()];
    for (序号, 期望号) in 期望号表.iter().enumerate() {
        let Some((号值, 数据字节)) = 迭代.next() else {
            return Err(容器错误::段数不符 { 实际: 段数 as u64 });
        };
        if 号值 != *期望号 {
            return Err(容器错误::段类型次序不符 { 第几段: 序号 as u64, 段号: 号值 });
        }
        数据表[序号] = 数据字节;
    }
    let [接口说明段, 本体段, 指纹段] = 数据表;
    let 本体段类别 = match 本体段号 {
        段类型_技能本体 => 本体段类别::技能本体,
        段类型_本机执行体 => 本体段类别::本机执行体,
        _ => 本体段类别::能力码,
    };
    Ok(能力包件类型化 { 接口说明段, 本体段类别, 本体段, 指纹段 })
}

pub fn 取技能本体文本(字节: &[u8]) -> Result<String, 技能容器错误> {
    let 解出包件 = 解包类型化(字节).map_err(技能容器错误::容器损坏)?;
    if 解出包件.本体段类别 != 本体段类别::技能本体 {
        return Err(技能容器错误::本体类别不符 { 本体段号: 段类型_能力码 });
    }
    if 校验段指纹(字节) != Some(true) {
        return Err(技能容器错误::指纹不符);
    }
    String::from_utf8(解出包件.本体段).map_err(|_| 技能容器错误::正文编码不符)
}

