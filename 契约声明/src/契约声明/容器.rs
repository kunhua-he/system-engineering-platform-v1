//! 都依赖 `v1-contract`（`README.md` §六：扩展只许依赖 `契约声明/`）⇒ 放这里两边共用。
//! 装配侧构建期 bin（`examples/装支持库制品.rs`）与扩展侧（`能力包件/装包.rs` · `能力包件/指纹.rs`）都**转调本件**。
//!
//! # 骨架逐字节同构（不许自创）
//!
//! 44 字节段头 · 段类型号在盘面是 `u8` · 名称区异或密钥 —— 照
//! `扩展根目录/原子支持库/编译器支持库/src/容器/`（`.e` 互操作路的容器层，与本件同源）。
//! **本件只认能力包件三段**（`16`/`17`/`18`）；参照实现的 `1–15`/`255` 一律 `段类型未知`。
//! 段边界只能靠扫描（无段长字段）⇒ **装包当场验往返**。

use alloc::vec::Vec;

/// 文件头魔数（8 字节）。与 `.e` 容器同源。
pub const 文件头魔数: [u8; 8] = *b"CNWTEPRG";

/// 段头长度（字节）。冻结形状：`u32 校验和 + u8 段类型 + 27 字节名称区 + u32 段名长 + u64 数据长 = 44`。
pub const 段头长度: usize = 44;

/// 段头里的两个固定标记（小端写出 `19 73` / `11 15`）。
const 段头标记首: u16 = 0x7319;
const 段头标记次: u16 = 0x1511;

/// 能力包件三段的段类型号（u8 空洞 `16–18`；登记见 `契约声明/冻结登记.json`）。
pub const 段类型_接口说明: u8 = 16;
pub const 段类型_能力码: u8 = 17;
pub const 段类型_指纹: u8 = 18;

/// 能力包件三段的段名（写入段头 27 字节名称区）。
const 段名_接口说明: &[u8] = "接口说明".as_bytes();
const 段名_能力码: &[u8] = "能力码".as_bytes();
const 段名_指纹: &[u8] = "指纹".as_bytes();

/// 名称区容量（字节）。
const 名称区容量: usize = 27;

/// 指纹宽度（sha256）。
pub const 指纹宽度: usize = 32;

/// 名称区异或密钥：`73 00 <段类型> 19`，相位锚在**段头起点**。
pub fn 名称区密钥(段类型: u8) -> [u8; 4] {
    [0x73, 0x00, 段类型, 0x19]
}

/// 一段的指纹项：段类型号 + 该段数据的 sha256。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct 段指纹 {
    pub 段类型号: u8,
    pub 哈希: [u8; 指纹宽度],
}

/// 解包结果：三段各自的**数据字节**。
///
/// 返回原始字节而不是解好的结构：接口说明的六字段什么时候解，由调用方定
/// （它才知道要不要看那一段）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 能力包件三段 {
    pub 接口说明段: Vec<u8>,
    pub 能力码段: Vec<u8>,
    pub 指纹段: Vec<u8>,
}

/// 容器错误。结构化段位，不是字符串、不是 panic。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 容器错误 {
    /// 文件头魔数不符。
    魔数不符,
    /// 段头不足 44 字节。
    段头截断 { 位置: u64 },
    /// 段头里的标记 / 尾标志不对。
    段头标记不符 { 位置: u64 },
    /// 段类型号不是能力包件三段（`16`/`17`/`18`）。
    段类型未知 { 位置: u64, 号: u8 },
    /// 段数不是 3。
    段数不符 { 实际: u64 },
    /// 第几段的段类型号与能力包件的段序不符。
    段类型次序不符 { 第几段: u64, 号: u8 },
    /// 指纹段自身解不开（截断 / 条数不符 / 尾部多余）。
    指纹段损坏,
}

