use super::{容器错误, 文件头魔数, 段头长度, 段头标记次, 段头标记首, 段类型_指纹, 段类型_技能本体, 段类型_接口说明, 段类型_能力码};
use alloc::vec::Vec;

pub(super) fn 拆分容器段(字节: &[u8]) -> Result<Vec<(u8, Vec<u8>)>, 容器错误> {
    if 字节.len() < 文件头魔数.len() || 字节[..文件头魔数.len()] != 文件头魔数 {
        return Err(容器错误::魔数不符);
    }
    let mut 段表 = Vec::new();
    let mut 字节位置 = 文件头魔数.len();
    while 字节位置 < 字节.len() {
        let 号值 = 解析段头(字节, 字节位置)?;
        let 数据起点 = 字节位置 + 段头长度;
        let 下一段头 = 找下一段头(字节, 数据起点);
        let 数据尾 = 下一段头.unwrap_or(字节.len());
        段表.push((号值, 字节[数据起点..数据尾].to_vec()));
        match 下一段头 {
            Some(下一位置) => 字节位置 = 下一位置,
            None => break,
        }
    }
    Ok(段表)
}

fn 解析段头(字节: &[u8], 字节位置: usize) -> Result<u8, 容器错误> {
    if 字节位置 + 段头长度 > 字节.len() {
        return Err(容器错误::段头截断 { 字节位置: 字节位置 as u64 });
    }
    let 段头字节 = &字节[字节位置..字节位置 + 段头长度];
    let 标记首 = 段头标记首.to_le_bytes();
    let 标记次 = 段头标记次.to_le_bytes();
    if 段头字节[0x00..0x02] != 标记首
        || 段头字节[0x02..0x04] != 标记次
        || 段头字节[0x08..0x0A] != 标记首
        || 段头字节[0x0A] != 0x00
    {
        return Err(容器错误::段头标记不符 { 字节位置: 字节位置 as u64 });
    }
    let 号值 = 段头字节[0x0B];
    if !是能力包件段类型(号值) {
        return Err(容器错误::段类型未知 { 字节位置: 字节位置 as u64, 段号: 号值 });
    }
    if !段头尾部合规(&段头字节[0x27..0x2C]) {
        return Err(容器错误::段头标记不符 { 字节位置: 字节位置 as u64 });
    }
    Ok(号值)
}

fn 是能力包件段类型(号值: u8) -> bool {
    matches!(号值, 段类型_接口说明 | 段类型_能力码 | 段类型_指纹 | 段类型_技能本体)
}

fn 段头尾部合规(尾部: &[u8]) -> bool {
    尾部 == [0x19, 0x73, 0x00, 0x00, 0x00]
}

fn 找下一段头(字节: &[u8], 起点: usize) -> Option<usize> {
    if 字节.len() < 段头长度 {
        return None;
    }
    let 尾部 = 字节.len() - 段头长度;
    (起点..=尾部).find(|&字节位置| 解析段头(字节, 字节位置).is_ok())
}
