/// 错误码信息 —— 一个错误码的登记项。
///
/// **为什么必须在契约里**：README 第一节的宪法级判据是「**失败可编程处理**：错误是带段位的
/// 结构化码，调用方能据此判断可重试、可自愈、需人工」。没有这个型，那三项在运行期
/// **一项都拿不到**——判据就成了一句空话（生成物只能把它们写进注释）。
///
/// 三项业务判断用 `u8`（0/1）而不是 `bool`：跨边界只走定长槽，宽度要显式。
#[repr(C)]
pub struct 错误码信息 {
    /// 完整 4 位码：`段位 × 1000 + 序号`。**就是 `错误码表/<码>.json` 的文件名。**
    pub 码: u32,
    /// 段位 = 码的首位十进制数字。**冗余登记项**：可从 `码` 导出，故意写出来由验证面
    /// 交叉比对抓错（写错了能被判据抓住，而不是默默按错的用）。
    pub 段位: u32,
    pub 名称: *const u8,
    pub 说明: *const u8,
    /// 可重试：重试有意义（例如瞬时故障）。
    pub 可重试: u8,
    /// 可自愈：平台自身能补上，不需要人（例如依赖没载入，先载入它再重试）。
    pub 可自愈: u8,
    /// 需人工：只能由人裁决（例如两个文件声明了同一个号）。
    pub 需人工: u8,
    pub 保留: u8,
}
