//! 号段形状 —— 一段号（闭区间）与它所属的命名空间。
//!
//! 公开面经 `lib.rs` 再导出 ⇒ `v1_contract::号段` / `v1_contract::号段空间` 逐字不变。

use crate::号值;

/// 号段所属的命名空间。
///
/// **能力号与通知号是两个独立命名空间**，各有自身的区间：同一个 `[1000,1999]`
/// 在能力号空间和通知号空间里可以**各占一次**，不算冲突。
///
/// 为什么单列一个型：早先 `号段已占用(起, 止)` 没有这个参数，实现只能把两本账
/// **取并集**判——于是「扩展占能力 1000–6999」会被底座占的「通知 0–999」误判成冲突，
/// 也就是**假冲突**：一个完全合法的扩展载不进来。参数不能靠约定补，要进类型。
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 号段空间 {
    能力号,
    通知号,
}

/// 一段号。闭区间 `[起, 止]`。
///
/// 端点是 `号值`（空间无关的号值）—— 号段既装能力号段也装通知号段，属哪个空间由
/// `号段空间` 说明，故端点**不能**是 `能力号`（那会把通知号段错标成能力号）。
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct 号段 {
    pub 起: 号值,
    pub 止: 号值,
}

impl 号段 {
    /// 用裸 `u32` 端点造。**保留这个造口**：生成物 `声明数据.rs` 用 `号段::新建(0, 999)`
    /// 造段，而生成物不许手改（判据⑩要求它与生成器逐字节一致）。
    pub const fn 新建(区间起点: u32, 区间终点: u32) -> Self {
        Self { 起: 号值::新建(区间起点), 止: 号值::新建(区间终点) }
    }
    /// 含端点判定。`起 > 止` 的空段恒不相交。
    ///
    /// 形参是 `号值`（空间无关的号值）而非裸 `u32` —— 号段端点是 `号值`，同一把尺子。
    pub const fn 包含(&self, 端点: 号值) -> bool {
        self.起.取号值() <= 端点.取号值() && 端点.取号值() <= self.止.取号值()
    }
    /// 两段是否相交（含端点）。
    pub const fn 相交(&self, 另一份: &号段) -> bool {
        self.起.取号值() <= 另一份.止.取号值() && 另一份.起.取号值() <= self.止.取号值()
    }
}
