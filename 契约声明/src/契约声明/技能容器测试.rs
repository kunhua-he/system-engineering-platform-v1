#[test]
fn 技能截断容器拒取文() {
    let 技能包件 = 装包技能(b"\x01", "中文\n正文").unwrap();
    for 截断位置 in 0..技能包件.len() {
        let 截断包件 = &技能包件[..截断位置];
        assert!(取技能本体文本(截断包件).is_err(), "截断位置：{截断位置}");
        assert_ne!(校验段指纹(截断包件), Some(true));
    }
    assert_eq!(解包类型化(&技能包件[..8 + 段头长度 - 1]), Err(容器错误::段头截断 { 字节位置: 8 }));
}

#[test]
fn 技能未知段按严格裁决拒绝() {
    let mut 包件 = 装包技能(b"\x01", "正文").unwrap();
    包件[8 + 0x0B] = 99;
    assert_eq!(取技能本体文本(&包件), Err(技能容器错误::容器损坏(容器错误::段类型未知 { 字节位置: 8, 段号: 99 })));
}

#[test]
fn 技能指纹形状损坏拒取文() {
    let 指纹段 = 编码指纹段(&[(段类型_接口说明, b"\x01"), (段类型_技能本体, b"\x02")]);
    for 字节位置 in [0, 4, 指纹段.len() - 1] {
        let 包件 = 拼装段表(&[(段类型_接口说明, b"\x01"), (段类型_技能本体, b"\x02"), (段类型_指纹, &指纹段[..字节位置])]);
        assert_eq!(取技能本体文本(&包件), Err(技能容器错误::指纹不符));
    }
    let mut 坏包件 = 装包技能(b"\x01", "正文").unwrap();
    坏包件.push(0);
    assert_eq!(取技能本体文本(&坏包件), Err(技能容器错误::指纹不符));
}

#[test]
fn 技能正文伪段头歧义可复现() {
    let mut 正文段头 = 写段头(段类型_技能本体, b"", b"");
    正文段头[4..8].fill(0);
    let 返回文本 = String::from_utf8(正文段头.to_vec()).unwrap();
    let 包件 = 装包三段(b"\x01", 返回文本.as_bytes(), 段类型_技能本体);
    assert_eq!(解包类型化(&包件), Err(容器错误::段数不符 { 实际: 4 }));
    assert_eq!(装包技能(b"\x01", &返回文本), Err(技能容器错误::容器损坏(容器错误::段数不符 { 实际: 4 })));
}
