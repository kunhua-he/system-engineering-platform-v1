use super::*;
use alloc::string::String;

fn 拼装段表(段表: &[(u8, &[u8])]) -> Vec<u8> {
    let mut 输出缓冲 = 文件头魔数.to_vec();
    for (号值, 数据字节) in 段表 {
        let 段名 = match *号值 {
            段类型_接口说明 => 段名_接口说明,
            段类型_能力码 => 段名_能力码,
            段类型_技能本体 => 段名_技能本体,
            _ => 段名_指纹,
        };
        输出缓冲.extend_from_slice(&写段头(*号值, 段名, 数据字节));
        输出缓冲.extend_from_slice(数据字节);
    }
    输出缓冲
}

#[test]
fn 技能文本逐字往返() {
    let 接口说明段 = b"\x40\x1f\0\0";
    for 待测正文 in ["# 中文技能\n前提：只取文\n```rust\npanic!(\"不执行\")\n```\n", "", "\r\n", "混合文本 🧩\n下一行"] {
        let 技能包件 = 装包技能(接口说明段, 待测正文).unwrap();
        let 解出包件 = 解包类型化(&技能包件).unwrap();
        assert_eq!(解出包件.接口说明段, 接口说明段);
        assert_eq!(解出包件.本体段类别, 本体段类别::技能本体);
        assert_eq!(解出包件.本体段, 待测正文.as_bytes());
        assert_eq!(校验段指纹(&技能包件), Some(true));
        assert_eq!(取技能本体文本(&技能包件).unwrap(), 待测正文);
        assert_eq!(解包(&技能包件).unwrap().能力码段, 待测正文.as_bytes());
        assert_eq!(技能包件[8 + 段头长度 + 接口说明段.len() + 0x0B], 段类型_技能本体);
    }
}

#[test]
fn 能力制品仍保持兼容() {
    for 能力码段 in [b"\x7fELF\x02\x01\0\0".as_slice(), b"\0asm\x01\0\0\0".as_slice()] {
        let 包件 = 装包(b"\x52\x04\0\0", 能力码段);
        assert_eq!(包件, 装包三段(b"\x52\x04\0\0", 能力码段, 段类型_能力码));
        let 解出包件 = 解包类型化(&包件).unwrap();
        assert_eq!(解出包件.本体段类别, 本体段类别::能力码);
        assert_eq!(解出包件.本体段, 能力码段);
        assert_eq!(解包(&包件).unwrap().能力码段, 能力码段);
        assert_eq!(校验段指纹(&包件), Some(true));
    }
}

#[test]
fn 能力码制品拒绝技能取文() {
    let 包件 = 装包("接口".as_bytes(), "正文".as_bytes());
    assert_eq!(取技能本体文本(&包件), Err(技能容器错误::本体类别不符 { 本体段号: 段类型_能力码 }));
}

#[test]
fn 技能坏指纹拒取文() {
    let 技能包件 = 装包技能(b"\x01", "中文正文").unwrap();
    let 正文起点 = 8 + 2 * 段头长度 + 1;
    for 字节位置 in [8 + 段头长度, 正文起点, 技能包件.len() - 1] {
        let mut 坏包件 = 技能包件.clone();
        坏包件[字节位置] ^= 1;
        assert_eq!(校验段指纹(&坏包件), Some(false));
        assert_eq!(取技能本体文本(&坏包件), Err(技能容器错误::指纹不符));
    }
}

#[test]
fn 技能指纹不许冒用能力码号() {
    for 本体段号 in [段类型_能力码, 段类型_技能本体] {
        let mut 包件 = 装包三段(b"\x01", b"\x02", 本体段号);
        let 指纹起点 = 8 + 3 * 段头长度 + 2;
        包件[指纹起点 + 4 + 1 + 指纹宽度] = if 本体段号 == 段类型_技能本体 { 段类型_能力码 } else { 段类型_技能本体 };
        assert_eq!(校验段指纹(&包件), Some(false));
        if 本体段号 == 段类型_技能本体 {
            assert_eq!(取技能本体文本(&包件), Err(技能容器错误::指纹不符));
        }
    }
}

