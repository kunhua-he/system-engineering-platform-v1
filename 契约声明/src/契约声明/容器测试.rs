//! 容器测试 —— 写→读往返 · 反向样本 · 段类型号越界 · 指纹校验 · SHA-256 已知向量。
//!
//! 由 `容器.rs` 以 `#[path = "容器测试.rs"] mod 测试;` 挂载（拆件：一个关注点一个文件）。

use super::*;
use alloc::string::String;

fn 转十六进制(字节: &[u8]) -> String {
    字节.iter().map(|字节| alloc::format!("{字节:02x}")).collect()
}

/// **写→读往返**：装包再解包，三段逐字节相等。
#[test]
fn 装包解包往返三段逐字节相等() {
    let 接口说明段 = b"\x52\x04\x00\x00\x06\x00\x00\x00";
    let 能力码段 = b"\0asm\x01\0\0\0";
    let 包件 = 装包(接口说明段, 能力码段);

    assert_eq!(&包件[..8], &文件头魔数);
    assert_eq!(包件.len(), 8 + 3 * 段头长度 + 接口说明段.len() + 能力码段.len() + 4 + 2 * (1 + 指纹宽度));

    let 解出包件 = 解包(&包件).expect("自行装的反解得开");
    assert_eq!(解出包件.接口说明段, 接口说明段);
    assert_eq!(解出包件.能力码段, 能力码段);
    // 指纹段登的是前两段。
    let 指纹表 = 解指纹段(&解出包件.指纹段).expect("指纹段该解得开");
    assert_eq!(指纹表.len(), 2);
    assert_eq!(指纹表[0].段类型号, 段类型_接口说明);
    assert_eq!(指纹表[0].哈希字节, 算指纹(接口说明段));
    assert_eq!(指纹表[1].段类型号, 段类型_能力码);
    assert_eq!(指纹表[1].哈希字节, 算指纹(能力码段));
    // 校验：两段都没被换过。
    assert_eq!(校验段指纹(&包件), Some(true));
}

/// **反向样本**：改一个段头字节 ⇒ 解包必须报错，不许静默。
#[test]
fn 反向样本改段头字节即报错() {
    let 包件 = 装包(b"\x01\x02", b"\x03\x04");
    // 改第一段段头的魔术次标记（偏移 8 + 0x02）。
    let mut 坏件 = 包件.clone();
    坏件[8 + 0x02] ^= 0xFF;
    assert_eq!(解包(&坏件), Err(容器错误::段头标记不符 { 字节位置: 8 }));

    // 改第一段段头的尾标志（偏移 8 + 0x2A）。
    let mut 坏尾 = 包件.clone();
    坏尾[8 + 0x2A] = 0x03;
    assert_eq!(解包(&坏尾), Err(容器错误::段头标记不符 { 字节位置: 8 }));

    // 魔数不符。
    assert_eq!(解包(b"NOTMAGIC"), Err(容器错误::魔数不符));
    assert_eq!(解包(&[]), Err(容器错误::魔数不符));
}

/// **段类型号越界**：`1–15` / `255` / 任意非 `16–18` ⇒ 报错（只认能力包件三段）。
#[test]
fn 段类型号越界即报错() {
    let 包件 = 装包(b"\x01", b"\x02");
    for 越界号 in [1u8, 7, 15, 99, 255] {
        let mut 坏件 = 包件.clone();
        坏件[8 + 0x0B] = 越界号;
        assert_eq!(
            解包(&坏件),
            Err(容器错误::段类型未知 { 字节位置: 8, 段号: 越界号 }),
            "段类型号 {越界号} 必须报错"
        );
    }
}

/// **反向样本**：改过能力码段一个字节 ⇒ 校验当场报「被换过」（解包仍成立）。
#[test]
fn 校验抓改过码段() {
    let 接口说明段 = b"\x01\x02\x03";
    let 能力码段 = b"\x04\x05\x06";
    let 包件 = 装包(接口说明段, 能力码段);
    assert_eq!(校验段指纹(&包件), Some(true));

    // 能力码段数据起点 = 8 + 44(接口说明段头) + len(接口说明段) + 44(能力码段头)。
    let 码起点 = 8 + 段头长度 + 接口说明段.len() + 段头长度;
    let mut 改后 = 包件.clone();
    改后[码起点] ^= 0xFF;
    assert_eq!(解包(&改后).is_ok(), true, "结构没坏，仍解得开");
    assert_eq!(校验段指纹(&改后), Some(false), "改过码段必须报到");
}

/// **反向样本**：段数不是 3 ⇒ 报错。
#[test]
fn 段数不符即报错() {
    let 包件 = 装包(b"\x01", b"\x02");
    // 只留第一段（截到第一段数据尾）。
    let 首段尾 = 8 + 段头长度 + 1;
    assert_eq!(
        解包(&包件[..首段尾]),
        Err(容器错误::段数不符 { 实际: 1 })
    );
}

/// 段头 44 字节逐字段布局：魔数 · 标记 · 段类型号 · 名称区密钥。
#[test]
fn 段头逐字段布局() {
    let 包件 = 装包(b"\xAA", b"\xBB");
    let 段头字节 = &包件[8..8 + 段头长度];
    assert_eq!(&段头字节[0x00..0x02], &[0x19, 0x73], "段头魔术 0x7319");
    assert_eq!(&段头字节[0x02..0x04], &[0x11, 0x15], "段头标记 0x1511");
    assert_eq!(&段头字节[0x08..0x0C], &[0x19, 0x73, 0x00, 段类型_接口说明], "类型标记 + 类型号");
    assert_eq!(&段头字节[0x27..0x2C], &[0x19, 0x73, 0x00, 0x00, 0x00], "结束标记 + 尾标志 + 补零");
    // 名称区：明文「接口说明」+ NUL + 补零，异或密钥 73 00 10 19。
    let 密钥 = 名称区密钥(段类型_接口说明);
    let 名称 = "接口说明".as_bytes();
    for 位次 in 0..名称.len() {
        assert_eq!(段头字节[0x0C + 位次], 名称[位次] ^ 密钥[位次 % 4], "名称区第 {位次} 字节");
    }
}

/// **SHA-256 已知向量**（FIPS 180-4 附录 B 与 NIST 常用向量）。
///
/// 自写哈希最大的坑是「编解码自洽但整体错」⇒ 必须拿外部公开向量钉。
#[test]
fn 算指纹两条已知向量() {
    assert_eq!(
        转十六进制(&算指纹(b"")),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
        "空串向量"
    );
    assert_eq!(
        转十六进制(&算指纹(b"abc")),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
        "abc 向量"
    );
    assert_eq!(
        转十六进制(&算指纹(
            b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
        )),
        "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1",
        "两块向量"
    );
}

/// 指纹段形状：条数不符 / 尾部多余 ⇒ 拒。
#[test]
fn 指纹段形状不符即拒() {
    let 字节 = 编码指纹段(&[(段类型_接口说明, b"aaa"), (段类型_能力码, b"bbb")]);
    assert_eq!(解指纹段(&字节).map(|项表| 项表.len()), Some(2));
    assert!(解指纹段(&[]).is_none());
    let mut 多余样本 = 字节.clone();
    多余样本.push(0);
    assert!(解指纹段(&多余样本).is_none(), "尾部多余字节必须拒");
}
