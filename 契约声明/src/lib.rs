/// **必须带 `#[path]`**：文件名非 ASCII，rustc 不会自动加载（否则 E0754）。
#[path = "声明数据.rs"]
pub mod 声明数据;

// ── 关注点拆出的子模块（都在 契约声明/ 文件夹里；文件名非 ASCII ⇒ 逐条给 `#[path]`）──
