//! 契约声明 —— 底座与扩展共用的全部契约类型。
//!
//! 本 crate 是整个平台的脊梁：所有跨边界形状都在这里定义一次，别处只许引用，不许复制。
//!
//! 三条硬约束（改这里之前先读）：
//! 1. **只做 64 位**：字宽一律 64 位，不写 32 位分支（`内核落点.md`）。
//! 2. **布局显式**：跨边界结构必须 `#[repr(C)]`，宽度必须写死。
//! 3. **签名冻结**：这里的一切都是冻结项，改动必须走 `契约声明/冻结登记.json`。
//!
//! 命名：内部标识符一律中文；**导出的 ABI 符号一律 ASCII**（外部协议边界）。
//!
//! # 主文件是路由
//!
//! 本文件只做三件事：**声明子模块 · 再导出公开面 · 零实现**（`开发规范.md` §六）。
//! 形状按关注点拆进同名字文件夹 `契约声明/`，一个关注点一个文件。
//! **公开面逐字不变**：`v1_contract::版本三元组` / `v1_contract::数据槽` /
//! `v1_contract::号段` / `v1_contract::命令信息` / `v1_contract::平台信息` 等
//! 全部照旧，调用方一处不用改。

#![allow(uncommon_codepoints)]
#![allow(non_snake_case)]
#![no_std]

extern crate alloc;

// 生成物（`声明数据.rs`）里的路径一律写成 `v1_contract::..` 全限定。本 crate 内部要能
// 解析这个名字，故把 crate 自身引入作用域。**别名必须与本 crate 名一致。**
extern crate self as v1_contract;

/// 生成物：`契约声明/*.json` → Rust 常量，由 `构建装配/形态装配/生成声明.py` 生成。
