/// 命令信息。
///
/// **字段顺序＝冻结区 + 旁路区**：旁路字段一律追加在尾部（旧读者仍能读前缀）。
/// 这是「新增段类型号不动旧段」在结构层的形态（同 `数据类型信息`）。
#[repr(C)]
pub struct 命令信息 {
    // ── 冻结区 ──
    pub 名称: *const u8,
    pub 说明: *const u8,
    pub 类别: u16,
    pub 状态位: u16,
    /// 返回类型标签；0 表示无返回值。
    pub 返回类型: u32,
    pub 用户级别: u16,
    pub 参数个数: u32,
    pub 参数表: *const 参数信息,
    // ── 旁路区（只增不改；一律追加）──
    /// **命令编号（显式）**。取自 `契约声明/能力声明/<编号>.json` 的「编号」。
    ///
    /// 早先 `平台信息` 里没有「编号」字段，注册表只能约定「编号 = 命令表下标（0 起）」。
    /// **实测咬人**（`冻结登记.json` 待办旁路 · 阻断级）：①「号只增不复用」判不了
    /// （重排一次表所有号静默全变）②占 `1xxx` 号段的扩展只要有一条 `错误` 状态位的命令，
    /// 就必然被判 `声明不自洽 { 命令号: 0 }`（段位口径 = 编号 / 号段类宽度，下标 0 的段位恒为 0）
    /// ③每份声明的编号都从 0 起 ⇒ 多声明共存时重号，「号段即归属」在命令编号上根本没落地。
    ///
    /// 显式给编号后：注册表**按编号查**（不按下标），建表要求**表按编号严格递增**（违反即 fail-closed）。
    /// 号**只增不复用、允许有洞**（宪法第 7 条）。
    pub 编号: u32,
    /// **可抛错误码**（表段<u32>）：本命令在执行中可能抛出的错误码，取自
    /// `契约声明/能力声明/<编号>.json` 的「可抛错误码」（`格式说明.md` §三）。
    ///
    /// **没有它，实现侧扫描器判据 ③d2 结构性判不了**（恒报「未判」）：`格式说明.md` §三
    /// 早就要求声明写 `可抛错误码`，而实现侧 `命令信息` 没有承载它的字段 ⇒ 声明里的
    /// `可抛错误码` 在实现面上没有对照物。空表用 `表段::空()`（= 本命令不抛错，不是漏写）。
    pub 可抛错误码: 表段<u32>,
}

