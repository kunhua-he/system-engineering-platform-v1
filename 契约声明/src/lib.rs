///
/// 为什么单列一个型：早先 `号段已占用(起, 止)` 没有这个参数，实现只能把两本账
/// **取并集**判——于是「扩展占能力 1000–6999」会被底座占的「通知 0–999」误判成冲突，
/// 也就是**假冲突**：一个完全合法的扩展载不进来。参数不能靠约定补，要进类型。
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 号段空间 {
    能力号,
    通知号,
}

/// 调用账本 —— 配额与超时的记账处。
///
/// **按实例持有、显式传入**：账本若落进程级，多实例就不隔离（违反三条补缺陷之一）。
///
/// **两个时点必须分开，不许合成一个方法**：执行**前**只可能问「准不准调」，
/// 执行**后**才知道真实耗时。早先写成 `记账(号, 耗时毫秒) -> bool` 是错的——
/// 执行前拿不到耗时（只能拿预算冒充），执行后已经拦不住调用（返回 `false` 也晚了）。
/// 一次调用无法同时满足这两件事，所以是两个方法。
pub trait 调用账本 {
    /// 执行**前**问一次。返回 `false` = 超配额，本次调用**不许进入执行函数**。
    fn 准调(&self, 能力号: u32) -> bool;
    /// 执行**后**记一次。`耗时毫秒` 是本次**真实**耗时；账本可据此限速。
    /// 返回值忽略——执行已经发生，此刻返回什么都拦不住它。
    fn 记账(&self, 能力号: u32, 耗时毫秒: u64);
}

