/// 声明格式号：这是**格式的身份证，不是版本号**。格式不变，它永远不变。
///
/// **只有一个来源**：值由 `声明数据`（即 `契约声明/平台声明.json`）给出。此处不再硬写——
/// 硬写就成了第二个来源，改 JSON 会让底座自身的声明过不了判定 ①（而 ① 比的正是它）。
/// `v1_contract::声明格式号` 这个路径必须继续可用（装载入口 · 统一注册表 · 调用调度都在用）。
pub use 声明数据::底座声明格式号 as 声明格式号;

/// 通知号段 —— 通知号的三个号段（下行 · 上行 · 生命周期）。
///
/// **值只有一个来源**：`声明数据::通知号段`（源：`契约声明/号段图.json.通知号段`，
/// 按 `归属` 前缀取标签）。这里只做 `pub use`，因为 `v1_contract::通知号段` 这个**路径名**
/// 必须继续可用（通知通道在用）。
///
/// 早先这里手写了 `下行起/止 · 上行起/止 · 生命周期起/止` 六个区间常量 —— 那是
/// `号段图.json` 的第二来源，已删。**不留别名**（留别名就是旧腿）。
pub use 声明数据::通知号段;

/// 资源号段 —— 资源号的两个号段（扩展自带资源 · 平台级资源）。
///
/// **值只有一个来源**：`声明数据::资源号段`（源：`契约声明/号段图.json.资源号段`）。
/// 资源网关口据此判「这个资源号该由扩展声明还是平台声明」。
///
/// 加这一段是因为实测：关口拿不到这个区间，只能自身手写一份 `资源号段 = 1..=9999`
/// —— 同一事实两个来源。**不留别名**（留别名就是旧腿）。
pub use 声明数据::资源号段;

/// 命令类别表 —— `命令信息.类别` 那个号的**名字**（号 → 名）。
///
/// **值只有一个来源**：`声明数据`（源 = `<声明根>/命令类别/*.json`，文件名即类别号）。
/// `v1_contract::取命令类别名(类别号) -> *const u8` 是查口（查不到返回空指针）。
///
/// **为什么必须有**：`命令信息` 有 `类别: u16` 而顶层原先**没有**「类别号 → 类别名」的表
/// ⇒ 这个号在运行期**永远解不出名字**。参照实现在 `LIB_INFO +0x5C/+0x60` 有一对
/// （计数 + 串块；字节级实测见 `项目文档/设计文档/接缝实测.md` §二/§三 —— shellEx 的 4 条
/// 类别串与命令 `cat=1..4` 正好一一对应）。这是对照表里唯一一条「我有字段、参照实现有表、
/// 而我没有表」的缺口 —— 本表补上这一对。**补的是我方自有的表，不是复刻它的结构**：
/// 它的表是「连续 NUL 结尾串块 + 双 NUL 结束」，我方是 `#[repr(C)]` 项表 + NUL 结尾串。
///
/// **值域已裁**：`1..23`，照易语言内核库 `krnln.fne` 的 `m_szzCategory` 那张 23 条类别表
/// （`契约声明/格式说明.md` §三·五）—— **不发明、不抄它的 4 位数字前缀**。
/// **表仍可以是空的**（源目录可缺 / 可空）⇒ 空表 = 「本声明没有类别表」，不是漏写。
/// `取命令类别名` 查不到时返回空指针，**不是错误**：类别号是可选说明，不是能力编号
/// （`能力声明.类别 = 0` = **未分类**，合法）。
///
/// **本表也进 `平台信息`**（旁路字段 `平台信息.命令类别表`，2026-09-27，见
/// `契约声明/冻结登记.json` 的 `旁路`）：`lib.rs` 这一处 `pub use` 只对**本 crate**（底座）可用；
/// 扩展的类别号宿主侧要取到，必须随 `平台信息` 交过去 —— 宿主不认识扩展的 `声明数据`。
pub use 声明数据::{取命令类别名, 命令类别表};
